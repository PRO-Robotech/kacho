package filter

import "testing"

// TestParseEmitsExactlyOneOperator — оператор, который Parse способен выпустить,
// сегодня ровно один: "=".
//
// Зачем это закреплено. Пять владельцев в дереве строят предикат литералом
// `<колонка> = $N`, не читая `ast.Op`. Сегодня это НЕ дефект и дефектом быть не
// может: грамматика принимает единственный оператор, поэтому литерал и
// разобранное выражение совпадают by construction. Проверять там нечего — а
// «шесть владельцев отбрасывают оператор» как утверждение о ДЕЙСТВУЮЩЕМ
// поведении неверно ровно по этой причине: отбрасывать нечего.
//
// Опасность появляется в тот день, когда в грамматику добавят второй оператор
// (подстрочный поиск, префикс, вхождение в множество). В этот момент все места,
// где оператор подставлен литералом, начнут молча отвечать РАВЕНСТВОМ на запрос
// другого отношения — то есть уверенно и неверно, а вызывающий примет ответ за
// результат поиска. Диффом такое не видно: правка будет в грамматике, а
// неверными станут места, которых правка не касалась.
//
// Поэтому проверка сформулирована так, чтобы истечь самой: она краснеет в тот
// момент, когда предмет запрета появляется, и её текст падения называет работу,
// которую тогда надо сделать. Держать вместо неё запись в документе значило бы
// держать утверждение, которое переживёт свой предмет и станет ложью незаметно.
func TestParseEmitsExactlyOneOperator(t *testing.T) {
	// Корпус намеренно содержит формы ДРУГИХ отношений. Сегодня каждая обязана
	// быть отвергнута; принятая форма — сигнал, что грамматика выросла.
	corpus := []string{
		`name="v"`,
		`name = "v"`,
		`name:"v"`,
		`name~"v"`,
		`name!="v"`,
		`name>"v"`,
		`name<"v"`,
		`name IN ("a","b")`,
		`name STARTS_WITH "v"`,
		`name CONTAINS "v"`,
		`name LIKE "%v%"`,
	}

	accepted := 0
	for _, expr := range corpus {
		ast, err := Parse(expr, []string{"name"})
		if err != nil || ast == nil {
			continue
		}
		accepted++
		if ast.Op != "=" {
			t.Fatalf(
				"Parse(%q) выпустил оператор %q — грамматика выросла.\n"+
					"Прежде чем это станет рабочим, обойди места, где предикат строится "+
					"литералом `<колонка> = $N` без чтения ast.Op, и научи их применять "+
					"разобранный оператор. На день заведения этой проверки таких мест "+
					"было пять: registry (Registry.List), storage (Volume/Snapshot/Image.List) "+
					"и nlb (shared.ParseNameFilter). Пока они читают только ast.Value, "+
					"новый оператор молча ответит равенством.",
				expr, ast.Op)
		}
	}

	// Перепись: «все отвергнуты» и «ни одно не разобрано» — разные исходы.
	// Без этого проверка осталась бы зелёной, даже если бы Parse перестал
	// принимать вообще всё.
	t.Logf("осмотрено выражений: %d, принято грамматикой: %d", len(corpus), accepted)
	if accepted == 0 {
		t.Fatal("грамматика не приняла ни одного выражения корпуса — " +
			"проверка ничего не утверждает, вердикт недействителен")
	}
}
