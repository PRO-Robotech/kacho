// Package tokenpolicy — ОДНО объявленное место для политики токенов платформы:
// закрытый словарь алгоритмов подписи, перечень обязательных проверок и числа,
// из которых вычисляется отсрочка снятия подписного ключа.
//
// # Почему перечень проверок объявляется, а не описывается словами
//
// Приём нашего токена исполняют РАЗНЫЕ реализации на разных поверхностях. Пока
// состав обязательных проверок живёт у каждой свой, различие между ними не
// является ничьей находкой: оно НЕ ВЫРАЖЕНО, и потому не может покраснеть.
// Перечень здесь — предмет, на который может смотреть гейт по дереву.
//
// Реализация проверок остаётся у поверхности: они разные по существу (одна
// разбирает токен библиотекой, другая — своим кодом над crypto/*). Общей
// делается ПОЛИТИКА, а не функция.
//
// # Почему числа здесь, а не у того, кто их применяет
//
// Отсрочка снятия ключа ВЫЧИСЛЯЕТСЯ из двух слагаемых: максимального срока
// выпускаемого токена и потолка кэша ключей у самого «медленного» потребителя.
// Пока слагаемые объявлены по своим сервисам, арифметика невыразима — её
// нечем проверить, и она угадывается. Здесь она проверяется гейтом, и смена
// любого слагаемого без пересмотра отсрочки роняет проверку, называя оба числа.
package tokenpolicy

import "time"

// ── Закрытый словарь алгоритмов ─────────────────────────────────────────────

// Алгоритмы подписи, которые платформа выпускает и принимает.
const (
	AlgRS256 = "RS256"
	AlgES256 = "ES256"
	AlgEdDSA = "EdDSA"
)

// Algorithms возвращает закрытый словарь целиком.
//
// Всякий, кому нужен перечень, ВЫВОДИТ его отсюда: страж старта, текст отказа,
// сверка алгоритма с ключом. Вторая копия словаря разошлась бы молча — и
// разошлась бы в сторону «принимаем больше», потому что расширять проще.
func Algorithms() []string { return []string{AlgRS256, AlgES256, AlgEdDSA} }

// AlgorithmAllowed отвечает, входит ли алгоритм в словарь.
//
// Пустое значение НЕ входит: «алгоритм не назван» означало бы «любой», а
// именно этого класса мы и избегаем.
func AlgorithmAllowed(alg string) bool {
	for _, a := range Algorithms() {
		if a == alg {
			return true
		}
	}
	return false
}

// ── Перечень обязательных проверок ──────────────────────────────────────────

// Check — обязательная проверка предъявленного токена.
type Check string

// Обязательные проверки. Перечень ЗАКРЫТ: поверхность, объявляющая свою
// проверку сверх него, обязана объявить и ПРИЧИНУ — молчаливое расхождение
// является находкой.
const (
	// CheckSignature — подпись сходится с ключом, найденным по kid.
	CheckSignature Check = "signature"
	// CheckAlgorithmAllowed — алгоритм заголовка входит в закрытый словарь;
	// «без подписи» отвергается ДО разрешения ключа.
	CheckAlgorithmAllowed Check = "algorithm-allowed"
	// CheckKeyBoundAlgorithm — алгоритм заголовка равен алгоритму,
	// ЗАКРЕПЛЁННОМУ за найденным ключом. Заголовок алгоритм не выбирает.
	CheckKeyBoundAlgorithm Check = "key-bound-algorithm"
	// CheckIssuer — издатель токена имеет объявленную запись источника
	// ключей; издателя без записи не бывает.
	CheckIssuer Check = "issuer"
	// CheckAudience — адресат токена равен адресату поверхности. Незаданный
	// адресат означает «любой», поэтому он обязателен в настройке.
	CheckAudience Check = "audience"
	// CheckTokenType — тип объявлен и равен ожидаемому.
	CheckTokenType Check = "token-type"
	// CheckExpiry — срок ПРИСУТСТВУЕТ и не истёк. Обязательность включается
	// ЯВНЫМ параметром: разбор, не встретив срока, не возразит сам.
	CheckExpiry Check = "expiry"
	// CheckNotBefore — токен не выпущен «из будущего» за пределом допуска.
	CheckNotBefore Check = "not-before"
	// CheckKeyID — идентификатор ключа присутствует, его форма ограничена ДО
	// использования, и он резолвится в ключ объявленной записи.
	CheckKeyID Check = "key-id"
	// CheckCriticalHeaders — параметр, помеченный отправителем обязательным к
	// пониманию (`crit`, RFC 7515 §4.1.11), либо исполняется, либо токен
	// отвергается целиком. Обратная сторона того же требования — НЕ помеченное
	// неизвестное игнорируется (RFC 7519, EID 8060): ужесточение первого без
	// второго ломает совместимость.
	CheckCriticalHeaders Check = "critical-headers"
	// CheckRevocation — отзыв читается НА ПРЕДЪЯВЛЕНИИ. Контроль, действующий
	// только на выдаче, отзывом не является: он лишь не выдаёт нового.
	CheckRevocation Check = "revocation"
)

// MandatoryChecks возвращает перечень обязательных проверок.
//
// Это и есть тот «один объявленный перечень», которым пользуются все
// реализации приёма. Реализация объявляет, какие проверки она исполняет, и
// гейт сверяет её объявление с этим перечнем.
func MandatoryChecks() []Check {
	return []Check{
		CheckAlgorithmAllowed,
		CheckKeyID,
		CheckSignature,
		CheckKeyBoundAlgorithm,
		CheckIssuer,
		CheckAudience,
		CheckTokenType,
		CheckExpiry,
		CheckNotBefore,
		CheckCriticalHeaders,
		CheckRevocation,
	}
}

// MissingChecks возвращает обязательные проверки, которых нет в объявлении
// реализации. Пустой ответ означает согласие с перечнем.
func MissingChecks(declared []Check) []Check {
	have := make(map[Check]bool, len(declared))
	for _, c := range declared {
		have[c] = true
	}
	var missing []Check
	for _, c := range MandatoryChecks() {
		if !have[c] {
			missing = append(missing, c)
		}
	}
	return missing
}

// ── Числа, из которых вычисляется отсрочка ──────────────────────────────────

const (
	// MaxTokenTTL — потолок срока выпускаемого токена. Первое слагаемое
	// арифметики отсрочки: ключ нельзя снять раньше, чем истечёт последний
	// подписанный им токен.
	MaxTokenTTL = 30 * time.Minute

	// ConsumerKeySetCacheCeiling — потолок срока, на который ПОТРЕБИТЕЛЬ
	// вправе удерживать снимок набора ключей. Второе слагаемое: снятый ключ
	// ещё какое-то время отвечает «да» из чужого кэша, и всё выглядит
	// исправным. Потолок обязан быть объявлен числом на КАЖДОЙ поверхности —
	// без него слагаемое неизвестно, и отсрочка не вычисляется, а угадывается.
	ConsumerKeySetCacheCeiling = time.Hour

	// RemovalSlack — запас. Он невелик намеренно: запас, покрывающий
	// произвольную величину, скрыл бы ошибку в слагаемых.
	RemovalSlack = 15 * time.Minute

	// KeyRemovalGrace — отсрочка снятия ключа из набора после вывода его из
	// подписи. ВЫЧИСЛЯЕТСЯ, а не выбирается: смена любого слагаемого без
	// пересмотра этого числа роняет гейт и называет оба.
	KeyRemovalGrace = MaxTokenTTL + ConsumerKeySetCacheCeiling + RemovalSlack

	// ClockSkew — допуск на расхождение часов при приёме токена. Объявлен
	// числом, потому что проба допуска обязана утверждать обе стороны: за
	// пределом — отказ, внутри — проход.
	ClockSkew = 60 * time.Second

	// UnknownKeyIDRefetchInterval — собственный минимальный интервал
	// вынужденного перезапроса набора. Без него неизвестный идентификатор
	// ключа становится усилителем нагрузки: поток запросов с выдуманными
	// идентификаторами превращается в поток обращений к публикатору.
	UnknownKeyIDRefetchInterval = 30 * time.Second

	// KeySetBodyCeiling — потолок тела ответа источника набора. Чтение
	// прекращается на нём, а не «после разбора».
	KeySetBodyCeiling = 1 << 20

	// KeyIDMaxLen — потолок длины идентификатора ключа.
	//
	// Идентификатор приходит ОТ ПРЕДЪЯВИТЕЛЯ и потому ограничивается по форме
	// ДО того, как попадёт в поиск по снимку, в журнал и в повод вынужденного
	// перезапроса. Число объявлено здесь, а не у каждого, кто его применяет: у
	// формы идентификатора три места исполнения — чеканка и две конфигурации
	// приёма, — и разойтись им можно только молча.
	KeyIDMaxLen = 128
)

// GraceCoversLiveTokens отвечает, покрывает ли объявленная отсрочка оба
// слагаемых. Предикат, а не комментарий: его зовёт гейт.
func GraceCoversLiveTokens() bool {
	return KeyRemovalGrace >= MaxTokenTTL+ConsumerKeySetCacheCeiling
}

// ── Минимальный размер ключа ────────────────────────────────────────────────

// MinRSAModulusBits — минимальный допустимый размер модуля RSA.
//
// Короткий модуль факторизуется, а значит подпись подделывается: ключ меньшего
// размера не должен попадать в снимок вовсе. Величина объявлена ЗДЕСЬ, потому
// что её обязаны знать все, кто принимает ключи, а второй словарь разошёлся бы
// молча — и разошёлся бы в сторону «принимаем меньше», потому что смягчать
// проще, чем ужесточать.
const MinRSAModulusBits = 2048

// ── Неизвестные параметры заголовка: ДВА требования с ОБРАТНОЙ полярностью ──
//
// RFC 7515 §4.1.11 (`crit`) и RFC 7519 (исправление EID 8060) требуют
// ПРОТИВОПОЛОЖНОГО от двух видов неизвестного:
//
//	помеченный обязательным (`crit`) → отказ: отправитель заявил, что без
//	    понимания этого параметра токен принимать нельзя;
//	НЕ помеченный                    → принимается: игнорирование неизвестного
//	    и есть то, на чём держится совместимость.
//
// Ужесточение первого без второго ломает совместимость, послабление второго без
// первого открывает приём токена, чьё условие мы не исполнили. Поэтому оба
// требования живут в ОДНОЙ функции: разнесённые по разным местам, они разойдутся
// на первой же правке, и разойдутся молча.

// KnownCriticalHeaders — параметры заголовка, которые мы УМЕЕМ исполнять и
// потому вправе принять помеченными обязательными.
//
// Перечень ПУСТ, и это факт, а не заготовка: ни одна поверхность приёма не
// исполняет ни одного расширения заголовка. Пустой перечень означает «любой
// помеченный обязательным параметр отвергается» — то, что и требуется, пока
// расширений нет.
func KnownCriticalHeaders() []string { return nil }

// CriticalHeadersUnderstood отвечает, можем ли мы принять токен с этим `crit`.
//
// Второй ответ — имя первого непонятого параметра — нужен тексту отказа: без
// него оператор видит «токен отвергнут» и не знает, чем именно он негоден.
//
// Пустой и отсутствующий `crit` — законный вход: требование касается только
// того, что отправитель ЯВНО пометил обязательным.
func CriticalHeadersUnderstood(crit []string) (bool, string) {
	known := make(map[string]bool, len(KnownCriticalHeaders()))
	for _, h := range KnownCriticalHeaders() {
		known[h] = true
	}
	for _, h := range crit {
		if !known[h] {
			return false, h
		}
	}
	return true, ""
}

// ── Объявленное отступление ─────────────────────────────────────────────────

// Deviation — обязательная проверка, которую поверхность НЕ исполняет, вместе с
// причиной.
//
// Причина обязательна и не бывает «пока»: отступление без причины неотличимо от
// пропуска, а «сделаем потом» — тот самый отложенный долг, за который никто не
// отвечает. Причина обязана называть, ЧТО делает эту проверку неприменимой
// здесь, а не то, когда её собираются добавить.
type Deviation struct {
	Check  Check
	Reason string
}

// MissingChecksExcept возвращает обязательные проверки, которых нет ни в
// объявлении реализации, ни в перечне её объявленных отступлений.
//
// Пустой ответ означает: всякая обязательная проверка либо исполняется, либо
// её неисполнение НАЗВАНО с причиной. Отступление с пустой причиной не
// засчитывается — иначе поле стало бы способом снять требование молча.
func MissingChecksExcept(declared []Check, deviations []Deviation) []Check {
	excused := make(map[Check]bool, len(deviations))
	for _, d := range deviations {
		if d.Reason != "" {
			excused[d.Check] = true
		}
	}
	var missing []Check
	for _, c := range MissingChecks(declared) {
		if !excused[c] {
			missing = append(missing, c)
		}
	}
	return missing
}

// ── Два вида подписанного: объявленные типы ─────────────────────────────────
//
// С задачи #898 один издатель начинает работать с ДВУМЯ видами подписанного:
// он выпускает токен доступа для наших поверхностей и принимает утверждение
// клиента, доказывающее владение зарегистрированным ключом. До этого предмета
// не существовало вовсе.
//
// # Почему типы объявлены здесь, а не у каждого потребителя
//
// Пока значения живут по своим пакетам, их РАЗЛИЧИЕ не является ничьей
// находкой: оно не выражено и потому не может покраснеть. Совпади они по
// недосмотру — и одно из двух направлений разделения перестало бы работать
// молча, а положительный путь при этом остался бы зелёным.

const (
	// TokenTypeAccess — объявленный тип токена доступа, выпускаемого
	// платформой (RFC 9068).
	TokenTypeAccess = "at+jwt"

	// TokenTypeClientAssertion — объявленный тип утверждения, которым клиент
	// себя аутентифицирует.
	//
	// Значение ИНОЕ, чем у токена доступа, и это первый из трёх независимых
	// признаков, разделяющих два вида (приёмка F2 §2.6). Единственным его
	// назначать нельзя: клиент, тип не проставивший, снял бы его целиком —
	// поэтому рядом стоят ещё два (адресат и чей ключ подписал), и требование
	// выполняется КАЖДЫМ по отдельности.
	TokenTypeClientAssertion = "client-authentication+jwt"

	// ClientAssertionType — объявленный стандартом вид предъявления
	// (RFC 7523 §2.2). Сравнивается ТОЧНО, без нормализации: отличие регистром
	// либо хвостовым пробелом — тоже отказ.
	ClientAssertionType = "urn:ietf:params:oauth:client-assertion-type:jwt-bearer"

	// GrantTypeClientCredentials — вид выдачи, который принимает наш
	// токен-эндпоинт. Перечень видов ЗАКРЫТ: «прочее» не является корзиной
	// приёма.
	GrantTypeClientCredentials = "client_credentials"
)

// SignedMaterialTypes возвращает объявленные типы обоих видов подписанного.
//
// Перечень читается гейтом, требующим попарной различности: два вида, у которых
// совпал объявленный тип, — это один вид, и разделение между ними держалось бы
// оставшимися двумя признаками, ни один из которых не назначен единственным.
func SignedMaterialTypes() []string {
	return []string{TokenTypeAccess, TokenTypeClientAssertion}
}

// ── Потолок длительности утверждения ────────────────────────────────────────

// MaxAssertionLifetime — потолок разницы «срок − момент выпуска» у утверждения
// клиента.
//
// Объявлен числом РОВНО ОДИН РАЗ и участвует в двух расчётах сразу: он
// ограничивает длительность самого утверждения и он же задаёт верхнюю границу
// жизни строки погашения. Два объявления об одном предмете разошлись бы молча —
// и разошлись бы там, где расхождение не видно, потому что обе величины по
// отдельности выглядят разумными.
//
// # Почему потолок вообще нужен
//
// Запись погашения обязана жить до истечения утверждения: снять её раньше
// значит сделать повтор законным. Значит длительность утверждения И ЕСТЬ срок
// жизни строки, а выбирает эту длительность ПРЕДЪЯВИТЕЛЬ. Без потолка
// утверждение со сроком в годы занимает свой ключ на годы, то есть хранилище,
// ограниченное сроком, перестаёт быть ограниченным, а отказ в обслуживании
// становится дешёвым.
//
// # Почему отсчёт от момента выпуска, а не от «сейчас»
//
// «Сейчас» — у нас, момент выпуска — у клиента. Отсчёт от «сейчас» дал бы разный
// потолок при одном и том же утверждении в зависимости от задержки доставки, то
// есть величину, которую нельзя ни объяснить клиенту, ни воспроизвести в пробе.
// Разница `exp − iat` — свойство самого утверждения.
const MaxAssertionLifetime = 5 * time.Minute

// ── Встроенный в заголовок ключевой материал ────────────────────────────────

// KeySourceHeaderMembers — члены заголовка, из которых ключ проверки выбираться
// НЕ МОЖЕТ.
//
// Перечень объявлен в ОДНОМ месте, а не выписан по месту употребления: место,
// закрывшее один член и забывшее второй, выглядит закрытым, и разница видна
// только тому, кто держит перечень в голове.
//
// # Почему это запрет, а не осторожность
//
// Доверять ключу, приехавшему ВМЕСТЕ С ПОДПИСЬЮ, значит принимать любую подпись:
// предъявитель приложит тот ключ, которым подписал. Ключ выбирается ТОЛЬКО из
// нашего реестра.
//
// # Где то же доверие ЗАКОННО — названо, чтобы запрет не расползся
//
// В доказательстве владения ключом (RFC 9449) ключ приходит В САМОМ
// доказательстве, и проверяющий связывает его с токеном по отпечатку: там
// встроенный ключ не уязвимость, а ПРЕДМЕТ. Такое место обязано включать выбор
// из предъявленного материала ЯВНО и по своему решению — умолчание «как
// получится» перенесло бы доверие туда, где оно недопустимо, и перенесло бы
// ТИХО: положительный путь при этом работает.
func KeySourceHeaderMembers() []string {
	return []string{
		"jwk", // сам ключ
		"jku", // ссылка на набор ключей
		"x5u", // ссылка на цепочку сертификатов
		"x5c", // сама цепочка
		"x5t", // отпечаток цепочки
		"x5t#S256",
	}
}

// KeySourceHeaderMember отвечает, является ли член заголовка источником ключа.
func KeySourceHeaderMember(name string) bool {
	for _, m := range KeySourceHeaderMembers() {
		if m == name {
			return true
		}
	}
	return false
}
