// Package tokenpolicy — ОДНО объявленное место для политики токенов платформы:
// закрытый словарь алгоритмов подписи, перечень обязательных проверок и числа,
// из которых вычисляется отсрочка снятия подписного ключа.
//
// # Почему перечень проверок объявляется, а не описывается словами
//
// Приём нашего токена исполняют РАЗНЫЕ реализации на разных поверхностях. Пока
// состав обязательных проверок живёт у каждой свой, различие между ними не
// является ничьей находкой: оно НЕ ВЫРАЖЕНО, и потому не может покраснеть.
// Перечень здесь — предмет, на который может смотреть гейт по дереву.
//
// Реализация проверок остаётся у поверхности: они разные по существу (одна
// разбирает токен библиотекой, другая — своим кодом над crypto/*). Общей
// делается ПОЛИТИКА, а не функция.
//
// # Почему числа здесь, а не у того, кто их применяет
//
// Отсрочка снятия ключа ВЫЧИСЛЯЕТСЯ из двух слагаемых: максимального срока
// выпускаемого токена и потолка кэша ключей у самого «медленного» потребителя.
// Пока слагаемые объявлены по своим сервисам, арифметика невыразима — её
// нечем проверить, и она угадывается. Здесь она проверяется гейтом, и смена
// любого слагаемого без пересмотра отсрочки роняет проверку, называя оба числа.
package tokenpolicy

import "time"

// ── Закрытый словарь алгоритмов ─────────────────────────────────────────────

// Алгоритмы подписи, которые платформа выпускает и принимает.
const (
	AlgRS256 = "RS256"
	AlgES256 = "ES256"
	AlgEdDSA = "EdDSA"
)

// Algorithms возвращает закрытый словарь целиком.
//
// Всякий, кому нужен перечень, ВЫВОДИТ его отсюда: страж старта, текст отказа,
// сверка алгоритма с ключом. Вторая копия словаря разошлась бы молча — и
// разошлась бы в сторону «принимаем больше», потому что расширять проще.
func Algorithms() []string { return []string{AlgRS256, AlgES256, AlgEdDSA} }

// AlgorithmAllowed отвечает, входит ли алгоритм в словарь.
//
// Пустое значение НЕ входит: «алгоритм не назван» означало бы «любой», а
// именно этого класса мы и избегаем.
func AlgorithmAllowed(alg string) bool {
	for _, a := range Algorithms() {
		if a == alg {
			return true
		}
	}
	return false
}

// ── Перечень обязательных проверок ──────────────────────────────────────────

// Check — обязательная проверка предъявленного токена.
type Check string

// Обязательные проверки. Перечень ЗАКРЫТ: поверхность, объявляющая свою
// проверку сверх него, обязана объявить и ПРИЧИНУ — молчаливое расхождение
// является находкой.
const (
	// CheckSignature — подпись сходится с ключом, найденным по kid.
	CheckSignature Check = "signature"
	// CheckAlgorithmAllowed — алгоритм заголовка входит в закрытый словарь;
	// «без подписи» отвергается ДО разрешения ключа.
	CheckAlgorithmAllowed Check = "algorithm-allowed"
	// CheckKeyBoundAlgorithm — алгоритм заголовка равен алгоритму,
	// ЗАКРЕПЛЁННОМУ за найденным ключом. Заголовок алгоритм не выбирает.
	CheckKeyBoundAlgorithm Check = "key-bound-algorithm"
	// CheckIssuer — издатель токена имеет объявленную запись источника
	// ключей; издателя без записи не бывает.
	CheckIssuer Check = "issuer"
	// CheckAudience — адресат токена равен адресату поверхности. Незаданный
	// адресат означает «любой», поэтому он обязателен в настройке.
	CheckAudience Check = "audience"
	// CheckTokenType — тип объявлен и равен ожидаемому.
	CheckTokenType Check = "token-type"
	// CheckExpiry — срок ПРИСУТСТВУЕТ и не истёк. Обязательность включается
	// ЯВНЫМ параметром: разбор, не встретив срока, не возразит сам.
	CheckExpiry Check = "expiry"
	// CheckNotBefore — токен не выпущен «из будущего» за пределом допуска.
	CheckNotBefore Check = "not-before"
	// CheckKeyID — идентификатор ключа присутствует, его форма ограничена ДО
	// использования, и он резолвится в ключ объявленной записи.
	CheckKeyID Check = "key-id"
	// CheckRevocation — отзыв читается НА ПРЕДЪЯВЛЕНИИ. Контроль, действующий
	// только на выдаче, отзывом не является: он лишь не выдаёт нового.
	CheckRevocation Check = "revocation"
)

// MandatoryChecks возвращает перечень обязательных проверок.
//
// Это и есть тот «один объявленный перечень», которым пользуются все
// реализации приёма. Реализация объявляет, какие проверки она исполняет, и
// гейт сверяет её объявление с этим перечнем.
func MandatoryChecks() []Check {
	return []Check{
		CheckAlgorithmAllowed,
		CheckKeyID,
		CheckSignature,
		CheckKeyBoundAlgorithm,
		CheckIssuer,
		CheckAudience,
		CheckTokenType,
		CheckExpiry,
		CheckNotBefore,
		CheckRevocation,
	}
}

// MissingChecks возвращает обязательные проверки, которых нет в объявлении
// реализации. Пустой ответ означает согласие с перечнем.
func MissingChecks(declared []Check) []Check {
	have := make(map[Check]bool, len(declared))
	for _, c := range declared {
		have[c] = true
	}
	var missing []Check
	for _, c := range MandatoryChecks() {
		if !have[c] {
			missing = append(missing, c)
		}
	}
	return missing
}

// ── Числа, из которых вычисляется отсрочка ──────────────────────────────────

const (
	// MaxTokenTTL — потолок срока выпускаемого токена. Первое слагаемое
	// арифметики отсрочки: ключ нельзя снять раньше, чем истечёт последний
	// подписанный им токен.
	MaxTokenTTL = 30 * time.Minute

	// ConsumerKeySetCacheCeiling — потолок срока, на который ПОТРЕБИТЕЛЬ
	// вправе удерживать снимок набора ключей. Второе слагаемое: снятый ключ
	// ещё какое-то время отвечает «да» из чужого кэша, и всё выглядит
	// исправным. Потолок обязан быть объявлен числом на КАЖДОЙ поверхности —
	// без него слагаемое неизвестно, и отсрочка не вычисляется, а угадывается.
	ConsumerKeySetCacheCeiling = time.Hour

	// RemovalSlack — запас. Он невелик намеренно: запас, покрывающий
	// произвольную величину, скрыл бы ошибку в слагаемых.
	RemovalSlack = 15 * time.Minute

	// KeyRemovalGrace — отсрочка снятия ключа из набора после вывода его из
	// подписи. ВЫЧИСЛЯЕТСЯ, а не выбирается: смена любого слагаемого без
	// пересмотра этого числа роняет гейт и называет оба.
	KeyRemovalGrace = MaxTokenTTL + ConsumerKeySetCacheCeiling + RemovalSlack

	// ClockSkew — допуск на расхождение часов при приёме токена. Объявлен
	// числом, потому что проба допуска обязана утверждать обе стороны: за
	// пределом — отказ, внутри — проход.
	ClockSkew = 60 * time.Second

	// UnknownKeyIDRefetchInterval — собственный минимальный интервал
	// вынужденного перезапроса набора. Без него неизвестный идентификатор
	// ключа становится усилителем нагрузки: поток запросов с выдуманными
	// идентификаторами превращается в поток обращений к публикатору.
	UnknownKeyIDRefetchInterval = 30 * time.Second

	// KeySetBodyCeiling — потолок тела ответа источника набора. Чтение
	// прекращается на нём, а не «после разбора».
	KeySetBodyCeiling = 1 << 20
)

// GraceCoversLiveTokens отвечает, покрывает ли объявленная отсрочка оба
// слагаемых. Предикат, а не комментарий: его зовёт гейт.
func GraceCoversLiveTokens() bool {
	return KeyRemovalGrace >= MaxTokenTTL+ConsumerKeySetCacheCeiling
}
