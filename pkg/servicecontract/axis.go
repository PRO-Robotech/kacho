package servicecontract

// Axis — ось, у которой ПУСТОЕ ЗНАЧЕНИЕ ЗАКОННО.
//
// # Зачем отдельный тип, а не просто поле
//
// «Пусто» и «не применимо» неразличимы без явного «почему». Сервис, у которого
// ось пуста по построению (глобальный справочник не раздаёт пообъектных
// грантов), и сервис, у которого её просто забыли заполнить, выглядят
// одинаково — а решения по ним противоположны. Пока различия не было,
// необъяснённая пустая клетка читалась как «здесь ничего не нужно», и проверить
// это было нечем.
//
// Поэтому у оси ТРИ состояния, а не два:
//
//   - значение —            [Value];
//   - «не применимо, потому что …» — [NotApplicable] с НЕПУСТОЙ причиной;
//   - ничего не сказано —   нулевое значение, которое [New] отвергает (О10).
//
// Пустая причина объявлением НЕ является намеренно: иначе закрыть ось стало бы
// дешевле, чем заполнить, и `NotApplicable("")` превратился бы в то самое
// умолчание, ради устранения которого тип и заводится.
//
// # Почему тип заводится ТОЛЬКО для таких осей
//
// Обёртка на каждом поле дескриптора была бы церемонией: у большинства полей
// пустое значение незаконно, и там достаточно обязательного поля с отвергающим
// конструктором. Осей, у которых пустота законна, четыре — эмиссия,
// регистрируемые типы, сужатели, формы скрытия, — плюс происхождение доставки,
// законно пустое у того, кто ничего не доставляет.
//
// # Заявление «не применимо» СУДИТСЯ, а не принимается на слово
//
// Само по себе объяснение — слово автора. Оно становится проверяемым там, где у
// него есть внешний судья: `NotApplicable` на оси сужателей при наличии строки
// `scope_filtered` того же домена есть НАХОДКА ([servicehost] О3), и ровно так
// же судится ось скрытия существования (О5). Поэтому исключение истекает само:
// как только у домена появляется первая такая строка каталога, заявление
// перестаёт быть верным и роняет старт.
type Axis[T any] struct {
	// Поля неэкспортируемые: ось, собранная литералом, обошла бы конструктор и
	// вернула бы ровно ту неразличимость, ради которой тип написан.
	value    T
	hasValue bool
	because  string
}

// Value объявляет ось значением. Пустое ЗНАЧЕНИЕ (пустой срез, пустая карта) —
// законное объявление и отличается от необъявленности: сервис вправе сказать
// «набор пуст» явно.
func Value[T any](v T) Axis[T] { return Axis[T]{value: v, hasValue: true} }

// NotApplicable объявляет ось неприменимой С ПРИЧИНОЙ. Пустая причина
// объявлением не является — [Axis.Declared] на ней ложен, и [New] отказывает.
func NotApplicable[T any](because string) Axis[T] { return Axis[T]{because: because} }

// Get отдаёт значение оси; ok ложен, если ось объявлена неприменимой или не
// объявлена вовсе.
func (a Axis[T]) Get() (T, bool) {
	if !a.hasValue {
		var zero T
		return zero, false
	}
	return a.value, true
}

// NotApplicableBecause отдаёт причину неприменимости; ok ложен, если ось несёт
// значение или не объявлена.
func (a Axis[T]) NotApplicableBecause() (string, bool) {
	if a.hasValue || a.because == "" {
		return "", false
	}
	return a.because, true
}

// Declared сообщает, сказал ли автор про эту ось ХОТЬ ЧТО-ТО. Это и есть
// предикат О10: незаявленная ось не доживает до обслуживания запроса.
func (a Axis[T]) Declared() bool { return a.hasValue || a.because != "" }
