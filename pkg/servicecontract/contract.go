// Package servicecontract — то, что сервис объявляет О СЕБЕ, чтобы носитель
// входящего пути (`pkg/servicehost`) поднял его контур работы с владельцем прав.
//
// # Почему это ДАННЫЕ, а не сборка
//
// Семь сервисов собирали цепочку звеньев каждый у себя, и порядок держался тем,
// что авторы написали одинаковое. Здесь сервис приносит ЗНАЧЕНИЯ — кто он, в
// каком режиме, каким транспортом говорит с владельцем прав, что эмитит, что
// сужает, что скрывает, — и ни одного поля интерсепторного типа. Невыразимость
// чужой цепочки и есть механизм: восьмой сервис, желающий свой порядок звеньев,
// не «нарушит правило» — ему не на чем его записать.
//
// # Что этот пакет НЕ решает
//
// Он решает, ЧТО МОЖНО ЗАПИСАТЬ. Согласованность записанного с тем, что процесс
// РЕАЛЬНО служит, решает [github.com/PRO-Robotech/kacho/pkg/servicehost] — там
// живут отказы, которым нужен служимый набор RPC и выведенный из него каталог
// прав. Применение записанного не закрывается ни тем, ни другим: его держат
// гейты по дереву. Смешивать эти три уровня нельзя — выдавать гейт за свойство
// построения значит объявить закрытым то, что открыто.
//
// # Поля `Domain` здесь НЕТ намеренно
//
// Домен ВЫВОДИТСЯ из имён зарегистрированных gRPC-сервисов (носитель снимает их
// у самого сервера). Объявление ввело бы второй источник, опечатка в котором
// молча выбирает ноль строк каталога — отказ старта такое поймает, но
// диагностика хуже, а второго источника не должно быть в принципе.
