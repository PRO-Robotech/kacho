// Package subscription — ОБЩИЙ сервер потока изменений ресурсов. Один на
// платформу, по экземпляру на владельца журнала.
//
// # Зачем пакет существует
//
// Сервер потока был написан ДВАЖДЫ и предметно, в двух разных сервисах: у одного
// 380 строк с выделенным соединением, курсором и пределом потоков, у другого свой
// обработчик того же предмета. Потребителя не оказалось ни у одного, а провязать
// подписку в остальных модулях копированием значило бы завести седьмую копию
// одного механизма.
//
// Решение владельца: формат подписки один на всех как стандарт, определённый в
// фундаменте как переиспользуемый механизм; остальное снимается и переводится на
// него. Этот пакет — тот механизм.
//
// # Что приносит владелец, подключаясь
//
// [Journal] — и ничего больше: где журнал лежит, каким каналом он будит, и как
// его строка становится событием общей формы. Всё прочее — курсор, горизонт
// устоявшегося, пределы, сужение по правам, порядок отказов — принадлежит
// серверу и владельцу не выдаётся. Это и есть предикат качества обобщения:
// появись у владельца возможность принести своё вместо любого из них, механизм
// перестал бы быть общим, оставшись общим по имени.
//
// # КОНТРАКТ МЕХАНИЗМА
//
// Он записан здесь дословно, потому что подписчик ведёт по нему СВОЁ состояние, и
// каждое из четырёх утверждений ниже — обязательство, а не подробность.
//
// ## Доставка: КАЖДОЕ устоявшееся событие ровно один раз на поток
//
// Событие, попавшее в журнал и ставшее устоявшимся, будет отдано подписчику,
// чьим осям оно отвечает и на чей взгляд у вызывающего есть право. В пределах
// ОДНОГО потока повтора не бывает: курсор двигается только вперёд.
//
// Между потоками — «хотя бы раз»: клиент, возобновившийся с позиции `P`,
// получает всё, что после `P`, и не получает того, что `P` покрывает. Если он
// сохранил позицию, но не успел обработать событие, повтор произойдёт — и это
// нормальный исход, к которому подписчик обязан быть готов.
//
// **Событие, НЕ попавшее в журнал, не существует для подписки.** Журнальная
// строка пишется в той же транзакции, что и ресурсная, поэтому при отказе
// мутации события нет ВОВСЕ: наблюдатель ресурсов не отличит «ещё делается» от
// «упало». Полл операции подписка не заменяет.
//
// ## Порядок: НЕУБЫВАЮЩИЙ по позиции, в пределах одного журнала
//
// События одного журнала приходят в порядке неубывания позиции; событие,
// пришедшее позже, никогда не относится к состоянию, предшествующему уже
// полученному. Это верно и для одного предмета, и для журнала целиком.
//
// **Порядок между журналами разных владельцев НЕ определён** и определён быть не
// может: у них независимые счётчики и независимые транзакции.
//
// Порядок держится не сортировкой, а ГРАНИЦЕЙ УСТОЯВШЕГОСЯ (см. `watermark.go`):
// номер выдаётся на вставке, а видимость наступает на фиксации, поэтому строка
// отдаётся только когда все меньшие номера уже определены — видимы либо потеряны
// откатом. Без этого писатель, закоммитивший позже с меньшим номером, терялся бы
// навсегда: молча, без отказа и без пропуска в нумерации, видимого клиенту.
//
// ## Разрыв: поток обрывается, ПОЗИЦИЯ переживает
//
// Позиция принадлежит КЛИЕНТУ; сервер её не помнит и остаётся stateless. Поэтому
// возобновление работает и после перезапуска сервера, и к ДРУГОЙ реплике.
//
// Обрыв — штатное событие, а не отказ. Сервер закрывает поток чисто по
// истечении срока жизни ([Config.StreamBudget]), и клиент возобновляется со своей
// позиции. Отдельно и явно назван исход, при котором возобновиться нельзя:
// владелец, переставший удерживать часть журнала, отвечает `OUT_OF_RANGE` и
// называет позицию, с которой подписка ещё возможна, — а НЕ начинает молча с
// ближайшего удержанного места. Молчаливое начало клиент записал бы как
// «изменений не было».
//
// Недоступность источника — тоже НЕ «событий нет»: она отвечает `UNAVAILABLE`.
// Пустой поток есть утверждение о мире, и делать его при неотвеченном чтении
// сервер не вправе.
//
// ## Медленный потребитель: держит СВОЙ поток, не чужие
//
// Отправка идёт синхронно в поток вызывающего: не читающий клиент упирается в
// окно транспорта, и курсор ЕГО потока перестаёт двигаться. Он не задерживает ни
// других подписчиков (у каждого свой курсор и своё соединение), ни писателей
// журнала (сервер только читает).
//
// Плата названа: медленный потребитель занимает слот и выделенное соединение всё
// время своей жизни. Поэтому число одновременных потоков ограничено
// ([Config.MaxStreams]), и превышение отвечает `RESOURCE_EXHAUSTED` — ОТКАЗОМ, а
// не молчаливой очередью: очередь превратила бы исчерпание в неограниченное
// ожидание, неотличимое для клиента от «событий нет». Сверху стоит срок жизни
// потока: слот освобождается даже у клиента, который не читает и не уходит.
//
// **Буфера на подписчика здесь нет намеренно.** Он превратил бы отставание в
// потерю (переполнился — что-то выбросили) либо в неограниченную память. Вместо
// этого отставание становится задержкой, и она видна: курсор не двигается,
// позиция в служебном сообщении при следующем открытии это покажет.
//
// # Чего этот пакет НЕ делает
//
//   - НЕ фильтрует по меткам: они мутабельны, ресурс входит в выборку и выходит
//     из неё, и без предыдущего состояния выход неотличим от удаления. Метки
//     отбирает клиент — он может себе это позволить, потому что событие несёт
//     полное состояние (kacho#1025 заводит серверный отбор, когда объём событий
//     будет измерен);
//
//   - НЕ фильтрует по имени: имя мутабельно, и подписка по нему МОЛЧА перестаёт
//     совпадать после переименования. Адресный отбор делает ось `ids`;
//
//   - НЕ подписывает на операции: полл операции дёшев, а поток операций
//     тиражировал бы подписчикам идентификатор, присвоенный до выполнения;
//
//   - НЕ чистит журнал: удержание — свойство владельца, и он его объявляет;
//
//   - НЕ принимает ЖУРНАЛ СМЕНЫ СУБЪЕКТА (`kacho_iam.subject_change_outbox`), и
//     это решение, а не объём работы. Он читается унарным глаголом
//     (`InternalIAMService.PollSubjectChanges`, потребитель — `pkg/subjectchange`
//     на крае), и попытка подключить его сюда была бы не обобщением, а подменой
//     предмета.
//
//     Предметы РАЗНЫЕ, и различие видно по вопросу, на который отвечает событие:
//     этот поток отвечает арендатору «что стало с твоими ресурсами», тот —
//     слою авторизации «твои решения устарели». Отсюда противоположная модель
//     доступа: здесь построчное сужение по правам есть ЗАЩИТА (глагол объявлен
//     `scope_filtered`), там оно fail-open — пропущенная строка означает, что
//     кэш вердиктов не погас, то есть край продолжает отвечать по отозванному
//     праву. Сужение сняло бы ровно тот эффект, ради которого журнал заведён.
//
//     И оно замкнуло бы круг: чтобы отдать строку, владелец спросил бы модель
//     прав, а предмет строки — обесценить кэшированные ответы на такие вопросы.
//     Под fail-closed это даёт «модель недоступна ⇒ край не узнаёт об отзывах»,
//     то есть хуже прямого чтения, а не лучше.
//
//     Два расхождения помельче названы здесь же, чтобы их не приняли за
//     единственные: сужатель этой формы типизирован конкретным
//     `*listnarrow.Narrower`, а у владельца прав своя реализация по решению
//     (видимость строки определяется НАБОРОМ отношений, а не одним действием);
//     и у того журнала нет колонки вида предмета, которой [Storage] требует, —
//     тип субъекта лежит в нагрузке, а `resource_type` там необязательная
//     подсказка, которую читатель не берёт.
//
//     Разбор целиком, включая два отвергнутых исхода и их цену, —
//     `docs/architecture/subject-change-journal-is-not-a-resource-stream.md`;
//     здесь он не пересказывается, чтобы два места об одном предмете снова не
//     разошлись (kacho#1397).
