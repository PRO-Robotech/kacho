package subscription

import (
	corelibsub "github.com/PRO-Robotech/corelib/subscription"
)

// Граница устоявшегося и объявление удержания остались в ФУНДАМЕНТЕ, и здесь
// они названы ПСЕВДОНИМАМИ, а не копиями.
//
// Почему шов прошёл именно здесь. Сервер потока объявляет форму подписки с
// платформенным именем и служит её владельцам платформы — его дом там же, где
// его контракт. Наблюдение позиции контракта не имеет вовсе: оно про строки и
// незавершённые транзакции, а не про вид ресурса, проект или право, — и тем же
// наблюдением пользуется служба доступа для своего журнала смены субъекта.
// Контракт уехал, примитив остался, и оба утверждения проверяются деревом:
// заглушек подписки в фундаменте больше нет, а [Watermark] у него один.
//
// Почему ПСЕВДОНИМ, а не объявление своего типа. Псевдоним есть тот же тип
// by construction: значение, собранное фундаментом, и значение, названное
// здесь, невозможно перепутать, а копия перечисления разошлась бы с
// оригиналом МОЛЧА — обе стороны продолжали бы компилироваться, и первым
// расхождение увидел бы владелец журнала, чей пол удержания вдруг стал бы
// считаться по чужой полосе.
type (
	// Watermark — наблюдатель границы устоявшегося у журнала владельца.
	Watermark = corelibsub.Watermark
	// Querier — источник, отвечающий на вопрос наблюдателя.
	Querier = corelibsub.Querier
	// Retention — что владелец обещает про удержание своего журнала.
	Retention = corelibsub.Retention
)

// Полосы удержания. Ноль объявлением не является, поэтому [RetentionUnset]
// существует отдельно: «удерживаю всё» есть свойство владельца, а не умолчание
// формы.
const (
	RetentionUnset         = corelibsub.RetentionUnset
	RetainsEverything      = corelibsub.RetainsEverything
	RetainsFromEarliestRow = corelibsub.RetainsFromEarliestRow
)
