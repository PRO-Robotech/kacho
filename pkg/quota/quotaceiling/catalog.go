// Package quotaceiling — ВЕЛИЧИНЫ ПОТОЛКОВ, ОБЪЯВЛЕННЫЕ ПОСАДКОЙ ДОМЕНА.
//
// Приёмка `docs/specs/sub-phase-QUOTA-FATE-1-limit-value-is-stated-by-posture-acceptance.md`
// (APPROVED, исход В), стадия `S1`; прецедент формы —
// `PRO-Robotech/kaname:internal/apps/kaname/config/own_ceilings.go` (`KAN-QUOTA-1`, `П25`).
//
// # Что этот пакет НЕ является — авторитетом величин под другим именем
//
// У авторитета есть контракт со своими глаголами, три области со старшинством,
// дельта и ревизия, и назначает величину администратор облака во время работы.
// Здесь ничего этого нет: контракта нет, область ОДНА (`DEFAULT` — низшая),
// величина одна на вид, назначает её оператор установки файлом при выкатке.
// Поэтому посадка не отзывает поарендаторных величин, а разблокирует их: полосы
// `ACCOUNT` и `PROJECT` остаются свободными и перекрывают посадку по построению.
//
// # Почему предикат ОДИН, а не по величине за величиной
//
// Две отдельные проверки дают потребителю возможность позвать первую и забыть
// вторую, и забытая половина есть контроль, которого нет. Здесь судится
// МНОЖЕСТВО целиком — одним вызовом, которого нечего забыть.
//
// # Почему он живёт в дереве платформы, а не в фундаменте
//
// Об объявленных величинах фундаменту знать неоткуда: каталог видов принадлежит
// домену, а домены здесь — пять служб ОДНОГО продукта. Предикат про посадку
// одного продукта нейтральному модулю не принадлежит (тот же довод, что у
// `pkg/quota/quotaedge`).
package quotaceiling

// catalog.go — страж МОЩНОСТИ объявленного множества и перенос величин в карту.
//
// # Множество либо ПУСТОЕ, либо РАВНОЕ каталогу; промежуточного не бывает
//
//	пустое         → установка потолков не объявляет; поведение сегодняшнее
//	равно каталогу → установка объявила потолки целиком
//	промежуточное  → ОТКАЗ СТАРТА
//
// Частично объявленный набор есть ПОЛОВИНА ПАРЫ, и она хуже отсутствия обеих,
// потому что ВЫГЛЯДИТ настроенной (`security-hardening.md` §«Контроль, у
// которого нет МЕХАНИЗМА исполниться»). Оператор, объявивший семь величин из
// восьми, читает свой профиль как «потолки заведены», а восьмой вид остаётся
// неограниченным — и не сообщает об этом ничем: ни отказом, ни записью, ни
// строкой витрины.
//
// # Почему пустое множество здесь законно, а умолчание у ручки авторитета — нет
//
// Различает НАПРАВЛЕНИЕ изменения. Умолчание у `quota.authority` сняло бы
// ДЕЙСТВУЮЩИЙ потолок молча. Пустое множество не снимает ничего: потолков нет
// ни в одной установке, и оно есть сегодняшнее состояние, не меняющееся ни на
// байт. Страж при этом остаётся НЕВАКУУМНЫМ — он падает на промежуточном
// множестве, то есть на единственном входе, где намерение оператора и поведение
// продукта могут разойтись.
//
// # Почему указатель, а не число
//
// Ноль — законная величина: «ресурсов этого вида не заводить». На простом
// `int64` он неотличим от «величина не объявлена», и оператор, желающий
// запретить вид, не смог бы этого выразить ни при каком вводе. Отсутствие
// обязано быть представимо ОТДЕЛЬНО от значения.

import (
	"fmt"
	"sort"
	"strings"

	"go.uber.org/multierr"
)

// Knob — ОДНА величина посадки: координата, вид, довод и доступ к полю.
//
// Таблица этих записей — ЕДИНСТВЕННОЕ место, где ключ настройки связан с видом.
// Второе разошлось бы с первым молча: ключ правят коммитом в файл посадки, вид —
// в каталог, и расхождение видно только тому, кто в этот день ставит службу.
//
// Параметр типа — посадка домена: у пяти доменов она своя, а предикат один.
// Пары «таблица + срез значений в том же порядке» здесь нет намеренно —
// «тот же порядок» есть ровно то соглашение, которое расходится молча.
type Knob[C any] struct {
	// Key — координата ручки глазами оператора: путь ключа в файле настроек у
	// доменов, читающих файл, либо имя переменной окружения у тех, кто читает
	// только окружение.
	Key string
	// Env — имя переменной окружения. У доменов с файлом настроек ВЫВОДИТСЯ из
	// ключа (`EnvNameOf`), а не пишется вторым литералом; у доменов без файла
	// совпадает с `Key`.
	Env string
	// Kind — вид каталога, чей потолок объявляет эта величина.
	Kind string
	// Why — чем этот потолок защищает установку, словами оператора.
	Why string
	// Value — доступ к полю. Функция, а не смещение: поле остаётся обычным и
	// читается прямо, а таблица не заводит второго способа его назвать.
	Value func(C) *int64
}

// Named — ручка, как её называет отказ: координата и переменная, когда они
// разные, и одна координата, когда они совпадают.
//
// Повтор имени дважды в одной строке отказа читается как две разные ручки, и
// оператор ищет вторую.
func (k Knob[C]) Named() string {
	if k.Env == "" || k.Env == k.Key {
		return k.Key
	}
	return k.Key + " (" + k.Env + ")"
}

// Catalog — величины ОДНОГО домена. Порядок — порядок, в котором величины
// встречает оператор.
type Catalog[C any] []Knob[C]

// EnvNameOf повторяет вывод имени переменной, который делает viper из пути
// ключа: префикс службы, точка → `__`, дефис → `_`, верхний регистр.
//
// Выведенное имя не расходится с ключом by construction: переименуй ключ — и
// текст отказа переедет вместе с ним, вместо того чтобы назвать переменную,
// которой нет.
func EnvNameOf(envPrefix, key string) string {
	return envPrefix + "_" + strings.ToUpper(
		strings.NewReplacer(".", "__", "-", "_").Replace(key))
}

// Shape — страж СОБСТВЕННОЙ таблицы: непуста, виды и ключи не повторяются, у
// каждой записи есть доступ к полю и довод.
//
// Без него испорченная таблица делает стража зелёным при ЛЮБОМ входе: пустой
// каталог даёт «объявлено 0 из 0», то есть законное пустое множество на любой
// посадке.
func (c Catalog[C]) Shape() error {
	if len(c) == 0 {
		return fmt.Errorf("каталог величин пуст: страж мощности судил бы пустоту " +
			"и был бы зелен при любой посадке")
	}
	var errs error
	kinds := make(map[string]int, len(c))
	keys := make(map[string]int, len(c))
	for i, k := range c {
		switch {
		case strings.TrimSpace(k.Kind) == "":
			errs = multierr.Append(errs, fmt.Errorf("величина №%d: вид не назван", i))
		case kinds[k.Kind] > 0:
			errs = multierr.Append(errs, fmt.Errorf(
				"вид %s объявлен дважды: величина у вида одна, и вторая запись "+
					"означает, что одна из двух ручек не читается никем", k.Kind))
		default:
			kinds[k.Kind]++
		}
		switch {
		case strings.TrimSpace(k.Key) == "":
			errs = multierr.Append(errs, fmt.Errorf(
				"величина вида %s: координата ручки не названа — отказ без неё "+
					"не говорит оператору, что править", k.Kind))
		case keys[k.Key] > 0:
			errs = multierr.Append(errs, fmt.Errorf(
				"ручка %s объявлена дважды", k.Key))
		default:
			keys[k.Key]++
		}
		if k.Value == nil {
			errs = multierr.Append(errs, fmt.Errorf(
				"величина вида %s: доступа к полю нет — объявленную величину "+
					"никто не прочтёт, и вид молча останется незаявленным", k.Kind))
		}
		if strings.TrimSpace(k.Why) == "" {
			errs = multierr.Append(errs, fmt.Errorf(
				"величина вида %s: не сказано, чем этот потолок защищает "+
					"установку — оператор не может выбрать число", k.Kind))
		}
	}
	return errs
}

// Validate — СТРАЖ МОЩНОСТИ: объявленное множество пусто либо равно каталогу, и
// ни одна объявленная величина не отрицательна.
//
// Отказ по КАЖДОЙ величине сразу (multierr), а не по первой: оператор, узнающий
// перечень по одному имени за перезапуск, платит перекатом за строку.
func (c Catalog[C]) Validate(cfg C) error {
	if err := c.Shape(); err != nil {
		return err
	}

	var (
		stated   int
		unstated []string
		errs     error
	)
	for _, k := range c {
		v := k.Value(cfg)
		if v == nil {
			unstated = append(unstated, fmt.Sprintf("%s — ручка %s; зачем: %s",
				k.Kind, k.Named(), k.Why))
			continue
		}
		stated++
		if *v < 0 {
			errs = multierr.Append(errs, fmt.Errorf(
				"%s = %d: потолок вида %s обязан быть неотрицательным. "+
					"Отрицательное значение НЕ означает «без ограничения» — такое "+
					"прочтение сняло бы потолок величиной, похожей на опечатку; "+
					"«не заводить вовсе» выражается нулём",
				k.Named(), *v, k.Kind))
		}
	}

	// Пустое множество законно: установка потолков не объявляет, и поведение
	// остаётся сегодняшним. Полный каталог законен тоже. Отказ — ровно на
	// промежуточном.
	if stated > 0 && len(unstated) > 0 {
		sort.Strings(unstated)
		errs = multierr.Append(errs, fmt.Errorf(
			"потолки объявлены ЧАСТИЧНО: %d величин из %d. Частичный набор "+
				"выглядит настроенным и не ограничивает %d вид(ов) — оператор "+
				"читает профиль как «потолки заведены», а необъявленный вид "+
				"остаётся без предела и не сообщает об этом ничем. Объявите "+
				"каталог ЦЕЛИКОМ либо не объявляйте ни одной величины (0 означает "+
				"«ресурсов этого вида не заводить»). Не объявлены:\n  %s",
			stated, len(c), len(unstated), strings.Join(unstated, "\n  ")))
	}
	return errs
}

// Stated — объявленные величины по видам. Пустая карта означает, что посадка
// потолков не объявляет; страж выше до промежуточного состояния не допускает.
//
// ЕДИНСТВЕННЫЙ путь, которым величины уезжают из настройки дальше: композиционный
// корень зовёт его и отдаёт результат тому, кто собирает полосу учёта.
func (c Catalog[C]) Stated(cfg C) map[string]int64 {
	out := make(map[string]int64, len(c))
	for _, k := range c {
		if k.Value == nil {
			continue
		}
		if v := k.Value(cfg); v != nil {
			out[k.Kind] = *v
		}
	}
	return out
}

// Kinds — виды каталога в объявленном порядке. Нужен тем, кто сверяет каталог
// посадки с каталогом списания, — чтобы перечень выводился, а не выписывался.
func (c Catalog[C]) Kinds() []string {
	out := make([]string, 0, len(c))
	for _, k := range c {
		out = append(out, k.Kind)
	}
	return out
}
