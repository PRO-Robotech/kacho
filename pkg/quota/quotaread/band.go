// Package quotaread — арендаторское чтение квот: ОДНО тело на всех владельцев.
//
// # Почему это общий пакет, а не пятая копия
//
// Число, из которого вычитают, остаётся в базе владельца ресурса — списание идёт
// в транзакции вставки, и распределённой транзакции в стеке нет. Но ЧТЕНИЕ
// доменно-независимо целиком: одна и та же таблица учёта с точностью до имени
// схемы, одно и то же правило «ответ никогда не бывает пустым», один и тот же
// порядок и один и тот же разбор промаха.
//
// Написанное пять раз порознь, оно разошлось бы там, где расхождение не видно ни
// одной из сторон: на промахе, то есть на проекте, который ещё ничего не
// создавал. Каждая копия по отдельности выглядела бы верной, а арендатор получал
// бы в разных доменах разный ответ на один и тот же вопрос.
//
// # Чего здесь нет и почему
//
// Здесь нет ни pgx, ни сгенерённых стабов: пакет стоит в слое use-case, и
// оператор чтения живёт у адаптера владельца (`pkg/quota.ListStates`), а перевод
// в контракт — у транспорта (`pkg/quota/quotapb`). Разделение не косметическое:
// полоса обязана быть проверяемой без базы и без соседа, иначе её собственные
// пробы становятся интеграционными и перестают писаться.
//
// Здесь нет и ЗАПИСИ. Резолв на промахе ничего не материализует — в отличие от
// `Admit`, где заведение строк есть часть предмета (место надо занимать). Предмет
// чтения иной: показать. Материализация на чтении означала бы, что список квот
// меняет состояние базы, и тогда «посмотреть» стало бы мутацией, которую никто не
// просил, а на fail-closed пути ещё и отказом там, где спрашивали только показать.
package quotaread

import (
	"context"
	"errors"
	"sort"

	"github.com/PRO-Robotech/kacho/pkg/peer"
)

// CarrierProject — носитель учёта «корень аренды».
//
// Объявлен ЗДЕСЬ, потому что и полоса, и её вызывающие называют одно и то же
// значение: пять литералов `"project"` разошлись бы молча ровно один раз, и это
// был бы последний раз, когда кто-то смог прочитать свои квоты.
const CarrierProject = "project"

// State — строка учёта, какой её ВИДИТ арендатор.
//
// Состав повторяет `kacho.cloud.quota.v1.Quota`: тип заводится под один контракт,
// и расхождение состава обязано быть видно сразу. Писателя у него нет ни одного —
// `used` пишет только триггер базы, и невыразимость «записать used» на Go-стороне
// и есть то, чем счётчик защищён от расхождения с реальностью.
type State struct {
	// Kind — вид ресурса точечным токеном платформы (`vpc.network`).
	Kind string
	// Limit — разрешённая величина на момент снимка.
	Limit int64
	// Used — сколько занято.
	Used int64
	// SourceScope — область, на которой величина победила.
	SourceScope string
	// SourceScopeID — объект победившей области; пуст, когда победило умолчание.
	SourceScopeID string
	// CarrierType, CarrierID — носитель учёта.
	CarrierType string
	CarrierID   string
}

// ResolvedLimit — одна разрешённая величина, как её отдаёт владелец величин.
//
// ЕДИНСТВЕННЫЙ экземпляр этого типа на все домены: у каждого владельца он
// объявлен псевдонимом сюда. Пять независимых структур с одинаковыми полями
// компилировались бы одинаково и разошлись бы при первом же новом поле —
// добавленном одному, а нужном всем.
//
// Ревизии здесь нет, и это НЕ упущение, а факт контракта: `Resolve` её не несёт.
// Настоящую проставляет синхронизатор дельты.
type ResolvedLimit struct {
	// Kind — вид ресурса точечным токеном платформы.
	Kind string
	// Value — разрешённая величина.
	Value int64
	// Carrier — ГДЕ этот вид считается: корень аренды (`project`) либо
	// родительский тип у вложенного вида.
	//
	// Приезжает ОТВЕТОМ и не выводится из формы токена: `iam.project` двухчастен
	// и считается в АККАУНТЕ. Догадка здесь не отказывает громко — она называет
	// носителем то, чем вид не считается.
	Carrier string
	// SourceScope — область, на которой величина победила.
	SourceScope string
	// SourceScopeID — объект победившей области; пуст, когда победило умолчание.
	SourceScopeID string
}

// Rows — строки учёта владельца, как их видит его собственная база.
type Rows interface {
	// ListStates отдаёт строки учёта носителя, упорядоченные по виду.
	//
	// Пустой срез означает «строк учёта ещё нет», а НЕ «квот нет»: различать эти
	// два состояния обязана полоса, и она это делает.
	ListStates(ctx context.Context, carrierType, carrierID string) ([]State, error)
}

// Limits — владелец величин. Старшинство областей (PROJECT > ACCOUNT > DEFAULT)
// разрешается У НЕГО и только у него.
type Limits interface {
	Resolve(ctx context.Context, scopeID, service string) ([]ResolvedLimit, error)
}

// Band — полоса чтения квот проекта.
type Band struct {
	rows   Rows
	limits Limits
	// limitService — токен КАТАЛОГА, под которым владелец величин знает виды
	// этого домена.
	limitService string
	// errorDomain — имя СЕРВИСА, называющее источник ответа в машинном признаке
	// (`ErrorInfo.domain`).
	//
	// Отдельно от предыдущего намеренно, а не ради симметрии: у домена `nlb` они
	// РАЗНЫЕ — каталог знает его виды как `loadbalancer`, а ответ на проводе
	// обязан называть источником `nlb`. Свести их в одно поле значило бы выбрать,
	// какое из двух утверждений сделать ложным.
	errorDomain string
}

// NewBand собирает полосу чтения.
//
// Отказывает при сборке, а не при первом вызове: полоса без строк или без
// владельца величин отвечала бы отказом на каждое чтение, оставаясь на вид
// собранной. Пустое имя каталога хуже — оно спрашивает у соседа виды сервиса с
// пустым именем и получает пустой набор, то есть «квот нет» вместо «не собрано».
func NewBand(rows Rows, limits Limits, limitService, errorDomain string) (*Band, error) {
	switch {
	case rows == nil:
		return nil, errors.New("quota read band: rows are required")
	case limits == nil:
		return nil, errors.New("quota read band: limit owner is required")
	case limitService == "":
		return nil, errors.New("quota read band: limit service token is required")
	case errorDomain == "":
		return nil, errors.New("quota read band: error domain is required")
	}
	return &Band{rows: rows, limits: limits, limitService: limitService, errorDomain: errorDomain}, nil
}

// States отдаёт квоты проекта: предел, потребление и источник победившей
// величины по каждому виду домена.
//
// ОТВЕТ НИКОГДА НЕ БЫВАЕТ ПУСТЫМ ПО УМОЛЧАНИЮ. Проект, ещё ничего не создавший,
// строк учёта не имеет by construction — их заводит первая мутация. Вернуть на
// это пустой набор значило бы сказать «квот нет», то есть «предела нет»: ровно
// обратное действительности, и прочитано оно будет как разрешение
// (`api-conventions.md` §«Пустое значение обязано означать „пусто“»).
//
// ЦЕНА НАЗВАНА: чтение квот проекта, ещё ничего не создавшего, зависит от
// доступности владельца величин и отвечает отказом, когда тот недоступен. После
// первой мутации строки есть, и чтение локально.
func (b *Band) States(ctx context.Context, projectID string) ([]State, error) {
	states, err := b.rows.ListStates(ctx, CarrierProject, projectID)
	if err != nil {
		return nil, err
	}
	if len(states) > 0 {
		return states, nil
	}

	limits, err := b.limits.Resolve(ctx, projectID, b.limitService)
	if err != nil {
		return nil, b.peerRefusal(err, projectID)
	}

	// Отвечаем только про виды, чей носитель — ПРОЕКТ: спрашивали про проект.
	//
	// Вид, считаемый в родительском ресурсе, единственного значения на уровне
	// проекта не имеет by construction — подсетей столько-то в КАЖДОЙ сети.
	// Строка такого вида, поданная с носителем `project`, называла бы носителем
	// то, чем вид не считается, и показывала бы потребление, которое не
	// наполнится никогда.
	out := make([]State, 0, len(limits))
	for _, l := range limits {
		if l.Carrier != CarrierProject {
			continue
		}
		out = append(out, State{
			Kind: l.Kind,
			// Потребление нулевое не по умолчанию, а по факту: строк учёта нет,
			// значит ни одна вставка ещё не списывала место.
			Used:          0,
			Limit:         l.Value,
			SourceScope:   l.SourceScope,
			SourceScopeID: l.SourceScopeID,
			CarrierType:   CarrierProject,
			CarrierID:     projectID,
		})
	}

	// Порядок задаётся здесь тем же признаком, что и на пути из базы (`ORDER BY
	// kind`): ответ владельца величин своего порядка не обещает, и без явной
	// сортировки набор свежего проекта шёл бы иначе, чем набор того же проекта
	// после первой мутации. Клиент, ведущий состояние по индексу, прочитал бы
	// перестановку как изменение.
	sort.Slice(out, func(i, j int) bool { return out[i].Kind < out[j].Kind })
	return out, nil
}

// peerRefusal переводит отказ соседа в нашу полосу — код и машинный признак
// берутся у носителя (`pkg/peer`), а не выписываются здесь.
//
// Проза соседа наружу не идёт: она может нести имя хоста и текст драйвера
// (`security.md` §Hardening #1).
func (b *Band) peerRefusal(err error, projectID string) error {
	return peer.Classify(err).Status(
		peer.Ref{Service: b.errorDomain, ResourceType: "iam.limit", ResourceID: projectID},
		peer.Prose{
			Missing:     "resource count limits are not stated for project %s",
			State:       "resource count limits for project %s cannot be read",
			Unavailable: "resource count limits are temporarily unavailable",
		},
	)
}
