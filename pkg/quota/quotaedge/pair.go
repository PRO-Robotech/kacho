// Package quotaedge — полнота пары «адрес домена величин + удостоверение к
// нему» у потребителя, вторая её половина.
//
// # Предмет: имя для сверки, названное при отсутствующем собеседнике
//
// Ручка адреса домена величин признаёт два значения: адрес в форме host:port
// либо слово, объявляющее, что домена величин в этой установке нет. Второе —
// законная посадка, а не отказ: вынос службы величин сделал адрес ручкой у
// каждого из пяти потребителей, и часть установок объявляет отсутствие.
//
// Удостоверение к этому ребру несёт ИМЯ, по которому сверяется рукопожатие. Имя
// не резолвится — оно СРАВНИВАЕТСЯ с SAN серверного листа. Поэтому при
// объявленном отсутствии домена оно не «лишняя строка»: оно называет ПИРА, к
// которому ребро не идёт, и контроль, присутствующий и исполняемый, защищает не
// фактического собеседника.
//
// Наблюдалось в дереве: шесть профилей развёртывания × пять потребителей — все
// тридцать пар объявляли отсутствие домена и тем же контейнером имя для сверки
// `kaname-internal.kacho.svc`. Манифест-проверка называла двух из пяти; о
// трёх остальных она молчала, потому что не знала формы, которой они писаны.
//
// # Почему это общий пакет, а не пять `if`
//
// Владельцев пятеро. Написанное у каждого, это решение было бы пятью копиями
// одного — и разошлось бы там, где расхождение не видит ни один из пяти:
// у одного потребителя посадка отвергалась бы, у соседнего та же посадка
// поднималась бы молча. По той же причине `corelib/quota.ReadPosture` держит
// перевод объявления в посадку витрины в одном месте.
//
// Живёт ЗДЕСЬ, а не в нейтральной библиотеке, ПО ЧИСЛУ ПРОДУКТОВ среди
// потребителей — тем же правилом, которым `credsecret` стал фундаментом.
// Потребителей пять, и все пять — службы платформы; службы доступа среди них нет
// ни одной, поэтому нейтральному модулю предикат не принадлежит: он про посадку
// ОДНОГО продукта (карта границы — `internal/repohygiene/foundationboundary.go`).
//
// Соседняя половина пары (адрес объявлен, удостоверения нет) живёт у разборщика
// объявления в нейтральной библиотеке, и обе половины в одном вызове были бы
// лучше. Свести их нечем: у разборщика нет поля об удостоверении, а завести его
// — правка другого репозитория. Пока предикат один и зовётся из того же метода,
// что и разбор, забыть его нечем.
//
// # Почему отказ безусловен, а не только в боевом режиме
//
// «Требуется ли проверяемый транспорт» — вопрос посадки: у остальных рёбер
// службы он решается режимом, и у этого ребра решается так же. «К кому мы
// идём» — НЕ вопрос посадки: собеседника нет ни в одном режиме. Смягчение по
// режиму оставило бы половину пары ровно на том стенде, который её и маскирует.
package quotaedge

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/corelib/grpcclient"
	corequota "github.com/PRO-Robotech/corelib/quota"
)

// Pair — объявление пары, как его прочитал потребитель из своей посадки.
//
// Имена ручек здесь не для красоты: они попадают в текст отказа старта, а он
// обязан восстанавливать следующий шаг оператора. Приходят ОТ потребителя, а не
// выводятся из общего образца: у двух из пяти посадка описана файлом настроек, и
// оператор видит там путь ключа, а не имя переменной окружения.
type Pair struct {
	// AuthorityKnob — имя ручки, объявляющей адрес домена величин.
	AuthorityKnob string
	// Authority — её сырое значение, как оно пришло из посадки.
	Authority string
	// TransportKnob — имя ручки, включающей удостоверение к домену величин.
	TransportKnob string
	// ServerNameKnob — имя ручки имени, по которому сверяется рукопожатие.
	ServerNameKnob string
	// Transport — удостоверение к домену величин целиком.
	Transport grpcclient.TLSClient
}

// ValidateAbsentAuthorityCarriesNoTransport отвергает половину пары, в которой
// адрес объявляет ОТСУТСТВИЕ домена величин, а удостоверение к нему объявлено.
//
// Вторая половина (адрес объявлен, удостоверения нет) проверяется разбором
// объявления и здесь не повторяется: два предиката об одном предмете расходятся
// именно там, где расхождение опасно.
func ValidateAbsentAuthorityCarriesNoTransport(p Pair) error {
	if strings.TrimSpace(p.Authority) != corequota.NotDeployed {
		return nil
	}

	declared := declaredHalves(p)
	if len(declared) == 0 {
		return nil
	}

	authorityKnob := p.AuthorityKnob
	if authorityKnob == "" {
		authorityKnob = "<ручка домена величин>"
	}

	return fmt.Errorf(
		"%s = %q объявляет, что домена величин в этой установке НЕТ, а удостоверение "+
			"к нему объявлено: %s. Обращаться не к кому, поэтому имя для сверки называет "+
			"ПИРА, К КОТОРОМУ РЕБРО НЕ ИДЁТ: рукопожатие прошло бы с тем, чьё имя "+
			"подставлено, а не с тем, к кому шли. Половина пары хуже отсутствия обеих, "+
			"потому что выглядит настроенной. Исход ровно один из двух: объявить адрес "+
			"домена величин в форме host:port — либо снять удостоверение к нему целиком",
		authorityKnob, corequota.NotDeployed, strings.Join(declared, "; "))
}

// declaredHalves — перечень объявленных частей удостоверения, каждая своей
// ручкой и своим значением.
//
// Перечисляются ВСЕ объявленные части, а не первая найденная: оператор снимает
// удостоверение целиком, и отказ, назвавший одну часть из трёх, отправлял бы его
// на второй круг за каждой следующей.
func declaredHalves(p Pair) []string {
	var out []string
	if p.Transport.Enable {
		out = append(out, fmt.Sprintf("%s = true", knobOr(p.TransportKnob, "<ручка удостоверения>")))
	}
	if name := strings.TrimSpace(p.Transport.ServerName); name != "" {
		out = append(out, fmt.Sprintf("%s = %q",
			knobOr(p.ServerNameKnob, "<ручка имени для сверки>"), name))
	}
	if strings.TrimSpace(p.Transport.CertFile) != "" {
		out = append(out, "сертификат клиента задан")
	}
	if strings.TrimSpace(p.Transport.KeyFile) != "" {
		out = append(out, "ключ клиента задан")
	}
	for _, ca := range p.Transport.CAFiles {
		if strings.TrimSpace(ca) != "" {
			out = append(out, "доверенные корни заданы")
			break
		}
	}
	return out
}

func knobOr(knob, fallback string) string {
	if strings.TrimSpace(knob) == "" {
		return fallback
	}
	return knob
}
