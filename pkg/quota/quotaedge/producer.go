// Package quotaedge — посадка ребра величин у потребителя.
//
// Пакет заведён под ПАРУ «адрес домена величин + удостоверение к нему»: вторая
// её половина отвергала удостоверение, объявленное при отсутствующем
// собеседнике. Половина снята вместе со своим предметом — ребра больше нет, и
// стеречь удостоверение к нему нечего. Осталось то, что от ребра пережило его
// самого: ЗНАЧЕНИЕ ручки и вердикт о нём.
//
// Живёт ЗДЕСЬ, а не в нейтральной библиотеке, ПО ЧИСЛУ ПРОДУКТОВ среди
// потребителей: их пять, и все пять — службы платформы. Предикат про посадку
// ОДНОГО продукта нейтральному модулю не принадлежит.
package quotaedge

// producer.go — у ручки домена величин осталось ОДНО законное значение, и адрес
// отвергается стартом, а не принимается молча.
//
// # Предмет: возможность, объявленная ручкой, и снятая у производителя
//
// Ручка `quota.authority` признавала два значения: адрес домена величин либо
// слово, объявляющее, что домена в этой установке нет. Первое значение
// производителя больше не имеет. Служба доступа сняла авторитет величин целиком
// (контракт, две службы, хранилище), платформа своего домена не завела:
// `proto/kacho/cloud/quota/v1` несёт ФОРМУ ответа учёта и не объявляет ни одной
// службы.
//
// Ручка, продолжающая принимать адрес, объявляет возможность, которой нет.
// Законных исходов у такого поля три (`api-conventions.md`
// §«Принято-и-проигнорировано»), и выбран ВТОРОЙ — отвергать явно: первый
// неисполним (реализовать нечего), третий снял бы ручку вместе с посадкой, на
// которой держится весь путь запроса пятерых.
//
// # Почему отказ, а не молчаливое «как отсутствие»
//
// Принять адрес и повести себя как при объявленном отсутствии значило бы
// подставить за оператора решение, которое он явно принял иначе. Это тот же
// класс, что «пусто = не сужаем» (`security.md`), только вывернутый: названное
// значение перестало бы значить названное. Отказ виден сразу; подмена — только
// по последствиям.
//
// # Почему здесь, а не пятью проверками у потребителей
//
// Потребителей пять, и написанное у каждого это решение было бы пятью копиями
// одного. Довод и место те же, что у второй половины пары в `pair.go`: предикат
// про посадку ОДНОГО продукта, а служб доступа среди потребителей нет ни одной.
//
// # Чем это состояние СНИМАЕТСЯ
//
// Развилка о судьбе авторитета величин не решена владельцем и ведётся задачей
// `PRO-Robotech/kacho#2190`. Оба её исхода снимают этот отказ по-своему: «квоты
// уходят из продукта» — вместе со всей полосой учёта; «новый владелец в Kachō» —
// вместе с появлением производителя, чей контракт будет СВОИМ, а не снятым
// контрактом службы доступа. Номер стоит в тексте отказа намеренно: отказ без
// предмета снятия бессрочен.

import (
	"fmt"
	"strings"

	corequota "github.com/PRO-Robotech/corelib/quota"
)

// canonicalAuthorityKnob — имя ручки, называемое, когда вызывающий своего не дал.
//
// Отказ без имени ручки неисполним: оператор видит, что стенд не поднялся, и не
// знает, что править. Умолчание здесь — не косметика, а то, что делает отказ
// восстанавливающим следующий шаг.
const canonicalAuthorityKnob = "quota.authority"

// ValidateAuthorityHasAProducer отвергает АДРЕС домена величин: производителя у
// контракта авторитета нет ни в одном дереве.
//
// Судит СЫРОЕ объявление, а не разрешённое: разрешение живёт в нейтральной
// библиотеке и об отсутствии производителя не знает — знать о нём ей неоткуда,
// предмет принадлежит платформе.
//
// Незаданное значение предикат пропускает НАМЕРЕННО. «Оператор не выбрал» судит
// разборщик объявления, и он же называет это своими словами; сказанное здесь
// вторым текстом об одном предмете дало бы два разных отказа на один вход, а
// оператор прочитал бы тот, который сработал первым.
func ValidateAuthorityHasAProducer(knob, value string) error {
	v := strings.TrimSpace(value)
	if v == "" || v == corequota.NotDeployed {
		return nil
	}
	return fmt.Errorf(
		"%s объявляет адрес домена величин %q, а производителя у этого контракта "+
			"НЕТ: авторитет величин снят со службы доступа целиком, и своего домена "+
			"платформа не завела. Обращаться некуда, поэтому адрес отвергается "+
			"стартом, а не принимается и не читается. Единственное действующее "+
			"значение ручки — %q; судьба авторитета ведётся PRO-Robotech/kacho#2190",
		knobOr(knob, canonicalAuthorityKnob), v, corequota.NotDeployed)
}

// knobOr отдаёт имя ручки вызывающего либо каноническое.
//
// Пустое имя приходит не от небрежности, а от вызывающего, который ручку не
// назвал: отказ обязан остаться исполнимым и в этом случае.
func knobOr(knob, fallback string) string {
	if strings.TrimSpace(knob) == "" {
		return fallback
	}
	return knob
}
