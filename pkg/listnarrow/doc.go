// Package listnarrow — ЕДИНСТВЕННАЯ реализация сужения списочной выдачи по правам.
//
// Публичный List читает СТРАНИЦУ строк из своей БД курсором и затем спрашивает
// kacho-iam, какие идентификаторы этой страницы видны вызывающему
// (`AuthorizeService.BatchCheck`, партии ≤100). Стоимость пропорциональна СТРАНИЦЕ,
// а не популяции типа в хранилище прав.
//
// # Почему не перечисление разрешённого
//
// Обратная форма вопроса — «перечисли ВСЕ объекты этого типа, которые субъекту
// можно» — имеет ЖЁСТКИЙ серверный предел и НЕ имеет продолжения: запрос вообще не
// несёт поля размера, поэтому просьба «дай больше» не расширяет ответ, а лишь
// обрезает уже усечённый. Предел действует на ТИП В ХРАНИЛИЩЕ, а не на арендатора,
// поэтому на долгоживущем сторе собственный ресурс арендатора выпадал за префикс и
// становился невидимым НАВСЕГДА при живых правах: строка есть, выдача есть, мутации
// работают (они задают прямой пообъектный вопрос) — а списка нет. Лечится не
// поднятием предела (он внешний и всё равно конечен), а формой вопроса.
//
// # Что здесь ЗАФИКСИРОВАНО, а что оставлено ПОЛЕМ
//
// Зафиксировано то, что является нормой и одинаково для всех:
//
//   - безымянный вызывающий получает ОТКАЗ — безусловно и ДО ветки «провязана ли
//     модель». Порядок несущий: пока отсечка жила за этой веткой, посадка без модели
//     отдавала всю страницу кому угодно, и держалось это лишь на загрузочном страже,
//     то есть ровно до первой конфигурации, которая его не взвела;
//   - «модель не провязана» — ОТКАЗ, никогда не сквозной проход. Состояние посадки
//     разрешением не бывает. За сужаемыми методами пообъектной проверки на крае нет
//     вовсе, откатываться не на что;
//   - аварийный режим остаётся явным исключением, но КАЖДОЕ его срабатывание
//     считается и называется: без прибора он становится тихим штатным, и «им
//     пользуются» неотличимо от «им не пользуются»;
//   - бюджет принадлежит ЗАПРОСУ: партии идут ограниченным веером, а потолок всей
//     операции выводится из глубины волн и срока одного вызова, а не задаётся
//     независимой ручкой.
//
// Оставлено полем то, что является ОСЬЮ, а не нормой:
//
//   - Config.Relations — предикат членства страницы ПО ТИПУ объекта. Сведение его к
//     одной константе меняло бы ВИДИМОСТЬ, а это продуктовое решение по каждому
//     ресурсу, а не выравнивание формы. Карта обязана быть ТОТАЛЬНОЙ (запись под
//     пустым ключом — умолчание), и это не формальность: тотальность есть то, что
//     позволяет гейту паритета прочитать объявление и сверить его с каталогом прав
//     потипно. Предикат, спрятанный в теле функции, — предикат, которого не видит ни
//     один гейт;
//   - размер партии, веер, срок вызова, окно кэша — величины посадки.
//
// # Кэш — только ПОЛОЖИТЕЛЬНЫЕ вердикты
//
// Отрицательный вердикт не кешируется никогда, иначе свежая выдача не была бы видна
// до истечения окна. Снятый доступ перестаёт действовать самое позднее через окно, и
// другого механизма отзыва здесь нет: мгновенное снятие потребовало бы канала
// уведомлений от владельца выдач сюда, то есть нового межсервисного ребра и
// отдельного решения.
