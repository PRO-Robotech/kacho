package authz

import "time"

// RevocationWindowPolicy — объявленная политика окна отзыва доступа.
//
// # Что такое это окно
//
// Срок жизни записи И ЕСТЬ окно отзыва — время, в течение которого субъект, у
// которого право уже отобрали, продолжает проходить. Иного пути снять запись у
// backend-сервиса нет.
//
// # Асимметрия есть НЕ ВЕЗДЕ, и это надо знать ДО того, как менять число
//
// Кешируются ТОЛЬКО положительные вердикты — на ВСЕХ площадках, включая край.
// Поэтому свежая ВЫДАЧА видна сразу (промах по кешу всегда идёт к авторитетному
// Check), а ждёт один лишь ОТЗЫВ. Асимметрия намеренная и правильная:
// администратор, выдавший доступ, не должен ждать; администратор, отобравший
// доступ, ждёт ограниченное и объявленное время.
//
// # Край отступал от этого правила, и цена отступления была измерена
//
// До 2026-08-05 край (api-gateway) складывал в тот же кеш и ОТКАЗ, из-за чего
// то же число работало второй, необъявленной стороной — как ЗАДЕРЖКА ВЫДАЧИ.
// Следствие наблюдалось не в теории: запрос, проигравший гонку материализации
// owner-tuple, сам записывал свой отказ и держал его весь срок жизни записи уже
// ПОСЛЕ появления права. В прогоне e2e это дало квантованное окно: из 75 шагов,
// восстановившихся ограниченным клиентским ретраем, 68 сошлись ровно на десятом
// повторе (10×500ms = 5.0s = ровно это число), ещё 3 — на двадцатом (второе
// такое же окно). Разброс, свойственный настоящей задержке материализации,
// отсутствовал: окно производил кеш, а не материализация.
//
// Отказ и так fail-closed, поэтому его кеширование не защищает НИЧЕГО — оно
// только откладывает выдачу. Край приведён к общему правилу, и нарушение
// сделано непредставимым по построению: у записи кеша края, как и у `Cache`
// ниже, нет поля «разрешено» (`gateway/internal/middleware.decisionCacheEntry`).
//
// # Почему это объявлено здесь, а не в комментарии каждого сервиса
//
// До этой записи окно было эмерджентным. Шесть сервисов несли положительный
// кеш вердиктов, каждый называл своё число в своём комментарии, и ни одно место
// не говорило, каким числу быть позволено. Параметр безопасности, которого
// никто не выбирал, нельзя ни обсудить, ни отозвать, ни заметить при смене.
// Гейт `internal/repohygiene.TestRevocationWindowIsDeclaredPolicy` связывает эту
// запись с деревом: смена умолчания без правки политики роняет проверку.
//
// # Второй путь получить окно, которого перепись не видела
//
// Перепись накрывает площадки, которые кеш НАЗЫВАЮТ. Пока `NewInterceptor`
// заводил кеш за вызывающего, оставившего поле пустым, существовал второй путь:
// сервис получал полноценное окно, ни разу его не назвав, и в исходнике не
// оставалось ни одной строки, по которой перепись могла бы его найти. Гейт при
// этом такой файл читал, засчитывал в «осмотрено» и объявлял чистым — то есть
// не просто не ловил, а отвечал «чисто» на вопрос, которого не задавал.
//
// Путь снят: неназванный кеш — отказ в старте (`NewInterceptor`), плюс
// `internal/repohygiene.TestNoServiceTakesTheWindowImplicitly` называет файл и
// строку до того, как процесс поднимут. Умолчание, меняющее посадку
// безопасности, обязано быть произнесённым — поэтому «своего числа нет»
// записывается как `NewCache(0)`, то есть ЯВНОЕ «беру умолчание политики», и
// такая площадка попадает в Inherited.
//
// # Что НЕ ездит по этому окну
//
// Окно относится к отзыву ГРАНТА (AccessBinding). Оно НЕ относится к отзыву
// УЧЁТНЫХ ДАННЫХ — скомпрометированный токен, уволенный сотрудник, утёкший ключ.
// Такой отзыв обязан быть немедленным, и он немедленный не потому, что окно
// мало, а потому, что идёт другим путём: сессия/токен снимается на краю
// (`session_revocations`, `InternalAuthzCacheService.InvalidateSubject` в
// api-gateway из `subject_change_outbox`, дренаж ≤1s после коммита), и
// закешированный положительный вердикт backend-сервиса ему не помогает — до
// backend-сервиса запрос с отозванным токеном просто не доходит.
//
// Смешивать эти два отзыва — ошибка, которая толкает «сделать окно поменьше»
// вместо «снять учётные данные». Окно ниже размерено под отзыв гранта, и
// уменьшать его ради сценария, который им не решается, не нужно.
type RevocationWindowPolicy struct {
	// Default — окно для сервиса, который своего числа не имеет (строит кеш
	// как NewCache(0)). Читается конструктором кеша: это единственный источник
	// значения, а не литерал, повторённый по дереву.
	Default time.Duration

	// Ceiling — потолок: ни одно окно не вправе быть больше. Это обещание
	// платформы про отзыв гранта.
	Ceiling time.Duration

	// Windows — перепись объявленных окон, ключ «<сервис> <ручка>».
	// Значение обязано совпадать с тем, что реально написано в исходнике
	// сервиса; расхождение — находка гейта.
	Windows map[string]time.Duration

	// Inherited — площадки, у которых своего числа НЕТ: они берут Default.
	// Перечислены явно, чтобы «у сервиса нет ручки» было записанным фактом, а
	// не следствием того, что гейт ничего не нашёл.
	Inherited map[string]bool
}

// RevocationPolicy — действующая политика.
//
// # Обоснование числа
//
// Потолок 10s выбран как сумма трёх слагаемых, каждое из которых наблюдаемо:
// срок жизни записи (≤5s) + дренаж очереди отзыва до хранилища прав (≤2s) +
// запас на переспрос под нагрузкой. Меньше 5s означало бы ходить к iam почти на
// каждый RPC — та самая нагрузка, ради амортизации которой кеш и заведён;
// больше 10s означало бы, что снятие права заметно человеку, который его снял.
//
// Число НЕ выведено из механизма проактивной инвалидации: такого механизма у
// backend-сервисов нет (см. ниже). Прежняя запись в doc.go складывала окно с
// членом «NOTIFY≤1s» от пути, у которого в этом репозитории нет ни одного
// отправителя, и потому обещала распространение, которого не происходит.
var RevocationPolicy = RevocationWindowPolicy{
	Default: 5 * time.Second,
	Ceiling: 10 * time.Second,

	// Windows — перепись на 2026-08-04, снятая с дерева гейтом (8 площадок,
	// 7 процессов). Ключ — «<процесс> <ручка>».
	//
	// Три семьи кешей, все кешируют вердикт и все задерживают отзыв:
	//   - `authz.cache*` — пообъектная проверка на КАЖДОМ RPC (оба листенера);
	//   - `authz.list-filter.*` — пообъектная видимость строки страницы List;
	//   - край (`api-gateway`) — решение по запросу до того, как он вообще уйдёт
	//     в сервис.
	//
	// Значения намеренно ОДИНАКОВЫ (5s) везде, кроме registry: у registry на
	// той же поверхности сидит docker-клиент, тянущий образы по выданному
	// гранту, поэтому там окно сужено вдвое осознанно и это записано у ручки.
	//
	// # Почему края здесь не было до 2026-08-04
	//
	// Перепись искала кеши двумя предикатами, и оба были привязаны к тому, КАК
	// кеш сделан, а не к тому, ЧТО он хранит: обход начинался с каталога
	// `services/` (край лежит в `gateway/`), а конструктор искался по имени
	// `authz.NewCache` (край строит свой `newDecisionCache` над общим LRU).
	// Поэтому процесс, через который проходит КАЖДЫЙ внешний запрос, не был
	// прочитан ни одной из проверок — ни разу, ни одним файлом, — и его окно
	// не было записано нигде. Это не недосмотр обхода: край находился вне того,
	// что обход был способен выразить.
	//
	// Оба предиката расширены (`revocationScanRoots` + `localVerdictCacheCtors`),
	// и перепись теперь считает ПРОЦЕССЫ, а не каталоги под `services/`.
	Windows: map[string]time.Duration{
		"vpc authz.cache-ttl":                            5 * time.Second,
		"vpc authz.list-filter.cache-ttl":                5 * time.Second,
		"nlb authz.cache.ttl":                            5 * time.Second,
		"nlb authz.list-filter.cache-ttl":                5 * time.Second,
		"registry KACHO_REGISTRY_AUTHZ_CACHE_TTL":        2 * time.Second,
		"compute KACHO_COMPUTE_LIST_FILTER_CACHE_TTL_MS": 5 * time.Second,
		"storage KACHO_STORAGE_LIST_FILTER_CACHE_TTL_MS": 5 * time.Second,

		// Край — единственная площадка с ПРОАКТИВНЫМ снятием записи:
		// `InternalAuthzCacheService.InvalidateSubject`, который зовёт дренаж
		// `subject_change_outbox` из iam (отправитель реальный —
		// `services/iam/internal/clients/cache_invalidation_applier.go`; снятие
		// гранта эмитит строку в той же транзакции, что и удаление привязки).
		// Поэтому обычный отзыв здесь укладывается в дренаж, а это окно —
		// ЗАПАСНОЕ: столько действует отозванный грант, если дренаж отстал или
		// лежит. Запасное окно — всё равно окно, и незаписанное запасное окно —
		// всё равно ничей параметр безопасности.
		//
		// Отличий от остальных строк по СЕМАНТИКЕ у этой величины больше нет:
		// край, как и все, кеширует только положительный вердикт, поэтому число
		// работает ровно одной стороной — как окно отзыва. Уменьшать его —
		// значит платить обращением к iam почти на каждый запрос именно там,
		// где запросов больше всего.
		"api-gateway KACHO_API_GATEWAY_AUTHZ_CACHE_TTL_SECONDS": 5 * time.Second,
	},

	// Inherited — площадки БЕЗ своей ручки: строятся как NewCache(0) и берут
	// Default. Перечислены явно, потому что «у сервиса нет ручки» — записанный
	// факт, а не следствие того, что гейт ничего не нашёл. Ключи держат форму
	// «<сервис> <ручка>», чтобы самоистечение переписи их не считало
	// просроченными.
	Inherited: map[string]bool{
		"compute authz.cache-ttl": true, // services/compute/internal/check/factory.go
		"geo authz.cache-ttl":     true, // services/geo/internal/check/factory.go
		"storage authz.cache-ttl": true, // services/storage/internal/check/factory.go
	},
}
