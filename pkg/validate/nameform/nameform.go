// Package nameform несёт ЕДИНСТВЕННУЮ форму имени ресурса Kachō и чистый
// предикат к ней — без транспорта.
//
// Зачем отдельный пакет, а не константа рядом с валидаторами. Форма нужна и
// слою домена (self-validating newtype), а домену запрещено тянуть транспорт:
// правило чистой архитектуры — `domain/` только stdlib и контракты, без grpc
// (`architecture.md`). Валидаторы же обязаны возвращать готовый gRPC-статус,
// поэтому `pkg/validate` импортирует grpc — и импорт ЛЮБОГО его символа тянет
// grpc в граф зависимостей импортёра целиком: в Go зависимость пакетная, а не
// посимвольная.
//
// Отсюда разделение: здесь — форма и предикат (ноль зависимостей вне stdlib),
// в `pkg/validate` — отказы в форме gRPC-статуса поверх этого предиката. Обе
// стороны читают ОДНУ строку, поэтому разойтись им не на чем.
package nameform

import "regexp"

// Form — единственная форма имени ресурса в дереве: DNS label по RFC 1123.
//
// Строчные латинские буквы, цифры и дефис; первый и последний символ — буква
// или цифра; длина 1..63. Производных «как общий, но здесь ещё подчёркивание»
// не заводится: два имени одного правила расходятся молча — так и разошлись
// четыре прежних валидатора (заглавные у одного, подчёркивание у двух, пустая
// строка у трёх), давая один контракт и разное исполнение (задача #715).
//
// Форма взята внешним стандартом намеренно. Имя, годное как DNS label, годится
// сегментом адреса, меткой в средствах наблюдения и именем в конфигурации
// развёртывания — без экранирования и без второго правила «а здесь можно
// иначе». Спор о вкусах при заведении следующего ресурса снят: форма не наша.
//
// Единственность объявления держит гейт internal/repohygiene
// TestResourceNameFormIsDeclaredOnce.
const Form = `^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`

// MaxLen — верхняя граница длины имени, та же, что в Form.
const MaxLen = 63

var re = regexp.MustCompile(Form)

// OK сообщает, отвечает ли значение форме.
//
// Пустая строка форме НЕ отвечает — и это верно на обоих путях, но означает
// разное: на правке пустое имя отвергается, на создании оно законный вход и до
// записи заменяется умолчанием. Решает это вызывающий; предикат отвечает только
// про форму.
func OK(value string) bool { return re.MatchString(value) }
