package grpcsrv

import (
	"strings"
	"unicode/utf8"
)

// Отображаемое имя принципала — ЕДИНСТВЕННОЕ значение семейства `x-kacho-`,
// которое приходит свободным вводом пользователя. Тип принципала — из закрытого
// словаря, идентификатор — крокфордова база32, claim'ы токена чеканит Hydra;
// имя же человек пишет сам, и продукт русскоязычный, поэтому кириллица в нём —
// ожидаемый ввод, а не ошибка.
//
// Транспорт gRPC допускает в значении ОБЫЧНОГО metadata-ключа только печатаемый
// ASCII (0x20–0x7E) и отвергает ВЕСЬ вызов кодом Internal, не доходя до
// обработчика. То есть без кодирования имя не «теряется» — оно лишает
// пользователя доступа к API целиком.
//
// # Почему процентное кодирование, а не бинарный ключ
//
// gRPC предлагает для произвольных байтов ключ с суффиксом `-bin`. Он здесь не
// годится по двум причинам, обе про КРАЙ. Первая: значение пересекает мост
// REST→gRPC обычным HTTP-заголовком, и суффикс `-bin` меняет его обработку
// (значение base64-декодируется мостом), то есть один логический ключ получил
// бы разные правила на разных участках одного пути. Вторая: смена ключа требует
// чтения обоих во время выкатки, а чтение двух ключей об одном предмете —
// расхождение, которое разойдётся молча.
//
// Процентное кодирование сохраняет ОДИН ключ и обладает свойством, ради
// которого выбрано: для печатаемого ASCII без знака процента оно ТОЖДЕСТВЕННО.
// Значит подавляющая часть значений едет байт в байт, и читатель, не успевший
// обновиться в окне выкатки, видит ровно то же, что видел вчера.
//
// # Что кодируется
//
// Всё вне 0x20–0x7E — и сам знак процента. Без экранирования процента кодек
// перестал бы быть обратимым: имя «100% хлопок», написанное человеком, было бы
// неотличимо от кодированного и расшифровалось бы в другую строку, то есть
// данные пользователя портились бы тихо.
const displayNameEscape = '%'

// EncodePrincipalDisplayName приводит отображаемое имя к печатаемому ASCII,
// пригодному значению обычного metadata-ключа gRPC.
//
// Для строки, целиком состоящей из печатаемого ASCII и не содержащей знака
// процента, возвращает её саму — это и есть свойство совместимости, на которое
// опирается выкатка.
func EncodePrincipalDisplayName(s string) string {
	if !displayNameNeedsEscaping(s) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s) + len(s)/2)
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x20 && c <= 0x7E && c != displayNameEscape {
			b.WriteByte(c)
			continue
		}
		b.WriteByte(displayNameEscape)
		b.WriteByte(hexUpper[c>>4])
		b.WriteByte(hexUpper[c&0x0F])
	}
	return b.String()
}

// DecodePrincipalDisplayName восстанавливает имя, закодированное
// EncodePrincipalDisplayName.
//
// Вход, который кодеком не производился, возвращается БЕЗ ИЗМЕНЕНИЙ — и это не
// снисходительность, а требование выкатки: пока на другом конце остаётся
// производитель прежней сборки, по этому ключу приезжает сырая строка, и
// строгий разбор превратил бы имя «100% хлопок» в отказ или в мусор.
//
// Отказ здесь невозможен by construction: имя косметическое, и ронять на нём
// вызов значило бы воспроизвести ровно тот дефект, ради которого кодек заведён.
func DecodePrincipalDisplayName(s string) string {
	if !strings.ContainsRune(s, displayNameEscape) {
		return s
	}
	out := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c != displayNameEscape {
			out = append(out, c)
			continue
		}
		if i+2 >= len(s) {
			return s // усечённая последовательность — вход не наш
		}
		hi, ok1 := unhex(s[i+1])
		lo, ok2 := unhex(s[i+2])
		if !ok1 || !ok2 {
			return s // не шестнадцатеричная пара — вход не наш
		}
		out = append(out, hi<<4|lo)
		i += 2
	}
	if !utf8.Valid(out) {
		return s // расшифровалось в не-UTF-8 — вход не наш
	}
	return string(out)
}

const hexUpper = "0123456789ABCDEF"

func displayNameNeedsEscaping(s string) bool {
	for i := 0; i < len(s); i++ {
		if c := s[i]; c < 0x20 || c > 0x7E || c == displayNameEscape {
			return true
		}
	}
	return false
}

func unhex(c byte) (byte, bool) {
	switch {
	case c >= '0' && c <= '9':
		return c - '0', true
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10, true
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10, true
	}
	return 0, false
}

// EnsurePrincipalDisplayNameWireSafe — страж транспорта для точки ПЕРЕСЫЛКИ, а
// не для пользовательского ввода.
//
// Отличие от EncodePrincipalDisplayName существенное и потому вынесено в
// отдельное имя. Кодировщик применяют там, где значение ВПЕРВЫЕ попадает под
// ключ: он обратим и экранирует знак процента, чтобы «100% хлопок» доехало
// собой. Страж применяют там, где значение УЖЕ под ключом и просто едет дальше:
// повторное кодирование там экранировало бы служебные проценты и превратило бы
// «%D0%94» в «%25D0%2594», то есть испортило бы уже правильное значение.
//
// Поэтому страж идемпотентен: печатаемый ASCII — а закодированное значение
// печатаемо by construction — проходит насквозь; всё прочее кодируется, потому
// что иначе транспорт отвергнет весь вызов.
func EnsurePrincipalDisplayNameWireSafe(s string) string {
	for i := 0; i < len(s); i++ {
		if c := s[i]; c < 0x20 || c > 0x7E {
			return EncodePrincipalDisplayName(s)
		}
	}
	return s
}
