package subjectchange_test

// flush_radius_test.go — РАДИУС сброса кэша решений: он сплошной, и это решение
// (kacho#1395), а не оставшееся от прежнего устройства упрощение.
//
// # Что здесь стережётся
//
// Соблазн очевиден и уже был высказан задачей: порция несёт ИМЕНА субъектов, та
// же порция закрывает потоки ПОИМЁННО — значит и кэш можно гасить поимённо, а не
// целиком. Для строк, чей субъект НАЗВАН, это верно. Для строк, чей субъект
// назвать нельзя, это ОТКАЗ ОТ ОТЗЫВА, и вот почему.
//
// Право выдаётся ГРУППЕ — это предпочтительная форма выдачи в продукте, а не
// редкость. Снятие такой привязки эмитит строку журнала с субъектом
// `group:<id>`; словарь имён субъектов ЗАКРЫТ (`authz.TenantSubject` признаёт
// `user` и `service_account`), поэтому строка приезжает к потребителю БЕЗ имени.
// А вердикты, которые обязаны погаснуть, принадлежат ЧЛЕНАМ группы — их имена в
// строке не названы и из неё не выводятся: членство знает владелец прав, а не
// журнал.
//
// Отсюда: поимённый сброс на такой строке гасит НОЛЬ записей, и каждый член
// группы продолжает проходить по закешированному «разрешено» весь срок жизни
// записи — уже ПОСЛЕ того, как привязку сняли. Сплошной сброс гасит их все.
//
// # Почему цена сплошного сброса мала — числами
//
// Срок жизни записи кэша решений — 5 с (`KACHO_API_GATEWAY_AUTHZ_CACHE_TTL_SECONDS`,
// умолчание 5, ни один профиль его не переопределяет), период перепроса — 2 с
// (`KACHO_API_GATEWAY_SUBJECT_CHANGE_POLL_INTERVAL`). Сброс происходит только на
// НЕПУСТОЙ порции, то есть не чаще раза в период. Значит поимённый сброс мог бы
// сохранить записи самое большее на 3 с из 5 — и ровно в те окна, когда права
// в кластере МЕНЯЮТСЯ, то есть когда устаревшее «разрешено» и опасно.
//
// # Что делает эта проба и чего не делает
//
// Она НЕ утверждает, что поимённого сброса не должно быть никогда: порция из
// одних только названных субъектов сужение допускает. Она утверждает узкое и
// достаточное: строка, чьего субъекта назвать нельзя, ОБЯЗАНА гасить кэш
// целиком. Существующие пробы этого не держат — они краснеют на таком сужении
// лишь по совпадению фикстур (их субъекты неназываемы), а текст их падения
// говорит о праймящем такте, то есть посылает читателя не туда.

import (
	"context"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/subjectchange"
)

// TestUnnameableSubjectStillFlushesTheDecisionCache — строка без имени субъекта
// гасит кэш ЦЕЛИКОМ.
//
// Положительный контроль стоит рядом и в той же пробе: та же строка закрывает
// НОЛЬ потоков. Он показывает, что поимённая полоса на этой строке не делает
// ничего — то есть сплошной сброс здесь не «подстраховка», а единственное, что
// вообще происходит.
func TestUnnameableSubjectStillFlushesTheDecisionCache(t *testing.T) {
	// Порция 1 — праймящая (курсор принимается, сброса нет).
	// Порция 2 — снятие привязки, выданной ГРУППЕ: субъект `group:grp-a` вне
	// закрытого словаря имён, поэтому до потребителя он доезжает пустым.
	p := &subjectPoller{batches: [][]subjectchange.SubjectChange{
		{{ID: 1, Subject: "user:usr-seed"}},
		{{ID: 2, Subject: ""}},
	}}
	closer := &closerStub{perClose: 1}
	var flushes int
	w := newWatcher(t, p, func() { flushes++ }, closer)

	w.Poll(context.Background())
	if flushes != 0 {
		t.Fatalf("предпосылка: праймящий перепрос не гасит кэш, а гасил %d раз(а)", flushes)
	}

	w.Poll(context.Background())

	closed, _ := closer.snapshot()
	if len(closed) != 0 {
		t.Fatalf("предпосылка пробы неверна: строка без имени закрыла потоки %v — "+
			"тогда поимённая полоса на ней что-то делает, и разбор радиуса надо перемерить", closed)
	}
	if flushes != 1 {
		t.Fatalf("кэш решений НЕ погашен (сбросов %d, ожидался 1) на строке, чьего субъекта назвать нельзя.\n"+
			"Это отзыв, который не доехал: так выглядит снятие привязки, выданной ГРУППЕ.\n"+
			"Вердикты, которые обязаны погаснуть, принадлежат ЧЛЕНАМ группы; их имена в строке\n"+
			"не названы и из неё не выводятся, поэтому поимённый сброс гасит ноль записей, и\n"+
			"каждый член продолжает проходить по закешированному «разрешено» весь срок TTL —\n"+
			"уже после снятия привязки. Сплошной сброс на неназываемой строке — решение\n"+
			"(kacho#1395), а не упрощение: сузишь его до названных субъектов — заведёшь\n"+
			"fail-open ровно в предпочтительной форме выдачи прав.", flushes)
	}
}

// TestMixedBatchFlushesOnceForTheWholeBatch — порция, где названные субъекты
// соседствуют с неназываемым, гасит кэш РОВНО ОДИН раз.
//
// Проба закрывает вторую половину развилки: «сбросов на порцию» — один, а не по
// одному на строку. Без неё сужение можно было бы «починить», начав звать сброс
// в цикле по строкам: первая проба осталась бы зелёной, а стоимость выросла бы
// кратно длине порции при том же радиусе.
func TestMixedBatchFlushesOnceForTheWholeBatch(t *testing.T) {
	p := &subjectPoller{batches: [][]subjectchange.SubjectChange{
		{{ID: 1, Subject: "user:usr-seed"}},
		{
			{ID: 2, Subject: "user:usr-a"},
			{ID: 3, Subject: ""},
			{ID: 4, Subject: "service_account:sva-b"},
		},
	}}
	closer := &closerStub{perClose: 1}
	var flushes int
	w := newWatcher(t, p, func() { flushes++ }, closer)

	w.Poll(context.Background())
	w.Poll(context.Background())

	if flushes != 1 {
		t.Fatalf("сбросов кэша %d, ожидался ровно 1 на порцию — "+
			"сброс на строку стоил бы кратно длине порции при том же радиусе", flushes)
	}
	closed, _ := closer.snapshot()
	if len(closed) != 2 || closed[0] != "user:usr-a" || closed[1] != "service_account:sva-b" {
		t.Fatalf("закрыты %v, ожидались ровно два НАЗВАННЫХ субъекта — "+
			"положительный контроль: поимённая полоса на названных строках работает", closed)
	}
}
