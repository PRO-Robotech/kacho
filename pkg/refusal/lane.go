// Package refusal — закрытый словарь полос отказа на СНЯТИЕ ресурса и два
// способа приклеить полосу к отказу.
//
// # Предмет
//
// Клиент обязан различать полосы отказа МАШИННО — по `reason`-токену в
// `google.rpc.ErrorInfo`, а не разбором прозы (`api-conventions.md`
// §By-lane code-split). Тон сообщения остаётся стабильным контрактом для
// ЧЕЛОВЕКА и предметом разбора не является: он несёт имена блокирующих строк,
// числа и падежи, и всякий, кто на него ключуется, ломается от правки текста,
// которую мы вправе сделать.
//
// До этого пакета у отказов на снятие признака не было вовсе: программа не
// могла отличить «ресурс защищён от удаления» от «контейнер не пуст» от
// «на лист ссылаются», не читая предложение.
//
// # Почему это ОТДЕЛЬНЫЙ словарь, а не шестая полоса corelib
//
// `corelib/errors.Reason` — словарь полос РЕЗОЛВА идентификатора, закрытый на
// пяти и закрытый КОМПИЛЯТОРОМ. Его предмет — «чей это идентификатор и нашёлся
// ли он»; предмет здешнего — «почему ссылочная структура не даёт снять». Оси
// ортогональны: отказ на снятие происходит с ресурсом, который прекрасно
// нашёлся. Дописать полосу туда значило бы сложить два вопроса в один словарь и
// заставить клиента различать их по коду, то есть вернуть ровно ту неразличимость,
// ради снятия которой словарь и заводится.
//
// # Почему токен ссылки ВЗЯТ У СЛУЖБЫ ДОСТУПА, а не придуман заново
//
// `REFERENCE_IN_USE` уже производит служба доступа (`kaname`), и консоль уже
// несёт по нему вердикт. Тот же факт — «снять нельзя, на ресурс ещё
// ссылаются» — платформа обязана называть ТЕМ ЖЕ токеном: два имени одного
// факта в двух продуктах разошлись бы молча, а клиенту пришлось бы держать
// таблицу «в каком продукте как называется».
//
// Замер, из которого это выведено: служба отдаёт `REFERENCE_IN_USE` и на
// «Account contains projects» (контейнер держит своих), и на «role is in use by
// access bindings» (на лист ссылаются чужие) — то есть уже решила, что это ОДНА
// полоса. Отсюда устройство ниже: токен один, а различие видов ссылки живёт в
// МЕТАДАННЫХ признака, где оно дополняет контракт, а не разветвляет его.
//
// `DELETION_PROTECTED` — токен собственный, потому что факт собственный: у
// службы доступа защиты от удаления нет вовсе, а действие вызывающего у него
// иное в корне — снять флаг у САМОГО ресурса, зависимых нет ни одного.
//
// # Почему тип, а не строка
//
// Поле `token` неэкспортируемое, поэтому за пределами пакета собрать полосу с
// произвольным токеном НЕЛЬЗЯ — словарь закрыт компилятором, а не соглашением.
// Токен строкой выразим любой: пятая полоса заводится опечаткой и доезжает до
// клиента молча, потому что клиент ключуется на равенство и просто не совпадёт,
// то есть отказ выглядит как ОТСУТСТВИЕ признака.
//
// # Чего пакет НЕ делает
//
// Он не выбирает код и не выводит полосу из прозы. Код у всех четырёх полос один
// (см. Code) и принадлежит классификации сервиса; полосу называет ПРОИЗВОДИТЕЛЬ
// отказа — тот, кто знает, почему отказал. Вывод полосы разбором сообщения был бы
// тем же разбором прозы, только перенесённым внутрь сервера.
package refusal

import (
	"errors"
	"fmt"

	"google.golang.org/genproto/googleapis/rpc/errdetails"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// Code — код всех полос этого словаря.
//
// Он ОДИН и вынесен в константу намеренно. Отказ на снятие из-за ссылочной
// структуры есть `FAILED_PRECONDITION` по определению (`api-conventions.md`
// §Error-format): ввод вызывающего корректен, не позволяет СОСТОЯНИЕ. Полоса
// уточняет ПОЧЕМУ, а не ЧЕМ ответить, поэтому кода в себе не носит: второе место,
// называющее код, разошлось бы с классификацией сервиса молча — и разошлось бы
// именно там, где деталь читают машиной.
const Code = codes.FailedPrecondition

// Lane — машинный признак полосы отказа на снятие.
type Lane struct {
	token string
	// refKind — вид ссылки, удержавшей снятие. Пусто там, где ссылок нет вовсе
	// (защита от удаления). Уезжает в `ErrorInfo.metadata`, а НЕ в токен:
	// уточнение обязано дополнять контракт, а не разветвлять его.
	refKind string
}

// Четыре полосы закрытого словаря на ДВУХ токенах. Пятой снаружи не завести:
// поля `token` и `refKind` неэкспортируемые.
//
// Полосы различаются не оттенком, а ДЕЙСТВИЕМ, которое требуют от вызывающего.
// Сведи любые две в одну — и получивший отказ пойдёт делать не то:
//
//	Protected       — снять защиту у САМОГО ресурса и повторить;
//	HoldsChildren   — удалить ДЕТЕЙ, которых ресурс держит, и повторить;
//	ReferredTo      — отцепить или перенацелить ЧУЖИЕ ссылки и повторить;
//	ReferredUnnamed — зависимые есть, вид не назван: перечислить самому.
//
// ТРИ ПОСЛЕДНИЕ ДЕЛЯТ ОДИН ТОКЕН, и это решение, а не экономия. Токен
// `REFERENCE_IN_USE` уже есть у службы доступа и уже разобран консолью; тот же
// факт обязан называться тем же именем в обоих продуктах. Различие видов ссылки
// доезжает МЕТАДАННЫМИ — `reference_kind` — и потому не требует от клиента
// второй таблицы токенов: читающий только токен продолжает работать, читающий
// метаданные получает больше.
//
// Различие children и referrers несущее, а не косметическое: в первом случае
// блокирующие строки принадлежат вызывающему и снимаются им, во втором — могут
// принадлежать другому владельцу, и «просто удали их» неисполнимо. Unnamed — не
// оттенок, а честное «не знаю который»: он приходит с запасного пути, где отказ
// вынесла БД по `FK ... ON DELETE RESTRICT`, а перечислить блокирующие строки не
// удалось. Обещать по нему перечень было бы неправдой.
//
// Токены ниже — МАШИННЫЙ ПРИЗНАК ПОЛОСЫ ОТКАЗА, уезжающий клиенту в деталях
// ответа, а не секрет. Директива подавления здесь стояла и СНЯТА: гейт предмета
// показал, что она не подавляет ничего — правило по этой координате не
// срабатывает. Послабление, пережившее свой предмет, читается следующим как
// принятое решение, которого никто не принимал.
//
// Вернётся находка — вернётся и директива, но уже со своим предметом.
var (
	// Protected — у ресурса поднята защита от удаления. Зависимых нет ни одного,
	// и потому вид ссылки пуст: писать сюда значение значило бы назвать ссылку,
	// которой не существует.
	Protected = Lane{token: "DELETION_PROTECTED"}

	// HoldsChildren — контейнер держит СВОИ дочерние ресурсы.
	HoldsChildren = Lane{token: "REFERENCE_IN_USE", refKind: "children"}

	// ReferredTo — на ресурс ссылаются ЧУЖИЕ: он лист, а не контейнер.
	ReferredTo = Lane{token: "REFERENCE_IN_USE", refKind: "referrers"}

	// ReferredUnnamed — зависимые ресурсы есть, вид и перечень не названы.
	ReferredUnnamed = Lane{token: "REFERENCE_IN_USE", refKind: "unnamed"}
)

// AllLanes возвращает словарь целиком.
//
// Нужен проверкам, утверждающим свойство НАБОРА (закрытость, отсутствие дублей,
// наличие производителя у каждой полосы), — без него они перечисляли бы полосы
// вручную и молчали бы ровно о той, которую забыли дописать.
func AllLanes() []Lane { return []Lane{Protected, HoldsChildren, ReferredTo, ReferredUnnamed} }

// Token — признак полосы, как он уезжает в google.rpc.ErrorInfo.reason.
func (l Lane) Token() string { return l.token }

// ReferenceKind — вид ссылки, удержавшей снятие, как он уезжает в
// `ErrorInfo.metadata["reference_kind"]`. Пусто означает «ссылок нет вовсе», и
// пустым в метаданные не едет: ключ с пустым значением читается как «вид известен
// и пуст».
func (l Lane) ReferenceKind() string { return l.refKind }

// String — реализация fmt.Stringer, чтобы полоса читалась в журнале именем, а не
// раскладкой структуры. Вид ссылки печатается рядом: три полосы делят один
// токен, и по токену их в журнале не различить.
func (l Lane) String() string {
	if l.refKind == "" {
		return l.token
	}
	return l.token + "/" + l.refKind
}

// IsDeclared отличает полосу словаря от нулевого значения типа. Нулевое значение
// собрать можно (`var l Lane`) — Go этого не запрещает; значимо то, что оно НЕ
// выдаёт себя за полосу контракта.
func (l Lane) IsDeclared() bool { return l.token != "" }

// Ref — координата ресурса, о котором отказ.
//
// Service — имя сервиса-источника («vpc»), из которого собирается
// `ErrorInfo.domain` вида "<service>.kacho.cloud". Производитель в слое
// репозитория своего домена обычно не знает, поэтому оставляет поле пустым, а
// подставляет его классификатор сервиса — там, где домен объявлен однажды.
//
// ResourceID пуст там, где отказ намеренно не подтверждает существование
// названного ресурса. Пустое значение НЕ едет в метаданные пустой строкой: ключ
// с пустым значением читается как «идентификатор известен и пуст», то есть
// сообщает ровно то, что скрытие и должно было закрыть.
type Ref struct {
	Service      string
	ResourceType string
	ResourceID   string
}

// laned — отказ, несущий полосу. Не экспортируется: снаружи его собирают
// конструкторами, и это единственный способ завести полосу на ошибке.
type laned struct {
	lane Lane
	ref  Ref
	err  error
}

// Error отдаёт текст обёрнутого отказа ДОСЛОВНО.
//
// Полоса текста не меняет и не дополняет: тон — часть контракта и принадлежит
// производителю. Обёртка, добавляющая к сообщению хоть слово, сдвинула бы все
// утверждения о тексте разом — и сдвинула бы молча, потому что каждое из них по
// отдельности осталось бы защитимым.
func (e *laned) Error() string { return e.err.Error() }

// Unwrap оставляет отказ прозрачным для errors.Is: классификация сервиса
// по-прежнему видит sentinel под полосой и по-прежнему выбирает код.
func (e *laned) Unwrap() error { return e.err }

// Wrap помечает отказ полосой, не трогая ни его текст, ни его sentinel.
//
// Возвращает err как есть, если полоса не объявлена либо ошибки нет: помеченный
// ничем отказ не вправе притвориться помеченным.
func Wrap(lane Lane, ref Ref, err error) error {
	if err == nil || !lane.IsDeclared() {
		return err
	}
	return &laned{lane: lane, ref: ref, err: err}
}

// LaneOf достаёт полосу из цепочки ошибок; ok=false — полосы нет.
func LaneOf(err error) (Lane, Ref, bool) {
	var l *laned
	if err != nil && errors.As(err, &l) {
		return l.lane, l.ref, true
	}
	return Lane{}, Ref{}, false
}

// Errf собирает отказ этой полосы сразу статусом — для синхронной предпроверки
// use-case'а, которая классификацию репозитория не проходит вовсе.
//
// Проза НЕ выводится из полосы и не дополняется ею: тексты — часть контракта
// Kachō и принадлежат вызывающему. Полоса добавляет к сказанному только машинный
// признак. Детали не влияют на HTTP-статус края (grpc-gateway отображает по
// КОДУ), поэтому постановка признака ничего не ломает у REST-клиента.
func (l Lane) Errf(ref Ref, format string, a ...any) error {
	return statusWithLane(l, ref, Code, fmt.Sprintf(format, a...))
}

// Attach приклеивает признак к уже классифицированному отказу.
//
// Зовётся классификатором сервиса ПОСЛЕ того, как код и текст выбраны: полосу
// называет производитель, код — классификация, и ни одна из двух половин не
// переопределяет другую. ok=false означает «полосы на этом отказе нет» и передаёт
// разбор дальше по общему пути.
//
// ПРЕДЕЛ, НАЗВАННЫЙ ПРЯМО: пара «полоса + код» здесь не сверяется. Полоса,
// наклеенная производителем на sentinel НЕ предусловия, уехала бы с чужим кодом —
// и Attach этого не заметит, потому что код ему передают готовым. Свойство
// держится гейтом дерева, требующим, чтобы всякий вызов Wrap оборачивал sentinel
// предусловия; здесь оно не проверяется намеренно, иначе у него стало бы два
// владельца.
func Attach(err error, fallback Ref, code codes.Code, message string) (error, bool) {
	lane, ref, ok := LaneOf(err)
	if !ok {
		return nil, false
	}
	if ref.Service == "" {
		ref.Service = fallback.Service
	}
	if ref.ResourceType == "" {
		ref.ResourceType = fallback.ResourceType
	}
	if ref.ResourceID == "" {
		ref.ResourceID = fallback.ResourceID
	}
	return statusWithLane(lane, ref, code, message), true
}

// statusWithLane — единственное место, где признак кладётся в детали ответа.
// Оба входа (синхронная предпроверка и классификация репозитория) идут через
// него, чтобы «отказ на публичном слушателе» и «тот же отказ на внутреннем» не
// разошлись формой признака.
func statusWithLane(lane Lane, ref Ref, code codes.Code, message string) error {
	st := status.New(code, message)
	meta := map[string]string{}
	if lane.refKind != "" {
		meta["reference_kind"] = lane.refKind
	}
	if ref.ResourceType != "" {
		meta["resource_type"] = ref.ResourceType
	}
	if ref.ResourceID != "" {
		meta["resource_id"] = ref.ResourceID
	}
	withDetails, derr := st.WithDetails(&errdetails.ErrorInfo{
		Reason:   lane.token,
		Domain:   ref.Service + ".kacho.cloud",
		Metadata: meta,
	})
	if derr != nil {
		// Деталь не прикрепилась — код и текст важнее признака.
		return st.Err()
	}
	return withDetails.Err()
}
