package provider

import (
	"strings"
	"testing"
)

// Описание атрибута — клиентская поверхность: его читают в справочнике провайдера и
// в подсказке редактора. Оно обязано говорить, что делает ПРОВАЙДЕР, и не отрицать
// возможность, которая у края ЕСТЬ.
//
// Наблюдалось (#1646): описание `repository` утверждало «Переименования у края нет»,
// при том что `RenameRepository` объявлен контрактом, реализован, публично
// маршрутизируется и покрыт пробами. Цена не в неточности, а в необратимости:
// поверивший этой строке не станет искать переименование и снесёт репозиторий вместе
// со всем содержимым — при том что край умеет перенести его без потерь.
//
// Утверждения парные намеренно. Одно отрицание («фразы нет») зеленело бы на пустом
// описании, то есть ровно там, где клиент не узнаёт вообще ничего.
func TestRepositorySchema_NameDescribesTheProviderAndDoesNotDenyTheEdge(t *testing.T) {
	s := schemaOf(t, NewRegistryRepositoryResource())

	attr, ok := s.Attributes["repository"]
	if !ok {
		t.Fatal("атрибута repository нет вовсе — описывать нечего, и остальные утверждения вакуумны")
	}
	desc := attr.GetMarkdownDescription()
	if strings.TrimSpace(desc) == "" {
		t.Fatal("описание repository пусто — отрицание ниже прошло бы на пустой строке")
	}

	// Отрицания края, наблюдавшиеся дословно и запрещённые впредь.
	for _, denial := range []string{
		"Переименования у края нет",
		"переименования у края нет",
		"край не поддерживает переименование",
	} {
		if strings.Contains(desc, denial) {
			t.Errorf("описание repository отрицает переименование у края (%q), "+
				"а RenameRepository объявлен контрактом и реализован", denial)
		}
	}

	// Что делает провайдер — свойство ПРОВАЙДЕРА, и оно обязано быть названо.
	if !strings.Contains(desc, "пересозда") {
		t.Error("описание repository не говорит, что смена имени ПЕРЕСОЗДАЁТ ресурс, — " +
			"клиент читает разрушительное действие как переименование")
	}

	// Следующий шаг клиента: непересоздающий путь у края существует и назван.
	if !strings.Contains(desc, ":rename") {
		t.Error("описание repository не называет `:rename` — клиенту, которому нельзя " +
			"терять содержимое, не с чего начать")
	}
}
