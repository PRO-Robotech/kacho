// Package terraform — корень отдельного Go-модуля Terraform-провайдера Kachō.
//
// # Почему модуль отдельный
//
// Провайдер тянет за собой дерево зависимостей terraform-plugin-framework. В едином
// модуле продукта оно вошло бы в граф КАЖДОГО сервиса и каждой сборки образа: выросли бы
// время сборки, поверхность анализа уязвимостей и объём файла сумм. На момент заведения
// модуля корневой go.sum не содержал ни одной строки hashicorp — и гейт
// TestProviderModuleIsIsolated (internal/repohygiene/artifactgates) держит это свойство,
// а не обещание.
//
// Модуль НЕ импортирует модуль продукта. Типы запросов приезжают вторым выходом генерации
// из общего каталога proto в internal/api — только message-типы, без gRPC- и
// gateway-стабов. Отсюда следует, что require на продукт не нужен, а значит не нужен и
// replace, который топология запрещает.
//
// # Что здесь НЕ лежит
//
// Оснастка, судящая изоляцию, живёт в модуле ПРОДУКТА. Гейт внутри этого модуля исчез бы
// вместе с тем изменением, которое он запрещает, и вдобавок читал бы не тот файл сумм:
// резолвер корня поднимается до ближайшего каталога с go.mod, а здесь это сам terraform.
//
// # Где контракт
//
// Приёмка под-фазы TF-1 в репозитории kacho-workspace, docs/specs — 41 сценарий, включая
// три свойства края, которые ломают наивный провайдер: ответ «не найдено» при отказе в
// доступе побайтово равен настоящему отсутствию; ключа идемпотентности в контракте нет;
// мутации асинхронны, а идентификатор в метаданных операции присутствует даже у
// завершившейся отказом.
