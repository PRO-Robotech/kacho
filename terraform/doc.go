// Package terraform — Terraform-провайдер Kachō: часть монорепо и того же Go-модуля,
// что и сервисы.
//
// # Почему в общем модуле, а не отдельным
//
// Отдельный модуль обосновывался тем, что дерево terraform-plugin-framework войдёт в граф
// каждого сервиса. Довод перемерен, и он не подтвердился: пакеты провайдера не импортируются
// ни одним cmd продукта, поэтому в бинарники они не попадают by construction, а go.sum вырос
// на несколько десятков строк. Плата за отдельный модуль оказалась выше: собственный файл
// сумм со своим сроком годности, вторая генерация тех же типов из общего каталога proto и
// оснастка, судящая изоляцию, которая живёт не там, где предмет.
//
// Взамен провайдер пользуется тем же фундаментом, что сервисы: pkg/api (типы запросов —
// те же, что у сервера, поэтому опечатка в имени поля не проходит молча), pkg/backoff
// (ожидание операции), pkg/ids (проверка формы идентификатора при импорте).
//
// # Три свойства края, которые ломают наивный провайдер
//
// Мутации асинхронны: край отвечает операцией, идентификатор ресурса лежит в её метаданных
// и присутствует ДАЖЕ у операции, завершившейся отказом, — поэтому читать метаданные можно
// только после проверки поля ошибки. Ответ «не найдено» при отказе в доступе побайтово равен
// настоящему отсутствию — поэтому исчезновение ресурса подтверждается отдельным запросом к
// списку, а не выводится из одного 404. Ключа идемпотентности в контракте нет — повтор
// создания после разорванного соединения даёт второй ресурс, и это названо в документации,
// а не спрятано.
//
// # Где контракт
//
