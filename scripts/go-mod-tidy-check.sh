# go-mod-tidy-check.sh — сверка объявления КАЖДОГО модуля Go с фактическим
# графом импортов: `go mod tidy` не должен менять ни go.mod, ни go.sum.
#
# ЧТО ЭТО ЛОВИТ. Объявленная классификация зависимости расходится с тем, что
# дерево реально импортирует: прямая уезжает в косвенные, косвенная — обратно,
# в go.sum остаются хэши снятой версии. Дрейф не собирает ни одной жалобы —
# сборка, vet и пробы на нём зелены, — поэтому копится молча.
#
# ПОЧЕМУ ЭТО ВООБЩЕ ПРЕДМЕТ, А НЕ ПЕДАНТИЗМ. Пока гейта нет, ВСЯКИЙ, кому
# понадобится `tidy` по своему делу, потащит в свой дифф чужую правку
# классификации — то есть чужой предмет в своей линии. Вердикт такой ветки
# перестаёт быть прослеживаемым: по диффу не видно, где работа автора, а где
# накопленное до него. Обнаружен дрейф был побочно (#2437) — только потому, что
# подъём версии всё равно требовал `tidy`, чтобы вычистить из go.sum хэши снятой
# версии. Без такого повода он остался бы невидим.
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ СКРИПТ, А НЕ БЛОК `run:` В WORKFLOW. Шаг `run:` исполняется
# под `bash -e`: ненулевой код любой команды обрывает шаг МОЛЧА, до любой
# развилки ниже. Здесь код возврата `go mod tidy` — ДАННЫЕ, а не вердикт: он
# ненулевой и когда дрейфа нет вовсе, а модуль просто не удалось достать. Такая
# логика внутри шага не выражается. Плюс скрипт зовётся локально — вердикт
# конвейера перестаёт быть невоспроизводимым.
#
# ПЕРЕЧЕНЬ МОДУЛЕЙ ВЫВОДИТСЯ ИЗ ИНДЕКСА git, А НЕ ВЫПИСЫВАЕТСЯ. Тем же приёмом,
# каким это уже сделано для gosec (`scripts/gosec-scan-modules.sh`): выписанный
# список разошёлся бы с деревом молча, и в этом репозитории такое уже стоило
# слепой зоны на половину дерева — скан шёл одной командой `./...` из корня, а
# `./...` во вложенный модуль не спускается by construction. Новый модуль
# попадает под сверку тем же коммитом, которым заводится.
#
# ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА:
#   0 — дрейфа нет; перепись напечатана;
#   1 — ДРЕЙФ: назван модуль и показан дифф;
#   2 — НЕ ВЫПОЛНЕНО: обход пуст, тулчейна нет, модули не достать. Вердикта нет
#       НИ ПО ОДНОМУ модулю, включая те, что успели пройти, — подавать это
#       красным значит посылать читателя искать поломку в своей ветке.
#
# ПРО СЕТЬ. `go mod tidy` строит граф модулей и потому может пойти за тем, чего
# нет в кэше. В конвейере кэш греется шагами `go mod download` (оба модуля) до
# этой сверки, поэтому штатно обращения к сети не требуется. Если оно всё же
# случилось и не удалось — это ТРЕТЬЯ КАТЕГОРИЯ, а не находка: дрейф не
# измерялся. Признак берётся из текста самого инструмента и держится узким —
# широкий превратил бы защиту от ложного красного в маску, глотающую настоящие
# находки, а это дороже той беды, которую он лечит.
#
# ДЕРЕВО ОСТАЁТСЯ КАК БЫЛО. `tidy` правит файлы на месте, поэтому go.mod и go.sum
# сохраняются до прогона и возвращаются после — включая аварийный выход. Гейт,
# оставляющий за собой правку, сам стал бы источником того дрейфа, который ловит.
#
# РЕЖИМ `--list-modules` печатает только перечень каталогов модулей и выходит.
# Он существует для доказательства: инъекция сверяет вывод с деревом и падает,
# если перечень перестал выводиться. Без такого режима «список выводится из
# дерева» осталось бы обещанием, а не проверяемым свойством.

set -uo pipefail

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "go-mod-tidy-check: вне git-дерева — перечень модулей выводить не из чего" >&2
    exit 2
}

list_modules() {
    git -C "$ROOT" ls-files '*go.mod' | while read -r f; do
        dirname "$f"
    done | sort -u
}

if [ "${1:-}" = "--list-modules" ]; then
    list_modules
    exit 0
fi

GO_BIN=${GO_BIN:-go}
if ! command -v "$GO_BIN" > /dev/null 2>&1; then
    echo "НЕ ВЫПОЛНЕНО: исполняемого go нет в PATH — сверка не запускалась"
    exit 2
fi

mapfile -t MODULES < <(list_modules)
if [ "${#MODULES[@]}" -eq 0 ]; then
    # Пустой обход — НЕ «дрейфа нет». Он означает, что предмета не нашли вовсе,
    # и зелёное здесь было бы формой без содержания.
    echo "НЕ ВЫПОЛНЕНО: в дереве не нашлось ни одного go.mod — обход пуст, судить не о чем"
    exit 2
fi

# Признаки НЕДОСТУПНОСТИ ИСТОЧНИКА МОДУЛЕЙ. Каждый — из текста инструмента, и
# каждый про транспорт, а не про содержимое дерева: сломанный импорт роняет
# `go build` в той же джобе и находкой этого гейта быть не обязан.
NET_SIGNS='dial tcp|no such host|connection refused|i/o timeout|TLS handshake timeout|proxy.golang.org|module lookup disabled|Get "https://|network is unreachable|certificate signed by unknown'

drift=()
undone=()
census=()

for mod in "${MODULES[@]}"; do
    dir="$ROOT/$mod"
    gomod="$dir/go.mod"
    gosum="$dir/go.sum"
    [ -f "$gomod" ] || { undone+=("$mod (go.mod по индексу есть, на диске нет)"); continue; }

    bak=$(mktemp -d)
    cp "$gomod" "$bak/go.mod"
    # ОТСУТСТВИЕ go.sum — ПЕРВОКЛАССНОЕ ЗНАЧЕНИЕ, А НЕ ПОВОД ПРОПУСТИТЬ СВЕРКУ.
    # Модуль без внешних зависимостей законно живёт без go.sum. Кодировать это
    # пропуском сравнения нельзя: сверка, исполняемая ПО НАЛИЧИЮ ФАЙЛА, с того
    # дня, как файл исчезнет, не сверяет НИЧЕГО — а цель остаётся зелёной и
    # неотличимой от исправной. Поэтому отсутствие представляется ПУСТЫМ файлом,
    # и сравнение идёт всегда. (Класс держит гейт дерева
    # `TestNoRecipeOrScriptRunsAComparisonOnlyIfAFileExists`, который поймал ровно
    # это в первой редакции скрипта.)
    had_sum=0
    : > "$bak/go.sum"
    if [ -f "$gosum" ]; then had_sum=1; cp "$gosum" "$bak/go.sum"; fi

    restore() {
        cp "$bak/go.mod" "$gomod"
        if [ "$had_sum" = 1 ]; then cp "$bak/go.sum" "$gosum"; else rm -f "$gosum"; fi
        rm -rf "$bak"
    }
    # Возврат дерева обязан случиться и при обрыве: гейт, оставляющий правку,
    # сам становится источником дрейфа.
    trap 'restore' EXIT INT TERM

    log=$(mktemp)
    rc=0
    ( cd "$dir" && "$GO_BIN" mod tidy ) > "$log" 2>&1 || rc=$?

    if [ "$rc" -ne 0 ]; then
        if grep -qE "$NET_SIGNS" "$log"; then
            undone+=("$mod (источник модулей недоступен)")
        else
            undone+=("$mod (go mod tidy отказал, код $rc)")
        fi
        echo "── модуль $mod: tidy НЕ СОСТОЯЛСЯ (код $rc)"
        sed 's/^/   | /' "$log" | head -20
        rm -f "$log"; trap - EXIT INT TERM; restore
        continue
    fi
    rm -f "$log"

    # Сверяются ОБА файла: go.sum несёт хэши, и оставшийся там хэш снятой версии
    # — тот же дрейф, только невидимый в go.mod.
    d=""
    diff -u "$bak/go.mod" "$gomod" > /dev/null 2>&1 || d="go.mod"
    # Состояние go.sum ПОСЛЕ tidy приводится к тому же виду, что и до: отсутствие
    # есть пустой файл. Оба сравнения ниже безусловны — сверять всегда есть что.
    : > "$bak/go.sum.after"
    if [ -f "$gosum" ]; then cp "$gosum" "$bak/go.sum.after"; fi
    diff -u "$bak/go.sum" "$bak/go.sum.after" > /dev/null 2>&1 || d="${d:+$d, }go.sum"

    if [ -n "$d" ]; then
        echo "── модуль $mod: ДРЕЙФ в $d"
        diff -u "$bak/go.mod" "$gomod" | sed 's/^/   | /' | head -40
        sumlines=$(diff -u "$bak/go.sum" "$bak/go.sum.after" | grep -c '^[+-][^+-]')
        if [ "$sumlines" -gt 0 ]; then
            echo "   | go.sum: $sumlines строк(и) различий"
        fi
        drift+=("$mod ($d)")
    fi

    census+=("$mod")
    trap - EXIT INT TERM
    restore
done

echo "=============================================================="
echo "ПЕРЕПИСЬ: модулей в дереве ${#MODULES[@]} | сверено ${#census[@]} | с дрейфом ${#drift[@]} | не выполнено ${#undone[@]}"
[ "${#census[@]}" -gt 0 ] && echo "   сверены: ${census[*]}"

if [ "${#undone[@]}" -gt 0 ]; then
    printf '   НЕ ВЫПОЛНЕНО: %s\n' "${undone[@]}"
fi

# ПОРЯДОК ИСХОДОВ. Находка объявляется РАНЬШЕ несостоявшегося: прогон, где есть
# и то и другое, обязан остаться красным — иначе третья категория стала бы
# маской для настоящего дрейфа.
if [ "${#drift[@]}" -gt 0 ]; then
    printf '   ДРЕЙФ: %s\n' "${drift[@]}"
    echo "Почини: go mod tidy в названном модуле, и закоммить go.mod/go.sum ОТДЕЛЬНО от своего предмета."
    exit 1
fi

if [ "${#undone[@]}" -gt 0 ]; then
    echo "Вердикта нет ни по одному модулю: это НЕ «дрейфа нет»."
    exit 2
fi

echo "дрейфа нет: объявление обоих модулей сходится с графом импортов"
exit 0
