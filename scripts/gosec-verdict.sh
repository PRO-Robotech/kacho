# gosec-verdict.sh — вердикт по отчёту, который оставил `gosec-scan-modules.sh`.
#
# ИСХОДОВ ТРИ, И КАЖДЫЙ ИМЕЕТ СВОЙ КОД (#2125, #958).
#
#   0  зелено          — отчёт есть, разобран, перепись снята, находок нет;
#   1  красное         — находки level=error;
#   3  НЕ ВЫПОЛНИЛОСЬ  — анализа не было или он неполон: метка отказа, отчёта
#                        нет, отчёт не разбирается, перепись пуста, модуль
#                        дерева в перепись не попал.
#
# ЗДЕСЬ СТОЯЛО ДВА КОДА НА ТРИ ИСХОДА, и различие жило ТОЛЬКО в тексте отказа.
# Текст читает человек; код читает конвейер — и для него «не смотрели» было
# неотличимо от «нашли». Разбор уходил не туда: лечатся эти два состояния
# противоположным.
#
# ОТОБРАЖЕНИЕ ТРЕТЬЕЙ КАТЕГОРИИ В ЦВЕТ — РЕШЕНИЕ ВЫЗЫВАЮЩЕГО, А НЕ УМОЛЧАНИЕ
# ЭТОГО СКРИПТА. В конвейере безопасности оно объявлено прямо в шаге
# (`security-scan.yml`): непроверенное дерево гейт безопасности не проходит,
# поэтому код 3 там отображается в отказ — с причиной, а не молча. Другой
# вызывающий вправе объявить другое отображение; чего он не вправе — принять
# третью категорию за зелёное.
#
# ПОЧЕМУ ВЕРДИКТ ЧИТАЕТ ПЕРЕПИСЬ РАНЬШЕ ЧИСЛА НАХОДОК. Отчёт на дереве, которое
# сканер не смог собрать, побайтово такой же, как на чистом: пустой список
# результатов, валидный JSON, тот же код возврата. То есть отказ анализа
# выглядит ровно как чистота. Отличить их можно ТОЛЬКО по объёму осмотренного.
#
# ПОЧЕМУ СВЕРКА С ДЕРЕВОМ ИДЁТ ЗАНОВО, А НЕ ПО СЛОВУ СКАНИРУЮЩЕГО. Перечень
# осмотренных модулей берётся из переписи, а перечень ОБЯЗАННЫХ быть
# осмотренными — из индекса git, здесь и сейчас. Это два независимых чтения
# одного предмета: если бы вердикт верил переписи на слово, модуль, вылетевший
# из скана, вылетел бы и из вердикта — и оба были бы уверены в своей правоте.
#
# ПОРОГ — SARIF `level == "error"`, А НЕ `severity == HIGH` в JSON-выводе. Это
# РАЗНЫЕ предикаты: правило приходило MEDIUM в JSON и error в SARIF, из-за чего
# локальная проверка «severity HIGH» показывала ноль, пока конвейер честно
# краснел. Сверяться надо именно по SARIF.
#
# ФЛАГА `-tests` У СКАНА НЕТ — И ЭТО РЕШЕНИЕ, А НЕ НЕДОСМОТР. Без него сканер не
# читает *_test.go вовсе. Умолчание защитимо: пробы не поставляются,
# эксплуатируемой в проде поверхности в них не бывает, а харнесс по своей природе
# делает ровно то, на что правила и срабатывают — ходит по дереву репозитория,
# поднимает докер, берёт самоподписанный сертификат.
#
# ЗАМЕРЕНО, А НЕ ПРИКИНУТО (пин v2.28.0, 2026-07-28, КОРНЕВОЙ модуль — второго
# тогда ещё не было): включение даёт 132 находки level=error против нынешних 0.
# По правилам: G304 40 · G101 33 · G115 15 · G204 7 · G122 6 · G401 5 · G306 5 ·
# G301 5 · G124 5 · G501 4 · G403 2 · G705/G703/G402/G302/G112 по 1. Все 132 — в
# *_test.go: ни одной находки в прод-коде включение не открывает. То есть
# выключенный флаг сегодня НЕ прячет ни одного прод-дефекта. Число относится к
# одному модулю и к своей дате; перемеряй его, а не цитируй.
#
# Включить молча нельзя: это мгновенно красный гейт на 132 позиции, и «починка»
# свелась бы к 132 подавлениям — воспроизводству ровно того класса, который
# отсюда убирали. Включать — только ОТДЕЛЬНЫМ заданием со СВОИМ порогом
# (не блокирующим, только SARIF в Security-tab): смешать прод-поверхность и
# харнесс в одном пороге значит обесценить прод-порог.

set -uo pipefail

NOT_EXECUTED=3

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "::error::gosec-verdict: вне git-дерева — перечень модулей сверять не с чем"
    exit "$NOT_EXECUTED"
}

GOSEC_OUT=${GOSEC_OUT:-"$PWD"}
CENSUS="$GOSEC_OUT/gosec-census.txt"
MERGED="$GOSEC_OUT/gosec.sarif"
FAILED="$GOSEC_OUT/gosec-scan-failed"

# Отказ ПО НАХОДКЕ — код 1. Отказ «вердикта нет» — код 3. Различает их не текст,
# а то, чем судили: содержимым отчёта или его отсутствием.
die() {
    while [ "$#" -gt 0 ]; do echo "::error::$1"; shift; done
    exit 1
}
unexecuted() {
    echo "::error::НЕ ВЫПОЛНИЛОСЬ — вердикта о дереве нет:"
    while [ "$#" -gt 0 ]; do echo "::error::  $1"; shift; done
    exit "$NOT_EXECUTED"
}

if [ -f "$FAILED" ]; then
    echo "gosec не завершил анализ:"
    sed 's/^/  | /' "$FAILED"
    unexecuted "gosec не завершил анализ (причины выше). Ноль находок здесь означает" \
        "«не сканировали», а не «чисто» — вердикт не выносится."
fi
[ -f "$MERGED" ] || unexecuted "отчёта gosec.sarif нет — скан не оставил результата. Судить не о чем."
jq -e . "$MERGED" > /dev/null 2>&1 || unexecuted "gosec.sarif не разбирается — судить не о чем."
[ -s "$CENSUS" ] || unexecuted "переписи осмотренного нет — без неё ноль находок ничего не означает."

# ── ПЕРЕПИСЬ ОСМОТРЕННОГО ────────────────────────────────────────────────────
scanned=0
total_files=0
total_lines=0
echo "осмотрено модулей:"
while read -r mod files lines; do
    [ -n "$mod" ] || continue
    scanned=$((scanned + 1))
    total_files=$((total_files + files))
    total_lines=$((total_lines + lines))
    printf '  %-24s файлов=%s строк=%s\n' "$mod" "$files" "$lines"
    if [ "$files" -eq 0 ]; then
        unexecuted "модуль $mod: прочитано 0 файлов. Пустой обход не является чистым деревом."
    fi
done < "$CENSUS"
echo "итого: модулей $scanned, файлов $total_files, строк $total_lines"

if [ "$scanned" -eq 0 ]; then
    unexecuted "перепись пуста — ни один модуль не осмотрен. Это отказ, а не чистота."
fi

# ── КАЖДЫЙ МОДУЛЬ ДЕРЕВА ОБЯЗАН БЫТЬ В ПЕРЕПИСИ ──────────────────────────────
# Второе, независимое чтение того же предмета. Модуль, не попавший под скан,
# роняет прогон: молчаливый пропуск половины дерева — ровно тот дефект, ради
# которого этот блок и существует.
missing=""
while read -r want; do
    [ -n "$want" ] || continue
    if ! awk -v m="$want" '$1 == m {found = 1} END {exit !found}' "$CENSUS"; then
        missing="$missing $want"
    fi
done < <(git -C "$ROOT" ls-files '*go.mod' | while read -r f; do dirname "$f"; done | sort -u)

if [ -n "$missing" ]; then
    unexecuted "модули Go, которых нет в переписи осмотренного:$missing." \
        "Скан их не читал — значит гейт по ним ничего не утверждает," \
        "а зелёное здесь означало бы «не смотрели», а не «чисто»."
fi

# ── НАХОДКИ ──────────────────────────────────────────────────────────────────
err=$(jq '[.runs[].results[] | select(.level == "error")] | length' "$MERGED")
total=$(jq '[.runs[].results[]] | length' "$MERGED")
echo "результатов всего: $total; из них level=error: $err"
if [ "$err" -gt 0 ]; then
    # С ПУТЁМ И СТРОКОЙ: без них лог даёт лишь имя правила на тысячу файлов, и
    # находку приходится искать вручную.
    jq -r '.runs[].results[] | select(.level == "error")
           | "- \(.ruleId) \(.locations[0].physicalLocation.artifactLocation.uri):\(.locations[0].physicalLocation.region.startLine) — \(.message.text)"' "$MERGED"
    die "gosec нашёл $err проблем level=error. См. вкладку Security." \
        "Исходы: починить по существу ЛИБО освободить записью с причиной там, где её" \
        'читает инструмент: // #nosec ПРАВИЛО -- причина. Форма //nolint:gosec здесь' \
        "не подавляет НИЧЕГО: gosec её не разбирает."
fi
exit 0
