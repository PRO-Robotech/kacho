# Набор групп локального прогона для отправляемой ветки — ОТДЕЛЬНЫМ
# производителем, а не выражением внутри хука.
#
# ЗАЧЕМ ОТДЕЛЬНО. Вычисление набора — это решение («вердикт о консоли нужен»),
# и оно ошибалось молча: хук требовал проверок консоли у линии, не касавшейся
# её ни одним своим коммитом. Пока выражение жило внутри хука, проверить его
# было можно только полной отправкой — то есть двадцатиминутным прогоном, после
# которого ответ всё равно смешан с вердиктом самих проверок.
#
# Отдельный производитель печатает набор и завершается. Его можно позвать на
# синтетическом репозитории и потребовать обе стороны: добавляет группу там,
# где предмет есть, и НЕ добавляет там, где его нет. Это и делает
# prepush-groups-inject.sh.
#
# БАЗА — ТО, ЧТО ОТПРАВЛЯЕТ ЭТА ОТПРАВКА, и её называет сам git.
#
# Диапазон приходит переменной `KACHO_PUSH_RANGE`: хук читает его из данных,
# которые git передаёт на вход (`<local_ref> <local_sha> <remote_ref>
# <remote_sha>`), и это авторитетный ответ на вопрос «что уедет».
#
# Прежняя редакция брала точку ветвления от ствола. Для ветки задачи это то же
# самое, а для НАКОПИТЕЛЬНОЙ релизной — нет: она несёт работу нескольких линий,
# поэтому «добавляет к стволу» включает чужие коммиты. Следствие измерено:
# коммит, тронувший четыре файла проб iam, отвергался требованием проверок
# консоли — потому что консоль трогала другая линия неделей раньше. Обход
# (`--no-verify`) становился обязательным на КАЖДОЙ отправке, а обход, который
# делают всегда, перестаёт быть заметным — то есть гейт вырождался в привычку.
#
# Предмет хука — не «вся ветка когда-нибудь окажется верна», а «ТВОЯ правка не
# уедет непроверенной». Работа соседей свой вердикт получает своими отправками
# и конвейером запроса на слияние.
#
# Если диапазон не задан (хук позвали руками, git ничего не передал), база
# остаётся прежней — точкой ветвления от ствола: лучше прогнать лишнее, чем
# пропустить непроверенное.
set -uo pipefail

trunk="${KACHO_TRUNK_REF:-origin/main}"
groups="${KACHO_PREPUSH_GROUP:-proto go}"

# Явно заданный набор сильнее вывода: тот, кто назвал группы, знает, что делает.
if [ -n "${KACHO_PREPUSH_GROUP:-}" ]; then
    printf '%s\n' "$groups"
    exit 0
fi

# Ствол может не резолвиться (свежий клон без origin, отвязанная копия). Тогда
# набор НЕ сужается: лучше прогнать лишнее, чем пропустить непроверенное.
if ! git rev-parse --verify --quiet "$trunk" > /dev/null; then
    printf '%s\n' "$groups"
    exit 0
fi

if [ -n "${KACHO_PUSH_RANGE:-}" ]; then
    # Диапазонов может быть несколько (git push отправляет несколько ссылок за раз).
    changed=""
    for range in $KACHO_PUSH_RANGE; do
        changed="$changed
$(git diff --name-only "$range" 2> /dev/null || true)"
    done
else
    changed="$(git diff --name-only "$trunk"...HEAD 2> /dev/null || true)"
fi

# Проверка типов консоли добавляется ТОЛЬКО когда тронута сама консоль.
# Не весь `ui` — пробы трёх модулей идут минуты, и хук, который столько держит,
# обойдут первым же `--no-verify`. Проверка типов — десятки секунд и ловит
# ровно тот класс, что дважды стоил круга: пробы зелёные, строгая проверка
# типов роняет линт, сборку семи модулей и образ консоли.
case "$changed" in
    *ui-future/*) groups="$groups ui-types" ;;
esac

printf '%s\n' "$groups"
