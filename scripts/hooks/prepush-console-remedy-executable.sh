# ГЕЙТ: ПРЕДПИСАНИЕ ХУКА ОТПРАВКИ ОБЯЗАНО БЫТЬ ИСПОЛНИМЫМ.
#
# ПРЕДМЕТ — не текст в файле, а ТО, ЧТО ПОЛУЧАЕТ ЧЕЛОВЕК В МОМЕНТ ОТКАЗА. Поэтому
# гейт не читает `pre-push` глазами: он поднимает синтетическое дерево, в котором
# условие проверок консоли НЕ СОЗДАНО, гонит НАСТОЯЩИЙ `scripts/hooks/pre-push` и
# судит ровно тот поток, который видит оператор, — стандартный поток ошибок.
#
# ПОЧЕМУ ЭТО ВООБЩЕ ЗАВЕДЕНО. Отказ верен по существу («не выполнено» не равно
# «зелено»), а починка, которую он предписывал, была невыполнима: печаталась
# команда `npm ci --prefix <пакет>` — с угловыми скобками вместо имени пакета, —
# и одиннадцать пропусков сводились в ОДНУ строку без координат. Человек, дословно
# скопировавший напечатанное, получал `npm error <пакет> not found`, то есть ТОТ ЖЕ
# исход. Так отказ, обязанный открывать выход, его закрывал: семь веток дневной
# работы стояли, каждая в единственном экземпляре.
#
# ТРИ НАХОДКИ, КАЖДАЯ СО СВОИМ ПРИЗНАКОМ:
#   F1 — в предписанной команде стоит заполнитель `<…>` вместо значения;
#   F2 — предписанная команда называет путь, которого нет;
#   F3 — число «не выполнено N» не сопровождается перечнем: пропуск не назван
#        своей координатой, хотя у прогонщика она была в руках;
#   F4 — предписано ставить зависимости во ВРЕМЕННУЮ выкладку отправляемой
#        ревизии. Она снимается по выходу хука: команда исполнится и исход не
#        изменит — тот же дефект, переехавший в другую ветку сообщения.
#
# ОСЕЙ ДВЕ, потому что веток сообщения две, и вторая — не косметика: когда
# рабочая копия не равна отправляемой ревизии, хук судит ВРЕМЕННУЮ выкладку, и
# предписание там обязано быть другим. Гейт, знающий только первую ветку,
# смолчал бы о неисполнимом предписании во второй.
#
# ПЕРЕПИСЬ ПЕЧАТАЕТСЯ ВСЕГДА, И ПУСТОЙ ОБХОД — ОТКАЗ: зелёный гейт, ничего не
# прочитавший, неотличим от гейта, которому нечего было читать.
#
# Способность упасть и способность смолчать доказывает
# `scripts/hooks/prepush-console-remedy-executable-inject.sh`.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HOOK="${KACHO_REMEDY_GATE_HOOK:-$ROOT/scripts/hooks/pre-push}"

if ! command -v node > /dev/null; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: node не установлен — предикат готовности пакета не выполнить" >&2
    exit 3
fi
if [ ! -x "$HOOK" ] && [ ! -f "$HOOK" ]; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: судимого хука нет — $HOOK" >&2
    exit 3
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
tree="$work/tree"

# ─────────────────────────────────────────────────────────────────────────────
# СИНТЕТИЧЕСКОЕ ДЕРЕВО: НАСТОЯЩАЯ ОСНАСТКА, ЗАВЕДОМО НЕ СОЗДАННОЕ УСЛОВИЕ
#
# Оснастка копируется, а не пишется заново: судить надо ту самую, что стоит в
# дереве. Пакеты консоли — минимальные, но ОБЕИХ форм, потому что предикат
# готовности у них разный и команда починки тоже разная: член воркспейса берёт
# зависимости из корня `ui-future`, standalone — из своего каталога. Одной формы
# не хватило бы: гейт, видевший только члена, смолчал бы о неисполнимой команде
# для standalone.
# ─────────────────────────────────────────────────────────────────────────────
mkdir -p "$tree/scripts" "$tree/ui-future/scripts" "$tree/ui-future/vpc" "$tree/ui-future/nlb"
cp -a "$ROOT/scripts/hooks" "$tree/scripts/hooks"
cp "$ROOT/scripts/ci-local.sh" "$tree/scripts/ci-local.sh"
cp "$ROOT/ui-future/scripts/deps-ready.mjs" "$tree/ui-future/scripts/deps-ready.mjs"
[ "$HOOK" = "$ROOT/scripts/hooks/pre-push" ] || cp "$HOOK" "$tree/scripts/hooks/pre-push"

cat > "$tree/ui-future/package.json" <<'JSON'
{ "name": "synthetic-console-root", "private": true, "workspaces": ["vpc"] }
JSON
cat > "$tree/ui-future/vpc/package.json" <<'JSON'
{ "name": "synthetic-vpc", "version": "0.0.0", "scripts": { "typecheck": "true" } }
JSON
cat > "$tree/ui-future/nlb/package.json" <<'JSON'
{ "name": "synthetic-nlb", "version": "0.0.0", "scripts": { "typecheck": "true" } }
JSON

(
    cd "$tree" || exit 1
    git init -q -b main
    git config user.name "gate"
    git config user.email "gate@example.invalid"
    git config commit.gpgsign false
    git add -A
    git -c core.hooksPath=/dev/null commit -q -m "основание"
    git branch -q -f trunk-for-gate
    printf '// правка консоли, ради которой хук зовёт её проверки\n' > ui-future/vpc/touched.ts
    git add -A
    git -c core.hooksPath=/dev/null commit -q -m "тронуть консоль"
) || { echo "ГЕЙТ НЕ СОСТОЯЛСЯ: синтетическое дерево не собралось" >&2; exit 3; }

tip="$(git -C "$tree" rev-parse HEAD)"

findings=0
say() { printf 'НАХОДКА [%s] %s\n' "$1" "$2" >&2; findings=$((findings + 1)); }

# Группа задаётся явно существующей ручкой: предмет — сообщение об УСЛОВИИ
# ПРОВЕРОК КОНСОЛИ, и гнать в синтетике `proto`/`go` значило бы судить отказ,
# порождённый отсутствием go-модуля, а не отсутствием зависимостей консоли.
provoke() { # provoke <куда-stdout> <куда-stderr>
    (
        cd "$tree" || exit 1
        printf 'refs/heads/gate %s refs/heads/feature/gate 0000000000000000000000000000000000000000\n' "$tip" |
            KACHO_PREPUSH_GROUP=ui-types KACHO_TRUNK_REF=trunk-for-gate \
                bash scripts/hooks/pre-push origin "file://$tree" > "$1" 2> "$2"
    )
}

# judge <ось> <stdout прогона> <stderr отказа> <ожидается ли перечень пропусков>
judge() {
    local axis="$1" out_all="$2" out_err="$3" want_names="$4"
    local named=0 p

    # F1 — ЗАПОЛНИТЕЛЬ В ПРЕДПИСАННОЙ КОМАНДЕ. Судится строка, несущая команду:
    # угловые скобки в прозе законны.
    while IFS= read -r line; do
        named=$((named + 1))
        case "$line" in
            *'<'*'>'*) say F1 "[$axis] предписана команда с заполнителем вместо значения: $line" ;;
        esac
    done < <(grep -oE '(npm ci --prefix|cd) [^ ]+' "$out_err")

    if [ "$named" -eq 0 ]; then
        say F1 "[$axis] отказ не назвал НИ ОДНОЙ исполнимой команды — предписывать нечего"
    fi

    # F2 — ПУТЬ, КОТОРОГО НЕТ. Команда без скобок всё ещё бесполезна, если
    # названный каталог не существует: «исполнимо» значит «исполнено и сработало».
    while IFS= read -r p; do
        [ -n "$p" ] || continue
        case "$p" in *'<'*) continue ;; esac   # уже названо находкой F1
        [ -d "$p" ] || say F2 "[$axis] предписанная команда называет каталог, которого нет: $p"
    done < <({
        grep -oE 'npm ci --prefix [^ ]+' "$out_err" | sed 's/.*--prefix //'
        grep -oE '(^|[[:space:]])cd [^ ]+' "$out_err" | sed 's/.*cd //'
    })

    # F3 — ЧИСЛО БЕЗ ПЕРЕЧНЯ. У прогонщика координата каждого пропуска в руках;
    # значит она обязана быть в тексте, который читает человек.
    if [ "$want_names" = "да" ]; then
        while IFS= read -r name; do
            [ -n "$name" ] || continue
            grep -qF -- "$name" "$out_err" ||
                say F3 "[$axis] пропуск «$name» не назван в отказе: число есть, координаты нет"
        done < <(sed -n 's/^== ui-types \(.*\)$/\1/p' "$out_all" | sort -u)
    fi
}

# ─── ОСЬ 1: КОПИЯ РАВНА ОТПРАВЛЯЕМОЙ РЕВИЗИИ — судится она сама ───────────────
out_all="$work/stdout-1.txt"; out_err="$work/stderr-1.txt"
provoke "$out_all" "$out_err"
hook_rc=$?
skipped_count="$(grep -c 'ПРОПУСК' "$out_all")"

# ПРЕДПОСЫЛКА. Гейт судит ОТКАЗ; если отказа не было, судить нечего — и это не
# «находок нет», а несостоявшийся прогон. Разницу надо называть вслух: иначе
# сломанная синтетика печатается как зелёный вердикт.
if [ "$hook_rc" -ne 1 ]; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: хук не отказал (код $hook_rc) — отказа, который надо судить, нет" >&2
    sed 's/^/   | /' "$out_err" >&2
    exit 3
fi
if [ "${skipped_count:-0}" -eq 0 ]; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: в синтетике не пропущено НИ ОДНОЙ проверки консоли" >&2
    exit 3
fi
judge "копия=ревизия" "$out_all" "$out_err" да

# ─── ОСЬ 2: КОПИЯ НЕ РАВНА РЕВИЗИИ — судится ВРЕМЕННАЯ ВЫКЛАДКА ───────────────
#
# Расхождение вносится неотслеживаемым файлом вне игнора: ровно то, что хук
# считает расхождением, — и он раскладывает ревизию во временную копию.
printf '// копия разошлась с отправляемой ревизией\n' > "$tree/ui-future/vpc/uncommitted.ts"
out_all2="$work/stdout-2.txt"; out_err2="$work/stderr-2.txt"
provoke "$out_all2" "$out_err2"
hook_rc2=$?
rm -f "$tree/ui-future/vpc/uncommitted.ts"

if [ "$hook_rc2" -ne 1 ]; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: на расходящейся копии хук не отказал (код $hook_rc2)" >&2
    exit 3
fi
if ! grep -q 'временной копии этой ревизии' "$out_all2"; then
    echo "ГЕЙТ НЕ СОСТОЯЛСЯ: ось временной выкладки не воспроизвелась — судить нечего" >&2
    exit 3
fi
judge "копия≠ревизия" "$out_all2" "$out_err2" нет

# F4 — ПРЕДПИСАНИЕ ВО ВРЕМЕННУЮ ВЫКЛАДКУ. Она снимается по выходу хука: такая
# команда исполнится и исход следующей отправки не изменит.
if grep -qE 'npm ci --prefix [^ ]*kacho-prepush-' "$out_err2"; then
    say F4 "[копия≠ревизия] предписано ставить во временную выкладку — она снимается по выходу"
fi

printf 'ПЕРЕПИСЬ: судим отказ хука %s; осей 2; пропущено проверок %s на первой; находок %d\n' \
    "$HOOK" "$skipped_count" "$findings"

if [ "$findings" -gt 0 ]; then
    echo "ОТКАЗ: предписание хука отправки НЕИСПОЛНИМО — находок $findings" >&2
    echo "--- текст, который получил оператор (копия=ревизия):" >&2
    sed 's/^/   | /' "$out_err" >&2
    echo "--- текст, который получил оператор (копия≠ревизия):" >&2
    sed 's/^/   | /' "$out_err2" >&2
    exit 1
fi
echo "ok: напечатанное можно скопировать и исполнить — на обеих осях"
