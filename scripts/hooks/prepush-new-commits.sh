# prepush-new-commits.sh — несёт ли отправка хоть один НОВЫЙ коммит (ws#1288).
#
# Вопрос: есть ли в отправляемых ссылках коммиты, которых нет ни в одной ветке
# удалённого. Нет ни одного — наборы хука судили бы то же дерево, что уже
# опубликовано и судилось, и их прогон (около 20 мин у монорепо) ничего не
# покупает. Класс: ветка заводится на sha, уже лежащей на origin.
#
# Вход — строки git для хука отправки на стандартном вводе
# (`<local_ref> <local_sha> <remote_ref> <remote_sha>`), первый аргумент — имя
# удалённого (не имя — любое удалённое отслеживание, строже: больше известно
# опубликованного, а не меньше).
#
# НОВЫЙ коммит — достижим из отправляемой вершины и не достижим из
# `refs/remotes/<удалённое>/*`. Слияние считается новым, если дерево отличается
# от деревьев ОБОИХ (всех) родителей: слияние с деревом родителя ничего нового
# для наборов не вносит, а догон с настоящим результатом слияния — вносит.
# Не ослабляется: обычный коммит новый всегда, пустой тоже; sha, которой нет
# среди ревизий, и ошибка rev-list — тоже «новое» (судить нечем — судить всё).
#
# Удаление ссылки (нулевой `<local_sha>`) не коммитов, а их отсутствие:
# нулём оно НЕ считается — ссылка пропускается, и отправка одних удалений
# даёт код 2 (судить нечего), а не 0.
#
# Коды: 0 — судились ссылки и новых коммитов во всех 0; 1 — новый коммит есть;
# 2 — судить нечего (вход пуст либо одни удаления). Печать — строка на ссылку и
# итог; «0 новых» отличимо от «ничего не прочитано» по коду 2.
set -uo pipefail

remote="${1:-origin}"
zero_sha="0000000000000000000000000000000000000000"
if git remote get-url "$remote" > /dev/null 2>&1; then
    sel=("--remotes=$remote")
else
    sel=(--remotes)
fi

judged=0
total=0
while read -r _lref lsha rref _rsha; do
    [ -n "${lsha:-}" ] || continue
    [ "$lsha" != "$zero_sha" ] || continue
    judged=$((judged + 1))
    new=0
    if commit="$(git rev-parse --verify -q "$lsha^{commit}")" &&
        revs="$(git rev-list --parents "$commit" --not "${sel[@]}" 2> /dev/null)"; then
        while read -r -a f; do
            [ "${#f[@]}" -gt 0 ] || continue
            if [ "${#f[@]}" -le 2 ]; then
                new=$((new + 1))
                continue
            fi
            t="$(git rev-parse "${f[0]}^{tree}")"
            same=0
            for p in "${f[@]:1}"; do
                [ "$(git rev-parse "$p^{tree}")" != "$t" ] || same=1
            done
            [ "$same" -eq 1 ] || new=$((new + 1))
        done <<< "$revs"
    else
        new=1
        echo "prepush-new-commits: «${rref:-?}» ($lsha) не разобрана — считается новой" >&2
    fi
    echo "${rref:-?} ${lsha:0:12} новых коммитов $new"
    total=$((total + new))
done
[ "$judged" -gt 0 ] || { echo "prepush-new-commits: судить нечего — вершин в отправке нет"; exit 2; }
echo "итого новых коммитов $total по ссылкам $judged"
[ "$total" -eq 0 ]
