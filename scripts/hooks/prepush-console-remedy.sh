# ПРОИЗВОДИТЕЛЬ ТЕКСТА ОТКАЗА, КОГДА ПРОВЕРКИ КОНСОЛИ НЕ ВЫПОЛНЯЛИСЬ.
#
# ОТДЕЛЬНЫМ ФАЙЛОМ ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО `prepush-groups.sh` И `prepush-range.sh`:
# это РЕШЕНИЕ, оно ошибалось молча, и проверить его выражением внутри хука можно
# было только полной отправкой. Здесь ошибка стоила дороже прочих: отказ верен по
# существу, а предписанная им починка была невыполнима — печаталось
# `npm ci --prefix <пакет>`, с угловыми скобками вместо имени, — и человек,
# дословно скопировавший напечатанное, получал тот же исход. Судья текста —
# `prepush-console-remedy-executable.sh`, он гонит настоящий хук и читает то, что
# получает оператор.
#
# ВХОД — вывод прогонщика на стандартном потоке. Координаты и КОМАНДЫ починки
# берутся ИЗ НЕГО, а не выводятся здесь заново: предикат готовности пакета живёт
# в одном месте (`ui-future/scripts/deps-ready.mjs`), прогонщик его уже спросил,
# и второй ответ на тот же вопрос разошёлся бы с первым молча.
#
# КЛЮЧИ:
#   --list                  напечатать ТОЛЬКО перечень пропусков с координатами
#   --subject-root <путь>   дерево, о котором был вердикт (может быть временной выкладкой)
#   --work-root <путь>      рабочая копия, из которой идёт отправка
#
# Перечень печатается ОДНОЙ реализацией и зовётся из хука дважды не бывает: два
# обхода одного вывода разошлись бы молча — и разошлись бы именно там, где
# расхождение не видно, потому что оба ответа выглядят правдоподобно.
#
# Когда `--subject-root` и `--work-root` различаются, прогон шёл во ВРЕМЕННОЙ
# выкладке отправляемой ревизии. Она снимается по выходу хука — установка в неё
# исход следующей отправки не изменит, и предписывать её значило бы снова
# печатать невыполнимое. Главным предписанием там становится «привести копию к
# отправляемой ревизии», а условие консоли спрашивается заново у того же
# предиката, но уже в РАБОЧЕЙ копии — не подменой путей в чужой строке.
set -uo pipefail

subject_root=""
work_root=""
list_only=0
while [ "$#" -gt 0 ]; do
    case "$1" in
        --list)         list_only=1; shift ;;
        --subject-root) subject_root="${2:-}"; shift 2 ;;
        --work-root)    work_root="${2:-}"; shift 2 ;;
        *) shift ;;
    esac
done

run_out="$(cat)"

# Пары «имя проверки → причина»: имя стоит заголовком `== …`, причина — строкой
# `ПРОПУСК:` под ним. Грепом одной строки имя терялось, а одинаковые причины
# схлопывались `sort -u` — одиннадцать пропусков печатались одной строкой без
# координат. Пара собирается обходом, поэтому теряться нечему.
pairs="$(printf '%s\n' "$run_out" | awk '
    /^== /       { name = substr($0, 4); next }
    /ПРОПУСК:/   {
        reason = $0
        sub(/^[[:space:]]*ПРОПУСК:[[:space:]]*/, "", reason)
        sub(/[[:space:]]*—[[:space:]]*НЕ выполнено[[:space:]]*$/, "", reason)
        if (name != "") printf "%s\t%s\n", name, reason
        next
    }')"

# КОМАНДА ПОЧИНКИ В ПЕРЕЧНЕ НЕ ПЕЧАТАЕТСЯ: прогонщик называет её В СВОЁМ дереве,
# а оно может быть временной выкладкой, которая снимается по выходу хука.
# Команды печатает только блок ниже — он один знает, какое это дерево.
print_list() {
    printf '%s\n' "$pairs" | while IFS=$'\t' read -r name reason; do
        [ -n "$name" ] || continue
        printf '  %s — %s\n' "$name" "${reason%% — условие:*}"
    done
}

if [ "$list_only" -eq 1 ]; then
    print_list
    exit 0
fi

console_pairs="$(printf '%s\n' "$pairs" | grep -F 'зависимости не установлены' || true)"
[ -n "$console_pairs" ] || exit 0

printf '\npre-push ОТКАЗ: изменение трогает консоль, а её проверки НЕ ВЫПОЛНЯЛИСЬ.\n'
printf 'Вердикта по ним нет ни одного — отправлять нечего подтверждать.\n'

# ЧИСЛО СО ССЫЛКОЙ НА ПЕРЕЧЕНЬ, А НЕ СО ВТОРОЙ ЕГО КОПИЕЙ. Перечень напечатан
# выше этой же программой (`--list`): повторять его здесь значило бы завести
# второе место об одном предмете — расходиться им потом молча.
printf '\nИз них проверок консоли — %s, и они перечислены выше поимённо.\n' \
    "$(printf '%s\n' "$console_pairs" | grep -c .)"

# ВРЕМЕННАЯ ВЫКЛАДКА — ДРУГОЙ СЛУЧАЙ, И ГЛАВНОЕ ПРЕДПИСАНИЕ В НЁМ ДРУГОЕ.
#
# Когда рабочая копия не равна отправляемой ревизии, хук раскладывает ревизию во
# ВРЕМЕННУЮ копию и судит её. Зависимостей там нет и быть не может: каталог
# заводится пустым и снимается по выходу. Поэтому `npm ci` в него — команда,
# которая исполнится и ничего не изменит: следующая отправка разложит новую
# пустую выкладку и откажет снова. Это был бы тот же дефект в новом месте.
#
# Главное здесь — привести копию к отправляемой ревизии. Условие консоли
# создаётся в РАБОЧЕЙ копии, и спрашивается оно у того же единственного предиката,
# а не выводится подменой путей в чужой строке: подмена дала бы правдоподобный
# ответ и там, где он неверен.
relayed=0
if [ -n "$subject_root" ] && [ -n "$work_root" ] && [ "$subject_root" != "$work_root" ]; then
    relayed=1
fi

commands=""
if [ "$relayed" -eq 0 ]; then
    # Команды: те же, что назвал прогонщик, без повторов и в порядке появления.
    # Повторы законны и многочисленны: четыре члена воркспейса берут зависимости
    # из одного корня, и печатать четыре одинаковых строки значило бы предлагать
    # исполнить одно и то же четырежды.
    #
    # Хвост до конца строки, а не «до пробела»: путь с пробелом обрезался бы
    # молча — то есть снова печаталась бы команда, которую нельзя исполнить.
    # Пояснение `deps-ready.mjs` про standalone снимается отдельно: оно не часть
    # команды.
    commands="$(printf '%s\n' "$console_pairs" \
        | sed -n 's/.*условие: \(npm ci --prefix .*\)$/\1/p' \
        | sed 's/   *(пакет standalone.*$//' \
        | sed 's/[[:space:]]*$//' \
        | awk 'length($0) > 0 && !seen[$0]++')"
elif command -v node > /dev/null && [ -f "$work_root/ui-future/scripts/deps-ready.mjs" ]; then
    while IFS=$'\t' read -r name _; do
        pkg="${name##* }"
        pkg_dir="$work_root/ui-future/$pkg"
        [ -d "$pkg_dir" ] || continue
        node "$work_root/ui-future/scripts/deps-ready.mjs" "$pkg_dir" > /dev/null 2>&1 && continue
        cmd="$(node "$work_root/ui-future/scripts/deps-ready.mjs" "$pkg_dir" 2>&1 \
            | sed -n 's/^Условие создаётся так: //p' | head -1 \
            | sed 's/   *(пакет standalone.*$//' | sed 's/[[:space:]]*$//')"
        [ -n "$cmd" ] && commands="$commands$cmd
"
    done <<< "$console_pairs"
    commands="$(printf '%s' "$commands" | awk 'length($0) > 0 && !seen[$0]++')"
fi

if [ "$relayed" -eq 1 ]; then
    printf '\nПрогон шёл во ВРЕМЕННОЙ выкладке отправляемой ревизии: рабочая копия ей не\n'
    printf 'равна. Выкладка заводится пустой и снимается по выходу — зависимостей там нет\n'
    printf 'и быть не может, поэтому установка В НЕЁ следующий исход не изменит.\n'
    printf '\nГлавное предписание здесь одно — привести копию к отправляемой ревизии:\n'
    printf '  cd %s && git status   # покажет, чем копия расходится\n' "$work_root"
    printf 'Приведите её (git add/commit, git stash) — и прогон пойдёт в самой копии,\n'
    printf 'где зависимости консоли живут.\n'
    if [ -n "$commands" ]; then
        printf '\nСверх того в рабочей копии условие тоже НЕ создано — скопируйте и исполните:\n'
        printf '%s\n' "$commands" | sed 's/^/  /'
    else
        printf '\nВ самой рабочей копии условие уже создано: спрошено у того же предиката,\n'
        printf 'что и в прогоне (ui-future/scripts/deps-ready.mjs). Ставить больше нечего.\n'
    fi
elif [ -z "$commands" ]; then
    # Прогонщик не назвал команды — это долг ПРОГОНЩИКА, и молчать о нём нельзя:
    # отказ без предписания и есть предмет, ради которого этот файл заведён.
    printf '\nПрогонщик не назвал команды создания условия — сообщите об этом:\n'
    printf '  scripts/ci-local.sh обязан печатать её рядом с каждым пропуском.\n'
else
    printf '\nСоздайте условие — скопируйте и исполните целиком:\n'
    printf '%s\n' "$commands" | sed 's/^/  /'
    printf '\nПотом повторите отправку: проверки исполнятся, и вердикт у них будет.\n'
fi

printf '\nЛибо отправьте черновик явно (git push --no-verify), зная, что конвейер станет\n'
printf 'первым читателем.\n'
