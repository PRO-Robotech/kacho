# Диапазон(ы), которые уезжают ЭТОЙ отправкой, — отдельным производителем.
#
# ЗАЧЕМ ОТДЕЛЬНО. Ровно по той же причине, по которой отдельно живёт
# prepush-groups.sh: это РЕШЕНИЕ («вот что уезжает»), и оно ошибалось молча,
# пока было выражением внутри хука. Проверить его можно было только полной
# отправкой — то есть двадцатиминутным прогоном, после которого ответ всё равно
# смешан с вердиктом самих проверок. Производитель печатает диапазоны и
# завершается: его зовут на синтетическом репозитории и требуют обе стороны
# (prepush-range-inject.sh).
#
# ФОРМА ВХОДА — та, что даёт git: строки `<local_ref> <local_sha> <remote_ref>
# <remote_sha>`, по одной на отправляемую ссылку.
#
# ─────────────────────────────────────────────────────────────────────────────
# БАЗА ПЕРВОЙ ОТПРАВКИ — БЛИЖАЙШАЯ ОПУБЛИКОВАННАЯ ТОЧКА ИНТЕГРАЦИИ, А НЕ СТВОЛ
#
# Нулевой `<remote_sha>` означает, что ссылки на origin ещё нет: сравнивать
# не с чем, и базу приходится ВЫБИРАТЬ. Здесь стоял ствол — и это верно ровно
# для ветки, отведённой от ствола.
#
# Работа копится в накопительных релизных ветках, поэтому ветка задачи чаще
# отводится от `origin/release/*`. Трёхточечный диапазон от ствола вбирает тогда
# ВСЮ работу линии — чужие коммиты нескольких недель, — и набор групп считается
# по ним. Следствие измерено (#805): ветка, не тронувшая консоль ни одним
# файлом, получала группу проверок консоли; в свежей рабочей копии зависимостей
# консоли нет, все её проверки попадают в «НЕ выполнено», и хук ОТКАЗЫВАЕТ.
# Обход (`KACHO_TRUNK_REF=...` либо `--no-verify`) становился обязательным на
# ПЕРВОЙ отправке КАЖДОЙ ветки, а обход, который делают всегда, перестаёт быть
# заметным — то есть гейт вырождался в привычку.
#
# Поэтому база выбирается: среди опубликованных точек интеграции (ствол и
# релизные линии) берётся та, относительно которой уезжает МЕНЬШЕ ВСЕГО
# коммитов. Это и есть «откуда ветка отведена», спрошенное у графа, а не
# выведенное из имени ветки.
#
# ПОЧЕМУ НЕ ЛЮБАЯ ССЫЛКА ORIGIN. Ветка соседа, случайно содержащая мою работу,
# дала бы базу, при которой не уезжает ничего, — и проверок не было бы вовсе.
# Точки интеграции — закрытый и осмысленный набор: именно от них ветвятся и
# именно в них вливают.
#
# ПОЧЕМУ СУЖЕНИЕ ЗАКОННО. Довод уже принят деревом для случая, когда ссылка на
# origin есть (prepush-groups.sh): предмет хука не в том, что вся ветка
# когда-нибудь окажется верна, а в том, что ТВОЯ правка не уедет непроверенной.
# Работа соседей свой вердикт получает своими отправками и конвейером запроса на
# слияние.
#
# РИСК СУЖЕНИЯ ОДНОСТОРОННИЙ. Устаревшая локальная копия `origin/release/*`
# отстаёт → выбранная база старше → диапазон ШИРЕ, а не уже. Промахнуться в
# сторону «прогнали меньше нужного» этим механизмом нельзя.
#
# НАЗВАННЫЙ СТВОЛ СИЛЬНЕЕ ВЫВОДА: `KACHO_TRUNK_REF` берётся как есть — тот, кто
# назвал базу, знает, что делает (и это же остаётся способом получить прежнее,
# широкое поведение).
set -uo pipefail

zero="0000000000000000000000000000000000000000"

# Кандидаты — ТОЧКИ ИНТЕГРАЦИИ, выведенные из ссылок, а не выписанные списком:
# рукописный перечень релизных линий разошёлся бы с деревом молча. Тот же приём
# и тот же набор, что у переписи веток (scripts/branch-audit.sh).
integration_refs() {
    git for-each-ref --format='%(refname)' \
        refs/remotes/origin/main refs/remotes/origin/release 2> /dev/null
}

# Ближайшая опубликованная точка интеграции: та, относительно которой уезжает
# меньше всего коммитов. Равенство разрешается порядком ссылок (ствол раньше
# релизных линий по имени) — важно, что правило детерминированно, а не какая
# именно сторона выигрывает: при равном числе коммитов уезжает одна и та же
# работа.
nearest_published_base() {
    local local_sha="$1" ref short mb n best="" best_n=""
    while read -r ref; do
        [ -n "$ref" ] || continue
        mb="$(git merge-base "$ref" "$local_sha" 2> /dev/null)" || continue
        [ -n "$mb" ] || continue
        n="$(git rev-list --count "$mb..$local_sha" 2> /dev/null)" || continue
        if [ -z "$best_n" ] || [ "$n" -lt "$best_n" ]; then
            short="${ref#refs/remotes/}"
            best="$short"; best_n="$n"
        fi
    done < <(integration_refs)
    # Ни одна не резолвится (свежий клон, отвязанная копия) — прежнее имя:
    # производитель групп на нерезолвимом стволе НЕ сужает набор.
    printf '%s' "${best:-origin/main}"
}

base_for() {
    local local_sha="$1"
    if [ -n "${KACHO_TRUNK_REF:-}" ]; then
        printf '%s' "$KACHO_TRUNK_REF"
        return
    fi
    nearest_published_base "$local_sha"
}

ranges=""
saw_line=0
while read -r _local_ref local_sha _remote_ref remote_sha; do
    saw_line=1
    [ -z "${local_sha:-}" ] && continue
    [ "$local_sha" = "$zero" ] && continue        # удаление ссылки — проверять нечего
    if [ -z "${remote_sha:-}" ] || [ "$remote_sha" = "$zero" ]; then
        ranges="$ranges $(base_for "$local_sha")...$local_sha"
    else
        ranges="$ranges $remote_sha..$local_sha"
    fi
done
ranges="${ranges# }"

# Вход пуст — хук позвали руками, git ничего не передал. Диапазон всё равно
# называется, и той же базой: иначе ручной вызов отвечал бы про другую работу,
# чем настоящая отправка той же ветки.
#
# Вход был, но все строки — удаления: диапазона нет и быть не может. Пустая
# строка здесь означает ровно это, и нижестоящие читают её как «база не задана».
if [ "$saw_line" = "0" ]; then
    ranges="$(base_for HEAD)...HEAD"
fi

printf '%s\n' "$ranges"
