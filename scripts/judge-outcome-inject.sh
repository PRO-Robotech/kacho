# judge-outcome-inject.sh — доказательство, что локальный прогонщик ЧИТАЕТ все
# четыре исхода КАЖДОГО судьи-цели, а не два (задачи #1851 и #1893).
#
# # Что здесь охраняется
#
# У цели-судьи исходов четыре: 0 годно · 1 находка · 2 VOID («проверять нечего»)
# · 3 «не исполнялась». Схлопывание VOID в успех — главный способ незаметно
# потерять проверку: пустое дерево отчитывалось бы зелёным так же уверенно, как
# проверенное. Схлопывание в красное — обратная ошибка: прогон, красный по
# построению на дереве, где чинить нечего, перестают читать.
#
# # Почему проба нужна, хотя классификаторы написаны верно
#
# Ровно потому, что они написаны верно. Способность различать исходы на дереве
# продукта наблюдается ТОЛЬКО в одном из четырёх случаев, а три остальных не
# встречаются никогда. «Зелёный» там неотличим от «мёртвый».
#
# # Почему судей ДВА, а скрипт один
#
# До 2026-09-02 этот файл знал имя одной функции константой и назывался по ней.
# Пока судья-цель был один, это было неотличимо от общего доказательства; со
# вторым (`model_canon_check`, #1893) стало видно, что имя функции — параметр, а
# не свойство харнесса. Вторая копия харнесса разошлась бы с первой молча и
# разошлась бы там, где обе зелены. Имя файла сменилось вместе с предметом:
# прежнее описывало бы половину того, что скрипт делает.
#
# # Устройство
#
# Функция берётся ИЗ ci-local.sh, а не переписывается здесь: копия разошлась бы с
# оригиналом молча, и проба доказывала бы свойство текста, которого никто не
# исполняет. Цель подменяется заглушкой `make`, возвращающей заданный код.
#
# Проба доказывает и СВОЮ способность упасть: тот же набор утверждений гоняется
# против НАМЕРЕННО сломанной копии, где VOID схлопнут в успех. Набор, зелёный на
# обеих, ничего не измеряет.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT_DIR/scripts/ci-local.sh"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# СУДЬИ — перечень пар «функция прогонщика | текст, которым она называет VOID».
#
# Перечень объявленный, а не выведенный, и это названо честно: вывести «какая
# функция читает исход судьи» из текста нельзя — признаком была бы форма записи
# `case`, то есть ровно то, что проба и проверяет. Зато перечень САМОИСТЕКАЕТ:
# функция, которой в прогонщике нет, роняет прогон кодом 2 («предмет исчез»), а
# не пропускается молча.
JUDGES="
manifest_form_check|манифестов в дереве нет
model_canon_check|сверять нечего
"

ASSERTS_TOTAL=0
FAILS_TOTAL=0
JUDGES_SEEN=0

# extract — тело функции из прогонщика, дословно.
extract() { # extract <имя функции>
    awk -v fn="$1" '$0 == fn "() {" {inb=1} inb {print} inb && $0 == "}" {exit}' "$SRC"
}

# harness <функция> <вариант> <код заглушки> — прогон функции с подменённым `make`.
#
# Заглушка кладётся в свой каталог и выводится в PATH первой: настоящий `make`
# собрал бы Go-двоичный файл, а предмет пробы — не он, а чтение исхода.
harness() { # harness <функция> <ключ: real|broken> <код заглушки>
    local fn="$1" variant="$2" code="$3" work body
    work="$tmp/$fn-$variant-$code"
    mkdir -p "$work/bin"
    cat > "$work/bin/make" <<EOF
#!/usr/bin/env bash
echo "заглушка цели: код $code"
exit $code
EOF
    chmod +x "$work/bin/make"
    body="$(extract "$fn")"

    {
        echo 'set -uo pipefail'
        echo "ROOT='$work'"
        echo "WORK='$work'"
        echo 'ran=0; fails=(); skips=()'
        if [ "$variant" = broken ]; then
            # ДЕФЕКТ: ветвь VOID заменяется целиком на успех — ровно то, что проба
            # обязана поймать. Мутируется ВСЯ ветвь, а не первая её строка: иначе
            # `skips+=` уцелел бы, пропуск по-прежнему считался, и «сломанная»
            # копия отличалась бы от настоящей только текстом.
            printf '%s\n' "$body" | awk '
                /^        2\)/ { print "        2)  echo \"   ok\" ;;"; inb=1; next }
                inb && /^        [0-9*]\)/ { inb=0 }
                inb { next }
                { print }'
        else
            printf '%s\n' "$body"
        fi
        echo "$fn"
        echo 'printf "ИТОГ ran=%s fails=%s skips=%s\n" "$ran" "${#fails[@]}" "${#skips[@]}"'
    } > "$work/probe.sh"

    PATH="$work/bin:$PATH" bash "$work/probe.sh" 2>&1
}

# want <функция> <вариант> <ярлык> <код> <ожидания…> — «!строка» означает
# «обязана отсутствовать».
want() {
    local fn="$1" variant="$2" label="$3" code="$4"; shift 4
    local out need bad=0 why=""
    ASSERTS=$((ASSERTS + 1))
    out="$(harness "$fn" "$variant" "$code")"
    for need in "$@"; do
        if [ "${need:0:1}" = "!" ]; then
            case "$out" in *"${need:1}"*) bad=1; why="$why; нашлось запрещённое «${need:1}»";; esac
        else
            case "$out" in *"$need"*) ;; *) bad=1; why="$why; не нашлось «$need»";; esac
        fi
    done
    if [ "$bad" = 0 ]; then
        printf '  ok   [%s] код %s\n' "$label" "$code"
    else
        printf '  FAIL [%s] код %s — %s\n' "$label" "$code" "${why#; }"
        FAILS=$((FAILS + 1))
    fi
}

# assert_all — один и тот же набор против обеих копий одной функции.
assert_all() { # assert_all <функция> <VOID-текст> <ключ: real|broken> <ярлык>
    local fn="$1" void="$2" variant="$3" label="$4"
    FAILS=0; ASSERTS=0
    # 0 — годно: ни отказа, ни пропуска.
    want "$fn" "$variant" "$label" 0 'ok' 'fails=0' 'skips=0'
    # 1 — находка: красное, и НЕ пропуск.
    want "$fn" "$variant" "$label" 1 'ОТКАЗ' 'fails=1' 'skips=0'
    # 2 — VOID: пропуск, и НИ В КОЕМ СЛУЧАЕ не «ok» и не отказ.
    want "$fn" "$variant" "$label" 2 "$void" 'fails=0' 'skips=1' '!ОТКАЗ'
    # 3 — не исполнялась: тоже пропуск, тоже не отказ и не успех.
    want "$fn" "$variant" "$label" 3 'НЕ ИСПОЛНЯЛАСЬ' 'fails=0' 'skips=1' '!ОТКАЗ'
}

rc=0
echo "== чтение четырёх исходов судьями прогонщика"
echo "   источник: $SRC"

# Перечень читается ПОСТРОЧНО, а не словами: текст VOID содержит пробелы, и
# `for … in $JUDGES` разорвал бы его на слова — проба искала бы в выводе первое
# слово вместо фразы и зеленела бы на чужой строке.
while IFS= read -r judge; do
    [ -n "$judge" ] || continue
    fn="${judge%%|*}"
    void="${judge#*|}"
    body="$(extract "$fn")"
    if [ -z "$body" ]; then
        echo "ОТКАЗ: $fn не найдена в $SRC — предмет пробы исчез, и её зелёное означало бы" >&2
        echo "       «нечего было читать», а не «всё верно». Если функцию сняли вместе с целью," >&2
        echo "       снимите и запись перечня: послабление обязано истекать вместе с предметом." >&2
        exit 2
    fi
    JUDGES_SEEN=$((JUDGES_SEEN + 1))
    lines="$(printf '%s\n' "$body" | wc -l | tr -d ' ')"

    echo
    echo "-- $fn (тело функции — строк $lines)"
    echo "   настоящая копия: набор обязан пройти целиком"
    assert_all "$fn" "$void" real настоящий
    real_fails="$FAILS"; real_asserts="$ASSERTS"

    echo "   сломанная копия (VOID схлопнут в успех): набор обязан ПОКРАСНЕТЬ"
    assert_all "$fn" "$void" broken сломанный
    broken_fails="$FAILS"

    ASSERTS_TOTAL=$((ASSERTS_TOTAL + real_asserts * 2))
    if [ "$real_fails" -ne 0 ]; then
        echo "ОТКАЗ: настоящая копия $fn не проходит собственный набор — классификатор читает не все исходы" >&2
        FAILS_TOTAL=$((FAILS_TOTAL + real_fails))
        rc=1
    fi
    if [ "$broken_fails" -eq 0 ]; then
        # Без этой половины набор мог бы быть зелёным на чём угодно.
        echo "ОТКАЗ: сломанная копия $fn прошла набор — проба НЕ СПОСОБНА поймать схлопывание" >&2
        echo "       VOID в успех, то есть её зелёное на настоящей копии ничего не доказывает." >&2
        rc=1
    fi
done <<< "$JUDGES"

# Пустой обход обязан ронять прогон: «ноль провалов» иначе означало бы «ноль
# прочитанного».
if [ "$JUDGES_SEEN" -eq 0 ]; then
    echo "ОТКАЗ: судей не осмотрено ни одного — перечень пуст, и вердикт беспредметен" >&2
    exit 2
fi

echo
echo "перепись: судей осмотрено $JUDGES_SEEN · утверждений $ASSERTS_TOTAL · провалов на настоящих копиях $FAILS_TOTAL"
if [ "$rc" = 0 ]; then
    echo "ГОДНО: у каждого судьи читаются все четыре исхода, и проба доказала свою способность упасть"
fi
exit "$rc"
