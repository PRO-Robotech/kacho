# Проверка совместимости контракта, различающая ОБЪЯВЛЕННЫЙ слом и незаявленный.
#
# Сама проверка знает только «сломано / не сломано». Конвенции продукта при этом
# разрешают снять поле с контракта — удалить с резервированием номера и имени,
# объявив слом в сообщении коммита. Без различения таких изменений было два
# исхода, и оба плохие: ронять ствол либо вырезать файл из области проверки
# навсегда. Здесь заведён третий: каждая ожидаемая находка названа поимённо в
# proto/breaking-declared.txt, и перечень обязан истекать сам.
#
# Три исхода, четвёртого нет:
#   находка есть, строки нет  → ОТКАЗ (незаявленный слом);
#   находка есть, строка есть → пропуск;
#   строка есть, находки нет  → ОТКАЗ (записи нечего исключать).
set -uo pipefail

REPO_SLUG="${1:-PRO-Robotech/kacho}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
DECLARED="$ROOT/proto/breaking-declared.txt"

cd "$ROOT/proto"

raw="$(buf breaking --against "https://github.com/${REPO_SLUG}.git#branch=main,subdir=proto" 2>&1)"
rc=$?

# Отказ ПО ДРУГОЙ причине (сеть, недоступное основание, неверная конфигурация) не
# должен выглядеть как «слом объявлен»: у такого вывода нет находок, и пустое
# пересечение с перечнем прочиталось бы как успех.
if [ $rc -ne 0 ] && [ -z "$raw" ]; then
    echo "ОТКАЗ: проверка совместимости не выполнилась и не назвала ни одной находки." >&2
    echo "       Это третья категория исхода — «не выполнилось», а не «сломано» и не «чисто»." >&2
    exit 1
fi

# Находки — строки вида «файл:строка:колонка:текст». Прочее (прогресс, шум) отсекается.
mapfile -t found < <(printf '%s\n' "$raw" | grep -E '^[^:]+\.proto:[0-9]+:[0-9]+:' | sort -u)

declared=()
if [ -f "$DECLARED" ]; then
    mapfile -t declared < <(grep -vE '^\s*(#|$)' "$DECLARED" | sort -u)
fi

echo "== совместимость контракта =="
echo "   находок проверки: ${#found[@]}; объявлено в перечне: ${#declared[@]}"

fail=0

for f in "${found[@]:-}"; do
    [ -z "$f" ] && continue
    hit=0
    for d in "${declared[@]:-}"; do
        [ "$f" = "$d" ] && hit=1 && break
    done
    if [ $hit -eq 0 ]; then
        [ $fail -eq 0 ] && echo "ОТКАЗ: слом контракта, который никто не объявлял:" >&2
        echo "   $f" >&2
        fail=1
    fi
done

for d in "${declared[@]:-}"; do
    [ -z "$d" ] && continue
    hit=0
    for f in "${found[@]:-}"; do
        [ "$d" = "$f" ] && hit=1 && break
    done
    if [ $hit -eq 0 ]; then
        echo "ОТКАЗ: записи перечня больше НЕЧЕГО исключать — она пережила свой предмет:" >&2
        echo "   $d" >&2
        echo "   Изменение влито, основание сравнения сдвинулось. Опустошите" >&2
        echo "   proto/breaking-declared.txt: перечень, переживший предмет, молча" >&2
        echo "   прикроет следующий слом." >&2
        fail=1
    fi
done

if [ $fail -ne 0 ]; then
    exit 1
fi

if [ ${#found[@]} -eq 0 ]; then
    echo "   контракт совместим; объявленных сломов нет"
else
    echo "   все ${#found[@]} находок объявлены поимённо — слом заявлен, а не проехал"
fi
