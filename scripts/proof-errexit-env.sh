# «УСЛОВИЕ НЕ СОЗДАНО» (#2831).
#
# Файл не запускается и руками не сорсится: его подаёт читатель доказательств
# через `BASH_ENV`, и bash исполняет его ДО первой строки доказательства.
# Читателей два, и оба подают этот один файл: `proof` в `scripts/ci-local.sh` и
# обход `deploy/scripts/run-injection-proofs.sh`.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ
#
# Контракт доказательств один на дерево: 0 доказано · 1 провалено · 2 условие не
# создано (`deploy/tests/helm/README.md` §«Три исхода»). Но под `set -e` двойкой
# выходит и доказательство, у которого оборвалась команда: `grep` или `sed` по
# отсутствующему файлу, встроенная команда с неверным доводом — все они отдают 2,
# и errexit выносит этот код наружу как есть. Читатель видел двойку и писал
# «условие не создано»: находка о сломанном доказательстве уходила в третью
# категорию, и хук отправки говорил «НЕ ВЫПОЛНЕНО — это не зелено» там, где было
# красное. Замер @eb603531617: из 34 доказательств, которые зовут два читателя,
# под errexit пять — единица счёта файл, признак `set -e…` в начале строки.
#
# Перечень пяти здесь не выписан и не нужен: перевод ставится КАЖДОМУ
# доказательству, которое зовёт читатель, поэтому шестое под errexit покрыто в
# тот же коммит, которым заведено.
#
# ─────────────────────────────────────────────────────────────────────────────
# КАК
#
# Ловушка ERR превращает выход по errexit в код 1 и называет оборванную команду.
#
#   * `set -E` (errtrace) — несущее: без него ловушка не наследуется функциями,
#     подоболочками и подстановками, и grep внутри функции доказательства ушёл
#     бы мимо неё с прежней двойкой.
#   * Срабатывает ровно там, где сработал бы errexit: ловушку ERR bash не зовёт
#     в условиях `if`/`while`, в `&&`/`||`, под `!` — тем же правилом, что и
#     errexit.
#   * Без errexit (`$-` без `e`) она не делает ничего: доказательства без `set -e`
#     её не замечают, и `$?` после неё прежний. В подстановке `$( … )` errexit
#     по умолчанию снят, поэтому терпимый там отказ команды терпимым и остаётся.
#   * Явный `exit 2` — не оборванная команда, ловушка его не трогает: двойка,
#     которую доказательство ОБЪЯВИЛО, остаётся двойкой.
#   * Своя ловушка ERR доказательства сильнее этой: она ставится позже.
#
# ГРАНИЦА, И ОНА НАЗВАНА. Двойка, вышедшая из ПОДОБОЛОЧКИ `( … )` под errexit,
# для родителя — оборванная команда и читается отказом, даже если внутри стоял
# явный `exit 2`. Объявленный исход из подоболочки выносят явно:
# `( … ) || exit $?`. У пяти доказательств под errexit такой формы нет: их
# объявленная двойка — `exit 2` верхнего уровня либо функции (`premise.sh`).
#
# BASH_ENV СНИМАЕТСЯ ПЕРВЫМ: иначе его унаследовал бы каждый bash, которого
# доказательство запускает (испытуемый гейт, копия прогонщика), и поведение
# испытуемого менялось бы вдали от места правки.
unset BASH_ENV
set -E
trap '__proof_errexit_rc=$?
if [[ $- == *e* ]]; then
    printf "доказательство оборвано errexit: «%s» вышла кодом %s — это отказ, а не «условие не создано»\n" "$BASH_COMMAND" "$__proof_errexit_rc" >&2
    exit 1
fi' ERR
