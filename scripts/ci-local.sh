# Локальный прогон тех же проверок, что делает конвейер, — чтобы не узнавать об
# отказе через двадцать минут ожидания.
#
# ЗАЧЕМ. Конвейер тратится один раз, на запрос в ствол; всё, что можно узнать до
# него, обязано узнаваться здесь. Иначе он становится первым читателем кода, а не
# подтверждением на чужой машине.
#
# ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Заменой конвейера. Здесь нет ни кластера, ни поднятого
# стенда, ни сквозных прогонов — они названы в конце явно, чтобы «локально
# зелено» не читалось шире, чем есть.
#
# ПОЧЕМУ ПЛАГИНЫ СТАВЯТСЯ ЗАНОВО. Генерация зависит от версии плагина, а не от
# версии buf: конвейер ставит их `go install` из ЭТОГО модуля, поэтому машина с
# другим бинарём в PATH даёт другой результат — и расхождение видно только в
# конвейере. Здесь они ставятся тем же способом, в отдельный каталог.
#
# Использование:
#   scripts/ci-local.sh            # всё
#   scripts/ci-local.sh proto      # только генерация и совместимость
#   scripts/ci-local.sh go|terraform|helm|ui  # отдельная группа
#   scripts/ci-local.sh --exhaustion-signatures  # по каким признакам прогон
#                                                # объявляет себя недействительным
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# ВСЕ аргументы, а не первый. Ветка разбора ниже принимает несколько групп через
# пробел, и хук отправки зовёт скрипт именно так («proto go»), — но `${1}` брал
# только первое слово, поэтому вторая группа не исполнялась НИ РАЗУ, а итог
# «отказов 0» относился к меньшему, чем читатель полагал. Найдено 2026-08-17:
# запрос четырёх групп дал три проверки контрактов и зелёный итог.
GROUP="${*:-all}"

# ─────────────────────────────────────────────────────────────────────────────
# ИСЧЕРПАНИЕ РЕСУРСА — ТРЕТИЙ ИСХОД, А НЕ КРАСНЫЙ ВЕРДИКТ (#862)
# ─────────────────────────────────────────────────────────────────────────────
# Шаг, оборванный нехваткой места или памяти, находок не даёт НИ ОДНОЙ: инструмент
# не дошёл до предмета. Подавать это красным значит посылать читателя искать
# поломку в своей ветке — ровно то, от чего правило про третий исход
# предостерегает («Прогон на исчерпанном ресурсе»: вердикта нет ни у одной пробы,
# включая те, что успели пройти).
#
# Наблюдалось 2026-08-20: три имени в строке «красное», ноль находок, одна причина
# на все три — и чтобы это понять, пришлось открывать журналы трёх шагов.
#
# ПРИЗНАК УЗКИЙ И БЕРЁТСЯ ИЗ ТЕКСТА ИНСТРУМЕНТА, а не угадывается. Широкий признак
# («любой отказ с коротким выводом») превратил бы защиту от ложного красного в
# маску, глотающую настоящие находки, — а это дороже той беды, которую он лечит.
#
# РЕГИСТР ЗНАЧИМ, и это не педантизм. Строчными (`no space left on device`)
# печатает текст errno — так его отдают Go, ядро и node. С ПРОПИСНОЙ фразу
# печатают двое, и они по разные стороны: git (`<путь>: No space left on
# device`) — это настоящее исчерпание, а классификатор хранилища в нашем дереве
# (`(28) No space left on device`) — это ЛИТЕРАЛ ПРОБЫ, и проба, упавшая на нём,
# обязана остаться КРАСНОЙ. Разводит их не регистр, а форма: у git перед фразой
# стоит ПУТЬ с двоеточием, у литерала — номер errno в скобках. Поэтому признаков
# на эту фразу два, и второй анкерован путём.
#
# Форма git добавлена не впрок: она наблюдалась живьём — прогон гейтов дерева
# упал на `git init` в своей синтетической фикстуре, и строчный признак её не
# брал.
#
# ЯКОРЬ ЕСТЬ У КАЖДОГО ПРИЗНАКА, включая `signal: killed`. Формообразующего
# префикса у него нет (инструменты печатают его по-разному), поэтому якорем
# служит КОНЕЦ СТРОКИ: сообщением инструмента эта фраза строку замыкает, а
# пробой, которая про снятый процесс что-то утверждает, — почти никогда
# (за ней идёт «, ждали …», кавычка, координата). Литерала `signal: killed` в
# дереве сегодня ноль (предикат: `git grep -c 'signal: killed'`), так что
# предмета у послабления нет вовсе; якорь стоит на случай, когда он появится.
#
# ЕСЛИ ТЕКСТ ИНСТРУМЕНТА СМЕНИТСЯ, признак перестанет отбирать — и это будет
# ЗАМЕТНО by construction: нераспознанное исчерпание приходит красным, то есть
# возвращается ровно тот симптом, ради которого написан этот блок. Послабление
# вечно-зелёным стать не может. Что у каждого признака есть производитель, а у
# каждого настоящего сообщения — признак, держит парная инъекция
# `scripts/ci-local-outcome-inject.sh` (обе стороны, с корпусом настоящих текстов).
# ОБЩИЙ КЭШ ИСЧЕЗАЕТ ИЗ-ПОД ИДУЩЕГО ПРОГОНА — И ЭТО ШТАТНОЕ СОБЫТИЕ, А НЕ
# РЕДКОСТЬ (#1431). На машине разработчика рабочих копий десятки, а кэш сборки и
# модкэш — ОБЩИЕ; решение их подрезать («кончается место») принимает любая копия,
# и соседний `go clean -cache` обрывает чужой идущий прогон. Предмета шаг при
# этом не достигает НИ РАЗУ: находок ноль, а «красное» посылает читателя искать
# поломку в своей ветке, где менять нечего. Наблюдалось на трёх шагах подряд
# (`go build`, `go vet`, `go test -short`) при нуле настоящих находок.
#
# ФОРМ ДВЕ, И ВТОРАЯ НЕОЧЕВИДНА:
#
#   * кэш СБОРКИ — инструмент жалуется на открытие файла, которого больше нет
#     (`go: open …/go-build/…-d: no such file or directory`);
#   * ТУЛЧЕЙН — `go.mod` называет `toolchain`, и Go держит его В МОДКЭШЕ, поэтому
#     чистка модкэша уносит саму стандартную библиотеку, и жалоба приходит про
#     `std` (`package fmt is not in std (…)`).
#
# ЯКОРЬ У КАЖДОЙ — ПУТЬ, и это не педантизм, а единственное, чем формы отличимы
# от настоящих находок (замер 2026-08-28, обе стороны воспроизведены):
#
#   `package fmtx is not in std (/usr/lib/go-1.22/src/fmtx)`   ← ОШИБКА КОДА
#   `package fmt  is not in std (…/pkg/mod/golang.org/toolchain@…/src/fmt)` ← окружение
#
# Тексты различаются ТОЛЬКО путём в скобках: имя пакета разводит их лишь тем,
# существует ли такой пакет в stdlib, а этого grep не знает. Признак без якоря
# по пути глотал бы неверный импорт — то есть был бы маской, а не защитой.
# По той же причине признак кэша требует `go-build` НЕПОСРЕДСТВЕННО перед фразой
# errno: литералы `/tmp/go-build/…` живут в дереве (pkg/treecorpus), и
# широкий признак съел бы падение той пробы.
#
EXHAUSTION_SIGNATURES=(
    ': no space left on device'        # errno ENOSPC: write/mkdir/open — Go, ядро, node
    '/[^ ]*: No space left on device'  # та же ошибка от git: перед фразой ПУТЬ, не «(28)»
    ': [Cc]annot allocate memory'      # errno ENOMEM; прописная — форма strerror у не-Go
    'signal: killed$'                  # процесс снят убийцей по памяти — ФРАЗА ЗАМЫКАЕТ СТРОКУ
    'fatal error: out of memory'       # рантайм Go сдался (ему предшествует runtime: out of memory)
    'JavaScript heap out of memory'    # node: куча кончилась (код 134)
    'go-build[^ ]*: no such file or directory'   # кэш сборки подрезан из-под прогона
    'is not in std \([^)]*/toolchain@'           # тулчейн из модкэша унесён чисткой
)

# Перечисление признаков — не служебный режим для пробы, а диагностика оператору:
# «по чему прогон решает, что он недействителен». Одно объявление, один читатель.
if [ "$GROUP" = "--exhaustion-signatures" ]; then
    printf '%s\n' "${EXHAUSTION_SIGNATURES[@]}"
    exit 0
fi

# Шаг ОБОРВАН исчерпанием ресурса? Читается ЖУРНАЛ шага, а не код возврата:
# инструменты выходят с чем угодно, а причина стоит в тексте.
step_aborted_by_exhaustion() { # <файл журнала>
    local sig
    for sig in "${EXHAUSTION_SIGNATURES[@]}"; do
        grep -qE -- "$sig" "$1" && return 0
    done
    return 1
}

# Строка журнала, на которой основан вердикт, — чтобы «недействителен» не читалось
# как слово прогонщика о самом себе.
exhaustion_evidence() { # <файл журнала>
    local sig
    for sig in "${EXHAUSTION_SIGNATURES[@]}"; do
        grep -m1 -E -- "$sig" "$1" && return 0
    done
}

# КАТАЛОГ ЛОГОВ ВЫВОДИТСЯ ИЗ ДЕРЕВА, А НЕ ОБЩИЙ НА МАШИНУ (#677).
#
# Рабочих копий продукта на машине разработчика бывает больше тридцати
# (агентские worktree, релизные линии, копии параллельных сессий), и прогоны в
# них идут одновременно. Общий каталог означал одни и те же имена файлов для
# всех — то есть вердикт переставал быть свойством ДЕРЕВА, КОТОРОЕ ПРОВЕРЯЛИ.
#
# Наблюдалось дважды за день: отказ коротких проб был прочитан из лога другой
# копии (и относился к правке, уже починенной), а лок линта соседнего дерева
# пришёл как находка, хотя это «не выполнилось».
#
# Ручка `CI_LOCAL_WORK` решала это и раньше — но по УМОЛЧАНИЮ была выключена, а
# правило «прогоняй локально» её не называет. Защита, которую надо помнить, не
# защищает: теперь копии не сталкиваются by construction.
if [ -n "${CI_LOCAL_WORK:-}" ]; then
    WORK="$CI_LOCAL_WORK"
else
    _tree_key="$(printf '%s' "$ROOT" | cksum | tr -dc '0-9' | cut -c1-8)"
    WORK="${TMPDIR:-/tmp}/kacho-ci-local-${_tree_key}"
fi
mkdir -p "$WORK"
printf 'ci-local: дерево %s\nci-local: логи   %s\n\n' "$ROOT" "$WORK"
cd "$ROOT"

# НЕПРОВЯЗАННЫЙ КЛОН НАЗЫВАЕТСЯ ЗДЕСЬ (#462). Этот прогонщик исполняется хуком
# отправки — и ровно поэтому его запуск РУКАМИ есть признак того, что хука может
# не быть: провязанный клон позвал бы его сам. Напоминание молчит, когда провязка
# есть, и ничего не роняет: предмет прогонщика — код, а не настройка клона.
#
# Почему это не дублирует `hooks-notice` на целях `make test*`: те закрывают
# того, кто гоняет пробы через make. Прямой `scripts/ci-local.sh` их не касается,
# а он-то как раз и стоит непосредственно перед отправкой.
[ -n "${CI:-}" ] || bash "$ROOT/scripts/hooks/install.sh" notice || true

# `aborted` — ПОДМНОЖЕСТВО `skips`, а не четвёртая категория. Исходов по-прежнему
# три; отдельный список нужен затем, что «предмета нет» и «шаг оборван» требуют от
# читателя РАЗНОГО: первое законно и прогон остаётся действительным, второе делает
# недействительным весь прогон, включая шаги, которые успели пройти.
fails=(); skips=(); aborted=(); ran=0

# ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА (#589). «Не выполнено» — это не
# «прошло»: инструмента нет, зависимости не поставлены, у пакета нет предмета
# проверки. Прежде такие случаи печатались строкой на экран и НЕ входили в итог,
# поэтому «исполнено 24, отказов 2» молчало о трёх пакетах, которых никто не
# смотрел. Считать их успехом нельзя, отказом — тоже: отказ означает, что предмет
# есть и он сломан.
skip() { # skip <имя> <причина>
    printf '\n== %s\n   ПРОПУСК: %s — НЕ выполнено\n' "$1" "$2"
    skips+=("$1 ($2)")
}

# manifest_form_check — единственный судья формы манифеста домена (задача #1851).
#
# СВОЯ ФУНКЦИЯ, А НЕ `run`, И ПРИЧИНА В ТРЕТЬЕМ ИСХОДЕ. У цели их четыре:
#   0  годно   — каждый найденный манифест прочитан, разобран и связен;
#   1  находка — манифест негоден либо путь не прочитан;
#   2  VOID    — манифестов не найдено ни одного: проверять нечего;
#   3  проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось.
# `run` считает отказом ВСЯКИЙ ненулевой код, поэтому VOID уехал бы в красное на
# дереве, где чинить нечего, — а прогон, красный по построению, перестают читать.
# Обратное схлопывание (VOID в успех) запрещено тем же доводом с другой стороны:
# пустое дерево отчитывалось бы зелёным так же уверенно, как проверенное.
#
# Вызов пишется ровно тем же литералом, что и шаг конвейера
# (`make -C services/iam module-manifest-check`), и это не оформление: обе провязки
# сверяет ОДИН гейт одним выражением, и вторая форма записи уехала бы из-под него
# невидимой.
manifest_form_check() {
    local name="манифесты модулей: форму судит один загрузчик"
    ran=$((ran + 1))
    printf '\n== %s\n' "$name"

    local log rc=0
    log="$WORK/$(printf 'log-%02d-manifest-form.txt' "$ran")"
    ( cd "$ROOT" && make -C services/iam module-manifest-check ) > "$log" 2>&1 || rc=$?

    case "$rc" in
        0)  echo "   ok" ;;
        2)  printf '   ПРОПУСК: манифестов в дереве нет ни одного — НЕ выполнено\n'
            printf '   | это НЕ «находок нет»: судья формы не высказывался ни о чём. Манифесты\n'
            printf '   | отслеживаются деревом, поэтому пустой обход означает, что до них не\n'
            printf '   | дошли — смотрите корень обхода, а не форму манифеста\n'
            printf '   | целиком: %s\n' "$log"
            skips+=("$name (манифестов нет — проверять нечего)") ;;
        3)  printf '   ПРОПУСК: проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось\n'
            printf '   | вердикта нет ни одного: это не «находок нет» и не «находки есть»\n'
            printf '   | целиком: %s\n' "$log"
            skips+=("$name (вызов не разобран)") ;;
        *)  echo "   ОТКАЗ (код $rc)"
            tail -15 "$log" | sed 's/^/   | /'
            echo "   | целиком: $log"
            fails+=("$name") ;;
    esac
}

# model_canon_check — судья ПОБАЙТОВОЙ сверки модели доступов с манифестами
# модулей (задача #1893).
#
# СВОЯ ФУНКЦИЯ, А НЕ `run`, ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО У СОСЕДА ВЫШЕ. У цели четыре
# исхода:
#   0  сверено — каждый блок канона, принадлежащий модулю набора, порождён и равен;
#   1  находка — расхождение блоков, блок без источника, модуль без манифеста;
#   2  VOID    — сверять нечего ни для одного модуля;
#   3  проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось.
# `run` считает отказом ВСЯКИЙ ненулевой код, поэтому VOID уехал бы в красное на
# дереве, где сверять нечего, — а прогон, красный по построению, перестают читать.
# Обратное схлопывание (VOID в успех) запрещено тем же доводом с другой стороны.
#
# ЗАЧЕМ ВООБЩЕ, ЕСЛИ ИСПОЛНИТЕЛЯ ЗОВЁТ ПРОБА. Звала — ровно одна, и ничем это не
# удерживалось: пропуск под `-short`, отбор пакетов, переименование пробы снимают
# единственного вызывающего МОЛЧА. Здесь цель зовётся ЦЕЛЬЮ, поэтому отбор проб на
# неё не влияет.
#
# Вызов пишется ровно тем же литералом, что и шаг конвейера
# (`make -C services/iam model-canon-check`): обе провязки сверяет ОДИН гейт одним
# выражением, и вторая форма записи уехала бы из-под него невидимой.
model_canon_check() {
    local name="модель доступов: блоки сверены с манифестами побайтово"
    ran=$((ran + 1))
    printf '\n== %s\n' "$name"

    local log rc=0
    log="$WORK/$(printf 'log-%02d-model-canon.txt' "$ran")"
    ( cd "$ROOT" && make -C services/iam model-canon-check ) > "$log" 2>&1 || rc=$?

    case "$rc" in
        0)  echo "   ok" ;;
        2)  printf '   ПРОПУСК: сверять нечего ни для одного модуля — НЕ выполнено\n'
            printf '   | это НЕ «находок нет»: судья не высказывался ни о чём. Манифесты\n'
            printf '   | отслеживаются деревом, поэтому пустой обход означает, что до них\n'
            printf '   | не дошли — смотрите корень обхода, а не форму манифеста\n'
            printf '   | целиком: %s\n' "$log"
            skips+=("$name (сверять нечего)") ;;
        3)  printf '   ПРОПУСК: проверка НЕ ИСПОЛНЯЛАСЬ — вызов разобрать не удалось\n'
            printf '   | вердикта нет ни одного: это не «находок нет» и не «находки есть»\n'
            printf '   | целиком: %s\n' "$log"
            skips+=("$name (вызов не разобран)") ;;
        *)  echo "   ОТКАЗ (код $rc)"
            tail -15 "$log" | sed 's/^/   | /'
            echo "   | целиком: $log"
            fails+=("$name") ;;
    esac
}

run() { # run <имя> <команда...>
    local name="$1"; shift
    ran=$((ran + 1))
    printf '\n== %s\n' "$name"

    # Журнал у КАЖДОЙ проверки свой и остаётся после прогона. Прежде все они писали в
    # один файл, и он доставался следующей: к моменту, когда читаешь отказ, разбирать
    # уже нечего — журнал перезаписан соседом. Плюс на экран идёт только хвост, а
    # инструменты, печатающие координату ПЕРВОЙ строкой и длинную сводку после (tofu
    # test — ровно такой), теряют в этом хвосте имя падения: вердикт остаётся, разбор
    # невозможен. Поэтому путь к целому журналу называется в самом отказе.
    # Порядковый номер в имени — потому что имена проверок русские, а `tr` режет по
    # БАЙТАМ: от многобайтного имени в слаге остаётся вереница дефисов, и два разных
    # отказа получили бы один файл.
    local log slug
    slug="$(printf '%s' "$name" | tr -c 'A-Za-z0-9' '-' | tr -s '-' | sed 's/^-//;s/-$//' | cut -c1-30)"
    log="$WORK/$(printf 'log-%02d-%s.txt' "$ran" "$slug")"

    # Код берётся СРАЗУ и в свою переменную: `if cmd; then …; fi` без `else`
    # возвращает НОЛЬ, когда условие ложно, поэтому `$?` после `fi` — это код
    # самого `if`, а не команды. Отказ печатался бы как «код 0».
    local rc=0
    "$@" > "$log" 2>&1 || rc=$?
    if [ "$rc" -eq 0 ]; then
        echo "   ok"
        return
    fi

    # ЗАНЯТО СОСЕДОМ — ЭТО «НЕ ВЫПОЛНЕНО», А НЕ НАХОДКА (#677).
    #
    # Каталог логов теперь свой у каждой копии, но лок инструмента остаётся
    # ОБЩИМ на машину: golangci-lint отказывается работать, пока идёт другой его
    # экземпляр, — из соседнего дерева, о котором эта проверка ничего не знает.
    #
    # Прежде такой отказ попадал в `fails` и отвергал отправку ветки, где менять
    # было нечего: за одну сессию это случилось трижды, и каждый раз читалось как
    # находка. Между тем прогон не состоялся вовсе — вердикта нет НИ ОДНОГО, и
    # выдавать его за красный значит смешивать третью категорию исхода со второй.
    #
    # Признак узкий и берётся из текста самого инструмента: сюда попадает только
    # отказ по занятости. Любая другая причина остаётся отказом.
    if grep -qiE 'parallel .* is running|another instance|resource temporarily unavailable' "$log"; then
        printf '   ПРОПУСК: инструмент занят другим прогоном на этой машине — НЕ выполнено\n'
        printf '   | вердикта нет ни одного: это не «находок нет» и не «находки есть»\n'
        printf '   | целиком: %s\n' "$log"
        skips+=("$name (занят соседним прогоном)")
        return
    fi

    # РЕСУРС ИСЧЕРПАН — ШАГ ОБОРВАН, ВЕРДИКТА НЕТ (#862). Разбор — в объявлении
    # признаков выше. Здесь важен порядок: проверка идёт ДО того, как отказ
    # запишется в `fails`, иначе имя шага попадёт в строку «красное» и читатель
    # пойдёт искать находку, которой не было.
    if step_aborted_by_exhaustion "$log"; then
        printf '   ПРОПУСК: ресурс исчерпан, шаг ОБОРВАН — НЕ выполнено\n'
        printf '   | %s\n' "$(exhaustion_evidence "$log")"
        printf '   | находок не получено ни одной: инструмент не дошёл до предмета\n'
        printf '   | целиком: %s\n' "$log"
        skips+=("$name (ресурс исчерпан)")
        aborted+=("$name")
        return
    fi

    echo "   ОТКАЗ (код $rc)"
    tail -15 "$log" | sed 's/^/   | /'
    echo "   | целиком: $log"
    fails+=("$name")
}

# ── proto: генерация и совместимость ────────────────────────────────────────
proto_group() {
    local bin="$WORK/protoc-bin"
    mkdir -p "$bin"
    echo "== плагины генерации из модуля (версии как в конвейере)"
    if ! GOBIN="$bin" go install \
        google.golang.org/protobuf/cmd/protoc-gen-go \
        google.golang.org/grpc/cmd/protoc-gen-go-grpc \
        github.com/grpc-ecosystem/grpc-gateway/v2/protoc-gen-grpc-gateway > "$WORK/out.txt" 2>&1; then
        echo "   ОТКАЗ: плагины не поставились"; tail -8 "$WORK/out.txt" | sed 's/^/   | /'
        fails+=("плагины генерации"); return
    fi
    export PATH="$bin:$PATH"

    run "buf lint" bash -c "cd '$ROOT/proto' && buf lint"
    # Та же адъюдикация, что в конвейере, и ТЕМ ЖЕ инструментом — иначе локально и
    # на чужой машине исполнялись бы две разные проверки одного предмета, и разошлись
    # бы они молча: обе отвечают «зелено» на зелёном входе.
    #
    # БАЗА СРАВНЕНИЯ — `origin/main`, А НЕ ЛОКАЛЬНАЯ ВЕТКА `main`.
    #
    # Конвейер сравнивает с `main` НА GITHUB. Локальная ветка `main` в общем клоне
    # живёт своей жизнью: её никто не обязан обновлять, и она отстаёт ровно настолько,
    # насколько давно тут не делали checkout. Сравнение с ней даёт вердикт о другом
    # дереве, причём ошибается в ОБЕ стороны сразу.
    #
    # Замер 2026-08-14, локальная `main` отставала на 78 коммитов: против неё — 29
    # находок и «четыре необъявленных разрыва», по которым была заведена задача;
    # против `origin/main` — 0 находок и 21 истёкшая запись перечня, то есть ровно то,
    # на чём покраснел бы MR в ствол. Отставшая база показывает разрывы, которых нет,
    # и одновременно ПРЯЧЕТ истёкшие послабления: перечень выглядит действующим,
    # потому что сопоставляется с находками, которых в стволе давно нет.
    run "adjudicate breaking (перечень объявленных разрывов)" bash -c '
        set -uo pipefail
        go build -o "'"$WORK"'/adjudicate" ./tools/declaredbreak/cmd/adjudicate-declared-breaks
        cd "'"$ROOT"'/proto"

        # Свежесть базы — предпосылка вердикта, поэтому она проверяется, а не
        # предполагается. Молчаливый откат на локальную ветку запрещён: он вернул бы
        # ровно тот вердикт о другом дереве, ради которого написан этот абзац.
        if git -C "'"$ROOT"'" rev-parse --verify --quiet origin/main >/dev/null; then
            against="'"$ROOT"'/.git#ref=origin/main,subdir=proto"
            behind=$(git -C "'"$ROOT"'" rev-list --count origin/main..main 2>/dev/null || echo 0)
            ahead=$(git -C "'"$ROOT"'" rev-list --count main..origin/main 2>/dev/null || echo 0)
            [ "${ahead:-0}" -gt 0 ] && echo "   (локальная main отстаёт от origin/main на ${ahead} коммитов — сравниваю с origin/main, как конвейер)"
        else
            echo "   ОТКАЗ: origin/main не разрешается — базы сравнения нет." >&2
            echo "   Локальная main ею НЕ является: вердикт был бы о другом дереве." >&2
            echo "   Почините: git fetch origin" >&2
            exit 2
        fi

        set +e
        buf breaking --against "$against" --error-format=json > "'"$WORK"'/buf-breaking.jsonl" 2>"'"$WORK"'/buf-breaking.err"
        rc=$?
        set -e
        case "$rc" in
            0|100) ;;
            *)  echo "buf breaking не сделал своей работы (код $rc) — это НЕ «разрывов нет»" >&2
                cat "'"$WORK"'/buf-breaking.err" >&2 || true
                exit 2 ;;
        esac
        cd "'"$ROOT"'"
        "'"$WORK"'/adjudicate" proto/declared-breaks.yaml < "'"$WORK"'/buf-breaking.jsonl"
    ' 

    ran=$((ran + 1))
    printf '\n== generate-diff (стабы в синхроне с .proto)\n'
    ( cd "$ROOT/proto" && buf generate ) > "$WORK/out.txt" 2>&1
    local dirty
    dirty="$(git -C "$ROOT" status --porcelain pkg/api | wc -l | tr -d ' ')"
    if [ "$dirty" = "0" ]; then
        echo "   ok — стабы совпадают с генерацией"
    else
        echo "   ОТКАЗ: генерация меняет $dirty файл(ов) — стабы собраны другим плагином"
        git -C "$ROOT" diff --stat pkg/api | tail -3 | sed 's/^/   | /'
        # Диагностика, а не совет: у ЭТОГО отказа две причины, и они лечатся
        # противоположно. Дерево устарело — коммить генерацию. Плагин не тот —
        # коммитить НЕЛЬЗЯ, иначе в ствол уедет выход чужой версии.
        echo "   | различить причины:"
        echo "   |   which -a protoc-gen-grpc-gateway            # больше одной строки — уже находка"
        echo "   |   go version -m \"\$(which protoc-gen-grpc-gateway)\"  # версия ИСПОЛНЯЕМОГО файла"
        echo "   | этот прогон ставит плагины из go.mod и кладёт их первыми в PATH,"
        echo "   | поэтому здесь отказ означает УСТАРЕВШЕЕ ДЕРЕВО. Если тот же diff"
        echo "   | получается вызовом buf напрямую — виновата копия плагина в PATH." 
        fails+=("generate-diff")
    fi
}

go_group() {
    # Инъекция производителя набора групп — секунды, и держит она то самое
    # решение, которым этот прогонщик и вызывается. Проба сама доказывает
    # свою способность упасть: гоняет утверждения дважды, против настоящего
    # производителя и против воссозданного дефекта.
    run "hooks: набор групп" bash "$ROOT/scripts/hooks/prepush-groups-inject.sh"
    # Инъекция базы диапазона — та же цена (доли секунды) и то же устройство, но
    # предмет другой: набор групп считает производитель, а ДИАПАЗОН, по которому
    # он считает, выбирает хук. Проба гоняет НАСТОЯЩИЙ pre-push с заглушкой
    # прогонщика и утверждает исход отправки, а не промежуточное значение.
    run "hooks: база диапазона" bash "$ROOT/scripts/hooks/prepush-range-inject.sh"
    # Инъекция САМОЙ ПРОВЯЗКИ (#1051) — предмет четвёртый и он под остальными
    # тремя: два предыдущих проверяют, что хук считает и по какому диапазону, а
    # этот — что хук вообще провязан и что непровязанность ЗАМЕТНА. Общий клон
    # четырнадцати рабочих копий прожил непровязанным неизвестно сколько, и
    # заметить это по исходу отправки нельзя: она проходит молча в обоих
    # случаях. Проба требует от механизма ОБЕИХ способностей — заговорить на
    # непровязанном клоне и смолчать на провязанном.
    run "hooks: провязка" bash "$ROOT/scripts/hooks/install-inject.sh"
    # Инъекция собственной КЛАССИФИКАЦИИ ИСХОДА — те же секунды и то же
    # устройство, но предмет третий: два предыдущих проверяют, ЧТО прогонщика
    # зовут, а этот — как он читает полученное. Проверка, которая сама решает,
    # красное перед ней или несостоявшийся прогон, обязана доказывать это на
    # настоящих текстах инструментов, а не на своём о них представлении.
    run "ci-local: классификация исхода" bash "$ROOT/scripts/ci-local-outcome-inject.sh"
    # Инъекции ЛИНИИ ВЫПУСКА — секунды, и предмет у них общий с соседями выше:
    # доказательство, которого никто не запускает, не отличается от
    # отсутствующего. Механизм публикации стоит перед НЕОБРАТИМЫМ действием
    # (прокси Go кэширует опубликованную версию навсегда), поэтому его
    # способность ОТКАЗАТЬ ценнее любой другой его способности — а на исправном
    # входе выродившаяся предпосылка выглядит точно так же, как работающая.
    #
    # Первая гоняет настоящий механизм по паре «пустой origin + рабочая копия» и
    # утверждает исход, включая то, что механизм НИЧЕГО не создал. Вторая меняет
    # ровно один факт — лежит ли версия в прокси — и показывает, что проба
    # годности зеленеет от ФАКТА публикации, а не от чего-то ещё. Публиковать
    # ради этого не требуется: обе работают на синтетике.
    run "выпуск: предпосылки публикации" bash "$ROOT/scripts/release/publish-version-inject.sh"
    run "выпуск: цвет пробы годности" bash "$ROOT/scripts/release/probe-published-inject.sh"
    # Четыре инъекции ниже пришли вместе с ПРОИЗВОДИТЕЛЕМ операции «поставить
    # версию»: до него линия выпуска существовала механизмами, которых никто не
    # звал, — а механизм без зовущего не отличается от отсутствующего.
    #
    # Предмет у каждой свой, и ни один не покрывается соседом: первая — что
    # зелень ствола спрашивается СВЕРКОЙ ИМЁН, а не счётом (проверка, которая не
    # начиналась, не краснеет, и «ноль проверок» читается как «замечаний нет»);
    # вторая — что точка отсчёта совместимости различает «разрывов нет» и
    # «сравнить не с чем»; третья — что производитель ОТКАЗЫВАЕТ без следа и
    # публикует ровно одну ссылку по вызову; четвёртая — что сводка оператору
    # читает факт на удалённом, а не пересказывает свой вход.
    #
    # Все четыре работают на синтетике: публиковать ради доказательства нельзя,
    # шаг необратим.
    run "выпуск: зелень ствола сверяется по именам" bash "$ROOT/scripts/release/assert-trunk-green-inject.sh"
    run "выпуск: точка отсчёта совместимости" bash "$ROOT/scripts/release/breaking-since-release-inject.sh"
    run "выпуск: производитель отказывает без следа" bash "$ROOT/scripts/release/publish-tag-inject.sh"
    run "выпуск: сводка читает факт, а не вход" bash "$ROOT/scripts/release/summarize-run-inject.sh"
    run "go build" go build ./...
    run "go vet" go vet ./...
    run "go test -short" go test ./... -short -count=1
    # МОДУЛЬ СЛУЖБЫ IAM — ВТОРОЙ ПРОГОН, А НЕ ПОДРАЗУМЕВАЕМЫЙ.
    #
    # Служба iam несёт свой `go.mod`: она выносится отдельным репозиторием и
    # обязана собираться без дерева монорепо на диске. Следствие — корневой
    # `./...` её пакетов НЕ ВИДИТ. Без трёх строк ниже прогон остался бы зелёным,
    # перестав проверять службу вовсе: «ноль находок» стало бы неотличимо от
    # «ноль прочитанного», причём по целому модулю сразу.
    run "iam: go build" go build -C services/iam ./...
    run "iam: go vet" go vet -C services/iam ./...
    run "iam: go test -short" go test -C services/iam ./... -short -count=1
    # Инъекция ЧТЕНИЯ ИСХОДОВ судей-целей (#1851, #1893) — доли секунды, и предмет
    # у неё свой: шаги ниже проверяют, что судей зовут, а этот — что их ответ
    # читают ЧЕТЫРЬМЯ исходами, а не двумя. Способность различать наблюдается на
    # дереве продукта только в одном случае из четырёх, поэтому «зелёный» там
    # неотличим от «мёртвый»; проба гоняет набор дважды на КАЖДОГО судью — против
    # настоящего классификатора и против копии, где VOID схлопнут в успех.
    #
    # Судей два, и проба одна: копия харнесса разошлась бы с первой молча и
    # разошлась бы там, где обе зелены. Функция, которой в этом файле нет, роняет
    # пробу кодом 2 — перечень судей истекает вместе со своим предметом.
    run "судьи целей: чтение исходов" bash "$ROOT/scripts/judge-outcome-inject.sh"
    # Судья формы манифеста домена — ОТДЕЛЬНЫМ шагом, и это не оформление.
    # Гоняется он не пробой, а целью сборки, поэтому `go test` выше его не зовёт
    # НИ ПРИ КАКОМ ОТБОРЕ: его зелёное о манифестах не говорило бы ничего. До #1851
    # цель не звал вообще никто — ни здесь, ни в конвейере, — и ось, которую судит
    # только она, не встречала ни одной автоматической проверки.
    manifest_form_check
    # Судья ПОБАЙТОВОЙ сверки модели с манифестами — тоже отдельным шагом, и по
    # той же причине (#1893). До провязки его звала ровно одна проба, попадавшая
    # в `go test -short` выше; отбор пакетов или её переименование сняли бы
    # единственного вызывающего молча. Цель зовётся ЦЕЛЬЮ — отбор проб на неё не
    # влияет.
    model_canon_check
    # Здесь стояли ещё три «провайдер: …» — те же build/vet/test, вызванные из
    # terraform/, — и объяснялись тем, что провайдер живёт ОТДЕЛЬНЫМ модулем, куда
    # корневой ./... не спускается. Провайдер сведён в общий модуль, поэтому
    # команды выше его уже видят, а те три стали повтором.
    #
    # Утверждение «модуль в дереве один» здесь стояло рядом и БОЛЬШЕ НЕВЕРНО:
    # модулей два (предикат: `git ls-files '*go.mod'` → две строки, корень и
    # services/iam). Довод от этого не пострадал — он был про провайдера, — но
    # само утверждение пережило свой предмет и потому переписано, а не оставлено
    # «почти верным»: следующий читатель вывел бы из него, что второго прогона не
    # требуется.
    #
    # Цикл terraform ими всё равно не исполнялся: он в группе terraform ниже.

    if command -v golangci-lint > /dev/null; then
        # Кэш линтера привязывается к КОРНЮ ЭТОЙ копии. Общий кэш между рабочими
        # копиями отравляет результат: линтер отдаёт вердикт, посчитанный по
        # чужому дереву, и «зелено» перестаёт что-либо значить.
        mkdir -p "$ROOT/.cache/golangci-lint"
        GOLANGCI_LINT_CACHE=$PWD/.cache/golangci-lint run "golangci-lint" golangci-lint run
        # Линтер работает В ГРАНИЦАХ МОДУЛЯ: прогон выше пакетов службы iam не
        # осматривает вовсе, и позвать его из корня нельзя — путь `services/iam/...`
        # корневым модулем не резолвится. Поэтому прогон идёт ИЗ каталога службы,
        # с той же — единственной на дерево — конфигурацией по абсолютному пути.
        GOLANGCI_LINT_CACHE=$PWD/.cache/golangci-lint run "iam: golangci-lint" \
            bash -c 'cd "$1/services/iam" && golangci-lint run --config "$1/.golangci.yml"' _ "$ROOT"
    else
        skip "golangci-lint" "не установлен"
    fi

    # gosec запускается В ТОЙ ЖЕ ФОРМЕ, что в конвейере, и «та же форма» — это
    # ЧЕТЫРЕ вещи разом, а не одна. Каждая добавлена своим расхождением, которое
    # уже случилось; порознь любое из них оставляло локальный вердикт верным «в
    # целом» и неверным по существу.
    #
    # 1. ВЕРСИЯ. Конвейер ставит пин (`security-scan.yml`, шаг «install gosec»);
    #    прежняя редакция брала то, что лежит в PATH. Замер 2026-08-14: в PATH был
    #    2.22.10 против пина v2.28.0, и правило G115 у них срабатывает по-разному.
    # 2. ПРЕДИКАТ. Конвейер гейтит по SARIF `level == "error"`; код возврата gosec
    #    ненулевой при находке ЛЮБОГО уровня. Что эти предикаты расходятся, записано
    #    в самом `security-scan.yml`: «локальная проверка „severity HIGH“ показывала
    #    0, пока CI честно краснел». Здесь тот же класс в обратную сторону.
    # 3. ИСКЛЮЧЕНИЕ КАТАЛОГА — единственное, что совпадало и раньше.
    # 4. ОБЛАСТЬ. Прежняя редакция несла СВОЙ перечень модулей, выписанный руками.
    #    Он совпадал с деревом ровно до следующего модуля — а область гейта
    #    конвейера на этом же классе уже разошлась с деревом молча (#2092).
    #
    # Сегодня «та же форма» — не сходство, а тождество: прогон и здесь, и в
    # конвейере идёт ОДНИМ скриптом (scripts/gosec-scan-modules.sh), поэтому
    # разойтись по области они больше не могут by construction.
    #
    # Цена расхождения измерена на объединённой волне: по коду возврата — шесть
    # находок и красное, по предикату конвейера — ноль ошибок при семи результатах
    # ниже порога. Ложное красное учит игнорировать локальный прогон, а он —
    # единственное, что стоит между правкой и стволом: PR внутрь релизной ветки
    # конвейером не проверяется.
    #
    # Отдельно: gosec читает `#nosec`, а НЕ `//nolint:gosec`. Второе здесь не
    # подавляет ничего, и снятие такого комментария открывает настоящую находку.
    local gosec_pin gosec_bin
    gosec_pin=$(grep -oE 'gosec/v2/cmd/gosec@v[0-9.]+' "$ROOT/.github/workflows/security-scan.yml" 2>/dev/null | head -1)
    if ! command -v jq > /dev/null; then
        # Без jq предикат конвейера не вычислить, а откатываться на код возврата
        # нельзя: он отвечает на другой вопрос и даёт ложное красное. Пропуск
        # называется пропуском — «не выполнено» не есть «находок нет».
        skip "gosec" "нет jq, предикат конвейера (SARIF level=error) не вычислить"
        echo "   Проверка НЕ выполнена. Поставьте jq — откат на код возврата дал бы"
        echo "   красное на находках ниже порога, то есть вердикт о другом вопросе."
    elif [ -z "$gosec_pin" ]; then
        echo -e "\n== gosec\n   ОТКАЗ: пин версии не найден в security-scan.yml —"
        echo "   без него локальный прогон судил бы другой версией, чем конвейер"
        fails+=("gosec: пин не найден")
    else
        gosec_bin="$WORK/gosec-bin"
        printf '\n== gosec (%s, как в конвейере)\n' "${gosec_pin##*@}"
        if GOBIN="$gosec_bin" go install "github.com/securego/${gosec_pin}" > "$WORK/gosec-install.txt" 2>&1; then
            ran=$((ran + 1))
            # Гейт — по SARIF level=error, тем же jq-предикатом, что в конвейере.
            # Код возврата gosec здесь НЕ вердикт: он ненулевой и при находках
            # ниже порога, то есть отвечает на другой вопрос.
            # Перечень модулей и сам прогон — ОДНИМ определением с конвейером
            # (scripts/gosec-scan-modules.sh). Прежде здесь стоял СВОЙ список из
            # двух модулей, выписанный руками рядом с корневым `./...`: он
            # разошёлся бы с деревом молча — ровно тем способом, каким разошлась
            # область гейта конвейера, когда модулей стало два. Третий модуль
            # попадёт под оба прогона в тот же коммит, которым заведётся.
            GOSEC_BIN="$gosec_bin/gosec" GOSEC_OUT="$WORK" \
                "$ROOT/scripts/gosec-scan-modules.sh" > "$WORK/gosec-run.txt" 2>&1
            if [ ! -s "$WORK/gosec.sarif" ] || [ -f "$WORK/gosec-scan-failed" ]; then
                echo "   ОТКАЗ: скан не дошёл до вердикта, и это НЕ «находок нет»."
                echo "   Непрочитанный модуль неотличим от чистого — вердикт не выносится."
                [ -f "$WORK/gosec-scan-failed" ] && sed 's/^/   | /' "$WORK/gosec-scan-failed"
                tail -5 "$WORK/gosec-run.txt" | sed 's/^/   | /'
                fails+=("gosec: отчёт не создан")
            else
                local errs total
                errs=$(jq '[.runs[].results[]|select(.level=="error")]|length' "$WORK/gosec.sarif")
                total=$(jq '[.runs[].results[]]|length' "$WORK/gosec.sarif")
                # Перепись — отдельное утверждение: «ноль ошибок» обязано быть
                # отличимо от «ноль прочитанного», и назвать объём надо ПО
                # МОДУЛЯМ: одно суммарное число скрывает непрочитанную половину.
                sed 's/^/   | модуль /' "$WORK/gosec-census.txt"
                echo "   осмотрено результатов ${total}; из них level=error: ${errs}"
                if [ "$errs" -eq 0 ]; then
                    echo "   ok"
                else
                    jq -r '.runs[].results[]|select(.level=="error")|"   | \(.ruleId) \(.locations[0].physicalLocation.artifactLocation.uri):\(.locations[0].physicalLocation.region.startLine)"' "$WORK/gosec.sarif"
                    fails+=("gosec (level=error)")
                fi

                # У ПОДАВЛЕНИЯ ОБЯЗАН БЫТЬ ПРЕДМЕТ — тот же гейт, что в
                # конвейере (security-scan.yml, шаг «у подавлений gosec ещё есть
                # предмет»). Вердикт по находкам его не отменяет и не заменяет:
                # директива, под которой правило больше не срабатывает, не
                # оставляет в отчёте выше НИКАКОГО следа, поэтому её не видно ни
                # при каком числе находок.
                #
                # Исходов три, и они читаются по КОДУ ВОЗВРАТА, а не по виду
                # вывода: 1 — находки, 2 — гейт не смог вынести вердикт
                # (перепись подавлений не снята, распознаватель разошёлся со
                # сканером). Второе в зелёное не засчитывается.
                # Бинарь собирается, а не зовётся через `go run`: тот схлопывает
                # любой ненулевой код в единицу, и третий исход стал бы
                # неотличим от находки — ровно то, что этот case и различает.
                local subj_rc=0
                go build -o "$WORK/gosec-subject" \
                    "$ROOT/tools/gosecsubject/cmd/verify-gosec-suppression-subject" \
                    > "$WORK/gosec-subject.txt" 2>&1 || subj_rc=$?
                if [ "$subj_rc" -eq 0 ]; then
                    subj_rc=0
                    "$WORK/gosec-subject" "$ROOT" "$WORK" > "$WORK/gosec-subject.txt" 2>&1 || subj_rc=$?
                else
                    subj_rc=2
                fi
                sed 's/^/   | /' "$WORK/gosec-subject.txt"
                case "$subj_rc" in
                    0) echo "   ok (подавления gosec: у каждого есть предмет)" ;;
                    1) fails+=("gosec: подавление без предмета") ;;
                    *) echo "   ОТКАЗ: гейт предмета НЕ ВЫНЕС вердикта (код $subj_rc)"
                       fails+=("gosec: гейт предмета не выполнен") ;;
                esac
            fi
        else
            echo "   ОТКАЗ: пиннутый gosec не поставился — проверка НЕ выполнена"
            tail -5 "$WORK/gosec-install.txt" | sed 's/^/   | /'
            fails+=("gosec: установка")
        fi
    fi
}

# ── terraform: конфигурации и приёмка провайдера ────────────────────────────
#
# ЧТО ЭТО ЗАКРЫВАЕТ. Файлы .tf не компилируются ничем: `go build` их не читает, и
# опечатка в связывании ресурсов доезжает до первого apply у пользователя. Go-сторона
# провайдера, наоборот, покрыта группой go выше — но она молчит о том, как ресурс ведёт
# себя под НАСТОЯЩИМ terraform: план, повторный план, пересоздание, импорт, уборка.
#
# ПОЧЕМУ СВОЙ ЭКЗЕМПЛЯР tofu, А НЕ ИЗ PATH. Вердикт имеет смысл, только если инструмент
# и версия те же, что в конвейере. Чужой tofu из PATH дал бы вердикт о другом
# инструменте — и разошёлся бы с конвейером молча, потому что на зелёном входе оба
# отвечают «зелено». Версия ниже — тот же пин, что у конвейера, и за их расхождением
# следит .github/scripts/check-pinned-tools.sh.
TOFU_VERSION=1.12.5

terraform_group() {
    local bin="$WORK/tofu-bin" tofu
    tofu="$bin/tofu"

    # Версия читается подстановкой, первая строка берётся раскрытием параметра:
    # `… | head -1 | grep -qF` под `pipefail` даёт отказ на СОВПАДЕНИИ (оба звена
    # выходят до конца входа, писатель получает SIGPIPE) — задача #658.
    local tofu_ver=""
    if [ -x "$tofu" ]; then
        tofu_ver="$("$tofu" version 2>/dev/null || true)"
        tofu_ver="${tofu_ver%%$'\n'*}"
    fi
    if [ ! -x "$tofu" ] || [[ "$tofu_ver" != *"v$TOFU_VERSION"* ]]; then
        local os arch
        case "$(uname -s)" in
            Linux)  os=linux ;;
            Darwin) os=darwin ;;
            *) skip "tofu" "$(uname -s) не поддержан этим прогоном"; return ;;
        esac
        case "$(uname -m)" in
            x86_64|amd64)  arch=amd64 ;;
            aarch64|arm64) arch=arm64 ;;
            *) skip "tofu" "$(uname -m) не поддержан этим прогоном"; return ;;
        esac

        printf '\n== tofu %s (%s_%s) — тот же артефакт, что ставит конвейер\n' "$TOFU_VERSION" "$os" "$arch"
        mkdir -p "$bin"
        if ! curl -fsSL -o "$WORK/tofu.zip" \
            "https://github.com/opentofu/opentofu/releases/download/v${TOFU_VERSION}/tofu_${TOFU_VERSION}_${os}_${arch}.zip" > "$WORK/tofu-install.txt" 2>&1 \
            || ! unzip -oq "$WORK/tofu.zip" -d "$bin" >> "$WORK/tofu-install.txt" 2>&1; then
            echo "   ОТКАЗ: tofu $TOFU_VERSION не поставился — НИ ОДНА проверка конфигураций НЕ выполнена"
            tail -8 "$WORK/tofu-install.txt" | sed 's/^/   | /'
            fails+=("tofu не поставился"); return
        fi
        echo "   ok"
    fi
    # Свой экземпляр — ПЕРВЫМ: он же достаётся приёмочным пробам, которые ищут
    # исполнителя в PATH.
    export PATH="$bin:$PATH"

    # Пробы гоняются против ТОГО ЖЕ провайдера, что собирается из этого дерева, а не
    # против опубликованного: иначе они судили бы чужую версию.
    mkdir -p "$WORK/tf-plugins"
    if ! go build -o "$WORK/tf-plugins/terraform-provider-kacho" \
        ./terraform/cmd/terraform-provider-kacho > "$WORK/tofu-install.txt" 2>&1; then
        echo -e "\n== провайдер для tofu\n   ОТКАЗ: не собрался — проверки конфигураций НЕ выполнены"
        tail -8 "$WORK/tofu-install.txt" | sed 's/^/   | /'
        fails+=("провайдер для tofu"); return
    fi
    cat > "$WORK/tofu.tfrc" <<RC
provider_installation {
  dev_overrides { "PRO-Robotech/kacho" = "$WORK/tf-plugins" }
  direct {}
}
RC
    export TF_CLI_CONFIG_FILE="$WORK/tofu.tfrc"

    run "формат .tf" tofu fmt -check -recursive terraform
    run "модульные пробы (tofu test)" tofu_modules
    run "примеры разбираются и сходятся по типам" tofu_examples
    # Приёмка провайдера: полный цикл terraform против поддельного края в том же
    # процессе. Исполнителя пробы находят сами — он выше положен в PATH.
    run "приёмка провайдера (цикл terraform)" go test ./terraform/internal/provider -run Acceptance -count=1
}

# Перечень модулей ВЫВОДИТСЯ из дерева, а не выписывается: рукописный список разошёлся
# бы с деревом молча, и новый модуль приехал бы непроверенным. Ноль модулей — ОТКАЗ, а
# не успех: обходчику, которому нечего обходить, положено быть отличимым от того, у кого
# всё сошлось. Печатается объём осмотренного.
tofu_modules() {
    local modules m suites seen=0
    modules=$(git ls-files 'terraform/modules/*/main.tf' | xargs -r -n1 dirname | sort -u)
    if [ -z "$modules" ]; then
        echo "модулей terraform не найдено — предикат поиска устарел или каталог переехал" >&2
        return 1
    fi
    for m in $modules; do
        suites=$(git ls-files "$m/tests/*.tftest.hcl" | wc -l)
        if [ "$suites" -eq 0 ]; then
            echo "$m/main.tf: модуль без модульных проб — заведите $m/tests/*.tftest.hcl" >&2
            return 1
        fi
        echo "── $m ($suites сюит)"
        ( cd "$m" && tofu test -no-color ) || return 1
        seen=$((seen + 1))
    done
    echo "модулей осмотрено: $seen"
}

# Примеры — то, что читатель копирует первым. Непроверяемый пример устаревает тише
# всего: он не собирается ничем и не падает нигде.
tofu_examples() {
    local examples e seen=0
    examples=$(git ls-files 'terraform/examples/*/main.tf' | xargs -r -n1 dirname | sort -u)
    if [ -z "$examples" ]; then
        echo "примеров terraform не найдено — предикат поиска устарел" >&2
        return 1
    fi
    for e in $examples; do
        # `tofu get`, а НЕ `tofu init`: провайдер здесь приходит подменой пути
        # (dev_overrides), и init на нём выходит с кодом 1, потому что честно не находит
        # его в реестре. Глушить этот код было бы мягким проходом, не отличающим
        # настройку от сбоя; `get` ставит только модули и таким вопросом не задаётся.
        ( cd "$e" && tofu get -no-color && tofu validate -no-color ) || return 1
        seen=$((seen + 1))
    done
    echo "примеров осмотрено: $seen"
}

helm_group() {
    if ! command -v helm > /dev/null; then
        skip "helm" "не установлен"; return
    fi

    # ВЕРСИЯ HELM СВЕРЯЕТСЯ С ПИНОМ КОНВЕЙЕРА — И ПИН ЧИТАЕТСЯ ИЗ ОБЪЯВЛЕНИЯ (#650).
    #
    # Содержимое рендера решает ВЕРСИЯ инструмента, а не наличие команды. Класс уже
    # закрывали для плагинов генерации (они ставятся из модуля), а helm остался
    # системным — и мажоры разошлись: на машине 3.17, в конвейере 4.2.3. Расхождение
    # не косметическое: на 3.17 рендер умбреллы проходит БЕЗ подкачанных подчартов,
    # на 4.2.3 — падает. То есть локальный прогон и конвейер отвечали на разные
    # вопросы, а видно это становилось только когда конвейер краснел.
    #
    # Пин НЕ выписывается сюда вторым числом: он берётся из самих рабочих процессов,
    # иначе разойдётся молча — ровно как расходились рукописные перечни до него.
    local want have
    # Опознаём шаг по имени ДЕЙСТВИЯ (`setup-helm`), а не по имени его издателя:
    # второй non-negotiable запрещает называть в этом дереве чужие облака, и гейт
    # `tools/foreignclouds` справедливо покраснел на первой редакции. Заводить
    # исключение ради одной строки не понадобилось — предикату издатель не нужен.
    want="$(awk '/setup-helm/{f=1} f&&/version:/{gsub(/[^v0-9.]/,"",$2); print $2; exit}' \
        "$ROOT/.github/workflows/ci.yaml" 2>/dev/null)"
    have="$(helm version --short 2> /dev/null | sed 's/+.*//')"
    if [ -z "$want" ]; then
        skip "helm: сверка версии с конвейером" "пин не найден в ci.yaml — сверять не с чем"
    elif [ "$want" != "$have" ]; then
        printf '\n== helm: версия против пина конвейера\n'
        printf '   ОТКАЗ: локально %s, конвейер пинит %s — вердикт был бы о другом инструменте\n' \
            "${have:-неизвестно}" "$want"
        printf '   | мажоры helm расходятся в обработке зависимостей и значений;\n'
        printf '   | поставьте пиненную версию либо гоняйте эту группу в конвейере\n'
        ran=$((ran + 1)); fails+=("helm: версия против пина конвейера")
        return
    else
        run "helm: версия совпадает с пином конвейера ($want)" true
    fi
    # ПЕРЕЧЕНЬ — ТОТ ЖЕ, ЧТО В КОНВЕЙЕРЕ (`ci.yaml`, шаг «lint сервисных чартов»),
    # и это не косметика: он разошёлся в ОБЕ стороны сразу.
    #
    #  - лишним был зонтичный чарт. Конвейер его НЕ линтит — он проверяет его
    #    РЕНДЕРОМ С ПРОФИЛЕМ, потому что голый линт красен на исправном дереве:
    #    локальные подчарты лежат в `charts/` каталогами и не объявлены
    #    зависимостями, а `.Values.<сервис>.networkPolicy` без профиля пуст.
    #    Локальный прогон изобрёл проверку, которой в конвейере нет, и она
    #    краснела всегда — то есть переставала быть сигналом;
    #  - недоставало чарта консоли (`ui-future/deploy`): конвейер его линтит, а
    #    локальный прогон не смотрел вовсе. Расхождение в эту сторону тише и
    #    хуже: оно не краснеет, оно молчит.
    local c
    for c in "$ROOT"/services/*/deploy "$ROOT"/gateway/deploy "$ROOT"/ui-future/deploy; do
        [ -f "$c/Chart.yaml" ] || continue
        run "helm lint $(basename "$(dirname "$c")")" helm lint "$c"
    done

    # Зонтичный чарт — РЕНДЕРОМ ПО ТАБЛИЦЕ СТЕКОВ, как в конвейере. Зависимости
    # материализует ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ (`deploy/scripts/helm-umbrella-deps.sh`),
    # а не голый `helm dependency build`: подкачка сетевая и полная (22
    # объявления, полный проход около трёх с половиной минут), владелец её
    # пропускает, когда подкачивать нечего. Свойство «владелец один» держит
    # гейт `deploy/helm_deps_single_owner_test.go` — звать helm здесь напрямую
    # значит завести седьмое место и уронить его.
    #
    # Сеть может быть недоступна, и это «условие не создано», а не отказ:
    # пропуск назван причиной и виден третьим числом итога.
    local umb="$ROOT/deploy/helm/umbrella"
    if [ -f "$umb/Chart.yaml" ] && [ -x "$ROOT/deploy/scripts/helm-umbrella-deps.sh" ]; then
        if bash "$ROOT/deploy/scripts/helm-umbrella-deps.sh" > "$WORK/umbrella-deps.txt" 2>&1; then
            run "umbrella template — каждый стек таблицы" bash -c "
                set -euo pipefail
                cd '$umb'
                n=0
                for stack in \$(bash ../../tests/helm/stacks.sh --names); do
                    args=\"\$(bash ../../tests/helm/stacks.sh --args \"\$stack\")\"
                    # shellcheck disable=SC2086
                    helm template ci . \$args > /dev/null
                    n=\$((n + 1))
                done
                [ \"\$n\" -ge 1 ] || { echo 'не отрендерено НИ ОДНОГО стека'; exit 1; }
                echo \"осмотрено: стеков \$n\""
        else
            skip "umbrella template" "зависимости умбреллы не материализованы (сеть?) — см. $WORK/umbrella-deps.txt"
        fi
    fi
    # Манифест-проверки посадки — здесь нас ловило чаще всего: они читают ДЕРЕВО
    # (классификацию отказов, круг отправителей, привязку пода к настройкам), а не
    # только рендер, поэтому краснеют на правках скриптов и профилей.
    if [ -f "$ROOT/deploy/Makefile" ]; then
        run "манифест-проверки посадки (deploy/tests/helm)" bash -c "cd '$ROOT/deploy' && make helm-manifest-test"
    fi
}

# Есть ли у пакета такой скрипт. ВЫВОДИТСЯ ИЗ package.json, а не из списка имён
# пакетов: выписанный перечень («shared — библиотека») разошёлся бы с деревом
# молча, ровно как разошлись три рукописных списка репозиториев до него. Пакет
# сам объявляет, что у него есть; прогонщику остаётся это прочитать.
has_npm_script() { # has_npm_script <каталог> <скрипт>
    node -e 'const s=(require(process.argv[1]).scripts)||{};process.exit(s[process.argv[2]]?0:1)' \
        "$1/package.json" "$2" 2> /dev/null
}

# Готов ли пакет к прогону — ВЫВОДИТСЯ ИЗ ДЕРЕВА, а не по наличию собственного
# `node_modules`.
#
# Консоль — npm-workspaces: у членов (`shared`, `vpc`, `iam`, `system`) своего
# каталога зависимостей НЕТ by construction, всё лежит в корне `ui-future`.
# Проверка «есть ли node_modules у модуля» объявляла их неустановленными ВСЕГДА
# — то есть четыре модуля, включая три единственных исполнителя проб общего
# кода, не проверялись ни разу, а итог честно печатал их в «не выполнено», и это
# читалось как временная нехватка зависимостей.
#
# Перечень членов берётся из корневого package.json: выписанный список разошёлся
# бы с деревом молча, как уже расходились три рукописных перечня репозиториев.
#
# ПРЕДИКАТ ЖИВЁТ В ОДНОМ МЕСТЕ — `ui-future/scripts/deps-ready.mjs`. Здесь стояла
# его вторая копия на bash, и вторая она была не для красоты: тот же вопрос
# задаёт `pretest` каждого пакета консоли, чтобы прямой `npm test` отвечал
# «условие не создано», а не `MODULE_NOT_FOUND`, неотличимым от красного. Две
# копии разошлись бы молча и именно там, где расхождение не видно: оба ответа
# выглядят правдоподобно, а неверный объявляет готовым то, что не готово.
npm_deps_ready() { # npm_deps_ready <каталог модуля>
    node "$ROOT/ui-future/scripts/deps-ready.mjs" "$1" > /dev/null 2>&1
}

# ui_types_group — ТОЛЬКО проверка типов консоли, без проб и сборки.
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ `ui`. Полная группа медленная (пробы трёх модулей — минуты),
# поэтому в хук отправки её не поставишь, и правка консоли уезжала в конвейер
# вообще без проверки. Дважды подряд это стоило круга: пробы были зелёными на
# 5443 утверждениях, а строгая проверка типов роняла линт, typecheck и сборку
# СЕМИ модулей плюс образ консоли — из-за одного объявления, оставшегося без
# читателя. Пробы такого не ловят by construction: они типы не проверяют.
#
# Проверка типов дешёвая (десятки секунд) и ловит ровно этот класс, поэтому
# место ей — перед отправкой, а не в конвейере.
ui_types_group() {
    local m
    if ! command -v node > /dev/null; then
        skip "ui-types" "node не установлен"; return
    fi
    for m in "$ROOT"/ui-future/*/package.json; do
        local dir name; dir="$(dirname "$m")"; name="$(basename "$dir")"
        npm_deps_ready "$dir" || { skip "ui-types $name" "зависимости не установлены (npm ci --prefix)"; continue; }
        if has_npm_script "$dir" typecheck; then
            run "ui-types $name" bash -c "cd '$dir' && npm run typecheck"
        else
            skip "ui-types $name" "скрипта нет в package.json"
        fi
    done
}

ui_group() {
    local m
    if ! command -v node > /dev/null; then
        skip "ui" "node не установлен"; return
    fi
    for m in "$ROOT"/ui-future/*/package.json; do
        local dir name; dir="$(dirname "$m")"; name="$(basename "$dir")"
        npm_deps_ready "$dir" || { skip "ui $name" "зависимости не установлены (npm ci --prefix)"; continue; }
        # Прогон проб НЕ заменяет сборку: сборка гоняет строгую проверку типов и
        # роняет то, что пробы пропускают (неиспользованный импорт — реальный
        # случай). Поэтому обе, и в этом порядке.
        #
        # ОТСУТСТВИЕ СКРИПТА — НЕ ОТКАЗ (#589). `shared` — библиотека: своей сборки
        # у него нет, а его пробы исполняются модулями-workspace (vpc, iam, system),
        # которые включают `../shared/src` в свои roots. Прогонщик звал у него все
        # три скрипта и получал два «Missing script» — то есть краснел ВСЕГДА, на
        # исправном дереве. Прогон, красный по построению, перестаёт быть сигналом:
        # следующий, кто увидит его красным, спишет на «оно и так красное».
        #
        # Пропуск при этом ВИДЕН: он идёт третьим числом итога и назван поимённо,
        # поэтому «у пакета нет скрипта» нельзя прочитать как «пакет проверен».
        # Снятый по ошибке `test` у продуктового модуля тоже попадёт сюда — молча
        # исчезнуть из прогона он не может.
        local s
        # `format:check` СТОИТ ЗДЕСЬ С #1653, и повод тот же, что у соседей по
        # циклу: девять пакетов объявляли проверку формата, а звать её было
        # некому — производителей у скрипта во всём дереве было НОЛЬ (контроль тем
        # же предикатом: у `typecheck` их семь). Расхождение копилось невидимо и
        # набрало 22 файла в семи пакетах из девяти, прежде чем его кто-то позвал
        # руками. Проверка идёт первой как самая дешёвая; отсутствие скрипта
        # (`shared`, `e2e`) по-прежнему НЕ отказ, а видимый пропуск — третьим
        # числом итога и поимённо.
        #
        # Число «22» получено КАЖДЫМ пакетом в его СОБСТВЕННОЙ закреплённой версии
        # prettier: судей тогда было три (3.8.3 · 3.9.4 · 3.9.6), и они не
        # согласны между собой — один и тот же файл одна версия принимает, другая
        # отвергает. Судья сведён к одному задачей #1674: версия объявлена ТОЧНО
        # (без каретки) и одинаково всеми девятью пакетами, замки разрешают ровно
        # её. Поэтому сегодня замер по всем девяти сравним между пакетами, а
        # свойство держит гейт internal/repohygiene/consoleformatterversion_test.go.
        for s in format:check typecheck test build; do
            # ПРОБЫ БРАУЗЕРОМ ТРЕБУЮТ РАЗВЁРНУТОГО СТЕНДА, и его отсутствие — это
            # «условие не создано», а НЕ отказ. Их конфигурация отказывается
            # стартовать без адреса намеренно (умолчание увело бы пробы на
            # несуществующий адрес, и «не выполнилось» читалось бы как «красное»)
            # — значит в прогоне без стенда этот шаг красный ВСЕГДА, на любом
            # дереве. Тот же класс, что двумя абзацами выше: прогон, красный по
            # построению, перестаёт быть сигналом.
            #
            # Признак читается ИЗ ДЕРЕВА — наличие конфигурации проб браузером, —
            # а не из имени пакета: выписанное имя разошлось бы с деревом молча.
            # Пропуск виден третьим числом итога и назван причиной, поэтому
            # «стенда не было» нельзя прочитать как «пробы прошли».
            if [ "$s" = "test" ] && [ -f "$dir/playwright.config.ts" ] && [ -z "${KACHO_CONSOLE_URL:-}" ]; then
                skip "ui $name: $s" "стенда нет: KACHO_CONSOLE_URL не задан — пробы браузером требуют развёрнутой консоли"
                continue
            fi
            if has_npm_script "$dir" "$s"; then
                run "ui $name: $s" bash -c "cd '$dir' && npm run $s"
            else
                skip "ui $name: $s" "скрипта нет в package.json"
            fi
        done
    done
}

case "$GROUP" in
    proto)     proto_group ;;
    go)        go_group ;;
    terraform) terraform_group ;;
    helm)      helm_group ;;
    ui)        ui_group ;;
    ui-types)  ui_types_group ;;
    all)       proto_group; go_group; terraform_group; helm_group; ui_group ;;
    # Несколько групп через пробел: хук отправки гоняет быстрые, но не медленные.
    *)
        ok=1
        for g in $GROUP; do
            case "$g" in
                proto)     proto_group ;;
                go)        go_group ;;
                terraform) terraform_group ;;
                helm)      helm_group ;;
                ui)        ui_group ;;
                ui-types)  ui_types_group ;;
                *) echo "неизвестная группа: $g (proto|go|terraform|helm|ui|ui-types|all)" >&2; ok=0 ;;
            esac
        done
        [ "$ok" = "1" ] || exit 2
        ;;
esac

printf '\n== итог: проверок исполнено %d, отказов %d, НЕ выполнено %d\n' \
    "$ran" "${#fails[@]}" "${#skips[@]}"
if [ "${#skips[@]}" -gt 0 ]; then
    # Третье число печатается ВСЕГДА, когда оно ненулевое, и называет пропущенное
    # поимённо: две цифры вместо трёх не сообщали, что часть предметов никто не
    # смотрел, и «исполнено 24, отказов 0» читалось как полный зелёный.
    printf '   не выполнено: %s\n' "${skips[*]}"
fi
# ПРОГОН, ОБОРВАННЫЙ ИСЧЕРПАНИЕМ, НЕ КРАСНЫЙ И НЕ ЗЕЛЁНЫЙ — ОН НЕДЕЙСТВИТЕЛЕН.
# Код возврата ненулевой (третий исход не зачитывается в успех), но ОТДЕЛЬНЫЙ:
# отправлять по нему нечего чинить, и текст обязан это сказать раньше, чем читатель
# откроет журналы. Обычный пропуск («предмета нет») кода не меняет — иначе прогон
# группы ui стал бы ненулевым на исправном дереве, и на третий день его перестали
# бы читать.
if [ "${#aborted[@]}" -gt 0 ]; then
    printf '   ПРОГОН НЕДЕЙСТВИТЕЛЕН: ресурс исчерпан на %d шаг(ах) — %s\n' \
        "${#aborted[@]}" "${aborted[*]}"
    printf '   Вердикта нет НИ У ОДНОГО шага, включая прошедшие: инструмент оборвался,\n'
    printf '   не дойдя до предмета, и «находок нет» здесь означает «не смотрели».\n'
    printf '   Это условие не создано, а не находка — в дереве чинить нечего.\n'
    printf '   Освободите ресурс и повторите прогон целиком.\n'
fi
if [ "${#fails[@]}" -gt 0 ]; then
    printf '   красное: %s\n' "${fails[*]}"
    if [ "${#aborted[@]}" -gt 0 ]; then
        printf '   (получено в НЕДЕЙСТВИТЕЛЬНОМ прогоне: находка остаётся находкой,\n'
        printf '    но молчание прочих шагов не означает, что там чисто)\n'
    fi
    exit 1
fi
if [ "${#aborted[@]}" -gt 0 ]; then
    exit 3
fi
echo "   Здесь НЕ проверялись: сквозные прогоны на поднятом стенде, интеграция с"
echo "   контейнерами (go test без -short), доказательства посадки. «Локально"
echo "   зелено» не означает «конвейер зелёный» — оно означает ровно исполненное выше."
