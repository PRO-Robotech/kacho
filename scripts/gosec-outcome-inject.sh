# gosec-outcome-inject.sh — три исхода скана и вердикта, доказанные ИСПОЛНЕНИЕМ.
#
# ПРЕДМЕТ (#2125)
#
# `scripts/gosec-scan-modules.sh` печатал «анализ не запускался» и выходил
# НУЛЁМ. Третья категория схлопывалась в успех: вердикта не было ни у одного
# файла — включая те, что скан прошёл бы, — а читающий код возврата получал
# зелёное там, где не смотрели вовсе.
#
# Утверждение «теперь исходов три» о ТЕКСТЕ скрипта ничего не стоит: ровно так
# третья категория и схлопнулась, оставаясь на вид написанной. Поэтому она
# проверяется исполнением настоящих скриптов.
#
# ЧТО ПОДМЕНЯЕТСЯ — РОВНО ОДИН ФАКТ НА СЛУЧАЙ
#
#   · наличие инструмента     — `GOSEC_BIN` указывает на несуществующий путь;
#   · содержимое его отчёта   — подставной сканер пишет SARIF без находок либо
#                               с одной находкой `level=error`.
#
# Всё остальное — настоящее: те же скрипты, тот же перечень модулей из индекса
# git, та же перепись, тот же `jq`-предикат. Подставной сканер повторяет ровно
# тот вывод, по которому скан снимает перепись (`Files :`, `Lines :`), и пишет
# оба отчёта — блокирующий и перепись подавлений.
#
# ПОЧЕМУ НЕ ПИННУТЫЙ НАСТОЯЩИЙ GOSEC. Предмет пробы — РАЗЛИЧЕНИЕ ИСХОДОВ, а не
# множество находок сканера. Настоящий сканер дал бы то же самое дороже (сеть,
# установка, минуты обхода) и при этом не дал бы случая «находка есть»: дерево
# сегодня чистое, и подать находку можно было бы только правкой прод-кода.
#
# Коды возврата:
#   0 — все случаи дали предсказанный исход;
#   1 — хотя бы один разошёлся (перечислены);
#   2 — проба НЕ ВЫПОЛНЕНА: нет git-дерева или jq.

set -uo pipefail

PASS=0
FAIL=0
say() { printf '\n── %s\n' "$*"; }
ok()  { PASS=$((PASS + 1)); echo "  ОК  $*"; }
bad() { FAIL=$((FAIL + 1)); echo "  ПРОВАЛ $*"; }

ROOT=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "ОТКАЗ: вне git-дерева — перечень модулей выводить не из чего; проба НЕ ВЫПОЛНЕНА" >&2
    exit 2
}
command -v jq > /dev/null || {
    echo "ОТКАЗ: нет jq — вердикт считает им; проба НЕ ВЫПОЛНЕНА" >&2
    exit 2
}

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# ── ПОДСТАВНОЙ СКАНЕР ───────────────────────────────────────────────────────
# Он обязан отвечать ТАК ЖЕ, как настоящий, во всём, что читает скан: текстовая
# сводка с переписью в stdout и SARIF в файл, названный ключом `-out`. Число
# находок задаётся переменной окружения — это и есть подменяемый факт.
make_stub() {
    cat > "$WORK/gosec" <<'STUB'
#!/usr/bin/env bash
set -u
out=""
prev=""
for a in "$@"; do
    if [ "$prev" = "-out" ]; then out="$a"; fi
    prev="$a"
done
results='[]'
if [ "${STUB_FINDINGS:-0}" != "0" ]; then
    results='[{"ruleId":"G101","level":"error","message":{"text":"синтетика инъекции"},"locations":[{"physicalLocation":{"artifactLocation":{"uri":"synthetic.go"},"region":{"startLine":1}}}]}]'
fi
case " $* " in
    *" -fmt json "*)
        printf '{"Issues":[],"Stats":{"files":7,"lines":70,"nosec":0,"found":0}}' > "$out" ;;
    *)
        printf '{"version":"2.1.0","$schema":"https://json.schemastore.org/sarif-2.1.0.json","runs":[{"tool":{"driver":{"name":"gosec","rules":[]}},"results":%s}]}' "$results" > "$out" ;;
esac
echo "Summary:"
echo "  Gosec  : v2.28.0-stub"
echo "  Files  : 7"
echo "  Lines  : 70"
echo "  Nosec  : 0"
echo "  Issues : 0"
exit 0
STUB
    chmod +x "$WORK/gosec"
}
make_stub

scan_rc() { # <bin> [окружение подставного]
    local bin="$1"; shift
    local out="$WORK/out"; rm -rf "$out"; mkdir -p "$out"
    local rc=0
    ( cd "$ROOT" && env "$@" GOSEC_BIN="$bin" GOSEC_OUT="$out" \
        "$ROOT/scripts/gosec-scan-modules.sh" ) > "$WORK/scan.txt" 2>&1 || rc=$?
    echo "$rc"
}
verdict_rc() {
    local rc=0
    ( cd "$ROOT" && GOSEC_OUT="$WORK/out" "$ROOT/scripts/gosec-verdict.sh" ) \
        > "$WORK/verdict.txt" 2>&1 || rc=$?
    echo "$rc"
}

# ── (1) ИНСТРУМЕНТА НЕТ → «НЕ ВЫПОЛНИЛОСЬ» У ОБОИХ ──────────────────────────
# Это ровно тот прогон из тела задачи: `PATH=/usr/bin:/bin …`. Прежде он давал
# ноль — успех на непрочитанном дереве.
say "инструмента нет: анализ не запускался"
rc=$(scan_rc "$WORK/нет-такого-файла" STUB_FINDINGS=0)
[ "$rc" = "3" ] && ok "скан → код 3 (не выполнилось)" \
                || bad "скан → код $rc, ждали 3"
grep -q 'анализ не запускался' "$WORK/scan.txt" && ok "причина названа поимённо" \
    || bad "причина не названа: $(head -c 160 "$WORK/scan.txt")"
rc=$(verdict_rc)
[ "$rc" = "3" ] && ok "вердикт → код 3 (не выполнилось), отдельный от находки" \
                || bad "вердикт → код $rc, ждали 3"
grep -q 'НЕ ВЫПОЛНИЛОСЬ' "$WORK/verdict.txt" && ok "вердикт называет категорию словом" \
    || bad "вердикт не называет категорию: $(head -c 160 "$WORK/verdict.txt")"

# ── (2) ЗАКОННЫЙ БЛИЗНЕЦ: ИНСТРУМЕНТ ЕСТЬ, НАХОДОК НЕТ → ЗЕЛЁНОЕ ────────────
# Без этой половины «код 3 всегда» выглядело бы работающим различением.
say "инструмент есть, находок нет: чистый прогон"
rc=$(scan_rc "$WORK/gosec" STUB_FINDINGS=0)
[ "$rc" = "0" ] && ok "скан → код 0 (анализ состоялся)" \
                || { bad "скан → код $rc, ждали 0"; sed 's/^/     | /' "$WORK/scan.txt" | tail -5; }
rc=$(verdict_rc)
[ "$rc" = "0" ] && ok "вердикт → код 0 (зелено)" \
                || { bad "вердикт → код $rc, ждали 0"; sed 's/^/     | /' "$WORK/verdict.txt" | tail -5; }
grep -q 'осмотрено модулей' "$WORK/verdict.txt" && ok "перепись осмотренного напечатана" \
    || bad "переписи нет — «ноль находок» неотличимо от «ноль прочитанного»"

# ── (3) НАХОДКА → КРАСНОЕ, И ЭТО ТРЕТИЙ, ОТДЕЛЬНЫЙ КОД ──────────────────────
say "инструмент есть, находка level=error: красное"
rc=$(scan_rc "$WORK/gosec" STUB_FINDINGS=1)
[ "$rc" = "0" ] && ok "скан → код 0: находка не мешает анализу состояться" \
                || bad "скан → код $rc, ждали 0"
rc=$(verdict_rc)
[ "$rc" = "1" ] && ok "вердикт → код 1 (находка), отдельный от «не выполнилось»" \
                || { bad "вердикт → код $rc, ждали 1"; sed 's/^/     | /' "$WORK/verdict.txt" | tail -5; }
grep -q 'level=error' "$WORK/verdict.txt" && ok "отказ называет порог" \
    || bad "отказ не называет порог"

# ── (4) ЧАСТИЧНЫЙ ОБХОД: ОТЧЁТ ЕСТЬ, ПЕРЕПИСЬ НЕПОЛНА → «НЕ ВЫПОЛНИЛОСЬ» ────
# Модуль дерева, не попавший в перепись, — это «не смотрели», а не «чисто».
# Подменяется ровно один факт: из переписи изымается строка модуля.
say "перепись потеряла модуль дерева: вердикта по нему нет"
rc=$(scan_rc "$WORK/gosec" STUB_FINDINGS=0)
[ "$rc" = "0" ] || bad "подготовка: скан → код $rc, ждали 0"
: > "$WORK/out/gosec-census.txt"
rc=$(verdict_rc)
[ "$rc" = "3" ] && ok "вердикт → код 3 на пустой переписи" \
                || bad "вердикт → код $rc, ждали 3"

# ── (5) ЗАКОННЫЙ БЛИЗНЕЦ ЧЕТВЁРТОГО: перепись на месте → прежний вердикт ────
say "перепись на месте: тот же прогон снова зелёный"
rc=$(scan_rc "$WORK/gosec" STUB_FINDINGS=0)
rc=$(verdict_rc)
[ "$rc" = "0" ] && ok "вердикт → код 0" || bad "вердикт → код $rc, ждали 0"

printf '\nосмотрено случаев 5; годно %d, беда %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
echo "скан и вердикт различают три исхода: 0 зелено · 1 находка · 3 не выполнилось"
exit 0
