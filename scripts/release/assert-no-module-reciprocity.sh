# assert-no-module-reciprocity.sh — ВЗАИМНОГО ТРЕБОВАНИЯ ВЕРСИЙ НЕТ.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Порядок выпуска существует ровно пока граф модулей ациклчен. Если объявление
# модуля A требует B, а объявление B требует A, то опубликовать нельзя ни один:
# каждый ждёт версию другого. Это и есть блокатор, ради которого предикат
# заведён (#1766, «ЧЕГО НЕ ДЕЛАТЬ»).
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЗДЕСЬ ИЗМЕРЯЕТСЯ — ЗАВИСИМОСТЬ, А НЕ НАПИСАНИЕ ПУТИ
#
# Прежний предикат #1766 звучал так:
#
#     git grep -l "pkg/api/kacho/cloud/iam/v1" origin/main -- "pkg/*" ":!pkg/api/*"
#
# и мерил ПОДСТРОКУ В ПУТИ ИМПОРТА. Он неверен дважды, и обе половины
# самостоятельны.
#
# Первая: подстрока — не зависимость. Импорт `…/kacho/pkg/api/kaname/cloud/iam/v1`
# ведёт из модуля `github.com/PRO-Robotech/kacho` в него же: `kaname` здесь имя
# КАТАЛОГА, а не модуля. Внутримодульный импорт требования версий не создаёт
# BY CONSTRUCTION, поэтому предикат считал то, что взаимностью быть не может.
#
# Вторая: он меняет цвет от переименования. Замер по дереву (2026-09-08),
# одно-фактная дельта — коммит `a10bfd208d` и его родитель `a9e635c7cd`:
#
#     предикат #1766 на родителе  → 17 файлов (9 прод-кода)
#     предикат #1766 на коммите   →  0
#     модулей   до / после        →  2 / 2
#     рёбер     до / после        →  1 / 1, оба `<служба> → kacho`
#
# То есть блокатор был объявлен снятым переименованием каталога стабов, при
# НЕИЗМЕННОМ графе модулей. Предикат снятия блокатора выпуска, ложно зелёный,
# дороже обычного: он объявляет открытым шаг, который сам же и стережёт.
#
# Здесь не читается ни один импорт и ни одно имя каталога. Читаются директивы
# `module`, `require` и `replace` — единственное место, где требование версии
# вообще ВЫРАЗИМО, — и читаются РАЗБОРОМ (`go mod edit -json`), а не поиском по
# тексту: путь модуля встречается и в комментариях объявления.
#
# Следствие, которое и требовалось: переименование каталога, пакета или самого
# модуля вердикта не двигает, а появление обратного `require` двигает — даже
# если ни один импорт при этом не написан.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ `replace` НА ВНУТРИДЕРЕВНЫЙ МОДУЛЬ — ТОЖЕ РЕБРО
#
# Подмена пути связывает те же два модуля, но ПРЯЧЕТ версию: собирается оно
# локальным каталогом, и цикл, замкнутый через подмену, ни в одной версии не
# виден. Поэтому ребро считается, а сама по себе подмена вердикта здесь НЕ
# производит: её запрет — предмет CI-гейта из `polyrepo.md` («replace на
# внутренний модуль ЗАПРЕЩЁН»), и второе место об одном предмете разошлось бы с
# ним молча. Перепись подмены называет всегда — чтобы «ноль» не выглядело как
# «не искали».
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ЧЕТЫРЕ, И ТРЕТИЙ НЕСУЩИЙ
#
#   0 — прочитано ≥2 объявления, цикла нет;
#   1 — НАХОДКА: цикл (в т.ч. самотребование) — с координатами каждого ребра;
#   2 — скрипт позван неверно;
#   3 — ВЕРДИКТА НЕТ: читать нечего либо прочитано не всё.
#
# Третий исход отделён от нулевого НАМЕРЕННО, и случаев у него три:
#
#   * объявлений модулей меньше двух — ребру не из чего быть, и цикл невозможен
#     BY CONSTRUCTION. Зелёное здесь было бы верным и ПУСТЫМ: до раскола службы
#     дерево несло один модуль, и предикат печатал бы «взаимности нет» годами,
#     ничего не проверив;
#   * объявление не прочиталось (нет разбора, файл битый) — модуль, о котором не
#     спросили, обратного ребра не несёт лишь предположительно. Молчание
#     источника не читается как «да»;
#   * нет инструмента или дерево не под git — обход пуст, и пустой обход зелёным
#     не бывает.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЕДИНИЦА СЧЁТА — ОТСЛЕЖИВАЕМОЕ ОБЪЯВЛЕНИЕ МОДУЛЯ
#
# Перечень ВЫВОДИТСЯ из индекса git (`git ls-files '*go.mod'`), а не выписывается:
# выписанный разошёлся бы с деревом на первом же новом модуле — молча, потому что
# скрипт продолжал бы быть зелёным. Неотслеживаемый `go.mod` предметом не
# является: он не уезжает ни к какому потребителю и порядка выпуска не связывает.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

ROOT="${KACHO_MODULE_GRAPH_ROOT:-.}"

usage() {
    cat >&2 <<USAGE
употребление: $0 [--root <каталог>]

  Строит граф ОБЪЯВЛЕННЫХ модулей дерева (module/require/replace) и утверждает,
  что взаимного требования версий в нём нет. Импортов и имён каталогов не
  читает: подстрока в пути импорта зависимостью не является.

  --root <каталог>   дерево, о котором спрашивают (умолчание: текущее)

переменные:
  KACHO_MODULE_GRAPH_ROOT   то же, что --root

исходы: 0 цикла нет · 1 находка · 2 позван неверно · 3 вердикта нет
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --root) [ $# -ge 2 ] || { echo "--root без значения" >&2; usage; exit 2; }
                ROOT="$2"; shift ;;
        -h|--help) usage; exit 2 ;;
        *) echo "неизвестный аргумент: $1" >&2; usage; exit 2 ;;
    esac
    shift
done

void() { printf 'ВЕРДИКТА НЕТ: %s\n' "$1" >&2; exit 3; }

[ -d "$ROOT" ] || void "каталога нет: $ROOT"
cd "$ROOT" || void "в каталог не войти: $ROOT"

for tool in git go jq awk; do
    command -v "$tool" >/dev/null 2>&1 || void "инструмента нет: $tool — обход пуст, а пустой обход зелёным не бывает"
done

git rev-parse --git-dir >/dev/null 2>&1 || void "дерево не под git — единицу счёта (отслеживаемое объявление) взять неоткуда"
TOP="$(git rev-parse --show-toplevel 2>/dev/null)"
[ -n "$TOP" ] || void "корень дерева не определён"

# Пути берутся ОТ КОРНЯ дерева (--full-name), а не от текущего каталога: без
# этого запуск из подкаталога молча давал бы ноль объявлений — то есть зелёное
# по причине, к дереву не относящейся.
DECLS="$(git -C "$TOP" ls-files --full-name '*go.mod' 2>/dev/null)"

tmp="$(mktemp -d "${TMPDIR:-/tmp}/modgraph.XXXXXX")" || void "временный каталог не завести"
trap 'rm -rf "$tmp"' EXIT

echo "граф объявленных модулей дерева $TOP"

declare -a MODS=() MOD_DECL=()
UNREAD=0
declare -a UNREAD_WHY=()
READ_N=0

while IFS= read -r decl; do
    [ -n "$decl" ] || continue
    READ_N=$((READ_N + 1))
    if ! json="$(go mod edit -json "$TOP/$decl" 2>"$tmp/err")"; then
        UNREAD=$((UNREAD + 1))
        UNREAD_WHY+=("$decl: разбор отказал — $(tr '\n' ' ' < "$tmp/err" | cut -c1-120)")
        continue
    fi
    path="$(printf '%s' "$json" | jq -r '.Module.Path // empty')"
    if [ -z "$path" ]; then
        UNREAD=$((UNREAD + 1))
        UNREAD_WHY+=("$decl: директивы module в разборе нет")
        continue
    fi
    printf '%s' "$json" > "$tmp/$(printf '%s' "$decl" | tr '/' '_').json"
    MODS+=("$path")
    MOD_DECL+=("$decl")
    printf '  прочитано  %-34s -> %s\n' "$decl" "$path"
done <<< "$DECLS"

for w in ${UNREAD_WHY[@]+"${UNREAD_WHY[@]}"}; do printf '  НЕ прочитано %s\n' "$w"; done

MOD_N="${#MODS[@]}"

# Одно объявление, называющее два модуля, делает граф неоднозначным: рёбра к
# такому пути нельзя отнести ни к одному дому. Это дефект дерева, а не
# отсутствие предмета, поэтому находка, а не «вердикта нет».
DUP="$(printf '%s\n' ${MODS[@]+"${MODS[@]}"} | sort | uniq -d)"

# ── рёбра: только между модулями ЭТОГО дерева ────────────────────────────────
: > "$tmp/edges"
REQ_E=0; REP_E=0
for i in "${!MODS[@]}"; do
    from="${MODS[$i]}"; decl="${MOD_DECL[$i]}"
    json="$(cat "$tmp/$(printf '%s' "$decl" | tr '/' '_').json")"
    for j in "${!MODS[@]}"; do
        to="${MODS[$j]}"
        v="$(printf '%s' "$json" | jq -r --arg t "$to" '(.Require // [])[] | select(.Path == $t) | .Version' | head -1)"
        if [ -n "$v" ]; then
            printf '%s\t%s\trequire\t%s\t%s\n' "$from" "$to" "$v" "$decl" >> "$tmp/edges"
            REQ_E=$((REQ_E + 1))
        fi
        r="$(printf '%s' "$json" | jq -r --arg t "$to" '(.Replace // [])[] | select(.Old.Path == $t) | ((.New.Path // "?") + " " + (.New.Version // "<каталог>"))' | head -1)"
        if [ -n "$r" ]; then
            printf '%s\t%s\treplace\t%s\t%s\n' "$from" "$to" "$r" "$decl" >> "$tmp/edges"
            REP_E=$((REP_E + 1))
        fi
    done
done

# ── поиск циклов: обход в глубину по рёбрам, порядок узлов детерминирован ────
awk -F'\t' '
    { adj[$1] = adj[$1] SUBSEP $2; node[$1]; node[$2]; lbl[$1 SUBSEP $2] = $3 " " $4 " (" $5 ")" }
    function dfs(u,   i, n, parts, v, k, cyc) {
        color[u] = 1; depth++; stack[depth] = u
        n = split(substr(adj[u], 2), parts, SUBSEP)
        for (i = 1; i <= n; i++) {
            v = parts[i]
            if (color[v] == 1) {
                cyc = ""
                for (k = 1; k <= depth; k++) if (found_at || stack[k] == v) { found_at = 1; cyc = cyc stack[k] "\n" }
                found_at = 0
                print cyc v "\n--"
            } else if (color[v] == 0) dfs(v)
        }
        color[u] = 2; depth--
    }
    END {
        m = 0; for (u in node) order[++m] = u
        for (i = 1; i <= m; i++) for (j = i + 1; j <= m; j++) if (order[j] < order[i]) { t = order[i]; order[i] = order[j]; order[j] = t }
        for (i = 1; i <= m; i++) if (color[order[i]] == 0) dfs(order[i])
    }
' "$tmp/edges" > "$tmp/cycles"

CYC_N="$(grep -c -- '^--$' "$tmp/cycles" 2>/dev/null || true)"
[ -n "$CYC_N" ] || CYC_N=0

printf '\nперепись: объявлений осмотрено %d, прочитано %d, НЕ прочитано %d, рёбер внутри дерева %d (require %d, replace %d), циклов %d\n' \
    "$READ_N" "$MOD_N" "$UNREAD" "$((REQ_E + REP_E))" "$REQ_E" "$REP_E" "$CYC_N"

if [ -s "$tmp/edges" ]; then
    echo "  рёбра:"
    while IFS=$'\t' read -r f t k v d; do printf '    %-38s -> %-38s %s %s (%s)\n' "$f" "$t" "$k" "$v" "$d"; done < "$tmp/edges"
fi
if [ "$REP_E" -gt 0 ]; then
    echo "  ВНИМАНИЕ: подмена пути на внутридеревный модуль — вердикт по ней принадлежит"
    echo "  CI-гейту из polyrepo.md, здесь она только считается ребром (версия спрятана)."
fi

if [ -n "$DUP" ]; then
    {
        echo
        echo "НАХОДКА: один путь модуля объявлен ДВАЖДЫ — граф неоднозначен, и рёбра к нему"
        echo "  нельзя отнести ни к одному дому:"
        printf '    %s\n' $DUP
    } >&2
    exit 1
fi

if [ "$UNREAD" -gt 0 ]; then
    void "объявлений не прочитано $UNREAD из $READ_N — модуль, о котором не спросили, обратного ребра не несёт лишь предположительно"
fi

if [ "$MOD_N" -lt 2 ]; then
    void "объявлений модулей прочитано $MOD_N — ребру не из чего быть, цикл невозможен by construction; зелёное здесь было бы верным и пустым"
fi

if [ "$CYC_N" -gt 0 ]; then
    {
        echo
        echo "НАХОДКА: граф модулей дерева ЦИКЛИЧЕН — взаимное требование версий."
        echo "  Порядок выпуска перестаёт существовать: каждый модуль цикла ждёт версию"
        echo "  другого, и опубликовать первым нельзя ни один."
        awk -F'\t' 'NR==FNR { lbl[$1 SUBSEP $2] = $3 " " $4 " (объявлено в " $5 ")"; next }
                    /^--$/ { print "  ---"; prev = ""; next }
                    { if (prev != "") printf "    %s\n      -> %s   %s\n", prev, $0, lbl[prev SUBSEP $0]; prev = $0 }' \
            "$tmp/edges" "$tmp/cycles"
        echo "  ЧТО ДЕЛАТЬ: разорвать цикл — вынести общее в третий модуль либо снять"
        echo "  обратное требование. Подмена пути (replace) цикл ПРЯЧЕТ, а не разрывает."
    } >&2
    exit 1
fi

echo "взаимности нет: рёбра внутри дерева однонаправлены, порядок выпуска определён"
exit 0
