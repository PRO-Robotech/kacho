# summarize-run.sh — сводка прогона выпуска для того, кто его позвал.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ШАГОМ. Он идёт при ЛЮБОМ исходе, в том числе после отказа
# гейта, поэтому не вправе ничего решать: он ЧИТАЕТ состояние удалённого и
# пересказывает его. Решения приняты выше и здесь не повторяются.
#
# ЗАЧЕМ ВООБЩЕ. Здесь называется единственное соседнее поведение, которое
# меняется от того, что ссылку создаёт процесс, а не человек: ссылка, созданная
# встроенным токеном площадки, НЕ ПОРОЖДАЕТ СОБЫТИЙ для других процессов. Значит
# сборка образов по триггеру `tags:` не сработает. Умолчать об этом значило бы
# оставить оператору расхождение, которое он обнаружит отсутствием образа.
#
# ИСХОДЫ: 0 — сводка напечатана; 2 — позван неверно. Иных у него нет и быть не
# должно: шаг сводки, способный уронить прогон, скрыл бы исход самого выпуска.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

[ $# -eq 2 ] || { echo "употребление: $0 <версия> <публиковали:true|false>" >&2; exit 2; }
VERSION="$1"; PUBLISH="$2"
REMOTE="${KACHO_RELEASE_REMOTE:-origin}"
OUT="${GITHUB_STEP_SUMMARY:-/dev/stdout}"

# Факт, а не намерение: спрашивается удалённый, а не то, чем закончился шаг выше.
LANDED=нет
if git ls-remote --tags "$REMOTE" 2>/dev/null \
     | awk -v r="refs/tags/$VERSION" '$2==r{f=1} END{exit !f}'; then
    LANDED=да
fi

PUBLISHED_COUNT="$(git ls-remote --tags "$REMOTE" 2>/dev/null \
    | awk '$2 ~ /^refs\/tags\/v[0-9]+\.[0-9]+\.[0-9]+/' | grep -c . || true)"

{
    printf '## Выпуск `%s`\n\n' "$VERSION"
    printf '| ось | значение |\n|---|---|\n'
    printf '| необратимый шаг запрошен | `%s` |\n' "$PUBLISH"
    printf '| ссылка на удалённом | **%s** |\n' "$LANDED"
    printf '| опубликованных версий всего | %s |\n' "$PUBLISHED_COUNT"

    if [ "$LANDED" = "да" ]; then
        cat <<TXT

### Что делать дальше

Потребитель бампается так:

    go get github.com/PRO-Robotech/kacho@$VERSION

Совместимость выражается **минором**: платформа выпускается в \`v0\`, где
разрыв — это подъём минора, а патч разрыва не несёт. Полностью —
\`docs/architecture/release-and-versioning.md\`.

### Образы по имени версии собраны НЕ БУДУТ

Ссылка создана встроенным токеном площадки, а такие ссылки событий для других
процессов не порождают — триггер \`tags:\` в \`docker-build\` не сработает.
Образы самой ревизии при этом уже собраны: публикуется вершина ствола, а
\`docker-build\` идёт и на push в ствол, и по завершении сквозных проб.
Если образ с именем версии всё же нужен:

    gh workflow run docker-build.yml --ref $VERSION
TXT
    else
        cat <<'TXT'

Ссылки на удалённом нет. Если необратимый шаг был запрошен — значит его
остановил гейт, и это правильный исход: тег, обещающий то, чего нет, отозвать
нельзя. Разбор — в выводе шага «предпосылки выпуска и публикация».
TXT
    fi
} >> "$OUT"

exit 0
