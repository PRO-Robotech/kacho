# breaking-since-release.sh — ТОЧКА ОТСЧЁТА СОВМЕСТИМОСТИ КОНТРАКТОВ.
#
# ЗАЧЕМ. `buf breaking` в `ci.yaml` сравнивает дерево СО СТВОЛОМ и отвечает на
# вопрос «ломает ли ЭТОТ запрос слияния то, что уже влито». Вопрос выпуска
# другой: «ломает ли накопленное с последней ОПУБЛИКОВАННОЙ версии то, на что
# потребитель уже сослался». Ствол на него не отвечает — он движется каждый день,
# а потребитель пиннит версию. После выноса службы в отдельный репозиторий
# сравнивать со стволом станет и вовсе нечем: дерева платформы у неё на диске
# нет, а есть версия в `go.mod`.
#
# ТОЧКА ОТСЧЁТА — ТОТ ЖЕ ТЕГ, ЧТО И У МОДУЛЯ, и это несущее решение, а не
# совпадение: одна координата отвечает сразу на два вопроса — «какой код» и
# «какие контракты». Второй перечень версий (реестр модулей контрактов, своя
# нумерация proto) завёл бы два места об одном предмете, и разошлись бы они
# молча — сборка потребителя осталась бы зелёной при разъехавшихся контрактах.
#
# ЧТО ПЕЧАТАЕТСЯ. Строка `release-minimum-bump=patch|minor` — машиночитаемый
# вердикт: какого наименьшего повышения требует накопленная дельта контрактов.
# В `v0` разрыв совместимости выражается МИНОРОМ (см. docs/architecture/
# release-and-versioning.md), поэтому вердиктов ровно два.
#
# ИСХОДОВ ЧЕТЫРЕ, И ЧИТАЕТСЯ КОД ВОЗВРАТА:
#   0 — сравнение состоялось, вердикт напечатан (и, если спрошено `--require`,
#       названная версия его удовлетворяет);
#   1 — НАХОДКА: названная `--require` версия МЕЛЬЧЕ требуемого повышения;
#   2 — скрипт позван неверно либо инструмента нет;
#   3 — НЕ ВЫПОЛНИЛОСЬ: точки отсчёта не существует (опубликованных версий ноль)
#       либо buf не сделал своей работы. «Не знаю» не выдаётся за «разрывов нет».
#
# ПОЧЕМУ «ТОЧКИ ОТСЧЁТА НЕТ» — ТРЕТИЙ ИСХОД, А НЕ ЗЕЛЁНОЕ. Сегодня
# опубликованных версий ноль (`go list -m -versions github.com/PRO-Robotech/kacho`
# отдаёт один путь модуля без единой версии). Зелёное на этом входе означало бы
# «разрывов нет» — утверждение, которого никто не проверял, потому что сравнивать
# было не с чем. Первый выпуск САМ становится точкой отсчёта, и это законно;
# незаконно молча выдать отсутствие сравнения за его успешный исход.
#
# ПОЧЕМУ КОД ВОЗВРАТА buf РАЗБИРАЕТСЯ, А НЕ ПРОГЛАТЫВАЕТСЯ. У buf ровно три
# осмысленных исхода: 0 — разрывов нет, 100 — разрывы есть, ЛЮБОЙ ДРУГОЙ — он не
# сделал своей работы (сеть, негодный вход, отсутствующая ссылка). Схлопывание
# третьего во второй читало бы сетевой отказ как «разрывов нет».
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

# Уборка ОДНА на весь скрипт: `trap … EXIT`, объявленный второй раз, ЗАМЕЩАЕТ
# первый, а не дополняет его, — поэтому перечень пополняется, а обработчик
# объявляется единожды. Прежняя редакция оставляла каталог пробы прокси на диске
# при каждом прогоне, и заметить это по исходу было нельзя.
CLEAN=()
trap 'rm -rf "${CLEAN[@]:-}" 2>/dev/null || true' EXIT

MODULE="${KACHO_RELEASE_MODULE:-github.com/PRO-Robotech/kacho}"
GIT_INPUT="${KACHO_RELEASE_GIT_INPUT:-https://github.com/PRO-Robotech/kacho.git}"
PROTO_DIR="${KACHO_RELEASE_PROTO_DIR:-proto}"

usage() {
    cat >&2 <<USAGE
употребление: $0 [--require <версия>] [<база>]

  <база>              версия, с которой сравнивать (умолчание: старшая
                      опубликованная, по ответу модуля-прокси)
  --require <версия>  спросить, довольно ли этой версии для накопленной дельты;
                      мельче требуемого повышения → находка

переменные:
  KACHO_RELEASE_MODULE     путь модуля (умолчание: github.com/PRO-Robotech/kacho)
  KACHO_RELEASE_GIT_INPUT  откуда buf берёт базу (умолчание: адрес репозитория;
                           годится и локальный путь к .git)
  KACHO_RELEASE_PROTO_DIR  каталог контрактов (умолчание: proto)
USAGE
}

REQUIRE=""; BASE=""
while [ $# -gt 0 ]; do
    case "$1" in
        --require)
            [ $# -ge 2 ] || { echo "--require без значения" >&2; usage; exit 2; }
            REQUIRE="$2"; shift 2 ;;
        -h|--help) usage; exit 2 ;;
        -*) echo "неизвестный ключ: $1" >&2; usage; exit 2 ;;
        *)
            [ -z "$BASE" ] || { echo "база названа дважды: '$BASE' и '$1'" >&2; exit 2; }
            BASE="$1"; shift ;;
    esac
done

command -v buf >/dev/null 2>&1 || { echo "инструмента нет: buf" >&2; exit 2; }

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "не репозиторий git: $PWD" >&2; exit 2; }
[ -d "$ROOT/$PROTO_DIR" ] || {
    echo "каталога контрактов нет: $ROOT/$PROTO_DIR" >&2; exit 2; }

# ── База: старшая опубликованная, если не названа ───────────────────────────
# Порядок версий спрашивается у МОДУЛЯ-ПРОКСИ, а не сортируется своими руками:
# прокси и есть тот авторитет, которым порядок разрешает потребитель. Свой
# компаратор был бы вторым местом об одном предмете и разошёлся бы на предвыпуске.
if [ -z "$BASE" ]; then
    command -v go >/dev/null 2>&1 || {
        echo "НЕ ВЫПОЛНИЛОСЬ: go не найден — старшая опубликованная версия не спрошена" >&2; exit 3; }
    probe="$(mktemp -d)"; CLEAN+=("$probe")
    printf 'module kacho.local/release-base\n\ngo 1.21\n' > "$probe/go.mod"
    if ! LIST="$(cd "$probe" && GOFLAGS= go list -m -versions "$MODULE" 2>/dev/null)"; then
        echo "НЕ ВЫПОЛНИЛОСЬ: прокси не ответил о версиях $MODULE — точка отсчёта неизвестна" >&2
        exit 3
    fi
    # Первое поле — путь модуля, дальше версии в порядке semver. Пусто после
    # первого поля означает «опубликованных версий ноль».
    BASE="$(printf '%s\n' "$LIST" | awk 'NR==1{print $NF}')"
    if [ -z "$BASE" ] || [ "$BASE" = "$MODULE" ]; then
        cat >&2 <<VOID
НЕ ВЫПОЛНИЛОСЬ: опубликованных версий $MODULE ноль — точки отсчёта не существует.
Сравнивать накопленную дельту контрактов не с чем; это НЕ «разрывов нет».
Первый выпуск сам становится точкой отсчёта — см.
docs/architecture/release-and-versioning.md.
VOID
        exit 3
    fi
fi

printf 'точка отсчёта совместимости контрактов: %s (вход: %s, каталог: %s)\n' \
    "$BASE" "$GIT_INPUT" "$PROTO_DIR"

# ── Сравнение ───────────────────────────────────────────────────────────────
out="$(mktemp)"; err="$(mktemp)"; CLEAN+=("$out" "$err")

( cd "$ROOT/$PROTO_DIR" && buf breaking \
    --against "$GIT_INPUT#tag=$BASE,subdir=$PROTO_DIR" \
    --error-format=text ) > "$out" 2> "$err"
rc=$?

case "$rc" in
    0)   BREAKS=0 ;;
    100) BREAKS="$(grep -c . < "$out" || true)" ;;
    *)
        echo "НЕ ВЫПОЛНИЛОСЬ: buf не сделал своей работы (код $rc) — это НЕ «разрывов нет»" >&2
        sed 's/^/       | /' < "$err" >&2
        exit 3 ;;
esac

if [ "$BREAKS" = "0" ]; then
    MIN_BUMP=patch
else
    MIN_BUMP=minor
    sed 's/^/  ! /' < "$out"
fi

printf '\nперепись: находок разрыва %s против %s\n' "$BREAKS" "$BASE"
printf 'release-minimum-bump=%s\n' "$MIN_BUMP"

[ -n "$REQUIRE" ] || exit 0

# ── Довольно ли названной версии ────────────────────────────────────────────
# Арифметика по полям, а не второй компаратор semver: спрашивается ровно
# «поднят ли минор» и «версия вообще больше базы». Предвыпуск для этого вопроса
# отбрасывается — предвыпуск нового минора минор поднимает.
fields() { printf '%s' "${1#v}" | sed 's/-.*//' | tr '.' ' '; }
read -r ba bb bc <<< "$(fields "$BASE")"
read -r ra rb rc_ <<< "$(fields "$REQUIRE")"
for v in "$ba" "$bb" "$bc" "$ra" "$rb" "$rc_"; do
    [[ "$v" =~ ^[0-9]+$ ]] || {
        echo "НЕ ВЫПОЛНИЛОСЬ: версии не разбираются по полям ('$BASE' против '$REQUIRE')" >&2
        exit 3; }
done

satisfied=1
if [ "$MIN_BUMP" = minor ]; then
    { [ "$ra" -gt "$ba" ] || { [ "$ra" -eq "$ba" ] && [ "$rb" -gt "$bb" ]; }; } || satisfied=0
else
    { [ "$ra" -gt "$ba" ] \
      || { [ "$ra" -eq "$ba" ] && [ "$rb" -gt "$bb" ]; } \
      || { [ "$ra" -eq "$ba" ] && [ "$rb" -eq "$bb" ] && [ "$rc_" -gt "$bc" ]; }; } || satisfied=0
fi

if [ "$satisfied" = "1" ]; then
    printf 'версия %s требуемое повышение (%s) удовлетворяет\n' "$REQUIRE" "$MIN_BUMP"
    exit 0
fi
cat >&2 <<RED
ВЫПУСК НЕ ОТКРЫТ: накопленная дельта контрактов требует повышения «$MIN_BUMP»
относительно $BASE, а объявлена версия $REQUIRE. Совместимость выражается
НОМЕРОМ; версия, номер которой обещает совместимость при её разрыве, обещает
то, чего нет, и обещание необратимо.
RED
exit 1
