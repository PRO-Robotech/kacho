# publish-tag.sh — ПРОИЗВОДИТЕЛЬ ОПЕРАЦИИ «поставить версию».
#
# ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ `publish-version.sh`, КОТОРЫЙ ЛЕЖИТ РЯДОМ. Тот проверяет
# предпосылки и ПЕЧАТАЕТ команду, оставляя нажатие человеку. Он и остаётся
# местным гейтом: его довод — «действие, которое нельзя отозвать, не делается
# побочным эффектом проверки» — верен и не отзывается.
#
# Но у операции «поставить версию» при этом НЕТ ПРОИЗВОДИТЕЛЯ, и это измеримо:
# скрипт существует в дереве, а зовущего у него ноль ни в одном объявлении
# конвейера и ни в одном рецепте сборки. Механизм, который никто не зовёт, не
# отличается от отсутствующего: печатать команду и выполнить её — разные вещи,
# и вторая происходит только тогда, когда человек ВСПОМНИЛ. «Ставят когда надо»
# означает «не ставится никогда».
#
# ПОЧЕМУ ЖЕ ЭТОТ ТОЛКАЕТ ССЫЛКУ, ЕСЛИ ТОТ ОТКАЗЫВАЛСЯ. Довод соседа — про
# ПОБОЧНЫЙ эффект: проверка не смеет публиковать. Здесь публикация не побочна,
# она и есть предмет вызова: скрипт зовётся ИМЕНЕМ ВЕРСИИ и ПОДТВЕРЖДЕНИЕМ,
# которое обязано совпасть с ней дословно. Выигрыш назван честно: гейт
# становится НЕОБХОДИМЫМ условием публикации. Публикующий руками гейт обходит —
# и обходит молча; публикующий этим механизмом обойти его не может.
#
# ЧТО ОН ТРЕБУЕТ ПЕРЕД НЕОБРАТИМЫМ ШАГОМ — ТРИ ГЕЙТА, КАЖДЫЙ СО СВОИМ ПРЕДМЕТОМ:
#   publish-version.sh      — годна ли версия и годно ли дерево к упаковке;
#   assert-trunk-green.sh   — зелены ли обязательные проверки на ЭТОЙ ревизии;
#   breaking-since-release  — довольно ли номера для накопленной дельты контрактов.
#
# ФОРМА ТОЛЧКА — `<sha>:refs/tags/<v>`, А НЕ `git tag` + `git push`. Локальный
# тег, созданный и не отправленный, уезжает следующим побочным `git push --tags`
# и уезжает молча; в этом дереве таких восемь (#1762). Эта форма создаёт ссылку
# СРАЗУ на удалённом и не оставляет локальной вовсе — класс закрывается
# построением, а не вниманием.
#
# ИСХОДОВ ЧЕТЫРЕ, И ЧИТАЕТСЯ КОД ВОЗВРАТА:
#   0 — опубликовано; либо холостой прогон прошёл и НИЧЕГО не создано;
#   1 — НАХОДКА: предпосылка нарушена. Ничего не создано;
#   2 — позван неверно (нет версии, подтверждение не совпало). Ничего не создано;
#   3 — НЕ ВЫПОЛНИЛОСЬ: часть предпосылок не спрошена. Ничего не создано.
#
# УМОЛЧАНИЕ — ХОЛОСТОЙ ПРОГОН. Публикация происходит только по явному
# `--publish`: умолчание, при котором забытый ключ ПУБЛИКУЕТ, стоило бы ровно
# одной опечатки, а отозвать её нельзя.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REMOTE="${KACHO_RELEASE_REMOTE:-origin}"

usage() {
    cat >&2 <<USAGE
употребление: $0 <версия> --confirm <версия> [--publish] [--skip-pack]

  <версия>            выпускаемая версия, vМАЖОР.МИНОР.ПАТЧ[-предвыпуск]
  --confirm <строка>  обязана совпасть с версией ДОСЛОВНО; расхождение — отказ
  --publish           выполнить необратимый шаг; без него — холостой прогон
  --skip-pack         передаётся гейту предпосылок (проба упаковки дорогая)

переменные:
  KACHO_RELEASE_REMOTE  имя удалённого репозитория (умолчание: origin)
  KACHO_RELEASE_REPO    владелец/репозиторий для чтения зелени ствола
USAGE
}

VERSION=""; CONFIRM=""; PUBLISH=0; PASS_THROUGH=()
while [ $# -gt 0 ]; do
    case "$1" in
        --confirm)
            [ $# -ge 2 ] || { echo "--confirm без значения" >&2; usage; exit 2; }
            CONFIRM="$2"; shift 2 ;;
        --publish)   PUBLISH=1; shift ;;
        --skip-pack) PASS_THROUGH+=("--skip-pack"); shift ;;
        -h|--help)   usage; exit 2 ;;
        -*)          echo "неизвестный ключ: $1" >&2; usage; exit 2 ;;
        *)
            [ -z "$VERSION" ] || { echo "версия названа дважды: '$VERSION' и '$1'" >&2; exit 2; }
            VERSION="$1"; shift ;;
    esac
done
[ -n "$VERSION" ] || { usage; exit 2; }

# ── Подтверждение намерения ─────────────────────────────────────────────────
# Дословное совпадение, а не «непусто»: подтверждение, которое можно дать не
# читая, подтверждением не является. Проверяется ДО всего прочего — отказ здесь
# не стоит ни одного вызова к сети.
if [ "$CONFIRM" != "$VERSION" ]; then
    cat >&2 <<CONF
ОТКАЗ: подтверждение не совпало с версией.
  версия:        '$VERSION'
  подтверждение: '$CONFIRM'
Публикация необратима, поэтому намерение подтверждается дословным повтором
номера. Ничего не создано.
CONF
    exit 2
fi

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "не репозиторий git: $PWD" >&2; exit 2; }
cd "$ROOT" || exit 2
SHA="$(git rev-parse HEAD 2>/dev/null)" || {
    echo "ревизия рабочей копии не прочитана" >&2; exit 2; }

if [ "$PUBLISH" = "1" ]; then
    printf 'производитель версии: ПУБЛИКАЦИЯ %s на %s (ревизия %.12s)\n\n' "$VERSION" "$REMOTE" "$SHA"
else
    printf 'производитель версии: ХОЛОСТОЙ прогон %s (ревизия %.12s) — ничего создано не будет\n\n' \
        "$VERSION" "$SHA"
fi

# ── Учёт исходов гейтов ─────────────────────────────────────────────────────
# Три состояния сохраняются раздельно и НЕ схлопываются: «не спрошено» не
# вычитается в успех и не выдаётся за находку.
gates=0; red=(); void=()

# gate <имя> <команда...>
gate() {
    local name="$1"; shift
    gates=$((gates + 1))
    printf '── %s\n' "$name"
    # `|| true` здесь стоять НЕ МОЖЕТ: `true` — простая команда, она ЗАМЕЩАЕТ
    # PIPESTATUS своим нулём, и код гейта читался бы как успех. Оболочка
    # запущена без `-e`, поэтому падающий конвейер её и так не обрывает.
    local rc=0
    "$@" 2>&1 | sed 's/^/   /'
    rc="${PIPESTATUS[0]}"
    case "$rc" in
        0) printf '   → сошлось\n\n' ;;
        1) red+=("$name");  printf '   → НАХОДКА\n\n' ;;
        *) void+=("$name"); printf '   → НЕ ВЫПОЛНИЛОСЬ (код %s)\n\n' "$rc" ;;
    esac
    return 0
}

# Разворот пустого массива: `"${A[@]:-}"` даёт ОДИН ПУСТОЙ аргумент, а не ноль
# аргументов, и гейт предпосылок принял бы его за вторую версию. Форма ниже даёт
# ровно ноль.
gate "предпосылки выпуска" "$HERE/publish-version.sh" "$VERSION" \
     ${PASS_THROUGH[@]+"${PASS_THROUGH[@]}"}
gate "зелень ствола на этой ревизии" "$HERE/assert-trunk-green.sh" "$SHA"

# ── Точка отсчёта совместимости: у ПЕРВОГО выпуска её нет by construction ───
# Отсутствие точки отсчёта — законное состояние ровно один раз: пока
# опубликованных версий ноль, сравнивать не с чем, и первый выпуск сам ею
# становится. Дальше то же «не выполнилось» означает, что спросить НЕ УДАЛОСЬ, —
# и это отказ, а не поблажка. Различает их перепись опубликованных, а не память.
PUBLISHED_COUNT="$(git ls-remote --tags "$REMOTE" 2>/dev/null \
    | awk '$2 ~ /^refs\/tags\/v[0-9]+\.[0-9]+\.[0-9]+/' | grep -c . || true)"
gates=$((gates + 1))
printf '── дельта контрактов с последней опубликованной версии\n'
BSR_OUT="$("$HERE/breaking-since-release.sh" --require "$VERSION" 2>&1)"; BSR_RC=$?
printf '%s\n' "$BSR_OUT" | sed 's/^/   /'
case "$BSR_RC" in
    0) printf '   → сошлось\n\n' ;;
    1) red+=("дельта контрактов"); printf '   → НАХОДКА\n\n' ;;
    *)
        if [ "$PUBLISHED_COUNT" = "0" ]; then
            printf '   → точки отсчёта нет, и опубликованных версий тоже ноль:\n'
            printf '     ЭТОТ выпуск ею и становится. Законно ровно один раз.\n\n'
        else
            void+=("дельта контрактов")
            printf '   → НЕ ВЫПОЛНИЛОСЬ (код %s) при %s опубликованных — спросить не удалось\n\n' \
                "$BSR_RC" "$PUBLISHED_COUNT"
        fi ;;
esac

printf 'перепись: гейтов %d, находок %d, НЕ спрошено %d, опубликованных версий %s\n' \
    "$gates" "${#red[@]}" "${#void[@]}" "$PUBLISHED_COUNT"

if [ "$gates" = "0" ]; then
    echo "обход пуст: не прогнано ни одного гейта — вердикт беспредметен" >&2; exit 3
fi
if [ "${#red[@]}" -gt 0 ]; then
    printf 'находки: %s\n' "${red[*]}" >&2
    echo "ВЫПУСК НЕ ОТКРЫТ. Ничего не создано." >&2
    exit 1
fi
if [ "${#void[@]}" -gt 0 ]; then
    printf 'не спрошено: %s\n' "${void[*]}" >&2
    echo "ВЕРДИКТА НЕТ: не спрошенная предпосылка не считается выполненной. Ничего не создано." >&2
    exit 3
fi

if [ "$PUBLISH" != "1" ]; then
    cat <<DRY

Все предпосылки сошлись. ХОЛОСТОЙ прогон: ничего не создано и не отправлено.
Необратимый шаг делает тот же скрипт с ключом --publish:

    $0 $VERSION --confirm $VERSION --publish

DRY
    exit 0
fi

# ── Необратимый шаг ─────────────────────────────────────────────────────────
echo "── публикация ссылки"
if ! git push "$REMOTE" "$SHA:refs/tags/$VERSION"; then
    echo "ссылка НЕ создана: отказ отправки" >&2
    exit 1
fi
printf '   создано: %s refs/tags/%s → %.12s\n' "$REMOTE" "$VERSION" "$SHA"

# Локального тега эта форма не оставляет — утверждается, а не подразумевается:
# именно локальный неотправленный тег и есть класс, ради которого форма выбрана.
if git rev-parse -q --verify "refs/tags/$VERSION" >/dev/null 2>&1; then
    echo "   ВНИМАНИЕ: локальная ссылка refs/tags/$VERSION существует — снимите её" >&2
else
    echo "   локальной ссылки не осталось (форма <sha>:refs/tags/<v>)"
fi

# ── Заметка о выпуске ───────────────────────────────────────────────────────
# Не обязательна для модуля Go, но это единственное место, где НОМЕР встречается
# со СМЫСЛОМ: в `v0` минор означает разрыв совместимости, и читателю это надо
# сказать там, где он берёт версию. Отказ здесь публикацию не отменяет — ссылка
# уже создана, и врать об этом нельзя.
if command -v gh >/dev/null 2>&1; then
    if gh release create "$VERSION" --verify-tag --generate-notes --title "$VERSION"; then
        echo "   заметка о выпуске создана"
    else
        echo "   заметка о выпуске НЕ создана — ссылка при этом опубликована" >&2
    fi
else
    echo "   gh не найден: заметка о выпуске не создана, ссылка опубликована"
fi

cat <<DONE

Версия $VERSION опубликована. Проверить, что она доехала до потребителя:

    scripts/release/probe-published.sh $VERSION

DONE
exit 0
