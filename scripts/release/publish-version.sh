# publish-version.sh — производитель версии монорепо.
#
# ЗАЧЕМ. Вынесенный iam ссылается на фундамент `pkg/` и контракты `proto/` как
# на внешнюю зависимость — versioned Go-модуль `github.com/PRO-Robotech/kacho`.
# Версий монорепо не публикует: семантических тегов на origin ноль, релизов
# ноль, производителя тега нет ни в одном из процессов конвейера (#1766).
# Пиннуть при этом есть что — прокси уже отдаёт псевдоверсию на вершину ствола,
# — но выразить СОВМЕСТИМОСТЬ нечем: «бампнуть фундамент до совместимой версии»
# не является операцией, пока версий не существует.
#
# ЧТО ЭТОТ СКРИПТ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Он проверяет предпосылки выпуска и
# печатает ЕДИНСТВЕННУЮ команду, которую остаётся выполнить владельцу. Он НЕ
# создаёт ссылок, НЕ отправляет их и НЕ создаёт релизов — ни при каком флаге.
#
# ПОЧЕМУ НАЖАТИЕ ОСТАЁТСЯ ЗА ЧЕЛОВЕКОМ. Публикация версии НЕОБРАТИМА: модуль-
# прокси Go кэширует опубликованную версию и суммирует её в `go.sum` всякого
# потребителя. Переиздать ту же версию другим содержимым нельзя, `retract` виден
# всем. Действие, которое нельзя отозвать, не делается побочным эффектом
# проверки.
#
# ПОЧЕМУ ПЕЧАТАЕТСЯ `git push origin <sha>:refs/tags/<v>`, А НЕ `git tag` + `push`.
# Локальный тег, созданный и не отправленный, — самостоятельная опасность: он
# уезжает следующим побочным `git push --tags` или `--follow-tags`, и уезжает
# молча. В этом дереве таких восемь (#1762). Форма `<sha>:refs/tags/<v>`
# создаёт ссылку СРАЗУ на origin и не оставляет локальной вовсе, поэтому класс
# закрывается by construction, а не вниманием.
#
# ИСХОДОВ ЧЕТЫРЕ, И ЧИТАЕТСЯ КОД ВОЗВРАТА, А НЕ ВИД ВЫВОДА:
#   0 — все предпосылки сошлись, напечатана команда владельца;
#   1 — НАХОДКА: предпосылка не выполнена, публиковать нельзя;
#   2 — скрипт позван неверно (нет аргумента, каталог не репозиторий);
#   3 — НЕ ВЫПОЛНИЛОСЬ: спросить не удалось (нет доступа к origin, нет go).
#       Это не «да» и не «нет»: непрочитанная предпосылка не считается ни
#       выполненной, ни нарушенной, и в вердикт не вычитается.
#
# ПЕРЕПИСЬ ПЕЧАТАЕТСЯ ВСЕГДА — «ноль находок» обязано быть отличимо от «ноль
# прочитанного», поэтому в итоге стоят три числа, а не одно.
set -uo pipefail

# Унаследованное окружение git сильнее рабочего каталога: без снятия действия
# уезжают в индекс той копии, из которой скрипт запущен (класс общий с
# scripts/ci-local-outcome-inject.sh).
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

REMOTE="${KACHO_RELEASE_REMOTE:-origin}"
TRUNK="${KACHO_RELEASE_TRUNK:-main}"
SKIP_PACK=0

usage() {
    cat >&2 <<USAGE
употребление: $0 <версия> [--skip-pack]

  <версия>      выпускаемая версия в форме vМАЖОР.МИНОР.ПАТЧ[-предвыпуск]
  --skip-pack   не спрашивать предпосылку упаковки (П8) — она дорогая;
                тогда она уходит в «не спрошено», а НЕ в «выполнена»

переменные:
  KACHO_RELEASE_REMOTE  имя удалённого репозитория (умолчание: origin)
  KACHO_RELEASE_TRUNK   имя ствола (умолчание: main)
USAGE
}

VERSION=""
for arg in "$@"; do
    case "$arg" in
        --skip-pack) SKIP_PACK=1 ;;
        -h|--help)   usage; exit 2 ;;
        -*)          echo "неизвестный ключ: $arg" >&2; usage; exit 2 ;;
        *)
            if [ -n "$VERSION" ]; then
                echo "версия названа дважды: '$VERSION' и '$arg'" >&2; exit 2
            fi
            VERSION="$arg"
            ;;
    esac
done
[ -n "$VERSION" ] || { usage; exit 2; }

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "не репозиторий git: $PWD" >&2; exit 2; }
cd "$ROOT" || exit 2
[ -r go.mod ] || { echo "в корне нет go.mod: $ROOT" >&2; exit 2; }

# ─────────────────────────────────────────────────────────────────────────────
# Сравнение версий — СВОЁ, потому что `sort -V` semver не соблюдает
# ─────────────────────────────────────────────────────────────────────────────
# `sort -V` считает `v1.0.0-rc1` СТАРШЕ `v1.0.0` (дефис для неё — обычный
# символ, а более длинная строка сортируется позже). По semver предвыпуск
# МЛАДШЕ своего выпуска, и на этом расхождении предпосылка П4 отвергала бы
# законный выпуск `v1.0.0` вслед за `v1.0.0-rc1` — то есть ложной находкой
# закрывала бы ровно тот переход, ради которого предвыпуски и делают.
#
# ГРАНИЦА НАЗВАНА ЧЕСТНО: ядро версии сравнивается по полям численно, наличие
# предвыпуска — по правилу semver, а два РАЗНЫХ предвыпуска одного ядра
# сравниваются `sort -V`. Порядок числовых и буквенных идентификаторов внутри
# предвыпуска semver задаёт тоньше, чем `sort -V`; для нашего употребления
# (rc1 → rc2 → выпуск) этого достаточно, а полный разбор потребовал бы
# второго компаратора рядом с уже существующим в `golang.org/x/mod/semver`.

# semver_gt <A> <B> → истина, если A строго старше B
semver_gt() {
    local a="${1#v}" b="${2#v}"
    local acore="${a%%-*}" bcore="${b%%-*}"
    local apre="" bpre=""
    [ "$a" != "$acore" ] && apre="${a#*-}"
    [ "$b" != "$bcore" ] && bpre="${b#*-}"

    local i af bf
    for i in 1 2 3; do
        af="$(printf '%s' "$acore" | cut -d. -f$i)"; af="${af:-0}"
        bf="$(printf '%s' "$bcore" | cut -d. -f$i)"; bf="${bf:-0}"
        [ "$af" -gt "$bf" ] 2>/dev/null && return 0
        [ "$af" -lt "$bf" ] 2>/dev/null && return 1
    done

    # Ядра равны. Выпуск старше своего предвыпуска — правило semver.
    [ -z "$apre" ] && [ -n "$bpre" ] && return 0
    [ -n "$apre" ] && [ -z "$bpre" ] && return 1
    [ "$apre" = "$bpre" ] && return 1
    [ "$(printf '%s\n%s\n' "$apre" "$bpre" | sort -V | tail -1)" = "$apre" ]
}

# ─────────────────────────────────────────────────────────────────────────────
# Учёт предпосылок: выполнена · нарушена · не спрошена
# ─────────────────────────────────────────────────────────────────────────────
checked=0; findings=(); unasked=()

ok()      { checked=$((checked + 1)); printf '  ✓ П%-2s %s\n' "$1" "$2"; }
finding() { checked=$((checked + 1)); findings+=("П$1"); printf '  ✗ П%-2s %s\n' "$1" "$2"; }
unask()   { unasked+=("П$1");        printf '  ? П%-2s %s\n' "$1" "$2"; }

printf 'производитель версии: предпосылки выпуска %s\n' "$VERSION"

# ── П1. Форма версии ─────────────────────────────────────────────────────────
# Годна ровно semver с обязательным `v`: прокси Go иных форм не принимает, и
# ошибка здесь стоила бы необратимой публикации мусорного имени.
semver_re='^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$'
if [[ "$VERSION" =~ $semver_re ]]; then
    ok 1 "форма версии годна"
else
    finding 1 "форма версии негодна: '$VERSION' — ожидается vМАЖОР.МИНОР.ПАТЧ[-предвыпуск]"
fi

# ── П2. Мажор согласован с путём модуля ──────────────────────────────────────
# Мажор ≥2 обязан нести суффикс `/vN` в пути модуля — иначе опубликованную
# версию НЕЛЬЗЯ импортировать по объявленному пути, и узнается это у
# потребителя, после публикации, то есть необратимо.
MODPATH="$(awk '$1=="module"{print $2; exit}' go.mod)"
MAJOR="$(printf '%s' "$VERSION" | sed -n 's/^v\([0-9][0-9]*\)\..*/\1/p')"
if [ -z "$MODPATH" ]; then
    finding 2 "в go.mod нет строки module — путь модуля не установлен"
elif [ -z "$MAJOR" ]; then
    unask 2 "мажор не выделен (форма версии негодна) — согласование с путём '$MODPATH' не спрошено"
elif [ "$MAJOR" -ge 2 ] && [[ "$MODPATH" != */v$MAJOR ]]; then
    finding 2 "мажор $MAJOR требует суффикса /v$MAJOR в пути модуля, а путь — '$MODPATH'"
elif [ "$MAJOR" -lt 2 ] && [[ "$MODPATH" =~ /v[0-9]+$ ]]; then
    finding 2 "путь модуля '$MODPATH' объявляет мажорный суффикс, а версия $VERSION — мажор $MAJOR"
else
    ok 2 "мажор $MAJOR согласован с путём модуля '$MODPATH'"
fi

# ── П7. В go.mod нет ни одного `replace` ─────────────────────────────────────
# Проверяется без сети, поэтому стоит здесь.
#
# ЗДЕСЬ СТОЯЛО «у внешнего потребителя не резолвится» — ЭТО НЕВЕРНО, и опровергла
# это собственная инъекция гейта годности (ось 2 была написана под это допущение
# и осталась ЗЕЛЁНОЙ). `replace` действует ТОЛЬКО в главном модуле и у
# потребителя ИГНОРИРУЕТСЯ — сломать его сборку он не может by construction.
#
# Настоящих причин две, и обе остаются:
#   * потребитель, игнорируя нашу подмену, получает ТУ редакцию зависимости,
#     которую подменял `replace`, — то есть редакцию, на которой мы ничего не
#     проверяли. Мы выпускаем версию, испытанную не в том составе, в каком её
#     соберут;
#   * `replace` на локальный путь ломает НАШУ ЖЕ сборку при одиночном клоне
#     (CI, docker-сборка) — действующий запрет `polyrepo.md`.
# Замер на 0c3b3313a798: `grep -cE '^[[:space:]]*replace' go.mod` → 0.
REPLACES="$(grep -cE '^[[:space:]]*replace' go.mod || true)"
if [ "$REPLACES" != "0" ]; then
    finding 7 "go.mod несёт $REPLACES replace — потребитель их игнорирует и соберёт НЕ тот состав, что испытан"
else
    ok 7 "replace в go.mod нет (осмотрено строк go.mod: $(wc -l < go.mod))"
fi

# ── Сеть: один запрос, и его исход решает, спрошены ли П3–П6 ────────────────
# Недоступный origin — «не выполнилось», а не «предпосылка нарушена»: молчание
# источника никогда не читается ни как «да», ни как «нет».
REMOTE_REFS=""
if REMOTE_REFS="$(git ls-remote --refs "$REMOTE" 2>/dev/null)" && [ -n "$REMOTE_REFS" ]; then
    NET=1
else
    NET=0
fi

TRUNK_SHA=""
if [ "$NET" = "1" ]; then
    TRUNK_SHA="$(printf '%s\n' "$REMOTE_REFS" | awk -v r="refs/heads/$TRUNK" '$2==r{print $1; exit}')"
fi

# ── П3. Версия ещё не занята ─────────────────────────────────────────────────
if [ "$NET" = "0" ]; then
    unask 3 "занятость версии на $REMOTE не спрошена: удалённый репозиторий не отвечает"
elif printf '%s\n' "$REMOTE_REFS" | awk -v r="refs/tags/$VERSION" '$2==r{found=1} END{exit !found}'; then
    finding 3 "версия $VERSION уже опубликована на $REMOTE — переиздать её другим содержимым нельзя"
else
    ok 3 "версия $VERSION на $REMOTE не занята"
fi

# ── П4. Версия строго больше уже опубликованной ──────────────────────────────
# Иначе `@latest` не сдвинется, и это молчаливо: публикация состоится, а
# потребитель по-прежнему получит прежнюю версию.
if [ "$NET" = "0" ]; then
    unask 4 "старшинство версии не спрошено: удалённый репозиторий не отвечает"
else
    PUBLISHED="$(printf '%s\n' "$REMOTE_REFS" \
        | awk '$2 ~ /^refs\/tags\/v[0-9]+\.[0-9]+\.[0-9]+/ {sub(/^refs\/tags\//,"",$2); print $2}')"
    PUB_COUNT="$(printf '%s' "$PUBLISHED" | grep -c . || true)"
    if [ "$PUB_COUNT" = "0" ]; then
        ok 4 "опубликованных версий на $REMOTE ноль — $VERSION становится точкой отсчёта совместимости"
    else
        # Старшая ищется ТЕМ ЖЕ компаратором, каким потом сравнивается: отбор
        # через `sort -V`, а сравнение через semver разошлись бы на предвыпуске
        # и разошлись бы молча.
        NEWEST=""
        while IFS= read -r pv; do
            [ -n "$pv" ] || continue
            if [ -z "$NEWEST" ] || semver_gt "$pv" "$NEWEST"; then NEWEST="$pv"; fi
        done <<< "$PUBLISHED"
        if semver_gt "$VERSION" "$NEWEST"; then
            ok 4 "версия $VERSION старше уже опубликованной $NEWEST (осмотрено версий: $PUB_COUNT)"
        else
            finding 4 "версия $VERSION не старше уже опубликованной $NEWEST (осмотрено версий: $PUB_COUNT)"
        fi
    fi
fi

# ── П5. Публикуется вершина ствола, и она осмотрена ──────────────────────────
# Тег ставится на ревизию, которую владелец видит в своей рабочей копии: иначе
# публикуется то, чего никто не читал. Ревизия берётся у origin, а не из
# локальной ссылки — локальная отстаёт молча.
HEAD_SHA="$(git rev-parse HEAD 2>/dev/null || true)"
if [ "$NET" = "0" ]; then
    unask 5 "вершина ствола не спрошена: удалённый репозиторий не отвечает"
elif [ -z "$TRUNK_SHA" ]; then
    finding 5 "на $REMOTE нет ветки $TRUNK — публиковать нечего"
elif [ "$HEAD_SHA" != "$TRUNK_SHA" ]; then
    finding 5 "HEAD рабочей копии ($(printf '%.12s' "$HEAD_SHA")) не равен вершине $REMOTE/$TRUNK ($(printf '%.12s' "$TRUNK_SHA")) — публикуется то, что осмотрено"
else
    ok 5 "HEAD равен вершине $REMOTE/$TRUNK ($(printf '%.12s' "$TRUNK_SHA"))"
fi

# ── П6. Посторонних локальных `v*` нет ───────────────────────────────────────
# Локальный семантический тег, не являющийся предком ствола, публикует код ВНЕ
# ствола при первом же побочном `git push --tags`. Цена необратима, а жест
# рутинный. Пока такие ссылки есть, линия выпуска не открывается (#1762).
STRAY=()
if [ "$NET" = "0" ] || [ -z "$TRUNK_SHA" ]; then
    unask 6 "посторонние локальные v* не спрошены: вершина ствола неизвестна"
else
    LOCAL_V="$(git tag --list 'v*' 2>/dev/null)"
    LOCAL_COUNT="$(printf '%s' "$LOCAL_V" | grep -c . || true)"
    while IFS= read -r t; do
        [ -n "$t" ] || continue
        git merge-base --is-ancestor "$t" "$TRUNK_SHA" 2>/dev/null || STRAY+=("$t")
    done <<< "$LOCAL_V"
    if [ "${#STRAY[@]}" -gt 0 ]; then
        finding 6 "локальных v*-тегов вне ствола ${#STRAY[@]} из $LOCAL_COUNT: ${STRAY[*]} — побочный 'git push --tags' опубликует код вне ствола необратимо (#1762)"
    else
        ok 6 "посторонних локальных v* нет (осмотрено локальных тегов: $LOCAL_COUNT)"
    fi
fi

# ── П8. Модуль упаковывается и собирается у внешнего потребителя ─────────────
# Самая дорогая предпосылка и единственная, отвечающая на вопрос «а получит ли
# потребитель то, что соберётся». Спрашивается герметичным гейтом, который
# упаковывает ревизию тем же кодом, что и сам инструментарий, и собирает её в
# пустом модуле.
PACK_TEST='^TestExternalConsumerCanBuildTheModule$'
if [ "$SKIP_PACK" = "1" ]; then
    unask 8 "упаковка не спрошена: позвано с --skip-pack"
elif ! command -v go >/dev/null 2>&1; then
    unask 8 "упаковка не спрошена: go не найден"
elif [ ! -d internal/release ]; then
    finding 8 "герметичного гейта упаковки нет: каталог internal/release отсутствует"
else
    PACK_OUT="$(go test ./internal/release/ -run "$PACK_TEST" -count=1 -v 2>&1)"
    PACK_RC=$?
    # «Тестов к запуску нет» — код 0 и ЗЕЛЁНЫЙ вид. Требуется наблюдённое
    # прохождение по имени, иначе опечатка в отборе читается как успех.
    if [ "$PACK_RC" != "0" ]; then
        finding 8 "модуль не собирается у внешнего потребителя (go test ./internal/release -run $PACK_TEST → $PACK_RC)"
        printf '%s\n' "$PACK_OUT" | tail -20 | sed 's/^/       | /'
    elif ! printf '%s\n' "$PACK_OUT" | grep -q -- '--- PASS: TestExternalConsumerCanBuildTheModule'; then
        finding 8 "гейт упаковки не исполнился: прохождения по имени в выводе нет — вердикта об упаковке НЕТ"
    else
        ok 8 "модуль упаковывается и собирается у внешнего потребителя"
    fi
fi

# ─────────────────────────────────────────────────────────────────────────────
# Итог
# ─────────────────────────────────────────────────────────────────────────────
printf '\nперепись: предпосылок проверено %d, нарушено %d, НЕ спрошено %d\n' \
    "$checked" "${#findings[@]}" "${#unasked[@]}"
[ "${#findings[@]}" -gt 0 ] && printf '  нарушены: %s\n' "${findings[*]}"
[ "${#unasked[@]}" -gt 0 ] && printf '  не спрошены: %s\n' "${unasked[*]}"

if [ "$checked" = "0" ]; then
    echo "обход пуст: не проверено ни одной предпосылки — вердикт беспредметен" >&2
    exit 3
fi
if [ "${#findings[@]}" -gt 0 ]; then
    echo "ВЫПУСК НЕ ОТКРЫТ: предпосылки нарушены — публиковать нельзя" >&2
    exit 1
fi
if [ "${#unasked[@]}" -gt 0 ]; then
    cat >&2 <<'VOID'
ВЕРДИКТА НЕТ: часть предпосылок не спрошена. Не спрошенная предпосылка не
считается выполненной — публиковать по такому прогону нельзя.
VOID
    exit 3
fi

cat <<DONE

Все предпосылки сошлись. Скрипт НИЧЕГО не создал и ничего не отправил.
Остаётся ОДНА команда, и она необратима — выполняет её владелец:

    git push $REMOTE $TRUNK_SHA:refs/tags/$VERSION

Она создаёт ссылку сразу на $REMOTE и не оставляет локального тега вовсе,
поэтому побочный 'git push --tags' после неё ничего лишнего не увезёт.
Проверить, что версия доехала до потребителя:

    scripts/release/probe-published.sh $VERSION
DONE
exit 0
