# Инъекция для `scripts/release/assert-no-module-reciprocity.sh` — предмет один:
# ПРЕДИКАТ МЕНЯЕТ ЦВЕТ ОТ ГРАФА МОДУЛЕЙ, А НЕ ОТ НАПИСАНИЯ ПУТИ.
#
# ЗАЧЕМ. Сегодня предикат зелёный и останется зелёным, пока в дерево не внесут
# обратное требование. Зелёное, которое не может покраснеть, неотличимо от
# зелёного, которое просто всегда зелёное. Завести настоящую взаимность в дереве
# ради доказательства нельзя — она ломает сборку обоих модулей.
#
# КАК ЭТО ДОКАЗЫВАЕТСЯ. Предикат читает объявления модулей и о природе дерева
# ничего не знает. Значит достаточно СИНТЕТИЧЕСКОГО репозитория, в котором
# меняется РОВНО ОДИН факт. Тот же скрипт, тот же вход, разный исход.
#
# ОСЬ 3 — ГЛАВНАЯ, И РАДИ НЕЁ ВСЁ ОСТАЛЬНОЕ. Она проводит ту же одно-фактную
# дельту, что нашлась в дереве (#2231): переименование каталога стабов и самого
# модуля при НЕИЗМЕННОМ графе. Новый предикат обязан НЕ шелохнуться, а прежний
# предикат #1766 — поиск подстроки в пути импорта — обязан на той же дельте
# перевернуться. Ось утверждает ОБЕ половины: без второй «не шелохнулся» было бы
# неотличимо от «ничего не мерит».
#
# ИСХОДЫ: 0 — все утверждения сошлись; 1 — есть провалившиеся; 2 — предмета нет.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX
export GOWORK=off

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUBJECT="$HERE/assert-no-module-reciprocity.sh"
[ -r "$SUBJECT" ] || { echo "предмета нет: $SUBJECT" >&2; exit 2; }
for tool in git go jq awk; do
    command -v "$tool" >/dev/null 2>&1 || { echo "инструмента нет: $tool" >&2; exit 2; }
done

# Временный каталог — ВНЕ всякого репозитория: синтетическое дерево, заведённое
# внутри объемлющего, нашло бы его индекс подъёмом вверх, и вердикт стал бы
# свойством рабочего каталога, а не входа.
tmp="$(mktemp -d "${TMPDIR:-/tmp}/modrecip.XXXXXX")"
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

P="example.com/platform"
S="example.com/service"
V="v0.0.0-20260101000000-aaaaaaaaaaaa"

checked=0; failed=0
pass() { checked=$((checked+1)); printf '  ok   %s\n' "$1"; }
fail() { checked=$((checked+1)); failed=$((failed+1)); printf '  FAIL %s\n     %b\n' "$1" "$2"; }

# gomod <путь-модуля> [<требуемый-модуль> <версия>]
gomod() {
    printf 'module %s\n\ngo 1.26.0\n' "$1"
    [ $# -ge 3 ] && printf '\nrequire %s %s\n' "$2" "$3"
    return 0
}

# mkworld <каталог> <каталог-стабов> <путь-модуля-службы>
#
# Заводит дерево из двух модулей с ОДНОСТОРОННИМ ребром «служба -> платформа»
# и одним импортом стабов внутри модуля платформы — то самое место, которое
# прежний предикат #1766 считал взаимностью.
mkworld() {
    local d="$1" stub="$2" svc="${3:-$S}"
    rm -rf "$d"; mkdir -p "$d/pkg/api/$stub/cloud/iam/v1" "$d/pkg/authz" "$d/services/iam"
    gomod "$P"            > "$d/go.mod"
    gomod "$svc" "$P" "$V" > "$d/services/iam/go.mod"
    printf 'package iamv1\n'                                        > "$d/pkg/api/$stub/cloud/iam/v1/iam.go"
    printf 'package authz\n\nimport _ "%s/pkg/api/%s/cloud/iam/v1"\n' "$P" "$stub" > "$d/pkg/authz/check.go"
    ( cd "$d" && git init -q -b main . && git add -A \
      && git -c user.email=x@y -c user.name=x commit -qm w ) >/dev/null 2>&1
    printf '%s' "$d"
}

run() { ( "$SUBJECT" --root "$1" 2>&1 ); }

# oldPredicate — ПРЕЖНИЙ предикат #1766 дословно: подстрока в пути импорта,
# по прод-коду `pkg/` вне сгенерённого `pkg/api`. Воспроизведён здесь не ради
# насмешки, а как контроль оси 3: без него «новый не шелохнулся» неотличимо от
# «новый ничего не мерит».
oldPredicate() { # oldPredicate <дерево> <каталог-стабов>
    git -C "$1" grep -l "pkg/api/$2/cloud/iam/v1" HEAD -- "pkg/*" ":!pkg/api/*" 2>/dev/null | wc -l
}

echo "инъекция: взаимность графа модулей, а не написание пути"

# ── ось 1: КОНТРОЛЬ — ребро одностороннее -> молчит ──────────────────────────
w="$(mkworld "$tmp/oneway" alpha)"
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "0" ]; then pass "1 одностороннее ребро -> код 0 (законный близнец молчит)"
else fail "1 одностороннее ребро" "ожидался 0, получен $RC:\n$OUT"; fi
if [[ "$OUT" == *"объявлений осмотрено 2"* && "$OUT" == *"рёбер внутри дерева 1"* ]]; then
    pass "1' перепись называет объём осмотренного: «ноль находок» отличимо от «ноль прочитанного»"
else fail "1' перепись" "её нет в выводе:\n$OUT"; fi

# ── ось 2: ИНЪЕКЦИЯ — обратное require (меняется РОВНО оно) -> находка ───────
w="$(mkworld "$tmp/cycle" alpha)"
gomod "$P" "$S" "v1.0.0" > "$w/go.mod"
( cd "$w" && git add -A && git -c user.email=x@y -c user.name=x commit -qm back ) >/dev/null 2>&1
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "1" ]; then pass "2 взаимное require -> код 1 (находка)"
else fail "2 взаимное require" "ожидался 1, получен $RC:\n$OUT"; fi
if [[ "$OUT" == *"$P"* && "$OUT" == *"$S"* && "$OUT" == *"go.mod"* && "$OUT" == *"services/iam/go.mod"* ]]; then
    pass "2' находка НАЗЫВАЕТ координаты обоих рёбер, а не только факт цикла"
else fail "2' находка называет координаты" "их нет в выводе:\n$OUT"; fi

# ── ось 3: ГЛАВНАЯ — переименование вердикта НЕ двигает, а прежний предикат двигает
# Две одно-фактные дельты одного и того же переименования: каталог стабов
# alpha -> beta и путь модуля службы. Граф при этом неизменен: 2 модуля, 1 ребро.
w1="$(mkworld "$tmp/name-before" alpha "$S")"
w2="$(mkworld "$tmp/name-after"  beta  "example.com/renamed")"
O1="$(run "$w1")"; R1=$?
O2="$(run "$w2")"; R2=$?
if [ "$R1" = "0" ] && [ "$R2" = "0" ]; then
    pass "3 переименование каталога и модуля вердикта НЕ двигает (0 -> 0)"
else fail "3 переименование двигает вердикт" "коды $R1 и $R2, ожидались 0 и 0:\n$O1\n---\n$O2"; fi
E1="$(printf '%s' "$O1" | sed -n 's/.*рёбер внутри дерева \([0-9]*\).*/\1/p')"
E2="$(printf '%s' "$O2" | sed -n 's/.*рёбер внутри дерева \([0-9]*\).*/\1/p')"
if [ "$E1" = "1" ] && [ "$E2" = "1" ]; then
    pass "3' измеряемая величина (рёбер) при переименовании неизменна: $E1 -> $E2"
else fail "3' величина при переименовании" "рёбер $E1 -> $E2, ожидалось 1 -> 1"; fi
# Ось 3'' зовёт прежний предикат НАПРЯМУЮ, а не через предмет: она утверждает,
# что дельта переименования РЕАЛЬНА, и потому от исправности предмета не зависит.
# Без неё ось 3 («не шелохнулся») была бы вакуумной на любом предмете.
B1="$(oldPredicate "$w1" alpha)"; B2="$(oldPredicate "$w1" beta)"
if [ "$B1" = "1" ] && [ "$B2" = "0" ]; then
    pass "3'' КОНТРОЛЬ: прежний предикат #1766 на ТОЙ ЖЕ дельте переворачивается ($B1 -> $B2)"
else fail "3'' прежний предикат" "по старому имени $B1, по новому $B2 — ожидалось 1 и 0; без этого «новый не шелохнулся» неотличимо от «новый ничего не мерит»"; fi

# ── ось 4: самотребование — вырожденный цикл, тоже находка ──────────────────
w="$(mkworld "$tmp/self" alpha)"
gomod "$P" "$P" "v1.0.0" > "$w/go.mod"
( cd "$w" && git add -A && git -c user.email=x@y -c user.name=x commit -qm self ) >/dev/null 2>&1
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "1" ]; then pass "4 самотребование -> код 1, а не молчание"
else fail "4 самотребование" "ожидался 1, получен $RC:\n$OUT"; fi

# ── ось 5: цикл, замкнутый ПОДМЕНОЙ пути -> находка (версия спрятана) ────────
w="$(mkworld "$tmp/replace" alpha)"
{ gomod "$P"; printf '\nreplace %s => ./services/iam\n' "$S"; } > "$w/go.mod"
( cd "$w" && git add -A && git -c user.email=x@y -c user.name=x commit -qm rep ) >/dev/null 2>&1
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "1" ] && [[ "$OUT" == *"replace"* ]]; then
    pass "5 цикл через подмену пути -> код 1: версия спрятана, цикл нет"
else fail "5 цикл через подмену" "ожидался 1 с упоминанием replace, получен $RC:\n$OUT"; fi

# ── ось 6: объявлений меньше двух -> ВЕРДИКТА НЕТ, а не зелёное ─────────────
d="$tmp/single"; rm -rf "$d"; mkdir -p "$d"
gomod "$P" > "$d/go.mod"
( cd "$d" && git init -q -b main . && git add -A && git -c user.email=x@y -c user.name=x commit -qm s ) >/dev/null 2>&1
OUT="$(run "$d")"; RC=$?
if [ "$RC" = "3" ]; then pass "6 один модуль -> код 3 (вердикта нет), НЕ 0: цикл невозможен by construction"
else fail "6 один модуль" "ожидался 3, получен $RC:\n$OUT"; fi

# ── ось 7: объявление не прочиталось -> ВЕРДИКТА НЕТ, а не зелёное ─────────
w="$(mkworld "$tmp/broken" alpha)"
printf 'это не объявление модуля\n@@@ ){\n' > "$w/services/iam/go.mod"
( cd "$w" && git add -A && git -c user.email=x@y -c user.name=x commit -qm brk ) >/dev/null 2>&1
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "3" ]; then pass "7 нечитаемое объявление -> код 3: молчание источника не читается как «да»"
else fail "7 нечитаемое объявление" "ожидался 3, получен $RC:\n$OUT"; fi

# ── ось 8: КОНТРОЛЬ распознавателя — путь модуля В КОММЕНТАРИИ ребром не является
# Без этой оси предикат считал бы ребром собственное объяснение и краснел бы на
# документе — класс, который корпус ловит у распознавателей.
w="$(mkworld "$tmp/comment" alpha)"
{ gomod "$P"; printf '\n// взаимности здесь нет: require %s v1.0.0 — это ОБЪЯСНЕНИЕ, а не директива\n' "$S"; } > "$w/go.mod"
( cd "$w" && git add -A && git -c user.email=x@y -c user.name=x commit -qm cmt ) >/dev/null 2>&1
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "0" ]; then pass "8 путь модуля в комментарии ребром не считается -> код 0"
else fail "8 путь модуля в комментарии" "ожидался 0, получен $RC — предикат читает текст, а не директиву:\n$OUT"; fi
if [ "$(grep -c "require $S" "$w/go.mod")" = "1" ]; then
    pass "8' контроль оси 8: строка в файле ЕСТЬ — поиск по тексту её бы нашёл"
else fail "8' контроль оси 8" "строки нет — ось ничего не проверяет"; fi

# ── ось 9: НЕотслеживаемое объявление предметом не является ─────────────────
w="$(mkworld "$tmp/untracked" alpha)"
mkdir -p "$w/scratch"
gomod "$P" "$S" "v1.0.0" > "$w/scratch/go.mod"   # обратное ребро, но вне индекса
OUT="$(run "$w")"; RC=$?
if [ "$RC" = "0" ] && [[ "$OUT" == *"объявлений осмотрено 2"* ]]; then
    pass "9 неотслеживаемый go.mod в счёт не идёт: единица счёта — отслеживаемое объявление"
else fail "9 неотслеживаемое объявление" "ожидался 0 при осмотренных 2, получен $RC:\n$OUT"; fi

# ── ось 10: запуск ИЗ ПОДКАТАЛОГА даёт тот же вердикт ──────────────────────
# Без --full-name перечень объявлений печатался бы от текущего каталога и вышел
# бы пустым — то есть зелёное по причине, к дереву не относящейся.
w="$(mkworld "$tmp/subdir" alpha)"
OUT="$( cd "$w/pkg/authz" && "$SUBJECT" --root . 2>&1 )"; RC=$?
if [ "$RC" = "0" ] && [[ "$OUT" == *"объявлений осмотрено 2"* ]]; then
    pass "10 запуск из подкаталога: осмотрено те же 2 объявления, вердикт тот же"
else fail "10 запуск из подкаталога" "ожидался 0 при осмотренных 2, получен $RC:\n$OUT"; fi

# ── ось 11: дерево не под git -> ВЕРДИКТА НЕТ ──────────────────────────────
d="$tmp/nogit"; rm -rf "$d"; mkdir -p "$d/services/iam"
gomod "$P" > "$d/go.mod"; gomod "$S" "$P" "$V" > "$d/services/iam/go.mod"
OUT="$(run "$d")"; RC=$?
if [ "$RC" = "3" ]; then pass "11 дерево не под git -> код 3: обход пуст, пустой обход зелёным не бывает"
else fail "11 дерево не под git" "ожидался 3, получен $RC:\n$OUT"; fi

# ── ось 12: позван неверно -> код 2, отличный и от находки, и от «вердикта нет»
OUT="$("$SUBJECT" --root 2>&1)"; RC=$?
if [ "$RC" = "2" ]; then pass "12 --root без значения -> код 2 (позван неверно)"
else fail "12 позван неверно" "ожидался 2, получен $RC:\n$OUT"; fi

printf '\nперепись инъекции: утверждений %d, провалено %d\n' "$checked" "$failed"
if [ "$checked" -eq 0 ]; then
    echo "ПРЕДМЕТА НЕТ: не исполнено ни одного утверждения" >&2; exit 2
fi
[ "$failed" -eq 0 ] || exit 1
exit 0
