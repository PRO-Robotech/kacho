# Инъекция для `scripts/release/assert-foundation-floor.sh` — предмет один:
# ОПУБЛИКОВАННЫЙ ПАКЕТ, ИСЧЕЗНУВШИЙ ИЗ СОБРАННОГО ДЕРЕВА.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ПРОГОНОВ ТРИ, А НЕ ДВА
#
# Инъекция обязана ронять ТОЛЬКО проверяемое. Рядом с полом стоит проба годности
# `probe-published.sh`, судящая ДРУГОЕ свойство того же выпуска — собирается ли
# он у постороннего потребителя. Поэтому каждая ось спрашивается тремя прогонами:
#
#   контроль            состав сошёлся, выпуск собирается -> молчат ОБА
#   инъекция нового     пакет исчез из сборки             -> краснеет ТОЛЬКО пол
#   инъекция старого    выпуск не собирается              -> краснеет ТОЛЬКО проба
#
# Без третьего прогона молчание существующей проверки неотличимо от молчания
# МЁРТВОЙ: проба годности могла бы утратить способность падать, и новый пол
# этого не показал бы ничем.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАКОННЫЙ БЛИЗНЕЦ — И ОН НЕ ВЫДУМАН
#
# Пакет, ДОБАВЛЕННЫЙ в сборку, находкой быть не должен: фундамент растёт, и
# переклассифицированный каталог обязан приехать. Близнец наблюдался на живом
# дереве в день заведения пола — сборка ствола добавила к выпуску v1.3.1 ровно
# два каталога (`modulemanifest`, `modulemanifest/producer`), переклассифицированных
# MR #2584. Пол, краснеющий на них, отключили бы первым, поэтому его молчание
# утверждается наравне с находкой.
#
# ─────────────────────────────────────────────────────────────────────────────
# ГЛАВНАЯ ОСЬ — СОСТАВ, А НЕ СЧЁТ, И ОНА ПРОВЕРЯЕТСЯ ОТДЕЛЬНО
#
# Ось 7 подаёт дерево, где ОДИН пакет исчез и ОДИН добавлен: счёт сошёлся, состав
# нет. Пол обязан краснеть. Это не край и не редкость — ровно это наблюдалось на
# живом замере (в выпуске 68 пакетов, в сборке 68, исчезло 2, добавилось 2), и
# пол, сверяющий ЧИСЛА, прошёл бы там зелёным.
#
# ─────────────────────────────────────────────────────────────────────────────
# ВСЁ ОФФЛАЙН, И ЭТО НЕ ПОДДЕЛКА МЕХАНИЗМА
#
# Выпуск берётся через ФАЙЛОВЫЙ прокси (`GOPROXY=file://…`) — тот же путь, тем же
# `go mod download`, с той же распаковкой зипа и тем же обходом. Подменён
# ИСТОЧНИК, а не механизм: пол сам GOPROXY не переопределяет, и настоящий его
# вызов отличается только адресом посредника.
#
# ГРАНИЦА ФИКСТУРЫ, НАЗВАННАЯ ЧЕСТНО. Синтетического модуля нет и не может быть
# в публичной базе контрольных сумм, поэтому здесь она отключена на домен
# фикстуры. Пол сам её НЕ отключает. Следствие: полоса проверки сумм этой
# инъекцией НЕ покрыта.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUBJECT="$HERE/assert-foundation-floor.sh"
NEIGHBOUR="$HERE/probe-published.sh"

[ -r "$SUBJECT" ] || {
    echo "ОТКАЗ: испытуемого нет: $SUBJECT" >&2
    echo "  Инъекция без испытуемого вердикта не даёт — это НЕ ВЫПОЛНИЛОСЬ." >&2
    exit 3; }
[ -r "$NEIGHBOUR" ] || {
    echo "ОТКАЗ: соседа нет: $NEIGHBOUR — третий прогон невозможен" >&2; exit 3; }
command -v go      >/dev/null 2>&1 || { echo "инструмента нет: go" >&2; exit 3; }
command -v python3 >/dev/null 2>&1 || { echo "инструмента нет: python3" >&2; exit 3; }

tmp="$(mktemp -d)"
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

MOD="example.com/foundation"
VER="v1.4.0"

checked=0; failed=0
pass() { checked=$((checked + 1)); printf '  ✓ %s\n' "$1"; }
fail() { checked=$((checked + 1)); failed=$((failed + 1)); printf '  ✗ %s\n     %s\n' "$1" "${2:-}"; }

# ── ВЫПУСК: файловый прокси со ВСЕМ, что нужно для распаковки ───────────────
#
# mkproxy <каталог> <собирается-ли:0|1> <есть-ли-версия:0|1>
#
# Зип несёт ЧЕТЫРЕ каталога, и один из них — только с тестом: он проверяет
# заявление пола о единице счёта (каталог с одними тестами импортируемым пакетом
# НЕ является, и его отсутствие в сборке находкой быть не должно).
mkproxy() {
    local dir="$1" buildable="$2" have="$3"
    python3 - "$dir" "$MOD" "$VER" "$buildable" "$have" <<'PY'
import os, sys, zipfile
dir_, mod, ver, buildable, have = sys.argv[1:6]
vdir = os.path.join(dir_, *mod.split("/"), "@v")
os.makedirs(vdir, exist_ok=True)
if have != "1":
    open(os.path.join(vdir, "list"), "w").close()
    sys.exit(0)
gomod = "module %s\n\ngo 1.21\n" % mod
ids = ('package ids\n\nfunc NewID(p string) string { return p + "0" }\n'
       if buildable == "1" else
       'package ids\n\nfunc NewID(p string) string { return p + }\n')
open(os.path.join(vdir, "list"), "w").write(ver + "\n")
open(os.path.join(vdir, ver + ".mod"), "w").write(gomod)
open(os.path.join(vdir, ver + ".info"), "w").write(
    '{"Version":"%s","Time":"2000-01-01T00:00:00Z"}' % ver)
with zipfile.ZipFile(os.path.join(vdir, ver + ".zip"), "w") as z:
    p = "%s@%s/" % (mod, ver)
    z.writestr(p + "go.mod", gomod)
    z.writestr(p + "LICENSE", "Apache-2.0\n")
    z.writestr(p + "ids/ids.go", ids)
    z.writestr(p + "authz/v1/opts.go", "package authzv1\n\nconst Marker = 1\n")
    z.writestr(p + "api/v1/op.go", "package apiv1\n\nconst Marker = 2\n")
    # Каталог с ОДНИМИ тестами: импортируемым пакетом не является.
    z.writestr(p + "onlytests/x_test.go", "package onlytests\n")
PY
}

# ── СОБРАННОЕ ДЕРЕВО: что положил бы производитель ──────────────────────────
#
# mktree <каталог> <вид>
#   control   — состав тот же, что в выпуске
#   vanished  — нет `authz/v1`
#   added     — плюс `newpkg` (законный близнец)
#   swap      — нет `authz/v1`, зато есть `newpkg`: СЧЁТ СОШЁЛСЯ, состав нет
#   empty     — пусто
mktree() {
    local dir="$1" kind="$2"
    rm -rf "$dir"; mkdir -p "$dir"
    [ "$kind" = "empty" ] && return 0
    printf 'module %s\n\ngo 1.21\n' "$MOD" > "$dir/go.mod"
    printf 'Apache-2.0\n' > "$dir/LICENSE"
    mkdir -p "$dir/ids" "$dir/api/v1"
    printf 'package ids\n\nfunc NewID(p string) string { return p + "0" }\n' > "$dir/ids/ids.go"
    printf 'package apiv1\n\nconst Marker = 2\n' > "$dir/api/v1/op.go"
    case "$kind" in
        control|added)
            mkdir -p "$dir/authz/v1"
            printf 'package authzv1\n\nconst Marker = 1\n' > "$dir/authz/v1/opts.go" ;;
    esac
    case "$kind" in
        added|swap)
            mkdir -p "$dir/newpkg"
            printf 'package newpkg\n\nconst Marker = 3\n' > "$dir/newpkg/n.go" ;;
    esac
    return 0
}

# run_floor <прокси> <дерево> [довод…] → RC, OUT
run_floor() {
    local proxy="$1" tree="$2"; shift 2
    OUT="$(GOPROXY="file://$proxy" GONOSUMDB="example.com/*" GOSUMDB=off GOFLAGS= \
        KACHO_FOUNDATION_MODULE="$MOD" \
        bash "$SUBJECT" "$tree" "$@" 2>&1)"
    RC=$?
}

# run_neighbour <прокси> → NRC, NOUT
run_neighbour() {
    NOUT="$(GOPROXY="file://$1" GONOSUMDB="example.com/*" GOSUMDB=off GOFLAGS= \
        KACHO_RELEASE_MODULE="$MOD" \
        bash "$NEIGHBOUR" "$VER" "$MOD/ids" 2>&1)"
    NRC=$?
}

PROXY_OK="$tmp/proxy-ok";      mkproxy "$PROXY_OK"     1 1
PROXY_BAD="$tmp/proxy-bad";    mkproxy "$PROXY_BAD"    0 1
PROXY_EMPTY="$tmp/proxy-none"; mkproxy "$PROXY_EMPTY"  1 0

echo "инъекция пола фундамента: цвет меняется от СОСТАВА собранного дерева"

# ══════════════════════════════════════════════════════════════════════════════
# ПРОГОН 1 — КОНТРОЛЬ: всё цело, МОЛЧАТ ОБА
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-control" control
run_floor "$PROXY_OK" "$tmp/t-control"
if [ "$RC" = "0" ]; then pass "1   контроль: состав сошёлся -> пол молчит"
else fail "1   контроль" "ожидался 0, получен $RC:\n$OUT"; fi

run_neighbour "$PROXY_OK"
if [ "$NRC" = "0" ]; then pass "1'  контроль: выпуск собирается -> сосед молчит"
else fail "1'  контроль соседа" "ожидался 0, получен $NRC:\n$NOUT"; fi

# Перепись обязана печатать ОБЕ величины: одно число скрывает ровно тот случай,
# ради которого пол заведён.
if [[ "$OUT" == *"в выпуске 3, в собранном дереве 3"* ]]; then
    pass "1'' перепись печатает ОБЕ величины (в выпуске 3, в сборке 3)"
else fail "1'' перепись" "обеих величин нет в выводе:\n$OUT"; fi

# Заявление о единице счёта: `onlytests` лежит в ВЫПУСКЕ и отсутствует в дереве,
# и находкой это не является — импортируемым пакетом он не был.
if [[ "$OUT" != *"onlytests"* ]]; then
    pass "1''' каталог с одними тестами импортируемым пакетом не считается"
else fail "1''' единица счёта" "onlytests попал в вердикт:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ПРОГОН 2 — ИНЪЕКЦИЯ НОВОГО: пакет исчез, краснеет ТОЛЬКО пол
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-vanished" vanished
run_floor "$PROXY_OK" "$tmp/t-vanished"
if [ "$RC" = "1" ]; then pass "2   пакет исчез из сборки -> НАХОДКА (код 1)"
else fail "2   исчезнувший пакет" "ожидался 1, получен $RC:\n$OUT"; fi

if [[ "$OUT" == *"authz/v1"* ]]; then
    pass "2'  находка НАЗЫВАЕТ координату исчезнувшего пакета"
else fail "2'  координата" "имени пакета в выводе нет:\n$OUT"; fi

if [[ "$OUT" == *"НАХОДКА"* ]]; then
    pass "2'' находка объявлена словом, а не только кодом"
else fail "2'' слово" "в выводе нет слова НАХОДКА:\n$OUT"; fi

run_neighbour "$PROXY_OK"
if [ "$NRC" = "0" ]; then pass "2''' сосед МОЛЧИТ: выпуск не менялся"
else fail "2''' сосед на чужой оси" "ожидался 0, получен $NRC:\n$NOUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ПРОГОН 3 — ИНЪЕКЦИЯ СТАРОГО: выпуск не собирается, краснеет ТОЛЬКО сосед
# ══════════════════════════════════════════════════════════════════════════════
run_neighbour "$PROXY_BAD"
if [ "$NRC" = "1" ]; then pass "3   выпуск не собирается -> краснеет сосед (код 1)"
else fail "3   сосед способен падать" "ожидался 1, получен $NRC:\n$NOUT"; fi

mktree "$tmp/t-control3" control
run_floor "$PROXY_BAD" "$tmp/t-control3"
if [ "$RC" = "0" ]; then pass "3'  пол МОЛЧИТ: состав тот же, а сборка — не его ось"
else fail "3'  пол на чужой оси" "ожидался 0, получен $RC:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ЗАКОННЫЙ БЛИЗНЕЦ — добавленный пакет находкой НЕ является
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-added" added
run_floor "$PROXY_OK" "$tmp/t-added"
if [ "$RC" = "0" ]; then pass "4   законный близнец: пакет ДОБАВЛЕН -> пол молчит"
else fail "4   законный близнец" "ожидался 0, получен $RC:\n$OUT"; fi

if [[ "$OUT" == *"ДОБАВЛЕНО 1"* ]]; then
    pass "4'  добавленное НАЗВАНО переписью, а не замолчано"
else fail "4'  перепись добавленного" "в выводе нет счёта добавленных:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ГЛАВНАЯ ОСЬ — СЧЁТ СОШЁЛСЯ, СОСТАВ НЕТ
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-swap" swap
run_floor "$PROXY_OK" "$tmp/t-swap"
if [ "$RC" = "1" ]; then pass "5   счёт сошёлся, состав нет -> НАХОДКА (пол судит СОСТАВ)"
else fail "5   состав против счёта" "ожидался 1, получен $RC:\n$OUT"; fi

if [[ "$OUT" == *"в выпуске 3, в собранном дереве 3"* ]]; then
    pass "5'  и перепись это ПОКАЗЫВАЕТ: 3 и 3 при исчезнувшем пакете"
else fail "5'  перепись равных счётов" "равных величин в выводе нет:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ПУСТОЙ ОБХОД ЗЕЛЁНОГО НЕ ДАЁТ
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-empty" empty
run_floor "$PROXY_OK" "$tmp/t-empty"
if [ "$RC" = "1" ]; then pass "6   сборка пуста -> НАХОДКА, а не зелёное"
else fail "6   пустая сборка" "ожидался 1, получен $RC:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ТРЕТИЙ ИСХОД ОТДЕЛЁН ОТ НАХОДКИ — И ОТ ЗЕЛЁНОГО
# ══════════════════════════════════════════════════════════════════════════════
mktree "$tmp/t-control7" control
OUT="$(GOPROXY=off GONOSUMDB="example.com/*" GOSUMDB=off GOFLAGS= \
    KACHO_FOUNDATION_MODULE="$MOD" bash "$SUBJECT" "$tmp/t-control7" 2>&1)"; RC=$?
if [ "$RC" = "3" ]; then pass "7   посредник недостижим -> ВЕРДИКТА НЕТ (код 3)"
else fail "7   недостижимый посредник" "ожидался 3, получен $RC:\n$OUT"; fi
if [[ "$OUT" == *"НЕ находка"* ]]; then
    pass "7'  состояние НАЗВАНО: «спросить не удалось» отличимо от «пакет исчез»"
else fail "7'  название состояния" "в выводе нет разграничения:\n$OUT"; fi

run_floor "$PROXY_EMPTY" "$tmp/t-control7"
if [ "$RC" = "3" ]; then pass "8   выпусков ноль -> ВЕРДИКТА НЕТ, а не зелёное"
else fail "8   ноль выпусков" "ожидался 3, получен $RC:\n$OUT"; fi

run_floor "$PROXY_OK" "$tmp/t-control7" --version v9.9.9
if [ "$RC" = "3" ]; then pass "9   названного выпуска нет -> ВЕРДИКТА НЕТ, а не находка о дереве"
else fail "9   отсутствующий ориентир" "ожидался 3, получен $RC:\n$OUT"; fi

# ══════════════════════════════════════════════════════════════════════════════
# ПОЗВАН НЕВЕРНО — отдельный код, не смешан с находкой
# ══════════════════════════════════════════════════════════════════════════════
OUT="$(bash "$SUBJECT" 2>&1)"; RC=$?
if [ "$RC" = "2" ]; then pass "10  без доводов -> позван неверно (код 2)"
else fail "10  без доводов" "ожидался 2, получен $RC:\n$OUT"; fi

OUT="$(bash "$SUBJECT" "$tmp/нет-такого-дерева" 2>&1)"; RC=$?
if [ "$RC" = "2" ]; then pass "11  дерева нет -> позван неверно (код 2), а не находка"
else fail "11  отсутствующее дерево" "ожидался 2, получен $RC:\n$OUT"; fi

printf '\nперепись: утверждений исполнено %d, провалено %d\n' "$checked" "$failed"
printf 'вне разбора: полоса проверки контрольных сумм — фикстуры нет в публичной базе\n'
if [ "$checked" = "0" ]; then
    echo "ВЕРДИКТА НЕТ: утверждений исполнено 0 — инъекция беспредметна" >&2
    exit 3
fi
[ "$failed" = "0" ] || exit 1
echo "инъекция сошлась: пол способен упасть по каждой оси и молчать на законных близнецах"
