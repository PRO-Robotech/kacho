# probe-published.sh — проба ГОДНОСТИ опубликованной версии.
#
# ЧТО ОНА СПРАШИВАЕТ. Ровно то, что сделает вынесенный iam: во временном
# каталоге заводится ПУСТОЙ модуль, объявляет зависимость от
# github.com/PRO-Robotech/kacho конкретной версии и собирает программу,
# импортирующую наш пакет. Ни одного `replace`, ни одной локальной ссылки —
# всё идёт через модуль-прокси, как у постороннего потребителя.
#
# ЧЕМ ОНА ОТЛИЧАЕТСЯ ОТ ГЕРМЕТИЧНОГО ГЕЙТА `internal/release`. Гейт
# упаковывает НАШЕ дерево и доказывает, что оно годно к публикации. Эта проба
# спрашивает, СОСТОЯЛАСЬ ЛИ публикация: годное дерево и опубликованная версия —
# разные факты, и первый второго не даёт. До нажатия владельца проба обязана
# быть КРАСНОЙ, и это правильное её состояние, а не поломка.
#
# ПОЧЕМУ ИМПОРТИРУЕТСЯ `pkg/ids`. У него ноль внешних зависимостей, поэтому
# отказ пробы означает наш модуль, а не недоступность чужого. Пакет
# переопределяется вторым аргументом, если спрашивают про другой.
#
# ИСХОДОВ ЧЕТЫРЕ, И ОНИ РАЗНЫЕ:
#   0 — версия опубликована и собирается у внешнего потребителя;
#   1 — НАХОДКА: версии нет либо она не собирается;
#   2 — скрипт позван неверно;
#   3 — НЕ ВЫПОЛНИЛОСЬ: спросить не удалось (нет go, прокси недостижим).
#
# ТРЕТИЙ ИСХОД ОТДЕЛЁН ОТ ВТОРОГО НЕ ПО ТЕКСТУ ОТКАЗА, А ПО КОНТРОЛЮ.
# Прежде главного вопроса задаётся управляющий: знает ли прокси наш ПУТЬ
# МОДУЛЯ вообще. Управляющий прошёл — прокси достижим, и отсутствие версии есть
# находка. Управляющий упал — спросить не удалось, и «не знаю» не выдаётся за
# «нет». Классификация по фразам инструмента этого не даёт: одна и та же фраза
# приходит и на опечатку в адресе (наша поломка), и на пропавшую сеть.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

MODULE="${KACHO_RELEASE_MODULE:-github.com/PRO-Robotech/kacho}"

usage() {
    cat >&2 <<USAGE
употребление: $0 <версия> [<путь-импорта>]

  <версия>        версия, годность которой проверяется (напр. v0.1.0)
  <путь-импорта>  что импортирует потребитель (умолчание: <модуль>/pkg/ids —
                  у него ноль внешних зависимостей, поэтому отказ означает нас)

переменные:
  KACHO_RELEASE_MODULE  путь модуля (умолчание: github.com/PRO-Robotech/kacho)
  GOPROXY               откуда берётся модуль; проба его не переопределяет
USAGE
}

[ $# -ge 1 ] || { usage; exit 2; }
case "$1" in -h|--help) usage; exit 2 ;; esac
VERSION="$1"
IMPORT="${2:-$MODULE/pkg/ids}"

command -v go >/dev/null 2>&1 || {
    echo "НЕ ВЫПОЛНИЛОСЬ: инструмента нет — go не найден" >&2; exit 3; }

tmp="$(mktemp -d)"
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

cons="$tmp/consumer"
mkdir -p "$cons"
# Директива `go` берётся минимально возможной: она поднимется сама до той,
# которую требует наш модуль. Завышенная здесь заставила бы пробу краснеть на
# версии инструмента у спрашивающего, а не на предмете.
printf 'module consumer.example\n\ngo 1.21\n' > "$cons/go.mod"
cat > "$cons/main.go" <<CONSUMER
package main

import probe "$IMPORT"

var _ = probe.NewID

func main() {}
CONSUMER

# Кэш модулей — СВОЙ: общий делит состояние с соседними сессиями на той же
# машине, и уже скачанная кем-то версия сделала бы зелёное купленным чужой
# работой.
export GOMODCACHE="$tmp/modcache"
export GOFLAGS="-mod=mod"
export GOWORK=off

echo "проба годности: модуль $MODULE версии $VERSION, импорт $IMPORT"
echo "  GOPROXY=${GOPROXY:-<умолчание>}"

# ── Управляющий вопрос: достижим ли прокси и знает ли он путь модуля ─────────
ctl_out="$tmp/control.txt"
(cd "$cons" && go list -m -versions "$MODULE") > "$ctl_out" 2>&1
ctl_rc=$?
if [ "$ctl_rc" != "0" ]; then
    echo "  ✗ управляющий вопрос не отвечен (go list -m -versions → $ctl_rc)"
    sed 's/^/     | /' "$ctl_out"
    cat >&2 <<'VOID'
НЕ ВЫПОЛНИЛОСЬ: спросить не удалось — прокси не ответил про путь модуля.
Это не «версия не опубликована»: вердикта нет вовсе, и в успех он не
зачитывается. Проверьте доступность GOPROXY и повторите.
VOID
    exit 3
fi

# Перепись опубликованного печатается ВСЕГДА: «версии нет» и «мы не смотрели»
# обязаны быть различимы, а число опубликованных версий — единственное, что их
# различает без чтения журналов.
published="$(sed "s|^$MODULE||" "$ctl_out" | tr -s ' \t' '\n' | grep -c '^v' || true)"
echo "  ✓ управляющий вопрос отвечен: прокси знает путь $MODULE"
echo "  перепись: опубликованных версий по данным прокси — $published"

# ── Главный вопрос: объявить зависимость и собрать ──────────────────────────
main_out="$tmp/main.txt"
(cd "$cons" && go mod edit -require="$MODULE@$VERSION" && go build ./...) > "$main_out" 2>&1
main_rc=$?
if [ "$main_rc" != "0" ]; then
    echo "  ✗ внешний потребитель не собрал $MODULE@$VERSION"
    sed 's/^/     | /' "$main_out"
    cat >&2 <<FINDING
НАХОДКА: версия $VERSION непригодна внешнему потребителю (опубликованных
версий по данным прокси — $published). Пока производитель версии не позван и
владелец не выполнил его команду, это ОЖИДАЕМОЕ состояние пробы:
    scripts/release/publish-version.sh $VERSION
FINDING
    exit 1
fi

echo "  ✓ внешний потребитель собрал $MODULE@$VERSION с импортом $IMPORT"
exit 0
