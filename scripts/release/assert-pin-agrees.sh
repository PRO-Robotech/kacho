# assert-pin-agrees.sh — ПИН ПЛАТФОРМЫ ЕДИН ВО ВСЕХ ДЕРЕВЬЯХ, ГДЕ ОН ОБЪЯВЛЕН.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# «Какой версией платформы пользуется вынесенная служба» объявлено НЕ в одном
# месте: объявление модуля службы живёт и в стволе платформы, и в накопительной
# линии, и в дереве опубликованной службы (чужой репозиторий). Три копии одного
# предмета расходятся МОЛЧА: каждое дерево по отдельности собирается, и ни один
# прогон о расхождении не говорит.
#
# Замер, ради которого скрипт написан (2026-09-07): три дерева называли ТРИ
# разные псевдоверсии, и обнаружено это было чтением трёх деревьев подряд, а не
# проверкой.
#
# Цена расхождения не в неопрятности: три сборки службы испытаны на ТРЁХ разных
# редакциях платформы, а опубликованный продукт ссылается на редакцию, которой
# нет ни в стволе, ни в линии — она с промежуточного коммита полосы, и после
# уборки временных ссылок такой пин перестаёт резолвиться вовсе.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ЧЕТЫРЕ, И ТРЕТИЙ НЕСУЩИЙ
#
#   0 — все СПРОШЕННЫЕ деревья называют одну версию;
#   1 — НАХОДКА: спрошенные деревья называют разное (либо, с --require-released,
#       названа псевдоверсия там, где обязана стоять опубликованная);
#   2 — скрипт позван неверно;
#   3 — ВЕРДИКТА НЕТ: спрошено меньше двух деревьев — сверять не с чем.
#
# Третий исход отделён от нулевого НАМЕРЕННО. Дерево, о котором спросить не
# удалось (ссылки нет в этом клоне, сеть выключена ручкой, инструмента нет),
# «согласным» не считается: молчание источника не читается как «да». Иначе в
# свежем клоне без второй ссылки скрипт печатал бы зелёное, сверив одно дерево
# с самим собой.
#
# ─────────────────────────────────────────────────────────────────────────────
# СЕТЕВАЯ ЧАСТЬ — ПО РУЧКЕ, И ПЕРЕПИСЬ НАЗЫВАЕТ ЕЁ СОСТОЯНИЕ ВСЕГДА
#
# Дерево опубликованной службы лежит в ЧУЖОМ репозитории, поэтому спрашивается
# только по явной ручке `KACHO_PIN_CROSSTREE_NETWORK=1`. Перепись печатает
# «сверено N» на каждом прогоне — чтобы «сверено 0» никогда не выглядело как
# «сверено» (образец — сверка номера задачи у проб консоли).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПЕРЕЧЕНЬ ДЕРЕВЬЕВ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ
#
# Ссылки платформы берутся из состава ссылок клона: ствол и всякая накопительная
# линия, у которой этот файл есть. Выписанный перечень разошёлся бы с деревом на
# первой же новой линии — молча, потому что скрипт продолжал бы быть зелёным.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

PLATFORM_MODULE="${KACHO_RELEASE_MODULE:-github.com/PRO-Robotech/kacho}"
SERVICE_GOMOD="${KACHO_SERVICE_GOMOD:-services/iam/go.mod}"
SERVICE_REPO="${KACHO_SERVICE_REPO:-PRO-Robotech/kaname}"
SERVICE_REPO_GOMOD="${KACHO_SERVICE_REPO_GOMOD:-go.mod}"
REMOTE="${KACHO_RELEASE_REMOTE:-origin}"
REQUIRE_RELEASED=0

usage() {
    cat >&2 <<USAGE
употребление: $0 [--require-released]

  Сверяет пин платформы ($PLATFORM_MODULE), объявленный в $SERVICE_GOMOD,
  между всеми деревьями, где он объявлен: рабочее дерево, ствол и накопительные
  линии клона, и (по ручке) дерево опубликованной службы $SERVICE_REPO.

  --require-released  считать находкой ПСЕВДОверсию: после шагов 6-7 порядка
                      выпуска все деревья обязаны называть опубликованную версию.

переменные:
  KACHO_PIN_CROSSTREE_NETWORK=1  спрашивать дерево $SERVICE_REPO (сеть)
  KACHO_RELEASE_MODULE           путь модуля платформы
  KACHO_SERVICE_GOMOD            объявление модуля службы в дереве платформы
  KACHO_SERVICE_REPO             репозиторий опубликованной службы
  KACHO_RELEASE_REMOTE           имя удалённого (умолчание: origin)

исходы: 0 согласие · 1 находка · 2 позван неверно · 3 вердикта нет
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --require-released) REQUIRE_RELEASED=1 ;;
        -h|--help) usage; exit 2 ;;
        *) echo "неизвестный аргумент: $1" >&2; usage; exit 2 ;;
    esac
    shift
done

# pinOf — версия платформы из текста объявления модуля.
#
# Разбор судит ДИРЕКТИВУ, а не строку: путь модуля встречается и в комментариях
# объявления, поэтому берётся первое поле строки, а не подстрока. Иначе скрипт
# считал бы пином собственное объяснение — класс, который корпус ловит у
# распознавателей.
pinOf() {
    awk -v mod="$PLATFORM_MODULE" '
        { sub(/\/\/.*/, "") }
        $1 == mod && $2 ~ /^v/ { print $2; found = 1; exit }
        END { if (!found) exit 1 }
    '
}

# isPseudo — псевдоверсия ли это (vX.Y.Z-<дата>-<ревизия>).
isPseudo() { [[ "$1" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-0)?\.?[0-9]*-?[0-9]{14}-[0-9a-f]{12}$ ]]; }

declare -a NAMES=() PINS=()
declare -a UNASKED=()

ask() { # ask <имя-источника> <версия|пусто> <причина-если-пусто>
    if [ -n "$2" ]; then
        NAMES+=("$1"); PINS+=("$2")
        printf '  спрошено  %-38s -> %s\n' "$1" "$2"
    else
        UNASKED+=("$1")
        printf '  НЕ спрошено %-36s -- %s\n' "$1" "$3"
    fi
}

echo "сверка пина платформы $PLATFORM_MODULE, объявленного в $SERVICE_GOMOD"

# ── источник 1: рабочее дерево ───────────────────────────────────────────────
if [ -f "$SERVICE_GOMOD" ]; then
    v="$(pinOf < "$SERVICE_GOMOD" || true)"
    ask "рабочее дерево" "$v" "объявление есть, а строки модуля платформы в нём нет"
else
    ask "рабочее дерево" "" "нет файла $SERVICE_GOMOD — служба в этом дереве не объявлена"
fi

# ── источник 2..N: ссылки платформы (ствол и накопительные линии) ────────────
# Перечень ВЫВОДИТСЯ из состава ссылок клона.
REFS=""
if command -v git >/dev/null 2>&1 && git rev-parse --git-dir >/dev/null 2>&1; then
    REFS="$(git for-each-ref --format='%(refname:short)' \
        "refs/remotes/$REMOTE/main" "refs/remotes/$REMOTE/release/*" 2>/dev/null || true)"
fi
if [ -z "$REFS" ]; then
    ask "ссылки платформы ($REMOTE)" "" "ни ствола, ни накопительных линий в этом клоне нет"
else
    while IFS= read -r ref; do
        [ -n "$ref" ] || continue
        if body="$(git show "$ref:$SERVICE_GOMOD" 2>/dev/null)" && [ -n "$body" ]; then
            v="$(printf '%s\n' "$body" | pinOf || true)"
            ask "$ref" "$v" "объявление есть, а строки модуля платформы в нём нет"
        else
            ask "$ref" "" "объявления $SERVICE_GOMOD на этой ссылке нет"
        fi
    done <<< "$REFS"
fi

# ── источник N+1: дерево опубликованной службы (сеть, по ручке) ──────────────
NET_NAME="$SERVICE_REPO:$SERVICE_REPO_GOMOD"
if [ "${KACHO_PIN_CROSSTREE_NETWORK:-0}" != "1" ]; then
    ask "$NET_NAME" "" "сетевая часть выключена (KACHO_PIN_CROSSTREE_NETWORK=1 включает)"
elif ! command -v gh >/dev/null 2>&1; then
    ask "$NET_NAME" "" "инструмента нет — gh не найден"
else
    if body="$(gh api "repos/$SERVICE_REPO/contents/$SERVICE_REPO_GOMOD" \
                  --jq .content 2>/dev/null | base64 -d 2>/dev/null)" && [ -n "$body" ]; then
        v="$(printf '%s\n' "$body" | pinOf || true)"
        ask "$NET_NAME" "$v" "объявление получено, а строки модуля платформы в нём нет"
    else
        ask "$NET_NAME" "" "спросить не удалось: репозиторий недостижим либо нет права"
    fi
fi

# ─────────────────────────────────────────────────────────────────────────────
# Вердикт
# ─────────────────────────────────────────────────────────────────────────────
UNIQUE="$(printf '%s\n' "${PINS[@]+"${PINS[@]}"}" | sed '/^$/d' | sort -u)"
UNIQUE_N="$(printf '%s' "$UNIQUE" | grep -c . || true)"

printf '\nперепись: сверено деревьев %d, НЕ спрошено %d, различных версий %d\n' \
    "${#PINS[@]}" "${#UNASKED[@]}" "$UNIQUE_N"
[ "${#UNASKED[@]}" -gt 0 ] && printf '  не спрошены: %s\n' "${UNASKED[*]}"

if [ "${#PINS[@]}" -lt 2 ]; then
    cat >&2 <<VOID
ВЕРДИКТА НЕТ: спрошено деревьев ${#PINS[@]} — сверять не с чем. Одно дерево,
сверенное с самим собой, согласием не является, и «не знаю» не выдаётся за «да».
VOID
    exit 3
fi

rc=0
if [ "$UNIQUE_N" -gt 1 ]; then
    {
        echo "НАХОДКА: деревья называют РАЗНЫЕ версии платформы — один предмет объявлен"
        echo "  в ${#PINS[@]} местах, и верно из них одно. Три сборки службы испытаны на"
        echo "  разных редакциях платформы, и расхождение не поймает ни один прогон:"
        echo "  каждое дерево по отдельности собирается."
        for i in "${!PINS[@]}"; do printf '    %-40s %s\n' "${NAMES[$i]}" "${PINS[$i]}"; done
        echo "  ЧТО ДЕЛАТЬ: свести пин к одной версии (порядок выпуска, шаги 6-7):"
        echo "    go get -C \"\$(dirname $SERVICE_GOMOD)\" $PLATFORM_MODULE@<версия>"
    } >&2
    rc=1
fi

if [ "$REQUIRE_RELEASED" = "1" ]; then
    for i in "${!PINS[@]}"; do
        if isPseudo "${PINS[$i]}"; then
            echo "НАХОДКА: ${NAMES[$i]} называет ПСЕВДОверсию ${PINS[$i]} — после шагов 6-7" >&2
            echo "  порядка выпуска пин обязан называть опубликованную версию: коммит" >&2
            echo "  псевдоверсии держат временные ссылки, и после их уборки он не резолвится." >&2
            rc=1
        fi
    done
fi

if [ "$rc" = "0" ]; then
    FORM="опубликованная версия"
    isPseudo "${PINS[0]}" && FORM="ПСЕВДОверсия (порядок выпуска, шаги 6-7, ещё не исполнен)"
    echo "СОГЛАСИЕ: все ${#PINS[@]} спрошенных деревьев называют ${PINS[0]} — $FORM"
fi

if [ "${#UNASKED[@]}" -gt 0 ] && [ "$rc" = "0" ]; then
    cat >&2 <<PARTIAL
ОГОВОРКА: вердикт относится к СПРОШЕННЫМ деревьям (${#PINS[@]}), а не ко всем.
Не спрошенное дерево согласным не считается — см. перепись выше.
PARTIAL
fi

exit "$rc"
