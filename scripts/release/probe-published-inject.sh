# Инъекция для `scripts/release/probe-published.sh` — предмет один: ПРОБА
# РАЗЛИЧАЕТ ТРИ ИСХОДА И МЕНЯЕТ ЦВЕТ ОТ ФАКТА ПУБЛИКАЦИИ, А НЕ ОТ ЧЕГО-ТО ЕЩЁ.
#
# ЗАЧЕМ. Сегодня проба красная, и красной она останется до нажатия владельца.
# Красное, которое не может позеленеть, неотличимо от красного, которое просто
# всегда красное: утверждение «зеленеет после публикации» без доказательства
# есть обещание. Публиковать ради доказательства нельзя — действие необратимо.
#
# КАК ЭТО ДОКАЗЫВАЕТСЯ БЕЗ ПУБЛИКАЦИИ. Проба ходит за модулем через GOPROXY и
# о его природе ничего не знает. Значит достаточно ФАЙЛОВОГО прокси: в нём
# заводится синтетический модуль, и меняется РОВНО ОДИН факт — лежит ли в
# прокси запрошенная версия. Тот же скрипт, тот же вход, разный исход.
#
# ЧЕТВЁРТАЯ ОСЬ ВАЖНЕЕ ТРЁХ ПЕРВЫХ. Недостижимый прокси обязан давать «НЕ
# ВЫПОЛНИЛОСЬ» (3), а не находку (1): иначе всякий обрыв сети читался бы как
# «версия не опубликована», и настоящая находка утонула бы среди ложных — а
# прибор, у которого все находки ложные, перестают читать.
#
# ИСХОДЫ: 0 — все утверждения сошлись; 1 — есть провалившиеся; 2 — предмета нет.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUBJECT="$HERE/probe-published.sh"
[ -r "$SUBJECT" ] || { echo "предмета нет: $SUBJECT" >&2; exit 2; }
command -v go      >/dev/null 2>&1 || { echo "инструмента нет: go" >&2; exit 2; }
command -v python3 >/dev/null 2>&1 || { echo "инструмента нет: python3" >&2; exit 2; }

tmp="$(mktemp -d)"
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

MOD="example.com/published"
ESC="example.com/published"   # экранирования не требует: строчные буквы
VER="v1.2.3"

passed=0; failed=0; fails=()
pass() { passed=$((passed + 1)); printf '  ✓ %s\n' "$1"; }
fail() { failed=$((failed + 1)); fails+=("$1"); printf '  ✗ %s\n     %s\n' "$1" "${2:-}"; }

# mkproxy <каталог> <лежит-ли-версия:0|1> <собирается-ли-пакет:0|1>
#
# Файловый прокси заводится ПОЛНОСТЬЮ (list/.info/.mod/.zip): урезанный отвечал
# бы отказом по своей неполноте, и красное приходило бы от фикстуры.
mkproxy() {
    local dir="$1" have="$2" buildable="$3"
    python3 - "$dir" "$MOD" "$ESC" "$VER" "$have" "$buildable" <<'PY'
import os, sys, zipfile
dir_, mod, esc, ver, have, buildable = sys.argv[1:7]
vdir = os.path.join(dir_, *esc.split("/"), "@v")
os.makedirs(vdir, exist_ok=True)
if have != "1":
    # Прокси достижим и путь модуля ему известен, а версии НЕТ. Пустой list —
    # ровно то, что сегодня отдаёт настоящий прокси на наш модуль.
    open(os.path.join(vdir, "list"), "w").close()
    sys.exit(0)
gomod = "module %s\n\ngo 1.21\n" % mod
body = ('package ids\n\nfunc NewID(prefix string) string { return prefix + "0" }\n'
        if buildable == "1" else
        'package ids\n\nfunc NewID(prefix string) string { return prefix + }\n')
open(os.path.join(vdir, "list"), "w").write(ver + "\n")
open(os.path.join(vdir, ver + ".mod"), "w").write(gomod)
open(os.path.join(vdir, ver + ".info"), "w").write(
    '{"Version":"%s","Time":"2000-01-01T00:00:00Z"}' % ver)
with zipfile.ZipFile(os.path.join(vdir, ver + ".zip"), "w") as z:
    p = "%s@%s/" % (mod, ver)
    z.writestr(p + "go.mod", gomod)
    z.writestr(p + "pkg/ids/ids.go", body)
PY
}

# run <GOPROXY> <версия> → RC, OUT
#
# ГРАНИЦА ФИКСТУРЫ, НАЗВАННАЯ ЧЕСТНО. Синтетического модуля нет и не может быть
# в публичной базе контрольных сумм, поэтому здесь она отключена (`GONOSUMDB` на
# домен фикстуры). Проба сама её НЕ отключает: настоящий потребитель нашего
# модуля суммы проверяет, и ослабить это значило бы сделать фикстуру
# снисходительнее продукта. Следствие названо прямо: полоса проверки сумм этой
# инъекцией НЕ покрыта.
run() {
    OUT="$(GOPROXY="$1" GONOSUMDB="example.com/*" GOSUMDB=off \
        KACHO_RELEASE_MODULE="$MOD" \
        bash "$SUBJECT" "$2" "$MOD/pkg/ids" 2>&1)"
    RC=$?
}

echo "инъекция пробы годности: цвет меняется от ФАКТА публикации"

# ── A. ВЕРСИЯ ОПУБЛИКОВАНА И СОБИРАЕТСЯ → зелёное ───────────────────────────
mkproxy "$tmp/have" 1 1
run "file://$tmp/have" "$VER"
if [ "$RC" = "0" ]; then
    pass "A  версия в прокси есть и собирается: код 0 — проба ЗЕЛЕНЕЕТ после публикации"
else fail "A  версия есть → код 0" "код $RC; вывод:\n$OUT"; fi

# ── B. ТОТ ЖЕ ПРОКСИ, ВЕРСИИ НЕТ → красное ──────────────────────────────────
# Один факт против A: содержимое `@v`. Всё остальное — путь модуля, импорт,
# инструмент, окружение — то же.
mkproxy "$tmp/empty" 0 1
run "file://$tmp/empty" "$VER"
if [ "$RC" = "1" ]; then
    pass "B  версии в прокси нет: код 1 — проба КРАСНАЯ до публикации"
else fail "B  версии нет → код 1" "код $RC; вывод:\n$OUT"; fi
if printf '%s' "$OUT" | grep -q 'опубликованных версий по данным прокси — 0'; then
    pass "B' перепись называет число опубликованных версий: «нет» отличимо от «не смотрели»"
else fail "B' перепись опубликованных версий" "в выводе её нет:\n$OUT"; fi

# ── C. ПРОКСИ НЕДОСТИЖИМ → «НЕ ВЫПОЛНИЛОСЬ» (3), а не находка ───────────────
run "https://proxy.invalid.example" "$VER"
if [ "$RC" = "3" ]; then
    pass "C  прокси недостижим: код 3 (НЕ выполнилось), а не 1"
else fail "C  недостижимый прокси → код 3" "код $RC; вывод:\n$OUT"; fi
if printf '%s' "$OUT" | grep -q 'НЕ ВЫПОЛНИЛОСЬ'; then
    pass "C' текст называет исход словами, а не только кодом"
else fail "C' текст называет «НЕ ВЫПОЛНИЛОСЬ»" "вывод:\n$OUT"; fi

# ── D. ВЕРСИЯ ЕСТЬ, НО НЕ СОБИРАЕТСЯ → красное, а не зелёное ────────────────
# Иначе проба измеряла бы наличие версии, а не её ГОДНОСТЬ: опубликованная и
# несобираемая версия — худший исход из возможных, и молчать о нём нельзя.
mkproxy "$tmp/broken" 1 0
run "file://$tmp/broken" "$VER"
if [ "$RC" = "1" ]; then
    pass "D  версия есть, но не собирается: код 1 — проба спрашивает годность, а не наличие"
else fail "D  несобираемая версия → код 1" "код $RC; вывод:\n$OUT"; fi

# ── E. ЗАПРОШЕНА ДРУГАЯ ВЕРСИЯ, КОТОРОЙ В ПРОКСИ НЕТ → красное ──────────────
# Законный близнец к A по всему, кроме номера: доказывает, что зелёное в A
# пришло от ЗАПРОШЕННОЙ версии, а не от того, что в прокси вообще что-то лежит.
run "file://$tmp/have" "v9.9.9"
if [ "$RC" = "1" ]; then
    pass "E  запрошена отсутствующая версия при непустом прокси: код 1"
else fail "E  отсутствующая версия → код 1" "код $RC; вывод:\n$OUT"; fi

# ── F. ПОЗВАНА БЕЗ АРГУМЕНТА → 2, а не 1 и не 3 ─────────────────────────────
# Неверный вызов не есть ни находка, ни несостоявшийся прогон.
OUT="$(bash "$SUBJECT" 2>&1)"; RC=$?
if [ "$RC" = "2" ]; then
    pass "F  вызов без версии: код 2 — не находка и не «не выполнилось»"
else fail "F  вызов без версии → код 2" "код $RC; вывод:\n$OUT"; fi

printf '\nперепись: утверждений исполнено %d, провалено %d\n' \
    "$((passed + failed))" "$failed"
if [ "$((passed + failed))" = "0" ]; then
    echo "обход пуст: не исполнено ни одного утверждения — вердикт беспредметен" >&2
    exit 2
fi
if [ "$failed" -gt 0 ]; then
    printf '  провалены: %s\n' "${fails[*]}" >&2
    exit 1
fi
exit 0
