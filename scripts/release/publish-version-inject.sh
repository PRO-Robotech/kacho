# Инъекция для `scripts/release/publish-version.sh` — предмет один: МЕХАНИЗМ
# ПУБЛИКАЦИИ СПОСОБЕН ОТКАЗАТЬ, СПОСОБЕН СМОЛЧАТЬ И НИЧЕГО НЕ СОЗДАЁТ САМ.
#
# ЗАЧЕМ. Механизм, стоящий перед НЕОБРАТИМЫМ действием, ценен ровно своей
# способностью отказать. На исправном входе он выглядит одинаково и когда
# работает, и когда его предпосылки выродились в тождественно-истинные:
# отличить нельзя ничем, кроме внесённого дефекта.
#
# ПОЧЕМУ СИНТЕТИЧЕСКИЕ РЕПОЗИТОРИИ. Предмет проверки — исход публикации, а
# публиковать в настоящий origin нельзя (действие необратимо). Утверждения
# гоняются по НАСТОЯЩЕМУ скрипту на паре «пустой origin + рабочая копия»,
# заводимой заново на каждое утверждение: тогда каждый дефект меняет РОВНО ОДИН
# факт против законного близнеца, и красное нельзя списать на соседа.
#
# ТРЕТЬЕ УТВЕРЖДЕНИЕ ВАЖНЕЕ ДВУХ ПЕРВЫХ. Механизм обязан НИЧЕГО НЕ СОЗДАВАТЬ:
# ни локальной ссылки, ни удалённой. Проверяется это исходом — снимками ссылок
# до и после, — а не чтением текста скрипта: скрипт печатает команду отправки, и
# поиск по подстроке не отличил бы печать от исполнения.
#
# ИСХОДЫ: 0 — все утверждения сошлись; 1 — есть провалившиеся; 2 — предмета нет
# либо нет инструмента (вердикта не получено ни по одному утверждению).
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REAL_SUBJECT="$HERE/publish-version.sh"
[ -r "$REAL_SUBJECT" ] || { echo "предмета нет: $REAL_SUBJECT" >&2; exit 2; }
SUBJECT="$REAL_SUBJECT"
command -v git >/dev/null 2>&1 || { echo "инструмента нет: git" >&2; exit 2; }
command -v go  >/dev/null 2>&1 || { echo "инструмента нет: go" >&2; exit 2; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

passed=0; failed=0; fails=()

# assert <имя> <условие-описание> — учёт исходов утверждений.
pass() { passed=$((passed + 1)); printf '  ✓ %s\n' "$1"; }
fail() { failed=$((failed + 1)); fails+=("$1"); printf '  ✗ %s\n     %s\n' "$1" "${2:-}"; }

# ─────────────────────────────────────────────────────────────────────────────
# Фикстура: пустой origin + рабочая копия, годная по ВСЕМ предпосылкам
# ─────────────────────────────────────────────────────────────────────────────
# Законный близнец заводится ОДНОЙ функцией, а дефект вносится ПОСЛЕ неё одним
# действием. Так видно, что именно отличается: дефект, вписанный прямо в
# фикстуру, менял бы неизвестно сколько фактов сразу.
mk() { # mk <имя-случая> [объявленный-путь-модуля] → печатает каталог рабочей копии
    local name="$1" modpath="${2:-example.com/synthetic}"
    # Фикстуры разводятся по ПРОГОНАМ: набор гоняется дважды, и общий каталог
    # донёс бы состояние первого прогона до второго (созданные теги, отправленные
    # ссылки). Тогда дефектная копия роняла бы утверждения не своим дефектом, а
    # чужим остатком — и доказательство измеряло бы не то.
    local base="$tmp/${RUN_LABEL:?метка прогона не задана}/$name"
    local origin="$base/origin.git" work="$base/work"
    mkdir -p "$base"
    git init --quiet --bare -b main "$origin"
    git init --quiet -b main "$work"
    mkdir -p "$work/internal/release"
    printf 'module %s\n\ngo 1.21\n' "$modpath" > "$work/go.mod"
    # Герметичный гейт упаковки синтетического репозитория: предпосылка П8 зовёт
    # его по ИМЕНИ, поэтому имя обязано совпадать с настоящим.
    cat > "$work/internal/release/pack_test.go" <<'GATE'
package release

import "testing"

func TestExternalConsumerCanBuildTheModule(t *testing.T) { t.Log("синтетический гейт упаковки") }
GATE
    git -C "$work" add -A
    git -C "$work" \
        -c user.name=probe -c user.email=probe@invalid \
        commit --quiet -m synthetic
    git -C "$work" remote add origin "$origin"
    git -C "$work" push --quiet origin main
    printf '%s\n' "$work"
}

# run <каталог> <аргументы...> → код возврата в RC, вывод в OUT
run() {
    local dir="$1"; shift
    OUT="$(cd "$dir" && KACHO_RELEASE_REMOTE=origin KACHO_RELEASE_TRUNK=main \
        bash "$SUBJECT" "$@" 2>&1)"
    RC=$?
}

# snapshot <каталог> → все ссылки: удалённые и локальные теги
snapshot() {
    local dir="$1"
    { git -C "$dir" ls-remote origin 2>/dev/null; echo "--"; git -C "$dir" tag -l; } | sort
}

assert_all() {
echo "инъекция производителя версии: утверждения по осям предпосылок"

# ── A. ЗАКОННЫЙ БЛИЗНЕЦ: всё сходится, механизм молчит и печатает команду ────
w="$(mk twin)"
before="$(snapshot "$w")"
run "$w" v0.1.0
after="$(snapshot "$w")"
sha="$(git -C "$w" rev-parse HEAD)"
if [ "$RC" = "0" ]; then pass "A1 законный близнец: код 0"
else fail "A1 законный близнец: код 0" "получен $RC; вывод:\n$OUT"; fi
if printf '%s' "$OUT" | grep -qF "git push origin $sha:refs/tags/v0.1.0"; then
    pass "A2 напечатана ровно та команда, что создаёт ссылку сразу на origin"
else
    fail "A2 напечатана команда владельца" "в выводе нет 'git push origin $sha:refs/tags/v0.1.0':\n$OUT"
fi
if [ "$before" = "$after" ]; then
    pass "A3 механизм НИЧЕГО не создал: ссылки до и после совпадают"
else
    fail "A3 механизм ничего не создал" "ссылки изменились:\n$(diff <(printf '%s' "$before") <(printf '%s' "$after") || true)"
fi
# Отдельным утверждением — что тега нет НИ ГДЕ. Совпадение снимков доказывает
# неизменность, но не отсутствие: обе стороны могли содержать тег изначально.
if ! git -C "$w" tag -l | grep -q . && ! git -C "$w" ls-remote --tags origin | grep -q .; then
    pass "A4 тегов нет ни локально, ни на origin"
else
    fail "A4 тегов нет ни локально, ни на origin" "локальные: $(git -C "$w" tag -l | tr '\n' ' ')"
fi

# ── B. П1: форма версии ──────────────────────────────────────────────────────
w="$(mk form)"
run "$w" 0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П1'; then
    pass "B  П1 форма версии: код 1 и назван П1"
else fail "B  П1 форма версии" "код $RC; вывод:\n$OUT"; fi

# ── C. П2: мажор ≥2 без суффикса пути ────────────────────────────────────────
# Один факт против близнеца: путь модуля тот же, версия — мажор 2.
w="$(mk major)"
run "$w" v2.0.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П2'; then
    pass "C  П2 мажор без суффикса /v2: код 1 и назван П2"
else fail "C  П2 мажор без суффикса" "код $RC; вывод:\n$OUT"; fi

# ── C'. П2 наоборот: путь с суффиксом, версия мажора 0 ───────────────────────
w="$(mk majorback example.com/synthetic/v2)"
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П2'; then
    pass "C' П2 путь /v2 при мажоре 0: код 1 и назван П2"
else fail "C' П2 путь /v2 при мажоре 0" "код $RC; вывод:\n$OUT"; fi

# ── D. П3: версия уже опубликована ───────────────────────────────────────────
w="$(mk taken)"
git -C "$w" push --quiet origin "$(git -C "$w" rev-parse HEAD):refs/tags/v0.1.0"
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П3'; then
    pass "D  П3 версия уже на origin: код 1 и назван П3"
else fail "D  П3 версия уже на origin" "код $RC; вывод:\n$OUT"; fi

# ── E. П4: версия не старше уже опубликованной ───────────────────────────────
w="$(mk older)"
git -C "$w" push --quiet origin "$(git -C "$w" rev-parse HEAD):refs/tags/v0.9.0"
run "$w" v0.2.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П4'; then
    pass "E  П4 версия не старше опубликованной: код 1 и назван П4"
else fail "E  П4 версия не старше опубликованной" "код $RC; вывод:\n$OUT"; fi

# ── E'. ПОРЯДОК ВЕРСИЙ: выпуск СТАРШЕ своего предвыпуска ────────────────────
# Законный близнец к E. `sort -V` считает `v1.0.0-rc1` старше `v1.0.0` — дефис
# для неё обычный символ, — и на этом П4 отвергала бы ровно тот переход, ради
# которого предвыпуски и делают. Утверждение держит СВОЙ компаратор semver.
w="$(mk prerelease)"
git -C "$w" push --quiet origin "$(git -C "$w" rev-parse HEAD):refs/tags/v1.0.0-rc1"
run "$w" v1.0.0
if [ "$RC" = "0" ]; then
    pass "E' выпуск вслед за своим предвыпуском: код 0 — предвыпуск МЛАДШЕ выпуска"
else fail "E' выпуск вслед за предвыпуском → код 0" "код $RC; вывод:\n$OUT"; fi

# ── E''. Обратная сторона той же оси: предвыпуск ПОСЛЕ выпуска — находка ─────
# Без неё E' зеленело бы и на компараторе, который просто всё разрешает.
w="$(mk prerelease-back)"
git -C "$w" push --quiet origin "$(git -C "$w" rev-parse HEAD):refs/tags/v1.0.0"
run "$w" v1.0.0-rc2
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П4'; then
    pass "E'' предвыпуск после выпуска: код 1 и назван П4"
else fail "E'' предвыпуск после выпуска" "код $RC; вывод:\n$OUT"; fi

# ── F. П5: HEAD не равен вершине ствола ──────────────────────────────────────
w="$(mk ahead)"
echo "правка после публикации ствола" > "$w/NOTE.md"
git -C "$w" add NOTE.md
git -C "$w" -c user.name=probe -c user.email=probe@invalid commit --quiet -m ahead
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П5'; then
    pass "F  П5 HEAD впереди вершины ствола: код 1 и назван П5"
else fail "F  П5 HEAD впереди вершины ствола" "код $RC; вывод:\n$OUT"; fi

# ── G. П6: посторонний локальный v* вне ствола ───────────────────────────────
# Тег ставится на коммит, ствола не достигший: ровно та форма, что в дереве
# наблюдалась восемью экземплярами (#1762).
w="$(mk stray)"
git -C "$w" checkout --quiet -b sidetrack
echo "вне ствола" > "$w/SIDE.md"
git -C "$w" add SIDE.md
git -C "$w" -c user.name=probe -c user.email=probe@invalid commit --quiet -m side
git -C "$w" tag v9.9.9
git -C "$w" checkout --quiet main
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П6'; then
    pass "G  П6 локальный v* вне ствола: код 1 и назван П6"
else fail "G  П6 локальный v* вне ствола" "код $RC; вывод:\n$OUT"; fi

# ── G'. Законный близнец той же формы: локальный v*, ЯВЛЯЮЩИЙСЯ предком ─────
# Без него П6 краснела бы на любом локальном теге, то есть ловила бы форму, а
# не существо.
w="$(mk straytwin)"
git -C "$w" tag v0.0.1
run "$w" v0.1.0
if [ "$RC" = "0" ]; then
    pass "G' законный близнец: локальный v* НА стволе — механизм молчит"
else fail "G' законный близнец: локальный v* на стволе" "код $RC; вывод:\n$OUT"; fi

# ── H. П7: replace в go.mod ──────────────────────────────────────────────────
w="$(mk replace)"
printf '\nreplace example.com/other => ./other\n' >> "$w/go.mod"
git -C "$w" add go.mod
git -C "$w" -c user.name=probe -c user.email=probe@invalid commit --quiet -m replace
git -C "$w" push --quiet origin main
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П7'; then
    pass "H  П7 replace в go.mod: код 1 и назван П7"
else fail "H  П7 replace в go.mod" "код $RC; вывод:\n$OUT"; fi

# ── I. П8: гейт упаковки НЕ ИСПОЛНИЛСЯ, хотя код возврата нулевой ───────────
# `go test -run` на несовпавшем образце выходит УСПЕХОМ и печатает «no tests to
# run». Предпосылка обязана требовать наблюдённого прохождения ПО ИМЕНИ, иначе
# опечатка в отборе читается как зелёное — класс, стоивший этому дереву
# отдельного запрета на кириллицу в именах.
w="$(mk unrun)"
sed -i 's/TestExternalConsumerCanBuildTheModule/TestSomethingElseEntirely/' \
    "$w/internal/release/pack_test.go"
git -C "$w" add -A
git -C "$w" -c user.name=probe -c user.email=probe@invalid commit --quiet -m renamed
git -C "$w" push --quiet origin main
run "$w" v0.1.0
if [ "$RC" = "1" ] && printf '%s' "$OUT" | grep -q 'нарушены:.*П8'; then
    pass "I  П8 гейт упаковки не исполнился при коде 0: код 1 и назван П8"
else fail "I  П8 гейт упаковки не исполнился" "код $RC; вывод:\n$OUT"; fi

# ── J. НЕ ВЫПОЛНИЛОСЬ ≠ НАХОДКА ──────────────────────────────────────────────
# Недоступный origin не делает предпосылки нарушенными: молчание источника не
# читается ни как «да», ни как «нет». Код обязан быть 3, а не 1.
w="$(mk void)"
OUT="$(cd "$w" && KACHO_RELEASE_REMOTE=nosuchremote KACHO_RELEASE_TRUNK=main \
    bash "$SUBJECT" v0.1.0 --skip-pack 2>&1)"; RC=$?
if [ "$RC" = "3" ] && printf '%s' "$OUT" | grep -q 'не спрошены:.*П3'; then
    pass "J  недоступный origin: код 3 (НЕ выполнилось), предпосылки в «не спрошено»"
else fail "J  недоступный origin даёт код 3" "код $RC; вывод:\n$OUT"; fi

# ── K. АНТИМАСКА: находка объявляется РАНЬШЕ «не спрошено» ───────────────────
# Иначе непрошенная предпосылка маскировала бы настоящую находку: прогон с
# дефектом и с пропуском выходил бы кодом 3, и отправка не остановилась бы по
# причине «просто не всё спросили».
w="$(mk mask)"
run "$w" 0.1.0 --skip-pack
if [ "$RC" = "1" ]; then
    pass "K  находка сильнее «не спрошено»: код 1, а не 3"
else fail "K  находка сильнее «не спрошено»" "код $RC; вывод:\n$OUT"; fi

}

# ─────────────────────────────────────────────────────────────────────────────
# ПРОГОН 1: против настоящего предмета. Ждём ноль провалов.
# ─────────────────────────────────────────────────────────────────────────────
RUN_LABEL=real
assert_all
real_passed=$passed; real_failed=$failed; real_fails=("${fails[@]:-}")

# ─────────────────────────────────────────────────────────────────────────────
# ПРОГОН 2: против ДЕФЕКТНОЙ копии — проба доказывает СВОЮ способность упасть
# ─────────────────────────────────────────────────────────────────────────────
# Дефект узкий и один: вердикт предпосылки П6 выродился в тождественно-истинный
# («посторонних тегов нет» печатается всегда). Ровно так предпосылка и умирает
# на практике — не исчезая, а переставая различать.
#
# Инъекция обязана ронять ТОЛЬКО проверяемое: провалиться обязано утверждение G
# и НИ ОДНО другое. Провал соседей означал бы, что дефект задел чужой предмет и
# красное пришло не оттуда, откуда объявлено.
DEFECT="$tmp/defective-publish-version.sh"
sed 's/^\([[:space:]]*\)finding 6 "локальных/\1ok 6 "локальных/' "$REAL_SUBJECT" > "$DEFECT"
if cmp -s "$DEFECT" "$REAL_SUBJECT"; then
    echo "дефект не внесён: образец П6 в предмете не найден — доказательство беспредметно" >&2
    exit 2
fi

echo
echo "прогон против дефектной копии (вердикт П6 выродился в тождественно-истинный)"
passed=0; failed=0; fails=()
RUN_LABEL=defect
SUBJECT="$DEFECT"
assert_all >/dev/null 2>&1
def_failed=$failed; def_fails=("${fails[@]:-}")
printf '  провалено на дефектной копии: %d — %s\n' "$def_failed" "${def_fails[*]:-<ничего>}"

# ─────────────────────────────────────────────────────────────────────────────
printf '\nперепись: утверждений исполнено %d, провалено %d; на дефектной копии провалено %d\n' \
    "$((real_passed + real_failed))" "$real_failed" "$def_failed"
if [ "$((real_passed + real_failed))" = "0" ]; then
    echo "обход пуст: не исполнено ни одного утверждения — вердикт беспредметен" >&2
    exit 2
fi
rc=0
if [ "$real_failed" -gt 0 ]; then
    printf '  провалены на настоящем предмете: %s\n' "${real_fails[*]}" >&2
    rc=1
fi
# Дефектная копия обязана ронять РОВНО утверждение G и никакое другое.
if [ "$def_failed" != "1" ] || [[ "${def_fails[0]:-}" != G\ * ]]; then
    printf '  ДОКАЗАТЕЛЬСТВО НЕГОДНО: на дефектной копии ожидался ровно один провал (G), получено %d: %s\n' \
        "$def_failed" "${def_fails[*]:-<ничего>}" >&2
    rc=1
fi
exit $rc
