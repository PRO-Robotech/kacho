# publish-service-artifact.sh — ПРОИЗВОДИТЕЛЬ ПОСТАВКИ вынесенной службы.
#
# ЗАЧЕМ ОН ЗАВЕДЁН. Дерево службы живёт в монорепо, а посторонний достаёт её из
# ОТДЕЛЬНОГО репозитория по пути модуля. Эти два дерева обязаны совпадать, и до
# сих пор их сводил человек: у поставки не было производителя вовсе — ни
# скрипта, ни цели сборки, ни задания конвейера. Проверяется одной командой:
#
#     git grep -nE 'git (subtree|filter-repo)|push .*PRO-Robotech/(kaname|corelib)'
#
# Цена отсутствия измерена, а не предположена. Единственная выкладка была ручным
# снимком; репозиторий после неё переименовали, объявление модуля осталось
# прежним, и `go get` у постороннего отвечал отказом «модуль объявляет свой путь
# как …, а затребован как …». За сутки дерево службы ушло вперёд на 162 файла, и
# заметить расхождение было нечем: у ручного снимка нет ни предиката, ни
# повторяемости (#2120).
#
# ЧТО ЭТОТ СКРИПТ ДЕЛАЕТ. Берёт дерево `services/<служба>` названной ревизии
# монорепо, прогоняет четыре гейта и КЛАДЁТ ЕГО ОДНИМ КОММИТОМ поверх ствола
# репозитория артефакта. Больше ничего: ни ссылок версий, ни заметок о выпуске,
# ни правки чужих веток.
#
# ПОЧЕМУ КОММИТ ПОВЕРХ, А НЕ ЗАМЕЩЕНИЕ СТВОЛА. Замещение требует принудительной
# отправки, а она необратима вдвойне: снимает чужую работу, о которой
# отправляющий может не знать. В этом репозитории такая работа ЕСТЬ — вторая
# ветка, чьего содержимого нет ни в одной ссылке монорепо. Коммит поверх её не
# касается by construction, и доказывать это отдельно не приходится.
#
# ЧЕГО ОН НЕ ЗАКРЫВАЕТ, И ЭТО НАДО ЗНАТЬ ДО ВЫЗОВА. Записи модуль-прокси
# НЕИЗМЕНЯЕМЫ: псевдоверсия, выложенная прежде, остаётся доступной навсегда и
# продолжает объявлять то, что объявляла. Скрипт двигает `@latest` вперёд и
# ничего не отзывает; затребовавший прежнюю псевдоверсию поимённо получит
# прежний ответ.
#
# ИСХОДОВ ЧЕТЫРЕ, И ЧИТАЕТСЯ КОД ВОЗВРАТА, А НЕ ВИД ВЫВОДА:
#   0 — выложено; либо холостой прогон сошёлся и НИЧЕГО не отправлено;
#   1 — НАХОДКА: предпосылка нарушена. Ничего не отправлено;
#   2 — позван неверно (нет службы, подтверждение не совпало). Ничего не отправлено;
#   3 — НЕ ВЫПОЛНИЛОСЬ: часть предпосылок не спрошена. Ничего не отправлено.
#
# УМОЛЧАНИЕ — ХОЛОСТОЙ ПРОГОН, как у соседа: умолчание, при котором забытый ключ
# ПУБЛИКУЕТ, стоило бы ровно одной опечатки.
#
# ПЕРЕПИСЬ ПЕЧАТАЕТСЯ ВСЕГДА — «ноль находок» обязано быть отличимо от «ноль
# прочитанного», поэтому в итоге стоят числа осмотренного, а не одно слово.
set -uo pipefail

# Унаследованное окружение git сильнее рабочего каталога: без снятия действия
# уезжают в индекс той копии, из которой скрипт запущен.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

ARTIFACT_HOST="${KACHO_ARTIFACT_HOST:-github.com}"

usage() {
    cat >&2 <<USAGE
употребление: $0 <служба> <владелец/репозиторий> --confirm <владелец/репозиторий> [ключи]

  <служба>              каталог под services/, напр. iam
  <владелец/репозиторий> репозиторий артефакта, напр. PRO-Robotech/kaname
  --confirm <строка>    обязана совпасть с репозиторием ДОСЛОВНО
  --publish             выполнить необратимый шаг; без него — холостой прогон
  --via-pull-request    доставить ЧЕРЕЗ ЗАПРОС НА СЛИЯНИЕ: ветка → запрос →
                        вердикт обязательных проверок → вливание. Обязателен
                        там, где ствол артефакта защищён
  --rev <ревизия>       ревизия монорепо-источника (умолчание: HEAD)
  --branch <имя>        ствол артефакта (умолчание: main)
  --checks-budget <сек> предел ожидания вердикта проверок (умолчание: 3000)

переменные:
  KACHO_ARTIFACT_HOST   узел (умолчание: github.com)
  KACHO_ARTIFACT_URL    полный адрес отправки; перебивает узел и репозиторий
  KACHO_FORGE_CMD       команда форжа (умолчание: gh)
USAGE
}

SVC=""; REPO=""; CONFIRM=""; PUBLISH=0; REV="HEAD"; BRANCH="main"
VIA_PR=0; CHECKS_BUDGET="${KACHO_CHECKS_BUDGET:-3000}"
while [ $# -gt 0 ]; do
    case "$1" in
        --confirm) [ $# -ge 2 ] || { echo "--confirm без значения" >&2; exit 2; }
                   CONFIRM="$2"; shift 2 ;;
        --rev)     [ $# -ge 2 ] || { echo "--rev без значения" >&2; exit 2; }
                   REV="$2"; shift 2 ;;
        --branch)  [ $# -ge 2 ] || { echo "--branch без значения" >&2; exit 2; }
                   BRANCH="$2"; shift 2 ;;
        --publish) PUBLISH=1; shift ;;
        --via-pull-request) VIA_PR=1; shift ;;
        --checks-budget) [ $# -ge 2 ] || { echo "--checks-budget без значения" >&2; exit 2; }
                   CHECKS_BUDGET="$2"; shift 2 ;;
        -h|--help) usage; exit 2 ;;
        -*)        echo "неизвестный ключ: $1" >&2; usage; exit 2 ;;
        *)         if   [ -z "$SVC"  ]; then SVC="$1"
                   elif [ -z "$REPO" ]; then REPO="$1"
                   else echo "лишний довод: $1" >&2; exit 2; fi; shift ;;
    esac
done
[ -n "$SVC" ] && [ -n "$REPO" ] || { usage; exit 2; }

# ── Подтверждение намерения ─────────────────────────────────────────────────
# Дословное совпадение, а не «непусто»: подтверждение, которое можно дать не
# читая, подтверждением не является. Спрашивается ДО всего прочего — отказ здесь
# не стоит ни одного вызова к сети.
if [ "$CONFIRM" != "$REPO" ]; then
    cat >&2 <<CONF
ОТКАЗ: подтверждение не совпало с репозиторием.
  репозиторий:   '$REPO'
  подтверждение: '$CONFIRM'
Выкладка необратима, поэтому намерение подтверждается дословным повтором
адреса. Ничего не отправлено.
CONF
    exit 2
fi

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "не репозиторий git: $PWD" >&2; exit 2; }
cd "$ROOT" || exit 2

SRC_SHA="$(git rev-parse --verify --quiet "${REV}^{commit}")" || {
    echo "ревизия не разрешается: $REV" >&2; exit 2; }
SVC_DIR="services/$SVC"
git rev-parse --verify --quiet "${SRC_SHA}:${SVC_DIR}" >/dev/null || {
    echo "в ревизии ${SRC_SHA:0:12} нет каталога $SVC_DIR" >&2; exit 2; }

# ТРАНСПОРТ НАСЛЕДУЕТСЯ У ИСТОЧНИКА, а не назначается здесь. Производитель
# обязан работать там же, где работает монорепо: если тот ходит по ssh, ключ уже
# заведён, а вписанный https потребовал бы ОТДЕЛЬНЫХ учётных данных — и отказал
# бы на первом же вызове, что здесь и наблюдалось.
ORIGIN_URL="$(git remote get-url origin 2>/dev/null || true)"
case "$ORIGIN_URL" in
    git@*|ssh://*) DEFAULT_URL="git@${ARTIFACT_HOST}:${REPO}.git" ;;
    *)             DEFAULT_URL="https://${ARTIFACT_HOST}/${REPO}.git" ;;
esac
URL="${KACHO_ARTIFACT_URL:-$DEFAULT_URL}"
MODULE_WANT="${ARTIFACT_HOST}/${REPO}"

if [ "$PUBLISH" = "1" ]; then
    printf 'производитель поставки: ВЫКЛАДКА %s → %s (ревизия %.12s)\n' "$SVC_DIR" "$REPO" "$SRC_SHA"
    if [ "$VIA_PR" = "1" ]; then
        printf 'полоса доставки: ЧЕРЕЗ ЗАПРОС НА СЛИЯНИЕ (ствол не трогается напрямую)\n'
    else
        printf 'полоса доставки: ПРЯМО В СТВОЛ %s\n' "$BRANCH"
    fi
else
    printf 'производитель поставки: ХОЛОСТОЙ прогон %s → %s (ревизия %.12s) — ничего отправлено не будет\n' \
        "$SVC_DIR" "$REPO" "$SRC_SHA"
    if [ "$VIA_PR" = "1" ]; then
        printf 'полоса доставки: ЧЕРЕЗ ЗАПРОС НА СЛИЯНИЕ (ствол не трогается напрямую)\n'
    else
        printf 'полоса доставки: ПРЯМО В СТВОЛ %s\n' "$BRANCH"
    fi
fi
printf 'адрес отправки: %s\n' "$URL"

# ── Условие транспорта, а НЕ гейт ───────────────────────────────────────────
# Это не находка о дереве: дерево верно, и вердикт о нём выносится ниже. Здесь
# называется УСЛОВИЕ, при котором необратимый шаг отвергнет удалённый, — и
# называется ДО гейтов, потому что иначе оно стоит полного прогона.
#
# Замер, а не догадка. Отправка по https идёт от приложения OAuth, и GitHub
# отвергает у него создание либо правку объявления конвейера без полномочия
# `workflow`; в перечне полномочий токена этого дерева его НЕТ. Отправка по ssh
# идёт от личности владельца ключа, и ограничение на неё не распространяется
# by construction. Дерево службы объявление конвейера НЕСЁТ, поэтому условие
# наступает не когда-нибудь, а на каждой выкладке, двигающей этот файл.
WF_N="$(git ls-tree -r --name-only "$SRC_SHA" -- "$SVC_DIR/.github/workflows" 2>/dev/null | grep -c . || true)"
case "$URL" in
    https://*)
        if [ "${WF_N:-0}" -gt 0 ]; then
            cat <<TRANSPORT
внимание: дерево несёт объявлений конвейера $WF_N, а отправка идёт по https —
  то есть от приложения OAuth. Удалённый отвергнет создание либо правку
  .github/workflows/* без полномочия workflow; проверить полномочия:
      gh auth status
  Ограничение снимается СМЕНОЙ ТРАНСПОРТА, а не расширением полномочий:
      GIT_SSH_COMMAND='ssh -o IdentityAgent=none' KACHO_ARTIFACT_URL= $0 …
TRANSPORT
        fi ;;
esac
printf '\n'

gates=0; red=(); void=()

# ── Гейт 1: объявленный путь модуля совпадает с адресом артефакта ───────────
# Тот самый предмет, ради которого производитель заведён. Расхождение здесь
# делает модуль недостижимым для постороннего, оставаясь невидимым в дереве:
# монорепо собирается, потому что путь у него согласован сам с собой.
gates=$((gates + 1))
printf '── путь модуля совпадает с адресом артефакта\n'
GOMOD="$(git show "${SRC_SHA}:${SVC_DIR}/go.mod" 2>/dev/null)"
if [ -z "$GOMOD" ]; then
    void+=("путь модуля"); printf '   → НЕ ВЫПОЛНИЛОСЬ: go.mod не прочитан\n\n'
else
    MODULE_IS="$(printf '%s\n' "$GOMOD" | awk '$1=="module"{print $2; exit}')"
    printf '   объявлено: %s\n   адрес:     %s\n' "$MODULE_IS" "$MODULE_WANT"
    if [ "$MODULE_IS" = "$MODULE_WANT" ]; then
        printf '   → сошлось\n\n'
    else
        red+=("путь модуля"); printf '   → НАХОДКА: посторонний получит отказ разбора go.mod\n\n'
    fi
fi

# ── Гейт 2: самодостаточность модуля — спрашивается У ЕГО ДЕРЖАТЕЛЯ ─────────
# Свойство «служба несёт свой модуль, и каждый импорт платформы покрыт require»
# в дереве УЖЕ держится — пробой `TestServiceCarriesItsOwnSelfSufficientModule`
# в services/<служба>/internal/supplyhygiene. Производитель её ЗОВЁТ, а не
# переписывает.
#
# Своя копия предиката была здесь написана и снята, и снята по замеру, а не по
# вкусу: текстовый поиск импортов немедленно дал ложную находку — он принял за
# импорт строковый литерал внутри инъекционной пробы СОСЕДНЕГО гейта, то есть
# счёл объяснение предметом (testing.md §«Гейт на класс», п. 4). Держатель
# разбирает Go и такой близнец у него молчит отдельной пробой.
#
# Гейт судит ДЕРЕВО РЕВИЗИИ, а не рабочую копию: копия несёт незакоммиченное, и
# вердикт относился бы к черновику. Поэтому прогон идёт в своём каталоге.
gates=$((gates + 1))
printf '── самодостаточность модуля (держатель: supplyhygiene)\n'
if ! command -v go >/dev/null 2>&1; then
    void+=("самодостаточность модуля"); printf '   → НЕ ВЫПОЛНИЛОСЬ: go не найден\n\n'
elif ! git rev-parse --verify --quiet "${SRC_SHA}:${SVC_DIR}/internal/supplyhygiene" >/dev/null; then
    void+=("самодостаточность модуля")
    printf '   → НЕ ВЫПОЛНИЛОСЬ: держателя нет в дереве ревизии\n\n'
else
    # Держатель читает СОСТАВ У ИНДЕКСА, а не обходом диска, — и правильно
    # делает: обход нашёл бы каталоги, которых в репозитории нет. Значит
    # распакованному дереву индекс нужно ЗАВЕСТИ, иначе держатель ответит
    # «вердикт беспредметен», а `go test` отдаст ту же единицу, что на находке,
    # и «не выполнилось» уехало бы в красное.
    HOLD="$(mktemp -d)"
    git archive --format=tar "${SRC_SHA}:${SVC_DIR}" | tar -x -C "$HOLD"
    ( cd "$HOLD" \
      && git init --quiet -b probe \
      && git -c user.name=probe -c user.email=probe@invalid add -A ) >/dev/null 2>&1
    HOLD_OUT="$(cd "$HOLD" && go test ./internal/supplyhygiene/ \
        -run 'TestServiceCarriesItsOwnSelfSufficientModule' -count=1 2>&1)"; HOLD_RC=$?
    # «Беспредметен» — третья категория, а не находка: держатель говорит это
    # своими словами, и слово читается прежде кода возврата.
    # Сравнение БЕЗ внешнего процесса: `grep -q` выходит до конца входа, писатель
    # слева получает SIGPIPE, и под `pipefail` это поднимается до статуса
    # конвейера — найденное объявлялось бы ненайденным (#658).
    if [[ "$HOLD_OUT" == *беспредметен* ]]; then HOLD_RC=3; fi
    printf '%s\n' "$HOLD_OUT" | tail -5 | sed 's/^/   /'
    rm -rf "$HOLD"
    case "$HOLD_RC" in
        0) printf '   → сошлось\n\n' ;;
        1) red+=("самодостаточность модуля"); printf '   → НАХОДКА\n\n' ;;
        *) void+=("самодостаточность модуля")
           printf '   → НЕ ВЫПОЛНИЛОСЬ (код %s)\n\n' "$HOLD_RC" ;;
    esac
fi

# ── Гейт 3: материал учётных данных ─────────────────────────────────────────
# Ищется САМ МАТЕРИАЛ, а не исходники о нём: заголовок ключа встречается в коде,
# который ключ ПОРОЖДАЕТ, и такой файл законен. Различает признак тела — длинная
# строка base64; она есть у выложенного ключа и отсутствует у порождающего его
# вызова. Предикат проверен в обе стороны пробой рядом.
gates=$((gates + 1))
printf '── материал учётных данных\n'
# Выражения объявлены переменными: правая часть `=~` не берётся в кавычки, иначе
# она сравнивается как литерал.
key_header_re='BEGIN [A-Z ]*PRIVATE KEY'
key_body_re=$'\n''[A-Za-z0-9+/]{40,}={0,2}'$'\n'
SCANNED=0; HITS=()
while IFS= read -r f; do
    [ -n "$f" ] || continue
    SCANNED=$((SCANNED + 1))
    body="$(git show "${SRC_SHA}:${f}" 2>/dev/null)" || continue
    case "$f" in
        *.pem|*.key|*.p12|*.pfx|*.jks|*.keystore|*/.env|.env|*/kubeconfig|*id_rsa|*id_ed25519)
            HITS+=("$f (имя)"); continue ;;
    esac
    # Оба сравнения — средствами оболочки, по той же причине (#658). Тело
    # ограничено переводами строки с обеих сторон, поэтому «длинная строка
    # base64» остаётся именно СТРОКОЙ, а не куском длинного текста.
    if [[ "$body" =~ $key_header_re ]] && [[ $'\n'"$body"$'\n' =~ $key_body_re ]]; then
        HITS+=("$f (тело)")
    fi
done < <(git ls-tree -r --name-only "$SRC_SHA" -- "$SVC_DIR")
printf '   осмотрено файлов %s, находок %s\n' "$SCANNED" "${#HITS[@]}"
if [ "$SCANNED" = "0" ]; then
    void+=("учётные данные"); printf '   → НЕ ВЫПОЛНИЛОСЬ: обход пуст\n\n'
elif [ "${#HITS[@]}" -gt 0 ]; then
    red+=("учётные данные")
    printf '   %s\n' "${HITS[@]}"
    printf '   → НАХОДКА: выкладка распространила бы материал\n\n'
else
    printf '   → сошлось\n\n'
fi

# ── Гейт 4: зависимость платформы достижима у ПОСТОРОННЕГО ──────────────────
# Дерево, собирающееся в монорепо, у постороннего может не собраться вовсе: он
# тянет платформу с прокси по псевдоверсии, а та достижима не всегда. Спрашивать
# надо прокси, а не своё дерево, — своё отвечает про соседний каталог.
gates=$((gates + 1))
printf '── зависимость платформы достижима с прокси\n'
PIN="$(printf '%s\n' "$GOMOD" | awk '/PRO-Robotech\/kacho[ \t]/{print $2; exit}')"
if [ -z "$PIN" ]; then
    printf '   зависимости на платформу нет — спрашивать нечего\n   → сошлось\n\n'
elif ! command -v curl >/dev/null 2>&1; then
    void+=("зависимость платформы"); printf '   → НЕ ВЫПОЛНИЛОСЬ: нет curl\n\n'
else
    ESC="$(printf '%s' "github.com/PRO-Robotech/kacho" | sed 's/\([A-Z]\)/!\l\1/g')"
    CODE="$(curl -s -o /dev/null -w '%{http_code}' --max-time 30 \
        "https://proxy.golang.org/${ESC}/@v/${PIN}.mod" 2>/dev/null || echo 000)"
    printf '   пин %s, ответ прокси %s\n' "$PIN" "$CODE"
    case "$CODE" in
        200) printf '   → сошлось\n\n' ;;
        000) void+=("зависимость платформы"); printf '   → НЕ ВЫПОЛНИЛОСЬ: прокси не ответил\n\n' ;;
        *)   red+=("зависимость платформы")
             printf '   → НАХОДКА: посторонний не соберёт службу — пин не отдаётся\n\n' ;;
    esac
fi

printf 'перепись: гейтов %d, находок %d, НЕ спрошено %d, файлов службы %s\n\n' \
    "$gates" "${#red[@]}" "${#void[@]}" "$SCANNED"

if [ "$gates" = "0" ]; then
    echo "обход пуст: не прогнано ни одного гейта — вердикт беспредметен" >&2; exit 3
fi
if [ "${#red[@]}" -gt 0 ]; then
    printf 'находки: %s\n' "${red[*]}" >&2
    echo "ВЫКЛАДКА НЕ ОТКРЫТА. Ничего не отправлено." >&2; exit 1
fi
if [ "${#void[@]}" -gt 0 ]; then
    printf 'не спрошено: %s\n' "${void[*]}" >&2
    echo "ВЕРДИКТА НЕТ: не спрошенная предпосылка не считается выполненной. Ничего не отправлено." >&2
    exit 3
fi

if [ "$PUBLISH" != "1" ]; then
    VIA_HINT=""; [ "$VIA_PR" = "1" ] && VIA_HINT=" --via-pull-request"
    cat <<DRY
Все предпосылки сошлись. ХОЛОСТОЙ прогон: ничего не отправлено.
Необратимый шаг делает тот же скрипт с ключом --publish:

    $0 $SVC $REPO --confirm $REPO --rev $REV --publish$VIA_HINT
DRY
    exit 0
fi

# ── Необратимый шаг ─────────────────────────────────────────────────────────
# Сборка идёт в СВОЁМ каталоге и своим клоном: рабочая копия монорепо не
# трогается ни индексом, ни ветками. Класс общий с прочими скриптами дерева —
# состояние, которого не заводил, не правишь.
WORK="$(mktemp -d)" || { echo "каталог не заведён" >&2; exit 3; }
trap 'rm -rf "$WORK"' EXIT

# ЛИЧНОСТЬ КОММИТЯЩЕГО ПЕРЕНОСИТСЯ ИЗ ИСТОЧНИКА, А НЕ ВЫДУМЫВАЕТСЯ. У свежего
# клона настроек нет, и «коммить умолчанием» там означает подпись, выведенную из
# имени машины. Значения читаются у ИСТОЧНИКА, поэтому коммит артефакта несёт ту
# же подпись, что несёт коммит монорепо; неустановленная личность — отказ, а не
# повод подписаться кем-то ещё.
WHO_NAME="$(git config user.name || true)"
WHO_MAIL="$(git config user.email || true)"
if [ -z "$WHO_NAME" ] || [ -z "$WHO_MAIL" ]; then
    echo "личность коммитящего не установлена в источнике — ничего не отправлено" >&2
    exit 3
fi

echo "── клон артефакта"
# Код читается у КЛОНА, а не у последнего звена конвейера: `sed` завершается
# успехом всегда, и отказ клона прошёл бы незамеченным.
git clone --quiet --branch "$BRANCH" "$URL" "$WORK/a" 2>&1 | sed 's/^/   /'
if [ "${PIPESTATUS[0]}" != "0" ] || [ ! -d "$WORK/a/.git" ]; then
    echo "   клон не удался — ничего не отправлено" >&2; exit 3
fi
git -C "$WORK/a" config user.name  "$WHO_NAME"
git -C "$WORK/a" config user.email "$WHO_MAIL"
BASE="$(git -C "$WORK/a" rev-parse HEAD)"
printf '   ствол %s на %.12s\n' "$BRANCH" "$BASE"

echo "── замещение дерева содержимым монорепо"
# ОБЕ команды исполняются В КЛОНЕ, и подсказка `git -C` тут негодна: она
# переставляет каталог только git-у, а `rm` в конвейере остаётся в текущем — то
# есть в рабочей копии вызывающего. Форма `git -C … ls-files | xargs rm` была
# здесь написана и снята по наблюдению: она удалила семь файлов КОРНЯ рабочей
# копии, чьи имена совпали с именами корня артефакта (go.mod, Makefile, LICENSE
# и другие). Индекс при этом цел, и восстановилось всё дословно, но правило
# «состояние, которого не заводил, не правишь» нарушила именно эта строка.
( cd "$WORK/a" && git ls-files -z | xargs -0 --no-run-if-empty rm -f ) || {
    echo "   прежнее дерево не снято — ничего не отправлено" >&2; exit 3; }
git archive --format=tar "${SRC_SHA}:${SVC_DIR}" | tar -x -C "$WORK/a" || {
    echo "   дерево не распаковано — ничего не отправлено" >&2; exit 3; }
git -C "$WORK/a" add -A || { echo "   индекс не собран" >&2; exit 3; }

# Ничего сверх дерева службы: утверждается замером, а не построением. Построение
# верно и сегодня, но проверка переживёт его правку, а довод «оно и так так» —
# нет.
WANT="$(git ls-tree -r --name-only "$SRC_SHA" -- "$SVC_DIR" | sed "s|^${SVC_DIR}/||" | sort)"
GOT="$(git -C "$WORK/a" ls-files | sort)"
if [ "$WANT" != "$GOT" ]; then
    echo "   НАХОДКА: набор файлов разошёлся с деревом службы — ничего не отправлено" >&2
    diff <(printf '%s\n' "$WANT") <(printf '%s\n' "$GOT") | head -20 >&2
    exit 1
fi
printf '   файлов к выкладке %s — набор равен дереву службы\n' "$(printf '%s\n' "$GOT" | grep -c . || true)"

if git -C "$WORK/a" diff --cached --quiet; then
    echo "   дерево артефакта уже совпадает с монорепо — отправлять нечего"
    exit 0
fi

git -C "$WORK/a" commit --quiet -m "$(cat <<MSG
Дерево службы приведено к монорепо

Поставка совпадает с ${SVC_DIR} монорепо на ревизии ${SRC_SHA}.
Объявленный путь модуля совпадает с адресом, по которому службу достают,
поэтому выборка модуля посторонним разрешается.

Коммит произведён scripts/release/publish-service-artifact.sh — у поставки
появился производитель, и её повторяемость больше не зависит от того, кто
и что вспомнил.
MSG
)" || { echo "   коммит не создан" >&2; exit 3; }

NEW="$(git -C "$WORK/a" rev-parse HEAD)"

done_note() {
    cat <<DONE

Выложено. Проверить тем же способом, каким берёт посторонний:

    cd "\$(mktemp -d)" && go mod init probe >/dev/null
    GOFLAGS= GOPRIVATE= go get ${MODULE_WANT}@latest

DONE
}

# ── Полоса 1: прямо в ствол ─────────────────────────────────────────────────
if [ "$VIA_PR" != "1" ]; then
    echo "── отправка"
    git -C "$WORK/a" push origin "HEAD:$BRANCH" 2>&1 | sed 's/^/   /'
    if [ "${PIPESTATUS[0]}" != "0" ]; then
        # ТРЕТЬЯ КАТЕГОРИЯ, а не находка. Отказ отправки — нет учётных данных,
        # ствол ушёл вперёд, ствол защищён, сеть — говорит об УСЛОВИИ, а не о
        # дереве; выдать его за находку значило бы послать читателя искать дефект
        # там, где его нет.
        echo "   НЕ отправлено: спросить удалённый не удалось. Дерево ни при чём." >&2
        echo "   Ствол защищён правилами? — полоса --via-pull-request." >&2
        exit 3
    fi
    printf '   %s %s: %.12s → %.12s\n' "$REPO" "$BRANCH" "$BASE" "$NEW"
    done_note
    exit 0
fi

# ── Полоса 2: через запрос на слияние ───────────────────────────────────────
# ЗАЧЕМ ОНА. Ствол артефакта защищён правилами репозитория: прямая отправка
# отвергается удалённым, и обойти это можно ровно двумя способами — снять защиту
# либо пройти тем путём, который она оставляет открытым. Первое запрещено: защита
# стоит на ЧУЖОМ стволе, и снятие её ради своей отправки есть расширение доступа
# вместо сужения. Значит производитель обязан уметь второе, иначе поставку снова
# доводит человек — то есть у неё снова нет производителя.
#
# ПОБОЧНО ЗАКРЫВАЕТСЯ ВТОРОЕ ПРЕПЯТСТВИЕ, и это надо назвать, чтобы не сочли
# совпадением: отправка по ssh идёт от ЛИЧНОСТИ владельца ключа, а не от
# приложения OAuth, поэтому ограничение «приложению не разрешено заводить или
# менять объявление конвейера без полномочия workflow» на неё не распространяется
# by construction. Полоса запроса на слияние транспорта не назначает — она
# наследует его у источника тем же правилом, что и полоса ствола.
WORK_BRANCH="publish/${SVC}-${SRC_SHA:0:12}"
FORGE="${KACHO_FORGE_CMD:-gh}"

printf '── доставка через запрос на слияние (ветка %s)\n' "$WORK_BRANCH"

# Ветка ИМЕНУЕТСЯ ОТ РЕВИЗИИ ИСТОЧНИКА, а не от времени: повторный вызов на той
# же ревизии обязан попасть в тот же запрос, а не завести второй. Занятость
# имени поэтому не «перезаписывается» — она РАЗБИРАЕТСЯ: своё дерево или чужое.
REMOTE_HEAD="$(git -C "$WORK/a" ls-remote origin "refs/heads/$WORK_BRANCH" 2>/dev/null | awk '{print $1}')"
LSR_RC=$?
if [ "$LSR_RC" != "0" ]; then
    echo "   НЕ выполнилось: удалённый не спрошен о ветке. Дерево ни при чём." >&2
    exit 3
fi
PUSH_NEEDED=1
if [ -n "$REMOTE_HEAD" ]; then
    git -C "$WORK/a" fetch --quiet origin "refs/heads/$WORK_BRANCH" 2>/dev/null
    REMOTE_TREE="$(git -C "$WORK/a" rev-parse --verify --quiet "${REMOTE_HEAD}^{tree}" 2>/dev/null || true)"
    OUR_TREE="$(git -C "$WORK/a" rev-parse "HEAD^{tree}")"
    if [ -n "$REMOTE_TREE" ] && [ "$REMOTE_TREE" = "$OUR_TREE" ]; then
        printf '   ветка уже несёт это дерево (%.12s) — отправлять нечего\n' "$REMOTE_HEAD"
        NEW="$REMOTE_HEAD"; PUSH_NEEDED=0
    else
        cat >&2 <<OCC
   НЕ выполнилось: ветка $WORK_BRANCH занята ЧУЖИМ деревом ($REMOTE_HEAD).
   Она не перезаписывается: работа, которой не заводил, не правится.
   Разберите её сами либо позовите производителя на другой ревизии.
OCC
        exit 3
    fi
fi

if [ "$PUSH_NEEDED" = "1" ]; then
    git -C "$WORK/a" push origin "HEAD:refs/heads/$WORK_BRANCH" 2>&1 | sed 's/^/   /'
    if [ "${PIPESTATUS[0]}" != "0" ]; then
        echo "   НЕ отправлено: спросить удалённый не удалось. Дерево ни при чём." >&2
        exit 3
    fi
    printf '   ветка %s: %.12s\n' "$WORK_BRANCH" "$NEW"
fi

# ── Форж ────────────────────────────────────────────────────────────────────
# Отсутствие форжа — ТРЕТЬЯ КАТЕГОРИЯ, а не находка: ветка уже на месте, дерево
# ни при чём, и человеку остаётся ровно один шаг, который здесь и называется.
if ! command -v "$FORGE" >/dev/null 2>&1; then
    cat >&2 <<NOFORGE
   НЕ выполнилось: команда форжа '$FORGE' не найдена — запрос не открыт.
   Ветка отправлена и цела; открыть запрос вручную:
     $FORGE pr create -R $REPO --base $BRANCH --head $WORK_BRANCH
NOFORGE
    exit 3
fi

PR_NUM="$("$FORGE" pr list -R "$REPO" --head "$WORK_BRANCH" --state open \
            --json number --jq '.[0].number' 2>/dev/null || true)"
if [ -z "$PR_NUM" ] || [ "$PR_NUM" = "null" ]; then
    PR_OUT="$("$FORGE" pr create -R "$REPO" --base "$BRANCH" --head "$WORK_BRANCH" \
        --title "Дерево службы приведено к монорепо (${SRC_SHA:0:12})" \
        --body "Поставка совпадает с ${SVC_DIR} монорепо на ревизии ${SRC_SHA}.

Ствол этого репозитория защищён правилами, поэтому дерево доставляется
через запрос на слияние, а не прямой отправкой. Защита не снимается и не
ослабляется: она стоит на стволе и обязана остаться.

Коммит и запрос произведены scripts/release/publish-service-artifact.sh
--via-pull-request." 2>&1)"; PR_RC=$?
    printf '%s\n' "$PR_OUT" | sed 's/^/   /'
    if [ "$PR_RC" != "0" ]; then
        echo "   НЕ выполнилось: запрос не открыт. Ветка отправлена и цела." >&2
        exit 3
    fi
    PR_NUM="$("$FORGE" pr list -R "$REPO" --head "$WORK_BRANCH" --state open \
                --json number --jq '.[0].number' 2>/dev/null || true)"
fi
if [ -z "$PR_NUM" ] || [ "$PR_NUM" = "null" ]; then
    echo "   НЕ выполнилось: номер запроса не установлен." >&2; exit 3
fi
printf '   запрос на слияние: %s#%s\n' "$REPO" "$PR_NUM"

# ── Обязательные проверки ───────────────────────────────────────────────────
# Перечень спрашивается У ЗАЩИТЫ, а не выписывается: выписанный разошёлся бы с
# репозиторием молча. Контекст, которого НЕТ СРЕДИ ПРОИЗВЕДЁННЫХ, не зеленеет и
# не краснеет — он остаётся «ожидается», и вливание блокируется навсегда;
# поэтому недостающие называются отдельно от идущих, а не сваливаются в «ждём».
REQ="$("$FORGE" api "repos/$REPO/branches/$BRANCH/protection" \
        --jq '.required_status_checks.contexts[]?' 2>/dev/null || true)"
REQ_N="$(printf '%s\n' "$REQ" | grep -c . || true)"
if [ "$REQ_N" = "0" ]; then
    echo "   НЕ выполнилось: перечень обязательных проверок не прочитан у защиты." >&2
    echo "   Вердикт о готовности выносить нечем; запрос $REPO#$PR_NUM открыт." >&2
    exit 3
fi
printf '   обязательных проверок %s, бюджет ожидания %s с\n' "$REQ_N" "$CHECKS_BUDGET"

DEADLINE=$(( $(date +%s) + CHECKS_BUDGET ))
STATE="pending"; MISSING=""; RED=""
while :; do
    RUNS="$("$FORGE" api "repos/$REPO/commits/$NEW/check-runs?per_page=100" --paginate \
            --jq '.check_runs[] | "\(.name)\t\(.status)\t\(.conclusion)"' 2>/dev/null || true)"
    MISSING=""; RED=""; RUNNING=""; GREEN=0
    while IFS= read -r ctx; do
        [ -n "$ctx" ] || continue
        line="$(printf '%s\n' "$RUNS" | awk -F'\t' -v c="$ctx" '$1==c{print; exit}')"
        if [ -z "$line" ]; then MISSING="$MISSING$ctx"$'\n'; continue; fi
        st="$(printf '%s' "$line" | cut -f2)"; cc="$(printf '%s' "$line" | cut -f3)"
        if [ "$st" != "completed" ]; then RUNNING="$RUNNING$ctx"$'\n'; continue; fi
        case "$cc" in
            success|neutral|skipped) GREEN=$((GREEN + 1)) ;;
            *) RED="$RED$ctx ($cc)"$'\n' ;;
        esac
    done < <(printf '%s\n' "$REQ")

    printf '   зелено %s, красно %s, идёт %s, не появилось %s\n' \
        "$GREEN" "$(printf '%s' "$RED" | grep -c . || true)" \
        "$(printf '%s' "$RUNNING" | grep -c . || true)" \
        "$(printf '%s' "$MISSING" | grep -c . || true)"

    if [ -n "$RED" ]; then STATE="red"; break; fi
    if [ "$GREEN" = "$REQ_N" ]; then STATE="green"; break; fi
    if [ "$(date +%s)" -ge "$DEADLINE" ]; then STATE="timeout"; break; fi
    sleep 30
done

case "$STATE" in
    red)
        # НАХОДКА, а не третья категория: конвейер артефакта прогнан по
        # ВЫЛОЖЕННОМУ дереву и отверг его. Это вердикт о дереве.
        printf 'красные обязательные проверки:\n%s' "$RED" >&2
        echo "ВЛИВАНИЕ НЕ ОТКРЫТО: конвейер артефакта отверг дерево. Запрос $REPO#$PR_NUM открыт." >&2
        exit 1 ;;
    timeout)
        [ -n "$MISSING" ] && printf 'не появилось ни разу (производителя нет?):\n%s' "$MISSING" >&2
        echo "НЕ ВЫПОЛНИЛОСЬ: вердикт не вынесен в пределах бюджета. Запрос $REPO#$PR_NUM открыт, ветка цела." >&2
        exit 3 ;;
esac

echo "── вливание"
# ТЕЛО СХЛОПНУТОГО КОММИТА ЗАДАЁТСЯ ЯВНО. Умолчание форжа склеивает тела всех
# коммитов ветки: сегодня он один, и умолчание совпало бы, но ветка перестаёт
# быть одно-коммитной от первой же правки, и склейка приедет молча.
MERGE_BODY="$WORK/merge-body.txt"
cat > "$MERGE_BODY" <<MB
Поставка совпадает с ${SVC_DIR} монорепо на ревизии ${SRC_SHA}.

Доставлено через запрос на слияние ${REPO}#${PR_NUM}: ствол защищён правилами
репозитория, и защита не снимается — производитель проходит тем путём, который
она оставляет открытым.

Коммит, ветка и запрос произведены scripts/release/publish-service-artifact.sh
--via-pull-request.
MB
"$FORGE" pr merge "$PR_NUM" -R "$REPO" --squash --delete-branch --body-file "$MERGE_BODY" 2>&1 | sed 's/^/   /'
if [ "${PIPESTATUS[0]}" != "0" ]; then
    echo "   НЕ выполнилось: вливание отвергнуто. Запрос $REPO#$PR_NUM открыт и зелен." >&2
    exit 3
fi
TRUNK="$(git -C "$WORK/a" ls-remote origin "refs/heads/$BRANCH" 2>/dev/null | awk '{print $1}')"
printf '   %s %s: %.12s → %.12s (через %s#%s)\n' "$REPO" "$BRANCH" "$BASE" "${TRUNK:-?}" "$REPO" "$PR_NUM"
done_note
exit 0
