#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ. У ПРОИЗВОДИТЕЛЯ НЕТ ПОЛА, И ЕГО ПЕРЕПИСЬ УБЫВАЕТ МОЛЧА
#
# `assemble-foundation-tree` собирает дерево фундамента из каталогов `pkg/*`,
# чей класс объявлен картой границы. Что он возьмёт — целиком следствие того,
# что лежит в дереве платформы: файла там нет — файл не поедет, и производитель
# об этом не скажет НИЧЕГО. Он отказывает на каталоге без класса, на пустом
# обходе, на неочищаемом назначении — но не на том, что взятого стало МЕНЬШЕ.
#
# Замер, ради которого пол заведён (задача #2131). Соседняя полоса перевела
# платформу на потребление опубликованного фундамента и удалила два порождённых
# стаба, которые платформе больше не нужны. Производитель на той ревизии:
#
#   код возврата                              0     (было 0)
#   каталогов к переезду                     69     (было 71)
#   файлов из индекса                       439     (было 441)
#   остаток пути платформы в дескрипторах     6     (было 8)
#
# ЕДИНСТВЕННАЯ МЕНЯЮЩАЯСЯ ВЕЛИЧИНА УБЫВАЕТ — и читается как улучшение: меньше
# файлов, меньше остатка. Ни красного, ни роста, ни ненулевого кода. А собранное
# дерево при этом НЕ СОБИРАЕТСЯ вовсе: пять файлов в нём импортируют два пакета,
# которых в нём больше нет.
#
# Пол задаёт вопрос, которого не задаёт никто: СОСТАВ собранного дерева против
# состава ПОСЛЕДНЕГО ОПУБЛИКОВАННОГО выпуска. Исчезнувший пакет — НАХОДКА, а не
# строка переписи.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЕДИНИЦА СЧЁТА — ИМПОРТИРУЕМЫЙ ПАКЕТ, А НЕ ФАЙЛ. ОБА ЧИСЛА ПЕЧАТАЮТСЯ
#
# Единица — каталог, несущий хотя бы один НЕ тестовый `.go`: ровно то, что
# посторонний может импортировать, и ровно то, чья пропажа ломает потребителя
# ПО ПОСТРОЕНИЮ — путь импорта перестаёт резолвиться.
#
# Файл единицей НЕ выбран, и это решение, а не упущение. Пакет, переживший
# правку с другим составом файлов, — рутина: слияние двух файлов в один, вынос
# помощника, переименование внутри пакета. Пол, краснеющий на них, стал бы
# прибором, у которого почти все находки ложные, — а такой перестают читать, и
# вместе с ним перестают читать настоящую находку. Пропажу ЭКСПОРТИРОВАННОГО
# ИМЕНИ внутри уцелевшего пакета судит соседний механизм — точка отсчёта разрыва
# (`breaking-since-release.sh`), у неё своя ось и свой вход.
#
# Число файлов при этом печатается — как перепись, а не как вердикт: «пакетов
# сошлось» при заметно упавшем счёте файлов есть повод посмотреть, а не повод
# уронить прогон.
#
# ПЕЧАТАЮТСЯ ОБЕ ВЕЛИЧИНЫ — сколько пакетов в сборке И сколько в выпуске. Одно
# число скрывает ровно тот случай, ради которого пол заводится: на замере выше
# у собранного дерева ПОСЛЕ правки соседки пакетов ровно столько же, сколько в
# выпуске (68 и 68), потому что два исчезли и два добавились. Счёт сошёлся,
# состав — нет. Пол судит СОСТАВ; счёт он печатает, чтобы читатель видел, что
# совпадение счёта ничего не доказывает.
#
# ─────────────────────────────────────────────────────────────────────────────
# ДОБАВЛЕННЫЙ ПАКЕТ — НЕ НАХОДКА. ЭТО ЗАКОННЫЙ БЛИЗНЕЦ, И ОН ЧАСТЫЙ
#
# Пол односторонний НАМЕРЕННО. Фундамент растёт: каталог, переклассифицированный
# в `corelib`, приезжает в следующей сборке и обязан приехать. На том же замере
# сборка ствола добавила к выпуску `modulemanifest` и `modulemanifest/producer` —
# ровно то, что переклассифицировал MR #2584. Двусторонний пол краснел бы на
# каждом таком переезде, то есть на штатной работе.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧЕМ БЕРЁТСЯ ОПУБЛИКОВАННОЕ — ПОСРЕДНИКОМ, И ЦЕНА НАЗВАНА
#
# Рассмотрены и клон по тегу, и загрузка посредником; обе на замере работают
# (тег `v1.3.1` виден `git ls-remote`, зип отдаёт `proxy.golang.org`). Выбран
# ПОСРЕДНИК, по двум причинам, и первая решающая:
#
#   1. посредник отдаёт то, что ПОЛУЧАЕТ ПОТРЕБИТЕЛЬ, и отдаёт НЕИЗМЕННО.
#      Опубликованная версия у посредника не меняется никогда — именно поэтому
#      по пути фундамента сожжено 46 номеров. Тег же в git ПОДВИЖЕН: его можно
#      переставить, и пол, сверяющийся с тегом, сверялся бы с величиной, которую
#      автор ошибки правит той же рукой;
#   2. соседняя проба годности (`probe-published.sh`) спрашивает тем же путём и
#      теми же словами — «как посторонний потребитель». Второй механизм об одном
#      предмете разошёлся бы с первым молча.
#
# ЦЕНА: нужны `go` и достижимый посредник. Без них пол НЕ ДАЁТ ВЕРДИКТА — это
# третий исход, «условие не создано», и он НЕ находка и НЕ зелёное. Смешать их
# нельзя: «спросить не удалось» и «пакет исчез» требуют разного от читателя.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ЧЕТЫРЕ, И ТРЕТИЙ ОТДЕЛЁН КОНТРОЛЬНЫМ ВОПРОСОМ, А НЕ ТЕКСТОМ ОТКАЗА
#
#   0 — состав сошёлся: ни один опубликованный пакет не исчез;
#   1 — НАХОДКА: пакет есть в выпуске и его нет в собранном дереве;
#   2 — скрипт позван неверно;
#   3 — ВЕРДИКТА НЕТ: спросить не удалось (нет `go`, посредник не отвечает, путь
#       модуля ему неизвестен) либо судить нечем (выпусков ноль, обход пуст).
#
# Прежде главного вопроса задаётся УПРАВЛЯЮЩИЙ: знает ли посредник путь модуля
# ВООБЩЕ. Управляющий прошёл — посредник достижим, и всё дальнейшее есть факт о
# дереве. Управляющий упал — спросить не удалось, и «не знаю» не выдаётся ни за
# «да», ни за «нет». Классификация по фразам инструмента этого не даёт: одна и
# та же фраза приходит и на опечатку в пути модуля (наша поломка), и на пропавшую
# сеть.
#
# НАХОДКА ОБЪЯВЛЯЕТСЯ ПЕРВОЙ. Прогон, где есть и находка, и неспрошенное, отдаёт
# 1: иначе неспрошенное маскировало бы находку.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

MODULE="${KACHO_FOUNDATION_MODULE:-github.com/PRO-Robotech/corelib}"

usage() {
    cat >&2 <<USAGE
употребление: $0 <собранное-дерево> [--version <версия>]

  <собранное-дерево>  выход assemble-foundation-tree
  --version <версия>  с чем сверять (умолчание: САМАЯ ПОЗДНЯЯ известная
                      посреднику; версия берётся из того же ответа, что и
                      управляющий вопрос, — одна просьба, два применения)

переменные:
  KACHO_FOUNDATION_MODULE  путь модуля (умолчание: $MODULE)
  GOPROXY                  откуда берётся выпуск; пол его НЕ переопределяет
USAGE
}

[ $# -ge 1 ] || { usage; exit 2; }
case "$1" in -h|--help) usage; exit 2 ;; esac
TREE="$1"; shift
WANT_VERSION=""
while [ $# -gt 0 ]; do
    case "$1" in
        --version) [ $# -ge 2 ] || { usage; exit 2; }; WANT_VERSION="$2"; shift 2 ;;
        *) echo "неизвестный довод: $1" >&2; usage; exit 2 ;;
    esac
done

[ -d "$TREE" ] || {
    echo "собранного дерева нет либо это не каталог: $TREE" >&2
    echo "  Пол судит ВЫХОД производителя; назовите каталог, который он собрал." >&2
    exit 2; }

command -v go >/dev/null 2>&1 || {
    echo "ВЕРДИКТА НЕТ: инструмента нет — go не найден" >&2; exit 3; }
command -v python3 >/dev/null 2>&1 || {
    echo "ВЕРДИКТА НЕТ: инструмента нет — python3 не найден" >&2; exit 3; }

tmp="$(mktemp -d)"
# Модуль-кэш посредника кладётся с правами только на чтение — снос без
# `chmod -R u+w` отказывает, и уборка молча не состоялась бы.
trap 'chmod -R u+w "$tmp" 2>/dev/null; rm -rf "$tmp"' EXIT

# Просьбы к посреднику идут ИЗ ПУСТОГО МОДУЛЯ во временном каталоге: рабочее
# дерево вызывающего пол не трогает и его `go.mod` не читает.
ask="$tmp/ask"; mkdir -p "$ask"
printf 'module floorprobe\n\ngo 1.21\n' > "$ask/go.mod"

# Кэш модулей — СВОЙ, как у соседней пробы годности: общий делит состояние с
# сессиями на той же машине, и «пакет на месте» оказалось бы куплено чужой
# работой — а на нём стоит вердикт о СОСТАВЕ выпуска.
export GOMODCACHE="$tmp/modcache"
export GOFLAGS="-mod=mod"
export GOWORK=off

# ── УПРАВЛЯЮЩИЙ ВОПРОС ──────────────────────────────────────────────────────
VERSIONS_RAW="$(cd "$ask" && go list -m -versions "$MODULE" 2>"$tmp/ctl.err")"
CTL_RC=$?
if [ "$CTL_RC" != "0" ]; then
    {
        echo "ВЕРДИКТА НЕТ: спросить не удалось — посредник не ответил про путь модуля."
        echo "  модуль: $MODULE"
        echo "  GOPROXY: ${GOPROXY:-<умолчание go>}"
        echo "  Это НЕ находка: «не знаю» не выдаётся за «пакет исчез». Проверьте сеть"
        echo "  и путь модуля, затем спросите снова."
        sed 's/^/    /' "$tmp/ctl.err"
    } >&2
    exit 3
fi

# Первое поле ответа — путь модуля, дальше версии по возрастанию.
read -r -a VF <<< "$VERSIONS_RAW"
KNOWN_N=$(( ${#VF[@]} - 1 ))
if [ "$KNOWN_N" -lt 1 ]; then
    {
        echo "ВЕРДИКТА НЕТ: посредник знает путь $MODULE, но версий у него ноль."
        echo "  Сверять не с чем — пола ещё не существует. Это НЕ зелёное:"
        echo "  «сравнить было не с чем» и «ничего не исчезло» — разные факты."
    } >&2
    exit 3
fi
VERSION="${WANT_VERSION:-${VF[$KNOWN_N]}}"

# ── ОРИЕНТИР ────────────────────────────────────────────────────────────────
DL="$(cd "$ask" && go mod download -json "$MODULE@$VERSION" 2>"$tmp/dl.err")"
PUB_DIR="$(printf '%s' "$DL" | python3 -c 'import json,sys
try:
    d = json.loads(sys.stdin.read() or "{}")
except Exception:
    d = {}
print(d.get("Dir", "") if not d.get("Error") else "")')"
if [ -z "$PUB_DIR" ] || [ ! -d "$PUB_DIR" ]; then
    {
        echo "ВЕРДИКТА НЕТ: ориентир не добыт — выпуск $MODULE@$VERSION не разложен."
        echo "  Посредник путь модуля знает (версий ему известно $KNOWN_N), но этот"
        echo "  выпуск взять не удалось. Судить не с чем; это НЕ находка о дереве."
        printf '%s' "$DL" | sed 's/^/    /'
        sed 's/^/    /' "$tmp/dl.err"
    } >&2
    exit 3
fi

# ── СОСТАВ ──────────────────────────────────────────────────────────────────
# Обе стороны считаются ОДНИМ И ТЕМ ЖЕ обходом: два разных обхода разошлись бы
# на первой же особенности раскладки, и разошлись бы молча.
python3 - "$PUB_DIR" "$TREE" "$MODULE" "$VERSION" <<'PY'
import os, sys

pub_dir, tree_dir, module, version = sys.argv[1:5]

def walk(root):
    """Возвращает (импортируемые пакеты, обычные файлы).

    Импортируемый пакет — каталог, несущий хотя бы один не тестовый `.go`.
    Каталог, где остались ОДНИ тесты, импортируемым не является: его пропажа
    ломает потребителя так же, как пропажа каталога целиком, — поэтому он
    здесь не считается уцелевшим."""
    pkgs, files = set(), 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        rel = os.path.relpath(dirpath, root).replace(os.sep, "/")
        importable = False
        for fn in filenames:
            files += 1
            if fn.endswith(".go") and not fn.endswith("_test.go"):
                importable = True
        if importable:
            pkgs.add(rel)
    return pkgs, files

pub_pkgs, pub_files = walk(pub_dir)
asm_pkgs, asm_files = walk(tree_dir)

vanished = sorted(pub_pkgs - asm_pkgs)
added = sorted(asm_pkgs - pub_pkgs)

print()
print("ОРИЕНТИР: %s@%s" % (module, version))
print("перепись, единица — импортируемый пакет (каталог с >=1 не тестовым .go):")
print("  в выпуске %d, в собранном дереве %d" % (len(pub_pkgs), len(asm_pkgs)))
print("  исчезло %d, добавлено %d" % (len(vanished), len(added)))
print("перепись, единица — обычный файл (НЕ вердикт, а контекст):")
print("  в выпуске %d, в собранном дереве %d" % (pub_files, asm_files))

# Перепись сбрасывается ДО любой записи в поток отказа. Без этого stdout,
# буферизованный блоками, вышел бы ПОСЛЕ stderr, и читатель общего файла увидел
# бы находку раньше объёма осмотренного — то есть раньше, чем узнал, что вообще
# было прочитано.
sys.stdout.flush()

# Пустой обход зелёного не даёт: «прочитано ноль» не есть «находок ноль».
if not pub_pkgs:
    print()
    print("ВЕРДИКТА НЕТ: в выпуске %s@%s импортируемых пакетов ноль — обход"
          " ориентира пуст." % (module, version), file=sys.stderr)
    sys.exit(3)

# НАХОДКА ОБЪЯВЛЯЕТСЯ ПЕРВОЙ — раньше любой оговорки о неспрошенном.
if vanished:
    print(file=sys.stderr)
    print("НАХОДКА: опубликованных пакетов исчезло из сборки: %d" % len(vanished),
          file=sys.stderr)
    for p in vanished:
        print("    %s" % p, file=sys.stderr)
    print(file=sys.stderr)
    print("  Производитель об этом не сказал: он берёт то, что лежит в дереве"
          " платформы,", file=sys.stderr)
    print("  и пропажу читает как убыль переписи, а не как отказ. Собранное"
          " дерево, потерявшее", file=sys.stderr)
    print("  пакет, ломает КАЖДОГО потребителя, чей импорт на него смотрел.",
          file=sys.stderr)
    print(file=sys.stderr)
    print("  Исходов три: вернуть пакет в дерево платформы · научить"
          " производителя ЭМИТИРОВАТЬ", file=sys.stderr)
    print("  его (если у пакета есть контракт) · снять его с выпуска ОСОЗНАННО,"
          " объявив слом.", file=sys.stderr)
    sys.exit(1)

if not asm_pkgs:
    print()
    print("ВЕРДИКТА НЕТ: в собранном дереве импортируемых пакетов ноль — обход пуст.",
          file=sys.stderr)
    sys.exit(3)

print()
print("ПОЛ ДЕРЖИТСЯ: все %d опубликованных пакетов на месте в собранном дереве"
      % len(pub_pkgs))
if added:
    print("ДОБАВЛЕНО %d — это НЕ находка: фундамент растёт, и переклассифицированный"
          % len(added))
    print("каталог обязан появиться в следующей сборке:")
    for p in added:
        print("    %s" % p)
PY
rc=$?
exit "$rc"
