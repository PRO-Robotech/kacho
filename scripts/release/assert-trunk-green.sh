# assert-trunk-green.sh — предпосылка «ТЕГ ОБЕЩАЕТ ЗЕЛЁНОЕ».
#
# ЗАЧЕМ. Версия — публичное утверждение о ревизии: потребитель пиннит её и
# складывает контрольную сумму в свой `go.sum`. Тег на красном стволе ХУЖЕ
# отсутствия тега: отсутствие ничего не обещает, а тег обещает то, чего нет, и
# отозвать обещание нельзя (`retract` виден всем, а прокси уже раздал версию).
#
# ЧТО ИМЕННО СПРАШИВАЕТСЯ — И ПОЧЕМУ НЕ «СКОЛЬКО ЗЕЛЁНЫХ». Спрашивается
# СОВПАДЕНИЕ ДВУХ МНОЖЕСТВ ПО ИМЕНАМ: перечень ОБЯЗАТЕЛЬНЫХ контекстов защиты
# ствола против перечня контекстов, УСПЕШНО завершившихся на ЭТОЙ ревизии.
# Счёт зелёных на этот вопрос не отвечает: проверка, которая не начиналась, не
# краснеет и не зеленеет — она отсутствует, и «ноль проверок» читается как
# «замечаний нет». Ровно этот класс уже стоил защиты ствола: слияние проходило в
# окне между открытием запроса и появлением обязательного контекста.
#
# ПУСТОЙ ПЕРЕЧЕНЬ ОБЯЗАТЕЛЬНЫХ — НАХОДКА, А НЕ ЗЕЛЁНОЕ. Если защита ствола не
# требует ни одного контекста, то условие «все обязательные зелены» выполняется
# ТОЖДЕСТВЕННО, и проверка становится формой без содержания. Тег, поставленный
# по такому прогону, не обещает ничего — значит публиковать по нему нельзя.
#
# ИСХОДОВ ЧЕТЫРЕ, И ЧИТАЕТСЯ КОД ВОЗВРАТА:
#   0 — каждый обязательный контекст завершился успехом на названной ревизии;
#   1 — НАХОДКА: обязательный контекст красен, не завершён либо не появлялся;
#   2 — скрипт позван неверно;
#   3 — НЕ ВЫПОЛНИЛОСЬ: спросить не удалось (нет gh, нет доступа, отказ API).
#       Молчание источника не читается ни как «да», ни как «нет»: непрочитанная
#       предпосылка не считается выполненной и в вердикт не вычитается.
#
# ПОЧЕМУ ТРЕТИЙ ИСХОД ОТДЕЛЁН ОТ ПЕРВОГО, А НЕ ОТ ВТОРОГО. Недоступный API даёт
# пустой перечень успешных — то есть выглядит РОВНО как красный ствол. Если не
# разделить, всякий сетевой сбой читался бы как «ствол красен», и настоящая
# находка утонула бы среди ложных.
#
# ПАГИНАЦИЯ ОБЯЗАТЕЛЬНА. Проверок на ревизии может быть больше страницы, и
# усечённый перечень успешных даёт находку по контексту, который на самом деле
# зелен. Продолжение берётся `--paginate`, а не «первой сотней».
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

REPO="${KACHO_RELEASE_REPO:-PRO-Robotech/kacho}"
TRUNK="${KACHO_RELEASE_TRUNK:-main}"

usage() {
    cat >&2 <<USAGE
употребление: $0 <ревизия>

  <ревизия>  полный sha, о зелени которого спрашивают

переменные:
  KACHO_RELEASE_REPO   владелец/репозиторий (умолчание: PRO-Robotech/kacho)
  KACHO_RELEASE_TRUNK  имя ствола (умолчание: main)
USAGE
}

[ $# -eq 1 ] || { usage; exit 2; }
case "$1" in -h|--help) usage; exit 2 ;; esac
SHA="$1"
[[ "$SHA" =~ ^[0-9a-f]{40}$ ]] || {
    echo "ревизия названа не полным sha: '$SHA'" >&2; exit 2; }

command -v gh >/dev/null 2>&1 || {
    echo "НЕ ВЫПОЛНИЛОСЬ: gh не найден — о зелени ствола вердикта нет" >&2; exit 3; }

printf 'предпосылка выпуска: обязательные проверки ствола на %.12s\n' "$SHA"

# ── Обязательные контексты защиты ствола ────────────────────────────────────
# Читаются ОБЕ формы сразу: исторический `contexts` и нынешний `checks[].context`.
# Провайдер отдаёт то одну, то другую в зависимости от того, чем защиту заводили;
# прочитать одну — значит молча получить пустое множество и тождественно-истинный
# вердикт.
PROT_JQ='[(.required_status_checks.contexts // [])[], (.required_status_checks.checks // [])[].context] | unique | .[]'
REQUIRED=""
if ! REQUIRED="$(gh api "repos/$REPO/branches/$TRUNK/protection" --jq "$PROT_JQ" 2>/dev/null)"; then
    cat >&2 <<VOID
НЕ ВЫПОЛНИЛОСЬ: защита ветки $TRUNK не прочитана (нет доступа либо API отказал).
Перечень обязательных проверок неизвестен — «все зелены» утверждать не о чем.
VOID
    exit 3
fi

REQ_COUNT="$(printf '%s' "$REQUIRED" | grep -c . || true)"
if [ "$REQ_COUNT" = "0" ]; then
    printf '\nперепись: обязательных контекстов 0, успешных на ревизии не спрашивалось\n'
    cat >&2 <<'EMPTY'
НАХОДКА: защита ствола не требует ни одного контекста. Условие «все обязательные
зелены» выполняется тождественно, то есть тег не обещал бы НИЧЕГО. Публиковать
по такому прогону нельзя — сперва объявить обязательные проверки.
EMPTY
    exit 1
fi

# ── Успешно завершившиеся на этой ревизии ───────────────────────────────────
# Два источника, потому что провайдер ведёт их раздельно: `check-runs` (действия)
# и `statuses` (внешние отметки). Обязательный контекст может прийти из любого,
# и чтение одного дало бы находку по живому зелёному.
SUCCEEDED=""
RUNS=""
if ! RUNS="$(gh api --paginate "repos/$REPO/commits/$SHA/check-runs?per_page=100" \
        --jq '.check_runs[] | select(.status == "completed" and .conclusion == "success") | .name' 2>/dev/null)"; then
    echo "НЕ ВЫПОЛНИЛОСЬ: перечень прогонов на $SHA не прочитан — вердикта о зелени нет" >&2
    exit 3
fi
STATUSES=""
if ! STATUSES="$(gh api --paginate "repos/$REPO/commits/$SHA/status?per_page=100" \
        --jq '.statuses[] | select(.state == "success") | .context' 2>/dev/null)"; then
    echo "НЕ ВЫПОЛНИЛОСЬ: перечень отметок на $SHA не прочитан — вердикта о зелени нет" >&2
    exit 3
fi
SUCCEEDED="$(printf '%s\n%s\n' "$RUNS" "$STATUSES")"
SUCC_COUNT="$(printf '%s' "$SUCCEEDED" | grep -c . || true)"

# ── Сверка по ИМЕНАМ, а не по числу ─────────────────────────────────────────
checked=0; findings=()
while IFS= read -r ctx; do
    [ -n "$ctx" ] || continue
    checked=$((checked + 1))
    # Сравнение целой строки БЕЗ внешнего процесса: `grep -q` выходит до конца
    # входа, писатель слева получает SIGPIPE, и под `pipefail` найденное
    # объявляется НЕнайденным — то есть успешный контекст читался бы как
    # неуспешный, и публикация отвергалась бы на зелёном стволе (#658).
    if [[ $'\n'"$SUCCEEDED"$'\n' == *$'\n'"$ctx"$'\n'* ]]; then
        printf '  ✓ %s\n' "$ctx"
    else
        findings+=("$ctx")
        printf '  ✗ %s — успеха на этой ревизии нет (красен, идёт либо не появлялся)\n' "$ctx"
    fi
done <<< "$REQUIRED"

printf '\nперепись: обязательных контекстов %d, успешных на ревизии %d, без успеха %d\n' \
    "$checked" "$SUCC_COUNT" "${#findings[@]}"

if [ "$checked" = "0" ]; then
    echo "обход пуст: не сверено ни одного контекста — вердикт беспредметен" >&2
    exit 3
fi
if [ "${#findings[@]}" -gt 0 ]; then
    printf 'без успеха: %s\n' "${findings[*]}" >&2
    cat >&2 <<'RED'
ВЫПУСК НЕ ОТКРЫТ: не всякая обязательная проверка ствола зелена на этой ревизии.
Тег на такой ревизии обещает то, чего нет, и обещание необратимо.
RED
    exit 1
fi

echo "ствол зелен на этой ревизии по всем обязательным контекстам"
exit 0
