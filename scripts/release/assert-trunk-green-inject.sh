# Инъекция для `scripts/release/assert-trunk-green.sh` — предмет один: ПРЕДПОСЫЛКА
# СВЕРЯЕТ ИМЕНА И РАЗЛИЧАЕТ ЧЕТЫРЕ ИСХОДА, А НЕ СЧИТАЕТ ЗЕЛЁНЫЕ.
#
# ЗАЧЕМ. На исправном стволе предпосылка зелена — и ровно так же зелена
# выродившаяся: та, что читает одну форму перечня из двух, теряет продолжение
# страницы либо принимает пустой перечень обязательных за «претензий нет».
# Отличить их можно только внесённым дефектом.
#
# ПОДСТАВНОЙ ВХОД — ДВА, ПО ЧИСЛУ ИСТОЧНИКОВ ПРЕДМЕТА. Перечень ОБЯЗАТЕЛЬНЫХ
# предмет читает из ОБЪЯВЛЕНИЯ В ДЕРЕВЕ (`.github/required-contexts.txt`, путь
# переопределяется `KACHO_REQUIRED_CONTEXTS_FILE`), а перечень УСПЕШНЫХ — у
# провайдера через `gh` по имени, поэтому достаточно положить `gh` в начало
# PATH. Гоняется НАСТОЯЩИЙ скрипт целиком, меняется РОВНО ОДИН факт — и
# наблюдается исход.
#
# ПОЧЕМУ ОСИ ПРО ЗАЩИТУ ВЕТКИ ЗДЕСЬ БОЛЬШЕ НЕТ. Ручку защиты предмет не читает:
# встроенному токену её не выдают, и запросить право нельзя (`administration`
# площадка отвергает вместе со всем объявлением процесса, kacho#2306). Согласие
# объявления с настоящей защитой — предмет ДРУГОГО гейта
# (`.github/scripts/assert-required-contexts-match-jobs.py`), и доказывается он
# своей самопроверкой. Здесь он не повторяется: два места об одном предмете
# расходятся молча.
#
# ОСИ (у каждой отрицательной есть законный близнец, который обязан молчать):
#   1. все обязательные зелены                     → 0
#   2. один обязательный красен                    → 1, назван поимённо
#   3. один обязательный ИДЁТ (не завершён)        → 1  ← «идёт» ≠ «успех»
#   4. один обязательный НЕ ПОЯВЛЯЛСЯ вовсе        → 1  ← главная ось: ноль проверок
#                                                        читается как «замечаний нет»
#   5. объявление есть, контекстов в нём НОЛЬ      → 1  ← тождественно-истинный вердикт
#   6. объявления НЕТ в дереве                     → 3, НЕ 1  ← «не спрошено» ≠ «ноль»
#   7. перечень прогонов не читается               → 3, НЕ 1
#   8. обязательный пришёл ОТМЕТКОЙ, а не прогоном → 0  ← законный близнец: два источника
#   9. обязательный лежит на ВТОРОЙ странице       → 0  ← законный близнец: продолжение
#  10. в объявлении примечания и пустые строки     → 0  ← законный близнец: разбор формы
#  11. имя с пробелами и знаками читается дословно → 0  ← законный близнец: без обрезки
#  12. объявление приехало с CRLF                  → 0  ← законный близнец: возврат снят
#  13. gh отсутствует                              → 3, НЕ 1
#
# ИСХОДЫ: 0 — все утверждения сошлись; 1 — есть провалившиеся; 2 — предмета нет.
set -uo pipefail

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
      GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_COMMON_DIR GIT_PREFIX

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUBJECT="$HERE/assert-trunk-green.sh"
[ -x "$SUBJECT" ] || { echo "предмета нет либо он неисполняем: $SUBJECT" >&2; exit 2; }

SHA="0123456789abcdef0123456789abcdef01234567"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

passed=0; failed=0; fails=()
pass() { passed=$((passed + 1)); printf '  ✓ %s\n' "$1"; }
fail() { failed=$((failed + 1)); fails+=("$1"); printf '  ✗ %s\n     %s\n' "$1" "${2:-}"; }

# mkgh <каталог> <тело-прогонов> <тело-отметок>
#
# Подставной `gh` отвечает РОВНО на два обращения предмета и на всё прочее
# отказывает: ответ на необъявленный запрос сделал бы фикстуру снисходительнее
# провайдера, и красное приходило бы не оттуда, откуда кажется. Ветки про ручку
# защиты здесь НЕТ намеренно: предмет её не спрашивает, и обращение к ней
# упёрлось бы в отказ фикстуры — то есть попытка вернуть чтение защиты в предмет
# станет видна сразу, а не тихо.
#
# <тело-прогонов>/<тело-отметок>: имена через запятую, либо FAIL, либо NONE.
#
# ЗАПЯТАЯ РАЗВОРАЧИВАЕТСЯ В ПЕРЕВОД СТРОКИ ЗДЕСЬ, А НЕ В ПОДСТАВНОМ. Прежняя
# редакция отдавала `printf '%s\n' ${RUNS//,/ }` — без кавычек, то есть с
# разбиением по ПРОБЕЛУ. Настоящие имена контекстов пробелы несут
# (`build · vet · gofmt · test -race`), поэтому фикстура рвала их на слова и
# оказывалась СТРОЖЕ провайдера: предмет получал находку по живому зелёному, и
# виноватым выглядел он. Фикстура, снисходительнее либо строже настоящего, —
# отдельный класс дефекта, и здесь он был строже.
mkgh() {
    local dir="$1" runs="$2" sts="$3"
    case "$runs" in FAIL|NONE) : ;; *) runs="${runs//,/$'\n'}" ;; esac
    case "$sts"  in FAIL|NONE) : ;; *) sts="${sts//,/$'\n'}" ;; esac
    mkdir -p "$dir"
    {
        printf '%s\n' '#!/usr/bin/env bash'
        printf '%s\n' 'set -uo pipefail'
        printf '%s\n' 'args="$*"'
        printf 'RUNS=%q\n' "$runs"
        printf 'STS=%q\n'  "$sts"
        cat <<'BODY'
case "$args" in
  *"/check-runs"*)
      [ "$RUNS" = FAIL ] && { echo "gh: HTTP 502" >&2; exit 1; }
      [ "$RUNS" = NONE ] && exit 0
      printf '%s\n' "$RUNS"
      exit 0 ;;
  *"/status"*)
      [ "$STS" = FAIL ] && { echo "gh: HTTP 502" >&2; exit 1; }
      [ "$STS" = NONE ] && exit 0
      printf '%s\n' "$STS"
      exit 0 ;;
esac
echo "подставной gh не отвечает на: $args" >&2
exit 64
BODY
    } > "$dir/gh"
    chmod +x "$dir/gh"
}

# mkdecl <файл> <контексты через запятую>
#
# Объявление пишется РОВНО той формой, что читает предмет: одна строка — один
# контекст. Пустая строка контекстов не даёт файла вовсе — она даёт файл без
# контекстов, и это разные состояния (ось 5 против оси 6).
mkdecl() {
    local file="$1" ctxs="$2"
    mkdir -p "$(dirname "$file")"
    : > "$file"
    [ -z "$ctxs" ] && return 0
    local IFS=','
    local c
    for c in $ctxs; do printf '%s\n' "$c" >> "$file"; done
}

# run <каталог-с-gh> <файл-объявления> → RC, OUT
run_subject() {
    OUT="$(PATH="$1:$PATH" KACHO_REQUIRED_CONTEXTS_FILE="$2" "$SUBJECT" "$SHA" 2>&1)"
    RC=$?
}

# assert_rc <имя> <ожидаемый> <полученный> <вывод>
assert_rc() {
    if [ "$2" = "$3" ]; then pass "$1 → $3"
    else fail "$1: ожидался код $2, получен $3" "$(printf '%s' "$4" | tail -6 | tr '\n' '|')"; fi
}

REQ3="alpha,bravo,charlie"

echo "инъекция предпосылки «ствол зелен»: объявление в дереве + подставной провайдер"

# ── 1. Все обязательные зелены ──────────────────────────────────────────────
d="$tmp/a1"; mkgh "$d" "alpha,bravo,charlie" NONE
mkdecl "$tmp/d1" "$REQ3"
run_subject "$d" "$tmp/d1"; assert_rc "все обязательные зелены" 0 "$RC" "$OUT"
if [[ "$OUT" == *"$tmp/d1"* ]]; then pass "объявление, по которому судили, названо"
else fail "предмет обязан называть источник перечня" "$OUT"; fi

# ── 2. Один красен (его нет среди успешных) ─────────────────────────────────
d="$tmp/a2"; mkgh "$d" "alpha,charlie" NONE
run_subject "$d" "$tmp/d1"; assert_rc "обязательный красен" 1 "$RC" "$OUT"
if [[ "$OUT" == *'bravo'* ]]; then pass "красный назван поимённо: bravo"
else fail "находка обязана называть координату" "$OUT"; fi

# ── 3. Идёт, но не завершён ─────────────────────────────────────────────────
# Подставной отдаёт только завершённые успехом (фильтр в самом предмете), поэтому
# идущий контекст в перечень не попадает — ровно как у провайдера.
d="$tmp/a3"; mkgh "$d" "alpha,bravo" NONE
run_subject "$d" "$tmp/d1"; assert_rc "обязательный ещё идёт" 1 "$RC" "$OUT"

# ── 4. Не появлялся ВОВСЕ: проверок на ревизии ноль ─────────────────────────
# ГЛАВНАЯ ОСЬ. Пустая сводка читается как «замечаний нет» — предмет обязан
# ответить находкой, а не тишиной.
d="$tmp/a4"; mkgh "$d" NONE NONE
run_subject "$d" "$tmp/d1"; assert_rc "проверок на ревизии ноль" 1 "$RC" "$OUT"
if [[ "$OUT" == *'без успеха 3'* ]]; then pass "перепись называет 3 без успеха"
else fail "перепись обязана печатать объём осмотренного" "$OUT"; fi

# ── 5. Объявление ЕСТЬ, контекстов в нём ноль ──────────────────────────────
# Файл существует и читается: вопрос ЗАДАН, ответ негоден. Это находка (1).
d="$tmp/a5"; mkgh "$d" NONE NONE
printf '# только примечание, ни одного контекста\n\n' > "$tmp/d5"
run_subject "$d" "$tmp/d5"; assert_rc "объявлено ноль контекстов" 1 "$RC" "$OUT"
if [[ "$OUT" == *'тождественно'* ]]; then pass "названа причина: вердикт тождественно-истинный"
else fail "находка обязана объяснить, чем плох пустой перечень" "$OUT"; fi

# ── 6. Объявления НЕТ в дереве → НЕ ВЫПОЛНИЛОСЬ, а не «ноль контекстов» ─────
# ГЛАВНОЕ РАЗЛИЧЕНИЕ ЭТОГО ИЗМЕНЕНИЯ. Файла нет — вопрос НЕ ЗАДАН (3). Слить его
# с осью 5 значило бы выдать сбой чтения за объявленное отсутствие защиты, а
# «не спрошено» в вердикт не вычитается.
d="$tmp/a6"; mkgh "$d" "alpha,bravo,charlie" NONE
run_subject "$d" "$tmp/decl-net"; assert_rc "объявления нет в дереве" 3 "$RC" "$OUT"
if [[ "$OUT" == *'не прочитано'* ]]; then pass "сказано, что перечень не прочитан"
else fail "третий исход обязан назвать причину" "$OUT"; fi
if [[ "$OUT" == *"$tmp/decl-net"* ]]; then pass "назван путь, которого не хватило"
else fail "третий исход обязан назвать координату" "$OUT"; fi

# ── 7. Прогоны не читаются → НЕ ВЫПОЛНИЛОСЬ, а не «ствол красен» ───────────
d="$tmp/a7"; mkgh "$d" FAIL NONE
run_subject "$d" "$tmp/d1"; assert_rc "прогоны не прочитаны" 3 "$RC" "$OUT"

# ── 8. Законный близнец: обязательный пришёл ОТМЕТКОЙ ──────────────────────
d="$tmp/a8"; mkgh "$d" "alpha,bravo" "charlie"
run_subject "$d" "$tmp/d1"; assert_rc "близнец: контекст пришёл отметкой" 0 "$RC" "$OUT"

# ── 9. Законный близнец: продолжение страницы ──────────────────────────────
# `--paginate` склеивает страницы, поэтому подставной отдаёт всё разом — и это
# честная модель: предмет обязан читать ВЕСЬ вывод, а не первую строку.
d="$tmp/a9"; mkgh "$d" "zulu,yankee,xray,whiskey,alpha,bravo,charlie" NONE
run_subject "$d" "$tmp/d1"; assert_rc "близнец: контекст на продолжении" 0 "$RC" "$OUT"

# ── 10. Законный близнец: примечания и пустые строки — не контексты ─────────
# Отрицательный контроль оси стоит рядом: если бы разбор принимал примечание за
# контекст, обязательных стало бы больше трёх и примечание ушло бы в находки.
d="$tmp/a10"; mkgh "$d" "alpha,bravo,charlie" NONE
{ printf '# примечание в первой позиции\n'
  printf '\n'
  printf 'alpha\n'
  printf '   \n'
  printf 'bravo\n'
  printf '# ещё примечание\n'
  printf 'charlie\n'; } > "$tmp/d10"
run_subject "$d" "$tmp/d10"; assert_rc "близнец: примечания не читаются контекстами" 0 "$RC" "$OUT"
if [[ "$OUT" == *'обязательных контекстов 3'* ]]; then pass "перепись насчитала ровно 3 контекста"
else fail "разбор формы обязан отбросить примечания и пустые строки" "$OUT"; fi

# ── 11. Законный близнец: имя читается ДОСЛОВНО, без обрезки ────────────────
# Настоящие имена несут пробелы, точки-разделители, скобки, кириллицу и знак
# многоточия у обрезанных площадкой. Обрезка строки по краям или разбиение по
# пробелу дали бы находку по живому зелёному.
FANCY='build · vet · gofmt · test -race'
TRUNCATED='Postgres-пробы вне отбора интеграционной джобы (пропуск =...'
d="$tmp/a11"; mkgh "$d" "$FANCY,$TRUNCATED" NONE
{ printf '%s\n' "$FANCY"; printf '%s\n' "$TRUNCATED"; } > "$tmp/d11"
run_subject "$d" "$tmp/d11"; assert_rc "близнец: имя с пробелами и знаками" 0 "$RC" "$OUT"

# ── 12. Законный близнец: объявление приехало с CRLF ───────────────────────
# Возврат каретки в конце строки сделал бы имя не равным ни одному
# произведённому — то есть находку по живому зелёному. Что фикстура не
# выродилась, видно по оси 2: недостающее имя там даёт именно 1.
d="$tmp/a12"; mkgh "$d" "alpha,bravo,charlie" NONE
printf 'alpha\r\nbravo\r\ncharlie\r\n' > "$tmp/d12"
run_subject "$d" "$tmp/d12"; assert_rc "близнец: объявление с CRLF" 0 "$RC" "$OUT"

# ── 13. gh отсутствует → НЕ ВЫПОЛНИЛОСЬ ────────────────────────────────────
# PATH сужается до каталога, где лежит РОВНО то, чем предмет пользуется, и нет
# `gh`. Пустой PATH не годится: не находится даже толкователь из строки запуска,
# и ось давала бы 127 — отказ фикстуры, выданный за исход предмета.
#
# У фикстуры ЕСТЬ СВОЙ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: прежде запуска утверждается, что
# под этим PATH `gh` действительно не находится. Без него ось молча выродилась бы
# в первую (всё на месте) на всякой машине, где `gh` лежит в /usr/bin.
d="$tmp/a13"; mkdir -p "$d"
for t in bash grep cat; do
    src="$(command -v "$t" 2>/dev/null)" || { echo "инструмента нет: $t" >&2; exit 2; }
    ln -sf "$src" "$d/$t"
done
if PATH="$d" command -v gh >/dev/null 2>&1; then
    fail "фикстура оси «gh отсутствует» негодна" "под сужённым PATH gh всё ещё находится"
else
    pass "фикстура: под сужённым PATH gh не находится (контроль оси)"
    OUT="$(PATH="$d" KACHO_REQUIRED_CONTEXTS_FILE="$tmp/d1" "$SUBJECT" "$SHA" 2>&1)"; RC=$?
    assert_rc "gh отсутствует" 3 "$RC" "$OUT"
fi

# ── 14. Предмет БОЛЬШЕ НЕ СПРАШИВАЕТ ручку защиты ──────────────────────────
# Ось про сам перевод на объявление. Утверждается прямо, чтобы возврат чтения
# защиты не прошёл молча: ветки на эту ручку у подставного нет, и такое
# обращение упёрлось бы в отказ фикстуры уже на первой оси.
#
# СУДИТСЯ ИСПОЛНЯЕМАЯ ЧАСТЬ, А НЕ ТЕКСТ. Первая редакция этой оси искала образец
# по сырому файлу — и нашла его в ПРИМЕЧАНИИ, которое объясняет, почему ручка
# защиты и не читается. Проверка краснела на собственном объяснении. Поэтому
# строки-примечания снимаются, и у самого съёмника есть положительный контроль:
# на синтетической исполняемой строке образец обязан находиться, иначе ось
# зеленела бы при любом предмете.
# ВЕРДИКТ НЕ БЕРЁТСЯ ИЗ ТРУБЫ. `… | grep -q` выходит до конца входа, писатель
# слева получает SIGPIPE, и под `pipefail` НАЙДЕННОЕ объявляется ненайденным —
# то есть ось молчала бы ровно тогда, когда предмет нарушен (#658). Съём
# примечаний идёт в переменную, а сравнение делает сама оболочка.
strip_comments() { grep -v '^[[:space:]]*#' "$1"; }

probe="$tmp/детектор-контроль"
printf '%s\n' 'gh api "repos/$REPO/branches/$TRUNK/protection" --jq .x' > "$probe"
probe_body="$(strip_comments "$probe")"
if [[ "$probe_body" =~ branches/.*/protection ]]; then
    pass "контроль детектора: на исполняемой строке образец находится"
else
    fail "детектор оси негоден" "образец не найден там, где он заведомо есть"
fi

subject_body="$(strip_comments "$SUBJECT")"
if [[ "$subject_body" =~ branches/.*/protection ]]; then
    fail "предмет всё ещё читает ручку защиты" "встроенному токену её не выдают"
else
    pass "предмет не обращается к ручке защиты ветки (судится исполняемая часть)"
fi
if grep -q 'required-contexts' "$SUBJECT"; then
    pass "предмет назвал объявление, из которого читает перечень"
else
    fail "предмет обязан назвать источник перечня" "ни одного упоминания объявления"
fi

# ── Итог ───────────────────────────────────────────────────────────────────
printf '\nперепись: утверждений %d, провалено %d\n' "$((passed + failed))" "$failed"
if [ "$((passed + failed))" = "0" ]; then
    echo "обход пуст: не проверено ни одного утверждения" >&2; exit 2
fi
if [ "$failed" -gt 0 ]; then
    printf 'провалены: %s\n' "${fails[*]}" >&2
    echo "предпосылка «ствол зелен» не доказана" >&2
    exit 1
fi
echo "предпосылка различает четыре исхода и сверяет имена"
exit 0
