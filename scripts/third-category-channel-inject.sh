# third-category-channel-inject.sh — третья категория ДОЕЗЖАЕТ до сводного
# вердикта, доказано исполнением НАСТОЯЩЕЙ связки.
#
# ПРЕДМЕТ (#958)
#
# Механизм различения у работ есть и работает: они узнают «условие не создано» и
# называют его. Умирала категория на ГРАНИЦЕ: до сводного вердикта доезжает
# только заключение check-run, и третья категория приходила неотличимой от
# настоящего красного. Читающий не мог отличить «продукт сломан» от «стенд не
# поднялся», а лечатся они противоположным.
#
# ЧТО ЗДЕСЬ ПРОГОНЯЕТСЯ. Настоящий `pr-verdict-wait.sh` и настоящий
# `pr-verdict.py`. Подменяются ровно два ВНЕШНИХ факта — ответ провайдера о
# наборе проверок и его же ответ об аннотациях одной проверки. Ни сам разбор, ни
# решение, ни печать не подменяются: пробе, подставляющей решателя, доказывать
# было бы нечего.
#
# ПОЧЕМУ ПРОБА ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ СЛУЧАЕМ В pr_verdict_test.py. Там живёт
# доказательство РЕШЕНИЯ (чистая функция `decide`), и оно уже есть. Здесь —
# доказательство КАНАЛА: что имя третьей категории собирается из аннотаций,
# доезжает до решателя и печатается отдельной строкой. Это разные предметы, и
# первый зеленел бы при полностью оборванном втором.
#
# Коды возврата: 0 — всё сошлось; 1 — расхождение (перечислено); 2 — проба НЕ
# ВЫПОЛНЕНА (нет python3).

set -uo pipefail

PASS=0
FAIL=0
say() { printf '\n── %s\n' "$*"; }
ok()  { PASS=$((PASS + 1)); echo "  ОК  $*"; }
bad() { FAIL=$((FAIL + 1)); echo "  ПРОВАЛ $*"; }

command -v python3 > /dev/null || {
    echo "ОТКАЗ: нет python3 — решатель на нём; проба НЕ ВЫПОЛНЕНА" >&2
    exit 2
}

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WAIT="$ROOT/.github/scripts/pr-verdict-wait.sh"
[ -x "$WAIT" ] || [ -f "$WAIT" ] || {
    echo "ОТКАЗ: нет $WAIT — доказывать нечего; проба НЕ ВЫПОЛНЕНА" >&2
    exit 2
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ── ПОДСТАВНОЙ ПРОВАЙДЕР ────────────────────────────────────────────────────
# Отдаёт ровно то, что отдаёт настоящий: объект с `total_count` и `check_runs`,
# а на запрос аннотаций — список с заголовком и текстом.
make_fetch() { # <json набора>
    printf '%s' "$1" > "$WORK/runs-payload.json"
    cat > "$WORK/fetch.sh" <<'F'
#!/usr/bin/env bash
cat "$WORK_DIR/runs-payload.json"
F
    chmod +x "$WORK/fetch.sh"
}
make_annotations() { # <json аннотаций>
    printf '%s' "$1" > "$WORK/ann-payload.json"
    cat > "$WORK/ann.sh" <<'A'
#!/usr/bin/env bash
# Аннотации спрашиваются по идентификатору проверки; подставной отвечает одним и
# тем же телом — предмет пробы в том, ЧИТАЕТСЯ ли заголовок, а не в маршрутизации.
cat "$WORK_DIR/ann-payload.json"
A
    chmod +x "$WORK/ann.sh"
}

run_wait() {
    ( cd "$WORK" && \
      REPO="p/r" SHA="deadbeef" SELF="сводный вердикт" \
      VERDICT_ATTEMPTS=1 VERDICT_INTERVAL=0 \
      WORK_DIR="$WORK" \
      VERDICT_FETCH_CMD="$WORK/fetch.sh" \
      VERDICT_ANNOTATIONS_CMD="$WORK/ann.sh" \
      bash "$WAIT" ) > "$WORK/out.txt" 2>&1
    echo $?
}

RUNS_ONE_FAIL='{"total_count":2,"check_runs":[
  {"id":1,"name":"юниты","status":"completed","conclusion":"success"},
  {"id":2,"name":"сквозные пробы консоли","status":"completed","conclusion":"failure"}]}'
RUNS_ALL_GREEN='{"total_count":1,"check_runs":[
  {"id":1,"name":"юниты","status":"completed","conclusion":"success"}]}'

ANN_UNMET='{"annotations":[{"title":"НЕ ВЫПОЛНИЛОСЬ (условие не создано)","message":"стенд не поднялся"}]}'
ANN_PLAIN='{"annotations":[{"title":"Проба упала","message":"ожидали 200, получили 500"}]}'

# ── (1) ТРЕТЬЯ КАТЕГОРИЯ ОБЪЯВЛЕНА → ПЕЧАТАЕТСЯ ОТДЕЛЬНО, ЦВЕТ ПРЕЖНИЙ ──────
say "работа объявила «не выполнилось» аннотацией"
make_fetch "$RUNS_ONE_FAIL"
make_annotations "$ANN_UNMET"
rc="$(run_wait)"
[ "$rc" = "1" ] && ok "вердикт по-прежнему блокирует (код 1) — цвет не меняется" \
                || bad "код $rc, ждали 1"
grep -qF '«не выполнилось» (условие не создано): 1' "$WORK/out.txt" \
    && ok "третья категория напечатана ОТДЕЛЬНОЙ строкой с числом" \
    || { bad "отдельной строки с числом нет"; sed 's/^/     | /' "$WORK/out.txt"; }
grep -qF 'разбирать условие, а не дерево' "$WORK/out.txt" \
    && ok "перечень назван и сказано, что разбирать" \
    || bad "перечня третьей категории нет"
grep -qF 'красные (вердикт о продукте вынесен' "$WORK/out.txt" \
    && bad "настоящих красных нет, а заголовок про них напечатан" \
    || ok "заголовка «красные» нет: настоящих красных в этом наборе не было"

# ── (2) ЗАКОННЫЙ БЛИЗНЕЦ: ТОТ ЖЕ ОТКАЗ БЕЗ ОБЪЯВЛЕНИЯ → ПРЕЖНЕЕ КРАСНОЕ ────
# Без этой половины канал «объявлял» бы третью категорию по любому отказу, то
# есть снимал бы разбор с каждого красного прогона.
say "тот же отказ, но третья категория НЕ объявлена"
make_annotations "$ANN_PLAIN"
rc="$(run_wait)"
[ "$rc" = "1" ] && ok "вердикт блокирует (код 1)" || bad "код $rc, ждали 1"
grep -qF '«не выполнилось» (условие не создано): 0' "$WORK/out.txt" \
    && ok "третья категория — ноль: отказ остался настоящим красным" \
    || { bad "ноль третьей категории не напечатан"; sed 's/^/     | /' "$WORK/out.txt"; }
grep -qF 'сквозные пробы консоли' "$WORK/out.txt" \
    && ok "имя названо среди красных" || bad "имя не названо"

# ── (3) КАНАЛ НЕДОСТУПЕН → ПРЕЖНЕЕ ПОВЕДЕНИЕ, А НЕ ПРОЩЕНИЕ ────────────────
say "опрос аннотаций отказал"
cat > "$WORK/ann.sh" <<'A'
#!/usr/bin/env bash
echo "boom" >&2
exit 1
A
chmod +x "$WORK/ann.sh"
rc="$(run_wait)"
[ "$rc" = "1" ] && ok "вердикт блокирует (код 1)" || bad "код $rc, ждали 1"
grep -qF '«не выполнилось» (условие не создано): 0' "$WORK/out.txt" \
    && ok "неизвестное осталось красным, а не прощённым" \
    || bad "недоступный канал изменил вердикт"

# ── (4) ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: ВСЁ ЗЕЛЕНО ─────────────────────────────────
# Без него все проверки выше зеленели бы на связке, которая всегда красная.
say "все проверки зелены"
make_fetch "$RUNS_ALL_GREEN"
make_annotations "$ANN_UNMET"
rc="$(run_wait)"
[ "$rc" = "0" ] && ok "вердикт зелёный (код 0)" \
                || { bad "код $rc, ждали 0"; sed 's/^/     | /' "$WORK/out.txt"; }

printf '\nосмотрено случаев 4; годно %d, беда %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
echo "третья категория доезжает до сводного вердикта и печатается отдельной строкой"
exit 0
