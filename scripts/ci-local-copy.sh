# ci-local-copy.sh — КОПИЯ `scripts/ci-local.sh` ДЛЯ ПРОБЫ, одним определением на
# все пробы прогонщика. Файл СОРСИТСЯ, не запускается.
#
# ЗАЧЕМ ОДНО ОПРЕДЕЛЕНИЕ. Пробы прогонщика судят настоящий код, а не его пересказ:
# у копии подменён только блок выбора группы (от `case "$GROUP" in` до `esac` в
# нулевой колонке) — на синтетическую группу `synth`, которая сорсит сценарий
# `$CI_LOCAL_SYNTH_FILE`. Всё остальное берётся ДОСЛОВНО. Две пробы с двумя
# копиями этого способа разошлись бы молча ровно там, где расхождение не видно:
# обе продолжили бы копировать, а судили бы разное.
#
# Использование:
#   CI_LOCAL_SUBJECT=<путь к ci-local.sh>
#   . "$(dirname "$0")/ci-local-copy.sh"
#   ci_local_copy <куда> [sed-выражение дефекта] [эталонная копия]
#
# Дефект ОБЯЗАН быть воссоздан, а не «применён»: `sed`, ничего не нашедший,
# выходит успехом, и тогда «дефектная» копия побайтово равна эталонной — проба
# краснела бы на обеих одинаково и ничего бы не доказывала. Не воссоздан — код 2
# («условие не создано»): форма кода изменилась, и проба обязана это сказать.
ci_local_copy() { # ci_local_copy <куда> [sed-выражение дефекта] [эталонная копия]
    local dest="$1" defect="${2:-}" real="${3:-}"
    [ -r "${CI_LOCAL_SUBJECT:-}" ] || { echo "предмета нет: ${CI_LOCAL_SUBJECT:-не задан}" >&2; exit 2; }
    mkdir -p "$(dirname "$dest")" || exit 2
    awk '
        /^case "\$GROUP" in$/ { skip = 1 }
        skip && /^esac$/      { skip = 0
                                print "case \"$GROUP\" in"
                                print "    synth) . \"$CI_LOCAL_SYNTH_FILE\" ;;"
                                print "    *) echo \"копия принимает только группу synth\" >&2; exit 2 ;;"
                                print "esac"
                                next }
        !skip { print }
    ' "$CI_LOCAL_SUBJECT" > "$dest"
    grep -q 'CI_LOCAL_SYNTH_FILE' "$dest" || {
        echo "подмена блока выбора группы не сработала — форма выбора группы изменилась" >&2; exit 2; }
    # Перевод обрыва errexit (#2831) — рядом с прогонщиком, как в дереве: без него
    # копия читала бы двойку любого доказательства отказом, и проба судила бы
    # не ту редакцию.
    cp "$(dirname "$CI_LOCAL_SUBJECT")/proof-errexit-env.sh" "$(dirname "$dest")/" || {
        echo "перевода errexit рядом с прогонщиком нет — копия была бы не той редакцией" >&2; exit 2; }
    if [ -n "$defect" ]; then
        sed -i "$defect" "$dest"
        [ -n "$real" ] || { echo "дефект без эталона: сверять воссоздание не с чем" >&2; exit 2; }
        cmp -s "$dest" "$real" && {
            echo "дефект не воссоздан: копия $dest равна эталонной — форма кода изменилась" >&2
            exit 2; }
    fi
    chmod +x "$dest"
}
