# ХРЕБЕТ ГЕНЕРАТОРА (#1379): форма коллекции — одна на дерево.
#
# ПРЕДМЕТ. Форму коллекции решали `build_collection`, `case_to_postman` и
# `step_to_postman` — по восемь версий на восемь наборов. Пока их восемь, новый
# вид шага стоит восьми правок, то есть ровно того числа, которое просили
# уменьшить.
#
# ЧТО СВЕДЕНО И ЧТО ОСТАЛОСЬ РЕШЕНИЕМ НАБОРА. Разбор восьми копий показал, что
# расходились они НЕ формой коллекции — она у всех одна, вплоть до порядка
# ключей, — а десятком точечных решений: под каким адресом живёт шаг, какие
# преобразования проходит перечень шагов кейса, что дописывается в пред-скрипт.
# Каждое такое решение названо полем `Emit` и объявляется НАБОРОМ в одном месте,
# вместо того чтобы жить копией тела функции.
#
# ПОЧЕМУ ИМЕННО ТАК, А НЕ «ОДНА ФУНКЦИЯ НА ВСЕХ». Модель кейса (`Case`/`Step`) у
# наборов СВОЯ и остаётся своей: у края шаг несёт трёхзначный выбор слушателя, у
# geo/compute/storage/vpc — двузначный признак, у iam/nlb/registry такого поля
# нет вовсе. Свести это к одному полю значило бы объявить, что решение принято,
# — а его никто не принимал. Общий слой обращается к шагу ПО УТИНОМУ и адрес
# спрашивает у набора.
# ═════════════════════════════════════════════════════════════════════════════

@dataclass
class Emit:
    """Решения набора, от которых зависит форма порождаемой коллекции.

    Поле здесь заводится ТОЛЬКО под расхождение, которое ДЕЙСТВИТЕЛЬНО есть в
    дереве: ручка «на будущее» — то же обещание без держателя, что и мёртвый
    код. Каждое поле ниже названо тем набором, который им пользуется.
    """

    # Вход UUIDv5 для `_postman_id`. Идентификатор ДЕТЕРМИНИРОВАН: случайный
    # делал грязной каждую перегенерацию, и «порождённое совпадает с исходником»
    # нельзя было проверить вовсе, а настоящему расхождению негде было показаться.
    id_slug: str
    # Видимое имя коллекции. У края оно НЕ совпадает со слагом идентификатора
    # (`kacho-gateway` против `kacho-api-gateway`) — расхождение историческое, и
    # сведение его не трогает: смена слага перечеканила бы все идентификаторы.
    display_name: str
    # Пред-скрипт уровня коллекции. Функция, а не список: vpc выбирает его по
    # имени коллекции (часть наборов идёт под администратором по умолчанию).
    pre_global: "Callable[[str], List[str]]"
    # Конвейер шагов кейса — ЗДЕСЬ живёт главное различие наборов, и оно
    # осознанное: какие преобразования применяются и в каком порядке.
    steps_of: "Callable[[object], list]"
    # Пред-скрипт смены предъявителя. Своя у каждого набора: перечень
    # предъявителей — свойство набора, а не формы коллекции.
    auth_pre: "Callable[[Optional[str]], List[str]]"
    # Имя переменной адреса по шагу. Умолчание — единственный публичный адрес.
    host_var: "Callable[[object], str]" = lambda step: "baseUrl"
    # Событие уровня коллекции на исход (iam).
    post_global: "Optional[List[str]]" = None
    # Элементы, идущие ПЕРЕД кейсами (vpc: резолв зон, посев пулов, якорь).
    prefix_items: "Optional[Callable[[str], list]]" = None
    # Дописывается в НАЧАЛО пред-скрипта шага (край: страж переменной адреса,
    # объявленной, но не заданной профилем).
    pre_head: "Optional[Callable[[object, str], List[str]]]" = None
    # Дописывается в КОНЕЦ пред-скрипта шага (iam: страж подстановки — он обязан
    # идти последним, после всех законных производителей адреса, включая сам шаг).
    pre_tail: "tuple" = ()
    # Правка элемента по свойству шага (iam/registry: ослабленная проверка
    # сертификата у шага, который ходит к внешнему предъявителю).
    item_hook: "Optional[Callable[[object, dict], None]]" = None
    # Разбор пути на сегменты. Умолчание общее; край отрезает строку запроса.
    path_segments: "Optional[Callable[[str], List[str]]]" = None


def _default_path_segments(path: str) -> List[str]:
    return [p for p in path.strip("/").split("/") if p]


def step_to_postman(emit: "Emit", step) -> Dict:
    """Один шаг кейса — в элемент коллекции.

    Тело ниже во всех восьми копиях совпадало ДОСЛОВНО, включая порядок ключей;
    расходились только точки, вынесенные в `Emit`.
    """
    var = emit.host_var(step)
    host = "{{" + var + "}}"
    segments = (emit.path_segments or _default_path_segments)(step.path)
    item: Dict = {
        "name": step.name,
        "request": {
            "method": step.method,
            "header": [{"key": "Content-Type", "value": "application/json"}],
            "url": {
                "raw": host + step.path,
                "host": [host],
                "path": segments,
            },
        },
    }
    if emit.item_hook is not None:
        emit.item_hook(step, item)
    if step.body is not None:
        item["request"]["body"] = {
            "mode": "raw",
            "raw": json.dumps(step.body, ensure_ascii=False),
            "options": {"raw": {"language": "json"}},
        }
    pre = list(step.pre_script)
    if emit.pre_head is not None:
        pre = emit.pre_head(step, var) + pre
    if step.auth is not None:
        pre = emit.auth_pre(step.auth) + pre
    pre = pre + list(emit.pre_tail)
    events = []
    if pre:
        events.append({"listen": "prerequest", "script": {"type": "text/javascript", "exec": pre}})
    # Шаг удаления без собственного утверждения получает утверждение по умолчанию
    # (см. `_DELETE_ACCEPTED` выше). Ставится в КОНЕЦ — после обёртки ожидания.
    test_exec = list(step.test_script)
    if step.method == "DELETE" and not _carries_assertion(test_exec):
        test_exec = test_exec + _DELETE_ACCEPTED
    if test_exec:
        events.append({"listen": "test", "script": {"type": "text/javascript", "exec": test_exec}})
    if events:
        item["event"] = events
    return item


def case_to_postman(emit: "Emit", case) -> Dict:
    """Один кейс — в папку коллекции.

    Расхождение всех восьми копий было ровно в ОДНОМ: какие преобразования
    проходит перечень шагов. Оно осознанное (у наборов разные конвейеры) и
    названо полем `steps_of`, а не спрятано в восьми телах.
    """
    tags = [f"class:{c}" for c in case.classes] + [f"priority:{case.priority}"]
    return {
        "name": f"{case.id} — {case.title}",
        "description": " | ".join(tags),
        "item": [step_to_postman(emit, s) for s in emit.steps_of(case)],
    }


def build_collection(emit: "Emit", key: str, cases: list) -> Dict:
    """Перечень кейсов — в коллекцию."""
    events = [
        {"listen": "prerequest", "script": {"type": "text/javascript", "exec": emit.pre_global(key)}},
    ]
    if emit.post_global is not None:
        events.append({"listen": "test", "script": {"type": "text/javascript", "exec": emit.post_global}})
    prefix = emit.prefix_items(key) if emit.prefix_items is not None else []
    return {
        "info": {
            "_postman_id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{emit.id_slug}/newman/{key}")),
            "name": f"{emit.display_name} / {key}",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "event": events,
        "item": prefix + [case_to_postman(emit, c) for c in cases],
        "variable": [],
    }


def load_cases_module(path, injected: Dict, before=None, stem_dashes_to_underscores: bool = True):
    """Загрузить модуль кейсов, впрыснув в его пространство имён помощники набора.

    ПЕРЕЧЕНЬ ВПРЫСКИВАЕМОГО — СЛОВАРЬ, А НЕ СТРОКИ `mod.X = X`. Семь наборов
    выписывали его руками, по строке на имя: перечень из сорока пяти строк,
    который обязан меняться вслед за помощниками и который ни на что не влияет,
    пока имя не понадобилось кейсу. Именно там и накапливался впрыск имён,
    снятых из генератора: строка переживала свой предмет молча.
    """
    if before is not None:
        before()
    stem = path.stem.replace("-", "_") if stem_dashes_to_underscores else path.stem
    spec = importlib.util.spec_from_file_location(stem, path)
    mod = importlib.util.module_from_spec(spec)
    for name, value in injected.items():
        setattr(mod, name, value)
    spec.loader.exec_module(mod)
    return mod


def http_method_not_allowed_block(case_cls, step_cls, prefix: str, base_path: str) -> list:
    """HTTP-глаголы, которых у списочного адреса нет: PUT и DELETE без id.

    ПРИНЯТА ВЕРСИЯ БОЛЬШИНСТВА (две копии против одной) — и она же строго лучше.
    Порождаемые утверждения у обеих ПОБАЙТОВО одни; расходились ЗАГОЛОВКИ, и
    заголовок меньшинства («→ 405 или 404») противоречил собственному
    утверждению шага, принимающему ещё 403 и 501. Заголовок кейса доезжает до
    коллекции именем папки — то есть читатель отчёта видел обещание, которого
    проба не проверяла.

    403 в перечне — не послабление, а задокументированная полоса: край решает
    доступ ДО маршрутизации глагола, поэтому отказ по правам приходит раньше
    отказа по методу (`testing.md` §e2e-инварианты, «authz-first толерантность»).
    Все четыре кода означают «глагол не выполнен», и отрицание сохраняется.
    """
    check = ("pm.test('not allowed (403/404/405/501)', "
             "() => pm.expect(pm.response.code).to.be.oneOf([403, 404, 405, 501]));")
    return [
        case_cls(
            id=f"{prefix}-METHOD-PUT-NOT-ALLOWED",
            title="PUT on List endpoint → 403/404/405/501",
            classes=["VAL", "NEG"], priority="P3",
            steps=[step_cls(name="put-list", method="PUT", path=base_path,
                            body={"projectId": "{{_suiteProjectId}}"},
                            test_script=[check])],
        ),
        case_cls(
            id=f"{prefix}-METHOD-DELETE-LIST",
            title="DELETE on List endpoint (no id) → 403/404/405/501",
            classes=["VAL", "NEG"], priority="P3",
            steps=[step_cls(name="del-list", method="DELETE", path=base_path,
                            test_script=[check])],
        ),
    ]

# Утверждение по умолчанию для шага удаления — ПОБАЙТОВО совпадало во всех
# восьми копиях. Читает его только `step_to_postman`, поэтому константа
# переезжает вместе с ним.
# Утверждение о том, что удаление ПРИНЯТО. Ровно одно и однозначное: `oneOf`
# со взаимоисключающими исходами утверждением не является (testing.md).
_DELETE_ACCEPTED = [
    "// УТВЕРЖДЕНИЕ ПО УМОЛЧАНИЮ для шага удаления: без него шаг зеленел бы и на",
    "// отказе, а следующий опрос уехал бы на opId предыдущей операции.",
    "pm.test('delete accepted: status 200', () => "
    "pm.expect(pm.response.code, pm.response.text()).to.eql(200));",
]


def retry_until_authorized(step, budget: int, interval_ms: int,
                           retry_on=(403, 404), lane_head=False, ledger=None):
    """ОКНО ЗАДАЁТ НАБОР, ТЕЛО — ОБЩЕЕ (#1379).

    Шесть копий этой функции расходились по ТРЁМ осям, и только одна из них была
    расхождением по существу:

      * ВЕЛИЧИНА ОКНА (40×600, 25×500, 15×400, 80×600 мс) — решение набора: путь
        материализации у доменов разный, и подгонять их под одно число значило бы
        решить за них. Поэтому окно здесь — ОБЯЗАТЕЛЬНЫЙ аргумент без умолчания:
        умолчание в общем слое молча стало бы решением за всех;
      * ДВЕ ДОБАВКИ (`lane_head`, `ledger`) — их несёт по одному набору.
        Названы полями, а не спрятаны в двух копиях тела. Обе — кандидаты в
        общее: `lane_head` заведён отдельной задачей (#1477), потому что его
        раздача МЕНЯЕТ ПОВЕДЕНИЕ пяти наборов и требует своего вердикта, а не
        едет попутным грузом сведения;
      * ШАПКИ — расходились текстом, и три из шести называли ЧУЖИЕ величины
        («default 15*400ms ≈ 6s» при подписи 40×600). Читатель планировал окно
        вдвое-вчетверо меньше действительного. Поэтому величина здесь НЕ
        называется прозой вовсе: она приходит аргументом и видна на вызове.

    Wrap the FIRST access of the caller's OWN just-created resource in a bounded
    read-your-writes retry over the owner-tuple materialization window.

    opgate (the create confirm-gate) was removed by design-review: Operation.done now
    means the resource is DURABLE, but its owner/creator FGA tuple materializes
    eventually-consistent (at-least-once drainer + reconciler + sync-registrar
    optimisation). Under load the first post-create Get/Update/Delete of the fresh
    resource can briefly return 403 (PERMISSION_DENIED) or 404 at the authz gate
    before the tuple is visible. This is a textbook read-your-writes lag -> the CLIENT
    retries; it is NOT a server barrier.

    Retries the SAME request (setNextRequest -> self) while the response code is in
    `retry_on` (default 403/404), spacing attempts by ~interval_ms (busy-wait -- newman
    fires setNextRequest before any setTimeout). budget*interval_ms bounds the wait
    (default 15*400ms = ~6s) -- fail-closed: on any other code the wrapped step's real
    test_script runs exactly once, and once the budget is spent it ALSO runs on the
    terminal 403/404 (a genuine, non-converging deny still FAILS the real assertions --
    never masked, never infinite).

    Use ONLY on the first access of the caller's OWN fresh resource. Do NOT wrap
    negative / cross-account-deny / absent-id steps (a poll there would mask a real
    deny). The counter/started env-vars are request-name-scoped (step names are
    globally unique after serialization) so the loop never bleeds across cases or
    steps -- same discipline as poll_operation_until_done.

    ГРАНИЦА, КОТОРУЮ ЭТА ОБЁРТКА НЕ ПЕРЕХОДИТ (issue #351). Решение о повторе
    принимается по КОДУ ОТВЕТА шага, поэтому закрыта ровно одна полоса — СИНХРОННЫЙ
    отказ этого запроса (шлюз не разрешил цель проверки прав → 403; чтение скрытого
    ресурса → 404). У АСИНХРОННОЙ мутации отказ ВЛАДЕЛЬЦА чужого ресурса приезжает
    иначе: шаг отвечает `200` и конвертом `Operation`, а отказ лежит терминальной
    ошибкой ВНУТРИ операции и читается уже другим шагом — сюда он не попадает НИКОГДА.
    Обёртка на таком шаге не инертна (полосу шлюза она по-прежнему закрывает), но
    читать её как «окно видимости здесь закрыто» — ошибка: чужой свежий идентификатор
    обязан быть либо ПРОЧИТАН до мутации (`retry_until_authorized(GET <владелец>/<id>)`
    — форма, посаженная PR #350), либо прикрыт повтором по ИСХОДУ операции
    (`poll_operation_until_done(retry_from=…)`). Свойство держит по всему дереву гейт
    `internal/repohygiene/artifactgates`
    `TestAsyncMutationDoesNotCarryAnUnwarmedPeerId`.
    """
    # Полоса, по которой приходит окно видимости, задаётся МЕТОДОМ, а не вкусом
    # автора: у мутации отказ виден как 403, а у ЧТЕНИЯ он спрятан под 404
    # (hide-existence: текст отказа побайтово равен настоящему «не найдено», см.
    # `security.md`). Поэтому рукописное `retry_on=(403,)` на GET — обёртка,
    # которая не может сработать на том коде, который она увидит: форма есть,
    # содержания нет. Такое место в дереве нашлось (vpc1 `get-no-dhcp`: 404 на
    # первом же обращении, ретрай не сработал ни разу, шаг упал). Чинится по
    # построению здесь, а не перечнем в кейсах; 404, названный шагом законным
    # исходом, в retry_on не попадает вовсе — его отсекает вызывающий.
    # Ожидание НИКОГДА не включает код, который шаг сам объявил приемлемым
    # исходом: иначе проба пережидала бы ровно то, ради чего написана, и жгла бы
    # бюджет на успехе. Нормализация здесь, а не у вызывающих: рукописные
    # обёртки этого не делали (5 мест в дереве ждали заявленный ими же 404).
    _acc = _accepted_http_codes("\n".join(step.test_script))
    retry_on = tuple(c for c in retry_on if c not in _acc)
    if step.method == "GET" and 404 not in retry_on and 404 not in _acc:
        retry_on = tuple(retry_on) + (404,)
    # То же и у УДАЛЕНИЯ, и по той же причине — только код приходит не из
    # hide-existence чтения, а из утверждения по умолчанию: шаг удаления без
    # собственного утверждения получит при сериализации `delete accepted: status 200`
    # (_DELETE_ACCEPTED), и 404 для него — падение, а не законное «уже нет».
    # Держим это ЗДЕСЬ, а не у вызывающих: рукописное `retry_on=(403,)` на таком шаге
    # даёт обёртку, которая не ждёт единственный код, на котором шаг упадёт, — форма
    # ожидания есть, содержания нет. 404, названный шагом законным исходом, сюда
    # по-прежнему не попадает: его отсекает `_acc`.
    if (step.method == "DELETE" and not _carries_assertion(list(step.test_script))
            and 404 not in retry_on and 404 not in _acc):
        retry_on = tuple(retry_on) + (404,)
    if not retry_on:
        # Ждать нечего: все коды полосы видимости объявлены исходами. Обёртка
        # выродилась бы в петлю, которая не может сработать, — не ставим её.
        return step
    # ЗДЕСЬ ЖЕ — граница, которую этот отказ ставить обёртку НЕ ловит (issue #351).
    # Условие выше отсекает вырожденный случай «ждать нечего», и это верно только
    # для полосы, ВИДИМОЙ КОДОМ ОТВЕТА. У асинхронной мутации есть вторая полоса —
    # отказ ВЛАДЕЛЬЦА чужого ресурса внутри `Operation`, — и она не видна отсюда ни
    # при каком `retry_on`: обёртка ставится, читается как закрытое окно и им не
    # является. Молча этот случай не проходит: эмитируемый комментарий ниже называет
    # свою полосу вслух, а свойство по дереву держит гейт
    # `internal/repohygiene/artifactgates` TestAsyncMutationDoesNotCarryAnUnwarmedPeerId.
    retry_set = ",".join(str(c) for c in retry_on)
    guard = [
        "// bounded read-your-writes retry over the owner-tuple materialization window",
        "// (opgate removed -> eventual-consistency); retries SELF only on 403/404.",
        "// ПОЛОСА — синхронный отказ ЭТОГО шага. У асинхронной мутации отказ ВЛАДЕЛЬЦА",
        "// приезжает внутри Operation и сюда НЕ попадает: нужен прогрев чтением.",
        # Добавка набора в ГОЛОВУ ожидания: проверка, которая обязана отработать
        # ДО того, как шаг начнёт жечь бюджет. Пусто у тех, кто её не заводил.
        *(_RETRY_LANE_HEAD if lane_head else ()),
        "if (pm.environment.get('_authRetryStarted') !== pm.info.requestName) {",
        "  pm.environment.set('_authRetryCount', '0');",
        "  pm.environment.set('_authRetryStarted', pm.info.requestName);",
        "}",
        "const _arc = parseInt(pm.environment.get('_authRetryCount') || '0', 10);",
        # `_rblank` в условии — не украшение головы: без него шаг СНАЧАЛА называет
        # предмет отказа, а ПОТОМ всё равно уходит в повтор и выжигает бюджет на том
        # же вопросе ни о чём. Голова без этого условия — половина меры.
        f"if ({'!_rblank && ' if lane_head else ''}[{retry_set}].includes(pm.response.code)"
        f" && _arc < {budget}) {{",
        "  pm.environment.set('_authRetryCount', String(_arc + 1));",
        f"  const _ard = Date.now(); while (Date.now() - _ard < {interval_ms}) {{ /* owner-tuple materialization wait */ }}",
        "  pm.execution.setNextRequest(pm.info.requestName);",
        "  return;",
        "}",
        # Добавка набора ПЕРЕД снятием счётчика: разведение «бюджет исчерпан» и
        # «бюджет не понадобился» — без неё оба исхода выглядят одинаково.
        *(ledger(f"[{retry_set}].includes(pm.response.code)", "_arc", budget) if ledger else ()),
        "pm.environment.unset('_authRetryCount');",
        "pm.environment.unset('_authRetryStarted');",
    ]
    _RYA_SEQ[0] += 1
    # Give the wrapped step a globally-unique name so its self-retry
    # setNextRequest(pm.info.requestName) always resolves to ITSELF. Newman resolves a
    # setNextRequest name to the FIRST item with that name in the collection; these
    # suites mostly do NOT prefix step names by case-id, so a wrapped step whose bare
    # name repeats would otherwise jump the retry to an earlier same-named step — the
    # exact hazard poll_operation_until_done avoids via its unique poll-op-<n> name.
    return replace(step, name=f"{step.name}-rya{_RYA_SEQ[0]}",
                   test_script=guard + list(step.test_script))



# Голова полосы ожидания: отказ ждать по НЕРАЗРЕШЁННОМУ адресу.
#
# Сегодня её объявляет один набор из шести (`lane_head=True`), и это НЕ решение —
# помощник был скопирован до того, как проверку написали. Раздача остальным пяти
# заведена задачей #1477 отдельно: она МЕНЯЕТ ПОВЕДЕНИЕ проб (шаг с незахваченной
# переменной начнёт падать сразу и по делу вместо того, чтобы падать позже и не по
# делу), а такое не едет попутным грузом сведения — у него свой вердикт.
_RETRY_LANE_HEAD = (
    "",
    "// ЖДАТЬ МОЖНО ТОЛЬКО ПРАВА, А НЕ ИМЯ. Если адрес шага собран из переменной,",
    "// которую предыдущий шаг не захватил, в пути стоит пустой сегмент либо сама",
    "// подстановка — и запрос спрашивает НЕ О РЕСУРСЕ. Окно видимости прав такой",
    "// адрес не наполнит никогда, поэтому повтор здесь — ожидание, которое не может",
    "// сработать: та самая форма без содержания, которую эта функция уже отказывается",
    "// строить выше (вырожденный retry_on). Хуже того, отказ по пустому адресу",
    "// приходит кодом 403 — он в полосе ожидания, и шаг выжигает ВЕСЬ бюджет.",
    "// Замер прогона 31951162447, часть registry: 1863 запроса из 3903 (48%) ушли",
    "// по пустому сегменту в 23 обёрнутых шагах — около 18 минут стенда на вопросы",
    "// ни о чём, при этом ни одно утверждение о продукте не проверялось.",
    "// Отказ здесь называет ПРЕДМЕТ (переменная не захвачена), а не следствие",
    "// («ожидал 200, получил 403») — падение уборки виновника не называет.",
    "const _rpath = ((pm.request.url && pm.request.url.path) || []).map(function (s) {",
    "  return String(s && s.value !== undefined ? s.value : s);",
    "});",
    "const _rblank = _rpath.some(function (v) { return v === '' || /\\{\\{[^}]*\\}\\}/.test(v); });",
    "if (_rblank) {",
    "  pm.environment.unset('_authRetryCount');",
    "  pm.environment.unset('_authRetryStarted');",
    "  pm.test('step addresses a captured variable', function () {",
    "    pm.expect.fail('адрес шага собран из НЕЗАХВАЧЕННОЙ переменной (/' + _rpath.join('/') +",
    "      '): предыдущий шаг не захватил её, повторять нечего — ждать можно право на " +
    "существующее имя, а не появление самого имени');",
    "  });",
    "}",
)

