# ПРИНЯТА ВЕРСИЯ geo — МЕНЬШИНСТВО СТРОГО ЛУЧШЕ (одна копия против семи).
#
# У шести наборов утверждение о коде ответа шло БЕЗ второго аргумента, то есть
