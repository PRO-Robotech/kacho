# ─────────────────────────────────────────────────────────────────────────────
# 1a. ЛИЧНОСТИ, ЗАВОДЯЩИЕ АККАУНТ: одна личность — один аккаунт
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ. Заведение аккаунта ограничено ТЕМПОМ на личность (`#618`, умолчание —
# три заведения в час на внешний идентификатор входа) и ОБЪЁМОМ на личность
# (`484002`, умолчание — пять одновременно живых). Оба носителя — одна и та же
# личность, поэтому вся волна, идущая под ОДНИМ человеком, складывается в один
# потолок каждого вида.
#
# ЧЕМ ЭТО КОНЧИЛОСЬ ИЗМЕРЕННО, А НЕ ПРЕДПОЛОЖЕНО. До этой правки восемь заведений
# волны шли под человеком церемонии, у которого посев уже занял два места (личный
# аккаунт первого входа плюс собственный аккаунт человека). Десять списаний против
# потолка темпа в три: первое заведение проходило, семь получали `RESOURCE_EXHAUSTED`,
# и падение доставалось не им, а шагам, которые шли следом за несозданным аккаунтом.
#
# РЕШЕНИЕ — ПО ПРОДУКТУ, А НЕ ПО ХАРНЕССУ. Человек заводит СЕБЕ аккаунт; заводить
# восемь подряд — не работа человека, а автоматизация, и потолок существует ровно
# затем, чтобы её остановить. Значит проба, заводящая аккаунт, приводит СВОЮ личность.
# Каждая личность ниже заводит РОВНО ОДИН аккаунт, и её баланс выглядит так:
# личный аккаунт первого входа (+1, безусловная ветвь вставки) плюс один заведённый
# пробой (+1) — два списания при потолке три, то есть запас в единицу.
#
# ПОЧЕМУ НЕ «ПОДНЯТЬ ПОТОЛОК ДЛЯ ПОЛОСЫ». Величина живёт ОДНОЙ строкой на вид
# (`kacho_iam.account_admission_rate_limits`, уникальность по виду среди действующих)
