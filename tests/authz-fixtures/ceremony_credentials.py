def admission_bearers(slot: str) -> tuple[str, str]:
    """Пара предъявителей слота: обычный вход и поднятый.

    Поднятый нужен КАЖДОМУ слоту, а не части: уборка за собой снимает аккаунт и его
    дочерний проект, а необратимое снятие объявлено чувствительным (`required_acr_min`),
    и уровень поднимает только церемония входа.
    """
    return f"jwtHuman{slot}", f"jwtHuman{slot}StepUp"


def admission_user_id_var(slot: str) -> str:
    """Переменная с идентификатором человека слота в iam.

    Отдельной переменной, а не выводом из предъявителя: кейс сверяет ВЛАДЕЛЬЦА
    заведённого аккаунта, и сверка с пустой строкой превратила бы утверждение
    в тождество.
    """
    return f"human{slot}UserId"


