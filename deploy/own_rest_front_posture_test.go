// own_rest_front_posture_test.go — гейт посадки ОЦЕНИВАЕТ состояние собственных
// REST-фронтов, а не только печатает его.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Служба, вынесенная отдельным продуктом, края платформы не имеет by
// construction, и её HTTP-поверхность обязана существовать сама. Состояние этих
// фронтов до задачи #2108 в общий самоотчёт не попадало вовсе: их посадку
// сообщали отдельные строки подъёма поверхностей, а гейт посадки читает ровно
// одну строку — «boot security posture». То есть измерение существовало и не
// имело читателя.
//
// Измерение, объявленное и не оценённое, даёт контроль, который присутствует и
// не работает: по зелёному прогону это неотличимо от исправного. Поэтому проба
// утверждает не наличие ключа, а ВЕРДИКТ по нему.
//
//	"true" — фронт поднят, провод под транспортом → проход;
//	"n/a"  — фронта НЕТ: адрес не объявлен профилем либо собственной
//	         HTTP-поверхности у процесса не бывает вовсе → проход;
//	"false"— фронт поднят и работает ОТКРЫТЫМ ТЕКСТОМ → ОТКАЗ;
//	""     — величина не из трёх объявленных (нулевое значение структуры) → ОТКАЗ;
//	ключа нет → ОТКАЗ: так выглядит процесс со СТАРЫМ образом, и молчание тут
//	         читалось бы как согласие.
//
// Схлопнуть "n/a" и "false" значило бы разрешить открытый текст молчанием — то
// есть снять контроль, а не сузить его предмет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ОСЕЙ ДВЕ, И ПРОБА ДЕРЖИТ ИХ ПОРОЗНЬ
//
// Публичный и внутренний фронты поднимаются разными ручками, досягаемы из разных
// мест и несут разный материал. Отрицательный случай меняет РОВНО ОДИН факт
// против положительного близнеца и требует, чтобы вердикт назвал именно его:
// иначе покрасневшая соседняя ось читалась бы как находка про этот фронт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ (чтобы «зелено» не читалось шире, чем есть)
//
// Проба судит ПРОГРАММУ ВЕРДИКТА, вынутую из гейта, а не весь гейт: обход подов,
// чтение живого лога и независимый свидетель со стороны СУБД требуют поднятого
// кластера и остаются за самим гейтом. Здесь — ровно решение «этот самоотчёт
// годен или нет».
package deploy_test

import (
	"encoding/json"
	"os"
	"os/exec"
	"strings"
	"testing"
)

// ownRESTFrontDimensions — оси, которые обязан судить гейт. Перечень тот же, что
// объявлен в общем типе самоотчёта (pkg/observability, own_rest_*_tls).
var ownRESTFrontDimensions = []string{"own_rest_public_tls", "own_rest_internal_tls"}

// withDimension — копия самоотчёта, у которой изменено РОВНО ОДНО измерение.
// nil означает «ключа нет вовсе» — так выглядит процесс со старым образом.
func withDimension(base map[string]any, key string, v any) map[string]any {
	out := make(map[string]any, len(base))
	for k, val := range base {
		out[k] = val
	}
	if v == nil {
		delete(out, key)
	} else {
		out[key] = v
	}
	return out
}

// TestPostureVerdict_OwnRESTFrontsAreJudged — обе оси судятся, и обе стороны
// утверждаются одним прогоном: без средних случаев «n/a проходит» означало бы
// «проходит что угодно».
func TestPostureVerdict_OwnRESTFrontsAreJudged(t *testing.T) {
	requireJQ(t)
	prog := postureVerdictProgram(t)

	// ПРЕДПОСЫЛКА: программа вообще судит эти измерения. Если перестанет — все
	// случаи ниже станут зелёными, и проба будет утверждать о пустоте.
	for _, dim := range ownRESTFrontDimensions {
		if !strings.Contains(prog, dim) {
			t.Fatalf("вынутая программа вердикта не судит %s вовсе — измерение исчезло "+
				"из гейта, и эта проба утверждала бы о пустоте:\n%s", dim, prog)
		}
	}

	control := controlLine(t, prog)

	// Положительный контроль: годная посадка проходит целиком. Без него отказы
	// ниже неотличимы от «программа бракует всё».
	if v := runVerdict(t, prog, control); v != "" {
		t.Fatalf("годная посадка забракована вердиктом: %q — отрицательные случаи "+
			"ниже красили бы по чужому измерению", v)
	}

	cases := []struct {
		name    string
		give    any
		wantBad bool
		why     string
	}{
		{
			name: "фронт поднят и провод под транспортом",
			give: "true", wantBad: false,
			why: "нормальная боевая посадка службы с собственным фронтом",
		},
		{
			name: "собственного фронта НЕТ ВОВСЕ",
			give: "n/a", wantBad: false,
			why: "адрес не объявлен профилем либо у процесса такой поверхности не бывает — " +
				"защищать нечего",
		},
		{
			name: "фронт поднят ОТКРЫТЫМ ТЕКСТОМ",
			give: "false", wantBad: true,
			why: "несущее различие: послабление под «фронта нет» не смеет накрыть фронт, " +
				"поднятый открытым текстом, иначе оно снимает контроль, а не сужает его предмет",
		},
		{
			name: "поля нет вовсе (старый образ)",
			give: nil, wantBad: true,
			why: "неотчитанное не считается сделанным",
		},
		{
			name: "поле объявлено пустым",
			give: "", wantBad: true,
			why: "нулевое значение структуры — величина не из трёх объявленных",
		},
		{
			name: "величина булева (образ до смены типа)",
			give: true, wantBad: true,
			why: "измерение строковое; булево true означает процесс со старым образом, " +
				"и наполовину перекатившийся флот обязан быть виден",
		},
	}

	// Перепись печатается ВСЕГДА: «ноль находок» обязано быть отличимо от «ноль
	// прочитанного». Измерения ВЫВОДЯТСЯ из вынутой программы, а не выписываются —
	// выписанный перечень был бы второй копией и разошёлся бы с ней молча.
	judged := judgedDimensions(prog)
	t.Logf("осмотрено: измерений судит гейт %d (%s), из них осей собственных "+
		"REST-фронтов %d, случаев на ось %d",
		len(judged), strings.Join(judged, " "), len(ownRESTFrontDimensions), len(cases))

	for _, dim := range ownRESTFrontDimensions {
		other := ownRESTFrontDimensions[0]
		if other == dim {
			other = ownRESTFrontDimensions[1]
		}
		for _, tc := range cases {
			t.Run(dim+"/"+tc.name, func(t *testing.T) {
				v := runVerdict(t, prog, withDimension(control, dim, tc.give))
				bad := strings.Contains(v, dim)
				if bad != tc.wantBad {
					t.Fatalf("%s=%#v: вердикт %q; ждали %s — %s",
						dim, tc.give, v,
						map[bool]string{true: "ОТКАЗ", false: "проход"}[tc.wantBad], tc.why)
				}
				// ЗАКОННЫЙ БЛИЗНЕЦ: соседняя ось не тронута и обязана молчать.
				// Без этого вердикт, покрасневший по обеим осям разом, читался бы
				// как находка про изменённый фронт.
				if strings.Contains(v, other) {
					t.Fatalf("%s=%#v: вердикт назвал НЕТРОНУТУЮ ось %s: %q — отказ обязан "+
						"называть ровно тот фронт, чьё состояние изменилось",
						dim, tc.give, other, v)
				}
			})
		}
	}
}

// TestPostureVerdict_OwnRESTFrontsSkippedInDevProfile — граница послабления с
// другой стороны: в dev-профиле измерение не судится вовсе.
//
// Иначе «n/a проходит» могло бы означать «программа перестала градуировать», а
// не «величина принята». Транспорт dev-профиль расслабляет осознанно — ровно как
// у соседних public_mtls и internal_mtls, — и требовать его здесь значило бы
// красить гейт на каждом dev-стенде до полной бесполезности.
func TestPostureVerdict_OwnRESTFrontsSkippedInDevProfile(t *testing.T) {
	requireJQ(t)
	prog := postureVerdictProgram(t)
	control := controlLine(t, prog)

	for _, dim := range ownRESTFrontDimensions {
		t.Run(dim, func(t *testing.T) {
			cmd := exec.Command("jq", "-r", "--argjson", "need_fwd", "false", prog)
			body, err := json.Marshal(withDimension(control, dim, "false"))
			if err != nil {
				t.Fatalf("фикстура самоотчёта не сериализовалась: %v", err)
			}
			cmd.Stdin = strings.NewReader(string(body))
			cmd.Env = append(os.Environ(), "POSTURE_PROFILE=dev")
			out, err := cmd.CombinedOutput()
			if err != nil {
				t.Fatalf("jq не отработал: %v\n%s", err, out)
			}
			if strings.Contains(string(out), dim) {
				t.Fatalf("dev-профиль стал судить %s: %q — гейт красил бы каждый dev-стенд, "+
					"и его перестали бы читать", dim, strings.TrimSpace(string(out)))
			}
		})
	}
}
