# restart-verdict.sh — РАЗЛИЧЕНИЕ двух событий, которые сверка целыми файлами
# смешивала в одно: перезапуск участника пути и смену состава участников.
#
# Живёт отдельным файлом ровно затем, чтобы способность вердикта упасть и
# смолчать можно было доказать БЕЗ поднятого стенда и без часового прогона
# лестницы: проба подсовывает сюда пары снимков (см. restart-verdict-inject.sh).
#
# Формат снимка — строки `<имя пода>=<счётчик перезапусков>`, ровно то, что
# отдаёт `restarts()` прогонщика ступеней.

# restart_grew «до» «после» — печатает имена подов, ПРИСУТСТВУЮЩИХ В ОБА
# момента, чей счётчик перезапусков вырос. Это и есть перезапуск участника.
#
# Поды, которых нет в одном из снимков, здесь НЕ рассматриваются намеренно:
# у появившегося счётчик заведомо начинается с нуля, а у исчезнувшего его
# больше не спросить. Их судьба — предмет composition_changed.
restart_grew() {
  awk -F= 'NR==FNR { was[$1]=$2; next } ($1 in was) && ($2+0) > (was[$1]+0) { print $1 }' "$1" "$2"
}

# composition_changed «до» «после» — истина, если множество имён различается
# в любую сторону. НЕ вердикт: состав меняет оператор масштабированием, ради
# которого лестницу и гоняют.
composition_changed() {
  ! diff -q <(cut -d= -f1 "$1" | sort) <(cut -d= -f1 "$2" | sort) >/dev/null 2>&1
}
