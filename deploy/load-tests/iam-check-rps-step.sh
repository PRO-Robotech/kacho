# iam-check-rps-step.sh — ступенчатый замер пропускной способности
# InternalIAMService.Check с одновременным съёмом того, ВО ЧТО он упирается.
#
# Число без ответа «что упёрлось» бесполезно: непонятно, что чинить. Поэтому
# каждая ступень снимает не только задержку, но и процессорное время КАЖДОГО
# участника пути (служба прав · её база · сам генератор нагрузки), состояние
# пула соединений службы и число соединений в базе.
#
# ГЕНЕРАТОР НАГРУЗКИ МЕРИТСЯ НАРАВНЕ С ПРЕДМЕТОМ — и это не педантизм: k6 живёт
# на том же узле, и его собственное насыщение выглядит СНАРУЖИ как насыщение
# службы. Ступень, на которой генератор упёрся в свой предел, обязана быть
# отличима от ступени, на которой упёрся продукт.
#
# Использование:
#   ./iam-check-rps-step.sh <метка> <ступени> <длительность> [повторов]
#   ./iam-check-rps-step.sh r1 "100,200,400,800,1600" 60s 1
set -euo pipefail

NS=kacho
LABEL="${1:?нужна метка прогона, напр. r1}"
STEPS="${2:-100,200,400,800,1600}"
DUR="${3:-60s}"
REPEATS="${4:-1}"
# REP_START — с какого номера нумеровать повторы. Длинный прогон приходится
# резать на куски (оболочка убивает фоновые задачи), а метки повторов обязаны
# не сталкиваться, иначе второй кусок затрёт первый.
REP_START="${REP_START:-1}"
ALLOW_RATIO="${ALLOW_RATIO:-0.9}"
OUT="${OUT_DIR:-/tmp/claude-1000/rps-work/results}/$LABEL"
mkdir -p "$OUT"

k() { kubectl -n "$NS" "$@"; }

# cpu_usec <pod> <container> — накопленное процессорное время контейнера.
#
# ОТКАЗ ЧТЕНИЯ ОБЯЗАН БЫТЬ ОТЛИЧИМ ОТ НУЛЯ. Прежняя редакция глушила отказ через
# `|| echo 0`, и «не измерено» становилось неотличимо от «не потратило». Это не
# теоретическая опасность: у участника, чей образ распространяется БЕЗ ОБОЛОЧКИ,
# `exec` невозможен в принципе, и снимок писал ему ровно ноль на каждой ступени
# каждого прогона. В разборе это выглядело как участник, который
# под нагрузкой не тратит процессор вовсе, — то есть как факт, а не как пробел.
# Теперь пробел называет себя сам, и его видно в таблице как NA.
cpu_usec() {
  local v
  v=$(k exec "$1" -c "$2" -- sh -c 'awk "/usage_usec/{print \$2}" /sys/fs/cgroup/cpu.stat' 2>/dev/null) || v=""
  case "$v" in
    ''|*[!0-9]*) echo "NA" ;;
    *)           echo "$v" ;;
  esac
}

iam_pods()  { k get pod -l app.kubernetes.io/name=kaname -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}'; }
# snapshot <файл> — состояние всех участников в один момент.
#
# Участников стало меньше: внешний движок отношений и его база сняты вместе с
# посадкой (S6 эпика #747), поэтому снимать процессорное время у них нечего —
# решение о доступе вычисляется в базе самой службы прав, и она в снимке уже есть.
snapshot() {
  local f="$1"
  {
    echo "ts_ns=$(date +%s%N)"
    for p in $(iam_pods); do echo "iam:$p=$(cpu_usec "$p" kaname)"; done
    echo "pgiam=$(cpu_usec kacho-umbrella-pg-iam-0 postgresql)"
    echo "k6=$(cpu_usec k6-iam-runner k6)"
  } > "$f"
}

# pool_stats — показатели пула соединений службы прав, со ВСЕХ реплик.
# Читаются с внутреннего порта метрик, суммарно по репликам.
pool_stats() {
  for p in $(iam_pods); do
    k exec "$p" -c kaname -- sh -c \
      'wget -qO- http://127.0.0.1:9095/metrics 2>/dev/null | grep -E "^kaname_db_pool_|^kaname_authz_check_duration_seconds_count|^kaname_shadow" || true' \
      2>/dev/null | sed "s|^|$p |"
  done
}

# restarts — счётчики перезапусков участников пути. Ступень, на которой хоть
# один из них перезапустился, НЕ является ни зелёной, ни красной: это «не
# выполнилось», и её число нельзя истолковывать. Наблюдалось вживую: база службы
# прав под насыщением перестала отвечать на собственную пробу живости и была
# убита, а счётчик процессорного времени обнулился — в разборе это выглядело как
# ОТРИЦАТЕЛЬНАЯ загрузка процессора, то есть как явная бессмыслица. Не будь
# счётчика перезапусков, тот же прогон дал бы правдоподобное, но ложное число.
# Вердикт о перезапуске/смене состава живёт отдельным файлом — его способность
# упасть и смолчать доказывается инъекцией без стенда (см. lib/restart-verdict.sh
# и restart-verdict-inject.sh).
# shellcheck source=lib/restart-verdict.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/restart-verdict.sh"

restarts() {
  k get pod -o jsonpath='{range .items[*]}{.metadata.name}={.status.containerStatuses[0].restartCount}{"\n"}{end}' 2>/dev/null \
    | grep -E 'kaname|pg-iam' || true
}

pg_conns() {
  local pw; pw=$(k get secret kacho-umbrella-pg-iam -o jsonpath='{.data.postgres-password}' 2>/dev/null | base64 -d || true)
  k exec kacho-umbrella-pg-iam-0 -c postgresql -- sh -c \
    "PGPASSWORD='$pw' psql -U postgres -d kacho_iam -t -A -F'|' -c \
     \"select count(*), count(*) filter (where state='active'), count(*) filter (where wait_event_type='Lock') from pg_stat_activity where datname='kacho_iam';\"" 2>/dev/null || echo "NA"
}

REPLICAS=$(k get deploy kaname -o jsonpath='{.spec.replicas}')
echo "=== прогон '$LABEL': реплик службы прав=$REPLICAS · ступени=$STEPS · длительность=$DUR · повторов=$REPEATS ==="
echo "replicas=$REPLICAS" > "$OUT/meta.txt"
echo "steps=$STEPS duration=$DUR repeats=$REPEATS allow_ratio=$ALLOW_RATIO" >> "$OUT/meta.txt"
k get pod -l app.kubernetes.io/name=kaname -o jsonpath='{range .items[*]}{.metadata.name}{" "}{.status.containerStatuses[0].imageID}{"\n"}{end}' >> "$OUT/meta.txt"

# ПРОГРЕВ, РЕЗУЛЬТАТ КОТОРОГО ВЫБРАСЫВАЕТСЯ. Первая ступень после переката или
# смены числа реплик меряет не продукт, а холодный старт: пулы пусты, соединения
# к базе прав ещё не установлены, планировщик базы не видел этих запросов.
# Наблюдалось прямо здесь: сразу после масштабирования ступень 100 rps дала p99
# 374 мс и 0.77% отказов, а следующая за ней ступень 200 rps — 4 мс и ноль. Без
# явного прогрева этот артефакт неотличим от находки, и он ложится на САМУЮ
# низкую ступень, то есть портит именно ту точку, от которой отсчитывают запас.
#
# ДЛИТЕЛЬНОСТЬ — 90 с, И ЭТО ИЗМЕРЕННАЯ ВЕЛИЧИНА, А НЕ КРУГЛОЕ ЧИСЛО. Здесь было
# зашито 30 с, тогда как разбор `BASELINE-internal-check.md` установил, что после
# перезапуска участника установление соединений занимает до 90 с. Тридцати не
# хватало: на перемере #773 одна ступень пятой посадки всё равно попала под
# холодный старт — 800 rps дала p99 62 мс против 17 и 19 мс в повторах той же
# подачи, и разрешилось это повтором, а не истолкованием. Прогревать приходилось
# вручную, то есть свойство держалось памятью прогоняющего.
WARMUP_DUR="${WARMUP_DUR:-90s}"
restarts > "$OUT/run.restarts.baseline"

if [ "${WARMUP:-1}" = "1" ]; then
  echo "--- прогрев $WARMUP_DUR (результат выбрасывается) ---"
  k exec k6-iam-runner -- k6 run --quiet -e TARGET_RPS=200 -e DURATION="$WARMUP_DUR" \
     -e ALLOW_RATIO="$ALLOW_RATIO" -e MAX_VUS=600 /scripts/internal_check.js \
     > "$OUT/warmup.k6.log" 2>&1 || true
  sleep 5
else
  # Прогрев ОТКЛЮЧЁН — сказать об этом в выводе, а не умолчать: первая ступень
  # ляжет на холодный старт, и её срыв будет неотличим от находки. «Прогрева не
  # было» обязано быть видно там же, где читают числа.
  echo "--- ПРОГРЕВА НЕ БЫЛО (WARMUP=0): первая ступень меряет холодный старт ---"
  echo "warmup=skipped" >> "$OUT/meta.txt"
fi
echo "warmup=${WARMUP:-1} warmup_duration=$WARMUP_DUR" >> "$OUT/meta.txt"

for rep in $(seq "$REP_START" $(( REP_START + REPEATS - 1 ))); do
breaches=0
for rate in ${STEPS//,/ }; do
  tag="rate${rate}_rep${rep}"
  echo "--- ступень $rate rps (повтор $rep) ---"
  restarts > "$OUT/$tag.restarts.before"
  pool_stats > "$OUT/$tag.pool.before" 2>/dev/null || true
  snapshot "$OUT/$tag.cpu.before"
  pg_conns > "$OUT/$tag.pg.before"

  set +e
  k exec k6-iam-runner -- k6 run --quiet \
      -e TARGET_RPS="$rate" -e DURATION="$DUR" -e ALLOW_RATIO="$ALLOW_RATIO" \
      -e MAX_VUS=$(( rate < 64 ? 64 : (rate * 3) )) \
      --summary-export="/out/$tag.json" /scripts/internal_check.js \
      > "$OUT/$tag.k6.log" 2>&1
  k6rc=$?
  set -e

  snapshot "$OUT/$tag.cpu.after"
  pg_conns > "$OUT/$tag.pg.after"
  pool_stats > "$OUT/$tag.pool.after" 2>/dev/null || true
  restarts > "$OUT/$tag.restarts.after"
  # Сверяем ДВАЖДЫ: с началом ступени и с началом ПРОГОНА. Только первая сверка
  # была здесь раньше, и она пропускает перезапуск, случившийся МЕЖДУ ступенями:
  # «до» и «после» такой ступени совпадают между собой, поэтому метка не
  # ставится, а числа соседних ступеней выглядят правдоподобно. Наблюдалось
  # вживую — база службы прав была убита (код 137) в ходе серии, и ни одного
  # файла .invalid не появилось.
  # СМЕНА СОСТАВА И ПЕРЕЗАПУСК — РАЗНЫЕ СОБЫТИЯ, и путать их нельзя.
  #
  # Сверка целыми файлами читала как перезапуск ЛЮБОЕ расхождение, включая
  # появление и исчезновение имени пода. А состав меняет ОПЕРАТОР — ровно тем
  # действием, ради которого лестницу и гоняют: масштабированием. Поэтому
  # прибор браковал замер горизонтального масштабирования BY CONSTRUCTION:
  # первая же ступень после `kubectl scale` объявлялась недействительной, и
  # ни одно число о трёх репликах прочитать было нельзя.
  #
  # Наблюдалось 2026-08-21: метка стояла на КАЖДОЙ ступени прогона на трёх
  # репликах, при том что счётчик перезапусков базы был нулём, а завершавшийся
  # под прежнего поколения просто исчезал из выдачи между двумя снимками.
  # Инструмент, у которого все находки ложные, перестают читать — и тогда
  # настоящий перезапуск проходит незамеченным.
  #
  # Теперь брак ставится по РОСТУ СЧЁТЧИКА у пода, присутствующего в ОБА
  # момента: это и есть перезапуск участника. Смена состава называется
  # отдельной строкой и отдельным файлом — она не вердикт, а факт, который
  # оператор обязан увидеть.
  #
  # Граница названа честно: под, УПАВШИЙ и заменённый новым именем, счётчик
  # роста не даёт (у новорождённого он ноль) и попадёт в «состав изменился»,
  # а не в брак. Поэтому смена состава печатается ГРОМКО и требует взгляда;
  # молча её проглатывать нельзя.
  grew_step=$(restart_grew "$OUT/$tag.restarts.before" "$OUT/$tag.restarts.after")
  grew_run=$(restart_grew "$OUT/run.restarts.baseline" "$OUT/$tag.restarts.after")
  if [ -n "$grew_step" ]; then
    echo "INVALID: участник пути перезапустился в ходе ступени: $grew_step" > "$OUT/$tag.invalid"
    echo "    !! НЕДЕЙСТВИТЕЛЬНО: перезапустился $grew_step — число этой ступени не читать"
  elif [ -n "$grew_run" ]; then
    echo "INVALID: участник пути перезапустился с начала прогона: $grew_run" > "$OUT/$tag.invalid"
    echo "    !! НЕДЕЙСТВИТЕЛЬНО: с начала прогона перезапустился $grew_run — прогон не сравним с началом"
  fi
  if composition_changed "$OUT/run.restarts.baseline" "$OUT/$tag.restarts.after"; then
    {
      echo "состав участников изменился с начала прогона"
      echo "было:"; cut -d= -f1 "$OUT/run.restarts.baseline"
      echo "стало:"; cut -d= -f1 "$OUT/$tag.restarts.after"
    } > "$OUT/$tag.composition-changed"
    echo "    ** СОСТАВ ИЗМЕНИЛСЯ с начала прогона (подробности в $tag.composition-changed)."
    echo "       Если это ваше масштабирование — читайте число; если нет, под мог быть"
    echo "       заменён после падения, и тогда числу верить нельзя."
  fi
  k exec k6-iam-runner -- cat "/out/$tag.json" > "$OUT/$tag.summary.json" 2>/dev/null || echo '{}' > "$OUT/$tag.summary.json"
  echo "k6_exit=$k6rc" > "$OUT/$tag.rc"
  # Легенда кода печатается ТОЛЬКО при ненулевом исходе. Пока она стояла
  # безусловно, строка «исход k6=0 (порог задержки нарушен ⇒ 99)» читалась как
  # утверждение о нарушении — на ней споткнулся автор соседнего кода и едва не
  # завёл задачу о бесполезном пороге, тогда как порог не нарушался ни разу.
  if [ "$k6rc" -eq 0 ]; then
    echo "    исход k6=0 — пороги прогона выдержаны"
  elif [ "$k6rc" -eq 99 ]; then
    echo "    исход k6=99 — ПОРОГ НАРУШЕН (бюджет задержки либо доля отказов)"
  else
    echo "    исход k6=$k6rc — прогон не состоялся (не вердикт о задержке)"
  fi
  # Ранняя остановка: точка насыщения найдена, дальше лестница только загоняет
  # базу в отказ (и, как выяснилось, под пробу живости). Две подряд нарушенные
  # ступени — достаточное свидетельство, третья ничего не добавляет.
  if [ "$k6rc" != "0" ]; then
    breaches=$(( breaches + 1 ))
    if [ "$breaches" -ge 2 ]; then
      echo "    (лестница остановлена: бюджет нарушен дважды подряд)"
      break
    fi
  else
    breaches=0
  fi
done
done
echo "=== готово: $OUT ==="
