# iam-scope-source-census.sh — перепись ИСТОЧНИКОВ звена цепи областей: что о
# предке объекта знает ЦЕПЬ (представление `kacho_iam.resource_scope_edge`)
# против того, что о нём знает ПРОЕКЦИЯ ЖУРНАЛА (`kacho_iam.relation_fact`), из
# которой свёрнуто состояние движка отношений.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ ПРОБЫ РАСХОЖДЕНИЯ
#
# `iam-shadow-divergence-probe.sh` меряет ИСХОД — долю вопросов, на которых
# форма E разошлась с движком. Он отвечает «расходится ли», но не «где именно
# рвётся цепь»: доля 61 % одинаково получается и от потерянного звена, и от
# неверного разбора выдачи, и от неверного словаря типов.
#
# Эта перепись отвечает на второй вопрос и держит СВОЙСТВО, а не текущие данные:
# объект, чей предок назван журналом, обязан иметь предка и в цепи. Расхождение
# здесь — прямая причина расхождения там, и видно оно ДО подачи нагрузки.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА
#
#   0 — перепись сделана, расхождений нет;
#   1 — перепись сделана, РАСХОЖДЕНИЕ НАЙДЕНО (называется по типам и числами);
#   3 — УСЛОВИЕ НЕ СОЗДАНО: базы нет, схемы нет, читать нечего. Это не «зелено»
#       и не «красно» — «ноль находок» обязано быть отличимо от «ноль
#       прочитанного», поэтому объём осмотренного печатается ВСЕГДА.
#
# Использование:
#   ./iam-scope-source-census.sh            # перепись, отказ при расхождении
#   ALLOW_TYPES=account ./iam-scope-source-census.sh
#
# ALLOW_TYPES — типы, расхождение по которым НЕ роняет перепись. Послабление
# несёт предикат снятия на ВНЕШНЕМ факте: запись живёт, пока у неё есть предмет,
# и перепись падает на записи, которой больше нечего прощать (см. ниже).
set -euo pipefail

NS="${NS:-kacho}"
PG_POD="${PG_POD:-kacho-umbrella-pg-iam-0}"
DB="${DB:-kacho_iam}"
DBUSER="${DBUSER:-postgres}"
ALLOW_TYPES="${ALLOW_TYPES:-}"

die_precond() { echo "УСЛОВИЕ НЕ СОЗДАНО: $*" >&2; exit 3; }

q() {
  kubectl -n "$NS" exec "$PG_POD" -- psql -U "$DBUSER" -d "$DB" -At -F'|' -c "$1" 2>/dev/null \
    | grep -v '^Defaulted' || true
}

# ── 0. Предусловия ───────────────────────────────────────────────────────────
kubectl -n "$NS" get pod "$PG_POD" >/dev/null 2>&1 \
  || die_precond "пода базы $PG_POD в пространстве $NS нет"
have_view=$(q "SELECT count(*) FROM pg_views WHERE schemaname='kacho_iam' AND viewname='resource_scope_edge';")
[ "${have_view:-0}" = "1" ] \
  || die_precond "представления kacho_iam.resource_scope_edge нет — цепь читать нечем"
have_fact=$(q "SELECT count(*) FROM information_schema.tables WHERE table_schema='kacho_iam' AND table_name='relation_fact';")
[ "${have_fact:-0}" = "1" ] \
  || die_precond "таблицы kacho_iam.relation_fact нет — сверять не с чем"

echo "── перепись источников звена цепи ────────────────────────────────────────"
echo "  база $PG_POD/$DB, снято $(date -u '+%Y-%m-%d %H:%M:%SZ')"

# ── 1. Объём осмотренного — ОТДЕЛЬНЫМ утверждением ───────────────────────────
#
# Без него «расхождений 0» неотличимо от «ничего не прочитали»: пустая проекция
# даёт ровно тот же ноль, что и здоровое дерево.
read -r facts pointers edges <<<"$(q "
  SELECT (SELECT count(*) FROM kacho_iam.relation_fact),
         (SELECT count(*) FROM kacho_iam.relation_fact
           WHERE relation = split_part(subject, ':', 1)),
         (SELECT count(*) FROM kacho_iam.resource_scope_edge);" | tr '|' ' ')"
echo "  осмотрено: прямых фактов ${facts:-0}, из них указателей на предка ${pointers:-0}, рёбер цепи ${edges:-0}"

if [ "${facts:-0}" -eq 0 ] || [ "${edges:-0}" -eq 0 ]; then
  die_precond "читать нечего (фактов ${facts:-0}, рёбер ${edges:-0}) — «расхождений нет» здесь означало бы «ничего не прочитано»"
fi
if [ "${pointers:-0}" -eq 0 ]; then
  die_precond "указателей на предка в проекции журнала ноль — дискриминатор «отношение называет тип субъекта» не нашёл НИ ОДНОГО, значит он разошёлся с формой журнала, а не журнал пуст"
fi

# ── 2. Перепись по типам ─────────────────────────────────────────────────────
#
# Единица — ОБЪЕКТ, а не строка: у объекта бывает несколько указателей (у проекта
# их два — аккаунт и кластер), и счёт строк завысил бы обе стороны по-разному.
#
# Дискриминатор указателя СТРУКТУРНЫЙ: отношение называет тип субъекта
# (`project --account--> account:acc-1`). Прямые факты, не являющиеся указателями
# (`owner`, `admin`, `system_admin`), его не удовлетворяют — их субъект человек
# или служебная учётка, а не предок.
echo "── по типам: объектов с предком ──────────────────────────────────────────"
printf '  %-26s %10s %10s %10s %10s\n' "тип объекта" "в журнале" "в цепи" "потеряно" "лишних"
rows=$(q "
  WITH j AS (
    SELECT object_type, object_id
      FROM kacho_iam.relation_fact
     WHERE relation = split_part(subject, ':', 1)
     GROUP BY 1, 2),
  c AS (
    SELECT object_type, object_id
      FROM kacho_iam.resource_scope_edge
     GROUP BY 1, 2)
  SELECT COALESCE(j.object_type, c.object_type),
         count(j.object_id),
         count(c.object_id),
         count(*) FILTER (WHERE c.object_id IS NULL),
         count(*) FILTER (WHERE j.object_id IS NULL)
    FROM j FULL OUTER JOIN c
      ON c.object_type = j.object_type AND c.object_id = j.object_id
   GROUP BY 1
   ORDER BY 4 DESC, 5 DESC, 1;")

[ -n "$rows" ] || die_precond "перепись по типам не вернула ни одной строки при непустых входах — читать нечем"

# ДВЕ полярности, а не одна. Инвариант «форма отвечает то же, что движок»
# ломается в обе стороны, и односторонняя перепись закрыла бы ровно половину:
#
#   потеряно — предок назван журналом, цепь его не видит  ⇒ форма ОТКАЗЫВАЕТ,
#              где движок разрешает (тихий отказ, неотличимый от честного);
#   лишних   — предок есть у цепи и НЕ назван журналом    ⇒ форма РАЗРЕШАЕТ,
#              где движок отказывает (тихое расширение охвата).
lost_total=0; extra_total=0; lost_types=""; extra_types=""; forgiven=""
while IFS='|' read -r otype in_journal in_chain lost extra; do
  [ -n "$otype" ] || continue
  printf '  %-26s %10s %10s %10s %10s\n' "$otype" "$in_journal" "$in_chain" "$lost" "$extra"
  if [ "${lost:-0}" -gt 0 ] || [ "${extra:-0}" -gt 0 ]; then
    # Сравнение БЕЗ внешнего процесса: `grep -q` выходит до конца входа, писатель
    # слева получает SIGPIPE, и под `pipefail` найденное объявляется ненайденным
    # (#658). Здесь от этого зависел бы вердикт, поэтому труба недопустима.
    if [ -n "$ALLOW_TYPES" ] && [[ ",$ALLOW_TYPES," == *",$otype,"* ]]; then
      forgiven="$forgiven $otype"
    else
      [ "${lost:-0}" -gt 0 ] && { lost_total=$((lost_total + lost)); lost_types="$lost_types $otype($lost)"; }
      [ "${extra:-0}" -gt 0 ] && { extra_total=$((extra_total + extra)); extra_types="$extra_types $otype($extra)"; }
    fi
  fi
done <<<"$rows"

# ── 3. Послабление, которому нечего прощать, — НАХОДКА ───────────────────────
#
# Иначе запись переживает свой предмет и маскирует следующее расхождение по
# тому же типу. Предикат снятия — ВНЕШНИЙ факт: тип перестал терять объекты.
if [ -n "$ALLOW_TYPES" ]; then
  echo "── послабления ───────────────────────────────────────────────────────────"
  for t in $(echo "$ALLOW_TYPES" | tr ',' ' '); do
    [ -n "$t" ] || continue
    if [[ " $forgiven " == *" $t "* ]]; then
      echo "  $t — прощено расхождение (предмет есть)"
    else
      echo "  ОТКАЗ: тип «$t» объявлен в ALLOW_TYPES, но расхождения по нему НЕТ." >&2
      echo "  Прощать нечего — запись пережила свой предмет и замаскирует следующее." >&2
      exit 1
    fi
  done
fi

# ── 4. Вердикт ───────────────────────────────────────────────────────────────
# ── 3a. Предел обхода: указателей на объект не больше глубины ────────────────
#
# Цепь читается соединением вбок с `LIMIT MaxAncestorDepth` по КАЖДОМУ объекту.
# Пока звенья выводились из схемы, строк на объект было не больше глубин, и
# предел усечь не мог — так и было записано в 740001. Журнальная ветвь этот довод
# отменяет: у проекта указателей два (аккаунт и кластер), оба на глубине 1.
#
# Двукратный запас — не самоочевидное свойство, а число, поэтому оно ПРОВЕРЯЕТСЯ.
# Объект, у которого указателей столько же, сколько предел обхода, усекается
# МОЛЧА: цепь просто не доходит до корня, и отказ неотличим от честного.
MAX_DEPTH="${MAX_DEPTH:-4}"
read -r max_ptr max_obj <<<"$(q "
  SELECT n, object_type || ':' || object_id
    FROM (SELECT object_type, object_id, count(*) n
            FROM kacho_iam.resource_scope_edge
           GROUP BY 1, 2) s
   ORDER BY n DESC LIMIT 1;" | tr '|' ' ')"
echo "── предел обхода ─────────────────────────────────────────────────────────"
echo "  максимум звеньев на объект: ${max_ptr:-0} (${max_obj:-нет}), предел обхода $MAX_DEPTH"
if [ "${max_ptr:-0}" -ge "$MAX_DEPTH" ]; then
  echo "  ОТКАЗ: у объекта ${max_obj} звеньев ${max_ptr} при пределе обхода $MAX_DEPTH." >&2
  echo "  Соединение вбок усекает цепь МОЛЧА: она не дойдёт до корня, а отказ в доступе" >&2
  echo "  будет неотличим от честного. Поднимать предел вслепую нельзя — сперва понять," >&2
  echo "  откуда у объекта столько звеньев." >&2
  exit 1
fi

echo "── вердикт ───────────────────────────────────────────────────────────────"
rc=0
if [ "$lost_total" -gt 0 ]; then
  echo "  ОТКАЗ: объектов, чей предок назван журналом и НЕ виден цепи:$lost_types" >&2
  echo "  Движок читает свёртку того же журнала, поэтому по этим объектам форма E" >&2
  echo "  отказывает там, где движок разрешает, и отказ неотличим от честного." >&2
  rc=1
fi
if [ "$extra_total" -gt 0 ]; then
  echo "  ОТКАЗ: объектов, у которых предок есть у цепи и НЕ назван журналом:$extra_types" >&2
  echo "  Это обратная полярность того же инварианта: форма РАЗРЕШАЕТ там, где движок" >&2
  echo "  отказывает. Тише первой и опаснее — расширение охвата не выглядит поломкой." >&2
  rc=1
fi
[ "$rc" -eq 0 ] && echo "  расхождений нет ни в одну сторону: цепь видит ровно то, что назвал журнал"
exit $rc
