# iam-shadow-divergence-probe.sh — доля расхождений теневой сверки формы E с
# движком, снятая ПОДАЧАМИ, которые разводят объяснения расхождения И разводят
# ЗНАМЕНАТЕЛИ.
#
# ЗАЧЕМ НЕСКОЛЬКО ПОДАЧ, А НЕ ОДНА. Прибор `internal_check.js` строит отказной
# вход ПЕРЕСТАНОВКОЙ — субъект одной тройки против объекта другой того же типа.
# Пока подача смешана (`ALLOW_RATIO=0.9`), одно число «доля расхождений» отвечает
# сразу на два вопроса и потому не отвечает ни на один: расходится ли форма E на
# настоящих выдачах стенда, или расхождение приносят синтетические пары, которых
# в выдачах нет вовсе. Замером пропускной способности это не разводится — нужны
# отдельные прогоны на одном стенде:
#
#   рука A — ALLOW_RATIO=1.0 — НИ ОДНОЙ перестановки, только выдачи стенда;
#   рука B — ALLOW_RATIO=0.0 — ОДНИ перестановки.
#
# Читается пара так, и только так:
#   A высоко, B низко  ⇒ расходятся НАСТОЯЩИЕ выдачи; фикстура ни при чём;
#   A низко,  B высоко ⇒ расхождение — артефакт перестановки;
#   обе высоко         ⇒ два разных предмета, разбирать порознь;
#   обе низко          ⇒ расхождения нет (или сравнение не доехало — см. «сравнено»).
#
# Замеры на ревизии стенда 5ddacfd85 (одна и та же, менялось ТОЛЬКО представление
# цепи областей — Go-код не тронут):
#   #775, до правки  — A = 61.0 %, B = 0.13 %  (расходятся настоящие выдачи);
#   #781, после      — A = 0.00 % (0 из 3041), B = 0.00 % (0 из 3042).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ РУК ЧЕТЫРЕ, А НЕ ДВЕ (R7-4-04, R7-4-12, решение Р9)
#
# Числа выше сняты на подаче, в которой пяти СОБСТВЕННЫХ типов iam
# (`iam_user` / `iam_group` / `iam_role` / `iam_service_account` /
# `iam_access_binding`) не было НИ ОДНОГО объекта: замер состава 2026-08-20 —
# `project 60 · account 60 · vpc_security_group 47 · vpc_route_table 47 ·
# vpc_network 42 · vpc_subnet 17`, всего 273 тройки. Поэтому «0.00 %» стоял рядом
# с переписью, называвшей 15 085 потерянных объектов ровно этих типов: два прибора
# мерили разные множества, и это было НЕОТЛИЧИМО ОТ СОГЛАСИЯ.
#
# Счётчики сравнителя живут в СЛУЖБЕ и общие на всю подачу — разложить их по типу
# объекта, не трогая службу, нельзя. Поэтому знаменатели разводятся ПОДАЧЕЙ:
#
#   A — выдачи стенда БЕЗ пяти собственных типов iam   (сравнимо с историей выше);
#   B — перестановки на том же множестве;
#   C — ТОЛЬКО пять собственных типов iam, без класса «проектная роль»;
#   D — ТОЛЬКО класс «проектная роль» — отчёт, никогда не вычитается и не
#       складывается ни с чем.
#
# Перечень пяти типов прибор берёт У СЦЕНАРИЯ (строка `ФИКСТУРА-СВОИ-ТИПЫ`), а не
# держит свою копию: две копии одного перечня разошлись бы молча.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА:
#   0 — измерено, бюджеты выдержаны;
#   1 — измерить не удалось (сводки нет, сравнений ноль, прибор не совпал с
#       деревом) ЛИБО бюджет не выдержан;
#   3 — УСЛОВИЕ НЕ СОЗДАНО (нет генератора, нет фикстуры, в подаче нет предмета).
#       Это не «зелено» и не «красно»: мерить было нечем, и оно обязано быть
#       отличимо от вердикта.
#
# Использование:
#   ./iam-shadow-divergence-probe.sh [подача_rps] [длительность]
#   ./iam-shadow-divergence-probe.sh 100 30s
#
# Подача строится генератором `iam-check-runner.sh fixture` — оттуда же берётся
# разметка класса «проектная роль».
#
# ─────────────────────────────────────────────────────────────────────────────
# БЮДЖЕТЫ — УСЛОВИЕ ПРОХОЖДЕНИЯ, А НЕ ОТЧЁТ
#
# «Доля посчитана» условием прохождения не является: прибор, который только
# печатает число, не удерживает ничего, и первый же прогон научит читать его
# число как погоду. Бюджетов ДВА, оба объявлены ДО прогона, и у каждого обе
# границы ИЗМЕРЕНЫ, а не выбраны круглыми.
#
# `MAX_DIVERGED_SHARE` — рука A, доля 0.01 (1 %):
#   снизу — наибольший наблюдавшийся транзиент 0.13 % (рука B до правки, 4 из
#           3042: выдача, материализовавшаяся в середине подачи). Бюджет выше
#           него примерно в 8 раз, поэтому одиночный лаг не красит прогон;
#   сверху — класс, который бюджет ОБЯЗАН ловить, давал 61 %. Бюджет ниже него
#           примерно в 60 раз, поэтому потеря целого звена цепи не пролезет.
#
# `MAX_IAM_DIVERGED_SHARE` — рука C, доля 0.01 (1 %):
#   снизу — тот же измеренный транзиент 0.13 %. Он свойство ЧАСОВ сравнителя
#           (материализация догоняет в середине подачи), а не типа объекта,
#           поэтому переносится на эту руку как есть;
#   сверху — 100 %, и это ИЗМЕРЕНО чтением базы, а не выведено: на 2026-08-20
#           живых объектов пяти типов 640 (`iam_access_binding` 432 ·
#           `iam_user` 183 · `iam_service_account` 21 · `iam_role` 3 ·
#           `iam_group` 1), а звеньев цепи у них — 0 из 640. Пока звена нет,
#           расходится КАЖДЫЙ вопрос по этим типам, то есть класс, который бюджет
#           обязан ловить, даёт ровно 100 %. Бюджет ниже него в 100 раз.
# Запас в обе стороны двузначный, и он не подогнан под сегодняшнее число: на
# достроенной цепи замер обязан дать РОВНО НОЛЬ, а не «чуть ниже порога».
#
# ЧТО ЭТА ПРОБА СЕГОДНЯ ПОКАЖЕТ КРАСНЫМ — сказано заранее, чтобы красное не
# приняли за поломку прибора: до достройки звена (стадия S2) рука C обязана
# давать долю около 100 % и РОНЯТЬ прогон. Это и есть смысл правки — прибор,
# который прежде молчал о предмете, теперь о нём отказывает.
set -euo pipefail

NS="${NS:-kacho}"
RPS="${1:-100}"
DUR="${2:-30s}"
RUNNER="${RUNNER:-k6-iam-runner}"
MAX_DIVERGED_SHARE="${MAX_DIVERGED_SHARE-0.01}"
MAX_IAM_DIVERGED_SHARE="${MAX_IAM_DIVERGED_SHARE-0.01}"
SCRIPT_CM="${SCRIPT_CM:-k6-iam-check-script}"
FIXTURE="${FIXTURE_PATH:-/fixtures/allow_tuples.json}"
# Сводка сравнителя печатается службой раз в 30 с: дельту снимать раньше нельзя,
# она была бы неполной. Величина вынесена ручкой, чтобы часы прибора были
# УПРАВЛЯЕМЫ — герметичной пробе ждать нечего, и недетерминированный вход сделал
# бы её медленной и мигающей.
SETTLE="${SETTLE:-35}"
TREE_SCRIPT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/services/iam/tests/k6/internal_check.js"

k() { kubectl -n "$NS" "$@"; }
die_precond() { echo "УСЛОВИЕ НЕ СОЗДАНО: $*" >&2; exit 3; }

declare -A SHARE=()
declare -A COMPARED=()
declare -A DIVERGED=()

# ── 0. Провенанс СНАЧАЛА, до подачи ──────────────────────────────────────────
#
# Не педантизм, а цена промаха: вердикт, снятый против стенда, исполняющего чужую
# ревизию, относится к дереву, которого нет. Спрашивается ОБРАЗ ЗАПУЩЕННОГО пода,
# а не метка развёртывания — метка переживает перекат.
echo "── провенанс ─────────────────────────────────────────────"
pods=$(k get pod -l app.kubernetes.io/name=kacho-iam -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}')
[ -n "$pods" ] || die_precond "службы прав на стенде нет"
for p in $pods; do
  img=$(k get pod "$p" -o jsonpath='{.status.containerStatuses[0].imageID}')
  # `|| true` здесь ОБЯЗАТЕЛЕН и не является глушением ошибки: строкой ниже
  # отсутствие клейма печатается как «НЕ УСТАНОВЛЕНА», то есть тракт задуман
  # переживающим отсутствие. Без него `set -e` вместе с `pipefail` роняет пробу
  # МОЛЧА на любой машине, где нет `docker` или кластер не kind, — и вместо
  # честного «ревизия не установлена» оператор получает голый код 1 без строки.
  rev=$( { docker exec "${KIND_NODE:-kacho-control-plane}" crictl inspecti "$img" 2>/dev/null || true; } \
        | sed -n 's/.*"org.opencontainers.image.revision": "\([0-9a-f]*\)".*/\1/p' | head -1)
  echo "  под $p ревизия ${rev:-НЕ УСТАНОВЛЕНА (клейма нет)}"
done
echo "  реплик: $(echo "$pods" | wc -l), подача ${RPS} rps × ${DUR}"

# ── 1. Предусловия ───────────────────────────────────────────────────────────
k get pod "$RUNNER" >/dev/null 2>&1 || die_precond "генератора $RUNNER нет; поднимите его до пробы (deploy/load-tests/iam-check-runner.sh up)"
k exec "$RUNNER" -- sh -c "[ -s '$FIXTURE' ]" 2>/dev/null || die_precond "фикстуры $FIXTURE в генераторе нет или она пуста (deploy/load-tests/iam-check-runner.sh fixture)"
[ -f "$TREE_SCRIPT" ] || die_precond "прибора нет в дереве: $TREE_SCRIPT"

# ── 2. Прибор стенда обязан совпасть с деревом ───────────────────────────────
#
# Иначе проба мерит чужой прибор и называет это замером о дереве. Сверяется
# ФАЙЛ В ПОДЕ, а не ConfigMap: правка ConfigMap доезжает до тома не мгновенно, и
# «применили» здесь не равно «исполняется».
tree_md5=$(md5sum "$TREE_SCRIPT" | cut -d' ' -f1)
k create configmap "$SCRIPT_CM" --from-file=internal_check.js="$TREE_SCRIPT" \
  --dry-run=client -o yaml | k apply -f - >/dev/null
for _ in $(seq 1 24); do
  pod_md5=$(k exec "$RUNNER" -- md5sum /scripts/internal_check.js 2>/dev/null | cut -d' ' -f1 || true)
  [ "$pod_md5" = "$tree_md5" ] && break
  sleep 5
done
[ "${pod_md5:-}" = "$tree_md5" ] || { echo "прибор в поде ($pod_md5) не сошёлся с деревом ($tree_md5)" >&2; exit 1; }
echo "  прибор сверен с деревом: $tree_md5"

# ── 3. СОСТАВ ПОДАЧИ — до подачи, а не в отчёте после ────────────────────────
#
# Спрашивается у самого прибора (режим COMPOSITION_ONLY: одна итерация, ни одного
# обращения к службе), чтобы вывод типа делался ОДНИМ выражением на весь тракт.
# Второе выражение здесь, на оболочечном языке, разошлось бы с первым молча — и
# разошлось бы именно там, где расхождение не видно.
set +e
comp_out=$(k exec "$RUNNER" -- k6 run --quiet \
  -e COMPOSITION_ONLY=1 -e FIXTURE_PATH="$FIXTURE" /scripts/internal_check.js 2>&1)
comp_rc=$?
set -e

# Строки НЕ якорятся на начало: k6 обрамляет `console.log` своей записью журнала
# (`time=… level=info msg="…" source=console`), и якорь `^` не совпал бы НИ РАЗУ —
# состав молча оказался бы «не получен» на исправном приборе. Проверено прогоном
# настоящего k6, а не прочитано: первая редакция этих выражений была якорной.
comp_total=$(printf '%s\n' "$comp_out" | sed -n 's/.*ФИКСТУРА-СОСТАВ всего \([^"]*\).*/\1/p' | tail -1)
comp_own=$(printf '%s\n' "$comp_out"   | sed -n 's/.*ФИКСТУРА-СВОИ \([0-9][0-9]*\).*/\1/p' | tail -1)
own_types=$(printf '%s\n' "$comp_out"  | sed -n 's/.*ФИКСТУРА-СВОИ-ТИПЫ \([a-z_,]*\).*/\1/p' | tail -1)
type_lines=$(printf '%s\n' "$comp_out" | sed -n 's/.*ФИКСТУРА-ТИП \([a-z_]*\) \([0-9][0-9]*\).*/\1 \2/p')
class_pr=$(printf '%s\n' "$comp_out"   | sed -n 's/.*ФИКСТУРА-КЛАСС project_role \([0-9][0-9]*\).*/\1/p' | tail -1)

# Вердикт не зависит от кода возврата трубы: он зависит от того, ПУСТА ли
# захваченная строка. `grep -q` в трубе выходит до конца входа, писатель слева
# получает SIGPIPE, и под `pipefail` найденное объявляется ненайденным (#658).
if [ -z "$comp_total" ] || [ -z "$comp_own" ] || [ -z "$own_types" ]; then
  echo "состав подачи не получен (k6 rc=$comp_rc); прибор обязан печатать его сам" >&2
  printf '%s\n' "$comp_out" | tail -20 >&2
  exit 1
fi

echo "── состав подачи ─────────────────────────────────────────"
while read -r ty n; do
  [ -n "$ty" ] || continue
  printf '  %-26s %6s\n' "$ty" "$n"
done <<<"$type_lines"
echo "  всего троек $comp_total; из них пяти собственных типов iam — $comp_own"
echo "  класс «проектная роль» (ожидаемое расхождение, Р3): троек — ${class_pr:-0}"

# Ноль объектов предмета — ТРЕТИЙ исход. Доля, снятая на такой подаче, об этих
# типах не утверждает ничего, и засчитывать её как утверждение о них — ровно тот
# дефект, который свёл 0.00 % пробы с 15 085 потерянными объектами переписи.
if [ "${comp_own:-0}" -eq 0 ]; then
  echo "  подача не содержит НИ ОДНОГО объекта пяти собственных типов iam" >&2
  die_precond "в подаче ноль объектов пяти собственных типов iam ($own_types): доля расхождений, снятая на ней, об этих типах НЕ УТВЕРЖДАЕТ НИЧЕГО, поэтому вердикт по бюджету здесь не выносится вовсе. Постройте подачу генератором: deploy/load-tests/iam-check-runner.sh fixture"
fi

# ── 4. Счётчики сравнителя: сумма ПОСЛЕДНЕЙ сводки каждой реплики ────────────
counters() {
  local tot_c=0 tot_d=0 seen=0 line c d
  for p in $pods; do
    line=$(k logs "$p" --tail=600 2>/dev/null | grep 'shadow verdict: сводка' | tail -1 || true)
    [ -n "$line" ] || continue
    c=$(printf '%s' "$line" | sed -n 's/.*"compared":\([0-9]*\).*/\1/p')
    d=$(printf '%s' "$line" | sed -n 's/.*"diverged":\([0-9]*\).*/\1/p')
    tot_c=$((tot_c + ${c:-0})); tot_d=$((tot_d + ${d:-0})); seen=$((seen + 1))
  done
  echo "$tot_c $tot_d $seen"
}

arm() { # arm <ключ> <ALLOW_RATIO> <имя> [доп. -e …]
  local key="$1" ratio="$2" name="$3"; shift 3
  local c0 d0 s0 c1 d1 out rc_run
  read -r c0 d0 s0 <<<"$(counters)"
  [ "$s0" -gt 0 ] || { echo "сводки сравнителя нет ни у одной реплики — мерить нечем" >&2; exit 1; }
  # Код возврата k6 вердиктом НЕ является: превышенный порог чтения (`p(99)<30`)
  # роняет k6, оставляя замер годным. Поэтому решает движение счётчиков, а вывод
  # прогона сохраняется, чтобы на «сравнений 0» назвать ПРИЧИНУ текстом, а не
  # именем шага.
  set +e
  out=$(k exec "$RUNNER" -- k6 run --quiet \
     -e TARGET_RPS="$RPS" -e DURATION="$DUR" -e ALLOW_RATIO="$ratio" \
     -e FIXTURE_PATH="$FIXTURE" "$@" /scripts/internal_check.js 2>&1)
  rc_run=$?
  set -e
  sleep "$SETTLE"
  read -r c1 d1 _ <<<"$(counters)"
  local dc=$((c1 - c0)) dd=$((d1 - d0))
  if [ "$dc" -le 0 ]; then
    printf '  %s — сравнений 0, ИЗМЕРИТЬ НЕ УДАЛОСЬ\n' "$name"
    echo "  причина — вывод прогона (k6 rc=$rc_run):" >&2
    printf '%s\n' "$out" | tail -8 >&2
    return 1
  fi
  # Колонки НЕ выравниваются шириной поля: имена рук по-русски, а `printf`
  # считает БАЙТЫ, поэтому кириллица разъезжается тем сильнее, чем длиннее имя.
  # «Сравнено» обязано стоять В ОДНОЙ СТРОКЕ с «разошлось» — доля без знаменателя
  # вердиктом не является, и разнесение их по строкам это свойство ослабило бы.
  printf '  %s — сравнено %d, разошлось %d, доля %s %%\n' \
    "$name" "$dc" "$dd" "$(awk -v a="$dd" -v b="$dc" 'BEGIN{printf "%.2f", 100*a/b}')"
  SHARE[$key]=$(awk -v a="$dd" -v b="$dc" 'BEGIN{print a/b}')
  COMPARED[$key]=$dc
  DIVERGED[$key]=$dd
}

echo "── руки ──────────────────────────────────────────────────"
rc=0
arm a 1.0 "A: выдачи стенда без собственных типов iam"      -e FEED_TYPES="not:$own_types"  || rc=1
arm b 0.0 "B: перестановки без собственных типов iam"       -e FEED_TYPES="not:$own_types"  || rc=1
arm c 1.0 "C: пять собственных типов iam (без «проектной роли»)" \
     -e FEED_TYPES="only:$own_types" -e FEED_CLASS="not:project_role"                       || rc=1
if [ "${class_pr:-0}" -gt 0 ]; then
  arm d 1.0 "D: класс «проектная роль» — ОЖИДАЕМОЕ расхождение" \
       -e FEED_TYPES="only:iam_role" -e FEED_CLASS="only:project_role"                      || rc=1
else
  echo "  D: класс «проектная роль» — УСЛОВИЕ НЕ СОЗДАНО: в подаче 0 таких троек."
  echo "     Класс назван ЗАРАНЕЕ и в общую долю не попадёт; его знаменатель пуст,"
  echo "     и пустой знаменатель здесь не «ноль расхождений», а «нечего мерить»."
fi
[ "$rc" -eq 0 ] || exit 1


# ── R7-4-12: РАСХОЖДЕНИЕ РАЗЛОЖЕНО ПО НАПРАВЛЕНИЮ И ПО ТИПУ ──────────────────
#
# Доля отвечает «сколько», и по ней НЕЛЬЗЯ действовать: «форма отказала, решатель
# разрешил» — недоданный доступ, виден пользователю сразу; «форма разрешила,
# решатель отказал» — ЛИШНИЙ доступ, не виден никому. Слить их в одно число
# значит потерять именно ту сторону, которая тише и опаснее.
#
# Разложение НЕ ИЗОБРЕТАЕТСЯ здесь: сравнитель уже кладёт его в сводку. Ключ
# класса имеет вид `<вопрос>|<тип объекта>|<отношение>|движок=<да|нет>`, и
# `движок=true` при расхождении означает «решатель разрешил, форма отказала», а
# `движок=false` — обратное. Заводить второй счётчик значило бы завести второе
# место об одном предмете.
classes_breakdown() {
  local line
  for p in $pods; do
    line=$(k logs "$p" --tail=600 2>/dev/null | grep 'shadow verdict: сводка' | tail -1 || true)
    [ -n "$line" ] || continue
    printf '%s' "$line" | sed -n 's/.*"class_breakdown":"\([^"]*\)".*/\1/p'
  done
}

# split_classes печатает `<направление>|<тип объекта>|<число>` по одной строке —
# ТОЛЬКО для классов РАСХОЖДЕНИЯ.
#
# # Почему классы разделяются по РОДУ, а не разбираются все подряд
#
# Сводка сравнителя перечисляет классы ВСЕХ исходов: расхождение, «не
# выполнилось» (движок или форма не ответили в срок), «спросить нельзя».
# Направление есть только у первого рода — у остальных его нет и быть не может.
#
# Прежняя редакция разбирала подряд всё и объявляла «N классов расхождения не
# разобраны по направлению» на классах, расхождением не являющихся. На прогоне с
# НУЛЁМ расхождений это давало отказ прибора, выданный за находку о продукте, —
# то есть ровно ту ошибку, ради ловли которой прибор и написан. Класс всплыл,
# когда теневым стал движок: до этого «не выполнилось» на нём просто не
# случалось, и разбор был зелёным по отсутствию предмета, а не по верности.
#
# Разбор БЕЗ трубы, решающей вердикт: `grep -q` слева от неё получает SIGPIPE, и
# под `pipefail` найденное объявляется ненайденным.
split_classes() {
  local raw entry key n objtype dir
  raw="$(classes_breakdown)"
  # Разделитель — ` ;; `, а НЕ пробел: ключ класса содержит пробелы («прямой
  # вердикт», «движок вердикта не дал»), и разбиение по пробелу режет его на
  # слова. Разделитель объявлен сравнителем (`ClassBreakdownSeparator`) и
  # закреплён его пробой — здесь он читается, а не выбирается заново.
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    key="${entry%×*}"; n="${entry##*×}"
    [ "$key" != "$entry" ] || continue
    # Классы НЕ-расхождения отсеиваются ПО ПРИСТАВКЕ рода, которую пишет сам
    # сравнитель. Их число печатается отдельной строкой ниже: молча выбросить
    # их значило бы потерять «сколько сверок не состоялось» — величину, без
    # которой «расхождений ноль» читается шире, чем измерено.
    case "$key" in
      "не выполнилось|"*|"не задан|"*) continue ;;
    esac
    objtype="$(printf '%s' "$key" | cut -d'|' -f2)"
    case "$key" in
      *"движок=true")  dir="форма отказала, решатель разрешил" ;;
      *"движок=false") dir="форма разрешила, решатель отказал" ;;
      *)               dir="направление НЕ РАЗОБРАНО" ;;
    esac
    printf '%s|%s|%s\n' "$dir" "$objtype" "$n"
  done <<<"$(printf '%s' "$raw" | sed 's/ ;; /\n/g')"
}

# other_classes печатает классы НЕ-расхождения: род и число.
#
# Они не вердикт, но и не шум: «сверка не состоялась N раз» — своя корзина, и
# «ноль расхождений» при большой этой корзине означает не согласие, а тишину.
other_classes() {
  local raw entry key n
  raw="$(classes_breakdown)"
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    key="${entry%×*}"; n="${entry##*×}"
    [ "$key" != "$entry" ] || continue
    case "$key" in
      # Разделитель полей — ТАБУЛЯЦИЯ, а не `|`: ключ класса сам состоит из
      # частей, разделённых `|`, и разбор читателя по `|` роняет ключ в первое
      # поле, а всё остальное — во второе. Строка при этом печатается, выглядит
      # осмысленной и называет не те величины.
      "не выполнилось|"*|"не задан|"*) printf '%s\t%s\n' "$n" "$key" ;;
    esac
  done <<<"$(printf '%s' "$raw" | sed 's/ ;; /\n/g')"
}

echo "── расхождения по направлению и по типу ──────────────────"
split_raw="$(split_classes)"
if [ -z "$split_raw" ]; then
  echo "  классов расхождения не объявлено ни одной репликой."
  echo "  Это НЕ «расхождений нет»: сводка могла не доехать. Знаменатель — «сравнено»"
  echo "  каждой руки выше; если он ноль, вердикт по этой руке не выносится вовсе."
else
  unparsed=0
  while IFS='|' read -r dir objtype n; do
    [ -n "$dir" ] || continue
    printf '  %-38s %-24s %s\n' "$dir" "$objtype" "$n"
    case "$dir" in *"НЕ РАЗОБРАНО"*) unparsed=$((unparsed + 1)) ;; esac
  done <<<"$split_raw"
  if [ "$unparsed" -gt 0 ]; then
    echo "  ОТКАЗ: $unparsed классов расхождения не разобраны по направлению." >&2
    echo "  Форма ключа сравнителя разошлась с разбором прибора: «сколько» есть, а" >&2
    echo "  «в какую сторону» — нет, и действовать по такому числу нельзя." >&2
    rc=1
  fi
fi

# Классы НЕ-расхождения — своя строка и свой счёт.
#
# «Расхождений ноль» при непустой этой корзине означает не согласие, а частичную
# тишину: сверка не состоялась столько-то раз. Знаменатель — «сравнено» рук выше.
other_raw="$(other_classes)"
if [ -n "$other_raw" ]; then
  echo "── сверки, которые НЕ состоялись (не расхождение) ─────────"
  while IFS=$'\t' read -r n key; do
    [ -n "$key" ] || continue
    printf '  %-6s %s\n' "$n" "$key"
  done <<<"$other_raw"
  echo "  Это не вердикт и не шум: доля таких сверок ограничивает то, о чём"
  echo "  «расхождений ноль» вообще утверждает."
fi

echo "── вердикт ───────────────────────────────────────────────"
awk -v a="${SHARE[a]}" -v b="${SHARE[b]}" 'BEGIN{
  if (a>=0.05 && b<0.05)      print "  расходятся НАСТОЯЩИЕ выдачи; перестановка ни при чём";
  else if (a<0.05 && b>=0.05) print "  расхождение — артефакт перестановки (чинить прибор)";
  else if (a>=0.05 && b>=0.05)print "  расходятся ОБЕ подачи — два разных предмета, разбирать порознь";
  else                        print "  расхождений нет ни на одной подаче";
}'
