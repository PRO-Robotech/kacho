  echo "     ограничению схемы и нет отношения «проект» в модели, поэтому форма отвечает"
  echo "     раньше каскада движка. Материализация догоняет, каскад не догонит никогда."
fi

# Бюджеты считаются ОБА, даже когда первый не выдержан: оператору нужны обе
# величины, а не первая попавшаяся.
budget() { # budget <ключ> <бюджет> <имя> <текст отказа>
  local key="$1" limit="$2" label="$3" refusal="$4"
  if [ -z "$limit" ]; then
    echo "  БЮДЖЕТ СНЯТ ЯВНО ($label=\"\") — эта рука ТОЛЬКО отчитывается и не удерживает"
    echo "  ничего. Снимать его допустимо для разового замера, но не в конвейере."
    return 0
  fi
  awk -v a="${SHARE[$key]}" -v m="$limit" -v r="$refusal" -v l="$label" 'BEGIN{
    if (a>m) { printf "  ОТКАЗ: %s %.4f выше бюджета %.4f (%s)\n", r, a, m, l; exit 1 }
    printf "  %s выдержан: %.4f <= %.4f\n", l, a, m;
  }' || return 1
}
