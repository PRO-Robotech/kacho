// Служба доступа с kaname#494 (ветка эпика 357, слияние волны-5) не строит
// дороги обмена подписанного утверждения у прежнего издателя: ни адреса его
// token-эндпоинта, ни якоря доверия к нему, ни его издателя она не читает.
// Подчарт выпускал все три — двумя переменными процесса и ключом карты
// настроек — из трёх ручек значений, и выпуск снят вместе с ручками.
//
// Судится отказ: профиль, объявивший любую из трёх ручек — значением или
// пустой строкой, — получает отказ рендера с именем ручки, а не значение,
// которого шаблон больше не читает. Близнец — те же умолчания без ручки —
// рендерится. Пока ручка жила, рендер с ней проходил и нёс провязку
// поставщика; отказ называет число её следов в рендере, если рендер прошёл.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ПРОВЕРКА НЕ УТВЕРЖДАЕТ — И КТО ДЕРЖИТ ОСТАЛЬНОЕ
//
// Что рендер подчарта значениями каждого стека и его умолчаниями не несёт
// провязки поставщика ни переменной процесса, ни ключом карты настроек, держит
// TestKanameSubchartRendersNoVendorWiring (kacho#2818): его перепись читает
// обе формы, которыми дорога выпускалась. Полный рендер зонта каждой цепочкой —
// TestNoStackRenderCarriesAVendorResidue под тегом `helmcharts`. Сквозной
// перечень `env` подчарта — сырой вход оператора, а не ручка, и отказа на нём
// не заводится.
package deploy_test

import (
	"strings"
	"testing"
)

// retiredExchangeRoadKnobs — ручки дороги обмена в значениях подчарта так, как
// их писал профиль: адрес token-эндпоинта, якорь доверия хопа, издатель.
// Литералы, а не ссылки на объявление: проба судит, что отвергается ИМЕННО то,
// что оператор мог написать, и строка стража, переименованная по ошибке, не
// должна утащить пробу за собой.
var retiredExchangeRoadKnobs = []string{
	"platform.iam.hydraTokenURL",
	"platform.iam.hydraTokenCaFile",
	"config.authn.hydraIssuer",
}

// TestKanameSubchartRefusesTheRetiredExchangeRoadKnobs — отказ рендера на
// каждой снятой ручке дороги обмена при любом значении.
func TestKanameSubchartRefusesTheRetiredExchangeRoadKnobs(t *testing.T) {
	if out, err := renderIdentitySubchart(t, nil); err != nil {
		t.Fatalf("близнец: подчарт на своих умолчаниях обязан рендериться: %v\n%s", err, out)
	}
	judged := 0
	for _, knob := range retiredExchangeRoadKnobs {
		for _, v := range []string{"https://retired.invalid/x", `""`} {
			judged++
			out, err := renderIdentitySubchart(t, nil, knob+"="+v)
			if err == nil {
				t.Errorf("профиль объявил `%s=%s`, и подчарт отрендерился: снятая ручка принята "+
					"(следов поставщика в рендере %d) — оператор читает её как действующую дорогу",
					knob, v, len(judgeVendorWiring(knob, renderedDocs(t, out))))
				continue
			}
			for _, want := range []string{knob, "снята", "Уберите"} {
				if !strings.Contains(out, want) {
					t.Errorf("отказ рендера на `%s=%s` не называет %q — оператор не узнает, что убрать:\n%s",
						knob, v, want, out)
				}
			}
		}
	}
	t.Logf("перепись: ручек %d · объявлений осуждено %d", len(retiredExchangeRoadKnobs), judged)
}
