// identity_config_reaches_the_process_test.go — конфигурация, объявляющая полосы
// обратных вызовов, обязана ДОЕЗЖАТЬ до процесса, который эти полосы исполняет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ, И ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ СОСЕДНЕЙ ПРОВЕРКИ
//
// Рядом живёт identity_callback_transport_test.go. Она спрашивает, каким
// ТРАНСПОРТОМ объявлена полоса, и делает это верно. Но вопроса «а читает ли
// кто-нибудь тот файл, где полоса объявлена» она не задаёт — и не обязана.
//
// Поэтому дефект её пережил: объявление полос лежало в карте настроек, которую
// НИКТО НЕ МОНТИРОВАЛ. Обе полосы — заведение пользователя и завершение
// восстановления доступа — были описаны правильно, защищённым транспортом, с
// верными адресами, и не исполнялись ни на одном стенде. Со стороны это
// неотличимо от исправной работы: шаблон рендерится, карта настроек в кластере
// есть, транспорт объявлен, соседняя проверка зелёная.
//
// Это тот же класс, что «форма проверки без содержания», только на уровне
// посадки: объявлено всё, не работает ничто.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
// Карта настроек, чьё СОДЕРЖИМОЕ несёт путь маршрута обратных вызовов, обязана
// быть смонтирована — либо шаблоном нашего же чарта, либо профилем через
// дополнительные тома подчарта поставщика. Где именно — проверке безразлично;
// ей важно, что монтирование ЕСТЬ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПЕРЕЧЕНЬ КАРТ ВЫВОДИТСЯ, А НЕ ВЫПИСАН
//
// Выписанный перечень разошёлся бы при заведении следующей карты молча. Карты
// находятся обходом шаблонов по признаку содержимого — пути маршрута хуков, —
// поэтому новая карта попадает под проверку сама, а снятая уходит из-под неё
// вместе со своим файлом.
//
// # ЧЕМ ДОКАЗАН КОНТРОЛЬ В ОБРАТНУЮ СТОРОНУ
//
// Отрицание без положительного контроля зеленеет на всём сломанном, поэтому
// законный близнец обязан быть и обязан молчать. Он есть в самом дереве: карт
// настроек службы личности три, а под проверку подпадают ДВЕ — третья
// (схема личности) маршрута обратных вызовов не несёт и носителем не считается.
// Перепись печатает оба числа, поэтому расширение проверки на всё подряд
// станет видно сразу.
//
// Способность упасть доказана возвратом дефекта: до провязки обе несущие карты
// назывались поимённо и проверка краснела; после — молчит, а перепись остаётся
// той же.
//
// ПОЧЕМУ БЕЗ helm. Проверка читает ОБЪЯВЛЕНИЕ (шаблоны и значения), а не
// рендер: рендер требует скачанных зависимостей и потому пропускается там, где
// их нет, — а пропущенная проверка не краснеет никогда.
package deploy_test

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// hookRouteMarker — путь маршрута обратных вызовов. Именно он делает карту
// настроек НЕСУЩЕЙ полосы: адрес слушателя может смениться, имя чарта тоже, а
// маршрут — часть контракта обработчика.
const hookRouteMarker = "/iam/v1/hooks/"

// configMapNameDecl вынимает имя карты настроек из её объявления. Имя
// сравнивается ВЫРАЖЕНИЕМ, а не строкой: в шаблоне оно собирается вызовом
// именованного шаблона, и рендерить его здесь нечем.
var configMapNameDecl = regexp.MustCompile(`(?m)^\s*name:\s*(\S.*?)\s*$`)

// nameTail — хвост имени после последней закрывающей скобки шаблона. Он и есть
// та часть, которая отличает одну карту от другой (`…-kratos-config`), и по
// которой монтирование можно узнать, не рендеря чарт.
var nameTail = regexp.MustCompile(`}}\s*(-[a-z0-9-]+)\s*$`)

// volumeSourceNames собирает имена карт настроек, названные ИСТОЧНИКОМ ТОМА.
// Признак — строка `configMap:`, после которой в пределах её блока стоит `name:`.
// Отступ блока берётся по самой строке `configMap:`, поэтому соседний ключ того
// же уровня выход из блока обозначает сам.
func volumeSourceNames(body string) []string {
	var out []string
	lines := strings.Split(body, "\n")
	for i, ln := range lines {
		if strings.TrimSpace(ln) != "configMap:" {
			continue
		}
		indent := len(ln) - len(strings.TrimLeft(ln, " "))
		for j := i + 1; j < len(lines); j++ {
			cur := lines[j]
			if strings.TrimSpace(cur) == "" {
				continue
			}
			ci := len(cur) - len(strings.TrimLeft(cur, " "))
			if ci <= indent {
				break
			}
			if m := configMapNameDecl.FindStringSubmatch(cur); m != nil {
				out = append(out, strings.Trim(m[1], `"'`))
				break
			}
		}
	}
	return out
}

func TestIdentityCallbackConfigIsMountedSomewhere(t *testing.T) {
	charts, err := filepath.Glob(filepath.Join(umbrellaDir, "charts", "*", "templates", "*.yaml"))
	if err != nil {
		t.Fatalf("обход шаблонов подчартов: %v", err)
	}
	profiles, err := filepath.Glob(filepath.Join(umbrellaDir, "values*.yaml"))
	if err != nil {
		t.Fatalf("обход профилей: %v", err)
	}
	if len(charts) == 0 || len(profiles) == 0 {
		t.Fatalf("корпус пуст: шаблонов %d, профилей %d — проверять нечего, "+
			"и это отказ, а не успех", len(charts), len(profiles))
	}

	// Монтированием считается имя, стоящее ВНУТРИ объявления тома, а не любое
	// упоминание: путь к файлу нагрузки, ссылка в прозе комментария и имя в
	// собственном объявлении карты — не монтирования. Без этого различения
	// проверка зеленеет на карте, чьё имя просто где-то встретилось.
	mounts := map[string]int{}
	for _, p := range append(append([]string{}, charts...), profiles...) {
		b, rerr := os.ReadFile(p) // #nosec G304 -- пути получены обходом собственного дерева
		if rerr != nil {
			t.Fatalf("чтение %s: %v", p, rerr)
		}
		for _, name := range volumeSourceNames(string(b)) {
			mounts[name]++
		}
	}

	var carriers, mounted int
	for _, p := range charts {
		b, rerr := os.ReadFile(p) // #nosec G304 -- пути получены обходом собственного дерева
		if rerr != nil {
			t.Fatalf("чтение %s: %v", p, rerr)
		}
		body := string(b)
		if !strings.Contains(body, "kind: ConfigMap") || !strings.Contains(body, hookRouteMarker) {
			continue
		}
		carriers++

		tail := ""
		for _, m := range configMapNameDecl.FindAllStringSubmatch(body, -1) {
			if t2 := nameTail.FindStringSubmatch(m[1]); t2 != nil {
				tail = t2[1]
				break
			}
		}
		if tail == "" {
			t.Errorf("%s: несёт объявление полос, но её имя не разбирается — "+
				"проверка не может установить, монтируется ли она", filepath.Base(p))
			continue
		}

		outside := 0
		for name, n := range mounts {
			if strings.HasSuffix(name, tail) {
				outside += n
			}
		}
		if outside <= 0 {
			t.Errorf("%s: карта настроек несёт объявление полос обратных вызовов (%s), "+
				"но НИКТО её не монтирует — объявленное поведение не исполняется ни на одном стенде",
				filepath.Base(p), tail)
			continue
		}
		mounted++
	}

	t.Logf("осмотрено: шаблонов подчартов %d, профилей %d; карт настроек с объявлением полос %d, "+
		"из них смонтировано %d", len(charts), len(profiles), carriers, mounted)

	if carriers == 0 {
		t.Fatalf("карт настроек с объявлением полос не найдено ни одной — "+
			"либо маршрут %q сменился, либо обход слеп; «ноль находок» здесь "+
			"неотличимо от «ноль прочитанного», поэтому это отказ", hookRouteMarker)
	}
}
