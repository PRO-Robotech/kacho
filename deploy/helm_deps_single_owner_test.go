// helm_deps_single_owner_test.go — материализацию зависимостей умбреллы
// выполняет ОДИН владелец, и каждый, кому она нужна, зовёт его.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// `helm dep update` по умбрелле — это не локальная операция: он ходит в сеть за
// КАЖДОЙ объявленной зависимостью (замер на этом дереве: 22 объявления, полный
// проход 3 мин 22 с, mtime всех `charts/*.tgz` обновляется, то есть архивы
// скачиваются заново на КАЖДОМ вызове — повторный вызов ничего не переиспользует).
//
// Пока каждый, кому нужен отрендеренный чарт, звал его сам, один прогон job'а
// делал это до десяти раз. Стоило это не только времени: каждый проход — это
// независимая возможность отказа у постороннего хоста, а отказ ЛЮБОГО из них
// красит весь job. Ровно так и вышло: два прогона подряд на релизной ветке упали
// на подкачке одной и той же зависимости, в разных местах — сначала на отдельном
// шаге конвейера, потом внутри самопроверки одного из гейтов. Причина у второго
// была ПРОГЛОЧЕНА (`>/dev/null 2>&1`), и вердикт читался как «FAIL: helm dep
// update» без единого слова о том, что именно не скачалось.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ТРЕБУЕТСЯ
//
// Единственный владелец — `deploy/scripts/helm-umbrella-deps.sh`. Он
//
//	· пропускает поход в сеть, когда зависимости УЖЕ материализованы и отпечаток
//	  исходников не изменился (то есть повторный вызов внутри одного прогона
//	  ничего не стоит, а правка локального сабчарта по-прежнему пересобирает);
//	· печатает вывод helm ЦЕЛИКОМ при отказе — причина не глотается;
//	· повторяет попытку ограниченное число раз, потому что отказ постороннего
//	  хоста — это не находка о дереве.
//
// Гейт требует свойства от ДЕРЕВА, а не от одного файла: любой новый вызов
// `helm dep update` мимо владельца — находка, включая тот, которого ещё нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРЕДИКАТ ЧИТАЕТ ПОЗИЦИЮ КОМАНДЫ, А НЕ СЛОВО
//
// Слово `helm dep update` стоит в дереве два десятка раз в прозе, в подсказках
// оператору (`echo "  Собрать: (cd $UMBRELLA && helm dep update)"`) и в
// сообщениях об отказе. Поиск по слову объявил бы находкой каждую из них — и
// первый же ложный срабат снял бы гейт целиком. Поэтому находкой считается
// только ВЫЗОВ: позиция команды (начало строки, `;`, `&&`, `||`, `|`, `(`,
// `$(`, либо `run:` в определении конвейера) и не внутри строкового литерала.
// Обе стороны предиката доказаны инъекцией — TestHelmDepPredicateReadsCommands.
package deploy_test

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/gitenv"
)

// helmDepsOwner — единственный файл дерева, которому позволено звать helm за
// зависимостями умбреллы. Путь от корня репозитория.
const helmDepsOwner = "deploy/scripts/helm-umbrella-deps.sh"

// helmDepsExempt — послабления с причиной. Запись, у которой в дереве не
// осталось ни одного вызова, — НАХОДКА: послабление обязано истекать само,
// иначе оно переживает свой предмет и становится слепой зоной.
var helmDepsExempt = map[string]string{
	"deploy/helm/umbrella/cutover-fe3455.sh": "процедура оператора для переката площадки, " +
		"а не проверка: она намеренно берёт `dependency build` ради пинов и исполняется " +
		"рукой один раз за перекат, вне прогона конвейера",
}

// helmDepCall — вызов helm за зависимостями в ПОЗИЦИИ КОМАНДЫ.
// `run:` — форма определения конвейера; двоеточие в позицию команды больше
// ничего не приводит, потому что литералы отсекаются отдельно (см. ниже).
var helmDepCall = regexp.MustCompile(`(^|[;&|(:]|\$\()[ \t]*helm[ \t]+dep(endency)?[ \t]+(update|build)\b`)

// helmDepCallSite — находка предиката: смещение начала совпадения нужно, чтобы
// отличить вызов от упоминания внутри строкового литерала.
func helmDepCallSite(line string) bool {
	trimmed := strings.TrimSpace(line)
	// Комментарий — объяснение, а не вызов. Форма `//` нужна не для симметрии:
	// без неё первый же файл на js/go красили бы его собственные пояснения.
	if strings.HasPrefix(trimmed, "#") || strings.HasPrefix(trimmed, "//") {
		return false
	}
	loc := helmDepCall.FindStringIndex(line)
	if loc == nil {
		return false
	}
	prefix := line[:loc[0]]
	// ПОРЯДОК ЗДЕСЬ — ЧАСТЬ ПРЕДИКАТА, А НЕ ОФОРМЛЕНИЕ. Обратная кавычка
	// разбирается ПЕРВОЙ, до всякого разговора о позиции команды: в Go она
	// открывает сырой литерал, и внутри него лежат фикстуры инъекции самого
	// этого гейта — настоящие формы вызова, по тексту от вызова неотличимые.
	// Пропусти её вперёд другой ветки — и гейт находит САМ СЕБЯ, а первый же
	// такой ложный срабат снимает его целиком.
	//
	// Размен назван честно: вызов, записанный УСТАРЕВШЕЙ подстановкой
	// (`` `helm dep update` `` вместо `$(…)`), предикат пропустит — отличить его
	// от разметки прозы по тексту нельзя. В дереве такой формы нет ни одной, а
	// современная подстановка `$(…)` предикатом узнаётся.
	if strings.Count(prefix, "`")%2 == 1 {
		return false
	}
	// ПОДСТАНОВКА `$(…)` — ПОЗИЦИЯ КОМАНДЫ, ДАЖЕ СТОЯ ВНУТРИ КАВЫЧЕК: кавычки
	// закрывают текст, а подстановку — нет, и то, что внутри неё, исполняется.
	//
	// Без этих двух веток предикат пропускал вызов, ЖИВШИЙ В ЭТОМ ЖЕ ДЕРЕВЕ:
	// обёртка повтора подкачки захватывала вывод как `log="$(helm dep update
	// 2>&1)"`, и гейт, объявляющий «владелец один», её НЕ ВИДЕЛ — то есть
	// держал свойство ровно до первой строки самой ходовой формы захвата.
	//
	// (а) подстановка начинает само совпадение: `x="$(helm dep update)"`.
	if strings.HasPrefix(line[loc[0]:], "$(") {
		return true
	}
	// (б) совпадение стоит ВНУТРИ незакрытой подстановки:
	// `out="$( cd "$U" && helm dep update )"`. Кавычки снаружи подстановки к
	// её содержимому отношения не имеют, поэтому чётность считается только по
	// хвосту — от последней незакрытой `$(`.
	if i := strings.LastIndex(prefix, "$("); i >= 0 && !strings.Contains(prefix[i+2:], ")") {
		prefix = prefix[i+2:]
	}
	// Внутри строкового литерала — подсказка оператору или текст отказа.
	// Нечётное число кавычек слева означает, что совпадение стоит внутри
	// незакрытой строки.
	if strings.Count(prefix, `"`)%2 == 1 || strings.Count(prefix, `'`)%2 == 1 {
		return false
	}
	return true
}

// helmDepScannable — файлы, из которых команду вообще можно исполнить.
func helmDepScannable(path string) bool {
	if filepath.Base(path) == "Makefile" {
		return true
	}
	switch filepath.Ext(path) {
	case ".sh", ".py", ".js", ".go", ".yaml", ".yml", ".mk", ".bash":
		return true
	}
	return false
}

func TestUmbrellaDepsHaveASingleOwner(t *testing.T) {
	root := ".."
	out, err := gitenv.Command(root, "ls-files", "-z").Output()
	if err != nil {
		t.Fatalf("git ls-files не отработал (%v) — обход не прочитал НИ ОДНОГО файла, "+
			"и «ноль находок» здесь ничего не значило бы", err)
	}
	files := strings.Split(strings.TrimRight(string(out), "\x00"), "\x00")

	scanned := 0
	calls := map[string][]string{}
	for _, f := range files {
		if f == "" || !helmDepScannable(f) {
			continue
		}
		// #nosec G304 -- путь приходит из содержимого репозитория, не извне.
		raw, err := os.ReadFile(filepath.Join(root, f))
		if err != nil {
			continue
		}
		scanned++
		for i, line := range strings.Split(string(raw), "\n") {
			if helmDepCallSite(line) {
				// Координата — часть находки: без номера строки правка
				// начинается с поиска, а на длинном Makefile это не мелочь.
				calls[f] = append(calls[f], fmt.Sprintf("%d: %s", i+1, strings.TrimSpace(line)))
			}
		}
	}

	t.Logf("осмотрено исполнимых файлов дерева: %d; файлов с вызовом helm за зависимостями: %d",
		scanned, len(calls))
	if scanned == 0 {
		t.Fatal("обход не прочитал ни одного файла — совпадение пустого с пустым не является " +
			"доказательством чего-либо")
	}

	if _, err := os.Stat(filepath.Join(root, helmDepsOwner)); err != nil {
		t.Errorf("владельца %s в дереве нет (%v) — требовать «звать владельца» не у кого",
			helmDepsOwner, err)
	}
	if len(calls[helmDepsOwner]) == 0 {
		t.Errorf("%s не зовёт helm за зависимостями сам — владелец, который ничего не "+
			"материализует, оставляет остальных без того, ради чего они к нему ходят",
			helmDepsOwner)
	}

	for f, lines := range calls {
		if f == helmDepsOwner {
			continue
		}
		if _, ok := helmDepsExempt[f]; ok {
			continue
		}
		t.Errorf("%s зовёт helm за зависимостями умбреллы сам (%d вызов(а)): %s\n"+
			"    Каждый такой вызов — отдельный поход в сеть за всеми объявленными "+
			"зависимостями и отдельная возможность уронить прогон отказом постороннего "+
			"хоста. Зови %s: повторный вызов внутри одного прогона ничего не стоит, а "+
			"причина отказа не глотается.",
			f, len(lines), strings.Join(lines, " ⏎ "), helmDepsOwner)
	}

	// Послабление живёт, пока у него есть предмет.
	for f, why := range helmDepsExempt {
		if len(calls[f]) == 0 {
			t.Errorf("послаблению для %s больше нечего извинять (причина записи: %s) — "+
				"вызова в этом файле не осталось. Снимите запись: она унаследует "+
				"следующую слепую зону", f, why)
		}
	}
}

// TestHelmDepPredicateReadsCommands — инъекция в ОБЕ стороны: предикат обязан
// поймать заведомый вызов в каждой встречающейся форме и промолчать на законном
// упоминании той же формы.
func TestHelmDepPredicateReadsCommands(t *testing.T) {
	defects := []string{
		`helm dep update`,
		`helm dependency build .`,
		`( cd helm/umbrella && helm dep update >/dev/null ); \`,
		`( cd "$UMBRELLA" && helm dep update >/dev/null 2>&1 ) \`,
		`cd helm/umbrella; helm dependency update`,
		`        run: helm dependency build`,
		`out=$(helm dep update 2>&1)`,
		`prep || helm dep update`,
		// Захват вывода в кавычках — самая частая форма, и предикат её
		// пропускал: кавычка слева ровно одна, а подстановка внутри кавычек
		// всё равно исполняется. Строка взята из обёртки повтора, жившей в
		// этом дереве, — то есть гейт не видел ВТОРОГО владельца.
		`    log="$(helm dep update 2>&1)"`,
		`  out="$( cd "$U" && helm dependency build )"`,
	}
	for _, line := range defects {
		if !helmDepCallSite(line) {
			t.Errorf("вызов не опознан: %q — предикат пропустил бы заведомый экземпляр", line)
		}
	}

	legit := []string{
		`# рендер падает у всех, КРОМЕ тех проверок, что зовут ` + "`helm dep update`" + ` сами`,
		`  echo "       Собрать: (cd $UMBRELLA && helm dep update)"`,
		`  echo "=== $SCRIPT: helm dep update (иначе рендерится вендоренная копия) ==="`,
		`[ -n "$FULL" ] || fatal "render is empty (deps not built? run helm dep update)"`,
		`  || die "helm dependency build failed. run 'helm dependency update' manually"`,
		"// её условие создаёт `helm dependency build`, а не unit-прогон",
		// строка из дерева как есть (assert-iac-scan-covers-every-chart.py):
		// разметка прозы внутри значения словаря.
		"    \"deploy/helm/umbrella/\": \"не рендерится без `helm dependency update` — \"",
		`bash scripts/helm-umbrella-deps.sh`,
		`bash "$REPO_ROOT/scripts/helm-umbrella-deps.sh" "$UMBRELLA"`,
	}
	for _, line := range legit {
		if helmDepCallSite(line) {
			t.Errorf("законная форма принята за вызов: %q — предикат читает текст, а не позицию "+
				"команды; первый же ложный срабат снял бы гейт целиком", line)
		}
	}
	t.Logf("инъекция: форм вызова %d, законных близнецов %d", len(defects), len(legit))
}
