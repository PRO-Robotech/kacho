// stand_posture_gate_is_not_narrowed_test.go — стенд, который поднимает шард
// сквозных проб, судит свою посадку ПОЛНЫМ гейтом, а не одним его измерением.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Сосед (stand_posture_terminal_stack_test.go) держит то, что стенд шарда
// ЗАКАНЧИВАЕТ боевой посадкой. Держателя у второй половины не было ни одного:
// рецепт подъёма звал гейт посадки СУЖЕННЫМ профилем — из четырёх измерений
// градуировалось одно (круг отправителей), а mTLS, сохранённые настройки по
// всем путям доставки и административный переход не спрашивались ни разу.
//
// Сужение обосновывалось тем, что стенд подъёма расслабляет `auth_mode` и
// `db_sslmode`. Довод пережил свой предмет: фаза боевой посадки переехала в
// рецепт подъёма, и расслаблять стало нечего (задача #2390). То есть проверка
// присутствовала, была провязана, исполнялась на каждом подъёме — и не могла
// отказать по трём измерениям из четырёх.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТДЕЛЬНЫЙ ДЕРЖАТЕЛЬ, А НЕ СТРОКА В СОСЕДЕ
//
// Предметы разные, и различие не педантское. Сосед отвечает «в какой посадке
// стенд ЖИВЁТ», этот — «чем эта посадка ПРОВЕРЯЕТСЯ». Первое можно вернуть в
// прежнее состояние, не тронув второго, и наоборот; слитые в один файл, они
// расходились бы молча ровно так же, как разошлись объявление и проверка.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ
//
//	Р1  рецепт подъёма ЗОВЁТ гейт посадки — цель читается из рецепта, не выписана;
//	Р2  цель гейта пинит БОЕВОЙ профиль (сужающего профиля не существует);
//	Р3  исключения ПРОБРАСЫВАЮТСЯ: стенд шарда поднимает подмножество служб, и
//	    без проброса гейт краснел бы на отсутствии, а не на посадке;
//	Р4  перепись печатается ДВУМЯ величинами.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ (названо, чтобы «зелено» не читалось шире)
//
//   - не поднимает стенд и о ЖИВОМ процессе не утверждает ничего. Это «не
//     выполнилось», третья категория; вердикт даёт подъём, и он приходит из
//     конвейера, а не отсюда;
//   - не судит содержание измерений — их держит сам скрипт;
//   - не судит имена исключений: их выводит работа конвейера из таблицы шардов,
//     и совпадение словарей держит перепись самого гейта на живом стенде.
package deploy_test

import (
	"fmt"
	"os"
	"regexp"
	"strings"
	"testing"
)

// standPostureGateTarget — цель гейта посадки. Имя ОДНО на всё дерево, и здесь
// оно единственный литерал: остальное читается из рецептов.
const standPostureGateTarget = "assert-production-posture"

// makeCall — вызов ЛЮБОЙ цели make из рецепта другой цели.
//
// РАСПОЗНАЁТСЯ ВЫЗОВ, А НЕ ИМЯ ГЕЙТА, и это несущее решение. Первая редакция
// искала цель, чьё имя содержит «posture», — и не узнавала ровно ту цель, ради
// которой держатель написан: сужающая называлась `assert-forwarder-narrowing`.
// То есть распознаватель молчал бы о сужении и говорил «гейта посадки нет
// вовсе» — находка есть, предмет назван неверно, читатель идёт не туда.
//
// Гейтом посадки считается цель, чей рецепт ЗОВЁТ скрипт посадки (ниже). Судится
// то, что цель делает, а не как она названа.
var makeCall = regexp.MustCompile(`\$\(MAKE\)\s+(?:--no-print-directory\s+)?([A-Za-z0-9_.-]+)([^\n]*)`)

// postureScript — скрипт, исполняющий гейт посадки. Одно объявление имени.
const postureScript = "scripts/assert-production-posture.sh"

// posturePinnedProduction — боевой профиль, пиньемый рецептом самой цели.
var posturePinnedProduction = regexp.MustCompile(`POSTURE_PROFILE=production\b`)

// postureSkipForwarded — проброс исключений. Именно ПЕРЕМЕННОЙ make, а не
// литералом: перечень исключений выводит работа конвейера из таблицы шардов, и
// выписанный здесь разошёлся бы с нею молча.
var postureSkipForwarded = regexp.MustCompile(`POSTURE_SKIP="\$\(POSTURE_SKIP\)"`)

// postureGateWiring — провязка гейта посадки, снятая с дерева.
type postureGateWiring struct {
	Target    string // цель подъёма, названная работой конвейера
	Gate      string // цель гейта посадки, названная рецептом подъёма
	RecipeLen int    // строк рецепта подъёма
	LinesRead int    // объём прочитанного
	Calls     int    // вызовов make в рецепте подъёма — ОСМОТРЕНО
	Posture   int    // из них исполняющих скрипт посадки — НАЙДЕНО
	findings  []string
}

func TestShardStandJudgesItsPostureWithTheFullGate(t *testing.T) {
	wf := readTreeFile(t, shardWorkflow)
	mk := readTreeFile(t, standMakefile)

	w := judgePostureGateWiring(t, wf, mk)

	// Р4: перепись ДВУМЯ величинами.
	t.Logf("ПЕРЕПИСЬ гейта посадки стенда шарда:\n"+
		"  цель подъёма (из работы конвейера): %s\n"+
		"  гейт посадки, названный рецептом:   %s\n"+
		"  вызовов make в рецепте подъёма ОСМОТРЕНО %d · исполняющих гейт посадки НАЙДЕНО %d\n"+
		"  прочитано строк рецептов: %d · строк рецепта подъёма: %d",
		w.Target, w.Gate, w.Calls, w.Posture, w.LinesRead, w.RecipeLen)

	for _, f := range w.findings {
		t.Error(f)
	}
}

// judgePostureGateWiring — САМО СУЖДЕНИЕ, отделённое от пробы и от дерева:
// доказательство способности гейта упасть обязано звать ЕГО ЖЕ над своей
// копией, иначе оно доказывало бы о пересказе, а не о гейте.
//
// Предпосылки — ОТКАЗ, а не находка: нераспознанный рецепт означает «читать
// нечего», и вердикт «нарушений 0» был бы объявлен о непрочитанном.
func judgePostureGateWiring(t *testing.T, workflow, makefile string) postureGateWiring {
	t.Helper()
	var w postureGateWiring

	m := standUpInvocation.FindStringSubmatch(workflow)
	if m == nil {
		t.Fatalf("в работе конвейера не найден вызов цели make через владельца подъёма стенда — " +
			"распознаватель перестал узнавать работу, и «гейт не сужен» было бы объявлено о непрочитанном")
	}
	w.Target = m[1]

	recipe, seen := recipeLinesIn(makefile, w.Target)
	w.LinesRead, w.RecipeLen = seen, len(recipe)
	if len(recipe) == 0 {
		t.Fatalf("рецепт цели подъёма %q пуст — распознаватель перестал узнавать рецепт, "+
			"а не подъём перестал звать гейты (прочитано строк %d)", w.Target, seen)
	}

	// Р1: рецепт зовёт гейт посадки. Цель узнаётся по тому, что она ДЕЛАЕТ —
	// зовёт скрипт посадки, — а не по своему имени.
	var callArgs, gateBody string
	var calls []string
	for _, line := range recipe {
		for _, mm := range makeCall.FindAllStringSubmatch(line, -1) {
			calls = append(calls, mm[1])
			body, _ := recipeLinesIn(makefile, mm[1])
			joined := strings.Join(body, "\n")
			if !strings.Contains(joined, postureScript) {
				continue
			}
			w.Posture++
			if w.Gate == "" {
				w.Gate, callArgs, gateBody = mm[1], mm[2], joined
			}
		}
	}
	w.Calls = len(calls)
	if w.Gate == "" {
		w.findings = append(w.findings, fmt.Sprintf(
			"рецепт цели подъёма %q не зовёт ни одной цели, исполняющей %s: стенд поднимается, "+
				"а чем судится его посадка — не сказано (строк рецепта %d, вызовов make %d: %s)",
			w.Target, postureScript, len(recipe), len(calls), strings.Join(calls, ", ")))
		return w
	}

	// Р2: зовётся цель ПОЛНОГО гейта, и её рецепт пинит боевой профиль.
	if w.Gate != standPostureGateTarget {
		w.findings = append(w.findings, fmt.Sprintf(
			"подъём судит посадку целью %q, а не %q.\n"+
				"    Гейт посадки градуирует ЧЕТЫРЕ измерения, и всякая иная цель — это его СУЖЕНИЕ.\n"+
				"    Сужение здесь уже было (#2390): из четырёх спрашивалось одно, три остальные\n"+
				"    не могли отказать ни при каком состоянии стенда.",
			w.Gate, standPostureGateTarget))
	}
	if !posturePinnedProduction.MatchString(gateBody) {
		w.findings = append(w.findings, fmt.Sprintf(
			"рецепт цели %q не пинит POSTURE_PROFILE=production.\n"+
				"    Профиль обязан выбирать ЦЕЛЬ, а не тот, кто её зовёт: унаследованный из\n"+
				"    окружения профиль увёл бы боевой гейт в зелёное правкой одной переменной.",
			w.Gate))
	}

	// Р3: исключения пробрасываются — иначе цель неприменима к стенду шарда.
	if !postureSkipForwarded.MatchString(callArgs) && !postureSkipForwarded.MatchString(gateBody) {
		w.findings = append(w.findings, fmt.Sprintf(
			"POSTURE_SKIP не пробрасывается ни вызовом из %q, ни рецептом %q.\n"+
				"    Перечень ожидаемых служб у гейта ЖЁСТКИЙ намеренно: не развернувшаяся служба\n"+
				"    обязана быть красной, а не незамеченной. Стенд шарда поднимает подмножество\n"+
				"    ОСОЗНАННО, и без проброса гейт откажет на отсутствии служб, а не на посадке —\n"+
				"    то есть станет красным всегда и по причине, к посадке отношения не имеющей.",
			w.Target, w.Gate))
	}

	return w
}

// readTreeFile — файл дерева. Отсутствие — ОТКАЗ: предпосылка проверки исчезла,
// а не дерево стало чистым.
func readTreeFile(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s не читается (%v) — предпосылка проверки исчезла, а не дерево стало чистым", path, err)
	}
	return string(raw)
}

// recipeLinesIn — строки рецепта названной цели и объём прочитанного.
//
// Заголовок цели читается ТЕМ ЖЕ выражением, что у соседних проверок рецептов
// (`makeTargetLine`): второе выражение об одном предмете разошлось бы молча.
func recipeLinesIn(makefile, target string) ([]string, int) {
	var out []string
	seen := 0
	inRecipe := false
	for _, line := range strings.Split(makefile, "\n") {
		seen++
		if strings.HasPrefix(line, "\t") {
			if inRecipe {
				out = append(out, line)
			}
			continue
		}
		if strings.TrimSpace(line) == "" {
			continue // пустая строка рецепт не закрывает
		}
		if m := makeTargetLine.FindStringSubmatch(line); m != nil {
			inRecipe = m[1] == target
			continue
		}
		inRecipe = false
	}
	return out, seen
}
