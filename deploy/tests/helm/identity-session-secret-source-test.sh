# identity-session-secret-source-test.sh — ВЕЛИЧИНЫ СЕССИИ СЛУЖБЫ ЛИЧНОСТИ
# ОБЯЗАНЫ ПЕРЕЖИВАТЬ ОБНОВЛЕНИЕ (задача #1751).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Чарт поставщика чеканит `secretsCookie`/`secretsCipher` сам, когда величины не
# объявлены: `randAlphaNum 32`, то есть НА КАЖДОМ РЕНДЕРЕ новая. Секрет при этом
# несёт `helm.sh/hook: pre-install, pre-upgrade` вместе с
# `helm.sh/hook-delete-policy: before-hook-creation`, поэтому каждое обновление
# сперва удаляет его, а потом создаёт заново — уже с новой величиной. Следствие
# для арендатора: всякое `helm upgrade` аннулирует ВСЕ действующие сессии.
#
# Соседняя аннотация `helm.sh/resource-policy: keep` от этого не спасает: у
# hook-ресурсов helm её не читает (`deleteHookByPolicy` удаляет безусловно).
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ОТРИЦАНИЕ ЗДЕСЬ НЕ ВАКУУМНО
#
# Проверка идёт ПАРАМИ: у каждого «обязан отказать» есть положительный контроль
# той же формы, который обязан ПРОЙТИ. Без него «рендер отказал» ничего не
# доказывает: на дереве без собранных зависимостей отказывает вообще всё, и
# отрицание засчиталось бы, не сверив ничего.
#
#   1  положительный контроль : боевой профиль РЕНДЕРИТСЯ (установка);
#   2  находка                : он же как ОБНОВЛЕНИЕ — отказ, и отказ ИМЕННО
#                               про необъявленную величину сессии;
#   3  законный близнец       : обновление с объявленными величинами — проходит;
#   4  законный близнец       : обновление с секретом ВНЕ helm — проходит;
#   5  законный близнец       : стенд dev, объявляющий величины, — проходит;
#   6  находка                : ссылка `${…}` величиной не является — отказ;
#   7  положительный контроль : объявленные величины дают ОДНУ И ТУ ЖЕ величину
#                               на двух рендерах подряд;
#   8  отрицательный контроль : НЕобъявленные дают РАЗНЫЕ — иначе утверждение 7
#                               зеленело бы на любом рендере и ничего не значило;
#   9  граница                : служба личности выключена — стражу нечего судить.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ `--is-upgrade`, А НЕ ОТКАЗ ВСЕГДА
#
# На первой установке терять нечего: сессий ещё нет, а объявить секрет в git
# нельзя. Отказ на обновлении ловит ровно тот момент, когда цена появляется, и
# ловит до того, как она заплачена. Побочно это значит, что ни один существующий
# рендер дерева стражем не затронут: `helm template` и `helm install` флага не
# взводят (замер: `--is-upgrade` в дереве не звал никто).
#
# Офлайновый харнесс: кластер не нужен, нужны собранные зависимости умбреллы.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# Каталог чарта — переменной, чтобы доказательство инъекцией
# (`identity-session-secret-source-inject.sh`) могло навести пробу на ВРЕМЕННУЮ
# КОПИЮ и вернуть в неё дефект, не трогая дерево. Проба не имеет права писать
# туда, откуда запущена: иначе её собственные находки становятся неотличимы от
# чужих, а состояние, которое читают соседние проверки, портится.
UMBRELLA="${KACHO_UMBRELLA_DIR:-$REPO_ROOT/helm/umbrella}"
SECRET_TPL="charts/kratos/templates/secrets.yaml"

# shellcheck source=deploy/tests/helm/outcome.sh
. "$(dirname "$0")/outcome.sh"
# shellcheck source=deploy/tests/helm/stacks.sh
. "$(dirname "$0")/stacks.sh"

# ── ЦЕПОЧКИ БЕРУТСЯ ИЗ ТАБЛИЦЫ, А НЕ ВЫПИСЫВАЮТСЯ ───────────────────────────
#
# Состав стенда объявляет ТОЛЬКО deploy/stacks.txt. Вторая копия расходится с
# ней молча — каждая проверка честно проверяет то, что сама объявила, — и этот
# класс здесь уже сработал: первая редакция выписала пару профилей строкой, и
# гейт единственности цепочки её нашёл.
#
# ПОЧЕМУ ИМЕННО ЭТИ ДВА СТЕНДА, а не все: у проверки две полосы, и они
# ПРОТИВОПОЛОЖНЫ по предмету. `prod` — стенд, чьи учётные данные приходят слоем
# вне git: он обязан быть ОТКЛОНЁН на обновлении. `dev` — стенд, объявляющий
# величины в git: он обязан ПРОЙТИ. Полосы одного механизма сверяются между
# собой, и сверять их можно только имея обе.
PROD_ARGS="$(stacks_args prod "$UMBRELLA")"
DEV_ARGS="$(stacks_args dev "$UMBRELLA")"

EXPECTED_ASSERTIONS=9

require_helm
require_mikefarah_yq
for f in $PROD_ARGS $DEV_ARGS; do
  [ "$f" = "-f" ] && continue
  require_file_present "$f" "профиль из цепочки stacks.txt"
done
require_umbrella_charts "$UMBRELLA"

# Величины для близнецов — ЗАВЕДОМО НЕ СЕКРЕТ и таковыми названы: гейт судит
# НАЛИЧИЕ объявленного источника, а не стойкость величины. Настоящие живут в
# слое учётных данных площадки, вне git.
NOT_A_SECRET_A='gate-fixture-not-a-secret-32byteA'
NOT_A_SECRET_B='gate-fixture-not-a-secret-32byteB'
NOT_A_SECRET_C='gate-fixture-not-a-secret-32byteC'

# Объявление всех ТРЁХ величин — ровно то, что страж считает законной формой 1.
DECLARE_ALL=(
  --set-string "kratos.kratos.config.secrets.default[0]=$NOT_A_SECRET_C"
  --set-string "kratos.kratos.config.secrets.cookie[0]=$NOT_A_SECRET_A"
  --set-string "kratos.kratos.config.secrets.cipher[0]=$NOT_A_SECRET_B"
)

# ── ЧТО ИМЕННО СВЕРЯЕТСЯ МЕЖДУ ДВУМЯ РЕНДЕРАМИ ──────────────────────────────
#
# Три ключа секрета, и только они. Сравнивать документ ЦЕЛИКОМ нельзя: он несёт
# ещё и `dsn`, а на профиле, где тот пуст, различие пришло бы не оттуда, откуда
# его ждут. Утверждение обязано говорить о том предмете, который оно называет.
secret_keys() {
  printf '%s\n' "$1" | yq -r '[.data.secretsDefault, .data.secretsCookie, .data.secretsCipher] | join("|")'
}

# ── ПОЧЕМУ У РЕНДЕРА-ОБНОВЛЕНИЯ ЕСТЬ ФИКСТУРА ПАРОЛЯ ────────────────────────
#
# Подчарты хранилищ ОТКАЗЫВАЮТ рендеру-обновлению, пока пароль не назван:
# «You must provide your current passwords when upgrading the release». Это их
# собственная защита, она верна и снята быть не должна.
#
# Но для ЭТОГО гейта она — посторонний отказ: без фикстуры каждый рендер как
# обновление падал бы на хранилищах, и утверждение «отказал из-за величины
# сессии» проходило бы вакуумно, ничего не сверив. Фикстура снимает ровно этот
# посторонний отказ и ничего больше — что доказано утверждениями 3/4/5, где тот
# же рендер с той же фикстурой обязан ПРОЙТИ.
#
# Величина заведомо не секрет и живёт только внутри рендера.
UPGRADE_FIXTURE=(--is-upgrade --set-string global.postgresql.auth.password=render-fixture-not-a-secret)

# shellcheck disable=SC2086  # цепочка `-f a -f b` обязана разбиться на слова
render_prod() { helm_try kacho-umbrella "$UMBRELLA" $PROD_ARGS "$@"; }

# ── 1. Положительный контроль: боевой профиль рендерится как УСТАНОВКА ───────
#
# Без него всё, что ниже, читалось бы как «отказал — значит поймали»: на дереве
# без зависимостей отказывает и установка тоже.
render_prod --show-only "$SECRET_TPL"
render_or_fatal "стенд prod (установка) → $SECRET_TPL"
render_nonempty_or_fatal "стенд prod (установка) → $SECRET_TPL"
PROD_INSTALL_1="$(secret_keys "$HELM_OUT")"
ok

# ── 2. НАХОДКА: то же дерево как ОБНОВЛЕНИЕ обязано отказать ────────────────
render_prod "${UPGRADE_FIXTURE[@]}"
render_must_fail_because \
  "kratos.kratos.config.secrets." \
  "стенд prod как обновление" \
  "боевой профиль ОБНОВЛЯЕТСЯ без объявленного источника величин сессии: чарт \
чеканит их заново на каждом рендере, секрет пересоздаётся hook'ом pre-upgrade, и \
все действующие сессии арендаторов перестают быть действительными. Страж \
templates/identity-session-secret-guard.yaml обязан это отклонить"
ok

# ── 3. Законный близнец: объявленные величины — обновление проходит ─────────
render_prod "${UPGRADE_FIXTURE[@]}" "${DECLARE_ALL[@]}" --show-only "$SECRET_TPL"
render_or_fatal "стенд prod как обновление с объявленными величинами"
render_nonempty_or_fatal "стенд prod как обновление с объявленными величинами"
DECLARED_1="$(secret_keys "$HELM_OUT")"
ok

# ── 4. Законный близнец: секрет заведён ВНЕ helm — обновление проходит ──────
#
# Вторая законная форма владения. Без неё страж требовал бы величину в значениях
# у площадки, которая осознанно держит секрет свой, — то есть запрещал бы ровно
# то решение, которое переживает обновление by construction.
render_prod "${UPGRADE_FIXTURE[@]}" \
  --set "kratos.secret.enabled=false" \
  --set-string "kratos.secret.nameOverride=kacho-identity-session-secrets"
render_or_fatal "стенд prod как обновление с секретом вне helm"
ok

# ── 5. Законный близнец: профиль стенда объявляет свои величины ─────────────
#
# Он объявляет их прямо в git, и это законно: величины стенда не секрет ни для
# кого. Полосы одного механизма обязаны сверяться МЕЖДУ СОБОЙ — без этого
# утверждения страж был бы неотличим от «отказывать всякому обновлению».
# shellcheck disable=SC2086  # то же: цепочка стенда разбивается на слова
helm_try kacho-umbrella "$UMBRELLA" $DEV_ARGS "${UPGRADE_FIXTURE[@]}" --show-only "$SECRET_TPL"
render_or_fatal "стенд dev как обновление"
render_nonempty_or_fatal "стенд dev как обновление"
ok

# ── 6. НАХОДКА: ссылка `${…}` величиной не является ─────────────────────────
render_prod "${UPGRADE_FIXTURE[@]}" "${DECLARE_ALL[@]}" \
  --set-string 'kratos.kratos.config.secrets.cookie[0]=${KRATOS_SECRETS_COOKIE}'
render_must_fail_because \
  "несёт ссылку" \
  "стенд prod как обновление со ссылкой вместо величины" \
  "ссылка \${…} принята как объявленная величина: служба личности подстановки в \
значениях настроек НЕ делает, строка уехала бы в ключ подписи печенья дословно"
ok

# ── 7. Положительный контроль: объявленное УСТОЙЧИВО между рендерами ────────
render_prod "${UPGRADE_FIXTURE[@]}" "${DECLARE_ALL[@]}" --show-only "$SECRET_TPL"
render_or_fatal "стенд prod как обновление с объявленными величинами (второй рендер)"
DECLARED_2="$(secret_keys "$HELM_OUT")"
[ "$DECLARED_1" = "$DECLARED_2" ] || fail "два рендера ОДНОГО дерева с ОБЪЯВЛЕННЫМИ \
величинами дали разные секреты — значит объявление не читается, и переживать \
обновление величине нечем"
ok

# ── 8. Отрицательный контроль: НЕобъявленное между рендерами МЕНЯЕТСЯ ───────
#
# Без него утверждение 7 зеленело бы на любом рендере: совпадение двух одинаковых
# строк ничего не говорит о том, что оно следствие ОБЪЯВЛЕНИЯ.
render_prod --show-only "$SECRET_TPL"
render_or_fatal "стенд prod (установка, второй рендер)"
PROD_INSTALL_2="$(secret_keys "$HELM_OUT")"
if [ "$PROD_INSTALL_1" = "$PROD_INSTALL_2" ]; then
  fail "два рендера боевого профиля БЕЗ объявленных величин дали ОДИН И ТОТ ЖЕ секрет — \
либо величины вдруг объявлены прямо в git (а это секрет, и ему там не место), либо \
предпосылка гейта исчезла: чарт больше не чеканит величину на каждом рендере, и \
утверждение 7 перестало что-либо доказывать"
fi
ok

# ── 9. Граница: служба личности выключена — судить нечего ──────────────────
render_prod "${UPGRADE_FIXTURE[@]}" --set "kratos.enabled=false"
render_or_fatal "стенд prod как обновление при выключенной службе личности"
ok

findings_verdict "стендов прочитано из stacks.txt: 2 (prod, dev); \
рендеров как обновление: 6"
exit 0
