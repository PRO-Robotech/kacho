# premise.sh — ЕДИНСТВЕННЫЙ читатель предпосылки доказательств инъекцией:
# «зависимости умбреллы материализованы, рендер возможен».
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ОН ЕСТЬ
#
# Доказательство инъекцией ждёт красного и получает красное — но по причине, к
# проверяемому гейту отношения не имеющей: зависимости чарта не собраны, и
# `helm template` отказывает ДО первого шаблона. Ось при этом выглядит
# ИСПОЛНЕННОЙ («ждали RED — получили RED»), код возврата тот же, вывод похож.
# Доказательство становится ВАКУУМНЫМ, и заметить это можно только сверкой
# фразы-улики — то есть случайно.
#
# Замер, ради которого файл заведён (задача #1769, дерево до правки, зависимости
# не собраны): из семи доказательств семейства шесть предпосылки не объявляли.
# ПЯТЬ вышли кодом 1 — то есть объявили условие прогона находкой о дереве; ещё
# одно вышло кодом 2, но по КАТЧ-ОЛЛУ «рендер не удался» — то есть объявило бы
# «условие не создано» и на настоящем дефекте чарта, что есть тот же класс с
# другой стороны. У `machine-credential-posture-inject.sh` наблюдался вакуум в
# чистом виде: ось «ручка включена на переведённом контуре → RED» отчиталась
# `ok`, будучи красной от несобранных зависимостей.
#
# `e2e-flow.md` §6: «условие не создано» — НЕ вердикт. У него свой код возврата
# и свой текст, и он не зачитывается ни в зелёное, ни в красное.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ОДИН ФАЙЛ, А НЕ СЕМЬ КОПИЙ
#
# Тот же довод, по которому состав стендов читает один `stacks.sh`: строку
# копировали, и копии разъезжались молча. Здесь цена расхождения выше обычной —
# разъехавшаяся копия не ломает прогон, она делает его ВАКУУМНЫМ, а вакуумный
# прогон зелен.
#
# ВОПРОС «материализовано ли» ЗДЕСЬ НЕ РЕШАЕТСЯ. Его владелец — тот же скрипт,
# что материализацию и делает (`scripts/helm-umbrella-deps.sh --check`), и он
# отвечает ТЕМ ЖЕ решением, каким сам решает, идти ли в сеть. Здесь живёт только
# КОНВЕНЦИЯ доказательств: как об этом сказать и каким кодом выйти.
#
# Имя НЕ оканчивается на `-test.sh` и не содержит `-inject`: цель
# `helm-manifest-test` перебирает `tests/helm/*-test.sh`, а прогонщик
# доказательств — `tests/helm/*-inject.sh`; библиотека, попавшая в любой из
# двух переборов, запускалась бы как проверка.
#
# Опции оболочки здесь НЕ выставляются: файл подключают доказательства с разными
# `set` (часть с `-e`, часть без), и библиотека, переписывающая их режим, меняла
# бы поведение вызывающего вдали от места правки.
#
# Использование:
#   . "$(dirname "$0")/premise.sh"
#   premise_chart_deps            # выходит кодом 2, если условия нет
#   premise_chart_deps "МЕТКА"    # то же, метка попадёт в текст пропуска

_premise_deploy_root() {
  # Путь считается от ЭТОГО файла, а не от рабочего каталога вызывающего:
  # доказательства запускаются и из deploy/, и из tests/helm/, и из корня.
  local self
  self="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  printf '%s\n' "$self/../.."
}

# premise_helm — инструмент. Отсутствие helm тоже «условие не создано», а не
# находка: гейт, объявивший дерево негодным потому, что у него нет инструмента,
# утверждает о дереве то, чего не измерял.
premise_helm() {
  command -v helm >/dev/null 2>&1 && return 0
  echo "SKIP: helm не установлен — доказательство НЕ ВЫПОЛНЕНО (это не красное)."
  echo "      создать условие: поставить helm той версии, что пинит конвейер"
  exit 2
}

# premise_chart_deps [МЕТКА] — материализация зависимостей умбреллы.
premise_chart_deps() {
  local label="${1:-}" root out code=0
  premise_helm
  root="$(_premise_deploy_root)"
  out="$(bash "$root/scripts/helm-umbrella-deps.sh" --check 2>&1)" || code=$?
  [ "$code" = "0" ] && return 0
  # Код 2 у владельца вопроса означает ровно «условия нет». Любой ДРУГОЙ
  # ненулевой код — не предпосылка, а поломка самого владельца, и глотать её
  # пропуском значило бы завести маску: тогда доказательство молчало бы всегда.
  if [ "$code" != "2" ]; then
    echo "ОТКАЗ: владелец вопроса о зависимостях сам отказал кодом $code — это НЕ «условие не создано»"
    printf '%s\n' "$out" | sed 's/^/       /'
    exit 1
  fi
  echo "SKIP${label:+ ($label)}: зависимости умбреллы не материализованы — доказательство НЕ ВЫПОЛНЕНО (это не красное)."
  printf '%s\n' "$out" | sed 's/^/      /'
  exit 2
}

# Как исполняемый файл — тот же вопрос, чтобы его можно было задать руками.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  premise_chart_deps "${1:-}"
  echo "предпосылка выполнена: зависимости умбреллы материализованы"
fi
