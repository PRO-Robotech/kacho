# stacks.sh — единственный shell-читатель состава стендов (deploy/stacks.txt).
#
# Зачем отдельный файл, а не строка sed в каждом гейте: строку копировали, и
# копии разъезжались молча. Здесь она одна, и она ОТКАЗЫВАЕТ, когда прочитать
# нечего, — вместо того чтобы вернуть пусто и позволить вызывающему объявить
# «стеков не осталось».
#
# Имя НЕ оканчивается на `-test.sh` намеренно: цель `helm-manifest-test` перебирает
# `tests/helm/*-test.sh`, и библиотека, попавшая в этот перебор, запускалась бы
# как проверка.
#
# Использование:
#   stacks.sh --names                     → имена стеков, по одному на строку
#   stacks.sh --table                     → строки `<имя>:<профиль>,…`
#   stacks.sh --chain <имя> [РАЗДЕЛИТЕЛЬ] → профили стека (по умолчанию через пробел)
#   stacks.sh --args  <имя> [КАТАЛОГ]     → `-f КАТАЛОГ/профиль …` для helm
#
# Либо как библиотека:  . "$(dirname "$0")/stacks.sh"  → функции stacks_names /
# stacks_table / stacks_chain / stacks_args.
#
# Опции оболочки здесь НЕ выставляются: файл подключают гейты с разными `set`
# (часть с `-e`, часть без), и библиотека, переписывающая их режим, меняла бы
# поведение вызывающего вдали от места правки.

_stacks_table_file() {
  # Путь считается от ЭТОГО файла, а не от рабочего каталога вызывающего:
  # гейты запускаются и из deploy/, и из tests/helm/, и из корня.
  #
  # КОД РАЗРЕШЕНИЯ КАТАЛОГА ПОТРЕБОВАН. Прежняя редакция роняла его: при неудаче
  # `cd` переменная оставалась пустой, и функция печатала `/../../stacks.txt` —
  # путь от корня файловой системы. Отказ дальше объявлялся «таблица не читается»,
  # то есть верным словом о НЕВЕРНОМ файле.
  local self
  self="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)" || return 1
  printf '%s\n' "$self/../../stacks.txt"
}

_stacks_die() { echo "FATAL: stacks.sh — $1" >&2; exit 2; }

# stacks_table — строки `<имя>:<профиль>,…` без комментариев и пустых.
# Пустой результат — ОТКАЗ: «стеков не осталось» и «таблица не прочиталась»
# обязаны быть различимы, иначе вызывающий объявит дерево осмотренным, не
# прочитав ни строки.
stacks_table() {
  local f n out
  f="$(_stacks_table_file)" \
    || _stacks_die "каталог этого файла не разрешается — таблицу искать негде"
  [ -r "$f" ] || _stacks_die "таблица стеков $f не читается — состав стендов взять неоткуда"
  out="$(grep -vE '^[[:space:]]*(#|$)' "$f")"
  n="$(printf '%s\n' "$out" | grep -c . || true)"
  [ "${n:-0}" -ge 1 ] || _stacks_die "в $f нет ни одной строки стека — обходить нечего"
  # Разбор обязан узнавать КАЖДУЮ строку: нераспознанная строка это не «стеков
  # меньше», это «предикат перестал их узнавать».
  local bad
  bad="$(printf '%s\n' "$out" | grep -vE '^[a-z0-9][a-z0-9-]*:values[^,[:space:]]*(,values[^,[:space:]]*)*$' || true)"
  [ -z "$bad" ] || _stacks_die "строка таблицы стеков не разобрана: $bad"
  printf '%s\n' "$out"
}

# ─────────────────────────────────────────────────────────────────────────────
# КОД ОТКАЗА ТАБЛИЦЫ ПОТРЕБОВАН КАЖДЫМ ПРОИЗВОДНЫМ — И ЭТО НЕСУЩЕЕ СВОЙСТВО
#
# Отказ здесь ГРОМКИЙ by design (`_stacks_die` → код 2). Но `exit` внутри
# подстановки убивает ТОЛЬКО её подоболочку, а дальше код надо ПОТРЕБОВАТЬ —
# иначе он теряется, и отказ оборачивается пустым выводом при нуле.
#
# Прежняя редакция теряла его тремя способами сразу, и замер показал все три:
# на копии файла без таблицы `--table` давал КОД 2, а `--names` и `--args` —
# КОД 0. `--args` при этом печатал ПУСТО и добавлял ВТОРУЮ, ложную причину
# («стека 's1' в таблице нет — имя переехало»), тогда как таблицы не было вовсе.
#
# Цена именно у `--args`: его вывод идёт в `helm` цепочкой `-f`, и пустая цепочка
# при нулевом коде означает `helm` БЕЗ ЕДИНОГО профиля.
#
# ЧТО ИЗ ЭТОГО СЛЕДУЕТ — ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО, и следует НЕ зелёное.
# `helm template ci .` без единого `-f` на сегодняшнем чарте ОТКАЗЫВАЕТ кодом 1:
# страж подчарта реестра требует учётных данных слоя хранения. Поэтому
# наблюдаемая цена — код 2 с ЛОЖНОЙ ПРИЧИНОЙ. Замер инъекцией одного факта
# (таблица нечитаема; библиотека, чарт, helm и кластер не тронуты): два гейта из
# пяти объявляли «helm template отказал … — это УСЛОВИЕ прогона», то есть винили
# несобранные зависимости вместо непрочитанной таблицы, и читатель шёл собирать
# зависимости, которые на месте.
#
# Зелёного на умолчаниях сегодня не выходит, и держит это СВОЙСТВО ЧАРТА, а не
# форма вызова: снимут страж в подчарте — и та же потеря кода даст зелёный вердикт
# о другом стенде. Двадцать вызывающих читают этот вывод, и до этой правки ни один
# не мог отличить «цепочка такая» от «таблица не прочиталась».
#
# Формы, в которых код терялся, и чем каждая заменена:
#   `stacks_table | cut`            → присваивание, затем `cut` по переменной;
#   `$(stacks_table | grep || true)`→ таблица отдельно, отбор строки отдельно;
#   `for f in $(stacks_chain …)`    → присваивание, затем обход переменной.
# Последняя — тот же язык, что в `for x in $(f)`: список `for` теряет код ВСЕГДА.
# ─────────────────────────────────────────────────────────────────────────────

# stacks_names — имена стеков, по одному на строку.
stacks_names() {
  local out
  out="$(stacks_table)" || return $?
  printf '%s\n' "$out" | cut -d: -f1
}

# stacks_chain <имя> [РАЗДЕЛИТЕЛЬ]
stacks_chain() {
  local want="$1" sep="${2:- }" table line
  # Таблица читается ОТДЕЛЬНО от отбора строки. Слитая форма приписывала отказ
  # чтения ОТСУТСТВИЮ ИМЕНИ: диагностика «имя переехало или стек снят» печаталась
  # на дереве, где таблицы нет ни для одного имени.
  table="$(stacks_table)" || return $?
  line="$(printf '%s\n' "$table" | grep -E "^${want}:" || true)"
  [ -n "$line" ] || _stacks_die "стека '$want' в таблице нет — имя переехало или стек снят"
  printf '%s\n' "${line#*:}" | tr ',' "$sep"
}

# stacks_args <имя> [КАТАЛОГ]
stacks_args() {
  local want="$1" dir="${2:-}" chain f out=""
  chain="$(stacks_chain "$want" ' ')" || return $?
  # ПУСТАЯ ЦЕПОЧКА — ОТКАЗ, А НЕ «СТЕНД БЕЗ ПРОФИЛЕЙ». Пустой вывод при нулевом
  # коде даёт `helm` без единого `-f`, то есть посадку на умолчания чарта.
  [ -n "$chain" ] || _stacks_die "цепочка стека '$want' пуста — helm без единого -f сел бы на умолчания чарта"
  # Цепочка дробится на слова намеренно. Пояснение стоит ПЕРЕД директивой, а не
  # после кода правила: токен, не имеющий вида ключ=значение, обрывает разбор, и
  # файл выпадает из-под проверки целиком.
  # shellcheck disable=SC2086
  for f in $chain; do
    if [ -n "$dir" ]; then out="$out -f $dir/$f"; else out="$out -f $f"; fi
  done
  printf '%s\n' "${out# }"
}

# Как исполняемый файл — разбор аргументов; как библиотека (source) — только
# функции выше.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  case "${1:---table}" in
    --names) stacks_names ;;
    --table) stacks_table ;;
    --chain) shift; stacks_chain "$@" ;;
    --args)  shift; stacks_args "$@" ;;
    *) _stacks_die "неизвестный аргумент '$1' (--names|--table|--chain|--args)" ;;
  esac
fi
