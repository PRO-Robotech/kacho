# КАЖДЫЙ профиль стенда обязан сузить круг отправителей у КАЖДОГО сервиса,
# который принимает переданную личность.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ПРОВЕРКА ПО ПРОФИЛЯМ, А НЕ ПО СЕРВИСАМ
#
# Круг отправителей уже проверяется у kaname и registry — каждым своим
# скриптом, и каждый смотрит СВОЙ чарт. Такая нарезка не отвечает на вопрос
# «есть ли хоть один сервис на этом стенде, который никого не сузил»: чарт может
# нести здоровое умолчание, а профиль — переопределить его пустым, и наоборот.
# Ровно так и вышло: у kacho-nlb умолчание чарта пустое (как у vpc), но vpc свой
# круг в dev-профиле объявлял, а nlb — нет. Шесть сервисов сужены, седьмой нет,
# и ни одна из существующих проверок такого вопроса не задавала.
#
# Поэтому здесь единица проверки — ПРОФИЛЬ ЦЕЛИКОМ: рендерим умбреллу ровно тем
# набором `-f`, которым поднимается стенд, и грузим круг у каждого сервиса из
# отрендеренного манифеста — то есть после всех слоёв values, а не из умолчания.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ГЕЙТА ПОСАДКИ. Тот спрашивает ЖИВОЙ процесс и потому
# авторитетнее, но приходит только после развёртывания. Этот — офлайновый, ловит
# то же самое в CI до деплоя. Оба нужны: живой ловит «под не перекатился»,
# офлайновый — «профиль так и не завели».
#
# ПУСТОЙ КРУГ — ЭТО НЕ «НЕ СУЖАЕМ», А «ДОВЕРЯЕМ ВСЕМ. Транспорт сверяет
# сертификат отправителя со списком ТОЛЬКО когда список непуст; на пустом он
# принимает переданную личность от любого пира, прошедшего проверку сертификата.
# Поэтому считаем НЕПУСТЫЕ записи, а не длину значения: строка "," и список из
# одних пустых строк дают ноль принимаемых транспортом записей и обязаны
# краснеть так же, как пустота.
# ─────────────────────────────────────────────────────────────────────────────
set -uo pipefail
# Состав стендов — из ЕДИНСТВЕННОЙ таблицы дерева (deploy/stacks.txt).
# Своей копии цепочек здесь нет: копии разъезжались молча.
. "$(dirname "$0")/stacks.sh"

SCRIPT="$(basename "$0")"
HERE="$(cd "$(dirname "$0")" && pwd)"
DEPLOY_ROOT="$(cd "$HERE/../.." && pwd)"
UMBRELLA="$DEPLOY_ROOT/helm/umbrella"

# Три исхода — ОДНОЙ реализацией на весь каталог. Свой `fatal` здесь уже был, а
# `fail` НАКАПЛИВАЛ нарушения и потому выходил кодом 1 в самом конце — вместе с
# отказом рендера, который свойством дерева не является (задача #1214). Накопитель
# остался, но зовётся `violation`: имя `fail` в этом каталоге означает ровно одно —
# «находка о дереве, выходим кодом 1».
# shellcheck source=deploy/tests/helm/outcome.sh
. "$HERE/outcome.sh"
require_helm

FAILURES=0
violation() { echo "FAIL: $1" >&2; FAILURES=$((FAILURES + 1)); }

command -v python3 >/dev/null 2>&1 || fatal "python3 не найден"
python3 -c 'import yaml' 2>/dev/null || fatal "нужен PyYAML (python3 -c 'import yaml')"

# ─────────────────────────────────────────────────────────────────────────────
# КАРТА ИЗМЕРЕНИЯ: где у каждого сервиса лежит круг.
#
# `<deployment>|<service>|<локатор>` — локатор либо `env:<ИМЯ_ПЕРЕМЕННОЙ>`
# (значение через запятую), либо `cm:<имя-ConfigMap>:<путь-в-config.yaml>`.
#
# Состав списка — это ОТВЕТ НА ВОПРОС «кто принимает переданную личность», и он
# совпадает с FORWARDER_NARROWING_REQUIRED в scripts/assert-production-posture.sh.
# api-gateway сюда НЕ входит намеренно: он личность не принимает, а чеканит из
# проверенного токена — требовать с него сужения значило бы красить сервис за
# отсутствие механизма, которого у него и не должно быть.
#
# ЛОКАТОР, КОТОРЫЙ НИЧЕГО НЕ НАШЁЛ, — ЭТО ОТКАЗ, А НЕ ПРОПУСК. Сервис волен
# переехать на другую ручку; тогда эта карта устареет, и «ничего не нашли»
# обязано читаться как «проверка не выполнена», иначе устаревший локатор
# превращает гейт в зелёную печать.
MEASURED="
compute|compute|env:KACHO_COMPUTE_AUTHZ_TRUSTED_FORWARDER_SANS
kacho-geo|geo|env:KACHO_GEO_AUTHZ_TRUSTED_FORWARDER_SANS
kacho-storage|storage|env:KACHO_STORAGE_AUTHZ_TRUSTED_FORWARDER_SANS
registry|registry|env:KACHO_REGISTRY_AUTHZ_TRUSTED_FORWARDER_SANS
vpc|vpc|cm:vpc-config:authz.trusted-forwarder-sans
kacho-nlb|nlb|cm:kacho-nlb-config:authz.trusted-forwarder-sans
kaname|iam|cm:kaname-config:authn.trusted-forwarder-sans
"

# Профили, которыми РЕАЛЬНО поднимается стенд, — из ЕДИНСТВЕННОЙ таблицы дерева
# (deploy/stacks.txt). `<имя>|<файлы через запятую>` — запятая, а не пробел:
# строки разбираются пословно, и файл со слоями иначе развалился бы на два
# «профиля».
#
# ВЕСЬ СМЫСЛ ЭТОЙ ПРОВЕРКИ В ТОМ, ЧТО ЕДИНИЦА ИЗМЕРЕНИЯ — НАБОР `-f`, КОТОРЫМ
# ПОДНИМАЮТСЯ. Значит состав набора не может быть местным мнением: круг
# отправителей — величина послойная, слой волен переопределить здоровое
# умолчание нижнего, поэтому цепочка, знающая на слой меньше, отвечает на вопрос
# про другой стенд и остаётся зелёной.
PROFILES="$(stacks_table | tr ':' '|')"

# Слой учётных данных боевой площадки — НЕ в репозитории (см. его шапку).
# Посадки он не несёт, поэтому его отсутствие в CI ничего не скрывает;
# добавляется к набору, только когда файл на месте. Что именно измерено,
# печатается ниже — «измерили меньше» не должно выглядеть как «измерили всё».
OPTIONAL_ORY="values.fe3455-ory.yaml"
if [ -f "$UMBRELLA/$OPTIONAL_ORY" ]; then
  PROFILES="$PROFILES
fe3455+ory|$(stacks_chain fe3455 ','),$OPTIONAL_ORY"
fi

# render <файлы-через-запятую> <имя профиля> — манифест профиля в $HELM_OUT.
# Отказ рендера — УСЛОВИЕ прогона (несобранные зависимости умбреллы, нет helm), а
# не свойство круга отправителей: код 2 и текст, который сказал сам helm. Прежде он
# приходил сюда пустым выводом и объявлялся нарушением наравне с пустым кругом.
render() {
  local args=() f
  local IFS=,
  for f in $1; do args+=(-f "$UMBRELLA/$f"); done
  unset IFS
  helm_try kacho-umbrella "$UMBRELLA" "${args[@]}"
  render_or_fatal "профиль $2"
}

# ─────────────────────────────────────────────────────────────────────────────
# Извлечение круга из ОТРЕНДЕРЕННОГО манифеста, по ВСЕМ путям доставки.
#
# Пути доставки перечислены не для полноты, а потому что через них уже утекал
# дефект: массовый импорт `envFrom` был слепым пятном гейта посадки, и сервис,
# получавший настройки только так, не осматривался вовсе.
#
# Печатает по строке `<service> <кол-во-непустых-записей>`; `-1` = локатор не
# разрешился (объект есть, ручки нет), пустая строка = объекта нет в рендере.
# ─────────────────────────────────────────────────────────────────────────────
extract() {
  MEASURED="$MEASURED" python3 - "$1" <<'PY'
import os, sys, yaml

render = open(sys.argv[1]).read()
docs = [d for d in yaml.safe_load_all(render) if isinstance(d, dict)]

cms = {d["metadata"]["name"]: (d.get("data") or {})
       for d in docs if d.get("kind") == "ConfigMap"}
deps = {d["metadata"]["name"]: d
        for d in docs if d.get("kind") == "Deployment"}


def env_of(dep):
    """Every env name→value of every container, from all delivery paths."""
    out = {}
    spec = dep["spec"]["template"]["spec"]
    for c in (spec.get("containers") or []) + (spec.get("initContainers") or []):
        for src in c.get("envFrom") or []:
            ref = (src.get("configMapRef") or {}).get("name")
            if ref in cms:
                out.update(cms[ref])
        for e in c.get("env") or []:
            if "value" in e:
                out[e["name"]] = e["value"]
            ref = ((e.get("valueFrom") or {}).get("configMapKeyRef") or {})
            if ref.get("name") in cms:
                out[e["name"]] = cms[ref["name"]].get(ref["key"], "")
    return out


def nonempty(entries):
    return len([s for s in entries if str(s).strip() != ""])


for row in os.environ["MEASURED"].split():
    dep_name, svc, locator = row.split("|", 2)
    dep = deps.get(dep_name)
    if dep is None:
        print(svc, "")            # сервис не разворачивается этим профилем
        continue
    kind, rest = locator.split(":", 1)
    if kind == "env":
        env = env_of(dep)
        if rest not in env:
            print(svc, -1)
            continue
        print(svc, nonempty(env[rest].split(",")))
    else:
        cm_name, path = rest.split(":", 1)
        data = cms.get(cm_name)
        if data is None or "config.yaml" not in data:
            print(svc, -1)
            continue
        node = yaml.safe_load(data["config.yaml"])
        for part in path.split("."):
            if not isinstance(node, dict) or part not in node:
                node = None
                break
            node = node[part]
        if node is None:
            print(svc, -1)
            continue
        print(svc, nonempty(node if isinstance(node, list) else str(node).split(",")))
PY
}

# ─────────────────────────────────────────────────────────────────────────────
# ПРОВЕРКА ВСЕХ ПРОФИЛЕЙ, И ЧИСЛО УТВЕРЖДЕНИЙ СВЕРЯЕТСЯ С ОЖИДАЕМЫМ.
#
# Ожидаемое известно заранее и точно: каждый профиль обязан дать по одному
# утверждению на каждый измеряемый сервис. Печатать число, ни с чем его не
# сверяя, — это перепись без вердикта: она честно сообщала «28 assertions», и
# ровно так же честно сообщила бы «4», если бы шесть сервисов перестали
# осматриваться. Прежний порог `> 0` от такого не защищает вовсе.
#
# ОТСУТСТВИЕ ОБЪЕКТА В РЕНДЕРЕ — ТОЖЕ ОТКАЗ. Шапка карты измерения выше уже
# объявляет: «локатор, который ничего не нашёл, — это отказ, а не пропуск». Но
# ветка «Deployment сервиса в рендере не найден» этому не следовала: она
# печатала «не разворачивается этим профилем» и шла дальше, не увеличив ни
# число утверждений, ни число нарушений. Переименование объекта развёртывания
# или потеря сервиса профилем тихо выводили его из-под гейта — при этом сервис
# продолжал бы принимать переданную личность на живом стенде. Ни один сервис
# сегодня в эту ветку не попадает (7 из 7 в каждом из профилей), то есть
# «мягкий пропуск» не имел предмета и был чистой слепой зоной.
#
# Профиль, который ДЕЙСТВИТЕЛЬНО не разворачивает сервис, — это осознанное
# решение, и объявляться оно должно там, где его видно: списком с причиной. Пока
# такого случая нет, списка тоже нет — исключение без предмета само является
# находкой.
# ─────────────────────────────────────────────────────────────────────────────
count_rows() { printf '%s\n' $1 | grep -c . ; }

# verify_all <подпись> — прогоняет все профили из PROFILES по карте MEASURED.
# Читает и меняет N/FAILURES. Вынесено в функцию, чтобы самопроверка
# могла прогнать ТОТ ЖЕ путь на подменённой карте: инъекция обязана проверять
# работающий вердикт, а не его копию.
verify_all() {
  local profile name files tmp measured svc count
  for profile in $PROFILES; do
    name="${profile%%|*}"; files="${profile#*|}"
    echo "--- профиль $name ($files)"

    tmp="$(mktemp)"
    render "$files" "$name"
    printf '%s\n' "$HELM_OUT" >"$tmp"
    if [ ! -s "$tmp" ]; then
      rm -f "$tmp"
      violation "профиль $name отрендерился ПУСТЫМ — измерение НЕ ВЫПОЛНЕНО (пустой рендер это не «чисто»)"
      continue
    fi
    if ! measured="$(extract "$tmp")" || [ -z "$measured" ]; then
      rm -f "$tmp"
      violation "профиль $name: разбор рендера СОРВАЛСЯ — измерение НЕ ВЫПОЛНЕНО"
      continue
    fi
    rm -f "$tmp"

    while read -r svc count; do
      [ -z "$svc" ] && continue
      case "$count" in
        "")  violation "$name/$svc: объекта развёртывания НЕТ в рендере профиля — сервис выпал из-под гейта, хотя переданную личность он принимать не перестал. Либо объект переименован (тогда карта измерения в $SCRIPT устарела), либо профиль его действительно не разворачивает — и тогда это надо объявить здесь с причиной, а не пропускать молча." ;;
        -1)  violation "$name/$svc: ручка круга отправителей НЕ НАЙДЕНА в рендере — карта измерения в $SCRIPT устарела, и «не нашли» здесь означает «не проверили», а не «всё хорошо»" ;;
        0)   violation "$name/$svc: круг отправителей ПУСТ — переданную личность примет ЛЮБОЙ пир с сертификатом внутреннего CA. Профиль обязан объявить круг по фактическим отправителям сервиса." ;;
        *)   ok; echo "  ✓ $name/$svc: круг сужен ($count записей)" ;;
      esac
    done <<EOF
$measured
EOF
  done
}

# ─────────────────────────────────────────────────────────────────────────────
# Самопроверка: гейт обязан ПОКРАСНЕТЬ на воспроизведённом дефекте.
#
# Без неё проверка доказывает лишь, что она отработала — а не что она способна
# отличить сужённый круг от пустого. Инъекция ровно та, что и была в жизни:
# профиль объявляет kacho-nlb пустой круг.
# ─────────────────────────────────────────────────────────────────────────────
if [ "${1:-}" = "--self-test" ]; then
  echo "=== self-test: инъекция пустого круга у kacho-nlb — в КАЖДЫЙ объявленный профиль ==="
  # Инъекция прогоняется по ВСЕМ профилям из PROFILES, а не по одному dev.
  # Иначе самопроверка доказывала бы работоспособность гейта на профиле, который
  # в список внесли первым, и молчала бы о том, что остальные строки списка,
  # возможно, не измеряются вовсе — а именно этим и был дефект: боевой набор,
  # которым поднимается кластер, в списке отсутствовал, и никто этого не видел.
  # Теперь добавить профиль в список, не измеряя его, нельзя: самопроверка
  # потребует, чтобы внесённый в него дефект стал виден.
  inj="$(mktemp)"; trap 'rm -f "$inj"' EXIT
  cat >"$inj" <<'EOF'
kacho-nlb:
  config:
    authz:
      trustedForwarderSANs: []
EOF
  rc=0
  checked=0
  for profile in $PROFILES; do
    name="${profile%%|*}"; files="${profile#*|}"
    args=(); IFS=,
    for f in $files; do args+=(-f "$UMBRELLA/$f"); done
    unset IFS
    helm_try kacho-umbrella "$UMBRELLA" "${args[@]}" -f "$inj"
    render_or_fatal "профиль $name с инъекцией (самопроверка)"
    r="$HELM_OUT"
    if [ -z "$r" ]; then
      echo "  ПРОВАЛ $name: рендер с инъекцией отдал ПУСТО — профиль объявлен, но не измеряется"
      rc=1; continue
    fi
    tmp="$(mktemp)"; printf '%s' "$r" >"$tmp"
    got="$(extract "$tmp" | awk '$1=="nlb"{print $2}')"
    rm -f "$tmp"
    checked=$((checked + 1))
    if [ "$got" = "0" ]; then
      echo "  ОК     $name: пустой круг извлечён как 0 записей → гейт покраснеет"
    else
      echo "  ПРОВАЛ $name: при пустом круге извлечено '$got', ожидалось 0 —"
      echo "         на этом профиле гейт не отличает пустой круг от сужённого."
      rc=1
    fi
  done

  # «Ноль находок» обязано быть отличимо от «ноль осмотренного».
  if [ "$checked" -eq 0 ]; then
    echo "FAIL: не проверено ни одного профиля — список PROFILES пуст или не разбирается."
    exit 1
  fi

  # ── ИНЪЕКЦИЯ: сервис ВЫПАЛ из рендера. Прогоняется ТОТ ЖЕ вердикт (verify_all)
  #    на подменённой карте, где имя объекта развёртывания заведомо отсутствует.
  #    Один профиль — покрытие профилей уже доказано инъекцией выше, а рендер
  #    умбреллы дорог.
  echo "=== self-test: сервис отсутствует в рендере — обязан быть находкой, а не пропуском ==="
  SAVED_MEASURED="$MEASURED"; SAVED_PROFILES="$PROFILES"
  PROFILES="dev|values.dev.yaml"
  MEASURED="
compute|compute|env:KACHO_COMPUTE_AUTHZ_TRUSTED_FORWARDER_SANS
this-deployment-does-not-exist|ghost|env:KACHO_GHOST_AUTHZ_TRUSTED_FORWARDER_SANS
"
  # Вывод уходит в ФАЙЛ, а не в подстановку команды: `$(verify_all)` исполняет
  # функцию в подоболочке, и её N/FAILURES наружу не возвращаются —
  # утверждения о числах читали бы нули и проходили всегда. Поймано этой же
  # инъекцией: сообщение о нарушении печаталось, а счётчик оставался нулём.
  log="$(mktemp)"; trap 'rm -f "$inj" "$log"' EXIT
  N=0; FAILURES=0
  verify_all >"$log" 2>&1
  if [ "$FAILURES" -ge 1 ] && grep -q "ghost" "$log"; then
    echo "  ОК     отсутствующий объект развёртывания → нарушение ($FAILURES), сервис назван"
  else
    echo "  ПРОВАЛ отсутствующий объект развёртывания прошёл (нарушений $FAILURES)"
    sed 's/^/         /' "$log"
    rc=1
  fi

  # ── КОНТРОЛЬ ТОЙ ЖЕ ФОРМЫ: карта без призрака на том же профиле — молчание,
  #    и число утверждений равно ожидаемому. Без этой половины предикат «нет
  #    объекта → красное» был бы неотличим от «красное всегда».
  MEASURED="
compute|compute|env:KACHO_COMPUTE_AUTHZ_TRUSTED_FORWARDER_SANS
"
  N=0; FAILURES=0
  verify_all >"$log" 2>&1
  want=$(( $(count_rows "$PROFILES") * $(count_rows "$MEASURED") ))
  if [ "$FAILURES" -eq 0 ] && [ "$N" -eq "$want" ]; then
    echo "  ОК     карта без призрака → молчание, утверждений $N из $want"
  else
    echo "  ПРОВАЛ законная карта: нарушений $FAILURES, утверждений $N из $want"
    sed 's/^/         /' "$log"
    rc=1
  fi

  # ── ПРЕДПОСЫЛКА СЧЁТА: ожидаемое число обязано ЗАВИСЕТЬ от карты и профилей.
  #    Константа пережила бы удаление сервиса из карты молча.
  MEASURED="$SAVED_MEASURED"; PROFILES="$SAVED_PROFILES"
  full=$(( $(count_rows "$PROFILES") * $(count_rows "$MEASURED") ))
  if [ "$full" -gt "$want" ]; then
    echo "  ОК     ожидаемое число выводится из карты и профилей ($full против $want на урезанной)"
  else
    echo "  ПРОВАЛ ожидаемое число не зависит от карты: $full против $want"
    rc=1
  fi

  echo
  if [ $rc -eq 0 ]; then
    echo "PASS: $SCRIPT --self-test (профилей проверено: $checked)"
  else
    echo "FAIL: $SCRIPT --self-test"
  fi
  exit $rc
fi

# ─────────────────────────────────────────────────────────────────────────────
echo "=== круг отправителей чужой личности: по профилям стенда ==="

PROFILE_COUNT="$(count_rows "$PROFILES")"
SERVICE_COUNT="$(count_rows "$MEASURED")"
EXPECTED=$((PROFILE_COUNT * SERVICE_COUNT))
EXPECTED_ASSERTIONS="$EXPECTED"
[ "$EXPECTED" -ge 1 ] || fatal "профилей $PROFILE_COUNT × сервисов $SERVICE_COUNT = 0 — измерять нечего"

verify_all

echo
echo "осмотрено: профилей $PROFILE_COUNT, сервисов $SERVICE_COUNT, ожидалось утверждений $EXPECTED"
[ "$FAILURES" -eq 0 ] \
  || fail "$SCRIPT — $FAILURES нарушений (утверждений выполнено $N из $EXPECTED)"

# Число утверждений СВЕРЯЕТСЯ, а не печатается. Каждый профиль обязан дать по
# одному утверждению на каждый измеряемый сервис; недобор означает, что часть
# карты не осматривалась — при нулевых нарушениях это выглядело бы как чистота.
# Тот же счёт делает `outcome_verdict` ниже; здесь он остаётся ради ИМЕНИ причины
# (профилей × сервисов), которого общая реализация знать не может.
if [ "$N" -ne "$EXPECTED" ]; then
  {
    echo "        (профилей $PROFILE_COUNT × сервисов $SERVICE_COUNT). Нарушений нет, но"
    echo "        осмотрено НЕ ВСЁ — а это не то же самое, что «всё хорошо»."
  } >&2
  fail "$SCRIPT — утверждений выполнено $N, ожидалось $EXPECTED"
fi
outcome_verdict "профилей $PROFILE_COUNT × сервисов $SERVICE_COUNT"
