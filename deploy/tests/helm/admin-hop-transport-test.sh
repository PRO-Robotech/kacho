# ХОП К АДМИНИСТРАТИВНОМУ API ПРОВАЙДЕРА: не публикуем и не переводим на TLS
# вслепую.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ПО ЭТОМУ ХОПУ ЕЗДИТ (и почему это стало другим вопросом)
#
# Раньше по адресу административного API ходили только административные вызовы.
# После того как проверка отзыва переехала на слой аутентификации, на КАЖДОМ
# промахе кэша интроспекции по нему уезжает ЖИВОЙ предъявитель конечного
# пользователя. Предъявитель — это предъявитель: кто прочитал его с провода, тот
# им и воспользуется. Поэтому транспорт этого хопа стал вопросом о тенантских
# данных, а не только об эксплуатации.
#
# ЧЕГО ЭТА ПРОВЕРКА НЕ УТВЕРЖДАЕТ. Она НЕ утверждает, что хоп уже на TLS — ни в
# одном профиле он не на TLS, и перевести его сегодня нельзя (у провайдера
# ОДИН общий блок `serve.tls` на оба листенера: включив его ради
# административного, включаешь и публичный, а публичный по открытому http
# читают шлюз, iam и сама самообслуживающая UI — то есть перевод затрагивает
# компоненты за пределами этой правки). Утверждается ровно то, что проверяемо
# и обязано оставаться верным ДО и ПОСЛЕ такого перевода:
#
#   1. АДРЕС ХОПА — ВНУТРИКЛАСТЕРНЫЙ. Административный API провайдера НЕ
#      АУТЕНТИФИЦИРУЕТ НИКОГО: кто до него дотянулся, тот заводит клиентов,
#      читает сессии и интроспектирует токены. Единственная его защита — то, что
#      он не маршрутизируется наружу. Профиль, направивший хоп на внешнее имя,
#      снимает эту единственную защиту.
#
#   2. TLS БЕЗ ЯКОРЯ ДОВЕРИЯ — ХУЖЕ, ЧЕМ ОТКРЫТЫЙ ХОП. Сертификат
#      внутрикластерного адреса выписан внутренним CA, которому шлюз по
#      умолчанию не доверяет (его умолчание — системные корни). Рукопожатие с
#      неизвестным удостоверителем классифицируется слоем интроспекции как
#      ПОСТОЯННАЯ ошибка конфигурации, после чего он ОТКАЗЫВАЕТ КАЖДОМУ запросу.
#      То есть благонамеренный перевод адреса на https без якоря кладёт API
#      целиком. Поэтому: https ⇒ якорь обязан быть объявлен.
#
#   3. РУЧКА ЯКОРЯ — НЕСУЩАЯ. Объявлена → рендерятся том, монтирование и
#      переменная; не объявлена → ни одного из трёх. Ручка, которая ничего не
#      меняет, — это ровно тот дефект, с которого началась работа: поле клиента
#      в конфигурации кэша интроспекции существовало и никогда не заполнялось.
#
# Самопроверка (`--self-test`) воспроизводит дефект №2 инъекцией и требует,
# чтобы проверка на нём покраснела — иначе пункт 2 зелен по построению
# (сегодня ни один профиль не на https, и утверждение исполнялось бы вхолостую).
# ─────────────────────────────────────────────────────────────────────────────
set -uo pipefail

SCRIPT="$(basename "$0")"
DEPLOY_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
UMBRELLA="$DEPLOY_ROOT/helm/umbrella"
GW_CHART="$(cd "$DEPLOY_ROOT/../gateway/deploy" && pwd)"

ASSERTIONS=0
FAILURES=0
fail() { echo "FAIL: $1"; FAILURES=$((FAILURES + 1)); }
ok()   { ASSERTIONS=$((ASSERTIONS + 1)); }
fatal() { echo "FATAL: $1"; exit 2; }

command -v helm >/dev/null 2>&1 || fatal "helm не найден"
command -v yq >/dev/null 2>&1 || fatal "нужен yq (mikefarah v4)"
yq --version 2>&1 | grep -q mikefarah || fatal "нужен mikefarah yq v4, а не python-обёртка над jq"
[ -d "$GW_CHART" ] || fatal "чарт шлюза не найден: $GW_CHART"

# hop_host <url> — host:port из адреса ("" если адрес пуст).
hop_host() { echo "${1#*://}" | cut -d/ -f1; }

# is_cluster_internal <host[:port]> — адрес внутрикластерного Service?
# Принимаем короткое имя, `<svc>.<ns>`, `.svc` и `.svc.cluster.local`, плюс
# localhost (проброс порта на стенде разработчика). Всё остальное — это имя,
# которое кто-то может отрезолвить снаружи.
is_cluster_internal() {
  local h="${1%%:*}"
  case "$h" in
    "")                       return 1 ;;
    localhost|127.0.0.1)      return 0 ;;
    *.svc|*.svc.cluster.local) return 0 ;;
    *.*.*)                    return 1 ;;   # a.b.c — похоже на внешний FQDN
    *)                        return 0 ;;   # короткое имя / <svc>.<ns>
  esac
}

# ── 1+2: профили ─────────────────────────────────────────────────────────────
# Читаем ОБЪЯВЛЕНИЕ в профиле, а не рендер: рендер умбреллы стоит десятки секунд
# на профиль, а предмет здесь — именно то, что объявил профиль.
check_profile() { # check_profile <имя> <values-файл>
  local name="$1" f="$2"
  [ -f "$f" ] || { echo "  — $name: файла нет ($f)"; return; }

  local intro admin ca
  intro="$(yq '.["api-gateway"].hydra.introspectionUrl // ""' "$f")"
  admin="$(yq '.["api-gateway"].hydra.adminUrl // ""' "$f")"
  ca="$(yq '.["api-gateway"].hydra.adminCa.secretName // ""' "$f")"

  if [ -z "$intro" ] && [ -z "$admin" ]; then
    echo "  — $name: хоп не объявлен (профиль наслаивается поверх другого)"
    return
  fi

  local url
  for url in "$intro" "$admin"; do
    [ -z "$url" ] && continue
    local host; host="$(hop_host "$url")"
    if is_cluster_internal "$host"; then
      ok; echo "  ✓ $name: $host — внутрикластерный адрес"
    else
      fail "$name: хоп ведёт на '$host' — административный API провайдера НЕ аутентифицирует никого, и единственная его защита в том, что снаружи до него не дотянуться. Этот адрес похож на маршрутизируемое имя."
    fi

    case "$url" in
      https://*)
        if [ -n "$ca" ]; then
          ok; echo "  ✓ $name: https-хоп объявлен вместе с якорем доверия ($ca)"
        else
          fail "$name: хоп объявлен как https ($host), но api-gateway.hydra.adminCa.secretName пуст. Шлюз доверяет только системным корням, сертификат внутреннего CA он отвергнет, а слой интроспекции считает неизвестного удостоверителя ПОСТОЯННОЙ ошибкой конфигурации и после неё ОТКАЗЫВАЕТ КАЖДОМУ запросу. Объявите якорь вместе с адресом."
        fi
        ;;
      http://*)
        echo "  — $name: хоп открытый (http). Перевод на TLS сегодня невозможен:"
        echo "      у провайдера ОДИН общий блок serve.tls на публичный и"
        echo "      административный листенеры, и включение затронуло бы"
        echo "      публичный OIDC-листенер, который читают по http шлюз, iam и"
        echo "      самообслуживающая UI. Утверждения 1 и 3 остаются в силе."
        ;;
    esac
  done
}

# ── 3: ручка якоря несущая ───────────────────────────────────────────────────
check_knob() {
  local with without
  with="$(helm template gw "$GW_CHART" \
            --set hydra.adminUrl=https://kacho-umbrella-hydra-admin.kacho.svc.cluster.local:4445 \
            --set hydra.adminCa.secretName=hydra-admin-tls 2>/dev/null)"
  without="$(helm template gw "$GW_CHART" \
            --set hydra.adminUrl=http://kacho-umbrella-hydra-admin.kacho.svc.cluster.local:4445 2>/dev/null)"
  [ -n "$with" ] && [ -n "$without" ] || { fail "чарт шлюза не рендерится — проверка ручки НЕ ВЫПОЛНЕНА"; return; }

  local n
  n="$(echo "$with" | grep -c "KACHO_HYDRA_ADMIN_CA_FILE")"
  [ "$n" -ge 1 ] && { ok; echo "  ✓ ручка объявлена → переменная якоря рендерится"; } \
                 || fail "ручка объявлена, а KACHO_HYDRA_ADMIN_CA_FILE не отрендерился — процесс не узнает про якорь"
  n="$(echo "$with" | grep -c "name: hydra-admin-ca")"
  [ "$n" -ge 2 ] && { ok; echo "  ✓ ручка объявлена → том И монтирование рендерятся"; } \
                 || fail "ручка объявлена, а том/монтирование якоря не отрендерились ($n из 2) — файла в контейнере не будет, и старт будет отвергнут"
  n="$(echo "$without" | grep -c "hydra-admin-ca")"
  [ "$n" -eq 0 ] && { ok; echo "  ✓ ручка не объявлена → ни тома, ни монтирования, ни переменной"; } \
                 || fail "ручка не объявлена, а следы якоря в рендере есть ($n) — тогда «пусто» и «задано» неразличимы"
}

# ── самопроверка: воспроизводим дефект №2 ────────────────────────────────────
if [ "${1:-}" = "--self-test" ]; then
  echo "=== self-test: https-хоп БЕЗ якоря доверия обязан покраснеть ==="
  inj="$(mktemp)"; trap 'rm -f "$inj"' EXIT
  cat >"$inj" <<'EOF'
api-gateway:
  hydra:
    introspectionUrl: "https://kacho-umbrella-hydra-admin.kacho.svc.cluster.local:4445/admin/oauth2/introspect"
    adminUrl: "https://kacho-umbrella-hydra-admin.kacho.svc.cluster.local:4445"
EOF
  FAILURES=0
  check_profile "инъекция" "$inj" >/dev/null 2>&1
  if [ "$FAILURES" -gt 0 ]; then
    echo "PASS: $SCRIPT --self-test (https без якоря → $FAILURES нарушений)"
    exit 0
  fi
  echo "FAIL: self-test — https-хоп без якоря прошёл проверку."
  echo "      Значит пункт 2 зелен по построению: сегодня ни один профиль не на"
  echo "      https, и утверждение исполнялось бы вхолостую."
  exit 1
fi

echo "=== хоп к административному API: адресация и якорь доверия ==="
check_profile dev      "$UMBRELLA/values.dev.yaml"
check_profile dev-prod "$UMBRELLA/values.dev-prod.yaml"
check_profile prod     "$UMBRELLA/values.prod.yaml"
echo "--- ручка якоря в чарте шлюза"
check_knob

echo
if [ "$FAILURES" -ne 0 ]; then
  echo "FAILED: $SCRIPT — $FAILURES нарушений"
  exit 1
fi
[ "$ASSERTIONS" -gt 0 ] || fatal "ни одного утверждения не выполнено — проверка ничего не проверила"
echo "PASS: $SCRIPT ($ASSERTIONS assertions)"
