# (задача #2732).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Стражи открывались условием на `*.enabled` чужого подчарта:
#
#   templates/identity-session-secret-guard.yaml     `.Values.kratos.enabled`
#   templates/identity-mail-lane-guard.yaml          `(.Values.kratos).enabled`
#
# (третий, страж величины обратного вызова поставщика, судил настройки его
# издателя и снят вместе с ним, #1276). Как только флаг стал бы `false` — а это
# был ближайший шаг снятия чужой службы, — оба перестали бы исполняться БЕЗ
# ЕДИНОГО КРАСНОГО. Они не падали, они ЗАМОЛКАЛИ. Замер на дереве до правки
# (helm v4.2.4, стенды из stacks.txt):
#
#   own  + `--is-upgrade` + `kratos.enabled=false` + пустая координата нашей
#        ключницы                                            → код 0
#   prod + `kratos.enabled=false` + узел без отправителя     → код 0
#
# Подчартов поставщика в зонте больше нет (#1276), и его ключей в значениях нет
# ни у одного профиля: страж, снова открытый условием на них, замолчал бы на
# КАЖДОМ рендере. Поэтому пробы ниже судят стражей на профилях как есть — без
# единого ключа поставщика — и требуют отказа по нашему признаку.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ОТРИЦАНИЕ ЗДЕСЬ НЕ ВАКУУМНО
#
# Проверка идёт ПАРАМИ: у каждого «обязан отказать» есть положительный контроль
# той же формы, который обязан ПРОЙТИ. Без него «рендер отказал» ничего не
# доказывает: на дереве без собранных зависимостей отказывает всё, и отрицание
# засчиталось бы, не сверив ничего. Причина отказа сверяется дословно
# (`render_must_fail_because`), а не сам факт отказа.
#
#   1  положительный контроль : посадка own, координаты ключницы как в профиле —
#                               обновление проходит;
#   2  находка (страж сессии) : там же пусто ИМЯ секрета ключницы — отказ;
#   3  находка (страж сессии) : там же пуст КЛЮЧ того же секрета — отказ:
#                               половина пары хуже отсутствия обеих;
#   4  граница                : то же пустое имя, но УСТАНОВКА, а не обновление —
#                               проходит: на первой установке терять нечего;
#   8  находка (страж почты)  : узел объявлен без отправителя — отказ;
#   9  законный близнец       : стенд dev, почтовая полоса объявлена ЦЕЛИКОМ —
#                               проходит;
#  10  находка (страж сессии) : ВТОРОЙ предмет — координата ключа
#                               обёртки секретов второго фактора пуста: отказ, и
#                               отказ со СВОЕЙ ценой, а не с ценой сессии.
#
# Номера сохранены: утверждения 6 и 7 (полоса обратного вызова издателя
# поставщика) сняты вместе со стражем и его предметом (#1276), утверждения 5
# (посадка external) нет с kacho#2818 — посадка у службы одна (kaname#363),
# ключа посадки у её подчарта нет, и ветвь стража о ключах поставщика снята
# вместе со второй посадкой.
#
# Офлайновый харнесс: кластер не нужен, нужны собранные зависимости умбреллы.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# Каталог чарта — переменной, чтобы доказательство инъекцией могло навести пробу
# на ВРЕМЕННУЮ КОПИЮ и вернуть в неё дефект, не трогая дерева.
UMBRELLA="${KACHO_UMBRELLA_DIR:-$REPO_ROOT/helm/umbrella}"

# shellcheck source=deploy/tests/helm/outcome.sh
. "$(dirname "$0")/outcome.sh"
# shellcheck source=deploy/tests/helm/stacks.sh
. "$(dirname "$0")/stacks.sh"

# ── ЦЕПОЧКИ БЕРУТСЯ ИЗ ТАБЛИЦЫ, А НЕ ВЫПИСЫВАЮТСЯ ───────────────────────────
# Состав стенда объявляет ТОЛЬКО deploy/stacks.txt; вторая копия расходится с
# ней молча. Код читателя потребован: пустая цепочка при нулевом коде дала бы
# обход в ноль утверждений и вердикт с ВЕРНЫМ словом и ЛОЖНОЙ причиной.
OWN_ARGS="$(stacks_args own "$UMBRELLA")" \
  || fatal "стек own: цепочка профилей не прочитана — посадку own сверять нечем"
PROD_ARGS="$(stacks_args prod "$UMBRELLA")" \
  || fatal "стек prod: цепочка профилей не прочитана — почтовую полосу боевого слоя сверять нечем"
DEV_ARGS="$(stacks_args dev "$UMBRELLA")" \
  || fatal "стек dev: цепочка профилей не прочитана — почтовую полосу сверять нечем"

EXPECTED_ASSERTIONS=7

require_helm
for f in $OWN_ARGS $PROD_ARGS $DEV_ARGS; do
  [ "$f" = "-f" ] && continue
  require_file_present "$f" "профиль из цепочки stacks.txt"
done
require_umbrella_charts "$UMBRELLA"

# ── ФИКСТУРА ОБНОВЛЕНИЯ ─────────────────────────────────────────────────────
# Подчарты хранилищ отказывают рендеру-обновлению, пока пароль не назван («You
# must provide your current passwords when upgrading the release»). Это их
# собственная защита, она верна и снята быть не должна; для ЭТОГО гейта она —
# посторонний отказ, и фикстура снимает ровно его. Величина заведомо не секрет.
UPGRADE=(--is-upgrade --set-string global.postgresql.auth.password=render-fixture-not-a-secret)

# Координаты НАШЕЙ ключницы: имя секрета и ключ в нём. Величина (ключ обёртки
# приватных половин подписных ключей) живёт в объекте Secret кластера — гейт
# судит НАЛИЧИЕ объявленного источника, а не стойкость величины.
KEYRING_DECLARED=(
  --set-string "kaname.platform.iam.jwks.encKeySecretName=kaname-jwks-enc-key"
  --set-string "kaname.platform.iam.jwks.encKeySecretKey=enc_key"
)
KEYRING_NAME_ERASED=(--set-string "kaname.platform.iam.jwks.encKeySecretName=")
KEYRING_KEY_ERASED=(--set-string "kaname.platform.iam.jwks.encKeySecretKey=")

# shellcheck disable=SC2086  # цепочка `-f a -f b` обязана разбиться на слова
render_own()  { helm_try kacho-umbrella "$UMBRELLA" $OWN_ARGS  "$@"; }
# shellcheck disable=SC2086
render_prod() { helm_try kacho-umbrella "$UMBRELLA" $PROD_ARGS "$@"; }
# shellcheck disable=SC2086
render_dev()  { helm_try kacho-umbrella "$UMBRELLA" $DEV_ARGS  "$@"; }

# ── 1. Положительный контроль: посадка own ─────────────────────────────────
#
# Без него всё, что ниже, читалось бы как «отказал — значит поймали»: на дереве
# без собранных зависимостей отказывает и законный рендер тоже.
render_own "${UPGRADE[@]}" "${KEYRING_DECLARED[@]}"
render_or_fatal "стенд own как обновление без чужой службы"
render_nonempty_or_fatal "стенд own как обновление без чужой службы"
ok

# ── 2. НАХОДКА: посадка own, ключница не названа ───────────────────────────
#
# Ровно то состояние, в котором страж замолкал: `kratos.enabled=false` снимал
# его целиком, и обновление с необъявленной координатой НАШЕЙ ключницы
# проходило. Ключ обёртки — то, чем разворачиваются приватные половины
# подписных ключей, уже лежащие в базе: потеряв его, служба не проверит ни
# одного выданного удостоверения.
render_own "${UPGRADE[@]}" "${KEYRING_NAME_ERASED[@]}"
render_must_fail_because \
  "kaname.platform.iam.jwks.encKeySecretName" \
  "стенд own как обновление без чужой службы и пустом имени секрета ключницы" \
  "страж величин сессии ЗАМОЛЧАЛ вместе с чужим флагом: посадка own, обновление, \
имя секрета нашей ключницы пусто — а рендер прошёл. Предмет стража — КЛЮЧ, а не чужой \
чарт, и открываться он обязан по признаку, который производим мы"
ok

# ── 3. НАХОДКА: половина пары — ключ того же секрета пуст ───────────────────
#
# Координата — ПАРА: имя объекта и ключ в нём. Половина не «почти настроена»:
# ссылка на секрет из неё не собирается, и величина до процесса не доезжает.
render_own "${UPGRADE[@]}" "${KEYRING_KEY_ERASED[@]}"
render_must_fail_because \
  "kaname.platform.iam.jwks.encKeySecretKey" \
  "стенд own как обновление без чужой службы и пустом ключе секрета ключницы" \
  "половина координаты нашей ключницы принята за объявленную: ссылка на секрет из неё \
не собирается, ключ обёртки до процесса не доедет"
ok

# ── 4. Граница: УСТАНОВКА этим стражем не затрагивается ─────────────────────
#
# На первой установке терять нечего: выданных удостоверений ещё нет. Без этого
# утверждения страж был бы неотличим от «отказывать всякому рендеру».
render_own "${KEYRING_NAME_ERASED[@]}"
render_or_fatal "стенд own как УСТАНОВКА при пустом имени секрета ключницы"
ok

# ── 8. НАХОДКА: половина почтовой пары ─────────────────────────────────────
render_prod \
  --set-string "global.kacho.identity.smtp.connectionURI=smtp://mail.example.invalid:1025/" \
  --set-string "global.kacho.identity.smtp.fromAddress="
render_must_fail_because \
  "адрес отправителя НЕ задан" \
  "стенд prod с узлом почтовой полосы без отправителя" \
  "страж почтовой полосы ЗАМОЛЧАЛ вместе с флагом подчарта: узел объявлен, отправитель \
пуст — а рендер прошёл. Полосу объявляет НАША служба, и открываться страж обязан по её \
объявлению"
ok

# ── 9. Законный близнец: полоса объявлена ЦЕЛИКОМ — рендер проходит ─────────
#
# Без него утверждение 8 было бы неотличимо от «отказывать всякой полосе».
render_dev
render_or_fatal "стенд dev с полной почтовой полосой без чужой службы"
render_nonempty_or_fatal "стенд dev с полной почтовой полосой без чужой службы"
ok

# ── 10. НАХОДКА: второй предмет той же посадки — ключ второго фактора ───────
#
# Предметов ДВА, и цена у них РАЗНАЯ: ключница — «все действующие
# сессии перестают быть действительными», второй фактор — «заведённые вторые
# факторы перестают открываться». Проба судит оба: страж, доказанный на одном
# предмете, о втором не доказывает ничего.
render_own "${UPGRADE[@]}" \
  --set-string "kaname.platform.iam.secondFactor.encKeySecretName="
render_must_fail_because \
  "kaname.platform.iam.secondFactor.encKeySecretName" \
  "стенд own как обновление при пустой координате секретов второго фактора" \
  "второй предмет посадки own не судится: координата ключа обёртки секретов второго \
фактора пуста, а рендер прошёл — заведённые вторые факторы перестали бы открываться молча"
ok

findings_verdict "стендов прочитано из stacks.txt: 3 (own, prod, dev)"
exit 0
