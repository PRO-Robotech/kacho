# iam: кто вправе передавать чужую личность — и видит ли это гейт посадки.
#
# Предмет. Оба листенера kaname строили доверенную пару CertIdentityExtract →
# TrustedPrincipalExtract, но с ПУСТЫМ списком отправителей, что по контракту
# corelib означает не «никому», а «любому пиру с проверенным сертификатом». Цена
# именно у iam выше, чем у соседей: на :9090 он СОЗНАТЕЛЬНО не перепроверяет права
# конечного пользователя (единственная парадная дверь — api-gateway), поэтому
# сосед с законным сертификатом получал полномочия названной им жертвы на всей
# тенантской поверхности — вплоть до чеканки личных токенов и ключей служебных
# учёток. Теперь список приходит из конфигурации, боевой режим на пустом не
# стартует, а пер-RPC политика вызывающего сужает ещё и «на каком RPC».
#
# Этот файл закрывает то, что Go-тесты закрыть не могут:
#   (1) чарт РЕАЛЬНО отдаёт ручку в конфиг пода, и её дефолт непуст (профиль,
#       забывший ручку, не должен отгружать «доверяем любому»);
#   (2) боевой профиль повторяет её явно (правка профиля не может её потерять);
#   (3) правка ручки перекатывает под (иначе процесс живёт со старой посадкой, а
#       стража старта не срабатывает, потому что старта нет);
#   (4) гейт посадки ГРАДУИРУЕТ измерение для iam. Именно тут прячется класс
#       «форма без содержания»: сервис может честно отчитываться полем, а вердикт
#       гейта на это поле не смотреть — и красный под печатает галочку.
#
# Offline-харнесс (без кластера): рендер под-чарта + чтение профиля + прогон
# ВЕРДИКТА САМОГО ГЕЙТА (программа jq вынимается из скрипта, а не переписывается
# здесь — копия разъехалась бы с оригиналом и снова ничего не проверяла).
set -euo pipefail

# line_in <многострочное значение> <строка> — есть ли СТРОКА ЦЕЛИКОМ в значении.
# Замена `grep -qx`/`grep -qxF`: под `pipefail` труба даёт ложный отказ НА
# СОВПАДЕНИИ, потому что писатель получает SIGPIPE (задача #658). Сравнение
# буквальное — там, где раньше стоял `-x` без `-F`, это СТРОЖЕ, то есть ложного
# зелёного добавить не может.
line_in() { [[ $'\n'"$1"$'\n' == *$'\n'"$2"$'\n'* ]]; }

HERE="$(cd "$(dirname "$0")" && pwd)"
DEPLOY_ROOT="$(cd "$HERE/../.." && pwd)"
REPO_ROOT="$(cd "$DEPLOY_ROOT/.." && pwd)"
CHART="$DEPLOY_ROOT/helm/umbrella/charts/kaname"
PROD="$DEPLOY_ROOT/helm/umbrella/values.prod.yaml"
GATE="$DEPLOY_ROOT/scripts/assert-production-posture.sh"

# Три исхода — ОДНОЙ реализацией на весь каталог: 0 зелено · 1 находка о дереве ·
# 2 условие не создано (плюс текст самого helm). Прежде отказ рендера соседнего
# чарта объявлялся находкой — тем же кодом 1, что и настоящий дефект круга
# отправителей, — и вызывающий не мог их различить машинно (задача #1214).
# shellcheck source=deploy/tests/helm/outcome.sh
. "$HERE/outcome.sh"
EXPECTED_ASSERTIONS=9
require_helm
command -v jq >/dev/null 2>&1 \
  || fatal "нужен jq — вердикт гейта посадки прогоняется его же программой, переписать её здесь нельзя"

GATEWAY_SAN="spiffe://kacho.cloud/ns/kacho/sa/kacho-api-gateway"

# Отсутствие чарта, профиля или самого гейта — УСЛОВИЕ прогона (дерево урезано,
# зеркало собрано неполно), а не свойство того, что мы проверяем.
[ -d "$CHART" ] || fatal "чарта iam нет по пути $CHART — судить не о чем"
[ -f "$PROD" ] || fatal "values.prod.yaml нет по пути $PROD — судить не о чем"
[ -f "$GATE" ] || fatal "гейта посадки нет по пути $GATE — судить не о чем"

# rendered_list <render> — записи списка trusted-forwarder-sans из отрендеренного
# config.yaml. Читаем текстом, а не через yq: в разных средах под этим именем
# стоят два разных инструмента с несовместимым синтаксисом, и тест не должен
# зависеть от того, какой из них оказался в PATH.
rendered_list() {
  printf '%s\n' "$1" \
    | awk '/^ *trusted-forwarder-sans: *$/ {inblk=1; next}
           inblk && /^ *- / {sub(/^ *- */, ""); gsub(/^"|"$/, ""); print; next}
           inblk && !/^ *$/ {exit}'
}

# peer_san <chart-path> — личность сертификата, которую этот чарт РЕАЛЬНО выдаёт
# своему поду. Берём из рендера, а не из шаблона строки: сегмент пространства имён
# НЕ единообразен (storage и оператор живут в своих), и запись, скопированная у
# соседа «по образцу», не совпала бы с предъявляемым сертификатом. Промах здесь
# молчаливый: пир остаётся собой, переданная им личность снимается, и его чтение
# отвечает как неаутентифицированному.
#
# РЕЗУЛЬТАТ — В ГЛОБАЛЬНОЙ ПЕРЕМЕННОЙ, А НЕ В stdout, и это не стиль. Прежде
# значение забиралось подстановкой; под `set -e` присваивание из подстановки, чей
# конвейер отказал, ОБРЫВАЕТ скрипт — и страж «чарт не отрендерил сертификат» ниже
# становился недостижимым. Наблюдалось живьём: чарт реестра перестал рендериться
# без учётных данных хранилища слоёв, конвейер отдал отказ, и весь тест вышел кодом
# 1 БЕЗ ЕДИНОЙ СТРОКИ вывода — «не выполнилось», неотличимое от «упало по существу».
# Обходной приём «|| true» это лечил наполовину: отказ рендера становился ПУСТЫМ
# значением, то есть по-прежнему объявлялся находкой о дереве. Теперь рендер идёт
# через общую реализацию исходов, и код отказа у него свой (2).
PEER_SAN=""
peer_san() { # peer_san <chart-path> → $PEER_SAN
  # Заглушки обязательных значений: без них рендер падает ещё до сертификата.
  #   db.password       — у части чартов;
  #   zot.auth.*        — чарт реестра ОТКАЗЫВАЕТ в рендере без учётных данных
  #                       хранилища слоёв (развернуть открытое он не умеет).
  # К предмету проверки (кто вправе передавать чужую личность) отношения не имеют.
  helm_try x "$1" --namespace kacho --set mtls.enable=true --set db.password=x \
    --set zot.auth.username=selftest --set zot.auth.password=selftest \
    --show-only templates/certificate.yaml
  # ДВА РАЗНЫХ ВОПРОСА, и раньше они давали один ответ: «чарт не отрендерился»
  # (условие прогона) и «отрендерился, а сертификата в нём нет» (свойство дерева).
  # Первое уходит кодом 2 с текстом helm, второе — кодом 1 у вызывающего.
  render_or_fatal "сертификат чарта $1"
  local hits
  hits="$(grep -oE 'spiffe://[^"]+' <<<"$HELM_OUT" || true)"
  PEER_SAN="${hits%%$'\n'*}"
}

# ── 1. Дефолт чарта непуст и совпадает с сертификатами, которые выдают соседи ─
# Круг установлен по рёбрам (кто зовёт ProjectService.Get / Check под личностью
# конечного пользователя), а сами строки — по чартам этих соседей.
helm_try iam "$CHART" --show-only templates/configmap.yaml
render_or_fatal "чарт iam, дефолт"
DEFAULT_RENDER="$HELM_OUT"
def_list="$(rendered_list "$DEFAULT_RENDER")"
[ -n "$def_list" ] \
  || fail "trusted-forwarder-sans отсутствует в конфиге пода ИЛИ пуст по умолчанию: профиль, не задавший ручку, отгрузил бы «доверяем любому пиру с сертификатом» (в боевом режиме — отказ старта)"
EXPECTED_SANS=""
for chart in "$REPO_ROOT/gateway/deploy" "$REPO_ROOT/services/vpc/deploy" \
             "$REPO_ROOT/services/compute/deploy" "$REPO_ROOT/services/nlb/deploy" \
             "$REPO_ROOT/services/storage/deploy" "$REPO_ROOT/services/registry/deploy" \
             "$DEPLOY_ROOT/helm/umbrella/charts/kacho-geo"; do
  peer_san "$chart"; san="$PEER_SAN"
  [ -n "$san" ] || fail "чарт $chart отрендерился, но сертификата в нём нет — тест разошёлся с деревом, обнови его"
  line_in "$def_list" "$san" \
    || fail "дефолт iam не содержит $san (чарт $chart) — этот пир перестал бы говорить за пользователя, и его путь под личностью тенанта молча отвечал бы как неаутентифицированный"
  EXPECTED_SANS="$EXPECTED_SANS$san
"
done
# Обратная сторона: в круге нет НИКОГО, кроме фактических отправителей.
#
# Здесь стояло требование держать запись под компонент вне дерева — «его чарта
# здесь нет, проверим хотя бы, что строку не потеряли». Требование пережило свой
# предмет: компонента с таким именем в дереве нет, репозитория под него не
# существует, и запись описывала отправителя, которого мы не выпускаем. Правило
# велит пинить круг по ФАКТИЧЕСКИМ отправителям, найденным по графу рёбер, —
# запись сверх этого разрешает говорить за пользователя предъявителю чужого
# сертификата (решение владельца 2026-08-09).
#
# Проверка перевёрнута и стала строже: раньше тест ТРЕБОВАЛ запись под
# несуществующее, теперь он на ней ПАДАЕТ. Появится компонент со своим чартом —
# его сертификат отрендерится, попадёт в EXPECTED и проверка пройдёт сама:
# послабление истекает от появления предмета, а не от чьей-то памяти.
for san in $def_list; do
  line_in "$EXPECTED_SANS" "$san" \
    || fail "круг доверенных отправителей содержит $san, которому в дереве не соответствует ни один чарт: круг обязан совпадать с фактическими отправителями, иначе он разрешает говорить за пользователя предъявителю сертификата, которого мы не выпускаем"
done
ok

# ── 2. Оператор всё ещё может выразить пустой список ─────────────────────────
# Чарт не решает за стражу: пусто он отрендерит, а откажет в старте боевой режим
# (Config.Validate → validateProductionTrustedForwarders). Так «пусто» остаётся
# наблюдаемым, а не подменяется чартом на дефолт втихую.
helm_try iam "$CHART" --set 'config.authn.trustedForwarderSANs=[]' \
  --show-only templates/configmap.yaml
render_or_fatal "чарт iam, явно пустая ручка"
EMPTY_RENDER="$HELM_OUT"
[ -z "$(rendered_list "$EMPTY_RENDER")" ] \
  || fail "явно пустая ручка отрендерилась непустой — чарт подменяет намерение оператора"
ok

# ── 3. Правка ручки перекатывает под ─────────────────────────────────────────
# Настройки приезжают файлом из ConfigMap и читаются ОДИН раз при старте. Без
# привязки шаблона пода к содержимому конфига правка не перекатила бы под, процесс
# жил бы со старой посадкой, а стража старта молчала бы — потому что старта не
# было. Ровно этот класс однажды дал ложный зелёный на storage.
# Первая подходящая строка выбирается в bash, а не `grep -m1`: тот выходит по
# первому совпадению, helm получает SIGPIPE, и под `pipefail` подстановка
# объявляла бы отказ рендера на успешном рендере (задача #658).
#
# «Не нашлось» — НЕ отказ этой функции, и `return 0` внизу намеренный: судит об
# этом вызывающий, проверяя значение на пустоту. Так отсутствующая аннотация
# получает СВОЁ сообщение («у пода нет аннотации с хешем конфига»), а не общее
# «deployment does not render», которым `grep -m1` накрывал оба случая сразу.
first_matching() {
  local _l
  while IFS= read -r _l; do
    if [[ "$_l" == *"$2"* ]]; then printf '%s' "$_l"; return 0; fi
  done <<<"$1"
  return 0
}
helm_try iam "$CHART" --show-only templates/deployment.yaml
render_or_fatal "чарт iam, шаблон пода"
RENDER_A="$HELM_OUT"
POD_ANNOT_A="$(first_matching "$RENDER_A" 'kacho.cloud/config-checksum:')"
helm_try iam "$CHART" --set 'config.authn.trustedForwarderSANs[0]=spiffe://kacho.cloud/ns/kacho/sa/kacho-api-gateway' \
  --show-only templates/deployment.yaml
render_or_fatal "чарт iam, шаблон пода со сменённым списком"
RENDER_B="$HELM_OUT"
POD_ANNOT_B="$(first_matching "$RENDER_B" 'kacho.cloud/config-checksum:')"
[ -n "$POD_ANNOT_A" ] \
  || fail "у пода нет аннотации с хешем конфига — правка списка не перекатит его, и процесс останется со старой посадкой"
[ "$POD_ANNOT_A" != "$POD_ANNOT_B" ] \
  || fail "смена списка не меняет хеш конфига в шаблоне пода — под не перекатится, стража старта не сработает"
ok

# ── 4. Боевой профиль повторяет ручку явно ───────────────────────────────────
# Профиль читается через ЕГО СОБСТВЕННЫЙ блок kaname (под-чарт рендерится
# отдельно, umbrella требует vendored-зависимостей). Сверяем поимённо, а не по
# счётчику: «стало на одну меньше» должно называть, кого именно потеряли.
IAM_BLOCK="$(mktemp)"; trap 'rm -f "$IAM_BLOCK"' EXIT
awk '/^kaname:[[:space:]]*$/{i=1;next} i&&/^[A-Za-z0-9_.-]+:/{exit} i{sub(/^  /,"");print}' "$PROD" > "$IAM_BLOCK"
[ -s "$IAM_BLOCK" ] || fail "в $PROD нет блока kaname — тест разошёлся с профилем"
helm_try iam "$CHART" -f "$IAM_BLOCK" --show-only templates/configmap.yaml
render_or_fatal "чарт iam с боевым профилем"
PROD_RENDER="$HELM_OUT"
prod_list="$(rendered_list "$PROD_RENDER")"
# Та же обратная проверка на боевом профиле: круг не шире фактических отправителей.
# Здесь стояло требование держать в профиле запись под компонент вне дерева; предмета
# у него нет (см. разбор в блоке 1).
for san in $prod_list; do
  line_in "$EXPECTED_SANS" "$san" \
    || fail "боевой профиль держит в круге $san, которому в дереве не соответствует ни один чарт — круг обязан совпадать с фактическими отправителями"
done
for chart in "$REPO_ROOT/gateway/deploy" "$REPO_ROOT/services/vpc/deploy" \
             "$REPO_ROOT/services/compute/deploy" "$REPO_ROOT/services/nlb/deploy" \
             "$REPO_ROOT/services/storage/deploy" "$REPO_ROOT/services/registry/deploy" \
             "$DEPLOY_ROOT/helm/umbrella/charts/kacho-geo"; do
  peer_san "$chart"; san="$PEER_SAN"
  line_in "$prod_list" "$san" \
    || fail "боевой профиль потерял отправителя $san (чарт $chart) — его путь под личностью пользователя встанет"
done
ok

# ── 5. Гейт посадки участвует: iam в списке градуируемых ─────────────────────
grep -qE '^FORWARDER_NARROWING_REQUIRED=.*\biam\b' "$GATE" \
  || fail "iam не входит в FORWARDER_NARROWING_REQUIRED — гейт не станет градуировать измерение, и под, никого не сузивший, напечатает галочку"
ok

# ── 6. …и вердикт гейта действительно смотрит на это поле ────────────────────
# Программу jq вынимаем из самого гейта: переписанная здесь копия разъехалась бы с
# оригиналом, и проверка снова стала бы формой без содержания.
JQPROG="$(awk '/verdict="\$\(printf/{f=1} f{print} /join\(", "\)/{if(f) exit}' "$GATE" \
  | sed "1s/.*jq -r --argjson need_fwd \"\\\$need_fwd\" '//")"
JQPROG="${JQPROG%\')\"}"
[ -n "$JQPROG" ] || fail "не удалось вынуть программу вердикта из $GATE (гейт изменил форму — обнови тест)"

# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ниже («сузивший круг проходит») обязан нести КАЖДОЕ
# измерение, которое судит вынутая программа, — иначе он краснеет по чужому
# измерению и говорит об этом голым текстом вердикта, из которого не видно, чего
# не хватает. Ровно это и случилось: гейт завёл `identity_provider` (задача
# #1125), фикстура о нём не знала, и обе проверки круга отправителей стали
# красными по причине, к кругу отношения не имеющей.
#
# Перечень измерений ВЫВОДИТСЯ из программы, а не выписывается: выписанный был бы
# второй копией и разошёлся бы с ней молча — тем же способом, каким разошлась эта.
# `identity_provider` — «own»: значение выбрано только чтобы измерение было
# ЗАЯВЛЕНО (гейт принимает external|own|n/a); какая полоса верна для конкретного
# стенда, этот тест не решает и не проверяет.
line() { # line <trusted_forwarders-фрагмент>
  printf '{"msg":"boot security posture","service":"iam","auth_mode":"production-strict",'
  # internal_mtls — СТРОКОВОЕ измерение с задачи #1024 (три состояния:
  # "true" | "false" | "n/a"), а не булево: у края внутреннего листенера больше
  # нет вовсе, и «нет листенера» обязано быть отличимо от «листенер без mTLS».
  # У ЭТОГО сервиса листенер есть, поэтому величина — "true".
  printf '"db_sslmode":"require","public_mtls":true,"internal_mtls":"true","authz_check":true,'
  printf '"identity_provider":"own"%s}' "$1"
}
verdict() { echo "$1" | jq -r --argjson need_fwd "$2" "$JQPROG"; }

# grep -o дочитывает вход до конца, поэтому SIGPIPE-класса задачи #658 здесь нет.
judged="$(printf '%s\n' "$JQPROG" | grep -oE 'shown\("[a-z_]+"\)' | sed 's/.*"\(.*\)".*/\1/' | sort -u)"
[ -n "$judged" ] || fail "в программе вердикта $GATE не нашлось ни одного измерения — тест разошёлся с гейтом"
control="$(line ',"trusted_forwarders":true')"
missing=""
for dim in $judged; do
  printf '%s' "$control" | jq -e --arg d "$dim" 'has($d)' >/dev/null || missing="$missing $dim"
done
[ -z "$missing" ] || fail "положительный контроль не несёт измерения, которые судит гейт посадки:$missing \
— добавьте их в line(), иначе «сузивший круг проходит» краснеет по чужому измерению"
ok

# сузивший круг под проходит…
v="$(verdict "$(line ',"trusted_forwarders":true')" true)"
[ -z "$v" ] || fail "под, сузивший круг отправителей, забракован вердиктом: '$v'"
ok

# …не сузивший — валится…
v="$(verdict "$(line ',"trusted_forwarders":false')" true)"
case "$v" in *trusted_forwarders*) ;; *) fail "под, НЕ сузивший круг, прошёл вердикт: '$v'";; esac
ok

# …устаревший бинарь без поля — тоже (fail-closed: неотчитанное не считается сделанным).
v="$(verdict "$(line '')" true)"
case "$v" in *trusted_forwarders*) ;; *) fail "самоотчёт без поля прошёл вердикт: '$v'";; esac
ok

outcome_verdict "измерений в программе вердикта: $(printf '%s\n' "$judged" | grep -c .)"
