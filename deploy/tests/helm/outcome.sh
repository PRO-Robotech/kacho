#
# Файл СОРСИТСЯ, не запускается: он не `*-test.sh`, поэтому цель
# `helm-manifest-test` его по глобу не подхватывает — ровно как соседний
# `stacks.sh`, который тем же способом держит единственность таблицы стендов.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ОДНА РЕАЛИЗАЦИЯ
#
# Контракт исходов записан в README этого каталога («Три исхода, и они обязаны
# быть РАЗЛИЧИМЫ»), а исполнялся он копиями: у каждого скрипта свои `fail`,
# свой `render`, своё решение, куда писать диагностику. Копии разошлись — и
# разошлись в ту сторону, где расхождение не видно: ШЕСТЬ скриптов каталога на
# дереве без собранных зависимостей умбреллы отдавали ненулевой код при НУЛЕ
# БАЙТ вывода (задача #1195, замер её предикатом). «Гейт нашёл дефект», «гейт
# сам сломан» и «условие для гейта не создано» давали ОДИН наблюдаемый
# результат, и читатель шёл искать дефект в дереве, которого там нет.
#
#   0 — ЗЕЛЕНО. Печатается перепись: утверждений выполнено из скольких
#       объявленных и сколько рендеров сделано.
#   1 — НАХОДКА О ДЕРЕВЕ: `FAIL: <причина>`. Утверждение не выполнилось — либо
#       выполнилось НЕ ВСЁ объявленное (секцию удалили: молчание о ней ничего
#       не доказывает).
#   2 — «УСЛОВИЕ НЕ СОЗДАНО» / отказ инструмента: `FATAL: <причина>` плюс
#       ТЕКСТ, который сказал сам helm. Зависимости умбреллы не собраны, нет
#       helm, в PATH не тот yq, профиля нет на диске. Это НЕ вердикт о дереве и
#       не зачитывается ни в зелёное, ни в красное (`e2e-flow.md` §1).
#
# Двойка, а не тройка: ровно этот код у `tests/helm/stacks.sh` и у
# `prod-profile-fail-closed-test.sh` для той же категории. Второй контракт кодов
# в одном каталоге был бы двумя местами об одном предмете.
#
# ─────────────────────────────────────────────────────────────────────────────
# ДИАГНОСТИКА ИДЁТ В stderr — И ЭТО НЕ СТИЛЬ
#
# Половина рендеров каталога стоит внутри подстановки (`DOC="$(render …)"`), а
# всё, что функция печатает в stdout изнутри `$( )`, попадает В ПЕРЕМЕННУЮ, а не
# читателю. Проверено: `r() { echo x; exit 2; }; V=$(r)` под `set -e` даёт код 2
# и НОЛЬ БАЙТ вывода. То есть наивная починка «убрать `2>/dev/null`» вернула бы
# текст helm, но по-прежнему проглотила бы собственное сообщение гейта. В stderr
# этот класс невозможен by construction, поэтому туда пишут ВСЕ функции вердикта.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ РЕЗУЛЬТАТ РЕНДЕРА — ГЛОБАЛЬНАЯ ПЕРЕМЕННАЯ, А НЕ stdout
#
# Вызов `V=$(helm_try …)` исполняет функцию в ПОДОБОЛОЧКЕ: и код возврата helm,
# и текст его отказа, и счётчик рендеров остались бы там и до вызывающего не
# доехали. Тогда различать три исхода было бы нечем — то есть вернулся бы ровно
# тот дефект, ради которого библиотека и написана.
#
# ─────────────────────────────────────────────────────────────────────────────
# ВАКУУМНОЕ ОТРИЦАНИЕ — ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕФЕКТА
#
# Рядом с молчанием живёт утверждение вида «этот рендер обязан быть пустым».
# На дереве без собранных зависимостей рендер пуст ВСЕГДА, поэтому такое
# отрицание засчитывалось, ничего не проверив. Разделяет два случая только
# положительный контроль: сперва тот же рендер БЕЗ накладки обязан пройти, и
# лишь тогда пустота накладки приписывается накладке. Для этого здесь есть
# `render_or_fatal` (отказ рендера = код 2, не «пусто») и `assert_render_empty`
# (пустота требует УСПЕШНОГО рендера).
#
# Как этим пользоваться:
#
#   . "$(dirname "$0")/outcome.sh"
#   EXPECTED_ASSERTIONS=6
#   require_helm; require_mikefarah_yq
#   helm_try kacho-umbrella "$UMBRELLA" -f "$DEV" --show-only "$TPL"
#   render_or_fatal "values.dev.yaml → $TPL"
#   DOC="$HELM_OUT"
#   …
#   ok
#   outcome_verdict "профилей прочитано: 2 (dev, prod)"
#   exit 0
#
# ВЕРДИКТ НА ЗЕЛЁНОМ ВОЗВРАЩАЕТ, А НЕ ВЫХОДИТ — и это стоило дефекта. Обе функции
# вердикта выходят ТОЛЬКО на находке (код 1); напечатав PASS, они отдают
# управление обратно, поэтому всё, что стоит НИЖЕ, исполнится. У одного скрипта
# каталога ниже стояла ветка `--self-test`: обычный прогон проваливался в неё и
# отчитывался ЕЁ вердиктом. Ставьте вердикт последней строкой либо `exit 0` за ним.
# Выходить самим нельзя: у другого скрипта вердикт живёт ВНУТРИ функции, которую
# самопроверка зовёт четырежды.
#
# ПО ТОЙ ЖЕ ПРИЧИНЕ СЧЁТЧИКИ ГЛОБАЛЬНЫ И НЕ СБРАСЫВАЮТСЯ. Скрипт, зовущий свою
# проверку несколько раз за прогон, обязан изолировать вызовы подоболочкой
# (`( run_checks "$dir" )`) — иначе находки первого вызова переживут его и покрасят
# отрицательный контроль следующего.
#
# Накопительная форма находки — для проверок посадки, где оператору дешевле
# увидеть ВЕСЬ перечень за один прогон, чем чинить по одной:
#
#   violation "<что не так>"      # считает и ПРОДОЛЖАЕТ (в отличие от `fail`)
#   …
#   outcome_verdict "…"           # красен и по N≠ожидаемого, и по VIOLATIONS>0
#   findings_verdict "…"          # для скрипта, ведущего счёт утверждений САМ
#
# Предпосылки, кроме `require_helm`/`require_mikefarah_yq`:
#
#   require_python_yaml                  # разбор объявлений PyYAML, а не `yq`
#   require_file_present <путь> <что>    # профиля нет на диске
#   require_umbrella_charts <умбрелла>   # зависимости материализованы
#   require_dep_chart <умбрелла> <имя>   # конкретная зависимость на месте
#   require_fresh_dep_charts <умбрелла>  # архив НЕ старше своего исходника
#   render_nonempty_or_fatal "<что>"     # рендер удался, но пуст — судить не о чем
#
# Что каждый потребитель обязан делать сам — и почему это не спрятано сюда:
# ПЕРВЫЙ рендер скрипта обязан быть положительным контролем (чарт вообще
# рендерится), потому что «что именно считать положительным контролем» знает
# только сам скрипт.
#
# Способность этой библиотеки различать исходы держится не чтением, а гейтом
# `tests/helm/three-outcomes-distinguishable-test.sh`: он гоняет КАЖДЫЙ скрипт
# каталога на зеркале дерева БЕЗ собранных зависимостей и требует, чтобы
# ненулевой код приходил с непустым выводом, а у объявивших этот контракт — с
# кодом 2 и текстом helm.

# ── Перепись и вердикт — по счётчикам, никогда по «дошли до конца» ───────────
N=0
RENDERS=0
: "${EXPECTED_ASSERTIONS:=0}"
: "${SCRIPT:=$(basename "${BASH_SOURCE[1]:-$0}")}"

# Перепись печатается при КАЖДОМ ненулевом исходе. «Ожидание не объявлено» и
# «ожидалось ноль» — разные вещи, и раньше они печатались одинаково («0 из 0»):
# скрипт, ведущий счёт утверждений сам (их число зависит от состава стендов),
# выглядел бы как скрипт, которому нечего было проверять.
census() {
  if [ "$EXPECTED_ASSERTIONS" -gt 0 ]; then
    echo "  перепись: утверждений выполнено $N из $EXPECTED_ASSERTIONS; рендеров helm: $RENDERS" >&2
  else
    echo "  перепись: утверждений выполнено $N (ожидание не объявлено — счёт ведёт сам скрипт); рендеров helm: $RENDERS" >&2
  fi
  # Накопленные находки печатаются ТОЛЬКО когда они есть: строка «находок 0»,
  # печатающаяся всегда, перестаёт читаться на третий день, а у скриптов, ведущих
  # счёт своим счётчиком, она была бы ещё и ложной.
  [ "${VIOLATIONS:-0}" -gt 0 ] && echo "  перепись: накоплено находок $VIOLATIONS" >&2
  return 0
}
# fail — НАХОДКА О ДЕРЕВЕ (код 1).
fail()  { echo "FAIL: $1" >&2; census; exit 1; }
# fatal — УСЛОВИЕ НЕ СОЗДАНО / отказ инструмента (код 2). НЕ вердикт о дереве.
fatal() { echo "FATAL: $1" >&2; census; exit 2; }
ok() { N=$((N + 1)); }

# ── Предпосылки инструмента — это «условие не создано», а не находка ─────────
require_helm() {
  command -v helm >/dev/null 2>&1 || fatal "нужен helm — рендерить нечем"
}

# yq ОБЯЗАН быть mikefarah v4. На многих машинах /usr/bin/yq — питонья обёртка
# над jq ТОГО ЖЕ ИМЕНИ: синтаксис фильтров у неё другой, поэтому она ругается в
# stderr и НЕ ПЕЧАТАЕТ НИЧЕГО в stdout. Утверждения вида `[ -z "$(yq … )" ]`
# после этого проходят ВАКУУМНО — проверка отчитывается об успехе, не сверив
# ничего. Ровно тот ложный зелёный, ради которого этот каталог и существует,
# поэтому самозванец опознаётся явно, а не через `command -v`.
require_mikefarah_yq() {
  command -v yq >/dev/null 2>&1 || fatal "нет yq (нужен mikefarah yq v4)"
  # Сравнение — БЕЗ трубы: `… | grep -q` под `set -o pipefail` возвращает ОТКАЗ
  # НА СОВПАДЕНИИ (grep выходит по первому попаданию, писатель получает SIGPIPE,
  # и `pipefail` поднимает ЕГО статус до статуса конвейера). Задача #658.
  local ver; ver="$(yq --version 2>&1 || true)"
  [[ "${ver,,}" == *mikefarah* ]] || fatal \
    "в PATH не тот yq ($(command -v yq)): '$ver'. Нужен mikefarah yq v4 — питонья \
обёртка над jq на этих фильтрах молча отдаёт ПУСТО, и утверждения прошли бы, ничего не сверив"
}

# ── helm_try <аргументы helm template…> ──────────────────────────────────────
# Рендер, чей КОД ВОЗВРАТА берётся КАК ДАННЫЕ, а не как условие продолжения.
# Сама ничего не решает: «отказал» и «отказал по НАШЕЙ причине» — разные
# вопросы, и второй решает вызывающий.
HELM_OUT=""
HELM_ERR=""
HELM_RC=0
helm_try() {
  local errf; errf="$(mktemp)"
  HELM_OUT="$(helm template "$@" 2>"$errf")" && HELM_RC=0 || HELM_RC=$?
  RENDERS=$((RENDERS + 1))
  # Предупреждение про kubeconfig helm печатает всегда, и оно не про отказ.
  HELM_ERR="$(grep -vE 'WARNING: Kubernetes configuration' "$errf" || true)"
  rm -f "$errf"
}

# ── helm_said — ТЕКСТ, который сказал сам helm, в stderr ─────────────────────
# Без него читатель получает голое «render failed» и идёт искать дефект в
# дереве. Пустой текст называется пустым, а не подменяется молчанием.
helm_said() {
  echo "--- helm отказал: $1 ---" >&2
  if [ -n "$HELM_ERR" ]; then printf '%s\n' "$HELM_ERR" >&2; else echo "(helm не сказал ничего)" >&2; fi
  echo "--- конец текста helm ---" >&2
}

# ── render_or_fatal <что рендерили> ──────────────────────────────────────────
# Отказ рендера — это УСЛОВИЕ прогона, а не свойство дерева.
render_or_fatal() {
  [ "$HELM_RC" -eq 0 ] && return 0
  helm_said "$1"
  # Подсказка называется ТОЛЬКО когда helm сказал именно про зависимости. Иначе
  # это была бы догадка, поданная как диагноз: «соберите зависимости» на отказе
  # по другой причине увело бы читателя ровно так же, как молчание.
  local hint=""
  case "$HELM_ERR" in
    *"missing in charts/ directory"*|*"dependency build"*)
      hint=" Зависимости умбреллы в git не лежат; соберите их: bash deploy/scripts/helm-umbrella-deps.sh" ;;
  esac
  fatal "helm template отказал на «$1» — это УСЛОВИЕ прогона, а не свойство дерева.$hint"
}

# ── render_must_fail_because <подстрока> <что рендерили> <сообщение находки> ──
# Отрицание «рендер обязан отказать» с проверкой ПРИЧИНЫ. Без сверки с причиной
# утверждение принимает ЛЮБОЙ отказ — включая «зависимости не собраны», то есть
# проходит вакуумно ровно там, где условия нет.
render_must_fail_because() {
  local want="$1" what="$2" msg="$3"
  [ "$HELM_RC" -ne 0 ] || fail "$msg"
  case "$HELM_ERR" in
    *"$want"*) ;;
    *) helm_said "$what"
       fail "рендер «$what» отказал НЕ из-за «$want» — отрицание проходило бы вакуумно" ;;
  esac
}

# ── assert_render_empty <что рендерили> <сообщение находки> ──────────────────
# «Здесь ничего не должно отрендериться» — утверждение о ПУСТОМ УСПЕШНОМ
# рендере. Отказ рендера пустотой не является: он уходит в код 2.
# Второй аргумент — предикат непустоты (yq-фильтр); без него считается сам вывод.
assert_render_empty() {
  local what="$1" msg="$2" got="${3-}"
  render_or_fatal "$what"
  [ -z "${got:-$HELM_OUT}" ] || fail "$msg"
}

# ── НАКОПЛЕНИЕ НАХОДОК: перечислить ВСЕ, а не первую ────────────────────────
#
# `fail` обрывает прогон первой же находкой. Для проверки посадки это часто не то,
# что нужно: профиль объявляет десятки величин, и оператору дешевле увидеть
# ВЕСЬ перечень за один прогон, чем чинить по одной, каждый раз перерендеривая
# умбреллу. Поэтому у находки есть вторая форма — накопительная.
#
# Форма НЕ была общей, и это стоило расхождения: одну и ту же накопительную
# находку каталог реализовывал ЧЕТЫРЬМЯ частными копиями с тремя разными
# префиксами вывода (`  ✗ `, `FAIL: `) и тремя разными именами (`fail`, `violation`,
# `refuse`-сосед). Копия у `fail` особенно коварна: имя занято общей реализацией,
# где `fail` ОБРЫВАЕТ, — то есть один и тот же вызов в двух скриптах каталога
# означал противоположное.
#
# Счётчик отдельный от `N`: `N` считает ВЫПОЛНЕННОЕ (объём осмотренного),
# `VIOLATIONS` — НАЙДЕННОЕ. Смешать их значит потерять различие между «проверок
# ноль» и «находок ноль» — то самое, ради чего этот файл написан.
VIOLATIONS=0
violation() { echo "  ✗ $1"; VIOLATIONS=$((VIOLATIONS + 1)); }

# findings_verdict [хвост переписи] — вердикт для скрипта, который ведёт счёт
# утверждений САМ (их число зависит от состава стендов, и `EXPECTED_ASSERTIONS`
# ему объявить нечем). Проверяет ДВЕ вещи, и вторая не менее важна первой:
#   • находок ноль;
#   • утверждений выполнено БОЛЬШЕ НУЛЯ — «ноль находок» на нулевом обходе
#     означает «ноль прочитанного», и это провал, а не чистота.
findings_verdict() {
  if [ "$N" -eq 0 ]; then
    fail "$SCRIPT — не выполнено НИ ОДНОГО утверждения: «ноль находок» здесь означает «ноль прочитанного»"
  fi
  if [ "${VIOLATIONS:-0}" -gt 0 ]; then
    fail "$SCRIPT — находок $VIOLATIONS (перечень выше)"
  fi
  echo "PASS: $SCRIPT ($N assertions, находок 0) — рендеров helm: $RENDERS${1:+; $1}"
}

# ── Предпосылки, которых общей реализации НЕ ХВАТАЛО ────────────────────────
# Каждая ниже была найдена как ЧАСТНАЯ копия у скриптов, не объявлявших общий
# контракт. Перечислены здесь не «на будущее»: у каждой есть вызывающий.

# require_python_yaml — разбор объявлений идёт PyYAML, а не `yq`, ОСОЗНАННО.
# В PATH под именем `yq` бывают две разные программы, и питонья обёртка над jq на
# фильтрах вида `.["a"]["b"]` не отдаёт ошибку — она отдаёт ПУСТО. Гейт, который
# на такой машине резолвит НОЛЬ объявлений и отчитывается полнотой, есть экземпляр
# ровно того класса, ради которого этот каталог существует.
require_python_yaml() {
  command -v python3 >/dev/null 2>&1 || fatal "нет python3 — объявления потребителей читать нечем"
  python3 -c 'import yaml' 2>/dev/null \
    || fatal "нужен python3 с PyYAML — им читаются объявления потребителей (pip install pyyaml)"
}

# require_python3 — разбор идёт python'ом БЕЗ YAML (регулярные выражения, json).
# Отдельно от `require_python_yaml`, и это не дробление ради дробления: половина
# потребителей разбирает `re`, и требовать от них PyYAML значило бы объявить
# «условие не создано» там, где условие ЕСТЬ.
require_python3() {
  command -v python3 >/dev/null 2>&1 || fatal "нет python3 — разбирать нечем"
}

# require_file_present <путь> <что это> — профиля нет на диске, значит судить не о чем.
require_file_present() {
  [ -f "$1" ] || fatal "$2 не найден на диске: $1"
}

# require_dir_present <путь> <что это> — отдельно от файла НАМЕРЕННО: `-f` на
# каталоге отвечает отказом, и общий вердикт сказал бы «не найден на диске» о том,
# что на диске есть. Отказ, называющий неверную причину, уводит читателя так же,
# как молчание.
require_dir_present() {
  [ -d "$1" ] || fatal "$2 не найден на диске: $1"
}

# require_umbrella_charts <каталог умбреллы> — зависимости МАТЕРИАЛИЗОВАНЫ.
# Проверка ДО рендера, а не реакция на его отказ: без неё обход увидел бы часть
# стека и отчитался ПОЛНОТОЙ — то есть зелёным на непрочитанном.
require_umbrella_charts() {
  [ -d "$1/charts" ] || fatal \
    "зависимости умбреллы не материализованы (нет $1/charts) — обход увидел бы часть стека и \
отчитался полнотой. Собрать: bash deploy/scripts/helm-umbrella-deps.sh"
}

# require_dep_chart <каталог умбреллы> <имя чарта> — конкретная зависимость на месте.
# Архивом ЛИБО распакованным каталогом: `helm dep update` кладёт первое, ручная
# правка — второе, и обе формы законны.
require_dep_chart() {
  ls "$1"/charts/"$2"-*.tgz >/dev/null 2>&1 && return 0
  [ -d "$1/charts/$2" ] && return 0
  fatal "чарт «$2» не материализован в $1/charts — без него рендер неполон, а обход \
нашёл бы ЧАСТЬ потребителей и отчитался полнотой. Собрать: bash deploy/scripts/helm-umbrella-deps.sh"
}

# require_fresh_dep_charts <каталог умбреллы> — АРХИВ НЕ СТАРШЕ СВОЕГО ИСХОДНИКА.
#
# Отдельная категория, которой в общей реализации не было вовсе, и её не закрывает
# ни одна из проверок выше: рендер УДАЁТСЯ, он непуст, зависимости на месте — и при
# этом показывает ПРОШЛОЕ состояние дерева. Локальная зависимость приезжает в рендер
# архивом `charts/<имя>-<версия>.tgz`, собранным из каталога сервиса; правка исходника
# в архив не попадает, пока его не пересоберут.
#
# Опаснее обычного устаревания тем, что ошибается в ОБЕ стороны: находка по уже
# исправленному файлу — потерянное время, а ЗЕЛЁНОЕ по архиву, собранному до внесения
# дефекта, — пропущенный дефект. Вердикт о дереве, вынесенный по его снимку недельной
# давности, — это «не выполнилось», а не «чисто».
#
# В конвейере предпосылка выполняется сама (свежий checkout → архивы собираются ПОСЛЕ
# выкладки исходников), поэтому там проверка молчит и ничего не стоит.
require_fresh_dep_charts() {
  local umbrella="$1" stale="" dep depdir name tgz newer
  [ -f "$umbrella/Chart.yaml" ] || fatal "нет $umbrella/Chart.yaml — состав зависимостей читать неоткуда"
  while IFS= read -r dep; do
    [ -z "$dep" ] && continue
    depdir="$umbrella/$dep"
    [ -d "$depdir" ] || continue
    name="$(sed -nE 's/^name:[[:space:]]*(.*)$/\1/p' "$depdir/Chart.yaml" 2>/dev/null | head -1)"
    [ -n "$name" ] || continue
    tgz="$(ls -1 "$umbrella/charts/$name"-*.tgz 2>/dev/null | head -1)"
    if [ -z "$tgz" ]; then stale="$stale $name(архива нет)"; continue; fi
    newer="$(find "$depdir" -type f -newer "$tgz" -print -quit 2>/dev/null)"
    [ -n "$newer" ] && stale="$stale $name"
  done < <(sed -nE 's#^[[:space:]]*repository:[[:space:]]*file://(.*)$#\1#p' "$umbrella/Chart.yaml")
  [ -z "$stale" ] || fatal \
    "исходник чарта НОВЕЕ собранного архива:$stale — рендер показал бы ПРОШЛОЕ состояние дерева, \
и вердикт относился бы не к тому, что лежит в исходниках. Пересоберите: bash deploy/scripts/helm-umbrella-deps.sh"
}

# ── render_nonempty_or_fatal <что рендерили> ────────────────────────────────
# Зеркало `assert_render_empty`: там пустота — утверждение, здесь она — ОТСУТСТВИЕ
# предмета. Успешный, но пустой рендер обычно значит несобранные зависимости, и
# судить по нему нельзя: все последующие утверждения прошли бы вакуумно.
render_nonempty_or_fatal() {
  render_or_fatal "$1"
  [ -n "$HELM_OUT" ] || fatal "рендер «$1» УСПЕШЕН, но ПУСТ — судить не о чем; \
все утверждения по нему прошли бы вакуумно (зависимости не собраны?)"
}

# ── outcome_verdict [хвост переписи] ─────────────────────────────────────────
# Секция, которую удалили или закомментировали, НЕ имеет права оставить за собой
# зелёный вердикт: её утверждения не исполнялись, и молчание о них ничего не
# доказывает. Это находка о дереве (код 1), а не «условие не создано».
outcome_verdict() {
  # Ожидание ОБЯЗАНО быть объявлено: без него сверка «N против ожидаемого»
  # выродилась бы в «0 против 0» и печатала бы PASS на скрипте, не выполнившем
  # ни одного утверждения. Скрипт, чей счёт ведётся им самим, вердикт печатает
  # сам и эту функцию не зовёт.
  if [ "$EXPECTED_ASSERTIONS" -le 0 ]; then
    echo "FAIL: $SCRIPT — ожидание не объявлено (EXPECTED_ASSERTIONS=$EXPECTED_ASSERTIONS): вердикт «$N из $EXPECTED_ASSERTIONS» ничего не утверждает" >&2
    exit 1
  fi
  if [ "$N" -ne "$EXPECTED_ASSERTIONS" ]; then
    echo "FAIL: $SCRIPT — утверждений выполнено $N из $EXPECTED_ASSERTIONS: секция пропущена или удалена, её утверждения не исполнялись" >&2
    exit 1
  fi
  # Накопленные находки — тоже находки. Скрипт, собравший их через `violation` и
  # дошедший до конца, зелёным быть не вправе: иначе накопительная форма означала
  # бы «нашли и промолчали».
  if [ "${VIOLATIONS:-0}" -gt 0 ]; then
    echo "FAIL: $SCRIPT — находок $VIOLATIONS (перечень выше); утверждений выполнено $N из $EXPECTED_ASSERTIONS" >&2
    exit 1
  fi
  echo "PASS: $SCRIPT ($N assertions) — рендеров helm: $RENDERS${1:+; $1}"
}
