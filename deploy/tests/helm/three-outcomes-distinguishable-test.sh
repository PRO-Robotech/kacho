mirror_except() { # <src> <dst> <пропустить…>
  local src="$1" dst="$2"; shift 2
  local e b skip
  mkdir -p "$dst"
  for e in "$src"/* "$src"/.[!.]*; do
    [ -e "$e" ] || continue
    b="$(basename "$e")"
    for skip in "$@"; do [ "$b" = "$skip" ] && continue 2; done
    ln -sfn "$e" "$dst/$b"
  done
}

