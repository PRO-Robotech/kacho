# executable_lines <файл> — без строк-комментариев И без ТЕКСТА СООБЩЕНИЙ.
#
# Комментарий отбрасывается потому, что гейт, читающий текст, засчитал бы за
# объявление контракта соседний `# shellcheck source=…`.
#
# Текст сообщения отбрасывается по той же причине, и цена этого измерена. Пока
# отбрасывались только комментарии, предикат «скрипт собирает зависимости САМ»
# срабатывал на строке `echo "  Собрать: (cd … && helm dep update)"` — то есть на
# ДИАГНОСТИКЕ о том, что зависимостей нет. Из восьми исключённых скриптов
# зависимости материализовали ТРИ; остальные пять были исключены за упоминание в
# сообщении. Один из них (`hydra-jwks-url-test.sh`) на дереве без зависимостей
# умирал НА ПРИСВАИВАНИИ из подстановки — кодом 1 и с НУЛЁМ БАЙТ вывода, — то есть
# нёс ровно тот дефект #1195, ради которого этот гейт и написан, и был невидим для
# него по построению.
executable_lines() {
  sed -E -e 's/[[:space:]]#[[:space:]].*$//' -e '/^[[:space:]]*#/d' \
         -e 's/^[[:space:]]*(echo|printf|note|warn)[[:space:]].*$//' \
         -e 's/(fail|fatal|refuse|die|violation)[[:space:]]+".*$//' "$1"
}

# ОБА предиката читают тело ЧЕРЕЗ ПЕРЕМЕННУЮ, а не через трубу. `sed … | grep -q`
# под `set -o pipefail` возвращает ОТКАЗ НА СОВПАДЕНИИ: grep выходит по первому
# попаданию, sed получает SIGPIPE, и `pipefail` поднимает ЕГО статус до статуса
# конвейера — а произойдёт это или нет, решает гонка между процессами. Наблюдалось
# здесь же: два прогона подряд на НЕИЗМЕННОМ дереве насчитали 6 и 4
# материализующих зависимости скрипта. Задача #658.
declares_contract() { # сорсит ли скрипт общую реализацию исходов
  # Путь несёт собственную подстановку с пробелом (`. "$(dirname "$0")/outcome.sh"`),
  # поэтому «слово без пробелов» здесь не годится: первая редакция предиката
  # насчитала НОЛЬ объявивших на шести объявивших, и гейт честно отказался
  # судить по вакуумной популяции — своей же проверкой предпосылки.
  local body; body="$(executable_lines "$1")"
  grep -qE '(^|[[:space:]])(\.|source)[[:space:]].*outcome\.sh' <<<"$body"
}
builds_deps() { # материализует ли зависимости САМ
  local body; body="$(executable_lines "$1")"
  grep -qE 'helm[[:space:]]+dep|helm-umbrella-deps' <<<"$body"
}

# renders_of <вывод> — сколько рендеров скрипт УСПЕЛ СДЕЛАТЬ. Число печатает сама
# общая реализация (строка переписи «… рендеров helm: N»), поэтому спрашивать его
# не приходится: оно уже в выводе, который гейт и так читает.
#
# ЗАЧЕМ ОНО ЗДЕСЬ. Утверждение 2 требовало текста helm от ЛЮБОГО кода 2 — то есть
# молча предполагало, что «условие не создано» всегда рождается отказом рендера.
# Для прежней популяции это было верно, и потому невидимо: все объявившие доходили
# до рендера. Предположение ложно для предпосылок, которые срабатывают РАНЬШЕ
# первого рендера — нет инструмента, не материализован чарт зависимости, архив
# старше исходника, нет профиля на диске. Текста helm у них не существует, и
# требовать его значит либо толкать скрипт рендерить впустую ради строчки в
# выводе, либо объявлять находкой правильное поведение.
#
# Пусто (строки переписи в выводе нет) — САМО ПО СЕБЕ находка: объявивший контракт
# обязан печатать перепись, иначе «ноль находок» неотличимо от «ноль прочитанного».
#
# ОСТАТОЧНАЯ СЛЕПАЯ ЗОНА НАЗВАНА, А НЕ УМОЛЧАНА: счётчик бумкает `helm_try`,
# поэтому скрипт, зовущий `helm template` в обход общей реализации, отчитается
# нулём рендеров и требования текста избежит. Утверждение 1 на нём остаётся в
# силе (ненулевой код обязан прийти с текстом), но именно текста helm с него уже
# не спросят. Закрывается это не здесь, а тем, что рендер идёт через `helm_try`;
# ширина зоны измерима: `grep -c "helm template" *-test.sh` при нуле у объявивших
# контракт означает, что зоны сегодня нет.
renders_of() {
  local line n=""
  while IFS= read -r line; do
    case "$line" in
      *"рендеров helm: "*)
        n="${line##*рендеров helm: }"
        n="${n%%[!0-9]*}"
        ;;
    esac
  done <<<"$1"
  printf '%s' "$n"
}

# helm_text_relayed <вывод> — вывод несёт блок «что сказал helm», и блок НЕ пуст.
# Требуется именно блок, а не подстрока из сообщения helm: привязка к его
# формулировке сделала бы гейт красным на смене версии helm, то есть по причине,
# к дереву отношения не имеющей.
helm_text_relayed() {
  local out="$1" inside=0 line
  case "$out" in *"--- helm отказал:"*) ;; *) return 1 ;; esac
  while IFS= read -r line; do
    case "$line" in
      "--- helm отказал:"*) inside=1; continue ;;
      "--- конец текста helm ---") inside=0; continue ;;
    esac
    if [ "$inside" = 1 ] && [ -n "$line" ] && [ "$line" != "(helm не сказал ничего)" ]; then
      return 0
    fi
  done <<<"$out"
  return 1
}

