SYN

  # (J) ОБЪЯВИЛ КОНТРАКТ И НЕ НАПЕЧАТАЛ ПЕРЕПИСЬ: причину назвал своими словами в
  #     обход общей реализации. Вывод непуст, поэтому утверждение 1 молчит, а
  #     «сколько он успел осмотреть» установить НЕЧЕМ — то есть «ноль находок»
  #     неотличимо от «ноль прочитанного».
  mk zz-contract-nocensus-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
. "$(dirname "$0")/outcome.sh"
EXPECTED_ASSERTIONS=1
echo "FATAL: своими словами, в обход общей реализации" >&2
exit 2
SYN

  # (F) ДЕФЕКТ #1214 дословно: о причине ГОВОРИТ, но кодом 1 — тем же, которым
  #     объявляется находка о дереве. Контракта не объявляет, поэтому утверждение
  #     2 его не видит; ловит утверждение 3.
  mk zz-speaks-code1-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
if ! DOC="$(helm template x "$ROOT/helm/umbrella" -f "$ROOT/helm/umbrella/values.dev.yaml" \
  --show-only templates/namespace.yaml 2>&1)"; then
  echo "FAIL: рендер не удался: $DOC"
  exit 1
fi
SYN

