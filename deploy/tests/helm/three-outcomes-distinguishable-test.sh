# three-outcomes-distinguishable-test.sh — НЕНУЛЕВОЙ КОД ОБЯЗАН ПРИЙТИ С ТЕКСТОМ.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЛОВИТ — НА КОНКРЕТНОМ СЛУЧАЕ
#
# Свежий клон: `helm/umbrella/charts/*.tgz` в git не лежат. В этом состоянии
# ШЕСТЬ скриптов каталога отдавали ненулевой код при НУЛЕ БАЙТ вывода (#1195;
# седьмой закрыт раньше — #1187; восьмой нашёлся позже, когда предикат исключений
# перестал засчитывать упоминание в тексте за вызов, — #1214). Механика у всех
# одна: `DOC="$(render …)"`
# внутри подстановки под `set -e`, а `render` гасила stderr. helm отказывал по
# причине, НЕ относящейся к предмету проверки, прогон умирал на первом же
# рендере, и наблюдаемый результат у трёх РАЗНЫХ состояний совпадал:
#
#   • гейт нашёл дефект в дереве          → надо чинить дерево;
#   • гейт сам сломан                     → надо чинить гейт;
#   • условие для гейта не создано        → надо собрать зависимости.
#
# Читатель шёл искать дефект в дереве, которого там нет. Это третья категория
# исхода — «не выполнилось», — поданная как красный вердикт (`e2e-flow.md` §1).
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ГЕЙТ, А НЕ ШЕСТЬ ПОЧИНЕННЫХ ЭКЗЕМПЛЯРОВ
#
# Починка шести закрывает находку и оставляет класс: седьмой скрипт напишут
# завтра, и он не покраснеет ничем. Предикат, которым класс замерен в #1195,
# исполняется здесь как проверка — и заодно перестаёт быть разрушительным:
# та его редакция СНИМАЛА `charts/*.tgz` в живом дереве, а этот гейт строит
# ЗЕРКАЛО (символьные ссылки на всё, кроме умбреллы; умбрелла — копия без
# архивов) и живой рабочей копии не касается вовсе.
#
# ─────────────────────────────────────────────────────────────────────────────
# ТРИ УТВЕРЖДЕНИЯ, И У НИХ РАЗНЫЕ ПОПУЛЯЦИИ
#
#   1. КАЖДЫЙ осмотренный скрипт: ненулевой код ⇒ вывод НЕПУСТ. Это дословно
#      предикат снятия #1195.
#   2. Скрипт, ОБЪЯВИВШИЙ контракт (сорсит `outcome.sh`): на этом состоянии
#      отдаёт 0 либо 2, печатает перепись, и при 2 — ТЕКСТ, который сказал сам
#      helm, ЕСЛИ рендер вообще звали. Оговорка не косметическая: предпосылка,
#      срабатывающая РАНЬШЕ первого рендера (нет инструмента, не материализован
#      чарт зависимости, архив старше исходника, нет профиля на диске), текста
#      helm не имеет by construction, и безусловное требование объявляло бы
#      находкой правильное поведение. Звали рендер или нет — гейт не гадает:
#      число рендеров печатает сама общая реализация. Ноль законен:
#      часть скриптов рендерит только ПОД-чарты, которым собранные зависимости
#      умбреллы не нужны, — требование «ровно 2» объявляло бы находкой то, что
#      дефектом не является. Объявление читается по ИСПОЛНЯЕМОЙ строке, а не по
#      слову: у каждого потребителя строкой выше стоит комментарий
#      `# shellcheck source=…`, и предикат по тексту засчитал бы за объявление его.
#   3. КОДОМ 1 не отказывает НИКТО (предикат снятия #1214). Дерево здесь не
#      тронуто — снята ровно одна вещь, собранные зависимости, — поэтому
#      единственный законный ненулевой исход тут «условие не создано». До этого
#      утверждения перечень отказавших кодом 1 только ПЕЧАТАЛСЯ: десять скриптов
#      о причине говорили, но выходили тем же кодом, каким объявляется находка о
#      дереве, и вызывающий не мог их различить машинно. Третья категория
#      существует затем, чтобы её можно было ПОСЧИТАТЬ (`e2e-flow.md` §1).
#   4. КАЖДЫЙ скрипт каталога ОБЪЯВЛЯЕТ общий контракт (предикат снятия #1260).
#      До него число «объявили N из N» только ПЕЧАТАЛОСЬ: оно сошлось усилием, а
#      не построением, и следующий несведённый скрипт не покраснил бы ничего.
#      Популяция здесь ШИРЕ, чем у (1)–(3), и это не расширение впрок: объявление
#      читается БЕЗ ЗАПУСКА, поэтому спрашивается и у тех, кого обход не гоняет.
#      Исключение «материализует зависимости САМ» заведено ради цены (сеть) и
#      работать как освобождение от контракта не вправе — пока работало, в нём
#      сидели ДВА скрипта, отдававших код 1 на «условие не создано» (нет PyYAML,
#      не собраны зависимости, сорвался рендер), то есть живой дефект #1214,
#      невидимый этому гейту by construction.
#
# Популяция (2) — те, кого обход ГОНЯЕТ и кто объявил контракт; популяции (1) и
# (3) — весь осмотренный каталог; популяция (4) — каталог ЦЕЛИКОМ, включая
# исключённых из прогона и сам этот гейт.
#
# ─────────────────────────────────────────────────────────────────────────────
# СЛЕПАЯ ЗОНА НАЗВАНА, А НЕ УМОЛЧАНА — И ОДНАЖДЫ ОНА БЫЛА ШИРЕ, ЧЕМ ДУМАЛИ
#
# Скрипты, которые материализуют зависимости САМИ, из обхода исключены: иначе
# каждый тянул бы полный `helm dep update` по сети (замер владельца операции:
# 22 объявления, 3 мин 22 с), и минутная проверка стала бы получасовой. Дефекта
# этого класса у них нет by construction — они условие себе создают, — но если
# у такого скрипта сорвётся сама материализация, отвечать за категорию будет
# `scripts/helm-umbrella-deps.sh` (у него код 3 для «источник не ответил»).
# Их имена и число печатаются, чтобы исключение было видно, а не подразумевалось.
#
# ПРЕДИКАТ ИСКЛЮЧЕНИЯ ЧИТАЕТ ВЫЗОВ, А НЕ СЛОВО. Пока он читал слово, из восьми
# исключённых зависимости материализовали ТРИ: остальные пять были исключены за
# строку `echo "  Собрать: (cd … && helm dep update)"` — то есть за ДИАГНОСТИКУ о
# том, что зависимостей нет. Цена измерена: один из этих пяти на дереве без
# зависимостей умирал НА ПРИСВАИВАНИИ из подстановки, кодом 1 и с НУЛЁМ БАЙТ
# вывода, — то есть нёс живой экземпляр #1195 и был невидим этому гейту by
# construction. Обе стороны предиката доказаны инъекцией (случаи G и H в
# самопроверке): «сборщик на словах» обязан быть осмотрен, вызывающий владельца —
# исключён и назван.
#
# Самопроверка: --self-test (инъекции в обе стороны; идут в ЗЕРКАЛО, живой
# рабочей копии не касаются).
set -euo pipefail

SCRIPT="$(basename "$0")"
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$HERE/../.." && pwd)"

# shellcheck source=deploy/tests/helm/outcome.sh
. "$HERE/outcome.sh"
EXPECTED_ASSERTIONS=4

require_helm

# Каталог, откуда берётся ПОПУЛЯЦИЯ. Переопределяется только самопроверкой —
# ей надо подложить синтетические скрипты, не трогая дерево.
SCRIPT_DIR="${THREE_OUTCOMES_SCRIPT_DIR:-$HERE}"

# ── Зеркало дерева БЕЗ собранных зависимостей ────────────────────────────────
# Всё, кроме умбреллы, — символьные ссылки: ноль копирования и ноль расхождения
# с деревом. Умбрелла копируется (65 файлов, ~1 МБ) по одной причине: helm
# ходит по каталогу чарта и на каждую ссылку внутри него печатает
# `walk.go: found symbolic link`, а этот шум попал бы в текст, который гейт
# читает как «что сказал helm».
# ═════════════════════════════════════════════════════════════════════════════
# САМОПРОВЕРКА — гейт обязан краснеть на внесённом дефекте и МОЛЧАТЬ на законном
# близнеце той же формы. Гейт, доказанный с одной стороны, ловит форму, а не
# существо, и его снимут при первом ложном срабатывании.
#
# Инъекции идут в СИНТЕТИЧЕСКУЮ популяцию (временный каталог со ссылками на
# настоящие скрипты плюс подложенные), живой рабочей копии самопроверка не
# касается вовсе.
# ═════════════════════════════════════════════════════════════════════════════
if [ "${1:-}" = "--self-test" ]; then
  echo "=== $SCRIPT --self-test: молчание ловится, законный близнец молчит ==="
  st_rc=0
  st_checked=0
  ST="$(mktemp -d)"
  trap 'rm -rf "$ST"' EXIT

  st_pop() { # st_pop <каталог> [синтетика…] — популяция = дерево + подложенное
    local dir="$1"; shift
    mkdir -p "$dir"
    local f
    for f in "$HERE"/*-test.sh; do ln -sfn "$f" "$dir/$(basename "$f")"; done
    for f in "$@"; do cp "$f" "$dir/$(basename "$f")"; done
  }

  # st_probe <метка> <ожидаемый код> <каталог> <обязательная подстрока…>
  #
  # Подстрок несколько, и это не удобство. Пока проба требовала ТОЛЬКО имени
  # виновника, она не различала, КАКОЕ утверждение отказало: инъекция под
  # утверждение 1 зеленела бы и тогда, когда её нашло утверждение 4. Требуя
  # вдобавок ТЕКСТ ПРИЧИНЫ, проба пришпиливает инъекцию к своей полосе.
  st_probe() {
    local label="$1" want_rc="$2" dir="$3"; shift 3
    local out rc txt missing=""
    st_checked=$((st_checked + 1))
    out="$(THREE_OUTCOMES_SCRIPT_DIR="$dir" bash "$0" 2>&1)" && rc=0 || rc=$?
    if [ "$rc" -ne "$want_rc" ]; then
      echo "  ✗ $label — код $rc, ожидался $want_rc"
      printf '%s\n' "$out" | sed 's/^/      /'
      st_rc=1; return
    fi
    for txt in "$@"; do
      case "$out" in *"$txt"*) ;; *) missing="$missing «$txt»" ;; esac
    done
    if [ -z "$missing" ]; then
      echo "  ✓ $label — код $rc, назван$(printf ' «%s»' "$@")"
    else
      echo "  ✗ $label — код $rc верен, но в выводе нет:$missing"
      printf '%s\n' "$out" | sed 's/^/      /'
      st_rc=1
    fi
  }

  # ── синтетические скрипты: ровно те формы, которые гейт различает ──────────
  mk() { cat >"$ST/$1"; }

  # (A) ДЕФЕКТ #1195 дословно: подстановка под `set -e`, stderr погашен.
  mk zz-silent-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DOC="$(helm template x "$ROOT/helm/umbrella" -f "$ROOT/helm/umbrella/values.dev.yaml" \
  --show-only templates/namespace.yaml 2>/dev/null)"
echo "$DOC"
SYN

  # (B) ЗАКОННЫЙ БЛИЗНЕЦ той же формы: тот же отказ, но скрипт ОБЪЯВЛЯЕТ общий
  #     контракт и исполняет его — код 2, перепись, текст helm. Гейт обязан
  #     молчать по всем четырём утверждениям сразу; это положительный контроль
  #     утверждения 1 (ненулевой код пришёл с текстом) и утверждения 2.
  #
  #     Прежняя редакция этого близнеца различала исходы СВОИМИ средствами, не
  #     объявляя общей реализации, и была законна ровно до утверждения 4. Оно
  #     объявляет такую форму находкой — и это осознанная смена нормы, а не
  #     недосмотр: см. (K) ниже, где та же форма стоит уже инъекцией.
  mk zz-speaks-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
. "$(dirname "$0")/outcome.sh"
EXPECTED_ASSERTIONS=1
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
helm_try x "$ROOT/helm/umbrella" -f "$ROOT/helm/umbrella/values.dev.yaml" \
  --show-only templates/namespace.yaml
render_or_fatal "пространство имён"
ok
outcome_verdict
SYN

  # (C) ИНЪЕКЦИЯ, РАЗЛИЧАЮЩАЯ ПРЕДИКАТ: слово `outcome.sh` стоит в КОММЕНТАРИИ,
  #     а исполняемой строки нет. По всему остальному скрипт БЕЗУПРЕЧЕН — код 2,
  #     непустой вывод, напечатанная перепись, ноль рендеров, — и это здесь
  #     несущее свойство, а не декорация: гейт, читающий ТЕКСТ вместо
  #     исполняемой строки, счёл бы его объявившим контракт и не нашёл бы ничего
  #     ни одним из четырёх утверждений. То есть проба краснеет РОВНО тогда,
  #     когда предикат читает текст, и молчит, когда читает разбор.
  mk zz-mentions-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
# Здесь могло бы стоять: . "$(dirname "$0")/outcome.sh" — но не стоит.
echo "FATAL: условие не создано (причина названа своими словами)" >&2
echo "  перепись: утверждений выполнено 0 из 1; рендеров helm: 0" >&2
exit 2
SYN

  # (K) ИНЪЕКЦИЯ УТВЕРЖДЕНИЯ 4 в чистом виде: различает исходы СВОИМИ средствами
  #     и общей реализации не объявляет. Ни слова про `outcome.sh` — то есть от
  #     (C) отличается ровно комментарием, и вдвоём они и составляют пару
  #     «предикат читает разбор, а не слово».
  #
  #     По утверждениям 1–3 скрипт безупречен: вывод непуст, код 2, перепись
  #     напечатана. Значит покраснеть он может ТОЛЬКО утверждением 4 — проба
  #     пришпилена к своей полосе, а не к «хоть чему-нибудь».
  mk zz-own-means-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
echo "FATAL: условие не создано, различаю исходы своими средствами" >&2
echo "  перепись: утверждений выполнено 0 из 1; рендеров helm: 0" >&2
exit 2
SYN

  # (L) ИНЪЕКЦИЯ УТВЕРЖДЕНИЯ 4 В ИСКЛЮЧЁННУЮ ПОПУЛЯЦИЮ — ради неё утверждение и
  #     распространено на весь каталог. Скрипт материализует зависимости САМ,
  #     поэтому обход его НЕ ГОНЯЕТ: утверждения 1–3 о нём не скажут ничего
  #     никогда. Пока утверждение 4 считало только осмотренных, исключение из
  #     прогона работало и как освобождение от контракта — и в нём сидели два
  #     живых экземпляра дефекта #1214.
  mk zz-builder-nodeclare-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
bash "$ROOT/scripts/helm-umbrella-deps.sh" "$ROOT/helm/umbrella"
echo "FATAL: условие не создано, различаю исходы своими средствами" >&2
exit 2
SYN

  # (D) ОБЪЯВИЛ КОНТРАКТ И НЕ ИСПОЛНИЛ: отдаёт код 1 там, где условие не создано.
  mk zz-contract-code1-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
. "$(dirname "$0")/outcome.sh"
EXPECTED_ASSERTIONS=1
fail "условие не создано, но названо находкой о дереве"
SYN

  # (E) ОБЪЯВИЛ КОНТРАКТ, РЕНДЕР ЗВАЛ, КОД ВЕРНЫЙ, А ТЕКСТА helm НЕТ. Без текста
  #     читатель получает голое «render failed» и идёт искать дефект в дереве.
  #     Рендер здесь звать ОБЯЗАТЕЛЬНО: до правки утверждения 2 хватало голого
  #     `fatal`, но такой синтетик неотличим от предпосылки, отказавшей раньше
  #     первого рендера, — то есть от ЗАКОННОГО поведения (случай I ниже).
  mk zz-contract-notext-test.sh <<'SYN'
#!/usr/bin/env bash
set -euo pipefail
. "$(dirname "$0")/outcome.sh"
EXPECTED_ASSERTIONS=1
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
helm_try x "$ROOT/helm/umbrella" -f "$ROOT/helm/umbrella/values.dev.yaml" \
  --show-only templates/namespace.yaml
