SYN

  # (I) ЗАКОННЫЙ БЛИЗНЕЦ (E): предпосылка отказала ДО первого рендера. Текста helm
  #     не существует, и требовать его значило бы толкать скрипт рендерить впустую
  #     ради строчки в выводе. Ровно эта форма и есть у сведённой четвёрки:
  #     чарт зависимости не материализован — судить не о чем, рендерить нечего.
  mk zz-precondition-test.sh <<'SYN'
