# ИМЯ ДЛЯ СВЕРКИ TLS: ОДНА ФОРМА НА ДЕРЕВО И СВЕРКА С СЕРТИФИКАТОМ ПИРА.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЭТО ЗА ВЕЛИЧИНА И ЧЕМ ОНА ОТЛИЧАЕТСЯ ОТ АДРЕСА
#
# `ServerName` клиента TLS НЕ РЕЗОЛВИТСЯ — он СРАВНИВАЕТСЯ: библиотека кладёт
# его в SNI и сверяет с SAN серверного листа, DNS-запроса по нему не делается ни
# одного. Поэтому правило формы адреса (`neighbour-address-form-test.sh`) к нему
# не применимо и намеренно его не судит: тот гейт про число обращений к DNS, а
# этот — про то, С КЕМ мы согласились разговаривать.
#
# ─────────────────────────────────────────────────────────────────────────────
# ТРИ УТВЕРЖДЕНИЯ, И КАЖДОЕ ЛОВИТ СВОЙ КЛАСС
#
#   А. ФОРМА ОДНА (#2179). Имя записано короткой служебной формой
#      `<служба>.<пространство>.svc`. Обе формы сегодня работают — сертификат
#      выписан на три имени каждого хоста, поэтому рукопожатие проходит при
#      любой, — и расхождение потому ТИХОЕ: оно не проявляется ничем и живёт до
#      дня, когда кто-нибудь сузит состав SAN. Тогда сломается ровно одно ребро
#      из двадцати трёх, а остальные продолжат работать, и причина будет
#      неочевидна. Предмет не в том, «какая форма правильнее», а в том, что
#      выбора никто не делал.
#
#   Б. ИМЯ ЛЕЖИТ В SAN (#2185). Значение обязано быть одним из `dnsNames`
#      сертификата, отрендеренного В ЭТОМ ЖЕ профиле. Ловит приписанный порт,
#      опечатку и выдуманную приставку — всё, что рукопожатие оборвёт, а
#      объявление выглядит настроенным.
#
#   В. ИМЯ СОВПАДАЕТ С АДРЕСОМ РЕБРА, ГДЕ АДРЕС ОБЪЯВЛЕН (#2185, несущая часть).
#      Имя, верное по форме и лежащее в SAN, всё ещё может указывать НЕ НА ТОГО,
#      к кому идёт ребро: mTLS тогда бессмысленен ровно там, где он и нужен —
#      рукопожатие пройдёт с тем, чьё имя подставлено, а не с тем, к кому шли.
#      Единственный НЕЦИКЛИЧЕСКИЙ источник «к кому идёт ребро» — адрес, который
#      клиент набирает, объявленный тем же контейнером под той же головой.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧЕГО ЭТОТ ГЕЙТ НЕ ЗАКРЫВАЕТ — НАЗВАНО ЧИСЛОМ, А НЕ УМОЛЧАНИЕМ
#
# Утверждение В проверяемо только там, где адрес ребра ОБЪЯВЛЕН рядом. У части
# рёбер адрес приезжает умолчанием процесса и в манифест не попадает вовсе —
# для них «тот ли это пир» из рендера невыводимо BY CONSTRUCTION, и выводить это
# из самого имени было бы кругом в рассуждении: имя сверялось бы само с собой.
#
# Поэтому перепись печатает ДВЕ величины отдельно — «сверено по адресу» и
# «адреса ребра рядом нет». Второе — не находка и не успех: это объём, до
# которого гейт не дотягивается, и он обязан быть виден, иначе «ноль находок»
# читается шире, чем есть.
#
# Пир, чей сертификат в ЭТОМ профиле не рендерится (служба выключена), тоже не
# находка: сверять не с чем. Требовать членства в SAN безусловно значило бы
# завести гейт, у которого находки ложные, — такой отключают первым.

set -uo pipefail

SCRIPT="$(basename "$0")"
DEPLOY_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
UMBRELLA="$DEPLOY_ROOT/helm/umbrella"

# shellcheck source=deploy/tests/helm/outcome.sh
. "$(dirname "$0")/outcome.sh"
# shellcheck source=deploy/tests/helm/premise.sh
. "$(dirname "$0")/premise.sh"
# shellcheck source=deploy/tests/helm/stacks.sh
. "$(dirname "$0")/stacks.sh"

require_helm
require_python_yaml

# ПРЕДПОСЫЛКА ОТДАЁТСЯ ЧЕРЕЗ `fatal`, А НЕ СВОИМ ВЫХОДОМ.
#
# `premise_chart_deps` выходит сам, минуя перепись, — и тогда «условие не
# создано» приходит БЕЗ строки объёма осмотренного. Общий контракт исходов
# каталога требует переписи при КАЖДОМ ненулевом исходе: без неё читатель не
# отличит «условие не создано» от «прочитано ноль», а гейт
# `three-outcomes-distinguishable-test.sh` справедливо считает это находкой —
# он и поймал первую редакцию этого файла.
if ! premise_out="$(premise_chart_deps "$SCRIPT" 2>&1)"; then
  fatal "$premise_out"
fi
[ -n "$premise_out" ] && printf '%s\n' "$premise_out"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# audit_render <файл-рендера> <имя-стека> — печатает строки разбора:
#   FINDING <текст>       — находка о дереве
#   SCOPE <n> <n> <n> <n> — осмотрено · сверено по SAN · сверено по адресу · без адреса
#
# Разбор живёт ОТДЕЛЬНЫМ файлом, а не встроен сюда, ровно затем, чтобы
# доказательство инъекцией кормило ТУ ЖЕ функцию синтетическим входом:
# доказанное на синтетике тогда верно для дерева. Он судит УЗЛЫ разобранных
# документов (перечень env контейнера, `Certificate.spec.dnsNames`), а не
# расположение символов в строке.
AUDIT="$(dirname "$0")/servername-peer-audit.py"
[ -r "$AUDIT" ] || fatal "разборщик $AUDIT не читается — предпосылка исчезла, а не дерево стало чистым"

audit_render() { python3 "$AUDIT" "$1" "$2"; }

TOT_SEEN=0; TOT_SAN=0; TOT_ADDR=0; TOT_NOADDR=0; TOT_CERTS=0

# КОД ПЕРЕЧНЯ СТЕКОВ ПОТРЕБОВАН ПРИСВАИВАНИЕМ, А НЕ СПИСКОМ `for`: подстановка в
# списке `for` теряет код ВСЕГДА, и отказ читателя таблицы обходил бы ноль стеков
# при нулевом коде. Пустой обход ловится ниже (`TOT_SEEN`), но НАЗЫВАЛСЯ бы он
# «имён для сверки не найдено» — то есть верным словом о неверной причине.
STACKS="$(stacks_names)" \
  || fatal "перечень стеков не прочитан — обходить нечего, и это не чистое дерево"
for stack in $STACKS; do
  args="$(stacks_args "$stack" "$UMBRELLA")" \
    || fatal "стек $stack: цепочка стенда не прочитана — helm без единого -f сел бы на умолчания чарта"
  # shellcheck disable=SC2086
  helm template kacho-umbrella "$UMBRELLA" $args \
      --namespace kacho >"$TMP/$stack.yaml" 2>"$TMP/$stack.err" \
    || fatal "рендер стека «$stack» не удался — судить нечего:
$(sed 's/^/       /' "$TMP/$stack.err")"
  RENDERS=$((RENDERS + 1))
  # Рендер удался и ПУСТ — это «условие не создано», а не чистое дерево.
  [ -s "$TMP/$stack.yaml" ] || fatal "рендер стека «$stack» пуст — судить нечего"

  out="$(audit_render "$TMP/$stack.yaml" "$stack")" \
    || fatal "разбор рендера «$stack» отказал — это НЕ находка о дереве"

  while IFS= read -r line; do
    case "$line" in
      FINDING\ *) violation "${line#FINDING }" ;;
      SCOPE\ *)
        read -r _ s sa ad na <<<"$line"
        TOT_SEEN=$((TOT_SEEN + s)); TOT_SAN=$((TOT_SAN + sa))
        TOT_ADDR=$((TOT_ADDR + ad)); TOT_NOADDR=$((TOT_NOADDR + na))
        # Каждый стек, отдавший разбор, — одно выполненное утверждение.
        ok
        ;;
    esac
  done <<<"$out"

  certs="$(grep -c '^kind: Certificate' "$TMP/$stack.yaml" || true)"
  TOT_CERTS=$((TOT_CERTS + certs))
  echo "  [$stack] имён для сверки: $s · сверено с SAN: $sa · сверено с адресом ребра: $ad · адреса ребра рядом нет: $na"
done

# ПУСТОЙ ОБХОД — ОТКАЗ, А НЕ ЧИСТОТА. Имён могло не остаться потому, что их
# перестали объявлять, а могло — потому что распознаватель перестал их узнавать.
[ "$TOT_SEEN" -gt 0 ] || fail "имён для сверки не найдено ни одного — «ноль находок» здесь означает «ноль прочитанного»"
[ "$TOT_CERTS" -gt 0 ] || fail "сертификатов в рендерах ноль — сверять имена не с чем, и вердикт беспредметен"

findings_verdict "имён для сверки $TOT_SEEN; сверено с SAN $TOT_SAN; сверено с адресом ребра $TOT_ADDR; адреса ребра рядом НЕТ $TOT_NOADDR (не находка и не успех — объём, до которого гейт не дотягивается); сертификатов $TOT_CERTS"
