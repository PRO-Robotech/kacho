# identity-session-secret-source-inject.sh — доказательство того, что проба
# `identity-session-secret-source-test.sh` СПОСОБНА упасть, молчит на законном
# дереве и НЕ ЗАСЧИТЫВАЕТ ЧУЖОЙ ОТКАЗ за свой. Без этого «зелено» неотличимо от
# «ничего не проверяет».
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРОГОНОВ ТРИ, И ТРЕТИЙ НЕ ФАКУЛЬТАТИВЕН
#
#   A  контроль            — дерево цело: проба зелена;
#   B  инъекция ПРОВЕРЯЕМОГО — страж снят: проба краснеет и называет предмет;
#   C  инъекция ЧУЖОГО ОТКАЗА — страж заменён на падающий по ПОСТОРОННЕЙ причине:
#      проба обязана покраснеть С ДРУГИМ текстом — «отказал НЕ из-за …».
#
# Без C утверждение «рендер обязан отказать» засчитывало бы ЛЮБОЙ отказ, включая
# «зависимости не собраны» и отказ соседнего подчарта, — то есть проходило бы
# вакуумно ровно там, где условия нет. Этот класс на этой пробе наблюдался
# вживую: первый прогон упал на защите хранилищ («You must provide your current
# passwords when upgrading»), и проба верно отказалась считать это своей находкой.
#
# Инъекции идут по временным КОПИЯМ чарта; дерево не трогается.

set -euo pipefail
cd "$(dirname "$0")/../.."

CHART="./helm/umbrella"
PROBE="tests/helm/identity-session-secret-source-test.sh"
GUARD="templates/identity-session-secret-guard.yaml"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

rc=0
# RED означает РОВНО код 1 — «находка о дереве». Код 2 («условие не создано»:
# зависимости умбреллы не собраны, нет helm) приходит на ЛЮБОЙ копии, включая
# законную, и засчитывать его за способность упасть значило бы доказывать ни о чём.
assert() { # имя · ожидание(RED|GREEN) · каталог чарта · ожидаемая подстрока вывода
  local name="$1" want="$2" dir="$3" want_text="${4-}" got code
  KACHO_UMBRELLA_DIR="$dir" bash "$PROBE" >"$TMP/out" 2>&1 && code=0 || code=$?
  case "$code" in
    0) got=GREEN ;;
    1) got=RED ;;
    *) got="УСЛОВИЕ-НЕ-СОЗДАНО(код=$code)" ;;
  esac
  if [ "$got" != "$want" ]; then
    echo "  ПРОВАЛ  $name → $got, ожидалось $want"
    sed -n '1,12p' "$TMP/out" | sed 's/^/          /'
    rc=1
    return 0
  fi
  if [ -n "$want_text" ] && ! grep -qF -- "$want_text" "$TMP/out"; then
    echo "  ПРОВАЛ  $name → $got, но текст не называет «$want_text»"
    sed -n '1,12p' "$TMP/out" | sed 's/^/          /'
    rc=1
    return 0
  fi
  echo "  ok   $name → $got"
}

# ── A. Контроль: копия дерева как есть ──────────────────────────────────────
cp -a "$CHART" "$TMP/intact"
assert "дерево цело" GREEN "$TMP/intact"

# ── B. Инъекция проверяемого: страж снят ────────────────────────────────────
cp -a "$CHART" "$TMP/no-guard"
rm -f "$TMP/no-guard/$GUARD"
assert "страж снят" RED "$TMP/no-guard" \
  "боевой профиль ОБНОВЛЯЕТСЯ без объявленного источника величин сессии"

# ── C. Инъекция ЧУЖОГО отказа: страж падает по посторонней причине ──────────
#
# Проба обязана НЕ засчитать это за свою находку: её отрицание сверяется с
# ПРИЧИНОЙ отказа, а не с фактом отказа.
cp -a "$CHART" "$TMP/foreign"
cat > "$TMP/foreign/$GUARD" <<'TPL'
{{- if .Release.IsUpgrade }}
{{- fail "посторонний отказ, к величинам сессии отношения не имеющий" }}
{{- end }}
TPL
assert "чужой отказ не засчитан" RED "$TMP/foreign" \
  "отказал НЕ из-за"

[ "$rc" -eq 0 ] && echo "OK: проба падает на возвращённом дефекте, молчит на законном дереве и не считает чужой отказ своим"
exit "$rc"
