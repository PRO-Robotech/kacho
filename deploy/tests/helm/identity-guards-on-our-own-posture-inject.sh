# identity-guards-on-our-own-posture-inject.sh — доказательство того, что проба
# `identity-guards-on-our-own-posture-test.sh` СПОСОБНА упасть на КАЖДОМ из двух
# стражей по отдельности, молчит на законном дереве и НЕ ЗАСЧИТЫВАЕТ ЧУЖОЙ ОТКАЗ
# за свой (задача #2732).
#
# ─────────────────────────────────────────────────────────────────────────────
# ОСЕЙ ЧЕТЫРЕ, И НИ ОДНА НЕ ФАКУЛЬТАТИВНА
#
#   A   контроль                — дерево цело: проба зелена;
#   B1  страж сессии снят       — проба краснеет и называет НАШУ ключницу;
#   B3  страж почты снят        — проба краснеет и называет отправителя;
#   C   чужой отказ             — страж заменён на падающий по ПОСТОРОННЕЙ
#       причине: проба обязана покраснеть С ДРУГИМ текстом — «отказал НЕ из-за …».
#
# Ось B2 (страж величины обратного вызова издателя поставщика) снята вместе со
# стражем и его предметом (#1276). Стражей ДВА, и снимать их по одному
# обязательно: «проба упала» при снятии обоих разом не отличило бы способную
# упасть пробу от пробы, у которой работает одно утверждение из семи.
#
# Без C утверждение «рендер обязан отказать» засчитывало бы ЛЮБОЙ отказ, включая
# «зависимости не собраны» и отказ соседнего подчарта, — то есть проходило бы
# вакуумно ровно там, где условия нет.
#
# Инъекции идут по временным КОПИЯМ чарта; дерево не трогается.

set -euo pipefail
# Каталог доказательства — АБСОЛЮТНЫЙ и снятый ДО смены рабочего: `$0`
# относителен вызывающему, поэтому после `cd` он указывает уже не туда, и
# подключение библиотеки по нему МОЛЧА не происходит.
INJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$INJECT_DIR/../.."

# shellcheck source=tests/helm/premise.sh
. "$INJECT_DIR/premise.sh" || { echo "ОТКАЗ: библиотека предпосылки не подключилась — молчаливый пропуск предпосылки хуже её отсутствия"; exit 1; }
premise_chart_deps

CHART="./helm/umbrella"
PROBE="tests/helm/identity-guards-on-our-own-posture-test.sh"
SESSION_GUARD="templates/identity-session-secret-guard.yaml"
MAIL_GUARD="templates/identity-mail-lane-guard.yaml"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

rc=0
# RED означает РОВНО код 1 — «находка о дереве». Код 2 («условие не создано»)
# приходит на ЛЮБОЙ копии, включая законную, и засчитывать его за способность
# упасть значило бы доказывать ни о чём.
assert() { # имя · ожидание(RED|GREEN) · каталог чарта · ожидаемая подстрока вывода
  local name="$1" want="$2" dir="$3" want_text="${4-}" got code
  KACHO_UMBRELLA_DIR="$dir" bash "$PROBE" >"$TMP/out" 2>&1 && code=0 || code=$?
  case "$code" in
    0) got=GREEN ;;
    1) got=RED ;;
    *) got="УСЛОВИЕ-НЕ-СОЗДАНО(код=$code)" ;;
  esac
  if [ "$got" != "$want" ]; then
    echo "  ПРОВАЛ  $name → $got, ожидалось $want"
    tail -n 12 "$TMP/out" | sed 's/^/          /'
    rc=1
    return 0
  fi
  if [ -n "$want_text" ] && ! grep -qF -- "$want_text" "$TMP/out"; then
    echo "  ПРОВАЛ  $name → $got, но текст не называет «$want_text»"
    tail -n 12 "$TMP/out" | sed 's/^/          /'
    rc=1
    return 0
  fi
  echo "  ok   $name → $got"
}

# ── A. Контроль: копия дерева как есть ──────────────────────────────────────
cp -a "$CHART" "$TMP/intact"
assert "дерево цело" GREEN "$TMP/intact"

# ── B1. Страж величин сессии снят ───────────────────────────────────────────
cp -a "$CHART" "$TMP/no-session"
rm -f "$TMP/no-session/$SESSION_GUARD"
assert "страж сессии снят" RED "$TMP/no-session" \
  "страж величин сессии ЗАМОЛЧАЛ вместе с чужим флагом"

# ── B3. Страж почтовой полосы снят ──────────────────────────────────────────
cp -a "$CHART" "$TMP/no-mail"
rm -f "$TMP/no-mail/$MAIL_GUARD"
assert "страж почтовой полосы снят" RED "$TMP/no-mail" \
  "страж почтовой полосы ЗАМОЛЧАЛ вместе с флагом подчарта"

# ── C. Инъекция ЧУЖОГО отказа ───────────────────────────────────────────────
#
# Страж почтовой полосы заменён на падающий РОВНО там, где проба ждёт его
# находки (узел полосы объявлен, отправителя нет), но по причине, к почтовой
# полосе отношения не имеющей. Проба обязана НЕ засчитать это за свою находку:
# её отрицание сверяется с ПРИЧИНОЙ отказа, а не с фактом отказа. Условие то же,
# что у настоящей ветви стража, поэтому на положительных контролях пробы (стенд
# own, стенд dev с полной полосой) посторонний отказ не срабатывает — иначе
# проба честно ответила бы «условие не создано» (код 2), и инъекция судила бы не
# то. Прежде хозяином этой оси был страж величины обратного вызова издателя
# поставщика; он снят вместе с предметом (#1276).
cp -a "$CHART" "$TMP/foreign"
cat > "$TMP/foreign/$MAIL_GUARD" <<'TPL'
{{- $smtp := ((((.Values.global).kacho).identity).smtp) | default dict }}
{{- if and (ne (trim (toString ($smtp.connectionURI | default ""))) "") (eq (trim (toString ($smtp.fromAddress | default ""))) "") }}
{{- fail "посторонний отказ, к почтовой полосе отношения не имеющий" }}
{{- end }}
TPL
assert "чужой отказ не засчитан" RED "$TMP/foreign" \
  "отказал НЕ из-за"

[ "$rc" -eq 0 ] && echo "OK: проба падает на снятии КАЖДОГО из двух стражей, молчит на законном дереве и не считает чужой отказ своим"
exit "$rc"
