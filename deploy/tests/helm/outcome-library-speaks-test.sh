# outcome-library-speaks-test.sh — ДЕРЖАТЕЛЬ НА САМУ БИБЛИОТЕКУ ИСХОДОВ:
# ненулевой код обязан приходить С НЕПУСТЫМ ВЫВОДОМ, и это верно для КАЖДОЙ
# ветки предпосылок, а не для тех, куда случайно зашёл соседний гейт.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ЭТОГО НЕ ДЕЛАЛ НИКТО
#
# Норму «ненулевой код при нуле байт вывода неотличим от находки о дереве»
# (#1195) держит `three-outcomes-distinguishable-test.sh`. Но держит он её
# СНАРУЖИ: гоняет каждый скрипт каталога на зеркале без собранных зависимостей и
# смотрит, что тот сказал. До функции `require_fresh_dep_charts` такой прогон
# НЕ ДОХОДИТ — раньше срабатывает другая предпосылка (нет `charts/`, нет
# конкретного подчарта), и её вывод засчитывается за вывод скрипта.
#
# Следствие измерено 2026-09-22 на четырёх синтетических входах: ТРИ ветки этой
# функции под `set -euo pipefail` убивали потребителя МОЛЧА — подстановка команды
# отдаёт ненулевой статус, `pipefail` поднимает его до статуса присваивания,
# `2>/dev/null` съедает объяснение. Одна из трёх выходила КОДОМ 1, а код 1 по
# контракту этой же библиотеки означает НАХОДКУ О ДЕРЕВЕ: молчаливый сбой
# выглядел красным вердиктом о дереве, которого никто не смотрел.
#
# Поэтому держатель здесь, а не снаружи: он зовёт функцию НАПРЯМУЮ, на входах,
# которые каждую ветку и открывают.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ
#
#   • законный вход (архив свежее исходников) — код 0;
#   • каждая ветка отказа — НЕНУЛЕВОЙ код И НЕПУСТОЙ вывод, называющий каталог;
#   • «не знаю» не выдаётся за «нет»: каталог, который не удалось осмотреть,
#     попадает в перечень, а не молча считается свежим.
#
# Инструментов не требует: ни helm, ни кластера, ни собранных зависимостей —
# входы синтетические, поэтому на зеркале без зависимостей скрипт зелен, и это
# законно (ему нечего у них спрашивать).
set -euo pipefail

# Имя читает `outcome.sh` (`: "${SCRIPT:=…}"`) при печати вердикта и переписи,
# поэтому оно присваивается ДО подключения. Для shellcheck это выглядит
# неиспользуемым — он не видит чтения через подстановку по умолчанию.
# shellcheck disable=SC2034
SCRIPT="$(basename "$0")"
# Каталог снимается АБСОЛЮТНЫМ до любого `cd`.
HERE="$(cd "$(dirname "$0")" && pwd)"

# shellcheck source=deploy/tests/helm/outcome.sh
. "$HERE/outcome.sh"

WORK="$(mktemp -d)"
# Права возвращаются ДО удаления: каталог с `chmod 000` иначе не снимается, и
# уборка оставила бы за собой мусор, который следующий прогон примет за вход.
cleanup() { chmod -R u+rwX "$WORK" 2>/dev/null || true; rm -rf "$WORK"; }
trap cleanup EXIT

# fixture <имя> — умбрелла с одной локальной зависимостью `dep`.
fixture() {
  local d="$WORK/$1"
  mkdir -p "$d/umbrella/charts" "$d/dep"
  printf 'dependencies:\n  - name: dep\n    repository: file://../dep\n' >"$d/umbrella/Chart.yaml"
  printf 'name: dep\nversion: 1.0.0\n' >"$d/dep/Chart.yaml"
  printf '%s\n' "$d"
}

# probe <метка> <каталог умбреллы> <ожидание: green|refusal> [подстрока]
#
# Функция зовётся В ПОДОБОЛОЧКЕ с `set -euo pipefail` — ровно в том режиме, в
# котором её убивало молча. Иначе держатель мерил бы не тот режим.
probe() {
  local label="$1" umbrella="$2" want="$3" want_txt="${4-}" out rc
  out="$(bash -c "set -euo pipefail; . '$HERE/outcome.sh'; require_fresh_dep_charts '$umbrella'; echo ДОШЛИ-ДО-КОНЦА" 2>&1)" && rc=0 || rc=$?
  if [ "$want" = green ]; then
    [ "$rc" -eq 0 ] || { violation "$label: ожидался код 0, получен $rc (вывод: ${out:-пусто})"; return; }
    case "$out" in *ДОШЛИ-ДО-КОНЦА*) ok ;; *) violation "$label: код 0, но функция не дошла до конца" ;; esac
    return
  fi
  if [ "$rc" -eq 0 ]; then
    violation "$label: отказа не случилось (код 0) — ветка не открылась, и утверждение прошло бы вакуумно"
    return
  fi
  if [ -z "$out" ]; then
    violation "$label: код $rc при НУЛЕ БАЙТ вывода — это и есть класс #1195: молчаливый сбой неотличим от вердикта"
    return
  fi
  if [ -n "$want_txt" ]; then
    case "$out" in
      *"$want_txt"*) ;;
      *) violation "$label: код $rc, вывод есть, но причина не названа ('$want_txt' нет): $(printf '%s' "$out" | head -1)"; return ;;
    esac
  fi
  ok
}

# ── 1. ЗАКОННЫЙ ВХОД — без него всякий отказ ниже проходил бы вакуумно ──────
A="$(fixture healthy)"
: >"$A/umbrella/charts/dep-1.0.0.tgz"
probe "законный вход: архив не старше исходника" "$A/umbrella" green

# ── 2. АРХИВА НЕТ ───────────────────────────────────────────────────────────
B="$(fixture no-archive)"
probe "архива подчарта нет" "$B/umbrella" refusal "архива нет"

# ── 3. ИСХОДНИК НОВЕЕ АРХИВА ────────────────────────────────────────────────
C="$(fixture stale-archive)"
: >"$C/umbrella/charts/dep-1.0.0.tgz"
touch -d '2001-01-01' "$C/umbrella/charts/dep-1.0.0.tgz"
probe "исходник новее архива" "$C/umbrella" refusal "dep"

# ── 4. ИМЯ ЧАРТА НЕ ПРОЧИТАЛОСЬ — «не знаю», а не «свежо» ───────────────────
D="$(fixture unreadable-chart)"
: >"$D/umbrella/charts/dep-1.0.0.tgz"
chmod 000 "$D/dep/Chart.yaml"
probe "Chart.yaml зависимости нечитаем" "$D/umbrella" refusal "имя чарта не прочиталось"
chmod 644 "$D/dep/Chart.yaml"

# ── 5. ОБХОД КАТАЛОГА НЕ УДАЛСЯ — тоже «не знаю» ────────────────────────────
E="$(fixture unreadable-subdir)"
mkdir -p "$E/dep/sub"
: >"$E/umbrella/charts/dep-1.0.0.tgz"
chmod 000 "$E/dep/sub"
probe "обход каталога зависимости не удался" "$E/umbrella" refusal "осмотр каталога не удался"
chmod 755 "$E/dep/sub"

# ── 6. НЕТ Chart.yaml УМБРЕЛЛЫ — состав зависимостей читать неоткуда ────────
F="$WORK/no-umbrella-chart"; mkdir -p "$F/umbrella/charts"
probe "у умбреллы нет Chart.yaml" "$F/umbrella" refusal "состав зависимостей"

findings_verdict "веток предпосылки проверено 6 (1 законная, 5 отказных); инструментов не требуется"
