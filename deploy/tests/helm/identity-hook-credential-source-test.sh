#!/usr/bin/env bash
#
# identity-hook-credential-source-test.sh — величина, которую ОБЪЯВЛЯЕТ
# конфигурация личности, обязана иметь ИСТОЧНИК В ПОДЕ.
#
# ЗАЧЕМ. Конфигурация службы личности объявляет учётные данные обратных вызовов
# ссылкой вида `${ИМЯ}`. Сама служба подстановки в ЗНАЧЕНИЯХ конфигурации не
# делает — она переопределяет ключи переменными по пути ключа, а элемент массива
# хуков таким путём невыразим. Пока подстановки не было, строка уезжала в
# заголовок ДОСЛОВНО: служба прав отвечала 401, провайдер — 502, вход паролем не
# проходил, посев церемонии не вставал, девять коллекций оставались без отчёта
# (прогон 32532668160, задача #948).
#
# Класс шире одной величины: ССЫЛКА БЕЗ ИСТОЧНИКА выглядит настроенной и не
# работает, а отказ приходит на третьей стороне и читается как чужой.
#
# ЧТО УТВЕРЖДАЕТСЯ, по каждому профилю с включённой службой личности:
#   (1) перепись: сколько ссылок `${ИМЯ}` объявляет конфигурация;
#   (2) у каждой есть источник — контейнер подстановки объявляет переменную с
#       тем же именем;
#   (3) процесс читает ОТРЕНДЕРЕННОЕ, а не шаблон: путь `--config` совпадает с
#       путём тома, в который пишет контейнер подстановки;
#   (4) отказ закрытый: подстановка проверяет и пустую величину, и остаточную
#       ссылку;
#   (5) ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: том отрендеренного смонтирован главному
#       контейнеру, иначе (3) зеленело бы на пути, которого нет.
#
# ГРАНИЦА. Проба читает ОБЪЯВЛЕНИЕ (рендер чарта), а не поднятый стенд: она
# отвечает на вопрос «объявлено ли», и только на него. Что величина ВЕРНА,
# доказывает сквозной прогон.
#
# Пустой перечень ссылок — законный исход: проба говорит об этом и проходит.
# Идеал не превращается в поломку.

set -euo pipefail
cd "$(dirname "$0")/../.."

CHART=./helm/umbrella
# Перечень профилей можно сузить извне — этим пользуется проба способности
# упасть (`identity-hook-credential-source-inject.sh`), подавая синтетический
# профиль с возвращённым дефектом. Умолчание — оба настоящих профиля.
read -r -a PROFILES <<< "${IDENTITY_SOURCE_PROFILES:-values.dev.yaml values.prod.yaml}"
rc=0
seen_profiles=0
seen_refs=0

for prof in "${PROFILES[@]}"; do
  [ -f "$CHART/$prof" ] || { echo "ПРОПУСК: нет $prof"; continue; }
  seen_profiles=$((seen_profiles + 1))

  out="$(helm template kacho-umbrella "$CHART" -f "$CHART/$prof" 2>/dev/null)" || {
    echo "ОТКАЗ [$prof]: рендер не удался — вердикта о посадке нет"; rc=1; continue
  }

  verdict="$(printf '%s' "$out" | python3 tests/helm/identity-hook-credential-source.py "$prof")" || { echo "ОТКАЗ [$prof]: разбор рендера не удался"; rc=1; continue; }

  while IFS='|' read -r kind msg n; do
    case "$kind" in
      ССЫЛКИ)  seen_refs=$((seen_refs + ${n:-0}))
               echo "  [$prof] ссылок в конфигурации: ${n:-0}${msg:+ — $msg}" ;;
      ПРОПУСК) echo "  [$prof] $msg" ;;
      ПУТЬ)    echo "  [$prof] $msg" ;;
      ОТКАЗ)   echo "ОТКАЗ [$prof]: $msg"; rc=1 ;;
    esac
  done <<< "$verdict"
done

echo "осмотрено: профилей $seen_profiles, ссылок $seen_refs"
if [ "$seen_profiles" -eq 0 ]; then
  echo "ОТКАЗ: ни один профиль не осмотрен — «ноль находок» здесь означало бы «ноль прочитанного»"
  exit 1
fi
[ "$rc" -eq 0 ] && echo "OK: каждая объявленная ссылка имеет источник в поде"
exit "$rc"
