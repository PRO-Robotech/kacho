"""Гейт: каждое исключение IaC-скана обязано иметь ПРЕДМЕТ.

ПРЕДМЕТ ГЕЙТА. `.trivyignore.yaml` перечисляет пути, находки по которым известны и
приняты. Такой перечень опасен не тем, что он есть, а тем, что он переживает свои
находки: файл вычистили, а строка осталась — и с этого момента она не защищает
ничего, зато предъявляет закрытый долг за открытый. Ровно это уже происходило в
дереве: сайт документации iam перевели на непривилегированный образ, а исключение
продолжало накрывать его по всем трём правилам, потому что было задано шаблоном.
Шаблоны тогда заменили пофайловым перечислением — но проверять перечень по-прежнему
было некому, и сам файл честно предупреждает: «сайт вычистили — строка лишняя».
Предупреждение без исполнителя — это форма без содержания, поэтому здесь исполнитель.

ПРЕДИКАТ — С РАЗЛИЧЕНИЕМ ДВУХ РАЗНЫХ «НЕТ НАХОДКИ». Скан прогоняется БЕЗ ignorefile.
Из него берутся ДВА множества, и смешивать их нельзя: реальные FAIL (правило, путь) и
ЦЕЛИ, до которых сканер вообще дошёл. Для записи исключения возможны три исхода:

  * под её образец попадает FAIL — предмет есть, запись работает;
  * FAIL нет, но путь БЫЛ ОСМОТРЕН — предмет исчез, запись устарела: находка;
  * путь НЕ ОСМОТРЕН вовсе — запись НЕ СУДИМА, и объявлять её устаревшей запрещено.

Третий исход — не педантизм, а урок, оплаченный дважды. Первая редакция этого гейта его
не различала и предъявила устаревшей строку, рядом с которой в самом файле исключений
стояло предупреждение: находки нет не потому, что путь вычищен, а потому, что чарт этого
сервиса не входит в цели сканера — он разбирает сайты документации поимённо, а этот чарт
не разбирает вовсе. Отсутствие находки там свидетельствует об отсутствии ОСМОТРА, а не об
отсутствии дефекта. Снятие строки по такому основанию сняло бы защиту, ничего не проверив,
и следующая версия сканера, научившаяся читать этот чарт, встретила бы дерево без записи.
Гейт, который не отличает «чисто» от «не смотрели», — сам экземпляр той формы без
содержания, которую он призван ловить.

Тот третий исход закрыт по существу 2026-08-09: причиной был намеренный отказ рендера у
чартов, требующих секрет оператора, и он снят заглушками ТОЛЬКО ДЛЯ СКАНА в корневом
`trivy.yaml`. Поэтому здесь тот же `--config`: гейт обязан судить РОВНО о том множестве
целей, которое видит гейт скана в CI. Разойдись они — «путь вне осмотра» у одного
означало бы «путь чист» у другого, и оба были бы уверены в своей правоте.

ПРОВЕРКА СВОЕЙ ПРЕДПОСЫЛКИ. Гейт опирается на факты о мире и меряет их, а не
предполагает:

  (1) файл настроек скана существует — от него зависит, какая часть дерева
      осматривается вообще; его исчезновение молча сужает осмотр;
  (2) скан ДОШЁЛ ДО ЦЕЛЕЙ. Мерилом служит число целей, а НЕ число находок: на
      вычищенном дереве находок законно ноль, и прежняя редакция на нём отказывала,
      объявляя чистоту отказом инструмента. Ноль целей — по-прежнему отказ;
  (3) нормализация идентификаторов правил действительно склеивает формы, в которых
      их пишут разные сборки сканера (`AVD-DS-0002` локально против `DS-0002` на
      раннере). Это проверяется самопробой ниже, а не верой: разойдись формы,
      совпадений не нашлось бы НИКОГДА и гейт объявил бы устаревшими все записи
      разом, то есть потребовал бы снять всю защиту.

ПУСТОЙ ПЕРЕЧЕНЬ — ЗАКОННЫЙ ИСХОД, А НЕ ОТКАЗ. Прежняя редакция отказывала, когда в
файле не прочитано ни одной записи, и это было верно ровно до того дня, когда перечень
довели до нуля фиксами: с этого момента гейт ронял бы CI за отсутствие долга. Проверять
надо не «есть ли записи», а «читается ли файл»: непрочитанный файл и пустой перечень
различаются, и различает их census ниже.

ОБЪЁМ ОСМОТРЕННОГО ПЕЧАТАЕТСЯ. «Ноль устаревших записей» обязано быть отличимо от «ноль
прочитанных записей» и от «ноль полученных находок».

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Он не судит, обоснованно ли исключение по существу — это вопрос
тикета, на который ссылается сам файл. И он не отвечает за полноту осмотра: за неё
отвечает `assert-iac-scan-covers-every-chart.py`, который держит предпосылку (1)
пофайлово по чартам.
"""
import fnmatch
import json
import os
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
IGNORE = ROOT / ".trivyignore.yaml"
SCAN_CONFIG = ROOT / "trivy.yaml"


def norm(rule_id):
    """Каноничный вид идентификатора правила — устойчивый к форме записи.

    Форма НЕ стабильна между сборками сканера, и это измерено, а не предположено: за
    один и тот же прогон по тому же правилу локальный отчёт даёт `AVD-DS-0002`, а
    отчёт на раннере — `DS-0002`. Сравнение сырых строк не находило бы совпадений
    НИКОГДА, и гейт объявил бы устаревшими все записи разом — то есть потребовал бы
    снять всю защиту. Ровно это и случилось на первом прогоне в CI.

    Нормализация снимает необязательный префикс `AVD-` и разделители: `AVD-DS-0002`,
    `DS-0002` и `DS002` — один идентификатор, записанный тремя способами.
    """
    s = (rule_id or "").upper().replace("_", "-")
    if s.startswith("AVD-"):
        s = s[4:]
    return s.replace("-", "")


def check_norm_selftest():
    """Самопроба нормализации — предпосылка (3).

    Проверяется ИСХОД (три известные формы склеиваются в одну), а не форма записи:
    требование конкретного префикса само однажды оказалось ложной предпосылкой,
    потому что префикс зависит от сборки сканера.
    """
    forms = ["AVD-DS-0002", "DS-0002", "ds_0002", "DS0002"]
    got = {norm(f) for f in forms}
    if got != {"DS0002"}:
        print("ОТКАЗ: нормализация идентификаторов правил перестала склеивать формы,\n"
              "       в которых их пишут разные сборки сканера: %s → %s.\n"
              "       С такой нормализацией сравнение не нашло бы совпадений и гейт\n"
              "       потребовал бы снять все исключения разом."
              % (forms, sorted(got)), file=sys.stderr)
        return False
    return True


def load_exclusions():
    """→ ([(rule_id, path_glob, lineno)], [непрочитанные строки], прочитан ли файл).

    Разбор построчный, а не через YAML-парсер: файл несёт значимые комментарии, а
    зависимость на pyyaml в этом окружении не гарантирована. Форма стабильна и задана
    самим файлом — `- id:` открывает правило, `- "<путь>"` под `paths:` перечисляет
    образцы. Любое отступление от формы обязано быть замечено, поэтому строка, которую
    разбор не понял внутри блока `paths:`, идёт в отчёт как непрочитанная.
    """
    rules, unread = [], []
    rule = None
    in_paths = False
    lines = IGNORE.read_text(encoding="utf-8").splitlines()
    for i, raw in enumerate(lines, 1):
        line = raw.split("#", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        s = line.strip()
        if s.startswith("- id:"):
            rule = s.split(":", 1)[1].strip().strip('"\'')
            in_paths = False
            continue
        if s == "paths:":
            in_paths = True
            continue
        if s.startswith("statement:") or s.endswith(":") and not in_paths:
            in_paths = False
            continue
        if in_paths:
            if s.startswith("- "):
                rules.append((rule, s[2:].strip().strip('"\''), i))
            else:
                in_paths = False
                if not s.startswith("statement:"):
                    unread.append((i, s[:60]))
    return rules, unread, len(lines)


def scan():
    """→ (множество (AVDID, target) реальных FAIL, множество осмотренных целей).

    Второе множество возвращается наравне с первым, потому что «нет находки» без него
    неоднозначно: путь мог быть осмотрен и оказаться чистым, а мог не попасть в цели
    сканера вовсе. Судить запись можно только в первом случае.
    """
    if not shutil.which("trivy"):
        print("ОТКАЗ: trivy не найден в PATH — судить не о чем", file=sys.stderr)
        sys.exit(2)
    env = dict(os.environ)
    env.pop("TRIVY_IGNOREFILE", None)
    cmd = [
        "trivy", "config", ".", "--config", SCAN_CONFIG.name,
        "--severity", "CRITICAL,HIGH", "--format", "json",
        "--skip-dirs", ".claude", "--skip-dirs", "**/node_modules", "--quiet",
    ]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env=env, timeout=900)
    if r.returncode not in (0, 1):
        print("ОТКАЗ: trivy вышел с кодом %d\n%s" % (r.returncode, r.stderr[:400]), file=sys.stderr)
        sys.exit(2)
    doc = json.loads(r.stdout or "{}")
    fails, targets = set(), set()
    for res in doc.get("Results") or []:
        target = res.get("Target") or ""
        targets.add(target)
        for m in res.get("Misconfigurations") or []:
            if m.get("Status") == "FAIL":
                fails.add((m.get("AVDID") or m.get("ID") or "", target))
    return fails, targets


def main():
    if not IGNORE.exists():
        print("ОТКАЗ: %s не найден — судить не о чем" % IGNORE.name, file=sys.stderr)
        return 2

    # ПРЕДПОСЫЛКА 1: файл настроек скана на месте. Именно он вводит в осмотр чарты,
    # которые намеренно отказывают в рендере без секрета оператора; без него часть
    # дерева уходит из осмотра МОЛЧА, и вердикт «путь вне осмотра» ниже сменил бы
    # смысл, не сменив формулировки.
    if not SCAN_CONFIG.exists():
        print("ОТКАЗ: %s не найден. Он вводит в осмотр чарты, которые без учётных\n"
              "       данных не рендерятся, и без него часть дерева выпадает из скана\n"
              "       молча — а вердикты этого гейта опираются на то, что осмотрено."
              % SCAN_CONFIG.name, file=sys.stderr)
        return 2

    # ПРЕДПОСЫЛКА 3 (проверяется до скана — она про сам гейт, а не про дерево).
    if not check_norm_selftest():
        return 2

    rules, unread, filelines = load_exclusions()
    fails, targets = scan()

    # ПРЕДПОСЫЛКА 2: скан дошёл до целей. Мерило — ЦЕЛИ, а не находки: на вычищенном
    # дереве находок законно ноль, и прежняя редакция на нём отказывала, выдавая
    # чистоту за отказ инструмента.
    if not targets:
        print("ОТКАЗ: скан не дошёл НИ ДО ОДНОЙ цели. Это не «всё вычищено», а\n"
              "       «сканер не отработал»: судить об исключениях не о чем.",
              file=sys.stderr)
        return 2

    scanned_ids = {norm(rid) for rid, _ in fails}
    declared_ids = {norm(rid) for rid, _, _ in rules}

    stale, unscanned = [], []
    for rid, glob, lineno in rules:
        if any(norm(r) == norm(rid) and fnmatch.fnmatch(t, glob) for r, t in fails):
            continue
        # Находки нет. Осмотрен ли путь вообще? Только если да, запись судима.
        if any(fnmatch.fnmatch(t, glob) for t in targets):
            stale.append((rid, glob, lineno))
        else:
            unscanned.append((rid, glob, lineno))

    print("iac-exclusions: строк файла прочитано %d; записей исключений %d (правил %d); "
          "целей осмотрено %d; находок скана %d; устаревших записей %d; вне осмотра %d"
          % (filelines, len(rules), len(declared_ids), len(targets), len(fails),
             len(stale), len(unscanned)))
    if not rules:
        # Законный исход, а не отказ: перечень доведён до нуля фиксами. Механизм
        # остаётся ради СЛЕДУЮЩЕЙ записи и сработает на ней в тот же прогон.
        print("  исключений в файле нет — судить нечего; механизм ждёт следующей записи")
    if unscanned:
        print("  НЕ СУДИМЫ — путь вне целей сканера, «нет находки» здесь означает\n"
              "  отсутствие осмотра, а не отсутствие дефекта:")
        for rid, glob, lineno in unscanned:
            print("    %s:%d: %s «%s»" % (IGNORE.name, lineno, rid, glob))
    if unread:
        print("  строк внутри перечня путей, которых разбор НЕ понял: %d" % len(unread))
        for lineno, frag in unread:
            print("    %s:%d: %s" % (IGNORE.name, lineno, frag))

    # Расхождение словарей проверяется ПОСЛЕ подсчёта и только когда сравнивать было
    # что: находки есть, записи есть, а общего элемента нет. У этого состояния два
    # прочтения — либо все записи действительно устарели, либо формы записи
    # идентификаторов разошлись, — и различить их отсюда нельзя. Отказ выбран
    # намеренно: цена ошибочного отказа — прочитать сообщение и снять запись руками,
    # цена ошибочного согласия — снять всю защиту разом.
    if fails and rules and not (scanned_ids & declared_ids):
        print("ОТКАЗ: у находок скана и у записей исключений НЕТ ни одного общего\n"
              "       правила даже после нормализации.\n"
              "       В отчёте: %s\n"
              "       В исключениях: %s\n"
              "       Либо все записи устарели разом, либо формы идентификаторов\n"
              "       разошлись между сборками сканера. Отсюда эти два случая\n"
              "       неразличимы, поэтому вердикт не выносится."
              % (", ".join(sorted(scanned_ids)) or "ничего",
                 ", ".join(sorted(declared_ids)) or "ничего"),
              file=sys.stderr)
        return 2

    orphan_ids = declared_ids - scanned_ids
    if orphan_ids:
        print("  правил объявлено, но ни одной находки по ним нет: %s"
              % ", ".join(sorted(orphan_ids)))

    for rid, glob, lineno in stale:
        print("  %s:%d: %s «%s» — предмета больше нет" % (IGNORE.name, lineno, rid, glob))

    if stale or unread:
        print("\nИсключение живёт, пока у него есть предмет. Перечисленному выше исключать\n"
              "уже нечего: путь вычищен или исчез. Удалите запись — и закройте связанный\n"
              "долг, если он закрыт по существу. Оставленная запись предъявляет закрытый\n"
              "долг за открытый и прячет следующую находку по тому же пути.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
