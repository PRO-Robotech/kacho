# ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ материализации зависимостей умбреллы.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ОДИН
#
# `helm dep update` по этому чарту — операция СЕТЕВАЯ и полная: она заново
# скачивает КАЖДУЮ объявленную зависимость, ничего не переиспользуя. Замер на
# этом дереве: 22 объявления, полный проход 3 мин 22 с, mtime всех
# `charts/*.tgz` обновляется на повторном вызове тоже.
#
# Пока каждый, кому нужен отрендеренный чарт, звал её сам, один прогон job'а
# «helm lint · template» доходил до десяти проходов: отдельный шаг конвейера,
# предусловие прогонщика самопроверок, две самопроверки, цель манифест-проверок
# и те же две проверки в обычном режиме. Платили не только временем: каждый
# проход — независимая возможность отказа у постороннего хоста, а отказ ЛЮБОГО
# красит весь прогон. Два прогона подряд на релизной ветке так и упали — на
# подкачке одной и той же зависимости, в двух разных местах.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЗДЕСЬ СДЕЛАНО И ЧЕГО НЕ СДЕЛАНО
#
# 1. ПОВТОРНЫЙ ВЫЗОВ НЕ ХОДИТ В СЕТЬ — но только когда доказано, что ходить не
#    за чем. Условий два, и оба обязательны:
#      · helm сам сообщает, что КАЖДАЯ объявленная зависимость на месте и нужной
#        версии (`helm dependency list`, статус `ok`) — это офлайновый вопрос;
#      · отпечаток исходников совпал с записанным на прошлой материализации.
#    Отпечаток берётся с Chart.yaml И с ФАЙЛОВ каждого локального сабчарта
#    (`file://…`). Это не осторожность впрок: локальные сабчарты вендорятся
#    ИЗ ИСХОДНИКОВ, и пропуск на изменившемся исходнике означал бы рендер
#    вендоренной копии — ровно тот класс «правка есть в файле, а в стенд не
#    попала», который проверки этого каталога и ловят.
#
# 2. ПРИЧИНА ОТКАЗА НЕ ГЛОТАЕТСЯ. Вывод helm печатается ЦЕЛИКОМ. Прежде вызов
#    стоял как `helm dep update >/dev/null 2>&1`, и на конвейере оставалась
#    строка «FAIL: helm dep update» без единого слова о том, что не скачалось;
#    имя недоступного адреса приходилось искать в ЧУЖОМ прогоне.
#
# 3. ПОВТОР ПОПЫТКИ — ограниченный И КЛАССИФИЦИРУЮЩИЙ. Отказ постороннего хоста
#    не является находкой о дереве, и превращать его в красный вердикт значит
#    утверждать о дереве то, чего не измеряли. Повтор ограничен и на исчерпании
#    ОТКАЗЫВАЕТ: «не выполнилось» не идёт в зачёт «прошло».
#
#    Постоянный отказ (архива по адресу нет, версия снята) от временного
#    отличается и повтором НЕ лечится — на нём цикл прерывается сразу, чтобы не
#    прятать причину за таймаутом. Эта половина пришла из отдельной обёртки
#    повтора, которая жила рядом и была ВТОРЫМ владельцем того же предмета:
#    Makefile звал её, остальные звали helm напрямую. Обёртка снята, её довод
#    сохранён здесь.
#
# 4. ЧЕЙ ЭТО ОТКАЗ — НАШ ИЛИ ЧУЖОГО ХОСТА — НАЗЫВАЕТСЯ КОДОМ ВОЗВРАТА, а не
#    только прозой. Материализация — ПРЕДПОСЫЛКА, и её срыв по чужой причине не
#    является вердиктом о дереве: по `e2e-flow.md` §6 это «условие не создано»,
#    третий исход, который не зачитывается ни в зелёное, ни в красное. Пока оба
#    отказа выходили единицей, вызывающий не мог их различить, и недоступность
#    постороннего хоста приезжала в сводку как красный шард — то есть как дефект
#    продукта (kacho#655).
#
# ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ: он не судит о содержимом чартов и ничего не
# рендерит. Материализация — предпосылка проверок, а не проверка.
#
# Использование:
#   bash deploy/scripts/helm-umbrella-deps.sh [путь-к-умбрелле]
#   KACHO_HELM_DEPS_REFRESH=1 …   — обойти пропуск (подтянуть свежие версии
#                                   вышестоящих чартов из плавающих диапазонов)
#   KACHO_HELM_DEPS_ATTEMPTS=N …  — число попыток (по умолчанию 3)
#
# Коды возврата:
#   0 — зависимости материализованы (или уже были на месте);
#   1 — ОТКАЗ НАШ: объявление, пин или локальный сабчарт. Это находка о дереве;
#   2 — предпосылки самого скрипта не выполнены (нет helm, не чарт);
#   3 — УСЛОВИЕ НЕ СОЗДАНО: удалённый источник чартов не ответил. Это НЕ находка
#       о дереве и не вердикт о продукте.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SELFTEST=0
CHECKONLY=0
if [ "${1:-}" = "--self-test" ]; then SELFTEST=1; shift; fi
# --check — ВОПРОС БЕЗ ДЕЙСТВИЯ: «материализация актуальна?». Отвечает офлайн,
# в сеть не ходит, дерева не касается. Заведён затем, чтобы у вопроса был ОДИН
# владелец: доказательства инъекцией спрашивают его перед первым рендером, и
# спрашивают ТЕМ ЖЕ решением (`skip_is_allowed`), каким этот скрипт решает, идти
# ли в сеть. Копия предиката у каждого из семи разошлась бы молча — тем же
# доводом, каким состав стендов читает один stacks.sh.
if [ "${1:-}" = "--check" ]; then CHECKONLY=1; shift; fi
UMBRELLA_IN="${1:-$SCRIPT_DIR/../helm/umbrella}"
UMBRELLA="$(cd "$UMBRELLA_IN" 2>/dev/null && pwd)" || {
  echo "FATAL: каталога умбреллы нет: $UMBRELLA_IN"; exit 2; }
[ -f "$UMBRELLA/Chart.yaml" ] || { echo "FATAL: не чарт: $UMBRELLA (нет Chart.yaml)"; exit 2; }
command -v helm >/dev/null 2>&1 || { echo "FATAL: нужен helm"; exit 2; }

MARKER="$UMBRELLA/.kacho-deps-fingerprint"
ATTEMPTS="${KACHO_HELM_DEPS_ATTEMPTS:-3}"

# Отметка «условие не создано» — то, чем срыв по ЧУЖОЙ причине доезжает до
# вызывающего через `make`. Код возврата через make не проходит: make отвечает
# своей двойкой на любой упавший рецепт, и код 3 из этого скрипта до шага
# конвейера не долетает by construction. Поэтому отметка — файлом.
#
# СНИМАЕТСЯ В НАЧАЛЕ КАЖДОГО ПРОГОНА, включая тот, что уходит по пропуску.
# Иначе отметка пережила бы свой прогон и объявляла «условие не создано» на
# здоровом стенде — послабление, которое не истекает само, то есть ровно тот
# класс, который правила запрещают.
PRECOND_MARK="$UMBRELLA/.kacho-deps-precondition-unmet"
# В режиме вопроса отметка НЕ снимается: `--check` обязан быть читающим целиком.
# Его зовут семь доказательств подряд, и запись в дерево из вопроса портила бы
# состояние, которое читают соседние проверки.
[ "$CHECKONLY" = "1" ] || rm -f "$PRECOND_MARK"

# ─────────────────────────────────────────────────────────────────────────────
# ЧЕЙ ОТКАЗ — РЕШАЕТСЯ ПО СТРОКЕ, КОТОРУЮ ПЕЧАТАЕТ САМ HELM, А НЕ ПО ЛЕКСИКОНУ
#
# Все пять образцов ниже сняты с ПИННУТОГО helm (тот же, что ставит
# azure/setup-helm в e2e-newman.yml и production-posture.yml), а не придуманы.
#
# СНЯТЫ на v4.2.3; при переводе пина на v4.2.4 (#590) образцы A и B сличены на
# ОБЕИХ версиях запуском настоящего helm — вывод побайтово тот же, значит
# различающая строка от версии не зависит. C и D на v4.2.4 не воспроизводились:
# они требуют отвечающего 502 хоста и снятой версии в чужом индексе. Поэтому
# здесь сказано, что именно сличалось, а не «образцы верны для v4.2.4».
#
# E снят не запуском, а с ЖУРНАЛА прогона накопительной линии #1523 (kacho#1525):
# он требует хоста, который оборвёт соединение посреди отдачи архива, и на
# офлайновой машине не воспроизводится вовсе. Провенанс назван именно так, чтобы
# «сняли с настоящего helm» не читалось как «повторили у себя».
#
#   A. хост не резолвится
#      ...Unable to get an update from the "https://…/charts" chart repository:
#      Get "…/index.yaml": dial tcp: lookup …: no such host
#   C. хост отвечает 502 — ФОРМА ИНЦИДЕНТА kacho#655
#      ...Unable to get an update from the "http://…/bitnami" chart repository:
#      failed to fetch http://…/bitnami/index.yaml : 502 Bad Gateway
#   B. нет локального сабчарта
#      Error: directory ../does-not-exist not found
#   D. хост ЖИВ, версия снята — наш пин мёртв
#      ...Successfully got an update from the "http://…" chart repository
#      Error: can't get a valid version for 1 subchart(s): "postgresql" …
#   E. хост оборвал соединение на СКАЧИВАНИИ АРХИВА — форма инцидента kacho#1525
#      Error: could not download https://…/postgresql-13.4.4.tgz:
#      Get "…": read tcp …: read: connection reset by peer
#
# ОДНОЙ РАЗЛИЧАЮЩЕЙ СТРОКИ НЕТ, и здесь она была объявлена — неверно. Форм чужой
# недоступности ТРИ, потому что стадий у `helm dep update` три, и каждая печатает
# СВОЁ: обновление индекса (A, C) говорит «репозиторий не ответил», сохранение
# (форма второй) — «репозиторий недостижим», скачивание (E) — «не смог скачать
# <файл>». Первая фраза не встречается ни во второй форме, ни в третьей.
#
# Обе поздние формы требуют ДВУХ признаков сразу — фразы о неудаче И сетевой
# причины в том же выводе. Одной фразы мало: она выходит и на опечатке в адресе,
# и на `404`, когда хост ЖИВ и честно отвечает, что архива у него нет; то и
# другое — НАША находка, повтором не лечится. Перечень сетевых причин объявлен в
# lib/deps-failure-class.sh ОДИН раз на все формы: выписанный у каждой отдельно,
# он разошёлся бы с собой молча.
#
# ИСХОД ЧИТАЕТ КЛАСС, А НЕ АДРЕС. Отметка «условие не создано» ставится по классу
# `external`; адрес источника — диагностика, и пустой адрес вердикта не понижает.
# Пока исход читал адрес, извлекавшийся регуляркой формы ПЕРВОЙ, формы вторая и
# третья классифицировались чужими и всё равно кончались красным «доказательства
# НЕТ» — два места об одном предмете, и решало более узкое (kacho#1525).
#
# ПОЧЕМУ НЕ ПО СЛОВАМ «404 / not found / no such host», как было раньше. Прежний
# предикат считал ПОСТОЯННЫМ всё, где встретилось `not found`, — и сообщение
# инцидента `chart postgresql not found in https://charts.bitnami.com/bitnami:
# … 502 Bad Gateway` попадало под него первым же словом. Отказ чужого хоста
# объявлялся нашим и не повторялся ни разу, хотя повтор был бы уместен.
#
# ГРАНИЦА ПРОВЕДЕНА В СТОРОНУ КРАСНОГО, И ЭТО НАМЕРЕННО. Наши маркеры
# проверяются ПЕРВЫМИ: если в одном выводе сошлись недоступный посторонний хост
# и наша собственная поломка, отказ считается НАШИМ. Послабление выдаётся только
# под доказательство, а не под его отсутствие, — иначе оно стало бы маской,
# превращающей любой срыв подъёма в «условие не создано».
#
# Классификатор вынесен в lib/deps-failure-class.sh — его способность различать
# наш отказ, чужую недоступность и неопознанное доказывается инъекцией БЕЗ
# подъёма helm (см. deps-failure-class-inject.sh).
# shellcheck source=lib/deps-failure-class.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/deps-failure-class.sh"

# Таблица объявленных зависимостей глазами самого helm, приведённая к четырём
# полям через табуляцию: имя · версия · репозиторий · статус.
#
# Читается ДО пустой строки: после неё helm печатает предупреждения о чартах,
# лежащих в `charts/` без объявления (у нас таких четыре, и это осознанно), а
# они не строки таблицы.
#
# Разделитель — ТАБУЛЯЦИЯ, а не «пробельные символы», и это не вкусовщина:
# колонка версии содержит пробел у каждой локальной зависимости (`>= 0.0.0`),
# поэтому разбиение по пробелам сдвигает поля ровно у тех строк, ради которых
# отпечаток и берётся. Первая редакция этой функции разбивала по пробелам, и
# список локальных сабчартов выходил ПУСТЫМ — то есть правка исходника сабчарта
# не сбрасывала пропуск. Поймано контролем «тронул исходник → обязан пересобрать».
deps_table() {
  helm dependency list "$UMBRELLA" 2>/dev/null \
    | awk -F'\t' 'NR == 1 {next} /^[[:space:]]*$/ {exit}
        {
          n = 0
          for (i = 1; i <= NF; i++) {
            f = $i
            gsub(/^[ \t]+|[ \t]+$/, "", f)
            if (f != "") { c[++n] = f }
          }
          if (n >= 4) printf "%s\t%s\t%s\t%s\n", c[1], c[2], c[3], c[n]
        }'
}

# Каталоги локальных сабчартов (`file://…`), путями относительно умбреллы.
local_dep_dirs() {
  deps_table | awk -F'\t' '$3 ~ /^file:\/\// {sub(/^file:\/\//, "", $3); print $3}' \
    | LC_ALL=C sort -u
}

# Отпечаток того, что вендоренные архивы обязаны отражать: объявление
# зависимостей + СОДЕРЖИМОЕ каждого локального сабчарта.
fingerprint() {
  {
    sha256sum "$UMBRELLA/Chart.yaml"
    deps_table | awk -F'\t' '{print $1, $2, $3}'
    local_dep_dirs \
      | while IFS= read -r rel; do
          abs="$(cd "$UMBRELLA" && cd "$rel" 2>/dev/null && pwd)" \
            || { echo "MISSING $rel"; continue; }
          find "$abs" -type f -printf '%P %s %T@\n' 2>/dev/null | LC_ALL=C sort
        done
  } | sha256sum | cut -d' ' -f1
}

# Решение о пропуске похода в сеть, вынесенное отдельно, чтобы его можно было
# прогнать на заведомых входах, не трогая ни сеть, ни дерево.
#   skip_is_allowed <объявлено> <не-на-месте> <отпечаток-совпал:0|1> <принудить:0|1>
skip_is_allowed() {
  [ "$4" = "1" ] && return 1          # принудительное обновление
  [ "$1" -gt 0 ] || return 1          # пустая таблица — не «всё на месте», а «ничего не прочитано»
  [ "$2" -eq 0 ] || return 1          # хоть одна зависимость не на месте
  [ "$3" = "1" ] || return 1          # исходники изменились либо отметки нет
  return 0
}

# ── САМОПРОВЕРКА: пропуск похода в сеть — решение, которое МОЖЕТ БЫТЬ НЕВЕРНЫМ
#    молча. Ошибись он в сторону «можно пропустить» — и проверки, которые от этой
#    материализации зависят, аттестуют ВЕНДОРЕННУЮ КОПИЮ вместо исходника, оставаясь
#    зелёными. Поэтому доказательство лежит здесь исполняемым, а не в чьей-то памяти.
if [ "$SELFTEST" = "1" ]; then
  echo "=== $(basename "$0") --self-test: разбор таблицы и решение о пропуске ==="
  rc=0
  t="$(deps_table)"; n="$(printf '%s\n' "$t" | grep -c .)"
  d="$(local_dep_dirs)"; nd="$(printf '%s\n' "$d" | grep -c .)"
  echo "  осмотрено: строк таблицы зависимостей $n, из них локальных сабчартов $nd"

  if [ "$n" -gt 0 ]; then echo "  ОК  таблица зависимостей непуста"
  else echo "  ПРОВАЛ таблица зависимостей пуста — отпечаток брать не с чего"; rc=1; fi

  # Ровно тот дефект, что и был: разбор по пробелам давал ПУСТОЙ список локальных
  # сабчартов (колонка версии у них содержит пробел), и правка исходника пропуск
  # не сбрасывала. Ноль здесь означает слепой отпечаток, а не «их нет».
  if [ "$nd" -gt 0 ]; then echo "  ОК  локальные сабчарты извлечены ($nd)"
  else echo "  ПРОВАЛ локальных сабчартов извлечено НОЛЬ — отпечаток слеп к правке их исходников"; rc=1; fi

  a="$(fingerprint)"; b="$(fingerprint)"
  if [ "$a" = "$b" ]; then echo "  ОК  отпечаток устойчив: два подряд совпали"
  else echo "  ПРОВАЛ отпечаток нестабилен — пропуск не сработает НИКОГДА, а причина будет невидима"; rc=1; fi

  # Чувствительность доказывается ПРАВКОЙ, а не рассуждением. Трогается время
  # изменения одного файла локального сабчарта и восстанавливается обратно;
  # содержимое дерева не меняется, восстановление — под trap.
  probe_rel="$(printf '%s\n' "$d" | head -1)"
  probe_abs="$(cd "$UMBRELLA" && cd "$probe_rel" 2>/dev/null && pwd)" || probe_abs=""
  # Файл пробы берётся ИЗ ИНДЕКСА, а не обходом диска: обход подобрал бы
  # произведённый артефакт или чужой черновик, и проба стала бы разной на разных
  # машинах. Нет индекса — ОТКАЗ самопроверки, а не возврат к обходу диска.
  #
  # Сам ОТПЕЧАТОК при этом читает диск намеренно, и это не двойной стандарт: он
  # обязан отражать то, что helm упакует, а упакует он рабочее дерево целиком,
  # включая неотслеживаемое. Проба выбирает ОДИН файл, отпечаток описывает ВСЁ
  # содержимое — предметы разные.
  probe_rel_file="$(git -C "$probe_abs" ls-files 2>/dev/null | LC_ALL=C sort | head -1)"
  if [ -n "$probe_rel_file" ]; then probe_file="$probe_abs/$probe_rel_file"; else probe_file=""; fi
  if [ -n "$probe_file" ] && [ -f "$probe_file" ]; then
    probe_was="$(date -r "$probe_file" '+%Y-%m-%d %H:%M:%S.%N %z')"
    # shellcheck disable=SC2064
    trap "touch -d '$probe_was' '$probe_file'" EXIT
    touch "$probe_file"
    c="$(fingerprint)"
    touch -d "$probe_was" "$probe_file"
    trap - EXIT
    if [ "$c" != "$a" ]; then
      echo "  ОК  правка исходника сабчарта меняет отпечаток (проба: ${probe_file#"$UMBRELLA"/})"
    else
      echo "  ПРОВАЛ правка исходника сабчарта отпечаток НЕ меняет — пропуск оставит вендоренную копию"; rc=1
    fi
    d2="$(fingerprint)"
    if [ "$d2" = "$a" ]; then echo "  ОК  проба восстановлена: отпечаток вернулся к исходному"
    else echo "  ПРОВАЛ проба не восстановлена — самопроверка оставила дерево изменённым"; rc=1; fi
  else
    echo "  ПРОВАЛ файла для пробы не нашлось в индексе — чувствительность отпечатка не доказана"; rc=1
  fi

  # Решение о пропуске: инъекция в обе стороны на заведомых входах.
  #   объявлено · не-на-месте · отпечаток-совпал · принудить → ожидание
  while IFS='|' read -r tot bad match force want why; do
    [ -n "${tot:-}" ] || continue
    if skip_is_allowed "$tot" "$bad" "$match" "$force"; then got=пропуск; else got=идём; fi
    if [ "$got" = "$want" ]; then echo "  ОК  ($tot/$bad/$match/$force) → $got — $why"
    else echo "  ПРОВАЛ ($tot/$bad/$match/$force) → $got, ожидалось $want — $why"; rc=1; fi
  done <<'CASES'
22|0|1|0|пропуск|всё на месте, исходники не менялись
22|0|0|0|идём|исходники изменились либо отметки нет
22|1|1|0|идём|одна зависимость не на месте
0|0|1|0|идём|таблица пуста: ноль прочитанного не есть «всё на месте»
22|0|1|1|идём|обновление затребовано явно
CASES

  # ─── ЧЕЙ ОТКАЗ: классификация на РЕАЛЬНЫХ выводах helm ────────────────────
  #
  # Образцы сняты с пиннутого helm (тот же, что в e2e-newman.yml), а не
  # сочинены: сочинённый образец доказывает, что предикат ловит сочинителя.
  # Провенанс версий — в шапке: сняты на v4.2.3, A и B сличены и на v4.2.4.
  # Инъекция в обе стороны: у «чужого» есть законный близнец «наше» той же
  # формы — иначе предикат ловил бы форму сообщения, а не его существо.
  echo
  echo "  --- чей отказ (образцы настоящего helm, инъекция в обе стороны)"
  cls_case() {
    local want="$1" label="$2" f; f="$(mktemp)"; cat > "$f"
    local got; got="$(classify_deps_failure "$f")"; rm -f "$f"
    if [ "$got" = "$want" ]; then echo "  ОК  $label → $got"
    else echo "  ПРОВАЛ $label → $got, ожидалось $want"; rc=1; fi
  }
  cls_case external 'A. хост не резолвится' <<'EOF'
Getting updates for unmanaged Helm repositories...
...Unable to get an update from the "https://charts.example.invalid/charts" chart repository:
	Get "https://charts.example.invalid/charts/index.yaml": dial tcp: lookup charts.example.invalid on 127.0.0.53:53: no such host
Error: no cached repository for helm-manager-f079cc88 found. (try 'helm repo update'): open /home/x/.cache/helm/repository/helm-manager-f079cc88-index.yaml: no such file or directory
EOF
  cls_case external 'C. хост отвечает 502 — форма инцидента kacho#655' <<'EOF'
Getting updates for unmanaged Helm repositories...
...Unable to get an update from the "https://charts.bitnami.com/bitnami" chart repository:
	failed to fetch https://charts.bitnami.com/bitnami/index.yaml : 502 Bad Gateway
Error: no cached repository for helm-manager-70341373 found. (try 'helm repo update'): open /home/x/.cache/helm/repository/helm-manager-70341373-index.yaml: no such file or directory
EOF
  cls_case ours 'B. нет локального сабчарта (близнец: та же немощь, причина НАША)' <<'EOF'
Error: directory ../does-not-exist not found
EOF
  cls_case ours 'D. хост ЖИВ, версия снята — наш пин мёртв' <<'EOF'
Getting updates for unmanaged Helm repositories...
...Successfully got an update from the "https://charts.bitnami.com/bitnami" chart repository
Error: can't get a valid version for 1 subchart(s): "postgresql" (repository "https://charts.bitnami.com/bitnami", version "13.4.4"). Make sure a matching chart version exists in the repo, or change the version constraint in Chart.yaml
EOF
  # Смесь: чужой хост молчит И у нас сломано. Наше выигрывает — послабление
  # выдаётся под доказательство, а не под его отсутствие.
  cls_case ours 'смесь: чужой молчит И наш сабчарт отсутствует → НАШЕ' <<'EOF'
...Unable to get an update from the "https://charts.bitnami.com/bitnami" chart repository:
	failed to fetch https://charts.bitnami.com/bitnami/index.yaml : 502 Bad Gateway
Error: directory ../kacho-vpc not found
EOF
  cls_case transient 'отказ без доказательства чужой недоступности → повтор, потом КРАСНОЕ' <<'EOF'
Error: context deadline exceeded
EOF

  # ─── ЖИВАЯ ИНЪЕКЦИЯ: настоящий helm, настоящий отказ, обе стороны ─────────
  #
  # Синтетический чарт, а не копия умбреллы: у умбреллы 22 объявления и полный
  # проход 3 мин 22 с, то есть проба стала бы дороже того, что доказывает, и её
  # перестали бы гонять. Предмет пробы — КОД ВОЗВРАТА И ОТМЕТКА, а они от числа
  # зависимостей не зависят.
  echo
  echo "  --- живая инъекция (реальный helm, обе стороны)"
  inj() {
    local want_rc="$1" want_mark="$2" label="$3" dir; dir="$(mktemp -d)"
    mkdir -p "$dir/u/templates"; cat > "$dir/u/Chart.yaml"
    local got_rc=0
    KACHO_HELM_DEPS_ATTEMPTS=1 bash "$0" "$dir/u" >"$dir/out.txt" 2>&1 || got_rc=$?
    local got_mark=нет; [ -f "$dir/u/.kacho-deps-precondition-unmet" ] && got_mark=есть
    if [ "$got_rc" = "$want_rc" ] && [ "$got_mark" = "$want_mark" ]; then
      echo "  ОК  $label → код $got_rc, отметка $got_mark"
    else
      echo "  ПРОВАЛ $label → код $got_rc (ждали $want_rc), отметка $got_mark (ждали $want_mark)"
      sed 's/^/        /' "$dir/out.txt" | tail -12; rc=1
    fi
    rm -rf "$dir"
  }
  # (1) ЧУЖОЕ: хост в объявлении недостижим. `.invalid` — зарезервированный
  #     домен верхнего уровня (RFC 2606): он не резолвится НИКОГДА и ни у кого,
  #     поэтому проба детерминирована и не зависит от того, что сегодня с чужим
  #     хостом. Ждём код 3 и отметку.
  inj 3 есть 'чужой источник недостижим → «условие не создано»' <<'EOF'
apiVersion: v2
name: probe-external
version: 0.1.0
dependencies:
  - name: postgresql
    version: 13.4.4
    repository: https://kacho-chart-host-does-not-exist.invalid/charts
EOF
  # (2) НАШЕ: законный близнец той же формы — тоже не материализовалось, тоже
  #     стенд не поднимется, но причина НАША. Ждём код 1 и НИКАКОЙ отметки.
  #     Без этой половины правка превратила бы любой срыв подъёма в «условие не
  #     создано», то есть завела бы маску.
  inj 1 нет 'наш сабчарт отсутствует → КРАСНОЕ, как прежде' <<'EOF'
apiVersion: v2
name: probe-ours
version: 0.1.0
dependencies:
  - name: mysub
    version: ">= 0.0.0"
    repository: file://../does-not-exist
EOF

  # (3) ОТМЕТКА ИСТЕКАЕТ САМА. Послабление, пережившее свой прогон, объявляло бы
  #     «условие не создано» на здоровом стенде. Кладём отметку руками и требуем,
  #     чтобы УСПЕШНЫЙ прогон её снял.
  stale_dir="$(mktemp -d)"; mkdir -p "$stale_dir/u/templates"
  printf 'apiVersion: v2\nname: probe-stale\nversion: 0.1.0\n' > "$stale_dir/u/Chart.yaml"
  touch "$stale_dir/u/.kacho-deps-precondition-unmet"
  KACHO_HELM_DEPS_ATTEMPTS=1 bash "$0" "$stale_dir/u" >/dev/null 2>&1 || true
  if [ -f "$stale_dir/u/.kacho-deps-precondition-unmet" ]; then
    echo "  ПРОВАЛ отметка пережила прогон — она объявит «условие не создано» на здоровом стенде"; rc=1
  else
    echo "  ОК  отметка снимается в начале прогона (не переживает свой предмет)"
  fi
  rm -rf "$stale_dir"

  # ─── ИСХОД ПО КЛАССУ, А НЕ ПО ТОМУ, ИЗВЛЁКСЯ ЛИ АДРЕС ─────────────────────
  #
  # Живая инъекция выше поднимает НАСТОЯЩИЙ helm, и потому умеет ровно одну форму
  # чужой недоступности — ту, что даёт недостижимый хост в объявлении (форма
  # первая). Формы вторая и третья требуют хоста, который ответит по-своему, и на
  # офлайновой машине не воспроизводятся вовсе.
  #
  # Поэтому здесь вывод настоящего helm ВОСПРОИЗВОДИТСЯ подставным: предмет этих
  # случаев — НАШ разбор и НАШ исход (отметка и код возврата), а не helm. Образцы
  # сняты с прогонов (PR #887 и накопительная линия #1523), а не сочинены;
  # подставной ничего не решает и не смягчает — он лишь печатает захваченное.
  #
  # Ради чего они здесь. Класс назывался всеми формами, а ИСХОД читал ПОДСКАЗКУ —
  # адрес, извлекавшийся регуляркой формы ПЕРВОЙ. Форма вторая с 2026-08-21
  # классифицировалась чужой и всё равно кончалась красным «доказательства НЕТ»:
  # два места об одном предмете, и решало более узкое. Отметку теперь ставит
  # КЛАСС, а подсказка осталась диагностикой — поэтому следующая форма, добавленная
  # в классификатор, доедет до исхода сама, без второй правки в другом файле.
  echo
  echo "  --- исход по классу (воспроизведение захваченного вывода helm)"
  replay() { # ждём-код ждём-отметку метка ; вывод helm на stdin
    local want_rc="$1" want_mark="$2" label="$3" dir; dir="$(mktemp -d)"
    mkdir -p "$dir/bin" "$dir/u/templates"
    cat > "$dir/helm-out.txt"
    printf 'apiVersion: v2\nname: probe-replay\nversion: 0.1.0\n' > "$dir/u/Chart.yaml"
    # Подставной helm отвечает на два вопроса, которые задаёт скрипт: офлайновая
    # таблица зависимостей (пуста) и материализация (печатает захваченное, падает).
    {
      echo '#!/usr/bin/env bash'
      # shellcheck disable=SC2016  # это ТЕЛО подставного helm: $1 обязан остаться
      # неразвёрнутым, иначе стоящий здесь аргумент скрипта запечётся в стаб
      echo 'case "$1" in'
      echo "  dep) cat '$dir/helm-out.txt'; exit 1 ;;"
      echo '  *)   exit 0 ;;'
      echo 'esac'
    } > "$dir/bin/helm"
    chmod +x "$dir/bin/helm"
    local got_rc=0
    PATH="$dir/bin:$PATH" KACHO_HELM_DEPS_ATTEMPTS=1 bash "$0" "$dir/u" >"$dir/out.txt" 2>&1 || got_rc=$?
    local got_mark=нет; [ -f "$dir/u/.kacho-deps-precondition-unmet" ] && got_mark=есть
    if [ "$got_rc" = "$want_rc" ] && [ "$got_mark" = "$want_mark" ]; then
      echo "  ОК  $label → код $got_rc, отметка $got_mark"
    else
      echo "  ПРОВАЛ $label → код $got_rc (ждали $want_rc), отметка $got_mark (ждали $want_mark)"
      sed 's/^/        /' "$dir/out.txt" | tail -8; rc=1
    fi
    rm -rf "$dir"
  }
  # (4) ФОРМА ВТОРАЯ — репозиторий недостижим на скачивании. Классификатор знал
  #     её и до этой правки; исход всё равно был КРАСНЫМ, потому что адрес
  #     извлекался только формой первой.
  replay 3 есть 'форма вторая (репозиторий недостижим) → «условие не создано»' <<'EOF'
Save error occurred:  could not find : chart hydra not found in https://k8s.ory.sh/helm/charts: looks like "https://k8s.ory.sh/helm/charts" is not a valid chart repository or cannot be reached: Get "https://k8s.ory.sh/helm/charts/index.yaml": read tcp 10.1.0.27:33630->185.199.111.153:443: read: connection reset by peer
EOF
  # (5) ФОРМА ТРЕТЬЯ — оборвано скачивание САМОГО АРХИВА (kacho#1525).
  replay 3 есть 'форма третья (оборван архив) → «условие не создано»' <<'EOF'
Getting updates for unmanaged Helm repositories...
...Successfully got an update from the "https://charts.bitnami.com/bitnami" chart repository
Saving 22 charts
Downloading postgresql from repo https://charts.bitnami.com/bitnami
Error: could not download https://charts.bitnami.com/bitnami/postgresql-13.4.4.tgz: Get "https://charts.bitnami.com/bitnami/postgresql-13.4.4.tgz": read tcp 10.1.0.186:38644->13.225.47.67:443: read: connection reset by peer
EOF
  # (6) ЗАКОННЫЙ БЛИЗНЕЦ той же формы: хост ОТВЕТИЛ, и ответил, что архива нет.
  #     Наш мёртвый пин либо опечатка в адресе — повтором не лечится. Без этого
  #     случая (4) и (5) были бы неотличимы от маски, превращающей любой срыв
  #     подъёма в «условие не создано».
  replay 1 нет 'близнец: архива по адресу нет (404) → КРАСНОЕ, послабления нет' <<'EOF'
Saving 22 charts
Downloading postgresql from repo https://charts.bitnami.com/bitnami
Error: could not download https://charts.bitnami.com/bitnami/postgresql-99.99.99.tgz: failed to fetch https://charts.bitnami.com/bitnami/postgresql-99.99.99.tgz : 404 Not Found
EOF

  echo
  [ $rc -eq 0 ] && echo "PASS: $(basename "$0") --self-test" || echo "FAIL: $(basename "$0") --self-test"
  exit $rc
fi

table="$(deps_table)"
total="$(printf '%s\n' "$table" | grep -c .)"
notok="$(printf '%s\n' "$table" | awk -F'\t' 'NF >= 4 && $4 != "ok"' | grep -c .)"

# ── РЕЖИМ ВОПРОСА (--check): исходов ДВА, и оба не про дерево ────────────────
#
#   0 — материализация актуальна: рендер возможен, доказательство исполнимо;
#   2 — УСЛОВИЕ НЕ СОЗДАНО: рендер отказал бы ДО первого шаблона, и всякая ось,
#       ждущая красного, покраснела бы по причине, к проверяемому отношения не
#       имеющей («ждали RED — получили RED»). Это НЕ вердикт о дереве.
#
# Решение — то же `skip_is_allowed`, которым скрипт решает, идти ли в сеть, и
# оно уже доказано инъекцией в `--self-test`. Второго предиката не заводится.
if [ "$CHECKONLY" = "1" ]; then
  fpmatch=0
  [ -f "$MARKER" ] && [ "$(cat "$MARKER" 2>/dev/null)" = "$(fingerprint)" ] && fpmatch=1
  if skip_is_allowed "$total" "$notok" "$fpmatch" 0; then
    echo "предпосылка: зависимости умбреллы материализованы (объявлено $total, не на месте $notok, отпечаток исходников совпал)"
    exit 0
  fi
  # Причина называется, а не подразумевается: «не на месте» и «исходник новее
  # архива» чинятся одной командой, но читателю надо знать, что именно случилось.
  if [ "$total" -eq 0 ]; then
    why="таблица зависимостей ПУСТА — прочитано ноль строк, а это не «всё на месте»"
  elif [ "$notok" -gt 0 ]; then
    why="не на месте $notok из $total (helm отказал бы: missing in charts/ directory)"
  else
    why="все $total на месте, но отпечаток исходников НЕ совпал — вендоренные архивы отстали от исходников локальных сабчартов"
  fi
  echo "УСЛОВИЕ НЕ СОЗДАНО: $why"
  echo "       создать условие: bash deploy/scripts/helm-umbrella-deps.sh"
  exit 2
fi

# Объём осмотренного печатается ВСЕГДА: «зависимости на месте» без числа
# одинаково читается и когда helm прочитал двадцать две строки объявления, и
# когда он не прочитал ни одной.
if [ "${KACHO_HELM_DEPS_REFRESH:-0}" != "1" ] \
   && [ "$total" -gt 0 ] && [ "$notok" -eq 0 ] \
   && [ -f "$MARKER" ] && [ "$(cat "$MARKER" 2>/dev/null)" = "$(fingerprint)" ]; then
  echo "=== зависимости умбреллы: объявлено $total, все на месте нужной версии," \
       "отпечаток исходников совпал → в сеть не идём"
  exit 0
fi

echo "=== зависимости умбреллы: объявлено $total, не на месте $notok — материализуем" \
     "(попыток до $ATTEMPTS)"
# ОТМЕТКУ СТАВИТ КЛАСС, А НЕ ПОДСКАЗКА ОБ АДРЕСЕ. Это два разных вопроса, и
# пока на второй отвечала регулярка ОДНОЙ формы, она же решала первый: отказ,
# признанный чужим, но чей адрес та регулярка не нашла, кончался красным
# «доказательства НЕТ» — при доказательстве в том же выводе. Адрес остаётся
# диагностикой: он попадает в текст, но исхода не решает.
last_external_seen=0
last_external_detail=""
i=1
while [ "$i" -le "$ATTEMPTS" ]; do
  log="$(mktemp)"
  if ( cd "$UMBRELLA" && helm dep update ) >"$log" 2>&1; then
    rm -rf "$UMBRELLA"/tmpcharts-*
    fingerprint >"$MARKER"
    echo "=== зависимости умбреллы материализованы (попытка $i из $ATTEMPTS)"
    rm -f "$log"
    exit 0
  fi
  echo "--- попытка $i из $ATTEMPTS не удалась; вывод helm ЦЕЛИКОМ:"
  sed 's/^/    /' "$log"

  # ОТКАЗ КЛАССИФИЦИРУЕТСЯ, А НЕ ПОВТОРЯЕТСЯ ВСЛЕПУЮ. Три класса чинятся тремя
  # разными людьми, и слить их в одно сообщение значит отправить его не туда.
  kind="$(classify_deps_failure "$log")"
  case "$kind" in
    ours)
      # Наш отказ повтором не лечится: пин мёртв, объявление неверно, локального
      # сабчарта нет. Это НАХОДКА О ДЕРЕВЕ, и она обязана остаться красной.
      last_external_seen=0
      last_external_detail=""
      rm -f "$log"
      echo "FATAL: отказ НАШ — повтор не поможет."
      echo "       Версия снята, объявление неверно либо локального сабчарта нет:"
      echo "       проверьте зависимости в $UMBRELLA/Chart.yaml. Причина названа выводом helm выше."
      exit 1
      ;;
    external)
      # Чужой хост не ответил. Повторить стоит (502 переживает пару минут), но
      # если не переживёт — это «условие не создано», а не находка.
      last_external_seen=1
      last_external_detail="$(external_source_hint "$log")"
      echo "--- отказ ЧУЖОЙ: удалённый источник чартов не ответил (${last_external_detail:-адрес не извлёкся})"
      ;;
    *)
      last_external_seen=0
      last_external_detail=""
      ;;
  esac
  rm -f "$log"

  if [ "$i" -lt "$ATTEMPTS" ]; then
    echo "--- отказ повторим, пауза $(( i * 5 ))с"
    sleep $(( i * 5 ))
  fi
  i=$(( i + 1 ))
done

# БЮДЖЕТ ПОВТОРОВ ИСЧЕРПАН. Чем это кончится, зависит от того, ЕСТЬ ЛИ
# ДОКАЗАТЕЛЬСТВО чужой недоступности, а не от того, что доказательства нет.
if [ "${last_external_seen:-0}" = "1" ]; then
  printf '%s\n' "источник чартов не ответил: ${last_external_detail:-адрес не извлёкся}" > "$PRECOND_MARK"
