-- ── 3. Действующие ревизии привязки — НЕ ЗДЕСЬ, и это не пропуск ────────────
--
-- Привязка называет ЗОНУ, а зоны живут в базе kacho_geo — чужой по построению
-- (база на сервис). Прочитать их отсюда нечем, и выписать их сюда списком
-- нельзя: имена зон — произвольные строки, выписанная копия разъехалась бы с
-- посевом geo молча и ровно в тот день, когда каталог размещения поправят.
--
-- Поэтому ревизии ставит доставляющий скрипт (`seed-storage-catalog.sh`): он
-- спрашивает открытые зоны у ВЛАДЕЛЬЦА каталога размещения и пишет строку на
-- каждую пару «класс × зона». Ноль зон у него — не повод писать ноль привязок
-- молча, а повод упасть: класс без действующей ревизии не обслуживается ничем.

COMMIT;
