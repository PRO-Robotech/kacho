     1073741824, 17592186044416, 1073741824),
    ('block-balanced', 'Общего назначения',
     'Без перекоса в одну сторону: корневые тома и обычная нагрузка.',
     '[]'::jsonb, 'BALANCED', 'ACTIVE',
     1073741824, 17592186044416, 1073741824),
    ('block-fast', 'Отклик',
     'Заведён ради задержки и частоты операций: базы данных, очереди.',
