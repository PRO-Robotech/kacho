-- Базовый каталог блочного хранения для ПОДНЯТОГО стенда: кластер данных,
-- действующие ревизии привязки и классы, которые эти привязки обслуживают.
--
-- ПОЧЕМУ ЭТО СТЕНД, А НЕ МИГРАЦИЯ. Каталог классов стартует ПУСТЫМ — решение
-- владельца: класс не может быть предложен арендатору раньше, чем администратор
-- объявит, ЧЕМ он обслуживается. Класс без действующей ревизии привязки —
-- обещание ёмкости, которой никто не дал: том по нему создастся, а положить его
-- будет некуда. Поэтому посев из миграции снят (0017), и продукт поставляется
-- пустым, как geo.
--
-- Следствие, ради которого этот файл существует: свежий стенд НЕПРИГОДЕН, пока
-- каталог пуст, и ни один «под Ready» этого не показывает — том отвечает «класс
-- не найден» на каждом создании. Тот же класс беды, что у пустого каталога geo,
-- и лечится он тем же способом: шагом подъёма, а не памятью оператора.
--
-- ПОЧЕМУ SQL, А НЕ АДМИН-RPC. Ровно по причине, записанной у geo-baseline.sql:
-- админская полоса живёт на cluster-internal слушателе и требует бутстрап-токена,
-- Hydra и проброса портов; вторая копия этой машинерии в шаге подъёма разъехалась
-- бы с первой молча. Здесь пишутся ТЕ ЖЕ строки, которые написал бы админ-RPC,
-- и каждое ограничение схемы (закрытые словари вида, состояния, яруса и
-- обращения; уникальность действующей ревизии на пару «класс×зона») проверяет их
-- так же, как проверило бы его.
--
-- ЧТО ЗДЕСЬ НЕ СТОИТ И НЕ БУДЕТ. Учётный материал кластера данных. В строке
-- лежит ССЫЛКА (`credentials_ref`) на смонтированный секрет; сам ключ не
-- проходит ни через API, ни через БД — строка переживает ротацию и уезжает в
-- резервные копии.
--
-- ИДЕМПОТЕНТНОСТЬ. Повторный прогон не пишет ни одной новой строки: ключи
-- детерминированы, привязка ставится ON CONFLICT DO NOTHING по своей паре.

BEGIN;

-- ── 1. Кластер данных ───────────────────────────────────────────────────────
--
-- Один на стенд. Зоны не перечисляются (`zone_ids = []`) — это означает «во всех
-- зонах», и на dev-стенде так и есть: кластер один. Адрес — путь к файлу
-- конфигурации в образе сервиса; ссылка на ключ — имя смонтированного секрета.
INSERT INTO kacho_storage.storage_backends
    (id, name, kind, description, zone_ids, endpoint, credentials_ref, status)
VALUES
    ('sb-devstand00000001', 'dev-stand', 'CEPH_RBD',
     'Кластер данных dev-стенда. Заведён шагом подъёма, не миграцией.',
     '[]'::jsonb, '/etc/ceph/ceph.conf', 'kacho-storage-ceph-keyring', 'ACTIVE')
ON CONFLICT (id) DO NOTHING;

-- ── 2. Классы ───────────────────────────────────────────────────────────────
--
-- Три, а не пять: каждый обязан отличаться от соседа тем, что арендатор
-- НАБЛЮДАЕТ. Ярус — из закрытого словаря; границы размера объявлены, иначе
-- проверка размера тома не имеет предмета.
