# pgtest-unavailable-mark.sh — ОДНО место, где для шелла живёт признак третьей
# категории исхода: «условие не создано».
#
# Файл не гейт и не команда: он только объявляет величины и подключается через
# `source`. Своего `--self-test` у него нет намеренно — доказывать нечего, а
# прогонщик самопроверок дерева выводит перечень по ИСПОЛНЯЕМОЙ ветке флага и
# такой файл не подхватит.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРОИЗВОДИТЕЛЬ ОДИН, И ОН ПРОИЗВОДИТ ОБЕ СТОРОНЫ
#
# `corelib/pgtest` при неподъёме Postgres печатает строку ниже и выходит кодом 75.
# Обе стороны — его: текст читает человек, код читает машина.
#
# ЧТО ИЗ ЭТОГО ВИДИТ ЧИТАТЕЛЬ ЛОГА — ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. `go test`
# код упавшего бинаря НЕ печатает: воспроизведение шага (пакет, чей `TestMain`
# выходит кодом 75) даёт `--- PASS` успевших проб, затем строки производителя,
# затем `FAIL <пакет> <время>` — и ни одной строки `exit status 75`. Сам `go
# test` выходит единицей. Значит распознавателю доступен ТОЛЬКО текст, и второй
# формы у признака в логе нет.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ПРИЗНАК УЗКИЙ, ХОТЯ У СОСЕДА ОН ШИРЕ
#
# Самостоятельная поставка службы доступа несёт свою копию распознавателя, и та
# знает пять форм (`could not start postgres`, `wait for reaper`, `Cannot connect
# to the Docker daemon`, …). Здесь форма одна, и это решение, а не недосмотр:
# перечисленные причины — ВНУТРЕННОСТИ отказа, которые производитель уже
# ОБЕРНУЛ своей строкой. Наблюдалось дословно на прогоне 34482160874: причиной
# был `wait for reaper … context deadline exceeded`, а в логе стояла строка
# производителя. Признать причину без обёртки значило бы прощать отказ, который
# производитель третьей категорией не объявлял.

# shellcheck shell=bash
# shellcheck disable=SC2034  # величины читают те, кто подключает файл

# PGTEST_UNAVAILABLE_MARK — подстрока, которую печатает производитель.
PGTEST_UNAVAILABLE_MARK='integration Postgres unavailable'

# PGTEST_UNAVAILABLE_CODE — код, которым производитель выходит и которым
# распознаватели этого дерева отвечают за третью категорию.
PGTEST_UNAVAILABLE_CODE=75
