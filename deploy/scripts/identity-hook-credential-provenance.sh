# identity-hook-credential-provenance.sh — ТРИ ОТПЕЧАТКА ОДНОЙ ВЕЛИЧИНЫ, снятые
# с ЖИВОГО стенда: у источника (Secret), у отправителя (файл настроек, который
# читает процесс службы личности) и у принимающей стороны (переменная службы
# прав). Расхождение любых двух — находка.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ, И ПОЧЕМУ ЭТОГО НЕ ЗАМЕНЯЕТ НИ ОДНА СУЩЕСТВУЮЩАЯ ПРОВЕРКА
#
# Полоса обратного вызова заведения пользователя отвечала `401`, край переводил
# это арендатору в `502`, посев церемонии не вставал, десять коллекций из
# тридцати восьми оставались без отчёта (задача #1754). Разбор занял девять
# опровергнутых гипотез и три полных прогона конвейера — и упёрся в то, что
# величина живёт ТОЛЬКО в памяти двух контейнеров: в карту настроек она не
# попадает, в рендер чарта тоже, а стенда прогона к моменту разбора уже нет.
#
# Проверки, которые СУЩЕСТВУЮТ, судят ОБЪЯВЛЕНИЕ: страж рендера — что профиль
# объявил источник; гейт источника — что обе стороны ссылаются на один Secret;
# шаг подстановки — что величина непуста, не равна своему имени и что в ЕГО
# выходе не осталось ни ссылки, ни голого имени. Ни одна не отвечает на вопрос
# «одну ли величину держат стороны ПРЯМО СЕЙЧАС» — а именно он и остался
# неотвеченным.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ПЕЧАТАЕТСЯ — ДЛИНА И ОТПЕЧАТОК, НИКОГДА ВЕЛИЧИНА
#
# Предмет — учётные данные, и вывод уезжает в журнал публичного конвейера.
# Поэтому наружу идут только ДЛИНА и первые 12 знаков md5 — той же формой,
# какой их печатает сам шаг подстановки (`_kratos-identity.tpl`), чтобы строки
# сравнивались глазами без раскрытия. Сравнение отпечатков отвечает на вопрос
# «одна ли величина», и большего для разбора не нужно.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДОВ ТРИ (e2e-flow.md §1)
#
#   0 — среди ИЗМЕРЕННОГО находок нет. Что осталось НЕИЗМЕРЕННЫМ, названо в ИТОГЕ
#       числами: отдаваемых файлов прочитано, имён на голое написание осмотрено.
#   1 — НАХОДКА: отпечатки расходятся либо в конфигурации стоит голое имя;
#   2 — УСЛОВИЕ НЕ СОЗДАНО: кластера нет, под не поднят, контейнер не отвечает.
#       Не вердикт о продукте и в зачёт «прошло» не идёт.
#
# ─────────────────────────────────────────────────────────────────────────────
# ВЕРДИКТ НЕ ПРОИЗНОСИТСЯ НАД НЕПРОЧИТАННЫМ (задача #1803)
#
# Здесь ИТОГ говорил «голых имён нет» БЕЗУСЛОВНО, то есть и в том прогоне, где
# отдаваемых файлов прочитано НОЛЬ: ни один работающий под не смонтировал
# каталог с отрендеренной конфигурацией — читать было нечего, — а строка
# утверждала, что искомого нет. Наблюдалось на прогоне, где конфигурация несла
# ПЯТЬ голых имён: отчёт объявил их отсутствие, не открыв ни одного файла.
#
# Корпус требует обратного прямо (`testing.md` §«Гейт на класс», п. 3): «ноль
# находок» обязано быть отличимо от «ноль прочитанного», и объём осмотренного
# печатается ВСЕГДА. Поэтому перепись ниже несёт ДВА собственных числа —
# прочитанных файлов и осмотренных имён, — а ИТОГ на нуле любого из них говорит
# «не измерено ничего», а не «нет».
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ВЫВОДИТСЯ, А ЧТО ВЫПИСАНО
#
# Перечень рабочих объектов службы личности ВЫВОДИТСЯ из стенда по признаку
# «под монтирует том с отрендеренной конфигурацией», а не выписывается: выписанный
# перечень называл бы объекты сегодняшнего чарта и не рос бы вместе с ним —
# почтовый курьер уже однажды выпал из такого перечня (#1741). Имя переменной,
# которой владеет шаг подстановки, тоже выводится — из объявления самого шага.
#
# Выписаны ровно две вещи, и обе суть КООРДИНАТЫ КОНТРАКТА, а не состав стенда:
# имя Secret'а с величиной и имя заголовка обратного вызова. Обе живут в чарте
# одним объявлением; разойдясь, они уронят эту проверку находкой, а не молчанием.

set -uo pipefail

NS="${1:-kacho}"
SECRET_NAME="${KACHO_HOOK_SECRET_NAME:-kacho-iam-hook-token}"
SECRET_KEY="${KACHO_HOOK_SECRET_KEY:-token}"
HEADER_NAME="${KACHO_HOOK_HEADER_NAME:-X-Kacho-Hook-Token}"
RENDERED="${KACHO_IDENTITY_RENDERED_PATH:-/etc/kacho-identity-rendered/kratos.yaml}"

say() { printf '%s\n' "$*"; }

command -v kubectl >/dev/null 2>&1 || { say "УСЛОВИЕ НЕ СОЗДАНО: kubectl не установлен"; exit 2; }
kubectl -n "$NS" get ns "$NS" >/dev/null 2>&1 || kubectl get ns "$NS" >/dev/null 2>&1 || {
  say "УСЛОВИЕ НЕ СОЗДАНО: пространства имён '$NS' нет — стенд не поднят"; exit 2; }

# fp — длина и отпечаток величины, поданной на stdin. Величина не печатается.
fp() { local v; v="$(cat)"; printf 'длина %s, отпечаток %s' \
        "$(printf %s "$v" | wc -c | tr -d ' ')" \
        "$(printf %s "$v" | md5sum | cut -c1-12)"; }

rc=0
seen=0        # сколько сторон удалось измерить
# Объём осмотренного по ПОЛОСЕ ГОЛЫХ ИМЁН — своя пара чисел, а не «сторон
# измерено»: сторон бывает три, и голые имена ищет только одна из них. Общее
# число сторон на нуле прочитанных отдаваемых файлов выглядит непустым и потому
# читается как подтверждение — ровно та подмена, из-за которой заведена #1803.
rendered_read=0   # отдаваемых файлов, ПРОЧИТАННЫХ у отправителя
bare_names=0      # имён, по которым голое написание реально искали
declare -A PRINT_BY_SIDE

say "=== провенанс учётных данных обратного вызова (пространство имён '$NS')"

# ── СТОРОНА 1: ИСТОЧНИК ──────────────────────────────────────────────────────
if secret_b64="$(kubectl -n "$NS" get secret "$SECRET_NAME" -o "jsonpath={.data.$SECRET_KEY}" 2>/dev/null)" \
   && [ -n "$secret_b64" ]; then
  src_fp="$(printf %s "$secret_b64" | base64 -d | fp)"
  say "  источник   · Secret $SECRET_NAME/$SECRET_KEY: $src_fp"
  PRINT_BY_SIDE["источник"]="${src_fp#*отпечаток }"
  seen=$((seen+1))
else
  say "  источник   · Secret $SECRET_NAME/$SECRET_KEY НЕ ЧИТАЕТСЯ — величины нет либо доступа нет"
fi

# ── СТОРОНА 2: ОТПРАВИТЕЛЬ (что реально лежит в файле, который читает процесс) ─
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
kubectl -n "$NS" get pods -o json > "$WORK/pods.json" 2>/dev/null || : > "$WORK/pods.json"
if [ ! -s "$WORK/pods.json" ]; then
  say "  отправитель · подов не прочитать — стенд не отвечает"
else
  mapfile -t targets < <(python3 - "$WORK/pods.json" "$RENDERED" <<'PY'
import json, sys
path = sys.argv[2]
mount = path.rsplit('/', 1)[0]
data = json.load(open(sys.argv[1], encoding='utf-8'))
for p in data.get('items', []):
    if (p.get('status', {}).get('phase')) != 'Running':
        continue
    spec = p['spec']
    # Перечень выводится по ПРИЗНАКУ: контейнер, которому смонтирован каталог с
    # отрендеренной конфигурацией, — он её и читает. Имена объектов не выписаны.
    for c in spec.get('containers', []):
        if any(m.get('mountPath') == mount for m in c.get('volumeMounts', [])):
            owned = ''
            for ic in spec.get('initContainers', []):
                for e in ic.get('env', []):
                    if e.get('name') == 'KACHO_IDENTITY_SUBSTITUTED_VARS':
                        owned = e.get('value', '')
            print('\t'.join((p['metadata']['name'], c['name'], owned)))
PY
  ) || targets=()

  if [ "${#targets[@]}" -eq 0 ]; then
    say "  отправитель · ни один работающий под не монтирует ${RENDERED%/*} — читать нечего"
  fi
  for t in "${targets[@]}"; do
    pod="${t%%	*}"; rest="${t#*	}"; ctr="${rest%%	*}"; owned="${rest#*	}"
    [ "$owned" = "$rest" ] && owned=""
    # Тело меры уезжает в под ПОТОКОМ, а не строкой в кавычках: вложенное
    # цитирование awk внутри `sh -c` внутри `kubectl exec` — три уровня, на
    # которых ошибка не видна ни одним прогоном, кроме этого самого.
    out="$(kubectl -n "$NS" exec -i "$pod" -c "$ctr" -- sh -s -- "$RENDERED" "$HEADER_NAME" "$owned" 2>/dev/null <<'REMOTE'
f="$1"; hdr="$2"; owned="$3"
[ -r "$f" ] || { echo "НЕТ-ФАЙЛА"; exit 0; }
# Величина берётся СТРОКОЙ НИЖЕ имени заголовка — той же формой, какой её читает
# процесс. Наружу уходит только длина и отпечаток, никогда сама величина.
awk -v hdr="$hdr" '
  index($0, hdr) { want = 1; next }
  want { sub(/^[[:space:]]*value:[[:space:]]*/, ""); gsub(/^"|"$/, ""); print; want = 0 }
' "$f" | sort -u | while IFS= read -r v; do
  printf 'ЗНАЧЕНИЕ\t%s\t%s\n' "$(printf %s "$v" | wc -c | tr -d ' ')" "$(printf %s "$v" | md5sum | cut -c1-12)"
done
for n in $owned; do
  c=$(sed 's/#.*$//; s/${[A-Za-z_][A-Za-z0-9_]*}//g' "$f" | grep -cw -- "$n" || true)
  printf 'ГОЛОЕ\t%s\t%s\n' "$n" "$c"
done
# Метка осмотра печатается ВСЕГДА и последней. Без неё пустой ответ означал бы
# сразу две разные вещи — «контейнер не ответил» и «искали, не нашли», — а
# различить их снаружи нечем: «ноль находок» обязано быть отличимо от «ноль
# прочитанного». Здесь это стоило захода: инъекция с чужим именем заголовка
# отвечала «контейнер не отвечает» при живом контейнере.
printf 'ОСМОТРЕНО\t%s\t%s\n' "$(wc -l < "$f" | tr -d ' ')" "$(printf %s "$owned" | wc -w | tr -d ' ')"
REMOTE
)" || out=""

    if [ -z "$out" ]; then
      say "  отправитель · $pod/$ctr — контейнер не отвечает, величину не снять"
      continue
    fi
    case "$out" in *НЕТ-ФАЙЛА*)
      say "  отправитель · $pod/$ctr — файла $RENDERED нет: процесс читает НЕ подставленную конфигурацию"
      rc=1; continue ;;
    esac

    n_values=0; n_lines=""; n_owned=""; n_bare_checked=0
    while IFS="$(printf '\t')" read -r kind a b; do
      case "$kind" in
        # Метка осмотра приходит ТОЛЬКО когда файл прочитан: ветка «НЕТ-ФАЙЛА»
        # обрывается выше. Значит её приход и есть «отдаваемый файл прочитан».
        ОСМОТРЕНО) n_lines="$a"; n_owned="$b"; rendered_read=$((rendered_read+1)) ;;
        ЗНАЧЕНИЕ)
          n_values=$((n_values+1))
          say "  отправитель · $pod/$ctr заголовок $HEADER_NAME: длина $a, отпечаток $b"
          PRINT_BY_SIDE["отправитель:$pod"]="$b"
          seen=$((seen+1))
          ;;
        ГОЛОЕ)
          # Строка приходит по КАЖДОМУ имени во владении, включая нулевые:
          # счёт осмотренного обязан расти и тогда, когда находок нет.
          n_bare_checked=$((n_bare_checked+1)); bare_names=$((bare_names+1))
          if [ "${b:-0}" -gt 0 ] 2>/dev/null; then
            say "  НАХОДКА    · $pod/$ctr: имя $a стоит в конфигурации ГОЛЫМ ИМЕНЕМ ($b раз) — оно уедет в заголовок дословно"
            rc=1
          fi
          ;;
      esac
    done <<< "$out"
    say "  осмотрено   · $pod/$ctr: строк ${n_lines:-?} · имён во владении ${n_owned:-0} · имён осмотрено на голое написание $n_bare_checked · величин заголовка $n_values"
    if [ "${n_owned:-0}" -eq 0 ] 2>/dev/null; then
      say "  граница     · $pod/$ctr: перечень владения шага не объявлен — голых имён здесь НЕ ИСКАЛИ (это не «не нашли»)"
    fi
    if [ "$n_values" -eq 0 ]; then
      say "  НАХОДКА    · $pod/$ctr: заголовка $HEADER_NAME в конфигурации НЕТ — полоса обратного вызова не объявлена"
      rc=1
    fi
  done
fi

# ── СТОРОНА 3: ПРИНИМАЮЩАЯ ───────────────────────────────────────────────────
# Величина принимающей стороны приезжает из ТОГО ЖЕ Secret'а объявлением чарта.
# Здесь снимается то, что доехало ДО ПОДА, — не объявление, а факт.
recv="$(python3 - "$WORK/pods.json" "$SECRET_NAME" "$SECRET_KEY" <<'PY'
import json, sys
name, key = sys.argv[2], sys.argv[3]
data = json.load(open(sys.argv[1], encoding='utf-8'))
for p in data.get('items', []):
    if p.get('status', {}).get('phase') != 'Running':
        continue
    for c in p['spec'].get('containers', []):
        for e in c.get('env', []):
            ref = (e.get('valueFrom') or {}).get('secretKeyRef') or {}
            if ref.get('name') == name and ref.get('key') == key:
                print('\t'.join((p['metadata']['name'], c['name'], e['name'])))
PY
)" || recv=""
if [ -z "$recv" ]; then
  say "  принимающая · ни один работающий под не берёт $SECRET_NAME/$SECRET_KEY переменной"
else
  while IFS="$(printf '\t')" read -r pod ctr var; do
    [ -n "$pod" ] || continue
    got="$(kubectl -n "$NS" exec -i "$pod" -c "$ctr" -- sh -s -- "$var" 2>/dev/null <<'REMOTE'
eval "v=\${$1-}"
printf %s "$v" | wc -c
printf %s "$v" | md5sum | cut -c1-12
REMOTE
)" || got=""
    if [ -z "$got" ]; then
      say "  принимающая · $pod/$ctr ($var): оболочки в образе нет — величину не снять здесь (это НЕ находка)"
      continue
    fi
    len="$(printf '%s' "$got" | sed -n 1p | tr -d ' ')"
    dig="$(printf '%s' "$got" | sed -n 2p)"
    say "  принимающая · $pod/$ctr переменная $var: длина $len, отпечаток $dig"
    PRINT_BY_SIDE["принимающая:$pod"]="$dig"
    seen=$((seen+1))
  done <<< "$recv"
fi

# ── ВЕРДИКТ ──────────────────────────────────────────────────────────────────
if [ "$seen" -eq 0 ]; then
  say "УСЛОВИЕ НЕ СОЗДАНО: ни одной стороны измерить не удалось — вердикта о величине нет"
  exit 2
fi

uniq_prints="$(for k in "${!PRINT_BY_SIDE[@]}"; do printf '%s\n' "${PRINT_BY_SIDE[$k]}"; done | sort -u | wc -l)"
say "перепись: сторон измерено $seen · различных отпечатков $uniq_prints · отдаваемых файлов прочитано $rendered_read · имён осмотрено на голое написание $bare_names"
if [ "$uniq_prints" -gt 1 ]; then
  say "НАХОДКА: стороны держат РАЗНЫЕ величины — обратный вызов будет отвергнут кодом 401:"
  for k in "${!PRINT_BY_SIDE[@]}"; do say "    $k → ${PRINT_BY_SIDE[$k]}"; done
  rc=1
fi

if [ "$rc" != 0 ]; then
  say "ИТОГ: НАХОДКА (подробности выше)"
elif [ "$bare_names" -eq 0 ]; then
  # НЕ «их нет», а «не смотрели». Строку читает человек посреди разбора, и
  # прочитанная как вердикт она закрывает вопрос, который никто не задавал.
  say "ИТОГ: величина одна у всех ИЗМЕРЕННЫХ сторон; о ГОЛЫХ ИМЕНАХ не измерено НИЧЕГО — отдаваемых файлов прочитано $rendered_read, имён осмотрено 0. Это НЕ «их нет»: при нуле осмотренных имён проверка не смотрела, а числа выше говорят, чего не хватило — отдаваемого файла или перечня владения шага"
else
  say "ИТОГ: величина одна у всех измеренных сторон; голых имён нет среди осмотренного — отдаваемых файлов прочитано $rendered_read, имён осмотрено $bare_names"
fi
exit "$rc"
