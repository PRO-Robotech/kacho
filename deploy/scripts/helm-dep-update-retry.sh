# helm-dep-update-retry.sh — подкачка подчартов с ограниченным повтором.
#
# ЗАЧЕМ. Подчарты умбреллы намеренно НЕ лежат в git (об этом говорит сама цель
# проверки: «charts/*.tgz не в git»), поэтому каждый подъём стенда ходит в сеть за
# архивами внешних чартов. Одиночный сетевой сбой роняет `helm dep update`, за ним
# всю цель подъёма, за ней ВСЕ сквозные пробы шарда — и ветка читается как красная,
# хотя её код не при чём. Наблюдалось 2026-08-13 на одном прогоне ДВАЖДЫ подряд с
# разными архивами (сначала хранилище решений о доступе, затем входной контроллер):
# четыре шарда отчитались «не выполнилось», и в сводке это выглядело как восемь
# падений ветки.
#
# ЧТО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ. Он не превращает отказ в успех. Исчерпав попытки, он
# падает — и падает ГРОМКО, назвав, чем отказ выглядел: временным (сеть, таймаут,
# сброс) или постоянным (архива нет, версия снята). Эти два случая чинятся
# по-разному, и слить их в одно сообщение значило бы отправить читателя не туда.
#
# ПОЧЕМУ ПОВТОР, А НЕ МЯГКИЙ ПРОХОД. Мягкий проход здесь запрещён по построению:
# без подчартов рендерить нечего, и «продолжим без них» дало бы отказ ниже по
# течению, в месте, к причине отношения не имеющем.
set -uo pipefail

ATTEMPTS="${HELM_DEP_ATTEMPTS:-3}"
CHART_DIR="${1:-.}"

cd "$CHART_DIR" || { echo "helm-dep-retry: нет каталога $CHART_DIR" >&2; exit 2; }

log=""
for i in $(seq 1 "$ATTEMPTS"); do
    log="$(helm dep update 2>&1)"
    rc=$?
    if [ $rc -eq 0 ]; then
        [ "$i" -gt 1 ] && echo "helm-dep-retry: подкачка удалась с попытки $i из $ATTEMPTS" >&2
        exit 0
    fi

    # Постоянный отказ повтором не лечится: архива нет либо версия снята.
    # Повторять его — тратить минуты и прятать причину за таймаутом.
    if grep -qiE '404|not found|no such host|unknown field|invalid' <<<"$log"; then
        echo "helm-dep-retry: отказ выглядит ПОСТОЯННЫМ — повтор не поможет." >&2
        echo "  Архив недоступен по адресу или версия снята: проверь пины подчартов в Chart.yaml." >&2
        echo "$log" >&2
        exit 1
    fi

    if [ "$i" -lt "$ATTEMPTS" ]; then
        pause=$(( i * 5 ))
        echo "helm-dep-retry: попытка $i из $ATTEMPTS не удалась (похоже на временный сетевой отказ), пауза ${pause}с" >&2
    fi
    sleep $(( i * 5 ))
done

echo "helm-dep-retry: подкачка не удалась за $ATTEMPTS попыт(ки/ок)." >&2
echo "  Отказ выглядит ВРЕМЕННЫМ (сеть/таймаут), но исчерпал бюджет повторов —" >&2
echo "  это НЕ находка о дереве: подчарты качаются извне, и их недоступность к коду ветки отношения не имеет." >&2
echo "$log" >&2
exit 1
