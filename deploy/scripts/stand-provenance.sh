# ЯДРО
# ─────────────────────────────────────────────────────────────────────────────

# containers_of <ns> — печатает «под<TAB>контейнер<TAB>образ<TAB>идентификатор»
# по КАЖДОМУ работающему контейнеру, нашему и чужому. Пустой вывод — не «чисто»:
# решает вызывающий по коду возврата kubectl, который здесь НЕ проглатывается.
#
# Отбор «наш/чужой» здесь НАМЕРЕННО не делается. Прежняя редакция отбирала
# выражением jq — и тем выводила чужие контейнеры из переписи МОЛЧА: отчёт не
# отличал «осмотрено 17» от «осмотрено 17 из 36». Хуже того, свойство было
# непроверяемо: самопроверка подменяет jq заглушкой, поэтому отбор не исполнялся
# ни на одной оси. Решает теперь is_our_image ниже — в оболочке, где инъекция до
# него дотягивается.
containers_of() {
  kubectl -n "$1" get pods -o json --request-timeout=30s \
    | jq -r '
        .items[]
        | select(.status.phase == "Running")
        | . as $pod
        | .status.containerStatuses[]?
        | [$pod.metadata.name, .name, .image, .imageID] | @tsv
      '
}

# is_our_image <образ> — образ продукта или чужой?
#
# ОТВЕТ СПРАШИВАЕТСЯ У ИСТОЧНИКА ИМЁН, А НЕ ВЫВОДИТСЯ ЗДЕСЬ ПРИСТАВКОЙ.
#
# Прежняя редакция судила одной приставкой платформы (`kacho-*`). Пока имя
# платформы было и именем каждой её части, это было верно; служба управления
# доступом получила СВОЁ имя продукта — и распознаватель ослеп ровно на ней.
# Слепота эта не красная и не зелёная, она МОЛЧАЛИВАЯ: чужого имени предикат не
# отвергает, он его не видит. Наблюдалось дословно — на стенде с тремя нашими
# подами цель печатала «работающих контейнеров ПРОДУКТА ноль», отнеся
# собственный образ в чужие и назвав его в списке посторонних.
#
# Судится по-прежнему ПОСЛЕДНИЙ сегмент ссылки, а не вся строка: и
# `docker.io/library/…`, и `prorobotech/…` — наши; `docker.io/bitnami/postgresql`,
# `hydra:v26.2.0` и голая ссылка по дайджесту `sha256:…` — чужие.
#
# Чужой образ метки провенанса нести НЕ ОБЯЗАН: он собран не нами. Поэтому он
# граница инструмента, а не находка, — но пропущен он вслух, числом и именем.
is_our_image() {
  product_image_is_ours "$1"
}

# revision_from_file <ns> <под> <контейнер> — печатает содержимое величины,
# возвращает 0 при успешном чтении (в т.ч. пустого файла) и 1 иначе.
#
# Причина отказа уходит в ФАЙЛ, а не в переменную: вызывающий берёт результат
# подстановкой команды, то есть функция исполняется в ПОДОБОЛОЧКЕ, и присваивание
# внутри неё до родителя не доезжает. Первая редакция так и делала — и печатала
# «не прочитан — ; клейма тоже нет», то есть отказ БЕЗ причины ровно там, где
# причина и есть весь ответ.
ERROR_SINK=""
revision_from_file() {
  local out rc
  out="$(kubectl -n "$1" exec "$2" -c "$3" --request-timeout="${EXEC_TIMEOUT}s" \
          -- cat "$REVISION_PATH" 2>&1)"
  rc=$?
  if [ "$rc" -ne 0 ]; then
    printf '%s' "$out" | tr '\n' ' ' | cut -c1-140 > "$ERROR_SINK"
    return 1
  fi
  : > "$ERROR_SINK"
  printf '%s' "$out" | tr -d '\r\n'
  return 0
}

# revision_from_label <идентификатор> — запасной путь: клеймо у демона хоста.
# Может вернуть УНАСЛЕДОВАННОЕ от базового образа значение, поэтому источник
# называется вызывающим вслух.
revision_from_label() {
  local sha="${1##*@}" out
  out="$(docker inspect --format '{{ index .Config.Labels "org.opencontainers.image.revision" }}' "$sha" 2>/dev/null)"
  case "$out" in
    ""|"<no value>") return 1 ;;
  esac
  printf '%s' "$out"
}

# commit_of <величина> — коммит без отметки грязи. Отметка вычисляется в момент
# СБОРКИ, а вопрос «то ли это дерево» решает коммит: сравнивать строки целиком
# значило бы краснеть на каждом прогоне, где грязь появилась позже сборки.
commit_of() { printf '%s' "${1%-dirty}"; }

# image_name_of <ссылка> — короткое имя образа: последний сегмент без тега и без
# отпечатка. Этим именем стенд называет контейнер, и им же названы части в
# единственном источнике имён, поэтому вопрос «наш ли / пином ли» задаётся о нём.
image_name_of() {
  local last="${1##*/}"
  last="${last%%@*}"
  printf '%s' "${last%%:*}"
}

# normalize_ref <ссылка> — форма ДЛЯ СРАВНЕНИЯ. Стенд и дерево называют один образ
# по-разному: containerd отвечает полной ссылкой (`docker.io/prorobotech/x:t`),
# профиль объявляет её же, а локально загруженный образ приезжает как
# `docker.io/library/x:t` при объявлении `x:t`. Сравнение сырых строк дало бы
# находку там, где ссылка ОДНА, — то есть ложную находку на каждом прогоне, а
# прибор, чьи находки ложны, перестают читать.
#
# Снимается РОВНО умолчание концентратора и умолчание владельца: то и другое
# приписывает сам containerd. Всё остальное — включая ЧУЖОГО владельца
# (`evil/x:t`) — расхождением остаётся, и это несущее свойство: подмена владельца
# и есть та подмена, ради которой сверка заведена.
normalize_ref() {
  local r="${1#index.docker.io/}"
  r="${r#docker.io/}"
  printf '%s' "${r#library/}"
}

report() {
  local ns="$1"
  local rows rc

  command -v kubectl >/dev/null || { echo "ОТКАЗ: kubectl не найден — спрашивать стенд нечем" >&2; return 2; }
  command -v jq      >/dev/null || { echo "ОТКАЗ: jq не найден — разбирать ответ нечем" >&2; return 2; }

  # ПУСТОЕ ОЖИДАНИЕ НЕ СРАВНИВАЕТСЯ НИ С ЧЕМ И ПОТОМУ СОВПАДАЕТ СО ВСЕМ.
  # Вызывающий получает величину подстановкой (`--expect "$(…)"`), и подстановка
  # бывает пустой: нет git, оторванный checkout, опечатка в цели. Приняв такое
  # молча, инструмент печатал бы «сходится у всех» — то есть выдавал бы отсутствие
  # вопроса за положительный ответ.
  if [ "$EXPECT_GIVEN" -eq 1 ]; then
    case "$(commit_of "$EXPECT")" in
      ""|unknown)
        echo "ОТКАЗ: ожидаемая ревизия пуста («$EXPECT») — сравнивать не с чем." >&2
        echo "       Это НЕ «сходится»: вопрос не был задан ни одному контейнеру." >&2
        return 2 ;;
    esac
  fi

  rows="$(containers_of "$ns")"; rc=$?
  if [ "$rc" -ne 0 ]; then
    echo "ОТКАЗ: кластер не отвечает (пространство имён «$ns») — стенд не опрошен." >&2
    echo "       Это НЕ «ревизия сходится»: не прочитан ни один контейнер." >&2
    return 2
  fi
  if [ -z "$rows" ]; then
    echo "ОТКАЗ: работающих контейнеров в «$ns» ноль — осматривать нечего." >&2
    return 2
  fi

  # Разделение на наших и чужих — ДО заголовка: стенд из одних чужих это не
  # «ревизия сходится», а исчезнувшая предпосылка, и код у него 2, а не 0.
  local product_rows="" foreign_pods=0 foreign_raw=""
  local r_pod r_name r_image r_id
  while IFS=$'\t' read -r r_pod r_name r_image r_id; do
    [ -n "$r_pod" ] || continue
    if is_our_image "$r_image"; then
      product_rows="${product_rows}${r_pod}\t${r_name}\t${r_image}\t${r_id}\n"
    else
      foreign_pods=$((foreign_pods + 1))
      foreign_raw="${foreign_raw}${r_image##*/}\n"
    fi
  done < <(printf '%s\n' "$rows")

  local foreign_list foreign_seen
  foreign_list="$(printf '%b' "$foreign_raw" | sed '/^$/d' | sort -u | tr '\n' ' ')"
  foreign_seen="$(printf '%b' "$foreign_raw" | sed '/^$/d' | sort -u | grep -c . || true)"

  if [ -z "$product_rows" ]; then
    echo "ОТКАЗ: работающих контейнеров ПРОДУКТА в «$ns» ноль — осматривать нечего." >&2
    echo "       чужих при этом осмотрено: контейнеров $foreign_pods, различных образов $foreign_seen [$foreign_list]" >&2
    echo "       Это НЕ «ревизия сходится»: ни один наш образ не опрошен." >&2
    return 2
  fi

  # Шапка выписана строкой, а не выровнена printf: `printf %-16s` считает БАЙТЫ,
  # а кириллическая буква их занимает два — выровненная им шапка съезжает над
  # ровными столбцами и читается как поломка вывода.
  # Столбцов ТРИ, и третий свободный: `printf %-9s` считает БАЙТЫ, а «клеймо» их
  # занимает двенадцать при шести знаках — выровненный им столбец съезжает ровно
  # на кириллице, то есть всегда. Источник ушёл в начало свободного столбца.
  echo "КОНТЕЙНЕР        ОБРАЗ                              ИСТОЧНИК И РЕВИЗИЯ"
  ERROR_SINK="$(mktemp)"

  local seen=0 pods=0 by_file=0 by_label=0 unknown=0 agree=0 diverge=0 dirty=0
  # Второй вид нашего контейнера считается ОТДЕЛЬНО, а не подмешивается к первому:
  # сложи их — и «пин сошёлся» стало бы неотличимо от «ревизия сошлась», то есть
  # перепись перестала бы отвечать на вопрос, из-за которого она заведена.
  local pinned=0 pin_ok=0 pin_bad=0 pin_undeclared=0 pin_narrowed=0
  local prev_key="" pod name image imageid key rev
  # Сортировка по ключу (контейнер, образ, идентификатор): реплики одного
  # развёртывания несут ОДИН образ, и спрашивать каждую значило бы платить
  # временем за заведомо тот же ответ. Число подов при этом называется.
  while IFS=$'\t' read -r pod name image imageid; do
    [ -n "$pod" ] || continue
    pods=$((pods + 1))
    key="$name|$image|$imageid"
    if [ "$key" = "$prev_key" ]; then continue; fi
    prev_key="$key"
    seen=$((seen + 1))

    local src="нет"
    if rev="$(revision_from_file "$ns" "$pod" "$name")"; then
      if [ -n "$rev" ]; then
        src="файл"; by_file=$((by_file + 1))
      else
        rev="(величина ПУСТА: образ собран без --build-arg OCI_IMAGE_REVISION)"
        unknown=$((unknown + 1))
      fi
    elif rev="$(revision_from_label "$imageid")"; then
      src="клеймо"; by_label=$((by_label + 1))
      rev="$rev  ← запасной путь: клеймо могло быть УНАСЛЕДОВАНО от базового образа"
    else
      rev="(не установлена: $REVISION_PATH не прочитан — $(cat "$ERROR_SINK"); клейма у демона хоста тоже нет)"
      unknown=$((unknown + 1))
    fi
    printf "%-16s %-34s [%s] %s\n" "$name" "${image##*/}" "$src" "$rev"

    # СРАВНЕНИЕ ИДЁТ ТОЛЬКО ПО УСТАНОВЛЕННОЙ ВЕЛИЧИНЕ. Строка «не установлена»
    # уже посчитана в unknown; сверять её с ожиданием значило бы завести ВТОРУЮ
    # находку об одном контейнере и назвать «расхождением» отсутствие ответа.
    #
    # НАШИХ КОНТЕЙНЕРОВ ДВА ВИДА, И ВОПРОС К НИМ РАЗНЫЙ.
    #
    # Контейнер, собранный ИЗ ДЕРЕВА ПРОГОНА, обязан нести ревизию прогона: его
    # образ собрал тот же прогон. Контейнер части, чьи ИСХОДНИКИ ВЫНЕСЕНЫ, несёт
    # ревизию ЕЁ ствола и с ревизией прогона не сходится BY CONSTRUCTION — его
    # образ приезжает объявленным пином. Требование ревизии прогона от такого
    # контейнера объявляло находкой ВЕРНЫЙ факт и гасило прогон целиком: четыре
    # шарда из четырёх и стенд консоли, 0 коллекций из 57 (прогон 34694955309).
    #
    # ВОПРОС МЕНЯЕТСЯ, А НЕ СНИМАЕТСЯ: «та ли это ссылка, которую объявляет ЭТО
    # дерево». Снять сверку вовсе значило бы разрешить стенду исполнять что угодно.
    if [ "$EXPECT_GIVEN" -eq 1 ] && [ "$src" != "нет" ]; then
      local imgname pin_rc
      imgname="$(image_name_of "$image")"
      product_image_is_pinned "$imgname"; pin_rc=$?
      case "$pin_rc" in
        0)
          pinned=$((pinned + 1))
          local declared want got matched narrowed wn
          local -a refs=()
          declared="$(product_pin_refs "$imgname" | tr '\n' ' ')"
          if [ -z "${declared// /}" ]; then
            # ПУСТОЙ ПЕРЕЧЕНЬ НЕ ЕСТЬ НИ ВСЕРАЗРЕШЕНИЕ, НИ НАХОДКА: сверять было
            # НЕ С ЧЕМ. Объяви это расхождением — и отметка встала бы от нашей же
            # слепоты; объяви совпадением — и стенд исполнял бы что угодно.
            pin_undeclared=$((pin_undeclared + 1))
            printf "    ↳ ПИН НЕ ОБЪЯВЛЕН: %s приезжает пином, а ссылки для него не называет ни один профиль умбреллы — сравнивать не с чем\n" \
              "$imgname"
          else
            got="$(normalize_ref "$image")"; matched=""; narrowed=0
            # Дробление через `read -a`, а не подстановкой в `for`: подстановка
            # проходит ещё и РАСКРЫТИЕ ШАБЛОНОВ, то есть ссылка со знаком шаблона
            # уехала бы в сравнение подменённой именем файла.
            read -r -a refs <<<"$declared"
            for want in "${refs[@]}"; do
              wn="$(normalize_ref "$want")"
              if [ "$got" = "$wn" ]; then matched="$want"; break; fi
              # Ссылка стенда без владельца — сверяем по имени и тегу, и говорим
              # об этом вслух: сужение, о котором не сказано, и есть слепота.
              case "$got" in
                */*) ;;
                *) if [ "$got" = "${wn##*/}" ]; then matched="$want"; narrowed=1; break; fi ;;
              esac
            done
            if [ -n "$matched" ]; then
              pin_ok=$((pin_ok + 1))
              if [ "$narrowed" -eq 1 ]; then
                pin_narrowed=$((pin_narrowed + 1))
                printf "    ↳ ГРАНИЦА: ссылка стенда не несёт владельца — сверено по имени и тегу с %s\n" "$matched"
              else
                printf "    ↳ пин совпадает с объявленным (%s; объявлен: %s)\n" \
                  "$matched" "$(product_pin_where "$imgname" "$matched")"
              fi
            else
              pin_bad=$((pin_bad + 1))
              printf "    ↳ РАСХОЖДЕНИЕ С ПИНОМ: контейнер исполняет %s, а дерево объявляет %s\n" \
                "$image" "${declared% }"
            fi
          fi
          ;;
        1)
          if [ "$(commit_of "$rev")" = "$(commit_of "$EXPECT")" ]; then
            agree=$((agree + 1))
            case "$rev$EXPECT" in *-dirty*) dirty=$((dirty + 1)) ;; esac
          else
            diverge=$((diverge + 1))
            printf "    ↳ РАСХОЖДЕНИЕ: контейнер исполняет %s, а прогон запущен из %s\n" \
              "$(commit_of "$rev")" "$(commit_of "$EXPECT")"
          fi
          ;;
        *)
          echo "ОТКАЗ: ведомость пинов не загружена — какой вопрос задавать контейнеру $name, неизвестно." >&2
          echo "       Молча спросить про ревизию прогона значило бы вернуть исходный дефект." >&2
          rm -f "$ERROR_SINK"
          return 2
          ;;
      esac
    fi
  done < <(printf '%b' "$product_rows" | sed '/^$/d' | sort -t$'\t' -k2,4)

  rm -f "$ERROR_SINK"
  echo
  echo "осмотрено: контейнеров всего $((pods + foreign_pods)) — продукта $pods (различных образов $seen), чужих $foreign_pods (различных образов $foreign_seen)"
  echo "ревизия установлена у $((by_file + by_label)) (по файлу $by_file, по клейму $by_label), НЕ установлена у $unknown"
  if [ "$foreign_seen" -gt 0 ]; then
    echo "чужие образы пропущены — метки провенанса нести не обязаны, это ГРАНИЦА инструмента, а не находка: $foreign_list"
  fi

  # ПЕРЕПИСЬ СРАВНЕНИЯ ПЕЧАТАЕТСЯ ВСЕГДА, когда ожидание задано, — в том числе
  # когда расхождений ноль. Иначе «сравнение прошло» неотличимо от «сравнения не
  # было»: обе картины дают молчание.
  if [ "$EXPECT_GIVEN" -eq 1 ]; then
    echo "из дерева прогона: ожидалась ревизия $(commit_of "$EXPECT") — сходится у $agree, РАСХОДИТСЯ у $diverge (не установлена у $unknown — не сравнивалась)"
    # ВТОРАЯ СТРОКА ПЕЧАТАЕТСЯ ВСЕГДА, в том числе когда пином не приезжает никто:
    # иначе «сверили пины» неотличимо от «пинов не бывает», а обе картины дают
    # молчание. Перечень объявленного печатается тем же читателем, что и сверял, —
    # второго обхода здесь нет намеренно.
    echo "пином приезжает $pinned — совпадает с объявленным у $pin_ok, РАСХОДИТСЯ у $pin_bad, пин не объявлен у $pin_undeclared (сверено по имени и тегу у $pin_narrowed)"
    echo "объявленное прочитано так: $(product_pins_census)"
    if [ "$dirty" -gt 0 ]; then
      echo "ГРАНИЦА: у $dirty совпадений хоть одна сторона помечена -dirty — равенство коммитов равенства СОДЕРЖИМОГО не доказывает"
    fi
    if [ "$pin_ok" -gt 0 ]; then
      echo "ГРАНИЦА: равенство ССЫЛКИ равенства СОДЕРЖИМОГО не доказывает — тег у чужого конвейера подвижен, а отпечатка дерево не объявляет"
    fi
  fi

  # Код 3 сильнее кода 1: «не установлена» — граница инструмента, «расходится» —
  # положительное утверждение о том, что стенд исполняет чужое дерево.
  # Порядок исходов прежний, и оба вида расхождения в нём равноправны: «стенд
  # исполняет дерево, которого прогон не знает» и «стенд исполняет пин, которого
  # дерево не объявляет» — одно утверждение о посадке, поданное двумя способами.
  [ "$((diverge + pin_bad))" -eq 0 ] || return 3
  [ "$((unknown + pin_undeclared))" -eq 0 ] || return 1
  return 0
}

# ─────────────────────────────────────────────────────────────────────────────
# САМОПРОВЕРКА — доказательство инъекцией в ОБЕ стороны.
#
# Кластера не требует: `kubectl` и `docker` подменяются заглушками в PATH, и
# ядро выше исполняется НАСТОЯЩЕЕ. Проба, читающая ядро глазами, доказывала бы
# только то, что оно написано.
# ─────────────────────────────────────────────────────────────────────────────
self_test() {
  local work; work="$(mktemp -d)"
  # shellcheck disable=SC2064
  trap "rm -rf '$work'" EXIT
  mkdir -p "$work/bin"
  local pass=0 fail=0 out rc

  ok()  { pass=$((pass + 1)); printf '  OK   %s\n' "$*"; }
  bad() { fail=$((fail + 1)); printf '  ПРОВАЛ %s\n' "$*"; }

  # Заглушка kubectl. Поведение задают файлы в $work:
  #   pods.tsv   — что вернёт `get pods` (уже в форме, которую даёт jq)
  #   getrc      — код возврата `get pods`
  #   exec.<контейнер> — содержимое величины; отсутствие файла = отказ exec
  cat > "$work/bin/kubectl" <<'STUB'
#!/usr/bin/env bash
W="$KACHO_SELFTEST_WORK"
args=("$@")
for a in "${args[@]}"; do
  if [ "$a" = "exec" ]; then
    # kubectl -n NS exec POD -c NAME --request-timeout=... -- cat PATH
    c=""
    for ((i=0; i<${#args[@]}; i++)); do
      [ "${args[$i]}" = "-c" ] && c="${args[$((i+1))]}"
    done
    if [ -f "$W/exec.$c" ]; then cat "$W/exec.$c"; exit 0; fi
    echo "Error from server: container \"$c\" not found" >&2
    exit 1
  fi
done
cat "$W/pods.tsv"
exit "$(cat "$W/getrc")"
STUB
  # jq заглушке не нужен: pods.tsv уже в конечной форме, поэтому подменяется и он.
  cat > "$work/bin/jq" <<'STUB'
#!/usr/bin/env bash
cat
STUB
  # Заглушка docker: клеймо отдаёт только для идентификаторов, перечисленных в
  # labels.tsv (строка «<идентификатор> <ревизия>»).
  cat > "$work/bin/docker" <<'STUB'
#!/usr/bin/env bash
W="$KACHO_SELFTEST_WORK"
sha="${!#}"
if [ -f "$W/labels.tsv" ]; then
  while read -r id rev; do
    [ "$id" = "$sha" ] && { printf '%s' "$rev"; exit 0; }
  done < "$W/labels.tsv"
fi
echo "Error: No such object: $sha" >&2
exit 1
STUB
  chmod +x "$work/bin/kubectl" "$work/bin/jq" "$work/bin/docker"
  export KACHO_SELFTEST_WORK="$work"
  local saved_path="$PATH"
  PATH="$work/bin:$PATH"

  local rev40="c11f1d52b93471f7321683c516403def8ae632c8"

  fixture_two_good() {
    printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\nui-1\tvpc\tdocker.io/library/kacho-ui-future-vpc:dev\tsha256:bbb\n' > "$work/pods.tsv"
    echo 0 > "$work/getrc"
    rm -f "$work"/exec.* "$work/labels.tsv"
    printf '%s\n' "$rev40" > "$work/exec.vpc"
    # Ожидание сбрасывается фикстурой: оси 1-11 писались до `--expect` и обязаны
    # остаться утверждениями о ПРЕЖНЕМ поведении. Не сбрось его — двенадцатая ось
    # молча меняла бы предмет одиннадцати предыдущих.
    EXPECT=""; EXPECT_GIVEN=0
  }

  echo "1. величина у каждого контейнера — код 0 (положительный контроль)"
  fixture_two_good
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"$rev40"* ]] && [[ "$out" == *"НЕ установлена у 0"* ]]; then
    ok "код 0, ревизия напечатана, перепись сошлась"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "2. внесён дефект: у одного образа величины нет и клейма нет — код 1 и ИМЯ"
  fixture_two_good
  # два разных контейнера, у второго своё имя, для которого файла нет
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\ngeo-1\tkacho-geo\tdocker.io/library/kacho-geo:dev\tsha256:ccc\n' > "$work/pods.tsv"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 1 ] && [[ "$out" == *"kacho-geo"* ]] && [[ "$out" == *"не установлена"* ]] \
     && [[ "$out" == *"НЕ установлена у 1"* ]]; then
    ok "код 1, координата названа, перепись назвала одного"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "3. законный близнец: файла нет, но есть клеймо — код 0 и ИСТОЧНИК назван"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\ngeo-1\tkacho-geo\tdocker.io/library/kacho-geo:dev\tsha256:ccc\n' > "$work/pods.tsv"
  printf 'sha256:ccc %s\n' "$rev40" > "$work/labels.tsv"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"клеймо"* ]] && [[ "$out" == *"УНАСЛЕДОВАНО"* ]] \
     && [[ "$out" == *"по клейму 1"* ]]; then
    ok "запасной путь сработал и назвал себя оговоркой"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "4. внесён дефект: образ собран без ревизии — величина ПУСТА, это не «прочитать не удалось»"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  printf '\n' > "$work/exec.vpc"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 1 ] && [[ "$out" == *"ПУСТА"* ]] && [[ "$out" == *"OCI_IMAGE_REVISION"* ]]; then
    ok "код 1 и названа ПРИЧИНА — сборка не проставила величину"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "5. исчезла предпосылка: кластер не отвечает — код 2, а НЕ молчаливый успех"
  fixture_two_good
  echo 1 > "$work/getrc"
  : > "$work/pods.tsv"
  out="$(report kacho 2>&1)"; rc=$?
  if [ "$rc" -eq 2 ] && [[ "$out" == *"не отвечает"* ]]; then
    ok "код 2 на недоступном кластере"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "6. исчезла предпосылка: контейнеров продукта ноль — код 2"
  fixture_two_good
  : > "$work/pods.tsv"
  out="$(report kacho 2>&1)"; rc=$?
  if [ "$rc" -eq 2 ] && [[ "$out" == *"ноль"* ]]; then
    ok "код 2 на пустом стенде"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "7. законный близнец: реплики одного образа спрашиваются ОДИН раз"
  fixture_two_good
  printf 'iam-1\tkaname\tdocker.io/library/kaname:dev\tsha256:ddd\niam-2\tkaname\tdocker.io/library/kaname:dev\tsha256:ddd\niam-3\tkaname\tdocker.io/library/kaname:dev\tsha256:ddd\n' > "$work/pods.tsv"
  printf '%s\n' "$rev40" > "$work/exec.kaname"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"продукта 3 (различных образов 1)"* ]]; then
    ok "перепись назвала ОБЕ величины — поды и образы"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "8. законный близнец: две РАЗНЫЕ ревизии на одном стенде видны как две"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\ngeo-1\tkacho-geo\tdocker.io/library/kacho-geo:dev\tsha256:ccc\n' > "$work/pods.tsv"
  printf '%s\n' "1111111111111111111111111111111111111111" > "$work/exec.kacho-geo"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"$rev40"* ]] && [[ "$out" == *"1111111111111111111111111111111111111111"* ]]; then
    ok "смешанный стенд читается как смешанный, а не как один коммит"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "9. отказ обязан НАЗВАТЬ причину — пустое место на её месте это не отчёт"
  # Ось заведена по СВОЕЙ ошибке: причина писалась в переменную, а функция
  # исполняется в подоболочке, поэтому строка выходила «не прочитан — ; клейма
  # тоже нет». Восемь предыдущих осей этого не увидели: они спрашивали ЧТО
  # напечатано, а не ПОЛОН ли ответ.
  fixture_two_good
  printf 'geo-1\tkacho-geo\tdocker.io/library/kacho-geo:dev\tsha256:ccc\n' > "$work/pods.tsv"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 1 ] && [[ "$out" == *"container \"kacho-geo\" not found"* ]]; then
    ok "причина отказа доехала из подоболочки до строки отчёта"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "10. ГРАНИЦА: чужой образ — не находка, но обязан быть НАЗВАН переписью"
  # Ось заведена потому, что различение «наш/чужой» жило в выражении jq, а jq в
  # этой самопроверке подменён на `cat`. То есть свойство, ради которого фильтр
  # написан, не проверяла ни одна из девяти осей выше, и чужой контейнер
  # отбрасывался МОЛЧА: перепись не отличала «осмотрели 17» от «осмотрели 17 из 36».
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\npg-0\tpostgresql\tdocker.io/bitnami/postgresql:16.4.0\tsha256:eee\n' > "$work/pods.tsv"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"чужих"* ]] && [[ "$out" == *"postgresql"* ]] \
     && [[ "$out" == *"НЕ установлена у 0"* ]]; then
    ok "чужой посчитан и назван, находкой не стал"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "11. ГРАНИЦА: стенд из ОДНИХ чужих — код 2, и сказано сколько их было"
  fixture_two_good
  printf 'pg-0\tpostgresql\tdocker.io/bitnami/postgresql:16.4.0\tsha256:eee\n' > "$work/pods.tsv"
  out="$(report kacho 2>&1)"; rc=$?
  if [ "$rc" -eq 2 ] && [[ "$out" == *"ноль"* ]] && [[ "$out" == *"чужих"* ]]; then
    ok "код 2, и «чужие были» отличимо от «стенд пуст»"
  else
    bad "код $rc; вывод: $out"
  fi

  # ───────────────────────────────────────────────────────────────────────────
  # ОСИ СРАВНЕНИЯ С ОЖИДАЕМОЙ РЕВИЗИЕЙ (задача #2180).
  #
  # Инъекция вносит РОВНО ОДИН факт против положительного близнеца: та же
  # фикстура, то же ожидание, отличается только величина в образе. Внеси два —
  # и неизвестно, который дал красное.

  local rev_other="1111111111111111111111111111111111111111"

  echo "12. ожидание СОВПАДАЕТ — код 0 и перепись сравнения (положительный контроль)"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  EXPECT="$rev40"; EXPECT_GIVEN=1
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"сходится у 1"* ]] && [[ "$out" == *"РАСХОДИТСЯ у 0"* ]]; then
    ok "код 0, перепись сравнения напечатана"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "13. ВНЕСЁН ДЕФЕКТ #2180: образ собран из ДРУГОГО коммита — код 3, названы обе ревизии"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  printf '%s\n' "$rev_other" > "$work/exec.vpc"
  EXPECT="$rev40"; EXPECT_GIVEN=1
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 3 ] && [[ "$out" == *"РАСХОЖДЕНИЕ"* ]] && [[ "$out" == *"$rev_other"* ]] \
     && [[ "$out" == *"$rev40"* ]] && [[ "$out" == *"РАСХОДИТСЯ у 1"* ]]; then
    ok "код 3, названы исполняемая и ожидаемая ревизии"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "14. ЗАКОННЫЙ БЛИЗНЕЦ: тот же коммит с отметкой -dirty — код 0, но ГРАНИЦА названа"
  # Без исключения отметки из сравнения это была бы ложная находка НА КАЖДОМ
  # прогоне: грязь вычисляется в момент сборки и к вердикту бывает другой.
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  printf '%s\n' "$rev40-dirty" > "$work/exec.vpc"
  EXPECT="$rev40"; EXPECT_GIVEN=1
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" == *"сходится у 1"* ]] && [[ "$out" == *"ГРАНИЦА"* ]] \
     && [[ "$out" == *"-dirty"* ]]; then
    ok "грязь не сделала находки и не была умолчана"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "15. ВНЕСЁН ДЕФЕКТ: ожидание ПУСТО — код 2, а не «совпало со всем»"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  EXPECT=""; EXPECT_GIVEN=1
  out="$(report kacho 2>&1)"; rc=$?
  if [ "$rc" -eq 2 ] && [[ "$out" == *"сравнивать не с чем"* ]]; then
    ok "пустое ожидание отвергнуто, а не принято за совпадение"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "16. ГРАНИЦА: без --expect переписи сравнения НЕТ — «не сравнивали» отличимо от «сошлось»"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\n' > "$work/pods.tsv"
  printf '%s\n' "$rev_other" > "$work/exec.vpc"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" != *"ожидалась ревизия"* ]] && [[ "$out" != *"РАСХОЖДЕНИЕ"* ]]; then
    ok "чужая ревизия без ожидания находкой не стала и молча сошедшейся не объявлена"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "17. ПОРЯДОК ИСХОДОВ: расхождение сильнее «не установлена» — код 3, не 1"
  fixture_two_good
  printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\ngeo-1\tkacho-geo\tdocker.io/library/kacho-geo:dev\tsha256:ccc\n' > "$work/pods.tsv"
  printf '%s\n' "$rev_other" > "$work/exec.vpc"
  EXPECT="$rev40"; EXPECT_GIVEN=1
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 3 ] && [[ "$out" == *"РАСХОДИТСЯ у 1"* ]] && [[ "$out" == *"НЕ установлена у 1"* ]]; then
    ok "оба факта названы, вернул сильнейший исход"
  else
    bad "код $rc; вывод: $out"
  fi

  # ───────────────────────────────────────────────────────────────────────────
  # ОСИ ДВУХ ВИДОВ НАШЕГО КОНТЕЙНЕРА: ИЗ ДЕРЕВА И ПО ПИНУ.
  #
  # Контейнер части, чьи исходники вынесены, несёт ревизию ЕЁ ствола и с ревизией
  # прогона не сходится by construction. Сверка с ревизией прогона объявляла это
  # расхождением — то есть находкой на ВЕРНОМ факте, — и гасила прогон: четыре
  # шарда из четырёх и стенд консоли, 0 коллекций из 57.
  #
  # ССЫЛКА БЕРЁТСЯ У ЧИТАТЕЛЯ, А НЕ ВЫПИСЫВАЕТСЯ. Выписанная устарела бы при
  # первом же обновлении пина — и устарела бы МОЛЧА: положительный контроль
  # перестал бы быть контролем, а инъекция — инъекцией.
  local pinned_image pinned_ref
  pinned_image="$(product_image_name iam)" || { bad "имя вынесенной части не прочитано"; return 1; }
  pinned_ref="$(product_pin_refs "$pinned_image" | head -1)"
  [ -n "$pinned_ref" ] || { bad "объявленная ссылка вынесенной части не прочитана — оси 18-22 беспредметны"; return 1; }

  # fixture_tree_and_pin — стенд из ДВУХ наших контейнеров: один из дерева, один
  # по пину. Ровно на такой картине и стоял дефект.
  fixture_tree_and_pin() {
    fixture_two_good
    printf 'vpc-1\tvpc\tdocker.io/library/kacho-vpc:dev\tsha256:aaa\niam-1\t%s\t%s\tsha256:fff\n' \
      "$pinned_image" "$1" > "$work/pods.tsv"
    printf '%s\n' "$rev40" > "$work/exec.vpc"
    printf '%s\n' "efa5d1f3d63ca74c32a3b85062c6ba59738e072d" > "$work/exec.$pinned_image"
    EXPECT="$rev40"; EXPECT_GIVEN=1
  }

  echo "18. КОНТРОЛЬ: контейнер по пину исполняет ОБЪЯВЛЕННУЮ ссылку — код 0, находки нет"
  fixture_tree_and_pin "$pinned_ref"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 0 ] && [[ "$out" != *"РАСХОЖДЕНИЕ"* ]] \
     && [[ "$out" == *"пином приезжает 1"* ]] && [[ "$out" == *"совпадает с объявленным у 1"* ]]; then
    ok "чужая ревизия вынесенной части находкой не стала, пин назван переписью"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "19. ВНЕСЁН ДЕФЕКТ: контейнер по пину исполняет НЕ ОБЪЯВЛЕННУЮ ссылку — код 3"
  # Отличие от оси 18 РОВНО ОДНО: тег ссылки. Внеси два — и неизвестно, который дал красное.
  fixture_tree_and_pin "${pinned_ref%:*}:main-deadbeef"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 3 ] && [[ "$out" == *"main-deadbeef"* ]] && [[ "$out" == *"$pinned_ref"* ]] \
     && [[ "$out" == *"РАСХОДИТСЯ у 1"* ]]; then
    ok "код 3, названы исполняемая и объявленная ссылки"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "20. ИНЪЕКЦИЯ СУЩЕСТВУЮЩЕГО: контейнер ИЗ ДЕРЕВА исполняет чужую ревизию — по-прежнему код 3"
  # Без этой оси молчание сверки по ревизии неотличимо от молчания снятой сверки.
  fixture_tree_and_pin "$pinned_ref"
  printf '%s\n' "$rev_other" > "$work/exec.vpc"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 3 ] && [[ "$out" == *"а прогон запущен из"* ]] && [[ "$out" == *"$rev_other"* ]] \
     && [[ "$out" == *"совпадает с объявленным у 1"* ]]; then
    ok "сверка по ревизии жива, и два вида контейнера различены в одной переписи"
  else
    bad "код $rc; вывод: $out"
  fi

  echo "21. ГРАНИЦА: пин не объявлен НИ ОДНИМ профилем — код 1, «сравнивать не с чем»"
  # Пустой перечень не есть всеразрешение и не есть находка: сверять было НЕ С ЧЕМ.
  # Перечень подменяется файлом БЕЗ объявления — единственный вход, на котором
  # «не объявлен» отличимо от «объявлен другой».
  printf 'neighbour:\n  image:\n    repository: docker.io/prorobotech/other\n    tag: main-01234567\n' \
    > "$work/no-pin.yaml"
  product_pins_load "$work/no-pin.yaml" || { bad "подменённый перечень не загрузился"; }
  fixture_tree_and_pin "$pinned_ref"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 1 ] && [[ "$out" == *"пин не объявлен у 1"* ]] && [[ "$out" != *"РАСХОДИТСЯ у 1"* ]]; then
    ok "«не объявлен» названо границей, а не расхождением"
  else
    bad "код $rc; вывод: $out"
  fi
  product_pins_load || { bad "перечень пинов дерева не перечитался"; }

  echo "22. ЗАКОННЫЙ БЛИЗНЕЦ: у контейнера по пину ревизия НЕ установлена — код 1, а не «сошлось»"
  fixture_tree_and_pin "$pinned_ref"
  rm -f "$work/exec.$pinned_image"
  out="$(report kacho)"; rc=$?
  if [ "$rc" -eq 1 ] && [[ "$out" == *"НЕ установлена у 1"* ]]; then
    ok "пин не отменяет требования нести ревизию"
  else
    bad "код $rc; вывод: $out"
  fi

  PATH="$saved_path"
  echo "итог самопроверки: прошло $pass, провалено $fail"
  [ "$fail" -eq 0 ]
}

case "$MODE" in
  self-test) self_test; exit $? ;;
  report)    report "$NAMESPACE"; exit $? ;;
esac
