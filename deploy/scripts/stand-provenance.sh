# stand-provenance.sh — какую РЕВИЗИЮ дерева исполняет каждый контейнер стенда.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ
#
# «Спроси стенд, что он исполняет» — первое действие при разборе красного: без
# ответа вердикт выносится про неизвестно что. Цена уже уплачена — разбор красного
# консоли стоил трёх ложных гипотез против стенда, исполнявшего две чужие ревизии
# сразу, а разбор удостоверения упёрся в поиск символов по бинарю внутри
# контейнера.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ФАЙЛ В ОБРАЗЕ, А НЕ КЛЕЙМО (и почему клеймо всё-таки осталось)
#
# Прежняя редакция читала клеймо `org.opencontainers.image.revision` у демона
# ХОСТА по идентификатору работающего образа. У этого пути две дыры, и обе
# наблюдались:
#
#   1. образа может не быть в демоне хоста. Локальный стенд держит образы в
#      containerd УЗЛА kind; чистка диска (`docker image prune`) уносит копию
#      хоста, а стенд продолжает работать. Замер 2026-08-25: образов `kacho-*` в
#      демоне хоста 0, в containerd узла 17 — и цель печатала «метки ревизии нет»
#      у ВСЕХ 18 контейнеров при живых, верных клеймах;
#   2. у управляемого кластера демона хоста нет by construction. Там образы
#      тянутся из реестра, и прочитать их клеймо можно только сетевым обращением
#      к реестру с учётными данными — то есть цель работала бы на одном стенде из
#      двух.
#
# Файл `/etc/kacho/image-revision` читается у РАБОТАЮЩЕГО контейнера одним
# `kubectl exec`, одинаково на kind и на управляемом кластере, без демона и без
# реестра. Он часть содержимого образа: подменить его объявлением пода нельзя, в
# отличие от переменной окружения.
#
# Отдельно про клеймо: на образе, собранном ОТ помеченной базы, клеймо того же
# имени приезжает ОТ БАЗЫ. Проверено на образе консоли: `image.source`,
# `image.title` и `maintainer` там принадлежат nginx. Значит клеймо, прочитанное
# без нашей сборки, выглядит нашим и им не является — поэтому запасной путь
# называет источник вслух, а не выдаёт величину за установленную.
#
# ─────────────────────────────────────────────────────────────────────────────
# КОДЫ ВОЗВРАТА
#
#   0  ревизия установлена у КАЖДОГО осмотренного контейнера, и, если задано
#      ожидание, каждый сошёлся со СВОИМ предметом сверки: контейнер из дерева —
#      с ревизией прогона, контейнер по пину — с объявленной ссылкой (см. ниже)
#   1  у части контейнеров установить не удалось либо пин не объявлен ни одним
#      профилем — они названы поимённо
#   2  предпосылка исчезла: кластер недоступен, контейнеров продукта ноль либо
#      ожидание задано пустым
#   3  сверка дала расхождение (только при `--expect`): либо ревизия установлена и
#      РАСХОДИТСЯ с ожидаемой, либо контейнер по пину исполняет ссылку, которой
#      это дерево не объявляет
#
# Код 2 отделён намеренно: «ноль находок» обязано быть отличимо от «ноль
# прочитанного». Прежняя редакция на недоступном кластере печатала ОДИН заголовок
# и выходила успехом — то есть молчание неотличимо от исправного стенда.
#
# ─────────────────────────────────────────────────────────────────────────────
# --expect: ЗАЧЕМ СРАВНЕНИЕ, ЕСЛИ ВЕЛИЧИНА И ТАК ПЕЧАТАЕТСЯ (задача #2180)
#
# Печатать ревизию мало: её надо С ЧЕМ-ТО СВЕРИТЬ, а сверять глазами некому —
# журнал планового прогона не читает никто. Наблюдалось дважды за один заход
# выкатки: образ на стенде был собран на 7 ч 16 мин РАНЬШЕ коммита, вводившего
# и ручку, и её читателя. Ручка в поде стояла, бинарь про неё не знал; вердикт
# был вынесен о дереве, которого стенд не исполнял.
#
# СРАВНИВАЕТСЯ КОММИТ, А НЕ СТРОКА ЦЕЛИКОМ. Величина имеет форму `<sha>` либо
# `<sha>-dirty`; отметка грязи вычисляется в МОМЕНТ сборки и в момент вердикта
# может быть уже другой (прогон успел насорить в дереве). Сравнение строк
# целиком дало бы расхождение там, где коммит один, — то есть ложную находку на
# каждом прогоне, а прибор, чьи находки ложны, перестают читать. Поэтому
# `-dirty` из сравнения ИСКЛЮЧЕНА и НАЗВАНА отдельной строкой: равенство двух
# грязных величин равенства содержимого не доказывает, и об этом сказано вслух,
# а не умолчано.
#
# ПУСТОЕ ОЖИДАНИЕ — ОТКАЗ, А НЕ «СРАВНИВАТЬ НЕ С ЧЕМ, ЗНАЧИТ ВСЁ СОШЛОСЬ».
# Пустая строка совпала бы с чем угодно, и сравнение выглядело бы исполненным.
#
# ПОРЯДОК ИСХОДОВ: код 3 сильнее кода 1. «Не установлена» — граница инструмента
# (образ мог быть собран не нами), а «расходится» — положительное утверждение о
# том, что стенд исполняет ЧУЖОЕ дерево. Второе доказательнее, поэтому побеждает.
#
# ─────────────────────────────────────────────────────────────────────────────
# НАШИХ КОНТЕЙНЕРОВ ДВА ВИДА, И ПРЕДМЕТ СВЕРКИ У НИХ РАЗНЫЙ
#
# Требование «несёт ревизию прогона» верно для части, чьи исходники в ЭТОМ дереве:
# её образ собирает тот же прогон. Для части ВЫНЕСЕННОЙ оно ложно by construction —
# её образ собирает чужой конвейер, приезжает он объявленным пином, и тег называет
# коммит ЕЁ ствола. Требуя ревизию прогона от такого контейнера, инструмент объявлял
# находкой ВЕРНЫЙ факт.
#
# Цена измерена, а не предположена (прогон 34694955309): отметка «предпосылка не
# создана» встала на ЧЕТЫРЁХ шардах newman из четырёх и на стенде консоли, и
# сквозной набор платформы не исполнил НИ ОДНОЙ коллекции из 57 — при том что
# сходилось 3 контейнера из 4 на шарде и 16 из 17 на консоли.
#
# ВОПРОС ПОЭТОМУ МЕНЯЕТСЯ, А НЕ СНИМАЕТСЯ. «Не сравнивать вовсе» исходом не
# является: тогда стенд вправе исполнять что угодно, и подмена владельца образа
# (`evil/<имя>:<тот же тег>`) прошла бы молча. Контейнер по пину сверяется с
# ССЫЛКОЙ, ОБЪЯВЛЕННОЙ ЭТИМ ДЕРЕВОМ, и расхождение С ПИНОМ остаётся находкой.
#
# ПЕРЕЧЕНЬ ПИНОВ ВЫВОДИТСЯ ИЗ ДЕРЕВА (`product_pins_load`, разбор — в шапке
# `deploy/scripts/lib/product-names.sh`): какая часть вынесена, объявляет
# `internal/productnaming`; какой ссылкой она приезжает — профили умбреллы,
# названные единственным читателем состава стендов (`deploy/tests/helm/stacks.sh`).
# Выписанный здесь перечень разошёлся бы с деревом МОЛЧА.
#
# ЧЕГО ЭТА СВЕРКА НЕ ДОКАЗЫВАЕТ, названо вслух и печатается строкой отчёта:
# равенство ссылки не есть равенство СОДЕРЖИМОГО — тег у чужого конвейера подвижен,
# а отпечатка (`@sha256:…`) дерево для этого образа не объявляет.
set -uo pipefail

NAMESPACE="${KACHO_NAMESPACE:-kacho}"
MODE="report"
EXEC_TIMEOUT="${KACHO_PROVENANCE_EXEC_TIMEOUT:-20}"

# EXPECT — ревизия дерева, из которого запущен прогон. Пусто = сравнения нет,
# отчёт прежний. Величину сюда передаёт вызывающий: ОБЪЯВЛЕНА она один раз, в
# provenance.mk, и второй её вычислитель здесь разошёлся бы с первым молча —
# ровно тем, чем разъехались три рукописных перечня репозиториев прежней топологии.
EXPECT=""
EXPECT_GIVEN=0

# REVISION_PATH — путь величины внутри образа. Объявлен ОДИН раз и здесь;
# Dockerfile'ы пишут этот же путь, и что все они его пишут, держит
# deploy/stand_provenance_declaration_test.go.
REVISION_PATH="/etc/kacho/image-revision"

usage() {
  cat <<'EOF'
stand-provenance.sh [--namespace <ns>] [--expect <ревизия>] [--self-test]

  --namespace   пространство имён стенда (умолчание: kacho, либо KACHO_NAMESPACE)
  --expect      ревизия дерева, из которого запущен прогон; расхождение = код 3
  --self-test   доказательство инъекцией в обе стороны, без кластера
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --namespace) NAMESPACE="${2:?--namespace требует значения}"; shift 2 ;;
    # Пустое значение принимается РАЗБОРОМ и отвергается ЯДРОМ (код 2): отвергни
    # его здесь — и `--expect "$(…)"` с пустой подстановкой выглядел бы опечаткой
    # вызова, тогда как это исчезнувшая предпосылка, и назвать её обязан отчёт.
    --expect)    EXPECT="${2-}"; EXPECT_GIVEN=1; shift 2 ;;
    --self-test) MODE="self-test"; shift ;;
    -h|--help)   usage; exit 0 ;;
    *) echo "неизвестный аргумент: $1" >&2; usage >&2; exit 2 ;;
  esac
done

# ИМЕНА ЧАСТЕЙ ПРОДУКТА — ОДИН ИСТОЧНИК, И ЧИТАЮТСЯ ОНИ ЗДЕСЬ, А НЕ В ЦИКЛЕ.
#
# Читатель подключается по МЕСТУ ЭТОГО ФАЙЛА, а не относительно текущего
# каталога: цель зовут и из `deploy/`, и из корня дерева.
#
# Загрузка стоит ДО развилки режимов и вне `report`, потому что `report`
# исполняется в подоболочке (`out="$(report …)"`): загрузи мы внутри, ведомость
# умирала бы вместе с подоболочкой, а инструмент собирался бы на каждый вызов.
#
# Отказ источника ГРОМКИЙ и это код 2, а не 1: не прочитав имена, мы не знаем,
# какой контейнер наш, — то есть не выносим вердикта ни об одном. Молча считать
# всё чужим значило бы вернуть ровно ту слепоту, ради снятия которой источник и
# заведён.
# shellcheck source=deploy/scripts/lib/product-names.sh
. "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lib/product-names.sh"
_dirs="$(product_service_dirs)" || {
  echo "ОТКАЗ: перечень частей продукта не прочитан — чей контейнер наш, неизвестно." >&2
  exit 2
}
# перечень каталогов передаётся отдельными словами — дробление намеренное.
# Пояснение стоит ПЕРЕД директивой, а не после кода правила: токен, не имеющий
# вида ключ=значение, обрывает разбор, и файл выпадает из-под проверки целиком.
# shellcheck disable=SC2086
product_names_load $_dirs || {
  echo "ОТКАЗ: имена частей продукта не прочитаны — вердикта нет ни об одном контейнере." >&2
  echo "       Это «не выполнилось», а не «наших контейнеров нет»." >&2
  exit 2
}

# ПИНЫ ВЫНЕСЕННЫХ ЧАСТЕЙ — ЧИТАЮТСЯ ЗДЕСЬ ЖЕ И ПО ТОЙ ЖЕ ПРИЧИНЕ.
#
# Контейнер части, чьи исходники вынесены, несёт ревизию ЕЁ ствола: сверять его с
# ревизией прогона значит объявлять находкой верный факт. Сверять надо с тем, что
# объявляет ЭТО дерево, — значит объявленное надо прочитать, и прочитать ДО цикла:
# `report` исполняется в подоболочке, и загрузка внутри умирала бы вместе с ней.
#
# Отказ ГРОМКИЙ и это код 2, а не 1: не прочитав объявленного, мы сверили бы
# ссылку с пустым перечнем и получили бы находку на КАЖДОМ верном пине.
product_pins_load || {
  echo "ОТКАЗ: объявленные пины не прочитаны — вердикта о посадке вынесенной части нет." >&2
  echo "       Это «не выполнилось», а не «пин разошёлся»." >&2
  exit 2
}

