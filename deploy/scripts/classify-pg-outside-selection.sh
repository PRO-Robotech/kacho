# classify-pg-outside-selection.sh — перепись и вердикт цели
# `make test-pg-outside-selection`, ПО ПОЛОСАМ и по числам.
#
#   classify-pg-outside-selection.sh --lane <модуль> <заявлено> <лог> <код> [--lane …]
#
# Коды возврата: 0 — зелено; 1 — находка; 2 — негодный вызов либо провал
# самопроверки.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ ВЕТКОЙ В РЕЦЕПТЕ
#
# Ветку внутри рецепта Makefile нечем доказать инъекцией, а недоказанная ветка
# сама становится тем классом, который мы ловим, — формой без содержания. Тот же
# довод и то же решение, что у соседа по каталогу (classify-integration-outcome.sh).
# Здесь вход подаётся файлом, поэтому обе стороны проверяются за миллисекунды.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ПЕРЕПИСЬ ИДЁТ ПО ПОЛОСАМ, А МОДУЛЬНЫЙ ПУТЬ ПРИХОДИТ ИЗВНЕ
#
# Прежняя редакция жила строкой рецепта и считала отчитавшиеся пакеты ОДНИМ
# выражением на весь совокупный лог:
#
#     grep -cE '^(ok|FAIL|\?)[[:space:]]+github\.com/PRO-Robotech/kacho[-/]'
#
# То есть распознаватель знал РОВНО ОДИН модульный путь. Служба iam несёт свой
# `go.mod`, её модуль называется иначе, и все её итоговые строки были для
# переписи невидимы: 14 пакетов из 24 отчитались `ok`, а цель напечатала
# «отчиталось 10 из 24 — часть перечня не дошла до прогона». Ни один пакет при
# этом не выпадал: красное было свойством ПРОВЕРКИ, а не дерева, и разобрать его
# можно было только сверив вывод с go.mod вручную.
#
# Отсюда два требования, и оба несущие:
#
#   • МОДУЛЬНЫЙ ПУТЬ НЕ ВПИСЫВАЕТСЯ, А ВЫВОДИТСЯ. Вызывающий берёт его у самого
#     модуля (`go -C <каталог> list -m`) и передаёт сюда. Литерал был вторым
#     местом об одном предмете — первым является `go.mod`, — и разошёлся молча
#     при переименовании модуля. Выведенный расходиться не может by construction.
#
#   • ПЕРЕПИСЬ ПО ПОЛОСАМ, А НЕ СУММОЙ. Перечень пакетов уже разделён по модулям
#     ровно потому, что «общий список молча потерял бы половину — она отчиталась
#     бы нулём пакетов, что неотличимо от успеха». Вердикт был при этом общим:
#     полоса, отчитавшаяся нулём, гасилась соседкой, если сумма сходилась.
#     Здесь каждая полоса судится отдельно и своими числами.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО СЧИТАЕТСЯ НАХОДКОЙ — ШЕСТЬ ОСЕЙ, КАЖДАЯ СВОИМ ЧИСЛОМ
#
#   1. пустая полоса (заявлено 0) — цель перестала проверять целый модуль;
#   2. ненулевой код `go test` — вердикт полосы недействителен;
#   3. упавшие утверждения (`--- FAIL`) либо пакеты (`FAIL <пакет>`; сюда же
#      попадает «[build failed]», у которого НЕТ ни одного `--- FAIL`);
#   4. пропуски (`--- SKIP`) — пропуск здесь ОТКАЗ: пропущенная проба печатает
#      `ok` и неотличима от пройденной, ради чего цель и заведена;
#   5. пакет без проб (`? <пакет> [no test files]`) — назван в перечне, а
#      исполнять в нём нечего: то же молчание, только на шаг раньше;
#   6. отчиталось не столько пакетов, сколько заявлено, — часть перечня не дошла.
#
# Ноль пройденных утверждений в полосе — тоже находка: полоса отработала
# вхолостую, и её зелёное неотличимо от её отсутствия.
#
# НАХОДКИ ПЕЧАТАЮТСЯ ВСЕ, а не до первой: разбирать красное по одной оси за
# прогон значит платить прогоном за каждую.
#
# Самопроверка: classify-pg-outside-selection.sh --self-test
set -uo pipefail

usage() {
  cat >&2 <<'USAGE'
classify-pg-outside-selection.sh --lane <модуль> <заявлено> <лог> <код> [--lane …]
classify-pg-outside-selection.sh --self-test
USAGE
}

# lane_reported — сколько строк итога пакета принадлежит ИМЕННО этой полосе.
#
# Граница обязательна: без неё модуль, чей путь есть префикс соседнего, считал бы
# чужие строки своими. Отделитель — либо `/` (пакет внутри модуля), либо пробел
# (пакет, совпадающий с корнем модуля).
lane_reported() { # <лог> <модуль> <первый-столбец-ERE>
  local log="$1" mod="$2" head="$3" quoted
  quoted=$(printf '%s' "$mod" | sed 's/[.[\*^$()+?{|]/\\&/g')
  grep -cE "^${head}[[:space:]]+${quoted}(/|[[:space:]])" "$log" 2>/dev/null || true
}

count_marks() { # <лог> <маркер>
  grep -c -- "$2" "$1" 2>/dev/null || true
}

# ─── вердикт ────────────────────────────────────────────────────────────────
classify() {
  local -a mods=() named=() logs=() rcs=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --lane)
        if [ $# -lt 5 ]; then
          echo "полосе нужны четыре величины: модуль, заявлено, лог, код возврата" >&2
          return 2
        fi
        mods+=("$2"); named+=("$3"); logs+=("$4"); rcs+=("$5"); shift 5 ;;
      *) usage; return 2 ;;
    esac
  done

  if [ "${#mods[@]}" -eq 0 ]; then
    echo "полос не задано — судить нечего, а молчание такой проверки" >&2
    echo "неотличимо от согласия." >&2
    return 2
  fi

  local findings=0 i total_named=0 total_reported=0 total_pass=0
  for i in "${!mods[@]}"; do
    local mod="${mods[$i]}" want="${named[$i]}" log="${logs[$i]}" rc="${rcs[$i]}"

    if ! [ -f "$log" ]; then
      echo "полоса ${mod}: лога ${log} нет — прогон не состоялся, и это НЕ зелёное" >&2
      findings=$((findings + 1))
      continue
    fi

    local okpkg failpkg notestpkg reported pass skip failed
    okpkg=$(lane_reported "$log" "$mod" 'ok')
    failpkg=$(lane_reported "$log" "$mod" 'FAIL')
    notestpkg=$(lane_reported "$log" "$mod" '\?')
    reported=$((okpkg + failpkg + notestpkg))
    pass=$(count_marks "$log" '--- PASS')
    skip=$(count_marks "$log" '--- SKIP')
    failed=$(count_marks "$log" '--- FAIL')

    total_named=$((total_named + want))
    total_reported=$((total_reported + reported))
    total_pass=$((total_pass + pass))

    echo "перепись полосы ${mod}: заявлено ${want}, отчиталось ${reported}" \
         "(ok ${okpkg}, FAIL ${failpkg}, без проб ${notestpkg});" \
         "утверждений пройдено ${pass}, пропущено ${skip}, упало ${failed};" \
         "код go test ${rc}"

    if [ "$want" -eq 0 ]; then
      echo "полоса ${mod}: перечень пуст — цель перестала проверять целый модуль," >&2
      echo "  и это неотличимо от успеха." >&2
      findings=$((findings + 1))
    fi
    if [ "$rc" -ne 0 ]; then
      echo "полоса ${mod}: go test вышел кодом ${rc} — вердикт полосы недействителен" >&2
      findings=$((findings + 1))
    fi
    if [ "$failed" -gt 0 ] || [ "$failpkg" -gt 0 ]; then
      echo "полоса ${mod}: упавших утверждений ${failed}, упавших пакетов ${failpkg}" >&2
      findings=$((findings + 1))
    fi
    if [ "$skip" -gt 0 ]; then
      echo "полоса ${mod}: пропущено ${skip} проб. Пропуск здесь — ОТКАЗ: пробу," >&2
      echo "  которая не выполнилась, нельзя засчитать выполненной, а именно ради" >&2
      echo "  невозможности такого зачёта эта цель и заведена." >&2
      findings=$((findings + 1))
    fi
    if [ "$notestpkg" -gt 0 ]; then
      echo "полоса ${mod}: пакетов без проб ${notestpkg} — перечень называет пакет," >&2
      echo "  в котором исполнять нечего; его \`?\` неотличим от пройденного." >&2
      findings=$((findings + 1))
    fi
    if [ "$pass" -eq 0 ]; then
      echo "полоса ${mod}: ноль пройденных утверждений — полоса отработала вхолостую" >&2
      findings=$((findings + 1))
    fi
    if [ "$reported" -ne "$want" ]; then
      echo "полоса ${mod}: отчиталось ${reported} пакетов из ${want} заявленных —" >&2
      echo "  часть перечня не дошла до прогона, и её молчание неотличимо от успеха." >&2
      findings=$((findings + 1))
    fi
  done

  echo "перепись: полос ${#mods[@]}, пакетов отчиталось ${total_reported} из ${total_named};" \
       "утверждений пройдено ${total_pass}; находок ${findings}"
  [ "$findings" -eq 0 ] || return 1
  return 0
}

# ─── самопроверка: инъекция в обе стороны по каждой оси ─────────────────────
self_test() {
  local tmp; tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' RETURN
  local probes=0 bad=0

  mk() { # mk <файл> <модуль> <пакетов-ok> <PASS> [SKIP] [FAIL] [?пакетов] [FAILпакетов]
    local f="$1" mod="$2" n="$3" p="$4" s="${5:-0}" fl="${6:-0}" q="${7:-0}" fp="${8:-0}" k
    : > "$f"
    for ((k = 0; k < p; k++)); do echo "--- PASS: TestX$k (0.00s)" >> "$f"; done
    for ((k = 0; k < s; k++)); do echo "--- SKIP: TestS$k (0.00s)" >> "$f"; done
    for ((k = 0; k < fl; k++)); do echo "--- FAIL: TestF$k (0.00s)" >> "$f"; done
    for ((k = 0; k < n; k++)); do printf 'ok  \t%s/pkg%d\t0.1s\n' "$mod" "$k" >> "$f"; done
    for ((k = 0; k < q; k++)); do printf '?   \t%s/nq%d\t[no test files]\n' "$mod" "$k" >> "$f"; done
    for ((k = 0; k < fp; k++)); do printf 'FAIL\t%s/bad%d\t[build failed]\n' "$mod" "$k" >> "$f"; done
  }

  run() { # run <ожидаемый-код> <имя> <аргументы…>
    local want="$1" name="$2"; shift 2
    local got=0 out
    probes=$((probes + 1))
    out="$(classify "$@" 2>&1)" || got=$?
    if [ "$got" -ne "$want" ]; then
      echo "  ПРОВАЛ $name — ждали код $want, получили $got" >&2
      printf '%s\n' "$out" | sed 's/^/      /' >&2
      bad=$((bad + 1)); return
    fi
    echo "  ok   $name (код $got)"
  }

  local A=github.com/PRO-Robotech/kacho
  local B=github.com/PRO-Robotech/kaname

  echo "=== перепись по полосам: обе стороны по каждой оси ==="

  # Положительный контроль. Две полосы, РАЗНЫЕ модульные пути — форма, на которой
  # прежний распознаватель терял вторую половину целиком.
  mk "$tmp/a" "$A" 10 120
  mk "$tmp/b" "$B" 14 1500
  run 0 "две полосы разных модулей — зелено" \
      --lane "$A" 10 "$tmp/a" 0 --lane "$B" 14 "$tmp/b" 0

  # Ось «распознаватель знает не все модульные пути». Именно этот дефект и
  # наблюдался: полоса iam отчиталась целиком, а перепись её не увидела.
  run 1 "полосу судят ЧУЖИМ модульным путём — находка" \
      --lane "$A" 10 "$tmp/a" 0 --lane "$A" 14 "$tmp/b" 0

  # Ось «полоса отчиталась нулём, а СУММА сошлась». Прежний общий счёт это гасил:
  # 24 из 24 сходилось, хотя одна полоса не отчиталась ни одним пакетом.
  # У полосы B нарочно НЕнулевые утверждения — иначе находку дала бы ось «полоса
  # вхолостую», и ось счёта осталась бы недоказанной.
  mk "$tmp/all24" "$A" 24 1620
  mk "$tmp/none" "$B" 0 5
  run 1 "сумма сходится, но полоса пуста — находка" \
      --lane "$A" 10 "$tmp/all24" 0 --lane "$B" 14 "$tmp/none" 0

  # Ось «пропуск = отказ» и её законный близнец.
  mk "$tmp/skip" "$A" 10 100 1
  run 1 "пропущенная проба — находка" --lane "$A" 10 "$tmp/skip" 0
  run 0 "тот же лог без пропуска — молчит" --lane "$A" 10 "$tmp/a" 0

  # Ось «упавшее утверждение».
  mk "$tmp/fail" "$A" 10 100 0 1
  run 1 "упавшее утверждение — находка" --lane "$A" 10 "$tmp/fail" 0

  # Ось «пакет не собрался»: `FAIL … [build failed]` не даёт НИ ОДНОГО `--- FAIL`,
  # поэтому счёт утверждений его не видит, а счёт пакетов — видит.
  mk "$tmp/build" "$A" 9 100 0 0 0 1
  run 1 "пакет не собрался — находка, хотя упавших утверждений ноль" \
      --lane "$A" 10 "$tmp/build" 0

  # Ось «пакет без проб».
  mk "$tmp/notests" "$A" 9 100 0 0 1
  run 1 "пакет без проб — находка" --lane "$A" 10 "$tmp/notests" 0

  # Ось «ненулевой код go test при внешне целом логе».
  run 1 "ненулевой код go test — находка" --lane "$A" 10 "$tmp/a" 2

  # Ось «полоса вхолостую»: пакеты отчитались, утверждений ноль.
  mk "$tmp/hollow" "$A" 10 0
  run 1 "ноль пройденных утверждений — находка" --lane "$A" 10 "$tmp/hollow" 0

  # Ось «недостача пакетов» и её законный близнец.
  mk "$tmp/short" "$A" 9 100
  run 1 "отчиталось меньше заявленного — находка" --lane "$A" 10 "$tmp/short" 0

  # Ось «перечень пуст».
  run 1 "заявлено ноль — находка" --lane "$A" 0 "$tmp/none" 0

  # Ось «лога нет»: прогон не состоялся, и это не зелёное.
  run 1 "лога нет — находка" --lane "$A" 10 "$tmp/no-such-log" 0

  # Ось «границы модуля»: путь одной полосы — префикс другой. Без границы
  # чужие строки считались бы своими.
  mk "$tmp/pref" "github.com/PRO-Robotech/ka" 10 100
  run 1 "префикс чужого модуля не засчитывается — находка" \
      --lane "github.com/PRO-Robotech/kacho" 10 "$tmp/pref" 0

  # Пакет, совпадающий с КОРНЕМ модуля, отделяется пробелом, а не косой чертой.
  { printf 'ok  \t%s\t0.1s\n' "$A"; echo '--- PASS: TestRoot (0.00s)'; } > "$tmp/root"
  run 0 "пакет-корень модуля засчитан — молчит" --lane "$A" 1 "$tmp/root" 0

  # Негодный вызов — код 2, а не 0 и не 1.
  run 2 "полос не задано — негодный вызов" 

  echo "=== проб ${probes}, провалов ${bad} ==="
  # Ноль исполненных проб — НЕ чистота: код 2, потому что доказательства нет
  # вовсе. Провал доказательства — код 1: это находка о самом гейте, и
  # прогонщик самопроверок дерева читает эти два кода по-разному.
  [ "$probes" -gt 0 ] || return 2
  [ "$bad" -eq 0 ] || return 1
  return 0
}

if [ "${1:-}" = "--self-test" ]; then
  st=0; self_test || st=$?
  case "$st" in
    0) echo "PASS: classify-pg-outside-selection --self-test"; exit 0 ;;
    2) echo "ПРОВАЛ: ни одной пробы не исполнено" >&2
       echo "FAIL: classify-pg-outside-selection --self-test" >&2; exit 2 ;;
    *) echo "FAIL: classify-pg-outside-selection --self-test" >&2; exit 1 ;;
  esac
fi

classify "$@"
