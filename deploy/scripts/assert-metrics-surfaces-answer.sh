# assert-metrics-surfaces-answer — доказать, что диагностическая поверхность
# КАЖДОГО процесса платформы отвечает, а не только объявлена.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЭТОТ ГЕЙТ УТВЕРЖДАЕТ, А ЧТО НЕТ
#
# Утверждает: по адресу пода `GET /metrics` отвечает `200`, тело — текстовая
# экспозиция, и в нём есть хотя бы одна серия платформы (`kacho_…`). Плюс
# перепись: сколько процессов опрошено.
#
# НЕ утверждает: что величины кто-то читает регулярно. Агента сбора в умбрелле
# нет, и это записано открытым долгом, а не замолчано. Пока он не появится,
# «ноль доставленных величин за всю жизнь поверхности» заметно только тому, кто
# пришёл смотреть.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ОБРАЩЕНИЕМ, А НЕ ЧТЕНИЕМ ЧАРТА
#
# `containerPort` — информационное поле: порт привязывает процесс, и привязывает
# его по своей конфигурации. Замер, считавший объявления, дал «поверхность
# поднимают четверо» там, где их поднимают семеро. Утверждение «поверхность
# поднята» доказывается ОБРАЩЕНИЕМ к ней; объявление отвечает на другой вопрос —
# «кто про неё знает», — и его проверяет декларативная проверка дерева
# `TestEveryRenderedChartDeclaresItsScrape`.
#
# ─────────────────────────────────────────────────────────────────────────────
# ТРИ ИСХОДА, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА
#
#   * зелёный — все опрошенные ответили;
#   * красный — процесс ответил не тем (не 200, не экспозиция, нет серий);
#   * «не выполнилось» — до процесса не дошёл сам опрос (пода нет, кластер не
#     отвечает, нечем выполнить запрос). Такой процесс печатается ОТДЕЛЬНО, и
#     вердикта нет ни у одного утверждения о нём.
#
# Перепись обязательна: «ноль находок» на пустом перечне процессов было бы
# зелёным и не значило бы ничего.
#
# ─────────────────────────────────────────────────────────────────────────────
# СХЕМА — ЧАСТЬ АДРЕСА, И ОНА ЧИТАЕТСЯ ИЗ ТОГО ЖЕ ОБЪЯВЛЕНИЯ, ЧТО И ПОРТ
#
# Прежняя редакция брала из объявления сбора ТОЛЬКО порт, а схему выписывала
# открытым текстом (`grep -c scheme` по этому файлу давал ноль). Процесс, чья
# поверхность работает под TLS, был гейту недоступен BY CONSTRUCTION: обращение
# открытым текстом к слушателю под TLS ответа не даёт, и поверхность попадала в
# «опрос не выполнился» — то есть гейт не выносил о ней вердикта, при том что
# она отвечает.
#
# Предмет стал наблюдаемым, а не гипотетическим: служба управления доступом
# объявляет `prometheus.io/scheme` от той же ручки, что поднимает транспорт
# слушателя, и на боевых профилях он `https`.
#
# СХЕМА НЕ ВЫВОДИТСЯ НИ ИЗ ЧЕГО ДРУГОГО — ни из приставки имени, ни из номера
# порта: номер не объявление, и слушатель меняет транспорт, номера не меняя.
# Незаданная аннотация означает `http` — это умолчание САМОГО объявления сбора
# (агент, аннотации не нашедший, идёт открытым текстом), и гейт его ПЕЧАТАЕТ, а
# не подставляет молча: перепись называет, скольких он опрашивал каждой схемой и
# скольким схема досталась умолчанием. Значение вне пары http|https — КРАСНОЕ с
# именем процесса: по такому адресу не придёт и агент.
#
# ЧЕГО ГЕЙТ ПРИ ЭТОМ НЕ УТВЕРЖДАЕТ — сказано прямо, потому что это ОСЛАБЛЕНИЕ.
# По схеме `https` сертификат сервера НЕ ПРОВЕРЯЕТСЯ (`curl --insecure`).
# Причина: опросчик — свой под, поднятый `kubectl run`, и корней доверия
# внутреннего центра в нём не смонтировано; монтировать их значило бы знать имя
# секрета каждого стенда, то есть завести второе объявление о посадке. Предмет
# этого гейта — «поверхность ОТВЕЧАЕТ и несёт свои ряды», а не «цепочка
# сертификата верна»; посадку транспорта утверждает `assert-production-posture.sh`
# по строке `boot security posture` самого процесса. Ослабление объявлено здесь и
# ПЕЧАТАЕТСЯ переписью в каждом прогоне, где по https опрошен хоть кто-то.
set -euo pipefail

# any_line_matches <многострочное значение> <ERE> — как `grep -qE`: истинно, если
# ХОТЬ ОДНА строка значения совпадает с выражением. Построчность важна: у `grep`
# точка не переходит через перевод строки, а у `[[ =~ ]]` на всём значении —
# переходит. Труба убрана из-за ложного отказа на совпадении (задача #658).
any_line_matches() {
  local _l
  while IFS= read -r _l; do
    if [[ "$_l" =~ $2 ]]; then return 0; fi
  done <<<"$1"
  return 1
}

NS="${KACHO_NS:-kacho}"

# ИМЕНА ЧАСТЕЙ ПРОДУКТА — ОДИН ИСТОЧНИК НА ВСЁ ДЕРЕВО.
#
# Читатель подключается по МЕСТУ ЭТОГО ФАЙЛА, а не относительно текущего
# каталога: гейт зовут и из `deploy/`, и из корня.
#
# PRODUCT_NAME — ответы источника, разложенные по процессам. Заполняется ОДИН
# раз (load_product_names ниже) и читается формами метки и приставкой рядов.
# shellcheck source=deploy/scripts/lib/product-names.sh
. "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lib/product-names.sh"
declare -A PRODUCT_NAME=()

# load_product_names ПРОЦЕСС… — спросить у источника имя каждого процесса.
#
# Отказ ГРОМКИЙ и это код 2, а не 1: не зная имени части, гейт не знает, какой
# под спрашивать, — то есть не выносит вердикта ни об одной поверхности. Молча
# продолжить с выводом по приставке значило бы вернуть ровно ту слепоту, ради
# снятия которой источник заведён.
load_product_names() {
  product_names_load "$@" || {
    echo "НЕ ВЫПОЛНИЛОСЬ: имена частей продукта не прочитаны — неизвестно, какой под чей."
    echo "Вердикта нет ни у одного процесса: это не зелёный и не красный исход."
    exit 2
  }
  local p
  for p in "$@"; do
    PRODUCT_NAME["$p"]="$(product_image_name "$p")" || exit 2
  done
}

# ─────────────────────────────────────────────────────────────────────────────
# САМОПРОВЕРКА: доказать, что гейт умеет краснеть на дефекте и молчать на
# законной конструкции той же формы.
#
# Предмет доказательства — РЕЗОЛВ ПОДА, а не текст скрипта: гейт восемь ночей
# подряд выходил «НЕ ВЫПОЛНИЛОСЬ» именно потому, что селектор не резолвился, и
# ни одна проверка этого не ловила. Заглушка отвечает МЕТКАМИ ЖИВОГО СТЕНДА
# (замер в шапке selector_candidates), поэтому «зелёный на заглушке» означает
# «зелёный на том, что реально развёрнуто», а не на удобной выдумке.
#
# Пять случаев, и три из них — контроль в обратную сторону:
#   1. стенд как живой                     → зелёный, опрошены ВСЕ процессы;
#   2. поды только с формой app.k8s.io/name (как гейт думал) → «не выполнилось»;
#   3. кластера нет вовсе                  → «не выполнилось», НЕ красное;
#   4. поверхность отвечает 500            → КРАСНОЕ (это уже вердикт);
#   5. поверхность отвечает 200 без серий  → КРАСНОЕ.
# Случай 2 — тот самый дефект: без него самопроверка зеленела бы и на прежнем
# селекторе, то есть не доказывала бы ничего.
#
# ОСЬ СХЕМЫ — случаи 7–9, и они устроены как ОДНО-ФАКТНАЯ тройка вокруг одного
# и того же пода с ЖИВЫМ слушателем под TLS:
#   7. объявлено `https`, слушатель под TLS → зелёный (законный близнец);
#   8. объявление снято, слушатель тот же   → КРАСНОЕ с именем процесса;
#   9. объявлена схема вне пары http|https  → КРАСНОЕ с именем процесса.
# Между 7 и 8 различие РОВНО ОДНО — что объявляет аннотация; транспорт слушателя
# в обоих случаях TLS. Без 7 красное восьмёрки не доказывало бы ничего:
# покраснеть могло бы от чего угодно в опросе. Без 8 зелёное семёрки не
# доказывало бы, что схема ЧИТАЕТСЯ, — гейт, выписавший `https` открытым
# текстом, дал бы то же зелёное. Поверхность открытым текстом остаётся
# опознанной случаем 1, где схему не объявляет никто.
self_test() {
  local root tmp rc out fails=0
  root="$(repo_root)"
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' RETURN
  mkdir -p "$tmp/bin"

  cat >"$tmp/bin/kubectl" <<'STUB'
#!/usr/bin/env bash
# Заглушка kubectl для самопроверки. Знает ровно то, что знает живой стенд:
# какие метки у каких подов, и что отвечает поверхность.
sel=""; want_exec=0
args=("$@")
for ((i=0; i<${#args[@]}; i++)); do
  case "${args[$i]}" in
    -l)   sel="${args[$((i+1))]}" ;;
    exec) want_exec=1 ;;
  esac
done

# Поднятие пробника: в режиме none кластера нет — `wait` отказывает, и гейт
# обязан назвать это «условие не создано», а не вердиктом о поверхностях.
case "${1:-}" in
  run)
    [[ "${STUB_MODE:-live}" == none ]] && exit 1
    exit 0 ;;
  wait)
    [[ "${STUB_MODE:-live}" == none ]] && exit 1
    exit 0 ;;
  delete) exit 0 ;;
esac
for a in "$@"; do
  case "$a" in
    run|wait|delete)
      [[ "${STUB_MODE:-live}" == none ]] && exit 1
      exit 0 ;;
  esac
done

if [[ "$want_exec" == 1 ]]; then
  # Приставка рядов у КАЖДОГО процесса СВОЯ — так объявлено в дереве, и заглушка
  # обязана быть не снисходительнее продукта. Прежняя редакция отдавала одну
  # `kacho_build_info` всем восьми; такого ряда на стенде нет ни у кого, и
  # проверка рядов на этой заглушке не могла покраснеть ни при каком имени.
  url=""
  for a in "${args[@]}"; do case "$a" in http://*|https://*) url="$a" ;; esac; done
  hostport="${url#*://}"; ip="${hostport%%:*}"
  # ТРАНСПОРТ СЛУШАТЕЛЯ — свойство пода, а не объявления. У пода службы доступа
  # им управляет STUB_LISTENER_KANAME, у остальных он открытый текст. Два знания
  # разведены НАМЕРЕННО: только так «объявлено одно, поднято другое» становится
  # представимым — то есть только так инъекция по оси схемы вообще возможна.
  listener=plain
  [[ "$ip" == 10.0.0.4 ]] && listener="${STUB_LISTENER_KANAME:-plain}"
  reachable=http
  [[ "$listener" == tls ]] && reachable=https
  if [[ "$url" != "$reachable://"* ]]; then
    # Ровно то, что печатает curl, пришедший не той схемой: тела нет, код 000.
    printf '\n000\n'
    exit 0
  fi
  case "$ip" in
    10.0.0.1) ns=kacho_api_gateway ;;
    10.0.0.2) ns=kacho_compute ;;
    10.0.0.3) ns=kacho_registry ;;
    10.0.0.4) ns=kaname ;;
    10.0.0.5) ns=kacho_nlb ;;
    10.0.0.6) ns=kacho_vpc ;;
    10.0.0.7) ns=kacho_geo ;;
    10.0.0.8) ns=kacho_storage ;;
    *)        ns=kacho_unknown ;;
  esac
  case "${STUB_SURFACE:-ok}" in
    ok)           printf '%s_build_info{service="x"} 1\n200\n' "$ns" ;;
    http500)      printf 'nope\n500\n' ;;
    noseries)     printf 'go_goroutines 12\n200\n' ;;
    # Внесённый дефект: поверхность несёт ТОЛЬКО приставку платформы — то есть
    # ровно то, что гейт считал признаком до появления второго имени продукта.
    platformonly) printf 'kacho_build_info{service="x"} 1\n200\n' ;;
  esac
  exit 0
fi

# Таблица меток. LIVE — как на стенде; NARROW — только форма app.k8s.io/name
# (ей отвечают лишь iam и nlb, края среди них нет); NONE — кластера нет.
#
# Поля разделены `|`, как их и спрашивает гейт: пустое поле схемы обязано
# доехать пустым, а не схлопнуться с соседним. Схему объявляет только под службы
# доступа — ровно как в дереве, где `prometheus.io/scheme` несёт один чарт.
kaname_row="kaname-1|10.0.0.4|9102|${STUB_SCHEME_KANAME:-}"
case "${STUB_MODE:-live}" in
  none) exit 0 ;;
  narrow)
    case "$sel" in
      app.kubernetes.io/name=kaname)    echo "$kaname_row" ;;
      app.kubernetes.io/name=kacho-nlb) echo "kacho-nlb-1|10.0.0.5|9102|" ;;
      *) : ;;
    esac ;;
  live)
    case "$sel" in
      app=api-gateway)                  echo "api-gateway-1|10.0.0.1|9102|" ;;
      app=compute)                      echo "compute-1|10.0.0.2|9102|" ;;
      app=registry)                     echo "registry-1|10.0.0.3|9102|" ;;
      app=vpc)                          echo "vpc-1|10.0.0.6|9102|" ;;
      app=kacho-geo)                    echo "geo-1|10.0.0.7|9102|" ;;
      app=kacho-storage)                echo "storage-1|10.0.0.8|9102|" ;;
      app.kubernetes.io/name=kaname)    echo "$kaname_row" ;;
      app.kubernetes.io/name=kacho-nlb) echo "kacho-nlb-1|10.0.0.5|9102|" ;;
      *) : ;;
    esac ;;
esac
exit 0
STUB
  chmod +x "$tmp/bin/kubectl"

  run_case() {  # <имя> <ожидаемый код> <обязательная подстрока> <env…>
    local name="$1" want="$2" needle="$3"; shift 3
    out="$(cd "$root" && env PATH="$tmp/bin:$PATH" "$@" bash "$root/deploy/scripts/assert-metrics-surfaces-answer.sh" 2>&1)" && rc=0 || rc=$?
    # Сравнение БЕЗ внешнего процесса: `grep -q` выходит до конца входа, писатель
    # слева получает SIGPIPE, и под `pipefail` найденное объявляется ненайденным
    # (задача #658). Держит это гейт `TestPipefailVerdictNeverComesFromAPipe` —
    # он и поймал эту строку в первой редакции самопроверки.
    if [[ "$rc" == "$want" && "$out" == *"$needle"* ]]; then
      echo "  ОК  $name (ждали код $want и «$needle», получили код $rc)"
    else
      echo "  ПРОВАЛ  $name: ждали код $want и «$needle», получили код $rc"
      printf '%s\n' "$out" | sed 's/^/        /' | tail -12
      fails=$((fails + 1))
    fi
  }

  echo "== самопроверка гейта поверхностей величин =="
  run_case "стенд как живой → зелёный, опрошены все" \
           0 "все 8 поверхностей отвечают" STUB_MODE=live
  # Тот самый дефект, ради которого перебор форм и заведён: на стенде, где поды
  # помечены ТОЛЬКО рекомендованной схемой, резолвится меньшинство. Пробник свой
  # и поднимается всегда, поэтому исход теперь другой — «поды не найдены», а не
  # «опросчика нет», — но третьей категорией он остаётся: вердикта о поверхностях
  # не вынесено ни одного.
  run_case "поды только с формой app.kubernetes.io/name → опрос не выполнился" \
           2 "под не найден" STUB_MODE=narrow
  run_case "кластера нет → не выполнилось, а НЕ красное" \
           2 "под-пробник не поднялся" STUB_MODE=none
  run_case "поверхность отвечает 500 → красное" \
           1 "вместо 200" STUB_MODE=live STUB_SURFACE=http500
  run_case "200 без единого ряда продукта → красное" \
           1 "ни одной серии kacho_api_gateway_" STUB_MODE=live STUB_SURFACE=noseries
  # Внесённый дефект по ВТОРОЙ оси того же класса: поверхность несёт приставку
  # платформы, а часть со своим именем продукта её не несёт и нести не должна.
  # Имя в ожидании ВЫПИСАНО намеренно: сверяй мы его производной самого гейта,
  # утверждение сравнивало бы гейт с самим собой и было бы пустым.
  run_case "ряды только с приставкой платформы → красное у части со СВОИМ именем" \
           1 "iam: ответ 200, но ни одной серии kaname_" STUB_MODE=live STUB_SURFACE=platformonly

  # ── ось схемы ────────────────────────────────────────────────────────────
  run_case "слушатель под TLS, объявлено https → зелёный (законный близнец)" \
           0 "все 8 поверхностей отвечают" \
           STUB_MODE=live STUB_LISTENER_KANAME=tls STUB_SCHEME_KANAME=https
  run_case "тот же слушатель под TLS, объявление снято → красное с именем процесса" \
           1 "iam: ответ 000 вместо 200 по адресу http://" \
           STUB_MODE=live STUB_LISTENER_KANAME=tls
  run_case "схема вне пары http|https → красное с именем процесса" \
           1 "iam: объявление сбора называет схему 'ftp'" \
           STUB_MODE=live STUB_SCHEME_KANAME=ftp

  echo "утверждений проверено: 9, провалов: $fails"
  [[ "$fails" -eq 0 ]]
}


# ПЕРЕЧЕНЬ ВЫВОДИТСЯ ИЗ ДЕРЕВА, а не выписывается здесь: процесс, чей
# композиционный корень несёт обработчик экспозиции, попадает под опрос в момент
# появления обработчика — без правки этого файла.
#
# Тот же предикат, что у декларативной проверки: обе формы записи маршрута
# обязательны — шесть процессов пишут `Handle("GET /metrics"`, iam —
# `Handle("/metrics"`. Предикат по одной форме дал бы шесть и объявил бы iam
# беспредметным.
repo_root() { git rev-parse --show-toplevel; }

processes_with_a_surface() {
  local root; root="$(repo_root)"
  git -C "$root" grep -lE 'Handle\("(GET )?/metrics"' -- \
      'services/*/cmd/**' 'gateway/cmd/**' ':!*_test.go' \
    | sed -E 's#^services/([^/]+)/.*#\1#; s#^gateway/.*#api-gateway#' \
    | sort -u
}

# selector_candidates — ФОРМЫ метки, которыми чарты платформы помечают под
# процесса. Их три, и это факт дерева, а не вкус: чарты разошлись по способу
# именования, и селектор в одной форме резолвит МЕНЬШИНСТВО подов.
#
# Замер на живом стенде (kind-kacho, ns=kacho, 2026-08-22) — восемь процессов
# с поверхностью, по каждому спрошены все три формы:
#
#   процесс      app.kubernetes.io/name   app=<имя>   app=kacho-<имя>
#   api-gateway            0                  1              0
#   compute                0                  1              0
#   geo                    0                  0              1
#   iam                    3                  0              3
#   nlb                    1                  0              1
#   registry               0                  1              0
#   storage                0                  0              1
#   vpc                    0                  1              0
#
# То есть форма `app.kubernetes.io/name` резолвит ДВА процесса из восьми, и
# именно на ней гейт стоял. Опросчик (край) в неё не попадает вовсе, поэтому
# гейт выходил «НЕ ВЫПОЛНИЛОСЬ» ещё до первого опроса — восемь ночных прогонов
# подряд (задача #957).
#
# ПОЧЕМУ ПЕРЕБОР, А НЕ ОДНА ВЕРНАЯ ФОРМА. Одна форма означала бы, что гейт
# знает раскладку меток лучше чартов; он её не знает и знать не должен —
# метку объявляет чарт. Перебор спрашивает кластер и печатает, ЧЕМ резолвился
# каждый процесс, поэтому расхождение меток остаётся ВИДНЫМ, а не замазанным.
# Единообразие меток — предмет отдельной задачи #1007, а не этого гейта.
#
# ИМЯ ЧАСТИ СПРАШИВАЕТСЯ У ИСТОЧНИКА, А НЕ ВЫВОДИТСЯ ПРИСТАВКОЙ.
#
# Прежняя редакция собирала форму как `kacho-<каталог>`. Вывод был верен, пока
# имя платформы было и именем каждой её части; служба управления доступом
# получила СВОЁ имя продукта — и все три её формы стали спрашивать про под,
# которого на стенде нет. Исход при этом не красный и не зелёный, а «опрос не
# выполнился»: гейт не выносил о ней вердикта вовсе, и перепись честно печатала
# «ответили 7 из 8».
#
# Слова второго имени здесь нет ни разу — оно приезжает ответом источника.
selector_candidates() {
  local process="$1" product="${PRODUCT_NAME[$1]}"
  printf '%s\n' "app.kubernetes.io/name=$product" \
                "app=$product" \
                "app=$process"
  # У края чарт помечает под ГОЛЫМ именем — форма, которой у прочих нет. Она
  # ДОБАВЛЯЕТСЯ к общим, а не заменяет их: снять её значило бы сузить перебор,
  # а перебор здесь и есть то место, где расхождение меток остаётся видимым.
  [[ "$process" == api-gateway ]] && printf '%s\n' "app.kubernetes.io/name=$process"
  return 0
}

# series_prefix <процесс> — приставка имён рядов, которые эта поверхность обязана
# нести. Производится из ТОГО ЖЕ имени, что и метка пода: `vpc` → `kacho_vpc`,
# `api-gateway` → `kacho_api_gateway`, служба доступа — своим именем продукта.
#
# ЗАЧЕМ ПОПРОЦЕССНО, А НЕ ОДНОЙ ПРИСТАВКОЙ ПЛАТФОРМЫ. Прежняя редакция искала
# `^kacho_` у всех восьми. Замер по дереву: КАЖДЫЙ процесс называет свои ряды
# своим именем (`kacho_vpc_build_info`, `kacho_api_gateway_build_info`, …), а у
# службы доступа рядов с приставкой платформы НЕТ НИ ОДНОГО — её константа имён
# объявляет собственное имя продукта. То есть на поднятом стенде общий предикат
# объявил бы её поверхность пустой при живых величинах на ней.
#
# Разделитель здесь `_`, потому что имя ряда Prometheus дефиса не допускает.
# Владелец этого соответствия — `productnaming.MetricNamespace`; здесь оно только
# переносится на уже полученное имя, а не толкуется заново.
series_prefix() {
  printf '%s_' "${PRODUCT_NAME[$1]//-/_}"
}

# resolve_pod <процесс> — печатает «селектор<TAB>имя<TAB>ip<TAB>порт<TAB>схема»
# у первой формы, которая дала под. Пусто — ни одна форма не резолвится.
#
# Все поля берутся ОДНИМ обращением на форму: спрашивать их по отдельности
# значит допустить, что между запросами под сменится, и получить ip одного
# экземпляра с портом другого. Схема — такое же поле объявления сбора, как порт,
# и берётся тем же обращением по той же причине.
#
# РАЗДЕЛИТЕЛЬ — `|`, А НЕ ПРОБЕЛ, И ЭТО НЕ ОФОРМЛЕНИЕ. Незаданная аннотация даёт
# ПУСТОЕ поле; при разборе по пробелам пустое поле схлопывается, и значение
# СЛЕДУЮЩЕГО поля молча занимает место предыдущего — незаданный порт при
# заданной схеме дал бы «порт = https». Пустое поле обязано означать «пусто».
resolve_pod() {
  local process="$1" sel line
  while read -r sel; do
    [[ -n "$sel" ]] || continue
    line="$(kubectl -n "$NS" get pods -l "$sel" \
      -o jsonpath='{.items[0].metadata.name}|{.items[0].status.podIP}|{.items[0].metadata.annotations.prometheus\.io/port}|{.items[0].metadata.annotations.prometheus\.io/scheme}' \
      2>/dev/null || true)"
    local name ip port scheme
    IFS='|' read -r name ip port scheme <<<"$line"
    if [[ -n "${name:-}" && -n "${ip:-}" ]]; then
      printf '%s\t%s\t%s\t%s\t%s\n' "$sel" "$name" "$ip" "${port:-}" "${scheme:-}"
      return 0
    fi
  done < <(selector_candidates "$process")
  return 0
}

expected=0
answered=0
failed=0
# Оси схемы. Считаются ПОПЫТКИ опроса, а не удачи: вопрос «скольких он опрашивал
# каждой схемой» — про адрес, по которому гейт пошёл, а не про то, чем ответили.
by_http=0
by_https=0
scheme_defaulted=0
not_run=0
declare -a red=() unknown=()

PROBE_IMAGE="${PROBE_IMAGE:-docker.io/alpine/k8s:1.36.2}"
PROBE_POD="kacho-metrics-probe-$$"

probe_pod=""
probe_ready=0

# start_probe — поднять СВОЙ под с инструментом опроса.
#
# ПОЧЕМУ НЕ `kubectl exec` В ПОД ПРОДУКТА. Именно так гейт и работал, и опрос
# отвечал «нечем или некуда» по ВСЕМ восьми процессам — то есть гейт не выносил
# вердикта ни разу, сколько бы поверхностей ни отвечало на самом деле.
#
# Точная причина названа замером, а не догадкой: в образе края `curl` нет, а
# `wget` есть. То есть «инструмента нет» верно ровно для того инструмента,
# который гейт звал, и зависит от того, что попало в образ, — а это меняется
# правкой Dockerfile, о которой гейт не узнает.
#
# Пробник снимает зависимость от содержимого чужого образа: инструмент есть
# потому, что мы его принесли. Заодно «проверка работает» перестаёт быть
# неотличимым от «в образе края случайно остался curl».
#
# Опрос по-прежнему ИЗНУТРИ кластера: поверхность выставлена только внутрь, и
# снаружи её не должно быть видно by construction.
start_probe() {
  kubectl -n "$NS" run "$PROBE_POD" \
    --image="$PROBE_IMAGE" --restart=Never --command -- sleep 600 >/dev/null 2>&1 || true
  if kubectl -n "$NS" wait --for=condition=Ready "pod/$PROBE_POD" --timeout=90s >/dev/null 2>&1; then
    probe_pod="$PROBE_POD"
    probe_ready=1
  fi
}

stop_probe() {
  [[ "$probe_ready" == 1 ]] || return 0
  kubectl -n "$NS" delete pod "$PROBE_POD" --wait=false >/dev/null 2>&1 || true
}
trap stop_probe EXIT

if [[ "${1:-}" == "--self-test" ]]; then
  self_test
  exit $?
fi

echo "== диагностические поверхности: опрос изнутри кластера (ns=$NS) =="
start_probe
[[ -n "$probe_pod" ]] && echo "  опросчик: под-пробник $probe_pod (образ $PROBE_IMAGE)"
if [[ -z "$probe_pod" ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ: под-пробник не поднялся в ns=$NS за 90 с."
  echo "Образ: $PROBE_IMAGE. Кластер недоступен либо образ не тянется — это"
  echo "условие прогона, а не вердикт о поверхностях."
  echo "Вердикта нет ни у одного процесса — это не зелёный и не красный исход."
  exit 2
fi

# Перечень берётся ОДИН раз: он нужен дважды — загрузить имена и обойти. Второй
# вызов обхода дерева мог бы ответить иначе, и тогда имена загружались бы не для
# тех процессов, которые опрашиваются.
PROCESSES="$(processes_with_a_surface)"
if [[ -n "$PROCESSES" ]]; then
  # перечень процессов передаётся отдельными словами — дробление намеренное.
  # Пояснение стоит ПЕРЕД директивой, а не после кода правила: токен, не имеющий
  # вида ключ=значение, обрывает разбор, и файл выпадает из-под проверки целиком.
  # shellcheck disable=SC2086
  load_product_names $PROCESSES
fi

while read -r process; do
  [[ -n "$process" ]] || continue
  expected=$((expected + 1))
  # Порт И СХЕМА берутся из ОБЪЯВЛЕНИЯ СБОРА этого же пода: аннотация и есть то
  # место, которое говорит собирателю, куда идти. Читая её, гейт проверяет ровно
  # тот адрес, по которому придёт агент, а не тот, который мы предполагаем.
  row="$(resolve_pod "$process")"
  sel="$(printf '%s' "$row" | cut -f1)"
  pod_ip="$(printf '%s' "$row" | cut -f3)"
  port="$(printf '%s' "$row" | cut -f4)"
  declared_scheme="$(printf '%s' "$row" | cut -f5)"
  if [[ -z "$pod_ip" || -z "$port" ]]; then
    not_run=$((not_run + 1))
    unknown+=("$process (под не найден либо объявления сбора у него нет: ip='$pod_ip' port='$port')")
    continue
  fi
  # Схема — из объявления; незаданная означает `http`, и это умолчание САМОГО
  # объявления сбора, а не наша подстановка: агент, аннотации не нашедший, идёт
  # открытым текстом. Умолчание ПЕЧАТАЕТСЯ и считается отдельно, поэтому
  # «объявлено http» отличимо от «не объявлено ничего».
  #
  # Третьего значения у схемы обращения не бывает, и «прочее» здесь не корзина:
  # по адресу, которого не существует, не придёт и агент — это вердикт о поде.
  case "$declared_scheme" in
    "")
      scheme=http; scheme_source="умолчание объявления сбора"
      scheme_defaulted=$((scheme_defaulted + 1)) ;;
    http|https)
      scheme="$declared_scheme"; scheme_source="объявлена" ;;
    *)
      failed=$((failed + 1))
      red+=("$process: объявление сбора называет схему '$declared_scheme' — обращения такой схемой не бывает, по этому адресу не придёт и агент")
      continue ;;
  esac
  if [[ "$scheme" == https ]]; then
    by_https=$((by_https + 1))
    # `--insecure` — ОБЪЯВЛЕННОЕ ослабление, разобранное в шапке (раздел «СХЕМА»):
    # корней доверия внутреннего центра в своём поде-пробнике не смонтировано, а
    # предмет этого гейта — «поверхность отвечает», не «цепочка верна». Перепись
    # называет ослабление в каждом прогоне, где оно применялось.
    body="$(kubectl -n "$NS" exec "$probe_pod" -- \
      curl -s --max-time 5 --insecure -w '\n%{http_code}' "https://$pod_ip:$port/metrics" 2>/dev/null || true)"
  else
    by_http=$((by_http + 1))
    body="$(kubectl -n "$NS" exec "$probe_pod" -- \
      curl -s --max-time 5 -w '\n%{http_code}' "http://$pod_ip:$port/metrics" 2>/dev/null || true)"
  fi
  if [[ -z "$body" ]]; then
    not_run=$((not_run + 1))
    unknown+=("$process (запрос не выполнился: нечем или некуда)")
    continue
  fi
  code="$(printf '%s' "$body" | tail -n1)"
  if [[ "$code" != "200" ]]; then
    failed=$((failed + 1))
    red+=("$process: ответ $code вместо 200 по адресу $scheme://$pod_ip:$port (схема — $scheme_source)")
    continue
  fi
  prefix="$(series_prefix "$process")"
  if ! any_line_matches "$body" "^$prefix"; then
    failed=$((failed + 1))
    red+=("$process: ответ 200, но ни одной серии $prefix — поверхность отвечает, а величин на ней нет")
    continue
  fi
  answered=$((answered + 1))
  # Селектор и СХЕМА печатаются ВСЕГДА: селектор — то место, где расхождение
  # меток чартов становится видимым, схема — то, где становится видимым
  # расхождение объявления сбора с транспортом слушателя.
  echo "  OK  $process → $scheme://$pod_ip:$port  (по метке $sel; схема — $scheme_source)"
done < <(printf '%s\n' "$PROCESSES")

echo
echo "перепись: процессов с поверхностью в дереве — $expected; ответили — $answered; " \
     "ответили не тем — $failed; опрос не выполнился — $not_run"
echo "  опрошены по схеме: http — $by_http (из них схема досталась умолчанием объявления — $scheme_defaulted); https — $by_https"
if [[ "$by_https" -gt 0 ]]; then
  echo "  по https сертификат сервера НЕ проверялся ($by_https шт.) — объявленное ослабление,"
  echo "  разобранное в шапке гейта; посадку транспорта утверждает assert-production-posture.sh"
fi

if [[ "$expected" -eq 0 ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ: в дереве не найдено ни одного процесса с обработчиком экспозиции."
  echo "«Ноль находок» на пустом перечне ничего не утверждает — проверьте предикат."
  exit 2
fi
if [[ "${#unknown[@]}" -gt 0 ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ (вердикта нет ни у одного утверждения об этих процессах):"
  printf '  - %s\n' "${unknown[@]}"
fi
if [[ "${#red[@]}" -gt 0 ]]; then
  echo "КРАСНОЕ:"
  printf '  - %s\n' "${red[@]}"
fi
if [[ "$failed" -gt 0 ]]; then
  exit 1
fi
if [[ "$not_run" -gt 0 ]]; then
  # Третий исход НЕ вычитается из вердикта и не зачитывается в успех.
  exit 2
fi
echo "все $answered поверхностей отвечают и несут серии платформы"
