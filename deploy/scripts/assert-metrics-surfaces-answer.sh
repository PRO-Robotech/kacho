#
# Точная причина названа замером, а не догадкой: в образе края `curl` нет, а
# `wget` есть. То есть «инструмента нет» верно ровно для того инструмента,
# который гейт звал, и зависит от того, что попало в образ, — а это меняется
# правкой Dockerfile, о которой гейт не узнает.
#
# Пробник снимает зависимость от содержимого чужого образа: инструмент есть
# потому, что мы его принесли. Заодно «проверка работает» перестаёт быть
# неотличимым от «в образе края случайно остался curl».
#
# Опрос по-прежнему ИЗНУТРИ кластера: поверхность выставлена только внутрь, и
# снаружи её не должно быть видно by construction.
start_probe() {
  kubectl -n "$NS" run "$PROBE_POD" \
    --image="$PROBE_IMAGE" --restart=Never --command -- sleep 600 >/dev/null 2>&1 || true
  if kubectl -n "$NS" wait --for=condition=Ready "pod/$PROBE_POD" --timeout=90s >/dev/null 2>&1; then
    probe_pod="$PROBE_POD"
    probe_ready=1
  fi
}

stop_probe() {
  [[ "$probe_ready" == 1 ]] || return 0
  kubectl -n "$NS" delete pod "$PROBE_POD" --wait=false >/dev/null 2>&1 || true
}
trap stop_probe EXIT

if [[ "${1:-}" == "--self-test" ]]; then
  self_test
  exit $?
fi

echo "== диагностические поверхности: опрос изнутри кластера (ns=$NS) =="
start_probe
[[ -n "$probe_pod" ]] && echo "  опросчик: под-пробник $probe_pod (образ $PROBE_IMAGE)"
if [[ -z "$probe_pod" ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ: под-пробник не поднялся в ns=$NS за 90 с."
  echo "Образ: $PROBE_IMAGE. Кластер недоступен либо образ не тянется — это"
  echo "условие прогона, а не вердикт о поверхностях."
  echo "Вердикта нет ни у одного процесса — это не зелёный и не красный исход."
  exit 2
fi

# Перечень берётся ОДИН раз: он нужен дважды — загрузить имена и обойти. Второй
# вызов обхода дерева мог бы ответить иначе, и тогда имена загружались бы не для
# тех процессов, которые опрашиваются.
PROCESSES="$(processes_with_a_surface)"
if [[ -n "$PROCESSES" ]]; then
  # перечень процессов передаётся отдельными словами — дробление намеренное.
  # Пояснение стоит ПЕРЕД директивой, а не после кода правила: токен, не имеющий
  # вида ключ=значение, обрывает разбор, и файл выпадает из-под проверки целиком.
  # shellcheck disable=SC2086
  load_product_names $PROCESSES
fi

while read -r process; do
  [[ -n "$process" ]] || continue
  expected=$((expected + 1))
  # Порт берётся из ОБЪЯВЛЕНИЯ СБОРА этого же пода: аннотация и есть то место,
  # которое говорит собирателю, куда идти. Читая её, гейт проверяет ровно тот
  # адрес, по которому придёт агент, а не тот, который мы предполагаем.
  row="$(resolve_pod "$process")"
  sel="$(printf '%s' "$row" | cut -f1)"
  pod_ip="$(printf '%s' "$row" | cut -f3)"
  port="$(printf '%s' "$row" | cut -f4)"
  if [[ -z "$pod_ip" || -z "$port" ]]; then
    not_run=$((not_run + 1))
    unknown+=("$process (под не найден либо объявления сбора у него нет: ip='$pod_ip' port='$port')")
    continue
  fi
  body="$(kubectl -n "$NS" exec "$probe_pod" -- \
    curl -s --max-time 5 -w '\n%{http_code}' "http://$pod_ip:$port/metrics" 2>/dev/null || true)"
  if [[ -z "$body" ]]; then
    not_run=$((not_run + 1))
    unknown+=("$process (запрос не выполнился: нечем или некуда)")
    continue
  fi
  code="$(printf '%s' "$body" | tail -n1)"
  if [[ "$code" != "200" ]]; then
    failed=$((failed + 1))
    red+=("$process: ответ $code вместо 200 по адресу $pod_ip:$port")
    continue
  fi
  prefix="$(series_prefix "$process")"
  if ! any_line_matches "$body" "^$prefix"; then
    failed=$((failed + 1))
    red+=("$process: ответ 200, но ни одной серии $prefix — поверхность отвечает, а величин на ней нет")
    continue
  fi
  answered=$((answered + 1))
  # Селектор печатается ВСЕГДА: он и есть то место, где расхождение меток
  # чартов становится видимым. Молчащий гейт скрыл бы, что половина процессов
  # резолвится не той формой, которой резолвится другая половина.
  echo "  OK  $process → $pod_ip:$port  (по метке $sel)"
done < <(printf '%s\n' "$PROCESSES")

echo
echo "перепись: процессов с поверхностью в дереве — $expected; ответили — $answered; " \
     "ответили не тем — $failed; опрос не выполнился — $not_run"

if [[ "$expected" -eq 0 ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ: в дереве не найдено ни одного процесса с обработчиком экспозиции."
  echo "«Ноль находок» на пустом перечне ничего не утверждает — проверьте предикат."
  exit 2
fi
if [[ "${#unknown[@]}" -gt 0 ]]; then
  echo "НЕ ВЫПОЛНИЛОСЬ (вердикта нет ни у одного утверждения об этих процессах):"
  printf '  - %s\n' "${unknown[@]}"
fi
if [[ "${#red[@]}" -gt 0 ]]; then
  echo "КРАСНОЕ:"
  printf '  - %s\n' "${red[@]}"
fi
if [[ "$failed" -gt 0 ]]; then
  exit 1
fi
if [[ "$not_run" -gt 0 ]]; then
  # Третий исход НЕ вычитается из вердикта и не зачитывается в успех.
  exit 2
fi
echo "все $answered поверхностей отвечают и несут серии платформы"
