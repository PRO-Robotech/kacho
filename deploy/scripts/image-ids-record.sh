# image-ids-record.sh <файл карты> <ключ>=<образ> [<ключ>=<образ> …]
#
# Записывает в карту `global.kachoImageIds` идентификатор СОДЕРЖИМОГО каждого
# названного образа под его ключом и СОХРАНЯЕТ ключи, которых вызов не называет.
#
# Зачем один писатель на две цели (kacho#3026). Карту пишут `build-services`
# (службы) и `build-ui` (модули консоли), и вызываются они как вместе, так и
# порознь. Писатель, переписывающий файл целиком, стирал бы ключи соседней цели,
# и её поды получали бы константу «unset» вместо идентификатора; писатель,
# дописывающий в конец, дал бы дубль ключа при повторной сборке. Поэтому слияние:
# названные ключи заменяются, прочие остаются, порядок ключей — сортировкой, так
# что неизменное содержимое даёт побайтово тот же файл (иначе каждый подъём
# перекатывал бы поды без причины).
#
# Идентификатор берётся у демона ПОСЛЕ сборки: это то, что реально лежит под
# тегом. Пустой ответ — отказ: «не смогли определить» не превращается в
# «привязка не нужна». Файл заменяется атомарно — сорванный вызов не оставляет
# полузаписанной карты.
set -uo pipefail

map="${1:-}"
[ -n "$map" ] && [ "$#" -ge 2 ] || {
  echo "usage: $(basename "$0") <файл карты> <ключ>=<образ> [<ключ>=<образ> …]" >&2
  exit 2
}
shift

declare -A ids=()

# Прежние значения. Формат файла — только наш собственный (этот же писатель), и
# строки иной формы не принимаются молча: чужая правка карты — отказ, а не потеря.
if [ -f "$map" ]; then
  while IFS= read -r line; do
    case "$line" in
      '#'*|'global:'|'  kachoImageIds:'|'') continue ;;
    esac
    if [[ "$line" =~ ^\ \ \ \ \"?([^\":]+)\"?:\ \"(sha256:[^\"]+)\"$ ]]; then
      ids["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
    else
      echo "ERROR: строка карты $map не в форме этого писателя: «$line»" >&2
      echo "       карта генерируется и не правится рукой — удали файл и пересобери образы" >&2
      exit 1
    fi
  done <"$map"
fi

for pair in "$@"; do
  key="${pair%%=*}"; img="${pair#*=}"
  [ -n "$key" ] && [ -n "$img" ] && [ "$key" != "$pair" ] || {
    echo "ERROR: аргумент «$pair» не в форме <ключ>=<образ>" >&2; exit 2; }
  id="$(docker image inspect --format '{{.Id}}' "$img" 2>/dev/null)"
  if [ -z "$id" ]; then
    echo "ERROR: не определён идентификатор содержимого образа $img" >&2
    exit 1
  fi
  ids["$key"]="$id"
done

tmp="$(mktemp "$(dirname "$map")/.image-ids.XXXXXX")" || exit 1
{
  echo "# generated by 'make build-services' / 'make build-ui' — не редактировать, не коммитить"
  echo "global:"
  echo "  kachoImageIds:"
  while IFS= read -r key; do
    [ -n "$key" ] || continue
    printf '    "%s": "%s"\n' "$key" "${ids[$key]}"
  done < <(printf '%s\n' "${!ids[@]}" | LC_ALL=C sort)
} >"$tmp" || { rm -f "$tmp"; exit 1; }
mv -f "$tmp" "$map"
