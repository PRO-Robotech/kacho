# product-names.sh — ЧИТАТЕЛЬ имён частей продукта для оболочки.
#
# # Предмет
#
# Как называется образ (и чарт) части продукта, объявлено ОДИН раз — в
# `internal/productnaming`. До задачи #2076 рецепт стенда выводил имя приставкой
# платформы (`services/<svc>` → `kacho-<svc>`), и это было верно, пока имя
# платформы было и именем каждой её части. Служба управления доступом получила
# собственное имя продукта (Kaname) — приставка перестала связывать, а рецепт
# продолжал собирать `kacho-iam:dev` при чарте, просящем `kaname:dev`.
#
# Отказ при этом ТИХИЙ: `helm template` рендерится зелёным, а под не стартует —
# образа нет в kind, и `IfNotPresent` уходит за ним в реестр. То есть проверка
# формы молчит, а отказ наступает на поднятом кластере.
#
# # Почему здесь НЕТ второй реализации правила
#
# Этот файл правило НЕ ТОЛКУЕТ. Он собирает `tools/productnames/cmd/product-names`
# ИЗ СВОЕГО ЖЕ ДЕРЕВА и спрашивает ответ у него — то есть у того же
# `internal/productnaming`, который читают все Go-потребители этого дерева.
# Второй реализации правила нет, а инструмент собирается в путь, отпечатанный
# корнем дерева, — поэтому соседняя рабочая копия своим ответом эту не
# подменяет.
#
# Что этим НЕ покрыто, названо прямо: ответ верен для дерева, из которого
# библиотека подключена. Собранный файл живёт до следующей сборки, поэтому
# правка ведомости без пересборки инструмента даст прежний ответ — `go build`
# зовётся на каждом первом обращении в процессе и это окно закрывает, но
# доказательства на гонку у нас нет (см. пробу согласия).
#
# Разобрать ведомость своей копией было бы дешевле на вид и дороже по существу:
# соответствие — это ПРАВИЛО (у большинства частей имя выводится, у части
# объявлено), и второй его толкователь разошёлся бы с первым молча.
#
# # Почему `go build`, а не `go run`
#
# `go run` отдаёт СВОЙ код 1 на любом ненулевом коде программы, поэтому «каталог
# не признан частью продукта» (1) стало бы неотличимо от «каталогов не названо»
# (2). Тот же довод уже записан у цели `module-manifests-configmap`.
#
# Инструментарий Go на этом пути уже требуется: `make dev-up` строит производителя
# манифестов той же командой. Новой зависимости здесь не заводится.
#
# # Использование
#
#   . ./scripts/lib/product-names.sh
#   product_names_load iam vpc compute …     # один разбор на процесс оболочки
#   img="$(product_image_name iam)"          # → kaname
#
# Стережётся ПУСТОЕ имя, а не «неизвестный каталог», и разница здесь несущая.
# Правило выводит имя для любого НЕПУСТОГО каталога и дерева не знает вовсе
# (`internal/productnaming`), поэтому «этой части у нас нет» оно ответить не
# может. Единственный вход, на котором читатель отказывает, — пустая строка: у
# неё нет тела после приставки. Класс реальный — пустое раскрытие переменной у
# вызывающего уехало бы в `docker build -t :dev` и собрало бы образ, которого
# никто не просил.
#
# Существование каталога — ОТВЕТСТВЕННОСТЬ ВЫЗЫВАЮЩЕГО, которому известен
# корень (так это оговорено и в шапке `tools/productnames/cmd/product-names`).
# Здесь этой проверки нет НАМЕРЕННО, а не по недосмотру: перечень частей
# продукта и перечень каталогов под `services/` — РАЗНЫЕ словари. Рецепт стенда
# законно собирает `api-gateway`, каталог которого — `gateway/`, и проверка
# `services/<он>` отвергла бы работающий вход.
#
# Держится это пробами `deploy/product_names_shell_reader_test.go`
# (`TestShellReaderDoesNotCheckThatTheDirectoryExists` — обе стороны;
# `TestShellReaderRefusalNamesTheSubjectOnly` — что видит оператор). Прежде
# здесь стояло обещание отказа на неизвестном каталоге; оно не наступало ни при
# каком входе, и следующий вызывающий прочитал бы его как действующий страж.

# Настроек оболочки этот файл НЕ МЕНЯЕТ: его подключают в чужой процесс, и
# `set -e`/`set -o pipefail`, выставленные здесь, меняли бы поведение
# вызывающего за его спиной. Конвейеров тут нет — ответ инструмента читается
# через файл, а не через трубу, — поэтому и нужды в них нет.

# _PRODUCT_NAMES_BIN — собранный инструмент. Собирается один раз на процесс.
_PRODUCT_NAMES_BIN=""
declare -gA _PRODUCT_IMAGE_NAME=()

# _product_names_root — корень дерева, выведенный из МЕСТА ЭТОГО ФАЙЛА, а не из
# текущего каталога: библиотеку зовут и из `deploy/`, и из корня, и из проб.
_product_names_root() {
  local here
  here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
  cd -- "$here/../../.." && pwd
}

# _product_names_cache_dir КОРЕНЬ — куда класть собранный инструмент.
#
# ПУТЬ ЗАВИСИТ ОТ ДЕРЕВА, И ЭТО НЕСУЩЕЕ СВОЙСТВО, А НЕ АККУРАТНОСТЬ.
#
# Прежняя редакция ключевала путь только на `TMPDIR` и uid. Тогда две рабочие
# копии одного репозитория — обычный здесь режим, полосы идут параллельно —
# делили ОДИН двоичный файл: чей `go build` отработал последним, того правило и
# отвечало всем. Разойтись это могло молча и правдоподобным неверным именем:
# соседнее дерево с иной ведомостью отвечало бы `iam → своё`, тогда как Go ЭТОГО
# дерева называет `kaname`.
#
# Утверждение «расхождение оболочки и Go невозможно by construction» при таком
# пути было ЛОЖНЫМ, и на него опиралось объяснение, зачем нужна проба согласия.
# Ложное «by construction» опаснее отсутствующего — на него полагаются.
#
# Отпечаток корня делает путь свойством ДЕРЕВА: у каждой копии свой инструмент,
# собранный из её собственного исходника. Каталог при этом остаётся стабильным
# для своего дерева, поэтому рост по-прежнему ограничен одним файлом на копию
# (`/tmp` здесь tmpfs, то есть память).
_product_names_cache_dir() {
  local root="$1" digest
  digest="$(printf '%s' "$root" | sha256sum | cut -c1-16)" || return 1
  printf '%s/kacho-product-names.%s.%s\n' "${TMPDIR:-/tmp}" "$(id -u)" "$digest"
}

# _product_names_build — собрать инструмент. Отказ сборки ГРОМКИЙ: молча
# продолжить значило бы вернуться к выводу имени по памяти.
_product_names_build() {
  [ -n "$_PRODUCT_NAMES_BIN" ] && return 0
  local root out
  root="$(_product_names_root)" || {
    echo "product-names: корень дерева не разрешается — читать имена неоткуда" >&2
    return 1
  }
  out="$(_product_names_cache_dir "$root")" || return 1
  mkdir -p "$out" || return 1
  if ! ( cd "$root" && go build -o "$out/product-names" ./tools/productnames/cmd/product-names ) >&2; then
    echo "product-names: инструмент не собрался — имена НЕ прочитаны." >&2
    echo "               Это «не выполнилось», а не «имён нет»: продолжать с выводом" >&2
    echo "               по приставке нельзя, часть продукта так не называется." >&2
    return 1
  fi
  _PRODUCT_NAMES_BIN="$out/product-names"
}

# product_names_load КАТАЛОГ… — прочитать имена названных частей.
#
# Вывод и КОД инструмента берутся за ОДИН прогон: подстановка процесса теряет
# код, а второй прогон ради кода спрашивал бы дважды и мог бы ответить иначе.
product_names_load() {
  [ "$#" -gt 0 ] || {
    echo "product-names: не названо ни одного каталога — обход беспредметен" >&2
    return 2
  }
  _product_names_build || return 1

  local out rc=0
  out="$(mktemp)" || return 1
  "$_PRODUCT_NAMES_BIN" "$@" >"$out" || rc=$?
  if [ "$rc" -ne 0 ]; then
    rm -f "$out"
    return "$rc"
  fi
  local dir name
  while IFS=$'\t' read -r dir name; do
    [ -n "$dir" ] || continue
    _PRODUCT_IMAGE_NAME["$dir"]="$name"
  done <"$out"
  rm -f "$out"
}

# product_image_name КАТАЛОГ — имя образа (оно же имя чарта) этой части.
#
# Стережётся ПУСТОЕ имя; существование каталога оставлено вызывающему — разбор в
# шапке файла.
#
# Пустой аргумент отсекается ДО обращения к ведомости: пустой ключ
# ассоциативного массива заставлял bash напечатать свою диагностику раньше
# стража — с номером строки этого файла и именем внутренней переменной. Такой
# отказ выглядит поломкой читателя имён и не говорит вызывающему ничего о его
# собственной пустой переменной.
#
# ЧЕЙ ЭТО ОТКАЗ — СКАЗАНО ТОЧНО, А НЕ ШИРЕ. Видно его только на ПРЯМОМ пути
# (эта функция без предшествующего `product_names_load`); через загрузку отказ
# наступает раньше, и до ведомости дело не доходит. Прямой путь в дереве ОДИН —
# `make reload-svc`, — и у него СВОЯ проверка имени, которая пустое отсекает
# прежде. То есть сегодня оператор этой диагностики не увидит; чинится она не
# потому, что дефект наблюдается, а потому, что от следующего вызывающего
# защищаться нечем: своя проверка есть свойство ЕГО кода, а не гарантия
# читателя. Держится `TestShellReaderRefusalNamesTheSubjectOnly`, и путь там
# прямой намеренно.
product_image_name() {
  local dir="$1"
  [ -n "$dir" ] || {
    echo "product-names: имя части пусто — печатать нечего." >&2
    echo "               Похоже на пустое раскрытие переменной у вызывающего:" >&2
    echo "               с таким именем собрался бы образ \`:dev\`, которого никто не просил." >&2
    return 1
  }
  if [ -z "${_PRODUCT_IMAGE_NAME[$dir]+set}" ]; then
    product_names_load "$dir" || return $?
  fi
  local name="${_PRODUCT_IMAGE_NAME[$dir]}"
  [ -n "$name" ] || {
    printf 'product-names: имя части %s не прочитано — собирать образ нечем\n' "$dir" >&2
    return 1
  }
  printf '%s\n' "$name"
}

# ─────────────────────────────────────────────────────────────────────────────
# ОБРАТНЫЙ ВОПРОС: «эта ссылка на образ — НАША?»
#
# Тот же предмет, что у `productnaming.IsProductImageRepo`, и заведён он здесь по
# той же причине, по какой заведён прямой читатель выше: спрашивающему из
# оболочки некуда было пойти, и он выводил ответ приставкой платформы сам.
#
# Цена этой самодеятельности измерена: `stand-provenance.sh` относил СОБСТВЕННЫЙ
# образ `kaname:dev` в чужие и печатал «работающих контейнеров ПРОДУКТА ноль» на
# стенде, где их трое. Отказ при этом ЗЕЛЁНЫЙ по форме — распознаватель чужое имя
# не отвергает, он его НЕ ВИДИТ.
#
# Правило здесь НЕ ТОЛКУЕТСЯ второй раз: имена частей спрашиваются у того же
# инструмента, а приставка платформы ВЫВОДИТСЯ из его же ответов (см. ниже).
# Слова `kaname` в оболочке не появляется ни разу — оно приезжает ответом.

# product_platform_prefix — приставка имени платформы, ВЫВЕДЕННАЯ из ответов.
#
# У части, имя которой правило ВЫВОДИТ, ответ оканчивается именем её каталога
# (`vpc` → `kacho-vpc`), и остаток — это и есть приставка. Часть со СВОИМ именем
# продукта (`iam` → `kaname`) на имя каталога не оканчивается и приставки не
# даёт; такая часть опознаётся членством, а не приставкой.
#
# Выписать приставку литералом было бы дешевле на вид и дороже по существу: это
# третье место об одном предмете (первые два — `platformPrefix` в Go и ведомость),
# и разошлось бы оно молча — ровно как разошлась приставка в этих скриптах.
#
# Пусто — законный ответ: приставки нет, если ВСЕ загруженные части переименованы.
# Вызывающий тогда судит одним членством, и это верно, а не досадно.
product_platform_prefix() {
  local dir name
  for dir in "${!_PRODUCT_IMAGE_NAME[@]}"; do
    name="${_PRODUCT_IMAGE_NAME[$dir]}"
    case "$name" in
      *"-$dir") printf '%s\n' "${name%"$dir"}"; return 0 ;;
    esac
  done
  return 0
}

# product_image_is_ours ССЫЛКА — образ по этой ссылке собран нами?
#
# Судится ПОСЛЕДНИЙ сегмент ссылки без тега: `docker.io/library/kacho-vpc:dev` и
# `prorobotech/kaname:<тег>` — наши; `docker.io/bitnami/postgresql:16.4.0`,
# `hydra:v26.2.0` и голая ссылка по дайджесту — чужие.
#
# Признак — членство в именах частей ЛИБО приставка платформы, и порядок здесь
# несущий: приставка покрывает то, что частью под `services/` не является
# (образы модулей консоли), а членство — то, у чего приставки нет by
# construction. Одного признака мало НИ ОДНОГО из двух.
#
# ПРЕДПОСЫЛКА: имена уже загружены `product_names_load`. Незагруженные имена —
# это «не спрашивали», а не «не наше», поэтому пустая ведомость ОТКАЗЫВАЕТ, а не
# отвечает «чужой» на всё подряд: молчаливое «чужой» и есть тот дефект, ради
# которого функция заведена.
product_image_is_ours() {
  local ref="${1##*/}" last prefix
  last="${ref%%:*}"
  if [ "${#_PRODUCT_IMAGE_NAME[@]}" -eq 0 ]; then
    echo "product-names: имена частей не загружены — на вопрос «наш ли образ» отвечать нечем." >&2
    echo "               Позовите product_names_load до первого обращения." >&2
    return 2
  fi
  local dir
  for dir in "${!_PRODUCT_IMAGE_NAME[@]}"; do
    [ "$last" = "${_PRODUCT_IMAGE_NAME[$dir]}" ] && return 0
  done
  prefix="$(product_platform_prefix)"
  [ -n "$prefix" ] || return 1
  case "$last" in "$prefix"?*) return 0 ;; esac
  return 1
}

# product_service_dirs — каталоги ЧАСТЕЙ ПРОДУКТА: те, что лежат под
# `services/` в индексе git, ПЛЮС те, что названы ведомостью собственных имён.
#
# Состав первого слагаемого берётся у индекса, а не с диска, по той же причине,
# по какой его берёт оттуда гейт рецептов стенда: под деревом лежат распакованные
# чужие чарты и рабочие каталоги, и обход диска считал бы их частями продукта.
#
# # ПОЧЕМУ ОДНОГО `services/*` НЕДОСТАТОЧНО — предпосылка пережила свой предмет
#
# Прежняя редакция брала перечень ТОЛЬКО из `services/*` и объясняла это так:
# «ведомость собственных имён закрыта и её ключи — каталоги под `services/`,
# поэтому загрузка ИМЕННО этого перечня даёт все имена, которые приставкой не
# выводятся». Посылка была верна до разреза монорепо и стала ЛОЖНОЙ вместе с ним:
# исходники Kaname уехали в свой репозиторий, а имя, чарт `charts/kaname` и пин
# образа остались нашими. Каталога `services/iam` в дереве больше нет — значит
# ключ ведомости из перечня ВЫПАЛ, и вместе с ним выпало имя, которое приставкой
# не выводится by construction.
#
# Цена измерена, а не предположена. Обратный вопрос `product_image_is_ours`
# отвечал «чужой» на СОБСТВЕННЫЙ образ, и отвечал МОЛЧА — распознаватель чужое
# имя не отвергает, он его не видит:
#
#   • stand-provenance.sh печатал «работающих контейнеров ПРОДУКТА ноль» на
#     стенде, где работает Kaname, — то есть не выносил вердикта о ревизии вовсе;
#   • gen-managed-image-pins.sh не считал пин второго имени пином продукта, и
#     этот пин уходил из-под наблюдения свежести.
#
# Ровно те два дефекта, против которых Go-сторона завела `SourcesInThisTree` и
# отдельную ведомость внешне-источниковых частей; оболочка этого разреза не
# знала.
#
# # ПОЧЕМУ ВЕДОМОСТЬ СПРАШИВАЕТСЯ, А НЕ ВЫПИСЫВАЕТСЯ
#
# Второе слагаемое приезжает ОТВЕТОМ того же инструмента (`--parts`), что
# отвечает и на прямой вопрос об имени. Выписать здесь `iam` литералом было бы
# дешевле на вид и дороже по существу: это второй толкователь правила, и
# разошёлся бы он молча — ровно так, как разошлась приставка в скриптах до
# заведения этого читателя. Слова второго имени продукта в оболочке по-прежнему
# нет ни разу.
#
# Объединение, а не замена: часть, чей каталог в дереве ЕСТЬ и чьё имя ведомость
# называет, законно приходит с обеих сторон, и `sort -u` сводит её к одной записи.
product_service_dirs() {
  local root
  root="$(_product_names_root)" || return 1
  _product_names_build || return 1
  local ledger
  # Отказ перечисления ГРОМКИЙ: перечень без ведомости неполон ровно на тех
  # частях, ради которых ведомость существует, а неполный перечень даёт молчаливое
  # «чужой» на своём образе.
  ledger="$("$_PRODUCT_NAMES_BIN" --parts)" || {
    echo "product-names: ведомость собственных имён не прочитана — перечень частей" >&2
    echo "               был бы неполон ровно на частях со своим именем продукта." >&2
    return 1
  }
  {
    git -C "$root" ls-files -- 'services/*' \
      | sed -n 's#^services/\([^/]*\)/.*#\1#p'
    printf '%s\n' "$ledger"
  } | sed '/^$/d' | sort -u
}

# ─────────────────────────────────────────────────────────────────────────────
# ТРЕТИЙ ВОПРОС: «этот образ продукта приезжает ПИНОМ, и какой пин объявлен?»
#
# Тот же предмет, что у двух вопросов выше, и заведён он здесь по той же причине:
# спрашивающему из оболочки некуда было пойти, и он не спрашивал вовсе.
#
# # Зачем вопрос существует
#
# Проверка посадки требует, чтобы контейнер продукта нёс ревизию ДЕРЕВА ПРОГОНА.
# Для части, чьи исходники здесь, это верно by construction: её образ собирает тот
# же прогон. Для части ВЫНЕСЕННОЙ — ложно by construction: её образ собирает чужой
# конвейер, и приезжает он объявленным пином, чей тег называет коммит ЕЁ ствола.
#
# Цена измерена, а не предположена: в прогоне 34694955309 сверка с ревизией прогона
# объявила расхождением ВЕРНЫЙ факт, отметка «предпосылка не создана» встала на
# ЧЕТЫРЁХ шардах из четырёх и на стенде консоли, и сквозной набор не исполнил ни
# одной коллекции из 57.
#
# # Почему ссылка ЧИТАЕТСЯ, а не выписывается
#
# Выписанная разошлась бы с деревом молча и в ту сторону, где расхождение не
# видно. Здесь она приезжает ОТВЕТОМ того же инструмента, что отвечает на два
# вопроса выше, а перечень профилей — от ЕДИНСТВЕННОГО shell-читателя состава
# стендов (`deploy/tests/helm/stacks.sh`). Третьего читателя `stacks.txt` не
# заводится: файл сам называет своих читателей, и их двое.
#
# # ГРАНИЦА НАЗВАНА: СРАВНЕНИЕ ИДЁТ С ОБЪЕДИНЕНИЕМ ПРОФИЛЕЙ, А НЕ С ОДНИМ
#
# Какой цепочкой поднят ЭТОТ стенд, оболочке неизвестно: вызывающий получает
# метку, а не имя стека. Поэтому объявленным считается пин, названный ЛЮБЫМ
# профилем любой цепочки, и это послабление названо вслух, а не заметено:
# разойдись профили в теге — стенд, исполняющий пин соседнего профиля, сверку
# пройдёт. Видно это будет в переписи (она печатает и число различных пинов, и
# файлы, объявившие совпавший), а не только в этой записи.
#
# Умолчание подчарта (`charts/<имя>/values.yaml`) пином НАМЕРЕННО не считается:
# образа с тем именем это дерево не собирает, производителя у него нет
# (deploy/stand_image_has_a_producer_test.go), и стенд, исполняющий его, — находка.

declare -gA _PRODUCT_PIN_REFS=()    # имя образа → ссылки через пробел
declare -gA _PRODUCT_PIN_WHERE=()   # «имя образа ссылка» → стенды через запятую
_PRODUCT_PINS_LOADED=0
_PRODUCT_PINS_CENSUS=""

# _product_pin_chains — ЦЕПОЧКИ, которыми стенды раскатываются, в форме
# «<имя стека>=<слой>,<слой>…»: базовый профиль плюс накладки этого стека, слева
# направо, как их получает helm.
#
# ЦЕПОЧКА, А НЕ ПЛОСКИЙ ПЕРЕЧЕНЬ ФАЙЛОВ, И ЭТО НЕСУЩЕЕ. Накладка вправе объявить
# ОДИН ТЕГ (`values.fe3455-prod.yaml` так и делает), а репозиторий приходит из слоя
# ниже. Судя файлы по одному, читатель такую накладку НЕ ОТВЕРГАЕТ — он её не
# видит, и ссылка стека вычислилась бы неверно. Сложение делает инструмент.
#
# Пустой ответ — ОТКАЗ: «стендов не осталось» и «читатель не ответил» обязаны быть
# различимы.
_product_pin_chains() {
  local root umbrella reader table
  root="$(_product_names_root)" || return 1
  umbrella="$root/deploy/helm/umbrella"
  reader="$root/deploy/tests/helm/stacks.sh"
  [ -r "$reader" ] || {
    echo "product-names: читатель состава стендов $reader не найден — перечень" >&2
    echo "               стендов взять неоткуда." >&2
    return 1
  }
  table="$(bash "$reader" --table)" || return 1
  [ -n "$table" ] || {
    echo "product-names: таблица стендов прочиталась пустой — стендов ноль." >&2
    return 1
  }
  # Имя стека — до двоеточия, слои — после, через запятую. Разбор здесь НЕ
  # повторяет разбор читателя: нераспознанную строку читатель уже отверг.
  local line name layers
  printf '%s\n' "$table" | while IFS= read -r line; do
    [ -n "$line" ] || continue
    name="${line%%:*}"
    layers="$(printf '%s' "${line#*:}" | sed "s#[^,][^,]*#$umbrella/&#g")"
    printf '%s=%s/values.yaml,%s\n' "$name" "$umbrella" "$layers"
  done
}

# product_pins_load [ЦЕПОЧКА…] — прочитать объявленные пины вынесенных частей.
#
# Без аргументов цепочки ВЫВОДЯТСЯ из дерева. Аргументы принимаются ради инъекции:
# доказать, что «пин не объявлен» отличимо от «объявлен другой», можно только подав
# вход, где его нет. Подмена при этом не прячется — перепись печатает, сколько
# цепочек и слоёв прочитано. Аргумент без знака равенства — цепочка из одного слоя.
product_pins_load() {
  _product_names_build || return 1
  local files=()
  if [ "$#" -gt 0 ]; then
    files=("$@")
  else
    # Перечень берётся ПРИСВАИВАНИЕМ, а не подстановкой в цикл: `while … < <(…)`
    # теряет код читателя ВСЕГДА, и его отказ выглядел бы «профилей ноль» — верным
    # словом о неверной причине.
    local list f rc_list=0
    list="$(_product_pin_chains)" || rc_list=$?
    if [ "$rc_list" -ne 0 ] || [ -z "$list" ]; then
      echo "product-names: перечень стендов НЕ прочитан (код $rc_list) — сверять пин" >&2
      echo "               было бы не с чем, и пустой перечень объявил бы находкой" >&2
      echo "               верный пин. Это «не выполнилось», а не «стендов ноль»." >&2
      return 2
    fi
    while IFS= read -r f; do [ -n "$f" ] && files+=("$f"); done <<<"$list"
  fi

  local out err rc=0
  out="$(mktemp)" || return 1
  err="$(mktemp)" || { rm -f "$out"; return 1; }
  "$_PRODUCT_NAMES_BIN" --external-pins "${files[@]}" >"$out" 2>"$err" || rc=$?
  if [ "$rc" -ne 0 ]; then
    echo "product-names: перечень объявленных пинов НЕ прочитан (код $rc) — сверять" >&2
    echo "               ссылку контейнера не с чем. Это «не выполнилось», а не" >&2
    echo "               «пинов нет»: пустой перечень объявил бы находкой верный пин." >&2
    cat "$err" >&2
    rm -f "$out" "$err"
    return "$rc"
  fi
  _PRODUCT_PIN_REFS=(); _PRODUCT_PIN_WHERE=()
  local kind a b c
  while IFS=$'\t' read -r kind a b c; do
    case "$kind" in
      PART) _PRODUCT_PIN_REFS["$b"]="${_PRODUCT_PIN_REFS[$b]-}" ;;
      PIN)  _PRODUCT_PIN_REFS["$a"]="${_PRODUCT_PIN_REFS[$a]:+${_PRODUCT_PIN_REFS[$a]} }$b"
            _PRODUCT_PIN_WHERE["$a $b"]="$c" ;;
    esac
  done <"$out"
  _PRODUCT_PINS_CENSUS="$(tr '\n' ' ' <"$err")"
  rm -f "$out" "$err"
  _PRODUCT_PINS_LOADED=1
}

# product_image_is_pinned ИМЯ — образ этой части приезжает пином (исходники
# вынесены)? Незагруженная ведомость ОТКАЗЫВАЕТ (код 2), а не отвечает «нет»:
# молчаливое «нет» вернуло бы сверку с ревизией прогона, то есть исходный дефект.
product_image_is_pinned() {
  [ "$_PRODUCT_PINS_LOADED" -eq 1 ] || {
    echo "product-names: ведомость пинов не загружена — на вопрос «приезжает ли пином»" >&2
    echo "               отвечать нечем. Позовите product_pins_load." >&2
    return 2
  }
  # Пустое имя отсекается ДО обращения к ведомости: пустой ключ ассоциативного
  # массива заставляет bash напечатать свою диагностику раньше нашей — с номером
  # строки этой библиотеки, то есть отказ выглядел бы её поломкой. Тот же довод
  # стоит у `product_image_name`.
  [ -n "${1-}" ] || {
    echo "product-names: имя образа пусто — «приезжает ли пином» спрошено ни о чём." >&2
    return 2
  }
  [ -n "${_PRODUCT_PIN_REFS[$1]+set}" ]
}

# product_pin_refs ИМЯ — объявленные ссылки, по одной в строке. Пусто — законный
# ответ и означает «часть вынесена, а ссылки ей не объявил ни один стенд»;
# решает по этому вызывающий, у которого есть вторая сторона сравнения.
product_pin_refs() {
  [ -n "${1-}" ] || return 0
  local refs="${_PRODUCT_PIN_REFS[$1]-}"
  [ -n "$refs" ] || return 0
  # Дробление через `read -a`, а не подстановкой: подстановка проходит ещё и
  # РАСКРЫТИЕ ШАБЛОНОВ, и ссылка со знаком шаблона уехала бы подменённой именем
  # файла из текущего каталога.
  local -a out=()
  read -r -a out <<<"$refs"
  printf '%s\n' "${out[@]}"
}

# product_pin_where ИМЯ ССЫЛКА — какие СТЕНДЫ её объявляют (после сложения слоёв).
product_pin_where() {
  [ -n "${1-}" ] && [ -n "${2-}" ] || return 0
  printf '%s\n' "${_PRODUCT_PIN_WHERE["$1 $2"]-}"
}

# product_pins_census — объём осмотренного читателем пинов, как он его назвал.
product_pins_census() { printf '%s\n' "$_PRODUCT_PINS_CENSUS"; }
