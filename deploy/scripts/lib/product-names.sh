# product-names.sh — ЧИТАТЕЛЬ имён частей продукта для оболочки.
#
# # Предмет
#
# Как называется образ (и чарт) части продукта, объявлено ОДИН раз — в
# `internal/productnaming`. До задачи #2076 рецепт стенда выводил имя приставкой
# платформы (`services/<svc>` → `kacho-<svc>`), и это было верно, пока имя
# платформы было и именем каждой её части. Служба управления доступом получила
# собственное имя продукта (Kaname) — приставка перестала связывать, а рецепт
# продолжал собирать `kacho-iam:dev` при чарте, просящем `kaname:dev`.
#
# Отказ при этом ТИХИЙ: `helm template` рендерится зелёным, а под не стартует —
# образа нет в kind, и `IfNotPresent` уходит за ним в реестр. То есть проверка
# формы молчит, а отказ наступает на поднятом кластере.
#
# # Почему здесь НЕТ второй реализации правила
#
# Этот файл правило НЕ ТОЛКУЕТ. Он собирает `tools/productnames/cmd/product-names`
# ИЗ СВОЕГО ЖЕ ДЕРЕВА и спрашивает ответ у него — то есть у того же
# `internal/productnaming`, который читают все Go-потребители этого дерева.
# Второй реализации правила нет, а инструмент собирается в путь, отпечатанный
# корнем дерева, — поэтому соседняя рабочая копия своим ответом эту не
# подменяет.
#
# Что этим НЕ покрыто, названо прямо: ответ верен для дерева, из которого
# библиотека подключена. Собранный файл живёт до следующей сборки, поэтому
# правка ведомости без пересборки инструмента даст прежний ответ — `go build`
# зовётся на каждом первом обращении в процессе и это окно закрывает, но
# доказательства на гонку у нас нет (см. пробу согласия).
#
# Разобрать ведомость своей копией было бы дешевле на вид и дороже по существу:
# соответствие — это ПРАВИЛО (у большинства частей имя выводится, у части
# объявлено), и второй его толкователь разошёлся бы с первым молча.
#
# # Почему `go build`, а не `go run`
#
# `go run` отдаёт СВОЙ код 1 на любом ненулевом коде программы, поэтому «каталог
# не признан частью продукта» (1) стало бы неотличимо от «каталогов не названо»
# (2). Тот же довод уже записан у цели `module-manifests-configmap`.
#
# Инструментарий Go на этом пути уже требуется: `make dev-up` строит производителя
# манифестов той же командой. Новой зависимости здесь не заводится.
#
# # Использование
#
#   . ./scripts/lib/product-names.sh
#   product_names_load iam vpc compute …     # один разбор на процесс оболочки
#   img="$(product_image_name iam)"          # → kaname
#
# Неизвестный каталог — ОТКАЗ, а не пустая строка: пустое имя уехало бы в
# `docker build -t :dev` и собрало бы образ, которого никто не просил.

# Настроек оболочки этот файл НЕ МЕНЯЕТ: его подключают в чужой процесс, и
# `set -e`/`set -o pipefail`, выставленные здесь, меняли бы поведение
# вызывающего за его спиной. Конвейеров тут нет — ответ инструмента читается
# через файл, а не через трубу, — поэтому и нужды в них нет.

# _PRODUCT_NAMES_BIN — собранный инструмент. Собирается один раз на процесс.
_PRODUCT_NAMES_BIN=""
declare -gA _PRODUCT_IMAGE_NAME=()

# _product_names_root — корень дерева, выведенный из МЕСТА ЭТОГО ФАЙЛА, а не из
# текущего каталога: библиотеку зовут и из `deploy/`, и из корня, и из проб.
_product_names_root() {
  local here
  here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
  cd -- "$here/../../.." && pwd
}

# _product_names_cache_dir КОРЕНЬ — куда класть собранный инструмент.
#
# ПУТЬ ЗАВИСИТ ОТ ДЕРЕВА, И ЭТО НЕСУЩЕЕ СВОЙСТВО, А НЕ АККУРАТНОСТЬ.
#
# Прежняя редакция ключевала путь только на `TMPDIR` и uid. Тогда две рабочие
# копии одного репозитория — обычный здесь режим, полосы идут параллельно —
# делили ОДИН двоичный файл: чей `go build` отработал последним, того правило и
# отвечало всем. Разойтись это могло молча и правдоподобным неверным именем:
# соседнее дерево с иной ведомостью отвечало бы `iam → своё`, тогда как Go ЭТОГО
# дерева называет `kaname`.
#
# Утверждение «расхождение оболочки и Go невозможно by construction» при таком
# пути было ЛОЖНЫМ, и на него опиралось объяснение, зачем нужна проба согласия.
# Ложное «by construction» опаснее отсутствующего — на него полагаются.
#
# Отпечаток корня делает путь свойством ДЕРЕВА: у каждой копии свой инструмент,
# собранный из её собственного исходника. Каталог при этом остаётся стабильным
# для своего дерева, поэтому рост по-прежнему ограничен одним файлом на копию
# (`/tmp` здесь tmpfs, то есть память).
_product_names_cache_dir() {
  local root="$1" digest
  digest="$(printf '%s' "$root" | sha256sum | cut -c1-16)" || return 1
  printf '%s/kacho-product-names.%s.%s\n' "${TMPDIR:-/tmp}" "$(id -u)" "$digest"
}

# _product_names_build — собрать инструмент. Отказ сборки ГРОМКИЙ: молча
# продолжить значило бы вернуться к выводу имени по памяти.
_product_names_build() {
  [ -n "$_PRODUCT_NAMES_BIN" ] && return 0
  local root out
  root="$(_product_names_root)" || {
    echo "product-names: корень дерева не разрешается — читать имена неоткуда" >&2
    return 1
  }
  out="$(_product_names_cache_dir "$root")" || return 1
  mkdir -p "$out" || return 1
  if ! ( cd "$root" && go build -o "$out/product-names" ./tools/productnames/cmd/product-names ) >&2; then
    echo "product-names: инструмент не собрался — имена НЕ прочитаны." >&2
    echo "               Это «не выполнилось», а не «имён нет»: продолжать с выводом" >&2
    echo "               по приставке нельзя, часть продукта так не называется." >&2
    return 1
  fi
  _PRODUCT_NAMES_BIN="$out/product-names"
}

# product_names_load КАТАЛОГ… — прочитать имена названных частей.
#
# Вывод и КОД инструмента берутся за ОДИН прогон: подстановка процесса теряет
# код, а второй прогон ради кода спрашивал бы дважды и мог бы ответить иначе.
product_names_load() {
  [ "$#" -gt 0 ] || {
    echo "product-names: не названо ни одного каталога — обход беспредметен" >&2
    return 2
  }
  _product_names_build || return 1

  local out rc=0
  out="$(mktemp)" || return 1
  "$_PRODUCT_NAMES_BIN" "$@" >"$out" || rc=$?
  if [ "$rc" -ne 0 ]; then
    rm -f "$out"
    return "$rc"
  fi
  local dir name
  while IFS=$'\t' read -r dir name; do
    [ -n "$dir" ] || continue
    _PRODUCT_IMAGE_NAME["$dir"]="$name"
  done <"$out"
  rm -f "$out"
}

# product_image_name КАТАЛОГ — имя образа (оно же имя чарта) этой части.
#
# Неизвестный каталог — ОТКАЗ, а не пустая строка: пустое имя уехало бы в
# `docker build -t :dev` и собрало бы образ, которого никто не просил.
product_image_name() {
  local dir="$1"
  if [ -z "${_PRODUCT_IMAGE_NAME[$dir]+set}" ]; then
    product_names_load "$dir" || return $?
  fi
  local name="${_PRODUCT_IMAGE_NAME[$dir]}"
  [ -n "$name" ] || {
    printf 'product-names: имя части %s не прочитано — собирать образ нечем\n' "$dir" >&2
    return 1
  }
  printf '%s\n' "$name"
}

# ─────────────────────────────────────────────────────────────────────────────
# ОБРАТНЫЙ ВОПРОС: «эта ссылка на образ — НАША?»
#
# Тот же предмет, что у `productnaming.IsProductImageRepo`, и заведён он здесь по
# той же причине, по какой заведён прямой читатель выше: спрашивающему из
# оболочки некуда было пойти, и он выводил ответ приставкой платформы сам.
#
# Цена этой самодеятельности измерена: `stand-provenance.sh` относил СОБСТВЕННЫЙ
# образ `kaname:dev` в чужие и печатал «работающих контейнеров ПРОДУКТА ноль» на
# стенде, где их трое. Отказ при этом ЗЕЛЁНЫЙ по форме — распознаватель чужое имя
# не отвергает, он его НЕ ВИДИТ.
#
# Правило здесь НЕ ТОЛКУЕТСЯ второй раз: имена частей спрашиваются у того же
# инструмента, а приставка платформы ВЫВОДИТСЯ из его же ответов (см. ниже).
# Слова `kaname` в оболочке не появляется ни разу — оно приезжает ответом.

# product_platform_prefix — приставка имени платформы, ВЫВЕДЕННАЯ из ответов.
#
# У части, имя которой правило ВЫВОДИТ, ответ оканчивается именем её каталога
# (`vpc` → `kacho-vpc`), и остаток — это и есть приставка. Часть со СВОИМ именем
# продукта (`iam` → `kaname`) на имя каталога не оканчивается и приставки не
# даёт; такая часть опознаётся членством, а не приставкой.
#
# Выписать приставку литералом было бы дешевле на вид и дороже по существу: это
# третье место об одном предмете (первые два — `platformPrefix` в Go и ведомость),
# и разошлось бы оно молча — ровно как разошлась приставка в этих скриптах.
#
# Пусто — законный ответ: приставки нет, если ВСЕ загруженные части переименованы.
# Вызывающий тогда судит одним членством, и это верно, а не досадно.
product_platform_prefix() {
  local dir name
  for dir in "${!_PRODUCT_IMAGE_NAME[@]}"; do
    name="${_PRODUCT_IMAGE_NAME[$dir]}"
    case "$name" in
      *"-$dir") printf '%s\n' "${name%"$dir"}"; return 0 ;;
    esac
  done
  return 0
}

# product_image_is_ours ССЫЛКА — образ по этой ссылке собран нами?
#
# Судится ПОСЛЕДНИЙ сегмент ссылки без тега: `docker.io/library/kacho-vpc:dev` и
# `prorobotech/kaname:<тег>` — наши; `docker.io/bitnami/postgresql:16.4.0`,
# `hydra:v26.2.0` и голая ссылка по дайджесту — чужие.
#
# Признак — членство в именах частей ЛИБО приставка платформы, и порядок здесь
# несущий: приставка покрывает то, что частью под `services/` не является
# (образы модулей консоли), а членство — то, у чего приставки нет by
# construction. Одного признака мало НИ ОДНОГО из двух.
#
# ПРЕДПОСЫЛКА: имена уже загружены `product_names_load`. Незагруженные имена —
# это «не спрашивали», а не «не наше», поэтому пустая ведомость ОТКАЗЫВАЕТ, а не
# отвечает «чужой» на всё подряд: молчаливое «чужой» и есть тот дефект, ради
# которого функция заведена.
product_image_is_ours() {
  local ref="${1##*/}" last prefix
  last="${ref%%:*}"
  if [ "${#_PRODUCT_IMAGE_NAME[@]}" -eq 0 ]; then
    echo "product-names: имена частей не загружены — на вопрос «наш ли образ» отвечать нечем." >&2
    echo "               Позовите product_names_load до первого обращения." >&2
    return 2
  fi
  local dir
  for dir in "${!_PRODUCT_IMAGE_NAME[@]}"; do
    [ "$last" = "${_PRODUCT_IMAGE_NAME[$dir]}" ] && return 0
  done
  prefix="$(product_platform_prefix)"
  [ -n "$prefix" ] || return 1
  case "$last" in "$prefix"?*) return 0 ;; esac
  return 1
}

# product_service_dirs — каталоги частей под `services/`, взятые у ИНДЕКСА GIT.
#
# Состав берётся у индекса, а не с диска, по той же причине, по какой его берёт
# оттуда гейт рецептов стенда: под деревом лежат распакованные чужие чарты и
# рабочие каталоги, и обход диска считал бы их частями продукта.
#
# Зачем перечень нужен здесь: ведомость собственных имён закрыта и её ключи —
# каталоги под `services/`, поэтому загрузка ИМЕННО этого перечня даёт все имена,
# которые приставкой не выводятся. Всё остальное покрывает приставка.
product_service_dirs() {
  local root
  root="$(_product_names_root)" || return 1
  git -C "$root" ls-files -- 'services/*' \
    | sed -n 's#^services/\([^/]*\)/.*#\1#p' \
    | sort -u
}
