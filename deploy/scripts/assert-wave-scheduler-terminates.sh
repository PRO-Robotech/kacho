# assert-wave-scheduler-terminates.sh — планировщик суит обязан ЗАВЕРШАТЬСЯ, когда
# рядом живут вечные фоновые процессы.
#
# ПРЕДМЕТ И ЦЕНА. newman-parallel.sh держит в фоне ВОСЕМЬ пробросов портов, которые
# по построению не завершаются: они живут ровно столько, сколько прогон. Любой
# ограничитель одновременности, написанный через `jobs -rp | wc -l` или голый
# `wait` / `wait -n` без списка pid'ов, считает и ждёт ИХ ТОЖЕ — и встаёт навсегда
# на первой же итерации.
#
# Почему это нужно ловить отдельно, а не «увидеть в прогоне»: симптом лжёт.
# Зависший планировщик убивается таймаутом шага, out/ остаётся пустым, и все гейты
# суит честно печатают «(no-report)». То есть отказ ПЛАНИРОВЩИКА выглядит как
# «продукт не отвечает ни на один запрос» — диагноз уводит в другую сторону на
# полный цикл стенда (десятки минут раннера на прогон, который не мог отчитаться).
# Найдено ровно так 2026-08-05, на первом же прогоне после снятия конкуренции.
#
# ЧТО УТВЕРЖДАЕТСЯ. Планировщик, извлечённый ИЗ newman-parallel.sh (а не переписанный
# здесь — иначе проверялась бы копия), при WAVE_JOBS=1 и живом вечном фоновом
# процессе:
#   * запускает все задачи и завершается в отведённый срок;
#   * исполняет их ПО ОДНОЙ (перекрытия нет).
# Инъекция в обратную сторону: та же форма, переписанная на `jobs -rp`/`wait -n`,
# обязана ЗАВИСНУТЬ — иначе проверка ничего не измеряет.
set -uo pipefail

# У этого гейта ОДИН режим, и это не небрежность: всё его содержимое — пара инъекций
# (живая форма обязана завершиться, прежняя — зависнуть). Отдельного «обычного
# прохода» у него нет и быть не может: предмет наблюдается только созданием условия.
# `--self-test` принимается, потому что по нему общий прогонщик самопроверок
# (run-gate-self-tests.sh) находит и зовёт гейты; поведение от флага не зависит,
# и здесь это сказано прямо, а не оставлено читателю в догадку.
if [ $# -gt 0 ] && [ "${1:-}" != "--self-test" ]; then
  echo "usage: $0 [--self-test]" >&2
  exit 2
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$SCRIPT_DIR/newman-parallel.sh"
BUDGET="${BUDGET:-20}"
rc=0

[ -f "$SRC" ] || { echo "FATAL: не найден $SRC — проверять нечего"; exit 2; }

# Извлекаем ЖИВОЙ текст ограничителя из прогонщика. Предпосылка проверяется: нет
# функции — отказ, а не тишина (её могли переименовать, и тогда эта проверка
# сторожит уже не то).
limiter="$(awk '/^_wave_wait_below\(\) \{/,/^\}/' "$SRC")"
if [ -z "$limiter" ]; then
  echo "FATAL: в $SRC нет функции _wave_wait_below — предпосылка проверки отпала."
  echo "       Её могли переименовать; тогда чинить надо ЭТУ проверку, а не молчать."
  exit 2
fi

run_case() { # <label> <тело ограничителя> <ожидание: ok|hang>
  local label="$1" body="$2" want="$3"
  local dir; dir="$(mktemp -d)"
  cat > "$dir/harness.sh" <<HARNESS
set -uo pipefail
WAVE_JOBS=1
WAVE_RUNNING=()
$body
# Вечный фоновый процесс — модель проброса порта: он не завершится сам.
sleep 3600 & FOREVER=\$!
for i in 1 2 3; do
  _wave_wait_below "\$WAVE_JOBS"
  ( echo "\$(date +%s%N) start" >> "$dir/order"; sleep 1; echo "\$(date +%s%N) end" >> "$dir/order" ) &
  WAVE_RUNNING+=("\$!")
done
_wave_wait_below 1
kill \$FOREVER 2>/dev/null
echo DONE > "$dir/done"
HARNESS
  timeout "$BUDGET" bash "$dir/harness.sh" >/dev/null 2>&1
  local got="hang"; [ -f "$dir/done" ] && got="ok"
  # Перекрытия быть не должно: при WAVE_JOBS=1 порядок строго start,end,start,end,…
  local overlap="нет"
  if [ "$got" = ok ]; then
    local seq; seq="$(sort -n "$dir/order" | awk '{print $2}' | tr '\n' ' ')"
    [ "$seq" = "start end start end start end " ] || overlap="ЕСТЬ ($seq)"
  fi
  if [ "$got" = "$want" ] && { [ "$want" = hang ] || [ "$overlap" = "нет" ]; }; then
    echo "  ОК  $label → $got (ждали $want), перекрытие: $overlap"
  else
    echo "  ПРОВАЛ $label → $got (ждали $want), перекрытие: $overlap"
    rc=1
  fi
  rm -rf "$dir"
}

echo "=== планировщик волны: завершается ли он при живом вечном фоне ==="
run_case "живой ограничитель из newman-parallel.sh" "$limiter" ok

# ИНЪЕКЦИЯ: прежняя форма, считающая ВСЕ фоновые задания шелла. Обязана зависнуть —
# если и она проходит, значит проверка не создаёт условия и ничего не измеряет.
run_case "инъекция: 'jobs -rp | wc -l' + голый 'wait -n'" \
'_wave_wait_below() { while [ "$(jobs -rp | wc -l)" -ge "$1" ]; do wait -n; done; }' hang

echo
if [ "$rc" -eq 0 ]; then
  echo "PASS: планировщик ждёт ТОЛЬКО свои суиты и завершается; прежняя форма — виснет."
else
  echo "FAIL: планировщик волны не доказал завершаемость."
fi
exit "$rc"
