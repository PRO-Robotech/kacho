# ОЖИДАНИЕ И ОСТАНОВКА ИДУТ ПО ЗАХВАЧЕННОМУ ИДЕНТИФИКАТОРУ ПРОЦЕССА, А НЕ ПО
# ШАБЛОНУ КОМАНДНОЙ СТРОКИ.
#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Поиск процессов по шаблону командной строки сопоставляет шаблон и с командной
# строкой ТОГО, КТО СПРАШИВАЕТ. Отсюда две поломки, обе тихие:
#
#   • сторожевая петля вида «ждать, пока никого не найдено» НЕ ЗАВЕРШАЕТСЯ
#     НИКОГДА — ждущий находит сам себя и ждёт своего же исчезновения;
#   • остановка по шаблону сносит ждущего ВМЕСТЕ с ожидаемым, а заодно чужие
#     оболочки, чья командная строка случайно содержит те же слова.
#
# ЗА ОДИН ДЕНЬ ЭТО СРАБОТАЛО ЧЕТЫРЕ РАЗА у разных исполнителей: дважды держало
# рабочий слот впустую до самого обрыва, один раз убило чужие оболочки, один раз
# — собственные.
#
# ПОЧЕМУ ГЕЙТ, А НЕ УСТНОЕ ПРАВИЛО. Класс повторяется ИМЕННО ПОТОМУ, что знание
# о нём нигде в дереве не записано: каждый следующий пишет ту же конструкцию с
# нуля, она выглядит очевидно правильной, а отказ проявляется как «висит
# непонятно почему» — то есть маскируется под нагрузку или под медленный тест.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО СЧИТАЕТСЯ ЗАКОННЫМ
#
# Сужение, исключающее себя, — любое из:
#   • ожидание по ЗАХВАЧЕННОМУ идентификатору (`wait "$pid"`, `kill -0 "$pid"`) —
#     тогда поиска по шаблону нет вовсе и гейту нечего находить;
#   • `-P` / `--parent` — область сужена до потомков названного процесса;
#   • явное исключение собственного идентификатора (`$$` / `$BASHPID` в том же
#     выражении);
#   • поиск БЕЗ `-f` — сопоставляется имя исполняемого файла, а не командная
#     строка, поэтому оболочка-ждущий под него не попадает.
#
# ЧИТАЕТСЯ ИСПОЛНЯЕМАЯ ЧАСТЬ, А НЕ ТЕКСТ. Тот же шаблон в комментарии,
# ОБЪЯСНЯЮЩЕМ запрет, краснеть не должен — иначе первый же гейт этого класса
# красит сам себя и его снимают при первом ложном срабатывании. Этот файл —
# проверка на себе: он содержит запрещённую форму в прозе многократно и обязан
# остаться вне находок.
#
# «НОЛЬ НАХОДОК» ОБЯЗАНО ОТЛИЧАТЬСЯ ОТ «НОЛЬ ПРОЧИТАННОГО»: перепись осмотренного
# печатается отдельным утверждением, и пустой обход — ПРОВАЛ.
# ─────────────────────────────────────────────────────────────────────────────
set -uo pipefail

SCRIPT="$(basename "$0")"
DEPLOY_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "$DEPLOY_ROOT/.." && pwd)"

# ═════════════════════════════════════════════════════════════════════════════
# ПРЕДИКАТ — ЧИСТАЯ ФУНКЦИЯ НАД ОДНИМ ФАЙЛОМ.
#
# Печатает по строке на находку: `<номер строки>|<вид>|<исполняемый текст>`.
# Вынесен затем, чтобы самопроверка кормила его синтетическими файлами БЕЗ
# обхода дерева и требовала покраснеть на дефектной форме и промолчать на
# законной той же формы.
# ═════════════════════════════════════════════════════════════════════════════
scan_file() {
  python3 - "$1" <<'PY'
import sys, re

path = sys.argv[1]
try:
    with open(path, "rb") as fh:
        blob = fh.read()
except OSError:
    sys.exit(0)
# Двоичный файл — не сценарий; читать его построчно нечестно. Признак — нулевой
# байт: в дереве лежит собранный исполняемый файл, чьи строки содержат и `pkill`,
# и что угодно ещё. Проверка «не декодируется как UTF-8» этого НЕ ловит: начало
# ELF из одних младших байтов декодируется прекрасно (померено на себе).
if b"\x00" in blob[:8192]:
    sys.exit(0)
try:
    lines = blob.decode("utf-8").splitlines()
except UnicodeDecodeError:
    sys.exit(0)

# Поиск по шаблону командной строки: `pgrep`/`pkill` с флагом -f в любой позиции
# и в любой связке (`-af`, `-9 -f`, `--full`).
HIT = re.compile(r"\bp(grep|kill)\b(?P<args>[^;&|)]*)")
FULL = re.compile(r"(?<![\w-])-[a-zA-Z]*f(?![\w-])|--full")

# Сужения, исключающие себя.
NARROWED = re.compile(r"(?<![\w-])-P(?![\w-])|--parent|\$\$|\$BASHPID")

def split_line(line):
    """→ (код с СОДЕРЖИМЫМ литералов, код с ВЫЧИЩЕННЫМИ литералами).

    Комментарий отбрасывается в обоих, но решётка внутри литерала комментария не
    начинает. Литералы вычищаются, потому что запрет обязан различать КОД и
    СТРОКУ: `echo 'не пиши until ! p<…> -f'` — объяснение запрета, а не его
    нарушение, и именно на этом гейт этого класса краснеет ложно и снимается.
    Сужение же (`$$`) ищется по варианту С литералами: `| grep -v "^$$"` —
    законная и распространённая запись.
    """
    kept, blanked, quote = [], [], None
    for i, ch in enumerate(line):
        if quote:
            kept.append(ch)
            blanked.append(" " if ch != quote else ch)
            if ch == quote and (i == 0 or line[i - 1] != "\\"):
                quote = None
            continue
        if ch in "'\"":
            quote = ch
            kept.append(ch)
            blanked.append(ch)
            continue
        if ch == "#":
            break
        kept.append(ch)
        blanked.append(ch)
    return "".join(kept), "".join(blanked)

for n, raw in enumerate(lines, 1):
    code, code_nostr = split_line(raw)
    if not code_nostr.strip():
        continue
    m = HIT.search(code_nostr)
    if not m:
        continue
    args = m.group("args")
    if not FULL.search(args):
        continue                      # ищет по имени, а не по командной строке
    if NARROWED.search(code):
        continue                      # сужение, исключающее себя, есть
    kind = "остановка" if "pkill" in m.group(0) else "поиск"
    if re.search(r"\b(until|while)\b", code):
        kind = "сторожевая петля"
    print("%d|%s|%s" % (n, kind, code.strip()[:160]))
PY
}

# ═════════════════════════════════════════════════════════════════════════════
# САМОПРОВЕРКА — БЕЗ ДЕРЕВА.
# ═════════════════════════════════════════════════════════════════════════════
if [ "${1:-}" = "--self-test" ]; then
  echo "=== $SCRIPT --self-test: инъекции в обе стороны ==="
  rc=0; checked=0
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

  # Запрещённые формы СОБИРАЮТСЯ из подстановки, а не пишутся литералом: литерал
  # сделал бы этот файл своей же находкой, и «гейт себя не находит» держалось бы
  # на везении, а не на предикате.
  G="p""grep"; K="p""kill"

  probe() { # <метка> <ожидание: red|silent> <строка кода>
    local label="$1" want="$2" code="$3" got
    checked=$((checked + 1))
    printf '#!/usr/bin/env bash\n%s\n' "$code" >"$tmp/probe.sh"
    got="$(scan_file "$tmp/probe.sh")"
    if [ "$want" = red ]; then
      if [ -n "$got" ]; then echo "  ✓ $label — находка: $(cut -d'|' -f1,2 <<<"$got" | tr '\n' ' ')"
      else echo "  ✗ $label — НЕ покраснел на внесённом дефекте"; rc=1; fi
    else
      if [ -z "$got" ]; then echo "  ✓ $label — молчит (законная конструкция)"
      else echo "  ✗ $label — покраснел на ЗАКОННОЙ конструкции: $got"; rc=1; fi
    fi
  }

  echo "-- дефектные формы обязаны краснеть --"
  probe "сторожевая петля по шаблону" red "until ! $G -f 'newman-run'; do sleep 2; done"
  probe "ожидание «пока найдено» по шаблону" red "while $G -f 'go test' >/dev/null; do sleep 5; done"
  probe "остановка по шаблону" red "$K -f 'port-forward'"
  probe "остановка по шаблону с сигналом" red "$K -9 -f 'kubectl port-forward'"
  probe "длинный флаг" red "$G --full 'suite'"
  probe "склеенные флаги" red "$G -af 'suite' | wc -l"

  echo
  echo "-- законные конструкции ТОЙ ЖЕ ФОРМЫ обязаны молчать --"
  probe "ожидание по захваченному идентификатору" silent 'wait "$pid"'
  probe "ожидание по захваченному идентификатору в петле" silent \
    'until ! kill -0 "$pid" 2>/dev/null; do sleep 1; done'
  probe "остановка по захваченному идентификатору" silent 'kill "$pid" 2>/dev/null'
  probe "поиск, суженный до потомков" silent "$G -P \$\$ -f 'child'"
  probe "поиск с исключением собственного идентификатора" silent \
    "$G -f 'suite' | grep -v \"^\$\$\$\""
  probe "поиск по имени исполняемого файла, а не по командной строке" silent "$G nginx"
  probe "запрещённая форма В КОММЕНТАРИИ" silent "# нельзя: until ! $G -f 'x'; do :; done"
  probe "запрещённая форма в объясняющей строке вывода" silent \
    "echo 'не пиши until ! $G -f' # так объясняют запрет"

  echo
  echo "-- гейт не находит САМ СЕБЯ --"
  checked=$((checked + 1))
  self="$(scan_file "$0")"
  if [ -z "$self" ]; then
    echo "  ✓ собственная проза с запрещённой формой находкой не признана"
  else
    echo "  ✗ гейт нашёл сам себя — предикат читает текст, а не исполняемую часть:"
    sed 's/^/      /' <<<"$self"; rc=1
  fi

  echo
  echo "-- двоичный файл не читается как сценарий --"
  checked=$((checked + 1))
  printf '\x7fELF\x02\x01\x01\x00%s' "$K -f x" >"$tmp/bin"
  if [ -z "$(scan_file "$tmp/bin")" ]; then
    echo "  ✓ двоичный файл пропущен, а не разобран построчно"
  else
    echo "  ✗ двоичный файл принят за сценарий"; rc=1
  fi

  echo
  echo "инъекций и законных входов проверено: $checked"
  [ $rc -eq 0 ] && echo "PASS: $SCRIPT --self-test" || echo "FAIL: $SCRIPT --self-test"
  exit $rc
fi

# ═════════════════════════════════════════════════════════════════════════════
# ОСНОВНОЙ ПРОХОД — ПО СОДЕРЖИМОМУ РЕПОЗИТОРИЯ.
#
# Обход идёт по `git ls-files`: это то же множество, что увидит CI на свежем
# checkout'е, поэтому вердикт воспроизводим и не зависит от локального мусора.
# ═════════════════════════════════════════════════════════════════════════════
cd "$REPO_ROOT" || exit 2
git rev-parse --git-dir >/dev/null 2>&1 || { echo "FATAL: не репозиторий: $REPO_ROOT"; exit 2; }

echo "=== $SCRIPT: ожидание и остановка — по захваченному идентификатору ==="

files=0; findings=0
FOUND=""
while IFS= read -r -d '' f; do
  [ -f "$f" ] || continue
  files=$((files + 1))
  hits="$(scan_file "$f")"
  [ -z "$hits" ] && continue
  while IFS= read -r h; do
    [ -z "$h" ] && continue
    findings=$((findings + 1))
    FOUND="$FOUND$f:${h%%|*} [$(cut -d'|' -f2 <<<"$h")] $(cut -d'|' -f3- <<<"$h")"$'\n'
  done <<<"$hits"
done < <(git ls-files -z '*.sh' '*.bash' '*.py' 'Makefile' '*/Makefile' '*.mk' '.github/workflows/*.yml' '.github/workflows/*.yaml')

echo
echo "── объём осмотренного ──"
echo "  файлов прочитано: $files"
if [ "$files" -eq 0 ]; then
  echo
  echo "FAIL: не прочитано НИ ОДНОГО файла — «ноль находок» здесь означало бы"
  echo "      «ноль прочитанного», а не «всё хорошо»."
  exit 1
fi

echo
if [ "$findings" -ne 0 ]; then
  echo "=== вердикт: файлов $files, находок $findings ==="
  printf '%s' "$FOUND" | sed 's/^/  ✗ /'
  echo
  echo "Починка: ждать и останавливать по ЗАХВАЧЕННОМУ идентификатору."
  echo "  cmd & pid=\$!;  wait \"\$pid\""
  echo "  until ! kill -0 \"\$pid\" 2>/dev/null; do sleep 1; done"
  echo "  kill \"\$pid\" 2>/dev/null"
  echo "Если поиск по шаблону действительно нужен — сузить область: -P <родитель>"
  echo "либо исключить собственный идентификатор (\$\$), либо искать по имени"
  echo "исполняемого файла (без -f)."
  echo "FAIL: $SCRIPT"
  exit 1
fi

echo "=== вердикт: файлов $files, находок 0 ==="
echo "PASS: $SCRIPT"
