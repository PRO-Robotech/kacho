#
# ─────────────────────────────────────────────────────────────────────────────
# ПРЕДМЕТ
#
# Гейт посадки читает живые процессы кластера АКТИВНОГО контекста. Имя контекста
# — локальный ярлык автора kubeconfig: одноимённый контекст однажды уже вёл в
# другой кластер. Поэтому цель пинится по КЛАСТЕРУ — по адресу apiserver'а, с
# которым kubectl действительно говорит, — а сверяется он с авторитетом, который
# переименованием контекста не подделать:
#
#   • стенд kind (умолчание): адрес, который выдаёт про кластер сам движок
#     (`kind get kubeconfig --name $CLUSTER_NAME`); имя контекста `kind-<имя>` —
#     первый отсев ради внятного совета оператору;
#   • стенд вне kind: адрес из ОБЪЯВЛЕНИЯ стенда — `STAND_APISERVER`. kind о таком
#     кластере не знает, и прежде гейт отказывал на нём целиком («не kind-kacho»),
#     хотя части A–C судили его исправно, — вердикта посадки стенд вне kind не
#     получал вовсе.
#
# Почему объявление — вход, а не строка stacks.txt: таблица стеков называет
# ЦЕПОЧКУ профилей, а адрес управляемого кластера — сведение об инфраструктуре
# площадки, которому в публичном дереве не место. Его объявляет оператор стенда
# при вызове, рядом с выбором контекста.
#
# ─────────────────────────────────────────────────────────────────────────────
# ИСХОДЫ
#
#   0 — активный кластер совпал с объявленным (печатается, с каким именно);
#   2 — УСЛОВИЕ НЕ СОЗДАНО: активный кластер не объявленный либо сверить не с
#       чем. Это не вердикт о посадке и не частичный вердикт: судить чужой
#       кластер значит вынести суждение не о том предмете.
set -uo pipefail

ctx="$(kubectl config current-context 2>/dev/null)"
have_srv="$(kubectl config view --minify -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null)"

if [ -n "${STAND_APISERVER:-}" ]; then
  if [ -z "$have_srv" ]; then
    echo "ABORT: УСЛОВИЕ НЕ СОЗДАНО — активный контекст «${ctx:-<нет>}» не отдал адрес apiserver'а;"
    echo "       объявлен $STAND_APISERVER, сверить не с чем."
    exit 2
  fi
  if [ "$have_srv" != "$STAND_APISERVER" ]; then
    echo "ABORT: УСЛОВИЕ НЕ СОЗДАНО — объявлен $STAND_APISERVER, активный контекст «$ctx» ведёт в $have_srv."
    echo "       Гейт судит живые процессы АКТИВНОГО кластера — вердикт был бы о другом стенде."
    echo "       Переключись на контекст объявленного стенда либо объяви тот, что активен."
    exit 2
  fi
  echo "=== цель: стенд вне kind — контекст «$ctx», apiserver совпал с объявлением STAND_APISERVER ==="
  exit 0
fi

# ИМЯ КЛАСТЕРА БЕРЁТСЯ ИЗ ОКРУЖЕНИЯ, А НЕ ВЫПИСЫВАЕТСЯ. Шарды сквозных проб
# поднимают каждый свой кластер (`kacho-iam`, `kacho-vpc`, …), и выписанное имя
# делает гейт неисполнимым на всех, кроме одного. Умолчание совпадает с
# объявлением сборки, поэтому одиночный стенд ведёт себя как прежде.
CLUSTER_NAME="${CLUSTER_NAME:-kacho}"
case "$ctx" in
  "kind-$CLUSTER_NAME") ;;
  *) echo "ABORT: активный kube-контекст '$ctx' — не kind-$CLUSTER_NAME."
     echo "       Стенд вне kind объявляется адресом apiserver'а: STAND_APISERVER=<адрес>."
     exit 2 ;;
esac
want_srv="$(kind get kubeconfig --name "$CLUSTER_NAME" 2>/dev/null | sed -n 's/^ *server: *//p' | head -1)"
if [ -z "$want_srv" ]; then
  echo "ABORT: kind не знает кластера '$CLUSTER_NAME' — сверить адрес apiserver'а НЕ С ЧЕМ,"
  echo "       а «не с чем сверить» означает «не проверили», а не «всё хорошо»."
  exit 2
fi
if [ "$want_srv" != "$have_srv" ]; then
  echo "ABORT: контекст называется kind-'$CLUSTER_NAME', но ведёт НЕ в этот кластер."
  echo "       активный → $have_srv"
  echo "       kind-$CLUSTER_NAME на самом деле → $want_srv"
  exit 2
fi
exit 0
