// shellcheck_directives_parse_test.go — директива отключения правила обязана
// РАЗБИРАТЬСЯ. Иначе отключение, задуманное узким, оказывается полным.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Директива несёт список `ключ=значение`. Первый токен, который на `ключ=значение`
// не похож и не начинает комментарий, обрывает разбор — инструмент отвечает
// SC1072/SC1073, то есть ошибкой РАЗБОРА, а не находкой.
//
// Цена не в одной строке: файл выпадает из-под проверки ЦЕЛИКОМ. Замер на
// наблюдавшемся экземпляре (задача #1770): у формы с прозой после кода правила
// само правило НЕ подавлено (SC2086 всплывает) И к нему прибавляются четыре
// строки о неразобранной директиве. Со стороны это выглядит как одна ошибка в
// одной строке — поэтому класс и живёт долго.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГЕЙТ СУДИТ ФОРМУ, А НЕ ЗОВЁТ ИНСТРУМЕНТ — И ЭТО РЕШЕНИЕ
//
// Позвать shellcheck было бы точнее, но проверка над внешним инструментом умеет
// ПРОПУСТИТЬСЯ («условие не создано»), а пропущенная проверка не краснеет
// никогда. Здесь предмет — синтаксис директивы, он объявлен самим инструментом
// и от его наличия не зависит; поэтому разбор свой, детерминированный.
//
// ─────────────────────────────────────────────────────────────────────────────
// РАСПОЗНАВАТЕЛЬ ЗНАЕТ ВСЕ ЗАКОННЫЕ ФОРМЫ — ПЕРЕЧЕНЬ СНЯТ ЗАПУСКОМ
//
// `testing.md` §«Гейт на класс», п.7: форма, о которой распознаватель не знает,
// хуже незнакомой — он о ней «знает» неверно. Формы ниже проверены запуском
// настоящего shellcheck 0.11.0, а не выведены из документации:
//
//	# shellcheck disable=SC2086                → разбирается
//	#shellcheck disable=SC2086                 → разбирается (пробел не обязателен)
//	# shellcheck  disable=SC2086               → разбирается (пробелов сколько угодно)
//	# shellcheck disable=SC2086,SC2034         → разбирается (список через запятую)
//	# shellcheck shell=bash disable=SC2086     → разбирается (несколько ключей)
//	# shellcheck disable=SC2086 # проза        → разбирается: `#` начинает комментарий
//	# shellcheck disable=SC2086  #проза        → разбирается (пробел после `#` не нужен)
//	# shellcheck disable=SC2086 -- проза       → НЕ разбирается
//	# shellcheck disable=SC2086 проза          → НЕ разбирается
//
// Шестая и седьмая формы — ЗАКОННЫЕ БЛИЗНЕЦЫ, и они не гипотетические: в
// `deploy/` их шесть. Наивный предикат «после кода правила ничего нет» объявил
// бы находкой каждую и был бы отключён первым же прогоном.
package deploy_test

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// scDirective — начало директивы. Регистр имени инструмента shellcheck считает
// значимым, поэтому и здесь он значим.
var scDirective = regexp.MustCompile(`^[[:space:]]*#[[:space:]]*shellcheck[[:space:]]+(.*)$`)

// scKeyValue — токен, который разбор принимает. Значение непусто: `key=` тоже
// обрывает разбор, и объявлять его законным значило бы завести слепую зону.
var scKeyValue = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_-]*=[^[:space:]]+$`)

// scDirectiveFault — почему директива не разберётся. Пустая строка означает
// «разберётся».
func scDirectiveFault(rest string) string {
	for _, tok := range strings.Fields(rest) {
		if strings.HasPrefix(tok, "#") {
			return "" // дальше комментарий; разбор его не читает
		}
		if !scKeyValue.MatchString(tok) {
			return fmt.Sprintf("токен %q не имеет вида ключ=значение и не начинает комментарий", tok)
		}
	}
	return ""
}

// scScan — обход и вердикт ОДНОЙ функцией, чтобы доказательство инъекцией
// прогоняло ГЕЙТ, а не только его распознаватель. Проба, зовущая распознаватель
// напрямую, закрепляет ОТВЕТ, а не МЕСТО (`testing.md` §«Гейт на класс», п.6).
func scScan(t *testing.T, root string) (files, directives int, findings []string) {
	t.Helper()
	var list []string
	err := filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			// Вендоренные и произведённые деревья не судятся: их директивы
			// принадлежат чужим авторам, и находка в них не чинится здесь.
			switch d.Name() {
			case "charts", "node_modules", ".git", "out":
				return filepath.SkipDir
			}
			return nil
		}
		switch filepath.Ext(p) {
		case ".sh", ".bash":
			list = append(list, p)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("обход %s не удался: %v", root, err)
	}
	sort.Strings(list)

	for _, f := range list {
		b, rerr := os.ReadFile(f)
		if rerr != nil {
			t.Fatalf("%s: %v", f, rerr)
		}
		for i, line := range strings.Split(string(b), "\n") {
			m := scDirective.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			directives++
			if why := scDirectiveFault(m[1]); why != "" {
				findings = append(findings, fmt.Sprintf(
					"%s:%d — %s; директива не разберётся (SC1072/SC1073), и ФАЙЛ ВЫПАДЕТ ИЗ-ПОД ПРОВЕРКИ ЦЕЛИКОМ, "+
						"а само правило останется НЕ отключённым. Пояснение выносится отдельной строкой либо после `#`",
					f, i+1, why))
			}
		}
	}
	return len(list), directives, findings
}

func TestShellcheckDirectivesParse(t *testing.T) {
	files, directives, findings := scScan(t, ".")

	// Объём осмотренного печатается ВСЕГДА: «ноль находок» обязано быть отличимо
	// от «ноль прочитанного».
	t.Logf("перепись: оболочечных файлов %d · директив shellcheck %d · находок %d",
		files, directives, len(findings))

	// Предпосылка гейта проверяется им самим: пустой обход — не «всё чисто».
	if files == 0 {
		t.Fatal("обход не нашёл НИ ОДНОГО оболочечного файла — вердикт беспредметен")
	}
	if directives == 0 {
		t.Fatal("директив shellcheck не найдено НИ ОДНОЙ — распознаватель ослеп либо их правда не стало; " +
			"второе означает, что гейт пережил свой предмет и снимается вместе с ним")
	}

	for _, f := range findings {
		t.Error(f)
	}
}
