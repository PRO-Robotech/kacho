#!/usr/bin/env node
// Установлены ли зависимости пакета консоли — ОДИН предикат на всё дерево.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Пакет без `node_modules` роняет прогон текстом `Cannot find module …jest.js`,
// `MODULE_NOT_FOUND`, `Node.js v22.x` и кодом 1 — то есть ровно тем, чем
// выглядит упавшая проба. А это ТРЕТЬЯ категория исхода: вердикта нет НИ У ОДНОЙ
// пробы, включая те, что успели бы пройти. Она не вычитается из вердикта и не
// зачитывается в успех.
//
// Различить это стоит одной команды — и её надо ЗНАТЬ. Прогонщик `ci-local.sh`
// различал, потому что спрашивал перед прогоном; прямой `npm test` (форма, в
// которой пакеты консоли зовёт корневой `package.json`, конвейер и всякий
// человек) не спрашивал ничего. Наблюдалось живьём: сквозная чистка диска сняла
// `node_modules` во всех тридцати рабочих копиях разом, посреди прогона, — и
// отказ пришёл именно в виде `MODULE_NOT_FOUND`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗДЕСЬ, А НЕ ВТОРОЙ КОПИЕЙ В bash
//
// Предикат нетривиален: у члена воркспейса зависимости лежат в КОРНЕ, у
// standalone-пакета — у него самого, и перепутать эти два случая значит объявить
// готовым то, что не готово. `scripts/ci-local.sh` зовёт этот же файл — два
// места об одном предмете разошлись бы молча, и разошлись бы именно там, где
// расхождение не видно: оба ответа выглядят правдоподобно.
//
// Состав перечня членов НЕ ВЫПИСАН — он читается из корневого `package.json`.
//
// ─────────────────────────────────────────────────────────────────────────────
// КОД ВОЗВРАТА
//
//	0 — зависимости на месте, прогон осмыслен;
//	3 — НЕ ВЫПОЛНЕНО (условие не создано). Тройка — уже принятое в этом дереве
//	    обозначение несостоявшегося прогона: `ci-local.sh` отвечает ею же, и хук
//	    отправки читает её как «вердикта нет», а не как «почините найденное».

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const UI_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

/** Каталог проверяемого пакета: аргумент либо cwd (npm зовёт скрипты из него). */
const pkgDir = resolve(process.argv[2] ?? process.cwd());
const pkgName = basename(pkgDir);

/**
 * Непустой каталог зависимостей. Именно НЕПУСТОЙ: оборванная установка оставляет
 * пустой `node_modules`, и проверка на существование объявила бы её готовой.
 */
function installed(dir) {
  const nm = join(dir, "node_modules");
  return existsSync(nm) && readdirSync(nm).length > 0;
}

function workspaceMembers() {
  const rootPkg = join(UI_ROOT, "package.json");
  if (!existsSync(rootPkg)) return [];
  const declared = JSON.parse(readFileSync(rootPkg, "utf8")).workspaces ?? [];
  return declared.map((entry) => basename(entry));
}

const isMember = workspaceMembers().includes(pkgName);
const needs = isMember ? UI_ROOT : pkgDir;

if (installed(needs)) process.exit(0);

const remedy = isMember
  ? `npm ci --prefix ${UI_ROOT}`
  : `npm ci --prefix ${pkgDir}   (пакет standalone: корневая установка его НЕ ставит)`;

process.stderr.write(
  `\nНЕ ВЫПОЛНЕНО: у пакета «${pkgName}» не установлены зависимости (${join(needs, "node_modules")}).\n` +
    `Это ТРЕТЬЯ категория исхода, а НЕ красный вердикт: ни одна проба не запускалась,\n` +
    `и вердикта нет ни у одной — включая те, что прошли бы. В зачёт успеха она тоже не идёт.\n` +
    `Не ищите регрессию: MODULE_NOT_FOUND здесь означает отсутствие условия, а не находку.\n` +
    `Условие создаётся так: ${remedy}\n\n`,
);
process.exit(3);
