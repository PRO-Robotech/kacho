// Тексты закрытых словарей storage, которые произносит ТОЛЬКО это приложение.
//
// # Что здесь, а что в @shared — и почему граница проходит именно так
//
// Словарь ТИПА ДИСКА (ярус, состояние обращения, способности) живёт в
// `@shared/lib/storage-disk-type`: его произносят два разных места консоли —
// карточка типа диска здесь и подпись опции в подборщике (`refOptionExtra`,
// общий на всё дерево). Держать его тут значило бы завести два места об одном
// предмете, и разошлись бы они на первом же уточнении формулировки, молча:
// обе стороны продолжали бы показывать что-то правдоподобное.
//
// Здесь остаётся то, что рисует только storage: причина состояния, подпись к
// промежуточному состоянию тома, границы размера (им нужен `formatBytes` этого
// приложения). Ниже — реэкспорт общего словаря, чтобы у кода storage было ОДНО
// место импорта: у реэкспорта нет тела, поэтому разойтись с источником он не
// может.
//
// # Почему таблица, а не печать значения как есть
//
// Контракт заменил свободные строки закрытыми словарями (`DiskType.tier`,
// `StatusReason`) именно затем, чтобы наружу не уходил текст бэкенда: гейт
// двухпроекционности перечисляет ИМЕНА полей и значения вида "pool-b-replicated"
// не видит. Печать `status_reason` как есть вернула бы этот канал с другой
// стороны — уже в интерфейсе. Поэтому текст берётся из таблицы по значению, а
// незнакомое значение показывается САМИМ значением и ничем больше (см. ниже).

