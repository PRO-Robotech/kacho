export function imageFormatText(v: unknown): string | null {
  const raw = typeof v === "string" ? v : "";
  if (!raw || raw === "FORMAT_UNSPECIFIED") return null;
  return IMAGE_FORMAT_LABEL[raw] ?? raw;
}
