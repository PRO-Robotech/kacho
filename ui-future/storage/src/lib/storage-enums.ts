// ──────────────────── промежуточные состояния тома ────────────────────

/**
 * Что происходит с томом, пока он НЕ готов.
 *
 * Том рождается в состоянии создания, а пригодным его делает сверщик — то есть
 * между успешным ответом на Create и работающим томом есть окно, и оно
 * наблюдаемо. Значок состояния сам по себе об этом не говорит: «Creating»
 * отвечает КАК называется состояние, но не отвечает, надо ли что-то делать и
 * чего ждать. Без этой строки окно читается как зависшая операция.
 *
 * Перечислены ТОЛЬКО промежуточные состояния. У готового тома строки нет вовсе
 * — не прочерк, а отсутствие (правило 9): «Available» самодостаточен, и подпись
 * под ним была бы шумом на каждой карточке.
 */
const VOLUME_TRANSIENT_HINT: Record<string, string> = {
  CREATING: "Хранилище готовит том. Подключить его к машине можно после того, как он станет доступен.",
  MIGRATING:
    "Том переезжает на другой тип диска — перенос длится. Если перенос отказал, данные остаются на исходном типе.",
  DELETING: "Том удаляется.",
};

/** Подпись к промежуточному состоянию — либо `null`, если состояние конечное. */
export function volumeTransientHint(status: unknown): string | null {
  const raw = typeof status === "string" ? status : "";
  return VOLUME_TRANSIENT_HINT[raw] ?? null;
}

// ──────────────────────── занятые байты тома ────────────────────────

/**
 * Фактически занятые байты словами — либо `null`, если бэкенд их не сообщил.
 *
 * Общий `formatBytes` здесь НЕ годится, и это не мелочь охвата. Он переводит
 * ноль в «—» — верно для размера тома (тома нулевого размера не бывает) и
 * НЕВЕРНО здесь: ноль занятых байт означает «том пуст», и это факт, а не его
 * отсутствие. Показав на нём «—», консоль сказала бы «не знаю» там, где сервер
 * ответил точно, — то есть ровно ту неправду, ради предотвращения которой поле
 * в контракте объявлено `optional`.
 *
 * Различие несёт САМО значение: `null` ⇒ строки нет вовсе (правило 9), «0 B» ⇒
 * строка есть и утверждает пустоту.
 */
export function usedBytesText(v: unknown): string | null {
  if (v === undefined || v === null || v === "") return null;
  const n = typeof v === "number" ? v : Number.parseInt(String(v), 10);
  if (!Number.isFinite(n) || n < 0) return null;
  if (n === 0) return "0 B";
  return formatBytes(n);
}

// ───────────────────────── границы размера ─────────────────────────

/** Число байт из int64-строки; `null`, если значения нет или оно не число. */
function toBytes(v: unknown): number | null {
  if (v === undefined || v === null || v === "") return null;
  const n = typeof v === "number" ? v : Number.parseInt(String(v), 10);
  return Number.isFinite(n) ? n : null;
}

/** Строка границ размера: подпись + значение СЛЕДСТВИЕМ.
 *
 *  Ноль означает «класс не сужает» — и это не то же самое, что «граница равна
 *  нулю». Печать «0 B» на месте отсутствующей границы утверждала бы о классе
 *  неправду: что он допускает том нулевого размера. Поэтому ноль превращается в
 *  фразу, а не в число. */
export interface SizeLimitFact {
  label: string;
  text: string;
}

/**
 * Границы размера словами — либо пустой массив, если класс не сужает НИЧЕГО.
 *
 * Пустой массив — сигнал вызывающему не показывать секцию вовсе (правило 9:
 * поле без источника не показывается). Три прочерка на месте трёх границ
 * читаются как «границы есть, но мы их не знаем».
 */
export function sizeLimitFacts(limits: DiskTypeSizeLimits | undefined): SizeLimitFact[] {
  const min = toBytes(limits?.min_size_bytes) ?? 0;
  const max = toBytes(limits?.max_size_bytes) ?? 0;
  const step = toBytes(limits?.size_step_bytes) ?? 0;
  if (min === 0 && max === 0 && step === 0) return [];
  return [
    { label: "Наименьший размер", text: min > 0 ? formatBytes(min) : "Класс не сужает снизу" },
    { label: "Наибольший размер", text: max > 0 ? formatBytes(max) : "Класс не сужает сверху" },
    { label: "Шаг размера", text: step > 0 ? `Кратно ${formatBytes(step)}` : "Кратность не требуется" },
  ];
}

// ─────────────────────── причина состояния ───────────────────────

/** Текст причины по значению закрытого словаря.
 *
 *  Каждая фраза отвечает на вопрос, который арендатор задаёт следующим: ждать
 *  или действовать. Именно ради этой разницы причина и заведена — один `status`
 *  не отличает «бэкенд не ответил, система вернётся» от «отказал по существу,
 *  идентичный повтор не пройдёт». */
export const STATUS_REASON_TEXT: Record<string, string> = {
  BACKEND_UNAVAILABLE: "Хранилище не ответило. Состояние временное — система вернётся к ресурсу сама.",
  BACKEND_REJECTED: "Хранилище отказало по существу запроса. Повтор тем же запросом не пройдёт.",
  BACKEND_CAPACITY_EXHAUSTED: "В хранилище нет места. Нужно освободить ёмкость или обратиться к администратору.",
  SOURCE_NOT_READY: "Источник (снимок или образ) ещё не готов.",
  PRECONDITION_FAILED: "Состояние ресурса не позволяет выполнить это действие.",
  INTERNAL_ERROR: "Внутренняя ошибка.",
};

/**
 * Причина состояния словами — либо `null`, если причины нет.
 *
 * `null` возвращается и на пустом значении, и на `STATUS_REASON_UNSPECIFIED`:
 * контракт называет их одним и тем же — «причины нет, ресурс в штатном
 * состоянии». Вызывающий обязан не показывать строку вовсе (правило 9: поле без
 * источника не показывается), а не рисовать прочерк — прочерк на месте причины
 * читается как «причина есть, но мы её не знаем».
 *
 * Незнакомое значение возвращается КАК ЕСТЬ. Оно не выдумывается и не глотается:
 * словарь мог пополниться раньше консоли, и показать сырой токен честнее, чем
 * промолчать о том, что ресурс не в порядке.
 */
export function statusReasonText(v: unknown): string | null {
  const raw = typeof v === "string" ? v : "";
  if (!raw || raw === "STATUS_REASON_UNSPECIFIED") return null;
  return STATUS_REASON_TEXT[raw] ?? raw;
}

