//
// Здесь лежал форк общего сборщика, и он отставал ровно в том, что видно в
// таблице:
//   • ветки логического формата (`format: "bool"`) у него не было вовсе —
//     булево доезжало до приведения к строке и печаталось литералом `true`
//     чужого языка (канон §5: «Булево не показывается сырым»). Ресурсам этого
//     модуля приходилось обходить сборщик собственным `render` колонки;
//   • ширины колонок он не задавал: колонка без ширины забирает весь остаток
//     себе, и значения расходились по экрану, а длинная подпись переносилась на
//     вторую строку, поднимая шапку таблицы;
//   • набор ссылок на потребителей показывал ПЕРВОГО и подпись «ещё N» —
//     число, из которого не узнать ни одного ресурса.
//
// Форма ресурса (`ResourceColumn` / `ResourceSpec`) объявлена в
// `@shared/lib/resource-spec` и у обоих реестров одна, поэтому общий сборщик
// принимает спеки этого модуля как свои.
