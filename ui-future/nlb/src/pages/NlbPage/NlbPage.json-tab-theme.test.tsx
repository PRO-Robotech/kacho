// Раздел балансировщика обязан загружаться на вкладке JSON.
//
// Предмет пробы — не «компонент рисует JSON» (это утверждает общая суита у
// самого компонента), а СВЯЗНОСТЬ поставщика и потребителя темы: поставщика
// ставит страница раздела (`NlbPage` → `ThemeProvider` из `@/lib/theme-context`),
// потребителя приводит оболочка ресурса (`ResourceShell` → `LazyJsonMonacoView`
// из `@/components/molecules/JsonMonacoView`). Если эти два импорта резолвятся
// в РАЗНЫЕ модули, объекты React-контекста разные, `useThemeMode` бросает — и
// бросок доходит до границы федеративного модуля, поэтому пользователь видит не
// пустую вкладку, а «Раздел «Load Balancer» недоступен. Модуль не загрузился».
// Наблюдалось на выкаченном стенде 2026-08-16.
//
// Импорты здесь взяты ДОСЛОВНО те же, что в продукте, и это существо пробы:
// написанная на `@shared/...` с обеих сторон, она была бы зелена при любом
// расколе — то есть не утверждала бы ничего.
//
// Почему не монтируется вся страница на адресе `.../json`: общий стенд antd
// подменяет `Tabs` компонентом, который рисует только `children`, а содержимое
// вкладок приезжает пропом `items` — до `LazyJsonMonacoView` такая проба не
// доходит by construction. Ограничение среды названо, а не обойдено молча.
//
// Чего эта проба НЕ закрывает и что остаётся долгом: наблюдаемое целиком —
// «раздел открывается на вкладке JSON у живой консоли» — видит только проба
// браузером, а её в `ui-future/e2e/specs/` нет (`ui.md` правило 12). Заведено
// предметом #479; здесь координата не называется, пока файла не существует —
// ссылка на ненаписанное читалась бы как готовое покрытие.

import { render } from "@testing-library/react";

// Поставщик — ровно тот, что ставит NlbPage.
import { ThemeProvider } from "@/lib/theme-context";
// Потребитель — ровно тот, что приводит ResourceShell (`LazyJsonMonacoView` —
// этот же компонент за `React.lazy`; прямой импорт делает падение читаемым, а
// не спрятанным внутрь Suspense).
import { JsonMonacoView } from "@/components/molecules/JsonMonacoView";

/** Подменённый редактор — единственный узел, несущий свойство `value`. */
function editorValue(container: HTMLElement): string | null {
  const el = container.querySelector<HTMLElement>("[value]");
  if (!el) throw new Error("узел редактора не найден");
  return el.getAttribute("value");
}

describe("вкладка JSON раздела балансировщика", () => {
  it("рисуется под поставщиком темы, который ставит страница раздела", () => {
    // verifies #479
    const { container } = render(
      <ThemeProvider>
        <JsonMonacoView data={{ id: "nlb-1", name: "front" }} />
      </ThemeProvider>,
    );

    expect(editorValue(container)).toBe('{\n  "id": "nlb-1",\n  "name": "front"\n}');
  });

  it("без поставщика темы отказывает — значит проба меряет связность, а не факт рендера", () => {
    // verifies #479
    //
    // Парный отрицательный контроль. Без него утверждение выше зеленело бы и на
    // компоненте, который тему не спрашивает вовсе, — то есть проба пережила бы
    // свой предмет, ничего об этом не сказав.
    expect(() => render(<JsonMonacoView data={{}} />)).toThrow(/useThemeMode must be used within/);
  });
});
