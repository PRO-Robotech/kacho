// Булево в ячейке таблицы — ФАКТ о ресурсе, названный следствием, а не `true`.
//
// ПРЕДМЕТ. Форма колонки объявлена ОДИН раз — в `@shared/lib/resource-spec`, и
// этот модуль импортирует её оттуда. Среди объявленных форматов есть `bool`, но
// разбор формата в ЭТОМ модуле такой ветки не имел: значение уезжало в
// умолчание и печаталось служебным словом `true`. Автор колонки при этом не
// получал ни отказа типов, ни находки — форма разрешена, показ неверен.
//
// ЧТО УТВЕРЖДАЕТСЯ — ОБЕ СТОРОНЫ И ОБА ВЫРОЖДЕННЫХ СЛУЧАЯ. Отрицание («не
// печатает true») в одиночку зеленело бы и на ячейке, не показывающей ничего,
// поэтому рядом стоят положительные контроли: истина и ложь называются своими
// фразами. Отсутствие значения остаётся ПРОЧЕРКОМ, а не превращается в «нет»:
// «сервер поля не прислал» и «у ресурса этого свойства нет» — разные
// утверждения, и подменять первое вторым значит говорить о ресурсе то, чего
// никто не проверял. Колонка без объявленных подписей — тоже прочерк: назвать
// следствие может только тот, кто знает предмет, и умолчание вернуло бы сюда
// ровно то «Да», ради снятия которого формат заведён.

import { render } from "@testing-library/react";
import type { ReactNode } from "react";

import { formatCellByFormat } from "./spec-columns";

function textOf(node: ReactNode): string {
  return render(<div>{node}</div>).container.textContent ?? "";
}

const LABELS = { yes: "Группа по умолчанию", no: "Назначается явно" };

/** Ячейка колонки формата `bool` над значением `v`.
 *
 *  Подписи передаются ВСЕГДА и без значения по умолчанию: параметр с умолчанием
 *  подставляет его и на явно переданный `undefined`, поэтому проба «колонка без
 *  подписей» рисовала бы колонку С подписями и утверждала о том, чего не
 *  проверяла. Первая редакция этой пробы так и делала — и осталась красной уже
 *  после починки продукта, чем себя и выдала. */
function boolCell(v: unknown, boolLabels?: { yes: string; no: string }): string {
  return textOf(
    formatCellByFormat({ header: "По умолчанию", path: "value", format: "bool", boolLabels }, { value: v }),
  );
}

describe("булево в ячейке показывается СЛЕДСТВИЕМ, а не служебным словом", () => {
  it("истина названа своей фразой", () => {
    const shown = boolCell(true, LABELS);
    expect(shown).toContain(LABELS.yes);
    expect(shown).not.toContain("true");
  });

  it("ложь названа своей фразой", () => {
    const shown = boolCell(false, LABELS);
    expect(shown).toContain(LABELS.no);
    expect(shown).not.toContain("false");
  });

  it("непришедшее поле остаётся прочерком, а не превращается в «нет»", () => {
    expect(boolCell(null, LABELS)).toBe("—");
    expect(boolCell(undefined, LABELS)).toBe("—");
  });

  it("колонка без объявленных подписей не выдумывает «Да»", () => {
    const shown = boolCell(true);
    expect(shown).toBe("—");
  });
});
