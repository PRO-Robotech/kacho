// Идентификаторы спек ОБЩЕГО реестра, которые монтирует это приложение.
//
// Лежит отдельным модулем не ради опрятности: маршруты строятся как
// `IDS.map((id) => REGISTRY[id])`, и несуществующий id даёт `undefined`, который
// роутер выбрасывает МОЛЧА — раздел просто не появляется. Отличить «спеки нет,
// поэтому раздела нет» от «раздел и не задумывался» по дереву нельзя: и то и
// другое выглядит как пустая ветка. Список, лежащий отдельным модулем,
// становится предметом проверки (`scoped-resources.test.ts`), и удаление спеки
// из общего реестра перестаёт быть беззвучным.
//
// Та же форма, что у vpc (`vpc/src/lib/scoped-resources.ts`), и по той же
// причине — раздел, пропавший молча, стоит дороже перечня.

/** Разделы под `/projects/:projectId/compute/<route>` — у каждого свои маршруты. */
export const COMPUTE_SCOPED_IDS = [
  "compute-instances",
  "machine-types",
  "guest-access-keys",
  "placement-groups",
] as const;

/**
 * Спеки, на которые ССЫЛАЮТСЯ формы и карточки этого приложения, но разделов
 * которых оно не монтирует: том и образ принадлежат storage, сетевой интерфейс —
 * vpc, зона — глобальному каталогу размещения.
 *
 * Перечислены здесь ровно затем, чтобы их исчезновение из общего реестра было
 * ГРОМКИМ. Резолвит их не этот перечень: `RefSelect` и `RefNameLink` ходят прямо
 * в `@shared/lib/resource-registry` (`getResource`/`REGISTRY`), поэтому копия
 * спеки в модуле на резолв не влияла НИКОГДА — она была мёртвой и при этом
 * отставала от общей.
 */
export const COMPUTE_REF_TARGET_IDS = ["zones", "volumes", "images", "network-interfaces"] as const;

/** Все id, которые это приложение резолвит в общем реестре. */
export const ALL_SCOPED_IDS: readonly string[] = [...COMPUTE_SCOPED_IDS, ...COMPUTE_REF_TARGET_IDS];
