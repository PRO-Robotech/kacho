import { expect, test, type APIRequestContext } from "@playwright/test";
import { CEREMONY_ADDRESSES } from "../../shared/src/pages/auth/ceremony-addresses";

/**
 * УСЛОВИЕ ПРОГОНА приёмки F8, §4: адреса церемоний отдаёт ОБОЛОЧКА консоли, а не
 * чужой экран.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТО НЕ ПРОБА И ПОЧЕМУ ОНО НЕ В `specs/`
 *
 * Сценарии церемоний судят консоль, и исполнимы они лишь на посадке, которую
 * создаёт чужой предмет: где полоса чужого экрана перехватывает адреса
 * церемоний до оболочки, экранов консоли не видит никто, и любой исход
 * сценариев был бы вердиктом о посадке, а не о консоли. Приёмка называет этот
 * исход ТРЕТЬЕЙ категорией — «не выполнилось» с числом сценариев, — а не
 * красным.
 *
 * Прежде условие было броском ошибки в `beforeAll` самих проб. Прогонщик
 * отчитывал его упавшей пробой и пропусками, гейт по отчёту — красным о
 * продукте: замерено на playwright 1.56.1, 1 упавшая и 22 пропущенные из 23,
 * «проб не в состоянии «прошла»: 23» (#2780, круг 1 ревью).
 *
 * Теперь условие — СВОЙ проект прогонщика (`playwright.config.ts`), и проект
 * зависящих проб объявляет от него зависимость. Упало условие — зависящие не
 * стартуют вовсе, а гейт по отчёту (`.github/scripts/assert-console-probes-verdict.py`)
 * узнаёт условие по ИМЕНИ ПРОЕКТА и называет исход «не выполнилось» с числом
 * сценариев без вердикта.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ — И ЧЕГО НАМЕРЕННО НЕТ
 *
 * Ровно два факта §4, и оба — о посадке:
 *   • консоль развёрнута: `/dashboard` отвечает документом оболочки;
 *   • ни один адрес церемонии не уведён от оболочки: ответ на него — тот же
 *     документ. Оболочка отдаёт один документ на любой путь, а полоса чужого
 *     экрана — свой ответ; перенаправления не следуются, иначе сравнивалось бы
 *     то, куда увёл чужой экран, а не то, что ответил адрес.
 *
 * Ретрансляции полосы формы краем здесь НЕТ, и это граница, а не пропуск: на
 * посадке, где адреса отдаёт оболочка, неработающая полоса — дефект продукта, и
 * о нём обязаны сказать сценарии красным. Условие, которое проверяло бы и её,
 * превратило бы дефект края в «не выполнилось» — то есть стало бы маской.
 */

// Адреса церемоний — ТО ЖЕ объявление, по которому консоль заводит им маршруты
// (`ceremony-addresses.ts`, приёмка F8, Р3): спросить посадку о других адресах,
// чем ведёт консоль, значило бы завести второй перечень об одном предмете.
// Отдаёт их оболочка или чужой экран, решает одна полоса раздачи на все адреса
// сразу, но спрашивается КАЖДЫЙ: условие утверждает о посадке, а не о том, как
// сегодня устроена её раздача.

/** Адрес, который по построению отдаёт оболочка: полоса чужого экрана его не касается. */
const SHELL_ADDRESS = "/dashboard";

interface Answer {
  address: string;
  status: number;
  location: string | null;
  contentType: string;
  bytes: number;
  document: string;
}

async function answerOf(api: APIRequestContext, address: string): Promise<Answer> {
  const res = await api.get(address, { headers: { Accept: "text/html" }, maxRedirects: 0 });
  const document = await res.text();
  return {
    address,
    status: res.status(),
    location: res.headers()["location"] ?? null,
    contentType: res.headers()["content-type"] ?? "",
    bytes: document.length,
    document,
  };
}

function described(a: Answer): string {
  return `${a.address} → ${a.status}${a.location ? ` (Location: ${a.location})` : ""}, ${a.contentType || "без типа"}, ${a.bytes} байт`;
}

test("условие прогона F8 §4 · адреса церемоний отдаёт оболочка консоли, а не чужой экран", async ({
  request,
}, testInfo) => {
  const shell = await answerOf(request, SHELL_ADDRESS);
  const answers = await Promise.all(CEREMONY_ADDRESSES.map((a) => answerOf(request, a)));

  // Свидетельство — вложением: условие браузера не открывает, трассы у него нет,
  // и без записи ответов «не выполнилось» разбиралось бы по одной строке текста.
  await testInfo.attach("ответы посадки", {
    body: JSON.stringify(
      [shell, ...answers].map(({ document: _d, ...rest }) => rest),
      null,
      2,
    ),
    contentType: "application/json",
  });

  expect(
    shell.status === 200 && shell.contentType.startsWith("text/html") && shell.bytes > 0,
    `УСЛОВИЕ ПРОГОНА НЕ СОЗДАНО (приёмка F8, §4): консоль не развёрнута — ${described(shell)}`,
  ).toBe(true);

  // Перечень уведённых адресов стоит В ПЕРВОЙ СТРОКЕ отказа: гейт вердикта
  // печатает начало текста, и разбор «не выполнилось» обязан начинаться с
  // названных адресов, а не с разницы двух массивов.
  const diverted = answers.filter((a) => a.status !== 200 || a.document !== shell.document);
  expect(
    diverted.length,
    "УСЛОВИЕ ПРОГОНА НЕ СОЗДАНО (приёмка F8, §4): адреса церемоний отдаёт не оболочка консоли — " +
      `${diverted.map(described).join("; ")}. Документ оболочки: ${described(shell)}. Посадок, где ` +
      "адрес церемонии перехватывает чужой экран, приёмка не поддерживает (Р1), и вердикта о консоли " +
      "прогон на них не даёт",
  ).toBe(0);
});
