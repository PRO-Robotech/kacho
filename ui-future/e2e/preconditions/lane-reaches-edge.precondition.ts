import { expect, test } from "@playwright/test";
import { LANE, newSeed, type Seed } from "../specs/ceremony-seed";

/**
 * УСЛОВИЕ ПРОГОНА: полоса формы доходит до края — на её адрес отвечает КРАЙ, а
 * не раздача консоли, которой до края дойти не удалось.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ (#1274, прогон 36201294380)
 *
 * Шаг конвейера ждёт `/healthz` консоли, а его отдаёт сама раздача, до края не
 * обращаясь. Первое обращение к краю через раздачу, чей ответ прогон
 * утверждает, — посев первой пробы, и он получил
 * `502 Bad Gateway` страницей nginx раздачи примерно через 23 с после того, как
 * выкатка края объявлена завершённой. Посев следующей пробы, около секунды
 * спустя, прошёл; из остальных 148 проб прошли 147, одна упала по своей
 * причине. Прогон судил продукт по первому ответу стенда, который до края ещё
 * не доходил, и назвал это красным.
 *
 * Почему край был недостижим, прогон не сохранил: журналов раздачи и края в его
 * артефактах нет. Условие этого и не утверждает — оно ждёт признак готовности.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРИЗНАК ГОТОВНОСТИ — ТОТ, ЧТО ПРОИЗВОДИТ КРАЙ
 *
 * Внешнее звено цепочки края (`HTTPRequestID`, gateway/internal/middleware/
 * request_id.go, провязка в gateway/cmd/api-gateway/main.go) ставит заголовок
 * `X-Request-ID` на КАЖДЫЙ ответ, прошедший через обработчики края, — раньше
 * разбора пути, проверки прав и восстановления после сбоя. Страница, которую раздача выдаёт, не дойдя до края,
 * этого заголовка не несёт. Заголовок есть — ответил край; нет — край ещё не
 * достигнут. Ждётся этот признак (`expect.poll`), а не время.
 *
 * Держит свойство край, а не эта проверка. Снимет край заголовок — условие
 * перестанет создаваться на ЛЮБОМ стенде, и прогон назовёт это «не выполнилось»
 * с последним ответом в тексте, а не пропустит молча.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ
 *
 * ЧТО ответил край, условие не спрашивает: ни код, ни тело. Неработающая
 * полоса — дефект продукта, и сказать о нём обязаны сценарии красным (граница
 * #2780, `ceremony-landing.precondition.ts`). Условие, требующее от края
 * правильного ответа, превращало бы его дефект в «не выполнилось» — то есть
 * стало бы маской. Здесь спрашивается только ДОСТИЖИМОСТЬ.
 *
 * Спрашивает ВЫПУСКАЮЩИЙ посева (`newSeed`, `seed.read`), а не свой контекст
 * запросов: обращения набора к полосе идут только через его запись (условие
 * C21, `shared/src/test/ceremony-single-sources.test.ts`).
 */

/** Заголовок, который ставит внешнее звено края на каждый свой ответ. */
const EDGE_STAMP = "x-request-id";

/** Первое обращение посева — признак формы (`ceremony-seed.ts`, `formToken`). */
const LANE_ADDRESS = `${LANE.csrf}?form=login`;

const EDGE_ANSWERED = "ответил край";

interface Answer {
  status: number;
  contentType: string;
  edgeStamp: boolean;
  head: string;
}

async function answerOf(seed: Seed): Promise<Answer> {
  const res = await seed.read(LANE_ADDRESS);
  const text = await res.text();
  return {
    status: res.status(),
    contentType: res.headers()["content-type"] ?? "",
    edgeStamp: (res.headers()[EDGE_STAMP] ?? "") !== "",
    head: text.slice(0, 200),
  };
}

function described(a: Answer): string {
  return `${LANE_ADDRESS} → ${a.status}, ${a.contentType || "без типа"}, без ${EDGE_STAMP}: ${JSON.stringify(a.head)}`;
}

test("условие прогона · полоса формы доходит до края: на её адрес отвечает край, а не раздача консоли", async ({
  browserName: _browser,
}, testInfo) => {
  const seed = await newSeed(testInfo);
  const answers: Answer[] = [];
  try {
    await expect
      .poll(
        async () => {
          const a = await answerOf(seed);
          answers.push(a);
          return a.edgeStamp ? EDGE_ANSWERED : described(a);
        },
        {
          message:
            "УСЛОВИЕ ПРОГОНА НЕ СОЗДАНО: край на полосе формы не отвечает — ответ дала раздача консоли, " +
            "до края не дойдя. Вердикта о продукте прогон на таком стенде не даёт",
        },
      )
      .toBe(EDGE_ANSWERED);
  } finally {
    // Свидетельство — вложением: сколько раз спросили и что получили до ответа
    // края. Без него «условие создано со второго раза» неотличимо от первого.
    await testInfo.attach("ответы полосы", {
      body: JSON.stringify(answers, null, 2),
      contentType: "application/json",
    });
    await seed.dispose();
  }
});
