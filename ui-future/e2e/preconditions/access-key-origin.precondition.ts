import { test } from "@playwright/test";
import { revokeAccessKey, seedAccessKey } from "../specs/access-key-seed";
import { newSeed, seedAddress, seedConfirmedHuman } from "../specs/ceremony-seed";
import { ConditionNotCreated } from "../specs/mail-receiver";

/**
 * УСЛОВИЕ ЧАСТИ НАБОРА (приёмка F8-S4, §4 П4; kacho#3057): служба принимает
 * происхождение браузера набора для ключей доступа.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ СВОИМ ПРОЕКТОМ, А НЕ ФИКСТУРОЙ КАЖДОЙ ПРОБЫ
 *
 * Перечень происхождений ключа задаёт профиль стенда: в профиле своего стенда
 * он пуст намеренно, и стендовая часть — отдельный предмет (kacho#3068). Пока
 * это условие наступало внутри проб (посев К, `specs/access-key-seed.ts`),
 * каждая проба ключа падала «условие не создано» и тратила бюджет ранней
 * остановки (`maxFailures` в `playwright.config.ts`): на прогоне волны 6 пять
 * таких падений остановили набор, и 218 проб, к ключам отношения не имеющих,
 * не стартовали — вердикта о консоли не было вовсе.
 *
 * Здесь условие проверяется ОДИН раз своим проектом, и от него зависит только
 * проект проб ключа. Не создано — пробы ключа не стартуют (гейт называет их
 * число «без вердикта»), остальной набор исполняется и судится.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ — И ЧЕГО НАМЕРЕННО НЕТ
 *
 * Посев К заводит ключ человеку П-п глаголами Ф7 тем же кодом, что у проб.
 * «Не создано» — ТОЛЬКО отказ, помеченный посевом как несозданное условие
 * (`ConditionNotCreated`: происхождение не в перечне, письмо не дошло). Любой
 * иной отказ посева — возможный дефект продукта, и о нём обязаны сказать пробы
 * красным: условие, требующее от службы правильного ответа, превратило бы её
 * дефект в «не выполнилось», то есть стало бы маской. Такой отказ условие
 * пропускает и кладёт его текст вложением.
 *
 * Ключ, заведённый условием, снимается тем же заходом — прогон не оставляет
 * его за собой.
 */
test("условие части набора F8-S4 §4 П4 · служба принимает происхождение браузера набора для ключей доступа", async ({
  browserName: _browser,
}, testInfo) => {
  const seed = await newSeed(testInfo);
  let outcome = "";
  try {
    await seedConfirmedHuman(seed, seedAddress("access-key-origin"));
    const key = await seedAccessKey(seed, testInfo.project.use.baseURL, { userVerification: true });
    outcome = "ключ заведён — происхождение принято";
    await revokeAccessKey(seed, key);
  } catch (err) {
    if (err instanceof ConditionNotCreated) throw err;
    // Отказ не об условии: пробы ключа исполнятся и скажут о нём своим вердиктом.
    outcome = `посев отказал не по условию — судят пробы: ${err instanceof Error ? err.message : String(err)}`;
  } finally {
    await testInfo.attach("исход посева К", { body: outcome || "условие не создано", contentType: "text/plain" });
    await seed.dispose();
  }
  console.log(`[F8-S4 П4] ${outcome}`);
});
