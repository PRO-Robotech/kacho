import { expect, test } from "@playwright/test";
import { ConditionNotCreated, conditionNotCreated, stationMailbox, UNMET_MAILBOX } from "../specs/mail-receiver";

/**
 * УСЛОВИЕ ПРОГОНА приёмки F6b, F6b-34: приёмник писем стенда читается прогоном.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ
 *
 * Фикстура регистрации набора доводит человека до подтверждённого адреса тем
 * путём, что человек: регистрация → экран подтверждения → код из письма
 * (приёмка F6b, Р13, F6b-32). Письмо набор читает у приёмника стенда. Нет
 * поверхности чтения — ни одна проба, заводящая арендатора, до своего предмета
 * не дойдёт, и падали бы они одним текстом по причине, к их предмету отношения
 * не имеющей (`e2e-flow.md` §11). Это не красное о продукте, а «не выполнилось»,
 * и различать его обязано условие, а не каждая проба порознь.
 *
 * Условие — СВОЙ проект прогонщика рядом с прочими условиями
 * (`playwright.config.ts`): упало — зависящие пробы не стартуют, и гейт вердикта
 * узнаёт исход по имени проекта, а не по тексту.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ — И ЧЕГО НАМЕРЕННО НЕТ
 *
 * Только то, что поверхность ЧИТАЕТСЯ: адрес и число писем печатаются, исход —
 * «условие создано». Пришло ли письмо конкретному человеку, условие не
 * спрашивает: письмо, которое служба не поставила, — дефект продукта, и о нём
 * обязаны сказать пробы. Условие, требующее письма, превратило бы этот дефект в
 * «не выполнилось», то есть стало бы маской.
 *
 * Ждётся ОТВЕТ поверхности, а не время: проброс, открытый шагом конвейера, мог
 * ещё не принять первое соединение.
 */

const READ_BUDGET_MS = 30_000;

test("условие прогона F6b-34 · приёмник писем стенда читается прогоном", async ({ browserName: _browser }, testInfo) => {
  const mailbox = stationMailbox();
  const tried: string[] = [];
  let letters = -1;
  try {
    await expect
      .poll(
        async () => {
          try {
            letters = await mailbox.total();
            return "читается";
          } catch (err) {
            if (!(err instanceof ConditionNotCreated)) throw err;
            tried.push(err.message);
            return err.message;
          }
        },
        { timeout: READ_BUDGET_MS, intervals: [500, 1_000] },
      )
      .toBe("читается");
  } catch (_budgetSpent) {
    // Текст отказа — последний ответ поверхности: он называет адрес и причину.
  } finally {
    await testInfo.attach("ответы поверхности чтения", {
      body: JSON.stringify({ address: mailbox.base, tried, letters }, null, 2),
      contentType: "application/json",
    });
  }
  if (letters < 0) {
    conditionNotCreated(tried.at(-1) ?? `${UNMET_MAILBOX}: ${mailbox.base} — ответа за ${READ_BUDGET_MS / 1000} с нет`);
  }
  console.log(`[F6b-34] поверхность чтения приёмника ${mailbox.base} — писем прочитано ${letters}; условие создано`);
});
