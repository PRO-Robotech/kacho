test("iam: исключение из аккаунта предлагается на строке только при выбранной области", async ({
  page,
}) => {
  // verifies #1127 — предмет ЗАКРЫТ продуктом, проба держит его закрытым.
  //
  // ПРЕДМЕТ. Директива владельца (2026-08-23) развела три области: имя и почта —
  // дело человека, участие В МОЁМ аккаунте — дело аккаунта, вход на платформу —
  // дело облака. Второй строке отвечает «Исключить из аккаунта»: оно снимает
  // строку ЧЛЕНСТВА и личности не трогает. Сосед по меню — «Запретить участие» —
  // выключает вход НА ПЛАТФОРМУ во всех аккаунтах сразу. Два разных предмета
  // стоят в одном меню в двух соседних строках, и цена промаха несимметрична.
  //
  // ПОЧЕМУ БРАУЗЕРОМ, А НЕ ЮНИТОМ. Юнит рядом
  // (`RowActionsMenu.rowverbs.test.tsx`) утверждает про сам пункт: появляется
  // при выбранной области, отсутствует без неё, уходит своим адресом и несёт
  // аккаунт телом. Всё это он проверяет, ЗАДАВ область прямой записью в
  // хранилище. У пункта же есть предусловие, которого в такой постановке нет
  // вовсе: область выбирают В ШАПКЕ КАРКАСА, а читает её меню строки ВНУТРИ
  // федеративного модуля. Между ними четыре перехода — выбор в шапке пишет
  // состояние каркаса, оно ложится в хранилище браузера, каркас передаёт его
  // свойством в страницу модуля, страница провязывает его в общее хранилище
  // области, и только оттуда его берёт меню. Юнит монтирует один конец этой
  // цепочки и зелен при любом состоянии остальных трёх.
  //
  // ЧЕГО ЭТА ПРОБА НАМЕРЕННО НЕ ДЕЛАЕТ — ИСКЛЮЧЕНИЯ.
  //
  // Она доводит человека до подтверждения и уходит, не подтвердив. Две причины,
  // и обе названы, чтобы следующий читатель не принял это за недоделку:
  //
  //   1. Единственный человек в аккаунте свежего арендатора — он сам, и
  //      исключение себя необратимо по построению: вернуть себя обратно может
  //      только тот, кто в аккаунте распоряжается, а распоряжался он. Проба,
  //      выполнившая его, уничтожила бы собственную фикстуру.
  //   2. Край требует у этого глагола повторного подтверждения личности
  //      (`required_acr_min = "2"` у `RemoveFromAccount` в
  //      `proto/kacho/cloud/iam/v1/user_service.proto`; тот же порог у
  //      приглашения — то есть и второго человека завести нечем). Консоль
  //      подтверждает его ТОЛЬКО ключом доступа (окно повторного подтверждения
  //      предлагает единственный способ — passkey), а арендатор этой пробы
  //      заведён паролем. Сценарий не «пропущен», его в браузере НЕ СОБРАТЬ.
  //
  // Исход самого исключения — человека нет в списке аккаунта, а личность цела —
  // утверждается там, где он собирается: кейсом чёрного ящика
  // `IAM-USR-EXCL-CRUD-OK`, у которого есть и предъявитель со ступенью доверия,
  // и надзор облака, чтобы прочитать строку исключённого. Здесь утверждается то,
  // чего не видит ни он, ни юнит: ДОСТИЖИМОСТЬ действия и её предусловие.
  //
  // ─────────────────────────────────────────────────────────────────────────
  // ОТКРЫТЫЙ ДОЛГ #1208 — ПРОБЫ ЗДЕСЬ НЕТ, И ЭТО СКАЗАНО, А НЕ ЗАМАСКИРОВАНО
  //
  // Задача #1208 требует пробы браузером на ПАРУ: текст подтверждения соседнего
  // пункта («Запретить участие») и наличие/отсутствие названного им «Исключить
  // из аккаунта» в ТОМ ЖЕ меню. Продукт починен (`resource-registry.tsx`,
  // `accountScopeChosen` — один предикат рисует пункт и решает текст соседа), и
  // пара закреплена юнитом рядом
  // (`RowActionsMenu.rowverbs.test.tsx`, две пробы: без области текст называет
  // условие, с областью — обещает безусловно).
  //
  // ПОЧЕМУ БРАУЗЕРОМ НЕ СОБРАТЬ. Нужна ЧУЖАЯ строка, то есть второй человек в
  // аккаунте, а его не завести: приглашение требует повторного подтверждения
  // личности (`required_acr_min = "2"` у `Invite` в
  // `proto/kacho/cloud/iam/v1/user_service.proto`), консоль подтверждает его
  // ТОЛЬКО ключом доступа, а арендатор этих проб заведён паролем. Тот же
  // блокатор, что назван у пробы выше, — и он не обходится обращением к краю
  // напрямую: ступень доверия проверяет край, а не консоль.
  //
  // ЗДЕСЬ СТОЯЛ ВТОРОЙ ДОВОД, И ОН ПЕРЕЖИЛ СВОЙ ПРЕДМЕТ (снят #1219). Он гласил:
  // «над собственной строкой показывается ветка `isSelf`, а она про исключение
  // не говорит ничего, поэтому утверждение о паре над своей строкой было бы
  // ИСТИННО ВПУСТУЮ». Молчание собственной ветки было не свойством постановки, а
  // ДЕФЕКТОМ — обратной стороной #1208, — и оно закрыто: узкий выход теперь
  // называется в обеих ветках из одного производителя
  // (`resource-registry.tsx`, `narrowExitFromAccount`). Проба над СВОЕЙ строкой
  // существует и стоит выше по файлу. Остаётся блокатор только на ЧУЖУЮ строку,
  // названный абзацем выше.
  //
  // ПРЕДИКАТ СНЯТИЯ ДОЛГА: как только фикстура научится заводить второго
  // человека в аккаунте (подставной ключ доступа через CDP либо посев членства
  // мимо консоли) — проба пишется здесь и утверждает пару над ЧУЖОЙ строкой в
  // обоих состояниях области. Заводить её раньше нельзя: она была бы либо
  // вечно красной, либо истинной впустую, и первый же читатель снял бы её.
  // ─────────────────────────────────────────────────────────────────────────
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);

  // Подпись области, которую предложит выбор в шапке. Спрашивается ДО перехода
  // на страницу, и это не оптимизация: каркас читает перечень аккаунтов ОДИН
  // раз при монтировании. Права арендатора материализуются в ограниченном окне,
  // и каркас, смонтированный раньше срока, оставил бы панель выбора пустой
  // навсегда — проба падала бы на пустой панели и называла бы невиновного.
  //
  // Подпись собирается ТЕМ ЖЕ правилом, что и в панели («имя либо
  // идентификатор»): аккаунт без имени показывается идентификатором, и ожидание
  // имени сделало бы пробу зависимой от того, назвал ли его кто-нибудь.
  let accountLabel = "";
  await expect
    .poll(
      async () => {
        const res = await page.request.get("/iam/v1/accounts?pageSize=1000");
        if (!res.ok()) return "";
        const body = (await res.json()) as { accounts?: Array<{ id: string; name?: string }> };
        const first = body.accounts?.[0];
        accountLabel = first ? first.name || first.id : "";
        return accountLabel;
      },
      {
        message:
          "у арендатора не видно ни одного аккаунта: выбрать область будет нечем, " +
          "и об исключении из аккаунта такой прогон не сказал бы ничего",
        timeout: 60_000,
      },
    )
    .not.toBe("");

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // УСЛОВИЕ: своя строка на странице есть. Без неё «пункта нет» ниже было бы
  // истинно и на странице, которой нет вовсе.
  const row = rowOf(page, email);
  await expect(
    row,
    `собственной строки арендатора (${email}) нет на странице пользователей — ` +
      `условие пробы не создано: действовать не над чем`,
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДПОСЫЛКА НАЗВАНА НАБЛЮДАЕМЫМ, а не подразумевается. Утверждение ниже
  // говорит не «пункта нет», а «НЕТ ОБЛАСТИ — нет пункта», и первая половина
  // этой пары обязана быть видна на экране, иначе пара распадается: пункт мог
  // бы отсутствовать по любой другой причине, а проба записала бы это в заслугу
  // предусловию.
  const noScope = page.getByRole("button", { name: "Выберите область" }).first();
  await expect(
    noScope,
    "в шапке нет выбора области с подписью «Выберите область»: либо область уже " +
      "выбрана (тогда первая половина пробы утверждала бы не о том), либо выбора " +
      "области на странице пользователей нет вовсе — и выбрать аккаунт человеку нечем",
  ).toBeVisible({ timeout: 30_000 });

  const actions = row.getByRole("button", { name: "Действия" }).first();
  await expect(
    actions,
    "у строки пользователя нет меню действий вовсе — тогда пункт-глагол негде было бы предложить",
  ).toBeVisible({ timeout: 15_000 });
  await actions.click();

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ к отрицанию ниже, и он обязателен. «Пункта нет»
  // зеленеет на не открывшемся меню, на не загрузившемся модуле и на пустой
  // странице — то есть ровно там, где не проверяет ничего. Сосед по ТОМУ ЖЕ
  // перечню глаголов доказывает, что меню открыто и глаголы строки разрешились.
  const ban = page.getByRole("menuitem", { name: /Запретить участие/ }).first();
  await expect(
    ban,
    "в открытом меню строки нет ни одного глагола: меню не открылось или глаголы " +
      "не разрешились — об отсутствии исключения такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 15_000 });

  // ПРЕДМЕТ, половина первая — без выбранной области пункта НЕТ.
  //
  // Это не косметика. Предмет исключения — ПАРА «человек и аккаунт»: у человека
  // аккаунтов бывает несколько, а на строке личности их больше нет ни одного,
  // поэтому вывести аккаунт из строки нельзя. Пункт, предложенный без области,
  // отправил бы запрос без половины предмета.
  await expect(
    page.getByRole("menuitem", { name: /Исключить из аккаунта/ }),
    "исключение из аккаунта предложено, когда область НЕ выбрана: у действия нет " +
      "второй половины предмета, и уйти оно может только неизвестно куда",
  ).toHaveCount(0);

  // Меню закрывается ДО работы с шапкой — иначе следующий щелчок достался бы
  // открытому меню, и проба меряла бы собственный порядок действий.
  await page.keyboard.press("Escape");
  await expect(
    page.getByRole("menuitem", { name: /Запретить участие/ }),
    "меню строки не закрылось по Escape — дальнейшие щелчки достаются ему, а не шапке",
  ).toHaveCount(0);

  // Выбираем область ровно так, как это делает человек: панелью в шапке.
  await noScope.click();
  const accountItem = page.getByRole("button", { name: accountLabel, exact: true }).first();
  await expect(
    accountItem,
    `панель выбора области не предлагает аккаунт «${accountLabel}», который край ` +
      `арендатору показывает: выбрать область в консоли нечем`,
  ).toBeVisible({ timeout: 15_000 });
  await accountItem.click();

  // КОНТРОЛЬ: область ДЕЙСТВИТЕЛЬНО выбрана, а не «по ней щёлкнули». Подпись
  // кнопки — то же наблюдаемое, которым выше названа предпосылка, и она обязана
  // смениться с приглашения на имя аккаунта.
  await expect(
    noScope,
    "после выбора аккаунта в шапке по-прежнему написано «Выберите область»: " +
      "выбор не состоялся, и всё дальнейшее меряло бы прежнее состояние",
  ).toHaveCount(0);
  await expect(
    page.getByRole("button", { name: accountLabel, exact: true }).first(),
    `шапка не называет выбранный аккаунт «${accountLabel}» — область сменилась не на ту, ` +
      `которую выбирали`,
  ).toBeVisible({ timeout: 15_000 });

  // ПРЕДМЕТ, половина вторая — с выбранной областью пункт ЕСТЬ. Именно здесь
  // проверяется вся цепочка из четырёх переходов: юнит зелен при её обрыве в
  // любом месте, потому что задаёт область в её конце.
  await actions.click();
  const exclude = page.getByRole("menuitem", { name: /Исключить из аккаунта/ }).first();
  await expect(
    exclude,
    `область выбрана («${accountLabel}»), а исключения из аккаунта в меню строки нет. ` +
      `Действие, оставленное распорядителю аккаунта директивой владельца, из консоли ` +
      `недостижимо: вывести человека ТОЛЬКО из своего аккаунта нечем, и остаётся ` +
      `соседний пункт, выключающий ему вход на платформу целиком`,
  ).toBeVisible({ timeout: 15_000 });

  // КОНТРОЛЬ состава: сосед остался на месте. Без него «пункт появился» было бы
  // истинно и на меню, которое подменили целиком, — а предмет пары в том, что
  // человеку предложены ОБА действия и он выбирает между ними.
  await expect(
    page.getByRole("menuitem", { name: /Запретить участие/ }).first(),
    "рядом с исключением из аккаунта пропал запрет участия: меню подменилось, а не " +
      "пополнилось — выбирать между «только здесь» и «на всей платформе» человеку не из чего",
  ).toBeVisible({ timeout: 15_000 });

  // Подтверждение обязано назвать ГРАНИЦУ действия — то, чем оно отличается от
  // соседа: личность остаётся. Два пункта стоят рядом, их последствия разной
  // цены, и различить их человек может только здесь.
  await exclude.click();
  const dialog = page.getByRole("dialog").first();
  await expect(
    dialog,
    "подтверждения не появилось — действие, снимающее участие, уходило бы одним нажатием",
  ).toBeVisible({ timeout: 15_000 });
  await expect(
    dialog,
    "подтверждение исключения не называет границу действия: человек не узнаёт, что " +
      "личность сохраняется, — и не отличит его от соседнего запрета входа на платформу",
  ).toContainText(/личност/i);

  // Уходим не подтвердив — см. «чего эта проба намеренно не делает» выше.
  await dialog.getByRole("button", { name: "Отмена" }).first().click();
  await expect(dialog, "окно подтверждения не закрылось по отказу").toBeHidden({ timeout: 15_000 });
});
