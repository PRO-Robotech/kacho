test("iam: карточка сотрудника не называет посторонних аккаунтов", async ({ page }) => {
  // verifies #1085 — сценарий приёмки IAM-ID-2-20.
  //
  // ПРЕДМЕТ. Человек состоит в нескольких аккаунтах, и карточка не вправе
  // раскрывать их состав: это тот же оракул, что и различимый отказ, только
  // словом. Здесь утверждается ДВА свойства сразу — что названо ровно то, что
  // спрошено, и что спрошено только про названный аккаунт.
  //
  // ЧЕГО ЭТА ПРОБА НЕ ДЕЛАЕТ, И ЭТО СКАЗАНО, А НЕ ЗАМАСКИРОВАНО.
  //
  // Она не заводит человеку ВТОРОЙ аккаунт. Постановка сценария («состоит в A и
  // в B») требует фикстуры, которой у набора нет: второе членство создаётся
  // ПРИГЛАШЕНИЕМ уже существующей почты в другой аккаунт, а `Invite` требует
  // повторного подтверждения личности (`required_acr_min = "2"` в
  // `proto/kacho/cloud/iam/v1/user_service.proto`). Создание второго аккаунта
  // членства НЕ даёт — измерено: в `services/iam/internal/repo/kacho/pg/account_repo.go`
  // нет ни одной записи в `memberships`, их пишет только заведение человека.
  //
  // Поэтому здесь утверждается свойство, которое от числа аккаунтов НЕ зависит
  // и держится при любом их количестве: карточка называет РОВНО ОДИН аккаунт, и
  // это выбранный. Различение «свой против чужого» при ДВУХ членствах в ответе
  // проверяет юнит рядом (`AccountMembership.test.tsx`, «не называет ни одного
  // другого аккаунта, даже пришедшего в ответе»): он подаёт чужое членство
  // ПЕРВЫМ, то есть ловит ровно «взять первое».
  //
  // ПРЕДИКАТ СНЯТИЯ ОСТАТКА: как только набор научится приглашать существующую
  // почту во второй аккаунт под поднятым уровнем (способ — `stepup.spec.ts`),
  // сюда добавляется второй аккаунт и утверждение, что его имени и
  // идентификатора нет ни на одной вкладке. Заведено задачей #1357.
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);
  const account = await onlyAccount(page);

  // Перечень исходящих обращений собирается ДО перехода: подписка, заведённая
  // после, пропустила бы запросы самой карточки — то есть ровно те, о которых
  // утверждает эта проба.
  const calls = apiCalls(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });
  await chooseAccountScope(page, account.label);
  await openOwnCard(page, email);

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: членство в выбранном аккаунте НАЗВАНО. Без него оба
  // отрицания ниже истинны у карточки, которая молчит обо всём.
  await expect(
    page.locator(`a[href="/iam/accounts/${account.id}"]`).first(),
    "членство в выбранном аккаунте не названо: отрицания ниже проверяли бы пустой экран",
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДМЕТ, часть 1 — на карточке ровно ОДИН аккаунт, и это выбранный.
  // Раскрываются все вкладки: состав аккаунтов не должен всплыть ни на одной.
  const tabs = page.getByRole("tab");
  for (let i = 0; i < (await tabs.count()); i++) {
    await tabs.nth(i).click();
    await expect(
      page.locator(`a[href^="/iam/accounts/"]:not([href="/iam/accounts/${account.id}"])`),
      "на карточке есть переход на аккаунт, который не выбран: состав аккаунтов " +
        "человека раскрыт ссылкой",
    ).toHaveCount(0);
  }

  // ПРЕДМЕТ, часть 2 — консоль не спрашивала про человека БЕЗ аккаунта.
  //
  // Вопрос без аккаунта отвечал бы про все аккаунты человека сразу; такого пути
  // на поверхности нет вовсе, и проба следит, чтобы он не завёлся незаметно.
  const membershipCalls = calls.filter((c) => c.includes("/memberships"));
  expect(
    membershipCalls.filter((c) => !c.includes(`/accounts/${account.id}/memberships`)),
    `консоль спросила членства не по аккаунт-скоупному пути: ${membershipCalls.join(", ")}`,
  ).toHaveLength(0);
  expect(
    calls.filter((c) => c.includes("/me/memberships")),
    "карточка чужого человека спрашивает СВОЙ список членств — он отвечает про все аккаунты сразу",
  ).toHaveLength(0);

});

