/**
 * Страница пользователей: что на ней можно СДЕЛАТЬ и что на ней НАПИСАНО.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ЮНИТОМ МОДУЛЯ
 *
 * Все три находки живут на стыке, которого юнит не видит. Первая — на стыке общей
 * оболочки списка и объявления ресурса: край глаголы подаёт, контракт их
 * объявляет, а до экрана они доезжают только если оболочка умеет их рисовать.
 * Вторая — на стыке объявления столбцов и того, что попадает в шапку таблицы, в
 * выбор столбцов и на карточку. Третья — на стыке ВЫБОРА ОБЛАСТИ и меню строки:
 * аккаунт выбирается в шапке КАРКАСА, а читает его меню строки внутри
 * ФЕДЕРАТИВНОГО модуля, и между ними четыре перехода (каркас → хранилище
 * браузера → провязка страницы модуля → общее хранилище области). Юнит монтирует
 * одну сторону стыка и потому зелен.
 *
 * ЧТО ЭТИ ПРОБЫ НАМЕРЕННО НЕ ДЕЛАЮТ
 *
 * Не запрещают участие по-настоящему. Запрет самому себе необратим по
 * построению: восстановление пароля его не снимает, и вернуть доступ может
 * только администратор аккаунта либо облака. Проба, выполнившая его над
 * собственной личностью, уничтожила бы свою же фикстуру, а её вердикт стал бы
 * зависеть от пути снятия, которого продукт не обещает. Поэтому утверждается
 * то, чего не было: действие ДОСТИЖИМО со строки и подтверждение НАЗЫВАЕТ цену.
 * Что уходит к краю при подтверждении, утверждает проба рядом
 * (`RowActionsMenu.rowverbs.test.tsx`), а существование самого маршрута —
 * перепись глаголов (`console-verb-routes-exist.test.ts`).
 */

/** Строка списка, принадлежащая этой почте. */
function rowOf(page: Page, email: string) {
  return page.locator("tr").filter({ hasText: email }).first();
}

/**
 * Единственный аккаунт свежего арендатора — его идентификатор и подпись.
 *
 * Подпись собирается ТЕМ ЖЕ правилом, что и панель выбора области («имя либо
 * идентификатор»): аккаунт без имени показывается идентификатором, и ожидание
 * имени сделало бы пробу зависимой от того, назвал ли его кто-нибудь.
 *
 * Спрашивается ДО перехода на страницу: права арендатора материализуются в
 * ограниченном окне, и каркас, смонтированный раньше срока, оставил бы панель
 * выбора пустой навсегда.
 */
async function onlyAccount(page: Page): Promise<{ id: string; label: string }> {
  let found = { id: "", label: "" };
  await expect
    .poll(
      async () => {
        const res = await page.request.get("/iam/v1/accounts?pageSize=1000");
        if (!res.ok()) return "";
        const body = (await res.json()) as { accounts?: Array<{ id: string; name?: string }> };
        const first = body.accounts?.[0];
        found = first ? { id: first.id, label: first.name || first.id } : { id: "", label: "" };
        return found.id;
      },
      {
        message:
          "у арендатора не видно ни одного аккаунта: выбрать область будет нечем, " +
          "и о членстве такой прогон не сказал бы ничего",
        timeout: 60_000,
      },
    )
    .not.toBe("");
  return found;
}

/**
 * Выбрать область ровно так, как это делает человек: панелью в шапке каркаса.
 *
 * Выбор ПОДТВЕРЖДАЕТСЯ наблюдаемым — приглашение обязано уйти, а на его месте
 * появиться имя аккаунта. Без подтверждения «щёлкнули по аккаунту» было бы
 * неотличимо от «область выбрана», и всё дальнейшее меряло бы прежнее состояние.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗДЕСЬ СТОЯЛА РАЗВИЛКА ПО `count()`, И ОНА НЕ СРАБАТЫВАЛА НИ РАЗУ
 *
 * Было: `if ((await empty.count()) > 0) { …выбрать аккаунт… }`. `count()` не ждёт
 * ничего — он отвечает про разметку, какая есть В ЭТУ МИЛЛИСЕКУНДУ, — а сразу
 * после `goto(…, "domcontentloaded")` разметки шапки нет ВООБЩЕ: исходный
 * документ несёт пустой корень, шапку рисует загруженный модуль. Значит ответ
 * «ноль» означал не «область уже выбрана», а «спрашивать ещё не у чего»: тело
 * развилки не исполнялось, по аккаунту никто не щёлкал, и проба падала
 * тридцатью секундами ниже — на утверждении, которое называет невиновного
 * («область не выбрана» вместо «её никто не выбирал»).
 *
 * Развилки больше нет вовсе, и это не ужесточение ради строгости: у свежего
 * арендатора в свежем окне выбора нет BY CONSTRUCTION. `loadHostContext`
 * (`host/src/utils/host-context.ts`) читает пустое хранилище браузера и отдаёт
 * `account: null`, `ScopePicker` рисует на этом «Выберите область», а из адреса
 * `/iam/users` аккаунт не выводится — `parsePathIds` знает только `/accounts/…`
 * и `/projects/…`. Поэтому «область уже выбрана» здесь не второй законный
 * случай, а расхождение с посылкой, и ему полагается падение С ИМЕНЕМ, а не
 * молчаливый пропуск.
 *
 * Та же последовательность нужна ниже по файлу — в пробе про исключение из
 * аккаунта. Прежде она была там ВЫПИСАНА ШАГ В ШАГ, а эта шапка обещала, что
 * два места об одном предмете не разойдутся снова; обещание держалось
 * вниманием, и однажды они уже расходились — тем расхождением и был дефект,
 * закрытый этой линией. Теперь место одно, и обещание держится построением
 * (#1441 п.3).
 */
async function chooseAccountScope(page: Page, label: string): Promise<void> {
  // ПЕРВОЕ ОЖИДАНИЕ ПОСЛЕ ПЕРЕХОДА — оно и есть подтверждение, что каркас
  // смонтирован: до него ни один вопрос о шапке не имеет смысла.
  const empty = page.getByRole("button", { name: "Выберите область" }).first();
  await expect(
    empty,
    `в шапке нет выбора области с подписью «Выберите область»: либо каркас не ` +
      `смонтировался вовсе, либо область уже выбрана — и тогда выбранной может ` +
      `оказаться не «${label}». Условие пробы не создано`,
  ).toBeVisible({ timeout: 60_000 });
  await empty.click();

  const item = page.getByRole("button", { name: label, exact: true }).first();
  await expect(
    item,
    `панель выбора области не предлагает аккаунт «${label}», который край арендатору ` +
      `показывает: выбрать область в консоли нечем — условие пробы не создано`,
  ).toBeVisible({ timeout: 15_000 });
  await item.click();

  // КОНТРОЛЬ: область ДЕЙСТВИТЕЛЬНО выбрана, а не «по ней щёлкнули». Приглашение
  // ушло — значит подпись сменилась, а не появилась вторая кнопка рядом.
  await expect(
    empty,
    "после выбора аккаунта в шапке по-прежнему написано «Выберите область»: " +
      "выбор не состоялся, и всё дальнейшее меряло бы прежнее состояние",
  ).toHaveCount(0);
  await expect(
    page.getByRole("button", { name: label, exact: true }).first(),
    `шапка не называет выбранный аккаунт «${label}»: область сменилась не на ту, ` +
      `которую выбирали, и карточка назвала бы членство не в том аккаунте — ` +
      `условие пробы не создано`,
  ).toBeVisible({ timeout: 30_000 });
}

