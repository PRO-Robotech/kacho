test("iam: карточка сотрудника называет членство в текущем аккаунте", async ({ page }) => {
  // verifies #1085 — сценарий приёмки IAM-ID-2-19.
  //
  // ПРЕДМЕТ. «К какому аккаунту относится этот человек и в каком он там
  // положении» — вопрос, на который консоль перестала отвечать после #471 и
  // отвечает снова с появлением ресурса членства. Утверждается не наличие
  // подписи, а ТРИ её свойства, каждое из которых легко потерять по отдельности:
  // аккаунт назван ССЫЛКОЙ (а не голым идентификатором, ui.md правило 2),
  // состояние названо СЛЕДСТВИЕМ (а не «да», ui.md правило 6), и оба взяты из
  // чтения, сужённого ВЫБРАННЫМ аккаунтом.
  //
  // ПОЧЕМУ БРАУЗЕРОМ. Юнит рядом
  // (`iam/src/components/organisms/iam/AccountMembership/AccountMembership.test.tsx`)
  // монтирует секцию напрямую и задаёт область записью в хранилище. Здесь
  // проверяется то, чего он не видит: область выбирается ЧЕЛОВЕКОМ в шапке
  // каркаса, а читает её секция внутри федеративного модуля — между ними те же
  // четыре перехода, что и у меню строки выше по файлу.
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);
  const account = await onlyAccount(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });
  await chooseAccountScope(page, account.label);

  await openOwnCard(page, email);

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: карточка отрисована. Без него всё дальнейшее
  // зеленело бы на пустом экране, на отказе и на не загрузившемся модуле.
  await expect(
    page.getByText("Статус приглашения", { exact: true }).first(),
    "карточка пользователя не отрисована: о членстве такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 60_000 });

  // ВСЁ ДАЛЬНЕЙШЕЕ СПРАШИВАЕТСЯ У САМОЙ СЕКЦИИ, А НЕ У СТРАНИЦЫ (#1441 п.4).
  //
  // Прежде подпись «Аккаунт» искалась по всей странице. Ровно такая же надпись
  // служит заголовком колонки в панели выбора области, которую рисует КАРКАС, а
  // не модуль: утверждение о карточке способно зазеленеть на шапке чужой панели
  // — то есть перестать проверять свой предмет, не изменившись само. Сегодня
  // панель закрывается по выбору и совпадения не случается, но «сегодня не
  // совпадает» — не свойство пробы.
  //
  // `.last()`, а не `.first()`: предок в разметке стоит ПЕРЕД потомком, поэтому
  // последняя из секций, содержащих этот заголовок, и есть сама секция, а не
  // обёртка вокруг неё.
  const membership = page
    .locator("section")
    .filter({ has: page.getByText("Членство в аккаунте", { exact: true }) })
    .last();
  await expect(
    membership,
    "секции «Членство в аккаунте» на карточке нет вовсе: ответ «к какому аккаунту " +
      "относится этот человек» снова потерян, хотя источник у него есть",
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДМЕТ, часть 1 — подпись «Аккаунт» В ЭТОЙ СЕКЦИИ есть.
  await expect(
    membership.getByText("Аккаунт", { exact: true }).first(),
    "в секции членства нет подписи «Аккаунт»: секция отрисована, а поля в ней нет",
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДМЕТ, часть 2 — аккаунт назван ССЫЛКОЙ на свою карточку.
  const accountLink = membership.locator(`a[href="/iam/accounts/${account.id}"]`).first();
  await expect(
    accountLink,
    `аккаунта нет ссылкой: перехода на /iam/accounts/${account.id} из секции членства нет. ` +
      `Идентификатор, показанный текстом, адресует ресурс и никуда не ведёт`,
  ).toBeVisible({ timeout: 60_000 });
  await expect(
    accountLink,
    "ссылка не несёт человекочитаемого имени аккаунта — человек работает с именем",
  ).toContainText(account.label);

  // ПРЕДМЕТ, часть 3 — состояние названо СЛЕДСТВИЕМ.
  await expect(
    membership.getByText(/Состоит в аккаунте|Приглашён, ещё не входил/).first(),
    "состояние членства не названо словами предмета: «Да» не сообщает ни что " +
      "человек состоит, ни что он приглашён",
  ).toBeVisible({ timeout: 60_000 });
});

