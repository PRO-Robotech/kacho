import { test, expect, type Page } from "@playwright/test";
import { tenantWithProject } from "./fixtures";

/**
 * Страница пользователей: что на ней можно СДЕЛАТЬ и что на ней НАПИСАНО.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ЮНИТОМ МОДУЛЯ
 *
 * Обе находки живут на стыке, которого юнит не видит. Первая — на стыке общей
 * оболочки списка и объявления ресурса: край глаголы подаёт, контракт их
 * объявляет, а до экрана они доезжают только если оболочка умеет их рисовать.
 * Вторая — на стыке объявления столбцов и того, что попадает в шапку таблицы, в
 * выбор столбцов и на карточку. Юнит монтирует одну сторону стыка и потому
 * зелен.
 *
 * ЧТО ЭТИ ПРОБЫ НАМЕРЕННО НЕ ДЕЛАЮТ
 *
 * Не запрещают участие по-настоящему. Запрет самому себе необратим по
 * построению: восстановление пароля его не снимает, и вернуть доступ может
 * только администратор аккаунта либо облака. Проба, выполнившая его над
 * собственной личностью, уничтожила бы свою же фикстуру, а её вердикт стал бы
 * зависеть от пути снятия, которого продукт не обещает. Поэтому утверждается
 * то, чего не было: действие ДОСТИЖИМО со строки и подтверждение НАЗЫВАЕТ цену.
 * Что уходит к краю при подтверждении, утверждает проба рядом
 * (`RowActionsMenu.rowverbs.test.tsx`), а существование самого маршрута —
 * перепись глаголов (`console-verb-routes-exist.test.ts`).
 */

/** Строка списка, принадлежащая этой почте. */
function rowOf(page: Page, email: string) {
  return page.locator("tr").filter({ hasText: email }).first();
}

test("iam: со строки пользователя достижим запрет участия", async ({ page }) => {
  // verifies #440 — КРАСНАЯ до фикса задачи.
  //
  // Дефект: `/iam/v1/users/{id}:block` и `:unblock` край подаёт, контракт их
  // объявляет, а в консоли обращения к ним не осталось ни одного — общая
  // оболочка списка знает только правку, удаление и перемещение. Возможность
  // оплачена разработкой и пользователю не досталась.
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // УСЛОВИЕ пробы: своя строка на странице есть. Без неё «действия нет» было бы
  // неотличимо от «страницы нет» — и утверждение ниже не значило бы ничего.
  const строка = rowOf(page, email);
  await expect(
    строка,
    `собственной строки арендатора (${email}) нет на странице пользователей — ` +
      `условие пробы не создано: действовать не над чем`,
  ).toBeVisible({ timeout: 60_000 });

  const действия = строка.getByRole("button", { name: "Действия" }).first();
  await expect(
    действия,
    "у строки пользователя нет меню действий вовсе — тогда действие-глагол " +
      "негде было бы предложить",
  ).toBeVisible({ timeout: 15_000 });
  await действия.click();

  // ПРЕДМЕТ: запрет участия предлагается со строки.
  const запрет = page.getByRole("menuitem", { name: /Запретить участие/ }).first();
  await expect(
    запрет,
    "в меню строки нет «Запретить участие»: край глагол подаёт, контракт его " +
      "объявляет, а из консоли позвать его нечем",
  ).toBeVisible({ timeout: 15_000 });

  // Положительный контроль состава: пары кнопок нет — действие ВЫБИРАЕТСЯ
  // состоянием строки. Участие действует, значит возвращать нечего.
  await expect(
    page.getByRole("menuitem", { name: /Вернуть участие/ }),
    "рядом с запретом предложен и возврат: действующему участию предлагается " +
      "вызов, который ничего не изменит",
  ).toHaveCount(0);

  await запрет.click();

  // Подтверждение обязано НАЗВАТЬ цену до нажатия: это своя строка, и снять
  // запрет с себя нельзя.
  const окно = page.getByRole("dialog").first();
  await expect(
    окно,
    "подтверждения не появилось — необратимое действие уходило бы одним нажатием",
  ).toBeVisible({ timeout: 15_000 });
  await expect(
    окно,
    "подтверждение не называет цену запрета САМОМУ СЕБЕ: оператор выключил бы " +
      "себя одним движением и узнал бы об этом потом",
  ).toContainText(/самостоятельно/i);

  // Уходим не подтвердив: предмет пробы — достижимость действия, а не его исход.
  await окно.getByRole("button", { name: "Отмена" }).first().click();
  await expect(окно, "окно подтверждения не закрылось по отказу").toBeHidden({ timeout: 15_000 });
});

