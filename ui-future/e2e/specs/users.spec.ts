test("iam: список пользователей не показывает аккаунт столбцом", async ({ page }) => {
  // verifies #473 — КРАСНАЯ до фикса задачи.
  //
  // Решение: столбец снят. Строка `users` — это ЧЛЕНСТВО, и аккаунт у неё один
  // по построению; «список аккаунтов человека» показать нечем — такого поля нет
  // ни на одном чтении контракта, поэтому жёсткое предусловие ветви списка не
  // выполнено и она автоматически заменяется на снятие столбца.
  //
  // Ответ «к какому аккаунту относится это членство» живёт на КАРТОЧКЕ и снова
  // имеет источник — ресурс членства (#1085), читаемый аккаунт-скоупно. Его
  // утверждают две пробы ниже по файлу; здесь он не утверждается, чтобы у этой
  // пробы остался один предмет — столбец.
  //
  // Разница охвата, из-за которой одно не противоречит другому: список
  // охватывает НЕСКОЛЬКО аккаунтов сразу, поэтому столбец назвал бы один там,
  // где их несколько; карточка спрашивает про ОДИН выбранный аккаунт.
  test.setTimeout(180_000);
  // Арендатор заводится, но его почта здесь больше не нужна: со снятием части 3
  // проба перестала открывать карточку и живёт целиком на странице списка.
  await tenantWithProject(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // Положительный контроль: таблица отрисована и её шапка читается. Утверждение
  // об ОТСУТСТВИИ столбца зеленеет на пустом экране, на отказе и на не
  // загрузившемся модуле — то есть ровно там, где оно ничего не проверяет.
  await expect(
    page.getByRole("columnheader", { name: "Эл. почта" }).first(),
    "шапки таблицы пользователей нет: список не отрисован, и об отсутствии " +
      "столбца такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДМЕТ, часть 1 — столбца нет в шапке.
  await expect(
    page.getByRole("columnheader", { name: "Аккаунт", exact: true }),
    "в шапке списка пользователей остался столбец «Аккаунт»",
  ).toHaveCount(0);

  // ПРЕДМЕТ, часть 2 — и выбор столбцов его не обещает. Без этой половины
  // столбец мог бы оказаться просто спрятанным: тогда он вернулся бы одним
  // нажатием, а предикат задачи требует, чтобы его не обещала ни одна страница.
  const columns = page.getByRole("button", { name: /Столбцы/ }).first();
  await expect(
    columns,
    "на странице нет выбора столбцов — вторую половину утверждения проверить нечем",
  ).toBeVisible({ timeout: 15_000 });
  await columns.click();
  await expect(
    page.getByRole("menuitem", { name: "Аккаунт", exact: true }),
    "выбор столбцов по-прежнему предлагает «Аккаунт»: столбец не снят, а спрятан",
  ).toHaveCount(0);
  await page.keyboard.press("Escape");

  // ЗДЕСЬ БЫЛА ЧАСТЬ 3 — «карточка НЕ показывает аккаунт». Она СНЯТА, потому
  // что её срок годности истёк ровно так, как был объявлен.
  //
  // Утверждение об отсутствии подписи было верным при отсутствии источника:
  // поле сняли с записи человека (#471), ресурса членства ещё не было, и
  // подпись без источника нарисовала бы прочерк — то есть сказала бы о членстве
  // неправду. Комментарий тогда назвал предикат снятия: «появится ресурс
  // членства — эта половина заменяется на „карточка называет членство“, и
  // заменяется ВМЕСТЕ с ним».
  //
  // Ресурс появился (#1085), и половина ЗАМЕНЕНА — не ослаблена и не удалена:
  // утверждение перевёрнуто в положительное и живёт двумя пробами ниже по
  // файлу, у своего предмета. Здесь оно не осталось потому, что предмет ЭТОЙ
  // пробы — столбец списка, а не карточка: две разные вещи в одной пробе
  // делают её вердикт непрослеживаемым.
  //
  // Части 1 и 2 остаются как были: столбца аккаунта в списке по-прежнему нет и
  // не появляется. Это не противоречие с карточкой, а следствие разницы охвата
  // — список охватывает НЕСКОЛЬКО аккаунтов сразу, поэтому столбец назвал бы
  // один там, где их несколько; карточка спрашивает про ОДИН названный аккаунт.
});

