test("iam: список пользователей не показывает аккаунт столбцом", async ({ page }) => {
  // verifies #473 — КРАСНАЯ до фикса задачи.
  //
  // Решение: столбец снят. Строка `users` — это ЧЛЕНСТВО, и аккаунт у неё один
  // по построению; «список аккаунтов человека» показать нечем — такого поля нет
  // ни на одном чтении контракта, поэтому жёсткое предусловие ветви списка не
  // выполнено и она автоматически заменяется на снятие столбца.
  //
  // Ответ «к какому аккаунту относится это членство» на карточке БОЛЬШЕ НЕ
  // ЖИВЁТ: поле снято с контракта (#471), а ресурса членства ещё нет — см.
  // разбор у части 3. Пока источника нет, карточка обязана МОЛЧАТЬ, а не
  // рисовать пустую подпись; «снято» от «потеряно» отличает теперь не эта
  // проба, а заведённая задача с предикатом (#1085).
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // Положительный контроль: таблица отрисована и её шапка читается. Утверждение
  // об ОТСУТСТВИИ столбца зеленеет на пустом экране, на отказе и на не
  // загрузившемся модуле — то есть ровно там, где оно ничего не проверяет.
  await expect(
    page.getByRole("columnheader", { name: "Эл. почта" }).first(),
    "шапки таблицы пользователей нет: список не отрисован, и об отсутствии " +
      "столбца такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДМЕТ, часть 1 — столбца нет в шапке.
  await expect(
    page.getByRole("columnheader", { name: "Аккаунт", exact: true }),
    "в шапке списка пользователей остался столбец «Аккаунт»",
  ).toHaveCount(0);

  // ПРЕДМЕТ, часть 2 — и выбор столбцов его не обещает. Без этой половины
  // столбец мог бы оказаться просто спрятанным: тогда он вернулся бы одним
  // нажатием, а предикат задачи требует, чтобы его не обещала ни одна страница.
  const columns = page.getByRole("button", { name: /Столбцы/ }).first();
  await expect(
    columns,
    "на странице нет выбора столбцов — вторую половину утверждения проверить нечем",
  ).toBeVisible({ timeout: 15_000 });
  await columns.click();
  await expect(
    page.getByRole("menuitem", { name: "Аккаунт", exact: true }),
    "выбор столбцов по-прежнему предлагает «Аккаунт»: столбец не снят, а спрятан",
  ).toHaveCount(0);
  await page.keyboard.press("Escape");

  // ПРЕДМЕТ, часть 3 — карточка НЕ показывает аккаунт, пока его неоткуда взять.
  //
  // Здесь стояло обратное утверждение — «ответ не потерян, карточка аккаунт
  // называет», — и оно было верно, пока поле было на контракте. Цепочка #471
  // сняла его с ресурса пользователя (`reserved 6; reserved "account_id"`), и
  // ответа не стало НИ У ОДНОГО чтения: `GetUserRequest` несёт только
  // `user_id`, `ListUsersResponse` возвращает голый `User`, ресурса членства
  // нет вовсе. Единственный `account_id`, оставшийся в user.proto, живёт в
  // метаданных ОПЕРАЦИЙ — он описывает мутацию в полёте, а не читаемый факт о
  // строке. То есть сервер аккаунт ЗНАЕТ, но пути прочитать его нет.
  //
  // Поэтому утверждается то, что сегодня верно и содержательно: подпись
  // «Аккаунт» на карточке не рисуется. Это не смягчение, а ПРАВИЛО КОНСОЛИ
  // (ui.md, «поле без источника не показывается»): прочерк под такой подписью
  // утверждал бы о членстве неправду, а список пользователей охватывает
  // НЕСКОЛЬКО аккаунтов сразу («users in Accounts where the principal is a
  // member»), поэтому пустое место читалось бы как «аккаунта нет».
  //
  // СРОК ГОДНОСТИ НАЗВАН: появится ресурс членства — эта половина заменяется на
  // «карточка называет аккаунт членства», и заменяется ВМЕСТЕ с ним, а не
  // раньше. Предмет и предикат — задача про читаемую принадлежность (#1085).
  await rowOf(page, email).getByRole("link").first().click();

  // Положительный контроль: карточка действительно отрисована. Без него
  // утверждение об ОТСУТСТВИИ подписи зеленело бы на пустом экране, на отказе
  // и на не загрузившемся модуле — то есть ровно там, где не проверяет ничего.
  await expect(
    page.getByText("Статус приглашения", { exact: true }).first(),
    "карточка пользователя не отрисована: об отсутствии подписи «Аккаунт» " +
      "такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 60_000 });

  await expect(
    page.getByText("Аккаунт", { exact: true }),
    "на карточке пользователя появилась подпись «Аккаунт», а источника у неё " +
      "нет: поле снято с контракта (#471), ресурса членства ещё нет. Значит " +
      "под подписью стоит прочерк либо величина, выведенная не из членства — " +
      "и то и другое утверждает о членстве неправду",
  ).toHaveCount(0);
});

