test("iam: подтверждение запрета СЕБЕ называет узкий выход", async ({ page }) => {
  // verifies #1219 — КРАСНАЯ до фикса задачи.
  //
  // ДЕФЕКТ. Подтверждение «Запретить участие» живёт в ДВУХ ветках — над чужой
  // строкой и над собственной. Чужая узкий выход называла («есть „Исключить из
  // аккаунта“»), собственная не называла его вовсе. Человек, запрещающий участие
  // СЕБЕ, совершал необратимое — снять запрет самому нельзя, восстановление
  // пароля его не снимает, возвращает доступ только администратор облака, — и не
  // узнавал, что рядом лежит узкое: выйти только из одного аккаунта.
  //
  // ПОЧЕМУ ЭТА ПОЛОВИНА В БРАУЗЕРЕ СОБИРАЕТСЯ, А ПОЛОВИНА #1208 — НЕТ. Предмет
  // #1208 живёт в НЕ-СВОЕЙ ветке, и для неё нужна чужая строка, то есть второй
  // человек в аккаунте (блокатор назван у пробы ниже, здесь не пересказывается).
  // Предмет #1219 — ветка над СОБОЙ, а собственная строка у арендатора этих проб
  // ровно одна и есть всегда. Ничего заводить не требуется.
  //
  // ПОЧЕМУ БРАУЗЕРОМ, А НЕ ТОЛЬКО ЮНИТОМ. Юнит рядом
  // (`RowActionsMenu.rowverbs.test.tsx`) сравнивает ОБЕ ветки в обоих состояниях
  // области, подменив личность вызывающего. Здесь личность НАСТОЯЩАЯ: ветку
  // выбирает сам продукт, сличая строку с тем, кто вошёл, — а это стык потока
  // входа, чтения своей личности и меню строки, которого юнит не видит.
  //
  // ЧТО ЭТА ПРОБА НАМЕРЕННО НЕ ДЕЛАЕТ. Не запрещает участие по-настоящему и не
  // выбирает область. Первое — по причине, названной в шапке файла: запрет себе
  // необратим и уничтожил бы фикстуру. Второе — потому что состояние «область не
  // выбрана» и есть то, в котором цена умолчания максимальна: узкого пункта в
  // меню сейчас нет, и без фразы человек не узнал бы о нём ниоткуда. Состояние
  // «область выбрана» держит юнит (текст) и проба ниже (появление пункта в меню
  // через все четыре перехода) — второй раз здесь оно не собирается.
  test.setTimeout(180_000);
  const { email } = await tenantWithProject(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // УСЛОВИЕ пробы: собственная строка на странице есть. Без неё всё дальнейшее
  // говорило бы не о ветке «над собой», а о том, что страницы нет.
  const row = rowOf(page, email);
  await expect(
    row,
    `собственной строки арендатора (${email}) нет на странице пользователей — ` +
      `условие пробы не создано: ветку «над собой» показать не над чем`,
  ).toBeVisible({ timeout: 60_000 });

  // ПРЕДПОСЫЛКА НАЗВАНА НАБЛЮДАЕМЫМ: область НЕ выбрана. Именно в этом состоянии
  // узкого пункта в меню нет, и текст обязан назвать условие его появления.
  // Выбранная область сделала бы утверждение о слове «выберите» ложным по
  // другой, законной причине — и проба обвинила бы невиновного.
  await expect(
    page.getByRole("button", { name: "Выберите область" }).first(),
    "в шапке нет выбора области с подписью «Выберите область»: область уже выбрана, " +
      "и об условном виде фразы такой прогон не сказал бы ничего",
  ).toBeVisible({ timeout: 30_000 });

  const actions = row.getByRole("button", { name: "Действия" }).first();
  await expect(
    actions,
    "у собственной строки нет меню действий вовсе — тогда подтверждение негде было бы открыть",
  ).toBeVisible({ timeout: 15_000 });
  await actions.click();

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: меню открыто и глаголы строки разрешились.
  const ban = page.getByRole("menuitem", { name: /Запретить участие/ }).first();
  await expect(
    ban,
    "в открытом меню собственной строки нет ни одного глагола: меню не открылось " +
      "или глаголы не разрешились — о тексте подтверждения такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 15_000 });

  // ВТОРАЯ ПОЛОВИНА ПАРЫ, и она обязательна: названный ниже пункт в ЭТОМ меню
  // сейчас ОТСУТСТВУЕТ. Без неё утверждение «текст называет условие» нельзя
  // отличить от текста, который называет условие всегда, в том числе там, где
  // пункт уже есть, — то есть от дефекта, зеркального проверяемому.
  await expect(
    page.getByRole("menuitem", { name: /Исключить из аккаунта/ }),
    "исключение из аккаунта предложено при невыбранной области: тогда фраза " +
      "подтверждения обязана быть безусловной, и эта проба меряет не то состояние",
  ).toHaveCount(0);

  await ban.click();

  const dialog = page.getByRole("dialog").first();
  await expect(
    dialog,
    "подтверждения не появилось — необратимое действие уходило бы одним нажатием",
  ).toBeVisible({ timeout: 15_000 });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ВЕТКИ: окно отрисовано и это ветка «над СОБОЙ», а не
  // общая. Без него утверждение ниже зеленело бы на тексте, показанном ВСЕМ, —
  // то есть ровно на том состоянии, из которого задача выводит.
  await expect(
    dialog,
    "подтверждение над собственной строкой не называет цену запрета САМОМУ СЕБЕ: " +
      "показана не та ветка, и о ней эта проба не утверждает ничего",
  ).toContainText(/самостоятельно/i);

  // ПРЕДМЕТ: узкий выход НАЗВАН — и над собой тоже.
  await expect(
    dialog,
    "подтверждение запрета СЕБЕ не называет «Исключить из аккаунта». Человек " +
      "выполняет необратимое — вход на платформу выключается во всех его " +
      "аккаунтах, и вернуть его сам он не сможет, — не узнав, что рядом есть " +
      "узкое: выйти только из одного аккаунта. Над ЧУЖОЙ строкой этот выход " +
      "называется; разницу веток никто не решал",
  ).toContainText("Исключить из аккаунта");

  // И названо УСЛОВИЕ, при котором пункт появляется: сейчас его в меню нет (см.
  // вторую половину пары выше). Без условия человек искал бы названный выход и
  // не нашёл — дефект #1208, только в собственной ветке.
  await expect(
    dialog,
    "узкий выход обещан БЕЗУСЛОВНО, а пункта в этом меню нет: человек ищет то, " +
      "чего не видит, и выполняет более широкое действие",
  ).toContainText(/выберите область/i);

  // Уходим не подтвердив: предмет пробы — текст подтверждения, а не его исход.
  await dialog.getByRole("button", { name: "Отмена" }).first().click();
  await expect(dialog, "окно подтверждения не закрылось по отказу").toBeHidden({ timeout: 15_000 });
});

