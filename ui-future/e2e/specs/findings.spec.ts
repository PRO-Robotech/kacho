test("vpc: заход по адресу вкладки правил показывает действия над правилами", async ({ page }) => {
  // verifies #425 — предмет ЗАКРЫТ (`42f41e77`), проба держит его закрытым.
  //
  // Дефект был: действия панели правил ставились в правый слот шапки СТРАНИЦЫ.
  // Слот был один, и побеждал в нём последний писатель; при заходе прямо по
  // адресу вкладки (а не переключением на неё внутри карточки) действия панели
  // на экран не попадали: таблица правил есть, а завести или снять правило нечем.
  //
  // Прямой адрес — не экзотика: так открывают ссылку из документации, из чужого
  // сообщения и из закладки.
  test.setTimeout(240_000);
  const { projectId } = await tenantWithProject(page);
  const тег = runTag();

  const сеть = await page.request.post("/vpc/v1/networks", {
    data: { projectId, name: `net-sg-${тег}`, ipv4CidrBlocks: ["10.92.0.0/16"] },
  });
  const netId = await createdResourceId(page, сеть, "networkId", (id) => `/vpc/v1/networks/${id}`, "сеть под группу");

  const имяГруппы = `sg-${тег}`;
  const группа = await page.request.post("/vpc/v1/securityGroups", {
    data: { projectId, networkId: netId, name: имяГруппы },
  });
  const sgId = await createdResourceId(
    page,
    группа,
    "securityGroupId",
    (id) => `/vpc/v1/securityGroups/${id}`,
    "группа безопасности",
  );

  const адресВкладки = `/projects/${projectId}/vpc/security-groups/${sgId}/rules`;
  await page.goto(адресВкладки, { waitUntil: "domcontentloaded" });

  // Положительный контроль: карточка группы отрисована и адрес не сменился. Без
  // него «кнопок не видно» было бы неотличимо от «страница не открылась».
  await expect(
    page.getByText(имяГруппы, { exact: false }).first(),
    `карточка группы ${имяГруппы} не отрисовалась по прямому адресу вкладки правил — условие пробы не создано`,
  ).toBeVisible({ timeout: 60_000 });
  expect(
    new URL(page.url()).pathname,
    "адрес вкладки правил сменился сам — вкладка по прямому заходу недостижима",
  ).toBe(адресВкладки);

  await expect(
    page.getByRole("button", { name: /Добавить правило/ }).first(),
    "по прямому адресу вкладки правил нет действия «Добавить правило»: правила " +
      "видны, а завести правило нечем — действия панели не доехали до шапки страницы",
  ).toBeVisible({ timeout: 30_000 });

  // Имя БЕЗ якоря начала строки, и это не послабление, а форма доступного имени
  // в antd: иконка кнопки — `<span role="img" aria-label="delete">`, и её метка
  // входит в имя ПЕРВОЙ. Кнопка зовётся «delete Удалить», поэтому `/^Удалить/`
  // не совпадал никогда — ни на сломанном продукте, ни на починенном. Соседнее
  // утверждение выше это переживало лишь потому, что строковое имя у Playwright
  // ищется подстрокой, а регулярное — по всему имени целиком.
  await expect(
    page.getByRole("button", { name: /Удалить/ }).first(),
    "по прямому адресу вкладки правил нет действия удаления — снять правило нечем",
  ).toBeVisible({ timeout: 15_000 });
});

