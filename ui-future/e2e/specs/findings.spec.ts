/**
 * Имена чужих поставщиков личности — тем, кто будет править эту строку.
 *
 * Проверка обязана называть то, что запрещает: правило, из которого вынули
 * предмет, следующий читатель снимет как непонятное (`security.md` — имя и текст
 * падения теста выведены из-под запрета именно поэтому).
 *
 * Следствие для закрытия #421: перепись `git grep -in zitadel` обязана исключать
 * ЭТОТ файл, иначе она не дойдёт до нуля никогда — гейт считал бы находкой сам
 * себя.
 */
const ЧУЖИЕ_ПОСТАВЩИКИ = /zitadel|keycloak|auth0|okta|cognito/i;

test("iam: страница пользователей не называет стороннего поставщика личности", async ({ page }) => {
  // verifies #421.
  //
  // Личность в Kachō выдаёт собственный фасад iam. Имя чужого продукта в подписи
  // колонки говорит арендатору неправду о том, чем он входит, и маскирует смысл
  // самого поля: это «идентификатор субъекта у поставщика», а не название чьей-то
  // системы (ban #2 — не называть чужие продукты в коде, документации, интерфейсе).
  test.setTimeout(180_000);
  await tenantWithProject(page);

  await page.goto("/iam/users", { waitUntil: "domcontentloaded" });

  // Положительный контроль: страница действительно отрисована. Утверждение об
  // ОТСУТСТВИИ строки зеленеет на пустом экране, на 404 и на не загрузившемся
  // модуле — то есть ровно там, где оно ничего не проверяет.
  await expect(
    page.getByText("Эл. почта", { exact: false }).first(),
    "страница пользователей не отрисовалась: колонки почты нет. Утверждение об " +
      "отсутствии чужого имени на такой странице ничего не значило бы",
  ).toBeVisible({ timeout: 60_000 });

  const видимыйТекст = await page.locator("body").innerText();
  const найдено = видимыйТекст.match(ЧУЖИЕ_ПОСТАВЩИКИ);
  expect(
    найдено?.[0] ?? null,
    `страница пользователей называет стороннего поставщика личности («${найдено?.[0] ?? ""}»). ` +
      `Арендатор входит через фасад iam, и подпись поля обязана говорить о том, ` +
      `что это за поле, а не о том, чей это продукт`,
  ).toBeNull();
});
