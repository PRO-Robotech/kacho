/**
 * Где на экране стоит подпись пункта раздела — САМАЯ ЛЕВАЯ из её отрисовок.
 *
 * Отрисовок у подписи бывает две: пункт в рейле и заголовок открытой страницы в
 * основной части. Рейл — левый по построению, поэтому «самая левая» выбирает
 * именно пункт и не требует знать разметку: положение на экране — это то, что
 * видит пользователь, а имя класса — нет.
 */
async function положениеПункта(page: Page, подпись: string): Promise<{ x: number; y: number }> {
  const все = page.getByText(подпись, { exact: true });
  const сколько = await все.count();
  expect(сколько, `подписи «${подпись}» нет на экране — раздел не отрисовался, и о его виде вывода нет`).toBeGreaterThan(
    0,
  );

  let лучшая: { x: number; y: number } | null = null;
  for (let i = 0; i < сколько; i++) {
    const box = await все.nth(i).boundingBox();
    if (!box) continue; // невидимая отрисовка — не то, что читает пользователь
    if (лучшая === null || box.x < лучшая.x) лучшая = { x: box.x, y: box.y };
  }
  expect(лучшая, `подпись «${подпись}» есть в разметке, но не занимает места на экране`).not.toBeNull();
  return лучшая!;
}

/** Стоят ли две подписи СТОЛБЦОМ (рейл), а не строкой (ряд вкладок поверх). */
function столбцом(a: { x: number; y: number }, b: { x: number; y: number }): boolean {
  return Math.abs(a.x - b.x) <= 4 && Math.abs(a.y - b.y) >= 16;
}

test("администрирование: обе части раздела строят пункты одним рейлом и без поясняющего абзаца", async ({ page }) => {
  // verifies #447 — КРАСНАЯ до фикса задачи.
  //
  // Владелец на живом стенде: раздел администрирования выглядит иначе, чем
  // прочие разделы консоли, и несёт лишний поясняющий текст. Перепись нашла в
  // разделе ДВА места со своей вёрсткой вкладок; живое из них — «Токены и
  // ключи»: горизонтальный ряд поверх содержимого плюс свой заголовок с
  // абзацем, тогда как соседняя часть того же раздела (регионы, зоны, пулы
  // адресов) рисует пункты вертикальным рейлом общей оболочки — тем же, что
  // карточка ресурса.
  //
  // ПОЧЕМУ БРАУЗЕРОМ. Предмет — РАСКЛАДКА на экране: столбец слева против ряда
  // сверху. Модульная проба монтирует компонент в jsdom, где размеров нет
  // вовсе; она может утверждать, какой оболочкой пункт нарисован, но не то,
  // где пользователь его увидит. Здесь утверждается положение.
  //
  // ПОЧЕМУ ДВЕ ЧАСТИ, А НЕ ОДНА. Одна часть отвечала бы лишь на вопрос «столбец
  // ли это», и проба зеленела бы на консоли, где столбцом стало ВСЁ, включая
  // карточку ресурса, — то есть на общей поломке оболочки. Соседняя часть
  // раздела здесь — положительный контроль: она уже построена общей оболочкой,
  // и если столбца нет и у неё, меряется способ счёта, а не раздел.
  test.setTimeout(180_000);
  await tenantWithProject(page);

  // ── контроль: часть раздела, уже построенная общей оболочкой ───────────────
  await page.goto("/system/regions", { waitUntil: "domcontentloaded" });
  // Условием берётся подпись, которую рисует ТОЛЬКО раздел. «Регионы» для этого
  // не годится: хлебная крошка оболочки хоста печатает её ДО того, как приедет
  // сам модуль, поэтому условие выполнялось бы на ещё не отрисованном разделе, а
  // падала бы следующая строка — и вина легла бы на невиновного.
  await expect(
    page.getByText("Зоны", { exact: true }).first(),
    "часть раздела «Регионы/Зоны» не отрисовалась — условие пробы не создано",
  ).toBeVisible({ timeout: 60_000 });

  const контроль = столбцом(await положениеПункта(page, "Регионы"), await положениеПункта(page, "Зоны"));
  expect(
    контроль,
    "пункты уже общей части раздела не стоят столбцом — меряется не раздел, а " +
      "способ счёта либо сама общая оболочка",
  ).toBe(true);

  // ── предмет: вторая часть того же раздела ─────────────────────────────────
  await page.goto("/system/tokens/service-account-keys", { waitUntil: "domcontentloaded" });
  // Опять подпись, которую печатает только раздел: «Ключи сервисных аккаунтов»
  // стоит и в крошке хоста, то есть появляется до модуля.
  await expect(
    page.getByText("Токены пользователей", { exact: true }).first(),
    "часть раздела «Токены и ключи» не отрисовалась — условие пробы не создано",
  ).toBeVisible({ timeout: 60_000 });

  const ключи = await положениеПункта(page, "Ключи сервисных аккаунтов");
  const токены = await положениеПункта(page, "Токены пользователей");
  expect(
    столбцом(ключи, токены),
    `пункты «Токены и ключи» стоят рядом (${Math.round(ключи.x)},${Math.round(ключи.y)}) и ` +
      `(${Math.round(токены.x)},${Math.round(токены.y)}) — это ряд вкладок поверх содержимого, ` +
      `а соседняя часть ТОГО ЖЕ раздела строит пункты столбцом слева. Пользователь читает ` +
      `разницу как «другое место продукта»`,
  ).toBe(true);

  // ── предмет: лишнего поясняющего абзаца нет ───────────────────────────────
  const видимыйТекст = await page.locator("body").innerText();
  expect(
    видимыйТекст,
    "раздел пересказывает своё название поясняющим абзацем: «Выпуск и отзыв …» " +
      "стоит под заголовком «Токены и ключи». Единственный факт этого абзаца — " +
      "секрет показывается один раз — сказан там, где он нужен: в окне выпуска",
  ).not.toMatch(/Выпуск и отзыв/);
});

