import { test, expect, type Page } from "@playwright/test";
import { dataTable, register } from "./fixtures";

/**
 * Человек видит свой предел на число аккаунтов и свой расход — не открывая ни
 * одного проекта.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ МОДУЛЬНОЙ ПРОБОЙ
 *
 * Модульная проба подменяет ответ и утверждает про отрисовку. Она не видит ни
 * маршрутизации, ни загрузки федеративного модуля, ни края — то есть не может
 * утверждать ровно то, ради чего задача заведена: что адрес ОТКРЫВАЕТСЯ, что
 * край на нём отвечает, и что открывается он БЕЗ проекта. Именно эти три вещи и
 * составляют предикат снятия.
 *
 * ПОЧЕМУ `register`, А НЕ `registerAndSignIn`
 *
 * Второй дожидается проекта арендатора и отдаёт его идентификатор. Здесь это
 * было бы прямо противоположно предмету: страница обязана работать у того, кому
 * открыть нечего. Ожидание проекта сделало бы пробу зелёной по причине, которую
 * она отрицает.
 */

/** Строка витрины, названная человеческим именем вида. */
function строкаВида(page: Page, имя: string) {
  return dataTable(page).locator("tr").filter({ hasText: имя });
}

test("человек видит свой предел на аккаунты и свой расход, не открывая проекта", async ({ page }) => {
  // verifies #622
  await register(page);

  // УСЛОВИЕ, А НЕ ПРЕДМЕТ. Личность резолвится строкой пользователя, которую
  // заводит первый вход; пока она не появилась, чтение отвечает отказом о
  // предпосылке. Ждём СОСТОЯНИЯ, а не времени, и говорим вслух, что провал
  // здесь — «условие не создано», а не вердикт о консоли.
  await expect
    .poll(async () => (await page.request.get("/iam/v1/quotas")).status(), {
      message:
        "чтение квот личности не дошло до 200: арендатор ещё не провязан у владельца величин. " +
        "Это УСЛОВИЕ пробы, а не её предмет — вердикта о консоли такой прогон не даёт",
      timeout: 60_000,
    })
    .toBe(200);

  const [ответ] = await Promise.all([
    page.waitForResponse((r) => new URL(r.url()).pathname === "/iam/v1/quotas", { timeout: 30_000 }),
    page.goto("/iam/quotas", { waitUntil: "domcontentloaded" }),
  ]);

  expect(ответ.status(), `край не отдал пределы личности: ${await ответ.text()}`).toBe(200);

  // Адрес обязан ОСТАТЬСЯ тем, по которому пришли. Пока маршрута не было,
  // раздел уводил ловушкой «всё остальное» на список аккаунтов — и страница
  // выглядела бы исправной, показывая совсем другое.
  expect(new URL(page.url()).pathname, "раздел увёл с адреса витрины — маршрута нет").toBe("/iam/quotas");

  const тело = (await ответ.json()) as { quotas?: Array<{ kind: string; limit: number; used: number }> };
  const предел = (тело.quotas ?? []).find((q) => q.kind === "iam.account");
  expect(
    предел,
    `край не назвал предел на аккаунты; ответ: ${JSON.stringify(тело).slice(0, 300)}`,
  ).toBeTruthy();

  const строка = строкаВида(page, "Аккаунты");
  await expect(строка).toBeVisible({ timeout: 20_000 });

  // Человек читает ИМЕННО ТО, что назвал край: предел и расход — числами, а не
  // именем носителя. Расход, показанный как «считается где-то ещё», и есть тот
  // отказ, ради устранения которого витрина заведена.
  const ячейки = (await строка.getByRole("cell").allInnerTexts()).map((t) => t.trim());
  expect(ячейки, `в строке не оказалось предела ${предел!.limit}`).toContain(String(предел!.limit));
  expect(ячейки, `в строке не оказалось расхода ${предел!.used}`).toContain(String(предел!.used));

  // Источник значения обязателен: без него упёршийся не знает, к кому идти.
  await expect(строка.getByText(/умолчание|Аккаунт |Проект /)).toBeVisible({ timeout: 20_000 });
});

test("витрина квот личности не предлагает арендатору менять величину", async ({ page }) => {
  // verifies #622
  await register(page);
  await expect
    .poll(async () => (await page.request.get("/iam/v1/quotas")).status(), {
      message: "чтение квот личности не дошло до 200 — условие пробы не создано",
      timeout: 60_000,
    })
    .toBe(200);

  await page.goto("/iam/quotas", { waitUntil: "domcontentloaded" });
  await expect(dataTable(page)).toBeVisible({ timeout: 30_000 });

  // Величину назначает администратор облака на внутреннем слушателе. Кнопка,
  // которая у арендатора всегда кончается отказом, — обещание возможности,
  // которой у него нет.
  for (const подпись of [/Изменить предел/i, /Поднять квоту/i, /Редактировать/i]) {
    expect(await page.getByRole("button", { name: подпись }).count()).toBe(0);
  }
});
