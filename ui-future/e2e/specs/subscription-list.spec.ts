import { expect, type Page } from "@playwright/test";
import { createdResourceId, runTag, scopeIsReady, tenantWithProject, test } from "./fixtures";

/**
 * СПИСОК КОНСОЛИ ВЕДЁТСЯ ПОТОКОМ, А НЕ ОПРОСОМ (#1021).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ И ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СОСЕДНЕЙ ПРОБЫ
 *
 * `subscription-stream.spec.ts` утверждает ПРОЕКЦИЮ: страница, открывшая поток
 * своими руками, получает кадры. Её собственная шапка предмет списка с себя
 * снимает и передаёт сюда.
 *
 * Здесь утверждается ПРОДУКТ: список, который человек видит, узнаёт об изменении
 * другого клиента — и узнаёт ПОТОКОМ, потому что опроса больше нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * КАК СНИМАЕТСЯ ВАКУУМНОСТЬ — И ПОЧЕМУ НЕ ГЛУШЕНИЕМ ЗАПРОСА
 *
 * Опасение соседней пробы верное: список, который опрашивается, обновится и без
 * всякого потока, и проба, наблюдающая такой список, зеленеет от опроса.
 *
 * Но названное там средство — заглушить чтение списка через `page.route` — здесь
 * НЕ ГОДИТСЯ, и это измерено, а не предположено: страница по событию не
 * применяет состояние из кадра, а ПЕРЕЧИТЫВАЕТ список тем же самым запросом
 * (`useResourceStream`: «ПОЧЕМУ ПО СОБЫТИЮ ИДЁТ ПЕРЕЧИТЫВАНИЕ, А НЕ ПРИМЕНЕНИЕ
 * СОСТОЯНИЯ» — событие несёт состояние не у всякого вида, а список сужается
 * сервером, и строка, вставленная клиентом, разошлась бы со страницей владельца).
 * Заглушив чтение, проба сломала бы ровно тот механизм, который пришла проверить,
 * и была бы красной при исправном продукте.
 *
 * Вакуумность снимается СИЛЬНЕЕ — наблюдением, а не запретом: перед изменением
 * проба выдерживает ТИХОЕ ОКНО и требует, чтобы за него список не читался НИ
 * РАЗУ. Опрос шёл раз в три секунды; ноль чтений за девять секунд означает, что
 * его нет. Дальше всякое чтение списка — следствие события, потому что другого
 * повода к нему не осталось.
 *
 * Тихое окно доказывает и второе, ради чего задача заводилась: опрос снят НЕ
 * ВООБЩЕ, а признаком покрытия (`refetchInterval: streamed ? false : 3_000`).
 * Не объяви край этот вид — покрытия бы не было, опрос бы работал, и окно
 * оказалось бы непустым.
 */

/**
 * Владелец журнала и его вид — те же, что у соседней пробы, и по той же причине:
 * вид объявлен словарём владельца, а строку журнала пишет само создание сети.
 *
 * ПОСЫЛКА ВТОРОЙ ПРОБЫ ПРОВЕРЕНА ОТДЕЛЬНО, а не унаследована у первой: ей нужна
 * строка журнала не на СОЗДАНИЕ, а на ПРАВКУ, и вид, чьё создание журналируется,
 * этого не обещает. Замер: `services/vpc/internal/apps/kacho/api/network/update.go`
 * эмитит `Network`/`UPDATED` с якорем проекта в той же writer-транзакции; словарь
 * родов изменения vpc выведен разбором ОБОИХ производителей и несёт три слова
 * (`CREATED`, `UPDATED`, `DELETED`).
 *
 * Проверка не педантизм: выбери проба предмет, который никто не журналирует, — и
 * честный отказ («вид не объявлен») сменился бы вечным ожиданием события, которое
 * не пишет никто. Отказ хуже исходного, потому что молчит.
 */
const LIST_PATH = "/vpc/v1/networks";

/**
 * Тихое окно: сколько ждать и сколько чтений списка за него допустимо.
 *
 * Девять секунд — три интервала прежнего опроса. Меньше трёх означало бы, что
 * непустое окно можно списать на совпадение фаз.
 */
const QUIET_MS = 9_000;

/** Счётчик чтений списка, которые делает САМА страница. */
function listReads(page: Page): { count: () => number } {
  let n = 0;
  page.on("request", (r) => {
    if (r.method() !== "GET") return;
    if (new URL(r.url()).pathname === LIST_PATH) n += 1;
  });
  return { count: () => n };
}

async function createNetwork(
  page: Page,
  projectId: string,
  name: string,
  labels?: Record<string, string>,
): Promise<string> {
  // Супернет не объявляется: подсети отсюда никто не режет, а непересекающиеся
  // блоки пришлось бы раздавать вручную — соседние создания в одном проекте
  // спорили бы за CIDR и роняли пробу поводом, к списку не относящимся.
  const res = await page.request.post(LIST_PATH, {
    data: labels ? { projectId, name, labels } : { projectId, name },
  });
  return createdResourceId(
    page,
    res,
    "networkId",
    (id) => `${LIST_PATH}/${id}`,
    `создание предмета списка «${name}»`,
  );
}

test("список показывает предмет, созданный другим клиентом, — и опроса при этом нет", async ({
  page,
}) => {
  // verifies #1021
  test.setTimeout(240_000);

  const { projectId } = await tenantWithProject(page);
  await scopeIsReady(page, projectId);

  // Счётчик ставится ДО перехода: первое чтение списка тоже надо видеть, иначе
  // «ноль за окно» неотличимо от «страница не читала список никогда».
  const reads = listReads(page);

  // Перезагрузок не было — утверждение обязано быть проверяемым, а не
  // подразумеваться из того, что проба не звала `goto` второй раз.
  let loads = 0;
  page.on("load", () => {
    loads += 1;
  });

  await page.goto(`/projects/${projectId}/vpc/networks`);
  await expect
    .poll(() => reads.count(), {
      message: `страница не прочитала ${LIST_PATH} ни разу: дальше утверждать нечего`,
      timeout: 60_000,
    })
    .toBeGreaterThan(0);
  const loadsAtStart = loads;

  // ТИХОЕ ОКНО. Ждём условие, а не время: опрос, если он есть, проявляется
  // РОСТОМ счётчика, поэтому ждём именно роста и требуем, чтобы он не наступил.
  const readsBeforeQuiet = reads.count();
  await expect
    .poll(() => reads.count(), {
      message:
        `за ${QUIET_MS} мс покоя список прочитан снова: опрос НЕ снят. ` +
        `Пока он работает, появление строки ниже ничего не доказывает — она приехала бы ` +
        `и без потока. Опрос выключается признаком покрытия от useResourceStream, ` +
        `значит либо край не объявил этот вид, либо поток не открылся`,
      timeout: QUIET_MS,
      intervals: [1_000],
    })
    .toBe(readsBeforeQuiet);

  // Теперь — и только теперь — изменение от другого клиента.
  const name = `net-list-${runTag()}`;
  await createNetwork(page, projectId, name);

  await expect(page.getByText(name).first(), {
    message:
      `список не показал сеть «${name}», созданную другим клиентом. Опроса нет (доказано ` +
      `тихим окном выше), значит единственным источником этого знания был поток — и он молчал`,
  }).toBeVisible({ timeout: 60_000 });

  expect(
    loads,
    "страница перезагружалась: тогда утверждение о потоке ничего не значит — " +
      "новое состояние приехало бы и обычным чтением",
  ).toBe(loadsAtStart);
});

test("метка снята другим клиентом — строка уходит из суженного списка", async ({ page }) => {
  // verifies #1021
  //
  // Отбор по меткам КЛИЕНТСКИЙ намеренно: оси подписки неизменяемы, а метка
  // мутабельна, и сервер не может сказать «вышел из выборки» иначе как
  // синтетическим снятием — подписчик прочитал бы его как «ресурс удалён».
  //
  // Предикат отбора проверен отдельно и дешевле (`shared/lib/list-label-filter`),
  // членство в показанном списке — тоже
  // (`ResourceListPage.label-filter.test.tsx`). Здесь утверждается то, чего ни
  // одна из двух увидеть не может: переход членства, вызванный СОБЫТИЕМ, — то
  // есть весь тракт целиком, от чужой правки до исчезнувшей строки.
  test.setTimeout(240_000);

  const { projectId } = await tenantWithProject(page);
  await scopeIsReady(page, projectId);

  const tag = runTag();
  const kept = `net-keep-${tag}`;
  const dropped = `net-drop-${tag}`;
  const id = await createNetwork(page, projectId, dropped, { env: "prod" });
  // Соседняя строка с той же меткой — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ отбора: без неё
  // «строка ушла» зеленело бы и на отборе, выбрасывающем всё подряд, и на
  // списке, который просто перестал грузиться.
  await createNetwork(page, projectId, kept, { env: "prod" });

  await page.goto(`/projects/${projectId}/vpc/networks`);
  await expect(page.getByText(dropped).first()).toBeVisible({ timeout: 60_000 });

  // Сужаем по метке. Ручка есть только у ресурсов, которые метки несут.
  await page.getByPlaceholder(/Метки:/i).fill("env=prod");
  await expect(page.getByText(dropped).first()).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText(kept).first()).toBeVisible({ timeout: 30_000 });

  // Другой клиент снимает метку. Пустой набор меток — законный вход правки: имя
  // и прочее не трогаем, поэтому маска называет ровно одно поле.
  const patched = await page.request.patch(`${LIST_PATH}/${id}`, {
    data: { updateMask: "labels", labels: {} },
  });
  expect(
    patched.status(),
    `край отверг снятие метки у ${id} — ${patched.status()}: это УСЛОВИЕ пробы, а не её предмет`,
  ).toBe(200);

  await expect(page.getByText(dropped), {
    message:
      `строка «${dropped}» осталась в суженном списке после того, как потеряла метку. ` +
      `Ровно этот дефект отбор и должен закрывать: ресурс, вышедший из выборки, иначе ` +
      `остаётся в ней навсегда`,
  }).toHaveCount(0, { timeout: 60_000 });

  await expect(page.getByText(kept).first(), {
    message:
      `вместе с потерявшей метку ушла и «${kept}», которая метку сохранила: значит ушёл ` +
      `не отбор, а список — и предыдущее утверждение зеленело бы на пустом экране`,
  }).toBeVisible();
});
