import { expect, type Locator, type Page } from "@playwright/test";
import { createdResourceId, runTag, tenantWithProject, test } from "./fixtures";

/**
 * «Переместить» в меню строки — только там, где перемещение существует.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРЕДМЕТ
 *
 * Пункт «Переместить» открывает окно-заглушку: оно печатает вызов, который был
 * бы сделан. Предлагать его у ресурса, которому перемещаться некуда, — значит
 * обещать возможность, которой нет ни на контракте, ни на крае. Какие ресурсы
 * перемещать нечем, решает ОДИН закрытый перечень на всю консоль; до сведения
 * копий меню (#686) каждый модуль объявлял свой, и один и тот же ресурс мог
 * оказаться перемещаемым в одном разделе и неперемещаемым в соседнем.
 *
 * Перечень — единственный источник этого решения, поэтому проба утверждает его
 * ОБЕ стороны разом: подавлено там, где нечего перемещать, и сохранено там, где
 * есть. Утверждение одной стороны зеленеет на консоли, где пункта нет нигде.
 *
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ МОДУЛЬНОЙ ПРОБОЙ
 *
 * Модульная проба монтирует меню с подставленной спекой и отвечает на вопрос
 * «что вернёт компонент при таком входе». Здесь вопрос другой: что арендатор
 * ВИДИТ в открытом меню на живой странице. Между компонентом и глазом лежат
 * федерация модуля, оболочка списка, реестр ресурсов раздела и права — и
 * перечень, приехавший в общую реализацию, обязан доехать до экрана в каждом
 * разделе, а не только в том, где его правили.
 *
 * ЧЕМ ЗАЩИЩЕНО ОТ ТРИВИАЛЬНОГО ЗЕЛЁНОГО
 *
 * Утверждение «пункта нет» выполняется само собой на пустой таблице, на
 * неоткрывшемся меню и при негодном локаторе. Отсюда три условия, и все три
 * проверяются ДО предмета:
 *   1. положительный контроль идёт ПЕРВЫМ и находит «Переместить» ТЕМ ЖЕ
 *      локатором — значит и пункт в продукте есть, и локатор его видит;
 *   2. строка, над которой открывается меню, видна на экране;
 *   3. меню открылось и непусто — в нём есть действие, приезжающее из состава
 *      операций ресурса, а не из перечня подавления, поэтому оно переживёт
 *      правку по этому предмету.
 */

/** Открывает меню строки и убеждается, что оно открылось непустым. */
async function openRowMenu(page: Page, row: Locator, subject: string): Promise<void> {
  const trigger = row.getByRole("button", { name: "Действия" }).first();
  await expect(
    trigger,
    `у строки (${subject}) нет кнопки действий — меню открывать нечем, и вывод о его ` +
      `составе был бы ни о чём`,
  ).toBeVisible({ timeout: 30_000 });
  await trigger.click();
}

test("меню строки предлагает перемещение только там, где оно есть", async ({ page }) => {
  // verifies #688
  test.setTimeout(180_000);
  const { projectId } = await tenantWithProject(page);

  // ── ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: ресурс, которому перемещение объявлено ────────
  //
  // Он идёт первым намеренно. Упади он — предмет ниже не проверяется вовсе, и
  // причина названа верно: «пункта нет нигде» либо «локатор его не видит», а не
  // «подавление работает».
  const name = `net-move-${runTag()}`;
  await createdResourceId(
    page,
    await page.request.post("/vpc/v1/networks", {
      data: { projectId, name, ipv4CidrBlocks: ["10.97.0.0/16"] },
    }),
    "networkId",
    (id) => `/vpc/v1/networks/${id}`,
    "сеть под положительный контроль перемещения",
  );

  await page.goto(`/projects/${projectId}/vpc/networks`, { waitUntil: "domcontentloaded" });

  const networkRow = page.locator("tr").filter({ hasText: name }).first();
  await expect(
    networkRow,
    `строки созданной сети (${name}) нет на странице сетей — условие пробы не создано: ` +
      `меню открывать не над чем`,
  ).toBeVisible({ timeout: 60_000 });

  await openRowMenu(page, networkRow, `сеть ${name}`);

  await expect(
    page.getByRole("menuitem", { name: /Переместить/ }).first(),
    `в меню строки сети нет пункта «Переместить», хотя сети перемещение объявлено. ` +
      `Пока это так, утверждение об ОТСУТСТВИИ пункта у другого ресурса не значит ничего: ` +
      `оно одинаково зеленеет и на верном подавлении, и на консоли, где пункта нет нигде`,
  ).toBeVisible({ timeout: 15_000 });

  // Меню закрывается явно: открытый список пунктов пережил бы переход и
  // следующее утверждение читало бы состав ЧУЖОГО меню.
  await page.keyboard.press("Escape");
  await expect(page.getByRole("menuitem", { name: /Переместить/ })).toHaveCount(0);

  // ── ПРЕДМЕТ: ресурс, которому перемещаться некуда ─────────────────────────
  //
  // Регион — глобальная координата размещения: она не принадлежит проекту, и
  // переносить её между проектами не во что. Строка берётся из справочника, а
  // не выписывается: имена каталога — произвольные строки стенда, и выписанное
  // значение разошлось бы с посевом молча.
  const catalog = await page.request.get("/geo/v1/regions");
  expect(
    catalog.ok(),
    "справочник регионов недоступен — условие пробы не создано: строки, над которой " +
      "открывают меню, не существует",
  ).toBeTruthy();
  const region =
    ((await catalog.json()) as { regions?: Array<{ id: string }> }).regions?.[0]?.id ?? "";
  expect(region, "справочник регионов пуст — стенд не засеян, условие пробы не создано").not.toBe("");

  await page.goto("/system/regions", { waitUntil: "domcontentloaded" });

  const regionRow = page.locator("tr").filter({ hasText: region }).first();
  await expect(
    regionRow,
    `строки региона (${region}) нет на странице каталога — условие пробы не создано`,
  ).toBeVisible({ timeout: 60_000 });

  await openRowMenu(page, regionRow, `регион ${region}`);

  // Меню открылось и осмысленно. Действие берётся из состава операций ресурса:
  // оно не приезжает из перечня подавления и потому переживёт правку по этому
  // предмету. Без этой строки «пункта нет» зеленело бы на меню, которое просто
  // не раскрылось.
  await expect(
    page.getByRole("menuitem", { name: /Редактировать|Удалить/ }).first(),
    `меню строки региона не открылось или пусто: в нём нет ни одного действия из состава ` +
      `операций ресурса. Вывод об отсутствии другого пункта был бы сделан над закрытым меню`,
  ).toBeVisible({ timeout: 15_000 });

  await expect(
    page.getByRole("menuitem", { name: /Переместить/ }),
    `строка региона предлагает «Переместить». Регион — глобальная координата размещения, ` +
      `переносить её между проектами не во что: пункт открыл бы окно-заглушку с вызовом, ` +
      `которого нет. Рядом в том же меню стоят настоящие действия, и на вид они неотличимы`,
  ).toHaveCount(0);
});
