test("темы документации не притворяются ссылками", async ({ page }) => {
  // verifies #1611
  //
  // Дефект: сорок четыре объявления ссылок на документацию несли адрес «#» —
  // живых адресов ноль. Оба места показа при этом уже рисовали темы текстом,
  // поэтому адрес не читал никто: он лишь приглашал «починить» его одной живой
  // строкой, после чего не произошло бы ничего.
  //
  // Утверждается наблюдаемое: под заголовком «Документация» стоят ТЕМЫ, и ни
  // одна из них не является ссылкой, ведущей на ту же страницу. Клик по такой
  // ссылке — единственный способ обнаружить обман, и проба закрывает именно его.
  test.setTimeout(180_000);
  const { projectId } = await tenantWithProject(page);

  await page.goto(`/projects/${projectId}/vpc/networks`, {
    waitUntil: "domcontentloaded",
  });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: раздел с темами отрисовался. Без него отрицание
  // ниже зеленело бы на странице, где нет ни одной темы.
  await expect(
    page.getByText("Документация").first(),
    "раздела «Документация» на экране нет — утверждать о его темах нечего",
  ).toBeVisible({ timeout: 45_000 });

  const dead = page.locator('a[href="#"]');
  await expect(
    dead,
    "на экране есть ссылка с адресом «#»: она обещает переход, которого не существует, " +
      "и обнаруживает это только кликом",
  ).toHaveCount(0);
});
