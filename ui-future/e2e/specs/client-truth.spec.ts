test("первый экран нового клиента называет первый шаг", async ({ page }) => {
  // verifies #1613
  //
  // Дефект: человек, впервые вошедший в консоль, читал на главной «Выберите
  // проект в дереве слева» и то же на пяти плитках из шести, тогда как дерево
  // слева сообщало «Аккаунтов нет». Продукт велел сделать то, чего клиент
  // сделать не может, и молчал о настоящем первом шаге; замки при этом читались
  // как «мне сюда не выдали прав».
  //
  // Проба берёт клиента ДО создания аккаунта — поэтому здесь `register`, а не
  // `tenantWithProject`: последний завёл бы аккаунт и уничтожил предмет.
  test.setTimeout(180_000);
  await register(page);

  await page.goto("/dashboard", { waitUntil: "domcontentloaded" });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: главная отрисовалась.
  await expect(
    page.getByRole("heading", { name: "Сервисы облака" }),
    "главная не отрисовалась — утверждать о её словах нечего",
  ).toBeVisible({ timeout: 45_000 });

  const step = page.getByTestId("dashboard-first-step-action");
  await expect(
    step,
    "на первом экране нет хода к первому шагу: клиенту сказано выбрать проект, " +
      "а выбирать нечего — ни аккаунта, ни проекта у него ещё нет",
  ).toBeVisible({ timeout: 30_000 });

  await expect(
    page.getByText(
      "Выберите проект в дереве слева — модули открываются в его границах.",
    ),
    "экран велит выбрать проект, когда выбирать нечего: это отказ, не восстанавливающий следующий шаг",
  ).toHaveCount(0);

  // Ход существует и ведёт туда, где шаг делается.
  await step.click();
  await expect
    .poll(() => new URL(page.url()).pathname, {
      message:
        "ход с первого экрана никуда не привёл: названный шаг остался недостижимым",
      timeout: 30_000,
    })
    .toContain("/iam/accounts");
});

