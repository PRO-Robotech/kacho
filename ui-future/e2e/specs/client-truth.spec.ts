test("экран выдачи прав называет уровни теми же словами, что и вся консоль", async ({
  page,
}) => {
  // verifies #1609
  //
  // Дефект: на самом ответственном экране одна и та же пара сущностей была
  // названа тремя способами сразу. Переключатель области подписан
  // «Облако»/«Каталог» — словами из модели, которой в продукте нет (уровни:
  // аккаунт → проект), причём «Каталог» уже занят админскими справочниками;
  // заглушка звала выбрать «Project» латиницей; пилюля в шапке говорила
  // «Проект». Цена не косметическая: ошибка выбора области здесь означает
  // выданный не туда доступ.
  test.setTimeout(180_000);
  await tenantWithProject(page);

  await page.goto("/iam/access", { waitUntil: "domcontentloaded" });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: переключатель уровня вообще отрисовался. Без него
  // отрицания ниже зеленели бы на пустой странице.
  const account = page.getByText("Аккаунт", { exact: true }).first();
  await expect(
    account,
    "переключатель уровня не назвал «Аккаунт»: либо экран не отрисовался, либо уровень " +
      "по-прежнему назван словом, которого в модели продукта нет",
  ).toBeVisible({ timeout: 45_000 });

  for (const wrong of ["Облако", "Каталог"]) {
    await expect(
      page.getByText(wrong, { exact: true }),
      `уровень назван «${wrong}» — словом из модели, которой в продукте нет. ` +
        `Клиенту приходится догадываться, что это аккаунт и проект`,
    ).toHaveCount(0);
  }

  // Заглушка и подсказки направляют к ручке ТЕМ ЖЕ словом, что на ручке
  // написано. Замер по дереву дал таких мест 18 — не только на этом экране,
  // поэтому проба смотрит на форму фразы, а не на одну строку.
  await expect(
    page.getByText(/Выберите (Project|Account)\b/),
    "экран зовёт выбрать «Project»/«Account» латиницей, а ручка подписана по-русски: " +
      "клиент отправлен искать то, чего на ней не написано",
  ).toHaveCount(0);
});

