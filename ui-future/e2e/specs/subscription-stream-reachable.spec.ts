import { expect } from "@playwright/test";
import { registerAndSignIn, test } from "./fixtures";

/**
 * Отказ ручки потока обязан БЫТЬ ДОСТИЖИМ ОТТУДА, ОТКУДА ЕГО БУДУТ ЧИТАТЬ.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРЕДМЕТ (#1394)
 *
 * Консоль ходит на тот же источник, что и страница, — значит через раздачу
 * консоли. Пока её блоки не покрывали адрес потока, он доставался общему
 * `location /`, а тот отдаёт `index.html` с кодом `200` и типом `text/html`.
 *
 * Для потока это класс хуже, чем «страница не открылась»: приёмник событий
 * браузера на неверном типе закрывает соединение НАВСЕГДА и выдаёт ошибку без
 * подробностей. Со стороны — тишина: в журнале края ни строки (запрос не
 * доехал), в журнале раздачи `200`, метрики нет. Всё зелено.
 *
 * Отдельная половина того же предмета: продукт объясняет своё состояние отказом
 * `501` («владелец журнала не объявлен»). Пока запрос не доезжал, этот отказ
 * производился ТОЛЬКО при прямом пробросе порта в под — то есть диагностика, на
 * которой построена вся возможность, была недоступна тому, кто ею пользуется.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЗДЕСЬ УТВЕРЖДАЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО
 *
 * Утверждается ОДНО: ответ произвёл КРАЙ, а не заглушка одностраничного
 * приложения. Признак машинный и не зависит от посадки — тип ответа: край
 * отвечает `application/json` (отказ) либо `text/event-stream` (поток), заглушка
 * — всегда `text/html`.
 *
 * Точный код здесь НЕ закрепляется, и это не послабление, а разные ПОЛОСЫ с
 * разными производителями, каждая из которых законна:
 *
 *   `501` — владелец журнала не объявлен ни в одном профиле (сегодня; это #1388);
 *   `200` — владелец объявлен, и поток открылся;
 *   `403`/`401` — полоса прав отвечает раньше обработчика.
 *
 * Закрепи проба любой один код — она покраснела бы на ЧУЖОЙ посадке, дефектом
 * продукта не являющейся, и первым же красным её сняли бы вместе с предметом.
 * Ровно тот исход, которого здесь нельзя допустить: `text/html` обязан остаться
 * красным навсегда.
 *
 * ЗАЧЕМ ЗАПРОСОМ, А НЕ `EventSource`. Приёмник событий браузера кода ответа не
 * отдаёт вовсе — он умеет только «открылось» и «сбой», и на `text/html` даёт
 * ровно тот же сбой, что на недоступном крае. То есть именно ту тишину, которую
 * проба обязана различить. Запрос страницы несёт те же печенья сессии и
 * возвращает и код, и тип.
 *
 * Разбор кадров и возобновление с позиции — предмет проб, ждущих своего условия
 * (`specs-awaiting-journal-owner/subscription-stream.spec.ts`), и здесь он не
 * пересказывается.
 */

const STREAM = "/subscription/v1/events";

test("адрес потока приходит на край, а не в заглушку приложения", async ({ page }) => {
  // verifies #1394
  await registerAndSignIn(page);

  const response = await page.request.get(STREAM, {
    headers: { Accept: "text/event-stream" },
    // Отказ — законный исход этой пробы, а не сбой запроса.
    failOnStatusCode: false,
  });

  const status = response.status();
  const contentType = (response.headers()["content-type"] ?? "").toLowerCase();
  const body = (await response.text()).slice(0, 400);

  // Положительный контроль стоит ПЕРВЫМ: без него отрицание ниже зеленело бы на
  // пустом ответе — а пустой ответ означает, что не сработал сам запрос.
  expect(contentType, `ответ ${STREAM} без типа: status=${status}, тело=${body}`).not.toBe("");

  expect(
    contentType,
    `адрес потока ${STREAM} вернул ${status} ${contentType} — это заглушка одностраничного ` +
      "приложения, а не край. Приёмник событий браузера на таком типе закрывает соединение " +
      "навсегда и выдаёт ошибку без подробностей: со стороны это тишина, при том что в журнале " +
      "раздачи стоит успех. Маршрут держит блок раздачи консоли " +
      "(ui-future/deploy/templates/configmap-nginx.yaml) и его проба " +
      `(ui-future/deploy/subscription_stream_serving_test.go). Тело ответа: ${body}`,
  ).not.toContain("text/html");

  expect(
    contentType.includes("application/json") || contentType.includes("text/event-stream"),
    `адрес потока ${STREAM} вернул тип ${contentType}, которого край не производит ни на одной ` +
      `своей полосе (отказ — application/json, поток — text/event-stream). status=${status}, тело=${body}`,
  ).toBe(true);

  // Перепись в отчёт: какая полоса ответила на этой посадке. «Ноль находок»
  // обязано быть отличимо от «ноль прочитанного» — здесь это читается прямо.
  test.info().annotations.push({
    type: "перепись",
    description: `${STREAM}: status=${status}, content-type=${contentType}, тело=${body}`,
  });
});
