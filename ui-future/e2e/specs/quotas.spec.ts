/**
 * Арендатор видит свои пределы — без обращения в поддержку.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ
 *
 * Модульная проба подменяет ответ и утверждает про отрисовку. Она не может
 * утверждать, что край этот ответ ДАЁТ: чтение квот гейтится отношением на
 * проекте, а сам глагол регистрируется условно — если полоса квот не собрана,
 * его нет вовсе, и вместо набора пределов приходит отказ «не реализовано».
 *
 * Поэтому здесь утверждается пара: край отвечает — и витрина показывает то, что
 * он назвал.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОСАДОК ДВЕ, И ОБЕ ЗАКОННЫ (#2515, объявлены #2596)
 *
 * Здесь стояло безусловное «край отдал 200 и непустой набор». Это было верно,
 * пока посадка была ОДНА: домен величин жил внутри службы доступа и
 * разворачивался всегда. Служба вынесена отдельным продуктом, ручка домена
 * величин получила второе законное значение — `not-deployed`, — и пять
 * потребителей объявили им себя. На такой посадке потолков не назначает никто,
 * ни одна мутация не отвергается по пределу, а витрина обязана НАЗВАТЬ это
 * словом (`docs/architecture/quota-surface-breakdown.md` §В5).
 *
 * Безусловное утверждение стало утверждением о ПОСАДКЕ, а не о продукте: оно
 * краснело на стенде, который ведёт себя ровно так, как решено. Поэтому посадка
 * читается у края машинным признаком (`quota-posture.ts`), и каждая ветвь несёт
 * СВОЙ полный набор утверждений.
 *
 * Это НЕ терпимость к двум исходам. Терпимость — «принимаем 200 либо 400 и не
 * утверждаем ничего». Здесь у каждой посадки своё наблюдаемое, каждое
 * опровержимо, и третий исход (пятеро разошлись) краснеет отдельным сообщением.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ `table` НЕ АДРЕСУЕТ СТРОКУ ОДНОЗНАЧНО
 *
 * Общая таблица консоли (`ResourceTable`) держит фиксированную шапку колонок
 * над скроллящимся телом (`ui.md`, правило 10) — библиотека реализует это ДВУМЯ
 * `<table>`: один несёт `<thead>` без строк, другой — `<tbody>` со строками.
 * Оба видимы, `page.locator("table")` резолвит два элемента, и `.first()` не
 * годится: у заголовочной таблицы строк нет, и следующее утверждение о
 * содержимом било бы мимо предмета. Таблица со строками — та, у которой ЕСТЬ
 * `tbody`; это верно и в режиме БЕЗ фиксированной шапки, где обе части живут в
 * одном `<table>` (`:has(tbody)` матчит и его).
 */
function dataTable(page: Page): Locator {
  return page.locator("table").filter({ has: page.locator("tbody") });
}

/**
 * Витрина ОТРИСОВАНА — положительный контроль, общий обеим посадкам.
 *
 * Без него каждое утверждение об отсутствии («машинных ключей нет», «красной
 * плашки нет») было бы истинно и на не загрузившемся модуле, и на пустой
 * странице. Фраза выбрана из шапки: она стоит там при ЛЮБОЙ посадке, поэтому
 * контроль не зависит от предмета ни одной из ветвей.
 */
async function showcaseRendered(page: Page): Promise<void> {
  await expect(
    page.getByText(VALUES_SET_BY).first(),
    "витрина квот не отрисована вовсе: об именах, пределах и посадке такой прогон " +
      "не говорит ничего — утверждения об отсутствии были бы истинны на пустом экране",
  ).toBeVisible({ timeout: 30_000 });
}

/**
 * Посадка без домена величин НАЗВАНА словом, а не выдана за сбой.
 *
 * Три утверждения, и ни одно не выводится из другого: сказано, что потолков нет
 * (арендатор узнаёт, что просить не у кого) · подпись пустой витрины — та же
 * посадка, а не «не прочитаны» · красной плашки НЕТ. Третье — тот самый дефект
 * #2515: законная посадка показывалась поломкой.
 */
async function absenceNamed(page: Page): Promise<void> {
  await expect(
    page.getByText(new RegExp(ABSENCE_TITLE, "i")).first(),
    "посадка без домена величин не названа: арендатор не узнаёт, что потолков нет " +
      "и повышения просить не у кого",
  ).toBeVisible({ timeout: 30_000 });

  await expect(
    page.getByText(ABSENCE_EMPTY_HINT).first(),
    "пустая витрина не назвала посадку: подпись «ограничения не прочитаны» утверждает " +
      "поломку там, где оператор объявил отсутствие потолков",
  ).toBeVisible({ timeout: 30_000 });

  expect(
    await page.getByText(new RegExp(READ_FAILED_PLATE, "i")).count(),
    "законная посадка показана СБОЕМ — ровно то состояние, ради устранения которого " +
      "витрина и заведена (#2515)",
  ).toBe(0);
}

test("витрина квот показывает пределы проекта", async ({ page }) => {
  // verifies #364
  const { projectId } = await registerAndSignIn(page);
  const showcase = await openShowcase(page, projectId);

  // Спрошены ВСЕ пятеро — до всякого вывода о посадке: владелец, списывающий
  // квоту и не спрошенный страницей, означает предел, которого арендатор не
  // видит, и посадку по четырём ответам устанавливать нельзя.
  expect(
    showcase.silent,
    "страница не спросила часть владельцев пределов: посадка выводится из ответов " +
      "ПЯТЕРЫХ, и по неполному набору она не устанавливается",
  ).toEqual([]);

  const posture = postureOrFail(showcase.answers);
  await showcaseRendered(page);

  if (posture === "absent") {
    // ПОСАДКА БЕЗ ДОМЕНА ВЕЛИЧИН. Показывать нечего — и это надо СКАЗАТЬ.
    await absenceNamed(page);
    // Положительный контроль к утверждению об отсутствии плашки: витрина
    // отрисовала таблицу, а не осталась заглушкой. Пустая — законно: пределов
    // нет, и подпись об этом уже утверждена выше.
    await expect(dataTable(page)).toBeVisible({ timeout: 20_000 });
    return;
  }

  // ПОСАДКА С РАЗВЁРНУТЫМ ДОМЕНОМ ВЕЛИЧИН — прежний предмет пробы целиком.
  //
  // Контракт обещает полный набор всегда — даже проекту, где ничего не создано.
  // Пустой ответ означал бы, что витрине нечего показать не по своей вине.
  const named = showcase.answers.flatMap((a) => a.kinds);
  expect(named.length, "край ответил успехом и не назвал ни одного предела").toBeGreaterThan(0);

  await expect(dataTable(page)).toBeVisible({ timeout: 20_000 });
  // Источник значения обязателен: без него упёршийся не знает, куда идти.
  await expect(page.getByText(/умолчание|Аккаунт |Проект /).first()).toBeVisible({ timeout: 20_000 });
});

/**
 * Тенантская страница НЕ несёт ручки изменения величины.
 *
 * Величины меняет только администратор облака, своим разделом. Кнопка, которая
 * у арендатора всегда заканчивается отказом, — обещание возможности, которой у
 * него нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ОТРИЦАНИЕ ЗДЕСЬ БЫЛО ОДИНОКИМ — И НА НОВОЙ ПОСАДКЕ СТАЛО ВАКУУМНЫМ
 *
 * Проба утверждала «кнопок правки нет» и требовала лишь видимой таблицы. На
 * посадке без домена величин таблица видима и ПУСТА, поэтому «кнопок нет»
 * истинно by construction: их нет, потому что нет ни одной строки. Проба была
 * зелена и не говорила ничего — тот же класс, что «положительный контроль,
 * выполняющийся на пустом наборе» (`testing.md`).
 *
 * Найдено переписью этого же прогона: проба прошла там, где две соседние
 * упали, — и прошла по причине, к своему предмету не относящейся.
 *
 * Поэтому контроль назван: витрина отрисована (общая фраза шапки), и на
 * посадке с пределами у неё ЕСТЬ строки — иначе отрицание снова судило бы о
 * пустом экране.
 */
test("витрина квот не предлагает арендатору менять величину", async ({ page }) => {
  // verifies #364
  const { projectId } = await registerAndSignIn(page);
  const showcase = await openShowcase(page, projectId);
  const posture = postureOrFail(showcase.answers);

  await showcaseRendered(page);
  await expect(dataTable(page)).toBeVisible({ timeout: 30_000 });

  if (posture === "deployed") {
    // Положительный контроль, доступный только на этой посадке: строки есть,
    // значит отрицание ниже судит о витрине С СОДЕРЖИМЫМ.
    await expect(
      dataTable(page).locator("tbody tr").first(),
      "витрина без строк: «ручек правки нет» было бы истинно и на пустом экране",
    ).toBeVisible({ timeout: 20_000 });
  } else {
    // На посадке без потолков строк нет ЗАКОННО, и контролем служит то, что
    // посадка названа словом: экран не пуст — он объясняет себя.
    await absenceNamed(page);
  }

  for (const label of [/Изменить предел/i, /Поднять квоту/i, /Редактировать/i]) {
    expect(
      await page.getByRole("button", { name: label }).count(),
      `витрина предлагает арендатору ручку «${label.source}» — действие, которое у него ` +
        "всегда заканчивается отказом: величины задаёт администратор облака",
    ).toBe(0);
  }
});

/**
 * Витрина квот называет ресурс тем же словом, что и остальная консоль.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ГЕЙТОМ
 *
 * Гейт рядом (`shared/src/test/console-quota-kind-named-like-the-entity.test.ts`)
 * сверяет ОБЪЯВЛЕНИЯ дерева и по построению не видит двух вещей: какие виды край
 * называет НА САМОМ ДЕЛЕ и что из названного доехало до экрана. Здесь — и то, и
 * другое: набор берётся из ответов края, слова читаются со страницы.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ИСТОЧНИКОВ ПЯТЬ, А НЕ ОДИН — И ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ПРОБЫ ЧИТАЛА ОДИН
 *
 * Первая редакция ждала `/vpc/v1/quotas` и строила набор видов ИЗ НЕГО, а затем
 * требовала пары «прежнее написание → нынешнее» по видам `loadbalancer.*`,
 * `compute.*` и `iam.*`. Ни один из них не является видом vpc, поэтому набор не
 * мог их содержать НИ НА КАКОМ стенде: проба честно печатала «условие пробы не
 * создано» и роняла весь набор. Условие было создано — спрашивали не тот
 * источник. Поэтому набор берётся из ТЕХ ЖЕ пяти источников, что читает страница.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ГРАНИЦА: ВИДОВ `iam.*` НА ЭТОЙ СТРАНИЦЕ НЕТ ВОВСЕ
 *
 * Среди пяти владельцев iam отсутствует, поэтому `iam.serviceAccount` и
 * `iam.accessBinding` этой страницей не показываются ни при каких условиях —
 * утверждать о них здесь значило бы утверждать об экране, который их показать
 * не может.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ОТКРЫТЫЙ ДОЛГ: НА ПОСАДКЕ БЕЗ ДОМЕНА ВЕЛИЧИН У ПОЛОВИНЫ ПРОБЫ НЕТ ПРЕДМЕТА
 *
 * Это надо сказать прямо, потому что молчание здесь дороже красного.
 *
 * Гейт-сосед объявляет, что сверку «каждый вид каталога владельца назван на
 * витрине» (B⊇A) он больше НЕ держит — каталог уехал вместе со службой доступа,
 * — и прямо делегирует её ЭТОЙ пробе: «держится ЖИВЫМ каталогом… спрашивает всех
 * владеющих доменов». Тем же изменением, которым делегировал, пять потребителей
 * объявили домен величин отсутствующим (#2596) — и живого каталога не стало ни
 * у гейта, ни у пробы.
 *
 * СЛЕДСТВИЕ, НАЗВАННОЕ ЧИСЛОМ: на посадке `not-deployed` край не называет НИ
 * ОДНОГО вида (пять владельцев из пяти отвечают отказом), поэтому утверждения
 * 2 и 3 ниже — «машинный ключ не доехал до экрана» и «прежние написания ушли» —
 * предмета не имеют: они истинны на экране, где не показано ничего. Сверка B⊇A
 * в этом дереве не держится СЕГОДНЯ НИЧЕМ.
 *
 * ЧТО ЗДЕСЬ СДЕЛАНО ВМЕСТО. Проба не снята (`testing.md` §«E2E НИКОГДА не
 * пропускаются»: кейсу с недоступной зависимостью полагается своя волна, а не
 * снятие) и не ослаблена до вакуумного зелёного: на посадке без потолков она
 * утверждает то, что НА САМОМ ДЕЛЕ наблюдаемо и опровержимо, — что арендатору
 * названа посадка, а не показан ключ, обрывок или красная плашка. Это слабее
 * B⊇A, и слабее названо словом, а не выдано за равное.
 *
 * ПРЕДИКАТ ВОЗВРАТА — ВНЕШНИЙ, а не «когда доделаем»: обе половины оживают в
 * тот момент, когда любая установка объявит домен величин адресом. Это вопрос
 * В1 разбора (`docs/architecture/quota-surface-breakdown.md`: «пока владелец не
 * назван, ребра нет») и стадия S4 задачи #2117. Ветвь `deployed` ниже —
 * прежний предмет пробы целиком, дословно; она исполнится без правки.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ
 *
 *  1. страница спрашивает ВСЕХ пятерых — на любой посадке. Владелец, списывающий
 *     квоту и не спрошенный страницей, — арендатор упирается в предел, которого
 *     не видит;
 *  2. перечень владельцев в этой пробе совпадает с тем, что страница спросила
 *     НА САМОМ ДЕЛЕ, — в обе стороны: пропавший владелец и появившийся шестой;
 *  3. на посадке с пределами: ни одно машинное имя вида не доехало до экрана, а
 *     прежние написания (#1703) ушли, и пришедшие им на смену — те же, что в
 *     меню консоли;
 *  4. на посадке без пределов: посадка названа словом.
 *
 * Отрицания идут В ПАРЕ с положительным контролем: «слова нет» истинно и на
 * пустой странице, и на не загрузившемся модуле.
 */
test("витрина квот называет ресурс словом консоли, а не ключом каталога", async ({ page }) => {
  // verifies #1703
  const { projectId } = await registerAndSignIn(page);
  const showcase = await openShowcase(page, projectId);

  // ПРЕДМЕТ, часть 1 — спрошены все пятеро.
  expect(
    showcase.silent,
    "страница не спросила часть владельцев пределов: набор видов ниже оказался бы " +
      "у́же экрана, и оба утверждения судили бы не о том. Владелец, списывающий " +
      "квоту и не спрошенный страницей, — арендатор упирается в предел, которого не видит",
  ).toEqual([]);

  // ПРЕДМЕТ, часть 2 — наблюдённый набор источников против ВЫПИСАННОГО.
  //
  // Перечень в пробе есть второе место об одном предмете, и разойтись с
  // `QUOTA_OWNERS` оно может молча: копия не собирается вместе со страницей и не
  // импортируется ею. Здесь это ловится не сверкой деревьев, а наблюдением — что
  // страница спросила на самом деле, — и потому ловится в ОБЕ стороны.
  expect(
    showcase.observed,
    "перечень владельцев пределов в этой пробе разошёлся с тем, что страница " +
      "спрашивает на самом деле: набор видов ниже не описывает экран целиком",
  ).toEqual([...QUOTA_OWNER_PATHS].sort());

  const posture = postureOrFail(showcase.answers);
  await showcaseRendered(page);

  if (posture === "absent") {
    // ПРЕДМЕТ, часть 4. Виды называть нечем — край не назвал ни одного. Назвать
    // это «именами в порядке» было бы вакуумным зелёным (см. долг в шапке),
    // поэтому утверждается наблюдаемое: посадка названа арендатору словом.
    await absenceNamed(page);
    return;
  }

  // ПОСАДКА С ПРЕДЕЛАМИ — прежний предмет пробы целиком.
  const kinds = showcase.answers.flatMap((a) => a.kinds);
  expect(kinds.length, "край вернул пустой набор пределов — называть на витрине нечего").toBeGreaterThan(0);

  await expect(dataTable(page)).toBeVisible({ timeout: 30_000 });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ к обоим отрицаниям ниже: витрина не только
  // отрисована, но и НАЗЫВАЕТ ресурс по-русски. Слово выбрано из тех, что и до
  // #1703 совпадали со словарём, — то есть контроль не зависит от предмета пробы.
  await expect(
    page.getByText("Облачные сети", { exact: true }).first(),
    "витрина не называет ни одного ресурса словом: строк нет, модуль не загрузился " +
      "или таблица пуста — об именах такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 30_000 });

  // ПРЕДМЕТ, часть 3 — ключ каталога на экран не выходит.
  //
  // До #1703 красным это было на видах `iam.*`, которых эта страница не
  // показывает, — то есть на ней утверждение было истинно и тогда. Оно стоит
  // здесь не как замок на прошлое, а как замок вперёд: вид, заведённый у одного
  // из пяти владельцев и не названный консолью, покажется арендатору ключом.
  const shownAsMachineName: string[] = [];
  for (const kind of kinds) {
    if ((await page.getByText(kind, { exact: false }).count()) > 0) shownAsMachineName.push(kind);
  }
  expect(
    shownAsMachineName,
    "витрина показала арендатору ключ каталога вместо имени ресурса: по такому " +
      "слову он не найдёт в консоли ни раздела, ни строки — искать ему негде",
  ).toEqual([]);

  // Прежние написания ушли, пришедшие им на смену совпадают с меню.
  const renamed = [
    { kind: "loadbalancer.listeners", was: "Слушатели", now: "Обработчики" },
    { kind: "loadbalancer.targetGroups", was: "Группы целей", now: "Целевые группы" },
    { kind: "compute.guestAccessKey", was: "Ключи гостевого доступа", now: "Ключи доступа" },
  ];
  const missing = renamed.filter((r) => !kinds.includes(r.kind)).map((r) => r.kind);
  expect(
    missing,
    "край не назвал вид, чьё написание и было находкой #1703, — при том что его " +
      "владелец спрошен и ответил успехом. Состав каталога сузился, и о переименовании " +
      "этот прогон уже не говорит",
  ).toEqual([]);

  for (const { was, now } of renamed) {
    expect(
      await page.getByText(was, { exact: true }).count(),
      `витрина по-прежнему называет ресурс «${was}» — раздела с таким именем в консоли нет ни одного`,
    ).toBe(0);
    await expect(
      page.getByText(now, { exact: true }).first(),
      `витрина не называет ресурс «${now}» — словом, которым его зовёт меню консоли`,
    ).toBeVisible({ timeout: 15_000 });
  }
});
