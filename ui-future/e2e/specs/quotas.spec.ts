import { expect, type Page, type Locator } from "@playwright/test";
import { registerAndSignIn, test } from "./fixtures";

/**
 * Арендатор видит свои пределы — без обращения в поддержку.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ
 *
 * Модульная проба подменяет ответ и утверждает про отрисовку. Она не может
 * утверждать, что край этот ответ ДАЁТ: чтение квот гейтится отношением на
 * проекте, а сам глагол регистрируется условно — если полоса квот не собрана,
 * его нет вовсе, и вместо набора пределов приходит отказ «не реализовано».
 *
 * Поэтому здесь утверждается пара: край отвечает успехом — и витрина показывает
 * то, что он назвал.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ `table` НЕ АДРЕСУЕТ СТРОКУ ОДНОЗНАЧНО
 *
 * Общая таблица консоли (`ResourceTable`) держит фиксированную шапку колонок
 * над скроллящимся телом (`ui.md`, правило 10) — библиотека реализует это ДВУМЯ
 * `<table>`: один несёт `<thead>` без строк, другой — `<tbody>` со строками.
 * Оба видимы, `page.locator("table")` резолвит два элемента, и `.first()` не
 * годится: у заголовочной таблицы строк нет, и следующее утверждение о
 * содержимом било бы мимо предмета. Таблица со строками — та, у которой ЕСТЬ
 * `tbody`; это верно и в режиме БЕЗ фиксированной шапки, где обе части живут в
 * одном `<table>` (`:has(tbody)` матчит и его).
 */
function dataTable(page: Page): Locator {
  return page.locator("table").filter({ has: page.locator("tbody") });
}

test("витрина квот показывает пределы проекта", async ({ page }) => {
  // verifies #364
  const { projectId } = await registerAndSignIn(page);

  const [response] = await Promise.all([
    page.waitForResponse((r) => new URL(r.url()).pathname === "/vpc/v1/quotas", { timeout: 30_000 }),
    page.goto(`/projects/${projectId}/quotas`, { waitUntil: "domcontentloaded" }),
  ]);

  expect(response.status(), `край не отдал пределы: ${await response.text()}`).toBe(200);

  const body = (await response.json()) as { quotas?: unknown[] };
  // Контракт обещает полный набор всегда — даже проекту, где ничего не создано.
  // Пустой ответ означал бы, что витрине нечего показать не по своей вине.
  expect(body.quotas?.length ?? 0, "край вернул пустой набор пределов").toBeGreaterThan(0);

  await expect(dataTable(page)).toBeVisible({ timeout: 20_000 });
  // Источник значения обязателен: без него упёршийся не знает, куда идти.
  await expect(page.getByText(/умолчание|Аккаунт |Проект /).first()).toBeVisible({ timeout: 20_000 });
});

/**
 * Тенантская страница НЕ несёт ручки изменения величины.
 *
 * Величины меняет только администратор облака, своим разделом. Кнопка, которая
 * у арендатора всегда заканчивается отказом, — обещание возможности, которой у
 * него нет.
 */
test("витрина квот не предлагает арендатору менять величину", async ({ page }) => {
  // verifies #364
  const { projectId } = await registerAndSignIn(page);
  await page.goto(`/projects/${projectId}/quotas`, { waitUntil: "domcontentloaded" });
  await expect(dataTable(page)).toBeVisible({ timeout: 30_000 });

  for (const label of [/Изменить предел/i, /Поднять квоту/i, /Редактировать/i]) {
    expect(await page.getByRole("button", { name: label }).count()).toBe(0);
  }
});

/**
 * Витрина квот называет ресурс тем же словом, что и остальная консоль.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ГЕЙТОМ
 *
 * Гейт рядом (`shared/src/test/console-quota-kind-named-like-the-entity.test.ts`)
 * сверяет ОБЪЯВЛЕНИЯ трёх файлов дерева и по построению не видит двух вещей:
 * какие виды край называет НА САМОМ ДЕЛЕ (каталог живёт у владельца величин и
 * растёт без консоли) и что из названного доехало до экрана. Здесь — и то, и
 * другое: набор берётся из ответа края, слова читаются со страницы.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ
 *
 *  1. ни одно машинное имя вида (`iam.user.credential`) не доехало до экрана —
 *     арендатору показано слово, а не ключ каталога;
 *  2. прежние написания, из-за которых заведена #1703, со страницы ушли, а
 *     пришедшие им на смену — те же, что в меню и крошке консоли.
 *
 * Отрицание идёт В ПАРЕ с положительным контролем: «слова нет» истинно и на
 * пустой странице, и на не загрузившемся модуле, поэтому сперва утверждается,
 * что витрина отрисована и что-то называет.
 */
test("витрина квот называет ресурс словом консоли, а не ключом каталога", async ({ page }) => {
  // verifies #1703
  const { projectId } = await registerAndSignIn(page);

  const [response] = await Promise.all([
    page.waitForResponse((r) => new URL(r.url()).pathname === "/vpc/v1/quotas", { timeout: 30_000 }),
    page.goto(`/projects/${projectId}/quotas`, { waitUntil: "domcontentloaded" }),
  ]);
  expect(response.status(), `край не отдал пределы: ${await response.text()}`).toBe(200);

  const body = (await response.json()) as { quotas?: Array<{ kind: string }> };
  const kinds = (body.quotas ?? []).map((q) => q.kind);
  // УСЛОВИЕ ПРОБЫ: край назвал хоть один вид. Без него оба утверждения ниже
  // истинны тривиально — сравнивать было бы не с чем.
  expect(kinds.length, "край вернул пустой набор пределов — называть на витрине нечего").toBeGreaterThan(0);

  await expect(dataTable(page)).toBeVisible({ timeout: 30_000 });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ к обоим отрицаниям: витрина не только отрисована, но
  // и НАЗЫВАЕТ ресурс по-русски. Слово выбрано из тех, что и до #1703 совпадали
  // со словарём, — то есть контроль не зависит от предмета этой пробы.
  await expect(
    page.getByText("Облачные сети", { exact: true }).first(),
    "витрина не называет ни одного ресурса словом: строк нет, модуль не загрузился " +
      "или таблица пуста — об именах такой прогон не говорит ничего",
  ).toBeVisible({ timeout: 30_000 });

  // ПРЕДМЕТ 1 — ключ каталога на экран не выходит.
  const shownAsMachineName: string[] = [];
  for (const kind of kinds) {
    if ((await page.getByText(kind, { exact: false }).count()) > 0) shownAsMachineName.push(kind);
  }
  expect(
    shownAsMachineName,
    "витрина показала арендатору ключ каталога вместо имени ресурса: по такому " +
      "слову он не найдёт в консоли ни раздела, ни строки — искать ему негде",
  ).toEqual([]);

  // ПРЕДМЕТ 2 — прежние написания ушли, пришедшие им на смену совпадают с меню.
  //
  // Пара проверяется только для тех видов, которые край в этом прогоне НАЗВАЛ:
  // каталог у него свой, и требовать строку, которой он не прислал, значило бы
  // судить не витрину, а посев. Перечень проверенных пар печатается — «ноль
  // находок» обязано быть отличимо от «ноль сверенных».
  const renamed: Array<{ kind: string; was: string; now: string }> = [
    { kind: "loadbalancer.listeners", was: "Слушатели", now: "Обработчики" },
    { kind: "iam.serviceAccount", was: "Служебные учётные записи", now: "Сервисные аккаунты" },
    { kind: "iam.accessBinding", was: "Выдачи доступа", now: "Привязки доступа" },
    { kind: "loadbalancer.targetGroups", was: "Группы целей", now: "Целевые группы" },
    { kind: "compute.guestAccessKey", was: "Ключи гостевого доступа", now: "Ключи доступа" },
  ];
  const checked = renamed.filter((r) => kinds.includes(r.kind));
  console.log(`[проба #1703] видов в ответе края ${kinds.length}, пар «прежнее → нынешнее» сверено ${checked.length}`);
  expect(
    checked.length,
    "край не назвал ни одного вида из тех, чьё написание и было находкой #1703: " +
      "условие пробы не создано, о переименовании такой прогон не говорит ничего",
  ).toBeGreaterThan(0);

  for (const { was, now } of checked) {
    expect(
      await page.getByText(was, { exact: true }).count(),
      `витрина по-прежнему называет ресурс «${was}» — раздела с таким именем в консоли нет ни одного`,
    ).toBe(0);
    await expect(
      page.getByText(now, { exact: true }).first(),
      `витрина не называет ресурс «${now}» — словом, которым его зовёт меню консоли`,
    ).toBeVisible({ timeout: 15_000 });
  }
});
