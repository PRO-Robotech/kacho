import { test, expect, type Page } from "@playwright/test";
import { createdResourceId, runTag, tenantWithProject } from "./fixtures";

/**
 * Участие в аккаунте: человека выводят отсюда, а не отовсюду.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ЮНИТОМ МОДУЛЯ
 *
 * У пункта «Исключить из аккаунта» есть предусловие, которого монтирование
 * компонента не проверяет вовсе, — ВЫБРАННАЯ ОБЛАСТЬ. Пункт берёт аккаунт не из
 * строки (у человека аккаунтов бывает несколько, и на строке личности их больше
 * нет), а из области, которую держит каркас. Юнит подставляет эту область сам,
 * поэтому его «пункт появился» верно про вызов `resolve` и молчит про то,
 * доезжает ли область до экрана: между ними лежат маршрутизация, загрузка
 * федеративного модуля и передача области из каркаса в модуль.
 *
 * Вторая половина — ИСХОД. Юнит утверждает, что нажатие уходит своим адресом и
 * несёт аккаунт телом; что после этого человек ПРОПАДАЕТ из списка людей
 * аккаунта и при этом ОСТАЁТСЯ собой, не видит ни он, ни край по отдельности:
 * это свойство пары «членство снято / личность цела», и наблюдать его можно
 * только там, где обе стороны живые.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕМ ЭТА ПРОБА ОТЛИЧАЕТСЯ ОТ СОСЕДНЕЙ (`users.spec.ts`)
 *
 * Та НАМЕРЕННО не доводит своё действие до конца: запрет участия выключает
 * человеку вход на платформу целиком, снять его самому нельзя, и проба,
 * выполнившая его над своей личностью, уничтожила бы собственную фикстуру.
 *
 * Здесь действие выполняется ПО-НАСТОЯЩЕМУ, и это не смелость, а свойство
 * предмета: исключение снимает СТРОКУ ЧЛЕНСТВА в названном аккаунте и не трогает
 * ни одного поля строки личности. Исключённый продолжает работать в остальных
 * своих аккаунтах — ровно это обещает текст подтверждения, и ровно это здесь
 * проверяется. Фикстура переживает своё действие, потому что у исключаемого есть
 * СВОЙ аккаунт.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПРИГЛАШЁННЫЙ — ВТОРОЙ НАСТОЯЩИЙ АРЕНДАТОР, А НЕ ОДНА ПОЧТА
 *
 * Приглашение незнакомой почты завело бы человека, у которого нет ничего, кроме
 * членства в этом аккаунте. После исключения у него не осталось бы НИ ОДНОГО
 * наблюдаемого места, где видно, что личность цела, — и вторая половина
 * утверждения оказалась бы непроверяемой.
 *
 * Второй арендатор снимает это by construction: он заводит свой аккаунт сам,
 * поэтому его приглашение в чужой аккаунт — это ВТОРОЕ членство ОДНОЙ строки
 * личности (`identity_is_global_integration_test.go`: «один человек в двух
 * аккаунтах — ОДНА строка, ДВА членства»). Снятие одного членства обязано
 * оставить другое нетронутым, и это видно в его собственном окне.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * КАК УЧТЁН ПОРЯДОК «СПЕРВА ПРАВА, ПОТОМ УЧАСТИЕ»
 *
 * Отложенный триггер `membership_carrying_rights_is_kept` (миграция 472002)
 * ОТВЕРГАЕТ снятие членства, несущего живую выдачу в этом аккаунте. Это
 * контракт, а не дефект, и проба обязана его соблюдать, а не обходить: иначе она
 * краснела бы на исправном продукте.
 *
 * Соблюдён он ФОРМОЙ ПРИГЛАШЕНИЯ, а не уборкой после него: приглашение уходит
 * БЕЗ пары «проект + роль», а она — единственное, чем этот путь заводит выдачу
 * (`InviteUserRequest.project_id` / `role_id`, оба необязательные: «если оба не
 * заполнены — только invite-row создаётся»). Членства без выдач триггеру
 * предъявить нечего, поэтому исключение принимается.
 *
 * Отзыв выдач перед исключением — предмет ОТДЕЛЬНОЙ пробы: там утверждается, что
 * край отвергает исключение, пока права есть. Смешивать их нельзя, иначе одна
 * проба утверждала бы про две разные полосы, и её краснота не называла бы, какая
 * именно сломалась.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕГО ПРОБА НЕ ДЕЛАЕТ
 *
 * Не утверждает про разметку: ни классов, ни имён компонентов. Класс переименуют,
 * компонент заменят — утверждение о разметке переживёт свой предмет и останется
 * зелёным при вернувшейся находке. Здесь утверждается то, что видит человек:
 * пункт в меню строки, окно подтверждения, состав списка людей аккаунта.
 */

/** Строка списка, принадлежащая этой почте. */
function rowOf(page: Page, email: string) {
  return page.locator("tr").filter({ hasText: email }).first();
}

/**
 * Сколько строк этой почты в списке ПОСЛЕ перечитывания страницы.
 *
 * Перечитывание здесь обязательно, а не осторожность: список — запрос модуля с
 * собственным сроком годности, и он сам собой не обновляется, пока страница
 * смонтирована. Ожидание без перечитывания упёрлось бы в срок пробы на
 * неизменившемся экране и назвало бы виновником продукт.
 */
async function rowsAfterReload(page: Page, email: string): Promise<number> {
  await page.reload({ waitUntil: "domcontentloaded" });
  // Признак того, что список ОТРИСОВАН, а не «ещё пуст»: шапка таблицы.
  // Без него ноль строк означал бы и «человека нет», и «страница не открылась».
  await expect(page.getByRole("columnheader", { name: "Эл. почта" }).first()).toBeVisible({
    timeout: 60_000,
  });
  return await rowOf(page, email).count();
}

/** Аккаунт, которому принадлежит проект арендатора. */
async function accountOfProject(page: Page, projectId: string): Promise<string> {
  const res = await page.request.get(`/iam/v1/projects/${projectId}`);
  expect(
    res.status(),
    `проект ${projectId} не читается по своему адресу — условие пробы не создано`,
  ).toBe(200);
  const body = (await res.json()) as { account_id?: string; accountId?: string };
  const id = body.account_id ?? body.accountId ?? "";
  expect(id, `у проекта ${projectId} не назван аккаунт — исключать было бы не откуда`).not.toBe("");
  return id;
}

test("iam: исключение из аккаунта выводит человека из списка и НЕ трогает его личность", async ({
  page,
  browser,
}) => {
  // verifies #1127 — проба заведена задачей #1173.
  //
  // Предмет #1127: у распорядителя аккаунта появилось СВОЁ действие. До него
  // «вывести человека отсюда» выражалось снятием выдач — а это не исключение, и
  // разница наблюдаема: членство оставалось, человек оставался в списке людей
  // аккаунта, и предел приёма продолжал его считать.
  //
  // Два соседних действия НЕ являются заменой и адресованы облаку, а не
  // аккаунту: запрет участия выключает вход на платформу целиком, удаление
  // стирает строку личности во всех её аккаунтах сразу.
  test.setTimeout(360_000);

  // ── арендатор A: у него свой аккаунт, и в нём он распоряжается ─────────────
  //
  // Право исключать — `member_remover`, а оно выводится из `editor`, тот из
  // `admin`, тот из `owner`. Создатель аккаунта — его владелец СТРУКТУРНО,
  // поэтому право держится с момента, когда аккаунт существует, и не ждёт
  // материализации. Отдельного ожидания прав здесь поэтому нет.
  const owner = await tenantWithProject(page);
  const accountId = await accountOfProject(page, owner.projectId);

  // ── арендатор B: своё окно, своя сессия, свой аккаунт ──────────────────────
  //
  // Окно нужно именно своё: сессия A и сессия B живут в разных наборах печенья,
  // и одной страницей их не изобразить. Адрес стенда берётся у своего же
  // прогона — умолчания здесь быть не должно (см. шапку `playwright.config.ts`).
  const base = process.env.KACHO_CONSOLE_URL ?? new URL(page.url()).origin;
  const contextB = await browser.newContext({ baseURL: base });
  const pageB = await contextB.newPage();

  try {
    const guest = await tenantWithProject(pageB);

    // ── B приглашён в аккаунт A — БЕЗ проекта и роли ───────────────────────
    //
    // Отсутствие пары «проект + роль» — это соблюдение контракта, а не
    // упрощение: см. разбор порядка «сперва права, потом участие» в шапке.
    //
    // Идентификатор приглашённого подтверждается ЧТЕНИЕМ по его адресу, а не
    // берётся из метаданных: операция чеканит его ДО того, как асинхронная часть
    // могла отказать, поэтому неподтверждённый идентификатор — фантом.
    const invite = await page.request.post("/iam/v1/users:invite", {
      data: { account_id: accountId, email: guest.email },
    });
    const guestId = await createdResourceId(
      page,
      invite,
      "userId",
      (id) => `/iam/v1/users/${id}`,
      `приглашение ${guest.email} в аккаунт ${accountId}`,
    );

    // ── ОБЛАСТЬ НЕ ВЫБРАНА: пункта нет вовсе ──────────────────────────────────
    //
    // Первая половина пары. Без неё «пункт есть» зеленело бы и на реестре,
    // который показывает его ВСЕГДА, — а такой пункт отправил бы запрос без
    // второй половины предмета, то есть вывел бы человека неизвестно откуда.
    //
    // Область снимается явно, а не предполагается пустой: она переживает
    // перезагрузку, и «пусто» по умолчанию — свойство, на которое проба не
    // вправе закладываться.
    await page.goto("/iam/users", { waitUntil: "domcontentloaded" });
    await page.evaluate(() => window.localStorage.removeItem("kacho.context.v2"));

    expect(
      await rowsAfterReload(page, guest.email),
      `строки приглашённого (${guest.email}) нет в списке людей аккаунта — ` +
        `условие пробы не создано: исключать не над чем, и об отсутствии пункта ` +
        `такой прогон не говорит ничего`,
    ).toBeGreaterThan(0);

    const rowWithoutScope = rowOf(page, guest.email);
    await rowWithoutScope.getByRole("button", { name: "Действия" }).first().click();
    // Положительный контроль состава: меню ОТКРЫЛОСЬ и глаголы в нём есть.
    // Утверждение об отсутствии пункта иначе зеленело бы на неоткрывшемся меню.
    await expect(
      page.getByRole("menuitem", { name: /Запретить участие/ }).first(),
      "меню строки не открылось или пусто — об отсутствии пункта исключения " +
        "такой прогон не говорит ничего",
    ).toBeVisible({ timeout: 15_000 });
    await expect(
      page.getByRole("menuitem", { name: /Исключить из аккаунта/ }),
      "пункт исключения предложен БЕЗ выбранной области: аккаунт брать неоткуда, " +
        "и запрос ушёл бы без второй половины предмета",
    ).toHaveCount(0);
    await page.keyboard.press("Escape");

    // ── ОБЛАСТЬ ВЫБРАНА: пункт появляется ─────────────────────────────────────
    //
    // Область устанавливается тем же путём, каким её получает человек: заход в
    // свой проект. Каркас резолвит владеющий аккаунт и запоминает область —
    // именно эта передача из каркаса в модуль и не видна юниту.
    await page.goto(`/projects/${owner.projectId}/dashboard`, { waitUntil: "domcontentloaded" });
    await expect
      .poll(
        async () =>
          await page.evaluate(() => {
            const raw = window.localStorage.getItem("kacho.context.v2");
            if (!raw) return "";
            const parsed = JSON.parse(raw) as { account?: { id?: string } };
            return parsed.account?.id ?? "";
          }),
        {
          message:
            `каркас не запомнил аккаунт ${accountId} после захода в свой проект: ` +
            `область не доехала, и пункт исключения не появится ни на одной строке`,
          timeout: 120_000,
        },
      )
      .toBe(accountId);

    await page.goto("/iam/users", { waitUntil: "domcontentloaded" });
    expect(
      await rowsAfterReload(page, guest.email),
      `строка приглашённого (${guest.email}) пропала со списка до исключения`,
    ).toBeGreaterThan(0);

    const row = rowOf(page, guest.email);
    await row.getByRole("button", { name: "Действия" }).first().click();

    const item = page.getByRole("menuitem", { name: /Исключить из аккаунта/ }).first();
    await expect(
      item,
      "при выбранной области пункта «Исключить из аккаунта» в меню строки нет: " +
        "край глагол подаёт, контракт его объявляет, а из консоли позвать нечем",
    ).toBeVisible({ timeout: 15_000 });
    await item.click();

    // ── подтверждение обязано НАЗВАТЬ границу действия ────────────────────────
    const dialog = page.getByRole("dialog").first();
    await expect(
      dialog,
      "подтверждения не появилось — действие над чужим участием уходило бы одним нажатием",
    ).toBeVisible({ timeout: 15_000 });
    await expect(
      dialog,
      "подтверждение не называет границу: человек не понимает, что теряет только " +
        "участие ЗДЕСЬ, а личность и остальные его аккаунты не затрагиваются",
    ).toContainText(/личност/i);

    await dialog.getByRole("button", { name: "Исключить", exact: true }).first().click();

    // Окно закрывается ТОЛЬКО по вердикту операции (`expectOperation`), поэтому
    // его исчезновение — наблюдаемое «край принял», а не «нажатие ушло».
    await expect(
      dialog,
      "окно подтверждения не закрылось: край не подтвердил исключение операцией",
    ).toBeHidden({ timeout: 120_000 });

    // ── ИСХОД, часть 1: человека нет в списке людей аккаунта ──────────────────
    //
    // Здесь и живёт положительный контроль, без которого утверждение было бы
    // тривиально верным: СОБСТВЕННАЯ строка A обязана остаться. Пустой список,
    // отказ края, не загрузившийся модуль и потерянная сессия дают ноль строк
    // приглашённого ровно так же, как исправное исключение.
    await expect
      .poll(async () => await rowsAfterReload(page, guest.email), {
        message:
          `${guest.email} остаётся в списке людей аккаунта ${accountId} после исключения: ` +
          `край подтвердил операцию, а членство не снято`,
        timeout: 120_000,
      })
      .toBe(0);

    await expect(
      rowOf(page, owner.email),
      `собственная строка распорядителя (${owner.email}) исчезла вместе с исключённым — ` +
        `список людей аккаунта пуст, и утверждение об отсутствии приглашённого ` +
        `выполнено тривиально, а не исключением`,
    ).toBeVisible({ timeout: 60_000 });

    // ── ИСХОД, часть 2: личность цела ─────────────────────────────────────────
    //
    // Ровно то, что обещает текст подтверждения: «в других своих аккаунтах
    // человек продолжит работать». Проверяется в ЕГО окне и на ЕГО аккаунте —
    // в аккаунте A он больше не виден by construction, и спрашивать там нечего.
    //
    // Строка личности при этом ОДНА на платформу: тот же идентификатор, что
    // назвало приглашение в чужой аккаунт, обязан по-прежнему читаться у себя.
    expect(
      await rowsAfterReload(pageB, guest.email),
      `${guest.email} пропал из списка людей СВОЕГО аккаунта после исключения из чужого: ` +
        `снятие одного членства задело личность либо остальные её членства`,
    ).toBeGreaterThan(0);

    const selfRead = await pageB.request.get(`/iam/v1/users/${guestId}`);
    expect(
      selfRead.status(),
      `строка личности ${guestId} перестала читаться её собственным владельцем после ` +
        `исключения из чужого аккаунта — исключение задело личность, а не членство`,
    ).toBe(200);
  } finally {
    await contextB.close();
  }
});
