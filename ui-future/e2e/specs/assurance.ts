import { expect, type Page } from "@playwright/test";
import { LANE, SESSION_COOKIE, newSeed, seedSecondFactor, type IssuedCall } from "./ceremony-seed";
import { test } from "./fixtures";

/**
 * Второй уровень уверенности: как его поднять и как его прочесть.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КОПИЯ РЯДОМ
 *
 * Механику подъёма уровня спрашивают ДВЕ пробы: `stepup.spec.ts` (уровень
 * ДОСТИЖИМ) и `users.spec.ts` (второе членство человека, #1357). Копия разошлась
 * бы с оригиналом молча — там, где расхождение не видно: обе стороны отвечают
 * «уровень поднят» на арендаторе, у которого он и так поднят.
 *
 * Модуль НЕ является пробой (`playwright` собирает `*.spec.ts`).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ГЛАГОЛАМИ НАШЕЙ СЛУЖБЫ И ОДНИМ ПРЕДЪЯВЛЕНИЕМ КОДА (приёмка F8, F8-43)
 *
 * Прежде модуль вёл три церемонии чужого поставщика напрямую и читал уровень у
 * его сессии под опросом, а между двумя предъявлениями кода ЖДАЛ следующего шага
 * стенными часами — вердикт зависел от фазы часов. Нашему глаголу второе
 * предъявление не нужно: подтверждение само предъявляет фактор в сессии и
 * отвечает уровнем. Поэтому здесь ровно два обращения — заведение и
 * подтверждение, — код по времени предъявляется ОДИН раз, повышения нет вовсе,
 * а уровень читается ответом подтверждения, без опроса.
 *
 * ОДИН КОНТЕКСТ ЗАПРОСОВ, который модуль заводит сам: носитель браузера
 * переносится в него ЯВНО, а перевыпущенный подтверждением — обратно в браузер.
 * Обращения этого контекста перепись страниц не видит; модуль держит их ответы
 * сам, в порядке выпуска, и отдаёт вызывающему — это запись выпускающего, на
 * которой вызывающий утверждает «заведение, затем подтверждение, повышения нет».
 */

/**
 * Уровень уверенности, с которым край видит сессию браузера, — ответом края о
 * сессии (`GET /iam/v1/auth/me`), а не чтением чужого поставщика.
 */
export async function assuranceLevel(page: Page): Promise<string> {
  const res = await page.request.get("/iam/v1/auth/me", { headers: { Accept: "application/json" } });
  if (!res.ok()) return "";
  const body = (await res.json()) as { session?: { assuranceLevel?: unknown } };
  return body.session?.assuranceLevel === undefined ? "" : String(body.session.assuranceLevel);
}

/**
 * Поднять сессию браузера до второго уровня: завести одноразовый код и
 * подтвердить его. Возвращает запись выпускающего — ответы глаголов (без
 * признаков формы) в порядке выпуска.
 *
 * КАЖДЫЙ шаг утверждает свой исход: шаг, собирающий условие и не утверждающий
 * его, при отказе оставляет сессию на первом уровне и роняет потом законно
 * отвергнутый глагол — виновником называется невиновный.
 */
export async function raiseAssurance(page: Page): Promise<IssuedCall[]> {
  // Носитель меняется МИМО вкладки, и её упорядочение (`api/carrier-order.ts`)
  // этого не видит. Чтение страницы, выпущенное с прежним носителем и
  // отвеченное после подтверждения, получает «сессия кончилась», а ответ такой
  // гасит печенье — уже перевыпущенное. Поэтому страница уводится на пустой
  // документ ДО подъёма: переход завершён — обращений прежнего документа больше
  // нет. После подъёма страница стоит на пустом документе; экран, если он
  // нужен, вызывающий открывает сам.
  await page.goto("about:blank");
  const browserContext = page.context();
  const own = (await browserContext.cookies()).find((c) => c.name === SESSION_COOKIE);
  expect(own, "у браузера нет носителя сессии — поднимать нечего").toBeTruthy();

  const seed = await newSeed(test.info(), [own!]);
  try {
    const factor = await seedSecondFactor(seed);
    expect(factor.assuranceLevel, "подтверждение второго фактора не подняло сессию до уровня 2").toBe("2");

    // Подтверждение перевыпустило носитель — браузер обязан получить новый.
    const raised = (await seed.api.storageState()).cookies.find((c) => c.name === SESSION_COOKIE);
    expect(raised?.value, "подтверждение не перевыпустило носитель").toBeTruthy();
    expect(raised?.value, "носитель после подтверждения тот же, что до него").not.toBe(own!.value);
    await browserContext.addCookies([raised!]);
    return seed.issued.filter((c) => c.path !== `${LANE.csrf}?form=second-factor`);
  } finally {
    await seed.dispose();
  }
}
