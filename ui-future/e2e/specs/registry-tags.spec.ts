import { expect } from "@playwright/test";
import { apiCalls, createdResourceId, registerAndSignIn, runTag, test } from "./fixtures";

/**
 * Вкладка «Теги» на карточке репозитория — против развёрнутого продукта.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ БРАУЗЕРОМ
 *
 * Предмет — не ветка компонента, а СЦЕПКА: таблица маршрутов раздела, параметры
 * адреса, сборка адреса чтения и запрос к краю. Модульная проба монтирует
 * компонент и маршрутизации не видит by construction — именно поэтому дефект и
 * дожил: связь «репозиторий → теги» была объявлена, покрыта типами и
 * неисполнима, а компонентные пробы этого не замечали.
 *
 * ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
 *
 * Запрос к краю: адрес несёт ОБА сегмента — реестр и репозиторий — и ни один
 * запрос не ушёл с литералом `{…}`. Присутствие строк на экране предметом не
 * является: у свежего репозитория тегов нет вовсе (тег появляется от `docker
 * push`, отдельного глагола создания у него нет), поэтому проба утверждает
 * ЧТЕНИЕ, а не улов.
 *
 * ПОЧЕМУ ПЕРЕХОД КЛИКОМ, А НЕ АДРЕСОМ
 *
 * Адрес проверяет маршрут, клик проверяет ВХОД. Маршрут, к которому нет входа, —
 * та же неисполнимая возможность на шаг дальше: страница есть, найти её нельзя.
 */
test("вкладка тегов репозитория читает адрес с реестром и репозиторием", async ({ page }) => {
  // verifies #627
  const { projectId } = await registerAndSignIn(page);

  // Регион — УСЛОВИЕ пробы, а не её предмет: реестр размещается регионально, и
  // край требует `regionId` на создании. Без него прогон отвечает 400 и о вкладке
  // тегов не говорит ничего. Берём из справочника, а не литералом: имя региона —
  // произвольная строка стенда, и выписанное значение разошлось бы с посевом молча.
  const regionsCatalog = await page.request.get("/geo/v1/regions");
  expect(
    regionsCatalog.ok(),
    "справочник регионов недоступен — условие пробы не создано: реестр разместить " +
      "негде, и о вкладке тегов такой прогон не говорит ничего",
  ).toBeTruthy();
  const region =
    ((await regionsCatalog.json()) as { regions?: Array<{ id: string }> }).regions?.[0]?.id ?? "";
  expect(region, "справочник регионов пуст — стенд не засеян, условие пробы не создано").not.toBe("");

  const registryId = await createdResourceId(
    page,
    await page.request.post("/registry/v1/registries", {
      data: { projectId, regionId: region, name: `reg-tags-${runTag()}` },
    }),
    "registryId",
    (id) => `/registry/v1/registries/${id}`,
    "реестр под пробу тегов",
  );

  // Репозиторий заводится ЯВНЫМ создатем (overlay-строка, survives-empty), а не
  // `docker push`: пробе нужен предмет, а не содержимое.
  const repository = `probe-${runTag()}`;
  await createdResourceId(
    page,
    await page.request.post(`/registry/v1/registries/${registryId}/repositories`, {
      data: { registryId, repository },
    }),
    "repository",
    (name) => `/registry/v1/registries/${registryId}/repositories/${name}`,
    "репозиторий под пробу тегов",
  );

  const calls = apiCalls(page);

  // Карточка репозитория живёт ПОД СВОИМ РЕЕСТРОМ: плоского адреса ей не хватает
  // — он не называет реестр, а без реестра адрес чтения не собрать.
  await page.goto(`/projects/${projectId}/registry/registries/${registryId}/repositories/${repository}`, {
    waitUntil: "domcontentloaded",
  });

  // Карточка открылась именно та: её имя на экране. Без этого клик по вкладке
  // ниже мог бы происходить на чужой странице.
  await expect(
    page.getByText(repository).first(),
    "карточка репозитория не открылась по адресу под реестром — дальше проверялась бы не она",
  ).toBeVisible();

  await expect(
    page.getByRole("tab", { name: /Теги/ }),
    "на карточке репозитория нет вкладки «Теги» — связь объявлена реестром ресурсов, " +
      "значит вкладка обязана быть; её отсутствие означает, что связь снова не доехала до оболочки",
  ).toBeVisible();
  await page.getByRole("tab", { name: /Теги/ }).click();

  const tagsPath = `/registry/v1/registries/${registryId}/repositories/${repository}/tags`;

  // Ждём УСЛОВИЕ, а не время: запрос ушёл и край его принял.
  await expect
    .poll(() => calls.some((c) => c === `200 ${tagsPath}`), {
      message:
        `вкладка тегов не прочитала ${tagsPath}. Так выглядит незакрытая подстановка адреса: ` +
        `запрос либо не уходит вовсе, либо уходит с литералом — и то и другое пользователь видит ` +
        `как пустую вкладку. Ушедшие запросы: ${JSON.stringify(calls)}`,
      timeout: 30_000,
    })
    .toBe(true);

  // Ни один запрос не ушёл с литералом в адресе. Утверждение отдельное и сильнее
  // предыдущего: «нужный адрес появился» не то же самое, что «ненужный не уходил»,
  // а литерал в адресе край отвергает отказом, неотличимым от «ресурса нет».
  expect(
    calls.filter((c) => c.includes("{") || c.includes("%7B")),
    "запрос ушёл с незакрытой подстановкой в адресе",
  ).toEqual([]);

  // И это не состояние «адрес неполон»: оно означало бы, что оболочка запрос не
  // отправляла, а утверждения выше проверяли бы чужие запросы страницы.
  await expect(page.getByText(/Адрес неполон/i)).toHaveCount(0);
});
