/**
 * ЧЬЯ ЭТО БЕДА: разбор отказа пробы потока изменений (#2016).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ТЕЛО ПРОБЫ
 *
 * Проба падала и проходила на ОДНОЙ ревизии, а её отказ говорил «событий 0» —
 * называл число и молчал о соединении. Под этим молчанием неразличимы три
 * разные беды, и у каждой свой владелец:
 *
 *   НЕ ОТПРАВЛЕНО  — строки журнала нет либо она вызывающему не видна.
 *                    Предмет у ВЛАДЕЛЬЦА журнала;
 *   НЕ ДОЕХАЛО     — строка есть и видна, но открытый поток её не довёз.
 *                    Предмет в ДОСТАВКЕ;
 *   НЕ ДОЖДАЛИСЬ   — довёз, но позже отведённого. Предмет в ВЕЛИЧИНЕ БЮДЖЕТА.
 *
 * Разбор вынесен сюда, потому что он ЧИСТЫЙ — и потому проверяем БЕЗ СТЕНДА.
 * Оставь он в теле пробы, его способность различать доказывалась бы только
 * подъёмом кластера, то есть не доказывалась бы никогда: проверка, которую
 * нельзя прогнать, отличается от отсутствующей лишь тем, что выглядит рабочей.
 * Самопроверка рядом — `scripts/stream-verdict-selftest.ts`, гоняется голым
 * `node` за секунды и до подъёма.
 *
 * Модуль НЕ является пробой (`playwright` собирает `*.spec.ts`), поэтому набор
 * от него не прирастает ни одним кейсом. Зависимостей у него нет намеренно:
 * импорт `@playwright/test` сделал бы самопроверку неисполнимой голым `node`.
 */

/** Состояние связи глазами страницы на момент разбора. */
export interface StreamState {
  /** `EventSource.readyState`; −1 означает «соединение не открывали вовсе». */
  readyState: number;
  /** Сколько раз край открывал поток. Больше единицы — было переоткрытие. */
  opened: number;
  /** Сколько раз браузер сообщил об ошибке связи, включая временные. */
  errors: number;
  /** Терминальное закрытие, названное словами, либо пустая строка. */
  failure: string;
  frames: number;
  events: number;
  lastEventId: string;
  openedAtMs: number;
  lastFrameAtMs: number;
  lastErrorAtMs: number;
  nowMs: number;
}

/** Исход перечитывания журнала с позиции ДО создания предмета. */
export interface ReplayOutcome {
  /** Принесло ли перечитывание сам предмет. */
  found: boolean;
  /** Сколько кадров пришло — отличает «пусто» от «пришло, но не то». */
  frames: number;
  /** Отказ края, если он был: тогда вердикта нет ВОВСЕ. */
  refusal: string;
}

/**
 * Имя виновника — МАШИННОЕ, рядом с прозой.
 *
 * Проза адресована человеку, читающему отказ; имя — самопроверке, которая иначе
 * сверяла бы разбор по подстроке собственного объяснения и зеленела бы на любой
 * его правке.
 */
export type StreamCause = "не отправлено" | "не доехало" | "не дождались" | "не установлено";

const READY_STATE_WORD: Record<number, string> = {
  [-1]: "НЕ ОТКРЫВАЛОСЬ",
  0: "соединяется",
  1: "ОТКРЫТО",
  2: "ЗАКРЫТО",
};

/**
 * Состояние связи СЛОВАМИ — эта строка идёт в отказ пробы.
 *
 * Называется ровно то, чем три беды различаются: открытый молчащий поток и
 * оборванный поток дают одно и то же число полученных событий.
 */
export function describeStream(s: StreamState): string {
  const ready = READY_STATE_WORD[s.readyState] ?? `неизвестно (${s.readyState})`;
  const ago = (t: number) => (t === 0 ? "никогда" : `${Math.round((s.nowMs - t) / 1000)} с назад`);
  return [
    `соединение: ${ready}`,
    `открытий потока: ${s.opened}` +
      (s.opened > 1 ? " — край ПЕРЕОТКРЫВАЛ поток, между соединениями было окно" : ""),
    `ошибок связи: ${s.errors}` + (s.errors > 0 ? ` (последняя ${ago(s.lastErrorAtMs)})` : ""),
    s.failure !== "" ? `край: ${s.failure}` : "",
    `кадров получено: ${s.frames}, из них событий: ${s.events}`,
    `последняя позиция: ${s.lastEventId === "" ? "нет" : s.lastEventId}`,
    `поток открылся ${ago(s.openedAtMs)}, последний кадр ${ago(s.lastFrameAtMs)}`,
  ]
    .filter((line) => line !== "")
    .join("; ");
}

/**
 * Кто виноват — по ИСХОДУ перечитывания, а не по числу полученных событий.
 *
 * ПОРЯДОК ВЕТВЕЙ НЕСУЩИЙ, и каждая стоит там, где стоит, по причине:
 *
 *   1. отказ края в перечитывании — вердикта нет ВООБЩЕ, и подавать «разбор не
 *      состоялся» как «поток потерял событие» значит обвинять механизм, до
 *      которого дело не дошло. Поэтому первым;
 *   2. предмет доехал ПОКА ШЁЛ разбор — тогда продукт исправен, а мал бюджет.
 *      Стоит перед «не доехало»: перечитывание в этом случае предмет тоже
 *      принесёт, и без этой ветви исправный продукт объявлялся бы сломанным;
 *   3. перечитывание принесло — строка есть и видна, значит беда в доставке;
 *   4. не принесло — строки нет либо она не видна вызывающему.
 */
export function streamVerdict(arg: {
  state: StreamState;
  replay: ReplayOutcome;
  /** Сколько событий о предмете у ЖИВОГО потока к концу разбора. */
  late: number;
  position: string;
  timeoutMs: number;
}): { cause: StreamCause; text: string } {
  const seconds = Math.round(arg.timeoutMs / 1000);

  if (arg.replay.refusal !== "") {
    return {
      cause: "не установлено",
      text:
        `ВИНОВНИК НЕ УСТАНОВЛЕН: перечитать журнал с позиции «${arg.position}» не удалось — ` +
        `${arg.replay.refusal}. Это УСЛОВИЕ разбора, а не вердикт о потоке: о судьбе строки ` +
        `такой прогон не говорит ничего.`,
    };
  }

  if (arg.late > 0) {
    return {
      cause: "не дождались",
      text:
        `НЕ ДОЖДАЛИСЬ: поток довёз предмет ПОЗЖЕ отведённых ${seconds} с — к концу разбора ` +
        `событий о нём ${arg.late}. Предмет в ВЕЛИЧИНЕ БЮДЖЕТА, а не в продукте; поднимать ` +
        `бюджет только ЗАМЕРОМ доставки, а не «на всякий случай».`,
    };
  }

  if (arg.replay.found) {
    const broke = arg.state.opened > 1 || arg.state.errors > 0 || arg.state.readyState !== 1;
    return {
      cause: "не доехало",
      text:
        `НЕ ДОЕХАЛО: перечитывание с позиции «${arg.position}» предмет ПРИНЕСЛО ` +
        `(кадров ${arg.replay.frames}). Строка в журнале есть и вызывающему видна — значит ` +
        `она отправлена, а ОТКРЫТЫЙ поток её не довёз. Предмет в ДОСТАВКЕ` +
        (broke
          ? ": связь рвалась либо переоткрывалась (см. состояние выше), и окно между " +
            "соединениями — первое, что надо смотреть."
          : ": связь не рвалась ни разу и поток всё это время был открыт — значит строку " +
            "пропустил САМ открытый поток, а не разрыв."),
    };
  }

  return {
    cause: "не отправлено",
    text:
      `НЕ ОТПРАВЛЕНО: перечитывание с позиции «${arg.position}» предмета НЕ принесло ` +
      `(кадров ${arg.replay.frames}), при том что сам ресурс уже читается по своему адресу. ` +
      `Значит строки журнала нет вовсе либо она вызывающему не видна. Предмет у ВЛАДЕЛЬЦА ` +
      `ЖУРНАЛА (запись строки в той же транзакции, построчное сужение по правам), а не в ` +
      `доставке.`,
  };
}
