export const ABSENCE_EMPTY_HINT = "В этой установке ограничений нет";
/** Красная плашка, которой посадка НЕ является (#2515). */
export const READ_FAILED_PLATE = "Пределы не прочитаны";
/** Фраза шапки витрины — положительный контроль «страница отрисована». */
export const VALUES_SET_BY = "Величины задаёт администратор облака";

/** Ответ ОДНОГО владельца пределов. */
export interface OwnerAnswer {
  path: string;
  /** Спрошен ли владелец вовсе. `false` — страница к нему не обращалась. */
  answered: boolean;
  /** HTTP-статус; `0`, когда владелец не спрошен. */
  status: number;
  /** Машинный признак отказа; пусто — признака нет (в том числе на успехе). */
  reason: string;
  /** Виды, названные в успешном ответе. */
  kinds: string[];
}


/**
 * Машинный признак отказа из ТЕЛА ответа края.
 *
 * Читается тело, а не статус: полосы различаются признаком, а `400` приходит и
 * от объявленного отсутствия, и от `QUOTA_NOT_PROVISIONED`, и от валидации.
 *
 * Неразбираемое тело даёт ПУСТО — «признака нет», а не «признак такой-то».
 * Догадка здесь стала бы корзиной «всё остальное», и посадка выводилась бы из
 * мусора.
 */
export function reasonFromBody(text: string): string {
  let body: { details?: Array<{ reason?: string }> };
  try {
    body = JSON.parse(text) as { details?: Array<{ reason?: string }> };
  } catch {
    return "";
  }
  for (const d of body.details ?? []) {
    if (typeof d.reason === "string" && d.reason !== "") return d.reason;
  }
  return "";
}

/**
 * Посадка, ВЫВЕДЕННАЯ из ответов пятерых.
 *
 * `split` — не посадка, а находка: пятеро разошлись, либо кто-то отказал по
 * другому признаку, либо не ответил вовсе. Он несёт разбор ПО КАЖДОМУ
 * владельцу — иначе читающий увидит «посадка не установлена» и не узнает, у
 * кого именно.
 */
export type Posture =
  | { kind: "deployed" }
  | { kind: "absent" }
  | { kind: "split"; detail: string };

export function postureOf(answers: OwnerAnswer[]): Posture {
  const roster = answers
    .map((a) => `${a.path} → ${a.answered ? a.status : "не спрошен"}${a.reason ? ` ${a.reason}` : ""}`)
    .join("; ");

  if (answers.length === 0) return { kind: "split", detail: "владельцев пределов не спрошено ни одного" };
  if (answers.some((a) => !a.answered)) return { kind: "split", detail: roster };

  if (answers.every((a) => a.status === 200)) return { kind: "deployed" };
  if (answers.every((a) => a.status !== 200 && a.reason === QUOTA_AUTHORITY_ABSENT)) return { kind: "absent" };

  return { kind: "split", detail: roster };
}

