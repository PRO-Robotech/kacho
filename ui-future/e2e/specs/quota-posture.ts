/** Признак полосы «домен величин объявлен отсутствующим». Один на край и консоль. */
export const QUOTA_AUTHORITY_ABSENT = "QUOTA_AUTHORITY_ABSENT";

/** Что видит арендатор на посадке без домена величин — слова самой консоли. */
export const ABSENCE_TITLE = "Пределы в этой установке не задаются";
