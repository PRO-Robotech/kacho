/**
 * Посадка установки по домену величин: РЕШЕНИЕ, отделённое от чтения края.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ МОДУЛЬ БЕЗ ЕДИНОГО ИМПОРТА
 *
 * Здесь живёт только решение — «какая посадка следует из этих ответов», — и
 * ни одной строки, которой нужен браузер. Это не аккуратность: самопроверка
 * решения (`scripts/quota-posture-selftest.ts`) гоняется голым `node` ДО
 * установки зависимостей и до подъёма стенда, как соседние самопроверки
 * отображения имени и разбора отказа потока. Значимый импорт сюда сделал бы
 * её невыполнимой, и способность решения различать посадки перестала бы
 * проверяться вовсе.
 *
 * Чтение края — `quota-showcase.ts`, оно требует браузера и стенда.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ
 *
 * Ручка домена величин принимает ДВА законных значения: адрес соседа либо слово
 * «домена величин в этой установке нет» (`not-deployed`). Второе — объявленный
 * выбор оператора, а не поломка: потолков не назначает никто, ни одна мутация
 * не отвергается по пределу, и витрина обязана НАЗВАТЬ это словом, а не выдать
 * за сбой (задача #2515, разбор — `docs/architecture/quota-surface-breakdown.md`
 * §В5).
 *
 * Пробы витрины писались, когда посадка была ОДНА: домен величин жил внутри
 * службы доступа и разворачивался всегда. Они утверждали успех и непустой
 * набор безусловно — то есть про посадку не говорили ничего, потому что второй
 * не существовало. Теперь их две, и утверждение «край отдал пределы» перестало
 * быть свойством продукта: оно стало свойством ПОСАДКИ.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПОСАДКА ВЫВОДИТСЯ ИЗ ОТВЕТА КРАЯ, А НЕ ЧИТАЕТСЯ ИЗ ДЕРЕВА
 *
 * Соблазн — прочесть объявление подчарта (`values.yaml` службы) и потребовать от края
 * объявленного. Отвергнуто: объявление подчарта НЕ есть посадка стенда —
 * поверх него кладёт umbrella, и проба стала бы ВТОРЫМ местом об одном
 * предмете, расходящимся с первым молча. Ровно тот класс, который этот корпус
 * ловит.
 *
 * ЧЕГО ЭТИМ НЕ УТВЕРЖДАЕТСЯ — названо, чтобы модуль не приняли за более
 * сильный: проба НЕ судит, в какой посадке установка ОБЯЗАНА быть. Это выбор
 * оператора, и предмета для пробы в нём нет. Проба судит другое — что край и
 * консоль СОГЛАСНЫ друг с другом и с той посадкой, которая объявлена
 * фактически.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПРИЗНАК МАШИННЫЙ, А НЕ СТАТУС И НЕ ПРОЗА
 *
 * Статуса недостаточно: `400` приходит и от объявленного отсутствия, и от
 * `QUOTA_NOT_PROVISIONED`, и от валидации. Прозы — тоже: тон отказа контрактен
 * и меняется осознанно, вывод полосы из английской фразы вернул бы пустоту при
 * первой же правке тона. Поэтому полоса берётся по `reason` в
 * `google.rpc.ErrorInfo` — ровно тем признаком, которым её берёт сама консоль
 * (`shared/src/lib/error-presentation.ts`, `refusalReasonOf`).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ «РАЗНОБОЙ» — ОТДЕЛЬНЫЙ ИСХОД, А НЕ ОДНА ИЗ ДВУХ ПОСАДОК
 *
 * Посадка одна на установку: домен величин либо развёрнут, либо нет. Владелец,
 * ответивший иначе остальных, означает, что пятеро разошлись в понимании
 * установки, — и это НАХОДКА, а не посадка. Корзины «всё остальное» здесь быть
 * не может: третий исход называется третьим исходом и краснеет.
 */

