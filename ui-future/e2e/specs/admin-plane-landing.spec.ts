import { expect, type Page } from "@playwright/test";
import { newSeed } from "./ceremony-seed";
import { registerAndSignIn, test } from "./fixtures";

/**
 * Раздел «Система» предлагает мутацию ровно там, где край её обслуживает
 * (kacho#3091, продолжение #2692).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРИЗНАК
 *
 * Консоль одна на обе посадки — внешнюю (арендаторскую) и внутреннюю
 * (операторскую), — и посадку она узнаёт пробой края. После ADM-1 S1 путь этой
 * пробы (`GET /vpc/v1/addressPools`) получил публичного близнеца, и на внешней
 * посадке проба перестала отвечать «маршрута нет»: экраны регионов, зон и
 * администраторов кластера снова показывали «Создать» и «Добавить
 * администратора», а край на их мутации отвечает внешнему вызывающему «маршрута
 * нет» — кнопка обещала действие, которого на этой посадке нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ И ОТКУДА БЕРЁТСЯ ОЖИДАНИЕ
 *
 * Ожидание не выписано под стенд: его даёт САМ КРАЙ, у которого спрашивается
 * мутация экрана — тот глагол, который нажатая кнопка и отправила бы. Спрашивает
 * аноним: край, к которому подключена консоль, отвечает внешнему вызывающему на
 * необслуживаемую координату «маршрута нет» раньше аутентификации (kacho#3053),
 * а на обслуживаемую — отказом аутентификации. Тело пустое, носителя нет — до
 * службы запрос не доходит ни на одной посадке, ничего не заводится.
 *
 *   - мутация не обслуживается (404) — кнопки мутации на экране НЕТ, а раздел
 *     говорит словами, что недоступен на этой посадке;
 *   - мутация обслуживается — кнопка на месте и слов о недоступности нет
 *     (контроль в обратную сторону: проба, способная только снимать кнопки,
 *     зеленела бы на консоли, которая их не показывает нигде).
 *
 * На одном стенде исполняется одна из двух ветвей — та, которую называет его
 * край; какая именно, проба печатает аннотацией.
 *
 * Смотрит арендатор: его посадка — внешняя, и кнопки, которые он видит, — те,
 * что видел бы и администратор облака на той же посадке: решение о показе
 * судит посадку, а не права (отказ в правах остаётся отказом в правах).
 */

/** Экран раздела и мутация, которую его кнопка отправила бы краю. */
interface Surface {
  name: string;
  address: string;
  mutation: string;
  /** Кнопка мутации на этом экране. */
  action: (page: Page) => ReturnType<Page["getByRole"]>;
  /** Подпись, которую рисует только сам модуль раздела: признак, что экран отрисован. */
  rendered: (page: Page) => ReturnType<Page["getByText"]>;
  /**
   * Мутация обслуживается на ЛЮБОЙ посадке — у неё публичная служба на обоих
   * слушателях края. Тогда ответ края на неё утверждается, а не только читается:
   * «маршрута нет» на ней — это уже не посадка, а потерянная публичная служба.
   */
  servedOnEveryLanding?: true;
}

const SURFACES: Surface[] = [
  {
    name: "регионы",
    address: "/system/regions",
    mutation: "/geo/v1/internal/regions",
    action: (page) => page.getByRole("link", { name: /Создать/ }),
    rendered: (page) => page.getByText("Зоны", { exact: true }).first(),
  },
  {
    name: "зоны",
    address: "/system/zones",
    mutation: "/geo/v1/internal/zones",
    action: (page) => page.getByRole("link", { name: /Создать/ }),
    rendered: (page) => page.getByText("Регионы", { exact: true }).first(),
  },
  {
    name: "администраторы кластера",
    address: "/system/cluster/admins",
    mutation: "/iam/v1/internal/cluster/admins",
    action: (page) =>
      page.getByRole("button", {
        name: "Добавить администратора (устаревший путь)",
      }),
    rendered: (page) => page.getByText("Зоны", { exact: true }).first(),
  },
  {
    // Пулы адресов — экран, чьё поведение фикс #3091 развёл с соседями: их
    // мутации с ADM-1 S1 обслуживает публичная `AddressPoolService`, и на
    // посадке без admin-плоскости кнопка «Создать» обязана остаться, а слов о
    // недоступности над экраном быть не должно. Ветвь здесь одна — served — на
    // обеих посадках.
    name: "пулы адресов",
    address: "/system/address-pools",
    mutation: "/vpc/v1/addressPools",
    action: (page) => page.getByRole("link", { name: /Создать/ }),
    rendered: (page) => page.getByText("Регионы", { exact: true }).first(),
    servedOnEveryLanding: true,
  },
];

const UNAVAILABLE = "Раздел «Система» недоступен на этой посадке";

/** Координата под префиксом домена края, которой нет ни у одного слушателя. */
const ABSENT_MUTATION = "/geo/v1/internal/kachoProbeAbsentResource";

test("раздел «Система» показывает мутацию регионов, зон, администраторов кластера и пулов адресов ровно там, где край её обслуживает", async ({
  page,
}, testInfo) => {
  // verifies #3091 — ложное «плоскость есть» после ADM-1 S1: кнопки мутаций на внешней посадке.
  test.setTimeout(240_000);

  // Ответ края на мутацию каждого экрана — до входа, анонимно.
  const seed = await newSeed(testInfo);
  const served = new Map<string, boolean>();
  try {
    // Какой слушатель перед консолью, называет ответ на координату, которой нет
    // ни у одного слушателя:
    //   - 404 — слушатель со сторожем маршрута (внешний, kacho#3053): он отвечает
    //     «маршрута нет» на всё, чего не обслуживает, раньше аутентификации, и
    //     ответ на мутацию экрана называет, обслуживается ли она;
    //   - 401 — слушатель без сторожа: внутренний, он обслуживает всю
    //     административную поверхность, и отказ входа на нём одинаков для всего.
    //     Так же отвечает и внешний край ревизии ДО kacho#3053 — на таком стенде
    //     проба исполняет ветвь внутренней посадки, и это её названное условие:
    //     ревизия края спрашивается до прогона (`make stand-provenance`).
    const absent = await seed.api.post(ABSENT_MUTATION, { data: {} });
    const gated = absent.status() === 404;
    expect(
      [401, 404].includes(absent.status()),
      `край ответил анониму на несуществующую координату ${ABSENT_MUTATION} ${absent.status()} ` +
        `${await absent.text()} — ни «маршрута нет», ни отказа входа: слушатель не назвать, условие пробы не создано`,
    ).toBe(true);
    testInfo.annotations.push({
      type: "посадка",
      description: `POST ${ABSENT_MUTATION} → ${absent.status()}: ${gated ? "внешний слушатель" : "внутренний слушатель"}`,
    });
    for (const s of SURFACES) {
      const res = await seed.api.post(s.mutation, { data: {} });
      const status = res.status();
      expect(
        gated && !s.servedOnEveryLanding
          ? [401, 404].includes(status)
          : status === 401,
        `край ответил на мутацию экрана «${s.name}» (${s.mutation}) ${status} ${await res.text()} — ` +
          (s.servedOnEveryLanding
            ? "а её обслуживает публичная служба на любой посадке — ждался отказ входа 401"
            : "ответ не совместим с названным слушателем, условие пробы не создано"),
      ).toBe(true);
      served.set(s.name, status !== 404);
      testInfo.annotations.push({
        type: "посадка",
        description: `${s.name}: POST ${s.mutation} → ${status}`,
      });
    }
  } finally {
    await seed.dispose();
  }

  await registerAndSignIn(page);

  for (const s of SURFACES) {
    await page.goto(s.address, { waitUntil: "domcontentloaded" });
    await expect(
      s.rendered(page),
      `экран «${s.name}» не отрисовался — условие пробы не создано`,
    ).toBeVisible({
      timeout: 60_000,
    });

    if (served.get(s.name)) {
      await expect(
        s.action(page),
        `край обслуживает мутацию экрана «${s.name}», а кнопки мутации нет`,
      ).toBeVisible({ timeout: 30_000 });
      await expect(
        page.getByText(UNAVAILABLE),
        `край обслуживает мутацию экрана «${s.name}», а раздел говорит, что недоступен на этой посадке`,
      ).toHaveCount(0);
    } else {
      // Сначала — слова: они появляются, когда консоль назвала посадку, и только
      // после этого отсутствие кнопки значит решение, а не «ещё не приехала».
      await expect(
        page.getByText(UNAVAILABLE),
        `край не обслуживает мутацию экрана «${s.name}» (${s.mutation} → 404), а раздел не говорит, ` +
          "что недоступен на этой посадке",
      ).toBeVisible({ timeout: 30_000 });
      await expect(
        s.action(page),
        `край не обслуживает мутацию экрана «${s.name}» (${s.mutation} → 404), а кнопка мутации на экране — ` +
          "нажатие кончилось бы «маршрута нет»",
      ).toHaveCount(0);
    }
  }
});
