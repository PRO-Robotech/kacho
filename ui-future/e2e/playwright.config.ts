/**
 * Сквозные пробы консоли.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ АДРЕС СТЕНДА — ОБЯЗАТЕЛЬНЫЙ ВХОД, А НЕ УМОЛЧАНИЕ
 *
 * Умолчание вида `http://localhost:8080` всегда непустое, поэтому проба, запущенная
 * без стенда, не отказывается, а идёт по несуществующему адресу и падает по
 * таймауту — то есть «не выполнилось» подаётся как «красное». Отсутствие адреса
 * обязано быть ОТКАЗОМ ЗАПУСКА с названной причиной.
 *
 * ПОЧЕМУ НЕТ ПОВТОРОВ НА КРАСНОМ
 *
 * Повтор скрывает ровно тот класс, ради которого пробы и написаны: неустойчивый
 * поток входа, гонка загрузки модуля, доступ, материализующийся не сразу. Там,
 * где ожидание законно (право появляется в ограниченном окне), оно выражается
 * ЯВНЫМ ожиданием условия внутри пробы, а не повтором всей пробы.
 */
const BASE = process.env.KACHO_CONSOLE_URL;
if (!BASE) {
  throw new Error(
    "KACHO_CONSOLE_URL не задан. Пробы консоли обязаны знать адрес стенда: " +
      "умолчание увело бы их на несуществующий адрес, и «не выполнилось» " +
      "читалось бы как «красное».",
  );
}

/**
 * ОТОБРАЖЕНИЕ ИМЕНИ СТЕНДА — ЯВНОЕ, А НЕ ЧЕРЕЗ РЕЗОЛВЕР (#935, #985, #1750)
 *
 * Имя стенда своего кластера (`console.kacho.local`) живёт только в `/etc/hosts`
 * ранера: ingress host-based, и без имени в заголовке `Host` стенд отвечать не
 * обязан. ОС это имя разрешает, а браузер — своим резолвером, и эти два ответа
 * РАЗОШЛИСЬ: шаг-гейт получал `200` от curl, а следом ВСЕ пробы падали на
 * `net::ERR_NAME_NOT_RESOLVED`, то есть ни одна не доходила до продукта, и
 * «не выполнилось» подавалось как красное.
 *
 * Механизм расхождения не установлен (суффикс `.local` зарезервирован за mDNS,
 * и браузер вправе идти туда вместо файла) — здесь снят САМ ПРЕДМЕТ: адрес
 * задаётся отображением, поэтому резолвер в разрешении имени не участвует. Ни
 * адрес, ни заголовок `Host` при этом не меняются, то есть стенд получает ровно
 * тот же запрос — маскировки нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЛОВИН У ПРОГОНА ДВЕ, И РУЧКА ЗАКРЫВАЕТ ОБЕ (#1750)
 *
 * Проба ходит на стенд двумя путями, и резолвер у них РАЗНЫЙ:
 *
 *   браузер      — `page.goto`, загрузка модулей, запросы консоли; имя разрешает
 *                  резолвер Chromium, и его закрывает `--host-resolver-rules`;
 *   путь запроса — `page.request.*` (`APIRequestContext`) исполняется В ПРОЦЕССЕ
 *                  NODE, а не в браузере; о флаге Chromium он не знает
 *                  by construction, и его закрывает `installHostMapping`.
 *
 * ПРЕЖНЯЯ РЕДАКЦИЯ ЭТОЙ ШАПКИ УТВЕРЖДАЛА БОЛЬШЕ СДЕЛАННОГО: она говорила, что
 * снят сам предмет, тогда как снята была ОДНА половина. На ранере имя стоит в
 * `/etc/hosts`, поэтому разрыв не виден никогда; проявлялся он ровно там, ради
 * чего ручка заведена, — на стенде, где имя разрешается ТОЛЬКО отображением:
 * каждая проба, зовущая `registerAndSignIn`, умирала на
 * `getaddrinfo ENOTFOUND console.kacho.local`, то есть ни одна не доходила до
 * продукта.
 *
 * Обе половины берут ОДНУ переменную и одно имя: разойтись им нечем. Совпадение
 * держит гейт дерева `internal/repohygiene`
 * `TestConsoleProbeHostMappingCoversBothLanes`.
 *
 * Ручка ЯВНАЯ и без умолчания: на внешнем стенде имя разрешается по-настоящему,
 * и молчаливое отображение на localhost увело бы пробы в никуда.
 */
const HOST_IP = process.env.KACHO_CONSOLE_HOST_IP;
const hostResolverArgs = (() => {
  if (!HOST_IP) {
    // ФАКТ ПЕЧАТАЕТСЯ ВСЕГДА. Отсутствие отображения выглядит в логе точно так
    // же, как его наличие, — а разошлись эти два состояния на живом прогоне:
    // шаг проверки условия отображение применил, прогон проб получил
    // ERR_NAME_NOT_RESOLVED минутой позже (#985). Отличить их можно было
    // только тем, чего в логе не было.
    console.log(`[конфиг проб] отображение имени НЕ задано (KACHO_CONSOLE_HOST_IP пуст); адрес ${BASE} разрешает резолвер браузера`);
    return [];
  }
  const url = new URL(BASE);
  const host = url.hostname;
  const port = url.port;
  // ДВЕ ФОРМЫ ПРАВИЛА, и это не перестраховка. Chromium принимает и
  // `MAP <хост> <адрес>`, и `MAP <хост>:<порт> <адрес>:<порт>`; какая из них
  // действует, зависит от того, как разбирается адрес с непустым портом.
  // Форма без порта на живом прогоне сработала в одном процессе и не
  // сработала в другом — значит полагаться на неё одну нельзя.
  const rules = port
    ? [`MAP ${host}:${port} ${HOST_IP}:${port}`, `MAP ${host} ${HOST_IP}`]
    : [`MAP ${host} ${HOST_IP}`];
  // ВТОРАЯ ПОЛОВИНА — путь запроса Node. Ставится ЗДЕСЬ, рядом с первой и из той
  // же переменной: разведи их по разным местам — и следующая правка закроет одну.
  const mapping = installHostMapping(host, HOST_IP);
  // ФАКТ ПЕЧАТАЕТСЯ ПО КАЖДОЙ ПОЛОВИНЕ ПОРОЗНЬ. Одна строка про «отображение
  // задано» скрыла бы ровно тот случай, ради которого #1750 заведена: половина
  // стоит, половина нет, и в логе это выглядит одинаково.
  console.log(`[конфиг проб] отображение имени браузеру: ${rules.join(", ")}`);
  console.log(
    `[конфиг проб] отображение имени пути запроса (node): ${mapping ? `${mapping.host} → ${mapping.ip}` : "НЕ поставлено"}`,
  );
  return [`--host-resolver-rules=${rules.join(",")}`];
})();

/**
 * УДАЛЁННЫЙ БРАУЗЕР ЗДЕСЬ НЕ ИСПОЛЬЗУЕТСЯ — РЕШЕНИЕМ, А НЕ ПО УМОЛЧАНИЮ (#1288).
 *
 * Объявление собирается в переменную и лишь потом уходит в `defineConfig`,
 * потому что решение обязано читать ЭТО ЖЕ объявление: заведут здесь
 * `connectOptions` — отказ увидит его и назовёт. Разбор решения, перечень трёх
 * форм выбора и предикат возврата — в `remote-browser-policy.ts`; здесь они не
 * пересказываются, чтобы два места об одном предмете не разошлись.
 */
const config: PlaywrightTestConfig = {
  // ЗДЕСЬ ЖИВЁТ ГРАНИЦА НАБОРА, И ОНА ОДНА (#1020).
  //
  // Пробы, чьё условие в дереве ещё не создано, лежат в СОСЕДНЕМ каталоге
  // (`specs-awaiting-journal-owner/`) и сюда не попадают. Так, а не пропуском
  // внутри пробы и не маской в прогонщике: пропуск подаёт «не выполнилось» как
  // вердикт, а маска переживает свой предмет.
  //
  // Сегодня тот каталог ПУСТ, и это его цель, а не отмена формы: долг истекает от
  // факта в дереве, и последняя его проба уехала сюда, когда поставка объявила
  // владельцев журнала. Форма остаётся ради следующей.
  //
  // Граница одна намеренно: гейт вердикта считает объявленные пробы ТЕМ ЖЕ
  // каталогом (`.github/scripts/assert-console-probes-verdict.py`). Исключение
  // внутри прогонщика развело бы «сколько объявлено» и «сколько исполнено», и
  // набор краснел бы недобором на каждом прогоне.
  testDir: "./specs",
  timeout: 90_000,
  expect: { timeout: 15_000 },
  retries: 0,
  workers: 1,
  // ─── РАННЯЯ ОСТАНОВКА: НАБОР ОБЯЗАН УСПЕТЬ ОСТАВИТЬ ОТЧЁТ ──────────────────
  //
  // ВСЕ пробы набора заводят арендатора ОДНИМ общим фикстуром, поэтому его
  // поломка роняет весь набор одинаково, и цена такой поломки всегда
  // максимальная. Замерено на прогоне 32602270323, когда проб было 66: упавшая
  // проба стоит 181 с (разброс меньше секунды на одиннадцати подряд), значит
  // весь набор при широкой поломке — 66 × 181 с ≈ 3 ч 19 мин против предела шага
  // в 35 минут. Вердикт при таких величинах существует, только если падает не
  // больше 11 проб.
  //
  // Число проб здесь НЕ выписывается как свойство набора: он растёт с каждой
  // находкой (`ui.md` §12), и счёт в настоящем времени устаревал бы молча при
  // каждой новой пробе. Величины выше принадлежат своему замеру и названы вместе
  // с ним; сколько проб в наборе СЕЙЧАС, говорит перепись гейта вердикта.
  //
  // Без предела прогон СНИМАЕТСЯ ПО ВРЕМЕНИ и не оставляет `results.json`
  // ВООБЩЕ: гейт честно говорит «отчёта нет», но текста отказа не остаётся
  // нигде, и диагноз стоит раскопок в усечённых архивах трасс. С пределом
  // прогон заканчивается сам за ≈15 минут, пишет отчёт, и первое падение видно
  // в сводке.
  //
  // Пять, а не десять: десять стоили бы 10 × 181 с ≈ 30 минут — почти весь
  // бюджет шага, то есть предел, который срабатывает слишком поздно, чтобы
  // что-то спасти. Пяти падений общего фикстура для диагноза достаточно.
  //
  // Смысл величин это НЕ размывает: «исполнено 5 из N» остаётся ТРЕТЬЕЙ
  // категорией — набор не исполнен целиком, поэтому зелёным он не становится
  // и красным по продукту тоже не называется. Это утверждает гейт вердикта
  // (.github/scripts/assert-console-probes-verdict.py).
  maxFailures: 5,
  reporter: [["list"], ["json", { outputFile: "results.json" }]],
  use: {
    baseURL: BASE,
    // Готовый браузер окружения, если он есть. Пробы обязаны работать и БЕЗ этой
    // ручки — обычный путь в конвейере тот же, что локально: браузер ставит
    // `playwright install`.
    //
    // В конвейере ручка задаётся ОТКАТОМ и только когда playwright не сумел
    // добыть браузер даже за свои пять собственных попыток. Тогда шаг берёт
    // браузер из образа ранера и ГРОМКО об этом объявляет — вердикт по пробам
    // лучше получить в другом браузере, чем не получить вовсе: «не выполнилось»
    // неотличимо от красного.
    //
    // Здесь стояло «шесть коротких заходов подряд не сдвинули прогресс ни на
    // процент». Перемерено 2026-08-17 по журналу шести прогонов: прогресс
    // доходил до 100 % КАЖДЫЙ раз, тело архива приходило целиком примерно за
    // секунду, а не укладывалась РАСПАКОВКА — шаг стоял после подъёма стенда и
    // делил ранер с ним. Разбор — в комментарии шага `.github/workflows/console-e2e.yml`.
    launchOptions: {
      ...(process.env.KACHO_CHROMIUM
        ? { executablePath: process.env.KACHO_CHROMIUM }
        : {}),
      ...(hostResolverArgs.length ? { args: hostResolverArgs } : {}),
    },
    // Проверить ФАКТ применения args из этого файла нечем: playwright не
    // отдаёт командную строку запущенного браузера. Поэтому печатается то,
    // что конфиг СОБРАЛСЯ применить, — и это единственное, что отличает
    // «правило не задано» от «правило задано и не подействовало».

    // ЗАПИСЬ ТРАССЫ ЖИВЁТ В НАБОРЕ, А НЕ ЗДЕСЬ (#1242).
    //
    // `retain-on-failure` собирал файл трассы отдельным этапом ПОСЛЕ пробы,
    // сливая свой архив с браузерным; слияние распаковывает каждую запись
    // браузерного архива, и на node 26 распаковка достаточно крупной записи не
    // завершается. Бюджет того этапа берётся из `timeout` ВЫШЕ, а не из предела,
    // объявленного пробой, — поэтому проба с `test.setTimeout(240_000)` получала
    // «Test timeout of 90000ms exceeded», этап обрывался на середине записи, и
    // файл трассы оставался без центрального каталога: ни один просмотрщик его
    // не открывал. То есть трасса терялась ровно на падении — там, где она
    // единственный артефакт разбора.
    //
    // Теперь браузерную трассу останавливает разбор `page` в `specs/fixtures.ts`:
    // внутри пробы, под её собственным пределом, штатным `tracing.stop({ path })`,
    // который складывает архив из файлов и ничего не распаковывает. Значение
    // здесь обязано остаться `"off"` — вернув штатную запись, вернём и слияние;
    // это проверяет сама фикстура и роняет первую же пробу.
    trace: "off",
    screenshot: "only-on-failure",
    video: "off",
  },
};

const refusal = remoteBrowserRefusal(process.env, config);
if (refusal) {
  throw new Error(refusal);
}

export default defineConfig(config);
