/**
 * Единицы канарейки условия П4 (приёмка F8-S4, §4 П4, DoD п. 6) и их ожидаемые
 * исходы — общие для канарейки (`origin.canary.ts`) и самопроверки, которая
 * читает её отчёт (`../access-key-origin-selftest.ts`). Отдельным модулем:
 * файл с вызовами `test(…)` вне прогонщика не импортируется.
 *
 * Исход назван так, как его называет гейт вердикта
 * (`.github/scripts/assert-console-probes-verdict.py`, `fixture_unmet`):
 * `unmet` — упала, и гейт узнал несозданное условие; `red` — упала красной;
 * `passed` — прошла.
 */
export type Outcome = "unmet" | "red" | "passed";

/** Режим края петли — его ставит единица канарейки до посева К. */
export type EdgeMode = "refuse-origin" | "refuse-other" | "accept";

export const ORIGIN_CANARY = {
  // Происхождение набора службой не принимается — тем отказом, каким его
  // отдаёт край на стенде (проба F7-44-edge держит эту форму живьём): условие
  // П4 «не выполнилось», а не красное.
  refuseOrigin: {
    title: "канарейка П4 · происхождение набора не принято — не выполнилось",
    mode: "refuse-origin",
    want: "unmet",
  },
  // Близнец: изменён ровно один факт — причина отказа регистрации. Отказ не об
  // условии превращать в «не выполнилось» нельзя: это маска дефекта службы.
  // Условие проходит, отказ кладёт вложением, и судят его пробы ключа.
  refuseOther: {
    title: "близнец П4 · регистрация отвергнута не по происхождению — условие не останавливает пробы",
    mode: "refuse-other",
    want: "passed",
  },
  // Положительный контроль: происхождение принято, ключ заведён и снят тем же
  // заходом. Без него «не выполнилось» было бы верно и для условия, которое
  // не спрашивает службу вовсе.
  accept: {
    title: "контроль П4 · происхождение принято — условие создано, ключ снят",
    mode: "accept",
    want: "passed",
  },
} as const satisfies Record<string, { title: string; mode: EdgeMode; want: Outcome }>;

