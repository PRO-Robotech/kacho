/**
 * Единицы канарейки чтения приёмника писем и их ожидаемые исходы — общие для
 * канарейки (`reads.canary.ts`) и самопроверки, которая читает её отчёт
 * (`../mail-receiver-marks-selftest.ts`). Отдельным модулем, потому что файл с
 * вызовами `test(…)` вне прогонщика не импортируется.
 *
 * Исход назван так, как его называет гейт вердикта
 * (`.github/scripts/assert-console-probes-verdict.py`, `fixture_unmet`):
 *   · `unmet`  — проба упала, и гейт узнал несозданное условие (оба признака);
 *   · `red`    — проба упала, и гейт считает её красной;
 *   · `passed` — проба прошла.
 */
export type Outcome = "unmet" | "red" | "passed";

export const MAIL_CANARY = {
  // Формы чтения, которыми набор спрашивает приёмник: снимок писем до
  // регистрации (`Mailbox.letters`), число писем (`Mailbox.total`) и ожидание
  // письма (`awaitLetter`). Приёмник не отвечает — каждая обязана отдать
  // «не выполнилось», а не красное (приёмка F6b, Р13; kacho#2901, H5).
  lettersDead: {
    title: "канарейка H5 · снимок писем у неотвечающего приёмника — не выполнилось",
    want: "unmet",
  },
  totalDead: {
    title: "канарейка H5 · число писем у неотвечающего приёмника — не выполнилось",
    want: "unmet",
  },
  awaitDead: {
    title: "канарейка H5 · ожидание письма у неотвечающего приёмника — не выполнилось",
    want: "unmet",
  },
  // Близнец снимка: чтение сорвалось ТАК ЖЕ, но проба его перехватила и упала
  // по существу. Изменён ровно один факт — чем проба упала. Пометка
  // преходящего чтения красного не извиняет.
  substanceAfterDead: {
    title: "близнец H5 · сорванное чтение перехвачено, проба упала по существу — красное",
    want: "red",
  },
  // Положительные контроли: приёмник отвечает. Без них «все чтения помечены»
  // было бы верно и для читателя, который не читает вовсе.
  lettersLive: {
    title: "контроль H5 · снимок писем у отвечающего приёмника проходит",
    want: "passed",
  },
  awaitLive: {
    title: "контроль H5 · письмо у отвечающего приёмника дожидается awaitLetter и отдаёт код",
    want: "passed",
  },
} as const satisfies Record<string, { title: string; want: Outcome }>;

