/**
 * САМОПРОВЕРКА РАЗБОРА ОТКАЗА ПРОБЫ ПОТОКА (#2016).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЗДЕСЬ ДОКАЗЫВАЕТСЯ И ПОЧЕМУ ЭТОГО НЕЛЬЗЯ ПРОЧИТАТЬ ГЛАЗАМИ
 *
 * Предикат задачи #2016 — «по тексту отказа отличимо „не отправлено“ от „не
 * доехало“ и от „не дождались“». Утверждение это о РАЗЛИЧАЮЩЕЙ СПОСОБНОСТИ, а
 * не о наличии слов: разбор, который на всех входах отвечает одинаково, читается
 * ровно так же убедительно, как работающий. Поэтому здесь ему подаются входы —
 * по одному на каждую беду — и сверяется, что виновники ВЫШЛИ РАЗНЫЕ.
 *
 * Прогон гоняется голым `node`, без зависимостей и без стенда: секунды, и потому
 * ДО подъёма — как соседние самопроверки отображения имени и решения о браузере.
 * Проверять разбор подъёмом кластера значило бы не проверять его никогда, а
 * гонку, ради которой он написан, подъёмом и не воспроизвести: она проходит и
 * падает на одной ревизии.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРОГОНОВ ЧЕТЫРЕ, И ЧЕТВЁРТЫЙ ОБЯЗАТЕЛЕН
 *
 *   не отправлено — перечитывание предмета не принесло;
 *   не доехало    — принесло, и живой поток за время разбора его так и не дал;
 *   не дождались  — живой поток довёз ПОЗЖЕ бюджета: продукт исправен, мал срок;
 *   не установлено — край отказал в перечитывании: вердикта нет ВООБЩЕ.
 *
 * Четвёртый — не украшение. Без него «разбор не состоялся» подавалось бы как
 * «поток потерял событие», то есть обвиняло бы механизм, до которого дело не
 * дошло, — ровно та подмена, из-за которой задача и заведена.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ОТДЕЛЬНО ПРОВЕРЯЕТСЯ ПОРЯДОК ВЕТВЕЙ
 *
 * «Не дождались» и «не доехало» отличаются ОДНИМ фактом: успел ли живой поток
 * довезти предмет за время разбора. Перечитывание в обоих случаях предмет
 * приносит. Значит ветви перекрываются по входу, и порядок между ними —
 * несущий: поставь «не доехало» первым, и исправный продукт с малым бюджетом
 * объявлялся бы сломанным. Поэтому подаётся вход, годный ОБЕИМ ветвям, и
 * сверяется, какая выиграла.
 */

import {
  describeStream,
  streamVerdict,
  type ReplayOutcome,
  type StreamCause,
  type StreamState,
} from "../specs/stream-verdict.ts";

let failed = 0;
function check(ok: boolean, what: string): void {
  console.log(`${ok ? "  ok  " : "  ПРОВАЛ"} ${what}`);
  if (!ok) failed += 1;
}

const NOW = 1_700_000_000_000;

/** Открытый поток, ни разу не рвавшийся: связь исправна, событий о предмете нет. */
function healthyStream(over: Partial<StreamState> = {}): StreamState {
  return {
    readyState: 1,
    opened: 1,
    errors: 0,
    failure: "",
    frames: 1,
    events: 0,
    lastEventId: "поз-7",
    openedAtMs: NOW - 70_000,
    lastFrameAtMs: NOW - 70_000,
    lastErrorAtMs: 0,
    nowMs: NOW,
    ...over,
  };
}

const brought: ReplayOutcome = { found: true, frames: 3, refusal: "" };
const empty: ReplayOutcome = { found: false, frames: 0, refusal: "" };
const refused: ReplayOutcome = { found: false, frames: 0, refusal: "край отказал: 503" };

function verdictOf(replay: ReplayOutcome, late: number, state = healthyStream()): {
  cause: StreamCause;
  text: string;
} {
  return streamVerdict({ state, replay, late, position: "поз-7", timeoutMs: 60_000 });
}

console.log("ПРОГОН 1 — НЕ ОТПРАВЛЕНО: перечитывание предмета не принесло");
{
  const v = verdictOf(empty, 0);
  check(v.cause === "не отправлено", `виновник назван: ${v.cause}`);
  check(
    v.text.includes("ВЛАДЕЛЬЦА") && v.text.includes("НЕ ОТПРАВЛЕНО"),
    "текст отсылает к владельцу журнала, а не к доставке",
  );
}

console.log("ПРОГОН 2 — НЕ ДОЕХАЛО: перечитывание принесло, живой поток — нет");
{
  const v = verdictOf(brought, 0);
  check(v.cause === "не доехало", `виновник назван: ${v.cause}`);
  check(v.text.includes("ДОСТАВКЕ"), "текст отсылает к доставке, а не к владельцу");
  check(
    v.text.includes("пропустил САМ открытый поток"),
    "при неразрывавшейся связи назван виновник ТОЧНЕЕ: пропустил сам открытый поток",
  );
  const broken = verdictOf(brought, 0, healthyStream({ opened: 2, errors: 1 }));
  check(
    broken.cause === "не доехало" && broken.text.includes("окно между"),
    "а при переоткрытии тот же виновник указывает на ОКНО между соединениями",
  );
}

console.log("ПРОГОН 3 — НЕ ДОЖДАЛИСЬ: живой поток довёз позже бюджета");
{
  const v = verdictOf(brought, 1);
  check(v.cause === "не дождались", `виновник назван: ${v.cause}`);
  check(
    v.text.includes("ВЕЛИЧИНЕ БЮДЖЕТА") && v.text.includes("ЗАМЕРОМ"),
    "текст относит беду к бюджету и требует поднимать его ЗАМЕРОМ, а не «на всякий случай»",
  );
}

console.log("ПРОГОН 4 — НЕ УСТАНОВЛЕНО: край отказал в перечитывании");
{
  const v = verdictOf(refused, 0);
  check(v.cause === "не установлено", `виновник назван: ${v.cause}`);
  check(
    v.text.includes("УСЛОВИЕ разбора") && !v.text.includes("НЕ ОТПРАВЛЕНО"),
    "отказ края назван УСЛОВИЕМ разбора и НЕ выдан за потерю строки",
  );
  // Отказ края перекрывает и «не дождались»: вердикта нет вообще, что бы ни
  // успел довезти живой поток.
  check(verdictOf(refused, 1).cause === "не установлено", "и он сильнее любого другого входа");
}

console.log("ПРОГОН 5 — РАЗЛИЧАЮЩАЯ СПОСОБНОСТЬ: четыре входа дали ЧЕТЫРЕ разных виновника");
{
  const causes = [
    verdictOf(empty, 0).cause,
    verdictOf(brought, 0).cause,
    verdictOf(brought, 1).cause,
    verdictOf(refused, 0).cause,
  ];
  check(
    new Set(causes).size === 4,
    `виновники попарно различны: ${causes.join(" | ")} — иначе разбор ` +
      "объявлял бы одно и то же на любом входе, оставаясь на вид работающим",
  );
  // Перекрывающиеся по входу ветви: «не дождались» и «не доехало» различает ОДИН
  // факт, и порядок между ними несущий.
  check(
    verdictOf(brought, 1).cause === "не дождались" && verdictOf(brought, 0).cause === "не доехало",
    "вход, годный ОБЕИМ перекрывающимся ветвям, разрешается в пользу бюджета: " +
      "иначе исправный продукт с малым сроком объявлялся бы сломанным",
  );
}

console.log("ПРОГОН 6 — СОСТОЯНИЕ СВЯЗИ НАЗВАНО, а не подразумевается");
{
  const open = describeStream(healthyStream());
  check(open.includes("соединение: ОТКРЫТО"), "открытый поток назван открытым");
  check(open.includes("кадров получено: 1"), "объём полученного назван числом");

  const closed = describeStream(
    healthyStream({ readyState: 2, opened: 2, errors: 3, failure: "поток закрыт краем" }),
  );
  check(closed.includes("соединение: ЗАКРЫТО"), "закрытый поток назван закрытым");
  check(closed.includes("ПЕРЕОТКРЫВАЛ"), "переоткрытие названо словом, а не одним числом");
  check(closed.includes("ошибок связи: 3"), "ошибки связи сосчитаны отдельно от закрытия");
  check(closed !== open, "два разных состояния дают РАЗНЫЙ текст — иначе строка вакуумна");

  // «Не открывали вовсе» — НЕ одно из трёх состояний EventSource, и путать его с
  // «закрыто» нельзя: это разные беды с разными владельцами. Состояние здесь
  // СОГЛАСОВАННОЕ: у непооткрывавшегося потока нет ни кадров, ни их отметок, и
  // первая редакция этой пробы оставила отметку от исправного потока — то есть
  // подала на разбор мир, которого не бывает. Самопроверка это и поймала.
  const never = describeStream(
    healthyStream({ readyState: -1, opened: 0, frames: 0, openedAtMs: 0, lastFrameAtMs: 0 }),
  );
  check(never.includes("НЕ ОТКРЫВАЛОСЬ"), "«соединение не открывали» отличимо от «закрыто»");
  check(never.includes("никогда"), "отметка времени отсутствующего кадра названа словом");
}

if (failed > 0) {
  console.error(`\nсамопроверка разбора отказа потока: провалов ${failed}`);
  process.exit(1);
}
console.log(`\nсамопроверка разбора отказа потока: все утверждения прошли (прогонов 6)`);
