/**
 * РЕШЕНИЕ: сквозные пробы консоли ходят ТОЛЬКО местным браузером (#1288).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРЕДМЕТ: У СОХРАНЕНИЯ ТРАССЫ ДВЕ ПОЛОСЫ, И ВЫБИРАЕТ МЕЖДУ НИМИ НЕ НАШ КОД
 *
 * Трассу упавшей пробы сохраняет разбор фикстуры `page` (specs/fixtures.ts)
 * штатным `tracing.stop({ path })`. У этого вызова ветвление по одному признаку
 * — «соединение с браузером удалённое»:
 *
 *   местный браузер — прогонщик просит у него ПЕРЕЧЕНЬ ФАЙЛОВ трассы и
 *                     складывает архив из них. Распаковывать нечего;
 *   удалённый       — прогонщик забирает у сервера ГОТОВЫЙ АРХИВ и дописывает в
 *                     него свои записи. Дописывание переоткрывает архив, ЧИТАЕТ
 *                     КАЖДУЮ ЕГО ЗАПИСЬ распаковщиком и пакует заново.
 *
 * Вторая полоса и есть механизм #1242: на node 26 распаковка достаточно крупной
 * записи не завершается, файл трассы остаётся без центрального каталога, и ни
 * один просмотрщик его не открывает. Замер той задачи: одна запись трассы в
 * 16 626 277 байт читается целиком на node 22.23.2 и останавливается на
 * 15 004 590 байтах на node 26.7.0.
 *
 * Починка #1242 увела запись трассы на ПЕРВУЮ полосу — но увела не выбором, а
 * тем, что браузер здесь местный. Дефект живёт в среде исполнения, он не наш, и
 * от него мы не защищены: мы просто не ходим по второй полосе. Пойдут пробы на
 * внешний сервер браузеров — ради скорости, ради общего пула, — и остановка
 * вернётся ТЕМ ЖЕ ПУТЁМ и МОЛЧА: трасса снова начнёт теряться ровно на падении,
 * там, где она единственный артефакт разбора.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ОТКАЗ, А НЕ КОММЕНТАРИЙ
 *
 * Объявление в комментарии решением не является: его не видит тот, кто задаёт
 * переменную окружения в объявлении конвейера, и оно не краснеет, когда его
 * нарушат. Здесь решение ИСПОЛНЯЕТСЯ — прогон отказывается стартовать, называя
 * и причину, и предикат возврата. Отказ наступает при загрузке конфигурации, ДО
 * подъёма стенда: сорок минут стенда не тратятся на исход, известный заранее.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРЕДИКАТ ВОЗВРАТА — что должно стать верным, чтобы решение перестало
 * действовать
 *
 * Ровно то, чем доказана починка #1242: уронить пробу на удалённом браузере и
 * ОТКРЫТЬ её файл трассы просмотрщиком (`npx playwright show-trace <файл>`) —
 * центральный каталог на месте, записи читаются. Сойдётся — снимать этот отказ
 * правкой ЗДЕСЬ, со ссылкой на замер. Ручки, снимающей его на ходу, нет
 * НАМЕРЕННО: она была бы маской ровно того класса, ради которого отказ заведён,
 * — послаблением, которое воссоздаёт дефект, от которого спасает.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ФОРМЫ ВЫБОРА УДАЛЁННОГО БРАУЗЕРА — ПЕРЕЧЕНЬ ЗАКРЫТЫЙ И ПРОЧИТАННЫЙ
 *
 * Их три, и все три читаются ниже. Перечень снят с кода playwright 1.56.1, а не
 * выведен из документации: рабочая копия проб пинит эту версию точно.
 *   1) переменная окружения `PW_TEST_CONNECT_WS_ENDPOINT`;
 *   2) `connectOptions` в блоке `use` конфигурации;
 *   3) `connectOptions` в блоке `use` любого проекта — на случай, если проекты
 *      здесь когда-нибудь заведут (сегодня их ноль).
 * Соседние переменные `PW_TEST_CONNECT_HEADERS` и `PW_TEST_CONNECT_EXPOSE_NETWORK`
 * удалённого браузера сами по себе НЕ выбирают: прогонщик читает их только
 * вместе с адресом. Включить их в перечень значило бы краснеть на входе, от
 * которого ничего не зависит, — а проверку, чьи находки ложны, перестают
 * читать.
 */

/**
 * Форма, в которой политика читает объявление. Намеренно уже настоящей: она
 * судит ровно об одном поле, и лишнее знание сделало бы её ломкой к правкам
 * конфигурации, которых её предмет не касается.
 */
export interface BrowserConnectionDeclaration {
  use?: { connectOptions?: unknown };
  projects?: ReadonlyArray<{ name?: string; use?: { connectOptions?: unknown } }>;
}

/** Переменная окружения, которой прогонщик выбирает удалённый браузер. */
export const REMOTE_ENDPOINT_ENV = "PW_TEST_CONNECT_WS_ENDPOINT";

/**
 * remoteBrowserRefusal — текст отказа, если удалённый браузер выбран хоть одной
 * из трёх форм; `null`, если не выбран ни одной.
 *
 * ПРЕДИКАТ ЗДЕСЬ ТОТ ЖЕ, ЧТО У ПРОГОНЩИКА, а не «похожий», и это не педантизм.
 * Прогонщик решает истинностью значения (`if (wsEndpoint)`, `if (connectOptions)`),
 * поэтому и здесь стоит истинность. Проверка, обрезавшая бы пробелы или
 * сравнивавшая с пустой строкой, разошлась бы с транспортом на вырожденном
 * значении: строка из одного пробела для неё пуста, а для прогонщика — адрес,
 * по которому он честно пойдёт соединяться.
 */
export function remoteBrowserRefusal(
  env: Readonly<Record<string, string | undefined>>,
  declaration: BrowserConnectionDeclaration,
): string | null {
  const selectors: string[] = [];

  if (env[REMOTE_ENDPOINT_ENV]) {
    selectors.push(`переменная окружения ${REMOTE_ENDPOINT_ENV}`);
  }
  if (declaration.use?.connectOptions) {
    selectors.push("use.connectOptions в playwright.config.ts");
  }
  (declaration.projects ?? []).forEach((project, index) => {
    if (project?.use?.connectOptions) {
      const named = project.name ? ` («${project.name}»)` : "";
      selectors.push(`projects[${index}]${named}.use.connectOptions`);
    }
  });

  if (selectors.length === 0) {
    return null;
  }

  // Отказ, который видит оператор, ОБЯЗАН называть предмет прямо: иначе стенд не
  // поднять, а непонятный запрет снимут следующей правкой как непонятный.
  return [
    "Удалённый браузер здесь НЕ ИСПОЛЬЗУЕТСЯ — это записанное решение (#1288), а",
    "не недосмотр. Выбран он вот чем: " + selectors.join("; ") + ".",
    "",
    "ПОЧЕМУ. Трассу упавшей пробы сохраняет разбор фикстуры `page`. При местном",
    "браузере архив складывается из файлов; при удалённом прогонщик дописывает",
    "записи в готовый архив, а дописывание переоткрывает его и распаковывает",
    "КАЖДУЮ запись. На этой полосе распаковка крупной записи не завершается",
    "(#1242): файл остаётся без центрального каталога и не открывается ни одним",
    "просмотрщиком — то есть трасса теряется ровно на падении, там, где она",
    "единственный артефакт разбора.",
    "",
    "ПРЕДИКАТ ВОЗВРАТА. Уронить пробу на удалённом браузере и ОТКРЫТЬ её файл",
    "трассы (`npx playwright show-trace <файл>`). Сойдётся — снять этот отказ",
    "правкой remote-browser-policy.ts со ссылкой на замер. Ручки, снимающей его",
    "на ходу, нет намеренно: она была бы маской того самого класса.",
  ].join("\n");
}
