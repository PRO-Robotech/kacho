// Колонки таблицы из объявления ресурса — ОДНА реализация на всё дерево,
// в `@shared/lib/spec-columns`.
//
// Здесь лежала её копия, и копия отстала — молча и ровно в том, что видит
// человек. Различия сняты этим ре-экспортом, и каждое названо, чтобы следующий
// не завёл копию снова:
//
//   • БУЛЕВО ПЕЧАТАЛОСЬ СЫРЫМ. Ветки `bool` в копии не было вовсе, поэтому
//     значение уходило в умолчание и показывалось словом `true` — служебным
//     ответом вместо факта о ресурсе. Общая ветка рисует `BoolFact`: обе стороны
//     названы следствием, а непришедшее поле остаётся прочерком (отсутствие
//     значения и ложь — разные утверждения).
//   • ШИРИНЫ КОЛОНОК НЕ ЗАДАВАЛИСЬ. Колонка без ширины забирает остаток себе, и
//     значения одного типа стоят в разных таблицах на разной вертикали.
//   • НАБОР ССЫЛОК СВОРАЧИВАЛСЯ В «ещё N» — число, из которого не узнать ни
//     одного ресурса; общая ветка рисует каждую ссылку своей строкой.
//   • ССЫЛКА НЕ ЗНАЛА, ЧТО СТОИТ В СТРОКЕ СВОЙСТВ. Копия тянула СВОЙ
//     `ResourceLink` — без `property-row-context`, поэтому рядом с общим значком
//     строки появлялся второй, свой; и копировала она ПОКАЗАННОЕ значение, то
//     есть идентификатор вместе с многоточием усечения.
//
// Реестр ресурсов при этом остаётся модульным: адрес карточки в этот модуль
// приходит от вызывающего (`nameHref`/`nameBasePath`), а не выводится из общего
// реестра, — поэтому сведение колонок ничего у модуля не отнимает.
