// Порядок суит — свойство ДЕРЕВА, а не машины, на которой идёт прогон.
//
// # Предмет
//
// Порядок по умолчанию задаёт `@jest/test-sequencer` (30.4.1, `build/index.js`,
// `sort()`), и он определяется четырьмя величинами, ни одна из которых деревом не
// является:
//
//   1. упала ли суита в ПРЕДЫДУЩЕМ прогоне — такие идут первыми;
//   2. есть ли о ней запись длительности в кэше `perf-cache-<id>` (`cacheDirectory`);
//   3. сама длительность — по убыванию;
//   4. РАЗМЕР ФАЙЛА по убыванию — когда записи о длительности нет.
//
// Отсюда: первый прогон на чистой машине идёт не в том порядке, что второй; прогон
// после красного — не в том, что после зелёного; правка комментария меняет размер
// файла и вместе с ним порядок. Наблюдалось при разборе #461: пара проб `a-…`/`b-…`
// исполнилась в порядке `b`, `a` — то есть «ну там алфавит» было бы догадкой.
//
// # Почему это дефект, а не мелочь
//
// Пока порядок плавает, суита, зависящая от порядка, даёт РАЗНОЕ число падений на
// одном и том же дереве (#461: «4–6 упавших, число меняется между прогонами»).
// Такую красноту нельзя ни воспроизвести, ни отличить от настоящей находки — её
// списывают на «флейк» вместе со всем, что рядом.
//
// Закрепление порядка зависимость от порядка НЕ прячет: она перестаёт быть
// перемежающейся и становится воспроизводимой, то есть впервые становится
// починяемой. А что зависимости нет — проверяется прогоном в ДРУГОМ порядке, и он
// делается этим же файлом, без второго механизма:
//
//   KACHO_JEST_SUITE_ORDER=reverse npm test
//
// Вердикт обоих прогонов обязан совпадать. В конвейере обратный прогон НЕ стоит,
// и это названо долгом, а не выдано за проверку: межсуитного носителя состояния в
// этом харнессе не нашлось ни одного живого (замер — в теле PR к #461), поэтому у
// второго полного прогона сегодня нет производителя входа. Появится проба, несущая
// состояние через файловую систему, — появится и предмет для второго прогона.
//
// # Цена, названная честно
//
// Теряется «упавшее — первым» из порядка по умолчанию: локально красная суита
// больше не всплывает наверх списка. Скорости это не стоит ничего — все девять
// пакетов консоли гоняют `--runInBand`
// (предикат: `grep -l -- --runInBand ui-future/*/package.json | wc -l` → 9 при
// `git ls-files ui-future | grep -c jest.config.cjs` → 9), то есть параллельных
// исполнителей нет вовсе и эвристика «длинное вперёд», ради которой порядок по
// умолчанию написан, не покупает ничего.
//
// # Чем держится
//
// `internal/repohygiene` `TestConsoleSuiteOrderIsAPropertyOfTheTree` — каждый
// пакет консоли с jest-конфигом обязан объявлять `testSequencer`, и объявленный
// файл обязан существовать.

const Sequencer = require("@jest/test-sequencer").default;

/** Обратный порядок — только по явному требованию; см. шапку. */
const REVERSED = process.env.KACHO_JEST_SUITE_ORDER === "reverse";

/**
 * Порядок — лексикографический по пути файла. Наследование сохраняет `shard()`
 * (`--shard`), `allFailedTests()` (`--onlyFailures`) и запись кэша длительностей:
 * меняется РОВНО порядок, ничего больше.
 */
class ByPathSequencer extends Sequencer {
  sort(tests) {
    const asc = Array.from(tests).sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
    return REVERSED ? asc.reverse() : asc;
  }
}

module.exports = ByPathSequencer;
