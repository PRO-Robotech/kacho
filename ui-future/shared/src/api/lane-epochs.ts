// Эпоха контекста формы, которую консоль ведёт сама, — ОДНА на вкладку.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ
//
// КОНТЕКСТ ФОРМЫ меняют три глагола — вход, регистрация и завершение
// восстановления (новое печенье `kaname_form`). Печенье `httpOnly`, консоль его
// не читает, и смена видна ей только ответом своего же глагола. Признак формы,
// добытый до такого ответа, принадлежит прежнему контексту и будет отвергнут
// (условие C12).
//
// Эпохи носителя здесь больше нет. Она служила повтору «с текущим носителем»
// на `invalid_token` после перевыпуска этой вкладкой (условие C18 редакции 6),
// а он невыполним: ответ края на прежний носитель гасит печенье, и повторять
// нечем. Перевыпуск носителя упорядочивает `carrier-order.ts` (приёмка F8, Р10):
// обращение, выпущенное до глагола, к его выпуску уже имеет исход, поэтому
// ответ на прежний носитель после перевыпуска вкладке не приходит вовсе.
//
// ПОЧЕМУ НА `globalThis`, А НЕ В ПЕРЕМЕННОЙ МОДУЛЯ
//
// `@shared` не разделяется между модулями консоли как единственный экземпляр:
// каждый модуль и каркас собирают свою копию. Смена контекста, сделанная экраном
// каркаса, обязана быть видна держателю признака модуля в той же вкладке,
// поэтому эпоха лежит в одном месте вкладки под ключом глобального реестра
// символов — он общий у всех копий в одной вкладке.

const KEY = Symbol.for("kacho.console.lane-epochs");

interface Epochs {
  formContext: number;
}

function epochs(): Epochs {
  const g = globalThis as unknown as Record<symbol, Epochs | undefined>;
  let e = g[KEY];
  if (!e) {
    e = { formContext: 0 };
    g[KEY] = e;
  }
  return e;
}

/** Номер смены контекста формы в этой вкладке. */
export function formContextEpoch(): number {
  return epochs().formContext;
}

/** Глагол этой вкладки сменил контекст формы. */
export function noteFormContextChanged(): void {
  epochs().formContext += 1;
}
