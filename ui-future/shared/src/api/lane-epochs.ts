// Две эпохи браузерной сессии, которые консоль ведёт сама, — ОДНИ на вкладку.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ
//
// Служба меняет две вещи под открытым экраном, и оба изменения видны консоли
// только ответом своего же глагола (печенья `httpOnly`, консоль их не читает):
//
//   • КОНТЕКСТ ФОРМЫ меняют три глагола — вход, регистрация и завершение
//     восстановления (новое печенье `kaname_form`). Признак формы, добытый до
//     такого ответа, принадлежит прежнему контексту и будет отвергнут
//     (условие C12);
//   • НОСИТЕЛЬ СЕССИИ перевыпускают восемь глаголов — вход, регистрация, смена
//     пароля, завершение восстановления, подтверждение и снятие второго
//     фактора, перечеканка запасных кодов, повышение уровня. Прежний дайджест
//     после этого не находит записи, и запрос ЭТОЙ вкладки, ушедший с прежним
//     носителем, получает `invalid_token` — не потому, что сессия кончилась, а
//     потому, что её перевыпустили здесь же (условие C18).
//
// ПОЧЕМУ НА `globalThis`, А НЕ В ПЕРЕМЕННОЙ МОДУЛЯ
//
// `@shared` не разделяется между модулями консоли как единственный экземпляр:
// каждый модуль и каркас собирают свою копию. Перевыпуск, сделанный экраном
// параметров каркаса, обязан быть виден клиенту API модуля в той же вкладке,
// поэтому эпохи лежат в одном месте вкладки под ключом глобального реестра
// символов — он общий у всех копий в одной вкладке.

const KEY = Symbol.for("kacho.console.lane-epochs");

interface Epochs {
  bearer: number;
  formContext: number;
}

function epochs(): Epochs {
  const g = globalThis as unknown as Record<symbol, Epochs | undefined>;
  let e = g[KEY];
  if (!e) {
    e = { bearer: 0, formContext: 0 };
    g[KEY] = e;
  }
  return e;
}

/** Номер перевыпуска носителя в этой вкладке. */
export function bearerEpoch(): number {
  return epochs().bearer;
}

/** Номер смены контекста формы в этой вкладке. */
export function formContextEpoch(): number {
  return epochs().formContext;
}

/** Глагол этой вкладки перевыпустил носитель. */
export function noteBearerRotated(): void {
  epochs().bearer += 1;
}

/** Глагол этой вкладки сменил контекст формы. */
export function noteFormContextChanged(): void {
  epochs().formContext += 1;
}
