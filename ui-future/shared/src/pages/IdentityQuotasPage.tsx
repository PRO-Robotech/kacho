// «Мои квоты» — пределы, носителем которых является ЛИЧНОСТЬ, а не проект (#622).
//
// Сегодня такой вид один: сколько аккаунтов человеку позволено завести
// (`iam.account`, платформенное умолчание — 5). Сервер его отдаёт с тех пор, как
// потолок заведён, консоль — не показывала, и человек упирался в отказ на первом
// же действии, к которому платформа его приглашает, не видя ни своего предела,
// ни своего расхода, ни того, что предел вообще существует.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГДЕ ЖИВЁТ ЭТА ВИТРИНА И ПОЧЕМУ ИМЕННО ТУТ
//
// Решение: ОТДЕЛЬНЫЙ РАЗДЕЛ `/iam/quotas`, рядом со списком аккаунтов, — не
// строка в проектной таблице и не новая страница профиля. Четыре довода, и
// первый из них исключает половину вариантов сам по себе.
//
//  1. АДРЕС НЕ ВПРАВЕ ТРЕБОВАТЬ ПРОЕКТА. Проектная витрина живёт под
//     `/projects/:projectId/quotas` и без выбранного проекта показывает
//     заглушку. Носитель здесь — личность: предел существует, когда у человека
//     нет ни одного проекта, и одинаков во всех его аккаунтах. Для того, кто
//     упёрся в потолок аккаунтов, требование «сначала откройте проект» может
//     быть невыполнимо by construction — а он и есть единственный читатель этой
//     страницы. Раздел `/iam/*` проекта не требует; это и есть предикат снятия
//     задачи, выраженный адресом.
//
//  2. НЕ СТРОКА В ПРОЕКТНОЙ ТАБЛИЦЕ. Та таблица отвечает про ОДИН проект и
//     спрашивает его владельцев. Число, которое от проекта не зависит, стоя в
//     ней, приписало бы проекту чужое свойство — и менялось бы синхронно во всех
//     проектах человека, что читается как дефект, а не как замысел.
//
//  3. РЯДОМ СО СПИСКОМ АККАУНТОВ, потому что потолок — НАД АККАУНТАМИ. Человек
//     видит там, сколько их у него, и тянется к кнопке, которая получит отказ.
//     Предел, объясняемый в другой части консоли, находят ПОСЛЕ отказа, а не до
//     него; здесь он попадается на глаза раньше, чем понадобится.
//
//  4. НЕ НОВАЯ СТРАНИЦА ПРОФИЛЯ. Страницы «моя учётная запись» в консоли нет, и
//     заводить целую поверхность ради одной таблицы значило бы спрятать ответ,
//     а не показать: вопрос «сколько аккаунтов мне можно» задают там, где
//     аккаунты перечислены. Появится профиль со своим предметом — эта витрина
//     переедет в него одной строкой маршрута, потому что своей вёрстки не несёт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО СТРАНИЦА НЕ ДЕЛАЕТ
//
// Не меняет величину и не предлагает её менять: предел назначает администратор
// облака на внутреннем слушателе. Арендатор, способный поднять свой потолок,
// потолка не имеет — кнопка здесь была бы обещанием действия, которое у него
// отказом и закончится.
//
// Не спрашивает, о ком речь. У чтения нет ни одного поля запроса: предмет —
// проверенный вызывающий и никто больше. Поэтому здесь нет ни выбора личности,
// ни идентификатора в адресе: вопрос о чужом расходе невыразим, и это сильнее
// любой проверки, которая обязана срабатывать каждый раз.

import { useMemo } from "react";
import { useQuery } from "@tanstack/react-query";
import { Alert, Typography } from "antd";
import { DashboardOutlined } from "@ant-design/icons";
import { api } from "@shared/api/client";
import { ErrorResult } from "@shared/components/molecules/ErrorResult";
import { PanelHeader } from "@shared/components/molecules/PanelHeader";
import { useBreadcrumb } from "@shared/components/molecules/PageHeaderSlot";
import { QuotaTable } from "@shared/components/organisms/QuotaTable";
import { CARRIER_IDENTITY, quotaRows, type Quota } from "@shared/lib/quota-view";

/**
 * Путь чтения — тот, что объявлен контрактом и зарегистрирован на крае:
 * `GET /iam/v1/quotas` (`kacho.cloud.quota.v1.IdentityQuotaService/List`).
 *
 * Владелец ОДИН, и перечня здесь нет намеренно: носитель-личность существует
 * ровно у владельца величин, потому что аккаунт — корень аренды, и потолок над
 * ним обязан лежать на том, что существует до аккаунта и переживает его.
 * Появится второй такой владелец — здесь появится перечень, как у проектной
 * витрины; заводить его вперёд предмета значило бы держать форму без содержания.
 */
const IDENTITY_QUOTAS_PATH = "/iam/v1/quotas";

interface QuotasResponse {
  quotas?: Quota[];
}

export function IdentityQuotasPage() {
  // Узел хлебной крошки МЕМОИЗИРУЕТСЯ. Свежий элемент на каждом рендере означал
  // бы новое значение в состоянии слота, то есть новый рендер — и цикл без
  // единого падающего утверждения: суита не доходит до отчёта, а выглядит как
  // зависшая.
  const breadcrumb = useMemo(
    () => (
      <span style={{ display: "inline-flex", alignItems: "center", gap: 6 }}>
        <Typography.Text type="secondary">Личность</Typography.Text>
        <Typography.Text type="secondary">/</Typography.Text>
        <Typography.Text strong>Мои квоты</Typography.Text>
      </span>
    ),
    [],
  );
  useBreadcrumb(breadcrumb);

  const { data, isLoading, isError, error, isSuccess } = useQuery({
    // Ключ не несёт ни проекта, ни аккаунта: ответ от них не зависит, и
    // подмешать их сюда значило бы обещать кэшу различие, которого нет.
    queryKey: ["identity-quotas"],
    queryFn: () => api.get<QuotasResponse>(IDENTITY_QUOTAS_PATH),
    staleTime: 10_000,
  });

  const quotas: Quota[] = useMemo(() => data?.quotas ?? [], [data]);
  // Предмет страницы назван ЯВНО. Без него строка с носителем-личностью прошла
  // бы как «считается не здесь» и потребление — единственное число, ради
  // которого человек сюда пришёл, — не показалось бы вовсе.
  const rows = useMemo(() => quotaRows(quotas, CARRIER_IDENTITY), [quotas]);

  return (
    <div
      className="kc-surface"
      style={{ padding: 20, height: "100%", overflow: "hidden", display: "flex", flexDirection: "column" }}
    >
      <div style={{ flexShrink: 0, marginBottom: 12 }}>
        <PanelHeader
          icon={<DashboardOutlined />}
          eyebrow="Личность"
          title="Мои квоты"
          subtitle="Считаются по всем вашим аккаунтам и не зависят ни от проекта, ни от того, под каким аккаунтом вы вошли"
          right={
            <Typography.Text type="secondary" style={{ fontSize: 12 }}>
              Величины задаёт администратор облака
            </Typography.Text>
          }
        />
      </div>

      {isError && (
        <Alert
          type="error"
          showIcon
          style={{ flexShrink: 0, marginBottom: 12 }}
          message="Пределы не прочитаны"
          // Отказ называется отказом. Пустая витрина на его месте читалась бы
          // как «ограничений нет» — то есть ровно наоборот действительности.
          description={<ErrorResult error={error} />}
        />
      )}

      {isSuccess && quotas.length === 0 && (
        <Alert
          type="warning"
          showIcon
          style={{ flexShrink: 0, marginBottom: 12 }}
          message="Ответ не назвал ни одного предела"
          // Контракт чтения обещает полный набор всегда — человек, не заведший
          // ничего, получает его с нулями. Пустой ответ достижим ровно тогда,
          // когда величина не назначена ни на одной области, а «потолок не
          // назван» есть отказ, а не бесконечность: выдать это за «ограничений
          // нет» значило бы пообещать возможность, которой не существует.
          description={
            "Так быть не должно: предел на число аккаунтов приходит и тому, кто не завёл ни одного. " +
            "Обратитесь к администратору облака."
          }
        />
      )}

      <div style={{ flex: 1, minHeight: 0, minWidth: 0 }}>
        <QuotaTable rows={rows} loading={isLoading} empty="Ограничения не прочитаны" />
      </div>
    </div>
  );
}
