// Выход вкладки: пока он идёт и после его подтверждения вкладку на вход уводит
// ТОЛЬКО он (приёмка F8, выход; условие C14).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ
//
// Выход уводит документ на экран входа БЕЗ адреса возврата: адрес возврата —
// страница прежнего человека, и следующий, вошедший в этом браузере, был бы
// уведён входом на неё — на чужой проект, чтения которого пошли бы с его
// сессией. Но на вход вкладку уводит не только выход: отказ `401` чтения
// (`redirectToLogin` каркаса и панели) уводит туда же С адресом возврата. После
// подтверждённого выхода носителя у браузера нет, и каждое чтение страницы,
// выпущенное до ухода документа (перечитывание при закрытии потока изменений,
// повтор списка), получает `401`. Переход по нему, начатый после перехода
// выхода, его отменяет — браузер исполняет последний, — и вкладка приходит на
// вход с адресом прежнего человека (F8-18, прогон 36208863788: `/login`
// отменён, исполнен `/login?returnTo=%2Fprojects%2F<проект первого>%2Fdashboard`,
// и вход второго человека увёл его на проект первого).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРАВИЛО
//
// С начала выхода (признак формы, затем глагол) вкладка УХОДИТ: переход на вход
// по отказу `401` не производится. Отказ выхода метку снимает — экран остаётся, и следующий `401`
// уводит как обычно. Подтверждённый выход её не снимает: документ уходит, и
// новая страница начинает без неё.
//
// ПОЧЕМУ С НАЧАЛА, А НЕ С ОТВЕТА. Чтение, дошедшее до края после того, как
// служба погасила сессию, получает `401`, и его ответ вправе прийти к странице
// раньше ответа выхода: метка, поставленная по ответу, такой `401` не застала бы.
//
// ПОЧЕМУ НА `globalThis`. `@shared` собирается в каждый модуль консоли своей
// копией: выход ведёт панель каркаса, а `401` получает клиент модуля (панель —
// `dashboard`). Метка одна на вкладку, поэтому лежит под ключом глобального
// реестра символов — та же причина, что у упорядочения (`api/carrier-order.ts`).
//
// ЧТО ДЕРЖИТ. Модульные пробы переходов по `401` каркаса и панели
// (`host/src/utils/auth.test.ts`, `dashboard/src/utils/auth.test.ts`) — исход
// выхода подтверждён, в полёте, отвергнут; исход у страницы — браузерная проба
// F8-18 (`e2e/specs/identity-ceremony.spec.ts`).

const KEY = Symbol.for("kacho.console.tab-exit");

/** Выход начат: с этого отрезка вкладку на вход уводит только он. */
export function beginTabExit(): void {
  const g = globalThis as unknown as Record<symbol, boolean | undefined>;
  g[KEY] = true;
}

/** Выход отвергнут: вкладка остаётся, и отказ `401` снова уводит на вход. */
export function abandonTabExit(): void {
  const g = globalThis as unknown as Record<symbol, boolean | undefined>;
  delete g[KEY];
}

/** Уходит ли вкладка выходом — тогда переход на вход по отказу `401` не производится. */
export function tabExiting(): boolean {
  const g = globalThis as unknown as Record<symbol, boolean | undefined>;
  return g[KEY] === true;
}
