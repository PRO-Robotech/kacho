// Признак покрытия потоком для вызывающего, который НЕ живёт над react-query.
//
// ---------------------------------------------------------------------------
// ЗАЧЕМ ВТОРОЙ ХУК ПОКРЫТИЯ, ЕСЛИ ЕСТЬ `useResourceStream`
//
// Предметы у них разные, и это не оттенок. `useResourceStream` отвечает на
// вопрос «перечитай ЭТОТ ключ запроса», поэтому неотделим от react-query:
// перечитывание делает `queryClient.invalidateQueries`. Витрина же считает
// счётчики САМА — своим загрузчиком, без клиента запросов вовсе, — и ей нужен
// ровно признак покрытия, а не перечитывание чужого ключа.
//
// Здесь НЕ ЗАВОДИТСЯ второй клиент потока: клиент один и тот же —
// `subscriptionHub()`, единственный дом которого `lib/subscription/hub.ts`
// (решение владельца 2026-08-22, тело #1021; держит гейт
// `console-stream-client-single`). Этот файл приёмника событий не строит и
// адреса потока не знает: он складывает уже существующие `subscribe`,
// `covers` и `onCoverageChange` в форму, годную вызывающему без react-query.
//
// ---------------------------------------------------------------------------
// ПОЧЕМУ ПОКРЫТИЕ — «ВСЕ ВИДЫ ИЛИ НИ ОДНОГО»
//
// Вызывающий здесь показывает НАБОР величин разом (счётчики плитки), и опрос у
// него один на весь набор: читая список ради одного счётчика, он всё равно
// сходит за остальными. Покрытие «частью видов» сняло бы опрос там, где часть
// величин перестала бы обновляться, — то есть дало бы застывшее число, которое
// со стороны неотличимо от верного. Поэтому `streamed` истинно, только когда
// покрыт КАЖДЫЙ вид набора, а один невыразимый предмет (домен без журнала)
// оставляет на опросе весь набор — осознанно и целиком.

import { useEffect, useRef, useState } from "react";
import { streamSubject } from "../lib/subscription/subjects";
import { subscriptionHub, type StreamEvent, type SubscriptionHub } from "../lib/subscription/hub";

export interface UseStreamCoverageArgs {
  /**
   * Идентификаторы спек, чьи величины показывает вызывающий.
   *
   * `null` в перечне — «у этого предмета журнала нет», и он честно гасит
   * покрытие всего набора. Пустой перечень покрытием тоже не является:
   * покрывать нечего, а «нечего» и «покрыто» — разные ответы.
   */
  specIds: readonly (string | null)[];
  /** Проект, к которому относится показанное. */
  projectId: string | null;
  /** Что позвать, когда владелец сообщил об изменении любого из видов набора. */
  onChanged: () => void;
  /** Открывать ли поток. Незаданное значение читается как «да». */
  enabled?: boolean;
}

export interface StreamCoverage {
  /** Покрыт ли КАЖДЫЙ вид набора прямо сейчас. Опрос снимается только по нему. */
  streamed: boolean;
}

/** Разделители ключа набора. Управляющие байты: во владельце, типе объекта и
 *  идентификаторе проекта они не встречаются, поэтому два разных набора не
 *  могут дать один ключ. */
const PAIR_SEP = "\u0000";
const FIELD_SEP = "\u0001";
const PROJECT_SEP = "\u0002";

export function useStreamCoverage(
  { specIds, projectId, onChanged, enabled = true }: UseStreamCoverageArgs,
  hub: SubscriptionHub = subscriptionHub(),
): StreamCoverage {
  // Разбор спек — во время отрисовки: `streamSubject` чистая, а результат нужен
  // ключом эффекта. Набор считается разобранным, только если разобрана КАЖДАЯ
  // спека: один неизвестный идентификатор означает «покрытия нет», а не
  // «покрыто остальным».
  const subjects = specIds.map((id) => (id ? streamSubject(id) : null));
  const resolved = specIds.length > 0 && subjects.every((s) => s !== null);

  // Ключ набора — он же признак «поток вообще открывается»: `null` означает
  // «предмета нет», и тогда покрытия не бывает ПО ПОСТРОЕНИЮ, а не потому, что
  // кто-то забыл его снять.
  //
  // Утверждения о непустоте здесь НЕТ намеренно: `every` сужает сам массив,
  // поэтому в этой ветке компилятор уже знает, что пустых нет. Приписанное
  // руками `!` не сузило бы ничего — зато сняло бы проверку, начни условие и
  // разбор расходиться.
  const targetKey = resolved
    ? `${subjects.map((s) => `${s.owner}${FIELD_SEP}${s.kind}`).join(PAIR_SEP)}${PROJECT_SEP}${projectId ?? ""}`
    : null;
  const activeKey = enabled ? targetKey : null;

  // Покрытие хранится КЛЮЧОМ покрытого набора, а не признаком «покрыто» — тот
  // пришлось бы гасить сбросом состояния прямо в эффекте, а это каскад
  // перерисовок. Ключ отвечает на тот же вопрос без сброса: покрытие прежнего
  // набора с новым не совпадает и его покрытием прочитаться не может.
  const [coveredKey, setCoveredKey] = useState<string | null>(null);

  // Обработчик — через ссылку: вызывающий пересоздаёт его на каждой отрисовке,
  // и попади он в зависимости эффекта, подписка снималась бы и заводилась
  // заново по нескольку раз в секунду. Поток при этом закрывался бы и
  // открывался — то есть предмет задачи заменился бы более дорогим опросом.
  const changedRef = useRef(onChanged);
  useEffect(() => {
    changedRef.current = onChanged;
  });

  useEffect(() => {
    if (activeKey === null) return;
    // Пересборка из ключа, а не из `subjects`: массив пересоздаётся каждой
    // отрисовкой, а ключ определён его содержимым — значит эффект
    // перезапускается ровно тогда, когда набор ДЕЙСТВИТЕЛЬНО изменился.
    const [joined, keyProject] = activeKey.split(PROJECT_SEP);
    const targets = joined.split(PAIR_SEP).map((pair) => {
      const [owner, kind] = pair.split(FIELD_SEP);
      return { owner, kind, projectId: keyProject === "" ? null : keyProject };
    });

    const handle = (_event: StreamEvent): void => {
      // Предмет события не разбирается: любое событие своего вида означает, что
      // показанные величины устарели. Разбирать род изменения значило бы решать
      // за владельца, какие события «важные», — а именно снятие предмета и есть
      // единственный источник знания о том, что строки больше нет.
      changedRef.current();
    };

    const offs = targets.map((t) => hub.subscribe(t, handle));
    const note = (): void => setCoveredKey(targets.every((t) => hub.covers(t)) ? activeKey : null);
    const offCoverage = hub.onCoverageChange(note);
    // Спросить СРАЗУ: канал этого владельца мог быть открыт соседней плиткой, и
    // тогда объявления покрытия уже не будет — оно прозвучало до подписки.
    note();
    return () => {
      offCoverage();
      for (const off of offs) off();
    };
  }, [hub, activeKey]);

  // Покрытие читается только для СВОЕГО набора. Отсюда же и «предмета нет ⇒ не
  // покрыт»: опрос остаётся включённым без единого сброса состояния.
  return { streamed: activeKey !== null && coveredKey === activeKey };
}
