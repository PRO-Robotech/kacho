import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Гейт: сборка стилей модуля обязана ЧИТАТЬ общие компоненты.
 *
 * ПРЕДМЕТ. Tailwind не «знает» классы — он выпускает правило только для того,
 * что НАШЁЛ в файлах из `content`. Каждый модуль перечислял там ровно свой
 * `./src/**`, а стилевой вход берёт у общего кода (`@shared/index.css`).
 * Следствие: утилита, использованная ТОЛЬКО в `shared/`, не попадала ни в один
 * бандл. Разметка есть, правила нет — элемент показывается умолчанием браузера.
 *
 * ПОЧЕМУ ЭТОГО НЕ ВИДНО НИ В ДИФФЕ, НИ В МОДУЛЬНОЙ ПРОБЕ. Обе стороны
 * исправны по отдельности: компонент честно ставит класс, конфигурация честно
 * перечисляет свой каталог. Ломается их СТЫК, и только на собранном стенде.
 * jsdom каскада не считает, поэтому проба, утверждающая класс в разметке,
 * остаётся зелёной ровно тогда, когда пользователь видит обратное.
 *
 * ЗАМЕР, ИЗ КОТОРОГО ВЫВЕДЕНО (vpc, сборка входа `shared/src/index.css` его же
 * конфигурацией): без общего каталога — 26 619 байт и ЕДИНСТВЕННАЯ утилита
 * прозрачности `.opacity-60`; с ним — 39 837 байт и `.opacity-0` / `.opacity-40`
 * / `.opacity-60` / `.opacity-70` плюс `.group:hover .group-hover\:opacity-100`.
 * То есть тринадцать килобайт правил, которые общий код считал своими, не
 * существовало ни в одном модуле.
 *
 * НАБЛЮДАЛОСЬ ДВАЖДЫ ОДНИМ КОРНЕМ. Значок копирования у имени стоял видимым в
 * покое (#480) — `opacity-40` не существовало; правка, вернувшая ему
 * сдержанность (#482), не подействовала на стенде — `opacity-0` не существовало
 * тоже. Вторую половину поймала сквозная проба браузером: вычисленная
 * прозрачность в покое была 1 при `opacity-0` в разметке.
 *
 * ЧТО ИМЕННО УТВЕРЖДАЕТСЯ — СОДЕРЖАНИЕ, А НЕ ФОРМА. Проверять наличие строки
 * в конфигурации мало: строка, никуда не ведущая (опечатка в пути, каталог
 * переехал), прошла бы такую проверку и оставила гейт зелёным при мёртвой
 * сборке. Поэтому шаблон РАЗВОРАЧИВАЕТСЯ и сверяется с ФАКТИЧЕСКИМ файлом
 * общего кода: гейт падает и тогда, когда шаблон есть, но не матчит ничего.
 *
 * ПЕРЕПИСЬ И СВОЯ ПРЕДПОСЫЛКА. Гейт печатает, сколько конфигураций прочитал, и
 * падает на нуле: «нарушений не найдено» обязано быть отличимо от «ничего не
 * прочитано» — переименованная раскладка иначе сделала бы все утверждения ниже
 * вакуумно истинными.
 */

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");

/** Модули со СВОЕЙ сборкой стилей — выводятся из дерева, а не выписываются:
 *  модуль, заведённый завтра, обязан попасть под гейт сам. */
const MODULES: string[] = readdirSync(repoRoot, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== "shared" && d.name !== "node_modules")
  .map((d) => d.name)
  .filter((name) => existsSync(path.join(repoRoot, name, "tailwind.config.js")))
  .sort();

/**
 * Файл общего кода, который сборка ОБЯЗАНА прочитать. Взят не наугад: именно
 * его классы прозрачности и отсутствовали. Существование проверяется отдельной
 * пробой — исчезни он, гейт стал бы вакуумным, а не красным.
 */
const SAMPLE = "shared/src/components/atoms/CopyableName/CopyableName.tsx";

/**
 * Строковые литералы из массива `content: [...]`.
 *
 * Разбор посимвольный, с состоянием, а НЕ вычёркиванием комментариев регулярным
 * выражением. Первая редакция вычёркивала их именно так — и съедала сам шаблон:
 * в `./src/**` + `/*` последовательность `/**\/` неотличима от блочного
 * комментария, поэтому `"./src/**\/*.{ts,tsx}"` превращался в `"./src*.{ts,tsx}"`
 * и гейт краснел на ИСПРАВЛЕННОМ дереве. Различать код, строковый литерал и
 * комментарий обязан любой гейт, читающий исходник, — здесь это стоило одного
 * прогона и поймано собственной пробой.
 */
function contentGlobs(configText: string): string[] {
  const block = /content:\s*\[([\s\S]*?)\]/.exec(configText);
  if (!block) return [];
  const src = block[1];
  const out: string[] = [];
  for (let i = 0; i < src.length; i += 1) {
    const ch = src[i];
    if (ch === "/" && src[i + 1] === "/") {
      // Строчный комментарий — до конца строки.
      const nl = src.indexOf("\n", i);
      i = nl === -1 ? src.length : nl;
      continue;
    }
    if (ch === "/" && src[i + 1] === "*") {
      const end = src.indexOf("*/", i + 2);
      i = end === -1 ? src.length : end + 1;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      const end = src.indexOf(ch, i + 1);
      if (end === -1) break;
      out.push(src.slice(i + 1, end));
      i = end;
    }
  }
  return out;
}

/** Шаблон пути → регулярное выражение. Поддержаны `**`, `*` и `{a,b}`. */
function globToRegExp(glob: string): RegExp {
  let out = "";
  for (let i = 0; i < glob.length; i += 1) {
    const ch = glob[i];
    if (ch === "*") {
      if (glob[i + 1] === "*") {
        // `**/` съедает и ноль сегментов, иначе `a/**/b.ts` не матчит `a/b.ts`.
        if (glob[i + 2] === "/") {
          out += "(?:.*/)?";
          i += 2;
        } else {
          out += ".*";
          i += 1;
        }
      } else {
        out += "[^/]*";
      }
      continue;
    }
    if (ch === "{") {
      const close = glob.indexOf("}", i);
      if (close !== -1) {
        const alts = glob.slice(i + 1, close).split(",");
        out += `(?:${alts.map((a) => a.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})`;
        i = close;
        continue;
      }
    }
    out += ch.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${out}$`);
}

describe("сборка стилей модуля читает общий код", () => {
  it(`перепись: модулей со своей сборкой стилей ${MODULES.length} (${MODULES.join(", ")})`, () => {
    // Ноль — это «ничего не прочитано», а не «нарушений нет».
    expect(MODULES.length).toBeGreaterThan(0);
    expect(MODULES).toEqual(
      expect.arrayContaining(["compute", "iam", "nlb", "registry", "storage", "system", "vpc"]),
    );
  });

  it("своя предпосылка: образец общего кода на месте", () => {
    // Без него сверка ниже проверяла бы шаблон против несуществующего файла и
    // краснела бы на переезде каталога, а не на дефекте сборки.
    expect(existsSync(path.join(repoRoot, SAMPLE))).toBe(true);
  });

  it.each(MODULES)("%s: шаблоны сборки достают до общего кода", (module) => {
    const configPath = path.join(repoRoot, module, "tailwind.config.js");
    const globs = contentGlobs(readFileSync(configPath, "utf8"));
    // Пустой список — это «читаем всё» ровно наоборот: Tailwind не выпустит
    // ничего. Отдельным утверждением, чтобы отказ назвал причину.
    //
    // Булевыми, а НЕ `expect.arrayContaining` внутри объекта: матчер типизирован
    // как `any`, и в свойстве объекта это присваивание `any` — храповик долга
    // линта пакета shared считает его ростом. Форма ниже строго сильнее прежней:
    // та требовала одного строкового элемента, эта — непустоты и всех строк.
    expect({
      module,
      nonEmpty: globs.length > 0,
      onlyStrings: globs.every((g) => typeof g === "string"),
    }).toEqual({ module, nonEmpty: true, onlyStrings: true });

    // Шаблон разворачивается ОТНОСИТЕЛЬНО каталога модуля — так же, как его
    // читает сборка, — и сверяется с фактическим файлом общего кода.
    const reach = globs.filter((g) => {
      const abs = path.resolve(repoRoot, module, g);
      return globToRegExp(abs).test(path.join(repoRoot, SAMPLE));
    });

    expect({
      module,
      reaches: reach.length > 0,
      hint: `добавь в content шаблон, покрывающий ${SAMPLE}`,
    }).toEqual({
      module,
      reaches: true,
      hint: `добавь в content шаблон, покрывающий ${SAMPLE}`,
    });
  });
});
