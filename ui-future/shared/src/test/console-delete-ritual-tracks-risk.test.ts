import { IRREVERSIBLE_DELETE, requiresNameConfirm } from "@shared/components/molecules/DeleteDialog";
import { hasDependencyResolver } from "@shared/lib/dependency-graph";
import { REGISTRY } from "@shared/lib/resource-registry";

/**
 * Гейт: ТЯЖЕСТЬ ПОДТВЕРЖДЕНИЯ РАСТЁТ ВМЕСТЕ С НЕОБРАТИМОСТЬЮ (#1606).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЛОВИТ
 *
 * Ритуал удаления был перевёрнут относительно риска. Ввод имени руками
 * требовался у сети, таблицы маршрутов и группы безопасности — там, где сервер
 * и так откажет, пока есть дети (RESTRICT), и терять нечего. У тома, снимка,
 * образа, машины и репозитория реестра — где содержимое исчезает безвозвратно —
 * хватало одного клика, и та же общая фраза «Ресурс будет удалён безвозвратно»
 * не называла, что именно уйдёт.
 *
 * Комментарий у критерия объявлял его как «необратимо + каскадные
 * RESTRICT-зависимости», хотя RESTRICT-зависимость — ровно то, что делает
 * удаление НЕ разрушительным.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ КРИТЕРИЙ — «ИСЧЕЗАЮТ ЛИ ДАННЫЕ», А НЕ «ЕСТЬ ЛИ ЗАВИСИМОСТИ»
 *
 * Ритуал — это сигнал, и сигнал стоит ровно столько, сколько стоит его
 * редкость. Ввод имени у КАЖДОГО удаления перестал бы отличать опасное от
 * рядового — тот же изъян, что у порога тревоги, срабатывающего на штатном
 * состоянии: его перестают читать, и вместе с ним перестают читать настоящую
 * находку. Поэтому имя спрашивается там и только там, где ошибка необратима по
 * СОДЕРЖИМОМУ, а не по количеству ссылок.
 *
 * RESTRICT-ресурс к таким не относится by construction: пока у него есть дети,
 * край отказывает, а без детей его воссоздают той же формой за минуту. Отсюда
 * проверяемое свойство — два множества НЕ ПЕРЕСЕКАЮТСЯ; на нём и держится
 * утверждение, что критерий сменился, а не расширился.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ КЛАССИФИКАЦИЯ И ЕЁ ОБОСНОВАНИЕ — ОДНО ОБЪЯВЛЕНИЕ
 *
 * `IRREVERSIBLE_DELETE` несёт не признак, а ПРИЧИНУ: что именно исчезнет.
 * Признак выводится из наличия причины. Разойтись им не на чем — «ресурс
 * помечен опасным» и «вот что он теряет» суть одна запись, а не две. Двумя
 * записями они разошлись бы при первой же правке, и опасным остался бы ресурс,
 * которому нечего терять.
 */

const specs = REGISTRY;

/** Ресурсы, чьё удаление край отклоняет, пока есть дети (дерево зависимостей). */
const restrictProtected = Object.keys(specs).filter((id) => hasDependencyResolver(id));

const irreversible = Object.keys(IRREVERSIBLE_DELETE);

process.stdout.write(
  `\n  ритуал удаления: спек осмотрено ${Object.keys(specs).length}, ` +
    `удаляемых ${Object.values(specs).filter((s) => s.ops?.delete).length}, ` +
    `необратимых по содержимому ${irreversible.length}, ` +
    `защищённых RESTRICT ${restrictProtected.length}\n\n`,
);

describe("ритуал удаления следует необратимости, а не зависимостям (#1606)", () => {
  it("перепись непуста: пустой обход — отказ, а не зелёное", () => {
    expect(Object.keys(specs).length).toBeGreaterThan(0);
    expect(irreversible.length).toBeGreaterThan(0);
    expect(restrictProtected.length).toBeGreaterThan(0);
  });

  it("ни один RESTRICT-защищённый ресурс не требует ввода имени", () => {
    // Ядро инверсии. Пересечение здесь означало бы, что имя спрашивают там, где
    // край и так откажет, — то есть ритуал снова висит на количестве ссылок.
    const both = restrictProtected.filter((id) => requiresNameConfirm(id));
    expect(both).toEqual([]);
  });

  it("каждый необратимый ресурс требует ввода имени", () => {
    const silent = irreversible.filter((id) => !requiresNameConfirm(id));
    expect(silent).toEqual([]);
  });

  it("каждая запись называет РЕАЛЬНЫЙ ресурс, который вправду удаляют", () => {
    // Запись про несуществующую спеку либо про ресурс без удаления — инертна:
    // она выглядит защитой и не срабатывает ни разу. Тот же класс, что
    // исключение, которому нечего исключать.
    const dead = irreversible
      .filter((id) => specs[id] === undefined || specs[id].ops?.delete !== true)
      .map((id) => (specs[id] === undefined ? `${id}: спеки нет в реестре` : `${id}: ресурс не удаляется из консоли`));
    expect(dead).toEqual([]);
  });

  it("каждая запись называет, ЧТО именно исчезнет", () => {
    // Общая фраза «Ресурс будет удалён безвозвратно» одинакова у тома и у
    // пустой сети и потому не сообщает ничего. Запись обязана назвать предмет
    // потери — иначе ритуал есть, а предупреждения нет.
    const mute = Object.entries(IRREVERSIBLE_DELETE)
      .filter(([, why]) => why.trim().length === 0 || /^Ресурс будет удалён безвозвратно/.test(why.trim()))
      .map(([id, why]) => `${id}: «${why}» — не называет, что теряется`);
    expect(mute).toEqual([]);
  });

  it("рядовое удаление имени НЕ требует — контроль в обратную сторону", () => {
    // Без него отрицания выше зеленели бы на критерии, который требует имя
    // всюду: «пересечения нет» верно и тогда, когда высок риск у всех.
    expect(requiresNameConfirm("subnets")).toBe(false);
    expect(requiresNameConfirm("networks")).toBe(false);
    expect(requiresNameConfirm("volumes")).toBe(true);
    expect(irreversible.length).toBeLessThan(Object.values(specs).filter((s) => s.ops?.delete).length);
  });
});
