import { ENTITIES, type EntityKey } from "@shared/lib/entity-names";
import { KNOWN_KINDS, kindLabel } from "@shared/lib/quota-view";

/**
 * Гейт: ВИТРИНА КВОТ НАЗЫВАЕТ РЕСУРС ТЕМ ЖЕ СЛОВОМ, ЧТО ВЕСЬ ОСТАЛЬНОЙ ПРОДУКТ (#1703).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЛОВИЛ — ТРИ ПОЛОСЫ ОДНОГО МЕХАНИЗМА, КОТОРЫЕ НИКТО НЕ СВЕРЯЛ МЕЖДУ СОБОЙ
 *
 * До ухода службы доступа их было ТРИ:
 *
 *  A. каталог видов у владельца величин (`services/iam/internal/domain/limit.go`,
 *     `countableKinds`) — что край вообще может назвать в ответе и в отказе;
 *  B. витрина квот консоли (`lib/quota-view.ts`, `KIND_LABELS`) — как это
 *     показано арендатору;
 *  C. словарь подписей сущностей (`lib/entity-names.ts`) — как тот же ресурс
 *     назван в меню, крошке, шапке карточки и сигнале об исходе мутации.
 *
 * У каждой полосы был свой гейт, и каждый был зелёным: #1605 держит, что дом
 * словаря B один и что отказ ходит именно в него; #1609/#1610 держат, что ни
 * один литерал консоли не называет сущность мимо C. Ни один не сравнивал B с C,
 * и расхождение приземлилось молча — ровно тот класс, о котором
 * `architecture.md` §«Параллельные полосы одного механизма обязаны сверяться
 * МЕЖДУ СОБОЙ»: обе полосы валидны по отдельности, неверна их РАЗНИЦА, и
 * решал её не человек, а случай.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЛОСА A СНЯТА (2026-09): служба доступа вынесена отдельным продуктом
 *
 * `services/iam/` в этом дереве не осталось ни одним файлом, и `countableKinds`
 * уехал с ней же. Другого производителя закрытого каталога видов в дереве
 * нет: контракт (`identity_quota_service.proto` и соседи) объявляет ТИП
 * носителя, а не роспись видов по нему, и вывести из него, какой вид
 * существует и как он называется, нельзя. Сравнивать B с A стало не с чем —
 * ровно тот же класс и то же решение, что уже применено в этом дереве для
 * того же расставания: `internal/repohygiene/nestedquotasuitereclaim_test.go`
 * снял двустороннюю сверку с этим же каталогом и оставил её НЕЗАМЕНЁННОЙ, а не
 * подменённой выдумкой.
 *
 * ЧТО ЭТИМ ПОТЕРЯНО — названо, а не заглажено: статическая сверка «каждый вид
 * каталога владельца назван на витрине» (B⊇A) и «у каждой подписи витрины есть
 * вид на сервере» (B⊆A) не держится больше НИЧЕМ в этом дереве. Разбор
 * `countableKinds` (`kindsInCatalogue`) снят вместе с ними — читать источник,
 * которого нет, гейту незачем.
 *
 * ЧТО ОСТАЁТСЯ ДЕРЖАТЬ — И ГДЕ ГРАНИЦА ЭТОГО.
 *
 * Здесь стояло, что B⊇A «держится ЖИВЫМ каталогом, а не его копией в дереве»:
 * сквозная проба браузером спрашивает всех владеющих доменов и требует, чтобы
 * ни одно названное ими машинное имя не дошло до экрана. Как ДЕЙСТВУЮЩАЯ
 * гарантия это неверно, и цена неверности не в устаревшей строке: следующий,
 * кто сошлётся сюда, ослабляя утверждение ниже, будет прав по тексту и неправ
 * по факту. Тем же изменением, которым сверка делегировалась пробе, пять
 * потребителей объявили домен величин отсутствующим (#2596).
 *
 * Проба (`e2e/specs/quotas.spec.ts`, кейс «витрина квот называет ресурс словом
 * консоли, а не ключом каталога») держит НА ЛЮБОЙ посадке одно: владеющих
 * доменов спрошены ВСЕ пятеро, и наблюдённый набор сверен с выписанным в обе
 * стороны — пропавший владелец и появившийся шестой краснеют оба. Это
 * ПРЕДПОСЫЛКА B⊇A, без которой набор видов оказался бы у́же экрана, а не сама
 * сверка.
 *
 * Самой сверки на посадке `not-deployed` нет, и это BY CONSTRUCTION, а не
 * недосмотр пробы. Виды приходят ТОЛЬКО из успешного ответа: в
 * `quota-showcase.ts` `kinds` заполняет единственная ветвь `status === 200`, —
 * а посадка «домена величин нет» устанавливается ровно тогда, когда успехом не
 * ответил НИ ОДИН владелец. Значит край не назвал ни одного вида, и «машинное
 * имя не дошло до экрана» истинно на ПУСТОМ множестве. Независимость пробы от
 * `services/iam/` — она читает ответ стенда, а не Go-исходник — тут и есть
 * причина, а не возражение: живой каталог отвечает то, что объявила посадка.
 *
 * ИТОГО, ЧТОБЫ НЕ ПЕРЕЧИТЫВАТЬ: B⊇A держится на посадке с РАЗВЁРНУТЫМ доменом
 * величин, где проба отдельно утверждает и непустоту набора видов, и что
 * витрина отрисована и называет ресурс по-русски («Облачные сети») — без такой
 * пары отрицание зеленело бы на пустом экране. И не держится больше НИЧЕМ,
 * пока ни одна установка домен величин не объявила. Разбор долга и ВНЕШНИЙ
 * предикат возврата стоят в шапке самого кейса, §«ОТКРЫТЫЙ ДОЛГ: НА ПОСАДКЕ
 * БЕЗ ДОМЕНА ВЕЛИЧИН…»; сюда они не копируются — третьей редакции одного долга
 * в дереве не заводится.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО УТВЕРЖДАЕТСЯ ЗДЕСЬ ТЕПЕРЬ — ТРИ РАЗНЫЕ ВЕЩИ, НИ ОДНА НЕ ВЫВОДИТСЯ ИЗ ДРУГОЙ
 *
 *  1. КАЖДЫЙ ПОКАЗАННЫЙ вид самосогласован: у него есть запись в `KIND_ENTITY`
 *     (вид не заводится в витрине молча) — сверка со СВОИМ же перечнем видов,
 *     не с каталогом владельца, которого больше не прочитать.
 *  2. B = C по слову — там, где у вида есть сущность в консоли, подпись взята
 *     из словаря дословно (вложенный вид — словарное слово плюс уточнение).
 *  3. B без машинных слов — ни одна подпись не содержит точечного имени вида.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ СВЕРКА, А НЕ ВЫВОД ПОДПИСИ ИЗ СЛОВАРЯ
 *
 * Вывод был бы сильнее (расхождение невозможно by construction) и отвергнут по
 * той же причине, что и раньше: не у каждого вида есть сущность в консоли —
 * удостоверения принципала показываются панелью, а не разделом, и ресурсом
 * реестра не являются; вывод потребовал бы завести сущность ради подписи.
 * Гейт #1605 требует, чтобы отображение «вид → русская подпись» существовало
 * объектным литералом в единственном доме и проверяет ЕГО ЖЕ непустоту; вывод
 * оставил бы там латинские значения и обесценил бы соседний гейт. Сверка
 * дешевле и не трогает уже посаженный контроль.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ГРАНИЦА НАЗВАНА ЧЕСТНО
 *
 * Гейт судит ОБЪЯВЛЕНИЯ двух файлов консоли (`quota-view.ts`, `entity-names.ts`),
 * а не отрисованный экран и не каталог владельца. Что арендатор действительно
 * читает на витрине, и называет ли витрина то, что владельцы действительно
 * вернули, — предмет сквозной пробы браузером (см. выше, `ui.md` правило 12).
 */

/**
 * Вид → сущность консоли, которой он считает штуки. `null` — сущности НЕТ, и это
 * решение, а не пропуск: причина названа строкой рядом.
 *
 * Перечень обязан покрывать ВИТРИНУ ЦЕЛИКОМ (`KNOWN_KINDS`) — вид без записи
 * роняет гейт, поэтому завести вид молча нельзя. Запись `null` САМОИСТЕКАЕТ —
 * заведут сущность с этим ключом, и утверждение ниже потребует объяснить,
 * почему подпись не из словаря.
 *
 * ПОКРЫТИЕ СУЖЕНО (2026-09) с закрытого каталога владельца до собственной
 * витрины: множество ключей здесь равно `KNOWN_KINDS` побайтово (перепроверено
 * на момент сужения), поэтому находок сужение не дало и не спрятало —
 * см. шапку файла.
 */
const KIND_ENTITY: Record<string, EntityKey | null> = {
  "vpc.network": "networks",
  "vpc.subnet": "subnets",
  "vpc.address": "addresses",
  "vpc.networkInterface": "network-interfaces",
  "vpc.securityGroup": "security-groups",
  "vpc.routeTable": "route-tables",
  "vpc.gateway": "gateways",
  "vpc.cidrGroup": "cidr-groups",
  "vpc.network.subnet": "subnets",
  "vpc.network.routeTable": "route-tables",
  "vpc.network.securityGroup": "security-groups",
  "iam.account": "accounts",
  // Удостоверение принципала разделом консоли не является: его показывает панель
  // на карточке пользователя и сервисного аккаунта, у него нет ни сегмента
  // адреса, ни записи реестра ресурсов — то есть нет и ключа словаря подписей.
  // Слово берётся у той же панели, которая его показывает («Создать токен»,
  // «Токен создан»), а не изобретается здесь.
  "iam.user.credential": null,
  "iam.serviceAccount.credential": null,
  "compute.instance": "instances",
  "compute.guestAccessKey": "guest-access-keys",
  "compute.placementGroup": "placement-groups",
  "storage.volumes": "volumes",
  "storage.snapshots": "snapshots",
  "storage.images": "images",
  "loadbalancer.networkLoadBalancers": "load-balancers",
  "loadbalancer.targetGroups": "target-groups",
  "loadbalancer.listeners": "listeners",
  "loadbalancer.networkLoadBalancers.listeners": "listeners",
  "registry.registries": "registries",
  "registry.repositories": "repositories",
  "registry.registries.repositories": "repositories",
};

/** Машинное имя вида: два и более сегмента через точку, латиницей. */
const MACHINE_NAME = /[a-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)+/;

/** Вложенный вид — три и более сегмента; его подпись несёт уточнение носителя. */
const isNested = (kind: string): boolean => kind.split(".").length >= 3;

const shown = [...KNOWN_KINDS];

process.stdout.write(
  `\n  словарь видов квот: на витрине ${shown.length}, ` +
    `сущностей в словаре подписей ${Object.keys(ENTITIES).length}, ` +
    `соответствий объявлено ${Object.keys(KIND_ENTITY).length} ` +
    `(из них «сущности нет» ${Object.values(KIND_ENTITY).filter((v) => v === null).length})\n\n`,
);

describe("витрина квот называет ресурс словом продукта (#1703)", () => {
  it("перепись непуста: пустой обход — отказ, а не зелёное", () => {
    // «Ноль находок» обязано быть отличимо от «ноль прочитанного». Опустел
    // словарь витрины или словарь подписей — здесь это отказ.
    expect(shown.length).toBeGreaterThan(0);
    expect(Object.keys(ENTITIES).length).toBeGreaterThan(0);
  });

  it("соответствие объявлено для каждого показанного вида — вид не заводится молча", () => {
    // Было сверкой с каталогом владельца (B⊇KIND_ENTITY-domain); каталог
    // больше не прочитать (шапка файла), поэтому проверяется самосогласие
    // витрины: KIND_ENTITY обязан знать про КАЖДЫЙ вид, который витрина
    // показывает, — иначе `kindLabel` рядом молча зависел бы от записи,
    // которой нет.
    expect(shown.filter((k) => !(k in KIND_ENTITY))).toEqual([]);
  });

  it("«сущности нет» истекает само: появился ключ в словаре — запись стала находкой", () => {
    const stale = Object.entries(KIND_ENTITY)
      .filter(([kind, key]) => key === null && (kind.split(".").at(-1) ?? "") in ENTITIES)
      .map(([kind]) => kind);
    expect(stale).toEqual([]);
  });

  it("подпись взята из словаря сущностей дословно", () => {
    const wrong: string[] = [];
    for (const kind of shown) {
      const key = KIND_ENTITY[kind];
      if (key == null) continue;
      const dictionary = ENTITIES[key].plural;
      const label = kindLabel(kind);
      const ok = isNested(kind) ? label.startsWith(`${dictionary} `) : label === dictionary;
      if (!ok) wrong.push(`${kind}: витрина «${label}» · словарь «${dictionary}»`);
    }
    expect(wrong).toEqual([]);
  });

  it("ни одна подпись не показывает машинное имя вида", () => {
    // Положительный контроль к утверждению выше: подпись, СОВПАВШАЯ со словарём,
    // ещё не доказывает, что словарь не пуст, а подпись у вида без сущности не
    // проверяется первым утверждением вовсе — её держит только это.
    expect(shown.filter((k) => MACHINE_NAME.test(kindLabel(k)))).toEqual([]);
  });

  it("незнакомый вид по-прежнему назван своим именем — каталог растёт на сервере", () => {
    // Утверждения выше не должны превратить страховку в запрет: вид, заведённый
    // на сервере позже консоли, обязан быть показан, а не спрятан.
    expect(kindLabel("future.widget")).toBe("future.widget");
  });
});
