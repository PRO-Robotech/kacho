// Типы ПРОВОДА платформы объявлены один раз — и объявляет их не модуль.
// Правило по ВСЕМУ дереву консоли.
//
// ПРЕДМЕТ. Конверт операции (`Operation`/`OperationList`), дескриптор зависимости
// (`Referrer`), ссылка на чужой ресурс — форма ПЛАТФОРМЫ, а не домена: их несёт
// каждый сервис, и меняются они вместе с контрактом платформы. Пока модуль
// объявляет их СВОЕЙ копией, поле, добавленное в общий конверт, до этого домена
// не доезжает вовсе. Класс тихий by construction: копия компилируется,
// структурно совпадает и потому молчит — расхождение начинается в тот день,
// когда общий конверт что-нибудь приобретает, и первым его увидит не
// разработчик, а пользователь.
//
// ПОЧЕМУ ПРАВИЛО ПО ДЕРЕВУ, А НЕ У МОДУЛЯ. Первым его получил compute, и проба
// завелась в модуле — по своей координате, для своего каталога. Предмет при этом
// один на всё дерево: контракт провода общий, и модуль, заведённый завтра,
// обязан попасть под правило сам, а не ждать, пока кто-нибудь напишет ему
// собственную пробу. Перечень модулей ВЫВОДИТСЯ обходом (`discoverApps`), а не
// выписывается: выписанный разошёлся бы с деревом молча.
//
// НАБЛЮДАЛОСЬ. На день заведения правила конверт был задвоен у `nlb` и
// `registry` — байт-в-байт копия `Operation`/`OperationList` в `api/types.ts`
// каждого (#408, #409). У `storage` тот же файл уже брал их ре-экспортом, у
// `compute` — тоже: то есть три модуля из четырёх пришли к общему по одному, и
// четвёртый отставал бы ровно до тех пор, пока кто-нибудь не заметил.
//
// ГРАНИЦА НАЗВАНА ЧЕСТНО. Судится ровно поверхность `shared/src/api/types.ts`.
// Доменные типы модуля (`Instance`, `NetworkLoadBalancer`, `Registry`, `Volume`)
// общим не объявлены, под правило не подпадают, и списка исключений у него нет
// вовсе: послаблению нечего было бы истекать. Законный близнец ниже это и
// утверждает — иначе «ноль находок» получалось бы из пустого обхода.

import path from "node:path";
import { fileURLToPath } from "node:url";

import { envelopeCensus } from "./platform-envelope";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const census = envelopeCensus(repoRoot);

describe("типы провода платформы объявлены один раз — по всему дереву", () => {
  it(`перепись: приложений ${census.apps.length}, файлов прочитано ${census.filesRead}, символов платформы ${census.platformSymbols.length}`, () => {
    // «Ноль находок» обязано быть отличимо от «ноль прочитанного»: сдвинутый
    // корень или переименованная раскладка иначе делают утверждение ниже
    // вакуумно истинным, не покраснев ни на чём.
    expect(census.apps.length).toBeGreaterThan(0);
    expect(census.filesRead).toBeGreaterThan(0);
    expect(census.platformSymbols.length).toBeGreaterThan(0);
    // Известные потребители закреплены, чтобы регрессия обнаружения не сузила
    // обход незаметно; перечисление при этом идёт по факту наличия `src/`, и
    // приложение, заведённое завтра, попадёт под правило само.
    expect(census.apps).toEqual(
      expect.arrayContaining(["compute", "iam", "nlb", "registry", "storage", "vpc"]),
    );
  });

  it("своя предпосылка: распознаватель узнаёт конверт в ОБЩЕМ исходнике", () => {
    // Предикат обоснован фактом о дереве — что конверт объявлен ИМЕННО такой
    // формой. Переедет он на другую (класс, генерация) — всплывёт здесь, а не
    // превратит утверждение ниже в тихий no-op.
    expect(census.platformSymbols).toEqual(
      expect.arrayContaining(["Operation", "OperationList", "Referrer"]),
    );
  });

  it("ни один модуль не объявляет заново символ платформы", () => {
    // Координаты, а не счёт: находка обязана назвать ФАЙЛ и СИМВОЛЫ, иначе её
    // нечем закрывать. Исход один — взять их ре-экспортом из `@shared/api/types`.
    expect(census.hits.map((h) => `${h.file}: ${h.symbols.join(", ")}`)).toEqual([]);
  });
});
