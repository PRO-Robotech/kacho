// Строка ДАННЫХ таблицы против строк её УСТРОЙСТВА — один источник на обе
// стороны: сквозную пробу браузера и гейт, который её предпосылку сторожит.
//
// # Предмет
//
// Тело общей таблицы всегда несёт служебные `<tr>`, в которых данных нет:
//
//   • строка обмера — рисуется, пока таблица меряет ширину столбцов; скрыта от
//     дерева доступности (`aria-hidden="true"`) и имеет нулевую высоту;
//   • строка-заполнитель — рисуется, когда набор ПУСТ, и несёт текст пустого
//     состояния, то есть текст у неё ЕСТЬ.
//
// Обе живут в том же `<tbody>`, что и строки данных. Значит счёт «строк в теле
// таблицы больше нуля» выполняется ПУСТОЙ таблицей: у неё их ровно две. Проба,
// построенная на таком положительном контроле, судит о пустой таблице — и все
// её отрицания становятся верны by construction.
//
// # Цена измерена, а не предположена (#1070)
//
// Прогон 2026-08-23: проба «в строках списка нет флажков и группового удаления»
// объявила, что у строк списка зон нет меню действий («строк 2»). Снимок
// страницы, снятый тем же отказом, показывал меню у КАЖДОЙ строки; на соседней
// ветке того же часа та же проба напечатала «строк 7, меню действий 6». Продукт
// был исправен — контроль пропустил вперёд ещё не дозагрузившуюся таблицу.
//
// # Почему это ОТДЕЛЬНЫЙ модуль, а не константа в пробе
//
// Признак нужен двоим: сквозной пробе (она им сужает локатор) и гейту (он
// доказывает, что признак вправду отделяет данные от устройства, и что
// установленная таблица эти строки помечает именно так). Пока признак жил в
// пробе, гейт брал его ЧТЕНИЕМ ЕЁ ИСХОДНИКА — то есть сверялся с текстом там,
// где заводился ради сверки с существом. Общий источник снимает и это
// противоречие, и саму возможность расхождения: копий предиката больше нет.
//
// Модуль намеренно НИЧЕГО не импортирует: его грузят два разных исполнителя —
// jsdom-харнесс консоли и транспилятор сквозных проб, — и общая зависимость
// сделала бы его непригодным одному из них.

/**
 * Признаки строк, которые тело таблицы рисует САМО.
 *
 * Первый — семантический: строку обмера таблица скрывает от дерева доступности,
 * и это её свойство, а не имя класса. Второй — по классу: заполнитель от дерева
 * доступности не скрыт (его текст адресован человеку), поэтому семантического
 * признака у него нет и быть не должно.
 *
 * Отбор идёт по УСТРОЙСТВУ строки, а не по её содержимому: у заполнителя текст
 * есть, поэтому «строка с текстом» его не отсекает.
 */
export const STRUCTURAL_BODY_ROW_MARKS = ['[aria-hidden="true"]', ".ant-table-placeholder"] as const;

/**
 * Локатор строк ДАННЫХ внутри `scope`.
 *
 * Наличие меню действий в определение строки данных не входит — иначе
 * утверждение пробы стало бы тождеством.
 */
export function dataRowSelector(scope: string): string {
  return `${scope} tbody tr` + STRUCTURAL_BODY_ROW_MARKS.map((mark) => `:not(${mark})`).join("");
}

/**
 * Числа о теле таблицы, снятые ОДНИМ обходом DOM.
 *
 * `settled` — таблица не в состоянии загрузки. Признак СЕМАНТИЧЕСКИЙ
 * (`aria-busy` над самой таблицей), а не по имени класса: имя переживёт свой
 * предмет молча.
 */
export type BodyCensus = {
  settled: boolean;
  dataRows: number;
  bodyRows: number;
  menus: number;
  checkboxes: number;
};

/**
 * Перепись тела таблицы — ВСЕ числа с одного состояния DOM.
 *
 * # Предмет (#2237)
 *
 * Сквозная проба «в строках списка нет флажков и группового удаления» снимала
 * строки данных, строки тела и меню ТРЕМЯ отдельными обращениями к странице, а
 * положительный контроль — четвёртым, ещё раньше. Числа сравнивались между
 * собой, хотя относились к РАЗНЫМ моментам одной страницы.
 *
 * Прогон 34142361500 дал отказ, противоречащий сам себе: «строк данных 0, меню
 * 48 (всего строк в теле таблицы 49)». Снимок DOM того же отказа показывал 48
 * строк без единого служебного признака — продукт был исправен, а между
 * контролем и утверждением список успел уйти в состояние загрузки.
 *
 * # Почему функция живёт ЗДЕСЬ, а не в самой пробе
 *
 * Её исполняют ДВА разных мира, и оба должны получить одно и то же:
 *
 *   • браузер — `page.evaluate(censusOfBody, …)` сериализует функцию и
 *     исполняет её В СТРАНИЦЕ синхронно; перерисоваться между её строками
 *     нечему by construction;
 *   • jsdom — гейт рядом с этим модулем подаёт ей синтетическое тело и
 *     доказывает, что противоречивой тройки она не даёт ни при каком порядке
 *     подмен, тогда как четыре отдельных чтения дают её ровно ту же.
 *
 * Копия предиката в пробе разошлась бы с гейтом молча — обе отвечают одинаково
 * на исправном дереве.
 *
 * # Ограничение, наложенное сериализацией
 *
 * Функция НЕ ДОЛЖНА ссылаться ни на что за пределами своих параметров:
 * `page.evaluate` переносит в страницу её текст, а не замыкание. Поэтому оба
 * селектора приходят аргументом, а не берутся из констант модуля.
 */
export function censusOfBody(arg: { scope: string; dataSelector: string }): BodyCensus {
  const root = document.querySelector(arg.scope);
  // Занятой считается ТА область, что накрывает саму таблицу: «где угодно в
  // консоли крутится спиннер» сделало бы признак вечно ложным из-за соседнего
  // виджета, и проба краснела бы там, где список давно готов. Признак опять
  // семантический плюс структурный — ни одного имени класса.
  const busyOverTable =
    root !== null &&
    Array.prototype.some.call(
      root.querySelectorAll('[aria-busy="true"]'),
      (el: Element) => el.querySelector("tbody") !== null,
    );
  return {
    settled: root !== null && !busyOverTable,
    dataRows: document.querySelectorAll(arg.dataSelector).length,
    bodyRows: document.querySelectorAll(`${arg.scope} tbody tr`).length,
    menus: document.querySelectorAll(`${arg.scope} tbody .anticon-more`).length,
    checkboxes: document.querySelectorAll(`${arg.scope} tbody input[type="checkbox"]`).length,
  };
}
