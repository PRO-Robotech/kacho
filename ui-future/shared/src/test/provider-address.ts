/**
 * Распознаватель адреса ЧУЖОГО поставщика личности — ОДИН на обе переписи
 * приёмки F8: перепись обращений страниц в сквозном наборе (Р6 п. 2) и
 * статическую перепись узлов разбора (F8-37, F8-43). Два распознавателя одного
 * предмета разошлись бы молча — и отрицание одной переписи перестало бы
 * значить то же, что у другой.
 *
 * Формы — ВСЕ, в которых дерево консоли этот адрес выпускало: путь под `/.ory/`
 * и под `/oauth2` (в том числе с происхождением) и поверхность потоков
 * поставщика — `/self-service/…` и `/sessions/whoami` — при любой базе и на
 * любом происхождении: база переопределялась при сборке, и распознаватель,
 * знающий одну её запись, промолчал бы на другой.
 *
 * Модуль без зависимостей намеренно: его импортирует и набор сквозных проб,
 * у которого своего `typescript`-разбора консоли нет.
 */
export function isProviderAddressText(text: string): boolean {
  if (/\/self-service\//.test(text) || /\/sessions\/whoami/.test(text)) return true;
  let pathPart = text.trim();
  const origin = /^[a-z][a-z0-9+.-]*:\/\/[^/]*/i.exec(pathPart);
  if (origin) pathPart = pathPart.slice(origin[0].length);
  return /^\/(\.ory|oauth2)(\/|$|\?)/.test(pathPart);
}
