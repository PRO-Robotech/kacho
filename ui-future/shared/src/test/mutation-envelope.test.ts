// Конверт мутации объявлен ОДИН раз — и объявляет его не домен.
//
// ПРЕДМЕТ. Пять глаголов платформы над одним базовым путём ресурса —
// `list`/`get`/`create`/`update`/`delete` — это форма ПЛАТФОРМЫ: список читается
// с фильтром, чтение и мутации адресуются `<путь>/<id>`, мутация возвращает
// `{ operation }`. Домен даёт только базовый путь и тип страницы, и больше
// ничего. Пока каждый модуль пишет эти пять строк сам, всякое изменение формы —
// кодирование идентификатора в адресе, ключ идемпотентности на мутации, единый
// разбор страницы — правится в стольких местах, сколько ресурсов у консоли, и
// доезжает не всюду. Класс тихий: копия компилируется и структурно совпадает,
// расхождение начинается в день первой правки.
//
// ЧТО ОСТАЁТСЯ ДОМЕНУ и правилом НЕ задето: суффикс-действия (`:start`/`:stop`,
// `:attachDisk`, `:copy`, `:changeDiskType`, `:add-cidr-blocks`) и адресация
// вложенных ресурсов (репозитории и теги реестра живут ПОД реестром). Ни то, ни
// другое общим не выражается — у них разные тела, разные пути и разное число
// координат. Правило судит ровно ПЯТЁРКУ над одним путём, и объект, добавивший
// к фабрике свои глаголы, под него не подпадает by construction: пять имён
// приходят в него распаковкой, а не собственными свойствами.
//
// НАБЛЮДАЛОСЬ. На день заведения правила пятёрка была выписана восемь раз —
// у `compute` (инстансы), `storage` (тома, снимки, образы), `nlb`
// (балансировщики, обработчики, целевые группы) и `registry` (реестры), — и все
// восемь были дословно одинаковы.
//
// РАЗБОР, А НЕ ПОИСК ПО ОБРАЗЦУ: имена глаголов встречаются в прозе и в строках,
// и текстовый предикат нашёл бы их в этом самом абзаце.
//
// ПЕРЕЧЕНЬ МОДУЛЕЙ ВЫВОДИТСЯ обходом, а не выписывается.

import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { mutationEnvelopeCensus, scanEnvelopes } from "./mutation-envelope";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const census = mutationEnvelopeCensus(repoRoot);
const FACTORY = path.join(repoRoot, "shared/src/api/resources.ts");

describe("конверт мутации объявлен один раз — по всему дереву", () => {
  it(`перепись: приложений ${census.apps.length}, файлов прочитано ${census.filesRead}, литералов осмотрено ${census.literalsSeen}`, () => {
    // «Ноль находок» обязано быть отличимо от «ноль прочитанного»: сдвинутый
    // корень или переименованная раскладка иначе делают утверждение ниже
    // вакуумно истинным, не покраснев ни на чём.
    expect(census.apps.length).toBeGreaterThan(0);
    expect(census.filesRead).toBeGreaterThan(0);
    expect(census.literalsSeen).toBeGreaterThan(0);
    expect(census.apps).toEqual(
      expect.arrayContaining(["compute", "iam", "nlb", "registry", "storage", "vpc"]),
    );
  });

  it("своя предпосылка: распознаватель узнаёт конверт в ОБЩЕЙ фабрике", () => {
    // Положительный контроль на настоящем коде дерева, а не на синтетике: если
    // распознаватель перестанет узнавать пятёрку (переезд на класс, на
    // генерацию, на вычисляемые имена свойств), это всплывёт ЗДЕСЬ, а не
    // превратит отрицание ниже в тихий no-op.
    const scan = scanEnvelopes(readFileSync(FACTORY, "utf8"), FACTORY);
    expect(scan.lines.length).toBe(1);
    expect(scan.literals).toBeGreaterThan(1);
  });

  it("ни один модуль не объявляет конверт мутации сам", () => {
    // Координаты, а не счёт: находка обязана назвать файл и строку. Исход один —
    // взять пятёрку фабрикой `resourceApi` из `@shared/api/resources` и добавить
    // к ней свои глаголы распаковкой.
    expect(census.hits).toEqual([]);
  });
});
