import path from "node:path";
import { fileURLToPath } from "node:url";

import { walkCeremonyCarriers } from "./identity-ceremony-carriers";

/**
 * Гейт полосы личности: носитель, ГОВОРЯЩИЙ с поставщиком личности по его
 * протоколу и экспортирующий компонент, обязан быть отрендерен продуктом.
 *
 * ЗАЧЕМ. Адреса церемоний — `/login`, `/registration`, `/recovery`,
 * `/settings`, `/logout` — раздача отдаёт ВНЕШНЕМУ поставщику безусловно
 * (`ui-future/deploy/templates/configmap-nginx.yaml`, полоса потоков → upstream
 * `kratosUi`). Собственная страница той же церемонии, лежащая рядом и не
 * смонтированная ничем, читается следующим как действующая часть продукта: два
 * способа выглядят равноправными, хотя работает один.
 *
 * Это уже стоило каталога из семи страниц (#1225): маршрутов в дереве было 162,
 * монтирующих эти страницы — ноль, а единственный `<Route>` на страницу
 * параметров жил ВНУТРИ пробы. В графе импортов они при этом выглядели
 * достижимыми — через барель `export * from "./auth"`.
 *
 * ЧТО ЭТОТ ГЕЙТ НЕ ЛОВИТ — названо, а не умолчано:
 *   • носитель, который церемонию НЕ ведёт, а лишь отсылает к поставщику
 *     (страница приветствия, посадка обратного перехода): протокола он не
 *     импортирует и в перепись не попадает. Такой снимается по общему правилу
 *     мёртвого кода, а не этим гейтом;
 *   • мёртвый код `shared` вообще — отдельный предмет, названный шапкой
 *     `module-reachability.test.ts`. Здесь закрыта его полоса личности.
 *
 * СПОСОБНОСТЬ УПАСТЬ доказана не этой зеленью, а `identity-ceremony-carriers.injection.test.ts`.
 */

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const { productFiles, carriers, rendered, orphaned } = walkCeremonyCarriers(uiRoot);

// Перепись печатается ВСЕГДА, а не только в имени пробы: штатный прогон идёт под
// `--silent`, который глушит `console.*`, и на зелёном обе величины были бы не
// видны вовсе. Прямая запись в поток `--silent` не затрагивает. Две величины, а
// не одна: «не рендерится 0» без «рендерится N» неотличимо от предиката, вовсе
// разучившегося распознавать рендер.
process.stdout.write(
  `\n[полоса личности] носителей церемонии ${carriers.length}` +
    ` · рендерится продуктом ${rendered.length}` +
    ` · НЕ рендерится ${orphaned.length}` +
    ` (прод-файлов прочитано ${productFiles.length})\n`,
);

describe("полоса личности: носитель церемонии обязан быть отрендерен", () => {
  it(
    `перепись: носителей церемонии ${carriers.length}, ` +
      `рендерится продуктом ${rendered.length}, НЕ рендерится ${orphaned.length} ` +
      `(прод-файлов прочитано ${productFiles.length})`,
    () => {
      // Перепись — отдельное утверждение, а не строка вывода: без неё «ноль
      // нерендерящихся» неотличимо от «ноль прочитанных файлов».
      expect(productFiles.length).toBeGreaterThan(100);
      expect(carriers.length).toBeGreaterThan(0);
    },
  );

  it("положительная сторона предиката жива — рендерящийся носитель существует", () => {
    // Без этого утверждение об отсутствии зеленело бы на предикате, вовсе не
    // умеющем распознать рендер: «не рендерится никто» стало бы тождеством.
    if (rendered.length === 0) {
      throw new Error(
        "ни один носитель церемонии не распознан как отрендеренный. Либо предикат " +
          "рендера сломан, либо продукт перестал рендерить окно повторного " +
          "подтверждения личности и поставщика контекста доступа. Отрицание ниже " +
          "при этом зеленеет тождественно — доверять ему нельзя",
      );
    }
  });

  it("носителя, которого не рендерит никто, в дереве нет", () => {
    if (orphaned.length > 0) {
      const detail = orphaned
        .map((c) => `      ${c.rel}   [${c.components.join(", ")}]`)
        .join("\n");
      throw new Error(
        `носителей церемонии, которых продукт не рендерит: ${orphaned.length}\n${detail}\n\n` +
          `Эти модули говорят с поставщиком личности по его протоколу и экспортируют ` +
          `компонент, но ни один маршрут и ни один узел JSX их не поднимает. Адрес ` +
          `церемонии при этом принадлежит ПОСТАВЩИКУ: раздача отдаёт полосу потоков ` +
          `наверх (ui-future/deploy/templates/configmap-nginx.yaml). Значит рядом лежат ` +
          `два способа, из которых работает один.\n\n` +
          `Действующие пути — вход: AuthContext.login → kratos.loginUrl; второй фактор ` +
          `и ключи доступа: StepUpModal → kratos.settingsUrl. Подробнее — ` +
          `shared/src/pages/auth/README.md.\n\n` +
          `Исходов два: смонтировать носитель маршрутом продукта (и тогда снять ` +
          `проксирование того же адреса — способ обязан остаться ОДИН) либо снять ` +
          `носитель вместе с его пробами`,
      );
    }
  });
});
