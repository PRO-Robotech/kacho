import path from "node:path";
import { fileURLToPath } from "node:url";

import { walkCeremonyCarriers } from "./identity-ceremony-carriers";

/**
 * Гейт полосы личности: носитель, ВЕДУЩИЙ церемонию личности и экспортирующий
 * компонент, обязан быть отрендерен продуктом.
 *
 * ЗАЧЕМ. Экран церемонии, лежащий рядом и не смонтированный ничем, читается
 * следующим как действующая часть продукта: два способа выглядят равноправными,
 * хотя работает один. Это уже стоило каталога из семи страниц (#1225): маршрутов
 * в дереве было 162, монтирующих эти страницы — ноль, а в графе импортов они
 * выглядели достижимыми — через барель `export * from "./auth"`.
 *
 * Церемонии ведёт консоль своими экранами (приёмка F8): носители — экраны
 * входа, регистрации и параметров учётной записи, окно повышения и контекст
 * личности, и все они в этой переписи. Что гейт доказывает, он говорит сам:
 * носитель ОТРИСОВАН. Что по нему МОЖНО ВОЙТИ, доказывает браузерная проба
 * (`ui-future/e2e/specs/identity-ceremony.spec.ts`), и одно не заменяет
 * другого.
 *
 * ЧТО ЭТОТ ГЕЙТ НЕ ЛОВИТ — названо, а не умолчано:
 *   • носитель, который дверь к церемонии НЕ импортирует, а лишь отсылает к
 *     экрану (страница «такого адреса здесь нет», ссылка «Войти»): в перепись он
 *     не попадает и снимается по общему правилу мёртвого кода;
 *   • мёртвый код `shared` вообще — отдельный предмет, названный шапкой
 *     `module-reachability.test.ts`. Здесь закрыта его полоса личности.
 *
 * СПОСОБНОСТЬ УПАСТЬ доказана не этой зеленью, а `identity-ceremony-carriers.injection.test.ts`.
 */

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const { productFiles, carriers, rendered, orphaned } = walkCeremonyCarriers(uiRoot);

// Перепись печатается ВСЕГДА, а не только в имени пробы: штатный прогон идёт под
// `--silent`, который глушит `console.*`, и на зелёном обе величины были бы не
// видны вовсе. Прямая запись в поток `--silent` не затрагивает. Две величины, а
// не одна: «не рендерится 0» без «рендерится N» неотличимо от предиката, вовсе
// разучившегося распознавать рендер.
process.stdout.write(
  `\n[полоса личности] носителей церемонии ${carriers.length}` +
    ` · рендерится продуктом ${rendered.length}` +
    ` · НЕ рендерится ${orphaned.length}` +
    ` (прод-файлов прочитано ${productFiles.length})\n`,
);

describe("полоса личности: носитель церемонии обязан быть отрендерен", () => {
  it(
    `перепись: носителей церемонии ${carriers.length}, ` +
      `рендерится продуктом ${rendered.length}, НЕ рендерится ${orphaned.length} ` +
      `(прод-файлов прочитано ${productFiles.length})`,
    () => {
      // Перепись — отдельное утверждение, а не строка вывода: без неё «ноль
      // нерендерящихся» неотличимо от «ноль прочитанных файлов».
      expect(productFiles.length).toBeGreaterThan(100);
      expect(carriers.length).toBeGreaterThan(0);
    },
  );

  it("положительная сторона предиката жива — рендерящийся носитель существует", () => {
    // Без этого утверждение об отсутствии зеленело бы на предикате, вовсе не
    // умеющем распознать рендер: «не рендерится никто» стало бы тождеством.
    if (rendered.length === 0) {
      throw new Error(
        "ни один носитель церемонии не распознан как отрендеренный. Либо предикат " +
          "рендера сломан, либо продукт перестал рендерить экраны церемоний, окно " +
          "повышения и поставщика контекста личности. Отрицание ниже при этом " +
          "зеленеет тождественно — доверять ему нельзя",
      );
    }
  });

  it("носителя, которого не рендерит никто, в дереве нет", () => {
    if (orphaned.length > 0) {
      const detail = orphaned
        .map((c) => `      ${c.rel}   [${c.components.join(", ")}]`)
        .join("\n");
      throw new Error(
        `носителей церемонии, которых продукт не рендерит: ${orphaned.length}\n${detail}\n\n` +
          `Эти модули ведут церемонию личности глаголами полосы формы и экспортируют ` +
          `компонент, но ни один маршрут и ни один узел JSX их не поднимает. Рядом ` +
          `лежат два способа, из которых работает один. Действующие экраны и их ` +
          `маршруты — shared/src/pages/auth/README.md.\n\n` +
          `Исходов два: смонтировать носитель маршрутом продукта либо снять его ` +
          `вместе с его пробами`,
      );
    }
  });
});
