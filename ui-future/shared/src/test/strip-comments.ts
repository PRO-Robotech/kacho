// Снятие комментариев с сохранением строковых литералов — для проб, которые
// читают ИСХОДНЫЙ ТЕКСТ дерева (TypeScript консоли и Go сервисов).
//
// Зачем это отдельный модуль, а не копия рядом с каждой пробой. Гейт обязан
// читать исполняемую часть, а не текст: имя, названное в объяснительном
// комментарии («такого маршрута больше нет», «почему это поле НЕ добавлено в
// белый список»), — это разбор, а не вызов, и падать на нём значило бы запретить
// объяснять. Предикат у всех таких проб один и тот же, поэтому и живёт он в одном
// месте: две редакции одного разборщика разошлись бы молча, а разошлись бы они
// именно там, где расхождение не видно, — оба ведь возвращают «текст» на любом
// входе.
//
// Что покрывает разбор кавычек: `"…"`, `'…'`, `` `…` `` с экранированием
// обратной косой. Порядок существен — кавычка проверяется ДО начала комментария,
// иначе `"http://…"` внутри строки читалось бы как комментарий; и наоборот,
// апострофа в комментарии (`// don't`) разборщик не увидит вовсе, потому что
// начало комментария он распознаёт первым символом. В Go одиночная кавычка
// открывает рунный литерал и всегда закрыта — то есть тем же правилом.

/** Исходник без комментариев; строковые литералы сохранены дословно. */
export function stripComments(src: string): string {
  let out = "";
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      out += c;
      i++;
      while (i < src.length) {
        if (src[i] === "\\") {
          out += src[i] + (src[i + 1] ?? "");
          i += 2;
          continue;
        }
        out += src[i];
        if (src[i] === quote) {
          i++;
          break;
        }
        i++;
      }
      continue;
    }
    if (c === "/" && src[i + 1] === "/") {
      while (i < src.length && src[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && src[i + 1] === "*") {
      i += 2;
      while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++;
      i += 2;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}
