// Файл, прощённый ДВУМЯ ведомостями сразу, не будет снят никогда — правило по
// ВСЕМУ дереву консоли.
//
// ПРЕДМЕТ. У дерева две ведомости послаблений, и каждая по отдельности честна:
//   · ведомость форков (`shared-fork-ledger.json`) прощает КОПИЮ общего кода —
//     «да, это форк, вот причина, почему он ещё жив»;
//   · ведомость достижимости (`module-reachability-ledger.json`) прощает файл,
//     до которого нет пути от входа приложения, — «да, он мёртв, вот причина».
//
// Пересечение этих двух перечней — состояние, которого не бывает по существу:
// копия общего кода, до которой вдобавок никто не доходит. Ни одного довода в
// пользу её жизни не остаётся: сводить нечего (её не зовут), провязывать нельзя
// (она отстала). При этом ОБЕ ведомости зелены — каждая видит свою половину и
// считает её объяснённой, — поэтому такой файл переживает оба послабления и
// снимается только случайно.
//
// НАБЛЮДАЛОСЬ трижды одним и тем же файлом: клиент края (229 строк, байт-в-байт
// одинаковый у трёх модулей) стоял и в ведомости форков, и в ведомости
// достижимости у `nlb`, `registry` и `storage`. Ни одного импортёра во всём
// дереве; снят вместе с записями обеих ведомостей (#1502).
//
// ПОЧЕМУ ПРАВИЛО ТУТ, А НЕ У МОДУЛЯ. Первым экземпляром класса был свой клиент
// края compute, и проба под него завелась В МОДУЛЕ, честно оговорив область:
// «класс живёт и у соседей, но их де-форк идёт своими задачами, и краснить чужую
// полосу отсюда значило бы отдать вердикт этого модуля в чужие руки». Оговорка
// была верна ровно до того дня, когда соседей починили, — и истекла вместе с
// ними. Предмет у класса ОДИН на дерево: перечни общие, живут в `shared/`, и
// модуль, заведённый завтра, обязан попасть под правило сам, а не ждать, пока
// кто-нибудь заведёт ему собственную пробу.
//
// ПЕРЕЧЕНЬ МОДУЛЕЙ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ: он берётся из самих ведомостей.
// Выписанный литералом перечень разошёлся бы с деревом молча — ровно тот класс,
// что мы ловим в коде.
//
// ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Обход импортов здесь не переписывается: достижимость
// считает `module-reachability.test.ts`, копии — `shared-organisms-single-source`,
// и второй реализации ни того, ни другого заводить нельзя. Здесь судится ровно
// СТЫК двух перечней — то, о чём ни один из них по отдельности не высказывается.
//
// САМОИСТЕЧЕНИЕ. Опустеет любой из перечней — правило останется зелёным и скажет
// об этом переписью: пустое пересечение есть ЦЕЛЬ, а не поломка. Способность
// упасть держится не этой зеленью, а инъекцией — `…injection.test.ts`.

import path from "node:path";
import { fileURLToPath } from "node:url";

import { doubleExcused } from "./fork-excused-by-two-ledgers";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const census = doubleExcused(repoRoot);

describe("ведомости послаблений не прощают один файл дважды — по всему дереву", () => {
  it(`перепись: модулей ${census.modules.length} (${census.modules.join(", ")}), прощённых копий ${census.excusedForks.length}, прощённых мёртвых ${census.excusedDead.length}`, () => {
    // Обе величины печатаются, потому что пустое пересечение получается и от
    // достигнутой цели, и от того, что перечни перестали читаться. Первое —
    // норма, второе — поломка, и различить их можно только по этим числам.
    // Требовать пересечение ненулевым НЕЛЬЗЯ: ноль здесь законная цель.
    expect(census.modules.length).toBeGreaterThan(0);
  });

  it("своя предпосылка: обе ведомости прочитаны и не пусты", () => {
    // Переедет ведомость или сменится форма ключа — всплывёт здесь, а не
    // превратит утверждение ниже в тихий no-op на двух пустых множествах.
    expect(census.forkGroups).toBeGreaterThan(0);
    expect(census.excusedForks.length).toBeGreaterThan(0);
    expect(census.excusedDead.length).toBeGreaterThan(0);
  });

  it("ключи обеих ведомостей — пути от корня дерева консоли", () => {
    // Пересечение считается по строке пути, поэтому расхождение формы ключа
    // («storage/src/…» против «./storage/src/…») сделало бы его пустым при живом
    // классе — молчание, неотличимое от достигнутой цели.
    expect(census.malformed).toEqual([]);
  });

  it("ни один файл не прощён обеими ведомостями", () => {
    // Координаты, а не счёт: находка обязана назвать ФАЙЛ, иначе её нечем
    // закрывать. Снятие — тем же порядком, каким запись заводилась: убедиться,
    // что файл недостижим, и снять его вместе с записями обеих ведомостей.
    expect(census.excusedTwice).toEqual([]);
  });
});
