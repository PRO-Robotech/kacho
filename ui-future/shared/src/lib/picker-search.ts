// Область поиска поля подбора (#528) — продолжение механизма списков (#373).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ У ПОЛЯ ПОДБОРА ЭТО ХУЖЕ, ЧЕМ У СПИСКА
//
// Список, сужающий загруженное, отвечает «отобрано среди загруженных» — и рядом
// стоят «Показать ещё» и счётчик, то есть у пользователя есть продолжение. У
// выпадающего поля продолжения нет BY CONSTRUCTION: человек видит список, не
// находит имя и заключает, что ресурса не существует. Отрицание, которое
// выглядит как факт о мире, а является фактом о прочитанной странице.
//
// Поэтому исходов два, и третьего нет:
//
//   СПРОСИТЬ СЕРВЕР — если владелец умеет сужать: ввод уезжает выражением в
//                     параметр `filter`, ответ показывается как есть;
//   СКАЗАТЬ ПРАВДУ  — если не умеет: пустой ответ обязан называть свою ОБЛАСТЬ
//                     («нет среди загруженных»), а не утверждать отсутствие.
//
// Выдумывать поле запроса нельзя: белый список выражения ведёт владелец, и
// незнакомое поле — не «фильтр без эффекта», а отказ на всю страницу.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ДВА КЛЮЧА, А НЕ ОДИН
//
// Ровно та же причина, что у `resource-spec.ts` (и тот же выбор): владельцы
// сужают РАЗНЫМИ операторами.
//
//   `serverSearchField` → `name CONTAINS "…"` — подстрока по настоящему полю
//                         ресурса (vpc, compute: `filter.Parse` + `ToSQL`);
//   `search.serverTerm` → `search="…"`        — ВЫДЕЛЕННОЕ слово запроса, которое
//                         владелец толкует сам (у пользователя имени нет вовсе,
//                         его узнают по почте; iam отвергает CONTAINS явно).
//
// Подставить одно вместо другого нельзя: iam ответит `InvalidArgument` на
// `CONTAINS`, а vpc не знает слова `search`. Оба конца — не наша выдумка:
// сходимость объявления с деревом владельца держит
// `lib/list-server-search-parity.test.ts`.

import { filterExpressionValue } from "@shared/lib/list-search";
import { searchFilterExpression } from "@shared/lib/list-search-filter";

/** Чем ресурс умеет сужаться у своего владельца. Оба ключа пусты — не умеет. */
export interface PickerSearchSource {
  /** настоящее поле ресурса; ввод уезжает как `<поле> CONTAINS "…"` */
  serverSearchField?: string;
  /** выделенное слово запроса; ввод уезжает как `<слово>="…"` */
  serverTerm?: string;
}

export interface PickerScope {
  /** спрашивает ли ввод сервер */
  asksServer: boolean;
  /** параметры запроса для введённого; пустой объект — добавлять нечего */
  query(term: string): Record<string, string>;
  /** правда об области: что именно сузит ввод. Идёт в подсказку поля */
  notice: string;
  /** что стоит на месте пустого ответа. Здесь и живёт ложь, если её не убрать */
  emptyText: string;
}

/**
 * `Ничего не найдено` законно ТОЛЬКО когда спрошен сервер: тогда это
 * утверждение о списке. В любом другом случае оно утверждает то, чего проба не
 * измеряла.
 */
export const PICKER_EMPTY_SERVER = "Ничего не найдено — искали по всему списку";
export const PICKER_EMPTY_LOADED = "Нет среди загруженных вариантов";

export const PICKER_NOTICE_SERVER = "Ввод уходит запросом: ищется по всему списку, а не среди загруженных вариантов.";

/**
 * Подпись поля, которое сужает загруженное.
 *
 * Она говорит, ЧТО СУЗИЛОСЬ, и молчит о причине. Прежняя редакция утверждала
 * «этот ресурс не умеет искать на сервере» — и была неправдой на двух из
 * восемнадцати поверхностей: у их владельцев сужение есть, а поле его не
 * спрашивает (дерево-каскад теряет предков совпавшего; страница выпуска ключей
 * получает список функцией без параметра запроса). Причина, названная неверно,
 * — тот же класс, что и весь #528, только на нашей стороне: следующий читатель
 * пойдёт заводить владельцу поиск, который у него уже есть.
 */
export const PICKER_NOTICE_LOADED =
  "Сужаются только уже загруженные варианты. Пустой ответ здесь означает " +
  "«нет среди загруженных», а не «не существует».";

/**
 * Область поиска поля подбора.
 *
 * `serverTerm` выигрывает у `serverSearchField`, если объявлены оба, — тем же
 * разрешением, что у строки поиска списка: выделенное слово владелец толкует
 * сам, и оно строго специфичнее подстроки по полю. Полагаться на это разрешение
 * не надо (объявлять оба запрещено), но детерминированным оно быть обязано:
 * иначе одно и то же поле искало бы по-разному в зависимости от порядка ветвей.
 */
export function pickerScope(source: PickerSearchSource | undefined): PickerScope {
  const term = source?.serverTerm;
  const field = source?.serverSearchField;

  if (term) {
    return {
      asksServer: true,
      query: (raw): Record<string, string> => {
        const v = filterExpressionValue(raw);
        return v ? { filter: `${term}="${v}"` } : {};
      },
      notice: PICKER_NOTICE_SERVER,
      emptyText: PICKER_EMPTY_SERVER,
    };
  }

  if (field) {
    return {
      asksServer: true,
      query: (raw): Record<string, string> => {
        const expr = searchFilterExpression(field, raw);
        return expr ? { filter: expr } : {};
      },
      notice: PICKER_NOTICE_SERVER,
      emptyText: PICKER_EMPTY_SERVER,
    };
  }

  return {
    asksServer: false,
    query: () => ({}),
    notice: PICKER_NOTICE_LOADED,
    emptyText: PICKER_EMPTY_LOADED,
  };
}

/**
 * То же по объявлению ресурса. Отдельная функция, а не разбор `ResourceSpec` в
 * каждом поле: два места, читающие одно объявление, разошлись бы молча — и
 * разошлись бы именно там, где расхождение не видно (оба ведь возвращают
 * «область» на любом входе).
 */
export function pickerScopeOfSpec(
  spec: { serverSearchField?: string; search?: { serverTerm?: string } } | undefined,
): PickerScope {
  return pickerScope({ serverSearchField: spec?.serverSearchField, serverTerm: spec?.search?.serverTerm });
}
