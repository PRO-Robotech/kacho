// Размер в байтах — ОДНО объявление на всю консоль.
//
// Предмет. `formatBytes` жил тремя байт-в-байт копиями (`compute`, `storage`,
// `registry`; один и тот же md5), у общего модуля дома не имел вовсе, и НИ ОДНА
// из копий не была покрыта пробой. Для переписи форков он был невидим сразу по
// обеим осям: символа `formatBytes` общий модуль не объявлял (ось имени молчит),
// файла `shared/src/lib/bytes.ts` не существовало (ось адреса молчит). То есть
// расхождение трёх копий не заметил бы никто — ни гейт, ни поиск по имени.
//
// Утверждается КОНТРАКТ, который копии объявляли комментарием и не проверяли
// ничем: строка с wire (proto3 int64 сериализуется строкой), «нет значения» и
// «ноль» отдельно от «0 B», и сама лестница единиц.

import { formatBytes } from "./bytes";

describe("formatBytes", () => {
  it("байты показываются целыми, без десятичной части", () => {
    // Разряд байт дробной части не имеет: «512.0 B» сообщал бы о точности,
    // которой у целого числа байт нет.
    expect(formatBytes(512)).toBe("512 B");
    expect(formatBytes(1023)).toBe("1023 B");
  });

  it("лестница единиц — на каждом разряде свой рубеж", () => {
    expect(formatBytes(1024)).toBe("1.0 KB");
    expect(formatBytes(1024 ** 2)).toBe("1.0 MB");
    expect(formatBytes(1024 ** 3)).toBe("1.0 GB");
    expect(formatBytes(1024 ** 4)).toBe("1.0 TB");
  });

  it("выше последней единицы лестница НЕ продолжается — растёт число", () => {
    // Иначе появился бы разряд, которого в списке нет, и вместо величины
    // пользователь увидел бы `undefined`.
    expect(formatBytes(1024 ** 5)).toBe("1024.0 TB");
  });

  it("число, пришедшее СТРОКОЙ, читается как число", () => {
    // int64 на wire сериализуется строкой. Без разбора строка ушла бы в
    // сравнение с 1024 как строка, и лестница молча встала бы на первом разряде.
    expect(formatBytes("1048576")).toBe("1.0 MB");
  });

  it("отсутствие значения и ноль — прочерк, а НИКОГДА не «0 B»", () => {
    // «0 B» — утверждение о размере ресурса; сервер его не делал. Это тот же
    // класс, что прочерк у булева поля: пустое обязано означать «пусто».
    for (const v of [undefined, null, "", 0, "0", -1, "не число", Number.NaN, {}, []]) {
      expect(formatBytes(v)).toBe("—");
    }
  });

  it("положительный контроль к предыдущему: настоящий размер прочерком НЕ становится", () => {
    // Без этой пары отрицание выше зеленело бы на реализации, возвращающей
    // прочерк всегда.
    expect(formatBytes(1)).toBe("1 B");
  });
});
