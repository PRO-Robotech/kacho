/**
 * Свободен ли адрес для привязки — один ответ на весь продукт.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ
 *
 * Списки выбора адреса есть в двух формах интерфейса — создания и правки, — и
 * ответ в них РАЗНЫЙ по одной причине: при правке адрес, уже привязанный к
 * этому же интерфейсу, тоже помечен занятым, и скрыв его, форма потеряла бы
 * собственное текущее значение. Разница ровно в этом, и она обязана быть
 * названа в одном месте, а не повторена двумя фильтрами, которые разойдутся.
 *
 * Занятость адрес сообщает сам — полем `used` (`vpc/v1/address.proto`, тег 16).
 * Читаются обе проекции имени: край отдаёт camelCase, домен объявляет
 * snake_case — это две ЖИВЫЕ формы одного поля, а не запасная ветка на снятое
 * имя.
 *
 * ПОЧЕМУ СКРЫВАТЬ, А НЕ ПОКАЗЫВАТЬ ОТКЛЮЧЁННЫМ. Отключённый пункт отвечает на
 * вопрос «почему нельзя» тому, кто ищет конкретный адрес. Здесь же выбирают
 * ЛЮБОЙ подходящий, и негодные среди годных заставляют перебирать. Тому, кому
 * нужен занятый адрес, его освобождают на карточке адреса — там занятость
 * названа прямо, вместе с тем, кто её держит.
 *
 * Что было до этого: список предлагал все адреса подсети, включая привязанные к
 * другому интерфейсу. Выбор проходил форму целиком и умирал на крае — «address
 * adr… is already in use». Консоль звала сделать то, что край отвергает by
 * construction, и узнать об этом можно было только отправкой.
 */
export function addressIsFree(row: Record<string, unknown>): boolean {
  return !(row.used ?? row.usedBy ?? false);
}

/**
 * Годится ли адрес для ЭТОГО интерфейса: свободен либо уже привязан к нему.
 *
 * `heldIds` — адреса, которые интерфейс держит сейчас. Без них форма правки
 * теряла бы собственное значение: оно занято — им же самим.
 */
export function addressSelectableFor(row: Record<string, unknown>, heldIds: readonly string[]): boolean {
  if (addressIsFree(row)) return true;
  const id = typeof row.id === "string" ? row.id : "";
  return id !== "" && heldIds.includes(id);
}
