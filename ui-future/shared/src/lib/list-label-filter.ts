// Отбор строк списка по МЕТКАМ — на клиенте, и это решение платформы, а не
// упущение консоли.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТБОР ПО МЕТКАМ НЕ ДЕЛАЕТ СЕРВЕР
//
// Оси подписки объявлены НЕИЗМЕНЯЕМЫМИ (`kinds` × `project` × `ids`), а метка
// мутабельна: ресурс входит в выборку и выходит из неё по правке метки. Событие
// потока предыдущего состояния не несёт, поэтому серверный отбор по меткам не
// смог бы сказать «вышел из выборки» иначе как синтетическим снятием — а
// подписчик прочитал бы его как «ресурс удалён» и показал бы человеку «сеть
// удалена» при живой сети.
//
// Отбор поэтому делает тот, у кого есть ОБА состояния: страница, которая
// перечитала список. Метка ушла — строка не прошла предикат ниже; метка
// появилась — прошла. Ни того, ни другого сервер знать не обязан.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРЕДИКАТ ЧИСТЫЙ
//
// Держи он своё состояние (запомненный набор подходящих идентификаторов), строка,
// потерявшая метку, осталась бы в списке до перезагрузки — ровно тот дефект,
// ради которого отбор и пишется. Чистая функция от строки и запроса такого
// состояния не имеет by construction.

/** Одно условие: имя метки и, если названо, её точное значение. */
export interface LabelTerm {
  key: string;
  /** `undefined` — «метка есть, значение любое». */
  value?: string;
}

/**
 * Разобрать строку запроса в условия.
 *
 * Форма: `ключ` либо `ключ=значение`, несколько — через пробел, соединяются
 * КОНЪЮНКЦИЕЙ (как оси подписки: заданное сужает вместе, незаданное не сужает
 * ничем).
 *
 * `ключ` и `ключ=` — РАЗНЫЕ вопросы: первый спрашивает метку с любым значением,
 * второй — метку с пустым. Свести их значило бы сделать один из двух
 * незадаваемым.
 *
 * Знак равенства внутри значения законен (`url=a=b`): режем по ПЕРВОМУ.
 */
export function parseLabelQuery(raw: string): LabelTerm[] {
  return raw
    .split(/\s+/)
    .map((t) => t.trim())
    .filter((t) => t.length > 0)
    .map((token) => {
      const at = token.indexOf("=");
      if (at < 0) return { key: token };
      return { key: token.slice(0, at), value: token.slice(at + 1) };
    })
    .filter((t) => t.key.length > 0);
}

/**
 * Сужает ли этот запрос список.
 *
 * Отдельная функция, а не `parseLabelQuery(raw).length > 0` у каждого
 * вызывающего: признак сужения выбирает, что увидит человек на пустом
 * результате — «ничего не найдено» или приглашение «создайте первый», — и
 * второе выражение того же предмета разошлось бы с первым молча (#927).
 */
export function labelFilterActive(raw: string): boolean {
  return parseLabelQuery(raw).length > 0;
}

/**
 * Строковая форма значения метки — либо `null`, «сравнивать не с чем».
 *
 * Значение приезжает из `JSON.parse`, то есть как `unknown`: в контракте метки
 * строковые, но верить в это на входе из сети нельзя. Приведение `String()`
 * поверх `unknown` давало ЛОЖНОЕ РАВЕНСТВО — у значения без осмысленной
 * строковой формы бралось умолчание языка, и разные значения становились равны.
 *
 * Достижимый случай — СПИСОК, и назвать его надо точно: `String([1, 2])` даёт
 * «1,2», пробела не содержит, значит такое условие человек набрать может — и
 * список сравнивался бы равным строке «1,2»; `String([])` даёт пустую строку и
 * попадал в условие «ключ=», означающее метку с пустым значением. Объект
 * недостижим: «[object Object]» несёт пробел, а условия режутся по пробелу.
 *
 * `null` и отсутствующее значение остаются пустой строкой — это документированный
 * вопрос «ключ=», а не следствие приведения.
 */
function labelValueAsText(value: unknown): string | null {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return null;
}

/**
 * Подходит ли строка под все условия.
 *
 * Строка приезжает из `JSON.parse`, то есть как `unknown`: `labels`, не
 * являющееся объектом, отбрасывается, а не роняет страницу. Значение
 * сравнивается как строка — метки в контракте строковые, но верить в это на
 * входе из сети нельзя.
 */
export function rowMatchesLabels(row: unknown, terms: readonly LabelTerm[]): boolean {
  if (terms.length === 0) return true;
  const labels = (row as { labels?: unknown } | null | undefined)?.labels;
  if (labels === null || typeof labels !== "object" || Array.isArray(labels)) return false;
  const map = labels as Record<string, unknown>;
  return terms.every((term) => {
    if (!Object.prototype.hasOwnProperty.call(map, term.key)) return false;
    if (term.value === undefined) return true;
    const text = labelValueAsText(map[term.key]);
    return text !== null && text === term.value;
  });
}
