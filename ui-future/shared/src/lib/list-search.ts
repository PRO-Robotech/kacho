// Поиск над списком ресурса: отставание ввода и подготовка значения к выражению
// фильтра.
//
// Оба здесь, а не в теле страницы, потому что оба — про КОНТРАКТ с сервером, а не
// про вид: одно решает, сколько запросов уходит на набранное слово, другое — что
// именно в этих запросах окажется.

import { useEffect, useState } from "react";

/**
 * Значение, отстающее от ввода на `delayMs`.
 *
 * Без отставания каждая нажатая клавиша — отдельный запрос к серверу, и ответы
 * приходят вперемешку: последний увиденный на экране может относиться к
 * предпоследнему слову.
 *
 * `delayMs <= 0` означает «без отставания» и отдаёт значение КАК ЕСТЬ, а не через
 * нулевой таймер: отложенный на такт ответ выглядел бы как задержка там, где её
 * не просили, — например при клиентском сужении, где спрашивать некого.
 */
export function useDebouncedValue<T>(value: T, delayMs: number): T {
  const [settled, setSettled] = useState(value);

  useEffect(() => {
    if (delayMs <= 0) return;
    const timer = setTimeout(() => setSettled(value), delayMs);
    return () => clearTimeout(timer);
  }, [value, delayMs]);

  return delayMs <= 0 ? value : settled;
}

/**
 * Значение, пригодное для выражения фильтра `field="value"`.
 *
 * Кавычка и обратный слэш во вводе ломают грамматику выражения, а сломанное
 * выражение сервер разбирать перестаёт — и отвечает ПОЛНЫМ списком на запрос,
 * который не нашёл никого. То есть цена — не отказ, а тихая ложь: поиск покажет
 * всех и будет выглядеть работающим.
 *
 * Знаки убираются, а не экранируются: искать по кавычке в почте или в
 * идентификаторе нечего — ни то, ни другое её не содержит.
 */
export function filterExpressionValue(raw: string): string {
  return raw.trim().replace(/["\\]/g, "");
}
