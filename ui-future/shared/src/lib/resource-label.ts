// Подпись действия над ресурсом — с падежом, а не с именительным на все случаи.
//
// «Создать» управляет ВИНИТЕЛЬНЫМ падежом, и по-русски это «Создать виртуальную
// машину», а не «Создать виртуальная машина». Класс держался на том, что у
// мужского и среднего рода винительный совпадает с именительным: половина
// подписей выглядела исправной, и находка приходила только на женском роде и на
// прилагательных.
//
// Падеж НЕ выводится из строки. Русское склонение по окончанию — правило с
// исключениями (одушевлённость: «Создать пользователя», а не «пользователь»), и
// вывод по хвосту слова ошибается молча — ровно тем классом, что и деривация
// региона из имени зоны. Поэтому форма ОБЪЯВЛЯЕТСЯ у ресурса, а гейт требует
// объявления от каждого.
//
// Уже объявленный `genitive` сюда не годится: это родительный падеж, собранный
// для другой конструкции («Обзор шлюза»), и он дал бы «Создать виртуальной
// машины».

import type { ResourceSpec } from "@shared/lib/resource-spec";

/**
 * Ресурсы, о чьём необъявленном падеже уже сказано.
 *
 * Подпись собирается на каждом рендере, и без памяти одна страница списка
 * выдала бы сотни одинаковых строк — предупреждение, которое листают, читать
 * перестают.
 */
const announced = new Set<string>();

/**
 * Запасной путь ЗАМЕТЕН, а не тих.
 *
 * Рассмотрено и отвергнуто:
 *   • бросить исключение — цена несопоставима с предметом: из-за косметической
 *     подписи страница перестала бы открываться целиком, а сама подпись при
 *     этом у мужского и среднего рода чаще всего верна;
 *   • пометить прямо в интерфейсе — упущение наше, а платит за него арендатор:
 *     он читает служебную метку и всё равно ничего с ней сделать не может;
 *   • промолчать — это и есть закрываемый класс.
 *
 * Остаётся сказать там, где смотрит инженер, и сказать ОДИН раз на ресурс.
 * Это второй рубеж: первый — гейт `resource-label.test.ts`, требующий
 * объявления от каждой записи ОБЩЕГО реестра. Реестры отдельных модулей этот
 * гейт не читает, и до них доходит только предупреждение времени исполнения.
 */
function announceMissingAccusative(singular: string, label: string): void {
  if (announced.has(singular)) return;
  announced.add(singular);
  console.warn(
    `[kacho] у ресурса «${singular}» не объявлен винительный падеж (accusative). ` +
      `Подпись действия собрана из именительного: «${label}». ` +
      `Объявите падеж в реестре ресурсов рядом с singular/plural.`,
  );
}

/**
 * «Создать облачную сеть», «Добавить подсеть».
 *
 * `verb` — для мест, где действие не «создать» (добавление в список, выбор из
 * справочника). Падеж от глагола не зависит: все они здесь управляют винительным.
 */
export function createActionLabel(spec: Pick<ResourceSpec, "singular" | "accusative">, verb = "Создать"): string {
  const label = `${verb} ${spec.accusative ?? spec.singular.toLowerCase()}`;
  if (!spec.accusative) announceMissingAccusative(spec.singular, label);
  return label;
}
