// Запасной путь подписи действия ЗАМЕТЕН, а не тих.
//
// ── ПРЕДМЕТ ───────────────────────────────────────────────────────────────────
// Винительный падеж ОБЪЯВЛЯЕТСЯ у ресурса (`accusative`), и от каждой записи
// общего реестра его требует гейт `resource-label.test.ts`. Но реестры отдельных
// модулей (`compute`, `nlb`, `registry`, `storage`) — свои файлы, и тот гейт их
// не читает: он импортирует ОДИН реестр. Значит ресурс без объявленного падежа в
// дерево попасть может, и вопрос ровно в том, что тогда произойдёт.
//
// Прежде происходило молчание: подпись собиралась из именительного и выглядела
// исправной у половины ресурсов — у мужского и среднего рода падежи совпадают.
// Это и есть закрываемый класс: форма объявлена, потребитель её не получил, и
// никто об этом не узнал.
//
// ── ПОЧЕМУ ИМЕННО ПРЕДУПРЕЖДЕНИЕ ──────────────────────────────────────────────
// Рассмотрено и отвергнуто: бросать исключение (страница перестала бы
// открываться из-за косметической подписи, которая к тому же чаще всего верна) и
// метить прямо в интерфейсе (упущение наше, а читает метку арендатор, и сделать
// с ней он ничего не может). Остаётся сказать там, где смотрит инженер.
//
// Утверждается ОБЕ стороны: сказано на ресурсе без объявления — и НЕ сказано на
// ресурсе с объявлением. Без второй половины «предупреждение работает» означало
// бы лишь, что оно печатается всегда.

import { jest } from "@jest/globals";
import { createActionLabel } from "@shared/lib/resource-label";

describe("ресурс без объявленного падежа", () => {
  it("подпись всё равно собирается — и об упущении сказано", () => {
    const warn = jest.spyOn(console, "warn").mockImplementation(() => {});
    try {
      const label = createActionLabel({ singular: "Кластер очередей" });

      // Кнопка обязана остаться рабочей: цена молчащей подписи меньше цены
      // неоткрывающейся страницы.
      expect(label).toBe("Создать кластер очередей");
      expect(warn).toHaveBeenCalledTimes(1);
      const said = String(warn.mock.calls[0]?.[0] ?? "");
      // Сообщение обязано называть ПРЕДМЕТ и МЕСТО правки: «что-то не так»
      // читатель снимает как непонятное.
      expect(said).toContain("Кластер очередей");
      expect(said).toContain("accusative");
    } finally {
      warn.mockRestore();
    }
  });

  it("говорит один раз на ресурс, а не на каждый рендер", () => {
    // Подпись собирается на каждом рендере списка; предупреждение, которое
    // листают сотнями строк, читать перестают — то есть оно снова становится
    // молчанием, только шумным.
    const warn = jest.spyOn(console, "warn").mockImplementation(() => {});
    try {
      createActionLabel({ singular: "Пул сессий" });
      createActionLabel({ singular: "Пул сессий" });
      createActionLabel({ singular: "Пул сессий" }, "Добавить");

      expect(warn).toHaveBeenCalledTimes(1);
    } finally {
      warn.mockRestore();
    }
  });

  it("положительный контроль: объявленный падеж не порождает ни слова", () => {
    const warn = jest.spyOn(console, "warn").mockImplementation(() => {});
    try {
      expect(createActionLabel({ singular: "Облачная сеть", accusative: "облачную сеть" })).toBe(
        "Создать облачную сеть",
      );
      expect(warn).not.toHaveBeenCalled();
    } finally {
      warn.mockRestore();
    }
  });
});
