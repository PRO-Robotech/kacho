/**
 * ФОРМА ИМЕНИ РЕСУРСА — объявлена в консоли ОДИН раз (#1604).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЭТО И ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ
 *
 * Правило имени нужно двум местам сразу — реестру ресурсов и форме гостевого
 * ключа, — а они импортируют друг друга. Положив правило в любое из них, мы
 * получили бы либо цикл импортов, либо вторую копию правила. Копия — это второе
 * место об одном предмете; ровно так и разошлись пять прежних объявлений.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ФОРМ ДВЕ, И ЭТО РЕШЕНИЕ, А НЕ НЕДОСВЕДЁННЫЙ ФОРК
 *
 * `NAME_FORM` — форма ПЛАТФОРМЫ, одна на всё дерево: DNS label по RFC 1123
 * (`pkg/validate/nameform`, плюс CHECK-ограничение миграции 715001 у пяти схем).
 * Её применяют iam, vpc, compute, storage, nlb, geo.
 *
 * `NAME_FORM_REGISTRY` — форма имени РЕЕСТРА ОБРАЗОВ
 * (`services/registry/internal/domain.ValidateName`): допускает точку и длину до
 * 255, потому что имя реестра живёт в OCI-пути. Свести её к общей нельзя —
 * консоль начала бы отвергать `my.registry`, законное имя, которое край
 * принимает. Унификация, берущая самую узкую семантику, заводит тот же дефект,
 * ради снятия которого делается, только в другую сторону.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕМ ДЕРЖИТСЯ СОВПАДЕНИЕ С ПЛАТФОРМОЙ
 *
 * Гейт `shared/src/test/console-name-form-tracks-platform` ЧИТАЕТ обе формы из
 * их исходников на Go и сверяет с объявленными здесь. Выписанная и не
 * сверяемая константа верна в день записи и стареет молча — так и вышло с
 * пятью прежними: они пережили и запрет подчёркивания, и разрешение цифры
 * первой, и никто этого не заметил, потому что заметить было нечем.
 */

/** Форма имени платформы: строчные, цифры, дефис; края — буква или цифра; 1..63. */
export const NAME_FORM = "^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$";

/** Форма имени реестра образов: то же плюс точка, длина до 255. */
export const NAME_FORM_REGISTRY = "^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$";

/**
 * Правило СЛОВАМИ, а не регуляркой.
 *
 * Подсказку читает тот, кто строит по ней соглашение об именах, и читать
 * регулярку он не обязан. Отказ края на негодном имени приходит по-английски и
 * образцом — тем более консоль обязана назвать правило заранее и по-русски.
 */
export const NAME_HINT =
  "Строчные латинские буквы, цифры и дефис. Первый и последний знак — буква или цифра, длина 1–63.";

/**
 * То же правило там, где имя необязательно.
 *
 * Пустое имя — законный ВХОД создания, и это контракт края, а не поблажка
 * формы: ресурса с пустым именем не существует, сервер подставляет имя,
 * производное от идентификатора.
 */
export const NAME_HINT_OPTIONAL = `${NAME_HINT} Можно не заполнять — платформа назовёт ресурс сама.`;

/** Правило имени реестра образов словами. */
export const NAME_HINT_REGISTRY =
  "Строчные латинские буквы, цифры, дефис и точка. Первый и последний знак — буква или цифра, длина до 255.";
