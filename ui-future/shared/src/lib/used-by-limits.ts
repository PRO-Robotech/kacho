// Число здесь — не выбор консоли, а зеркало серверной константы: сервер отдаёт
// не больше предела плюс одну строку, и лишняя строка — единственный признак
// «есть ещё» (отдельного поля под него в контракте нет). Ошибись консоль в
// числе — она либо припишет усечение полному списку, либо промолчит об усечении.
//
// Расхождение с сервером ловит `used-by-limits.test.ts`: он читает объявление из
// исходника vpc и падает, если числа разошлись. Правило «два места об одном
// предмете» здесь не нарушено ровно потому, что второе место проверяется первым,
// а не переписывается по памяти.
//
// Источник: `services/vpc/internal/repo/kacho/entity_security_group.go`,
// константа `SecurityGroupUsedByLimit`.
