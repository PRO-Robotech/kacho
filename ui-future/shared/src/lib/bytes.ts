// Размер в байтах в человекочитаемый вид — ОДНО объявление на всю консоль.
//
// Здесь эта функция появилась потому, что дома у неё не было: она жила тремя
// байт-в-байт копиями у `compute`, `storage` и `registry` (совпадал md5), не
// была покрыта ни одной пробой и для переписи форков была невидима СРАЗУ ПО
// ОБЕИМ осям — общий модуль символа `formatBytes` не объявлял, а файла по
// такому адресу у него не существовало. Копия, которую не видит ни признак по
// имени, ни признак по адресу, расходится тише всех: узнать о расхождении можно
// было бы только сравнив три файла вручную, а повода сравнивать не возникает.
//
// Форматов размера в консоли ДВА, и путать их нельзя. Здесь — лестница разрядов
// (B/KB/MB/GB/TB) для величин, о которых сообщает сервер: размер образа, тега,
// репозитория. Отдельно, в реестре ресурсов, живут `fmtMiBGiB` (память типа
// машины приходит в МиБ) и `fmtBytesGiB` (объём диска, всегда в ГиБ) — у них
// фиксированный разряд, потому что величина там сравнивается глазом между
// строками таблицы, и плавающий разряд сравнение ломает.

/**
 * Размер в байтах словами: `1.0 MB`, `512 B`.
 *
 * Принимает `unknown`, потому что int64 приходит с wire СТРОКОЙ: без разбора
 * строка ушла бы в сравнение с 1024 как строка, и лестница молча встала бы на
 * первом разряде.
 *
 * Пусто / ноль / не число → прочерк, и НИКОГДА «0 B»: «0 B» — утверждение о
 * размере ресурса, которого сервер не делал. Пустое значение обязано означать
 * «пусто», иначе оно лжёт.
 *
 * Байты показываются целыми, старшие разряды — с одним знаком: у целого числа
 * байт нет дробной части, и «512.0 B» сообщал бы о точности, которой нет.
 */
export function formatBytes(v: unknown): string {
  const n = typeof v === "string" ? Number.parseInt(v, 10) : typeof v === "number" ? v : Number.NaN;
  if (!Number.isFinite(n) || n <= 0) return "—";
  const units = ["B", "KB", "MB", "GB", "TB"];
  let x = n;
  let i = 0;
  // Верхний разряд — последний в списке: выше него растёт ЧИСЛО, а не единица.
  // Иначе индекс ушёл бы за конец списка и вместо величины пользователь увидел
  // бы `undefined`.
  while (x >= 1024 && i < units.length - 1) {
    x /= 1024;
    i += 1;
  }
  return `${i ? x.toFixed(1) : x} ${units[i]}`;
}
