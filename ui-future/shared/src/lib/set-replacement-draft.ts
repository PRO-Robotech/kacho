/**
 * Объявление места, где консоль правит НАБОР полной заменой.
 *
 * # Класс, ради которого это заведено
 *
 * Форма читает набор с сервера в черновик и отправляет **весь массив обратно**.
 * Поле контракта, которого черновик не назвал, исчезает у ВСЕХ элементов —
 * включая те, которых оператор не касался. Ни ошибки, ни предупреждения: край
 * получает валидный запрос, где поля просто нет (#422 — правка маршрутов
 * стирала метки; #498 — тот же класс ещё в трёх местах).
 *
 * # Что делает это объявление
 *
 * Связывает место записи с сообщением контракта и с типами-черновиками, через
 * которые элементы набора проходят. Гейт
 * `shared/src/test/set-replacement-draft-composition.test.ts`:
 *
 *   * находит места полной замены ОБХОДОМ ДЕРЕВА, а не по перечню, — поэтому
 *     пятое такое место попадает под наблюдение по построению: у него не будет
 *     этого объявления, и гейт покраснеет с координатой;
 *   * читает САМ `.proto` и требует, чтобы КАЖДОЕ поле сообщения было названо
 *     членом каждого названного здесь типа-черновика. Лишние члены (служебные,
 *     только для представления) законны и не проверяются;
 *   * снимает объявление, которому больше нечего описывать: объявление без
 *     места записи в своём файле — находка, а не остаток.
 *
 * Почему связь ОБЪЯВЛЯЕТСЯ, а не выводится: имя поля `rules` несут два разных
 * сообщения контракта (`iam.v1.Rule` и `vpc.v1.SecurityGroupRule`), а тип
 * элемента без полного графа типов из места записи не читается. Выведенная
 * «по совпадению имён» связь молча указала бы не на то сообщение — то есть
 * гейт сверял бы черновик не с его контрактом.
 *
 * Сам ЭТОТ модуль — только тип: `import type` стирается сборкой, поэтому в
 * бандл он не попадает. Объявление на месте записи — обычная константа: объект
 * из четырёх полей, который сборка эмитит. Цена названа, чтобы её не пришлось
 * узнавать: столько стоит связь черновика с его контрактом, проверяемая
 * машинно.
 */
export interface SetReplacementDraft {
  /** Имя поля, которым набор уезжает на край (`static_routes`, `rules`, `targets`). */
  readonly field: string;
  /** Путь контракта внутри `proto/` — `kacho/cloud/vpc/v1/route_table.proto`. */
  readonly contract: string;
  /** Имя сообщения-элемента набора в этом контракте. */
  readonly message: string;
  /**
   * Имена типов-черновиков, через которые проходит элемент набора.
   *
   * Разрешаются ПО ИМЕНИ во всём дереве консоли, поэтому форк типа (копия того
   * же имени в другом модуле) проверяется вместе с оригиналом — а не остаётся
   * незамеченным ровно потому, что он копия.
   */
  readonly drafts: readonly string[];
}
