// Плоский список идентификаторов из значения generic-массива формы.
//
// `ArrayField` хранит элемент ОБЪЕКТОМ (`{value: "…"}`) — это его форма, общая
// для всех подполей. Контракт же ждёт `repeated string`. Перевод между ними
// нужен каждому такому полю (`security_group_ids`, `guest_access_key_ids`, …), и
// живёт он здесь, в одном месте: копия в каждом реестре разошлась бы ровно тем
// способом, каким уже расходились копии формы машины — молча и в одну сторону.
//
// Пустой результат — `undefined`, а НЕ `[]`. Разница смысловая: пустой массив в
// теле запроса утверждает «ни одного», тогда как арендатор чаще просто не дошёл
// до поля. Решение, что делать с `undefined`, принимает вызывающий: он один
// знает, обязательно ли поле.

/**
 * Приводит значение поля-массива к плоскому списку непустых строк.
 *
 * Принимает и объектную форму элемента (`{value}`), и уже плоскую строку —
 * одно и то же поле встречается в обеих на пути «форма → провод».
 *
 * @returns список непустых строк либо `undefined`, если непустых нет.
 */
export function flatIdList(raw: unknown): string[] | undefined {
  if (!Array.isArray(raw)) return undefined;
  const out = (raw as unknown[])
    .map((it): unknown =>
      typeof it === "object" && it !== null && "value" in it ? (it as Record<string, unknown>).value : it,
    )
    .filter((v): v is string => typeof v === "string" && v !== "");
  return out.length > 0 ? out : undefined;
}
