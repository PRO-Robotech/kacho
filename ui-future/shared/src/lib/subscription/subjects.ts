// Мост между спекой консоли и словарём владельца журнала — ОДНО объявление на
// всю консоль.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ ОБЪЯВЛЕНО И ЧЕГО ЗДЕСЬ НЕТ
//
// Здесь только СООТВЕТСТВИЕ: какой ресурс консоли какому владельцу журнала и
// какому виду предмета отвечает. Словаря видов здесь НЕТ и быть не может: он
// принадлежит владельцу, закрыт им и приезжает по проводу первым же кадром
// потока (`knownKinds`). Выпиши его тут — и он разошёлся бы с владельцем молча
// в день, когда владелец заведёт вид или снимет его.
//
// Поэтому карта ниже отвечает на вопрос «чего СПРАШИВАТЬ», а решение «покрыт ли
// вид» принимает `hub.covers()` по ответу владельца.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЛАДЕЛЕЦ — ДОМЕН КОНТРАКТА, А НЕ СЕГМЕНТ REST-ПУТИ И НЕ КАТАЛОГ В ДЕРЕВЕ
//
// Имя владельца — домен контракта (`kacho.cloud.<домен>.v1`), тот же ключ, каким
// край резолвит адрес дозвона. У большинства доменов он совпадает с сегментом
// пути, у балансировщика — НЕТ: REST-путь `/nlb/v1/`, каталог в дереве
// `services/nlb`, а владелец `loadbalancer`. Взять здесь сегмент пути или имя
// каталога значило бы получать `400 unknown owner` на каждом открытии — то есть
// возможность, объявленную и неисполнимую.
//
// Здесь ровно это и стояло (kacho#1440): предмет балансировщика назывался
// владельцем `nlb`, и страница списка давала ДВА отказа `400` подряд — на
// открытии потока и на запросе разбора причины. Список при этом работал: опрос
// возвращается по построению, поэтому ни одно утверждение о содержимом страницы
// покраснеть не могло. Прежняя редакция этого абзаца меняла обе половины
// местами и объясняла верным ровно то, что отвергается.
//
// Принимаемые написания перечисляет первая колонка таблицы владельцев на
// клиентской странице подписки (`gateway/docs/content/api/subscription.mdx`);
// множество их приезжает вызовом `config.Config.DomainsWithInternalBackend` —
// той же функцией, которой пользуется край на старте. Согласие ЭТОГО файла с ней
// держит гейт `gateway/deploy/console_subscription_owner_test.go`.
//
// Соседняя функция `resourceServicePrefix` (`@shared/lib/service-prefix`)
// отвечает на ДРУГОЙ вопрос — каким сегментом открывается страница ресурса, — и
// совпадение её значений с этими на пяти доменах из шести случайно.
//
// ─────────────────────────────────────────────────────────────────────────────
// НАПИСАНИЕ ВИДА — ТИП ОБЪЕКТА МОДЕЛИ ПРАВ, ОДНО НА ВСЁ ДЕРЕВО
//
// `vpc_network`, `compute_instance`, `nlb_network_load_balancer` — ровно то, что
// владелец перечисляет в `knownKinds` и принимает осью `kinds`. Не слово, каким
// владелец записал строку в своём журнале (у compute это `Instance` — с
// заглавной и без домена).
//
// Согласие ЭТИХ написаний со словарями владельцев держит третий гейт —
// `ui-future/deploy/console_stream_kind_dictionary_test.go`. Он заведён потому,
// что цена ошибки здесь ИНАЯ, чем у имени владельца: неверное имя даёт `400` на
// открытии и видно в журнале браузера, а неверное написание вида не даёт
// НИЧЕГО — поток откроется, словарь этого вида не принесёт, `hub.covers()`
// ответит «нет», и список молча останется на опросе. Словарь гейт выводит из
// дерева (поле `ObjectType` карты `Kinds` каждого журнала), а не выписывает
// здесь: выписанный разошёлся бы с владельцем молча — ровно то, о чём
// предупреждает абзац выше.

/**
 * Владельцы журналов, служащие глагол подписки.
 *
 * Множество задаёт КРАЙ, а не это объявление: перечень владельцев закрыт
 * (`gateway/deploy/values.yaml` → `subscriptionStream.owners`), и имя вне его
 * отвечает `501`. Согласие держат ДВА гейта, по одному на направление, — вторая
 * копия перечня здесь была бы третьим местом об одном предмете:
 *
 * · имя, названное здесь, край обязан принимать —
 *   `gateway/deploy/console_subscription_owner_test.go`;
 * · владелец, объявленный краю, обязан быть назван здесь —
 *   `ui-future/deploy/console_stream_owner_coverage_test.go`.
 *
 * Второй заведён по находке: край объявлял пятерых, карта называла троих, и
 * молчание расхождения родило четыре места опроса, объяснённых утверждением
 * «журнала у этого домена нет» — при живых журналах блочного хранения и реестра.
 */
export type JournalOwner = "compute" | "loadbalancer" | "registry" | "storage" | "vpc";

export interface StreamSubject {
  owner: JournalOwner;
  /** Тип объекта модели прав — то же написание, что в `knownKinds` владельца. */
  kind: string;
}

/**
 * Спека консоли → предмет потока.
 *
 * ЗДЕСЬ РОВНО ТЕ РЕСУРСЫ, ЧЕЙ ВЛАДЕЛЕЦ ЖУРНАЛ ОБЪЯВИЛ. Ресурс своего домена, но
 * не своего журнала, сюда НЕ попадает — и это не пропуск: у compute журнал
 * пишет один вид (машины), поэтому группа размещения и тип машины остаются на
 * опросе. Назови их здесь — владелец отверг бы поток, а список замолчал бы
 * навсегда, потому что «вида нет в словаре» и «событий нет» со стороны
 * выглядят одинаково.
 */
export const STREAM_SUBJECTS: Readonly<Record<string, StreamSubject>> = {
  // VPC — восемь видов, все, что объявляет журнал домена.
  networks: { owner: "vpc", kind: "vpc_network" },
  subnets: { owner: "vpc", kind: "vpc_subnet" },
  addresses: { owner: "vpc", kind: "vpc_address" },
  gateways: { owner: "vpc", kind: "vpc_gateway" },
  "route-tables": { owner: "vpc", kind: "vpc_route_table" },
  "security-groups": { owner: "vpc", kind: "vpc_security_group" },
  "network-interfaces": { owner: "vpc", kind: "vpc_network_interface" },
  "cidr-groups": { owner: "vpc", kind: "vpc_cidr_group" },

  // Compute — один вид: журнал пишет только машины.
  "compute-instances": { owner: "compute", kind: "compute_instance" },

  // Балансировщик — три вида. Владелец `loadbalancer` (домен контракта), путь
  // `/nlb/v1/`, каталог в дереве `services/nlb`. Написание вида при этом
  // остаётся `nlb_*` — это тип объекта модели прав, и от имени владельца он НЕ
  // производится: у балансировщика они попросту разные.
  "load-balancers": { owner: "loadbalancer", kind: "nlb_network_load_balancer" },
  listeners: { owner: "loadbalancer", kind: "nlb_listener" },
  "target-groups": { owner: "loadbalancer", kind: "nlb_target_group" },

  // Блочное хранение — три вида из шести спек модуля. Тип диска, зона и регион
  // журналом НЕ покрыты, и это решение владельца, а не пропуск: у их строк нет
  // ни `project_id`, ни типа объекта модели прав, поэтому вопрос «вправе ли
  // вызывающий это видеть» задать нечем, а строка без ответа на него не
  // доставляется. Назови их здесь — поток молчал бы, а список замер бы навсегда.
  volumes: { owner: "storage", kind: "storage_volume" },
  snapshots: { owner: "storage", kind: "storage_snapshot" },
  images: { owner: "storage", kind: "storage_image" },

  // Реестр — один вид: журнал пишет только сами реестры. Репозиторий и тег сюда
  // не попадают, и это тоже не пропуск — тег живёт в OCI-данных и ресурсом
  // платформы не является вовсе, а репозиторий журнал не ведёт.
  registries: { owner: "registry", kind: "registry_registry" },
};

/**
 * Перечень владельцев — ВЫВОДИТСЯ из карты, а не выписывается вторым списком.
 *
 * Прежняя редакция объявляла ровно это и при том держала рукописный литерал:
 * два места об одном предмете, из которых верно одно. Расхождение не наступило
 * только потому, что перечень не рос.
 */
export const JOURNAL_OWNERS: readonly JournalOwner[] = [
  ...new Set(Object.values(STREAM_SUBJECTS).map((subject) => subject.owner)),
].sort();

/**
 * Предмет потока для спеки — либо `null`, «журнала для этого ресурса нет».
 *
 * Корзины «прочее» здесь нет намеренно: неизвестный идентификатор отвечает
 * `null`, и вызывающий остаётся на опросе. Догадка вида «раз домен compute,
 * значит покрыто» дала бы отказ на открытии и молчащий список — то есть худший
 * из возможных исходов, потому что выглядел бы он как «изменений не было».
 */
export function streamSubject(specId: string): StreamSubject | null {
  return STREAM_SUBJECTS[specId] ?? null;
}
