// Провязка потока изменений с чтением списка/карточки.
//
// ---------------------------------------------------------------------------
// ЧТО ЭТОТ ХУК ОТДАЁТ И ЗАЧЕМ
//
// Одно значение — `streamed`: покрыт ли предмет этой страницы потоком ПРЯМО
// СЕЙЧАС. Вызывающий гасит им свой опрос (`refetchInterval: streamed ? false :
// N`), и это единственный законный способ снять опрос в консоли: снятие «по
// таблице» разошлось бы со словарём владельца молча, а снятие «навсегда»
// заморозило бы список на установке, где владелец не объявлен.
//
// Двух механизмов одновременно не бывает by construction: опрос выключается
// ровно тем же значением, которым включается перечитывание по событию.
//
// ---------------------------------------------------------------------------
// ПОЧЕМУ ПО СОБЫТИЮ ИДЁТ ПЕРЕЧИТЫВАНИЕ, А НЕ ПРИМЕНЕНИЕ СОСТОЯНИЯ
//
// Соблазн велик — событие несёт полное состояние, — но несёт его НЕ ВСЯКОЕ
// событие, и это измерено, а не предположено: у владельца `nlb` состояния нет
// ни у одного из трёх видов и ни у одного рода изменения; у `vpc` и `compute`
// его нет у СНЯТИЯ. Значит применение состояния закрывало бы часть видов, а
// рядом жил бы второй путь для остальных — два источника одного состояния,
// которые расходятся молча, и расхождение видно человеку как мерцание строки.
//
// Второй довод сильнее первого: список читается КУРСОРОМ и сужается СЕРВЕРОМ
// (`filter`, `listFilters`). Строка, вставленная в него клиентом, разошлась бы
// с тем, что владелец считает страницей, — и разошлась бы именно там, где
// расхождение не видно: на валидном входе оба ответа выглядят правдоподобно.
//
// Цена перечитывания названа честно: один запрос НА ИЗМЕНЕНИЕ вместо одного
// запроса в три секунды НА ВСЯКИЙ СЛУЧАЙ. Отдельного склеивания всплеска здесь
// нет намеренно — react-query не запускает второе чтение того же ключа, пока
// идёт первое, поэтому пачка событий стоит не больше двух чтений.
//
// ---------------------------------------------------------------------------
// ОТБОР ПО МЕТКАМ ЗДЕСЬ НЕ ЖИВЁТ
//
// Он живёт там, где есть ОБА состояния строки, — на странице, перечитавшей
// список (`@shared/lib/list-label-filter`). Событие предыдущего состояния не
// несёт, поэтому «вышел из выборки» и «удалён» в нём неразличимы; отбор,
// построенный на событии, показал бы человеку снос вместо правки метки.

import { useEffect, useRef, useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { streamSubject } from "./subjects";
import { subscriptionHub, type StreamEvent, type SubscriptionHub } from "./hub";

export interface UseResourceStreamArgs {
  /** Идентификатор спеки ресурса. `null` — предмета нет, поток не открывается. */
  specId: string | null;
  /** Проект, к которому относится страница. */
  projectId: string | null;
  /**
   * Ключ запроса, который перечитывается по событию.
   *
   * Называет ВЫЗЫВАЮЩИЙ, а не хук: у одного ресурса на странице бывает
   * несколько чтений (список, карточка, связанная вкладка), и они живут под
   * разными ключами. Хук, перечитывающий всё по идентификатору спеки, тянул бы
   * за собой чужие чтения — например ленту операций, которую поток не покрывает
   * вовсе.
   */
  invalidate: readonly unknown[];
  /** Открывать ли поток. Незаданное значение читается как «да». */
  enabled?: boolean;
}

export interface ResourceStream {
  /** Покрыт ли предмет потоком: опрос снимается ТОЛЬКО по этому признаку. */
  streamed: boolean;
}

export function useResourceStream(
  { specId, projectId, invalidate, enabled = true }: UseResourceStreamArgs,
  hub: SubscriptionHub = subscriptionHub(),
): ResourceStream {
  const queryClient = useQueryClient();

  const subject = specId ? streamSubject(specId) : null;
  const owner = subject?.owner ?? null;
  const kind = subject?.kind ?? null;

  // КЛЮЧ ПРЕДМЕТА — он же признак «поток вообще открывается»: `null` означает
  // «предмета нет», и тогда покрытия не бывает ПО ПОСТРОЕНИЮ, а не потому, что
  // кто-то не забыл его снять. Разделитель — нулевой байт: он не встречается ни
  // во владельце, ни в типе объекта, ни в идентификаторе проекта, поэтому две
  // разные тройки не могут дать один ключ.
  const targetKey = enabled && owner && kind ? `${owner}\u0000${kind}\u0000${projectId ?? ""}` : null;

  // Покрытие хранится КЛЮЧОМ покрытого предмета, а не признаком «покрыто».
  //
  // Признак пришлось бы гасить самому — сбросом в эффекте на каждом переходе,
  // где предмет исчез, — а сброс состояния прямо в теле эффекта запускает
  // каскад перерисовок (`react-hooks/set-state-in-effect`). Ключ отвечает на
  // тот же вопрос без сброса: покрытие, записанное для ПРЕЖНЕГО предмета, с
  // новым не совпадает и прочитаться как его покрытие не может.
  const [coveredKey, setCoveredKey] = useState<string | null>(null);

  // Ключ перечитывания — через ссылку: массив пересоздаётся на каждой
  // перерисовке, и попади он в зависимости эффекта, подписка снималась бы и
  // заводилась заново по нескольку раз в секунду. Поток бы при этом закрывался
  // и открывался — то есть предмет задачи заменился бы более дорогим опросом.
  //
  // Присвоение — В ЭФФЕКТЕ, а не в теле функции: ссылка во время отрисовки ещё
  // не принадлежит зафиксированному состоянию, и правка её там читается как
  // отрисовка с побочным действием. Эффект без списка зависимостей исполняется
  // после КАЖДОЙ отрисовки, а читают ссылку только из обработчика события —
  // то есть всегда позже фиксации.
  const invalidateRef = useRef(invalidate);
  useEffect(() => {
    invalidateRef.current = invalidate;
  });

  useEffect(() => {
    if (targetKey === null || !owner || !kind) return;
    const target = { owner, kind, projectId };

    const handle = (_event: StreamEvent): void => {
      // Предмет события здесь не разбирается: любое событие своего вида
      // означает, что страница, показанная человеку, устарела. Разбирать род
      // изменения значило бы решать за владельца, какие события «важные», — а
      // именно снятие предмета, у которого состояния нет ни у кого, и есть
      // единственный источник знания о том, что строки больше нет.
      void queryClient.invalidateQueries({ queryKey: invalidateRef.current as unknown[] });
    };

    const off = hub.subscribe(target, handle);
    const note = (): void => setCoveredKey(hub.covers(target) ? targetKey : null);
    const offCoverage = hub.onCoverageChange(note);
    // Спросить СРАЗУ: канал этого владельца мог быть открыт соседним списком, и
    // тогда объявления покрытия уже не будет — оно прозвучало до подписки.
    note();
    return () => {
      offCoverage();
      off();
    };
  }, [hub, targetKey, owner, kind, projectId, queryClient]);

  // Покрытие читается только для СВОЕГО предмета. Отсюда же и «предмета нет ⇒
  // не покрыт»: опрос остаётся включённым без единого сброса состояния.
  return { streamed: targetKey !== null && coveredKey === targetKey };
}
