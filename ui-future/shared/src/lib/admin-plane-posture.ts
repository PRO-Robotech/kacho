// Посадка admin-плоскости: обслуживает ли край, к которому подключена ЭТА
// консоль, административную поверхность платформы (#2692).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СПРАШИВАЕТСЯ У КРАЯ, А НЕ ОБЪЯВЛЯЕТСЯ ПРОФИЛЕМ
//
// Административные глаголы (`Internal*`) живут только на внутреннем слушателе
// края (запрет #6); консоль же одна на обе посадки — арендаторскую, чей край
// внешний, и операторскую, чей край внутренний. Объявление «плоскость есть» в
// профиле консоли было бы вторым местом об одном предмете: оно разошлось бы с
// тем, куда на самом деле смотрит `upstreams.apiGateway`, и разошлось бы молча.
// Ответ края расходиться не с чем: он и есть посадка.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО СПРАШИВАЕТСЯ И ПОЧЕМУ 404 ЗДЕСЬ — ОТВЕТ, А НЕ ПРОМАХ
//
// Проба — чтение одиночки административной плоскости: кластера `cluster_root`
// (`InternalClusterService/Get`). Запись есть всегда, где плоскость есть, а
// публичного близнеца у пути нет. Внешний слушатель отвечает на необслуживаемую
// координату ровно так, как на несуществующий маршрут, и раньше аутентификации
// (`restmux.ExternalRouteGate`, kacho#3053), — то есть 404. На чтении записи,
// которая есть всегда, 404 не может значить «записи нет». Значит 404 здесь
// читается однозначно — на этом слушателе плоскости нет.
//
// ПУТЬ ОБЯЗАН НЕ ИМЕТЬ ПУБЛИЧНОГО БЛИЗНЕЦА — и это судит таблица маршрутов края,
// а не этот комментарий (admin-plane-posture.test.ts). Прежний путь пробы,
// `GET /vpc/v1/addressPools`, близнеца получил: с ADM-1 S1 его обслуживает и
// публичная `AddressPoolService`, внешний слушатель отвечает на него как на
// обслуживаемый, и проба на внешней посадке называла плоскость присутствующей
// (kacho#3091). Пулы адресов с тех пор от посадки не зависят вовсе: их мутации
// край обслуживает на обоих слушателях.
//
// Настоящий отказ в правах приходит 403 и остаётся отказом в правах: раздел
// на него не закрывается, и смотрящий видит то же «нет прав», что и на любом
// другом действии. Всё остальное (5xx, сеть) посадки не называет — и не
// выдаётся ни за наличие, ни за отсутствие: неизвестное остаётся неизвестным.

import { useQuery } from "@tanstack/react-query";
import { api, ApiError } from "@shared/api/client";

/**
 * `pending` — проба ещё не ответила; `unknown` — ответила, но посадки не назвала
 * (сбой, сеть). Разводятся намеренно: до ответа раздел действий не предлагает,
 * а после неназванного ответа — предлагает, чтобы смотрящий увидел настоящий
 * отказ края, а не молчаливо снятые кнопки.
 */
export type AdminPlanePosture = "pending" | "unknown" | "present" | "absent" | "denied";

/**
 * Путь пробы — кластер `cluster_root`: `InternalClusterService/Get`, обслуживается
 * только внутренним слушателем, публичного GET по этому пути нет.
 */
export const ADMIN_PLANE_PROBE_PATH = "/iam/v1/internal/cluster";

/**
 * Предлагать ли мутации, которые обслуживает только admin-плоскость (регионы,
 * зоны, администраторы кластера). Нет — на посадке без плоскости и пока проба
 * не ответила: кнопка, показанная до ответа, успела бы отказать раньше, чем
 * раздел сказал бы, почему. Отказ в правах и неназванный сбой мутаций НЕ
 * снимают: первый остаётся отказом в правах, второй — отказом края, который
 * смотрящий обязан увидеть, а не молчаливо снятые кнопки.
 */
export function adminPlaneMutable(posture: AdminPlanePosture): boolean {
  return posture !== "pending" && posture !== "absent";
}

/** Классификация исхода пробы. `null` — проба ответила успехом. */
export function classifyAdminPlaneProbe(failure: unknown): AdminPlanePosture {
  if (failure === null || failure === undefined) return "present";
  if (!(failure instanceof ApiError)) return "unknown";
  switch (failure.status) {
    case 404:
      return "absent";
    case 403:
      return "denied";
    default:
      return "unknown";
  }
}

async function probeAdminPlane(): Promise<AdminPlanePosture> {
  try {
    await api.get(ADMIN_PLANE_PROBE_PATH);
    return classifyAdminPlaneProbe(null);
  } catch (e) {
    return classifyAdminPlaneProbe(e);
  }
}

/**
 * Посадка admin-плоскости для этой консоли. Спрашивается один раз на сессию:
 * посадка — свойство края, а не запроса, и меняется она перекатом, а не
 * временем.
 */
export function useAdminPlanePosture(): AdminPlanePosture {
  const { data } = useQuery({
    queryKey: ["admin-plane-posture"],
    queryFn: probeAdminPlane,
    staleTime: Infinity,
    retry: false,
  });
  return data ?? "pending";
}
