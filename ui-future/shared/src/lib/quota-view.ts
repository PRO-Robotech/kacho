// Витрина квот: что показывать про предел и чего показывать НЕЛЬЗЯ (#364).
//
// Отказ на пределе без витрины неотличим для арендатора от сбоя платформы. Он
// обязан видеть по каждому виду четвёрку: вид · предел · занято · источник —
// причём источник обязателен: без него упёршийся не понимает, чей это предел и
// куда идти его поднимать.
//
// ─────────────────────────────────────────────────────────────────────────────
// НОСИТЕЛЬ — ПОЧЕМУ «ЗАНЯТО» ЕСТЬ НЕ У КАЖДОЙ СТРОКИ
//
// Часть видов считается не в проекте, а внутри РОДИТЕЛЬСКОГО ресурса: «сколько
// подсетей в ОДНОЙ сети». У такого вида на уровне проекта нет единственного
// значения «занято» — их столько же, сколько сетей. Показать там число значит
// солгать; показать прочерк — тоже (`ui.md` правило 9: прочерк на месте живого
// факта утверждает о ресурсе неправду). Строка называет носителя и потребления
// не показывает вовсе.

/**
 * Кто задаёт величины — ОДНА фраза на витрину и на отказ.
 *
 * Витрина отвечает на три вопроса упёршегося (каков предел · сколько занято ·
 * кто его задал), и отказ обязан отвечать на третий тем же словом: два места об
 * одном предмете расходятся молча, а расхождение здесь означает, что упёршийся
 * идёт не к тому человеку.
 */
export const QUOTA_VALUES_SET_BY = "Величины задаёт администратор облака";

/** Строка ответа `GET /vpc/v1/quotas` (после приведения имён клиентом). */
export interface Quota {
  kind: string;
  limit: number;
  used: number;
  source_scope: string;
  source_scope_id: string;
  carrier_type: string;
  carrier_id: string;
}

/** Носитель-проект — единственное значение, при котором «занято» относится к проекту. */
const CARRIER_PROJECT = "project";

/**
 * Считается ли этот вид В ПРОЕКТЕ — то есть есть ли у строки «занято».
 *
 * Требуются ОБА признака, и они независимы:
 *
 *  1. **носитель назван проектом** (`carrier_type`). Аккаунтные виды
 *     (`iam.project`, `iam.user`) состоят из двух частей, но считаются
 *     аккаунтом — по одной лишь форме имени они прошли бы как проектные;
 *  2. **имя вида состоит из двух частей.** Три части означают вложенный вид по
 *     построению (форму имени закрепляет ограничение хранилища владельца).
 *     Второй признак нужен, пока владелец проставляет носителя КОНСТАНТОЙ
 *     «проект» всем строкам: без него четыре вложенных вида показали бы 0 как
 *     факт, а он там не факт, а просто не считается.
 *
 * Когда носитель станет приезжать верным, второй признак останется избыточным,
 * но не станет неверным: вложенный вид не назовут носителем-проектом.
 */
export function countedInProject(q: Quota): boolean {
  return q.carrier_type === CARRIER_PROJECT && q.kind.split(".").length === 2;
}

