// Витрина квот: что показывать про предел и чего показывать НЕЛЬЗЯ (#364, #622).
//
// Отказ на пределе без витрины неотличим для арендатора от сбоя платформы. Он
// обязан видеть по каждому виду четвёрку: вид · предел · занято · источник —
// причём источник обязателен: без него упёршийся не понимает, чей это предел и
// куда идти его поднимать.
//
// ─────────────────────────────────────────────────────────────────────────────
// НОСИТЕЛЬ — ПОЧЕМУ «ЗАНЯТО» ЕСТЬ НЕ У КАЖДОЙ СТРОКИ
//
// Часть видов считается не в проекте, а внутри РОДИТЕЛЬСКОГО ресурса: «сколько
// подсетей в ОДНОЙ сети». У такого вида на уровне проекта нет единственного
// значения «занято» — их столько же, сколько сетей. Показать там число значит
// солгать; показать прочерк — тоже (`ui.md` правило 9: прочерк на месте живого
// факта утверждает о ресурсе неправду). Строка называет носителя и потребления
// не показывает вовсе.
//
// НОСИТЕЛЕЙ ТРИ, А НЕ ОДИН (#622). Кроме проекта и родительского ресурса есть
// ЛИЧНОСТЬ: число аккаунтов, которое человеку позволено завести, одинаково во
// всех его аккаунтах и существует, когда у него нет ни одного проекта. Поэтому
// «против чего считается» — вход этого модуля (`subject`), а не его допущение:
// одно и то же число есть «занято» для читателя своей страницы и «не про вас»
// для читателя чужой.

/**
 * Строка ответа любого владельца квот (после приведения имён клиентом).
 *
 * Форма ОДНА на всех: её объявляет общий контракт `kacho.cloud.quota.v1.Quota`,
 * и подают её и пятеро проектных владельцев (`/vpc/v1/quotas` и соседи), и
 * владелец величин, отвечающий о самом вызывающем (`/iam/v1/quotas`). Второй
 * интерфейс под ту же тройку чисел разошёлся бы с первым молча.
 */
export interface Quota {
  kind: string;
  limit: number;
  used: number;
  source_scope: string;
  source_scope_id: string;
  carrier_type: string;
  carrier_id: string;
}

/** Носитель-проект: «занято» относится к выбранному проекту. */
export const CARRIER_PROJECT = "project";

/**
 * Носитель-личность: «занято» относится к ЧЕЛОВЕКУ и одинаково во всех его
 * аккаунтах.
 *
 * Значение приезжает в `carrier_type` от владельца величин и совпадает с
 * литералом его схемы. Оно НЕ выводится из имени вида: `iam.account` и
 * `iam.project` неотличимы по форме, а носители у них разные.
 */
export const CARRIER_IDENTITY = "identity";

/**
 * Считается ли этот вид ПРОТИВ ПРЕДМЕТА СТРАНИЦЫ — то есть есть ли у строки
 * «занято», которое читателю этой страницы что-то говорит.
 *
 * ПРЕДМЕТ НАЗЫВАЕТ ВЫЗЫВАЮЩИЙ, а не выводится из ответа. Страница пределов
 * проекта спрашивает про проект, страница пределов личности — про личность, и
 * ответ одного владельца, показанный на чужой странице, «занято» не имеет:
 * число там настоящее, но оно не про то, что читатель открыл.
 *
 * Требуются ОБА признака, и они независимы:
 *
 *  1. **носитель назван предметом** (`carrier_type`). Аккаунтные виды
 *     (`iam.project`, `iam.user`) состоят из двух частей, но считаются
 *     аккаунтом — по одной лишь форме имени они прошли бы как проектные;
 *  2. **имя вида состоит из двух частей.** Три части означают вложенный вид по
 *     построению (форму имени закрепляет ограничение хранилища владельца).
 *     Второй признак нужен, пока проектные владельцы проставляют носителя
 *     КОНСТАНТОЙ «проект» всем строкам: без него четыре вложенных вида показали
 *     бы 0 как факт, а он там не факт, а просто не считается.
 *
 * Когда носитель станет приезжать верным, второй признак останется избыточным,
 * но не станет неверным: вложенный вид не назовут носителем-предметом.
 */
export function countedAgainst(q: Quota, subject: string = CARRIER_PROJECT): boolean {
  return q.carrier_type === subject && q.kind.split(".").length === 2;
}

