/**
 * Виды, которые витрина умеет назвать по-человечески.
 *
 * ВЫВОДИТСЯ из словаря выше, а не выписывается: второй перечень тех же имён
 * разошёлся бы с первым молча. Потребитель один и назван поимённо — гейт
 * согласия трёх полос (`test/console-quota-kind-named-like-the-entity.test.ts`):
 * он сверяет этот набор с каталогом владельца величин и со словарём подписей
 * сущностей. Прод-кода среди потребителей нет намеренно: показ ходит в
 * `kindLabel`, которому перечень не нужен.
 */
export const KNOWN_KINDS: readonly string[] = Object.keys(KIND_LABELS);

/**
 * Имя вида по-человечески; незнакомое — КАК ЕСТЬ.
 *
 * Каталог видов растёт на сервере, и витрина, знающая закрытый перечень, молча
 * теряла бы новые пределы — то есть ровно те, о которых арендатор ещё не знает и
 * в которые упрётся первым. Незнакомое имя не повод спрятать строку.
 */
export function kindLabel(kind: string): string {
  return KIND_LABELS[kind] ?? kind;
}

/** Кто задал действующее значение — и, значит, к кому идти его поднимать. */
export function sourceLabel(q: Quota): string {
  switch (q.source_scope) {
    case "DEFAULT":
      return "Платформенное умолчание";
    case "ACCOUNT":
      return `Аккаунт ${q.source_scope_id}`;
    case "PROJECT":
      return `Проект ${q.source_scope_id}`;
    default:
      // Молчаливый откат к «умолчанию» приписал бы платформе предел, который
      // задал кто-то другой, и увёл бы упёршегося не туда.
      return "Источник не назван";
  }
}

/** Чем ограничен вид, который считается не в проекте. */
function carrierLabel(q: Quota): string | null {
  if (countedInProject(q)) return null;
  if (q.carrier_type === "account") return "Считается в аккаунте";
  // Носитель-человек: аккаунты считаются по личности, через все её аккаунты
  // сразу. Без этой ветки строка показывала бы машинное слово «identity» —
  // `kindLabel` отдаёт незнакомое имя как есть, и здесь это было бы не
  // страховкой, а утечкой внутреннего словаря в клиентский текст.
  if (q.carrier_type === "identity") return "Считается на человека";
  const parentLabel = kindLabel(q.carrier_type);
  return `Считается в каждом: ${parentLabel}`;
}

export interface QuotaRow {
  kind: string;
  label: string;
  limit: number;
  /** `null` — значения нет вовсе; столбец обязан молчать, а не рисовать 0 или прочерк. */
  used: number | null;
  source: string;
  /** Чем ограничен вид, если не проектом. `null` — считается в проекте. */
  carrierLabel: string | null;
}

/**
 * Строки витрины в устойчивом порядке.
 *
 * Ответ порядка не обещает, а страница поллится: показанный «как пришёл» список
 * переставлялся бы под курсором читателя. Сортируем по имени вида — оно
 * неизменяемо, в отличие от значений.
 */
export function quotaRows(quotas: Quota[]): QuotaRow[] {
  return [...quotas]
    .sort((a, b) => a.kind.localeCompare(b.kind))
    .map((q) => ({
      kind: q.kind,
      label: kindLabel(q.kind),
      limit: q.limit,
      used: countedInProject(q) ? q.used : null,
      source: sourceLabel(q),
      carrierLabel: carrierLabel(q),
    }));
}
