/**
 * Имя вида по-человечески; незнакомое — КАК ЕСТЬ.
 *
 * Каталог видов растёт на сервере, и витрина, знающая закрытый перечень, молча
 * теряла бы новые пределы — то есть ровно те, о которых арендатор ещё не знает и
 * в которые упрётся первым. Незнакомое имя не повод спрятать строку.
 */
export function kindLabel(kind: string): string {
  return KIND_LABELS[kind] ?? kind;
}

/** Кто задал действующее значение — и, значит, к кому идти его поднимать. */
export function sourceLabel(q: Quota): string {
  switch (q.source_scope) {
    case "DEFAULT":
      return "Платформенное умолчание";
    case "ACCOUNT":
      return `Аккаунт ${q.source_scope_id}`;
    case "PROJECT":
      return `Проект ${q.source_scope_id}`;
    default:
      // Молчаливый откат к «умолчанию» приписал бы платформе предел, который
      // задал кто-то другой, и увёл бы упёршегося не туда.
      return "Источник не назван";
  }
}

/**
 * Носители, у которых есть СВОЁ имя, а не имя ресурса-родителя.
 *
 * Проект, аккаунт и личность — уровни аренды, а не виды ресурсов: подставить их
 * в оборот «считается в каждом» значило бы назвать уровень ресурсом («считается
 * в каждом: identity»). Перечень закрыт по построению — уровней три, и растёт он
 * миграцией, а не ответом.
 */
const CARRIER_LABELS: Record<string, string> = {
  [CARRIER_PROJECT]: "Считается в проекте",
  account: "Считается в аккаунте",
  [CARRIER_IDENTITY]: "Считается по всем вашим аккаунтам",
};

/** Чем ограничен вид, который считается не против предмета страницы. */
function carrierLabel(q: Quota, subject: string): string | null {
  if (countedAgainst(q, subject)) return null;
  const уровень = CARRIER_LABELS[q.carrier_type];
  if (уровень) return уровень;
  const родитель = kindLabel(q.carrier_type);
  return `Считается в каждом: ${родитель}`;
}

export interface QuotaRow {
  kind: string;
  label: string;
  limit: number;
  /** `null` — значения нет вовсе; столбец обязан молчать, а не рисовать 0 или прочерк. */
  used: number | null;
  source: string;
  /** Чем ограничен вид, если не проектом. `null` — считается в проекте. */
  carrierLabel: string | null;
}

/**
 * Строки витрины в устойчивом порядке.
 *
 * `subject` — носитель, ПРО КОТОРЫЙ открыта страница (умолчание — проект).
 * Он решает, у каких строк «занято» относится к читателю, а у каких столбец
 * обязан молчать, назвав носителя.
 *
 * Ответ порядка не обещает, а страница поллится: показанный «как пришёл» список
 * переставлялся бы под курсором читателя. Сортируем по имени вида — оно
 * неизменяемо, в отличие от значений.
 */
export function quotaRows(quotas: Quota[], subject: string = CARRIER_PROJECT): QuotaRow[] {
  return [...quotas]
    .sort((a, b) => a.kind.localeCompare(b.kind))
    .map((q) => ({
      kind: q.kind,
      label: kindLabel(q.kind),
      limit: q.limit,
      used: countedAgainst(q, subject) ? q.used : null,
      source: sourceLabel(q),
      carrierLabel: carrierLabel(q, subject),
    }));
}
