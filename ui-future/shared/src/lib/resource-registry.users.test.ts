// Столбцы страницы пользователей.
//
// Список пользователей ГЛОБАЛЕН (`scope: "global"`, `ListUsers` без сужения
// аккаунтом), а строка `users` — это ЧЛЕНСТВО: одна личность держит по строке
// на каждый аккаунт, и `account_id` у строки один по построению. Показать
// «аккаунты человека» столбец не может — такого поля нет ни на одном чтении
// контракта; единственный, кто перечисляет аккаунты человека, отвечает про
// СЕБЯ и наружу полем пользователя не выходит.
//
// Поэтому столбец снят (#473): жёсткое предусловие ветви «список аккаунтов» —
// «списочное чтение обязано заполнять это поле» — не выполнено by construction,
// и решение автоматически становится «убрать столбец». Ответ «к какому аккаунту
// относится это членство» остаётся на КАРТОЧКЕ пользователя, где значение одно,
// сверено прямым чтением и не повторяется в каждой строке.
//
// Отрицание здесь стоит В ПАРЕ с положительными контролями двух родов: столбцы
// самой страницы (иначе «нет Аккаунта» зеленело бы на пустом наборе колонок) и
// столбцы соседей по домену (иначе оно зеленело бы на сплошной зачистке слова
// из реестра — а у проекта, служебной учётки и группы аккаунт остаётся полем
// самого ресурса и снятию не подлежит).

import { REGISTRY } from "./resource-registry";

const headers = (specId: string): string[] => REGISTRY[specId].columns.map((c) => c.header);

describe("страница пользователей: столбец аккаунта", () => {
  it("столбца «Аккаунт» у пользователя нет", () => {
    // verifies #473
    expect(headers("users")).not.toContain("Аккаунт");
  });

  it("страница при этом СТОЛБЦЫ имеет — и те, ради которых её открывают", () => {
    expect(headers("users")).toEqual(
      expect.arrayContaining(["Эл. почта", "Статус", "ID"]),
    );
  });

  it("ни один столбец пользователя не читает поле аккаунта", () => {
    // Заголовок можно переименовать, а чтение оставить — тогда столбец вернулся
    // бы под другим именем. Утверждается ПОЛЕ, а не подпись.
    expect(REGISTRY.users.columns.map((c) => c.path)).not.toContain("account_id");
  });

  it("у проекта, служебной учётки и группы столбец аккаунта ОСТАЁТСЯ", () => {
    // Там аккаунт — поле самого ресурса, единственное и неизменяемое, а список
    // сужается аккаунтом запросом владельца. Предмет #473 к ним не относится.
    // Имя виновника попадает в вердикт значением, а не сообщением: `expect`
    // здесь второго аргумента не принимает вовсе (первая редакция его передала
    // и утверждение не исполнилось ни разу — падение было про подпись функции,
    // а не про реестр).
    const withAccount = ["projects", "service-accounts", "groups"].filter((id) =>
      headers(id).includes("Аккаунт"),
    );
    expect(withAccount).toEqual(["projects", "service-accounts", "groups"]);
  });
});
