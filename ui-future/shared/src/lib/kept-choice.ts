// Память поля подбора о СВОЁМ выборе (#528).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ
//
// Как только ввод уезжает на сервер, ответ края перестаёт быть «весь список» и
// становится «то, что совпало с введённым». Уже сделанный выбор в такой ответ
// попадать не обязан — и поле, у которого нет своей памяти, показывает вместо
// имени идентификатор (`net-…`): ровно то, что канон консоли, правило 2,
// запрещает. Значение формы при этом не теряется, теряется только его ИМЯ, и
// заметить это можно лишь глазами.
//
// ПОЧЕМУ НЕ ССЫЛКОЙ (`useRef`), ХОТЯ ТАК КОРОЧЕ
//
// Ссылка, которую пишут и читают ВО ВРЕМЯ рендера, — это состояние, спрятанное
// от React: при повторном или прерванном проходе рендера значение окажется не
// тем, и правило `react-hooks/refs` запрещает это не из вкусовщины. Здесь та же
// память сделана состоянием с обновлением в эффекте.
//
// ПОЧЕМУ КЛЮЧИ — СТРОКИ, А НЕ ОБЪЕКТЫ ВАРИАНТА
//
// Список вариантов пересобирается каждый рендер, поэтому у найденного варианта
// каждый раз новая идентичность. Память, обновляемая по такому объекту, писала
// бы состояние на каждый рендер — а запись состояния вызывает рендер: петля,
// которая не даёт ни одного падающего утверждения, а просто съедает память
// прогона (наблюдалось в этом дереве дважды за день, см. `ui.md`). Наружу
// торчат только строки: сравнение по значению исключает петлю by construction.
//
// ПОЧЕМУ ПРАВКА СОСТОЯНИЯ ВО ВРЕМЯ РЕНДЕРА, А НЕ В ЭФФЕКТЕ
//
// Это документированный приём React для состояния, ВЫВОДИМОГО из свойств:
// сеттер, вызванный в теле рендера того же компонента, заставляет React
// повторить рендер немедленно, ничего не показав между. Эффект здесь был бы
// хуже дважды: он выполняется ПОСЛЕ показа (то есть один кадр поле успевает
// показать идентификатор вместо имени) и запрещён правилом
// `react-hooks/set-state-in-effect` — по той же причине.
//
// Условие завершения обязательно и стоит перед каждым сеттером: без него
// «правка во время рендера» — это и есть петля.

import { useState } from "react";

/**
 * Метка выбранного значения, пережившая сужение списка.
 *
 * `label` — метка, найденная в ТЕКУЩЕМ ответе края, либо `null`, если её там
 * нет. Возвращает запомненную метку ровно тогда, когда выбор есть, а в ответе
 * его нет; в остальных случаях — `null`, и вызывающий показывает свежую.
 */
export function useKeptLabel(value: string | undefined | null, label: string | null): string | null {
  const [kept, setKept] = useState<{ value: string; label: string } | null>(null);

  if (value && label !== null && (kept?.value !== value || kept.label !== label)) {
    setKept({ value, label });
  }

  return value && label === null && kept?.value === value ? kept.label : null;
}

/**
 * Накопительная память имён: всё, что край когда-либо присылал этому полю.
 *
 * Нужна там, где выбор МНОЖЕСТВЕННЫЙ (метки-фишки): сузив список, край может не
 * прислать ни одного из уже выбранных, и каждая фишка выродилась бы в
 * идентификатор. Память не выкидывает ничего — цена одна строка на ресурс,
 * и она заведомо меньше цены запроса за именем каждого выбранного.
 */
export function useKeptLabels(entries: ReadonlyArray<readonly [string, string]>): (id: string) => string {
  const [memo, setMemo] = useState<Record<string, string>>({});

  // Новый объект собирается ТОЛЬКО когда есть что добавить, и сеттер зовётся
  // только тогда же. Безусловная запись здесь означала бы рендер на каждый
  // рендер: React сравнивает состояние по идентичности.
  let next: Record<string, string> | null = null;
  for (const [id, label] of entries) {
    if (id && memo[id] !== label) {
      next = next ?? { ...memo };
      next[id] = label;
    }
  }
  if (next) setMemo(next);

  const known = next ?? memo;
  return (id: string) => known[id] ?? id;
}
