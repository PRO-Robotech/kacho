// Алфавит id платформы — проверка сегмента адреса, пришедшего из ЧУЖОГО ответа
// (приёмка NTF-6 Р7, замысел З12).
//
// Строка ленты уведомлений несёт `resourceId` и `projectId`, и консоль строит из
// них адрес карточки (`resourceDetailHref`). Ответ пишет другая служба, и
// консоль не вправе полагаться на его форму: сегмент с косой, `..`, `?`, `#` или
// `%` увёл бы человека на другой адрес консоли. Поэтому сегмент передаётся в
// ссылку, только если он весь — в алфавите формы id платформы: строчные
// латинские буквы, цифры и дефис, первый знак — буква или цифра, длина не больше
// 64 (`api-conventions.md` `api-id-newid`, `api-hyphen-prefix`: приставка, дефис,
// crockford-base32 в нижнем регистре; слитная прежняя форма в тот же алфавит
// входит). Не прошедшее — имя текстом, без ссылки.
//
// Функция ОТБИРАЕТ, что передать единственному автору адреса, и адреса не строит.
// Кодирования сегмента вторым рубежом здесь нет намеренно: на принятом алфавите
// `encodeURIComponent` тождественен.

const PLATFORM_ID = /^[a-z0-9][a-z0-9-]{0,63}$/;

/** Сегмент — в алфавите формы id платформы (Р7). Не-строка — не id. */
export function isPlatformId(s: string): boolean {
  return typeof s === "string" && PLATFORM_ID.test(s);
}
