// Единственное место, где исход мутации превращается в сигнал пользователю.
//
// # Предмет
//
// Владелец 2026-08-15: «нужно унифицировать, чтобы каждое действие сигнализировало
// о выполнении или фейле». Наблюдение, из которого это выведено: на форме создания
// региона нажатие «создать» не показывало НИЧЕГО, при том что край отвечал отказом.
//
// Части для этого в дереве были — канал уведомлений (`toast`), разбор отказа
// (`error-presentation`), разбор исхода операции (`operation-outcome`), — а шва не
// было: каждое место складывало сообщение само. Отсюда три разные формы одного
// события («создан» · «готово» · «— готово») и места, где сообщения нет вовсе.
//
// # Почему исходов ТРИ, а не два
//
// Мутации Kachō асинхронные: `Create`/`Update`/`Delete` отвечают не ресурсом, а
// `Operation`, и клиент опрашивает её до `done=true` (`api-conventions.md`). Значит
// «запрос прошёл» и «действие выполнено» — РАЗНЫЕ события:
//
//	НЕ ПРИНЯТА    край отказал сразу (403/400/404/409) либо ответ не несёт операции
//	              там, где ресурс объявил, что несёт. Подтверждать нечем.
//	ПРИНЯТА       операция заведена и ещё идёт. Сигнал о приёме, не об исходе.
//	ЗАВЕРШЕНА     `done=true` — и только теперь видно, УДАЛАСЬ она или нет:
//	              операция вправе завершиться успехом приёма и отказом исполнения.
//
// Третий случай — тот, который легко упустить: сообщение «создан», выданное по
// факту приёма, будет ЛОЖЬЮ ровно там, где пользователю важнее всего правда.
// Разбор этих состояний уже написан и не переписывается — `operation-outcome.ts`.
//
// # Причина отказа берётся у края ДОСЛОВНО
//
// Тон сообщений сервера — часть контракта (`api-conventions.md` §Error-format), и
// придумывать свой текст поверх него значит показывать пользователю утверждение,
// которого край не делал. Здесь добавляется только огранка: подлежащее, отрицание
// и двоеточие.
//
// # Чего этот модуль НЕ делает
//
// Он не рендерит. Сигнал уходит в `toast`, а его показывает `Toaster`, который
// обязан быть примонтирован в модуле. Модуль без `Toaster` глотает КАЖДЫЙ сигнал
// молча — именно так и выглядела находка владельца.

import type { Gender } from "@shared/lib/entity-names";
import { ENTITIES } from "@shared/lib/entity-names";

/** Глагол мутации. Иных у ресурса нет: контракт знает Create/Update/Delete. */
export type MutationVerb = "create" | "update" | "delete";

/** О чём сообщаем: подпись ресурса, её род и (если есть) имя экземпляра. */
export interface MutationSubject {
  /** Подпись ресурса, как её видит пользователь: «Облачная сеть». */
  label: string;
  /** Род `label` — объявленный, не выведенный (см. `entity-names.ts`). */
  gender: Gender;
  /** Имя экземпляра: «net-1». Пусто там, где имени ещё/уже нет. */
  name?: string | null;
}

/**
 * Причастие совершённого действия, согласованное по роду.
 *
 * Таблица выписана, а не собрана из корня и окончания: «удалён» отличается от
 * «удален» буквой, которую генератор бы потерял, а читатель заметил.
 */
const PARTICIPLE: Record<MutationVerb, Record<Gender, string>> = {
  create: { m: "создан", f: "создана", n: "создано" },
  update: { m: "обновлён", f: "обновлена", n: "обновлено" },
  delete: { m: "удалён", f: "удалена", n: "удалено" },
};

/**
 * Действие в процессе. Возвратная форма настоящего времени по роду НЕ меняется —
 * поэтому у неё одна ячейка на глагол, а не три.
 */
const PROGRESSIVE: Record<MutationVerb, string> = {
  create: "создаётся",
  update: "обновляется",
  delete: "удаляется",
};

/** «Облачная сеть net-1» — подлежащее сообщения. */
function subjectText(subject: MutationSubject): string {
  const name = subject.name?.trim();
  return name ? `${subject.label} ${name}` : subject.label;
}

/** «Облачная сеть net-1 создана». */
export function mutationSuccessText(verb: MutationVerb, subject: MutationSubject): string {
  return `${subjectText(subject)} ${PARTICIPLE[verb][subject.gender]}`;
}

/**
 * «Облачная сеть net-1 не создана: <причина от края>».
 *
 * Пустая причина не превращается в «не создана: » с висящим двоеточием: отсутствие
 * текста у края — не повод показать пунктуацию вместо сообщения.
 */
export function mutationFailureText(verb: MutationVerb, subject: MutationSubject, reason: string): string {
  const head = `${subjectText(subject)} не ${PARTICIPLE[verb][subject.gender]}`;
  const r = reason.trim();
  return r ? `${head}: ${r}` : head;
}

/** «Облачная сеть net-1 создаётся…» */
export function mutationPendingText(verb: MutationVerb, subject: MutationSubject): string {
  return `${subjectText(subject)} ${PROGRESSIVE[verb]}…`;
}

/**
 * Род подписи — точным поиском в таблице, которая эту подпись и объявила.
 *
 * Это ПОИСК, а не вывод из строки: морфологическая догадка по окончанию здесь
 * запрещена (`entity-names.ts`), а сверка значения с породившим его словарём —
 * обычный резолв. `undefined` означает «подпись пришла не из словаря», и это
 * находка, а не повод угадать: её ловит проба `mutation-signal.test.ts`.
 */
export function genderOfLabel(label: string): Gender | undefined {
  for (const e of Object.values(ENTITIES)) {
    if (e.singular === label) return e.gender;
  }
  return undefined;
}

/**
 * Чем ресурс называет себя в сообщении о мутации: подпись, а если её нет — сам
 * идентификатор.
 *
 * Подпись есть не у всех. У каталога размещения (регион, зона) её нет вовсе:
 * идентификатор назначает администратор и он человекочитаем by construction, а
 * второе поле того же назначения снято (#716). Без этого запасного шага
 * сообщение вырождалось в безличное «Регион не создан», не называя, КАКОЙ, —
 * при том что оператор только что ввёл его идентификатор своими руками.
 *
 * Порядок именно такой: где подпись есть, она и остаётся подлежащим.
 */
export function subjectNameOf(body: Record<string, unknown>): string | null {
  const name = body.name;
  if (typeof name === "string" && name.trim() !== "") return name;
  const id = body.id;
  return typeof id === "string" && id.trim() !== "" ? id : null;
}

/**
 * Подлежащее из спеки ресурса.
 *
 * Запасной род существует, чтобы отсутствие объявления не роняло экран, — но
 * приземлиться незамеченным он не может: проба требует, чтобы КАЖДАЯ запись
 * реестра резолвилась без него.
 */
export function subjectOfSpec(spec: { singular: string }, name?: string | null): MutationSubject {
  return { label: spec.singular, gender: genderOfLabel(spec.singular) ?? "m", name };
}
