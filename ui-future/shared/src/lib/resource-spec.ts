// Форма описания ресурса — ОДНО объявление на всю консоль.
//
// Здесь живут `ResourceColumn`, `ListFilter` и `ResourceSpec`: типы, которыми
// generic ListPage / DetailShell / Create-Edit читают любой ресурс. Реестры
// (`resource-registry.tsx`) у приложений остаются СВОИ — они несут содержимое
// (какие ресурсы, какие колонки и поля), — но ФОРМУ импортируют отсюда и не
// объявляют у себя.
//
// Почему форма вынесена (KAC #132). Прежде она была выписана в пяти файлах:
// в общем реестре и по копии у compute / nlb / registry / storage. Копии
// разошлись — и разошлись МОЛЧА, потому что сверять их было нечем:
//   · `admin`, `mutationsReturnOperation`, `listFilters` были только в общей;
//   · `facet`, `loadAllPages` — только в трёх приватных;
//   · комментарий у `immutable?` в `form-schema.ts` существовал в ТРЁХ разных
//     редакциях, из которых верна была одна.
// Обнаружилось это не проверкой, а падением сборки сразу трёх приложений: проба
// `dev-proxy.test.ts` читала `spec.admin`, которого в их форме не было. То есть
// первым о расхождении узнал не автор правки, а тот, кто через неделю чинил
// чужую сборку.
//
// Что изменилось по существу: расхождение форм теперь НЕВЫРАЗИМО — объявление
// одно, и второго места, где его можно было бы завести, нет. Реэкспорт формы
// приложением (`export type { ResourceSpec } from "@shared/lib/resource-spec"`)
// расхождения не создаёт: у реэкспорта нет тела, он следует за источником сам.
// Повторное ОБЪЯВЛЕНИЕ — создаёт, и его ловит `scripts/check-resource-spec-single-source.mjs`.

import type { ReactNode } from "react";
import type { FormField } from "./form-schema";

export interface ResourceColumn {
  header: string;
  /**
   * Значение занимает НЕСКОЛЬКО СТРОК (набор адресов, набор ссылок) и обрезке
   * в одну строку не подлежит.
   *
   * Объявляется явно, а не выводится из `format`: такие колонки рисуют своим
   * `render`, и формата у них нет вовсе — вывод по формату молча пропустил бы
   * ровно те колонки, ради которых признак и заведён.
   */
  multiline?: boolean;
  // Путь в плоском объекте: "name", "status", "zone_id"
  path: string;
  format?: "text" | "uid-short" | "datetime" | "status" | "code" | "list" | "references" | "bool";
  className?: string;
  render?: (row: Record<string, unknown>) => ReactNode;
  /** Что означают истина и ложь — ФРАЗОЙ ПРЕДМЕТА, не «Да»/«Нет» (правило 6
   *  `ui.md`). Обязательно при `format:"bool"`: назвать следствие может только
   *  тот, кто знает предмет, поэтому умолчания у подписей нет — оно вернуло бы
   *  ровно тот дефект, ради которого формат заведён. Отсутствие подписей —
   *  находка гейта `spec-columns.bool-labels`, а не повод напечатать «Да». */
  boolLabels?: { yes: string; no: string };
}

/** Фильтр списка, отправляемый в query-параметре (server-side, см. `listFilters`). */
export type ListFilter =
  | { kind: "toggle"; param: string; label: string; description?: string }
  | { kind: "ref"; param: string; label: string; refSpecId: string; allLabel: string };

/** Связанный дочерний ресурс — вкладка со встроенной таблицей в `ResourceShell`.
 *
 *  `childId` — ключ ребёнка в реестре; `filterField` — поле(я) ребёнка, ссылающееся
 *  на этого родителя (клиентское сужение; массив = ИЛИ по нескольким полям, напр.
 *  подсеть→адреса v4∪v6); `label` — заголовок вкладки (по умолчанию множественное
 *  число ребёнка).
 *
 *  КТО сужает список — ровно один из двух серверных механизмов ниже либо никто.
 *  Оба сразу объявить нельзя: тип это запрещает (`never`), поэтому противоречие
 *  «выражением ИЛИ параметром» не представимо и не решается втихую тем, что одна
 *  ветка кода выиграла у другой. */
export type RelatedSpec = {
  childId: string;
  filterField: string | string[];
  label?: string;
} & (
  | {
      /** Имя поля в белом списке выражения `filter` ВЛАДЕЛЬЦА ребёнка. Объявлено —
       *  вкладка просит `filter=<поле>="<id родителя>"`, и сужает СЕРВЕР.
       *
       *  Отличие от `filterField` существенно и не косметично, даже когда имена
       *  совпадают текстуально: `filterField` — путь в СТРОКЕ ответа (может быть
       *  вложенным), и фильтрует КЛИЕНТ, то есть только то, что успело приехать.
       *
       *  Список владельца ЗАКРЫТ: поле вне него — не «фильтр без эффекта», а
       *  `InvalidArgument` на всю вкладку. Паритет держит
       *  `related-server-filter-parity.test.ts` (читает белые списки из прод-кода
       *  сервиса), форму запроса — `ResourceShell.related.test.tsx`. */
      serverFilterField?: string;
      serverParamField?: never;
    }
  | {
      /** Имя ТИПИЗИРОВАННОГО поля списочного запроса владельца ребёнка (напр.
       *  `subnet_id` у адреса). Объявлено — вкладка передаёт его отдельным
       *  параметром запроса, и сужает СЕРВЕР.
       *
       *  Это ДРУГОЙ механизм, а не синоним выражения `filter`, и выбор между ними
       *  делает ВЛАДЕЛЕЦ, а не консоль: выражение разбирается по белому списку имён
       *  КОЛОНОК, поэтому ссылка, которой у владельца нет отдельной колонкой, им не
       *  выражается вовсе. Адрес — ровно этот случай: подсеть лежит внутри jsonb и
       *  в двух семьях, поэтому у него сужение по подсети — типизированное поле
       *  запроса.
       *
       *  Паритет с владельцем держит `related-server-param-parity.test.ts` (читает
       *  контракт и его читателя из дерева сервиса), форму запроса —
       *  `ResourceShell.related.test.tsx`. */
      serverParamField?: string;
      serverFilterField?: never;
    }
);

/**
 * Что предложить действием-глаголом НА КОНКРЕТНОЙ СТРОКЕ.
 *
 * Состояние строки — предмет, а не оформление: предлагать «запретить» уже
 * запрещённому значит предлагать вызов, который ничего не изменит. Поэтому
 * действие ВЫБИРАЕТСЯ по строке, а не показывается парой пунктов.
 */
export interface RowVerbState {
  /** Подпись пункта меню — она же называет, что произойдёт. */
  label: string;
  /** Значок пункта. */
  icon?: ReactNode;
  /**
   * Действие к этой строке неприменимо, и это ПРИЧИНА — она показывается
   * подсказкой. Пункт остаётся видимым: скрытый пункт неотличим от
   * несуществующей возможности, и пользователь ищет её там, где её нет.
   */
  disabledReason?: string;
  /**
   * Путь глагола у края (`…/{id}:verb`).
   *
   * Литерал строит ВЛАДЕЛЕЦ ресурса — то есть файл реестра, а не общий вид.
   * Причина не косметическая: перепись глаголов консоли
   * (`console-verb-routes-exist.test.ts`) резолвит голову литерала в объявление
   * реестра и сверяет получившийся путь с `google.api.http` контракта. Спрятав
   * путь за общий сборщик, мы вывели бы действие из-под этого надзора — и
   * снятый с контракта глагол остался бы живой кнопкой.
   */
  path: string;
  /** Заголовок окна подтверждения. */
  confirmTitle: string;
  /** Текст окна подтверждения — он обязан называть ЦЕНУ, а не пересказывать подпись. */
  confirmText: string;
  /** Подпись подтверждающей кнопки. */
  okText: string;
  /** Подтверждение красное — необратимое либо отнимающее доступ действие. */
  danger?: boolean;
  /** Заголовок сообщения о ходе и исходе: «Запрет участия». */
  progressTitle: string;
  /**
   * Тело запроса, когда глагол его ТРЕБУЕТ.
   *
   * У большинства глаголов предмет назван самим путём (`…/{id}:block`), и тело
   * им не нужно. Исключение из аккаунта — не такой: его предмет ПАРА (человек и
   * аккаунт), у человека аккаунтов бывает несколько, и вывести второй половиной
   * из первой нельзя — вывелся бы не тот аккаунт. Поэтому она называется телом.
   */
  body?: unknown;
}

/** Что общий вид знает о вызывающем, когда решает состав действий строки. */
export interface RowVerbContext {
  /**
   * Идентификатор строки ВЫЗЫВАЮЩЕГО — чтобы предупредить о действии над собой
   * ДО нажатия. `undefined`, когда личность ещё не прочитана: тогда особого
   * предупреждения не будет, но действие останется доступным.
   */
  selfId?: string;
  /**
   * Аккаунт, в области которого читается список. `undefined`, когда область не
   * выбрана.
   *
   * Нужен глаголам, чей предмет — ПАРА «человек × аккаунт» (исключение из
   * аккаунта). Такой глагол обязан вернуть `null`, пока аккаунт неизвестен:
   * пункт, который отправил бы запрос без половины предмета, хуже отсутствующего.
   */
  accountId?: string;
}

/**
 * Действие-глагол на строке списка (`POST …/{id}:verb`).
 *
 * Отличие от `ops.update`/`ops.delete` существенно: у глагола НЕТ маски полей,
 * поэтому «забыть поле» и задеть им всех, кого коснулся, здесь невозможно by
 * construction. Права решает край; консоль ничего не предугадывает.
 */
export interface RowVerb {
  /** Ключ пункта меню — уникален в пределах ресурса. */
  key: string;
  /** Что предложить на ЭТОЙ строке. `null` — действие к строке не относится вовсе. */
  resolve: (row: Record<string, unknown>, ctx: RowVerbContext) => RowVerbState | null;
}

export interface ResourceSpec {
  id: string;
  // route path в SPA (без leading slash)
  route: string;
  // Полный URL-path для REST: /<domain>/v1/<plural>
  // Verbatim из proto google.api.http annotations.
  apiPath: string;
  // ключ массива в List response: "networks", "projects"
  payloadKey: string;
  // singular label для UI
  singular: string;
  // plural label
  plural: string;
  // родительный падеж ед.ч. («Обзор шлюзА», «Операции сетИ») — заголовок
  // мастер-ресурса в зоне-3 (обзор/операции/json). Fallback: plural.
  genitive?: string;
  // винительный падеж ед.ч. со строчной буквы («Создать облачнУЮ сетЬ»,
  // «Создать пользователЯ») — подписи действий. Родительный сюда НЕ подходит:
  // он собран для другой конструкции и дал бы «Создать облачной сети».
  // Выводить падеж из строки нельзя — окончание не решает одушевлённость, а
  // ошибка вывода тиха; поэтому форма объявляется, и гейт требует объявления от
  // каждого ресурса (`lib/resource-label.test.ts`).
  accusative?: string;
  description?: string;
  /** Service-domain заголовок (отображается в breadcrumb перед именем категории).
   *  Примеры: "Virtual Private Cloud", "IAM", "Администрирование". */
  serviceTitle?: string;
  // global = cluster-scoped, project = в выбранном Project, account = в выбранном Account
  scope: "global" | "project" | "account";
  /**
   * У ресурса НЕТ отдельной подписи: идентификатор назначает человек, и он и
   * есть имя. Сегодня это каталог размещения geo — регион и зона (#716).
   *
   * Читает это `ResourceLink`, и читает ради ровно одного: идентификатор такого
   * ресурса показывается ЦЕЛИКОМ. Общее правило обрезает идентификатор до 12
   * знаков, потому что машинный крокфордов идентификатор длинен и его хвост
   * читателю ничего не говорит. У слага всё наоборот — значение несёт как раз
   * хвост: `ru-central1-a` обрезалось до `ru-central1-…`, и ВСЕ шесть зон
   * региона выглядели на экране одинаково, то есть ссылка переставала называть,
   * куда ведёт.
   *
   * Флаг объявляется, а не выводится из состава колонок: «колонки `name` нет»
   * верно и у ресурса, чью подпись просто не показывают в списке, — а это
   * другое утверждение.
   */
  idIsTheName?: boolean;
  // поддерживаемые операции (кнопки действий рендерятся по этим флагам)
  ops: {
    create: boolean;
    update: boolean;
    delete: boolean;
    restart?: boolean;
    start?: boolean;
    stop?: boolean;
  };
  /**
   * ПОЧЕМУ `ops` говорят «нет» там, где край публично обслуживает глагол.
   *
   * Заводится ровно на такой паре. Молчаливое «нет» в ней читается клиентом как
   * свойство ПЛАТФОРМЫ, а не как устройство консоли: он ищет возможность в
   * документации, не находит и заключает, что её нет вовсе. Так и было у
   * репозитория реестра (#1593) — консоль объявляла его read-only, пока контракт
   * нёс полный CRUD, а `visibility` оставался единственным рычагом публикации
   * образа.
   *
   * Законных ответов ДВА, и они разные:
   *   · глагол ДАН, но не общей формой — своей страницей раздела. Тогда `ops`
   *     говорят «нет» про механизм, а не про возможность;
   *   · глагол НЕ ДАН — тогда причина обязана называть ПРЕПЯТСТВИЕ, измеренное,
   *     а не намерение: «пока не сделали» не сообщает читателю ничего, чего он
   *     не видел бы сам.
   *
   * Держит это гейт `shared/src/test/console-ops-match-contract`: он сверяет
   * адреса спеки с `google.api.http` контракта и требует причину у каждой
   * необъяснённой пары.
   */
  mutationsNotOffered?: string;
  // колонки для list-таблицы
  columns: ResourceColumn[];
  /**
   * Действия-глаголы на строке списка. Объявляются ЗДЕСЬ, а не отдельной
   * страницей ресурса: страница мимо общей оболочки расходится с ней в первый
   * же день (у пользователя такая уже была — она не рендерилась ни одним
   * маршрутом, и вместе с ней с экрана ушли оба глагола запрета участия).
   */
  rowVerbs?: RowVerb[];
  // schema полей формы (если undefined — fallback к JSON-editor)
  fields?: FormField[];
  // Path-template для drill-down link при клике на строку (плейсхолдер `:id`).
  // Если задан — кнопка в строке ведёт сюда вместо DetailPage. Используется
  // для иерархического drill-flow Account → Projects → VPC.
  childRoute?: string;
  // skeleton-объект для Create-формы.
  // projectId — выбранный Project (VPC/Compute scope).
  // accountId — выбранный Account (kaname.cloud.iam.v1.Project.account_id).
  template: (ctx: { projectId?: string; accountId?: string }) => unknown;
  // Опциональная нормализация payload перед отправкой на API.
  // Используется для конвертации form-internal представления (wrapper-объекты, toggle-поля)
  // в wire format (plain arrays, oneof etc.).
  sanitize?: (obj: Record<string, unknown>) => Record<string, unknown>;
  /** Обратная sanitize: wire → form. Вызывается InlineResourceEditForm перед
   *  установкой initial form-state. Используется когда у формы есть array-of-ref
   *  или array-of-string поля, для которых wire-format = массив строк, а
   *  form-format = массив объектов `{value: "..."}` (см. NIC v4/v6_address_ids
   *  / security_group_ids; Subnet v4/v6_cidr_blocks). Без hydrate-адаптера
   *  RefSelect получает массив строк вместо объектов и не отображает
   *  выбранные значения в edit-режиме. */
  hydrate?: (obj: Record<string, unknown>) => Record<string, unknown>;
  /** Клиентская pre-submit валидация формы (form-values → сообщение об ошибке |
   *  null). Возвращает первый нарушенный инвариант (напр. IAM-1: Role.rules[]
   *  non-empty, definitionTier XOR); null = ок. Дополняет per-field required —
   *  для кросс-полевых/структурных гейтов. Используется и для инвариантов,
   *  которые backend отверг бы асинхронно через 1-2с (напр. LB: хотя бы одно
   *  семейство VIP включено). */
  validate?: (obj: Record<string, unknown>) => string | null;
  /** Path-template для internal/infra-проекции ресурса (плейсхолдер `{id}`).
   *  Если задан — на DetailPage появляется tab "jsonint", который делает
   *  GET <internalGetPath с подставленным {id}> и pretty-print'ит JSON-ответ.
   *  Пример: "/vpc/v1/networks/{id}:internal" — форма ГЛАГОЛЬНАЯ, через
   *  двоеточие: так объявлена единственная :internal-аннотация vpc
   *  (`InternalNetworkService.GetNetwork`). Прежний пример показывал слэшевую
   *  форму `/{id}/internal`, которой на поверхности нет, — и по образцу такое
   *  поле завели ещё раз.
   *  Поле ставится ТОЛЬКО когда у Internal*-сервиса есть http-аннотация:
   *  `InternalNetworkInterfaceService` её не имеет вовсе (pure gRPC
   *  service→service), поэтому вкладки internal у NIC быть не может.
   *  Большинство ресурсов поля не имеют. */
  internalGetPath?: string;
  /** Admin-плоскость ресурса (`Internal*`-сервис на cluster-internal listener).
   *  `apiPath` остаётся поверхностью ЧТЕНИЯ; когда задан `admin`, Create/Update/
   *  Delete уходят на `admin.basePath`. Нужно там, где публичный путь мутации
   *  вообще не смаршрутизирован — geo Region/Zone читаются на /geo/v1/{regions,
   *  zones}, а меняются на /geo/v1/internal/…; POST на публичный путь не
   *  обслуживается никем.
   *
   *  `readForEdit` — читать начальное состояние формы редактирования с
   *  `admin.basePath/{id}` (GetInternal): у двухпроекционного ресурса мутируемые
   *  поля (`status`, `infra°`) на публичной проекции отсутствуют, и форма,
   *  заполненная публичным чтением, показала бы оператору пустое поле там, где
   *  на самом деле есть значение. */
  admin?: { basePath: string; readForEdit?: boolean };
  /** Мутации ресурса отвечают `operation.Operation` — **умолчание, а не
   *  пожелание**: этого требует ban #9. Ответ без operation-id есть нарушение
   *  контракта, а не синхронный успех, и страница говорит об этом вместо того,
   *  чтобы отрапортовать «готово». Существенно потому, что internal-листенер не
   *  эмитит нулевые значения: Operation с `done=false` приходит вообще без ключа
   *  `done`.
   *
   *  УМОЛЧАНИЕ ПЕРЕВЁРНУТО 2026-08-15. Признак читался как `=== true`, то есть
   *  строгость включалась по желанию. Замер по дереву: спек **50**, признак стоял
   *  у **двух**. Для остальных сорока восьми «операции не пришло» молча читалось
   *  как «сделано» — при том что контракт требует обратного.
   *
   *  ЯВНОЕ ПОСЛАБЛЕНИЕ (`false`) — только там, где сервер честно отвечает
   *  ресурсом. По контракту таких путей ровно два, оба административные:
   *  `/vpc/v1/addressPools` и `/storage/v1/diskTypes`. Предикат — разбор
   *  `rpc … returns (…)` по дереву контрактов, не память; повторяется поиском
   *  мутирующих RPC, чей ответ не `operation.Operation`.
   *
   *  ЗЕРНИСТОСТЬ НАЗВАНА ЧЕСТНО: признак живёт на **ресурсе**, а синхронность
   *  бывает у **отдельного глагола** — сеть асинхронна по CRUD, но её
   *  «назначить группой по умолчанию» отвечает ресурсом. Такие глаголы идут
   *  своими компонентами и передают `expectOperation` явно, не спрашивая спеку. */
  mutationsReturnOperation?: boolean;
  /** Фильтры списка, уезжающие в query — то есть применяемые НА СЕРВЕРЕ, ко
   *  всему списку, а не к загруженной странице. Клиентский фильтр поверх
   *  курсорной страницы отфильтровал бы то, что успело приехать, и выдал бы
   *  результат за полный. */
  listFilters?: ListFilter[];
  /** Поле поиска над списком: по чему ищет и кто сужает.
   *
   *  Умолчание (спека молчит) — сужение НА КЛИЕНТЕ по `name` и `id`. Оно годится
   *  ровно там, где имя у ресурса есть и список короткий: клиент видит только
   *  загруженную страницу и обо всём, что за курсором, отвечает «нет такого».
   *
   *  `serverTerm` переводит поиск НА СЕРВЕР: ввод уезжает выражением
   *  `<serverTerm>="<ввод>"` в параметр `filter`, и ответ показывается как есть —
   *  повторно резать его у клиента нельзя, иначе сузим ответ сервера по полям,
   *  которых он не спрашивал.
   *
   *  `placeholder` обязателен, потому что подпись поля — часть контракта с
   *  пользователем: она называет то, ПО ЧЕМУ ищут. У пользователя, например,
   *  имени нет вовсе, и обещание «по имени» описывало бы несуществующее.
   *
   *  `fields` — поля клиентского сужения, если умолчание `name`/`id` не подходит;
   *  при заданном `serverTerm` не читается (сужает сервер).
   *
   *  ОТЛИЧИЕ ОТ `serverSearchField` (ниже) — в том, ЧТО уезжает на сервер, и это
   *  не косметика. `serverTerm` — ВЫДЕЛЕННОЕ слово запроса, которое владелец
   *  толкует сам (`search="…"` у пользователя: почта или идентификатор, имени у
   *  него нет вовсе); `serverSearchField` — НАСТОЯЩЕЕ поле ресурса, по которому
   *  ищут подстроку (`name CONTAINS "…"`). Разные операторы и разные предметы,
   *  поэтому ключа два, а не один.
   *
   *  Объявлять оба на одном ресурсе ЗАПРЕЩЕНО: получилось бы два выражения об
   *  одном вводе, и какое уедет — решал бы порядок чтения кода. `ResourceListPage`
   *  разрешает это детерминированно (выигрывает `serverTerm`), но полагаться на
   *  разрешение вместо запрета не надо. */
  search?: { placeholder: string; serverTerm?: string; fields?: string[] };

  /**
   * Поле, которым строка поиска списка спрашивает СЕРВЕР (`filter=<поле> CONTAINS "…"`).
   *
   * Не объявлено — поиск остаётся клиентским и судит только о ПРОЧИТАННЫХ
   * страницах; строка ввода обязана называть это сама (см. `ResourceListPage`).
   *
   * Объявлять можно, только когда владелец удовлетворяет ОБОИМ условиям, и они
   * разные:
   *
   *  1. поле стоит в его белом списке выражения (`filter.Parse(…, []string{…})`) —
   *     иначе запрос вернёт `InvalidArgument` на всю страницу;
   *  2. владелец применяет разобранный узел через `ToSQL` — а не забирает из него
   *     одно значение. Забирающий значение теряет ОПЕРАТОР: подстрока молча
   *     превратится в точное равенство, и поиск станет отвечать «ничего не
   *     найдено» на любой неполный ввод. Второе условие не выводится из первого и
   *     на ревью не видно вовсе.
   *
   * Сходимость объявления с деревом владельца по обоим условиям держит
   * `lib/list-server-search-parity.test.ts`; он же роняет объявление, чей
   * владелец перестал их выполнять.
   */
  serverSearchField?: string;
  /** Facet-фильтр списка (client-side по значению уже загруженного поля): напр.
   *  тип артефакта образа. Рендерит Select рядом с поиском и фильтрует
   *  загруженные строки. Отличие от `listFilters` существенно и не косметично:
   *  тот уезжает в query и потому судит обо ВСЁМ списке, а этот — только о том,
   *  что приехало на страницу. Поэтому facet осмыслен в паре с `loadAllPages`
   *  либо на заведомо коротких path-scoped списках. */
  facet?: { path: string; label: string; options: { value: string; label: string }[] };
  /** Грузить ВСЕ страницы списка (follow next_page_token) до рендера — чтобы
   *  client-side facet видел полный набор (path-scoped дети, напр. образы). */
  loadAllPages?: boolean;
  /** KAC-233: связанные дочерние ресурсы — отдельные табы со встроенными
   *  таблицами в ResourceShell. childId — ключ ребёнка в REGISTRY; filterField —
   *  поле(я) ребёнка, ссылающееся на этот ресурс (client-side фильтр; массив =
   *  OR по нескольким полям, напр. subnet→addresses v4∪v6). label —
   *  переопределение заголовка таба (по умолчанию childSpec.plural). */
  related?: RelatedSpec[];
  /** KAC-233: ссылки на документацию по типу ресурса (блок «Документация» в
   *  aside DetailShell). Kachō-style. */
  // ПОЛЕ `docs` СНЯТО ЦЕЛИКОМ (#1611), и это завершение уже принятого решения,
  // а не новое: два ресурса storage сняли свои объявления раньше, назвав причину
  // в комментарии, — остальные четырнадцать остались.
  //
  // Читателя у поля не было НИ ОДНОГО: темы пустого списка приезжают из
  // `emptyState.docs` (строки), а боковая панель берёт их у своего модуля, и ни
  // один модуль `spec.docs` в навигацию не отдавал. Все объявления несли
  // `href: "#"` — адрес, ведущий на ту же страницу.
  //
  // Снято, а не оставлено «до появления адресов», по двум причинам. Поле формы
  // ссылки приглашает «починить» его одной живой строкой — и ничего не
  // произойдёт, потому что читателя нет. И адреса взяться неоткуда: сайты
  // документации собираются гейтом конвейера, но не публикуются ни одним
  // профилем развёртывания — ни чарта, ни ingress, ни шага публикации. Появится
  // адрес — темы станут ссылками в ДВУХ местах показа, а не в сорока четырёх
  // объявлениях.
  /** KAC-233: welcome-копирайт для пустой таблицы этого ресурса (когда он
   *  показан как ребёнок и список пуст). Kachō-style. */
  emptyState?: { title: string; body: string; docs?: string[] };
}
