/** Ярус словами. Незнакомое значение показывается САМИМ значением: выдумывать
 *  ему подпись значило бы утверждать о классе то, чего контракт не говорил, а
 *  проглотить — скрыть, что словарь пополнился раньше консоли. */
export function tierLabel(v: unknown): string | null {
  const raw = typeof v === "string" ? v : "";
  if (!raw) return null;
  return TIER_LABEL[raw] ?? raw;
}

// ──────────────────── состояние обращения класса ────────────────────

/** Состояние обращения — СЛЕДСТВИЕМ, а не токеном перечисления. Вопрос у него
 *  ровно один: принимает ли класс НОВЫЕ тома. Существующие тома живут при любом
 *  значении, и подписи обязаны это показывать, иначе «Выведен из обращения»
 *  читается как «мои тома пропали». */
export const LIFECYCLE_LABEL: Record<string, string> = {
  LIFECYCLE_UNSPECIFIED: "Не объявлено",
  ACTIVE: "Принимает новые тома",
  DEPRECATED: "Новые тома не создаются",
  RETIRED: "Выведен из обращения",
};

export const LIFECYCLE_HINT: Record<string, string> = {
  LIFECYCLE_UNSPECIFIED: "Состояние обращения не названо.",
  ACTIVE: "На этом типе диска можно создать том.",
  DEPRECATED:
    "Уже созданные тома работают и обновляются; новый том на этом типе создать нельзя.",
  RETIRED: "Тип снят с обращения. Уже созданные тома продолжают работать.",
};

export function lifecycleLabel(v: unknown): string | null {
  const raw = typeof v === "string" ? v : "";
  if (!raw) return null;
  return LIFECYCLE_LABEL[raw] ?? raw;
}

/**
 * Принимает ли класс новые тома.
 *
 * Спрашивают ЗДЕСЬ, а не сравнивают с "ACTIVE" по месту: сравнений было бы
 * столько же, сколько мест, и следующее значение словаря пришлось бы вносить в
 * каждое. Молчание сервера (поле не пришло) — НЕ «принимает»: неизвестное
 * состояние не превращаем в разрешение.
 */
export function acceptsNewVolumes(lifecycle: unknown): boolean {
  return lifecycle === "ACTIVE";
}

