// место, где консоль решает, как назвать значение этих перечислений.
//
// # Почему в @shared, а не в приложении storage
//
// Два разных места консоли произносят эти слова: карточка типа диска (remote
// storage) и подпись опции в подборщике (`refOptionExtra`, живущий здесь и
// переиспользуемый всеми приложениями). Держать словарь в приложении значило бы
// завести два места об одном предмете — и разошлись бы они на первом же
// уточнении формулировки, причём молча: обе стороны продолжали бы показывать
// что-то правдоподобное.
//
// # Почему таблица, а не печать значения как есть
//
// Контракт заменил свободную строку яруса закрытым словарём именно затем, чтобы
// наружу не уходил текст бэкенда: гейт двухпроекционности перечисляет ИМЕНА
// полей, и значение вида "pool-b-replicated" проходило сквозь него целиком.
// Печать значения как есть вернула бы этот канал уже в интерфейсе.
//
// # Правило 6 канона консоли
//
// `CAPABILITIES` держит ПАРУ фраз на каждую способность: что означает истина и
// что означает ложь, обе — словами предмета. «Да» рядом с подписью «Снимки» не
// говорит ни что снимки можно снимать, ни что нельзя.

