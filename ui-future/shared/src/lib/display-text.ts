// Единственное место, где консоль превращает значение строки API в текст.
//
// Зачем отдельная функция вместо `String(v)`. Строка ответа — `Record<string,
// unknown>`: у ресурсов Kachō поле бывает вложенным объектом
// (`internal_ipv4_address`), картой (`labels`) или списком. `String(объект)`
// даёт `[object Object]` — один и тот же текст для любого объекта, поэтому
// ячейка таблицы, подстрока поиска и ключ сортировки переставали различать
// значения вообще, а пользователь видел слово, из которого ничего не следует.
//
// Решение принимается здесь, а не в каждом вызывающем: иначе «как показать
// нескаляр» отвечалось бы в двух десятках мест по-разному.

/**
 * Текстовое представление произвольного значения строки API для показа
 * человеку, поиска и сравнения.
 *
 * Отсутствие значения — пустая строка (а не `"null"`/`"undefined"`): вызывающие
 * различают «пусто» именно ею. Скаляры проходят без изменений. Объект и список
 * показывают СОСТАВ; значение, которое сериализовать нельзя (цикл, функция,
 * символ), сводится к пустой строке — «не знаю, что это» честнее, чем
 * `[object Object]`.
 */
export function displayText(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (typeof v === "string") return v;
  if (typeof v === "number" || typeof v === "boolean" || typeof v === "bigint") return String(v);
  if (typeof v === "function" || typeof v === "symbol") return "";
  try {
    return JSON.stringify(v) ?? "";
  } catch {
    // Циклическая структура — показывать нечего, и падать на отрисовке ячейки
    // из-за формы данных нельзя.
    return "";
  }
}
