// Витрина квот утверждает о пределе ровно то, что известно (#364).
//
// ПРЕДМЕТ. Отказ на пределе без витрины неотличим для арендатора от сбоя
// платформы: он не видит ни своего предела, ни потребления, ни того, КТО этот
// предел задал и куда идти его поднимать.
//
// ГЛАВНОЕ ОГРАНИЧЕНИЕ — НОСИТЕЛЬ. Часть видов считается не в проекте, а внутри
// РОДИТЕЛЬСКОГО ресурса (сколько подсетей в одной сети). У таких видов на уровне
// проекта нет единственного значения «занято»: их столько же, сколько сетей.
// Показать там число — солгать; показать прочерк — тоже (`ui.md` правило 9:
// прочерк на месте живого факта утверждает о ресурсе неправду). Поэтому строка
// называет НОСИТЕЛЯ и не показывает потребление вовсе.
//
// Носитель приезжает в ответе (`carrier_type`), и брать его надо оттуда. Пока
// владелец проставляет его константой, вторым признаком служит ФОРМА вида:
// три части в имени означают вложенный вид по построению — это свойство
// контракта, закреплённое ограничением его хранилища.

import {
  CARRIER_IDENTITY,
  CARRIER_PROJECT,
  countedAgainst,
  kindLabel,
  quotaRows,
  sourceLabel,
  type Quota,
} from "./quota-view";

const плоский: Quota = {
  kind: "vpc.network",
  limit: 5,
  used: 2,
  source_scope: "DEFAULT",
  source_scope_id: "",
  carrier_type: "project",
  carrier_id: "prj-1",
};

const вложенный: Quota = {
  kind: "vpc.network.subnet",
  limit: 10,
  used: 0,
  source_scope: "PROJECT",
  source_scope_id: "prj-1",
  carrier_type: "vpc.network",
  carrier_id: "",
};

describe("что считается в проекте, а что внутри носителя", () => {
  it("плоский вид с носителем-проектом считается в проекте", () => {
    expect(countedAgainst(плоский)).toBe(true);
  });

  it("вид, названный носителем чужого типа, — не считается", () => {
    expect(countedAgainst(вложенный)).toBe(false);
  });

  it("вложенный вид не считается в проекте, даже когда носитель назван проектом", () => {
    // Ровно то состояние, в котором владелец находится сегодня: носитель
    // проставлен константой и говорит «проект» про все виды. Признак формы имени
    // не зависит от этой ошибки и не даёт показать 0 как факт.
    expect(countedAgainst({ ...вложенный, carrier_type: "project" })).toBe(false);
  });

  it("оба признака требуются вместе — контроль в обе стороны", () => {
    expect(countedAgainst({ ...плоский, carrier_type: "vpc.network" })).toBe(false);
    expect(countedAgainst({ ...плоский, kind: "vpc.subnet.networkInterface" })).toBe(false);
    expect(countedAgainst(плоский)).toBe(true);
  });
});

/**
 * Предмет страницы решает, чьё «занято» показано (#622).
 *
 * Пределы, носителем которых является ЛИЧНОСТЬ (сколько аккаунтов человеку
 * позволено завести), приезжают тем же контрактом и той же формой, что
 * проектные. Отличает их ровно `carrier_type` — и, значит, страница, на которой
 * число «занято» относится к читателю.
 */
const личный: Quota = {
  kind: "iam.account",
  limit: 5,
  used: 2,
  source_scope: "DEFAULT",
  source_scope_id: "",
  carrier_type: "identity",
  carrier_id: "ory-subject-1",
};

describe("предмет страницы решает, чьё потребление показано", () => {
  it("на своей странице личный предел показывает потребление", () => {
    expect(countedAgainst(личный, CARRIER_IDENTITY)).toBe(true);
    const rows = quotaRows([личный], CARRIER_IDENTITY);
    expect(rows[0].used).toBe(2);
    expect(rows[0].carrierLabel).toBeNull();
  });

  it("на ЧУЖОЙ странице то же число молчит и называет носителя", () => {
    // Контроль в обратную сторону: без него «показывает потребление» означало бы
    // «показывает всегда», и число, относящееся к человеку, читалось бы на
    // проектной странице как свойство проекта.
    expect(countedAgainst(личный, CARRIER_PROJECT)).toBe(false);
    const rows = quotaRows([личный], CARRIER_PROJECT);
    expect(rows[0].used).toBeNull();
    expect(rows[0].carrierLabel).toMatch(/аккаунт/i);
  });

  it("проектный предел на странице личности потребления не показывает", () => {
    // Та же несимметричность с другой стороны — иначе предмет страницы был бы
    // объявлен, но ни на что не влиял в одном из двух направлений.
    const rows = quotaRows([плоский], CARRIER_IDENTITY);
    expect(rows[0].used).toBeNull();
    expect(rows[0].carrierLabel).toMatch(/проект/i);
  });

  it("умолчание предмета — проект: прежние вызывающие не меняют поведения", () => {
    expect(quotaRows([плоский])).toEqual(quotaRows([плоский], CARRIER_PROJECT));
  });

  it("уровень аренды назван уровнем, а не «каждым ресурсом»", () => {
    // «Считается в каждом: identity» подставило бы уровень аренды в оборот,
    // предназначенный для родительского РЕСУРСА, и человек прочитал бы, что у
    // него много личностей.
    const rows = quotaRows([личный], CARRIER_PROJECT);
    expect(rows[0].carrierLabel).not.toMatch(/в каждом/i);
    expect(rows[0].carrierLabel).not.toContain("identity");
  });

  it("вид «аккаунты» назван по-человечески, а не токеном контракта", () => {
    // Токен остаётся в подсказке (он нужен, чтобы попросить поднять предел), но
    // в столбце ресурса человек читает имя.
    expect(kindLabel("iam.account")).toBe("Аккаунты");
  });
});

describe("строки витрины", () => {
  it("потребление показывается только там, где оно есть", () => {
    const rows = quotaRows([плоский, вложенный]);
    expect(rows[0].used).toBe(2);
    // Не 0 и не прочерк: значения нет вовсе, и столбец обязан молчать.
    expect(rows[1].used).toBeNull();
  });

  it("строка без потребления называет носителя", () => {
    const rows = quotaRows([вложенный]);
    expect(rows[0].carrierLabel).toContain("сет");
    expect(rows[0].used).toBeNull();
  });

  it("предел 0 — это предел, а не отсутствие предела", () => {
    // 0 означает «ничего нельзя», и спутать его с «не задано» нельзя: арендатор
    // прочитал бы отказ как сбой.
    const rows = quotaRows([{ ...плоский, limit: 0 }]);
    expect(rows[0].limit).toBe(0);
  });

  it("порядок строк устойчив — по имени вида", () => {
    // Ответ не обещает порядка; страница, показывающая его «как пришло», при
    // каждом обновлении переставляла бы строки под курсором читателя.
    const rows = quotaRows([
      { ...плоский, kind: "vpc.subnet" },
      { ...плоский, kind: "vpc.address" },
      { ...плоский, kind: "vpc.network" },
    ]);
    expect(rows.map((r) => r.kind)).toEqual(["vpc.address", "vpc.network", "vpc.subnet"]);
  });
});

describe("вид, которого витрина не знала, всё равно показывается", () => {
  it("незнакомое имя вида остаётся именем вида, а строка не пропадает", () => {
    // Перспективность: каталог видов растёт на сервере, и витрина, знающая
    // закрытый перечень, молча теряла бы новые пределы — то есть именно те, о
    // которых арендатор ещё не знает.
    expect(kindLabel("совсем.новый")).toBe("совсем.новый");
    const rows = quotaRows([{ ...плоский, kind: "совсем.новый.вид" }]);
    expect(rows).toHaveLength(1);
    expect(rows[0].kind).toBe("совсем.новый.вид");
  });

  it("знакомое имя вида переводится — положительный контроль", () => {
    // Без него «показывает имя как есть» означало бы «не переводит ничего».
    expect(kindLabel("vpc.network")).not.toBe("vpc.network");
  });
});

describe("источник значения назван так, чтобы было понятно, куда идти", () => {
  it("платформенное умолчание не приписывается ни проекту, ни аккаунту", () => {
    expect(sourceLabel({ ...плоский, source_scope: "DEFAULT", source_scope_id: "" })).toMatch(/умолчание/i);
  });

  it("предел аккаунта и предел проекта различимы", () => {
    const acc = sourceLabel({ ...плоский, source_scope: "ACCOUNT", source_scope_id: "acc-1" });
    const prj = sourceLabel({ ...плоский, source_scope: "PROJECT", source_scope_id: "prj-1" });
    expect(acc).not.toBe(prj);
    expect(acc).toContain("acc-1");
    expect(prj).toContain("prj-1");
  });

  it("неизвестный источник не выдаётся за известный", () => {
    // Молчаливый откат к «умолчанию» приписал бы платформе предел, который
    // задал кто-то другой, — и увёл бы арендатора не туда.
    expect(sourceLabel({ ...плоский, source_scope: "SCOPE_UNSPECIFIED", source_scope_id: "" })).toMatch(/не назван/i);
  });
});
