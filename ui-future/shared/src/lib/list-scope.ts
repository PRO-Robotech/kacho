// Область, о которой судит список: весь набор или прочитанная его часть (#373).
//
// Списки консоли курсорные: страница приезжает с сервера, общего числа нет. Всё,
// что делается в браузере поверх приехавшего — отбор, порядок, поиск, — судит о
// ПРОЧИТАННОЙ ЧАСТИ. Пока часть равна целому, разницы не видно; на масштабе она
// становится ложью, и ложью тем убедительнее, чем больше у арендатора ресурсов:
//
//   • отрицание   — «ничего не найдено» означает «нет на этой странице»;
//   • порядок     — первая строка экрана не есть первая строка набора, и при
//                   догрузке порядок молча меняется;
//   • утверждение — «создайте первый» поверх недочитанного списка.
//
// Здесь живут ОДИН тип этого факта и ВСЕ подписи, которыми он называется
// пользователю. Подписи собраны в одном месте намеренно: пока они стояли по
// месту, соседние списки говорили об одном предмете разными словами, и правка
// доезжала не всюду.

/**
 * О чём судит ручка сужения (строка поиска, выпадающий отбор).
 *
 * `server` — сужает СЕРВЕР: выражение уезжает запросом, ответ относится ко всему
 *            списку независимо от того, сколько страниц прочитано;
 * `whole`  — сужает браузер, но набор на экране полон (курсор дочитан);
 * `loaded` — сужает браузер над прочитанной частью. Единственный случай, когда
 *            пустой ответ ручки НЕ означает «такого нет».
 */
export type NarrowingScope = "server" | "whole" | "loaded";

/**
 * Область клиентской ручки по факту дочитанности курсора.
 *
 * Отдельная функция, а не тернарник по месту: `hasMore` приходит из хука списка
 * (`useResourceList`) в форме `boolean | undefined`, и `undefined` здесь значит
 * «страниц за курсором нет» — списки, читаемые одним запросом, курсора не имеют
 * вовсе.
 */
export function clientScope(hasMore: boolean | undefined): NarrowingScope {
  return hasMore ? "loaded" : "whole";
}

/**
 * Полон ли набор строк на экране.
 *
 * Отвечает на единственный вопрос, от которого зависит, законно ли предлагать
 * порядок: сортируется МАССИВ переданных строк, и на неполном наборе стрелка
 * упорядочивает случайную его часть.
 */
export function rowsAreComplete(scope: NarrowingScope): boolean {
  return scope !== "loaded";
}

/**
 * Хвост подписи, называющий область.
 *
 * Отдельно от плейсхолдера, потому что ищут не везде по имени: у адреса ищут
 * ещё и по самому адресу, у операции — по идентификатору. Предмет поиска
 * называет страница, область — этот хвост, и он один на всю консоль.
 */
export function scopeSuffix(scope: NarrowingScope): string {
  return scope === "loaded" ? "— среди загруженных" : "— по всему списку";
}

/** Плейсхолдер строки поиска — называет область прямо в поле ввода. */
export function searchPlaceholder(scope: NarrowingScope): string {
  const subject = scope === "server" ? "Поиск по имени" : "Поиск по имени или идентификатору";
  return `${subject} ${scopeSuffix(scope)}`;
}

/**
 * Подсказка при наведении. Дополняет плейсхолдер тем, чего в него не вместить:
 * ЧТО делать, если искомого не нашлось.
 */
export function narrowingTitle(scope: NarrowingScope): string {
  switch (scope) {
    case "server":
      return "Запрос уходит на сервер: ищется по всему списку, а не по загруженным строкам.";
    case "whole":
      return "Список прочитан целиком: сужается весь набор.";
    case "loaded":
      return "Список прочитан не весь: сужаются только уже загруженные строки. Нажмите «Показать ещё», чтобы расширить набор.";
  }
}

/**
 * Сообщение вместо строк, когда сужение ничего не дало.
 *
 * Над недочитанным списком «ничего не найдено» — утверждение, которого никто не
 * проверял: искомое может лежать за курсором.
 */
export function noMatchesText(scope: NarrowingScope): string {
  return scope === "loaded"
    ? "Среди загруженных строк совпадений нет — за курсором есть ещё."
    : "По запросу ничего не найдено.";
}

