// Форма ключа входа в гостевую систему — объявлена ОДИН раз.
//
// Ресурс живёт в двух реестрах: `compute` (свой раздел консоли) и `shared`
// (тот же раздел, который монтирует remote vpc). Колонки списка у них свои —
// они несут разметку и у каждого модуля свои атомы, — а вот ПОЛЯ ФОРМЫ
// одинаковы по построению: это входной контракт `CreateGuestAccessKeyRequest`.
// Выписать их дважды значило бы завести ровно тот форк, из-за которого правка
// доезжает до одного пути пользователя и не доезжает до другого.
//
// Ground truth: proto/kacho/cloud/compute/v1/guest_access_key_service.proto
// (`CreateGuestAccessKeyRequest`: project_id / name / public_key / labels) и
// use-case `services/compute/internal/apps/kacho/api/guestaccesskey` — именно он
// отвергает пустой project_id, имя вне 1..63 и неразбираемый публичный ключ.
// Обязательность взята у того, кто ОТКАЗЫВАЕТ, а не у дескриптора, — и другого
// источника у неё в этом дереве больше нет: семейство расширений, объявлявшее
// ограничения полей, снято с контрактов целиком (kacho#1255).

import type { FormField } from "./form-schema";
import { NAME_FORM, NAME_HINT } from "./name-form";

export const GUEST_ACCESS_KEY_FIELDS: FormField[] = [
  {
    // Имя ОБЯЗАТЕЛЬНО — в отличие от машины, где оно косметическое и может быть
    // пустым: сервер отвергает пустое. Поэтому берётся объявление обязательного
    // имени, а не необязательного.
    //
    // ЗДЕСЬ СТОЯЛА ТОЛЬКО ДЛИНА («от 1 до 63 символов»), и это пережило свой
    // предмет: имя ключа проверялось одной длиной, пока `guestaccesskey.go` не
    // стал звать `corevalidate.Name` — то есть ту же форму, что и остальное
    // дерево. Подсказка о наборе знаков молчала, и `My Laptop` уезжал на сервер
    // за отказом (#1604).
    name: "name",
    label: "Имя",
    type: "string",
    required: true,
    placeholder: "my-laptop",
    description:
      `Как вы узнаете этот ключ в списке. ${NAME_HINT} ` +
      "Имя косметическое: машина ссылается на ключ по неизменяемому идентификатору, поэтому переименование ничего не ломает.",
    pattern: NAME_FORM,
  },
  {
    // Закрытая половина здесь не хранится НИКОГДА и полем формы не является:
    // хранилище закрытых ключей — отдельный домен со своей моделью угроз.
    name: "public_key",
    label: "Публичный ключ",
    type: "text",
    rows: 4,
    required: true,
    immutable: true,
    placeholder: "ssh-ed25519 AAAAC3Nza… user@host",
    description:
      "Публичная половина ключа в форме, которую понимает гостевая система. Разбирается при создании: строку, которую нельзя разобрать, мы не примем — иначе она доехала бы до машины и молча не сработала, а отладка началась бы с гостя. Закрытую половину не присылайте: здесь она не хранится никогда.",
  },
  { name: "labels", label: "Метки", type: "labels" },
  { name: "project_id", label: "Проект", type: "string", hidden: true },
];

// Стрелкой, а не объявлением функции: тело формы читает не только человек. Гейт
// состава тела (`gateway/internal/restmux`) разбирает шаблон, чтобы сверить
// набор ключей с контрактом, и понимает форму «стрелка возвращает литерал» —
// функцию с телом он не читает вовсе, а значит перестал бы проверять ресурс.
export const guestAccessKeyTemplate = (ctx: { projectId?: string | null }) => ({
  project_id: ctx.projectId ?? "",
  name: "",
  public_key: "",
  labels: {},
});

