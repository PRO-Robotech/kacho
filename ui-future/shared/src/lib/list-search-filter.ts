// Выражение фильтра для строки поиска списка (#373).
//
// Владелец разбирает выражение своей грамматикой: одно сравнение, поле из
// закрытого белого списка, значение в двойных кавычках. Ни ветвления, ни `AND`
// в ней нет — поэтому строка поиска и остальные фильтры списка не складываются
// в одно выражение, и каждый уходит своим механизмом (`listFilters` — отдельными
// параметрами запроса).
//
// Оператор `CONTAINS` (подстрока) заведён ради этой строки: точное равенство для
// неё бесполезно — набирающий имя по частям не совпадёт никогда.

/** Оператор, которым спрашивается подстрока. Ровно тот, что разбирает `pkg/filter`. */
export const CONTAINS = "CONTAINS";

/**
 * Кавычка ЗАКРЫВАЕТ значение, и обратной косой грамматика владельца не понимает.
 *
 * Значит кавычку нельзя ни экранировать, ни пронести: `name CONTAINS "we\"b"`
 * прочиталось бы как значение `we\` плюс мусор, и весь список ответил бы отказом
 * разбора — то есть один символ в строке поиска ронял бы страницу целиком.
 * Убираем её из значения: пользователь ищет имя, а не выражение.
 */
export function sanitizeSearchValue(raw: string): string {
  return raw.replace(/"/g, "").trim();
}

/**
 * Выражение фильтра либо `null` — спрашивать нечего.
 *
 * `null` возвращается и для непустой строки, состоящей из одних кавычек: после
 * очистки от неё не остаётся значения, а `field CONTAINS ""` означал бы «любая
 * строка» — то есть страница молча показала бы весь список как результат поиска.
 */
export function searchFilterExpression(field: string | undefined, raw: string): string | null {
  if (!field) return null;
  const value = sanitizeSearchValue(raw);
  if (!value) return null;
  return `${field} ${CONTAINS} "${value}"`;
}
