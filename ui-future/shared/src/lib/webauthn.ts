// Кодирование двоичных полей церемонии WebAuthn.
//
// Дом здесь, а не рядом с церемонией, по измеренной причине. Функция чистая, и
// единственный её живой потребитель — окно повторного подтверждения личности;
// лежала же она внутри страницы входа на 352 строки, которую продукт не
// монтировал ни одним маршрутом. Цена была видна прямо в пробах потребителя:
// ОБЕ они подменяли всю страницу целиком ради одного кодировщика, и одна из
// них объясняла это дословно — «чтобы не тянуть страницу входа вместе с её
// деревом импортов». Вторая ловила под ESM отказ всей суиты разом, когда в
// подмене недоставало транзитивного экспорта.
//
// Страница снята (#1225), кодировщик остался: он к церемонии поставщика не
// привязан — это преобразование, которое требует сам браузерный интерфейс
// WebAuthn, отдающий `ArrayBuffer` там, где протокол ждёт base64url.

/**
 * `ArrayBuffer` → base64url (RFC 4648 §5): без выравнивающих знаков, `+`→`-`,
 * `/`→`_`. Ровно та форма, в которой поля удостоверения уходят на сервер.
 */
export function bufferToBase64Url(buf: ArrayBuffer): string {
  const bytes = new Uint8Array(buf);
  let bin = "";
  for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
  return btoa(bin).replace(/=+$/g, "").replace(/\+/g, "-").replace(/\//g, "_");
}
