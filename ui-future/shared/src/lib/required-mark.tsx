// Звёздочка обязательного поля — СПРАВА от подписи.
//
// Решение владельца: все звёздочки справа. Библиотека формы по умолчанию ставит
// её СЛЕВА, поэтому решение исполняется единственным способом — своим
// производителем в `ConfigProvider form.requiredMark`.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВЁРСТКА ВНУТРИ ОБОЛОЧКИ. Прежняя настройка
// жила выражением внутри оболочки, у которой оказалось ноль прод-импортёров, и
// уехала вместе с ней незаметно: смотреть на неё было нечему. Отдельный
// производитель имеет своё имя, поэтому его провязку можно УТВЕРЖДАТЬ пробой, а
// его пропажу — заметить.
//
// Звёздочку рисует именно этот файл. `FieldLabel` её не рисует и не должен:
// подпись поля и признак обязательности — разные предметы, и второй экземпляр
// разошёлся бы с этим молча.

import type { ReactNode } from "react";

/** Признак обязательности, каким его подаёт форма. */
interface RequiredInfo {
  required: boolean;
}

/**
 * requiredMarkAfterLabel — производитель подписи поля со звёздочкой ПОСЛЕ текста.
 *
 * Звёздочка помечена `aria-hidden`: обязательность поля программы чтения с
 * экрана берут из `aria-required` самого поля ввода, а вторая её озвучка
 * символом «звёздочка» была бы шумом, а не сведением.
 */
export function requiredMarkAfterLabel(label: ReactNode, info: RequiredInfo): ReactNode {
  return (
    <>
      {label}
      {info.required && (
        <span style={{ color: "var(--kc-danger, #ff4d4f)", marginLeft: 4 }} aria-hidden>
          *
        </span>
      )}
    </>
  );
}
