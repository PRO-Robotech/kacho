// Способы второго фактора, которыми консоль ПОДНИМАЕТ уровень уверенности, —
// ОДНО объявление на продукт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЛИТЕРАЛ ВНУТРИ ОКНА
//
// Про один и тот же предмет — «каким вторым фактором арендатор поднимает
// уровень» — высказываются ДВЕ стороны: служба (какие способы она принимает в
// поле `method`) и консоль (какие она умеет предъявить). Разойдясь, они дают
// состояние, ради которого заведена задача #1213: пол уровня «2» спрашивается,
// а поднять его нечем.
//
// Расхождение ловится СРАВНЕНИЕМ сторон, и сторона консоли объявлена здесь
// ОДНОЙ строкой — её читает гейт развёртывания
// (`deploy/identity_second_factor_reachable_test.go`) ТЕКСТОМ, по имени. Поле
// предъявления кода (`SecondFactorCodeField`) строит свой выбор ИЗ ЭТОГО
// перечня, поэтому способ, добавленный сюда и не подписанный там, роняет
// сборку, а не даёт пустой выбор.
//
// ИМЯ — `OWN_STEP_UP_METHODS` (условие C0). Гейт различает посадки: на `own`
// консоль поднимает уровень НАШЕЙ церемонией (`POST /iam/v1/auth/step-up`), и
// её способы гейт читает под этим именем. Перечня потока поставщика
// (`STEP_UP_METHODS`) у консоли нет: поток поставщика она не ведёт (приёмка F8,
// Р1), и объявить его значило бы засчитать консоли умение, которого у неё нет.
// Держит имя проба рядом — `step-up-methods.test.ts`.
//
// Словарь — словарь службы (`method` глаголов второго фактора и повышения):
// `totp` — код из приложения, `lookup_secret` — запасной код. Пароль в перечне
// НЕТ: он даёт свежесть предъявления, а уровня «2» не поднимает.

/** Способы второго фактора, которыми НАША церемония повышения поднимает уровень до «2». */
export const OWN_STEP_UP_METHODS = ["totp", "lookup_secret"] as const;

/** Способ второго фактора — значение поля `method` в теле глагола. */
export type SecondFactorMethod = (typeof OWN_STEP_UP_METHODS)[number];
