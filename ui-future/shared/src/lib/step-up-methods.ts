// Способы, которыми окно повторного подтверждения УМЕЕТ поднять уровень
// уверенности, — ОДНО объявление на продукт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЛИТЕРАЛ ВНУТРИ ОКНА
//
// Про один и тот же предмет — «каким вторым фактором арендатор поднимает
// уровень» — высказываются ДВЕ стороны: настройки службы личности (какие методы
// она включает) и консоль (какие она умеет вести). Разойдясь, они дают ровно то
// состояние, ради которого заведена задача #1213: пол уровня «2» спрашивается,
// а поднять его нечем — при том что каждая сторона по отдельности валидна и
// проходит свои проверки.
//
// Расхождение ловится только СРАВНЕНИЕМ сторон, а сравнить их может лишь тот,
// кто читает обе. Читатель этот — гейт дерева на стороне развёртывания
// (`deploy/identity_second_factor_reachable_test.go`), и ему нужен адрес, по
// которому сторона консоли объявлена ОДНОЙ строкой, а не выведена разбором
// вёрстки. Отсюда этот файл.
//
// ПРАВИЛО ПРАВКИ: строка ниже и тело окна правятся ВМЕСТЕ. Что перечень не
// врёт — держит не внимание, а проба рядом с окном
// (`StepUpModal.secondfactor.test.tsx`): она прогоняет окно ПО КАЖДОМУ
// названному здесь способу и требует, чтобы окно его действительно предложило.
// Без неё гейт дерева судил бы по объявлению, которое некому опровергнуть.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
//
// `passkey` (и `webauthn` в беспарольной посадке) — ПЕРВЫЙ фактор, а не второй:
// служба личности выдаёт по нему `aal1` и в потоке `aal=aal2` не предлагает его
// вовсе. Держать его здесь значило бы обещать поднятие уровня способом, который
// уровня не поднимает. `webauthn` в перечне есть потому, что в НЕбеспарольной
// посадке он вторым фактором быть вправе, и окно эту посадку ведёт; какая
// посадка развёрнута — решают настройки, и это ровно та сторона, с которой
// перечень сверяет гейт.

/**
 * Методы службы личности, которые окно повторного подтверждения умеет довести
 * до конца в потоке `aal=aal2`.
 *
 * Порядок значим: окно предлагает ПЕРВЫЙ способ, который служба личности
 * действительно предложила в этом потоке. Одноразовый код стоит первым, потому
 * что он не требует оборудования и настраивается арендатором самостоятельно;
 * запасные коды — последний рубеж, а не повседневный способ.
 */
export const STEP_UP_METHODS = ["totp", "webauthn", "lookup_secret"] as const;

/** Способ подтверждения, который умеет вести окно. */
export type StepUpMethod = (typeof STEP_UP_METHODS)[number];

/**
 * Узел потока, по наличию которого способ узнают, и поле, которым его
 * отправляют. Одна таблица на оба вопроса: разведя их, мы получили бы два места
 * об одном предмете.
 */
export const STEP_UP_METHOD_NODES: Record<StepUpMethod, string> = {
  totp: "totp_code",
  webauthn: "webauthn_login_trigger",
  lookup_secret: "lookup_secret",
};
