// AdminPlaneUnavailable — раздел «Система» на посадке, чей край не обслуживает
// admin-плоскость, говорит об этом СЛОВАМИ (#2692).
//
// Отказ «нет прав» здесь был бы ложью о смотрящем: прав у администратора
// достаточно, нет — двери. Текст называет, что работает (чтение каталога),
// что нет (мутации) и где дверь (профиль развёртывания операторской консоли),
// то есть следующий шаг, а не только факт.

import { Alert } from "antd";

export const ADMIN_PLANE_UNAVAILABLE_TITLE = "Раздел «Система» недоступен на этой посадке";

export const ADMIN_PLANE_UNAVAILABLE_TEXT =
  "Административный API платформы обслуживает только внутренний слушатель края, а эта консоль " +
  "подключена к внешнему. Каталог размещения читается, но заводить, править и удалять его записи " +
  "здесь нельзя. Откройте консоль оператора — её профиль развёртывания называет дверь к " +
  "внутреннему слушателю.";

export function AdminPlaneUnavailable() {
  return (
    <Alert
      type="warning"
      showIcon
      message={ADMIN_PLANE_UNAVAILABLE_TITLE}
      description={ADMIN_PLANE_UNAVAILABLE_TEXT}
      style={{ margin: 16 }}
    />
  );
}
