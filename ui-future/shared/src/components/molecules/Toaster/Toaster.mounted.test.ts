// Сигнал без показа — молчание. Проба держит вторую половину нормы.
//
// # Класс
//
// Механизм сигнала может быть исправен целиком — разбор ответа, опрос операции,
// текст сообщения — и не показать НИЧЕГО, если в модуле не примонтирован
// `Toaster`. Очередь тостов это модульный синглтон: `toast.error()` кладёт запись
// и возвращает управление, а читает её только подписанный показ. Нет показа —
// запись оседает в памяти, и отличить это от «сигнала не было» на экране нельзя.
//
// Наблюдалось: модуль `system` не нёс показа вовсе, при том что маршрутизирует
// общие страницы создания/правки/удаления (`/system/regions/create` и соседние).
// Отказ края (403) доезжал до `toast.error` и не был виден никак — «ничего не
// происходит, но выдаёт 403», находка владельца 2026-08-15.
//
// # Почему проба читает ДЕРЕВО, а не рендер
//
// Утверждение здесь — про набор модулей, а не про один компонент: смонтировать
// девять приложений в jest дороже и хрупче, чем прочитать их исходники, а
// предмет («в каждом мутирующем модуле есть показ») — свойство дерева. Тот же
// приём, которым проверяется объявление чарта в `deploy`-пробах.
//
// # Чего проба НЕ утверждает
//
// Что показ примонтирован в правильном месте дерева компонентов. Это видно
// глазом и держится обзором; здесь ловится случай, который глазом НЕ виден —
// отсутствие показа целиком.

import { readdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

import { mountsDisplay } from "../../../test/toaster-mount";

/**
 * Корень консоли ищется ВВЕРХ от рабочего каталога, а не собирается из `__dirname`:
 * суита исполняется как ESM, где `__dirname` не определён, и прогон падал бы
 * поломкой разбора — то есть «не выполнилось», а не вердиктом.
 *
 * Признак корня — каталог, в котором лежит и `shared`, и хотя бы один модуль.
 */
function findUiRoot(): string {
  let dir = process.cwd();
  for (let i = 0; i < 6; i++) {
    if (
      existsSync(join(dir, "shared", "src")) &&
      existsSync(join(dir, "vpc", "src"))
    )
      return dir;
    const up = dirname(dir);
    if (up === dir) break;
    dir = up;
  }
  throw new Error(
    `корень консоли не найден вверх от ${process.cwd()} — проба не знает, что читать`,
  );
}

const UI_ROOT = findUiRoot();

/**
 * Модули, которые мутируют и потому обязаны показывать сигнал.
 */
const MUTATING_MODULES = [
  "vpc",
  "iam",
  "compute",
  "storage",
  "nlb",
  "registry",
  "system",
] as const;

/**
 * Модули, показа НЕ несущие, — и это решение, а не пропуск: они собираются из
 * своего дерева (их образ не копирует `shared/`) и мутирующих страниц не несут.
 *
 * Перечислены здесь потому, что перечень выше сам по себе о них не утверждает
 * НИЧЕГО: модуль, в него не внесённый, не осматривается вовсе, и «его тут нет по
 * решению» неотличимо от «о нём забыли». До #1532/#1534 у `dashboard` контроль
 * был, а у `host` — ни одного утверждения: он назывался только в прозе, и,
 * обзаведись он мутацией, остался бы без показа молча.
 *
 * ЧТО КОНТРОЛЬ НИЖЕ ЛОВИТ И ЧЕГО НЕ ЛОВИТ — сказано прямо, иначе обещание шире
 * сделанного. Ловит: модуль отсюда начал МОНТИРОВАТЬ показ, то есть его место в
 * этом перечне кончилось и он переезжает в перечень выше. Не ловит: модуль начал
 * мутировать и показа НЕ примонтировал — «мутирует ли модуль» предиката по
 * дереву не имеет, и выдумывать его по совпадению слов значило бы завести
 * проверку, чьи находки нечем адъюдицировать.
 */
const NON_MUTATING_MODULES = ["host", "dashboard"] as const;

function sourceFilesOf(module: string): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name === "node_modules") continue;
        walk(p);
      } else if (/\.tsx?$/.test(e.name) && !/\.test\.tsx?$/.test(e.name)) {
        out.push(p);
      }
    }
  };
  const src = join(UI_ROOT, module, "src");
  if (existsSync(src)) walk(src);
  return out;
}

/**
 * Монтирует ли модуль показ хотя бы в одном не-тестовом исходнике.
 *
 * Решение принимает разбор (`mountsDisplay`), а не вхождение подстроки. Прежде
 * здесь стояло `includes("<Toaster")`, и оно засчитывало сразу три вещи, показом
 * не являющиеся: соседа с похожим именем, упоминание в комментарии и строковый
 * литерал. Слепота эта тихая — она не даёт ни красного, ни зелёного, она молчит:
 * сними показ, переименовав его в `<ToasterDISABLED`, и проба не заметит.
 * Способность распознавателя различать эти случаи доказана инъекцией по каждой
 * оси в `Toaster.mounted.injection.test.ts`.
 */
function rendersToaster(module: string): boolean {
  return sourceFilesOf(module).some((f) =>
    mountsDisplay(f, readFileSync(f, "utf8")),
  );
}

describe("показ уведомлений примонтирован в каждом мутирующем модуле", () => {
  // Перепись: «все несут показ» обязано быть отличимо от «ничего не прочитано».
  it("исходники модулей прочитаны", () => {
    // Утверждается пара «модуль и число», а не одно число: на голом `n > 0`
    // отказ не называет, У КАКОГО модуля перепись пуста, — а именно это и надо
    // знать, потому что пустая перепись означает сломанный обход, а не чистый
    // модуль. Прежняя редакция строила ту же пару через `expect.any(Number)`;
    // он возвращает `any`, и присваивание в литерал становится небезопасным —
    // проверка ничего не утверждала (число есть число) и стоила находки линта.
    //
    // Осматриваются ОБА перечня. У исключённых это несущее, а не симметрия ради
    // симметрии: контроль ниже утверждает ОТСУТСТВИЕ показа, а отсутствие в
    // пустом обходе выполняется тождественно. Пропади каталог модуля — и
    // `rendersToaster` ответил бы «показа нет» на ничём, то есть контроль
    // зеленел бы ровно там, где перестал что-либо измерять.
    const counts = [...MUTATING_MODULES, ...NON_MUTATING_MODULES].map((m) => ({
      module: m,
      files: sourceFilesOf(m).length,
    }));
    const empty = counts.filter((c) => c.files === 0);
    // `--silent` глушит `console.log`, поэтому перепись печатается потоком: та,
    // которую не печатают, переписью не является — «все несут показ» осталось бы
    // неотличимо от «ничего не прочитано».
    process.stdout.write(
      `\n[показ уведомлений] мутирующих модулей ${MUTATING_MODULES.length} · без показа по решению ` +
        `${NON_MUTATING_MODULES.length} · исходников прочитано ${counts.reduce((n, c) => n + c.files, 0)}\n`,
    );
    expect(empty).toEqual([]);
  });

  it("ни одного мутирующего модуля без показа", () => {
    const silent = MUTATING_MODULES.filter((m) => !rendersToaster(m));
    expect(silent).toEqual([]);
  });

  /**
   * Контроль к предыдущему, и он же — половина обещания перечня исключённых.
   *
   * Без него «ни одного без показа» было бы выполнено и предикатом, который
   * всегда отвечает «да». А поимённо, по каждому исключённому, — потому что
   * решение принято по каждому: покажется показ у любого из них, и красное
   * назовёт, у кого именно, вместо общего «что-то изменилось».
   */
  it.each([...NON_MUTATING_MODULES])(
    "%s показа не несёт — иначе его место в перечне кончилось",
    (module) => {
      expect(rendersToaster(module)).toBe(false);
    },
  );
});
