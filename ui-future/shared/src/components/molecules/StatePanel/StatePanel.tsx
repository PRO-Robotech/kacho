import type { CSSProperties, ReactNode } from "react";

/**
 * Экран СОСТОЯНИЯ: раздел недоступен, список пуст, доступа нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ОДНА ОБОЛОЧКА НА ВСЕ ТАКИЕ ЭКРАНЫ
 *
 * Это один предмет: продукт объясняет, почему смотреть не на что, и предлагает
 * следующий шаг. Пока у каждого случая была своя вёрстка, они отличались всем —
 * кеглем заголовка, шириной строки, наличием рисунка, местом кнопки, — и один и
 * тот же продукт выглядел разным в зависимости от того, чего именно не хватает.
 *
 * Отличается по делу ровно содержимое: рисунок, слова и набор действий. Форма
 * общая, и меняется она в одном месте.
 *
 * ОФОРМЛЕНИЕ ИНЛАЙНОВОЕ, А НЕ КЛАССАМИ
 *
 * Панель рисуется и в каркасе, и внутри модуля, поднятого отдельно от него, — а
 * свой лист стилей каркаса такой модуль не подключает. Класс без листа дал бы
 * неоформленный экран ровно там, где что-то и так сломалось. Цвета при этом
 * остаются токенами, поэтому тема управляет ими как обычно.
 */
export interface StatePanelProps {
  /** Рисунок состояния — встроенный SVG. Без него панель тоже собирается:
   *  у части состояний рисунка нет, и пустое место лучше случайной картинки. */
  art?: ReactNode;
  title: ReactNode;
  /** Объяснение: почему так и что это значит. Одним абзацем. */
  description?: ReactNode;
  /** Действия — первым идёт то, которое предлагается. */
  actions?: ReactNode;
  /** Дополнительное под действиями: ссылки на документацию, оговорки. */
  footer?: ReactNode;
  role?: "alert" | "status";
  "data-testid"?: string;
  /** Опознавательные `data-*` — на ТОТ ЖЕ узел, что и `data-testid`.
   *
   *  Разведённые по разным узлам, признак и атрибуты рвут утверждение пробы: она
   *  находит элемент по признаку и не находит на нём атрибута. Так и вышло —
   *  пять проб границы отказа покраснели ровно на этом. */
  data?: Record<string, string | undefined>;
}

/**
 * ЗОНЫ ФИКСИРОВАННОЙ ВЫСОТЫ (решение владельца).
 *
 * Рисунок, заголовок, описание и действия стоят на ОДНИХ И ТЕХ ЖЕ местах у
 * каждого ресурса. Иначе кнопка гуляет по вертикали вслед за длиной описания:
 * у групп безопасности оно 231 знак, у самого короткого — 111, и это разница в
 * две строки, то есть в полсотни точек. Переход между разделами читался как
 * прыжок, хотя менялся только текст.
 *
 * Высоты названы числами, а не «по содержимому»: содержимое и есть то, что
 * меняется. Описание переносится ВНУТРИ своей области и центрируется в ней —
 * область не растёт и не сжимается.
 */
const ART_HEIGHT = 136;
const TITLE_HEIGHT = 26;
/** Ширина и высота области описания — от САМОГО ДЛИННОГО описания реестра, а не
 *  от среднего.
 *
 *  Замер по дереву: описаний 13, длины от 111 до 231 знака, медиана 179.
 *  При 560 точках и кегле 14 в строку входит около 75 знаков кириллицы, то есть
 *  самое длинное занимает четыре строки: 4 × 14 × 1.6 ≈ 90.
 *
 *  Первая редакция взяла три строки при 460 точках — этого хватало медианному
 *  описанию и не хватало длинному, и текст вылезал за свою область. Считать
 *  надо по краю распределения: область фиксирована, а значит обязана вмещать
 *  худший случай, иначе фиксация превращается в обрезку. */
const DESCRIPTION_HEIGHT = 90;
const DESCRIPTION_WIDTH = 560;
/** Зона подвала (темы документации) — тоже фиксированная, и по той же причине,
 *  что и остальные.
 *
 *  Она стоит ПОСЛЕ кнопки, но колонка центрирована по вертикали, поэтому её
 *  высота двигает ВСЁ, что выше: и кнопку, и заголовок, и рисунок. Замер по
 *  реестру: ссылок у ресурса бывает 0 (два ресурса), 1 (десять) и 2 (один), —
 *  то есть разброс в две строки, и переход между двумя соседними разделами
 *  сдвигал картинку с кнопкой на глаз.
 *
 *  Считано по худшему случаю: разделительная линия сверху (16 отступа) плюс две
 *  строки тем по 13px с межстрочным 1.5. */
const FOOTER_HEIGHT = 56;
/** Зона действий — своя высота, а не «по содержимому».
 *
 *  Без неё зона занимала ровно высоту кнопки и вплотную примыкала к подвалу, у
 *  которого сверху разделительная линия. Линия проходила ПО КНОПКЕ: на глаз
 *  выглядело так, будто кнопка заехала на блок документации. Кнопка antd —
 *  32 точки; отступ ниже отделяет её от линии. */
const ACTIONS_HEIGHT = 32;
const ACTIONS_GAP = 22;

const layout: CSSProperties = {
  display: "flex",
  flexDirection: "column",
  alignItems: "center",
  justifyContent: "center",
  // Панель занимает предложенную высоту целиком: экран состояния, прижатый к
  // верхнему краю пустой области, читается как сбившаяся вёрстка.
  minHeight: "100%",
  padding: "48px 24px",
  textAlign: "center",
};

const titleStyle: CSSProperties = {
  margin: 0,
  height: TITLE_HEIGHT,
  display: "flex",
  alignItems: "center",
  fontSize: 18,
  fontWeight: 600,
  lineHeight: 1.3,
  color: "var(--kc-text)",
};

const textStyle: CSSProperties = {
  margin: 0,
  // Ширина строки ограничена: длинная строка через всю таблицу не читается.
  width: DESCRIPTION_WIDTH,
  maxWidth: "100%",
  // Высота ОБЛАСТИ, а не текста: короткое описание оставляет её пустой снизу,
  // длинное занимает целиком, и кнопка под ней не двигается ни в том, ни в
  // другом случае. Текст стоит по центру области — прижатый к верху, он
  // читался бы как оборванный.
  height: DESCRIPTION_HEIGHT,
  display: "flex",
  alignItems: "center",
  justifyContent: "center",
  fontSize: 14,
  lineHeight: 1.6,
  color: "var(--kc-text-secondary)",
  // Перенос по словам с висячим переносом длинных идентификаторов: описание
  // ресурса иногда несёт адрес или CIDR, который иначе распирал бы область.
  overflowWrap: "anywhere",
};

export function StatePanel({
  art,
  title,
  description,
  actions,
  footer,
  role,
  "data-testid": testId,
  data,
}: StatePanelProps) {
  return (
    <div style={layout} role={role} data-testid={testId} {...data}>
      {/* Зона рисунка держит высоту и БЕЗ рисунка: у части состояний его нет, и
          без резерва заголовок с кнопкой уезжали бы вверх ровно на его высоту. */}
      <div
        style={{
          height: ART_HEIGHT,
          marginBottom: 20,
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
        }}
        aria-hidden={art === undefined ? true : undefined}
      >
        {art}
      </div>
      <h2 style={titleStyle}>{title}</h2>
      {/* Область описания стоит ВСЕГДА — и когда описания нет. Пустая, она
          держит место, и кнопка у ресурса без описания оказывается там же, где
          у ресурса с описанием. */}
      <div style={{ ...textStyle, marginTop: 10, marginBottom: 18 }}>{description ?? null}</div>
      {/* Зона действий стоит ВСЕГДА — и когда действия нет (у ресурсов без
          глагола создания: каталог типов дисков, типов машин, зон). Иначе их
          подвал поднимался бы на высоту кнопки относительно соседних разделов. */}
      <div
        style={{
          height: ACTIONS_HEIGHT,
          marginBottom: ACTIONS_GAP,
          display: "flex",
          gap: 12,
          alignItems: "center",
          justifyContent: "center",
        }}
        aria-hidden={actions === undefined ? true : undefined}
      >
        {actions}
      </div>
      {/* Зона подвала держит высоту и ПУСТАЯ: у двух ресурсов реестра тем нет
          вовсе, и без резерва их экран поднимался бы относительно соседних. */}
      <div
        style={{
          height: FOOTER_HEIGHT,
          width: DESCRIPTION_WIDTH,
          maxWidth: "100%",
          display: "flex",
          alignItems: "flex-start",
          justifyContent: "center",
        }}
        aria-hidden={footer === undefined ? true : undefined}
      >
        {footer}
      </div>
    </div>
  );
}
