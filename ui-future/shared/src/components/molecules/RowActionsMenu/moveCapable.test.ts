// «Перемещать нечем» — решение о ДОМЕННОМ ОБЪЕКТЕ, а не об имени спеки (#1532).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Пункт «Переместить» — окно-заглушка, печатающее REST-вызов. Предложить его
// ресурсу, у которого такого глагола нет ни на контракте, ни на крае, значит
// объявить возможность, которой не существует. Перечень `MOVE_INCAPABLE` эту
// возможность и закрывает.
//
// Ключуется он идентификатором спеки — то есть ИМЕНЕМ ПРЕДСТАВЛЕНИЯ в консоли.
// Один и тот же доменный объект представлен в реестре не всегда один раз: у
// каталога размещения geo записей ДВЕ — каноническая (`regions` / `zones`,
// admin-CRUD) и читающая (`compute-regions` / `compute-zones`, на неё ссылаются
// подборщики зоны и региона). Обе адресуют `/geo/v1/regions` и `/geo/v1/zones`,
// то есть говорят об одном и том же каталоге; в перечне до #1532 стояла только
// каноническая. Решение о ДОМЕННОМ ОБЪЕКТЕ принималось по имени одного из двух
// его представлений — и второе обходило его целиком.
//
// Тот же класс, что «предикат по имени мерит соглашение об именовании»: соседняя
// проба этого же каталога (`lib/resource-registry.geo.test.ts`) уже потеряла на
// нём один замок — перепись брала спеки по списку идентификаторов, читающие
// близнецы в неё не попадали и годами несли колонку, привязанную к снятому полю.
// Там вывод сделан: перепись берётся ОТ ПУТИ. Здесь — то же самое решение.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ
//
//	A. ПЕРЕПИСЬ. Реестр прочитан, и объём осмотренного назван: «ноль находок»
//	   обязано быть отличимо от «ноль прочитанного».
//	B. ИСКЛЮЧЕНИЕ ЖИВЁТ, ПОКА У НЕГО ЕСТЬ ПРЕДМЕТ. Каждая запись перечня
//	   отвечает живой спеке; записи, которой больше нечего исключать, здесь
//	   не место — она унаследует следующую слепую зону.
//	C. ДВЕ СПЕКИ ОДНОГО ОБЪЕКТА ОТВЕЧАЮТ ОДИНАКОВО. Утверждение о ДЕРЕВЕ:
//	   считается по фактическим совпадениям `apiPath`, а не по выписанному
//	   списку близнецов.
//	D. БЛИЗНЕЦ УЗНАЁТСЯ ПО ПРЕДМЕТУ, А НЕ ПО ИМЕНИ. Синтетическая спека с
//	   ЧУЖИМ идентификатором и тем же путём обязана быть подавлена. Это
//	   утверждение не выродится, даже если завтра в дереве не останется ни
//	   одной пары близнецов, — в отличие от C, которое тогда станет пустым.
//	E. ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Предикат не есть константа «нечем»: обычный
//	   ресурс перемещаем. Без него C и D выполнил бы предикат, отвечающий
//	   «нечем» всем подряд.

import { REGISTRY, type ResourceSpec } from "@shared/lib/resource-registry";
import { MOVE_INCAPABLE, resourceIsMoveCapable } from "./RowActionsMenu";

const specs = Object.entries(REGISTRY);

/** Спеки, сгруппированные по доменному объекту, — то есть по адресу коллекции. */
const byApiPath = new Map<string, string[]>();
for (const [id, spec] of specs) {
  byApiPath.set(spec.apiPath, [...(byApiPath.get(spec.apiPath) ?? []), id]);
}
const twinGroups = [...byApiPath.entries()].filter(([, ids]) => ids.length > 1);

describe("«перемещать нечем» решается доменным объектом, а не именем спеки", () => {
  it("реестр прочитан — перепись названа", () => {
    // Пара «сколько осмотрено» и «сколько подавлено», а не одно число: на голом
    // «нарушений нет» пустой обход неотличим от чистого дерева.
    const suppressed = specs.filter(([, spec]) => !resourceIsMoveCapable(spec)).map(([id]) => id);
    // `process.stdout.write`, а не `console.log`: прогонщик зовёт jest с
    // `--silent`, и вывод через консоль до отчёта не доходит — перепись,
    // которую не печатают, переписью не является.
    process.stdout.write(
      `\n[перемещение] спек ${specs.length} · доменных объектов ${byApiPath.size} · ` +
        `объектов с двумя и более представлениями ${twinGroups.length}` +
        `${twinGroups.length ? ` (${twinGroups.map(([, ids]) => ids.join("+")).join(", ")})` : ""}` +
        ` · подавлено ${suppressed.length}\n`,
    );
    expect(specs.length).toBeGreaterThan(0);
    expect(suppressed.length).toBeGreaterThan(0);
  });

  it("каждая запись перечня отвечает живой спеке", () => {
    // Запись, которой больше нечего исключать, — находка, а не запас: перечень
    // обязан истекать сам, иначе он переживает свой предмет молча.
    const orphaned = MOVE_INCAPABLE.filter((id) => !REGISTRY[id]);
    expect(orphaned).toEqual([]);
  });

  it("два представления одного доменного объекта отвечают одинаково", () => {
    const split = twinGroups
      .filter(([, ids]) => new Set(ids.map((id) => resourceIsMoveCapable(REGISTRY[id]))).size > 1)
      .map(([apiPath, ids]) => `${apiPath} → ${ids.join(", ")}`);
    expect(split).toEqual([]);
  });

  it("близнец узнаётся по предмету: чужой идентификатор при том же пути подавлен", () => {
    // Не зависит от того, есть ли близнецы в дереве СЕГОДНЯ: утверждение о
    // предикате, а не о составе реестра. Снимут читающие спеки geo — эта проба
    // останется единственной, которая держит свойство.
    const shadow: ResourceSpec = { ...REGISTRY.regions, id: "regions-shadow", route: "regions-shadow" };
    expect(MOVE_INCAPABLE).not.toContain(shadow.id);
    expect(resourceIsMoveCapable(shadow)).toBe(false);
  });

  it("предикат не константа: обычный ресурс перемещаем", () => {
    expect(resourceIsMoveCapable(REGISTRY.networks)).toBe(true);
    const ordinary: ResourceSpec = { ...REGISTRY.networks, id: "widgets", apiPath: "/vpc/v1/widgets" };
    expect(resourceIsMoveCapable(ordinary)).toBe(true);
  });
});
