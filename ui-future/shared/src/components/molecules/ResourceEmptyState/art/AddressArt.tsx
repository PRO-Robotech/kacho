import type { FC } from "react";

/**
 * Пустой список адресов.
 *
 * ЧТО НАРИСОВАНО: адресная метка-ярлык с точкой крепления, а справа — контур
 * внешней стороны, к которой адрес обращён.
 *
 * ПОЧЕМУ ИМЕННО ЭТО. Адрес — не «строка в таблице», а величина, которую
 * арендатор ЗАКРЕПЛЯЕТ за собой: она выделяется из полосы, живёт отдельно от
 * того, кому её потом отдадут, и с внешней стороны видна как одна точка. Ярлык
 * с ушком (точка крепления) говорит ровно это: предмет, который вешают на
 * что-то, а не встроенная часть ресурса. Внутри ярлыка — ритм октетов, чтобы
 * метка читалась адресом, а не биркой вообще.
 *
 * Дуги справа — граница «наружу», единственная кривая на всём рисунке: у
 * соседей по группе (интерфейс, шлюз) внешняя сторона выражена иначе, и адрес
 * не должен читаться их перестановкой.
 *
 * Пунктирный ярлык — единственное цветное пятно: это то, чего ещё нет, и тон у
 * него первичный (приглашение), а не предупреждающий.
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным. Движения нет вовсе: анимация на
 * пустом экране обещает строки, которых не будет.
 */

// Октеты внутри метки: три штриха и две точки-разделителя. Перечень, а не цикл
// по индексу, — координаты видны глазом, и правка одного штриха не двигает остальные.
const OCTET_STROKES = [
  { x1: 62, x2: 74 },
  { x1: 82, x2: 94 },
  { x1: 102, x2: 114 },
];

const OCTET_DOTS = [78, 98];

export const AddressArt: FC = () => (
  // Смысл несёт текст под рисунком; озвучивать «ярлык и две дуги» нечего.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё рисунок висит в пустоте и читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* То, к чему метку крепят: узел слева и короткая привязь к ушку ярлыка.
        Адрес всегда чей-то — висящая сама по себе метка читалась бы мусором. */}
    <circle cx="22" cy="66" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="26" y1="66" x2="34" y2="66" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Контур внешней стороны: две дуги периметра и точка на нём — так адрес
        виден снаружи. Кривая здесь одна на весь рисунок и принадлежит только
        внешней границе. */}
    <path d="M150 28 A44 44 0 0 1 150 104" stroke="var(--kc-border)" strokeWidth="1.25" />
    <path d="M150 42 A34 34 0 0 1 150 90" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
    <circle cx="172" cy="66" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />

    {/* Сама метка — НАМЕЧЕННАЯ: остриё с ушком слева, тело с октетами справа.
        Это и есть предмет экрана: адрес, который ещё не зарезервирован. */}
    <path
      d="M34 66 L52 48 H118 A6 6 0 0 1 124 54 V78 A6 6 0 0 1 118 84 H52 Z"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />
    <circle cx="50" cy="66" r="3.5" stroke="var(--kc-primary)" strokeWidth="1.25" />

    {OCTET_STROKES.map((s) => (
      <line
        key={s.x1}
        x1={s.x1}
        y1="66"
        x2={s.x2}
        y2="66"
        stroke="var(--kc-primary)"
        strokeWidth="1.25"
      />
    ))}
    {OCTET_DOTS.map((cx) => (
      <circle key={cx} cx={cx} cy="66" r="1.25" fill="var(--kc-primary)" />
    ))}
  </svg>
);
