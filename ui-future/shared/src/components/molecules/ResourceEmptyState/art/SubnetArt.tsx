import type { FC } from "react";

/**
 * Рисунок пустого списка подсетей.
 *
 * ЧТО НАРИСОВАНО И ПОЧЕМУ ИМЕННО ЭТО
 *
 * Линейка адресов с делениями и отмеченными началом и концом. Подсеть — не
 * коробка и не контейнер: это ОТРЕЗОК чужого адресного пространства, поэтому
 * рисунок построен на оси, а не на рамке. Ось и есть то, чего у сети на её
 * собственном рисунке нет, а у подсети есть всегда: место на шкале.
 *
 * Отрезки над осью разной ширины — это тоже предмет, а не украшение: подсети
 * различаются размером диапазона, и одинаковые по ширине блоки утверждали бы
 * обратное. Каждый отрезок опущен на ось: адрес подсети не выбирается на глаз,
 * он занимает конкретное место.
 *
 * Метка сверху — зона: подсеть привязана к зоне размещения, и без этой привязки
 * она не заводится. Полоса от метки вправо показывает, что зоне принадлежит вся
 * линейка целиком, а не один отрезок на ней.
 *
 * Третий отрезок намечен пунктиром — свободное место на шкале, которое займёт
 * первое действие пользователя. Цветное пятно ровно одно, тон первичный:
 * приглашение, а не предупреждение.
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным.
 *
 * Движения нет: анимация на пустом экране читается как продолжающаяся загрузка,
 * то есть обещает строки, которых не будет.
 */

// Внутренние деления шкалы — через 16 единиц. Края в перечень не входят: у них
// своя, более длинная засечка (начало и конец диапазона отмечены явно).
const TICKS = [40, 56, 72, 88, 104, 120, 136, 152, 168];

// Занятые отрезки: ширина у каждого своя — это диапазоны разного размера.
const RANGES = [
  { x: 32, w: 48, cx: 56 },
  { x: 92, w: 34, cx: 109 },
];

export const SubnetArt: FC = () => (
  // Смысл несёт текст под рисунком, поэтому для чтения с экрана рисунок скрыт.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё линейка висит в пустоте и рисунок читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Зона размещения, к которой привязан диапазон, и её полоса на всю ширину
        шкалы: зоне принадлежит вся линейка, а не отдельный отрезок. */}
    <rect x="24" y="18" width="52" height="18" rx="9" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
    <circle cx="36" cy="27" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="44" y1="27" x2="66" y2="27" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="84" y1="27" x2="184" y2="27" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Занятые диапазоны: рамка, штрих содержимого и отвод на ось. */}
    {RANGES.map((range) => (
      <g key={range.x}>
        <rect
          x={range.x}
          y="62"
          width={range.w}
          height="22"
          rx="5"
          stroke="var(--kc-border)"
          strokeWidth="1.25"
        />
        <line
          x1={range.x + 10}
          y1="73"
          x2={range.x + range.w - 10}
          y2="73"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
        <line
          x1={range.cx}
          y1="84"
          x2={range.cx}
          y2="94"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
      </g>
    ))}

    {/* Свободный диапазон — единственное цветное пятно рисунка. Его отвод на ось
        остаётся в общем тоне: место на шкале есть, нет подсети на этом месте. */}
    <rect
      x="138"
      y="62"
      width="42"
      height="22"
      rx="5"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />
    <line x1="153" y1="73" x2="165" y2="73" stroke="var(--kc-primary)" strokeWidth="1.25" />
    <line x1="159" y1="67" x2="159" y2="79" stroke="var(--kc-primary)" strokeWidth="1.25" />
    <line x1="159" y1="84" x2="159" y2="94" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Ось адресов с делениями. */}
    <line x1="24" y1="94" x2="184" y2="94" stroke="var(--kc-border)" strokeWidth="1.25" />
    {TICKS.map((x) => (
      <line key={x} x1={x} y1="94" x2={x} y2="100" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
    ))}

    {/* Начало и конец адресного пространства: засечка длиннее делений — границы
        у диапазона всегда известны, подсеть не «где-то там». */}
    <line x1="24" y1="88" x2="24" y2="106" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="184" y1="88" x2="184" y2="106" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
  </svg>
);
