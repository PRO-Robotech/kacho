import type { FC } from "react";

/**
 * Рисунок пустого списка балансировщиков.
 *
 * ЧТО НАРИСОВАНО. Слева — входящая стрелка (соединения, пришедшие снаружи),
 * посередине — узел распределения, справа — веер к трём целям. Нижняя цель
 * намечена пунктиром: место, куда встанет первый балансировщик.
 *
 * ПОЧЕМУ ИМЕННО ЭТО. Предмет ресурса — не «коробка с адресом», а РАЗВЕТВЛЕНИЕ:
 * один вход, много получателей. Стрелка и веер показывают ровно то, ради чего
 * балансировщик заводят, и отличают его от целевой группы (там предмет — набор
 * адресатов и их состояние, а не сам распределяющий узел).
 *
 * Цветное пятно ровно одно — намеченная цель, тон первичный: это приглашение
 * создать первый ресурс, а не предупреждение. Пустые цели рядом показывают, что
 * место под них уже размечено.
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным.
 *
 * Движения нет: анимация на пустом экране читается как продолжающаяся загрузка,
 * то есть обещает строки, которых не будет.
 */

