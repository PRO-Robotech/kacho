import type { FC } from "react";

/**
 * Пустой список сетевых интерфейсов.
 *
 * ЧТО НАРИСОВАНО: разъём-порт с контактами, уходящий от него линк и контур
 * подсети, в чью строку линк приходит.
 *
 * ПОЧЕМУ ИМЕННО ЭТО. Интерфейс — самостоятельный ресурс, а не свойство машины:
 * он существует как ТОЧКА ПОДКЛЮЧЕНИЯ и только потом кому-то достаётся.
 * Поэтому нарисован разъём (у него есть ключ-выступ и контакты — предмет,
 * который втыкают), а не «карточка машины с портом внутри». Линк ведёт не в
 * пустоту, а в конкретное место подсети: интерфейс без подсети не бывает, и
 * пустой экран обязан показать обе стороны связи.
 *
 * Линк намеренно с изломом и без наконечника: он не «направление наружу», а
 * проводка до места. Стрелка с наконечником занята шлюзом, и два ресурса не
 * вправе получить одну схему.
 *
 * Пунктирный разъём — единственное цветное пятно: это то, чего ещё нет, и тон
 * у него первичный (приглашение), а не предупреждающий.
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным. Движения нет вовсе: анимация на
 * пустом экране обещает строки, которых не будет.
 */

