import type { FC } from "react";

/**
 * Пустой список шлюзов.
 *
 * ЧТО НАРИСОВАНО: стена сети в разрезе, проём-ворота в ней и стрелка, которая
 * проходит сквозь проём наружу; слева — то, что внутри и собирается на выход.
 *
 * ПОЧЕМУ ИМЕННО ЭТО. Шлюз — не «ещё один узел сети», а ЕДИНСТВЕННОЕ место, где
 * граница проходима. Значит рисовать надо саму границу: без стены проём не
 * существует, а стрелка без стены — просто линия и ничем не отличается от
 * линка. Стена дана в разрезе (две ножки с перевязью), поэтому разрыв в ней
 * читается проёмом, а не обрывом.
 *
 * Стрелка идёт слева направо и НЕ прерывается в проёме: шлюз выпускает, а не
 * задерживает. Наконечник — единственный на всю группу; у интерфейса линк
 * намеренно без него, чтобы два ресурса не читались одной схемой.
 *
 * Пунктирный проём — единственное цветное пятно: это то, чего ещё нет, и тон у
 * него первичный (приглашение), а не предупреждающий. Стена при этом
 * нейтральная: сеть без шлюза не сломана, она просто замкнута.
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным. Движения нет вовсе: анимация на
 * пустом экране обещает строки, которых не будет.
 */

// Узлы внутренней стороны: три источника, сходящиеся на общий сборник перед
// стеной. Перечень, а не цикл по индексу, — координаты видны глазом.
const INNER_NODE_YS = [52, 68, 84];

// Стена в разрезе: две ножки по краям проёма. Перевязь внутри каждой — чтобы
// ножка читалась кладкой, а не отдельно стоящим столбом: с одной перемычкой
// пара прямоугольников выглядела воротными столбами, и стены не было.
const WALL_LEGS = [
  { y: 26, ties: [35, 45] },
  { y: 82, ties: [91, 101] },
];

export const GatewayArt: FC = () => (
  // Смысл несёт текст под рисунком; озвучивать «стена и стрелка» нечего.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё рисунок висит в пустоте и читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Внутренняя сторона: три узла и сборник, от которого начинается выход. */}
    {INNER_NODE_YS.map((y) => (
      <g key={y}>
        <circle cx="26" cy={y} r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
        <line x1="29" y1={y} x2="40" y2={y} stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
      </g>
    ))}
    <line x1="40" y1="52" x2="40" y2="84" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Стена сети в разрезе. Разрыв между ножками — место, где стоял бы шлюз. */}
    {WALL_LEGS.map((leg) => (
      <g key={leg.y}>
        <rect x="100" y={leg.y} width="8" height="28" stroke="var(--kc-border)" strokeWidth="1.25" />
        {leg.ties.map((tie) => (
          <line
            key={tie}
            x1="100"
            y1={tie}
            x2="108"
            y2={tie}
            stroke="var(--kc-border-secondary)"
            strokeWidth="1.25"
          />
        ))}
      </g>
    ))}

    {/* Сам проём — НАМЕЧЕННЫЙ: врезан в стену и шире её, как створ ворот. Это и
        есть предмет экрана: выход, которого ещё нет. */}
    <rect
      x="92"
      y="50"
      width="24"
      height="36"
      rx="8"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />

    {/* Стрелка сквозь проём — рисуется последней, поверх створа: путь наружу
        существует ровно потому, что проём открыт. */}
    <line x1="40" y1="68" x2="176" y2="68" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="176" y1="68" x2="168" y2="63.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="176" y1="68" x2="168" y2="72.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
  </svg>
);
