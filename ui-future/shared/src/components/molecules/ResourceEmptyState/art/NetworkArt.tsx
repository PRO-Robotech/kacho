import type { FC } from "react";

/**
 * Рисунок пустого списка облачных сетей.
 *
 * ЧТО НАРИСОВАНО И ПОЧЕМУ ИМЕННО ЭТО
 *
 * Охватывающий контур — сам предмет ресурса: сеть есть изолированное адресное
 * пространство, и всё, что живёт внутри неё, нарисовано ВНУТРИ него. Именно
 * граница отличает сеть от всего остального в консоли: у подсети границы нет —
 * она диапазон внутри чужой, у набора префиксов её нет тем более.
 *
 * Внутри — сегменты на общей шине: сеть ценна не собой, а тем, что в ней можно
 * разложить подсети. Пустой контур без сегментов читался бы как «коробка», а не
 * как адресное пространство, у которого есть внутреннее устройство.
 *
 * Третий сегмент намечен пунктиром — это и есть предмет экрана: место, которое
 * пользователь займёт первым действием. Цветное пятно ровно одно и тон у него
 * первичный: приглашение, а не предупреждение (предупреждающий тон занят
 * экраном отказавшего раздела, и путать их нельзя).
 *
 * Встроенный SVG, а не файл: экран показывается и в модуле, поднятом отдельно
 * от каркаса, где путей к ассетам каркаса нет. Цвета — только токены, иначе на
 * светлой теме рисунок читался бы выключенным.
 *
 * Движения нет: анимация на пустом экране читается как продолжающаяся загрузка,
 * то есть обещает строки, которых не будет.
 */

// Сегменты внутри сети: три равных места — равенство здесь смысловое, все
// подсети сети однородны по форме, различаются они диапазоном, а не рангом.
// Перечень, а не цикл по индексу: координаты видны глазом.
const SEGMENTS = [
  { x: 34, cx: 56 },
  { x: 82, cx: 104 },
];

export const NetworkArt: FC = () => (
  // Смысл несёт текст под рисунком, поэтому для чтения с экрана рисунок скрыт.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё контур висит в пустоте и рисунок читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Контур сети — её граница. Стоит на опоре: сеть и есть основание, на
        котором строится всё остальное в разделе. */}
    <rect x="18" y="14" width="172" height="104" rx="16" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Шапка сети: имя и её адресное пространство — два штриха разной длины.
        Ритм узнаётся без подписей, которых на рисунке быть не должно. */}
    <line x1="34" y1="32" x2="62" y2="32" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="68" y1="32" x2="82" y2="32" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />

    {/* Внутренняя шина: сегменты сети связаны между собой by construction —
        это и отличает сеть от произвольного списка блоков. */}
    <line x1="34" y1="52" x2="174" y2="52" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Занятые сегменты: рамка, узел на шине и короткий штрих содержимого. */}
    {SEGMENTS.map((seg) => (
      <g key={seg.x}>
        <circle cx={seg.cx} cy="52" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
        <line
          x1={seg.cx}
          y1="52"
          x2={seg.cx}
          y2="64"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
        <rect x={seg.x} y="64" width="44" height="36" rx="6" stroke="var(--kc-border)" strokeWidth="1.25" />
        <line
          x1={seg.x + 10}
          y1="82"
          x2={seg.x + 34}
          y2="82"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
      </g>
    ))}

    {/* Узел и отвод третьего сегмента остаются в общем тоне: место под него на
        шине уже есть — нет самого сегмента. Цветом помечено только его отсутствие. */}
    <circle cx="152" cy="52" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
    <line x1="152" y1="52" x2="152" y2="64" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />

    {/* Намеченный сегмент — единственное цветное пятно рисунка. */}
    <rect
      x="130"
      y="64"
      width="44"
      height="36"
      rx="6"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />
    <line x1="146" y1="82" x2="158" y2="82" stroke="var(--kc-primary)" strokeWidth="1.25" />
    <line x1="152" y1="76" x2="152" y2="88" stroke="var(--kc-primary)" strokeWidth="1.25" />
  </svg>
);
