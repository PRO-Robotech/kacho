import type { FC } from "react";

/**
 * Рисунок пустого журнала операций.
 *
 * ЧТО НАРИСОВАНО. Лента, разделённая на кадры, и в каждом кадре одна операция:
 * сверху отметка времени, посередине сама запись, снизу её исход. Кадры разной
 * длины записи — операции не одинаковы, и каждая заканчивается по-своему.
 *
 * ПОЧЕМУ ИМЕННО ЭТО. Операция в Kachō асинхронна: мутация возвращает не ресурс,
 * а запись о начатом изменении, и смотрят на неё ПО ВРЕМЕНИ — что было раньше,
 * что позже, чем кончилось. Поэтому лента, а не таблица строк: таблица говорит
 * «вот набор», лента говорит «вот ход событий», и пустая лента честно означает
 * «пока ничего не происходило», а не «ничего не заведено».
 *
 * ЦВЕТНОЕ ПЯТНО ОДНО — последний кадр пунктиром: отметки ещё не было. Тон
 * первичный, а не предупреждающий: отсутствие операций — нормальное состояние
 * только что созданного проекта, а не отказ.
 *
 * Встроенный SVG, а не файл и не внешний адрес: экран показывается и в модуле,
 * поднятом отдельно от каркаса, где путей к ассетам каркаса нет. Цвета — только
 * токены: литерал не меняется вместе с темой, и на светлой теме рисунок читался
 * бы выключенным.
 *
 * Движения нет вовсе: на журнале асинхронных изменений анимация читается как
 * «идёт прямо сейчас» — то есть обещает записи, которых не будет.
 */

// Кадры ленты. Длина записи у каждого своя — перечнем, а не циклом: одинаковые
// штрихи читались бы как разметка, а не как три разных события.
const FRAMES = [
  { id: "first", cx: 36, entryTo: 48, outcomeTo: 44 },
  { id: "second", cx: 81, entryTo: 87, outcomeTo: 85 },
  { id: "third", cx: 126, entryTo: 140, outcomeTo: 138 },
];

// Границы кадров внутри ленты.
const FRAME_EDGES = [59, 104, 149];

export const OperationArt: FC = () => (
  // Смысл несёт текст под рисунком; озвучивать схему нечего.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё лента висит в пустоте и рисунок читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Лента целиком: она горизонтальна, потому что несёт ВРЕМЯ, а не перечень. */}
    <rect x="14" y="36" width="180" height="64" rx="10" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Границы кадров: одна операция — один кадр, соседние не сливаются. */}
    {FRAME_EDGES.map((x) => (
      <line key={x} x1={x} y1="36" x2={x} y2="100" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
    ))}

    {/* Прошедшие операции: отметка времени, запись, исход. Исход отмечен кружком
        у левого края строки — место под состояние есть у каждой операции. */}
    {FRAMES.map((frame) => (
      <g key={frame.id}>
        <line
          x1={frame.cx - 14}
          y1="50"
          x2={frame.cx + 14}
          y2="50"
          stroke="var(--kc-text-tertiary)"
          strokeWidth="1.25"
        />
        <line
          x1={frame.cx - 14}
          y1="68"
          x2={frame.entryTo}
          y2="68"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
        <circle cx={frame.cx - 13} cy="85" r="2.5" stroke="var(--kc-text-tertiary)" strokeWidth="1.25" />
        <line
          x1={frame.cx - 6}
          y1="85"
          x2={frame.outcomeTo}
          y2="85"
          stroke="var(--kc-border-secondary)"
          strokeWidth="1.25"
        />
      </g>
    ))}

    {/* Последний кадр — предмет экрана: место под операцию, которой ещё не было.
        Внутри пусто намеренно: у несостоявшегося события нет ни времени, ни
        исхода, и дорисовывать их значило бы обещать запись, которой нет. */}
    <rect
      x="155"
      y="44"
      width="32"
      height="48"
      rx="6"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />
  </svg>
);
