import type { FC } from "react";

/**
 * Рисунок пустого списка — В ТОМ ЖЕ КЛЮЧЕ, что рисунок отказавшего раздела.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЛИНИЯ, А НЕ ПЛИТКА С ГЛИФОМ
 *
 * Здесь стояла плитка 96×96 с иконкой ресурса на заливке. Рядом, на экране
 * «раздел временно недоступен», — линейный рисунок из токенов со штрихом 1.25.
 * Два состояния ОДНОГО рода («смотреть не на что, вот следующий шаг») выглядели
 * приехавшими из разных продуктов: одно пятном насыщенного цвета, другое
 * чертежом. Решение владельца — один стиль; общий здесь линейный, потому что
 * плитка-глиф не масштабируется до рассказа о состоянии, а чертёж масштабируется.
 *
 * ЧТО НАРИСОВАНО
 *
 * Полка списка с двумя пустыми местами и точкой ввода на первом. Не «пустая
 * коробка»: пустое место с намеченной первой строкой читается как приглашение,
 * а не как поломка. Цветное пятно ровно одно — маркер первой строки, и тон у
 * него первичный (приглашение), а не предупреждающий (там предмет другой).
 *
 * Встроенный SVG, а не файл: пустой список показывается и в модуле, поднятом
 * отдельно от каркаса, где путей к ассетам каркаса нет. Цвета — только токены,
 * иначе на светлой теме рисунок читался бы выключенным.
 *
 * Движения нет: анимация на пустом экране читается как продолжающаяся загрузка,
 * то есть обещает, что вот-вот появятся строки, — а их не будет.
 */
export const ResourceEmptyArt: FC = () => (
  // Смысл несёт текст под рисунком; озвучивать «схема из трёх полок» нечего.
  <svg
    viewBox="0 0 208 136"
    width="208"
    height="136"
    fill="none"
    strokeLinecap="round"
    aria-hidden="true"
    focusable="false"
    style={{ maxWidth: "100%" }}
  >
    {/* Опора: без неё рамка висит в пустоте и рисунок читается обрезанным. */}
    <line x1="10" y1="118" x2="198" y2="118" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Рамка списка со своей шапкой — то же, что увидит пользователь, когда
        строки появятся. Пустота показана В КОНТЕКСТЕ таблицы, а не сама по себе. */}
    <rect x="26" y="16" width="156" height="102" rx="12" stroke="var(--kc-border)" strokeWidth="1.25" />
    <line x1="26" y1="42" x2="182" y2="42" stroke="var(--kc-border)" strokeWidth="1.25" />

    {/* Заголовки столбцов: короткие штрихи разной длины — шапка узнаётся по
        ритму, а не по подписям, которых на рисунке быть не должно. */}
    {[
      { x: 42, w: 30 },
      { x: 86, w: 20 },
      { x: 120, w: 26 },
    ].map((c) => (
      <line
        key={c.x}
        x1={c.x}
        y1="29"
        x2={c.x + c.w}
        y2="29"
        stroke="var(--kc-text-tertiary)"
        strokeWidth="1.25"
      />
    ))}

    {/* Первая строка — НАМЕЧЕННАЯ: пунктир и точка ввода. Это и есть предмет
        экрана: место под ресурс, которого ещё нет. */}
    <rect
      x="40"
      y="54"
      width="128"
      height="18"
      rx="5"
      fill="var(--kc-primary-bg)"
      stroke="var(--kc-primary)"
      strokeWidth="1.25"
      strokeDasharray="4 4"
    />
    <line x1="53" y1="63" x2="61" y2="63" stroke="var(--kc-primary)" strokeWidth="1.25" />
    <line x1="57" y1="59" x2="57" y2="67" stroke="var(--kc-primary)" strokeWidth="1.25" />

    {/* Вторая строка — просто пустая: одна намеченная строка говорит «начните
        отсюда», две одинаковые говорили бы «здесь всегда пусто». */}
    <rect x="40" y="82" width="128" height="18" rx="5" stroke="var(--kc-border-secondary)" strokeWidth="1.25" />
  </svg>
);
