// CopyableId — идентификатор ресурса моноширинно, В ОДНУ СТРОКУ, с копированием.
// Click копирует через navigator.clipboard, показывает toast и подменяет
// иконку на ✓ на 1.5s. Используется везде, где раньше был truncated `slice(0,8)…`.
//
// ОДНА СТРОКА — не косметика, а форма ячейки. Прежде значение несло `break-all`,
// то есть переносилось по любому знаку: в узкой колонке `rtb6qc1500147672jdm`
// разрывался посреди хвоста, буква уезжала во вторую строку, и СТРОКА ТАБЛИЦЫ
// становилась выше соседних. Отсюда сразу два наблюдаемых дефекта — рваный
// идентификатор и разная высота строк. Поэтому здесь `nowrap` + многоточие:
// сколько колонка даёт, столько и показано, остальное — в подсказке и в буфере.
// Ширину колонки это НЕ лечит и не должно: перенос был свойством ячейки.
//
// Кнопкой является ВСЁ значение целиком, а не отдельный значок сбоку: щёлкнуть
// по идентификатору и получить его в буфере — то, ради чего он вообще показан
// (core #15: id — единственная внешне-адресуемая координата ресурса). Поэтому
// форму копирующей кнопки целевого оформления (радиус 6, тусклый тон, заливка
// при наведении) несёт вся строка, а не квадрат 30×30 рядом с ней: у ячейки
// таблицы отступ 9px сверху и снизу, содержимое строки — 20px, то есть строка
// ≈38px; квадрат 30×30 поднял бы КАЖДУЮ строку до ≈48px. Именно в таблицах этот
// атом и стоит чаще всего, а высота строки — предмет отдельного дефекта.

import { useState } from "react";
import { useInPropertyRow } from "@shared/components/organisms/DetailShell/property-row-context";
import { MonoValue } from "./MonoValue";
import { Check, Copy } from "lucide-react";
import { toast } from "@shared/lib/toast";
import { cn } from "@shared/lib/utils";

interface Props {
  id: string;
  className?: string;
  // false — без иконки рядом (подсказка title всё равно работает; click активен).
  showIcon?: boolean;
}

export function CopyableId({ id, className, showIcon = true }: Props) {
  // В СТРОКЕ СВОЙСТВ идентификатор — не кнопка, а текст: копирование там общее и
  // стоит столбцом справа. Прежде значение отзывалось само, и в одной таблице
  // жили два поведения. Спрашиваем место, а не проп: правило исполняется само.
  const inPropertyRow = useInPropertyRow();
  const [copied, setCopied] = useState(false);

  // Рисует его `MonoValue`, а НЕ такой же `<span>` здесь: тот же вид, объявленный
  // дважды, расходится молча — сегодня это байт-в-байт одна разметка, а завтра у
  // одной из копий поправят подсказку или тон, и в одной карточке будут жить два
  // поведения (канон §9). `MonoValue` уже рисует девять строк свойств, где
  // идентификатор приходит значением, а не через этот атом.
  if (inPropertyRow) return <MonoValue value={id} />;
  if (!id) return <span className="text-muted-foreground">—</span>;

  const onCopy = async (e: React.MouseEvent) => {
    e.preventDefault();
    e.stopPropagation();
    try {
      await navigator.clipboard.writeText(id);
      setCopied(true);
      toast.success("ID скопирован");
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Не удалось скопировать");
    }
  };

  return (
    <button
      type="button"
      onClick={onCopy}
      title={copied ? "Скопировано" : "Скопировать ID"}
      // Отступ уходит в отрицательное поле: заливка при наведении обязана
      // дышать вокруг значения, но левый край значения при этом остаётся на
      // линии колонки — иначе столбец идентификаторов «поедет» относительно
      // соседних.
      //
      // `minWidth: 0` — условие работы многоточия: без него flex-элемент
      // отказывается быть уже своего содержимого, и обрезка не наступает
      // никогда, сколь бы узкой ни была колонка.
      //
      // Переход задан токенами продукта (160 мс, общая кривая), а не набором
      // Tailwind: движение по консоли обязано читаться как одно вещество.
      // Меняются ровно две вещи, которые здесь и меняются, — цвет и заливка.
      // Отступы и радиус — КЛАССОМ, а не инлайном.
      //
      // Инлайновое объявление невозможно переопределить снаружи без `!important`,
      // и строка свойств не могла подвинуть кнопку к общему правому краю: три
      // значка копирования стояли на 1217, 1227 и 1235 при внутреннем крае
      // ячейки 1227. Значения те же, что были, — меняется только место
      // объявления, поэтому в таблицах вид не трогается.
      style={{ minWidth: 0, maxWidth: "100%" }}
      className={cn(
        "kc-copyable-id",
        "inline-flex items-center gap-1.5 t-mono",
        "text-[var(--kc-text-tertiary)] hover:text-[var(--kc-text)] hover:bg-[var(--kc-hover-fill)]",
        "cursor-pointer",
        "max-w-full",
        className,
      )}
    >
      {/* Подсказка несёт ЗНАЧЕНИЕ, а не название действия: когда колонка узка,
          обрезанный идентификатор перестаёт читаться, и вернуть его глазам
          важнее, чем повторить «скопировать» — про действие говорят курсор,
          значок и подсказка самой кнопки на её нетекстовой части. */}
      <span
        title={id}
        style={{
          minWidth: 0,
          overflow: "hidden",
          textOverflow: "ellipsis",
          whiteSpace: "nowrap",
        }}
        className="text-left"
      >
        {id}
      </span>
      {/* Значок виден ВСЕГДА, а не по наведению (решение владельца). Действие,
          которого не видно, пока на него не навели, недоступно с сенсорного
          ввода вовсе — там наведения нет как события, — а глазами страницу
          нельзя прочесть как список доступных возможностей. Тишину держит ТОН,
          а не отсутствие: значок берёт цвет кнопки (`currentColor`), то есть
          тусклый в покое и яркий, когда к нему потянулись. Отсюда же снят класс
          `group` с кнопки — он стоял ЯКОРЕМ прежнего правила появления, и без
          правила у него не осталось ни одного читателя.

          Подтверждение остаётся видимым и после ухода курсора: галочка живёт
          своим таймером (1.5 с), а не наведением, — пропав вместе с курсором,
          она не успевала бы прочитаться. */}
      {showIcon &&
        (copied ? (
          <Check
            className="h-3 w-3 shrink-0"
            style={{ color: "var(--status-ok-fg)" }}
          />
        ) : (
          <Copy className="h-3 w-3 shrink-0" />
        ))}
    </button>
  );
}
