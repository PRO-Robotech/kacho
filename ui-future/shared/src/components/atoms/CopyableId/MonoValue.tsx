import type { CSSProperties } from "react";

/**
 * Идентификатор в СТРОКЕ СВОЙСТВ: моноширинный текст, и только текст.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ `CopyableId` И ЗАЧЕМ ВВЕДЁН
 *
 * `CopyableId` — кнопка целиком: копирует клик по САМОМУ ЗНАЧЕНИЮ, и всё
 * значение подсвечивается при наведении. В таблице это верно — там у ячейки нет
 * столбца действий, и удобно нажать на сам идентификатор.
 *
 * В строке свойств рядом стоят другие строки, и у них кнопка одна — значок
 * справа. Получалось два разных поведения в одной таблице: у «Имени» отзывается
 * значок, у «Идентификатора» — вся строка. Решение владельца — одно поведение,
 * поэтому здесь значение перестаёт быть кнопкой, а копирование берёт на себя
 * общий значок строки (`copy` у элемента списка свойств).
 *
 * Отдельный компонент, а не голый `<span>` у каждого вызывающего: обрезка,
 * шрифт и подсказка с полным значением обязаны совпадать у всех девяти мест, где
 * идентификатор показывается строкой свойств.
 */
const style: CSSProperties = {
  minWidth: 0,
  overflow: "hidden",
  textOverflow: "ellipsis",
  whiteSpace: "nowrap",
  color: "var(--kc-text-tertiary)",
};

export function MonoValue({ value }: { value: string }) {
  if (!value) return <span className="text-muted-foreground">—</span>;
  // Подсказка несёт ПОЛНОЕ значение: в узкой колонке идентификатор обрезается,
  // и вернуть его глазам важнее, чем повторить название действия.
  return (
    <span className="t-mono" style={style} title={value}>
      {value}
    </span>
  );
}
