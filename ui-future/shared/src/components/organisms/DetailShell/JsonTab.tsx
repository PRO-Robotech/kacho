// JsonTab — вкладка «JSON» карточки ресурса: полотно редактора плюс кнопка
// «скопировать целиком».
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ КОМПОНЕНТ. Вкладку строят ДВЕ оболочки карточки —
// `ResourceShell` (все ресурсы общего реестра) и `ResourceDetailPage`. Пока
// каждая собирала её у себя, копирование пришлось бы заводить дважды, и вторая
// копия разошлась бы с первой на первой же правке: два места об одном предмете.
//
// ПОЧЕМУ КНОПКА В ШАПКЕ СТРАНИЦЫ, А НЕ НАД ПОЛОТНОМ. У вкладки уже есть
// заведённое место для своих ручек — правый слот строки имени (`HeaderSlotPortal`,
// им пользуются связанные таблицы и операции). Своя шапка над полотном была бы
// вторым таким местом на одной странице, и читателю пришлось бы искать ручку
// то там, то тут.
//
// ПОЧЕМУ КОПИРУЕТСЯ СЕРИАЛИЗАЦИЯ, А НЕ ВЫДЕЛЕНИЕ. Полотно доступно только на
// чтение и прокручивается: выделить его целиком мышью нельзя, а «скопировать
// видимое» отдало бы кусок. Строка собирается тем же способом, каким её рисует
// редактор (отступ в два пробела), поэтому в буфере оказывается ровно то, что
// на экране.

import { useMemo, useState } from "react";
import { Button } from "antd";
import { Check, Copy } from "lucide-react";
import { LazyJsonMonacoView } from "@shared/components/molecules/JsonMonacoView";
import { toast } from "@shared/lib/toast";
import { HeaderSlotPortal } from "./DetailShell";
import { copyText } from "@shared/lib/clipboard";

interface Props {
  data: unknown;
}

export function JsonTab({ data }: Props) {
  const [copied, setCopied] = useState(false);
  // Сериализация мемоизируется: карточка поллит ресурс каждые пять секунд и
  // передаёт новый объект, а строка нужна только кнопке. Без этого она
  // пересобиралась бы на каждый ответ края.
  const text = useMemo(() => JSON.stringify(data, null, 2), [data]);

  const onCopy = async () => {
    try {
      // См. `@shared/lib/clipboard`.
      if (!(await copyText(text))) throw new Error("буфер недоступен");
      setCopied(true);
      toast.success("JSON скопирован");
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Не удалось скопировать");
    }
  };

  return (
    <div>
      <HeaderSlotPortal>
        {/* Высота — как у соседей по ряду (поиск, отбор, выбор столбцов).
            Уменьшенная кнопка стояла бы в ряду единственной низкой, и ряд
            читался бы как два ряда. */}
        <Button
          icon={copied ? <Check size={14} /> : <Copy size={14} />}
          onClick={() => void onCopy()}
          title="Скопировать JSON целиком"
        >
          {copied ? "Скопировано" : "Скопировать"}
        </Button>
      </HeaderSlotPortal>
      {/* Высота полотна остаётся его собственной (доля окна). Растянуть его на
          доступную высоту отсюда нельзя: полотно резолвит свою высоту в
          процентах от собственной обёртки, а её высоту задаёт не эта вкладка, —
          и «сделать по месту» превратилось бы в догадку о чужой раскладке,
          проверить которую нечем без браузера. */}
      <LazyJsonMonacoView data={data} />
    </div>
  );
}
