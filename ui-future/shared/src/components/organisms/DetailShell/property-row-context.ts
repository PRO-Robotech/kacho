import { createContext, useContext } from "react";

/**
 * «Это значение стоит в СТРОКЕ СВОЙСТВ» — один признак на всю консоль.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ПРИЗНАК, А НЕ ПРОП У КАЖДОГО КОМПОНЕНТА
 *
 * В строке свойств копирование ОБЩЕЕ: одна кнопка на строку, столбцом у правого
 * края. В ячейке таблицы такого столбца нет, и там значение копирует себя само.
 * Разница принадлежит МЕСТУ, а не компоненту, — поэтому решает место.
 *
 * Пока это выражалось пропами (`copy={false}` у каждого вызова), правило
 * приходилось помнить при каждом новом значении. Оно и не удержалось: за один
 * заход строка размещения, ссылка на сеть и ссылка на таблицу маршрутов
 * трижды оказывались со своим значком, прилипшим к тексту, — потому что их
 * добавляли, не зная о договорённости.
 *
 * С признаком договорённость исполняется САМА: компонент спрашивает «я в строке
 * свойств?» и рисует себя соответственно. Новый компонент, попав в строку,
 * подчинится ей, ничего не зная о ней заранее.
 */
const PropertyRowContext = createContext(false);

export const PropertyRowProvider = PropertyRowContext.Provider;

/** true — значение рисуется внутри строки свойств (копирование там общее). */
export function useInPropertyRow(): boolean {
  return useContext(PropertyRowContext);
}
