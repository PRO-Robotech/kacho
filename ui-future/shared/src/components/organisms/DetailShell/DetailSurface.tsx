/** Значок копирования, стоящий вплотную за значением строки. Отдельным
 *  компонентом — из-за состояния «скопировано»: держать его в `PropertyRows`
 *  значило бы одно состояние на все строки сразу, и подтверждение зажигалось бы
 *  не там, где нажали. */
function ValueCopy({ value, label }: { value: string; label: string }) {
  const [copied, setCopied] = useState(false);
  const onCopy = async () => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      toast.success("Скопировано");
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Не удалось скопировать");
    }
  };
  return (
    <button
      type="button"
      className="kc-props-copy"
      data-copied={copied ? "true" : undefined}
      // Название действия несёт ИМЯ ПОЛЯ: на карточке таких кнопок столько же,
      // сколько строк, и «Скопировать» без предмета не различает ни одну из них
      // для того, кто читает страницу не глазами.
      aria-label={`Скопировать: ${label}`}
      title={copied ? "Скопировано" : `Скопировать: ${label}`}
      onClick={() => void onCopy()}
    >
      {copied ? <Check size={13} /> : <Copy size={13} />}
    </button>
  );
}

/** Текст названия строки — для подписи кнопки копирования. Название бывает
 *  узлом (имя плюс подсказка ⓘ), и вытащить из узла строку в общем случае
 *  нельзя; тогда подпись говорит о значении, а не выдумывает имя поля. */
function labelText(label: ReactNode): string {
  return typeof label === "string" ? label : "значение";
}

/** Перечень свойств ресурса — эталонная строка «ключ · значение».
 *
 *  Разметка та же, что у эталона: `dl` → `div` → `dt`/`dd`. Пустой перечень
 *  рисует пустой `dl`, а не «нет свойств»: строку с сообщением придумывает
 *  вызывающий, если ему есть что сказать. */
export function PropertyRows({ items }: { items: PropertyItem[] }) {
  return (
    <>
      {/* Лист стоит СНАРУЖИ `dl`: у списка определений законные дети — только
          `dt`/`dd`/`div`, и валидность разметки не приносится в жертву
          удобству. */}
      <style>{PROPERTY_CSS}</style>
      <dl className="kc-props">
        {items.map((it, i) => {
          // Простое значение (строка/число) обрезается многоточием, узел — нет.
          const plain = typeof it.value === "string" || typeof it.value === "number";
          return (
            <div className="kc-props-row" key={i}>
              <dt>{it.label}</dt>
              <dd>
                {/* Признак «я в строке свойств» — чтобы вложенные значения не
                    рисовали СВОИХ кнопок копирования: здесь она одна на строку и
                    стоит столбцом справа. Признак вместо пропа у каждого вызова:
                    правило принадлежит месту, и место его и объявляет. */}
                <PropertyRowProvider value={true}>
                  {plain ? <span className="kc-props-text">{it.value}</span> : it.value}
                </PropertyRowProvider>
                {it.copy ? <ValueCopy value={it.copy} label={labelText(it.label)} /> : null}
              </dd>
            </div>
          );
        })}
      </dl>
    </>
  );
}

interface SurfaceProps {
  /** Заголовок секции. Без него шапки нет вовсе — пустая полоса читалась бы
   *  как «заголовок не загрузился». */
  title?: ReactNode;
  /** Примечание справа в шапке — тише заголовка: счётчик секции, оговорка о
   *  полноте. Здесь же стоял отдельный `count` рядом с заголовком; его не
   *  передавал НИ ОДИН вызывающий за всё время жизни — форма без содержания, —
   *  и держать два места под одно и то же значило заводить расхождение заранее. */
  note?: ReactNode;
  children: ReactNode;
}

/** Поверхность-секция: заливка, рамка, радиус 11, шапка с заголовком, БЕЗ тени.
 *
 *  Заливка появилась вместе со снятием ОБЩЕЙ подложки страницы. Пока карточка
 *  ресурса сама была поверхностью, вторая заливка поверх неё дала бы третий тон —
 *  ту самую вложенную карточку, которую эталон запрещает, и фон здесь был
 *  прозрачным. Теперь снаружи фон страницы, и секция обязана быть поверхностью
 *  сама: иначе рамка висит на пустоте и «Обзор» не отделён от рабочей области.
 *  Комментарий переписан вместе с основанием — довод, переживший свой предмет,
 *  вернул бы прозрачность следующей правкой. */
export function DetailSurface({ title, note, children }: SurfaceProps) {
  return (
    <section
      style={{
        border: "1px solid var(--kc-border)",
        borderRadius: 11,
        background: "var(--kc-surface-bg)",
        overflow: "hidden",
      }}
    >
      {title !== undefined && (
        // ШАПКА — ЭТО ПЕРВАЯ СТРОКА ТАБЛИЦЫ, А НЕ БЛОК НАД НЕЙ.
        //
        // Прежде она была высотой 54 при высоте строки таблицы 45 и стояла на
        // том же фоне, что и строки, — то есть выглядела строкой, но на четверть
        // выше остальных, и оттого читалась приделанной сверху. Одинаковая
        // высота и своя, чуть отличная заливка делают её шапкой ЯВНО: она
        // отличается по назначению, а не по случайной геометрии.
        //
        // Подпись справа (у секции адресов это «Адресное пространство») набрана
        // тем же кеглем, что заголовки столбцов таблиц продукта, и стоит на
        // одной с заголовком линии — как правая часть шапки, а не как оторванная
        // приписка.
        <header
          style={{
            display: "flex",
            alignItems: "center",
            justifyContent: "space-between",
            gap: 16,
            height: 45,
            padding: "0 16px",
            background: "var(--kc-field)",
            borderBottom: "1px solid var(--kc-border)",
          }}
        >
          <h2
            style={{
              display: "flex",
              alignItems: "center",
              gap: 9,
              margin: 0,
              fontSize: 13,
              fontWeight: 650,
              letterSpacing: "-0.01em",
              color: "var(--kc-text)",
            }}
          >
            {title}
          </h2>
          {note !== undefined && (
            <span
              style={{
                color: "var(--kc-text-tertiary)",
                fontSize: 11,
                fontWeight: 600,
                letterSpacing: "0.02em",
                whiteSpace: "nowrap",
              }}
            >
              {note}
            </span>
          )}
        </header>
      )}
      {children}
    </section>
  );
}
