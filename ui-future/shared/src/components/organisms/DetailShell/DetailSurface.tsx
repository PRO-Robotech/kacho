// Язык карточки ресурса: поверхность-секция и строка свойства.
//
// Оба взяты у эталона операторской (`network-detail.html, .surface и
// .property) и живут здесь, потому что ими пользуются ОБЕ страницы карточки —
// ResourceShell и ResourceDetailPage. Раньше «Обзор» рисовал Descriptions
// antd: он даёт таблицу с собственной рамкой на каждой ячейке, то есть решётку
// там, где эталон держит одну горизонтальную линию между строками.
//
// ЧТО ЗАДАЁТ ФОРМУ. Геометрия строки живёт в КЛАССЕ, а не в инлайн-стилях, и
// это не вкусовщина: у строки есть состояния, которых инлайном не выразить
// (последняя в списке — без нижней линии; узкая страница — одна колонка), а
// инлайн-стиль перебивает любое правило листа, так что смешение дало бы
// половину формы, которую нельзя переопределить. Лист печатает сам компонент —
// тогда строка выглядит одинаково везде, где её отрисовали, и не зависит от
// того, подключил ли модуль общий стилевой вход.

import { useState, type ReactNode } from "react";
