/** Строка свойства: ключ и значение. label — узел, а не строка: ключу бывает
 *  нужна подсказка ⓘ рядом с именем (см. DescItem расширений карточки). */
export interface PropertyItem {
  label: ReactNode;
  value: ReactNode;
  /** Что кладётся в буфер значком РЯДОМ СО ЗНАЧЕНИЕМ. Не задано — значка нет.
   *
   *  Объявляется только там, где у значения НЕТ СВОЕГО копирования. Значение,
   *  которое копирует себя само (CopyableId, CopyableName, ResourceLink
   *  с copy), несёт значок внутри себя — это и есть форма продукта, — и
   *  второй значок рядом с ним был бы вторым предложением сделать одно и то же.
   *
   *  Копируется ИСХОДНОЕ значение, а не то, что видно: значение обрезается
   *  многоточием, и копирование видимого отдало бы обрезок. Поэтому здесь
   *  строка, а не «взять текст узла» — узел рисует ссылку, набор меток или
   *  факт со своим словом, и что из них считать значением, знает вызывающий,
   *  а не строка. */
  copy?: string;
}

