// Копирование значения в строке обзора.
//
// ПРЕДМЕТ. Значение строки обрезается многоточием — это условие сетки: длинный
// идентификатор не вправе растягивать колонку и ломать соседние строки. Цена
// обрезки в том, что обрезанное НЕЛЬЗЯ выделить мышью, а именно эти значения и
// переносят в чужие поля (идентификатор в запрос, MAC в конфигурацию гостя).
// Значит у строки обязана быть кнопка, кладущая в буфер ИСХОДНОЕ значение.
//
// ЧТО ИМЕННО УТВЕРЖДАЕТСЯ — наблюдаемое: кнопка есть · в буфер уезжает полное
// значение, а не показанный обрезок · подпись кнопки называет ПОЛЕ (иначе для
// читающего страницу не глазами все кнопки карточки называются одинаково).
// Отрицание стоит в паре с положительным: строка БЕЗ объявленного копирования
// кнопки не несёт — без этой пары проба зеленела бы на компоненте, который
// рисует кнопку каждой строке подряд.

import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { PropertyRows } from "./DetailSurface";

const LONG_VALUE = "net-0123456789abcdefghijklmnopqrstuvwxyz-конец";

let copied: string[] = [];

beforeEach(() => {
  copied = [];
  // Буфера обмена в jsdom нет вовсе. Подменяется он ЦЕЛИКОМ и на каждую пробу:
  // общий на файл накапливал бы записи соседних проб, и утверждение «уехало
  // ровно это» стало бы утверждением «уехало в том числе это».
  Object.defineProperty(globalThis.navigator, "clipboard", {
    configurable: true,
    value: {
      writeText: (t: string) => {
        copied.push(t);
        return Promise.resolve();
      },
    },
  });
});

describe("строка обзора: копирование значения", () => {
  it("строка с объявленным копированием несёт кнопку, и в буфер уезжает ПОЛНОЕ значение", async () => {
    render(<PropertyRows items={[{ label: "Идентификатор", value: LONG_VALUE, copy: LONG_VALUE }]} />);

    const button = screen.getByRole("button", { name: "Скопировать: Идентификатор" });
    await userEvent.click(button);

    expect(copied).toEqual([LONG_VALUE]);
  });

  it("строка БЕЗ объявленного копирования кнопки не несёт (парное отрицание)", () => {
    render(<PropertyRows items={[{ label: "Дата создания", value: "1 января 2026" }]} />);

    expect(screen.queryByRole("button")).toBeNull();
  });

  it("подпись кнопки называет поле, а не только действие", () => {
    render(
      <PropertyRows
        items={[
          { label: "Имя", value: "core", copy: "core" },
          { label: "Описание", value: "опорная сеть", copy: "опорная сеть" },
        ]}
      />,
    );

    expect(screen.getAllByRole("button").map((b) => b.getAttribute("aria-label"))).toEqual([
      "Скопировать: Имя",
      "Скопировать: Описание",
    ]);
  });

  it("название строки — узел, а не строка: подпись говорит о значении и кнопка остаётся достижимой", () => {
    // Ключу бывает нужна подсказка ⓘ рядом с именем, и тогда `label` — узел.
    // Вытащить из узла имя поля в общем случае нельзя; проба закрепляет, что в
    // этом случае кнопка не исчезает и не получает пустого имени.
    render(<PropertyRows items={[{ label: <span>MAC-адрес</span>, value: "0e:11:22", copy: "0e:11:22" }]} />);

    expect(screen.getByRole("button", { name: "Скопировать: значение" })).toBeInTheDocument();
  });
});
