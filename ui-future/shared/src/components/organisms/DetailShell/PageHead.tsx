import type { ReactNode } from "react";
import { Typography } from "antd";

// Высота блока-шапки — ОДНА на все страницы. У карточки ресурса она вдобавок
// зеркалится боковой панелью, чтобы нижние линии обеих зон встали на одной y:
// разная высота читалась бы как две сшитые страницы.
//
// ВЫНОСНЫЕ БУКВЫ ПОМЕЩАЮТСЯ ВНУТРИ СТРОКИ, А НЕ В ПОДОБРАННОМ ЗАПАСЕ.
//
// Здесь дважды стояло подобранное число: сперва 40 (ровно строка), потом 44
// (строка плюс «запас на хвосты»). Оба раза это была подпорка: высота строки
// была 1.05 от кегля, то есть МЕНЬШЕ того, что шрифт занимает на самом деле, и
// хвосты «у», «р», «д», а у латиницы «g», «y», «p» выходили за неё. Один
// множитель — 1.05 — не покрывает ни одну гарнитуру: ниже базовой линии шрифт
// уводит до 0.22 от кегля, и сколько ни добавляй к контейнеру, буква всё равно
// выходит ЗА СВОЮ строку, а значит однажды наползёт на то, что стоит ниже.
//
// Правильная величина — та, при которой строка вмещает шрифт целиком. Она
// ЗАМЕРЕНА, а не выбрана: при 1.25 браузер отдавал содержимому 41 точку против
// коробки в 40, и `overflow: hidden` (он нужен многоточию по горизонтали) срезал
// ровно эту точку — на глаз это и есть «текст не помещается». При 1.35 запас
// положительный и у латинских выносных («g», «y», «p»), и у кириллических
// («у», «р», «ц»), проверено обеими на живой странице.
//
// Высота блока = высота строки, поэтому число ниже не подбирается руками: оно
// вычисляется из кегля и множителя, и правка одного меняет второе.
//
// Прежде сюда входил ещё надзаголовок (9px плюс отступ 8), отчего высота была
// 52; надзаголовок снят решением владельца.
export const HEAD_TITLE_SIZE_MAX = 32;
export const HEAD_TITLE_LINE_HEIGHT = 1.35;
export const HEAD_CONTENT_HEIGHT = Math.ceil(HEAD_TITLE_SIZE_MAX * HEAD_TITLE_LINE_HEIGHT);
// Отступы уменьшены (решение владельца: «вкладки поднять выше»): было 18 + 18,
// стало 8 + 8. Вкладки и первая строка таблицы поднимаются на 20 точек, а буквы
// заголовка на них не наползают — за это отвечает запас в высоте выше, а не
// расстояние до следующего блока.
export const HEAD_PADDING_BOTTOM = 8;
export const HEAD_BLOCK_HEIGHT = HEAD_CONTENT_HEIGHT + HEAD_PADDING_BOTTOM;

/** Ширина колонки содержимого карточки ресурса.
 *
 *  ОДНА на все блоки: обзор, секции адресов, связанные секции. Разные значения
 *  ставили правый край страницы лесенкой (920 у обзора против 760 у секций), и
 *  блоки читались как приехавшие из разных мест. Строка «ключ · значение» при
 *  этом остаётся читаемой: 920 — верхняя граница удобной длины строки, а не
 *  «сколько влезет». */
export const DETAIL_CONTENT_WIDTH = 920;

/** Поля страницы — ОДНИ на список, карточку и форму.
 *
 *  Здесь их было двое: у списка и карточки `20px 24px`, у формы `20`. Четыре
 *  точки разницы по горизонтали не видны на статичной странице и отлично видны
 *  в переходе: заголовок «Облачные сети» и заголовок «Создать облачную сеть»
 *  стоят на разных вертикалях, и при навигации текст дёргается.
 *
 *  Значение живёт рядом с шапкой, а не у каждой страницы: пока их было двое,
 *  правка одной не доезжала до другой — и не доехала. */
export const PAGE_PADDING = "20px 24px";

interface Props {
  /** Заголовок — САМ предмет страницы. */
  title: ReactNode;
  /** Признаки состояния предмета (статус, пометки). Стоят рядом с именем, а не
   *  среди действий справа: они описывают предмет, а не предлагают что-то с ним
   *  сделать. */
  badges?: ReactNode;
  /** Действия и слоты справа, на одной высоте с заголовком. */
  right?: ReactNode;
  /** Линия под шапкой. Снимается там, где сразу под ней идут вкладки: две линии
   *  в двух десятках пикселей друг от друга читаются как пустая полоса между
   *  ними, а имя ресурса отрывается от своих же вкладок. */
  divider?: boolean;
}

/**
 * Шапка страницы: надзаголовок над крупным заголовком, действия справа, линия снизу.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ОДНА СТРОКА: ТОЛЬКО ПРЕДМЕТ СТРАНИЦЫ
 *
 *   список:   Облачные сети            карточка:  networks-722779
 *
 * Здесь был надзаголовок-родитель — «VPC» над списком, «ОБЛАЧНАЯ СЕТЬ» над
 * карточкой, прописными и с чёрточкой. Снят решением владельца: родителя
 * называют уже три места сразу — хлебные крошки в шапке приложения, подсветка
 * в колонке ресурсов и сам адрес, — и четвёртое ничего не добавляло, занимая
 * строку над каждым заголовком продукта.
 *
 * Чего в шапке НЕТ помимо этого:
 *
 *  - надзаголовка «Список». Он сообщал способ показа вместо предмета и стоял
 *    одинаковым на каждой странице списка — то есть не различал ничего;
 *  - счётчика элементов (снят решением владельца ВЕЗДЕ);
 *  - иконки-плитки. Иконка здесь — признак ИДЕНТИЧНОСТИ ресурса, и её место в
 *    боковой панели карточки, рядом с именем экземпляра. У секции её нет.
 */
export function PageHead({ title, badges, right, divider = true }: Props) {
  return (
    <div
      style={{
        display: "flex",
        justifyContent: "space-between",
        alignItems: "flex-end",
        gap: 16,
        flexWrap: "nowrap",
        // ГЕОМЕТРИЯ ШАПКИ ОДНА, ЧЕМ БЫ ЕЁ НИ ЗАПОЛНИЛИ.
        //
        // `height`, а не `minHeight`: содержимое правого слота у страниц разное
        // — у списка поиск и две кнопки, у карточки действия и слот фильтров, у
        // формы ничего, — и на `minHeight` блок рос от самого высокого из них.
        // Выравнивание по нижнему краю переносило этот рост НАВЕРХ, и заголовок
        // садился на 2–4 точки иначе. Замер до правки: 78 · 74 · 76 · 74 у
        // четырёх страниц одного ресурса; в переходе это и есть тот прыжок.
        //
        // Отступы снизу тоже одни, независимо от линии: линия либо рисуется,
        // либо нет, но МЕСТО под неё зарезервировано всегда — иначе карточка
        // (где её роль исполняет полоса вкладок) поднимала бы своё содержимое
        // относительно списка ровно на её высоту.
        height: HEAD_CONTENT_HEIGHT,
        boxSizing: "content-box",
        flexShrink: 0,
        paddingBottom: HEAD_PADDING_BOTTOM,
        marginBottom: 8,
        borderBottom: divider ? "1px solid var(--kc-border)" : "1px solid transparent",
      }}
    >
      {/* Колонка заголовка ОБЯЗАНА сжиматься: `minWidth: 0` снимает у flex-детей
          неявный минимум по содержимому, но без `flex` колонка не отдаёт ширину
          вовсе — длинное имя ресурса вылезало за свою зону и наезжало на
          соседей. Обрезка многоточием ниже работает только внутри ограниченной
          ширины, поэтому оба свойства нужны вместе, а не по отдельности. */}
      <div style={{ flex: "1 1 auto", minWidth: 0, overflow: "hidden" }}>
        <Typography.Title
          level={3}
          ellipsis={{ tooltip: undefined }}
          style={{
            margin: 0,
            fontSize: `clamp(24px, 2vw, ${HEAD_TITLE_SIZE_MAX}px)`,
            fontWeight: 590,
            // Высота строки вмещает шрифт ЦЕЛИКОМ — см. разбор у
            // `HEAD_CONTENT_HEIGHT`. Меньший множитель обрезает не текст, а
            // строку под ним: буква выходит за свою строку и наползает на то,
            // что стоит ниже, — на полосу вкладок.
            lineHeight: HEAD_TITLE_LINE_HEIGHT,
            letterSpacing: "-0.035em",
            color: "var(--kc-text)",
          }}
        >
          {title}
        </Typography.Title>
      </div>
      {badges !== undefined && (
        <div style={{ display: "flex", gap: 8, alignItems: "center", flexShrink: 0, marginRight: "auto" }}>
          {badges}
        </div>
      )}
      {right !== undefined && (
        // Класс задаёт ОДНУ высоту и один радиус всем ручкам, попавшим в шапку, —
        // см. его объявление в общем листе.
        //
        // Он стоит ЗДЕСЬ, а не у вызывающего, потому что вызывающих несколько, а
        // ряд ручек — один и тот же предмет. Пока класс вешал только лист
        // ресурсов, ряд на вкладке карточки собирался из трёх слотов и общего
        // правила не получал: те же три ручки давали 38/36/36 против 32/32/32 на
        // списке. Порядок при этом был верен — разъезжалась только геометрия,
        // поэтому в обзоре диффа расхождение не видно.
        <div
          className="kc-list-tools"
          style={{ display: "flex", gap: 8, alignItems: "center", flexWrap: "nowrap", flex: "0 0 auto" }}
        >
          {right}
        </div>
      )}
    </div>
  );
}
