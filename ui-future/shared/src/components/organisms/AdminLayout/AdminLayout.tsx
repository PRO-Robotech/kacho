// Каркас раздела администрирования — МЕСТО ДЛЯ СТРАНИЦЫ, и только.
//
// Прежде он рисовал собственный заголовок «Администрирование» и полосу
// горизонтальных вкладок с перечнем частей раздела. Обе вещи сняты решением
// владельца о сведении раздела к общей логике: перечень частей приходит от
// самого модуля и показывается колонкой слева, как у всех прочих разделов, а
// заголовок называет предмет открытой страницы, а не имя раздела.
//
// Перечень `SECTIONS`, живший здесь, снят вместе со своим потребителем: он был
// ВТОРЫМ объявлением того же, что объявляет `system/src/navigation.ts`, и два
// места об одном предмете разошлись бы при первом же новом разделе. Правки
// перечня идут туда.

import { Outlet } from "react-router";

export function AdminLayout() {
  // ЭТОТ КАРКАС БОЛЬШЕ НЕ РИСУЕТ НИ ЗАГОЛОВКА, НИ ВКЛАДОК.
  //
  // Раздел администрирования подавал свои части ТРЕТЬЕЙ конструкцией навигации:
  // рейл слева, затем — теперь — колонка разделов, и поверх них ещё полоса
  // горизонтальных вкладок «Регионы / Зоны / …», перечислявшая ровно то же
  // самое. Вместе с ней шёл и второй заголовок: «Администрирование» над
  // «Регионами», то есть имя раздела и имя страницы одновременно, тогда как у
  // прочих разделов заголовок один и называет предмет.
  //
  // Колонка разделов приходит к каркасу от самого модуля (`system/navigation`) —
  // она и есть перечень частей. Здесь остаётся только место для страницы.
  //
  // Права ЗДЕСЬ БОЛЬШЕ НЕ ЧИТАЮТСЯ и это не потеря: перечень колонки и прежде
  // строился не отсюда, а страницу, на которую нет прав, закрывает сама
  // страница — тем же отказом, что и при заходе по прямой ссылке. Проверка,
  // прятавшая пункт, но не закрывавшая адрес, защитой не была.
  return <Outlet />;
}

export default AdminLayout;
