// Край закреплённой колонки — ЛИНИЯ, а не тень.
//
// Что рисовало полосу. Широкая таблица прокручивается вбок, поэтому колонка
// идентичности закреплена слева, а столбец действий справа. Закреплённой клетке
// antd рисует псевдоэлемент шириной 30 точек с внутренней тенью
// (`inset ∓10px 0 8px -8px`), цвет которой берётся из общего токена `colorSplit`
// — на тёмной поверхности это тёмный размытый мазок вдоль всего столбца. Со
// стороны он читается не как «здесь содержимое уезжает под закреплённый край»,
// а как артефакт отрисовки, и вдобавок ложится поверх соседней колонки: её
// заголовок выглядит обрезанным на полуслове.
//
// Что вместо. Тень снимается (цвет — прозрачный), а граница закрепления
// называется тем же, чем в этой консоли называется всякая граница, — линией в
// один пиксель цветом `--kc-border`. Тогда край честен: видно, что за ним
// содержимое продолжается, и видно, где именно проходит стык.
//
// Почему тема объявлена здесь, а не в `lib/theme.ts`. Там живёт вид таблицы —
// шапка, линии, наведение, кегль; всё это верно для любой таблицы независимо от
// того, закреплён у неё край или нет. Тень же существует РОВНО из-за решения
// закреплять края, а решение это принимает `ResourceTable`. Токен уехал бы в
// тему — и следующий, кто снимет закрепление, оставил бы за собой снятую тень
// без предмета.
//
// Цена названа: `colorSplit` у таблицы кормит ещё и подложку полосы прокрутки
// (`tableScrollBg`). Прозрачная подложка полосу не прячет — ползунок красится
// отдельным токеном (`stickyScrollBarBg`) и остаётся видимым; именно он и
// сообщает, что таблица прокручивается вбок.

import type { ThemeConfig } from "antd";
import type { CSSProperties } from "react";

export const TABLE_EDGE_THEME: ThemeConfig = {
  components: { Table: { colorSplit: "transparent" } },
};

/**
 * Линия на стыке закрепления. `start` — правый край левого закрепления,
 * `end` — левый край правого: линия всегда стоит со стороны прокручиваемого
 * содержимого, потому что она сообщает именно про него.
 */
export function pinnedEdgeStyle(side: "start" | "end"): CSSProperties {
  return side === "start"
    ? { borderInlineEnd: "1px solid var(--kc-border)" }
    : { borderInlineStart: "1px solid var(--kc-border)" };
}
