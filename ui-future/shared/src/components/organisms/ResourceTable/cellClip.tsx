// Клетка списка — ОДНА строка. Здесь это решено один раз для всех таблиц
// консоли, потому что нарушается оно одинаково и последствия у него одни.
//
// Список читают сверху вниз, и ровный шаг строк — то, по чему взгляд идёт, не
// спотыкаясь. Стоит одной ячейке перенести значение, и своя высота появляется у
// КАЖДОЙ строки, где текст длиннее соседнего: список идёт лесенкой, а её ритм
// не сообщает о данных ничего.
//
// Отсюда два запрета и одно обещание:
//
//   * значение НЕ переносится. Идентификатор `rtb…jdm` не рвётся посреди себя
//     на «rtb…jd» и «m» — разорванный идентификатор нельзя ни прочитать, ни
//     сверить глазом с соседним, а он у нас единственная внешне-адресуемая
//     координата ресурса, и его показывают именно затем, чтобы сверять;
//   * клетка НЕ выше одной строки — даже когда её содержимое нарисовано
//     столбиком (набор статических маршрутов, многострочное сообщение об
//     ошибке). Иначе одна такая клетка задаёт высоту всей строке;
//   * что не поместилось — договаривается подсказкой при наведении, а не
//     пропадает молча.
//
// Ширина. Клетка не растягивает свой столбец дальше предела: без предела одно
// длинное описание делает столбец в две тысячи точек, и таблица уезжает вбок
// вся целиком. С пределом длинное описание обрезается, а идентификатор (около
// 175 точек вместе со значком копирования) до предела не достаёт вовсе —
// поэтому обрезка идентификатора остаётся редким случаем, а не нормой.

import type { CSSProperties, ReactNode } from "react";

/**
 * Предел ширины клетки. 320 — примерно 44 знака основного ряда: столько нужно,
 * чтобы имя, адрес сети, отметка времени и пара меток читались целиком, и мало
 * настолько, чтобы восемь колонок помещались в обычное окно без прокрутки.
 */
export const CELL_MAX_WIDTH = 320;

/** Высота строки текста в клетке — одна строка, из неё считается всё остальное. */
export const CELL_LINE_HEIGHT = 20;

/**
 * Продых вокруг клетки. За строку выходят две вещи, и обе — не украшение:
 * заливка копирующей кнопки идентификатора (2 точки по вертикали, 5 влево — её
 * фон обязан дышать вокруг значения, а левый край значения при этом стоять на
 * линии колонки) и ОРЕОЛ ФОКУСА в 3 точки (`--kc-focus-ring`), по которому
 * работающий с клавиатуры видит, где он находится. Обрезка без этих полей
 * съела бы и то и другое — то есть чинила бы перенос ценой другого дефекта,
 * причём второй заметен ровно тем, кто мышью не пользуется.
 *
 * Вертикальный продых объявлен НАРУЖУ, чтобы проба читала его, а не своё число:
 * второе объявление того же значения разошлось бы с первым молча.
 */
export const CELL_BLEED = 3;
const CELL_BLEED_INLINE = 5;

/**
 * Класс-крючок для подсказки при наведении. Правила у него нет и не должно
 * быть: он не оформляет, он позволяет обработчику поверхности найти клетку,
 * над которой стоит указатель, не подписываясь на каждую из них по отдельности.
 */
export const CELL_CLIP_CLASS = "kc-cell-clip";

/** Отступы клетки внутри ячейки таблицы — из них считается предел ширины. */
export const CELL_INSET = 16;

export function cellClipStyle(maxWidth: number = CELL_MAX_WIDTH): CSSProperties {
  return {
    display: "block",
    boxSizing: "border-box",
    maxWidth,
    // Одна строка: перенос запрещён, лишнее уходит в многоточие. `maxHeight`
    // держит высоту и у содержимого, нарисованного столбиком: там многоточия не
    // будет (оно про строчный поток), но лишние строки не поднимут строку списка.
    whiteSpace: "nowrap",
    overflow: "hidden",
    textOverflow: "ellipsis",
    lineHeight: `${CELL_LINE_HEIGHT}px`,
    maxHeight: CELL_LINE_HEIGHT + CELL_BLEED * 2,
    paddingBlock: CELL_BLEED,
    marginBlock: -CELL_BLEED,
    paddingInlineStart: CELL_BLEED_INLINE,
    marginInlineStart: -CELL_BLEED_INLINE,
  };
}

/** Клетка таблицы: одна строка, предел ширины, многоточие. */
export function CellClip({ maxWidth, children }: { maxWidth?: number; children: ReactNode }) {
  return (
    <div className={CELL_CLIP_CLASS} style={cellClipStyle(maxWidth)}>
      {children}
    </div>
  );
}

/**
 * Подсказка ставится ЛЕНИВО — на наведение, а не при отрисовке.
 *
 * Узнать, обрезано ли значение, можно только измерив элемент, а измерение
 * заставляет браузер посчитать раскладку. Восемь колонок на тысяче строк — это
 * восемь тысяч измерений ради подсказки, которую спросят у одной клетки:
 * стоимость, умноженная на число строк, в диффе не видна, а на живом списке
 * видна сразу.
 *
 * Обработчик вешается ОДИН на поверхность таблицы и находит клетку по крючку —
 * подписка на каждую клетку стоила бы столько же, сколько измерение.
 */
export function showTitleWhenClipped(event: { target: EventTarget | null }): void {
  const from = event.target as HTMLElement | null;
  const cell = from?.closest?.(`.${CELL_CLIP_CLASS}`) as HTMLElement | null;
  if (!cell) return;
  // Единица допуска — против дробных величин раскладки: без неё клетка,
  // совпадающая с колонкой до сотых, объявлялась бы обрезанной.
  const clipped = cell.scrollWidth > cell.clientWidth + 1 || cell.scrollHeight > cell.clientHeight + 1;
  // `innerText` сохраняет переносы между строками столбика (маршрут на строку),
  // `textContent` склеил бы их в одно слово. В jsdom `innerText` не реализован,
  // поэтому он же и запасной путь — и проба видит текст, а не пустоту.
  const full = clipped ? (cell.innerText || cell.textContent || "").trim() : "";
  if (full) {
    if (cell.title !== full) cell.title = full;
  } else if (cell.title) {
    cell.removeAttribute("title");
  }
}
