import type { FC } from "react";
import { Button } from "antd";
import { StatePanel } from "@shared/components/molecules/StatePanel";
import { ModuleUnavailableArt } from "./ModuleUnavailableArt";
import { goToServices } from "./browser-navigation";

export interface ModuleUnavailablePanelProps {
  /** Имя раздела так, как его видит пользователь в меню. Экран обязан называть
   *  раздел ПО ИМЕНИ: «что-то пошло не так» не говорит, ЧТО именно недоступно. */
  moduleLabel: string;
  /**
   * Техническая причина отказа. На экран НЕ выводится: «remoteEntry.js: Failed
   * to fetch» ничего не сообщает тому, кто это читает, и пугает. Причина живёт
   * в журнале браузера (её пишет граница) и здесь — атрибутом разметки, чтобы
   * отладка стенда не требовала снимать экран с пользователя.
   */
  detail?: string;
  /**
   * Повторная попытка. Кнопка появляется ТОЛЬКО когда попытка есть: предлагать
   * «Повторить» там, где повторять нечего (страница раздела ещё не выставлена
   * наружу), значит обещать действие, которое ничего не изменит.
   */
  onRetry?: () => void;
  /**
   * Уход к списку сервисов. По умолчанию — обычный переход браузера: панель
   * рисуется и там, где маршрутизатора нет вовсе (корневая граница каркаса
   * оборачивает BrowserRouter снаружи), поэтому `useNavigate` здесь упал бы.
   * Вызывающий с маршрутизатором передаёт свой переход и экономит перезагрузку.
   */
  onGoHome?: () => void;
}




/**
 * Экран «раздел недоступен» — единственная форма отказа модуля в консоли.
 *
 * Оформление — ИНЛАЙНОВОЕ, а не классами общего листа стилей. Панель рисуется и
 * в каркасе, и внутри модуля, поднятого отдельно от него, — а свой лист стилей
 * каркаса такой модуль не подключает. Класс без листа дал бы неоформленный
 * экран ровно там, где что-то и так сломалось. Цвета при этом остаются
 * токенами, поэтому тема ими управляет как обычно.
 *
 * Роль `alert` и `data-testid` живут на собственной обёртке: заменитель antd в
 * пробах пропускает в DOM только `data-*`/`aria-*`/`id`/`title`, поэтому
 * утверждение, повешенное на внутренний виджет, было бы верно лишь в одном из
 * двух харнессов (каркас держит настоящий antd, остальные — заменитель).
 */
export const ModuleUnavailablePanel: FC<ModuleUnavailablePanelProps> = ({
  moduleLabel,
  detail,
  onRetry,
  onGoHome,
}) => (
  // Оболочка ОБЩАЯ с пустым состоянием списка (`StatePanel`): предмет один —
  // продукт объясняет, почему смотреть не на что, и предлагает следующий шаг.
  // Держать два одинаковых экрана двумя вёрстками значило заводить расхождение
  // заранее: они разъезжались бы по кеглю и отступам при первой же правке.
  <StatePanel
      role="alert"
      data-testid="module-unavailable"
      // Признак и опознавательные атрибуты — на ОДНОМ узле: проба находит
      // элемент по первому и читает вторые, и разводить их по разным узлам
      // значит рвать это утверждение пополам.
      data={{ "data-module-label": moduleLabel, "data-detail": detail }}
      art={<ModuleUnavailableArt />}
      title={title(moduleLabel)}
      description={
        // Про СОСЕДНИЕ разделы не утверждаем ничего (решение владельца).
        // Отсюда, изнутри отказавшего раздела, о них ничего не известно: причина
        // могла задеть и их. Обещание «остальное работает как обычно» проверить
        // нечем, а нарушенное читается хуже молчания — оно уже один раз обмануло.
        "Ведутся технические работы. Это временно — попробуйте открыть раздел снова через несколько минут."
      }
      actions={
        <>
          {onRetry ? (
            <Button type="primary" onClick={onRetry}>
              Повторить
            </Button>
          ) : null}
          <Button onClick={onGoHome ?? goToServices}>Все сервисы</Button>
        </>
      }
  />
);

/**
 * Заголовок. Конструкция «Раздел «X»» выбрана не для красоты: имена разделов —
 * это и «Virtual Private Cloud», и «Консоль Kachō», и род у них разный, поэтому
 * согласовать «недоступен» с самим именем нельзя. Слово «раздел» берёт род на
 * себя, и одна форма работает для всех.
 *
 * Имени нет — значит канон имён такого раздела не знает, и назвать его нечем:
 * сегмент адреса («quotas») именем не является. Безымянная форма честнее
 * выдуманной.
 */
function title(moduleLabel: string): string {
  return moduleLabel ? `Раздел «${moduleLabel}» временно недоступен` : "Раздел временно недоступен";
}
