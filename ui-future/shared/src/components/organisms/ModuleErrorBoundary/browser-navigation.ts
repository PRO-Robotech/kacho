/**
 * Полный переход браузера — ОДНО место на оба случая экрана отказа.
 *
 * Вынесено из компонентов не ради удобства проб, а потому что это одно решение,
 * принятое дважды: и повтор там, где попытку некому пересоздать, и уход к
 * списку сервисов обязаны поднять приложение заново целиком. Отказ мог случиться
 * в любом месте уже смонтированного дерева, поэтому переход внутри приложения
 * не гарантирует выхода из него — а свежая загрузка гарантирует.
 *
 * Следствие, названное честно: `window.location` в jsdom не подменяется ни
 * `Object.defineProperty` («Cannot redefine property»), ни `jest.spyOn`
 * («Cannot assign to read only property»), поэтому проба перехватывает ИМЕННО
 * этот модуль. Свойство продукта от этого не меняется: в браузере переход
 * остаётся настоящим, и подменять его нечем.
 */

/** Адрес списка сервисов — он же точка входа консоли. */
export const SERVICES_PATH = "/dashboard";

export function reloadPage(): void {
  window.location.reload();
}

export function goToServices(): void {
  window.location.assign(SERVICES_PATH);
}
