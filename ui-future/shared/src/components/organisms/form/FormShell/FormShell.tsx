// src/components/form/FormShell.tsx
// FormShell — единый презентабельный «панель»-контейнер Create/Edit форм:
//   • шапка-band: градиентная иконка-плитка ресурса + caps-verb (Создание/
//     Редактирование) + заголовок (singular) + подзаголовок — по образцу
//     DeleteDialog и welcome-страницы «первый ресурс»;
//   • подложка-карточка (elevated + border + radius + shadow) поверх тёмного
//     фона (modal body / page = --kc-page), на которой лежит тело формы;
//   • единая ширина FORM_WIDTH для ВСЕХ ресурсов (modal == page == custom).
// Рендерится и generic-телом (ResourceFormBody), и кастом-формами
// (InlineSubnet/SG/NIC/AddressPool) → визуальный паритет всех форм.
// Theme-aware (--kc-*): чисто в DARK и LIGHT.
import { createContext, useContext, type ReactNode } from "react";
import { ConfigProvider } from "antd";
import { useDetailHeaderIcon } from "@shared/components/molecules/PanelHeader";
// ПРЯМО ИЗ ФАЙЛА, а не через баррель `DetailShell/index.ts`.
//
// Баррель реэкспортирует и сам `DetailShell`, а тот тянет `react-router`, —
// пакет с ESM-сборкой, который jest в этом дереве не трансформирует
// (`transformIgnorePatterns` оставлен по умолчанию). Через баррель эта
// зависимость приезжала к КАЖДОМУ, кто импортирует форму: цепочка
// `resource-registry → RoutesEditor → RefSelect → InlineResourceCreateForm →
// ResourceFormBody → FormShell → DetailShell → react-router` кладёт суиту
// целиком — не «падает проба», а «suite failed to run», то есть вердикта нет
// ни у одной пробы файла. Замер в момент починки: 153 суиты из 219 не
// исполнялись вовсе.
//
// Шапка страницы про маршрутизацию не знает и знать не должна — импорт из
// файла оставляет её зависимости её собственными.
import { PageHead, PAGE_PADDING } from "@shared/components/organisms/DetailShell/PageHead";

/** Единый стандарт ширины формы (modal width / page maxWidth / card maxWidth). */
export const FORM_WIDTH = 820;

/**
 * Оформление подписи поля — ОДНО на все формы консоли.
 *
 * Подпись приглушена намеренно: в паре «имя слева, ввод справа» смысл несёт
 * ввод, а имя лишь называет строку. Подпись того же тона и кегля, что и
 * значение, заставляет глаз читать колонку имён как содержимое.
 *
 * Стоит здесь, а не у каждой формы: через `FormShell` проходит КАЖДАЯ форма
 * консоли — и generic-тело, и рукописные (подсеть, группа безопасности,
 * интерфейс, пул адресов), — поэтому одно объявление накрывает их все и не
 * может разойтись по копиям. Цвет — токеном, чтобы светлая тема получила ту же
 * форму, а не свой набор цветов.
 */
const FORM_LABEL_THEME = {
  components: {
    Form: {
      labelColor: "var(--kc-text-secondary)",
      labelFontSize: 12,
      labelRequiredMarkColor: "var(--kc-danger)",
      itemMarginBottom: 18,
    },
  },
} as const;

// FormBareContext — форма внутри модалки: сама модалка уже даёт поверхность и
// рамку, поэтому FormShell рисует шапку (иконка+действие+тип) + поля БЕЗ своей
// kc-surface-карточки (иначе двойной лайаут: карточка внутри карточки-модалки).
const FormBareContext = createContext(false);

/** Оборачивает форму в модалке — FormShell рендерит шапку без kc-surface-подложки. */
export function FormBareProvider({ children }: { children: ReactNode }) {
  return <FormBareContext.Provider value={true}>{children}</FormBareContext.Provider>;
}

interface Props {
  /**
   * Ресурс, форму которого рисуем.
   *
   * В отрисовке НЕ участвует — и это не повод его снять. Значение читает гейт
   * дерева `required-mark-contract-parity`: по нему он находит контракт ресурса
   * и сверяет, не помечено ли «Имя» обязательным вопреки контракту владельца.
   * Другого способа связать форму с ресурсом у него нет — формы зовут `FormShell`
   * из разных мест и под разными именами.
   *
   * Снятие этого пропа гейт не роняет: он просто перестаёт находить формы, и
   * «рассужено 0 · находок 0» читается как «всё чисто». Проверено опытом —
   * снял, и перепись показала ноль рассуженных при 325 прочитанных формах.
   */
  specId: string;
  mode: "create" | "edit";
  singular: string;
  /** Предмет действия в ВИНИТЕЛЬНОМ падеже — «Создать подсеть», «Изменить
   *  таблицу маршрутов». Берётся из объявления ресурса (`spec.accusative`), а не
   *  выводится из `singular`: русское склонение по окончанию — правило с
   *  исключениями (одушевлённость: «пользователя», а не «пользователь»), и
   *  вывод по хвосту слова ошибается молча.
   *
   *  Винительный, а не родительный, по двум причинам: он объявлен у ВСЕХ 30
   *  ресурсов реестра (родительный — у 24), и он даёт ту же форму, что подпись
   *  действия в остальном продукте, — заголовок и кнопка говорят одинаково.
   *
   *  Не задан — заголовком остаётся одно действие. Это ХУЖЕ (страница не
   *  говорит, что именно создаётся), но честнее выдуманной формы. */
  accusative?: string;
  /** Override заголовка (по умолчанию — singular ресурса). */
  title?: string;
  /** Override подзаголовка (по умолчанию — generic-подсказка по mode). */
  subtitle?: string;
  children: React.ReactNode;
}

export function FormShell({ specId, mode, singular, accusative, title, subtitle, children }: Props) {
  void specId; // читается гейтом дерева по исходному тексту — см. Props.specId
  // ─────────────────────────────────────────────────────────────────────────
  // ШАПКА ФОРМЫ: ЧТО ДЕЛАЕМ, А НЕ ГДЕ НАХОДИМСЯ
  //
  // Прежде здесь стояли плитка с иконкой ресурса и его название — ровно то, что
  // уже сказано слева: второй уровень сайдбара называет и подсвечивает раздел
  // («Облачные сети»), а хлебные крошки повторяют это же. Форма говорила то же
  // самое в третий раз и вдобавок той же иконкой.
  //
  // Осталось то, чего не говорит НИКТО, — совершаемое действие. Надзаголовок
  // называет ТИП (родитель), заголовок — САМО ДЕЙСТВИЕ над ним; это тот же
  // принцип, по которому устроены шапки списка и карточки, поэтому переход
  // «список → создание» не читается как переход в другой продукт.
  const verb = mode === "create" ? "Создать" : "Изменить";
  // ДЕЙСТВИЕ И ПРЕДМЕТ — В ОДНОЙ СТРОКЕ: «Создание подсети», «Изменение сети».
  //
  // Прежде они стояли двумя строками — действие заголовком, предмет
  // надзаголовком. Надзаголовки сняты по всему продукту решением владельца, и
  // оставить одно действие значило бы получить страницу с заголовком
  // «Изменение», не говорящую, чего именно.
  //
  // Предмет берётся в ВИНИТЕЛЬНОМ падеже из объявления ресурса — «Создать
  // таблицу маршрутов», а не «Создать таблица маршрутов». Своего падежа здесь
  // не собираем: собранный по месту разошёлся бы со следующим местом молча.
  //
  // Здесь стояло «в родительном» — падеж, которого код не читает (читается
  // `accusative`, и `Props` объявляет винительный). Два места об одном предмете,
  // из которых верно одно.
  // Предмет берём объявленным падежом; `singular` — только чтобы не молчать
  // вовсе, когда падеж у ресурса не объявлен (он в именительном и согласуется
  // неверно, поэтому идёт ПОСЛЕ падежа, а не вместо него).
  const subject = accusative?.toLowerCase() ?? singular.toLowerCase();
  const heading = title ?? `${verb} ${subject}`;

  // Внутри detail-страницы (есть DetailHeaderContext) форма рендерится edit-/
  // child-create-панелью в main-pane, который УЖЕ является поверхностью. Своя
  // kc-surface-карточка тут не нужна — она сдвигала бы шапку формы относительно
  // шапки таба (padding карточки) → «прыжок» иконки/названия/действия при
  // переключении таб↔форма. Embedded → без карточки, шапка ровно как у таба.
  const embedded = useDetailHeaderIcon() !== undefined;
  const bare = useContext(FormBareContext);

  // Иконки нет намеренно: она — признак ИДЕНТИЧНОСТИ ресурса, её место рядом с
  // разделом в навигации, а не над формой, где повторяла бы соседнюю колонку.
  // Шапка формы — ТА ЖЕ, что у списка и у карточки ресурса (`PageHead`):
  // надзаголовок-родитель телеметрийного цвета с чёрточкой, под ним крупный
  // заголовок. Пока у формы была своя (`PanelHeader` с другим кеглем и другой
  // конструкцией), переход «карточка → правка» читался как переход в другое
  // место продукта: менялся не предмет, а оформление вокруг него.
  const header = <PageHead title={heading} right={subtitle} />;

  if (embedded) {
    // Внутри detail-страницы шапку (иконка+действие+тип) показывает ЗОНА 2
    // (`DetailShell.headerTitle`) — здесь её НЕ дублируем, только поля.
    return (
      <ConfigProvider theme={FORM_LABEL_THEME}>
        <div style={{ maxWidth: FORM_WIDTH, width: "100%", margin: 0 }}>{children}</div>
      </ConfigProvider>
    );
  }

  if (bare) {
    // Внутри модалки: шапка (иконка+действие+тип) + поля, БЕЗ kc-surface-карточки
    // (поверхность — сама модалка). Единый лайаут, без вложенных карточек.
    return (
      <ConfigProvider theme={FORM_LABEL_THEME}>
        <div style={{ width: "100%", margin: 0 }}>
          {header}
          {children}
        </div>
      </ConfigProvider>
    );
  }

  return (
    // Отдельная страница создания или правки.
    //
    // ШАПКА ЖИВЁТ НА ШИРИНЕ СТРАНИЦЫ, А НЕ НА ШИРИНЕ ПОЛЕЙ. Прежде вся форма,
    // вместе с заголовком, лежала в колонке шириной `FORM_WIDTH`, а поля
    // поверхности были свои (20 против 20/24 у списка и карточки). Из-за обоих
    // расхождений заголовок стоял на другой вертикали, чем на странице, откуда
    // на форму пришли, — и в переходе «список → создание» текст дёргался.
    //
    // Ширину ограничивают ПОЛЯ: длинная строка ввода не читается, а заголовок
    // от ширины не страдает.
    <ConfigProvider theme={FORM_LABEL_THEME}>
      <div className="kc-surface" style={{ padding: PAGE_PADDING }}>
        {header}
        <div style={{ maxWidth: FORM_WIDTH, width: "100%", margin: 0 }}>{children}</div>
      </div>
    </ConfigProvider>
  );
}
