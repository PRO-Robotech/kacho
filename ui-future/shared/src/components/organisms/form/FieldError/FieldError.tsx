// Отказ стоит У ПОЛЯ, а не только сверху.
//
// ПОЧЕМУ НЕ ВСПЛЫВАЮЩЕЕ СООБЩЕНИЕ. Всплывашка появляется в углу, живёт секунды и
// исчезает; чтобы связать её с полем, читателю надо помнить, что он нажал. На
// длинной форме она вдобавок оказывается за пределами взгляда, направленного на
// ввод. Отказ, названный у поля, читается там же, где его исправляют.
//
// Числа полей здесь намеренно нет: оно стареет при первой же правке схемы, а
// довод от него не зависит.
//
// ПОЧЕМУ СВОЯ РАЗМЕТКА, А НЕ `help` У `Form.Item`. Два довода, и оба про то,
// чтобы утверждение было проверяемо. Во-первых, `help` рисует библиотека, и
// проба о нём утверждала бы о ЗАМЕНИТЕЛЕ библиотеки в харнессе, а не о продукте
// (заменитель `Form.Item` подписи рисует, а `help` не рисует вовсе). Во-вторых,
// это же сообщение показывают формы, у которых `Form.Item` вообще нет, — тогда
// у одного предмета завелись бы два вида.
//
// Цвет — токеном: у отказа нет своей палитры, и светлая тема обязана получить ту
// же форму, а не другой продукт.
import type { CSSProperties } from "react";

const STYLE: CSSProperties = {
  marginTop: 6,
  fontSize: 12,
  lineHeight: 1.35,
  color: "var(--kc-danger)",
  // Сообщение бывает длиннее строки ввода — переносим по словам, а не режем.
  overflowWrap: "anywhere",
};

interface Props {
  /**
   * Идентификатор сообщения. Ввод ссылается на него через `aria-describedby`,
   * поэтому читающий с экрана слышит причину отказа вместе с самим полем, а не
   * отдельной репликой неизвестно о чём.
   */
  id?: string;
  message?: string;
}

export function FieldError({ id, message }: Props) {
  if (!message) return null;
  return (
    <div id={id} role="alert" style={STYLE}>
      {message}
    </div>
  );
}

/** Идентификатор сообщения выводится из идентификатора поля — одним правилом на все формы. */
export function fieldErrorId(fieldId: string): string {
  return `${fieldId}-error`;
}
