// Геометрия формы — ОДНА на все формы консоли: имя поля слева, ввод справа.
//
// Правило продукта (`.claude/rules/ui.md`, правило 1) требует от тела формы
// пары «подпись в левой колонке шириной 200, ввод в правой». Требование
// исполнялось ВОСЕМЬЮ дословными копиями одного набора свойств — по одной в
// общем теле формы и в каждой рукописной форме (подсеть создать/править, группа
// безопасности, интерфейс создать/править, пул адресов создать/править).
//
// Восемь копий одного числа расходятся молча: расхождение видно только тогда,
// когда две формы стоят рядом на одном экране, то есть почти никогда. Это тот
// же довод, по которому геометрия табличного редактора собрана в одном файле
// (`editor-surface.ts`), а не выписана у каждого редактора.
//
// Ширина колонки подписи объявлена ЧИСЛОМ, а не строкой: её читает не только
// форма — на неё равняется отступ подвала и всё, что обязано встать по краю
// поля. Строка «200px» в семи местах уже означала бы семь мест правки.
import { Form } from "antd";
import type { ReactNode } from "react";

/** Ширина колонки с именем поля. Одна на все формы — иначе подписи «прыгают». */
export const FORM_LABEL_WIDTH = 200;

interface Props {
  children: ReactNode;
}

export function FormGrid({ children }: Props) {
  return (
    <Form
      layout="horizontal"
      labelCol={{ flex: `${FORM_LABEL_WIDTH}px` }}
      wrapperCol={{ flex: "1 1 0" }}
      labelAlign="left"
      colon={false}
      size="middle"
    >
      {children}
    </Form>
  );
}
