/** Разделитель строк — линия, а не заливка (полосатости в консоли нет).
 *
 *  Линия РАЗДЕЛЯЕТ, а значит первой строке не нужна: над ней уже стоит линия
 *  шапки секции. Две линии вплотную дают тёмную полосу в две точки, и на глаз
 *  это читается как щель между шапкой и таблицей — при том что зазора нет
 *  вовсе (замер: между низом шапки и верхом тела 0 точек).
 *
 *  Стиль первой строки берётся `editorFirstRowStyle` — см. ниже. */
export const editorRowStyle: CSSProperties = {
  height: EDITOR_ROW_HEIGHT,
  borderTop: "1px solid var(--kc-border)",
};

/** Первая строка тела: та же геометрия, но БЕЗ верхней линии — её роль исполняет
 *  нижняя граница шапки секции. */
export const editorFirstRowStyle: CSSProperties = { ...editorRowStyle, borderTop: "none" };

/**
 * Пометка НЕЗАПОЛНЕННОГО поля — НА САМОМ ПОЛЕ (решение владельца, канон §8).
 *
 * Прежде нехватка называлась только сводкой под таблицей («Строка 1: не указан
 * префикс назначения»): оператор пересчитывал строки глазами, а сообщение не
 * показывало, КУДА смотреть. Здесь место ошибки и место исправления совпадают.
 *
 * Объявлена ЗДЕСЬ, а не у редактора маршрутов, откуда она пришла, по той же
 * причине, по которой здесь лежат высота строки и ширина колонки действий:
 * пометка нужна каждому набору значений, который правят по одному, и вторая её
 * копия разойдётся с первой молча — увидеть расхождение можно только поставив
 * два редактора рядом на одном экране, то есть почти никогда.
 *
 * Поле-ячейка своих полей не имеет (это «невидимый» ввод внутри таблицы), и
 * рамка вплотную к тексту читается как обрезка. Отступ уходит в отрицательное
 * поле, чтобы левый край значения остался на линии столбца.
 */
