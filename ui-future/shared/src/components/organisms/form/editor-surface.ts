/**
 * Тело секции ВНУТРИ общей поверхности — без своей рамки и своего радиуса.
 *
 * Секция «шапка + таблица» обязана быть ОДНИМ блоком. Пока у шапки была своя
 * рамка, а у тела своя, они стыковались двумя линиями и двумя радиусами: шапка
 * читалась приделанной сверху, а не частью таблицы, и на стыке шла двойная
 * граница. Рамку теперь держит внешняя поверхность (`DetailSurface`), тело —
 * только заливку и обрезку углов по ней.
 */
