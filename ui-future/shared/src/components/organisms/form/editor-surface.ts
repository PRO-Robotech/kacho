// Геометрия табличного редактора — ОДНА на все наборы значений консоли.
//
// Образец — секция CIDR эталона: список значений, строка добавления снизу,
// надпись на месте пустого набора. Тем же видом рисуются метки, статические
// маршруты, правила группы безопасности и блоки CIDR: это один предмет —
// «набор значений, который правят по одному», — и рисовать его по-разному
// значило бы называть один предмет несколькими именами (правило 3 канона
// консоли).
//
// Числа собраны здесь, а не выписаны у каждого редактора, по той же причине:
// пять копий одной высоты строки расходятся молча, и расхождение видно только
// рядом на одном экране — то есть почти никогда.
//
// Цвет берётся ТОЛЬКО токенами (`--kc-*`): у редактора нет своей палитры, и
// светлая тема обязана получить ту же форму, а не другой продукт.
import type { CSSProperties } from "react";

/** Моноширинный ряд: адреса, префиксы, идентификаторы. */
export const MONO_FONT = 'ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, monospace';

/** Высота строки значения. Одна на все редакторы — иначе списки «прыгают». */
export const EDITOR_ROW_HEIGHT = 42;

/** Высота поля ввода и кнопки — разные намеренно: в поле вводят, кнопку жмут. */
export const EDITOR_INPUT_HEIGHT = 38;
export const EDITOR_BUTTON_HEIGHT = 36;

/**
 * Ширина колонки действий. У эталона она 88 — там на строке ДВА действия
 * (копирование и снятие) по 30 px. У наших редакторов действие одно, поэтому
 * колонка ровно под него: 88 оставили бы пустую полосу шириной в кнопку, и
 * значение уехало бы от края влево без причины.
 */
export const EDITOR_ACTIONS_WIDTH = 56;

/** Поверхность редактора: линия и тон, без тени (глубина делается тоном). */
