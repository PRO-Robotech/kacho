// Пояснение к полю формы — то, что оператор ПРОЧТЁТ, а не то, что ему обещано
// значком.
//
// ЧТО ДЕРЖИТСЯ. `Tooltip` получает пояснение пропом `title`, и оно бывает двух
// родов. Строку общий заменитель кладёт в нативный `title`, УЗЕЛ — рисует
// содержимым, и это не прихоть: `String(<узел>)` даёт `[object Object]`, то
// есть ОДИН И ТОТ ЖЕ текст для любого пояснения. Проба, написанная на таком
// заменителе, проходила бы при любом содержании подсказки — и при пустом тоже.
//
// Проходной <div> роняет узел в атрибут и теряет его целиком: значок подсказки
// остаётся на месте, объяснение исчезает. Соседний `FieldLabel.test.tsx` этого
// не ловит и ловить не должен — его предмет в том, ЕСТЬ ли значок, а не в том,
// что за ним написано: на возвращённом в <div> `Tooltip` он остаётся зелёным.
//
// ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Строковая ветвь не утверждается: заменитель отдаёт
// её нативным атрибутом `title`, которого настоящий antd не производит вовсе
// (у него подпись видна при наведении). Утверждение о ней было бы прибито к
// форме дублёра и пережило бы продукт (#588, #418).
//
// Инъекция в обе стороны: `Tooltip: Component` в заменителе — красное на
// узловом пояснении; заменитель на месте — молчание.

import { render, screen } from "@testing-library/react";

import { FieldLabel } from "./FieldLabel";

describe("FieldLabel — пояснение доходит до читателя", () => {
  it("узловое пояснение читается ТЕКСТОМ, а не схлопывается в «[object Object]»", () => {
    render(
      <FieldLabel
        text="CIDR"
        info={
          <span>
            Префикс обязателен: <b>10.0.0.0/24</b>
          </span>
        }
      />,
    );

    expect(screen.getByText(/Префикс обязателен/)).toBeInTheDocument();
    expect(screen.getByText("10.0.0.0/24")).toBeInTheDocument();
    expect(document.body.textContent ?? "").not.toContain("[object Object]");
  });

  it("без пояснения читать нечего — контроль в обратную сторону", () => {
    // Без этой половины утверждение выше зеленело бы на заменителе, рисующем
    // подпись всегда: «пояснение видно» перестало бы отличать поле с
    // пояснением от поля без него.
    render(<FieldLabel text="CIDR" />);

    expect(screen.getByText("CIDR")).toBeInTheDocument();
    expect(screen.queryByText(/Префикс обязателен/)).toBeNull();
    expect(screen.queryByLabelText("field-info")).toBeNull();
  });
});
