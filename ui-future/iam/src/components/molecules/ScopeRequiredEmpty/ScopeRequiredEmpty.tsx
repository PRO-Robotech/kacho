// «Область не выбрана» — ОДНА форма на весь раздел IAM.
//
// Экран объясняет, почему смотреть не на что, и называет следующий шаг, — то же
// самое, что делают пустой список ресурса и «раздел недоступен». Предмет один,
// значит и оболочка одна (`StatePanel`): зоны фиксированной высоты, центровка по
// обеим осям, ширина строки описания от самого длинного текста.
//
// ЧТО ЗДЕСЬ БЫЛО. Шесть разных ответов на один и тот же вопрос в одном модуле:
// `Empty` от antd (список ресурса, лента операций, привязки доступа), голая
// строка вторичным тоном (группы) и `Alert` (права доступа, приглашение). Ни
// один не стоял по центру, у каждого была своя высота и свой кегль, а слова
// расходились: «Выберите Account вверху секции», «Выберите аккаунт», «Выберите
// Account в шапке». Переход между соседними страницами раздела читался как
// переход в другой продукт.
//
// РИСУНКА У ЭТОГО ЭКРАНА НЕТ, и это решение, а не пропуск. Карта рисунков
// (`ResourceEmptyState/art`) намеренно не назначает схему ресурсам IAM: у
// аккаунта нет узнаваемой схемы, и выдуманная сообщала бы неправду. Зона
// рисунка при этом всё равно держит высоту — `StatePanel` резервирует её и
// пустой, поэтому заголовок и описание стоят там же, где у экранов с рисунком.
import { StatePanel } from "@shared/components/molecules/StatePanel";

/** Какая именно область не выбрана. Слово в описании — то же, что на пилюле
 *  выбора в шапке: подменив его переводом, экран отправил бы искать ручку,
 *  которая называется иначе. */
type Scope = "account" | "project";

const SCOPE_TITLE: Record<Scope, string> = {
  account: "Аккаунт не выбран",
  project: "Проект не выбран",
};

const SCOPE_PICKER: Record<Scope, string> = {
  account: "Account",
  project: "Project",
};

interface Props {
  /** Чего нельзя сделать без области — глагольной фразой, продолжающей «чтобы»:
   *  «увидеть привязки доступа», «пригласить пользователя».
   *
   *  Прописан ОДИН способ сказать это, а не «предмет с умолчанием и перекрытие
   *  на случай другого глагола»: два способа сказать одно расходятся при первой
   *  же правке, и половина экранов остаётся со старой формулировкой. */
  purpose: string;
  scope?: Scope;
}

export function ScopeRequiredEmpty({ purpose, scope = "account" }: Props) {
  return (
    <StatePanel
      role="status"
      data-testid="iam-scope-required"
      data={{ "data-scope": scope }}
      title={SCOPE_TITLE[scope]}
      description={`Выберите ${SCOPE_PICKER[scope]} вверху секции, чтобы ${purpose}.`}
    />
  );
}
