// Членство человека В ТЕКУЩЕМ АККАУНТЕ — секция под обзором карточки сотрудника.
//
// ЧТО ЭТА СЕКЦИЯ ОТВЕЧАЕТ. «К какому аккаунту относится этот человек и в каком
// он там положении». До ресурса членства (#1085) ответа не было ни у одного
// чтения — поле сняли с записи человека (#471), потому что назвать им можно
// было только ОДИН аккаунт, а человек состоит в нескольких, — и карточка
// обязана была молчать. Источник появился, молчание кончилось.
//
// ПОЧЕМУ ТЕКУЩИЙ АККАУНТ БЕРЁТСЯ ИЗ ОБЛАСТИ, А НЕ ИЗ КОНТЕКСТА СПИСКА. Список
// пользователей охватывает НЕСКОЛЬКО аккаунтов сразу («люди аккаунтов, где
// состоит вызывающий»), поэтому строка списка аккаунт членства не определяет:
// вывести его оттуда значило бы назвать наугад. Область — единственное место,
// где аккаунт назван решением человека.
//
// ПОЧЕМУ ОДИН ВОПРОС, А НЕ ПЕРЕЧЕНЬ. Карточка сотрудника не вправе раскрывать
// состав аккаунтов человека: это тот же оракул, что и различимый отказ, только
// словом. Здесь он закрыт РАНЬШЕ показа — самой формой запроса: аккаунт стоит в
// пути, вопроса «в каких аккаунтах состоит этот человек» на поверхности нет
// вовсе, и задать его нечем.
//
// ПОЧЕМУ ОТБОР ПО АККАУНТУ ПОВТОРЁН ЗДЕСЬ. Чтение сужено аккаунтом на стороне
// края, и в ответе чужой строке взяться неоткуда. Но «взять первую» держалось
// бы на этом молча: расхождение — своё в кэше, чужое в ответе постороннего
// края, ошибка отбора — назвало бы чужой аккаунт, и вид у него был бы такой же
// уверенный. Отбор по названному аккаунту делает промах невозможным здесь, а не
// маловероятным там.

import { useQuery } from "@tanstack/react-query";
import { iamApi, membershipUserFilter } from "@shared/api/iam";
import { BoolFact } from "@shared/components/atoms/BoolFact";
import { IamRefLink } from "@shared/components/molecules/IamRefLink";
import { DetailSurface, PropertyRows, type PropertyItem } from "@shared/components/organisms/DetailShell";
import { useContext } from "@shared/lib/context-store";

const TITLE = "Членство в аккаунте";

export function AccountMembership({ userId }: { userId: string }) {
  const accountId = useContext((s) => s.account)?.id ?? "";

  const { data } = useQuery({
    queryKey: ["account-membership", accountId, userId],
    queryFn: () => iamApi.listAccountMemberships(accountId, { filter: membershipUserFilter(userId) }),
    // Без аккаунта вопрос не задаётся ВООБЩЕ. Это не оптимизация: запрос без
    // аккаунта пришлось бы адресовать поверхности, отвечающей про все аккаунты
    // человека сразу, — а её карточка чужого человека спрашивать не вправе.
    enabled: !!accountId && !!userId,
    staleTime: 30_000,
    retry: false,
  });

  if (!accountId) {
    // Молчание ОБЪЯСНЯЕТСЯ. Пустое место на карточке читается как «человек не
    // состоит нигде» — утверждение, которого никто не делал и которое обычно
    // неверно. Строка называет причину и следующий шаг, но не рисует ни поля,
    // ни прочерка: источника у них по-прежнему нет.
    return (
      <DetailSurface title={TITLE}>
        <div style={{ padding: "12px 16px", color: "var(--kc-text-tertiary)", fontSize: 12 }}>
          Аккаунт не выбран — членство не показано.
        </div>
      </DetailSurface>
    );
  }

  const membership = (data?.memberships ?? []).find((m) => m.account_id === accountId);

  // Человек не состоит в текущем аккаунте — секции нет вовсе. Прочерк здесь
  // означал бы «значение не задано», тогда как не задана не величина, а строка
  // членства: её просто нет (ui.md, правило 9).
  if (!membership) return null;

  const rows: PropertyItem[] = [
    {
      label: "Аккаунт",
      value: <IamRefLink specId="accounts" refId={membership.account_id} />,
    },
  ];

  // Состояние показывается, только когда оно НАЗВАНО одним из двух известных
  // значений. Третьего у контракта нет, поэтому его появление означает не
  // «другое положение», а рассинхрон с краем: назвать его словом — соврать, а
  // прочерком — соврать иначе.
  if (membership.state === "ACTIVE" || membership.state === "PENDING") {
    rows.push({
      label: "Состояние",
      value: (
        <BoolFact
          value={membership.state === "ACTIVE"}
          yes="Состоит в аккаунте"
          no="Приглашён, ещё не входил"
          yesTone="good"
          yesGlyph="check"
          noTone="attention"
          noGlyph="warn"
        />
      ),
    });
  }

  return (
    <DetailSurface title={TITLE}>
      <PropertyRows items={rows} />
    </DetailSurface>
  );
}
