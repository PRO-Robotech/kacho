package restmux

import "testing"

func TestBAT1_ResolveBasicCredentialIsInternalOnly(t *testing.T) {
	const route = "/iam/v1/internal/iam:resolveBasicCredential"

	if !isInternalPath(route) {
		t.Errorf("маршрут авторитета %q классифицирован ПУБЛИЧНЫМ — на внешней "+
			"поверхности он оракул подбора", route)
	}
	// Положительный контроль соседом по сервису.
	if !isInternalPath("/iam/v1/internal/iam:lookupSubject") {
		t.Error("сосед по внутреннему сервису классифицирован публичным — " +
			"классификатор сломан целиком, и вердикт о нашем маршруте ничего не значит")
	}
	// Обратный контроль: публичный маршрут внутренним НЕ становится, иначе
	// «внутренний» было бы верно обо всём.
	if isInternalPath("/iam/v1/users/{user_id}/tokens") {
		t.Error("публичный маршрут выдачи объявлен внутренним — классификатор " +
			"объявляет внутренним всё, и проба выше вакуумна")
	}
}
