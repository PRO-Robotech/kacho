// Package credentialrevocation — ЧИТАТЕЛЬ отзыва УДОСТОВЕРЕНИЯ на открытых
// соединениях края (kacho#1410).
//
// # Предмет, и чем он отличается от соседнего
//
// Отзыв ПРАВ уже доезжает до потока: привязку сняли — перепрос журнала смены
// субъекта закрыл потоки названного принципала (kacho#1022, `pkg/subjectchange`).
// Отзыв УДОСТОВЕРЕНИЯ — выход человека, административное принудительное
// завершение, отзыв токена — в тот журнал строк НЕ ПИШЕТ, поэтому тем читателем
// не виден вовсе.
//
// До этого пакета граница отзыва удостоверения на открытом соединении равнялась
// СРОКУ ЖИЗНИ ПОТОКА: проверка делалась один раз, при открытии, а дальше поток
// запросов больше не делал — то есть контроль стоял на выдаче и не стоял на
// предъявлении. Такое состояние не сходится само: сходиться нечему.
//
// # Дверь ОДНА, ключей ДВА
//
// Второго механизма закрытия здесь не заводится. Реестр открытых потоков и
// отмена их контекстов — те же, что у отзыва прав; отличается только имя, каким
// отзыв называет закрываемое:
//
//	отзыв прав          → ПРИНЦИПАЛ      → Handler.CloseSubject
//	отзыв удостоверения → УДОСТОВЕРЕНИЕ  → Handler.CloseCredential
//
// Радиусы различаются не по вкусу, а по существу: выход из одной вкладки не
// вправе закрыть остальные вкладки того же человека, а человек, вошедший заново,
// обязан продолжать работать. По ключу принципала ни то, ни другое неразличимо.
//
// # Почему в дереве края, а не в фундаменте
//
// Читатель смены субъекта живёт в `pkg/`, потому что он читает ЖУРНАЛ ПЛАТФОРМЫ
// и потребителей у него может быть много; свойство «смена прав доезжает» обязано
// держаться одной реализацией на всех. Здесь предмет другой: вопросы задаются те
// же, что задаёт полоса аутентификации КРАЯ (`middleware`), материал для них
// собирается из заголовков, которые ставит край, а длинные соединения арендатора
// живут только на крае. Пакет в фундаменте был бы фундаментом с одним
// потребителем и лишним портом.
//
// # Что он делает — ОДНО дело
//
// На каждом обходе спрашивает авторитет про РАЗЛИЧНЫЕ удостоверения открытых
// сейчас потоков и закрывает те, про которые получен ОПРЕДЕЛЁННЫЙ ответ «это
// удостоверение больше не действует». Кэша решений он не трогает: тот отвечает
// на следующий запрос, а открытое соединение следующего запроса не делает.
package credentialrevocation

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"sync/atomic"
	"time"

	"github.com/PRO-Robotech/kacho/gateway/internal/middleware"
	"github.com/PRO-Robotech/kacho/gateway/internal/subscriptionstream"
)

// Reader — НАШ авторитет отзыва удостоверения, спрошенный ДВУМЯ вопросами.
//
// Два, а не один, и второй из первого не выводится: у браузерной сессии
// удостоверения нет вовсе — ни идентификатора, ни подписи, — и спросить про неё
// можно только по паре «человек + момент аутентификации». Свести их в один
// вопрос значило бы оставить без отзыва ровно ту полосу, которой консоль и
// открывает поток.
//
// Порт объявлен ЗДЕСЬ, у вызывающего: край зависит от вопросов, которые задаёт,
// а не от того, кто на них отвечает. Исполняется адаптером края
// (`gateway/internal/clients`.SessionRevocationsAdapter) — тем же самым, что
// отвечает на эти вопросы на пути запроса. Второй адаптер об одном предмете
// разошёлся бы с первым молча.
type Reader interface {
	// IsSessionRevoked — отозвано ли подписанное удостоверение с этим
	// идентификатором. Ошибка означает «спросить не удалось», НИКОГДА «не
	// отозвано».
	IsSessionRevoked(ctx context.Context, jti string) (bool, error)

	// SessionCutoffOf — момент, раньше которого сессии человека
	// недействительны. Три исхода несёт ПАРА значений вместе с ошибкой:
	// «отсечки нет» (found=false) и «спросить не удалось» (err) — разные
	// состояния, и слитые в одно они дали бы либо мягкий проход на молчащем
	// авторитете, либо закрытие каждому, кого никто не отзывал.
	SessionCutoffOf(ctx context.Context, userID string) (cutoff time.Time, found bool, err error)
}

// StreamRegistry — реестр открытых длинных соединений края.
//
// Исполняется проекцией потока (`gateway/internal/subscriptionstream`.Handler).
// Три метода, и каждый нужен: чем спрашивать, что закрывать поимённо и что
// закрывать, когда имён нет вовсе.
type StreamRegistry interface {
	// OpenCredentials — различные удостоверения открытых сейчас потоков.
	OpenCredentials() []subscriptionstream.Credential
	// CloseCredential закрывает потоки одного удостоверения, возвращает их число.
	CloseCredential(subscriptionstream.Credential) int
	// CloseAll закрывает ВСЕ открытые потоки, возвращает их число.
	CloseAll() int
}

// DefaultCallTimeout — бюджет ОДНОГО вопроса к авторитету.
//
// То же число, что у полосы базового секрета на пути запроса
// (`middleware.BasicCredentialCallBudget`): один и тот же сосед, один и тот же
// вопрос, и разъехавшиеся бюджеты означали бы, что «авторитет не ответил»
// наступает на двух путях в разное время без чьего-либо решения. Названный
// бюджет обязателен: неотвечающий сосед без него вешает горутину навсегда.
const DefaultCallTimeout = time.Second

// DefaultInterval — период обхода, когда посадка своего не назвала.
const DefaultInterval = 2 * time.Second

// Config — что приносит композиционный корень края.
type Config struct {
	// Reader — авторитет отзыва. Обязателен.
	Reader Reader

	// Streams — реестр открытых потоков. ОБЯЗАТЕЛЕН.
	//
	// Необязательным он быть не может, и это установлено инъекцией у соседнего
	// читателя: передай ноль — и весь корпус проб края остаётся зелёным, код
	// собирается, а отзыв перестаёт доезжать до потоков совсем. Несделанная
	// провязка была бы НЕОТЛИЧИМА от сделанной.
	Streams StreamRegistry

	// Interval — период обхода. Неположительный резолвится в [DefaultInterval].
	Interval time.Duration

	// CallTimeout — бюджет одного вопроса. Неположительный резолвится в
	// [DefaultCallTimeout].
	CallTimeout time.Duration

	// StaleAfter — сколько край вправе ДЕРЖАТЬ потоки, не подтвердив состояния
	// предъявленных удостоверений. Обязателен.
	//
	// Это ОКНО FAIL-CLOSED, и оно есть следствие решения, а не срока жизни
	// соединения: величина отсчитывается от последнего подтверждённого обхода и
	// к длительности соединения отношения не имеет. Обязана превосходить
	// [Config.Interval] — иначе один пропущенный обход объявляется аварией.
	StaleAfter time.Duration

	// Now — часы. Ноль резолвится в [time.Now]; проба подставляет свои, потому
	// что срок обязан быть свойством решения, а не занятости машины.
	Now func() time.Time

	// Logger — журнал процесса. Обязателен: застрявший отзыв обязан быть виден,
	// а не только не работать.
	Logger *slog.Logger
}

// Stats — счётчики обхода.
//
// «Ноль отказов за всю жизнь контроля» обязано быть заметно: контроль, который
// ни разу не сработал, и контроль, который не провязан, выглядят одинаково —
// если их не считать.
//
// Величины ЗНАКОВЫЕ, хотя отрицательными не бывают: складывается в них длина
// среза и счётчик цикла, то есть `int`, и беззнаковый приёмник потребовал бы
// приведения на каждом сложении. Приведение знакового к беззнаковому —
// переполнение, которого сборщик не запрещает, а проверка кода безопасности
// справедливо считает находкой; знаковый приёмник снимает целый класс вместо
// того, чтобы объявлять его невозможным.
type Stats struct {
	// Sweeps — сколько обходов состоялось.
	Sweeps int64
	// Asked — сколько вопросов задано авторитету.
	Asked int64
	// Closed — сколько потоков закрыто по отзыву удостоверения.
	Closed int64
	// Unanswered — сколько вопросов остались без ответа. Считается отдельно от
	// [Stats.Unsupported]: «сосед молчит» и «сосед такого вопроса не
	// предлагает» лечатся противоположно, и слитые в одно они дали бы либо
	// закрытие флота на всё окно раската, либо полосу без проверки.
	Unanswered int64
	// Unsupported — сколько раз авторитет ответил «такого вопроса не
	// предлагаю» (окно раската: край поднялся раньше службы прав).
	Unsupported int64
	// Unaskable — сколько открытых удостоверений не несут ВОПРОСА вовсе.
	//
	// ОСТАТОК, названный числом. Молчаливое выбрасывание сделало бы «закрывать
	// было нечего» неотличимым от «закрыть было нечем».
	Unaskable int64
	// FailClosed — сколько раз неподтверждённое чтение само стало решением
	// закрыть всё.
	FailClosed int64
}

// Sweeper обходит открытые потоки и закрывает те, чьё удостоверение отозвано.
type Sweeper struct {
	cfg      Config
	lastRead time.Time

	sweeps      atomic.Int64
	asked       atomic.Int64
	closed      atomic.Int64
	unanswered  atomic.Int64
	unsupported atomic.Int64
	unaskable   atomic.Int64
	failClosed  atomic.Int64
}

// New собирает сметателя и судит объявление посадки.
//
// Отказ на сборке, а не первым отказом в бою: величина, при которой fail-closed
// не наступает никогда, — ошибка посадки, и обнаруживать её тогда, когда она уже
// кому-то стоила доступа, поздно.
func New(cfg Config) (*Sweeper, error) {
	if cfg.Reader == nil {
		return nil, fmt.Errorf("credentialrevocation: авторитет отзыва не назван — " +
			"сметатель без него молчит ровно так же, как сметатель, которому нечего закрывать")
	}
	if cfg.Streams == nil {
		return nil, fmt.Errorf("credentialrevocation: реестр открытых потоков не назван — " +
			"отзыв удостоверения не доезжал бы до длинных соединений вовсе, и несделанная " +
			"провязка была бы неотличима от сделанной")
	}
	if cfg.Logger == nil {
		return nil, fmt.Errorf("credentialrevocation: журнал процесса не назван — " +
			"застрявший отзыв обязан быть виден, а не только не работать")
	}
	if cfg.Interval <= 0 {
		cfg.Interval = DefaultInterval
	}
	if cfg.CallTimeout <= 0 {
		cfg.CallTimeout = DefaultCallTimeout
	}
	if cfg.StaleAfter <= 0 {
		return nil, fmt.Errorf("credentialrevocation: срок StaleAfter не объявлен — поток пережил бы " +
			"аварию читателя отзыва целиком, то есть контроль отключался бы тем самым событием, " +
			"ради которого заведён")
	}
	if cfg.StaleAfter <= cfg.Interval {
		return nil, fmt.Errorf(
			"credentialrevocation: StaleAfter %v не превосходит Interval %v — срок, исчерпываемый "+
				"одним пропущенным обходом, объявляет аварией всякую заминку",
			cfg.StaleAfter, cfg.Interval)
	}
	if cfg.Now == nil {
		cfg.Now = time.Now
	}
	// Срок неподтверждённого чтения отсчитывается от СТАРТА, а не от нуля
	// времени: процесс, чей сметатель не заработал ни разу, обязан закрывать
	// потоки — но по истечении того же объявленного срока, а не немедленно.
	return &Sweeper{cfg: cfg, lastRead: cfg.Now()}, nil
}

// Window — ОБЪЯВЛЕННАЯ граница отзыва удостоверения на открытом соединении.
//
// Число, а не «быстро»: период обхода плюс бюджет одного вопроса — столько
// отозванное удостоверение держит уже открытый поток в худшем случае. Именно эту
// величину называет самоотчёт процесса, и именно её сверяет страж старта со
// сроком жизни потока: окно, не меньшее бюджета соединения, означало бы, что
// закрытие по собственному сроку выглядит закрытием по отзыву.
func (s *Sweeper) Window() time.Duration { return s.cfg.Interval + s.cfg.CallTimeout }

// StaleAfter — объявленный срок неподтверждённого чтения. Для самоотчёта.
func (s *Sweeper) StaleAfter() time.Duration { return s.cfg.StaleAfter }

// Interval — объявленный период обхода. Для самоотчёта.
func (s *Sweeper) Interval() time.Duration { return s.cfg.Interval }

// ClosesStreams — провязан ли реестр открытых потоков.
//
// Существует ради САМООТЧЁТА: он обязан печатать НАБЛЮДЕНИЕ, а не литерал.
// Литерал продолжает утверждать «закрывает» при отключённом закрывателе — то
// есть ровно тот класс, ради которого задача заведена.
func (s *Sweeper) ClosesStreams() bool { return s.cfg.Streams != nil }

// Stats отдаёт снимок счётчиков.
func (s *Sweeper) Stats() Stats {
	return Stats{
		Sweeps:      s.sweeps.Load(),
		Asked:       s.asked.Load(),
		Closed:      s.closed.Load(),
		Unanswered:  s.unanswered.Load(),
		Unsupported: s.unsupported.Load(),
		Unaskable:   s.unaskable.Load(),
		FailClosed:  s.failClosed.Load(),
	}
}

// Run блокирует до отмены контекста. Зовётся в своей горутине.
//
// РЕПЛИКИ: на-реплику — обход спрашивает про СВОИ открытые потоки и закрывает
// СВОИ. Каждая реплика обязана обходить сама: разведи её выбором одной — и
// потоки невыбранных переживут отзыв. Дубль безвреден по свойству операторов:
// вопрос ничего не меняет, а закрытие уже закрытого потока стоит нуля.
func (s *Sweeper) Run(ctx context.Context) {
	t := time.NewTicker(s.cfg.Interval)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			s.Sweep(ctx)
		}
	}
}

// Sweep исполняет РОВНО ОДИН обход: спросить про каждое открытое удостоверение и
// закрыть те, про которые получен определённый отказ.
//
// Метод публичный по той же причине, что и у читателя смены субъекта: он и есть
// единица работы, которую [Sweeper.Run] повторяет по расписанию, и им же
// ставится СКВОЗНОЙ вопрос — проба обязана читать наблюдаемое ПОСЛЕ того, как
// обход закончился, а не пока он идёт. Через [Sweeper.Run] это означало бы
// угадывать момент по таймеру: угадывание верное на свободной машине и неверное
// на занятой.
func (s *Sweeper) Sweep(ctx context.Context) {
	s.sweeps.Add(1)

	creds := s.cfg.Streams.OpenCredentials()
	var closed, unaskable, unanswered, unsupported int
	for _, cred := range creds {
		switch verdict, err := s.ask(ctx, cred); {
		case errors.Is(err, middleware.ErrSessionCutoffUnsupported):
			unsupported++
		case err != nil:
			unanswered++
		case verdict == verdictUnaskable:
			unaskable++
		case verdict == verdictRevoked:
			closed += s.cfg.Streams.CloseCredential(cred)
		}
	}
	s.closed.Add(int64(closed))
	s.unaskable.Add(int64(unaskable))
	s.unanswered.Add(int64(unanswered))
	s.unsupported.Add(int64(unsupported))

	if unanswered > 0 {
		// Подтверждения НЕ БЫЛО: хотя бы про одно предъявленное удостоверение
		// состояние установить не удалось. Часы неподтверждённого чтения не
		// двигаются — и это строгое прочтение, у которого названа цена:
		// удостоверение, про которое сосед не отвечает дольше объявленного
		// срока, закрывает потоки ВСЕХ, а не только свои. Радиус широкий
		// намеренно и по той же причине, что у соседнего читателя: кого именно
		// закрывать, реплика в этом состоянии знать не может.
		s.cfg.Logger.Warn("credential revocation sweep left credentials unconfirmed",
			"unanswered", unanswered, "credentials", len(creds))
		s.failClosedIfStale()
		return
	}
	s.lastRead = s.cfg.Now()

	if unsupported > 0 {
		// Проход ГРОМКИЙ: «метода нет» сходится само раскатом, но застрявшее
		// расхождение версий тихо оставило бы полосу без проверки.
		s.cfg.Logger.Error("credential revocation is not enforced on open streams: "+
			"the authority does not offer this question (image skew)",
			"credentials", unsupported,
			"predicate", "исчезает, когда служба прав докатится до того же дерева")
	}
	if closed > 0 {
		s.cfg.Logger.Info("streams closed by credential revocation",
			"streams_closed", closed, "credentials", len(creds), "window", s.Window().String())
	}
	if unaskable > 0 {
		// ОСТАТОК. Печатается на обходе, где он есть, и не печатается на пустом:
		// запись на каждом тике — шум, который перестают читать.
		s.cfg.Logger.Warn("open streams whose credential carries no question to the revocation authority",
			"credentials", unaskable,
			"consequence", "их отзыв доезжает только полосой отзыва прав; своей полосы у них нет")
	}
}

// verdict — исход одного вопроса.
type verdict int

const (
	// verdictLive — спросили, удостоверение действует.
	verdictLive verdict = iota
	// verdictRevoked — спросили, получен ОПРЕДЕЛЁННЫЙ отказ.
	verdictRevoked
	// verdictUnaskable — вопроса нет: предъявленное не несёт ни идентификатора
	// удостоверения, ни человека, про которого спрашивают отсечку.
	verdictUnaskable
)

// ask задаёт авторитету вопрос ПРО ЭТО удостоверение.
//
// # Порядок вопросов и почему он такой
//
// Идентификатор удостоверения — первым: он спрашивает ровно про предъявленное, и
// на отозванном избавляет от второго вопроса, который всё равно ничего бы не
// добавил. Отсечка спрашивается только тогда, когда идентификатора нет, — то
// есть на браузерной полосе, где его не бывает вовсе.
//
// Тот же порядок и та же классификация, что на пути запроса: два пути об одном
// предмете, разошедшись, дали бы отзыв, действующий на запросах и не действующий
// на соединении, — ровно тот класс, ради которого пакет заведён.
func (s *Sweeper) ask(ctx context.Context, cred subscriptionstream.Credential) (verdict, error) {
	if !cred.Askable() {
		return verdictUnaskable, nil
	}
	// Бюджет НА КАЖДЫЙ вопрос: неотвечающий сосед не вправе занять обход целиком
	// и отложить вместе с ним fail-closed.
	callCtx, cancel := context.WithTimeout(ctx, s.cfg.CallTimeout)
	defer cancel()

	if cred.JTI != "" {
		s.asked.Add(1)
		revoked, err := s.cfg.Reader.IsSessionRevoked(callCtx, cred.JTI)
		switch {
		case err != nil:
			return verdictLive, fmt.Errorf("источник отзыва не ответил: %w", err)
		case revoked:
			return verdictRevoked, nil
		}
		return verdictLive, nil
	}

	s.asked.Add(1)
	cutoff, found, err := s.cfg.Reader.SessionCutoffOf(callCtx, cred.UserID)
	switch {
	case err != nil:
		// «Метода нет» доезжает сюда типизированным признаком и наверх
		// возвращается как есть: вызывающий обязан отличать его от молчания —
		// они лечатся противоположно.
		return verdictLive, err
	case !found:
		// Пустой ответ означает ПУСТО. Человек, которого никто не отзывал,
		// работает.
		return verdictLive, nil
	case cred.AuthAt == 0:
		// Отсечка есть, а сравнивать не с чем: источник момента не назвал.
		// Пропустить значило бы дать обходить отзыв ОТСУТСТВИЕМ поля. Та же
		// посадка принята полосой запроса, и расходиться с ней незачем.
		return verdictRevoked, nil
	case cred.AuthAt > cutoff.Unix():
		// Отсечка действует ВПЕРЁД: вошедший заново работает.
		return verdictLive, nil
	}
	// Аутентифицировавшаяся В МОМЕНТ отсечки или раньше — недействительна.
	// Включение самого момента взято у полосы запроса: иначе принудительное
	// завершение, совпавшее по метке со входом, не подействовало бы, а совпадают
	// они тем чаще, чем грубее разрешение метки у хранилища.
	return verdictRevoked, nil
}

// failClosedIfStale закрывает ВСЕ потоки, когда состояние предъявленных
// удостоверений не подтверждалось дольше объявленного срока.
//
// Неполученный ответ авторитета не есть «никого не отзывали». Кого именно
// закрывать, реплика в этом состоянии знать не может, — поэтому радиус широкий,
// и он назван.
//
// Закрывает на КАЖДОМ обходе за сроком, а не однажды: клиент, переоткрывшийся в
// середине аварии, обязан закрыться тоже. На пустом реестре это стоит нуля.
func (s *Sweeper) failClosedIfStale() {
	stale := s.cfg.Now().Sub(s.lastRead)
	if stale < s.cfg.StaleAfter {
		return
	}
	closed := s.cfg.Streams.CloseAll()
	s.failClosed.Add(1)
	if closed == 0 {
		// Ноль закрытых — не событие: держать было нечего. Печатать это на
		// каждом обходе значило бы утопить настоящую находку в шуме.
		return
	}
	s.closed.Add(int64(closed))
	s.cfg.Logger.Error("credential revocation reader is stale: closing every open stream (fail-closed)",
		"stale_for", stale.String(), "stale_after", s.cfg.StaleAfter.String(), "streams_closed", closed)
}
