// Package subscriptionstream — ЕДИНСТВЕННАЯ проекция потока изменений в браузер.
//
// # Что это и чем оно не является
//
// Край становится ПОТРЕБИТЕЛЕМ общего глагола подписки
// (`kacho.cloud.subscription.InternalSubscriptionService/Subscribe`,
// `pkg/subscription`) и отдаёт наружу СВОЮ поверхность — Server-Sent Events.
//
// Это не проекция метода через `runtime.ServeMux`, и различие проверяемо, а не
// декларативно:
//
//   - ручка не зарегистрирована ни на одном `runtime.ServeMux`;
//   - вход — пять названных величин запроса, а не сообщение контракта;
//   - выход — кадры SSE, собранные здесь, а не сериализованное сообщение;
//   - решение о показе принимает ВЛАДЕЛЕЦ, на каждой отдаваемой строке, под
//     личностью ВЫЗЫВАЮЩЕГО.
//
// Внешнего пути у самого метода нет и не заводится: его нет в
// `allowlist.AllowedMethods`, его имя отсекает `allowlist.HasInternalSuffix`, а
// `google.api.http` контракт не объявляет — значит `generatedRestRoutes` его не
// несёт. Запрет #6 держат эти три механизма, а не настоящая фраза.
//
// # Точка проекции ОДНА, владелец — параметр
//
// Владелец журнала называется параметром `owner` из ЗАКРЫТОГО словаря, а не
// своей ручкой. Седьмой модуль добавляет строку словаря и не добавляет ни пути,
// ни обработчика, ни записи каталога прав.
//
// Словарь закрыт не ради аккуратности: открытый параметр отдал бы выбор адреса
// дозвона вызывающему.
//
// # Позицию называет ОДИН носитель
//
// `Last-Event-ID` — единственный способ назвать позицию. Запроса `?position=`
// нет намеренно: два носителя одного значения расходятся, и первым же случаем
// расхождения было бы переподключение — в адресе стоит начальная позиция, в
// заголовке текущая.
//
// Позиция непрозрачна и переносится ДОСЛОВНО. Второго кодека курсора здесь нет:
// разбирает её только владелец (`pkg/pagetoken`), и заведи край свой — они
// разошлись бы молча, потому что на валидном входе оба отвечают «валидно».
//
// # Заголовки ответа пишутся ПОСЛЕ первого сообщения владельца
//
// Порядок несущий. Отказы владельца (негодный вид, недоступный проект,
// утраченная позиция, исчерпание, недоступность) обязаны стать КОДОМ ОТВЕТА, а
// код после отправки заголовков уже не изменить. Контракт гарантирует, что
// служебное сообщение открытия приходит ПЕРВЫМ и ВСЕГДА, — поэтому дождаться его
// можно, ничего не отдав.
//
// # Шов, оставленный отзыву прав (kacho#1022)
//
// Каждый открытый поток стоит в реестре под идентификатором принципала вместе со
// своей отменой. Закрыть все потоки субъекта — обход одного ключа, а не поиск по
// горутинам. Подписки реестра на инвалидацию здесь НЕТ: её заводит kacho#1022.
