package subscriptionstream

// registry_gap_test.go — ЗАЗОР между постановкой потока на учёт и заведением его
// отмены (kacho#1022).
//
// # Почему зазор существует намеренно
//
// Место в реестре занимается ДО того, как заведён контекст: иначе проверка
// предела и постановка на учёт разъезжаются, и два одновременных запроса одного
// субъекта оба увидят свободное место — software check-then-act. Плата за это —
// окно, в котором поток УЧТЁН, но отменять ещё нечего. Закрытие, пришедшее в это
// окно, обязано сработать при вооружении, иначе поток, закрытый по отзыву,
// продолжит жить — молча и ровно в том окне, где отзыв и происходит.
//
// # Почему проба ВНУТРЕННЯЯ и почему детерминированная
//
// Снаружи в зазор не попасть: он микроскопический, а закрыватель, бьющий в
// цикле, ловит поток уже вооружённым — такая проба остаётся ЗЕЛЁНОЙ при снятом
// признаке закрытия (проверено: она была написана, прогнана под детектором
// гонок и не различила дефект). Гонка здесь не в данных, а в ПОРЯДКЕ, и
// детектор гонок о ней не говорит ничего.
//
// Поэтому порядок задаётся явно: учли → закрыли → вооружаем. Это ровно та
// последовательность, которую зазор и допускает.

import (
	"testing"

	"github.com/PRO-Robotech/kacho/gateway/internal/principalmeta"
)

func TestClosingInsideTheArmingGapCancelsOnArm(t *testing.T) {
	r := newRegistry()

	entry, release, ok := r.tryAdd("user:usr-gap", principalmeta.Credential{}, 4)
	if !ok {
		t.Fatal("поток не встал на учёт")
	}
	defer release()

	// Субъекта закрывают, пока отмены ещё нет — законное окно.
	if n := r.closeSubject("user:usr-gap"); n != 1 {
		t.Fatalf("закрыто %d потоков, ожидался 1 (поток учтён, но ещё не вооружён)", n)
	}

	cancelled := false
	entry.arm(func() { cancelled = true })

	if !cancelled {
		t.Fatal("отмена, заведённая ПОСЛЕ закрытия субъекта, не сработала немедленно — " +
			"поток, закрытый по отзыву, продолжил бы жить: молча и ровно в том окне, где отзыв и происходит")
	}
}

// TestArmingWithoutClosingKeepsTheStream — положительный контроль.
//
// Без него утверждение выше зеленело бы на записи, отменяющей поток ВСЕГДА, —
// то есть на устройстве, которое не даёт открыть ни одного потока.
func TestArmingWithoutClosingKeepsTheStream(t *testing.T) {
	r := newRegistry()

	entry, release, ok := r.tryAdd("user:usr-live", principalmeta.Credential{}, 4)
	if !ok {
		t.Fatal("поток не встал на учёт")
	}
	defer release()

	cancelled := false
	entry.arm(func() { cancelled = true })

	if cancelled {
		t.Fatal("отмена сработала на потоке, которого никто не закрывал")
	}

	// А закрытие ПОСЛЕ вооружения обязано её вызвать — иначе первая проба
	// зеленела бы на записи, которая не отменяет никогда.
	if n := r.closeSubject("user:usr-live"); n != 1 {
		t.Fatalf("закрыто %d потоков, ожидался 1", n)
	}
	if !cancelled {
		t.Fatal("закрытие вооружённого потока не вызвало отмену")
	}
}
