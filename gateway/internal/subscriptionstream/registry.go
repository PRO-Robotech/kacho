// OpenStream — учтённый поток, каким его видит читатель отзыва УДОСТОВЕРЕНИЯ
// (kacho#1410).
//
// # Почему закрытие едет ЗАМЫКАНИЕМ, а не номером
//
// Тем же доводом, что и снятие с учёта: вызывающему не приходится хранить ключ,
// а значит и терять его. Замыкание идемпотентно — поток, закрытый дважды, стоит
// нуля, — поэтому читатель вправе не сверяться с реестром между решением и
// действием.
//
// # Почему удостоверение, а не только субъект
//
// Отзыв ПРАВ называет субъекта, и потоков у субъекта столько, сколько вкладок.
// Отзыв УДОСТОВЕРЕНИЯ называет предъявленное — а два потока одного человека
// могут быть открыты разными удостоверениями, и отозвано может быть одно.
// Закрытие по субъекту здесь закрывало бы лишнее.
type OpenStream struct {
	// Subject — субъект модели прав, под которым поток учтён.
	Subject string
	// Credential — чем предъявитель назвал себя, открывая этот поток.
	Credential principalmeta.Credential
	// Close — отменить именно ЭТОТ поток. Идемпотентно.
	Close func()
}

// registry — открытые потоки, сгруппированные по субъекту.
//
// # Зачем группировка ПО СУБЪЕКТУ, а не плоский список
//
// Она заведена ради kacho#1022 («отзыв прав закрывает открытый поток»), и это
// сказано прямо, чтобы её не приняли за преждевременное обобщение. Отзыв
// приходит с ИМЕНЕМ СУБЪЕКТА — край уже получает его на своём внутреннем
// слушателе, — поэтому закрытие обязано быть обходом одного ключа. Плоский
// список потребовал бы перебора всех открытых потоков на каждый отзыв, а их
// столько, сколько вкладок у всех арендаторов сразу.
//
// Здесь реализовано ТОЛЬКО ведение реестра. Подписку на событие отзыва держат
// его читатели ([Handler.CloseSubject], [Handler.CloseAll]), а провязывает их
// композиционный корень края.
type registry struct {
	mu     sync.Mutex
	next   uint64
	bySubj map[string]map[uint64]*stream
}

func newRegistry() *registry {
	return &registry{bySubj: make(map[string]map[uint64]*stream)}
}

// stream — один учтённый поток.
//
// Отмена ставится ПОЗЖЕ учёта: место в реестре занимается до того, как заведён
// контекст, — иначе проверка предела и постановка на учёт разъезжаются, и два
// одновременных запроса одного субъекта оба увидят свободное место. Это
// software check-then-act, и лечится он не аккуратностью, а тем, что решение и
// его следствие происходят под одним замком.
//
// Из-за этого зазора появляется [stream.closed]: субъекта могут закрыть между
// учётом и заведением контекста, и тогда отмена обязана сработать НЕМЕДЛЕННО
// при постановке. Иначе поток, закрытый по отзыву прав, продолжил бы жить —
// молча и ровно в том окне, где отзыв и происходит.
type stream struct {
	// cred — удостоверение, которым поток открыт. Пишется ОДИН раз, при
	// постановке на учёт, и не меняется: предъявленное потоком не обновляется —
	// длинное соединение второго запроса не делает, и подменить своё
	// удостоверение на живое вызывающий не может by construction.
	cred principalmeta.Credential

	mu     sync.Mutex
	cancel context.CancelFunc
	closed bool
}

// arm ставит отмену уже учтённому потоку.
func (s *stream) arm(cancel context.CancelFunc) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		// Субъекта закрыли в зазоре между учётом и заведением контекста.
		cancel()
		return
	}
	s.cancel = cancel
}

// close отменяет поток и помечает его закрытым.
func (s *stream) close() {
	s.mu.Lock()
	cancel := s.cancel
	s.closed = true
	s.mu.Unlock()
	if cancel != nil {
		cancel()
	}
}

// tryAdd ставит поток на учёт, если субъект не исчерпал СВОЙ предел.
//
// # Почему предел на субъекта, а не только на реплику
//
// Потолок реплики один на всех, поэтому один арендатор занимает его целиком, и
// остальные получают отказ, не имея НИ ОДНОГО собственного потока. Консоль
// открывает поток на вкладку — десяток вкладок одного пользователя закрывал бы
// подписку всем прочим. Предел реплики защищает ПРОЦЕСС, предел субъекта
// защищает АРЕНДАТОРОВ ДРУГ ОТ ДРУГА, и одно другого не заменяет.
//
// # Почему проверка и постановка — под одним замком
//
// «Посмотреть, сколько занято, и занять ещё одно» есть software check-then-act:
// два одновременных запроса одного субъекта оба увидят свободное место и оба
// его займут. Предел, обходимый параллелизмом, — это предел ровно до той
// нагрузки, ради которой он заведён.
//
// Возвращается замыкание снятия, а не пара (субъект, номер): вызывающему не
// приходится хранить ключ, а значит и терять его. Снятие идемпотентно, поэтому
// `defer` безопасен на любом пути выхода.
func (r *registry) tryAdd(
	subject string, cred principalmeta.Credential, perSubject int,
) (*stream, func(), bool) {
	if subject == "" {
		// Безымянный поток закрыть нечем: у отзыва нет ключа, которым его
		// назвать. Отсекается здесь, а не только у вызывающего, — страж у одной
		// двери переживает появление второго вызывающего.
		return nil, nil, false
	}
	r.mu.Lock()
	streams, ok := r.bySubj[subject]
	if ok && perSubject > 0 && len(streams) >= perSubject {
		r.mu.Unlock()
		return nil, nil, false
	}
	r.next++
	id := r.next
	if !ok {
		streams = make(map[uint64]*stream)
		r.bySubj[subject] = streams
	}
	entry := &stream{cred: cred}
	streams[id] = entry
	r.mu.Unlock()

	var once sync.Once
	return entry, func() {
		once.Do(func() {
			r.mu.Lock()
			defer r.mu.Unlock()
			if streams, ok := r.bySubj[subject]; ok {
				delete(streams, id)
				// Пустая карта субъекта снимается вместе с последним потоком:
				// иначе реестр растёт по числу когда-либо подписавшихся, а не
				// по числу подписанных сейчас.
				if len(streams) == 0 {
					delete(r.bySubj, subject)
				}
			}
		})
	}, true
}

// snapshot — открытые потоки вместе с удостоверением каждого.
//
// Снимок берётся ПОД ЗАМКОМ и отдаётся значениями: читатель отзыва спрашивает
// авторитет по сети, и держать замок реестра всё это время значило бы
// останавливать открытие новых потоков на время недоступности соседа — то есть
// превращать заминку авторитета в отказ ручки.
//
// Поток, закрывшийся между снимком и решением, снимается с учёта сам, а
// повторное закрытие стоит нуля: рассинхрон снимка безвреден by construction.
func (r *registry) snapshot() []OpenStream {
	r.mu.Lock()
	defer r.mu.Unlock()
	out := make([]OpenStream, 0, len(r.bySubj))
	for subject, streams := range r.bySubj {
		for _, entry := range streams {
			out = append(out, OpenStream{Subject: subject, Credential: entry.cred, Close: entry.close})
		}
	}
	return out
}

// closeSubject отменяет контексты всех потоков субъекта и возвращает их число.
//
// Снятие с учёта делает САМ поток, выходя, а не эта функция: отмена контекста
// его разбудит, и он снимется своим `defer`. Снимай их здесь — снятие
// произошло бы дважды, а второй раз уже не по своему потоку.
func (r *registry) closeSubject(subject string) int {
	r.mu.Lock()
	streams := r.bySubj[subject]
	entries := make([]*stream, 0, len(streams))
	for _, entry := range streams {
		entries = append(entries, entry)
	}
	r.mu.Unlock()

	for _, entry := range entries {
		entry.close()
	}
	return len(entries)
}

// closeAll отменяет контексты ВСЕХ учтённых потоков и возвращает их число.
//
// Снятие с учёта, как и у [registry.closeSubject], делает сам поток, выходя:
// отмена контекста его разбудит, и он снимется своим `defer`.
func (r *registry) closeAll() int {
	r.mu.Lock()
	entries := make([]*stream, 0, len(r.bySubj))
	for _, streams := range r.bySubj {
		for _, entry := range streams {
			entries = append(entries, entry)
		}
	}
	r.mu.Unlock()

	for _, entry := range entries {
		entry.close()
	}
	return len(entries)
}
