// dpopExpiredPredicate — «запись больше не действует».
//
// # Почему ОДНА константа на читателя и уборщика
//
// Порог уборки обязан совпадать с предикатом ЧИТАТЕЛЯ таблицы. Читатель здесь
// судит по СРОКУ, а не по наличию строки: просроченную запись он перезаписывает
// и предъявление допускает. Разойдись эти два выражения — уборка снимала бы
// строку РАНЬШЕ, чем читатель перестаёт её принимать, и перехваченное
// доказательство прошло бы вторично; разойдись в другую сторону — уборка не
// уносила бы то, что уже мертво.
//
// Согласованность держится не сверкой двух текстов, а тем, что текст ОДИН:
// оба оператора собираются из этой строки, и разойтись им нечем by construction.
//
// Часы — базы, а не процесса, в ОБОИХ операторах. Уборщик, судящий часами
// своего пода, и читатель, судящий часами базы, тождественны лишь при их
// синхронности; на ушедших вперёд часах пода уборка снимала бы строку, которую
// читатель ещё считает действующей, — то самое окно, только незаметное.
const dpopExpiredPredicate = `kacho_gateway.dpop_replay.expires_at <= now()`

// dpopReplaySQL — допуск ОДНИМ оператором.
//
// Вставилось ⇒ это доказательство предъявлено впервые. Не вставилось ⇒ его уже
// предъявляли, и повтор отвергается. Проверки перед вставкой здесь нет и быть
// не может: пара «посмотреть — записать» под конкуренцией двух реплик пропустит
// оба предъявления (ban #10), а именно эта конкуренция и есть предмет.
//
// Просроченная запись перезаписывается, а не мешает: за пределами окна свежести
// повтор отвергается уже проверкой времени, и держать её как запрет значило бы
// запрещать значение навсегда.
const dpopReplaySQL = `
INSERT INTO kacho_gateway.dpop_replay (jti, expires_at)
VALUES ($1, now() + make_interval(secs => $2))
ON CONFLICT (jti) DO UPDATE
    SET expires_at = EXCLUDED.expires_at
    WHERE ` + dpopExpiredPredicate + `
RETURNING TRUE`

// dpopPurgeSQL — уборка ОДНОЙ ограниченной партии.
//
// Партия ограничена по той же причине, что и у ключа однократности: одиночный
// DELETE по хвосту произвольной длины держал бы блокировки дольше, чем живёт
// запрос. Ограничение партии — НЕ ограничение ёмкости уборки: партий за одну
// уборку столько, сколько нужно, чтобы хвост кончился (см. PurgeExpiredDPoPProofs).
const dpopPurgeSQL = `
DELETE FROM kacho_gateway.dpop_replay
 WHERE ctid IN (
     SELECT ctid FROM kacho_gateway.dpop_replay
      WHERE ` + dpopExpiredPredicate + `
      LIMIT $1
 )`

// dpopLagSQL — возраст САМОЙ СТАРОЙ просроченной записи.
//
// Это и есть отставание уборки от темпа записи, выраженное величиной, а не
// выведенное из спокойствия: пока уборка догоняет, просроченных строк после неё
// не остаётся вовсе; как только перестала — возраст растёт без границы.
//
// `min` по индексированному столбцу берёт первую строку индекса, поэтому запрос
// не дорожает вместе с хвостом — то есть остаётся дешёвым ровно тогда, когда
// хвост велик и величина нужнее всего. Это ЗАМЕРЕНО, а не предположено:
// Postgres 16, хвост 200 000 просроченных строк, `EXPLAIN (ANALYZE, BUFFERS)` —
// `Index Only Scan using dpop_replay_expires_idx` под `Limit 1`, прочитано
// 3 страницы, время исполнения 0.043 мс.
const dpopLagSQL = `
SELECT COALESCE(EXTRACT(EPOCH FROM (now() - min(expires_at))), 0)
  FROM kacho_gateway.dpop_replay
 WHERE ` + dpopExpiredPredicate

// ErrDPoPReplay — доказательство уже предъявляли.
//
// Отдельная величина, а не общая ошибка: вызывающий обязан отличить «повтор» от
// «хранилище не ответило». Первое — отказ клиенту, второе — отказ края, и
// смешать их значило бы отдать клиенту 401 на нашу же недоступность.
var ErrDPoPReplay = errors.New("dpop: proof already presented")

// AddDPoPProof допускает доказательство ровно один раз за окно свежести.
//
// Возвращает nil при первом предъявлении, ErrDPoPReplay при повторном и ошибку
// хранилища во всех прочих случаях — fail-closed остаётся за вызывающим, у
// которого есть контекст запроса.
func (s *Store) AddDPoPProof(ctx context.Context, jti string, ttl time.Duration) error {
	if jti == "" {
		// Пустой `jti` — не «нет значения», а доказательство без опознавателя:
		// допустить его значило бы разрешить неограниченный повтор одного и
		// того же пустого ключа.
		return fmt.Errorf("dpop replay store: jti пуст — доказательство без опознавателя не допускается")
	}
	if ttl <= 0 {
		return fmt.Errorf("dpop replay store: окно свежести %v не положительно — запись истекла бы раньше, чем появилась", ttl)
	}

	var inserted bool
	err := s.pool.QueryRow(ctx, dpopReplaySQL, jti, ttl.Seconds()).Scan(&inserted)
	switch {
	case err == nil && inserted:
		return nil
	case errors.Is(err, pgx.ErrNoRows):
		// Ни вставки, ни перезаписи: живая строка с этим `jti` уже есть.
		return ErrDPoPReplay
	case err != nil:
		return fmt.Errorf("dpop replay store: %w", err)
	default:
		return ErrDPoPReplay
	}
}

// DPoPSweep — исход ОДНОЙ уборки.
//
// Три величины, и ни одна не выводится из остальных: `Removed` говорит, что
// уборка сделала, `Drained` — кончился ли хвост, `Lag` — насколько уборка от
// него отстала. Одного `Removed` мало: уборщик, унёсший свою партию и
// замолчавший, по нему неотличим от уборщика, который догоняет.
type DPoPSweep struct {
	// Removed — сколько строк унесено этой уборкой.
	Removed int64
	// Drained — уборка остановилась потому, что просроченного не осталось, а не
	// потому, что упёрлась в свою границу.
	Drained bool
	// Lag — возраст самой старой просроченной записи, ОСТАВШЕЙСЯ после уборки.
	//
	// Ноль означает ДВА разных состояния, и различает их не он: догнавшей уборке
	// отставать не от чего (`Drained`), а уборке, оборвавшейся отказом
	// хранилища, отставание измерить нечем — соединение и есть то, что отказало.
	// Поэтому величину читают в паре с `Drained` и с исходом вызова, а не
	// в одиночку.
	Lag time.Duration
}

// PurgeExpiredDPoPProofs уносит просроченные записи ограниченными партиями,
// пока хвост не кончится, и говорит, догнала ли она темп.
//
// # Кто зовёт
//
// Сборщик хранилища, СВОИМ шагом — `Store.purgeDPoPOnce` из `reapLoop`, а не
// вместе с уборкой ключей однократности: у двух таблиц разная жизнь строки, и
// общий шаг был бы верен разве что случайно. Здесь стояло обратное («вместе со
// своей уборкой»), и это было утверждением о вызове, которого не существовало:
// прод-вызывающих у этого метода было НОЛЬ, а сборщик звал соседний `Reap`.
// Что зовут — держит теперь не шапка, а проба
// `TestDPoPSweep_JanitorRemovesExpiredWithoutBeingCalled`: она утверждает исход
// (строки нет), а не факт вызова, — «вызвался» зелено и на уборщике, не унёсшем
// ничего.
//
// # Почему партии, а не один оператор
//
// Темп записи задаёт ПРЕДЪЯВИТЕЛЬ: строка появляется на каждый запрос с
// доказательством владения, то есть величина внешняя и границы у неё нет.
// Значит ни одна постоянная ёмкость уборки не может быть верной: уборка, уносящая
// B строк за период P, догоняет ровно пока темп ≤ B/P, а выше — хвост растёт без
// границы, оставаясь ЗЕЛЁНЫМ по всякой проверке вида «уборщик вызвался».
//
// Поэтому ограничена ПАРТИЯ (блокировки не держатся дольше запроса), а ёмкость
// уборки — нет: партий столько, сколько нужно. Тогда «догоняет ли» перестаёт
// зависеть от знания темпа.
//
// # Что ограничивает уборку сверху
//
// Срок вызывающего (у сборщика он свой) и `DPoPPurgeMaxBatches` — сторож от
// бесконечного цикла, а НЕ ограничитель темпа. Упёрлись в любую из границ —
// уборка возвращает `Drained=false` и измеренное отставание, и молчаливым это
// состояние быть не может.
func (s *Store) PurgeExpiredDPoPProofs(ctx context.Context) (DPoPSweep, error) {
	var out DPoPSweep
	maxBatches := s.cfg.DPoPPurgeMaxBatches
	for i := 0; i < maxBatches; i++ {
		if err := ctx.Err(); err != nil {
			break
		}
		tag, err := s.pool.Exec(ctx, dpopPurgeSQL, DPoPPurgeBatch)
		if err != nil {
			s.recordDPoPSweep(out)
			return out, fmt.Errorf("dpop replay store: уборка: %w", err)
		}
		n := tag.RowsAffected()
		out.Removed += n
		if n < DPoPPurgeBatch {
			// Неполная партия — просроченного больше нет. Это единственный
			// выход, означающий «догнали».
			out.Drained = true
			break
		}
	}
	if !out.Drained {
		lag, err := s.dpopLag(ctx)
		if err != nil {
			s.recordDPoPSweep(out)
			return out, err
		}
		out.Lag = lag
		// Граница исчерпана РОВНО на пустом хвосте: просроченного не осталось,
		// и объявлять отставание было бы тревогой без предмета. Проверка,
		// кричащая в исправном состоянии, перестаёт читаться, а вместе с ней —
		// и настоящая находка.
		out.Drained = lag == 0
	}
	s.recordDPoPSweep(out)
	return out, nil
}

// dpopLagTimeout — срок ОДНОГО замера отставания, когда срок захода уже вышел.
//
// Замер — не уборка: он читает первую строку индекса, и держать его дольше
// незачем.
const dpopLagTimeout = 2 * time.Second

// dpopLag спрашивает возраст самой старой просроченной записи.
//
// # Почему замер переживает срок захода
//
// Срок захода выходит ИМЕННО ПОТОМУ, что хвост велик, — то есть ровно в том
// случае, ради которого величина и заведена. Замер на исчерпанном контексте
// отказал бы, и отставание осталось бы неизмеренным именно тогда, когда оно
// максимально: наблюдение гасло бы при наступлении своего предмета.
//
// Свой срок при этом короткий и по-прежнему ограничен жизнью ХРАНИЛИЩА: на
// закрытии замер обрывается вместе со всем остальным.
func (s *Store) dpopLag(ctx context.Context) (time.Duration, error) {
	if ctx.Err() != nil {
		var cancel context.CancelFunc
		ctx, cancel = context.WithTimeout(s.baseCtx, dpopLagTimeout)
		defer cancel()
	}
	var secs float64
	if err := s.pool.QueryRow(ctx, dpopLagSQL).Scan(&secs); err != nil {
		return 0, fmt.Errorf("dpop replay store: отставание уборки: %w", err)
	}
	if secs <= 0 {
		return 0, nil
	}
	return time.Duration(secs * float64(time.Second)), nil
}
