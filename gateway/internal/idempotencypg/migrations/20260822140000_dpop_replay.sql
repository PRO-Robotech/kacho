-- 20260822140000 — однократность предъявления доказательства владения (`jti`).
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ВНЕ ПРОЦЕССА
--
-- Край проверяет, что одно и то же доказательство владения ключом (DPoP,
-- RFC 9449) не предъявлено дважды. Пока запись о предъявленном `jti` живёт в
-- памяти процесса, обещание верно ровно до второй реплики: перехваченное
-- доказательство, поданное в СОСЕДНИЙ под, записи не находит и проходит.
--
-- Отказа при этом не происходит и наблюдаемого следа нет — ровно то свойство,
-- из-за которого класс живёт долго. Домен параллелизма гарантии — ФЛОТ подов
-- края, значит и запись обязана лежать там, где её видят все реплики.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПЕРВИЧНЫЙ КЛЮЧ, А НЕ ПРОВЕРКА ПЕРЕД ВСТАВКОЙ
--
-- Уникальность `jti` делает допуск ОДНИМ атомарным оператором
-- (`INSERT … ON CONFLICT DO NOTHING`, вставлено ⇒ предъявлено впервые), то есть
-- держит инвариант оператором базы, а не программной парой «посмотреть —
-- записать» (ban #10). Под конкуренцией двух реплик выигрывает ровно одна.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ГРАНИЦА ХРАНИЛИЩА
--
-- Строка живёт до `expires_at` — это окно свежести доказательства, за его
-- пределами повтор отвергается уже проверкой времени, и хранить запись дольше
-- незачем. Уборка идёт по индексу; без неё таблица росла бы без границы, а
-- уникальный ключ превратился бы в вечный запрет на повторное значение.

-- +goose Up
CREATE SCHEMA IF NOT EXISTS kacho_gateway;

CREATE TABLE IF NOT EXISTS kacho_gateway.dpop_replay (
    -- `jti` доказательства. Первичный ключ и есть механизм однократности.
    jti        TEXT        PRIMARY KEY,
    -- Когда запись перестаёт быть нужной: окно свежести доказательства.
    expires_at TIMESTAMPTZ NOT NULL
);

-- Уборка просроченных: единственное чтение этой таблицы, кроме допуска.
CREATE INDEX IF NOT EXISTS dpop_replay_expires_idx
    ON kacho_gateway.dpop_replay (expires_at);

-- +goose Down
DROP INDEX IF EXISTS kacho_gateway.dpop_replay_expires_idx;
DROP TABLE IF EXISTS kacho_gateway.dpop_replay;
