// f1d_issuer_address_is_never_derived_test.go — Ф1г: адрес издателя на крае
// ОБЪЯВЛЯЕТСЯ и никогда не выводится.
//
// # Что здесь снимается и почему именно сейчас
//
// У края была запасная ветвь: перечень издателей не объявлен ⇒ построить ОДНУ
// запись приёма из скалярного пина `KACHO_HYDRA_ISSUER` / `KACHO_HYDRA_JWKS_URL`,
// а при пустом пине — ВЫВЕСТИ адрес чужого издателя из домена установки
// (`https://hydra.` + домен). Отказа старта на этой ветви не было ни под одной
// меткой окружения, включая производственную: край поднимался, объявлял одну
// запись приёма на хост, которого на стенде нет, и отвергал каждый токен при
// первом же запросе. Для арендатора — 401, неотличимый от неверных учётных
// данных; для оператора — зелёный выкат и готовый под.
//
// Ветвь держалась на том, что её мог кто-то исполнять. Полоса предусловия
// измерила дерево и закрыла этот вопрос: перечень издателей объявлен КАЖДЫМ
// стендом — сам или слоем ниже по цепочке `-f`, — и это утверждение держит
// страж, краснеющий на необъявившем (gateway/deploy/f1c_issuer_set_reaches_every_stand_test.go).
// Ни один стенд ветви вывода не исполняет, и ни один профиль скалярного пина не
// задаёт.
//
// Отсюда пара, которую это изменение разрушает. Прежде утверждение было
// ПОЛОВИННЫМ: «перечень не объявлен ⇒ сегодняшняя посадка», и правдой его делал
// не код, а то, что все объявили. Теперь оно БЕЗУСЛОВНОЕ: перечень не объявлен ⇒
// ОТКАЗ В СТАРТЕ, под любой меткой окружения. Отказ виден оператору и не доходит
// до арендатора; вывод адреса был виден арендатору и не доходил до оператора.
//
// # Почему ручки снимаются, а не оставляются пустыми
//
// Ручка, которую никто не читает, — это объявление без предмета: оператор задаёт
// значение, оно принимается и не действует. Здесь этого мало: снятая ветвь была
// ЕДИНСТВЕННЫМ читателем обеих ручек, поэтому пустая ручка рядом со снятой
// ветвью — приглашение вернуть ветвь обратно «чтобы ручка заработала».
package config_test

import (
	"reflect"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/gateway/internal/config"
)

// f1dRetiredKnobs — ручки, снятые вместе с ветвью вывода.
//
// Перечислены ПОИМЁННО, а не образцом `KACHO_HYDRA_*`: образец накрыл бы и те
// ручки чужого поставщика, которые сегодня живы на каждом стенде (адрес
// интроспекции, административный адрес и якорь доверия административного хопа),
// и проба объявляла бы снятым то, что снято не было.
var f1dRetiredKnobs = map[string]string{
	"KACHO_HYDRA_ISSUER": "скалярный пин издателя: его единственным читателем была " +
		"ветвь вывода, и ни один профиль его не задаёт",
	"KACHO_HYDRA_JWKS_URL": "скалярный пин адреса набора ключей: тот же единственный " +
		"читатель и та же пустота во всех профилях",
}

// ЗДЕСЬ НЕТ `KACHO_HYDRA_JWKS_CA_FILE`, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК.
//
// Ручка несёт имя чужого поставщика, но предмет у неё НАШ: хоп за ключами едет
// сегодня к нашему зеркалу набора на внутреннем слушателе службы доступа
// (`https://kaname-internal…/.well-known/jwks.json` — так объявлено записью
// издателя у каждого боевого стенда), и связка пинит сертификат ЭТОГО адреса.
// Снять ручку значило бы вернуть ровно то состояние, ради выхода из которого её
// завели: у хопа есть ручка АДРЕСА и нет ручки ДОВЕРИЯ, поэтому «перевести хоп
// на защищённый транспорт» снова стало бы недостижимо.
//
// Задать её сегодня не может ни один профиль — `hydra.jwksCa.secretName` пуст в
// умолчании чарта края и не переопределён ни одной цепочкой, — но «возможность,
// которой пока не пользуются» и «объявление без предмета» это разные вещи:
// предмет у неё есть и он живой. Что с ней НЕ так — имя чужого продукта у нашей
// ручки (ban #2); лечится это переименованием вместе с ключом чарта и профилями,
// то есть изменением контракта настройки, а не снятием.

// TestF1d_AnUndeclaredIssuerSetRefusesTheStartUnconditionally — перечень не
// объявлен ⇒ отказ в старте, и это не зависит от метки окружения.
//
// Метки перечислены ОБЕИХ классов намеренно. Соседние стражи края терпят
// послабление под явными метками разработки (открытый HTTP к набору ключей,
// незашифрованное соединение к базе), и естественно было бы ожидать послабления
// и здесь. Его нет и быть не может: послабление означало бы «на стенде
// разработки адрес выводим», то есть ровно ту ветвь, ради снятия которой всё и
// делается.
func TestF1d_AnUndeclaredIssuerSetRefusesTheStartUnconditionally(t *testing.T) {
	t.Parallel()
	for _, env := range []string{"", "production", "production-strict", "dev", "local", "test"} {
		cfg := config.Config{AppEnv: env, APIDomain: "api.kacho.test"}
		bindings, err := cfg.TokenAcceptance()
		if err == nil {
			t.Errorf("KACHO_APP_ENV=%q: необъявленный перечень издателей ПРИНЯТ — построено "+
				"записей приёма %d (%+v).\nЭто и есть снимаемая ветвь: край поднимется, под "+
				"станет готовым, а адрес издателя будет ВЫВЕДЕН из домена установки. Хоста с "+
				"таким именем на стенде нет, поэтому каждый предъявленный токен получит отказ "+
				"при первом же запросе — без отказа старта и без красного",
				env, len(bindings), bindings)
			continue
		}
		if !strings.Contains(err.Error(), "KACHO_API_GATEWAY_TOKEN_ISSUERS") {
			t.Errorf("KACHO_APP_ENV=%q: отказ не называет ручку, которую оператору править: %v",
				env, err)
		}
	}
}

// TestF1d_ADeclaredIssuerSetStillBoots — ЗАКОННЫЙ БЛИЗНЕЦ.
//
// Без него проба выше зеленеет на разборе, отвергающем любую посадку, и «край
// требует объявления» становится неотличимо от «край не поднимается никогда».
// Против отрицательного кейса здесь меняется РОВНО ОДИН факт: перечень объявлен.
func TestF1d_ADeclaredIssuerSetStillBoots(t *testing.T) {
	t.Parallel()
	cfg := f1bFullDeclaration()
	bindings, err := cfg.TokenAcceptance()
	if err != nil {
		t.Fatalf("объявленный перечень отвергнут: %v", err)
	}
	if len(bindings) != 2 {
		t.Fatalf("записей приёма %d, ожидалось 2: %+v", len(bindings), bindings)
	}
}

// TestF1d_NoConfigFieldCarriesARetiredKnob — ручки сняты ИЗ ОБЪЯВЛЕНИЯ ПРОЦЕССА,
// а не оставлены пустыми.
//
// Утверждение о структуре читается разбором её полей, а не поиском слова по
// файлу: снятая ручка остаётся законной в прозе, объясняющей снятие, и предикат
// по слову краснел бы на этом самом комментарии.
func TestF1d_NoConfigFieldCarriesARetiredKnob(t *testing.T) {
	t.Parallel()
	rt := reflect.TypeOf(config.Config{})
	examined, tagged := 0, 0
	for i := 0; i < rt.NumField(); i++ {
		examined++
		knob, ok := rt.Field(i).Tag.Lookup("envconfig")
		if !ok {
			continue
		}
		tagged++
		if why, retired := f1dRetiredKnobs[knob]; retired {
			t.Errorf("поле %s объявляет снятую ручку %s — %s.\nОбъявление, у которого не "+
				"осталось читателя, приглашает вернуть снятую ветвь обратно «чтобы ручка "+
				"заработала»", rt.Field(i).Name, knob, why)
		}
	}
	t.Logf("перепись: полей структуры настроек осмотрено %d; из них объявляют ручку %d; "+
		"снятых ручек в перечне %d", examined, tagged, len(f1dRetiredKnobs))

	// Предпосылка. Разбор, не нашедший НИ ОДНОЙ ручки, молчал бы о любой из
	// них, и «снятых не найдено» читалось бы как «прочитано ноль полей».
	if tagged == 0 {
		t.Fatal("ни одного поля с объявлением ручки — разбор не дошёл до предмета, " +
			"и его молчание ничего не значит")
	}
}

// TestF1d_TheRetiredKnobPredicateCanFail — САМОПРОВЕРКА распознавателя выше.
//
// Строится на СИНТЕТИКЕ, а не на живой записи перечня: проба, привязанная к
// снимаемому предмету, истекает вместе с ним — перечень снятых ручек однажды
// сойдётся с деревом, и самопроверка покраснела бы на достижении своей цели.
func TestF1d_TheRetiredKnobPredicateCanFail(t *testing.T) {
	t.Parallel()
	type donor struct {
		Live     string `envconfig:"KACHO_API_GATEWAY_TOKEN_ISSUERS"`
		Retired  string `envconfig:"KACHO_HYDRA_ISSUER"`
		Untagged string
	}
	rt := reflect.TypeOf(donor{})
	found, tagged := 0, 0
	for i := 0; i < rt.NumField(); i++ {
		knob, ok := rt.Field(i).Tag.Lookup("envconfig")
		if !ok {
			continue
		}
		tagged++
		if _, retired := f1dRetiredKnobs[knob]; retired {
			found++
		}
	}
	if tagged != 2 {
		t.Fatalf("донор прочитан не весь: полей с объявлением ручки %d, ожидалось 2", tagged)
	}
	if found != 1 {
		t.Fatalf("распознаватель не отличает снятую ручку от живой: найдено %d, ожидалась 1", found)
	}
}
