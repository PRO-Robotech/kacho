// session_carrier_readers.go — ПРЕДИКАТЫ ПРИСУТСТВИЯ носителя браузерной
// сессии: один на сторону, общий для обеих полос, которые эту сессию читают.
//
// # Зачем отдельный файл, а не пара строк в каждой полосе
//
// Полос, читающих одну и ту же браузерную сессию, две: полоса личности на пути
// запроса (`auth.go`) и маршрут «кто я» (`session_identity_handler.go`). Пока
// читатель в процессе был один, их предикаты могли разойтись незаметно. В
// ПЕРЕХОДНОМ состоянии, где живы оба читателя, расхождение становится решением
// о ЛИЧНОСТИ: одна полоса считала бы запрос нашим, вторая отдавала бы его
// чужой стороне, и действующий человек зависел бы от того, какую полосу он
// задел. Предикат поэтому ОДИН на сторону, и обе полосы зовут именно его.
//
// Это утверждение О ДЕРЕВЕ, и держит его обход, а не внимание автора:
// `session_carrier_readers_gate_test.go` объявляет находкой всякое чтение имени
// носителя вне этого файла. Без обхода утверждение прожило меньше одного
// изменения — третья копия осталась в том же диффе, которым единственность
// объявлялась, и нашлась на ревью.
//
// # Почему не в файле перечня имён
//
// `session_carrier_names.go` объявляет ИМЕНА и гасит их. Читатель имени —
// другой предмет, и гейт `session_carrier_names_gate_test.go` требует у
// каждого гасимого имени читателя ВНЕ файла объявления: иначе «имя читают» и
// «имя объявили» слились бы в одно, и перечень подтверждал бы сам себя.
package middleware

import (
	"net/http"
	"strings"
)

// ourSessionCarrierOf — НАШ носитель из запроса и признак его присутствия.
//
// ОДИН предикат на обе полосы, читающие эту сессию (полоса личности и маршрут
// «кто я»), и это несущее: в переходном состоянии, где жив и чужой читатель,
// расхождение предикатов означало бы, что одна полоса считает запрос нашим, а
// вторая отдаёт его чужой стороне, — то есть личность действующего зависела бы
// от того, какую полосу он задел.
//
// Печенье с ПУСТЫМ значением носителем не является: пустая строка не
// идентифицирует сессию, а браузер оставляет такое печенье после гашения
// соседним путём.
func ourSessionCarrierOf(r *http.Request) (string, bool) {
	c, err := r.Cookie(OurSessionCarrierName)
	if err != nil || c.Value == "" {
		return "", false
	}
	return c.Value, true
}

// providerSessionCarrierPresented — предъявлен ли носитель ЧУЖОЙ стороны.
// Тот же один предикат на обе полосы и по той же причине.
func providerSessionCarrierPresented(r *http.Request) bool {
	return strings.Contains(r.Header.Get("Cookie"), providerSessionCarrierName)
}
