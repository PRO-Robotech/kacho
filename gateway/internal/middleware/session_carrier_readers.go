// session_carrier_readers.go — ПРЕДИКАТЫ ПРИСУТСТВИЯ носителя браузерной
// сессии: один на сторону, общий для обеих полос, которые эту сессию читают.
//
// # Зачем отдельный файл, а не пара строк в каждой полосе
//
// Полос, читающих одну и ту же браузерную сессию, две: полоса личности на пути
// запроса (`auth.go`) и маршрут «кто я» (`session_identity_handler.go`). Их
// предикаты могли бы разойтись незаметно — и расхождение стало бы решением о
// ЛИЧНОСТИ: одна полоса считала бы запрос сессией, вторая нет, и действующий
// человек зависел бы от того, какую полосу он задел. Предикат поэтому ОДИН, и
// обе полосы зовут именно его.
//
// Это утверждение О ДЕРЕВЕ, и держит его обход, а не внимание автора:
// `session_carrier_readers_gate_test.go` объявляет находкой всякое чтение имени
// носителя В ПАКЕТЕ ПОЛОС вне этого файла. Без обхода утверждение прожило
// меньше одного изменения — третья копия осталась в том же диффе, которым
// единственность объявлялась, и нашлась на ревью.
//
// ОБЛАСТЬ НАЗВАНА ТОЧНО, И ЭТО НЕ ОГОВОРКА МЕЛКИМ ШРИФТОМ. Прежняя редакция
// говорила «вне этого файла», а обход шёл по одному каталогу — объявление было
// ШИРЕ исполняемого, и «вне дома — 0» печаталось о знаменателе, поставленном
// так, чтобы ноль получился.
//
// Почему область именно такая: предмет — расхождение ДВУХ ПОЛОС, читающих одну
// сессию, и обе живут здесь. Вне пакета имя встречается в другом качестве:
// чужой код НАЗЫВАЕТ его — в тексте отказа старта, в обходе перечня гасимых, —
// и читателем носителя от этого не становится. Запрет на такое называние был
// бы запретом объяснять оператору, о каком печенье речь.
//
// # Почему не в файле перечня имён
//
// `session_carrier_names.go` объявляет ИМЕНА и гасит их. Читатель имени —
// другой предмет, и гейт `session_carrier_names_gate_test.go` требует у
// каждого гасимого имени читателя ВНЕ файла объявления: иначе «имя читают» и
// «имя объявили» слились бы в одно, и перечень подтверждал бы сам себя.
package middleware

import "net/http"

// ourSessionCarrierOf — НАШ носитель из запроса и признак его присутствия.
//
// ОДИН предикат на обе полосы, читающие эту сессию (полоса личности и маршрут
// «кто я»), и это несущее: расхождение предикатов означало бы, что личность
// действующего зависит от того, какую полосу он задел.
//
// Печенье с ПУСТЫМ значением носителем не является: пустая строка не
// идентифицирует сессию, а браузер оставляет такое печенье после гашения
// соседним путём.
func ourSessionCarrierOf(r *http.Request) (string, bool) {
	c, err := r.Cookie(OurSessionCarrierName)
	if err != nil || c.Value == "" {
		return "", false
	}
	return c.Value, true
}
