// TestRoleGetIsScopeFilteredNotExempt — чтение одной роли стоит на полосе
// сужения по данным, а не на освобождении.
//
// # Предмет (#973)
//
// Запись каталога объявляла `<exempt>` с причиной «решение принимает сервис
// своим Check». Решения не принимал никто: каталог ролей читает любой
// аутентифицированный, а сужение по вызывающему делает обработчик на данных —
// тем же предикатом, что страница.
//
// Причина, названная неверно, — не придирка к слову: по ней читают, что у RPC
// есть свой гейт, которого нет. Плюс у освобождения есть ВТОРОЙ смысл, к
// предмету отношения не имеющий: оно допускает вызов внутреннего слушателя
// вообще без принципала — а сужать тогда становится не по кому.
//
// # Что утверждается
//
// Пара: запись НЕ освобождённая — И она несёт настоящее имя права. Проверка
// одной половины зеленела бы на записи с пустым правом, то есть на «гейт есть,
// но неизвестно какой».
func TestRoleGetIsScopeFilteredNotExempt(t *testing.T) {
	cat, err := LoadEmbeddedPermissionCatalog("")
	if err != nil {
		t.Fatalf("каталог прав не прочитан: %v", err)
	}

	const fqn = "kaname.cloud.iam.v1.RoleService/Get"
	entry, ok := cat.Lookup(fqn)
	if !ok {
		t.Fatalf("%s не найден в каталоге — запись пропала вместе с гейтом", fqn)
	}

	if entry.IsExempt() {
		t.Errorf("%s объявлен освобождённым: сужение по вызывающему становится невозможным "+
			"на внутреннем слушателе, где принципала может не быть вовсе", fqn)
	}
	if !entry.ScopeFiltered {
		t.Errorf("%s не объявлен сужаемым по данным — край не узнает, что решение принимает "+
			"обработчик, и потребует объекта, которого у этого чтения нет", fqn)
	}
	if entry.Permission != "iam.roles.get" {
		t.Errorf("%s несёт право %q, ожидалось iam.roles.get — запись без настоящего имени "+
			"читается как «гейт есть», не говоря какой", fqn, entry.Permission)
	}

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ полосы: список ролей стоит на ней же и с самого
	// начала. Без него проба зеленела бы на каталоге, где сужаемым объявлено
	// всё подряд, — то есть на снятии гейтов, а не на их уточнении.
	listEntry, ok := cat.Lookup("kaname.cloud.iam.v1.RoleService/List")
	if !ok {
		t.Fatal("RoleService/List не найден — контроль полосы беспредметен")
	}
	if !listEntry.ScopeFiltered || listEntry.IsExempt() {
		t.Errorf("RoleService/List перестал быть сужаемым по данным (exempt=%v, filtered=%v) — "+
			"контроль показывает, что изменилась ПОЛОСА, а не одна запись",
			listEntry.IsExempt(), listEntry.ScopeFiltered)
	}

	// ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: освобождения в каталоге ЕСТЬ и остаются законными
	// там, где у них предмет. Проба, требующая «ни одного освобождения», ловила
	// бы форму, а не существо.
	//
	// Перепись идёт по встроенному тексту каталога: у типа нет обхода записей,
	// а заводить его ради одной пробы значило бы расширять поверхность ради
	// удобства проверки.
	raw := EmbeddedPermissionCatalogJSON()
	total := strings.Count(string(raw), `"fqn"`)
	exempt := strings.Count(string(raw), `"exempt_reason": "`) - strings.Count(string(raw), `"exempt_reason": ""`)
	t.Logf("перепись: записей каталога %d; из них освобождённых %d", total, exempt)
	if total == 0 {
		t.Fatal("записей в каталоге ноль — перепись читает не то, и «ноль освобождений» ничего не значит")
	}
	if exempt == 0 {
		t.Fatal("освобождений ноль — либо их снесли скопом, либо изменилась форма записи")
	}
}
