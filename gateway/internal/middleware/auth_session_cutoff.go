// auth_session_cutoff.go — наш отзыв, спрошенный на БРАУЗЕРНОЙ полосе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// На момент этой правки у края было две полосы личности человека, и это было
// сказано в шапке `HTTP`: сессия развёрнутого провайдера (cookie) и подписанный
// предъявитель (`Authorization`). Третья — базовое удостоверение — появилась
// позже (#1142); про отзыв она спрашивает своим механизмом, окном вердикта
// авторитета (`BasicCredentialVerdictWindow`), а не этим. Полоса предъявителя спрашивает про отзыв — свой и чужой
// (`auth_revocation.go`). Полоса cookie не спрашивала НИЧЕГО.
//
// Разница между ними никем не решалась. Обоснование, стоявшее в шапке соседнего
// файла, звучало так: сессия перепроверяется у провайдера на каждом запросе,
// поэтому отдельный вопрос про отзыв ей не нужен. Про отзывы САМОГО провайдера
// это верно. Про запись, которую делает НАШ глагол — выход человека и
// административный принудительный выход, — неверно и не может быть верным: тот,
// у кого спрашивают про сессию, о нашей записи не знает by construction.
//
// Следствие наблюдаемое: администратор, выполнивший принудительный выход,
// получал успех, а человек продолжал работать в консоли — его личность на этой
// полосе не резолвится через предъявителя, и ни один читатель нашей отсечки на
// его пути не стоял.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО СПРАШИВАЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО
//
// У браузерной сессии нет удостоверения: ни `jti`, ни подписи, которую край мог
// бы прочитать. Спросить про неё можно только по СУБЪЕКТУ и по моменту, в
// который она аутентифицировалась. Это ровно та пара, которой оперирует наша
// отсечка (`user_token_revocations.revoke_before`) и которой уже пользуются хуки
// выдачи: «сессия, аутентифицировавшаяся в этот момент или раньше,
// недействительна».
//
// Отсечка действует ВПЕРЁД. Аутентифицировавшаяся позже — законна, поэтому
// человек, войдя заново, работает; отзыв снимает выданное, а не блокирует
// принципала навсегда.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТКАЗ ЗАКАНЧИВАЕТ НОСИТЕЛЯ, А НЕ ТОЛЬКО ОТВЕЧАЕТ 401
//
// Отсечка держится без чужого содействия, и это её сильная сторона. Слабая —
// сама по себе она даёт СТОЯЩИЙ ОТКАЗ: носитель жив, момент аутентификации у
// него прежний, и он будет отвергаться при каждом обращении, а повторной
// аутентификации ничто не запрашивает. Выходом такое состояние не является.
//
// Прежде обратимость покупалась вызовом к поставщику — снятием сессии входа на
// его стороне. Мера была чужой, требовала его административного API и, как
// измерено, выданный токен всё равно не гасила. Здесь обратимость делается
// НАШИМ действием на нашей же стороне: отвергая носителя, край его и
// заканчивает — гасит cookie. Следующее обращение приходит без сессии, консоль
// уводит человека на вход, момент аутентификации сдвигается за отсечку, доступ
// возвращается.
//
// Отличать надо два исхода, и они лечатся противоположно: «отозван» —
// определённый ответ, носителя заканчиваем; «авторитет не ответил» — отказ без
// окончания носителя, потому что гасить чужую живую сессию из-за своей заминки
// значило бы выкидывать всех при первом же перебое.
package middleware

import (
	"context"
	"errors"
	"net/http"
	"time"
)

// ErrSessionCutoffUnsupported — авторитет ЖИВ, но такого вопроса не предлагает.
//
// ЭТО ТРЕТЬЕ СОСТОЯНИЕ, и слитое с «не ответил» оно стоило бы простоя консоли.
// Раскат не атомарен: реплика края поднимается раньше, чем докатится служба
// прав, и в этом окне она отвечает «метода нет». Считать это отказом значит
// отвергнуть КАЖДУЮ браузерную сессию на всё окно раската — авария, а не
// ужесточение; при том что состояние сходится само, без чьего-либо участия.
//
// От неисправности настройки оно отличается предикатом: расхождение версий
// исчезает от раската, а неверный адрес не исчезает никогда. Поэтому здесь
// проход — но ГРОМКИЙ и со своим счётчиком: «контроль не исполнился» обязано
// быть видно, иначе застрявшее расхождение версий тихо оставит полосу без
// проверки.
//
// Ставит его АДАПТЕР (gateway/internal/clients): знание о кодах транспорта
// принадлежит ему, а не этому слою.
var ErrSessionCutoffUnsupported = errors.New("session cutoff: authority does not offer this question")

// SessionCutoffReader — порт НАШЕГО авторитета отзыва, спрошенного ПРО СУБЪЕКТА.
//
// Реализуется адаптером над `InternalSessionRevocationsService.SessionCutoffOf`
// на внутреннем слушателе службы прав. Порт объявлен здесь, чтобы полоса
// проверялась без поднятого соседа.
//
// Три исхода несёт ПАРА возвращаемых значений вместе с ошибкой, а не одно
// значение: «отсечки нет» и «спросить не удалось» — разные состояния, и
// вызывающий обязан их различать. Слитые в одно, они дали бы либо мягкий проход
// на молчащем авторитете, либо отказ каждому, кого никто не отзывал.
type SessionCutoffReader interface {
	SessionCutoffOf(ctx context.Context, userID string) (cutoff time.Time, found bool, err error)
}

// sessionCutoffVerdict — четыре ответа полосы. Разные исходы держатся врозь
// потому, что читателю журнала они говорят разное: не спрашивали ·
// спросили-и-годно · отозван · спросить не удалось.
type sessionCutoffVerdict int

const (
	// sessionCutoffNotAsked — читатель не провязан либо у сессии нет пары
	// (субъект, момент), по которой можно спросить. Запрос идёт дальше, и об
	// этом сообщается: «контроль не исполнился» никогда не выглядит как
	// «контроль прошёл».
	sessionCutoffNotAsked sessionCutoffVerdict = iota
	// sessionCutoffLive — спросили, сессия моложе отсечки либо отсечки нет.
	sessionCutoffLive
	// sessionCutoffEnded — спросили, сессия аутентифицировалась в момент отсечки
	// или раньше. Отвергаем И заканчиваем носителя.
	sessionCutoffEnded
	// sessionCutoffUnanswered — наш авторитет не ответил. Отвергаем, носителя НЕ
	// заканчиваем.
	sessionCutoffUnanswered
	// sessionCutoffUnsupported — авторитет жив и такого вопроса не предлагает
	// (окно раската). Проходим, громко. См. ErrSessionCutoffUnsupported.
	sessionCutoffUnsupported
)

// sessionCutoffDenyDescription — что видит клиент на отвергнутой сессии.
// Называет состояние ЕГО СОБСТВЕННОЙ сессии и ничего про чужие, поэтому
// оракулом не является; говорит «войди заново», а не «повтори».
const sessionCutoffDenyDescription = "session ended; sign in again"

// sessionCutoffUnavailableReason — что видит клиент, когда спросить не удалось.
// Намеренно тонкое: какой именно адрес этого развёртывания молчит — дело
// оператора, и оно идёт в журнал, а не на провод.
const sessionCutoffUnavailableReason = "session revocation check unavailable"

// WithSessionCutoffCheck — провязывает читателя нашей отсечки на браузерную
// полосу. nil оставляет полосу непровязанной.
//
// reportInterval ограничивает, как часто повторяется доклад о неотвечающем
// авторитете; ноль берёт умолчание. Счётчик СВОЙ, не общий с полосой
// предъявителя: «наш авторитет молчит для браузерной сессии» и «он молчит для
// предъявителя» суть один авторитет, но разные читатели и разные последствия,
// и слитое окно дало бы всплеск одного, подавляющий первый доклад другого.
func (a *AuthInterceptor) WithSessionCutoffCheck(r SessionCutoffReader, reportInterval time.Duration) *AuthInterceptor {
	if r == nil {
		return a
	}
	a.sessionCutoff = r
	a.sessionCutoffFailures = newIntrospectionFailureReporter(reportInterval, nil)
	return a
}

// endSessionCarrier заканчивает носителя браузерной сессии.
//
// Тот же набор имён и та же форма, что у выхода (`handler.LogoutHandler`), —
// одно место продукта гасит cookie одним способом, иначе «выход» и «отказ»
// оставляли бы разное состояние у одного и того же браузера.
func endSessionCarrier(w http.ResponseWriter) {
	for _, c := range []string{"ory_kratos_session"} {
		http.SetCookie(w, &http.Cookie{
			Name:     c,
			Value:    "",
			Path:     "/",
			MaxAge:   -1,
			HttpOnly: true,
			Secure:   true,
			SameSite: http.SameSiteLaxMode,
		})
	}
}

// sessionCutoffCheck спрашивает НАШ авторитет про сессию и докладывает вердикт,
// беря на себя доклад о неотвечающем авторитете (с ограничением частоты и
// нарастающим итогом) — чтобы «контроль не исполнился» никогда не выглядело как
// «контроль прошёл».
//
// route — только контекст журнала; вердикта он не меняет.
func (a *AuthInterceptor) sessionCutoffCheck(
	ctx context.Context, subj Subject, sess KratosWhoamiResult, route string,
) sessionCutoffVerdict {
	if a.sessionCutoff == nil {
		return sessionCutoffNotAsked
	}
	// Отсечка ключуется человеком. Личность другого вида на этой полосе не
	// появляется, и спрашивать про неё по словарю людей значило бы задавать
	// вопрос про субъекта, которого в таблице не бывает.
	if subj.Type != "user" || subj.ID == "" {
		return sessionCutoffNotAsked
	}

	cutoff, found, err := a.sessionCutoff.SessionCutoffOf(ctx, subj.ID)
	if errors.Is(err, ErrSessionCutoffUnsupported) {
		// Окно раската: край впереди службы прав. Проходим — но громко, и со
		// своим счётчиком, чтобы застрявшее расхождение версий не оставило
		// полосу без проверки молча.
		if report, total, represents := a.sessionCutoffFailures.observe(); report {
			a.logger.Error("session revocation not enforced on the browser lane: "+
				"the authority does not offer this question (image skew)",
				"route", route,
				"session_cutoff_unsupported_total", total,
				"occurrences_since_last_report", represents,
				"predicate", "исчезает, когда служба прав докатится до того же дерева")
		}
		return sessionCutoffUnsupported
	}
	if err != nil {
		// Авторитет НАШ, и молчит он тогда же, когда край и так отказывает по
		// правам. Мягкий проход здесь означал бы: отзываем и свой же отзыв не
		// исполняем — ровно тот класс, где контроль действует на выдаче и не
		// действует на предъявлении.
		if report, total, represents := a.sessionCutoffFailures.observe(); report {
			a.logger.Error("session revocation check unanswered; refusing browser session",
				"err", err, "route", route,
				"session_cutoff_failures_total", total,
				"occurrences_since_last_report", represents)
		}
		return sessionCutoffUnanswered
	}
	if !found {
		// Пустой ответ означает ПУСТО. Человек, которого никто не отзывал,
		// работает.
		return sessionCutoffLive
	}
	if sess.AuthenticatedAt.IsZero() {
		// Отсечка есть, а сравнивать не с чем: провайдер момента не назвал.
		// Пропустить — значит дать обходить отзыв ОТСУТСТВИЕМ поля в чужом
		// ответе. Та же посадка принята хуком обновления, где «нет момента ⇒
		// отказ» действует давно.
		//
		// Носителя при этом гасим: состояние определённое (отсечка есть, доказать
		// её непревышение нечем), и стоящий отказ здесь был бы таким же тупиком.
		if report, total, represents := a.sessionCutoffFailures.observe(); report {
			a.logger.Error("browser session carries no authentication instant while a cutoff stands",
				"route", route,
				"session_cutoff_failures_total", total,
				"occurrences_since_last_report", represents)
		}
		return sessionCutoffEnded
	}
	// Отсечка действует ВПЕРЁД и включает свой момент: аутентифицировавшаяся
	// РОВНО в него сессия недействительна. Иначе принудительный выход,
	// совпавший по метке с входом, не подействовал бы — а совпадают они тем
	// чаще, чем грубее разрешение метки времени у хранилища.
	if sess.AuthenticatedAt.After(cutoff) {
		return sessionCutoffLive
	}
	return sessionCutoffEnded
}
