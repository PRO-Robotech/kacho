// session_carrier_names.go — ЕДИНСТВЕННОЕ объявление имён носителя браузерной
// сессии, которые край гасит (F4d-26, приёмка Ф3 §4.1 п.9).
//
// # Предмет
//
// Носитель гасится в двух местах: отказом F4d-22 на полосе личности
// (`auth.go`) и обработчиком выхода (`handler/logout_handler.go`). До Ф3 имя
// носителя стояло литералом в обоих — два перечня об одном предмете, и наше имя
// не значилось ни в одном. Второй перечень расходится с первым молча: имя,
// добавленное сюда и забытое там, гасится отказом и переживает выход.
//
// # Два имени, и у каждого свой читатель
//
//   - [OurSessionCarrierName] — печенье НАШЕЙ сессии (Ф3 Р3); читает полоса
//     личности (`tryOwnSession`) и маршрут «кто я»;
//   - [providerSessionCarrierName] — печенье прежнего поставщика; читает полоса
//     (`tryKratosSession`) и тот же маршрут — до S3 (`kacho#1276`), когда
//     читатель снимается и имя становится находкой гейта.
//
// Какие из этих читателей провязаны — решение ПРОФИЛЯ
// (`config.SessionCarrierSet`, ручка `KACHO_API_GATEWAY_SESSION_CARRIERS`), и
// состояний три: только чужой · ОБА · только наш. Среднее — переходное: оно
// существует ради того, чтобы перевод стенда с людьми не отнимал вход у
// каждого, чья чужая сессия жива.
//
// # Гашение НЕ зависит от того, кто провязан
//
// [EndSessionCarriers] гасит ОБА имени во всех трёх состояниях. Иначе выход,
// произошедший в состоянии «только наш», оставлял бы у браузера целое чужое
// печенье — а оно станет носителем снова, стоит откатить профиль на одно
// состояние назад.
//
// Гейт `session_carrier_names_gate_test.go` требует у каждого имени
// ПРОИЗВОДИТЕЛЯ — читателя на пути аутентификации — и объявляет второе
// объявление любого из имён находкой: имя, которое гасят и никто не читает, есть
// печенье, стёртое у клиента без основания.
package middleware

import "net/http"

// OurSessionCarrierName — имя печенья нашей сессии человека, выданной службой
// (Ф3 Р3). Значение непрозрачно для края: он передаёт его службе как есть и
// ничего из него не читает.
const OurSessionCarrierName = "kaname_session"

// providerSessionCarrierName — имя печенья сессии прежнего поставщика
// удостоверений. Читается, пока профиль называет чужую сторону в множестве
// читателей.
const providerSessionCarrierName = "ory_kratos_session"

// sessionCarrierNames — перечень гасимых имён. Элементы — константы выше, не
// литералы: гейт связывает каждое имя с его читателем по идентификатору.
var sessionCarrierNames = []string{OurSessionCarrierName, providerSessionCarrierName}

// SessionCarrierNames отдаёт КОПИЮ перечня — читателям, которым нужен состав, а
// не действие (пробы, самоотчёт). Правка копии перечня не меняет.
func SessionCarrierNames() []string {
	out := make([]string, len(sessionCarrierNames))
	copy(out, sessionCarrierNames)
	return out
}

// EndSessionCarriers заканчивает носитель браузерной сессии — по ВСЕМУ перечню
// и одной формой.
//
// Одно место продукта ПРОИЗВОДИТ гашение: путь отказа F4d-22, обработчик
// выхода и ответ глагола выхода на ретрансляции берут печенья у
// [SessionCarrierEndings], иначе «выход» и «отказ» оставляли бы у одного и того
// же браузера разное состояние — а расхождение атрибутов молчит: браузер не
// сопоставит гашение с чужим путём, и «выйти» оставит человека вошедшим. Атрибуты те же, что у выдачи
// (Ф1 §4.1: `Path=/`, `HttpOnly`, `Secure`, `SameSite=Lax`): браузер сопоставляет
// печенье по имени, пути и домену, и гашение с другим путём не нашло бы его.
func EndSessionCarriers(w http.ResponseWriter) {
	for _, c := range SessionCarrierEndings() {
		http.SetCookie(w, c)
	}
}

// SessionCarrierEndings — ГАСЯЩИЕ ПЕЧЕНЬЯ по всему перечню, по одному на имя.
//
// ЕДИНСТВЕННЫЙ производитель атрибутов гашения. Мест, откуда носитель гасится,
// больше одного — путь отказа полосы, обработчик выхода и ответ глагола выхода
// на ретрансляции, — и собирать атрибуты в каждом значило бы держать их
// совпадение ВНИМАНИЕМ автора. Расхождение при этом молчит: браузер
// сопоставляет печенье по имени, пути и домену, и гашение с другим путём его
// не находит — «выйти» оставляет человека вошедшим, и ни одна проверка знака
// срока этого не видит.
//
// Отдаются СВЕЖИЕ значения на каждый вызов: вызывающий вправе их дополнять
// (ретранслятор пропускает имена, которые служба погасила сама), и общий
// экземпляр он бы менял всем.
//
// Атрибуты те же, что у выдачи (Ф1 §4.1): `Path=/`, `HttpOnly`, `Secure`,
// `SameSite=Lax`.
func SessionCarrierEndings() []*http.Cookie {
	out := make([]*http.Cookie, 0, len(sessionCarrierNames))
	for _, name := range sessionCarrierNames {
		out = append(out, &http.Cookie{
			Name:     name,
			Value:    "",
			Path:     "/",
			MaxAge:   -1,
			HttpOnly: true,
			Secure:   true,
			SameSite: http.SameSiteLaxMode,
		})
	}
	return out
}
