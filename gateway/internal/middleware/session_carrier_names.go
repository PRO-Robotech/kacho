// session_carrier_names.go — ЕДИНСТВЕННОЕ объявление имён носителя браузерной
// сессии, которые край гасит (F4d-26, приёмка Ф3 §4.1 п.9).
//
// # Предмет
//
// Край гасит носитель в одном месте — отказом F4d-22 на полосе личности
// (`auth_own_session.go`). Выход сессии гасит его служба (`POST
// /iam/v1/auth/logout`, край ретранслирует ответ с её `Set-Cookie`); выход пути
// токенов (`handler/logout_handler.go`) печенье сессии не гасит вовсе: гашение у
// клиента без конца сессии на сервере есть «вышли» при живой сессии (kacho#2959,
// Ф3 Р4). До Ф3 имя носителя стояло литералом в двух местах края — два перечня об
// одном предмете, и наше имя не значилось ни в одном; перечень здесь один.
//
// # Имя одно, и у него один читатель
//
// [OurSessionCarrierName] — печенье НАШЕЙ сессии (Ф3 Р3); читает полоса
// личности (`tryOwnSession`) и маршрут «кто я». Второе имя — печенье прежнего
// поставщика — снято вместе с его читателем (#2792): имя, которое гасят и никто
// не читает, есть печенье, стёртое у клиента без основания, а там, где чужая
// сторона ставила печенью `Domain`, гашение края с ним не совпадало вовсе и
// отказ по отсечке становился стоящим.
//
// # Совпадение гашения зависит от `Domain`
//
// Выдать гашение и закрыть им печенье — не одно и то же: браузер сопоставляет
// печенье по имени, пути и домену. Домен печенья выбирает служба настройкой
// `authn.login.cookie-domain` (слово `none` — только на хост), и гашение края
// обязано идти с тем же доменом: гашение без `Domain` печенье, выданное С
// доменом, не закрывает, и отказ по отсечке остаётся стоящим (kacho#3174).
// Поэтому домен у края — своя ручка того же значения,
// `KACHO_API_GATEWAY_SESSION_COOKIE_DOMAIN` (`config.SessionCookieDomain`):
// пусто либо `none` у службы — пусто у края. Согласие двух величин на каждом
// стенде держит проба отрисовки `gateway/deploy/session_cookie_domain_render_test.go`;
// что гашение совпадает с выдачей, и браузер печенье удаляет, —
// `session_carrier_domain_test.go`.
//
// Гейт `session_carrier_names_gate_test.go` требует у каждого имени
// ПРОИЗВОДИТЕЛЯ — читателя на пути аутентификации — и объявляет второе
// объявление любого из имён находкой: имя, которое гасят и никто не читает, есть
// печенье, стёртое у клиента без основания.
package middleware

import "net/http"

// OurSessionCarrierName — имя печенья нашей сессии человека, выданной службой
// (Ф3 Р3). Значение непрозрачно для края: он передаёт его службе как есть и
// ничего из него не читает.
const OurSessionCarrierName = "kaname_session"

// sessionCarrierNames — перечень гасимых имён. Элементы — константы выше, не
// литералы: гейт связывает каждое имя с его читателем по идентификатору.
var sessionCarrierNames = []string{OurSessionCarrierName}

// SessionCarrierNames отдаёт КОПИЮ перечня — читателям, которым нужен состав, а
// не действие (пробы, самоотчёт). Правка копии перечня не меняет.
func SessionCarrierNames() []string {
	out := make([]string, len(sessionCarrierNames))
	copy(out, sessionCarrierNames)
	return out
}

// EndSessionCarriers заканчивает носитель браузерной сессии — по перечню и одной
// формой.
//
// Одно место края ПРОИЗВОДИТ гашение: путь отказа F4d-22 берёт печенья у
// [SessionCarrierEndings]; атрибуты совпадают с выдачей службы, иначе «выход»
// службы и «отказ» края оставляли бы у одного и того же браузера разное
// состояние — а расхождение атрибутов молчит: браузер не сопоставит гашение с
// чужим путём, и «выйти» оставит человека вошедшим.
//
// Атрибуты те же, что у выдачи НАШЕГО печенья (Ф1 §4.1: `Path=/`, `HttpOnly`,
// `Secure`, `SameSite=Lax`, `Domain` = домен печенья службы): браузер
// сопоставляет печенье по имени, пути и домену, и гашение с другим путём или
// доменом не нашло бы его.
func EndSessionCarriers(w http.ResponseWriter, domain string) {
	for _, c := range SessionCarrierEndings(domain) {
		http.SetCookie(w, c)
	}
}

// SessionCarrierEndings — ГАСЯЩИЕ ПЕЧЕНЬЯ по всему перечню, по одному на имя.
//
// ЕДИНСТВЕННЫЙ производитель атрибутов гашения: у отказа полосы и у сквозных
// проб, сличающих ответ, атрибуты одни, и собирать их в каждом месте значило бы
// держать их совпадение ВНИМАНИЕМ автора. Расхождение при этом молчит: браузер
// сопоставляет печенье по имени, пути и домену, и гашение с другим путём его
// не находит — «выйти» оставляет человека вошедшим, и ни одна проверка знака
// срока этого не видит.
//
// Отдаются СВЕЖИЕ значения на каждый вызов: общий экземпляр вызывающий,
// правящий свою копию, менял бы всем.
//
// Атрибуты те же, что у выдачи нашего печенья (Ф1 §4.1): `Path=/`, `HttpOnly`,
// `Secure`, `SameSite=Lax`; `Domain` — domain, тот же, с каким печенье выдаёт
// служба (пусто — только на хост; шапка файла).
func SessionCarrierEndings(domain string) []*http.Cookie {
	out := make([]*http.Cookie, 0, len(sessionCarrierNames))
	for _, name := range sessionCarrierNames {
		out = append(out, &http.Cookie{
			Name:     name,
			Value:    "",
			Path:     "/",
			Domain:   domain,
			MaxAge:   -1,
			HttpOnly: true,
			Secure:   true,
			SameSite: http.SameSiteLaxMode,
		})
	}
	return out
}

// WithSessionCookieDomain — домен, с которым служба выдаёт печенье нашей
// сессии (kacho#3174): гашение края на отказе полосы идёт с ним. Пусто — только
// на хост. Значение разобрано и проверено конфигурацией
// (`config.ParseSessionCookieDomain`); здесь оно не переразбирается.
func (a *AuthInterceptor) WithSessionCookieDomain(d string) *AuthInterceptor {
	a.sessionCookieDomain = d
	return a
}
