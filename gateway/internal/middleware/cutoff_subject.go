package middleware

// cutoff_subject.go — параметр вопроса об отсечке выражен ТИПОМ (kacho#2760 п. 2).
//
// Отсечка ключуется ЧЕЛОВЕКОМ (`user_token_revocations` по субъекту-человеку).
// Пока параметр порта был свободной строкой, он принимал любое значение любого
// происхождения: идентификатор машинной учётки, пустую строку, чужой вид
// идентификатора — и такая подстановка обнаруживалась только опытом, вопросом про
// субъекта, которого в таблице не бывает. Единственность места сборки держалась
// комментарием («один читатель отсечки»), а комментарий не гейт.
//
// Теперь вопрос задаётся значением `CutoffSubject`, которое собирает ОДИН
// конструктор и только для человека с идентификатором. Код, передающий в порт
// строку, не компилируется; нулевое значение идентификатора не несёт, и адаптер
// на него отказывает, а не спрашивает.

// CutoffSubject — субъект вопроса об отсечке: человек с идентификатором.
type CutoffSubject struct {
	userID string
}

// NewCutoffSubject — единственный конструктор. ok=false — субъект вопроса об
// отсечке не порождает: не человек либо без идентификатора.
func NewCutoffSubject(principalType, id string) (CutoffSubject, bool) {
	if principalType != "user" || id == "" {
		return CutoffSubject{}, false
	}
	return CutoffSubject{userID: id}, true
}

// UserID — идентификатор человека; пусто у нулевого значения.
func (s CutoffSubject) UserID() string { return s.userID }
