// auth_session_stepup.go — пол ступенчатой аутентификации, спрошенный на
// БРАУЗЕРНОЙ полосе (#1201).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// У этого края две полосы личности человека (см. шапку `AuthInterceptor.HTTP`):
// сессия развёрнутого провайдера (cookie) и подписанный предъявитель
// (`Authorization`). Пол, объявленный каталогом прав (`required_acr_min`),
// спрашивала ТОЛЬКО вторая. Первая до его вычисления не доходила вовсе и при
// этом подавляла вторую: резолвившаяся сессия терминальна.
//
// Разницу никто не решал — она возникла как побочный эффект. Класс тот же, что
// у отсечки сессии по соседству (`auth_session_cutoff.go`): параллельные полосы
// одного механизма, разошедшиеся без чьего-либо решения. Обе валидны по
// отдельности; неверна их РАЗНИЦА.
//
// Наблюдаемое следствие: действие, которому каталог объявил пол уровня «2»,
// из браузера выполнялось БЕЗ предъявления второго фактора — браузер ходит по
// сессии, а на этой полосе пол не спрашивался.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТОГО НЕЛЬЗЯ БЫЛО ПОЧИНИТЬ ОДНИМ ВЫЗОВОМ
//
// Полоса сессии не смогла бы вычислить пол, даже если бы его спросила: у неё не
// было ВХОДА решения. Край не разбирал уровень уверенности провайдера вовсе —
// поля не было в разбираемой форме сессии, и во всём не-тестовом дереве края
// не было ни одного его упоминания. Контроль без производителя входа — не
// строгий контроль, а непрочитанный (`security.md` §Hardening инв. 8-9).
//
// Поэтому починка — пара: провайдер СПРАШИВАЕТСЯ про уровень
// (`kratos_session.go`), и уровень ПЕРЕВОДИТСЯ на ось каталога здесь.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕРАСПОЗНАННЫЙ УРОВЕНЬ — ОТКАЗ, А НЕ ПРОХОД
//
// Мягкий проход дал бы ровно тот контроль, который не отказал НИ РАЗУ за свою
// жизнь: он присутствует, провязан, исполняется на каждом запросе — и не
// отвергает ничего. Такой исход неотличим от отсутствия контроля и живёт
// вечно, потому что «работает» и «не проверяет» выглядят одинаково.
//
// Отсутствующий, пустой и незнакомый уровень дают ОДНО значение на оси —
// пустую строку, — и общее правило (`grpcsrv.ACRRank`) ранжирует её нулём:
// положительного пола она не удовлетворяет, нулевого не касается. То есть
// обычная работа с ресурсами не ломается, а поднятый пол не обходится
// ОТСУТСТВИЕМ поля в чужом ответе. Та же посадка принята отсечкой сессии, где
// «нет момента ⇒ отказ» действует давно.
//
// Состояние при этом ГРОМКОЕ и со своим счётчиком: провайдер, не называющий
// уровня, — это НАСТРОЙКА, а не заминка, и она не исчезает сама.
package middleware

import (
	"strings"
)

// acrFromAssuranceLevel переводит уровень уверенности провайдера сессий на ось
// каталога прав.
//
// Лестница НЕ изобретается здесь: она объявлена нормативно в `pkg/grpcsrv/acr.go`
// и объявлена ИМЕННО в терминах AAL —
//
//	"" / "0" (anonymous) < "1" (password-only, AAL1) <
//	"2" (phishing-resistant / MFA, AAL2) < "3" (hardware-bound UV passkey, AAL3)
//
// — поэтому перевод есть сопоставление словаря провайдера с уже записанной
// лестницей, а не второе мнение о ней. Второго сопоставления AAL→acr в дереве
// нет: хуки выдачи читают готовый OIDC-claim `acr`, а не уровень сессии.
//
// Регистр и обрамляющие пробелы нормализуются: `AAL2` и `aal2` называют одну
// ступень, и отвергать по написанию значило бы отвергать по косметике.
// Расширять эту снисходительность на неизвестные значения нельзя — см. шапку.
//
// recognized=false означает «мы не знаем, что это» — ни низкий уровень, ни
// высокий. Вызывающий обязан различать его отдельно и доложить о нём.
func acrFromAssuranceLevel(level string) (acr string, recognized bool) {
	switch strings.ToLower(strings.TrimSpace(level)) {
	case "aal0":
		return "0", true
	case "aal1":
		return "1", true
	case "aal2":
		return "2", true
	case "aal3":
		// Ступень объявлена словарём провайдера и названа лестницей выше.
		// Не переводить её значило бы отвергать САМУЮ СИЛЬНУЮ аутентификацию
		// везде, где объявлен пол, — отказ безопасный, но неверный, и выглядел
		// бы он дефектом продукта.
		return "3", true
	default:
		return "", false
	}
}

// sessionAssurance строит вход пола из ответа провайдера сессий и резолвленного
// субъекта — и докладывает, если уровня назвать не смогли.
//
// Тип принципала передаётся ТОТ, ЧТО резолвила полоса, а не выведенный здесь:
// освобождение машинного принципала — арм общего правила, и переизобретать его
// на полосе запрещено (`stepup_gate.go`, `pkg/grpcsrv/acr.go`). Полоса
// извлекает величины своего транспорта; решает по ним одна функция.
//
// route — только контекст журнала; вердикта он не меняет.
func (a *AuthInterceptor) sessionAssurance(subj Subject, res KratosWhoamiResult, route string) StepUpAssurance {
	acr, recognized := acrFromAssuranceLevel(res.AssuranceLevel)
	if !recognized {
		// Громко и с нарастающим итогом: «полоса не может поручиться ни за один
		// уровень» обязано быть видно, иначе поднятый пол будет отвергать всех
		// браузерных, а причина останется незаписанной. Два разных диагноза с
		// разными исправлениями различаются текстом, но счётчик один: следствие
		// у них одно и то же, и раздельные окна лишь дробили бы один сигнал.
		if report, total, represents := a.sessionAssuranceUnknown.observe(); report {
			msg := "browser session carries an assurance level this edge does not know; " +
				"the authentication floor cannot be satisfied on this lane"
			predicate := "исчезает, когда словарь провайдера и acrFromAssuranceLevel сойдутся"
			if strings.TrimSpace(res.AssuranceLevel) == "" {
				msg = "browser session carries NO assurance level; " +
					"the authentication floor cannot be satisfied on this lane"
				predicate = "исчезает, когда провайдер начнёт отдавать " +
					"session.authenticator_assurance_level"
			}
			a.logger.Error(msg,
				"lane", stepUpLaneSession,
				"route", route,
				"assurance_level", res.AssuranceLevel,
				"session_assurance_unknown_total", total,
				"occurrences_since_last_report", represents,
				"predicate", predicate)
		}
	}
	return StepUpAssurance{
		PrincipalType: subj.Type,
		ACR:           acr,
		// Момент аутентификации сессии — тот же смысл, что `auth_time` у
		// предъявителя: его читает арм свежести, когда каталог объявил окно.
		// Нулевой момент при объявленном окне даёт отказ, а не проход.
		AuthTime: res.AuthenticatedAt,
	}
}
