// Package anonmail — звено-ограничитель края для анонимных почтовых глаголов
// (приёмка NTF-2, Р5; замысел issue-2917, З8, З9, З26).
//
// Звено стоит в HTTP-цепочке края ПЕРЕД ретрансляцией полосы формы и только на
// записях объявления с признаком `anonMail` (`middleware.LoginLaneRoute`):
// запрос кода восстановления и регистрация — пути, которые ставят письмо на
// адрес из тела запроса. Тело запроса звено не читает: ключи — только источник
// и его подсети, поэтому ответ не зависит от адресата.
//
// # Решение и счёт — одна операция
//
// Хранилище (`Store`) решает одним неделимым шагом: блокировки ключей →
// пометка вызова использованным (одноразовость доказательства) → счёт ключей →
// лестница → ведро общего потока (только когда исход от него зависит: открытая
// ступень без доказательства) → момент пропуска. Пометка и момент фиксируются только при
// исходе `Pass`; вызов и отказ откатывают всё, и предъявленное доказательство
// остаётся неистраченным. Исход закрыт: `Pass · Challenge · Reject ·
// StoreUnavailable`, ветки «не смог спросить → пропустить» нет.
//
// # Хранилищ два — то же объявление, что у однократности
//
// `memory` законно при флоте из одной реплики (полосатые мьютексы по той же
// свёртке ключей, критическая секция процесса); `postgres` — общее хранилище
// флота на собственном пуле ограничителя (store_pg.go).
