package middleware

import (
	"net/http"

	"github.com/PRO-Robotech/kacho/pkg/httpbody"
)

// EdgeMaxRequestBodyBytes — потолок тела запроса на REST-краю.
//
// Тела control-plane измеряются килобайтами; потолок в мегабайт оставляет
// трёхзначный запас и при этом делает конечным всё, что происходит с телом
// дальше. А дальше происходит немало: тело буферизуется для извлечения области,
// затем разбирается в сообщение, затем — ОТДЕЛЬНЫМ полным проходом — в
// обобщённое представление, чтобы поймать имя значения перечисления, которое
// разборщик молча отбрасывает. Этот второй проход снять нельзя: он и есть
// проверка, а в разобранном сообщении отброшенного имени уже нет. Значит
// объём, резидентно удерживаемый на КАЖДЫЙ запрос в полёте, кратен размеру
// тела, и ограничивать надо ВХОД.
//
// Значение совпадает с bodyInspectCap намеренно: всё, что край принимает,
// обязано целиком поддаваться осмотру, иначе законный запрос в пределах потолка
// не отдал бы область и получил бы отказ по правам. Соотношение закреплено
// пробой предпосылки.
const EdgeMaxRequestBodyBytes int64 = 1 << 20

// HTTPMaxBodyBytes ограничивает тело запроса.
//
// Два слоя, потому что заявленную длину клиент может не прислать:
//   - объявленная длина больше потолка → 413 сразу, тело не читается вовсе;
//   - иначе тело оборачивается ограничителем, и попытка прочитать больше
//     потолка обрывает чтение (сервер закроет соединение). Так chunked-тело без
//     заявленной длины тоже остаётся конечным по памяти.
//
// Место в цепочке несущее: ограничитель обязан стоять СНАРУЖИ всего, что тело
// читает, — в том числе снаружи проверки прав, которая буферизует префикс.
// Порядок закреплён отдельной пробой над сборкой цепочки.
func HTTPMaxBodyBytes(limit int64) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			// Оба слоя потолка — в pkg/httpbody, единственной в дереве
			// реализации. Форма отказа остаётся здесь: у края она своя.
			if httpbody.Cap(w, r, limit) {
				http.Error(w, "request body too large", http.StatusRequestEntityTooLarge)
				return
			}
			next.ServeHTTP(w, r)
		})
	}
}
