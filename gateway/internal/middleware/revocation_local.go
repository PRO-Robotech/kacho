package middleware

// revocation_local.go — НАША ЗАПИСЬ ОТЗЫВА как источник ответа на полосе отзыва.
//
// # Что здесь было и почему стало одним
//
// Источников было два, и спрашивались оба: сперва НАША запись отзыва (по
// идентификатору удостоверения, её пишет выход человека), потом прежний
// поставщик по административному пути его интроспекции. Второй знал об
// отзывах, которых не знали мы, — собственных, администраторских, по истечению
// срока, — и подменять его было нельзя.
//
// Подменять больше нечего: прежний поставщик снят целиком (#2734), и вопрос ему
// был бы утверждением о предмете, которого у края нет. Композиция выродилась в
// свою первую половину, и половина эта — наша запись. Композиция с одним
// участником не оставлена: это была бы не композиция, а тихая подмена, и
// отличить её от исправной работы было бы нечем.
//
// # Fail-closed: «не знаю» — не «не отозван»
//
// Недоступность записи не есть отрицательный ответ. Вопрос здесь о
// безопасности, и ответ «не знаю» означает отказ — тот же контракт, что у
// проверки доступа, которую край делает рядом. Ошибка не подменяется на
// ErrTokenInactive: вызывающий различает «отозван» и «спросить не удалось», и в
// журнале это разные состояния одного контроля.

import (
	"context"
	"errors"
	"fmt"
)

// ErrOwnRevocationSourceSilent — наша запись отзыва не ответила.
//
// Признак ТИПИЗИРОВАН и ставится тем, кто знает, чей источник молчит, — этим
// читателем. Сравнивать текст ошибки нельзя: его пишет сосед, и он меняется от
// его версии.
var ErrOwnRevocationSourceSilent = errors.New("наш источник отзыва не ответил")

// OwnRevocationCallBudget — бюджет ОДНОГО вопроса нашей записи отзыва.
//
// Названный бюджет обязателен: вопрос стоит на пути запроса, а сырой контекст
// запроса пределом не является. Неотвечающий сосед без бюджета держит горутину
// столько, сколько держится клиент.
//
// Величина — та же, что у полосы базового секрета
// (`BasicCredentialCallBudget`): тот же сосед, то же соединение, тот же путь
// запроса и та же семантика молчания (fail-closed). Два разных числа на одном
// ребре были бы двумя решениями об одном предмете.
const OwnRevocationCallBudget = BasicCredentialCallBudget

// SessionRevocationsReader — наша запись отзыва: знает ли служба доступа, что
// удостоверение с этим идентификатором отозвано.
//
// Порт объявлен ЗДЕСЬ, у вызывающего, а не у клиента: край зависит от вопроса,
// который задаёт, а не от того, кто на него отвечает.
type SessionRevocationsReader interface {
	IsSessionRevoked(ctx context.Context, jti string) (bool, error)
}

// OwnRevocationSource — наша запись отзыва в форме, которую спрашивает слой
// решения. Реализует TokenRevocationChecker: вызывающий задаёт один вопрос и
// получает три исхода.
type OwnRevocationSource struct {
	local SessionRevocationsReader
}

// NewOwnRevocationSource собирает читателя.
//
// Участник обязателен: читатель без источника отвечал бы на вопрос о
// безопасности, ничего не спросив.
func NewOwnRevocationSource(local SessionRevocationsReader) *OwnRevocationSource {
	return &OwnRevocationSource{local: local}
}

// Introspect спрашивает нашу запись отзыва.
//
// Имя сохранено от интерфейса, который читатель исполняет; вопрос идёт на
// внутренний слушатель службы доступа её же контрактом.
func (c *OwnRevocationSource) Introspect(
	ctx context.Context, jti, _ string,
) (IntrospectionResult, error) {
	if c == nil || c.local == nil {
		// «Не должен наступить» — не «не может», а тихо пропустить запрос здесь
		// значит снять контроль целиком. Признак — ErrIntrospectionMisconfigured:
		// неполная сборка не лечится повтором и не проходит сама.
		return IntrospectionResult{}, fmt.Errorf(
			"%w: проверка отзыва собрана без источника — край не может установить, "+
				"действительно ли предъявленное удостоверение",
			ErrIntrospectionMisconfigured)
	}

	// СВОЙ предел на вызове соседа. Ставится ЗДЕСЬ, а не в адаптере: бюджет —
	// решение о пути запроса, а адаптер знает только транспорт. `WithTimeout`
	// берёт МЕНЬШИЙ из двух пределов, поэтому предел вызывающего остаётся в силе.
	callCtx, cancel := context.WithTimeout(ctx, OwnRevocationCallBudget)
	defer cancel()

	revoked, err := c.local.IsSessionRevoked(callCtx, jti)
	switch {
	case err != nil:
		// Признак молчания несётся типом, причина — цепочкой.
		return IntrospectionResult{}, fmt.Errorf("%w: %w", ErrOwnRevocationSourceSilent, err)
	case revoked:
		return IntrospectionResult{}, ErrTokenInactive
	}
	return IntrospectionResult{Active: true}, nil
}

// Утверждение формы: читатель исполняет порт слоя решения.
var _ TokenRevocationChecker = (*OwnRevocationSource)(nil)
