package middleware

// revocation_local.go — ДВА ИСТОЧНИКА ОТЗЫВА, И СПРАШИВАТЬ НАДО ОБА.
//
// # Что было не так
//
// Край спрашивает об отзыве провайдера — на каждом запросе, с кешем, fail-closed.
// Это верно и остаётся. Но выход пользователя записывает отзыв В НАШУ базу: по
// идентификатору удостоверения и отсечкой по времени. Провайдер об этой записи
// не знает и знать не может — она наша, — поэтому предъявленное удостоверение
// проходит его проверку и ПОСЛЕ нашего отзыва.
//
// Разрыв не виден ни с одной стороны по отдельности: у нас запись есть и пишется,
// у провайдера проверка есть и исполняется. Не сходятся они только вместе.
//
// # Почему «закрыть вход» этого не заменяет
//
// Второй механизм выхода снимает у провайдера сессию входа. Замер живого стенда
// (2026-08-21): сессий входа — ноль, выданных удостоверений — полсотни. Они
// выданы машинным потоком и к сессии не привязаны by construction, поэтому
// снятие сессии не касается ни одного из них. Механизм есть, предмета у него нет.
//
// # Порядок вопросов и почему он такой
//
// Свой источник — ПЕРВЫМ. Две причины, и обе про существо, а не про вкус:
//
//  1. он отвечает на вопрос, которого провайдер не понимает: об отзыве, который
//     записали мы;
//  2. он дешевле — сосед по кластеру против внешнего провайдера, — и на уже
//     отозванном удостоверении избавляет от обхода, который всё равно вернул бы
//     «живо».
//
// Провайдер спрашивается, только если свой источник сказал «не отозван»: он
// знает об отзывах, которых не знаем мы (сам провайдер, его администратор,
// истечение срока), и подменять его нельзя.
//
// # Fail-closed: «не знаю» — не «не отозван»
//
// Недоступность своего источника не есть отрицательный ответ. Вопрос здесь о
// безопасности, и ответ «не знаю» означает отказ — тот же контракт, что у
// проверки доступа, которую край делает рядом. Ошибка не подменяется на
// ErrTokenInactive: вызывающий различает «отозван» и «спросить не удалось», и в
// журнале это разные состояния одного контроля.
//
// # ДВА МОЛЧАНИЯ, И ОНИ РАЗНЫЕ (#2728)
//
// Здесь ошибка своего источника возвращалась НЕТИПИЗИРОВАННОЙ обёрткой, и для
// вызывающего она была неотличима от молчания чужого провайдера — то есть
// попадала в объявленный мягкий проход. Следствие: отозванное удостоверение
// продолжало действовать всё время, пока НАША служба доступа не отвечает.
//
// Различать эти два молчания текстом ошибки нельзя: текст пишет тот, кто её
// породил, и он меняется от версии соседа. Поэтому признак ТИПИЗИРОВАН, и
// ставит его тот, кто ЗНАЕТ, чей источник ответил, — эта композиция.
//
// Асимметрия объявлена, а не выведена, и у неё разные предметы:
//
//   - НАШ источник. Сосед по кластеру, отзыв наш, авторитет наш. Мягкий проход
//     означал бы: отзываем и свой же отзыв не исполняем — тот класс, где
//     контроль действует на ВЫДАЧЕ и не действует на ПРЕДЪЯВЛЕНИИ;
//   - ЧУЖОЙ провайдер. Третья сторона, её доступностью мы не управляем. Мягкий
//     проход там принят, задокументирован и остаётся ровно как был.
//
// ПРЕДИКАТ СНЯТИЯ асимметрии: она уходит вместе с полосой прежнего издателя.

import (
	"context"
	"errors"
	"fmt"
)

// ErrOwnRevocationSourceSilent — НАШ источник отзыва не ответил.
//
// Признак ставится ЗДЕСЬ, а не у вызывающего и не в адаптере: только эта
// композиция знает, ЧЕЙ из двух источников замолчал, — адаптер знает коды
// транспорта, но не знает, что рядом стоит второй источник с другой семантикой
// молчания.
//
// ЧТО ВХОДИТ В «НЕ ОТВЕТИЛ», И ПОЧЕМУ `UNIMPLEMENTED` ТОЖЕ. На браузерной
// полосе тот же код транспорта отделён отдельным признаком
// (ErrSessionCutoffUnsupported) и проходит ГРОМКО: вопрос об отсечке появился
// позже края, и «метода нет» там означает окно раската — состояние, которое
// сходится само, без чьего-либо участия.
//
// Здесь это неприменимо, и довод — замер, а не вкус. `IsRevoked` не новее ни
// одного из внутренних вопросов, которые край уже задаёт тому же соседу: по
// закреплённым версиям `kaname` он присутствует в каждой, где есть хоть один из
// них. Реплики, отвечающей «метода нет» на `IsRevoked` и отвечающей на
// остальные, не существует — у неё нет ни одного, и браузерная полоса такую
// реплику уже отвергает (ErrHumanSessionUnsupported — отказ, не проход).
// Послабление на этот код было бы послаблением, которому НЕЧЕГО исключать:
// предиката снятия у него нет, снять его было бы нечем, и оно пережило бы любое
// окно раската.
//
// Закреплено TestE2E_Revocation_OurSourceAnsweringUnimplementedIsSilenceNotARolloutPass.
var ErrOwnRevocationSourceSilent = errors.New("наш источник отзыва не ответил")

// SessionRevocationsReader — наш источник отзыва: знает ли iam, что удостоверение
// с этим идентификатором отозвано.
//
// Порт объявлен ЗДЕСЬ, у вызывающего, а не у клиента: край зависит от вопроса,
// который задаёт, а не от того, кто на него отвечает.
type SessionRevocationsReader interface {
	IsSessionRevoked(ctx context.Context, jti string) (bool, error)
}

// LocalThenProviderRevocation — композиция двух источников в порядке «свой,
// потом чужой». Реализует TokenRevocationChecker, поэтому вызывающему менять
// нечего: он по-прежнему задаёт один вопрос и получает три исхода.
type LocalThenProviderRevocation struct {
	local    SessionRevocationsReader
	provider TokenRevocationChecker
}

// NewLocalThenProviderRevocation собирает композицию.
//
// Оба участника обязательны. Композиция с одним участником — это не композиция,
// а тихая подмена: край продолжал бы отвечать, спрашивая половину, и отличить
// это от исправной работы было бы нечем.
func NewLocalThenProviderRevocation(
	local SessionRevocationsReader,
	provider TokenRevocationChecker,
) *LocalThenProviderRevocation {
	return &LocalThenProviderRevocation{local: local, provider: provider}
}

// Introspect задаёт вопрос обоим источникам в порядке, объявленном выше.
func (c *LocalThenProviderRevocation) Introspect(
	ctx context.Context, jti, rawToken string,
) (IntrospectionResult, error) {
	if c == nil || c.local == nil || c.provider == nil {
		// Ни один из трёх случаев не должен наступить: конструктор требует обоих.
		// Но «не должен» — не «не может», а тихо пропустить запрос здесь значит
		// снять контроль целиком. Отказ называет причину сам.
		//
		// Признак — ErrIntrospectionMisconfigured, а не «не ответил»: половинная
		// сборка не лечится повтором и не проходит сама. Это НАСТРОЙКА, и
		// отвечать на неё надо тем же, чем на неверный адрес, — отказом, который
		// держится, пока её не исправят.
		return IntrospectionResult{}, fmt.Errorf(
			"%w: проверка отзыва собрана неполно — край не может установить, "+
				"действительно ли предъявленное удостоверение",
			ErrIntrospectionMisconfigured)
	}

	revoked, err := c.local.IsSessionRevoked(ctx, jti)
	switch {
	case err != nil:
		// Признак СВОЕГО молчания несётся типом, а причина — цепочкой: первый
		// %w делает исход различимым для вызывающего, второй сохраняет диагноз
		// для журнала. Подмены на ErrTokenInactive по-прежнему нет: «спросить не
		// удалось» и «отозван» лечатся противоположно.
		return IntrospectionResult{}, fmt.Errorf("%w: %w", ErrOwnRevocationSourceSilent, err)
	case revoked:
		return IntrospectionResult{}, ErrTokenInactive
	}

	return c.provider.Introspect(ctx, jti, rawToken)
}
