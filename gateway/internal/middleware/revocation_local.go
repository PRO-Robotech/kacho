package middleware

// revocation_local.go — ИСТОЧНИК ОТЗЫВА ОДИН, И ОН НАШ.
//
// # Что здесь было и почему стало одним
//
// Источников было два, и спрашивались оба: сперва НАША запись отзыва (по
// идентификатору удостоверения, её пишет выход человека), потом чужой
// поставщик по административному пути его интроспекции. Второй знал об
// отзывах, которых не знали мы, — собственных, администраторских, по истечению
// срока, — и подменять его было нельзя.
//
// Подменять больше нечего: чужой поставщик снят целиком, его токенов край не
// принимает, и вопрос ему был бы утверждением о предмете, которого у него нет.
// Композиция выродилась в свою первую половину, и половина эта — авторитет.
//
// # Fail-closed: «не знаю» — не «не отозван»
//
// Недоступность источника не есть отрицательный ответ. Вопрос здесь о
// безопасности, и ответ «не знаю» означает отказ — тот же контракт, что у
// проверки доступа, которую край делает рядом. Ошибка не подменяется на
// ErrTokenInactive: вызывающий различает «отозван» и «спросить не удалось», и в
// журнале это разные состояния одного контроля.
//
// # ПОЧЕМУ МОЛЧАНИЕ ЭТОГО ИСТОЧНИКА НЕ ПРОХОДИТ МЯГКО (#2728)
//
// Мягкий проход был объявлен для ЧУЖОГО поставщика: третья сторона, её
// доступностью мы не управляем. Наш источник — сосед по кластеру, отзыв наш,
// авторитет наш; мягкий проход означал бы «отзываем и свой же отзыв не
// исполняем» — тот класс, где контроль действует на ВЫДАЧЕ и не действует на
// ПРЕДЪЯВЛЕНИИ. Асимметрия, которую держал типизированный признак, ушла вместе
// с чужой половиной: асимметрии между двумя источниками нет, когда источник
// один, — но признак остаётся, потому что его читает слой решения, и мягкого
// прохода для этого источника не было и нет.

import (
	"context"
	"errors"
	"fmt"
)

// ErrOwnRevocationSourceSilent — НАШ источник отзыва не ответил.
//
// Признак ставится ЗДЕСЬ, а не у вызывающего и не в адаптере: только эта
// композиция знает, ЧЕЙ из двух источников замолчал, — адаптер знает коды
// транспорта, но не знает, что рядом стоит второй источник с другой семантикой
// молчания.
//
// ЧТО ВХОДИТ В «НЕ ОТВЕТИЛ», И ПОЧЕМУ `UNIMPLEMENTED` ТОЖЕ. На браузерной
// полосе тот же код транспорта отделён отдельным признаком
// (ErrSessionCutoffUnsupported) и проходит ГРОМКО: вопрос об отсечке появился
// позже края, и «метода нет» там означает окно раската — состояние, которое
// сходится само, без чьего-либо участия.
//
// Здесь это неприменимо, и довод — замер, а не вкус. `IsRevoked` не новее ни
// одного из внутренних вопросов, которые край уже задаёт тому же соседу: по
// закреплённым версиям `kaname` он присутствует в каждой, где есть хоть один из
// них. Реплики, отвечающей «метода нет» на `IsRevoked` и отвечающей на
// остальные, не существует — у неё нет ни одного, и браузерная полоса такую
// реплику уже отвергает (ErrHumanSessionUnsupported — отказ, не проход).
// Послабление на этот код было бы послаблением, которому НЕЧЕГО исключать:
// предиката снятия у него нет, снять его было бы нечем, и оно пережило бы любое
// окно раската.
//
// Закреплено TestE2E_Revocation_OurSourceAnsweringUnimplementedIsSilenceNotARolloutPass.
var ErrOwnRevocationSourceSilent = errors.New("наш источник отзыва не ответил")

// SessionRevocationsReader — наш источник отзыва: знает ли служба доступа, что
// удостоверение с этим идентификатором отозвано.
//
// Порт объявлен ЗДЕСЬ, у вызывающего, а не у клиента: край зависит от вопроса,
// который задаёт, а не от того, кто на него отвечает.
type SessionRevocationsReader interface {
	IsSessionRevoked(ctx context.Context, jti string) (bool, error)
}

// OwnRevocationSource — наш источник отзыва в форме, которую спрашивает слой
// решения. Реализует TokenRevocationChecker: вызывающему менять нечего — он
// по-прежнему задаёт один вопрос и получает три исхода.
//
// ЗДЕСЬ БЫЛА КОМПОЗИЦИЯ ДВУХ ИСТОЧНИКОВ. Она снята вместе со вторым из них, а
// не оставлена с одним участником: композиция с одним участником — это не
// композиция, а тихая подмена, и отличить её от исправной работы было бы нечем.
type OwnRevocationSource struct {
	local SessionRevocationsReader
}

// NewOwnRevocationSource собирает читателя.
//
// Участник обязателен: читатель без источника отвечал бы на вопрос о
// безопасности, ничего не спросив.
func NewOwnRevocationSource(local SessionRevocationsReader) *OwnRevocationSource {
	return &OwnRevocationSource{local: local}
}

// Introspect спрашивает наш источник.
//
// Имя сохранено от интерфейса, который он исполняет, и путь интроспекции здесь
// ВНУТРЕННИЙ: вопрос идёт на внутренний слушатель службы доступа её же
// контрактом, а не по чужому административному пути.
func (c *OwnRevocationSource) Introspect(
	ctx context.Context, jti, _ string,
) (IntrospectionResult, error) {
	if c == nil || c.local == nil {
		// «Не должен наступить» — не «не может», а тихо пропустить запрос здесь
		// значит снять контроль целиком. Отказ называет причину сам.
		//
		// Признак — ErrIntrospectionMisconfigured, а не «не ответил»: неполная
		// сборка не лечится повтором и не проходит сама. Это НАСТРОЙКА, и
		// отвечать на неё надо тем же, чем на неверный адрес, — отказом,
		// который держится, пока её не исправят.
		return IntrospectionResult{}, fmt.Errorf(
			"%w: проверка отзыва собрана неполно — край не может установить, "+
				"действительно ли предъявленное удостоверение",
			ErrIntrospectionMisconfigured)
	}

	revoked, err := c.local.IsSessionRevoked(ctx, jti)
	switch {
	case err != nil:
		// Признак молчания несётся типом, а причина — цепочкой: первый %w
		// делает исход различимым для вызывающего, второй сохраняет диагноз для
		// журнала. Подмены на ErrTokenInactive по-прежнему нет: «спросить не
		// удалось» и «отозван» лечатся противоположно.
		return IntrospectionResult{}, fmt.Errorf("%w: %w", ErrOwnRevocationSourceSilent, err)
	case revoked:
		return IntrospectionResult{}, ErrTokenInactive
	}

	// Источник ответил «не отозвано». Спрашивать больше некого, и это ПОЛНЫЙ
	// ответ, а не половина прежнего: второй источник знал о чужих токенах,
	// которых край не принимает.
	return IntrospectionResult{Active: true}, nil
}
