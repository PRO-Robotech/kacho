package middleware

// revocation_local.go — ДВА ИСТОЧНИКА ОТЗЫВА, И СПРАШИВАТЬ НАДО ОБА.
//
// # Что было не так
//
// Край спрашивает об отзыве провайдера — на каждом запросе, с кешем, fail-closed.
// Это верно и остаётся. Но выход пользователя записывает отзыв В НАШУ базу: по
// идентификатору удостоверения и отсечкой по времени. Провайдер об этой записи
// не знает и знать не может — она наша, — поэтому предъявленное удостоверение
// проходит его проверку и ПОСЛЕ нашего отзыва.
//
// Разрыв не виден ни с одной стороны по отдельности: у нас запись есть и пишется,
// у провайдера проверка есть и исполняется. Не сходятся они только вместе.
//
// # Почему «закрыть вход» этого не заменяет
//
// Второй механизм выхода снимает у провайдера сессию входа. Замер живого стенда
// (2026-08-21): сессий входа — ноль, выданных удостоверений — полсотни. Они
// выданы машинным потоком и к сессии не привязаны by construction, поэтому
// снятие сессии не касается ни одного из них. Механизм есть, предмета у него нет.
//
// # Порядок вопросов и почему он такой
//
// Свой источник — ПЕРВЫМ. Две причины, и обе про существо, а не про вкус:
//
//  1. он отвечает на вопрос, которого провайдер не понимает: об отзыве, который
//     записали мы;
//  2. он дешевле — сосед по кластеру против внешнего провайдера, — и на уже
//     отозванном удостоверении избавляет от обхода, который всё равно вернул бы
//     «живо».
//
// Провайдер спрашивается, только если свой источник сказал «не отозван»: он
// знает об отзывах, которых не знаем мы (сам провайдер, его администратор,
// истечение срока), и подменять его нельзя.
//
// # Fail-closed: «не знаю» — не «не отозван»
//
// Недоступность своего источника не есть отрицательный ответ. Вопрос здесь о
// безопасности, и ответ «не знаю» означает отказ — тот же контракт, что у
// проверки доступа, которую край делает рядом. Ошибка возвращается КАК ЕСТЬ, не
// подменяясь на ErrTokenInactive: вызывающий различает «отозван» и «спросить не
// удалось», и в журнале это разные состояния одного контроля.

import (
	"context"
	"fmt"
)

// SessionRevocationsReader — наш источник отзыва: знает ли iam, что удостоверение
// с этим идентификатором отозвано.
//
// Порт объявлен ЗДЕСЬ, у вызывающего, а не у клиента: край зависит от вопроса,
// который задаёт, а не от того, кто на него отвечает.
type SessionRevocationsReader interface {
	IsSessionRevoked(ctx context.Context, jti string) (bool, error)
}

// LocalThenProviderRevocation — композиция двух источников в порядке «свой,
// потом чужой». Реализует TokenRevocationChecker, поэтому вызывающему менять
// нечего: он по-прежнему задаёт один вопрос и получает три исхода.
type LocalThenProviderRevocation struct {
	local    SessionRevocationsReader
	provider TokenRevocationChecker
}

// NewLocalThenProviderRevocation собирает композицию.
//
// Оба участника обязательны. Композиция с одним участником — это не композиция,
// а тихая подмена: край продолжал бы отвечать, спрашивая половину, и отличить
// это от исправной работы было бы нечем.
func NewLocalThenProviderRevocation(
	local SessionRevocationsReader,
	provider TokenRevocationChecker,
) *LocalThenProviderRevocation {
	return &LocalThenProviderRevocation{local: local, provider: provider}
}

// Introspect задаёт вопрос обоим источникам в порядке, объявленном выше.
func (c *LocalThenProviderRevocation) Introspect(
	ctx context.Context, jti, rawToken string,
) (IntrospectionResult, error) {
	if c == nil || c.local == nil || c.provider == nil {
		// Ни один из трёх случаев не должен наступить: конструктор требует обоих.
		// Но «не должен» — не «не может», а тихо пропустить запрос здесь значит
		// снять контроль целиком. Отказ называет причину сам.
		return IntrospectionResult{}, fmt.Errorf(
			"проверка отзыва собрана неполно: край не может установить, " +
				"действительно ли предъявленное удостоверение")
	}

	revoked, err := c.local.IsSessionRevoked(ctx, jti)
	switch {
	case err != nil:
		// Возвращаем КАК ЕСТЬ: это «спросить не удалось», а не «отозван».
		return IntrospectionResult{}, fmt.Errorf("источник отзыва не ответил: %w", err)
	case revoked:
		return IntrospectionResult{}, ErrTokenInactive
	}

	return c.provider.Introspect(ctx, jti, rawToken)
}
