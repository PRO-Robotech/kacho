// own_session_assurance.go — уровень уверенности НАШЕЙ сессии на полосе
// личности под посадкой `own` (приёмка Ф11, Р7; Ф11-19).
//
// # Край ничего не сопоставляет
//
// Уровень приходит из ответа нашей службы о сессии уже НА ОСИ каталога прав:
// выводит его правило службы (`internal/assurance`) из множества
// предъявленного, и второго вывода на крае нет by construction. Здесь
// проверяется ровно одно — принадлежность оси СЕССИИ, множеству «1», «2»,
// «3». Форма у проверки та же, что у полосы базового удостоверения
// (`acrFromCredentialLevel`: словарь — сама ось), а МНОЖЕСТВО другое: у той
// «0» законен — долгоживущий секрет уровня может не иметь, — у сессии нет,
// потому что сессии без уровня не бывает (Р1). Переиспользовать ту функцию
// нельзя: она пропустила бы «0» молча и без счётчика.
//
// # Почему значение вне оси — отказ, а не проход, и почему громко
//
// Ответ без уровня, с «0» либо со значением вне оси — в том числе словарное
// `aal2` поставщика — есть расхождение версий службы и края либо прямая запись
// в хранилище; продукт такого ответа не производит (Р1). Мягкий проход дал бы
// контроль, не отказавший ни разу за свою жизнь; перевод `aal2` в «2» вернул бы
// сопоставление словаря поставщика на полосу, у которой его источника нет.
// Поэтому величина уезжает дальше ПУСТОЙ: общее правило (`grpcsrv.ACRRank`)
// ранжирует её нулём — положительного пола она не удовлетворяет, нулевого не
// касается, — и второй замок отказывает по той же причине, что первый.
//
// Состояние при этом докладывается записью уровня ошибки с нарастающим итогом
// и считается своей клеткой: на глаголе без пола такой ответ ПРОХОДИТ, отказом
// он не является, и без своей клетки «служба перестала отдавать уровень»
// осталось бы невидимым до первого действия с полом.
package middleware

import (
	"strings"
)

// acrFromSessionLevel сверяет уровень, названный ответом службы о сессии, с
// осью СЕССИИ каталога прав: «1», «2», «3».
//
// onAxis=false означает «сессии с таким уровнем не бывает» — пустое, «0» и
// всякое значение вне оси, включая словарь поставщика. Вызывающий обязан
// доложить о нём и переслать дальше пустой уровень, а не подменять его.
// Обрамляющие пробелы нормализуются: отвергать по косметике значило бы
// отвергать сессию, которую служба выдала верно.
func acrFromSessionLevel(level string) (acr string, onAxis bool) {
	switch v := strings.TrimSpace(level); v {
	case "1", "2", "3":
		return v, true
	default:
		return "", false
	}
}

// ownSessionAssurance строит вход пола из ответа службы о НАШЕЙ сессии и
// докладывает, если уровень вне оси сессии (Ф11-19).
//
// Тип принципала передаётся ТОТ, ЧТО назвала полоса, а не выведенный здесь:
// освобождение машинного принципала — арм общего правила
// (`grpcsrv.EvaluateStepUp`), и переизобретать его на полосе запрещено.
//
// route — только контекст журнала; вердикта он не меняет.
func (a *AuthInterceptor) ownSessionAssurance(subj Subject, sess HumanSession, route string) StepUpAssurance {
	acr, onAxis := acrFromSessionLevel(sess.AssuranceLevel)
	if !onAxis {
		a.sessionLane.recordAssuranceOffAxis()
		if a.ownAssuranceOffAxis != nil {
			if report, total, represents := a.ownAssuranceOffAxis.observe(); report {
				// Два диагноза с разными починками различаются текстом, счётчик один:
				// следствие у них одно и то же — пол на этой полосе не удовлетворить
				// ничем, кроме глагола без пола.
				msg := "our session answer names an assurance level off the session axis; " +
					"every positive authentication floor refuses this session"
				predicate := "исчезает, когда служба отдаёт уровень на оси сессии («1», «2», «3»): " +
					"расхождение версий службы и края либо прямая запись в хранилище"
				if strings.TrimSpace(sess.AssuranceLevel) == "" {
					msg = "our session answer carries NO assurance level; " +
						"every positive authentication floor refuses this session"
				}
				a.logger.Error(msg,
					"lane", stepUpLaneSession,
					"route", route,
					"assurance_level", sess.AssuranceLevel,
					"session_assurance_off_axis_total", total,
					"occurrences_since_last_report", represents,
					"predicate", predicate)
			}
		}
	}
	return StepUpAssurance{
		PrincipalType: subj.Type,
		ACR:           acr,
		// Момент аутентификации — неподвижен на всю жизнь сессии (Ф11 Р6); его
		// читает арм свежести, когда каталог объявил окно.
		AuthTime: sess.AuthenticatedAt,
	}
}
