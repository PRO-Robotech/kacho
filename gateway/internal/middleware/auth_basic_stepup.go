// auth_basic_stepup.go — пол ступенчатой аутентификации, спрошенный на ТРЕТЬЕЙ
// полосе: базовое удостоверение (#1215).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ, И ПОЧЕМУ ЕГО НЕ МОГЛА УВИДЕТЬ НИ ОДНА ИЗ ДВУХ РАБОТ
//
// Полосу базового удостоверения (#1142) и пол на браузерной полосе (#1201)
// писали параллельно. Обе работы верны в своих границах, обе зелены по
// отдельности, и влились они друг в друга БЕЗ ЕДИНОГО ТЕКСТОВОГО КОНФЛИКТА:
// git сравнивает тексты, а разошёлся смысл. Автор полосы вводил вид
// удостоверения — пола на соседних полосах тогда ещё не было; автор пола чинил
// две полосы, которые видел, — третьей тогда ещё не было.
//
// Наблюдаемое следствие на собранном дереве: глагол, которому каталог объявил
// пол уровня «2» (чеканка и отзыв удостоверений), выполнялся по базовому
// секрету — то есть долгоживущее предъявительское удостоверение уровня «1»
// могло чеканить себе смену. Ровно то, что шапка `BasicCredentialLevel`
// объявляет невозможным: объявление было, исполнения не было.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТОБРАЖЕНИЕ, А НЕ ПРЯМАЯ ПЕРЕДАЧА КОНСТАНТЫ
//
// Уровень полосы объявлен константой `BasicCredentialLevel`, и до этой правки
// он писался в заголовок ВТОРОГО замка как есть, без единой проверки. Значение,
// уехавшее с оси каталога (опечатка, «aal1», «high», пустая строка), приняли бы
// оба замка молча: `grpcsrv.ACRRank` ранжирует незнакомое нулём, поэтому
// поднятый пол не обошёлся бы — но и НИКТО БЫ НЕ УЗНАЛ, что полоса перестала
// ручаться за уровень, а обычная работа арендатора при этом отвалилась бы вся
// разом с необъяснимым отказом. Отображение делает состояние ГРОМКИМ и со своим
// счётчиком — та же посадка, что у полосы сессии (`auth_session_stepup.go`).
//
// Лестница НЕ изобретается здесь: она объявлена нормативно в
// `pkg/grpcsrv/acr.go`, и эта функция лишь сверяет, что величина полосы на ней
// стоит. Второго ранжирования, второго освобождения и второго умолчания на
// крае нет by construction — вердикт выносит `StepUpGate.CheckAssurance`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ НЕРАСПОЗНАННЫЙ УРОВЕНЬ — ОТКАЗ, А НЕ ПРОХОД
//
// По той же причине, что на полосе сессии: мягкий проход дал бы контроль,
// который присутствует, провязан, исполняется на каждом запросе — и не
// отвергает ничего. Нераспознанное приезжает к стражу пустой строкой, общее
// правило ранжирует её нулём: положительного пола она не удовлетворяет,
// нулевого не касается.
package middleware

import (
	"strings"
)

// acrFromCredentialLevel сверяет уровень, объявленный полосой удостоверения, с
// осью каталога прав.
//
// В отличие от полосы сессии, словарь этой полосы — САМА ОСЬ ("0".."3"), а не
// чужая лестница AAL, поэтому отображение тождественно по значению и НЕ
// тождественно по действию: оно отсеивает величину, съехавшую с оси.
//
// Регистр и обрамляющие пробелы нормализуются — отвергать по написанию значило
// бы отвергать по косметике. Расширять снисходительность на неизвестные
// значения нельзя: см. шапку.
//
// recognized=false означает «мы не знаем, что это» — ни низкий уровень, ни
// высокий. Вызывающий обязан различать его отдельно и доложить о нём.
func acrFromCredentialLevel(level string) (acr string, recognized bool) {
	switch strings.ToLower(strings.TrimSpace(level)) {
	case "0", "1", "2", "3":
		return strings.TrimSpace(level), true
	default:
		return "", false
	}
}

// basicCredentialAssurance строит вход пола из проверенного удостоверения — и
// докладывает, если уровня назвать не смогли.
//
// Тип принципала передаётся ТОТ, ЧТО назвал авторитет, а не выведенный здесь:
// освобождение машинного принципала — арм общего правила
// (`grpcsrv.EvaluateStepUp`), и переизобретать его на полосе запрещено. Это не
// теоретическая оговорка: базовое удостоверение законно принадлежит служебной
// учётке, и решать про неё обязана та же функция, что и на прочих полосах.
//
// AuthTime остаётся нулевым, и это ОБЪЯВЛЕНИЕ, а не пропуск: момента
// интерактивной аутентификации у долгоживущего предъявительского секрета нет
// вовсе. При объявленном каталогом окне свежести нулевой момент даёт отказ, а
// не проход, — та же посадка, что у отсечки сессии.
//
// route — только контекст журнала; вердикта он не меняет.
func (a *AuthInterceptor) basicCredentialAssurance(cred BasicVerifiedCredential, route string) StepUpAssurance {
	acr, recognized := acrFromCredentialLevel(cred.AuthenticationLevel)
	if !recognized && a.basicAssuranceUnknown != nil {
		if report, total, represents := a.basicAssuranceUnknown.observe(); report {
			a.logger.Error(
				"basic credential lane declares an assurance level this edge does not know; "+
					"the authentication floor cannot be satisfied on this lane",
				"lane", stepUpLaneBasic,
				"route", route,
				"declared_level", cred.AuthenticationLevel,
				"basic_assurance_unknown_total", total,
				"occurrences_since_last_report", represents,
				"predicate", "исчезает, когда BasicCredentialLevel и ось каталога "+
					"(pkg/grpcsrv/acr.go) сойдутся")
		}
	}
	return StepUpAssurance{
		PrincipalType: cred.PrincipalType,
		ACR:           acr,
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОТКАЗ ПО ПОЛУ НА ЭТОЙ ПОЛОСЕ — НЕ ВЫЗОВ RFC 9470, А ЕЁ СОБСТВЕННЫЙ
// ЕДИНЫЙ ОТКАЗ
//
// Полоса объявляет свой контракт сама, и он ровно об этом (`ErrCredentialRefused`):
// неизвестный идентификатор, неверный секрет, истёкший срок, отозванное,
// неактивный владелец — ОДИН исход, потому что «различимый был бы оракулом».
//
// Вызов ступенчатой аутентификации завёл бы ШЕСТОЙ исход, и он говорит ровно
// то, чего остальные пять избегают: «предъявленное годно, его уровень прочитан,
// не хватает силы». То есть по глаголу, который вызывающему НЕ доступен, он
// получал бы подтверждение годности строки — бесплатно, не совершив ни одного
// авторизованного действия и не оставив следа в аудите. Для угадываемого
// долгоживущего предъявительского секрета это ровно тот оракул, ради закрытия
// которого пять исходов и сведены в один.
//
// Второй, независимый довод: вызов RFC 9470 СОВЕТУЕТ НЕВОЗМОЖНОЕ. Уровень этой
// полосы — константа вида удостоверения, и церемонии, которая подняла бы его,
// не существует: `acr_values="2"` предлагает предъявителю сделать то, чего он
// не сможет никогда. Тот же довод уже записан рядом про неспособность
// установить состояние: предлагать переаутентификацию там, где её ничто не
// исправит, значит вводить вызывающего в заблуждение.
//
// Вызывающий при этом НЕ теряет ничего исполнимого: средство у него одно и то
// же в обоих случаях — взять другое удостоверение, интерактивное. Это и есть
// смысл «credential refused».
//
// ВЕРДИКТ ПРИ ЭТОМ ОСТАЁТСЯ ОБЩИМ. Отличается только рендеринг: решение
// выносит `StepUpGate.CheckAssurance` — та же функция, что на прочих полосах, —
// и второго ранжирования здесь не заводится (`auth_stepup.go`).

// stepUpCeremonyReachable — существует ли для носителя ЭТОЙ полосы церемония,
// которая подняла бы предъявленный уровень.
//
// Умолчание — НЕ достижима, и это не осторожность ради осторожности: выдать
// вызов полосе, для которой церемонии нет, значит подтвердить годность
// предъявленного и посоветовать невозможное. Новая полоса обязана назвать себя
// здесь ОСОЗНАННО; молчаливое умолчание в сторону выдачи вызова было бы ровно
// тем классом, который #1215 и чинит.
func stepUpCeremonyReachable(lane string) bool {
	switch lane {
	case stepUpLaneSession, stepUpLaneBearer:
		// Человек за браузером и держатель токена провайдера могут пройти
		// второй фактор: церемония существует, и назвать её — работа вызова.
		return true
	case stepUpLaneBasic:
		return false
	default:
		return false
	}
}

// basicCredentialRefusalText — ЕДИНСТВЕННЫЙ производитель текста отказа полосы.
//
// Берётся из сигнальной ошибки, а не выписывается литералом: байт-идентичность
// отказа по полу и отказа в удостоверении обязана держаться ПОСТРОЕНИЕМ, а не
// согласием двух строк в разных файлах. Согласие расходится молча — и разойдётся
// оно ровно там, где расхождение и есть оракул.
func basicCredentialRefusalText() string {
	return ErrCredentialRefused.Error()
}
