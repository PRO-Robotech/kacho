package middleware_test

// lane_names_askable_credential_test.go — ТРЕТЬЕ сравнение полос личности по
// одному свойству: НАЗЫВАЕТ ЛИ ПОЛОСА УДОСТОВЕРЕНИЕ ДЛЯ СВОЕГО СОБСТВЕННОГО
// ВОПРОСА К АВТОРИТЕТУ ОТЗЫВА (kacho#1450, остаток #1410).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Перепрос состояния удостоверения на открытых соединениях
// (`gateway/internal/streamrevocation`) собирает предъявленное строителем
// `principalmeta.CredentialFromRequest` и спрашивает про него нашего авторитета.
// Вопросов ТРИ, и они разделены так же, как полосы на пути запроса:
// по идентификатору удостоверения · по идентификатору строки базового
// удостоверения · по паре (человек, момент аутентификации).
//
// Полоса, не назвавшая НИЧЕГО, открывает поток, который отзывом удостоверения
// закрыть нельзя ни при каких условиях: объявленное окно отзыва для него не
// действует, действует срок жизни соединения. Перепрос такие потоки не
// пропускает молча — считает величиной `streams_unaskable` и поднимает тревогу.
// Но счётчик есть наблюдение В БОЮ: он говорит, что полоса уже завелась и уже
// работает.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СВОЙСТВО ПО-ЛОСНОЕ, А НЕ «НАЗВАЛА ХОТЬ ЧТО-ТО»
//
// Это исправление собственной первой редакции, и записано оно потому, что ошибка
// незаметна и повторима. Первая редакция утверждала `Credential.Askable()` — то
// есть ДИЗЪЮНКЦИЮ трёх наименований. Инъекция показала, что она зелена на
// настоящем дефекте: у владельца базового удостоверения БЫВАЕТ человек, и полоса
// приёма ставит его личность в заголовки. Снимешь идентификатор строки — полоса
// остаётся «спрашиваемой» ЧЕЛОВЕКОМ, дизъюнкция выполнена, проба молчит.
//
// А перепрос в этот момент задал бы ЧУЖОЙ вопрос: браузерную отсечку пути
// запроса базовому секрету не задают вовсе (см. довод у `streamrevocation.ask`,
// где порядок разбора объявлен несущим ровно по этой причине). Поток при этом
// «спрошен» — и спрошен по условию, которого путь запроса к нему не применяет.
// Дизъюнкция такое не отличает by construction, поэтому утверждается ПАРА
// «полоса ↔ её собственный вопрос».
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО НЕ ВТОРАЯ КОПИЯ РАЗБОРА ПЕРЕПРОСА
//
// Здесь объявлено, что КАЖДАЯ ПОЛОСА НАЗЫВАЕТ, и это факт о полосе приёма,
// добытый её ПРОГОНОМ через настоящую точку входа края. Порядок разбора — какой
// вопрос задать первым, когда названо больше одного, — знает
// `streamrevocation.ask`, и знает в единственном экземпляре; сюда он не
// переписывается.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ТЕМ ЖЕ СТРОИТЕЛЕМ, ЧТО ЗОВЁТ ПЕРЕПРОС
//
// Удостоверение собирается `principalmeta.CredentialFromRequest` — той же
// функцией, которую зовёт перепрос, — из ТОГО ЖЕ запроса, что дошёл до backend.
// Второй сборщик, написанный здесь по образцу, разошёлся бы с первым молча: на
// отсутствующем заголовке, на мостовой форме и на ключе, у которого мостовой
// формы нет вовсе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕ БЫЛО ДО ЭТОЙ ПРОБЫ
//
// Перепись полос выводится из дерева (stepup_lane_census_test.go), и четвёртая
// полоса роняет ОБА соседних сравнения своим именем — пол ступенчатой
// аутентификации и уровень уверенности к внутреннему замку. Про удостоверение не
// спрашивало НИ ОДНО: `Askable()` утверждался ровно в одном месте — у полосы
// базового секрета, той самой, ради которой его завели (#1450). Четвёртая полоса
// могла завестись, осознанно ответив на два вопроса, и молча не ответить на
// третий; узнали бы об этом из счётчика в бою.

import (
	"net/http"
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho/gateway/internal/principalmeta"
)

// laneQuestion — вопрос авторитета отзыва, на который отвечает удостоверение
// ОДНОЙ полосы. Значение — то поле [principalmeta.Credential], без которого
// вопрос задать нечем.
type laneQuestion struct {
	// name — как вопрос называется человеку; попадает в перепись и в отказ.
	name string
	// named — назвала ли полоса то, чем ЭТОТ вопрос задаётся.
	named func(principalmeta.Credential) bool
}

var (
	// questionSessionRevocation — «отозвано ли удостоверение с этим
	// идентификатором» (`IsRevoked`).
	questionSessionRevocation = laneQuestion{
		name:  "по идентификатору удостоверения",
		named: func(c principalmeta.Credential) bool { return c.JTI != "" },
	}
	// questionBasicCredentialLiveness — «живо ли удостоверение с этим
	// идентификатором строки» (`CheckBasicCredentialLive`, #1450).
	questionBasicCredentialLiveness = laneQuestion{
		name:  "по идентификатору строки базового удостоверения",
		named: func(c principalmeta.Credential) bool { return c.BasicCredentialID != "" },
	}
	// questionSubjectCutoff — «не позже ли отсечки субъекта» (`SessionCutoffOf`).
	// Идентификатора у браузерной сессии нет вовсе, поэтому вопрос ключуется
	// парой; момент — вторая половина пары, и без него вердикт выносится, но
	// другой, поэтому здесь требуются ОБЕ величины.
	questionSubjectCutoff = laneQuestion{
		name: "по паре (человек, момент аутентификации)",
		named: func(c principalmeta.Credential) bool {
			return c.UserID != "" && !c.AuthenticatedAt.IsZero()
		},
	}
)

// laneQuestions — какой вопрос авторитета отвечает КАЖДАЯ полоса, ключ = имя
// метода-полосы В ДЕРЕВЕ (тот же ключ, что у `laneDrivers`).
//
// Перечень сверяется с деревом в ОБЕ стороны (см. ниже): полоса без записи —
// четвёртая полоса, заведённая молча; запись без полосы — утверждение,
// пережившее свой предмет.
//
// Полосы, НЕ устанавливающей личность в production, здесь нет намеренно: у неё
// нет своего вопроса, потому что нет и потока. Это утверждается зеркалом в
// конце пробы, а не принимается на веру.
func laneQuestions() map[string]laneQuestion {
	return map[string]laneQuestion{
		"tryKratosSession":   questionSubjectCutoff,
		"tryHydraJWT":        questionSessionRevocation,
		"tryBasicCredential": questionBasicCredentialLiveness,
	}
}

// namedByLane — ЧТО полоса назвала, для переписи и текста отказа.
//
// Диагностика значения, не решение: читает, какие поля непусты, и ничего не
// выбирает.
func namedByLane(c principalmeta.Credential) string {
	var named []string
	if c.JTI != "" {
		named = append(named, "идентификатор удостоверения")
	}
	if c.BasicCredentialID != "" {
		named = append(named, "идентификатор строки базового удостоверения")
	}
	if c.UserID != "" {
		moment := "без момента"
		if !c.AuthenticatedAt.IsZero() {
			moment = "с моментом"
		}
		named = append(named, "человек ("+moment+")")
	}
	if len(named) == 0 {
		return "НИЧЕГО"
	}
	sort.Strings(named)
	return strings.Join(named, " + ")
}

// TestIdentityLaneParity_EveryProductionLaneNamesItsOwnRevocationQuestion —
// каждая полоса, устанавливающая личность в production-посадке, обязана назвать
// удостоверение для СВОЕГО вопроса к авторитету отзыва.
//
// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ОБЯЗАТЕЛЕН И СТОИТ ЗДЕСЬ ЖЕ: полос, устанавливающих
// личность, обязано быть больше нуля, и каждая обязана ДОЙТИ до backend. Без
// первого цикл пуст и утверждение тождественно истинно; без второго «вопрос не
// назван» стало бы верно для полосы, которая просто не аутентифицирует, — и
// проба краснела бы не на своём предмете.
func TestIdentityLaneParity_EveryProductionLaneNamesItsOwnRevocationQuestion(t *testing.T) {
	c, drivers := resolveDrivers(t)
	questions := laneQuestions()
	rig := newLaneRig(t)

	// СВЕРКА ПЕРЕЧНЯ С ДЕРЕВОМ В ОБЕ СТОРОНЫ — тем же порядком, что у
	// `resolveDrivers`, и по той же причине: перечень, принадлежащий пробе,
	// измеряет память автора, а не дерево.
	var unquestioned, orphaned []string
	for _, m := range c.lanes {
		if !drivers[m].carriesIdentityInProduction {
			continue
		}
		if _, ok := questions[m]; !ok {
			unquestioned = append(unquestioned, m)
		}
	}
	for m := range questions {
		if !drivers[m].carriesIdentityInProduction {
			orphaned = append(orphaned, m)
		}
	}
	sort.Strings(unquestioned)
	sort.Strings(orphaned)
	require.Empty(t, unquestioned,
		"полоса устанавливает личность в production, а какой вопрос авторитета отвечает её "+
			"удостоверение — не решено: %v.\n"+
			"Поток, открытый на такой полосе, отзывом удостоверения не закрыть. Решите "+
			"ОСОЗНАННО и внесите в laneQuestions().", unquestioned)
	require.Empty(t, orphaned,
		"вопрос объявлен для полосы, которая личность в production не устанавливает: %v — "+
			"утверждение пережило свой предмет", orphaned)

	type laneCredential struct {
		lane     string
		method   string
		reached  bool
		question string
		answered bool
		askable  bool
		named    string
	}

	var carrying, excluded []laneCredential
	for _, m := range c.lanes {
		d := drivers[m]
		o := driveLane(t, rig, http.MethodPost, m, routineRoute, d)
		lc := laneCredential{
			lane:    d.name,
			method:  m,
			reached: o.backendReached,
			askable: o.cred.Askable(),
			named:   namedByLane(o.cred),
		}
		if !d.carriesIdentityInProduction {
			excluded = append(excluded, lc)
			continue
		}
		q := questions[m]
		lc.question, lc.answered = q.name, q.named(o.cred)
		carrying = append(carrying, lc)
	}

	answering := 0
	for _, lc := range carrying {
		if lc.answered {
			answering++
		}
	}

	// ОБЕ величины переписи, а не одна: «полос N» без «отвечают своему вопросу M»
	// скрывает ровно тот случай, ради которого проба заведена. Плюс объём
	// осмотренного — «ноль находок» обязано быть отличимо от «ноль прочитанного».
	t.Logf("перепись: полос личности %d · устанавливают личность в production %d · "+
		"называют удостоверение для СВОЕГО вопроса %d",
		len(c.lanes), len(carrying), answering)
	t.Logf("  (выведено из дерева: файлов %d · методов %s %d)", c.filesRead, c.receiverTyp, c.methods)
	for _, lc := range carrying {
		t.Logf("  %-52s бэкенд=%-5v свой-вопрос=%-5v (%s) назвала: %s",
			lc.lane, lc.reached, lc.answered, lc.question, lc.named)
	}
	for _, lc := range excluded {
		t.Logf("  %-52s (личность в production не устанавливает) назвала: %s", lc.lane, lc.named)
	}

	require.Positive(t, len(carrying),
		"ни одна полоса не объявлена устанавливающей личность в production — "+
			"сравнение было бы вакуумным: утверждать оказалось бы не о чем")

	for _, lc := range carrying {
		require.True(t, lc.reached,
			"положительный контроль: полоса %q обязана аутентифицировать и довести запрос "+
				"до backend, иначе «вопрос не назван» верно для неё тождественно и проба "+
				"краснеет не на своём предмете", lc.lane)
		require.True(t, lc.answered,
			"полоса %q не называет удостоверения для СВОЕГО вопроса к авторитету отзыва "+
				"(%s).\nНазвала: %s.\n"+
				"Следствие — и оно ХУЖЕ, чем «поток не закрыть»: если полоса назвала что-то "+
				"другое, перепрос спросит вопросом ЧУЖОЙ полосы, то есть по условию, которого "+
				"путь запроса к этому предъявителю не применяет вовсе; если не назвала ничего, "+
				"поток отзывом удостоверения не закрыть ни при каких условиях, объявленное окно "+
				"для него не действует и действует срок жизни соединения (перепрос считает его "+
				"величиной streams_unaskable и поднимает тревогу в бою).\n"+
				"Проставьте величину в полосе приёма — единственной, кто её знает.",
			lc.lane, lc.question, lc.named)
	}

	// ЗЕРКАЛО ИСКЛЮЧЕНИЯ. Полоса, объявленная не устанавливающей личность в
	// production, не вправе называть удостоверение: назвала — значит она в
	// production ЖИВА, исключение потеряло предикат, и полосу надо вносить в
	// сравнение выше, а не держать вне его.
	//
	// Граница названа честно: у соседнего сравнения тот же предикат утверждается
	// личностью, дошедшей до backend. Здесь он утверждается удостоверением —
	// осью ЭТОЙ пробы, — чтобы исключение не пережило свой предмет именно в том
	// свойстве, о котором проба.
	for _, lc := range excluded {
		require.False(t, lc.askable,
			"полоса %q объявлена не устанавливающей личность в production-посадке, "+
				"но назвала спрашиваемое удостоверение (%s) — исключение потеряло предикат",
			lc.lane, lc.named)
	}
}
