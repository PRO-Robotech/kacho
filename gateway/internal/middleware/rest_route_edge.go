package middleware

import "github.com/PRO-Robotech/kacho/gateway/internal/subscriptionstream"

// rest_route_edge.go — маршруты СОБСТВЕННЫХ ручек края, которых нет и не может
// быть в сгенерённой таблице.
//
// # Почему отдельный файл, а не строка в сгенерённом
//
// Сгенерённая таблица выводится из `google.api.http` контракта и помечена «не
// править»: правка пережила бы ровно до следующей генерации. Здесь стоят ручки,
// которые край обслуживает САМ, — у них нет объявления в контракте by
// construction, потому что объявить его значило бы завести методу внешний путь.
//
// # Зачем маршрут вообще нужен
//
// Полоса прав ищет запись каталога по ИМЕНИ МЕТОДА. Путь, для которого имя не
// резолвится, промахивается мимо каталога, а промах — отказ (fail-closed).
// То есть без этой строки ручка была бы не «открытой», а мёртвой.
//
// # Почему имя НАСТОЯЩЕЕ, а не выдуманное для края
//
// Ручка исполняет от имени вызывающего ровно один глагол, и право на него уже
// объявлено записью каталога. Вторая запись под собственным именем края
// объявляла бы право, которого не спрашивает ни один вызов, и разошлась бы с
// настоящей молча — при том, что обе выглядели бы действующими.
//
// # Что эта строка НЕ делает
//
// Она не заводит методу внешнего пути. Резолв «путь → имя метода» живёт внутри
// полосы прав и маршрутом не является: наружу метод по-прежнему не
// маршрутизируется — его нет в `allowlist.AllowedMethods`, его имя отсекает
// `allowlist.HasInternalSuffix`, а `runtime.ServeMux` о нём не знает вовсе,
// потому что `google.api.http` контракт не объявляет. Три механизма, ни один из
// которых этим изменением не тронут.
var edgeRestRoutes = []restRoute{
	{
		Method:   "GET",
		Template: subscriptionstream.Path,
		FQN:      subscriptionstream.MethodFQN,
	},
}
