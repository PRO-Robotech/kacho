package middleware

import (
	"strconv"
	"unicode/utf8"
)

// EdgeMaxLoggedPathBytes — сколько байт пути попадает в ОДНУ запись журнала.
//
// # Зачем предел вообще
//
// Путь приходит от запросчика, и на внешнем слушателе — от запросчика БЕЗ
// удостоверения. Запись о нём ведут два звена, значит объём журнала на один
// запрос кратен длине пути, а длину выбирает тот, кого записывают. Предел
// строки запроса у сервера края — отдельное решение (`EdgeMaxRequestHeaderBytes`),
// но даже при нём один запрос писал бы в журнал кратно своему размеру, а
// ограничителя темпа на полосе HTTP нет ни одного.
//
// Наблюдаемость, которой можно залить диск, наблюдаемостью не остаётся: ротация
// вымывает историю ровно во время события, ради разбора которого запись и
// заводилась.
//
// # Почему усечение, а не счётчик вместо строки
//
// Счётчик отвечает «сколько», но не «что спрашивали», — а разбор происшествия
// начинается со второго. Усечение сохраняет обе величины: начало пути называет
// поверхность, по которой шли, а исходная длина рядом отличает запрос чуть
// длиннее предела от запроса под потолок строки. Счётчик при этом никуда не
// делся: полоса `Unserved` считает их все.
//
// # Откуда ЧИСЛО
//
// Из дерева, а не на глаз: обход дескрипторов по всем 300 биндингам даёт
// медиану 30 байт, p95 46 и самый длинный конкретный путь 65 байт
// (`/registry/v1/registries/{id}/repositories/{repo}/tags/{tag}`).
//
// Предел взят почти вчетверо от самого длинного, а не впритык, и запас здесь не
// суеверие: часть маршрутов несёт глубокий подстановочный знак (`{repo=**}`),
// значение которого занимает НЕСКОЛЬКО сегментов, поэтому законный путь реестра
// бывает заметно длиннее любого, который даёт обход шаблонов. Путь, не влезающий
// и в этот предел, ни одному маршруту края не соответствует, и в записи от него
// нужен ровно префикс, по которому видно, куда целились.
const EdgeMaxLoggedPathBytes = 256

// LogTruncationMark — признак усечения.
//
// Обязателен: молча укороченный путь читается как настоящий и уводит разбор
// происшествия по ложному следу. Рядом с ним всегда идёт исходная длина.
const LogTruncationMark = "…[усечено]"

// TruncateForLog возвращает значение, пригодное для записи в журнал: либо
// исходное, либо префикс с явным признаком усечения и исходной длиной.
//
// Режет по границе руны: путь приходит уже раскодированным и может нести UTF-8,
// а половина руны в записи — это невалидный JSON у собирателя.
func TruncateForLog(s string) string {
	if len(s) <= EdgeMaxLoggedPathBytes {
		return s
	}
	cut := EdgeMaxLoggedPathBytes
	for cut > 0 && !utf8.RuneStart(s[cut]) {
		cut--
	}
	return s[:cut] + LogTruncationMark + " исходно " + strconv.Itoa(len(s)) + " байт"
}
