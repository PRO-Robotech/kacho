package principalmeta

// credential_strip.go — край не ПЕРЕСЫЛАЕТ арендаторское удостоверение за себя.
//
// # Предмет
//
// Край требует удостоверение и проверяет его сам. Установив личность, он кладёт
// её в свои заголовки — и за краем действует именно она. Само же удостоверение
// за краем не нужно НИКОМУ, кроме одного читателя, и этот читатель принимает
// решение о вызывающем ЗАНОВО. Пока обе формы личности уезжают вместе, вопрос
// «кто звонит» имеет два ответа в одном запросе, и разрешать его догадкой —
// «предъявленная главнее» или «переданная главнее» — нельзя.
//
// Поэтому полосы делаются взаимоисключающими ПОСТРОЕНИЕМ, а не проверкой:
// проверку можно обойти, построение — нет. За краем действует переданная
// личность, напрямую — предъявленная, и сочетания не бывает.
//
// Побочно закрывается ещё одно: доверенному отправителю нельзя подменить
// переданную личность подсунутым удостоверением — подсунутое до слушателя не
// доезжает.
//
// # Это НЕ ослабление транспорта
//
// Требование к вызывающему не меняется ни на байт: он по-прежнему обязан
// предъявить удостоверение краю, и край по-прежнему его проверяет. Меняется
// только то, что уезжает ЗА край, и происходит это ПОСЛЕ того, как край
// прочитал удостоверение сам.
//
// # Форма не изобретена здесь
//
// Плоскость данных реестра уже снимает удостоверение перед проксированием за
// себя, и по тому же доводу: доступ разрешён выше по пути, за проксированием
// удостоверение не нужно, а осевшее в чужих журналах — расширяет поверхность.
//
// # Где снятие СТОИТ, и почему двумя формами, а не одной
//
// Поверхностей пересылки у края две, и переносят удостоверение они РАЗНЫМИ
// механизмами:
//
//   - gRPC-полоса собирает исходящие метаданные из входящих — здесь снятие
//     живёт в общем узле [OutgoingFromIncoming], через который проходит каждый
//     межпроцессный переход;
//   - HTTP-полоса переносит удостоверение ОСОБЫМ СЛУЧАЕМ библиотеки моста, до
//     обращения к сопоставителю входящих заголовков. Сузить его сопоставителем
//     НЕЛЬЗЯ — он до этого решения не доходит; снимается сам заголовок запроса
//     ([StripCredentialBeforeForwarding]), и обе производные формы исчезают
//     вместе с ним, потому что обе выводятся из него.
//
// # Конструкции сборки исходящих метаданных ПОМИМО общего узла — решение по каждой
//
// Край строит исходящие метаданные не в одном месте. Снятие, положенное только
// в общий узел, эти конструкции не покрывает; положенное в каждую — разойдётся
// молча при следующей правке. Поэтому перечень стоит ЗДЕСЬ, рядом со снятием, —
// там, где его увидит следующий, кто заведёт четвёртую:
//
//	middleware/auth.go        injectPrincipal        — УДОСТОВЕРЕНИЯ НЕ НЕСЁТ by construction:
//	                                                   собирает из СВОИХ исходящих метаданных,
//	                                                   в которые край удостоверения не пишет;
//	                                                   межпроцессный переход поверх неё всё равно
//	                                                   пересобирает контекст общим узлом.
//	middleware/auth_stepup.go withTokenContextMetadata — то же основание: копия своих исходящих
//	                                                   плюс три ключа контекста проверенного
//	                                                   удостоверения; самого удостоверения там нет.
//	subscriptionstream/handler.go callerContext      — УДОСТОВЕРЕНИЯ НЕ НЕСЁТ by construction:
//	                                                   метаданные собираются ЗАКРЫТЫМ перечнем
//	                                                   ключей личности ([MetadataFromRequest]),
//	                                                   а не копированием входящих.
//
// Заводя четвёртую конструкцию — впиши сюда решение по ней. Пустая строка здесь
// означает «никто не решал», а не «безопасно».

import (
	"net/http"
	"strings"

	"google.golang.org/grpc/metadata"
)

// MetaPresentedCredential — ключ метаданных, под которым едет предъявленное
// арендатором удостоверение.
//
// Имя объявлено ЗДЕСЬ и один раз: снятие и проба обязаны говорить об одном
// ключе, а второе объявление разошлось бы с первым молча — на ключе, который
// сняли в одном месте и забыли в другом.
const MetaPresentedCredential = "authorization"

// MetaBridgedCredential — ВТОРАЯ форма того же удостоверения на проводе.
//
// Мост REST→gRPC переносит постоянный заголовок HTTP под приставкой
// `grpcgateway-`, ПОМИМО своего особого случая, дающего голую форму. То есть за
// краем одно и то же значение приезжает дважды и под разными ключами; снять
// одну форму и оставить вторую значит снять наполовину.
const MetaBridgedCredential = "grpcgateway-authorization" // #nosec G101 -- имя ключа метаданных, под которым мост переносит заголовок, а не удостоверение

// credentialHeaderNames — формы имени удостоверения на HTTP-поверхности.
//
// Голая — то, что предъявляет вызывающий; мостовая — то, из чего библиотека
// производит вторую форму метаданных. Обе выводятся из заголовка запроса,
// поэтому снимаются здесь, а не за мостом.
var credentialHeaderNames = []string{"authorization", BridgePrefix + "authorization"}

// StripPresentedCredential отдаёт КОПИЮ метаданных без предъявленного
// удостоверения — во всех формах ключа.
//
// Копия, а не правка на месте: входящие метаданные принадлежат запросу, и их
// изменение увидели бы звенья края, которым удостоверение ещё нужно (полоса
// выхода читает его на самом крае). Ключи метаданных gRPC регистр схлопывают
// сами, поэтому вариантов написания здесь не перебирается.
func StripPresentedCredential(md metadata.MD) metadata.MD {
	out := md.Copy()
	out.Delete(MetaPresentedCredential)
	out.Delete(MetaBridgedCredential)
	return out
}

// StripCredentialBeforeForwarding — обёртка HTTP-поверхности пересылки.
//
// Ставится ВПЛОТНУЮ к пересылающему обработчику, а не в общую цепочку края:
// цепочка обслуживает и собственные обработчики края (выход, поток изменений), а
// они удостоверение читают сами. Снятие в цепочке отобрало бы его у них —
// «после того, как край прочитал» перестало бы быть верным.
//
// Имя заголовка судится по НОРМАЛИЗОВАННОМУ виду, а не по написанному:
// вызывающий вправе прислать любой регистр, и разбор, сверяющий написание,
// пропустил бы `AUTHORIZATION` молча.
func StripCredentialBeforeForwarding(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		for name := range r.Header {
			lower := strings.ToLower(name)
			for _, want := range credentialHeaderNames {
				if lower == want {
					delete(r.Header, name)
					break
				}
			}
		}
		next.ServeHTTP(w, r)
	})
}
