package principalmeta

// auth_methods.go — форма перечня способов подтверждения на проводе.
//
// ПОЧЕМУ КОДЕК ЗДЕСЬ, А НЕ У КАЖДОЙ СТОРОНЫ. Ключ и форма его значения — один
// предмет. Производитель (полоса аутентификации) и потребитель (сборка доводов
// условия) обязаны читать ОДИН кодек: две копии разошлись бы молча и разошлись
// бы там, где расхождение не видно, — обе отвечают «разобрал» на разборном
// входе.
//
// ПОЧЕМУ НАБОР, А НЕ СПИСОК. Условие модели спрашивает о ЧЛЕНСТВЕ («webauthn
// среди применённых»), а не о порядке. Порядок здесь не значим и не
// сохраняется — и это сказано вслух, потому что умолчание «как получилось»
// читатель принял бы за обещание (`api-conventions.md` §«Пустое значение
// обязано означать пусто»).
//
// ПОЧЕМУ ФОРМА СУЖЕНА. Значение приходит из ответа стороннего поставщика
// личности, а уезжает в метаданные gRPC, где законна лишь печатаемая латиница:
// один символ вне её роняет ВЕСЬ вызов, и падает он не здесь, а на любом
// последующем обращении арендатора. Разделитель внутри элемента — вторая беда
// того же рода: он превратил бы один способ в два. Поэтому годен только токен
// вида `[a-z0-9_-]`, а всё прочее ОТБРАСЫВАЕТСЯ И НАЗЫВАЕТСЯ вызывающему —
// молчаливое выбрасывание чужого значения есть «принято-и-проигнорировано».

import "strings"

const (
	// MaxAuthMethods — потолок числа способов на проводе. Перечень приходит из
	// чужого ответа, поэтому его длина ограничивается здесь, а не надеждой на
	// поставщика. Величина взята с запасом: словари обоих известных источников
	// (RFC 8176 и провайдер сессий) вместе дают меньше половины.
	MaxAuthMethods = 16

	// MaxAuthMethodLen — потолок длины одного способа. Тот же мотив.
	MaxAuthMethodLen = 32

	// authMethodSeparator — разделитель набора. Пробел, как у `scope` в OAuth 2:
	// форма уже принята соседним ключом того же семейства, и заводить вторую
	// значило бы держать два правила об одном предмете.
	authMethodSeparator = " "
)

// validAuthMethod — годен ли способ для провода.
//
// Судит по ЗНАКАМ, а не по словарю: словарь поставщика — его дело и меняется
// без нас, а вот «пролезет ли это в метаданные и не расколется ли на два» —
// свойство знаков, и оно от поставщика не зависит.
func validAuthMethod(m string) bool {
	if m == "" || len(m) > MaxAuthMethodLen {
		return false
	}
	for i := 0; i < len(m); i++ {
		c := m[i]
		switch {
		case c >= 'a' && c <= 'z':
		case c >= '0' && c <= '9':
		case c == '_' || c == '-':
		default:
			return false
		}
	}
	return true
}

// EncodeAuthMethods сводит перечень способов к значению заголовка.
//
// Нормализует регистр и обрамляющие пробелы (`WebAuthn` и `webauthn` называют
// один способ, и различать их по написанию значило бы различать по косметике),
// снимает повторы и отбрасывает всё, что на проводе жить не может.
//
// Возвращает ВТОРЫМ значением отброшенное — целиком, в исходном виде. Вызывающий
// обязан об этом доложить: способ, которого мы не сумели передать, есть
// НАСТРОЙКА поставщика, а не заминка, и сама она не исчезнет.
func EncodeAuthMethods(methods []string) (value string, dropped []string) {
	if len(methods) == 0 {
		return "", nil
	}
	seen := make(map[string]bool, len(methods))
	kept := make([]string, 0, len(methods))
	for _, raw := range methods {
		m := strings.ToLower(strings.TrimSpace(raw))
		if !validAuthMethod(m) {
			dropped = append(dropped, raw)
			continue
		}
		if seen[m] {
			continue
		}
		if len(kept) >= MaxAuthMethods {
			dropped = append(dropped, raw)
			continue
		}
		seen[m] = true
		kept = append(kept, m)
	}
	return strings.Join(kept, authMethodSeparator), dropped
}

// DecodeAuthMethods разбирает значение заголовка обратно в набор.
//
// Применяет ТУ ЖЕ проверку формы, что и запись. Симметрия не украшение: значение
// на входе края снимается namespace-политикой и ставится заново, но читатель,
// доверяющий разбору больше, чем записи, стал бы вторым — и более
// снисходительным — правилом о том же предмете.
//
// Пустое значение даёт nil, а не пустой срез: «способов не назвали» и «способов
// ноль» здесь одно наблюдение, и оба означают, что довода нет.
func DecodeAuthMethods(value string) []string {
	if strings.TrimSpace(value) == "" {
		return nil
	}
	seen := make(map[string]bool)
	var out []string
	for _, raw := range strings.Fields(value) {
		m := strings.ToLower(raw)
		if !validAuthMethod(m) || seen[m] || len(out) >= MaxAuthMethods {
			continue
		}
		seen[m] = true
		out = append(out, m)
	}
	return out
}
