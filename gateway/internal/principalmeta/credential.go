package principalmeta

// credential.go — ПРЕДЪЯВЛЕННОЕ, собранное из тех же заголовков, что и личность.
//
// # Зачем это отдельно от [MetadataFromRequest]
//
// Тот строитель отвечает на вопрос «кого назвать соседу»; здесь — «про что
// спросить наш авторитет отзыва». Величины разные: соседу личность едет всегда,
// а спросить про отзыв можно только тем, чем удостоверение себя назвало.
//
// # Почему здесь, а не у вызывающего
//
// Имена заголовков живут в этом пакете, и второй их читатель, собранный на
// стороне, разошёлся бы с ними молча — на отсутствующем заголовке, на мостовой
// форме и на ключе, у которой мостовой формы нет вовсе.

import (
	"net/http"
	"strings"
)

// Credential — ПРЕДЪЯВЛЕННОЕ в том объёме, которым про него можно спросить наш
// авторитет отзыва (`InternalSessionRevocationsService`).
//
// # Почему НЕСКОЛЬКО величин, а не одна
//
// У авторитета три вопроса, и они не сводимы друг к другу. Про удостоверение с
// идентификатором спрашивают ПО НЕМУ (`IsRevoked`). У браузерной сессии
// идентификатора нет вовсе — ни `jti`, ни подписи, которую край мог бы
// прочитать, — и спросить про неё можно только по человеку и её носителю:
// момент аутентификации называет ответ службы о сессии по носителю
// (`Resolve`), и он же сравнивается с отсечкой субъекта (`SessionCutoffOf`). У базового секрета нет ни того, ни
// другого: он предъявительская строка, и спрашивают про него по идентификатору
// его СТРОКИ (`CheckBasicCredentialLive`). Это ровно тот же раздел полос, что
// стоит на пути ЗАПРОСА; сведи их в одну величину — и одна из полос осталась бы
// без вопроса, не сказав об этом ничем.
//
// Тип СРАВНИМ намеренно: читатель отзыва группирует потоки по удостоверению,
// чтобы не спрашивать авторитет об одном и том же по разу на вкладку.
//
// # Почему момента аутентификации здесь НЕТ (kacho#2690)
//
// Он стоял здесь и читался из довода свежести (заголовок `mfa-at`), а у того
// своя единица — секунды условия `mfa_fresh`. Отсечка же приходит в разрешении
// хранилища (микросекунды) и датируется на единицу НИЖЕ первой аутентификации
// (Ф3 §4.1 п.19), поэтому сессия, годная на пути запроса, закрывалась на
// открытом соединении: два читателя одной отсечки судили одну сессию
// по-разному. Путь запроса берёт момент из ответа службы о сессии по носителю
// — перепрос задаёт тот же вопрос тем же носителем ([Presented]) и берёт
// момент оттуда же. Второго источника одной величины не остаётся.
type Credential struct {
	// JTI — идентификатор предъявленного удостоверения. Пуст на браузерной полосе.
	JTI string
	// UserID — человек, предъявивший браузерную сессию. Пуст, когда предъявитель
	// человеком не является: отсечка ключуется людьми, и спрашивать про
	// служебную учётку по словарю людей значило бы задавать вопрос про субъекта,
	// которого в таблице не бывает.
	UserID string
	// BasicCredentialID — идентификатор СТРОКИ базового удостоверения. Пуст на
	// обеих полосах выше: у них своего вопроса к авторитету достаточно.
	//
	// Полоса третья, и она не сводится к первым двум. `JTI` у базового секрета
	// нет — он не подписанное утверждение, а предъявительская строка; `UserID`
	// у него бывает (владелец-человек), но спрашивать по нему БРАУЗЕРНУЮ отсечку
	// значило бы задавать вопрос ЧУЖОЙ полосы: путь запроса эту отсечку базовому
	// секрету не задаёт, и стоящее здесь расхождение полос никто бы не решал.
	BasicCredentialID string
	// Presented — предъявленное ЦЕЛИКОМ, которым полоса приёма спрашивала
	// службу (kacho#2900). Нужно ровно там, где вопрос по идентификатору отметку
	// адреса не называет: на полосе сессии и на полосе нашего токена. Берётся из
	// контекста запроса, а не из заголовков: см. presented.go.
	Presented Presented
}

// Askable — есть ли у авторитета вопрос про это удостоверение.
//
// Отрицательный ответ означает поток, который отзывом удостоверения закрыть
// НЕЛЬЗЯ НИ ПРИ КАКИХ УСЛОВИЯХ. Такой остаток обязан быть назван числом, а не
// выведен: «закрывать было нечего» и «закрыть было нечем» — разные состояния.
func (c Credential) Askable() bool {
	return c.JTI != "" || c.UserID != "" || c.BasicCredentialID != ""
}

// CredentialFromRequest собирает предъявленное из заголовков, выставленных
// полосой аутентификации края.
//
// Клиентские заголовки этого пространства снесены в ОБЕИХ поверхностных формах
// до того, как выбрана полоса (`stripForgeableIdentityHeaders`), поэтому
// прочитанное здесь произведено краем, а не прислано.
func CredentialFromRequest(r *http.Request) Credential {
	c := Credential{JTI: headerEither(r, HeaderGRPCMetaTokenJti, HeaderTokenJti)}
	if strings.EqualFold(headerEither(r, HeaderGRPCMetaPrincipalType, HeaderPrincipalType), "user") {
		c.UserID = headerEither(r, HeaderGRPCMetaPrincipalID, HeaderPrincipalID)
	}
	// Идентификатор базового удостоверения читается ТОЛЬКО голой формой:
	// мостовой у него нет by construction (объявлен остающимся на краю, см.
	// edgeOnlyKeys), и чтение несуществующей формы было бы чтением, которое не
	// сработает никогда, а выглядеть будет полным.
	c.BasicCredentialID = r.Header.Get(HeaderTokenBasicCredentialID)
	// Предъявленное целиком — из контекста, куда его кладёт полоса приёма после
	// своего вердикта (presented.go); заголовков у него нет намеренно.
	c.Presented = PresentedFrom(r.Context())
	return c
}
