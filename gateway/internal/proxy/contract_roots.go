package proxy

import (
	"strings"

	"github.com/PRO-Robotech/kacho/pkg/contractroot"
)

// ContractRoots — ЗАКРЫТОЕ объявленное множество корней контракта, которые край
// вправе маршрутизировать. До KAN-PKG-1 корень был литералом `"/kacho.cloud."`,
// и литералов этих в прод-коде края было ДВА: страж резолвера и функция вывода
// ключа бэкенда. Порядок между ними несущий — страж резолвера замыкается
// раньше, чем зовётся второй, — поэтому перевод одного из двух оставил бы путь
// мёртвым при зелёном прогоне на той половине, которая до второго не доходит.
// Объявление здесь одно, и читают его оба.
//
// ПУСТОЕ МНОЖЕСТВО ОЗНАЧАЕТ «НИКОГО», а не «не сужаем». Это перечень
// РАЗРЕШАЮЩЕГО вида: он не сужает уже разрешённое, а разрешает, — поэтому
// безопасен by construction только при таком чтении. Тот же разбор, что у
// перечня владельцев журнала подписки; обратный разбор («пусто = доверяем
// всем») принадлежит перечням СУЖАЮЩЕГО вида, вроде круга законных
// отправителей переданной личности, и здесь неприменим.
//
// Корней ДВА, и это не переходное состояние: платформа называет себя
// `kacho.cloud.*`, служба доступа — `kaname.cloud.*` (KAN-PKG-1, решение Р14
// замысла перехода). Окна двух имён У ОДНОЙ службы при этом не существует —
// прежнее написание службы доступа снято из контракта целиком, поэтому
// `/kaname.cloud.iam.v1.…` не резолвится не потому, что корень запрещён, а
// потому что такого метода в дескрипторах и в перечне разрешённых больше нет.
//
// Форма корня — ЧЕТЫРЁХСЕГМЕНТНАЯ (`<корень>.<домен>.<версия>.<Служба>`), и это
// требование, а не вкус: ключ бэкенда выводится ПОЗИЦИОННО третьим сегментом
// имени пакета. Трёхсегментный корень дал бы ключ `v1`, которого в карте
// бэкендов нет, — метод не резолвился бы, оставаясь в перечне разрешённых, и
// вызывающий получал бы отказ, скрывающий существование.
// Объявление ВЫВОДИТСЯ из общего словаря корней (`pkg/contractroot`), а не
// выписывается здесь: выписанный перечень был бы ВТОРЫМ объявлением того же
// предмета — тем самым, ради снятия которого словарь и заведён, — и разошёлся
// бы с ним молча при заведении третьего корня.
var ContractRoots = contractroot.PackagePrefixes()

// hasContractRoot сообщает, начинается ли полное имя метода с одного из
// объявленных корней. Имя приходит в форме "/<пакет>.<Служба>/<Метод>", поэтому
// ведущий слеш снимается здесь, а не хранится в самом перечне: перечень
// называет КОРЕНЬ КОНТРАКТА, а слеш — деталь транспорта.
func hasContractRoot(fullMethod string) bool {
	name := strings.TrimPrefix(fullMethod, "/")
	for _, root := range ContractRoots {
		if strings.HasPrefix(name, root) {
			return true
		}
	}
	return false
}
