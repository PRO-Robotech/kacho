# stage-proto-tree.sh — сборка единого buf-дерева для генераторов края.
#
# ПРЕДМЕТ. Два генератора (`gen-permission-catalog.sh`, `gen-rest-route-table.sh`)
# делают одно и то же первым шагом: раскладывают доменные `.proto` во временный
# каталог, чтобы скормить их buf одним модулем. Раскладка у них была ОДИНАКОВОЙ и
# лежала ДВУМЯ рукописными копиями — пятнадцать строк `cp -R` в каждой.
#
# ЧЕМ ЭТО ПЛОХО, ИЗМЕРЕННО. Копии стареют не вместе. Пакет, заведённый в `proto/`
# и не дописанный сюда, в стадию не попадает — и генератор падает не своим
# сообщением, а компилятором: «imported file does not exist», координатой чужого
# файла. Наблюдалось 2026-08-15 при заведении общего пакета `kacho/cloud/quota`:
# упали ОБА генератора, по очереди, одинаково — то есть чинить пришлось бы дважды
# и второй раз уже после того, как первый «починен».
#
# РЕШЕНИЕ. Перечень ВЫВОДИТСЯ из дерева: копируется всё под объявленными корнями
# контракта, кроме явно исключённого. Список исключений — один, здесь, и он
# проверяется на наличие предмета: запись, которой больше нечего исключать, —
# находка, а не безобидный остаток (иначе она унаследует следующую слепую зону).
#
# КОРНЕЙ КОНТРАКТА ДВА, и отбор популяции идёт по ОБЪЯВЛЕННОМУ множеству, а не по
# литералу приставки (KAN-PKG-1). Платформа называет себя `kacho`, служба доступа
# — `kaname`. Литерал оставил бы дерево службы вне обхода, и оба генератора
# честно напечатали бы «скопировано N» по опустевшей популяции: каталог вышел бы
# БЕЗ записей службы, то есть с отказом в доступе на всей её поверхности, а
# прогон остался бы зелёным. Поэтому корень — не приставка в коде, а запись
# перечня, и домен резолвится в свой корень обходом дерева.
#
# ОТБОР ДОМЕНОВ (заведён вместе с разрезом на отдельные продукты). Домен,
# вынесенный в свой репозиторий, получает дерево контрактов ВНЕШНЕЙ зависимостью,
# то есть ЦЕЛИКОМ — урезать его он не вправе. Значит сузить выход обязан отбор, а
# не форма дерева. Отбор — четвёртый аргумент, строка имён через пробел; пусто
# означает «все домены дерева» и воспроизводит прежнее поведение побайтово.
#
# ЗАМЫКАНИЕ ИМПОРТОВ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ. Домен не компилируется в
# одиночку: `kaname/cloud/iam` импортирует `kacho/cloud/operation` и
# `corelib/api/v1` — то есть замыкание пересекает границу корней. Рукописный
# перечень «что ещё нужно iam» был бы ровно той
# второй копией, ради снятия которой этот файл и заведён, — поэтому недостающие
# деревья добираются обходом `import`-строк до неподвижной точки.
#
# НЕЙТРАЛЬНЫЕ КОРНИ ФУНДАМЕНТА — ТОЖЕ ВЫВОДЯТСЯ (kacho#1110). Корень без сегмента
# `cloud` (`corelib/<дерево>/v1`) отбором не сужается: его словарём размечает свои
# методы каждый домен, поэтому стадия несёт его целиком. Здесь до kacho#1110
# стоял единственный на весь файл рукописный перечень — по строке `cp -R` на
# поддерево, — и он был полон ровно на день своей правки. Свойство утверждает ось
# A12 гейта разреза, чья популяция выводится ОТДЕЛЬНЫМ обходом.
#
# Использование:
#   source "$(dirname "$0")/lib/stage-proto-tree.sh"
#   stage_proto_tree "${PROTO_ROOT}" "${STAGE}" "<имя-генератора>" ["<домен> <домен> …"]

# KACHO_PROTO_ROOTS — объявленное закрытое множество корней дерева контрактов.
# Пусто означало бы «ни одного корня», то есть пустую стадию, и обход ниже роняет
# прогон на нуле скопированных деревьев.
KACHO_PROTO_ROOTS=(kacho kaname corelib)

# kacho_proto_tree_root — корень, под которым лежит дерево домена. Резолвится
# ОБХОДОМ объявленных корней, а не выводится из имени: имя домена о своём корне
# ничего не сообщает, и вывод по имени был бы второй копией этого перечня.
kacho_proto_tree_root() {
  local proto_root=$1 tree=$2 root
  for root in "${KACHO_PROTO_ROOTS[@]}"; do
    if [[ -d "${proto_root}/${root}/cloud/${tree}" ]]; then
      echo "${root}"
      return 0
    fi
  done
  return 1
}

# Каталоги под корнями контракта, которые в стадию НЕ идут.
#
# `apigateway` — служебный сервис самого края: он не входит ни в публичный, ни в
# доменный каталог прав и не выставляет tenant-facing REST-маршрутов, поэтому его
# присутствие в стадии добавило бы в оба выхода записи, которых там быть не должно.
KACHO_PROTO_STAGE_EXCLUDE=()

# kacho_proto_tree_imports — деревья под объявленными корнями, на которые
# ссылаются `import`-строки файлов одного дерева. Читается синтаксис объявления
# импорта, а не любое вхождение пути: путь встречается и в комментариях.
#
# Образец собирается ИЗ ПЕРЕЧНЯ корней, а не пишется литералом: импорт через
# границу корней законен и существует (контракт службы доступа импортирует
# `kacho/cloud/operation`), и корень, о котором образец не знает, дал бы
# молчание, неотличимое от отсутствия импорта.
kacho_proto_tree_imports() {
  local proto_root=$1 tree=$2 root alt lines names
  root="$(kacho_proto_tree_root "${proto_root}" "${tree}")" || return 0
  alt="$(IFS='|'; echo "${KACHO_PROTO_ROOTS[*]}")"
  lines="$(grep -rhE "^[[:space:]]*import[[:space:]]+(public[[:space:]]+)?\"(${alt})/cloud/[^\"]+\"[[:space:]]*;" \
    "${proto_root}/${root}/cloud/${tree}" 2>/dev/null || true)"
  [[ -n "${lines}" ]] || return 0

  # Имя дерева берётся ТРЕТЬИМ сегментом пути в кавычках (`<корень>/cloud/<дерево>/…`)
  # разбором полей, а НЕ подстановкой с интерполяцией перечня корней.
  #
  # Здесь стояла подстановка `sed -E "s|…(${alt})…|\2|"`, где разделителем
  # s-команды был тот же знак `|`, которым склеен перечень корней. Пока корень был
  # ОДИН, перечень знака не содержал и подстановка работала; со вторым корнем
  # (KAN-PKG-1) `alt` стал `kacho|kaname`, и sed разбирал `s|…"(kacho|` как
  # завершённую s-команду с неизвестным модификатором — то есть УМИРАЛ на каждом
  # вызове. Отказ уходил в stderr, `sort -u` получал пустой вход, функция
  # возвращала пустоту, и замыкание честно печатало «добрано: (нечего)» — форма,
  # НЕОТЛИЧИМАЯ от «этому дереву ничего не нужно».
  #
  # Молчание не проявлялось на умолчании: при пустом отборе копируются ВСЕ
  # деревья, и замыканию нечего добавлять by construction. Механизм был мёртв
  # ровно в том режиме, ради которого заведён, — в порождении по отбору, то есть
  # у вынесенного в свой репозиторий домена.
  names="$(printf '%s\n' "${lines}" \
    | awk -F'"' '{ n = split($2, seg, "/"); if (n >= 4 && seg[2] == "cloud" && seg[3] != "") print seg[3] }' \
    | sort -u)"

  # Проверка СВОЕЙ предпосылки: строки импорта прочитаны, а имён не извлечено ни
  # одного — это отказ разборщика, а не отсутствие импортов. Молчаливый возврат
  # пустоты здесь и был предметом фикса выше.
  if [[ -z "${names}" ]]; then
    echo "ERR: kacho_proto_tree_imports: в дереве '${tree}' прочитано строк импорта:" >&2
    printf '%s\n' "${lines}" | wc -l | sed 's/^/       /' >&2
    echo "     а имён деревьев извлечено 0 — разбор пути импорта отказал." >&2
    echo "     Ноль извлечённых при непустом входе — находка, а не «импортов нет»." >&2
    return 1
  fi
  printf '%s\n' "${names}"
}

# --------------------------------------------------------------------------
# Распознаватель ЭМИТИРОВАННЫХ доменов — общий на оба генератора и на гейт.
#
# ПРЕДМЕТ. Оба генератора и гейт спрашивают одно и то же: какие домены попали в
# выход. Спрашивали они это ТРЕМЯ рукописными подстановками с ЛИТЕРАЛОМ приставки
# `kacho.cloud.`, и с появлением второго корня (KAN-PKG-1) все три ослепли на
# дереве службы: имя её метода начинается `kaname.cloud.iam.`, под литерал не
# подпадает и в перечень эмитированных не попадает ВОВСЕ. Проверка при этом
# краснеть не начинала — она молчала, а перепись «эмитировано доменов: N»
# называла заниженное число, не сообщая, что треть выхода ею не прочитана.
#
# Здесь корень сверяется с ОБЪЯВЛЕННЫМ множеством `KACHO_PROTO_ROOTS` — тем же,
# по которому идёт раскладка, — а не с приставкой в коде. Разбор идёт по полям
# имени, поэтому перечень корней ни в какую подстановку не интерполируется.
#
# kacho_proto_output_fqns <файл> <ключ> — полные имена методов выхода.
#   ключ: `"fqn"` у каталога (JSON), `FQN` у таблицы маршрутов (Go).
kacho_proto_output_fqns() {
  local out=$1 key=$2
  # Имя берётся ПОСЛЕДНИМ полем в кавычках, а не полем с фиксированным номером:
  # ключ выхода бывает в кавычках сам (`"fqn"` у JSON) и без них (`FQN` у Go), и
  # номер поля у этих двух форм РАЗНЫЙ. Фиксированный номер читал бы у одной из
  # форм ключ вместо имени и возвращал бы пустой перечень доменов — то же
  # молчание, ради снятия которого распознаватель и сведён в одно место.
  grep -oE "${key}: \"[^\"]+\"" "${out}" 2>/dev/null | awk -F'"' '{ print $(NF - 1) }'
}

# kacho_proto_emitted_pairs — пары «корень⇥домен» имён выхода, уникальные.
# Одно место разбора: перечни корней и доменов ниже ВЫВОДЯТСЯ отсюда, а не
# разбирают имя во второй раз.
kacho_proto_emitted_pairs() {
  local out=$1 key=$2 roots
  roots="$(printf '%s\n' "${KACHO_PROTO_ROOTS[@]}")"
  kacho_proto_output_fqns "${out}" "${key}" \
    | awk -v roots="${roots}" '
        BEGIN { n = split(roots, r, "\n"); for (i = 1; i <= n; i++) known[r[i]] = 1 }
        { m = split($0, seg, "."); if (m >= 3 && (seg[1] in known) && seg[2] == "cloud" && seg[3] != "") print seg[1] "\t" seg[3] }
      ' \
    | sort -u
}

# kacho_proto_emitted_domains — домены выхода (третий сегмент имени).
kacho_proto_emitted_domains() {
  kacho_proto_emitted_pairs "$1" "$2" | cut -f2 | sort -u
}

# kacho_proto_output_roots — корни, чьи домены РАСПОЗНАНЫ.
#
# Величина НЕ равна «корням, чьи имена в выходе есть»: вторую даёт чистый разбор
# имени, без сверки с перечнем, и именно расхождение двух величин обнажает
# слепоту распознавателя. Независимую половину меряет тот, кто проверяет
# (см. ось A10 гейта разреза), — здесь её заводить нельзя: обе стороны сверки в
# одном разборе разошлись бы вместе и молча.
kacho_proto_output_roots() {
  kacho_proto_emitted_pairs "$1" "$2" | cut -f1 | sort -u
}

stage_proto_tree() {
  local proto_root=$1
  local stage=$2
  local caller=${3:-stage-proto-tree}
  local selection_raw=${4:-}

  local _root
  for _root in "${KACHO_PROTO_ROOTS[@]}"; do
    [[ -d "${proto_root}/${_root}/cloud" ]] || continue
    mkdir -p "${stage}/${_root}/cloud"
  done

  # --- общая инфраструктура ---
  #
  # Здесь стояла ТРЕТЬЯ строка — безусловное копирование `kacho/cloud/validation.proto`,
  # объявлявшего семейство ограничений полей. Файл снят вместе с семейством (kacho#1255):
  # исполнителя на пути запроса у него не было ни одного. Строка была БЕЗУСЛОВНОЙ, а оба
  # зовущих генератора идут под `set -euo pipefail`, поэтому её пропуск ронял их обоих на
  # `cp: cannot stat`, то есть раньше, чем они успевали произвести хоть что-нибудь. Ни
  # `buf breaking`, ни перепись читателей на Go этого пути не видят — он живой и
  # единственный такой.
  cp -R "${proto_root}/google"             "${stage}/google"

  # --- НЕЙТРАЛЬНЫЕ корни фундамента: целиком и безусловно -------------------
  #
  # Нейтральный корень — объявленный корень контракта, чья раскладка НЕ несёт
  # сегмента `cloud` (`corelib/<дерево>/v1`). Домена у него нет by construction,
  # а весь обход деревьев ниже построен на `<корень>/cloud/<дерево>` — поэтому
  # отбор его не касается вовсе, и стадия обязана нести его ЦЕЛИКОМ: словарём
  # фундамента размечает свои методы КАЖДЫЙ домен, «нужного подмножества» у него
  # не существует.
  #
  # ЗДЕСЬ СТОЯЛ РУКОПИСНЫЙ ПЕРЕЧЕНЬ — по строке `cp -R` на поддерево
  # (`corelib/authz/v1`, затем `corelib/api/v1`), единственный на всю раскладку:
  # продуктовые корни она ОБХОДИТ. Перечень был полон ровно на день своей
  # правки, а третье поддерево пропускал бы МОЛЧА — и молчание это двойное:
  # пока поддерево никто не импортирует, гейт разреза даёт код 0 и 0 находок;
  # когда импорт появляется, отказ достаётся не тому, кто поддерево завёл, и
  # называет симптом («порождение полного каталога отказало» плюс сотня строк
  # компилятора) вместо причины. Цена этого класса уже платилась однажды —
  # kacho#2433, когда сюда не доехала аннотация операции.
  #
  # Перечень теперь ВЫВОДИТСЯ из дерева контрактов. Свойство утверждает ось A12
  # гейта разреза, и её популяция выводится ОТДЕЛЬНЫМ обходом — проверяющий не
  # вправе брать ожидание у проверяемого.
  local _neutral _staged_neutral=0
  for _neutral in "${KACHO_PROTO_ROOTS[@]}"; do
    [[ -d "${proto_root}/${_neutral}" ]]       || continue
    [[ -d "${proto_root}/${_neutral}/cloud" ]] && continue
    rm -rf "${stage:?}/${_neutral}"
    cp -R "${proto_root}/${_neutral}" "${stage}/${_neutral}"
    _staged_neutral=$((_staged_neutral + 1))
  done
  if [[ "${_staged_neutral}" -eq 0 ]]; then
    echo "${caller}: нейтральных корней фундамента не найдено —" \
         "стадия не понесёт ни словаря разметки, ни аннотации операции" >&2
    return 1
  fi

  # --- исключения обязаны иметь предмет ---
  local excluded
  for excluded in "${KACHO_PROTO_STAGE_EXCLUDE[@]}"; do
    if ! kacho_proto_tree_root "${proto_root}" "${excluded}" >/dev/null; then
      echo "ERR: ${caller}: исключение '${excluded}' не имеет предмета —" >&2
      echo "     дерева '${excluded}' нет ни под одним объявленным корнем" >&2
      echo "     (${KACHO_PROTO_ROOTS[*]})." >&2
      echo "     Запись, которой больше нечего исключать, — находка: снимите её" >&2
      echo "     из KACHO_PROTO_STAGE_EXCLUDE, иначе она молча унаследует" >&2
      echo "     следующую слепую зону." >&2
      return 1
    fi
  done

  # --- перечень деревьев дерева, выведенный из дерева ---
  local tree name skip root
  local -a present=()
  for root in "${KACHO_PROTO_ROOTS[@]}"; do
    for tree in "${proto_root}/${root}"/cloud/*/; do
      [[ -d "${tree}" ]] || continue
      name="$(basename "${tree}")"
      skip=0
      for excluded in "${KACHO_PROTO_STAGE_EXCLUDE[@]}"; do
        [[ "${name}" == "${excluded}" ]] && skip=1
      done
      [[ "${skip}" -eq 1 ]] && continue
      present+=("${name}")
    done
  done

  # --- отбор ---
  local -a selected=()
  if [[ -z "${selection_raw// /}" ]]; then
    selected=("${present[@]}")
  else
    read -r -a selected <<< "${selection_raw}"
    for name in "${selected[@]}"; do
      if ! kacho_proto_tree_root "${proto_root}" "${name}" >/dev/null; then
        echo "ERR: ${caller}: выбранного домена '${name}' нет в дереве контрактов" >&2
        echo "     ни под одним объявленным корнем (${KACHO_PROTO_ROOTS[*]}) —" >&2
        echo "     отбор назвал то, чего нет." >&2
        return 1
      fi
    done
  fi

  # --- замыкание импортов до неподвижной точки ---
  local -A in_closure=()
  local -a queue=() closure_order=()
  for name in "${selected[@]}"; do
    [[ -n "${in_closure[${name}]:-}" ]] && continue
    in_closure[${name}]=1
    closure_order+=("${name}")
    queue+=("${name}")
  done
  local -a added_by_closure=()
  local head dep deps
  while [[ ${#queue[@]} -gt 0 ]]; do
    head="${queue[0]}"
    queue=("${queue[@]:1}")
    # Разбор импортов зовётся ПОДСТАНОВКОЙ КОМАНДЫ, а не подстановкой процесса:
    # у `< <(…)` код возврата производителя не виден вызывающему вовсе, поэтому
    # отказ разборщика приходил сюда как «импортов нет» и молча давал неполную
    # стадию, которую buf ронял чужим сообщением компилятора.
    if ! deps="$(kacho_proto_tree_imports "${proto_root}" "${head}")"; then
      echo "ERR: ${caller}: разбор импортов дерева '${head}' отказал —" >&2
      echo "     замыкание собралось бы неполным, а стадия вышла бы без" >&2
      echo "     деревьев, на которые '${head}' ссылается." >&2
      return 1
    fi
    while IFS= read -r dep; do
      [[ -n "${dep}" ]] || continue
      [[ -n "${in_closure[${dep}]:-}" ]] && continue
      if ! kacho_proto_tree_root "${proto_root}" "${dep}" >/dev/null; then
        echo "ERR: ${caller}: '${head}' импортирует дерево '${dep}', а такого" >&2
        echo "     дерева в ${proto_root} нет ни под одним объявленным корнем" >&2
        echo "     (${KACHO_PROTO_ROOTS[*]}) — стадия собралась бы неполной и buf" >&2
        echo "     упал бы чужим сообщением компилятора." >&2
        return 1
      fi
      in_closure[${dep}]=1
      closure_order+=("${dep}")
      added_by_closure+=("${dep}")
      queue+=("${dep}")
    done <<< "${deps}"
  done

  # --- копирование ---
  local copied=0
  local -A copied_per_root=()
  for name in "${closure_order[@]}"; do
    root="$(kacho_proto_tree_root "${proto_root}" "${name}")"
    cp -R "${proto_root}/${root}/cloud/${name}" "${stage}/${root}/cloud/${name}"
    copied=$((copied + 1))
    copied_per_root[${root}]=$(( ${copied_per_root[${root}]:-0} + 1 ))
  done

  # --- стадия НАША, и её режим не наследуется от источника ------------------
  #
  # Дерево контрактов приезжает вынесенному домену из КЭША МОДУЛЕЙ, а кэш
  # read-only: каталоги 555, файлы 444. Это не свойство машины — это форма, в
  # которой Go раскрывает модуль, то есть единственная форма, которой
  # потребитель располагает. `cp -R` режим источника СОХРАНЯЕТ, поэтому
  # каталоги стадии выходят 555, а создать в каталоге запись (mkdir, unlink)
  # можно только имея право записи на КАТАЛОГ.
  #
  # Отказывало это ДВАЖДЫ и по-разному:
  #   * зовущий генератор кладёт в стадию anchor-файл, и его каталог лежит ПОД
  #     нейтральным корнем (`corelib/authz/catalog/v1`) — `mkdir -p` внутри
  #     скопированного поддерева отказывает, порождение даёт НОЛЬ выхода и
  #     печатает `mkdir: Permission denied`, не называя ни пути, ни причины;
  #   * `rm -rf` в trap-е уборки отказывает, и генератор выходит кодом 1, УЖЕ
  #     НАПИСАВ верный выход, — вердикт ложен в ОБЕ стороны: читающий код
  #     заключает «порождение отказало», не читающий копит неудаляемый мусор.
  #
  # Механизм установлен ОДНО-ФАКТНЫМ опытом: та же стадия, `chmod u+w` ТОЛЬКО
  # на каталогах — `rm -rf` даёт 0; файлы при 444 значения не имеют, потому что
  # unlink спрашивает право у каталога, а не у файла. Поэтому правится режим
  # каталогов, а не всего поддиректории: снимать защиту с файлов не за что.
  #
  # Свойство утверждает ось A13 гейта разреза (порождение от read-only дерева
  # даёт код 0 и побайтово тот же выход).
  find "${stage}" -type d -exec chmod u+w {} +

  # Перепись: «ноль находок» обязано быть отличимо от «ноль прочитанного».
  # Печатается число ПО КАЖДОМУ корню: одно суммарное число скрыло бы ровно тот
  # случай, ради которого перечень корней заведён, — корень, из которого не
  # скопировано ни одного дерева.
  local per_root_census="" _r
  for _r in "${KACHO_PROTO_ROOTS[@]}"; do
    per_root_census+=" ${_r}=${copied_per_root[${_r}]:-0}"
  done
  echo "${caller}: деревьев контракта скопировано ${copied} (по корням:${per_root_census})," \
       "исключено: ${KACHO_PROTO_STAGE_EXCLUDE[*]}"
  echo "${caller}: отбор доменов: ${selected[*]}" \
       "· добрано замыканием импортов: ${added_by_closure[*]:-(нечего)}"

  if [[ "${copied}" -eq 0 ]]; then
    echo "ERR: ${caller}: под корнями (${KACHO_PROTO_ROOTS[*]}) не скопировано ни" >&2
    echo "     одного дерева — выход собрался бы из пустоты и вышел бы успехом." >&2
    return 1
  fi
}
