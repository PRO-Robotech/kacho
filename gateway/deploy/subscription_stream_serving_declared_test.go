// subscription_stream_serving_declared_test.go — посредники перед краем обязаны
// называть ТОТ ЖЕ адрес, который край объявляет ручкой.
//
// # Предмет — ШОВ, а не маршрутизация
//
// Маршрутизацию (какой блок раздачи выигрывает адрес, снято ли накопление,
// переживает ли предел ожидания срок жизни потока) держит проба со стороны
// консоли — `ui-future/deploy/subscription_stream_serving_test.go`. Здесь она не
// пересказывается: два места об одном предмете расходятся молча.
//
// Здесь предмет один и он оттуда недостижим. Та проба вынуждена ПОВТОРИТЬ
// величину адреса своей строкой: ручка живёт под `gateway/internal`, а внутренние
// пакеты одного поддерева невидимы другому — это свойство языка, а не
// небрежность. Повторённая величина расходится молча: край переименует путь,
// объявления посредников останутся прежними, и обе стороны будут по-своему правы.
//
// Эта проба смотрит с той стороны, где величина ПОДЛИННАЯ: она берёт константу
// ручки и требует, чтобы объявления посредников её несли. Разойдись значения —
// краснеет здесь, с обоими текстами в находке.
//
// # Почему сверяется ТЕКСТ объявления
//
// Объявления посредников — не Go: это шаблон раздачи и шаблон входа. Их предмет
// (адрес маршрута) выражен в них строкой, поэтому сверка строки здесь сверяет
// именно предмет, а не его описание. Разбор синтаксического дерева тут не
// применим — дерева нет.
//
// Перепись печатается всегда: «ноль находок» обязано быть отличимо от «ноль
// прочитанного», а обход пустого перечня — отказ.
func TestServingDeclarationsNameTheSubscriptionStreamPath(t *testing.T) {
	// Объявления, обязанные назвать адрес: раздача консоли (её блок решает, куда
	// уйдёт запрос) и внешний вход для потока (его пометки решают, каким придёт
	// ответ). Перечень короткий и выписан намеренно: он и есть утверждение о
	// том, СКОЛЬКО посредников стоит перед этой ручкой.
	declarations := []string{
		filepath.Join("..", "..", "ui-future", "deploy", "templates", "configmap-nginx.yaml"),
		filepath.Join("..", "..", "ui-future", "deploy", "templates", "ingress-subscription-stream.yaml"),
	}

	path := subscriptionstream.Path
	read, naming := 0, 0
	for _, rel := range declarations {
		raw, err := os.ReadFile(rel) // #nosec G304 -- обход собственного дерева
		if err != nil {
			t.Errorf("объявление посредника %s не читается (%v): адрес потока обязан быть "+
				"назван им, а прочитать нечего", filepath.ToSlash(rel), err)
			continue
		}
		read++
		if strings.Contains(string(raw), path) {
			naming++
			continue
		}
		t.Errorf("объявление посредника %s не называет адрес ручки %q, который объявляет "+
			"край (`subscriptionstream.Path`). Непокрытый адрес достаётся заглушке "+
			"одностраничного приложения: она отдаёт `index.html` с кодом `200` и типом "+
			"`text/html`, а приёмник событий браузера на неверном типе закрывает соединение "+
			"навсегда и выдаёт ошибку без подробностей — со стороны это тишина.",
			filepath.ToSlash(rel), path)
	}

	t.Logf("перепись: адрес ручки %q · объявлений посредников %d · прочитано %d · называют адрес %d",
		path, len(declarations), read, naming)

	if read == 0 {
		t.Fatal("не прочитано ни одного объявления посредника — прочитано ноль, и молчание " +
			"пробы не является утверждением о согласии величин")
	}
}
