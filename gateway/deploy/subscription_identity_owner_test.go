// subscription_identity_owner_test.go — служба доступа ОБЪЯВЛЕНА владельцем
// журнала, чей поток край проецирует.
//
// # Предмет
//
// Словарь владельцев край строит ИЗ ЭТОГО ПЕРЕЧНЯ, а не из карты соединений:
// домен, до которого край умеет дозвониться, но которого перечень не назвал,
// отвечает вызывающему `400 unknown owner`. Значит имя в перечне — единственное,
// чем возможность включается, и его снятие снимает возможность целиком.
//
// Снятие при этом НИЧЕГО не роняет само по себе: перечень остаётся непустым,
// край поднимается, ручка отвечает — просто на один домен меньше. Отличить
// «решили, что подписка этому владельцу не нужна» от «имя потерялось при правке
// соседней величины» по дереву нечем, и эта проба ровно та разница.
//
// # Почему имя ЛИТЕРАЛОМ, а не выведено
//
// Предмет утверждения — РЕШЕНИЕ («край подписывается на журнал службы доступа»),
// а не факт дерева. Вывести его отсюда нельзя: служит ли владелец глагол —
// свойство ЕГО репозитория, и здешнее дерево о нём не знает (сервер потока
// поднимает `cmd/kaname`). Литерал, выведенный из того, что видно здесь, сказал
// бы не то: карта соединений несёт внутренний адрес и у `geo`, который журнала не
// служит вовсе.
//
// Поэтому литерал, и поэтому же он не голый: рядом проверяется, что край это имя
// РЕЗОЛВИТ. Имя, объявленное владельцем и не резолвимое, — отказ СТАРТА края, и
// узнать о нём на выкатке дороже, чем здесь.
//
// # Предикат снятия
//
// Решат, что край службе не подписчик, — эта проба снимается ТЕМ ЖЕ изменением,
// что и имя в перечне. Остаться она не может: её красное тогда будет верным
// утверждением о несуществующем решении.
func TestProfileDeclaresTheIdentityServiceAsAJournalOwner(t *testing.T) {
	// Написание владельца — домен КОНТРАКТА (`kacho.cloud.iam.v1`), а не имя
	// продукта, которому служба принадлежит, и не каталог её исходников.
	const identityOwner = "iam"

	declared := declaredSubscriptionOwners(t)
	accepted := config.Config{}.DomainsWithInternalBackend()
	repo, external := ownerSourcedElsewhere(identityOwner)

	t.Logf("перепись: профиль объявил владельцев %d %v · край принимает %d %v · "+
		"исходники владельца %q в другом репозитории: %t (%s)",
		len(declared), declared, len(accepted), accepted, identityOwner, external, repo)

	if len(accepted) == 0 {
		t.Fatal("край не принимает НИ ОДНОГО имени владельца — карта соединений пуста, " +
			"и утверждение ниже было бы вынесено о пустоте")
	}

	if !slices.Contains(accepted, identityOwner) {
		t.Fatalf("край не резолвит %q в соединение (принимает %v): объявить такого владельца "+
			"значит получить ОТКАЗ СТАРТА края — подписка живёт только на внутреннем "+
			"слушателе владельца, и дозвониться до него нечем. Чинится не этим перечнем, "+
			"а внутренним адресом домена в карте соединений",
			identityOwner, accepted)
	}

	if !slices.Contains(declared, identityOwner) {
		t.Errorf("профиль края (%s) объявил владельцами %v, и %q среди них нет: край умеет "+
			"дозвониться до этого домена, но словарь владельцев строится из перечня, а не "+
			"из карты соединений — значит подписка на его ресурсы отвечает `400 unknown "+
			"owner` КАЖДОМУ вызывающему, и возможность выключена целиком.\nЕсли имя снято "+
			"осознанно — снимите и эту пробу тем же изменением: иначе она утверждает "+
			"решение, которого больше нет",
			edgeValuesRel, declared, identityOwner)
	}

	// Сторона владельца названа вслух: его потолок потоков объявлен в ЕГО дереве,
	// поэтому арифметика «реплики × потолок» здесь не выполняется ни разу.
	// Молчание об этом читалось бы как «осмотрели и сошлось» —
	// см. TestReplicaFanoutFitsUnderTheOwnerCeiling.
	if external {
		t.Logf("НЕ СУДИЛОСЬ: потолок потоков владельца %q объявлен в %s — арифметика "+
			"«реплики × потолок» для него не выполнена здесь ни разу", identityOwner, repo)
	}
}
