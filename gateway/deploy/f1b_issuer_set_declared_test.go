// f1b_issuer_set_declared_test.go — перечень принимаемых издателей ОБЪЯВЛЯЕТСЯ
// стендом, а не достаётся ему умолчанием из ручек ЧУЖОГО издателя.
//
// # Предмет
//
// У приёма токена на крае два пути. Объявленный: стенд называет издателей и
// адрес набора ключей у каждого. Запасной: перечень не объявлен вовсе, и край
// строит ОДНУ запись из прежнего скалярного пина — `KACHO_HYDRA_ISSUER` и
// `KACHO_HYDRA_JWKS_URL`, то есть из адресов чужого издателя.
//
// Запасной путь сам по себе исправен: обе его половины объявляются, ни одна не
// выводится, и неполный пин даёт отказ при СТАРТЕ. Неисправно другое — то, что
// стенд может им пользоваться МОЛЧА. Якорь доверия проверки подписи приезжает
// туда, где оператор его не называл, а читающий профиль видит настроенную
// посадку: ручки чужого издателя непусты, перечня нет, и отличить «решено
// принимать прежнего издателя» от «никто не переводил» нечем.
//
// Отсюда предмет этой пробы, и он УЖЕ: не «путь исправен» (это предмет проб у
// самого разборщика), а «ни один живой стенд по нему не идёт».
//
// # Почему это предусловие СНЯТИЯ запасного пути, а не само снятие
//
// Снять ручки чужого издателя раньше, чем каждый стенд объявил перечень сам,
// значит уронить приём токенов на том стенде, который ими пользовался, — и
// уронить молча: отказ придёт не рендеру и не прогону, а арендатору на первом
// же запросе. Эта проба краснеет РОВНО НА ТОМ состоянии, из-за которого снятие
// опасно, и потому её зелёное — и есть предикат, открывающий следующий шаг.
//
// # Единица суждения — СТЕНД
//
// Слой, несущий одни образы или одну посадку, приёма не объявляет и не обязан:
// он его НАСЛЕДУЕТ. Судить такой слой в одиночку значит спрашивать о контракте
// у половины его текста. Цепочка берётся из `deploy/stacks.txt` — единственного
// места в дереве, где она объявлена.
//
// # Чего здесь НЕ проверяется
//
// Не проверяется, что объявление даёт поднимающийся процесс: это предмет
// `TestF1b_EveryStackDeclaresAnAcceptanceTheProcessWillBoot`, и второе
// утверждение об одном предмете разошлось бы с первым молча. Не проверяется и
// то, что объявленные адреса отвечают: это свойство поднятого кластера.
package deploy_test

import (
	"fmt"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/gateway/internal/config"
)

// f1bIssuerSetFindings — находки об ОДНОМ объявлении приёма: чем оно
// объявлено и откуда приехал адрес набора у каждой записи.
//
// Вердикт вынесен ОДНИМ местом намеренно: его спрашивают двое — обход живых
// стендов ниже и самопроверка на синтетике, — и две формулировки одного
// вопроса разошлись бы молча ровно там, где расхождение не видно.
//
// Спрашивается при этом НАСТОЯЩИЙ читатель: `DeclaresTokenIssuerSet` — тот же
// предикат, который исполняет процесс при старте, а `SourceKnob` — та же
// величина, которую процесс кладёт в запись приёма. Ни имя ручки, ни признак
// объявленности здесь не выписаны литералом: выписанный литерал разошёлся бы с
// продуктом при переименовании, то есть ровно тогда, когда проба обязана
// покраснеть.
func f1bIssuerSetFindings(cfg config.Config) []string {
	var out []string
	if !cfg.DeclaresTokenIssuerSet() {
		out = append(out, fmt.Sprintf("перечень издателей НЕ ОБЪЯВЛЕН (%s пуст): "+
			"приём строится ОДНОЙ записью из ручек ЧУЖОГО издателя "+
			"(KACHO_HYDRA_ISSUER=%q / %s=%q)",
			config.KnobDeclaredIssuers, cfg.HydraIssuer, config.KnobLegacyKeySet, cfg.HydraJWKSURL))
	}
	bindings, err := cfg.TokenAcceptance()
	if err != nil {
		// Отказ разборщика — предмет СОСЕДНЕЙ пробы, и он здесь не пересужается.
		// Но и промолчать нельзя: без записей вопрос «из чьей ручки приехал
		// адрес» остался бы незаданным, а молчание читалось бы как «ни одна
		// запись не пришла от чужой ручки».
		return append(out, fmt.Sprintf("объявление не разбирается, и вопрос об источнике "+
			"адреса остался НЕЗАДАННЫМ: %v", err))
	}
	for _, b := range bindings {
		if b.SourceKnob == config.KnobLegacyKeySet {
			out = append(out, fmt.Sprintf("запись издателя %q взяла адрес набора %q из ручки "+
				"%s — якорь доверия проверки подписи приехал оттуда, где стенд его не называл",
				b.Issuer, b.KeySetURL, config.KnobLegacyKeySet))
		}
	}
	return out
}

// TestF1b07_EveryLiveStackDeclaresItsIssuerSetExplicitly — каждый стенд,
// поднимающий край, объявляет перечень издателей САМ.
func TestF1b07_EveryLiveStackDeclaresItsIssuerSetExplicitly(t *testing.T) {
	stacks := deployableStacks(t)
	if len(stacks) == 0 {
		t.Fatalf("прочитано НОЛЬ стендов — «ноль находок» на таком объёме означало бы " +
			"«ноль прочитанного», и молчание этой пробы сказано ни о чём")
	}

	carrying, declaring := 0, 0
	for _, name := range f1bSortedKeys(stacks) {
		stack := stacks[name]
		cfg, declaresAcceptance := f1bStackAcceptance(t, stack)
		if !declaresAcceptance && strings.TrimSpace(cfg.HydraIssuer) == "" &&
			strings.TrimSpace(cfg.HydraJWKSURL) == "" {
			// Стенд, не называющий края вовсе, судить нечем — и это отличается
			// от «назвал и унаследовал чужое».
			continue
		}
		carrying++
		findings := f1bIssuerSetFindings(cfg)
		if len(findings) == 0 {
			declaring++
			continue
		}
		t.Errorf("стенд %s (%s) НЕ ОБЪЯВЛЯЕТ своего перечня издателей:\n  · %s\n\n"+
			"Пока это так, ручки чужого издателя снимать нельзя: снятие уронит приём "+
			"токенов на этом стенде МОЛЧА — отказ придёт не рендеру и не прогону, а "+
			"арендатору на первом же запросе. Объявите `%s.tokenAcceptance.issuers` и "+
			"`.issuerKeySets` теми же адресами, что стоят в пине сейчас, и очистите сам "+
			"пин: два объявления об одном предмете разборщик отвергает.",
			name, strings.Join(stack, " + "), strings.Join(findings, "\n  · "), edgeChartKey)
	}

	if carrying == 0 {
		t.Fatal("ни один стенд не несёт объявления края — предпосылка пробы отказала, и её " +
			"молчание не означает исправного дерева")
	}
	t.Logf("перепись: стендов объявлено %d · несут объявление края %d · объявляют перечень "+
		"издателей САМИ %d · получают его умолчанием из ручек чужого издателя %d",
		len(stacks), carrying, declaring, carrying-declaring)
}

// TestF1b07_TheIssuerSetVerdictFiresAndStaysSilent — САМОПРОВЕРКА вердикта
// выше: инъекция в обе стороны.
//
// Фикстура синтетическая намеренно: опирайся доказательство на живой стенд, оно
// исчезло бы вместе с его починкой — то есть ровно тогда, когда проба достигла
// цели. Сверяется ТОТ ЖЕ вердикт, которым судит обход, а не его копия.
//
// Против законного близнеца меняется РОВНО ОДИН факт: адреса у обоих ОДНИ И ТЕ
// ЖЕ, различается только то, ЧЕМ они объявлены — ручкой чужого издателя или
// собственным перечнем стенда. Пин у близнеца пуст не вторым решением, а тем же
// самым: два объявления об одном предмете разборщик отвергает, поэтому «перечень
// объявлен» и «пин очищен» — одна величина, записанная в двух полях.
func TestF1b07_TheIssuerSetVerdictFiresAndStaysSilent(t *testing.T) {
	const (
		issuer = "http://localhost:28080/.ory/hydra/public/"
		keySet = "http://kacho-umbrella-hydra-public.kacho.svc:4444/.well-known/jwks.json"
	)

	// (1) ДЕФЕКТ: те же два адреса объявлены ручками ЧУЖОГО издателя.
	inherited := config.Config{
		AppEnv:       "dev",
		APIDomain:    "api.kacho.test",
		HydraIssuer:  issuer,
		HydraJWKSURL: keySet,
	}
	found := f1bIssuerSetFindings(inherited)
	if len(found) == 0 {
		t.Fatal("внесённый дефект НЕ НАЙДЕН: приём, построенный из ручек чужого издателя, " +
			"прошёл за объявленный — вердикт не способен упасть, и его молчание на живом " +
			"дереве не означает ничего")
	}
	// Находка обязана назвать ПРИЧИНУ, а не симптом: имя ручки — то, что
	// оператор правит, и то, по чему следующий шаг узнаёт свой предмет.
	joined := strings.Join(found, "\n")
	for _, want := range []string{config.KnobDeclaredIssuers, config.KnobLegacyKeySet} {
		if !strings.Contains(joined, want) {
			t.Errorf("находка не называет ручку %s:\n%s", want, joined)
		}
	}

	// (2) ЗАКОННЫЙ БЛИЗНЕЦ: те же два адреса, объявленные перечнем стенда.
	declared := config.Config{
		AppEnv:             "dev",
		APIDomain:          "api.kacho.test",
		TokenIssuers:       issuer,
		TokenIssuerKeySets: issuer + "=" + keySet,
	}
	if silent := f1bIssuerSetFindings(declared); len(silent) != 0 {
		t.Fatalf("законный близнец объявлен находкой:\n  · %s\n\nТогда проба падает на "+
			"ДОСТИЖЕНИИ СВОЕЙ ЦЕЛИ и наказывает правильный поступок",
			strings.Join(silent, "\n  · "))
	}

	// (3) Вердикт обязан различать и то, чего проба не судит: объявление,
	// которое не разбирается вовсе, не смеет пройти за объявленное.
	degenerate := declared
	degenerate.TokenIssuers = ","
	if len(f1bIssuerSetFindings(degenerate)) == 0 {
		t.Fatal("вырожденный перечень («,» — длина есть, элементов ноль) прошёл за " +
			"объявленный: вопрос об источнике адреса остался бы незаданным молча")
	}

	t.Logf("самопроверка: осмотрено объявлений 3 (дефект · законный близнец · вырожденное)")
}
