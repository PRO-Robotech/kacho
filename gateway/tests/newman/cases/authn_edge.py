# ---------------------------------------------------------------------------
# IBT-10 (б), третья форма — НАСТОЯЩИЙ предъявитель с испорченной подписью.
#
# Ближайшее достижимое здесь утверждение к «нападающий подписал своей парой»:
# песочница newman не умеет RSA, поэтому подпись не подделывается, а ломается.
# Предмет тот же и он сильнее прочих отрицаний: заголовок, издатель, аудитория,
# срок и `kid` остаются ЗАКОННЫМИ — отличается ровно подпись. Значит `401`
# здесь может прийти только оттого, что подпись действительно проверяется, а не
# оттого, что что-то в предъявителе не понравилось раньше.
# ---------------------------------------------------------------------------
def tampered_signature_case(*, case_id: str, title: str, env_var: str,
                            step_name: str, lane: str) -> "Case":
    """Кейс «настоящий предъявитель, испорченная подпись» — ОДНА реализация на все полосы.

    Полос у края две (внешний поставщик и наш издатель), и утверждение у них
    одно и то же: подпись ПРОВЕРЯЕТСЯ. Копия этого кейса на вторую полосу
    разошлась бы с первой молча — и разошлась бы именно в подстановке, свойство
    которой держит отдельный гейт (`scripts/selftest_tamper_mutation.py`).
    Поэтому реализация одна, а различаются ВЕЛИЧИНЫ: имя слота предъявителя,
    имя шага и название полосы в текстах утверждений.
    """
    return Case(
        id=case_id,
        title=title,
        classes=["AUTHN", "NEG", "SEC", "CONF"],
        priority="P0",
        steps=[
        Step(
            name=step_name,
            method="GET",
            path=PROBE_PATH,
            mux="public",
            pre_script=[
                # СВОЙ страж предъявителя, а не `auth="jwtBootstrap"`: заголовок
                # здесь строится, а не подставляется, поэтому страж генератора
                # до него не достаёт. Форма — та же, что у `_auth_pre_script`:
                # СНАЧАЛА падающее утверждение с именем переменной, ПОТОМ отказ
                # от запроса. Молча пропустить нельзя — запрос ушёл бы анонимно
                # и кейс отчитался бы зелёным о другом утверждении.
                f"const _base = pm.environment.get('{env_var}')"
                f" || pm.variables.get('{env_var}') || '';",
                "if (!_base) {",
                f"  pm.test('harness config: {env_var} is set (нечего портить)', () => {{",
                f"    pm.expect.fail('{env_var} не задан — посев фикстур "
                "(tests/authz-fixtures/setup.sh) не выдал предъявителя. Испортить подпись "
                "не у чего, а запрос без заголовка проверил бы анонимный доступ, то есть "
                "другой кейс.');",
                "  });",
                "  pm.execution.skipRequest();",
                "} else {",
                "  const _s = _base.split('.');",
                # Один символ последнего сегмента. Замена на ДРУГОЙ символ того
                # же алфавита base64url — длина и форма сохраняются, поэтому
                # отвергнут он будет проверкой подписи, а не разбором.
                #
                # ПЕРВЫЙ СИМВОЛ, А НЕ ПОСЛЕДНИЙ — И ЭТО НЕ ВКУСОВЩИНА.
                #
                # В base64url значащи все шесть бит КАЖДОГО символа, кроме
                # ПОСЛЕДНЕГО символа кодировки: у него часть младших бит —
                # заполнение, и разборщик их игнорирует (не-strict base64, то
                # есть подавляющее большинство). Сколько именно бит — зависит от
                # длины подписи: у 512 байт (RS256 на ключе 4096 бит, ровно то,
                # что чеканит этот стенд) заполнение занимает 2 бита, у 256 байт
                # — 4. Поэтому у последнего символа есть СОСЕДИ ПО ЗНАЧЕНИЮ:
                # разные символы, декодирующиеся в одни и те же байты.
                #
                # Прежняя редакция меняла ровно последний символ по правилу
                # «`A` → `B`, иначе → `A`». На подписи длиной 512 байт `A` и `B`
                # различаются только битом заполнения ⇒ на каждом шестнадцатом
                # предъявителе (терминальный символ равномерен по алфавиту из 16
                # значений) проба отправляла краю ПОБАЙТОВО ТУ ЖЕ подпись. Край
                # отвечал `200` — правильно, предъявитель был подлинный, — а
                # кейс читал этот `200` как «край принял испорченную подпись».
                #
                # Замер по 19 прогонам с сохранившимися отчётами: терминальный
                # символ `A` — 3 прогона, и все три красные; прочие символы — 16
                # прогонов, красных ноль. Предикат — терминальный символ
                # подлинного предъявителя из отчёта `list-accounts-as-bootstrap`
                # против числа падений `api-gateway/authn_edge` в описи шарда.
                #
                # Первый символ значащий при ЛЮБОЙ длине подписи, поэтому замена
                # его на другой символ алфавита меняет декодированные байты
                # ВСЕГДА. Свойство держится не этим комментарием, а гейтом
                # `scripts/selftest_tamper_mutation.py`, который гоняет саму эту
                # подстановку над всеми 256 значениями обоих краевых байт на
                # пяти длинах подписи и требует расхождения В БАЙТАХ.
                "  const _sig = _s[2];",
                "  const _c = _sig[0];",
                "  const _flipped = (_c === 'A' ? 'B' : 'A') + _sig.slice(1);",
                "  pm.request.headers.upsert({ key: 'Authorization',",
                "    value: 'Bearer ' + _s[0] + '.' + _s[1] + '.' + _flipped });",
                "}",
            ],
            test_script=[
                "const _sent = (pm.request.headers.get('Authorization') || '');",
                "const _tok = _sent.replace(/^Bearer /, '');",
                f"const _base = pm.environment.get('{env_var}')"
                f" || pm.variables.get('{env_var}') || '';",
                f"pm.test('полоса «{lane}»: отправлен предъявитель, отличный от исходного',"
                " () => {",
                "  pm.expect(_tok, 'отправленный предъявитель').to.not.eql(_base);",
                "});",
                # Именно это и делает кейс утверждением о ПОДПИСИ: два первых
                # сегмента обязаны совпасть с исходными. Разойдись они — край
                # отвергал бы уже другой предъявитель (чужая аудитория, чужой
                # `kid`), и `401` не говорил бы ничего о проверке подписи.
                "pm.test('заголовок и тело совпадают с исходными — испорчена ТОЛЬКО подпись',"
                " () => {",
                "  const _a = _tok.split('.');",
                "  const _b = _base.split('.');",
                "  pm.expect(_a[0], 'заголовок').to.eql(_b[0]);",
                "  pm.expect(_a[1], 'тело').to.eql(_b[1]);",
                "  pm.expect(_a[2], 'подпись').to.not.eql(_b[2]);",
                "  pm.expect(_a[2].length, 'длина подписи').to.eql(_b[2].length);",
                "});",
                # РАСХОЖДЕНИЕ СТРОК ≠ РАСХОЖДЕНИЕ БАЙТ, и утверждение выше знает
                # только про строки. Последний символ кодировки несёт биты
                # заполнения, поэтому у него есть соседи по значению: строка
                # другая, декодированные байты те же, подпись подлинная, край
                # отвечает `200` — и `_REJECTED` ниже краснеет, обвиняя край в
                # том, чего он не делал. Это и случилось (разбор — у подстановки
                # в pre-script выше).
                #
                # Утверждение о позиции сильнее, чем сравнение строк, и не
                # требует декодирования в песочнице: изменён ровно один символ, и
                # он НЕ последний ⇒ все его шесть бит значащие ⇒ байты подписи
                # заведомо разошлись. Стоит ДО утверждений об ответе — как и
                # прочие утверждения о входе (см. шапку файла): сломанный
                # производитель входа обязан краснеть своей причиной, а не
                # притворяться находкой о крае.
                "pm.test('изменён ровно один символ подписи, и он НЕ последний "
                "(у последнего часть бит — заполнение, байты совпали бы)', () => {",
                "  const _a = _tok.split('.')[2];",
                "  const _b = _base.split('.')[2];",
                "  const _diff = [];",
                "  for (let i = 0; i < _b.length; i++)"
                " { if (_a[i] !== _b[i]) _diff.push(i); }",
                "  pm.expect(_diff.length, 'позиции расхождения: ' + JSON.stringify(_diff))"
                ".to.eql(1);",
                "  pm.expect(_diff[0], 'позиция расхождения (последняя — ' + (_b.length - 1)"
                " + ')').to.not.eql(_b.length - 1);",
                "});",
                *_REJECTED,
            ],
        ),
        ],
    )


