# ВТОРАЯ ПОЛОСА КРАЯ — предъявитель НАШЕЙ чеканки (задача #1014).
#
# ЧТО ЭТО ЗА ПОЛОСА. Край объявлен принимающим ДВУХ издателей: внешнего
# поставщика и нас самих (`api-gateway.tokenAcceptance` в профиле стенда). Полоса
# внешнего поставщика утверждена соседними кейсами выше — предъявитель принят,
# анонимный отвергнут, испорченная подпись отвергнута. Полоса НАШЕГО издателя до
# этого кейса утверждалась только косвенно: ключ подписи заведён, набор ключей
# публикуется, эндпоинт выдачи отвечает на негодное утверждение отказом. Ни одно
# из трёх не говорит, что край отвечает `200` на НАСТОЯЩИЙ токен нашей чеканки —
# они говорят, что механизм СОБРАН.
#
# ГДЕ ТЕПЕРЬ СВОЙСТВО «ПЕРЕЧЕНЬ ИЗДАТЕЛЕЙ — ПЕРЕЧЕНЬ» И ПОЧЕМУ НЕ ЗДЕСЬ.
# Кейс утверждал его сравнением: `iss` своего предъявителя против `iss`
# предъявителя соседней полосы, оба приняты одним краем на одном маршруте.
# Средством служил бутстрап-предъявитель, и средство истекло вместе с задачей
# #1119 — бутстрап чеканит теперь НАШ подписант, поэтому обе стороны сравнения
# стали одной полосой, и утверждение о различии стало ложным о верном мире.
#
# Починить сравнение на месте нельзя, и это ИЗМЕРЕНО, а не предположено: после
# #1120 выдача ключа служебной учётки не заводит зеркала у прежнего издателя,
# после #1121 того же лишился персональный токен. Машинного пути к предъявителю
# прежней полосы не осталось ВООБЩЕ; единственный такой предъявитель добывается
# интерактивным входом (полоса церемонии), а её шард края не поднимает.
#
# Свойство переехало в объявление профиля:
# `gateway/deploy/f1b_token_acceptance_declared_test.go`,
# `TestF1b_OurIssuerIsADDEDToTheListNotSubstitutedForIt` — профиль, назвавший
# нашего издателя, обязан нести И запись прежней полосы. Оно доказано инъекцией
# в обе стороны и не требует ни стенда, ни предъявителя.
#
# ЧТО ПРИ ЭТОМ ПОТЕРЯНО, названо прямо, чтобы «зелено» не читалось шире: сквозного
# доказательства, что край и сегодня ПРИНИМАЕТ предъявителя прежней полосы, у
# машинных суит больше нет — проба профиля утверждает объявление, а не поведение
# процесса. Предмет заведён отдельной задачей.
#
# ЧЕГО ЭТОТ КЕЙС НЕ ДУБЛИРУЕТ. Отрицание «без токена» лежит выше
# (IBT-10-ANONYMOUS-REJECTED) и полосы не имеет by construction: у запроса без
# предъявителя нет издателя, значит нет и записи, которую он мог бы выбрать.
# Второй анонимный кейс на тот же маршрут утверждал бы ровно то же самое и стоил
# бы лишнего шага. Отрицание «испорченная подпись» полосу имеет — у полос разные
# записи проверяющего и разные наборы ключей, — и оно заведено ниже, ТОЙ ЖЕ
# реализацией.
#
# ОКНО ОТЗЫВА НАЗВАНО, А НЕ УМОЛЧАНО. Отзыв предъявителя НАШЕЙ чеканки читается
# на предъявлении, и неотвеченный вердикт края — отказ (`503`), а не пропуск.
# Значит `200` здесь получен ПРИ ДОСТУПНОМ авторитете отзыва, и это утверждается
