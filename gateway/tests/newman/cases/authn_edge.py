"""Case-set authn_edge — какой предъявитель край ПРИНИМАЕТ, а какой отвергает.

Приёмка `docs/specs/sub-phase-IAM-BOOTSTRAP-TOKEN-acceptance.md` (APPROVED
2026-07-22) относит IBT-04 и IBT-10 к уровню «e2e-conformance (Phase C)» —
то есть к утверждению против РАЗВЁРНУТОГО края, а не против функции в процессе.
Этот файл и есть тот уровень.

ЧТО ЗДЕСЬ ЕСТЬ ТАКОГО, ЧЕГО НЕТ В GO-ПРОБАХ
--------------------------------------------
Отказ симметричному предъявителю уже закреплён юнитом
(`gateway/internal/middleware/auth_prod_hmac_refuse_test.go`,
`jwt_verifier_test.go`, `fuzz/fuzz_jwt_verify_test.go`) — он зовёт проверяющего
НАПРЯМУЮ и доказывает, что тот отказывает. Это утверждение о ФУНКЦИИ.
Утверждения о том, что функция стоит НА ПУТИ развёрнутого края, юнит не делает
и сделать не может: он не проходит ни маршрутизацию, ни цепочку промежуточных
слоёв, ни ту посадку, в которой стенд реально поднят.

Разница не умозрительная. Именно этот класс — «контроль написан, провязан и ни
разу не исполнился» — стоил стенду целой поверхности API (см. блок про флаг
провайдера в `deploy/helm/umbrella/values.dev-prod.yaml`).

ПОЧЕМУ ВСЕ ПЯТЬ КЕЙСОВ ИДУТ ПО ОДНОМУ И ТОМУ ЖЕ МАРШРУТУ
---------------------------------------------------------
`GET /iam/v1/accounts` выбран не наугад, и его свойства проверены по дереву:

* в каталоге прав (`gateway/internal/middleware/embed/permission_catalog.json`)
  запись `kacho.cloud.iam.v1.AccountService/List` несёт `permission="<exempt>"`
  БЕЗ `required_acr_min` — значит аутентификация обязательна, per-RPC проверка
  прав пропускается, ответ сужается пообъектным фильтром. Успех положительного
  контроля поэтому не зависит ни от одной выдачи: он проверяет ровно authN;
* маршрута нет ни в одном обходе аутентификации — ни в `DefaultPublicAllowlist()`
  (там одна запись, и это проба живости), ни в `isPublicHTTPPath` (там четыре
  адреса, и этого среди них нет). Если бы маршрут был в обходе, все отрицания
  ниже зеленели бы, ничего не проверяя.

Один маршрут на все пять кейсов — чтобы положительный и отрицательные отличались
РОВНО предъявителем. Отрицание в паре с положительным — требование
`testing.md`: одиночное «отвергнуто» зеленеет сильнее всего тогда, когда сломано
всё.

ПРОИЗВОДИТЕЛЬ ВХОДА УТВЕРЖДАЕТСЯ ОТДЕЛЬНО, И ЭТО НЕ ПЕДАНТИЗМ
--------------------------------------------------------------
Скрипт, подделывающий предъявителя, может упасть — и упавший pre-request
newman НЕ отменяет запрос: он уходит БЕЗ заголовка, то есть анонимно. Тогда
`401` по-прежнему приходит, кейс зеленеет и проверяет совсем другое утверждение
(«аноним отвергнут» вместо «подделка отвергнута»). Проверено вживую при
постройке этого файла: первая редакция скрипта падала на `SyntaxError`
(`CryptoJS` в песочнице newman — уже объявленный глобальный идентификатор,
`const CryptoJS = require(...)` его переобъявляет), запрос всё равно ушёл, и
без утверждения о ФАКТИЧЕСКИ ОТПРАВЛЕННОМ заголовке это осталось бы незаметно.

Поэтому каждый отрицательный кейс сначала утверждает, ЧТО именно он отправил
(три сегмента, объявленный алгоритм, длина подписи), и только потом — что край
ответил. Утверждение о входе стоит первым намеренно: если производитель входа
сломан, кейс краснеет с внятной причиной, а не притворяется другим кейсом.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ (не «забыли», а установлено предикатом)
----------------------------------------------------------------
* **IBT-05** (принципал-машина проходит порог `required_acr_min`) — уже закреплён
  e2e соседним файлом: `cluster_admin.py::CLUSTER-ADMIN-GRANT-OK` зовёт
  `POST /iam/v1/internal/cluster/admins` под `jwtBootstrap` и утверждает `200`,
  а у этого RPC в каталоге `required_acr_min="2"` — самый высокий порог. Токен
  `client_credentials` не несёт `acr` вовсе, значит `200` там И ЕСТЬ работающее
  освобождение служебного принципала. Порог применяется одинаково на обоих
  слушателях (`auth_stepup.go::enforceStepUpHTTP` не смотрит на слушателя), так
  что внутренний адрес утверждению не мешает. Дублировать это здесь значило бы
  завести вторую выдачу ключа на каждый прогон — течь фикстур ради имени кейса.
* **IBT-06** (у RPC нет REST-двери) — держится двумя Go-пробами:
  `gateway/internal/restmux/bootstrap_token_no_rest_route_test.go` и
  `services/iam/cmd/kacho-iam/bootstrap_token_internal_only_test.go`. Они судят
  по РЕГИСТРАЦИИ маршрута, то есть по тому, чего в дереве нет; e2e-проба на
  `404` слабее — `404` приходит и от опечатки в адресе.
* **Подделка RS256 своим ключом** (нападающий чеканит собственную пару) —
  песочница newman не умеет подписывать RSA. Ближайшее достижимое утверждение
  того же класса — кейс с испорченной подписью НАСТОЯЩЕГО предъявителя: он
  доказывает, что подпись именно ПРОВЕРЯЕТСЯ, а не только разбирается.

ГРАНИЦА ЧЕСТНОСТИ У КЕЙСА С HS256
----------------------------------
Он подписан ключом, который эта установка никогда не выдавала (случайный на
прогон), поэтому утверждает «произвольный симметричный предъявитель отвергнут».
Он НЕ утверждает «симметричная ветка выключена» — для этого нужен настоящий
общий ключ, а такого в дереве нет by construction
(`internal/repohygiene/sharedsigningliteral_test.go`), и production-стенд не
поднимется с ним (`Config.Validate` края). Эти два свойства держат гейт и
boot-guard; здесь — наблюдаемое поведение развёрнутого края.
"""

CASES = []


# Маршрут, общий для всех пяти кейсов. Разбор выбора — в шапке файла.
PROBE_PATH = "/iam/v1/accounts"


# Подписыватель подделок. Живёт одной константой, потому что три кейса из пяти
# отличаются РОВНО заголовком JWS и телом — всё остальное у них общее, и
# расхождение копий было бы расхождением того, что кейсы вообще отправляют.
#
# `require('crypto-js')` под СВОИМ именем (`_cj`), а не `CryptoJS`: глобальный
# идентификатор с этим именем в песочнице newman уже объявлен, и `const CryptoJS
# = require(...)` роняет скрипт на `SyntaxError` — проверено прогоном.
_FORGE_PRELUDE = [
    "const _cj = require('crypto-js');",
    "function _b64u(wa) { return _cj.enc.Base64.stringify(wa)"
    ".replace(/\\+/g, '-').replace(/\\//g, '_').replace(/=+$/, ''); }",
    "function _b64uStr(s) { return _b64u(_cj.enc.Utf8.parse(s)); }",
    "const _now = Math.floor(Date.now() / 1000);",
]


def _assert_sent_bearer_shape(*, segments: int, alg: str,
                              sig_len: int | None) -> list[str]:
    """Утверждения о ФАКТИЧЕСКИ ОТПРАВЛЕННОМ заголовке — до утверждений об ответе.

    Зачем они есть вообще — в шапке файла: упавший pre-request не отменяет
    запрос, тот уходит анонимно, и отрицательный кейс зеленеет, проверив другое
    утверждение. `pm.request` в test-скрипте отражает отправленный запрос —
    проверено прогоном против локального эха (заголовок как отправлен совпал с
    заголовком как получен).
    """
    lines = [
        "// ПРОИЗВОДИТЕЛЬ ВХОДА: сначала — что отправили, потом — что ответили.",
        "const _sent = (pm.request.headers.get('Authorization') || '');",
        "const _tok = _sent.replace(/^Bearer /, '');",
        "pm.test('проба отправила Bearer (иначе это анонимный кейс, а не этот)', () => {",
        "  pm.expect(_sent.startsWith('Bearer '), 'Authorization как отправлен: ' + _sent)"
        ".to.eql(true);",
        "});",
        f"pm.test('отправленный предъявитель — JWS из {segments} сегментов', () => {{",
        f"  pm.expect(_tok.split('.').length, _tok).to.eql({segments});",
        "});",
        f"pm.test(\"заголовок отправленного предъявителя объявляет alg={alg}\", () => {{",
        "  const _cj = require('crypto-js');",
        "  const _b64 = _tok.split('.')[0].replace(/-/g, '+').replace(/_/g, '/');",
        "  const _h = JSON.parse(_cj.enc.Utf8.stringify(_cj.enc.Base64.parse(_b64)));",
        f"  pm.expect(_h.alg, JSON.stringify(_h)).to.eql('{alg}');",
        "});",
    ]
    if sig_len is not None:
        lines += [
            f"pm.test('сегмент подписи длиной {sig_len} — подпись действительно "
            "поставлена', () => {",
            f"  pm.expect(_tok.split('.')[2].length, _tok).to.eql({sig_len});",
            "});",
        ]
    return lines


# Отказ аутентификации, каким его видит клиент. Оба места, которые его пишут
# (`writeHTTPUnauthorized` в auth.go и `writeHTTPUnauth` в
# permission_denied_response.go), кладут `{"code":16}` и заголовок вызова
# RFC 6750 — поэтому утверждается и то, и другое.
#
# ЗНАЧЕНИЕ заголовка вызова НЕ пиннится: два законных пути пишут разный текст
# (`Bearer error="invalid_token"…` против `Bearer realm="kacho"`), и пин выбрал
# бы ОДИН внутренний путь, то есть утверждал бы про устройство края, а не про
# его контракт. Утверждается схема вызова — она у обоих одна и она обязательна.
_REJECTED = [
    "pm.test('край ответил 401 — предъявитель не принят', () => {",
    "  pm.expect(pm.response.code, pm.response.text()).to.eql(401);",
    "});",
    "pm.test('grpc code 16 (Unauthenticated), а не 7 (PermissionDenied)', () => {",
    "  const j = pm.response.json();",
    "  pm.expect(j.code, JSON.stringify(j)).to.eql(16);",
    "});",
    "pm.test('ответ несёт вызов RFC 6750 (WWW-Authenticate: Bearer …)', () => {",
    "  const h = pm.response.headers.get('WWW-Authenticate') || '';",
    "  pm.expect(h.startsWith('Bearer'), 'WWW-Authenticate: ' + h).to.eql(true);",
    "});",
]


# ---------------------------------------------------------------------------
# IBT-04 — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ.
#
# Без него четыре отрицания ниже зеленели бы на полностью сломанном крае: край,
# который отвечает 401 ВСЕМ, проходит их все. Этот кейс — единственное, что
# отличает «отвергает подделки» от «не работает».
#
# Он же и есть сценарий IBT-04 приёмки: предъявитель из MintBootstrapToken
# принимается шлюзом (200, не 401/403). Предъявителя кладёт посев
# (`tests/authz-fixtures/mint_rs256.py::mint_bootstrap` → `jwtBootstrap`).
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IBT-04-BOOTSTRAP-RS256-ACCEPTED",
    title="bootstrap RS256 Bearer is accepted by the edge on a public route → 200",
    classes=["AUTHN", "CONF", "FLOW"],
    priority="P0",
    steps=[
        Step(
            name="list-accounts-as-bootstrap",
            method="GET",
            path=PROBE_PATH,
            mux="public",
            auth="jwtBootstrap",
            test_script=[
                # Тот же порядок, что у отрицаний: сперва — чем именно
                # представились. Иначе «200» ничего не говорит: пустой заголовок
                # на этом маршруте дал бы 401, но частично разрешённый или
                # подменённый посевом предъявитель — вполне 200 «не тем».
                "const _sent = (pm.request.headers.get('Authorization') || '');",
                "const _tok = _sent.replace(/^Bearer /, '');",
                "pm.test('проба представилась предъявителем посева', () => {",
                "  pm.expect(_sent.startsWith('Bearer '), 'Authorization: ' + _sent)"
                ".to.eql(true);",
                "});",
                "pm.test('это трёхсегментный JWS', () => {",
                "  pm.expect(_tok.split('.').length, _tok).to.eql(3);",
                "});",
                # Асимметричный алгоритм — предмет всей под-фазы: край в
                # production принимает ТОЛЬКО подпись выдающего. Симметричный
                # предъявитель здесь означал бы, что посев вернулся к
                # собственной чеканке, и это надо увидеть на положительном
                # контроле, а не гадать по отрицаниям.
                "pm.test('его заголовок объявляет асимметричный алгоритм', () => {",
                "  const _cj = require('crypto-js');",
                "  const _b64 = _tok.split('.')[0].replace(/-/g, '+').replace(/_/g, '/');",
                "  const _h = JSON.parse(_cj.enc.Utf8.stringify(_cj.enc.Base64.parse(_b64)));",
                "  pm.expect(['RS256', 'ES256', 'EdDSA'], JSON.stringify(_h))"
                ".to.include(_h.alg);",
                "});",
                *assert_status(200),
                # Форма ответа — чтобы «200» не оказалось чужой страницей
                # (маршрут перепутан, прокси вернул своё): список аккаунтов
                # обязан быть списком. Пустым он быть вправе — фильтр по правам
                # сужает его законно, и требовать непустоты значило бы завести
                # зависимость от выдач, которой у этого кейса нет.
                "pm.test('ответ — страница списка (поле accounts — массив)', () => {",
                "  const j = pm.response.json();",
                "  pm.expect(Array.isArray(j.accounts || []), JSON.stringify(j))"
                ".to.eql(true);",
                "});",
            ],
        ),
    ],
))


# ---------------------------------------------------------------------------
# IBT-10 (а) — запрос без удостоверения.
#
# Тот же маршрут, что у положительного контроля, поэтому пара «200 с
# предъявителем / 401 без него» отличается ровно одним.
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IBT-10-ANONYMOUS-REJECTED",
    title="no credential on an authenticated route → 401, never a page",
    classes=["AUTHN", "NEG", "CONF"],
    priority="P0",
    steps=[
        Step(
            name="list-accounts-anonymously",
            method="GET",
            path=PROBE_PATH,
            mux="public",
            auth="anonymous",
            test_script=[
                # Зеркало утверждения о входе: здесь производитель входа —
                # ОТСУТСТВИЕ заголовка, и он тоже утверждается. Заголовок,
                # доехавший сюда по наследству от коллекции, превратил бы кейс
                # в «предъявитель коллекции получает 401», то есть в проверку
                # чужого свойства.
                "pm.test('запрос ушёл БЕЗ Authorization (иначе это другой кейс)', () => {",
                "  const _sent = pm.request.headers.get('Authorization');",
                "  pm.expect(_sent === undefined || _sent === null || _sent === '',",
                "    'Authorization как отправлен: ' + _sent).to.eql(true);",
                "});",
                *_REJECTED,
            ],
        ),
    ],
))


# ---------------------------------------------------------------------------
# IBT-10 (б) — симметрично подписанный предъявитель.
#
# CWE-347. Ключ — случайный на прогон и назван так, чтобы его нельзя было
# перепутать с настоящим: правдоподобная фикстура прячет ровно тот дефект,
# ради которого её подставляют.
#
# Утверждения (`kacho_principal_type=service_account` + `kacho_sa_id`) стоят в
# теле НАМЕРЕННО: это полезная нагрузка подделки принципала — на симметричной
# ветке такие утверждения принимались бы БЕЗ обращения к iam. Пустое тело
# проверяло бы «мусор отвергнут», а не «подделка принципала отвергнута».
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IBT-10-HS256-FORGED-REJECTED",
    title="symmetrically signed (HS256) Bearer asserting a service_account → 401",
    classes=["AUTHN", "NEG", "SEC", "CONF"],
    priority="P0",
    steps=[
        Step(
            name="list-accounts-with-hs256-forgery",
            method="GET",
            path=PROBE_PATH,
            mux="public",
            pre_script=[
                *_FORGE_PRELUDE,
                "const _h = _b64uStr(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));",
                "const _p = _b64uStr(JSON.stringify({",
                "  sub: 'sva-forged-by-the-conformance-probe',",
                "  kacho_principal_type: 'service_account',",
                "  kacho_sa_id: 'sva-forged-by-the-conformance-probe',",
                "  iat: _now, exp: _now + 900,",
                "}));",
                "const _si = _h + '.' + _p;",
                "const _key = 'a-key-this-deployment-has-never-issued-'"
                " + Math.random().toString(36).slice(2);",
                "pm.request.headers.upsert({ key: 'Authorization',",
                "  value: 'Bearer ' + _si + '.' + _b64u(_cj.HmacSHA256(_si, _key)) });",
            ],
            test_script=[
                # 43 символа base64url — ровно 32 байта HMAC-SHA256. Длина
                # утверждается, чтобы «подпись поставлена» не путалось с
                # «сегмент пуст»: у формы `alg=none` третий сегмент пустой, и
                # без длины эти два кейса стали бы неразличимы.
                *_assert_sent_bearer_shape(segments=3, alg="HS256", sig_len=43),
                *_REJECTED,
            ],
        ),
    ],
))


# ---------------------------------------------------------------------------
# IBT-10 (б), вторая форма — предъявитель БЕЗ подписи (`alg: none`).
#
# Классический обход разбором: подпись объявлена отсутствующей, и разборщик,
# который читает алгоритм из заголовка предъявителя вместо собственной
# настройки, принимает такой токен как проверенный.
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IBT-10-ALG-NONE-REJECTED",
    title="unsigned Bearer (alg=none) asserting a service_account → 401",
    classes=["AUTHN", "NEG", "SEC", "CONF"],
    priority="P0",
    steps=[
        Step(
            name="list-accounts-with-alg-none",
            method="GET",
            path=PROBE_PATH,
            mux="public",
            pre_script=[
                *_FORGE_PRELUDE,
                "const _h = _b64uStr(JSON.stringify({ alg: 'none', typ: 'JWT' }));",
                "const _p = _b64uStr(JSON.stringify({",
                "  sub: 'sva-forged-by-the-conformance-probe',",
                "  kacho_principal_type: 'service_account',",
                "  kacho_sa_id: 'sva-forged-by-the-conformance-probe',",
                "  iat: _now, exp: _now + 900,",
                "}));",
                # Третий сегмент пустой — так предписывает RFC 7519 для `none`;
                # точка на конце обязана остаться, иначе это двухсегментная
                # строка, которую край отвергнет как синтаксический мусор, а не
                # как незаконный алгоритм.
                "pm.request.headers.upsert({ key: 'Authorization',",
                "  value: 'Bearer ' + _h + '.' + _p + '.' });",
            ],
            test_script=[
                *_assert_sent_bearer_shape(segments=3, alg="none", sig_len=None),
                "pm.test('сегмент подписи ПУСТ — это форма alg=none, а не обрезок', () => {",
                "  pm.expect(_tok.split('.')[2], _tok).to.eql('');",
                "});",
                *_REJECTED,
            ],
        ),
    ],
))


# ---------------------------------------------------------------------------
# IBT-10 (б), третья форма — НАСТОЯЩИЙ предъявитель с испорченной подписью.
#
# Ближайшее достижимое здесь утверждение к «нападающий подписал своей парой»:
# песочница newman не умеет RSA, поэтому подпись не подделывается, а ломается.
# Предмет тот же и он сильнее прочих отрицаний: заголовок, издатель, аудитория,
# срок и `kid` остаются ЗАКОННЫМИ — отличается ровно подпись. Значит `401`
# здесь может прийти только оттого, что подпись действительно проверяется, а не
# оттого, что что-то в предъявителе не понравилось раньше.
# ---------------------------------------------------------------------------
CASES.append(Case(
    id="IBT-10-RS256-TAMPERED-SIGNATURE-REJECTED",
    title="genuine bootstrap Bearer with one signature byte flipped → 401",
    classes=["AUTHN", "NEG", "SEC", "CONF"],
    priority="P0",
    steps=[
        Step(
            name="list-accounts-with-tampered-signature",
            method="GET",
            path=PROBE_PATH,
            mux="public",
            pre_script=[
                # СВОЙ страж предъявителя, а не `auth="jwtBootstrap"`: заголовок
                # здесь строится, а не подставляется, поэтому страж генератора
                # до него не достаёт. Форма — та же, что у `_auth_pre_script`:
                # СНАЧАЛА падающее утверждение с именем переменной, ПОТОМ отказ
                # от запроса. Молча пропустить нельзя — запрос ушёл бы анонимно
                # и кейс отчитался бы зелёным о другом утверждении.
                "const _base = pm.environment.get('jwtBootstrap')"
                " || pm.variables.get('jwtBootstrap') || '';",
                "if (!_base) {",
                "  pm.test('harness config: jwtBootstrap is set (нечего портить)', () => {",
                "    pm.expect.fail('jwtBootstrap не задан — посев фикстур "
                "(tests/authz-fixtures/setup.sh) не выдал предъявителя. Испортить подпись "
                "не у чего, а запрос без заголовка проверил бы анонимный доступ, то есть "
                "другой кейс.');",
                "  });",
                "  pm.execution.skipRequest();",
                "} else {",
                "  const _s = _base.split('.');",
                # Один символ последнего сегмента. Замена на ДРУГОЙ символ того
                # же алфавита base64url — длина и форма сохраняются, поэтому
                # отвергнут он будет проверкой подписи, а не разбором.
                "  const _sig = _s[2];",
                "  const _c = _sig.slice(-1);",
                "  const _flipped = _sig.slice(0, -1) + (_c === 'A' ? 'B' : 'A');",
                "  pm.request.headers.upsert({ key: 'Authorization',",
                "    value: 'Bearer ' + _s[0] + '.' + _s[1] + '.' + _flipped });",
                "}",
            ],
            test_script=[
                "const _sent = (pm.request.headers.get('Authorization') || '');",
                "const _tok = _sent.replace(/^Bearer /, '');",
                "const _base = pm.environment.get('jwtBootstrap')"
                " || pm.variables.get('jwtBootstrap') || '';",
                "pm.test('отправлен предъявитель, отличный от исходного', () => {",
                "  pm.expect(_tok, 'отправленный предъявитель').to.not.eql(_base);",
                "});",
                # Именно это и делает кейс утверждением о ПОДПИСИ: два первых
                # сегмента обязаны совпасть с исходными. Разойдись они — край
                # отвергал бы уже другой предъявитель (чужая аудитория, чужой
                # `kid`), и `401` не говорил бы ничего о проверке подписи.
                "pm.test('заголовок и тело совпадают с исходными — испорчена ТОЛЬКО подпись',"
                " () => {",
                "  const _a = _tok.split('.');",
                "  const _b = _base.split('.');",
                "  pm.expect(_a[0], 'заголовок').to.eql(_b[0]);",
                "  pm.expect(_a[1], 'тело').to.eql(_b[1]);",
                "  pm.expect(_a[2], 'подпись').to.not.eql(_b[2]);",
                "  pm.expect(_a[2].length, 'длина подписи').to.eql(_b[2].length);",
                "});",
                *_REJECTED,
            ],
        ),
    ],
))
