// struct_fields_forms_test.go — ПЕРЕБОР ФОРМ ВХОДА у вывода состава полей.
//
// # Почему перебор, а не ещё одна починка
//
// Вывод состава полей завёлся затем, чтобы «корень передаёт все поля осей»
// перестало держаться выписанным от руки перечнем. На именованном поле он
// работал, и этим я его и опробовал — а на ВСТРОЕННОМ поле список имён пуст,
// и цикл его пропускал. Подстановка рецензента: встроенный тип с полем,
// которое читает новая ось; корень поле не передаёт; гейт ПРОШЁЛ, перепись
// напечатала «полей у типа 5 · не названо 0».
//
// Это хуже выписанного перечня, который он заменил: ручной перечень был честен
// о своей природе, а тут ложное число стояло под словом «выведено».
//
// Отсюда форма этой пробы: не «встроенное поле теперь видно», а ПЕРЕЧЕНЬ ФОРМ
// ВХОДА С ИСХОДОМ ПО КАЖДОЙ. Механизм, чьи формы входа не перечислены и не
// опробованы, принимать нельзя — ни свой, ни чужой.
//
// # Что перечислено и что НЕ перечислено
//
// Перечислены одиннадцать форм объявления поля. Границу называю здесь же:
// встроенный тип даёт ОДНО имя — своё, — а его ПРОДВИНУТЫЕ поля разбором
// отсюда не видны: для этого нужно разрешить чужой тип, а разбор идёт по
// одному файлу. Следствие названо числом в переписи гейта: «встроенных полей
// N, их продвинутые поля не перечислены».
//
// Для предмета гейта этого достаточно: ключом составного литерала у
// встроенного поля служит ИМЯ ТИПА, и именно оно обязано быть названо
// перечнем осей. Продвинутое поле, прочитанное осью, приходит вместе со своим
// встроенным типом — назвав тип, корень передаёт и его.
package main

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

// fieldFormCase — одна форма объявления поля и ожидаемый исход вывода.
type fieldFormCase struct {
	name string
	decl string
	want []string
	why  string
}

// fieldFormCases — ПЕРЕЧЕНЬ ФОРМ ВХОДА. Пополняется вместе с находкой новой
// формы, и каждая несёт свой исход.
func fieldFormCases() []fieldFormCase {
	return []fieldFormCase{
		{
			name: "именованное поле", decl: "Alpha string",
			want: []string{"Alpha"},
			why:  "основная форма; на ней вывод и был опробован",
		},
		{
			name: "несколько имён в одном объявлении", decl: "Alpha, Beta, Gamma string",
			want: []string{"Alpha", "Beta", "Gamma"},
			why:  "одно объявление — три поля; счёт по объявлениям занизил бы состав",
		},
		{
			name: "ВСТРОЕННОЕ поле", decl: "Embedded",
			want: []string{"Embedded"},
			why: "список имён ПУСТ, имя даёт тип; на этой форме вывод молчал, и ось " +
				"выключалась без единой находки",
		},
		{
			name: "встроенный УКАЗАТЕЛЬ", decl: "*Embedded",
			want: []string{"Embedded"},
			why:  "та же форма со звёздочкой: ключ литерала всё равно имя типа",
		},
		{
			name: "встроенный тип ИЗ ДРУГОГО ПАКЕТА", decl: "other.Embedded",
			want: []string{"Embedded"},
			why:  "квалификатор в ключ литерала не входит — имя берётся последним",
		},
		{
			name: "встроенный указатель на тип из другого пакета", decl: "*other.Embedded",
			want: []string{"Embedded"},
			why:  "обе обёртки разом",
		},
		{
			name: "НЕЭКСПОРТИРУЕМОЕ поле", decl: "hidden string",
			want: []string{"hidden"},
			why: "ось читает его так же, как экспортируемое; корень в том же пакете и " +
				"передать его может",
		},
		{
			name: "поле ТИПА ИЗ ДРУГОГО ПАКЕТА", decl: "At other.Time",
			want: []string{"At"},
			why:  "имя поля своё, тип чужой — на состав это не влияет",
		},
		{
			name: "поле С ТЕГОМ", decl: "Alpha string `json:\"alpha\"`",
			want: []string{"Alpha"},
			why:  "тег к составу отношения не имеет",
		},
		{
			name: "поле-функция", decl: "Clock func() int64",
			want: []string{"Clock"},
			why:  "часы приходят функцией — форма, которой у нас уже почти воспользовались",
		},
		{
			name: "встроенный ИНТЕРФЕЙС", decl: "Reader",
			want: []string{"Reader"},
			why:  "то же встроенное поле; отличается только тем, чем окажется тип",
		},
	}
}

func TestStructFieldForms_EveryFormOfAFieldDeclarationIsEnumeratedAndJudged(t *testing.T) {
	t.Parallel()

	cases := fieldFormCases()
	if len(cases) == 0 {
		t.Fatal("перечень форм пуст — перебор судил бы о непрочитанном")
	}
	agreed := 0
	for _, tc := range cases {
		src := "package main\ntype Subject struct {\n\t" + tc.decl + "\n}\n"
		f, err := parser.ParseFile(token.NewFileSet(), "synthetic.go", src, 0)
		if err != nil {
			t.Fatalf("%s: синтетика не разбирается: %v", tc.name, err)
		}
		got := fieldsOfStructIn(f, "Subject")
		if strings.Join(got, ",") != strings.Join(tc.want, ",") {
			t.Errorf("%s: вывод дал %v, ожидалось %v — %s", tc.name, got, tc.want, tc.why)
			continue
		}
		agreed++
	}

	// ПУСТАЯ СТРУКТУРА — отдельная форма: ноль полей есть законный исход, а не
	// отказ. Без неё «полей не найдено» и «структуры нет» слились бы в одно.
	empty, err := parser.ParseFile(token.NewFileSet(), "empty.go",
		"package main\ntype Subject struct{}\n", 0)
	if err != nil {
		t.Fatalf("синтетика пустой структуры не разбирается: %v", err)
	}
	if got := fieldsOfStructIn(empty, "Subject"); len(got) != 0 {
		t.Errorf("пустая структура дала поля %v", got)
	}

	// ОТСУТСТВУЮЩИЙ ТИП — тоже форма входа, и её исход отличается от пустой
	// структуры: у вызывающего на нём стоит отказ, а не молчание.
	if got := fieldsOfStructIn(empty, "NoSuchType"); len(got) != 0 {
		t.Errorf("несуществующий тип дал поля %v", got)
	}

	t.Logf("перепись: ФОРМ ВХОДА объявления поля перечислено %d · сошлись %d · плюс две формы "+
		"без полей (пустая структура · отсутствующий тип). ГРАНИЦА: продвинутые поля встроенного "+
		"типа не перечисляются — разбор идёт по одному файлу, и чужой тип отсюда не разрешить",
		len(cases), agreed)
}
