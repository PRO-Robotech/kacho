package main

import (
	"net"
	"time"

	"github.com/soheilhy/cmux"
)

// edgeFirstByteBudget — сколько времени соединению даётся на то, чтобы себя
// назвать: прислать HTTP/2-преамбулу, строку запроса HTTP/1.1 либо ClientHello.
//
// Пока протокол не распознан, соединение НЕ принадлежит ни http.Server, ни
// grpc.Server, поэтому ни ReadHeaderTimeout, ни ConnectionTimeout к этому окну
// не относятся — они начинают действовать после того, как мультиплексор принял
// решение. Без собственного бюджета молчащее соединение держит горутину, дескриптор
// и буфер распознавания неограниченно долго, и для этого не нужно ни токена, ни
// сертификата — достаточно уметь открыть TCP.
//
// Величина соразмерна ReadHeaderTimeout самого http.Server: законный клиент
// называет протокол первым же сегментом сразу после установления соединения
// (gRPC — преамбулой, REST — строкой запроса, TLS — приветствием), поэтому
// десяти секунд с запасом хватает на медленную сеть и не хватает на парковку.
const edgeFirstByteBudget = 10 * time.Second

// newEdgeCmux собирает мультиплексор края с бюджетом на первый байт.
//
// ЕДИНСТВЕННАЯ точка создания cmux в шлюзе — так новый слушатель получает бюджет
// по построению, а не по памяти автора; это требование проверяется гейтом
// TestNoRawCmuxNewOutsideFactory.
func newEdgeCmux(l net.Listener, firstByteBudget time.Duration) cmux.CMux {
	m := cmux.New(l)
	// Бюджет применяется мультиплексором как дедлайн чтения на время
	// распознавания и СНИМАЕТСЯ сразу после того, как протокол определён, —
	// поэтому долгоживущие соединения (keep-alive REST, gRPC-стримы) он не
	// режет. Обе половины закреплены пробами.
	m.SetReadTimeout(firstByteBudget)
	return m
}
