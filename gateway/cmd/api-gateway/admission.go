package main

// admission.go — потолок темпа и одновременности на вызывающего, на ОБА
// gRPC-слушателя края.
//
// # Почему у края своя проводка, а не носителя контура
//
// Шесть сервисов платформы поднимают слушателей через `pkg/servicehost`, и
// потолок им ставит он. Край собирает серверы сам — внешний в `main.go`,
// cluster-internal в `internal_grpc_listener.go`, — поэтому провязка стоит
// здесь. Это отличие раскладки, а не решения: величины берутся из ТОГО ЖЕ пола
// платформы, ключи у слушателей те же, и счёт печатается тем же телом.
//
// # Почему у края ДВЕ формы провязки, а у сервиса одна
//
// Обёртка регистратора покрывает то, что через неё зарегистрировано. У края
// основной поток не проходит ни через один дескриптор: чужие методы он
// пересылает обработчиком неизвестной службы, а тот вызывается вне какой бы то
// ни было службы. Поэтому:
//
//   - ПРОКСИРУЕМЫЙ поток покрывает ПОТОКОВОЕ ЗВЕНО (`StreamInterceptor`) —
//     библиотека диспетчеризует обработчик неизвестной службы как поток и
//     подставляет в звено настоящее имя метода;
//   - СОБСТВЕННУЮ поверхность края (опрос операций) покрывает ОБЁРТКА
//     РЕГИСТРАТОРА, а служебная поверхность (здоровье) регистрируется мимо неё —
//     ровно как у остальных слушателей платформы.
//
// Совмещать формы на ОДНОЙ службе нельзя: потоковый метод заплатил бы дважды.
// Здесь они не пересекаются by construction — под обёртку уходит служба без
// потоковых методов, и это утверждает проба проводки.
//
// # Почему звено стоит ДО решения о правах, а не после него
//
// У сервиса допуск стоит между цепочкой и обработчиком, то есть последним. У
// края это было бы дороже, чем кажется: решение о правах здесь — СЕТЕВОЙ вызов
// к iam на КАЖДОМ запросе, и все запросы края идут в iam под ОДНОЙ личностью
// сертификата, то есть в одно ведро на внутреннем слушателе iam. Поток одного
// арендатора, не остановленный на крае, вычерпал бы это общее ведро — и решение
// о правах перестало бы приниматься для ВСЕХ. Поэтому звено стоит сразу за тем,
// которое устанавливает личность (ключ уже есть), и перед теми, которые дорого
// стоят: отказом в маршруте, решением о правах и пересылкой в домен.

import (
	"fmt"

	"log/slog"

	"github.com/PRO-Robotech/kacho/gateway/internal/config"
	"github.com/PRO-Robotech/kacho/pkg/grpcsrv"
)

// admissionLimits — величины ОБОИХ слушателей: ручки посадки там, где она их
// назвала, и ПОЛ ПЛАТФОРМЫ там, где молчит.
//
// Ноль здесь невозможен by construction: молчание разрешается полом, а не
// пустотой, — иначе «величины не объявлены» означало бы «слушатель не
// ограничен» и выглядело бы в журнале одной строкой предупреждения, то есть
// контролем, который навешен, исполняется на каждом запросе и не отверг ни разу.
//
// Частичный набор — ОТКАЗ старта, а не дополнение полом: оператор, задавший темп
// и забывший одновременность, получил бы наполовину свои, наполовину чужие
// величины и считал бы предел выставленным.
func admissionLimits(cfg config.Config) (public, internal grpcsrv.AdmissionLimits, err error) {
	if public, err = cfg.AdmissionPublic.Resolve(grpcsrv.PlatformPublicAdmission()); err != nil {
		return public, internal, fmt.Errorf("KACHO_API_GATEWAY_ADMISSION_PUBLIC_*: %w", err)
	}
	if internal, err = cfg.AdmissionInternal.Resolve(grpcsrv.PlatformInternalAdmission()); err != nil {
		return public, internal, fmt.Errorf("KACHO_API_GATEWAY_ADMISSION_INTERNAL_*: %w", err)
	}
	return public, internal, nil
}

// armAdmission печатает объявленные величины слушателя.
//
// Печатается ВСЕГДА: посадка обязана быть видна в журнале, а не выводиться из
// отсутствия строки — отсутствие читается как «версия старая» ничуть не реже,
// чем как «потолка нет». `from_posture` отличает величины, названные профилем
// развёртывания, от пола платформы: без него две разные посадки печатают
// одинаковую строку.
func armAdmission(logger *slog.Logger, a *grpcsrv.Admission, fromPosture bool) {
	if logger == nil || a == nil {
		return
	}
	logger.Info("api-gateway: request admission armed",
		"listener", a.Listener(), "limits", a.Limits().String(), "from_posture", fromPosture)
}
