// describePosture — ОБЪЯВЛЕНИЕ края о своей посадке центральному дескриптору
// (`pkg/servicecontract`), задача продукта #1407.
//
// # Что это меняет, и это НЕ «была дыра»
//
// Своих стражей посадки у края два, оба позваны и оба отказывают:
// `validateProductionAuthzConfig` (снятая проверка прав, открытый исход,
// анонимный вход, общий ключ подписи) и `validateProductionInternalListener`
// (внутренний слушатель без mTLS на боевой метке). Не хватало другого: набор
// осей, которые край судит, выбирал он сам, и ни с чем не сверялся — «эту ось
// здесь забыли» было неотличимо от «эту ось здесь решили не судить».
//
// Второе, и оно дороже: край был ВНЕ НАБЛЮДЕНИЯ обхода дерева вовсе, стоя в его
// ведомости послаблений. Ведомость снята вместе с этой правкой.
//
// # Почему объявлен СОБСТВЕННЫЙ контур
//
// [servicecontract.Spec] описывает две вещи: посадку — она есть у каждого
// развёрнутого процесса — и проводку носителя (`pkg/servicehost`). Вторую читает
// только носитель, а контур края он не поднимает и поднять не может: у края
// четыре слушателя двух разных протоколов (открытый мультиплексор за входом
// кластера, необязательный TLS-слушатель, внутренний REST и внутренний gRPC),
// а служб своего домена он не регистрирует вовсе — он проксирует чужие.
// Принеси он проводку — её бы никто не прочитал, и она разошлась бы с
// фактической ручной сборкой МОЛЧА; конструктор такое приносение отвергает (О14).
//
// # ДВЕ ОСИ ИЗЪЯТЫ, и у каждой названа причина
//
// Молчаливое заполнение пустыми значениями исходом не является, поэтому ни одна
// из двух не заполняется правдоподобной константой:
//
//   - шифрования до собственной базы у края НЕТ ПРЕДМЕТА: своей базы он не
//     держит. Строка «require» прошла бы стража всегда, ничего при этом не
//     описывая;
//   - круга отправителей переданной личности у края НЕТ ПРЕДМЕТА с другой
//     стороны: он эту личность не ПРИНИМАЕТ, а ОТПРАВЛЯЕТ. Звена, читающего
//     `x-kacho-principal-*`, у него нет ни на одном слушателе, и ручки круга он
//     не объявляет; выдуманный непустой круг был бы объявлением защиты, которой
//     нет.
//
// Оба изъятия ИСТЕКАЮТ САМИ, и не памятью автора: обход дерева
// (`internal/repohygiene.TestServiceDeclaringPostureKnobsHasABootGuard`)
// требует, чтобы компонент, объявивший ось неприменимой, НЕ объявлял её ручек.
// Заведёт край свою базу либо начнёт принимать переданную личность — заведёт и
// ручку, и изъятие станет находкой.
//
// # Что осталось у края и почему
//
// Транспорт слушателей центральный дескриптор знает как РОВНО ДВА gRPC-порта,
// которые поднимает носитель. У края их четыре и двух разных протоколов, а
// публичный вход — открытый мультиплексор за входом кластера, снимающим TLS.
// Объявить это парой полей значило бы описать форму, которой у процесса нет,
// а изъять транспорт публичного входа — завести послабление, которое ничем не
// истекает. Ось поэтому остаётся у края (`validateProductionInternalListener` и
// `mtls_config.go`) и названа остатком, а не закрыта молча.
func describePosture(cfg config.Config, logger *slog.Logger) (servicecontract.Descriptor, error) {
	// Режим разбирается ОДИН раз на процесс, и отказ на неразборчивом значении
	// доезжает до вызывающего. Прежде здесь стояла мягкая посадка «неизвестное
	// значение читаем как боевое»: она fail-closed и потому защитима, но
	// оператор, опечатавшийся в ручке, узнавал об этом ниоткуда.
	mode, err := servicecontract.ParseMode(cfg.AuthNMode)
	if err != nil {
		return servicecontract.Descriptor{}, fmt.Errorf("KACHO_API_GATEWAY_AUTHN_MODE: %w", err)
	}

	return servicecontract.New(servicecontract.Spec{
		Service: "api-gateway",
		Mode:    mode,
		Logger:  logger,

		OwnContour: "контур входящего пути края собран в его композиционном корне: четыре " +
			"слушателя двух разных протоколов, а служб своего домена край не регистрирует — " +
			"он проксирует чужие",

		DBSSLMode: servicecontract.NotApplicable[string](
			"край не держит собственной базы: строки, к которой можно было бы применить " +
				"sslmode, у него не существует ни в одном профиле развёртывания"),

		// Домен доверия — ЗНАЧЕНИЕ, и это НЕ противоречит изъятию круга ниже.
		// Оси отвечают на разные вопросы: круг — «кому позволено говорить за
		// пользователя» (край переданную личность не принимает, сужать нечего),
		// домен — «чьи предъявители вообще наши». Личность СЕРТИФИКАТА край
		// разбирает: вызывающий с проверенным клиентским сертификатом становится
		// служебной учёткой по своему SPIFFE-имени, и опознаётся оно относительно
		// домена. Изъять домен значило бы объявить, что край не признаёт своим
		// никого, — а он признаёт.
		TrustDomain:     servicecontract.Value(grpcsrv.NewTrustDomain(cfg.AuthNTrustDomain)),
		TrustDomainKnob: "KACHO_API_GATEWAY_AUTHN_TRUST_DOMAIN",

		Forwarders: servicecontract.NotApplicable[grpcsrv.TrustedForwarders](
			"край переданную личность конечного пользователя не ПРИНИМАЕТ, а ОТПРАВЛЯЕТ: " +
				"звена, читающего x-kacho-principal-*, у него нет ни на одном слушателе, и " +
				"ручек круга он не объявляет. Сужать здесь нечего — принимающая сторона " +
				"сужает круг до личности сертификата края"),
	})
}
