// f1b_revocation_wiring_test.go — читатель отзыва НАШИХ токенов провязывается
// по ЗАПИСИ ИЗДАТЕЛЯ, и ничем больше.
//
// # Предмет
//
// Он стоял ВНУТРИ ветки «адрес прежнего провайдера задан», и это делало
// невыразимой посадку, к которой фаза ведёт: «принимаем ТОЛЬКО нашего
// издателя». Такой профиль адреса прежнего провайдера не задаёт — задавать
// нечего, — и наш читатель не провязывался вовсе, а следом старт отвергался.
// Отказ был честный, но отвергал он не ошибку оператора, а состояние, которое
// обязано быть законным: возможность, объявленная и неисполнимая ни при каком
// входе, — тот же класс, что поле, которое требуют и прислать нельзя.
//
// # ПОСАДКА, К КОТОРОЙ ФАЗА ВЕЛА, ДОСТИГНУТА — И УТВЕРЖДЕНИЕ СМЕНИЛО ЗНАК
//
// Прежний провайдер снят целиком: ветки его адреса в корне нет ни одной.
// Проверка «наш читатель ВНЕ этой ветки» стала неизмеримой — её собственная
// проверка предпосылки это и сказала, отказом «предмет вложенности искать не в
// чем». Утверждение поэтому переведено на признак, который ПРОИЗВОДИТ дерево, а
// не на отсутствие снятого: единственная ветка, под которой читатель вправе
// стоять, — объявленный приём НАШЕГО издателя.
//
// Это не ослабление, а та же мысль с живым предметом. Вернувший ветку чужого
// адреса и вложивший в неё читатель роняет случай ниже: условие ветки перестанет
// быть `platformAccepted`.
//
// # Почему проверяется ИСХОДНИК, а не поведение
//
// `main()` из пробы не исполнить: он дозванивается до соседей и занимает
// слушатели. Чтение исходника СЛАБЕЕ исполнения, и здесь оно применяется ровно
// к тому свойству, которого «оно собирается» не показывает, — к ВЛОЖЕННОСТИ
// одного решения в другое. Ровно та же форма и то же обоснование, что у
// соседней пробы провязки хопов.
//
// Разбор ведётся по дереву синтаксиса, а не по тексту: предмет здесь —
// вложенность узлов, и предикат по подстроке отвечал бы на другой вопрос.
package main

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"testing"
)

// f1bFindCall возвращает позиции всех вызовов метода с названным именем.
func f1bFindCall(f *ast.File, name string) []token.Pos {
	var out []token.Pos
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != name {
			return true
		}
		out = append(out, call.Pos())
		return true
	})
	return out
}

// platformAcceptanceBinding — имя, которым композиционный корень связывает
// ОБЪЯВЛЕННЫЙ ПРИЁМ нашего издателя. Ветка ищется по ЭТОЙ привязке: имя названо
// здесь, чтобы его переименование роняло пробу переписью («ветка не найдена»),
// а не делало её тихо беспредметной.
const platformAcceptanceBinding = "platformAccepted"

// enclosingIfCond — условие самой внутренней ветки `if`, охватывающей позицию,
// записанное исходным текстом; "" если позиция не лежит ни в одной ветке.
//
// Условие читается УЗЛОМ, а не подстрокой файла: предмет — вложенность, и
// подстрока нашлась бы и в комментарии рядом. Но печатается оно ЦЕЛИКОМ, а не
// только когда это простое имя: находка обязана называть ПРИЧИНУ, а первая
// редакция этой функции возвращала "" на всяком составном условии — то есть на
// том самом дефекте, ради которого случай и заведён, не говорила ничего.
// Поймала это её собственная самопроверка ниже.
func enclosingIfCond(fset *token.FileSet, f *ast.File, pos token.Pos) string {
	cond := ""
	ast.Inspect(f, func(n ast.Node) bool {
		ifs, ok := n.(*ast.IfStmt)
		if !ok {
			return true
		}
		if pos <= ifs.Body.Lbrace || pos >= ifs.Body.Rbrace {
			return true
		}
		var buf bytes.Buffer
		if err := printer.Fprint(&buf, fset, ifs.Cond); err != nil {
			cond = "<условие не печатается>"
			return true
		}
		cond = buf.String()
		return true
	})
	return cond
}

// TestF1b_OurRevocationReaderIsWiredOnTheIssuerRecordAlone — читатель отзыва
// НАШИХ токенов стоит под объявленным приёмом нашего издателя и ни под чем
// другим.
func TestF1b_OurRevocationReaderIsWiredOnTheIssuerRecordAlone(t *testing.T) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, compositionRootLabel, compositionRoot(t), 0)
	if err != nil {
		t.Fatalf("композиционный корень не разбирается: %v", err)
	}

	// Положительный контроль: читатель вообще провязывается. Без него проба
	// молчала бы на дереве, где его сняли целиком.
	calls := f1bFindCall(f, "WithPlatformRevocationCheck")
	if len(calls) == 0 {
		t.Fatalf("читатель отзыва НАШИХ токенов не провязывается в композиционном корне " +
			"вовсе — объявленный контроль без читателя не отказал бы ни разу за свою жизнь")
	}

	for _, pos := range calls {
		cond := enclosingIfCond(fset, f, pos)
		if cond != platformAcceptanceBinding {
			t.Errorf("читатель отзыва НАШИХ токенов провязан под условием %q, а обязан — под "+
				"объявленным приёмом нашего издателя (%s), координата %s.\n\n"+
				"Полоса отзыва — свойство ЗАПИСИ ИЗДАТЕЛЯ, а не настройки процесса. Всякое "+
				"другое условие возвращает тот же класс, ради которого этот случай заведён: "+
				"посадка «принимаем только нашего издателя» становится невыразимой, потому "+
				"что читатель не провязывается, а следом отвергается старт.",
				cond, platformAcceptanceBinding, fset.Position(pos))
		}
	}

	t.Logf("перепись: вызовов провязки нашего читателя %d · под объявленным приёмом %d",
		len(calls), len(calls))
}

// TestF1b_EnclosingCondPredicateCanFail — САМОПРОВЕРКА предиката на СИНТЕТИКЕ.
//
// Предикат, не краснеющий на дефекте, не удерживает ничего. Синтетика намеренно
// не опирается на живой корень: опирайся она на него, доказательство исчезло бы
// вместе с починкой — ровно тогда, когда предикат достиг цели.
func TestF1b_EnclosingCondPredicateCanFail(t *testing.T) {
	const src = `package main
func wire() {
	if legacyProviderURL != "" {
		auth = auth.WithPlatformRevocationCheck(a, 0)
	}
	if platformAccepted {
		auth = auth.WithPlatformRevocationCheck(b, 0)
	}
}
`
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "main.go", src, 0)
	if err != nil {
		t.Fatalf("синтетика не разбирается: %v", err)
	}
	calls := f1bFindCall(f, "WithPlatformRevocationCheck")
	if len(calls) != 2 {
		t.Fatalf("мест %d, ожидалось 2", len(calls))
	}
	// Дефект: вложен в чужую ветку — предикат обязан назвать ЕЁ условие.
	if got := enclosingIfCond(fset, f, calls[0]); got != `legacyProviderURL != ""` {
		t.Fatalf("вложенность в чужую ветку не распознана: %q", got)
	}
	// Законный близнец той же формы — молчание.
	if got := enclosingIfCond(fset, f, calls[1]); got != platformAcceptanceBinding {
		t.Fatalf("законная вложенность объявлена находкой: %q", got)
	}
}
