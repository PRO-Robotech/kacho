// TestSubjectChangeReaderIsWiredToTheVerdictCache — ПОСЛЕДНЕЕ звено цепи,
// которое сквозная проба владельца достать не может.
//
// # Что уже доказано в другом месте
//
// Что изменение прав доезжает от производителя журнала до читателя и заставляет
// его погасить кэш — утверждает сквозная проба на стороне владельца
// (`services/iam/internal/repo/kacho/pg`, `TestRightsChangeReachesTheEdge…`): она
// ставит вопрос через обе стороны на настоящей схеме, настоящем контракте и
// настоящем читателе `pkg/subjectchange`.
//
// Достать оттуда она не может ровно одного: КУДА этот читатель провязан здесь.
// Кэш решений живёт в дереве края, и правило видимости `internal/` не пускает к
// нему владельца — не по нашей нерадивости, а по построению языка.
//
// # Поэтому здесь судится ПРОВЯЗКА, и только она
//
// Читатель обязан гасить ИМЕННО кэш вердиктов слоя прав. Провяжи его к чему
// угодно другому — сквозная проба останется зелёной (она о читателе), а отзыв
// перестанет доезжать, и не покраснеет ничто.
//
// Судится текст композиционного корня, а не поведение: поднять край целиком ради
// одной строки дороже, чем прочитать её, и предмет здесь — именно строка.
func TestSubjectChangeReaderIsWiredToTheVerdictCache(t *testing.T) {
	src, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatalf("чтение композиционного корня: %v", err)
	}
	root := string(src)

	const wiring = "subjectchange.New(reader, authzMW.InvalidateCache,"
	if !strings.Contains(root, wiring) {
		t.Fatalf("читатель журнала смены субъекта не провязан к кэшу вердиктов.\n"+
			"Ожидалось: %s\n\n"+
			"Гасить он обязан ИМЕННО кэш решений слоя прав. Провязанный к чему-то "+
			"другому, он оставит сквозную пробу владельца зелёной — она о читателе, "+
			"а не о том, куда его подключили, — и отзыв перестанет доезжать молча.",
			wiring)
	}

	// Соединение открывает ПОТРЕБИТЕЛЬ, и берёт он его у УЖЕ ОБЪЯВЛЕННОГО адреса
	// владельца. Второе объявление того же адреса разошлось бы с первым молча:
	// оба непусты, оба резолвятся, ведут в разные места.
	const dial = `subjectchange.NewReader(backends["iamInternal"])`
	if !strings.Contains(root, dial) {
		t.Fatalf("читатель открывает соединение не по объявленному адресу владельца.\n"+
			"Ожидалось: %s", dial)
	}

	// И обратное: толчка от владельца больше нет. Появись он снова, ребро из
	// листа обратно к потребителю вернулось бы вместе с ним.
	for _, gone := range []string{
		"InternalAuthzCacheService",
		"startInternalGRPCListener",
		"AsInvalidator",
	} {
		if strings.Contains(root, gone) {
			t.Errorf("композиционный корень снова знает %q: обратное ребро "+
				"владелец→потребитель вернулось", gone)
		}
	}
}
