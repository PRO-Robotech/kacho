package domain

import "fmt"

// Пределы кратности повторяемых полей запроса создания машины.
//
// # Почему предел вообще нужен
//
// Кратность повторяемого поля публичного запроса НАПРЯМУЮ умножает работу, которую
// один запрос делает за пределами процесса. У списка интерфейсов каждый элемент
// стоит одного обращения к владельцу подсети (kacho-vpc), и каждое такое обращение
// сосед авторизует у себя. Без предела длину резал только размер сообщения — то
// есть порядок десятков тысяч элементов, — и один корректный запрос выпускал
// десятки тысяч авторизованных вызовов к соседу, занимая при этом слот ОБЩЕГО пула
// исполнителей асинхронных мутаций до его собственного предела в четыре минуты.
// Слотов шестьдесят четыре; занять их все стоило около трети запроса в секунду,
// что в метриках частоты неотличимо от тишины.
//
// # Где предел обязан проверяться
//
// Синхронно, в проверке запроса, ДО любого обращения к соседу — иначе он защищает
// от роста строки, но не от нагрузки: список сверх предела всё равно оплачивался бы
// вызовами. Канонический образец того же класса у соседа (nlb, набор групп
// безопасности на балансировщике) проверяется ровно там же и по той же причине.
//
// # Почему восемь
//
// Восемь интерфейсов на машину — потолок, за которым в этом продукте нет сценария:
// адресация, группы безопасности и маршрутизация задаются на подсети, поэтому
// осмысленная кратность измеряется единицами. Столько же вторичных томов, и этот
// предел контракт УЖЕ объявлял (`(size) = "<=8"` на поле вторичных томов) — просто
// не проверял никто: расширения проверок из объявлений не читает ни одна строка
// прод-кода, поэтому объявление было обещанием без исполнителя. Совпадение
// объявленного и проверяемого заперто гейтом
// internal/repohygiene.TestDeclaredCardinalityLimitsHaveAnEnforcer.
const (
	// MaxNetworkInterfaceSpecsPerInstance — предел числа интерфейсов в запросе
	// создания машины. Каждый элемент стоит одного обращения к kacho-vpc.
	MaxNetworkInterfaceSpecsPerInstance = 8
	// MaxSecondaryVolumeSpecsPerInstance — предел числа вторичных томов в запросе
	// создания машины. Значение объявлено контрактом (`(size) = "<=8"`).
	MaxSecondaryVolumeSpecsPerInstance = 8
)

// Бюджет свободной карты данных машины (`metadata`).
//
// # Почему граница нужна
//
// Карта принималась без единой границы, а правка СЛИВАЕТСЯ в уже накопленное,
// поэтому потолок размера сообщения не ограничивал хранимое вовсе: карта росла от
// вызова к вызову до потолка поля БД. И каждая правка навсегда клала весь выросший
// блоб ещё и в две служебные таблицы (ответ операции и исходящую очередь), которые
// не подчищаются никогда, — при том что база у сервиса одна на всех тенантов.
// Записанное объяснение отсутствия границы («ограничивает потолок сообщения») было
// ложным именно в этой части.
//
// # Где проверяется
//
// Дельта — синхронно, в проверке запроса, чтобы отказ называл поле и не стоил
// строки операции. ИТОГ СЛИЯНИЯ — на уровне БД (CHECK), потому что «прочитать →
// сложить → проверить → записать» здесь было бы проверкой до записи с окном между
// ними: два одновременных upsert'а прошли бы каждый по отдельности и превысили
// бюджет вместе.
//
// # Числа
//
// 256 КиБ суммарно — с запасом накрывает реальное назначение поля (cloud-init
// user-data, ключи, короткие пометки) и на три порядка ниже потолка поля БД.
// 64 ключа — столько же, сколько у меток; длина ключа 128 байт.
const (
	// MaxInstanceMetadataKeys — предел числа ключей карты.
	MaxInstanceMetadataKeys = 64
	// MaxInstanceMetadataKeyLen — предел длины ключа в байтах.
	MaxInstanceMetadataKeyLen = 128
	// MaxInstanceMetadataBytes — предел СУММАРНОГО размера карты в байтах
	// (сериализованное представление; тем же предикатом её меряет CHECK в БД).
	MaxInstanceMetadataBytes = 256 * 1024
)

// ValidateInstanceMetadata проверяет бюджет свободной карты данных машины.
//
// Возвращает имя поля и человекочитаемую причину; в gRPC-статус их переводит
// вызывающий слой (тон и код — по конвенции сервиса).
//
// Меряется СЕРИАЛИЗОВАННЫЙ размер («ключ=значение» плюс разделители) — тем же
// предикатом, которым бюджет накопленной карты меряет CHECK в БД. Разойдись они,
// синхронный отказ и отказ БД говорили бы о разном.
func ValidateInstanceMetadata(m map[string]string) (field, reason string, ok bool) {
	if len(m) > MaxInstanceMetadataKeys {
		return "metadata", fmt.Sprintf("metadata must contain at most %d keys (got %d)",
			MaxInstanceMetadataKeys, len(m)), false
	}
	total := 0
	for k, v := range m {
		if len(k) > MaxInstanceMetadataKeyLen {
			return "metadata", fmt.Sprintf("metadata key must be at most %d bytes (got %d)",
				MaxInstanceMetadataKeyLen, len(k)), false
		}
		total += len(k) + len(v) + metadataPairOverhead
	}
	if total > MaxInstanceMetadataBytes {
		return "metadata", fmt.Sprintf("metadata must be at most %d bytes in total (got %d)",
			MaxInstanceMetadataBytes, total), false
	}
	return "", "", true
}

// metadataPairOverhead — накладные байты одной пары в сериализованном виде
// (кавычки, двоеточие, запятая). Учитываются, чтобы синхронная оценка не была
// заметно ОПТИМИСТИЧНЕЕ той, что делает БД: иначе запрос проходил бы проверку и
// падал на записи.
const metadataPairOverhead = 6
