// Фикстура учёта для проб, чей предмет — НЕ учёт.
//
// Файл БЕЗ признака сборки `integration` намеренно: его зовёт `setupTestDB`
// (`integration_test.go`), у которого признака тоже нет. Поставь признак сюда —
// и обычная сборка проб перестанет находить помощника, а падение будет говорить
// про неизвестный идентификатор, а не про то, что случилось.
//
// # Зачем это существует
//
// С появлением учёта вставка строки ресурса СПИСЫВАЕТ место, а списать его не с
// чего, пока у проекта нет строки учёта: «не сказано» — отказ, а не «без
// предела». На живом пути строку заводит материализация ПЕРЕД
// writer-транзакцией; проба этого пакета идёт мимо use-case'а, прямо в
// репозиторий, и потому обязана привести базу в то же состояние, в каком её
// видит репозиторий на живом пути. Иначе сорок пять проб, не имеющих к квотам
// никакого отношения, краснели бы одним и тем же «потолок не назван».
//
// # Почему это НЕ послабление
//
// Фикстура заводит строку ТЕМ ЖЕ оператором, что и продукт
// (`MaterializeQuotas` — единственный, и `QuotaRepo.Materialize` зовёт его же),
// то есть она не подставная реализация, а вызов настоящей. Механизм при этом
// продолжает работать на каждой вставке: триггер списывает, удаление
// возвращает, отказ на исчерпании возможен. Меняется ровно одно — величина у
// этих проектов заведомо больше, чем им нужно, потому что предмет этих проб
// лежит в другом месте. Величину назначает администратор, и «большой предел у
// служебного проекта» — состояние, которое продукт производит штатно.
//
// # Почему перечень, а не «всем подряд»
//
// Умолчание «любой проект получает место» сделало бы невыразимым состояние
// «потолка нет» — то самое, которое проверяют пробы учёта рядом
// (`quota_integration_test.go`). Они держат СВОИ идентичности (`prj-quota-*`,
// `prj-no-ceiling`, `prj-with-ceiling`), в этот перечень не входят и заводят
// строки сами.
//
// # Что произойдёт с пробой, заведённой позже
//
// Новая проба с неназванной здесь идентичностью получит отказ
// `resource count quota not provisioned: project <id> has no ceiling stated for <вид>` —
// громкий, называющий предмет и указывающий, что делать: либо добавить
// идентичность сюда, либо (если предмет пробы — сам учёт) завести строку самой.
//
// # Граница этого обещания — она у́же, чем здесь стояло (перемерено 2026-08-16)
//
// Прежняя редакция кончалась словами «перечень поэтому не дрейфует молча:
// расхождение с деревом наблюдаемо в тот же прогон». Обещание верно ровно для
// проб, которые прогон ИСПОЛНЯЕТ, — а пробы под признаком сборки `integration`
// не исполнял никто: юнит-прогон идёт с `-short`, интеграционный шёл без
// признаков, и сам пакет под своим признаком не собирался вовсе.
//
// Наблюдалось на `prj-bind`: три пробы владения узлом заведены раньше учёта,
// учёт пришёл миграцией 0036, и свип по перечню обошёл их стороной. Громкий
// отказ, обещанный выше, был бы верным — его просто некому было произнести.
//
// Обе половины закрыты: СОБИРАЕМОСТЬ держит гейт
// `internal/repohygiene/buildtaggedtestpackage_test.go`, ИСПОЛНЕНИЕ —
// `-tags=integration` в цели `test-integration` корневого Makefile. Свойства
// разные, и одно другого не заменяет; до них обоих обещание выше было
// объявлением.

// fixtureQuotaLimit — предел служебных проектов проб.
//
// Заведомо больше, чем нужно любой пробе пакета: предел здесь не предмет
// утверждения, а условие, при котором предмет вообще достижим. Проба, которой
// нужен ИСЧЕРПАННЫЙ предел, заводит свой проект и свою величину.
const fixtureQuotaLimit = 1_000_000

// fixtureQuotaKinds — три тенантных вида домена, ровно те, на которых висят
// триггеры учёта (миграция 0036).
//
// Выписаны, а не выведены из каталога: у владельца типа копии каталога нет by
// construction — перечень приезжает ответом владельца величин. Здесь соседа нет,
// поэтому фикстура называет виды прямо. Разойдясь с набором триггеров, перечень
// проявит себя тем же громким отказом, что и незаведённая идентичность.
var fixtureQuotaKinds = []string{
	"compute.instance",
	"compute.guestAccessKey",
	"compute.placementGroup",
}

// fixtureProjects — идентичности проектов, которыми пользуются пробы пакета.
//
// Пробы учёта (`prj-quota-*`, `prj-no-ceiling`, `prj-with-ceiling`) здесь
// отсутствуют НАМЕРЕННО: их предмет — поведение при заведённой и при
