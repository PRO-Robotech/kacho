// seedFixtureQuotas приводит свежую базу пробы в состояние «проекты
// материализованы».
//
// Идёт через `MaterializeQuotas` — тот же и единственный оператор, которым
// пользуется живой путь. Своего INSERT здесь нет намеренно: копия оператора
// разошлась бы с настоящим молча, и разошлась бы именно там, где расхождение не
// видно, — на составе столбцов.
// Помощник ЭКСПОРТИРОВАН намеренно: пробы пакета разделены на внутренние
// (`repo`) и внешние (`repo_test`), и обе половины вставляют ресурсы. Список
// идентичностей обязан быть ОДИН — две копии разошлись бы молча, и разошлись бы
// именно там, где расхождение не видно: у пробы, заведённой позже в другой
// половине.
func SeedFixtureQuotas(t testing.TB, dsn string) {
	t.Helper()
	ctx := context.Background()

	conn, err := pgx.Connect(ctx, dsn)
	require.NoError(t, err, "фикстура учёта: подключение к базе пробы")
	defer func() { _ = conn.Close(ctx) }()

	rows := make([]ports.QuotaRow, 0, len(fixtureProjects)*len(fixtureQuotaKinds))
	for _, p := range fixtureProjects {
		for _, k := range fixtureQuotaKinds {
			rows = append(rows, ports.QuotaRow{
				CarrierType:   ports.QuotaCarrierProject,
				CarrierID:     p,
				Kind:          k,
				Limit:         fixtureQuotaLimit,
				SourceScope:   "DEFAULT",
				SourceScopeID: "",
				LimitRevision: 0,
				// Зеркало аккаунта непусто: схема отвергает пустое, и отвергает
				// правильно — строка без зеркала невидима аккаунтной дельте.
				AccountID: "acc-fixture",
			})
		}
	}

	n, err := MaterializeQuotas(ctx, conn, rows)
	require.NoError(t, err, "фикстура учёта: заведение строк")
	require.Equal(t, int64(len(rows)), n,
		"перепись: заведено строк — столько же, сколько объявлено. Расхождение означает, "+
			"что часть идентичностей уже существовала, то есть фикстура работает не на свежей базе")
}
