package repo

import (
	"context"
	"fmt"
	"sort"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ExistenceProbe — read-only сверка «есть ли такой объект в МОЕЙ базе» по его
// объекту модели прав.
//
// Спрашивается ТОЛЬКО на пути отказа. Владелец модели отвечает одинаково и на
// несуществующий объект, и на существующий чужой, поэтому различить «объекта
// нет» и «объект есть, но не твой» может лишь тот, у кого строка лежит в базе.
// Без сверки отказ на СВОЮ несуществующую машину приходил бы формой сокрытия от
// звена решения, а не собственным промахом обработчика; со сверкой отсутствующий
// объект пропускается к обработчику, а существующий чужой отвечает голосом
// владельца — байт в байт тем же текстом, что и настоящий промах.
//
// Лёгкий `SELECT EXISTS` без чтения строки: вопрос задаётся на каждом отказе.
type ExistenceProbe struct {
	pool *pgxpool.Pool
}

// NewExistenceProbe собирает пробу поверх пула композиционного корня, и пул
// обязан быть МАСТЕРОМ.
//
// Реплика здесь была бы дефектом, а не оптимизацией. Проба отвечает на вопрос
// «объекта не существует?», и ответ «да» превращает отказ в правах в промах
// обработчика. На реплике только что созданная машина какое-то время не видна,
// поэтому владелец, обратившийся к своему свежему ресурсу, получил бы «не
// существует» — тот же ответ, что и посторонний, которому машина недоступна. То
// есть отсутствие и недоступность перестали бы различаться именно в момент,
// когда объект уже создан. Задержка репликации сверху не ограничена и отсюда не
// наблюдаема, поэтому «обычно свежая реплика» защитой не является.
func NewExistenceProbe(pool *pgxpool.Pool) *ExistenceProbe {
	return &ExistenceProbe{pool: pool}
}

// objectTypeTable — whitelist «тип объекта модели прав → таблица». Имя таблицы
// берётся ТОЛЬКО из этой константной карты, никогда из запроса, — подстановка
// невозможна by construction.
//
// Перечень обязан покрывать ВСЕ пообъектные типы карты прав сервиса, и это
// сверяет носитель на старте (`servicehost`, О5в) — сравнением с
// `catalogderive.ObjectScopedTypes`, выведенной из той же карты, по которой
// рантайм решает, спрашивать ли пробу. Тип, попавший в карту и не попавший
// сюда, отвечает на отказе ошибкой пробы, а она fail-closed — то есть `403`
// там, где соседний тип того же сервиса отвечает `404`.
//
// # Здесь стояло «пообъектный тип ровно один» — утверждение пережило свой предмет
//
// Прежняя редакция говорила: «Замер по карте прав compute: пообъектный тип из
// неё выводится РОВНО один — `compute_instance`». На день записи это было
// верно; ключ входа в машину (`0032_guest_access_keys.sql`) и группа
// размещения (`0033_placement_groups.sql`) приехали позже, каждый со своими
// записями каталога прав, и перепись стала другой. Перемер (задача продукта
// решением о скрытии существования): `catalogderive.ObjectScopedTypes(check.PermissionMap())` даёт **три**
// — `compute_guest_access_key`, `compute_instance`, `compute_placement_group`,
// — а карта знала один. Два типа отвечали на отказе не тем кодом, что третий,
// и покраснеть было нечему: обе полосы защитимы по отдельности.
//
// Тип машины (`MachineTypeService`) и внутренний каталог типов гейтятся
// кластерным ярусом, объекта у них нет, и в переписи их нет тоже.
//
// Имя таблицы неквалифицированное — тем же способом, каким её адресует слой
// доступа к данным (`instance_repo.go`): схема приезжает из `search_path`
// соединения, и вторая запись пути разошлась бы с первой молча.
var objectTypeTable = map[string]string{
	"compute_instance": "instances",
	// Ключ входа в машину — `0032_guest_access_keys.sql`, `id text PRIMARY KEY`.
	"compute_guest_access_key": "guest_access_keys",
	// Группа размещения — `0033_placement_groups.sql`, `id text PRIMARY KEY`.
	"compute_placement_group": "placement_groups",
}

// ProbeableTypes — типы, о которых проба умеет ответить.
//
// Возвращается свежий срез: носитель читает перечень и не вправе зависеть от
// того, что за ним стоит карта пакета.
func (p *ExistenceProbe) ProbeableTypes() []string {
	out := make([]string, 0, len(objectTypeTable))
	for ot := range objectTypeTable {
		out = append(out, ot)
	}
	sort.Strings(out)
	return out
}

// ObjectExists отвечает, есть ли строка с таким идентификатором в таблице,
// соответствующей типу объекта.
//
// Неизвестный тип — ОШИБКА, а не «нет»: вызывающий трактует ошибку как «не могу
// подтвердить отсутствие» и оставляет отказ отказом (fail-closed), тогда как
// молчаливое «нет» пропустило бы вызов к обработчику — то есть неизвестный тип
// открывал бы дверь, вместо того чтобы её запирать.
func (p *ExistenceProbe) ObjectExists(ctx context.Context, objectType, objectID string) (bool, error) {
	if p == nil || p.pool == nil {
		return false, fmt.Errorf("existence probe: pool is not wired")
	}
	table, ok := objectTypeTable[objectType]
	if !ok {
		return false, fmt.Errorf("existence probe: unprobeable object type %q", objectType)
	}
	var exists bool
	// table — из константного whitelist выше; objectID — связанный параметр.
	if err := p.pool.QueryRow(ctx,
		"SELECT EXISTS(SELECT 1 FROM "+table+" WHERE id = $1)", objectID,
	).Scan(&exists); err != nil {
		return false, err
	}
	return exists, nil
}
