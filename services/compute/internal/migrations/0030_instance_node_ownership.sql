-- Владение машиной узлом: кто вправе её исполнять прямо сейчас.
--
-- ЗАЧЕМ ЭТО, ЕСЛИ ОГРАЖДЕНИЯ ПОКА НЕТ. Довод «пока нет автоматического
-- переноса, двух писателей не бывает» НЕВЕРЕН, и это установлено разбором, а не
-- предположением: остаются ручное восстановление оператором, повтор после
-- разрыва связи и перезапуск агента. В каждом из трёх случаев второй узел может
-- начать исполнять машину, которую первый ещё исполняет — а том у них один.
--
-- ЧЕГО ЭТА ТАБЛИЦА НЕ ДЕЛАЕТ. Она не ограждение. Ограждение — примитив
-- хранилища, и оно единственное умеет отрезать узел, который нас не слушает.
-- Здесь — согласие между узлами, которые нас слушают: дешевле ограждения,
-- работает без него и закрывает три пути из четырёх. Четвёртый — узел, потерявший
-- связь и продолжающий писать — закрывается ограждением, и до него автоматический
-- перенос не вводится.
--
-- ПОЧЕМУ АРЕНДА, А НЕ ПРОСТО «ЧЕЙ УЗЕЛ». Узел, потерявший связь навсегда,
-- удерживал бы машину вечно, и она стала бы невосстановимой. Аренда истекает —
-- но её истечение НЕДОСТАТОЧНО для перехвата: узел обязан сам остановить машину
-- ДО истечения по своим часам, а перехват законен только с запасом, превышающим
-- срок самоостановки. Иначе разрыв связи с плоскостью управления, не разрывающий
-- связь с хранилищем, даёт ровно двух писателей.

-- +goose Up

CREATE TABLE instance_node_bindings (
    -- Машина. Первичный ключ, а не просто уникальный индекс: у машины ровно
    -- одна привязка либо ни одной, и это свойство самой строки.
    instance_id     text PRIMARY KEY
        REFERENCES instances(id) ON DELETE CASCADE,

    -- Узел, которому машина принадлежит сейчас. Идентификатор узла —
    -- инфра-чувствительные данные: на публичную проекцию не выходит никогда.
    node_id         text NOT NULL,

    -- Номер события доставки, по которому узел взял машину. Служит признаком
    -- поколения привязки: отчёт со старым номером не воскрешает снятую привязку.
    claimed_seq_no  bigint NOT NULL,

    -- До какого момента аренда действительна. Узел обязан продлить её раньше и
    -- остановить машину, если не сумел.
    lease_until     timestamptz NOT NULL,

    claimed_at      timestamptz NOT NULL DEFAULT now(),
    renewed_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT instance_node_bindings_node_check
        CHECK (length(node_id) BETWEEN 1 AND 253),
    CONSTRAINT instance_node_bindings_seq_check
        CHECK (claimed_seq_no > 0),
    -- Продление не может быть раньше взятия: строка, где это нарушено, описывает
    -- порядок событий, которого не было.
    CONSTRAINT instance_node_bindings_renew_order_check
        CHECK (renewed_at >= claimed_at)
);

-- Поиск истёкших аренд: работа сверщика, а не путь запроса. Частичный индекс не
-- нужен — истёкших мало, но проверяются они по всей таблице.
CREATE INDEX instance_node_bindings_lease_idx
    ON instance_node_bindings (lease_until);

-- «Что исполняет этот узел» — запрос оператора при выводе узла из обслуживания.
CREATE INDEX instance_node_bindings_node_idx
    ON instance_node_bindings (node_id);

-- +goose Down

DROP TABLE IF EXISTS instance_node_bindings;
