-- +goose Up
-- Снятие двух колонок NIC под DNS-записи — последнее, что осталось от поддерева DNS.
--
-- Колонки стоят здесь с самой первой миграции (0001) и за всю жизнь не получили ни
-- читателя, ни писателя: во всём дереве сервиса их имена встречались только в
-- собственном объявлении и в описании схемы. Поддерево DNS уже снято с контракта — на
-- входе оно было недостижимо по построению, на выходе доезжало до клиента ВСЕГДА
-- ПУСТЫМ, и отличить «записей нет» от «поле не реализовано» было нельзя.
--
-- Данные не переносятся, и это измерено, а не заявлено: ни одна миграция цепочки не
-- пишет в эту таблицу ни строки, поэтому снятие колонок на базе, построенной этой
-- цепочкой, уничтожает ноль строк. Счёт делает
-- repo/drop_nic_dns_columns_migration_integration_test.go на версии 0022, где колонки
-- ещё существуют и потому считаемы; drop-guard сервиса сюда не смотрит — он читает
-- DROP TABLE, а здесь уходят колонки.
--
-- DNS-запись не атрибут интерфейса машины: ей нужна зона, которой кто-то владеет,
-- набор записей со своим жизненным циклом, TTL и семантика распространения, и своя
-- авторизация. Появится — придёт своим доменом со своей приёмкой, а не колонкой,
-- которую забыли снять вместе с полем.
ALTER TABLE instance_network_interfaces
  DROP COLUMN primary_v4_dns_records,
  DROP COLUMN primary_v6_dns_records;

-- +goose Down
-- Восстановление в том же типе, с тем же умолчанием и той же обязательностью, что
-- были объявлены в 0001. Порядок колонок в таблице не восстанавливается — Postgres
-- добавляет их в конец, и позиционной вставки у него нет; на состав это не влияет.
ALTER TABLE instance_network_interfaces
  ADD COLUMN primary_v4_dns_records JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN primary_v6_dns_records JSONB NOT NULL DEFAULT '[]'::jsonb;
