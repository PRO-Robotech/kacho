-- 0027_instances_deleting_since.sql — отметка «когда строка вошла в DELETING».
--
-- ПРЕДМЕТ. Удаление ВМ — сага: сначала строка переводится в DELETING, затем
-- снимаются привязки интерфейсов и томов у их владельцев, и только последней
-- удаляется сама строка. Порядок выбран так, что крах на любом шаге оставляет
-- согласованное состояние: строка ещё жива, значит привязки резолвятся и повтор
-- доделает начатое.
--
-- Повторять, однако, было НЕКОМУ. Разрешитель осиротевших операций по контракту
-- не перезапускает рабочую функцию — он приводит статус операции в соответствие
-- закоммиченной реальности: видит, что строка на месте, и помечает операцию
-- прерванной. После этого ВМ остаётся в DELETING навсегда, а её интерфейсы и
-- тома — занятыми у владельцев, которые о случившемся не знают и знать не могут.
-- Занятый том нельзя присоединить к другой машине; занятый интерфейс держит
-- адрес из ограниченного пула.
--
-- ЗАЧЕМ КОЛОНКА. Добивателю нужен порог возраста — иначе он подхватит удаление,
-- которое прямо сейчас доделывает законный исполнитель, и они будут снимать одни
-- и те же привязки наперегонки. Взять порог было неоткуда: у instances нет
-- ни одной колонки времени, кроме created_at, а он про создание — по нему
-- давно созданная и только что удаляемая машина считалась бы «застрявшей» в тот
-- же миг.
--
-- Колонка NULLable намеренно: NULL означает «в удаление не входила», и это
-- отличимо от «вошла давно». Значение по умолчанию (например, эпоха) сделало бы
-- каждую живую машину вечно просроченной — ровно тот класс, когда защита
-- выглядит исполненной и пропускает всё.
--
-- BACKFILL. Строки, уже застрявшие в DELETING до этой миграции, получают
-- now(): их подлинное время входа не сохранил никто, а now() даёт им ровно один
-- полный интервал отсрочки перед тем, как добиватель их возьмёт. Это
-- консервативно в нужную сторону — задержка на один интервал против риска
-- схватить чужую живую сагу.

-- +goose Up

ALTER TABLE instances
    ADD COLUMN deleting_since TIMESTAMPTZ;

UPDATE instances SET deleting_since = now() WHERE status = 'DELETING';

-- Частичный индекс ровно под выборку добивателя: только строки в удалении,
-- упорядоченные по времени входа. Живые строки в индекс не входят, поэтому он
-- почти всегда пуст и ничего не стоит.
CREATE INDEX instances_deleting_since_idx
    ON instances (deleting_since)
    WHERE status = 'DELETING';

-- +goose Down

DROP INDEX IF EXISTS instances_deleting_since_idx;
ALTER TABLE instances DROP COLUMN IF EXISTS deleting_since;
