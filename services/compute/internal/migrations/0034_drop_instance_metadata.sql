-- Свободная карта данных машины снята вместе со своим бюджетом.
--
-- ЧТО ЭТО БЫЛО. Карта принималась на создании, писалась сюда и НЕ ВОЗВРАЩАЛАСЬ
-- НИКОГДА: поле ответа снято волной 1 вместе с остальной мёртвой поверхностью,
-- правка — вместе со своим RPC, а приём остался. Вызывающий получал успех и был
-- уверен, что его данные применены; прочитать их не мог никто, включая его
-- самого.
--
-- ПОЧЕМУ СНЯТИЕ, А НЕ ВОЗВРАТ ЧТЕНИЯ. Конфигурация гостя едет `user_data` и
-- выдаётся службой метаданных — это назначенный канал, у него есть читатель и
-- есть доставка. Вторая свободная карта рядом с ним не имеет ни того, ни
-- другого: она не участвовала ни в одном решении и ни в одном ответе.
--
-- ПОЧЕМУ НОВОЙ МИГРАЦИЕЙ. Бюджет карты объявлен применённой миграцией 0025, и
-- править её нельзя. Ограничение снимается здесь же, где колонка: оставить
-- проверку размера на несуществующей колонке нельзя, а снять её отдельно —
-- значит на один шаг иметь схему, где бюджет не держит ничего.

-- +goose Up

ALTER TABLE instances DROP CONSTRAINT IF EXISTS instances_metadata_budget_check;
ALTER TABLE instances DROP COLUMN IF EXISTS metadata;

-- +goose Down

-- Обратный путь восстанавливает колонку и её бюджет — но НЕ данные: их
-- содержимое не читалось ни одним путём, и восстанавливать нечего.
ALTER TABLE instances ADD COLUMN IF NOT EXISTS metadata jsonb NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE instances
    ADD CONSTRAINT instances_metadata_budget_check
    CHECK (octet_length(metadata::text) <= 262144);
