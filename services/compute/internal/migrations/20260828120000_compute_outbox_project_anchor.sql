-- +goose NO TRANSACTION
-- +goose Up
-- Журнал изменений получает ЯКОРЬ ПРОЕКТА колонкой.
--
-- Задача `PRO-Robotech/kacho#1019` (провязка общего сервера потока, `pkg/subscription`).
--
-- ЗАЧЕМ. Общая форма подписки несёт проектный якорь полем ОБОЛОЧКИ события, и по
-- нему принимается решение «кому это показать» — без обращения к предмету. Для
-- события снятия это несущее: обращаться не к чему, предмета больше нет, а
-- нагрузка у снятия беднее всего — она несёт один идентификатор.
--
-- ПОЧЕМУ НЕ РАЗБОР НАГРУЗКИ. Общая форма допускает и его, и он был рассмотрен.
-- У событий создания и правки якорь в нагрузке есть; у снятия его нет. Значит
-- разбор дал бы у снятий ПУСТОЙ якорь, а пустой якорь по контракту означает
-- «предмет уровня аккаунта или кластера» — утверждение, ложное для машины.
-- Дальше подписка с осью `project_id` такие события не пропускала бы, и
-- потребитель, снявший опрос, НИКОГДА не узнавал бы об удалении: он держал бы
-- удалённые строки вечно. Отказ наступает ТИХО — ни ошибки, ни пропуска в
-- нумерации, — и потому его не находят.
--
-- Второе следствие выбора: ось отбирается ЗАПРОСОМ по частичному индексу, а не
-- после чтения строки. Прочитано будет ровно то, что отдано.
--
-- ПОЧЕМУ ВНЕ ОБЩЕЙ ТРАНЗАКЦИИ. Сборка индекса без параллельного режима берёт на
-- таблице замок, разделяемый с чтением, но НЕ с записью: всякая вставка в журнал
-- ждала бы конца сборки, а вставка в журнал идёт в той же транзакции, что и
-- мутация ресурса, — то есть вставали бы и мутации. Такова же конвенция дерева:
-- ей следуют 17 миграций, собирающих индексы параллельно.
--
-- Цена режима названа: шаги перестают быть атомарными между собой, поэтому
-- каждый обязан быть ПОВТОРИМ. Сборка индекса вдобавок умеет оставить негодный
-- индекс при обрыве — его снимает предусловие ниже, до сборки.
--
-- ОБРАТНОЕ ЗАПОЛНЕНИЕ — по тому, что в нагрузке ЕСТЬ, и не более.
-- Нагрузка создания и правки записана обходом `encoding/json` по доменной
-- структуре, у которой поле проекта объявлено без своего имени, поэтому ключ
-- нагрузки — имя поля Go (`ProjectID`); согласие ключа с тем, что журнал реально
-- пишет, закреплено пробой `TestBackfillKeyMatchesWhatTheJournalActuallyWrites`.
-- Историческим СНЯТИЯМ заполнять якорь НЕОТКУДА: их нагрузка несёт только
-- идентификатор, а строка ресурса к этому моменту удалена. Такие строки остаются
-- с пустым якорем, и это названо прямо, а не замаскировано: суждение о показе
-- снятия идёт по якорю, поэтому строка без якоря остаётся при пообъектном
-- суждении и вызывающему не показывается. Умолчание пустой строкой, а не NULL, —
-- та же форма, что у соседнего журнала (`nlb_outbox`).
ALTER TABLE compute_outbox ADD COLUMN IF NOT EXISTS project_id TEXT NOT NULL DEFAULT '';

UPDATE compute_outbox
   SET project_id = payload->>'ProjectID'
 WHERE project_id = ''
   AND payload ? 'ProjectID'
   AND payload->>'ProjectID' IS NOT NULL;

-- Негодный индекс, оставшийся обрывом предыдущей попытки, снимается ДО сборки:
-- `IF NOT EXISTS` его не пересобирает — он видит имя занятым и молчит, и тогда
-- отбор по оси проекта шёл бы без индекса, ничем об этом не сообщая.
-- +goose StatementBegin
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_index i
          JOIN pg_class c ON c.oid = i.indexrelid
         WHERE c.relname = 'compute_outbox_project_idx' AND NOT i.indisvalid
    ) THEN
        EXECUTE 'DROP INDEX compute_outbox_project_idx';
    END IF;
END
$$;
-- +goose StatementEnd

-- Частичный индекс, а не полный: строки без якоря по нему не отбираются никогда
-- (подписка с осью проекта их не спрашивает), и держать их в индексе значило бы
-- платить за то, что не читается. Пара «якорь, номер» — ровно порядок, которым
-- читает поток: отбор по проекту с продвижением по возрастанию номера.
CREATE INDEX CONCURRENTLY IF NOT EXISTS compute_outbox_project_idx
    ON compute_outbox (project_id, sequence_no) WHERE project_id <> '';

-- +goose NO TRANSACTION
-- +goose Down
-- Возврат в форму без якоря.
--
-- ЧТО ТЕРЯЕТСЯ, И ЭТО НЕ ВОССТАНОВИТСЯ. Якоря уходят вместе с колонкой. Повторное
-- применение заполнит заново только те строки, у которых якорь ЕСТЬ В НАГРУЗКЕ, —
-- то есть создания и правки. Строки СНЯТИЯ, записанные уже с якорем в колонке,
-- источника в нагрузке не имеют (там один идентификатор) и после отката получат
-- пустой якорь навсегда: восстанавливать их не из чего.
--
-- Сказано прямо, потому что читать это будут при откате и под давлением. Потеря
-- неизбежна и сама по себе не порок — порок был бы в обещании восстановления,
-- которого не происходит.
DROP INDEX CONCURRENTLY IF EXISTS compute_outbox_project_idx;
ALTER TABLE compute_outbox DROP COLUMN IF EXISTS project_id;
