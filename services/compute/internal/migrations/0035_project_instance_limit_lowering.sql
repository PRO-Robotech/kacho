-- Понижение предела ниже текущего потребления обязано быть выразимо.
--
-- ЧТО БЫЛО НЕ ТАК. `CHECK (used <= limit_value)` из 0031 запрещал состояние
-- «занято больше, чем разрешено». Звучит как защита, а работает как запрет на
-- САМО ПОНИЖЕНИЕ: администратор, желающий ограничить проект, получал 23514,
-- пока проект сам не освободит место. То есть административное действие
-- становилось заложником того, кого оно ограничивает.
--
-- ПОЧЕМУ `used > limit_value` — ЗАКОННОЕ СОСТОЯНИЕ. Оно означает ровно то, что
-- нужно после понижения: новые нельзя, старые живут, удаление работает. Иного
-- корректного поведения у понижения нет — сносить чужие машины за арендатора
-- платформа не вправе, а откладывать понижение до его доброй воли значит не
-- иметь понижения вовсе.
--
-- ЧЕМ ТЕПЕРЬ ДЕРЖИТСЯ ПОТОЛОК. Условным списанием `UPDATE … WHERE used <
-- limit_value` — тем же единственным оператором, что берёт блокировку строки,
-- поэтому свойство не слабее прежнего: второй писатель ждёт коммита первого и
-- видит его результат. Ограничение схемы ловило превышение ПОСЛЕ того, как оно
-- уже записано; предикат не даёт его записать. Проба гонки (2N списаний при
-- пределе N) остаётся зелёной и на новом механизме — она и есть доказательство,
-- что замена не ослабила потолок.
--
-- ЦЕНА, НАЗВАННАЯ ЧЕСТНО. Инвариант теперь держит предикат списания, а не
-- ограничение схемы, поэтому путь, который запишет `used` мимо этого предиката,
-- потолок обойдёт. Сегодня такой путь ровно один — `chargeProjectQuota`, и
-- других производителей у таблицы нет вовсе (их нет и у самой величины предела:
-- строку не пишет ни один путь прод-кода). Гейт, доказывающий отсутствие обхода,
-- заводится вместе с производителем предела — до его появления охранять нечего.
--
-- ЧТО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Она не назначает пределы, не доводит исчерпание
-- до арендатора кодом `RESOURCE_EXHAUSTED` и не меняет трактовку отсутствующей
-- строки. Это предмет приёмки квот, а не схемы.

-- +goose Up

ALTER TABLE project_instance_quotas
    DROP CONSTRAINT IF EXISTS project_instance_quotas_within_limit_check;

-- +goose Down

-- Возврат ограничения возможен только там, где потребление ни в одном проекте
-- не превышает предел; иначе откат упал бы на данных, которые сам же и сделал
-- законными. Ограничение восстанавливается как NOT VALID: существующие строки
-- не перепроверяются (они законны по решению выше), а новые обязаны условию.
ALTER TABLE project_instance_quotas
    ADD CONSTRAINT project_instance_quotas_within_limit_check
        CHECK (used <= limit_value) NOT VALID;
