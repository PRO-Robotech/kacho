-- +goose Up
-- Бюджет свободной карты данных машины — на уровне БАЗЫ.
--
-- Правка карты СЛИВАЕТСЯ в уже накопленное
-- (`metadata = (metadata - $del) || $upsert`), поэтому проверка одной дельты
-- границу не держит: карту любой величины набирают множеством приемлемых по
-- отдельности правок. Программная проверка итога («прочитать → сложить →
-- проверить → записать») оставляла бы окно между проверкой и записью, в которое
-- две одновременные правки проходят каждая по отдельности и превышают бюджет
-- вместе. Инвариант внутри сервиса принадлежит базе — здесь он и стоит, а слияние
-- остаётся одним стейтментом.
--
-- Почему это вообще нужно. Поле принималось без единой границы, и записанное
-- объяснение («ограничивает потолок размера сообщения») было ложным именно в
-- несущей части: потолок ограничивает ОДИН вызов, а не хранимое. Карта росла от
-- вызова к вызову до потолка поля БД, и каждая правка навсегда клала весь выросший
-- блоб ещё и в две служебные таблицы (ответ операции и исходящую очередь), которые
-- не подчищаются никогда, — при том что база у сервиса одна на всех тенантов.
--
-- Предикат — octet_length(metadata::text): та же мера, которой синхронную оценку
-- делает domain.ValidateInstanceMetadata. Разойдись они, синхронный отказ и отказ
-- базы говорили бы о разном.
--
-- 256 КиБ с запасом накрывают реальное назначение поля (cloud-init user-data,
-- ключи, короткие пометки) и на три порядка ниже потолка поля БД.
--
-- Нарушение → SQLSTATE 23514 → ports.ErrInvalidArg (уже провязано в repo/unique.go),
-- то есть вызывающий получает неверный аргумент, а не внутреннюю ошибку.
--
-- Замок — services/compute/internal/repo/instance_metadata_budget_integration_test.go
-- (восемь правок по четверти бюджета: без базы все восемь проходили).
ALTER TABLE instances
    ADD CONSTRAINT instances_metadata_budget_check
    CHECK (octet_length(metadata::text) <= 262144);

-- +goose Down
ALTER TABLE instances DROP CONSTRAINT IF EXISTS instances_metadata_budget_check;
