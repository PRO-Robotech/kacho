-- +goose Up
-- Композитный индекс под КУРСОРНУЮ страницу списка машин.
--
-- Запрос списка одной формы:
--   WHERE project_id = $1 [AND name = …] AND (created_at, id) > ($2, $3)
--   ORDER BY created_at ASC, id ASC LIMIT page_size + 1
--
-- Индекса под эту пару не было: только раздельные однополевые (по проекту и по
-- времени создания). Планировщику оставались два плана, и ни один не по странице:
--   * скан по проекту + СОРТИРОВКА всех строк проекта на КАЖДУЮ страницу;
--   * скан по времени создания от позиции курсора + отбрасывание чужих проектов —
--     то есть чтение тем дороже, чем меньше доля проекта в таблице.
-- Полный обход проекта постранично при этом становится квадратичным, тогда как
-- курсорная пагинация продаётся клиенту как ПОСТОЯННАЯ стоимость страницы.
--
-- Ведущий столбец — project_id (единственное равенство запроса), затем
-- (created_at, id) в порядке сортировки: страница читается как непрерывный отрезок
-- индекса, без сортировки и без отбрасывания чужих строк.
--
-- Соседний каталог размеров машин композит под курсор уже несёт (миграция 0015,
-- «cursor pagination anchor») — здесь закрывается тот же путь доступа для главной
-- тенантной таблицы сервиса.
--
-- Замок — services/compute/internal/repo/instances_cursor_index_integration_test.go
-- (утверждает ПЛАН и число прочитанных строк, а не наличие строки в каталоге).
CREATE INDEX IF NOT EXISTS instances_project_cursor_idx ON instances (project_id, created_at, id);

