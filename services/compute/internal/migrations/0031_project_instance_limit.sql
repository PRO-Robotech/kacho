-- Предел числа машин на проект и счётчик потребления.
--
-- ЗАЧЕМ СЕЙЧАС, А НЕ ВМЕСТЕ С ДОМЕНОМ ЛИМИТОВ. Пока граф состояний был замкнут,
-- создание машины делало строку в базе и ничего больше — железа она не занимала,
-- и отсутствие предела было безобидно. Открытие графа меняет это полностью: тот
-- же вызов начинает делать машины на общем железе, а ограничителя в дереве нет
-- ни одного — ни предела, ни частотного ограничения. Аутентифицированный
-- вызывающий получал бы железо без счёта.
--
-- ПОЧЕМУ СЧЁТЧИК ЗДЕСЬ, А ПОЛИТИКА СНАРУЖИ. Лимит как ресурс — предмет
-- платформенного домена: он один на все сервисы, у него своё чтение и своя
-- выдача. Но СПИСАНИЕ обязано жить там же, где вставка строки, и в той же
-- транзакции: разнесённые «спросить» и «списать» схлопываются под конкуренцией,
-- и потолок вырождается в частоту, умноженную на число параллельных пар.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ СТРОКА, А НЕ ПОДСЧЁТ ПО ТАБЛИЦЕ. Подсчёт читает всю выборку
-- проекта на каждом создании и не блокирует ничего: два создателя посчитают
-- одно и то же число и оба пройдут. Строка счётчика блокируется при обновлении,
-- поэтому второй ждёт первого и видит его результат.

-- +goose Up

CREATE TABLE project_instance_quotas (
    project_id   text PRIMARY KEY,

    -- Сколько машин проекту разрешено. Значение приходит из платформенного
    -- домена лимитов; здесь оно — проекция, обновляемая его же путём.
    limit_value  integer NOT NULL,

    -- Сколько занято сейчас. Списывается ТЕМ ЖЕ стейтментом, что вставляет
    -- машину, и возвращается тем же, что её удаляет.
    used         integer NOT NULL DEFAULT 0,

    updated_at   timestamptz NOT NULL DEFAULT now(),

    -- Отрицательное потребление означало бы возврат того, что не списывали:
    -- удаление машины, которой не было. Ограничение ловит это в момент, когда
    -- ошибка ещё локальна.
    CONSTRAINT project_instance_quotas_used_check
        CHECK (used >= 0),

    -- Потребление сверх предела — не «перерасход», а состояние, из которого
    -- нельзя выйти правильно: непонятно, какие машины законны, а какие нет.
    -- Поэтому оно запрещено схемой, а не проверкой в коде.
    CONSTRAINT project_instance_quotas_within_limit_check
        CHECK (used <= limit_value),

    CONSTRAINT project_instance_quotas_limit_check
        CHECK (limit_value >= 0)
);

-- +goose Down

DROP TABLE IF EXISTS project_instance_quotas;
