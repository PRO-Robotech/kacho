package config

import (
	"github.com/PRO-Robotech/kacho/pkg/grpcsrv"
)

// Validate — ДОПОЛНЕНИЕ к центральному стражу посадки, а не его замена.
//
// НЕСУЩИЙ СТРАЖ — ЦЕНТРАЛЬНЫЙ ДЕСКРИПТОР. Посадку compute судит
// `servicecontract.New(servicecontract.Spec{…})` в `cmd/compute/describe.go`:
// режим, `sslmode`, круг отправителей, транспорт обоих слушателей и ребра
// решения о доступе — одним перечнем безопасных значений на всё дерево, с
// отказом, называющим каждую негодную ось разом. Ошибка возвращается наверх и
// роняет старт до подъёма слушателей.
//
// ЧТО ЭТА ФУНКЦИЯ ДОБАВЛЯЕТ СВЕРХ НЕГО — одно, и оно названо точно: дескриптор
// требует сужения круга отправителей В БОЕВОМ режиме, а здесь оно требуется на
// ЛЮБОМ non-breakglass старте. Контроль, чья ветка на локальном стенде не
// исполняется ни разу, находит «забыл выставить круг» только на боевом профиле,
// где цена ошибки максимальна.
//
// Здесь стояло «прочие боевые инварианты остаются в `cmd/compute` и переезжают
// сюда отдельным шагом». Отсрочка была записана прозой, без задачи и без
// предиката снятия — а запрет тех-долга знает три исхода, и «сказать словами,
// что отложено» среди них нет. К тому же она пережила свой предмет: инварианты
// уехали не сюда, а в дескриптор, и судятся им сегодня.
//
// Здесь же стояло «проверка, привязанная к значению, едет с ним всюду: второй
// процесс из этого конфига получил бы его без единой проверки». Довод не
// держится замером: мигратор (`cmd/migrator`) — единственный второй процесс, и
// он этой функции НЕ ЗОВЁТ. Обоснование описывало намерение, а не код.
func (c Config) Validate() error {
	// Круг отправителей обязан быть сужен на ЛЮБОМ non-breakglass старте, а не
	// только в боевом режиме: контроль, чья ветка на локальном стенде не
	// исполняется ни разу, находит «забыл выставить круг» только на боевом
	// профиле, где цена ошибки максимальна. Вне боевого режима пустой круг
	// остаётся возможным, но как ЯВНЫЙ опт-ин.
	//
	// Аварийный режим освобождает — по ИСТОРИЧЕСКОЙ причине, которой больше нет, и
	// это названо прямо: прежде он снимал per-RPC проверку целиком, а с переездом
	// контура на общий носитель не снимает ничего (см. Config.AuthZBreakglass).
	// Освобождение оставлено потому, что наблюдаемого послабления оно не даёт: тот
	// же круг тем же предикатом судит конструктор дескриптора, безусловно. В боевом
	// режиме взведённая ручка отвергается отдельно (cmd/compute validateAuthMode).
	//
	// Стража общая на все семь сервисов: grpcsrv.TrustedForwarders.Require — один
	// исход, один текст отказа, различаются только имена ручек.
	if c.AuthZBreakglass {
		return nil
	}
	return c.TrustedForwarders().Require(grpcsrv.ForwarderGate{
		Production:   c.AuthMode == "production" || c.AuthMode == "production-strict",
		DevTrustAny:  c.AuthZTrustAnyForwarder,
		SANsKnob:     "KACHO_COMPUTE_AUTHZ_TRUSTED_FORWARDER_SANS",
		TrustAnyKnob: "KACHO_COMPUTE_AUTHZ_TRUST_ANY_FORWARDER",
	})
}
