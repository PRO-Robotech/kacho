package config

import (
	"testing"

	corequota "github.com/PRO-Robotech/kacho/pkg/quota"
)

// Свидетель отказа: страж посадки обязан ОТВЕРГАТЬ несуженный круг отправителей.
//
// Прежде такой пробы не было ни у одного из двух самых компактных стражей, и
// гейт присутствия этого не видел: его предикат совпадал с любым вызовом
// `Validate`, включая доменные проверки. То есть страж, возвращающий nil,
// прошёл бы насквозь — ровно та форма без содержания, ради которой гейт заведён.
//
// Пустой круг означает «не сужаем», а НЕ «запрещаем»: переданную личность
// примет любой проверенный пир. Сертификат доказывает, что пир предъявил наш
// удостоверяющий центр, и ничего не говорит о том, за кого ему позволено
// говорить, — поэтому сужение обязано быть явным и непустым.
func TestValidateRefusesUnnarrowedForwarderCircle(t *testing.T) {
	var c Config
	c.AuthMode = "production"
	if err := c.Validate(); err == nil {
		t.Fatal("несуженный круг отправителей принят: контроль выглядит включённым, " +
			"а переданную личность примет любой проверенный пир")
	}
}

// Парный положительный контроль: с суженным кругом страж молчит. Без него
// отрицание выше зеленело бы и на страже, отвергающем всё подряд.
func TestValidateAcceptsNarrowedForwarderCircle(t *testing.T) {
	var c Config
	c.AuthMode = "production"
	// Объявление домена величин — часть законной посадки: без него конфигурация
	// отличалась бы от законной ДВУМЯ фактами, и красное выше означало бы не то,
	// что объявлено.
	c.QuotaAuthority = corequota.NotDeployed
	c.AuthZTrustedForwarderSANs = []string{"spiffe://kacho.cloud/ns/kacho/sa/kacho-api-gateway"}
	if err := c.Validate(); err != nil {
		t.Fatalf("суженный круг отвергнут — тогда красное выше означает не то, что объявлено: %v", err)
	}
}
