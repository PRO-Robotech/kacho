package main

// audit_outbox_metrics.go — сканер состояния ЖУРНАЛА АУДИТА вычислений.
//
// # Почему сканер есть, а дренажа нет
//
// Журнал аудита пишется в той же транзакции, что и мутация (миграция
// 0028_audit_outbox.sql), и не доставляется никуда: приёмника аудита в продукте
// не существует ни одного, поэтому дренаж вести некуда. Снять журнал тоже
// нельзя — это решение уровня требований к аудиту control-plane, а не уборка
// кода. Оба вывода записаны решением вместе с предикатом их пересмотра:
// services/iam/docs/engineering/architecture/audit-outbox-has-no-receiver.md.
//
// # Что тогда делает этот сканер
//
// Делает МОЛЧАНИЕ СЛЫШИМЫМ. `data-integrity.md` требует, чтобы «ноль
// доставленных строк за всю жизнь очереди» было заметно; до этого сканера
// заметить это было нечем — величины не существовало вовсе, и очередь без
// доставки выглядела ровно как пустая. Он НИЧЕГО НЕ ИЗОБРАЖАЕТ: глубина растёт
// монотонно, возраст головы равен возрасту стенда, отравленных ноль (попыток
// доставки не было ни одной). Именно это и есть верное описание положения дел.
//
// # Почему провязан БЕЗУСЛОВНО, а не рядом с обвязкой очереди регистраций
//
// Обвязка очереди регистраций поднимается только при включённом её дренаже
// (`KACHO_COMPUTE_FGA_REGISTER_DRAINER_ENABLED`). Журнал аудита наполняется
// НЕЗАВИСИМО от этой ручки — его пишет каждая мутация репозитория, — поэтому
// сканер, поставленный под тот же переключатель, замолчал бы ровно на той
// посадке, где очередь всё равно растёт.
//
// # Почему форма объявляется, а не подразумевается
//
// Эта очередь помечает доставленность СОСТОЯНИЕМ (`status = 'sent'`), а число
// попыток держит в `attempts`. Умолчание пакета читает другую форму
// (`sent_at IS NULL` + `attempt_count`), и на ней первый же скан упал бы на
// «колонки attempt_count нет» — то есть очередь была бы ненаблюдаема by
// construction, а её ненаблюдаемость выглядела бы как ненужность наблюдения.

import (
	"context"
	"log/slog"

	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/PRO-Robotech/kacho/pkg/outbox/metrics"
)

// computeAuditOutboxTable — журнал аудита вычислений.
//
// Константой пакета, а не полем чужой структуры и не вычислением: гейт
// repohygiene резолвит координату очереди разбором исходника, и адрес,
// собранный в рантайме, для него неотличим от отсутствующего — то есть очередь
// снова выпала бы из переписи молча.
const computeAuditOutboxTable = "public.audit_outbox"

// computeAuditOutboxMaxAttempts — порог отравления.
//
// Объявлен ЗДЕСЬ, а не взят из конфигурации дренажа, ровно потому, что дренажа
// нет. Значение совпадает с умолчанием пакета дренажа: гейдж отравленных обязан
// считать по тому же порогу, по которому будет травить будущий дренаж, — иначе
// в день его появления величина сменит смысл молча.
const computeAuditOutboxMaxAttempts = 10

// runAuditOutboxMetrics — периодический скан журнала аудита.
//
// Ошибка скана логируется и цикл продолжается: наблюдаемость не гейт и уронить
// под не может.
func runAuditOutboxMetrics(ctx context.Context, pool *pgxpool.Pool, rec metrics.Recorder, logger *slog.Logger) {
	collector := metrics.NewCollector(pool, rec, metrics.CollectorConfig{
		Table:       computeAuditOutboxTable,
		MaxAttempts: computeAuditOutboxMaxAttempts,
		Shape:       metrics.ShapeStatus,
	})
	collector.Run(ctx, func(err error) {
		logger.Warn("audit outbox metrics scan failed",
			slog.String("table", computeAuditOutboxTable), slog.String("err", err.Error()))
	})
}
