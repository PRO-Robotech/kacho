// СХЕМОЙ.
//
// # Предмет
//
// Сканер состояния не гейт: ошибка скана логируется и цикл продолжается. Значит
// форма, объявленная не та, не роняет НИЧЕГО — она молча превращает сканер в
// шум: каждые пятнадцать секунд в лог уходит «колонки нет», величина не
// публикуется никогда, и очередь снова становится неотличимой от пустой. Это
// ровно тот класс, ради закрытия которого сканер и поднят, только с другой
// стороны.
//
// Пакет наблюдаемости читает две формы: умолчание помечает доставленность
// ОТМЕТКОЙ ВРЕМЕНИ (`sent_at IS NULL` + `attempt_count`), объявленная здесь —
// СОСТОЯНИЕМ (`status = 'sent'` + `attempts`). Журнал аудита вычислений несёт
// вторую, и разница не косметическая: колонки `attempt_count` у него нет вовсе.
//
// # Проба утверждает ПАРУ, а не одну сторону
//
// Одной стороны не хватило бы ни в том, ни в другом направлении:
//
//	проводка объявляет ShapeStatus          — иначе можно сменить форму, не покраснев;
//	схема несёт колонки этой формы          — иначе можно переименовать колонку, не покраснев;
//	схема НЕ несёт колонку формы-умолчания  — контроль: без него первое утверждение
//	                                          было бы верно и при форме-умолчании,
//	                                          то есть ничего бы не различало.
//
// Проба читает ОБЪЯВЛЕНИЕ (исходник проводки и текст миграции), а не живую базу:
// она обязана падать на обзоре изменения, а не после его применения, и обязана
// работать без контейнера.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// auditQueueMigration — миграция, заводящая журнал аудита вычислений.
const auditQueueMigration = "../../internal/migrations/0028_audit_outbox.sql"

// auditQueueWiring — файл, объявляющий форму очереди сканеру.
const auditQueueWiring = "audit_outbox_metrics.go"

func TestAuditOutboxScannerShapeMatchesTheSchema(t *testing.T) {
	wiring := readForShape(t, auditQueueWiring)
	schema := readForShape(t, auditQueueMigration)

	t.Logf("ОБЪЁМ ОСМОТРЕННОГО: проводка %s (%d байт) · схема %s (%d байт)",
		auditQueueWiring, len(wiring), filepath.Base(auditQueueMigration), len(schema))

	// 1. Проводка объявляет форму «состояние», а не молчит и не берёт умолчание.
	if !strings.Contains(wiring, "Shape:       metrics.ShapeStatus") &&
		!strings.Contains(wiring, "Shape: metrics.ShapeStatus") {
		t.Errorf("%s не объявляет metrics.ShapeStatus. Без объявления сканер возьмёт "+
			"умолчание пакета — форму с отметкой времени, — и первый же скан упрётся в "+
			"колонку attempt_count, которой у этой очереди нет. Сканер при этом не "+
			"упадёт: он залогирует отказ и продолжит, то есть очередь снова станет "+
			"неотличимой от пустой.", auditQueueWiring)
	}

	// 2. Схема несёт колонки объявленной формы.
	for _, col := range []string{"status", "attempts"} {
		if !declaresColumn(schema, col) {
			t.Errorf("схема журнала не объявляет колонку %q, которую читает "+
				"metrics.ShapeStatus. Либо колонку переименовали новой миграцией — тогда "+
				"форма в %s обязана переехать за ней тем же изменением, — либо форма "+
				"объявлена не та.", col, auditQueueWiring)
		}
	}

	// 3. Контроль: колонки формы-умолчания у схемы НЕТ.
	//
	// Без этого утверждения пункт 2 был бы верен и для формы-умолчания (обе
	// читают `sent_at`), то есть не различал бы формы вовсе — и проба зеленела бы
	// на любой из них.
	if declaresColumn(schema, "attempt_count") {
		t.Errorf("схема журнала объявила attempt_count — колонку формы-умолчания. Тогда " +
			"объявление ShapeStatus перестало быть различающим: обе формы стали " +
			"исполнимыми, и проба ниже ничего не доказывает. Перечитай, какая форма у " +
			"этой очереди теперь верна.")
	}
}

// readForShape — файл целиком; отсутствие файла — отказ, а не пропуск.
//
// Проба, тихо пропускающая себя при переехавшем файле, утверждает о дереве
// ровно ничего и при этом выглядит зелёной.
func readForShape(t *testing.T, rel string) string {
	t.Helper()
	body, err := os.ReadFile(rel)
	if err != nil {
		t.Fatalf("файл %s не читается: %v — проба не может судить то, чего не видит "+
			"(файл переехал? тогда переехать обязана и координата здесь)", rel, err)
	}
	if len(body) == 0 {
		t.Fatalf("файл %s пуст — молчание пробы ничего не доказывало бы", rel)
	}
	return string(body)
}

// declaresColumn — ОБЪЯВЛЕНИЕ колонки, а не упоминание имени.
//
// Имя колонки стоит и в комментариях миграции, и внутри ограничений; засчитывать
// их значило бы считать объяснение исполнением — тот самый класс, который эта
// линия и закрывает.
func declaresColumn(schema, col string) bool {
	for _, line := range strings.Split(schema, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "--") {
			continue
		}
		rest, ok := strings.CutPrefix(trimmed, col)
		if !ok {
			continue
		}
		// За именем обязан идти пробел и тип, а не буква имени подлиннее
		// (`attempts` против `attempts_total`).
		if rest == "" || (rest[0] != ' ' && rest[0] != '\t') {
			continue
		}
		return true
	}
	return false
}
