package main

// listener_registrar_choice_test.go — ВЫБОР регистратора в композиционном корне.
//
// # Что этой пробы не хватало
//
// Рубеж «публичный слушатель не читает заголовки администратора» держится
// конструкцией: у публичного конструктора параметра «слушатель» нет, поэтому
// написать «публичный, но с админскими заголовками» невозможно. Пробы рядом это
// закрепляют — и все они спрашивают САМИ КОНСТРУКТОРЫ.
//
// Незакрытым оставался шаг раньше: КАКОЙ конструктор корень зовёт на какой
// стороне. Инъекция подтвердила дыру — замена публичного регистратора на
// внутренний в вызове `servicehost.Serve` собиралась чисто и не роняла ни одной
// пробы во всём дереве. То есть публичный слушатель начал бы признавать
// ретранслируемые краем `x-kacho-admin` и `x-kacho-project-id`, и об этом не
// покраснело бы ничто.
//
// # Почему проба читает исходник, а не поведение
//
// Поведение обёрток уже закреплено соседями (что делает каждая из них). Здесь
// предмет другой — СООТВЕТСТВИЕ стороны и конструктора в единственном месте, где
// оно решается. Достать это из поднятого процесса нельзя: обе стороны отдают
// одинаковый `grpc.ServiceRegistrar`, а различие живёт в том, какой функцией он
// обёрнут, и наружу не проявляется, пока не придёт запрос с админским заголовком
// на публичный порт — то есть ровно тогда, когда проверять поздно.
//
// Поэтому утверждение синтаксическое, и его границы названы честно: оно ловит
// подмену конструктора и перестановку сторон, но не поймает переписывание самих
// обёрток. Для второго есть соседи.

import (
	"os"
	"strings"
	"testing"
)

// TestPublicSideCallsThePublicRegistrar — стороны и конструкторы не перепутаны.
func TestPublicSideCallsThePublicRegistrar(t *testing.T) {
	const root = "main.go"
	src, err := os.ReadFile(root)
	if err != nil {
		t.Fatalf("композиционный корень не прочитан: %v", err)
	}
	text := string(src)

	call := strings.Index(text, "servicehost.Serve(serveCtx, desc,")
	if call < 0 {
		t.Fatal("в корне нет вызова носителя `servicehost.Serve(serveCtx, desc,` — " +
			"проба ничего не осмотрела, и её молчание неотличимо от исправности")
	}
	tail := text[call:]
	end := strings.Index(tail, "\n\t\t)")
	if end < 0 {
		t.Fatal("не найден конец вызова носителя — предикат разошёлся с формой корня")
	}
	region := tail[:end]

	pub := strings.Index(region, "handler.PublicRegistrar(")
	intr := strings.Index(region, "handler.InternalRegistrar(")

	switch {
	case pub < 0:
		t.Error("публичная сторона носителя не зовёт handler.PublicRegistrar: заголовки " +
			"администратора и проектной области читались бы на ПУБЛИЧНОМ слушателе — тот самый " +
			"подлог, ради которого рубеж и заведён")
	case intr < 0:
		t.Error("внутренняя сторона не зовёт handler.InternalRegistrar: администраторские " +
			"заголовки перестали бы читаться там, где они законны, и внутренние методы " +
			"отвергали бы своего же вызывающего")
	case pub > intr:
		t.Error("стороны переставлены местами: первым аргументом носителя идёт ПУБЛИЧНЫЙ " +
			"регистратор, и раньше в тексте встретился внутренний")
	}

	// Положительный контроль: оба конструктора вообще существуют под этими именами.
	// Без него переименование обеих обёрток дало бы два `< 0` и проба сообщила бы о
	// подлоге там, где его нет.
	if strings.Count(region, "handler.PublicRegistrar(")+strings.Count(region, "handler.InternalRegistrar(") == 0 {
		t.Fatal("в области вызова носителя нет НИ ОДНОГО из двух конструкторов — " +
			"скорее всего их переименовали, и предикат этой пробы устарел вместе с ними")
	}
	t.Logf("перепись: область вызова носителя %d символов, публичный на позиции %d, внутренний на %d",
		len(region), pub, intr)
}
