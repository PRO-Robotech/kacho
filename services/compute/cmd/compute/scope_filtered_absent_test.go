// Здесь лежал файл из трёх проб, связывавших загрузочного стража фильтра
// пообъектной видимости с RPC, которые на него опираются: страж и перечень
// таких RPC не должны были расходиться, и связь утверждалась в обе стороны.
//
// Предмета у той связи больше нет. Сужаемым по данным у compute был ровно один
// метод — поток журнала изменений, — и он снят вместе со своей поверхностью
//. Пробы, требовавшие непустоты перечня, краснели бы вечно на достижении
// собственной цели; замер по дереву: у vpc такой метод один, у iam восемь, у
// storage и registry по одному, у compute, nlb и geo — ноль.
//
// Что осталось нормой и потому проверяется ниже: страж — это код, который
// защищает СВОЙСТВО, а не строку в конфигурации. Пока сужаемых методов нет,
// перечень обязан быть ПУСТ, а не «почти пуст»: появившаяся запись означает либо
// возврат снятого, либо новый метод, чей сужатель никем не провязан — и тогда
// «сужение живёт на уровне данных» становится заявлением без исполнителя.
//
// Появится такой метод — вернётся и файл: связь в обе стороны, и проба, что
// страж отказывает в старте при невключённом фильтре.
func TestComputeHasNoScopeFilteredRPCsWhileTheStreamIsRetired(t *testing.T) {
	m := check.PermissionMap()
	if len(m) == 0 {
		t.Fatal("карта прав пуста — «сужаемых нет» было бы вакуумной истиной на " +
			"пустом наборе; карта выводится из контракта, значит сломан её вывод")
	}
	var filtered []string
	for fqn, e := range m {
		if e.ScopeFiltered {
			filtered = append(filtered, fqn)
		}
	}
	if len(filtered) != 0 {
		t.Fatalf("сужаемых по данным RPC у compute: %v, ожидался ноль.\nЛибо снятый "+
			"поток вернулся — имя стоит в надгробии retiredRPCSurface, либо "+
			"заведён новый метод — тогда верните пробы связи со стражем фильтра: "+
			"без них «сужение живёт на данных» остаётся заявлением без исполнителя", filtered)
	}
	t.Logf("осмотрено записей карты прав: %d, сужаемых по данным среди них: 0", len(m))
}
