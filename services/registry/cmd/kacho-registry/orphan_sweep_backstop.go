package main

import (
	"context"
	"log/slog"
	"time"

	"github.com/PRO-Robotech/kacho/services/registry/internal/repo/kacho/pg"
)

// orphanSweepInterval — как часто владелец сверяет объекты прав со своими живыми
// таблицами. Час, а не минуты: предмет — не оперативный отказ, а расхождение,
// которое накапливается медленно и терпит.
const orphanSweepInterval = time.Hour

// startOrphanSweepBackstop поднимает периодическую сверку «объект прав есть, ресурса
// у владельца нет» с эмиссией снятия на каждый такой объект.
//
// # Зачем он нужен, если накопление уже остановлено
//
// Прямая причина закрыта: удаление реестра теперь эмитирует снятие на каждый свой
// репозиторий. Но закрыта ОДНА причина, а свойство, которое требуется держать, шире
// неё — «у объекта прав есть живой ресурс». Оно нарушалось молча и может нарушиться
// снова любым будущим путём, снимающим строку без намерения: ещё один каскад,
// восстановление базы из копии, ручная правка. Подметальщик утверждает само свойство,
// а не отсутствие одной его причины, и потому переживает следующую.
//
// Второе, ради чего он существует прямо сейчас: накопленное. Объекты, оставшиеся от
// уже случившегося, снимать больше некому — они не привязаны ни к какому будущему
// удалению. Подметальщик разбирает их теми же намерениями, что и обычный путь.
//
// # Почему это не гейт
//
// Сверка не участвует в пути запроса, не мутирует ресурсы и не может уронить под:
// ошибка прохода логируется, следующий проход повторяет. Она эмитирует намерения в
// собственную очередь владельца — то есть пользуется обычным путём со всеми его
// свойствами (доставка не менее одного раза, порядок по голове партиции,
// идемпотентное применение), а не правит хранилище прав в обход него.
//
// Первый проход идёт СРАЗУ, до первого тика: иначе после каждого перезапуска мусор
// ждал бы час, а перезапусков в жизни сервиса больше, чем часов между ними.
func startOrphanSweepBackstop(ctx context.Context, repo *pg.RegistryRepo, logger *slog.Logger) {
	log := logger.With(slog.String("component", "orphan_sweep"))
	go func() {
		tick := time.NewTicker(orphanSweepInterval)
		defer tick.Stop()
		runOrphanSweepOnce(ctx, repo, log)
		for {
			select {
			case <-ctx.Done():
				return
			case <-tick.C:
				runOrphanSweepOnce(ctx, repo, log)
			}
		}
	}()
}

// runOrphanSweepOnce — один проход. Названные объекты логируются поимённо: снятие
// прав обязано оставлять след, по которому потом можно сказать, что именно было снято
// и почему, — «подмёл N штук» такого следа не даёт.
func runOrphanSweepOnce(ctx context.Context, repo *pg.RegistryRepo, log *slog.Logger) {
	// Проход не должен висеть до конца жизни процесса на неотвечающей базе.
	sweepCtx, cancel := context.WithTimeout(ctx, 2*time.Minute)
	defer cancel()

	named, err := repo.SweepOrphanedRepositories(sweepCtx, -1)
	if err != nil {
		log.Warn("сверка объектов прав с живыми ресурсами не завершилась",
			"withdrawn_before_error", len(named), "err", err)
		return
	}
	if len(named) == 0 {
		// Ноль находок печатается тоже: молчащий подметальщик неотличим от
		// неподнятого, а различить их — ровно та задача, ради которой заведена
		// наблюдаемость очереди.
		log.Info("сверка объектов прав завершена: расхождений нет")
		return
	}
	for _, objectID := range named {
		log.Info("объект прав снят: живого ресурса у владельца нет", "object", objectID)
	}
	log.Warn("сняты объекты прав без живого ресурса", "count", len(named))
}
