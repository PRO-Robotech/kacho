package pg

import (
	"context"
	"fmt"
	"sort"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ExistenceProbe — read-only сверка «есть ли такой объект в МОЕЙ базе» по его
// объекту модели прав.
//
// Спрашивается ТОЛЬКО на пути отказа: владелец модели отвечает одинаково и на
// несуществующий объект, и на существующий чужой, поэтому различить «объекта
// нет» и «объект есть, но не твой» может лишь тот, у кого строка лежит в базе.
// Без этой сверки отказ на СВОЙ несуществующий реестр приходил бы формой
// сокрытия (`Registry <id> not found` от звена решения), а не собственным
// промахом обработчика; с ней отсутствующий объект пропускается к обработчику, а
// существующий чужой отвечает голосом владельца.
//
// Лёгкий `SELECT EXISTS` без чтения строки: вопрос задаётся на каждом отказе.
type ExistenceProbe struct {
	pool *pgxpool.Pool
}

// NewExistenceProbe собирает пробу поверх пула, который передаёт композиционный
// корень, и этот пул обязан быть МАСТЕРОМ.
//
// Реплика здесь была бы дефектом, а не оптимизацией. Проба отвечает на вопрос
// «объекта не существует?», и ответ «да» превращает отказ в правах в промах
// обработчика. На реплике только что созданный реестр какое-то время не виден,
// поэтому владелец, обратившийся к собственному свежему ресурсу, получил бы
// «не существует» вместо нормального разрешения — и тот же ответ получил бы
// посторонний, которому реестр недоступен, то есть отсутствие и недоступность
// перестали бы различаться в пользу первого именно в момент, когда объект уже
// создан. Задержка репликации не ограничена сверху и отсюда не наблюдаема,
// поэтому «обычно свежая реплика» защитой не является.
func NewExistenceProbe(pool *pgxpool.Pool) *ExistenceProbe {
	return &ExistenceProbe{pool: pool}
}

// objectTypeTable — whitelist «тип объекта модели прав → таблица схемы
// kacho_registry». Имя таблицы берётся ТОЛЬКО из этой константной карты (никогда
// из запроса) — подстановка невозможна.
//
// Тип репозитория (`registry_repository`) сюда НЕ входит намеренно: он
// пообъектным по карте прав не является (его RPC несут `scope_filtered`, и
// решение по ним принимается на уровне данных в `internal/handler/listauthz.go`,
// со своим сокрытием существования), поэтому носитель о нём эту пробу не
// спрашивает. Заведи он тип здесь «про запас» — получилась бы ветка, которую
// никто не дёргает.
var objectTypeTable = map[string]string{
	"registry_registry": "registries",
}

// ObjectExists отвечает, есть ли строка с таким идентификатором в таблице,
// соответствующей типу объекта. Неизвестный тип — ОШИБКА, а не «нет»:
// вызывающий трактует ошибку как «не могу подтвердить отсутствие» и оставляет
// отказ отказом (fail-closed), тогда как молчаливое «нет» пропустило бы вызов к
// обработчику.
func (p *ExistenceProbe) ObjectExists(ctx context.Context, objectType, objectID string) (bool, error) {
	if p == nil || p.pool == nil {
		return false, fmt.Errorf("existence probe: pool is not wired")
	}
	table, ok := objectTypeTable[objectType]
	if !ok {
		return false, fmt.Errorf("existence probe: unprobeable object type %q", objectType)
	}
	var exists bool
	// table — из константного whitelist выше; objectID — связанный параметр.
	if err := p.pool.QueryRow(ctx,
		"SELECT EXISTS(SELECT 1 FROM "+schema+"."+table+" WHERE id = $1)", objectID,
	).Scan(&exists); err != nil {
		return false, err
	}
	return exists, nil
}

// ProbeableTypes — типы, о которых проба умеет ответить.
//
// Перечень обязан покрывать ВСЕ пообъектные типы карты прав сервиса; сверяет
// это носитель на старте (`servicehost`, О5в) сравнением с
// `catalogderive.ObjectScopedTypes` — обе стороны выведены, ни одна не
// выписана в месте сравнения. Тип, попавший в карту и не попавший сюда,
// отвечает на отказе ошибкой пробы, а она fail-closed: `403` там, где соседний
// тип того же сервиса отвечает `404` (задача продукта #1931).
//
// Возвращается свежий срез: носитель читает перечень и не вправе зависеть от
// того, что за ним стоит карта пакета.
func (p *ExistenceProbe) ProbeableTypes() []string {
	out := make([]string, 0, len(objectTypeTable))
	for ot := range objectTypeTable {
		out = append(out, ot)
	}
	sort.Strings(out)
	return out
}
