package domain

// repo_parent_chain_test.go — регистрация репозитория называет ПРОМЕЖУТОЧНОЕ
// звено иерархии, а не только проект.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Репозиторий подчинён РЕЕСТРУ, а реестр — проекту. Namespace-полей регистрации
// два — проект и аккаунт, — и реестра среди них нет: до появления цепи
// репозиторий регистрировался с одним `ParentProjectID`, то есть как будто
// подчинён проекту напрямую. Промежуточное звено не существовало для области
// выдачи вовсе.
//
// Чем это плохо на практике: выдача, сделанная НА РЕЕСТР, не достигала его
// репозиториев — между ними не было ребра. Отказ при этом честный по форме
// («нет права»), и отличить его от настоящего отсутствия выдачи нельзя ничем,
// кроме как знать про пропущенное звено.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО УТВЕРЖДАЕТСЯ
//
// Порядок цепи — от БЛИЖАЙШЕГО предка к дальнему, и он несущий: по нему
// принимающая сторона проставляет глубину ребра. Перевёрнутая цепь означала бы
// «проект лежит под репозиторием» — форма верная, смысл обратный, и ни одна
// проверка формы этого не поймает.

import "testing"

func TestRepoRegistrationNamesTheRegistryAsItsNearestAncestor(t *testing.T) {
	const (
		registryID = "reg-abc"
		repo       = "team/app"
		projectID  = "prj-xyz"
	)

	intent := RegisterIntentForRepoPush(registryID, repo, projectID, "user:usr-1")

	if len(intent.ParentChain) != 2 {
		t.Fatalf("цепь предков репозитория = %v (длина %d), ожидалось два звена: "+
			"реестр, затем проект. Одно звено означает, что промежуточный предок снова "+
			"потерян", intent.ParentChain, len(intent.ParentChain))
	}
	if got, want := intent.ParentChain[0], "registry_registry:"+registryID; got != want {
		t.Errorf("ближайший предок = %q, ожидался %q — порядок цепи несущий: по нему "+
			"проставляется глубина ребра, и перевёрнутая цепь означает «проект лежит под "+
			"репозиторием»", got, want)
	}
	if got, want := intent.ParentChain[1], "project:"+projectID; got != want {
		t.Errorf("дальний предок = %q, ожидался %q", got, want)
	}

	// Положительный контроль: прежнее поле НЕ снято. Цепь его дополняет, а не
	// заменяет — принимающая сторона по-прежнему кладёт проект в зеркало, и
	// вызывающие, которые цепь не шлют, ничего не теряют.
	if intent.ParentProjectID != projectID {
		t.Errorf("ParentProjectID = %q, ожидался %q — цепь ДОПОЛНЯЕТ прежние поля, "+
			"а не замещает их", intent.ParentProjectID, projectID)
	}

	t.Logf("осмотрено: звеньев цепи %d %v", len(intent.ParentChain), intent.ParentChain)
}
