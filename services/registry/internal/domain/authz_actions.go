// authz_actions.go — СТРОКИ ПРАВ реестра, названные один раз.
//
// Строка права — не то же, что тип объекта модели прав, и путать их нельзя: тип
// отвечает «что это за предмет» (`registry_registry`), строка права — «какой
// глагол над ним просят» (`registry.registries.list`). Ни одна из них не
// выводится из другой ни в какую сторону, поэтому обе названы, а не вычислены.
//
// Подлинник строки — аннотация контракта (`option (kacho.iam.authz.v1.permission)`
// у глагола). Согласие этой константы с подлинником держит проба
// `TestActionRegistryListIsDerivedFromTheContractAnnotation`: она читает
// аннотацию через реестр дескрипторов и требует дословного совпадения. Значит
// константа — не второе решение, а имя, у которого есть машинно проверяемый
// источник.
//
// Живёт в домене, потому что домен и есть дом словаря реестра: рядом стоят типы
// объектов модели прав (`FGAObjectTypeRegistry` и соседи). Читатель у константы
// сегодня один — объявление журнала подписки, которому запрещено выписывать
// чужие слова литералом.
const (
	// ActionRegistryList — право ЧИТАТЬ КАТАЛОГ реестров
	// (`kacho.cloud.registry.v1.RegistryService/List`).
	//
	// Им же поток подписки спрашивает модель прав о видимости строки журнала:
	// вопрос, который задаёт поток, обязан быть ТЕМ ЖЕ вопросом, что задаёт
	// список, а не похожим. Разойдись они — подписчик видел бы в потоке не то,
	// что видит в списке, и ни один отказ этого бы не назвал.
	ActionRegistryList = "registry.registries.list"
)
