package check

import "time"

// disabledCacheTTL — окно, которым выражается «положительный кэш выключен»:
// запись истекает раньше следующего запроса (монотонные часы строго растут между
// записью вердикта и его чтением в другом вызове), поэтому ни один устаревший
// «разрешено» не доживает до следующей проверки, и отзыв действует немедленно.
//
// Отдельного «выключенного» режима у кэша общего фундамента нет: `NewCache(≤0)`
// молча берёт своё умолчание в пять секунд. Выражать выключение нулём, отданным
// ему как есть, значило бы получить не отсутствие окна, а чужое окно, которого
// никто не выбирал.
const disabledCacheTTL = time.Nanosecond

// CacheWindow — окно кэша положительных вердиктов, ВЫВЕДЕННОЕ из ручки
// `KACHO_REGISTRY_AUTHZ_CACHE_TTL`.
//
// Существует ради одного предмета: окно отзыва обязано быть строго
// положительным там, где его читает носитель контура (`servicecontract.Spec`
// отвергает неположительное — параметр безопасности, которого никто не выбирал,
// нельзя ни обсудить, ни сузить), а ручка при этом сохраняет своё landed-значение
// «ноль = кэш выключен, отзыв немедленный». Обе стороны спрашивают ЭТУ функцию,
// поэтому «ручка выставлена в ноль» и «окно, с которым процесс поднялся» не могут
// разойтись.
func CacheWindow(ttl time.Duration) time.Duration {
	if ttl > 0 {
		return ttl
	}
	return disabledCacheTTL
}
