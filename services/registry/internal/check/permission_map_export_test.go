package check

import (
	// Дескрипторы обслуживаемых RPC обязаны быть в бинаре ЭТОГО пакета: карта
	// строится из их аннотаций, и пустой реестр дал бы карту без единой записи —
	// то есть отказ на каждом вызове. Импорт делает предпосылку вывода
	// принадлежностью пакета, а не удачей чужого графа импортов.
	_ "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/api"
	_ "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/registry/v1"
	"github.com/PRO-Robotech/kacho/pkg/authz"
	"github.com/PRO-Robotech/kacho/pkg/authz/catalogderive"
)

// permission_map_export_test.go — карта прав реестра ДЛЯ ПРОБ.
//
// # Почему это тестовый файл, а не прод-код
//
// Прежде отсюда карту брал собственный сборщик звена решения о доступе. Его
// больше нет: слушатели поднимает носитель контура, и карту он ВЫВОДИТ из
// служимого набора RPC — из тех же аннотаций и тем же `catalogderive`. Оставить
// здесь второе объявление значило бы завести второй источник одного предмета,
// который расходится молча; оставить прод-функцию без прод-читателя — мёртвый
// код, который выглядит работающим.
//
// Пробы домена при этом никуда не делись и остаются нужны: они утверждают
// свойства ВЫВЕДЕННОЙ карты (полнота покрытия, отношение на создании, граница
// читателя, окно отзыва) — то есть ровно то, что носитель выведет на старте из
// этих же пакетов. Поэтому объявление живёт здесь, в тестовой сборке пакета, и
// видно как `check.PermissionMap()` пробам обеих половин (`check` и
// `check_test`).

// protoPackages — proto-пакеты, чьи gRPC-сервисы поднимает registry. Тот же
// перечень носитель ВЫВОДИТ из имён служимых методов на каждом старте; здесь он
// выписан ради проб, которым нужно спросить карту без поднятия процесса.
var protoPackages = []string{
	"kacho.cloud.registry.v1",
	// LRO-конверт: Operation.Get/Cancel поднимает каждый сервис.
	"kacho.cloud.operation",
}

// PermissionMap — карта `<gRPC FullMethod>` → требуемое право, выведенная из
// аннотаций ровно так же, как её выводит носитель контура.
//
// Паникует (а не отдаёт неполную карту) при аннотации, называющей
// несуществующее поле запроса, при несвязанном пакете и при методе без
// аннотации вовсе: всё это свойства собранного бинаря, одинаковые на каждом
// прогоне, и каждое иначе выглядело бы как отказ по правам.
func PermissionMap() authz.RPCMap {
	return catalogderive.MustDerive(protoPackages...)
}
