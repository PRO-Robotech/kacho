// Package subscriptionjournal — объявление ЖУРНАЛА реестра для общего сервера
// потока изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы,
// сужение по правам и порядок отказов принадлежат общему серверу и владельцу не
// выдаются.
//
// # ЖУРНАЛ РЕСУРСОВ — НЕ ОЧЕРЕДЬ ПРАВ, и это две разные таблицы
//
// У реестра есть `registry_outbox` — очередь намерений регистрации ПРАВ. Она
// похожа на журнал ровно настолько, чтобы её захотелось переиспользовать, и
// непригодна по трём независимым причинам: её словарь родов события закрыт
// ограничением базы на двух словах, её нагрузка — набор кортежей прав, а её
// дренаж читает по голове партиции, поэтому чужая строка заклинивала бы выдачу
// прав. Ресурсный журнал живёт своей таблицей, со своим каналом и своим закрытым
// словарём; разделённость держится ограничениями ОБЕИХ таблиц — слово одной не
// проходит CHECK другой, — а не соглашением.
//
// # ВИД ОДИН — РЕЕСТР, и это решение, а не недоделка
//
// Строку в базе имеет только реестр. Репозиторий и тег — проекции zot: у
// репозитория в базе два вспомогательных следа, у тега нет ничего, а самый
// частый путь появления тега (потоковый проброс манифеста) к базе не обращается
// вовсе — пристегнуть эмиссию не к чему.
//
// Объявить их видами было бы ХУЖЕ, чем не объявить: тип объекта репозитория в
// модели прав существует, но в аннотациях контрактов не объявлен ни разу
// (репозиторные глаголы гейтятся сужением страницы, а не пообъектной записью
// каталога), и вопрос «вправе ли вызывающий видеть эту строку» задать было бы
// нечем. Поток по такому виду молчал бы, оставаясь «зелёным». Предмет назван и
// вынесен: репозитории и теги попадут в поток, когда у них появится
// транзакционный писатель состояния и объявленный тип в каталоге, — не раньше.
//
// # ЭМИССИЯ — ТРИГГЕРОМ БАЗЫ
//
// У репозитория реестра четыре пути мутации, и `MarkDeleting` идёт БЕЗ
// транзакции: это единственный переход ACTIVE→DELETING, и он наблюдаем
// арендатором. Понятия транзакционного порта у реестра нет вовсе, поэтому
// «позвать эмиттер в той же транзакции» здесь не выражается. Триггер снимает
// вопрос по построению — он всегда в транзакции своего оператора, — и якорь
// проекта берёт из строки, поэтому у снятия якорь есть.
//
// Цена решения: ключи нагрузки — ИМЕНА КОЛОНОК, а не имена полей Go. Отсюда
// собственный разбор ниже; его согласие со штатным отображением реестра в
// контракт закреплено интеграционной пробой, которая пишет строку настоящим
// репозиторием.
package subscriptionjournal

import (
	"encoding/json"
	"fmt"
	"time"

	"google.golang.org/protobuf/types/known/anypb"

	registryv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/registry/v1"
	subscriptionv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/subscription"
	"github.com/PRO-Robotech/kacho/pkg/authz"
	"github.com/PRO-Robotech/kacho/pkg/subscription"
	"github.com/PRO-Robotech/kacho/services/registry/internal/apps/kacho/shared/prototime"
	"github.com/PRO-Robotech/kacho/services/registry/internal/domain"
)

const (
	// Table — таблица ресурсного журнала, квалифицированная схемой.
	//
	// Имя говорит, что это ЖУРНАЛ РЕСУРСОВ: `registry_outbox` рядом занят чужим
	// предметом (очередь намерений о правах), и назвать журнал похоже значило бы
	// оставить следующему читателю две таблицы, различимые только чтением их
	// содержимого.
	Table = "kacho_registry.registry_resource_journal"

	// Channel — канал пробуждения.
	//
	// Он назван ОТДЕЛЬНО от таблицы, и реестр — ровно тот случай, ради которого
	// общая форма держит его отдельным полем: таблица схемо-квалифицирована, а
	// `pg_notify` квалифицированного имени не принимает. Вывод одного из другого
	// работал бы у владельцев с неквалифицированной таблицей и молча ошибался
	// здесь.
	//
	// Канал очереди прав (`kacho_registry_outbox`) сюда НЕ переиспользован: он
	// будит дренаж прав, и тот ходил бы за пустой выборкой на каждую мутацию
	// реестра — без отказа и потому незаметно.
	Channel = "registry_resource_journal"

	// JournalWordRegistry — слово, которым ТРИГГЕР записывает вид строки в
	// колонку `resource_kind`.
	//
	// Названо словом ЖУРНАЛА, а не «видом», намеренно: клиенту этот предмет едет
	// как `registry_registry` — тип объекта модели прав, единственное написание
	// вида на всё дерево. Имя вида `KindRegistry` утверждало бы обратное и было
	// бы прочитано следующим как то, что клиент пишет в ось `kinds`.
	JournalWordRegistry = "Registry"

	// Слова владельца для родов изменения. Ровно те три, что разрешает
	// ограничение базы (`registry_resource_journal_event_type_check`); согласие
	// объявления с ограничением и с тем, что пишет триггер, держит проба
	// `TestChangeDictionaryIsDerivedFromTheMigration`.
	changeCreated = "CREATED"
	changeUpdated = "UPDATED"
	changeDeleted = "DELETED"
)

// Journal — объявление журнала реестра.
//
// `endpointBase` — tenant-facing основа адреса реестра, из которой производится
// output-only поле `endpoint` (`<base>/<id>`). Она приходит ПАРАМЕТРОМ, а не
// зашита, по одной причине: адрес зависит от посадки, а состояние предмета
// обязано быть ПОЛНЫМ. Общая форма разрешает подписчику читать непустую нагрузку
// как полное состояние, поэтому событие без адреса читалось бы как «адрес у
// реестра исчез» — утверждение, которого владелец не делал.
//
// Пустое значение здесь недопустимо, и судит его КОМПОЗИЦИОННЫЙ КОРЕНЬ
// (`buildSubscriptionServer` отказывает в подъёме): отказ величины посадки не
// должен обнаруживаться первым событием в бою.
func Journal(endpointBase string) subscription.Journal {
	return subscription.Journal{
		Channel: Channel,
		Storage: subscription.Storage{
			Table:          Table,
			PositionColumn: "sequence_no",
			KindColumn:     "resource_kind",
			IDColumn:       "resource_id",
			ChangeColumn:   "event_type",
			PayloadColumn:  "payload",
			ProjectColumn:  "project_id",
			// Якорь лежит КОЛОНКОЙ, и её заполняет триггер из самой строки
			// (`NEW.project_id` / `OLD.project_id`). Значит у снятия якорь ЕСТЬ —
			// а разбор нагрузки дал бы там пустоту, потому что нагрузка снятия
			// несёт один идентификатор. Пустой якорь по контракту означает
			// «предмет уровня аккаунта или кластера», то есть утверждение, ложное
			// для реестра; подписка с осью проекта такие события не пропускала бы,
			// и потребитель, снявший опрос, об удалении не узнавал бы НИКОГДА.
			//
			// Второе следствие: ось отбирается ЗАПРОСОМ по частичному индексу
			// `registry_resource_journal_project_idx (project_id, sequence_no)
			// WHERE project_id <> ''` — прочитано будет ровно то, что отдано.
			Project: subscription.ProjectInColumn,
			// Журнал ЧИСТИТСЯ, и обещание подписчику меняется ВМЕСТЕ с этим.
			//
			// Прежняя редакция объявляла [subscription.RetainsEverything] и
			// говорила прямо: «заведётся чистка — эта величина обязана поменяться
			// вместе с ней, обещание удержания живёт ровно столько, сколько живёт
			// его основание». Основание снято задачей #1666: строка журнала
			// пишется на КАЖДОЙ мутации ресурса, темп задаёт арендатор, а снятия
			// строк не было ни на одном пути — рост был монотонным и вечным.
			//
			// Что теперь верно для подписчика: нижняя возобновимая позиция у
			// потока ЕСТЬ, она приходит в служебном сообщении открытия, и
			// возобновление с позиции ниже неё отвечает ЯВНЫМ отказом
			// `OutOfRange` с названной позицией — а не молча отдаёт неполное.
			// Окно объявлено платформой один раз ([subscription.JournalRetention]).
			Retention: subscription.RetainsFromEarliestRow,
			// Колонка срока — ПАРА к объявлению выше; предикат уборки строится по
			// ней. Отметку ставит умолчание колонки (`DEFAULT now()`, миграция
			// `20260828154000_registry_resource_journal.sql`), то есть часами
			// БАЗЫ — теми же, которыми судит уборщик, поэтому слагаемого на
			// разницу источников у порога нет.
			AgeColumn: "created_at",
		},
		Mapping: subscription.Mapping{
			// Словарь видов ЗАКРЫТ в обе стороны: вид вне его отвергается на
			// открытии, а строка вне его не доставляется — вопрос о видимости
			// задать нечем.
			//
			// СЛЕВА — слово ХРАНИЛИЩА (что пишет триггер в колонку), СПРАВА — то,
			// что едет клиенту. Клиенту едет ТИП ОБЪЕКТА: написание вида одно на
			// всё дерево, и берётся оно у ПРОИЗВОДИТЕЛЯ (`domain`), а не
			// выписывается — второе написание чужого словаря расходится молча.
			// Здесь оно разошлось бы виднее всего: слово хранилища у этого журнала
			// `Registry`, с заглавной и без домена, то есть ни на что в дереве не
			// похоже.
			//
			// Действие — то же право, которым гейтится КАТАЛОГ реестров
			// (`RegistryService/List`), а отношение видимости общий сервер берёт у
			// того же сужателя, что сужает страницу списка (`v_list` на
			// `registry_registry`). Значит вопрос, который задаёт поток, есть тот
			// же вопрос, что задаёт список, — а не похожий.
			Kinds: map[string]subscription.Kind{
				JournalWordRegistry: {
					ObjectType: domain.FGAObjectTypeRegistry,
					Action:     domain.ActionRegistryList,
				},
			},
			// Словарь родов изменения — ровно три слова, разрешённые ограничением
			// базы. Слово вне словаря делает строку недоставляемой, и потеря эта
			// тихая, поэтому перечень взят у ограничения, а не у сегодняшнего
			// прочтения триггера.
			Changes: map[string]subscriptionv1.SubscriptionEvent_Change{
				changeCreated: subscriptionv1.SubscriptionEvent_CREATED,
				changeUpdated: subscriptionv1.SubscriptionEvent_UPDATED,
				changeDeleted: subscriptionv1.SubscriptionEvent_DELETED,
			},
			State: stateWithEndpoint(endpointBase),
		},
	}
}

// ProjectGate — страж оси `project_id`.
//
// Без него вызывающий, назвавший недоступный ему проект, получил бы ОТКРЫТЫЙ
// поток, молчащий вечно: ни одна строка не прошла бы построчного сужения, и это
// читалось бы как «изменений нет».
//
// Форма отказа берётся у ПРОИЗВОДИТЕЛЯ форм скрытия, а не сочиняется здесь: она
// обязана быть неотличима от настоящего промаха владельца проектов, иначе
// подписка становится способом узнать существование чужого проекта. Отсутствие
// формы у производителя — отказ сборки, а не молчаливое умолчание: страж без
// формы отвечал бы отличимым текстом, то есть ровно тем, что закрывает.
func ProjectGate() (subscription.ProjectGate, error) {
	const projectObjectType = "project"
	form, ok := authz.OwnerNotFoundFormat(projectObjectType)
	if !ok {
		return subscription.ProjectGate{}, fmt.Errorf(
			"subscriptionjournal: у типа %q нет формы отсутствия у производителя (pkg/authz): "+
				"страж оси project_id отвечал бы текстом, отличимым от промаха владельца, "+
				"то есть выдавал бы существование чужого проекта", projectObjectType)
	}
	return subscription.ProjectGate{
		ObjectType: projectObjectType,
		// Действие и отношение — те же, которыми владелец проектов гейтит своё
		// чтение (`iam.v1.ProjectService/Get` в каталоге прав): вопрос «вправе ли
		// он видеть этот проект» обязан быть ТЕМ ЖЕ вопросом, а не похожим.
		Action:         "iam.projects.get",
		Relations:      []string{"v_get"},
		NotFoundFormat: form,
	}, nil
}

// journalRow — нагрузка события в том виде, в каком её кладёт ТРИГГЕР.
//
// Ключи — ИМЕНА КОЛОНОК (`to_jsonb(NEW)`), а не имена полей Go, и это следствие
// решения об эмиссии триггером. Имя колонки устойчивее: молчаливый рефактор Go
// его не трогает, а `buf breaking` имён полей Go не видит вовсе.
//
// Отметку создания триггер перекрывает явной формой RFC 3339 в UTC, потому что
// `to_jsonb` рендерит `timestamptz` по часовому поясу СЕССИИ: без этого форма
// публичной нагрузки зависела бы от настройки того, кто пишет.
type journalRow struct {
	ID                string            `json:"id"`
	ProjectID         string            `json:"project_id"`
	Name              string            `json:"name"`
	Description       string            `json:"description"`
	Labels            map[string]string `json:"labels"`
	Status            string            `json:"status"`
	CreatedAt         string            `json:"created_at"`
	DefaultVisibility string            `json:"default_visibility"`
	RegionID          string            `json:"region_id"`
	PlacementType     string            `json:"placement_type"`
}

// stateWithEndpoint — состояние предмета события.
//
// # Почему снятие отдаётся БЕЗ состояния, и это не потеря
//
// Нагрузка снятия несёт один идентификатор — полного состояния в ней нет и быть
// не может: предмета больше нет. Собрать из неё `registryv1.Registry` значило бы
// отдать подписчику почти пустой реестр, а контракт формы разрешает читать
// НЕПУСТУЮ нагрузку как ПОЛНОЕ состояние предмета. Подписчик записал бы пустые
// поля как факт: имя исчезло, регион исчез, метки исчезли.
//
// Поэтому род изменения спрашивается ЯВНО, а не выводится из бедности нагрузки:
// вывод из бедности сработал бы и на настоящем сбое разбора, и два разных исхода
// стали бы неразличимы.
//
// Для снятия подписчику довольно оболочки: вид, идентификатор, якорь проекта и
// род изменения — этого хватает, чтобы убрать строку из своего состояния.
//
// # Почему причина отсутствия у снятия — «НЕ ПРОИЗВОДИТСЯ»
//
// Журнал реестра состояние НЕСЁТ: у единственного своего вида он собирает полный
// контракт из нагрузки триггера. Значит отсутствие бывает ровно у одного рода — у
// снятия, где предмета больше нет by construction: собирать было нечего, попытки не
// было, повтор ничего не изменит. Это [subscription.StateNotProduced].
//
// Без названной причины сервер отдал бы `REASON_UNSPECIFIED` — «владелец забыл», —
// и подписчик, ключующийся на причину, пошёл бы ПЕРЕЧИТЫВАТЬ реестр, которого нет.
// Прежде он получал здесь «не удалось сериализовать», то есть объяснение снятия
// неудавшейся попыткой, которой не было.
func stateWithEndpoint(endpointBase string) func(subscription.Row) (*anypb.Any, subscription.StateAbsence, error) {
	return func(r subscription.Row) (*anypb.Any, subscription.StateAbsence, error) {
		if r.Change == changeDeleted {
			return nil, subscription.StateNotProduced, nil
		}
		var row journalRow
		if err := json.Unmarshal(r.Payload, &row); err != nil {
			return nil, subscription.StateAbsenceUnnamed, fmt.Errorf("разбор нагрузки журнала: %w", err)
		}
		createdAt, err := parseJournalTime(row.CreatedAt)
		if err != nil {
			return nil, subscription.StateAbsenceUnnamed, fmt.Errorf("отметка создания в нагрузке журнала: %w", err)
		}
		// Тип НАЗВАН: `Any` несёт имя типа на проводе, и ключи нагрузки суть поля
		// контракта владельца. Свободной структуры здесь нет намеренно — её ключи
		// производились бы от имён идентификаторов Go, и обычный внутренний
		// рефактор молча ломал бы публичную нагрузку.
		//
		// Состав и порядок полей повторяют штатное отображение реестра в контракт
		// (`internal/apps/kacho/api/registry`, `ProtoRegistry`). Что это ДВА места
		// об одном предмете — сказано вслух: отображение живёт методом use-case и
		// требует его коллабораторов, поэтому позвать его отсюда нельзя, не
		// потащив в объявление журнала весь прикладной слой. Расхождение
		// держит не соглашение, а интеграционная проба
		// `TestTriggerPayloadDecodesIntoTheSameProjectionTheServiceServes`: она
		// пишет строку настоящим репозиторием, читает её настоящим репозиторием и
		// требует, чтобы событие дало то же, что отдаёт сервис.
		return packed(anypb.New(&registryv1.Registry{
			Id:        row.ID,
			ProjectId: row.ProjectID,
			// Усечение до секунд — то же, что делает штатное отображение:
			// микросекунды базы на провод не текут, и событие обязано нести ту же
			// отметку, что и чтение по идентификатору.
			CreatedAt:                   prototime.Truncate(createdAt),
			Name:                        row.Name,
			Description:                 row.Description,
			Labels:                      row.Labels,
			Endpoint:                    endpointFor(endpointBase, row.ID),
			Status:                      registryStatusFromColumn(row.Status),
			DefaultRepositoryVisibility: registryv1.Visibility(domain.VisibilityFromString(row.DefaultVisibility)),
			RegionId:                    row.RegionID,
			PlacementType:               registryv1.PlacementType(domain.PlacementTypeFromString(row.PlacementType)),
		}))
	}
}

// packed переводит исход упаковки в тройку общей формы.
//
// Отказ упаковки — НАСТОЯЩИЙ отказ сборки: состояние есть, собрать не удалось.
// Причину такому исходу даёт сервер (`NOT_SERIALIZABLE`), и владелец её не
// называет: назвал бы — и свойство журнала стало бы неотличимо от поломки.
func packed(a *anypb.Any, err error) (*anypb.Any, subscription.StateAbsence, error) {
	if err != nil {
		return nil, subscription.StateAbsenceUnnamed, err
	}
	return a, subscription.StateAbsenceUnnamed, nil
}

// journalTimeLayouts — формы отметки времени, которые разбор принимает.
//
// Первая — то, что кладёт триггер (пинним UTC явным `to_char`). Вторая —
// умолчание `to_jsonb` для `timestamptz`, оставленное ради строк, записанных ДО
// этой миграции у владельца, который перейдёт на общую форму позже: разбор
// обязан их прочитать, а не объявить сбоем. Третьей формы нет намеренно —
// перечень принимаемых форм есть контракт, и «на всякий случай» его не расширяют.
var journalTimeLayouts = []string{time.RFC3339Nano, "2006-01-02T15:04:05.999999-07:00"}

func parseJournalTime(s string) (time.Time, error) {
	if s == "" {
		return time.Time{}, fmt.Errorf("пуста — отметка создания есть поле контракта, и пустой она не бывает")
	}
	var lastErr error
	for _, layout := range journalTimeLayouts {
		t, err := time.Parse(layout, s)
		if err == nil {
			return t.UTC(), nil
		}
		lastErr = err
	}
	return time.Time{}, fmt.Errorf("%q не разобралась ни одной объявленной формой: %w", s, lastErr)
}

// endpointFor повторяет производство output-only адреса реестра.
//
// Оно повторено, а не позвано, по той же причине, что и отображение выше:
// подлинник — метод use-case. Согласие держит интеграционная проба, сверяющая
// событие с тем, что отдаёт сервис.
func endpointFor(base, id string) string {
	if id == "" {
		return ""
	}
	return base + "/" + id
}

// registryStatusFromColumn — состояние жизненного цикла из колонки в контракт.
//
// Колонка хранит короткое слово (`ACTIVE`/`DELETING`), а перечисление контракта
// пишет его с префиксом (`REGISTRY_STATUS_ACTIVE`), поэтому вывод по имени из
// сгенерённого словаря здесь НЕ работает — и это стоит сказать, иначе следующий
// «упростит» разбор до `RegistryStatus_value[...]` и получит нулевое значение на
// каждом событии, молча. Перевод берётся у ПРОИЗВОДИТЕЛЯ доменного словаря.
func registryStatusFromColumn(s string) registryv1.RegistryStatus {
	return registryv1.RegistryStatus(domain.RegistryStatusFromString(s))
}
