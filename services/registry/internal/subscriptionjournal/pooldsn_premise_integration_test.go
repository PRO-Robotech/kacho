package subscriptionjournal_test

import (
	"context"
	"strings"
	"testing"

	"github.com/jackc/pgx/v5"

	"github.com/PRO-Robotech/kacho/pkg/pgtest"
)

// TestAPoolParameterIsFatalForASingleConnection — ПРЕДПОСЫЛКА стража подъёма,
// проверенная подключением, а не прочитанная в чужом комментарии.
//
// # Что здесь утверждается и зачем
//
// Композиционный корень отказывает в подъёме потока, если строка подключения
// несёт пуловый параметр. Обоснование стража — «вне пула это неизвестный
// PG-параметр и FATAL при подключении», и оно взято из комментария соседнего
// метода конфигурации. Утверждение о ЧУЖОМ механизме, взятое из его назначения,
// а не из его поведения, — это допущение, звучащее как знание.
//
// Проверяется оно одним вызовом: подать такую строку одиночному соединению и
// посмотреть исход. Если бы драйвер параметр молча игнорировал, у стража не было
// бы предмета — и он был бы проверкой без содержания, которую следующий читатель
// справедливо снял бы.
//
// Обе стороны: та же строка БЕЗ пулового параметра обязана подключиться. Без
// этого контроля проба зеленела бы и на строке, негодной по любой другой причине.
func TestAPoolParameterIsFatalForASingleConnection(t *testing.T) {
	if testing.Short() {
		t.Skip("интеграционная проба: нужна настоящая база")
	}
	dsn := pgtest.NewDB(t)
	ctx := context.Background()

	// Положительный контроль: строка сама по себе годна.
	clean, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatalf("одиночное соединение НЕ поднялось на исправной строке (%v): "+
			"отрицание ниже зеленело бы на любой негодной строке", err)
	}
	_ = clean.Close(ctx)

	sep := "?"
	if strings.Contains(dsn, "?") {
		sep = "&"
	}
	polluted := dsn + sep + "pool_max_conns=8"

	conn, err := pgx.Connect(ctx, polluted)
	if err == nil {
		_ = conn.Close(ctx)
		t.Fatal("одиночное соединение ПРИНЯЛО пуловый параметр: у стража подъёма нет предмета, " +
			"и он есть проверка без содержания — обоснование стража надо переписать по факту, " +
			"а не оставлять как есть")
	}
	t.Logf("предпосылка стража подтверждена подключением: %v", err)
}
