-- +goose Up
-- РЕСУРСНЫЙ ЖУРНАЛ реестра — отдельная таблица, не очередь прав.
--
-- Задача `PRO-Robotech/kacho#1415` (провязка общего сервера потока изменений,
-- `pkg/subscription`).
--
-- =============================================================================
-- ПОЧЕМУ НОВАЯ ТАБЛИЦА, А НЕ `registry_outbox`
-- =============================================================================
-- `registry_outbox` (миграция 0001) — очередь НАМЕРЕНИЙ РЕГИСТРАЦИИ ПРАВ, а не
-- журнал состояния ресурса, и её собственный код зовёт её очередью регистраций.
-- Три вещи делают её непригодной, и ни одна из них не про удобство:
--
--   · её словарь родов события ЗАКРЫТ ограничением базы на двух словах
--     (`fga.register`, `fga.unregister`); слово ресурсного журнала туда не
--     вставится вовсе;
--   · её нагрузка — набор кортежей прав, а не состояние предмета;
--   · её дренаж читает ПО ГОЛОВЕ ПАРТИЦИИ (миграции 0008-0011): чужая строка,
--     подмешанная в партицию, блокировала бы выдачу прав до конца окна повторов.
--
-- Смешать их значило бы обесценить пять миграций тонкой настройки плана клейма и
-- сделать выдачу прав заложником потока подписки. Поэтому — своя таблица, свой
-- канал, свой закрытый словарь. Разделённость держится не соглашением, а
-- ограничениями обеих таблиц: слово одной не проходит CHECK другой.
--
-- =============================================================================
-- ЧТО ЛОЖИТСЯ В ЖУРНАЛ, А ЧТО НЕТ — И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА
-- =============================================================================
-- Строку в базе реестра имеет ТОЛЬКО реестр. Репозиторий и тег — проекции zot:
-- у репозитория в базе лежат два вспомогательных следа (наложение конфигурации и
-- признак существования), у тега нет ничего. Самый частый путь появления тега —
-- потоковый проброс манифеста в zot, где обращения к базе НЕТ ВОВСЕ: пристегнуть
-- эмиссию не к чему.
--
-- Значит журнал несёт ОДИН вид — реестр. Объявить больше было бы хуже, чем не
-- объявить: вид, о видимости строки которого нельзя спросить модель прав, не
-- доставляется, и поток по нему молчал бы, оставаясь «зелёным».
--
-- =============================================================================
-- ПОЧЕМУ ТРИГГЕР, А НЕ ВЫЗОВ В КАЖДОМ МЕСТЕ ЗАПИСИ
-- =============================================================================
-- У репозитория реестра ЧЕТЫРЕ пути мутации, и один из них — `MarkDeleting` —
-- идёт БЕЗ транзакции (`pool.QueryRow`). А это единственный переход состояния
-- реестра ACTIVE→DELETING, и он наблюдаем арендатором. Понятия транзакционного
-- порта у реестра нет вовсе (`.Writer(ctx)` — ноль вхождений в его дереве против
-- 124 у vpc), поэтому «просто позвать эмиттер в той же транзакции» здесь не
-- выражается: транзакции нет.
--
-- Триггер снимает вопрос ПО ПОСТРОЕНИЮ: он всегда исполняется в транзакции
-- своего оператора, какой бы она ни была, — включая неявную транзакцию
-- одиночного UPDATE. Якорь проекта он берёт из самой строки, поэтому у СНЯТИЯ
-- якорь есть (`OLD.project_id`), а не выводится из нагрузки, которой у снятия
-- нет. Прецедент в дереве: vpc эмитит правку подсети триггером
-- (`subnets_outbox_emit_route_table_change`, миграция 0001 vpc).
--
-- ЦЕНА РЕШЕНИЯ, НАЗВАННАЯ ВСЛУХ. Ключи нагрузки — ИМЕНА КОЛОНОК (`to_jsonb(NEW)`),
-- а не имена полей Go. Это лучше (имя колонки не меняется молчаливым рефактором
-- Go, а `buf breaking` имён полей Go не видит by construction), но означает СВОЙ
-- разбор нагрузки на стороне читателя. Разбор закреплён интеграционной пробой,
-- которая пишет строку НАСТОЯЩИМ репозиторием и требует, чтобы событие дало то
-- же, что даёт штатное отображение реестра в контракт.
--
-- Вторая цена: `to_jsonb(NEW)` подхватывает КАЖДУЮ колонку таблицы, включая
-- добавленную позже. Для `registries` это верно и сегодня, и вперёд — там лежат
-- только tenant-facing метаданные пространства имён (ни секретов, ни координат
-- инфраструктуры). Заведётся в этой таблице колонка, которой арендатору видеть
-- не положено, — нагрузку придётся сузить перечислением ЗДЕСЬ, и это надо помнить
-- при всяком `ALTER TABLE registries ADD COLUMN`.

CREATE TABLE kacho_registry.registry_resource_journal (
  -- Номер выдаёт счётчик на ВСТАВКЕ, а строка становится видимой на ФИКСАЦИИ:
  -- порядок номеров и порядок фиксаций независимы. Читатель обязан держать
  -- границу устоявшегося — этим занимается общий сервер потока, не журнал.
  sequence_no   BIGSERIAL    PRIMARY KEY,
  -- Вид предмета СЛОВОМ ЖУРНАЛА. Наружу оно не выходит: клиенту едет тип объекта
  -- модели прав, и перевод живёт в объявлении владельца
  -- (`internal/subscriptionjournal`).
  resource_kind TEXT         NOT NULL,
  resource_id   TEXT         NOT NULL,
  -- Якорь проекта КОЛОНКОЙ. Ось отбирается ЗАПРОСОМ по частичному индексу ниже,
  -- а не после чтения строки: прочитано будет ровно то, что отдано. Умолчание
  -- пустой строкой, а не NULL, — та же форма, что у соседних журналов дерева.
  project_id    TEXT         NOT NULL DEFAULT '',
  event_type    TEXT         NOT NULL,
  payload       JSONB        NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  -- Словарь родов изменения ЗАКРЫТ. Слово вне словаря делает строку
  -- недоставляемой, и потеря эта тихая — поэтому она отсекается вставкой, а не
  -- обнаруживается подписчиком. Он же — разделитель с очередью прав: её слова
  -- (`fga.register`/`fga.unregister`) сюда не проходят, а эти три не проходят к
  -- ней.
  CONSTRAINT registry_resource_journal_event_type_check
    CHECK (event_type = ANY (ARRAY['CREATED'::text, 'UPDATED'::text, 'DELETED'::text])),
  CONSTRAINT registry_resource_journal_payload_object_ck
    CHECK (jsonb_typeof(payload) = 'object'::text)
);

-- Частичный индекс, а не полный: строки без якоря по нему не отбираются никогда
-- (подписка с осью проекта их не спрашивает), и держать их в индексе значило бы
-- платить за то, что не читается. Пара «якорь, номер» — ровно порядок, которым
-- читает поток: отбор по проекту с продвижением по возрастанию номера.
--
-- ПОЧЕМУ БЕЗ ПАРАЛЛЕЛЬНОГО РЕЖИМА, хотя у соседа он есть. У compute индекс
-- добавлялся на ЖИВУЮ таблицу с идущей записью: обычная сборка взяла бы замок,
-- разделяемый с чтением и не разделяемый с записью, и всякая вставка в журнал —
-- то есть всякая мутация ресурса — ждала бы конца сборки. Здесь таблица
-- СОЗДАЁТСЯ этой же миграцией и до её конца писателей не имеет вовсе: блокировать
-- нечего и некого. Параллельный режим при этом не бесплатен — он требует
-- `NO TRANSACTION`, то есть отказа от атомарности всей миграции и обязанности
-- сделать каждый шаг повторимым. Платить эту цену за отсутствующий предмет
-- незачем, поэтому режим не переносится, а отвергается осознанно.
CREATE INDEX registry_resource_journal_project_idx
  ON kacho_registry.registry_resource_journal (project_id, sequence_no)
  WHERE project_id <> '';

-- +goose StatementBegin
-- Пробуждение подписки. Канал СВОЙ и назван отдельно от таблицы: имя таблицы
-- схемо-квалифицировано, а `pg_notify` квалифицированного имени не принимает.
-- Канал очереди прав (`kacho_registry_outbox`) здесь НЕ переиспользуется: он
-- будит дренаж прав, и тот на каждой мутации реестра ходил бы за пустой выборкой.
CREATE FUNCTION kacho_registry.registry_resource_journal_notify() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_notify('registry_resource_journal', NEW.sequence_no::text);
  RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER registry_resource_journal_notify_trg
  AFTER INSERT ON kacho_registry.registry_resource_journal
  FOR EACH ROW EXECUTE FUNCTION kacho_registry.registry_resource_journal_notify();

-- +goose StatementBegin
-- ЭМИССИЯ. Один обработчик на три операции: расписывать три почти одинаковых
-- функции значило бы завести три места, расходящихся молча.
--
-- ОТМЕТКА ВРЕМЕНИ ПРИБИТА К UTC. `to_jsonb` рендерит `timestamptz` по часовому
-- поясу СЕССИИ, то есть форма ключа зависела бы от настройки того, кто пишет.
-- Нагрузка — публичный контракт, и зависеть от настройки сессии писателя она не
-- вправе, поэтому ключ перекрывается явной формой RFC 3339 в UTC.
--
-- СНЯТИЕ несёт ОДИН идентификатор, а не снимок строки. Общая форма подписки
-- разрешает читать НЕПУСТУЮ нагрузку как ПОЛНОЕ состояние предмета; предмета
-- больше нет, поэтому состояния у снятия не бывает, и объявить его богаче
-- значило бы соврать. Подписчику довольно оболочки: вид, идентификатор, якорь
-- проекта и род изменения — этого хватает, чтобы убрать строку у себя.
CREATE FUNCTION kacho_registry.registries_journal_emit() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  v_event   text;
  v_row     record;
  v_payload jsonb;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_event := 'DELETED';
    v_row   := OLD;
  ELSIF TG_OP = 'UPDATE' THEN
    v_event := 'UPDATED';
    v_row   := NEW;
  ELSE
    v_event := 'CREATED';
    v_row   := NEW;
  END IF;

  IF v_event = 'DELETED' THEN
    v_payload := jsonb_build_object('id', v_row.id);
  ELSE
    v_payload := to_jsonb(v_row) || jsonb_build_object(
      'created_at',
      to_char(v_row.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'));
  END IF;

  INSERT INTO kacho_registry.registry_resource_journal
    (resource_kind, resource_id, project_id, event_type, payload)
  VALUES ('Registry', v_row.id, v_row.project_id, v_event, v_payload);

  RETURN NULL;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER registries_journal_emit_insert_trg
  AFTER INSERT ON kacho_registry.registries
  FOR EACH ROW EXECUTE FUNCTION kacho_registry.registries_journal_emit();

-- Правка эмитится, ТОЛЬКО когда строка действительно изменилась.
--
-- Сужение не косметическое: `MarkDeleting` идёт формой
-- `... WHERE id = $1 AND status IN ('ACTIVE','DELETING')`, то есть повтор и
-- восстановление после обрыва переписывают DELETING в DELETING. Без условия
-- каждый такой повтор рождал бы событие правки, в котором ничего не поменялось, —
-- подписчик перечитывал бы предмет впустую, а отличить это от настоящей правки
-- было бы нечем. Ни одной колонки, меняющейся «без изменения существа», у этой
-- таблицы нет: все десять — tenant-facing поля контракта, а отметка создания не
-- меняется никогда. Поэтому сужение по ВСЕЙ строке, а не по перечню колонок:
-- перечень пришлось бы править при каждом `ADD COLUMN`, и он бы отстал молча.
CREATE TRIGGER registries_journal_emit_update_trg
  AFTER UPDATE ON kacho_registry.registries
  FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*)
  EXECUTE FUNCTION kacho_registry.registries_journal_emit();

CREATE TRIGGER registries_journal_emit_delete_trg
  AFTER DELETE ON kacho_registry.registries
  FOR EACH ROW EXECUTE FUNCTION kacho_registry.registries_journal_emit();

-- +goose Down
-- Возврат в форму без ресурсного журнала.
--
-- ЧТО ТЕРЯЕТСЯ, И ЭТО НЕ ВОССТАНОВИТСЯ: журнал уходит вместе с таблицей, а с ним
-- и все позиции подписчиков. Повторное применение заведёт ПУСТОЙ журнал, и
-- всякий подписчик, возобновляющийся с сохранённой позиции, получит отказ
-- «позиция больше не возобновима» и обязан будет перечитать каталог целиком.
-- Восстанавливать историю не из чего: она производилась мутациями, которых
-- больше не будет.
DROP TRIGGER IF EXISTS registries_journal_emit_delete_trg ON kacho_registry.registries;
DROP TRIGGER IF EXISTS registries_journal_emit_update_trg ON kacho_registry.registries;
DROP TRIGGER IF EXISTS registries_journal_emit_insert_trg ON kacho_registry.registries;
DROP FUNCTION IF EXISTS kacho_registry.registries_journal_emit();
DROP TRIGGER IF EXISTS registry_resource_journal_notify_trg ON kacho_registry.registry_resource_journal;
DROP FUNCTION IF EXISTS kacho_registry.registry_resource_journal_notify();
DROP TABLE IF EXISTS kacho_registry.registry_resource_journal;
