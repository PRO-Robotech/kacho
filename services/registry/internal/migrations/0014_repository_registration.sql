-- +goose Up
-- registry_repository_registration — durable признак СУЩЕСТВОВАНИЯ репозитория как
-- РЕСУРСА, записываемый той же транзакцией, что и register-intent на него.
--
-- Зачем. Право писать в репозиторий выбиралось по предикату «в движке есть хотя бы
-- один тег» (zot-каталог). Тег — это СОДЕРЖИМОЕ, а не ресурс: репозиторий, заявленный
-- через control-plane и ещё пустой, этому предикату не отвечал, поэтому запись в него
-- гейтилась правом «создавать репозитории в реестре» вместо права «изменять ЭТОТ
-- репозиторий», а ветка создания попутно выписывала владельца на чужой объект. Тот же
-- предикат делал регистрацию на первом push безвозвратной: интент эмитился отдельной
-- транзакцией уже ПОСЛЕ отданного клиенту 2xx, и его потеря не имела повторной попытки —
-- следующий push видел теги, переключался на глагол изменения и упирался в отказ.
--
-- Что даёт эта таблица. Ресурс существует ⟺ есть строка наложения (repository_configs)
-- ИЛИ есть строка ЗДЕСЬ. Оба источника — durable и принадлежат сервису; содержимое
-- движка в предикате больше не участвует. Строка пишется и снимается ВНУТРИ той же
-- транзакции, что и эмиссия register/unregister-интента репозитория (emitFGAIntent),
-- поэтому «намерение эмитировано» и «ресурс существует» не могут разъехаться by
-- construction: откат транзакции убирает и то и другое.
--
-- Почему отдельная таблица, а не строка наложения. Наложение — заявленная владельцем
-- конфигурация (описание/метки/видимость), и его появление означает «репозиторий
-- заявлен через control-plane». Если бы push писал наложение, CreateRepository на уже
-- запушенный репозиторий начал бы отвечать «уже существует» и сломал бы задокументированный
-- путь принятия (adopt): сегодня он ДОБАВЛЯЕТ наложение поверх проекции. Отдельный ключ
-- оставляет adopt рабочим (INSERT наложения не конфликтует), а предикат существования
-- получает второе слагаемое.
--
-- Почему не «спросить очередь». Строки registry_outbox дренятся и подметаются, а последним
-- событием объекта может быть unregister — предикат существования ресурса тогда зависел бы
-- от жизненного цикла очереди, а не от самого ресурса.
--
-- Within-service инварианты — на DB-уровне (ban #10, data-integrity.md):
--   * уникальность (registry_id, repo)  → PRIMARY KEY (registry_id, repo);
--   * ссылка на реестр в той же БД      → FK registry_id → registries(id)
--     ON DELETE CASCADE (same-DB cascade, как у repository_configs — ban #4 это НЕ
--     cross-service cascade). Следствие, которое нужно знать: зарегистрировать
--     репозиторий под НЕСУЩЕСТВУЮЩИМ реестром теперь нельзя — 23503 → отказ, а не
--     «интент уехал к несуществующему родителю».
SET search_path TO kacho_registry, public;

CREATE TABLE registry_repository_registration (
  registry_id TEXT        NOT NULL REFERENCES registries(id) ON DELETE CASCADE,
  repo        TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (registry_id, repo)
);

