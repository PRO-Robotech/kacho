// Package notify — шлюз уведомлений платформы. Этот файл — ведомость
// поверхности: какие gRPC-сервисы обслуживает каждый корень процесса под
// `services/notify/cmd/` (З15, NTF1-G19).
//
// Перепись поверхности notify сверяет найденное в коде с ЭТОЙ ведомостью, а не
// с константой: корень, которого здесь нет, — находка «корень без записи», а
// обслуживаемый сервис вне строки своего корня — находка «сервис вне
// ведомости». Следующие под-фазы правят строку ведомости, а не логику
// переписи: NTF-3 добавляет корень с публичным глаголом, NTF-4 — форму
// «только внутренний» (Д17, Д20).
//
// Корень `cmd/notify-probe` из переписи исключён приёмкой (NTF1-G19): это
// фикстурный источник стенда, а не шлюз.
package notify

// ServeSurfaceLedger — ведомость «корень процесса → множество обслуживаемых им
// gRPC-сервисов (полные имена)». Пустое множество — у корня нет ни одного
// gRPC-сервиса: процесс поднимает только диагностическую поверхность.
var ServeSurfaceLedger = map[string][]string{
	// cmd/notify — шлюз NTF-1: форма хоста no-grpc, входящего глагола нет.
	"cmd/notify": {},
	// cmd/migrator — процесс наката цепочек миграций notify (одноразовый,
	// задание развёртывания): ни слушателя, ни gRPC-сервиса у него нет.
	"cmd/migrator": {},
}
