# audit-list-filter.sh — CI gate для public List<Resource>: per-object видимость
# (RBAC v2, парити с vpc/compute/nlb) + project-scoped listauthz-posture (INV-10).
#
# Это ТОНКАЯ обёртка: что именно проверяется, почему проверок три и почему форма
# «перечисли всё разрешённое → сузь SQL» отвергается — на пакете
# tools/auditlistfilter (godoc). Здесь только запуск.
#
# Почему анализ живёт в Go, а не в этом файле. Прежняя редакция гейта была grep'ом
# и опознавала ресурс по ЛИТЕРАЛЬНОМУ ТЕКСТУ `func (r *…Repo) List(` — то есть по
# ИМЕНИ ПЕРЕМЕННОЙ-приёмника. Переименование `r` → `repo` (рефактор, который ни один
# ревьюер не остановит) убирало ресурс из поля зрения гейта целиком: что бы ни делал
# его use-case, это больше не судили, а гейт печатал OK. Плюс на дереве без адаптеров
# он тоже печатал OK — «ноль находок» было неотличимо от «ноль прочитанного».
# Разбор AST опознаёт объявление по СУЩЕСТВУ (метод `List` на приёмнике ТИПА
# `<X>Repo`), не видит комментариев как кода by construction и умеет отчитаться об
# ОБЪЁМЕ осмотренного.
#
# Аргументы прокидываются как есть:
#   --allow=<resource>  исключить ресурс (cluster-каталог); запись, которой больше
#                       нечего исключать, — сама находка.
#   --root=<dir>        аудировать другое дерево (используют тесты гейта).

set -euo pipefail
cd "$(dirname "$0")/.."

exec go run ./tools/auditlistfilter/cmd/audit-list-filter "$@"
