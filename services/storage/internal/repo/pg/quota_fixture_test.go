// Фикстура учёта для проб, чей предмет — НЕ учёт.
//
// Приёмка `docs/specs/sub-phase-quota-v2-materialised-usage-acceptance.md`
// (APPROVED, раунд 2), DoD S4 п.1.
//
// # Зачем это существует
//
// С появлением учёта вставка строки ресурса СПИСЫВАЕТ место, а списать его не с
// чего, пока у проекта нет строки учёта: «не сказано» — отказ, а не «без
// предела» (V2-3). На живом пути строку заводит материализация ПЕРЕД вставкой;
// проба этого пакета идёт мимо use-case'а, прямо в репозиторий, и потому обязана
// привести базу в то же состояние, в каком её видит репозиторий на живом пути.
// Замер на этом дереве: без фикстуры краснели 93 пробы пакета из 141 — все одним
// и тем же «потолок не назван», ни одна из них к квотам отношения не имеет.
//
// # Почему это НЕ послабление
//
// Фикстура заводит строку учёта ТЕМ ЖЕ оператором, что и продукт
// (`pg.MaterializeQuotas` — единственный, и `QuotaRepo.Materialize` зовёт его
// же), — она не подставная реализация, а вызов настоящей. Механизм при этом
// продолжает работать на каждой вставке: триггер списывает, удаление возвращает,
// отказ на исчерпании возможен. Меняется ровно одно — величина у этих проектов
// заведомо больше, чем им нужно, потому что предмет этих проб лежит в другом
// месте. Величину назначает администратор, и «большой предел у служебного
// проекта» — состояние, которое продукт производит штатно.
//
// # Почему перечень, а не «всем подряд»
//
// Умолчание «любой проект получает место» сделало бы невыразимым состояние
// «потолка нет» — то самое, которое проверяют пробы учёта рядом
// (`quota_integration_test.go`). Они держат СВОИ идентичности (`prj-quota-*`), в
// этот перечень не входят и заводят строки сами.
//
// # Что произойдёт с пробой, заведённой позже
//
// Новая проба с неназванной здесь идентичностью получит отказ
// `resource count quota not provisioned: project <id> has no ceiling stated for
// <вид>` — громкий, называющий предмет и указывающий, что делать: либо добавить
// идентичность сюда, либо (если предмет пробы — сам учёт) завести строку самой.
// Перечень поэтому не дрейфует молча: расхождение с деревом наблюдаемо в тот же
// прогон.

// fixtureQuotaLimit — предел служебных проектов проб.
//
// Заведомо больше, чем нужно любой пробе пакета: предел здесь не предмет
// утверждения, а условие, при котором предмет вообще достижим. Проба, которой
// нужен ИСЧЕРПАННЫЙ предел, заводит свой проект и свою величину.
const fixtureQuotaLimit = 1_000_000

// fixtureQuotaKinds — три тенантных вида домена, ровно те, на которых висят
// триггеры учёта (миграция 0023).
//
// Выписаны, а не выведены из каталога: у владельца типа копии каталога нет by
// construction — перечень приезжает ответом владельца величин. Здесь соседа нет,
// поэтому фикстура называет виды прямо. Разойдясь с набором триггеров, перечень
// проявит себя тем же громким отказом, что и незаведённая идентичность.
var fixtureQuotaKinds = []string{
	"storage.volumes",
	"storage.snapshots",
	"storage.images",
}

// fixtureProjects — идентичности проектов, которыми пользуются пробы пакета.
//
// Пробы учёта (`prj-quota-*`) здесь отсутствуют НАМЕРЕННО: их предмет —
// поведение при заведённой и при отсутствующей строке, и заведи им строку
// фикстура, они бы утверждали про состояние, которого не создавали.
var fixtureProjects = []string{
	"prj-1", "prj-2", "prj-attacker", "prj-attacker-zone",
	// `prj-cursor-N` — восемь идентичностей пробы курсорного индекса
	// (`cursorProbeProjects`), которые она порождает форматом, а не литералами.
	// Перечислены полностью: диапазон, взятый «с запасом», молча пережил бы
	// сокращение пробы и стал бы записью, которой нечего исключать.
	"prj-cursor-0", "prj-cursor-1", "prj-cursor-2", "prj-cursor-3",
	"prj-cursor-4", "prj-cursor-5", "prj-cursor-6", "prj-cursor-7",
	"prj-fk", "prj-list-dup", "prj-observed", "prj-other",
	"prj-relabel-c", "prj-relabel-i", "prj-relabel-ic", "prj-relabel-n",
	"prj-relabel-s", "prj-relabel-sc", "prj-relabel-v",
	"prj-victim", "prj-victim-zone", "project",
}

// seedFixtureQuotas приводит свежую базу пробы в состояние «проекты
// материализованы».
//
// Идёт через `pg.MaterializeQuotas` — тот же и единственный оператор, которым
// пользуется живой путь. Своего INSERT здесь нет намеренно: копия оператора
// разошлась бы с настоящим молча, и разошлась бы именно там, где расхождение не
// видно, — на составе столбцов.
func seedFixtureQuotas(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()
	ctx := context.Background()

	rows := make([]quota.Row, 0, len(fixtureProjects)*len(fixtureQuotaKinds))
	for _, p := range fixtureProjects {
		for _, k := range fixtureQuotaKinds {
			rows = append(rows, quota.Row{
				CarrierType:   quota.CarrierProject,
				CarrierID:     p,
				Kind:          k,
				Limit:         fixtureQuotaLimit,
				SourceScope:   "DEFAULT",
				SourceScopeID: "",
				LimitRevision: 0,
				// Зеркало аккаунта непусто: схема отвергает пустое, и отвергает
				// правильно — строка без зеркала невидима аккаунтной дельте.
				AccountID: "acc-fixture",
			})
		}
	}

	n, err := pg.MaterializeQuotas(ctx, pool, rows)
	require.NoError(t, err, "фикстура учёта: заведение строк")
	require.Equal(t, int64(len(rows)), n,
		"перепись: заведено строк — столько же, сколько объявлено. Расхождение означает, "+
			"что часть идентичностей уже существовала, то есть фикстура работает не на свежей базе")
}

// quotaRowsFor собирает набор строк учёта по всем трём видам домена — так, как
// его собрала бы материализация из ответа владельца величин.
//
// Отдельный помощник, а не литерал в каждой пробе: набор видов домена один, и
// три пробы, выписавшие его порознь, разошлись бы на четвёртом виде — молча и
// каждая по-своему.
func quotaRowsFor(project string, limit int64) []quota.Row {
	rows := make([]quota.Row, 0, len(fixtureQuotaKinds))
	for _, k := range fixtureQuotaKinds {
		rows = append(rows, quota.Row{
			CarrierType:   quota.CarrierProject,
			CarrierID:     project,
			Kind:          k,
			Limit:         limit,
			SourceScope:   "DEFAULT",
			LimitRevision: 0,
			AccountID:     "acc-fixture",
		})
	}
	return rows
}
