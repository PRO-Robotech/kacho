package pg

import "github.com/PRO-Robotech/kacho/pkg/filter"

// nameFilterCond — предикат сужения по имени для списка, с СОХРАНЁННЫМ
// оператором (#460).
//
// Колонка уточнена псевдонимом таблицы (`v.name`, `i.name`, `s.name`), поэтому
// `ToSQL` здесь не подходит — он строит предикат по имени ПОЛЯ, а поле зовётся
// `name`. Именно из-за этого расхождения три владельца забирали из узла одно
// значение и теряли оператор: подстрочный запрос молча отвечал точным
// равенством, и поиск по части имени возвращал «ничего не найдено».
//
// ast == nil — сужения нет.
//
// Общим сделан ТОЛЬКО предикат имени. Сужение по project_id намеренно осталось в
// теле каждого List: гейт `audit-list-filter` читает тело метода и обязан
// увидеть его там — вынесенное за помощник, оно становится ему невидимо, и
// проверка, стерегущая межарендную видимость, замолчала бы, оставшись зелёной.
// Собственная читаемость дороже не бывает.
func nameFilterCond(alias string, ast *filter.FilterAST, nextArg int) (string, []any) {
	if ast == nil {
		return "", nil
	}
	return ast.ToSQLOn(alias+".name", nextArg)
}
