package pg

import (
	"context"
	"fmt"
	"sort"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ExistenceProbe — read-only сверка «есть ли такой объект в МОЕЙ базе» по его
// объекту модели прав.
//
// Спрашивается ТОЛЬКО на пути отказа. Владелец модели отвечает одинаково и на
// несуществующий объект, и на существующий чужой, поэтому различить «объекта
// нет» и «объект есть, но не твой» может лишь тот, у кого строка лежит в базе.
// Без сверки отказ на СВОЙ несуществующий том приходил бы формой сокрытия от
// звена решения, а не собственным промахом обработчика; с ней отсутствующий
// объект пропускается к обработчику, а существующий чужой отвечает голосом
// владельца — байт в байт тем же текстом, что и настоящий промах.
//
// Лёгкий `SELECT EXISTS` без чтения строки: вопрос задаётся на каждом отказе.
type ExistenceProbe struct {
	pool *pgxpool.Pool
}

// NewExistenceProbe собирает пробу поверх пула композиционного корня, и пул
// обязан быть МАСТЕРОМ.
//
// Реплика здесь была бы дефектом, а не оптимизацией. Проба отвечает на вопрос
// «объекта не существует?», и ответ «да» превращает отказ в правах в промах
// обработчика. На реплике только что созданный том какое-то время не виден,
// поэтому владелец, обратившийся к своему свежему ресурсу, получил бы «не
// существует» — тот же ответ, что и посторонний, которому том недоступен. То
// есть отсутствие и недоступность перестали бы различаться именно в момент,
// когда объект уже создан. Задержка репликации сверху не ограничена и отсюда не
// наблюдаема, поэтому «обычно свежая реплика» защитой не является.
func NewExistenceProbe(pool *pgxpool.Pool) *ExistenceProbe {
	return &ExistenceProbe{pool: pool}
}

// objectTypeTable — whitelist «тип объекта модели прав → таблица схемы
// kacho_storage». Имя таблицы берётся ТОЛЬКО из этой константной карты, никогда
// из запроса, — подстановка невозможна by construction.
//
// Три типа ровно потому, что ровно эти три скрывает рантайм: чтение объекта
// глаголом `v_get` у типа, за который есть чем говорить (`pkg/authz`, таблица
// промахов владельцев). Тип диска (`DiskType`) сюда не входит — он глобальный
// справочник, скрывать у него нечего.
var objectTypeTable = map[string]string{
	"storage_volume":   "volumes",
	"storage_snapshot": "snapshots",
	"storage_image":    "images",
}

// ObjectExists отвечает, есть ли строка с таким идентификатором в таблице,
// соответствующей типу объекта.
//
// Неизвестный тип — ОШИБКА, а не «нет»: вызывающий трактует ошибку как «не могу
// подтвердить отсутствие» и оставляет отказ отказом (fail-closed), тогда как
// молчаливое «нет» пропустило бы вызов к обработчику — то есть неизвестный тип
// открывал бы дверь, вместо того чтобы её запирать.
func (p *ExistenceProbe) ObjectExists(ctx context.Context, objectType, objectID string) (bool, error) {
	if p == nil || p.pool == nil {
		return false, fmt.Errorf("existence probe: pool is not wired")
	}
	table, ok := objectTypeTable[objectType]
	if !ok {
		return false, fmt.Errorf("existence probe: unprobeable object type %q", objectType)
	}
	var exists bool
	// table — из константного whitelist выше; objectID — связанный параметр.
	if err := p.pool.QueryRow(ctx,
		"SELECT EXISTS(SELECT 1 FROM kacho_storage."+table+" WHERE id = $1)", objectID,
	).Scan(&exists); err != nil {
		return false, err
	}
	return exists, nil
}

// ProbeableTypes — типы, о которых проба умеет ответить.
//
// Перечень обязан покрывать ВСЕ пообъектные типы карты прав сервиса; сверяет
// это носитель на старте (`servicehost`, О5в) сравнением с
// `catalogderive.ObjectScopedTypes` — обе стороны выведены, ни одна не
// выписана в месте сравнения. Тип, попавший в карту и не попавший сюда,
// отвечает на отказе ошибкой пробы, а она fail-closed: `403` там, где соседний
// тип того же сервиса отвечает `404` (задача продукта #1931).
//
// Возвращается свежий срез: носитель читает перечень и не вправе зависеть от
// того, что за ним стоит карта пакета.
func (p *ExistenceProbe) ProbeableTypes() []string {
	out := make([]string, 0, len(objectTypeTable))
	for ot := range objectTypeTable {
		out = append(out, ot)
	}
	sort.Strings(out)
	return out
}
