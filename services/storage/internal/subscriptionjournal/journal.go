// Package subscriptionjournal — объявление ЖУРНАЛА storage для общего сервера
// потока изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы, сужение
// по правам и порядок отказов принадлежат общему серверу и владельцу не выдаются.
//
// # ПОЧЕМУ СТРОКУ ЖУРНАЛА ПИШЕТ ТРИГГЕР БАЗЫ, А НЕ ВЫЗОВ В КАЖДОМ МЕСТЕ ЗАПИСИ
//
// У соседних владельцев журнал эмитирует репозиторий. У storage писателей
// ресурсных строк БОЛЬШЕ, чем репозиториев, и часть их не имеет транзакции вовсе:
//
//   - сверщик (`internal/reconciler/store.go`) мутирует `volumes`/`snapshots`/
//     `images` МИМО репозиториев, на голом пуле. Именно его `Confirm`
//     (`CREATING → READY`) — тот переход, ради которого консоль и опрашивает
//     списки; журнал, эмитирующий только из репозиториев, о нём не узнал бы;
//   - его же `Forget` снимает строку без `RETURNING project_id` — при
//     вызове-эмиссии якорь снятию взять неоткуда, а без якоря снятие не
//     проходит ось проекта и потребитель держит удалённый том вечно.
//
// Триггер закрывает это ПО ПОСТРОЕНИЮ: он в той же транзакции, что и мутация,
// всегда; якорь берёт из самой строки; и следующий писатель попадает в журнал,
// не зная о нём. Прецедент в дереве есть — журнал vpc пишет в том числе триггер.
//
// # ЧТО ОТДАЁТСЯ СОСТОЯНИЕМ — ВСЕ ТРИ ВИДА, у каждого со своим производителем
//
// Общая форма разрешает подписчику читать НЕПУСТУЮ нагрузку как ПОЛНОЕ состояние
// предмета. Поэтому состояние отдаётся там и только там, где оно ПОЛНОЕ и остаётся
// полным впредь. У всех трёх видов оба условия сегодня выполнены; у снятия
// состояния нет ни у кого — предмета больше не существует, собирать нечего.
//
// **ТОМ.** Публичная проекция выводится через две таблицы: `Volume.status` — из
// `volumes.state` и существования привязки (`domain.DeriveStatus`), `attachments`
// и `used_by` — из `volume_attachments`. Свежесть по построению: у обоих
// перекрёстных входов есть свой триггер эмиссии.
//
// **СНИМОК И ОБРАЗ.** Их `used_by` — перечень ТОМОВ, засеянных этим источником
// (`volumes.source_snapshot_id` / `source_image_id`). Входы нашлись бы и раньше;
// не было ПРОИЗВОДИТЕЛЯ их событий — мутация тома источнику не эмитировала ничего,
// и состояние устаревало бы МОЛЧА. Производитель заведён миграцией
// `20260830120000_storage_journal_source_state.sql`: триггер по строке тома
// объявляет правкой ИСТОЧНИКА появление и снятие сеянного тома.
//
// Цена перемерена и оказалась ниже, чем предполагалось: ссылка на источник
// ИММУТАБЕЛЬНА, поэтому перечень меняют ровно два перехода строки тома — её
// появление и снятие. Правка меток, изменение размера, привязка, отвязка и все
// подтверждения сверщика источнику не эмитируют НИЧЕГО, и это утверждается пробой
// (`TestVolumeUpdateDoesNotWakeItsSourceSubscribers`), а не намерением.
//
// **Ни один из трёх не есть вторая реализация публичной проекции.** Триггер не
// вычисляет НИ ОДНОГО производного поля: он кладёт в конверт те же ВХОДЫ, что
// подаёт запрос чтения своим соединением либо коррелированным подзапросом, и тем
// же порядком. Проекция остаётся в единственном `internal/protoconv`, деривация —
// в единственных `domain.DeriveStatus` / `domain.*StatusFromState`; на SQL переехал
// лишь способ ДОБЫТЬ входы, и он тот же, что у чтения.
//
// # ЗДЕСЬ ДВАЖДЫ СТОЯЛО «СОСТОЯНИЕ НЕ ОТДАЁТСЯ» — и оба раза предикат сработал
//
// Первая редакция отказывала ВСЕМ трём видам, называя условие возврата дословно:
// состояние вводится тогда и только тогда, когда публичную проекцию можно получить,
// НЕ переписывая её. Условие выполнилось у тома — решение сменилось вместе с ним.
//
// Вторая отказывала снимку и образу по ДРУГОЙ причине — отсутствию производителя
// событий — и тоже называла условие: сперва завести производителя. Условие
// выполнено здесь.
//
// Абзац оставлен как разбор, а не удалён: предикат снятия, названный вслух, и есть
// то, чем такое решение отличается от бессрочного. Оба раза он и снял решение — не
// чья-то память о том, что «когда-нибудь надо бы».
//
// # РАССМОТРЕН И ОТВЕРГНУТ второй путь для снимка и образа
//
// Объявить `used_by` полем, которого поток НЕ несёт, было дешевле. Путь неисполним,
// и запрещает его не storage: платформенный контракт подписки объявляет носитель
// нагрузки ВЫБОРОМ ИЗ ДВУХ ВЕТВЕЙ на СОБЫТИЕ целиком и прямо уполномочивает
// подписчика читать непустую нагрузку как ПОЛНОЕ состояние. Признака «поле не
// приехало» в этой форме нет — значит состояние с вырезанным `used_by` неотличимо
// от состояния источника без детей, и подписчик записал бы «детей нет» как факт.
// Разбор целиком — в заголовке той же миграции.
//
// # ЧТО НЕСЁТ НАГРУЗКА, РАЗ ЕЁ НЕ ЧИТАЮТ
//
// Тенантские колонки строки, БЕЗ инфра-полей (привязка к бэкенду, имя объекта,
// пространство имён, наблюдение). Отбор — не украшение: журнал кормит ручку,
// доступную арендатору, а размещение и адрес у бэкенда живут только на внутреннем
// слушателе (`security.md` §«Инфра-чувствительные данные»). Тот же отбор решает и
// второй вопрос — какая правка СЧИТАЕТСЯ изменением: см. заголовок миграции.
