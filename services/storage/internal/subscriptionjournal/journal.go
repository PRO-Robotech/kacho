// Package subscriptionjournal — объявление ЖУРНАЛА storage для общего сервера
// потока изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы, сужение
// по правам и порядок отказов принадлежат общему серверу и владельцу не выдаются.
//
// # ПОЧЕМУ СТРОКУ ЖУРНАЛА ПИШЕТ ТРИГГЕР БАЗЫ, А НЕ ВЫЗОВ В КАЖДОМ МЕСТЕ ЗАПИСИ
//
// У соседних владельцев журнал эмитирует репозиторий. У storage писателей
// ресурсных строк БОЛЬШЕ, чем репозиториев, и часть их не имеет транзакции вовсе:
//
//   - сверщик (`internal/reconciler/store.go`) мутирует `volumes`/`snapshots`/
//     `images` МИМО репозиториев, на голом пуле. Именно его `Confirm`
//     (`CREATING → READY`) — тот переход, ради которого консоль и опрашивает
//     списки; журнал, эмитирующий только из репозиториев, о нём не узнал бы;
//   - его же `Forget` снимает строку без `RETURNING project_id` — при
//     вызове-эмиссии якорь снятию взять неоткуда, а без якоря снятие не
//     проходит ось проекта и потребитель держит удалённый том вечно.
//
// Триггер закрывает это ПО ПОСТРОЕНИЮ: он в той же транзакции, что и мутация,
// всегда; якорь берёт из самой строки; и следующий писатель попадает в журнал,
// не зная о нём. Прецедент в дереве есть — журнал vpc пишет в том числе триггер.
//
// # ПОЧЕМУ СОСТОЯНИЕ ПРЕДМЕТА НЕ ОТДАЁТСЯ — измерено, а не выбрано
//
// Общая форма разрешает подписчику читать НЕПУСТУЮ нагрузку как ПОЛНОЕ состояние
// предмета, и это единственный случай, когда он вправе так делать. Публичная
// проекция всех трёх видов storage ПОЛНОЙ по строке своей таблицы не собирается:
//
//   - `Volume.status` ВЫВОДИТСЯ из двух таблиц: `domain.DeriveStatus(state,
//     attached)`, где `attached` — существование строки в `volume_attachments`.
//     Строка `volumes` несёт `state='READY'` и не отличает `AVAILABLE` от
//     `IN_USE`. Это не поле на краю — это ровно то поле, ради которого консоль
//     опрашивает;
//   - `Volume.attachments` и `Volume.used_by` выводятся из `volume_attachments`;
//   - `Snapshot.used_by` и `Image.used_by` — из `volumes`, засеянных этим
//     источником (`repo/pg/snapshot_repo.go`, `image_repo.go`; заполняются и на
//     `Get`, и на странице списка).
//
// Собрать это в триггере значило бы записать ВТОРУЮ реализацию публичной проекции
// на SQL — рядом с `internal/protoconv`, на другом языке, без общего кода. Она
// разошлась бы МОЛЧА: день, когда деривация в Go получает новую ветку, SQL
// продолжает отвечать прежним значением, и подписчик записывает его как факт.
// Отдать же неполное состояние нельзя тем более: том, привязанный к машине,
// уезжал бы как `AVAILABLE` без единой привязки.
//
// Поэтому события storage доезжают с признаком «состояния не будет», а состояние
// подписчик берёт чтением по идентификатору.
//
// **Ценность потока от этого не исчезает, и её стоит назвать точно.** Подписчик
// узнаёт вид, идентификатор, якорь проекта и род изменения — то есть ЧТО
// перечитать и когда. Именно это снимает постоянный опрос: чтение случается на
// изменении, а не по таймеру.
//
// **Предикат пересмотра назван, чтобы решение не пережило своё основание.**
// Состояние сюда вводится тогда и только тогда, когда публичную проекцию можно
// получить, НЕ переписывая её: например если нагрузку начнёт собирать тот же
// Go-код, что отвечает на чтение. Пока источник нагрузки — SQL, а деривация —
// Go, второй реализации не миновать.
//
// # ЧТО НЕСЁТ НАГРУЗКА, РАЗ ЕЁ НЕ ЧИТАЮТ
//
// Тенантские колонки строки, БЕЗ инфра-полей (привязка к бэкенду, имя объекта,
// пространство имён, наблюдение). Отбор — не украшение: журнал кормит ручку,
// доступную арендатору, а размещение и адрес у бэкенда живут только на внутреннем
// слушателе (`security.md` §«Инфра-чувствительные данные»). Тот же отбор решает и
// второй вопрос — какая правка СЧИТАЕТСЯ изменением: см. заголовок миграции.
package subscriptionjournal

import (
	"fmt"

	"google.golang.org/protobuf/types/known/anypb"

	subscriptionv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/subscription"
	"github.com/PRO-Robotech/kacho/pkg/authz"
	"github.com/PRO-Robotech/kacho/pkg/subscription"
	"github.com/PRO-Robotech/kacho/services/storage/internal/authzfilter"
)

const (
	// Table — таблица журнала, квалифицированная схемой: домен storage живёт в
	// собственной схеме, а не в `public`.
	Table = "kacho_storage.storage_outbox"

	// Channel — канал пробуждения.
	//
	// Он НЕ выводится из имени таблицы: таблица схемо-квалифицирована, а канал —
	// нет (`pg_notify('storage_outbox', …)`). Вывод одного из другого работал бы
	// у владельцев с таблицей в `public` и молча ошибался здесь.
	Channel = "storage_outbox"

	// JournalWordVolume — слово, которым ТРИГГЕР записывает вид строки в колонку
	// `resource_kind`.
	//
	// Имя названо словом ЖУРНАЛА, а не «видом», намеренно: клиенту этот предмет
	// едет как `storage_volume` — тип объекта модели прав, единственное написание
	// вида на всё дерево.
	JournalWordVolume = "Volume"
	// JournalWordSnapshot — то же для снимка.
	JournalWordSnapshot = "Snapshot"
	// JournalWordImage — то же для образа.
	JournalWordImage = "Image"

	// changeDeleted — слово владельца для снятия предмета.
	changeDeleted = "DELETED"
)

// Journal — объявление журнала storage.
func Journal() subscription.Journal {
	return subscription.Journal{
		Channel: Channel,
		Storage: subscription.Storage{
			Table:          Table,
			PositionColumn: "sequence_no",
			KindColumn:     "resource_kind",
			IDColumn:       "resource_id",
			ChangeColumn:   "event_type",
			PayloadColumn:  "payload",
			ProjectColumn:  "project_id",
			// Якорь проекта лежит КОЛОНКОЙ, и у storage он есть у всех трёх видов
			// прямо в строке ресурса (`volumes`/`snapshots` — 0003, `images` —
			// 0007). Триггер берёт его из `NEW.project_id`/`OLD.project_id`,
			// поэтому у СНЯТИЯ он есть так же, как у создания, — а именно снятие
			// без якоря стоит дороже всего: подписка с осью проекта его не
			// пропустит, и потребитель, снявший опрос, будет держать удалённый
			// том вечно, ни разу не увидев ни отказа, ни пропуска в нумерации.
			//
			// Второе следствие: ось отбирается ЗАПРОСОМ, по частичному индексу
			// `(project_id, sequence_no) WHERE project_id <> ''`.
			Project: subscription.ProjectInColumn,
			// Журнал НЕ чистится: снятия строк у него нет ни на одном пути.
			// Предикат — `git grep -in 'DELETE FROM kacho_storage.storage_outbox'`
			// по не-тестовому дереву даёт пусто. Значит отказ «позиция утрачена»
			// не наступает никогда, и служебное сообщение вправе сказать это
			// прямо. Заведётся чистка — эта величина обязана поменяться ВМЕСТЕ с
			// ней: обещание удержания живёт ровно столько, сколько его основание.
			Retention: subscription.RetainsEverything,
		},
		Mapping: subscription.Mapping{
			// Словарь видов ЗАКРЫТ в обе стороны: вид вне его отвергается на
			// открытии, а строка вне его не доставляется — вопрос о видимости
			// задать нечем.
			//
			// СЛЕВА — слово ХРАНИЛИЩА (что кладёт в колонку триггер), СПРАВА — то,
			// что едет клиенту. Клиенту едет ТИП ОБЪЕКТА, и берётся он у
			// ПРОИЗВОДИТЕЛЯ (`authzfilter`), а не выписывается: второе написание
			// чужого словаря расходится молча. Здесь оно разошлось бы заметно —
			// слово журнала `Volume` с заглавной и без домена не похоже ни на что
			// в дереве.
			//
			// Действие — то же, которым сужается СПИСОК того же предмета, поэтому
			// видимость в потоке равна видимости в списке.
			//
			// ТИПЫ ДИСКОВ, БЭКЕНДЫ ХРАНЕНИЯ И ПРИВЯЗКИ ТИПОВ сюда НЕ входят, и это
			// требование, а не пробел. У них нет проектного измерения: колонки
			// `project_id` в их таблицах не существует (`0003_storage_domain.sql`
			// для `disk_types`, `0015_storage_backends_and_bindings.sql` для
			// остальных двух), и типа объекта модели прав у них тоже нет. Значит
			// вопрос «вправе ли вызывающий это видеть» задать НЕЧЕМ, а строка без
			// ответа на него не доставляется — поток по такому виду молчал бы,
			// оставаясь зелёным. Это тот же разграничитель, каким vpc вывел из
			// подписки административные предметы уровня кластера.
			Kinds: map[string]subscription.Kind{
				JournalWordVolume: {
					ObjectType: authzfilter.ResourceTypeVolume,
					Action:     authzfilter.ActionVolumeList,
				},
				JournalWordSnapshot: {
					ObjectType: authzfilter.ResourceTypeSnapshot,
					Action:     authzfilter.ActionSnapshotList,
				},
				JournalWordImage: {
					ObjectType: authzfilter.ResourceTypeImage,
					Action:     authzfilter.ActionImageList,
				},
			},
			// Словарь родов изменения — ровно те слова, которые пишет триггер, и
			// ровно те, которые разрешает ограничение колонки. Обе стороны
			// сверяются с производителем разбором, а не вторым рукописным
			// перечнем (`producer_test.go`): слово вне словаря делает строку
			// НЕДОСТАВЛЯЕМОЙ, и потеря эта тихая.
			Changes: map[string]subscriptionv1.SubscriptionEvent_Change{
				"CREATED":     subscriptionv1.SubscriptionEvent_CREATED,
				"UPDATED":     subscriptionv1.SubscriptionEvent_UPDATED,
				changeDeleted: subscriptionv1.SubscriptionEvent_DELETED,
			},
			State: state,
		},
	}
}

// ProjectGate — страж оси `project_id`.
//
// Без него вызывающий, назвавший недоступный ему проект, получил бы ОТКРЫТЫЙ
// поток, молчащий вечно: ни одна строка не прошла бы построчного сужения, и это
// читалось бы как «изменений нет».
//
// Форма отказа берётся у ПРОИЗВОДИТЕЛЯ форм скрытия, а не сочиняется здесь: она
// обязана быть неотличима от настоящего промаха владельца проектов, иначе
// подписка становится способом узнать существование чужого проекта. Отсутствие
// формы у производителя — отказ сборки, а не молчаливое умолчание: страж без
// формы отвечал бы отличимым текстом, то есть ровно тем, что закрывает.
func ProjectGate() (subscription.ProjectGate, error) {
	const projectObjectType = "project"
	form, ok := authz.OwnerNotFoundFormat(projectObjectType)
	if !ok {
		return subscription.ProjectGate{}, fmt.Errorf(
			"subscriptionjournal: у типа %q нет формы отсутствия у производителя (pkg/authz): "+
				"страж оси project_id отвечал бы текстом, отличимым от промаха владельца, "+
				"то есть выдавал бы существование чужого проекта", projectObjectType)
	}
	return subscription.ProjectGate{
		ObjectType: projectObjectType,
		// Действие и отношение — те же, которыми владелец проектов гейтит своё
		// чтение (`iam.v1.ProjectService/Get` в каталоге прав): вопрос «вправе ли
		// он видеть этот проект» обязан быть ТЕМ ЖЕ вопросом, а не похожим.
		Action:         "iam.projects.get",
		Relations:      []string{"v_get"},
		NotFoundFormat: form,
	}, nil
}

// state — состояние предмета события; у журнала storage его НЕТ ни у одного рода.
//
// Отсутствие возвращается БЕЗ ошибки и с НАЗВАННОЙ причиной: это не сбой сборки, а
// свойство журнала.
// Ошибка здесь означала бы «состояние есть, но собрать не удалось» — и звала бы
// следующего читателя чинить несуществующую поломку. Ровно на этом различии
// стоит и решение спрашивать род изменения ЯВНО, а не выводить его из бедности
// нагрузки: вывод из бедности склеил бы отсутствие с настоящим сбоем разбора.
//
// Почему не собрать предмет из строки таблицы — разобрано в заголовке пакета
// одним предложением: публичная проекция всех трёх видов выводится ЧЕРЕЗ таблицы
// (`Volume.status` — из `volumes.state` и существования привязки; коллекции
// `attachments`/`used_by` — из `volume_attachments` и `volumes`), и собрать её в
// триггере значило бы завести вторую реализацию `protoconv` на SQL.
//
// Функция объявлена ПОСТРОЧНОЙ, а не выключенной на весь журнал, потому что
// решение принадлежит РОДУ ПРЕДМЕТА: станет один из трёх видов собираться без
// второй реализации — ветка появится здесь, у этого вида, и остальные её не
// унаследуют.
//
// # Почему причина — «НЕ ПРОИЗВОДИТСЯ», и почему это ВЕСЬ журнал, а не только снятие
//
// Владелец состояния для этих предметов не производит НИ ПРИ КАКОМ роде: публичная
// проекция всех трёх видов выводится ЧЕРЕЗ таблицы, и собрать её из строки журнала
// нечем — попытки нет, повтор её не создаст. Ровно это и означает
// [subscription.StateNotProduced].
//
// Две соседние причины разобраны и отвергнуты, иначе их подставит следующий:
//
//   - [subscription.StateNotRetained] («больше не удерживается») сказала бы, что
//     состояние когда-то отдавалось и подписчик за ним опоздал. Журнал объявляет
//     [subscription.RetainsEverything] и не чистится вовсе — утверждение было бы
//     ложным, а подписчик пошёл бы искать несуществующее окно;
//   - [subscription.StateWithheld] («есть, но не показывается») сказала бы, что
//     дело в ПРАВАХ вызывающего. Дело не в них: состояния нет ни для кого, и
//     подписчик, получивший «скрыто», просил бы прав, которые ничего не откроют.
//
// Отказ здесь означал бы «состояние есть, собрать не удалось» — и звал бы
// перечитывать событие вечно.
func state(subscription.Row) (*anypb.Any, subscription.StateAbsence, error) {
	return nil, subscription.StateNotProduced, nil
}
