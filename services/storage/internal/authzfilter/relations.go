package authzfilter

// PageRelations — предикат членства строки в СТРАНИЦЕ публичного List, ПО ТИПУ
// объекта. Карта ТОТАЛЬНА: запись под пустым ключом — умолчание для типа, не
// названного поимённо, поэтому типа без объявленного предиката не существует.
//
// Тотальность — не оформление. Она есть то, что позволяет гейту паритета
// (internal/repohygiene/listreadrelationparity_test.go) прочитать это объявление и
// сверить его с каталогом прав потипно. Предикат, спрятанный в теле функции, — это
// предикат, которого не видит ни один гейт.
//
// Значение — ТО ЖЕ отношение, которым пообъектная проверка на крае гейтит одиночное
// чтение (`<Resource>Service/Get` → `v_get`, `internal/check/permission_map.go` и
// запись каталога шлюза). Совпадение — не совпадение имён, а инвариант: страница не
// может быть шире чтения.
//
// Ярусные отношения (`viewer`/`editor`/`admin`) и глагольные (`v_*`) в модели
// РАЗВЯЗАНЫ намеренно, поэтому союз `viewer ∪ v_list` расходился с `v_get` в ОБЕ
// стороны: держатель яруса без глагола получал объект в выдаче, а на чтении — отказ
// (List возвращает ТО ЖЕ сообщение, что и Get, поэтому раскрывалось содержимое
// целиком); держатель глагола без яруса не находил собственный читаемый объект в
// своём же списке.
var PageRelations = map[string][]string{
	"": {"v_get"}, // умолчание: отношение, которым каталог гейтит `<Service>/Get`

	// Типы названы ПОИМЁННО, хотя предикат у всех один. Смысл не в значении, а в
	// том, что гейт паритета сверяет объявление с каталогом прав ПОТИПНО: под одним
	// умолчанием ему нечего сопоставлять, и «сверено типов = 0» выглядело бы как
	// зелёное, будучи пустым.
	"storage_volume":   {"v_get"},
	"storage_snapshot": {"v_get"},
	"storage_image":    {"v_get"},
	"compute_instance": {"v_get"},
}
