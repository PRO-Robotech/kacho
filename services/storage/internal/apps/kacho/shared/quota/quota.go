// Package quota — совещательная полоса учёта числа ресурсов и материализация
// строк учёта у владельца типа.
//
// Приёмка `docs/specs/sub-phase-quota-v2-materialised-usage-acceptance.md`
// (APPROVED, раунд 2): V2-1 (материализуется УЧЁТ, величина наследуется), V2-3
// («не сказано» = отказ), V2-4 (зеркало аккаунта), DoD S4 п.1.
//
// # Где этот пакет стоит в потоке
//
// Он стоит ПЕРЕД вставкой строки ресурса и после неё не участвует ни в чём.
// Решение о списании принимает триггер базы в той же транзакции, что вставка;
// здесь — ранний и понятный отказ плюс заведение строк, без которых триггеру
// нечего списывать.
//
// # Почему порт объявлен ЗДЕСЬ, а не в пакете репозитория
//
// Так устроен весь kacho-storage: порт объявляет тот, кто им пользуется
// (`volume.Reader`, `image.Writer`, `snapshot.Repo`), а адаптер его реализует и
// импортирует. Обратное направление втянуло бы pgx в замыкание зависимостей
// use-case-слоя.
//
// # Почему материализация живёт у владельца типа, а не у владельца величин
//
// Ребро «владелец величин → владелец типа» завести нельзя: kaname остаётся
// листом, и обратный вызов замкнул бы цикл, запрещённый `polyrepo.md`. Вдобавок
// синхронный вызов из iam в семь владельцев на пути создания проекта сделал бы
// создание проекта заложником доступности каждого из них. Значит строку заводит
// сам владелец — и единственный момент, когда он о проекте узнаёт, это обращение
// к нему.
//
// # Что из этого следует для проекта, созданного ДО появления учёта
//
// Ничего особенного: он материализуется на первом же обращении, ничем не
// отличаясь от свежесозданного. Обратного заполнения миграцией не существует и
// существовать не может — перечня проектов у владельца типа нет by construction
// (проекты принадлежат iam). Цена названа честно: самое первое обращение в
// незнакомом проекте делает один дополнительный вызов к соседу; дальше всё
// местное.
package quota

import (
	"context"
	"errors"
	"fmt"

	"github.com/PRO-Robotech/kacho/pkg/peer"
	"github.com/PRO-Robotech/kacho/pkg/quota/quotaread"
	storageerr "github.com/PRO-Robotech/kacho/services/storage/internal/errors"
)

// CarrierProject — носитель учёта «проект».
//
// Строка, а не перечисление, потому что носитель обязан совпадать с тем, что
// стоит в столбце `carrier_type` и в предикате триггера — то есть значение
// принадлежит СХЕМЕ, а не Go-типу. Константа существует затем, чтобы литерал
// `"project"` не расползся по вызывающим: разойдясь с триггером в одном месте,
// он дал бы вызывающего, который спрашивает про место не там, где его списывают,
// и получал бы вечное «потолок не назван» при заведённой строке.
const CarrierProject = "project"

// Service — домен, чьи виды спрашиваются у владельца величин.
//
// Тот же токен, которым каталог видов именует записи домена
// (`storage.volumes` → `storage`).
const Service = "storage"

// Виды ресурсов домена — ОДИН источник токена на весь сервис.
//
// Константы, а не литералы по месту вызова, и это не про стиль. Токен вида —
// КООРДИНАТА: он обязан совпасть с аргументом триггера учёта (миграция 0023) и с
// записью закрытого каталога у владельца величин. Форма второй части у этого
// домена МНОЖЕСТВЕННАЯ (`storage.volumes`, не `storage.volume`) — то есть именно
// та, которую рука пишет неверно чаще всего.
//
// Цена расхождения несимметрична и обе стороны тихие. Use-case, спрашивающий про
// вид, которого триггер не знает, получает «потолок не назван» ВСЕГДА: строк
// такого вида не заводит никто, потому что материализация заводит виды, названные
// владельцем величин. Опечатка в одном литерале выключила бы создание целого
// ресурса наглухо, для всех арендаторов, и выглядела бы как «платформа не назвала
// потолок». Обратное расхождение тише: вид, который триггер списывает, а полоса
// про него не спрашивает, теряет РАННИЙ отказ — предел при этом продолжает
// соблюдаться, поэтому дефект ничем себя не выдаёт.
//
// Совпадение с триггерами держится пробой `TestQuotaKinds_MatchTheTriggers`, а не
// вниманием: она читает миграцию и сверяет наборы в обе стороны.
const (
	// KindVolumes — тома проекта.
	KindVolumes = "storage.volumes"
	// KindSnapshots — снимки проекта.
	KindSnapshots = "storage.snapshots"
	// KindImages — образы проекта.
	KindImages = "storage.images"
)

// Row — одна строка учёта, какой её ЗАВОДИТ материализация.
//
// Потребления здесь нет НАМЕРЕННО: `used` принадлежит триггеру и никакому
// другому писателю (гейт дерева `TestQuotaUsedIsWrittenOnlyByItsTrigger`).
// Структура, несущая `Used`, немедленно сделала бы «записать потребление»
// выразимым на Go-стороне — а невыразимость этого и есть то, чем счётчик
// защищён от расхождения с реальностью.
type Row struct {
	// CarrierType — тип носителя учёта (`project`).
	CarrierType string
	// CarrierID — идентификатор носителя.
	CarrierID string
	// Kind — вид ресурса точечным токеном платформы (`storage.volumes`).
	Kind string
	// Limit — разрешённая величина, как её РАЗРЕШИЛ владелец величин. Снимок, а
	// не второй авторитет.
	Limit int64
	// SourceScope — область, на которой величина победила (`DEFAULT` /
	// `ACCOUNT` / `PROJECT`). Ради неё арендатор отличает личное перекрытие от
	// общего правила, а синхронизатор — строки, которых касается дельта
	// умолчания.
	SourceScope string
	// SourceScopeID — объект победившей области; пуст, когда победило умолчание.
	SourceScopeID string
	// LimitRevision — ревизия величины на момент снимка.
	LimitRevision int64
	// AccountID — зеркало аккаунта проекта. Пустым быть не может: строка без
	// зеркала невидима аккаунтной дельте, а снаружи это неотличимо от исправной
	// работы. Схема отвергает пустое значение.
	AccountID string
}

// ResolvedLimit — одна разрешённая величина, как её отдаёт владелец величин.
//
// ПСЕВДОНИМ, а не своя структура. Ровно та же тройка полей была объявлена в пяти
// доменах порознь: пять деклараций компилировались одинаково и разошлись бы при
// первом же новом поле — добавленном одному владельцу, а нужном всем. Общий
// экземпляр вдобавок делает клиента этого домена пригодным полосе чтения
// (`quotaread.Band`) БЕЗ переходника, а переходник — это ровно то место, где
// снисходительность к чужому ответу заводится незамеченной.
//
// Ревизии здесь нет, и это НЕ упущение, а факт контракта: `EffectiveLimit`
// владельца её не несёт. Строка учёта заводится с ревизией 0 — значением,
// которого у настоящих ревизий не бывает (они монотонны от единицы), то есть
// «ревизия не названа резолвом» отличимо от любой настоящей. Синхронизатор
// проставит настоящую.
type ResolvedLimit = quotaread.ResolvedLimit

// revisionUnknown — ревизия строки, заведённой резолвом, который её не назвал.
// Настоящие ревизии монотонны от единицы, поэтому ноль не совпадает ни с одной и
// означает ровно «ещё не синхронизировано», а не «синхронизировано нулевой».
const revisionUnknown = 0

// LimitResolver — владелец величин. Старшинство областей (PROJECT > ACCOUNT >
// DEFAULT) разрешается У НЕГО и только у него: владелец типа не знает аккаунта
// проекта иначе как зеркалом и потому разрешить старшинство сам не может.
type LimitResolver interface {
	Resolve(ctx context.Context, scopeID, service string) ([]ResolvedLimit, error)
}

// AccountLocator — аккаунт проекта.
//
// Отдельный порт, а не поле в резолве: аккаунт приходит из УЖЕ существующего
// вызова к соседу на пути создания (проверка существования проекта), и новым
// ребром эта работа не обзаводится. Реализация обязана делить с этой проверкой
// один вызов — иначе «нового вызова нет» перестанет быть правдой, оставшись
// правдой на бумаге.
type AccountLocator interface {
	AccountOf(ctx context.Context, projectID string) (string, error)
}

// Repo — то, что нужно полосе от репозитория: совещательный вопрос и
// материализация.
//
// Списания и возврата здесь НЕТ и быть не должно: их делает триггер той же
// транзакцией, что вставку строки ресурса, а Go-метод «списать» означал бы
// второго писателя счётчика — ровно то, что гейт дерева запрещает.
type Repo interface {
	// Admit сообщает, есть ли место под ещё одну строку этого вида у этого
	// носителя, НЕ занимая его.
	//
	// nil — место было в момент чтения. Отказ — `storageerr.ErrQuotaExceeded`
	// либо `storageerr.ErrQuotaNotProvisioned`, теми же текстом и признаком, что
	// и отказ авторитетной полосы: у обеих один производитель.
	Admit(ctx context.Context, carrierType, carrierID, kind string) error
	// Materialize заводит отсутствующие строки учёта и не трогает имеющиеся.
	// Возвращает число заведённых — чтобы «ноль заведённых» было отличимо от
	// «не звали».
	Materialize(ctx context.Context, rows []Row) (int64, error)
	// ListStates отдаёт строки учёта носителя — то, что арендатор читает как свои
	// квоты.
	//
	// Пустой срез означает «строк учёта ещё нет», а НЕ «квот нет»: различать эти
	// два состояния обязан вызывающий, и он же обязан ответить арендатору полным
	// набором видов с нулевым потреблением.
	ListStates(ctx context.Context, carrierType, carrierID string) ([]quotaread.State, error)
}

// Guard — совещательная полоса с материализацией на промахе.
type Guard struct {
	repo     Repo
	resolver LimitResolver
	accounts AccountLocator
}

// NewGuard собирает полосу.
func NewGuard(r Repo, resolver LimitResolver, accounts AccountLocator) *Guard {
	return &Guard{repo: r, resolver: resolver, accounts: accounts}
}

// Admit — ранний отказ по учёту, если места нет.
//
// nil означает «место было в момент вопроса», а не «место будет»: между этим
// ответом и вставкой помещается чужая запись. Решает атомарное списание триггера
// (ban #10), и приёмка прямо запрещает считать эту полосу решением (§7.4).
//
// Порядок ровно такой и он несущий:
//
//  1. спросить местную строку — исчерпание есть местный факт и обращения к
//     соседу не стоит;
//  2. промах («потолок не назван») → материализовать по всем видам домена;
//  3. спросить ещё раз — и если вид потолка так и не получил, это ОТКАЗ
//     `QUOTA_NOT_PROVISIONED`, а не разрешение.
//
// Третий шаг и есть то, чем «не сказано = отказ» держится: сосед, ответивший
// набором без этого вида, оставляет строку незаведённой, и второй вопрос
// отвечает тем же отказом — но уже терминально.
func (g *Guard) Admit(ctx context.Context, projectID, kind string) error {
	if g == nil {
		// Полоса не собрана (нет соседа, у которого спрашивать величины).
		//
		// Приёмник проверяется ЗДЕСЬ, а не у вызывающего, из-за ловушки
		// типизированного nil: `*Guard`, положенный в интерфейсный порт,
		// интерфейсу не равен nil, поэтому проверка `u.quota != nil` у
		// вызывающего истинна и вызов доходит сюда. Без этой ветки КАЖДЫЙ
		// Create на посадке без внутреннего адреса соседа падал бы паникой — то
		// есть «полоса не собрана» означало бы не «нет раннего отказа», а
		// «сервис не работает».
		//
		// nil означает «раннего отказа нет», а НЕ «предела нет»: место
		// по-прежнему занимает триггер в той же транзакции, что вставка, и
		// исчерпание приезжает отказом операции.
		return nil
	}
	err := g.repo.Admit(ctx, CarrierProject, projectID, kind)
	if !errors.Is(err, storageerr.ErrQuotaNotProvisioned) {
		return err
	}
	if merr := g.materialise(ctx, projectID); merr != nil {
		return merr
	}
	return g.repo.Admit(ctx, CarrierProject, projectID, kind)
}

// materialise заводит строки учёта по всем видам, которые назвал владелец
// величин.
//
// Fail-closed на каждом отказе соседа: пропустить мутацию, не установив предела,
// значит снять контроль ровно в тот момент, когда это труднее всего заметить —
// «пока сосед лежит, пределов нет» (`security.md` §Hardening п.8).
func (g *Guard) materialise(ctx context.Context, projectID string) error {
	accountID, err := g.accounts.AccountOf(ctx, projectID)
	if err != nil {
		return g.peerRefusal(err, "iam.project", projectID)
	}
	if accountID == "" {
		// Строка без зеркала аккаунта НЕВИДИМА аккаунтной дельте: изменение
		// аккаунтной области её не найдёт, и она проживёт со старой величиной, а
		// снаружи это неотличимо от исправной работы — дельта отчитается
		// успехом, просто не тронув её (V2-4). Схема отвергает пустое зеркало
		// ограничением; здесь отказ наступает раньше и называет предмет.
		return fmt.Errorf("%w: project %s carries no account", storageerr.ErrFailedPrecondition, projectID)
	}

	limits, err := g.resolver.Resolve(ctx, projectID, Service)
	if err != nil {
		return g.peerRefusal(err, "iam.limit", projectID)
	}
	if len(limits) == 0 {
		// Владелец величин не назвал ни одного вида. Заводить нечего, и это НЕ
		// разрешение: вызывающий получит отказ «потолок не назван» вторым
		// вопросом — тем же, что и при частичном ответе. Отдельной ветки отказа
		// здесь нет намеренно, иначе исход зависел бы от того, промолчал сосед
		// про все виды или про один.
		return nil
	}

	rows := make([]Row, 0, len(limits))
	for _, l := range limits {
		rows = append(rows, Row{
			CarrierType:   CarrierProject,
			CarrierID:     projectID,
			Kind:          l.Kind,
			Limit:         l.Value,
			SourceScope:   l.SourceScope,
			SourceScopeID: l.SourceScopeID,
			LimitRevision: revisionUnknown,
			AccountID:     accountID,
		})
	}
	_, err = g.repo.Materialize(ctx, rows)
	return err
}

// peerRefusal переводит отказ соседа в нашу полосу — код и машинный признак
// берутся у носителя (`pkg/peer`), а не выписываются здесь.
//
// Проза соседа наружу не идёт: она может нести имя хоста и текст драйвера
// (`security.md` §Hardening #1).
func (g *Guard) peerRefusal(err error, resourceType, resourceID string) error {
	return peer.Classify(err).Status(
		peer.Ref{Service: Service, ResourceType: resourceType, ResourceID: resourceID},
		peer.Prose{
			Missing:     "resource count limits are not stated for project %s",
			State:       "resource count limits for project %s cannot be read",
			Unavailable: "resource count limits are temporarily unavailable",
		},
	)
}
