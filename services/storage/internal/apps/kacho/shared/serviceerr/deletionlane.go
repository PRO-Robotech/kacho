package serviceerr

import (
	"google.golang.org/grpc/codes"

	"github.com/PRO-Robotech/kacho/pkg/refusal"
)

// serviceDomain — короткое имя источника отказа в `ErrorInfo.domain`. Назван ОДИН
// раз на пакет: литерал домена, повторённый по местам чеканки, разъезжается
// молча — и разъедется он именно там, где деталь читают машиной, а не глазом.
// Отсюда же ниже выводится домен отказа учёта: у одного предмета один владелец.
const serviceDomain = "storage"

// Отказ на СНЯТИЕ ресурса на пути наружу.
//
// ПОЧЕМУ ОТДЕЛЬНАЯ ВЕТКА, А НЕ ОБЩАЯ КЛАССИФИКАЦИЯ. Общая классификация отвечает
// только за КОД. Отказу на снятие этого мало: клиент обязан различать полосы
// МАШИННО — по `reason`-токену `google.rpc.ErrorInfo`, а не разбором прозы
// (`api-conventions.md`, раздел By-lane code-split). Без признака «защищён от удаления»,
// «контейнер не пуст», «на лист ссылаются» и «зависимые есть, вид не назван»
// приезжают ОДНИМ кодом и различаются только предложением — а действия
// вызывающего у них разные.
//
// ПОЧЕМУ ПРИЗНАК ПРИКЛЕИВАЕТСЯ ЗДЕСЬ, А НАЗЫВАЕТСЯ НЕ ЗДЕСЬ. Полосу называет
// ПРОИЗВОДИТЕЛЬ отказа — тот, кто знает, почему отказал; она едет в цепочке
// ошибки (`refusal.Wrap`). Здесь известен домен сервиса, назван он один раз, и
// поэтому признак собирается в одном месте на все отображения: «отказ на
// публичном слушателе» и «тот же отказ на внутреннем» не вправе разойтись формой
// признака.
//
// Вывод полосы РАЗБОРОМ СООБЩЕНИЯ здесь невозможен by construction и запрещён по
// существу: это был бы тот же разбор прозы, только перенесённый внутрь сервера.
func deletionRefusal(err error, code codes.Code, message string) (error, bool) {
	return refusal.Attach(err, refusal.Ref{Service: serviceDomain}, code, message)
}

// DeletionRefusal — синхронный отказ ПРЕДПРОВЕРКИ на снятие ресурса.
//
// Отличается от deletionRefusal тем, ОТКУДА приходит: предпроверка use-case'а
// классификацию репозитория не проходит вовсе — она чеканит статус сама, и без
// этого входа признак на её отказах не появился бы никогда. Домен берётся у
// пакета, а не у вызывающего: литерал источника отказа, повторённый по местам
// чеканки, разъезжается молча.
func DeletionRefusal(lane refusal.Lane, resourceType, id, format string, a ...any) error {
	return lane.Errf(refusal.Ref{Service: serviceDomain, ResourceType: resourceType, ResourceID: id}, format, a...)
}
