package main

// Распознаватель эфемерного порта знает все ЧИСЛОВЫЕ написания своего предмета —
// и РАСХОДИТСЯ с настоящим слушателем на пустом, намеренно.
//
// Разбор — в соседе (services/nlb/cmd/kacho-loadbalancer/ephemeralport_test.go).
// Коротко: ядру порт отдаёт ЧИСЛО ноль, а не строка «0», и `net.Listen` поднимает
// эфемерный слушатель на `:0`, `:00`, `:0000`, `:+0` и `:-0`, отвергая ` 0` и
// `0x0` — замерено прямым вызовом по каждому из восьми написаний.
//
// Девятое, ПУСТОЕ, исключено намеренно и потому названо: адрес собирается
// склейкой `":" + порт`, `net.Listen("tcp", ":")` поднимается на эфемерном порту
// (замерено), а явно пустая переменная умолчания не получает (замерено тоже) —
// то есть такая конфигурация достижима. Страж всё равно отвечает «нет»: он судит,
// ДОЕХАЛА ЛИ РУЧКА, а не что сделает ядро, и незаданная ручка — отсутствующая
// конфигурация, а не разрешение.

import "testing"

func TestPortKernelAssignedMatchesTheListenerOnNumericSpellings(t *testing.T) {
	for _, tc := range []struct {
		port string
		want bool
		why  string
	}{
		{"0", true, "каноническое написание"},
		{"00", true, "ядро смотрит на ЧИСЛО: net.Listen поднимает эфемерный слушатель"},
		{"0000", true, "то же числом, другой записью"},
		{"+0", true, "net.Listen принимает и поднимает эфемерный слушатель — замерено"},
		{"-0", true, "то же: область приёма продукта шире канонической записи"},
		{" 0", false, "с пробелом net.Listen ОТКАЗЫВАЕТ — распознаватель не вправе быть шире"},
		{"0x0", false, "шестнадцатеричную запись net.Listen тоже отвергает"},
		{"9090", false, "фиксированный порт — предмет запрета"},
		{"9091", false, "фиксированный порт — предмет запрета"},
		{"10", false, "ненулевой порт, начинающийся с цифры предмета"},
		// РАСХОЖДЕНИЕ с настоящим слушателем, намеренное. Фактов два, и стоять
		// обязаны оба: net.Listen("tcp", ":") ПОДНИМАЕТСЯ на эфемерном порту
		// (замерено), — и всё же мы считаем это незаданной конфигурацией, а не
		// разрешением, потому что страж судит, доехала ли ручка, а не что сделает
		// ядро.
		{"", false, "слушатель на \":\" поднялся бы на эфемерном; для стража это НЕЗАДАННАЯ ручка"},
	} {
		if got := portIsKernelAssigned(tc.port); got != tc.want {
			t.Errorf("portIsKernelAssigned(%q) = %v, ждали %v — %s", tc.port, got, tc.want, tc.why)
		}
	}
}
