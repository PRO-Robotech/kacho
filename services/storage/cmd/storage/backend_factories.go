package main

import "github.com/PRO-Robotech/kacho/services/storage/internal/clients"

// blockBackendFactories — виды плоскости данных, которые УМЕЕТ обслуживать этот
// бинарь.
//
// # Почему перечень пуст и почему это не заглушка
//
// Адаптер к конкретному хранилищу — отдельный предмет со своим протоколом,
// учётными данными и приёмкой. Пока его нет, честное состояние ровно это: процесс
// не умеет обслуживать НИ ОДИН вид, и посадка, объявившая вид, СТАРТ НЕ ПРОХОДИТ
// (см. serve.go). Альтернатива — принять вид и молча ничего не делать — дала бы
// сверщик, который каждый проход берёт работу и не двигает её, при этом сервис
// отчитывался бы здоровым, а тома стояли бы создаваемыми навсегда.
//
// Появится адаптер — он регистрируется ЗДЕСЬ одной строкой, и страж старта
// перестанет ронять посадку сам собой: послабления, которое надо было бы помнить и
// снимать, тут нет by construction.
func blockBackendFactories() map[string]clients.BackendFactory {
	return map[string]clients.BackendFactory{}
}
