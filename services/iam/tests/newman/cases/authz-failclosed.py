# AUTHZ-FAILCLOSED-LIST-NEVER-EMPTY-200 — ни один список НЕ отвечает пустой
# страницей, когда вердикта о правах взять неоткуда (задача #645), И отказ
# производит САМ СЕРВИС (задача #1198).
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ СОСЕДА ВЫШЕ. Тот кейс про ЧТЕНИЕ ОДНОГО объекта, и его отказ
# производит край: у `Get` есть запись каталога со scope, поэтому до iam запрос
# не доходит вовсе. Списочные RPC iam объявлены `scope_filtered` — край по ним
# per-RPC Check НЕ делает (он допускает вызов и оставляет сужение владельцу
# данных), запрос доезжает до сервиса, и отвечает уже САМ СЕРВИС. Это разные
# производители одного кода, и второй здесь не проверялся ничем.
#
# (Здесь стояло `<exempt>` — на дереве этих семи записей нет ни одной такой:
# перепись по контрактам семи служб даёт `scope_filtered` 7 из 7. Полосы
# различаются по существу: `<exempt>` допускает вызов внутреннего слушателя
# ВООБЩЕ БЕЗ ПРИНЦИПАЛА, `scope_filtered` идёт ПОСЛЕ его извлечения.)
#
# ЧТО ИМЕННО УТВЕРЖДАЕТСЯ. Пустая страница и отказ — разные ответы, и арендатор
# обязан их различать. `200 {}` на списке означает «тебе ничего не выдано»;
# именно так выглядел бы стенд, на котором вердикта взять неоткуда, — то есть
# сломанное развёртывание было бы неотличимо от корректно запертого. Поэтому
# утверждается ПАРА (HTTP-статус И код `google.rpc.Status`), отдельно — что
# ответ не является успехом с пустым массивом, и отдельно — ЧЬЯ полоса ответила.
#
# ПОЧЕМУ ВСЕ СЕМЬ. Инвариант принадлежит не одной поверхности, а классу: до
# задачи #645 привязки доступа отвечали на непровязанный порт отношений пустой
# страницей, а шесть соседей — отказом. Одна поверхность из семи, ведущая себя
# иначе, и есть та форма дефекта, которую перечень ловит, а точечный кейс нет.
#
# ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ — ПЕРВЫМ ШАГОМ, И ОН НЕ УКРАШЕНИЕ. Семь утверждений
# ниже — отрицания («ответ обязан быть отказом»), и на стенде, где до сервиса не
# доезжает НИ ОДИН запрос, они зеленели бы отказом края. Первый шаг спрашивает
# ту же поверхность тем же предъявителем так, чтобы ответил СЕРВИС и ответил
# НЕ отказом доступности: величина страницы вне допустимого диапазона отвергается
# ПЕРВЫМ СТЕЙТМЕНТОМ обработчика, до единого обращения к базе (`shared.
# ValidateVisiblePagination` в `internal/apps/kacho/api/project/list.go`), —
# поэтому под свёрнутой базой он даёт 400 / gRPC 3 ОТ СЕРВИСА. Он утверждает
# сразу три вещи, каждая из которых нужна семи отрицаниям ниже:
#   * запрос вообще ДОЕЗЖАЕТ до сервиса — снимок ключей края прогрет, полоса
#     отзыва не короткозамкнула, слой прав пропустил;
#   * ответы сервиса несут `details` — предпосылка различителя выполняется
#     ЗДЕСЬ И СЕЙЧАС, а не по чтению чужого кода;
#   * различитель отличает ответ сервиса от ответа края на РАЗНЫХ исходах, а не
#     только на 503.
# ---------------------------------------------------------------------------

