# AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE — ВТОРАЯ ветка того же условия: край не
# может добыть проверочные ключи и отказывает САМ (задача #1198).
#
# ЗАЧЕМ ОН НУЖЕН. Без него различитель полос был бы утверждением об одной
# стороне: «полоса сервиса опознаётся». Здесь он предъявляется на ответе, который
# по ИСХОДУ неотличим от соседнего кейса (те же 503 / gRPC 14) и обязан быть
# опознан ДРУГОЙ полосой. Два шага одной волны, одна и та же поверхность, один и
# тот же предъявитель — и два разных производителя, каждый назван.
#
# КАК СОЗДАЁТСЯ ПОЛОСА. Предъявляется удостоверение, отличающееся от настоящего
# РОВНО ОДНИМ ПОЛЕМ — идентификатором ключа в заголовке. Край выбирает запись
# издателя по `iss` (он не тронут), не находит такой ключ в снимке и идёт за
# набором ВЫНУЖДЕННО, не спрашивая срок снимка. Источник ключей — ключница в
# свёрнутой базе, поэтому набор не добывается, и край отвечает своей полосой.
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ «СНИМОК ПРОСТО УСТАРЕЛ», и почему взят этот повод.
# Поводов перезапроса у края два — истёк срок снимка и назван неизвестный ключ, —
# но ветвь добычи набора у них ОДНА, и классификация её отказа одна. Ждать
# истечения срока волна не может: срок 300 с, и это пять минут стенда со
# свёрнутой базой; укоротить срок нельзя тоже — ручка читается при старте, а
# перезапуск края обрывает проброс к нему НАВСЕГДА (цена уже измерена, см. шапку
# `scripts/run-failclosed.sh`). Поэтому берётся повод, который создаётся
# запросом, а не часами: `testing.md` — ждём УСЛОВИЕ, а не время.
#
# ОТЛИЧИЕ ОТ НЕГОДНОГО ТОКЕНА НАЗВАНО. На ИСПРАВНОМ источнике ключей то же самое
# удостоверение даёт 401: набор добыт, ключа в нём нет ⇒ токен негоден. Здесь
# утверждается 503 — то есть «не твоя вина, повтори позже». Ровно эта развилка и
# закрыта задачей #1194; кейс её не пересматривает, а пользуется ею как
# признаком: 401 на этом шаге означал бы, что источник ключей ОТВЕТИЛ, то есть
# условие волны не создано.
#
# ПОЧЕМУ ШАГ ОДИН. Вынужденный перезапрос несёт собственный минимальный интервал:
# второй такой запрос, пришедший сразу следом, набор перезапрашивать не станет и
# получит 401 вместо 503. Шаг здесь ровно один, и он отделён от прогрева всей
# длительностью сворачивания базы и выжидания кэша решений.
# ---------------------------------------------------------------------------

# Идентификатор ключа, которого мы не публикуем. Тот же литерал стоит в
# `scripts/run-failclosed.sh`, который прогревает снимок ключей тем же приёмом, —
# но СОВПАДЕНИЕ НЕ ТРЕБУЕТСЯ: обеим сторонам нужен лишь ключ вне опубликованного
# набора, и разойдясь, они ничего не сломают. Начни мы публиковать такой ключ —
# обе стороны скажут об этом громко (прогрев получит 200 вместо 401, кейс ниже
# покраснеет), поэтому предмета для гейта согласия здесь нет.
_LANE_PROBE_KID = "kacho-lane-probe-no-such-key"

CASES.append(Case(
    id="AUTHZ-FAILCLOSED-EDGE-KEY-SOURCE-LANE",
    title="the EDGE refuses (503/14) on its own key-source lane when the verification key set cannot be fetched",
    classes=["AUTHZ", "AUTHN", "FLOW", "FAIL_CLOSED", "NEG"],
    priority="P0",
    steps=[
        Step(
            name="list-projects-with-a-key-id-the-key-source-must-be-asked-about",
            method="GET",
            path="/iam/v1/projects?accountId={{accountAId}}",
            # auth НЕ задаётся: заголовок ставит пред-скрипт ниже — он несёт
            # СВОЙ страж настройки харнесса, потому что предъявляется не
            # переменная, а производное от неё.
            pre_script=[
                "// base64url ↔ текст. Восемь строк без продуктовой семантики:",
                "// разойтись такой копии не с чем — расхождение не разбиралось бы",
                "// вовсе, а роняло бы разбор заголовка на месте.",
                "function _b64urlToText(s) {",
                "  var t = String(s).replace(/-/g, '+').replace(/_/g, '/');",
                "  while (t.length % 4 !== 0) { t += '='; }",
                "  return CryptoJS.enc.Base64.parse(t).toString(CryptoJS.enc.Utf8);",
                "}",
                "function _b64urlFromText(s) {",
                "  return CryptoJS.enc.Base64.stringify(CryptoJS.enc.Utf8.parse(s))",
                "    .replace(/\\+/g, '-').replace(/\\//g, '_').replace(/=+$/, '');",
                "}",
                "const _real = pm.environment.get('jwtAccountAdminA')",
                "  || pm.variables.get('jwtAccountAdminA') || '';",
                "const _parts = String(_real).split('.');",
                "let _hdr = null;",
                "if (_parts.length === 3 && _parts[0] !== '') {",
                "  try { _hdr = JSON.parse(_b64urlToText(_parts[0])); } catch (_) { _hdr = null; }",
                "}",
                "if (!_hdr || typeof _hdr.alg !== 'string' || _hdr.alg === '') {",
                # СТРАЖ НАСТРОЙКИ ХАРНЕССА, та же форма, что у per-step auth в
                # gen.py: отсутствующий предмет = ОТКАЗ С ИМЕНЕМ, потом пропуск.
                # Отправить шаг без заголовка значило бы проверить анонимного
                # вызывающего — он получил бы отказ, и кейс прошёл бы, ни разу не
                # спросив источник ключей.
                "  pm.test('harness config: jwtAccountAdminA is a JWT this probe can derive from', () => {",
                "    pm.expect.fail('jwtAccountAdminA отсутствует либо не разбирается как JWT — "
                "производное удостоверение построить не из чего. Отправить шаг без заголовка "
                "нельзя: анонимный вызывающий получил бы отказ, и кейс прошёл бы, ни разу не "
                "спросив источник ключей.');",
                "  });",
                "  pm.execution.skipRequest();",
                "} else {",
                f"  _hdr.kid = {_LANE_PROBE_KID!r};",
                "  _parts[0] = _b64urlFromText(JSON.stringify(_hdr));",
                "  pm.request.headers.upsert({",
                "    key: 'Authorization', value: 'Bearer ' + _parts.join('.')",
                "  });",
                "}",
            ],
            test_script=(
                _refusal_head()
                + [
                    "// 401 здесь означал бы, что источник ключей ОТВЕТИЛ (набор добыт,",
                    "// ключа в нём нет ⇒ токен негоден) — то есть условие волны не",
                    "// создано. Утверждение об исходе ниже это и ловит.",
                ]
                + _unavailable_pair("edge-key-source")
                + _lane_assert("edge-key-source", "edge:key-source")
                + _never_empty_page("edge-key-source", "projects")
            ),
        ),
    ],
))
