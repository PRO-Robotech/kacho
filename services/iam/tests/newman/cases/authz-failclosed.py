"""Case-set authz-failclosed — отказ, когда вердикта о правах взять неоткуда.

Своя коллекция, а не кейс внутри authz-deny, потому что ей нужно УСЛОВИЕ,
несовместимое с остальным прогоном: база источника вердикта, свёрнутая в ноль.
Пока кейс жил среди соседей, это условие создать было нечем, и он держался
исключением в гейте — то есть инвариант «нет вердикта ⇒ отказ, никогда не 200»
не проверялся вообще, а выглядело это как зелёная суита.

Условие создаёт ``scripts/run-failclosed.sh``: ПРОГРЕВАЕТ снимок проверочных
ключей края, сворачивает базу, дожидается, пока решение перестанет отдаваться из
кэша шлюза, гоняет эту коллекцию и поднимает базу обратно. Прогонщик зовёт его
ОТДЕЛЬНОЙ ВОЛНОЙ, после всех остальных — соседям выключенная база сломала бы всё.

Исключения этой коллекции не полагается ни при каком исходе: не удалось создать
условие ⇒ отчёта нет ⇒ гейт докладывает ``authz-failclosed(no-report)`` и
краснеет. «Здесь не запустить» — факт расписания, а не вердикт.

Pre-conditions: `tests/authz-fixtures/setup.sh` (jwtAccountAdminA, accountAId).


ПОЧЕМУ У КАЖДОГО КЕЙСА УТВЕРЖДАЕТСЯ ПРОИЗВОДИТЕЛЬ ОТКАЗА (задача #1198)
=======================================================================

ПРИЗНАК. Семь списочных утверждений объявляли, что отказ производит САМ СЕРВИС, а
проверяли только пару «503 + gRPC 14». Под этим условием такую пару производят
ЧЕТЫРЕ разных места, и по паре они неразличимы:

  * край, полоса проверки подписи — набор проверочных ключей не добыт;
  * край, полоса чтения отзыва — авторитет отзыва не ответил;
  * край, полоса прав — источник вердикта не ответил;
  * СЕРВИС — вердикт не вычислить, потому что база не отвечает.

Совпадение не случайное: недоступность зависимости всюду классифицируется
одинаково и обязана классифицироваться одинаково (#1194). Различать её ИСХОД и её
ПРОИЗВОДИТЕЛЯ — разные задачи, и вторую утверждения не решали.

ПОЧЕМУ КЛАСС ТИХИЙ. Волна, кладущая базу ради проверки отказа сервиса, кладёт
заодно и источник ключей края: наш издатель подписывает своим ключом из ключницы,
а ключница живёт в той же базе. Край держит снимок ключей со сроком (умолчание
процесса — 300 с; действующую величину `scripts/run-failclosed.sh` читает у
РАЗВЁРНУТОГО края, а не предполагает) и обновляет его ЛЕНИВО — значит возраст
снимка на старте волны равномерно размазан по этому сроку, и если он истекает
внутри волны, отвечает край. Прогон при этом
остаётся зелёным: проверка исполняется, отчитывается и утверждает не своё.

РАЗЛИЧИТЕЛЬ — СТРУКТУРНЫЙ, А НЕ ТЕКСТОВЫЙ. Отказ, произведённый СЕРВИСОМ, едет
наружу через мост gRPC↔REST и маршалится публичным маршаллером края, у которого
`EmitUnpopulated=true`; поэтому в теле ВСЕГДА есть ключ `details` (пустым
массивом, если подробностей нет). Отказы самого края пишутся его промежуточными
слоями РУКАМИ, объектом из двух полей, и `details` в них нет НИКОГДА.

Замерено вызовом того же маршаллера, что стоит на боевом пути
(`newPublicJSONPb`, `gateway/internal/restmux/strict_enum.go`):

    public   -> {"code":14,"message":"service unavailable","details":[]}
    internal -> {"code":14,"message":"service unavailable"}

Почему признак взят структурный, а не «текст сообщения сервиса». Текстов у
сервиса под этим условием больше одного (их ставят разные слои), и перечислять их
значило бы завести список, который молча разойдётся с деревом. Ключ `details`
ставит МОСТ, один на все ответы сервиса, — и он не зависит ни от одного из них.

ПРЕДПОСЫЛКА РАЗЛИЧИТЕЛЯ НАЗВАНА И ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ. Он опирается на
`EmitUnpopulated=true` у ПУБЛИЧНОГО маршаллера. Снимут — различитель
перевернётся; но перевернётся он ГРОМКО: полоса сервиса перестанет опознаваться,
и первым же покраснеет положительный контроль ниже, который под тем же условием
обязан доехать до сервиса и получить от него `details`. Тихого зелёного эта
поломка не даёт by construction.

ЧЕГО ЗДЕСЬ НЕТ. Полоса края опознаётся `details`-отсутствием ПЛЮС постоянным
текстом отказа — исключительно чтобы падение НАЗЫВАЛО, какая именно полоса края
ответила. Текст здесь диагностический: вердикт выносит структурный признак.
"""

CASES = []


# ---------------------------------------------------------------------------
# Общий JS: КТО произвёл отказ.
#
# Функция возвращает ИМЯ ПОЛОСЫ, а не «да/нет»: утверждение сравнивает имя с
# ожидаемым, и падение печатает то, что ответило на самом деле, — иначе разбор
# красного начинался бы с перечня упавших шагов вместо текста отказа
# (`testing.md` §«Диагноз ставится по ТЕКСТУ отказа»).
#
# КОРЗИНЫ «ПРОЧЕЕ» НЕТ. Тело, которое не опознано ни одной полосой, возвращает
# `unrecognised:<текст>` — значение, не равное ни одному ожидаемому, поэтому
# такой ответ РОНЯЕТ утверждение и печатает себя. Не-JSON (страница ошибки
# входного контроллера, обрыв) попадает сюда же.
# ---------------------------------------------------------------------------

_LANE_JS = [
    "function _laneOf(j) {",
    "  // Мост gRPC↔REST маршалит статус публичным маршаллером края",
    "  // (EmitUnpopulated=true) ⇒ ключ `details` есть ВСЕГДА. Отказы самого края",
    "  // пишутся руками объектом из двух полей ⇒ `details` в них нет никогда.",
    "  var bridged = !!j && Object.prototype.hasOwnProperty.call(j, 'details')",
    "    && Array.isArray(j.details);",
    "  if (bridged) { return 'service'; }",
    "  var m = (j && typeof j.message === 'string') ? j.message : '';",
    "  // Ниже — ДИАГНОСТИКА, а не вердикт: вердикт вынесен строкой выше.",
    "  if (m === 'token key source unavailable') { return 'edge:key-source'; }",
    "  if (m === 'revocation check unavailable') { return 'edge:revocation'; }",
    "  if (m === 'authz service unavailable') { return 'edge:authz'; }",
    "  return 'unrecognised:' + JSON.stringify(m);",
    "}",
]

# Что означает каждое имя полосы — для текста падения. Перечень читает ЧЕЛОВЕК,
# разбирающий красное, поэтому он говорит не «ожидали X, получили Y», а чем
# именно это плохо.
_LANE_MEANING = {
    "service": "СЕРВИС (ответ приехал мостом gRPC↔REST)",
    "edge:key-source": "КРАЙ, полоса проверочных ключей (снимок ключей устарел и не обновился)",
    "edge:revocation": "КРАЙ, полоса чтения отзыва",
    "edge:authz": "КРАЙ, полоса прав",
}


def _lane_assert(label: str, expected: str) -> list:
    """Утверждение о ПРОИЗВОДИТЕЛЕ отказа.

    Отдельным `pm.test`, а не довеском к утверждению об исходе: исход и
    производитель — разные факты, и падение обязано называть, какой именно из них
    не сошёлся.
    """
    meaning = _LANE_MEANING[expected]
    return [
        f"pm.test('[FAIL-CLOSED] {label}: отказ произвёл {meaning}', () => {{",
        "  pm.expect(_lane, 'отказ произвёл ' + _lane + ', а кейс утверждает про "
        f"{meaning}: тот же исход (503/14) производят ЧЕТЫРЕ разных места, и по "
        "исходу они неразличимы — ' + _body).to.eql(" + repr(expected) + ");",
        "});",
    ]


def _refusal_head() -> list:
    """Разбор ответа: тело, полоса. Ставится в начало test-скрипта шага."""
    return _LANE_JS + [
        "let _j; try { _j = pm.response.json(); } catch (_) { _j = {}; }",
        "const _body = JSON.stringify(_j);",
        "const _lane = _laneOf(_j);",
    ]


def _unavailable_pair(label: str) -> list:
    """Пара «HTTP-статус + код `google.rpc.Status`».

    Пара, а не один из них: 503 приходит только от UNAVAILABLE, но код несёт
    смысл, а статус — механическое следствие (api-conventions.md, таблица края).
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: 503 Unavailable', () => {{",
        "  pm.expect(pm.response.code, _body).to.eql(503);",
        "});",
        f"pm.test('[FAIL-CLOSED] {label}: grpc code 14 (Unavailable)', () => {{",
        "  pm.expect(_j.code, _body).to.eql(14);",
        "});",
    ]


def _never_empty_page(label: str, field: str) -> list:
    """Утверждение о ЗАПРЕЩЁННОМ исходе.

    Не дублирует утверждения об исходе и производителе: те говорят, каким ответ
    обязан быть, это — каким он обязан НЕ быть, и падает с текстом, называющим
    именно ту подмену, ради которой кейс написан.
    """
    return [
        f"pm.test('[FAIL-CLOSED] {label}: never a successful empty page', () => {{",
        "  const _emptyOk = pm.response.code === 200"
        f" && Array.isArray(_j.{field}) && _j.{field}.length === 0;",
        "  pm.expect(_emptyOk, 'answered 200 with an empty array while the verdict "
        "source was unreachable: a tenant cannot tell that from \"nothing has been "
        "granted to you\" — ' + _body).to.eql(false);",
        "});",
    ]


