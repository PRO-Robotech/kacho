# AUTHZ-FAILCLOSED-OPENFGA-DOWN
#
# Шлюз развёрнут с `authz.enabled=true, authz.failOpen=false`. Когда вопрос о
# правах не может быть отвечен (источник вердикта недоступен), промежуточный слой
# уходит в ветвь ошибки и при failOpen=false ОБЯЗАН ответить 503 / gRPC 14. Ответ
# 200 здесь означал бы, что отсутствие ответа о правах засчитывается за
# «разрешено», — то есть защита снимается ровно тогда, когда она нужнее всего.
#
# Запрос выбран самый обычный (чтение своего аккаунта): предмет — НЕ конкретный
# метод, а поведение слоя прав; на разрешённом в норме запросе отличие «отказал,
# потому что не смог спросить» от «отказал, потому что не положено» видно чище
# всего — в норме этот же запрос отвечает 200.
#
# ПОЛОСА ЗДЕСЬ — `edge:authz`, И ЭТО УТВЕРЖДАЕТСЯ. У `Get` есть запись каталога
# со scope, поэтому решение принимает край и до сервиса запрос не доходит. Кейс
# называется «шлюз отказывает, когда источник вердикта недоступен» — значит
# отказ полосы проверочных ключей его утверждения НЕ подтверждает: он про другую
# зависимость и наступил бы при исправном источнике вердикта.
# ---------------------------------------------------------------------------

