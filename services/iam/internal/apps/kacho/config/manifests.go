// manifests.go — доставка манифестов модулей работающей службе (задача #1875).
//
// # Предмет
//
// Манифест модуля объявлен источником истины о том, что у платформы существует.
// В дереве он есть — по одному на модуль закрытого набора, — а способа доставить
// его работающей службе не было ни одного: ручки каталога у конфигурации нет,
// монтирования у чарта нет, загрузчик на пути старта никем не зовётся. Пока
// доставки нет, всякая сверка живых строк каталога с ОБЪЯВЛЕННЫМ состоянием
// невыразима: второго операнда у неё не существует (#1861).
//
// # Почему ручка, а не путь константой
//
// Каталог доставки — свойство ПОСАДКИ, а не бинаря: где посадка смонтирует
// манифесты, знает только она. Константа была бы решением, принятым за оператора
// и ему не предъявленным, а сменить его он мог бы только релизом образа — то
// есть ровно тем, от чего доставка и уводит.
//
// # Почему выключатель ЯВНЫЙ, а не «пустой каталог значит выключено»
//
// Пустая строка двусмысленна: «доставка не заведена» и «доставка заведена, а
// каталог забыли назвать» выглядят одинаково, и второе — это «не сужаем» в
// чистом виде (`security.md` §«Пустой список — это „не сужаем"»). Поэтому
// намерение объявляется отдельно, а незаданный при объявленном намерении каталог
// ОТКАЗЫВАЕТ В ПУСКЕ, а не подставляет умолчание.
package config

import "fmt"

// ManifestsConfig — секция `manifests` конфигурации службы.
type ManifestsConfig struct {
	// Dir — каталог, в который посадка монтирует манифесты модулей.
	//
	// Пустой означает «доставка не объявлена», и это законное состояние ровно
	// до тех пор, пока не объявлено Required: доставка вводится вперёд своих
	// потребителей, и стенд, её не объявивший, поднимается как прежде.
	Dir string `mapstructure:"dir"`

	// Required — объявляет ли посадка доставленные манифесты ОБЯЗАТЕЛЬНЫМИ.
	//
	// Не «включить чтение»: чтение включает сам Dir. Здесь объявляется, что
	// посадка на манифесты ОПИРАЕТСЯ, — и тогда её молчание о каталоге есть
	// расхождение, а не умолчание.
	//
	// ЗНАЧЕНИЕ `false` ПРИ НАЗВАННОМ КАТАЛОГЕ НЕ СУЩЕСТВУЕТ (#1924). Оно
	// объявлялось и не исполнялось ничем: чтение включает Dir, а сорванную
	// доставку `manifest.LoadDelivered` отвергает НЕЗАВИСИМО от этого поля —
	// решение записано у него же («почему отказ, а не мягкий проход»). То есть
	// исполнимых состояний было два, а объявленных три, и вызывающий — здесь
	// оператор посадки — получал успех рендера, уверенный, что его величина
	// применена. Теперь неполная пара отвергается в ОБЕ стороны.
	Required bool `mapstructure:"required"`
}

// Validate — страж старта секции: ПАРА объявляется целиком либо не объявляется
// вовсе.
//
// Отказ в пуске, а не подстановка умолчания: подставленный каталог был бы
// непустым всегда, поэтому доставка выглядела бы объявленной на всякой посадке —
// включая ту, что не монтирует ничего. Контроль, который не отказывает ни при
// каком входе, контролем не является.
//
// # Почему отвергаются ОБЕ неполные половины, а не одна
//
// Секция есть пара «намерение + координата», и половина пары ХУЖЕ отсутствия
// обеих, потому что выглядит настроенной (`security.md` §«Контроль, у которого
// нет МЕХАНИЗМА исполниться»). Прежде отвергалась одна половина из двух, и
// вторая — «каталог назван, опоры нет» — принималась, означая не то, что
// говорит: чтение включает Dir, а сорванную доставку читатель отвергает при
// любом Required. Величина, принимающая значение, которое ничего не меняет, есть
// «принято-и-проигнорировано» (`api-conventions.md`) этажом ниже поля запроса —
// следующий, кто её поставит, получит не объявленное поведение (#1924).
//
// # Почему не «сделать `false` мягким проходом» и не «снять величину»
//
// Мягкий проход отвергнут не здесь, а у самого читателя, и записан у него же:
// он дал бы контроль, не отказавший ни разу за свою жизнь, а сорванная доставка
// выглядела бы снаружи как «прав не выдали». Снятие величины вернуло бы «молчание
// о координате» в умолчание — тот самый класс «пусто значит не сужаем», против
// которого поле и заводилось, — и замены ему в дереве нет: проверка объявлений
// профилей стенд, доставку не объявивший, законным СЧИТАЕТ.
func (c ManifestsConfig) Validate() error {
	if c.Required && c.Dir == "" {
		return fmt.Errorf(
			"manifests.required объявлен, а manifests.dir пуст — посадка опирается на " +
				"манифесты модулей и не сказала, откуда их читать; умолчания здесь нет " +
				"намеренно: подставленный каталог был бы непуст всегда, и доставка " +
				"выглядела бы объявленной на посадке, которая не монтирует ничего (kacho#1875)")
	}
	if !c.Required && c.Dir != "" {
		return fmt.Errorf(
			"manifests.dir назван (%s), а manifests.required не объявлен — посадка сказала, "+
				"откуда читать манифесты модулей, и объявила, что на них не опирается; "+
				"такого состояния нет: чтение включает сам каталог, и сорванную доставку "+
				"процесс отвергает независимо от manifests.required, поэтому объявленное "+
				"«не опираемся» не исполняется ничем. Либо manifests.required: true "+
				"(опора объявлена честно), либо manifests.dir пуст — на посадке умбреллы "+
				"каталог берётся из manifests.configMapName, и снимается доставка "+
				"опустошением ИМЕНИ, а не отзывом опоры (kacho#1924)", c.Dir)
	}
	return nil
}
