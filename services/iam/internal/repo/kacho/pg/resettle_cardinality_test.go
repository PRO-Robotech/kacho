package pg

// resettle_cardinality_test.go — СВЕРКА КАРДИНАЛЬНОСТИ ПЕРЕСЕЛЕНИЯ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТО ДЕРЖИТ
//
// У проекции роли ДВА писателя, и это решение, а не упущение: один АВТОРУЕТ
// строку (`roleWriter.ReplaceRoleVerbs` / `ReplaceRuleRefs` — путь роли), второй
// только СНИМАЕТ её по чужому референту (`catalogWriter.ResettleTenantProjections`
// — путь применителя каталога). Довод — в шапке `catalog_writer.go`.
//
// Остаток, который это решение оставляет, ровно один: снимающий ПОВТОРЯЕТ ключ
// строки в предикате `USING … WHERE`. Ключ меняется — предикат расходится с
// отбором, и расхождение МОЛЧАЛИВО в обе стороны:
//
//	предикат УЖЕ ключа   снято меньше отобранного → ключ каталога отвергнет
//	                     снятие 23503, и отказ назовёт НЕ ту причину
//	предикат ШИРЕ ключа  снято больше отобранного → у арендатора отобрано
//	                     право, которого никто не отбирал, и записи об этом нет
//
// Второе необратимо: переселено ровно отобранное, а снято сверх того.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СВЕРКА, А НЕ ПРОВЕРКА ПЕРЕД ЗАПИСЬЮ
//
// Обе величины приходят ИЗ ОДНОГО ОПЕРАТОРА и, значит, из одного снимка: `doomed`
// — что отобрано, `dropped` — что снято. Это канонический приём запрета #10
// («`RETURNING …` + проверка кардинальности»), а не software check-then-act:
// между отбором и снятием ничего не помещается by construction, и действие по
// расхождению — ОТКАЗ, а не вторая запись.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРОИЗВОДИТЕЛЬ ВХОДА — СИНТЕТИКА, И ЭТО СКАЗАНО ПРЯМО
//
// Сегодня расхождение не производится НИ ОДНИМ входом: предикат снятия совпадает
// с ключом. Значит настоящих данных, роняющих сверку, не существует, и её
// способность отказать доказывается здесь — подачей величин напрямую. Законный
// близнец (совпадение → молчание) стоит рядом, иначе «отказывает» было бы
// неотличимо от «отказывает всегда», а сама сверка — от вечно красной.
//
// Вторая половина — что оператор ДЕЙСТВИТЕЛЬНО отдаёт обе величины и что сверку
// ЗОВУТ, — утверждается против живой Postgres:
// `module_catalog_applier_integration_test.go`.

import (
	"strings"
	"testing"
)

// TestResettleExactly_SilentWhenRemovalMatchesSelection — ЗАКОННЫЙ БЛИЗНЕЦ.
//
// Совпадение — штатный и единственный сегодняшний исход. Сверка, краснеющая
// здесь, остановила бы всякое снятие модуля.
func TestResettleExactly_SilentWhenRemovalMatchesSelection(t *testing.T) {
	for _, n := range []int{0, 1, 7, 1000} {
		if err := resettleExactly("role_verb", n, n); err != nil {
			t.Errorf("сверка отказывает на СОВПАДЕНИИ (%d = %d): %v — при таком поведении "+
				"снятие модуля не прошло бы ни разу", n, n, err)
		}
	}
}

// TestResettleExactly_RefusesWhenFewerRowsRemovedThanSelected — предикат УЖЕ ключа.
func TestResettleExactly_RefusesWhenFewerRowsRemovedThanSelected(t *testing.T) {
	err := resettleExactly("role_rule_ref", 5, 3)
	if err == nil {
		t.Fatal("сверка МОЛЧИТ, когда снято меньше отобранного — то есть не способна отказать, " +
			"и её присутствие в операторе ничего не значит")
	}
	assertNamesPopulationAndBothCounts(t, err, "role_rule_ref", "5", "3")
}

// TestResettleExactly_RefusesWhenMoreRowsRemovedThanSelected — предикат ШИРЕ ключа.
//
// Ось отдельная, а не «то же самое наоборот»: у неё другое следствие — право
// отобрано молча и переселением не сохранено, — и сверка, знающая лишь одну
// сторону, пропустила бы именно необратимую.
func TestResettleExactly_RefusesWhenMoreRowsRemovedThanSelected(t *testing.T) {
	err := resettleExactly("role_verb", 2, 9)
	if err == nil {
		t.Fatal("сверка МОЛЧИТ, когда снято БОЛЬШЕ отобранного — то есть пропускает тот исход, " +
			"в котором право отобрано и нигде не записано")
	}
	assertNamesPopulationAndBothCounts(t, err, "role_verb", "2", "9")
}

// assertNamesPopulationAndBothCounts — отказ обязан называть популяцию и ОБЕ
// величины: без них читатель видит «переселение не сошлось» и идёт искать
// причину, не зная ни таблицы, ни того, в какую сторону разошлось.
func assertNamesPopulationAndBothCounts(t *testing.T, err error, want ...string) {
	t.Helper()
	msg := err.Error()
	for _, w := range want {
		if !strings.Contains(msg, w) {
			t.Errorf("отказ не называет %q: %q", w, msg)
		}
	}
}
