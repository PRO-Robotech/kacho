package relverdict

// catalogtype.go — ИМЯ ТИПА В СЛОВАРЕ КАТАЛОГА БЕРЁТСЯ У ЖИВОЙ СТРОКИ КАТАЛОГА,
// а не у таблицы, ПОРОЖДЁННОЙ СБОРКОЙ (kacho#1986).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ЭТОГО МАЛО
//
// Параметр словаря каталога связывался значением `authzmap.CatalogTypeName` —
// оболочки над `authzmap/tables_gen.go`, порождённой сборкой из манифестов
// ДЕРЕВА. Оболочка ТОТАЛЬНА: незнакомое имя она возвращает как есть, то есть
// именем словаря МОДЕЛИ (`vpc_network`). Колонки, с которыми параметр
// соединяется, названы словарём КАТАЛОГА (`vpc.network`), и соединение разных
// написаний не совпадает НИКОГДА и молча.
//
// Тот же класс, что у зеркала (#1982), материализатора (#1967) и проекции
// (#1816), но исход ТИШЕ всех трёх и стоит ПОЗЖЕ: у зеркала промах отвергался
// проверкой схемы — громко, а здесь перечисление просто возвращает пусто, а
// селектор меток объект не покрывает. Клиент видит «прав нет», а не «что-то
// сломалось», и от честного отказа это неотличимо ничем.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПЕРЕВОД УЕХАЛ В ЗАПРОС, А НЕ ОСТАЛСЯ ВТОРЫМ ОБРАЩЕНИЕМ ИЗ Go
//
// Вердикт лежит на пути КАЖДОГО запроса с проверкой прав. Второе обращение к
// базе (прочитать строку каталога, затем спросить вердикт) стоило бы лишнего
// круга на всяком вопросе — и, сверх того, открыло бы окно между «спросил имя» и
// «спросил права»: применение, переименовавшее ресурс между двумя обращениями,
// дало бы ответ по имени, которого уже нет. Выражение внутри того же оператора
// закрывает и то, и другое: круг остаётся один, снимок — тот же.
//
// Цена самого выражения — один поиск по уникальному ключу
// `catalog_resource_object_type_live_uk` на таблице из десятков строк, и он
// НЕ КОРРЕЛИРОВАН (внутри — только параметр запроса), поэтому планировщик
// вычисляет его ОДИН РАЗ на исполнение, а не на строку. Нелинейности по
// населению это не заводит by construction.
//
// ─────────────────────────────────────────────────────────────────────────────
// СУЖЕНИЕ ИДЁТ ПО СВОЙСТВУ, А НЕ ПО ИМЕНИ
//
// Запретить сборочный переходник ПО ИМЕНИ нельзя: он тотален, поэтому любая его
// замена — те же две строки у следующего читателя, и запрет обходится молча.
// Различает словари СВОЙСТВО, объявленное самими словарями
// (`authzmap/type_dictionaries.go`): имя каталога содержит точку ВСЕГДА, имя
// модели — НИКОГДА.
//
// Здесь свойство выражено не проверкой на точку, а САМИМ ИСТОЧНИКОМ: имя берётся
// из колонки `dotted`, у которой точка стоит ограничением схемы
// (`catalog_resource_dotted_form`). Проверять её вторично значило бы завести
// второе место об одном предмете.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ТОТАЛЬНО, А НЕ ОТКАЗОМ
//
// Тип вне каталога законен, и таких два вида: вершина иерархии `cluster`
// (кластер не ресурс, строки у него нет и не будет) и непрозрачный тип чужого
// сервиса. Отказ здесь превратил бы вопрос о доступе к ним в ошибку, то есть в
// «сервис недоступен» вместо ответа. Поэтому промах отдаёт имя КАК ЕСТЬ — ровно
// тем поведением, какое было у снятого переходника, — и ни одна из трёх колонок
// на него не совпадёт, что для этих двух видов и верно: строк зеркала и проекции
// у них не бывает.
//
// Писателю колонки словаря МОДЕЛИ такой тотальности не хватило бы (см.
// `resource_mirror/model_dictionary.go`), и это не противоречие: там значение
// уезжает В ЗАПИСЬ, и неверное имя остаётся в таблице; здесь оно уезжает В
// СРАВНЕНИЕ, и неверное имя не совпадает ни с чем.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПОРЯДОК, А НЕ ПРОСТО «НАЙТИ СТРОКУ»
//
// Ключ уникальности каталога — `(object_type, live)`, а не `object_type`.
// Значит один тип модели ЗАКОННО описывают ДВЕ строки: снятая и живая, — и это
// не край, а форма переименования ресурса применением (`superseded_by` у снятой).
//
// Отсюда ОБА слагаемых, и каждое закрывает свой исход, а не украшает соседа:
//
//	без `LIMIT`      подзапрос отвечает ошибкой «больше одной строки», то есть
//	                 вердикт становится пятисоткой на живом состоянии каталога;
//	без `ORDER BY`   строка выбирается ПРОИЗВОЛЬНО, и с равным правом приезжает
//	                 имя СНЯТОЙ — то есть ровно тот тихий промах, ради которого
//	                 правка и сделана. Проверено инъекцией: снятие порядка при
//	                 сохранённом пределе роняет обе пробы применения и не трогает
//	                 ни одной соседней.
//
// Живое имя и есть то, каким названы `role_verb` и селекторы правил: их ключи
// живости другого имени не допускают.
const catalogTypeMark = "{{catalog_type}}"

// catalogTypeOfLiveRow — выражение SQL, дающее имя типа в словаре КАТАЛОГА для
// имени типа словаря МОДЕЛИ, пришедшего параметром `modelTypeParam`.
//
// Возвращается ВЫРАЖЕНИЕ, а не имя параметра: вызывающий подставляет его на
// место заполнителя в собранном запросе, и приведение `::text` рядом с
// заполнителем остаётся законным.
func catalogTypeOfLiveRow(modelTypeParam string) string {
	return "COALESCE((SELECT r.dotted" +
		" FROM kacho_iam.catalog_resource r" +
		" WHERE r.object_type = " + modelTypeParam + "::text" +
		" ORDER BY r.live DESC, r.dotted" +
		" LIMIT 1), " + modelTypeParam + "::text)"
}
