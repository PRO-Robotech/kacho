package authzguard

// own_door.go — СОБСТВЕННАЯ дверь iam: пообъектный вопрос о доступе на его
// собственных слушателях.
//
// # Предмет
//
// До этой двери решение о доступе на публичной поверхности iam принимал КРАЙ:
// api-gateway читал каталог прав и спрашивал модель об объекте, а сам iam
// повторял этот вопрос лишь у части своих RPC (у чтений — AllowsVGet, у двух
// правок — RequireScopeRelation). Пока iam стоит за нашим краем, это защитимо.
//
// Вынесенный в чужое облако iam нашего края не имеет BY CONSTRUCTION. Тогда
// каждый публичный RPC без собственного вопроса отдаёт объект любому
// АУТЕНТИФИЦИРОВАННОМУ вызывающему: посторонний читает чужой аккаунт, удаляет
// чужой проект и чеканит токен на чужого пользователя. Это не деградация
// разграничения, а его отсутствие.
//
// # Почему это ПРОВЯЗКА общего звена, а не ещё один страж
//
// Звено решения о доступе у платформы ОДНО — `pkg/authz.Interceptor`, — и
// шесть сервисов уже поднимаются с ним через носитель `pkg/servicehost`. Ровно
// для владельца модели носитель несёт полосу `servicecontract.AuthzSelf`
// («решает У СЕБЯ, ребра к себе не бывает»), и у неё до сих пор не было НИ
// ОДНОГО производителя: iam строит свои слушатели сам, минуя носитель, поэтому
// объявленная полоса не исполнялась никогда.
//
// Здесь заводится не второе звено, а недостающий вызывающий у первого. Из этого
// следует всё остальное: сокрытие существования берётся из общей таблицы
// текстов владельцев (`pkg/authz`, hide_existence.go) и потому ПОБАЙТОВО равно
// промаху; поведение на недоступности модели, на неизвестном RPC и на пустом
// субъекте — то же, что у шести соседей; и расхождения «край спрашивает одно,
// сервис другое» не существует, потому что карта у обоих ВЫВЕДЕНА из одних и
// тех же аннотаций контракта.
//
// # Карта ВЫВОДИТСЯ, а не пишется
//
// `catalogderive.Derive` строит карту из аннотаций дескрипторов, уже влинкованных
// в бинарь iam. Выписанная руками карта была бы ВТОРЫМ объявлением того же
// предмета: она разошлась бы с каталогом молча, и действующим требованием стало
// бы их пересечение — то, против чего никто не выдаёт прав. Опечатка в имени
// поля здесь роняет СТАРТ, а не первый запрос того, кто позовёт этот RPC.
//
// Замер на дереве (`Derive("kacho.cloud.iam.v1")`): методов 116 · пообъектных
// 82 · авторизуемых по данным 15 · освобождённых 19 · без двери 0. Карта ТОТАЛЬНА
// над пакетом — неназванного RPC в ней не бывает by construction, поэтому
// «забыли завести дверь новому RPC» невыразимо: незамапленный отвергается.
//
// # Решатель — СВОЙ, и ребра к себе не бывает
//
// iam владеет моделью прав, поэтому спрашивает СЕБЯ: тот же порт, которым
// пользуются RelationWriteGate, SystemViewerFloor и AllowsVGet. Сетевого соседа
// здесь нет — и не должно быть: вызов iam→iam был бы ребром в себя, а на
// вынесенном стенде ещё и зависимостью от адреса, которого нет.
//
// ПОРТА ОДНОГО НЕ ХВАТАЕТ, и это надо сказать прямо: соседи спрашивают iam ПО
// СЕТИ и получают ответ `AuthorizeService.check`, который применяет плоский
// надзор администратора облака ПЕРЕД выводом модели. Голый порт этого надзора не
// несёт — он отвечает выводом формы и только им. Поэтому надзор применяет сама
// дверь, тем же вызовом, что AllowsVerb и authorize_service: разбор, цена и
// порядок вопросов — в godoc checkAdapter ниже. Без него дверь отвергала бы
// администратора облака на каждом глаголе, у которого армы надзора в модели нет
// намеренно (`iam_user.token_issuer: subject` — каноничный такой).

import (
	"context"
	"fmt"
	"log/slog"
	"strings"
	"time"

	"google.golang.org/grpc"

	"github.com/PRO-Robotech/kacho/pkg/authz"
	"github.com/PRO-Robotech/kacho/pkg/authz/catalogderive"
)

// OwnDoorProtoPackages — пакеты контракта, чьи службы iam поднимает на своих
// слушателях.
//
// Перечень ЗАКРЫТ и обязан покрывать всё, что регистрируется: карта тотальна
// над названными пакетами, а RPC из НЕ названного пакета в неё не попадает
// вовсе и отвергается как незамапленный. То есть пропуск пакета здесь — не
// послабление, а отказ обслуживать его целиком; ошибка громкая, и это выбрано
// намеренно.
func OwnDoorProtoPackages() []string {
	return []string{
		"kacho.cloud.iam.v1",
		"kacho.cloud.operation",
		"kacho.cloud.quota.v1",
	}
}

// livenessProbeMethod — проба живости платформы, которую край зовёт у каждого
// бэкенда, решая свою готовность (gateway/internal/health).
//
// Служба `grpc.health.v1.Health` регистрируется КАЖДОМУ сервису общим
// конструктором `pkg/grpcsrv.NewServer`, то есть живёт на слушателе рядом со
// службами контракта, но НИ В ОДНОМ его пакете не объявлена. Карта, выведенная
// из аннотаций контракта, её не содержит by construction — и дверь отвергала бы
// пробу как незамапленную.
//
// Для iam это не косметика: край объявил его ЕДИНСТВЕННОЙ критичной
// зависимостью своей готовности, поэтому отвергнутая проба означает 503 на
// `/readyz` навсегда — реплика края не становится Ready ни при каком состоянии
// продукта, а выкатка не сходится по сроку.
const livenessProbeMethod = "/grpc.health.v1.Health/Check"

// withPlatformLivenessProbe доводит до карты двери РОВНО один метод — тот, чью
// публичность платформа уже решила и записала.
//
// # Это сведение двух мест об одном предмете, а не послабление
//
// Круг публичных на крае несёт `grpc.health.v1.Health/Check` ЕДИНСТВЕННОЙ
// записью, и её обоснование записано там же: ответ константен, одинаков для
// всякого вызывающего, не несёт ни арендатора, ни идентификаторов, а гейтить
// живость вопросом о правах значит превратить перебой модели в перезапуск
// каждой реплики. Край объявлял метод публичным, служба его отвергала — два
// места об одном предмете, из которых верно одно.
//
// # Круг узок намеренно
//
// Освобождается ровно то, что край зовёт. `Health/Watch` и служба отражения
// остаются за дверью: освобождение заводится ВМЕСТЕ с тем, что оно освобождает,
// а не вперёд него. Обе стороны держит own_door_liveness_test.go.
//
// Запись НИКОГДА не перекрывает выведенную: если пакет контракта однажды
// объявит метод с этим же именем, победит объявление контракта, а не эта
// строка, — иначе аннотация молча перестала бы действовать.
func withPlatformLivenessProbe(m authz.RPCMap) authz.RPCMap {
	if _, taken := m[livenessProbeMethod]; taken {
		return m
	}
	m[livenessProbeMethod] = authz.RPCEntry{Public: true}
	return m
}

// CallerAuthorityGatedMethods — RPC, которыми у модели СПРАШИВАЮТ, а не
// действуют: «можно ли субъекту S сделать A с объектом O».
//
// # Почему у них нет личности арендатора
//
// Субъект такого RPC стоит В ЗАПРОСЕ, а вызывающий — модуль: край на пути
// каждого запроса и сервисы-соседи при сужении списочной выдачи. Личности
// арендатора в их исходящем контексте нет by construction — вопрос задаётся ДО
// того, как решение о доступе принято, и задаёт его не тот, о ком спрашивают.
//
// # Кто их решает — ОДИН, и он назван
//
// `api/authorize/caller_authority.go` — единственный решатель вопроса «кто
// вправе спрашивать», и его шапка это заявляет прямо. Он строго fail-closed:
// вызывающий без личности проходит ТОЛЬКО с проверенным сертификатом модуля
// (`authorizeAnonymousPeer`), арендатор — только про себя, про объект, которым
// администрирует, либо будучи администратором кластера. Соседний рубеж того же
// слушателя (`AntiAnonymousUnary`) вычитает эти RPC по той же причине.
//
// Дверь для них добавляла ровно одно требование — «вызывающий назван», — и
// именно оно неверно: модуль называет себя сертификатом, а не заголовком
// личности. Наблюдалось: пять шардов сквозных проб, у каждого 40+ отказов
// `authz_no_principal` на `AuthorizeService/Check`, при нуле таких записей на
// стволе; посев умирал на первой же мутации, потому что ОТКАЗОМ становилось
// всякое решение о доступе на стенде.
//
// # Круг узок намеренно, и у каждой записи назван ПРОИЗВОДИТЕЛЬ
//
//   - `Check` — край, `gateway/internal/clients/iam_authorize_client.go`
//     (вопрос на пути каждого запроса);
//   - `BatchCheck` — сужатель списочной выдачи, `pkg/listnarrow/client.go`
//     (вопрос о странице у сервисов-соседей).
//
// `ListSubjects` и `ExpandRelations` тот же обработчик судит тем же гейтом, но
// производителя вне iam у них в этом дереве НЕТ (предикат:
// `git grep -l 'ExpandRelations\|ListSubjects' -- gateway pkg services ':!services/iam'`),
// поэтому записи им здесь не заводится: освобождение заводится ВМЕСТЕ с тем,
// что оно освобождает, а не вперёд него. Появится производитель — запись
// приедет вместе с ним.
//
// # Поправка живёт В ЗВЕНЕ, а не в карте — и это решение, а не вкус
//
// Карту двери судит перепись публичной поверхности
// (`internal/publicauthzcensus`), и её шапка объявляет: перепись обязана читать
// ТУ ЖЕ карту, которую звено спрашивает в проде. Перекрой мы здесь выведенную
// запись — перепись назвала бы эти два RPC освобождёнными КОНТРАКТОМ, чего
// контракт не объявлял; получилось бы второе место об одном предмете, и
// разошлись бы они молча. Карта остаётся выведенной, а поправка стоит там, где
// её видно как отдельное звено, — рядом с двумя другими рубежами того же
// слушателя.
//
// Сужение при этом строже, чем у записи в карте: дверь снимается ровно там, где
// у неё НЕТ ОБЪЕКТА, о котором спрашивать, — и случаев таких два, а не один.
//
// # Второй случай: вызывающий назван, а области запрос не назвал
//
// Здесь стояло «дверь снимается ТОЛЬКО когда личности арендатора нет вовсе», и
// половина эта неполна. `BatchCheck` спрашивает СУЖАТЕЛЬ СПИСОЧНОЙ ВЫДАЧИ
// (`pkg/listnarrow/client.go`), и он оборачивает исходящий контекст
// `auth.PropagateOutgoing` НАМЕРЕННО: решатель вопроса пропускает субъекта,
// спрашивающего о СЕБЕ, и настоящий принципал ему обязателен. То есть вызывающий
// назван — и снятие по первому случаю к нему не относится.
//
// Объекта у этого вопроса при этом нет. Контракт называет `scope_id`
// НЕОБЯЗАТЕЛЬНЫМ дословно: «Optional scope id for authz of the batch as a whole.
// When set, the gateway gates the entire batch on this scope's permission
// INSTEAD OF per-item». Незаданное поле означает «сужения нет, решает служба по
// данным»; сужатель его не заполняет ни в одном месте дерева (предикат:
// `git grep -n 'ScopeId' -- pkg/listnarrow` → пусто). Выведенный извлекатель
// читает поле как заданное всегда и отдаёт `project:` с пустым идентификатором —
// модель на такой объект отвечает «нет», и вызывающий получает отказ, к правам
// отношения не имеющий.
//
// Наблюдалось на прогоне 33965153510 (console-e2e, голова d1c7a4a89b): консоль
// показывала «Сервер не смог ответить · list filter: AuthorizeService.BatchCheck
// PermissionDenied: permission denied», СПИСКИ ВСЕХ РЕСУРСОВ ПРОЕКТА были пусты
// у каждого арендатора, и пять сквозных проб падали на том, что предмет их не
// виден. Журнал звена называл причину прямо: `authz_object_format_failed
// err="authz: empty object id"`.
//
// # Что снимается и что остаётся
//
// Дверь отходит, когда извлекатель отдал ПУСТОЙ идентификатор, — то есть когда
// спрашивать не о чем. Запрос, назвавший `scope_id`, проходит дверь как прежде:
// объект есть, и гейт контракта на нём осмыслен. `Check` не затронут вовсе — он
// объявлен `scope_filtered`, извлекателя у него нет by construction, и полоса
// данных остаётся его полосой.
func CallerAuthorityGatedMethods() []string {
	return []string{
		"/kacho.cloud.iam.v1.AuthorizeService/Check",
		"/kacho.cloud.iam.v1.AuthorizeService/BatchCheck",
	}
}

// OwnDoorOptions — то, что композиционный корень приносит двери.
type OwnDoorOptions struct {
	// SelfCheck — решатель ВЛАДЕЛЬЦА модели: собственный порт отношений iam.
	// Обязателен. nil → конструктор отказывает, а не заводит дверь, которая
	// никого не спрашивает: дверь без решателя пропускала бы всех, оставаясь на
	// вид провязанной.
	SelfCheck RelationChecker

	// Logger — журнал звена. nil → slog.Default().
	Logger *slog.Logger

	// CheckTimeout — предел одного вопроса к модели. ≤0 → умолчание звена.
	CheckTimeout time.Duration

	// DenyRateLimitPerSec — потолок темпа отказов на принципала. 0 → выключен.
	DenyRateLimitPerSec float64

	// PositiveTTL — окно вердикта: срок жизни ПОЛОЖИТЕЛЬНОГО ответа, то есть
	// время, в течение которого субъект с уже отобранным правом продолжает
	// проходить. Это параметр безопасности, а не производительности. 0 —
	// ЯВНОЕ «беру умолчание политики», как того требует конструктор кеша.
	PositiveTTL time.Duration
}

// NewOwnDoor собирает звено решения о доступе для собственных слушателей iam.
//
// Отказ возвращается там, где дверь получилась бы НЕДЕЙСТВУЮЩЕЙ: нет решателя,
// не выводится карта. Оба случая обязаны ронять старт, а не тихо давать
// пропускающее звено, — иначе провязка выглядит исполненной, и отличить её от
// исправной нельзя ничем.
func NewOwnDoor(opts OwnDoorOptions) (*OwnDoor, error) {
	if opts.SelfCheck == nil {
		return nil, fmt.Errorf("authzguard: собственная дверь iam не собирается — " +
			"решатель модели не принесён; дверь без решателя пропускает всех")
	}
	m, err := catalogderive.Derive(OwnDoorProtoPackages()...)
	if err != nil {
		return nil, fmt.Errorf("authzguard: собственная дверь iam не собирается — "+
			"карта прав не выводится из аннотаций контракта: %w", err)
	}
	logger := opts.Logger
	if logger == nil {
		logger = slog.Default()
	}
	full := withPlatformLivenessProbe(m)
	// Извлекатель берётся ИЗ ТОЙ ЖЕ карты, которую спрашивает звено: второй,
	// написанный рядом, разошёлся бы с первым молча — и разошёлся бы ровно там,
	// где расхождение невидимо, на пустом поле.
	bypass := make(map[string]authz.ObjectExtractor, len(CallerAuthorityGatedMethods()))
	for _, method := range CallerAuthorityGatedMethods() {
		bypass[method] = full[method].Extract
	}
	return &OwnDoor{inner: authz.NewInterceptor(authz.InterceptorOptions{
		ServiceName:         "kacho-iam",
		Map:                 full,
		Client:              checkAdapter{inner: opts.SelfCheck},
		Cache:               authz.NewCache(opts.PositiveTTL),
		Logger:              logger,
		CheckTimeout:        opts.CheckTimeout,
		DenyRateLimitPerSec: opts.DenyRateLimitPerSec,
	}), bypass: bypass}, nil
}

// OwnDoor — собственная дверь iam вместе с поправкой на вопросы о правах.
//
// Тип существует затем, чтобы у двери был ОДИН конструктор: композиционный
// корень и пробы обязаны собирать её одинаково, иначе проба судила бы вторую
// проводку, которой в проде нет.
type OwnDoor struct {
	inner *authz.Interceptor
	// bypass — методы, которыми у модели СПРАШИВАЮТ, а не действуют. Значение —
	// извлекатель объекта, ВЫВЕДЕННЫЙ из аннотаций контракта: им дверь и решает,
	// назвал ли запрос область, о которой можно спросить. Карта строится один
	// раз: сравнение по срезу на каждом запросе было бы линейным поиском на
	// горячем пути.
	bypass map[string]authz.ObjectExtractor
}

// callerNamed — назван ли вызывающий арендатором.
//
// Предикат ОДИН на звено и на обработчик: `PrincipalSubject` — то же чтение,
// которым `caller_authority.go` решает, идти ли вызывающему в
// `authorizeAnonymousPeer`. Второй предикат разошёлся бы с первым молча, и
// разошёлся бы ровно там, где расхождение невидимо, — на безымянном вызывающем.
func callerNamed(ctx context.Context) bool {
	_, named := PrincipalSubject(ctx)
	return named
}

// questionNamesNoScope — вопрос о правах не назвал области, о которой дверь
// могла бы спросить модель.
//
// # Почему это отдельный предикат, а не «пустая строка»
//
// Он отвечает ровно на один вопрос — есть ли у ДВЕРИ объект, — и отвечает по
// тому же извлекателю, которым звено соберёт объект секундой позже. Иначе
// завелось бы второе объявление того же предмета: имя поля контракта, выписанное
// здесь руками, пережило бы своё переименование молча.
//
// # Три исхода, и средний назван отдельно
//
//   - извлекателя нет вовсе (`scope_filtered`) — объекта у RPC нет by
//     construction, но и снимать нечего: звено единичного вопроса не задаёт.
//     Отвечаем «область названа», чтобы полоса `Check` осталась ровно той же;
//   - извлечение отказало — мы НЕ УСТАНОВИЛИ, что области нет. Дверь остаётся:
//     неполученный ответ не есть «спрашивать не о чем»;
//   - идентификатор пуст — области нет, и вопрос решает его решатель.
func questionNamesNoScope(extract authz.ObjectExtractor, req any) bool {
	if extract == nil {
		return false
	}
	_, id, err := extract(req)
	if err != nil {
		return false
	}
	return strings.TrimSpace(id) == ""
}

// questionGoesToItsOwnDecider — вопрос о правах решает `caller_authority.go`, а
// не дверь.
//
// Два случая, и оба про ОТСУТСТВИЕ объекта у двери, а не про доверие
// вызывающему: безымянный модуль называет себя сертификатом, а названный
// арендатор спрашивает о странице, области не назвав. Решатель за дверью строго
// fail-closed в обоих: субъект проходит, только спрашивая о себе, об объекте,
// которым администрирует, либо будучи администратором облака.
func (d *OwnDoor) questionGoesToItsOwnDecider(ctx context.Context, method string, req any) bool {
	extract, question := d.bypass[method]
	if !question {
		return false
	}
	return !callerNamed(ctx) || questionNamesNoScope(extract, req)
}

// Unary — звено публичного слушателя.
func (d *OwnDoor) Unary() grpc.UnaryServerInterceptor {
	door := d.inner.Unary()
	return func(ctx context.Context, req any, info *grpc.UnaryServerInfo, handler grpc.UnaryHandler) (any, error) {
		if d.questionGoesToItsOwnDecider(ctx, info.FullMethod, req) {
			// Вопрос о правах: решает обработчик — сертификатом вызывающего либо
			// данными самого вопроса. Объекта, о котором спросить, у двери нет.
			return handler(ctx, req)
		}
		return door(ctx, req, info, handler)
	}
}

// Stream — то же на второй полосе.
//
// Стримовых RPC у iam сегодня НОЛЬ, поэтому поправка здесь ничего не решает
// СЕЙЧАС и стоит ради того, чтобы решать, когда предмет появится: полоса без
// поправки при полосе с поправкой — различие, которого никто не принимал.
func (d *OwnDoor) Stream() grpc.StreamServerInterceptor {
	door := d.inner.Stream()
	return func(srv any, ss grpc.ServerStream, info *grpc.StreamServerInfo, handler grpc.StreamHandler) error {
		if d.questionGoesToItsOwnDecider(ss.Context(), info.FullMethod, nil) {
			return handler(srv, ss)
		}
		return door(srv, ss, info, handler)
	}
}

// checkAdapter доводит порт отношений iam до порта решателя общего звена и
// применяет плоский надзор администратора облака.
//
// # Почему надзор стоит ЗДЕСЬ, а не в модели
//
// Надзор администратора облака — ПЛОСКИЙ супер-гейт (один факт
// `cluster:<singleton> # system_admin @ <субъект>`), а не вывод модели, и живёт
// он отдельным звеном намеренно: один кортеж — один факт — одна строка аудита.
// Поэтому его применяет САМО каждое место решения о доступе:
//
//   - `service.AuthorizeService.check` — им отвечают краю и шести соседям
//     платформы, чей `pkg/authz.Interceptor` спрашивает iam по сети;
//   - `AllowsVerb`/`AllowsVGet` — собственные читающие стражи iam, тем же
//     вызовом перед вопросом об объекте.
//
// Здесь обёртка пересылала тройку прямо форме. То есть решение о доступе,
// пришедшее к iam ПО СЕТИ, надзор получало, а пришедшее на его собственный
// слушатель — нет: два места об одном предмете внутри одного сервиса, судящие
// одним портом и разным правилом.
//
// # Почему модель этого закрыть не может
//
// У части отношений армы надзора НЕТ НАМЕРЕННО. `iam_user` объявляет
// `token_issuer: subject`: обладать им можно единственным способом — БЫТЬ этим
// человеком, и источников уровня аккаунта у него нет по решению (персональный
// токен делает предъявителя самим человеком во ВСЕХ его аккаунтах, поэтому
// право, взятое внутри одного аккаунта, вышло бы за его границу). Значит машина
// приходит к такому глаголу ЕДИНСТВЕННЫМ путём — плоским надзором, — и дверь без
// надзора отвергает её при любой выдаче. Наблюдалось на учётке первичной
// посадки: чеканка персонального токена отвечала ей `AUTHZ_DENIED`, и посев
// матрицы сквозных проб не доходил до первой суиты.
//
// # Процедура решения — ДОСЛОВНО та, что получают по сети
//
// Три ветви, и они переписаны с `service.AuthorizeService.verdict`, а не
// придуманы: объект не ответил — исход ОШИБКА (надзор не спрашивается, второй
// вопрос неполученного ответа не заменяет); объект разрешил — разрешено; объект
// отказал — решает надзор. Мирить их незачем и нечем: это одна и та же дверь,
// и вызывающий не обязан знать, по сети он пришёл или на слушатель.
//
// Порядок «сначала объект» — обратный `AllowsVerb`, и это выбор: дверь стоит на
// КАЖДОМ публичном вызове, где разрешённый арендатор — обычный случай, и он
// платит ОДИН вопрос. Второй задаётся только там, где первый отказал. Исход от
// порядка не зависит: разрешено ⟺ объект разрешил ЛИБО субъект — администратор
// облака.
//
// РАСХОЖДЕНИЕ С `AllowsVerb` НАЗВАНО, а не заметено: он спрашивает надзор первым
// и потому разрешает администратору на НЕОТВЕТИВШЕМ вопросе об объекте («разрешению
// второе мнение не нужно»). Дверь так не делает — она повторяет `verdict`, ответ
// которого уже получают край и шесть соседей. Дверь, отвечающая по сети одно, а на
// своём слушателе другое, была бы двумя местами об одном предмете.
type checkAdapter struct{ inner RelationChecker }

func (a checkAdapter) Check(ctx context.Context, subject, relation, object string) (bool, error) {
	allowed, err := a.inner.Check(ctx, subject, relation, object)
	if err != nil {
		// Вопрос об объекте не ответил. Надзор здесь НЕ спрашивается — ровно
		// так же, как в `verdict`: неполученный ответ не есть ни «да», ни «нет»,
		// и второй вопрос его не заменяет.
		return false, err
	}
	if allowed {
		return true, nil
	}
	if a.isSuperGateQuestion(relation, object) {
		// Вопрос двери СОВПАЛ с вопросом надзора — переспрашивать то же самое
		// незачем: ответ «нет» уже получен выше.
		return false, nil
	}
	admin, adminErr := SubjectIsClusterAdminPlainE(ctx, a.inner, subject)
	if adminErr != nil {
		// Объект ответил «нет», а надзор не ответил вовсе. Отказом это назвать
		// нельзя: субъект мог оказаться администратором.
		return false, adminErr
	}
	return admin, nil
}

// isSuperGateQuestion — дверь спрашивает ровно то же, что спросил бы надзор.
func (a checkAdapter) isSuperGateQuestion(relation, object string) bool {
	return relation == "system_admin" && object == ClusterObject()
}
