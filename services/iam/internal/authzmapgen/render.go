package authzmapgen

// render.go — ТЕКСТ порождённого файла.
//
// Вынесен отдельно от вывода таблиц намеренно: «что дерево объявляет» и «как это
// записывается на Go» — разные предметы, и правка второго не вправе менять
// первый.

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

// Render — порождённый файл целиком, отформатированный тем же инструментом, что
// и остальное дерево.
//
// Форматирование ЗДЕСЬ, а не советом читателю: файл сверяется побайтово, и
// расхождение отступа читалось бы как расхождение таблицы.
func Render(t Tables) ([]byte, error) {
	if len(t.Entries) == 0 {
		return nil, fmt.Errorf("порождать нечего: записей ноль (%s) — пустой файл снёс бы "+
			"каталог типов целиком", t.Census.Summary())
	}

	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "// Перепись производителя: %s.\n", t.Census.StableSummary())
	b.WriteString("\npackage authzmap\n\n")

	b.WriteString(typeVerbRelationsDoc)
	b.WriteString("var typeVerbRelations = map[string][]string{\n")
	// Порядок — по имени ТИПА, а не по точечному имени: таблица ключуется типом,
	// и читаемый порядок есть порядок её собственного ключа. Детерминизм держат
	// обе сортировки одинаково; здесь выбран тот, по которому файл читают.
	byType := make([]TypeEntry, 0, len(t.Entries))
	for _, e := range t.Entries {
		if len(e.VerbRelations) == 0 {
			continue
		}
		byType = append(byType, e)
	}
	sort.Slice(byType, func(i, j int) bool { return byType[i].ObjectType < byType[j].ObjectType })
	for _, e := range byType {
		fmt.Fprintf(&b, "\t%q: {", e.ObjectType)
		for i, rel := range e.VerbRelations {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", rel)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("порождённый текст не форматируется (%w) — значит он и не "+
			"компилируется; отдать его нельзя", err)
	}
	return out, nil
}

