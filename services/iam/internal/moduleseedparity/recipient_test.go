// recipient_test.go — ВТОРАЯ проба предпосылки границы сверки (#1891, #1936).
//
// # Что она стережёт и почему одной пробы формы мало
//
// Соседняя проба (`TestBindingFormStillCannotExpressARelationGrant`) стережёт
// ОДНУ половину основания: у формы выдачи нет ключа отношения. Из неё читается,
// будто предмет #1936 закрывается заведением такого ключа. Он им не
// закрывается, и это записано в приёмке-основании, а не выведено здесь:
//
//   - `module-manifest-roles-and-seed-grants.md` §3.5 (APPROVED) — получателем
//     преднастроенной выдачи объявлена ТОЛЬКО группа, а служебная запись модуля
//     получает права вступлением в группу, не прямой выдачей;
//   - §10 п. 6 той же приёмки — задача-преемник обязана нести форму выдачи
//     отношением ВМЕСТЕ С ТИПОМ ЕЁ ПОЛУЧАТЕЛЯ, потому что модель ограничивает
//     субъект самим отношением.
//
// Обе живые строки, стоящие сегодня «ВНЕ ВЕРДИКТА», наделяют СЛУЖЕБНУЮ ЗАПИСЬ,
// а их отношение членства группы не принимает. Значит путь, предписанный §3.5
// («заведи группу, впиши в неё запись, выдай группе»), для них НЕИСПОЛНИМ, и
// форма, объявляющая отношение только группе, оставила бы #1891 заблокированной
// навсегда — при закрытом #1936.
//
// # Чем эта проба отличается от простого утверждения в комментарии
//
// Она читает КАНОН и живую базу, а не память. Пересечение правил пусто ровно до
// тех пор, пока канон таков; станет модель принимать членство группы у этих
// отношений — путь §3.5 станет исполнимым, решение о типе получателя придётся
// принимать заново, и проба скажет об этом сама, а не переживёт свой предмет.
//
// # Достижение цели НЕ является поломкой
//
// Невыразимых строк не осталось — проверять нечего, и проба проходит, напечатав
// перепись. Отказ на пустом перечне подталкивал бы держать строку ради зелёного:
// пустой перечень и есть предикат снятия #1891.
package moduleseedparity_test

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho/services/iam/internal/domain"
	"github.com/PRO-Robotech/kacho/services/iam/internal/moduleseedparity"
)

// fgaModelPath — канон модели прав. Он ОДИН на дерево; конфигмап чарта
// порождается из него, поэтому спрашивать надо здесь, а не у порождённого.
const fgaModelPath = "proto/kacho/cloud/iam/v1/fga_model.fga"

// TestRelationGrantRecipientTypeMustBeDecidedWithTheKey — сама проба.
func TestRelationGrantRecipientTypeMustBeDecidedWithTheKey(t *testing.T) {
	if testing.Short() {
		t.Skip("нужен Postgres: невыразимые выдачи берутся из ЖИВОЙ базы, а не из перечня имён")
	}
	ctx := context.Background()
	root := repoRoot(t)

	// #nosec G304 -- путь постоянный и лежит в этом же репозитории
	canon, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(fgaModelPath)))
	require.NoErrorf(t, err, "канон модели %s не прочитан: судить о типе получателя нечем", fgaModelPath)
	model := string(canon)

	states, _ := moduleStates(ctx, t, root)

	var inexpressible []moduleseedparity.Binding
	for _, st := range states {
		_, bad := moduleseedparity.SplitBindings(st.LiveBinding)
		inexpressible = append(inexpressible, bad...)
	}

	// Перепись — ДО вердикта и независимо от него.
	t.Logf("перепись: состояний модулей %d · невыразимых выдач %d · канон %s (%d байт)",
		len(states), len(inexpressible), fgaModelPath, len(canon))
	if len(inexpressible) == 0 {
		t.Log("невыразимых выдач в живой базе нет — предмета у этой пробы не осталось; " +
			"снимите её вместе с ним (#1891, #1936)")
		return
	}

	for _, b := range inexpressible {
		t.Logf("  судится: %s", b)

		require.Equalf(t, moduleseedparity.SubjectTypeServiceAccount, b.SubjectType,
			"получатель невыразимой выдачи %s — не служебная запись. Основание этой пробы "+
				"описывает ДРУГУЮ живую строку: §3.5 приёмки-основания требует получателем "+
				"группу, и для получателя-группы противоречия нет. Перечитайте границу #1936",
			b)

		bare, ok := domain.ScopeTypeFromDotted(b.ScopeType)
		require.Truef(t, ok,
			"якорь %q выдачи %s не переводится в тип объекта модели — судить по канону нечем",
			b.ScopeType, b)

		d, found := moduleseedparity.LookupRelation(model, bare, b.Relation)
		require.Truef(t, found,
			"в каноне %s нет объявления отношения %q у типа %q, которым наделена живая выдача %s. "+
				"«Не нашёл» не есть «группу не принимает»: молчание здесь было бы вымыслом",
			fgaModelPath, b.Relation, bare, b)
		require.Truef(t, d.HasDirectSubjects,
			"отношение %q у типа %q объявлено ВЫЧИСЛЯЕМЫМ — членство группы может прийти "+
				"транзитивно, и по этой строке о типе получателя судить нельзя (выдача %s)",
			b.Relation, bare, b)

		require.Falsef(t, d.AdmitsGroupMember(),
			"отношение %q у типа %q стало принимать %s (объявлено: %v). Предпосылка этой пробы "+
				"умерла: путь §3.5 приёмки-основания («получатель — группа, служебная запись "+
				"вступает в неё») для выдачи %s стал ИСПОЛНИМ. Решение о типе получателя формы "+
				"выдачи отношением (#1936, §10 п. 6 приёмки) принималось при пустом пересечении "+
				"двух правил — примите его заново и снимите эту пробу вместе с её предметом",
			b.Relation, bare, moduleseedparity.SubjectGroupMember, d.DirectSubjects, b)
	}

	t.Logf("предпосылка жива: у всех %d невыразимых выдач получатель — служебная запись, "+
		"а их отношение членства группы не принимает. Форма выдачи отношением, объявленная "+
		"ТОЛЬКО для получателя-группы, не сделает эти строки объявимыми — и #1891 осталась бы "+
		"заблокированной при закрытом #1936", len(inexpressible))
}
