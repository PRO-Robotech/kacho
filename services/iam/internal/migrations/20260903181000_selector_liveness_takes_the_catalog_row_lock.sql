-- 20260903181000_selector_liveness_takes_the_catalog_row_lock — страж живости
-- селектора берёт СТРОЧНЫЙ ЗАМОК на строке каталога, которую судит.
--
-- Задача продукта #1985. Остаток, названный вслух решением #1942
-- (`modulecatalog/prune.go`, раздел «чего решение не закрывает»).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ: ПЕРЕКОС ЗАПИСИ, А НЕ «СПРОСИТЬ, ЗАТЕМ СДЕЛАТЬ»
--
-- Две транзакции идут одновременно: одна снимает строку каталога, другая пишет
-- селектор, эту строку называющий.
--
--   * страж `role_rule_selectors_types_live` читает `catalog_resource` по СВОЕМУ
--     снимку и видит строку живой — незакоммиченного снятия он не видит;
--   * вырезание применителя читает `role_rule_selectors` по своему — только что
--     записанной, незакоммиченной строки селектора оно не видит.
--
-- Обе коммитятся. Селектор остаётся называть снятый тип.
--
-- Каждая сторона исполнена ОДНИМ оператором и корректна на своём снимке — то
-- есть это не software check-then-act и программной проверкой ни с одной стороны
-- не закрывается (запрет #10). Закрывает его только ОБЩИЙ ЗАМОК.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЗАМОК ВЫБРАН НЕ ПРОИЗВОЛЬНО: ЭТО ТОТ ЖЕ ЗАМОК, ЧТО БЕРЁТ ВНЕШНИЙ КЛЮЧ
--
-- У двух других проекций правила референт держится КЛЮЧОМ
-- (`role_rule_ref_res_fk`, `role_verb_type_fk` → `catalog_resource(dotted, live)`),
-- и перекоса записи у них НЕТ — потому что проверка ключа сама берёт на
-- родительской строке `FOR KEY SHARE`. Третья проекция ключа иметь не может
-- (внешний ключ на ЭЛЕМЕНТ массива в Postgres невыразим), и вместе с ключом она
-- лишилась не только проверки, но и ЗАМКА. Здесь замок возвращается — ровно тот,
-- который взял бы ключ, будь он выразим.
--
-- Отсюда же и его достаточность, и она НЕ предполагается, а следует из схемы:
-- `live` входит в уникальные ограничения, служащие целями внешних ключей
-- (`catalog_resource_live_uk`, `catalog_resource_dotted_live_uk`,
-- `catalog_resource_object_type_live_uk`), поэтому снятие строки есть ОБНОВЛЕНИЕ
-- КЛЮЧА и берёт `FOR UPDATE`, а `FOR UPDATE` с `FOR KEY SHARE` конфликтует.
-- Возьми страж более слабое — замок стоял бы, а не держал; возьми более сильное
-- (`FOR UPDATE`) — два арендатора, пишущие селекторы по одному типу,
-- сериализовались бы друг относительно друга без предмета.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ПРОИСХОДИТ ПРИ КАЖДОМ ИЗ ДВУХ ПОРЯДКОВ
--
--   селектор раньше снятия — запись держит строку каталога в `KEY SHARE`; снятие
--     ЖДЁТ её коммита, после чего вырезание, идущее в применителе следом за
--     снятием, читает уже закоммиченную строку селектора и вырезает её;
--
--   снятие раньше записи — запись ЖДЁТ коммита снятия и после него перечитывает
--     строку по её НОВОЙ версии (умолчание `READ COMMITTED`, повторная сверка
--     условия). Живой она уже не является — запись отвергается тем же отказом,
--     что и всякая запись снятого типа.
--
-- Исходы РАЗНЫЕ, и это не расхождение: общее у них ровно то, что и требуется, —
-- повисших не остаётся ни при каком порядке.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЦЕНА НАЗВАНА, А НЕ УМОЛЧАНА
--
--   1. КАЖДАЯ запись селектора берёт `KEY SHARE` на строку каталога за каждый
--      свой элемент. Замок разделяемый: арендаторы, пишущие селекторы, друг друга
--      не ждут. Ждёт только снятие строки каталога — глагол применителя, идущий
--      на подъёме службы, а не на пути запроса арендатора.
--
--   2. ПОРЯДОК ВЗЯТИЯ ЗАМКОВ у двух сторон НЕ СОВПАДАЕТ, и взаимная блокировка
--      НАСТУПАЕТ — это измерено, а не предположено. Применитель берёт строку
--      каталога, затем строки селекторов; путь пользовательской роли
--      (`ReplaceRuleSelectors`) снимает строки селекторов роли, а затем пишет их
--      — и страж берёт строку каталога уже после.
--
--      Замер (`TestSelectorLockOrderInversionIsStillPayable`, обе стороны
--      одновременно на живой базе): Postgres обнаруживает пару и отвергает
--      СТОРОНУ АРЕНДАТОРА — применитель доходит до конца, правка правил роли
--      получает `40P01`. То есть цену платит не тот, кто инверсию создаёт.
--
--      Это осознанный размен: громкий отказ, который повторяется, против тихого
--      неверного состояния, которое не сходится само. Условие наступления узкое —
--      правка правил роли одновременно со снятием строки каталога, называемой ЕЁ
--      селекторами; снятие идёт на подъёме службы, то есть окно привязано к
--      выкатке, а не к нагрузке. Предмет заведён отдельной задачей продукта
--      #1996 и здесь не чинится: у него другая поверхность (порядок взятия
--      замков на стороне писателя роли), а эта миграция судит вход.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ТЕКСТ ОТКАЗА НЕ МЕНЯЕТСЯ
--
-- Сообщение, SQLSTATE и имя ограничения остаются побайтово прежними: они часть
-- контракта отказа, их читают пробы и разбирает оператор. Меняется РОВНО способ
-- чтения строки каталога — с `EXISTS` на `PERFORM … FOR KEY SHARE`.
--
-- Форма `PERFORM` выбрана вместо `EXISTS (SELECT … FOR KEY SHARE)` намеренно:
-- блокирующее предложение внутри подзапроса `EXISTS` читается неоднозначно, а
-- `PERFORM` с `FOUND` — идиома plpgsql, у которой и замок, и признак находки
-- стоят на верхнем уровне оператора.
--
-- ДАННЫХ МИГРАЦИЯ НЕ ТРОГАЕТ: заменяется тело функции, ни одна строка не
-- читается и не пишется. Обратный путь полный — откатная половина возвращает
-- прежнее тело дословно, вместе с прежним комментарием.

-- +goose Up

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION kacho_iam.role_rule_selector_types_live() RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    declared_type text;
BEGIN
    FOREACH declared_type IN ARRAY NEW.object_types LOOP
        -- FOR KEY SHARE — тот же замок, который взял бы внешний ключ, будь он на
        -- элемент массива выразим. Он не даёт снятию строки каталога разойтись с
        -- этой записью по разным снимкам: снятие меняет `live`, входящий в
        -- уникальные ограничения — цели внешних ключей, то есть обновляет КЛЮЧ и
        -- берёт FOR UPDATE, а FOR UPDATE с FOR KEY SHARE конфликтует.
        PERFORM 1 FROM kacho_iam.catalog_resource cr
         WHERE cr.dotted = declared_type AND cr.live
           FOR KEY SHARE OF cr;
        IF NOT FOUND THEN
            RAISE EXCEPTION
                'object_types: % is not a live platform resource (role %)',
                declared_type, NEW.role_id
                USING ERRCODE = '23514',
                      CONSTRAINT = 'role_rule_selectors_types_live';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

COMMENT ON FUNCTION kacho_iam.role_rule_selector_types_live() IS
  'Референт ТРЕТЬЕЙ поверхности проекции правила: каждый элемент role_rule_selectors.object_types обязан называть живую строку kacho_iam.catalog_resource. Внешний ключ на элемент массива невыразим, проверка в коде запрещена (ban #10) — поэтому триггер. Проверяется КАЖДЫЙ элемент; отказ 23514 называет элемент и роль. Локальная переменная названа declared_type, а не именем колонки catalog_resource: совпадение имён даёт 42702 на КАЖДОЙ записи селектора. Строка каталога читается ПОД FOR KEY SHARE — тем же замком, который взял бы внешний ключ: без него снятие строки и запись селектора расходятся по своим снимкам (перекос записи, #1985).';

-- +goose Down

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION kacho_iam.role_rule_selector_types_live() RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    declared_type text;
BEGIN
    FOREACH declared_type IN ARRAY NEW.object_types LOOP
        IF NOT EXISTS (
            SELECT 1 FROM kacho_iam.catalog_resource cr
             WHERE cr.dotted = declared_type AND cr.live
        ) THEN
            RAISE EXCEPTION
                'object_types: % is not a live platform resource (role %)',
                declared_type, NEW.role_id
                USING ERRCODE = '23514',
                      CONSTRAINT = 'role_rule_selectors_types_live';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

