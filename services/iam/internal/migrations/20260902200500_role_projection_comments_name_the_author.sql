-- приводится к факту: у проекции роли один АВТОР, а не один писатель.
--
-- Задача продукта #1034 (применитель каталога модуля).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Комментарий `role_rule_ref`, поставленный миграцией 20260901113757, кончается
-- словами «Писатель один — role_repo.ReplaceRuleRefs». На день записи это было
-- верно. С приходом применителя каталога писателей стало ДВА: применитель снимает
-- строки, теряющие референт вместе со снимаемой строкой каталога, и переселяет их
-- в `role_grant_orphan`.
--
-- То есть комментарий ПЕРЕЖИЛ СВОЙ ПРЕДМЕТ и утверждает о схеме неправду —
-- причём в самом авторитетном месте, какое есть у схемы: в её собственном
-- каталоге, куда смотрит всякий, кто читает базу без исходников.
--
-- Править миграцию 20260901113757 нельзя (запрет #5, она применена), поэтому
-- утверждение приводится к факту НОВОЙ миграцией. Комментарий — единственное, что
-- она меняет: ни одной строки, ни одного ограничения, ни одного индекса.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО ТЕПЕРЬ ВЕРНО, И ПОЧЕМУ ИМЕННО «АВТОР»
--
-- Форму законной строки объявляет ТОЛЬКО тот, кто её вносит: он называет колонки
-- и значения. Снимающий формы не объявляет — он повторяет КЛЮЧ. Отсюда норма,
-- которую держит гейт `internal/repohygiene` `TestIAMRV112_...HasASoleWriter`:
--
--   вносит строку           ровно ОДИН — путь роли
--   снимает не-автор        законно, НО обязан переселить снятое тем же
--                           оператором, иначе отобранное право неотличимо от
--                           никогда не выданного
--
-- Вторую половину — что снято РОВНО отобранное — держит сверка кардинальности
-- внутри самого оператора применителя (`pg.resettleExactly`, запрет #10).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ КОММЕНТАРИЙ ПОЯВЛЯЕТСЯ И У ВТОРОЙ ПРОЕКЦИИ
--
-- `role_verb` и `role_rule_ref` — две проекции ОДНОГО объявления, и норма у них
-- одна. До сих пор одна из них норму писателя объявляла, вторая молчала, и этого
-- никто не решал: различие возникло как побочный эффект того, что таблицы заведены
-- разными миграциями с разницей в год. Полосы одного механизма обязаны сверяться
-- между собой, поэтому обе теперь говорят одно и то же.
--
-- Обратная сторона названа честно: `role_verb` до этой миграции комментария не
-- имела вовсе, то есть ЛОЖНОГО утверждения там не было — добавление её строки
-- закрывает не ложь, а молчание.

-- +goose Up

COMMENT ON TABLE kacho_iam.role_rule_ref IS
  'Проекция ОБЪЯВЛЕННЫХ сегментов правила роли — то, на чём внешний ключ в каталог ВОЗМОЖЕН (на roles.rules jsonb он невыразим: подзапрос в CHECK отвергается DDL). Строка кладётся на КАЖДЫЙ объявленный сегмент, а не на резолвящийся. АВТОР один — role_repo.ReplaceRuleRefs: форму строки объявляет только тот, кто её вносит. Снимать вправе и не-автор (применитель каталога, когда референт снят), но снятое он обязан ПЕРЕСЕЛИТЬ в role_grant_orphan тем же оператором.';

COMMENT ON TABLE kacho_iam.role_verb IS
  'Проекция «роль → тип объекта × глагол» — то, из чего цепь вердикта собирает ответ «разрешено ли действие». АВТОР один — role_repo.ReplaceRoleVerbs: форму строки объявляет только тот, кто её вносит. Снимать вправе и не-автор (применитель каталога, когда снят ресурс, на который ссылается role_verb_type_fk), но снятое он обязан ПЕРЕСЕЛИТЬ в role_grant_orphan тем же оператором.';

-- +goose Down

COMMENT ON TABLE kacho_iam.role_rule_ref IS
  'Проекция ОБЪЯВЛЕННЫХ сегментов правила роли — то, на чём внешний ключ в каталог ВОЗМОЖЕН (на roles.rules jsonb он невыразим: подзапрос в CHECK отвергается DDL). Строка кладётся на КАЖДЫЙ объявленный сегмент, а не на резолвящийся. Писатель один — role_repo.ReplaceRuleRefs.';

