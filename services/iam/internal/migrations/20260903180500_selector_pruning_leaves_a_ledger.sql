-- 20260903180500_selector_pruning_leaves_a_ledger — вырезание висячих элементов
-- третьей проекции правила перестаёт быть БЕЗМОЛВНЫМ.
--
-- Задача продукта #1988. Преемник решения #1034/#1942 (`modulecatalog/prune.go`).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Применитель приводит третью проекцию правила к каталожному факту: вырезает из
-- `role_rule_selectors.object_types` элементы, не называющие живой строки
-- каталога, а строку, у которой живого типа не осталось, снимает целиком. Это
-- НЕОБРАТИМО и не записано НИГДЕ: у переселения проекций ведомость есть
-- (`role_grant_orphan` — роль, предмет, причина, момент), у вырезания не было
-- никакой. Объём оператор узнавал ТОЛЬКО из плана, а постфактум — ниоткуда.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЭТО ВТОРАЯ ОПОРА К РЕШЕНИЮ, А НЕ ОТМЕНА ЕГО
--
-- Решение не ставить потолок на эту популяцию принято и остаётся в силе. Довод
-- его верен: потолок запрещал бы ПОЧИНКУ. Висячий элемент делает строку
-- неприемлемой для стража живости (`role_rule_selectors_types_live`), поэтому
-- арендатор не может её править, пока висяк не вырезан, — контроль, поставленный
-- ради безопасности, заблокировал бы единственный путь к исправному состоянию.
-- Ведомость потолка не заводит и не подразумевает: она делает НАБЛЮДАЕМЫМ то,
-- что до сих пор наблюдалось только в плане.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ СВОЯ ТАБЛИЦА, А НЕ ТРЕТЬЯ ПОПУЛЯЦИЯ СИРОТЫ
--
-- Закрытый набор источников `role_grant_orphan_source_known` знает две популяции,
-- и «третьей у него нет by construction» — это ЗАПИСАННОЕ решение применителя
-- (`modulecatalog/apply.go`, п. 4), а не пропуск. Довод его здесь не
-- пересматривается и остаётся верным: сироты адресуются парой «тип объекта +
-- глагол», а у элемента селектора глагола нет вовсе, и переселять его нечем.
--
-- Вырезанное адресуется ИНАЧЕ — тройкой «роль + отпечаток правила + тип», —
-- потому и живёт своей таблицей. Отпечаток правила существенен: одна роль
-- проецирует несколько правил, и «у роли вырезан тип» не говорит, из какого
-- именно правила.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ИСХОД — ОТДЕЛЬНАЯ КОЛОНКА
--
-- Строка, потерявшая последний живой тип, СНЯТА целиком; строка, у которой живой
-- тип остался, УКОРОЧЕНА. Для разбирающего последствия это события разного рода:
-- в первом случае правило перестало проецироваться вовсе, во втором сузилось.
-- Сложенные в одну величину, они это различие теряют — тем же доводом, каким
-- `Resettled` и `Pruned` несут по две-три величины, а не по одной.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПРИЧИНА ЧИТАЕТСЯ У СНЯТОЙ СТРОКИ КАТАЛОГА, А НЕ ПРИХОДИТ ПАРАМЕТРОМ
--
-- Элемент становится висячим ровно в тот момент, когда строка каталога помечена
-- снятой, — и причина того снятия УЖЕ записана в `catalog_resource.retired_reason`
-- тем же применением, в той же транзакции. Второй экземпляр той же величины
-- разошёлся бы с первым молча.
--
-- Колонка НУЛЛИРУЕМА, и это не небрежность: под вырезание попадают и элементы,
-- повисшие ДО заведения применителя (фильтр «оставить живое», а не «вырезать
-- снятое этим применением»), — а строки каталога, снятые ранними миграциями,
-- причины не несут. NULL здесь означает «строка каталога причины не несла», а не
-- «причину потеряли»; схлопнуть его в пустую строку значило бы выдать второе за
-- первое.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- «КАКИМ ПРИМЕНЕНИЕМ» ОТВЕЧАЕТ МОМЕНТ
--
-- `pruned_at` — `now()`, то есть ВРЕМЯ ТРАНЗАКЦИИ: у всех строк одного применения
-- оно совпадает дословно, и по нему собирается ровно то, что снято одним заходом.
-- Отдельного идентификатора применения не заводится: он был бы вторым носителем
-- уже выразимого факта, а применитель их не чеканит.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОВТОРНАЯ ЗАПИСЬ — ПЕРВАЯ ПОБЕЖДАЕТ, КАК У ВЕДОМОСТИ ПЕРЕСЕЛЕНИЯ
--
-- Ключ не несёт момента, а писатель кладёт строку через `ON CONFLICT DO NOTHING`
-- — дословно как переселение. Повтор возможен лишь через оживление строки
-- каталога, повторную запись селектора и повторное снятие; тогда ведомость
-- сохраняет ПЕРВЫЙ момент. Это осознанный размен: ключ с моментом сделал бы
-- ведомость неограниченно растущей, а её предмет — «что было вырезано у этой
-- роли» — не требует истории повторов.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- СЛЕД УМИРАЕТ ВМЕСТЕ СО СВОЕЙ РОЛЬЮ
--
-- `ON DELETE CASCADE` — тем же доводом, что у `role_grant_orphan`: запись
-- адресована ролью и пережить её не может, иначе ведомость копила бы строки без
-- предмета, а читающий не отличал бы отобранное у живой роли от следа удалённой.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ДАННЫХ МИГРАЦИЯ НЕ ТРОГАЕТ И ЗАДНИМ ЧИСЛОМ НИЧЕГО НЕ ВОССТАНАВЛИВАЕТ
--
-- Уже вырезанное записано не будет: его нет нигде, и выдумать его не из чего.
-- Ведомость действует ВПЕРЁД — это сказано вслух, а не умолчано, чтобы пустая
-- таблица на намигрированной базе не читалась как «ничего никогда не вырезали».
-- Обратный путь полный: `DROP TABLE` снимает след и ничего кроме.

-- +goose Up

CREATE TABLE kacho_iam.role_selector_prune (
  role_id     text        NOT NULL
    REFERENCES kacho_iam.roles (id) ON DELETE CASCADE,
  -- rule_fp — отпечаток правила, из проекции которого элемент вырезан. Внешнего
  -- ключа на `role_rule_selectors` здесь НЕТ и быть не может: строку, у которой
  -- живого типа не осталось, тот же оператор снимает целиком, и ключ отверг бы
  -- ровно ту запись, ради которой ведомость заводится.
  rule_fp     text        NOT NULL,
  object_type text        NOT NULL,
  -- outcome — что стало со строкой селектора. Набор ЗАКРЫТ.
  outcome     text        NOT NULL,
  -- retired_reason — причина снятия строки каталога, сделавшего элемент висячим.
  -- NULL означает «строка каталога причины не несла» (снята ранней миграцией), а
  -- НЕ «причину потеряли».
  retired_reason text,
  pruned_at   timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT role_selector_prune_pkey PRIMARY KEY (role_id, rule_fp, object_type),
  CONSTRAINT role_selector_prune_outcome_known CHECK (outcome IN ('shortened', 'dropped')),
  CONSTRAINT role_selector_prune_fp_nonempty CHECK (rule_fp <> ''),
  CONSTRAINT role_selector_prune_type_nonempty CHECK (object_type <> '')
);

COMMENT ON TABLE kacho_iam.role_selector_prune IS
  'Элементы третьей проекции правила, вырезанные применителем каталога при снятии строки ресурса. Вырезание необратимо; без этой ведомости объём был виден ТОЛЬКО в плане применения, а постфактум — ниоткуда. Ведомость действует вперёд: уже вырезанное в ней не появится. Потолка на популяцию она не вводит и не подразумевает — потолок запрещал бы починку, см. #1034.';

COMMENT ON COLUMN kacho_iam.role_selector_prune.outcome IS
  'shortened — у строки селектора остался живой тип, она укорочена; dropped — живого типа не осталось, строка снята целиком. Разные события для разбирающего последствия, поэтому колонка, а не сумма.';

COMMENT ON COLUMN kacho_iam.role_selector_prune.pruned_at IS
  'Время ТРАНЗАКЦИИ применения: у всех строк одного применения совпадает дословно, и по нему собирается вырезанное одним заходом. Отдельного идентификатора применения не заводится — он был бы вторым носителем уже выразимого факта.';

-- Чтение «что вырезано у этой роли» идёт первичным ключом. Отдельный индекс по
-- моменту НЕ заводится: перечень «что снято одним применением» — вопрос
-- разбирающего, а не путь запроса арендатора, и платить за него на каждой записи
-- незачем.

-- +goose Down

DROP TABLE IF EXISTS kacho_iam.role_selector_prune;
