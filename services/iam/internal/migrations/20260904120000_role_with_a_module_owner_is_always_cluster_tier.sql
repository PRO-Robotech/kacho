-- role_with_a_module_owner_is_always_cluster_tier — инвариант «есть
-- владелец-модуль ⟹ роль системная» получает СВОЁ ограничение и перестаёт быть
-- побочным следствием двух правил об ИМЕНИ.
--
-- Задача продукта #2020 (P1). Проба —
-- `role_owner_module_cluster_tier_integration_test.go`.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НЕВЕРНО СЕГОДНЯ
--
-- Владение (`owner_module`, миграция 20260902190500) и ярус (`cluster_id`, из
-- которого вычисляется `is_system`, миграция 0056) — две независимые колонки, и
-- НИ ОДИН объект схемы их не связывает. Держат связь два софтверных места:
-- применитель манифеста пропускает роль, чей ярус не кластерный
-- (`moduleroles/apply.go`, ветка `mr.Tier.TierType != ScopeTypeClusterDotted` →
-- `Skipped++`), а `UpsertSystemRole` — единственный оператор, кладущий
-- `owner_module`, — всегда пишет и `cluster_id`. Второй писатель вопрос
-- времени, и его правка пройдёт обзор: в диффе строка роли выглядит обычной.
--
-- Цена названа соседней приёмкой, а не предположена: на кластерном ярусе роли
-- модуля стоит её вывод «цепь областей у такой роли пуста, поэтому меточную
-- ветвь вердикта сужать не надо». Роль модуля с непустой цепью делает вывод
-- неверным, а доступ возвращается МОЛЧА — отказа не будет ни от кого.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НАШЛА ПЕРЕПИСЬ — И ЭТО МЕНЯЕТ ПОСТАНОВКУ, А НЕ ОТМЕНЯЕТ РАБОТУ
--
-- Нарушающая строка сегодня НЕ проходит. Отвергают её проверки ИМЕНИ, и какая
-- именно — зависит от имени:
--
--   * имя с точкой (`vpc.viewer`) на арендаторском ярусе рубит
--     `roles_custom_name_check`: у не-системной роли имя обязано быть
--     `^[a-z][a-z0-9_]{0,40}$`, а точки в этом классе нет;
--   * имя без точки (`viewer`) рубит `roles_owner_module_name_prefix`: имя роли
--     с владельцем начинается с `<модуль>.`.
--
-- Пересечения у двух требований нет: одно требует точку на позиции
-- `length(owner_module) + 1`, другое запрещает её вовсе. Значит входа,
-- нарушающего ТОЛЬКО владение, не существует, и «оно и так не проходит» —
-- правда. Тем не менее ограничение заводится, по трём причинам:
--
--   1. держатель ЧУЖОЙ и снимается законной правкой. Разреши
--      `roles_custom_name_check` точку в имени арендаторской роли (изменение
--      правдоподобное — точечные имена арендатора), и инвариант испарится, не
--      покраснев нигде;
--   2. отказ называет НЕ ТОТ предикат. Пишущий, поставивший владельца
--      арендаторской роли, читает «имя не той формы» и чинит ИМЯ — то есть
--      гонится за следствием. Хуже: он вправе «починить» его послаблением
--      проверки имени, то есть снять последнего держателя, чиня симптом;
--   3. инвариант НИКТО НЕ РЕШАЛ. Он есть совпадение двух правил о другом
--      предмете, и в схеме не назван ни одним объектом — а на него опёрся вывод
--      о меточной ветви.
--
-- Измерено, а не выведено чтением: проба снимает `roles_owner_module_name_prefix`
-- в откатываемой транзакции — то есть убирает ЗАСЛОНЯЮЩЕГО соседа, оставив один
-- факт, — и подаёт роль с владельцем на ярус аккаунта. До этой миграции строка
-- ЛОЖИТСЯ («An error is expected but got nil»). Значит своего держателя у
-- инварианта нет.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ОТДЕЛЬНОЕ ОГРАНИЧЕНИЕ, А НЕ ДОРАБОТКА `roles_definition_tier_xor`
--
-- Соблазн понятен: XOR ярусов рядом, и «дописать в него ещё условие» выглядит
-- бережливее. Отвергнуто по четырём причинам, каждая самостоятельна:
--
--   * ПРЕДМЕТ ДРУГОЙ. XOR судит КАРДИНАЛЬНОСТЬ якоря («ровно один из трёх»), и
--     0056 переписал его НАМЕРЕННО «over the tier columns only», освободив от
--     `is_system`. Вернуть туда владение значило бы молча отменить решение,
--     принятое осознанно;
--   * ДИАГНОСТИКА СХЛОПНУЛАСЬ БЫ. Два разных нарушения — «якорей два» и «роль
--     модуля на чужом ярусе» — называли бы ОДНО имя. Предмет этой миграции ровно
--     в том, что отказ называет не тот предикат; слияние воспроизвело бы этот
--     дефект намеренно;
--   * ОКНО БЕЗ ЗАЩИТЫ. Доработка — это DROP + ADD: между ними таблица остаётся
--     БЕЗ проверки кардинальности вовсе, и строка с двумя якорями в это окно
--     ложится. Отдельное ограничение такого окна не открывает by construction;
--   * ЭКОНОМИИ НЕТ. `roles_definition_tier_xor` проверено; DROP + ADD требует
--     повторного прохода по таблице ровно так же, как новое ограничение.
--
-- Генерируемый столбец отвергнут: `owner_module` — ВХОДНЫЕ данные, а не
-- производное. Вывести его из яруса нельзя в принципе — платформенные роли тоже
-- кластерные, и владелец у них пуст (это и есть их отличие).
--
-- Ключ отвергнут: составной ключ на пару «модуль + системность» потребовал бы
-- строки, существующей ради кодирования булева значения, поставил бы годность
-- роли в зависимость от ЖИВОСТИ референта — ровно та связь, которую 20260902190500
-- отвергла, выбрав `catalog_module (module)` вместо `(module, live)`, — и
-- диагностировался бы как «ключа нет», что о ярусах не говорит ничего.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПРЕДИКАТ НАПИСАН ЧЕРЕЗ `is_system`, А НЕ ЧЕРЕЗ `cluster_id IS NOT NULL`
--
-- `is_system` — GENERATED ALWAYS AS (cluster_id IS NOT NULL) STORED (0056), то
-- есть ЕДИНСТВЕННОЕ определение системности в схеме. Написать здесь
-- `cluster_id IS NOT NULL` значило бы завести ВТОРОЕ место, утверждающее «системная
-- — это кластерный якорь»: поменяйся выражение столбца, и два места разошлись бы
-- молча. Обе соседние проверки имени (`roles_custom_name_check`,
-- `roles_system_name_check`) выражены через `is_system`, а не через якорь; эта
-- к ним присоединяется, а не заводит третье написание.
--
-- ФОРМА `NOT VALID` + `VALIDATE CONSTRAINT` — взята у 20260902190500 и у
-- 0062_access_binding_target_cardinality.sql, а не выведена: `roles` каталогом не
-- является и растёт с арендаторами. `ADD CONSTRAINT … NOT VALID` берёт краткий
-- ACCESS EXCLUSIVE без прохода по таблице, `VALIDATE CONSTRAINT` перепроверяет
-- строки под более слабым SHARE UPDATE EXCLUSIVE.
--
-- ЗАЩИТА ПОСЛЕДНЕГО РУБЕЖА, как и обе проверки 20260902190500: величину проверяет
-- и применитель до вставки. Срабатывание по существу означает «мы пропустили
-- негодную строку» — наш дефект, а не ввод вызывающего; полосу оно получает всё
-- же ввода (общий текст, текст СУБД наружу не эхается), перевод в полосу дефекта
-- сервиса — предмет #1903.

-- +goose Up

-- Досмотр ДО ограничения. `VALIDATE CONSTRAINT` на нарушающих строках откажет
-- сам, но его текст назовёт только имя ограничения; оператору нужно знать, СКОЛЬКО
-- строк и чьи они. Досмотр отвечает на это раньше и своими словами.
-- +goose StatementBegin
DO $$
DECLARE
    offenders bigint;
    sample    text;
BEGIN
    SELECT count(*) INTO offenders
      FROM kacho_iam.roles
     WHERE owner_module IS NOT NULL AND NOT is_system;

    IF offenders > 0 THEN
        SELECT string_agg(format('%s (владелец %s)', id, owner_module), ', ')
          INTO sample
          FROM (SELECT id, owner_module
                  FROM kacho_iam.roles
                 WHERE owner_module IS NOT NULL AND NOT is_system
                 ORDER BY id
                 LIMIT 10) s;

        RAISE EXCEPTION
            'ярус роли модуля: строк с владельцем на НЕ кластерном ярусе % — '
            'ограничение на таких строках не создастся. Первые: %. '
            'Каждая из них даёт права по цепи областей арендатора, чего вывод о '
            'меточной ветви не предполагает: разберите их до применения',
            offenders, sample;
    END IF;
END;
$$;
-- +goose StatementEnd

ALTER TABLE kacho_iam.roles
  ADD CONSTRAINT roles_owner_module_is_cluster_tier
    CHECK (owner_module IS NULL OR is_system) NOT VALID;

ALTER TABLE kacho_iam.roles VALIDATE CONSTRAINT roles_owner_module_is_cluster_tier;

COMMENT ON CONSTRAINT roles_owner_module_is_cluster_tier ON kacho_iam.roles IS
  'Роль с владельцем-модулем стоит на кластерном ярусе. До этого ограничения инвариант '
  'держали ДВА софтверных места (пропуск не-кластерного яруса применителем и единственный '
  'писатель owner_module) и — побочно — две проверки ИМЕНИ, требования которых несовместимы. '
  'Ни одно из четырёх не про владение: первые два снимаются вторым писателем, вторые два — '
  'послаблением формы имени. Задача продукта #2020.';

-- +goose StatementBegin
DO $$
DECLARE
    owned    bigint;
    platform bigint;
    ok       boolean;
BEGIN
    SELECT count(*) FILTER (WHERE owner_module IS NOT NULL),
           count(*) FILTER (WHERE owner_module IS NULL)
      INTO owned, platform
      FROM kacho_iam.roles;

    SELECT convalidated INTO ok
      FROM pg_constraint
     WHERE conrelid = 'kacho_iam.roles'::regclass
       AND conname  = 'roles_owner_module_is_cluster_tier';

    -- Перепись печатается ВСЕГДА: «ноль ролей с владельцем» — ожидаемое
    -- состояние на день применения (владение заведено 20260902190500 без
    -- обратного заполнения), и оно обязано быть отличимо от «строк не читали».
    RAISE NOTICE
        'ярус роли модуля: ролей с владельцем %, платформенных %; ограничение проверено %',
        owned, platform, coalesce(ok::text, 'НЕТ ВОВСЕ');

    IF ok IS NOT TRUE THEN
        RAISE EXCEPTION 'ярус роли модуля: ограничение не проверено — '
            'невалидированное ограничение планировщик доказанным не считает';
    END IF;
END;
$$;
-- +goose StatementEnd

-- +goose Down
--
-- Откат возвращает состояние, в котором связь владения с ярусом держат ЧУЖИЕ
-- правила: две проверки имени, требования которых несовместимы. Инвариант при
-- этом продолжает выполняться — но его снимет первое же послабление формы имени
-- арендаторской роли, и никто не заметит. Это надо знать тому, кто откат
-- применяет.
ALTER TABLE kacho_iam.roles
  DROP CONSTRAINT roles_owner_module_is_cluster_tier;
