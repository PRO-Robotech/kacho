-- 20260903215500_ledgers_name_the_author — обе ведомости, объясняющие потерю
-- права, начинают нести АВТОРА снятия.
--
-- Задача продукта #2005.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕГО НЕ ХВАТАЛО
--
-- Ведомости отвечали на «что отобрали», «почему» и «когда»:
--
--   role_grant_orphan    (role_id, object_type, verb, source, reason, orphaned_at)
--   role_selector_prune  (role_id, rule_fp, object_type, outcome, retired_reason, pruned_at)
--
-- и не отвечали на «КТО». Для разбора «почему у меня отобрали право» это второй
-- по важности вопрос после «почему», и ответить на него было неоткуда: применение
-- отбирает права НЕОБРАТИМО, а следа автора не оставалось ни в одной строке.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ АВТОР — ИНИЦИАТОР, А НЕ УЧЁТКА ИСПОЛНИТЕЛЯ
--
-- Применение разрешает актора ПЕРВЫМ действием — до чтения манифеста и до
-- открытия транзакции (`modulecatalog.actorOf`): на пути глагола это проверенная
-- личность вызывающего, на пути старта — названный процессный актор, и
-- подставленного `system` там не бывает.
--
-- Записать сюда учётку, под которой исполнялась транзакция, значило бы ответить
-- «снял iam» на вопрос «кто снял» — то есть не ответить. Колонка называется
-- `applied_by` именно поэтому: она про того, кто ПРИМЕНИЛ, а не про того, кто
-- выполнил оператор.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ПУСТАЯ СТРОКА, А НЕ NULL И НЕ CHECK НА НЕПУСТОТУ
--
-- Строки, переселённые и вырезанные ДО этой миграции, автора не несут и понести
-- не могут: его никто не записывал, и восстановить его не из чего. Значит нужна
-- величина «этой строке автор не записан», отличимая от «автора потеряли».
--
-- Взята пустая строка, а не NULL, — по тому же доводу, что у `verb` в
-- `role_grant_orphan`: ключа на колонке нет, и пустая строка оставляет чтение
-- простым (`coalesce` не нужен ни одному читателю). Соседний `retired_reason`
-- остаётся NULL-евым и этой миграцией не трогается: там NULL уже объявлен и
-- означает своё.
--
-- CHECK на непустоту НЕ ставится, и это не послабление: он отверг бы
-- унаследованные строки, то есть потребовал бы переписать применённое. Непустоту
-- НОВЫХ строк держит писатель — он получает актора обязательным параметром, а
-- применение без проверенного актора отвергается ДО открытия транзакции. Свойство
-- утверждается пробой (`ledgers_name_the_author_integration_test.go`), а не
-- ограничением, и граница названа честно: ограничение судило бы и прошлое.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ
--
-- Не заводит индекса. Обе ведомости читаются ПО НАЧАЛУ первичного ключа
-- (`role_id`) одним вопросом на страницу; автор — колонка ответа, а не отбора, и
-- индекс под неё был бы платой за запрос, которого никто не задаёт.
--
-- Не трогает порядок роста применения: колонка добавляется с умолчанием, оба
-- оператора получают её значением параметра, и ни одна строка дополнительно не
-- читается.

-- +goose Up

ALTER TABLE kacho_iam.role_grant_orphan
  ADD COLUMN applied_by text NOT NULL DEFAULT '';

ALTER TABLE kacho_iam.role_selector_prune
  ADD COLUMN applied_by text NOT NULL DEFAULT '';

COMMENT ON COLUMN kacho_iam.role_grant_orphan.applied_by IS
  'Автор применения, снявшего эту строку: проверенная личность вызывающего на пути глагола либо названный процессный актор на пути старта. НЕ учётка, под которой исполнялась транзакция. ПУСТАЯ строка означает «строка переселена до заведения колонки», а НЕ «автора потеряли».';

COMMENT ON COLUMN kacho_iam.role_selector_prune.applied_by IS
  'Автор применения, вырезавшего этот тип из отбора правила. Та же величина и тот же источник, что у role_grant_orphan.applied_by: вопрос «кто снял» у обеих ведомостей общий — арендатор не различает, какой из проекций правила он лишился. ПУСТАЯ строка означает «строка вырезана до заведения колонки».';

-- +goose Down

ALTER TABLE kacho_iam.role_selector_prune DROP COLUMN IF EXISTS applied_by;
ALTER TABLE kacho_iam.role_grant_orphan   DROP COLUMN IF EXISTS applied_by;
