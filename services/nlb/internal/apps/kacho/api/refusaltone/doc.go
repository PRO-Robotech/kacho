// Package refusaltone держит пробы, утверждающие СОГЛАСИЕ текстов отказа между
// ресурсами nlb — то, чего проба одного ресурса утверждать не может.
//
// Тон сообщений об отказе — часть контракта (`api-conventions.md` §Error-format):
// один запрет обязан звучать одинаково у всех ресурсов, которые его формулируют,
// и обязан называть клиенту следующий шаг (core ban #18). Проба, закрепляющая
// ответ ОДНОГО ресурса, это свойство не проверяет: она зеленеет при любом
// расхождении с соседом — расхождение видно только при сравнении.
//
// Пакет намеренно лежит листом графа импортов: он импортирует use-case'ы всех
// трёх мутируемых ресурсов, а его не импортирует никто.
