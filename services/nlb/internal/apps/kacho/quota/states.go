package quota

import (
	"context"

	"github.com/PRO-Robotech/kacho/pkg/quota/quotaread"
)

// Арендаторское чтение квот — задача `PRO-Robotech/kacho#412`.
//
// ПОЧЕМУ ЭТО ЖИВЁТ В ПОЛОСЕ, А НЕ ОТДЕЛЬНЫМ USE-CASE'ОМ. Чтению нужны ровно те
// же два источника, что и полосе: местные строки учёта и владелец величин на
// промахе. Отдельный тип с теми же полями означал бы второе место, знающее, как
// связаны эти два источника, — и оно разошлось бы с первым молча, потому что
// расхождение видно только на промахе, то есть на свежем проекте.
//
// ТЕЛО ОБЩЕЕ (`quotaread.Band`) — доменного в чтении квот только то, чем этот
// владелец добирается до своих строк и каким токеном каталога зовёт соседа.

// serviceDomain — имя сервиса, называющее ИСТОЧНИК ответа в машинном признаке.
//
// ЗДЕСЬ ОНО ОТЛИЧАЕТСЯ ОТ ТОКЕНА КАТАЛОГА, и именно этот домен — причина, по
// которой у полосы два имени, а не одно: каталог видов знает этот сервис как
// `loadbalancer` (`loadbalancer.listeners`), а ответ на проводе обязан называть
// источником `nlb` — так его знает вызывающий. Свести их в одно поле значило бы
// выбрать, какое из двух утверждений сделать ложным.
const serviceDomain = "nlb"

// stateRows — переходник от транзакционного чтения этого владельца к порту общей
// полосы.
//
// Существует потому, что у nlb строки читаются ВНУТРИ read-транзакции (у части
// соседей — прямо из пула), и открытие транзакции есть частность владельца, а не
// свойство чтения квот. Переходник ничего не решает: он открывает, спрашивает и
// закрывает.
type stateRows struct{ repo Repo }

func (s stateRows) ListStates(
	ctx context.Context, carrierType, carrierID string,
) ([]quotaread.State, error) {
	rd, err := s.repo.Reader(ctx)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rd.Close() }()
	return rd.Quotas().ListStates(ctx, carrierType, carrierID)
}

// States отдаёт квоты проекта: предел, потребление и источник победившей
// величины по каждому виду домена.
//
// Полоса собирается ЗДЕСЬ, а не хранится в поле: у неё нет состояния, а её
// сборка — четыре проверки на пустоту, которые на собранном страже не могут не
// пройти. Поле означало бы вторую точку сборки и вопрос, что делать со стражем,
// чьё поле не собралось, — вопрос без хорошего ответа.
func (g *Guard) States(ctx context.Context, projectID string) ([]quotaread.State, error) {
	band, err := quotaread.NewBand(stateRows{repo: g.repo}, g.resolver, g.service, serviceDomain)
	if err != nil {
		return nil, err
	}
	return band.States(ctx, projectID)
}
