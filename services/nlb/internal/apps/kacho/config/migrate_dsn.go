package config

// migrate_dsn.go — адрес базы для ТОЧКИ НАКАТА и её собственная посадка.
//
// Дверь у конфигурации не одна, и это решение (#1650 назвал предмет, эта
// полоса его закрывает):
//
//	Load        — служба: разбор + страж посадки процесса, который СЛУЖИТ;
//	MigrateDSN  — накат:  тот же разбор + посадка, которой связан САМ НАКАТ.
//
// Разбор общий, дверей две, и у каждой названо, что она спрашивает.

import (
	"fmt"
	"strings"

	coredb "github.com/PRO-Robotech/kacho/pkg/db"
)

// MigrateDSN — строка подключения, которой точка наката (`cmd/migrator`)
// применяет цепочку миграций.
//
// # Почему не Load
//
// [Load] несёт стража посадки СЛУЖБЫ: взаимную проверку сертификата на каждом
// ребре к соседу, круг отправителей чужой личности, объявление домена величин,
// пообъектный фильтр списков, адреса слушателей. У точки наката нет НИ ОДНОГО
// из этих предметов — ни слушателя, ни соседей, ни переданной личности, — и её
// отказ по ним называет оператору не тот предмет: init-контейнер, чья работа
// `goose up`, отвечал девятью строками про plaintext-слушатель и mTLS-рёбра
// при исправной базе.
//
// Различие это к тому же было НАШЕ И НИКЕМ НЕ РЕШЁННОЕ: у шести соседей
// `Load` не валидирует вовсе (страж стоит в композиционном корне `serve`), и
// их точки наката посадку службы не наследуют. `docs/architecture/migrator-cli.md`
// перечисляет РЕШЁННЫЕ различия точек наката, и этого среди них нет.
//
// # Что накат спрашивает всё-таки — и почему именно это
//
// Ровно то, чем пользуется сам: адрес собственной базы и режим шифрования до
// неё. Соединение к базе — тот же периметр, что у службы: по нему идут пароль
// и DDL, поэтому на боевой посадке plaintext запрещён и здесь. Снять эту
// проверку заодно со всеми прочими значило бы разменять «отказ называет не тот
// предмет» на «контроль пропал», а это другой размен.
//
// Посадку приходится РАЗОБРАТЬ, а не прочитать: [Config.Mode] проглатывает
// ошибку разбора и на неизвестном значении отдаёт непроизводственный режим —
// то есть опечатка в `mode:` молча снимала бы требование шифрования. Величина,
// которая решает, применяется ли контроль, обязана быть принята явно.
//
// Пустой адрес отказом ЗДЕСЬ не становится: у отказа «адрес не задан» ОДИН
// производитель — общий пакет (`migratorcli.ResolveDSN`), и он перечисляет все
// источники приоритета. Своя редакция того же текста назвала бы одно
// подмножество, а общая — другое (#1544).
func MigrateDSN(path string) (string, error) {
	cfg, err := parse(path)
	if err != nil {
		return "", err
	}
	return cfg.MigrateDSN()
}

// MigrateDSN — тот же предикат на уже разобранной конфигурации.
//
// Имя метода то же, что у шести соседей (`cfg.MigrateDSN()`): у одного предмета
// одно имя во всём дереве, иначе следующий читатель ищет у седьмого сервиса то,
// чего там нет под привычным именем.
func (c Config) MigrateDSN() (string, error) {
	dsn := strings.TrimSpace(c.Repository.Postgres.URL)
	if dsn == "" {
		return "", nil
	}
	mode, err := ParseMode(c.ModeRaw)
	if err != nil {
		return "", err
	}
	if mode.IsProduction() {
		if terr := postgresTransportRefusal(dsn); terr != nil {
			return "", terr
		}
	}
	return dsn, nil
}

// postgresTransportRefusal — отказ по режиму шифрования соединения с
// собственной базой. ОДИН производитель текста на обе двери.
//
// Судится строка, которой вызывающий СОЕДИНЯЕТСЯ: служба — ту, что уходит в пул
// (`DSN()`), накат — ту, которой открывает `database/sql`. У nlb они совпадают
// по `sslmode` (пуловая дописывает только `pool_*`), но спрашивать надо исход,
// иначе первое же изменение сборки строки разведёт стража с соединением молча.
//
// Разбор строки подключения и перечень безопасных значений — НЕ свои: оба
// приходят из дома семантики DSN (`pkg/db`), где объявлены один раз на всё
// дерево (#1464).
func postgresTransportRefusal(dsn string) error {
	dsn = strings.TrimSpace(dsn)
	if dsn == "" || coredb.SSLModeSecure(coredb.SSLModeFromDSN(dsn)) {
		return nil
	}
	return fmt.Errorf(
		"production mode: insecure Postgres transport — repository.postgres.url sslmode must be %s "+
			"(disable/allow/prefer or unset permits a plaintext DB connection; forbidden)",
		strings.Join(coredb.SecureSSLModes(), "|"))
}
