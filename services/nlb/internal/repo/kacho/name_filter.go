package kacho

import (
	"strings"

	"github.com/PRO-Robotech/kacho/pkg/filter"
)

// NameFilter — сужение списка по имени: РАЗОБРАННЫЙ узел выражения, а не одно
// его значение.
//
// Носитель именно такой, потому что значение без оператора лжёт (#460). Пока
// поле было строкой, репозиторий не мог узнать, какое отношение у него
// спросили, и строил предикат с зашитым равенством — то есть отвечал точным
// совпадением на запрос подстроки. Строка поиска в консоли получала «ничего не
// найдено» на любой неполный ввод, и это выглядело как пустой результат, а не
// как потерянный оператор.
//
// nil — сужения нет.
type NameFilter = filter.FilterAST

// ExactName — узел «имя в точности равно». Для ВНУТРЕННИХ резолвов (проверка
// занятости имени перед созданием), где отношение выбирает не арендатор, а мы
// сами, и оно всегда равенство.
//
// Отдельная функция, а не второе поле рядом с разобранным узлом: два поля об
// одном предмете разошлись бы на первой же правке, и какое из них применится —
// решал бы порядок чтения кода.
func ExactName(name string) *NameFilter {
	if name == "" {
		return nil
	}
	return &NameFilter{Field: "name", Op: filter.OpEquals, Value: name}
}

// MatchesName — применяет узел к имени в памяти, тем же отношением, каким его
// применил бы SQL: `=` — точное совпадение, CONTAINS — подстрока.
//
// Существует ради того, чтобы у отношения был ОДИН исполнитель. Дублёр
// репозитория, сравнивающий имена своей строкой, снисходительнее продукта ровно
// в том месте, ради которого его подставляют: пока он отвечал точным
// совпадением, проба на подстрочный поиск зеленела бы и на владельце, который
// оператор потерял.
//
// nil — сужения нет, подходит любое имя.
func MatchesName(nf *NameFilter, name string) bool {
	if nf == nil {
		return true
	}
	if nf.Op == filter.OpContains {
		return strings.Contains(name, nf.Value)
	}
	return name == nf.Value
}
