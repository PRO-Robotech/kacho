package subscriptionjournal

import (
	"go/ast"
	"go/parser"
	"go/token"
	"testing"
)

// TestJournalStateCannotReadThePayload — САМОИСТЕКАЮЩАЯ проверка утверждения
// «нагрузку журнала nlb не читает никто» (задача #1452).
//
// # Что она держит
//
// Объявление журнала (`journal.go`) и записка отступления
// (`docs/engineering/architecture/08-known-divergences.md`) утверждают, что
// состояние из нагрузки НЕ собирается. Прозе следующий читатель верить не
// обязан, а прежняя редакция этого места показала цену непроверяемой прозы:
// комментарий называл потребителя нагрузки в настоящем времени спустя два
// снятия подряд (#814 — контракт, #1043 — его читатель), и на этот ложный ответ
// опирался разбор соседней задачи #1381.
//
// # Почему проверка структурная, а не текстовая
//
// Слова «читает нагрузку» стоят в самих объяснениях, поэтому проверка по
// подстроке краснела бы на собственном комментарии. Здесь судится УЗЕЛ: у
// функции `state` параметр строки объявлен БЕЗ ИМЕНИ, то есть прочитать
// нагрузку она не может by construction — не «не читает сегодня», а «не имеет
// чем».
//
// # Когда она обязана упасть — и это НЕ поломка
//
// Когда журнал nlb получит состояние (задача #1381), параметр придётся
// поименовать. Проверка покраснеет, и это её работа: вместе с параметром обязаны
// поменяться оба утверждения о нагрузке — шапка пакета и запись отступления, —
// а сама проверка снимается вместе со своим предметом. Послабление, которому
// больше нечего исключать, — находка, а не наследство.
func TestJournalStateCannotReadThePayload(t *testing.T) {
	const file = "journal.go"

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("объявление журнала %s не разобрано: %v", file, err)
	}

	var (
		funcsInspected int
		stateDecl      *ast.FuncDecl
	)
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok {
			continue
		}
		funcsInspected++
		if fn.Name.Name == "state" && fn.Recv == nil {
			stateDecl = fn
		}
	}

	// Объём осмотренного печатается всегда: «ноль находок» обязано быть отличимо
	// от «ноль прочитанного».
	t.Logf("перепись: файл %s · объявлений функций осмотрено %d · сборщик состояния найден: %t",
		file, funcsInspected, stateDecl != nil)

	if funcsInspected == 0 {
		t.Fatalf("в %s не осмотрено ни одного объявления функции — проверка беспредметна, "+
			"а не пройдена", file)
	}
	if stateDecl == nil {
		t.Fatalf("в %s нет функции state — сборщик состояния переименован или снят; "+
			"проверка утверждала бы о том, чего нет", file)
	}

	params := stateDecl.Type.Params.List
	if len(params) != 1 {
		t.Fatalf("state принимает %d параметров, ожидался ровно один (строка журнала): "+
			"форма сборщика изменилась, проверку надо пересмотреть вместе с ней", len(params))
	}
	if n := len(params[0].Names); n != 0 {
		t.Errorf(
			"%s: параметр строки журнала у state ПОИМЕНОВАН (%d имя/имён) — значит нагрузку "+
				"стало чем читать.\n"+
				"Если у журнала nlb появилось состояние (задача #1381), это ожидаемо, и вместе "+
				"с параметром обязаны поменяться ОБА утверждения о нагрузке:\n"+
				"  · шапка пакета subscriptionjournal («ЖУРНАЛ nlb СОСТОЯНИЯ НЕ НЕСЁТ»);\n"+
				"  · запись в services/nlb/docs/engineering/architecture/08-known-divergences.md\n"+
				"    («Нагрузка журнала пишется и не читается»);\n"+
				"а сама эта проверка снимается вместе со своим предметом — держать её после того, "+
				"как читатель появился, значит держать послабление без предмета",
			fset.Position(params[0].Pos()), n)
	}
}
