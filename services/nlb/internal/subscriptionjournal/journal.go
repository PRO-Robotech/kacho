// Package subscriptionjournal — объявление ЖУРНАЛА nlb для общего сервера потока
// изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы, сужение
// по правам и порядок отказов принадлежат общему серверу и владельцу не выдаются.
//
// # СОСТОЯНИЕ ЕСТЬ У ДВУХ ВИДОВ ИЗ ТРЁХ, и это сказано вслух
//
// У `nlb_listener` и `nlb_target_group` событие несёт ПОЛНОЕ состояние предмета —
// тот же самый, что отдаёт `Get`, и с метками; у группы вдобавок с НАБОРОМ ЦЕЛЕЙ,
// каждая со своим lifecycle-состоянием. У `nlb_load_balancer` состояния НЕТ: его
// нагрузка остаётся намеренно минимальным снимком (`kachorepo.LifecyclePayload`),
// и подписчик читает предмет отдельным вызовом по идентификатору.
//
// Различие не дрейф, а СЛЕДСТВИЕ СЧЁТА, приведённого ниже: у двух обогащённых
// видов ВСЕ точки эмиссии на Go, и публичная проекция собирается из данных,
// которые есть у пишущей транзакции. У балансировщика это сегодня не так — две
// его точки живут в SQL, и одна из них (триггер пересчёта статуса) пишет свою
// нагрузку сама.
//
// Обогащение обязано быть ВСЁ-ИЛИ-НИЧЕГО В ПРЕДЕЛАХ ВИДА: контракт разрешает
// читать непустое состояние как ПОЛНОЕ, поэтому один эмиттер, отдающий частичный
// снимок, делает ложным весь вид — и делает тихо. Для слушателя это держит разбор
// пакета эмиттеров (`TestEveryEmissionOfAStatefulKindBuildsTheSamePayload`), а не
// внимание.
//
// # Полноту объявляет КОНВЕРТ, а не удача разбора
//
// Журнал не чистится (`RetainsEverything` ниже), а подписчик вправе открыть поток
// с начала — значит строки ПРЕЖНЕЙ, минимальной формы доезжают до сборщика и
// сегодня. Отличить их надо однозначно, и удача разбора этого не даёт:
// `encoding/json` сопоставляет имена без учёта регистра, поэтому `id`, `name`,
// `protocol`, `port` и `status` минимального снимка попали бы в поля записи, а
// проект, родитель, отметка создания и МЕТКИ — нет. Вышел бы предмет, который
// разобрался, перенёсся в контракт и оказался ложным.
//
// Поэтому полное состояние лежит под собственным ключом
// (`kachorepo.PayloadKeyState`), а его отсутствие доезжает причиной
// `NOT_PRODUCED` — то есть подписчик отличает свойство строки от сбоя сборки
// МАШИННО, не читая ни строчки документации.
//
// # Что это ЗАКРЫЛО и что НЕТ
//
// Закрыло: клиентский отбор по меткам для видов `nlb_listener` и
// `nlb_target_group` — источник у них теперь есть. У группы закрыт и второй
// вопрос: набор её целей приходит С СОСТОЯНИЕМ, поэтому сливающаяся цель
// отличима от обычной без второго чтения.
//
// Не закрыло: для `nlb_load_balancer` такой отбор по-прежнему НЕИСПОЛНИМ, и это
// сказано и здесь, и в таблице владельцев клиентской страницы подписки. Ценность
// потока для него не исчезает: подписчик узнаёт вид, идентификатор, якорь проекта
// и род изменения — то есть ЧТО перечитать и когда. Именно это снимает постоянный
// опрос списков.
//
// # ЦЕНА ОБОГАЩЕНИЯ ИЗМЕРЕНА, а не оценена на глаз
//
// ЕДИНИЦА СЧЁТА — ТОЧКА ЭМИССИИ: оператор, записывающий строку журнала. Не
// «путь» и не «место, где удобно»: у переезда путь один, а точек две, и
// обогащать надо обе.
//
// У `nlb_listener` их ПЯТЬ и все на Go — создание, правка, пометка снятия, само
// снятие и каскадный переезд, который эмитит ПАКЕТ БАЛАНСИРОВЩИКА (#1549); точек
// SQL у вида НОЛЬ (таблица плоская, `labels` колонкой). Поэтому вид обогащён
// целиком и без миграции.
//
// Пятая точка — довод в пользу того, чтобы строитель нагрузки вида жил в
// repo-leaf (`kachorepo.ListenerStatePayload`), а не в пакете слушателя: строитель,
// спрятанный в одном пакете, второму недоступен, и второй завёл бы свой — вторую
// форму нагрузки того же вида.
//
// У `nlb_load_balancer` точек ДЕВЯТЬ, и две из них — SQL:
//
//   - СЕМЬ точек Go, и лежат они в ДВУХ пакетах use-case. Пять — в собственном
//     (создание · правка · удаление · переезд, у которого их две). Ещё ДВЕ — в
//     пакете СЛУШАТЕЛЯ: создание и снятие слушателя эмитят правку своего
//     балансировщика. Запись у первых пяти на руках, обогащаются прямо — кроме
//     переезда: он отдаёт только идентификаторы (`lbMovedPayload`), то есть
//     заведомо частичен уже сегодня. У двух последних записи балансировщика
//     ПОСЛЕ мутации на руках нет: строку читали до вставки слушателя, а триггер
//     пересчёта статуса срабатывает между чтением и эмиссией;
//   - пересчёт состояния — ТРИГГЕР БАЗЫ. Функция ОДНА (`lb_status_recompute`),
//     переопределённая чередой миграций и подвешенная к нескольким триггерам;
//     пишет `{id, status, recomputed}`. Она живёт в ПРИМЕНЁННЫХ миграциях,
//     править их нельзя (ban #5) — значит нужна НОВАЯ миграция, переопределяющая
//     тело;
//   - сборщик свободных адресов (`free_ip_runner`) — свой INSERT, род `DELETED`.
//     Состояния у снятия не бывает by construction, поэтому обогащения он не
//     требует и в трудную часть не входит.
//
// Предикаты, чтобы это перемерить, а не поверить:
//
//	git grep -n OutboxResourceLoadBalancer -- 'services/nlb/internal/apps/**/*.go' | grep -v _test
//	grep -rn "'nlb_load_balancer'" services/nlb/internal/migrations/*.sql \
//	  services/nlb/internal/apps/kacho/jobs/*.go
//
// Второй предикат даёт БОЛЬШЕ строк, чем точек: имя функции триггера повторяется
// в каждой миграции, которая её переопределяла, и в разделе отката тоже. Живая —
// последняя применённая; считать надо ФУНКЦИИ, а не совпадения.
//
// # ЗДЕСЬ СТОЯЛА ОГОВОРКА «слушателя эти предикаты НЕ находят» — предмета у неё БОЛЬШЕ НЕТ
//
// Она была верна и называла причину: точки эмиссии слушателя звали собственную
// константу пакета use-case, а не общую, поэтому перепись по канону отвечала по
// нему НОЛЬ при четырёх точках. Копия снята (#1550), и сегодня предикат выше
// находит ВСЕ три вида.
//
// Оговорка сохранена разбором, а не удалена, потому что тем же способом были
// ЗАНИЖЕНЫ числа этой самой шапки: у балансировщика она называла пять точек Go
// при семи — две невидимые лежали в пакете слушателя и звали копию. То есть
// слепая зона переписи испортила не чужой отчёт, а собственную оценку цены.
//
// Держит это разбор дерева use-case'ов, а не внимание:
// `TestEveryEmissionNamesTheKindByTheCanonicalConstant` судит УЗЕЛ аргумента
// вида и краснеет на следующей копии.
//
// # ТРУДНАЯ ЧАСТЬ ОСТАВШЕГОСЯ — ГРУППА ЦЕЛЕЙ, а не язык триггера
//
// Прежняя редакция называла трудной частью триггер: «собрать полный предмет в
// PL/pgSQL значит завести ВТОРУЮ проекцию ресурса — на другом языке, рядом с
// первой, и расходиться они будут молча».
//
// **Опровергнуто дважды, и оба раза деревом, а не рассуждением:**
//
//  1. проекцию в PL/pgSQL собирать НЕ НАДО. Журнал реестра тоже наполняется
//     триггером — и состояние ПРОИЗВОДИТ: его триггер пишет `to_jsonb(v_row)`,
//     то есть строку целиком, а проекция в контракт случается ОДИН раз, на Go
//     (`services/registry/internal/migrations/20260828154000_registry_resource_journal.sql`,
//     посажено той же неделей). Вторую проекцию заводит только тот, кто собирает
//     нагрузку `jsonb_build_object`-ом по полям;
//  2. у балансировщика строки для этого ДОСТАТОЧНО: `kacho_nlb.load_balancers` —
//     одна плоская таблица, и `labels` лежит колонкой на ней. Стороны разбора у
//     nlb уже есть — `kachorepo.LoadBalancerRecord` (встраивает доменную запись)
//     и перенос `dto`/`type2pb`, то есть ровно те две части, которыми собирает
//     состояние слушатель здесь и журнал vpc у себя.
//
// Значит доля триггера — новая миграция, меняющая нагрузку на `to_jsonb` строки:
// обычная работа с известным в дереве образцом.
//
// **ТРУДНАЯ ЧАСТЬ БЫЛА — ГРУППА ЦЕЛЕЙ, и она ЗАКРЫТА (#1551).** Публичная проекция
// группы строится не из её строки, а из набора целей С СОСТОЯНИЕМ
// (`TargetStates`), поэтому одной строки для неё недостаточно ни при каком
// кодировании, а её джоба слива целей писала строку журнала своим запросом.
//
// Вопрос «где собирать набор» решён так: набор собирает ТА ЖЕ транзакция, что
// мутирует группу, и собирает его ПОСЛЕ мутации — иначе снятая цель пришла бы
// живой. Пути записи (`Update`, `MoveProject`) дочитывают цели тем же
// разложением, что и чтение; добавление и снятие целей перечитывают группу в
// своей же транзакции; джоба слива перестала эмитить строку своим оператором —
// её порт отдаёт ЧТО СНЯЛОСЬ, а строку собирает Go тем же строителем, что и
// остальные шесть точек. Второй проекции ресурса в SQL не заведено ни одной.
//
// Числа по группе, перемеренные тем же предикатом ПОСЛЕ снятия копии слова вида:
// точек Go СЕМЬ (создание · правка · удаление · переезд, у которого их две ·
// добавление целей · снятие целей) плюс восьмая — джоба слива, ставшая точкой Go
// вместо запроса. Прежняя редакция называла шесть — она считала ПУТИ, а не точки,
// тогда как единицей счёта в этой же шапке объявлена точка эмиссии.
//
// **ЧТО ОСТАЛОСЬ — БАЛАНСИРОВЩИК, и трудная часть у него ДРУГАЯ.** Она не в
// количестве точек, а в том, что одна из них — ТРИГГЕР БАЗЫ, и у неё свой язык.
// `to_jsonb(строки)` даёт ключи ИМЁН КОЛОНОК, а нагрузка семи точек Go — имён
// полей Go: две формы одного конверта у одного вида, и расходиться они будут
// молча. Образец реестра эту цену называет прямо и платит её тем, что у него
// эмиттер ОДИН — триггер; здесь эмиттеров восемь, и семь из них на Go.
//
// Исходов у этого два, и выбирать надо ОСОЗНАННО: либо обе стороны приводятся к
// одной форме (тегами записи под имена колонок) и расхождение держится сквозной
// пробой, либо триггер перестаёт эмитить строку вовсе, а её эмитят пути Go,
// которые его и вызывают, — перечитав строку ПОСЛЕ пересчёта, в своей же
// транзакции. Второй путь требует новой миграции (применённые править нельзя,
// ban #5) и двух НОВЫХ точек эмиссии в пакете слушателя: пометка снятия и
// перепривязка сегодня меняют статус балансировщика, не объявляя этого ничем,
// кроме строки самого триггера.
//
// # ЖУРНАЛОВ БЕЗ СОСТОЯНИЯ В ДЕРЕВЕ ОСТАЁТСЯ ОДИН, И ЭТО НЕ ЭТОТ
//
// До обогащения состояния не производили ДВА журнала из пяти — этот и журнал
// хранилища. Причины были РАЗНЫЕ, и путать их нельзя: там публичная проекция всех
// трёх видов выводится ЧЕРЕЗ таблицы, поэтому строки не хватает ни одному виду;
// здесь строки не хватало одному виду из трёх — и этот вид обогащён.
//
// Перепись печатает гейт `internal/repohygiene`
// `TestSubscriptionOwnerPageSaysWhatItsJournalDoes` — он же держит согласие этого
// свойства с тем, что о владельце обещает клиентская страница подписки. Гейт
// судит владельца ЦЕЛИКОМ («собирает состояние или нет»), поэтому различие по
// видам внутри владельца он не видит и видеть не обязан: его предмет — не солгала
// ли страница о владельце. Что состояние есть у одного вида из трёх, страница
// говорит своей строкой.
package subscriptionjournal

import (
	"fmt"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/anypb"

	lbv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/loadbalancer/v1"
	subscriptionv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/subscription"
	"github.com/PRO-Robotech/kacho/pkg/authz"
	"github.com/PRO-Robotech/kacho/pkg/subscription"
	"github.com/PRO-Robotech/kacho/services/nlb/internal/authzfilter"
	"github.com/PRO-Robotech/kacho/services/nlb/internal/dto"
	_ "github.com/PRO-Robotech/kacho/services/nlb/internal/dto/type2pb" // регистрация трансферов
	kachorepo "github.com/PRO-Robotech/kacho/services/nlb/internal/repo/kacho"
)

const (
	// Table — таблица журнала, квалифицированная схемой.
	Table = "kacho_nlb.nlb_outbox"

	// Channel — канал пробуждения.
	//
	// Он НЕ выводится из имени таблицы, и nlb — ровно тот случай, ради которого
	// общая форма держит его отдельным полем: таблица здесь схемо-квалифицирована
	// (`kacho_nlb.nlb_outbox`), а канал триггера — нет (`pg_notify('nlb_outbox', …)`,
	// миграция 0001). Вывод одного из другого работал бы у большинства владельцев
	// и молча ошибался у этого.
	Channel = "nlb_outbox"
)

// Journal — объявление журнала nlb.
func Journal() subscription.Journal {
	return subscription.Journal{
		Channel: Channel,
		Storage: subscription.Storage{
			Table:          Table,
			PositionColumn: "sequence_no",
			// Имена колонок у nlb СВОИ: вид предмета зовётся `resource_type`, а
			// род изменения — `action`, тогда как у соседних журналов это
			// `resource_kind` и `event_type`. Разнобой форм хранения дефектом не
			// является: единой объявлена форма ПОДПИСКИ, а не форма журнала, и
			// ровно поэтому имена стоят здесь значениями, а не выводятся из
			// «стандартной схемы», которой нет.
			KindColumn:    "resource_type",
			IDColumn:      "resource_id",
			ChangeColumn:  "action",
			PayloadColumn: "payload",
			ProjectColumn: "project_id",
			// Якорь проекта у nlb лежит колонкой С БАЗОВОЙ СХЕМЫ — это
			// единственный ресурсный журнал дерева, у которого он был изначально.
			// Значит ось отбирается запросом, по частичному индексу
			// `nlb_outbox_project_idx (project_id, sequence_no) WHERE project_id <> ''`.
			Project: subscription.ProjectInColumn,
			// Журнал НЕ чистится: снятия строк у него нет ни на одном пути
			// (предикат — `git grep -in 'DELETE FROM kacho_nlb.nlb_outbox'` по
			// не-тестовому дереву даёт пусто). Заведётся чистка — эта величина
			// обязана поменяться вместе с ней.
			Retention: subscription.RetainsEverything,
		},
		Mapping: subscription.Mapping{
			// Словарь видов закрыт в обе стороны.
			//
			// СЛЕВА — слово ХРАНИЛИЩА (что лежит в колонке `resource_type`),
			// СПРАВА — то, что едет клиенту. Клиенту едет ТИП ОБЪЕКТА: написание
			// вида одно на всё дерево, и берётся оно у ПРОИЗВОДИТЕЛЯ
			// (`authzfilter`), а не выписывается.
			//
			// ВНИМАНИЕ на балансировщике: слово журнала и тип модели прав здесь
			// РАЗНЫЕ — `nlb_load_balancer` в таблице против
			// `nlb_network_load_balancer` в модели. Совпадение остальных двух пар
			// делает это различие невидимым на глаз, и оно несёт СРАЗУ ДВА
			// следствия: вид, унаследовавший чужой тип, спрашивал бы модель не о
			// том объекте, оставаясь «зелёным», — и он же уехал бы клиенту вторым
			// написанием предмета, которого нет больше нигде.
			Kinds: map[string]subscription.Kind{
				kachorepo.OutboxResourceLoadBalancer: {
					ObjectType: authzfilter.ResourceTypeLoadBalancer,
					Action:     authzfilter.ActionLoadBalancerList,
				},
				kachorepo.OutboxResourceListener: {
					ObjectType: authzfilter.ResourceTypeListener,
					Action:     authzfilter.ActionListenerList,
				},
				kachorepo.OutboxResourceTargetGroup: {
					ObjectType: authzfilter.ResourceTypeTargetGroup,
					Action:     authzfilter.ActionTargetGroupList,
				},
			},
			// Словарь родов изменения — все слова, разрешённые ограничением базы
			// (`CHECK (action IN (...))`, миграция 0001). Слово вне словаря делает
			// строку НЕДОСТАВЛЯЕМОЙ, и потеря эта тихая, поэтому перечень взят у
			// ограничения, а не у сегодняшних эмиттеров.
			//
			// Две записи требуют объяснения, иначе их снимут как лишние:
			//
			//   MOVED — переезд между проектами. Отдаётся как правка: подписчик
			//   перечитывает предмет и видит новый проект.
			//
			//   Парного UPDATED у него НЕ ВСЕГДА есть, и здесь стояло обратное.
			//   Балансировщик и целевая группа шлют оба рода подряд — исторически,
			//   ради потребителей, отбиравших по роду; подписчик получает правку
			//   дважды, повтор идемпотентен. А строки СЛУШАТЕЛЕЙ, которые
			//   балансировщик эмитит на своём переезде каскадом (#1549), приходят
			//   ОДНИМ MOVED: подписка сужается по видам, проекту и идентификаторам,
			//   но НЕ по роду изменения, поэтому второй род не добавил бы
			//   получателей — только объём журнала.
			//
			//   Отсюда требование к словарю, а не к эмиттерам: MOVED обязан стоять
			//   здесь сам по себе. Слово вне словаря делает строку НЕДОСТАВЛЯЕМОЙ, и
			//   потеря эта тихая.
			//
			//   FAILED — производителя в дереве СЕГОДНЯ НЕТ (единственный источник
			//   снят миграцией 0028). Запись оставлена не «на будущее», а ради
			//   ИСТОРИЧЕСКИХ строк долгоживущей базы: без неё они стали бы
			//   недоставляемыми и на каждом догоне писали бы в журнал процесса
			//   расхождение, которого нет. Появится новый производитель — он
			//   попадёт в уже объявленный род, а не заведёт свой.
			Changes: map[string]subscriptionv1.SubscriptionEvent_Change{
				kachorepo.OutboxActionCreated: subscriptionv1.SubscriptionEvent_CREATED,
				kachorepo.OutboxActionUpdated: subscriptionv1.SubscriptionEvent_UPDATED,
				kachorepo.OutboxActionDeleted: subscriptionv1.SubscriptionEvent_DELETED,
				kachorepo.OutboxActionMoved:   subscriptionv1.SubscriptionEvent_UPDATED,
				kachorepo.OutboxActionFailed:  subscriptionv1.SubscriptionEvent_UPDATED,
			},
			State: state,
		},
	}
}

// ProjectGate — страж оси `project_id`.
//
// Форма отказа берётся у производителя форм скрытия, а не сочиняется: она обязана
// быть неотличима от промаха владельца проектов, иначе подписка становится
// способом узнать существование чужого проекта.
func ProjectGate() (subscription.ProjectGate, error) {
	const projectObjectType = "project"
	form, ok := authz.OwnerNotFoundFormat(projectObjectType)
	if !ok {
		return subscription.ProjectGate{}, fmt.Errorf(
			"subscriptionjournal: у типа %q нет формы отсутствия у производителя (pkg/authz): "+
				"страж оси project_id отвечал бы текстом, отличимым от промаха владельца, "+
				"то есть выдавал бы существование чужого проекта", projectObjectType)
	}
	return subscription.ProjectGate{
		ObjectType:     projectObjectType,
		Action:         "iam.projects.get",
		Relations:      []string{"v_get"},
		NotFoundFormat: form,
	}, nil
}

// state — состояние предмета события.
//
// # Состояние ЕСТЬ у слушателя и группы, НЕТ у балансировщика
//
// Решение принадлежит РОДУ ПРЕДМЕТА, а не журналу целиком, поэтому и объявлено
// оно построчно. У `nlb_listener` и `nlb_target_group` все точки эмиссии на Go, и
// пишущая транзакция располагает всем, из чего собирается публичная проекция: у
// слушателя это его собственная плоская строка, у группы — строка ПЛЮС набор
// целей, дочитанный в той же транзакции. У балансировщика это сегодня не так
// (см. шапку пакета), и его нагрузка остаётся минимальным снимком.
//
// # Полноту объявляет КОНВЕРТ, а не удача разбора
//
// Журнал не чистится, а подписчик вправе открыть поток с начала — значит строки
// ПРЕЖНЕЙ формы доезжают сюда и сегодня. Разбор их молча не отвергнет:
// `encoding/json` сопоставляет имена без учёта регистра, поэтому `id`, `name`,
// `protocol`, `port` и `status` минимального снимка попали бы в поля записи, а
// проект, родитель, отметка создания и МЕТКИ — нет. Вышел бы предмет, который
// разобрался, перенёсся в контракт и оказался ложным: слушатель без проекта и без
// меток. Поэтому «состояние есть» — наблюдаемое свойство строки
// (`kachorepo.PayloadKeyState`), а не вывод из того, что разбор не отказал.
//
// # Причины отсутствия РАЗЛИЧАЮТСЯ, и это несущее
//
// [subscription.StateNotProduced] означает «попытки не было»: чужой вид, снятие
// предмета, строка прежней формы. [subscription.StateAbsenceUnnamed] с ошибкой
// означает «состояние есть, собрать не удалось». Действия у двух причин
// противоположны — на сбой разумно перечитать событие, на свойство журнала разумно
// сразу идти за предметом по идентификатору, — и неразличимые причины заставляют
// клиента выбрать неверное.
//
// # Перенос идёт ТЕМ ЖЕ трансфером, каким отвечает чтение
//
// Своего второго отображения записи в контракт здесь нет намеренно: оно
// разошлось бы с первым молча, и подписчик получал бы слушателя, отличного от
// того, что отдаёт `Get`.
func state(r subscription.Row) (*anypb.Any, subscription.StateAbsence, error) {
	if r.Change == kachorepo.OutboxActionDeleted {
		// Предмета больше нет: собирать было нечего, попытки не было. Ошибка здесь
		// звала бы подписчика перечитать снятый предмет. Проверка стоит ДО разбора
		// вида: у снятия любого вида состояния не бывает by construction.
		return nil, subscription.StateNotProduced, nil
	}

	switch r.Kind {
	case kachorepo.OutboxResourceListener:
		return stateOf(r, kachorepo.ListenerStateFromPayload, func(rec kachorepo.ListenerRecord) (*lbv1.Listener, error) {
			var pb *lbv1.Listener
			return pb, dto.Transfer(dto.FromTo(rec, &pb))
		})
	case kachorepo.OutboxResourceTargetGroup:
		return stateOf(r, kachorepo.TargetGroupStateFromPayload, func(rec kachorepo.TargetGroupRecord) (*lbv1.TargetGroup, error) {
			var pb *lbv1.TargetGroup
			return pb, dto.Transfer(dto.FromTo(rec, &pb))
		})
	default:
		// `nlb_load_balancer` — единственный вид без состояния, и это сказано
		// машинно, а не только прозой: подписчик получает `NOT_PRODUCED` и идёт за
		// предметом по идентификатору.
		return nil, subscription.StateNotProduced, nil
	}
}

// stateOf — общая полоса сборки состояния: разбор конверта · перенос записи в
// контракт · упаковка.
//
// Полосой она сделана не ради краткости, а чтобы три её отказа классифицировались
// у всех видов ОДИНАКОВО. Причины отсутствия различаются, и различие несущее:
// [subscription.StateNotProduced] означает «попытки не было» (строка прежней
// формы), [subscription.StateAbsenceUnnamed] с ошибкой — «состояние есть,
// собрать не удалось». Действия у двух причин противоположны, и повторённая
// вручную у каждого вида полоса разошлась бы по ним молча.
func stateOf[R any, P proto.Message](
	r subscription.Row,
	parse func([]byte) (*R, error),
	toPb func(R) (P, error),
) (*anypb.Any, subscription.StateAbsence, error) {
	rec, err := parse(r.Payload)
	if err != nil {
		return nil, subscription.StateAbsenceUnnamed,
			fmt.Errorf("разбор нагрузки журнала (%s %s): %w", r.Kind, r.ID, err)
	}
	if rec == nil {
		// Строка прежней, минимальной формы. Это не сбой: состояние в ней не
		// производилось.
		return nil, subscription.StateNotProduced, nil
	}
	pb, err := toPb(*rec)
	if err != nil {
		return nil, subscription.StateAbsenceUnnamed,
			fmt.Errorf("перенос записи в контракт (%s %s): %w", r.Kind, r.ID, err)
	}
	packed, err := anypb.New(pb)
	if err != nil {
		return nil, subscription.StateAbsenceUnnamed,
			fmt.Errorf("упаковка состояния (%s %s): %w", r.Kind, r.ID, err)
	}
	return packed, subscription.StateAbsenceUnnamed, nil
}
