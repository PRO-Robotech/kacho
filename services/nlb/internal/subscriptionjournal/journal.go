// Package subscriptionjournal — объявление ЖУРНАЛА nlb для общего сервера потока
// изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы, сужение
// по правам и порядок отказов принадлежат общему серверу и владельцу не выдаются.
//
// # СОСТОЯНИЕ ЕСТЬ У ВСЕХ ТРЁХ ВИДОВ
//
// Событие несёт ПОЛНОЕ состояние предмета — тот же самый, что отдаёт `Get`, и с
// метками: `kacho.cloud.loadbalancer.v1.NetworkLoadBalancer` у балансировщика,
// `Listener` у слушателя, `TargetGroup` у группы, причём у группы — с НАБОРОМ
// ЦЕЛЕЙ, каждая со своим lifecycle-состоянием. Клиентский отбор по меткам
// исполним у всех трёх.
//
// Состояния нет у СНЯТИЯ, и это by construction: предмета больше нет, собирать
// нечего, попытки не было. Подписчик получает `NOT_PRODUCED` — то есть «иди за
// предметом», а не «перечитай событие».
//
// Обогащение обязано быть ВСЁ-ИЛИ-НИЧЕГО В ПРЕДЕЛАХ ВИДА: контракт разрешает
// читать непустое состояние как ПОЛНОЕ, поэтому один эмиттер, отдающий частичный
// снимок, делает ложным весь вид — и делает тихо. Держит это разбор пакетов
// эмиттеров (`TestEveryEmissionOfAStatefulKindBuildsTheSamePayload`), а не
// внимание.
//
// # Полноту объявляет КОНВЕРТ, а не удача разбора
//
// Строки ПРЕЖНЕЙ, минимальной формы доезжают до сборщика и сегодня: окно
// удержания (`RetainsFromEarliestRow` ниже) ограничивает ВОЗРАСТ строки, а не её
// форму, — внутри окна лежат строки всех форм, писавшихся в этом окне, и
// следующая смена формы заведёт их снова. Отличить их надо однозначно, и удача
// разбора этого не даёт:
// `encoding/json` сопоставляет имена без учёта регистра, поэтому `id`, `name`,
// `protocol`, `port` и `status` минимального снимка попали бы в поля записи, а
// проект, родитель, отметка создания и МЕТКИ — нет. Вышел бы предмет, который
// разобрался, перенёсся в контракт и оказался ложным.
//
// Поэтому полное состояние лежит под собственным ключом
// (`kachorepo.PayloadKeyState`), а его отсутствие доезжает причиной
// `NOT_PRODUCED` — то есть подписчик отличает свойство строки от сбоя сборки
// МАШИННО, не читая ни строчки документации.
//
// # У БАЛАНСИРОВЩИКА ДВА ПРОИЗВОДИТЕЛЯ СТРОКИ, И ФОРМА У НИХ ОДНА
//
// Это несущее решение вида, и оно принято осознанно (#1551). Точек эмиссии у него
// ДЕВЯТЬ, и состояние обязаны нести ВОСЕМЬ — девятая эмитит СНЯТИЕ, у которого
// состояния не бывает by construction (сборщик свободных адресов, свой оператор
// на Go; о нём — ниже, в разделе про единицу счёта). Эти восемь:
//
//   - СЕМЬ на Go, в ДВУХ пакетах use-case. Пять — в собственном (создание ·
//     правка · снятие · переезд, у которого их две). Ещё ДВЕ — в пакете
//     СЛУШАТЕЛЯ: создание и снятие слушателя объявляют правку своего
//     балансировщика, и запись родителя они ЧИТАЮТ ЗАНОВО после мутации, потому
//     что триггер пересчёта статуса срабатывает внутри самого оператора (разбор —
//     `services/nlb/internal/apps/kacho/api/listener/helpers.go`);
//   - ВОСЬМАЯ — ТРИГГЕР БАЗЫ (`lb_status_recompute`), пересчёт статуса. Он тоже
//     пишет ПОЛНОЕ состояние, и на своём языке. Строку журнала он выбирает ИЗ
//     ТОГО, ЧТО ВЕРНУЛ его CAS, поэтому «событие есть ⟺ пересчёт применился»
//     держится построением, а не признаком.
//
// Форма на проводе принята ОДНА — форма ТРИГГЕРА: `to_jsonb(строки)`, ключи имён
// КОЛОНОК. Сторона Go приведена к ней типом `kachorepo.LoadBalancerJournalRow`,
// чьи теги суть имена этих колонок; вторую проекцию ресурса это не заводит —
// проекция в контракт по-прежнему одна и общая с чтением (`dto/type2pb`).
//
// **Почему форма ТРИГГЕРА, а не форма Go.** Имя колонки устойчивее: молчаливый
// рефактор Go его не трогает, а авторитет у него один — схема. И это единственная
// из двух форм, которая не может быть собрана «по полям»: `to_jsonb` ничего не
// выбирает, поэтому вторая проекция ресурса на языке SQL не заводится вовсе.
//
// **Почему нельзя было обойтись тегами на самой записи** — измерено, а не
// предположено: `Labels` записи есть `dict.HDict`, чей JSON — МАССИВ ПАР, тогда
// как `to_jsonb(labels)` даёт ОБЪЕКТ. Запись с тегами колонок разобрала бы строку
// триггера всюду, кроме меток, — то есть ровно там, ради чего обогащение и
// делается.
//
// # РАССМОТРЕН И ОТВЕРГНУТ обратный исход: триггер перестаёт эмитить
//
// Второй исход был назван честно: снять эмиссию из триггера новой миграцией и
// объявлять правку из тех путей Go, которые его вызывают, перечитав строку после
// пересчёта. Он отвергнут, и вот чем.
//
//   - ЦЕНА ОШИБКИ РАЗНАЯ. Здесь худшее — состояние отсутствует, и подписчик
//     получает честное `NOT_PRODUCED`: он идёт за предметом. Там худшее — СОБЫТИЯ
//     НЕТ ВОВСЕ: подписчик не узнаёт, что надо перечитать, и держит устаревшее
//     состояние сколько угодно долго, не имея ни одного наблюдаемого признака.
//   - ИНВАРИАНТ ПЕРЕЕЗЖАЕТ ИЗ БАЗЫ В СОГЛАШЕНИЕ. «Статус пересчитан ⇒ событие
//     есть» держится сегодня оператором базы, атомарно с самой записью статуса.
//     Пересчёт вызывает ЛЮБАЯ запись в `listeners` — вставка, правка `status`
//     либо `default_target_group_id`, снятие; сегодня один из этих путей (правка
//     привязки слушателя) о балансировщике не объявляет ничего. Значит это не
//     «две новые точки», а обязанность каждого следующего автора помнить.
//   - ОТКАТ. Правка формы нагрузки откатывается новой миграцией, и откат
//     деградирует к сегодняшнему `NOT_PRODUCED` — прежние строки от этого
//     недостоверными не становятся, конверт их различает. Снятие эмиссии
//     откатывается тем же способом, но в окне между выкаткой миграции и выкаткой
//     кода события ТЕРЯЮТСЯ — в одном порядке выкатки или в другом.
//
// Что стоило принятое решение, сказано тут же: ключи двух видов конверта в
// дереве теперь разные (у слушателя и группы — имена полей Go, у балансировщика —
// имена колонок), и это надо знать, читая нагрузку глазами.
//
// # ЧЕМ ДЕРЖИТСЯ СОГЛАСИЕ ДВУХ ФОРМ
//
//   - `TestJournalPayloadSpeaksTheColumnVocabulary` (`repo/kacho/pg`) — словарь
//     провода равен списку колонок, которым репозиторий ЧИТАЕТ строку. Дёшев,
//     базы не требует, сходится в обе стороны;
//   - `TestLoadBalancerStateIsTheSameFromTheTriggerAndFromGo` — сквозная проба над
//     НАСТОЯЩЕЙ схемой: заставляет триггер сработать настоящим оператором и
//     сверяет обе нагрузки на ОДНОЙ строке, с третьим предметом сравнения — тем,
//     что отдаёт чтение. Пара без третьего зеленела бы на двух одинаково неверных
//     формах.
//
// Гейта по ТЕКСТУ миграций здесь нет и быть не может: живое тело функции есть
// последнее из череды переопределений, а прежние лежат в ПРИМЕНЁННЫХ миграциях,
// править которые нельзя (ban #5), — текстовая проверка краснела бы на
// собственной истории. Живое тело знает только база.
//
// # ЕДИНИЦА СЧЁТА — ТОЧКА ЭМИССИИ, а не «путь»
//
// Оператор, записывающий строку журнала. У переезда путь один, а точек две, и
// обогащать надо обе. Перепись по видам печатает разбор эмиттеров; предикаты,
// чтобы перемерить её, а не поверить:
//
//	git grep -n OutboxResourceLoadBalancer -- 'services/nlb/internal/apps/**/*.go' | grep -v _test
//	grep -rn "'nlb_load_balancer'" services/nlb/internal/migrations/*.sql \
//	  services/nlb/internal/apps/kacho/jobs/*.go
//
// Второй предикат даёт БОЛЬШЕ строк, чем точек: имя функции триггера повторяется
// в каждой миграции, которая её переопределяла, и в разделе отката тоже. Живая —
// последняя применённая; считать надо ФУНКЦИИ, а не совпадения. Он же находит
// сборщик свободных адресов (`free_ip_runner`) — тот пишет свой INSERT рода
// `DELETED`, и состояния у снятия не бывает by construction.
//
// # ЗДЕСЬ СТОЯЛА ОГОВОРКА «слушателя эти предикаты НЕ находят» — предмета у неё БОЛЬШЕ НЕТ
//
// Она была верна и называла причину: точки эмиссии слушателя звали собственную
// константу пакета use-case, а не общую, поэтому перепись по канону отвечала по
// нему НОЛЬ при четырёх точках. Копия снята (#1550), и сегодня предикат выше
// находит ВСЕ три вида.
//
// Оговорка сохранена разбором, а не удалена, потому что тем же способом были
// ЗАНИЖЕНЫ числа этой самой шапки: у балансировщика она называла пять точек Go
// при семи — две невидимые лежали в пакете слушателя и звали копию. То есть
// слепая зона переписи испортила не чужой отчёт, а собственную оценку цены.
//
// Держит это разбор дерева use-case'ов, а не внимание:
// `TestEveryEmissionNamesTheKindByTheCanonicalConstant` судит УЗЕЛ аргумента
// вида и краснеет на следующей копии.
//
// # ЖУРНАЛОВ, НЕ ПРОИЗВОДЯЩИХ СОСТОЯНИЕ ВОВСЕ, В ДЕРЕВЕ НЕ ОСТАЛОСЬ
//
// Здесь стояло «журналов без состояния остаётся один, и это не этот» — и это
// было неверно уже на момент записи, потому что мерило не то. Журнал хранилища
// состояние ПРОИЗВОДИТ — у вида `storage_volume`; у двух остальных его видов
// состояния нет, и причина у них своя (их поле «кем используется» — перечень
// томов, а мутация тома событий им не эмитирует). То есть он не «без состояния»,
// а СМЕШАННЫЙ — ровно тем, чем был этот до сегодняшнего дня.
//
// Перемерено переписью гейта, а не памятью: объявлений журналов пять, собирают
// состояние ПЯТЬ. Смешанным остаётся один — хранилище.
//
// Перепись печатает гейт `internal/repohygiene`
// `TestSubscriptionOwnerPageSaysWhatItsJournalDoes` — он же держит согласие этого
// свойства с тем, что о владельце обещает клиентская страница подписки. Гейт
// судит владельца ЦЕЛИКОМ («собирает состояние или нет»), поэтому различие по
// видам внутри владельца он не видит и видеть не обязан: его предмет — не солгала
// ли страница о владельце. У этого владельца различия по видам БОЛЬШЕ НЕТ, и
// строка страницы обязана сказать это ровно так же прямо, как прежде говорила
// обратное.
