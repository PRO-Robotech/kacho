// Package subscriptionjournal — объявление ЖУРНАЛА nlb для общего сервера потока
// изменений (`pkg/subscription`).
//
// Здесь только ЗНАЧЕНИЯ: где журнал лежит, каким каналом будит, как его строка
// становится событием общей формы. Курсор, граница устоявшегося, пределы, сужение
// по правам и порядок отказов принадлежат общему серверу и владельцу не выдаются.
//
// # ЖУРНАЛ nlb СОСТОЯНИЯ НЕ НЕСЁТ, и это сказано вслух
//
// Нагрузка событий nlb — намеренно МИНИМАЛЬНЫЙ снимок (`kachorepo.LifecyclePayload`:
// идентификатор, родитель, проект, регион, имя, состояние, протокол, порт), и её
// собственный комментарий объявляет это решением: «outbox-event это уведомление,
// а не полный ресурс — consumer делает дополнительный Get(id) если нужно».
//
// Общая форма подписки разрешает читать НЕПУСТУЮ нагрузку как ПОЛНОЕ состояние
// предмета, и это единственный случай, когда подписчик вправе так делать. Значит
// отдать сюда частичный снимок нельзя: подписчик записал бы отсутствующие поля
// как факт — меток нет, зоны нет, целей нет. Поэтому события nlb доезжают с
// признаком «состояния не будет», а состояние подписчик берёт чтением по
// идентификатору.
//
// **Ценность потока от этого не исчезает, и её стоит назвать точно.** Подписчик
// узнаёт вид, идентификатор, якорь проекта и род изменения — то есть ЧТО
// перечитать и когда. Именно это снимает постоянный опрос списков: чтение
// случается на изменении, а не каждые три секунды.
//
// **Чего это НЕ закрывает — тоже названо, чтобы следующий не принял за
// закрытое.** Отбор по меткам на стороне клиента (решение владельца о единой форме подписки) исходил
// из того, что событие несёт полное состояние. Для журнала nlb посылка неверна:
// меток в нагрузке нет вовсе. Предмет заведён отдельной задачей — здесь он
// назван, а не починен, потому что чинится он ОБОГАЩЕНИЕМ ЖУРНАЛА nlb, а это
// правка его эмиттеров, а не подписки.
//
// # «Состояния нет» и «нагрузку не читает никто» — РАЗНЫЕ утверждения
//
// Первое — про то, что подписчику не отдаётся `state`. Второе сильнее и
// проверено отдельно (задача #1452): нагрузку `nlb_outbox.payload` пишут десять
// производителей, а читателей у неё в прод-дереве ноль — общий сервер выбирает
// колонку запросом и отдаёт её сюда, а `state` ниже её не берёт. Путать их
// нельзя: обогащение журнала (#1381) меняет ПЕРВОЕ, и в тот же момент обязано
// отменить второе вместе с записью отступления и с проверкой, которая его
// держит (`TestJournalStateCannotReadThePayload`).
//
// Что при этом СДЕЛАНО, чтобы обещание не висело неисполнимым: цена названа с
// обеих сторон. Контракт больше не объявляет клиентский отбор по меткам
// исполнимым везде (`SubscriptionRequest`, оговорка у отсутствующей оси меток), и
// клиентская страница подписки называет владельца `loadbalancer` поимённо. А само
// отсутствие состояния доезжает причиной `NOT_PRODUCED` — то есть подписчик
// отличает свойство журнала от сбоя МАШИННО, не читая ни строчки документации.
//
// # ЦЕНА ОБОГАЩЕНИЯ ИЗМЕРЕНА, а не оценена на глаз
//
// Обогащение обязано быть ВСЁ-ИЛИ-НИЧЕГО В ПРЕДЕЛАХ ВИДА: контракт разрешает
// читать непустую нагрузку как ПОЛНОЕ состояние, поэтому один эмиттер,
// отдающий частичный снимок, делает ложным весь вид — и делает тихо. Значит
// считать надо ЭМИТТЕРЫ вида, а не места, где удобно.
//
// ЕДИНИЦА СЧЁТА — ТОЧКА ЭМИССИИ: оператор, записывающий строку
// `nlb_load_balancer`. Не «путь» и не «место, где удобно»: у переезда путь один, а
// точек две, и обогащать надо обе.
//
// Их СЕМЬ, и две из них — SQL:
//
//   - ПЯТЬ точек Go на четырёх путях use-case (создание · правка · удаление ·
//     переезд, у которого их две). Запись у них на руках, обогащаются прямо —
//     кроме переезда: он отдаёт только идентификаторы (`lbMovedPayload`), то есть
//     заведомо частичен уже сегодня;
//   - пересчёт состояния — ТРИГГЕР БАЗЫ. Функция ОДНА (`lb_status_recompute`),
//     переопределённая чередой миграций и подвешенная к нескольким триггерам;
//     пишет `{id, status, recomputed}`. Она живёт в ПРИМЕНЁННЫХ миграциях,
//     править их нельзя (ban #5) — значит нужна НОВАЯ миграция, переопределяющая
//     тело;
//   - сборщик свободных адресов (`free_ip_runner`) — свой INSERT, род `DELETED`.
//     Состояния у снятия не бывает by construction, поэтому обогащения он не
//     требует и в трудную часть не входит.
//
// Предикаты, чтобы это перемерить, а не поверить:
//
//	git grep -n OutboxResourceLoadBalancer -- 'services/nlb/internal/apps/**/*.go' | grep -v _test
//	grep -rn "'nlb_load_balancer'" services/nlb/internal/migrations/*.sql \
//	  services/nlb/internal/apps/kacho/jobs/*.go
//
// Второй предикат даёт БОЛЬШЕ строк, чем точек: имя функции триггера повторяется
// в каждой миграции, которая её переопределяла, и в разделе отката тоже. Живая —
// последняя применённая; считать надо ФУНКЦИИ, а не совпадения.
//
// # ЧТО ЗДЕСЬ БЫЛО НЕВЕРНО: трудная часть НЕ триггер (перемерено 2026-08-29)
//
// Прежняя редакция называла триггер трудной частью на том основании, что «собрать
// полный предмет в PL/pgSQL значит завести ВТОРУЮ проекцию ресурса — на другом
// языке, рядом с первой, и расходиться они будут молча», и выводила отсюда, что
// работа упирается в решение про вторую проекцию.
//
// **Опровергнуто дважды, и оба раза деревом, а не рассуждением:**
//
//  1. проекцию в PL/pgSQL собирать НЕ НАДО. Журнал реестра тоже наполняется
//     триггером — и состояние ПРОИЗВОДИТ: его триггер пишет `to_jsonb(v_row)`,
//     то есть строку целиком, а проекция в контракт случается ОДИН раз, на Go
//     (`services/registry/internal/migrations/20260828154000_registry_resource_journal.sql`,
//     посажено той же неделей). Вторую проекцию заводит только тот, кто собирает
//     нагрузку `jsonb_build_object`-ом по полям;
//  2. у балансировщика строки для этого ДОСТАТОЧНО: `kacho_nlb.load_balancers` —
//     одна плоская таблица, и `labels` лежит колонкой на ней. Стороны разбора у
//     nlb уже есть — `kachorepo.LoadBalancerRecord` (встраивает доменную запись)
//     и перенос `dto`/`type2pb`, то есть ровно те две части, которыми собирает
//     состояние журнал vpc.
//
// Значит доля триггера — новая миграция, меняющая нагрузку на `to_jsonb`
// строки: обычная работа с известным в дереве образцом.
//
// **ТРУДНАЯ ЧАСТЬ — ГРУППА ЦЕЛЕЙ, и она осталась неназванной.** Публичная
// проекция группы строится не из её строки, а из набора целей С СОСТОЯНИЕМ
// (`TargetStates`; решение записано в
// `docs/engineering/architecture/08-known-divergences.md` §«Публичная проекция
// группы строится из набора С состоянием»). Одной строки для неё недостаточно ни
// при каком кодировании, а её джоба слива целей пишет строку журнала своим
// запросом. Здесь — и только здесь — стоит вопрос «где собирать набор», который
// прежняя редакция приписывала триггеру.
//
// Числа по остальным двум видам, перемеренные тем же предикатом: у `nlb_listener`
// точек SQL **ноль** (таблица плоская, `labels` колонкой) — он обогащается
// целиком на Go; у `nlb_target_group` точек Go шесть плюс запрос джобы слива.
//
// Отсюда вывод, который стоит прочитать до начала работы: это отдельная задача
// nlb с миграцией, а не правка объявления журнала, — но упирается она в проекцию
// ГРУППЫ, а не в язык триггера.
//
// # ЭТО КЛАСС ИЗ ДВУХ ВЛАДЕЛЬЦЕВ, А НЕ ОТСТАВАНИЕ nlb
//
// Состояния не производят ДВА журнала из пяти — этот и журнал хранилища. Причины
// РАЗНЫЕ, и путать их нельзя: там публичная проекция всех трёх видов выводится
// ЧЕРЕЗ таблицы, поэтому строки не хватает ни одному виду; здесь строки не
// хватает одному виду из трёх. Перепись печатает гейт
// `internal/repohygiene` `TestSubscriptionOwnerPageSaysWhatItsJournalDoes` — он
// же держит согласие этого свойства с тем, что о владельце обещает клиентская
// страница подписки.
package subscriptionjournal

