package subscriptionjournal

import (
	"go/ast"
	"sort"
	"testing"
)

// statefulKinds — виды, у которых событие несёт ПОЛНОЕ состояние предмета, и
// имя ЕДИНСТВЕННОГО строителя их нагрузки.
//
// Ключ — константа общего словаря видов (см. соседний гейт: слово вида
// объявлено один раз, поэтому здесь оно берётся именем константы, а не
// литералом). Значение — имя функции, собирающей нагрузку, как оно записано в
// вызове.
//
// Строитель квалифицирован пакетом (`kachorepo.…`) НЕ для красоты: точки эмиссии
// одного вида лежат в РАЗНЫХ пакетах use-case, поэтому строитель обязан быть им
// общим. Строитель, спрятанный в одном из пакетов, второй бы завёл заново — то
// есть ровно вторую форму нагрузки того же вида (#1549).
//
// Вид, у которого состояния НЕТ, здесь не стоит — и это не пробел, а
// объявление: его нагрузка остаётся минимальным снимком, а сборщик состояния
// отвечает по нему «не производится». Появится состояние — вид обязан появиться
// и здесь, иначе одна частичная точка сделает ложным весь вид.
var statefulKinds = map[string]string{
	"kachorepo.OutboxResourceListener": "kachorepo.ListenerStatePayload",
}

// TestEveryEmissionOfAStatefulKindBuildsTheSamePayload — ВСЁ-ИЛИ-НИЧЕГО В ПРЕДЕЛАХ ВИДА.
//
// # Предмет
//
// Контракт единой формы подписки разрешает подписчику читать непустое состояние
// события как ПОЛНОЕ состояние предмета. Значит один эмиттер вида, положивший в
// нагрузку частичный снимок, делает ложным ВЕСЬ вид — и делает это тихо: событие
// придёт, разберётся, перенесётся в контракт и объявит, что у предмета нет ни
// меток, ни проекта.
//
// Свойство принадлежит не одной функции и даже не одному пакету: точки эмиссии
// вида лежат в РАЗНЫХ пакетах use-case (у балансировщика — в его собственном и в
// пакете слушателя), и добавить следующую можно не тронув ни одной из
// существующих. Поэтому судится дерево, а не вызов и не каталог.
//
// # Почему проверка ОДНА на все виды, а не по копии в каждом пакете
//
// Прежняя редакция жила в пакете слушателя и обходила только его каталог
// (`TestEveryListenerEmissionBuildsTheSamePayload`). Она была верна и
// недостаточна дважды: не видела точек эмиссии вида, лежащих в чужом пакете, и
// потребовала бы копии на каждый следующий обогащённый вид — а копии расходятся
// молча. Здесь она ЗАМЕНЕНА строго более сильной: тот же предмет плюс все
// прочие виды, объявленные несущими состояние.
//
// # Почему разбор, а не поиск по образцу
//
// Имена строителей стоят в объяснениях — и в этом файле тоже. Проверка по
// подстроке краснела бы на собственном комментарии. Здесь судится УЗЕЛ: аргумент
// вида и аргумент нагрузки берутся позиционно из вызова `Emit`.
//
// # Чего проверка НЕ утверждает — названо, чтобы её не приняли шире
//
// Она не утверждает, что нагрузка ПОЛНА: полноту утверждают пробы строителей и
// сквозная проба журнала. Она утверждает, что строитель у вида ОДИН — то есть
// что вторая, частичная форма не заведётся мимо первой.
func TestEveryEmissionOfAStatefulKindBuildsTheSamePayload(t *testing.T) {
	seen := map[string]int{}
	var findings []string

	res := inspectEmissions(t, func(e emission) {
		kind := kindLiteralName(e.kind)
		builder, stateful := statefulKinds[kind]
		if !stateful {
			return
		}
		seen[kind]++
		if call, ok := e.payload.(*ast.CallExpr); ok {
			if kindLiteralName(call.Fun) == builder {
				return
			}
		}
		findings = append(findings, e.pos+" ("+kind+", ожидался строитель "+builder+")")
	})

	kinds := make([]string, 0, len(statefulKinds))
	for k := range statefulKinds {
		kinds = append(kinds, k)
	}
	sort.Strings(kinds)
	t.Logf("перепись: файлов осмотрено %d · вызовов Emit найдено %d · видов с состоянием объявлено %d",
		res.filesRead, res.emitsSeen, len(statefulKinds))
	for _, k := range kinds {
		t.Logf("  %s — точек эмиссии найдено %d, строитель %q", k, seen[k], statefulKinds[k])
	}

	if res.filesRead == 0 {
		t.Fatal("не осмотрено ни одного файла — проверка беспредметна, а не пройдена")
	}
	// Объявление вида, у которого точек эмиссии не нашлось, — находка, а не
	// пустое место: либо эмиссия переехала и проверка перестала иметь предмет,
	// либо вид объявлен несущим состояние, не будучи никем эмитируемым.
	for _, k := range kinds {
		if seen[k] == 0 {
			t.Errorf("вид %s объявлен несущим состояние, но точек его эмиссии в дереве НЕТ. "+
				"Проверка по нему беспредметна: она одобрит любое дерево, ничего не прочитав", k)
		}
	}
	for _, pos := range findings {
		t.Errorf("%s: нагрузка собрана НЕ общим строителем вида.\n"+
			"Контракт формы разрешает читать непустое состояние как ПОЛНОЕ, поэтому одна "+
			"частичная нагрузка делает ложным ВЕСЬ вид — и делает это тихо: событие придёт, "+
			"разберётся и объявит, что у предмета нет ни меток, ни проекта", pos)
	}
}
