-- =============================================================================
-- Backend-порт слушателя снят с контракта — снимается и колонка, которую
-- прежний контракт заполнял
-- =============================================================================
-- Снять поле с контракта и убрать за ним данные — РАЗНЫЕ действия, и второе не
-- видно ни в диффе контракта, ни в прогоне: строка молчит. Пока колонка стоит,
-- она либо ничего не значит (тогда её читатель однажды решит, что значит), либо
-- значит то, чего продукт не делает.
--
-- ЧТО ИМЕННО ЗНАЧИЛО ЗНАЧЕНИЕ В ЭТОЙ КОЛОНКЕ. Ничего, решающего исход. Backend-
-- порт — величина с ОДНИМ хозяином, и хозяин это `target_groups.port`: именно он
-- уезжает наружу производным `resolved_backend_port` (скалярный подзапрос в
-- listenerCols), именно на него ссылается контракт слушателя. Колонка слушателя
-- заполнялась вставкой, читалась обратно проекцией и не участвовала ни в одном
-- решении — «принято-и-проигнорировано», что конвенция запрещает прямо.
--
-- ПОЧЕМУ ЭТО НЕ ЛЕЧИЛОСЬ УМОЛЧАНИЕМ. Контракт объявлял поле необязательным и
-- обещал наследование порта группы, а проверка диапазона отвергала ноль —
-- единственную форму «не задавал». Возможность была объявлена, задокументирована
-- и не работала НИ ПРИ КАКОМ входе; исполнимого входа для неё не существовало.
-- Достроить умолчание значило бы завести второго хозяина одной величины и
-- потребовать правила старшинства между ним и группой — правила, которое сегодня
-- некому исполнять.
--
-- ПОЭТОМУ У СТРОК НЕТ «ВЫРАЗИМОГО ВИДА», В КОТОРЫЙ ИХ НАДО ПРИВЕСТИ. Перенести
-- значение в `target_groups.port` нельзя: у группы порт свой, он старше по
-- смыслу, и слушателей на одной группе бывает несколько — перенос выбирал бы
-- произвольного победителя. Приведение строк к действительности и снятие колонки
-- здесь одно и то же действие.
--
-- ЧТО АРЕНДАТОР ЗАМЕТИТ. `targetPort` исчезает из проекции слушателя и перестаёт
-- приниматься на создании; путь маски с этим именем отвергается как неизвестный
-- (было — «неизменяемо после Create», то есть утверждение, что величина есть).
-- Нужен другой backend-порт — ссылайтесь на ДРУГУЮ группу целей: она дешёвая и
-- переиспользуемая, а порт у неё ровно один.
--
-- ban #5 (применённую миграцию не править): 0001, создавшая колонку, не тронута —
-- это новая миграция вперёд.
--
-- ЗАВИСИМЫЙ ОБЪЕКТ РОВНО ОДИН, И ОН НАЗВАН. 0001 завела вместе с колонкой
-- ограничение `listeners_target_port_check CHECK (target_port BETWEEN 1 AND
-- 65535)`. Оно ссылается ТОЛЬКО на снимаемую колонку, поэтому Postgres снимает
-- его вместе с ней — без `CASCADE` и без отдельного стейтмента. Индексов и
-- выражений по умолчанию у колонки нет (перепись по 0001 и по 0002–0030).
--
-- Оно же — вторая половина доказательства, что «не задавал» было невыразимо:
-- ноль отвергала не только проверка входа, но и сама база.
--
-- Блокировки: `DROP COLUMN` для целочисленного столбца — операция каталога,
-- переписи таблицы нет, но `ACCESS EXCLUSIVE` на `listeners` она берёт (доли
-- миллисекунды на этом размере).

ALTER TABLE kacho_nlb.listeners
    DROP COLUMN IF EXISTS target_port;

-- +goose Down

-- Откат возвращает КОЛОНКУ, но НЕ прежнее ограничение — и это не небрежность.
-- `CHECK (target_port BETWEEN 1 AND 65535)` запрещает единственное значение,
-- которое откату честно писать: у строк, созданных после снятия поля,
-- backend-порта слушателя нет, и выдумать его нечем — порт живёт на группе, а
-- слушателей на одной группе бывает несколько. Ноль здесь и означает «величины
-- не было»; вернуть вместе с ним прежний диапазон значило бы уронить откат на
-- собственных строках.
--
-- Данные не восстановимы, и восстанавливать нечего: значение не решало ничего.
ALTER TABLE kacho_nlb.listeners
    ADD COLUMN IF NOT EXISTS target_port integer NOT NULL DEFAULT 0;
