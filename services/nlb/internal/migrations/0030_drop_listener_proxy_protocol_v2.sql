-- =============================================================================
-- Обрамление PROXY-протокола снято с контракта — снимаются и строки, которые
-- прежний контракт успел записать
-- =============================================================================
-- Снять поле с контракта и убрать за ним данные — РАЗНЫЕ действия, и второе не
-- видно ни в диффе контракта, ни в прогоне: строка молчит. Пока колонка стоит,
-- она либо ничего не значит (тогда её читатель однажды решит, что значит), либо
-- значит то, чего продукт не умеет.
--
-- ЧТО ИМЕННО ЗНАЧИЛО `true` В ЭТОЙ КОЛОНКЕ. Ничего. Заголовок PROXY-протокола по
-- его собственной спецификации уходит ДО любых данных соединения, то есть его
-- вставляет только тот, кто владеет байтовым потоком к бекенду. Балансировщик
-- четвёртого уровня потоком не владеет — он его пересылает; у рассмотренного
-- программного датаплейна такого обрамления нет вовсе. Значит исполнителя не
-- существовало ни в одном варианте, ни один узел никогда не обрамлял ни одного
-- соединения, и `proxy_protocol_v2 = true` описывало намерение, а не факт.
--
-- ПОЭТОМУ У СТРОК НЕТ «ВЫРАЗИМОГО ВИДА», В КОТОРЫЙ ИХ НАДО ПРИВЕСТИ. Разбор по
-- видам, как в vpc-миграции 0029 (где одно снятое значение сохраняло смысл, а
-- второе — нет), здесь беспредметен: у булева признака одно значение — `false` —
-- и оно тождественно тому, что происходило на самом деле. Приведение строк к
-- действительности и снятие колонки — одно и то же действие, поэтому колонка
-- снимается целиком, а не обнуляется.
--
-- ЧТО АРЕНДАТОР ЗАМЕТИТ. Ровно то, что и так было верно: поведение соединений не
-- меняется — оно и не менялось никогда. Меняется видимое: `proxyProtocolV2`
-- исчезает из проекции ресурса, а путь маски с этим именем отвергается как
-- неизвестный (было — принимался молча). Это и есть разница между решением и
-- «принято-и-проигнорировано»: отказ виден сразу, а несделанное — только по
-- последствиям и в чужой отладке.
--
-- ban #5 (применённую миграцию не править): 0001, создавшая колонку, не тронута —
-- это новая миграция вперёд.
--
-- Блокировки: `DROP COLUMN` для булева столбца — операция каталога, переписи
-- таблицы нет, но `ACCESS EXCLUSIVE` на `listeners` она берёт (доли миллисекунды
-- на этом размере). Зависимых объектов у колонки нет — ни индекса, ни ограничения,
-- ни выражения по умолчанию сверх `DEFAULT false` (проверено по 0001 и по всем
-- миграциям 0002–0029), поэтому явного снятия чего-либо перед ней не требуется, и
-- неявного каскада не происходит.

ALTER TABLE kacho_nlb.listeners
    DROP COLUMN IF EXISTS proxy_protocol_v2;

-- +goose Down

-- Возврат к форме до 0030. Данные НЕ восстановимы и восстанавливать нечего:
-- значение не исполнялось ни разу, поэтому колонка, вернувшаяся со своим прежним
-- умолчанием, воспроизводит ровно то состояние, в котором продукт и находился.
ALTER TABLE kacho_nlb.listeners
    ADD COLUMN IF NOT EXISTS proxy_protocol_v2 boolean NOT NULL DEFAULT false;
