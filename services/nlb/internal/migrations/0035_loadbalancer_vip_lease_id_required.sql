-- =============================================================================
-- Выданный VIP обязан нести ключ к своей аренде.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#467`.
--
-- ЧТО БЫЛО НЕВЕРНО. Ни одно ограничение не связывало непустой `address_v4/v6`
-- (сам IP) с непустым `address_id_v4/v6` (ключ аренды у vpc). Строка со
-- значением `address_v6 = '2a02::7'` и `address_id_v6 = ''` была законной, а
-- смысл у неё нечитаемый: адрес выдан, вернуть его нечем.
--
-- ЧЕМ ЭТО КОНЧАЛОСЬ. Освобождение при удалении смотрело только на
-- идентификатор и на пустом возвращало успех — «этому семейству освобождать
-- нечего». Дальше строка балансировщика удалялась, и с этого мгновения аренду
-- не видел никто: реконсайлер выбирает только строки в DELETING/CREATING, а
-- обратного поиска «что принадлежит этому балансировщику» у vpc нет. Подсеть
-- после такого удаления не удаляется НИКОГДА — `Subnet has allocated internal
-- addresses`, — и починить это в системе некому.
--
-- ПОЧЕМУ НА УРОВНЕ БАЗЫ. Внутрисервисный инвариант держится конструкцией схемы,
-- а не проверкой в коде (`data-integrity.md`, ban #10). Код тоже научен
-- различать два состояния и отказывать на потерянном ключе, но код — это
-- ВТОРОЙ рубеж: он ловит уже записанное. Ограничение не даёт записать.
--
-- ЭКВИВАЛЕНТНОСТЬ, А НЕ ИМПЛИКАЦИЯ. Проверяется `(адрес = '') = (ключ = '')`,
-- то есть запрещены ОБА перекоса. Обратный — ключ есть, адреса нет — означал бы
-- аренду, которую балансировщик держит, никому её не показывая; она так же
-- висит на подсети, только вдобавок невидима арендатору.
--
-- NOT VALID — намеренно, тем же приёмом, что и соседние ограничения семейств в
-- `0011`: проверка действует на всю новую и изменяемую запись, но не требует
-- полного прохода по таблице при выкатке. Уже записанные перекошенные строки
-- (если они есть) остаются видимыми и чинятся отдельно — снос строки здесь
-- уничтожил бы последнюю зацепку к висящей аренде, то есть ровно то, что эта
-- миграция и защищает.

-- +goose Up
ALTER TABLE kacho_nlb.load_balancers
    ADD CONSTRAINT load_balancers_v4_lease_id_present_check
    CHECK ((address_v4 = '') = (address_id_v4 = '')) NOT VALID;

ALTER TABLE kacho_nlb.load_balancers
    ADD CONSTRAINT load_balancers_v6_lease_id_present_check
    CHECK ((address_v6 = '') = (address_id_v6 = '')) NOT VALID;

-- +goose Down
ALTER TABLE kacho_nlb.load_balancers
    DROP CONSTRAINT IF EXISTS load_balancers_v6_lease_id_present_check;

ALTER TABLE kacho_nlb.load_balancers
    DROP CONSTRAINT IF EXISTS load_balancers_v4_lease_id_present_check;
