package main

// Распознаватель эфемерного порта знает все ЧИСЛОВЫЕ написания своего предмета —
// и РАСХОДИТСЯ с настоящим слушателем на пустом, намеренно.
//
// Заголовок сужен по замеру, и это не осторожность формулировки: сказать «знает
// ВСЕ законные написания» было бы неправдой, а неправда в заголовке пробы дороже
// пропуска — она объявляет доказанным то, чего проба не доказывала.
//
// ЧТО ДОКАЗАНО. Страж проб носителя утверждает «слушатель поднят на порту, который
// назначит ядро». Ядру порт отдаёт ЧИСЛО ноль, а не строка «0»: `net.Listen`
// поднимает эфемерный слушатель и на `:0`, и на `:00`, и на `:0000`, и на `:+0`,
// и на `:-0`, а ` 0` и `0x0` отвергает — замерено прямым вызовом по каждому из
// восьми написаний. На этих восьми распознаватель совпадает со слушателем.
//
// ЧТО ИСКЛЮЧЕНО, И ПОЧЕМУ. Девятое написание — ПУСТОЕ — расходится: `net.Listen`
// поднимается и на `tcp://…:` (порт пуст), и на пустом адресе вовсе, выдавая
// эфемерный порт (замерено), а распознаватель отвечает «нет». Это выбор, а не
// недосмотр. Страж судит НЕ то, что сделает ядро, а то, ДОЕХАЛА ЛИ РУЧКА: пустое
// значение — отсутствующая конфигурация, и предпосылка пробы на ней не создана.
// Достижимо это продуктовым путём — явно пустая переменная умолчания не получает
// (замерено), — поэтому исключение названо здесь, а не подразумевается.
//
// Утверждения ДВУСТОРОННИЕ: числовые написания молчат, фиксированный порт
// находится. Односторонняя проба зеленела бы на распознавателе, который не видит
// ничего.

import "testing"

func TestEndpointKernelAssignedMatchesTheListenerOnNumericSpellings(t *testing.T) {
	for _, tc := range []struct {
		endpoint string
		want     bool
		why      string
	}{
		{"tcp://127.0.0.1:0", true, "каноническое написание"},
		{"tcp://127.0.0.1:00", true, "ядро смотрит на ЧИСЛО: net.Listen поднимает эфемерный слушатель"},
		{"tcp://0.0.0.0:0000", true, "то же числом, другой записью"},
		{"tcp://0.0.0.0:+0", true, "net.Listen принимает и поднимает эфемерный слушатель — замерено"},
		{"tcp://0.0.0.0:-0", true, "то же: область приёма продукта шире канонической записи"},
		{"tcp://0.0.0.0: 0", false, "с пробелом net.Listen ОТКАЗЫВАЕТ — распознаватель не вправе быть шире"},
		{"tcp://0.0.0.0:0x0", false, "шестнадцатеричную запись net.Listen тоже отвергает"},
		{"tcp://0.0.0.0:9090", false, "фиксированный порт — предмет запрета"},
		{"tcp://0.0.0.0:9091", false, "фиксированный порт — предмет запрета"},
		{"tcp://0.0.0.0:10", false, "ненулевой порт, начинающийся с цифры предмета"},
		{"tcp://0.0.0.0", false, "двоеточия нет вовсе: net.Listen ОТКАЗЫВАЕТ тоже — здесь согласие"},
		// Два РАСХОЖДЕНИЯ с настоящим слушателем, и оба намеренные. Факта здесь
		// два, и стоять обязаны оба: net.Listen на `tcp://0.0.0.0:` и на пустом
		// адресе ПОДНИМАЕТСЯ, выдавая эфемерный порт (замерено), — и всё же мы
		// считаем это незаданной конфигурацией, а не разрешением, потому что страж
		// судит, доехала ли ручка, а не что сделает ядро.
		{"tcp://0.0.0.0:", false, "слушатель поднялся бы на эфемерном; для стража это НЕЗАДАННАЯ ручка"},
		{"", false, "слушатель поднялся бы на эфемерном; для стража это НЕЗАДАННАЯ ручка"},
	} {
		if got := endpointIsKernelAssigned(tc.endpoint); got != tc.want {
			t.Errorf("endpointIsKernelAssigned(%q) = %v, ждали %v — %s", tc.endpoint, got, tc.want, tc.why)
		}
	}
}
