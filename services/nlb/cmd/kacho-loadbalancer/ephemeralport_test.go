package main

// Распознаватель эфемерного порта знает ВСЕ законные написания своего предмета.
//
// Страж проб носителя утверждает «слушатель поднят на порту, который назначит
// ядро». Ядру порт отдаёт ЧИСЛО ноль, а не строка «0»: `net.Listen` поднимает
// эфемерный слушатель и на `:0`, и на `:00`, и на `:0000` — замерено прямым
// вызовом. Распознаватель, сравнивавший строкой, краснел бы на законном входе.
//
// Ложная тревога дороже пропуска: читатель идёт чинить исправное и не находит
// дефекта, потому что его там нет. Поэтому утверждения ДВУСТОРОННИЕ — законные
// написания молчат, фиксированный порт находится. Односторонняя проба зеленела бы
// на распознавателе, который не видит ничего.

import "testing"

func TestEndpointKernelAssignedKnowsEveryLawfulSpelling(t *testing.T) {
	for _, tc := range []struct {
		endpoint string
		want     bool
		why      string
	}{
		{"tcp://127.0.0.1:0", true, "каноническое написание"},
		{"tcp://127.0.0.1:00", true, "ядро смотрит на ЧИСЛО: net.Listen поднимает эфемерный слушатель"},
		{"tcp://0.0.0.0:0000", true, "то же числом, другой записью"},
		{"tcp://0.0.0.0:+0", true, "net.Listen принимает и поднимает эфемерный слушатель — замерено"},
		{"tcp://0.0.0.0:-0", true, "то же: область приёма продукта шире канонической записи"},
		{"tcp://0.0.0.0: 0", false, "с пробелом net.Listen ОТКАЗЫВАЕТ — распознаватель не вправе быть шире"},
		{"tcp://0.0.0.0:0x0", false, "шестнадцатеричную запись net.Listen тоже отвергает"},
		{"tcp://0.0.0.0:9090", false, "фиксированный порт — предмет запрета"},
		{"tcp://0.0.0.0:9091", false, "фиксированный порт — предмет запрета"},
		{"tcp://0.0.0.0:10", false, "ненулевой порт, начинающийся с цифры предмета"},
		{"tcp://0.0.0.0", false, "порта нет вовсе — это не «назначит ядро»"},
		{"", false, "пустой эндпойнт: отсутствие не считается за разрешение"},
	} {
		if got := endpointIsKernelAssigned(tc.endpoint); got != tc.want {
			t.Errorf("endpointIsKernelAssigned(%q) = %v, ждали %v — %s", tc.endpoint, got, tc.want, tc.why)
		}
	}
}
