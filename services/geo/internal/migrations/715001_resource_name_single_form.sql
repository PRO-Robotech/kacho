-- =============================================================================
-- Имя ресурса: одна форма на всё дерево, пустого имени не существует.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#715`. Парная к 715001 у vpc/compute/storage/nlb.
--
-- ПОЧЕМУ geo ПРИВОДИТСЯ ТОЖЕ. Прежде каталог размещения считался изъятием:
-- у него `name` — подпись, а не метка арендатора. Изъятие снято решением
-- владельца: канон RFC 1123 связывает ВСЕ домены, отдельного поля под
-- человекочитаемую подпись не заводится, и читаемость обеспечивает сама форма
-- (дефис разделяет слова), а не второе поле.
--
-- ЧЕМ geo ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ЧЕТЫРЁХ — три отличия, все влияют на текст:
--
--   * прежнего ограничения формы здесь НЕ БЫЛО вовсе (`0001_initial.sql`:
--     `name TEXT NOT NULL DEFAULT ''`), поэтому снимать нечего — только
--     добавить. Откат по этой же причине ограничение просто снимает и НЕ
--     возвращает предшественника: предшественника не существовало;
--   * умолчание `''` уже снято `0004` (`ALTER COLUMN name DROP DEFAULT`), то
--     есть колонки, чьё умолчание противоречило бы собственному ограничению,
--     здесь нет by construction;
--   * `UNIQUE(name)` здесь ГЛОБАЛЬНАЯ (`regions_name_key` / `zones_name_key`,
--     заведены `0004`), а не в границах проекта. Замена `name = id` её не
--     нарушает: `id` — первичный ключ той же таблицы, значит уникален, значит
--     и производное имя уникально. Порядок строк на результат не влияет.
--
-- ЧТО ДЕЛАЕТСЯ СО СТАРЫМИ СТРОКАМИ. Строка, чьё имя новой форме не отвечает,
-- получает `name = id`. Правило то же, что у четырёх остальных, и по той же
-- причине: `id` уже удовлетворяет форме — у Region/Zone это назначаемый
-- администратором слаг (`ru-central1`, `ru-central1-a`), а не крокфордов
-- идентификатор, и он строчный с дефисами by construction.
--
-- Прежняя подпись НЕ сохраняется — ни в комментарии, ни в соседней колонке, ни
-- меткой: перенос читаемой формы вбок был бы тем же алиасом, который решением
-- владельца не заводится.
--
-- ЦЕНА НАЗВАНА ЧЕСТНО и она здесь МЕНЬШЕ, чем у четырёх остальных: посев
-- каталога уже пишет `name = id` (`deploy/scripts/geo-baseline.sql` и
-- `tests/authz-fixtures/prodseed_matrix.py::_seed_geo_catalog` — оба сеют
-- `('ru-central1', 'ru-central1')`), поэтому на поднятом стенде эта миграция
-- не меняет НИ ОДНОЙ строки. Заменять она будет только те имена, которые завёл
-- администратор вручную не по форме.
--
-- ИДЕМПОТЕНТНОСТЬ. Повторный прогон не меняет ничего: после первого прохода
-- строк, не отвечающих форме, не остаётся, ограничение создаётся через
-- DROP IF EXISTS + ADD.

-- +goose Up
-- +goose StatementBegin

SET search_path TO kacho_geo, public;

DO $$
DECLARE
    t    text;
    tbl  text[] := ARRAY['regions', 'zones'];
    -- Единственная форма имени. Держится в одной переменной, чтобы два
    -- ограничения не могли разойтись между собой внутри одного файла.
    form text := '^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$';
BEGIN
    FOREACH t IN ARRAY tbl LOOP
        -- 1. Имя, не отвечающее форме (включая пустое), заменяется на id —
        --    ДО создания ограничения, иначе оно не построится.
        EXECUTE format(
            'UPDATE kacho_geo.%I SET name = id WHERE name IS NULL OR name !~ %L',
            t, form);

        -- 2. Ограничение формы. Прежнего нет, но DROP IF EXISTS оставлен ради
        --    идемпотентности повторного прогона.
        EXECUTE format('ALTER TABLE kacho_geo.%I DROP CONSTRAINT IF EXISTS %I', t, t || '_name_check');
        EXECUTE format(
            'ALTER TABLE kacho_geo.%I ADD CONSTRAINT %I CHECK (name ~ %L)',
            t, t || '_name_check', form);
    END LOOP;
END $$;

-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin

-- Откат СНИМАЕТ ограничение и не ставит на его место ничего: до этой миграции
-- формы имени у geo не существовало, и возвращать нечего.
--
-- Прежние имена строк он тоже не восстанавливает: заменённое имя не сохранено
-- нигде. Это свойство названо прямо, а не скрыто за «симметричным» текстом.

SET search_path TO kacho_geo, public;

ALTER TABLE regions DROP CONSTRAINT IF EXISTS regions_name_check;
ALTER TABLE zones   DROP CONSTRAINT IF EXISTS zones_name_check;

-- +goose StatementEnd
