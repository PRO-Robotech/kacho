package migrations_test

import (
	"os"
	"testing"

	"github.com/PRO-Robotech/kacho/internal/pgtest"
)

// TestMain выдаёт пакету ОДИН Postgres вместо контейнера на пробу.
//
// `Migrate` нет намеренно: пробы этого пакета применяют цепочку сами и потому
// обязаны начинать с ПУСТОЙ базы — пре-мигрированный шаблон не оставил бы им
// того состояния, до которого и после которого они сравнивают. Каждый вызов
// получает свою базу (свой каталог, свои строки, своё пространство advisory-
// блокировок), поэтому между двумя пробами не пересекается ничего, что не
// пересекалось бы между двумя контейнерами.
//
// Контейнер поднимается лениво: под `-short`, где пробы пропускаются, не
// поднимается вовсе.
func TestMain(m *testing.M) {
	os.Exit(pgtest.Run(m, pgtest.Config{Name: "geoplan"}))
}
