-- =============================================================================
-- Каталог размещения: у региона и зоны остаётся ОДНА идентичность — `id`.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#716`. Решение владельца 2026-08-18.
--
-- ПОЧЕМУ СНЯТИЕ ПРАВОМЕРНО. У Region/Zone идентификатор назначает АДМИНИСТРАТОР,
-- и он человекочитаем by construction: `ru-central1`, `ru-central1-a`. Колонка
-- `name` несла ту же строку в другом написании («RU Central 1»), то есть два
-- места об одном предмете — и ровно то место, где значения расходятся: правят
-- одно, забывают второе, и через месяц регион зовётся по-разному в двух ответах
-- одного API.
--
-- Дубля не было видно, пока написания отличались. Канон формы имени (715001)
-- привёл `name` к той же форме, что и `id`, — то есть НЕ создал дубль, а обнажил
-- его. Здесь он снимается.
--
-- ЧЕМ geo ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ РЕСУРСОВ ПЛАТФОРМЫ и почему это не общий
-- приём: у сети, тома, балансировщика `id` машинный (крокфордов base32), и
-- человекочитаемость несёт именно `name` — там два поля оправданы. Каталог
-- размещения — единственное место дерева, где идентификатор пишут рукой.
--
-- ЧТО ПРОПАДАЕТ. Строки, чьё имя отличалось от идентификатора. После 715001 их
-- могло остаться ровно два вида: заведённые администратором вручную в канонной
-- форме, но не равные `id`, — и никакие другие (несоответствующие форме та
-- миграция уже заменила на `id`). На посеянном стенде таких строк НЕТ вовсе:
-- оба посева (`deploy/scripts/geo-baseline.sql` и приёмочная фикстура) пишут
-- `name = id`. Прежние значения не сохраняются ни в соседней колонке, ни меткой,
-- ни комментарием: перенос дубля вбок был бы тем же дублем под другим именем.
--
-- ЧТО УХОДИТ ВМЕСТЕ С КОЛОНКОЙ. Postgres снимает вместе с ней всё, что построено
-- РОВНО на ней: глобальную уникальность `<t>_name_key` (0004) и ограничение
-- формы `<t>_name_check` (715001). Оба сняты здесь ЯВНО и до `DROP COLUMN` — не
-- ради результата (он тот же), а чтобы снятие формы было видно в тексте: гейт
-- `TestNameFormConstraintIsProvenWhereItIsDeclared` перестаёт требовать от geo
-- доказательства ограничения, которого больше нет, и читает это отсюда.
--
-- ИДЕМПОТЕНТНОСТЬ. Повторный прогон не меняет ничего: `IF EXISTS` у обоих видов.

-- +goose Up
SET search_path TO kacho_geo, public;

ALTER TABLE regions DROP CONSTRAINT IF EXISTS regions_name_check;
ALTER TABLE regions DROP CONSTRAINT IF EXISTS regions_name_key;
ALTER TABLE regions DROP COLUMN IF EXISTS name;

ALTER TABLE zones DROP CONSTRAINT IF EXISTS zones_name_check;
ALTER TABLE zones DROP CONSTRAINT IF EXISTS zones_name_key;
ALTER TABLE zones DROP COLUMN IF EXISTS name;

-- +goose Down
-- Откат возвращает КОЛОНКУ, но НЕ прежние значения и НЕ форму.
--
-- Значения не сохранены нигде и восстановить их неоткуда. Каждая строка получает
-- `name = id` — единственное значение, которое здесь можно назвать не выдумывая,
-- и то самое, которое стояло у ВСЕХ строк посева.
--
-- Форма имени (`<t>_name_check`) не восстанавливается сознательно: в дереве у неё
-- РОВНО ОДНО объявление, и копия здесь была бы вторым — тем самым классом «два
-- места об одном предмете», ради которого форму и сводили в одно место (#715).
-- Откат самой формы принадлежит её собственной миграции.
--
-- То есть эта миграция обратима НЕ полностью, и это сказано прямо, а не спрятано
-- за симметричным текстом.
SET search_path TO kacho_geo, public;

ALTER TABLE regions ADD COLUMN IF NOT EXISTS name TEXT;
ALTER TABLE zones   ADD COLUMN IF NOT EXISTS name TEXT;

UPDATE regions SET name = id WHERE name IS NULL;
UPDATE zones   SET name = id WHERE name IS NULL;

ALTER TABLE regions ALTER COLUMN name SET NOT NULL;
ALTER TABLE zones   ALTER COLUMN name SET NOT NULL;

ALTER TABLE regions ADD CONSTRAINT regions_name_key UNIQUE (name);
ALTER TABLE zones   ADD CONSTRAINT zones_name_key   UNIQUE (name);
