package main

// carrier_start_test.go — geo проходит ВСЕ отказы старта носителя, а не только
// те, что соседняя проба умеет повторить у себя.
//
// # Почему конструктора дескриптора недостаточно
//
// `describe_test.go` спрашивает КОНСТРУКТОР: он судит поля по себе — объявлена
// ли ось, положительна ли величина, сходится ли форма с производителем. Половина
// отказов носителя так не проверяется: они существуют только там, где есть
// СЛУЖИМЫЙ НАБОР, снятый у самих серверов после регистрации, — метод без строки
// каталога, домен без единой записи карты, служимый стрим при неприменимой оси
// его бюджета, сверка объявленных осей с каталогом.
//
// У geo это особенно весомо: он объявляет НЕПРИМЕНИМЫМИ семь осей из десяти —
// больше всех в платформе. Каждое такое объявление есть утверждение о служимом
// наборе («своих типов не заводит», «ни один метод не сужается», «скрывать
// нечего»), и проверить его можно только там, где набор известен. До этой пробы
// семь заявлений geo не проверял никто: конструктор их принимает по форме.
//
// Порты эфемерные: проба обязана быть детерминированной, а фиксированный номер
// сделал бы её заложницей занятости машины прогона.

import (
	"context"
	"log/slog"
	"strings"
	"testing"

	"github.com/prometheus/client_golang/prometheus"
	"google.golang.org/grpc"

	"github.com/PRO-Robotech/corelib/authz"
	"github.com/PRO-Robotech/corelib/servicehost"

	"github.com/PRO-Robotech/kacho/internal/carrierprobe"
)

// TestCarrierRaisesGeoWithoutAStartRefusal — исход: носитель поднимает geo и не
// находит расхождения между объявленным и служимым.
//
// Контекст отменён ЗАРАНЕЕ: предмет пробы — отказы, которые носитель считает ДО
// первого соединения. Отменённый контекст гасит слушатели сразу после того, как
// отказы отработали: проба держит только сокеты на портах, назначенных ядром,
// и лишь до гашения, а сети не ждёт. Что порты эфемерны, утверждает страж
// `carrierprobe.RequireKernelAssigned`, а не этот комментарий.
func TestCarrierRaisesGeoWithoutAStartRefusal(t *testing.T) {
	cfg := bootConfig(t, map[string]string{
		"KACHO_GEO_GRPC_PORT":     "0",
		"KACHO_GEO_INTERNAL_PORT": "0",
	})

	// Журнал носителя читается, а не выбрасывается: перепись осмотренного он
	// печатает ВСЕГДА, и без неё «отказов нет» неотличимо от «ничего не осмотрено».
	var log strings.Builder
	logger := slog.New(slog.NewTextHandler(&log, nil))

	// Приёмник величин кеша вердиктов — НАСТОЯЩИЙ, а не заглушка: предмет здесь
	// не «поле заполнено», а «носитель позвал приёмник И отдал читателя того
	// кеша, который спрашивает звено». Проба, принимающая заглушку, осталась бы
	// зелёной на носителе, который приёмник не зовёт вовсе.
	var authzCacheReader func() authz.Metrics
	observeAuthzCache := func(read func() authz.Metrics) { authzCacheReader = read }

	desc, err := describe(cfg, logger, observeAuthzCache, prometheus.NewRegistry())
	if err != nil {
		t.Fatalf("дескриптор отвергнут конструктором — процесс не поднялся бы:\n%v", err)
	}
	// Страж предусловия — ДО носителя и по адресам ДЕСКРИПТОРА, то есть ровно
	// по тому, что получит net.Listen: ручка, не доехавшая до разбора,
	// краснит здесь текстом «условие не создано», а не соседним стендом.
	carrierprobe.RequireKernelAssigned(t, desc.Spec(), "KACHO_GEO_GRPC_PORT", "KACHO_GEO_INTERNAL_PORT")

	ctx, cancel := context.WithCancel(context.Background())
	cancel()

	// Регистраторы — те же, что в композиционном корне, но use-case'ы им не
	// нужны: предмет отказов — СОСТАВ служимого набора (какие методы и стримы
	// объявлены сервером), а не их поведение. Передать сюда nil-зависимости
	// законно ровно потому, что ни один обработчик не вызывается: контекст
	// отменён до первого соединения.
	serveErr := servicehost.Serve(ctx, desc,
		func(reg grpc.ServiceRegistrar) { registerPublic(reg, nil, nil, nil) },
		func(reg grpc.ServiceRegistrar) { registerInternal(reg, nil, nil, nil) },
	)
	// Исход подъёма судит общий пакет: отказ носителя — красное, слушатель,
	// не поднявшийся на порту, — «условие не создано», прочее — красное с
	// текстом. Три исхода различимы, и различие не зависит от того, какую
	// строку вернул носитель на штатном гашении.
	carrierprobe.RequireRaised(t, "geo", serveErr)

	// Величины кеша вердиктов вышли из процесса: без этого доля попаданий не
	// наблюдается, и «кеш не попадает ни разу» снаружи неотличимо от «кеш
	// поглощает весь поток».
	if authzCacheReader == nil {
		t.Fatal("носитель не отдал читателя величин кеша положительных вердиктов — " +
			"доля попаданий не выходит из процесса")
	}
	if s := authzCacheReader().Cache; s.Hits != 0 || s.Misses != 0 {
		t.Fatalf("до первого вызова окно вердиктов не спрашивали, а счётчики не нулевые: %+v", s)
	}

	census := log.String()
	// Якорь — НАЧАЛО переписи, а не подстрока «методов 0»: та же перепись несёт
	// «сужаемых методов 0», и предикат по подстроке краснел бы на СОГЛАСОВАННОМ
	// объявлении geo (он не сужает ни одного метода — это его законное
	// состояние). Ровно тот класс, который платформа ловит гейтами: предикат,
	// совпавший не со своим предметом.
	if strings.Contains(census, "осмотрено: методов 0") {
		t.Fatalf("отказы старта осмотрели НОЛЬ методов — вердикт получен на пустом наборе:\n%s", census)
	}
	t.Logf("перепись носителя: %s", strings.TrimSpace(census))
}
