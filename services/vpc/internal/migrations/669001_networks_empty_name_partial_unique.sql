-- =============================================================================
-- Пустое имя — не имя: у сети оно перестаёт занимать слот уникальности.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#669`.
--
-- ЧТО БЫЛО НЕВЕРНО. Уникальный индекс имени у сети был ПОЛНЫМ —
-- `UNIQUE (project_id, name)`, — тогда как у семи соседних ресурсов того же
-- сервиса он частичный: `WHERE name <> ''`. Перепись по `0001_initial.sql` плюс
-- `0035_cidr_groups.sql` даёт восемь таблиц с этим индексом, и полная форма была
-- ровно одна — у сети.
--
-- ПОЧЕМУ ЭТО РАСХОЖДЕНИЕ, А НЕ РЕШЕНИЕ. Контракт объявляет пустое имя законным, и
-- объявляет дважды, в двух независимых местах:
--
--   * `nameReVPC` (`pkg/validate/validate.go`) допускает пустую строку — вся
--     группа шаблона необязательна, и текст отказа говорит это словами:
--     «… up to 63 chars; empty allowed»;
--   * CHECK `networks_name_check` на ЭТОЙ ЖЕ таблице повторяет тот же шаблон,
--     то есть пустое имя разрешено самой таблицей.
--
-- Значит таблица одновременно разрешала пустое имя (CHECK) и позволяла ему
-- существовать лишь в одном экземпляре на проект (UNIQUE) — два правила об одном
-- поле, из которых исполнялось второе. Вторая сеть без имени получала 23505 →
-- ALREADY_EXISTS, тогда как второй адрес, подсеть, группа безопасности или
-- маршрутная таблица — нет. Один контракт исполнялся по-разному в зависимости от
-- ресурса, и разницу платил вызывающий.
--
-- ОБОСНОВАНИЕ ПОЛНОЙ ФОРМЫ БЫЛО ФОЛЬКЛОРОМ. `internal/migrations/README.md`
-- объяснял её словами «name никогда не пустое». Это утверждение неверно и было
-- неверно всегда: его опровергают оба места контракта выше и кейс проб
-- `NET-CR-BVA-NAME-EMPTY`, само имя которого называет пустое имя разрешённым.
-- Объяснение пережило свой предмет и читалось как решение. README поправлен тем
-- же изменением.
--
-- ЧТО ЭТА МИГРАЦИЯ НЕ МЕНЯЕТ. Уникальность НЕПУСТЫХ имён остаётся ровно прежней:
-- дубль имени в проекте по-прежнему 23505 → ALREADY_EXISTS. Меняется только
-- судьба пустой строки, которая именем не является. Имя индекса сохранено
-- дословно — на него ссылаются документация сервиса и разбор ошибок.
--
-- ПОЧЕМУ ПЕРЕСОЗДАНИЕ БЕЗОПАСНО. Новый индекс строже прежнего ни в чём: его
-- предикат отбирает подмножество строк, покрытых прежним, поэтому ни одна
-- существующая строка не может нарушить его при создании. Обратного порядка
-- (создать, потом снять) быть не может — два уникальных индекса по одному ключу
-- ужились бы, но прежний продолжал бы отвергать пустые имена, то есть предмет
-- правки остался бы нетронутым.

SET search_path TO kacho_vpc, public;

DROP INDEX IF EXISTS kacho_vpc.networks_project_id_name_key;

CREATE UNIQUE INDEX IF NOT EXISTS networks_project_id_name_key
    ON kacho_vpc.networks (project_id, name)
    WHERE name <> '';

