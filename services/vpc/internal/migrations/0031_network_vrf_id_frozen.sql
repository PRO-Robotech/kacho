-- =============================================================================
-- Координата изоляции тенант-домена сети заморожена — конструкцией базы.
-- =============================================================================
-- `networks.vrf_id` (миграция 0007) — имя изоляции, которое control-plane выдаёт
-- сети и по которому исполнитель датаплейна отличает одну изоляцию от другой.
-- Поле инфра-чувствительное: на публичной поверхности его нет, отдаётся только
-- `InternalNetworkService.GetNetwork` на cluster-internal листенере.
--
-- Такая координата обязана быть НЕИЗМЕННОЙ и НЕВЫДАВАЕМОЙ ВТОРОЙ РАЗ на всю
-- жизнь сети. Оба нарушения дают ОДИН исход, поэтому закрываются одной
-- миграцией: если значение сменило владельца — во времени (смена у живой строки)
-- или после удаления сети (повторная выдача), — то две разные изоляции в разное
-- время назывались одним именем, и исполнитель с отставшей записью применит
-- правило к ЧУЖОЙ сети. Это не оценка риска, а прямое следствие: у исполнителя
-- нет способа отличить «то же имя, тот же смысл» от «то же имя, другой смысл».
--
-- Что из этого УЖЕ держалось до 0031 (замер на дереве, предикаты приведены,
-- чтобы их можно было повторить):
--   * уникальность — `networks_vrf_id_key UNIQUE (vrf_id)` из 0007. Оставлена
--     как есть, дублировать нечем;
--   * выдача только вперёд — последовательность `networks_vrf_seq`
--     (`START WITH 101`), а не «максимум плюс один»: последняя под конкуренцией
--     выдала бы одно значение дважды. Механизм сохранён; сменилось лишь МЕСТО
--     обращения к нему (см. ниже);
--   * `NOT NULL` из 0007 — поэтому нулевого значения у живой строки нет.
--     `COALESCE(vrf_id, 0)` в пути чтения (`repo/helpers/scans.go`, NetworkCols)
--     после 0007 недостижим, и граница ниже делает 0 невыразимым и на записи:
--     ноль — доменное «координата не выдана», а у живой сети она выдана всегда.
--
-- Чего НЕ держалось (проверено исполнением на PG 16.14 до написания миграции —
-- оба случая ПРОШЛИ, то есть инвариант держался соглашением, а не базой):
--   1. смена значения у существующей строки: `UPDATE … SET vrf_id = <другое>`
--      применялась. Единственным препятствием был перечень столбцов в
--      `UPDATE networks SET …` прод-репозитория — то есть соглашение ОДНОГО
--      писателя. База обязана отвечать КАЖДОМУ: воркеру, inline-пути в чужой
--      writer-TX, административной консоли, восстановлению из дампа;
--   2. повторная выдача значения удалённой сети: `INSERT … vrf_id = <значение
--      удалённой>` применялась. Уникальность это не ловит by construction —
--      строка, которой значение принадлежало, уже удалена, и конфликтовать не с
--      чем. Последовательность защищает только то значение, которое взято ИЗ неё.
--
-- Три конструкции ниже закрывают ровно это, и ни одна не заменяет другую.

-- +goose Up
-- +goose StatementBegin
SET search_path TO kacho_vpc, public;

-- 1. Область значений — то, что доставимо исполнителю БЕЗ искажения.
--
-- Путь чтения приводит значение к uint32 (`ScanNetwork` → `safeconv.IntToUint32`),
-- а тот вне диапазона не падает, а ЗАЖИМАЕТ до 4294967295. Без границы в базе
-- две разные сети с номерами выше диапазона доехали бы до исполнителя под ОДНИМ
-- именем — то же слияние координат, против которого написана вся миграция,
-- только произведённое чтением, а не записью. Поэтому граница здесь, а не
-- «аккуратность в коде чтения»: зажим — свойство уже прочитанного значения.
--
-- Производитель входа у этой проверки РЕАЛЬНЫЙ и единственный — исчерпание
-- последовательности (~4.29e9 сетей). Исход при исчерпании — громкий отказ
-- вставки (23514), а не молчаливое слияние двух координат в одну; это осознанный
-- размен в пользу отказа. Комментарий `scans.go` про «DB-CHECK держит значение в
-- диапазоне uint32» до этой миграции был ЛОЖЕН (ни одного CHECK на vrf_id в
-- дереве не было); с ней он становится верным, а имя ограничения названо там,
-- чтобы утверждение можно было проверить, а не принять на слово.
--
-- Нижняя граница — 1, а не 101 (текущий `START WITH` последовательности):
-- ограничение обязано выражать ДОСТАВИМОСТЬ, а не сегодняшнюю точку отсчёта
-- выдачи. Вшив 101, мы получили бы ограничение, которое ломается от законной
-- смены параметров последовательности и при этом ничего дополнительно не
-- защищает.
--
-- Идемпотентность — DO-guard по pg_constraint (ALTER TABLE ADD CONSTRAINT не
-- поддерживает IF NOT EXISTS для CHECK), как в 0011/0016/0024/0027. Обратного
-- заполнения нет и быть не может: все существующие значения выданы этой же
-- последовательностью и лежат в диапазоне, поэтому валидация существующих строк
-- при ADD CONSTRAINT проходит. Если она не пройдёт — это находка, а не помеха:
-- значит в таблице есть значение, которое исполнителю уже доставлялось искажённым.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'networks_vrf_id_deliverable_range') THEN
        ALTER TABLE kacho_vpc.networks
            ADD CONSTRAINT networks_vrf_id_deliverable_range
            CHECK (vrf_id >= 1 AND vrf_id <= 4294967295);
    END IF;
END $$;
-- +goose StatementEnd

-- +goose StatementBegin
-- 2. Выдача — ТОЛЬКО из последовательности, и значение писателя не принимается.
--
-- Почему выдача переехала из `DEFAULT` в триггер, хотя последовательность та же:
-- `DEFAULT` подставляется лишь когда столбец в INSERT не назван, поэтому база не
-- может отличить «значение взято из последовательности» от «значение назвал
-- писатель» — именно так и проходило переиспользование (случай 2 выше). Без
-- `DEFAULT` столбец на входе BEFORE-триггера равен NULL ровно тогда, когда
-- писатель его не называл, и различение становится ТОЧНЫМ.
--
-- Значение писателя ОТВЕРГАЕТСЯ, а не переписывается молча: принять и выбросить
-- значило бы вернуть вызывающему успех на параметр, который не применён
-- (запрещено конвенциями API — «принято-и-проигнорировано»). Здесь это тем
-- важнее, что выброшенным оказалось бы имя изоляции.
--
-- Рассмотренная и отклонённая альтернатива — `GENERATED ALWAYS AS IDENTITY`.
-- Она отвергает значение писателя силами самой базы, но НЕ даёт заморозки:
-- проверено исполнением на PG 16.14 — `UPDATE … SET vrf_id = DEFAULT` у столбца
-- identity ПРОХОДИТ и выдаёт новое значение (наблюдалось 101 → 104), то есть
-- координата меняется. Плюс `OVERRIDING SYSTEM VALUE` остаётся штатным обходом
-- для вставки, а её отказ несёт родовой текст базы, не называющий предмет.
-- Триггер закрывает обе формы и говорит, что именно запрещено.
CREATE OR REPLACE FUNCTION kacho_vpc.kacho_network_vrf_issue()
RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.vrf_id IS NULL THEN
        NEW.vrf_id := nextval('kacho_vpc.networks_vrf_seq');
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'vrf_id is issued by the platform and cannot be supplied on Network.Create'
        USING ERRCODE = '23514',
              DETAIL  = format('network %s supplied its own vrf_id', NEW.id),
              HINT    = 'vrf_id — координата изоляции тенант-домена: она выдаётся '
                        'последовательностью kacho_vpc.networks_vrf_seq и НИКОГДА не '
                        'выдаётся второй раз, иначе исполнитель датаплейна применит '
                        'правило к чужой сети. Восстановление из дампа — единственный '
                        'законный случай явных значений: pg_restore --disable-triggers '
                        '(или session_replication_role=''replica''), он сохраняет '
                        'исходные значения. Не снимайте этот запрет, чтобы «починить» '
                        'вставку: без него значение удалённой сети можно выдать снова.';
END;
$fn$;
-- +goose StatementEnd

-- +goose StatementBegin
-- 3. Неизменяемость — смена значения у существующей строки отвергается.
--
-- Ключуется на ИЗМЕНЕНИЕ (`IS DISTINCT FROM`), а не на упоминание столбца в SET:
-- присваивание того же значения ничего не меняет и обязано проходить, иначе
-- запрет начал бы ломать законные обновления сети.
--
-- Триггер объявлен на `BEFORE UPDATE` целиком, а не на `UPDATE OF vrf_id`.
-- Второе выглядит точнее и сегодня достаточно (столбец нельзя изменить, не назвав
-- его в SET), но перестанет быть достаточным ровно в тот день, когда у таблицы
-- появится ещё один BEFORE-триггер, выставляющий NEW.vrf_id сам: тогда столбец в
-- SET не назван, и сужённый триггер не сработает. Цена общей формы — один вызов
-- на обновление сети, а обновления сети редки.
CREATE OR REPLACE FUNCTION kacho_vpc.kacho_network_vrf_frozen()
RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.vrf_id IS DISTINCT FROM OLD.vrf_id THEN
        RAISE EXCEPTION 'vrf_id is immutable after Network.Create'
            USING ERRCODE = '23514',
                  DETAIL  = format('network %s attempted to change its vrf_id', OLD.id),
                  HINT    = 'vrf_id — координата изоляции тенант-домена, выданная сети '
                            'на всю её жизнь. Сменить значение значит объявить, что две '
                            'разные изоляции в разное время назывались одним именем: '
                            'исполнитель датаплейна с отставшей записью применит правило '
                            'к чужой сети. Операции смены vrf_id не существует; сети '
                            'нужна другая изоляция — это другая сеть.';
    END IF;
    RETURN NEW;
END;
$fn$;
-- +goose StatementEnd

-- +goose StatementBegin
-- Выдача переезжает в триггер: сначала снимаем DEFAULT, потом ставим триггеры.
-- Порядок важен только для читателя — оба стейтмента в одной транзакции goose.
ALTER TABLE kacho_vpc.networks ALTER COLUMN vrf_id DROP DEFAULT;

-- CREATE OR REPLACE TRIGGER есть с PG 14, но в этом дереве принят DROP+CREATE
-- (идемпотентность без зависимости от версии).
DROP TRIGGER IF EXISTS networks_vrf_id_issue ON kacho_vpc.networks;
CREATE TRIGGER networks_vrf_id_issue
    BEFORE INSERT ON kacho_vpc.networks
    FOR EACH ROW EXECUTE FUNCTION kacho_vpc.kacho_network_vrf_issue();

DROP TRIGGER IF EXISTS networks_vrf_id_frozen ON kacho_vpc.networks;
CREATE TRIGGER networks_vrf_id_frozen
    BEFORE UPDATE ON kacho_vpc.networks
    FOR EACH ROW EXECUTE FUNCTION kacho_vpc.kacho_network_vrf_frozen();

COMMENT ON COLUMN kacho_vpc.networks.vrf_id IS
    'vrf_id — infra-sensitive tenancy isolation coordinate: internal-only surface, '
    'issued once from kacho_vpc.networks_vrf_seq, immutable and never re-issued';
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
SET search_path TO kacho_vpc, public;

-- Возврат ровно к состоянию 0007: выдача через DEFAULT той же последовательности.
DROP TRIGGER IF EXISTS networks_vrf_id_frozen ON kacho_vpc.networks;
DROP TRIGGER IF EXISTS networks_vrf_id_issue ON kacho_vpc.networks;
DROP FUNCTION IF EXISTS kacho_vpc.kacho_network_vrf_frozen();
DROP FUNCTION IF EXISTS kacho_vpc.kacho_network_vrf_issue();

ALTER TABLE kacho_vpc.networks
    ALTER COLUMN vrf_id SET DEFAULT nextval('kacho_vpc.networks_vrf_seq');
ALTER TABLE kacho_vpc.networks
    DROP CONSTRAINT IF EXISTS networks_vrf_id_deliverable_range;
COMMENT ON COLUMN kacho_vpc.networks.vrf_id IS NULL;
-- +goose StatementEnd
