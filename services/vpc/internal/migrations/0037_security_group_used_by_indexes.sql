-- =============================================================================
-- Индексы под обратную ссылку группы правил — «кем используется».
-- =============================================================================
-- Поле `used_by` группы правил объявлено контрактом с самого основания
-- репозитория и до сих пор не имело производителя: сервер его не заполнял, а
-- карточка показывала прочерк при живых потребителях. Отношение при этом уже
-- выражено базой в двух местах, и ни одно из них не индексировано под ВОПРОС
-- «кто держит эту группу»:
--
--   network_interfaces.security_group_ids  jsonb-массив идентификаторов групп.
--                                          Индексов у колонки нет вовсе, поэтому
--                                          вопрос «в чьём наборе есть эта группа»
--                                          означал бы последовательное чтение
--                                          ВСЕХ интерфейсов на каждое открытие
--                                          карточки группы.
--   networks.default_security_group_id     ссылка на группу по умолчанию. Внешний
--                                          ключ на неё объявлен миграцией 0005, но
--                                          Postgres индекс на ССЫЛАЮЩЕЙСЯ стороне
--                                          не создаёт — его надо объявить самому.
--
-- Своей таблицы обратная ссылка не заводит осознанно: отношение уже есть, и вторая
-- его копия — поддерживаемая триггером проекция вроде
-- `security_group_rule_cidr_group_refs` — понадобилась там, где ссылка живёт
-- внутри JSONB-документа И на неё нужен внешний ключ. Здесь внешний ключ не
-- нужен: обратная ссылка ничего не запрещает, она отвечает на вопрос. Платить за
-- вторую копию отношения ради ответа на вопрос — значит завести место, где копия
-- разойдётся с оригиналом молча.
--
-- ПОЧЕМУ ОТВЕТ ВСЁ РАВНО ОГРАНИЧЕН. Индекс делает дешёвым ОТБОР, но не отменяет
-- того, что интерфейсов, держащих одну группу, может быть сколько угодно:
-- потолков на число ресурсов у платформы сегодня нет (это открытый долг домена
-- квот). Поэтому запрос читает не больше предела плюс одной строки, и эта лишняя
-- строка — признак «есть ещё» (`kacho.SecurityGroupUsedByLimit`).
--
-- Идемпотентность (IF NOT EXISTS): защищает от повторного или параллельного
-- migrate-init — helm rollout запускает goose из нескольких подов.

-- +goose Up
-- +goose StatementBegin
-- Отбор «набор групп интерфейса содержит эту группу» — операция вложенности
-- (`@>`) над jsonb. Её обслуживает GIN; класс операторов `jsonb_path_ops` взят
-- намеренно: он строит записи только под вложенность, поэтому меньше и быстрее
-- умолчательного `jsonb_ops`, а ничего, кроме вложенности, этой колонке и не
-- задают. Проверять существование ключа или искать по значению отдельного
-- элемента здесь никто не будет — колонка хранит плоский массив идентификаторов.
CREATE INDEX IF NOT EXISTS network_interfaces_security_group_ids_gin
    ON kacho_vpc.network_interfaces USING gin (security_group_ids jsonb_path_ops);
-- +goose StatementEnd

-- +goose StatementBegin
-- Отбор «сеть держит эту группу по умолчанию» — равенство по одной колонке.
--
-- Индекс ЧАСТИЧНЫЙ по `IS NOT NULL`, и предикат выписан именно так, а не через
-- сравнение с пустой строкой. Колонка стала NULL-able миграцией 0005 (пустая
-- строка тогда же переведена в NULL, потому что внешний ключ на '' невозможен —
-- группы с таким идентификатором не существует), поэтому «нет группы по
-- умолчанию» здесь записано NULL, и сети без группы в индекс не входят.
--
-- Предикат `<> ''` был бы не только неточным описанием колонки, но и НЕРАБОЧИМ:
-- чтобы применить частичный индекс, планировщик обязан доказать, что условие
-- запроса влечёт условие индекса. Из `col = $1` следует `col IS NOT NULL`
-- (оператор строгий), но НЕ следует `col <> ''` — параметр мог бы оказаться
-- пустой строкой. Индекс существовал бы и не использовался ни разу.
CREATE INDEX IF NOT EXISTS networks_default_security_group_idx
    ON kacho_vpc.networks (default_security_group_id)
 WHERE default_security_group_id IS NOT NULL;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP INDEX IF EXISTS kacho_vpc.networks_default_security_group_idx;
-- +goose StatementEnd

-- +goose StatementBegin
DROP INDEX IF EXISTS kacho_vpc.network_interfaces_security_group_ids_gin;
-- +goose StatementEnd
