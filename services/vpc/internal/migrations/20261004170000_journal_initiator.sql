-- =============================================================================
-- Журнал vpc несёт ИНИЦИАТОРА изменения; строки без него не существует.
-- =============================================================================
-- Задача `PRO-Robotech/kacho#2918` (полоса S1-A1); приёмка
-- `docs/specs/sub-phase-NTF-3-kacho-modules-notifications-acceptance.md`, решение
-- Р2 и сценарий NTF3-62 (строка журнала без инициатора или времени не пишется),
-- заказ УК3-28 (переиспользованное соединение).
--
-- ЕДИНСТВЕННЫЙ ПРОИЗВОДИТЕЛЬ ЗНАЧЕНИЯ — УМОЛЧАНИЕ КОЛОНКИ. Его читает настройка
-- `kacho_journal.initiator`, которую помощник транзакции записи журнала
-- (`corelib/journaltx`, `SettingInitiator`) выставляет ЛОКАЛЬНО к транзакции.
-- Оператор вставки в журнал колонку не называет — ни на Go, ни в функциях базы,
-- пишущих журнал (`subnets_outbox_emit_route_table_change`). Поэтому функции НЕ пересобираются: их строки получают
-- инициатора тем же умолчанием.
--
-- ОТСУТСТВИЕ — ОТКАЗ, А НЕ ПОДСТАНОВКА. Настройка не выставлена — `current_setting(…,
-- true)` даёт NULL; выставлена пустой строкой (так её оставляет соединение после
-- локальной установки в прошлой транзакции) — `NULLIF` делает пустое тем же NULL.
-- `NOT NULL` отвергает строку `23502` с именем колонки `initiator`, и на свежем, и
-- на переиспользованном соединении одинаково; изменение ресурса откатывается
-- вместе со строкой журнала, которую оно вызвало.
--
-- ФОРМА — ОГРАНИЧЕНИЕ `vpc_outbox_initiator_form` (`23514`). Три типа субъекта Р2, у
-- каждого — семейство из каталога приставок `corelib/ids` в обеих формах записи
-- (слитной `usr…` и дефисной `usr-…`):
--   * `user:` — только приставка пользователя (`ids.PrefixUser`), поэтому
--     `user:system.…` и `user:sva-…` отвергаются сами по себе;
--   * `service_account:` — только приставка сервисного аккаунта
--     (`ids.PrefixServiceAccount`);
--   * `system:` — имя компонента формы DNS-метки (`validate/nameform.Form`).
-- Тело id — алфавит Crockford base32 (`ids.crockfordAlphabet`; регистр, как у
-- Crockford, не различается) длиной 1..17. Точную форму тела (17 строчных
-- символов) судит единственный производитель значения `auth.InitiatorOf`;
-- ограничение базы — рубеж ТИПА И СЕМЕЙСТВА, и оно обязано пропускать близнеца
-- NTF3-62 `user:usr-A`, которого приёмка утверждает вставленным.
--
-- ВРЕМЯ СТРОКИ — существующая колонка `created_at` (`NOT NULL DEFAULT now()`); новой
-- колонки времени нет (замысел З2).
--
-- НЕПУСТОЙ ЖУРНАЛ. Умолчание вычисляется для существующих строк в момент миграции,
-- когда инициатора нет, и миграция отказывает `23502`: стенды поднимаются заново
-- (решение Д12 приёмки — прода нет, прямое переключение).

-- +goose Up
SET search_path TO kacho_vpc, public;
ALTER TABLE kacho_vpc.vpc_outbox
    ADD COLUMN initiator text NOT NULL
        DEFAULT NULLIF(current_setting('kacho_journal.initiator', true), '')
        CONSTRAINT vpc_outbox_initiator_form
            CHECK (initiator ~ '^(user:usr-?[0-9a-hjkmnp-tv-zA-HJKMNP-TV-Z]{1,17}|service_account:sva-?[0-9a-hjkmnp-tv-zA-HJKMNP-TV-Z]{1,17}|system:[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?)$');

-- +goose Down
SET search_path TO kacho_vpc, public;
ALTER TABLE kacho_vpc.vpc_outbox DROP COLUMN IF EXISTS initiator;
