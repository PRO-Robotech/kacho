-- +goose Up
-- Таблица серверных курсоров подписки снимается: читателя у неё нет, а форма её
-- приглашает отменить решение о том, где живёт позиция потока.
--
-- Задача `PRO-Robotech/kacho#1148`; тот же класс закрыт для compute задачей
-- `PRO-Robotech/kacho#1046`, и разбор оттуда здесь не повторяется — повторяется
-- только то, что относится к vpc.
--
-- ЧТО СНИМАЕТСЯ. `kacho_vpc.vpc_watch_cursors` заведена базовой схемой (0001):
-- `subscriber_id` первичным ключом, `last_sequence_no` и `updated_at` рядом.
-- Прод-читателя у неё нет ни одного — ни запроса, ни вставки, ни обновления.
-- Перепись велась не по имени таблицы, а по её колонкам, потому что имя таблицы
-- можно и не написать: вхождений `subscriber_id` вне миграций и документации в
-- дереве ноль, `last_sequence_no` — только в самих миграциях, типа `WatchCursor`
-- в Go нет вовсе. За всю жизнь таблицы в неё не писал никто.
--
-- ПОЧЕМУ ЭТО НЕ ПРОСТО МЁРТВЫЙ КОД. Позиция подписки принадлежит КЛИЕНТУ: он
-- присылает курсор, сервер состояния не держит. Отсюда следует свойство, ради
-- которого решение и принято, — поток переживает переподключение К ДРУГОЙ
-- РЕПЛИКЕ, потому что новой реплике нечего про подписчика помнить. Общий сервер
-- потока это уже исполняет: операторов записи в нём ноль.
--
-- Таблица серверных курсоров ПО ПОДПИСЧИКУ выглядит указанием обратного. Автор
-- следующей фазы, увидев её в схеме, естественно заключит, что позицию положено
-- хранить на сервере, — и решение будет отменено не спором, а тем, что схема
-- выглядела приглашением. Цена такой отмены выше цены мёртвого кода: мёртвый код
-- подбирают и выбрасывают, а отменённое решение обнаруживается прогоном, на
-- котором поток не пережил переподключения.
--
-- ПОЧЕМУ СНЯТИЕ, А НЕ КОММЕНТАРИЙ В СХЕМЕ. Документация сервиса уже называла эту
-- таблицу vestigial — то есть предмет был назван, а таблица осталась, и следующий
-- читатель схемы видел таблицу, а не строку в чужом документе. Комментарий
-- переживает своё основание и читается как описание действительности; снятая
-- таблица не переживает ничего. Приглашения не остаётся, когда не остаётся
-- приглашающего.
--
-- ЧТО ТЕРЯЕТСЯ. Ничего, что создал бы вызывающий: строк в таблице нет и не было,
-- поверхности для их создания не существовало ни на одном слушателе. Ноль строк
-- здесь не предполагается, а ПРОВЕРЯЕТСЯ: запись в `dropguard.json` объявляет
-- ожидание, и гейт снятий пересчитывает его на пустой базе, проигрывая цепочку до
-- версии перед этой.
DROP TABLE IF EXISTS kacho_vpc.vpc_watch_cursors;

-- +goose Down
-- Возврат в форму базовой схемы (0001), чтобы откат приходил в то состояние, из
-- которого Up вышел. Строк не восстанавливается, потому что их не было.
--
-- Откат возвращает и приглашение: следующий, читающий схему после него, снова
-- увидит серверные курсоры по подписчику. Решение о том, что позиция принадлежит
-- клиенту, от этого не меняется — оно записано здесь и в приёмке фазы, а не в
-- наличии или отсутствии таблицы.
CREATE TABLE kacho_vpc.vpc_watch_cursors (
    subscriber_id    text         NOT NULL PRIMARY KEY,
    last_sequence_no bigint       NOT NULL DEFAULT 0,
    updated_at       timestamptz  NOT NULL DEFAULT now()
);
