-- 20260822120000_address_indexes_without_own_subject — три индекса таблицы
-- адресов сняты: собственного предмета у них не осталось (kacho#963).
--
-- ───────────────────────────────────────────────────────────────────────────
-- РАДИУС ВЗЯТ ПО МЕХАНИЗМУ, А НЕ ПО ЗАДАЧЕ
--
-- Задача называла ОДИН дубль — постраничный индекс по паре (проект, подсеть)
-- против курсорного по подсети. Перепись индексов таблицы (их семь) показала
-- ТРИ индекса, чей предикат целиком покрыт префиксом другого:
--
--   addresses_project_subnet_page_idx   (project_id, internal_subnet_id, created_at, id)
--                                        WHERE internal_subnet_id IS NOT NULL
--   addresses_project_idx               (project_id)
--   addresses_internal_subnet_idx       (internal_subnet_id)
--
-- Первый — предмет задачи; второй и третий — тот же класс, найденный переписью.
-- Оставшиеся курсорные индексы содержат их ключи ПРЕФИКСОМ:
--
--   addresses_project_cursor_idx        (project_id, created_at, id)          — 708001
--   addresses_subnet_cursor_idx         (internal_subnet_id, created_at, id)  — 912001
--
-- Индекс по префиксу отвечает на всякий вопрос, на который отвечал бы индекс
-- по этому префиксу отдельно: равенство по ведущей колонке ищется тем же
-- спуском по дереву. Поэтому снятие второго и третьего не меняет плана
-- ни у одного чтения и ни у одной проверки ссылочной целостности.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ИЗ ПАРЫ ОСТАЁТСЯ КУРСОРНЫЙ, А НЕ ПОСТРАНИЧНЫЙ
--
-- Чтений с фильтром по подсети ДВА, и они разные:
--
--   публичный список адресов   `?subnet_id=` — предикат подсети идёт ПОСЛЕ проекта;
--   дочерний список подсети                  — предикат подсети идёт ПЕРВЫМ, проекта нет вовсе.
--
-- Курсорный отвечает обоим: второму — прямо, первому — равенством по подсети
-- плюс дешёвый отбор по проекту поверх, причём отбрасывать ему нечего:
-- подсеть принадлежит одному проекту, значит все её адреса — одного проекта.
-- Постраничный второму чтению НЕ отвечает by construction: его ведущая
-- колонка не задана, и спуск по дереву начать не с чего.
--
-- Обратное решение (оставить постраничный) потребовало бы держать оба.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО ЭТО СТОИЛО, ПОКА ИХ БЫЛО ДВА
--
-- Планировщик выбирал между ними ПО СТАТИСТИКЕ, то есть от наполнения таблицы,
-- и проба, утверждавшая имя индекса, падала не на дефекте, а на распределении
-- данных. Утверждение тогда перевели с имени на предикат — обход, а не решение:
-- имя вернётся в утверждение вместе с этой миграцией (п.3 предиката снятия).
--
-- Плюс постоянная цена: каждая вставка и правка адреса обновляла ТРИ лишних
-- дерева, и все три занимали буферный кеш, вытесняя оттуда страницы, за
-- которыми ходят на самом деле.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО ВЕРНЁТ ИХ ОБРАТНО
--
-- Чтение, спрашивающее пару (проект, подсеть) БЕЗ курсорного порядка и
-- страдающее от отбора по проекту, — то есть подсеть, чьи адреса принадлежат
-- разным проектам. Сегодня такого не бывает; заведётся — индекс вернётся
-- ВМЕСТЕ с этим чтением, а не вперёд него.
--
-- CONCURRENTLY: таблица адресов пишется на пути запроса (выдача адреса
-- инициатору), и останавливать её запись ради снятия индекса нечем оправдать.

-- +goose NO TRANSACTION
-- +goose Up

DROP INDEX CONCURRENTLY IF EXISTS kacho_vpc.addresses_project_subnet_page_idx;
DROP INDEX CONCURRENTLY IF EXISTS kacho_vpc.addresses_project_idx;
DROP INDEX CONCURRENTLY IF EXISTS kacho_vpc.addresses_internal_subnet_idx;

-- +goose Down

CREATE INDEX CONCURRENTLY IF NOT EXISTS addresses_project_subnet_page_idx
    ON kacho_vpc.addresses (project_id, internal_subnet_id, created_at, id)
    WHERE internal_subnet_id IS NOT NULL;

CREATE INDEX CONCURRENTLY IF NOT EXISTS addresses_project_idx
    ON kacho_vpc.addresses (project_id);

CREATE INDEX CONCURRENTLY IF NOT EXISTS addresses_internal_subnet_idx
    ON kacho_vpc.addresses (internal_subnet_id);
