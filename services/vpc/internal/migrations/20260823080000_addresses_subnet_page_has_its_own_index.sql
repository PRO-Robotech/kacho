-- 20260823080000_addresses_subnet_page_has_its_own_index — постраничный индекс
-- пары (проект, подсеть) возвращён: посылка, по которой его сняли, ОПРОВЕРГНУТА
-- замером.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО УТВЕРЖДАЛА СНЯВШАЯ ЕГО МИГРАЦИЯ И ЧТО ОКАЗАЛОСЬ
--
-- 20260822120000 сняла три индекса как «без собственного предмета» и обосновала
-- снятие постраничного так: курсорный по подсети отвечает публичному списку
-- «равенством по подсети плюс дешёвый отбор по проекту поверх», а значит
-- снятие «не меняет плана ни у одного чтения».
--
-- Довод верен про ДАННЫЕ и неверен про ПЛАНИРОВЩИК. Планировщик не знает, что
-- подсеть принадлежит одному проекту; он видит ДВА равенства и два индекса, из
-- которых каждый покрывает ровно одно, и выбирает между ними по оценке. Второй
-- вариант — курсорный по проекту — берёт проект ведущей колонкой и отбрасывает
-- фильтром всё, что не в подсети.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЗАМЕР, А НЕ ПРЕДПОЛОЖЕНИЕ
--
-- Восемь прогонов интеграционной пробы `…_NarrowBySubnet_PlanIsPagePriced` на
-- дереве без этого индекса: семь зелёных, один красный. В красном план брал
-- курсорный по проекту и тронул 272 строки ради страницы в 51 — «Rows Removed
-- by Filter: 221» при бюджете 102. Оценки двух планов почти совпадают
-- (55.51 против сопоставимой у второго), поэтому выбор решает статистика, а она
-- меняется с наполнением таблицы.
--
-- То же наблюдалось в конвейере на СЕМИ ветках, ни одна из которых каталога vpc
-- не касалась: 274 · 303 · 210 · 335 · 211 · 265 · 229 тронутых строк — одна и
-- та же проба, один и тот же неверный индекс, разное наполнение.
--
-- Стоимость ошибки растёт вместе с проектом: доля подсети в таблице адресов
-- проекта — величина произвольная, и при сотне подсетей страница вкладки
-- оплачивается сотней страниц.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ПОЧЕМУ ИМЕННО ЭТА ФОРМА
--
-- Индекс покрывает ОБА равенства публичного списка и его порядок целиком:
--
--     WHERE project_id = $1 AND internal_subnet_id = $2 ORDER BY created_at, id
--
-- поэтому отбрасывать ему нечего, а порядок приходит из дерева, а не из
-- сортировки. Курсорный по подсети остаётся и остаётся нужным: дочерний список
-- подсети идёт БЕЗ проекта, а у этого индекса ведущая колонка — проект, значит
-- спуск по дереву начать не с чего. Два чтения — два индекса; это цена, которую
-- сняли и вернули, измерив.
--
-- Два других индекса, снятых 20260822120000 (`addresses_project_idx`,
-- `addresses_internal_subnet_idx`), НЕ возвращаются: их довод — «префикс
-- курсорного отвечает на тот же вопрос» — про планировщик тоже верен, потому
-- что у них ОДНО равенство, и спор между вариантами не возникает.
--
-- ───────────────────────────────────────────────────────────────────────────
-- ЧТО СНИМЕТ ЕГО СНОВА
--
-- Не «он выглядит дублем», а замер: план публичного списка, суженного по
-- подсети, укладывается в бюджет страницы БЕЗ него — на наполнении, где доля
-- подсети в проекте мала. Проба `…_NarrowBySubnet_PlanIsPagePriced` этот замер
-- и есть; она обязана оставаться зелёной без послаблений.
--
-- CONCURRENTLY: таблица адресов пишется на пути запроса (выдача адреса
-- инициатору), и останавливать её запись ради заведения индекса нечем оправдать.

-- +goose NO TRANSACTION
-- +goose Up

CREATE INDEX CONCURRENTLY IF NOT EXISTS addresses_project_subnet_page_idx
    ON kacho_vpc.addresses (project_id, internal_subnet_id, created_at, id)
    WHERE internal_subnet_id IS NOT NULL;

-- +goose Down

DROP INDEX CONCURRENTLY IF EXISTS kacho_vpc.addresses_project_subnet_page_idx;
