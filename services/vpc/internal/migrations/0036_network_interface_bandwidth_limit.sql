-- =============================================================================
-- Верхняя граница полосы интерфейса, заданная арендатором
-- =============================================================================
-- Арендатор вправе ограничить полосу СВОЕГО интерфейса сверху. Величина хранится
-- на самом интерфейсе — это его настройка, а не свойство подсети, сети или зоны:
-- поле, зависящее от чего-то из перечисленного, означало бы разные обещания у
-- одной и той же платформы в разных местах.
--
-- НОЛЬ — ЭТО «НЕ ЗАДАНО», И ЭТО ЕДИНСТВЕННОЕ ПРЕДСТАВЛЕНИЕ ОТСУТСТВИЯ. Колонка
-- `NOT NULL DEFAULT 0`, а не nullable: два способа сказать «ограничения нет»
-- (NULL и 0) однажды разъехались бы, и сравнение по одному перестало бы совпадать
-- со сравнением по другому. Ограничение в ноль мегабит означало бы интерфейс без
-- связи — такой просьбы не существует, поэтому ноль свободен под «не задано».
--
-- ЧТО ИМЕННО ДЕРЖИТ ЭТА ПРОВЕРКА, А ЧТО — НЕТ (граница названа прямо)
--
-- Промежуток приёма — (пол продукта; гарантия, объявленная ЭТИМ стендом]. Из двух
-- краёв на уровне БД выразим ровно один: нижний. Он — постоянная продукта
-- (`domain.GuaranteedInterfaceBandwidthFloorMbps`, «не менее 1 Гбит/с на
-- интерфейс»), одинаковая на каждом стенде, поэтому её можно вморозить в схему.
-- Верхний край — объявление ПОСАДКИ (`dataplane.executor.
-- guaranteed-bandwidth-per-interface-mbps`); вморозить его в CHECK значило бы
-- завести второе место для настройки, которое разойдётся с первым при первой же
-- правке значений и потребует миграции на каждый стенд.
--
-- Поэтому здесь стоит инвариант, который от посадки НЕ зависит: величина либо
-- «не задано», либо строго выше опубликованного пола. Он ловит то, что путь
-- запроса пропустить не вправе ни при какой настройке: строку, которая
-- противоречит обещанию платформы самой себе. Верхний край остаётся за путём
-- запроса — и он там проверяется тем же предикатом, который читает страж старта.
--
-- Число 1000 повторено здесь и в `domain.GuaranteedInterfaceBandwidthFloorMbps` —
-- два места об одном предмете. Расхождение видимо: интеграционная проба
-- `migration_0036_bandwidth_limit_integration_test.go` берёт границу ИЗ
-- КОНСТАНТЫ и предъявляет её базе, поэтому смена константы без правки схемы
-- краснеет, а не расходится молча.

ALTER TABLE kacho_vpc.network_interfaces
    ADD COLUMN IF NOT EXISTS bandwidth_limit_mbps bigint NOT NULL DEFAULT 0;

ALTER TABLE kacho_vpc.network_interfaces
    ADD CONSTRAINT network_interfaces_bandwidth_limit_check
        CHECK (bandwidth_limit_mbps = 0 OR bandwidth_limit_mbps > 1000);

-- +goose Down

ALTER TABLE kacho_vpc.network_interfaces
    DROP CONSTRAINT IF EXISTS network_interfaces_bandwidth_limit_check;

ALTER TABLE kacho_vpc.network_interfaces
    DROP COLUMN IF EXISTS bandwidth_limit_mbps;
