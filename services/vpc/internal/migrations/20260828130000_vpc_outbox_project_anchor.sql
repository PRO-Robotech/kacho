-- +goose NO TRANSACTION
-- +goose Up
-- Журнал изменений vpc получает ЯКОРЬ ПРОЕКТА колонкой.
--
-- Задача `PRO-Robotech/kacho#1023` (провязка общего сервера потока, `pkg/subscription`).
-- Тот же класс закрыт для compute задачей `PRO-Robotech/kacho#1019`; разбор оттуда
-- здесь не повторяется — повторяется только то, что относится к vpc, и добавляется
-- то, чего у compute не было.
--
-- ЗАЧЕМ. Общая форма подписки несёт проектный якорь полем ОБОЛОЧКИ события, и по
-- нему принимается решение «кому это показать» — без обращения к предмету. Для
-- события снятия это несущее: обращаться не к чему, предмета больше нет, а
-- нагрузка у снятия беднее всего — она несёт один идентификатор
-- (`map[string]any{"id": id}` на всех пятнадцати путях снятия vpc).
--
-- ПОЧЕМУ НЕ РАЗБОР НАГРУЗКИ. Общая форма допускает и его. У создания и правки
-- якорь в нагрузке есть; у снятия его нет. Значит разбор дал бы у снятий ПУСТОЙ
-- якорь, а пустой якорь по контракту означает «предмет уровня аккаунта или
-- кластера» — утверждение, ложное для сети, подсети и всякого проектного предмета
-- vpc. Дальше подписка с осью `project_id` такие события не пропускала бы, и
-- потребитель, снявший опрос, НИКОГДА не узнавал бы об удалении. Отказ наступает
-- ТИХО: ни ошибки, ни пропуска в нумерации.
--
-- ЧЕГО У compute НЕ БЫЛО: У ЖУРНАЛА vpc ДВА ПРОИЗВОДИТЕЛЯ, И КЛЮЧИ У НИХ РАЗНЫЕ.
-- Первый — код (`Outbox().Emit`, 52 места): нагрузка собирается обходом
-- `encoding/json` по доменной структуре, у которой поле проекта объявлено БЕЗ
-- своего имени, поэтому ключ нагрузки — имя поля Go, `ProjectID`.
-- Второй — САМА БАЗА: триггер `subnets_outbox_emit_route_table_change` (0001)
-- вставляет `Subnet`/`UPDATED` при авто-привязке таблицы маршрутов, и строит
-- нагрузку через `jsonb_build_object`, где тот же якорь назван `project_id`.
-- Два ключа одного якоря в одном журнале — поэтому обратное заполнение ниже
-- спрашивает ОБА, а не тот, который попался первым. Спроси оно один ключ, вторая
-- половина журнала осталась бы без якоря, и потеря была бы тихой ровно там, где
-- события порождает не код, а база.
--
-- ПОЧЕМУ ВНЕ ОБЩЕЙ ТРАНЗАКЦИИ. Сборка индекса без параллельного режима берёт на
-- таблице замок, разделяемый с чтением, но НЕ с записью: всякая вставка в журнал
-- ждала бы конца сборки, а вставка в журнал идёт в той же транзакции, что и
-- мутация ресурса, — то есть вставали бы и мутации. Такова же конвенция дерева:
-- ей следуют миграции, собирающие индексы параллельно.
--
-- Цена режима названа: шаги перестают быть атомарными между собой, поэтому каждый
-- обязан быть ПОВТОРИМ. Сборка индекса вдобавок умеет оставить негодный индекс при
-- обрыве — его снимает предусловие ниже, до сборки.
ALTER TABLE kacho_vpc.vpc_outbox ADD COLUMN IF NOT EXISTS project_id TEXT NOT NULL DEFAULT '';

-- ОБРАТНОЕ ЗАПОЛНЕНИЕ — по тому, что в нагрузке ЕСТЬ, и не более. Оба ключа, в
-- порядке «код, затем база»: у одной строки бывает ровно один из них, поэтому
-- порядок здесь не выбор политики, а перечисление.
--
-- Историческим СНЯТИЯМ заполнять якорь НЕОТКУДА: их нагрузка несёт только
-- идентификатор, а строка ресурса к этому моменту удалена. Такие строки остаются
-- с пустым якорем, и это названо прямо, а не замаскировано: суждение о показе
-- снятия идёт по якорю, поэтому строка без якоря вызывающему не показывается.
-- Умолчание пустой строкой, а не NULL, — та же форма, что у соседних журналов.
UPDATE kacho_vpc.vpc_outbox
   SET project_id = COALESCE(payload->>'ProjectID', payload->>'project_id')
 WHERE project_id = ''
   AND COALESCE(payload->>'ProjectID', payload->>'project_id') IS NOT NULL;

-- +goose StatementBegin
-- ВТОРОЙ ПРОИЗВОДИТЕЛЬ УЧИТСЯ ПИСАТЬ ЯКОРЬ. Без этого обратное заполнение выше
-- закрыло бы прошлое, а будущее продолжало бы копить строки без якоря — те самые
-- `Subnet`/`UPDATED`, что рождает авто-привязка таблицы маршрутов. Подписчик с осью
-- проекта не увидел бы ни одной из них, и это был бы ровно тот тихий отказ, против
-- которого заведён якорь.
--
-- Применённую 0001 не редактируем (ban #5) — тело функции заменяется здесь.
-- Замена, а не новый триггер: два триггера на одном событии писали бы ДВЕ строки
-- журнала на одну правку, и подписчик увидел бы двойное изменение.
CREATE OR REPLACE FUNCTION kacho_vpc.subnets_outbox_emit_route_table_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO kacho_vpc.vpc_outbox (resource_kind, resource_id, project_id, event_type, payload)
    VALUES (
        'Subnet',
        NEW.id,
        NEW.project_id,
        'UPDATED',
        jsonb_build_object(
            'id', NEW.id,
            'project_id', NEW.project_id,
            'network_id', NEW.network_id,
            'route_table_id', NEW.route_table_id,
            'name', NEW.name,
            'auto_association', true
        )
    );
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

-- Негодный индекс, оставшийся обрывом предыдущей попытки, снимается ДО сборки:
-- `IF NOT EXISTS` его не пересобирает — он видит имя занятым и молчит, и тогда
-- отбор по оси проекта шёл бы без индекса, ничем об этом не сообщая.
-- +goose StatementBegin
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_index i
          JOIN pg_class c ON c.oid = i.indexrelid
          JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE c.relname = 'vpc_outbox_project_idx'
           AND n.nspname = 'kacho_vpc'
           AND NOT i.indisvalid
    ) THEN
        EXECUTE 'DROP INDEX kacho_vpc.vpc_outbox_project_idx';
    END IF;
END
$$;
-- +goose StatementEnd

-- Частичный индекс, а не полный: строки без якоря по нему не отбираются никогда
-- (подписка с осью проекта их не спрашивает), и держать их в индексе значило бы
-- платить за то, что не читается. Пара «якорь, номер» — ровно порядок, которым
-- читает поток: отбор по проекту с продвижением по возрастанию номера.
CREATE INDEX CONCURRENTLY IF NOT EXISTS vpc_outbox_project_idx
    ON kacho_vpc.vpc_outbox (project_id, sequence_no) WHERE project_id <> '';

-- +goose NO TRANSACTION
-- +goose Down
-- Возврат в форму без якоря.
--
-- ЧТО ТЕРЯЕТСЯ, И ЭТО НЕ ВОССТАНОВИТСЯ. Якоря уходят вместе с колонкой. Повторное
-- применение заполнит заново только те строки, у которых якорь ЕСТЬ В НАГРУЗКЕ, —
-- то есть создания и правки. Строки СНЯТИЯ, записанные уже с якорем в колонке,
-- источника в нагрузке не имеют (там один идентификатор) и после отката получат
-- пустой якорь навсегда: восстанавливать их не из чего.
--
-- Сказано прямо, потому что читать это будут при откате и под давлением. Потеря
-- неизбежна и сама по себе не порок — порок был бы в обещании восстановления,
-- которого не происходит.
DROP INDEX CONCURRENTLY IF EXISTS kacho_vpc.vpc_outbox_project_idx;

-- +goose StatementBegin
-- Тело триггера возвращается к форме 0001 — без якоря.
CREATE OR REPLACE FUNCTION kacho_vpc.subnets_outbox_emit_route_table_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO kacho_vpc.vpc_outbox (resource_kind, resource_id, event_type, payload)
    VALUES (
        'Subnet',
        NEW.id,
        'UPDATED',
        jsonb_build_object(
            'id', NEW.id,
            'project_id', NEW.project_id,
            'network_id', NEW.network_id,
            'route_table_id', NEW.route_table_id,
            'name', NEW.name,
            'auto_association', true
        )
    );
    RETURN NEW;
END;
$$;
-- +goose StatementEnd

ALTER TABLE kacho_vpc.vpc_outbox DROP COLUMN IF EXISTS project_id;
