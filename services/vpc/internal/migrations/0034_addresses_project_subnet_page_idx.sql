-- =============================================================================
-- Страница адресов подсети стоит страницу, а не подсеть.
-- =============================================================================
-- Публичный список адресов принимает сужение по подсети (`ListAddresses?subnet_id=`),
-- и вкладка адресов под подсетью — его единственный потребитель, у которого
-- альтернативы нет: подсеть адреса лежит внутри jsonb и в ДВУХ семьях, поэтому
-- выражением `filter` по имени колонки она не выражается вовсе.
--
-- Сужение при этом было верно наполовину: оно ОТБИРАЛО правильное множество и
-- стоило чтения таблицы адресов всех проектов (дизъюнкция jsonb-выражений, которую
-- не покрывает ни один индекс). Дочерний список подсети переведён на хранимую
-- колонку `internal_subnet_id` ещё миграцией 0025 — публичный остался на
-- дизъюнкции, то есть один и тот же вопрос стоил в двух местах по-разному.
-- Предикат публичного списка приведён к той же колонке (см. репозиторий адресов);
-- эта миграция даёт ему индекс.
--
-- Почему НОВЫЙ индекс, а не уже существующий `addresses_internal_subnet_idx`
-- -----------------------------------------------------------------------------
-- Тот индекс несёт одну колонку подсети и обслуживает ДРУГОЙ запрос — дочерний
-- список, у которого проекта в предикате нет. Публичный список спрашивает иначе:
--
--     WHERE project_id = $1 AND internal_subnet_id = $2
--     ORDER BY created_at ASC, id ASC LIMIT <страница+1>
--
-- По индексу из одной колонки строки приходят БЕЗ порядка, поэтому курсорная
-- страница из 50 строк оплачивается сортировкой ВСЕХ адресов подсети — при
-- объявленной плотности (тысячи адресов в проекте) это цена на каждый тик опроса
-- вкладки. Порядок обязан приходить из индекса, а не из узла сортировки, поэтому
-- в индекс входят и ключи курсора.
--
-- Ни один из двух индексов другой не замещает: у нового ведущая колонка —
-- проект, поэтому дочерний список (без проекта в предикате) равенством по нему
-- воспользоваться не может и остаётся на своём. Это не дублирование, а два
-- разных вопроса.
--
-- Почему ЧАСТИЧНЫЙ
-- -----------------------------------------------------------------------------
-- Подсеть есть только у внутреннего адреса; у внешнего `internal_subnet_id` равен
-- NULL, и таких строк в зрелом проекте много. В индексе они — вес без единого
-- запроса: спрашивают всегда равенством по конкретной подсети. Планировщик
-- выводит `internal_subnet_id IS NOT NULL` из `internal_subnet_id = $2`, поэтому
-- частичность применимости индекса не сужает.

SET search_path TO kacho_vpc, public;

CREATE INDEX IF NOT EXISTS addresses_project_subnet_page_idx
    ON kacho_vpc.addresses (project_id, internal_subnet_id, created_at, id)
    WHERE internal_subnet_id IS NOT NULL;

