package config

import (
	"github.com/PRO-Robotech/kacho/pkg/grpcsrv"
)

// RateLimitConfig — секция `api-server.rate-limit`: сколько запросов в секунду и
// сколько одновременно вправе задать ОДИН вызывающий каждому листенеру.
//
// # Почему листенеров ДВА, а не один набор на процесс
//
// У них разные вызывающие и разная стоимость ошибки, и общий набор был бы
// решением, принятым за оба сразу:
//
//   - ПУБЛИЧНЫЙ листенер зовёт арендатор через край. Ключ — личность конечного
//     пользователя; величины — опубликованный ПОЛ продукта, ниже которого
//     арендатор вправе не опускаться;
//   - ВНУТРЕННИЙ листенер зовут наши же модули по проверенному сертификату. Ключ
//     — личность СЕРТИФИКАТА, а не арендатора: запрос модуля несёт личности
//     разных арендаторов, и ключ по арендатору дробил бы бюджет соседа на тысячу
//     вёдер. Величины — заведомо выше рабочих, и это не щедрость, а требование:
//     ограничитель, задушивший наш собственный поток намерения, воспроизводит
//     заклинивание головы очереди — класс, при котором работа перестаёт доезжать
//     БЕЗ ЕДИНОГО ВИДИМОГО СИМПТОМА, потому что «работает» и «не доехало»
//     выглядят одинаково.
//
// # Почему это настройка, а не константа
//
// Опубликованные числа — пол продукта, но исполняются они ведром В ПРОЦЕССЕ: при
// N репликах эффективный предел равен N × объявленного. Значит посадка обязана
// уметь назвать свои величины (одна реплика или двадцать — разный запас), и
// вписанный в код литерал описывал бы один стенд.
//
// А раз это настройка, у неё есть состояние «не задана», и оно НЕ безобидно:
// нулевые величины означают «не ограничиваем», а не «ограничивать нечего».
// Ограничитель тогда либо не навешивается вовсе, либо навешивается пустым — и в
// обоих случаях выглядит включённым, ни разу не отказав. Боевая посадка с
// необъявленными величинами НЕ ПОДНИМАЕТСЯ (Config.ValidateRequestRateLimits).
type RateLimitConfig struct {
	// Public — величины публичного листенера (:9090), на ПРИНЦИПАЛА.
	Public AdmissionLimitsConfig `mapstructure:"public"`
	// Internal — величины внутреннего листенера (:9091), на ЛИЧНОСТЬ
	// СЕРТИФИКАТА.
	Internal AdmissionLimitsConfig `mapstructure:"internal"`
}

// AdmissionLimitsConfig — четыре оси допуска ОДНОГО листенера.
//
// Читать эти поля напрямую нельзя — только через Config.PublicAdmissionLimits /
// Config.InternalAdmissionLimits: страж старта, самоотчёт о посадке и проводка
// обязаны спрашивать ОДНО значение и ОДИН его предикат непустоты
// (grpcsrv.AdmissionLimits.IsDeclared). Разойдясь здесь, они разошлись бы ровно
// там, где расхождение опасно, — «страж доволен, а листенер не ограничен».
type AdmissionLimitsConfig struct {
	// ReadPerSec — устойчивый темп ЧТЕНИЙ на вызывающего, запросов в секунду.
	// Чтение стоит до 1000 объектов на страницу с проверкой прав партиями.
	ReadPerSec float64 `mapstructure:"read-per-sec"`

	// MutationPerSec — устойчивый темп МУТАЦИЙ на вызывающего. Ниже темпа
	// чтений намеренно: каждая мутация — три строки в базе (ресурс, очередь
	// намерения, операция).
	MutationPerSec float64 `mapstructure:"mutation-per-sec"`

	// BurstFactor — во сколько раз всплеск превышает устойчивый темп. Значение
	// меньше единицы — самопротиворечие, отвергаемое в любом режиме.
	BurstFactor float64 `mapstructure:"burst-factor"`

	// InFlight — предел ОДНОВРЕМЕННЫХ запросов на вызывающего. Отдельная ось от
	// темпа, и сводить их в одну нельзя: одновременность ограничивает стоимость
	// одного мгновения независимо от `page_size`, чего темп сам по себе не
	// делает.
	InFlight int `mapstructure:"in-flight"`
}

// limits переводит объявление посадки в значение, которое понимает носитель.
func (a AdmissionLimitsConfig) limits() grpcsrv.AdmissionLimits {
	return grpcsrv.AdmissionLimits{
		ReadPerSec:     a.ReadPerSec,
		MutationPerSec: a.MutationPerSec,
		BurstFactor:    a.BurstFactor,
		InFlight:       a.InFlight,
	}
}

// PublicAdmissionLimits — величины публичного листенера.
//
// ЕДИНСТВЕННЫЙ законный способ прочитать одноимённую секцию настроек: значение
// одно на процесс, и его спрашивают страж старта, самоотчёт о посадке и
// композиционный корень.
func (c Config) PublicAdmissionLimits() grpcsrv.AdmissionLimits {
	return c.APIServer.RateLimit.Public.limits()
}

// InternalAdmissionLimits — величины внутреннего листенера. Тот же контракт
// единственного источника, что у PublicAdmissionLimits.
func (c Config) InternalAdmissionLimits() grpcsrv.AdmissionLimits {
	return c.APIServer.RateLimit.Internal.limits()
}
