package networkinterface

// Интерфейс с пустым набором групп НАСЛЕДУЕТ группу по умолчанию своей сети.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ: обещание контракта, у которого не было исполнителя
//
// Комментарий поля `security_group_ids` обещает: «Дефолт при создании —
// default_security_group_id сети (наследуется); можно переопределить». Подстановок в
// коде было НОЛЬ: интерфейс с пустым набором получал пустой набор.
//
// Почему это хуже обычного невыполненного обещания. Модель закрыта в обе стороны:
// нет правила — значит не разрешено. Значит пустой набор — это не «настройки по
// умолчанию», а «не разрешено ничего», и обещанное умолчание работало
// ПРОТИВОПОЛОЖНО обещанию. Обнаруживалось это не отказом на создании, а тишиной на
// трафике — то есть в чужой отладке.
//
// ПОЧЕМУ ЭТО ЧАСТЬ ОДНОГО ИЗМЕНЕНИЯ С БЕЗУСЛОВНОСТЬЮ ГРУППЫ. Наследовать можно
// только то, что есть. Пока создание группы по умолчанию было условным, между
// снятием условности и наследованием существовало состояние «сеть жива, группы нет,
// интерфейс уже наследует» — и в нём интерфейс получал бы пустой набор снова.
// Раздельная посадка это состояние создаёт, поэтому она запрещена.

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestInheritedSecurityGroups(t *testing.T) {
	const netDefault = "sgr-net-default"

	for _, tc := range []struct {
		name         string
		explicit     []string
		defaultGroup string
		want         []string
		why          string
	}{
		{
			name:         "пустой набор наследует группу сети",
			explicit:     nil,
			defaultGroup: netDefault,
			want:         []string{netDefault},
			why: "это и есть обещание контракта; без него пустой набор означает " +
				"«не разрешено ничего», то есть противоположное обещанному",
		},
		{
			name:         "явный выбор сильнее наследования",
			explicit:     []string{"sgr-mine-1", "sgr-mine-2"},
			defaultGroup: netDefault,
			want:         []string{"sgr-mine-1", "sgr-mine-2"},
			why: "положительный контроль: без него утверждение выше зеленело бы на " +
				"реализации, которая ВСЕГДА подставляет группу сети и затирает выбор",
		},
		{
			name:         "пустая группа сети наследования не даёт",
			explicit:     nil,
			defaultGroup: "",
			want:         nil,
			why: "подставить пустую строку в набор ссылок значило бы завести висячую " +
				"ссылку вместо отсутствия — сеть, заведённая до того, как создание группы " +
				"стало безусловным, обязана давать отсутствие, а не мусор",
		},
		{
			name:         "явный выбор при пустой группе сети сохраняется",
			explicit:     []string{"sgr-mine-1"},
			defaultGroup: "",
			want:         []string{"sgr-mine-1"},
			why:          "второй положительный контроль: наследование не вмешивается в явный выбор",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := inheritedSecurityGroups(tc.explicit, tc.defaultGroup)
			assert.Equal(t, tc.want, got, tc.why)
		})
	}
}
