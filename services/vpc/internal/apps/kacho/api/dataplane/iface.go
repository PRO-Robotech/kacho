// Package dataplane — шов между control plane и исполнителем датаплейна:
// доставка НАМЕРЕНИЯ потоком и приём ПОДТВЕРЖДЕНИЯ применения.
//
// # Что здесь решается
//
// Control plane объявляет намерение (сеть, подсеть, интерфейс, адрес, правило,
// шлюз, маршрут), исполнитель его применяет. Три свойства делают этот шов
// работающим, и ни одно из них не является украшением:
//
//  1. ПОЛНАЯ ВЫДАЧА. Поток не источник истины. Исполнитель, пропустивший
//     сколько угодно изменений, обязан уметь начать с нуля — иначе один
//     пропуск оставляет его в рассинхроне навсегда, и заметить это нечем.
//  2. РЕВИЗИЯ ОБЪЕКТА. Каждое сообщение несёт монотонную ревизию НАМЕРЕНИЯ
//     этого объекта. По ней исполнитель отличает «применил устаревшее» от
//     «применил новое», а после разрыва знает, с чего продолжить. Ревизия
//     выдаётся базой в порядке фиксации транзакций (миграция 0032), поэтому
//     «всё, что ≤ N, я видел» — верное утверждение, а не надежда.
//  3. ЧЕСТНЫЙ ИСХОД ВМЕСТО МОЛЧАНИЯ. Продолжить с названной позиции не всегда
//     возможно: след мог быть уплотнён, позиции могло не существовать вовсе, а
//     медленный получатель мог исчерпать предел незавершённых сообщений. Во
//     всех трёх случаях ответ — отдельное сообщение «начни с полной выдачи», а
//     не тишина: потерянное изменение неотличимо от непришедшего.
//
// # Слои
//
// Пакет определяет ПОРТЫ ([IntentReader], [ApplyRecorder]) и не знает ни про
// pgx, ни про gRPC-сервер. Адаптер портов живёт в `internal/repo/dataplane`,
// транспорт — тонкий [Handler] в этом же пакете (как у ресурсных use-case'ов
// vpc).
package dataplane

import (
	"context"
	"errors"
	"time"

	kachorepo "github.com/PRO-Robotech/kacho/services/vpc/internal/repo/kacho"
)

// Kind — вид объекта намерения. Значения совпадают со словарём столбца
// `kacho_vpc.dataplane_intent.kind`, закрытым CHECK-ограничением миграции 0032:
// вид вне словаря не сохраняется, поэтому сюда он и не доедет.
type Kind string

// Виды объектов, составляющих намерение для датаплейна.
const (
	KindNetwork          Kind = "network"
	KindSubnet           Kind = "subnet"
	KindNetworkInterface Kind = "network_interface"
	KindSecurityGroup    Kind = "security_group"
	KindRouteTable       Kind = "route_table"
	KindGateway          Kind = "gateway"
	KindAddress          Kind = "address"
)

// KnownKinds — перечень видов в том же составе, что и словарь базы.
//
// Существует ради ОДНОГО утверждения, которое иначе никто не сделает: каждая
// ветвь контракта потока имеет вид, а каждый вид — ветвь. Проба
// `TestEveryKindHasAContractBranch` обходит этот перечень; вид, добавленный в
// базу и забытый здесь, доехал бы до исполнителя ничем.
var KnownKinds = []Kind{
	KindNetwork, KindSubnet, KindNetworkInterface, KindSecurityGroup,
	KindRouteTable, KindGateway, KindAddress,
}

// IntentRow — одна строка проекции намерения.
//
// # Почему семь именованных указателей, а не `any`
//
// Тело строки — запись ровно одного вида, и вид уже назван полем [IntentRow.Kind].
// `any` заставил бы читателя приводить тип на каждом использовании и допускал бы
// пару «вид один, тело другого» без единого возражения компилятора. Семь полей
// шумнее в объявлении и строже в употреблении; проверку «ровно одно тело и оно
// соответствует виду» несёт [IntentRow.Validate], а не соглашение.
//
// У снятого намерения (`Withdrawn`) тело отсутствует ЦЕЛИКОМ: полей удалённого
// ресурса не существует, и досочинять их значило бы утверждать о состоянии,
// которого нет. Для адресации достаточно `ResourceID` — он неизменяем и
// глобально уникален (запрет #15).
type IntentRow struct {
	Revision   int64
	ResourceID string
	Kind       Kind
	Withdrawn  bool

	Network          *kachorepo.NetworkRecord
	Subnet           *kachorepo.SubnetRecord
	NetworkInterface *kachorepo.NetworkInterfaceRecord
	SecurityGroup    *kachorepo.SecurityGroupRecord
	RouteTable       *kachorepo.RouteTableRecord
	Gateway          *kachorepo.GatewayRecord
	Address          *kachorepo.AddressRecord
}

// ErrRowShape — строка проекции не имеет формы, в которой её можно отдать.
var ErrRowShape = errors.New("dataplane: строка намерения не имеет формы, пригодной для доставки")

// Validate проверяет форму строки: у живого намерения ровно одно тело, и оно
// того вида, который назван; у снятого тела нет вовсе.
//
// Проверка нужна не «на всякий случай»: строка собирается адаптером из ДВУХ
// источников — курсора проекции и таблицы ресурса, — и рассогласование между
// ними означает, что исполнителю поехало бы пустое тело под видом объявленного
// намерения. Пустое тело неотличимо от «все поля сброшены».
func (r IntentRow) Validate() error {
	bodies := 0
	matched := false
	check := func(present bool, kind Kind) {
		if !present {
			return
		}
		bodies++
		if r.Kind == kind {
			matched = true
		}
	}
	check(r.Network != nil, KindNetwork)
	check(r.Subnet != nil, KindSubnet)
	check(r.NetworkInterface != nil, KindNetworkInterface)
	check(r.SecurityGroup != nil, KindSecurityGroup)
	check(r.RouteTable != nil, KindRouteTable)
	check(r.Gateway != nil, KindGateway)
	check(r.Address != nil, KindAddress)

	switch {
	case r.ResourceID == "":
		return errors.New("dataplane: строка намерения без идентификатора ресурса")
	case r.Revision <= 0:
		return errors.New("dataplane: строка намерения с неположительной ревизией")
	case r.Withdrawn && bodies != 0:
		return errors.New("dataplane: снятое намерение несёт тело — у удалённого ресурса полей нет")
	case r.Withdrawn:
		return nil
	case bodies == 0:
		return errors.New("dataplane: живое намерение без тела")
	case bodies > 1:
		return errors.New("dataplane: живое намерение несёт больше одного тела")
	case !matched:
		return errors.New("dataplane: тело намерения не того вида, который назван строкой")
	default:
		return nil
	}
}

// Bounds — границы журнала намерения.
//
// Обе величины снимаются ОДНИМ обращением: разнесённые во времени, они дали бы
// пару, которой ни в один момент не существовало, и решение о том, продолжать
// ли поток, принималось бы по несуществующему состоянию.
type Bounds struct {
	// Horizon — наибольшая ревизия, чей след уже уплотнён. Позиция ниже неё
	// могла пропустить снятие намерения, и продолжать с неё нельзя.
	Horizon int64
	// Head — наибольшая выданная ревизия. Позиция выше неё не существует.
	Head int64
}

// IntentReader — чтение проекции намерения.
type IntentReader interface {
	// Bounds возвращает горизонт уплотнения и голову журнала.
	Bounds(ctx context.Context) (Bounds, error)

	// Page возвращает строки с ревизией строго больше after, в порядке
	// возрастания ревизии, не более limit штук.
	//
	// skipWithdrawnUpTo исключает снятые намерения с ревизией не выше
	// названной. Предмет — ПЕРВАЯ выдача: объект, удалённый до подписки,
	// исполнителю никогда не отдавался, и его надгробие для него шум. Величина,
	// а не флаг, потому что граница здесь несущая: снятие, случившееся ПОСЛЕ
	// начала выдачи, отдать обязаны — объект мог быть уже отправлен ранней
	// страницей, и пропуск его надгробия оставил бы применённое навсегда.
	Page(ctx context.Context, after, skipWithdrawnUpTo int64, limit int) ([]IntentRow, error)
}

// ApplyOutcome — чем кончилось применение намерения у исполнителя.
type ApplyOutcome string

// Исходы применения. Значения совпадают со словарём столбца
// `kacho_vpc.dataplane_apply.outcome`.
const (
	OutcomeApplied ApplyOutcome = "APPLIED"
	OutcomeFailed  ApplyOutcome = "FAILED"
)

// FailureReason — КЛАСС причины отказа исполнителя.
//
// Именно класс, а не текст: свободной строки в этом контракте нет ни на одном
// уровне — ни в proto, ни в столбце, — поэтому имя интерфейса на узле, номер
// порта коммутатора или идентификатор туннеля физически некуда положить.
// Проекция состояния арендатору безопасна по построению, а не по внимательности
// пишущего.
type FailureReason string

// Классы отказа. Значения совпадают со словарём CHECK-ограничения
// `dataplane_apply_reason_matches_outcome`.
const (
	ReasonNone               FailureReason = ""
	ReasonCapacity           FailureReason = "CAPACITY"
	ReasonConflict           FailureReason = "CONFLICT"
	ReasonUnsupported        FailureReason = "UNSUPPORTED"
	ReasonDependencyNotReady FailureReason = "DEPENDENCY_NOT_READY"
	ReasonTransient          FailureReason = "TRANSIENT"
	ReasonExecutorInternal   FailureReason = "EXECUTOR_INTERNAL"
)

// ApplyReport — что исполнитель сообщает о применении.
type ApplyReport struct {
	ResourceID string
	Revision   int64
	Outcome    ApplyOutcome
	Reason     FailureReason
}

// ApplyRecord — что платформа записала в ответ на подтверждение.
type ApplyRecord struct {
	// Recorded — подтверждение записано. false означает, что оно СТАРЕЕ уже
	// записанного и за свежее не засчитано.
	Recorded bool
	// CurrentRevision — ревизия намерения, действующая у платформы сейчас.
	CurrentRevision int64
}

// ErrIntentUnknown — намерения с таким идентификатором у платформы нет.
var ErrIntentUnknown = errors.New("dataplane: намерения с таким идентификатором нет")

// ErrRevisionNotIssued — платформа не выдавала этому объекту такой ревизии.
var ErrRevisionNotIssued = errors.New("dataplane: ревизия этому объекту не выдавалась")

// ApplyRecorder — запись подтверждения применения.
type ApplyRecorder interface {
	// Record атомарно записывает подтверждение.
	//
	// Возвращает [ErrIntentUnknown], если намерения нет, и
	// [ErrRevisionNotIssued], если названная ревизия выше действующей: такой
	// ревизии этому объекту платформа не выдавала, и принять отчёт о ней
	// значило бы записать применение того, чего не объявляли.
	Record(ctx context.Context, rep ApplyReport) (ApplyRecord, error)
}

// Величины потока. Ручками конфигурации они НЕ являются намеренно: каждая —
// свойство самого шва, а не посадки, и ни одна не имеет осмысленного значения,
// которое оператор выбирал бы под свой стенд. Названы константами, чтобы их
// можно было найти поиском и обсудить как контракт.
const (
	// PageLimit — сколько строк проекции читается одним обращением.
	//
	// Величина ограничивает не поток, а РАЗМЕР ОДНОГО ЧТЕНИЯ: страница читается
	// в снимке вместе с телами, и слишком крупная держала бы снимок дольше, чем
	// нужно. Догоняющий исполнитель получает столько страниц подряд, сколько
	// нужно, — предела на догон нет.
	PageLimit = 200

	// PendingLimit — предел НЕЗАВЕРШЁННЫХ сообщений на один поток.
	//
	// Ради него написана половина этого пакета: медленный исполнитель не вправе
	// копить у сервера неограниченную очередь — она принадлежит процессу,
	// обслуживающему ВСЕХ, и её рост есть исчерпание памяти для всех сразу.
	// Превышение не отбрасывает сообщение молча (потерянное неотличимо от
	// непришедшего), а переводит поток в «начни с полной выдачи».
	//
	// Величина выбрана так, чтобы одна прочитанная страница целиком помещалась
	// в очередь: иначе предел срабатывал бы на КАЖДОМ догоне даже у исправного
	// исполнителя, и «начни сначала» стало бы штатным ответом на штатную работу.
	PendingLimit = 2 * PageLimit

	// PendingStallBudget — сколько источник ЖДЁТ места в очереди, прежде чем
	// объявить переполнение.
	//
	// Величина отделяет «получатель отстал» от «получатель не забирает», и это
	// различение — весь предмет предела. Полная очередь сама по себе не значит
	// ничего: источник читает журнал страницами и легко опережает получателя на
	// планировщике. Объявив переполнением каждую полную очередь, мы отправляли бы
	// исправного исполнителя на полную пересинхронизацию по расписанию
	// операционной системы — то есть предел срабатывал бы там, где защищать
	// нечего, и его пришлось бы отключить.
	//
	// Ожидание при этом БЕЗОПАСНО: снимок базы к моменту ожидания уже закрыт
	// (страница прочитана целиком), поэтому источник ждёт, ничего не удерживая, а
	// память по-прежнему ограничена ёмкостью очереди.
	//
	// Полминуты — величина, при которой исполнитель, не забравший НИ ОДНОГО
	// сообщения, честно называется не забирающим.
	PendingStallBudget = 30 * time.Second

	// PollInterval — как часто проверяется появление новых ревизий, когда поток
	// уже догнал голову журнала.
	//
	// Выбран опрос, а не оповещение базы: оповещение требует отдельного
	// соединения ВНЕ пула на каждый поток, то есть ресурса, который при отказе
	// исполнителя копится там, где пул его не считает. Цена опроса названа
	// прямо: задержка доставки не превышает этой величины, а простаивающий
	// поток стоит одного индексного чтения за интервал.
	PollInterval = 500 * time.Millisecond

	// TombstoneRetention — сколько лежит СНЯТОЕ намерение, прежде чем его след
	// уплотняется.
	//
	// Величина отвечает на один вопрос: на сколько исполнителю позволено
	// отстать, не теряя права продолжить с известной позиции. Трое суток
	// покрывают выходные и разбор аварии; отставший дольше получает честное
	// «начни с полной выдачи» вместо молчаливо пропущенного удаления.
	TombstoneRetention = 72 * time.Hour

	// CompactInterval — как часто уплотняется журнал.
	//
	// Уплотнение — не срочная работа: срок хранения на три порядка больше
	// интервала, поэтому запаздывание на час не меняет ничего, кроме размера
	// таблицы.
	CompactInterval = time.Hour

	// MaxConcurrentStreams — сколько подписок обслуживается одновременно.
	//
	// Предел существует потому, что каждая подписка держит горутину, очередь до
	// PendingLimit сообщений и периодическое чтение. Исполнителей датаплейна
	// единицы; величина оставляет запас на перекрытие старой и новой подписки
	// при перекатывании и отсекает случай, когда клиент переподключается в
	// цикле, не закрывая прежние потоки.
	MaxConcurrentStreams = 32
)
