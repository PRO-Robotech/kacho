package dataplane

import (
	"context"
	"fmt"
	"sync/atomic"
	"time"

	vpcv1 "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/vpc/v1"
)

// pending — очередь незавершённых сообщений ОДНОГО потока.
//
// # Почему очередь вообще есть
//
// Чтение журнала и отправка получателю разнесены: чтение держит снимок базы,
// отправка ждёт получателя. Соединив их напрямую, мы держали бы снимок ровно
// столько, сколько тормозит исполнитель. Очередь разрывает эту связь — и тем
// самым заводит место, которое может расти.
//
// # Почему она ОГРАНИЧЕНА, и что происходит на границе
//
// Очередь принадлежит процессу, обслуживающему всех арендаторов. Неограниченная,
// она превращает медленного исполнителя в исчерпание памяти для всех сразу.
// Поэтому предел жёсткий, а исход на границе — НЕ молчаливое отбрасывание:
// выброшенное сообщение неотличимо для получателя от неслучившегося изменения,
// то есть тихая потеря оставляет датаплейн расходящимся с намерением навсегда.
// Единственный честный исход — объявить переполнение и заставить исполнителя
// начать с полной выдачи.
//
// Ёмкость канала И ЕСТЬ предел: длина канала не может превысить его ёмкость, и
// свойство «не выросла» здесь держится конструкцией, а не сложением в уме.
type pending struct {
	ch       chan *vpcv1.WatchIntentResponse
	limit    int
	stall    time.Duration
	overflow atomic.Bool
}

// newPending собирает очередь. Непозитивный предел — ошибка сборки, а не вход:
// такая очередь отвергала бы КАЖДОЕ сообщение, то есть переводила бы в полную
// пересинхронизацию любой поток при исправном получателе.
func newPending(limit int, stall time.Duration) *pending {
	if limit <= 0 {
		panic(fmt.Sprintf("dataplane: предел незавершённых сообщений обязан быть положительным, получено %d", limit))
	}
	if stall <= 0 {
		panic(fmt.Sprintf("dataplane: срок ожидания получателя обязан быть положительным, получено %v", stall))
	}
	return &pending{ch: make(chan *vpcv1.WatchIntentResponse, limit), limit: limit, stall: stall}
}

// offerResult — исход постановки сообщения в очередь.
//
// Исходов ТРИ, и сводить их к булеву значению нельзя: «получатель не забирает» и
// «поток гасят» требуют разных действий и по-разному считаются. Сведённые в
// один, они дали бы счётчик переполнений, равный числу перезапусков процесса, —
// то есть наблюдаемость предела перестала бы значить что-либо.
type offerResult int

const (
	// offerAccepted — сообщение принято очередью.
	offerAccepted offerResult = iota
	// offerStalled — срок ожидания истёк, места так и нет: получатель не
	// забирает. Поток обязан завершиться указанием начать с полной выдачи.
	offerStalled
	// offerAborted — контекст отменён: подписку гасят. Переполнением это не
	// является.
	offerAborted
)

// Offer кладёт сообщение в очередь, ожидая места не дольше объявленного срока.
//
// # Быстрый путь не спрашивает отмену — и это не оптимизация
//
// Пока в очереди есть место, сообщение принимается БЕЗУСЛОВНО. Спроси мы здесь
// про отмену, `select` получил бы две готовые ветви и выбирал бы между ними
// СЛУЧАЙНО: тот же поток то доставлял бы страницу, то объявлял бы гашение, и оба
// исхода выглядели бы работающими, пока кто-нибудь не прочтёт журнал. Отмена
// спрашивается только там, где выбора нет, — в ожидании места.
//
// # Почему ожидание, а не немедленный отказ
//
// Полная очередь сама по себе не означает беды: источник читает журнал
// страницами и легко опережает получателя на планировщике. Отказав немедленно,
// мы объявляли бы переполнением обычную разницу в скорости и отправляли бы
// исправного исполнителя на полную пересинхронизацию по расписанию
// операционной системы — предел срабатывал бы там, где защищать нечего.
//
// Ожидание безопасно: страница журнала к этому моменту прочитана целиком и
// снимок базы закрыт, поэтому источник ждёт, ничего не удерживая. Память
// по-прежнему ограничена ёмкостью очереди — ждущее сообщение в ней не лежит.
func (p *pending) Offer(ctx context.Context, msg *vpcv1.WatchIntentResponse) offerResult {
	select {
	case p.ch <- msg:
		return offerAccepted
	default:
	}

	timer := time.NewTimer(p.stall)
	defer timer.Stop()
	select {
	case p.ch <- msg:
		return offerAccepted
	case <-ctx.Done():
		return offerAborted
	case <-timer.C:
		p.overflow.Store(true)
		return offerStalled
	}
}

// Len — сколько сообщений ждёт отправки.
func (p *pending) Len() int { return len(p.ch) }

// Limit — объявленный предел.
func (p *pending) Limit() int { return p.limit }

// Overflowed — предел был исчерпан хотя бы раз за жизнь очереди.
func (p *pending) Overflowed() bool { return p.overflow.Load() }

// C — сторона получателя.
func (p *pending) C() <-chan *vpcv1.WatchIntentResponse { return p.ch }

// Close закрывает очередь: производитель закончил. Получатель дочитывает
// принятое и видит закрытие как конец выдачи.
func (p *pending) Close() { close(p.ch) }
