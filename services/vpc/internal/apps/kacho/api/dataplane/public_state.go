// public_state.go — ПУБЛИЧНАЯ проекция подтверждения применения.
//
// # Предмет
//
// Шов принимает от исполнителя подтверждение: оно durable, класс причины отказа
// закрыт перечислением, ревизия сверяется. До этого файла всё это было видно
// ТОЛЬКО в базе — арендатор видел свой ресурс как ни в чём не бывало, тогда как
// исполнитель его не применил. Отказ существовал и не доходил до того, кого
// касается.
//
// # Что именно сообщается арендатору — и почему ровно это
//
// Две вещи и ни одной больше: применено ли намерение ТЕКУЩЕЙ ревизии, и — если
// нет и исполнитель отчитался отказом — КЛАСС причины из закрытого словаря.
//
// Ни имени узла, ни интерфейса, ни туннеля, ни кода ядра здесь нет, и положить
// их сюда НЕКУДА: [FailureReason] — перечисление, а не строка, и оно закрыто на
// трёх уровнях сразу (CHECK-ограничение столбца, словарь контракта, проверка
// этого файла). Свойство держится конструкцией, а не внимательностью пишущего:
// публичное поле, по которому опознаётся конкретная реализация фабрики, есть
// дефект дизайна, а не подробность.
//
// # Это НЕ статус ресурса
//
// Статуса у сети, шлюза и группы безопасности нет намеренно — у него нет
// производителя, и миграция 0003 дропнула столбец состояния группы ровно за это.
// Здесь производитель ЕСТЬ (подтверждение исполнителя, таблица
// `kacho_vpc.dataplane_apply`), но предмет другой: не жизненный цикл ресурса, а
// применение ОДНОЙ его ревизии. Ресурс существует и корректен независимо от
// того, что ответил исполнитель; поле отвечает на «доехало ли моё последнее
// изменение», а не на «жив ли объект».
//
// # Почему сравнение ревизий, а не флаг
//
// Подтверждение в базе — про ту ревизию, о которой отчитался исполнитель, и
// сама по себе запись «применено» ничего не говорит о СЕГОДНЯШНЕМ намерении:
// арендатор мог поменять ресурс после отчёта. Поэтому состояние выводится
// СРАВНЕНИЕМ (`applied_revision` против `revision` намерения), а не чтением
// одного столбца. Отсюда же берётся тонкая половина правила: устаревший ОТКАЗ
// не приписывается новому намерению — иначе арендатор чинил бы причину, которой
// у его текущего изменения нет.

// KnownFailureReasons — закрытый словарь классов отказа, ЕДИНЫМ перечнем.
//
// Единственный источник для трёх читателей: приёма подтверждения
// (`validateReport`), этой проекции и проб. Второй перечень разошёлся бы с
// первым молча — и разошёлся бы именно там, где расхождение не видно: класс,
// добавленный в контракт и забытый в проверке, отвергался бы у исполнителя, а
// класс, забытый здесь, не доезжал бы до арендатора.
//
// Состав совпадает со словарём CHECK-ограничения
// `dataplane_apply_reason_matches_outcome` (миграция 0032). Расхождение с ним
// наблюдаемо: значение из базы вне этого перечня даёт [ErrApplyRowShape], а не
// молчаливое «не применено».
var KnownFailureReasons = []FailureReason{
	ReasonCapacity,
	ReasonConflict,
	ReasonUnsupported,
	ReasonDependencyNotReady,
	ReasonTransient,
	ReasonExecutorInternal,
}

// knownReasonSet — тот же словарь для проверки принадлежности.
var knownReasonSet = func() map[FailureReason]struct{} {
	m := make(map[FailureReason]struct{}, len(KnownFailureReasons))
	for _, r := range KnownFailureReasons {
		m[r] = struct{}{}
	}
	return m
}()

// ErrApplyRowShape — строка подтверждения не имеет формы, из которой можно
// сделать утверждение о состоянии.
//
// Попасть сюда значение может ровно одним способом: словарь базы разошёлся с
// этим кодом (сами столбцы закрыты CHECK-ограничениями). Отказ, а не корзина
// «прочее»: свернув расхождение в «не применено», проекция сообщала бы
// арендатору правдоподобную неправду и пережила бы собственный предмет.
var ErrApplyRowShape = errors.New("dataplane: строка подтверждения не имеет годной формы")

// PublicApplyState — что видит АРЕНДАТОР о применении своего намерения.
//
// Ровно два поля. Третьего здесь быть не может — состав закреплён пробой
// `TestPublicProjectionCarriesExactlyTwoFacts`, которая падает на любом
// добавленном поле и называет его: инфра-чувствительное приезжает в такие
// проекции по одному полю за раз, и каждое по отдельности выглядит безобидной
// подробностью.
type PublicApplyState struct {
	// Applied — намерение ТЕКУЩЕЙ ревизии подтверждено исполнителем как
	// применённое. false означает «не подтверждено», а не «сломано»: сюда
	// попадают и ещё не дошедшие до исполнителя изменения.
	Applied bool

	// Reason — класс отказа. Непуст ТОЛЬКО когда исполнитель отчитался отказом
	// именно по текущей ревизии. Пустое значение при `Applied == false` означает
	// «отказа не было» (намерение в работе), и это разные вещи: арендатору,
	// получившему пустой класс, чинить нечего — надо ждать.
	Reason FailureReason
}

// ApplyReportRow — пара «намерение ↔ подтверждение», как она лежит в базе.
//
// [ApplyReportRow.Reported] отделяет ОТСУТСТВИЕ подтверждения от его значения:
// без него «подтверждения нет» и «подтверждение с нулевой ревизией» стали бы
// одним состоянием, а различать их обязательно — первое штатно, второе означает
// испорченную строку.
type ApplyReportRow struct {
	// IntentRevision — действующая ревизия намерения (`dataplane_intent.revision`).
	IntentRevision int64
	// Reported — подтверждение по этому объекту существует.
	Reported bool
	// AppliedRevision — ревизия, о которой отчитался исполнитель.
	AppliedRevision int64
	// Outcome — чем кончилось применение той ревизии.
	Outcome ApplyOutcome
	// Reason — класс отказа той ревизии.
	Reason FailureReason
}

// PublicState сводит строку базы к тому, что видит арендатор.
//
// Порядок: сначала форма (негодная строка — отказ, а не состояние), затем
// сравнение ревизий, затем исход. Возвращает [ErrApplyRowShape] обёрнутым, с
// названным значением: отказ без значения заставляет искать расхождение
// словарей вслепую.
func (r ApplyReportRow) PublicState() (PublicApplyState, error) {
	if err := r.validate(); err != nil {
		return PublicApplyState{}, err
	}
	// Подтверждения нет вовсе, либо оно про ДРУГУЮ ревизию. В обоих случаях о
	// текущем намерении исполнитель не сказал ничего — и придумывать за него
	// нельзя ни успех, ни причину отказа.
	//
	// Строгое равенство, а не `>=`: ревизии выше действующей платформа этому
	// объекту не выдавала (её отвергает приём подтверждения), поэтому такая
	// строка означала бы рассогласование, а не «применено с запасом».
	if !r.Reported || r.AppliedRevision != r.IntentRevision {
		return PublicApplyState{}, nil
	}
	if r.Outcome == OutcomeApplied {
		return PublicApplyState{Applied: true}, nil
	}
	return PublicApplyState{Applied: false, Reason: r.Reason}, nil
}

// validate отвергает формы, в которых строка не описывает никакого состояния.
//
// Проверяется ВСЯ строка, а не только та её часть, что влияет на ответ при
// текущей ревизии: испорченная строка испорчена независимо от того, совпала ли
// ревизия, и заметить расхождение словарей надо в тот прогон, когда оно
// появилось, а не тогда, когда до него случайно дойдёт сравнение.
func (r ApplyReportRow) validate() error {
	if r.IntentRevision <= 0 {
		return fmt.Errorf("%w: ревизия намерения %d неположительна", ErrApplyRowShape, r.IntentRevision)
	}
	if !r.Reported {
		// Подтверждения нет — остальным полям взяться неоткуда, и требовать от
		// них словаря значило бы требовать значения от отсутствия.
		if r.AppliedRevision != 0 || r.Outcome != "" || r.Reason != ReasonNone {
			return fmt.Errorf("%w: подтверждения нет, а его поля заполнены", ErrApplyRowShape)
		}
		return nil
	}
	if r.AppliedRevision <= 0 {
		return fmt.Errorf("%w: ревизия подтверждения %d неположительна", ErrApplyRowShape, r.AppliedRevision)
	}
	switch r.Outcome {
	case OutcomeApplied:
		if r.Reason != ReasonNone {
			return fmt.Errorf("%w: у успеха стоит класс отказа %q", ErrApplyRowShape, r.Reason)
		}
	case OutcomeFailed:
		if _, ok := knownReasonSet[r.Reason]; !ok {
			return fmt.Errorf("%w: класс отказа %q вне закрытого словаря", ErrApplyRowShape, r.Reason)
		}
	default:
		return fmt.Errorf("%w: исход %q вне закрытого словаря", ErrApplyRowShape, r.Outcome)
	}
	return nil
}

// PublicStateReader — чтение публичной проекции подтверждений.
//
// Порт объявлен ЗДЕСЬ, у use-case-слоя, а реализован адаптером
// (`internal/repo/dataplane`) — как и остальные порты этого пакета.
type PublicStateReader interface {
	// PublicApplyStates возвращает состояние по названным объектам ОДНИМ
	// обращением.
	//
	// Партия, а не вызов на идентификатор: стоимость страницы принадлежит
	// запросу, и список из пятидесяти строк не вправе становиться пятьюдесятью
	// обращениями к базе.
	//
	// Объект, о котором сказать нечего (намерения нет либо оно снято), в карте
	// ОТСУТСТВУЕТ — отсутствие представимо отдельно от значения, и вызывающий
	// отличает «нет данных» от «не применено» проверкой наличия ключа, а не
	// сравнением с нулём.
	PublicApplyStates(ctx context.Context, resourceIDs []string) (map[string]PublicApplyState, error)
}
