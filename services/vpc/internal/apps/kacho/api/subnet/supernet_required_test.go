package subnet

// supernet_required_test.go — сеть без объявленного супернета семейства НЕ
// принимает подсеть этого семейства.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Контракт заявляет безусловно: каждый CIDR подсети обязан быть подмножеством
// одного из блоков сети. Код делал исключение — пустой супернет ПРОПУСКАЛ
// проверку целиком, и в такой сети принимался любой CIDR. Поле при этом не
// обязательно на создании сети, то есть пустой супернет — не редкость, а штатное
// состояние: ограничение, ради которого поле существует, не действовало.
//
// Почему выбран отказ, а не ослабление текста контракта. Нарезать не из чего:
// без объявленного блока у сети нет адресного плана, и «подсеть» перестаёт быть
// частью чего-либо — остаётся произвольный диапазон, у которого с соседями по
// сети нет отношения, кроме непересечения. Путь вперёд существует и уже
// поставлен: объявить блоки через :add-cidr-blocks и создать подсеть после.
//
// Почему прежняя оговорка не защитима. Она ссылалась на совместимость, не
// называя ни того, чья это совместимость, ни предиката снятия, — послабление,
// которое не истекает само и потому переживает свой повод.

import (
	"strings"
	"testing"

	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

func TestSubnetRefusedWhenNetworkDeclaresNoSupernetOfThatFamily(t *testing.T) {
	for _, tc := range []struct {
		name    string
		netV4   []string
		netV6   []string
		subV4   []string
		subV6   []string
		wantErr bool
		family  string
	}{
		{
			name:    "v4-подсеть в сети без v4-супернета",
			subV4:   []string{"10.77.7.0/24"},
			wantErr: true,
			family:  "IPv4",
		},
		{
			name:    "v6-подсеть в сети без v6-супернета",
			netV4:   []string{"10.0.0.0/8"},
			subV6:   []string{"fd00::/64"},
			wantErr: true,
			family:  "IPv6",
		},
		{
			// Отсутствие супернета ЧУЖОГО семейства не касается: подсеть его не
			// использует, и отказ был бы про то, чего не просили.
			name:  "v4-подсеть в сети, объявившей только v4",
			netV4: []string{"10.0.0.0/8"},
			subV4: []string{"10.77.7.0/24"},
		},
		{
			name:  "v6-подсеть в сети, объявившей только v6",
			netV6: []string{"fd00::/48"},
			subV6: []string{"fd00::/64"},
		},
		{
			// Положительное рядом с отрицаниями: без него «отказ» зеленел бы и на
			// реализации, отвергающей всё подряд.
			name:  "обе семьи объявлены и подсеть в них укладывается",
			netV4: []string{"10.0.0.0/8"},
			netV6: []string{"fd00::/48"},
			subV4: []string{"10.77.7.0/24"},
			subV6: []string{"fd00::/64"},
		},
		{
			// Прежнее поведение проверки сохраняется: блок вне объявленного
			// супернета отвергается по-прежнему.
			name:    "блок вне объявленного супернета",
			netV4:   []string{"10.0.0.0/8"},
			subV4:   []string{"192.168.0.0/24"},
			wantErr: true,
			family:  "within",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := validateSubnetWithinSupernet(tc.netV4, tc.netV6, tc.subV4, tc.subV6)
			if !tc.wantErr {
				if err != nil {
					t.Fatalf("законная подсеть отвергнута: %v", err)
				}
				return
			}
			if err == nil {
				t.Fatalf("подсеть принята сетью, которой нечего ей выделить. Контракт "+
					"заявляет вложенность безусловно, а поле супернета не обязательно на "+
					"создании сети — значит ограничение просто не действовало (семейство %s)",
					tc.family)
			}
			st, ok := status.FromError(err)
			if !ok || st.Code() != codes.InvalidArgument {
				t.Fatalf("отказ не того рода: %v — вызывающий обязан отличить неверный ввод "+
					"от состояния ресурса", err)
			}
			if tc.family != "within" && !strings.Contains(st.Message(), tc.family) {
				t.Errorf("в отказе не названо семейство: %q — не понять, какие блоки "+
					"объявлять через :add-cidr-blocks", st.Message())
			}
		})
	}
}

// TestSubnetRefusedWhenNoDeclaredBlockIsReadable — ВТОРАЯ ПОЛОВИНА той же ловушки.
//
// Отказ выше снял пропуск проверки по пустому списку блоков. Ровно тот же пропуск
// оставался на шаг ниже: список блоков непуст, но НИ ОДИН из них не разбирается в
// префикс, разобранный набор выходит пустым — и проверка снова принимала любую
// подсеть, потому что сравнивать было не с чем.
//
// Обе половины — один класс: проверка отвечает «да», когда пуст её собственный
// источник ограничения. Первая половина видна в контракте (поле не обязательно),
// вторая не видна нигде и потому пережила фикс первой. Держит класс по дереву гейт
// `TestCheckNeverAcceptsBecauseItsConstraintIsEmpty` в `internal/repohygiene` — он
// и назвал это место.
//
// Почему отказ, а не приём: у сети, чей объявленный адресный план не читается,
// плана нет — ровно как у сети, которая его не объявила. Разница между «не
// объявлено» и «объявлено нечитаемым» касается того, кто это чинит, а не того,
// можно ли из этого нарезать.
func TestSubnetRefusedWhenNoDeclaredBlockIsReadable(t *testing.T) {
	for _, tc := range []struct {
		name    string
		netV4   []string
		subV4   []string
		wantErr bool
	}{
		{
			name:    "единственный объявленный блок не разбирается",
			netV4:   []string{"10.0.0.0/8/24"},
			subV4:   []string{"10.77.7.0/24"},
			wantErr: true,
		},
		{
			name:    "все объявленные блоки не разбираются",
			netV4:   []string{"не-cidr", "10.0.0.0/33"},
			subV4:   []string{"10.77.7.0/24"},
			wantErr: true,
		},
		{
			// Законный близнец той же формы: часть блоков нечитаема, но набор
			// читаемых непуст — по нему и судим. Без этого случая «отказ» зеленел
			// бы и на реализации, отвергающей всё, где встретился мусор.
			name:  "нечитаемый блок рядом с читаемым, подсеть в читаемом",
			netV4: []string{"не-cidr", "10.0.0.0/8"},
			subV4: []string{"10.77.7.0/24"},
		},
		{
			name:    "нечитаемый блок рядом с читаемым, подсеть ВНЕ читаемого",
			netV4:   []string{"не-cidr", "10.0.0.0/8"},
			subV4:   []string{"192.168.0.0/24"},
			wantErr: true,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := validateSubnetWithinSupernet(tc.netV4, nil, tc.subV4, nil)
			if !tc.wantErr {
				if err != nil {
					t.Fatalf("законная подсеть отвергнута: %v", err)
				}
				return
			}
			if err == nil {
				t.Fatalf("подсеть принята сетью, ни один объявленный блок которой не "+
					"читается: сравнивать было не с чем, и проверка ответила «да» — то же "+
					"самое, что она отвечала на пустом списке блоков (netV4=%v)", tc.netV4)
			}
			st, ok := status.FromError(err)
			if !ok || st.Code() != codes.InvalidArgument {
				t.Fatalf("отказ не того рода: %v", err)
			}
			if !strings.Contains(st.Message(), "not within any network CIDR block") {
				t.Errorf("тон отказа разошёлся с контрактом: %q", st.Message())
			}
		})
	}
}
