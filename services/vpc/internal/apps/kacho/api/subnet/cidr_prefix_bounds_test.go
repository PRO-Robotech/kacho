package subnet

// cidr_prefix_bounds_test.go — обе границы размера IPv4-подсети действуют.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Контракт обещает диапазон с ДВУХ сторон: «Minimum /28, maximum /16»
// (`ipv4_cidr_primary` — и в проекции `Subnet`, и в `CreateSubnetRequest`).
// Код исполнял только одну: длинный префикс (/29…/32) отвергался, короткий —
// нет, поэтому `/8` проходил, и подсеть забирала у сети адресное пространство,
// которое контракт ей не обещал.
//
// Обещание оставлено, код приведён к нему (решение владельца). Обратный исход —
// снять обещание из контракта — здесь неприменим: у обещания есть предмет
// (потолок размера подсети в сети), а у поля есть читатель.
//
// ПОЧЕМУ ОБЕ ГРАНИЦЫ ПРОВЕРЯЮТСЯ ВКЛЮЧИТЕЛЬНО И РЯДОМ С ПОЛОЖИТЕЛЬНЫМ
//
// Отрицание «/15 отвергается» зеленеет на реализации, отвергающей вообще всё,
// и — что тише — на реализации, сдвинувшей границу на единицу. Поэтому у каждой
// границы стоит пара: сама граница проходит, шаг за неё отвергается.
//
// IPv6: контракт границы НЕ называет — ни у `ipv6_cidr_primary`, ни у
// `ipv6_cidr_blocks`. Ненаписанная граница не выдумывается; проба это состояние
// закрепляет, а появление обещания в контракте ловит проба паритета
// (`cidr_bounds_contract_parity_test.go`), которая на таком обещании краснеет.

import (
	"fmt"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// TestSubnetV4PrefixBounds — обе границы размера, каждая включительно.
func TestSubnetV4PrefixBounds(t *testing.T) {
	for _, tc := range []struct {
		cidr   string
		отказ  bool
		почему string
	}{
		// Верхний предел РАЗМЕРА сети — самый короткий допустимый префикс.
		{cidr: "10.0.0.0/16", почему: "контрактный «maximum /16» — сама граница законна"},
		{cidr: "10.0.0.0/15", отказ: true, почему: "шаг за «maximum /16»"},
		{cidr: "10.0.0.0/8", отказ: true, почему: "далеко за «maximum /16» — именно этот вход и проходил"},
		{cidr: "0.0.0.0/0", отказ: true, почему: "весь адресный простор одной подсетью"},
		// Нижний предел РАЗМЕРА сети — самый длинный допустимый префикс.
		{cidr: "10.0.0.16/28", почему: "контрактный «Minimum /28» — сама граница законна"},
		{cidr: "10.0.0.8/29", отказ: true, почему: "шаг за «Minimum /28» (прежде единственная действовавшая граница)"},
		{cidr: "10.0.0.1/32", отказ: true, почему: "одиночный адрес подсетью не бывает"},
		// Середина диапазона — контроль, что запрещено не всё подряд.
		{cidr: "10.0.0.0/24", почему: "рабочая величина внутри диапазона"},
		{cidr: "10.0.0.0/20", почему: "середина диапазона"},
	} {
		t.Run(tc.cidr, func(t *testing.T) {
			err := validateSubnetV4CIDR("ipv4_cidr_primary", tc.cidr)
			if !tc.отказ {
				require.NoError(t, err, "законный префикс отвергнут (%s)", tc.почему)
				return
			}
			require.Error(t, err, "префикс вне обещанного контрактом диапазона принят (%s). "+
				"Контракт называет обе границы — «Minimum /28, maximum /16», — а код "+
				"исполнял одну", tc.почему)
			assert.Equal(t, codes.InvalidArgument, status.Code(err),
				"неверный ввод, а не состояние ресурса")
			assert.Equal(t,
				fmt.Sprintf("Illegal argument Invalid network prefix /%s", prefixLenOf(tc.cidr)),
				status.Convert(err).Message(),
				"тон отказа — часть контракта и утверждается дословно")
			assert.Contains(t, fieldViolationsOf(t, err), "ipv4_cidr_primary",
				"отказ обязан называть поле: без имени вызывающий правит наугад")
		})
	}
}

// prefixLenOf — длина префикса из строки CIDR (для дословной сверки текста).
func prefixLenOf(cidr string) string {
	for i := len(cidr) - 1; i >= 0; i-- {
		if cidr[i] == '/' {
			return cidr[i+1:]
		}
	}
	return ""
}

// TestSubnetV6PrefixHasNoPromisedBound — у IPv6 контракт границ не называет,
// поэтому валидатор их не выдумывает.
//
// Проба закрепляет ОТСУТСТВИЕ границы, и это отсутствие самоистекает: как только
// контракт назовёт границу для v6-поля, `TestSubnetCidrBoundsMatchTheContract`
// покраснеет и потребует исполнения — то есть послабление здесь не переживёт
// своего основания.
func TestSubnetV6PrefixHasNoPromisedBound(t *testing.T) {
	for _, cidr := range []string{
		"fd00::/8", // короче любой v4-границы — у v6 её нет
		"2001:db8::/32",
		"fd00::/64",
		"fd00::/128", // одиночный адрес: границы нет, значит и отказа нет
	} {
		t.Run(cidr, func(t *testing.T) {
			require.NoError(t, validateSubnetV6CIDR("ipv6_cidr_primary", cidr),
				"граница, которой контракт не обещал, не выдумывается")
		})
	}
}
