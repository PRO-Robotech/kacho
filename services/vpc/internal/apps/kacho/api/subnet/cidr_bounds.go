package subnet

// cidr_bounds.go — обещанный контрактом диапазон размера IPv4-подсети, названный
// один раз.
//
// Величины были литералами внутри валидатора, и одна из двух в нём отсутствовала
// вовсе: контракт обещал диапазон с двух сторон, код исполнял одну сторону. Пара
// названа здесь, а её совпадение с текстом контракта держит проба паритета
// `TestSubnetCidrBoundsMatchTheContract` — иначе обещание и предикат разъедутся
// молча, и разъедутся именно там, где расхождение не видно: оба «работают».

// Диапазон размера IPv4-подсети в ДЛИНЕ ПРЕФИКСА.
//
// Контракт называет его в терминах РАЗМЕРА сети — «Minimum /28, maximum /16»
// (`ipv4_cidr_primary` в проекции `Subnet` и в `CreateSubnetRequest`). Термины
// обратны длине префикса, и в этом вся цена пары имён: самая МАЛЕНЬКАЯ сеть —
// это самый ДЛИННЫЙ префикс. Поэтому имена здесь про длину префикса, а не про
// размер сети, и перевод между двумя языками сделан ровно один раз — здесь.
//
// Границы включительны с обеих сторон: /16 и /28 законны, /15 и /29 — нет.
//
// IPv6 своего диапазона НЕ имеет: контракт его не называет ни у
// `ipv6_cidr_primary`, ни у `ipv6_cidr_blocks`, а граница, которую никто не
// обещал, не выдумывается. Появление обещания в контракте ловит та же проба
// паритета — она на нём краснеет и требует исполнения.
const (
	// subnetV4PrefixLenMin — самый КОРОТКИЙ допустимый префикс, то есть самая
	// большая подсеть. Контракт называет его «maximum /16».
	subnetV4PrefixLenMin = 16
	// subnetV4PrefixLenMax — самый ДЛИННЫЙ допустимый префикс, то есть самая
	// маленькая подсеть. Контракт называет его «Minimum /28».
	subnetV4PrefixLenMax = 28
)
