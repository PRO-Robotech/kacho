package serviceerr

import (
	"fmt"

	"google.golang.org/genproto/googleapis/rpc/errdetails"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// Отказ на пересечении объявляемого диапазона со служебным адресным
// пространством платформы.
//
// # Почему у этого отказа СВОЙ машинный признак
//
// Перечень служебных диапазонов задаётся посадкой и наружу не выставляется —
// решение осознанное (`security.md` §«Инфра-чувствительные данные»: адреса узлов
// и точка получения метаданных суть underlay, и печатать их в отказе значило бы
// отдать карту служебного пространства за один пробный запрос).
//
// Цена этого решения ложится на клиента и названа прямо: планировщик адресации
// ходит кругами «запрос → отказ → другой префикс», и число кругов не ограничено
// сверху ничем. Пока отказ различим ТОЛЬКО прозой, автомат не может даже
// разветвиться: «этот префикс служебный, возьми следующий кандидат» неотличимо от
// «твой ввод сломан, чинить надо код», а разбирать прозу контракт прямо запрещает
// (`api-conventions.md` §By-lane code-split — тон сообщения стабилен, но не
// парсибелен).
//
// Признак этого не отменяет и КРУГОВ НЕ УБАВЛЯЕТ — он делает их машинно
// различимыми. Это меньше, чем публикация перечня, и это всё, что можно дать, не
// отдавая карту.
//
// # Почему признак объявлен ЗДЕСЬ, а не в общем словаре полос
//
// Общий словарь (`pkg/errors`) закрыт пятью полосами РЕЗОЛВА ИДЕНТИФИКАТОРА —
// своё против чужого, найдено против недоступно. Здесь предмет другой: доменная
// проверка значения. Тот же выбор уже сделан для отказа учёта (`quota.go`), и
// сделан по той же причине.
const (
	// ReasonSubnetCIDRReserved — объявляемый диапазон пересекается со служебным
	// адресным пространством платформы.
	//
	// Что этот признак говорит вызывающему: ввод отвергнут НЕ по форме — он
	// синтаксически верен и не станет законным ни при каком повторе. Следующий шаг
	// — другой префикс, а не починка кодировщика запроса.
	//
	// #nosec G101 -- машинный признак полосы отказа, уезжающий клиенту в деталях
	// ответа, а не секрет. Эвристика ключуется на форме имени (заглавные с
	// подчёркиваниями рядом со строковым литералом) и не различает токен
	// публичного контракта от учётных данных.
	ReasonSubnetCIDRReserved = "SUBNET_CIDR_RESERVED"

	// reservedReasonDomain — источник отказа в `ErrorInfo.domain`, как его видит
	// клиент. Совпадает с доменом отказа учёта: источник один и тот же сервис.
	reservedReasonDomain = "vpc.kacho.cloud"
)

// reservedOverlapFormat — тон отказа. Часть контракта: меняется только осознанно
// (`api-conventions.md` §Error-format).
//
// Называется ИМЯ СЛОТА и ПРИСЛАННОЕ ЗНАЧЕНИЕ — то, что вызывающий и так знает и
// что ему править. Служебный диапазон, с которым вышло пересечение, НЕ
// называется ни в тексте, ни в метаданных.
const reservedOverlapFormat = "%s %s overlaps an address range reserved by the platform"

// ReservedCIDROverlap собирает отказ на пересечении со служебным диапазоном.
//
// Отказ несёт ДВЕ детали, и обе нужны разным читателям: `BadRequest` — тому, кто
// показывает человеку, какое поле править; `ErrorInfo` — тому, кто ветвится
// машинно. Признак ДОБАВЛЕН к прежней форме, а не заменил её: смена не ломающая.
//
// Сборка деталей не удалась — возвращается голый статус с тем же кодом и текстом.
// Терять отказ из-за неудачи упаковки детали нельзя: без него негодный ввод
// уехал бы дальше по тракту.
func ReservedCIDROverlap(field, value string) error {
	msg := fmt.Sprintf(reservedOverlapFormat, field, value)
	st := status.New(codes.InvalidArgument, msg)
	withDetails, err := st.WithDetails(
		&errdetails.BadRequest{
			FieldViolations: []*errdetails.BadRequest_FieldViolation{
				{Field: field, Description: msg},
			},
		},
		&errdetails.ErrorInfo{
			Reason: ReasonSubnetCIDRReserved,
			Domain: reservedReasonDomain,
			// Метаданные несут ТОЛЬКО присланное вызывающим. Ключа под служебный
			// диапазон здесь нет и не должно быть: он и есть то, что не
			// раскрывается.
			Metadata: map[string]string{"field": field, "value": value},
		},
	)
	if err != nil {
		return st.Err()
	}
	return withDetails.Err()
}
