package domain

// frame_guarantee.go — обещание продукта о полезной нагрузке кадра.
//
// # Почему это величина продукта, а не настройка
//
// Арендатор не знает ни стенда, на который он пришёл, ни его исполнителя
// датаплейна, и спросить их не может: возможности исполнителя объявляет посадка
// (`dataplane.executor` — см. `internal/apps/kacho/config/dataplane.go`), а
// посадка арендатору не видна. Значит нижнюю границу обязан обещать ПРОДУКТ —
// одним числом, одинаковым на каждом стенде. Без такого обещания арендатор
// вынужден догадываться, и догадка у каждого своя: один подберёт величину
// опытом на одном стенде, второй унаследует её из чужой памяти, и оба узнают о
// расхождении по последствиям в чужой отладке.
//
// Обещание — НИЖНЯЯ граница, а не равенство: исполнитель вправе проносить
// больше, и посадка это объявляет. Обещание при этом связывает посадку в другую
// сторону — боевой страж старта (`Config.ValidateExecutorProfile`) НЕ ПОДНИМАЕТ
// стенд, чей исполнитель объявил меньше обещанного: иначе обещание оставалось бы
// написанным в документации и ложным на этом стенде, причём молча — контур
// принимает тот же трафик, что и раньше.
//
// # Из обещания НЕ следует, чем оно достигается, и это требование, а не стиль
//
// Величина названа как гарантированный минимум полезной нагрузки — не как
// «столько-то за вычетом такого-то заголовка». Разница не косметическая: по
// величине накладных расходов опознаётся конкретная инкапсуляция, то есть
// конкретная реализация сетевой фабрики, а публичное поле, по которому она
// опознаётся, — дефект дизайна (запрет инфра-чувствительных данных на публичной
// поверхности: идентификаторы оверлея, адреса туннельных эндпоинтов, префиксы
// underlay и всё, из чего строится карта физики, живут только в `Internal*` на
// :9091). Поэтому здесь нет ни арифметики вычета, ни имени инкапсуляции — ни в
// коде, ни в документации, которая это обещание называет.
//
// # Два места об одном предмете сверяются механически
//
// Число живёт здесь и повторяется в документации сервиса, которая обещает его
// арендатору. Прозой такая пара расходится молча — правку вносят в одно место, и
// с этого дня второе лжёт. Поэтому пару держит гейт дерева
// `internal/repohygiene` `TestGuaranteedPayloadFloorIsOnePlace`: он требует
// ровно одного объявления этой величины, требует, чтобы её читал прод-код, и
// сверяет число, которое называет документация, с числом отсюда.
const (
	// GuaranteedPayloadFloorBytes — гарантированный минимум полезной нагрузки
	// кадра (байт), который платформа обещает арендатору на любом стенде.
	//
	// Единственное место, где эта величина задана. Литерал вместо ссылки на неё —
	// находка гейта, названного выше: три копии одного числа расходятся на первой
	// же правке, и расходятся именно там, где расхождение не видно.
	GuaranteedPayloadFloorBytes = 1400
)
