package domain

// interface_limits.go — три величины ОДНОГО сетевого интерфейса, которые продукт
// обещает арендатору постоянными: полоса, предел одновременных соединений и темп их
// установления.
//
// # Почему это величины продукта, а не поля ресурса и не настройка
//
// Арендатор не знает ни стенда, на который он пришёл, ни того, кто несёт на нём трафик,
// и спросить не может: возможности исполнителя объявляет посадка, а посадка арендатору
// не видна. Значит планировать нагрузку ему не от чего — если только продукт не назовёт
// числа сам, одни и те же на каждом стенде.
//
// Полем ресурса это быть не может по той же причине, по какой не может быть настройкой:
// поле, зависящее от сети, зоны или семейства адресов, означало бы, что у одной и той же
// платформы разные обещания в разных местах, — а обещание, у которого есть исключения,
// перестаёт быть обещанием ровно в тот момент, когда на него сошлются. Поэтому величины
// объявлены здесь по одной, и документация обязана называть каждую всеобщей: одно число
// для всех сетей, всех зон и обоих семейств адресов.
//
// # Пол и потолок — РАЗНЫЕ обещания, и это видно в самих именах
//
// Полосу продукт обещает ПОЛОМ (`…FloorMbps`): её можно превысить безнаказанно, поэтому
// запас железа, лишняя реплика и всплеск обещания не ломают. Предел соединений и темп их
// установления — ПОТОЛКИ (`…Ceiling`): они защищают не того, кто в них упёрся, а его
// соседей по стенду, поэтому названы «не более».
//
// Смешать их нельзя, и разница не косметическая: потолок, объявленный полом, обещал бы
// арендатору ресурс, которого у платформы нет; пол, объявленный потолком, стал бы ложью
// при первом же стенде, который умеет больше.
//
// # Опубликованное число не уменьшается никогда
//
// На нём строят. Если замер покажет, что величина недостижима, растёт бюджет стенда — а
// не падает обещание. Поднять величину можно; это тоже решение продукта, а не правка
// константы, потому что поднятая величина связывает все будущие стенды.
//
// # Из величины НЕ следует, чем она достигается, и это требование, а не стиль
//
// Здесь нет ни вывода чисел, ни того, из чего они выведены: плотность интерфейсов на
// узел, бюджет узла, ёмкость таблицы состояний и класс сетевой карты — инфра-данные. По
// ним опознаётся конкретная реализация сетевой фабрики, а публичная поверхность, по
// которой она опознаётся, — дефект дизайна (запрет инфра-чувствительных данных: адреса
// туннельных эндпоинтов, префиксы underlay, идентификаторы оверлея и всё, из чего
// строится карта физики, живут только в `Internal*` на :9091). Вывод живёт в плане
// модуля; арендатору сообщается величина и то, что она ни от чего не зависит. По той же
// причине не публикуется ИЗМЕРЕННАЯ полоса: измеренное — отпечаток железа и способа
// передачи.
//
// # Честно про исполнение: объявить и исполнить — разные вещи
//
// У управляющего контура НЕТ производителя этих величин. Полосу выдерживает, соединения
// считает и темп их появления ограничивает тот, кто несёт трафик; контур не наблюдает ни
// одной из них и, в отличие от гарантированного минимума полезной нагрузки
// (`GuaranteedPayloadFloorBytes`), не имеет даже стража старта, который бы не поднял
// посадку, объявившую меньше обещанного.
//
// Это записано ОТКРЫТЫМ ДОЛГОМ, а не умолчанием, и записано так, чтобы долг нельзя было
// принять за исполненный: `services/vpc/docs/engineering/architecture/10-executor-conformance-debt.md`
// называет по каждой величине, что делает наша сторона, что обязан подтвердить
// исполнитель, и предикат снятия. Совпадение реестра с деревом держит гейт
// `internal/repohygiene` `TestPublishedInterfaceLimitsAreOnePlace`, и держит его в ОБЕ
// стороны: величина без читателя в прод-коде обязана нести запись «наша сторона не
// проверяет ничего», а величина, у которой читатель появился, обязана эту запись
// потерять. Поэтому долг истекает сам — в тот день, когда его закроют, а не тогда, когда
// кто-нибудь про него вспомнит.
//
// # Два места об одном предмете сверяются механически
//
// Каждое число живёт здесь и повторяется в документации, которая обещает его арендатору.
// Прозой такая пара расходится молча — правку вносят в одно место, и с этого дня второе
// лжёт. Тот же гейт требует одного объявления на величину, требует, чтобы документация
// называла её тем же числом, и падает, если число названо там, где канонической
// формулировки обещания нет.
const (
	// GuaranteedInterfaceBandwidthFloorMbps — гарантированная полоса на интерфейс,
	// Мбит/с. НИЖНЯЯ граница: стенд вправе давать больше, и то, что он даёт, трафик
	// арендатора использует без объявлений с его стороны.
	//
	// Единица — Мбит/с, а не Гбит/с, потому что в этой же единице посадка объявляет
	// возможности исполнителя (`dataplane.executor.guaranteed-bandwidth-per-interface-mbps`):
	// величины, которые однажды придётся сравнить, обязаны быть выражены одинаково, иначе
	// сравнение заведёт третье место — пересчёт, — и разойдётся с обоими.
	GuaranteedInterfaceBandwidthFloorMbps = 1000

	// InterfaceConnectionCeiling — предел одновременно отслеживаемых соединений на один
	// интерфейс. ПОТОЛОК, применяемый к обоим семействам адресов одинаково: асимметрия
	// семейств — скрытая дыра, при которой ограничение действует на одно и не действует
	// на другое, а арендатор об этом не знает.
	InterfaceConnectionCeiling = 10000

	// InterfaceConnectionRateCeilingPerSecond — темп установления новых соединений на
	// один интерфейс, в секунду. ПОТОЛОК.
	//
	// Отдельная величина от предыдущей, а не её следствие: предел одновременных защищает
	// ПАМЯТЬ, занятую записями о соединениях, а темп — стоимость их появления. Поток
	// полуоткрытых соединений исчерпывает второе, не приближаясь к первому, поэтому
	// свести их к одному числу нельзя: арендатор, упёршийся в темп, ведёт себя иначе, чем
	// упёршийся в число.
	InterfaceConnectionRateCeilingPerSecond = 2000

	// InterfaceConnectionRateBurstCeiling — кратковременный всплеск темпа установления
	// соединений на один интерфейс, в секунду.
	//
	// Всплеск публикуется ВМЕСТЕ с постоянным темпом и порознь с ним не имеет смысла:
	// «2 000 в секунду» без права на всплеск отвергало бы законную неравномерность
	// нагрузки, а всплеск без постоянного темпа не говорит, сколько его можно держать.
	InterfaceConnectionRateBurstCeiling = 8000
)
