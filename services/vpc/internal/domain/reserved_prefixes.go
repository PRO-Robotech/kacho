// ReservedPrefixes — адресные диапазоны, которые посадка платформы держит ЗА
// СОБОЙ и не отдаёт арендатору.
//
// # Зачем это величина, а не литерал в коде
//
// Часть адресного пространства обслуживает саму платформу: служебные адреса
// узлов, адреса служб внутри подсети, точка получения метаданных экземпляра.
// Подсеть арендатора, объявленная поверх такого диапазона, даёт продукт, который
// «иногда не работает», причём отладка уходит в сеть, а причина — в перекрытии.
// Какие именно диапазоны служебные, зависит от ПОСАДКИ, поэтому перечень
// объявляется конфигурацией развёртывания; литерал в коде описывал бы один стенд
// и лгал бы про остальные.
//
// # Полярность нулевого значения названа прямо
//
// Нулевое значение (и пустой перечень) не резервирует НИЧЕГО: `Overlaps` на нём
// отвечает `false` каждому вводу. Это «не сужаем», а не «нечего сужать», и
// закрывается это НЕ здесь, а стражем старта посадки
// (`config.Config.ValidateReservedPrefixes`): боевой режим с необъявленным
// перечнем не поднимается. Обратный выбор — «пустой перечень отвергает всё» —
// сделал бы неработоспособными внутрипроцессные фикстуры, у которых посадки нет
// вовсе, и превратил бы отсутствие настройки в отказ обслуживания.
//
// # Перечень нельзя получить обратно из значения
//
// Ни один метод не отдаёт сами диапазоны — by construction, а не по
// забывчивости: служебные адреса инфраструктуры не выставляются на публичной
// поверхности (`security.md` §«Инфра-чувствительные данные»), а арендатору
// сообщается про ЕГО ввод, а не выдаётся карта служебного пространства. Поэтому
// `String()` печатает счёт, а не перечень: его читает журнал процесса.
//
// Значение неизменяемо после сборки.
type ReservedPrefixes struct {
	// declared — годные диапазоны в канонической форме, повторы схлопнуты.
	declared []netip.Prefix
	// rejected — записи, которые объявлением стать не могут, в том виде, как их
	// написал оператор, вместе с причиной. Хранятся, чтобы отказ старта мог их
	// НАЗВАТЬ: молча отброшенная запись оставила бы диапазон, который оператор
	// считает зарезервированным, а контур — нет.
	rejected []RejectedPrefix
}

// RejectedPrefix — запись перечня, которую нельзя принять, и причина.
//
// Причина формулируется для ОПЕРАТОРА, поднимающего стенд: она попадает в текст
// отказа старта, и по ней запись чинят. Это рантайм-диагностика, а не публичный
// артефакт.
type RejectedPrefix struct {
	// Entry — запись как её написал оператор (с обрезанными краевыми пробелами).
	Entry string
	// Reason — почему запись непригодна.
	Reason string
}

// NewReservedPrefixes собирает перечень из того, что написала посадка.
//
// Нормализация: краевые пробелы срезаются, ПУСТЫЕ записи отбрасываются, повторы
// схлопываются. Пустая запись — не негодная запись, а её отсутствие: оператор,
// написавший перечень через «запятая-пробел», обязан получить объявленный
// перечень, а одинокая запятая (она разбирается в две пустые записи) обязана
// читаться как «не объявлено» — тем же предикатом, каким её читает страж старта.
//
// Отвергается, и НАЗЫВАЕТСЯ в отказе, ровно четыре вида записи:
//
//   - неразбираемая — опечатка;
//   - с непустыми host-битами (`10.0.0.1/24`) — объявление значило бы не то, что
//     написано, а продукт требует канонической формы и от арендатора
//     (host-bits=0). Молча нормализовать значит расширить резерв без ведома
//     автора;
//   - в форме IPv4-в-IPv6 (`::ffff:10.0.0.0/104`) — это адрес семейства IPv6,
//     поэтому с арендаторским `10.0.0.0/8` он не пересекается ни по одному
//     предикату: объявление выглядело бы исполненным, НЕ ЗАПРЕЩАЯ ничего;
//   - покрывающая всё семейство (`0.0.0.0/0`, `::/0`) — контуру не остаётся ни
//     одного адреса, который он мог бы выдать. Процесс при этом поднимается, а
//     отвергается КАЖДОЕ создание подсети этого семейства, то есть увидеть такое
//     объявление можно только в трафике арендатора.
func NewReservedPrefixes(raw ...string) ReservedPrefixes {
	var (
		declared []netip.Prefix
		rejected []RejectedPrefix
		seen     = make(map[netip.Prefix]struct{}, len(raw))
		seenBad  = make(map[string]struct{}, len(raw))
	)
	for _, entry := range raw {
		trimmed := strings.TrimSpace(entry)
		if trimmed == "" {
			continue
		}
		prefix, reason := parseReservedPrefix(trimmed)
		if reason != "" {
			if _, dup := seenBad[trimmed]; dup {
				continue
			}
			seenBad[trimmed] = struct{}{}
			rejected = append(rejected, RejectedPrefix{Entry: trimmed, Reason: reason})
			continue
		}
		if _, dup := seen[prefix]; dup {
			continue
		}
		seen[prefix] = struct{}{}
		declared = append(declared, prefix)
	}
	if len(declared) == 0 && len(rejected) == 0 {
		// Канонический ноль: «не объявлено» обязано быть неотличимо от нулевого
		// значения, иначе у одного состояния появятся два представления, и
		// сравнение по одному однажды разойдётся с другим.
		return ReservedPrefixes{}
	}
	return ReservedPrefixes{declared: declared, rejected: rejected}
}

// parseReservedPrefix разбирает одну запись. Непустая причина означает, что
// запись объявлением стать не может; текст причины читает оператор.
func parseReservedPrefix(entry string) (netip.Prefix, string) {
	prefix, err := netip.ParsePrefix(entry)
	if err != nil {
		return netip.Prefix{}, "not a CIDR prefix"
	}
	if prefix.Addr().Is4In6() {
		return netip.Prefix{}, fmt.Sprintf(
			"IPv4-mapped IPv6 form: this is an IPv6 address, so it would never overlap "+
				"an IPv4 tenant prefix and would reserve nothing; write it as an IPv4 prefix (e.g. %s)",
			netip.PrefixFrom(prefix.Addr().Unmap(), prefix.Bits()-96).Masked())
	}
	if prefix.Masked() != prefix {
		return netip.Prefix{}, fmt.Sprintf(
			"host bits are set: write the network address %s", prefix.Masked())
	}
	if prefix.Bits() == 0 {
		return netip.Prefix{}, "covers the entire address family: the control plane would have " +
			"no address left to hand out, and every tenant subnet of that family would be refused"
	}
	return prefix, ""
}

// IsDeclared — ЕДИНСТВЕННЫЙ предикат «объявлен ли перечень». Его спрашивают и
// страж старта, и читатель на пути запроса, поэтому «страж пропустил» ⟺
// «диапазоны действительно объявлены» — по построению, а не по совпадению двух
// одинаково написанных условий.
func (r ReservedPrefixes) IsDeclared() bool { return len(r.declared) > 0 }

// Len — сколько диапазонов объявлено. Счёт, а не сами диапазоны: величину читает
// журнал процесса и пробы, и ни одному из них перечень не нужен.
func (r ReservedPrefixes) Len() int { return len(r.declared) }

// Rejected отдаёт КОПИЮ записей, которые объявлением стать не могут.
func (r ReservedPrefixes) Rejected() []RejectedPrefix {
	if len(r.rejected) == 0 {
		return nil
	}
	out := make([]RejectedPrefix, len(r.rejected))
	copy(out, r.rejected)
	return out
}

// Overlaps — пересекается ли диапазон, названный вызывающим, хотя бы с одним
// зарезервированным.
//
// Пересечение — свойство ДИАПАЗОНОВ, а не строк, и ловится в ОБЕ стороны
// вложенности: и когда ввод лежит внутри служебного диапазона (`10.0.0.0/8`
// служебный, просят `10.1.2.0/24`), и когда служебный лежит внутри ввода
// (`10.1.2.0/24` служебный, просят `10.0.0.0/8`). Вторая сторона — тот самый
// промах, который делает проверку, написанную как «содержится ли ввод в
// перечне»: арендатор забирает служебные адреса, попросив диапазон пошире.
// Оба направления даёт `netip.Prefix.Overlaps`; отдельного сравнения здесь нет
// намеренно — своя арифметика была бы вторым местом об одном предмете.
//
// Семейства не смешиваются (это тоже свойство `Overlaps`). Касание границ
// пересечением не является: соседний диапазон — законный ввод.
//
// На НЕобъявленном перечне отвечает `false` каждому вводу — см. полярность
// нулевого значения в доке типа: закрывает это страж старта, а не этот предикат.
func (r ReservedPrefixes) Overlaps(p netip.Prefix) bool {
	for _, reserved := range r.declared {
		if reserved.Overlaps(p) {
			return true
		}
	}
	return false
}

// String — читаемое представление для журнала процесса и отказа старта.
//
// Печатается СЧЁТ, а не перечень: диапазоны служебной инфраструктуры не
// выставляются наружу, а способ напечатать их через это значение стал бы первым
// путём, которым они туда попадут (`security.md` §«Инфра-чувствительные данные»).
func (r ReservedPrefixes) String() string {
	if len(r.declared) == 0 {
		return "<not declared>"
	}
	return fmt.Sprintf("%d reserved prefix(es)", len(r.declared))
}
