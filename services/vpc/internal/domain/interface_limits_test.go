// TestPublishedInterfaceLimitsStayCoherent — три опубликованные величины связаны между
// собой, и связь обязана пережить правку любой из них по отдельности.
//
// # Что здесь НЕ проверяется, и почему это сказано прямо
//
// Не проверяется «величина одинакова для всех сетей, зон и семейств»: это утверждение
// тождественно истинно на константе — у неё нет входа, которым её можно было бы
// различить, — и проба на него зеленела бы при любом состоянии продукта. Свойство
// «величина одна и не выводится ни из чего, что задаёт арендатор» держится там, где его
// вообще можно нарушить: в ДЕРЕВЕ и в ДОКУМЕНТАЦИИ, гейтом
// `internal/repohygiene` `TestPublishedInterfaceLimitsAreOnePlace` (одно объявление на
// величину; страница называет её тем же числом; страница обязана назвать обещание
// всеобщим; привязка числа к частной зоне, сети или семейству — находка).
//
// Не проверяется и исполнение: полосу выдерживает, соединения считает и темп их
// появления ограничивает не управляющий контур. Это открытый долг, а не пробел в наборе,
// и он записан в `docs/engineering/architecture/10-executor-conformance-debt.md`.
//
// # Что проверяется здесь и почему это не тавтология
//
// Взаимная согласованность двух потолков. Она не следует ни из одного из них, ломается
// правкой ЛЮБОГО по отдельности и не видна ни сборке, ни ревью диффа, потому что каждое
// число по отдельности останется правдоподобным.
func TestPublishedInterfaceLimitsStayCoherent(t *testing.T) {
	// Через переменные, а не константы напрямую: сравнение двух нетипизированных
	// констант анализатор справедливо назовёт тождественным и свернёт, и проба
	// перестанет быть исполняемой ровно в тот день, когда она понадобится.
	sustained := domain.InterfaceConnectionRateCeilingPerSecond
	burst := domain.InterfaceConnectionRateBurstCeiling
	ceiling := domain.InterfaceConnectionCeiling
	floor := domain.GuaranteedInterfaceBandwidthFloorMbps

	if burst <= sustained {
		t.Fatalf("всплеск темпа (%d/с) не больше постоянного темпа (%d/с) — тогда всплеска "+
			"нет вовсе, а обещание называет две величины там, где действует одна", burst, sustained)
	}
	if burst > ceiling {
		t.Fatalf("всплеск темпа (%d/с) больше предела одновременных соединений (%d) — "+
			"на всплеске арендатор упрётся в предел числа раньше, чем в предел темпа, и "+
			"обещанный всплеск окажется недостижим. Потолок, который не может связать, "+
			"защищает не тот ресурс, ради которого объявлен", burst, ceiling)
	}
	if floor <= 0 {
		t.Fatalf("пол полосы объявлен неположительным (%d Мбит/с) — «не менее нуля» не "+
			"является обещанием и не отвергает ни одной посадки", floor)
	}
}
