package domain

import (
	"errors"
	"fmt"
)

// tenant_bandwidth_limit.go — верхняя граница полосы, которую арендатор вправе
// задать СВОЕМУ интерфейсу, и правило, по которому такое значение принимается.
//
// # Почему это не просто число в запросе
//
// Полосу выдерживает не управляющий контур, а исполнитель датаплейна. Умеет ли он
// ограничивать полосу логического порта — свойство СТЕНДА, а не продукта: контур
// его не знает и вывести не может. Принять поле там, где исполнителя нет, значит
// отдать арендатору успех на настройке, которая не действует, — «принято и
// проигнорировано», что конвенция запрещает прямо. Поэтому поле принимается
// ТОЛЬКО когда посадка объявила умение в профиле возможностей исполнителя
// (`dataplane.executor.tenant-settable-bandwidth-limit`), а иначе отвергается
// явно, с именем поля и причиной.
//
// # Откуда обе границы, и почему они РАЗНЫЕ по происхождению
//
// Обе — из одной величины «гарантированная полоса на интерфейс», но из разных её
// половин, и это не совпадение:
//
//   - НИЖНЯЯ — опубликованный пол продукта (GuaranteedInterfaceBandwidthFloorMbps,
//     «не менее 1 Гбит/с»). Он обещан КАЖДОМУ интерфейсу на КАЖДОМ стенде, и
//     обещание это платформа даёт от своего имени. Ограничение на уровне пола или
//     ниже поставило бы её собственное опубликованное обещание и настройку
//     арендатора в прямое противоречие: выполнить оба нельзя. Поэтому граница
//     СТРОГАЯ — ровно пол уже негоден.
//
//   - ВЕРХНЯЯ — то, что ЭТОТ стенд объявил гарантированным на интерфейс
//     (`dataplane.executor.guaranteed-bandwidth-per-interface-mbps`). Выше этого
//     числа платформа не обещала ничего, значит ограничивать нечего: такое
//     значение приняли бы и оно не подействовало бы — тот же запрещённый исход, от
//     которого и защищает признак профиля. Граница ВКЛЮЧАЮЩАЯ: ограничить ровно
//     тем, что гарантировано, — законная и осмысленная просьба «не больше
//     гарантии».
//
// Из этого следует ровно одно требование к посадке, и оно проверяется стражем
// старта, а не здесь: объявив умение, стенд обязан объявить гарантию СТРОГО выше
// пола продукта — иначе принимаемый промежуток пуст, и умение объявлено там, где
// им нельзя воспользоваться ни разу.
//
// # Ноль — это «не задано», а не «ноль полосы»
//
// Отсутствие ограничения представимо отдельно от значения, и представлено оно
// каноническим нулём: другого способа сказать «ограничения нет» нет, поэтому два
// представления одного состояния завестись не могут. Ограничение в ноль мегабит
// означало бы интерфейс без связи — его не выражает ни одна законная просьба.
const TenantBandwidthLimitUnset int64 = 0

var (
	// ErrBandwidthLimitNotSettable — исполнитель этого стенда умения не объявляет.
	ErrBandwidthLimitNotSettable = errors.New("bandwidth limit is not settable on this stand")
	// ErrBandwidthLimitOutOfRange — умение объявлено, но величина вне промежутка.
	ErrBandwidthLimitOutOfRange = errors.New("bandwidth limit is out of range")
)

// BandwidthLimitPolicy — то, что посадка объявила о полосе, в форме, пригодной
// для решения на пути запроса.
//
// Тип, а не пара голых значений, по той же причине, по какой множество семейств
// адресов в настройках — тип: у правила обязан быть ОДИН предикат, и спрашивать
// его обязаны все — путь запроса, самоотчёт процесса и проба. Пара `bool` + `int`,
// разложенная по вызывающим, разошлась бы ровно там, где расхождение не видно.
//
// Нулевое значение типа означает «умение не объявлено» — то же, что нулевое
// значение признака в настройках. Полярность выбрана так намеренно: посадка,
// забывшая объявить профиль, обязана получать отказ на поле, а не молчаливое
// «умеет всё».
type BandwidthLimitPolicy struct {
	settable bool
	// ceilingMbps — гарантия, объявленная стендом. Читается только когда
	// settable=true: без умения промежутка нет вовсе, и число ничего не значит.
	ceilingMbps int64
}

// NewBandwidthLimitPolicy собирает правило из двух объявлений профиля.
//
// declaredGuaranteeMbps приходит из настроек в той же единице, в которой продукт
// публикует свой пол (Мбит/с): величины, которые придётся сравнить, обязаны быть
// выражены одинаково, иначе сравнение заведёт третье место — пересчёт, — и
// разойдётся с обоими.
func NewBandwidthLimitPolicy(settable bool, declaredGuaranteeMbps int) BandwidthLimitPolicy {
	if !settable {
		// Канонический ноль: «не объявлено» обязано быть неотличимо от нулевого
		// значения типа, иначе у одного состояния появится два представления.
		return BandwidthLimitPolicy{}
	}
	return BandwidthLimitPolicy{settable: true, ceilingMbps: int64(declaredGuaranteeMbps)}
}

// Settable — объявил ли исполнитель умение. ЕДИНСТВЕННЫЙ предикат: его спрашивает
// и путь запроса, и страж старта, поэтому «страж пропустил» ⟺ «поле принимается» —
// по построению, а не по совпадению двух одинаково написанных условий.
func (p BandwidthLimitPolicy) Settable() bool { return p.settable }

// CeilingMbps — верхняя включающая граница. Ноль, если умение не объявлено.
func (p BandwidthLimitPolicy) CeilingMbps() int64 { return p.ceilingMbps }

// Check решает судьбу присланной величины.
//
// Возвращает обёрнутый sentinel, чтобы вызывающий мог отличить «умения нет» от
// «величина вне промежутка», не разбирая прозу: тексты стабильны, но не парсибельны.
// Сам текст при этом обязан назвать И поле, И причину — арендатор, получивший
// отказ, должен понять, что чинить, не читая наших правил.
func (p BandwidthLimitPolicy) Check(limitMbps int64) error {
	if limitMbps == TenantBandwidthLimitUnset {
		// Не задано — законно всегда, в том числе на стенде без умения: отсутствие
		// просьбы не есть просьба.
		return nil
	}
	if !p.settable {
		return fmt.Errorf("%w: the dataplane executor of this stand does not declare it",
			ErrBandwidthLimitNotSettable)
	}
	if limitMbps <= GuaranteedInterfaceBandwidthFloorMbps {
		return fmt.Errorf("%w: must be above the guaranteed %d Mbps, got %d",
			ErrBandwidthLimitOutOfRange, GuaranteedInterfaceBandwidthFloorMbps, limitMbps)
	}
	if limitMbps > p.ceilingMbps {
		return fmt.Errorf("%w: must not exceed the %d Mbps this stand guarantees per interface, got %d",
			ErrBandwidthLimitOutOfRange, p.ceilingMbps, limitMbps)
	}
	return nil
}
