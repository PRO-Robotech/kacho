package authzfilter

// PageRelations — предикат членства строки в СТРАНИЦЕ публичного List, ПО ТИПУ
// объекта. Карта ТОТАЛЬНА: запись под пустым ключом — умолчание для типа, не
// названного поимённо, поэтому типа без объявленного предиката не существует.
//
// Тотальность — не оформление. Она есть то, что позволяет гейту паритета
// (internal/repohygiene/listreadrelationparity_test.go) прочитать это объявление и
// сверить его с каталогом прав потипно. Предикат, спрятанный в теле функции, — это
// предикат, которого не видит ни один гейт; ровно так прошлая волна сузила четыре
// сервиса и оставила пятый.
//
// Значение — ТО ЖЕ отношение, которым пообъектная проверка на крае гейтит одиночное
// чтение (`<Resource>Service/Get` → `v_get`, `internal/apps/kacho/check/permission_map.go`
// и запись каталога шлюза). Совпадение — не совпадение имён, а инвариант: страница не
// может быть шире чтения.
//
// # Почему здесь нет союза `viewer ∪ v_list`
//
// Ярусные отношения (`viewer`/`editor`/`admin`) и глагольные (`v_*`) в модели
// РАЗВЯЗАНЫ намеренно, как анти-over-grant guard, — ни одно не выводится из другого.
// Значит союз и `v_get` расходились в ОБЕ стороны, и обе наблюдались: держатель яруса
// без глагола получал объект в выдаче, а на чтении — отказ (и это не только оракул
// существования: List отдаёт ТО ЖЕ сообщение, что и Get, поэтому членство в странице
// раскрывало содержимое целиком); держатель глагола без яруса не находил собственный
// читаемый объект в своём же списке.
//
// # Что стало с `v_list`
//
// Он остаётся отношением модели и продолжает гейтить списки, вложенные В объект
// (`NetworkService/ListSubnets` → `v_list` на `vpc_network` — там вопрос задаётся о
// РОДИТЕЛЕ, и это другой вопрос). Как предикат членства страницы он снят: пока List
// возвращает полное сообщение ресурса, «видеть в списке без содержимого»
// нереализуемо.
var PageRelations = map[string][]string{
	"": {"v_get"}, // умолчание: отношение, которым каталог гейтит `<Service>/Get`
}
