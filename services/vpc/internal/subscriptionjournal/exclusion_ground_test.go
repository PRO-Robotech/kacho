// exclusion_ground_test.go — ОСНОВАНИЕ исключения сверяется с деревом (#1494).
//
// # Предмет
//
// `AddressPool` и `AddressPoolNetworkDefault` исключены из словаря видов
// НАМЕРЕННО, и решение верно. Неверна была половина его обоснования: пакет
// четырьмя местами утверждал, что типа объекта в модели прав у пула нет вовсе —
// при том что `vpc_address_pool` объявлен в канонической модели и несёт четыре
// глагола.
//
// # Почему это не мелочь
//
// «Типа в модели нет» — РАБОЧИЙ признак непровязываемости, и он применяется там,
// где верен: у geo типов `geo_*` действительно ноль, и потому geo не владеет
// потоком (`pkg/subscription/doc.go`). Ложное употребление признака здесь
// обесценивает его там: следующий, сверивший `vpc_address_pool` с комментарием,
// перестанет верить и настоящему случаю.
//
// # Что утверждает эта проба, и чего она НЕ умеет
//
// ДВЕ стороны. Положительная: тип в канонической модели ЕСТЬ, и число его
// глаголов печатается перепи́сью — чтобы факт был виден читателю, а не только
// проверке. Отрицательная: ни один файл ЭТОГО пакета не заявляет обратного.
//
// Отрицательная сторона читает ТЕКСТ, и это осознанно: её предмет и есть текст
// комментария, а не исполняемое. Ограничение названо: распознаватель знает
// НАЗВАННЫЕ формы утверждения, выведенные из дерева на день заведения; форма, о
// которой он не знает, остаётся невидимой. Поэтому рядом стоит положительная
// сторона — она не зависит от написания.
//
// Охват сужен до этого пакета намеренно: та же фраза про `geo_*` в
// `pkg/subscription/doc.go` ВЕРНА, и гейт, судящий её, краснел бы на законном
// близнеце.
//
// О ЧЁМ абзац, распознаватель не спрашивает — и остаточный класс назван, а не
// умолчан: приедь в этот пакет проза про ЧУЖОЙ домен, где типа в модели и
// вправду нет, гейт покраснел бы на верном утверждении. Спрашивать про пул
// поимённо нельзя: одно из четырёх найденных мест — однострочный комментарий,
// который предмета не называет вовсе, и сужение потеряло бы настоящую находку.
// Предмет у пакета один, второй сюда не приезжает; приедет — сужать
// распознаватель придётся вместе с заведением абзаца, а не задним числом.
//
// # Проза ОБ утверждении и само утверждение не разделяются послаблением
//
// Разбор, объясняющий, почему довод опровергнут, законен — но он обязан
// ОПИСЫВАТЬ утверждение, а не воспроизводить его дословно. Дословная копия
// краснит гейт, и это ПРАВИЛЬНЫЙ исход, а не ложное срабатывание: комментарий,
// в котором опровергнутая фраза стоит целиком, приглашает её обратно —
// следующий читатель скопирует именно её. Списка прощённых здесь нет: он и был
// бы тем самым входом, которым довод вернулся бы незамеченным.
//
// Проверено на себе: первая редакция правки воспроизвела фразу в кавычках, и
// гейт покраснел на собственном объяснении — фраза переписана в описательную.
//
// # Самоистечение
//
// Проба привязана к факту, а не к формулировке: исчезнет `vpc_address_pool` из
// модели — положительная сторона покраснеет и потребует пересмотреть основание
// заново, вместе с текстом.

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// canonicalModel — каноническая модель прав. Копия у iam
// (`services/iam/internal/authzmodel/fga_model.fga`) держится гейтом дрейфа и
// здесь не читается: два чтения об одном предмете разошлись бы молча.
const canonicalModel = serviceRoot + "/../../proto/kaname/cloud/iam/v1/fga_model.fga"

// poolObjectType — тип объекта пула адресов в модели прав.
const poolObjectType = "vpc_address_pool"

// refutedGroundForms — НАЗВАННЫЕ формы опровергнутого утверждения.
//
// Перечень выведен обходом пакета на день заведения (#1494), а не составлен по
// памяти. Каждая форма отвергает ОДНО: «типа объекта в модели прав нет».
var refutedGroundForms = []*regexp.Regexp{
	// «…типа объекта в модели прав у него тоже нет», «…у них нет».
	regexp.MustCompile(`типа[^.]{0,60}в модели прав[^.]{0,30}нет`),
	// «…без типа в модели прав».
	regexp.MustCompile(`без типа[^.]{0,20}в модели прав`),
	// «…ни типа объекта в модели прав».
	regexp.MustCompile(`ни типа[^.]{0,40}в модели прав`),
}

// TestPoolExclusionGroundMatchesTheAuthzModel — основание исключения пула
// сверяется с канонической моделью прав.
func TestPoolExclusionGroundMatchesTheAuthzModel(t *testing.T) {
	// ── положительная сторона: тип в модели ЕСТЬ ───────────────────────────
	raw, err := os.ReadFile(filepath.Clean(canonicalModel))
	if err != nil {
		t.Fatalf("каноническая модель не прочитана (%s): %v — без неё проба судила бы "+
			"о признаке, которого не измеряла", canonicalModel, err)
	}
	model := string(raw)

	head := "type " + poolObjectType
	idx := strings.Index(model, "\n"+head+"\n")
	if idx < 0 {
		t.Fatalf("тип %q в канонической модели НЕ объявлен. Если он снят осознанно — "+
			"основание исключения вида из словаря подписки изменилось, и текст пакета "+
			"обязан быть переписан вместе с ним", poolObjectType)
	}
	block := model[idx+1:]
	if next := strings.Index(block[len(head):], "\ntype "); next >= 0 {
		block = block[:len(head)+next]
	}
	verbs := strings.Count(block, "define v_")
	if verbs == 0 {
		t.Fatalf("тип %q объявлен, но глаголов `v_*` не несёт — признак «авторизовать нечем» "+
			"стал бы верным, и текст пакета обязан быть переписан вместе с моделью", poolObjectType)
	}
	latent := strings.Contains(block, "# kacho:latent")

	// ── отрицательная сторона: пакет обратного не утверждает ────────────────
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("каталог пакета не прочитан: %v", err)
	}
	var filesRead, linesScanned int
	var findings []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") {
			continue
		}
		body, rerr := os.ReadFile(filepath.Clean(name))
		if rerr != nil {
			t.Fatalf("файл %s пакета не прочитан: %v", name, rerr)
		}
		if name == "exclusion_ground_test.go" {
			// Собственное объяснение под запрет не подпадает: гейт, краснеющий
			// на своём разборе, снимут первым.
			filesRead++
			continue
		}
		filesRead++
		for _, para := range commentParagraphs(string(body)) {
			linesScanned += para.lines
			for _, re := range refutedGroundForms {
				if loc := re.FindStringIndex(para.text); loc != nil {
					findings = append(findings,
						name+":"+itoa(para.startLine)+" — …"+excerpt(para.text, loc)+"…")
					break
				}
			}
		}
	}

	if filesRead == 0 || linesScanned == 0 {
		t.Fatalf("прочитано файлов %d, строк %d — «ноль находок» здесь означало бы "+
			"«ноль прочитанного»", filesRead, linesScanned)
	}
	t.Logf("перепись: тип %q объявлен, глаголов `v_*` %d, помечен спящим: %v; "+
		"файлов пакета прочитано %d · строк осмотрено %d · известных форм утверждения %d",
		poolObjectType, verbs, latent, filesRead, linesScanned, len(refutedGroundForms))

	for _, f := range findings {
		t.Errorf("%s\n  ← пакет утверждает, что типа объекта в модели прав у пула НЕТ, "+
			"а каноническая модель объявляет %q с %d глаголами. Исключение вида из словаря "+
			"остаётся верным — негоден ДОВОД: сужать нечем не потому, что типа нет, а потому "+
			"что у пула нет проектного измерения (ось подписки — `project_id`), а сам тип "+
			"спящий: объектов пула у владельца прав не регистрирует никто.",
			f, poolObjectType, verbs)
	}
}

// commentPara — АБЗАЦ комментария: подряд идущие строки `//`, склеенные в один
// текст.
//
// Склейка обязательна, а не удобна. Утверждение о модели прав живёт в прозе, а
// проза переносится по ширине: в `journal.go` подлежащее стояло на одной строке,
// а отрицание — на следующей. Построчный распознаватель такую форму не видит
// вовсе — и молчит, вместо того чтобы покраснеть либо позеленеть. Ровно тот
// класс, ради которого проба и заведена (`testing.md` §«Гейт на класс», п.7).
type commentPara struct {
	text      string
	startLine int
	lines     int
}

// commentParagraphs собирает абзацы комментариев файла.
//
// Читает `//`-строки; блочные комментарии в этом дереве прозой не пользуются, и
// их отсутствие названо, а не подразумевается: появится блочная проза с этим
// утверждением — распознаватель её не увидит, и это ограничение той же природы,
// что и перечень форм.
func commentParagraphs(body string) []commentPara {
	var out []commentPara
	var cur []string
	start := 0
	flush := func(end int) {
		if len(cur) == 0 {
			return
		}
		out = append(out, commentPara{
			text:      strings.Join(cur, " "),
			startLine: start,
			lines:     end - start,
		})
		cur = nil
	}
	for i, line := range strings.Split(body, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "//") {
			if len(cur) == 0 {
				start = i + 1
			}
			cur = append(cur, strings.TrimSpace(strings.TrimPrefix(trimmed, "//")))
			continue
		}
		flush(i + 1)
	}
	flush(len(strings.Split(body, "\n")) + 1)
	return out
}

// excerpt — окрестность совпадения. Абзац печатается НЕ целиком: находка обязана
// показывать утверждение, а не весь разбор вокруг него.
//
// Режет по РУНАМ, а не по байтам: продукт русскоязычный, и байтовый срез
// разваливает символ пополам — находка тогда печатается мусором ровно в том
// месте, ради которого её читают.
func excerpt(text string, loc []int) string {
	const pad = 40
	r := []rune(text)
	from := len([]rune(text[:loc[0]])) - pad
	if from < 0 {
		from = 0
	}
	to := len([]rune(text[:loc[1]])) + pad
	if to > len(r) {
		to = len(r)
	}
	return strings.TrimSpace(string(r[from:to]))
}

// itoa — маленький помощник, чтобы не тянуть strconv ради одного вызова.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b [20]byte
	i := len(b)
	for n > 0 {
		i--
		b[i] = byte('0' + n%10)
		n /= 10
	}
	return string(b[i:])
}
