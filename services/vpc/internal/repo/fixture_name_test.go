// fixtureName — произвольное имя, отвечающее единственной форме дерева (#715).
//
// Пробам ниже имя безразлично: они спрашивают про аллокацию адресов, гонки и
// ограничения ссылок, а не про то, как ресурс подписан. Но пустым имя быть
// больше не может — миграция 715001 вешает форму ограничением БД, — поэтому
// фикстуре нужно КАКОЕ-ТО годное значение, и это оно.
//
// Почему не «имя = id», как делает умолчание продукта: внутри композитного
// литерала на собственное поле сослаться нельзя, а второй вызов генератора дал
// бы имя, НЕ совпадающее с id, — то есть выглядел бы как «имя = id» и им не
// был. Отдельная функция говорит прямо: значение произвольно.
func fixtureName() domain.RcNameVPC { return domain.RcNameVPC(ids.NewUID()) }
