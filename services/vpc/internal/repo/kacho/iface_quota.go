// Контракт доступа к строкам учёта числа ресурсов.
//
// Приёмка `docs/specs/sub-phase-quota-v2-materialised-usage-acceptance.md`
// (APPROVED, раунд 2), DoD S2 п.3 и п.5.

// QuotaRow — одна строка учёта, какой её ЗАВОДИТ материализация.
//
// Потребления здесь нет НАМЕРЕННО: `used` принадлежит триггеру и никакому
// другому писателю (гейт дерева `TestQuotaUsedIsWrittenOnlyByItsTrigger`).
// Структура, несущая `Used`, немедленно сделала бы «записать потребление»
// выразимым на Go-стороне — а невыразимость этого и есть то, чем счётчик
// защищён от расхождения с реальностью.
type QuotaRow struct {
	// CarrierType — тип носителя учёта (`project`; в S3 к нему добавляются
	// родительские типы вроде `vpc.network`).
	CarrierType string
	// CarrierID — идентификатор носителя.
	CarrierID string
	// Kind — вид ресурса точечным токеном платформы (`vpc.network`).
	Kind string
	// Limit — разрешённая величина, как её РАЗРЕШИЛ владелец величин. Снимок, а
	// не второй авторитет.
	Limit int64
	// SourceScope — область, на которой величина победила (`DEFAULT` / `ACCOUNT`
	// / `PROJECT`). Ради неё арендатор отличает личное перекрытие от общего
	// правила, а синхронизатор — строки, которых касается дельта умолчания.
	SourceScope string
	// SourceScopeID — объект победившей области; пуст, когда победило умолчание.
	SourceScopeID string
	// LimitRevision — ревизия величины на момент снимка.
	LimitRevision int64
	// AccountID — зеркало аккаунта проекта. Пустым быть не может: строка без
	// зеркала невидима аккаунтной дельте, а снаружи это неотличимо от исправной
	// работы. Схема отвергает пустое значение.
	AccountID string
}

// QuotaState — строка учёта, какой её ВИДИТ арендатор: величина, потребление и
// то, откуда величина взялась.
//
// Отдельный тип, а не поле `Used` в `QuotaRow`, и это не дубль. `QuotaRow`
// описывает то, что материализация ЗАПИСЫВАЕТ, и потребления не несёт намеренно:
// невыразимость «записать used» на Go-стороне и есть то, чем счётчик защищён от
// расхождения с реальностью. `QuotaState` описывает то, что чтение ОТДАЁТ, и
// живёт ровно на этом пути — у него нет ни одного писателя.
//
// Порядок полей повторяет `Quota` из `kacho.cloud.quota.v1`: тип заводится под
// один контракт, и расхождение состава было бы видно сразу.
//
// ПСЕВДОНИМ общего типа, а не своя структура: чтение квот доменно-независимо
// целиком, и полоса, которая его исполняет, живёт в `pkg/quota/quotaread` — одна
// на всех владельцев. Своя структура здесь означала бы переходник между ней и
// полосой, то есть место, где снисходительность к чужому ответу заводится
// незамеченной.
type QuotaState = quotaread.State

// QuotaReaderIface — совещательная полоса.
type QuotaReaderIface interface {
	// Admit сообщает, есть ли место под ещё одну строку этого вида у этого
	// носителя, НЕ занимая его.
	//
	// nil — место было в момент чтения. Отказ — `repo.ErrQuotaExceeded` либо
	// `repo.ErrQuotaNotProvisioned`, теми же текстом и признаком, что и отказ
	// авторитетной полосы: у обеих один производитель.
	//
	// Решением НЕ является: между этим ответом и вставкой помещается чужая
	// запись. Решает атомарное списание триггера.
	Admit(ctx context.Context, carrierType, carrierID, kind string) error

	// ListStates отдаёт все строки учёта носителя — то, что арендатор читает как
	// свои квоты.
	//
	// Пустой срез означает «строк учёта ещё нет», а НЕ «квот нет»: различать эти
	// два состояния обязан вызывающий, и он же обязан ответить арендатору полным
	// набором видов с нулевым потреблением, резолвя величины у владельца
	// синхронно. Пустой массив на проводе читался бы как «предела нет» —
	// утверждение, которого владелец не делал.
	//
	// Порядок — по виду, чтобы ответ не зависел от порядка вставки: строки
	// заводятся материализацией одной транзакцией, и метка времени у них
	// совпадает (`api-conventions.md` §«Порядок повторяющегося поля»).
	ListStates(ctx context.Context, carrierType, carrierID string) ([]QuotaState, error)
}

// QuotaWriterIface — материализация строк учёта.
type QuotaWriterIface interface {
	QuotaReaderIface
	// Materialize заводит отсутствующие строки учёта и не трогает имеющиеся.
	// Возвращает число заведённых — чтобы «ноль заведённых» было отличимо от
	// «не звали».
	Materialize(ctx context.Context, rows []QuotaRow) (int64, error)

	// MaterializeNestedDefaults заводит ПРОЕКТНЫЙ резолв вложенных видов и
	// догоняющие строки учёта для родителей, которые уже существуют.
	//
	// Два действия одним глаголом намеренно. Резолв без догоняющих строк оставил
	// бы вложенный предел недействующим у каждой сети, созданной раньше него, —
	// то есть у всех сегодняшних, — и это состояние ничем не отличалось бы
	// снаружи от «предел работает». Разделив их, мы получили бы вызывающего,
	// который вправе позвать одно и забыть второе.
	MaterializeNestedDefaults(ctx context.Context, rows []QuotaRow) (int64, error)
}
