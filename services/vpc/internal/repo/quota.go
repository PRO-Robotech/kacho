// Учёт числа ресурсов — имена, которыми пользуется весь сервис.
//
// Приёмка `docs/specs/sub-phase-quota-v2-materialised-usage-acceptance.md`
// (APPROVED, раунд 2), DoD S2 п.3 и п.5.

// QuotaCarrierProject — носитель учёта «проект».
//
// Строка, а не перечисление, потому что носитель обязан совпадать с тем, что
// стоит в столбце `carrier_type` и в предикате триггера — то есть значение
// принадлежит СХЕМЕ, а не Go-типу. Константа существует затем, чтобы литерал
// `"project"` не расползся по вызывающим: разойдясь с триггером в одном месте,
// он дал бы вызывающего, который спрашивает про место не там, где его списывают,
// и получал бы вечное «потолок не назван» при заведённой строке.
//
// S3 добавляет носителей-родителей (`vpc.network`, `vpc.subnet`); они приходят
// сюда же и тем же способом — токеном типа модели прав, а не новым словарём.
const QuotaCarrierProject = "project"

// QuotaRow — строка учёта в том виде, в каком её заводит материализация.
// Реэкспорт контракта репозитория: use-case-слой не импортирует пакет адаптера.
type QuotaRow = kacho.QuotaRow
