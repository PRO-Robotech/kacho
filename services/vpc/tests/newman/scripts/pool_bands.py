"""ЕДИНОЕ объявление полос CIDR для наборов, создающих AddressPool.

ПРЕДМЕТ
-------
`address_pool_cidrs` несёт ограничение
`EXCLUDE USING gist (kind WITH =, block inet_ops WITH &&)`
(`services/vpc/internal/migrations/0004_address_pool_cidrs.sql`). У него **нет**
измерения зоны и проекта: два пула ОДНОГО вида не могут нести пересекающиеся
блоки нигде во всём кластере. Значит блок — глобальное имя, и наборы проб,
идущие параллельно, делят одно пространство имён.

Второе ограничение — `address_pools_zone_kind_default_uniq` `(zone_id, kind)
WHERE is_default` (`services/vpc/internal/migrations/0001_initial.sql`). Оно
задаёт ВТОРУЮ ось развода: два набора не могут одновременно держать
умолчательный пул одного вида в одной зоне. Обе оси объявлены здесь.

НОРМА
-----
Каждый набор, создающий пул, владеет СВОЕЙ полосой; блок пула обязан ВХОДИТЬ в
полосу своего набора. Вхождение, а не различие: блок вне полосы отличается от
чужих блоков и при этом ложится поверх чужой полосы — различие не запрещает
столкновения, запрещает его только вхождение.

ПРИЗНАК НАРУШЕНИЯ
-----------------
Блок пула, не входящий в полосу своего набора; набор, создающий пулы и не
названный здесь; полосы, пересекающиеся между собой; блок, накрывающий сеть из
`OCCUPIED`.

ЧЕМ ДЕРЖИТСЯ
------------
`deploy/scripts/assert-pool-bands-are-disjoint.py` — читает это объявление и
файлы кейсов, разбирает каждый блок и требует вхождения. Его способность упасть
доказана инъекцией в обе стороны (`--self-test`).

Расписание (перечень последовательных коллекций) этого НЕ держало и держать не
могло: оно разводит наборы во ВРЕМЕНИ, а имя блока остаётся общим — стоит
двум наборам оказаться в одном прогоне по любой другой причине (умбрелла,
повторный прогон, ручной запуск), и столкновение возвращается.

ЛЕСТНИЦА ПОЛОС
--------------
Полоса выводится из НОМЕРА набора, а не выписывается второй раз:

    v4: 100.(100 + idx).0.0/16      (внутри 100.64.0.0/10, RFC 6598)
    v6: 2001:db8:(100 + idx)::/48   (внутри 2001:db8::/32, RFC 3849)

Число `100 + idx` читается в обеих полосах ОДИНАКОВО — по блоку видно, чей он,
без обращения к таблице.

Блок внутри полосы:

    v4: 100.(100 + idx).<n>.0/24
    v6: 2001:db8:(100 + idx):<n>::/64
"""
from __future__ import annotations

import ipaddress

# Набор проб (basename файла в `services/vpc/tests/newman/cases/`) → номер полосы.
SUITE_BANDS = {
    "internal-pool": 0,
    "address": 1,
    "public-pool": 3,
}

# Полосы, занятые НЕ набором проб. Номер держится за владельцем, чтобы следующий
# набор не получил его лестницей; блоки этих владельцев живут в их собственных
# файлах и здесь не воспроизводятся (два места об одном предмете разошлись бы).
RESERVED_BANDS = {
    2: "deploy/scripts/seed-nlb-fixtures.sh — зональный посев nlb "
       "(100.102.<октет зоны>.0/24), живёт весь прогон умбреллы",
}

# Наборы, которые ПИШУТ тело пула, но ни один их пул не доезжает до ограничения:
# каждое создание утверждает ОТКАЗ. Полоса им не нужна — но освобождение
# проверяется механически (см. гейт, правило 5), а не принимается на слово.
NO_LANDING_SUITES = {
    "authz-deny": "все создания пула идут через `emit(..., mode=\"gate\")` и "
                  "утверждают 403 у всех шести субъектов — блок не доезжает до "
                  "`address_pool_cidrs` ни при каком исходе",
}

# Сети, занятые вне лестницы полос. Блок набора не вправе их накрывать.
# `carves` назван там, где занятая сеть лежит ВНУТРИ полосы: это не разрешение,
# а требование назвать двойное владение вслух — молча оно превращается в
# столкновение при первом же расширении набора.
OCCUPIED = [
    ("100.64.0.0/24", "services/vpc/tests/newman/scripts/gen.py — посев "
                      "умолчательного внешнего пула зоны A", None),
    ("100.65.0.0/24", "services/vpc/tests/newman/scripts/gen.py — посев "
                      "зоне-независимого (anycast) пула", None),
    ("100.103.0.0/22", "deploy/scripts/seed-nlb-fixtures.sh — зоне-независимый "
                       "пул nlb; лежит ВНУТРИ полосы набора public-pool, потому "
                       "что оба владельца объявили себе 100.103/16 независимо "
                       "друг от друга", 3),
    ("2001:db8:e2e::/48", "deploy/scripts/seed-nlb-fixtures.sh — v6-блоки посева "
                          "nlb (зональные по октету + anycast)", None),
]

# Зона, в которой набор держит СВОИ умолчательные пулы (вторая ось развода —
# partial-UNIQUE `(zone_id, kind) WHERE is_default`). Значение — переменная
# окружения newman, а не идентификатор зоны: их резолвит первый шаг коллекции.
#
# zoneA занят посевом (`seed-default-external-zonea`), поэтому наборам не
# выдаётся; zoneB держит набор internal-pool под НЕумолчательный пул, и его
# кейс утверждает, что умолчательного v4-пула в zoneB нет ни у кого.
DEFAULT_POOL_ZONE = {
    "internal-pool": "{{zoneC}}",
    "address": "{{zoneD}}",
    "public-pool": None,  # пулы набора создаются без isDefault — партишн не занимают
}

# Помощники набора, чей ИМЕНОВАННЫЙ аргумент несёт блок пула (тело словаря
# собирается внутри помощника, поэтому по литералу словаря блок не виден).
# (набор, имя функции, имя аргумента, семейство).
HELPER_BLOCK_ARGS = [
    ("address", "_make_v6_pool", "cidr", 6),
]

_V4_LADDER = ipaddress.ip_network("100.100.0.0/16")
_V6_LADDER_PREFIX = "2001:db8"


def band_v4(idx: int) -> ipaddress.IPv4Network:
    """Полоса v4 набора с номером `idx`: 100.(100 + idx).0.0/16."""
    if idx < 0:
        raise ValueError(f"номер полосы отрицателен: {idx}")
    second = int(_V4_LADDER.network_address.packed[1]) + idx
    if second > 255:
        raise ValueError(f"лестница v4 исчерпана на номере {idx}")
    return ipaddress.ip_network(f"100.{second}.0.0/16")


def band_v6(idx: int) -> ipaddress.IPv6Network:
    """Полоса v6 набора с номером `idx`: 2001:db8:(100 + idx)::/48.

    Метка группы — те же ДЕСЯТИЧНЫЕ цифры, что и во втором октете полосы v4
    (100, 101, …). Цифры 0-9 — законные шестнадцатеричные, поэтому запись
    разбирается, а число читается так же, как в v4: по блоку видно владельца.
    """
    if idx < 0:
        raise ValueError(f"номер полосы отрицателен: {idx}")
    label = 100 + idx
    if label > 9999:
        raise ValueError(f"лестница v6 исчерпана на номере {idx}")
    return ipaddress.ip_network(f"{_V6_LADDER_PREFIX}:{label}::/48")


def band_for(suite: str, family: int):
    """Полоса набора по семейству (4 или 6). KeyError — набор не объявлен."""
    idx = SUITE_BANDS[suite]
    return band_v4(idx) if family == 4 else band_v6(idx)


def block_v4(suite: str, n: int) -> str:
    """Блок /24 внутри полосы v4 набора: 100.(100 + idx).<n>.0/24."""
    if not 0 <= n <= 255:
        raise ValueError(f"порядковый номер блока вне /16: {n}")
    band = band_for(suite, 4)
    return f"{band.network_address.packed[0]}.{band.network_address.packed[1]}.{n}.0/24"


def block_v6(suite: str, n: int) -> str:
    """Блок /64 внутри полосы v6 набора: 2001:db8:(100 + idx):<n>::/64."""
    if not 0 <= n <= 0xFFFF:
        raise ValueError(f"порядковый номер блока вне /48: {n}")
    label = 100 + SUITE_BANDS[suite]
    tail = "" if n == 0 else f":{n:x}"
    return f"{_V6_LADDER_PREFIX}:{label}{tail}::/64"


def occupied_networks():
    """[(сеть, владелец, номер полосы-хозяйки либо None)] с разобранными сетями."""
    return [(ipaddress.ip_network(cidr), owner, carves) for cidr, owner, carves in OCCUPIED]


def declared_suites() -> set:
    """Все наборы, о которых объявление что-то утверждает."""
    return set(SUITE_BANDS) | set(NO_LANDING_SUITES)
