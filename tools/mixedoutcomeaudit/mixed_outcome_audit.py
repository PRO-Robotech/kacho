    # (10) МОЛЧАНИЕ на законном близнеце ТОЙ ЖЕ формы: тот же глагол в имени шага,
    #      но предмет кейса — ДРУГАЯ операция, а удаление здесь уборка за собой.
    #      Живая форма — `IPL-ACB-*` / `SUB-ACB-*`: добавление блоков, за которым
    #      идёт снос пула. Ни одного слова о РОЛИ в этом кейсе нет намеренно —
    #      иначе инъекция проверяла бы ярус 1 и молчала бы о разделителе.
    #      (Прежняя редакция брала для этого `IPL-RMCIDR-NEG-INUSE`. После того
    #      как `RMCIDR` вошёл в словарь предмета-удаления, тот кейс держится
    #      ярусом РОЛИ — его `pm.test` называется `del pool`, — и о разделителе
