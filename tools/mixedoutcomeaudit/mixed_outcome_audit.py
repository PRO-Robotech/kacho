RE_NUM = re.compile(r"\b([1-5]\d\d)\b")
RE_PMTEST = re.compile(r"pm\.test(?:\.skip)?\(\s*(['\"])(.*?)\1", re.S)
# Кортеж/список ЦЕЛЫХ КОДОВ, привязанный к имени. Ловит обе формы одинаково:
# обычное присваивание `sync_codes = (400, 403)` и — что здесь и важно —
# УМОЛЧАНИЕ В СИГНАТУРЕ `def refuse(..., sync_codes=(400,), ...)`. Умолчание есть
# та ветка, которая раскрывается у всякого вызывающего, её не указавшего, поэтому
# читать её обязательно; `RE_ASSIGN` её не видит (он якорится на начало строки и
# спотыкается о хвост аннотации возвращаемого типа).
RE_INT_TUPLE = re.compile(r"\b([A-Za-z_]\w*)\s*=\s*[\(\[]\s*((?:[1-5]\d\d)(?:\s*,\s*[1-5]\d\d)*)\s*,?\s*[\)\]]")

# ЗАГОЛОВОК КЕЙСА записывается в дереве НЕСКОЛЬКИМИ законными формами, и все они
# обязаны читаться. Форма, о которой распознаватель не знает, — не край и не
# редкость: всё записанное в ней оказывается ВНЕ НАБЛЮДЕНИЯ, не давая ни
# красного, ни зелёного (`testing.md` §«Гейт на класс», п. 7). Перечень формами
# и закрывается — числа ниже названы, чтобы его можно было перемерить, а не
# поверить ему.
#
#   простая     `title="…"`, `title=f"…"`              — читалась всегда
#   скобочная   `title=("…" "…")`, `title=(f"…" f"…")` — НЕ ЧИТАЛАСЬ НИЧЕМ;
#               у неё два способа соединения — склейка и ветвление, и они дают
#               РАЗНЫЙ текст (см. `find_titles`)
#
# Замер по всему дереву на ревизии 87a44f62 (единица — объявление `title=` в
# ИСПОЛНЯЕМОЙ части файла, комментарии Python и JS вырезаны): объявлений 1541,
# из них простых 1524, скобочных 10 (iam 9, vpc 1). Ещё 7 записаны как
# `title=title` / `title=case.title` — там литерала нет ВОВСЕ; это не слепая
# зона, а граница статического чтения, и она остаётся: читать нечего by
# construction. Все три величины печатает перепись, иначе «прочитано ноль»
# было бы неотличимо от «заголовков нет».
#
# Чем обошлась слепота. Скобочная форма законна и используется, но её заголовки
# не читались ничем, и это давало ДВА разных дефекта сразу. Кейс, объявивший
# себя отрицательным, попадал в корзину «не читается ни одним словом
# направления» с ПУСТОЙ меткой — то есть предъявлял `:: ` и пустоту после него.
# Хуже второе: соседний `id=` получал заголовок ЧУЖОГО, стоящего ниже кейса
# (`IAM-BAT-SECRET-LIFECYCLE-OK` читался по метке про отвергнутый срок). Мерка,
# ошибающаяся в метке, ошибается и в направлении — в том единственном, ради чего
# она существует. Ровно этот класс уже ловили здесь на `id=f"…"`; тогда починили
# один экземпляр формы, а не форму как класс.
RE_TITLE_SIMPLE = re.compile(r"title=\s*f?[\"'](.*?)[\"']\s*,", re.S)
RE_TITLE_PAREN = re.compile(r"title=\s*\(")
RE_TITLE_ANY = re.compile(r"\btitle=")
# Строковый литерал с любым питоновским префиксом. Соседние литералы Python
# склеивает БЕЗ разделителя, поэтому и здесь `"".join` — пробел на стыке несёт
# сама строка («… ЧУЖОГО аккаунта » + «тоже отвергнут»). Склейка через пробел
# дала бы двойной и разошлась бы с тем, что реально уезжает в коллекцию.
RE_STR_LIT = re.compile(r"(?:[fFrRuUbB]{0,2})([\"'])(.*?)\1", re.S)


def find_titles(body):
    """Позиции и текст заголовков кейсов — все законные формы записи.

    Возвращает список пар (позиция `title=`, прочитанный текст), упорядоченный
    по позиции: вызывающие ищут «ближайший до» и «первый после», и порядок для
    них несущий.

    Позиция объявления и ЧИТАЕМАЯ часть метки — разные вещи (тот же довод, что
    у `id=f"…"` в `scan_case_sources`): позицией остаётся начало `title=`, а
    текстом — то, что удалось прочитать. Скобка, внутри которой нет ни одного
    литерала (`title=(inner_case.title)`), текста не даёт — и выдумывать его
    нельзя.

    Внутри скобки различаются ДВА способа соединения, и путать их нельзя:

      склейка   `("… аккаунта " "тоже отвергнут")` — соседние литералы Python
                сшивает БЕЗ разделителя, пробел на стыке несёт сама строка;
                здесь `""`, иначе получился бы двойной пробел и текст, который
                в коллекцию не уезжает;
      ветвление `(f"… 403 …" if scope else f"… 400 …")` — литералы принадлежат
                РАЗНЫМ веткам, и в коллекцию уезжает одна из них. Сшивать их
                вплотную значило бы склеить слова разных строк в несуществующее
                («…first"Create…»). Разделяются пробелом, а читаются ОБЕ: ветка,
                выбранная не для всех вызывающих, всё равно уезжает — тот же
                довод, по которому `assigns` читает оба списка кодов у
                `codes = "[400, 200]" if f else "[400]"`.
    """
    out = [(m.start(), m.group(1)) for m in RE_TITLE_SIMPLE.finditer(body)]
    n = len(body)
    for m in RE_TITLE_PAREN.finditer(body):
        i, depth, parts, last_end = m.end(), 1, [], m.end()
        while i < n and depth:
            c = body[i]
            if c in "\"'":
                if body.startswith(c * 3, i):
                    j = body.find(c * 3, i + 3)
                    if j < 0:
                        break
                    text, nxt = body[i + 3:j], j + 3
                else:
                    j = i + 1
                    while j < n and body[j] not in (c, "\n"):
                        j += 2 if body[j] == "\\" else 1
                    if j >= n or body[j] != c:
                        break
                    text, nxt = body[i + 1:j], j + 1
                if parts:
                    # Разрыв из одних пробелов и префикса литерала (f/r/u/b) —
                    # склейка; всё прочее между литералами — ветвление.
                    gap = body[last_end:i].strip(" \t\r\nfFrRuUbB")
                    parts.append("" if gap == "" else " ")
                parts.append(text)
                i = last_end = nxt
                continue
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    if parts:
                        out.append((m.start(), "".join(parts)))
                    break
            i += 1
    return sorted(out)


def strip_js_comments(s: str) -> str:
    """Убрать JS-комментарии, сохранив позиции (заменой на пробелы)."""
    out = list(s)
    i, n = 0, len(s)
    in_str = None
    while i < n:
        c = s[i]
        if in_str:
            if c == "\\":
                i += 2
                continue
            if c == in_str:
                in_str = None
            i += 1
            continue
        if c in "'\"`":
            in_str = c
            i += 1
            continue
        if c == "/" and i + 1 < n and s[i + 1] == "/":
            j = s.find("\n", i)
            j = n if j < 0 else j
            for k in range(i, j):
                out[k] = " "
            i = j
            continue
        if c == "/" and i + 1 < n and s[i + 1] == "*":
            j = s.find("*/", i)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
            continue
        i += 1
    return "".join(out)


def unnegated_hits(rx, label: str):
    """Вхождения `rx` в `label`, перед которыми НЕТ отрицания.

    ОДНА ФУНКЦИЯ НА ОБОИХ ЧИТАТЕЛЕЙ — на вердикт (`direction`) и на самоистечение
    (`stale_vocabulary`), — по той же причине, по какой одна `direction_subject`
    (#1180): будь у каждого свой способ прочитать, они разошлись бы МОЛЧА, и
    разошлись бы именно там, где расхождение не видно — на согласном входе оба
    отвечают одинаково. Мета-инъекция это и показала: пока копий было две,
    снятие охраны в одной оставляло проверку самоистечения зелёной.
    """
    return [m.group(0) for m in rx.finditer(label)
            if not RE_CODE_NEGATION_HEAD.search(label[:m.start()])]


def reject_5xx_hits(label: str):
    """Упоминания кодов 5xx, которые ОБЪЯВЛЯЮТ отказ (отрицаемые не в счёт).

    Возвращает список найденных написаний — именно список, а не булево: на нём
    держится перепись «сколько заголовков прочитано ПО 5xx», а «ноль прочитанных
    по 5xx» обязано быть отличимо от «по 5xx не искали».

    Отрицаемое вхождение пропускается: «→ 200, well-formed, not 503/code14» —
    заголовок обещает УСПЕХ и называет 503 как то, чего быть не должно. Без этого
    пополнение словаря кодами перевело бы 4 честно-успешных заголовка дерева из
    SUCCESS в BOTH, то есть погасило бы на них фатальную корзину.
    """
    return unnegated_hits(RE_REJECT_5XX, label)


def direction(label: str):
    r = bool(RE_REJECT.search(label)) or bool(reject_5xx_hits(label))
    s = bool(RE_SUCCESS.search(label))
    if r and not s:
        return "REJECT"
    if s and not r:
        return "SUCCESS"
    if r and s:
        return "BOTH"
    return "NONE"


def direction_subject(case_id: str, title: str) -> str:
    """Текст, по которому решается направление кейса. ЗАГОЛОВОК, и только он.

    ИДЕНТИФИКАТОР СЮДА НЕ ВХОДИТ, и это не вкус (#1180, третье срабатывание
    класса «мерка не читает направление кейса» за двое суток — #1163, #1178).
    Идентификатор кейса есть СОГЛАШЕНИЕ ОБ ИМЕНОВАНИИ: `-OK`, `-NF`,
    `-NOTFOUND`, `-SUCCEEDS` называют РАЗДЕЛ набора, а не исход, которого кейс
    ждёт. Пока он подмешивался в текст, его токены попадали в словарь наравне
    со словами заголовка и ПЕРЕБИВАЛИ его.

    Замер по дереву ДО этой правки (единица — ЗАГОЛОВОК КЕЙСА; объём — 101 файл,
    1576 объявлений; ревизия 02e3667a). Числа названы о том состоянии, ради
    которого правка сделана; после неё идентификатор не читается вовсе, поэтому
    повторить их можно только сравнением `direction(t)` и `direction(f"{t} {c}")`:

        кейсов, где идентификатор МЕНЯЕТ направление заголовка   158
          из них NONE   → SUCCESS (токен `OK` в имени)           136
          из них REJECT → BOTH    (тот же токен поверх отказа)    20
          из них SUCCESS → BOTH                                    1
          из них NONE   → REJECT                                   1
        из них там, где заголовок читался САМ (title != NONE)      22

    Живой экземпляр, из-за которого класс завели: `-NEG-`-кейс, чей заголовок
    говорит отказ дважды, получал ОБЕЩАНИЕ УСПЕХА по хвосту `SUCCEEDS` в имени.
    Следствий два, и второе тише первого: фатальная корзина на таком кейсе не
    сработает никогда, а `negative_vocabulary_coverage` ловит только `NONE` —
    значит кейс, прочитанный НЕВЕРНО, для неё «прочитан», и число нечитаемых
    занижено. Слепая зона была ровно там, где ошибка МЕНЯЕТ вердикт.

    ФУНКЦИЯ ОДНА НА ВСЕ ТРИ МЕСТА НАМЕРЕННО. Направление читают `bucketize`,
    `negative_vocabulary_coverage` и самоистечение словаря; будь у каждого свой
    способ собрать текст, они разошлись бы молча — и разошлись бы именно там,
    где расхождение не видно, потому что на согласном входе все трое отвечают
    одинаково.
    """
    return title or ""


def classify(codes):
    has2 = any(200 <= c < 300 for c in codes)
    hasErr = any(c >= 400 for c in codes)
    return has2 and hasErr


def resolve_ident(name, tuples, derived, seen=None):
    """Коды, которые может нести идентификатор. `None` — прочитать не удалось.

    Транзитивно: `codes` собирается из `sync_codes`, а `sync_codes` — умолчание
    сигнатуры. Останавливаться на первом звене значило бы объявить непрочитанным
    то, что прочитывается, и наоборот — прочитать половину и промолчать об
    остатке, а половина списка кодов хуже, чем честное «не прочитал».
    """
    if seen is None:
        seen = set()
    if name in seen:
        return None
    seen.add(name)
    if name in tuples:
        return sorted(set(tuples[name]))
    if name in derived:
        rhs = derived[name]
        out = {int(x) for x in RE_NUM.findall(rhs)}
        for ident in RE_IDENT.findall(rhs):
            if ident == name:
                continue
            sub = resolve_ident(ident, tuples, derived, seen)
            if sub:
                out.update(sub)
        return sorted(out) if out else None
    return None


def resolve_bracket(inner, tuples, derived):
    """Коды скобки `oneOf([...])`, часть которой — подстановка `{…}`.

    Возвращает `(коды, прочитано)`. КАЖДАЯ подстановка обязана дать хотя бы один
    код: подстановка, не давшая ничего, — непрочитанная часть списка, и списывать
    её в «здесь ничего нет» значит повторять ловимый класс уровнем ниже. Именно
    так предикат и слеп: скобка на месте ⇒ «список прочитан», а из `{codes}` не
    извлекалось ни одного кода, и пустота уходила в тишину.
    """
    codes = {int(x) for x in RE_NUM.findall(RE_FSUB.sub(" ", inner))}
    for sub in RE_FSUB.findall(inner):
        got = {int(x) for x in RE_NUM.findall(sub)}
        for ident in RE_IDENT.findall(sub):
            r = resolve_ident(ident, tuples, derived)
            if r:
                got.update(r)
        if not got:
            return [], False
        codes.update(got)
    return sorted(codes), True


# --- источник 1: исходники кейсов (там, где живут правки) --------------------
def scan_case_sources(paths):
    """Вернуть находки, перепись и список НЕПРОЧИТАННЫХ мест вызова.

    Третье значение — не украшение отчёта. Место вызова `oneOf(...)`, чей список
    кодов не раскрылся статически, предикатом не проверен, и молчание о нём
    неотличимо от «здесь чисто».
    """
    findings = []
    unreadable = []
    scanned = 0
    for path in paths:
        try:
            raw = open(path, encoding="utf-8").read()
        except OSError:
            continue
        scanned += 1
        # Python-комментарии тоже не исполняются: строка, у которой перед `#`
        # нет открытой кавычки, — комментарий. Достаточная аппроксимация:
        # выбрасываем строки, чей первый непробельный символ — `#`.
        lines = raw.split("\n")
        keep = []
        for ln in lines:
            keep.append("" if ln.lstrip().startswith("#") else ln)
        body = strip_js_comments("\n".join(keep))

        # позиции Case(id=..., title=...) и Step(name=...).
        #
        # `f?` — НЕ косметика. Генераторы объявляют кейс как `id=f"{prefix}-…"`, и
        # регэксп без `f?` их не видел: девять сгенерированных кейсов подсети
        # получали метку СОСЕДНЕГО, ничем с ними не связанного кейса, стоявшего
        # выше по файлу. Мерка, ошибающаяся в метке, ошибается и в направлении —
        # то есть в том единственном, ради чего она существует.
        # Позиция объявления и ЧИТАЕМАЯ часть метки — разные вещи, и путать их
        # нельзя. `id=f"{prefix}-CR-CONF-ALREADY-EXISTS"` объявляет кейс (значит
        # владение есть), но подстановку статически не раскрыть — остаётся хвост.
        # Поэтому владение решается по ПОЗИЦИИ объявления, а направление — по тому
        # тексту, который удалось прочитать (хвост id + title).
        id_positions = [m.start() for m in re.finditer(r"\bid=\s*f?[\"']", body)]
        cases = [(m.start(), RE_FSUB.sub(" ", m.group(1)))
                 for m in re.finditer(r"\bid=\s*f?[\"']([^\"']*)[\"']", body)]
        # Все законные формы записи заголовка — см. `find_titles`.
        titles = [(q, RE_FSUB.sub(" ", t)) for q, t in find_titles(body)]
        steps = [(m.start(), RE_FSUB.sub(" ", m.group(1)))
                 for m in re.finditer(r"\bname=\s*f?[\"']([^\"']*)[\"']", body)]
        step_positions = [p for p, _ in steps]
        # Границы функций верхнего уровня: `oneOf`, лежащий в теле помощника,
        # который САМ принимает идентификатор кейса параметром, не принадлежит
        # никакому кейсу — и не вправе занимать обещание того, чей `id=` случайно
        # оказался выше по файлу. Такой помощник (`_assert_absent`, `_deny`)
        # раскрывается у КАЖДОГО вызывающего со своей меткой, и статически ни одна
        # из них к нему не привязана.
        defs = [m.start() for m in re.finditer(r"(?m)^def\s", body)]

        def nearest_before(pos, arr):
            best = None
            for p, v in arr:
                if p <= pos:
                    best = v
                else:
                    break
            return best or ""

        # Таблица «идентификатор → списки кодов, которые он может нести».
        # Собирается один раз на файл: `codes = "[400, 200, 403]" if f else "[400, 200]"`
        # даёт ДВА списка, и оба обязаны быть проверены — ветка, выбранная не для
        # всех вызывающих, всё равно уезжает в сгенерированную коллекцию.
        assigns = {}
        for a in RE_ASSIGN.finditer(body):
            lists = [[int(x) for x in RE_NUM.findall(g)]
                     for g in RE_BRACKETED.findall(a.group(2))]
            lists = [ls for ls in lists if ls]
            if lists:
                assigns.setdefault(a.group(1), []).extend(lists)

        # Вторая половина той же таблицы — для формы, где список приходит
        # ПОДСТАНОВКОЙ ВНУТРЬ СКОБОК: `oneOf([{codes}])`.
        #   tuples  — имя → целые коды, записанные кортежем/списком, включая
        #             УМОЛЧАНИЕ СИГНАТУРЫ (`sync_codes=(400,)`): это та ветка,
        #             которая раскрывается у всякого вызывающего, её не указавшего;
        #   derived — имя → правая часть присваивания без литерального списка
        #             (`codes = ", ".join(... sync_codes ... 200 ...)`), из которой
        #             коды добираются транзитивно.
        tuples, derived = {}, {}
        for m in RE_INT_TUPLE.finditer(body):
            tuples.setdefault(m.group(1), []).extend(
                int(x) for x in RE_NUM.findall(m.group(2)))
        for a in RE_ASSIGN.finditer(body):
            if a.group(1) not in tuples and a.group(1) not in assigns:
                derived.setdefault(a.group(1), a.group(2))

        literal_at = {m.start(): m for m in RE_ONEOF.finditer(body)}

        for site in RE_ONEOF_ANY.finditer(body):
            pos = site.start()
            # аргумент вызова: до закрывающей скобки того же уровня
            arg = body[site.end():body.find(")", site.end()) + 1
                       if body.find(")", site.end()) >= 0 else len(body)]
            inner = literal_at[pos].group(1) if pos in literal_at else None
            if inner is not None and RE_FSUB.search(inner):
                # СКОБКА ЕСТЬ, НО ЧАСТЬ ЕЁ — ПОДСТАНОВКА. До этой ветки такой сайт
                # уходил в ветку литерала, отдавал ПУСТОЙ список кодов и молча
                # пропадал: ни находкой, ни непрочитанным. Три исхода схлопывались
                # в «чисто» — то самое смешение, которое гейт и ловит, только на
                # уровень выше. Пять живых мест дерева записаны этой формой, и
                # четыре из них — переписи прежней формы `oneOf({codes})`, которую
                # предикат читать умел.
                codes, ok = resolve_bracket(inner, tuples, derived)
                if not ok:
                    if "response.code" not in body[max(0, pos - 200):pos]:
                        continue
                    unreadable.append({
                        "file": path,
                        "line": body[:pos].count("\n") + 1,
                        "arg": " ".join(inner.split())[:120],
                    })
                    continue
                code_lists = [codes]
            elif inner is not None:
                code_lists = [[int(x) for x in RE_NUM.findall(inner)]]
            else:
                code_lists = []
                for ident in RE_IDENT.findall(arg):
                    code_lists.extend(assigns.get(ident, []))
                if not code_lists:
                    # Непрочитанным считается только то, что вообще является
                    # предметом этой мерки — КОД ОТВЕТА HTTP. `oneOf` над
                    # `j.error.code` (коды gRPC) и над `s.status` (строковые
                    # состояния) сравнивает другие величины, и требовать от них
                    # читаемости значило бы краснеть на законном: такой гейт
                    # снимают при первом же ложном срабатывании.
                    if "response.code" not in body[max(0, pos - 200):pos]:
                        continue
                    unreadable.append({
                        "file": path,
                        "line": body[:pos].count("\n") + 1,
                        "arg": " ".join(arg.split())[:120],
                    })
                    continue
            # ближайший pm.test(' перед позицией
            seg = body[:pos]
            tm = None
            for t in RE_PMTEST.finditer(seg):
                tm = t
            pmlabel = tm.group(2) if tm else ""
            cid = nearest_before(pos, cases)
            ctitle = nearest_before(pos, titles)
            sname = nearest_before(pos, steps)
            # Метка принадлежит находке только если её `id=` лежит в ТОЙ ЖЕ
            # функции (или оба на уровне модуля). Иначе метки нет — и это
            # отдельный исход, а не повод взять чужую.
            last_def = max([d for d in defs if d < pos], default=-1)
            cid_pos = max([p for p in id_positions if p <= pos], default=-1)
            owned = cid_pos > last_def
            line = body[:pos].count("\n") + 1
            # Окно прибития: от имени ЭТОГО шага до конца кейса (следующее
            # объявление `id=`). Смотреть только на сам `oneOf` было бы неверно —
            # у двухполосного отказа вторую полосу заявляет СЛЕДУЮЩИЙ шаг
            # (поллер `must_fail`), и такая форма законна.
            case_end = min([p for p in id_positions if p > cid_pos], default=len(body))
            step_pos = max([p for p in step_positions if p <= pos], default=cid_pos)
            window = body[max(step_pos, cid_pos):case_end] if owned else ""
            for codes in code_lists:
                if not codes or not classify(codes):
                    continue
                findings.append({
                    "file": path, "line": line, "codes": sorted(set(codes)),
                    "pmtest": pmlabel,
                    "case_id": cid if owned else "",
                    "case_title": ctitle if owned else "",
                    "step": sname, "owned": owned,
                    "pins_reject": pins(window, "REJECT"),
                    "pins_success": pins(window, "SUCCESS"),
                })
    return findings, scanned, unreadable


def split_top_level(s: str, sep: str = ","):
    """Разбить по разделителю ВЕРХНЕГО уровня: скобки и строковые литералы не в счёт.

    Нужно, чтобы отделить ПРЕДМЕТ `pm.expect` от диагностического сообщения:
    `pm.expect([undefined, null, 0, 6], '…' + JSON.stringify(j.error))` утверждает
    про массив, а слово `error` живёт в сообщении. Наивный split по запятой
    разорвал бы и сам массив.
    """
    out, depth, i, start, quote = [], 0, 0, 0, None
    while i < len(s):
        c = s[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "'\"`":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == sep and depth == 0:
            out.append(s[start:i])
            start = i + 1
        i += 1
    out.append(s[start:])
    return out


def expect_statements(text: str):
    """`(первый аргумент, матчер, разобрано)` для каждого `pm.expect(` в тексте.

    Скобка считается со скидкой на строковые литералы. ПРЕДПОСЫЛКА ОБХОДА
    измерена, а не предположена: на d24476c1 из 2635 мест `pm.expect(` в
    исполняемой части исходников кейсов скобка не закрылась у НУЛЯ. Место, где
    она не закроется, отдаётся третьим значением `False` — «не разобрано» есть
    отдельный исход, и `unparsed_expect_sites` роняет на нём прогон.
    """
    for m in RE_EXPECT_OPEN.finditer(text):
        j = m.end()
        if RE_FORM_MENTION.match(text[j:]):
            continue                          # форма НАЗВАНА, а не вызвана
        depth, k, quote = 1, j, None
        while k < len(text) and depth:
            c = text[k]
            if quote:
                if c == "\\":
                    k += 2
                    continue
                if c == quote:
                    quote = None
            elif c in "'\"`":
                quote = c
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            k += 1
        if depth:
            yield "", "", False, j
            continue
        end = text.find(";", k)
        yield (split_top_level(text[j:k - 1])[0],
               text[k:(end if end >= 0 else len(text))], True, j)


def error_assertion(first_arg: str, matcher: str):
    """Что это `pm.expect` утверждает об ошибке: `PRESENT` / `ABSENT` / `UNREAD` / `None`.

    `None` — про ошибку не утверждается ничего (слова нет в предмете либо
    матчер не читается). Слово `error` во ВТОРОМ аргументе — диагностика chai,
    предметом не является.

    КРИТЕРИЙ `PRESENT` — «утверждение НЕ МОЖЕТ ПРОЙТИ при отсутствующей ошибке».
    Всё, что при отсутствии ошибки проходит, наличия не доказывает и отказа не
    прибивает: перечисление с пустыми значениями, отрицательный матчер в голове,
    дизъюнкция, чья первая ветвь про ошибку не говорит.

    `UNREAD` — предмет про ошибку, но СПИСОК ЧЛЕНОВ `oneOf` не раскрыт статически
    (пришёл подстановкой). Отдельный исход, а не `PRESENT`: см. ниже, почему
    разрешающее умолчание здесь и было бы ловимым классом.
    """
    if not RE_ERR_WORD.search(first_arg):
        return None
    # Дизъюнкция: предметом считается ГОЛОВА. `j.response || j.error` при успехе
    # разрешается первой ветвью, то есть утверждается не ошибка. `(j.error &&
    # j.error.message) || ''` — голова про ошибку, хвост лишь запасное пустое.
    head = split_top_level(first_arg, "|")[0]
    if head.strip() and not RE_ERR_WORD.search(head):
        return None
    if RE_ABSENT_MATCHER.search(matcher):
        return "ABSENT"
    members = RE_ONEOF_MEMBERS.search(matcher)
    if members and RE_ABSENT_MEMBER.search(members.group(1)):
        return "ABSENT"                      # `error` ∈ {undefined, null}
    # СПИСОК ЧЛЕНОВ, ПРИШЕДШИЙ ПОДСТАНОВКОЙ, НЕ ПРОЧИТАН — и это отдельный исход
    # (найдено приёмкой 2026-08-06, остаточная асимметрия внутри самой правки).
    # Правило выше требует литеральных скобок сразу за `oneOf(`, поэтому форма
    # `.to.be.oneOf({codes_js})` уходила в разрешающее умолчание `PRESENT` и
    # ЗАСЧИТЫВАЛАСЬ КАК ПРИБИТЫЙ ОТКАЗ — без всякого счётчика непрочитанного. То
    # есть принцип, который этот же файл провозглашает для СПИСКА КОДОВ ОТВЕТА
    # («не смог прочитать» ≠ «чисто»), в этой ветке не действовал.
    # Замер (единица — место `pm.expect`, чей предмет про ошибку, а матчер —
    # `.to.be.oneOf(`; объём — 92 файла; ревизия a78dd6a8): таких мест 9, из них
    # 7 со списком-литералом и 2 подстановкой (`scripts/gen.py` compute и
    # storage), скобок-с-подстановкой внутри — 0.
    if members is None and RE_ONEOF_CALL.search(matcher):
        return "UNREAD"
    if members is not None and RE_FSUB.search(members.group(1)):
        return "UNREAD"                      # скобки есть, но внутри подстановка
    if RE_ERR_NEGATED.search(first_arg) and RE_TRUE_MATCHER.search(matcher):
        return "ABSENT"                      # `done && !error` → true
    if RE_ERR_BOOLEAN.search(first_arg) and RE_FALSE_MATCHER.search(matcher):
        return "ABSENT"                      # `Boolean(error)` / `!!error` → false
    if RE_NEGATED_MATCHER.search(matcher):
        return None                          # `.to.not.eql(…)` проходит без ошибки
    if RE_ANY_MATCHER.search(matcher):
        return "PRESENT"
    return None


def error_claims(window: str) -> set:
    """Множество того, что окно утверждает об ошибке: `{'PRESENT'} | {'ABSENT'}`.

    `UNREAD` тоже попадает в множество, но НИ ОДНО направление им не прибивается
    (см. `pins`): непрочитанное утверждение не вправе увести находку из красной
    корзины. Держать его в множестве нужно, чтобы счётчик по дереву считал ровно
    те места, которые классификатор не прочитал, — а не пересчитывал их своим,
    вторым предикатом (два предиката об одном предмете разъезжаются).
    """
    out = set()
    for first, matcher, ok, _ in expect_statements(window):
        if not ok:
            continue
        k = error_assertion(first, matcher)
        if k:
            out.add(k)
    return out


def unread_error_member_sites(paths):
    """Места, где предмет про ошибку, а список членов `oneOf` не раскрыт.

    ПОЧЕМУ ЭТО ПРЕДУПРЕЖДЕНИЕ, А НЕ ОТКАЗ — в отличие от списка КОДОВ ОТВЕТА,
    который прогон роняет. У кодов ответа исход назван и достижим: записать
    список литералом рядом с вызовом либо присвоить идентификатору в том же
    файле. Здесь литерала не существует в принципе: `codes_js = "[" + ", ".join(
    str(c) for c in codes) + "]"` собирается из аргумента ВЫЗЫВАЮЩЕГО и у каждого
    свой. Гейт, краснеющий на законной конструкции без достижимого исхода, снимут
    первым же ложным срабатыванием — и вместе с ним уйдёт весь класс.

    Поэтому «не прочитал» здесь выражается ДВУМЯ вещами сразу, и ни одной из них
    по отдельности не хватило бы: (а) непрочитанное НЕ ПРИБИВАЕТ ничего, то есть
    находка остаётся в своей красной корзине, а не уходит в тишину по умолчанию;
    (б) число печатается отдельной строкой вердикта. Разрешающее умолчание без
    счётчика — это ровно «ноль находок», неотличимый от «ноль прочитанного».
    """
    out = []
    for path in paths:
        try:
            raw = open(path, encoding="utf-8").read()
        except OSError:
            continue
        body = strip_js_comments("\n".join(
            "" if ln.lstrip().startswith("#") else ln for ln in raw.split("\n")))
        for first, matcher, ok, pos in expect_statements(body):
            if not ok or error_assertion(first, matcher) != "UNREAD":
                continue
            out.append({"file": path, "line": body[:pos].count("\n") + 1,
                        "arg": " ".join((first + matcher).split())[:120]})
    return out


def unparsed_expect_sites(paths):
    """Места `pm.expect(`, чью скобку не удалось закрыть.

    ПРОВЕРКА СОБСТВЕННОЙ ПРЕДПОСЫЛКИ. Разделение «ошибка есть» и «ошибки нет»
    держится на том, что предмет и матчер отделимы разбором. Место, где разбор
    не сошёлся, не проверено ничем — и молчать о нём значило бы повторить
    ловимый класс ещё раз: «не смог прочитать» неотличимо от «чисто».
    """
    bad = []
    for path in paths:
        try:
            raw = open(path, encoding="utf-8").read()
        except OSError:
            continue
        body = strip_js_comments("\n".join(
            "" if ln.lstrip().startswith("#") else ln for ln in raw.split("\n")))
        for m in RE_EXPECT_OPEN.finditer(body):
            if RE_FORM_MENTION.match(body[m.end():]):
                continue
            # Та же механика счёта скобки, что в `expect_statements`, но с
            # позицией: сама она позиций не возвращает, а находке нужна координата.
            j, depth, k, quote = m.end(), 1, m.end(), None
            while k < len(body) and depth:
                c = body[k]
                if quote:
                    if c == "\\":
                        k += 2
                        continue
                    if c == quote:
                        quote = None
                elif c in "'\"`":
                    quote = c
                elif c == "(":
                    depth += 1
                elif c == ")":
                    depth -= 1
                k += 1
            if depth:
                bad.append({"file": path, "line": body[:j].count("\n") + 1})
    return bad


def pins(window: str, want: str) -> bool:
    """Прибито ли в этом окне обещание направления `want`.

    «Прибито» значит: есть утверждение, которое ОТЛИЧАЕТ обещанный исход от
    противоположного. Для отказа это НАЛИЧИЕ ошибки операции, синхронный код
    отказа, отрицательная видимость (`to.not.include`) либо вызов помощника,
    который всё перечисленное делает за вызывающего. Утверждение одного лишь
    `done` не прибивает ничего: у операции, завершившейся ОШИБКОЙ, `done` тоже
    `true` — тот же класс, что ловит `assert-delete-operation-outcome.py`.

    НАЛИЧИЕ ошибки и ЕЁ ОТСУТСТВИЕ разведены (см. `error_assertion`): «ошибки
    нет» прибивает УСПЕХ и не прибивает отказ. Прежняя редакция засчитывала в
    прибитие отказа любое упоминание слова `error`, включая утверждения, что
    ошибки нет, — то есть уводила находку из красного утверждением, которое
    доказывает противоположное.
    """
    claims = error_claims(window)
    if want == "REJECT":
        if "PRESENT" in claims or RE_PIN_REJECT_MARK.search(window):
            return True
        lo, hi = 400, 599
    else:
        if "ABSENT" in claims or RE_PIN_SUCCESS_MARK.search(window):
            return True
        lo, hi = 200, 299
    # Утверждение над кодом ответа, ВСЕ исходы которого лежат в нужной половине,
    # тоже прибивает: `oneOf([400, 403, 404])` — это «отказ, полоса не важна».
    for m in RE_CODE_EQL.finditer(window):
        if lo <= int(m.group(1)) <= hi:
            return True
    for m in RE_CODE_ONEOF.finditer(window):
        cs = [int(p) for p in m.group(1).replace(" ", "").split(",") if p]
        if cs and all(lo <= c <= hi for c in cs):
            return True
    return False


def is_housekeeping(f) -> bool:
    """Шаг освобождён как уборка — ролью, а не глаголом (см. два яруса выше)."""
    s, pm = f["step"] or "", f["pmtest"] or ""
    if RE_TEARDOWN_ROLE.search(s) or RE_TEARDOWN_ROLE.search(pm):
        return True
    if RE_TEARDOWN_VERB.search(s) or RE_TEARDOWN_VERB.search(pm):
        # Глагол освобождает, только если предмет кейса — НЕ он сам.
        subject_is_delete = bool(
            RE_CASE_SUBJECT_DELETE_ID.search(f["case_id"] or "")
            or RE_CASE_SUBJECT_DELETE_TITLE.search(f["case_title"] or ""))
        return not subject_is_delete
    return False


def bucketize(findings):
    """Разложить находки по корзинам. Красные — только REJECT и SUCCESS.

    ПОРЯДОК РАЗБОРА ИСПРАВЛЕН 2026-08-06. Прежде ветка уборки стояла ПЕРВОЙ и
    делала `continue`, поэтому обещание кейса не читалось вовсе: слово в имени
    шага перебивало заголовок. Теперь освобождение уборки решается ярусом (роль
    освобождает всегда, голый глагол — только когда предмет кейса не он), а
    обещание, которое НЕЧЕМ прибить, остаётся находкой.
    """
    buckets = {"REJECT": [], "SUCCESS": [], "BOTH": [], "NONE": [], "TEARDOWN": [],
               "UNOWNED": []}
    for f in findings:
        if not f["owned"]:
            # Обещания нет: находка внутри параметризованного помощника. Она НЕ
            # молчит — она в своей корзине, и её надо смотреть глазами у каждого
            # вызывающего.
            f["dir"] = "UNOWNED"
            buckets["UNOWNED"].append(f)
            continue
        if is_housekeeping(f):
            f["dir"] = "TEARDOWN"
            buckets["TEARDOWN"].append(f)
            continue
        # Направление решает МЕТКА КЕЙСА (id + title) — то, что объявляет, ЗАЧЕМ
        # кейс существует. Имя `pm.test` частью обещания НЕ является: это часть
        # самого утверждения, и хеджирующее имя («200 или 403») — ровно тот
        # способ, которым дефект прячется от свипа по именам утверждений.
        d = direction(direction_subject(f["case_id"], f["case_title"]))
        # Двухполосный отказ — законная форма Kachō, если вторая полоса заявлена.
        # Прибитое обещание уводит находку из красного в свою корзину, но НЕ в
        # тишину: она остаётся видна как PINNED.
        if d == "REJECT" and f.get("pins_reject"):
            d = "BOTH"
        elif d == "SUCCESS" and f.get("pins_success"):
            d = "BOTH"
        f["dir"] = d
        buckets[d].append(f)
    return buckets


RE_NEG_CASE = re.compile(r"(?:^|[-_])(?:NEG|DENY|FORBID)(?:[-_]|$)")


def negative_vocabulary_coverage(labels):
    """Доля ОБЪЯВЛЕННО отрицательных кейсов, которых словарь не читает вовсе.

    ПРОВЕРКА СОБСТВЕННОЙ ПРЕДПОСЫЛКИ. Вердикт «REJECT: 0» обоснован допущением
    «я умею прочитать, как это дерево обещает отказ». Допущение — факт о дереве,
    и оно меняется: заведут суиту, пишущую отказ иначе, — корзина останется
    пустой, а гейт будет печатать «чисто». Кейс, сам объявивший себя
    отрицательным токеном `-NEG-`/`-DENY-` в идентификаторе, обязан читаться как
    REJECT; если он не читается НИКАК (`NONE`), дыра в мерке, а не в дереве.

    `labels` — пары (идентификатор кейса, заголовок).
    """
    negs = [(cid, t) for cid, t in labels if RE_NEG_CASE.search(cid or "")]
    if not negs:
        return 0.0, []
    unknown = [(cid, t) for cid, t in negs
               if direction(direction_subject(cid, t)) == "NONE"]
    return 100.0 * len(unknown) / len(negs), unknown


def stale_vocabulary(step_names, case_labels):
    """Записи словаря, которым в дереве больше нечего классифицировать.

    Послабление обязано ИСТЕКАТЬ САМО (`testing.md` §«Гейт на класс», п. 5):
    запись, которой нечего освобождать, невидимо наследует следующую слепую зону.
    То же и со словарём направления — он часть предиката, а не украшение.

    ЕДИНИЦА СЧЁТА ОБЪЯВЛЕНА ЯВНО, и это не формальность: первая попытка мерить
    прогоняла шаблоны по ТЕКСТУ ФАЙЛА и объявила мёртвыми `^del-`, `-rm$`,
    `\\bdrop-` — все три живы, просто якорь строки не совпадает с границей
    имени шага. Шаблоны уборки сверяются с ИМЕНАМИ шагов и `pm.test`, шаблоны
    направления — с тем текстом, который классификатор ЧИТАЕТ, то есть с
    `direction_subject` (заголовок кейса). Предикат обязан видеть ту единицу, о
    которой отчитывается.

    ЕДИНИЦА СУЖЕНА ВМЕСТЕ С КЛАССИФИКАТОРОМ (#1180). Прежде сюда приходило
    `title + id`, и запись, живая ТОЛЬКО в идентификаторе, числилась имеющей
    предмет — при том что направление она уже не решала бы ничего. Самоистечение
    обязано мерить то же, что мерит вердикт, иначе оно охраняет чужой предмет.
    Замер на 02e3667a: записей, живых только в идентификаторах, — 0, поэтому
    сужение не сняло с дерева ни одной живой записи и ни одной не воскресило.
    """
    dead = []
    for w in TEARDOWN_WORDS:
        if not any(re.search(w, n, re.I) for n in step_names):
            dead.append(w)
    for w in REJECT_WORDS + SUCCESS_WORDS:
        if not any(re.search(w, l, re.I) for l in case_labels):
            dead.append(w)
    # Подсловарь 5xx сверяется ТОЙ ЖЕ охраной отрицания, какой его читает
    # `direction()` (#1197). Сырым поиском запись `\b500\b` числилась бы живой —
    # десять вхождений в дереве, — при том что классифицирует она НОЛЬ: все десять
    # стоят под отрицанием («не 500», «без 500/leak», «no 500»). Самоистечение,
    # мерящее не то, что мерит вердикт, охраняет чужой предмет — замечание #1180,
    # там же и почему единица сужалась.
    for w in REJECT_WORDS_5XX:
        rx = re.compile(w, re.I)
        if not any(unnegated_hits(rx, l) for l in case_labels):
            dead.append(w)
    return dead




def collect_vocabulary_subjects(paths):
    """Единицы, с которыми сверяются словари: имена шагов и заголовки кейсов.

    Возвращает (имена шагов и `pm.test`, пары (id, title), перепись заголовков).
    Читается та же исполняемая часть, что и в `scan_case_sources`: словарь,
    сверенный с закомментированным кодом, объявил бы живым то, чего в прогоне
    нет.

    Перепись заголовков — ОТДЕЛЬНОЕ утверждение, и она печатается. Без неё
    «прочитано ноль» неотличимо от «заголовков нет», а расширение
    распознавателя — от холостого: число прочитанных обязано вырасти, иначе
    расширение снимают, а не оставляют «на всякий случай».
    """
    names, labels = set(), []
    census = {"всего": 0, "простой": 0, "скобочной": 0, "без литерала": 0}
    for path in paths:
        try:
            raw = open(path, encoding="utf-8").read()
        except OSError:
            continue
        body = strip_js_comments("\n".join(
            "" if ln.lstrip().startswith("#") else ln for ln in raw.split("\n")))
        for m in re.finditer(r"\bname=\s*f?[\"']([^\"']*)[\"']", body):
            names.add(RE_FSUB.sub(" ", m.group(1)))
        for m in RE_PMTEST.finditer(body):
            names.add(m.group(2))
        ids = [(m.start(), RE_FSUB.sub(" ", m.group(1)))
               for m in re.finditer(r"\bid=\s*f?[\"']([^\"']*)[\"']", body)]
        # Все законные формы записи заголовка — см. `find_titles`.
        found = find_titles(body)
        titles = [(q, RE_FSUB.sub(" ", t)) for q, t in found]
        declared = [m.start() for m in RE_TITLE_ANY.finditer(body)]
        simple = {m.start() for m in RE_TITLE_SIMPLE.finditer(body)}
        read_at = {q for q, _ in found}
        census["всего"] += len(declared)
        census["простой"] += len(read_at & simple)
        census["скобочной"] += len(read_at - simple)
        census["без литерала"] += len([q for q in declared if q not in read_at])
        for pos, cid in ids:
            after = [v for q, v in titles if q > pos]
            labels.append((cid, after[0] if after else ""))
    return names, labels, census


# Порог предпосылки. Мерка обоснована тем, что словарь читает дерево; порог
# связывает эту предпосылку с вердиктом, а не оставляет её на веру.
#
# ЕДИНИЦА СЧЁТА И ПРЕДИКАТ НАЗВАНЫ, ПОТОМУ ЧТО ЗДЕСЬ УЖЕ ОШИБЛИСЬ. Единица —
# КЕЙС, объявивший себя отрицательным токеном `-NEG-`/`-DENY-`/`-FORBID-` в
# идентификаторе; объём — 92 файла, 1478 объявлений кейсов, из них 394
# отрицательных; ревизия d24476c1. Предикатов ДВА, и они дают разные числа:
#
#   «не читается НИ ОДНИМ словом» (`direction()=="NONE"`) — базовый словарь
#       даёт 52 (13.2%), нынешний — 2 (0.5%). ЭТО И МЕРИТ КОД НИЖЕ;
#   «не прочитан КАК ОТКАЗ» (`NONE`+`SUCCESS`+`BOTH`) — базовый словарь даёт
#       83 (21.1%), нынешний — 34 (8.6%).
#
# Первая редакция этого комментария и тело коммита несли «83 (21.1%)» рядом со
# словами «не читались ни одним словом»: число второго предиката при описании
# первого. Число было верным — для другой мерки; описание было верным — для
# другого числа. Правка приведена к КОДУ: он меряет `NONE`.
#
# ПОРОГ В ПРОЦЕНТАХ СНЯТ — ОН НЕ МОГ ИСТЕЧЬ САМ (по замечанию приёмки 2026-08-06).
# Стояло `5.0%` при текущем значении `0.5%`: десятикратный запас, не связанный ни
# с каким предикатом снятия. Мерка печатала число, поэтому дрейф был виден, но
# УПАСТЬ она смогла бы только после того, как словарь ослепнет на порядок — то
# есть послабление пережило бы свой предмет и не сказало бы об этом.
#
# Вместо порога — ПОИМЁННОЕ РАЗРЕШЕНИЕ, той же формы, что `stale_vocabulary` в
# этом же файле: у послабления есть предмет, и оно истекает вместе с ним. Ниже
# перечислены ровно те кейсы, чей заголовок словарь прочитать не может, не
# заведя слова, которое начнёт ложно срабатывать («unknown», «only»). Мерка
# роняет прогон в ОБЕ стороны:
#   • появился нечитаемый кейс, которого в списке нет → находка, кейс назван;
#   • кейс из списка стал читаться → находка тоже: разрешение без предмета
#     молча унаследует следующую слепую зону (`testing.md` §«Гейт на класс», п.5).
#
# Замер (единица — КЕЙС, объявивший себя отрицательным токеном `-NEG-`/`-DENY-`/
# `-FORBID-`; объём — 92 файла, 1478 объявлений, 394 отрицательных): список
# совпадает на ТРЁХ ревизиях — d24476c1, a78dd6a8 и снимке 044e3969, где сведены
# восемь веток, — то есть он про дерево, а не про одну ветку.
NEG_UNREADABLE_ALLOWED = {
    # Заголовок целиком про ВХОД («type:'unknown.thing'»), слова об исходе в нём
    # нет вовсе; читаемым его сделает правка заголовка кейса, а не словаря.
    "IAM-ACB-RD-CR-TARGET-UNKNOWN-TYPE-NEG",
    # Отказ выражен сужением («system roles only, not accountB custom»). Слово
    # «only» в словаре отказа ложно срабатывало бы на половине положительных.
    "IAM-ROL-LS-NEG-NO-FOREIGN-CUSTOM",
}


def neg_coverage_verdict(unknown_ids):
    """(нечитаемые вне списка, разрешения без предмета) — обе половины красные."""
    unknown = set(unknown_ids)
    return (sorted(unknown - NEG_UNREADABLE_ALLOWED),
            sorted(NEG_UNREADABLE_ALLOWED - unknown))


def negative_success_misread(labels):
    """`-NEG-`-кейсы, чей ЗАГОЛОВОК читается как обещание УСПЕХА.

    ВТОРАЯ ПОЛОВИНА ПРОВЕРКИ СОБСТВЕННОЙ ПРЕДПОСЫЛКИ (#1180).
    `negative_vocabulary_coverage` выше ловит только `NONE` — «не прочитан».
    Кейс, прочитанный НЕВЕРНО, для неё прочитан, поэтому число нечитаемых
    занижено, а слепая зона у мерки оказывается ровно там, где ошибка МЕНЯЕТ
    вердикт, а не отсутствует. Живой экземпляр: `-NEG-`-кейс, чей заголовок
    говорит отказ дважды, получал обещание УСПЕХА по хвосту `SUCCEEDS` в
    собственном идентификаторе (закрыто `direction_subject` + словарём).

    `BOTH` находкой НЕ является и это не послабление: пара «видит … но НЕ
    получает» — канонический вид кейса о сужении выдачи (#1163, #1178), у неё
    в дереве 34 экземпляра, и обе полосы она обещает честно.
    """
    return sorted({cid for cid, t in labels
                   if RE_NEG_CASE.search(cid or "")
                   and direction(direction_subject(cid, t)) == "SUCCESS"})


# Поимённое разрешение, той же формы и той же дисциплины, что
# `NEG_UNREADABLE_ALLOWED`: у послабления есть ПРЕДМЕТ, и оно истекает вместе с
# ним. Мерка красная в ОБЕ стороны — появился неназванный, ИЛИ названный
# перестал быть таким.
#
# Исход выбран не «запретить `-NEG-` читаться как успех»: законный такой кейс
# существует, и запрет краснел бы на нём — а гейт, краснеющий на законном,
# снимают первым же ложным срабатыванием.
NEG_SUCCESS_ALLOWED = {
    # Анти-оракульный кейс: сужение по значению, которого ни у кого нет, обязано
    # вернуть 200 с ПУСТОЙ страницей, а не отказ, — иначе по коду ответа
    # отличают «нет доступа» от «не существует». Отрицание здесь про
    # СОДЕРЖИМОЕ страницы, а не про код; заголовок обещает успех верно.
    # `services/vpc/tests/newman/cases/address.py`, classes NEG+AUTHZ, P0.
    "ADR-LBV-NEG-NF",
}


def neg_success_verdict(success_ids):
    """(прочитанные как успех вне списка, разрешения без предмета) — обе красные."""
    got = set(success_ids)
    return (sorted(got - NEG_SUCCESS_ALLOWED),
            sorted(NEG_SUCCESS_ALLOWED - got))


def main():
    if "--self-test" in sys.argv:
        return self_test()
    roots = sorted(glob.glob("services/*/tests/newman")) + ["gateway/tests/newman"]
    paths = []
    for r in roots:
        paths += sorted(glob.glob(os.path.join(r, "cases", "*.py")))
        paths += sorted(glob.glob(os.path.join(r, "scripts", "gen.py")))
    findings, scanned, unreadable = scan_case_sources(paths)

    if scanned == 0:
        print("НИЧЕГО НЕ ПРОЧИТАНО — предикат ничего не утверждает", file=sys.stderr)
        return 2

    buckets = bucketize(findings)
    step_names, case_labels, title_census = collect_vocabulary_subjects(paths)

