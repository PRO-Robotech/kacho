RE_ABSENT_MEMBER = re.compile(r"\b(?:undefined|null)\b")
RE_NEGATED_MATCHER = re.compile(r"\.to\.not\.")
# `!x.error` — но НЕ `!!x.error`: двойное отрицание приводит к булеву, а не
