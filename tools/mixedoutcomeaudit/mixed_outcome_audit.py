    if dead:
        for w in dead:
            print(f"  мёртвая запись словаря: {w}", file=sys.stderr)
        print(f"\nПОСЛАБЛЕНИЕ БЕЗ ПРЕДМЕТА: {len(dead)} записей словаря не "
              f"классифицируют в дереве НИЧЕГО. Запись, которой нечего освобождать, "
              f"молча унаследует следующая слепая зона — ровно так `del-` начал "
              f"глотать шаг, чьё удаление и было предметом кейса. Исход: удалить "
              f"запись либо назвать место в дереве, ради которого она держится.",
              file=sys.stderr)
