    # (11) МОЛЧАНИЕ: кейс обещает отказ, утверждение шага принимает обе полосы —
    #      но отказ ПРИБИТ другим утверждением того же кейса (ошибка операции).
    #      Это законная двухполосная форма (`assert_refused_sync_or_async` +
