    # (61) КРАСНОЕ: ПУСТОЙ словарь обязан совпадать НИ С ЧЕМ. `"|".join([])` даёт
    #      пустой образец, а он совпадает в каждой позиции любой строки — значит
    #      словарь, из которого вынули последнюю запись, объявил бы отказом ВСЕ
