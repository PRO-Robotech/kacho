    if buckets["UNOWNED"]:
        print(f"\nВНИМАНИЕ: {len(buckets['UNOWNED'])} находок внутри параметризованных "
              f"помощников — статически ничьи, смотреть глазами у каждого вызывающего "
              f"(запуск с аргументом UNOWNED покажет их).", file=sys.stderr)
