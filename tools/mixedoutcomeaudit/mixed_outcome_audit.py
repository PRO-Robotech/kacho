    # (56) КРАСНОЕ: САМОИСТЕЧЕНИЕ мерит ТО ЖЕ, что вердикт. Запись словаря 5xx,
    #      у которой в дереве только ОТРИЦАЕМЫЕ вхождения, классифицирует НОЛЬ —
