              f"направления, пустая корзина REJECT означает «не умею прочитать», а не "
              f"«чисто». Исходы: пополнить REJECT_WORDS оборотом из заголовка; "
              f"поправить заголовок кейса; внести кейс в NEG_UNREADABLE_ALLOWED с "
              f"причиной. Для второй половины исход один — убрать из "
              f"NEG_UNREADABLE_ALLOWED запись, которой больше нечего разрешать.",
