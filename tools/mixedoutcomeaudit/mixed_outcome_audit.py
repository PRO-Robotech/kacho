    #      вплотную получилось бы несуществующее слово на стыке.
    _, labels, _ = vocab(
        'Case(id="X-BRANCH", title=(f"поле {fld} → отказ: sync 403"\n'
        '                           if scope_field else\n'
        '                           f"поле {fld} → отказ: sync 400"), steps=[])\n')
    got = dict(labels).get("X-BRANCH", "")
    check("обе ветки условного заголовка прочитаны и не склеены вплотную",
          "403" in got and "400" in got and "403поле" not in got,
          f"метка {got!r}")

    # (69) ГРАНИЦА, а не слепая зона: `title=inner_case.title` литерала не несёт
    #      ВОВСЕ — читать нечего by construction, и выдумывать нельзя. Такое
    #      объявление обязано остаться без текста, а не получить чужой.
    _, labels, _ = vocab(
        'Case(id="X-VAR", title=(inner_case.title), steps=[])\n'
        'Case(id="X-NEXT", title="Create → 200", steps=[])\n')
    check("скобка без литерала текста не даёт и чужого не занимает",
          dict(labels).get("X-VAR") == "Create → 200"
          and dict(labels).get("X-NEXT") == "Create → 200",
          f"метки {dict(labels)}")

    # (70) ПЕРЕПИСЬ — отдельное утверждение: расширение обязано быть ВИДНО числом.
    #      Перепись, не изменившаяся от расширения, означает холостое расширение,
    #      и тогда его снимают, а не оставляют «на всякий случай».
    _, _, cens = vocab(
        'Case(id="A", title="простая", steps=[])\n'
        'Case(id="B", title=("скобочная " "склейка"), steps=[])\n'
        'Case(id="C", title=inner.title, steps=[])\n')
    check("перепись различает три формы записи заголовка",
          cens == {"всего": 3, "простой": 1, "скобочной": 1, "без литерала": 1},
          f"перепись {cens}")

    print("\n" + ("PASS: смешанный исход" if rc == 0 else "FAIL: смешанный исход"))
    return rc


