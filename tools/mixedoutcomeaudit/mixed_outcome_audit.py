    # ── НАЛИЧИЕ ОШИБКИ ≠ ЕЁ ОТСУТСТВИЕ (найдено приёмкой 2026-08-06) ─────────
    #
    # Инъекция (11) выше — законный близнец: отказ прибит утверждением, что ошибка
    # ЕСТЬ. Пары к ней не было, и без пары отрицание зеленеет на всём сломанном:
    # прежняя редакция прибивала отказ ЛЮБЫМ упоминанием слова `error`, включая
    # утверждения, что ошибки НЕТ. Ниже — формы, каждая живая в дереве, и у
    # каждой свой близнец. Все они обязаны КРАСНЕТЬ: ни одна отказа не доказывает.
    #
    # Перепись (единица — вхождение прежней альтернативы в исполняемой части;
    # объём — 92 файла, 164 вхождения; ревизия d24476c1; классификатор нынешний):
    # 84 утверждают ОТСУТСТВИЕ ошибки — больше половины. То есть альтернатива,
    # заведённая как признак прибитого ОТКАЗА, чаще указывала на УСПЕХ.

    def bucket_of(src_):
        return bucketize(scan(src_)[0])

    def mixed_reject_case(cid, pin_step, pin_body):
        return (
            f'Case(id="{cid}", title="Delete SG, прилинкованного к NIC → '
            'FailedPrecondition",\n'
            '     steps=[Step(name="del-sg-attached", test="pm.test(\'sync 200 or 400\', '
            '() => pm.expect(pm.response.code).to.be.oneOf([200, 400]));"),\n'
            f'            Step(name="{pin_step}", test="pm.test(\'chk\', () => '
            f'{{ {pin_body}; }});")])\n')

    # (12) КРАСНОЕ: единственное утверждение об ошибке проверяет, что её НЕТ.
    #      Живая форма — `pm.expect(j.error, JSON.stringify(j)).to.not.exist`
    #      (29 вхождений) и `.to.be.undefined` (9).
    b = bucket_of(mixed_reject_case(
        "X-DEL-NEG-ABSENT", "check-result",
        "pm.expect(j.error, JSON.stringify(j)).to.not.exist"))
