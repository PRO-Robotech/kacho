    # ── МЕХАНИЗМЫ, КОТОРЫЕ САМОПРОВЕРКА НЕ ЗАПИРАЛА (мета-инъекция приёмки) ──
    #
    # Приёмка 2026-08-06 прогнала по мерке десять хирургических мутаций — по одной
    # на механизм — и спросила у самопроверки, ловит ли она СНЯТИЕ СВОЕГО. Семь
    # ловились, три нет. Один из трёх был регрессией этой же итерации и починен
