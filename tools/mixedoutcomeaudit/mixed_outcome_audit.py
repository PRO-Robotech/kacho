    # (58) ПЕРЕПИСЬ ПО 5xx — отдельное утверждение: «ноль прочитанных по 5xx»
    #      обязано быть отличимо от «по 5xx не искали». Считаются ровно
    #      неотрицаемые вхождения.
    check("перепись по 5xx считает только неотрицаемые вхождения",
          reject_5xx_hits(t_503) and not reject_5xx_hits(t_not503),
          f"на объявлении {reject_5xx_hits(t_503)}, "
          f"на отрицании {reject_5xx_hits(t_not503)}")

    # (59) КРАСНОЕ: охрана отрицания читает и РУССКОЕ написание. Оно не про запас:
    #      именно на нём держится вывод, по которому кода 500 в подсловаре НЕТ —
    #      все десять его вхождений в дереве записаны так («не 500», «без
