    #
    # (31) КРАСНОЕ: владение находки решается ГРАНИЦЕЙ ОБЪЯВЛЕНИЯ ФУНКЦИИ.
    #      `oneOf` в теле параметризованного помощника не принадлежит никакому
    #      кейсу: помощник раскрывается у каждого вызывающего со своей меткой, и
    #      статически ни одна к нему не привязана. Без этого механизма находка
    #      занимает обещание СОСЕДНЕГО кейса, стоящего выше по файлу, — то есть
    #      мерка отвечает про чужой предмет. Живых таких находок в дереве 26
    #      (корзина UNOWNED, ревизия a78dd6a8), эталон формы —
    #      `services/iam/tests/newman/cases/iam-rbac-subjects.py:240`.
    src = (
        'Case(id="X-DEL-NEG-ATTACHED", title="Delete SG, прилинкованного к NIC → '
        'FailedPrecondition",\n'
        '     steps=[Step(name="del-sg", test="pm.test(\'sync\', '
        '() => pm.expect(pm.response.code).to.eql(400));")])\n'
        '\n'
        'def _revoke(case_id):\n'
        '    return Step(name="revoke", test="pm.test(\'revoked or already gone\', '
        '() => pm.expect(pm.response.code).to.be.oneOf([200, 404]));")\n'
    )
