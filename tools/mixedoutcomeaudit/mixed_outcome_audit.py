def self_test():
    """Инъекция в ОБЕ стороны: предикат обязан краснеть на внесённом дефекте и
    молчать на законной конструкции той же формы.

    Гейт жил без этой ветки, и именно её отсутствие дало ему прожить со слепой
    зоной: он читал только литеральный список кодов, печатал «чисто» и был
    неотличим от работающего. Проверяются ровно те четыре формы, на которых
    ошибка и была возможна.
    """
    import tempfile

    def scan(src):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "cases.py")
            open(p, "w", encoding="utf-8").write(src)
            return scan_case_sources([p])

    rc = 0

    def check(name, ok, detail=""):
        nonlocal rc
        print(f"  {'ОК ' if ok else 'ПРОВАЛ'} {name}{'' if ok else ' — ' + detail}")
        if not ok:
            rc = 1

    print("=== смешанный исход: инъекции ===")

    # (1) КРАСНОЕ, форма-подстановка. Заголовок обещает ОТКАЗ, список кодов
    #     приходит идентификатором и содержит 200. Ровно живая форма из
    #     services/vpc/tests/newman/scripts/gen.py.
    src = (
        'codes = "[400, 200, 403]"\n'
        'Case(id="X-CR-VAL-REQ-NAME", title="Create без required поля → 400 InvalidArgument",\n'
        '     steps=[Step(name="cr-no-name", test=f"pm.test(\'rejected\', () => '
        'pm.expect(pm.response.code).to.be.oneOf({codes}));")])\n'
    )
    f, _, u = scan(src)
    bad = [x for x in f if direction(label_of(x, "case")) == "REJECT"]
    check("подстановочный список кодов прочитан и признан нарушением",
          len(bad) == 1 and not u, f"находок REJECT {len(bad)}, непрочитанных {len(u)}")

    # (2) МОЛЧАНИЕ на законном той же формы: список кодов — только отказы
    #     (документированная терпимость authz-first), подстановка та же.
    src = (
        'codes = "[400, 403, 404]"\n'
        'Case(id="X-GET-NEG-ABSENT", title="Get несуществующего → отказ",\n'
        '     steps=[Step(name="get-absent", test=f"pm.test(\'rejected\', () => '
        'pm.expect(pm.response.code).to.be.oneOf({codes}));")])\n'
    )
    f, _, u = scan(src)
    check("список только из отказов той же формы — не находка",
          not f and not u, f"находок {len(f)}, непрочитанных {len(u)}")

    # (3) КРАСНОЕ: список кодов вообще не раскрывается статически. Молчать о нём
    #     нельзя — «не смог прочитать» неотличимо от «чисто».
    src = (
        'Case(id="X-CR-VAL", title="Create без поля → 400 InvalidArgument",\n'
        '     steps=[Step(name="cr", test=f"pm.test(\'rejected\', () => '
        'pm.expect(pm.response.code).to.be.oneOf({build_codes(fld)}));")])\n'
    )
    f, _, u = scan(src)
    check("нераскрываемый список попадает в непрочитанное, а не в «чисто»",
          len(u) == 1, f"непрочитанных {len(u)}")

    # (4) МОЛЧАНИЕ: обычный литеральный список — прежнее поведение не сломано.
    src = (
        'Case(id="X-CR-OK", title="Create → 200",\n'
        '     steps=[Step(name="cr", test="pm.test(\'ok\', () => '
        'pm.expect(pm.response.code).to.be.oneOf([200, 201]));")])\n'
    )
    f, _, u = scan(src)
    check("однородный литеральный список — не находка и не непрочитанное",
          not f and not u, f"находок {len(f)}, непрочитанных {len(u)}")

    # ── ФОРМА СО СКОБКАМИ, В КОТОРЫХ СТОИТ ПОДСТАНОВКА ───────────────────────
    #
    # Предыдущая редакция считала «скобка на месте» за «список прочитан»: сайт
    # попадал в ветку литерала, из `{codes}` не извлекалось НИ ОДНОГО кода, пустой
    # список молча пропускался — и в находки, и в непрочитанное. Три исхода
    # схлопывались в «чисто». Ровно этой формой записаны пять живых мест дерева, и
    # четыре из них появились ПЕРЕПИСЬЮ прежней формы `oneOf({codes})`, которую
    # предикат читать умел: переписав кейсы, мы увели их из-под собственной мерки.

    # (5) КРАСНОЕ: скобка с подстановкой, чей список раскрывается по умолчанию
    #     сигнатуры и СМЕШИВАЕТ успех с отказом. Живая форма vpc/nlb.
    src = (
        'def refuse(what, sync_codes=(400,), async_lane=True):\n'
        '    codes = ", ".join(str(c) for c in ((*sync_codes, 200) if async_lane else sync_codes))\n'
        '    return [f"pm.test(\'{what} refused\', () => '
        'pm.expect(pm.response.code).to.be.oneOf([{codes}]));"]\n'
    )
    f, _, u = scan(src)
    got = sorted({c for x in f for c in x["codes"]})
    check("скобка с подстановкой прочитана: смешанный список — находка, а не тишина",
          len(f) == 1 and 200 in got and 400 in got and not u,
          f"находок {len(f)} codes={got}, непрочитанных {len(u)}")

    # (6) МОЛЧАНИЕ на законном близнеце ТОЙ ЖЕ формы: скобка с подстановкой, чей
    #     список — только отказы. Без этой половины гейт ловил бы форму, а не
    #     существо, и был бы снят при первом ложном срабатывании.
    src = (
        'def refuse(what, sync_codes=(400, 403, 404)):\n'
        '    codes = ", ".join(str(c) for c in sync_codes)\n'
        '    return [f"pm.test(\'{what} refused\', () => '
        'pm.expect(pm.response.code).to.be.oneOf([{codes}]));"]\n'
    )
    f, _, u = scan(src)
    check("скобка с подстановкой, раскрывшаяся в одни отказы — не находка",
          not f and not u, f"находок {len(f)}, непрочитанных {len(u)}")

    # (7) КРАСНОЕ: скобка с подстановкой, которая не раскрывается ничем. «Не смог
    #     прочитать» обязано отличаться от «чисто» и в этой форме тоже.
    src = (
        'Case(id="X-CR-VAL", title="Create без поля → 400 InvalidArgument",\n'
        '     steps=[Step(name="cr", test=f"pm.test(\'rejected\', () => '
        'pm.expect(pm.response.code).to.be.oneOf([{build_codes(fld)}]));")])\n'
    )
    f, _, u = scan(src)
    check("нераскрываемая подстановка в скобках → непрочитанное, а не «чисто»",
          len(u) == 1 and not f, f"находок {len(f)}, непрочитанных {len(u)}")

    # (8) МОЛЧАНИЕ: подстановка в скобках над величиной, которая КОДОМ ОТВЕТА не
    #     является (строковые состояния Operation). Требовать от неё читаемости
    #     значило бы краснеть на законном.
    src = (
        'Case(id="X-OP", title="Operation доходит до терминального состояния",\n'
        '     steps=[Step(name="poll", test=f"pm.test(\'terminal\', () => '
        'pm.expect(j.status).to.be.oneOf([{states}]));")])\n'
    )
    f, _, u = scan(src)
    check("подстановка в скобках не над кодом ответа — не непрочитанное",
          not f and not u, f"находок {len(f)}, непрочитанных {len(u)}")

    # ── РАЗРЕШЕНИЕ ОСВОБОЖДЕНИЙ (найдено 2026-08-06 разбором упавшего прогона) ──
    #
    # Обе инъекции ниже — ДОСЛОВНЫЕ формы дерева, а не выдуманные. Гейт был
    # зелёным при обеих, потому что обе его красные корзины пусты by construction:
    # находка успевала уйти в освобождение раньше, чем читалось обещание кейса.

    # (9) КРАСНОЕ: шаг, чьё УДАЛЕНИЕ И ЕСТЬ ПРЕДМЕТ кейса, освобождался как
    #     уборка по одному лишь глаголу в имени (`del-`). Живая форма —
    #     services/vpc/tests/newman/cases/security-group.py, кейс
    #     SG-DEL-STATE-DEFAULT-SG: заголовок обещает отказ, утверждение
    #     принимает и успех, и НИ ОДНО утверждение кейса отказ не проверяет.
    src = (
        'Case(id="X-DEL-STATE-DEFAULT", title="Delete default-SG напрямую → должен fail '
        '(нельзя delete default SG в обход)",\n'
        '     steps=[Step(name="del-default-sg", test="pm.test(\'200 (op started) or 400/409 sync\', '
        '() => pm.expect(pm.response.code).to.be.oneOf([200, 400, 409]));"),\n'
        '            Step(name="check-result", test="pm.test(\'completed\', '
        '() => pm.expect(j.done).to.eql(true));")])\n'
    )
    f, _, u = scan(src)
    b = bucketize(f)
    check("удаление, которое и есть предмет кейса, не освобождается словом «del-»",
          len(b["REJECT"]) == 1,
          f'REJECT {len(b["REJECT"])}, TEARDOWN {len(b["TEARDOWN"])}, NONE {len(b["NONE"])}')

    # (10) МОЛЧАНИЕ на законном близнеце ТОЙ ЖЕ формы: тот же глагол в имени шага,
    #      но предмет кейса — ДРУГАЯ операция, а удаление здесь уборка за собой.
    #      Живая форма — `IPL-ACB-*` / `SUB-ACB-*`: добавление блоков, за которым
    #      идёт снос пула. Ни одного слова о РОЛИ в этом кейсе нет намеренно —
    #      иначе инъекция проверяла бы ярус 1 и молчала бы о разделителе.
    #      (Прежняя редакция брала для этого `IPL-RMCIDR-NEG-INUSE`. После того
    #      как `RMCIDR` вошёл в словарь предмета-удаления, тот кейс держится
    #      ярусом РОЛИ — его `pm.test` называется `del pool`, — и о разделителе
    #      уже ничего не утверждает.)
    src = (
        'Case(id="X-ACB-NEG-OVERLAP", title="AddCidrBlocks: пересекающийся блок → '
        '400 FailedPrecondition",\n'
        '     steps=[Step(name="add-cidr", test="pm.test(\'refused\', '
        '() => pm.expect(pm.response.code).to.be.oneOf([400]));"),\n'
        '            Step(name="del-pool", test="pm.test(\'снос пула\', '
        '() => pm.expect(pm.response.code).to.be.oneOf([200, 404]));")])\n'
    )
    f, _, u = scan(src)
    b = bucketize(f)
    check("тот же глагол, но предмет кейса другой — уборка остаётся освобождённой",
          not b["REJECT"] and not b["SUCCESS"],
          f'REJECT {len(b["REJECT"])}, SUCCESS {len(b["SUCCESS"])}')

    # (11) МОЛЧАНИЕ: кейс обещает отказ, утверждение шага принимает обе полосы —
    #      но отказ ПРИБИТ другим утверждением того же кейса (ошибка операции).
    #      Это законная двухполосная форма (`assert_refused_sync_or_async` +
    #      поллер `must_fail`), живая в SG-DEL-NEG-NIC-ATTACHED и
    #      IAM-ROL-DL-NEG-SYSTEM. Гейт, краснеющий на ней, был бы снят первым же
    #      ложным срабатыванием.
    src = (
        'Case(id="X-DEL-NEG-ATTACHED", title="Delete SG, прилинкованного к NIC → '
        'FailedPrecondition",\n'
        '     steps=[Step(name="del-sg-attached", test="pm.test(\'sync 200 (op started) or 400\', '
        '() => pm.expect(pm.response.code).to.be.oneOf([200, 400]));"),\n'
        '            Step(name="assert-blocked", test="pm.test(\'must fail\', () => '
        '{ pm.expect(j.error, JSON.stringify(j)).to.be.an(\'object\'); });")])\n'
    )
    f, _, u = scan(src)
    b = bucketize(f)
    check("двухполосный отказ, прибитый ошибкой операции — не находка",
          not b["REJECT"] and not b["SUCCESS"],
          f'REJECT {len(b["REJECT"])}, SUCCESS {len(b["SUCCESS"])}')

    # ── НАЛИЧИЕ ОШИБКИ ≠ ЕЁ ОТСУТСТВИЕ (найдено приёмкой 2026-08-06) ─────────
    #
    # Инъекция (11) выше — законный близнец: отказ прибит утверждением, что ошибка
    # ЕСТЬ. Пары к ней не было, и без пары отрицание зеленеет на всём сломанном:
    # прежняя редакция прибивала отказ ЛЮБЫМ упоминанием слова `error`, включая
    # утверждения, что ошибки НЕТ. Ниже — формы, каждая живая в дереве, и у
    # каждой свой близнец. Все они обязаны КРАСНЕТЬ: ни одна отказа не доказывает.
    #
    # Перепись (единица — вхождение прежней альтернативы в исполняемой части;
    # объём — 92 файла, 164 вхождения; ревизия d24476c1; классификатор нынешний):
    # 84 утверждают ОТСУТСТВИЕ ошибки — больше половины. То есть альтернатива,
    # заведённая как признак прибитого ОТКАЗА, чаще указывала на УСПЕХ.

    def bucket_of(src_):
        return bucketize(scan(src_)[0])

    def mixed_reject_case(cid, pin_step, pin_body):
        return (
            f'Case(id="{cid}", title="Delete SG, прилинкованного к NIC → '
            'FailedPrecondition",\n'
            '     steps=[Step(name="del-sg-attached", test="pm.test(\'sync 200 or 400\', '
            '() => pm.expect(pm.response.code).to.be.oneOf([200, 400]));"),\n'
            f'            Step(name="{pin_step}", test="pm.test(\'chk\', () => '
            f'{{ {pin_body}; }});")])\n')

    # (12) КРАСНОЕ: единственное утверждение об ошибке проверяет, что её НЕТ.
    #      Живая форма — `pm.expect(j.error, JSON.stringify(j)).to.not.exist`
    #      (29 вхождений) и `.to.be.undefined` (9).
    b = bucket_of(mixed_reject_case(
        "X-DEL-NEG-ABSENT", "check-result",
        "pm.expect(j.error, JSON.stringify(j)).to.not.exist"))
    check("утверждение, что ошибки НЕТ, отказ не прибивает",
          len(b["REJECT"]) == 1, f'REJECT {len(b["REJECT"])}, BOTH {len(b["BOTH"])}')

    # (13) КРАСНОЕ: `done && !error → true` — тоже утверждение УСПЕХА (23 вхождения).
    b = bucket_of(mixed_reject_case(
        "X-DEL-NEG-DONE", "poll", "pm.expect(j.done && !j.error).to.eql(true)"))
    check("«операция завершилась БЕЗ ошибки» отказ не прибивает",
          len(b["REJECT"]) == 1, f'REJECT {len(b["REJECT"])}, BOTH {len(b["BOTH"])}')

    # (14) КРАСНОЕ: слово `error` стоит во ВТОРОМ аргументе `pm.expect` — это
    #      диагностическое сообщение chai, а утверждается совсем другая величина.
    #      Тело взято с живой формы `iam-read-authz-vget.py:205` (та же форма —
    #      `rbac-subject-channel-equivalence.py:170`): предмет — литерал-массив,
    #      слово `error` живёт только в сообщении.
    #
    #      МАТЧЕР ЗДЕСЬ ОБЯЗАН БЫТЬ ПОЛОЖИТЕЛЬНЫМ, и это не вкусовщина: прежнее
