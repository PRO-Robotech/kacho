#   • ОТРИЦАТЕЛЬНЫЙ МАТЧЕР В ГОЛОВЕ. `.to.not.eql(1)` над `(j.error||{}).code || 0`
#     при отсутствии ошибки ПРОХОДИТ (0 ≠ 1) — отказа не доказывает. Отрицание
#     ВНУТРИ положительного утверждения (`.to.be.a('string').and.not.eql('')`)
#     под это не подпадает: предмет там разыменовывается и без ошибки падает;
#   • ДИЗЪЮНКЦИЯ НЕ ПРО ОШИБКУ. `pm.expect(j.response || j.error).to.exist` при
