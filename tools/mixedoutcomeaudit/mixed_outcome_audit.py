RE_ERR_BOOLEAN = re.compile(r"(?:Boolean\(\s*|!!\s*)[A-Za-z_$][\w.$]*\.error\b")
# `pm.expect(` ВНУТРИ строковой константы, которая просто НАЗЫВАЕТ форму, а не
# вызывает её: `_ASSERT_FORMS = ("pm.test(", "pm.expect(", "pm.response.to.")` —
# восемь таких строк в дереве (по одной в каждом `scripts/gen.py`, d24476c1).
# Признак однозначен: сразу за скобкой стоит кавычка, ЗАКРЫВАЮЩАЯ питоновский
