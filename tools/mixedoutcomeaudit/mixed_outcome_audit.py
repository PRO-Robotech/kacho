    #      половины сырой поиск объявил бы её живой (вхождение-то есть), и
    #      послабление охраняло бы чужой предмет — ровно замечание #1180.
    #      Замер, ради которого проверка заведена: у `\b500\b` в дереве 10
    #      вхождений и НИ ОДНОГО неотрицаемого, поэтому кода 500 в словаре нет.
    stale5 = set(stale_vocabulary({"cleanup-net"}, {t_not503}))
    check("запись 5xx, у которой все вхождения отрицаемы, названа мёртвой",
          r"\b503\b" in stale5, f"мёртвых {sorted(stale5)[:8]}")

    # (57) МОЛЧАНИЕ, близнец к (56): та же запись при НЕотрицаемом вхождении
    #      мёртвой не объявляется.
    stale5 = set(stale_vocabulary({"cleanup-net"}, {t_503}))
