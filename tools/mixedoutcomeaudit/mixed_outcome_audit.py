# ОТСУТСТВИЕ, ЗАПИСАННОЕ НЕ СЛОВОМ «НЕТ» (дополнено 2026-08-06 по второй половине
# той же находки приёмки). Первое разведение закрыло три формы и пропустило три:
#   • ПЕРЕЧИСЛЕНИЕ. `pm.expect(j.error).to.be.oneOf([undefined, null])` — это
