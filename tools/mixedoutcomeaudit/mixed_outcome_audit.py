# --- прибитие обещания --------------------------------------------------------
#
# Смешанный список кодов сам по себе НЕ является дефектом: у отказа в Kachō две
# законные полосы (синхронный валидатор `400` либо `200` и Operation, которая
# завершается С ОШИБКОЙ), и кейс, называющий вход незаконным, обязан принимать обе.
# Дефект — когда обещание метки не прибито НИЧЕМ: ни этим утверждением, ни одним
# из следующих шагов того же кейса. Тогда кейс зеленеет на исходе, ради запрета
# которого написан.
#
# Окно поиска — от имени ЭТОГО шага до конца кейса, то есть шаг и всё, что за ним.
# Окно выбрано намеренно щедрым: гейт, краснеющий на законной двухполосной форме,
# был бы снят при первом же ложном срабатывании. Узкую половину класса — «полоса
# отказа объявлена законной, а следующий шаг уезжает на пустой идентификатор
# операции» — держит отдельная мерка `deploy/scripts/assert-refusal-lane-has-a-reader.py`,
# и держит структурно, без словаря.
RE_PIN_REJECT_MARK = re.compile(
    r"assert_refused_sync_or_async\(|must_fail\s*=\s*True|assert_grpc_code\(\s*[1-9]"
    r"|assert_absent_id_rejected\(|assert_unscoped_rejected\(|assert_transcode_error\("
    r"|assert_field_violation\("
    r"|to\.not\.include\(|to\.not\.contain\(|\.to\.be\.empty\b"
)
RE_PIN_SUCCESS_MARK = re.compile(r"assert_status\(\s*2\d\d|assert_op_success\(")

# --- утверждение об ОШИБКЕ: НАЛИЧИЕ и ОТСУТСТВИЕ — противоположные обещания ----
#
# ЗДЕСЬ ЛОВИМЫЙ КЛАСС БЫЛ ПОВТОРЁН УРОВНЕМ ВЫШЕ (найдено приёмкой 2026-08-06,
# закрыто в ДВА захода — второй тоже нашла приёмка, и это часть урока).
# До первой правки прибитие отказа включало альтернативу
# `pm\.expect\([^;]{0,200}?\berror\b` — ЛЮБОЕ утверждение, в котором встретилось
# слово `error`. Под неё попадали живые формы дерева, каждая из которых
# утверждает НЕ ТО, что засчитывалось:
#
#   `pm.expect(j.error, JSON.stringify(j)).to.not.exist`   — «ошибки НЕТ»;
#   `pm.expect(j.done && !j.error).to.eql(true)`           — «ошибки НЕТ»;
#   `pm.expect(code, '…' + JSON.stringify(j.error)).to…`   — слово в ДИАГНОСТИКЕ,
#                                                            утверждается `code`;
#   `pm.expect(j.error).to.be.oneOf([undefined, null])`    — «ошибки НЕТ» МНОЖЕСТВОМ;
#   `pm.expect(!!j.error).to.eql(false)`                   — «ошибки НЕТ» БУЛЕВЫМ;
#   `pm.expect((j.error||{}).code || 0).to.not.eql(1)`     — проходит БЕЗ ошибки;
#   `pm.expect(j.response || j.error).to.exist`            — предмет НЕ ошибка.
#
# То есть кейс, обещающий отказ, считался прибитым утверждением, доказывающим
# ПРОТИВОПОЛОЖНОЕ, — уходил из красной корзины в `BOTH` и молчал.
#
# ПОЧЕМУ ПЕРВЫЙ ЗАХОД ЗАКРЫЛ ТОЛЬКО ПОЛОВИНУ: он перечислял НАПИСАНИЯ отсутствия
# («не существует», «→ true при отрицании»), а не свойство. Написаний оказалось
# больше, чем пришло в голову. Свойство одно и проверяемо: **утверждение прибивает
# отказ, только если ОНО НЕ МОЖЕТ ПРОЙТИ при отсутствующей ошибке.** Перечисление
# с `undefined`, приведение к `false`, отрицание в голове матчера и дизъюнкция не
# про ошибку — все ПРОХОДЯТ, поэтому ни одно отказа не доказывает.
#
# Перепись (единица — вхождение прежней альтернативы в исполняемой части
# исходников кейсов; объём — 92 файла, 164 вхождения; ревизия d24476c1;
# классификатор — нынешний, иначе числа несопоставимы): **73 утверждают наличие
# ошибки, 84 — её отсутствие, 7 не утверждают об ошибке ничего**. Прежний
# классификатор на том же корпусе давал 81 / 78 / 5 — то есть восемь мест звал
# наличием ошибки, доказывая ровно обратное.
#
# Поэтому слово `error` больше не решает ничего само по себе. Предмет и матчер
