// Package injectionproofgate — разбор: доказательство способности упасть,
// НАЗВАННОЕ пробой, обязано существовать (#2519).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Проба, чья шапка говорит «способность упасть доказана инъекцией — такой-то
// файл», делает утверждение о ДЕРЕВЕ. Утверждение это не компилируется и никем
// не сверяется: файл переименовали, унесли вместе с рефакторингом либо не
// написали вовсе — а шапка продолжает обещать доказательство. Гейт, потерявший
// способность краснеть, на чистом дереве выглядит РОВНО ТАК ЖЕ, как исправный,
// поэтому обещание доказательства читается как само доказательство.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ВТОРАЯ РЕАЛИЗАЦИЯ ОДНОГО РАЗБОРА — И ПОЧЕМУ ИНАЧЕ НЕЛЬЗЯ
//
// Такой же разбор живёт у службы доступа (`services/iam/internal/check`,
// `AuditNamedInjections`, задача #2479). Он обходит корень СВОЕГО модуля и о
// платформе не высказывается — и это решение, а не пробел: служба уезжает
// отдельным продуктом, в её самостоятельном клоне монорепо нет вовсе, и обход
// его корня был бы обходом дерева, которого не существует.
//
// Свести обе реализации в одну сегодня НЕЛЬЗЯ, и причина названа числом: модуль
// службы пинит платформу ПСЕВДОВЕРСИЕЙ, поэтому импортировать пакет, которого в
// пинованной ревизии ещё нет, он не может. Сведение требует бампа пина — это
// предмет другой полосы, и до него две реализации об одном предмете живут рядом
// осознанно. Предикат сведения: пин службы указывает на ревизию, где этот пакет
// существует.
//
// ─────────────────────────────────────────────────────────────────────────────
// СУДЯТСЯ КОММЕНТАРИИ, И ЭТО РЕШЕНИЕ, А НЕ УПРОЩЕНИЕ
//
// Координата доказательства пишется ПРОЗОЙ — это её законное место, и разбор
// читает разобранные группы комментариев, а не сырой текст файла. Строковые
// литералы намеренно НЕ судятся: в них живут синтетические имена, которые
// инъекции кладут во временные каталоги, и дерева они не называют вовсе. Судить
// их значило бы краснеть на чужой фикстуре — то есть на собственном
// доказательстве. Величина «в литералах» всё равно печатается переписью:
// молчание о целом виде вхождений неотличимо от их отсутствия.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАКОННЫХ ФОРМ КООРДИНАТЫ ЧЕТЫРЕ, И РАСПОЗНАВАТЕЛЬ ЗНАЕТ ВСЕ ЧЕТЫРЕ
//
// Форма, о которой он не знает, даёт не красное и не зелёное, а МОЛЧАНИЕ:
//
//	СОСЕД           `<имя>_injection_test.go` — файл в каталоге называющего;
//	ПО ДЕРЕВУ       то же имя, но доказательство лежит в ДРУГОМ каталоге;
//	ОТ КОРНЯ ОБХОДА `internal/<пакет>/<имя>_injection_test.go`;
//	ОТ КОРНЯ МОДУЛЯ тот же путь, но считанный от go.mod, ОБЪЕМЛЮЩЕГО называющего.
//	                В самостоятельном клоне службы приставки `services/iam/` нет,
//	                поэтому её пробы называют координату от своего модуля — и от
//	                корня монорепо она НЕ резолвится. Обе записи законны и живут в
//	                дереве, поэтому формы объединены СОЮЗОМ, а не выбором
//	                ближайшего корня (довод — у самого резолва).
//
// Четвёртая форма и есть цена подъёма разбора до корня монорепо: без неё каждая
// такая координата стала бы ЛОЖНОЙ находкой, а гейт с ложными находками
// отключают первым.
//
// Имя в примерах — ОБРАЗЕЦ с угловыми скобками, а не координата: координата,
// названная в прозе, есть утверждение о дереве, и выдуманная — ложное.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЯЗЫК ДОКАЗАТЕЛЬСТВА — ВТОРАЯ ОСЬ ФОРМЫ, И ДО #2519 РАЗБОР ЕЁ НЕ ВИДЕЛ ВОВСЕ
//
// Четыре формы выше — про ПУТЬ. Ось, о которой разбор молчал, — про ЯЗЫК файла:
// доказательство, названное Go-пробой, бывает и оболочкой (`<тема>-inject.sh`,
// `<тема>_inject.sh`), и пробой на Python (`<тема>_injection_test.py`). Обещание
// такой формы не давало ни красного, ни зелёного: оно не совпадало с образцом и
// потому уходило из наблюдения ЦЕЛИКОМ — ни в находках, ни в переписи.
//
// Замер дня заведения (числа стареют молча — живые печатает перепись держателя):
// обещаний прежней формы 542, все резолвятся; обещаний ДРУГОГО ЯЗЫКА в
// комментариях Go — 6, и о них не было сказано ничего. Полоса прежней формы
// расширением не тронута — значит прибавка была слепой зоной, а не регрессией
// дерева. Одно из шести не резолвилось: координата была записана от каталога
// называющего, а не от корня, и посылала искать доказательство туда, где его нет.
//
// Словарь форм оболочки объявляет `deploy/scripts/run-injection-proofs.sh` —
// обходчик, который эти доказательства ИСПОЛНЯЕТ. Здесь он повторён, потому что
// разбор на Go не может импортировать оболочку, и это названо вслух: заведут там
// третью форму — обещание, названное ею, снова выпадет из наблюдения, а признак
// расхождения виден числом `InOtherLanguages`, которое перестанет расти.
//
// Судится КООРДИНАТА, а не образец: `*-inject.sh` и `<тема>-inject.sh` в прозе
// дерева не называют, поэтому распознаватель требует перед разделителем букву
// или цифру. Без этого он краснел бы на файлах, которые форму ОБЪЯСНЯЮТ.
package injectionproofgate

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path"
	"regexp"
	"sort"
	"strings"
)

// coordinate — имя файла-доказательства.
//
// Собирается СКЛЕЙКОЙ намеренно: записанный одним литералом образец нашёл бы сам
// себя в этом же файле, и разбор судил бы собственное объяснение.
var coordinate = regexp.MustCompile(
	`[A-Za-z0-9_./-]*[a-z0-9_]` + `_injection` + `(?:_internal)?` + `_test` + `\.go`)

// foreignCoordinate — то же имя, но доказательство написано НЕ на Go.
//
// Перед разделителем обязана стоять буква или цифра: без этого требования
// образец `*-inject.sh`, которым форму объясняют в прозе, стал бы координатой, и
// разбор краснел бы на собственном объяснении.
var foreignCoordinate = regexp.MustCompile(
	`[A-Za-z0-9_./-]*[a-z0-9]` + `[-_]inject` + `\.sh` +
		`|` + `[A-Za-z0-9_./-]*[a-z0-9_]` + `_injection` + `_test` + `\.py`)

// IsProofFile — файл сам является доказательством инъекцией: его имя резолвит
// координату формы «ПО ДЕРЕВУ». Экспортируется, чтобы состав корпуса собирал
// ТОТ ЖЕ предикат, которым разбор потом судит, — иначе обещание резолвилось бы
// или не резолвилось в зависимости от того, попал ли файл в корпус.
func IsProofFile(p string) bool {
	base := path.Base(p)
	return strings.HasSuffix(base, "_test.go") ||
		foreignCoordinate.FindString(base) == base
}

// Census — объём осмотренного. Печатается ВСЕГДА: «ноль находок» обязано быть
// отличимо от «ноль прочитанного».
type Census struct {
	// GoFiles — исходников разобрано.
	GoFiles int
	// ModuleRoots — объявлений модуля в корпусе: по ним считается четвёртая форма.
	ModuleRoots int
	// NamingFiles / InComments — файлов, называющих доказательство, и самих
	// упоминаний В КОММЕНТАРИЯХ (судимая полоса).
	NamingFiles int
	InComments  int
	// InStrings — упоминаний в строковых литералах (полоса НЕ судимая; названа,
	// чтобы её отсутствие в вердикте не приняли за отсутствие вхождений).
	InStrings int
	// InOtherLanguages — из СУДИМЫХ упоминаний те, чьё доказательство написано не
	// на Go (оболочка, Python). Названо отдельным числом намеренно: по нему видно,
	// исполняется ли эта ось вообще, — а ноль здесь означал бы, что словарь форм
	// разошёлся со словарём обходчика, который эти доказательства запускает.
	InOtherLanguages int
	// Resolved — из судимых упоминаний нашли свой файл.
	Resolved int
}

// Finding — упоминание, у которого нет предмета.
type Finding struct {
	NamedBy    string // координата называющего, от корня обхода
	Coordinate string // что названо
}

// Audit разбирает ПРОИЗВОЛЬНЫЙ корпус (путь → содержимое): настоящее дерево и
// синтетический мир инъекции проходят одну функцию, поэтому доказанное на втором
// верно для первого.
//
// Ключи корпуса — пути со слешами от корня обхода. Ключ с базовым именем
// `go.mod` объявляет корень модуля; его содержимое не читается.
func Audit(corpus map[string][]byte) ([]Finding, Census, error) {
	var census Census
	if len(corpus) == 0 {
		return nil, census, fmt.Errorf(
			"на вход подано ноль файлов — обход дерева не состоялся, и молчание " +
				"разбора ничего не утверждает")
	}

	paths := make([]string, 0, len(corpus))
	for p := range corpus {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	// Указатель имён всех проб корпуса: форма «по дереву» резолвится по нему.
	byBase := map[string]bool{}
	// Корни модулей: по ним резолвится форма «от корня модуля».
	moduleRoots := map[string]bool{}
	for _, p := range paths {
		base := path.Base(p)
		if base == "go.mod" {
			moduleRoots[path.Dir(p)] = true
			continue
		}
		if IsProofFile(p) {
			byBase[base] = true
		}
	}
	census.ModuleRoots = len(moduleRoots)

	exists := func(p string) bool { _, ok := corpus[p]; return ok }

	var findings []Finding
	for _, p := range paths {
		if !strings.HasSuffix(p, ".go") {
			continue
		}
		fset := token.NewFileSet()
		file, perr := parser.ParseFile(fset, p, corpus[p], parser.ParseComments)
		if perr != nil {
			// Неразбираемый исходник — не находка ЭТОГО разбора и не тишина:
			// о нём высказывается компилятор, а перепись недосчитает его вслух.
			continue
		}
		census.GoFiles++

		named := false
		for _, group := range file.Comments {
			text := group.Text()
			for _, coord := range coordinate.FindAllString(text, -1) {
				census.InComments++
				named = true
				if resolves(coord, path.Dir(p), byBase, moduleRoots, exists) {
					census.Resolved++
					continue
				}
				findings = append(findings, Finding{NamedBy: p, Coordinate: coord})
			}
			// Вторая ось формы — язык доказательства. Резолв у неё ТОТ ЖЕ: путь
			// не зависит от того, на чём написан файл.
			for _, coord := range foreignCoordinate.FindAllString(text, -1) {
				census.InComments++
				census.InOtherLanguages++
				named = true
				if resolves(coord, path.Dir(p), byBase, moduleRoots, exists) {
					census.Resolved++
					continue
				}
				findings = append(findings, Finding{NamedBy: p, Coordinate: coord})
			}
		}
		if named {
			census.NamingFiles++
		}

		ast.Inspect(file, func(n ast.Node) bool {
			lit, ok := n.(*ast.BasicLit)
			if ok && lit.Kind == token.STRING {
				census.InStrings += len(coordinate.FindAllString(lit.Value, -1))
				census.InStrings += len(foreignCoordinate.FindAllString(lit.Value, -1))
			}
			return true
		})
	}

	sort.Slice(findings, func(i, j int) bool {
		if findings[i].NamedBy != findings[j].NamedBy {
			return findings[i].NamedBy < findings[j].NamedBy
		}
		return findings[i].Coordinate < findings[j].Coordinate
	})
	return findings, census, nil
}

// resolves — резолв по всем четырём законным формам.
func resolves(
	coord, dir string,
	byBase map[string]bool,
	moduleRoots map[string]bool,
	exists func(string) bool,
) bool {
	if !strings.Contains(coord, "/") {
		// СОСЕД.
		if exists(path.Join(dir, coord)) {
			return true
		}
		// ПО ДЕРЕВУ.
		return byBase[path.Base(coord)]
	}
	// ОТ КОРНЯ МОДУЛЯ и ОТ КОРНЯ ОБХОДА — одна попытка на каждый ОБЪЕМЛЮЩИЙ
	// корень модуля, от ближайшего к дальнему. Корень обхода — самый дальний из
	// них, поэтому третья и четвёртая формы здесь не две ветви, а одна.
	//
	// ЭТО СОЮЗ, А НЕ ВЫБОР БЛИЖАЙШЕГО, и это решение. Проба внутри модуля службы
	// вправе назвать координату И от своего модуля (в самостоятельном клоне
	// приставки монорепо нет), И от корня монорепо — обе записи законны, обе
	// живут в дереве. Требовать ближайший корень значило бы объявить вторую
	// запись находкой: гейт с ложными находками отключают первым, а масштаб
	// послабления здесь узкий — совпасть должен ВЕСЬ относительный путь, а не
	// только имя файла.
	roots := enclosingModules(dir, moduleRoots)
	if len(roots) == 0 {
		// Корней модуля в корпусе нет вовсе — тогда координата считается от
		// корня обхода, иначе форма не исполнялась бы ни разу.
		return exists(coord)
	}
	for _, root := range roots {
		if exists(path.Join(root, coord)) {
			return true
		}
	}
	return false
}

// enclosingModules — корни модулей, объемлющие каталог, от ближайшего к дальнему.
func enclosingModules(dir string, moduleRoots map[string]bool) []string {
	var out []string
	for d := dir; ; d = path.Dir(d) {
		if moduleRoots[d] {
			out = append(out, d)
		}
		if d == "." || d == "/" || d == "" {
			break
		}
	}
	return out
}
