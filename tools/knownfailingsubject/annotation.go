// # Пометка `# verifies <тикет>` на кейсе — третья половина гейта
//
// Первая половина читает объявления «известного красного» в `docs/RESULTS.md`, вторая —
// маркер живого объявления, стоящий вне надзорного раздела. Ни одна из них НЕ читает
// пометку `# verifies <ссылка-на-тикет>` в самом файле кейсов, хотя эта пометка —
// объявление того же рода: по ban #13 она означает «кейс ожидаемо КРАСНЫЙ, пока дефект
// открыт», то есть выкупает кейс из «всё обязано быть зелёным».
//
// Померено на дереве перед заведением этой половины (предикат — в отчёте задачи): в
// файлах кейсов стояли ЧЕТЫРЕ таких пометки, и ВСЕ ЧЕТЫРЕ ссылались на закрытые тикеты
// (`kacho#105`, `kacho#8` дважды, `kacho#71`). Три из них стояли над кейсами, которые
// давно переписаны под ИСПРАВЛЕННЫЙ контракт и обязаны быть зелёными, а четвёртая
// называла тикет БЕЗ репозитория (`#71`) — такую ссылку нельзя разрешить, поэтому срока
// жизни у неё не было даже в принципе. Сверка «пометка ↔ состояние тикета» существовала
// ровно в ОДНОМ сервисе из семи (`services/storage/tools/auditknownfailing`), и там она
// требует вдобавок парной записи в `docs/RESULTS.md` — контракт строже, и приняла его
// одна сюита.
//
// # Что проверяется здесь
//
//  1. ССЫЛКА РАЗРЕШИМА. Пометка называет тикет ВМЕСТЕ с репозиторием (`kacho#8`,
//     `kacho-vpc#27`, URL тикета). Голый `#71` — находка: его нельзя разрешить ни
//     человеком, ни машиной, значит истечь такая пометка не может.
//  2. ПОМЕТКА ПРИВЯЗАНА К КЕЙСУ. У пометки находится идентификатор кейса — того, над
//     которым она стоит, либо того, внутри чьего конструктора она написана. Пометка без
//     кейса не выкупает ничего и не проверяется ничем.
//  3. КЕЙС СУЩЕСТВУЕТ В НАБОРЕ. Названный кейс генерируется коллекциями своей сюиты.
//  4. КЕЙС ВСЁ ЕЩЁ КРАСНЫЙ (сторона ДЕФЕКТА, сети не требует). Там, где под `out/`
//     лежит отчёт прогона, кейс, который ИСПОЛНИЛСЯ и не дал ни одного упавшего
//     утверждения, — находка: пометка пережила свой предмет. Кейс, который не
//     исполнялся, зачётом НЕ считается — он объявляется непроверенным.
//  5. ТИКЕТ ВСЁ ЕЩЁ ОТКРЫТ (сторона ТРЕКЕРА). Закрытый тикет — находка с координатой
//     `файл:строка`.
//
// Измерения (4) и (5) НЕ дублируют друг друга и расходятся в обе стороны: тикет — это
// заметка О дефекте, а не дефект. На этом дереве уже наблюдались оба расхождения —
// пометка, пережившая фикс при ОТКРЫТОМ тикете (`kacho-vpc#27`, разбор оставлен в
// `services/vpc/tests/newman/cases/security-group.py`), и тикет, закрытый раньше, чем
// кейс перестал быть красным.
//
// # Почему НЕ снимок состояний тикетов в дереве
//
// Соблазн понятен: снимок «тикет → состояние + дата» убрал бы сеть с каждого прогона.
// Он отвергнут, и вот на каком основании.
//
//   - Снимок — ВТОРОЕ место, утверждающее состояние тикета. Просрочился снимок — гейт
//     зелёный и лжёт, то есть ровно тот класс, который эта половина и ловит, только
//     этажом выше и тише: пометка просрочена, снимок говорит «открыт», проверка
//     довольна.
//   - У снимка потребовался бы СВОЙ срок годности, а проверить его можно только… у
//     трекера. Сеть не исчезает, а переезжает на один уровень вверх вместе с
//     обязанностью не соврать.
//   - Жёсткий предел возраста снимка дал бы красноту ПО КАЛЕНДАРЮ — красноту, не
//     относящуюся к изменению, которое проверяют. Такую продлевают правкой даты, и
//     послабление воссоздаёт дефект, от которого спасало.
//   - Цена сети здесь измеряется РАЗЛИЧНЫМИ тикетами, а не пометками: номера
//     складываются в ту же карту, что и ссылки из `docs/RESULTS.md`, и разрешается
//     каждый ОДИН раз на прогон. Отдельного обращения эта половина не добавляет вовсе,
//     пока тикет уже назван документом отчёта.
//   - Хрупкость закрыта не снимком, а третьей категорией исхода: недоступный трекер даёт
//     НЕПРОВЕРЕНО с координатой и попадает в перепись, а не «прошло». Плюс измерение (4)
//     — сторона дефекта — сети не требует вообще и на этом дереве поймало бы три пометки
//     из четырёх без единого сетевого вызова.
//
// # Премиса гейта, названная так, чтобы её можно было опровергнуть
//
// Пометка — КОММЕНТАРИЙ, который начинается словом `verifies`. Проза, ЦИТИРУЮЩАЯ пометку
// («здесь стояла пометка `# verifies …`»), отсекается не словарём вердиктов, а
// ПОЛОЖЕНИЕМ: цитата стоит в обратных кавычках посреди строки, а пометка — с начала
// своего комментария. Поэтому строка разбирается сканером, который отличает комментарий
// от строкового литерала (одиночные и тройные кавычки) и от разметки цитаты (обратные
// кавычки), — не регулярным выражением по сырому тексту. Разбор УЖЕ СНЯТОЙ пометки
// остаётся законным и не требует ни слова оправдания: он молчит по построению.
//
// Пометка на пункт требований (`# verifies GEO-1-21`, `# verifies REQ-TGR-CR-01`) и
// пометка-проза (`# verifies: a non-member gets 200 + empty`) тикета не называют и
// объявлением «известного красного» не являются — они здесь не судятся, а СЧИТАЮТСЯ
// отдельно, чтобы слепая зона была видна числом. Признак ссылки на тикет —
// `#<цифры>` либо `/issues/<цифры>`; на дереве таких из 226 пометок было четыре.
//
// Пометка `# closes <тикет>` — ДРУГОЙ маркер и здесь не судится: она не выкупает кейс из
// зелёного, а называет артефакт, закрывающий тикет, и от закрытия тикета становится
// подтверждённой, а не ложной.
//
// # Что эта половина НЕ видит, названное прямо
//
// Читаются `cases/*.py` каждой сюиты — там, где у пометки есть автор. Сгенерированные
// коллекции и каталог `out/` не читаются как авторский текст (там produced-артефакт), а
// пометка в документе требований или в скрипте прогонщика ловится второй половиной
// (`unsupervised.go`) по своему словарю маркеров, не по этому. Пометка, написанная в
// строковом литерале, здесь невидима намеренно: литерал — данные, а не объявление.
//
// # Перепись
//
// Названо: файлов кейсов прочитано, пометок найдено, из них со ссылкой на тикет. «Ни
// одной пометки» и «не прочитано ни одного файла» обязаны печататься по-разному.

var (
	// verifiesPayloadRe — форма пометки: комментарий, НАЧИНАЮЩИЙСЯ словом `verifies`.
	// Двоеточие после слова допускается (`# verifies: …`) — такая пометка всё равно
	// отсеется ниже, если не называет тикет.
	verifiesPayloadRe = regexp.MustCompile(`^#\s*verifies\b`)
	// issueAttemptRe — признак ссылки на ТИКЕТ (в отличие от пункта требований и прозы).
	issueAttemptRe = regexp.MustCompile(`#\d+|/issues/\d+`)
	// bareIssueRe — номер тикета БЕЗ репозитория. Считается только тогда, когда
	// разрешимой ссылки в той же пометке нет: `kacho#8` содержит и `#8`.
	bareIssueRe = regexp.MustCompile(`#(\d+)|/issues/(\d+)`)
	// caseIDDeclRe — объявление идентификатора кейса в его конструкторе.
	caseIDDeclRe = regexp.MustCompile(`\bid\s*=\s*"([A-Z][A-Z0-9]*(?:-[A-Z0-9]+){2,})"`)
	// appendRe — начало кейса: граница, за которую поиск идентификатора не уходит.
	appendRe = regexp.MustCompile(`CASES\.append\s*\(`)
)

// caseAnnotation — одна пометка `# verifies …` в файле кейсов.
type caseAnnotation struct {
	file string // путь от корня дерева, через прямые слэши
	line int    // 1-based
	// issues — ссылки, называющие репозиторий: их и проверяет трекер.
	issues []issueRef
	// bare — номера, названные без репозитория: разрешить нельзя, срока нет.
	bare []int
	// caseID — кейс, к которому пометка привязана; пусто, если не нашёлся.
	caseID string
}

// commentStarts возвращает для каждой строки индекс `#`, начинающего КОММЕНТАРИЙ, либо
// -1. Тройные кавычки отслеживаются через строки, одиночные — внутри строки, обратные —
// как разметка цитаты. Без этого разбора гейт считал бы пометкой и цитату в прозе, и
// строковый литерал: первое сделало бы находкой законный разбор снятой пометки, второе —
// данные фикстуры.
func commentStarts(lines []string) []int {
	out := make([]int, len(lines))
	triple := "" // "" | `"""` | `'''`
	for i, ln := range lines {
		out[i] = -1
		j := 0
		for j < len(ln) {
			if triple != "" {
				if k := strings.Index(ln[j:], triple); k >= 0 {
					j += k + len(triple)
					triple = ""
					continue
				}
				// Тройная кавычка не закрыта в этой строке — остаток строки внутри
				// литерала, разбирать нечего. Присваивать j перед выходом не нужно:
				// после цикла оно не читается (на это и указал staticcheck SA4006).
				break
			}
			switch {
			case ln[j] == '\\':
				j += 2
			case strings.HasPrefix(ln[j:], `"""`):
				triple = `"""`
				j += 3
			case strings.HasPrefix(ln[j:], `'''`):
				triple = `'''`
				j += 3
			case ln[j] == '"' || ln[j] == '\'' || ln[j] == '`':
				q := ln[j]
				j++
				for j < len(ln) && ln[j] != q {
					if ln[j] == '\\' {
						j++
					}
					j++
				}
				j++ // закрывающая кавычка либо конец строки
			case ln[j] == '#':
				out[i] = j
				j = len(ln)
			default:
				j++
			}
		}
	}
	return out
}

// closeRe — строка, закрывающая конструктор кейса на верхнем уровне (`))`).
var closeRe = regexp.MustCompile(`^\)\)`)

// caseIDNear находит идентификатор кейса, к которому относится пометка на строке i.
//
// В дереве пометка встречается в ТРЁХ размещениях, и все три обязаны привязываться верно:
// хвостом на самой строке `id="…"` (так пишет registry), внутри конструктора после `id=`
// (так было в storage) и в комментарии ПЕРЕД конструктором (так было в iam и nlb).
// Порядок поиска — от самого точного к самому общему:
//
//  1. своя строка;
//  2. назад, пока не встретится `id="…"`; поиск ОБРЫВАЕТСЯ на закрытии предыдущего
//     конструктора (`))`) и на `CASES.append(` — иначе комментарий, стоящий МЕЖДУ двумя
//     кейсами, привяжется к ПРЕДЫДУЩЕМУ, а не к следующему;
//  3. вперёд до первого `id="…"`.
//
// Шаг (2) без обрыва — не теоретический промах: на инъекции настоящей пометки в дерево
// он привязал её к соседнему кейсу, и находка назвала бы чужую координату. Гейт, который
// называет не тот предмет, чинят удалением.
func caseIDNear(lines []string, i int) string {
	if m := caseIDDeclRe.FindStringSubmatch(lines[i]); m != nil {
		return m[1]
	}
	for k := i - 1; k >= 0; k-- {
		if m := caseIDDeclRe.FindStringSubmatch(lines[k]); m != nil {
			return m[1]
		}
		if closeRe.MatchString(lines[k]) || appendRe.MatchString(lines[k]) {
			break
		}
	}
	for k := i + 1; k < len(lines); k++ {
		if m := caseIDDeclRe.FindStringSubmatch(lines[k]); m != nil {
			return m[1]
		}
	}
	return ""
}

// scanCaseAnnotations читает `cases/*.py` одной сюиты и возвращает пометки, число
// прочитанных файлов и число найденных пометок (включая те, что тикета не называют).
func scanCaseAnnotations(root, suiteRel string) (out []caseAnnotation, files, markers int) {
	dir := filepath.Join(root, suiteRel, "cases")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, 0, 0
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".py") {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)

	for _, name := range names {
		// #nosec G304 -- путь получен обходом каталога кейсов самой сюиты.
		raw, rerr := os.ReadFile(filepath.Join(dir, name))
		if rerr != nil {
			continue
		}
		files++
		lines := strings.Split(string(raw), "\n")
		starts := commentStarts(lines)
		rel := filepath.ToSlash(filepath.Join(suiteRel, "cases", name))
		for i, ln := range lines {
			if starts[i] < 0 {
				continue
			}
			payload := ln[starts[i]:]
			if !verifiesPayloadRe.MatchString(payload) {
				continue
			}
			markers++
			if !issueAttemptRe.MatchString(payload) {
				continue // пункт требований либо проза — не объявление о дефекте
			}
			a := caseAnnotation{file: rel, line: i + 1, caseID: caseIDNear(lines, i)}
			qualified := map[int]bool{}
			for _, m := range issueRe.FindAllStringSubmatch(payload, -1) {
				n, cerr := strconv.Atoi(m[2])
				if cerr != nil {
					continue
				}
				qualified[n] = true
				a.issues = append(a.issues, issueRef{repo: m[1], num: n})
			}
			for _, m := range bareIssueRe.FindAllStringSubmatch(payload, -1) {
				digits := m[1]
				if digits == "" {
					digits = m[2]
				}
				n, cerr := strconv.Atoi(digits)
				if cerr != nil || qualified[n] {
					continue
				}
				a.bare = append(a.bare, n)
			}
			out = append(out, a)
		}
	}
	return out, files, markers
}

// judgeCaseAnnotations выносит находки по пометкам одной сюиты и складывает названные
// тикеты в общую карту разрешения (сетевое обращение — одно на тикет за прогон).
func judgeCaseAnnotations(
	anns []caseAnnotation,
	idx suiteIndex,
	reports map[string]*runReport,
	suiteRel string,
	issues map[issueRef][]string,
) (findings, unverified []string, resolved int) {
	for _, a := range anns {
		at := fmt.Sprintf("%s:%d", a.file, a.line)

		for _, n := range a.bare {
			findings = append(findings, fmt.Sprintf(
				"%s: пометка `# verifies` называет тикет БЕЗ репозитория (#%d) — такую ссылку "+
					"нельзя разрешить, поэтому пометка не может истечь ни по трекеру, ни глазами. "+
					"Исходы: назвать репозиторий (`kacho#%d`, URL тикета) либо снять пометку, если "+
					"выкупать из зелёного больше нечего", at, n, n))
		}
		for _, ir := range a.issues {
			issues[ir] = append(issues[ir], at)
		}

		if a.caseID == "" {
			findings = append(findings, fmt.Sprintf(
				"%s: пометка `# verifies` не привязана ни к одному кейсу (рядом нет объявления "+
					"`id=\"…\"`) — она ничего не выкупает и ничем не проверяется", at))
			continue
		}

		refs, ok := idx.resolve(a.caseID)
		if !ok {
			findings = append(findings, fmt.Sprintf(
				"%s: пометка `# verifies` стоит на кейсе %q, которого коллекции сюиты %s не "+
					"содержат — либо коллекции устарели (перегенерировать), либо кейс переименован "+
					"и пометка пережила свой предмет",
				at, a.caseID, filepath.ToSlash(suiteRel)))
			continue
		}
		resolved++

		switch v, where := judge(reports, a.caseID, refs); v {
		case subjectPassed:
			findings = append(findings, fmt.Sprintf(
				"%s: пометка `# verifies` объявляет кейс %q ожидаемо КРАСНЫМ (ban #13), а он "+
					"ИСПОЛНИЛСЯ и не дал ни одного упавшего утверждения — %s. Пометка пережила свой "+
					"предмет: это ложное утверждение о продукте, и оно переживает фикс. Снять "+
					"пометку и описать вместо неё защищаемое свойство",
				at, a.caseID, where))
		case subjectNotRun:
			unverified = append(unverified, fmt.Sprintf(
				"%s: кейс %q не исполнялся в %s — «всё ещё красный» НЕ ДОКАЗАНО, а не доказано",
				at, a.caseID, where))
		case subjectNoReport:
			unverified = append(unverified, fmt.Sprintf(
				"%s: у кейса %q нет отчёта прогона под %s/out — «всё ещё красный» НЕ ДОКАЗАНО, "+
					"а не доказано", at, a.caseID, filepath.ToSlash(suiteRel)))
		}
	}
	return findings, unverified, resolved
}
