// # Незанадзорное объявление «известного красного»
//
// Гейт выше проверяет предмет и срок жизни объявлений, написанных ТАМ, ГДЕ ИМ
// ПОЛОЖЕНО: в объявляющем разделе `docs/RESULTS.md` своей сюиты. Эта половина
// отвечает на другой вопрос — а все ли объявления написаны там.
//
// Померено на дереве (rev b49f5794): гейт видел ОДНО объявление, тогда как маркер
// живого объявления стоял ещё в четырёх местах — в каталоге кейсов, в документе
// требований и дважды комментарием над самим кейсом, — плюс десяток строк,
// утверждавших, что кейс «в whitelist'е известных красных» прогонщика. Ни одно из
// этих мест гейт не читает, и потому ни одно не истекает.
//
// Чем это плохо ровно настолько, насколько плохо просроченное объявление вообще:
// проверенные на этой ревизии, четыре из них оказались ЛОЖНЫМИ утверждениями о
// продукте — названные ими дефекты закрыты (поле области у создания роли есть,
// правка привязки на публичном мультиплексоре есть, подпись утверждения клиента
// в оснастке есть, ссылочная проверка при удалении группы есть). А whitelist, на
// который ссылается вторая группа, из прогонщика УДАЛЁН целиком: его больше нет,
// и «кейс освобождён» стало утверждением ни о чём.
//
// # Что именно запрещено
//
// 1. Маркер живого объявления (`persistent-RED`, `known-RED`) вне объявляющего
//    раздела `docs/RESULTS.md`. Место объявления — решение владельца гейта,
//    записанное в его же шапке; объявление в другом файле не подчиняется ни
//    одному сроку.
// 2. Утверждение, что кейс ОСВОБОЖДЁН от зелёного вычитанием/списком, — само по
//    себе, где бы ни стояло: `testing.md` запрещает такой механизм («маска /
//    whitelist / список известных красных в прогонщике или гейте»). Значит
//    утверждение либо ложно (списка нет), либо описывает нарушение (список есть).
//    Оба исхода — находка.
//
// # Что НЕ запрещено, и почему это отдельная ветка
//
// Разбор УЖЕ СНЯТОГО механизма — половина ценности этих файлов: именно он не даёт
// вернуть маску «временно». Поэтому строка, рядом с которой стоит вердикт снятия
// (`removed`, `no longer`, `was`, `never`, `снято`, `удал`, `прежн`…), находкой не
// является. Окно — сама строка и две соседние сверху: в прозе вердикт стоит перед
// предметом, и на дереве он ровно так и стоял.
//
// Без этой ветки гейт краснел бы на законном и был бы снят при первой встрече —
// вместе со всем, что он ловит.

var (
	// liveMarkerRe — словарь маркера ЖИВОГО объявления.
	//
	// Маркер — ТЕРМИН, и написан он как термин: через дефис/подчёркивание либо
	// заглавными. Свободная проза «the persistent red this fixes» термином не
	// является и объявлением тоже — это разбор уже сделанной починки. Без этого
	// сужения мерка краснела на законном, а гейт, краснеющий на законном, снимают
	// при первом же ложном срабатывании — вместе со всем, что он ловит.
	liveMarkerRe = regexp.MustCompile(`(?i)persistent[-_]red|known[-_]red` +
		`|(?-i:PERSISTENT RED|KNOWN RED)`)
	// retiredVerdictRe — вердикт снятия: то, что делает упоминание РАЗБОРОМ, а не
	// объявлением. Обе стороны словаря — и «убрано», и «никогда не было».
	//
	// Словарь НАРОЧНО не содержит голых основ «удал»/«закрыт»: в этом продукте это
	// обычные доменные глаголы (ресурсы удаляются, тикеты закрываются), и на них
	// оправдание срабатывало по соседству со словом, к сроку жизни объявления
	// отношения не имеющим — строка каталога кейсов уезжала из находок из-за
	// «SG удаляется» в её же описании.
	retiredVerdictRe = regexp.MustCompile(`(?i)\bremoved\b|\bremove\b|\bdeleted\b|\bretired\b|` +
		`\bno longer\b|\bused to\b|\bwas\b|\bwere\b|\bstood\b|\bnever\b|\bprior\b|\bformer\b|` +
		`\bshrinks\b|\bhistoric\b|снят|снесен|снесён|бывш|прежн|больше не|упразд|истори|стоял`)
	// verdictWindow — насколько близко к маркеру обязан стоять вердикт снятия.
	//
	// Не «где-то в абзаце»: в таблице соседняя строка — ЧУЖАЯ запись, а в длинном
	// описании дальний конец строки говорит уже о другом. Разбор снятия называет
	// снятие ПРЯМО ПРИ маркере — так на дереве и написано во всех законных местах.
	verdictWindow = 60
	// h2Re — заголовок второго уровня: граница раздела в документе отчёта.
	h2Re = regexp.MustCompile(`(?m)^##\s`)
)

// scanDirs — где внутри сюиты объявление может оказаться. Сгенерированные
// коллекции и каталог отчётов исключены намеренно: там нет авторского текста,
// а есть produced-артефакт, и находка в нём указывала бы не на своего автора.
var scanDirs = []string{"docs", "cases", "scripts", "."}

// unsupervisedFiles — файлы сюиты, в которых объявление имело бы автора.
func unsupervisedFiles(base string) []string {
	var out []string
	for _, d := range scanDirs {
		entries, err := os.ReadDir(filepath.Join(base, d))
		if err != nil {
			continue
		}
		for _, e := range entries {
			if e.IsDir() {
				continue
			}
			switch strings.ToLower(filepath.Ext(e.Name())) {
			case ".md", ".py", ".sh":
				out = append(out, filepath.ToSlash(filepath.Join(d, e.Name())))
			}
		}
	}
	return out
}

// supervisedLines — номера строк документа отчёта, лежащих в объявляющем разделе.
//
// Читается ЗАГОЛОВОК, а не близость к записи: раздел, чей заголовок объявляет
// известные красные, — единственное место, где маркер поднадзорен.
func supervisedLines(doc string) map[int]bool {
	out := map[int]bool{}
	lines := strings.Split(doc, "\n")
	supervised := false
	for i, ln := range lines {
		if h2Re.MatchString(ln + "\n") {
			supervised = declaringRe.MatchString(ln)
		}
		if supervised {
			out[i+1] = true
		}
	}
	return out
}

// excused — стоит ли вердикт снятия ВПЛОТНУЮ к маркеру.
//
// Контекст — строка вместе с предыдущей: в прозе вердикт часто уезжает на конец
// предыдущей строки («…including the removed \n known-RED whitelist»), и это одно
// предложение, а не два.
func excused(lines []string, i int) bool {
	ctx := lines[i]
	off := 0
	if i > 0 {
		ctx = lines[i-1] + " " + lines[i]
		off = len(lines[i-1]) + 1
	}
	m := liveMarkerRe.FindStringIndex(lines[i])
	if m == nil {
		return false
	}
	lo, hi := off+m[0]-verdictWindow, off+m[1]+verdictWindow
	if lo < 0 {
		lo = 0
	}
	if hi > len(ctx) {
		hi = len(ctx)
	}
	return retiredVerdictRe.MatchString(ctx[lo:hi])
}

// findUnsupervised — находки и перепись (файлов прочитано, строк с маркером).
func findUnsupervised(root, suiteRel string) (findings []string, files, markers int) {
	base := filepath.Join(root, suiteRel)
	for _, rel := range unsupervisedFiles(base) {
		// #nosec G304 -- путь получен обходом каталога самой сюиты.
		raw, err := os.ReadFile(filepath.Join(base, rel))
		if err != nil {
			continue
		}
		files++
		body := string(raw)
		lines := strings.Split(body, "\n")
		var supervised map[int]bool
		if filepath.ToSlash(rel) == "docs/RESULTS.md" {
			supervised = supervisedLines(body)
		}
		for i, ln := range lines {
			if !liveMarkerRe.MatchString(ln) {
				continue
			}
			markers++
			if supervised[i+1] {
				continue
			}
			if excused(lines, i) {
				continue
			}
			findings = append(findings, fmt.Sprintf(
				"%s:%d: объявление «известного красного» стоит вне объявляющего раздела "+
					"docs/RESULTS.md своей сюиты, поэтому не подчиняется НИ ОДНОМУ сроку: "+
					"ни предмет, ни дефект, ни состояние тикета у него никем не проверяются. "+
					"Исходы: перенести объявление в объявляющий раздел (тогда его проверит эта "+
					"же мерка) либо удалить, если исключать больше нечего. Разбор УЖЕ СНЯТОГО "+
					"механизма запретом не является — назови снятие рядом.\n      %s",
				filepath.ToSlash(filepath.Join(suiteRel, rel)), i+1, strings.TrimSpace(ln)))
		}
	}
	return findings, files, markers
}
