// Package knownfailingsubject is the repository-wide gate for one rule: a
// declaration that a case is "known failing" must have a SUBJECT.
//
// # What a declaration is, and why it needs a mechanism
//
// A results doc may declare that a case is expected red because the product
// diverges from its contract. That is legitimate and required — testing.md forbids
// skipping such a case, so it stays red and stays visible, and the declaration is
// what tells a reader the red is understood rather than new.
//
// What is not legitimate is a declaration nobody checks. It is not documentation:
// it is an ASSERTION ABOUT THE PRODUCT, written in prose, that no mechanism can
// contradict. Two ways it goes wrong, both observed in this tree:
//
//   - it outlives its fix. The defect is repaired, the row keeps saying the product
//     is broken, and the next reader either plans work already done or discounts a
//     genuine red as "the known one". One such row lived a day past its fix here and
//     queued work that was not needed.
//   - it never had a subject. The named case was renamed or deleted, so the row
//     excuses a case that cannot fail, cannot pass and cannot be looked at. Three of
//     those were standing when this gate was written.
//
// A subtraction in the suite runner used to make these rows load-bearing. That
// mechanism was removed — it keyed on a NAME while claiming to select by REASON, so
// it could not tell its subject from a stranger at any width. Removing it left the
// rows with no mechanism at all, which is what this gate supplies.
//
// # What is checked
//
//  1. SUBJECT EXISTS. Every case id a declaration names must be generated by that
//     suite's collections. A section that declares known-failing and names no
//     checkable subject at all is itself a finding — otherwise the unreadable part of
//     these files is exactly where declarations would go to hide.
//
//  2. SUBJECT IS STILL RED. Where a run left a report under out/, a declared case
//     that EXECUTED and produced no failed assertion is a finding: the declaration
//     outlived its subject. A case that did not run is NOT a pass — it is announced
//     as unverified and never folded into the verdict.
//
//  3. THE RECORD CAN EXPIRE. Every declaration names at least one tracker issue WITH
//     its repository (`kacho#11`, `kacho-iam#276`, or an issue URL). A bare `#11` is
//     not accepted: it cannot be resolved, and prose in these files says things like
//     "ban #6" which are not issues at all. A closed issue is a finding.
//
//  4. THE EXPIRY IS TIED TO THE DEFECT, NOT TO THE TRACKER. Every declaration carries
//     `Снимается-когда:` / `Retired-when:` naming, in backticks, at least one coordinate
//     this gate can look at: a SUBJECT of that suite (a run of it going green retires the
//     row) or a PATH that exists in the tree. A clause naming only an issue is a finding,
//     and so is one whose coordinate has rotted.
//
//     This is not a duplicate of (3). An issue is a note ABOUT a defect, and the two move
//     independently — in BOTH directions. Measured here at ee0591b: eight declarations,
//     twenty subjects, zero run reports, so check (2) was universally unproven and (3) was
//     the only expiry standing. It could not have worked. `kacho#106` was filed on
//     2026-07-30 for a defect fixed on 2026-07-19, eleven days earlier — the issue existed
//     only to give the row something to expire by, which reverses the dependency: the row
//     was not waiting on the defect, the ticket was waiting on the row. A stale "this is
//     known" is worse than a stale "this is red": the second summons someone to fix it,
//     the first tells them not to bother.
//
// # The gate's own premise, stated so it can be falsified
//
// Names in these docs are written in backticks; that is what makes a record readable
// by anything other than a human. Of the backticked tokens:
//
//   - a CASE ID is UPPER-KEBAB with at least two dashes (`NLB-CR-CRUD-OK`,
//     `AUTHZ-NIC-LS-OWN-AAB`) and MUST resolve — one that resolves to nothing is the
//     finding in check (1);
//   - any other name-shaped token (at least one dash, none of `._<>(){}@#$ `) is a
//     subject only WHEN IT RESOLVES, against a step name or a whole collection name.
//     Prose wears the same shape (`read-your-writes`, `PRO-Robotech`), so flagging
//     unresolvable ones would teach contributors to write around the matcher.
//
// The hole that asymmetry could leave — a record naming only a step or collection
// that has since been renamed — is closed one level up: a declaring section that
// yields no declaration at all fails.
//
// Sections are H2 and deeper (an H1 is the document title), and a NEUTRAL subsection
// of a declaring section stays declaring, because that is where these files actually
// keep their lists.
//
// A table row, a bullet, a blockquote and a paragraph are all read the same way: a
// declaration must not escape by changing its markdown shape.
//
// Text saying the red is already resolved marks a RECORD rather than a declaration —
// as a heading for a whole section, or inside one row for that row alone. History is
// allowed, and required, to name cases that now pass. Every such skip is counted, so it
// cannot become a quiet way out.
//
// A heading is read case-insensitively ("Closed — was known failing"); one record must
// carry the word as a VERDICT, in capitals (**FIXED 2026-07-29**, RECONCILED, СНЯТО).
// The asymmetry is not cosmetic: read case-insensitively, a record quoting an error
// message that happens to contain "resolved" would exempt itself, and one on this tree
// did exactly that.
//
// # What this gate does NOT see, stated rather than implied
//
// It reads `docs/RESULTS.md` of each newman suite, and inside it only the sections whose
// heading declares known-failing cases; plus `cases/*.py` of each suite for the
// `# verifies <issue>` marker (annotation.go — same three questions, asked of the same kind
// of declaration written on the case itself). A red declared somewhere else — another
// document, or a section titled so that nothing marks it as a declaration — is invisible
// here. That
// is a real limit, not a rhetorical one, and it is written down for the same reason the
// premise above is: a gate whose blind spot is undocumented gets trusted for more than it
// checks. Closing it by matching every section that happens to name a case id was tried
// and rejected — these documents name cases everywhere, and a rule that fires on all of
// them teaches contributors to stop naming cases.
//
// # Census
//
// The gate states what it read: suites, docs, collections, reports, declarations,
// resolved subjects, skipped resolution records, and defect-side retirement conditions.
// Reading nothing is a finding — "zero findings" must never be reachable from "zero
// files". The retirement count is printed for the same reason: a rule every producer
// happens to be missing reads exactly like a rule everybody follows.
//
// # Relationship to the per-suite gate in services/storage
//
// services/storage/tools/auditknownfailing asks different questions about the same
// rows for one suite: roster parity with the generated collections, and a TWO-WAY
// binding between a RESULTS.md row and a `# verifies <issue-url>` annotation in cases/.
// That contract is stricter and only that suite adopted it. This gate asks the
// repository-wide question — does the declaration have a subject, and is the subject
// still red — of BOTH places where such a declaration is written: the results doc
// (here) and the case file (annotation.go). It does NOT require the two to be paired,
// because that pairing is the stricter per-suite contract, not the tree-wide one.
// Both gates check liveness; neither subsumes the other.
package knownfailingsubject

