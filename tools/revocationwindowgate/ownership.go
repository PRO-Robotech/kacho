// ownership.go — ДВЕ формы, которыми процесс держит окно отзыва, и ОДИН
// распознаватель на обе.
//
// # Почему это отдельный предмет, а не деталь ScanConstructors
//
// Держать окно можно двумя способами, и они не сводятся друг к другу:
//
//  1. процесс строит кеш вердиктов САМ — зовёт конструктор из
//     verdictCacheCtorNames (это ScanConstructors);
//  2. процесс отдаёт окно ДЕСКРИПТОРУ носителя — называет величину полем
//     DescriptorWindowField, а кеш строит носитель на все сервисы разом.
//
// Вторая форма — не экзотика и не будущее: сегодня ею и только ею держат окно
// БОЛЬШИНСТВО площадок дерева. Замер по `release/kaname` @ 369c7d491b, единица
// счёта — процесс (каталог под services/ плюс край):
//
//	форма 1 (вызов конструктора): 3 — api-gateway, iam, registry
//	форма 2 (поле дескриптора):   6 — compute, geo, nlb, registry, storage, vpc
//	только формой 2:              5 — compute, geo, nlb, storage, vpc
//
// # Что этот файл чинит
//
// Распознаватель формы 2 существовал, но жил в теле одной пробы, поэтому вторая
// проба о том же предмете несла СВОЙ обход, знающий только форму 1. Две
// переписи одного предмета в одном прогоне печатали 3 и 8, и меньшая
// принадлежала той, чьё имя обещает «каждый процесс с кешем вердиктов
// объявлен». Её предпосылка при этом выполнялась — три площадки она находила, —
// так что потерю пяти заметить было нечем: «не нашла» и «нечего искать» с этой
// стороны выглядят одинаково.
//
// Распознаватель здесь один, и обе переписи зовут его. Форма, о которой
// распознаватель не знает, не даёт ни красного, ни зелёного — она молчит; ровно
// поэтому набор форм назван множеством, каждая доказана инъекцией ОТДЕЛЬНО, а
// перепись печатает величину ПО КАЖДОЙ форме, а не их сумму.
//
// # Граница, названная, а не обещанная прочь
//
// Обе формы — словари: имён конструкторов и имени поля. Кеш, построенный под
// новым именем конструктора, и окно, отданное дескриптору под новым именем
// поля, здесь не видны. Это настоящая граница; закрывает её не расширение
// словаря, а вопрос, заданный БЕЗ словаря — форма имени ручки
// (KnobSizesAuthzWindow), у которой единица переписи ОКНО, а не процесс.
//
// # Граница модуля этому распознавателю НЕ мешает — и это надо знать
//
// Служба доступа вынесена собственным модулем и резолвит фундамент
// ОПУБЛИКОВАННОЙ версией (`services/iam/go.mod`: пин на
// github.com/PRO-Robotech/kacho, `replace` — ноль). Распознаватель это
// переживает by construction: он РАЗБИРАЕТ исходник как текст, а не импортирует
// его, поэтому площадка вынесенного модуля попадает в перепись наравне с
// остальными.
//
// Чего он тем самым НЕ доказывает: величина, которую вынесенный модуль возьмёт
// у фундамента, приезжает с ПИНА, а не из дерева. Поэтому площадка вынесенного
// модуля обязана нести СВОЮ ручку (запись Windows), а не умолчание платформы:
// умолчание такой площадки живёт в чужой ревизии и меняется не правкой политики,
// а бампом пина. Здесь этот довод только объяснён; требование держат
// TestEveryVerdictCacheProcessDeclaresItsOwnKnob по дереву и JudgeOwnKnobs —
// вердиктом, которому можно подать вход.
//
// Довод этот, среди прочего, и снял вторую редакцию правила: политика держала
// карту «площадок без своей ручки», объявлявшую законным ровно то состояние,
// которое для вынесенного модуля вредно по существу. Карта снята (#2298).

// DescriptorWindowField — имя поля, которым процесс объявляет окно отзыва
// ДЕСКРИПТОРУ носителя вместо того, чтобы строить кеш самому.
//
// Признаком взято имя поля: оно принадлежит закрытому набору осей дескриптора
// (`corelib/servicecontract`), поэтому совпасть случайно ему не с чем. Тип литерала
// намеренно НЕ проверяется — дескриптор собирают и как `Spec{…}`, и как
// `servicecontract.Spec{…}`, и возвратом функции, а пиннить квалификатор здесь
// значило бы повторить ошибку, уже записанную в ScanConstructors: ответ стал бы
// зависеть от того, где тип лежит, а не от того, что процесс объявляет.
const DescriptorWindowField = "CacheWindow"

// WindowOwnership — какими формами файл держит окно отзыва.
//
// Формы разведены, а не сложены в один флаг, потому что их надо считать
// ПОРОЗНЬ: перепись, печатающая сумму, не отличает «форма 1 исчезла» от «стало
// меньше площадок», а первое означает переименованный конструктор, то есть
// ослепшую половину распознавателя.
type WindowOwnership struct {
	// ByConstructor — процесс строит кеш вердиктов сам.
	ByConstructor bool
	// ByDescriptor — процесс отдаёт окно дескриптору носителя.
	ByDescriptor bool
}

// Any — держит ли файл окно хоть какой-нибудь формой.
func (o WindowOwnership) Any() bool { return o.ByConstructor || o.ByDescriptor }

// Merge — объединение форм по нескольким файлам одного процесса.
func (o WindowOwnership) Merge(other WindowOwnership) WindowOwnership {
	return WindowOwnership{
		ByConstructor: o.ByConstructor || other.ByConstructor,
		ByDescriptor:  o.ByDescriptor || other.ByDescriptor,
	}
}

// OwnershipFormNames — имена форм в порядке полей WindowOwnership, чтобы
// вызывающий мог назвать в переписи то, что он считал, а не «две величины».
func OwnershipFormNames() []string {
	return []string{"вызов конструктора", "окно отдано дескриптору"}
}

// ScanWindowOwnership разбирает один файл и сообщает, какими формами он держит
// окно отзыва.
//
// Разбор, а не поиск по образцу: имя поля дескриптора и имена конструкторов
// стоят в этом дереве и в прозе — в комментариях, объясняющих сам предмет, — а
// текстовый поиск не отличает объявление от рассказа о нём.
func ScanWindowOwnership(path, src string) (WindowOwnership, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
	if err != nil {
		return WindowOwnership{}, fmt.Errorf("parse %s: %w", path, err)
	}
	var out WindowOwnership
	ast.Inspect(f, func(n ast.Node) bool {
		switch node := n.(type) {
		case *ast.CallExpr:
			// Форма 1. Квалификатор намеренно не читается — см. ScanConstructors.
			switch fn := node.Fun.(type) {
			case *ast.SelectorExpr:
				out.ByConstructor = out.ByConstructor || verdictCacheCtorNames[fn.Sel.Name]
			case *ast.Ident:
				out.ByConstructor = out.ByConstructor || verdictCacheCtorNames[fn.Name]
			}
		case *ast.CompositeLit:
			// Форма 2. Литерал дескриптора, называющий окно полем.
			for _, elt := range node.Elts {
				kv, ok := elt.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				if key, kok := kv.Key.(*ast.Ident); kok && key.Name == DescriptorWindowField {
					out.ByDescriptor = true
				}
			}
		}
		return true
	})
	return out, nil
}
