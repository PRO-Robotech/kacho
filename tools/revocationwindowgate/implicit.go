package revocationwindowgate

// implicit.go — вторая полоса того же предмета: окно отзыва, полученное МОЛЧА.
//
// # Почему одной переписи кешей мало
//
// Остальной части этого пакета известен ровно один способ получить окно:
// сервис строит кеш вердиктов, и тогда его видно — по имени ручки либо по
// самому вызову конструктора кеша. На этом строилось обещание, записанное в
// package doc: «спросим, строит ли сервис кеш вердиктов, — словаря не нужно,
// и седьмой сервис поймается в день появления».
//
// Обещание было неверно, и неверно оно было ровно в ту сторону, которую хуже
// всего заметить. Конструктор интерсептора принимал кеш полем; поле не
// заполнено — конструктор заводил кеш САМ. Сервис, ни разу не назвавший кеш,
// получал полноценное окно отзыва, не оставив в своём исходнике ни одной
// строки, по которой перепись могла бы его найти. Гейт при этом не просто
// молчал: он читал этот файл, засчитывал его в «осмотрено» и объявлял чистым.
//
// Гейт, который не ловит, — слепая зона. Гейт, который не ловит и ОБЕЩАЕТ
// ловить, вреднее отсутствия гейта: на его обещание опираются, когда решают,
// что проверять не нужно.
//
// # Предикат
//
// Каждый литерал `InterceptorOptions` в осмотренном дереве обязан НАЗЫВАТЬ
// поле кеша. Предикат берёт литерал, а не аргумент вызова, потому что дерево
// пользуется обеими формами: vpc/compute/geo/storage/registry строят литерал
// прямо в вызове, nlb собирает его в переменную и передаёт её. Если бы предикат
// смотрел на аргумент `NewInterceptor`, форма nlb обходила бы его переносом
// литерала на строку выше.
//
// Значение поля предикат НЕ читает. «Назвал» — это и есть проверяемое свойство:
// названное поле видно в правке, видно в обзоре, и его значение уже накрыто
// остальной частью гейта (перепись + потолок). Неназванное не видно нигде.
//
// # Что этот предикат НЕ покрывает, и почему это честно
//
// Опции можно собрать и без литерала — объявить переменную и присвоить поля по
// одному. Такой формы в дереве нет (перепись литералов это утверждает числом:
// ноль литералов = нарушенная предпосылка, а не успех), но она возможна.
// Поэтому предикат здесь — не единственная защита и не выдаёт себя за неё:
// исчерпывающий отказ живёт в самом конструкторе, который на неназванный кеш
// отказывает В СТАРТЕ, какой бы формой опции ни собрали. Этот гейт нужен
// раньше и точнее — он называет файл и строку тогда, когда процесс ещё никто
// не поднимал.
//
// Разделение обязанностей записано здесь намеренно: обещание, которого проверка
// не держит, — это тот самый дефект, из-за которого файл появился.

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
)

// ImplicitSite — площадка, строящая интерсептор, не назвав кеш вердиктов.
type ImplicitSite struct {
	Service string
	File    string
	Line    int
}

// ImplicitReport — исход разбора одного файла вместе с объёмом осмотренного.
//
// LiteralsSeen отделяет «литералы прочитаны и все назвали кеш» от «литералов не
// встретилось». Без этого числа молчание гейта означает сразу и то и другое, а
// вызывающий обязан уметь отличить чистое дерево от переехавшего.
type ImplicitReport struct {
	LiteralsSeen int
	Sites        []ImplicitSite
}

// ScanImplicitSites разбирает один Go-файл и возвращает каждый литерал
// `InterceptorOptions`, в котором поле кеша не названо.
//
// Разбор, а не текстовый поиск: godoc конструктора в pkg/authz содержит РОВНО
// ту форму, которую ищет предикат, и перепись регулярным выражением на этом
// примере уже ошиблась — объявила комментарий площадкой. AST различает код и
// текст by construction.
//
// service вызывающий разрешает из пути сам; анализатор не угадывает его по
// имени пакета, которое в дереве не уникально (шесть пакетов `check`).
func ScanImplicitSites(service, path, src string) (ImplicitReport, error) {
	var rep ImplicitReport

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		return rep, fmt.Errorf("parse %s: %w", path, err)
	}

	ast.Inspect(f, func(n ast.Node) bool {
		lit, ok := n.(*ast.CompositeLit)
		if !ok || !isInterceptorOptions(lit.Type) {
			return true
		}
		rep.LiteralsSeen++
		if literalNamesField(lit, "Cache") {
			return true
		}
		rep.Sites = append(rep.Sites, ImplicitSite{
			Service: service,
			File:    path,
			Line:    fset.Position(lit.Pos()).Line,
		})
		return true
	})
	return rep, nil
}

// isInterceptorOptions распознаёт тип литерала в обеих формах, которыми
// пользуется дерево: `authz.InterceptorOptions` из сервиса и голый
// `InterceptorOptions` внутри самого пакета.
func isInterceptorOptions(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.SelectorExpr:
		pkg, ok := t.X.(*ast.Ident)
		return ok && pkg.Name == "authz" && t.Sel.Name == "InterceptorOptions"
	case *ast.Ident:
		return t.Name == "InterceptorOptions"
	}
	return false
}

// literalNamesField сообщает, названо ли поле в литерале. Именно НАЗВАНО:
// значение не читается — см. package doc этого файла.
func literalNamesField(lit *ast.CompositeLit, field string) bool {
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.Ident)
		if ok && key.Name == field {
			return true
		}
	}
	return false
}
