// ownknob.go — вердикт «у держателя окна есть СВОЯ ручка», отделённый от обхода.
//
// # Зачем отдельной функцией, а не веткой внутри пробы
//
// Утверждение это сегодня МОЛЧИТ: все восемь держателей дерева свою ручку имеют,
// и зелёный прогон о его способности падать не говорит ничего. Доказать её можно
// только инъекцией, а инъекция требует производителя входа — то есть функции,
// которой вход можно подать. Ветка внутри пробы, читающей дерево, такого входа
// не принимает: чтобы её пошевелить, пришлось бы завести в дереве настоящий
// дефект.
//
// Тексты находок живут здесь в единственном экземпляре, поэтому инъекция судит
// ровно то, что прочтёт человек: проверка, чья способность падать доказана на
// другом тексте, доказана не про эту находку.
//
// # Что здесь НЕ решается
//
// Форму владения (строит ли процесс кеш сам или отдаёт величину дескриптору)
// знает ScanWindowOwnership, и только он. Здесь вопрос уже другой и от формы не
// зависит: названа ли ручка, из которой процесс берёт величину.
package revocationwindowgate

import "sort"

// OwnKnobVerdict — вердикт о переписи держателей окна против переписи ручек.
//
// Стороны ДВЕ, и обе обязаны быть в вердикте: односторонняя проверка здесь
// переживает свой предмет молча. «Держатель без ручки» ловит новый процесс,
// взявший окно у платформы; «ручка без держателя» ловит запись, чей процесс
// переименован или лишился кеша, — иначе перепись остаётся зелёной, описывая
// дерево, которого нет.
type OwnKnobVerdict struct {
	// HoldersWithoutKnob — процессы, держащие окно и не назвавшие своей ручки.
	HoldersWithoutKnob []string
	// KnobsWithoutHolder — объявленные ручки, под которыми держателя нет.
	KnobsWithoutHolder []string
}

// Clean сообщает, что обе стороны сошлись.
func (v OwnKnobVerdict) Clean() bool {
	return len(v.HoldersWithoutKnob) == 0 && len(v.KnobsWithoutHolder) == 0
}

// JudgeOwnKnobs сверяет перепись держателей окна с переписью объявленных ручек.
//
// held — процессы, о которых обход установил, что они держат окно отзыва;
// withOwnKnob — процессы, у которых политика объявляет СВОЮ ручку.
//
// # Почему множество разрешённых строится ровно из ручек, и ни из чего больше
//
// Держатель, чьей ручки нет, отдаёт своё окно отзыва платформе: оператор не
// может сузить его на конкретной посадке, и в конфигурации процесса о нём нет
// ни строки. Это ровно то состояние, которое `pkg/servicecontract` отвергает
// отказом в старте и которое `pkg/authz`.RevocationPolicy больше не объявляет
// законным ни в какой форме.
//
// До 2026-09-08 политика объявляла его законным картой `Inherited` — и та же
// площадка одновременно была находкой здесь. Обе половины были синтаксически
// верны, состояние молчало (карта стояла пустой), а исполнимого входа у
// объявленной возможности не существовало НИ ОДНОГО. Карта снята; здесь она не
// появляется намеренно, и второму множеству разрешённых взяться неоткуда.
func JudgeOwnKnobs(held map[string]WindowOwnership, withOwnKnob map[string]bool) OwnKnobVerdict {
	var v OwnKnobVerdict
	for svc := range held {
		if !withOwnKnob[svc] {
			v.HoldersWithoutKnob = append(v.HoldersWithoutKnob, svc)
		}
	}
	for svc := range withOwnKnob {
		if _, holds := held[svc]; !holds {
			v.KnobsWithoutHolder = append(v.KnobsWithoutHolder, svc)
		}
	}
	sort.Strings(v.HoldersWithoutKnob)
	sort.Strings(v.KnobsWithoutHolder)
	return v
}

// HolderWithoutKnobFinding — текст находки «держатель без своей ручки».
//
// Находка обязана называть ФОРМУ владения: читатель, которому названы только
// имя процесса и требование ручки, пойдёт искать вызов конструктора там, где его
// может не быть вовсе — шесть площадок дерева из восьми не строят ничего.
func HolderWithoutKnobFinding(service, forms string) string {
	return "процесс держит кеш вердиктов, но своей ручки окна у него нет: «" + service +
		"» (" + forms + ").\n" +
		"Окно отзыва этого процесса принадлежит платформе: оператор не может сузить его " +
		"на конкретной посадке, и в конфигурации сервиса о нём нет ни строки. Заведи ручку " +
		"окна и запись в pkg/authz.RevocationPolicy.Windows.\n" +
		"Взять умолчание платформы вместо ручки НЕЛЬЗЯ: такой процесс не поднимается " +
		"(pkg/servicecontract: у окна отзыва умолчания быть не может), и записать его " +
		"исключением тоже некуда — ведомости исключений у этого правила нет."
}

// KnobWithoutHolderFinding — текст находки «ручка без держателя»: перепись
// пережила свой предмет.
func KnobWithoutHolderFinding(service string) string {
	return "запись Windows без процесса: «" + service + "» объявлен, но такого процесса, строящего кеш " +
		"вердиктов, в дереве нет. Кеш убран или процесс переименован — сними запись."
}
