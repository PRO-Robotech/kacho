# unread-field-audit-inject.sh — ДОКАЗАТЕЛЬСТВО СПОСОБНОСТИ УПАСТЬ для границы дерева
# (`unread_field_audit.py`, полоса «ВНЕ ДЕРЕВА»).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ПРОГОНЩИК. Признак границы объявляет о дереве факт, который
# нельзя проверить прочтением: «сервер этого домена здесь не поднимает никто,
# значит поля его запросов измерить НЕЛЬЗЯ». Ошибка в каждую сторону стоит своего,
# и ни одна не видна в диффе:
#
#   * извинить домен, чья служба ЗДЕСЬ, — МАСКА над дрейфом сопоставления
#     каталогов: поля домена уходят из наблюдения МОЛЧА, вердикт остаётся rc=0;
#   * не извинить домен, чья служба в другом продукте, — ВЕЧНОЕ КРАСНОЕ на верном
#     факте: прогон краснеет тем, что дерево в порядке.
#
# Прежняя редакция признака (по корню дерева контрактов) была МАСКОЙ первого вида,
# и самопроверка её не находила: фикстура несла корень с ДВУМЯ доменами, а корень,
# к которому признак применялся, домен несёт РОВНО ОДИН — там признак тождественно
# безусловен. Отсюда правила этого прогонщика:
#
#   * инъекция вносится в КОПИЮ ТОЧНОЙ ЗАМЕНОЙ СТРОКИ и обязана внестись — иначе
#     утверждение считается НЕ ДОКАЗАННЫМ, а не пройденным;
#   * инъекция в РАСПОЗНАВАТЕЛЬ доказывается самопроверкой; инъекция в ВЕРДИКТНОЕ
#     МЕСТО — прогоном ЦЕЛОГО предиката на фикстуре: самопроверка о провязке
#     вердикта не утверждает ничего и осталась бы зелёной;
#   * у каждой инъекции есть ЗАКОННЫЙ БЛИЗНЕЦ, который обязан молчать.
#
# Прогон: обходом доказательств (`make -C deploy injection-proofs`), который находит
# это доказательство ПО ФОРМЕ ИМЕНИ `<тема>-inject.sh`. Прежде файл звался
# `inject.sh`, формы не имел и потому не запускался НИКЕМ: доказательство
# существовало как текст — ровно то, ради борьбы с чем оно и пишется.
# Руками: bash tools/unreadfieldaudit/unread-field-audit-inject.sh
# Исход:  0 — все утверждения доказаны; 1 — хотя бы одно не доказано;
#         2 — предпосылка не выполнена (доказывать нечего или нечем).
set -uo pipefail

AUDIT="tools/unreadfieldaudit/unread_field_audit.py"
[ -f "$AUDIT" ] || { echo "ОТКАЗ: $AUDIT не найден — прогонять из корня дерева" >&2; exit 2; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
IDX="$WORK/idx.json"
FX="$WORK/fx"; mkdir -p "$FX"
: > "$WORK/injected"   # отметка внесённых инъекций; см. ниже, почему не переменная

asserted=0; failed=0
# Счётчик инъекций ведётся ФАЙЛОМ, а не переменной: `inject` зовётся в подстановке
# `$( )`, то есть в ПОДОБОЛОЧКЕ, и присваивание из неё не возвращается. Первая
# редакция считала переменной и напечатала «инъекций внесено: 0» при семи внесённых —
# доказательство объявило себя беспредметным, будучи предметным.
say() { printf '%s\n' "$*"; }
claim() { # claim <утверждение> <ожидаемое> <полученное>
  asserted=$((asserted + 1))
  if [ "$2" = "$3" ]; then say "  ОК           $1"
  else failed=$((failed + 1)); say "  НЕ ДОКАЗАНО  $1 (ожидалось $2, получено $3)"; fi
}
rc_of() { python3 "$1" --reader-index="$2" >"$WORK/o" 2>"$WORK/e"; printf '%s' "$?"; }
st_of() { python3 "$1" --self-test >/dev/null 2>&1; printf '%s' "$?"; }

say "строю индекс чтений (go run) …"
if ! go run ./tools/unreadfieldaudit/cmd/proto-field-readers >"$IDX" 2>"$WORK/idx.err"; then
  say "ПРЕДПОСЫЛКА НЕ ВЫПОЛНЕНА: индекс чтений не построен"; sed -n '1,20p' "$WORK/idx.err" >&2; exit 2
fi

# ── ДОМЕН ГРАНИЦЫ СПРАШИВАЕТСЯ У САМОГО ПРЕДИКАТА ────────────────────────────
# Не выписывается и не выводится своим обходом: перечень вынесенных служб,
# записанный здесь руками, был бы копией того, что уже лежит в дереве, и разошёлся
# бы молча. Спросить надо ровно то, что предикат объявляет границей, — иначе
# фикстура строится на домене, который в эту полосу не попадает ВООБЩЕ (первая
# редакция этого прогонщика выбрала домен без публичной поверхности, и «находки»
# не было by construction).
python3 "$AUDIT" --reader-index="$IDX" >"$WORK/live.out" 2>"$WORK/live.err"
DOMAIN="$(sed -n "s/.*ВНЕ ДЕРЕВА: домен '\([^']*\)'.*/\1/p" "$WORK/live.out" | head -1)"
[ -n "$DOMAIN" ] || { say "ПРЕДПОСЫЛКА НЕ ВЫПОЛНЕНА: предикат не объявил ни одной границы — доказывать нечего"; exit 2; }
STUB="$(python3 -c "import sys;sys.path.insert(0,'tools/unreadfieldaudit');import unread_field_audit as u;print(u.stub_pkg('$DOMAIN'))")"
say "домен границы (спрошен у предиката): $DOMAIN; пакет стабов: $STUB"

# ── ФИКСТУРЫ: КАЖДАЯ ОТЛИЧАЕТСЯ ОТ БЛИЗНЕЦА РОВНО ОДНИМ ФАКТОМ ───────────────
cat > "$FX/serve.go" <<GO
package main

import (
	domv1 "$STUB"
)

// Композиционный корень ВЕРНУВШЕЙСЯ службы: поднимает её сервер.
func serve(s *grpc.Server, impl domv1.AccountServiceServer) {
	domv1.RegisterAccountServiceServer(s, impl)
}
GO
cat > "$FX/handler.go" <<GO
package handler

import (
	domv1 "$STUB"
)

// Сигнатура обработчика БЕЗ регистрации: её объявляют и клиентские порты.
func (s *Server) Get(ctx context.Context, req *domv1.GetAccountRequest) error {
	return nil
}
GO

MOD="github.com/PRO-Robotech/kacho"
RET="services/$DOMAIN-returned"
mkfix() { # mkfix <имя> [<пакет>=<файл> …]
  local out="$WORK/idx-$1.json"; shift
  python3 - "$IDX" "$out" "$@" <<'PY'
import json, sys
idx = json.load(open(sys.argv[1]))
for spec in sys.argv[3:]:
    pkg, _, f = spec.partition("=")
    idx["packages"].append({"path": pkg, "files": [f]})
json.dump(idx, open(sys.argv[2], "w"))
PY
  printf '%s' "$out"
}
I_EXTERN="$(mkfix extern)"
I_REG="$(mkfix reg "$MOD/$RET/cmd/x=$FX/serve.go")"
# A2: каталог службы ПРОЧИТАН индексом, регистрации нет — так его увидел бы
# настоящий обход. Файл называется путём В ДЕРЕВЕ: премисса непрочитанного каталога
# обязана быть удовлетворена, чтобы одна премисса не маскировала другую.
I_A2="$(mkfix a2 "$MOD/$RET/internal/handler=$RET/internal/handler/handler.go")"

# ── ИНЪЕКЦИЯ — ТОЧНАЯ ЗАМЕНА СТРОКИ В КОПИИ, и она обязана внестись ──────────
inject() { # inject <было> <стало> → печатает путь копии либо пусто
  local dst; dst="$WORK/audit-$(wc -c <"$WORK/injected").py"
  if python3 - "$AUDIT" "$dst" "$1" "$2" <<'PY'
import sys
src = open(sys.argv[1], encoding="utf-8").read()
old, new = sys.argv[3], sys.argv[4]
if src.count(old) != 1:
    sys.exit(3)
open(sys.argv[2], "w", encoding="utf-8").write(src.replace(old, new, 1))
PY
  then printf 'x' >> "$WORK/injected"; printf '%s' "$dst"; fi
}
need() { # need <путь-копии> <имя инъекции>
  [ -n "$1" ] || { say "  НЕ ДОКАЗАНО  инъекция «$2» НЕ ВНЕСЛАСЬ — строка не найдена либо не одна"
                   asserted=$((asserted + 1)); failed=$((failed + 1)); return 1; }
}

say
say "── КОНТРОЛЬ: целый предикат на живом дереве ───────────────────────────────"
claim "законный внешний домен молчит (граница объявлена)" 0 "$(rc_of "$AUDIT" "$I_EXTERN")"
claim "вернувшаяся служба — НАХОДКА, а не граница"        2 "$(rc_of "$AUDIT" "$I_REG")"
# Отчёт предиката идёт в stdout, жёсткие премиссы — в stderr; отказ по ДОМЕНУ лежит
# в отчёте. Ищем в ОБЪЕДИНЁННОМ выводе: первая редакция читала только stderr и
# объявила «координата не названа» при названной координате.
python3 "$AUDIT" --reader-index="$I_REG" >"$WORK/both" 2>&1
grep -q "$RET/cmd/x" "$WORK/both" && got=1 || got=0
claim "находка называет КООРДИНАТУ регистрирующего пакета" 1 "$got"
claim "самопроверка целого предиката зелёная" 0 "$(st_of "$AUDIT")"

say
say "── ИНЪЕКЦИЯ 1 (вердиктное место): признак перестаёт читать наблюдаемое ────"
# Буквальное восстановление прежнего поведения: признак, тождественно безусловный
# для домена с одним корнем, эквивалентен «регистраций нет никогда».
M="$(inject '            reg = server_registrations(index, domain)' '            reg = {}')"
if need "$M" "обнуление вердиктного признака"; then
  claim "вернувшаяся служба снова ИЗВИНЯЕТСЯ — маска воспроизведена" 0 "$(rc_of "$M" "$I_REG")"
  claim "законный близнец при той же инъекции молчит"                0 "$(rc_of "$M" "$I_EXTERN")"
  claim "самопроверка при этом ЗЕЛЁНАЯ — она о провязке вердикта не судит" 0 "$(st_of "$M")"
fi

say
say "── ИНЪЕКЦИЯ 2 (распознаватель): слепота к импорту БЕЗ псевдонима ─────────"
M="$(inject '            name = stub_pkg_name(domain)' '            name = None')"
if need "$M" "слепота к безымянному импорту"; then
  claim "самопроверка краснеет" 1 "$(st_of "$M")"
  claim "живое дерево молчит — формы в нём сегодня нет" 0 "$(rc_of "$M" "$I_EXTERN")"
fi

say
say "── ИНЪЕКЦИЯ 3 (распознаватель): слепой импорт начинает квалифицировать ────"
M="$(inject '        if alias == "_":
            continue' '        if alias == "_":
            out.add("")
            continue')"
if need "$M" "слепой импорт квалифицирует"; then
  claim "самопроверка краснеет" 1 "$(st_of "$M")"
fi

say
say "── ИНЪЕКЦИЯ 4 (распознаватель): снята вторая законная форма регистрации ───"
M="$(inject 'r"RegisterService\s*\(\s*&?\s*" + q + r"(\w+)_ServiceDesc\b",' 'r"(?!x)x(\w+)",')"
if need "$M" "снятие формы дескриптора"; then
  claim "самопроверка краснеет" 1 "$(st_of "$M")"
fi

say
say "── ИНЪЕКЦИЯ 5 (распознаватель): атрибуция становится завышающей ───────────"
M="$(inject '                q = re.escape(local + ".") if local else r"(?<![\w.])"' '                q = r"\w+\."')"
if need "$M" "завышающая атрибуция"; then
  claim "самопроверка краснеет — чужой домен приписан" 1 "$(st_of "$M")"
fi

say
say "── ИНЪЕКЦИЯ 6 (вердиктное место): снята премисса незаявленного каталога ───"
M6="$(inject '    unclaimed = unclaimed_service_dirs(domains)' '    unclaimed = []')"
if need "$M6" "снятие премиссы незаявленного каталога"; then
  claim "самопроверка ЗЕЛЁНАЯ — премисса провязана в main, не в ней" 0 "$(st_of "$M6")"
  if [ -e "$RET" ]; then
    say "  ПРОПУЩЕНО: $RET уже существует — чужого не трогаем"
  else
    mkdir -p "$RET/internal/handler" && cp "$FX/handler.go" "$RET/internal/handler/"
    claim "каталог на диске, прочитанный и не заявленный, роняет ЦЕЛЫЙ предикат" \
          2 "$(rc_of "$AUDIT" "$I_A2")"
    claim "при снятой премиссе тот же каталог ИЗВИНЯЕТСЯ — маска воспроизведена" \
          0 "$(rc_of "$M6" "$I_A2")"
    rm -rf "$RET"
    claim "каталог снят — предикат снова молчит" 0 "$(rc_of "$AUDIT" "$I_EXTERN")"
  fi
fi

say
say "── ИНЪЕКЦИЯ 7 (вердиктное место): снята премисса непрочитанного каталога ──"
M7="$(inject '    unindexed = unindexed_service_dirs(index)' '    unindexed = []')"
if need "$M7" "снятие премиссы непрочитанного каталога"; then
  if [ -e "$RET" ]; then
    say "  ПРОПУЩЕНО: $RET уже существует — чужого не трогаем"
  else
    mkdir -p "$RET/internal/handler" && cp "$FX/handler.go" "$RET/internal/handler/"
    # Каталог на диске, индексом НЕ прочитанный: премисса обязана его назвать.
    claim "непрочитанный каталог роняет ЦЕЛЫЙ предикат" 2 "$(rc_of "$AUDIT" "$I_EXTERN")"
    # При снятой премиссе непрочитанного его подхватывает премисса незаявленного —
    # и это НЕ провал инъекции, а вторая линия защиты. Утверждаем её прямо.
    claim "при снятой премиссе его ловит вторая — незаявленного каталога" \
          2 "$(rc_of "$M7" "$I_EXTERN")"
    rm -rf "$RET"
    claim "каталог снят — предикат снова молчит" 0 "$(rc_of "$AUDIT" "$I_EXTERN")"
  fi
fi

say
say "── ИНЪЕКЦИЯ 8 (вердиктное место): снята премисса переписи Go-модулей ──────"
# ЧТО ДОКАЗЫВАЕТСЯ. `go list` в каталог со своим `go.mod` не спускается by
# construction, поэтому обход обязан идти ПО МОДУЛЯМ, а число обойдённых —
# сверяться с ДЕРЕВОМ. Сама сверка разобрана в `--self-test` по семи формам записи
# объявления; здесь доказывается ДРУГОЕ — что она провязана в вердикт main(), а не
# только объявлена. Инъекция обнуляет перепись объявлений, и предикат обязан
# ответить отказом «судить нечем», а не молчанием: пустая перепись даёт разность,
# равную пустому множеству, то есть при вычитании выглядит полным обходом.
#
# Тревожить дерево тут нечем и не нужно: вносится обнуление ПЕРЕПИСИ, а не
# `go.mod`. Прогон на дереве с внесённым `go.mod` сделан отдельно и записан в
# отчёте линии — в CI он стоил бы записи в рабочую копию посреди прогона.
M8="$(inject '    declared_mods = declared_module_dirs(walk_patterns)' '    declared_mods = set()')"
if need "$M8" "обнуление переписи объявлений модуля"; then
  claim "пустая перепись объявлений роняет ЦЕЛЫЙ предикат" 2 "$(rc_of "$M8" "$I_EXTERN")"
  claim "законный близнец без инъекции молчит"              0 "$(rc_of "$AUDIT" "$I_EXTERN")"
  # Самопроверка зовёт `declared_module_dirs` напрямую, а инъекция снята с ВЕРДИКТНОГО
  # места — значит она обязана остаться зелёной. Утверждается прямо: иначе «инъекция
  # внеслась» было бы неотличимо от «инъекция попала не туда, куда задумано».
  claim "самопроверка ЗЕЛЁНАЯ — она о провязке вердикта не судит" 0 "$(st_of "$M8")"
fi

say
injected=$(wc -c <"$WORK/injected")
say "утверждений проверено: $asserted; НЕ доказано: $failed; инъекций внесено: $injected"
say "фикстур прогнано: 3 (законный внешний · вернувшаяся служба · обработчик без регистрации)"
if [ "$asserted" -eq 0 ] || [ "$injected" -eq 0 ]; then
  say "ОТКАЗ: доказательство беспредметно — утверждений $asserted, инъекций $injected" >&2
  exit 2
fi
[ "$failed" -eq 0 ] || exit 1
exit 0
