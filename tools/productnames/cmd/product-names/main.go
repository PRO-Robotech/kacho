// Команда product-names — ОТВЕТ на вопрос «как называется образ (и чарт) этой
// части продукта», для тех, кто спрашивает не из Go.
//
// Использование:
//
//	product-names КАТАЛОГ [КАТАЛОГ…]     печатает «каталог<TAB>имя» построчно
//	product-names --parts                печатает каталоги частей ВЕДОМОСТИ, по одному в строке
//
// # Зачем режим перечисления
//
// Спрашивающему из оболочки нужен ПОЛНЫЙ перечень частей, чьё имя приставкой не
// выводится, — иначе обратный вопрос «наш ли это образ» отвечает ложью на части
// со своим именем продукта. Вывести перечень самому спрашивающий не может: до
// разреза монорепо ключи ведомости совпадали с каталогами под `services/`, и
// оболочка брала их оттуда. После выноса части в свой репозиторий совпадение
// кончилось — каталога нет, а имя, чарт и пин образа остались нашими, — и
// перечень из `services/*` терял ровно ту часть, ради которой ведомость и
// существует.
//
// Печатаются каталоги, а не имена: вызывающему нужен КЛЮЧ, которым он потом
// спросит имя тем же инструментом. Печатать здесь имя значило бы дать ему второй
// путь к тому же ответу.
//
// # Зачем отдельная команда, а не ведомость, которую разберёт оболочка
//
// Соответствие «каталог исходников ↔ имя чарта ↔ имя образа» — это ПРАВИЛО, а
// не таблица: у большинства частей имя выводится приставкой платформы, и лишь
// у части есть собственное имя продукта. Ведомость, разбираемая двумя
// сторонами, дала бы ДВЕ реализации одного правила — то есть ровно тот второй
// словарь, ради снятия которого всё и заведено; расходятся такие своды молча.
//
// Здесь реализация ОДНА: оболочка не толкует правило, она спрашивает его у
// `internal/productnaming` и переносит ответ. Второго толкователя нет — значит
// расходиться нечему.
//
// ГРАНИЦА НАЗВАНА ЧЕСТНО, а не заметена под «by construction»: ответ верен для
// ДЕРЕВА, из которого собран этот инструмент. Библиотека оболочки поэтому
// ключует путь сборки отпечатком корня — иначе две рабочие копии (обычный здесь
// режим) делили бы один двоичный файл, и чей `go build` отработал последним, чьё
// правило и отвечало бы всем. Разошлось бы это МОЛЧА и правдоподобным неверным
// именем. Проба согласия сторожит именно перенос, а не толкование.
//
// # Исходов три, и каждый свой код
//
//	0  имена напечатаны;
//	1  среди названного есть ПУСТОЕ имя — печатать для него нечего;
//	2  каталогов не названо ни одного — обход беспредметен, и это НЕ успех;
//	   либо ведомость пуста в режиме `--parts` — «ноль прочитанного» не есть «ноль частей».
//
// Пустой вывод при коде 0 невозможен by construction: код 2 отделяет «спросили
// и не получили» от «не спрашивали».
//
// # Что код 1 ловит НА САМОМ ДЕЛЕ — сказано точно, а не шире
//
// Правило выводит имя для любого непустого каталога, поэтому «не наша часть»
// оно ответить не может и проверять это здесь было бы формой без содержания.
// Единственный вход, на котором обратный резолв отвечает «не признано», —
// ПУСТАЯ строка: у неё нет тела после приставки. Класс реальный и стоит
// проверки: пустое раскрытие переменной у вызывающего дало бы `docker build -t
// :dev`, то есть образ, которого никто не просил.
//
// Существование каталога в дереве здесь НЕ проверяется — это ответственность
// вызывающего, которому известен корень (так это и оговорено в godoc
// `productnaming.ServiceDir`). У рецепта стенда несуществующий каталог всё
// равно роняет `docker build -f services/<он>/Dockerfile` следующей же строкой.
package main

import (
	"fmt"
	"os"
	"sort"

	"github.com/PRO-Robotech/kacho/internal/productnaming"
)

func main() {
	dirs := os.Args[1:]

	// Режим перечисления отсекается ДО общего пути: без него `--parts` уезжал
	// в правило как имя каталога и печатал выведенное из него имя образа —
	// то есть отвечал на вопрос, которого никто не задавал.
	if len(dirs) == 1 && dirs[0] == "--parts" {
		ledger := productnaming.RenamedServices()
		if len(ledger) == 0 {
			fmt.Fprintln(os.Stderr,
				"product-names: ведомость собственных имён пуста — перечислять нечего.\n"+
					"               Это НЕ «частей со своим именем нет»: пустой вывод при коде 0\n"+
					"               вызывающий прочитал бы как полный перечень.")
			os.Exit(2)
		}
		out := make([]string, 0, len(ledger))
		for dir := range ledger {
			out = append(out, dir)
		}
		// Порядок байтовый: вызывающий сличает перечень с другим перечнем, а
		// обход карты в Go порядка не даёт вовсе.
		sort.Strings(out)
		for _, dir := range out {
			fmt.Println(dir)
		}
		return
	}

	if len(dirs) == 0 {
		fmt.Fprintln(os.Stderr,
			"product-names: не названо ни одного каталога службы — печатать нечего.\n"+
				"               Перечень принадлежит вызывающему (у рецепта стенда это SERVICES);\n"+
				"               здесь живёт только правило, по которому каталог даёт имя.")
		os.Exit(2)
	}

	empty := 0
	for _, d := range dirs {
		name := productnaming.ChartName(d)
		// Обратный резолв отвечает «не признано» ровно на пустом имени —
		// см. разбор в шапке. Печатать для него нечего.
		if _, ok := productnaming.ServiceDir(name); !ok {
			empty++
			fmt.Fprintf(os.Stderr,
				"product-names: имя части пусто (аргумент %d) — печатать нечего.\n"+
					"               Похоже на пустое раскрытие переменной у вызывающего:\n"+
					"               с таким именем собрался бы образ `:dev`, которого никто не просил.\n",
				empty)
			continue
		}
		fmt.Printf("%s\t%s\n", d, name)
	}
	if empty > 0 {
		os.Exit(1)
	}
}
