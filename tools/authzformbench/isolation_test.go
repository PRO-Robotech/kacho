// Доказательство предпосылки, на которой этот пакет стоит в санкционированных
// поставщиках гейта `TestNoPackageStartsAContainerPerTest`: контейнер поднимается
// ОДИН на процесс, а изоляция между кейсами достигается собственным store внутри
// него.
//
// Гейт это допущение НЕ читает из кода — он ключуется на запись в своём списке, а
// запись обязана называть, где лежит доказательство. Без этого файла запись была бы
// утверждением о намерении: следующий контрибьютор, разбив `sync.Once` или начав
// поднимать сервер из тела кейса, не уронил бы ничего, а гейт продолжил бы молчать
// именно потому, что пакет объявлен исключением.
//
// Обе половины проверяются ВМЕСТЕ и по отдельности бессмысленны: «сервер один» без
// «области разные» означает, что кейсы видят чужие кортежи и меряют не то, что
// думают; «области разные» без «сервер один» означает контейнер на кейс, то есть
// ровно то, что гейт и запрещает.
package authzformbench

import (
	"context"
	"testing"

	"github.com/stretchr/testify/require"
)

// TestOneStackManyStores — санкция гейта на этот пакет, выраженная исходом.
func TestOneStackManyStores(t *testing.T) {
	if testing.Short() {
		t.Skip("поднимает контейнеры")
	}
	ctx := context.Background()
	stack, canon := bootForTest(ctx, t)

	model, err := TransformDSL(canon)
	require.NoError(t, err, "трансформ канона в JSON-модель")

	first, err := stack.NewStore(ctx, "isolation-first", model)
	require.NoError(t, err)
	second, err := stack.NewStore(ctx, "isolation-second", model)
	require.NoError(t, err)

	// Половина первая — СЕРВЕР ОДИН. Второй запрос стека обязан вернуть тот же
	// адрес: иначе `sync.Once` разорван и каждый кейс платит своим контейнером.
	again, _ := bootForTest(ctx, t)
	require.Same(t, stack, again,
		"второй запрос стека вернул ДРУГОЙ объект — контейнер поднимается не один раз, "+
			"и пакет перестал соответствовать тому, ради чего он внесён в санкционированные")

	// Половина вторая — ОБЛАСТИ РАЗНЫЕ. Одинаковый store означал бы, что кейсы
	// видят кортежи друг друга: замер тогда мерил бы сумму чужих записей, а
	// проба эквивалентности вердиктов сравнивала бы формы на общем состоянии.
	require.NotEqual(t, first.ID, second.ID,
		"два запроса вернули ОДИН store — изоляции между кейсами нет, и любое число, "+
			"снятое этим пакетом, относится к чужим данным вперемешку со своими")
}
