# drift.sh — «перенос ветки не откатил ствол».
#
# Предмет. Ветка, отставшая от ствола на сотни файлов, при переносе может
# ВЕРНУТЬ содержимое базы на файлах, которых она не касалась, — и это пройдёт
# без единого конфликта, потому что конфликт возникает только там, где ОБЕ
# стороны правили одно место. Молчание git о конфликте не есть утверждение о
# сохранности ствола.
#
# Предикат. Для каждого файла F, который ствол изменил со времени базы ветки:
# если ветка F НЕ касалась, то результат обязан совпадать со стволом ПОБАЙТОВО.
# Расхождение — откат, и гейт называет координату.
#
# Почему сравнение именно с деревом объектов, а не с рабочей копией: рабочая
# копия несёт незакоммиченное, и гейт, читающий её, отвечал бы про черновик.
#
# Предпосылка проверяется: если множество изменённых стволом файлов пусто, то
# сравнивать нечего, и это НЕ то же самое, что «откатов нет» — такой прогон
# объявляется беспредметным и падает. «Ноль находок» обязано быть отличимо от
# «ноль прочитанного».
#
# Ветка-источник задаётся СПИСКОМ через запятую, и это не удобство. Когда в один
# результат садятся несколько веток, файл, правленный СОСЕДНЕЙ веткой, для этой
# выглядит «стволом изменён, веткой не тронут» — то есть ровно как откат. Гейт,
# знающий одну ветку, на втором же переносе выдал бы пять ложных находок (и выдал:
# .github/workflows/ci.yaml, services/iam/Makefile и три файла анализатора iam).
# Ложная находка здесь дороже пропущенной: она учит снимать гейт. Поэтому
# исключаемое множество — ОБЪЕДИНЕНИЕ правок всех перенесённых веток, каждая со
# своей базой: у веток базы разные, и вычитать их по одной нельзя.
#
# Осознанное СНЯТИЕ и осознанное ПРИСПОСОБЛЕНИЕ отличаются от отката объявлением —
# и, для приспособления, ещё одним фактом: откат возвращает содержимое БАЗЫ, а
# приспособление отличается и от неё. Второй признак проверяется всегда, поэтому
# запись в перечне не может прикрыть возврат к базе. Ствол и ветка могут
# независимо завести один предмет разными файлами; тогда в результате остаётся один,
# и файл ствола снимается решением, а не переносом. По графу обе картины одинаковы,
# поэтому решение называется явно — `tools/carrydrift/declared-removals.txt`, по
# записи на файл, с причиной. Запись живёт ровно пока у неё есть предмет: снятие вне
# перечня — красное, запись без снятия — ТОЖЕ красное.
#
# Использование:
#   drift.sh <база> <ветка[,ветка...]> <ревизия-ствола> <ревизия-результата>

set -euo pipefail

if [ $# -ne 4 ]; then
  echo "usage: drift.sh <base> <source-branch[,branch...]> <trunk-rev> <landed-rev>" >&2
  exit 2
fi

BASE=$1
SRCS=$2
TRUNK=$3
LANDED=$4

IFS=',' read -r -a SRC_LIST <<< "$SRCS"

for rev in "$BASE" "$TRUNK" "$LANDED" "${SRC_LIST[@]}"; do
  git rev-parse --verify --quiet "$rev^{commit}" >/dev/null || {
    echo "drift: ревизия '$rev' не разрешается в коммит — гейт смотрит не туда" >&2
    exit 2
  }
done

# Файлы, изменённые стволом с базы, и файлы, которых касалась ЛЮБАЯ из веток.
# Каждая ветка сравнивается со СВОЕЙ точкой расхождения со стволом, а не с базой
# аргумента: иначе правки соседней ветки, сделанные от другой базы, не вычтутся.
mapfile -t TRUNK_TOUCHED < <(git diff --name-only "$BASE" "$TRUNK")
BRANCH_TOUCHED=()
for src in "${SRC_LIST[@]}"; do
  mb=$(git merge-base "$TRUNK" "$src")
  mapfile -t -O "${#BRANCH_TOUCHED[@]}" BRANCH_TOUCHED < <(git diff --name-only "$mb" "$src")
done

if [ "${#TRUNK_TOUCHED[@]}" -eq 0 ]; then
  # Заявление о пустой ОБЛАСТИ — машиночитаемое, тем же приёмом, что и
  # `declared-used:` ниже. Решение по нему принимает `judge.sh`: у беспредметности
  # и слепоты разная цена, а отличить их по одному коду возврата нельзя.
  echo "no-surface: ствол не изменил с базы ни одного файла"
  echo "drift: ствол не изменил с базы $BASE ни одного файла — сравнивать нечего," >&2
  echo "       и это не то же самое, что «откатов нет»; вердикт беспредметен" >&2
  exit 2
fi

declare -A BRANCH_SET=()
for f in "${BRANCH_TOUCHED[@]}"; do BRANCH_SET["$f"]=1; done

# Объявленные снятия. Перечень читается с ВЕРШИНЫ отправки (`HEAD` по умолчанию),
# а не из каждой судимой посадки, и это не мелочь: посадка уже совершена, и
# требовать объявления внутри неё значило бы требовать переписать историю ради
# того, чтобы её объяснить. Объявление описывает ОТПРАВКУ целиком, и каждая
# посадка в ней судится под ним.
#
# Читается из дерева объектов, а не из рабочей копии: рабочая копия несёт
# незакоммиченное, и гейт, читающий её, разрешал бы себе черновиком.
declare -A DECLARED=()
declare -A DECLARED_USED=()
DECLARED_FILE=tools/carrydrift/declared-removals.txt
DECLARED_REV=${DRIFT_DECLARED_REV:-HEAD}
if git rev-parse --quiet --verify "$DECLARED_REV:$DECLARED_FILE" >/dev/null 2>&1; then
  while IFS= read -r line; do
    case "$line" in ''|'#'*) continue ;; esac
    path=${line%%[[:space:]]*}
    [ -n "$path" ] && DECLARED["$path"]=1
  done < <(git show "$DECLARED_REV:$DECLARED_FILE")
fi

findings=0
examined=0
skipped=0
declared_hits=0
moves=0

for f in "${TRUNK_TOUCHED[@]}"; do
  if [ -n "${BRANCH_SET[$f]+x}" ]; then
    skipped=$((skipped + 1))
    continue
  fi
  examined=$((examined + 1))
  a=$(git rev-parse --quiet --verify "$TRUNK:$f" 2>/dev/null || echo MISSING)
  b=$(git rev-parse --quiet --verify "$LANDED:$f" 2>/dev/null || echo MISSING)
  if [ "$a" != "$b" ]; then
    # Объявление покрывает ДВА исхода, и каждый печатается своим словом: СНЯТИЕ
    # (результат не несёт файла) и ПРИСПОСОБЛЕНИЕ (файл на месте, содержимое
    # новое). Третий исход не покрывается НИКОГДА — возврат к содержимому БАЗЫ:
    # иначе строка перечня стала бы разрешением тихо отменять чужую работу.
    # Различитель — содержимое базы, он пятью строками ниже.
    #
    # Здесь стояло «пропуском засчитывается ТОЛЬКО снятие; файл на месте с другим
    # содержимым запись не прикрывает». Верно это было до 17399329d4 — того самого
    # изменения, которое завело ветку приспособления прямо под этим комментарием.
    # То есть комментарий отрицал код, стоявший ниже него, и отрицал ровно ту
    # ветку, ради которой перечень и нужен на накопительной линии (#1912).
    if [ -n "${DECLARED[$f]+x}" ]; then
      if [ "$b" = MISSING ]; then
        DECLARED_USED["$f"]=1
        declared_hits=$((declared_hits + 1))
        echo "снято решением: $f — объявлено в $DECLARED_FILE"
        continue
      fi
      # Файл на месте, но с ДРУГИМ содержимым. Это либо откат, либо осознанное
      # приспособление содержимого ствола к форме ветки, и различитель точный:
      # ОТКАТ возвращает содержимое БАЗЫ, приспособление отличается и от неё.
      # Поэтому объявление не покрывает возврат к базе никогда — иначе строка в
      # перечне стала бы разрешением тихо отменять чужую работу.
      base_blob=$(git rev-parse --quiet --verify "$BASE:$f" 2>/dev/null || echo MISSING)
      if [ "$b" != "$base_blob" ]; then
        DECLARED_USED["$f"]=1
        declared_hits=$((declared_hits + 1))
        echo "приспособлено решением: $f — объявлено в $DECLARED_FILE (содержимое новое, не возврат к базе)"
        continue
      fi
      echo "ОБЪЯВЛЕНО, НО ЭТО ВОЗВРАТ К БАЗЕ: $f — результат совпал с базой $BASE;"
      echo "       объявление приспособления не покрывает откат, и не должно"
    fi
    # ПЕРЕЕЗД, а не утрата. Файла по этому пути в результате нет, но его
    # содержимое лежит там под другим именем — значит перенос ничего не потерял.
    #
    # Форма встречается на каждом сведении двух живых линий: ствол и ветка
    # независимо заводят миграции с одним номером, и при сведении одна из них
    # перенумеровывается. Наблюдалось 2026-08-14 — 0087/0088 стали 0089/0090
    # побайтово тождественными, а гейт объявил обе откатом, потому что сверял
    # ПО ПУТИ. Ложная находка здесь дороже пропущенной: она учит снимать гейт.
    #
    # Послабление узкое by construction: оно требует ТОГО ЖЕ объекта в дереве
    # результата. Исчезнувшее содержимое под него не подпадает и краснеет —
    # это закреплено отдельным случаем пробы, стоящим рядом с этим.
    if [ "$b" = MISSING ] && [ "$a" != MISSING ]; then
      moved=$(git ls-tree -r "$LANDED" | awk -v blob="$a" '$3 == blob {print $4; exit}')
      if [ -n "$moved" ]; then
        moves=$((moves + 1))
        echo "переехало: $f → $moved — содержимое ствола в результате есть, путь другой"
        continue
      fi
    fi
    findings=$((findings + 1))
    echo "ОТКАТ: $f — ствол несёт $a, результат несёт $b;"
    echo "       ветка этого файла не касалась, значит расхождение внесено переносом"
  fi
done

# Самоистечение перечня судится ОТПРАВКОЙ, а не посадкой — и это не мелочь.
#
# Комментарий выше говорит прямо: «объявление описывает ОТПРАВКУ целиком, и
# каждая посадка в ней судится под ним». Проверка же делала обратное — считала
# запись пережившей предмет в КАЖДОЙ посадке, где это снятие не случилось. При
# непустом перечне краснела любая посадка, и вердикт переставал зависеть от
# того, что в ней произошло: наблюдалось 2026-08-14, четыре записи против девяти
# посадок гарантировали красное независимо от содержимого.
#
# Поэтому здесь только ФАКТ применения, машиночитаемо; решение принимает тот,
# кто видит отправку целиком (`judge.sh`), собрав объединение по всем посадкам.
for f in "${!DECLARED_USED[@]}"; do
  echo "declared-used: $f"
done

echo "drift: перепись — ствол изменил ${#TRUNK_TOUCHED[@]} файл(ов) с базы $BASE;"
echo "       ветки отличаются на $skipped из них (их судит не этот гейт);"
echo "       сверено побайтово $examined; находок $findings; переездов $moves;"
echo "       снятий по объявлению $declared_hits; записей перечня ${#DECLARED[@]}"

if [ "$examined" -eq 0 ]; then
  # ВТОРОЙ способ остаться без области — и он ничем не хуже первого. Ствол
  # двигался, но КАЖДЫЙ сдвинутый им файл правит и сама ветка, а такие файлы
  # гейт не судит по собственному правилу области (строка «их судит не этот
  # гейт» в переписи выше). Значит откатывать в его области было нечего
  # by construction — ровно как когда ствол не двигался вовсе.
  #
  # Это НЕ слепота. Слепота — когда посмотреть не удалось; здесь смотреть было
  # не на что, и разница между ними стоит красного вердикта на каждом, кто
  # догонит такой ствол.
  #
  # Довод, проверяемый глазом: при `skipped=3` из 417 гейт молчит и всегда
  # молчал. Краснеть на `skipped=1` из 1 и молчать на `skipped=3` из 417 —
  # несогласуемо: дыра области одна и та же, различается только её доля.
  echo "no-surface: вся правка ствола лежит на файлах, которые правит ветка"
  echo "drift: ни один файл не сверён — ветка касается всего, что менял ствол;" >&2
  echo "       у гейта не осталось файлов в области, и судить было нечего" >&2
  exit 2
fi

# Код возврата этого скрипта — утверждение об ОДНОЙ посадке: 0 сверено чисто,
# 1 есть находки, 2 сверять было нечем. Состояние перечня сюда не примешивается:
# оно относится к отправке, и смешение делало вердикт посадки непрочитываемым.
[ "$findings" -eq 0 ] || exit 1
