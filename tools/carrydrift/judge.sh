# judge.sh — судья посадок отправки: находит в диапазоне слияния, определяет у
# каждого сторону ствола и зовёт `drift.sh`, который и сверяет содержимое.
#
# Здесь стояло «чистый перенос тела шага конвейера — без единой правки
# поведения; правки идут следующим коммитом». Это было верно ровно один раз —
# в день переноса, — и с тех пор поведение правилось трижды. Утверждение
# пережило свой предмет и продолжало обещать читателю, что перед ним копия
# конвейерного шага.
#
# Что остаётся нормой: тело живёт в СКРИПТЕ, а не в объявлении конвейера,
# поэтому его можно прогнать локально тем же вызовом, а его собственная проба
# (`drift-test.sh`) судит судью на синтетических графах — шагом конвейера, а не
# на словах.
#
# Исходов у судьи ШЕСТЬ, и они не сливаются: 0 сверено чисто · 1 находки ·
# 2 посадка, которую не удалось сверить · 3 запись перечня без предмета ·
# 4 опорных линий нет вовсе · 5 вердикта не получила ни одна посадка. Посадка,
# у которой сторону ствола установить нечем, вердикта не получает и стоит в
# переписи отдельным числом; но если таких ВСЕ, гейт говорит это вслух —
# иначе «ноль находок» стало бы неотличимо от «ноль прочитанного».
set -uo pipefail

# ДИАПАЗОН ВЫВОДИТСЯ ИЗ ГРАФА, а не берётся из события.
#
# Здесь стоял диапазон события (`before..head`), и он описывал ПРИРОСТ отправки,
# тогда как всё, что судья говорит, относится к ЛИНИИ ЦЕЛИКОМ. Расхождение
# единиц стоило двух дефектов сразу, и оба тихие:
#
#   1. ПЕРЕЧЕНЬ. Шапка `drift.sh` говорит прямо: «объявление описывает ОТПРАВКУ
#      целиком, и каждая посадка в ней судится под ним», — а самоистечение
#      судилось приростом. Запись, сработавшая законно, на СЛЕДУЮЩЕЙ отправке
#      объявлялась пережившей предмет и роняла гейт кодом 3, хотя не изменилось
#      ничего. То есть механизм объявления был неприменим на накопительной линии
#      — единственной раскладке, ради которой он и нужен (задача #1911).
#   2. НАХОДКА. Та же единица счёта, цена на порядок выше: откат, найденный в
#      приросте одной отправки, на следующей не пересматривался вовсе, и линия
#      зеленела, неся живой откат до самого слияния в ствол. Дефект работал
#      двойным дном — он же и служил единственным способом погасить красное:
#      достаточно было толкнуть что угодно ещё раз.
#
# Сверх того охват был функцией СОБЫТИЯ: `github.event.before` есть у `push` и у
# `pull_request` с действием `synchronize`, но не у `opened`. На боевых прогонах
# наблюдались обе формы — «диапазон прогона: X..Y» и «диапазона нет … судится
# вершина», — то есть на открытии запроса судилась ОДНА вершина при любом числе
# накопленных посадок.
#
# Опорная точка вывода — ТОЛЬКО ствол (`main`), никогда не накопительная линия:
# у линии общий предок с самой собой есть её же вершина, и диапазон схлопнулся бы
# в пустой. Предпочитается удалённая ссылка: в рабочей копии локальная `main`
# отстаёт, а в конвейере её не существует вовсе (checkout по SHA даёт открепленную
# голову и заводит только `refs/remotes/origin/*`).
head_rev=""
if git rev-parse --verify --quiet "${HEAD_SHA}^{commit}" >/dev/null; then
  head_rev=$(git rev-parse "${HEAD_SHA}^{commit}")
fi
trunk_base_ref=""
for r in refs/remotes/origin/main refs/heads/main; do
  if git rev-parse --verify --quiet "$r^{commit}" >/dev/null; then
    trunk_base_ref=$r
    break
  fi
done
derived=""
if [ -n "$head_rev" ] && [ -n "$trunk_base_ref" ]; then
  if derived=$(git merge-base "$trunk_base_ref" "$head_rev" 2>/dev/null); then
    # Голова СТОИТ НА СТВОЛЕ: линии сверх ствола не существует by construction,
    # и выводить нечего. Это не отказ — это другой случай, и он ниже.
    if [ "$derived" = "$head_rev" ]; then derived=""; fi
  else
    derived=""
  fi
fi

candidates=""
if [ -n "$derived" ]; then
  candidates=$(git rev-list --merges "${derived}..${head_rev}")
  echo "диапазон выведен из графа: ${derived}..${head_rev} — вся линия сверх ствола"
  echo "       (опорная точка ${trunk_base_ref}), а не прирост события"
elif [ -n "${BEFORE:-}" ] && [ -n "${BEFORE//0/}" ] \
   && git rev-parse --verify --quiet "${BEFORE}^{commit}" >/dev/null; then
  # Голова на стволе — линии сверх него нет, и прирост события есть ЕДИНСТВЕННОЕ
  # доступное понятие диапазона. Это остаток зависимости от события, и он назван
  # вслух, а не спрятан: по журналу обязано быть видно, что именно судили.
  candidates=$(git rev-list --merges "${BEFORE}..${HEAD_SHA}")
  echo "линии сверх ствола нет — судится прирост события: ${BEFORE}..${HEAD_SHA}"
else
  # Ни линии сверх ствола, ни диапазона в событии: судится сама вершина — если
  # она посадка.
  echo "ни линии сверх ствола, ни диапазона в событии — судится вершина"
  if [ "$(git rev-list --parents -n1 "${HEAD_SHA}" | wc -w)" -gt 2 ]; then
    candidates="${HEAD_SHA}"
  fi
fi

# Здесь стоял ВТОРОЙ различитель стороны ствола — мой, заведённый в этой
# ветке, пока ствол независимо заводил свой. При слиянии уцелели оба:
# мой лишь вычислял переменную, которую никто не читает, а решение
# принимал стволовой ниже. Мёртвым он был не безобидно: под `-e` его
# `git rev-parse` роняло ШАГ ЦЕЛИКОМ до первой посадки, и гейт выходил
# единицей, не напечатав ни строки разбора — «нашлись находки» было
# неотличимо от «не дошли до проверки».
#
# Оставлен ОДИН, и он определяет сторону ствола по ДОСТИЖИМОСТИ от опорных
# линий, а когда граф на вопрос не отвечает — НЕ выносит вердикта вовсе.

total=0; clean=0; findings=0; blind=0; nosurface=0; undecided=0
trunk_refs_count=0; trunk_commits=0
declare -A DECLARED_HIT=()

# Перепись печатается ВСЕГДА, включая аварийный выход.
#
# Причина названа опытом, а не осторожностью: шаг уже умирал молча посреди
# цикла, и по его выводу нельзя было отличить «есть находки» от «не дошёл до
# первой посадки». Пока перепись стоит только в конце удачного пути, она
# описывает лишь те прогоны, которым и так нечего скрывать.
summary() {
  echo "drift: посадок в прогоне ${total}; сверено чисто ${clean}; находок ${findings};"
  echo "       без поверхности отката ${nosurface}; не сверено ${blind};"
  echo "       сторона ствола не установлена ${undecided}"
  echo "       осмотрено опорных линий ${trunk_refs_count}; коммитов на них ${trunk_commits}"
}
trap 'rc=$?; [ "$rc" -eq 0 ] || { echo "::error::судья прервался кодом $rc, не дойдя до вердикта"; summary; }' EXIT
# Сторона СТВОЛА определяется по ДОСТИЖИМОСТИ от опорных линий, а не по
# порядку родителей.
#
# Порядок родителей говорит, где стоял тот, кто слил, а не что во что
# влито. `git merge <полоса>` с линии даёт первым родителем линию;
# `git merge <линия>` из полосы — первым родителем ПОЛОСУ. Обе формы
# законны, и вторая прямо предписана: отставшая полоса вливает линию В СЕБЯ,
# чтобы догнать, и слияние сохраняет запись о догоне.
#
# Читая порядок буквально, гейт на второй форме менял стороны местами:
# объявлял стволом полосу, а всякий её собственный файл — «откатом
# ствола». Наблюдалось дважды. На ветке провайдера: пять новых файлов, ни
# одного из которых в стволе не существует, названы возвращёнными; на том
# же графе с верным дискриминатором гейт сверил 646 файлов и нашёл 6
# настоящих находок — то есть перепутанные стороны не просто шумели, они
# ПРЯТАЛИ предмет проверки. На посадке `3a66c8574e` линии modules-5: три
# файла названы откаченными, и все три завела сама полоса.
#
# ОПОРНЫХ ЛИНИЙ НЕСКОЛЬКО, и это несущая часть, а не запас. Прежняя
# редакция знала одну — `origin/main`, — и потому молчала на всём, что
# копится в накопительной линии: линия в ствол ещё не влита, её посадок на
# первородительской цепи `main` нет by construction. Замер на запросе
# слияния `release/modules-5` (2026-09-02): «родителей на линии ствола: 0»
# напечатано для 23 посадок из 24, то есть различитель был инертен почти
# везде и отдавал решение обратно порядку родителей. Поэтому опорные линии
# — `main` И накопительные `release/*`: полосу судит линия, линию судит
# ствол.
#
# Дискриминатор — ПЕРВОРОДИТЕЛЬСКАЯ цепь опорной линии: коммит принадлежит
# ей тогда и только тогда, когда до него можно дойти от вершины линии по
# первым родителям. У слияния с линии ей отвечает первый родитель, у
# слияния из полосы — второй. Работа, влитая в линию, на цепь не попадает
# никогда: она входит вторым родителем.
#
# ТРЕТЬЯ КАТЕГОРИЯ. Если на опорных линиях не ровно один родитель, граф на
# вопрос НЕ ОТВЕЧАЕТ, и вердикт по такой посадке не выносится: она не
# находка и не чистая сверка, а отдельное число переписи. Прежде здесь
# стояло «берём первого родителя» — то есть гейт решал молча ровно там, где
# сам объявил, что различить не может, и его вердикт зависел от того, с
# какой стороны кто-то стоял, когда сливал.
trunk_refs=$(git for-each-ref --format='%(refname)' \
  refs/heads/main refs/remotes/origin/main \
  'refs/heads/release/*' 'refs/remotes/origin/release/*')
trunk_line=""
for r in $trunk_refs; do
  trunk_refs_count=$((trunk_refs_count + 1))
  trunk_line="${trunk_line}"$'\n'"$(git rev-list --first-parent "$r" 2>/dev/null || true)"
done
trunk_commits=$(printf '%s\n' "$trunk_line" | sed -n '/./p' | wc -l | tr -d ' ')
# Сверка ПОСТРОЧНАЯ, а не по вхождению подстроки: ревизия — целая строка.
on_trunk() { case $'\n'"$trunk_line"$'\n' in *$'\n'"$1"$'\n'*) return 0 ;; *) return 1 ;; esac; }

echo "опорных линий ${trunk_refs_count}; коммитов на их первородительских цепях ${trunk_commits}"

# Обход опорных линий ПУСТ — спрашивать сторону ствола не у чего. Это не
# третья категория и не может ею быть: иначе мелкий клон без ссылок дал бы
# «вердикт не выносится» на КАЖДОЙ посадке, и гейт молчал бы всегда,
# оставаясь на вид рабочим.
if [ -n "${candidates}" ] && [ "$trunk_commits" -eq 0 ]; then
  echo "::error::опорной линии в дереве ссылок нет — ни main, ни накопительной;"
  echo "       сторону ствола спрашивать не у чего, и обход опорных линий пуст"
  trap - EXIT
  summary
  exit 4
fi

for m in $candidates; do
  total=$((total + 1))
  read -r _self first rest <<<"$(git rev-list --parents -n1 "$m")"

  echo "── посадка $(git log -1 --format='%h %s' "$m")"

  # Ровно один родитель на опорных линиях — он и ствол. Ноль или больше
  # одного означает, что граф на вопрос не отвечает: вердикт по такой
  # посадке НЕ выносится, и это говорится словами. Прежде здесь стояло
  # «берём первого родителя» — решение молчком ровно там, где различить
  # нечем.
  trunk_count=0
  for pp in $first $rest; do on_trunk "$pp" && trunk_count=$((trunk_count + 1)); done
  if [ "$trunk_count" -ne 1 ]; then
    undecided=$((undecided + 1))
    echo "   сторону ствола установить нечем: родителей на опорных линиях ${trunk_count};"
    echo "   вердикт по этой посадке не выносится — это НЕ находка и не чистая сверка"
    continue
  fi
  if ! on_trunk "$first"; then
    for pp in $rest; do
      if on_trunk "$pp"; then
        # Список пересобирается СРЕДСТВАМИ ОБОЛОЧКИ, без внешней команды.
        #
        # Здесь стоял конвейер с `grep -v`, вычищавшим стволового родителя. У
        # слияния ровно с двумя родителями вычищать было нечего: grep не находил
        # ни строки, возвращал единицу, `pipefail` поднимал её на всё
        # присваивание, а `-e` роняло ШАГ ЦЕЛИКОМ — до печати переписи и до
        # первой посадки, которую стоило показать. Гейт выходил единицей молча,
        # и «нашлись находки» снова становилось неотличимо от «не дошли до
        # проверки» — ровно тот класс, который абзац выше объявляет закрытым.
        #
        # Форма, на которой это срабатывало, — не экзотика: слияние линии В
        # ПОЛОСУ, которым отставшая полоса догоняет линию. То есть гейт падал
        # тем чаще, чем точнее ему следовали.
        swapped_rest="$first"
        for q in $rest; do
          [ "$q" = "$pp" ] || swapped_rest="$swapped_rest $q"
        done
        first="$pp"; rest="$swapped_rest"
        break
      fi
    done
    echo "   стороны определены по графу: стволом взят $(git log -1 --format=%h "$first") (не первый родитель)"
  fi

  srcs=$(echo "$rest" | tr ' ' ',' | sed 's/,*$//')
  base=$(git merge-base "$first" $rest)
  rc=0
  out=$(bash tools/carrydrift/drift.sh "$base" "$srcs" "$first" "$m" 2>&1) || rc=$?
  printf '%s\n' "$out"
  # Записи перечня, СРАБОТАВШИЕ в этой посадке, копятся на всю отправку: перечень
  # описывает отправку целиком, и судить его посадкой значит требовать, чтобы
  # каждое снятие случилось в каждой из них.
  while IFS= read -r used; do
    [ -n "$used" ] && DECLARED_HIT["$used"]=1
  done < <(printf '%s\n' "$out" | sed -n 's/^declared-used: //p')
  case "$rc" in
    0) clean=$((clean + 1)) ;;
    1) findings=$((findings + 1)) ;;
    *)
      # Скрипт отказывается называть беспредметный прогон чистым, и правильно
      # делает. Но у отказа ДВЕ причины, и они не равны: если у гейта не было
      # ОБЛАСТИ, возвращать было нечего by construction; если область была, а
      # сверить не удалось, то гейт слеп, и это краснеет.
      #
      # Здесь стоял различитель по факту о графе — «двигался ли ствол с базы
      # ветки». Он был УЖЕ условия, которое различал, и потому ломался раньше
      # своего предмета: область гейта пуста не только при неподвижном стволе,
      # но и когда вся правка ствола легла на файлы, которые правит сама ветка,
      # — а их гейт не судит по собственному правилу области. Второй случай
      # прокси читал как слепоту.
      #
      # Цена ошибки измерена, а не предположена: посадка такой формы уезжает в
      # ствол и краснеет у КАЖДОГО, кто потом догоняет ствол. 2026-08-16 она
      # покраснила два несвязанных PR разом, при нуле находок в обоих; сама
      # форма — две линии, дописывающие один перечень, то есть не экзотика.
      #
      # Различитель теперь — machine-readable заявление того, кто единственный
      # знает состав области, тем же приёмом, что и `declared-used:` ниже. Это
      # не «разбор прозы»: прозу скрипт по-прежнему пишет в stderr для человека,
      # а решение принимается по токену. Отказ по любой ДРУГОЙ причине токена не
      # несёт и остаётся слепотой — послабление fail-closed by construction.
      reason=$(printf '%s\n' "$out" | sed -n 's/^no-surface: //p' | head -1)
      if [ -n "$reason" ]; then
        nosurface=$((nosurface + 1))
        echo "   области отката не было: ${reason}"
      else
        blind=$((blind + 1))
        echo "   гейт не сверил НИ ОДНОГО файла — его молчание ничего не значит"
      fi
      ;;
  esac
done

# Самоистечение перечня — утверждение об ОТПРАВКЕ, поэтому проверяется здесь,
# один раз, по объединению сработавших записей. Запись, которой нечего
# исключать, остаётся находкой: иначе она молча прикроет следующее снятие.
stale=0
DECLARED_FILE=tools/carrydrift/declared-removals.txt
if [ -n "${candidates}" ] && git rev-parse --quiet --verify "HEAD:$DECLARED_FILE" >/dev/null 2>&1; then
  while IFS= read -r line; do
    case "$line" in ''|'#'*) continue ;; esac
    path=${line%%[[:space:]]*}
    [ -n "$path" ] || continue
    if [ -z "${DECLARED_HIT[$path]+x}" ]; then
      stale=$((stale + 1))
      echo "ПЕРЕЖИЛА ПРЕДМЕТ: $DECLARED_FILE называет снятие $path,"
      echo "       а ни одна посадка этой отправки его не сняла — удалите запись"
      echo "       тем же изменением, иначе она молча прикроет следующее снятие"
    fi
  done < <(git show "HEAD:$DECLARED_FILE")
fi

# Перепись — отдельное утверждение, и исходы стоят врозь.
summary
echo "       записей перечня, переживших предмет: ${stale}"

if [ "$total" -eq 0 ]; then
  echo "прогон не нёс ни одной посадки — судить нечего, и гейт этого не скрывает"
  trap - EXIT
  exit 0
fi
trap - EXIT

# НИ ОДНА посадка не получила вердикта — и это громко, а не зелено.
#
# Третья категория выше законна поштучно: неразличимая посадка стоит рядом с
# разрешимыми, гейт о них высказался, а пробел назван числом. Но если
# неразличимы ВСЕ, то гейт отработал, не проверив ничего, и молчание стало бы
# маской: «ноль находок» превратилось бы в «ноль прочитанного», а отличить их
# по зелёному заданию нельзя.
#
# Форма достижима без злого умысла: опорные ссылки в дереве есть, а работы
# прогона на них нет — накопительные линии переименовали, образец опорных
# ссылок за ними не пошёл. До починки судья в такой раскладке молча брал
