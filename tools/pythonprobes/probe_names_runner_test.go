// probe_names_runner_test.go — файл проб обязан НАЗЫВАТЬ того, кто его исполняет.
//
// ПРЕДМЕТ. Состав прогонщика находится ОБХОДОМ дерева по образцу
// `services/*/tests/newman/scripts/*_test.py` (и корневой `tests/newman/scripts/`
// для проб вердиктного слоя), и это верное решение: проба новой
// сюиты попадает под гейт по построению, а не после того, как кто-то вспомнит.
// У решения есть цена, и платит её ЧИТАТЕЛЬ: имени файла проб нет НИГДЕ, кроме
// него самого, поэтому естественный вопрос «а её кто-нибудь зовёт?» получает
// естественный предикат `git grep <имя>` — и тот отвечает ОДНИМ попаданием.
//
// Одно попадание читается как «не зовётся никто». Это неверно: файл исполняется
// прогонщиком, его код возврата доезжает до вердикта шага, и держат это
// TestCIRunsThePythonProbeRunner с TestRunnerPatternCoversEveryTrackedProbeFile.
// Но узнать это можно только прочитав прогонщик, а до него ещё надо догадаться.
//
// ЦЕНА ИЗМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА. Так был заведён P1 «гейт адресации набора не
// зовётся ни одним прогоном» (kacho#2206): предикат по имени дал единицу, вывод
// сделан, задача открыта. Гейт при этом исполнялся каждым прогоном конвейера и
// был зелёным. Перепись в день заведения: файлов проб 21, называли исполнителя 4.
//
// ПОЧЕМУ НЕ «СДЕЛАТЬ, ЧТОБЫ ПРЕДИКАТ ДАВАЛ ДВА». Заставить `git grep <имя>`
// отвечать двойкой можно ровно одним способом — выписать состав прогонщика рукой.
// Это прямо противоположно тому, ради чего обход и заведён, и вернуло бы класс
// «проба новой сюиты не попала в список». Поэтому чинится не предикат, а ответ:
// файл сам говорит, кто его исполняет.
//
// ПОЧЕМУ ЭТО НЕ ГЕЙТ НА ПРОЗУ. Сверяется не наличие слов, а КООРДИНАТА, и берётся
// она из `const runner` — оттуда же, откуда её берут два соседних утверждения
// этого файла. Переедет прогонщик — координата в константе сменится, и все
// пометки станут несходящимися разом: гейт покраснеет на устаревшем адресе, а не
// промолчит. Ровно та связь, которой не бывает у комментария.
package pythonprobes

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// namesItsRunner — файл называет своего исполнителя.
//
// Предикат — вхождение ПУТИ прогонщика, а не его имени: имя `run-python-probes`
// встречается и в прозе о соседних предметах, путь же указывает ровно на один
// файл дерева.
func namesItsRunner(raw []byte, runnerPath string) bool {
	return strings.Contains(string(raw), runnerPath)
}

// TestEveryProbeFileNamesItsRunner — каждый файл проб называет своего исполнителя.
func TestEveryProbeFileNamesItsRunner(t *testing.T) {
	root := repoRoot(t)
	all := findProbeFiles(t, root)

	// Перепись — ОТДЕЛЬНОЕ утверждение: обход, переставший доходить до проб,
	// выходит зелёным на пустом множестве.
	if len(all) == 0 {
		t.Fatalf("в дереве не найдено ни одной пробы %q в %q — обход сломан, "+
			"а не дерево чисто", probeSuffix, probeDirGlobs)
	}

	named := 0
	var silent []string
	for _, rel := range all {
		raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Fatalf("чтение %s: %v", rel, err)
		}
		if namesItsRunner(raw, runner) {
			named++
			continue
		}
		silent = append(silent, rel)
	}

	// ОБЕ величины, а не одна: «ноль незваных» обязано быть отличимо от
	// «ноль осмотренных».
	t.Logf("файлов проб в дереве: %d; называют исполнителя: %d; молчат: %d",
		len(all), named, len(silent))

	for _, rel := range silent {
		t.Errorf("%s не называет своего исполнителя: во всём дереве имя этого файла "+
			"встречается один раз — в нём самом, поэтому `git grep` отвечает «не зовёт "+
			"никто», хотя его исполняет %s каждым прогоном конвейера. Добавь в шапку "+
			"файла, КТО его исполняет и по какому образцу собирает состав", rel, runner)
	}
}

// TestNamesItsRunnerInjection — доказательство, что утверждение выше способно
// упасть и способно смолчать, и что оно судит КООРДИНАТУ, а не похожие слова.
func TestNamesItsRunnerInjection(t *testing.T) {
	const note = "исполняется прогонщиком `" + runner + "` по образцу"

	cases := []struct {
		name string
		body string
		want bool
	}{
		{"законный близнец: путь прогонщика назван", note, true},
		{"инъекция: шапка без исполнителя вовсе",
			`"""Гейт чего-то. Перепись печатается."""`, false},
		{"инъекция: назван УСТАРЕВШИЙ адрес прогонщика — не засчитывается",
			"исполняется прогонщиком `.github/scripts/run-probes.py`", false},
		{"инъекция: названо только ИМЯ без пути — не засчитывается",
			"эту пробу гоняет run-python-probes", false},
	}
	for _, c := range cases {
		if got := namesItsRunner([]byte(c.body), runner); got != c.want {
			t.Errorf("%s: получено %v, ожидалось %v", c.name, got, c.want)
		}
	}

	// Предпосылка: координата берётся из константы, а не выписана здесь второй раз.
	// Разойдись они — гейт судил бы адрес, которого в дереве нет.
	if _, err := os.Stat(filepath.Join(repoRoot(t), filepath.FromSlash(runner))); err != nil {
		t.Fatalf("прогонщика нет по адресу %s: %v — гейт судил бы координату, "+
			"которой в дереве не существует", runner, err)
	}
	t.Logf("координата прогонщика резолвится: %s", runner)
}
