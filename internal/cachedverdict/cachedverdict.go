// Package cachedverdict — отказ пробы, зовущей ВНЕШНИЙ ИНСТРУМЕНТ подпроцессом,
// отвечать на прогоне, вердикт которого `go test` положит в кеш.
//
// # Предмет
//
// `go test` считает отпечаток пакета по его исходникам, импортам и журналу
// обращений пробы. Подпроцесс в этот отпечаток не входит: файлы, которые читает
// `helm`, проба сама не открывает, и журнал о них не знает. Значит правка чарта
// или профиля кеш НЕ сбрасывает, и над деревом, где страж обязан краснеть,
// печатается `ok (cached)` — строка, отличимая от настоящего прохода ровно одним
// словом.
//
// Замерено 2026-09-22 на дереве вровень с origin/main (bec320cf47d):
//
//	gateway/deploy/values.yaml:37  geo: kacho-geo.kacho.svc:9090 → geo.kacho.svc:9090
//	go test ./gateway/deploy/ -run TestRender_GeoBackendHost            ok … (cached), код 0
//	то же с -count=1   render_geo_test.go:55: rendered manifest missing
//	                   "kacho-geo.kacho.svc:9090", код 1
//
// Дефект в дереве ЕСТЬ, проба на него заведена, вердикт — зелёный.
//
// # Почему отказ нужен, хотя конвейер сегодня краснеет правильно
//
// Конвейер гоняет с отключённым кешем: `make test-unit` — `go test $pkgs -race
// -short -count=1 …`, шаг сборки под -race в `.github/workflows/ci.yaml` —
// `go test ./... -race -short -count=1 -exec /bin/true`. То есть В КОНВЕЙЕРЕ
// класс сегодня не живой, и это описание ОБЛАСТИ, а не оправдание: класс живой у
// человека за клавиатурой и на любом прогоне, где флаг не поставили. Зелёное из
// кеша неотличимо от зелёного по делу — ни по коду возврата, ни по тексту (без
// `-v` проба на кешированном прогоне не исполняется вовсе и ничего не печатает).
//
// # Три состояния, а не два
//
// Дискриминатор кеша берётся у самого инструмента: `go test` передаёт пробе
// `-test.testlogfile` РОВНО ТОГДА, когда собирается кешировать результат
// (разбор и замеры — `treecorpus/cachedverdict.go` фундамента). Но отсутствие
// этого флага читается ДВОЯКО:
//
//   - инструмент нас запустил и кешировать не будет — УСТАНОВЛЕННЫЙ факт;
//   - инструмент нас не запускал вовсе — заявления нет НИ В КАКУЮ сторону, и
//     сказать «кеш не применяется» здесь нельзя: это было бы отсутствие
//     заявления, выданное за заявление об отсутствии.
//
// Различаются они по второму флагу самого инструмента. Замерено 2026-09-22,
// go1.26.8, изолированный модуль, печать os.Args из пробы:
//
//	go test .                 -test.testlogfile=… -test.paniconexit0 -test.timeout=10m0s
//	go test . -count=1                            -test.paniconexit0 -test.timeout=10m0s -test.count=1
//	go test  (режим каталога)                     -test.paniconexit0 -test.timeout=10m0s
//	go test . -count=1 -run X                     -test.paniconexit0 -test.timeout=10m0s -test.count=1 -test.run=X
//	собранный двоичный, запущен руками  (флагов инструмента нет ни одного)
//
// `-test.paniconexit0` инструмент передаёт ВСЕГДА и человек его не набирает.
// Поэтому: есть журнал — кэшируемый; журнала нет, но флаг инструмента есть — не
// кэшируемый; нет ни того, ни другого — НЕ УСТАНОВЛЕНО, и это отдельный текст
// отказа, чтобы отказ по незнанию не читался как отказ по факту.
//
// # Почему текст живёт здесь, а не рядом с каждой пробой
//
// Мест, зовущих внешний инструмент подпроцессом, в дереве не одно. Текст,
// переписанный в каждое, — два (шесть, десять) утверждений об одном предмете, из
// которых верным остаётся не всякое. Механизм при этом ОДИН и чужой:
// `treecorpus.RunResultWillBeCached()` фундамента; здесь только его прочтение и
// слова, принадлежащие этому репозиторию.
package cachedverdict

import (
	"os"
	"strings"

	"github.com/PRO-Robotech/corelib/treecorpus"
)

// RunState — что известно о судьбе вердикта ЭТОГО прогона.
type RunState string

const (
	// StateCached — инструмент заявил, что положит результат в кеш.
	StateCached RunState = "кэшируемый"
	// StateNotCached — инструмент нас запустил и заявил, что не положит.
	StateNotCached RunState = "не кэшируемый"
	// StateUnknown — заявления инструмента нет: процесс запущен не им.
	StateUnknown RunState = "НЕ УСТАНОВЛЕНО"
)

// toolOwnFlag — флаг, который `go test` передаёт пробе всегда. Его наличие есть
// признак ТОГО, что инструмент вообще нас запустил, и только он позволяет
// прочесть отсутствие журнала обращений как заявление, а не как молчание.
const toolOwnFlag = "-test.paniconexit0"

// runArgs — командная строка ЭТОГО прогона. Переменная, а не прямой os.Args,
// ради одного читателя: пробы, которой нужно подать обе формы командной строки.
// Прод-кода у неё нет; подмена в пробе обязана возвращаться на место.
var runArgs = os.Args

// Observe — состояние кеша для этого прогона.
func Observe() RunState { return observe(runArgs, treecorpus.RunResultWillBeCached()) }

// observe — тот же вопрос к ЗАДАННЫМ входам. Оба входа параметрами, а не
// чтением из пакета: иначе пробу трёх состояний нельзя написать — заявление
// фундамента читается из НАСТОЯЩЕЙ командной строки прогона, то есть проба
// проверяла бы ровно то состояние, в котором её запустили.
func observe(argv []string, willBeCached bool) RunState {
	if willBeCached {
		return StateCached
	}
	for _, arg := range argv {
		name, _, _ := strings.Cut(arg, "=")
		if name == toolOwnFlag || name == "-"+toolOwnFlag {
			return StateNotCached
		}
	}
	return StateUnknown
}

// SubprocessRefusal — текст отказа для пробы, чей вердикт строит ПОДПРОЦЕСС
// tool, и ПУСТАЯ строка, когда отказывать не на чем.
//
// Отдаётся текстом, а не завершением процесса: место отказа выбирает
// вызывающий — та же форма, что у `treecorpus.CachedVerdictRefusal()`.
func SubprocessRefusal(tool string) string { return refusalFor(tool, Observe()) }

// refusalFor — тот же текст по ЗАДАННОМУ состоянию: состояние параметром, иначе
// два из трёх исходов непроверяемы (см. cachedverdict_test.go).
func refusalFor(tool string, state RunState) string {
	switch state {
	case StateCached:
		return cachedStateRefusal(tool)
	case StateUnknown:
		return unknownStateRefusal(tool)
	default:
		return ""
	}
}

// cachedStateRefusal — текст отказа по УСТАНОВЛЕННОМУ факту.
//
// Текст здесь свой, а не заимствованный у `treecorpus.CachedVerdictRefusal()`:
// тот говорит о проверке ДЕРЕВА и называет своей причиной `git ls-files`
// подпроцессом — для пробы, которая рендерит чарт, это было бы утверждением о
// не том механизме. Общий у двух текстов только МЕХАНИЗМ распознавания, и он
// один: `treecorpus.RunResultWillBeCached()`.
func cachedStateRefusal(tool string) string {
	return "" +
		"вердикт строит ПОДПРОЦЕСС " + tool + ", а результат этого прогона `go test`\n" +
		"положит в кеш — принять такой вердикт нельзя.\n" +
		"\n" +
		"починить — прогонять с отключённым кешем:\n" +
		"    go test <пакеты> -count=1\n" +
		"    make test-unit            — цель уже несёт -count=1\n" +
		"\n" +
		"почему это ОТКАЗ, а не предупреждение: `go test` считает отпечаток пакета по\n" +
		"его исходникам, импортам и журналу обращений САМОЙ пробы. Подпроцесса в\n" +
		"отпечатке нет: файлы, которые читает " + tool + ", проба не открывает, и журнал\n" +
		"о них не знает. Их правка кеш не сбрасывает — над деревом, где предмет пробы\n" +
		"уже сломан, печатается `ok (cached)`, строка, отличимая от настоящего прохода\n" +
		"ровно одним словом. Предупреждением тут не обойтись by construction: на\n" +
		"кешированном прогоне проба не исполняется вовсе, а без `-v` её вывод и не\n" +
		"печатается.\n" +
		"\n" + whyEvenThoughCIIsGreen
}

const whyEvenThoughCIIsGreen = "" +
	"почему это нужно, если конвейер и так гоняет без кеша: потому что конвейер —\n" +
	"не единственный читатель вердикта. `make test-unit` и шаг сборки под -race\n" +
	"(`go test ./... -race -short -count=1 -exec /bin/true`) кеш отключают, и В\n" +
	"КОНВЕЙЕРЕ этот класс сегодня не живой. Это описание ОБЛАСТИ, а не оправдание:\n" +
	"живой он у человека за клавиатурой и на любом прогоне, где флаг не поставили.\n" +
	"Там зелёное из кеша неотличимо от зелёного по делу — код возврата тот же,\n" +
	"а без `-v` проба не исполняется и не печатает ничего. Поэтому проба\n" +
	"ОТКАЗЫВАЕТСЯ отвечать, а не отвечает с оговоркой."

func unknownStateRefusal(tool string) string {
	return "" +
		"вердикт строит ПОДПРОЦЕСС " + tool + ", а состояние кеша НЕ УСТАНОВЛЕНО —\n" +
		"это отказ по НЕЗНАНИЮ, а не по установленному факту, и путать их нельзя.\n" +
		"\n" +
		"что именно не установлено: в командной строке этого процесса нет ни\n" +
		"журнала обращений (`-test.testlogfile`), ни собственного флага инструмента\n" +
		"(`" + toolOwnFlag + "`), который `go test` передаёт пробе всегда. Значит\n" +
		"процесс запущен НЕ инструментом, заявления о кешировании нет ни в какую\n" +
		"сторону, и сказать «кеш не применяется» было бы отсутствием заявления,\n" +
		"выданным за заявление об отсутствии.\n" +
		"\n" +
		"починить — звать пробу инструментом и с отключённым кешем:\n" +
		"    go test <пакеты> -count=1\n" +
		"    make test-unit            — цель уже несёт -count=1"
}
