// Package retiredknobs — ведомость ручек, СНЯТЫХ с объявления процесса края:
// имя переменной окружения → почему её больше нет.
//
// # Зачем ведомость, если есть проверка «эмитируется только объявленное»
//
// Двухколоночный гейт края (`gateway/deploy/knob_producer_parity_test.go`)
// ловит ЛЮБУЮ эмиссию имени, которого процесс не объявляет, и ведомость для
// этого не нужна. Она нужна для второго вопроса: снятое имя обязано не
// вернуться НИ С ОДНОЙ стороны. Сторона ЧИТАТЕЛЯ — поле настроек снова объявило
// снятое имя «чтобы ручка заработала»; сторона ПРОИЗВОДИТЕЛЯ — рендер стенда
// эмитирует снятое имя, в том числе через `extraEnv` профиля, которого шаблон
// чарта не видит вовсе. Первое судит двухколоночный гейт по исходнику, второе —
// рендер каждой цепочки (`deploy/edge_retired_knobs_render_test.go`).
//
// Без ведомости гейт, требующий ЭМИССИИ ручки, пережил бы снятие её читателя:
// он краснел бы посреди того изменения, которое снимает ручку, и решать это
// приходилось бы на месте. С ведомостью проба, требующая эмиссии, спрашивает её
// первой и истекает вместе с предметом.
//
// # Почему ведомость живёт здесь, а не рядом с настройками края
//
// Её читают ДВА пакета проб в разных деревьях каталогов: пробы чарта края и
// рендерные пробы развёртывания. Второй до `gateway/internal/...` не
// дотягивается по правилу видимости `internal` языка, поэтому ведомость,
// оставленная у настроек края, была бы переписана во втором месте — и
// разошлась бы с первым молча, на первой же новой записи.
//
// Образец — `internal/productnaming`: ведомость для гейтов живёт непроверочным
// объявлением и отдаётся КОПИЕЙ, потому что правится решением, а не вызывающим.
package retiredknobs

