// Package treecorpus отвечает на вопрос «какие файлы содержит этот
// репозиторий» — для проверок, вердикт которых обязан быть свойством КОММИТА, а
// не рабочего каталога.
//
// # Зачем это не filepath.Walk
//
// Проверка, собирающая свой корпус обходом диска, читает и то, чего в
// репозитории нет: рабочие копии агентов, распаковки чартов, сгенерированные
// каталоги, отчёты прогонов, локальные оверлеи. Все они перечислены в
// `.gitignore` — то есть автор дерева уже сказал, что частью его они не
// являются, — но обходу файловой системы об этом никто не сообщает.
//
// Следствие ходит в обе стороны, и обе наблюдались вживую на этом дереве:
//
//   - ШУМ: файл, которого в репозитории нет и по построению быть не может,
//     делает проверку красной. Тогда её перестают читать;
//   - ТИШИНА: то же самое наоборот. Место, которое проверка читает только на
//     машине разработчика (распакованный вендорный артефакт, сгенерированный
//     каталог), в свежем checkout отсутствует — и там она молчит именно тогда,
//     когда обязана говорить.
//
// Единица счёта — отслеживаемый git-элемент. Это не выбор вкуса: ровно то
// множество увидит свежий клон и CI.
//
// # Почему отказ, а не откат на обход
//
// Недоступность git — ОТКАЗ. Молчаливый откат «нет git — пойду по диску» вернул
// бы ровно тот дефект, ради которого пакет написан, и сделал бы это незаметно:
// на машине без git проверка продолжала бы «работать».
//
// Синтетическое дерево, собранное самой проверкой во временном каталоге,
// репозиторием не является, спрашивать у него индекс нечего — там обход
// файловой системы законен и остаётся на месте вызова. Этот пакет про
// репозиторий.
package treecorpus

import (
	"fmt"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// Under возвращает АБСОЛЮТНЫЕ пути отслеживаемых файлов под каталогом dir,
// отсортированные (детерминизм входа — часть контракта проверки).
//
// dir обязан лежать внутри рабочего дерева git. Ошибка возвращается и в случае,
// когда git недоступен, и когда каталог вне репозитория: вызывающий обязан на
// этом остановиться, а не выдать «ноль находок».
func Under(dir string) ([]string, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, fmt.Errorf("treecorpus: абсолютный путь для %s: %w", dir, err)
	}
	// Каталог задаётся рабочей директорией процесса, а НЕ аргументом `-C <путь>`:
	// так в командной строке не остаётся ни одного операнда, кроме литералов.
	// `git -C <dir> ls-files` и запуск git с рабочим каталогом <dir> дают здесь
	// одно и то же — обе формы велят git считать <dir> текущим каталогом, а
	// `ls-files` перечисляет относительно него.
	cmd := exec.Command("git", "ls-files", "-z")
	cmd.Dir = abs
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("treecorpus: git ls-files в %s: %w — состав дерева "+
			"взять неоткуда; обход диска вместо индекса читал бы игнорируемые "+
			"каталоги (рабочие копии агентов, распаковки чартов, отчёты прогонов), "+
			"и вердикт стал бы свойством рабочего каталога, а не коммита", abs, err)
	}
	var files []string
	for _, rel := range strings.Split(string(out), "\x00") {
		if rel == "" {
			continue
		}
		files = append(files, filepath.Join(abs, filepath.FromSlash(rel)))
	}
	// Пустой корпус — ОТКАЗ, а не пустой успех.
	//
	// Вызывающий здесь — всегда проверка, и её вопрос всегда «что в этом дереве
	// не так». Ноль файлов означает, что смотреть было не на что: каталог
	// переехал, целиком игнорируется или назван неверно. Вернув (nil, nil), этот
	// пакет отдал бы «ноль находок» на «ноль прочитанного» — тот самый класс,
	// ради которого он написан, только этажом ниже и в каждом будущем гейте
	// сразу. Требование «ноль целей — отказ, а не успех» пережило механизм, из
	// которого выведено, и распространяется на любой обходчик дерева.
	//
	// Каталог, законно пустой в индексе, обходить незачем: у проверки, которой
	// он нужен, нет предмета.
	if len(files) == 0 {
		return nil, fmt.Errorf("treecorpus: под %s нет ни одного отслеживаемого файла — "+
			"смотреть не на что. «Ноль находок» на «ноль прочитанного» неотличимо от "+
			"чистого дерева, поэтому это отказ, а не пустой успех: проверь путь, "+
			"не переехал ли каталог и не покрыт ли он целиком правилами игнорирования", abs)
	}
	sort.Strings(files)
	return files, nil
}

// UnderWithSuffix — то же, но оставляет только пути с одним из суффиксов.
// Пустой набор суффиксов означает «все файлы».
func UnderWithSuffix(dir string, suffixes ...string) ([]string, error) {
	files, err := Under(dir)
	if err != nil {
		return nil, err
	}
	if len(suffixes) == 0 {
		return files, nil
	}
	var out []string
	for _, f := range files {
		for _, s := range suffixes {
			if strings.HasSuffix(f, s) {
				out = append(out, f)
				break
			}
		}
	}
	return out, nil
}
