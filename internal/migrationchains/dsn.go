package migrationchains

import (
	"errors"
	"strings"

	"github.com/jackc/pgx/v5"
)

// DatabaseOf — имя базы, к которой соединится драйвер по этому DSN (Д83, Д93).
//
// Разбор — [pgx.ParseConfig], ровно тот вызов, которым общий тракт наката
// (`corelib/migratorcli.OpenDB`) строит соединение; имя базы он берёт у
// `pgconn.ParseConfig` и сверх него разбирает три собственных ключа драйвера
// (`statement_cache_capacity`, `description_cache_capacity`,
// `default_query_exec_mode`). Своего разбора здесь нет, и разбор libpq без
// ключей драйвера тоже не годится: строку с негодным значением такого ключа он
// принял бы, выбор цепочки состоялся бы, а отказ разбора пришёл бы позже — от
// соединения, текстом драйвера с узлом, пользователем и базой (GS-C3). Один
// разбор — один отказ, и он здесь.
//
// Два разбора одной строки уже расходились (DSN-DB-DIVERGENCE): при втором
// источнике имени в строке (query-параметр `dbname`/`database` у URL, ключ
// `database` у ключевой формы) точка выбирала цепочку по одному имени, а
// драйвер соединялся с другим. Окружение (`PGDATABASE`), которое драйвер читает
// при DSN без имени, решает и здесь — по той же причине: решение о цепочке
// судит ту базу, к которой будет соединение.
//
// Имя пусто (ни строка, ни окружение его не называют) — отказ, а не пустое имя.
//
// Текст отказа разбора — только вид отказа: ни строки DSN, ни её кусков. Текст
// ошибки драйвера сюда не переносится НИ целиком, НИ обёрткой: маска пароля у
// драйвера частичная (пароль с `@` или `%` уходит хвостом в «узел»), а обёрнутая
// ошибка `url.Parse` несёт строку целиком (SEC-W1-01). Отказ уходит в журнал
// init-контейнера, который читает каждый с правом `pods/log`.
func DatabaseOf(dsn string) (string, error) {
	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		return "", errors.New("DSN не разобран драйвером (" + dsnForm(dsn) + "); " +
			"текст разбора не печатается — он несёт куски строки соединения")
	}
	if cfg.Database == "" {
		return "", errors.New("DSN не называет базу: имени нет ни в строке, ни в окружении PGDATABASE")
	}
	return cfg.Database, nil
}

// dsnForm — запись DSN для текста отказа: вид, не содержимое.
func dsnForm(dsn string) string {
	s := strings.TrimSpace(dsn)
	if strings.HasPrefix(s, "postgres://") || strings.HasPrefix(s, "postgresql://") {
		return "запись URL"
	}
	return "ключевая запись libpq"
}
