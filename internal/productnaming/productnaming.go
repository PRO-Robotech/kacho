// Package productnaming — ЕДИНСТВЕННОЕ место, где объявлено, как продукт
// называет свои части: каталог исходников службы, имя её чарта в умбрелле и имя
// её образа.
//
// # Почему пакет заведён
//
// До 2026-09 соответствие ВЫВОДИЛОСЬ приставкой имени платформы: каталог
// `services/<svc>` ↔ чарт `kacho-<svc>` ↔ образ `kacho-<svc>`. Вывод был верен,
// пока имя платформы было и именем каждой её части.
//
// Служба управления доступом получила собственное имя продукта — Kaname
// (решение владельца, задача #2076): «Kaname наследует от Kachō КОД, но не ИМЯ».
// С этого момента имя продукта и имя каталога исходников — РАЗНЫЕ СЛОВАРИ, и
// приставка их больше не связывает.
//
// # Чем это было опасно
//
// Правило вывода стояло в дереве ШЕСТЬЮ копиями, в шести проверках. Три из них
// на переименовании покраснели и назвали предмет; три остались зелёными — и
// именно они опаснее: распознаватель, ключующийся на приставке, чужое имя не
// отвергает, он его НЕ ВИДИТ. Образ, не названный `kacho-*`, переставал быть
// «образом продукта» для проверки свежести пинов — то есть его пин уходил
// из-под наблюдения молча (`deploy/managed_cluster_profile_test.go`).
//
// Поэтому соответствие объявлено здесь один раз, а не выведено в каждом месте
// заново. Записи ведомости самоистекают: запись, у которой в дереве нет обеих
// сторон, — находка (см. productnaming_test.go).
package productnaming

import (
	"sort"
	"strings"
)

// platformName — имя платформы. Оно же имя ПРОДУКТА для тех частей, у которых
// своего имени нет.
const platformName = "kacho"

// platformPrefix — приставка имени платформы. Ею связаны те части, у которых
// СВОЕГО имени продукта нет; для них соответствие по-прежнему выводится.
//
// Выводится из platformName, а не выписывается вторым литералом: два написания
// одного имени расходятся молча, и расходятся на переименовании — то есть ровно
// тогда, когда их сверить некому.
const platformPrefix = platformName + "-"

// renamedServices — части, чьё имя продукта НЕ выводится из имени платформы.
//
// Ключ — каталог исходников под `services/`, значение — имя продукта (оно же
// имя чарта в умбрелле и имя образа). Ведомость закрыта: попадание сюда — это
// решение владельца о названии, а не удобство исполнителя.
var renamedServices = map[string]string{
	"iam": "kaname",
}

// externallySourcedServices — части продукта, чьи ИСХОДНИКИ живут в ДРУГОМ
// репозитории, а имя, чарт и образ остались нашими.
//
// # Почему это отдельная ведомость, а не удаление записи из renamedServices
//
// Разрез монорепо развёл две стороны, до сих пор всегда лежавшие вместе:
// исходники части и её ПОСТАВКУ. У Kaname после выноса (задача #1111) чарт
// `deploy/helm/umbrella/charts/kaname` и пин её образа остались в нашей
// умбрелле, а каталог `services/iam` уехал целиком.
//
// Соблазн — снять запись из renamedServices, раз гейт самоистечения справедливо
// говорит «каталога нет». Цена этого хода измерена и она недопустима: без записи
// [ServiceDir] отвечает «не наша часть», а значит [IsProductImageRepo] отвечает
// ложью на `kaname`, и пин её образа уходит из-под наблюдения свежести МОЛЧА —
// ровно тот дефект, против которого пакет и заведён (шапка выше, случай
// `deploy/managed_cluster_profile_test.go`). Сверх того чарт в умбрелле стал бы
// считаться «чужим вендоренным», то есть о нашей же поставке дерево утверждало
// бы неправду.
//
// Поэтому имя остаётся, а СТОРОНА объявляется явно. Ведомость самоистекает в
// обе стороны, и это проверяется (productnaming_test.go):
//
//   - запись, чей каталог исходников В ДЕРЕВЕ ЕСТЬ, — находка: часть вернулась,
//     объявление пережило свой предмет;
//   - запись без своего чарта в умбрелле — находка: поставки нет, значит и
//     имени в этом дереве взяться неоткуда;
//   - имя, которого нет в renamedServices, — находка: два словаря об одном
//     предмете разошлись бы молча.
//
// Значение — репозиторий-источник. Оно не резолвится проверкой и не обязано:
// его предмет вне этого дерева, а назначение — сказать читателю, ГДЕ искать, и
// не дать записи выродиться в голое имя без причины.
var externallySourcedServices = map[string]string{
	"iam": "PRO-Robotech/kaname",
}

// SourcesInThisTree — лежат ли исходники части в ЭТОМ дереве.
//
// Спрашивают ПЕРЕД тем как пойти читать `services/<dir>`: часть, отвечающая
// ложью, судится в своём репозитории, и «ноль прочитанного» о ней здесь не
// является ни находкой, ни чистотой. Проверка, которая её пропускает, обязана
// НАЗВАТЬ пропуск в переписи — молчаливый пропуск неотличим от «осмотрели и
// сошлось».
func SourcesInThisTree(serviceDir string) bool {
	_, external := externallySourcedServices[serviceDir]
	return !external
}

// ExternallySourcedServices — ведомость для гейта самоистечения. Возвращается
// копия: ведомость правится решением о разрезе, а не вызывающим.
func ExternallySourcedServices() map[string]string {
	out := make(map[string]string, len(externallySourcedServices))
	for k, v := range externallySourcedServices {
		out[k] = v
	}
	return out
}

// ChartName — имя чарта (и образа) части по её каталогу исходников.
func ChartName(serviceDir string) string {
	if name, ok := renamedServices[serviceDir]; ok {
		return name
	}
	return platformPrefix + serviceDir
}

// ServiceDir — каталог исходников по имени чарта (или образа).
//
// Второй возврат — было ли имя РАСПОЗНАНО как имя части продукта. Ложь означает
// «это не наша часть», а не «каталога нет»: существование каталога проверяет
// вызывающий, которому известен корень дерева.
func ServiceDir(chartName string) (string, bool) {
	for dir, name := range renamedServices {
		if name == chartName {
			return dir, true
		}
	}
	if rest, ok := strings.CutPrefix(chartName, platformPrefix); ok && rest != "" {
		return rest, true
	}
	return "", false
}

// IsProductImageRepo — последний сегмент репозитория образа называет часть
// ПРОДУКТА.
//
// Признак — членство в словаре имён продукта, а не приставка: с появлением
// собственных имён приставка перестала быть признаком, и предикат по ней
// ослеп бы ровно на переименованных частях.
func IsProductImageRepo(repo string) bool {
	last := repo[strings.LastIndex(repo, "/")+1:]
	_, ok := ServiceDir(last)
	return ok
}

// RenamedServices — ведомость для гейта самоистечения: он обязан убедиться, что
// у каждой записи в дереве есть ОБЕ стороны. Возвращается копия — ведомость
// правится решением, а не вызывающим.
func RenamedServices() map[string]string {
	out := make(map[string]string, len(renamedServices))
	for k, v := range renamedServices {
		out[k] = v
	}
	return out
}

// EnvPrefix — корневой сегмент имён окружения части продукта.
//
// Выводится из ТОГО ЖЕ имени, что чарт и образ: `vpc` → `KACHO_VPC`,
// `api-gateway` → `KACHO_API_GATEWAY`, `iam` → `KANAME`. Отдельной ведомости
// у окружения нет намеренно — своя ведомость стала бы третьим словарём об одном
// предмете и разошлась бы с двумя первыми молча.
func EnvPrefix(serviceDir string) string {
	return strings.ToUpper(strings.ReplaceAll(ChartName(serviceDir), "-", "_"))
}

// MetricNamespace — приставка имён рядов метрик части продукта.
//
// Выводится из ТОГО ЖЕ имени, что чарт, образ и окружение: `vpc` →
// `kacho_vpc`, `iam` → `kaname`. Разделитель здесь `_`, потому что имя ряда
// Prometheus дефиса не допускает; иного различия с прочими словарями нет, и
// своей ведомости у метрик не заводится.
func MetricNamespace(serviceDir string) string {
	return strings.ReplaceAll(ChartName(serviceDir), "-", "_")
}

// ProductName — имя ПРОДУКТА, которому принадлежит часть.
//
// Отличается от [ChartName] у частей БЕЗ своего имени: чарт службы сети зовётся
// `kacho-vpc`, а продукт, которому она принадлежит, — `kacho`. У части со своим
// именем эти два совпадают: Kaname и есть продукт целиком.
//
// Выводится из ТОЙ ЖЕ ведомости, что чарт, образ, окружение и метрики. Своей
// ведомости у продукта не заводится: она стала бы третьим словарём об одном
// предмете и разошлась бы с двумя первыми молча.
func ProductName(serviceDir string) string {
	if name, ok := renamedServices[serviceDir]; ok {
		return name
	}
	return platformName
}

// MigratorBinary — имя двоичного файла накатчика схемы части продукта.
//
// # Почему имя ПРОДУКТА, а не части
//
// Накатчик у каждой службы свой двоичный файл, но имя у него одно на продукт:
// `kacho-migrator` у шести служб платформы, `kaname-migrator` у Kaname. Это не
// небрежность и не наследие — знание об одном накатчике обязано применяться к
// соседнему, поэтому имя различает ПРОДУКТЫ, а не службы внутри продукта.
//
// # Почему это не «код, а имя» (эпик #2076)
//
// Проверочный вопрос разделения — «это имя, которым продукт себя называет, или
// код, который он исполняет?». Разбор командной строки, форма вызова и тексты
// отказа общие и наследуются как есть (corelib/migratorcli). Имя двоичного файла
// кодом не является: его выбирает сборка (`go build -o`), и ничем, кроме самой
// сборки, оно не связано.
//
// # Почему это ВИТРИНА
//
// Оператор чужого облака набирает это имя руками — в спецификации пода
// (`kubectl describe`), в клиентском документе установки, в разборе неполадок.
// Значит оно попадает под П3 предиката готовности линии: «ноль чужого бренда
// там, где продукт называет себя».
func MigratorBinary(serviceDir string) string {
	return ProductName(serviceDir) + "-migrator"
}

// ProductNames — имена ВСЕХ продуктов дерева: платформа плюс части, получившие
// собственное имя. Отсортированы (детерминизм входа — часть контракта всякой
// проверки, которая этим перечнем пользуется).
//
// Существует ради распознавателей: чтобы отличить имя продукта от постороннего
// слова той же формы (`build-migrator` — цель сборки, а не двоичный файл), надо
// знать, какие слова именами продуктов ЯВЛЯЮТСЯ. Перечень выводится из той же
// ведомости, а не выписывается: второй словарь разошёлся бы с первым молча.
func ProductNames() []string {
	seen := map[string]bool{platformName: true}
	out := []string{platformName}
	for _, name := range renamedServices {
		if seen[name] {
			continue
		}
		seen[name] = true
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}
