// Package productnaming — ЕДИНСТВЕННОЕ место, где объявлено, как продукт
// называет свои части: каталог исходников службы, имя её чарта в умбрелле и имя
// её образа.
//
// # Почему пакет заведён
//
// До 2026-09 соответствие ВЫВОДИЛОСЬ приставкой имени платформы: каталог
// `services/<svc>` ↔ чарт `kacho-<svc>` ↔ образ `kacho-<svc>`. Вывод был верен,
// пока имя платформы было и именем каждой её части.
//
// Служба управления доступом получила собственное имя продукта — Kaname
// (решение владельца, задача #2076): «Kaname наследует от Kachō КОД, но не ИМЯ».
// С этого момента имя продукта и имя каталога исходников — РАЗНЫЕ СЛОВАРИ, и
// приставка их больше не связывает.
//
// # Чем это было опасно
//
// Правило вывода стояло в дереве ШЕСТЬЮ копиями, в шести проверках. Три из них
// на переименовании покраснели и назвали предмет; три остались зелёными — и
// именно они опаснее: распознаватель, ключующийся на приставке, чужое имя не
// отвергает, он его НЕ ВИДИТ. Образ, не названный `kacho-*`, переставал быть
// «образом продукта» для проверки свежести пинов — то есть его пин уходил
// из-под наблюдения молча (`deploy/managed_cluster_profile_test.go`).
//
// Поэтому соответствие объявлено здесь один раз, а не выведено в каждом месте
// заново. Записи ведомости самоистекают: запись, у которой в дереве нет обеих
// сторон, — находка (см. productnaming_test.go).
package productnaming

import "strings"

// platformPrefix — приставка имени платформы. Ею связаны те части, у которых
// СВОЕГО имени продукта нет; для них соответствие по-прежнему выводится.
const platformPrefix = "kacho-"

// renamedServices — части, чьё имя продукта НЕ выводится из имени платформы.
//
// Ключ — каталог исходников под `services/`, значение — имя продукта (оно же
// имя чарта в умбрелле и имя образа). Ведомость закрыта: попадание сюда — это
// решение владельца о названии, а не удобство исполнителя.
var renamedServices = map[string]string{
	"iam": "kaname",
}

// ChartName — имя чарта (и образа) части по её каталогу исходников.
func ChartName(serviceDir string) string {
	if name, ok := renamedServices[serviceDir]; ok {
		return name
	}
	return platformPrefix + serviceDir
}

// ServiceDir — каталог исходников по имени чарта (или образа).
//
// Второй возврат — было ли имя РАСПОЗНАНО как имя части продукта. Ложь означает
// «это не наша часть», а не «каталога нет»: существование каталога проверяет
// вызывающий, которому известен корень дерева.
func ServiceDir(chartName string) (string, bool) {
	for dir, name := range renamedServices {
		if name == chartName {
			return dir, true
		}
	}
	if rest, ok := strings.CutPrefix(chartName, platformPrefix); ok && rest != "" {
		return rest, true
	}
	return "", false
}

// IsProductImageRepo — последний сегмент репозитория образа называет часть
// ПРОДУКТА.
//
// Признак — членство в словаре имён продукта, а не приставка: с появлением
// собственных имён приставка перестала быть признаком, и предикат по ней
// ослеп бы ровно на переименованных частях.
func IsProductImageRepo(repo string) bool {
	last := repo[strings.LastIndex(repo, "/")+1:]
	_, ok := ServiceDir(last)
	return ok
}

// RenamedServices — ведомость для гейта самоистечения: он обязан убедиться, что
// у каждой записи в дереве есть ОБЕ стороны. Возвращается копия — ведомость
// правится решением, а не вызывающим.
func RenamedServices() map[string]string {
	out := make(map[string]string, len(renamedServices))
	for k, v := range renamedServices {
		out[k] = v
	}
	return out
}

// EnvPrefix — корневой сегмент имён окружения части продукта.
//
// Выводится из ТОГО ЖЕ имени, что чарт и образ: `vpc` → `KACHO_VPC`,
// `api-gateway` → `KACHO_API_GATEWAY`, `iam` → `KANAME`. Отдельной ведомости
// у окружения нет намеренно — своя ведомость стала бы третьим словарём об одном
// предмете и разошлась бы с двумя первыми молча.
func EnvPrefix(serviceDir string) string {
	return strings.ToUpper(strings.ReplaceAll(ChartName(serviceDir), "-", "_"))
}
