// Package carrierprobe — общие предикаты проб композиционных корней: слушает ли
// процесс в пробе порт, который назначит ядро, и каким исходом кончился подъём
// носителя.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Проба носителя поднимает оба слушателя процесса и гасит их отменённым
// контекстом. Если слушатель встаёт на ФИКСИРОВАННОМ порту, вердикт пробы
// становится функцией того, что ещё поднято на машине прогона: занятый 9090
// соседним стендом краснит её текстом «bind: address already in use», а в
// конвейере порт свободен, и она зеленеет, ничего не доказывая (kacho#2678,
// kacho#2680). Имя ручки, которого разбор конфигурации не знает, не отказывает и
// не предупреждает — величина остаётся умолчанием, и проба занимает порт,
// объявив, что не занимает.
//
// Предикат и страж жили двумя посимвольно одинаковыми копиями в пробах двух
// служб из шести; правка вносилась в одну из двух, у остальных четырёх стража
// не было вовсе (kacho#2749). Здесь их единственное определение; что его зовут
// все композиционные корни, держит перепись `census_test.go`.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ СУДИТСЯ АДРЕС ДЕСКРИПТОРА, А НЕ ВЕЛИЧИНА КОНФИГУРАЦИИ
//
// Службы задают слушатель по-разному: одни портом (`":" + порт`), другие
// эндпойнтом (`tcp://хост:порт`). Прежние копии предиката принимали каждая свою
// форму — и общий предикат, принявший ОБЕ, отвечал бы «да» на вход, который для
// одной из сторон незаконен: значение `127.0.0.1:0` в ручке порта процесс
// склеит в `:127.0.0.1:0`, и слушатель не поднимется вовсе. Широкая форма
// перестала бы отвечать на вопрос каждой стороны.
//
// Поэтому вход здесь один и самый узкий — адрес РОВНО в той форме, в которой
// носитель отдаёт его `net.Listen("tcp", …)`: `servicecontract.Spec.PublicAddr` /
// `InternalAddr`. Он общий для всех шести служб, и суждение о нём — суждение об
// исходе, а не об объявлении: как именно служба собрала адрес из своей ручки,
// проверяет сам этот вход.
package carrierprobe

import (
	"errors"
	"fmt"
	"net"
	"strconv"
	"strings"

	"github.com/PRO-Robotech/corelib/servicecontract"
	"google.golang.org/grpc"
)

// KernelAssigned — просит ли адрес слушателя порт, который назначит ЯДРО.
//
// Вход — адрес в форме, которую получает `net.Listen("tcp", addr)`: `хост:порт`
// либо `:порт`. Иные формы (эндпойнт со схемой, голый порт) — не адрес
// слушателя, и ответ на них «нет»: так же отвечает и сам `net.Listen`.
//
// Порт судится ЧИСЛОМ, а не строкой «0»: ядру его отдаёт число, и
// `net.Listen` поднимает эфемерный слушатель и на `:00`, и на `:+0`. Разбор —
// `strconv.Atoi`: его область приёма совпадает с областью приёма слушателя на
// всех числовых написаниях, которые перечисляет проба рядом, и совпадение там
// не записано, а исполняется — каждое написание предъявляется настоящему
// `net.Listen`.
//
// РАСХОЖДЕНИЕ ОДНО, И ОНО НАМЕРЕННОЕ: ПУСТОЙ порт (`:`, пустой адрес).
// `net.Listen` поднимается и на нём, выдавая эфемерный порт, а предикат
// отвечает «нет». Он судит не то, что сделает ядро, а то, ДОЕХАЛА ЛИ РУЧКА:
// пустое значение — отсутствующая конфигурация, и предпосылка пробы на ней не
// создана.
func KernelAssigned(addr string) bool {
	_, port, err := net.SplitHostPort(addr)
	if err != nil {
		return false
	}
	n, err := strconv.Atoi(port)
	return err == nil && n == 0
}

// Listener — слушатель процесса: ручка, которой его задаёт проба, и адрес,
// который из неё собрал процесс.
type Listener struct {
	Knob string
	Addr string
}

// Listeners — оба слушателя дескриптора с названными ручками.
func Listeners(spec servicecontract.Spec, publicKnob, internalKnob string) []Listener {
	return []Listener{
		{Knob: publicKnob, Addr: spec.PublicAddr},
		{Knob: internalKnob, Addr: spec.InternalAddr},
	}
}

// ErrConditionNotCreated — исход «условие не создано». Это ТРЕТЬЯ категория, не
// красное и не зелёное: проба не спросила о своём предмете вовсе.
var ErrConditionNotCreated = errors.New("УСЛОВИЕ НЕ СОЗДАНО")

// Refusal — отказ стража предусловия: nil, если каждый слушатель просит порт
// у ядра; иначе отказ называет РУЧКУ и адрес, который из неё собран.
func Refusal(ls ...Listener) error {
	var bad []string
	for _, l := range ls {
		if !KernelAssigned(l.Addr) {
			bad = append(bad, fmt.Sprintf("слушатель ручки %s собран в адрес %q", l.Knob, l.Addr))
		}
	}
	if len(bad) == 0 {
		return nil
	}
	return fmt.Errorf("%w: %s — это не порт, назначенный ядром. Подстановка ручки не доехала до "+
		"разбора конфигурации (либо проба её не задала), и вердикт пробы стал бы функцией того, что "+
		"ещё поднято на машине прогона; о носителе такой прогон не говорит ничего",
		ErrConditionNotCreated, strings.Join(bad, "; "))
}

// T — то, что стражу нужно от пробы. Интерфейс, а не *testing.T: способность
// упасть доказывается подставным исполнителем.
type T interface {
	Helper()
	Fatalf(format string, args ...any)
}

// RequireKernelAssigned — СТРАЖ ПРЕДУСЛОВИЯ проб носителя: оба слушателя
// дескриптора просят порт у ядра. Стоит ДО вызова носителя: без него проба
// падала бы не на своём предмете, а на соседнем стенде, и чужим текстом.
func RequireKernelAssigned(t T, spec servicecontract.Spec, publicKnob, internalKnob string) {
	t.Helper()
	if err := Refusal(Listeners(spec, publicKnob, internalKnob)...); err != nil {
		t.Fatalf("%v", err)
	}
}

// Outcome — исход подъёма носителя на ЗАРАНЕЕ отменённом контексте.
type Outcome int

const (
	// Raised — отказы старта отработали, слушатели поднялись и погашены.
	Raised Outcome = iota + 1
	// Refused — носитель отказал процессу в старте: красное по существу.
	Refused
	// NotCreated — слушатель не поднялся (порт занят, адрес не берётся): условие
	// пробы не создано, и это третья категория, а не отказ носителя.
	NotCreated
	// Failed — иная ошибка подъёма: красное, названное как есть.
	Failed
)

// refusalMarker — чем носитель помечает отказ старта. Типа у отказа нет;
// единственное место, где это слово читается, — здесь.
const refusalMarker = "не поднимается"

// Classify — исход подъёма по ошибке `servicehost.Serve`.
//
// Порядок проверок — порядок значения: отказ старта считается раньше слушателя
// (отказы отрабатывают ДО `net.Listen`), слушатель — раньше прочего.
func Classify(serveErr error) Outcome {
	if serveErr == nil || errors.Is(serveErr, grpc.ErrServerStopped) {
		return Raised
	}
	if strings.Contains(serveErr.Error(), refusalMarker) {
		return Refused
	}
	var op *net.OpError
	if errors.As(serveErr, &op) && op.Op == "listen" {
		return NotCreated
	}
	return Failed
}

// Verdict — текст исхода для пробы; пустая строка — подъём состоялся.
func Verdict(service string, serveErr error) string {
	switch Classify(serveErr) {
	case Raised:
		return ""
	case Refused:
		return fmt.Sprintf("носитель ОТКАЗАЛ %s в старте — на стенде процесс не поднялся бы:\n%v", service, serveErr)
	case NotCreated:
		return fmt.Sprintf("%v: слушатель %s не поднялся — %v. Это свойство машины прогона, а не "+
			"коммита: о носителе прогон не сказал ничего", ErrConditionNotCreated, service, serveErr)
	default:
		return fmt.Sprintf("носитель вернул ошибку подъёма %s: %v", service, serveErr)
	}
}

// RequireRaised — проба носителя: подъём состоялся. Отказ носителя, занятость
// слушателя и прочая ошибка отличимы по тексту — каждый чинится своим.
func RequireRaised(t T, service string, serveErr error) {
	t.Helper()
	if v := Verdict(service, serveErr); v != "" {
		t.Fatalf("%s", v)
	}
}
