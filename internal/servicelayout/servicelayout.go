// Package servicelayout — где у службы живёт слой бизнес-логики.
//
// Сегмент каталога выведен из имени ПРОДУКТА, а не из имени службы: служба
// управления доступом получила собственное имя (Kaname) и назвала им свои
// каталоги, тогда как остальные наследуют имя платформы. Общего у них код, а
// не идентичность.
//
// ОБЪЯВЛЕНИЕ ОДНО НА ДЕРЕВО. Прежде сегмент стоял литералом в каждом гейте,
// обходящем службы, и такой литерал верен ровно до первой службы, назвавшей
// себя иначе: он не краснеет, а МОЛЧА обходит не тот каталог — то есть даёт
// «ноль находок» там, где не прочитано ничего.
package servicelayout

// platformSegment — имя, которое служба наследует от платформы, пока не
// назвала себя сама.
const platformSegment = "kacho"

// ownSegments — службы, назвавшие свои каталоги собственным именем продукта.
//
// Карта, а не одна ветка `if`: вторая такая служба заводится одной строкой, и
// её отсутствие здесь видно как отсутствие строки, а не как забытое условие.
//
// СЕЙЧАС КАРТА ПУСТА, и это законное состояние, а не незаконченная работа.
// Единственная запись (`iam` → `kaname`) снята ВМЕСТЕ СО СВОИМ ПРЕДМЕТОМ:
// служба доступа вынесена отдельным продуктом (задача #1111), каталога
// `services/iam` в этом дереве нет, и запись, у которой обе стороны не
// резолвятся, прикрывала бы координату, которой не существует.
//
// Пустая карта означает «своё имя каталогам не дала ни одна служба дерева» —
// именно это здесь сегодня и верно. Заведётся такая служба — вернётся строка;
// перепись гейта различает «ноль записей» и «ноль прочитанного» (см.
// servicelayout_test.go), поэтому пустота не выродится в молчание.
var ownSegments = map[string]string{}

// UseCaseSegment — сегмент каталога слоя use-case и слоя репозитория у
// названной службы. Имя службы — каталог под `services/`.
func UseCaseSegment(service string) string {
	if seg, ok := ownSegments[service]; ok {
		return seg
	}
	return platformSegment
}
