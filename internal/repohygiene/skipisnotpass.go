// skipisnotpass.go — пропуск не есть проход: работа, чьи вердиктные шаги
// погасила отметка `STAND_PRECONDITION_UNMET`, не вправе выйти зелёной.
//
// # Предмет
//
// Отметку `STAND_PRECONDITION_UNMET=1` ставит тот, кто НАБЛЮДАЛ несозданное
// условие: владелец подъёма (посторонний источник чартов не ответил) либо
// провенанс ревизии (стенд исполняет ДРУГОЕ дерево). Она гасит шаги ниже — и
// это верно: вердикт о чужом дереве относится не к тому предмету.
//
// Неверно другое. Погашенный шаг не падает, он ПРОПУСКАЕТСЯ, а работа без
// упавших шагов выходит `success`. То есть отсутствие вердикта приходило в
// сводку запроса на слияние тем же зелёным кружком, что и вердикт «проверено,
// замечаний нет». Зелёное перестаёт быть гарантией и означает «мы не
// спрашивали».
//
// # Замер, из которого правило выведено (2026-09-12)
//
// Предикат — разбор всех файлов конвейера, отбор шагов, чьё условие читает
// отметку: файлов 13, работ 31, шагов 309; отметка гасит 22 шага в ТРЁХ работах
// (`ci.yaml`/`helm` — 5, `console-e2e.yml`/`probes` — 6, `e2e-newman.yml`/`shard`
// — 11). Наблюдалось на прогонах 34694955300 и 34694955309: консоль пропустила
// `прогон проб` и гейт по отчёту и вышла `success`; четыре шарда вышли `success`
// при нуле исполненных коллекций из 57 — сказал это только сводный вердикт, сами
// работы молчали.
//
// # Решение владельца (2026-09-12), которое это правило держит
//
// «Сделай так, чтобы можно было гарантировать зелёный; если что-то не так — в
// красный.» То есть исход работы при выставленной отметке обязан быть КРАСНЫМ, а
// различение трёх категорий остаётся в ДИАГНОСТИКЕ: текст отказа называет
// причину и говорит прямо, что вердикта о продукте нет ни у одной проверки.
// Прежняя редакция механизма (#2250) решала обратное — «не выполнилось» не
// красит работу, — и честно называла остаток: «зелёная проверка означает
// „слиянию не препятствует“, НЕ „стенд поднялся“». Владелец выбрал другую
// сторону этого же остатка.
//
// # Что здесь считается защитой — ГАРАНТИЯ, а не починка одного случая
//
// Работа, где отметка гасит хотя бы один шаг, обязана нести ПЕРЕПИСЬ ИСХОДОВ:
// шаг, который сверяет объявленное с исполненным и роняет работу, когда
// объявленный вердиктный шаг результата не дал. Требований к нему пять, и каждое
// несущее:
//
//  1. перепись ЕСТЬ. Без неё гарантии нет: зелёное означает «ни один шаг не
//     упал», а погашенный шаг не падает;
//  2. перепись объявлена с функцией состояния (`always()`/`!cancelled()`).
//     Условие без неё вычисляется с подразумеваемым `success()`, то есть
//     перепись промолчит ровно тогда, когда нужна;
//  3. перепись САМА НЕ ГАСИТСЯ отметкой. Шаг, гасимый тем, о чём он обязан
//     доложить, есть та же дыра одним уровнем выше;
//  4. перепись идёт ПОСЛЕ всех гасимых шагов. Раньше — и она прочтёт их как
//     «ещё не исполнялись», то есть уронит зелёный прогон;
//  5. у КАЖДОГО гасимого шага есть `id`. Шаг без него в контекст `steps` не
//     попадает вовсе — перепись его не видит и объявленным считать не может.
//
// Перечень объявленных вердиктных шагов ВЫВОДИТСЯ из объявления процесса (шаги,
// чьё условие читает отметку), а не выписывается рядом. Выписанный разошёлся бы
// молча — класс, который эта линия ловила четырежды.
package repohygiene

import (
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// skipVerdictFlag — отметка, гасящая шаги.
const skipVerdictFlag = "STAND_PRECONDITION_UNMET"

// skipVerdictOwner — единственный владелец переписи исходов. Имя, а не место:
// шаг зовёт его из тела, и признак — вызов, а не заголовок шага.
const skipVerdictOwner = "assert-declared-verdicts-ran.py"

// reStateFunction — функция состояния в условии шага. Без неё условие
// вычисляется с подразумеваемым `success()`.
var reStateFunction = regexp.MustCompile(`\b(always|!cancelled|cancelled|failure)\s*\(`)

// skipVerdictDoc — то немногое из workflow, что нужно этому гейту.
type skipVerdictDoc struct {
	Jobs map[string]struct {
		Steps []struct {
			Name string `yaml:"name"`
			ID   string `yaml:"id"`
			If   string `yaml:"if"`
			Run  string `yaml:"run"`
			Uses string `yaml:"uses"`
		} `yaml:"steps"`
	} `yaml:"jobs"`
}

// skipVerdictCensus — объём осмотренного. «Ноль находок» обязано быть отличимо
// от «ноль прочитанного».
type skipVerdictCensus struct {
	Files     int
	Jobs      int // работ с гашением
	Gated     int // гасимых шагов
	WithOwner int // работ, несущих перепись
	Exempt    int // сработавших послаблений
}

func (c *skipVerdictCensus) add(o skipVerdictCensus) {
	c.Files += o.Files
	c.Jobs += o.Jobs
	c.Gated += o.Gated
	c.WithOwner += o.WithOwner
	c.Exempt += o.Exempt
}

// skipVerdictExempt — работы, которым перепись ещё не провязана.
//
// Запись означает: предмет у работы ЖИВ, и его закрывает ДРУГОЙ держатель, чей
// механизм выбирает своя полоса. Это не разрешение оставить зелёное — это
// названная граница ЭТОГО гейта. Запись, которой нечего исключать, — находка:
// послабление обязано истекать само.
var skipVerdictExempt = map[[2]string]string{
	{"e2e-newman.yml", "shard"}: "работу чинит параллельная полоса (различение " +
		"контейнера, собранного из дерева, и контейнера, приезжающего пином внешнего " +
		"продукта); её файл эта полоса не трогает, и навязывать ей свой механизм " +
		"значило бы решить за неё. Снимается, когда работа `shard` начнёт звать " +
		"владельца переписи либо её полоса объявит своего держателя",
}

// checkSkipIsNotPass — находки одного файла плюс его перепись. Вынесено
// отдельно, чтобы обход доказывался инъекцией на синтетическом содержимом.
func checkSkipIsNotPass(path, raw string) ([]string, skipVerdictCensus, map[[2]string]bool) {
	census := skipVerdictCensus{Files: 1}
	hit := map[[2]string]bool{}

	var doc skipVerdictDoc
	if err := yaml.Unmarshal([]byte(raw), &doc); err != nil {
		return []string{path + ": не разобран YAML: " + err.Error() + " — файл НЕ проверен"},
			census, hit
	}

	var findings []string
	for name, job := range doc.Jobs {
		// ГАСИМЫЕ ШАГИ ВЫВОДЯТСЯ, А НЕ ВЫПИСЫВАЮТСЯ: гасимым считается шаг, чьё
		// условие ЧИТАЕТ отметку. Перечень имён пришлось бы дописывать ровно
		// тогда же, когда о новом шаге забывают.
		var gated []int
		ownerIdx := -1
		ownerIf, ownerName, ownerRun := "", "", ""
		for i, st := range job.Steps {
			if strings.Contains(st.If, skipVerdictFlag) {
				gated = append(gated, i)
			}
			if strings.Contains(st.Run, skipVerdictOwner) && ownerIdx < 0 {
				ownerIdx, ownerIf = i, st.If
				ownerName, ownerRun = st.Name, st.Run
			}
		}
		if len(gated) == 0 {
			continue
		}
		census.Jobs++
		census.Gated += len(gated)
		where := path + ": работа '" + name + "'"

		if reason, ok := skipVerdictExempt[[2]string{fileName(path), name}]; ok {
			hit[[2]string{fileName(path), name}] = true
			census.Exempt++
			if ownerIdx >= 0 {
				findings = append(findings, where+": послаблению нечего исключать — работа "+
					"УЖЕ зовёт владельца переписи `"+skipVerdictOwner+"` шагом #"+
					strconv.Itoa(ownerIdx+1)+". Снимите запись из skipVerdictExempt, "+
					"иначе она переживёт свой предмет (причина записи: "+reason+")")
			}
			continue
		}

		// ВИДИМОСТЬ ГАСИМОГО ШАГА — ЕГО `id`. Проверяется ПОСЛЕ послабления: у
		// освобождённой работы механизм исхода выбирает её собственная полоса, и
		// требовать `id` под НАШУ перепись значило бы навязать ей механизм.
		for _, i := range gated {
			st := job.Steps[i]
			if strings.TrimSpace(st.ID) == "" {
				findings = append(findings, where+": шаг #"+strconv.Itoa(i+1)+" («"+
					stepLabel(st.Name, st.Uses)+"») гасится отметкой "+skipVerdictFlag+
					" и не имеет `id`. Шаг без `id` в контекст `steps` не попадает вовсе — "+
					"перепись исходов его не видит и объявленным считать не может, "+
					"значит гарантия «объявленное исполнилось» на него не распространяется")
			}
		}

		if ownerIdx < 0 {
			findings = append(findings, where+": отметка "+skipVerdictFlag+" гасит "+
				strconv.Itoa(len(gated))+" шаг(ов), а переписи исходов в работе НЕТ. "+
				"Погашенный шаг не падает — он пропускается, и работа без упавших шагов "+
				"выходит `success`: отсутствие вердикта приходит в сводку тем же зелёным "+
				"кружком, что и «проверено, замечаний нет». Заведите последним шагом вызов "+
				"`"+skipVerdictOwner+"` под `always()`: он сверяет объявленное с исполненным "+
				"и роняет работу, когда объявленный вердиктный шаг результата не дал")
			continue
		}
		census.WithOwner++

		if !reStateFunction.MatchString(ownerIf) {
			findings = append(findings, where+": перепись исходов («"+ownerName+"», шаг #"+
				strconv.Itoa(ownerIdx+1)+") объявлена с условием `"+strings.TrimSpace(ownerIf)+
				"` — без функции состояния. Такое условие вычисляется с подразумеваемым "+
				"`success()`, то есть перепись промолчит ровно тогда, когда она и нужна")
		}
		if strings.Contains(ownerIf, skipVerdictFlag) {
			findings = append(findings, where+": перепись исходов («"+ownerName+"») ГАСИТСЯ "+
				"той самой отметкой, о которой обязана доложить. Это та же дыра одним "+
				"уровнем выше: она промолчит именно в своём случае")
		}
		if last := gated[len(gated)-1]; ownerIdx < last {
			findings = append(findings, where+": перепись исходов идёт шагом #"+
				strconv.Itoa(ownerIdx+1)+", то есть ДО последнего гасимого шага #"+
				strconv.Itoa(last+1)+". Она прочтёт ещё не исполнявшиеся шаги как "+
				"неисполнившиеся и уронит зелёный прогон")
		}
		// Вызов обязан НАЗЫВАТЬ свой предмет: без имени работы и пути к
		// объявлению владелец вывел бы перечень не той работы.
		for _, key := range []string{"--workflow", "--job", "--steps"} {
			if !strings.Contains(ownerRun, key) {
				findings = append(findings, where+": вызов переписи не передаёт `"+key+
					"` — владелец вывел бы перечень объявленных шагов не из того "+
					"объявления и молча измерил бы не тот предмет")
			}
		}
	}
	sort.Strings(findings)
	return findings, census, hit
}

// stepLabel — чем назвать шаг в находке.
func stepLabel(name, uses string) string {
	if s := strings.TrimSpace(name); s != "" {
		return s
	}
	if s := strings.TrimSpace(uses); s != "" {
		return s
	}
	return "без имени"
}

// fileName — последний сегмент пути; ключ послабления называет файл, а не путь.
func fileName(path string) string {
	if i := strings.LastIndex(path, "/"); i >= 0 {
		return path[i+1:]
	}
	return path
}
