// deferredwork.go — СВОЯ часть запрета «никакого тех-долга» (ban #11): корень
// обхода и виды вычитания.
//
// # Что здесь, а что в фундаменте
//
// Разбор — словарь форм отсрочки, образец, отсев по затравке, граница
// употребления и упоминания, обход и перепись — живёт в
// [github.com/PRO-Robotech/corelib/treehygiene]. До этого он лежал КОПИЕЙ в двух
// деревьях: платформа и служба доступа делили 99 строк кода из 186, а словарь
// совпадал по составу точно — двенадцать записей с обеих сторон.
//
// Держателя у этой одинаковости не было ни одного (ban #20, `polyrepo.md`
// §«Копия между репозиториями ЗАПРЕЩЕНА»), и совпадение содержимого нарушением
// не смягчалось, а ДОКАЗЫВАЛО его: разойтись копии обязаны были молча. Заведут в
// одном дереве тринадцатую форму — в другом её не будет, и написанное в ней
// окажется не находкой и не чистотой, а НЕВИДИМОСТЬЮ; ни сборка, ни гейт, ни
// обзор диффа этого не увидят, потому что каждое дерево по отдельности исправно.
//
// # Что осталось здесь — и почему именно это
//
// Ровно то, что есть утверждение об ЭТОМ дереве:
//
//   - КОРЕНЬ ОБХОДА — его даёт проба. Судить чужое дерево значило бы краснеть на
//     чужом, а в самостоятельном клоне соседа нет вовсе;
//   - ВИДЫ ВЫЧИТАНИЯ ([deferralSkips]) — перечень вычитаемого есть утверждение о
//     составе этого дерева, и проверяется он здесь же: вид, которому больше
//     нечего вычитать, роняет прогон (TestNoDeferredWorkInTheTree).
//
// Готовых видов фундамент не раздаёт намеренно: раздавая их, он утверждал бы о
// чужом дереве то, чего не измерял, и предикат «виду больше нечего вычитать»
// обессмыслился бы — под общим именем можно положить что угодно, и счёт не
// сдвинется.
//
// # Чего здесь НЕТ
//
// Перечня прощённых путей — ни закрытого, ни пустого. Уточнение предиката до
// формы обращения к читателю кода обнулило предмет всех четырёх прежних записей,
// и механизм снят целиком: пустой перечень есть приглашение дописать в него
// первую запись, а каждая запись — место, куда отсрочку вносят незамеченной.
//
// Вычета имени функции стандартной библиотеки здесь тоже нет, и это ЗАМЕР, а не
// упущение. Инъекция фундамента показала ту ветвь недостижимой: образец требует
// перед именем начала строки либо пробельного знака, а в вызове через точку
// перед ним стоит точка — совпадения не возникает вовсе, и до вычета дело не
// доходит ни при каком входе. Ветвь, которая не может исполниться, защитой не
// является: она есть её вид.
package repohygiene

import (
	"strings"

	"github.com/PRO-Robotech/corelib/treehygiene"
)

// deferralSkips — виды, вычитаемые из области обхода ЭТОГО дерева.
//
// Вычитается ровно то, что судить нельзя ПО СУЩЕСТВУ, а не то, что неудобно:
// фикстура гейта обязана уметь написать форму дефекта, иначе гейт нельзя
// проверить инъекцией, а маркер в сгенерированном принадлежит генератору.
//
// Каждый вид несёт предмет, и предмет проверяется: обход считает вычтенное
// поштучно, а гейт роняет прогон на виде, которому больше нечего вычитать. Вид
// без предмета — слепая зона, которую унаследует следующий: под его именем можно
// положить что угодно, и счёт не сдвинется.
var deferralSkips = []treehygiene.DeferralSkip{
	{
		Name:  "тестовый корпус",
		Why:   "фикстура гейта обязана уметь написать форму дефекта — иначе гейт не проверить инъекцией",
		Match: func(s string) bool { return strings.HasSuffix(s, "_test.go") },
	},
	{
		Name:  "тестовые данные",
		Why:   "вход проб, а не код: маркер там принадлежит сценарию, а не продукту",
		Match: func(s string) bool { return strings.Contains(s, "/testdata/") },
	},
	{
		Name:  "сгенерированное",
		Why:   "маркеры принадлежат генератору, а не автору дерева",
		Match: func(s string) bool { return strings.HasPrefix(s, "pkg/api/") },
	},
}

// auditDeferredWork — обход ЭТОГО дерева: корень плюс виды вычитания.
//
// Провязка держится одним местом намеренно: вызывающий не может позвать разбор,
// забыв виды вычитания, — а позвав, покраснел бы на собственных фикстурах.
func auditDeferredWork(root string) (
	[]treehygiene.DeferralFinding, treehygiene.DeferralCensus, error) {
	return treehygiene.AuditDeferredWork(root, deferralSkips)
}
