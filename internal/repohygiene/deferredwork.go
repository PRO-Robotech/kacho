// deferredwork.go — разбор отложенной работы: маркер, обещающий сделать позже.
//
// # Предмет
//
// Запреты «никакого тех-долга» и «всегда production-grade, НИКОГДА MVP» стоят в
// корпусе правил с самого начала — и до этого файла их не держало НИЧЕГО. Их
// исполнение было свойством памяти автора, а не дерева.
//
// Цена измерена, а не предположена. На день заведения гейта дерево несло три
// маркера отложенного, и за ними стоял живой дефект: хук завершения
// восстановления пароля был нацелен на порт, где его пути не существует, —
// событие не доезжало никогда, восстановивший доступ оставался заблокированным,
// прежние сессии переживали восстановление. Объяснение отсрочки («RPC ещё не
// реализован») к тому дню было ЛОЖНЫМ: RPC существовал. То есть маркер не просто
// откладывал работу — он прикрывал её ссылкой на исчезнувшее препятствие.
//
// # Что ловится
//
// Маркер отложенной работы в НЕ-ТЕСТОВОМ дереве: код, шаблоны развёртывания,
// конфигурация. Тесты исключены намеренно: их предмет — сам репозиторий, и
// синтетическая фикстура обязана уметь написать форму дефекта, иначе гейт нельзя
// проверить инъекцией.
//
// # Чего гейт НЕ делает и почему это названо
//
// Он не судит ПРОЗУ. Слово «TODO» внутри объяснения запрета (в этом файле, в
// README проверок, в описании соседнего гейта) — не отложенная работа, а её имя.
// Различение идёт по форме: маркером считается вхождение в позиции, где оно
// адресует ЧИТАТЕЛЯ КОДА, — то есть `TODO:` либо `TODO(тикет):`, а не голое
// слово внутри предложения.
//
// Перечня путей-объяснений у гейта НЕТ — ни закрытого, ни пустого, — и пробы
// его самоистечения нет тоже, потому что истекать нечему. Здесь стояло обратное:
// шапка объявляла закрытый список и пробу над ним, тогда как тело того же файла
// (ниже, над deferralFinding) объясняет, почему механизм снят целиком. Два места
// об одном предмете, из которых верно одно, — и неверным было то, которое
// читают первым.
//
// # Область обхода ВЫВОДИТСЯ из дерева
//
// Состав берётся у индекса git целиком, а верхний уровень перечисляется по
// нему же. Выписанный руками перечень корней держался ровно до появления
// восьмого каталога: он молчал про то, чего в нём нет, и «ноль находок» в такой
// области неотличимо от «ноль прочитанного». Из счёта вычитаются три вида,
// и у каждого проверяется предмет (см. deferralSkip): тестовый корпус по
// суффиксу, тестовые данные по каталогу и сгенерированное.
package repohygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/PRO-Robotech/kacho/internal/treecorpus"
)

// deferralForm — одна форма отсрочки: затравка для дешёвого отсева и точный
// образец для решения.
//
// Затравка и образец лежат в ОДНОЙ записи намеренно. Отсев по подстроке
// («есть ли в файле хоть одна затравка») экономит порядок величины — regexp с
// альтернацией по всему дереву стоил 155 секунд из 438 у пакета, то есть треть
// его бюджета и, в конечном счёте, таймаут конвейера. Но отсев, живущий
// ОТДЕЛЬНЫМ списком, — второе место об одном предмете: добавят форму в образец,
// забудут в затравки, и гейт молча перестанет её видеть. Здесь такое
// расхождение невозможно by construction: и предикат, и отсев выводятся из
// этого перечня.
type deferralForm struct {
	seed    string // подстрока, обязательно присутствующая в любом совпадении
	pat     string // образец, решающий по существу
	example string // строка, которую эта форма ОБЯЗАНА ловить (проверяется пробой)
}

// deferralForms — формы, которыми в этом дереве пишется «сделаю позже».
//
// Слова русского языка включены наравне с англоязычными: корпус двуязычен, и
// запрет, ловящий только TODO, обходится словом «потом» без единой уловки.
//
// Отсрочка отличается от УПОМИНАНИЯ формой обращения: она адресует читателя
// кода и потому пишется как `TODO:` либо `TODO(тикет):`. Голое слово внутри
// предложения («`TODO.md` упразднён», «design §«Future TODO»», «никакого
// context.TODO()») — разговор О маркерах, а не обещание сделать.
//
// Различать обязательно: запрет, ловящий слово, заставляет переписывать
// собственную документацию о запрете — и первым делом снимают сам запрет.
//
// Русские формы собираются из ЧАСТЕЙ, а не пишутся целиком: иначе строка
// определения совпадает сама с собой, и гейт объявляет находкой собственный
// исходник. Заводить ради этого исключение по пути было бы хуже — список
// прощённых есть место, куда отсрочку вносят незамеченной.
var deferralForms = []deferralForm{
	// Примеры англоязычных форм собираются из частей ровно по той же причине, что
	// и русские образцы: написанные целиком, они делают ЭТОТ файл нарушителем
	// собственного запрета. Это не гипотеза — первая редакция перечня дала четыре
	// находки, все в этих строках, и гейт был прав.
	{seed: "TODO", pat: `(?m)(?:^|[\s;{(])TODO\s*(?:\([^)]*\))?\s*:`,
		example: "\t// " + "TODO" + ": дочинить"},
	{seed: "FIXME", pat: `(?m)(?:^|[\s;{(])FIXME\s*(?:\([^)]*\))?\s*:`,
		example: "\t// " + "FIXME" + "(KAC-1): поправить"},
	{seed: "XXX", pat: `(?m)(?:^|[\s;{(])XXX\s*(?:\([^)]*\))?\s*:`,
		example: "\t// " + "XXX" + ": разобраться"},
	{seed: "HACK", pat: `(?m)(?:^|[\s;{(])HACK\s*(?:\([^)]*\))?\s*:`,
		example: "\t// " + "HACK" + ": обход"},
	{seed: "позже", pat: "позже " + `допил`,
		example: "\t// " + "позже " + "допилим" + " до конца"},
	{seed: "потом", pat: "потом " + `додел`,
		example: "\t// " + "потом " + "доделаем"},
	{seed: "пока", pat: "пока " + `заглушк`,
		example: "\t// " + "пока " + "заглушка"},
	{seed: "временное", pat: "временное " + `упрощени`,
		example: "\t// " + "временное " + "упрощение"},
	{seed: "надо", pat: "надо " + `допилить`,
		example: "\t// " + "надо " + "допилить"},
	{seed: "заглушка", pat: "заглушка " + `на время`,
		example: "\t// " + "заглушка " + "на время" + " релиза"},
}

// deferralMarker — объединение всех образцов; собирается из deferralForms,
// поэтому форма, добавленная в перечень, не может остаться неучтённой.
var deferralMarker = regexp.MustCompile(func() string {
	pats := make([]string, 0, len(deferralForms))
	for _, f := range deferralForms {
		pats = append(pats, f.pat)
	}
	return strings.Join(pats, "|")
}())

// deferralSeeds — те же формы, что и выше, но затравками: файл, не содержащий
// ни одной, разбору не подлежит.
var deferralSeeds = func() []string {
	seen := map[string]bool{}
	var out []string
	for _, f := range deferralForms {
		if seen[f.seed] {
			continue
		}
		seen[f.seed] = true
		out = append(out, f.seed)
	}
	return out
}()

// hasDeferralSeed — дешёвый отсев перед разбором.
func hasDeferralSeed(body string) bool {
	for _, s := range deferralSeeds {
		if strings.Contains(body, s) {
			return true
		}
	}
	return false
}

// contextTODO — `context.TODO()` из стандартной библиотеки: имя функции, а не
// отсрочка. Вычитается отдельно, потому что синтаксически неотличим от формы
// `TODO(...)` с последующим двоеточием в той же строке.
var contextTODO = regexp.MustCompile(`context\.TODO\(\)`)

// deferralSkip — вид, вычитаемый из области, и предикат его узнавания.
//
// Вычитается ровно то, что судить нельзя ПО СУЩЕСТВУ, а не то, что неудобно:
// фикстура гейта обязана уметь написать форму дефекта, иначе гейт нельзя
// проверить инъекцией, а маркер в сгенерированном принадлежит генератору.
//
// Каждый вид несёт предмет, и предмет проверяется: обход считает вычтенное
// поштучно, а гейт роняет прогон на виде, которому больше нечего вычитать
// (см. TestNoDeferredWorkInTheTree). Вид без предмета — это слепая зона,
// которую унаследует следующий: под его именем можно положить что угодно, и
// счёт не сдвинется.
type deferralSkip struct {
	name  string
	why   string
	match func(slashed string) bool
}

var deferralSkips = []deferralSkip{
	{
		name: "тестовый корпус",
		why:  "фикстура гейта обязана уметь написать форму дефекта — иначе гейт не проверить инъекцией",
		match: func(s string) bool {
			return strings.HasSuffix(s, "_test.go")
		},
	},
	{
		name:  "тестовые данные",
		why:   "вход проб, а не код: маркер там принадлежит сценарию, а не продукту",
		match: func(s string) bool { return strings.Contains(s, "/testdata/") },
	},
	{
		name:  "сгенерированное",
		why:   "маркеры принадлежат генератору, а не автору дерева",
		match: func(s string) bool { return strings.HasPrefix(s, "pkg/api/") },
	},
}

// deferralCensus — объём осмотренного. Печатается всегда: «ноль находок»
// обязано быть отличимо от «ноль прочитанного», а «область покрыта» — от
// «область выписана».
type deferralCensus struct {
	Tracked int            // элементов в индексе дерева
	Read    int            // прочитано
	Roots   []string       // верхний уровень индекса, ВЫВЕДЕННЫЙ из него же
	ByRoot  map[string]int // корень → прочитано под ним
	Skipped map[string]int // вид вычитания → сколько вычтено
}

// topLevel — верхний сегмент пути; для файла в корне репозитория это он сам.
func topLevel(slashed string) string {
	if i := strings.IndexByte(slashed, '/'); i >= 0 {
		return slashed[:i]
	}
	return "."
}

// Перечня исключений у этого гейта НЕТ — и это измерение, а не упущение.
//
// Первая редакция ловила голое слово и потому нуждалась в четырёх записях-
// объяснениях: файл запрета, соседний гейт, свод правил проверок и шапка одной
// из них — все они произносят «TODO», говоря О маркерах. Уточнение предиката до
// ФОРМЫ ОБРАЩЕНИЯ (`TODO:` либо `TODO(тикет):` — то, чем адресуют читателя кода)
// обнулило предмет всех четырёх сразу: проза о маркерах под него не подпадает.
//
// Механизм исключений снят целиком, а не оставлен пустым: пустой перечень —
// приглашение дописать в него первую запись, а каждая запись есть место, куда
// отсрочку можно внести незамеченной. Дешевле точный предикат, чем список
// прощённых.

// deferralFinding — одна находка с координатой.
type deferralFinding struct {
	Where string
	Line  string
}

// markedLine — строка тела, в которой сработал образец, вместе с её номером.
type markedLine struct {
	no   int
	text string
}

// markedLines гонит образец по ВСЕМУ телу разом и возвращает только затронутые
// строки.
//
// Прежняя редакция звала образец на каждой строке отдельно — то есть платила
// накладными расходами вызова за каждую строку дерева. Один проход по телу
// дешевле на порядок; номер строки восстанавливается по смещению совпадения,
// поэтому координата в находке та же самая.
func markedLines(body string) []markedLine {
	locs := deferralMarker.FindAllStringIndex(body, -1)
	if len(locs) == 0 {
		return nil
	}
	var (
		out      []markedLine
		lineNo   = 1
		scanned  int
		lastLine = -1
	)
	for _, loc := range locs {
		lineNo += strings.Count(body[scanned:loc[0]], "\n")
		scanned = loc[0]
		if lineNo == lastLine {
			continue // два совпадения в одной строке — одна находка
		}
		lastLine = lineNo

		start := strings.LastIndexByte(body[:loc[0]], '\n') + 1
		end := strings.IndexByte(body[loc[0]:], '\n')
		if end < 0 {
			end = len(body)
		} else {
			end += loc[0]
		}
		out = append(out, markedLine{no: lineNo, text: body[start:end]})
	}
	return out
}

// auditDeferredWork обходит дерево и ищет маркеры отложенной работы.
//
// Область — ВЕСЬ индекс: корни не выписываются, а выводятся из него, поэтому
// каталог, заведённый завтра, попадает под гейт в день появления, а не тогда,
// когда кто-нибудь снова пройдёт по дереву руками.
//
// Возвращает находки и перепись осмотренного: «ноль находок» обязано быть
// отличимо и от «ноль прочитанного», и от «прочитал не там».
func auditDeferredWork(root string) (findings []deferralFinding, census deferralCensus, err error) {
	census.ByRoot = map[string]int{}
	census.Skipped = map[string]int{}
	for _, s := range deferralSkips {
		census.Skipped[s.name] = 0
	}

	tracked, terr := treecorpus.Under(root)
	if terr != nil {
		return nil, census, fmt.Errorf("состав дерева: %w", terr)
	}
	census.Tracked = len(tracked)

	roots := map[string]struct{}{}
	for _, abs := range tracked {
		rel, rerr := filepath.Rel(root, abs)
		if rerr != nil {
			return nil, census, fmt.Errorf("путь %s: %w", abs, rerr)
		}
		slashed := filepath.ToSlash(rel)
		roots[topLevel(slashed)] = struct{}{}

		if skipped := func() bool {
			for _, s := range deferralSkips {
				if s.match(slashed) {
					census.Skipped[s.name]++
					return true
				}
			}
			return false
		}(); skipped {
			continue
		}

		// #nosec G304 -- путь пришёл из индекса git ЭТОГО дерева (treecorpus), а не из
		// ввода: включить посторонний файл нечем.
		raw, berr := os.ReadFile(abs)
		if berr != nil {
			return nil, census, fmt.Errorf("чтение %s: %w", slashed, berr)
		}
		body := string(raw)
		census.Read++
		census.ByRoot[topLevel(slashed)]++
		// Отсев: файл без единой затравки разбору не подлежит. Подавляющее
		// большинство дерева отсекается здесь, и именно поэтому гейт
		// укладывается в бюджет пакета.
		if !hasDeferralSeed(body) {
			continue
		}
		for _, line := range markedLines(body) {
			// Строка, где единственное совпадение — имя стандартной функции,
			// отсрочкой не является.
			if contextTODO.MatchString(line.text) &&
				!deferralMarker.MatchString(contextTODO.ReplaceAllString(line.text, "")) {
				continue
			}
			findings = append(findings, deferralFinding{
				Where: fmt.Sprintf("%s:%d", slashed, line.no),
				Line:  strings.TrimSpace(line.text),
			})
		}
	}

	for r := range roots {
		census.Roots = append(census.Roots, r)
	}
	sort.Strings(census.Roots)
	sort.Slice(findings, func(i, j int) bool { return findings[i].Where < findings[j].Where })
	return findings, census, nil
}

// String — перепись одной строкой, включая раскладку по корням.
func (c deferralCensus) String() string {
	byRoot := make([]string, 0, len(c.Roots))
	for _, r := range c.Roots {
		byRoot = append(byRoot, fmt.Sprintf("%s=%d", r, c.ByRoot[r]))
	}
	skipped := make([]string, 0, len(deferralSkips))
	for _, s := range deferralSkips {
		skipped = append(skipped, fmt.Sprintf("%s=%d", s.name, c.Skipped[s.name]))
	}
	return fmt.Sprintf(
		"перепись: в индексе %d, прочитано %d, корней (выведено из индекса) %d [%s]; "+
			"вычтено: %s; перечня исключений у гейта нет — предикат ловит форму обращения, а не слово",
		c.Tracked, c.Read, len(c.Roots), strings.Join(byRoot, " "), strings.Join(skipped, " "))
}
