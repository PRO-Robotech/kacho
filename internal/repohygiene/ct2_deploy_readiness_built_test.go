// Каждый сервис СТРОИТ готовность, а не подставляет в её слот живость.
//
// # ПРЕДМЕТ
//
// Живость отвечает «процесс жив»; готовность — «процесс МОЖЕТ ОБСЛУЖИВАТЬ»: база
// отвечает, соседи достижимы, исполнитель операций поднят. Подставив живость в
// слот готовности, получаем под, объявляющий себя готовым до того, как способен
// ответить, — и трафик, приходящий в отказ. Различие видно арендатору: он
// получает отказ там, где ждал бы ожидания, а дежурному в три часа ночи нечем
// отличить «сломан продукт» от «не создано условие».
//
// # ПОЧЕМУ ГЕЙТ, А НЕ ОБЗОР
//
// Дефект не виден в диффе by construction: у сервиса без готовности НЕТ строки,
// которая была бы написана неверно, — есть строка, которой нет. Замер на день
// заведения (задача продукта #1655): сервисов семь, готовность строили четыре;
// storage отвечал безусловным `/healthz`, registry — тоже, geo обслуживал только
// `/metrics`. Все три при этом рапортовали Ready.
//
// # ПАРА С СОСЕДНИМ ГЕЙТОМ, И ПОРЯДОК МЕЖДУ НИМИ ЗНАЧИМ
//
// `TestReadinessProbeAsksWhatTheServiceActuallyServes` сверяет ВТОРУЮ полосу: что
// чарт пробирует то, что сервис отдаёт. Он молчит о сервисе, который `/readyz` не
// отдаёт вовсе, — и это верно для него, но оставляет утверждение односторонним:
// сними завтра готовность у сервиса, и тот гейт ЗАМОЛЧИТ вместо того чтобы
// покраснеть (`testing.md` §«Гейт на класс», п.9 — негативное утверждение теряет
// вход и не выдаёт себя ничем). Этот гейт — его положительная половина: он требует
// готовность от КАЖДОГО сервиса, поэтому её исчезновение краснеет здесь.
func TestEveryServiceBuildsReadinessRatherThanServingLiveness(t *testing.T) {
	root := repoRoot(t)

	var rels []string
	for _, abs := range trackedGoFiles(t, filepath.Join(root, "services")) {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			t.Fatalf("относительный путь %s: %v", abs, err)
		}
		rels = append(rels, filepath.ToSlash(rel))
	}
	sort.Strings(rels)
	if len(rels) == 0 {
		t.Fatal("предпосылка гейта не выполняется: не-тестовых файлов Go под services/ в индексе " +
			"НОЛЬ — обход смотрит не туда; чинить надо гейт, а не молча выходить успехом")
	}

	findings, cen, err := auditReadinessBuilt(root, rels)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// Предпосылка: «ноль находок» обязано быть отличимо от «ноль прочитанного».
	if cen.FilesRead == 0 {
		t.Fatal("разобрано ноль файлов Go — полоса «что сервис обслуживает» не построена")
	}
	if cen.Services == 0 {
		t.Fatal("обход не нашёл ни одного сервиса — гейт не утверждает ничего")
	}
	if cen.WithMetrics == 0 {
		t.Fatalf("ни один из %d сервисов не поднимает диагностической поверхности — либо дерево "+
			"её лишилось, либо разбор перестал её видеть; и то и другое находка", cen.Services)
	}

	for _, f := range findings {
		t.Errorf("%s: %s", f.Service, f.Why)
	}

	t.Logf("перепись: сервисов %d · поднимают диагностику %d · отдают %s %d · строят именованные "+
		"зависимости %d · файлов Go разобрано %d",
		cen.Services, cen.WithMetrics, routeReady, cen.ServingReady, cen.WithNamedDeps, cen.FilesRead)

	if t.Failed() {
		t.Logf("готовность строится набором ИМЕНОВАННЫХ проверок зависимостей и отдаётся отдельным "+
			"путём от живости; общий носитель — %s", strings.TrimSpace("pkg/observability/health"))
	}
}

// Слот ЖИВОСТИ не спрашивает вопрос ГОТОВНОСТИ — ни в одном шаблоне
// развёртывания дерева.
//
// # ПРЕДМЕТ
//
// Зеркало #1655 и ломает оно иначе. Живость в слоте готовности даёт под,
// рапортующий Ready, когда обслуживать не может. Обратная подмена даёт шторм
// перезапусков: блип зависимости читается как смерть процесса, каждая реплика
// уходит в рестарт по внешней причине, которая прошла бы сама, и восстановление
// откладывается ровно тем, что должно было помочь.
//
// # ПОЧЕМУ ПРЕВЕНТИВНО, И ЭТО СКАЗАНО ПРЯМО
//
// Сегодня находок ноль: все девять шаблонов спрашивают живость `/healthz`. Гейт
// заводится вместе с изменением, которое ВПЕРВЫЕ дало трём сервисам два разных
// ответа на диагностической поверхности, — то есть вместе с появлением
// возможности перепутать их местами. Способность упасть доказывается инъекцией
// (`ct2_deploy_readiness_built_injection_test.go`), а не тем, что дерево сегодня
// чисто: «проверка не нашла» и «проверке нечего искать» печатают один и тот же
// ноль (`testing.md` §«Гейт на класс», п.9), и различает их только перепись.
func TestLivenessSlotNeverAsksTheReadinessQuestion(t *testing.T) {
	root := repoRoot(t)

	charts := deploymentTemplates(t, root)
	var rels []string
	for _, paths := range charts {
		for _, abs := range paths {
			rel, err := filepath.Rel(root, abs)
			if err != nil {
				t.Fatalf("относительный путь %s: %v", abs, err)
			}
			rels = append(rels, filepath.ToSlash(rel))
		}
	}
	sort.Strings(rels)
	if len(rels) == 0 {
		t.Fatal("предпосылка гейта не выполняется: шаблонов развёртывания в дереве НОЛЬ — " +
			"обход смотрит не туда; чинить надо гейт, а не молча выходить успехом")
	}

	findings, cen, err := auditLivenessSlotStaysLiveness(root, rels)
	if err != nil {
		t.Fatalf("обход шаблонов: %v", err)
	}
	if cen.Templates == 0 {
		t.Fatal("прочитано ноль шаблонов — гейт не утверждает ничего")
	}
	// Положительный контроль: отрицание («живость не спрашивает готовность»)
	// выполняется тривиально на дереве, где слота живости нет ни у кого, и на
	// дереве, где готовность не спрашивает никто. Без этой пары гейт зеленел бы
	// на сломанном.
	if cen.WithLiveSlot == 0 {
		t.Fatal("ни один шаблон не несёт слота живости — отрицание выполнялось бы тривиально")
	}
	if cen.WithReadySlot == 0 {
		t.Fatal("ни один шаблон не спрашивает готовность по /readyz — либо дерево её лишилось, " +
			"либо разбор перестал её видеть; и то и другое находка")
	}

	for _, f := range findings {
		t.Errorf("%s: %s", f.Template, f.Why)
	}

	t.Logf("перепись: шаблонов %d · спрашивают готовность по %s %d · несут слот живости %d · "+
		"живость спрашивает готовность %d · строк-комментариев снято до разбора %d",
		cen.Templates, routeReady, cen.WithReadySlot, cen.WithLiveSlot, cen.LiveAsksReady, cen.CommentsPruned)
}
