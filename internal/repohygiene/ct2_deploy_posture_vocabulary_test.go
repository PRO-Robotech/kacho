// Словарь допустимых значений посадки объявлен В ДЕРЕВЕ ОДИН РАЗ.
//
// # ПРЕДМЕТ
//
// «Какое написание считать посадкой» — правило безопасности: от него зависит,
// сработает ли страж старта, сузится ли круг отправителей чужой личности,
// потребуется ли проверяемый транспорт. Пока словарь объявлен у каждого сервиса
// своими руками, это не «второе место вызова», а второй ИСТОЧНИК: копии
// перечисляют написания сами, сойтись им нечем, и расходятся они молча.
//
// # ПОЧЕМУ ГЕЙТ, А НЕ ОБЗОР
//
// Замер на день заведения (задача продукта #1656): объявлений было ПЯТЬ, и одно
// расходилось с остальными В ОБЕ СТОРОНЫ — принимало написания, которых не
// принимал никто (`prod`, `development`, пустая строка), и отвергало
// `production-strict`, в котором работали шестеро. Обзор диффа этого не видит by
// construction: каждая копия по отдельности написана верно, а неверна их РАЗНИЦА,
// и увидеть её можно было только на выкатке — двумя противоположными поломками
// сразу.
//
// # ЧТО ГЕЙТ СУДИТ, А ЧТО НЕТ
//
// Судит СТРОКОВЫЙ ЛИТЕРАЛ разобранного дерева. Комментарий, называющий посадки,
// законен и остаётся: поиск по подстроке краснел бы на собственном объяснении
// гейта. Текст отказа тоже законен — он одна строка целиком и ни одному написанию
// не равен.
//
// НЕ судит, ЧТО вызывающий делает с ответом разбора. Свой перечень посадок у
// сервиса законен; незаконны свои ПИСЬМЕНА для них.
func TestPostureVocabularyHasASingleSource(t *testing.T) {
	root := repoRoot(t)

	var files []string
	for _, sub := range []string{"services", "gateway", "pkg", "internal", "tools", "terraform"} {
		for _, abs := range trackedGoFiles(t, filepath.Join(root, sub)) {
			rel, err := filepath.Rel(root, abs)
			if err != nil {
				t.Fatalf("относительный путь %s: %v", abs, err)
			}
			files = append(files, filepath.ToSlash(rel))
		}
	}
	sort.Strings(files)
	if len(files) == 0 {
		t.Fatal("предпосылка гейта не выполняется: не-тестовых файлов Go в индексе НОЛЬ — " +
			"обход смотрит не туда; чинить надо гейт, а не молча выходить успехом")
	}

	findings, cen, err := auditPostureVocabularySingleSource(root, files)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// Предпосылки. «Ноль находок» обязано быть отличимо от «ноль прочитанного», а
	// «дом на месте» — от «дом переехал, и распознаватель ослеп на всё дерево».
	if cen.FilesRead == 0 {
		t.Fatal("разобрано ноль файлов Go — вердикт беспредметен")
	}
	if cen.HomeFiles == 0 {
		t.Fatalf("в %s не нашлось ни одного файла со словарём посадок — дом переехал либо разбор "+
			"перестал его видеть; и то и другое находка, а не повод молчать", postureHomeDir)
	}
	// Положительный контроль на распознаватель: каждое написание, объявленное
	// домом, обязано быть НАЙДЕНО хотя бы раз. Иначе «ноль находок» означало бы,
	// что гейт не узнаёт словарь вовсе.
	for _, mode := range servicecontract.Modes() {
		if cen.ByValue[mode] == 0 {
			t.Errorf("написание %q не встретилось в дереве НИ РАЗУ, хотя объявлено домом — "+
				"распознаватель словаря ослеп, и молчание гейта ничего не значит", mode)
		}
	}

	for _, f := range findings {
		t.Errorf("%s: словарь посадок объявлен вне общего дома (%s) — перечисляет %s. Страж старта "+
			"обязан читать ОДИН словарь: пока копии перечисляют написания сами, сойтись им нечем, "+
			"и разница выходит наружу двумя противоположными поломками — «ужесточить флот» роняет "+
			"одних, «написать алиас» роняет других. Спрашивайте servicecontract.ParseMode, а перечень "+
			"для текста отказа берите у servicecontract.Modes",
			f.Where, postureHomeDir, strings.Join(f.Values, ", "))
	}

	t.Logf("перепись: файлов Go разобрано %d · файлов дома со словарём %d · литералов словаря "+
		"по дереву %d · по написаниям %v · объявлений вне дома %d",
		cen.FilesRead, cen.HomeFiles, cen.LiteralsSeen, cen.ByValue, len(findings))
}
