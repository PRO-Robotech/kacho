// listcursorindex_test.go — репо-широкий гейт задачи #708: КАЖДОЕ курсорное
// чтение страницы обязано получать порядок из индекса.
//
// # Почему гейт, а не перепись
//
// Перепись находит то, что есть сегодня. Расхождение направления (`объявлено
// created_at DESC` при обходе `created_at ASC`) читается как сделанная работа:
// ревизия видит правильный составной индекс с нужными колонками и идёт дальше.
// Найтись оно может только сплошным чтением миграций — то есть один раз, руками,
// и следующая таблица заведётся с тем же расхождением.
//
// # Что здесь утверждается
//
// Разбор (`listcursorindex.go`) сводит две стороны:
//
//   - обход — `ORDER BY` курсорных чтений прод-кода;
//   - объявление — индексы, дожившие до конца цепочки миграций сервиса.
//
// Пара «(сервис, таблица) × подпись порядка», у которой служащего индекса нет, —
// находка. Направление входит в сравнение: btree читается в обе стороны, поэтому
// целиком инвертированный индекс засчитывается, а СМЕШАННЫЙ — нет.
//
// Способность гейта упасть и смолчать доказана инъекцией в обе стороны на
// синтетическом дереве — `listcursorindex_injection_test.go`.
package repohygiene

import (
	"fmt"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

// TestEveryCursorPageReadGetsItsOrderFromAnIndex — сам гейт.
func TestEveryCursorPageReadGetsItsOrderFromAnIndex(t *testing.T) {
	// Состав дерева берётся у ИНДЕКСА git, а не обходом диска: под `services/`
	// и `gateway/` на машине, где поднимали стенд, лежат игнорируемые каталоги,
	// и вердикт стал бы свойством рабочего каталога, а не коммита.
	tree, err := treecorpus.NewTree(repoRoot(t))
	if err != nil {
		t.Fatalf("состав дерева: %v", err)
	}

	c, err := SurveyCursorIndexes(tree)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// Объём осмотренного печатается ВСЕГДА: «ноль находок» обязано быть отличимо
	// от «ноль прочитанного».
	t.Logf("перепись: сервисов %d · миграций %d · живых таблиц %d · индексов %d · "+
		"файлов Go %d · строковых литералов %d · курсорных чтений %d · "+
		"пар (сервис,таблица)×подпись %d · покрыто %d · находок %d",
		len(c.Services), c.SQLFiles, c.LiveTables, c.Indexes,
		c.GoFiles, c.GoLiterals, len(c.Reads), c.Pairs, c.Covered, len(c.Findings))

	// Предпосылка гейта: ему есть что рассматривать. Пустая перепись означает не
	// «чисто», а «разбор перестал видеть предмет» — например, репозитории
	// переехали, или форма запроса сменилась.
	if len(c.Services) == 0 || c.SQLFiles == 0 {
		t.Fatalf("миграций не прочитано (сервисов %d, файлов %d) — гейт не утверждал бы ничего",
			len(c.Services), c.SQLFiles)
	}
	if c.Pairs == 0 {
		t.Fatalf("курсорных чтений не найдено при %d прочитанных файлах Go — "+
			"либо разбор ослеп, либо пагинация сменила форму; и то и другое надо чинить, а не зеленить",
			c.GoFiles)
	}

	// Чтение, чью таблицу назвать нечем, — не «пропустим»: это ровно тот случай,
	// на котором замер задачи #708 потерял семь таблиц. Требуется объявление
	// рядом с чтением.
	for _, r := range c.Unresolved {
		t.Errorf("%s:%d — курсорное чтение `ORDER BY %s`, но имя таблицы в запросе не названо "+
			"(вычисляется в Go). Поставь рядом объявление `cursor-list-table: <таблица>`, "+
			"иначе индекс под этот обход никем не проверяется",
			r.File, r.Line, cursorSignature(r.Keys))
	}

	for _, f := range c.Findings {
		var b strings.Builder
		fmt.Fprintf(&b, "%s.%s — обход `ORDER BY %s` не получает порядок из индекса.\n",
			f.Service, f.Table, f.Order)
		for _, r := range f.Reads {
			fmt.Fprintf(&b, "    чтение: %s:%d\n", r.File, r.Line)
		}
		if len(f.Candidates) == 0 {
			b.WriteString("    индексов с колонкой created_at у таблицы нет вовсе — нужен новый\n")
		} else {
			b.WriteString("    есть индексы с created_at (сверь ПОРЯДОК колонок и НАПРАВЛЕНИЕ):\n")
			for _, ix := range f.Candidates {
				fmt.Fprintf(&b, "      %s\n", ix)
			}
		}
		b.WriteString("    нужен полный (не частичный) btree, где ключи курсора идут подряд, " +
			"им предшествует не более одной колонки равенства, а направление совпадает целиком " +
			"либо инвертировано целиком")
		t.Error(b.String())
	}
}
