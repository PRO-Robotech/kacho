// TestGuaranteedPayloadFloorIsOnePlace — обещание продукта о полезной нагрузке
// кадра живёт в дереве ОДНИМ объявлением, его читает прод-код, и число, которым
// его называет документация, совпадает с этим объявлением.
//
// Что делать, если гейт сработал, — исходов три, четвёртого нет:
//
//  1. документация отстала -> привести её число к объявленному (оба напечатаны);
//  2. объявление отстало -> поднять его и ПЕРЕСМОТРЕТЬ обещание: величина
//     адресована арендатору, поэтому её снижение — продуктовое решение, а не
//     правка константы;
//  3. число рассыпалось по копиям (литерал, второе объявление) -> свести к одному
//     объявлению и сослаться на него.
//
// Чего делать нельзя: снимать гейт «потому что документация и код — разные
// предметы». Они разные ровно до того дня, когда продукт пообещал арендатору
// число; с этого дня они два места об одном.
func TestGuaranteedPayloadFloorIsOnePlace(t *testing.T) {
	root := repoRoot(t)
	findings, census, err := auditGuaranteedPayloadFloor(root)
	if err != nil {
		t.Fatalf("перепись дерева: %v", err)
	}
	t.Log(census)

	// Предпосылка переписи: пустой корпус — отказ, а не пустой успех. Ноль
	// прочитанных файлов дал бы «ноль расхождений» на непрочитанном.
	if census.GoFilesParsed == 0 || census.DocFilesRead == 0 {
		t.Fatalf("корпус пуст — смотреть было не на что: %s", census)
	}
	if len(findings) == 0 {
		return
	}
	var b strings.Builder
	for _, f := range findings {
		b.WriteString("  " + f.String() + "\n")
	}
	t.Fatalf("обещание продукта разошлось со своим объявлением (%d):\n%s\n%s",
		len(findings), b.String(), census)
}
