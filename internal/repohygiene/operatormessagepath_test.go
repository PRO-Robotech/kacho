// operatormessagepath_test.go — координата, названная ОПЕРАТОРУ в момент отказа,
// обязана существовать в дереве.
//
// # Предмет
//
// Хук отправки останавливает ветку и печатает, что делать дальше: «объявите слом
// там, где он объявляется (<путь>)». Оператор идёт по названному пути. Если путь
// неверен, происходит не «он поищет ещё» — происходит хуже: пустой ответ читается
// как ОТВЕТ. Поиск по несуществующей координате возвращает ноль строк, и ноль
// строк неотличим от «записей нет», а из «записей нет» следует вывод, которого
// делать было нельзя.
//
// Наблюдалось 2026-08-19 и стоило круга работы. Хук назвал `proto/breaking-declared.txt`
// при живом `proto/declared-breaks.yaml`. Исполнитель грепнул названное, получил
// пусто, заключил «перечень пуст, красное не моё» и построил на этом план обхода
// хука. Красное было своё: ветка отставала ровно на коммит, снявший записи.
// Сообщение отказа — рантайм-диагностика, ей разрешено называть предмет прямо
// (`security.md`, три места из-под запрета), и ровно поэтому её неверность дорога.
//
// # Границы предиката — измерены, а не выбраны
//
// Замер по дереву (ревизия a2e873a91, единица счёта — различный путь):
//
//	все файлы scripts/ tools/ deploy/scripts/   213 путей, 58 «нет», ~54 ложных
//	те же, без самопроверок и _test.go           68 путей,  7 «нет»,   7 ложных
//	перечень OperatorFacingScripts                9 путей,  0 «нет»,   0 ложных
//
// Первые две формы отброшены не по вкусу: их находки — синтетические фикстуры
// самопроверок (`x.sh`, `driver_dead.sh`), которые ПОРОЖДАЮТСЯ во временном
// каталоге и обязаны отсутствовать, плюс относительные имена (`gen.py`), про
// которые гейт не вправе судить, из какого каталога их запустят. Гейт с 54
// ложными находками из 58 отключают первым же коммитом.
//
// Отсюда перечень выписан. Цена названа: файл, заговоривший с оператором и не
// внесённый в перечень, гейтом не наблюдается. Это осознанный размен узости на
// правдивость — и он виден, потому что перепись печатает, сколько файлов прочитано.
package repohygiene

import (
	"strings"
	"testing"
)

func TestOperatorMessagePathsExist(t *testing.T) {
	root := repoRoot(t)
	c := CollectOperatorMessagePaths(root)

	t.Logf("осмотрено файлов оснастки %d из %d объявленных; путей дерева названо %d; находок %d",
		c.FilesRead, len(OperatorFacingScripts), c.PathsNamed, len(c.Findings))

	// Предпосылка гейта: если перечень указывает в пустоту, гейт молчит не потому,
	// что всё хорошо, а потому что читать нечего.
	if len(c.FilesAbsent) > 0 {
		t.Fatalf("ПРЕДМЕТ ГЕЙТА ПЕРЕЕХАЛ: перечисленных файлов нет в дереве: %s\n"+
			"  Гейт наблюдает перечень OperatorFacingScripts; файл, сменивший путь, выпадает\n"+
			"  из наблюдения молча. Поправьте перечень тем же изменением, что переносит файл.",
			strings.Join(c.FilesAbsent, ", "))
	}
	if c.FilesRead == 0 || c.PathsNamed == 0 {
		t.Fatalf("КОРПУС ПУСТ: прочитано файлов %d, названо путей %d — «ноль находок» здесь\n"+
			"  означало бы «ноль прочитанного», а не «всё верно»", c.FilesRead, c.PathsNamed)
	}

	for _, f := range c.Findings {
		t.Errorf("КООРДИНАТА, НАЗВАННАЯ ОПЕРАТОРУ, НЕ СУЩЕСТВУЕТ: %s ← %s\n"+
			"  Оператор пойдёт по ней, получит пустой ответ и прочитает его как ответ.\n"+
			"  Исходов два: поправить координату либо завести названное.", f.Path, f.File)
	}
}
