package repohygiene

import (
	"path/filepath"
	"strings"
)

// isInstrumentPath — путь ПРИБОРА ЗАМЕРА, а не кода пути запроса.
//
// # Зачем это объявление, и почему оно появилось именно сейчас
//
// Несколько гейтов дерева судят прод-код пути запроса и в своих шапках прямо
// оговаривают, что приборы замера их предметом не являются: прибор ничего не
// обслуживает, его не импортирует продукт, его стоимость есть предмет отчёта, а
// не договора с арендатором. Оговорка была, а МЕХАНИЗМА у неё не было —
// исключение держалось тем, что приборы лежали в корневом `tools/`, а гейты
// обходили `services/`, `pkg/`, `gateway/`. То есть свойство выполнялось
// СЛУЧАЙНО, по раскладке каталогов.
//
// Линия выноса iam отдельным продуктом это обнажила: прибор замера форм доступа
// переехал под `services/iam/tools/`, потому что принадлежит домену iam и обязан
// уехать вместе с ним. Ни один гейт не изменился — и четыре из них немедленно
// объявили прибор нарушителем, при том что их собственные шапки объявляли его
// вне предмета. Два места об одном предмете, из которых верно одно.
//
// Здесь предмет объявлен ОДИН раз и по признаку, а не по адресу: каталог
// `tools` в любом сегменте пути. Тогда переезд прибора внутрь сервиса ничего не
// ломает, а вернуть прибор под надзор можно, только вынув его из `tools/` — то
// есть заявив, что он стал кодом пути запроса.
//
// # Чего это НЕ означает
//
// Не означает, что содержимое `tools/` не проверяется вовсе: гейты формы,
// лицензий, имён-идентификаторов и отложенной работы обходят дерево целиком и
// приборов не освобождают. Освобождение узкое — от гейтов, чей предмет есть
// поведение развёрнутого процесса на пути запроса.
//
// Не означает и того, что «`tools` в пути» является определением прибора на все
// времена. Это признак, выведенный из сегодняшней раскладки: каталог `tools`
// служит в этом дереве ровно одному — оснастке и приборам. Появится под `tools/`
// код, который поднимает развёрнутый процесс, — признак перестанет быть верным,
// и чинить надо будет его, а не отдельный гейт.
func isInstrumentPath(rel string) bool {
	for _, seg := range strings.Split(filepath.ToSlash(rel), "/") {
		if seg == "tools" {
			return true
		}
	}
	return false
}
