// moduleknowsnoedgeaddress.go — ТРЕТЬЯ половина анализатора «модуль не знает
// своего края»: адрес края как ЦЕЛЬ ДОЗВОНА.
//
// Половины ТИПА и АДРЕСА-ПО-ИМЕНИ-РУЧКИ живут в `moduleknowsnoedge.go`; здесь
// только распознаватель и его обоснование. Анализатор остаётся ОДИН, и перепись
// у него одна: второй анализатор об одном предмете разошёлся бы с первым молча.
//
// # Зачем понадобилась третья половина — измерено, а не предположено
//
// Шапка гейта утверждала, что адрес края, названный в обход конвенции ручек,
// держит половина ТИПА: «набрать типизированный вызов края без его контракта
// нечем, а контракт — импорт». Это верно для ТИПИЗИРОВАННОГО gRPC и ложно для
// нетипизированного HTTP: `http.Get` контракта не требует вовсе.
//
// Инъекция на синтетическом дереве показала молчание анализатора в обоих случаях
// (задача продукта #1576):
//
//	(A) services/vpc/edgecall.go
//	    http.Get("http://api-gateway.kacho.svc:8080/vpc/v1/networks")   → находок 0
//	(B) services/vpc/deploy/deployment.yaml
//	    command: ["sh","-c","until nc -z api-gateway.kacho.svc 8080; …"] → находок 0
//
// Цена каждого — ровно предмет гейта: (A) есть исходящее ребро модуль→край, то
// есть ЦИКЛ (край уже зовёт модуль потоком подписки); (B) есть «модуль не
// поднимается там, где края нет вовсе» — дословно вторая половина предмета из
// шапки самого гейта.
//
// # Что судится — ЦЕЛЬ ДОЗВОНА, а НИКОГДА имя
//
// Имя края в модуле законно и встречается десятками: круг законных отправителей,
// личность вызывающего, проза, ключи самого края. Судить имя значит покраснеть на
// каждом из них и быть снятым в первый же день.
//
// Поэтому предмет — не «названо имя», а «названа СЕТЕВАЯ ЦЕЛЬ». Различают три
// формы, и все три опираются на то, что стоит ВПЛОТНУЮ к имени хоста:
//
//  1. схема дозвона перед хостом:  http:// https:// grpc:// dns://
//  2. порт сразу после хоста:      api-gateway.kacho.svc:8080
//  3. порт через пробел (ТОЛЬКО чарт, форма оболочечной пробы): nc -z <хост> 8080
//
// Третья форма ограничена чартом намеренно: в чарте она есть команда ожидания, а
// в строковом литерале Go число после имени — проза («api-gateway 8080 закрыт»).
//
// # ЗАКОННЫЕ БЛИЗНЕЦЫ, каждый закрыт по построению
//
//   - `"api-gateway"` — бесхозное имя службы: ни схемы, ни порта. Это личность
//     ВХОДЯЩЕГО пира, решение «кого я впускаю», и оно обязано остаться.
//   - `spiffe://kacho.cloud/ns/kacho/sa/kacho-api-gateway` — схема `spiffe`
//     означает ЛИЧНОСТЬ и не дозванивается никуда. Круг законных отправителей
//     правило безопасности требует НЕПУСТЫМ и пиненным по фактическим
//     отправителям, то есть модуль обязан знать край по имени. Схема разбирается
//     ВПЛОТНУЮ к хосту, поэтому `spiffe` не попадает в перечень дозвонных.
//   - `apiGatewayPodSelector` / `app: kacho-api-gateway` — селектор пода края в
//     сетевой политике: направление край→модуль, вход, а не выход.
//   - `image: kacho-api-gateway:dev` — после хоста двоеточие, но НЕ цифры: тег
//     образа портом не является.
//   - `KACHO_API_GATEWAY_*` — ключи самого края в прозе модуля. Верхний регистр и
//     подчёркивания под токен хоста не подпадают.
//   - ресурс `Gateway` домена vpc (`vpc_gateway`, `GatewayService`, каталог
//     `api/gateway`) — общее с краем только слово «gateway»; токен хоста
//     `api-gateway` в них не встречается.
//   - проза и сообщение отказа («api-gateway did not forward …») — после хоста
//     пробел и БУКВЫ, а не цифры.
//
// # ГРАНИЦЫ, названные вслух
//
// Не видит адрес, СОБРАННЫЙ В РАНТАЙМЕ: хост в переменной, склейка, `fmt.Sprintf`
// с подстановкой. Литерала в дереве тогда нет, и судить нечего — узел, который
// можно прочесть, отсутствует by construction. Такой формы в дереве сегодня нет;
// появится — её держит половина ТИПА, пока вызов типизирован, и не держит ничто,
// пока он голый HTTP. Это остаток, а не обещание.
//
// Не видит ожидание края БЕЗ порта (`dependsOn: [api-gateway]`, initContainer,
// зовущий край по имени без цифр): все три формы опираются на порт либо схему.
// Блочный разбор шаблона чарта потребовал бы своего парсера — до подстановки это
// не YAML, — и цена его выше цены остатка.
package repohygiene

import "strings"

// Полосы анализатора. Находка называет свою полосу, потому что инъекция обязана
// доказывать «роняет ТОЛЬКО проверяемое», а это доказуемо лишь атрибуцией.
const (
	// EdgeLaneType — модуль ТИПИЗИРОВАН краем: импорт контракта либо кода края.
	EdgeLaneType = "тип"
	// EdgeLaneKnob — модуль объявляет РУЧКУ адреса края по конвенции имён.
	EdgeLaneKnob = "ручка"
	// EdgeLaneAddress — модуль называет ЦЕЛЬ ДОЗВОНА до края сырым адресом.
	EdgeLaneAddress = "адрес"
)

// edgeHostToken — по чему узнаётся ХОСТ края. Токен в нижнем регистре и с дефисом
// намеренно: ресурс Gateway домена vpc пишется `vpc_gateway`/`GatewayService`, а
// ключи самого края — `KACHO_API_GATEWAY_*`; ни то ни другое под токен не подпадает.
const edgeHostToken = "api-gateway"

// edgeDialSchemes — схемы, означающие ЦЕЛЬ ДОЗВОНА. `spiffe` сюда не входит и не
// должен: он означает личность предъявителя сертификата, а не адрес.
var edgeDialSchemes = map[string]bool{
	"http": true, "https": true, "grpc": true, "dns": true,
}

// isHostRune — состав имени хоста. Заглавных здесь нет намеренно: имя службы в
// адресе всегда в нижнем регистре, а верхний регистр — это ключи самого края.
func isHostRune(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '.' || c == '-'
}

func isDigit(c byte) bool { return c >= '0' && c <= '9' }

// edgeDialTargets возвращает цели дозвона до края, названные в s.
//
// allowSpacePort включает третью форму (порт через пробел) и подаётся ИСТИНОЙ
// только для строк чарта: в Go это была бы проза.
//
// Возвращается именно НАЙДЕННАЯ ЦЕЛЬ, а не признак: находка обязана называть то,
// на что она указывает, иначе читатель ищет её глазами по всей строке.
func edgeDialTargets(s string, allowSpacePort bool) []string {
	var out []string
	for i := 0; ; {
		idx := strings.Index(s[i:], edgeHostToken)
		if idx < 0 {
			return out
		}
		at := i + idx
		i = at + len(edgeHostToken)

		// Границы имени хоста вокруг токена: `kacho-api-gateway.kacho.svc`.
		lo := at
		for lo > 0 && isHostRune(s[lo-1]) {
			lo--
		}
		hi := at + len(edgeHostToken)
		for hi < len(s) && isHostRune(s[hi]) {
			hi++
		}
		host := s[lo:hi]

		// СХЕМА, стоящая ВПЛОТНУЮ перед хостом, решает первой — и решает в обе
		// стороны. Дозвонная (`http`, `grpc`) делает целью весь адрес; НЕдозвонная
		// (`spiffe`) означает ЛИЧНОСТЬ, и тогда это не цель ни при каком порте.
		// Вплотную и есть разделитель: в `spiffe://…/sa/kacho-api-gateway` схема
		// отделена от хоста путём, поэтому под этот случай он не подпадает и
		// разбирается ниже как бесхозное имя.
		start, scheme := lo, ""
		if lo >= 3 && s[lo-3:lo] == "://" {
			sb := lo - 3
			for sb > 0 && s[sb-1] >= 'a' && s[sb-1] <= 'z' {
				sb--
			}
			scheme = s[sb : lo-3]
			if !edgeDialSchemes[scheme] {
				continue
			}
			start = sb
		}

		// ПОРТ сразу после хоста. Двоеточие с БУКВАМИ после него портом не
		// является: так пишется тег образа (`kacho-api-gateway:dev`).
		end := hi
		if hi+1 < len(s) && s[hi] == ':' && isDigit(s[hi+1]) {
			end = hi + 1
			for end < len(s) && isDigit(s[end]) {
				end++
			}
		}

		switch {
		case end > hi || scheme != "":
			// Цель названа портом либо дозвонной схемой — сообщается ЦЕЛИКОМ,
			// вместе со схемой: находка обязана называть то, на что указывает.
			out = append(out, s[start:end])
		case allowSpacePort:
			// Порт через пробел — форма оболочечной пробы (`nc -z <хост> 8080`),
			// которой посадка ЖДЁТ край. Только чарт: в литерале Go число после
			// имени было бы прозой.
			j := hi
			for j < len(s) && (s[j] == ' ' || s[j] == '\t') {
				j++
			}
			if j > hi && j < len(s) && isDigit(s[j]) {
				pe := j
				for pe < len(s) && isDigit(s[pe]) {
					pe++
				}
				out = append(out, host+" "+s[j:pe])
			}
		}
	}
}
