// TestEveryDrainedOutboxIsObserved — каждая очередь, для которой поднят дренаж,
// имеет сканер состояния той же таблицы.
//
// Проверено инъекцией в обе стороны: снятие любого из четырёх сканеров красит
// гейт и печатает имя таблицы и сервис; добавление дренажа со сканером он
// пропускает молча.
func TestEveryDrainedOutboxIsObserved(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	// «Ноль находок» обязано быть отличимо от «ноль прочитанного».
	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root — предпосылка обхода "+
			"сломана, молчание ничего не доказывает (корень %s)", root)
	}
	if len(inv.drained) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ дренируемой очереди в %d прочитанных файлах — "+
			"распознавание сломано (ищется композитный литерал drainer.Config с полем Table)",
			inv.filesRead)
	}

	// Собственная слепая зона гейта, названная вслух. Координата очереди
	// резолвится разбором исходника, поэтому адрес, вычисляемый в рантайме
	// (поле чужой структуры, вызов функции, конкатенация), для него неотличим от
	// отсутствующего — и такая проводка была бы НЕВИДИМА обоим утверждениям выше.
	// Молчать об этом нельзя: гейт, у которого предмет может уехать из поля
	// зрения незаметно, — сам экземпляр формы без содержания.
	for _, u := range inv.unresolved {
		t.Errorf("%s: имя таблицы задано выражением, которое не резолвится разбором "+
			"исходника — гейт не видит эту очередь и молчал бы о ней «чисто». Назови "+
			"таблицу строковой константой пакета (та же, что стоит в конфигурации "+
			"дренажа), а не полем чужой структуры.", u)
	}

	drained := sortedKeys(inv.drained)
	observed := sortedKeys(inv.observed)
	t.Logf("прочитано файлов composition root: %d; дренируемых очередей: %d; со сканером состояния: %d\n"+
		"  дренаж:  %s\n  сканер:  %s",
		inv.filesRead, len(drained), len(observed),
		strings.Join(drained, "\n           "), strings.Join(observed, "\n           "))

	for _, table := range drained {
		if _, ok := inv.observed[table]; ok {
			continue
		}
		t.Errorf("очередь %s дренится (%s), но её состояние не сканирует никто: "+
			"глубины, возраста головы и числа отравленных строк не производит ни одна серия. "+
			"Застрявшая очередь неотличима от пустой — обе молчат. Подними "+
			"outbox/metrics.Collector на эту таблицу рядом с дренажом.",
			table, strings.Join(inv.drained[table], ", "))
	}
}

// TestEveryDrainedOutboxIsSplitByDirection — очередь, несущая обе половины
// (выдачу и снятие), обязана публиковать их порознь либо иметь запись
// исключения с обоснованием.
//
// Сводные серии на такой очереди здоровы при полностью мёртвом снятии: выдачи
// дренятся непрерывно, поэтому глубина мала и голова молода — что бы ни
// происходило со второй половиной. «Работает» и «ни разу не отозвано» дают
// ОДИНАКОВУЮ картину.
func TestEveryDrainedOutboxIsSplitByDirection(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root (корень %s)", root)
	}

	for _, table := range sortedKeys(inv.observed) {
		if inv.split[table] {
			continue
		}
		// Очередь без дренажа спрашивать о направлении доставки нечего: доставки
		// нет ни в одном направлении. Утверждение об этом — сильнее, чем
		// «половина одна», и живёт своей записью со своим истечением.
		if _, noDrainer := outboxObservedWithoutDrainer[table]; noDrainer {
			continue
		}
		if why, exempt := outboxDirectionSplitExempt[table]; exempt {
			if strings.TrimSpace(why) == "" {
				t.Errorf("исключение %s без обоснования: обязано называть, почему у очереди "+
					"нет второй половины", table)
			}
			continue
		}
		t.Errorf("очередь %s наблюдается только сводно: разложения по направлению нет. "+
			"Сводные серии остаются здоровыми при полностью мёртвом снятии, потому что "+
			"выдачи дренятся непрерывно. Задай CollectorConfig.Directions либо заведи "+
			"запись в outboxDirectionSplitExempt с обоснованием.", table)
	}
}

// TestOutboxDirectionExemptionsHaveSubject — исключение живёт, пока у него есть
// предмет: очередь, исчезнувшая из дерева, унаследует следующую слепую зону.
func TestOutboxDirectionExemptionsHaveSubject(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	for table := range outboxDirectionSplitExempt {
		if _, ok := inv.drained[table]; !ok {
			t.Errorf("исключение %s больше не имеет предмета: такой дренируемой очереди в "+
				"дереве нет. Удали запись.", table)
		}
	}
}

// TestObservedWithoutDrainerEntriesHaveSubject — запись «наблюдается без
// дренажа» истекает САМА, и истекает двумя разными способами.
//
// Оба проверяются, потому что означают противоположное: появление дренажа —
// хорошая новость, при которой очередь обязана вернуться под общие правила;
// исчезновение сканера — плохая, при которой очередь снова замолчала, а запись
// продолжает утверждать, что за ней смотрят.
func TestObservedWithoutDrainerEntriesHaveSubject(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root (корень %s)", root)
	}
	t.Logf("прочитано файлов composition root %d; дренируемых очередей %d, наблюдаемых %d, "+
		"записей «наблюдается без дренажа» %d",
		inv.filesRead, len(inv.drained), len(inv.observed), len(outboxObservedWithoutDrainer))

	tables := make([]string, 0, len(outboxObservedWithoutDrainer))
	for table := range outboxObservedWithoutDrainer {
		tables = append(tables, table)
	}
	sort.Strings(tables)

	for _, table := range tables {
		if strings.TrimSpace(outboxObservedWithoutDrainer[table]) == "" {
			t.Errorf("запись %s без обоснования: обязана называть, почему дренажа нет и "+
				"почему очередь при этом не снята", table)
		}
		if _, ok := inv.observed[table]; !ok {
			t.Errorf("запись %s больше не имеет предмета: сканера состояния у этой очереди "+
				"в дереве нет. Очередь снова молчит так же, как пустая, а запись утверждает, "+
				"что за ней смотрят. Удали запись — или верни сканер.", table)
		}
		if where, ok := inv.drained[table]; ok {
			t.Errorf("запись %s ИСТЕКЛА: у очереди появился дренаж (%s). Теперь её судят "+
				"общие правила — задай CollectorConfig.Directions либо заведи запись в "+
				"outboxDirectionSplitExempt. Эта запись выводит её из-под них.",
				table, strings.Join(where, ", "))
		}
	}
}

type outboxInventory struct {
	// drained — таблица → координаты (сервис:файл), где поднят дренаж.
	drained map[string][]string
	// observed — таблица → координаты, где поднят сканер состояния.
	observed map[string][]string
	// shipped — доставка этой таблицы ведётся ВЫВОЗОМ (`pkg/audit`), а не общей
	// оснасткой дренажа. Читается там, где текст находки описывает механику:
	// у двух механизмов она разная, и общий текст посылал бы чинить не то.
	shipped map[string]bool
	// split — у сканера этой таблицы задано разложение по направлению.
	split map[string]bool
	// partition — таблица → ключ партиции порядка, объявленный проводкой
	// дренажа (drainer.Config.PartitionColumn). Ключа нет в карте = проводка
	// поля не задаёт, то есть заявляет коммутативность потока. Читается гейтом
	// порядка (outboxorderinggate_test.go).
	partition map[string]string
	// partitionUnresolved — координаты проводок, где поле ключа партиции задано,
	// но его значение разбором исходника не восстанавливается. Такая проводка
	// для гейта порядка неотличима от «ключ не задан», поэтому она называется
	// вслух, а не проглатывается.
	partitionUnresolved []string
	// redrive — таблица → координаты, где поднят возврат отравленных строк
	// (reconciler.Config). Читается гейтом согласия ключей
	// (outboxredrivekeygate_test.go).
	redrive map[string][]string
	// redrivePartition — таблица → ключ партиции, объявленный проводкой ВОЗВРАТА.
	// Обязан совпадать с ключом дренажа той же таблицы: заявка стережёт
	// доставляемого предшественника, возврат — доставленного преемника, и на
	// разных ключах каждая половина стережёт партицию, которой не стережёт другая.
	redrivePartition map[string]string
	// retryPermanent — таблица → координаты проводок дренажа, объявивших
	// `PermanentPolicy: drainer.RetryPermanent`, то есть отказавшихся травить
	// ПОСТОЯННЫЙ отказ применения. Такая очередь возврата отравленных строк не
	// требует: травление покупает разблокировку партиции, и там, где партиции
	// нет, покупать нечего. Читается гейтом возврата
	// (outboxredrivekeygate_test.go).
	retryPermanent map[string][]string
	// unresolved — координаты проводок, чьё поле Table не резолвится разбором.
	unresolved []string
	// notes — таблица → комментарии, стоящие ВНУТРИ литерала настроек её дренажа.
	// Именно там живёт обоснование ОТСУТСТВУЮЩЕГО поля: отсутствие само по себе
	// ничего не объясняет, поэтому объяснение пишут рядом — и оно оказывается
	// вторым местом об одном предмете, которое не сверяется ни с чем.
	notes map[string][]wiringNote
	// commentsSeen — сколько комментарных групп разбор нашёл внутри литералов
	// проводок. Объём осмотренного: «ноль обоснований» обязано быть отличимо от
	// «файлы разобраны без комментариев» (parser.ParseComments не включён).
	commentsSeen int
	filesRead    int
}

// wiringNote — один комментарий внутри литерала настроек проводки.
type wiringNote struct {
	coord string // сервис:файл
	line  int
	text  string
}

// outboxInventoryCache — разобранный инвентарь на корень дерева.
//
// Семь проб (три про наблюдаемость, три про порядок, одна про словарь событий)
// спрашивают ОДНО И ТО ЖЕ, а один разбор стоит двух проходов по всем не-тестовым
// файлам каждого сервиса: сперва за строковыми константами, потом за
// композитными литералами.
//
// # Величина выигрыша — и почему она приведена парами, а не одним числом
//
// Замер сумм собственного времени проб, по три прогона на условие, флаги
// `-short -count=1`:
//
//	условие      | без кэша          | с кэшем
//	-------------|-------------------|------------------
//	под -race    | 12.8 / 13.0 / 15.0| 2.00 / 2.11 / 2.18
//	без -race    | 1.93 / 1.96 / 1.97| 0.32 / 0.33 / 0.33
//
// Выигрыш — примерно ШЕСТИКРАТНЫЙ, и он один и тот же в обеих строках. А вот
// абсолютные величины между строками отличаются на порядок, и это ловушка, в
// которую здесь уже попались: сообщение коммита, вводившего кэш, назвало пару
// «12.54 c → 0.36 c», то есть «до» из верхней строки и «после» из НИЖНЕЙ. Флаги
// в том сообщении объявлены с `-race`. Выигрыш оказался завышен впятеро с
// половиной, и заметил это приёмщик, а не автор: он не смог воспроизвести
// «после» ни при одном наборе флагов — потому что при ОБЪЯВЛЕННЫХ флагах такой
// величины не бывает.
//
// Мораль для следующего замера: величина без условия — не величина. Условие
// здесь — флаги, набор проб и машина; менять их между «до» и «после» нельзя даже
// случайно.
//
// # Зачем кэш вообще — и почему запас записан ПРЕДИКАТОМ, а не числом
//
// Запас — это РАЗНОСТЬ потолка и стоимости пакета, и обе величины меняются
// независимо от этого файла: потолок задаёт ручка `UNIT_TIMEOUT` в корневом
// Makefile (её поднимают отдельным решением), стоимость растёт вместе с деревом
// и вдобавок гуляет от прогона к прогону. Поэтому здесь записано не число, а
// способ его получить:
//
//	потолок   — `grep -n UNIT_TIMEOUT Makefile` (значение на бинарь пакета);
//	стоимость — строка `ok  …/internal/repohygiene` в журнале джобы юнит-прогона
//	            ПОСЛЕДНЕГО зелёного прогона ветки, а не местный `go test`.
//
// Измеренные точки — с ревизией и номером прогона, чтобы был виден разброс, а не
// одно значение:
//
//	ствол d24476c1 | 282.5 / 286.2 / 291.4 c (три прогона)
//	коммит 0b405119 | 293.8 c (прогон 31094737316)
//	коммит 77c0c5f5 | 297.2 c (прогон 31096143205) — те же гейты, +3.3 c
//
// Разброс между прогонами ОДНОГО И ТОГО ЖЕ кода доходит до 11 c — больше, чем
// вклад любой отдельной правки этой ветки (парный местный замер: ветка не дороже
// ствола). Отсюда два следствия, ради которых абзац и переписан. Первое:
// величину запаса нельзя записывать в дерево — здесь стояло «запаса ШЕСТЬ
// СЕКУНД» со ссылкой на 31094737316, и прогон СОБСТВЕННОГО коммента дал 2.8 c,
// то есть запись устарела на своей же ревизии, продолжая читаться как
// действующая. Второе: местный замер занижает риск примерно в полтора раза и
// вердиктом не является.
//
// Что от этого НЕ зависит: превышение потолка обращает зелёное не в красное, а в
// «не выполнилось» — таймаут не роняет ни одного утверждения, он их не доводит.
// Семь одинаковых разборов дерева — не то, на что стоит тратить запас, каким бы
// он ни был; отсюда кэш и парный ему кэш инвентаря словарей
// (outboxeventdictionary_test.go).
//
// Кэш безопасен по построению: ни одна проба этого пакета в читаемое дерево НЕ
// пишет (те, кому нужно другое дерево, строят его во временном каталоге и зовут
// другой разборщик), поэтому в пределах одного процесса ответ не может
// устареть. Ключ — корень, так что появление второго корня даст свою запись, а
// не чужой ответ. Кладётся только УСПЕШНЫЙ разбор: неудачный завершается
// t.Fatalf внутри, до присвоения.
//
// Объём осмотренного при этом не подделывается: `filesRead` лежит в самом
// инвентаре, поэтому проба, получившая кэш, печатает и проверяет НАСТОЯЩЕЕ число
// прочитанных файлов — то самое, на котором инвентарь построен в этом же
// процессе. Требование «ноль находок отличимо от ноль прочитанного» остаётся
// выполненным: пустой разбор в кэш попадёт так же, как непустой, и первая же
// проба на нём упадёт.
var (
	outboxInventoryMu    sync.Mutex
	outboxInventoryCache = map[string]outboxInventory{}
)

// outboxWiringInventory разбирает composition root'ы всех сервисов и шлюза.
//
// Резолв имени таблицы: значение поля Table — либо строковый литерал, либо
// идентификатор/селектор, чьё значение объявлено константой ГДЕ-ТО В ТОМ ЖЕ
// сервисе. Константы собираются по сервису, а не по дереву: одноимённые
// константы разных сервисов не должны сливаться в одну запись.
func outboxWiringInventory(t *testing.T, root string) outboxInventory {
	t.Helper()
	outboxInventoryMu.Lock()
	cached, ok := outboxInventoryCache[root]
	outboxInventoryMu.Unlock()
	if ok {
		return cached
	}
	inv := outboxInventory{
		drained:          map[string][]string{},
		observed:         map[string][]string{},
		shipped:          map[string]bool{},
		split:            map[string]bool{},
		partition:        map[string]string{},
		redrive:          map[string][]string{},
		redrivePartition: map[string]string{},
		retryPermanent:   map[string][]string{},
		notes:            map[string][]wiringNote{},
	}

	servicesDir := filepath.Join(root, "services")
	entries, err := os.ReadDir(servicesDir)
	if err != nil {
		t.Fatalf("читаю %s: %v", servicesDir, err)
	}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		svc := e.Name()
		svcRoot := filepath.Join(servicesDir, svc)
		consts := serviceConstStrings(t, svcRoot)
		// Ключ партиции register-очередей назван КОНСТАНТОЙ общей библиотеки
		// (reconciler.RegisterOutboxPartition), а не литералом в каждом сервисе.
		// Её значение читается из дерева, а не повторяется здесь: повторённое
		// разошлось бы с ней молча, и гейт сверял бы ключи с числом, которого в
		// коде уже нет.
		for k, v := range corelibOutboxConstStrings(t, root) {
			if _, taken := consts[k]; !taken {
				consts[k] = v
			}
		}
		files := goFilesUnder(t, svcRoot)
		for _, path := range files {
			inv.filesRead++
			scanOutboxWiring(t, path, svc, root, consts, &inv)
		}
	}
	outboxInventoryMu.Lock()
	outboxInventoryCache[root] = inv
	outboxInventoryMu.Unlock()
	return inv
}

// serviceConstStrings собирает все строковые константы сервиса: имя → значение.
// Имя берётся без квалификатора пакета, поэтому `clients.ProviderCompensationTable`
// резолвится по хвосту селектора.
func serviceConstStrings(t *testing.T, svcRoot string) map[string]string {
	t.Helper()
	out := map[string]string{}
	fset := token.NewFileSet()
	for _, path := range goFilesUnder(t, svcRoot) {
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			continue
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, spec := range gd.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for i, name := range vs.Names {
					if i >= len(vs.Values) {
						continue
					}
					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok || lit.Kind != token.STRING {
						continue
					}
					v, err := strconv.Unquote(lit.Value)
					if err != nil {
						continue
					}
					out[name.Name] = v
				}
			}
		}
	}
	return out
}

// goFilesUnder — не-тестовые .go файлы поддерева, взятые из ИНДЕКСА git, а не
// обходом диска.
//
// Разница не косметическая: под services/ на любой машине, где поднимали стенд
// или гоняли прогоны, лежат игнорируемые каталоги (распаковки чартов, рабочие
// копии, отчёты). Обход диска сделал бы вердикт гейта свойством рабочего
// каталога, а не коммита. Пустой корпус treecorpus считает отказом — «ноль
// находок» на «ноль прочитанного» здесь неотличимо от чистого дерева.
func goFilesUnder(t *testing.T, dir string) []string {
	t.Helper()
	tracked, err := treecorpus.UnderWithSuffix(dir, ".go")
	if err != nil {
		t.Fatalf("состав дерева под %s взять неоткуда: %v", dir, err)
	}
	out := make([]string, 0, len(tracked))
	for _, path := range tracked {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		out = append(out, path)
	}
	sort.Strings(out)
	return out
}

// scanOutboxWiring находит в одном файле композитные литералы drainer.Config и
// CollectorConfig и записывает таблицу, которую они называют.
func scanOutboxWiring(t *testing.T, path, svc, root string, consts map[string]string, inv *outboxInventory) {
	t.Helper()
	fset := token.NewFileSet()
	// ParseComments — не роскошь: обоснование ОТСУТСТВУЮЩЕГО поля живёт только в
	// комментарии, а без этого флага разбор его не видит вовсе и гейт молчал бы
	// «чисто» на любом обосновании, включая ложное.
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return
	}
	rel, _ := filepath.Rel(root, path)
	coord := svc + ":" + rel

	ast.Inspect(f, func(n ast.Node) bool {
		cl, ok := n.(*ast.CompositeLit)
		if !ok {
			return true
		}
		sel, ok := cl.Type.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		// Проводка распознаётся ДО чтения полей: иначе нерезолвящийся Table
		// молча выпал бы из обеих картин вместе со своим литералом.
		kind := ""
		// retryPermanentByType — механизм доставки, у которого травления нет BY
		// CONSTRUCTION, а не по объявленной политике. Признак читается по типу
		// настроек, потому что политикой он и не может быть объявлен: поля с
		// одним законным значением не бывает.
		retryPermanentByType := false
		switch sel.Sel.Name {
		case "Config":
			if pkg, ok := sel.X.(*ast.Ident); ok {
				switch pkg.Name {
				case "drainer":
					kind = "дренаж"
				case "reconciler":
					kind = "возврат"
				}
			}
		case "ShipperConfig":
			// Вывоз журнала аудита (`pkg/audit`) — доставка НАРАВНЕ с дренажом:
			// он клеймит строку, отдаёт её приёмнику и помечает доставленной.
			// Не признать его дренажом значило бы оставить очередь под записью
			// «наблюдается, но не дренится» при живой доставке — то есть гейт
			// молчал бы о механизме, которого не видит, и молчал бы «чисто».
			if pkg, ok := sel.X.(*ast.Ident); ok && pkg.Name == "audit" {
				kind = "дренаж"
				// Травления у вывоза журнала НЕТ by construction: контракт его
				// приёмника (`audit.Sink`) знает два исхода — принято и не
				// принято, — а класса «не приму никогда» у него не существует.
				// Значит и возврату отравленных строк нечего возвращать;
				// свойство держится пробой пакета
				// TestPermanentlyRefusedRowNeverWedgesTheQueue, которая
				// утверждает, что бессрочно отвергаемая запись остаётся ждущей,
				// а не объявляется негодной.
				retryPermanentByType = true
			}
		case "CollectorConfig":
			kind = "сканер"
		}
		if kind == "" {
			return true
		}

		var table string
		var hasTableKey bool
		var hasDirections bool
		var partition string
		var hasPartitionKey bool
		retryPermanent := retryPermanentByType
		for _, elt := range cl.Elts {
			kv, ok := elt.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			key, ok := kv.Key.(*ast.Ident)
			if !ok {
				continue
			}
			switch key.Name {
			case "Table":
				hasTableKey = true
				table = resolveStringExpr(kv.Value, consts)
			case "Directions":
				hasDirections = true
			case "PartitionColumn":
				hasPartitionKey = true
				partition = resolveStringExpr(kv.Value, consts)
			case "PermanentPolicy":
				// Значение — не строка, а константа пакета, поэтому резолвится
				// по ХВОСТУ селектора, а не через resolveStringExpr. Всё, что не
				// названо RetryPermanent, читается как умолчание «травить»:
				// нулевое значение поля означает именно его.
				if selv, ok := kv.Value.(*ast.SelectorExpr); ok &&
					selv.Sel.Name == "RetryPermanent" {
					retryPermanent = true
				}
			}
		}
		if table == "" {
			if hasTableKey {
				inv.unresolved = append(inv.unresolved,
					coord+" ("+kind+", строка "+strconv.Itoa(fset.Position(cl.Pos()).Line)+")")
			}
			return true
		}
		if kind == "возврат" {
			inv.redrive[table] = append(inv.redrive[table], coord)
			if hasPartitionKey && partition != "" {
				inv.redrivePartition[table] = partition
			}
			return true
		}
		if kind == "дренаж" {
			inv.drained[table] = append(inv.drained[table], coord)
			if retryPermanentByType {
				inv.shipped[table] = true
			}
			if retryPermanent {
				inv.retryPermanent[table] = append(inv.retryPermanent[table], coord)
			}
			for _, cg := range f.Comments {
				if cg.Pos() < cl.Pos() || cg.End() > cl.End() {
					continue
				}
				inv.commentsSeen++
				inv.notes[table] = append(inv.notes[table], wiringNote{
					coord: coord, line: fset.Position(cg.Pos()).Line, text: cg.Text(),
				})
			}
			switch {
			case hasPartitionKey && partition != "":
				inv.partition[table] = partition
			case hasPartitionKey:
				inv.partitionUnresolved = append(inv.partitionUnresolved,
					coord+" (строка "+strconv.Itoa(fset.Position(cl.Pos()).Line)+")")
			}
			return true
		}
		inv.observed[table] = append(inv.observed[table], coord)
		if hasDirections {
			inv.split[table] = true
		}
		return true
	})
}

// resolveStringExpr — строковый литерал, идентификатор-константа либо селектор
// вида `pkg.Const`; иначе пустая строка.
func resolveStringExpr(e ast.Expr, consts map[string]string) string {
	switch v := e.(type) {
	case *ast.BasicLit:
		if v.Kind != token.STRING {
			return ""
		}
		s, err := strconv.Unquote(v.Value)
		if err != nil {
			return ""
		}
		return s
	case *ast.Ident:
		return consts[v.Name]
	case *ast.SelectorExpr:
		return consts[v.Sel.Name]
	}
	return ""
}

func sortedKeys(m map[string][]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// corelibOutboxConstStrings — строковые константы пакетов общей библиотеки,
// на которые ссылается проводка очередей по имени (сегодня это ровно
// reconciler.RegisterOutboxPartition). Значение берётся ИЗ ДЕРЕВА: повтори его
// здесь литералом — и оно разошлось бы с константой молча, а гейт сверял бы
// ключи с величиной, которой в коде уже нет.
func corelibOutboxConstStrings(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, pkg := range []string{"reconciler", "drainer"} {
		dir := filepath.Join(root, "pkg", "outbox", pkg)
		if _, err := os.Stat(dir); err != nil {
			continue
		}
		for k, v := range serviceConstStrings(t, dir) {
			out[k] = v
		}
	}
	return out
}

// ─────────────────────────────────────────────────────────────────────────────
// КОЛОНКИ ДОСТАВКИ, КОТОРЫЕ ПИШУТ И НЕ ЧИТАЮТ
// ─────────────────────────────────────────────────────────────────────────────
//
// # Предмет — тот же класс, но на уровне КОЛОНКИ, а не проводки
//
// Проверки выше судят очередь по её ПРОВОДКЕ: есть дренаж — обязан быть сканер.
// Очередь, которую не провёл никто, для них не существует BY CONSTRUCTION — она
// не попадает ни в одно из двух множеств и молчит вместе с ними.
//
// Между тем схема такой очереди ОБЕЩАЕТ доставку: колонки `sent_at` /
// `next_attempt_at` (а с ними `status` и `attempts`) объявляют переход строки из
// «положена» в «доставлена». Значение в них пишется умолчанием на каждой вставке
// и не читается никем и никогда. Снаружи это неотличимо от работающей очереди:
// строки есть, состояние у них есть, а вопроса «сколько доставлено» не задаёт
// никто.
//
// Класс измерен, а не предположен. Журнал аудита службы прав: 29 921 строка на
// стенде kind-kacho (2026-08-21, только чтение, образ службы `a4b6cfba9`),
// доставленных 0, `max(attempts)` = 0 — НИ ОДНОЙ попытки доставки за всю жизнь
// очереди, а возраст старейшей строки равен возрасту стенда. Его брат в службе
// вычислений устроен так же и до этой правки не наблюдался ничем.
//
// # Почему предикат — КОЛОНКИ, а не имя таблицы
//
// Имя — соглашение: очередь, названную иначе, гейт по суффиксу `_outbox`
// пропустил бы, а таблицу с таким суффиксом, но без доставки (лента изменений
// `vpc_outbox`, `nlb_outbox`, `compute_outbox`, `geo_outbox` — у них нет ни
// `sent_at`, ни `next_attempt_at`), объявил бы находкой. Колонки доставки —
// свойство САМОЙ таблицы: их объявляет тот, кто обещает доставку, и объявляет
// ровно тогда, когда обещает. Замер по дереву: 11 таблиц из 194 миграций несут
// такую колонку, и все одиннадцать — очереди; лент изменений среди них нет ни
// одной.
//
// # Три законных исхода, и все три названы записью, а не молчанием
//
//  1. строки ДВИГАЕТ кто-то — дренаж (проводка `drainer.Config`) либо
//     собственный оператор прод-кода (`UPDATE … SET sent_at`), как у очереди
//     реконсиляции;
//  2. строки не двигает никто, и это ВИДНО — поднят сканер состояния, а очередь
//     стоит в [outboxObservedWithoutDrainer] с обоснованием;
//  3. строки не двигает никто, сканера нет намеренно, и это НАЗВАНО записью в
//     [deliveryColumnsWithoutAdvancer] с обоснованием и номером задачи.
//
// Четвёртого исхода нет: очередь, не попавшая ни в один, — находка.

// deliveryColumnsWithoutAdvancer — очереди, чьи колонки доставки объявлены
// схемой, но двигать их некому И сканера у них нет.
//
// # Чем эта запись отличается от [outboxObservedWithoutDrainer]
//
// Там очередь МОЛЧИТ СЛЫШИМО: сканер публикует растущую глубину и стареющую
// голову, и это верное описание положения дел. Здесь сканера нет — и его нет по
// решению, а не по забывчивости: у очереди, чья доставка стала тождеством
// коммита, растущий возраст головы означал бы исправную службу, а тревога,
// которая звонит всегда, отключается первой.
//
// # Запись обязана нести НОМЕР ЗАДАЧИ
//
// Обоснования мало: оно объясняет, почему так СЕЙЧАС, и ничего не говорит о том,
// кто это закроет. Отсрочка без ответственного — это ban #11 через заднюю дверь,
// поэтому [TestDeliveryColumnDeclarationsHaveSubject] требует в тексте ссылку
// вида `#<номер>` и падает без неё.
//
// # Как запись истекает — двумя способами, и оба роняют гейт
//
// У очереди появился тот, кто двигает строки (её судят общие правила), либо
// таблица исчезла из миграций (запись унаследует следующую слепую зону).
var deliveryColumnsWithoutAdvancer = map[string]string{
	// ПЕРЕЧЕНЬ ПУСТ, И ПУСТЫМ ОН И ЕСТЬ ЦЕЛЬ.
	//
	// Он пустел дважды и по одной и той же причине — сужающий шаг доезжал следом
	// за расширяющим, а не «когда-нибудь»:
	//
	//   #917   журнал намерений службы прав — колонки и индексы под клейм сняты;
	//   #1396  журнал смены субъекта — `sent_at`/`attempt_count`/`last_error`/
	//          `notified_at` сняты миграцией 20260829181500 после того, как
	//          писателей не осталось (толчок к краю снят #1024, направление
	//          развёрнуто, потребитель читает курсором `id > $1`).
	//
	// Обе записи ушли ВМЕСТЕ со своим предметом, а не были вычеркнуты: их снятия
	// потребовал [TestDeliveryColumnDeclarationsHaveSubject], покрасневший в тот
	// же заход, что и миграция. Так и полагается — запись живёт, пока у неё есть
	// предмет.
	//
	// Заводя следующую, помни, ЧТО она означает: очередь обещает доставку, не
	// доставляет и молчит об этом. Это законно ровно как СРЕДНЯЯ фаза
	// расширения-сужения, у которой есть номер задачи и предикат снятия.
}

// deliveryColumnMarks — колонки, объявляющие ПЕРЕХОД строки в доставленную.
//
// Ровно две, и обе именно объявляют переход, а не сопровождают его: `sent_at` —
// отметка состоявшейся доставки, `next_attempt_at` — время следующей попытки.
// `status` и `attempts` сюда НЕ входят намеренно: первое встречается у половины
// ресурсных таблиц продукта, второе — у попыток чего угодно, и предикат на них
// мерил бы не очередь, а словарь.
var deliveryColumnMarks = []string{"sent_at", "next_attempt_at"}

// deliveryColumnDecl — одна таблица, объявившая колонки доставки.
type deliveryColumnDecl struct {
	svc   string   // служба, чьей миграцией таблица заведена
	table string   // имя без схемы: проводка и миграция квалифицируют по-разному
	marks []string // какие именно колонки доставки объявлены
	file  string   // миграция-производитель
}

// key — ключ учёта: служба и таблица вместе.
//
// Порознь они лгут: `fga_register_outbox` объявлен ТРЕМЯ службами, и объединение
// по имени сделало бы одну провязанную очередь оправданием для двух
// непровязанных.
func (d deliveryColumnDecl) key() string { return d.svc + "/" + d.table }

// migrationSource — одна миграция: путь и её ИСПОЛНЯЕМАЯ Up-секция.
//
// Тип нужен затем, чтобы разбор мог питаться синтетикой инъекции той же
// функцией, что и деревом: проба, гоняющая свою копию разбора, доказывает
// свойство копии.
type migrationSource struct {
	path string
	up   string
}

var (
	reCreateTable = regexp.MustCompile(`(?i)CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?("?[A-Za-z_0-9.]+"?)\s*\(`)
	reDropTable   = regexp.MustCompile(`(?i)DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?("?[A-Za-z_0-9.]+"?)`)

	// reDropColumn — снятие колонки: `ALTER TABLE [схема.]имя DROP COLUMN [IF EXISTS] колонка`.
	//
	// Читается так же, как снятие таблицы. `IF EXISTS` необязателен — миграции
	// пишут обе формы, и предикат, знающий одну, пропускал бы половину снятий.
	reDropColumn = regexp.MustCompile(`(?is)ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?([a-z0-9_.\"]+)\s+DROP\s+COLUMN\s+(?:IF\s+EXISTS\s+)?([a-z0-9_]+)`)
	// reColumnDecl — объявление колонки: имя в начале строки, за ним тип.
	//
	// Тип пишется В ЛЮБОМ РЕГИСТРЕ, и это не педантизм: миграции дерева пишут его
	// и строчными (`timestamp with time zone`, вывод pg_dump), и заглавными
	// (`TIMESTAMPTZ`, рукописные). Первая редакция принимала только строчные и
	// не увидела ДВЕ очереди из одиннадцати — то есть молчала бы на них при
	// снятом движителе.
	reColumnDecl = regexp.MustCompile(`(?m)^\s*"?([a-z_0-9]+)"?\s+[A-Za-z]`)
	// reGoDeliveryAdvance — оператор, ДВИГАЮЩИЙ строку очереди.
	//
	// `[^;]{0,400}` намеренно: тело оператора не пересекает точку с запятой, и
	// без этой границы выражение склеило бы соседние операторы одного литерала.
	reGoDeliveryAdvance = regexp.MustCompile(`(?is)UPDATE\s+(?:[a-z_0-9]+\.)?([a-z_0-9]+)\s+SET\s+[^;]{0,400}?(sent_at|status)\s*=`)
)

// rawMigration — миграция как она лежит в дереве: путь и СЫРОЙ текст.
type rawMigration struct {
	path string
	body string
}

// deliveryColumnDeclsInRaw — единственный вход разбора схемы.
//
// Отдельной функцией именно затем, чтобы инъекция и обход дерева шли ОДНИМ
// путём, включая отрезание Down-секции и вырезание комментариев. Пока каждая
// сторона звала [migrationUpSection] сама, инъекция доказывала свойство своей
// последовательности вызовов, а не гейта: снять подготовку в обходе дерева и
// оставить её в инъекции можно было бы, не покраснев.
func deliveryColumnDeclsInRaw(svc string, files []rawMigration) []deliveryColumnDecl {
	src := make([]migrationSource, 0, len(files))
	for _, f := range files {
		src = append(src, migrationSource{path: f.path, up: migrationUpSection(f.body)})
	}
	return deliveryColumnDeclsIn(svc, src)
}

// deliveryColumnDeclsIn — таблицы одной службы, объявившие колонки доставки, с
// учётом последующего снятия.
//
// Миграции подаются В ПОРЯДКЕ ПРИМЕНЕНИЯ; таблица, заведённая одной и дропнутая
// следующей, в результат не попадает — иначе запись пережила бы свой предмет, а
// это ровно то, что гейт и ловит.
func deliveryColumnDeclsIn(svc string, files []migrationSource) []deliveryColumnDecl {
	live := map[string]deliveryColumnDecl{}
	var order []string
	for _, f := range files {
		for _, m := range reCreateTable.FindAllStringSubmatchIndex(f.up, -1) {
			name := bareTableName(f.up[m[2]:m[3]])
			body, ok := parenBody(f.up, m[1]-1)
			if !ok {
				continue
			}
			marks := deliveryMarksIn(body)
			if len(marks) == 0 {
				continue
			}
			if _, seen := live[name]; !seen {
				order = append(order, name)
			}
			live[name] = deliveryColumnDecl{svc: svc, table: name, marks: marks, file: f.path}
		}
		for _, m := range reDropTable.FindAllStringSubmatch(f.up, -1) {
			delete(live, bareTableName(m[1]))
		}
		// СНЯТИЕ КОЛОНКИ — тоже снятие объявления, и до 2026-08-22 гейт его не
		// читал: он видел `sent_at` в первой миграции и объявлял находку на
		// таблице, где колонки давно нет. То есть судил по ОБЪЯВЛЕНИЮ, а не по
		// итогу цепочки — ровно тот класс, который сам же и ловит.
		//
		// Обнаружено первым же снятием (#917): колонки доставки журнала намерений
		// сняты миграцией, а гейт продолжал требовать для них либо движителя,
		// либо записи в перечне исключений.
		for _, m := range reDropColumn.FindAllStringSubmatch(f.up, -1) {
			name, col := bareTableName(m[1]), m[2]
			d, ok := live[name]
			if !ok {
				continue
			}
			rest := make([]string, 0, len(d.marks))
			for _, mark := range d.marks {
				if mark != col {
					rest = append(rest, mark)
				}
			}
			if len(rest) == 0 {
				delete(live, name) // колонок доставки не осталось — предмета нет
				continue
			}
			d.marks = rest
			live[name] = d
		}
	}
	out := make([]deliveryColumnDecl, 0, len(live))
	for _, name := range order {
		if d, ok := live[name]; ok {
			out = append(out, d)
		}
	}
	return out
}

// deliveryMarksIn — какие колонки доставки объявлены телом CREATE TABLE.
//
// Читается ОБЪЯВЛЕНИЕ колонки (имя в начале строки, за ним тип), а не любое
// упоминание имени: `CONSTRAINT … CHECK (sent_at IS NULL …)` колонку не заводит,
// и засчитывать его значило бы считать ограничение обещанием доставки.
func deliveryMarksIn(body string) []string {
	declared := map[string]bool{}
	for _, m := range reColumnDecl.FindAllStringSubmatch(body, -1) {
		declared[m[1]] = true
	}
	var out []string
	for _, mark := range deliveryColumnMarks {
		if declared[mark] {
			out = append(out, mark)
		}
	}
	return out
}

// parenBody — тело скобки, открытой в позиции open.
//
// Скобки считаются, а не ищется первая закрывающая: определение колонки несёт
// свои скобки (`timestamptz(3)`, `CHECK (…)`), и наивный поиск обрезал бы тело
// на первой из них.
func parenBody(s string, open int) (string, bool) {
	if open < 0 || open >= len(s) || s[open] != '(' {
		return "", false
	}
	depth := 0
	for i := open; i < len(s); i++ {
		switch s[i] {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return s[open+1 : i], true
			}
		}
	}
	return "", false
}

// bareTableName — имя без схемы и без кавычек.
func bareTableName(s string) string {
	s = strings.Trim(s, `"`)
	if i := strings.LastIndex(s, "."); i >= 0 {
		s = s[i+1:]
	}
	return strings.Trim(s, `"`)
}

// goDeliveryAdvancersIn — таблицы, чьи колонки доставки двигает СОБСТВЕННЫЙ
// оператор прод-кода этой службы.
//
// Читаются ТОЛЬКО строковые литералы разобранного файла — то есть исполняемый
// SQL. Текстовый поиск засчитал бы комментарий, объясняющий этот же оператор, и
// молчал бы при снятом операторе: ровно тот класс, который гейт и ловит.
func goDeliveryAdvancersIn(files map[string]string) map[string][]string {
	out := map[string][]string{}
	fset := token.NewFileSet()
	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		f, err := parser.ParseFile(fset, path, files[path], 0)
		if err != nil {
			continue
		}
		ast.Inspect(f, func(n ast.Node) bool {
			lit, ok := n.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			text := lit.Value
			if unq, uerr := strconv.Unquote(text); uerr == nil {
				text = unq
			}
			for _, m := range reGoDeliveryAdvance.FindAllStringSubmatch(text, -1) {
				table := m[1]
				out[table] = append(out[table], path+":"+strconv.Itoa(fset.Position(lit.Pos()).Line))
			}
			return true
		})
	}
	return out
}

// deliveryAccountability — как очередь отчитывается за свои колонки доставки.
type deliveryAccountability int

const (
	// deliveryAdvanced — строки кто-то двигает.
	deliveryAdvanced deliveryAccountability = iota
	// deliveryVisiblySilent — не двигает никто, и это видно: сканер плюс запись.
	deliveryVisiblySilent
	// deliveryDeclaredSilent — не двигает никто, сканера нет, и это названо записью.
	deliveryDeclaredSilent
	// deliveryUnaccounted — не двигает никто и не говорит об этом никто. Находка.
	deliveryUnaccounted
)

// classifyDeliveryColumns — исход по одной очереди.
//
// Отдельной функцией, потому что инъекция гоняет ЕЁ ЖЕ на синтетических
// множествах: проба, повторяющая условие своими словами, доказывает свойство
// своей копии.
func classifyDeliveryColumns(advanced, drained, observed, observedNoted, declared bool) deliveryAccountability {
	switch {
	case advanced || drained:
		return deliveryAdvanced
	case observed && observedNoted:
		return deliveryVisiblySilent
	case declared:
		return deliveryDeclaredSilent
	default:
		return deliveryUnaccounted
	}
}

// TestEveryDeliveryColumnHasSomeoneWhoMovesItOrSaysNobodyDoes — колонки
// доставки, которые пишут и не читают.
//
// Проверено инъекцией в обе стороны (outboxobservedgate_injection_test.go):
// очередь с колонками доставки и без движителя даёт находку с координатой её
// миграции; законные близнецы — лента изменений без таких колонок, очередь с
// собственным оператором, очередь под дренажом и очередь со сканером и записью —
// молчат.
func TestEveryDeliveryColumnHasSomeoneWhoMovesItOrSaysNobodyDoes(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)
	decls, advancers, filesRead := deliveryColumnInventory(t, root)

	// «Ноль находок» обязано быть отличимо от «ноль прочитанного».
	if filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одной миграции — предпосылка обхода сломана, "+
			"молчание ничего не доказывает (корень %s)", root)
	}
	if len(decls) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ таблицы с колонками доставки в %d миграциях — "+
			"распознавание сломано (ищется объявление колонки %s внутри CREATE TABLE)",
			filesRead, strings.Join(deliveryColumnMarks, " / "))
	}

	drained, observed, observedFull := wiringByServiceAndTable(inv)

	lines := make([]string, 0, len(decls))
	unaccounted := 0
	for _, d := range decls {
		key := d.key()
		_, declared := deliveryColumnsWithoutAdvancer[key]
		_, noted := outboxObservedWithoutDrainer[observedFull[key]]
		verdict := classifyDeliveryColumns(
			len(advancers[key]) > 0, drained[key], observed[key], noted, declared)

		switch verdict {
		case deliveryAdvanced:
			lines = append(lines, "  двигают        "+key+" ("+strings.Join(d.marks, ", ")+")")
		case deliveryVisiblySilent:
			lines = append(lines, "  молчит слышимо "+key+" ("+strings.Join(d.marks, ", ")+")")
		case deliveryDeclaredSilent:
			lines = append(lines, "  названо        "+key+" ("+strings.Join(d.marks, ", ")+")")
		case deliveryUnaccounted:
			unaccounted++
			lines = append(lines, "  НАХОДКА        "+key+" ("+strings.Join(d.marks, ", ")+")")
			t.Errorf("очередь %s объявила колонки доставки (%s, миграция %s), и НИКТО их не "+
				"двигает: ни дренажа, ни собственного оператора. Строка ложится в таблицу со "+
				"значением по умолчанию и остаётся в нём навсегда; «доставлено ноль за всю "+
				"жизнь очереди» при этом не производит ни одна серия, поэтому застрявшая "+
				"очередь неотличима от работающей. Исходов три: подними дренаж; либо "+
				"подними сканер состояния и заведи запись в outboxObservedWithoutDrainer "+
				"(молчание станет слышимым); либо заведи запись в "+
				"deliveryColumnsWithoutAdvancer с обоснованием и номером задачи.",
				key, strings.Join(d.marks, ", "), d.file)
		}
	}

	sort.Strings(lines)
	t.Logf("прочитано миграций: %d; таблиц с колонками доставки: %d; собственных операторов "+
		"движения: %d; записей «двигать некому»: %d; находок: %d\n%s",
		filesRead, len(decls), len(advancers), len(deliveryColumnsWithoutAdvancer),
		unaccounted, strings.Join(lines, "\n"))
}

// TestDeliveryColumnDeclarationsHaveSubject — запись «двигать некому» живёт,
// пока у неё есть предмет, и обязана называть ответственного.
//
// Два способа истечь, и оба роняют гейт: у очереди появился движитель (её судят
// общие правила) либо таблица исчезла из миграций.
func TestDeliveryColumnDeclarationsHaveSubject(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)
	decls, advancers, filesRead := deliveryColumnInventory(t, root)

	if filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одной миграции (корень %s)", root)
	}
	t.Logf("прочитано миграций %d; таблиц с колонками доставки %d; записей «двигать некому» %d",
		filesRead, len(decls), len(deliveryColumnsWithoutAdvancer))

	live := map[string]deliveryColumnDecl{}
	for _, d := range decls {
		live[d.key()] = d
	}
	drained, _, _ := wiringByServiceAndTable(inv)

	keys := make([]string, 0, len(deliveryColumnsWithoutAdvancer))
	for k := range deliveryColumnsWithoutAdvancer {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, key := range keys {
		why := deliveryColumnsWithoutAdvancer[key]
		if strings.TrimSpace(why) == "" {
			t.Errorf("запись %s без обоснования: обязана называть, почему движителя нет и "+
				"почему колонки при этом не сняты", key)
		}
		if !reIssueRef.MatchString(why) {
			t.Errorf("запись %s не называет задачу: обоснование объясняет, почему так СЕЙЧАС, "+
				"и ничего не говорит о том, кто это закроет. Отсрочка без ответственного — "+
				"ban #11 через заднюю дверь. Поставь ссылку вида #<номер>.", key)
		}
		if _, ok := live[key]; !ok {
			t.Errorf("запись %s больше не имеет предмета: таблицы с колонками доставки под "+
				"этим именем в миграциях нет. Удали запись — иначе её унаследует следующая "+
				"слепая зона.", key)
		}
		if drained[key] || len(advancers[key]) > 0 {
			t.Errorf("запись %s ИСТЕКЛА: у очереди появился движитель. Теперь её судят общие "+
				"правила, а эта запись выводит её из-под них. Удали запись.", key)
		}
	}
}

// reIssueRef — ссылка на задачу в обосновании записи.
var reIssueRef = regexp.MustCompile(`#\d+`)

// wiringByServiceAndTable — множества проводки, приведённые к ключу «служба и
// таблица».
//
// Приведение нужно потому, что проводка называет таблицу С квалификатором схемы
// (`kacho_iam.audit_outbox`, `public.compute_fga_register_outbox`), а миграция —
// как придётся: та же таблица службы вычислений заведена без схемы вовсе.
// Сравнение полных имён объявило бы находкой каждую очередь, чьи два места
// написаны по-разному.
func wiringByServiceAndTable(inv outboxInventory) (drained, observed map[string]bool, observedFull map[string]string) {
	drained = map[string]bool{}
	observed = map[string]bool{}
	observedFull = map[string]string{}
	for table, coords := range inv.drained {
		for _, c := range coords {
			drained[coordService(c)+"/"+bareTableName(table)] = true
		}
	}
	for table, coords := range inv.observed {
		for _, c := range coords {
			key := coordService(c) + "/" + bareTableName(table)
			observed[key] = true
			observedFull[key] = table
		}
	}
	return drained, observed, observedFull
}

// coordService — служба из координаты проводки («служба:путь»).
func coordService(coord string) string {
	if i := strings.Index(coord, ":"); i >= 0 {
		return coord[:i]
	}
	return coord
}

// deliveryColumnInventory — таблицы с колонками доставки и собственные операторы
// движения, по всем службам дерева.
//
// Состав берётся У ИНДЕКСА репозитория, а не обходом диска: под services/ на
// машине, где поднимали стенд, лежат распаковки чартов и отчёты прогонов, и
// обход по диску судил бы дерево, которого в репозитории нет.
func deliveryColumnInventory(t *testing.T, root string) (decls []deliveryColumnDecl, advancers map[string][]string, filesRead int) {
	t.Helper()
	advancers = map[string][]string{}

	servicesDir := filepath.Join(root, "services")
	entries, err := os.ReadDir(servicesDir)
	if err != nil {
		t.Fatalf("читаю %s: %v", servicesDir, err)
	}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		svc := e.Name()
		migDir := filepath.Join(servicesDir, svc, "internal", "migrations")
		sqls, serr := treecorpus.UnderWithSuffix(migDir, ".sql")
		if serr != nil {
			// Служба без каталога миграций — законный случай, а не отказ.
			sqls = nil
		}
		sort.Strings(sqls) // имя миграции начинается с версии ⇒ лексикографический порядок = порядок применения
		sources := make([]rawMigration, 0, len(sqls))
		for _, path := range sqls {
			body, rerr := os.ReadFile(path)
			if rerr != nil {
				t.Fatalf("чтение %s: %v", path, rerr)
			}
			filesRead++
			rel, _ := filepath.Rel(root, path)
			sources = append(sources, rawMigration{path: rel, body: string(body)})
		}
		decls = append(decls, deliveryColumnDeclsInRaw(svc, sources)...)

		goFiles := map[string]string{}
		for _, path := range goFilesUnder(t, filepath.Join(servicesDir, svc)) {
			body, rerr := os.ReadFile(path)
			if rerr != nil {
				continue
			}
			rel, _ := filepath.Rel(root, path)
			goFiles[rel] = string(body)
		}
		for table, coords := range goDeliveryAdvancersIn(goFiles) {
			key := svc + "/" + table
			advancers[key] = append(advancers[key], coords...)
		}
	}
	return decls, advancers, filesRead
}
