// outboxObservedWithoutDrainer — очереди, которые НАБЛЮДАЮТСЯ, но НЕ ДРЕНЯТСЯ.
//
// # Почему это отдельная категория, а не запись в списке выше
//
// Прежняя модель гейта знала два множества и молча предполагала, что наблюдаемое
// вложено в дренируемое. Первая же очередь вне этого вложения показала, что
// предположение было именно предположением: у неё нет НЕ «второй половины» — у
// неё нет ДОСТАВКИ ВООБЩЕ. Свернуть эти два утверждения в одно значило бы
// записать «разложение по направлению неприменимо» там, где верно куда более
// сильное «доставки не существует», и следующий читатель прочёл бы очередь как
// работающую.
//
// # Зачем вообще наблюдать очередь без дренажа
//
// Затем, что «ноль доставленных строк за всю жизнь очереди обязано быть
// заметно» (data-integrity.md). Очередь без сканера и очередь без дренажа
// молчат ОДИНАКОВО; сканер эту пару различает, ничего не изображая: глубина
// растёт монотонно, голова стареет, отравленных нет — верное описание.
//
// # Как запись истекает
//
// Двумя способами, и оба роняют гейт ниже: у очереди появился дренаж (её судят
// общие правила, и запись отсюда выводит её из-под них) либо сканер сняли
// (наблюдать перестали, а запись утверждает обратное).
//
// # СЕГОДНЯ ЗДЕСЬ ПУСТО, и это измерение, а не забытая карта
//
// Обе записи, ради которых категория заводилась, — журналы аудита двух служб —
// ИСТЕКЛИ первым способом: у обоих появился приёмник и вывоз (#812). Пустой
// перечень и есть цель категории; проверку он НЕ роняет, потому что очередь без
// доставки — состояние, которое мы не запрещаем, а делаем видимым.
