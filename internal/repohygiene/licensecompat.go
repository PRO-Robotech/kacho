// licensecompat.go — СОВМЕСТИМОСТЬ лицензий на ребре импорта: код одного уровня
// не вправе втянуть код уровня, чьи обязательства он исполнить не может.
//
// # Предмет, и он НЕ тот же, что у двух соседних лицензионных гейтов
//
//	license_test.go        заголовок файла отвечает уровню, на котором файл лежит
//	dependencylicense.go   у ЧУЖОГО закреплённого модуля лицензия вообще есть
//	этот файл              РЕБРО между уровнями юридически выразимо
//
// Первые два зелены на дереве, где BUSL-код импортирует AGPL-код: у каждого
// файла заголовок верен своему уровню, у каждого чужого модуля лицензия есть.
// Несовместимость живёт не в файле и не в модуле, а в РЕБРЕ между ними, и
// потому у неё обязан быть свой держатель. `dependencylicense.go` оговаривает
// эту границу прямо — «гейт судит ФАКТ наличия лицензии, а не её
// СОВМЕСТИМОСТЬ… подменять решение человека предикатом значило бы обещать
// проверку, которой нет». Здесь заведена ровно та проверка, которую он не
// делает, и решение человека она не подменяет: она сверяет ребро с УЖЕ
// принятым решением об уровнях (licensemap.go), а не выбирает лицензию.
//
// # Правило совместимости — одна строка, и она выводится, а не выбирается
//
// Импортирующий принимает на себя обязательства импортируемого: линковка даёт
// производную работу. Отсюда ровно три исхода:
//
//	импортируемое ПЕРМИССИВНО (Apache-2.0) → можно всем
//	уровни СОВПАДАЮТ                       → можно
//	иначе                                  → нельзя
//
// Два следствия этого правила названы прямо, потому что каждое стоило бы
// отдельного разбора, а вместе они и есть предмет задачи #2083:
//
//   - AGPL-работа не вправе импортировать BUSL: §10 AGPL запрещает налагать на
//     получателя дополнительные ограничения, а BUSL налагает их собственным
//     текстом (ограничение промышленного использования);
//   - BUSL-платформа не вправе импортировать AGPL: она стала бы производной
//     работой и обязана была бы сама стать AGPL — то есть выбранная для неё
//     лицензия отменилась бы молча, без чьего-либо решения.
//
// # Почему уровень БЕЗ объявленной лицензии — находка, а не пропуск
//
// Уровень третьей стороны несёт пустой идентификатор: наш заголовок его файлам
// не положен (разбор — licensemap.go). Для ЗАГОЛОВКА пустота законна, для
// РЕБРА — нет: судить совместимость нечем. Поэтому импорт такого уровня
// отвергается fail-closed и требует решения человека. Сегодня под ним нет ни
// одного файла Go, поэтому ложных находок это не даёт, — а истечёт послабление
// само в тот день, когда файл там появится.
//
// # Направление рёбер сегодня и завтра
//
// Замер 2026-09-06 по этому дереву: служба (AGPL) тянет 61 пакет платформы, и
// ВСЕ они лежат под `pkg/`, то есть под Apache-2.0; обратных рёбер ноль.
// Значит несовместимой пары в дереве сегодня НЕТ, и пустая перепись находок —
// законный исход, а не подозрительная тишина.
//
// Завтра она появляется by construction: по решению владельца о трёх модулях
// (`corelib ← kaname ← kacho`) клиентские пакеты службы уезжают ВМЕСТЕ С НЕЙ,
// то есть под AGPL, а платформа продолжает их импортировать. Кандидатов сегодня
// семь каталогов, и тянут их 52 РАЗЛИЧНЫХ пакета платформы: `pkg/ownerregister`
// 19, `pkg/api/kacho/cloud/iam/v1` 25, `pkg/api/kacho/iam/authz/v1` 12,
// `pkg/tokenpolicy` 4, `pkg/identityposture` и `pkg/subjectchange` по 2,
// `pkg/credsecret` 1. Предикат — не проба этого пакета, а команда, и она названа
// здесь целиком, потому что перечень кандидатов есть СУЖДЕНИЕ о будущем переезде,
// а не свойство дерева; заводить ему держателя значило бы объявить решение
// принятым:
//
//	go list -f '{{$p:=.ImportPath}}{{range .Imports}}{{$p}} {{.}}
//	{{end}}' ./... | awk '$2=="<путь кандидата>"{print $1}' | sort -u | wc -l
//
// Гейт заводится ДО переезда намеренно. Ошибка здесь необратима: у того, кто
// получил опубликованный код, права остаются, и отзыв публикации их не отменяет.
// Проверка, заведённая после переезда, застала бы нарушение уже случившимся.

// # ГРАНИЦЫ — названы, чтобы гейт не читался шире сделанного
//
// Судится РЕБРО ИМПОРТА Go внутри двух модулей продукта. Вне предмета остаются
// три вещи, и каждая названа с владельцем, а не умолчана:
//
//   - ЛИЦЕНЗИЯ ЧУЖОГО МОДУЛЯ. Её наличие держит `dependencylicense.go`, её
//     совместимость не держит никто. Замер 2026-09-06 (162 каталога модулей в
//     кэше): копилефт-модулей 22, все — MPL-2.0, у которого копилефт файловый и
//     §3.3 прямо разрешает объединение с работой под другой лицензией; GPL,
//     LGPL и AGPL среди зависимостей ноль. То есть предмета у гейта сегодня нет,
//     а замер — не гейт: он снят командой и здесь только записан.
//
//   - ЗАВИСИМОСТЬ ОТ МОДУЛЯ ЦЕЛИКОМ. Служба закрепляет `github.com/PRO-Robotech/kacho`,
//     а Go выкачивает модуль АРХИВОМ — вместе с BUSL-каталогами, которых служба не
//     импортирует. Линкуется только пермиссивное (это и судит гейт), но получатель
//     службы получает и BUSL-файлы. Закрывается это не проверкой, а разъездом на
//     три модуля: тогда служба закрепляет `corelib`, где непермиссивного нет вовсе.
//     Предмет — задача #2131, и до неё гейт УМЫШЛЕННО зелёный: краснеть на том,
//     чинить что запрещено этой линией, значило бы завести послабление, которое
//     снимут первым.
//
//   - НЕ-GO ПОВЕРХНОСТИ (чарты, миграции, документация). Их принадлежность
//     уровню держит заголовок файла (`license_test.go`); ребра между ними, которое
//     можно было бы судить, не существует — линковки у них нет.

// licenseEdgeKind — прод или проба. Различаются в переписи, но НЕ в вердикте:
// публичный репозиторий распространяет и то и другое, поэтому обязательства
// лицензии наступают одинаково.
const (
	licenseEdgeProd = "прод"
	licenseEdgeTest = "проба"
)

// licenseEdge — одно ребро импорта, уже приведённое к путям ДЕРЕВА.
//
// Приведение делает вызывающий (licensecompat_test.go): путь импорта переводит
// в путь дерева `treePathOfImport`, общая с гейтом границы фундамента. Разделение
// намеренное — так инъекция подаёт синтетические рёбра, не заводя ни файлов, ни
// каталогов, и судит именно правило совместимости, а не добычу входа.
type licenseEdge struct {
	// FromDir — каталог импортирующего пакета, rel от корня дерева. Координата
	// находки: чинить надо здесь.
	FromDir string
	// ToTree — путь импортируемого пакета в дереве, rel от корня.
	ToTree string
	// Import — путь импорта, как он написан. Вторая половина координаты.
	Import string
	// Kind — прод или проба.
	Kind string
	// Files — в скольких ФАЙЛАХ каталога стоит этот импорт. Единица счёта та же,
	// что у гейта границы фундамента: список пакета приходит дедуплицированным,
	// поэтому счёт по записям списка скрыл бы рост долга.
	Files int
}

// licenseEdgeFinding — ребро, которое юридически невыразимо.
type licenseEdgeFinding struct {
	Edge licenseEdge
	From licenseTier
	To   licenseTier
	// Why — почему пара невозможна, словами и в терминах лицензий.
	Why string
}

func (f licenseEdgeFinding) String() string {
	return fmt.Sprintf("%s (%s, %s) -> %s: %s -> %s — %s [файлов: %d]",
		f.Edge.FromDir, f.From.Name, f.Edge.Kind, f.Edge.Import,
		licenseSPDXLabel(f.From), licenseSPDXLabel(f.To), f.Why, f.Edge.Files)
}

// licenseSPDXLabel — идентификатор уровня для текста находки. Пустой
// идентификатор печатается словами, иначе находка читалась бы как «-> » с
// оборванным хвостом.
func licenseSPDXLabel(t licenseTier) string {
	if t.SPDX == "" {
		return "лицензия уровня не объявлена"
	}
	return t.SPDX
}

// licenseTierForDir — уровень КАТАЛОГА.
//
// Отдельно от licenseTierFor, и это не украшение: та сверяет префиксы,
// ЗАКАНЧИВАЮЩИЕСЯ слэшем, поэтому каталог `services/iam` под запись
// `services/iam/` не подходит и молча уехал бы в умолчание BUSL — то есть
// вынесенный продукт под AGPL сошёл бы за монорепо, и ровно те рёбра, ради
// которых гейт заведён, стали бы законными. Корень дерева `go/build` отдаёт как
// ".", и он тоже приводится к форме умолчания.
func licenseTierForDir(dir string) licenseTier {
	if dir == "" || dir == "." {
		return licenseTierFor("")
	}
	return licenseTierFor(strings.TrimSuffix(dir, "/") + "/")
}

// licenseCompatible — можно ли импортирующему уровню втянуть импортируемый.
// Второй результат — причина отказа; при разрешении он пуст.
func licenseCompatible(from, to licenseTier) (bool, string) {
	switch {
	case to.SPDX == "":
		return false, "уровень импортируемого лицензии не объявляет — совместимость судить нечем"
	case to.SPDX == licenseApache:
		return true, ""
	case from.SPDX == to.SPDX:
		return true, ""
	case from.SPDX == "":
		return false, "уровень импортирующего лицензии не объявляет — обязательства принять некому"
	default:
		return false, fmt.Sprintf("%s не вправе принять обязательства %s", from.SPDX, to.SPDX)
	}
}

// licenseCompatCensus — объём осмотренного. Печатается ВСЕГДА, потому что «ноль
// находок» обязано быть отличимо от «ноль прочитанного».
type licenseCompatCensus struct {
	// Packages, Files — сколько каталогов и файлов Go осмотрено.
	Packages int
	Files    int
	// Edges — рёбер внутри продукта (оба модуля), то есть судимых.
	Edges int
	// External — рёбер наружу: стандартная библиотека и чужие модули. Не
	// судятся здесь — их предмет у dependencylicense.go.
	External int
	// Prod, Test — судимые рёбра по виду.
	Prod, Test int
	// Pairs — сколько рёбер у каждой пары уровней.
	Pairs map[string]int
}

func (c licenseCompatCensus) String() string {
	var b strings.Builder
	b.WriteString("перепись совместимости лицензий: пакетов " + strconv.Itoa(c.Packages))
	b.WriteString(" · файлов " + strconv.Itoa(c.Files))
	b.WriteString(" · рёбер в продукте " + strconv.Itoa(c.Edges))
	b.WriteString(" (прод " + strconv.Itoa(c.Prod) + ", проба " + strconv.Itoa(c.Test) + ")")
	b.WriteString(" · рёбер наружу " + strconv.Itoa(c.External) + " (не судятся здесь)")
	keys := make([]string, 0, len(c.Pairs))
	for k := range c.Pairs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString("\n  " + k + ": " + strconv.Itoa(c.Pairs[k]))
	}
	return b.String()
}

// licensePairKey — имя пары уровней для переписи.
func licensePairKey(from, to licenseTier) string {
	return fmt.Sprintf("%s (%s) -> %s (%s)",
		from.Name, licenseSPDXLabel(from), to.Name, licenseSPDXLabel(to))
}

// scanLicenseCompat — вердикт по набору рёбер.
//
// Находки отсортированы: вход приходит из обхода карт, порядок которого
// случаен, и несортированная находка меняла бы текст отказа от прогона к
// прогону при неизменном дереве.
func scanLicenseCompat(edges []licenseEdge, packages, files int) ([]licenseEdgeFinding, licenseCompatCensus) {
	census := licenseCompatCensus{Packages: packages, Files: files, Pairs: map[string]int{}}
	findings := make([]licenseEdgeFinding, 0, 8)

	for _, e := range edges {
		if e.ToTree == "" {
			census.External++
			continue
		}
		census.Edges++
		switch e.Kind {
		case licenseEdgeTest:
			census.Test++
		default:
			census.Prod++
		}

		from := licenseTierForDir(e.FromDir)
		to := licenseTierForDir(e.ToTree)
		census.Pairs[licensePairKey(from, to)]++

		if ok, why := licenseCompatible(from, to); !ok {
			findings = append(findings, licenseEdgeFinding{Edge: e, From: from, To: to, Why: why})
		}
	}

	sort.Slice(findings, func(i, j int) bool {
		a, b := findings[i].Edge, findings[j].Edge
		if a.FromDir != b.FromDir {
			return a.FromDir < b.FromDir
		}
		if a.Import != b.Import {
			return a.Import < b.Import
		}
		return a.Kind < b.Kind
	})
	return findings, census
}
