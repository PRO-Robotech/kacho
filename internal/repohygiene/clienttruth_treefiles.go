// clienttruth_treefiles.go — как гейты семейства «правда для клиента» берут
// состав дерева и читают его файлы.
//
// ОДНА реализация на семейство. Прежде эти две функции жили внутри
// clienttruth_nlb_name_scope.go под именами с приставкой `nlb` и уже
// обслуживали ДВА гейта, к nlb отношения не имеющих поровну: имя обещало
// принадлежность домену, которой у них нет. Приставка снята вместе с переездом,
// а не в отдельный заход, потому что остальные восемь гейтов семейства
// переводятся на эти же функции — и второй экземпляр того же предмета разошёлся
// бы с первым молча.
//
// # СОСТАВ — У ИНДЕКСА, ЧТЕНИЕ — ВНЕ ОБХОДА. Два требования, и они разные
//
// 1. **Состав берётся у индекса git, а не у диска.** Под `proto/` и
//    `services/*/docs/` на машине, где поднимали стенд или собирали сайт
//    документации, лежат распаковки чартов, сборочные каталоги и отчёты
//    прогонов; обход файловой системы прочитал бы их наравне с деревом, и
//    вердикт стал бы свойством рабочего каталога, а не коммита. Два соседних
//    гейта уже разошлись ровно так — 342 против 341 на одной неотслеживаемой
//    миграции (`treewalkindex_test.go`).
//
// 2. **Файл читается ВНЕ обхода.** Обход `filepath.Walk` сообщает путь
//    обратному вызову, и путь этот описывает состояние файловой системы на
//    момент вызова `lstat`, а не на момент чтения: между ними каталог можно
//    подменить ссылкой, и чтение уйдёт наружу дерева. Здесь обхода нет вовсе —
//    состав приходит перечнем ОТНОСИТЕЛЬНЫХ имён, а абсолютный путь
//    склеивается в момент чтения из корня дерева и такого имени.
//
// Требования независимы, и путать их не надо: первое про то, ЧТО осмотрено,
// второе про то, КАК прочитано. Первое чинит расхождение вердикта с коммитом,
// второе — гонку между наблюдением и чтением.
//
// # ЧЕМ ДЕРЖИТСЯ
//
// Сканером безопасности на пине конвейера (`.github/workflows/security-scan.yml`,
// gosec v2.28.0): нарушение первого требования не ловится ничем автоматически и
// держится этим текстом плюс `TestTreeWalkersAskTheIndex`, нарушение второго —
// правилом G304 (путь-переменная в чтении) и анализатором G122 (файловая
// операция в обратном вызове обхода). Возврат к обходу диска с чтением внутри
// него роняет джобу `gosec` на обоих сразу.

package repohygiene

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/PRO-Robotech/kacho/internal/treecorpus"
)

// clientTruthTreeFiles — отслеживаемые файлы под каталогом dirRel с одним из
// суффиксов, в порядке индекса (детерминизм входа — часть контракта проверки).
//
// recursive=false повторяет семантику `filepath.Glob("dir/*.ext")` — ОДИН
// уровень: перевод плоского каталога на рекурсивный обход сменил бы вместе с
// источником состава и ВОПРОС, который проверка задаёт. Пустой набор суффиксов
// означает «все файлы».
//
// Пустой каталог здесь — НЕ отказ, и это осознанно: вызывающие перечисляют
// каталоги нескольких сервисов, у части которых сайта документации нет вовсе.
// Отличать «каталога нет» от «смотреть не на что» обязан вызывающий — переписью
// прочитанного, которую он и так печатает.
//
// Возвращаются ОТНОСИТЕЛЬНЫЕ пути (как их отдаёт индекс); читающая сторона
// склеивает их с корнем через [clientTruthReadTreeFile].
func clientTruthTreeFiles(
	tree *treecorpus.Tree, dirRel string, recursive bool, suffixes ...string,
) []string {
	prefix := strings.TrimSuffix(filepath.ToSlash(dirRel), "/") + "/"
	var out []string
	for _, rel := range tree.SortedFiles() {
		if !strings.HasPrefix(rel, prefix) {
			continue
		}
		if !recursive && strings.Contains(rel[len(prefix):], "/") {
			continue
		}
		if len(suffixes) > 0 {
			ok := false
			for _, sfx := range suffixes {
				if strings.HasSuffix(rel, sfx) {
					ok = true
					break
				}
			}
			if !ok {
				continue
			}
		}
		out = append(out, rel)
	}
	return out
}

// clientTruthReadTreeFile — чтение файла состава. Путь склеивается ЗДЕСЬ, из
// корня дерева и относительного имени, пришедшего из индекса: в таком виде он
// не приходит извне ни одной своей частью и не приходит из обратного вызова
// обхода.
func clientTruthReadTreeFile(tree *treecorpus.Tree, rel string) ([]byte, error) {
	return os.ReadFile(filepath.Join(tree.Root(), filepath.FromSlash(rel)))
}
