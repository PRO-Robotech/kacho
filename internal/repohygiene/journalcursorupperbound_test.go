// journalCursorAllowances — ведомость послаблений: чтения по голому номеру,
// заведённые ДО этого гейта и снимаемые своими задачами.
//
// # Записи здесь — ДОЛГ С ПРЕДМЕТОМ, а не прощение
//
// Каждая называет задачу и предикат снятия. Ведомость самоистекающая: запись,
// которой в дереве больше нечего исключать, роняет прогон отдельной находкой —
// иначе она пережила бы свой фикс и разрешила следующему завести такое же
// чтение под тем же оправданием.
//
// Записи заводились ЗАМЕРОМ по дереву при закрытии kacho#1053, тело которой
// утверждало обратное: «все прочие журналы читаются как очередь с клеймом».
// Клейма нет ни у одного из двух.
//
// # ИХ БЫЛО ДВЕ, ОСТАЛАСЬ ОДНА — и разошлись они не по объёму работы
//
// Журнал изменений субъекта (kacho#1374) нёс класс ЖИВЫМ: номер приходил голым
// `nextval`, потеря воспроизведена пробой окна, чтение ограничено сверху границей
// устоявшегося — запись снята, и снята она тем, что гейт больше не видит здесь
// нарушения, а не тем, что кто-то её вычеркнул.
//
// Дельта величин (kacho#1373) класса НЕ НЕСЛА: посылка задачи опровергнута
// замером — выдачу ревизии сериализует триггер, и сценарий потери не строится.
// Работа тут была не в границе, а в СВЯЗИ: корректность читателя держалась
// свойством далёкого артефакта, которое шапка соседней пробы ЗАЯВЛЯЛА и ни одна
// проба не держала. Теперь держит, и эта проба — предикат истечения записи ниже.
//
// # ТРЕТЬЕЙ ЗАКОННОЙ ЗАКРЫТОСТИ РАСПОЗНАВАТЕЛЬ НЕ ВИДИТ, и это сказано вслух
//
// Он судит текст запроса и объявленный тип колонки, поэтому «номер выдаётся под
// блокировкой, держащейся до коммита» ему невидимо by construction: это свойство
// ПИСАТЕЛЯ, а запрос читателя выглядит одинаково в обоих случаях. Закрыть разрыв
// расширением распознавателя (разбор тела триггера, штампующего колонку) —
// отдельная работа с отдельным предметом; пока её нет, разграничение держит эта
// запись вместе с названной в ней пробой, и держит НАЗВАННО, а не молча.
//
// # ЧЕГО ЗДЕСЬ НЕ ЛЕЧАТ — и это главная ловушка ведомости
//
// Запись сюда прощает ЧТЕНИЕ ПО ГОЛОМУ НОМЕРУ — нарушение. Находку
// `КОЛОНКА-НЕОПОЗНАНА` она НЕ лечит и лечить не должна: там нарушения нет, там
// НЕПОЛНОТА НАБЛЮДЕНИЯ — анализатор не нашёл объявленного типа колонки. Чинится
// она пополнением списка типов (`jcOpaqueTypes` / `jcCounterTypes`) либо
// расширением корней схемы, и только так.
//
// Соблазн закрыть её послаблением велик, потому что это одна строка и прогон
// зеленеет. Цена — наблюдение гаснет НАВСЕГДА и молча: послабление снимает
// вопрос вместо того, чтобы на него ответить, а самоистечение его не поймает —
// предмет-то у записи есть.
var journalCursorAllowances = []JournalCursorAllowance{
	{
		File:   "services/iam/internal/repo/kacho/pg/limit_repo.go",
		Column: "revision",
		Because: "дельта величин: класс закрыт НА СТОРОНЕ ПИСАТЕЛЯ, а не читателя. Ревизию штампует " +
			"триггер limits_stamp_revision (миграция 0092) под pg_advisory_xact_lock, взятым ПЕРЕД nextval " +
			"и держащимся до коммита, поэтому невыданными в каждый момент остаются номера ОДНОГО писателя " +
			"и они старше всякого видимого: порядок ревизий есть порядок коммитов, и курсор, продвинутый " +
			"на видимую ревизию, не теряет ничего. Опровержение посылки kacho#1373 замерено, а не вычитано. " +
			"ПРЕДИКАТ ИСТЕЧЕНИЯ — проба TestLimitRevisionOrderIsCommitOrder " +
			"(services/iam/internal/repo/kacho/pg/limit_revision_commit_order_integration_test.go): она " +
			"краснеет, как только сериализацию выдачи снимут, и тогда это послабление теряет основание, " +
			"а чтению нужна верхняя граница по устоявшемуся",
	},
}

func journalCursorOptions(t *testing.T) JournalCursorOptions {
	t.Helper()
	return JournalCursorOptions{
		Root:     repoRoot(t),
		GoRoots:  []string{"pkg", "services", "gateway", "terraform", "internal", "cmd"},
		SQLRoots: []string{"pkg", "services", "gateway"},
		Allow:    journalCursorAllowances,
	}
}

// TestJournalReadersNeverAdvanceOnABareSequenceNumber — вердикт о НАСТОЯЩЕМ
// дереве.
//
// Способность падать доказывает не этот прогон, а инъекция
// (`journalcursorupperbound_injection_test.go`): здесь только вердикт.
func TestJournalReadersNeverAdvanceOnABareSequenceNumber(t *testing.T) {
	var log strings.Builder
	findings, census, err := AuditJournalCursorUpperBound(journalCursorOptions(t), &log)
	if err != nil {
		t.Fatalf("анализатор не отработал: %v", err)
	}
	t.Log(strings.TrimSpace(log.String()))

	// Премиса: прочитано то, что заведомо есть. Без неё «ноль находок» было бы
	// достижимо пустым обходом.
	if census.GoFiles < 500 || census.Literals < 5000 || census.Columns < 500 {
		t.Fatalf("файлов прод-кода %d, литералов %d, колонок схемы %d — обход пуст, вердикт беспредметен",
			census.GoFiles, census.Literals, census.Columns)
	}
	// И премиса предмета: возобновимые чтения в дереве ЕСТЬ. Ноль означал бы, что
	// распознаватель перестал их видеть, а не что дерево исправилось.
	if census.ResumableReads == 0 {
		t.Fatal("возобновимых чтений опознано 0: распознаватель ослеп, и молчание гейта беспредметно")
	}

	if len(findings) == 0 {
		return
	}
	lines := make([]string, 0, len(findings))
	for _, f := range findings {
		lines = append(lines, "  "+f.String())
	}
	t.Errorf("чтений по счётчику %d, из них ограничено сверху %d; послаблений %d:\n%s",
		census.CounterReads, census.Bounded, census.Allowances, strings.Join(lines, "\n"))
}
