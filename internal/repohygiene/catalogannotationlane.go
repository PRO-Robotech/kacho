package repohygiene

import (
	"fmt"

	"github.com/PRO-Robotech/corelib/authz/catalogderive"
)

// Полосы аннотации авторизации — те же три, что различает производитель карты
// (`catalogderive.entryFor`): край проверяет ровно одну из них на каждом RPC.
const (
	laneExempt        = "exempt"
	laneScopeFiltered = "scope_filtered"
	laneRelation      = "relation"
)

// annotationLane называет полосу, в которую аннотации метода попадают у края, и
// возвращает находку, если ни в одну.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ СВЕРКИ «АННОТАЦИЯ == СТРОКА» (задача #2692). Плагин
// каталога эмитит строку на КАЖДЫЙ метод, а для метода без аннотации — строку с
// пустыми полями (так каталог остаётся исчерпывающим). Сверка аннотации со
// строкой на таком методе сравнивает пустоту с пустотой и молчит: класс
// «RPC объявлен, но не аннотирован» проходил гейт зелёным, а ловился только
// стражем старта того сервиса, который выводит карту из этого пакета. Край при
// этом отвечал на такой метод отказом каталога — 403, который вызывающий
// читает как «нет прав», а оператор — как ничто.
//
// Полоса берётся тем же порядком, что у производителя карты, поэтому «что
// сделал бы край» и «что говорит гейт» не могут разойтись:
//
//   - нет ни права, ни отношения, ни сужения владельцем — аннотации НЕТ;
//   - `<exempt>` — проверки модели нет по решению; названное рядом отношение —
//     противоречие, на котором сервис отказывает в старте;
//   - `scope_filtered` — сужает владелец; отношение и область рядом были бы
//     обещанием проверки, которой край не делает;
//   - отношение названо — обычная полоса;
//   - право названо, а отношение и сужение НЕТ — производитель читает это как
//     публичную полосу: имя действия есть, вопроса к модели нет. Это находка, а
//     не полоса: открыть метод именем права никто не решал.
func annotationLane(a catalogderive.Annotations) (lane string, complaint string) {
	switch {
	case a.Permission == "" && a.RequiredRelation == "" && !a.ScopeFiltered:
		return "", "RPC не несёт аннотации авторизации (ни permission, ни required_relation, " +
			"ни scope_filtered): каталог получил бы строку с пустыми полями, а край отвечал бы " +
			"отказом каталога, который вызывающий читает как «нет прав»"
	case a.Permission == catalogderive.ExemptPermission:
		if a.RequiredRelation != "" {
			return "", fmt.Sprintf("<exempt> вместе с отношением %q: проверки модели нет по решению, "+
				"и названное рядом отношение утверждает проверку, которой не делается", a.RequiredRelation)
		}
		return laneExempt, ""
	case a.ScopeFiltered:
		return laneScopeFiltered, ""
	case a.RequiredRelation != "":
		return laneRelation, ""
	default:
		return "", fmt.Sprintf("право %q названо без отношения и без сужения владельцем: производитель "+
			"карты читает это как публичную полосу, то есть имя действия открывает метод без "+
			"единого вопроса к модели", a.Permission)
	}
}
