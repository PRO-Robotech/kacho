// TestPublishedInterfaceLimitsAreOnePlace — три величины одного интерфейса (полоса,
// предел одновременных соединений, темп их установления) живут в дереве по одному
// объявлению; документация называет их тем же числом и говорит, что число одно для
// всех сетей, зон и семейств; вывод числа на публичную страницу не вынесен; а то, что
// наша сторона проверить не может, записано открытым долгом с предикатом снятия.
//
// Что делать, если гейт сработал, — исходов четыре, пятого нет:
//
//  1. документация отстала -> привести её число к объявленному (оба напечатаны);
//  2. объявление отстало -> поднять его и ПЕРЕСМОТРЕТЬ обещание: величина адресована
//     арендатору, и опубликованное число не уменьшается никогда — если замер показал,
//     что оно недостижимо, растёт бюджет стенда, а не падает обещание;
//  3. обещание опубликовано «по зонам» или объяснено выводом -> переписать: величина
//     одна для всех, а вывод — инфра-данные;
//  4. долг разошёлся с деревом -> привести запись реестра к тому, что дерево делает
//     СЕЙЧАС. Появился страж старта под величину — запись обязана это сказать; исчез —
//     тоже.
//
// Чего делать нельзя: снимать гейт, потому что «эти величины всё равно держит не наша
// сторона». Именно поэтому он и написан: там, где исполнения нет, единственное, что
// стоит между обещанием и вымыслом, — совпадение числа и записанный долг.
func TestPublishedInterfaceLimitsAreOnePlace(t *testing.T) {
	root := repoRoot(t)
	findings, census, err := auditPublishedInterfaceLimits(root)
	if err != nil {
		t.Fatalf("перепись дерева: %v", err)
	}
	t.Log(census)

	// Предпосылка переписи: пустой корпус — отказ, а не пустой успех. Ноль прочитанных
	// файлов дал бы «ноль расхождений» на непрочитанном.
	if census.GoFilesParsed == 0 || census.DocFilesRead == 0 {
		t.Fatalf("корпус пуст — смотреть было не на что: %s", census)
	}
	if len(census.PerValue) != len(limitsCatalog) {
		t.Fatalf("перепись не покрыла периметр: величин в каталоге %d, в переписи %d",
			len(limitsCatalog), len(census.PerValue))
	}
	if len(findings) == 0 {
		return
	}
	var b strings.Builder
	for _, f := range findings {
		b.WriteString("  " + f.String() + "\n")
	}
	t.Fatalf("опубликованная величина разошлась со своим объявлением, обещанием или "+
		"записанным долгом (%d):\n%s\n%s", len(findings), b.String(), census)
}
