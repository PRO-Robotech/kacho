// catalogcheckwiring_test.go — гейт «сверку двух копий каталога прав обязан
// звать конвейер» (задача #2084).
//
// # Шов, который до этого не утверждался ничем
//
// Про сверку копий каталога прав уже сказано трижды: класс по дереву (сверка не
// обёрнута условием), поведение цели (сверка на целом дереве проходит) и связь
// ВНУТРИ Makefile (`permission-catalog-check` зависит от
// `permission-catalog-copies-in-sync`). Все три — в catalogcopyparity_test.go.
//
// Ни одно из них не высказывается о шве ВЫШЕ: зовёт ли эту цепочку хоть один
// шаг конвейера. Снимут шаг из ci.yaml — цель останется исполнимой и перестанет
// исполняться, и произойдёт это МОЛЧА: `make` не жалуется на то, что его никто
// не позвал, а гейт связи внутри Makefile остаётся зелёным, потому что связь
// цела. Это тот же класс, ради которого заводилась #1105 («условие, переставшее
// выполняться, неотличимо от условия выполненного»), только на звено выше.
//
// Цена расхождения копий не косметическая и названа в #1105: RPC без записи в
// каталоге получает `catalog: no entry for method` → AUTHZ_DENIED на КАЖДЫЙ
// вызов, независимо от выданных прав.
//
// # Почему провязка считается ЧЕРЕЗ ДОСТИЖИМОСТЬ, а не по имени одной цели
//
// Конвейер зовёт не саму сверку, а `permission-catalog-check`, чьей
// зависимостью она стоит. Требовать в конвейере ИМЕННО имя сверки значило бы
// краснеть на живой провязке; требовать ИМЕННО имя проверяемой — зеленеть после
// того, как сверку вынут из её зависимостей. Поэтому гейт спрашивает: позвана ли
// хоть одна цель, ИЗ КОТОРОЙ сверка достижима. Множество достигающих
// ВЫВОДИТСЯ из gateway/Makefile тем же разбором, которым его читает соседняя
// проба связи, — не выписывается: рукописный перечень разошёлся бы с деревом
// молча.
//
// # Чем этот гейт НЕ является
//
// Он не сверяет копии и не дублирует сверку — второй сверщик здесь измерял бы
// согласие двух разборщиков вместо согласия текстов. Его предмет — ПРОВЯЗКА:
// существует ли у цели вызывающий среди того, что исполняется само.
//
// Он не требует локального прогонщика. Требование обоих носителей принадлежит
// предмету гейта, а не механизму: `scripts/ci-local.sh` эту цель не зовёт и
// звать не обязан — сверка требует полного чекаута монорепо, а вменять
// отсутствие второго носителя значило бы краснеть на дереве, которое никто не
// ломал. Появится довод завести и второй носитель — он заводится своим
// изменением и своей инъекцией.
//
// # Механизм ОБЩИЙ, и это решение, а не удобство
//
// Обход живёт в gatetargetwiring.go и принимает КАТАЛОГ и ИМЯ ЦЕЛИ параметрами;
// им же пользуются гейты судей services/* (#1851, #1893). Вторая копия обхода
// расходилась бы с первой молча и расходилась бы там, где обе зелены. Ради этой
// цели механизм расширен второй формой вызова — `make <цель>` в шаге с
// `working-directory`, — потому что именно ею конвейер её и зовёт.
package repohygiene

import (
	"testing"
)

// catalogMakefileDir — каталог, чей Makefile объявляет цепочку каталога прав.
//
// Параметр, а не литерал в теле: каталог и имя цели — вход обхода, и разбросать
// их по телу значило бы завести второе место об одном предмете.
const catalogMakefileDir = "gateway"

// TestCatalogCopyParityTargetIsCalledByThePipeline — у сверки копий каталога
// прав обязан быть вызывающий среди того, что исполняется само.
//
// Что делать, если гейт сработал: провязать цепочку шагом конвейера — шагом с
// `working-directory: gateway` и телом `make permission-catalog-check` либо
// `make -C gateway permission-catalog-check`. Заводить вторую сверку взамен
// провязки нельзя: сверка объявлена побайтовой именно затем, чтобы не измерять
// согласие двух разборщиков. Снять шаг и «пока обойтись локальным прогоном»
// тоже нельзя — локальный прогонщик этой цели не зовёт, и тогда у неё не
// остаётся вызывающих вовсе.
func TestCatalogCopyParityTargetIsCalledByThePipeline(t *testing.T) {
	root := repoRoot(t)
	w, err := readMakeTargetWiring(root, catalogMakefileDir, catalogParityTarget)
	if err != nil {
		t.Fatalf("провязка не прочитана: %v — вердикт беспредметен", err)
	}

	// ── ПРЕДПОСЫЛКИ ОБХОДА ──────────────────────────────────────────────────
	//
	// Пустой обход обязан ронять прогон: иначе «находок ноль» означало бы «ноль
	// прочитанного», и эти два состояния печатались бы одинаково.
	if w.Reach.RecipeLines == 0 {
		t.Fatalf("в %s/Makefile не прочитано ни одной строки рецепта — разбор сломан, "+
			"и вердикт о провязке беспредметен", catalogMakefileDir)
	}
	if w.WorkflowsRead == 0 {
		t.Fatal("не прочитано ни одного файла .github/workflows — гейт смотрит не туда")
	}
	if w.WorkflowStepsRead == 0 {
		t.Fatal("ни в одном файле конвейера не найдено шага с телом `run:` — разбор сломан, " +
			"и «вызова нет» означало бы «не прочитано ничего»")
	}
	// Положительный контроль: цель обязана быть НАЙДЕНА объявленной. Ноль
	// объявлений означает, что цель сняли либо разбор сломан, и тогда «провязка
	// в порядке» — не свойство дерева, а слепота гейта.
	if !w.Reach.Declared {
		t.Fatalf("цель %s не объявлена в %s/Makefile (прочитано %d строк рецепта) — сверять копии "+
			"некому, и молчание про провязку ничего не значит",
			catalogParityTarget, catalogMakefileDir, w.Reach.RecipeLines)
	}
	// Второй положительный контроль: достигающих обязано быть НЕ МЕНЬШЕ одной
	// (сама цель). Пустое множество достигающих сделало бы «никто не позван»
	// истинным by construction.
	if len(w.Reach.Reaching) == 0 {
		t.Fatalf("множество целей, достигающих %s, пусто — разбор достижимости сломан, "+
			"и «никто не зовёт» было бы верно ни на чём", catalogParityTarget)
	}

	for _, f := range findMakeTargetWiringFaults(w) {
		t.Errorf("%s", f)
	}

	t.Log(makeTargetWiringCensus(w))
}
