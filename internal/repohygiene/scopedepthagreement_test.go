// scopedepthagreement_test.go — ТРИ ВЕЛИЧИНЫ ГЛУБИНЫ ЦЕПИ ОБЯЗАНЫ СОВПАДАТЬ.
//
// # Предмет
//
// Предел обхода цепи областей несёт ДВОЙНУЮ нагрузку: тем же числом ограничена
// и рекурсия (сколько уровней вверх пройти), и выборка внутри соединения вбок
// (сколько рёбер взять у одного объекта). Довод «предел не усекает» верен ровно
// пока это число не меньше того, что допускает схема: у объекта не бывает больше
// рёбер, чем глубин, а глубина ограничена проверкой `depth BETWEEN 1 AND N`.
//
// Совпадение сегодня есть, и оно НИЧЕМ НЕ ДЕРЖИТСЯ. Понизить константу обхода —
// и предел начнёт молча отбрасывать рёбра; поднять границу схемы новой миграцией
// — то же самое с другой стороны. Отбрасывать он будет по `ORDER BY pe.depth`,
// то есть ДАЛЬНИХ предков первыми: аккаунт и кластер. Это Б1 через другую дверь:
// область схлопывается вверх, ответ остаётся «нет», и отказ неотличим от
// честного.
//
// # Почему гейт, а не комментарий
//
// Комментарий у запроса это уже объясняет. Но объяснение живёт в одном файле, а
// величины — в трёх местах: константа Go, число в проверке схемы и предел внутри
// соединения. Правка любого из трёх выглядит локальной и безобидной.
package repohygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/internal/treecorpus"
)

const (
	scopeDepthConstFile = "services/iam/internal/repo/kacho/pg/relverdict/query.go"

	// scopeDepthMigration — файл, в котором граница глубины ОБЪЯВЛЕНА СЕГОДНЯ.
	//
	// Прежде здесь стоял `0082_resource_parent_edge.sql` — миграция, которая
	// границу вводила. Цепь iam сведена в одну первичную миграцию, и той
	// координаты в дереве нет: гейт падал на чтении файла. Это не потеря
	// свойства — граница жива, — а устаревание КООРДИНАТЫ, и лечится она
	// перенаправлением, а не ослаблением сверки.
	//
	// Координата остаётся ОДНИМ файлом намеренно. Поиск по каталогу миграций был
	// бы устойчивее к переезду, но неверен по существу: в цепи из многих файлов
	// границу может поднять более поздняя миграция, и тогда объявлений станет два,
	// причём законно — побеждает последнее. Правило «величина объявлена ровно
	// один раз» верно ВНУТРИ файла и неверно поперёк цепи, поэтому предикат
	// смотрит в файл. Устаревание координаты здесь громкое: чтение файла фатально,
	// а не молча пусто.
	scopeDepthMigration = "services/iam/internal/migrations/0001_initial.sql"

	// Третья величина названа координатой затем, чтобы находка о ней называла
	// МЕСТО, а не только число. Обходу этот путь не нужен — он ищет по всему
	// дереву и найдёт величину, куда бы она ни переехала; здесь путь служит
	// только тексту находки, и его устаревание гейт заметит сам:
	// `TestScopeDepthPlanFileCoordinateIsAlive` ниже.
	scopeDepthPlanFile = "internal/authzplan/compile.go"
)

var (
	reMaxAncestorDepth = regexp.MustCompile(`MaxAncestorDepth\s*=\s*(\d+)`)

	// reDepthCheck знает ОБЕ законные формы записи одной и той же границы, и это
	// не запас на будущее, а измеренный факт дерева.
	//
	// Миграция пишет предикат человеком: `depth BETWEEN 1 AND 4`. Свод цепи
	// получается из `pg_dump`, а он печатает то, что хранит каталог, и хранит он
	// РАЗЛОЖЕННУЮ форму: `((depth >= 1) AND (depth <= 4))`. Формы означают ровно
	// одно и то же, обе законны, и предикат, знающий только первую, на сведённой
	// схеме не находит НИЧЕГО — то есть не краснеет и не зеленеет, а молчит
	// (`testing.md` §«Гейт на класс», п. 7).
	//
	// Молчание здесь было бы фатальным, а не тихим (`singleNumber` требует ровно
	// одного совпадения), но чинить его подгонкой координаты значило бы отложить
	// тот же отказ до свода следующего сервиса: всякая будущая сводка придёт из
	// того же `pg_dump` и в той же форме.
	// Граница слова перед `depth` несущая: без неё предикат ловил бы `max_depth`,
	// `tree_depth` и всякое чужое поле с тем же хвостом, и «величина объявлена
	// дважды» приходило бы от однофамильцев.
	reDepthCheck = regexp.MustCompile(`\bdepth BETWEEN 1 AND (\d+)|\bdepth\s*<=\s*(\d+)`)

	rePlanDepth = regexp.MustCompile(`MaxPointerDepth\s*=\s*(\d+)`)
)

func TestScopeDepthBoundsAgreeAcrossAllThreePlaces(t *testing.T) {
	root := repoRoot(t)

	code := readFileForDepth(t, filepath.Join(root, scopeDepthConstFile))
	schema := readFileForDepth(t, filepath.Join(root, scopeDepthMigration))

	goDepth := singleNumber(t, reMaxAncestorDepth, code, "предел обхода в коде (MaxAncestorDepth)")
	sqlDepth := singleNumber(t, reDepthCheck, schema, "граница глубины в проверке схемы")

	// Третья величина — предел компилятора модели. Он объявлен в другом пакете и
	// сверяется собственной пробой рядом с ним; здесь он лишь ИЩЕТСЯ, и его
	// отсутствие названо, а не проглочено.
	planDepth, planFound := findPlanDepth(t, root)

	t.Logf("ОБЪЁМ ОСМОТРЕННОГО: предел обхода %d (%s) · граница схемы %d (%s) · "+
		"предел компилятора модели %s",
		goDepth, scopeDepthConstFile, sqlDepth, scopeDepthMigration,
		planDepthText(planDepth, planFound))

	for _, finding := range adjudicateScopeDepth(scopeDepthTriple{
		goDepth: goDepth, sqlDepth: sqlDepth,
		planDepth: planDepth, planFound: planFound,
	}) {
		t.Error(finding)
	}
}

// scopeDepthTriple — три величины, которые обязаны совпадать, и признак того,
// найдена ли третья.
type scopeDepthTriple struct {
	goDepth   int
	sqlDepth  int
	planDepth int
	planFound bool
}

// adjudicateScopeDepth — СУЖДЕНИЕ О ТРЁХ ВЕЛИЧИНАХ, отделённое от их добычи.
//
// Отделено намеренно: пока сверка жила внутри пробы, доказать её способность
// упасть можно было только испортив настоящее дерево — то есть никак. Гейт,
// который нельзя уронить нарочно, не отличается от гейта, который не может
// упасть вовсе; сверка величин ЗЕЛЕНЕЛА БЫ на любой из них, если бы предикат
// однажды перестал находить своё число.
//
// Находка называет ОБЕ координаты: расхождение — это всегда пара, и «предел
// обхода 4» без второго числа не говорит, что чинить.
func adjudicateScopeDepth(tr scopeDepthTriple) []string {
	var out []string
	if tr.goDepth != tr.sqlDepth {
		out = append(out, fmt.Sprintf("предел обхода %d (%s) не равен границе схемы %d (%s).\n"+
			"    Тем же числом ограничена выборка внутри соединения вбок, и довод «предел не "+
			"усекает» держится ровно их равенством. При меньшем пределе выборка молча "+
			"отбросит рёбра, причём по ORDER BY pe.depth — ДАЛЬНИХ предков первыми, то есть "+
			"аккаунт и кластер. Область схлопнется вверх, ответ останется «нет», и отказ "+
			"будет неотличим от честного.",
			tr.goDepth, scopeDepthConstFile, tr.sqlDepth, scopeDepthMigration))
	}
	if tr.planFound && tr.planDepth != tr.goDepth {
		out = append(out, fmt.Sprintf("предел компилятора модели %d (%s) не равен пределу "+
			"обхода %d (%s): модель выводит права на глубину, до которой обход не доходит "+
			"(или наоборот)",
			tr.planDepth, scopeDepthPlanFile, tr.goDepth, scopeDepthConstFile))
	}
	return out
}

func readFileForDepth(t *testing.T, path string) string {
	t.Helper()
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("файл %s не читается: %v — гейт не может судить дерево, которого не видит", path, err)
	}
	return string(body)
}

// singleNumber — величина обязана быть НАЙДЕНА и быть ЕДИНСТВЕННОЙ.
//
// Ноль совпадений означает, что объявление переехало и гейт сторожит пустоту;
// два — что величина уже задвоена, и сверять её саму с собой бессмысленно.
func singleNumber(t *testing.T, re *regexp.Regexp, body, what string) int {
	t.Helper()
	ms := re.FindAllStringSubmatch(body, -1)
	if len(ms) == 0 {
		t.Fatalf("%s не найдена: объявление переехало, и «величины совпадают» стало бы "+
			"утверждением ни о чём", what)
	}
	if len(ms) > 1 {
		t.Fatalf("%s объявлена %d раз: она уже задвоена, и расхождение возможно внутри "+
			"одного файла", what, len(ms))
	}
	// Ветвь совпадения выбирается по НЕПУСТОЙ группе, а не по её номеру:
	// распознаватель знает несколько форм записи, и у каждой своя группа.
	raw := ""
	for _, g := range ms[0][1:] {
		if g != "" {
			raw = g
			break
		}
	}
	if raw == "" {
		t.Fatalf("%s: совпадение есть, а числа в нём нет — распознаватель нашёл форму, "+
			"из которой не извлекает величину", what)
	}
	n, err := strconv.Atoi(raw)
	if err != nil {
		t.Fatalf("%s не число: %q", what, raw)
	}
	return n
}

// findPlanDepth — предел компилятора модели, если он в дереве объявлен.
//
// ОБХОД — ВСЁ ДЕРЕВО, а не поддерево одной службы. Прежняя редакция искала
// только под `services/iam/internal`, а величина объявлена в `internal/authzplan`
// — то есть гейт печатал «не объявлен в дереве (сверять не с чем)» при
// объявленной величине, и третья из трёх сверок не выполнялась НИ РАЗУ.
//
// Слепая зона была тихой вдвойне: сообщение звучит как честная оговорка о
// границе, а не как признание, что искали не там. «Названо, а не проглочено»
// верно по форме и ложно по существу, когда предмет лежит рядом.
//
// Состав берётся У ИНДЕКСА РЕПОЗИТОРИЯ, а не обходом диска: под рабочей копией
// на машине, где поднимали стенд или собирали фронтенд, лежат игнорируемые
// каталоги распаковки чартов и отчёты прогонов, и обход диска судил бы дерево,
// которого в репозитории нет.
//
// Объявлений с ЧИСЛОМ ожидается ровно одно. Псевдоним (`= authzplan.MaxPointerDepth`)
// под предикат не подпадает by construction — он не несёт цифры, — и это верно:
// псевдоним не второе объявление, а ссылка на первое. Два РАЗНЫХ числа — находка,
// и она называется отдельно: два места об одном пределе расходятся молча.
func findPlanDepth(t *testing.T, root string) (int, bool) {
	t.Helper()
	files, err := treecorpus.UnderWithSuffix(root, ".go")
	if err != nil {
		t.Fatalf("состав дерева у индекса репозитория: %v — гейт не может судить о "+
			"дереве, которого не может назвать", err)
	}
	type decl struct {
		path  string
		value int
	}
	var found []decl
	for _, abs := range files {
		if strings.HasSuffix(abs, "_test.go") {
			continue
		}
		body, rerr := os.ReadFile(abs)
		if rerr != nil {
			continue
		}
		if m := rePlanDepth.FindStringSubmatch(string(body)); m != nil {
			if n, cerr := strconv.Atoi(m[1]); cerr == nil {
				rel, _ := filepath.Rel(root, abs)
				found = append(found, decl{path: rel, value: n})
			}
		}
	}
	if len(found) == 0 {
		return 0, false
	}
	for _, d := range found[1:] {
		if d.value != found[0].value {
			t.Errorf("предел компилятора модели объявлен ДВАЖДЫ и по-разному: "+
				"%s = %d, %s = %d.\n"+
				"    Два места об одном пределе расходятся молча, и следующий читатель "+
				"возьмёт то, которое нашёл первым. Оставьте одно объявление, остальные "+
				"сделайте ссылкой на него.",
				found[0].path, found[0].value, d.path, d.value)
		}
	}
	return found[0].value, true
}

func planDepthText(n int, ok bool) string {
	if !ok {
		return "не объявлен в дереве (сверять не с чем — названо, а не проглочено)"
	}
	return strconv.Itoa(n)
}
