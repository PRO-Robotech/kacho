// bakedledgersubject.go — САМОИСТЕЧЕНИЕ ведомости запечённых дескрипторов.
//
// # Предмет, и почему он отдельный от оси, которую ведомость обслуживает
//
// Ведомость `knownBakedDescriptors` прощает вхождения координаты переезжающего
// пакета внутри порождённого стаба. Её ось (`TestFoundationNamesNoMovingPackage…`)
// на сегодняшнем дереве **беспредметна**: каталогов класса фундамента под `pkg/`
// не осталось, и ось честно уходит в `Skip`. Ведомость при этом остаётся, и
// судить её становится нечем — `Skip` срабатывает РАНЬШЕ, чем счёт вхождений.
//
// Это тот самый класс, который ведомость и стережёт, применённый к ней самой:
// **послабление, которому нечего прощать, не истечёт больше никогда**
// (`testing.md` §«Гейт на класс», п. 5). Замер 2026-09-16: записей было пять, и
// **ни одного** из пяти файлов в дереве нет.
//
// # Почему признак — СУЩЕСТВОВАНИЕ ФАЙЛА, а не счёт вхождений
//
// Счёт вхождений судит ось: он отвечает на вопрос «прощает ли запись больше, чем
// встречается». Ответ у него есть только тогда, когда ось прошла обход, — то есть
// ровно не тогда, когда нужен. Существование файла ни от какого обхода не зависит
// и отвечает на более сильный вопрос: **есть ли у записи предмет вообще**.
//
// Две проверки не дублируют друг друга и обе нужны: файл может существовать, а
// вхождений в нём не остаться (перегенерация) — это ловит счёт; файла может не
// быть вовсе — это ловит существование, и только оно.
//
// # Пустая ведомость — ЦЕЛЬ, а не поломка
//
// Отказ на пустой ведомости подталкивал бы держать запись ради зелёного
// (`testing-verdict.md` §4). Поэтому пустая ведомость проходит, а перепись
// печатается всегда: «ноль находок» обязано быть отличимо от «ноль прочитанного».
package repohygiene

import (
	"fmt"
	"sort"
	"strings"
)

// BakedLedgerCensus — объём осмотренного.
type BakedLedgerCensus struct {
	// Entries — записей ведомости прочитано.
	Entries int
	// WithSubject — из них тех, чей файл лежит в дереве.
	WithSubject int
	// TreeFiles — файлов состава дерева осмотрено. Печатается, чтобы «предмета
	// нет» было отличимо от «дерева не прочитали».
	TreeFiles int
}

func (c BakedLedgerCensus) String() string {
	return fmt.Sprintf("перепись: записей ведомости %d; из них с предметом в дереве %d; "+
		"файлов состава осмотрено %d", c.Entries, c.WithSubject, c.TreeFiles)
}

// JudgeBakedLedgerSubjects — у каждой записи ведомости есть предмет в дереве.
//
// inTree отвечает, лежит ли путь в составе дерева. Передаётся вызывающим, чтобы
// инъекция звала ТО ЖЕ, что исполняется на дереве.
func JudgeBakedLedgerSubjects(
	ledger []knownBakedDescriptor,
	inTree func(rel string) bool,
	treeFiles int,
) (stale []string, census BakedLedgerCensus) {
	census.Entries = len(ledger)
	census.TreeFiles = treeFiles

	seen := map[string]bool{}
	for _, e := range ledger {
		if seen[e.File] {
			stale = append(stale, fmt.Sprintf("%s: запись ведомости названа дважды — "+
				"два послабления об одном файле истекут порознь", e.File))
			continue
		}
		seen[e.File] = true

		if !inTree(e.File) {
			stale = append(stale, fmt.Sprintf("%s: файла в дереве НЕТ — послаблению нечего "+
				"прощать. Снимите запись тем же изменением, которым снят её предмет: "+
				"иначе она унаследует следующую слепую зону и простит путь, которого "+
				"никто не заводил", e.File))
			continue
		}
		census.WithSubject++
	}
	sort.Strings(stale)
	return stale, census
}

// FormatBakedLedgerStale — находки одной строкой на запись.
func FormatBakedLedgerStale(stale []string) string {
	var b strings.Builder
	for _, s := range stale {
		b.WriteString("\n  " + s)
	}
	return b.String()
}
