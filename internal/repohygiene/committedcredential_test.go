// committedcredential_test.go — отслеживаемое дерево не несёт предъявительских
// кредов.
//
// # Предмет
//
// Оба репозитория ПУБЛИЧНЫ, и значение считается опубликованным в момент
// КОММИТА, а не пуша (`security.md` §«Публичные артефакты»). Прогон e2e устроен
// так, что креды всё время оказываются вплотную к индексу: `scripts/run.sh`
// материализует рабочий `local.postman_environment.json` копией отслеживаемого
// `*.template.json`, посев ДОПИСЫВАЕТ туда свежие предъявительские токены, а
// newman кладёт рядом отчёт прогона, в который те же токены попадают
// заголовками запросов. Рабочая копия и каталог отчётов объявлены игнорируемыми
// — но игнорирование это ДОГОВОРЁННОСТЬ, которую не соблюдают ни `git add -f`,
// ни новый набор, заведённый без своего правила игнорирования.
//
// Инвариант уже нарушался (PRO-Robotech/kacho#70). Уборка — снятие рабочих
// копий с учёта, правила игнорирования, чистые шаблоны — landed в 73b394ab, но
// проверки, которая удержит это состояние, вместе с ней не завели: «в дереве
// чисто» было свойством последнего коммита, а не свойством, за которым кто-то
// следит.
//
// # Две оси, потому что у каждой своя ложная предпосылка
//
// Ось СЛОТА проверяет ПОЛИТИКУ отслеживаемого шаблона: запись окружения, чьё имя
// обещает кред, обязана нести ПУСТОЕ значение — слот объявлен, значение допишет
// посев в игнорируемую рабочую копию. Её предпосылка — «кред опознаётся по имени
// ключа» — верна ровно до первого ключа, названного иначе.
//
// Ось МАТЕРИАЛА имени не читает вовсе и идёт по ВСЕМУ индексу, а не только по
// окружениям. Так измерено, а не предположено — но измерять надо на том корпусе,
// о котором делается вывод, и здесь первая редакция этого не сделала.
//
// Два корпуса, и путать их нельзя:
//
//   - ВСЁ ХРАНИЛИЩЕ ОБЪЕКТОВ клона (включая объекты, не удерживаемые ни одной
//     ссылкой): материал лежит по 54 путям, из них 7 — файлы окружения, а 47 —
//     отчёты прогонов newman, куда токен попадает заголовком запроса.
//   - ДОСТИЖИМОЕ С origin, то есть опубликованное: путей отчётов прогонов —
//     НОЛЬ. Предикат: перечень всех объектов, достижимых со всех ссылок origin,
//     с их путями; осмотрено 33192 объекта, совпадений по форме пути отчёта — 0.
//
// Первая редакция назвала «54 и 47» там, где речь шла об опубликованном, и тем
// самым завысила предмет. Опубликованный материал лежит ТОЛЬКО в окружениях.
//
// Обоснование оси при этом НЕ отзывается, а становится точнее: отчёты попали в
// объекты потому, что их однажды действительно закоммитили, — и ровно поэтому
// ось не должна ограничиваться окружениями. Ограниченная окружениями, она не
// заметила бы следующий такой коммит в момент, когда он ещё не отправлен, то
// есть тогда, когда его ещё можно снять без переписывания публичной истории.
//
// # Что считается кредом, и почему не «похоже на токен»
//
// Ось материала признаёт находкой только то, что предъявитель мог бы РЕАЛЬНО
// предъявить: подпись обязана быть той длины, которую производит объявленный
// алгоритм. Это не косметика — на этом предикате гейт и разошёлся со своей
// первой редакцией. В дереве лежит затравка фаззера `gateway/internal/fuzz`:
// настоящий по форме DPoP-заголовок `alg=ES256`, у которого подпись — восемь
// символов-заглушки. Запрет «три сегмента и заголовок с alg» краснел бы на ней,
// а ложный срабат снимает гейт целиком. Проверено в обе стороны: правило длины
// молчит на затравке и удерживает ВСЕ 1203 вхождения токенов из истории этого
// репозитория (HS256 с подписью 32 байта, RS256 с подписью 512 байт).
//
// Неизвестный алгоритм — НАХОДКА, а не тишина: у проверки входа корзины «всё
// остальное» не бывает, и «мы не смогли определить» не должно выглядеть как
// «чисто». Сегодня в дереве такого нет (замер ниже это печатает).
//
// # Что здесь считается деревом, и почему это не придирка
//
// Состав корпуса — ИНДЕКС git (`newTrackedTree`, авторитет объявлен в
// `trackedtree_test.go`), содержимое — рабочая копия этих путей. Разделение
// намеренное и несёт обе половины пары:
//
//   - живой `local.postman_environment.json` со свежими токенами лежит рядом с
//     шаблоном на КАЖДОЙ машине, где поднимали стенд. Он не в индексе, значит
//     находки не даёт — иначе гейт краснел бы у того, кто гонял e2e, и молчал
//     в CI, то есть был бы свойством рабочего каталога, а не коммита;
//   - зато отслеживаемый путь читается таким, каков он СЕЙЧАС на диске. Если
//     посев когда-нибудь запишет токен в сам шаблон, гейт скажет об этом ДО
//     коммита, а не после.
//
// # Чего гейт НЕ ловит, названо прямо
//
// Непрозрачный кред без структуры (случайная строка, пароль, ключ API без
// формата) под ключом вне словаря: ось слота его не узнаёт, оси материала не за
// что зацепиться. Необъявленная слепая зона читается как покрытие, поэтому она
// объявлена. Общий симметричный подписной ключ — предмет соседнего гейта
// `sharedsigningliteral_test.go`, здесь он не дублируется.
