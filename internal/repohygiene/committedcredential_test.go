// TestCommittedCredentialGateCutsBothWays — гейт обязан краснеть на внесённом
// креде и МОЛЧАТЬ на законном значении той же формы, лежащем там же.
//
// Дерево здесь НАСТОЯЩЕЕ git-дерево, а не обход каталога: главная половина пары
// — «живая рабочая копия рядом с шаблоном находки не даёт» — про ИНДЕКС, и на
// синтетике, собранной обходом диска, её не показать в принципе.
//
// Материал не берётся из дерева и не кладётся в него: токен собирается здесь же
// из заведомо игрушечных claim'ов, ключ генерируется в памяти. Закоммитить в
// публичный репозиторий настоящий кред ради пробы значило бы совершить ровно то,
// что гейт запрещает. Зато ЗАКОННЫЕ близнецы взяты из настоящего дерева
// дословно: адреса стендов, идентификаторы ресурсов, CIDR, заведомо мусорные id,
// подстановка окружения, затравка фаззера — то, что в живых данных лежит
// вплотную к предмету и на чём предикат уже один раз ошибся.
func TestCommittedCredentialGateCutsBothWays(t *testing.T) {
	root := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		cmd := gitenv.Command(root, args...)
		cmd.Env = append(cmd.Env,
			"GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@example.invalid",
			"GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@example.invalid")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
		}
	}
	write := func(rel, body string) {
		t.Helper()
		mustWrite(t, filepath.Join(root, filepath.FromSlash(rel)), body)
	}
	envDoc := func(kv ...[2]string) string {
		parts := make([]string, 0, len(kv))
		for _, p := range kv {
			k, _ := json.Marshal(p[0])
			v, _ := json.Marshal(p[1])
			parts = append(parts, `{"key":`+string(k)+`,"value":`+string(v)+`,"enabled":true}`)
		}
		return `{"values":[` + strings.Join(parts, ",") + `]}`
	}

	git("init", "-q")
	write("go.mod", "module synthetic\n")
	// Ровно те правила игнорирования, что живут в дереве: рабочая копия
	// окружения и каталог отчётов прогона вне индекса.
	write(".gitignore", "local.postman_environment.json\nout/\n")

	// ── ОТСЛЕЖИВАЕМОЕ: пять внесённых кредов и двенадцать законных близнецов ──
	write("services/demo/tests/newman/environments/local.postman_environment.template.json",
		envDoc(
			// (а) КРАСНОЕ, ось слота: имя обещает кред, значение непусто.
			[2]string{"jwtBootstrap", "not-empty-placeholder"},
			// (б) КРАСНОЕ, ось материала: предъявимый по форме токен под ключом
			//     ВНЕ словаря — ось слота его не увидит by construction.
			[2]string{"warmupPayload", presentableFixtureToken(t, "RS256")},
			// (в) ЗАКОННЫЕ БЛИЗНЕЦЫ — дословно из настоящих окружений дерева.
			[2]string{"baseUrl", "http://localhost:${KACHO_API_GATEWAY_NODEPORT:-30880}"},
			[2]string{"externalBaseUrl", "https://127.0.0.1:18443"},
			[2]string{"existingAccountId", "acc1n3v4gg1xj99064rs"},
			[2]string{"existingSubnetCidr", "10.180.0.0/24"},
			[2]string{"garbageId", "garbage-id-that-does-not-exist"},
			[2]string{"existingZoneId", "ru-central1-a"},
			// (г) ЗАКОННЫЕ БЛИЗНЕЦЫ — пустой слот креда, это и есть норма.
			[2]string{"apiTokenValid", ""},
			[2]string{"jwtSAA", "   "},
			// (д) ЗАКОННЫЙ БЛИЗНЕЦ — не-строка кредом не бывает.
			[2]string{"pollCap", "300"},
		))
	// (е) КРАСНОЕ, ось материала ВНЕ окружений: настоящий приватный ключ в
	//     блочном скаляре YAML — каждая строка с ОТСТУПОМ, ровно как он лёг бы
	//     в профиль развёртывания. Стандартный разбор PEM такую форму не берёт,
	//     и первая редакция предиката её пропускала.
	write("deploy/stand/keys.yaml", "signing: |\n"+indentedPEM(fixturePrivateKeyPEM(t)))
	// (ж) КРАСНОЕ, тот же ключ в другой настоящей форме: строка JSON с
	//     ЭКРАНИРОВАННЫМИ переводами и кавычкой вплотную к метке.
	write("deploy/stand/secret.json",
		`{"signingKeyPem":"`+escapedPEM(fixturePrivateKeyPEM(t))+`"}`)
	// (з) КРАСНОЕ, отчёт прогона В ИНДЕКСЕ: токен приезжает заголовком запроса и
	//     прячется за схемой `Bearer`. Ради ЭТОГО ось и сделана tree-wide: в
	//     хранилище объектов клона 47 из 54 путей с материалом окружениями не
	//     были. На origin таких путей ноль — их сняли до отправки, и ось нужна
	//     именно чтобы следующий такой коммит был замечен в это же окно.
	write("services/demo/tests/newman/report.json",
		`{"run":{"executions":[{"request":{"header":[{"key":"Authorization","value":"Bearer `+
			presentableFixtureToken(t, "ES256")+`"}]}}]}}`)
	// (и) ЗАКОННЫЙ БЛИЗНЕЦ той же формы: метка PEM есть, тела нет. В дереве
	//     таких три (страница документации и две фикстуры). Гейт по метке
	//     краснел бы на них и был бы снят первым же ложным срабатыванием.
	write("docs/tokens.md",
		"privateKeyPem: \"-----BEGIN PRIVATE KEY-----\\n… (показывается один раз) …\\n-----END PRIVATE KEY-----\"\n")
	// (к) ЗАКОННЫЙ БЛИЗНЕЦ: три сегмента через точку, но это не токен.
	write("internal/demo/wire.go",
		"package demo\n\n// runner.suite.case — координата кейса, не токен\nconst Coord = \"runner.suite.case\"\n")
	// (л) ЗАКОННЫЙ БЛИЗНЕЦ, на котором предикат уже ошибался: затравка фаззера.
	//     Заголовок настоящий (`alg=ES256`), нагрузка настоящая, подпись —
	//     заглушка. Такой строкой нельзя воспользоваться; красное здесь сняло бы
	//     гейт целиком. Проба обязана удержать ИМЕННО это различие.
	write("internal/demo/fuzz_seed_test.go",
		"package demo\n\nvar seeds = []string{\n\t\""+unpresentableSeedToken(t, "ES256")+"\",\n}\n")

	git("add", "-A")
	git("-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-q", "-m", "fixture")

	// ── НЕ ОТСЛЕЖИВАЕМОЕ: следы прогона, которые лежат на КАЖДОЙ машине, где
	//    поднимали стенд. Оба несут предъявимый токен и оба обязаны остаться
	//    НЕЗАМЕЧЕННЫМИ: вердикт гейта — свойство коммита. ──
	write("services/demo/tests/newman/environments/local.postman_environment.json",
		envDoc([2]string{"jwtBootstrap", presentableFixtureToken(t, "HS256")}))
	write("services/demo/tests/newman/out/demo.json",
		`{"run":{"executions":[{"request":{"header":[{"key":"Authorization","value":"Bearer `+
			presentableFixtureToken(t, "HS256")+`"}]}}]}}`)

	scan, err := scanCommittedCredentials(newTrackedTree(t, root), credentialKeyVocabulary)
	if err != nil {
		t.Fatalf("обход синтетического дерева: %v", err)
	}

	// Корпус — из ИНДЕКСА. Девять отслеживаемых файлов, два следа прогона мимо.
	if scan.indexFiles != 9 {
		t.Fatalf("в индексе %d файл(ов), ожидалось 9 — корпус собран не из индекса, "+
			"и тогда вердикт стал свойством рабочего каталога, а не коммита", scan.indexFiles)
	}
	if scan.envFiles != 1 {
		t.Fatalf("прочитано файлов окружения %d, а отслеживается 1 — рабочая копия "+
			"с живым токеном попала в корпус: гейт краснел бы у того, кто гонял e2e, "+
			"и молчал бы в CI", scan.envFiles)
	}
	// Затравка обязана дойти ДО правила длины, иначе её «тишина» ничего не
	// доказывает: молчать можно и потому, что до решения никто не добрался.
	// Отслеживаемых JWS-форм ровно три — токен под `warmupPayload`, токен в
	// отчёте прогона и затравка фаззера; две формы в следах прогона в корпус не
	// входят и сюда не считаются.
	if scan.jwsShaped != 3 {
		t.Fatalf("до решения о длине подписи дошло %d кандидат(а|ов), а отслеживаемых "+
			"JWS-форм внесено три (warmupPayload, отчёт прогона и затравка фаззера) — "+
			"значит тишина на затравке достигнута не тем предикатом, который её объясняет",
			scan.jwsShaped)
	}

	type coord struct{ rel, key string }
	got := map[coord]string{}
	for _, f := range scan.findings {
		got[coord{f.rel, f.key}] = f.axis
	}

	// ── КРАСНОЕ, и с координатой ──
	for c, wantAxis := range map[coord]string{
		{"services/demo/tests/newman/environments/local.postman_environment.template.json", "jwtBootstrap"}: credentialAxisSlot,
		{"services/demo/tests/newman/environments/local.postman_environment.template.json", ""}:             credentialAxisMaterial,
		{"deploy/stand/keys.yaml", ""}:                 credentialAxisMaterial,
		{"deploy/stand/secret.json", ""}:               credentialAxisMaterial,
		{"services/demo/tests/newman/report.json", ""}: credentialAxisMaterial,
	} {
		axis, found := got[c]
		if !found {
			t.Errorf("внесённый кред (%s%s) НЕ найден — гейт не краснеет на своём предмете",
				c.rel, credentialKeySuffix(c.key))
			continue
		}
		if axis != wantAxis {
			t.Errorf("находка (%s%s) отнесена к оси %q, ожидалась %q",
				c.rel, credentialKeySuffix(c.key), axis, wantAxis)
		}
	}

	// ── ТИШИНА: законные близнецы и следы прогона ──
	for _, rel := range []string{
		"docs/tokens.md",
		"internal/demo/wire.go",
		"internal/demo/fuzz_seed_test.go",
		"services/demo/tests/newman/environments/local.postman_environment.json",
		"services/demo/tests/newman/out/demo.json",
	} {
		for c, axis := range got {
			if c.rel == rel {
				t.Errorf("%s объявлен находкой (ось %q, ключ %q) — гейт ловит форму, "+
					"а не существо, и первый же ложный срабат его отключит", rel, axis, c.key)
			}
		}
	}
	for _, key := range []string{
		"baseUrl", "externalBaseUrl", "existingAccountId", "existingSubnetCidr",
		"garbageId", "existingZoneId", "apiTokenValid", "jwtSAA", "pollCap",
	} {
		for c, axis := range got {
			if c.key == key {
				t.Errorf("законное значение под ключом %q объявлено находкой (ось %q)", key, axis)
			}
		}
	}
	if len(scan.findings) != 5 {
		t.Errorf("находок %d, ожидалось ровно 5 внесённых: лишние — ложные срабатывания, "+
			"недостающие — слепая зона. Находки:\n%s", len(scan.findings), scan.render())
	}

	// ── ОСЬ МАТЕРИАЛА НЕЗАВИСИМА ОТ СЛОВАРЯ ИМЁН ──
	//
	// Без этой проверки «две оси» остались бы объявлением: ось материала могла
	// бы срабатывать только на тех же ключах, что и первая, и её вклад был бы
	// нулевым — ровно та слепая зона, ради закрытия которой она заведена.
	blind, err := scanCommittedCredentials(newTrackedTree(t, root), blindVocabulary)
	if err != nil {
		t.Fatalf("обход синтетического дерева со снятым словарём: %v", err)
	}
	if blind.credentialSlots != 0 {
		t.Errorf("словарь снят, а слотов насчитано %d — перепись читает не тот предикат, "+
			"что проверка", blind.credentialSlots)
	}
	if blind.countAxis(credentialAxisSlot) != 0 {
		t.Error("словарь снят, а ось слота всё ещё даёт находки — она читает не имя ключа")
	}
	if blind.countAxis(credentialAxisMaterial) != 4 {
		t.Errorf("со снятым словарём ось материала дала находок %d, ожидалось 4 — значит "+
			"она зависит от имени ключа, и предпосылка «кред опознаётся по имени» ничем "+
			"не подстрахована.\n%s", blind.countAxis(credentialAxisMaterial), blind.render())
	}
}

func credentialKeySuffix(key string) string {
	if key == "" {
		return ""
	}
	return " → " + key
}

// presentableFixtureToken — заведомо игрушечный токен, ПРЕДЪЯВИМЫЙ по форме.
//
// Форма взята у настоящих: три сегмента base64url, заголовок с `alg`, нагрузка
// с `sub`/`iat`/`exp`/`iss`, подпись той длины, которую производит алгоритм.
// Материала при этом нет — байты подписи случайны: гейт судит по ФОРМЕ и обязан
// краснеть и на неподписанном самозванце, потому что отличить его от утёкшего
// можно только у выдающего, а к тому моменту токен уже опубликован.
func presentableFixtureToken(t *testing.T, alg string) string {
	t.Helper()
	sigLen := exactSignatureBytes[alg]
	if sigLen == 0 {
		if !rsaSignatureAlgs[alg] {
			t.Fatalf("проба просит токен с алгоритмом %q, которого нет ни в одном перечне длин", alg)
		}
		sigLen = 256 // RSA-2048, самый обычный размер у выдающего
	}
	sig := make([]byte, sigLen)
	if _, err := rand.Read(sig); err != nil {
		t.Fatalf("сборка подписи для пробы: %v", err)
	}
	return fixtureJWSPrefix(t, alg) + "." + base64.RawURLEncoding.EncodeToString(sig)
}

// unpresentableSeedToken — затравка фаззера: заголовок и нагрузка настоящие,
// подпись — заглушка неправильной длины. Ровно та форма, что лежит в
// `gateway/internal/fuzz`, и ровно тот вход, на котором первая редакция
// предиката давала ложное срабатывание.
func unpresentableSeedToken(t *testing.T, alg string) string {
	t.Helper()
	return fixtureJWSPrefix(t, alg) + "." + base64.RawURLEncoding.EncodeToString([]byte("stub-sig"))
}

// fixtureJWSPrefix — «заголовок.нагрузка» игрушечного токена.
func fixtureJWSPrefix(t *testing.T, alg string) string {
	t.Helper()
	b64 := func(v any) string {
		raw, err := json.Marshal(v)
		if err != nil {
			t.Fatalf("сборка игрушечного токена: %v", err)
		}
		return base64.RawURLEncoding.EncodeToString(raw)
	}
	head := b64(map[string]string{"alg": alg, "typ": "JWT"})
	body := b64(map[string]any{
		"sub": "synthetic-fixture", "iss": "gate-injection", "iat": 0, "exp": 1,
	})
	return head + "." + body
}

// indentedPEM — тот же блок внутри блочного скаляра YAML: каждая строка с
// отступом. Отдельным помощником, чтобы форма была видна в пробе, а не спрятана
// в конкатенации.
func indentedPEM(block string) string {
	return "  " + strings.ReplaceAll(strings.TrimRight(block, "\n"), "\n", "\n  ") + "\n"
}

// escapedPEM — тот же блок одной строкой с экранированными переводами: так он
// выглядит внутри значения JSON и внутри литерала Go.
func escapedPEM(block string) string {
	return strings.ReplaceAll(strings.TrimRight(block, "\n"), "\n", `\n`)
}

// fixturePrivateKeyPEM — НАСТОЯЩИЙ приватный ключ, сгенерированный в памяти на
// время пробы.
//
// Настоящий, потому что предикат структурный: он разбирает тело блока, и
// заглушка его не проверила бы — проба на заглушке была бы вакуумной. Ключ
// никуда не сохраняется и умирает вместе с процессом теста; P-256 выбран за
// мгновенную генерацию (RSA под `-race` стоил бы десятые доли секунды на каждом
// прогоне пакета).
func fixturePrivateKeyPEM(t *testing.T) string {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("генерация ключа для пробы: %v", err)
	}
	der, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		t.Fatalf("сериализация ключа для пробы: %v", err)
	}
	out := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: der})
	if out == nil {
		t.Fatal("сборка PEM для пробы вернула пусто")
	}
	return string(out)
}
