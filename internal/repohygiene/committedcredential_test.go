// TestNoCommittedCredentialMaterial — ось МАТЕРИАЛА по всему индексу.
func TestNoCommittedCredentialMaterial(t *testing.T) {
	scan := mustRepoCredentialScan(t)

	// Предпосылка 1: индекс непуст.
	if scan.indexFiles == 0 {
		t.Fatal("индекс пуст — смотреть было не на что. «Ноль находок» здесь означало бы " +
			"«ноль прочитанного»: гейт запущен вне рабочего дерева git либо git недоступен")
	}
	// Предпосылка 2: перепись не обвалилась. Порог берётся у соседнего гейта,
	// который читает ТОТ ЖЕ корпус по той же причине, — одно значение на двоих,
	// чтобы они не разошлись.
	if scan.filesRead < sharedSigningLiteralCensusFloor {
		t.Fatalf("перепись обвалилась: прочитано %d файлов индекса при пороге %d — "+
			"вердикт «ноль находок» на таком объёме означал бы «ноль прочитанного»",
			scan.filesRead, sharedSigningLiteralCensusFloor)
	}
	// Предпосылка 3: прочитано ВСЁ, что в индексе. Число, а не молчание:
	// частичный checkout или битый симлинк — это «не проверили», а не «чисто».
	if scan.unreadable > 0 {
		t.Fatalf("в индексе %d файл(ов), прочитано %d, не прочитано %d — гейт судит "+
			"о дереве, которого не видел целиком", scan.indexFiles, scan.filesRead, scan.unreadable)
	}
	// Предпосылка 4: ветвь материала ИСПОЛНЯЛАСЬ. Ноль сработываний предфильтра
	// на сотне мегабайт индекса означает, что байты через ось не прошли, — и
	// тогда её «ноль находок» ничего не утверждает.
	if scan.jwsTruncated > 0 {
		t.Fatalf("%d кандидат(ов) отсечено по потолку длины сегмента (%d символов) — "+
			"это «не проверили», а не «чисто»: пропущенный из-за потолка кандидат и есть "+
			"тот вид слепоты, который здесь ловится. Потолок и его обоснование "+
			"пересматриваются вместе", scan.jwsTruncated, jwsSegmentScanCap)
	}
	// Предпосылка 5: у оси материала есть ЖИВОЕ упражнение на настоящем дереве.
	//
	// «Не с чем сверить» здесь означает «не проверили», а не «чисто»: если из
	// начал заголовка не собралось ни одного трёхсегментного кандидата, ось
	// молчит, ни разу не дойдя до решения, и отличить это от сломанного разбора
	// нечем. Сегодня кандидатов пять — все синтетические затравки с подписью-
	// заглушкой. Исчезнут все до одного (затравки убрали, разбор сломался) — это
	// повод посмотреть, а не зелёный вердикт.
	if scan.jwsCandidates == 0 {
		t.Fatalf("на %d файл(ах) (%d байт) от начал заголовка не собралось НИ ОДНОГО "+
			"трёхсегментного кандидата — ось материала ни разу не дошла до решения, и "+
			"её молчание неотличимо от сломанного разбора. Если синтетические затравки "+
			"действительно убраны из дерева, эта предпосылка снимается вместе с ними; "+
			"пока они есть, ноль означает поломку", scan.filesRead, scan.bytesRead)
	}

	// Перепись печатается всегда, в том числе на зелёном, и ПО КАЖДОЙ ветви.
	t.Logf("осмотрено: файлов индекса %d, прочитано %d (%d байт); кандидатов от начал "+
		"заголовка %d, из них разобралось как JWS %d, отсечено по потолку длины %d; "+
		"меток PEM %d; находок материала %d",
		scan.indexFiles, scan.filesRead, scan.bytesRead,
		scan.jwsCandidates, scan.jwsShaped, scan.jwsTruncated, scan.pemMarkers,
		scan.countAxis(credentialAxisMaterial))

	// «Ноль меток PEM» и «ноль JWS-форм» отказом НЕ являются: это желаемое
	// состояние, а не несделанная работа. Положительный контроль обеих ветвей —
	// инъекция TestCommittedCredentialGateCutsBothWays, где и токен, и ключ
	// настоящие по форме и разбираются.

	reportCredentialFindings(t, scan, credentialAxisMaterial,
		"предъявимый кред лежит в ОТСЛЕЖИВАЕМОМ дереве")
}

