// TestJWSHeaderPrefixSetIsComplete — предпосылка ПОИСКА НАЧАЛА, выведенная заново.
//
// Набор начал решает, что вообще попадёт в разбор. Ошибись он в одну тройку — и
// целый вид заголовка станет невидим, а гейт останется зелёным и будет числиться
// работающим: молчание неотличимо от чистого дерева. Поэтому набор не
// объявляется верным, а перебирается здесь — и перебирается ДВАЖДЫ, на двух
// уровнях, потому что одного уровня для такого утверждения не хватает.
//
// Уровень 1 — КОДИРОВАНИЕ, исчерпывающе: все допустимые пробельные начала
// JSON-объекта × весь диапазон третьего байта 0x00..0xFF. Проверяется только
// арифметика base64, поэтому байт может быть любым, в том числе не образующим
// корректный JSON.
//
// Уровень 2 — ВЕСЬ ПУТЬ, на настоящих заголовках: от каждого реального начала
// строится предъявимый токен, и гейт обязан его НАЙТИ. Первый уровень один
// доказывал бы только свойство таблицы; сломайся разбор вперёд — он остался бы
// зелёным.
//
// Отрицание в паре с положительным: рядом проба того, что поиск не стал
// всеразрешающим — строки, токенами не являющиеся, кандидатов не дают. Без неё
// набор из одной пустой тройки прошёл бы «проверку полноты» с блеском.
func TestJWSHeaderPrefixSetIsComplete(t *testing.T) {
	covered := func(encoded string) bool {
		for _, p := range jwsHeaderPrefixes {
			if strings.HasPrefix(encoded, string(p)) {
				return true
			}
		}
		return false
	}

	// ── Уровень 1: арифметика кодирования, исчерпывающе по ГРАММАТИКЕ ──
	//
	// Перебор идёт по тому, что вообще может стоять в первых трёх байтах
	// сериализованного JSON-объекта, а не по всем 256^2 сочетаниям: после `{`
	// стоит либо кавычка имени первого члена, либо пробельный символ, и после
	// пробельного — снова пробельный либо кавычка. Перебор «любой байт после
	// пробела» был бы перебором строк, JSON-объектами не являющихся, и требовал
	// бы покрывать начала, которых у заголовка быть не может. Пустой объект
	// `{}` из перебора исключён по существу: он не несёт `alg`, а значит и не
	// заголовок.
	whitespace := []byte{' ', '\t', '\n', '\r'}
	var heads [][]byte
	// (а) имя первого члена сразу за скобкой: третий байт — ЛЮБОЙ.
	for b := 0; b <= 0xFF; b++ {
		heads = append(heads, []byte{'{', '"', byte(b)})
	}
	// (б) пробельный символ за скобкой: третий байт — снова пробельный либо кавычка.
	for _, w := range whitespace {
		for _, next := range append(append([]byte{}, whitespace...), '"') {
			heads = append(heads, []byte{'{', w, next})
		}
	}
	checked, missed := 0, 0
	for _, head := range heads {
		encoded := base64.RawURLEncoding.EncodeToString(head)
		checked++
		if covered(encoded) {
			continue
		}
		missed++
		if missed <= 3 {
			t.Errorf("начало заголовка %q кодируется в %q — тройка %q не покрыта "+
				"набором jwsHeaderPrefixes: целый вид заголовка невидим поиску, "+
				"и «ноль находок» по нему ничего не значит", head, encoded, encoded[:3])
		}
	}
	if missed > 0 {
		t.Fatalf("не покрыто %d начал(а) из %d перебранных", missed, checked)
	}

	// ── Уровень 2: весь путь на настоящих заголовках ──
	//
	// Каждый из них — валидный JSON-объект с `alg`, каждый кодируется в своё
	// начало, и от каждого гейт обязан собрать кандидата и признать его
	// предъявимым.
	realHeaders := []string{
		`{"alg":"RS256","typ":"JWT"}`, // компактный, самый обычный
		`{"typ":"JWT","alg":"HS256"}`, // alg не первым членом
		`{"0kid":"x","alg":"ES256"}`,  // имя члена с цифры  → eyI
		`{"_x":1,"alg":"HS256"}`,      // имя члена с подчёркивания
		`{"кид":"x","alg":"RS256"}`,   // имя члена не-ASCII → eyL
		`{ "alg":"HS256"}`,            // пробел после скобки → eyA
		"{\t\"alg\":\"HS256\"}",       // табуляция          → ewk
		"{\n\"alg\":\"HS256\"}",       // перевод строки     → ewo
		"{\r\"alg\":\"HS256\"}",       // возврат каретки    → ew0
	}
	for _, header := range realHeaders {
		var probe map[string]any
		if json.Unmarshal([]byte(header), &probe) != nil {
			t.Fatalf("заголовок пробы %q сам не является JSON-объектом — проба беспредметна", header)
		}
		alg, _ := probe["alg"].(string)
		sig := make([]byte, exactSignatureBytes[alg])
		if len(sig) == 0 {
			sig = make([]byte, 256)
		}
		token := base64.RawURLEncoding.EncodeToString([]byte(header)) + "." +
			base64.RawURLEncoding.EncodeToString([]byte(`{"sub":"synthetic-fixture"}`)) + "." +
			base64.RawURLEncoding.EncodeToString(sig)

		var found []string
		haystack := []byte(`{"someKey":"` + token + `"}`)
		n, cut := forEachJWSCandidate(haystack, func(c string) { found = append(found, c) })
		if cut != 0 {
			t.Errorf("заголовок %q: разбор упёрся в потолок длины — кандидат потерян", header)
		}
		if n == 0 || !slicesContains(found, token) {
			t.Errorf("заголовок %q (начало %q) НЕ найден разбором вперёд: кандидатов %d — "+
				"набор начал покрывает кодирование, но путь до кандидата разорван",
				header, token[:3], n)
			continue
		}
		if _, presentable := presentableToken(token); !presentable {
			t.Errorf("заголовок %q: кандидат найден, но признан непредъявимым — предикат "+
				"отвергает настоящий токен", header)
		}
	}

	t.Logf("набор начал полон: перебрано %d начал (уровень кодирования) и %d настоящих "+
		"заголовков (весь путь), не покрыто 0", checked, len(realHeaders))

	// ── Положительный контроль: поиск не стал всеразрешающим ──
	for _, notAToken := range []string{
		"a.b.c", "10.180.0.0/24", "runner.suite.case", "acc1n3v4gg1xj99064rs",
		"github.com/PRO-Robotech/kacho", "eyJ.eyJ", "",
	} {
		if n, _ := forEachJWSCandidate([]byte(notAToken), func(string) {}); n != 0 {
			t.Errorf("на строке %q собрано %d кандидат(ов) — поиск перестал отсеивать, "+
				"и вся его экономия обернулась тишиной о том, чего он не проверял",
				notAToken, n)
		}
	}
}

// slicesContains — без зависимости от порядка обхода набора начал.
func slicesContains(hay []string, needle string) bool {
	for _, h := range hay {
		if h == needle {
			return true
		}
	}
	return false
}

func reportCredentialFindings(t *testing.T, scan credentialScan, axis, headline string) {
	t.Helper()
	var lines []string
	for _, f := range scan.findings {
		if f.axis == axis {
			lines = append(lines, f.String())
		}
	}
	if len(lines) == 0 {
		return
	}
	t.Errorf("находок %d — %s:\n%s\n\n%s",
		len(lines), headline, strings.Join(lines, "\n"), credentialFixMessage)
}

