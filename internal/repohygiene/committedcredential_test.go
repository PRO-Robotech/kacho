// credentialKeyVocabulary — имена, по которым узнаётся СЛОТ креда в файле
// окружения.
//
// Словарь рукописный, и это осознанно: породить его неоткуда. Посев объявляет
// свои ключи питоновским словарным литералом вперемешку с идентификаторами
// ресурсов (`tests/authz-fixtures/prodseed_matrix.py`), то есть объявления «вот
// это креды» в дереве не существует. Взамен рукописности — две страховки:
// предпосылка словаря проверяется отдельным тестом (у него обязан остаться
// предмет), а материал ловится второй осью, которая имени не читает.
//
// В словарь взяты только СУЩЕСТВИТЕЛЬНЫЕ, которые в окружении набора
// практически всегда означают кред. Намеренно НЕ взяты `auth` и одиночный `key`:
// `authMode`, `keyPrefix`, `idempotencyKey` — законные непустые значения, а
// ложный срабат здесь дороже пропуска (гейт, краснеющий на законном, снимают
// целиком). Материал под такими именами всё равно поймает вторая ось.
var credentialKeyVocabulary = regexp.MustCompile(
	`(?i)jwt|token|secret|password|passwd|bearer|credential|apikey|api_key|` +
		`privatekey|private_key|signingkey|signing_key|accesskey|access_key|passphrase`)

// blindVocabulary — словарь, не совпадающий ни с одним именем. Нужен инъекции,
// чтобы показать: ось материала работает и при полностью снятой оси слота.
// Отдельная переменная, а не подмена `credentialKeyVocabulary` на время теста:
// глобальная подмена связала бы тесты пакета между собой и рассыпалась бы от
// первого `t.Parallel()`.
var blindVocabulary = regexp.MustCompile(`\A\z`)

// jwsHeaderPrefixes — ПОЛНЫЙ набор трёхсимвольных начал, с которых способен
// начаться заголовок компактного JWS. По ним и только по ним ищется токен: разбор
// идёт ВПЕРЁД от найденного начала, а не автоматом по всему файлу.
//
// Набор ВЫВЕДЕН из кодирования, а не подобран по дереву. Заголовок — base64url
// сериализованного JSON-ОБЪЕКТА, значит его первый байт `{` (0x7B), и первый
// символ кодирования всегда `e` (0x7B>>2 = 30). Второй и третий символы
// определяются следующими двумя байтами, а те у JSON-объекта могут быть только
// пробельными или открывающей кавычкой имени первого члена. Полный перебор всех
// таких начал — включая имена, начинающиеся с цифры и с не-ASCII, — даёт ровно
// эти восемь троек и ничего сверх.
//
// Полнота не заявлена, а ПРОВЕРЯЕТСЯ (TestJWSHeaderPrefixSetIsComplete): начала
// перебираются заново, и в паре с этим строится настоящий токен от каждого
// РЕАЛЬНОГО начала — гейт обязан его найти. Без этого предфильтр был бы
// догадкой, тихо решающей за предикат.
//
// Набор — надмножество достижимого, и это намеренно: `eyK` соответствует
// продолжающему байту UTF-8 (0x80..0xBF), которым имя члена начаться не может.
// Полнота здесь дороже минимальности — лишняя тройка стоит одного поиска
// подстроки, а недостающая делает целый вид заголовка невидимым.
//
// Стоимость измерена на этом дереве (113.7 МБ индекса, 6146 файлов): начал
// заголовка 530, трёхсегментных кандидатов из них 5. Прежняя редакция гоняла по
// индексу автомат регулярного выражения и стоила 75 c под детектором гонок —
// пакет гейтов уже однажды не уложился в свой бюджет (`reachabilitycost_test.go`),
// поэтому цена здесь не косметика.
var jwsHeaderPrefixes = [][]byte{
	[]byte("eyJ"), // {"<буква|_|любой байт 0x40..0x7F>
	[]byte("eyI"), // {"<цифра|любой байт 0x00..0x3F>
	[]byte("eyK"), // {"<не-ASCII, 0x80..0xBF>
	[]byte("eyL"), // {"<не-ASCII, 0xC0..0xFF>
	[]byte("eyA"), // {<пробел>
	[]byte("ewk"), // {<таб>
	[]byte("ewo"), // {<перевод строки>
	[]byte("ew0"), // {<возврат каретки>
}

// pemBeginLiteral — буквальный префикс метки PEM. Это НЕ отдельное допущение:
// подстрока входит в само `pemPrivateKeyMarker`, поэтому файл без неё не мог бы
// дать совпадения и в полном разборе. Отсев по ней снимает проход автомата по
// индексу целиком: метка есть в 8 файлах из 6146 (0.116 МБ из 113.7 МБ).
var pemBeginLiteral = []byte("-----BEGIN ")

// jwsSegmentScanCap — потолок длины ОДНОГО сегмента при разборе вперёд.
//
// Он про стоимость, а не про предикат: без него длинный непрерывный пробег
// base64 (замок пакетов, вложенный дескриптор) сканировался бы заново от каждого
// начала внутри него. Значение выбрано на два порядка выше любого настоящего
// сегмента: самый длинный токен в истории этого дерева — 413 символов ЦЕЛИКОМ,
// подпись RSA-4096 — 683 символа.
//
// Отсечение по потолку — ОТКАЗ гейта, а не тишина. Сегодня оно не наступает ни
// разу, и «отсечено по длине» не должно молча превращаться в «не найдено»:
// пропущенный из-за потолка кандидат — ровно тот вид слепоты, который здесь
// ловится. Наступит — потолок и его обоснование пересматриваются вместе.
const jwsSegmentScanCap = 1 << 16

// isBase64URL — алфавит сегмента JWS.
func isBase64URL(c byte) bool {
	return c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-' || c == '_'
}

// jwsSpan — от позиции start вперёд лежит `сегмент.сегмент.сегмент`; возвращает
// его конец. `truncated` означает «упёрлись в потолок», а не «не нашли».
func jwsSpan(raw []byte, start int) (end int, ok bool, truncated bool) {
	i := start
	for seg := 0; seg < 3; seg++ {
		if seg > 0 {
			if i >= len(raw) || raw[i] != '.' {
				return i, false, false
			}
			i++
		}
		segStart := i
		for i < len(raw) && isBase64URL(raw[i]) {
			i++
			if i-segStart > jwsSegmentScanCap {
				return i, false, true
			}
		}
		if i == segStart {
			return i, false, false
		}
	}
	return i, true, false
}

// forEachJWSCandidate — обход всех возможных НАЧАЛ токена в байтах.
//
// Разбор идёт ВПЕРЁД от начала заголовка, а не автоматом по всему файлу.
// Причина измерена: в индексе 113.7 МБ, а возможных начал заголовка — 530.
// Автомат регулярного выражения под детектором гонок стоил на этом дереве
// десятки секунд, а пакет гейтов уже однажды не уложился в свой бюджет
// (`reachabilitycost_test.go`). Позиция начала берётся поиском подстроки —
// векторной реализацией, которая инструментируется одним обращением на вызов,
// а не одним на байт.
//
// Смещение продвигается на один символ, а не на конец кандидата: начало
// заголовка встречается и ВНУТРИ чужого токена, и пропускать такие позиции
// значило бы решать за предикат.
func forEachJWSCandidate(raw []byte, visit func(string)) (candidates, truncated int) {
	for _, needle := range jwsHeaderPrefixes {
		for off := 0; off < len(raw); {
			i := bytes.Index(raw[off:], needle)
			if i < 0 {
				break
			}
			start := off + i
			off = start + 1
			end, ok, cut := jwsSpan(raw, start)
			if cut {
				truncated++
				continue
			}
			if !ok {
				continue
			}
			candidates++
			visit(string(raw[start:end]))
		}
	}
	return candidates, truncated
}

// base64URLSegment — сегмент JWS целиком (для разбора значения окружения, где
// строка известна полностью и предфильтр не нужен).
var base64URLSegment = regexp.MustCompile(`^[A-Za-z0-9_-]*$`)

// pemPrivateKeyMarker — предфильтр PEM-блока. Метка сужена до `PRIVATE KEY`:
// `BEGIN CERTIFICATE` — публичный материал, красное на нём было бы ложным
// срабатыванием. Как и выше, решает не он, а разбор.
var pemPrivateKeyMarker = regexp.MustCompile(`-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----`)

// exactSignatureBytes — длина подписи в байтах, однозначно заданная алгоритмом.
// Значения не подобраны, а следуют из самих алгоритмов: HMAC отдаёт полный
// дайджест своей хеш-функции, ECDSA — пару координат размера кривой, Ed25519 —
// 64 байта.
var exactSignatureBytes = map[string]int{
	"HS256": 32, "HS384": 48, "HS512": 64,
	"ES256": 64, "ES384": 96, "ES512": 132,
	"EdDSA": 64,
}

// rsaSignatureAlgs — алгоритмы, у которых длина подписи равна размеру модуля и
// потому переменна. Нижняя граница 128 байт — это RSA-1024, ключ короче которого
// не производит ни одна библиотека, способная подписать JWS.
var rsaSignatureAlgs = map[string]bool{
	"RS256": true, "RS384": true, "RS512": true,
	"PS256": true, "PS384": true, "PS512": true,
}

const rsaMinSignatureBytes = 128

// credentialFinding — одна находка.
//
// Материал значения здесь НЕ хранится и никуда не печатается. Вывод гейта
// уезжает в журнал CI ПУБЛИЧНОГО репозитория: напечатанный кред был бы
// опубликован повторно — самой проверкой, которая его запрещает. Координаты
// (путь + ключ) хватает, чтобы починить, и не хватает, чтобы воспользоваться.
type credentialFinding struct {
	rel  string // путь от корня репозитория
	key  string // ключ записи окружения; пусто для находки в произвольном файле
	axis string // credentialAxisSlot | credentialAxisMaterial
	what string // чем опознано
}

const (
	credentialAxisSlot     = "слот"
	credentialAxisMaterial = "материал"
)

func (f credentialFinding) String() string {
	where := f.rel
	if f.key != "" {
		where += " → " + f.key
	}
	return "  " + where + "  [ось: " + f.axis + "] — " + f.what
}

// credentialScan — результат ОДНОГО обхода вместе с переписью осмотренного.
//
// Перепись ведётся ПО КАЖДОЙ ветви отдельно. Одно общее «осмотрено N» скрыло бы
// ровно тот случай, ради которого перепись и заводят: одна ось молчит потому,
// что чисто, другая — потому, что её предмет вообще не читался.
type credentialScan struct {
	indexFiles int   // файлов в индексе
	filesRead  int   // ...из них прочитано с диска
	unreadable int   // ...и не прочитано (нет на диске, нет прав)
	bytesRead  int64 // ...и сколько это байтов — объём, прошедший через обе оси

	jwsCandidates int // трёхсегментных кандидатов от начал заголовка — ветвь исполнялась
	jwsShaped     int // ...из них разобралось как JWS (заголовок+нагрузка — JSON-объекты)
	jwsTruncated  int // ...и отсечено по потолку длины сегмента (не «не найдено»)
	pemMarkers    int // найдено меток PEM-блока приватного ключа

	envFiles        int // файлов окружения newman в индексе
	envValues       int // записей values[] в них
	credentialSlots int // ...из них с именем из словаря — предмет оси слота
	envNonEmpty     int // непустых строковых значений, прогнанных через разбор формы

	findings []credentialFinding
}

func (s credentialScan) countAxis(axis string) int {
	n := 0
	for _, f := range s.findings {
		if f.axis == axis {
			n++
		}
	}
	return n
}

func (s credentialScan) render() string {
	lines := make([]string, 0, len(s.findings))
	for _, f := range s.findings {
		lines = append(lines, f.String())
	}
	return strings.Join(lines, "\n")
}

// newmanEnvFile — путь принадлежит окружению набора newman.
//
// Предикат по РОЛИ каталога, а не по подстроке имени: `…/tests/newman/
// environments/<что угодно>.json`. Так в корпус попадают и шаблоны, и
// отслеживаемые окружения стендов (`kind-stand`, `fe3455`) — они не
// игнорируются и уезжают в коммит ровно так же.
func newmanEnvFile(rel string) bool {
	rel = filepath.ToSlash(rel)
	return strings.HasSuffix(rel, ".json") && strings.Contains(rel, "/tests/newman/environments/")
}

// presentableToken — строка является JWS, который предъявитель мог бы РЕАЛЬНО
// предъявить. Возвращает объявленный алгоритм.
//
// Разбор структурный на всех трёх сегментах:
//
//  1. заголовок декодируется из base64url в JSON-ОБЪЕКТ с непустым `alg`;
//  2. полезная нагрузка декодируется в JSON-объект (это отсекает `a.b.c` из
//     кода, координаты вида `runner.suite.case`, идентификаторы и CIDR);
//  3. подпись декодируется, и её длина соответствует алгоритму.
//
// Третий пункт — не украшение. Он отделяет кред от синтетической затравки
// фаззера, у которой заголовок настоящий, а подпись — заглушка: такой строкой
// нельзя воспользоваться, её отвергнет любой проверяющий ещё до обращения к
// ключу. Неизвестный алгоритм признаётся находкой (fail-closed): «не смогли
// определить» не должно выглядеть как «чисто».
//
// `alg=none` кредом НЕ считается: незаверенный токен в этом продукте не
// принимает никто (край требует RS256 от выдающего), и красное на нём было бы
// красным о строке, которой нельзя воспользоваться.
func presentableToken(s string) (string, bool) {
	parts := strings.Split(s, ".")
	if len(parts) != 3 || parts[0] == "" || parts[1] == "" {
		return "", false
	}
	for _, p := range parts {
		if !base64URLSegment.MatchString(p) {
			return "", false
		}
	}
	var hdr map[string]any
	if !decodeB64JSONObject(parts[0], &hdr) {
		return "", false
	}
	alg, _ := hdr["alg"].(string)
	if alg == "" || alg == "none" {
		return "", false
	}
	var payload map[string]any
	if !decodeB64JSONObject(parts[1], &payload) {
		return "", false
	}
	sig, err := base64.RawURLEncoding.DecodeString(parts[2])
	if err != nil {
		return "", false
	}
	switch {
	case exactSignatureBytes[alg] != 0:
		return alg, len(sig) == exactSignatureBytes[alg]
	case rsaSignatureAlgs[alg]:
		return alg, len(sig) >= rsaMinSignatureBytes && len(sig)%8 == 0
	default:
		// Алгоритм не из перечня. Классифицировать нечем, а корзины «всё
		// остальное» у проверки входа не бывает: отвечаем находкой.
		return alg, true
	}
}

// jwsShaped — строка разобралась как JWS независимо от того, признана ли она
// предъявимой. Нужно ТОЛЬКО для переписи: «сколько кандидатов дошло до решения
// о длине подписи». Без этого числа нельзя отличить «правило длины отсеяло» от
// «до правила длины никто не дошёл».
func jwsShaped(s string) bool {
	parts := strings.Split(s, ".")
	if len(parts) != 3 || parts[0] == "" || parts[1] == "" {
		return false
	}
	var hdr, payload map[string]any
	if !decodeB64JSONObject(parts[0], &hdr) || !decodeB64JSONObject(parts[1], &payload) {
		return false
	}
	alg, _ := hdr["alg"].(string)
	return alg != ""
}

func decodeB64JSONObject(seg string, into *map[string]any) bool {
	raw, err := base64.RawURLEncoding.DecodeString(seg)
	if err != nil {
		return false
	}
	if json.Unmarshal(raw, into) != nil {
		return false
	}
	return *into != nil
}

// privateKeyPEM — байты содержат PEM-блок, который РАЗБИРАЕТСЯ как приватный
// ключ; возвращает метку блока.
//
// Разбор, а не поиск метки. Это не педантизм: в дереве уже лежат три законных
// вхождения `-----BEGIN … PRIVATE KEY-----` — страница документации с
// многоточием вместо тела и две фикстуры, чьё «тело» состоит из одной буквы.
// Запрет по метке краснел бы на всех трёх, и его сняли бы первым же ложным
// срабатыванием. Разбор отличает материал от заглушки по построению, без
// единого исключения в списке.
//
// Тело извлекается САМОСТОЯТЕЛЬНО, а не через `pem.Decode`. Стандартный разбор
// требует, чтобы метка стояла в начале строки без отступа, — а утёкший ключ
// почти никогда так не лежит: в профиле развёртывания он внутри блочного скаляра
// YAML (каждая строка с отступом), в JSON и в литерале Go — одной строкой с
// экранированными переводами (`\n` двумя символами) и кавычкой перед меткой.
// Поэтому берётся текст между метками, из него выбрасывается всё, кроме
// алфавита base64, и результат пробуется как ключ — в двух вариантах, с
// восстановленными переводами строк и без. Экранирование снимается ДО отсева:
// иначе буква `n` от `\n` осталась бы внутри тела и испортила его.
func privateKeyPEM(raw []byte) (string, bool) {
	const beginPrefix = "-----BEGIN "
	const endPrefix = "-----END "

	s := string(raw)
	for off := 0; ; {
		loc := pemPrivateKeyMarker.FindStringIndex(s[off:])
		if loc == nil {
			return "", false
		}
		// Метка совпала с pemPrivateKeyMarker, значит она заведомо имеет вид
		// `-----BEGIN <…> PRIVATE KEY-----`: отдельная проверка суффикса была бы
		// мёртвой веткой.
		label := strings.TrimSuffix(strings.TrimPrefix(s[off+loc[0]:off+loc[1]], beginPrefix), "-----")
		bodyStart := off + loc[1]
		off = bodyStart

		end := strings.Index(s[bodyStart:], endPrefix)
		if end < 0 {
			return "", false // метка открыта и не закрыта — тела нет
		}
		body := s[bodyStart : bodyStart+end]
		for _, variant := range []string{body, unescapeNewlines(body)} {
			der, err := base64.StdEncoding.DecodeString(nonBase64.ReplaceAllString(variant, ""))
			if err != nil || len(der) == 0 {
				continue
			}
			if parsesAsPrivateKey(der) {
				return label, true
			}
		}
	}
}

// unescapeNewlines — восстанавливает переводы строк, записанные двумя символами.
// Так ключ выглядит в литерале Go, в строке JSON и в однострочном значении YAML.
func unescapeNewlines(s string) string {
	return strings.NewReplacer(`\r\n`, "\n", `\n`, "\n").Replace(s)
}

// nonBase64 — всё, что не является алфавитом base64. Отступы, кавычки, запятые,
// маркеры продолжения строки YAML и многоточия из документации выбрасываются,
// после чего от тела остаётся либо ключ, либо мусор, который не декодируется.
var nonBase64 = regexp.MustCompile(`[^A-Za-z0-9+/=]`)

// parsesAsPrivateKey — тело блока действительно является ключом.
func parsesAsPrivateKey(der []byte) bool {
	if _, err := x509.ParsePKCS8PrivateKey(der); err == nil {
		return true
	}
	if _, err := x509.ParsePKCS1PrivateKey(der); err == nil {
		return true
	}
	if _, err := x509.ParseECPrivateKey(der); err == nil {
		return true
	}
	// OpenSSH-формат x509 не разбирает; его опознаёт собственная сигнатура.
	return strings.HasPrefix(string(der), "openssh-key-v1\x00")
}

// scanCommittedCredentials — ЕДИНСТВЕННОЕ место, где вычисляются находки обеих
// осей. Словарь передаётся ПАРАМЕТРОМ, а не читается из глобальной переменной:
// инъекции нужно показать ось материала при полностью снятой оси слота, а
// подмена глобали связала бы тесты пакета между собой.
//
// Ошибка возвращается, а не роняет тест на месте: результат кэшируется на весь
// бинарь (обход стоит ~5 c на 113 МБ), и вызывающий обязан сам решить, чем
// является отказ в его контексте.
func scanCommittedCredentials(tt *trackedTree, vocabulary *regexp.Regexp) (credentialScan, error) {
	scan := credentialScan{indexFiles: tt.count()}

	paths := make([]string, 0, tt.count())
	for rel := range tt.files {
		paths = append(paths, rel)
	}
	sort.Strings(paths) // детерминизм входа — часть контракта проверки

	for _, rel := range paths {
		raw, err := os.ReadFile(filepath.Join(tt.root, filepath.FromSlash(rel)))
		if err != nil {
			// Файл индекса, которого нет на диске: не находка и не тишина —
			// он просто не прочитан, и это отдельное число переписи.
			scan.unreadable++
			continue
		}
		scan.filesRead++
		scan.bytesRead += int64(len(raw))

		// ── ОСЬ МАТЕРИАЛА: по всему индексу, имени ключа не читает ──
		seenAlg := map[string]bool{}
		cands, cut := forEachJWSCandidate(raw, func(candidate string) {
			if jwsShaped(candidate) {
				scan.jwsShaped++
			}
			alg, presentable := presentableToken(candidate)
			if !presentable || seenAlg[alg] {
				return
			}
			seenAlg[alg] = true
			scan.findings = append(scan.findings, credentialFinding{
				rel: rel, axis: credentialAxisMaterial,
				what: "байты несут предъявимый токен формы JWS (alg=" + alg + ")",
			})
		})
		scan.jwsCandidates += cands
		scan.jwsTruncated += cut
		if bytes.Contains(raw, pemBeginLiteral) && pemPrivateKeyMarker.Match(raw) {
			scan.pemMarkers++
			if label, ok := privateKeyPEM(raw); ok {
				scan.findings = append(scan.findings, credentialFinding{
					rel: rel, axis: credentialAxisMaterial,
					what: "байты несут PEM-блок, разбирающийся как приватный ключ (" + label + ")",
				})
			}
		}

		// ── ОСЬ СЛОТА: только окружения newman, читает имя ключа ──
		if !newmanEnvFile(rel) {
			continue
		}
		var doc struct {
			Values []struct {
				Key   string          `json:"key"`
				Value json.RawMessage `json:"value"`
			} `json:"values"`
		}
		if err := json.Unmarshal(raw, &doc); err != nil {
			// Нечитаемое окружение — ОТКАЗ, а не пропуск: пропустив его, гейт
			// вернул бы «ноль находок» на файле, которого он не разобрал.
			return credentialScan{}, fmt.Errorf("%s: разбор окружения newman: %w", rel, err)
		}
		scan.envFiles++
		for _, v := range doc.Values {
			scan.envValues++
			named := vocabulary.MatchString(v.Key)
			if named {
				scan.credentialSlots++
			}
			val, isString := jsonStringValue(v.Value)
			if !isString || strings.TrimSpace(val) == "" {
				continue
			}
			scan.envNonEmpty++
			if _, isToken := presentableToken(val); isToken {
				continue // уже названо осью материала — не задваиваем находку
			}
			if named {
				scan.findings = append(scan.findings, credentialFinding{
					rel: rel, key: v.Key, axis: credentialAxisSlot,
					what: "имя ключа обещает кред, а значение непусто",
				})
			}
		}
	}

	sort.Slice(scan.findings, func(i, j int) bool {
		return scan.findings[i].String() < scan.findings[j].String()
	})
	return scan, nil
}

// jsonStringValue — значение записи как строка. Не-строка (число, bool, объект)
// предъявительским кредом в окружении Postman не бывает.
func jsonStringValue(raw json.RawMessage) (string, bool) {
	if len(raw) == 0 {
		return "", false
	}
	var s string
	if json.Unmarshal(raw, &s) != nil {
		return "", false
	}
	return s, true
}

// repoCredentialScan — обход НАСТОЯЩЕГО дерева, посчитанный один раз на бинарь.
//
// Кэш здесь не оптимизация ради оптимизации: обход читает 113 МБ индекса, и три
// теста, спрашивающие о разных осях одного и того же обхода, платили бы за него
// трижды. Пакет гейтов уже однажды не уложился в свой бюджет и упал по таймауту
// (`reachabilitycost_test.go`) — эта цена оплачена заранее.
var repoCredentialScan = sync.OnceValues(func() (credentialScan, error) {
	root, err := repoRootFromWD()
	if err != nil {
		return credentialScan{}, err
	}
	cmd := gitenv.Command(root, "ls-files", "-z")
	out, err := cmd.Output()
	if err != nil {
		return credentialScan{}, fmt.Errorf("git ls-files в %s: %w — гейт не может назвать "+
			"дерево, о котором говорит, а обход диска вместо индекса читал бы игнорируемые "+
			"каталоги (рабочие копии агентов, отчёты прогонов). Это отказ, а не пропуск", root, err)
	}
	return scanCommittedCredentials(parseTrackedTree(root, out), credentialKeyVocabulary)
})

// repoRootFromWD — тот же подъём до каталога с `go.mod`, что и у `repoRoot`, но
// без `*testing.T`: кэшируемая функция вызывается вне контекста конкретного
// теста и обязана возвращать ошибку, а не ронять чужой.
func repoRootFromWD() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("getwd: %w", err)
	}
	for {
		if _, statErr := os.Stat(filepath.Join(dir, "go.mod")); statErr == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("корень репозитория не найден: go.mod отсутствует во всех " +
				"каталогах вверх от рабочего")
		}
		dir = parent
	}
}

func mustRepoCredentialScan(t *testing.T) credentialScan {
	t.Helper()
	scan, err := repoCredentialScan()
	if err != nil {
		t.Fatalf("обход отслеживаемого дерева: %v", err)
	}
	return scan
}

