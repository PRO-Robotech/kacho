// Единый ответ на вопрос «что такое ДЕРЕВО, о котором говорит гейт».
//
// # Зачем это вообще есть
//
// Гейт, идущий от корня репозитория обходом ДИСКА, читает и то, чего в
// репозитории нет: рабочие копии агентов под `.claude/worktrees/`, распаковки,
// отчёты прогонов, локальные оверлеи с кредами. Все они перечислены в
// `.gitignore` — то есть автор дерева уже сказал, что частью его они не
// являются, — но `filepath.Walk` этого не знает.
//
// Следствие не косметическое: вердикт гейта перестаёт быть свойством КОММИТА и
// становится свойством чужого рабочего каталога. Померено на 8c2eba3e, а не
// предположено: в чистой копии `go test ./internal/repohygiene/...` зелёный, а
// в той же копии плюс ОДИН git-игнорируемый каталог с деревом внутри — красный,
// 14 находок, и КАЖДАЯ координата начинается с `.claude/worktrees/`. Одного
// файла в игнорируемом каталоге хватает, чтобы фаз-гейт объявил «цель есть в
// дереве, но не в матрице» о цели, которой в репозитории не существует.
//
// Обратная сторона того же дефекта тише и хуже: находка, лежащая ВНЕ
// игнорируемого каталога, тонет в сотнях привнесённых, и её никто не читает.
//
// # Где живёт сама раскладка — и почему больше не здесь
//
// Раскладка (индекс git → множества файлов и каталогов-предков) переехала в
// `pkg/treecorpus`, где у неё дом обычного пакета: её импортирует кто
// угодно. Полтора десятка гейтов опирались на неё, пока она лежала в ТЕСТОВОМ
// файле этого пакета, и вынести любой из них в соседний пакет было нельзя, не
// унеся с собой копию помощника, — расщепление упиралось не в предмет обхода, а
// в место объявления. Проба, доказывающая отсев в обе стороны, переехала туда же
// (`treecorpus.TestTreeExcludesIgnoredAndKeepsTracked`): доказательство живёт
// рядом с доказываемым.
//
// Здесь осталась ТЕСТОВАЯ обёртка — двадцать строк, превращающих отказ в
// `t.Fatalf`. Такая же есть у соседнего пакета гейтов, и это намеренная копия:
// связывать пакеты ради двадцати строк дороже, чем повторить их, а разойтись они
// не могут — предмет один.
//
// `git ls-files` — ровно то множество, которое увидит свежий checkout и CI. Тот
// же выбор и по той же причине уже сделан в `license_test.go` (SPDX) и в
// `run-gate-self-tests.sh` (состав самопроверок).
type trackedTree struct {
	*treecorpus.Tree
	// files и root — то же, что у Tree, полями: гейты обходят состав напрямую
	// (`for rel := range tt.files`) и собирают пути от корня, и обёртка сохраняет
	// им эту форму.
	files map[string]bool
	root  string
}

// newTrackedTree читает индекс git. Недоступность git — ОТКАЗ, а не пропуск:
// молчаливый откат на обход диска вернул бы ровно тот дефект, ради которого
// написан этот файл, и сделал бы это невидимо.
func newTrackedTree(t *testing.T, root string) *trackedTree {
	t.Helper()
	tree, err := treecorpus.NewTree(root)
	if err != nil {
		t.Fatalf("состав дерева %s: %v — гейт не может назвать дерево, о котором "+
			"он говорит, и обход диска вместо индекса читал бы игнорируемые "+
			"каталоги (рабочие копии агентов, отчёты прогонов). Это отказ, а не пропуск.",
			root, err)
	}
	return &trackedTree{Tree: tree, files: tree.Files(), root: tree.Root()}
}

// newSyntheticTree — состав СИНТЕТИЧЕСКОГО дерева, собранного самой проверкой во
// временном каталоге. Такое дерево репозиторием не является, спрашивать у него
// индекс нечего, и обход файловой системы здесь — не откат, а единственный
// возможный авторитет.
func newSyntheticTree(t *testing.T, root string) *trackedTree {
	t.Helper()
	tree, err := treecorpus.SyntheticTree(root)
	if err != nil {
		t.Fatalf("обход синтетического дерева %s: %v", root, err)
	}
	return &trackedTree{Tree: tree, files: tree.Files(), root: tree.Root()}
}

// parseTrackedTree — обёртка над разбором вывода `git ls-files -z` для
// вызывающих, у которых нет `*testing.T` (кэшируемая перепись возвращает ошибку,
// а не роняет чужой тест).
func parseTrackedTree(root string, nulSeparated []byte) *trackedTree {
	tree := treecorpus.ParseIndex(root, nulSeparated)
	return &trackedTree{Tree: tree, files: tree.Files(), root: tree.Root()}
}

// hasFile — файл лежит в составе.
func (tt *trackedTree) hasFile(rel string) bool { return tt.Tree.HasFile(rel) }

// hasDir — в каталоге (или ниже) есть хоть один файл состава.
func (tt *trackedTree) hasDir(rel string) bool { return tt.Tree.HasDir(rel) }

// count — сколько файлов прочитано. Перепись печатается вызывающими, чтобы
// «ноль находок» отличалось от «ноль прочитанного».
func (tt *trackedTree) count() int { return tt.Tree.Count() }
