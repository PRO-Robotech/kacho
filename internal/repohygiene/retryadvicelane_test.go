package repohygiene

import (
	"sort"
	"strings"
	"testing"
)

// Совет повторить обязан быть исполнимым на той полосе, где он напечатан.
//
// ПРЕДМЕТ и границы — в шапке `retryadvicelane.go`; здесь они не пересказываются,
// иначе заведутся два места об одном предмете.
//
// ВЕДОМОСТИ ПОСЛАБЛЕНИЙ У ГЕЙТА НЕТ, и это решение, а не упущение: на день
// заведения гейт находит в дереве два живых совета и починку несёт та же ветка,
// что и гейт. Понадобится послабление под предмет иного рода — заводится вместе
// со своим номером задачи и своей проверкой самоистечения (`testing.md` §«Гейт
// на класс», п.5).
func TestRetryAdviceIsExecutableOnItsLane(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)

	sources, err := loadRetryAdviceSources(root)
	if err != nil {
		t.Fatalf("обход прод-кода: %v", err)
	}
	c := auditRetryAdvice(sources)

	t.Logf("файлов Go прочитано: %d; разобрано: %d", c.Files, c.Parsed)
	// ОБЕ величины по оси отказа: «выражений отказа» без «текстов осмотрено» не
	// отличает отказ, несущий текст, от отказа с фиксированным сообщением.
	t.Logf("выражений отказа осмотрено: %d; текстов отказа в них: %d; снято как "+
		"строка журнала: %d", c.Refusals, c.Literals, c.LogSkipped)
	// ОБЕ величины по оси асинхронного тела: «тел найдено» без «текстов внутри
	// них» скрывает ослепшую ось A2 — тела есть, а смотреть в них перестали.
	t.Logf("асинхронных тел мутации найдено: %d; текстов отказа внутри них "+
		"лексически: %d", c.AsyncBodies, c.AsyncLiterals)
	t.Logf("советов повторить распознано: %d; из них снято отрицанием: %d; "+
		"на РАЗРЕШАЮЩЕМ коде (законны): %d; на коде вне обоих множеств "+
		"(не судятся): %d", c.Advices, c.Negated, c.OnAllowedCode, c.OnUnjudgedCode)
	t.Logf("по формам совета: %s", adviceFormat(c.ByForm))
	t.Logf("по кодам отказа, несущим совет: %s", adviceFormat(c.ByCode))

	// Форма, не сработавшая ни разу, названа вслух: расширение распознавателя,
	// не меняющее осмотренного, — холостое, и его снимают, а не оставляют «на
	// всякий случай» (`testing.md` §«Гейт на класс», п.7). Это НЕ отказ: форму
	// держит своя инъекция, и дерево вправе сегодня её не использовать.
	var idle []string
	for _, f := range retryAdviceForms {
		if c.ByForm[f.Name] == 0 {
			idle = append(idle, f.Name)
		}
	}
	sort.Strings(idle)
	if len(idle) > 0 {
		t.Logf("формы совета, не сработавшие в дереве ни разу: %v — каждая держится "+
			"своей инъекцией; если форма простаивает и дальше, её снимают", idle)
	}

	// ПРЕДПОСЫЛКИ. «Ноль находок» обязано быть отличимо от «ноль прочитанного»:
	// каждая ступень обхода утверждается отдельно, потому что обрыв на любой из
	// них даёт зелёное, ничего не проверив.
	if len(c.ParseFails) > 0 {
		t.Fatalf("разбор не состоялся на %d файлах — вердикт об их содержимом не "+
			"получен, и молчание тут значило бы «проверено»: %v",
			len(c.ParseFails), c.ParseFails[:min(len(c.ParseFails), 5)])
	}
	if c.Files == 0 || c.Parsed == 0 {
		t.Fatalf("прочитано ноль файлов Go (прочитано %d, разобрано %d) — обход "+
			"пуст, вердикт беспредметен", c.Files, c.Parsed)
	}
	if c.Refusals == 0 {
		t.Fatal("не найдено ни одного выражения отказа — распознаватель кода ослеп; " +
			"молчание здесь неотличимо от исправной работы")
	}
	if c.Literals == 0 {
		t.Fatalf("выражения отказа найдены (%d), а текстов в них не извлечено ни "+
			"одного — оборвана вторая половина цепочки, и вердикт беспредметен",
			c.Refusals)
	}
	if c.AsyncBodies == 0 {
		t.Fatal("не найдено ни одного асинхронного тела мутации при непустом обходе — " +
			"ось A2 не исполняется вовсе; либо производитель тела сменил имя, либо " +
			"мутации перестали быть асинхронными (ban #9), и оба случая требуют " +
			"правки гейта, а не молчания")
	}
	// Предпосылка распознавателя: дерево советы повторить ПИШЕТ. Ноль советов на
	// тысячах текстов отказа означает ослепший распознаватель гораздо вероятнее,
	// чем корпус, из которого исчезли все такие обороты — и тогда гейт снимается
	// ВМЕСТЕ с предметом, а не остаётся молчать (`testing.md` §«Гейт на класс», п.9).
	if c.Advices == 0 {
		t.Fatalf("не распознано ни одного совета повторить при %d осмотренных "+
			"текстах отказа — распознаватель ослеп либо предмет исчез; молчание в "+
			"обоих случаях неотличимо от исправной работы", c.Literals)
	}

	if len(c.Findings) == 0 {
		return
	}
	var b strings.Builder
	b.WriteString("совет повторить напечатан там, где повтор ничего не меняет:\n")
	for _, f := range c.Findings {
		b.WriteString("  " + f.Describe() + "\n")
	}
	b.WriteString("\nИСХОДА ТРИ, четвёртого нет: снять совет и оставить текст, " +
		"называющий СОСТОЯНИЕ (тон соседей той же полосы уже такой); перевести отказ " +
		"на код, который повтор разрешает, если он и вправду повторяем; либо назвать " +
		"вызывающему ДРУГОЕ действие — то, которое на этой полосе исполнимо.")
	t.Fatal(b.String())
}
