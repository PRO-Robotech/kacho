// modulemanifestformpin.go — ФОРМУ манифестов доменов платформы судит В ЭТОМ
// ДЕРЕВЕ тот самый единственный исполнитель, собранный ИЗ ПИНА (задача
// PRO-Robotech/kacho#2613).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ: судья ФОРМЫ существовал и не звался НИ В ОДНОМ дереве
//
// У сверки две стороны, и обе живы: пять документов (`services/*/manifest.yaml`)
// и схема, по которой их прочтёт адресат. Документы — у платформы; схема,
// строгий загрузчик и встроенный каталог прав — у службы доступа. Исполнитель
// один — `tools/modulemanifestcheck` репозитория PRO-Robotech/kaname, — и после
// разреза его не звал никто:
//
//   - в этом дереве его не было вовсе: каталог службы уехал, а вместе с ним
//     носитель провязки (`modulemanifestcheckwiring_test.go`, надгробие
//     retired_gate_carriers.json, судьба тогда `unguarded`);
//   - в дереве службы он исполним и зелен, но видит ОДИН документ — её
//     собственный. Пяти документов платформы там нет ни одним путём.
//
// Замер на ревизии заведения: исполнитель, собранный из пина и наведённый на
// это дерево, читает 5 манифестов из 5 и выходит кодом 0. То есть работал он
// всё это время — его просто не звали, и «ноль находок» у формы было неотличимо
// от «ноль прогонов».
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ: ВТОРОГО СУДЬИ ФОРМЫ
//
// Второго судью формы заводить ЗАПРЕЩЕНО решением #1778: схема документа
// принадлежит его адресату (`apiVersion: iam/v1`), и повторённая здесь она
// разошлась бы с оригиналом на первом же новом разделе — молча и там, где обе
// копии зелены. Поэтому исполнитель не переписан и не скопирован: он
// СОБИРАЕТСЯ из пина `github.com/PRO-Robotech/kaname`, объявленного в go.mod
// этого дерева, и запускается как двоичное.
//
// Сосед по этому корпусу — TestModuleManifestsOfThePlatformAreReadable — вторым
// судьёй формы тоже не является и говорит это сам: он судит четыре оси, которые
// платформа вправе утверждать о СВОИХ документах, не владея их схемой
// (разбираемость, самоописание, единственность модуля и типа объекта). Форму
// как таковую — закрытый набор ключей, связность разделов, согласие с каталогом
// прав — судит только исполнитель из пина.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ КОРЕНЬ НЕ СОБИРАЕТСЯ, В ОТЛИЧИЕ ОТ СОСЕДНЕЙ СВЕРКИ
//
// Сосед modelcanonpin.go собирает транзитный корень: его второй операнд — канон
// модели — лежит у службы, и дерева, где лежали бы оба, не существует.
//
// У ФОРМЫ этой беды нет. Второй операнд формы — схема и каталог прав — не файл
// дерева, а ЧАСТЬ САМОГО ИСПОЛНИТЕЛЯ: он несёт их встроенными и приезжает с
// ними вместе. Значит исполнителю довольно одного корня, и корнем служит ЭТО
// дерево, как есть. Собирать транзитный корень значило бы завести лишний слой,
// в котором вердикт перестал бы быть свойством коммита.
//
// Это и есть признак, по которому выбран исход: у сверки, чьи операнды
// разъехались по деревьям, корень собирают; у сверки, чей второй операнд везёт
// сам исполнитель, — нет.
//
// ─────────────────────────────────────────────────────────────────────────────
// ИСХОДОВ ТРИ, И ТРЕТИЙ НЕ ВЫЧИТАЕТСЯ ИЗ ВЕРДИКТА
//
// Исполнитель различает исходы кодом возврата, и здесь они читаются ВРОЗЬ:
// «форма негодна» и «судить было нечего» означают разное и чинятся разным.
// Схлопывание их в «ненулевой код» вернуло бы ровно тот дефект, ради которого
// заведён этот файл: пустое дерево отчитывалось бы так же уверенно, как
// проверенное.
//
// Поэтому двоичное СОБИРАЕТСЯ и запускается, а не зовётся через `go run`: тот
// схлопывает код возврата программы в единицу, и VOID стал бы неотличим от
// находки. То же решение и по той же причине принято у обёртки самого
// исполнителя и у соседней сверки.
package repohygiene

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// ManifestFormJudgePackage — пакет единственного судьи ФОРМЫ в модуле службы.
// Собирается из пина; второй реализации разбора это дереву не заводит.
//
// Он лежит ВНЕ `internal/` своего модуля и потому собирается отсюда законно —
// свойство проверено сборкой, а не выведено.
const ManifestFormJudgePackage = "github.com/PRO-Robotech/kaname/tools/modulemanifestcheck"

// Исходы судьи формы. Значения принадлежат ЕМУ, а не этому файлу: здесь они
// лишь названы словами, чтобы вердикт не читался по голому числу.
const (
	// ManifestFormJudgeOK — каждый найденный документ прочитан, разобран и связен.
	ManifestFormJudgeOK = 0
	// ManifestFormJudgeFinding — документ негоден: названы файл, поле и причина.
	ManifestFormJudgeFinding = 1
	// ManifestFormJudgeVoid — манифеста не найдено ни одного: СУДИТЬ НЕЧЕГО.
	ManifestFormJudgeVoid = 2
)

// ManifestFormJudgeOutcome — что означает код возврата судьи формы.
//
// Возвращает имя исхода, его смысл для читателя и признак «это зелёное».
// Зелёный ровно один: у «судить было нечего» предмета нет, и в успех он не
// засчитывается (`testing.md` §«Чтение вердикта»). Неизвестный код — тоже не
// зелёное: вердикта о форме он не несёт.
func ManifestFormJudgeOutcome(code int) (name, meaning string, green bool) {
	switch code {
	case ManifestFormJudgeOK:
		return "ГОДНО", "каждый найденный манифест прочитан, разобран и связен", true
	case ManifestFormJudgeFinding:
		return "НАХОДКА", "манифест негоден либо путь не прочитан — названы файл, поле и причина", false
	case ManifestFormJudgeVoid:
		return "БЕЗ ПРЕДМЕТА", "манифеста не найдено НИ ОДНОГО — судить было нечего; это НЕ " +
			"находка о продукте и НЕ успех: «ноль находок» здесь означает «ноль прочитанного»", false
	default:
		return "НЕ ИСПОЛНЯЛАСЬ", "судья вышел кодом, которого его контракт не объявляет — " +
			"вердикта о форме нет вовсе", false
	}
}

// ManifestFormCensus — объём осмотренного судьёй формы.
//
// Величины печатаются ПО КАЖДОЙ ОСИ отдельно. Одно число скрыло бы ровно тот
// случай, ради которого гейт заведён: «манифестов ноль» неотличимо от
// «манифесты прочитаны и негодного в них нет».
type ManifestFormCensus struct {
	// FilesWalked — сколько путей индекса судья осмотрел.
	FilesWalked int
	// ManifestsRead — сколько документов он прочитал. Ноль здесь означает, что
	// СУДА НЕ БЫЛО, каким бы ни был код возврата.
	ManifestsRead int
	// Findings — сколько находок он назвал.
	Findings int
}

// String — перепись одной строкой.
func (c ManifestFormCensus) String() string {
	return fmt.Sprintf("осмотрено путей %d · манифестов прочитано %d · находок %d",
		c.FilesWalked, c.ManifestsRead, c.Findings)
}

// manifestFormCensusRe — перепись судьи. Читаются ТРИ величины сразу: частичный
// разбор дал бы нули там, где формат сменился, и они прошли бы за «нечего было
// читать».
var manifestFormCensusRe = regexp.MustCompile(
	`осмотрено файлов (\d+).*?манифестов прочитано (\d+) · находок (\d+)`)

// ParseManifestFormCensus — достаёт объём ОСМОТРЕННОГО СУДЬЁЙ из его вывода.
//
// ПОЧЕМУ ЭТО ЧИТАЕТСЯ, А НЕ ПРИНИМАЕТСЯ НА ВЕРУ. Код возврата 0 означает «не
// нашёл», а не «прочитал». Судья отдаёт VOID на пустом обходе сам, но полагаться
// на одну только его арифметику значило бы иметь ОДНО утверждение там, где нужно
// два: сколько он прочитал — вопрос к нему, и задать его обязан тот, кто его
// позвал.
//
// НЕРАЗОБРАННАЯ ПЕРЕПИСЬ — ОТКАЗ, а не нули. Формат вывода принадлежит чужому
// репозиторию и может смениться; молчаливые нули тогда прошли бы за «судить было
// нечего», то есть расхождение формата выдало бы себя за свойство дерева.
func ParseManifestFormCensus(out string) (ManifestFormCensus, error) {
	m := manifestFormCensusRe.FindStringSubmatch(out)
	if m == nil {
		return ManifestFormCensus{}, fmt.Errorf(
			"перепись судьи формы не разобрана: в его выводе нет величин «осмотрено файлов N … "+
				"манифестов прочитано K · находок F». Объём осмотренного назвать нечем, поэтому "+
				"вердикт о форме не выносится — вероятно, сменился формат вывода в модуле "+
				"службы.\nвывод:\n%s", strings.TrimSpace(out))
	}
	var c ManifestFormCensus
	c.FilesWalked, _ = strconv.Atoi(m[1])
	c.ManifestsRead, _ = strconv.Atoi(m[2])
	c.Findings, _ = strconv.Atoi(m[3])
	return c, nil
}
