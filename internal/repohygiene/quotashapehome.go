package repohygiene

import (
	"regexp"
	"strings"
)

// Пакет общей ФОРМЫ ответа учёта объявляет форму, а не СЛУЖБУ.
//
// # Предмет (задача `PRO-Robotech/kacho#2362`, решение `Д9` приёмки KAN-QUOTA-1)
//
// Общая форма ответа заводилась ради одного: чтобы владельцы ресурсов не
// разошлись в диалекты одних и тех же трёх чисел. Форма — общая; служба,
// которая ею отвечает, — всегда чья-то. Служба, объявленная В ПАКЕТЕ ФОРМЫ,
// принадлежит модулю квотирования, а не своему владельцу, — и когда модуль
// выносят из продукта, публичная арендаторская поверхность владельца уезжает
// вместе с ним, хотя предмет её остаётся.
//
// Ровно это и произошло: служба чтения потолка личности была объявлена в
// `kacho.cloud.quota.v1`, а обслуживает её служба доступа, которая выносится
// в самостоятельный продукт.
//
// # Почему проверка о МЕСТЕ объявления, а не о владельце
//
// «Кто владелец» — суждение; «в каком пакете объявлено» — свойство дерева.
// Пять владельцев платформы объявляют `QuotaService` каждый в своём каталоге и
// этой проверкой не затрагиваются вовсе: они и есть её положительный близнец.

// quotaShapePackageDir — каталог пакета общей формы ответа учёта, относительно
// корня дерева.
//
// Координата, а не догадка: именно этот пакет объявляет сообщение `Quota`,
// которое шесть владельцев отдают арендатору.
const quotaShapePackageDir = "proto/kacho/cloud/quota/"

// quotaShapeServiceDeclRe — объявление службы в контракте.
//
// Судится НАЧАЛО СТРОКИ, а не вхождение слова: `service` встречается в прозе
// комментариев этих же файлов десятками раз, и предикат по подстроке краснел бы
// на собственном объяснении проверки.
var quotaShapeServiceDeclRe = regexp.MustCompile(`(?m)^service\s+([A-Za-z0-9_]+)\s*\{`)

// ServicesDeclaredIn — имена служб, объявленных в теле контракта.
//
// Вынесено функцией, чтобы доказательство способности упасть подавало НАСТОЯЩУЮ
// форму из дерева, а не воспроизводило разбор второй копией.
func ServicesDeclaredIn(content string) []string {
	m := quotaShapeServiceDeclRe.FindAllStringSubmatch(content, -1)
	out := make([]string, 0, len(m))
	for _, g := range m {
		out = append(out, g[1])
	}
	return out
}

// InQuotaShapePackage — лежит ли контракт в пакете общей формы ответа.
//
// Путь приводится к разделителю дерева до сравнения: обход отдаёт системный,
// а координата записана деревянным, и на их расхождении проверка молча
// осматривала бы ноль файлов.
func InQuotaShapePackage(rel string) bool {
	return strings.Contains(strings.ReplaceAll(rel, "\\", "/"), quotaShapePackageDir)
}
