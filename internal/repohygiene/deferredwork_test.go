// TestNoDeferredWorkInTheTree — в дереве нет маркеров отложенной работы.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. работа нужна → сделать её СЕЙЧАС, в том же изменении. Правило продукта
//     не знает состояния «сделаю в следующем PR»;
//  2. работа не нужна → снять маркер вместе с кодом, который он подпирал;
//  3. работа принадлежит другому предмету и требует решения → завести
//     ПРЕДМЕТ (issue/приёмку) с причиной и предикатом снятия, а в коде не
//     оставлять обещания. Маркер отличается от предмета тем, что за ним никто
//     не отвечает.
//
// Заводить запись в перечень объяснений — НЕ исход: такого перечня у разбора нет.
func TestNoDeferredWorkInTheTree(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)
	findings, census, err := auditDeferredWork(root)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	t.Logf("%s; находок %d", census, len(findings))

	if census.Read == 0 {
		t.Fatal("не прочитано ни одного файла — «маркеров нет» здесь означало бы «ничего не " +
			"читал», а не чистое дерево")
	}
	if len(census.Roots) == 0 {
		t.Fatal("верхний уровень индекса пуст — область обхода выведена из ничего, и её покрытие " +
			"ничего не утверждает")
	}
	// Вид вычитания, которому больше нечего вычитать, — находка: под его именем
	// можно положить что угодно, и счёт не сдвинется.
	for _, s := range deferralSkips {
		if census.Skipped[s.Name] == 0 {
			t.Errorf("вид вычитания %q не вычел НИ ОДНОГО файла — у него больше нет предмета "+
				"(заведён потому, что %s). Снимите вид вместе с предметом: оставленный, он "+
				"остаётся слепой зоной, в которую можно внести отсрочку незамеченной", s.Name, s.Why)
		}
	}

	for _, f := range findings {
		t.Errorf("отложенная работа: %s — %q\n"+
			"Правила продукта не знают состояния «сделаю позже» (ban #11, ban #14): работа делается "+
			"сразу в production-форме. Исходы: сделать сейчас / снять вместе с кодом / завести "+
			"ПРЕДМЕТ с причиной и предикатом снятия. Маркер отличается от предмета тем, что за "+
			"ним никто не отвечает — и он переживает своё основание: ровно так хук восстановления "+
			"пароля простоял нацеленным в никуда, пока его отсрочка ссылалась на препятствие, "+
			"которого давно не было.", f.Where, f.Line)
	}
}

// Проб на САМ РАЗБОР здесь нет, и это решение, а не пробел.
//
// Словарь форм, отсев по затравке, граница употребления и упоминания, обратный
// порядок слов, вычет вызова через точку — всё это переехало в
// `corelib/treehygiene` вместе с разбором, и там же стоят его инъекции. Держать
// их копию здесь значило бы вернуть ровно то, ради снятия чего разбор и получил
// один дом: два места об одном предмете, расходящиеся молча.
//
// Ниже — инъекция СВОЕЙ части: что гейт этого дерева способен упасть и что его
// виды вычитания вычитают именно своё.

// Перепись цитат (Mentions) печатается, но НЕ роняет прогон на нуле — и это
// решение, а не упущение. С переездом разбора она стала нулём: все семь цитат
// этого дерева стояли в прозе снятой шапки, то есть в объяснении самого запрета.
//
// Требовать «отсечена хотя бы одна» значило бы требовать держать в дереве прозу
// о маркерах ради зелёного — то же самое, что запись в перечне прощённых, только
// наизнанку. Способность фильтра сработать доказывается ИНЪЕКЦИЕЙ, и она стоит
// там же, где сам фильтр, — в `corelib/treehygiene`.

func synthDeferralTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	// Дерево обязано быть непустым: обход берёт состав у индекса и отказывает на
	// пустом — «смотреть не на что» есть отказ, а не успех. Подкаталоги при этом
	// НЕ засеиваются: область выводится из индекса, поэтому корни синтетического
	// дерева — ровно те, которые написала сама проба.
	if err := os.WriteFile(filepath.Join(root, "README.md"),
		[]byte("# синтетическое дерево пробы\n"), 0o644); err != nil {
		t.Fatalf("seed: %v", err)
	}
	for rel, body := range files {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", rel, err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatalf("write %s: %v", rel, err)
		}
	}
	synthTrack(t, root)
	return root
}

// Сторона дефекта: гейт ЭТОГО дерева способен упасть и называет координату.
//
// Проба гоняет ту же провязку, что и гейт по дереву (auditDeferredWork), —
// значит доказывает не разбор фундамента, а то, что корень и виды вычитания
// связаны так, что находка доезжает до вердикта.
func TestDeferralGateCatchesAMarkerInProductionCode(t *testing.T) {
	t.Parallel()
	root := synthDeferralTree(t, map[string]string{
		"services/x/internal/thing.go": "package thing\n\n// TODO: дочинить после релиза\nfunc F() {}\n",
	})
	findings, census, err := auditDeferredWork(root)
	if err != nil {
		t.Fatalf("обход синтетического дерева: %v", err)
	}
	if census.Read == 0 {
		t.Fatal("синтетическое дерево не прочитано")
	}
	if len(findings) != 1 || !strings.Contains(findings[0].Where, "thing.go") {
		t.Fatalf("маркер в прод-коде не пойман: %+v", findings)
	}
}

// TestDeferralGateSubtractsItsOwnKindsAndStillFalls — каждый вид вычитания
// вычитает СВОЁ, и рядом стоит положительный контроль.
//
// Виды вычитания — единственное, что этот гейт утверждает о составе своего
// дерева, и проверить их больше нечем: фундамент своих видов не раздаёт. Проба
// кладёт по одному файлу с маркером под каждый вид и обещание в прод-коде рядом.
//
// Положительный контроль обязателен: без него «одна находка вместо четырёх»
// было бы неотличимо от гейта, разучившегося падать, — молчание на вычтенном
// ничего не доказывает, пока не показано, что невычтенное краснеет.
func TestDeferralGateSubtractsItsOwnKindsAndStillFalls(t *testing.T) {
	t.Parallel()
	root := synthDeferralTree(t, map[string]string{
		// вид «тестовый корпус»: фикстура соседнего гейта пишет форму дефекта
		"services/x/internal/thing_test.go": "package thing\n\n// TODO: фикстура гейта пишет форму дефекта\n",
		// вид «тестовые данные»: вход сценария, а не код продукта
		"services/x/internal/testdata/input.go": "package input\n\n// TODO: вход сценария\n",
		// вид «сгенерированное»: маркер принадлежит генератору
		"pkg/api/kacho/cloud/x/v1/x.pb.go": "package v1\n\n// TODO: маркер генератора\n",
		// положительный контроль: обещание в прод-коде обязано остаться находкой
		"services/x/internal/thing.go": "package thing\n\n// " + "пока " + "заглушка\nfunc F() {}\n",
	})
	findings, census, err := auditDeferredWork(root)
	if err != nil {
		t.Fatalf("обход синтетического дерева: %v", err)
	}
	if census.Read == 0 {
		t.Fatal("синтетическое дерево не прочитано")
	}

	for _, s := range deferralSkips {
		if census.Skipped[s.Name] != 1 {
			t.Errorf("вид вычитания %q вычел %d файлов, а в дереве пробы его ровно один: "+
				"вид, не вычевший своего, красит прогон на чужой фикстуре, а вид, вычевший "+
				"лишнее, уносит прод-код из-под наблюдения", s.Name, census.Skipped[s.Name])
		}
	}

	if len(findings) != 1 || !strings.Contains(findings[0].Where, "services/x/internal/thing.go") {
		t.Fatalf("положительный контроль не сработал (%+v): обещание в прод-коде обязано "+
			"остаться единственной находкой — иначе молчание на вычтенном означает не "+
			"вычитание, а то, что гейт перестал падать вовсе", findings)
	}
}
