package repohygiene_test

// Личность модуля заводит ТОЛЬКО применённая базовая миграция (задача продукта
// #2098, второй её предмет — ПР-5 приёмки WIRE-1).
//
// # ПРЕДМЕТ
//
// Личности модулей посеяны БАЗОВОЙ миграцией iam, то есть приезжают и в
// установку, где платформы нет вовсе. Строка, которую арендатор, развернувший
// службу доступа отдельно, нести не обязан, — это данные окружения, и в
// миграцию они не идут ни при каких условиях (`data-integrity.md` §«Данные
// СТЕНДА заводятся посевом»).
//
// Сегодня долг НЕПОДВИЖЕН, и это не выбор автора: применённую миграцию править
// нельзя (ban #5), а применителя у раздела `seed` манифеста модуля нет ни
// одного — об этом прямо сказано в его собственной прозе
// (`services/iam/internal/manifest/manifest.go`, тип `Seed`: «раздел НИЧЕГО НЕ
// ЗАВОДИТ»). Снять строки может только новая миграция вместе с применителем, и
// это работа со своим предметом.
//
// # ЧТО ЗАКРЫВАЕТ ЭТОТ ГЕЙТ, А ЧТО ОСТАЁТСЯ ПРЕДМЕТОМ ЗАДАЧИ
//
// У предиката ПР-5 две половины, и производитель есть только у одной:
//
//	«свежая установка без платформы несёт ноль»  — производителя НЕТ: нужен
//	                                               применитель и новая миграция;
//	                                               остаётся предметом #2098;
//	«долг не РАСТЁТ»                             — производитель есть, и он здесь.
//
// Вторая половина не косметическая: каждая новая строка ложится в миграцию,
// которую после применения уже не отредактировать, — рост долга НЕОБРАТИМ.
// Заметить его было нечем: гейт по соседству
// (`moduleserviceaccounthasacomponent_test.go`) судит, ЧТО посеяно (называет ли
// учётка живой компонент), и не судит, КТО её посеял, — при том что имя
// миграции он уже разбирает и носит в `seededSA.where`. Здесь судится ровно эта
// вторая ось.
//
// # РОДСТВО, КОТОРОЕ НАДО НАЗВАТЬ — И РАЗЛИЧИЕ
//
// У ролей модуля такой судья давно есть: `migrationnotawriterofmodulerole.go`
// (Г2) запрещает миграции писать роль модуля, у которого есть манифест. Разница
// в применителе: у ролей он ЕСТЬ (`apps/kaname/moduleroles`), поэтому им
// запрещена всякая запись миграцией; у личностей его нет, поэтому базовая
// миграция остаётся законным писателем — а всякая иная нет. Появится
// применитель — запрет обязан стать таким же полным, как у ролей, и эта проза
// перечитывается вместе с ним.
//
// # ПОПУЛЯЦИЯ И БАЗОВАЯ ВЫВОДЯТСЯ, ПЕРЕЧНЯ ПРОЩЁННЫХ НЕТ
//
// Модульной считается учётка, объявившая себя такой (`seededSA.isModule`) —
// признак стоит в самой посеянной строке и уже держится соседним гейтом с двух
// сторон: учётка, названная по компоненту, но модульной себя не объявившая, у
// него тоже находка, поэтому снять признак вместе с проверкой нельзя.
//
// Базовая миграция — ПЕРВАЯ в порядке применения, а не имя из литерала: goose
// применяет их лексикографически, поэтому «первая» есть свойство перечня, а
// выписанное имя разошлось бы с деревом молча в день, когда базовую пересоберут.
//
// # ЧЕГО ГЕЙТ НЕ ЛОВИТ (названо, чтобы на него не сослались шире предмета)
//
// Он про ПОСЕВ, а не про живую базу: строку, заведённую не миграцией, он не
// читает by construction. И он ничего не утверждает о ПОЛНОТЕ посева — о том,
// что у каждого модуля платформы личность есть; у этой половины производителя
// сегодня нет, она сосчитана и названа, а не обещана.

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

// baselineMigrationOf — применённая базовая миграция: первая в порядке
// применения. Порядок goose лексикографический, поэтому перечень уже
// отсортирован вызывающим.
func baselineMigrationOf(ordered []string) string {
	if len(ordered) == 0 {
		return ""
	}
	return ordered[0]
}

// seedScopeUnfit — ПРЕДМЕТА нет. Отдельной функцией, а не тремя ветвями внутри
// пробы: способность гейта отличить «ноль находок» от «ноль прочитанного»
// проверяется инъекцией, а инъекция не может спросить `require`.
func seedScopeUnfit(ordered []string, alive map[string]seededSA) string {
	switch {
	case len(ordered) == 0:
		return "миграций iam не прочитано ни одной — обход пуст, и «ноль находок» здесь " +
			"означало бы «ноль прочитанного»"
	case len(alive) == 0:
		return fmt.Sprintf("в %d миграциях не разобрано ни одной живой служебной учётки: "+
			"либо имя таблицы сменилось, либо форма записи перестала попадать под разбор",
			len(ordered))
	}
	return ""
}

// moduleIdentitiesSeededOutsideTheBaseline — судья, отделённый от дерева ради
// инъекции. Находка — живая МОДУЛЬНАЯ учётка, чью строку завела не базовая
// миграция.
func moduleIdentitiesSeededOutsideTheBaseline(alive map[string]seededSA, baseline string) []string {
	ids := make([]string, 0, len(alive))
	for id := range alive {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	var out []string
	for _, id := range ids {
		sa := alive[id]
		if !sa.isModule() || sa.where == baseline {
			continue
		}
		out = append(out, fmt.Sprintf(
			"%s: миграция заводит личность модуля %q (%s). Личность модуля заводит ТОЛЬКО "+
				"применённая базовая миграция %s: применителя у раздела `seed` манифеста нет "+
				"ни одного, поэтому строка ляжет в миграцию, которую после применения уже не "+
				"отредактировать (ban #5), и приедет в установку, где платформы нет вовсе. "+
				"Долг #2098 неподвижен, но расти не вправе — исходов три: завести строку "+
				"посевом на подъёме стенда · снять её вместе с тем, что она подпирала · "+
				"закрыть #2098 применителем",
			sa.where, sa.name, id, baseline))
	}
	return out
}

// TestOnlyTheAppliedBaselineSeedsAModuleIdentity — рост долга ПР-5 запрещён.
func TestOnlyTheAppliedBaselineSeedsAModuleIdentity(t *testing.T) {
	t.Parallel()

	root := repoRootFor(t)

	sqlFiles, err := treecorpus.UnderWithSuffix(
		filepath.Join(root, "services", "iam", "internal", "migrations"), ".sql")
	require.NoError(t, err, "перечень миграций берётся у индекса дерева, а не обходом диска")

	bodies := map[string]string{}
	ordered := make([]string, 0, len(sqlFiles))
	for _, f := range sqlFiles {
		raw, rerr := os.ReadFile(filepath.Clean(f)) // #nosec G304 -- путь из индекса дерева
		require.NoError(t, rerr, "чтение %s", f)
		name := filepath.Base(f)
		bodies[name] = string(raw)
		ordered = append(ordered, name)
	}
	sort.Strings(ordered) // порядок применения goose = лексикографический порядок имён

	alive, unknown, stmts := foldSeededServiceAccounts(ordered, bodies)
	require.Emptyf(t, unknown, "форма посева служебных учёток, неизвестная разбору:\n%s",
		strings.Join(unknown, "\n"))
	require.Emptyf(t, seedScopeUnfit(ordered, alive), "проверка НЕ ИСПОЛНЯЛАСЬ: %s",
		seedScopeUnfit(ordered, alive))

	baseline := baselineMigrationOf(ordered)
	findings := moduleIdentitiesSeededOutsideTheBaseline(alive, baseline)

	modules, byBaseline := 0, 0
	for _, sa := range alive {
		if !sa.isModule() {
			continue
		}
		modules++
		if sa.where == baseline {
			byBaseline++
		}
	}

	t.Logf("перепись: миграций iam прочитано %d · базовая (первая в порядке применения) %s · "+
		"операторов о служебных учётках %d · живых учёток посева %d · из них модульных %d · "+
		"находок %d",
		len(ordered), baseline, stmts, len(alive), modules, len(findings))
	t.Logf("перепись долга ПР-5: личностей модулей, которые несёт установка БЕЗ платформы, "+
		"%d — все посеяны базовой миграцией (%d из %d). Снятие требует применителя и новой "+
		"миграции; эта проба о снятии не утверждает ничего и стережёт только рост",
		modules, byBaseline, modules)

	require.Empty(t, findings, strings.Join(findings, "\n"))
}
