// Замок на класс «гейт сверяет имя вызова подстрокой».
//
// Гейт мёртвых строителей примирителя решал «вызвано ли имя» вхождением
// `имя + "("` в текст файла. Подстрока не отличает вызов от ХВОСТА чужого
// идентификатора: `newBuildReconciler(` содержит `BuildReconciler(`.
//
// Направление ошибки здесь — ложное МОЛЧАНИЕ, и оно опаснее ложной находки.
// Лишнее совпадение объявляет мёртвого строителя вызванным, тот не попадает в
// перечень, гейт зелен, предмет жив, и заметить нечем. Ложная находка себя
// выдаёт сразу — кто-то упирается в красное и идёт разбираться.
//
// Разбор по узлам вызова снимает класс by construction: объявление функции
// узлом вызова не является, поэтому и поправка «в своём файле имя встречается
// дважды», компенсировавшая разбор текстом, стала не нужна.
package repohygiene

import "testing"

func TestCalledFuncNamesJudgesCallNodesNotSubstrings(t *testing.T) {
	files := map[string]string{
		"a.go": "package p\nfunc buildReconciler() {}\nfunc newBuildReconciler() {}\n",
		"b.go": "package p\nfunc use() { newBuildReconciler() }\n",
	}
	called := calledFuncNames(files)

	// Положительный контроль: без него отрицание ниже зеленело бы на пустом.
	if !called["newBuildReconciler"] {
		t.Fatalf("вызванное имя не найдено — разбор не видит узла вызова, " +
			"и тогда гейт объявил бы мёртвыми всех")
	}
	if called["buildReconciler"] {
		t.Fatalf("МЁРТВЫЙ строитель объявлен вызванным: его имя — хвост чужого " +
			"идентификатора, и подстрочный разбор гасил бы находку")
	}

	// Вызов через селектор считается тем же именем: `pkg.Name(` — тот же вызов.
	sel := calledFuncNames(map[string]string{
		"c.go": "package p\nfunc use(x t) { x.Reconcile() }\n",
	})
	if !sel["Reconcile"] {
		t.Fatalf("вызов через селектор не засчитан — гейт объявил бы мёртвым " +
			"строителя, который зовётся методом")
	}
}
