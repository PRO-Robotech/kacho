// licensemap.go — ОТОБРАЖЕНИЕ путь→лицензия: единственное место дерева, где
// сказано, под какой лицензией лежит файл по данному пути.
//
// # Почему отображение, а не одна константа
//
// До 2026-09-04 лицензионный гейт держал идентификатор ЛИТЕРАЛОМ
// (`const spdxMarker = "SPDX-License-Identifier: BUSL-1.1"`) и требовал его от
// каждого файла в области покрытия. Пока лицензия в дереве одна, литерал и
// отображение неразличимы; как только уровней становится больше одного, литерал
// начинает лгать в обе стороны сразу:
//
//   - файл с ЛЮБОЙ другой лицензией читается как файл БЕЗ лицензии — гейт
//     краснеет с текстом «missing SPDX header» на файле, у которого заголовок
//     есть. Разбор уводит не туда: чинят отсутствие там, где предмет —
//     несовпадение;
//   - обратное молчание: заголовок, не отвечающий своему пути, распознать
//     нечем — сравнивать не с чем.
//
// # Уровни — следствие формы зависимости, а не вкус
//
// Реализация iam ВЫНЕСЕНА отдельным продуктом под AGPL-3.0-or-later и осталась
// потребителем фундамента `pkg/` и контрактов `proto/`, которые остаются здесь.
// Копилефт §10 AGPL запрещает налагать на получателя дополнительные ограничения
// сверх самой лицензии, а BUSL-1.1 именно такова: она ограничивает использование
// до наступления даты перехода. Значит фундамент и контракты обязаны быть
// ПЕРМИССИВНЫМИ — иначе выбранная форма зависимости невыразима юридически при
// том, что технически она собирается. Довод от выноса не ослаб, а УСИЛИЛСЯ:
// потребитель теперь в чужом дереве, и юридическая совместимость — единственное,
// что связывает две стороны.
//
//	pkg/           → Apache-2.0          фундамент, линкуется извне
//	proto/         → Apache-2.0          контракты, линкуются извне
//	остальное      → BUSL-1.1            монорепо без изменений
//
// Уровня `services/iam/` → AGPL-3.0-or-later здесь БОЛЬШЕ НЕТ: каталог уехал
// вместе с продуктом, а уровень, на который не разрешается ни один путь дерева,
// есть запись без предмета — её снимает ось четвёртая ниже. Запись и файл
// лицензии сняты ОДНИМ изменением: снятие файла без записи роняет соседний гейт
// громко, снятие записи без файла — молчит.
//
// # Третья сторона — не пропуск, а объявленный уровень
//
// `proto/google/` — вендоренные контракты Google под собственным уведомлением
// Apache-2.0. Наш заголовок им не положен: он утверждал бы наше авторство над
// чужим текстом. Поэтому уровень несёт ПУСТОЙ идентификатор, а не отсутствует в
// таблице, — и его пустота наблюдаема: уровень, под который в дереве не попал
// НИ ОДИН файл, есть послабление без предмета, и гейт на нём краснеет
// (см. TestLicenseHeadersMatchTheirTier).
//
// # Разрешение пути — по САМОМУ ДЛИННОМУ совпавшему префиксу
//
// Не по порядку записей: порядок — свойство, которое правящий таблицу обязан
// помнить, а длина префикса выводится из самой записи. `proto/google/api/x.proto`
// принадлежит третьей стороне, а не контрактам, потому что её префикс длиннее,
// а не потому, что запись стоит выше.
package repohygiene

import (
	"fmt"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/PRO-Robotech/kacho/internal/productnaming"
)

// Идентификаторы уровней. Держатся именованными константами, потому что их
// читают три разных места: заголовок файла, тело файла LICENSE и перепись.
const (
	licenseBUSL   = "BUSL-1.1"
	licenseApache = "Apache-2.0"
	licenseAGPL   = "AGPL-3.0-or-later"
)

// licenseTier — уровень лицензирования дерева.
type licenseTier struct {
	// Prefix — префикс rel-пути, ЗАКАНЧИВАЮЩИЙСЯ слэшем. Пустая строка —
	// умолчание всего дерева.
	Prefix string
	// Name — имя уровня, которым он назван в переписи и в находке.
	Name string
	// SPDX — идентификатор, который обязан стоять в заголовке файла этого
	// уровня. Пустая строка означает «файлы третьей стороны»: нашего заголовка
	// у них быть не должно.
	SPDX string
	// OwnLicenseFile — у корня уровня лежит СВОЙ файл LICENSE.
	OwnLicenseFile bool
}

// Root — каталог корня уровня в форме, в которой его отдаёт path.Dir: у
// умолчания это ".", у остальных — префикс без хвостового слэша.
func (t licenseTier) Root() string {
	if t.Prefix == "" {
		return "."
	}
	return strings.TrimSuffix(t.Prefix, "/")
}

// licenseTiers — само отображение. Порядок записей на разрешение НЕ влияет.
var licenseTiers = []licenseTier{
	{Prefix: "proto/google/", Name: "третья сторона", SPDX: ""},
	{Prefix: "pkg/", Name: "фундамент", SPDX: licenseApache, OwnLicenseFile: true},
	{Prefix: "proto/", Name: "контракты", SPDX: licenseApache, OwnLicenseFile: true},
	{Prefix: "", Name: "монорепо", SPDX: licenseBUSL, OwnLicenseFile: true},
}

// licenseTierFor — уровень, которому принадлежит путь: самый длинный совпавший
// префикс. Умолчание с пустым префиксом совпадает всегда, поэтому результат
// определён для любого пути и второго значения не требуется.
func licenseTierFor(rel string) licenseTier {
	best := -1
	for i, t := range licenseTiers {
		if t.Prefix != "" && !strings.HasPrefix(rel, t.Prefix) {
			continue
		}
		if best < 0 || len(t.Prefix) > len(licenseTiers[best].Prefix) {
			best = i
		}
	}
	return licenseTiers[best]
}

// licenseTierNames — имена уровней в порядке убывания длины префикса. Нужен
// переписи: она печатает объём осмотренного ПО КАЖДОМУ уровню отдельно, и
// порядок строк не должен зависеть от обхода карты.
func licenseTierNames() []string {
	tiers := append([]licenseTier(nil), licenseTiers...)
	sort.Slice(tiers, func(i, j int) bool { return len(tiers[i].Prefix) > len(tiers[j].Prefix) })
	out := make([]string, 0, len(tiers))
	for _, t := range tiers {
		out = append(out, t.Name)
	}
	return out
}

// licenseTextMarkers — по чему узнаётся ТЕЛО файла лицензии. Идентификатор в
// заголовке файла и текст лицензии — разные утверждения, и расходятся они
// молча: файл, названный Apache-2.0 и содержащий текст BUSL, валиден для всякого
// читателя, кроме юриста.
var licenseTextMarkers = map[string][]string{
	licenseBUSL:   {"Business Source License 1.1"},
	licenseApache: {"Apache License", "Version 2.0, January 2004"},
	licenseAGPL:   {"GNU AFFERO GENERAL PUBLIC LICENSE", "Version 3, 19 November 2007"},
}

// licenseSubjectAliases — каталоги, чьё имя НЕ совпадает с идентификатором
// компонента. Запись здесь заводится только под такое расхождение; каталог,
// чьё имя совпадает, в карте не появляется.
var licenseSubjectAliases = map[string]string{
	"gateway": "kacho-api-gateway",
}

// licenseFileWant — чего гейт ждёт от файла LICENSE по данному пути.
type licenseFileWant struct {
	// SPDX — какая это лицензия.
	SPDX string
	// Subject — идентификатор предмета в строке `Licensed Work:`. Пустой у
	// форм, где параметра предмета нет вовсе (Apache-2.0, AGPL-3.0): требовать
	// его от них значило бы требовать строки, которой в лицензии не бывает.
	Subject string
	// Tier — уровень, из которого выведено ожидание; идёт в текст находки.
	Tier string
}

// licenseFileWantFor — чего обязан быть файл LICENSE по этому пути. Второй
// результат false означает «правило этого места не знает» — это находка, а не
// пропуск: иначе первый же файл лицензии в новом каталоге выпал бы из
// наблюдения молча.
func licenseFileWantFor(rel string) (licenseFileWant, bool) {
	dir := path.Dir(rel)
	tier := licenseTierFor(rel)

	// Корень уровня: лицензия уровня, предмет — только у формы BUSL.
	if tier.OwnLicenseFile && tier.Root() == dir {
		want := licenseFileWant{SPDX: tier.SPDX, Tier: tier.Name}
		if tier.SPDX == licenseBUSL {
			want.Subject = "kacho"
		}
		return want, true
	}

	// Компонент внутри уровня BUSL: предмет выводится из пути механически —
	// новый сервис под services/ карты НЕ требует.
	if tier.SPDX == licenseBUSL {
		if alias, ok := licenseSubjectAliases[dir]; ok {
			return licenseFileWant{SPDX: licenseBUSL, Subject: alias, Tier: tier.Name}, true
		}
		if svc, ok := strings.CutPrefix(dir, "services/"); ok && svc != "" && !strings.Contains(svc, "/") {
			// Имя предмета спрашивается у владельца имён, а не собирается из
			// имени платформы: часть продукта вправе носить СВОЁ имя (#2076).
			return licenseFileWant{SPDX: licenseBUSL, Subject: productnaming.ChartName(svc), Tier: tier.Name}, true
		}
	}
	return licenseFileWant{}, false
}

// ─────────────────────────────────────────────────────────────────────────────
// ОСЬ ЧЕТВЁРТАЯ: у каждого уровня есть ПРЕДМЕТ в дереве
//
// # Зачем она, если неверный УРОВЕНЬ уже ловится тремя проверками
//
// Неверный уровень ловится немедленно: заголовок файла перестаёт совпадать с
// ожидаемым, и находка называет обе лицензии. А вот мёртвое ИМЯ записи не
// ловится ничем. [licenseTierFor] разрешает путь по самой длинной совпавшей
// приставке и о существовании путей под ней НЕ спрашивает, поэтому уровень, на
// который не разрешается ни один путь дерева, просто никогда не возвращается:
//
//	{Prefix: "services/nosuchservice/", Name: "…", SPDX: licenseAGPL}  // путей 0 → тишина
//
// Пока запись жива вместе со своим файлом лицензии, красное приходит от соседа:
// TestLicenseTierRootsCarryTheirLicenseFile роняет прогон на отсутствующем
// `<Prefix>/LICENSE`. Но как только запись снимут ВМЕСТЕ с файлом, пара уровней
// исчезает из наблюдения тихо: судимых рёбер этой пары становится ноль, а
// перепись совместимости печатает их отсутствие наравне с любым другим нулём.
//
// Соседняя карта путей эту ось уже несёт — judgeFoundationPrefixes в
// foundationboundary.go, — и покрывает ДВЕ карты (foundationSubtrees,
// foundationRoots). Карта лицензий была третьей картой путей корпуса и
// единственной без такой оси; симметрию собственного принципа надо было
// закрыть, а не объяснить.
//
// # Что считается «путём под уровнем» — РАЗРЕШЕНИЕ, а не совпадение приставки
//
// Считаются пути, которые [licenseTierFor] РАЗРЕШАЕТ в этот уровень, а не те,
// что начинаются с его приставки. Различие несущее: если под `proto/` окажутся
// только вендоренные файлы `proto/google/`, все они разрешатся в уровень
// третьей стороны (его приставка длиннее), и запись «контракты» станет мёртвым
// именем при непустом каталоге. Счёт по совпадению приставки этого не увидел бы
// НИКОГДА — то есть измерял бы не то, ради чего ось заводится.
//
// # Уровень по умолчанию исключён BY CONSTRUCTION, и это сказано, а не умолчано
//
// Пустая приставка совпадает со всяким путём, поэтому уровень умолчания
// разрешает всё, что не досталось другим, и мёртвым именем быть не может. Судить
// его нечем: находка на нём означала бы пустое дерево, а это уже предпосылка
// ниже, а не находка оси.
//
// # Сверка ОДНОСТОРОННЯЯ намеренно
//
// Путь дерева без своего уровня — не находка: он достаётся умолчанию, и это
// объявленное решение карты. Находка — только уровень без путей.

// licenseTierSubjectCensus — перепись оси четвёртой.
//
// Числа печатаются ПО КАЖДОМУ уровню отдельно: одно суммарное число скрыло бы
// ровно тот случай, ради которого ось заводится, — полный обход при нулевом
// одном уровне читается как чистота.
type licenseTierSubjectCensus struct {
	// Tiers — уровней осмотрено (включая умолчание).
	Tiers int
	// Judged — из них судимых осью (с непустой приставкой).
	Judged int
	// Live — из судимых те, на которые разрешился хотя бы один путь.
	Live int
	// PathsPerTier — путей, разрешённых в каждый уровень, по имени уровня.
	PathsPerTier map[string]int
	// Order — имена уровней в порядке печати, ВЫВЕДЕННЫЕ из судимой карты.
	//
	// Не из licenseTierNames(): та читает глобальную таблицу, и перепись
	// печатала бы имена, которых суждение не видело, а судимые — не печатала
	// вовсе. Это ровно тот класс «два места об одном предмете», ради которого
	// уровни и передаются параметром; собственная инъекция его и нашла.
	Order []string
	// Paths — путей разрешено всего.
	Paths int
}

// String — перепись одной строкой плюс строка на уровень.
func (c licenseTierSubjectCensus) String() string {
	var b strings.Builder
	fmt.Fprintf(&b, "уровней %d, из них судимых осью %d, с живым предметом %d; путей разрешено %d",
		c.Tiers, c.Judged, c.Live, c.Paths)
	for _, name := range c.Order {
		fmt.Fprintf(&b, "\n  уровень %-20s путей %6d", name, c.PathsPerTier[name])
	}
	return b.String()
}

// judgeLicenseTierSubjects — ось четвёртая как ЧИСТОЕ суждение.
//
// Уровни передаются параметром, а не читаются из [licenseTiers] по месту:
// инъекция обязана менять ровно один факт входа, а неизменяемая глобальная
// таблица этого не позволяет — доказательство пришлось бы строить на копии
// суждения, то есть доказывать не то, что исполняется.
func judgeLicenseTierSubjects(tiers []licenseTier, pathsPerTier map[string]int) ([]string, licenseTierSubjectCensus) {
	census := licenseTierSubjectCensus{Tiers: len(tiers), PathsPerTier: map[string]int{}}
	ordered := append([]licenseTier(nil), tiers...)
	sort.SliceStable(ordered, func(i, j int) bool { return len(ordered[i].Prefix) > len(ordered[j].Prefix) })
	for _, t := range ordered {
		census.Order = append(census.Order, t.Name)
		census.PathsPerTier[t.Name] = pathsPerTier[t.Name]
		census.Paths += pathsPerTier[t.Name]
	}

	// ПРЕДПОСЫЛКА. Обход, не разрешивший ни одного пути ни в один уровень, —
	// отказ, а не пустой успех: «мёртвых записей нет» означало бы непрочитанное.
	if len(tiers) == 0 {
		return []string{"карта лицензий пуста: судить нечего, и всякий вердикт о " +
			"лицензии пути относился бы к непрочитанному"}, census
	}
	if census.Paths == 0 {
		return []string{"обход пуст: ни один путь не разрешён ни в один уровень — " +
			"«мёртвых уровней нет» означало бы, что смотреть было не на что"}, census
	}

	var faults []string
	for _, t := range tiers {
		if t.Prefix == "" {
			continue // умолчание: совпадает со всем, мёртвым именем быть не может
		}
		census.Judged++
		if pathsPerTier[t.Name] > 0 {
			census.Live++
			continue
		}
		faults = append(faults, "карта лицензий объявляет уровень "+strconv.Quote(t.Name)+
			" с приставкой "+t.Prefix+", в который не разрешается НИ ОДИН путь дерева: "+
			"запись описывает несуществующее, никогда не совпадёт и потому не истечёт "+
			"сама — снимите её вместе с предметом")
	}

	if census.Judged == 0 {
		return []string{"судимых осью уровней ноль: у карты остался один уровень " +
			"умолчания, и мёртвое имя стало невыразимым — это отказ, а не чистота"}, census
	}

	sort.Strings(faults)
	return faults, census
}

// licenseTierPathCensus — путей, разрешённых в каждый уровень, по перечню путей.
// Разрешение идёт тем же [licenseTierFor], которым его судят остальные проверки:
// второй способ считать разошёлся бы с первым молча.
func licenseTierPathCensus(paths []string) map[string]int {
	out := map[string]int{}
	for _, rel := range paths {
		out[licenseTierFor(rel).Name]++
	}
	return out
}
