// gitrevcause.go — ОДИН дом для двух вещей, которыми отказ о ревизии отличает
// свою причину от соседней: вопроса о ГЛУБИНЕ клона и словаря РЕМОНТА.
//
// # Предмет: разделителя из одного числа не существует
//
// `git rev-parse --verify --quiet <объект>` отвечает кодом 1 И на «объекта нет
// вовсе», И на «объект существует у источника, но не довезён мелким клоном».
// Измерено на паре origin/`--depth=1` с двумя пустыми коммитами (git 2.x,
// 2026-09-22):
//
//	недовезённая ревизия · мелкий клон  · --verify --quiet   → 1
//	выдуманная ревизия   · ПОЛНЫЙ клон  · --verify --quiet   → 1
//	корневой коммит      · ПОЛНЫЙ клон  · HEAD^ --verify -q  → 1
//	те же два первых входа           · БЕЗ --quiet           → 128
//	каталог не является репозиторием                         → 128
//
// Ни одно число этих входов не разделяет: «нет объекта» и «не довезён» приходят
// как 1 неотличимо, а 128 достаётся сразу трём непохожим состояниям. Значит
// различение строится НЕ на коде возврата, а на отдельно заданном вопросе —
// мелкий ли клон, — и задаётся он ДО классификации.
//
// # Почему вопрос и словарь живут в одном НЕ-тестовом файле
//
// Механизм `rev-parse --verify` стоит в дереве не в одном месте, и ошибался он
// одинаково: отказ утверждал «объекта нет», где объект был не довезён, — то есть
// ЛГАЛ О ПРИЧИНЕ и посылал читающего чинить не то. Пока вопрос о глубине задаёт
// каждое место своими руками, это не «второй вызов», а второй ИСТОЧНИК: сойтись
// копиям нечем, и расходятся они молча.
//
// То же со словом РЕМОНТА. Пока каждое место называет ремонт своей прозой, а
// проба ищет в отказе подстроку, проверка ловит переименование слова (краснеет
// зря) и молчит на подмене смысла (предложение переписано, слово сохранено).
// Общий источник переворачивает обе стороны: производитель собирает текст ИЗ
// него, утверждение спрашивает ЕГО ЖЕ — переименование двигает обе стороны
// согласованно, а своя проза мимо источника краснеет.
//
// Файл НЕ тестовый намеренно: вопрос о глубине зовёт и прод-разбор
// ([gateCarrierBase] в gatecarrierremoval.go), и пробы; тестовый файл первому
// недоступен by construction.

// gitCloneIsShallow — МЕЛКИЙ ЛИ КЛОН по этому пути.
//
// Это и есть недостающий разделитель (см. шапку файла).
//
// Отказ самого вопроса означает «не знаем» и читается как НЕ мелкий: спрашивают
// это уже после того, как дерево ответило кодом 1, то есть дерево спрошено, и
// придумывать ему мелкость по неответу значило бы менять одну ложь о причине на
// другую.
func gitCloneIsShallow(root string) bool {
	out, err := gitenv.Command(root, "rev-parse", "--is-shallow-repository").Output()
	return err == nil && strings.TrimSpace(string(out)) == "true"
}

// Словарь РЕМОНТА: по одной формулировке на причину, объявленной в дереве ОДИН
// раз.
//
// Формулировка — ЦЕЛАЯ, а не слово. Слово («ГЛУБИНЫ») проходит и в переписанном
// мимо источника предложении; клауза целиком — нет, и ровно этим утверждение о
// ремонте перестаёт быть поиском подстроки.
const (
	// gitRevRemedyLedger — объекта нет, и клон ПОЛНЫЙ: врёт запись ведомости.
	gitRevRemedyLedger = "ремонт — в ЗАПИСИ ВЕДОМОСТИ"
	// gitRevRemedyCloneDepth — объект может существовать у источника: врёт не
	// запись, а глубина клона.
	gitRevRemedyCloneDepth = "ремонт начинается с ГЛУБИНЫ КЛОНА"
	// gitRevRemedyWorkingDir — дерева не спросили вовсе.
	gitRevRemedyWorkingDir = "ремонт — в РАБОЧЕМ КАТАЛОГЕ"
	// gitRevRemedyDeclaredBase — родителя нет ПО СУЩЕСТВУ: HEAD есть корневой
	// коммит, и вывести точку сравнения неоткуда. Ни ведомость, ни глубина, ни
	// рабочий каталог здесь ни при чём — назвать базу обязан вызывающий
	// (ручка [gateCarrierBaseEnv]).
	//
	// Четвёртая клауза заведена задним числом и по находке: ветвь корневого
	// коммита ремонта не называла ВОВСЕ, и её причина утверждалась подстрокой
	// «корневой» мимо этого словаря — ровно тем поиском по свободной прозе,
	// ради снятия которого словарь и появился.
	gitRevRemedyDeclaredBase = "ремонт — в ЯВНО ОБЪЯВЛЕННОЙ БАЗЕ"
)

// gitRevRemedyNamed — назван ли в отказе ремонт ИМЕННО ЭТОТ.
//
// Отдельной функцией ради инъекции: пара, доказывающая, что утверждение о
// ремонте способно покраснеть, зовёт ТОТ ЖЕ код, что и настоящие утверждения, —
// иначе она доказывала бы свойство своей копии.
func gitRevRemedyNamed(err error, remedy string) bool {
	return err != nil && strings.Contains(err.Error(), remedy)
}
