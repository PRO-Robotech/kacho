// quotasyncobserver_test.go — слепой тянущий величин квот не заводится
// незаметно.
//
// # Предмет
//
// Тянущий величин работает и без стока наблюдаемости — так объявлено у ядра, и
// это правильно: наблюдение не должно ронять доставку величин. Цена в том, что
// слепой тянущий СНАРУЖИ НЕОТЛИЧИМ от живого. На неизменной конфигурации живой
// правит ноль строк, поэтому нулевой счёт строк не говорит ничего; сказать
// могли бы «сколько проходов состоялось» и «когда удался последний» — но без
// стока этих рядов нет вовсе, и «ни одного прохода за всю жизнь» произнести
// нечем.
//
// # Почему гейт, а не пункт регламента
//
// Компилятор держит ПОЛОВИНУ свойства: параметр стока обязателен, поэтому
// шестой владелец не сможет его не заметить, а пятеро нынешних правятся
// принудительно. Но `nil` компилируется — и это ровно тот исход, который
// выглядит рабочим и молчит. Вторая половина — свойство ДЕРЕВА («ни один вызов
// не поднимает тянущего вслепую»), и держать её может только обход дерева.
// Шестого владельца заведут копированием пятого; скопироваться обязан и сток.
//
// # Предмет сужен СВОЙСТВОМ, а не перечнем прощённых
//
// Судится не «сервис из списка», а вызов подъёма — любой, где бы он ни стоял.
// Перечня исключений здесь нет и заводить его нельзя: каждая запись в таком
// перечне есть место, куда слепой тянущий вносят незамеченным. Позиция
// аргумента тоже не выписана — она выводится из объявления подъёма, поэтому
// перестановка параметров гейт не обманет, а исчезновение параметра стока
// роняет его на собственной предпосылке.

// quotaSyncCorpus — состав дерева для разбора: прод-файлы Go под каталогами
// сервисов и общего фундамента.
//
// Состав берётся у ИНДЕКСА git (через общий обходчик), а не с диска: под
// services/ на всякой машине, где поднимали стенд, лежат распаковки чартов и
// отчёты прогонов, и обход диска судил бы чужой рабочий каталог.
func quotaSyncCorpus(t *testing.T, root string) []string {
	t.Helper()
	var files []string
	walkOwnerRegisterGoFiles(t, root, []string{"services", "pkg"}, func(rel string, _ []byte) {
		files = append(files, filepath.Join(root, rel))
	})
	return files
}

// TestEveryLimitSyncerCarriesItsObservabilitySink — каждый подъём тянущего
// величин несёт сток наблюдаемости.
func TestEveryLimitSyncerCarriesItsObservabilitySink(t *testing.T) {
	root := repoRoot(t)
	files := quotaSyncCorpus(t, root)

	c, err := ScanQuotaSyncSink(root, files)
	if err != nil {
		// Отказ предпосылки, а не находка: разбор не понял дерева, и его
		// молчание не значило бы ничего.
		t.Fatalf("предпосылка гейта не держится: %v", err)
	}

	// ── перепись: «ноль находок» обязано быть отличимо от «ноль прочитанного» ──
	sites := make([]string, 0, len(c.Calls))
	direct := 0
	for _, call := range c.Calls {
		via := "прямой"
		if call.Via != "" {
			via = "через " + call.Via
		} else {
			direct++
		}
		arg := call.Arg
		if arg == "" {
			arg = "<аргумента нет>"
		}
		sites = append(sites, call.File+":"+itoa(call.Line)+" ("+via+", сток: "+arg+")")
	}
	sort.Strings(sites)
	t.Logf("прочитано файлов Go: %d, разобрано: %d; объявление подъёма: %s:%d, параметров %d, "+
		"сток — %q на позиции %d; вызовов распознано: %d (прямых %d); пересыльщиков: %d; находок: %d\n  %s",
		c.FilesRead, c.FilesParsed, c.DeclFile, c.DeclLine, c.Arity, c.SinkParam, c.SinkIndex+1,
		len(c.Calls), direct, len(c.Forwarders), len(c.Findings), strings.Join(sites, "\n  "))

	if c.FilesRead == 0 {
		t.Fatal("осмотрено ноль файлов — гейт не читал дерева, и его молчание ничего не значит")
	}
	if len(c.Calls) == 0 {
		t.Fatal("распознано ноль вызовов подъёма при найденном объявлении — это поломка " +
			"разбора, а не чистота дерева: объявление без единого вызывающего означало бы " +
			"мёртвый подъём, и тогда снимать надо его, а не молчать")
	}

	if len(c.Findings) > 0 {
		var lines []string
		for _, f := range c.Findings {
			lines = append(lines, f.File+":"+itoa(f.Line)+" — "+f.Why)
		}
		sort.Strings(lines)
		t.Fatalf("тянущий величин поднимается вслепую:\n  %s", strings.Join(lines, "\n  "))
	}
}
