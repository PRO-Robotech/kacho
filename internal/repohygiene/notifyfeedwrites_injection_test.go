// notifyfeedwrites_injection_test.go — УК87, CX1-74 (а): тонкий вызывающий
// `treehygiene.AuditFeedTableWrites` В ФОРМЕ ДЕРЕВА kacho (корень, каталог
// стабов `pkg/api`, модуль kacho) видит функцию миграции модуля, пишущую окно
// ленты, и называет её координатой.
//
// Вызов гейта по самому дереву kacho — `TestNTF1B19FeedWriters_OnKacho`
// (notifytreegates_test.go, полоса D7): второго вызывающего по дереву здесь
// не заводится. Здесь — инъекция: синтетическое дерево модуля kacho в
// индексе git (гейт читает отслеживаемые `*.sql`, а не диск), один пакет Go и
// одна миграция модуля. Порча меняет ровно один факт против близнеца:
// функция миграции с `UPDATE <svc>_notification_window` вместо функции без
// таблиц ленты.

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/treehygiene"
)

// feedWritesTree — синтетическое дерево модуля kacho с миграцией migration.
func feedWritesTree(t *testing.T, migration string) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"go.mod":       "module " + kachoModulePath + "\n\ngo 1.26\n",
		"pkg/api/x.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n\nconst V = 1\n",
		"services/vpc/internal/x/x.go": "package x\n\nimport \"fmt\"\n\n" +
			"func Q(id string) string { return fmt.Sprintf(\"SELECT 1 FROM vpc_items WHERE id = %q\", id) }\n",
		"services/vpc/internal/migrations/20261004000000_fn.sql": migration,
	}
	for rel, body := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.Command("git", args...) // #nosec G204 -- argv фиксирован
		cmd.Dir = root
		// Без GIT_DIR и родни: из хука git они указали бы на чужое хранилище.
		for _, kv := range os.Environ() {
			if !strings.HasPrefix(kv, "GIT_") {
				cmd.Env = append(cmd.Env, kv)
			}
		}
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: git %v: %v\n%s", args, err, out)
		}
	}
	return root
}

const feedWritesTwinMigration = `-- +goose Up
CREATE FUNCTION vpc_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE vpc_items SET updated_at = now() WHERE id = NEW.id;
  RETURN NEW;
END $$;
-- +goose Down
DROP FUNCTION vpc_touch();
`

// TestUK87FeedWindowWriterInModuleMigration_KachoCallerForm — близнец и порча
// гейта писателей таблиц ленты в форме вызова по дереву kacho.
func TestUK87FeedWindowWriterInModuleMigration_KachoCallerForm(t *testing.T) {
	t.Parallel()
	twin, err := treehygiene.AuditFeedTableWrites(feedWritesTree(t, feedWritesTwinMigration), "pkg/api")
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: %v", err)
	}
	t.Logf("близнец: %s", twin)
	if twin.Census.Files == 0 || twin.SQLFiles == 0 || twin.Census.Generated == 0 {
		t.Fatalf("близнец: пустой обход — не вердикт: %s", twin)
	}
	if len(twin.Findings) != 0 || twin.WindowSites != 0 || twin.Exceptions != 0 {
		t.Fatalf("законный близнец (функция миграции без таблиц ленты) объявлен находкой либо несёт "+
			"писателей окна или применимые записи реестра: %s", twin)
	}

	injected := strings.Replace(feedWritesTwinMigration, "UPDATE vpc_items SET updated_at = now() WHERE id = NEW.id;",
		"UPDATE vpc_notification_window SET count = 0;", 1)
	r, err := treehygiene.AuditFeedTableWrites(feedWritesTree(t, injected), "pkg/api")
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: %v", err)
	}
	t.Logf("порча: %s", r)
	var got []string
	for _, f := range r.Findings {
		got = append(got, f.String())
	}
	joined := strings.Join(got, "\n")
	t.Logf("находки порчи: %s", joined)
	if r.SQLFindings == 0 || !strings.Contains(joined, "services/vpc/internal/migrations/20261004000000_fn.sql") {
		t.Errorf("функция миграции модуля, пишущая окно ленты, не названа находкой с координатой: %s", joined)
	}
}
