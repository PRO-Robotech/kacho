// notifyfeedwrites_injection_test.go — УК87, CX1-74 (а): тонкий вызывающий
// `treehygiene.AuditFeedTableWrites` В ФОРМЕ ДЕРЕВА kacho (корень, каталог
// стабов `pkg/api`, модуль kacho) видит функцию миграции модуля, пишущую окно
// ленты, и называет её координатой.
//
// Вызов гейта по самому дереву kacho — `TestNTF1B19FeedWriters_OnKacho`
// (notifytreegates_test.go, полоса D7): второго вызывающего по дереву здесь
// не заводится. Здесь — инъекция: синтетическое дерево модуля kacho в
// индексе git (гейт читает отслеживаемые `*.sql`, а не диск), один пакет Go и
// одна миграция модуля. Порча меняет ровно один факт против близнеца:
// функция миграции с `UPDATE <svc>_notification_window` вместо функции без
// таблиц ленты.
//
// Законное дерево kacho несёт функцию базы resource-event (NTF-3 З10): запись
// реестра исключений гейта с областью kacho применяется к нему и без функции
// краснеет самоистечением. Поэтому в синтетическом дереве рядом с миграцией
// предмета лежит миграция функции — вывод шаблона corelib
// (resourceevent.Render), а не её копия: у близнеца применимая запись одна и
// признанная функция одна, находок нет.

