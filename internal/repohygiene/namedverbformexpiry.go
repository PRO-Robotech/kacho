// namedverbformexpiry.go — разбор пары, которой держится отсрочка `#1844`:
// поимённая форма права роли (ключ `verbs:` в правиле) отвергается сентинелом
// ДО разбора, и ровно поэтому шести проб её полноты в дереве нет.
//
// # Предмет: отсрочка, у которой не было ПРОИЗВОДИТЕЛЯ снятия
//
// Шесть сценариев приёмки `#1090` — MOD-RL-04, 04a, 18, 18a, 19, 19a — проб не
// имеют, и это НЕ «не написаны»: их `Given` требует ключа `verbs:` в правиле
// роли, а ключ снят и отвергается пред-разборной проверкой со своим сентинелом
// (`manifest.ErrRoleRuleVerbsRetired`). Входа у них нет ни при каком написании.
//
// Отсрочка законна (запрет #11, третий исход: у неё есть ПРЕДМЕТ с номером), но
// до сих пор держалась только прозой. Прозе нечем истечь: в день, когда ключ
// снова станет законным входом, ни одна проверка дерева не заметит, что шесть
// проб полноты по-прежнему отсутствуют, — а именно этого сочетания приёмка и
// запрещает. Её довод дословен: принять перечень ИМЁН, не умея проверить его
// полноту по классу, значит свести его к классу МОЛЧА и выдать право шире
// просимого (замер приёмки: 55 вхождений из 92 в черновике vpc совпадают с
// именем класса).
//
// # Что здесь находка — ПАРА, а не любая её половина
//
// Находка ровно одна: сентинел БОЛЬШЕ НЕ ВОЗВРАЩАЕТСЯ прод-кодом манифеста,
// И проб шести сценариев в дереве по-прежнему нет. Каждая половина по
// отдельности законна и находкой не является:
//
//   - сентинел возвращается, проб нет — сегодняшнее состояние: форма отвергнута,
//     проверять полноту не по чему;
//   - сентинел не возвращается, пробы есть — форма вернулась ВМЕСТЕ со своей
//     проверкой, то есть ровно так, как требует приёмка.
//
// Гейт, судящий одну половину, был бы либо красным сегодня (при живой и законной
// отсрочке), либо не заметил бы возвращения формы без проверки — то есть ровно
// того, ради чего он заводится.
//
// # Почему сентинел судится ВОЗВРАТОМ, а не упоминанием
//
// Имя `ErrRoleRuleVerbsRetired` стои́т в объявлении, в тексте отказа, в пробах и
// в прозе этого файла. Гейт, считающий вхождения, краснел бы на собственном
// объяснении и молчал бы на объявлении, которое никто не возвращает, — то есть
// на мёртвом сентинеле, неотличимом от живого. Разбор судит УЗЕЛ: присваивание
// поля `kind` этим именем внутри составного литерала, возвращаемого функцией.
//
// # Чего разбор НЕ видит — названо, а не спрятано
//
// Возврат сентинела, собранный в рантайме (через переменную, через таблицу
// видов). Такой формы в этом пакете нет, и появись она — гейт увидит ноль
// возвратов и покраснеет, то есть ошибётся В СТОРОНУ находки, а не молчания.
package repohygiene

import (
	"go/ast"
	"go/parser"
	"go/token"
	"strings"
)

// VerbFormSentinelCensus — объём, осмотренный разбором ОДНОГО файла.
type VerbFormSentinelCensus struct {
	// CompositeLits — составных литералов прочитано. Предпосылка оси: разбор
	// ищет присваивание внутри литерала, и ноль литералов означает, что искать
	// было негде.
	CompositeLits int
	// Idents — идентификаторов прочитано: объём разбора в самой мелкой единице.
	Idents int
	// SentinelReturns — возвратов сентинела найдено.
	SentinelReturns int
}

// RoleRuleVerbsSentinel — имя сентинела, которым пред-разборная проверка
// отвергает снятый ключ. Объявлено ЗДЕСЬ, потому что гейт живёт в пакете корня
// репозитория, а сентинел — в `services/iam/internal/…`, закрытом правилом
// видимости Go. Что имя не разошлось с продуктом, утверждает сам гейт: ноль
// возвратов на живом дереве — находка, а не молчание.
const RoleRuleVerbsSentinel = "ErrRoleRuleVerbsRetired"

// ScanVerbFormSentinel считает ВОЗВРАТЫ сентинела в одном файле Go.
//
// Возвратом считается присваивание `kind: <Сентинел>` в составном литерале,
// стоящем внутри `return` — то есть исход функции, а не упоминание имени.
func ScanVerbFormSentinel(rel string, src []byte) (VerbFormSentinelCensus, error) {
	var census VerbFormSentinelCensus
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, rel, src, 0)
	if err != nil {
		return census, err
	}

	// Составные литералы, лежащие внутри return: только их исход виден снаружи.
	inReturn := map[*ast.CompositeLit]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		ret, ok := n.(*ast.ReturnStmt)
		if !ok {
			return true
		}
		ast.Inspect(ret, func(m ast.Node) bool {
			if cl, ok := m.(*ast.CompositeLit); ok {
				inReturn[cl] = true
			}
			return true
		})
		return true
	})

	ast.Inspect(f, func(n ast.Node) bool {
		switch node := n.(type) {
		case *ast.Ident:
			census.Idents++
		case *ast.CompositeLit:
			census.CompositeLits++
			if !inReturn[node] {
				return true
			}
			for _, el := range node.Elts {
				kv, ok := el.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				key, ok := kv.Key.(*ast.Ident)
				if !ok || key.Name != "kind" {
					continue
				}
				if id, ok := kv.Value.(*ast.Ident); ok && id.Name == RoleRuleVerbsSentinel {
					census.SentinelReturns++
				}
			}
		}
		return true
	})
	return census, nil
}

// NamedVerbFormFinding — РЕШЕНИЕ гейта одной функцией: сценарии, оставшиеся без
// пробы, когда форма уже не отвергается.
//
// Объявлено здесь, а не внутри гейта, ровно затем, чтобы инъекция гоняла ТОТ ЖЕ
// предикат, что и прогон дерева: второй, написанный в пробе «по образцу»,
// разошёлся бы с первым молча — и разошёлся бы именно там, где расхождение не
// видно, потому что оба отвечают одинаково на сегодняшнем входе.
//
// Пустой результат означает молчание, и у него ДВЕ законные причины: форма
// отвергается (`sentinelReturns > 0`) либо она вернулась вместе со своей
// проверкой (пробы найдены). Различать их вызывающему не нужно — обе законны.
func NamedVerbFormFinding(sentinelReturns int, probeNames []string) []string {
	if sentinelReturns > 0 {
		return nil
	}
	return MissingScenarioProbes(probeNames)
}

// NamedVerbScenarios — шесть сценариев, чья проверка полноты и есть содержание
// отсрочки. Перечень ЗАКРЫТ и выписан: он приезжает из приёмки `#1090`, а не из
// дерева, и выводить его неоткуда — проб этих сценариев в дереве ноль by
// construction, то есть вывод из дерева дал бы пустой перечень и гейт, которому
// нечего требовать.
var NamedVerbScenarios = []string{"04", "04a", "18", "18a", "19", "19a"}

// ScenarioProbeName — имя пробы сценария в написании этого дерева.
func ScenarioProbeName(scenario string) string { return "TestMODRL" + scenario }

// MissingScenarioProbes — сценарии из закрытого перечня, у которых в дереве нет
// ни одной пробы.
//
// Принимается перечень ИМЁН функций, а не текст файлов: подстрока `TestMODRL04`
// стои́т и внутри `TestMODRL04a`, и гейт, судящий вхождение, зачёл бы одну пробу
// за две. Имя сравнивается с ПРЕФИКСОМ и следующим за ним символом.
func MissingScenarioProbes(funcNames []string) []string {
	var missing []string
	for _, s := range NamedVerbScenarios {
		want := ScenarioProbeName(s)
		found := false
		for _, name := range funcNames {
			if !strings.HasPrefix(name, want) {
				continue
			}
			rest := name[len(want):]
			// `TestMODRL04` против `TestMODRL04a`: следующий символ обязан НЕ
			// продолжать номер сценария.
			if rest != "" && (rest[0] >= '0' && rest[0] <= '9' || rest[0] >= 'a' && rest[0] <= 'z') {
				continue
			}
			found = true
			break
		}
		if !found {
			missing = append(missing, s)
		}
	}
	return missing
}
