// ct3_registry_probe_window_value.go — корпус проб registry не приписывает
// ожиданию величину, у которой в дереве нет производителя.
//
// ПРЕДМЕТ (задача продукта #1730). Ожидание видимости выдачи обосновывалось в
// корпусе проб величиной «~0.6–2s» — ценой очереди к ВНЕШНЕМУ движку прав.
// Движок снят вместе со своей выделенной базой (см. надгробие `pg-openfga` в
// профиле боевого развёртывания), поэтому величина пережила свой предмет:
// производителя у неё нет ни одного, и сверить её не с чем.
//
// ПОЧЕМУ ЭТО НЕ ПРОСТО УСТАРЕВШЕЕ ЧИСЛО. В документе такая величина неверна и
// безобидна; в корпусе проб она есть ОБОСНОВАНИЕ ОЖИДАНИЯ. Бюджет повтора
// выбирается «чтобы покрыть окно», и если окно названо величиной снятого
// механизма, то бюджет обоснован тем, чего нет, — а зелёная проба означает не то,
// что она утверждает. Замер 2026-08-31: ни одно из четырёх исполняемых мест НЕ
// ждало по этой величине (все ждут УСЛОВИЯ, бюджет объявлен на связывании) —
// то есть до дефекта проб не дошло, но обоснование было ложным у всех четырёх.
//
// НОРМА, КОТОРУЮ ЭТО ЗАКРЕПЛЯЕТ. Обоснование ожидания называет ПРОИЗВОДИТЕЛЯ
// величины — ручку кэша вердиктов, документацию владельца прав, бюджет на
// связывании, — а не саму величину в прозе. Прозаическая величина есть второе
// место об одном предмете и расходится с производителем МОЛЧА: правка умолчания
// ручки комментария не касается. Норма выведена не здесь — она уже стоит в этом
// же корпусе (`services/registry/tests/newman/scripts/gen.py`, у связывания
// `_rya`: «Величина видна на связывании, а не в прозе шапки»).
//
// ЧЕГО ГЕЙТ НЕ ДЕРЖИТ — названо, а не спрятано:
//
//   - ОБЩУЮ норму выше. «Величина окна» и «величина бюджета» в прозе отличаются
//     только смыслом: `10× по 1.5s` — законное объявление бюджета, `окно ~2s` —
//     запрещённая копия чужой величины, и обе суть длительность в комментарии.
//     Машинного предиката у различия нет, поэтому норму держит порядок работ и
//     обзор, а гейт держит её НАСТУПИВШИЙ частный случай — величину снятого
//     механизма. Узкий предикат, который доказан, лучше широкого, который слеп;
//   - ПРИГОДНОСТЬ бюджета. Покрывает ли `10× по 1.5s` настоящее окно — свойство
//     ПРОГОНА на поднятом стенде, а не текста. Гейт об этом не высказывается.
//     Замер по дереву показал, что бюджеты одного и того же окна в этом корпусе
//     расходятся втрое (10s у случаев авторизации, 15s у оболочки данных, 48s у
//     связывания `_rya`); это находка, но её предмет — прогон, и заведена она
//     отдельно;
//   - КОРПУСА ДРУГИХ сервисов. Окно принадлежит владельцу кэша, и путь
//     материализации у доменов разный — «одно число за всех было бы решением за
//     них» (тот же `gen.py`). Снятие движка проверено для контекста registry;
//     что цитата соседнего домена ложна ДЛЯ ЕГО состава окна, не измерено, и
//     утверждать это значило бы назвать число без предиката. Поэтому обход
//     сужен до корпуса registry ОСОЗНАННО, а не по умолчанию.
//
// ГРАНИЦА СОСЕДНЕГО ГЕЙТА — ТОЖЕ РЕШЕНИЕ. `ct2_misc_authz_window` судит
// КЛИЕНТСКИЕ СТРАНИЦЫ и на дерево проб не распространён намеренно: его обе
// половины предполагают страницу («названа ли ручка», «совпала ли величина с
// умолчанием»), а его грамматика — разметка страницы и оборот «по умолчанию N».
// Комментарий оболочки и комментарий генератора случаев страницами не являются и
// клиента ждать не отправляют; требовать от них этой грамматики значило бы
// завести вторую грамматику внутри одного гейта — ровно то, от чего его
// собственная шапка отказывается в случае экранированных подчёркиваний.
//
// ПОЧЕМУ ОТРИЦАТЕЛЬНОЕ УТВЕРЖДЕНИЕ ЗДЕСЬ НЕ ЗАМОЛЧИТ (`testing.md` §«Гейт на
// класс», п.9). Негативная проверка немеет, когда её вход перестаёт
// ПРОИЗВОДИТЬСЯ механизмом — снят контракт, снят генератор. Здесь вход
// производит человек, пишущий комментарий, и исчезнуть он может только вместе с
// целью гейта. Что действительно может отнять у гейта предмет — переезд корпуса
// проб; ровно на это стоит проверка предпосылки: пустой обход роняет прогон.
package repohygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

// ct3ProbeCorpusDir — корпус, за который гейт отвечает. Сужение до registry —
// решение, обоснованное в шапке (владелец окна называет свою величину сам).
const ct3ProbeCorpusDir = "services/registry/tests/newman/"

// ct3UnitRe — единица длительности и её ГРАНИЦА.
//
// Граница выражена явным «дальше не буква», а НЕ `\b`. Причина измерена, а не
// предположена: `\b` в этом языке — граница ASCII-слова, и кириллическая `с`
// для него не буква вовсе. Значит `с\b` перед пробелом требовал бы перехода,
// которого нет, и запись «~0.6–2 с» — та самая, что стояла на клиентской
// странице, — не совпала бы НИКОГДА. Это не край и не редкость: форма, о
// которой распознаватель не знает, даёт не находку и не молчание, а
// невидимость (`testing.md` §«Гейт на класс», п.7), и заметить её нельзя ничем,
// кроме инъекции именно этой формой — она стоит в наборе.
//
// Длинные записи идут первыми: иначе `с` совпала бы с началом `сек`, а
// требование «дальше не буква» отвергло бы строку, которая предмет содержит.
const ct3UnitRe = `(?:msec|мсек|sec|сек|ms|мс|s|с)(?:[^\p{L}]|$)`

// ct3WindowForm — одна ЗАКОННАЯ ФОРМА ЗАПИСИ предмета.
//
// Форм несколько НАМЕРЕННО. Распознаватель, знающий одну форму, оставляет всё
// записанное иначе вне наблюдения — не находкой и не молчанием, а невидимостью
// (`testing.md` §«Гейт на класс», п.7). Формы не придуманы: обе записи тире и
// обе записи единицы СТОЯЛИ в дереве одновременно — корпус случаев писал
// `~0.6-2s` дефисом, документы и оболочка `~0.6–2s` тире, клиентская страница
// `~0.6–2 с` кириллической единицей.
type ct3WindowForm struct {
	// Name — как форма зовётся в переписи и в находке.
	Name string
	// Re — распознаватель формы.
	Re *regexp.Regexp
}

// ct3RetiredWindowForms — величина снятого механизма во всех известных записях,
// и цена ожидания, приписанная его очереди.
var ct3RetiredWindowForms = []ct3WindowForm{
	{
		// Величина как таковая: «0.6», любое тире, «2», любая единица. Разделитель
		// дробной части — точка или запятая; тире — дефис, среднее или длинное;
		// единица — латинская `s`, кириллическая `с`, `sec`, `сек`.
		Name: "величина снятого механизма",
		Re: regexp.MustCompile(
			`0[.,]6\s*[-\x{2010}\x{2011}\x{2012}\x{2013}\x{2014}]\s*2\s*` + ct3UnitRe),
	},
	{
		// Цена, приписанная очереди снятого движка. Ловит переписанное число:
		// `~1-3s` вместо `~0.6-2s` — тот же дефект в другой записи.
		//
		// Дискриминатор — СОСТАВНОЕ имя («FGA-пропагация», «FGA propagation»), а
		// не голый токен `FGA`: он законно стоит в корпусе десятками (модель,
		// реконсайлер, Write, тип объекта), и предикат по нему давал бы ложные
		// находки — а проверку, у которой находки ложные, перестают читать.
		Name: "цена, приписанная очереди снятого движка",
		Re: regexp.MustCompile(
			`(?i)FGA[- ](?:пропагац|propagation)[^\n]*?\d+\s*` + ct3UnitRe),
	},
}

// ct3ProbeWindowCitation — одно место, называющее величину без производителя.
type ct3ProbeWindowCitation struct {
	// Rel — координата; находка обязана её называть.
	Rel string
	// Line — номер строки; находка обязана его называть.
	Line int
	// Form — какой формой опознано: без этого читатель не поймёт, что править.
	Form string
	// Text — сама строка, усечённая: находка обязана показать предмет.
	Text string
}

// ct3ProbeWindowCensus — перепись обхода. Печатается ВСЕГДА: «ноль находок»
// обязано быть отличимо от «ноль прочитанного».
type ct3ProbeWindowCensus struct {
	// CorpusDir — за какой корпус гейт отвечал в этом прогоне.
	CorpusDir string
	// FilesRead — сколько файлов корпуса прочитано.
	FilesRead int
	// LinesScanned — сколько строк осмотрено. Вторая величина переписи: файл
	// можно «прочитать» пустым, и одно число это скрыло бы.
	LinesScanned int
	// FormsKnown — сколько форм записи знает распознаватель.
	FormsKnown int
	// Citations — найденное.
	Citations []ct3ProbeWindowCitation
}

// collectRegistryProbeWindow обходит корпус проб registry.
//
// Состав дерева берётся у ИНДЕКСА git, а не у диска: рядом с корпусом лежат
// выводы прогонов и каталоги зависимостей, и вердикт, собранный обходом файловой
// системы, стал бы свойством рабочего каталога, а не коммита.
func collectRegistryProbeWindow(tree *treecorpus.Tree) (ct3ProbeWindowCensus, error) {
	c := ct3ProbeWindowCensus{
		CorpusDir:  ct3ProbeCorpusDir,
		FormsKnown: len(ct3RetiredWindowForms),
	}

	for _, rel := range tree.SortedFiles() {
		if !strings.HasPrefix(rel, ct3ProbeCorpusDir) {
			continue
		}
		body, err := os.ReadFile(filepath.Join(tree.Root(), filepath.FromSlash(rel)))
		if err != nil {
			return c, fmt.Errorf("чтение %s: %w", rel, err)
		}
		c.FilesRead++
		for i, line := range strings.Split(string(body), "\n") {
			c.LinesScanned++
			for _, f := range ct3RetiredWindowForms {
				if !f.Re.MatchString(line) {
					continue
				}
				c.Citations = append(c.Citations, ct3ProbeWindowCitation{
					Rel: rel, Line: i + 1, Form: f.Name, Text: ct3Trim(line),
				})
				// Одна строка — одно место: перечислять все совпавшие формы
				// значило бы считать один дефект дважды.
				break
			}
		}
	}
	return c, nil
}

// ct3Trim — строка для находки: без отступа и не длиннее осмысленного.
func ct3Trim(s string) string {
	s = strings.TrimSpace(s)
	r := []rune(s)
	if len(r) > 120 {
		return string(r[:120]) + "…"
	}
	return s
}

// registryProbeWindowFindings — расхождения, каждое с координатой.
func registryProbeWindowFindings(c ct3ProbeWindowCensus) []string {
	var out []string
	for _, ct := range c.Citations {
		out = append(out, fmt.Sprintf(
			"%s:%d: обоснование ожидания называет %s — у этой величины нет "+
				"производителя в дереве (движок прав и его база сняты), сверить её "+
				"не с чем: назови ПРОИЗВОДИТЕЛЯ (ручку кэша вердиктов, документацию "+
				"владельца прав) либо бюджет на связывании: %s",
			ct.Rel, ct.Line, ct.Form, ct.Text))
	}
	return out
}
