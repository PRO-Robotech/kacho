// systemrolerowisneverdeleted.go — разбор прод-кода iam на предмет удаления
// строки СИСТЕМНОЙ роли (решение
// `services/iam/docs/engineering/architecture/role-withdrawal-is-a-mark.md`,
// задача продукта #1913).
//
// # Предмет
//
// Роль, объявленная манифестом модуля, системная BY CONSTRUCTION: применитель
// ставит `IsSystem: true`, а `roles.is_system` вычисляется из `cluster_id`.
// Значит вопрос «как снять роль модуля» есть вопрос «что делает прод-код со
// строкой системной роли», и у него два взаимоисключающих ответа: удалить
// строку либо пометить её снятой. Линия выбрала ВТОРОЙ, и вот чем измерена цена
// первого:
//
//  1. **роль в работе не удалится вовсе.** Выдачи ссылаются на роль ключом
//     `access_bindings_role_fk … ON DELETE RESTRICT`; удаление роли, за которой
//     стоит хоть одна строка выдачи, отвергается `SQLSTATE 23503`. То есть
//     удаление как форма отзыва отказывает ровно в том случае, ради которого
//     отзыв и делают;
//  2. **если бы не отвергалось — три проекции уехали бы МОЛЧА**: селекторы
//     правил, проекция глаголов и проекция объявленных сегментов. Каскад ничего
//     не печатает;
//  3. **отзыв перестал бы достигать ПРЕДЪЯВЛЕНИЯ наблюдаемо.** У снятой пометкой
//     строки есть что читать на пути запроса; у удалённой читать нечего, и
//     «роль отозвана» становится неотличимо от «роли не было никогда».
//
// # Что здесь считается находкой — ОДНА ось, и она про оператор
//
// Оператор `DELETE` над таблицей `roles`, не сужённый на ПОЛЬЗОВАТЕЛЬСКУЮ роль.
// Сужение опознаётся в ДВУХ законных написаниях, потому что оба выражают одно и
// то же: `is_system = false` (и `NOT is_system`) — прямо по вычисляемой колонке;
// `cluster_id IS NULL` — по кластерному якорю, из которого она и вычисляется.
// Распознаватель, знающий одно написание, объявил бы верный код находкой, а
// гейт, краснеющий на верном коде, отключают первым.
//
// Ось судит СТРОКОВЫЙ ЛИТЕРАЛ узла разбора, а не текст файла: слово `DELETE`
// стоит и в комментариях, объясняющих сам запрет, — гейт, судящий подстроку,
// краснел бы на собственном объяснении. Это поймал законный близнец инъекции.
//
// # Оператор отличается от ПРОЗЫ, ЦИТИРУЮЩЕЙ оператор, по продолжению
//
// Привязки к началу строки НЕДОСТАТОЧНО, и это измерено, а не предположено:
// текст отказа `"DELETE FROM roles здесь не производится безусловно"` — тоже
// строковый литерал, тоже начинается с оператора, и первая редакция этого
// разбора прочитала его как оператор. Поймал законный близнец инъекции, а не
// подозрение.
//
// Различает ПРОДОЛЖЕНИЕ: за именем таблицы у оператора идёт SQL (`WHERE`,
// `RETURNING`, `USING`, `;`, конец литерала), у прозы — проза. Форма «удалить
// всё без условия» при этом остаётся находкой by construction: у неё
// продолжение — конец литерала, и это самый опасный из представимых операторов.
//
// Слепая зона названа: сообщение об отказе, воспроизводящее ЦЕЛЫЙ оператор
// дословно (`"... DELETE FROM roles WHERE ..."`), стало бы находкой. Форма
// редкая, чинится перефразированием, и цена ошибки здесь — лишний разбор, а не
// пропущенное удаление.
//
// # Чего разбор НЕ видит — названо, а не спрятано
//
//  1. **миграции.** Их девять, и каждая снимала роль удалением — это СТАТУС-КВО,
//     который решение и заменяет, а не находка сегодняшнего дерева. Миграция как
//     писатель роли модуля запрещена отдельным гейтом
//     (`migrationnotawriterofmodulerole.go`, Г2), и у него свой предмет — вставка;
//  2. **каскад по чужому ключу.** Строка роли уезжает вместе со своим ярусом
//     (аккаунт, проект). Для СИСТЕМНОЙ роли ярус — кластер, и его удаление
//     означает конец кластера, а не отзыв роли;
//  3. **запрос, собранный из кусков в рантайме** либо приехавший параметром.
//     Первой формы в дереве нет; вторая означала бы, что оператор пишет не iam,
//     и предмет тогда переезжает целиком.
package repohygiene

import (
	"go/ast"
	"go/parser"
	"go/token"
	"regexp"
)

// RoleDeleteSite — координата находки.
type RoleDeleteSite struct {
	File string
	Line int
	// What — начало литерала: координата и первая строка называют место
	// однозначно, а целый запрос в сообщении нечитаем.
	What string
}

// RoleDeleteCensus — объём осмотренного одним файлом.
type RoleDeleteCensus struct {
	// StringLiterals — строковых литералов прочитано.
	StringLiterals int
	// Comments — комментариев прочитано. Печатается отдельно: ненулевой счётчик
	// при нулевых находках говорит, что различение «код против прозы» вообще
	// имело предмет.
	Comments int
	// Statements — операторов удаления над `roles` прочитано.
	Statements int
	// Guarded — из них сужённых на пользовательскую роль.
	Guarded int
}

// roleDeleteStmtRe — оператор удаления над таблицей ролей.
//
// Образец привязан к НАЧАЛУ СТРОКИ, и это несущее: запрос, отдаваемый оператору,
// начинается глаголом (возможно, после отступа, перевода строки или общего
// табличного выражения). Проза о самом запрете несёт то же слово ПОСРЕДИ
// предложения, и образец без привязки не различает их.
//
// Граница `\b` после `roles` отделяет таблицу ролей от её проекций
// (`role_rule_ref`, `role_verb`, `role_rule_selectors`): их удаление законно —
// с него начинается приведение правила (`ReplaceRuleRefs`).
var roleDeleteStmtRe = regexp.MustCompile(`(?im)^\s*(with\b[^\n]*\n\s*)?delete\s+from\s+(kacho_iam\.)?roles\b`)

// roleDeleteTailRe — продолжение, по которому оператор отличается от прозы,
// цитирующей оператор. Привязан к началу ОСТАТКА литерала, поэтому режим
// многострочности здесь не нужен и был бы неверен: `$` в нём означал бы конец
// строки, а нужен конец литерала.
var roleDeleteTailRe = regexp.MustCompile(`(?is)^\s*($|;|--|\)|where\b|returning\b|using\b|as\b)`)

// roleDeleteGuardRe — сужение на пользовательскую роль в двух законных
// написаниях. Перечень выведен из того, как `is_system` объявлена в схеме
// (`0056_role_definition_tier.sql`: `GENERATED ALWAYS AS (cluster_id IS NOT NULL)`),
// а не угадан: третьего написания у этого предиката нет.
var roleDeleteGuardRe = regexp.MustCompile(`(?i)(is_system\s*=\s*false|not\s+is_system\b|cluster_id\s+is\s+null)`)

// ScanRoleDeletes разбирает один файл Go.
func ScanRoleDeletes(path string, src []byte) (sites []RoleDeleteSite, census RoleDeleteCensus, err error) {
	fset := token.NewFileSet()
	f, perr := parser.ParseFile(fset, path, src, parser.ParseComments)
	if perr != nil {
		return nil, RoleDeleteCensus{}, perr
	}
	for _, g := range f.Comments {
		census.Comments += len(g.List)
	}
	ast.Inspect(f, func(n ast.Node) bool {
		lit, ok := n.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		census.StringLiterals++
		text := litText(lit.Value)
		stmts := 0
		for _, m := range roleDeleteStmtRe.FindAllStringIndex(text, -1) {
			if roleDeleteTailRe.MatchString(text[m[1]:]) {
				stmts++
			}
		}
		if stmts == 0 {
			return true
		}
		census.Statements += stmts
		// Сужений обязано быть не меньше, чем операторов: литерал с двумя
		// операторами и одним сужением оставляет один несужённым, и зачесть его
		// по соседу значило бы засчитать чужую защиту.
		if len(roleDeleteGuardRe.FindAllString(text, -1)) >= stmts {
			census.Guarded += stmts
			return true
		}
		sites = append(sites, RoleDeleteSite{
			File: path, Line: fset.Position(lit.Pos()).Line, What: firstLineOf(lit.Value),
		})
		return true
	})
	return sites, census, nil
}
