// opSourceExempt — кому предмет разрешён, с ПРИЧИНОЙ.
//
// Запись обязана называть причину, а не факт: молчаливое освобождение
// неотличимо от пропущенного места. Запись, которой нечего исключать, — находка
// (гейт падает на ней сам).
var opSourceExempt = map[string]string{
	"gateway/internal/opsproxy": "" +
		"край, а не обработчик поверх репозитория: собственной таблицы операций у " +
		"него нет, он проксирует чтение к домену-владельцу и потому собирает ключ " +
		"владения сам. Его полоса РАСХОДИТСЯ с общей по трём осям (системный обход " +
		"предиката, форма отказа чужому, форма отмены) — это отдельный предмет, " +
		"заведённый своей задачей. Запись снимается, когда край перейдёт на общую " +
		"полосу либо когда расхождение будет решено и записано. Предмет заведён " +
		"задачей продукта #1399. ЧЕТВЁРТАЯ ось — текст отказа — закрыта #1370 и в " +
		"перечне выше не значится: край его больше не записывает, а зовёт общий " +
		"производитель. Ссылка правится вместе с осью, иначе запись пережила бы " +
		"свой предмет по частям: три оси живы, а названная задача закрыта.",
}

// Арендаторская полоса операции объявлена В ДЕРЕВЕ ОДИН РАЗ.
//
// ПРЕДМЕТ. `OperationService` — единственный сервис контракта, который несёт
// КАЖДЫЙ домен: любая мутация возвращает `Operation` (ban #9). Реализация у всех
// одна и та же по существу — три шага: вывести ключ владения из ctx, уйти в
// ownership-scoped репозиторий, отдать одинаковый no-leak `NotFound` и на чужую
// операцию, и на несуществующую.
//
// ПОЧЕМУ ЭТО ГЕЙТ, А НЕ ОБЗОР. Копий было семь, и хотя к моменту сведения шесть
// из них почти сошлись, расхождение седьмой было видно только тому, кто сравнит
// копии: она отменяла операцию НЕАТОМАРНО — проверяла владение отдельным
// чтением, а мутацию звала НЕСУЖЕННУЮ, то есть предикат владения уходил из
// мутации совсем. По диффу это выглядит добросовестной работой: обе половины по
// отдельности защитимы.
//
// ПОЧЕМУ СУДИТСЯ ПРЕДМЕТ, А НЕ ИМЕНА. Первая редакция искала три литерала —
// `func NewOperationHandler(`, `func [Oo]perationToProto(` и `operationpb.` — и
// внешний аудит провёл через неё ЧЕТЫРЕ форка подряд: с чужим алиасом импорта,
// с чужим именем преобразователя, с делегированием в собственную функцию и с
// чужими именами параметров. Следующие два круга дали ещё десять и семь.
//
// Числа переписи алиасов здесь НЕ выписаны намеренно: они зависят от популяции
// и устаревают внутри того же коммита, который их снял (так и вышло — величина
// стояла в трёх местах и во всех трёх была верна лишь для базы). Перепись
// печатается КАЖДЫМ прогоном, ниже.
//
// ЧТО ГЕЙТ СУДИТ. Только то, что у предмета ОДНО место. Как этот предмет
// реализован — работа проб `pkg/operations/operationspb`.
func TestOperationHandlerHasASingleSource(t *testing.T) {
	root := repoRoot(t)

	// Охват: ВСЁ дерево Go, а не только сервисы. Прежде обход шёл по
	// `services/` + `gateway/` = 1277 файлов, и вне наблюдения оставались
	// `pkg/` (371), `internal/` (72), `tools/` (36), `terraform/` (35) — 514
	// не-тестовых файлов. `pkg/` — дом самого общего слоя, то есть самое
	// вероятное место для второго «почти общего» помощника.
	var files []string
	for _, sub := range []string{"services", "gateway", "pkg", "internal", "tools", "terraform"} {
		for _, abs := range trackedGoFiles(t, filepath.Join(root, sub)) {
			rel, err := filepath.Rel(root, abs)
			if err != nil {
				t.Fatalf("относительный путь %s: %v", abs, err)
			}
			files = append(files, filepath.ToSlash(rel))
		}
	}
	sort.Strings(files)
	if len(files) == 0 {
		t.Fatal("предпосылка гейта не выполняется: не-тестовых файлов Go под services/ и " +
			"gateway/ в индексе НОЛЬ — обход смотрит не туда; чинить надо гейт, а не молча " +
			"выходить успехом")
	}

	findings, cen, err := auditOperationSingleSource(root, files, opSourceExempt)
	if err != nil {
		t.Fatalf("обход: %v", err)
	}

	// Перепись по осям порознь + какие алиасы стабов встретились: слепая зона
	// распознавателя обнаруживается именно так.
	var aliases []string
	for a, n := range cen.Aliases {
		aliases = append(aliases, a+"×"+strconv.Itoa(n))
	}
	sort.Strings(aliases)
	t.Logf("осмотрено файлов Go: %d; обработчиков: %d; преобразователей: %d (из них своим телом: %d); "+
		"мест полосы владения (по санкционированным глаголам): %d; подавлено ведомостью: %d; "+
		"алиасы стабов операции: %s",
		cen.FilesRead, cen.Handlers, cen.Converters, countBy(findings, "преобразователь"),
		cen.Ownership, cen.Exempted, strings.Join(aliases, " "))

	// СТРАЖ ПРЕДПОСЫЛКИ — САМОПРОВЕРКА РАСПОЗНАВАТЕЛЯ, А НЕ СЧЁТ НАХОДОК В ДЕРЕВЕ.
	//
	// Здесь было `Converters==0 && Handlers==0 && Ownership==0`, потом
	// «по каждой оси» с выражением `Handlers + Exempted`. Обе редакции негодны, и
	// по разным причинам:
	//
	//   - `&&` глушил ослепшую ось любой другой;
	//   - `Handlers + Exempted` ВОЗВРАЩАЛ исключённое в ось, то есть тревогу
	//     «я ослеп» глушило ровно то место, которое из суждения выведено. Рядом
	//     стояла инъекция, утверждающая обратное (`cen.Handlers == 0` для
	//     исключённого пути), — проба была зелёной, свойства не было;
	//   - и главное: СЧЁТ НАХОДОК В ДЕРЕВЕ НЕГОДЕН КАК СТРАЖ В ПРИНЦИПЕ. Ось
	//     обработчика в сведённом дереве законно даёт НОЛЬ — единственный
	//     обработчик лежит в общем слое, выведенном по построению. Требовать от
	//     неё непустоты значит обещать красное на достижении цели: закроется
	//     задача #1370, ведомость опустеет, и гейт упадёт, ничего не найдя.
	//
	// Годный страж спрашивает другое: ЖИВ ЛИ РАСПОЗНАВАТЕЛЬ. Он подаёт судящей
	// функции синтетический предмет по каждой оси и требует находки. Это не
	// зависит ни от состава дерева, ни от ведомости, и краснеет ровно тогда,
	// когда распознаватель перестал видеть форму.
	for _, probe := range []struct {
		axis string
		src  string
	}{
		{"обработчик", `package p

import (
	operationpb "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/operation"
)

type H struct{}

func (h *H) Get(ctx context.Context, req *operationpb.GetOperationRequest) (*operationpb.Operation, error) {
	return nil, nil
}
`},
		{"преобразователь", `package p

import (
	operationpb "github.com/PRO-Robotech/kacho/pkg/api/kacho/cloud/operation"
	"github.com/PRO-Robotech/kacho/pkg/operations"
)

func toPB(op *operations.Operation) *operationpb.Operation {
	return &operationpb.Operation{Id: op.ID}
}
`},
		{"полоса владения", `package p

import (
	"github.com/PRO-Robotech/kacho/pkg/operations"
)

func lane(ctx context.Context, repo operations.Repo) {
	owned, _ := operations.AsOwned(repo)
	_ = owned
}
`},
	} {
		dir := t.TempDir()
		rel := "services/probe/x.go"
		if err := os.MkdirAll(filepath.Join(dir, filepath.Dir(rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, rel), []byte(probe.src), 0o600); err != nil {
			t.Fatal(err)
		}
		got, _, err := auditOperationSingleSource(dir, []string{rel}, nil)
		if err != nil {
			t.Fatalf("самопроверка оси «%s»: %v", probe.axis, err)
		}
		if len(got) == 0 {
			t.Fatalf("предпосылка гейта не выполняется: распознаватель ОСЛЕП по оси «%s» — "+
				"синтетический предмет этой оси не найден.\nЛибо контракт переименован, либо "+
				"распознаватель сломан; «ноль находок» по дереву в таком состоянии не "+
				"утверждает ничего.\nперепись по дереву: %+v", probe.axis, cen)
		}
	}

	if len(findings) > 0 {
		var b strings.Builder
		for _, f := range findings {
			b.WriteString("\n    " + f.Where + " — " + f.What + " [" + f.Why + "]")
		}
		t.Fatalf("арендаторская полоса операции объявлена вне общего слоя "+
			"(`pkg/operations/operationspb`).\nСемь копий давали семь поведений, и расхождение "+
			"видно только тому, кто сравнит копии. Прослойка в одну строку, ведущая в общий "+
			"слой, законна; своё тело — нет:%s", b.String())
	}
}

func countBy(fs []opSourceFinding, why string) int {
	n := 0
	for _, f := range fs {
		if f.Why == why {
			n++
		}
	}
	return n
}
