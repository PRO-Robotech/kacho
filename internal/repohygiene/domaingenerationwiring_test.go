// domaingenerationwiring_test.go — гейт «гейт разреза обязан звать конвейер»
// (задача #1110).
//
// # Предмет: судья, чей вердикт не доходит ни до кого
//
// `gateway/scripts/check-domain-generation.sh` утверждает то, ради чего вынос
// службы отдельным продуктом вообще выполним: порождение каталога прав и
// таблицы маршрутов ДЛЯ ОБЪЯВЛЕННОГО ПЕРЕЧНЯ ДОМЕНОВ выполнимо вне дерева
// монорепо и даёт ПОБАЙТОВО то же, что порождение по всему дереву. Утверждений у
// него много, каждое своей осью, и рядом инъекция с законным близнецом на каждую;
// перепись объёма осмотренного судья печатает сам.
//
// Числа здесь НЕ выписаны намеренно. Прежняя редакция называла «одиннадцать
// утверждений, двадцать осей», и к первой же правке судьи это стало ложью: у
// выписанного в прозе числа нет владельца — правят судью, а число остаётся.
// Перемеряются они предикатами, и оба дёшевы:
//
//	grep -oE 'finding A[0-9]+' gateway/scripts/check-domain-generation.sh | sort -u | wc -l
//	gateway/scripts/inject-domain-generation-defects.sh   # последняя строка: «осей прогнано N»
//
// Сам судья печатает первое из них тем же предикатом по собственному тексту.
//
// Цель `domain-generation-check` объявлена в gateway/Makefile и названа там
// словами «CI GATE», а страница `gateway/docs/engineering/architecture/
// domain-scoped-generation.md` называет её в разделе «Чем держится». На день
// заведения этого гейта имя цели встречалось в дереве ТРИЖДЫ: строка `.PHONY`,
// собственное объявление и одна строка документации. Вызывающих — НОЛЬ.
//
// То есть свойство объявлено удержанным, а держащий его судья не исполнялся ни
// разу. Молчание такого судьи неотличимо от исправной работы: `make` не
// жалуется на то, что его никто не позвал.
//
// # Цена измерена, а не предположена
//
// Гейт разреза существовал 2026-09-08. Назавтра аннотация операции переехала в
// нейтральный корень `corelib/api/v1`, а раскладчик дерева контрактов копировать
// его не стал — импорт перестал резолвиться у КАЖДОГО домена платформы
// (kacho#2433). Одно-фактный опыт на дереве этой линии: со снятой правкой #2433
// гейт разреза даёт код 1 и находку A11, называющую ПРИЧИНУ — «стадия не
// замкнута по импортам: не резолвится 17, первый — corelib/api/v1/
// operation.proto ← kaname/cloud/iam/v1/account_service.proto», — а с правкой
// код 0 и ноль находок. Различие ровно в одной группе строк раскладчика.
//
// Судья, который назвал бы причину в тот же день, существовал и молчал, потому
// что его никто не звал. Это и есть цена непровязанного судьи: не «неаккуратно»,
// а прогон конвейера, потраченный на симптом.
//
// # ЧЕТВЁРТЫЙ подряд экземпляр класса, и три предыдущих — в том же job'е
//
// Класс «цель существовала и не вызывалась ни одним процессом» этот job уже
// пережил трижды, и каждый раз он записан в его же комментариях: сама сверка
// копий каталога (#2041), таблица маршрутов («таргет тоже уже существовал и тоже
// не был подключён к CI») и listauthz в четырёх сервисах («гейт не запускался ни
// разу»). Чинится он тем же, чем чинились те: ПРОВЯЗКОЙ существующего судьи, а
// не вторым судьёй.
//
// # Чем этот гейт НЕ является
//
// Он не порождает каталог, не сверяет выходы и не дублирует ни одного из
// утверждений судьи — второй такой сверщик измерял бы согласие двух
// разборщиков вместо согласия артефактов. Его предмет — ПРОВЯЗКА: существует ли
// у цели вызывающий среди того, что исполняется само.
//
// Он не требует локального прогонщика, и это решение, а не упущение. Судья
// требует `buf`, `go` и полное дерево контрактов; на машине без `buf` он
// отвечает кодом 2 «без предмета», и вменять отправке ветки его отсутствие
// значило бы либо ронять отправку на несозданном условии, либо приучать читать
// код 2 как успех. Требование второго носителя принадлежит ПРЕДМЕТУ гейта, а не
// механизму (см. gatetargetwiring.go). Появится довод — заводится своим
// изменением и своей инъекцией.
//
// # Механизм ОБЩИЙ
//
// Обход живёт в gatetargetwiring.go и принимает КАТАЛОГ и ИМЯ ЦЕЛИ параметрами;
// им же пользуются гейты `module-manifest-check` (#1851), `model-canon-check`
// (#1893) и `permission-catalog-check` (#2084). Вторая копия обхода разошлась бы
// с первой молча — и разошлась бы там, где обе зелены.
package repohygiene

import (
	"testing"
)

// domainGenerationMakefileDir — каталог, чей Makefile объявляет судью разреза.
//
// Параметр, а не литерал в теле: каталог и имя цели — вход обхода, и разбросать
// их по телу значило бы завести второе место об одном предмете.
const domainGenerationMakefileDir = "gateway"

// domainGenerationTarget — цель, чей вердикт обязан кого-то достигать.
const domainGenerationTarget = "domain-generation-check"

// TestDomainGenerationGateIsCalledByThePipeline — у гейта разреза обязан быть
// вызывающий среди того, что исполняется само.
//
// Что делать, если гейт сработал: провязать судью шагом конвейера — шагом с
// `working-directory: gateway` и телом `make domain-generation-check` либо
// `make -C gateway domain-generation-check`. Заводить второй судья разреза
// взамен провязки нельзя: утверждения судьи и оси инъекции уже написаны, и
// вторая их копия разошлась бы с первой молча.
func TestDomainGenerationGateIsCalledByThePipeline(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)
	w, err := readMakeTargetWiring(root, domainGenerationMakefileDir, domainGenerationTarget)
	if err != nil {
		t.Fatalf("провязка не прочитана: %v — вердикт беспредметен", err)
	}

	// ── ПРЕДПОСЫЛКИ ОБХОДА ──────────────────────────────────────────────────
	//
	// Пустой обход обязан ронять прогон: иначе «находок ноль» означало бы «ноль
	// прочитанного», и эти два состояния печатались бы одинаково.
	if w.Reach.RecipeLines == 0 {
		t.Fatalf("в %s/Makefile не прочитано ни одной строки рецепта — разбор сломан, "+
			"и вердикт о провязке беспредметен", domainGenerationMakefileDir)
	}
	if w.WorkflowsRead == 0 {
		t.Fatal("не прочитано ни одного файла .github/workflows — гейт смотрит не туда")
	}
	if w.WorkflowStepsRead == 0 {
		t.Fatal("ни в одном файле конвейера не найдено шага с телом `run:` — разбор сломан, " +
			"и «вызова нет» означало бы «не прочитано ничего»")
	}
	// Положительный контроль: цель обязана быть НАЙДЕНА объявленной. Ноль
	// объявлений означает, что цель сняли либо разбор сломан, и тогда «провязка
	// в порядке» — не свойство дерева, а слепота гейта.
	if !w.Reach.Declared {
		t.Fatalf("цель %s не объявлена в %s/Makefile (прочитано %d строк рецепта) — судить разрез "+
			"некому, и молчание про провязку ничего не значит",
			domainGenerationTarget, domainGenerationMakefileDir, w.Reach.RecipeLines)
	}
	// Второй положительный контроль: достигающих обязано быть НЕ МЕНЬШЕ одной
	// (сама цель). Пустое множество достигающих сделало бы «никто не позван»
	// истинным by construction.
	if len(w.Reach.Reaching) == 0 {
		t.Fatalf("множество целей, достигающих %s, пусто — разбор достижимости сломан, "+
			"и «никто не зовёт» было бы верно ни на чём", domainGenerationTarget)
	}

	for _, f := range findMakeTargetWiringFaults(w) {
		t.Errorf("%s", f)
	}

	t.Log(makeTargetWiringCensus(w))
}
