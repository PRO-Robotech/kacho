// Package artifactgates — гейты по дереву, обходящие НЕ-Go артефакты и весь
// корпус целиком.
//
// ВЕРДИКТ ЭТОГО ПАКЕТА НЕДЕЙСТВИТЕЛЕН БЕЗ ОТКЛЮЧЕНИЯ КЕША `go test`: гейты судят
// дерево, а состав дерева инструменту невидим, и `ok (cached)` печатается над
// деревом, где гейт красный. Пакет отказывается работать на кешируемом прогоне
// (TestMain в cachedverdictmain_test.go); прогонять — с `-count=1`. Разбор —
// pkg/treecorpus, cachedverdict.go.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ, А НЕ ПОДНЯТЫЙ ПОТОЛОК ВРЕМЕНИ
//
// Гейты этого дерева живут в одном пакете, и пакет — единица параллелизма у
// `go test`: сколько бы ни было ядер, один пакет исполняется одним процессом.
// Четыре самых дорогих гейта стоили столько же, сколько все остальные вместе, и
// суммарное время пакета переросло бюджет прогона.
//
// Средство названо в самом Makefile рядом с бюджетом: РАСЩЕПИТЬ, а не поднимать
// потолок, — «поднятие лишь возвращает запас, потерянный молча». Здесь это и
// сделано: два пакета исполняются параллельно, и время прогона определяется
// более долгим из них, а не их суммой.
//
// Шов проведён по ПРЕДМЕТУ обхода, а не по времени: сюда переехали гейты, чей
// корпус — не только Go-код (весь индекс дерева, сценарии проверок, случаи
// чёрного ящика, шаблоны развёртывания). Шов по времени пришлось бы двигать
// после каждой правки; шов по предмету переживает её.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВТОРОЙ ЗАХОД: ЧТО МЕШАЛО ДОВЕСТИ ШОВ И ЧЕМ ЭТО СНЯТО
//
// Первый заход перенёс два гейта и честно назвал остаток: раскладка состава
// дерева жила в ТЕСТОВОМ файле соседнего пакета, полтора десятка гейтов на неё
// опирались, и вынести любой из них было нельзя, не унеся с собой её копию.
// Помощник в тестовом файле — дом на одну семью: он виден ровно одному пакету,
// поэтому расщепление упиралось не в предмет обхода, а в место объявления.
//
// Снято переездом раскладки в `pkg/treecorpus` — обычный пакет, который
// импортирует кто угодно. У каждого пакета гейтов осталась своя двадцатистрочная
// обёртка (отказ → `t.Fatalf`), и это намеренная копия по той же причине, что и
// `repoRoot`: связывать пакеты ради двадцати строк дороже, чем повторить их.
//
// Тем же швом сюда переехали гейты, чей корпус — оснастка прогона: сценарии
// проверок (`scriptgatewiring`), рецепты сборки и конвейеры (`renderguard`,
// `reachabilitycost`) и случаи чёрного ящика (`newman*`). Все они читают
// НЕ-Go-артефакты; в соседнем пакете остались гейты, читающие Go-код разбором.
