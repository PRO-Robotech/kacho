// Package artifactgates — гейты по дереву, обходящие НЕ-Go артефакты и весь
// корпус целиком.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ, А НЕ ПОДНЯТЫЙ ПОТОЛОК ВРЕМЕНИ
//
// Гейты этого дерева живут в одном пакете, и пакет — единица параллелизма у
// `go test`: сколько бы ни было ядер, один пакет исполняется одним процессом.
// Четыре самых дорогих гейта стоили столько же, сколько все остальные вместе, и
// суммарное время пакета переросло бюджет прогона.
//
// Средство названо в самом Makefile рядом с бюджетом: РАСЩЕПИТЬ, а не поднимать
// потолок, — «поднятие лишь возвращает запас, потерянный молча». Здесь это и
// сделано: два пакета исполняются параллельно, и время прогона определяется
// более долгим из них, а не их суммой.
//
// Шов проведён по ПРЕДМЕТУ обхода, а не по времени: сюда переехали гейты, чей
// корпус — не только Go-код (весь индекс дерева, сценарии проверок, случаи
// чёрного ящика, шаблоны развёртывания). Шов по времени пришлось бы двигать
// после каждой правки; шов по предмету переживает её.
package artifactgates

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// repoRoot — поднимаемся от каталога теста до каталога с go.mod (корень репо).
//
// Копия соседского помощника — намеренная и дешёвая: связать пакеты ради шести
// строк значило бы завести между ними зависимость, которой нет по существу.
// Разойтись они не могут: предмет у обхода один — каталог с go.mod, и любое
// расхождение немедленно роняет оба пакета.
func repoRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			t.Fatal("не найден корень репозитория (каталог с go.mod)")
		}
		dir = parent
	}
}

// synthTrack делает синтетическое дерево видимым для git-индекса.
//
// Копия по той же причине, что и repoRoot: две строки git-команд, связывать
// пакеты ради которых дороже, чем повторить.
func synthTrack(t *testing.T, root string) {
	t.Helper()
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v в синтетическом дереве: %v\n%s", args, err, out)
		}
	}
}
