// Package artifactgates — гейты по дереву, обходящие НЕ-Go артефакты и весь
// корпус целиком.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ, А НЕ ПОДНЯТЫЙ ПОТОЛОК ВРЕМЕНИ
//
// Гейты этого дерева живут в одном пакете, и пакет — единица параллелизма у
// `go test`: сколько бы ни было ядер, один пакет исполняется одним процессом.
// Четыре самых дорогих гейта стоили столько же, сколько все остальные вместе, и
// суммарное время пакета переросло бюджет прогона.
//
// Средство названо в самом Makefile рядом с бюджетом: РАСЩЕПИТЬ, а не поднимать
// потолок, — «поднятие лишь возвращает запас, потерянный молча». Здесь это и
// сделано: два пакета исполняются параллельно, и время прогона определяется
// более долгим из них, а не их суммой.
//
// Шов проведён по ПРЕДМЕТУ обхода, а не по времени: сюда переехали гейты, чей
// корпус — не только Go-код (весь индекс дерева, сценарии проверок, случаи
// чёрного ящика, шаблоны развёртывания). Шов по времени пришлось бы двигать
// после каждой правки; шов по предмету переживает её.
