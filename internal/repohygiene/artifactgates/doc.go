// Package artifactgates — гейты по дереву, обходящие НЕ-Go артефакты: случаи
// чёрного ящика и их окружения.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ, А НЕ ПОДНЯТЫЙ ПОТОЛОК ВРЕМЕНИ
//
// Пакет — единица параллелизма у `go test`: сколько бы ни было ядер, один пакет
// исполняется одним процессом. Самые дорогие гейты стоили столько же, сколько
// все остальные вместе, и суммарное время пакета переросло бюджет прогона.
//
// Средство названо в самом Makefile рядом с бюджетом: РАСЩЕПИТЬ, а не поднимать
// потолок, — «поднятие лишь возвращает запас, потерянный молча». Здесь это и
// сделано: два пакета исполняются параллельно, и время прогона определяется
// более долгим из них, а не их суммой.
//
// Шов проведён по ПРЕДМЕТУ обхода, а не по времени: шов по времени пришлось бы
// двигать после каждой правки; шов по предмету переживает её.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ И ПОЧЕМУ (2026-08-12)
//
// Сюда переезжали ДВА гейта. Второй — запрет отложенной работы — вернулся в
// `internal/repohygiene`, и не по соображениям времени: нормативный текст
// продукта цитирует его по координате `internal/repohygiene` +
// `TestNoDeferredWorkInTheTree`, а прогон по этой координате печатал `ok` на
// НУЛЕ проб. Цитируемая координата обязана резолвиться — иначе читатель правила
// получает зелёное от проверки, которая не исполнялась. Пакет — деталь
// раскладки, координата в правиле — контракт с читателем; уступает деталь.
//
// Здесь это отмечено, а не умолчано, потому что и Makefile, и этот файл
// описывают ОДИН предмет — раскладку прогона по пакетам. Умолчав, мы получили бы
// два места об одном предмете, из которых верно одно.
