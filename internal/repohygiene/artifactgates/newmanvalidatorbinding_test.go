// validatorBindingCensus — объём осмотренного. Печатается ВСЕГДА: без него «ноль
// находок» неотличимо от «ноль прочитанного». Обе величины названы порознь —
// сколько проверок кейсов осмотрено и сколько из них берут связывание набора, —
// потому что одно суммарное число скрыло бы ровно тот случай, ради которого
// гейт заведён.
type validatorBindingCensus struct {
	validators int
	callSites  int
	bound      int
}

// reValidatorLoaderCall — обращение проверки кейсов к загрузчику модулей.
//
// Ищется ВЫЗОВ, а не упоминание: имя загрузчика встречается и в прозе шапки, и
// гейт по подстроке краснел бы на собственном объяснении.
var reValidatorLoaderCall = regexp.MustCompile(`gen\.(load_cases_module|load_cases|_RUN\.load)\s*\(`)

// auditValidatorCasesBinding — судящая функция гейта.
//
// Выделена, чтобы инъекция гоняла ЕЁ, а не свою копию: проба, повторяющая логику
// гейта, доказывала бы свойство копии.
//
// Находкой считается обращение к ОБЩЕМУ загрузчику напрямую
// (`gen.load_cases_module(...)`): такой вызов обязан назвать решения набора —
// впрыскиваемые имена, сброс счётчиков, трактовку дефиса в имени модуля, — и
// тем самым заводит ВТОРОЕ место, где эти решения записаны.
func auditValidatorCasesBinding(validators map[string]string) ([]string, validatorBindingCensus) {
	cen := validatorBindingCensus{validators: len(validators)}

	rels := make([]string, 0, len(validators))
	for rel := range validators {
		rels = append(rels, rel)
	}
	sort.Strings(rels)

	var findings []string
	for _, rel := range rels {
		for _, m := range reValidatorLoaderCall.FindAllStringSubmatch(validators[rel], -1) {
			cen.callSites++
			if m[1] == "load_cases_module" {
				findings = append(findings, fmt.Sprintf(
					"%s — зовёт общий загрузчик напрямую (gen.%s), минуя связывание набора", rel, m[1]))
				continue
			}
			cen.bound++
		}
	}
	return findings, cen
}

// Проверка кейсов набора грузит их модули ТЕМ ЖЕ связыванием, что генерация.
//
// ПРЕДМЕТ. Модуль кейсов исполняется с впрыснутыми именами набора, со сброшенными
// счётчиками имён шагов и с принятой набором трактовкой дефиса в имени файла.
// Пока проверка кейсов звала общий загрузчик своими руками, эти решения были
// записаны ДВАЖДЫ — в генераторе и в проверке, — и разошлись на первой же смене
// подписи загрузчика.
//
// ЦЕНА ИЗМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА. Сведение хребта генератора (#1379) сделало
// перечень впрыскиваемого обязательным параметром загрузчика. Генераторы его
// передают; шесть проверок кейсов — нет, и каждая стала отвечать
// `TypeError: load_cases_module() missing 1 required positional argument`
// на ЛЮБОЙ вход. То есть проверка кейсов перестала исполняться ВОВСЕ, а её отказ
// читался как находка о кейсах.
//
// ПОЧЕМУ ГЕЙТ, А НЕ ВНИМАНИЕ. Отказ виден только тому, кто позвал проверку
// руками: генерация при этом зелёная, а конвейер зовёт проверку отдельным шагом.
// Расхождение двух мест об одном предмете не ломает ни сборку, ни генерацию —
// оно ломает ТРЕТЬЕГО, и молча.
//
// ЧЕГО ГЕЙТ НЕ СУДИТ. Он не требует, чтобы связывание называлось определённым
// именем и не проверяет, ЧТО в него связано: это решение набора. Предмет здесь
// один — что решения записаны в ОДНОМ месте, а проверка берёт их оттуда.
func TestNewmanValidatorLoadsCasesThroughTheSuiteBinding(t *testing.T) {
	root := repoRoot(t)

	// Состав — из индекса git, а не обходом диска: под корнем лежат рабочие
	// копии агентов, и обход по диску сделал бы вердикт свойством чужого
	// каталога — в обе стороны.
	tt := newTrackedTree(t, root)

	validators := map[string]string{}
	for rel := range tt.files {
		if filepath.Base(rel) != "validate-cases.py" || !strings.Contains(rel, "tests/newman") {
			continue
		}
		b, err := os.ReadFile(filepath.Join(root, rel)) // #nosec G304 -- путь из индекса git этого модуля
		if err != nil {
			t.Fatalf("чтение %s: %v", rel, err)
		}
		validators[rel] = string(b)
	}
	if len(validators) == 0 {
		t.Fatalf("предпосылка гейта не выполняется: проверок кейсов newman в индексе НОЛЬ —\n" +
			"либо файл переименован, либо обход смотрит не туда; чинить надо гейт,\n" +
			"а не молча выходить успехом.")
	}

	findings, cen := auditValidatorCasesBinding(validators)

	if cen.callSites == 0 {
		t.Fatalf("предпосылка гейта не выполняется: осмотрено проверок %d, обращений к\n"+
			"загрузчику НОЛЬ. Либо проверки перестали грузить модули кейсов, либо\n"+
			"распознаватель не знает формы вызова — в обоих случаях это отказ, а не\n"+
			"молчание: гейт, потерявший предмет, вечнозелен.", cen.validators)
	}

	t.Logf("осмотрено проверок кейсов newman: %d; обращений к загрузчику %d, из них через связывание набора %d",
		cen.validators, cen.callSites, cen.bound)

	if len(findings) > 0 {
		t.Fatalf("проверка кейсов грузит модули СВОИМ вызовом загрузчика, а не связыванием набора.\n"+
			"Тогда решения набора записаны в двух местах, и расходятся они молча — генерация\n"+
			"остаётся зелёной, а проверка перестаёт исполняться. Чинится вызовом связывания,\n"+
			"объявленного в gen.py рядом с самими решениями:\n  %s",
			strings.Join(findings, "\n  "))
	}
}
