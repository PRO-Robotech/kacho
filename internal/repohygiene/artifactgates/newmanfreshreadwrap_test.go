// newmanfreshreadwrap_test.go — первый доступ к СВОЕМУ свежему ресурсу обёрнут
// ограниченным ретраем ВО ВСЕХ генераторах newman, а не в тех, где вспомнили.
//
// # Предмет
//
// Kachō eventually-consistent: owner-tuple свежесозданного ресурса
// материализуется вне мутации (`api-conventions.md` §Форма ресурса,
// `testing.md` §e2e-инварианты), поэтому ПЕРВОЕ обращение создателя к своему
// ресурсу может кратко получить 403/404. Норма предписывает клиентский
// ограниченный ретрай, и он реализован — `retry_until_authorized` в каждом
// генераторе. Но ставился он ВРУЧНУЮ, а значит пропуск неотличим от решения не
// оборачивать.
//
// Замер по артефактам прогона CI 31002239590 (8 суит, 82 отчёта, 15648
// утверждений, 151 упавшее): из 68 падений полосы видимости (403/404) **42**
// пришлись на шаги, у которых обёртки не было ВОВСЕ — при том что в тех же
// кейсах соседние шаги той же формы обёрнуты. Это пропуск, а не замысел.
//
// # Что здесь считается защитой
//
// Защитой считается ПРЕДИКАТ по свойству шага (`_wrap_own_fresh_reads`),
// провязанный в сериализацию кейса (`case_to_postman`), — а не перечень имён
// шагов и не аккуратность автора. Генератор, у которого есть
// `retry_until_authorized`, но нет предиката в сериализации, — находка: класс в
// нём открыт, и следующий кейс унаследует слепую зону.
//
// Гейт несёт проверку СВОЕЙ предпосылки: если ни одного генератора с
// `retry_until_authorized` в дереве не нашлось, он падает, а не выходит
// «нулём находок» — «ноль находок» обязано быть отличимо от «ноль прочитанного».
// Этот гейт утверждает, что предикат ПРОВЯЗАН — у КАЖДОГО генератора. Что он ещё
// и РАБОТАЕТ — отдельное утверждение, отдельная проверка и, что важно, ДРУГОЙ
// охват: `services/vpc/tests/newman/scripts/selftest_autowrap.py` исполняет
// генератор vpc и только его. У compute/iam/nlb/registry/storage своей
// самопроверки НЕТ, и этой они не покрыты (`PRO-Robotech/kacho#1277`); их
// генераторы говорят об этом прямо, а не обещают обратное.
//
// ЧИСЛА САМОПРОВЕРКИ ЗДЕСЬ НЕ ВЫПИСЫВАЮТСЯ: она печатает объём осмотренного
// последней строкой, поэтому «ноль находок» в ней отличимо от «ноль
// прочитанного». Прежняя редакция называла «шесть инъекций и восемь законных
// близнецов» — на момент этой правки их тринадцать и четырнадцать. Перечень,
// который надо править вслед за предметом, переживает предмет молча; ровно этот
// класс уже ловили в `ci.yaml` («было „четырёх“ при шести»).
//
// Вызывающих у самопроверки два: шаг «предикат обёртки первого доступа (vpc)» в
// `ci.yaml` и одноимённый в job'е `plan` workflow'а `e2e-newman.yml`. Прежняя
// редакция этой шапки на такой шаг уже ссылалась, но вызывающего у самопроверки
// не было ни одного — ссылка вела в пустоту, и проверка, доказывающая
// способность предиката краснеть, сама не исполнялась.
//
// # Что этот гейт НЕ утверждает — и чем это закрыто
//
// ЧТО ИМЕННО читает предикат — свойство самой самопроверки, а не этого гейта:
// пока условие смотрело только на АДРЕС шага, гейт был зелёным при открытой
// слепой зоне (цель проверки прав, названная в ТЕЛЕ запроса). Инъекция №6
// самопроверки краснеет ровно на возврате условия к адресу.
//
// ПОБОЧНОЕ ДЕЙСТВИЕ обёртки — переименование шага (`<имя>-rya<N>`) — держит
// соседний гейт `newmanjumptarget_test.go`: буквальная ссылка на переименованный
// шаг не роняет прогон, а ЗАВЕРШАЕТ его, и остаток набора становится «не
// выполнилось» под видом зелёного.
package artifactgates

