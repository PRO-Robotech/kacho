// reachabilitycost_test.go — стоимость предиката достижимости принадлежит
// ЧИСЛУ КАНДИДАТОВ, а не размеру осмотренного текста.
//
// ПРЕДМЕТ. `anyMentions` спрашивает про один гейт: зовёт ли его хоть одна
// достижимая из конвейера команда. Кандидатов у гейта не больше трёх (полный
// путь, имя файла, путь от каталога сервиса), а осматриваемого текста —
// десятки тысяч строк: все workflow'ы плюс тела всех достижимых скриптов,
// подтягиваемые транзитивно. Пока шаблон присваивания компилировался ВНУТРИ
// построчного цикла, стоимость одного вопроса была пропорциональна не числу
// кандидатов, а произведению «кандидаты × строки», и росла вместе с деревом.
//
// ЧЕМ ЭТО КОНЧИЛОСЬ (замер на ревизии 50e5e624). Пакет гейтов не укладывался в
// свой бюджет и падал `panic: test timed out after 5m0s`: из 144 тестов
// стартовало 108, вердикт получили 107, тридцать шесть не начинались вовсе.
// То есть юнит-джоба переставала быть свидетельством о дереве — не потому, что
// дерево грязное, а потому, что её собственная оснастка не доезжала до конца.
// Профиль называл виновника прямо: 58% сэмплов — `regexp.MustCompile`,
// вызванный из `reAssignOf`.
//
// ПОЧЕМУ СВОЙСТВО, А НЕ ЗАМЕР ВРЕМЕНИ. Утверждение «уложись в N секунд» меряет
// машину, а не код: на медленном раннере оно краснеет на исправном дереве, на
// быстром — молчит на вернувшемся дефекте. Поэтому здесь считается РАБОТА, а не
// время: сколько шаблонов предикат компилирует, отвечая на ОДИН вопрос. Это
// число обязано не зависеть от объёма текста, в котором он ищет.
package artifactgates

import (
	"strconv"
	"strings"
	"sync/atomic"
	"testing"
)

// reachabilityCompiles — сколько шаблонов скомпилировали предикаты достижимости.
//
// Счётчик живёт рядом с ними (`reAssignOf`, `execOfVarRe` в renderguard_test.go)
// и инкрементируется в самих конструкторах, а не в вызывающем: иначе следующий
// вызывающий обойдёт учёт, ничего не заметив. Атомарный — на случай, если пробу
// когда-нибудь пометят `t.Parallel()`.
var reachabilityCompiles atomic.Int64

// compilesDuring — сколько шаблонов скомпилировано за время вызова fn.
func compilesDuring(fn func()) int64 {
	before := reachabilityCompiles.Load()
	fn()
	return reachabilityCompiles.Load() - before
}

// noiseLines — текст заданной длины, НЕ упоминающий предмет вопроса.
//
// Строки нарочно разные: одинаковые строки предикат мог бы срезать дедупликацией,
// и проба перестала бы отличать «стоимость не растёт» от «вход выродился».
func noiseLines(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteString("\tgo test ./pkg/unrelated" + strconv.Itoa(i) + "/... -run TestNothing\n")
	}
	return b.String()
}

// TestReachabilityCostBelongsToCandidatesNotToTextSize — предикат достижимости
// компилирует шаблоны по числу кандидатов, а не по числу осмотренных строк.
//
// Проба различающая: до правки она видела рост ровно в отношении размеров входа
// (200 строк → 600 компиляций, 20000 строк → 60000), после — одно и то же число
// на обоих входах.
func TestReachabilityCostBelongsToCandidatesNotToTextSize(t *testing.T) {
	const guard = "tools/somegate/check.sh"

	const smallLines, bigLines = 200, 20000
	small := compilesDuring(func() { _ = anyMentions([]string{noiseLines(smallLines)}, guard) })
	big := compilesDuring(func() { _ = anyMentions([]string{noiseLines(bigLines)}, guard) })

	t.Logf("осмотрено строк: %d и %d; скомпилировано шаблонов: %d и %d",
		smallLines, bigLines, small, big)

	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ, без которого отрицание ниже зеленеет на всём
	// сломанном: счётчик обязан вообще двигаться. Ноль здесь означает, что
	// проба меряет не то — предикат перестали звать, шаблоны перестали
	// компилировать в учитываемых конструкторах, — а не что стоимость нулевая.
	if small == 0 {
		t.Fatalf("предикат достижимости не скомпилировал НИ ОДНОГО шаблона на %d строках — "+
			"счётчик оторван от предмета, проба ничего не меряет", smallLines)
	}

	if big != small {
		t.Errorf("стоимость одного вопроса о достижимости растёт вместе с текстом: "+
			"на %d строках %d компиляций, на %d — %d (в %.1f раза). "+
			"Шаблон кандидата компилируется внутри построчного обхода; вынеси компиляцию "+
			"из цикла — кандидатов у гейта не больше трёх, а строк в достижимом тексте "+
			"десятки тысяч. Симптом класса: пакет гейтов перестаёт укладываться в бюджет "+
			"и часть тестов не получает вердикта вовсе.",
			smallLines, small, bigLines, big, float64(big)/float64(small))
	}
}

// TestReachabilityAnswerSurvivesDilution — ответ не зависит от того, ТОНЕТ ли
// упоминание в тексте.
//
// Общая симметрия предиката (вызов ≠ упоминание, печать ≠ запуск, присваивание
// без исполняющего потребителя) принадлежит TestRenderGuardReachabilityIsSymmetric
// и здесь НЕ переписывается — два набора об одном предмете разъедутся. Этой пробе
// принадлежит ровно то, чего у той нет: её случаи однострочные, а удешевление
// стоимости отбирает строки вхождением подстроки ДО прогона автомата. Отбор
// обоснован тем, что вхождение — необходимое условие шаблона; если это перестанет
// быть верным, ошибётся именно разбавленный вход, где нужная строка одна на тысячу.
//
// Пара обязательна: положительные случаи (упоминание уцелело в шуме) и
// отрицательные (шум сам по себе вызовом не становится). Без вторых «предикат
// отвечает да» удовлетворяется предикатом, который отвечает «да» всегда.
func TestReachabilityAnswerSurvivesDilution(t *testing.T) {
	const guard = "tools/somegate/check.sh"
	const padLines = 1000
	pad := noiseLines(padLines)

	cases := []struct {
		name      string
		reachable []string
		want      bool
	}{
		{"вызов полным путём в конце длинного текста", []string{pad + "python3 " + guard}, true},
		{"вызов полным путём в начале длинного текста", []string{"python3 " + guard + "\n" + pad}, true},
		{"вызов именем файла среди шума", []string{pad + "bash check.sh\n" + pad}, true},
		{"присваивание и запуск разнесены по РАЗНЫМ текстам через шум",
			[]string{pad + "G=" + guard, pad + "bash \"$G\"\n" + pad}, true},
		{"присваивание есть, исполняющего потребителя нет — не вызов",
			[]string{pad + "G=" + guard, pad + "note \"перемерить: bash $G\""}, false},
		{"полный путь только напечатан среди шума — не вызов",
			[]string{pad + "echo \"запусти: bash " + guard + "\"\n" + pad}, false},
		{"один шум — не вызов", []string{pad}, false},
	}
	positives := 0
	for _, c := range cases {
		if c.want {
			positives++
		}
		t.Run(c.name, func(t *testing.T) {
			if got := anyMentions(c.reachable, guard); got != c.want {
				t.Errorf("достижим=%v, ожидалось %v", got, c.want)
			}
		})
	}
	t.Logf("осмотрено случаев: %d (положительных %d, отрицательных %d); строк шума на случай: %d",
		len(cases), positives, len(cases)-positives, padLines)
}
