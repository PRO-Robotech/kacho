// uisourcereadtest_test.go — проба интерфейса не подтверждает себя чтением
// модуля консоли как текста.
//
// # Предмет — КЛАСС, а не механизм
//
// Прежняя редакция гейта ловила механизм: «в файле встречается readFileSync».
// Механизм — не дефект. По этому предикату в перечень-долг попали конформансные
// пробы, для которых чтение исходников И ЕСТЬ проверка: они обходят дерево и
// утверждают его СОСТАВ (какой модуль что объявляет, нет ли второй копии
// поверхности, согласуется ли реестр консоли со связываниями `proto/`). Такой
// факт исполнением одного модуля не получить — читать здесь нечем заменить.
//
// Дефект — другое: проба берёт координату, которую САМА ЖЕ и написала, читает
// по ней **модуль консоли** и утверждает о его символах. Эталонная форма (её в
// дереве было 139 копий):
//
//	const source = readFileSync(join(here, "DetailShell.tsx"), "utf8");
//	expect(source).toContain("DetailShell");
//
// Компонент не отрисован, функция не вызвана, ни один исход не утверждён: проба
// зелена, пока файл существует, и не краснеет ни на одном изменении поведения.
// Слот занят, отчёт зелёный, поведение не проверено ничем — это хуже
// отсутствующей пробы: отсутствие видно, ложная уверенность нет.
//
// # Предикат
//
// Находка = проба, которая (1) читает содержимое файла, (2) НЕ обходит дерево и
// (3) называет в исполняемой части путь модуля консоли (`.ts`/`.tsx`) — причём
// называет его ТАМ, ГДЕ ЕГО ЧИТАЮТ. Отдельно и независимо от обхода — проба,
// читающая СВОЙ модуль (`X.test.tsx` → `X.tsx`): это буквально «подтвердить себя
// своим же текстом», и обход дерева такую форму не оправдывает.
//
// Каждое из трёх условий несёт свой смысл:
//
//   - (1) без чтения предмета нет вовсе;
//   - (2) обход = перепись состава дерева, законный предмет (см. выше). Записывают
//     его ДВУМЯ равно законными формами, и распознаватель обязан знать обе:
//     прямым вызовом системной функции в теле пробы и вызовом экспорта
//     модуля-помощника, который обходит сам (§«Обход, вынесенный в ПОМОЩНИКА»);
//   - (3) читается **загружаемый** модуль. Контракт ствола (`.proto`), исходник
//     другого языка (`.go`), объявление сборки (`.cjs`) проба исполнить не
//     может — там чтение единственный доступный способ, и запрет был бы просто
//     запретом на проверку. А `.ts`/`.tsx` она обязана ЗАГРУЗИТЬ: `vite.config.ts`
//     отдаёт `server.proxy` объектом, реестр — записями, компонент — разметкой.
//
// Разбор идёт по исполняемой части: комментарии и содержимое строковых/
// регулярных литералов из поиска вызовов исключены. Иначе гейт нашёл бы
// `readFileSync` в абзаце, который сам же и объясняет запрет, — и остался бы
// зелёным при снятой защите (`testing.md` §«Гейт на класс», п. 4).
//
// # Почему координата берётся у ВЫЗОВА, а не у файла целиком (2026-08-17, #523)
//
// Прежняя редакция брала под условие (3) ЛЮБОЙ строковый литерал файла, похожий
// на имя модуля. Такой предикат ловит имя, а не координату, — и первая же проба
// новой формы дала ложную находку: соседний гейт (#498) строит исходник ИЗ
// СТРОКИ В ПАМЯТИ (`ts.createSourceFile`) и передаёт первым аргументом МЕТКУ —
// `bad.ts`, `good.ts`, `fresh.ts`, `synthetic.ts`. Диском эти четыре не являются
// и файлами не являются; к файловой системе за ними не идёт ни один вызов.
//
// Цена ложной находки была двойной. Первое: один красный на самом стволе, к
// работе читающего отношения не имеющий. Второе, и оно дороже, — проба инъекции
// этого же гейта отказывалась работать вовсе («гейт красен ДО инъекции»), то
// есть СПОСОБНОСТЬ ГЕЙТА УПАСТЬ переставала быть чем-либо удостоверена.
//
// Поэтому литерал считается координатой, только если он стоит в аргументах
// вызова, который этот путь ПОТРЕБЛЯЕТ: чтения (`readFileSync(…)`) либо сборки
// пути (`join(…)`/`resolve(…)`, откуда путь доезжает до чтения переменной).
// Метка, уехавшая в произвольную функцию, координатой не становится.
//
// Отвергнутая альтернатива названа, чтобы её не предложили снова: «спросить у
// индекса, резолвится ли имя в дерево». Она закрыла бы эту находку и УБИЛА бы
// доказательство — подложенный дефект инъекции читает `InjectedWidget.tsx`,
// файла с таким именем в дереве нет и быть не должно. Привязать фикстуру к
// существующему файлу значило бы завести близнеца, истекающего вместе с чужим
// файлом (`testing.md` §«Фикстура пробы, привязанная к снимаемому предмету»).
//
// Радиус сужения назван числами, а не словом «точечно» (дерево `19b44f61`; те же
// числа сняты и на `c9e40a75` — за четыре коммита между ними не сдвинулось ни одно):
//
//   - у проб, которые читают и НЕ обходят дерево, — то есть ровно у тех, кого
//     эта ветка вообще способна пометить, — литералов, похожих на модуль
//     консоли, **4**, в **одном** файле, и координатой из них не является **ни
//     один**: это те самые четыре метки #498. Сужение отняло у гейта ровно
//     ложную находку и больше ничего;
//   - у всех читающих проб (включая переписи) таких литералов **71**, из них у
//     потребляющего вызова стоят **22**. Остальные 49 — образцы, аргументы
//     сверок и координаты, найденные обходом; переписи они и раньше прощались
//     отдельной веткой, поэтому вердиктов не меняли.
//
// Находок по дереву: было 1 (ложная), стало 0 при переписи 314/38/31.
//
// # Объём осмотренного
//
// Гейт печатает перепись на каждом прогоне: сколько проб осмотрено, сколько из
// них читает с диска, сколько обходит дерево, сколько признано находками.
// «Ноль находок» обязано быть отличимо от «ноль прочитанного», а непустой
// счётчик переписей доказывает, что дискриминатору есть что различать.
//
// # Вторая форма записи обхода (#1517)
//
// Прежний распознаватель знал у обхода одну форму — прямой системный вызов. По
// второй он не давал ни красного, ни зелёного: он МОЛЧАЛ, и записанное ею
// оказывалось вне наблюдения (`testing.md` §«Гейт на класс», п. 7). Выражалось
// это прямо наоборот — ветка прощения переписи до таких проб не доходила, и
// ТРИ переписи состава дерева объявлялись тем самым дефектом, ради которого гейт
// заведён.
//
// Замер расширения (дерево `df/P1-gates`, 2026-08-29). Осмотренное НЕ изменилось,
// изменилось узнанное — признак того, что прибавка была слепой зоной, а не
// послаблением:
//
//	проб осмотрено      379 → 379
//	читают с диска       59 →  59
//	обходят дерево       40 →  48
//	находок               3 →   0
//
// # Способность упасть
//
// Доказана инъекцией в четыре стороны — `uisourcereadtest_injection_test.go`:
// настоящий дефект краснеет с координатой; законная перепись (обход дерева) и
// законная сверка со стволом (`.proto` по фиксированному пути) молчат, И ПРИ
// ЭТОМ объём осмотренного растёт — иначе молчание означало бы «не прочитал»;
// метка синтетического исходника молчит, а ТО ЖЕ ИМЯ, уехавшее в чтение,
// краснеет — пара держит дискриминатор координаты с обеих сторон одним именем.
//
// Вторая форма обхода доказана своей парой, и обе стороны держит ОДИН помощник:
// проба, зовущая его обходящий экспорт, молчит; проба, взявшая у него же НЕ
// обходящий экспорт и подтверждающая названный ею модуль его же текстом,
// краснеет. Разойдись эти вердикты в одну сторону — гейт мерил бы ИМПОРТ
// помощника, и одна строка импорта снимала бы запрет с любой пробы. Отдельной
// парой закреплено, что обход через помощника НЕ оправдывает чтения СВОЕГО
// модуля, и что замыкание идёт по всем функциям помощника, а не только по
// экспортируемым: обходчик бывает объявлен местным, а экспорт лишь зовёт его.
//
// Отслеживается PRO-Robotech/kacho#5.
