package repohygiene

// roleverbsolewriter_test.go — IAM-RV-1-12: У ПРОЕКЦИИ РОЛИ ОДИН АВТОР.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Таблицы `kacho_iam.role_verb` и `kacho_iam.role_rule_ref` — проекции роли, то,
// из чего цепь вердикта собирает ответ «разрешено ли действие». Класс, ради
// которого гейт заведён: ДВЕ реализации знают, что такое законная строка, и
// расходятся МОЛЧА — обе компилируются, у обеих есть пробы, и различаются они
// только на входе, который ни одна проба не подаёт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЕДИНИЦА СМЕНЕНА: НЕ «ПИШЕТ», А «АВТОРУЕТ» (решение kacho#1034)
//
// Прежняя редакция считала ФУНКЦИИ, ПИШУЩИЕ таблицу, и требовала одной. Предикат
// был верен, пока оба писателя делали ОДНО И ТО ЖЕ: путь роли заменял проекцию, и
// путь досева заменял её же, своим сырым SQL. Считать реализации было тем же, что
// считать операции.
//
// Это совпало, а не было решено. С приходом применителя каталога
// (`catalogWriter.ResettleTenantProjections`) второй писатель делает ДРУГОЕ, и
// прежний счёт перестал измерять свой класс:
//
//	ось                 путь роли                применитель каталога
//	отбор               одна роль (`role_id`)    все арендаторские по СНЯТОМУ референту
//	снятая строка       пропадает                ПЕРЕСЕЛЯЕТСЯ в `role_grant_orphan`
//	кто заявляет        сама роль                внешнее событие — снятие строки каталога
//	вносит ли строку    ДА                       НЕТ
//
// Последняя строка и есть решающая. **Что такое законная строка, объявляет только
// INSERT**: он называет колонки и значения. DELETE строку не авторует — он её
// снимает. Значит класс живёт в АВТОРСТВЕ, а не в записи вообще, и единица гейта —
// функция, ВНОСЯЩАЯ строку.
//
// Предикат от смены не ослаб: прежний второй писатель (`replaceRoleVerbsTx` в
// слое досева) нёс `INSERT INTO kacho_iam.role_verb` и был бы пойман ОДНОЙ этой
// осью. И он не вакуумен: авторов сегодня ровно по одному на проекцию, а
// применитель под него не подпадает — он не вносит.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ДЕРЖИТ ВТОРУЮ ПОЛОВИНУ КЛАССА — И ЧЕГО ГЕЙТ НЕ ДЕРЖИТ ВОВСЕ
//
// Снимающий не-автор повторяет КЛЮЧ строки в предикате `USING … WHERE`, и это
// остаток разделения. Держат его две вещи, и ни одна не является ведомостью:
//
//	ЗДЕСЬ    снимающий не-автор обязан ПЕРЕСЕЛИТЬ снятое — тем же оператором.
//	         Тогда «право отобрано молча» непредставимо: строка либо на месте,
//	         либо в сиротах. Проверяется по литералу оператора, а не по имени
//	         функции и не по перечню разрешённых.
//
//	В КОДЕ   сверка кардинальности внутри самого оператора: отобрано `doomed`,
//	         снято `dropped`, расхождение — ОТКАЗ с откатом транзакции
//	         (`pg.resettleExactly`, запрет #10 — `RETURNING` + проверка
//	         кардинальности). Она и превращает молчаливый промах в громкий.
//
// ОСТАТОК, НАЗВАННЫЙ ЧЕСТНО: число снимающих-переселяющих гейт НЕ ограничивает.
// Ограничить его можно было бы только числом в ведомости, а ведомость без
// предиката снятия — послабление, которое не истечёт никогда. Второй такой
// писатель данных не потеряет (переселение обязательно) и формы строки не
// объявит (не вносит), но ключ повторит — и эту его половину ловит уже сверка
// кардинальности, а не гейт.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА НАЗВАНА, А НЕ УМОЛЧАНА
//
// Гейт читает СТРОКОВЫЕ ЛИТЕРАЛЫ непроверочного кода Go, разобранного в дерево, и
// приписывает находку объемлющей функции. Он НЕ видит:
//   - SQL миграций (там запись законна — миграция и есть схема);
//   - проб (им положено готовить состояние);
//   - имя таблицы, СОБРАННОЕ ИЗ КУСКОВ — настоящая слепая зона, предикатом по
//     подстроке не ловится ничем.
//
// И отдельно: инъекция подаёт вход сама, поэтому исчезновение предмета из дерева
// её не трогает — гейт ЗАМОЛЧАЛ БЫ, оставаясь зелёным. Поэтому предпосылка
// проверяется отдельно: ноль упоминаний таблицы — ОТКАЗ, а не «нарушений нет».
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗДЕСЬ СТОЯЛО ИМЯ ПИСАТЕЛЯ, КОТОРОГО В ДЕРЕВЕ НЕТ
//
// Прежняя шапка называла второго писателя поимённо — `BackfillOwnerBindings` →
// `replaceRoleVerbsTx`, свой сырой SQL в слое досева. Его там больше нет. Шапка
// пережила свой предмет и посылала читателя искать координату, которой не
// существует, — ровно тот класс, против которого сам гейт и написан.
//
// Предикат отсутствия — с исключением ЭТОГО каталога, и исключение не косметика:
// имя живёт теперь в двух местах, и оба здесь — разбор выше и синтетическая
// функция инъекции. Предикат без исключения находил бы СОБСТВЕННОЕ объяснение
// гейта и объявлял писателя живым:
//
//	git grep -l replaceRoleVerbsTx -- '*.go' ':!internal/repohygiene/*'   → пусто

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/gitenv"
)

// roleVerbTable — проекция «роль → тип объекта × глагол».
const roleVerbTable = "kacho_iam.role_verb"

// roleRuleRefTable — проекция ОБЪЯВЛЕННЫХ сегментов правила (kacho#1030).
//
// ВТОРАЯ проекция того же объявления, и свойство единственного автора обязано
// прийти вместе с ней: решение #1028 закрыто наполовину, если новая таблица его
// не наследует. Предмет у таблиц разный (та несёт резолвящееся, эта — каждый
// объявленный сегмент), а требование к автору — одно.
const roleRuleRefTable = "kacho_iam.role_rule_ref"

// roleGrantOrphanTable — куда обязано переселяться снятое не-автором.
//
// Таблица существует ровно ради этого: снятие ПЕРЕСЕЛЯЕТ, а не отбирает молча,
// иначе отобранное право неотличимо от никогда не выданного.
const roleGrantOrphanTable = "kacho_iam.role_grant_orphan"

// roleProjectionTables — таблицы, у каждой из которых автор обязан быть один.
var roleProjectionTables = []string{roleVerbTable, roleRuleRefTable}

// authorVerbOf — оператор, которым строка ВНОСИТСЯ. Только он объявляет, что
// такое законная строка: называет колонки и значения.
func authorVerbOf(table string) string { return "INSERT INTO " + table }

// removalVerbsOf — операторы, которыми строка СНИМАЕТСЯ либо правится. Формы
// строки они не объявляют, но повторяют её КЛЮЧ.
//
// Чтение (`SELECT … FROM`, `JOIN`) в перечень не входит намеренно: читателей у
// проекции шесть, все считают или соединяют строки, и все обязаны остаться
// законными — они и служат близнецом, на котором гейт молчит.
func removalVerbsOf(table string) []string {
	return []string{"DELETE FROM " + table, "UPDATE " + table}
}

// roleVerbWriterLayer — слой, которому принадлежит SQL проекции. Писатель вне
// него — находка, даже если он один: проекция есть состояние репозитория, и
// решение «как писать» не принадлежит ни use-case, ни транспорту.
const roleVerbWriterLayer = "/internal/repo/"

// projectionOp — один найденный оператор над проекцией.
type projectionOp struct {
	// Func — объемлющая функция; пустое имя означает пакетный уровень (константа).
	Func string
	// Verb — какой оператор найден.
	Verb string
	// Authors — оператор ВНОСИТ строку, то есть объявляет её форму.
	Authors bool
	// Relocates — ТОТ ЖЕ литерал переселяет снятое в `role_grant_orphan`.
	//
	// Признак читается по литералу, а не по функции: переселение и снятие обязаны
	// быть неделимы, а неделимы они ровно тогда, когда стоят в одном операторе.
	Relocates bool
}

// roleVerbWritesIn — совместимая обёртка для инъекции по первой проекции.
func roleVerbWritesIn(filename, src string) ([]projectionOp, int, error) {
	return projectionWritesIn(filename, src, roleVerbTable)
}

// projectionWritesIn разбирает исходник Go и возвращает операторы над таблицей
// проекции, приписанные объемлющей функции, плюс число строковых литералов,
// называющих таблицу вообще (перепись предпосылки: читатели тоже считаются).
//
// Признак судит УЗЕЛ-ЛИТЕРАЛ разобранного дерева, а не текст файла: имя таблицы
// встречается и в комментариях — в том числе в комментариях, ОБЪЯСНЯЮЩИХ эту
// самую проверку, — и гейт по подстроке краснел бы на собственном объяснении.
func projectionWritesIn(filename, src, table string) ([]projectionOp, int, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, 0)
	if err != nil {
		return nil, 0, err
	}

	// enclosing сопоставляет позицию литерала имени объемлющей функции.
	type span struct {
		from, to token.Pos
		name     string
	}
	var spans []span
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		name := fn.Name.Name
		if fn.Recv != nil && len(fn.Recv.List) > 0 {
			name = typeName(fn.Recv.List[0].Type) + "." + name
		}
		spans = append(spans, span{from: fn.Body.Pos(), to: fn.Body.End(), name: name})
	}

	var (
		ops      []projectionOp
		mentions int
	)
	ast.Inspect(file, func(n ast.Node) bool {
		lit, ok := n.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		if !strings.Contains(lit.Value, table) {
			return true
		}
		mentions++
		upper := strings.ToUpper(lit.Value)
		owner := ""
		for _, s := range spans {
			if lit.Pos() >= s.from && lit.End() <= s.to {
				owner = s.name
				break
			}
		}
		relocates := strings.Contains(upper,
			strings.ToUpper("INSERT INTO "+roleGrantOrphanTable))

		if author := authorVerbOf(table); strings.Contains(upper, strings.ToUpper(author)) {
			ops = append(ops, projectionOp{Func: owner, Verb: author, Authors: true, Relocates: relocates})
		}
		for _, verb := range removalVerbsOf(table) {
			if strings.Contains(upper, strings.ToUpper(verb)) {
				ops = append(ops, projectionOp{Func: owner, Verb: verb, Relocates: relocates})
			}
		}
		return true
	})
	return ops, mentions, nil
}

// TestIAMRV112_RoleVerbProjectionHasASoleWriter — в непроверочном коде Go ровно
// ОДНА функция вносит строку проекции роли, всякий снимающий не-автор переселяет
// снятое, и все они лежат в слое репозитория.
func TestIAMRV112_RoleVerbProjectionHasASoleWriter(t *testing.T) {
	// Таблиц ДВЕ (kacho#1030, требование Т5 приёмки
	// rule-segments-have-a-referent): у каждой проекции одного и того же
	// объявления автор обязан быть один. Подпроба на таблицу, а не один проход по
	// обеим: перепись обязана печататься по КАЖДОЙ, иначе «автор один» на
	// суммарном счёте зеленело бы при двух и нуле.
	for _, table := range roleProjectionTables {
		t.Run(table, func(t *testing.T) { soleWriterOf(t, table) })
	}
}

func soleWriterOf(t *testing.T, table string) {
	root := repoRoot(t)
	out, err := gitenv.Command(root, "ls-files", "-z", "--", "*.go").Output()
	if err != nil {
		t.Fatalf("git ls-files: %v — состав дерева не установлен, и «ноль находок» "+
			"здесь означало бы «ноль прочитанного»", err)
	}

	var (
		filesRead int
		mentions  int
		// authors — функции, ВНОСЯЩИЕ строку: «путь::функция».
		authors []string
		// removers — функции, снимающие либо правящие строку.
		removers []string
		// strandedRemovers — снимающие, чей оператор НЕ переселяет снятое.
		strandedRemovers []string
		// writers — все пишущие вообще: их и судит ось слоя.
		writers    = map[string]bool{}
		writerKeys []string
	)
	seenAuthor := map[string]bool{}
	seenRemover := map[string]bool{}

	for _, rel := range strings.Split(strings.TrimRight(string(out), "\x00"), "\x00") {
		if rel == "" || skipPath(rel) || strings.HasSuffix(rel, "_test.go") {
			continue
		}
		b, readErr := os.ReadFile(filepath.Join(root, rel)) // #nosec G304 -- путь из индекса своего дерева
		if readErr != nil {
			t.Fatalf("чтение %s: %v", rel, readErr)
		}
		filesRead++
		body := string(b)
		if !strings.Contains(body, table) {
			continue
		}
		ops, m, perr := projectionWritesIn(rel, body, table)
		if perr != nil {
			t.Fatalf("разбор %s: %v — файл индекса не разобран, и его молчание ничего не значит", rel, perr)
		}
		mentions += m
		for _, op := range ops {
			key := rel + "::" + op.Func
			if !writers[key] {
				writers[key] = true
				writerKeys = append(writerKeys, key)
			}
			if op.Authors {
				if !seenAuthor[key] {
					seenAuthor[key] = true
					authors = append(authors, key)
				}
				continue
			}
			if !seenRemover[key] {
				seenRemover[key] = true
				removers = append(removers, key)
			}
			if !op.Relocates {
				strandedRemovers = append(strandedRemovers, key+" ("+op.Verb+")")
			}
		}
	}

	t.Logf("осмотрено непроверочных файлов Go: %d; литералов, называющих %s: %d; "+
		"пишущих функций: %d, из них АВТОРОВ (вносят строку): %d, снимающих: %d",
		filesRead, table, mentions, len(writerKeys), len(authors), len(removers))

	if filesRead == 0 {
		t.Fatal("осмотрено ноль файлов — гейт не читал дерева, и его молчание ничего не значит")
	}
	// Предпосылка: таблица вообще названа в коде. Ноль упоминаний означает либо
	// переименование (правь `roleVerbTable` вместе с ним), либо что её перестали
	// и читать, и писать. И то и другое обязано быть замечено ЗДЕСЬ, а не принято
	// за «нарушений нет»: инъекция подаёт вход сама и исчезновения предмета не видит.
	if mentions == 0 {
		t.Fatalf("имя %q не встречается в непроверочном коде НИ РАЗУ — предмета у гейта нет: "+
			"либо таблица переименована, либо её перестали читать и писать", table)
	}

	// ── ОСЬ 1: АВТОР ОДИН ────────────────────────────────────────────────────
	if len(authors) != 1 {
		t.Errorf("авторов проекции роли %d, а обязан быть ОДИН: %v\n"+
			"Что такое законная строка, объявляет ТОЛЬКО тот, кто её вносит: он называет "+
			"колонки и значения. Пока вносящих двое, изменение формы строки обязано доехать "+
			"до каждого, а промах МОЛЧАЛИВ — обе реализации компилируются, у обеих есть "+
			"пробы, и расходятся они только на входе, который ни одна проба не подаёт.",
			len(authors), authors)
	}

	// ── ОСЬ 2: СНИМАЮЩИЙ НЕ-АВТОР ПЕРЕСЕЛЯЕТ ─────────────────────────────────
	//
	// Автор снимает СВОЮ проекцию, заменяя её тем же вызовом, — переселять ему
	// нечего и незачем. Всякий другой снимает по ЧУЖОМУ поводу, и снятое обязано
	// найтись в сиротах, иначе отобранное право неотличимо от невыданного.
	for _, stranded := range strandedRemovers {
		key := stranded[:strings.Index(stranded, " (")]
		if seenAuthor[key] {
			continue
		}
		t.Errorf("%s — снимает строку проекции роли, НЕ будучи её автором и НЕ переселяя "+
			"снятое в %s.\nСнятие по чужому поводу обязано ПЕРЕСЕЛЯТЬ тем же оператором: "+
			"иначе у арендатора отобрано право, записи об этом нет, и отобранное неотличимо "+
			"от никогда не выданного. Переселение и снятие неделимы ровно тогда, когда стоят "+
			"в одном операторе — поэтому признак читается по литералу, а не по функции.",
			stranded, roleGrantOrphanTable)
	}

	// ── ОСЬ 3: СЛОЙ ──────────────────────────────────────────────────────────
	for _, key := range writerKeys {
		rel := key[:strings.Index(key, "::")]
		if !strings.Contains("/"+rel, roleVerbWriterLayer) {
			t.Errorf("%s — писатель проекции роли ВНЕ слоя репозитория (%s).\n"+
				"Проекция есть состояние репозитория: форму строки, отображение отказов и "+
				"транзакционность держит слой repo/. Решение «как писать» не принадлежит ни "+
				"use-case, ни транспорту — они решают лишь КОГДА и ДЛЯ КАКИХ ролей пересчитывать, "+
				"и зовут писателя через порт.", key, roleVerbWriterLayer)
		}
	}
}
