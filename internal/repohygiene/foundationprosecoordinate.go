// foundationprosecoordinate.go — КООРДИНАТА ПЕРЕЕЗЖАЮЩЕГО ПАКЕТА, НАЗВАННАЯ
// ВНУТРИ ФУНДАМЕНТА НЕ ИМПОРТОМ, ПЕРЕЖИВЁТ СВОЙ ПРЕДМЕТ В ДЕНЬ ПУБЛИКАЦИИ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Дерево фундамента собирается из `pkg/` со сменой пути модуля, и импорты
// переезжающих пакетов переписываются ПОЛНЫМ ТОКЕНОМ В КАВЫЧКАХ — ровно тем,
// что видит компилятор. Всё, что названо ИНАЧЕ, уезжает дословно:
//
//	[github.com/PRO-Robotech/kacho/pkg/servicehost]   ссылка godoc
//	пакет github.com/PRO-Robotech/kacho/pkg/outbox    проза
//	`…/pkg/errors`.Reason                             код-span
//
// После публикации такой координаты нет НИ В ОДНОМ дереве: пакет уехал из
// платформы вместе с `pkg/`, а в фундаменте лежит под другим модулем. Ссылка не
// «устарела» — она указывает в пустоту, и заметить это нечем: сборка её не
// читает, а перепись производителя печатает лишь ЧИСЛО остатка.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО СУДИТСЯ, И ПОЧЕМУ ИМЕННО ДОПОЛНЕНИЕ К ПЕРЕПИСЫВАЕМОМУ
//
// Находка — вхождение пути ПЕРЕЕЗЖАЮЩЕГО пакета внутри переезжающего каталога,
// НЕ окружённое кавычками с обеих сторон. Предикат намеренно есть дополнение к
// тому, что переписывает производитель дерева: он заменяет `"<путь>"`, значит
// всё прочее остаётся дословно. Совпадение предикатов — не дубль, а шов: гейт
// стережёт ровно то, чего производитель не трогает, и это сказано вслух, чтобы
// следующий не «упростил» одну из сторон.
//
// ─────────────────────────────────────────────────────────────────────────────
// ТРИ ЗАКОННЫХ БЛИЗНЕЦА — НАЗВАНЫ, ЧТОБЫ ГЕЙТ НЕ ЛОВИЛ ФОРМУ ВМЕСТО СУЩЕСТВА
//
//  1. путь в кавычках — его переписывает производитель, в том числе в обычном
//     строковом литерале, а не только в блоке импорта;
//  2. ГОЛЫЙ путь модуля платформы без пакета под ним — законное утверждение о
//     платформе как таковой (`go mod tidy` дописывал бы `require <модуль>`),
//     и оно переживает переезд, потому что модуль платформы никуда не девается;
//  3. путь пакета, который НЕ переезжает (доменные контракты, манифест модулей):
//     после публикации он остаётся ровно там, где назван.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО РАСПОЗНАВАТЕЛЬ НЕ ВИДИТ — НАЗВАНО ЧИСЛОМ, А НЕ УМОЛЧАНО
//
// Судится путь, названный ЦЕЛИКОМ, вместе с приставкой модуля. Форма без неё —
// `kacho/pkg/<каталог>`, которой пишут предикаты в комментариях, — под ось НЕ
// подпадает, и это решение, а не упущение.
//
// Замер на `f49fd977ce` (предикат: вхождения `kacho/pkg/` под `pkg/`, не
// предварённые полной приставкой модуля): их ШЕСТЬ. Пять — фикстуры значений в
// `pkg/listfiltergate/ownmodule_test.go`, подающие раскладку монорепо самой
// проверке; отличить их от координаты распознаватель не может ничем, кроме
// исключения с единственным членом, то есть послабления с одним предметом и без
// предиката снятия. Шестое — предикат в комментарии `pkg/authz/doc.go`: он
// записан этой формой и после публикации ответит пусто по неверной причине.
// Здесь он не правится намеренно — его предмет перечень потребителей `pkg/authz`,
// а не координата переезда, и правка формы без правки утверждения сделала бы
// абзац противоречащим себе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПУТЬ МОДУЛЯ ПЛАТФОРМЫ ВЫВОДИТСЯ, А НЕ ВЫПИСЫВАЕТСЯ
//
// Он берётся у корневого `go.mod` того же дерева. Выписанный, он был бы ровно
// тем классом, который ловит `TestModulePathConstantDoesNotOutliveItsModule`:
// собственным именем, пережившим свой предмет.

// knownBakedDescriptor — запись ведомости: ПОРОЖДЁННЫЙ стаб, чей сериализованный
// дескриптор несёт путь платформы, и предмет, которым запись снимается.
//
// Счёт ТОЧНЫЙ, а не потолок: запись, которой больше нечего прощать, обязана
// истечь сама. Потолок («не больше N») не краснеет на сокращении долга и потому
// не истекает никогда.
type knownBakedDescriptor struct {
	// File — путь стаба от корня дерева.
	File string
	// Count — сколько вхождений в этом файле прощается.
	Count int
	// Subject — чем запись снимается. Пустой предмет запрещён: запись без
	// обоснования неотличима от упущения.
	Subject string
}

// knownBakedDescriptors — ведомость запечённых дескрипторов, живых на сегодняшнем
// дереве.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ВЕДОМОСТЬ, А НЕ ПРАВКА
//
// `go_package` лежит внутри сериализованного `FileDescriptorProto`, а перед телом
// строки стоит её ДЛИНА. Правка текстом либо меняет длину — и тогда разбор падает
// при `init`, до первой строки любой пробы, — либо длину не меняет и оставляет
// прежний путь. Третьего текстового исхода нет.
//
// Единственная починка — РЕГЕНЕРАЦИЯ из контракта: путь задаётся `option
// go_package` в дереве `proto/`, по одному объявлению на каждый файл этой
// ведомости. Сделать её В МОНОРЕПО нельзя, и это измерено, а не предположено:
// генерация ведётся с `paths=source_relative`, поэтому смена `go_package` файл НЕ
// двигает, но переписывает ИМПОРТЫ во всяком порождённом файле, который ссылается
// на эти типы, — на модуль, которого дерево ещё не производит. Замер на f49fd977ce:
// таких порождённых файлов 192, а всего импортёров этих пяти путей 417. То есть
// правка до публикации фундамента ломает платформу целиком.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ВЕДОМОСТЬ ДАЁТ, РАЗ ПОЧИНИТЬ СЕЙЧАС НЕЛЬЗЯ
//
// Она делает остаток НАХОДКОЙ, а не числом, напечатанным инструментом, который
// зовут вручную. Девятый контракт, заведённый в одном из этих четырёх поддеревьев,
// добавит стаб — и счёт разойдётся с ведомостью в тот же день, а не в день
// публикации, когда исправлять уже нечего: версию модуля из базы контрольных сумм
// не отозвать.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЕДОМОСТЬ ЗАКРЫТА ДЛЯ ПРОЗЫ — И ЭТО НЕСУЩЕЕ
//
// Прощается только ПОРОЖДЁННЫЙ стаб (`.pb.go`). Координата, названная прозой,
// ссылкой godoc или код-спаном, правится текстом за секунду, и запись о ней была
// бы послаблением без предмета. Проверяется отдельной осью, а не доверием к
// автору записи.
