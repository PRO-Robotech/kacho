// foundationProseFinding — одно наблюдение: координата переезжающего пакета,
// названная внутри фундамента так, что переезд её не поправит.
type foundationProseFinding struct {
	// File — путь носителя от корня дерева.
	File string
	// Line — номер строки.
	Line int
	// Named — путь, названный в строке.
	Named string
	// Text — сама строка, обрезанная до читаемого.
	Text string
}

func (f foundationProseFinding) String() string {
	return fmt.Sprintf("%s:%d называет переезжающий пакет %q не импортом (%s) — "+
		"производитель дерева фундамента переписывает только путь В КАВЫЧКАХ, "+
		"поэтому эта координата уедет дословно и после публикации не будет "+
		"резолвиться ни в одном дереве: пакет уехал из платформы, а в фундаменте "+
		"лежит под другим модулем", f.File, f.Line, f.Named, strings.TrimSpace(f.Text))
}

// foundationProseCensus — объём осмотренного.
//
// Печатаются ОБЕ величины — осмотренное и найденное, — потому что расширение
// распознавателя обязано быть отличимо от регрессии дерева: выросло осмотренное
// при неизменной находке — закрыта слепая зона; не изменилось — расширение
// холостое.
type foundationProseCensus struct {
	// Files — файлов переезжающих каталогов прочитано.
	Files int
	// MovingDirs — переезжающих каталогов насчитано.
	MovingDirs int
	// Quoted — вхождений пути переезжающего пакета В КАВЫЧКАХ (их переписывает
	// производитель; это законный близнец, а не находка).
	Quoted int
	// Surviving — вхождений, переживающих публикацию: голый путь модуля
	// платформы и путь пакета, который НЕ переезжает (близнецы 2 и 3).
	Surviving int
	// Outside — вхождений вне кавычек ВСЕГО (до сверки с ведомостью).
	Outside int
	// Excused — из них прощённых ведомостью запечённых дескрипторов.
	Excused int
	// Findings — из них не прощённых, то есть находок.
	Findings int
}

func (c foundationProseCensus) String() string {
	return fmt.Sprintf("перепись: файлов переезжающих каталогов %d · переезжающих каталогов %d · "+
		"путь переезжающего пакета в кавычках %d · переживает публикацию %d · "+
		"вне кавычек %d (прощено дескрипторов %d, находок %d)",
		c.Files, c.MovingDirs, c.Quoted, c.Surviving, c.Outside, c.Excused, c.Findings)
}

// judgeFoundationProseCoordinates — вердикт над уже прочитанным составом.
//
// Вход — содержимое файлов ПЕРЕЕЗЖАЮЩИХ каталогов и множество этих каталогов,
// чтобы доказательство способности упасть шло по синтетическому корпусу и не
// писало в живое дерево.
//
// Пустой обход — НАХОДКА, а не чистота: гейт, не прочитавший ни одного файла,
// о дереве не высказался.
func judgeFoundationProseCoordinates(
	platformModule string,
	movingDirs map[string]bool,
	contents map[string]string,
) ([]foundationProseFinding, foundationProseCensus) {
	census := foundationProseCensus{Files: len(contents), MovingDirs: len(movingDirs)}

	var findings []foundationProseFinding
	if platformModule == "" {
		return []foundationProseFinding{{File: "<корень>", Line: 0, Named: "",
			Text: "корневой go.mod не объявил модуля — путь платформы выводить не из чего"}}, census
	}
	if len(contents) == 0 || len(movingDirs) == 0 {
		return []foundationProseFinding{{File: "<обход>", Line: 0, Named: "",
			Text: "прочитано ноль файлов либо ноль переезжающих каталогов — вердикт беспредметен"}}, census
	}

	// Пути переезжающих пакетов, от самого длинного: иначе `…/pkg/outbox`
	// перехватило бы вхождение `…/pkg/outbox/drainer`, и находка назвала бы не
	// тот пакет.
	moving := make([]string, 0, len(movingDirs))
	for d := range movingDirs {
		moving = append(moving, platformModule+"/"+d)
	}
	sort.Slice(moving, func(i, j int) bool { return len(moving[i]) > len(moving[j]) })

	names := make([]string, 0, len(contents))
	for f := range contents {
		names = append(names, f)
	}
	sort.Strings(names)

	for _, file := range names {
		for i, line := range strings.Split(contents[file], "\n") {
			rest := line
			off := 0
			for {
				idx := strings.Index(rest, platformModule)
				if idx < 0 {
					break
				}
				at := off + idx
				matched := ""
				for _, m := range moving {
					if strings.HasPrefix(line[at:], m) && !isPathChar(line, at+len(m)) {
						matched = m
						break
					}
				}
				switch {
				case matched == "":
					// Голый путь модуля платформы либо пакет, который не
					// переезжает: и то и другое переживает публикацию.
					census.Surviving++
				case at > 0 && line[at-1] == '"' && at+len(matched) < len(line) && line[at+len(matched)] == '"':
					census.Quoted++
				default:
					census.Outside++
					findings = append(findings, foundationProseFinding{
						File: file, Line: i + 1, Named: matched, Text: line,
					})
				}
				step := len(platformModule)
				if matched != "" {
					step = len(matched)
				}
				off = at + step
				rest = line[off:]
			}
		}
	}
	return findings, census
}

// judgeFoundationProseCoordinatesAgainst — тот же вердикт, сведённый с ведомостью
// запечённых дескрипторов.
//
// Возвращает ТРИ величины, а не одну: не прощённые находки, устаревшие записи
// ведомости («исключению нечего исключать») и перепись. Слить их нельзя ни в одну
// сторону — сокращение долга обязано краснеть так же громко, как его рост.
func judgeFoundationProseCoordinatesAgainst(
	platformModule string,
	movingDirs map[string]bool,
	contents map[string]string,
	ledger []knownBakedDescriptor,
) (unexcused []foundationProseFinding, stale []string, census foundationProseCensus) {
	all, census := judgeFoundationProseCoordinates(platformModule, movingDirs, contents)
	census.Outside = len(all)

	allowed := map[string]int{}
	for _, e := range ledger {
		if e.Subject == "" {
			stale = append(stale, fmt.Sprintf("%s: запись ведомости без предмета — обоснование "+
				"обязательно, иначе запись неотличима от упущения", e.File))
			continue
		}
		if !strings.HasSuffix(e.File, ".pb.go") {
			stale = append(stale, fmt.Sprintf("%s: ведомость закрыта для всего, кроме порождённых "+
				"стабов — координата, названная прозой, правится текстом и записи не требует", e.File))
			continue
		}
		allowed[e.File] += e.Count
	}

	seen := map[string]int{}
	for _, f := range all {
		if allowed[f.File] > seen[f.File] {
			seen[f.File]++
			census.Excused++
			continue
		}
		unexcused = append(unexcused, f)
	}
	census.Findings = len(unexcused)

	files := make([]string, 0, len(allowed))
	for f := range allowed {
		files = append(files, f)
	}
	sort.Strings(files)
	for _, f := range files {
		if seen[f] < allowed[f] {
			stale = append(stale, fmt.Sprintf("%s: ведомость прощает %d вхождени(й), а в дереве их %d — "+
				"записи нечего прощать. Стаб перегенерирован? Снимите запись тем же изменением: "+
				"послабление, пережившее свой предмет, не истечёт больше никогда",
				f, allowed[f], seen[f]))
		}
	}
	return unexcused, stale, census
}

// isPathChar сообщает, продолжает ли байт на позиции i путь пакета, — чтобы
// `…/pkg/errors` не совпало внутри `…/pkg/errorsx`, а `…/pkg/quota/quotaiam`
// (каталог НЕ переезжает) не был прочитан как `…/pkg/quota`.
//
// Точка сюда НЕ входит намеренно: в ссылке godoc она отделяет символ от пакета
// (`…/pkg/errors.Reason`), и включив её, распознаватель молча перестал бы видеть
// самую частую форму находки — именно ту, ради которой гейт заведён.
func isPathChar(s string, i int) bool {
	if i >= len(s) {
		return false
	}
	c := s[i]
	return c == '/' || c == '-' || c == '_' ||
		(c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')
}
