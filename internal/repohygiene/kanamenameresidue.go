// BorderCatalogueCensus — сколько вхождений дерева покрывает КАЖДАЯ запись
// закрытого перечня. Второй возврат — файлов прочитано.
//
// ПОЧЕМУ СЧЁТ ИДЁТ МИМО ПРАВИЛ. Запись, чьи вхождения забирает более раннее
// правило (путь модуля фундамента, одобренная приёмка), при счёте по полосам
// выглядела бы беспредметной, и самоистечение сняло бы живую запись. Здесь
// считается СЕГМЕНТ дерева, а не находка полосы, поэтому порядок правил на
// вердикт не влияет вовсе.
//
// Ноль прочитанных файлов — ОТКАЗ: «у записи нет предмета» и «мы не читали»
// обязаны быть различимы, иначе перечень истёк бы весь и разом на пустом обходе.
func BorderCatalogueCensus(
	files map[string][]byte,
	catalogues map[string][]string,
) (map[string]map[string]int, int, error) {
	if len(files) == 0 {
		return nil, 0, fmt.Errorf(
			"на вход подано ноль файлов — обход не состоялся, и «у записи нет " +
				"предмета» означало бы «мы не читали»")
	}
	wanted := map[string]bool{}
	out := map[string]map[string]int{}
	for catalogue, names := range catalogues {
		out[catalogue] = map[string]int{}
		for _, name := range names {
			out[catalogue][name] = 0
			wanted[name] = true
		}
	}

	filesRead := 0
	seen := map[string]int{}
	for _, body := range files {
		if len(body) == 0 || containsNUL(body) {
			continue
		}
		filesRead++
		for lineNo, line := range strings.Split(string(body), "\n") {
			for _, h := range hitsInLine("", lineNo+1, line, false) {
				name := strings.TrimRight(h.Seg, proseNameTerminators)
				if wanted[name] {
					seen[name]++
				}
			}
		}
	}
	for catalogue, names := range out {
		for name := range names {
			out[catalogue][name] = seen[name]
		}
	}
	return out, filesRead, nil
}

