// Перечень узок НАМЕРЕННО: продолжение имени буквой, цифрой, подчёркиванием или
// дефисом означает ДРУГОЙ объект (`kacho_nlb.targets`, `kacho-iam-bootstrap`),
// и срезать его значило бы признать чужим то, чем оно не
// является. По той же причине НЕ срезается адрес: `kacho-iam:9091` — Service
// НАШЕГО развёртывания, и снять это имя обязана служба, а не простить граница.
const proseNameTerminators = ".:"

// residueHit — одно вхождение имени и его окрестность.
//
// Разбор идёт по СЕГМЕНТУ пути, а не по всему токену: у адреса
// `spiffe://kacho.cloud/ns/kacho/sa/kacho-vpc` три вхождения с тремя разными
// смыслами — домен доверия, пространство имён и чужой модуль, — и распознаватель
// по целому токену свёл бы их в одно.
type NameResidueHit struct {
	Path string
	Line int
	// Text — токен целиком: то, что читатель находки увидит в дереве.
	Text string
	// Seg — сегмент пути, содержащий вхождение; SegPre и SegRest — что стоит в
	// сегменте до и после имени.
	Seg, SegPre, SegRest string
	// PathPre и PathRest — сегменты токена до и после текущего.
	PathPre, PathRest string
	// Hit — имя, КАК ЗАПИСАНО в дереве; Macron — диакритическая ли форма.
	Hit    string
	Macron bool
	// LinePrefix — вся строка слева от вхождения: по ней узнаётся значение
	// ключа профиля, которое сегментом пути не выражается.
	LinePrefix string
	// LineRest — вся строка справа от ТОКЕНА. Знак, стоящий сразу за именем,
	// токеном не выражается (в токен он не входит), а различить по нему нужно:
	// `kacho#2260` называет репозиторий учёта, а не продукт.
	LineRest string
	// InChart — файл принадлежит чарту оператора.
	InChart bool
	// Lane — полоса, признавшая вхождение своим предметом.
	Lane string
}

// residueWorld — то, что распознаватель узнаёт НЕ из самого вхождения, а из
// дерева: перечни, объявленные другими его частями.
//
// Заведено параметром, а не глобальной переменной, ровно затем, чтобы
// синтетический мир инъекции и настоящее дерево проходили ОДНУ функцию: перечень,
// выставляемый в глобаль перед прогоном, сделал бы вердикт функцией порядка
// тестов, а они идут параллельно.
type residueWorld struct {
	// FoundationSeries — имена рядов витрины, ОБЪЯВЛЕННЫЕ фундаментом. Пустой
	// перечень означает «не собирали»: вычитание тогда не делается вовсе, и это
	// отличимо от «рядов нет» переписью держателя.
	FoundationSeries map[string]bool
}

type residueRule struct {
	Lane  string
	Match func(h NameResidueHit, w residueWorld) bool
}

