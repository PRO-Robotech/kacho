// FoundationSeriesFromCorpus — имена рядов витрины, объявленные ЛИТЕРАЛОМ в
// позиции имени ряда. Второе возвращаемое — файлов разобрано: ноль означает, что
// обход не состоялся, и «рядов нет» тогда значит «не искали».
//
// Судится ПОЗИЦИЯ (`Name:` в объявлении измерителя), а не подстрока: имя ряда и
// имя схемы записываются одинаково — приставка платформы плюс слова через
// подчёркивание, — и различает их только место, где литерал стоит.
func FoundationSeriesFromCorpus(files map[string][]byte) (map[string]bool, int) {
	out := map[string]bool{}
	filesRead := 0

	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	for _, path := range paths {
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			continue
		}
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, files[path], 0)
		if err != nil {
			// Неразбираемый исходник — предмет компилятора, не этого разбора.
			continue
		}
		filesRead++
		ast.Inspect(file, func(n ast.Node) bool {
			kv, ok := n.(*ast.KeyValueExpr)
			if !ok {
				return true
			}
			key, ok := kv.Key.(*ast.Ident)
			if !ok || key.Name != "Name" {
				return true
			}
			lit, ok := kv.Value.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			value, uerr := strconv.Unquote(lit.Value)
			if uerr != nil {
				return true
			}
			if strings.HasPrefix(value, "kacho_") {
				out[value] = true
			}
			return true
		})
	}
	return out, filesRead
}

// foundationSeriesSuffixes — хвосты, которые Prometheus дописывает к ряду
// гистограммы. В объявлении их нет: объявлено базовое имя, а запрос дежурного
// берёт производное, и страница называет именно производное.
var foundationSeriesSuffixes = [...]string{"_bucket", "_sum", "_count"}

// isFoundationMetricSeries — объявлен ли токен рядом витрины фундамента.
//
// ПОЛНОЕ имя спрашивается ПЕРВЫМ, и только затем — имя без хвоста гистограммы.
// Обратный порядок ошибается на настоящем ряде, чьё имя оканчивается так же:
// счётчик `..._total` производным ни от чего не является.
//
// Пустой перечень означает «не собирали», и тогда вычитания не происходит вовсе:
// молчание здесь не выдаётся за «рядов нет» — это различает перепись держателя.
func isFoundationMetricSeries(series map[string]bool, token string) bool {
	if len(series) == 0 {
		return false
	}
	if series[token] {
		return true
	}
	for _, suffix := range foundationSeriesSuffixes {
		if strings.HasSuffix(token, suffix) && series[strings.TrimSuffix(token, suffix)] {
			return true
		}
	}
	return false
}

// isForeignPlatformModule — сегмент есть УПОМИНАНИЕ имени чужого модуля
// платформы в любой из форм, которыми его записывает дерево.
//
// Судится ОХРАНА, а не словарь, ровно как у функции фундамента выше: словарь
// закрыт и остаётся закрытым, расходилась с ним ОБЁРТКА. Замер 2026-09-10:
// **19 вхождений в 16 файлах** несли имя чужого продукта с терминальной
// пунктуацией прозы (`kacho-vpc:`, `kacho-iam.`, `kacho-deploy.`,
// `kacho-loadbalancer.`) и потому числились остатком СЛУЖБЫ — то есть держатель
// требовал снять имя, которого Kaname не переименовывает.
//
// Снимается РОВНО ОДИН слой, и он структурен: терминальная пунктуация прозы,
// частью имени быть не могущая. Всё прочее продолжение остаётся значимым —
// `kacho-iam-bootstrap` есть встроенная учётка СЛУЖБЫ, а `kacho-iam:9091` —
// адрес Service НАШЕГО развёртывания; оба обязаны остаться в долге, и оба
// остаются by construction.
func isForeignPlatformModule(seg string) bool {
	_, ok := KanameForeignPlatformModules[strings.TrimRight(seg, proseNameTerminators)]
	return ok
}

// isPlatformOwnedObject — сегмент называет объект, которым владеет НЕ Kaname.
//
// Признаний ДВА, и они о разном:
//
//   - имя ПОРОЖДЕНО релизом зонта платформы (`<релиз>-<имя>`) — это способ
//     порождения, а не образец: перечислять поимённо пришлось бы каждый объект
//     каждого подчарта, и перечень отставал бы от чарта молча;
//   - имя стоит в ЗАКРЫТОМ каталоге, где у каждой записи назван владелец.
//
// Терминальная пунктуация прозы снимается тем же перечнем, что у Б3: беда одна
// на обоих, и лечится она одним местом.
func isPlatformOwnedObject(seg string) bool {
	if strings.HasPrefix(seg, platformUmbrellaRelease+"-") {
		return true
	}
	_, ok := KanamePlatformOwnedObjects[strings.TrimRight(seg, proseNameTerminators)]
	return ok
}

// namespacePositions — левый контекст строки, после которого стоит имя
// ПРОСТРАНСТВА ИМЁН кластера, а не имя объекта.
//
// Судится ПОЗИЦИЯ, а не имя: пространство имён зовут `kacho-system` и
// `kacho-prod`, и по написанию первое из них неотличимо от СИСТЕМНОГО АККАУНТА
// службы — это одно и то же слово, посеянное в двух разных мирах. Отличает их
// ровно место, где имя стоит.
// ПЕРЕЧЕНЬ ВЕДЁТСЯ ПО ФАКТУ, а не про запас: замер 2026-09-10 даёт по каждой
// записи предмет (`/ns/` — 12, ключ манифеста — 1, длинный флаг — 1, краткий —
// 1), и записи `namespace:` без пробела здесь нет, потому что таких строк на
// поверхности НОЛЬ. Позиция без предмета — то же послабление, выданное вперёд:
// она ничего не ловит и переживает своё основание молча.
var namespacePositions = [...]string{
	"/ns/",         // сегмент SPIFFE-имени
	"namespace: ",  // ключ манифеста
	"--namespace ", // флаг kubectl/kubeseal
	"-n ",          // он же, краткий
}

// isClusterNamespacePosition — имя стоит в позиции пространства имён кластера И
// является СОСТАВНЫМ (`kacho-<слово>`).
//
// Пространство имён заводит УСТАНОВКА платформы: его выбирает тот, кто ставит
// зонт, и Kaname в своей поставке выберет своё. Поэтому составное имя здесь
// называет чужой объект, а не себя.
//
// ГОЛАЯ ФОРМА НАМЕРЕННО ОСТАВЛЕНА ЗА ГРАНИЦЕЙ, и это не осторожность, а замер.
// Позиция сама по себе владельца НЕ решает: `namespace: kacho` — это и
// пространство платформенной установки, и то, как продукт называет себя в
// собственном примере, а различить их местом нельзя. Правило, судившее одну
// позицию, забрало у соседней полосы **107** вхождений из 311 (замер
// 2026-09-10) — то есть решило за неё спорный вопрос, которого никто не решал.
// Составная форма спора не имеет: системный аккаунт службы в позиции
// пространства имён не стоит никогда.
//
// Форм ТРИ, и третья не выражается левым контекстом: в DNS-имени Service
// (`kaname.kacho-system.svc`) пространство имён стоит ВТОРЫМ ярлыком, а слева от
// него — имя Service. Её распознаёт отдельная ветвь, иначе она молчала бы.
func isClusterNamespacePosition(h NameResidueHit) bool {
	if !strings.HasPrefix(h.SegRest, "-") {
		return false
	}
	for _, pos := range namespacePositions {
		if strings.HasSuffix(h.LinePrefix, pos) {
			return true
		}
	}
	if strings.HasPrefix(h.SegPre, "system:serviceaccount:") {
		return true
	}
	// DNS-имя Service: `<служба>.<пространство>.svc`. Слева от имени — ярлык и
	// точка, справа внутри сегмента — `.svc`.
	return strings.HasSuffix(h.SegPre, ".") && h.SegPre != "." &&
		strings.Contains(h.SegRest, ".svc")
}

// isTrackerReference — вхождение есть КРАТКАЯ ссылка на задачу трекера вида
// `kacho#2260`. Имя платформы здесь называет РЕПОЗИТОРИЙ, в котором ведётся
// учёт, а не продукт, который себя так зовёт, — поэтому оно и не остаток.
//
// ДИСКРИМИНАТОР СТРУКТУРНЫЙ, А НЕ СЛОВАРНЫЙ, и это несущее. Требуются ОБА
// условия сразу:
//
//  1. токен есть имя платформы ЦЕЛИКОМ — ни приставки, ни продолжения. Всякая
//     форма самоназвания продукта (`kacho-<слово>`, `kacho.cloud`, `kacho_iam`,
//     `PRO-Robotech/kacho`) продолжается ВНУТРИ токена и до правила не доходит
//     by construction;
//  2. сразу за токеном стоит знак номера И ЦИФРА. Знак в токен не входит,
//     поэтому увидеть его можно только справа от токена — отсюда LineRest.
//
// ПОЧЕМУ ГРАНИЦА, А НЕ ЗАПИСЬ ВЕДОМОСТИ. Ведомость решённого остаться ведут
// перечнем «путь + полоса + точное число», и это верно для адъюдикации ПО
// ОДНОМУ. Здесь предмет другой: ссылка на задачу — принятое в дереве написание,
// она появляется в КАЖДОМ новом разборе, и перечень пришлось бы дополнять
// каждым изменением, которое сослалось на задачу. Такая запись не истекает и не
// адъюдицируется — она учитывает форму, а формы учитывают границы.
//
// ЧЕГО ГРАНИЦА НЕ ДЕЛАЕТ — и по какой причине ИМЕННО, а не по правдоподобной.
// Токен длиннее имени она не берёт: `apps/kacho` со знаком номера остаётся на
// полосе имени платформы, потому что условие 1 судит ТОКЕН, а не сегмент пути.
// А вот `PRO-Robotech/kacho` со знаком номера остаётся за границей пути модуля
// фундамента (Б1) по ДРУГОЙ причине — Б1 стоит в перечне правил РАНЬШЕ, и до
// этого правила вхождение не доходит вовсе. Две причины названы врозь
// намеренно: инъекция, подменившая токен сегментом, на форме `PRO-Robotech/…`
// молчит — её держит порядок, а не предикат, — и доказательство, опирающееся
// только на неё, было бы зелёным при сломанном условии 1.
func isTrackerReference(h NameResidueHit) bool {
	if h.Macron || !strings.EqualFold(h.Text, "kacho") {
		return false
	}
	return len(h.LineRest) > 1 && h.LineRest[0] == '#' &&
		h.LineRest[1] >= '0' && h.LineRest[1] <= '9'
}

// contractDomainOf — координата контракта: точечная форма `kacho.cloud.<домен>`
// либо путь `kacho/cloud/<домен>`, а также словарь аннотаций `kacho.iam.<…>`.
func contractDomainOf(h NameResidueHit) (string, bool) {
	if rest, ok := trimAny(h.SegRest, ".cloud.", ".iam."); ok {
		return rest, true
	}
	if h.Seg == "kacho" {
		if rest, ok := trimAny(h.PathRest, "/cloud/", "/iam/"); ok {
			return rest, true
		}
	}
	return "", false
}

// isAccessContractDomain — домен принадлежит контракту ДОСТУПА (пакет службы
// либо словарь её аннотаций авторизации).
func isAccessContractDomain(rest string) bool {
	return hasWordPrefix(rest, "iam") || hasWordPrefix(rest, "authz")
}

// trimAny — если строка начинается с одного из образцов, вернуть остаток.
func trimAny(s string, prefixes ...string) (string, bool) {
	for _, p := range prefixes {
		if strings.HasPrefix(s, p) && len(s) > len(p) {
			return s[len(p):], true
		}
	}
	return "", false
}

// hasWordPrefix — строка начинается словом word, а не более длинным словом с
// таким началом.
func hasWordPrefix(s, word string) bool {
	if !strings.HasPrefix(s, word) {
		return false
	}
	if len(s) == len(word) {
		return true
	}
	c := s[len(word)]
	return !isLowerWordByte(c) && c != '_'
}

// schemaPrefixRest — вхождение есть приставка схемы `kacho_iam`; вернуть, что
// стоит следом.
func schemaPrefixRest(h NameResidueHit) (string, bool) {
	const suffix = "_iam"
	if h.Hit != "kacho" || !strings.HasPrefix(h.SegRest, suffix) {
		return "", false
	}
	return h.SegRest[len(suffix):], true
}

// isProfileDatabaseKey — слева от вхождения стоит РОВНО ключ профиля со своим
// отступом: `  name: ` либо `  database: `. Судится весь отступ, иначе под
// правило попала бы проза, где те же слова стоят посреди предложения.
func isProfileDatabaseKey(prefix string) bool {
	rest := strings.TrimLeft(prefix, " \t-")
	for _, key := range [...]string{"name:", "database:"} {
		if strings.HasPrefix(rest, key) && strings.TrimLeft(rest[len(key):], " ") == "" {
			return true
		}
	}
	return false
}

// isParenthesisedGlobalAccess — ключ глобального блока значений, записанный
// ЗАЩИТНЫМИ СКОБКАМИ: `(((.Values.global).kacho).registry).serviceAud`.
//
// Форма законная и в шаблонах обычная — она не падает, когда промежуточного
// ключа нет, — но для распознавателя она НЕВИДИМА: скобка не входит в токен,
// поэтому токеном оказывается `.kacho` в одиночестве, у него нет ни приставки
// `.Values.`, ни продолжения `.<буква>`, и вхождение уезжало в слепую зону.
//
// Судится ЛЕВЫЙ КОНТЕКСТ СТРОКИ, а не токен, потому что предмет расхождения
// стоит ровно там: `global).` — это то, что скобка оставляет слева от имени.
// Сегментом пути это не выражается by construction.
func isParenthesisedGlobalAccess(h NameResidueHit) bool {
	return strings.HasSuffix(h.LinePrefix, "global).")
}

// isValuesMapKey — имя платформы стоит КЛЮЧОМ карты значений: `  kacho:` своей
// строкой, без приставки и без продолжения внутри сегмента.
//
// Требуются ОБА условия: слева от имени в строке только отступ, справа сразу
// двоеточие и на этом сегмент кончается. Продолжение (`kacho.cloud/component:`)
// правилам выше видно и до этого не доходит; проза, где имя стоит посреди
// предложения перед двоеточием, отсекается требованием пустого отступа.
func isValuesMapKey(h NameResidueHit) bool {
	return h.SegRest == ":" && h.SegPre == "" &&
		strings.TrimSpace(h.LinePrefix) == ""
}

func isLowerWordByte(b byte) bool {
	return (b >= 'a' && b <= 'z') || (b >= '0' && b <= '9')
}

func lowerByte(b byte) byte {
	if b >= 'A' && b <= 'Z' {
		return b + ('a' - 'A')
	}
	return b
}

func isASCIILetter(b byte) bool {
	return (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z')
}

