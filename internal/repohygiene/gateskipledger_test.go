package repohygiene

import (
	"os"
	"path/filepath"
	"testing"
)

// gateSkipRoots — пакеты, чьи пропуски судит ведомость. Это гейты дерева: их
// пропуск неотличим от их успеха, потому что прогон идёт без `-v`.
//
// Перечень выписан, а не выведен, и это названо честно: «пакеты гейтов» — не
// свойство дерева, а решение о том, где сверка стоит своей цены. Расширяя
// область, правь и `--watch` у прогонщика `.github/scripts/go-test-verdict.py` —
// иначе гейт и прогон станут двумя местами об одном предмете.
var gateSkipRoots = []string{"internal/repohygiene"}

// TestGateSkipLedgerEntriesHaveASubject — послабление живёт, пока его есть чем
// исключать.
//
// # Предмет
//
// Ведомость `.github/scripts/gate-skips-allowed.txt` называет причины, при которых
// пропуск гейта дерева законен: предмета нет BY CONSTRUCTION (нет симлинков в ФС,
// нет git, корень не рабочее дерево) либо пустой перечень — цель самоистечения.
// Прогонщик юнитов краснеет на любой ДРУГОЙ причине.
//
// Запись, которой в дереве больше не соответствует ни один вызов, — находка, а не
// «просто больше не нужна»: она унаследует следующую слепую зону, и первый же
// пропуск с похожим началом сообщения окажется прощён без решения.
//
// # Почему разбор, а не поиск по тексту
//
// Причины пропусков объясняются в комментариях — в том числе в комментарии,
// объясняющем этот самый запрет. Поиск по тексту нашёл бы их там и остался бы
// зелёным при снятом вызове. Перепись читает УЗЛЫ вызова.
//
// # Пустая ведомость — цель, а не поломка
//
// Ноль записей означает «законных пропусков у гейтов дерева не осталось». Гейт на
// этом проходит и печатает перепись; падение на достигнутой цели подталкивало бы
// держать запись ради зелёного.
func TestGateSkipLedgerEntriesHaveASubject(t *testing.T) {
	root := repoRoot(t)

	raw, err := os.ReadFile(filepath.Join(root, GateSkipLedgerFile))
	if err != nil {
		t.Fatalf("ведомость законных пропусков не читается (%s): %v — сверять "+
			"пропуски прогона стало бы не с чем, а прогонщик судил бы по "+
			"неизвестному основанию", GateSkipLedgerFile, err)
	}
	entries := ParseGateSkipLedger(string(raw))

	var roots []string
	for _, r := range gateSkipRoots {
		roots = append(roots, filepath.Join(root, r))
	}
	c, err := CollectSkipSites(roots)
	if err != nil {
		t.Fatalf("обход проб гейтов дерева: %v", err)
	}

	t.Logf("осмотрено: пробных файлов %d, вызовов пропуска %d; записей ведомости %d",
		c.FilesRead, len(c.Sites), len(entries))

	if c.FilesRead == 0 {
		t.Fatal("пробных файлов не прочитано ни одного — «ноль находок» здесь " +
			"означало бы «ноль прочитанного»: проверь корни в gateSkipRoots")
	}
	if len(c.Sites) == 0 {
		t.Fatal("вызовов t.Skip не найдено ни одного — предпосылка разбора не " +
			"выполнена: либо форма вызова сменилась, либо обход смотрит не туда. " +
			"Пустая ВЕДОМОСТЬ законна, пустая ПЕРЕПИСЬ — нет")
	}

	for _, f := range AuditGateSkipLedger(entries, c) {
		t.Error(f)
	}
}
