// gateSkipRoots — пакеты, чьи пропуски судит ведомость. Это гейты дерева: их
// пропуск неотличим от их успеха, потому что прогон идёт без `-v`.
//
// Перечень выписан, а не выведен, и это названо честно: «пакеты гейтов» — не
// свойство дерева, а решение о том, где сверка стоит своей цены. Расширяя
// область, правь и `--watch` у прогонщика `.github/scripts/go-test-verdict.py` —
// иначе гейт и прогон станут двумя местами об одном предмете.
var gateSkipRoots = []string{"internal/repohygiene"}

// TestGateSkipLedgerEntriesHaveASubject — послабление живёт, пока его есть чем
// исключать.
//
// # Предмет
//
// Ведомость `.github/scripts/gate-skips-allowed.txt` называет причины, при которых
// пропуск гейта дерева законен. Оснований ДВА, и держатся они разным:
//
//   - предмета нет BY CONSTRUCTION — нет симлинков в ФС, нет git, корень не рабочее
//     дерево; пустой перечень — цель самоистечения. Держится доводом: запускать нечего;
//   - пробу гоняет СВОЙ названный шаг конвейера без `-short`. Предмет есть, но краткий
//     режим его не измеряет: тело пробы выходит из процесса. Держится механизмом —
//     `TestShortGatedPackagesAreEitherSelectedOrCounted` требует, чтобы пакет вне
//     отбора интеграционной джобы назвал свой шаг в `shortGatedRunByOwnCIStep` и чтобы
//     эта строка нашлась в ci.yaml.
//
// Прогонщик юнитов краснеет на любой ДРУГОЙ причине. Отказ ПРЕДПОСЫЛКИ (недостижимый
// ствол, неподнятая зависимость) ни одним из двух оснований не является и остаётся
// красным: от второго его отличает вопрос «назови шаг, который эту пробу исполняет».
//
// Этот гейт судит ОДНО направление — у каждой записи есть предмет. Обратное
// («каждый пропуск объявлен») судит `TestEveryGateSkipIsDeclaredInTheLedger` ниже:
// прогонщик видит только пропуски, которые СЛУЧИЛИСЬ, а тот, чья предпосылка
// сегодня держится, молчит до дня её отказа — и в этот день краснеет не на дефекте
// (#2548).
//
// Запись, которой в дереве больше не соответствует ни один вызов, — находка, а не
// «просто больше не нужна»: она унаследует следующую слепую зону, и первый же
// пропуск с похожим началом сообщения окажется прощён без решения.
//
// # Почему разбор, а не поиск по тексту
//
// Причины пропусков объясняются в комментариях — в том числе в комментарии,
// объясняющем этот самый запрет. Поиск по тексту нашёл бы их там и остался бы
// зелёным при снятом вызове. Перепись читает УЗЛЫ вызова.
//
// # Пустая ведомость — цель, а не поломка
//
// Ноль записей означает «законных пропусков у гейтов дерева не осталось». Гейт на
// этом проходит и печатает перепись; падение на достигнутой цели подталкивало бы
// держать запись ради зелёного.
func TestGateSkipLedgerEntriesHaveASubject(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)

	raw, err := os.ReadFile(filepath.Join(root, GateSkipLedgerFile))
	if err != nil {
		t.Fatalf("ведомость законных пропусков не читается (%s): %v — сверять "+
			"пропуски прогона стало бы не с чем, а прогонщик судил бы по "+
			"неизвестному основанию", GateSkipLedgerFile, err)
	}
	entries := ParseGateSkipLedger(string(raw))

	var roots []string
	for _, r := range gateSkipRoots {
		roots = append(roots, filepath.Join(root, r))
	}
	c, err := CollectSkipSites(roots)
	if err != nil {
		t.Fatalf("обход проб гейтов дерева: %v", err)
	}

	t.Logf("осмотрено: пробных файлов %d, вызовов пропуска %d; записей ведомости %d",
		c.FilesRead, len(c.Sites), len(entries))

	if c.FilesRead == 0 {
		t.Fatal("пробных файлов не прочитано ни одного — «ноль находок» здесь " +
			"означало бы «ноль прочитанного»: проверь корни в gateSkipRoots")
	}
	if len(c.Sites) == 0 {
		t.Fatal("вызовов t.Skip не найдено ни одного — предпосылка разбора не " +
			"выполнена: либо форма вызова сменилась, либо обход смотрит не туда. " +
			"Пустая ВЕДОМОСТЬ законна, пустая ПЕРЕПИСЬ — нет")
	}

	for _, f := range AuditGateSkipLedger(entries, c) {
		t.Error(f)
	}
}

// TestEveryGateSkipIsDeclaredInTheLedger — обратное направление: у каждого
// пропуска есть объявление.
//
// # Предмет — пропуск, который МОЛЧИТ, а не краснеет
//
// Прогонщик юнитов судит пропуски, которые СЛУЧИЛИСЬ. Пропуск, чья предпосылка
// сегодня держится, не случается — и не судится никем. Он ждёт дня, когда
// предпосылка откажет, и в этот день прогон краснеет НЕ НА ДЕФЕКТЕ.
//
// Замер, из которого выведено (#2548): вызовов пропуска у гейтов дерева 13,
// срабатывает при `-short` ОДИН. Двенадцать причин прогонщик не судил ни разу.
//
// Худший случай был среди них: проба ведомости границ фундамента пропускалась при
// ПУСТОЙ ведомости — на достижении цели выноса фундамента. Успех работы уронил бы
// прогон, а корпус требует обратного: проверка, стерегущая перечень послаблений,
// на пустом перечне обязана ПРОХОДИТЬ с переписью, а не падать.
//
// # Пара направлений, а не благословение
//
// Вместе с `TestGateSkipLedgerEntriesHaveASubject` это ЩИПЦЫ: запись без вызова —
// находка там, вызов без записи — находка здесь. Завести пропуск и объявить его
// законным можно только ОДНИМ изменением, где видно и то и другое.
func TestEveryGateSkipIsDeclaredInTheLedger(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)

	raw, err := os.ReadFile(filepath.Join(root, GateSkipLedgerFile))
	if err != nil {
		t.Fatalf("ведомость законных пропусков не читается (%s): %v — судить "+
			"пропуски стало бы не по чему", GateSkipLedgerFile, err)
	}
	entries := ParseGateSkipLedger(string(raw))

	var roots []string
	for _, r := range gateSkipRoots {
		roots = append(roots, filepath.Join(root, r))
	}
	c, err := CollectSkipSites(roots)
	if err != nil {
		t.Fatalf("обход проб гейтов дерева: %v", err)
	}

	findings := AuditGateSkipDeclared(entries, c)
	t.Logf("осмотрено: пробных файлов %d, вызовов пропуска %d (причина разрешена %d, "+
		"не разрешена %d); записей ведомости %d; необъявленных %d",
		c.FilesRead, len(c.Sites)+len(c.Unresolved), len(c.Sites), len(c.Unresolved),
		len(entries), len(findings))

	if c.FilesRead == 0 {
		t.Fatal("пробных файлов не прочитано ни одного — «ноль находок» здесь " +
			"означало бы «ноль прочитанного»: проверь корни в gateSkipRoots")
	}
	if len(c.Sites)+len(c.Unresolved) == 0 {
		t.Fatal("вызовов пропуска не найдено ни одного — предпосылка разбора не " +
			"выполнена: либо форма вызова сменилась, либо обход смотрит не туда. " +
			"Пустая ВЕДОМОСТЬ законна, пустая ПЕРЕПИСЬ — нет")
	}

	for _, f := range findings {
		t.Error(f)
	}
}
