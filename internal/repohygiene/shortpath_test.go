// shortpath_test.go — путь от каталога служб, чтобы координата в отказе гейта
// читалась глазом.
//
// # Откуда он здесь
//
// Помощник приехал из носителя гейта наблюдаемости добора страницы
// (`listscanobservability_test.go`). Предметом того гейта были семь списков с
// пообъектной проверкой прав, и все семь жили в службе доступа: предикат
// `git grep -ln AddBatch` на ревизии до выноса называл девять файлов, из них
// восемь под `services/iam/` и один — сам гейт. Служба вынесена отдельным
// продуктом, циклов добора в дереве ноль, и гейт снят.
//
// Помощник пережил его своим предметом: его зовёт `tokenverifierpolicy_test.go`,
// который со службой доступа не связан.
//
// Файл назван по тому, что он делает, а не по гейту, которого больше нет.
package repohygiene

import "strings"

// short — путь от каталога служб, чтобы координата в отказе читалась.
func short(abs string) string {
	if i := strings.Index(abs, "/services/"); i >= 0 {
		return abs[i+1:]
	}
	return abs
}
