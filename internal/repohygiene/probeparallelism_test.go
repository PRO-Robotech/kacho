// sequentialProbes — ведомость проб гейтов дерева, которые обязаны остаться
// последовательными.
//
// Ведомость самоистекает: запись без пробы и запись на пробу, которая объявила
// себя параллельной, — находки. Причина обязана называть, ЧТО ЛОМАЕТ соседний
// параллельный прогон, а не «так исторически»: без этого запись становится
// местом, куда последовательную пробу вносят незамеченной.
var sequentialProbes = []SequentialProbeAllowance{
	{
		Dir:   "internal/repohygiene/artifactgates",
		Probe: "TestReachabilityCostBelongsToCandidatesNotToTextSize",
		Why: "проба меряет ДЕЛЬТУ пакетного счётчика компиляций шаблонов " +
			"(reachabilityCompiles) вокруг одного вызова. Атомарность счётчика снимает " +
			"гонку данных и НЕ снимает чужой вклад: параллельный сосед, зовущий тот же " +
			"предикат достижимости, попадает в тот же счётчик, и дельта перестаёт " +
			"принадлежать измеряемому вызову. Наблюдалось замером: под `-parallel 4` " +
			"проба даёт 3 и 6 компиляций там, где последовательно даёт 3 и 3, — то есть " +
			"объявляет рост стоимости, которого нет. Предикат снятия записи: счётчик " +
			"перестал быть пакетным (стал принадлежать вызову) — тогда дельта " +
			"измерима при любом соседе",
	},
	{
		Dir:   "internal/repohygiene",
		Probe: "TestEdgeOutOfANewlyDeclaredRootIsJudged",
		Why: "проба ВРЕМЕННО правит пакетную карту корней фундамента (foundationRoots) и " +
			"возвращает её в Cleanup. Пока правка действует, соседние пробы того же пакета " +
			"читают ту же карту: `TestForbiddenEdgeInsideANewRootIsSeen` требует, чтобы " +
			"незнакомый корень класса НЕ получал, и под параллелью видит временно " +
			"объявленный. Наблюдалось прогоном: та же пара под `-parallel 4` даёт красное " +
			"через раз при неизменном дереве. Предикат снятия записи: правка перестала " +
			"быть глобальной (карта приезжает параметром разбора) — тогда соседу нечего " +
			"увидеть",
	},
	{
		Dir:   "internal/repohygiene",
		Probe: "TestDocsNameFormGateInjection",
		Why: "подпробы ВРЕМЕННО правят пакетную ведомость исключений " +
			"(docsNameFormExemptions) и возвращают её в Cleanup. Ту же ведомость читает " +
			"гейт по дереву того же пакета (TestDocsNameFormMatchesTheCodeThatMintsIt) и " +
			"печатает её длину в переписи — под параллелью он судит дерево по чужой " +
			"временной записи. Предикат снятия записи: ведомость приезжает входом разбора " +
			"(как Allow у AuditProbeParallelism), а не берётся из пакетной переменной",
	},
}

func probeParallelismOptions(t *testing.T) ProbeParallelismOptions {
	t.Helper()
	return ProbeParallelismOptions{
		Root:  repoRoot(t),
		Dir:   "internal/repohygiene",
		Allow: sequentialProbes,
	}
}

// TestEveryTreeGateProbeDeclaresItsParallelism — каждая проба пакетов гейтов
// дерева объявляет свой режим: параллельна либо названа в ведомости с причиной.
//
// # Что здесь удерживается
//
// Не скорость сама по себе, а ЗАПАС до предела. `-timeout` отмеряется тестовому
// бинарю, поэтому его исчерпание отнимает вердикт у ВСЕХ проб пакета, включая
// прошедшие: отличить «дерево сломано» от «ранер был занят» становится нечем.
// Запас держится тем, что работа пакета раскладывается по ядрам ранера, а не
// идёт в одно.
//
// # Почему запрет не истекает
//
// Разовая правка закрыла бы сегодняшние пробы и ничего не сказала бы о
// завтрашних: новая проба без объявления снова стоит последовательного времени,
// а прогон остаётся ЗЕЛЁНЫМ — просто медленнее. Заметить это нечем, кроме
// гейта.
func TestEveryTreeGateProbeDeclaresItsParallelism(t *testing.T) {
	t.Parallel()

	findings, census, err := AuditProbeParallelism(probeParallelismOptions(t))
	if err != nil {
		t.Fatalf("разбор проб: %v", err)
	}
	t.Logf("%s; находок %d", census, len(findings))

	// Премиса: «находок ноль» обязано быть отличимо от «прочитано ноль».
	if census.Files == 0 {
		t.Fatal("файлов проб прочитано ноль — обход пуст, вердикт беспредметен")
	}
	if census.Probes == 0 {
		t.Fatal("проб осмотрено ноль — разбор не признал пробой ни одной функции, " +
			"и «все объявили себя параллельными» здесь означало бы «не читал»")
	}
	// Премиса ВТОРОЙ стороны: полоса параллельных обязана быть непустой, иначе
	// гейт зеленел бы на дереве, где ведомость покрывает всё.
	if census.Parallel == 0 {
		t.Fatal("параллельных проб ноль — предмета у гейта нет: он ничего не наблюдает")
	}

	for _, f := range findings {
		t.Errorf("%s", f)
	}
	if len(findings) > 0 {
		t.Log("Замер, из которого выведено требование (одна машина, одна команда, " +
			"`GOMAXPROCS=4 go test ./internal/repohygiene/... -short -count=1 -p 4`): " +
			"до объявления — repohygiene 190.3 с, artifactgates 59.3 с, стена 191.4 с; " +
			"после — 77.9 с, 38.4 с, стена 87.1 с.")
	}

	if len(sequentialProbes) == 0 {
		t.Log("ведомость последовательных пуста — это цель, а не поломка: " +
			"пустая ведомость означает, что каждая проба пакета раскладывается по ядрам")
	}
}

// TestSequentialLedgerReasonsAreSubstantive — причина в ведомости обязана
// называть предмет, а не занимать поле.
//
// Отдельной пробой, а не веткой гейта выше: там предмет — дерево, здесь —
// ведомость, и смешение двух предметов в одном вердикте делает находку
// непрослеживаемой.
func TestSequentialLedgerReasonsAreSubstantive(t *testing.T) {
	t.Parallel()
	const floor = 80
	for _, a := range sequentialProbes {
		if strings.TrimSpace(a.Dir) == "" || strings.TrimSpace(a.Probe) == "" {
			t.Errorf("запись ведомости без координаты: %+v", a)
		}
		if len(strings.TrimSpace(a.Why)) < floor {
			t.Errorf("%s %s: причина короче %d символов (%q) — запись, не называющая, "+
				"ЧТО ломает параллельный сосед, не проверяема и снимается вместе с "+
				"предметом кем угодно", a.Dir, a.Probe, floor, a.Why)
		}
	}
	t.Logf("перепись: записей ведомости %d", len(sequentialProbes))
}
