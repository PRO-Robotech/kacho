// modelcanonpin.go — побайтовое согласие блоков канона модели прав с
// манифестами доменов платформы, судимое В ЭТОМ ДЕРЕВЕ (задача
// PRO-Robotech/kacho#2613).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ: проверка, которую оба дерева называли своей, не исполнялась НИ В ОДНОМ
//
// Сверка имеет две стороны, и обе живы: пять манифестов доменов
// (`services/*/manifest.yaml`) и канон `kaname/cloud/iam/v1/fga_model.fga`.
// Решением владельца (kacho#2616, исход C, 2026-09-13) канон уехал в репозиторий
// службы доступа вместе с её контрактами, а манифесты остались здесь. Исполнитель
// сверки живёт у службы и отказывается вне монорепо (`require_tree`), потому что
// ему не хватает ВТОРОГО ОПЕРАНДА — манифестов платформы; в это дерево он не
// приезжал вовсе.
//
// Замер на ревизии заведения: исполнитель, собранный ИЗ ПИНА и наведённый на это
// дерево, выходил кодом 1 с переписью «манифестов найдено 0 · байт сверено 0» —
// то есть отдавал КРАСНОЕ О ПРОДУКТЕ там, где красного нет, и обход не начинался.
// «Ноль находок» было неотличимо от «ноль прочитанного» в обе стороны сразу.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ЗДЕСЬ НЕТ: ВТОРОЙ РЕАЛИЗАЦИИ РАЗБОРА
//
// Порождение блоков из манифеста и побайтовое сравнение их с каноном ведёт
// РОВНО ОДИН исполнитель — `tools/modelcanoncheck` репозитория
// PRO-Robotech/kaname. Он не переписан и не скопирован: он СОБИРАЕТСЯ ИЗ ПИНА
// `github.com/PRO-Robotech/kaname`, объявленного в go.mod этого дерева, и
// запускается как двоичное. Две реализации одного разбора расходятся молча и
// расходятся там, где обе зелены (#2613 §«ЧЕГО НЕ ДЕЛАТЬ»), поэтому второй здесь
// не заводится.
//
// Пакет `internal/modelrender` службы этому дереву закрыт правилом видимости Go,
// а `tools/modelcanoncheck` — НЕТ: он лежит вне `internal/`, импортирует
// `internal` СВОЕГО модуля законно, и потому собирается отсюда. Это свойство
// проверено сборкой, а не выведено.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ КОРЕНЬ СОБИРАЕТСЯ, И ПОЧЕМУ ЭТО НЕ КОПИЯ ЧУЖОГО ФАЙЛА (ban #20)
//
// Исполнитель принимает ОДИН корень (`-root`) и читает из него оба операнда.
// Дерева, в котором лежат оба, не существует: канон — у службы, манифесты —
// здесь. Поэтому корень собирается ТРАНЗИТНО, на время прогона, в каталоге
// пробы: манифесты берутся ИЗ ИНДЕКСА git этого дерева, канон и манифест самой
// службы — ИЗ ПИНА.
//
// Копией чужого файла это не является, и различие не в словах:
//
//   - в дереве не лежит ни одного файла службы — собранный корень живёт в
//     каталоге прогона и снимается вместе с ним, отслеживаемым не становясь;
//   - ребро ОБЪЯВЛЕНО: корень собирается из того, что называет `go.mod`, и
//     пересобирается заново на каждом прогоне. Расходиться с пином ему нечем
//     by construction — он им и порождён.
//
// Ровно это ban #20 и требует: «нужен предмет — заводится ребро сборки пином
// версии». Копия запрещена потому, что у неё нет ни объявленного ребра, ни
// того, кто её обновит; здесь есть и то и другое.
//
// ─────────────────────────────────────────────────────────────────────────────
// ИСХОДОВ ЧЕТЫРЕ, И ОНИ НЕ СХЛОПЫВАЮТСЯ
//
// Исполнитель различает четыре исхода кодом возврата, и здесь они читаются
// врозь: «расхождение» и «сверять было нечего» означают разное и чинятся разным.
// Схлопывание их в «ненулевой код» вернуло бы ровно тот дефект, ради которого
// заведён этот файл.
//
// Собственно поэтому двоичное СОБИРАЕТСЯ и запускается, а не зовётся через
// `go run`: тот схлопывает код возврата программы в единицу, и VOID стал бы
// неотличим от находки. То же решение и по той же причине принято у обёртки
// самого исполнителя.
package repohygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/PRO-Robotech/corelib/modulemanifest"
)

const (
	// ModelCanonRelToProto — канон модели прав, названный путём ОТНОСИТЕЛЬНО
	// `proto/`. В таком виде координату принимает `internal/contractsource`: он
	// и решает, читается ли корень из этого дерева или из пина.
	ModelCanonRelToProto = "kaname/cloud/iam/v1/fga_model.fga"

	// CanonJudgePackage — пакет исполнителя сверки в модуле службы. Собирается
	// из пина; второй реализации разбора это дереву не заводит.
	CanonJudgePackage = "github.com/PRO-Robotech/kaname/tools/modelcanoncheck"

	// canonJudgeModuleManifestDir — куда в собранном корне кладётся манифест
	// САМОЙ службы, приехавший пином.
	//
	// Каталог намеренно НЕ `services/iam`: модуль исполнитель берёт из
	// разобранной оболочки документа, а не из имени каталога, поэтому путь на
	// вердикт не влияет — а вот столкнуться с каталогом домена платформы он бы
	// мог. Здесь столкновение невыразимо by construction.
	canonJudgeModuleManifestDir = "modules/kaname"
)

// Исходы исполнителя сверки. Значения принадлежат ЕМУ, а не этому файлу:
// здесь они лишь названы словами, чтобы вердикт не читался по голому числу.
const (
	// CanonJudgeOK — сверено всё объявленное, расхождений нет.
	CanonJudgeOK = 0
	// CanonJudgeFinding — расхождение канона с манифестом.
	CanonJudgeFinding = 1
	// CanonJudgeVoid — сверять нечего НИ ДЛЯ ОДНОГО модуля.
	CanonJudgeVoid = 2
	// CanonJudgeNotRun — канона в судимом дереве нет: условие не создано.
	CanonJudgeNotRun = 3
)

// CanonJudgeOutcome — что означает код возврата исполнителя.
//
// Возвращает имя исхода, его смысл для читателя и признак «это зелёное».
// Зелёный ровно один: у «сверять было нечего» и у «проверка не исполнялась»
// предмета нет, и в успех они не засчитываются (`testing.md` §«Чтение
// вердикта»).
func CanonJudgeOutcome(code int) (name, meaning string, green bool) {
	switch code {
	case CanonJudgeOK:
		return "СВЕРЕНО", "блоки канона совпали с порождёнными из манифестов", true
	case CanonJudgeFinding:
		return "НАХОДКА", "канон разошёлся с манифестами платформы", false
	case CanonJudgeVoid:
		return "БЕЗ ПРЕДМЕТА", "сверять было нечего ни для одного модуля — в собранном " +
			"корне не оказалось ни манифестов, ни блоков; это НЕ находка о продукте, " +
			"а поломка сборки корня", false
	case CanonJudgeNotRun:
		return "НЕ ИСПОЛНЯЛАСЬ", "канона в собранном корне нет — условие сверки не создано; " +
			"это НЕ находка о продукте, а поломка сборки корня", false
	default:
		return "НЕИЗВЕСТНЫЙ ИСХОД", "исполнитель вышел кодом, которого его контракт не " +
			"объявляет — вердикта о сверке нет", false
	}
}

// CanonJudgeCensus — объём осмотренного: что легло в собранный корень и что
// исполнитель в нём прочитал.
//
// Величины печатаются ПО КАЖДОЙ ОСИ отдельно. Одно число скрыло бы ровно тот
// случай, ради которого гейт заведён: «манифестов ноль» неотличимо от
// «манифесты прочитаны и блоков в них нет».
type CanonJudgeCensus struct {
	// ManifestsFromTree — манифестов домена, взятых из индекса этого дерева.
	ManifestsFromTree int
	// ManifestFromModule — лёг ли в корень манифест самой службы, приехавший пином.
	ManifestFromModule bool
	// CanonBytes — размер канона, положенного в корень.
	CanonBytes int
	// CanonSrc — откуда канон взят: путь в дереве либо путь в кэше модулей.
	CanonSrc string
	// BlocksCompared / BlocksOwned — блоков сверено из скольких принадлежащих модулям.
	BlocksCompared int
	BlocksOwned    int
	// BytesCompared — сколько байт исполнитель сравнил. Ноль здесь означает, что
	// сверки НЕ БЫЛО, каким бы ни был код возврата.
	BytesCompared int
}

// String — перепись одной строкой.
func (c CanonJudgeCensus) String() string {
	return fmt.Sprintf(
		"манифестов из дерева %d · манифест службы из пина %t · канон %d байт (%s) · "+
			"блоков сверено %d из %d · байт сверено %d",
		c.ManifestsFromTree, c.ManifestFromModule, c.CanonBytes, c.CanonSrc,
		c.BlocksCompared, c.BlocksOwned, c.BytesCompared)
}

// ComposeCanonJudgeRoot — собирает транзитный корень, в котором лежат ОБА
// операнда сверки, и возвращает перепись положенного.
//
// treeManifests — пути манифестов доменов В ЭТОМ ДЕРЕВЕ (абсолютные).
// canonSrc — путь канона: в дереве либо в кэше модулей, решает contractsource.
// moduleManifestSrc — манифест самой службы из пина; пустая строка означает
// «модуль его не везёт», и это НЕ отказ: набор модулей исполнитель знает свой.
//
// ПУСТОЙ НАБОР МАНИФЕСТОВ — ОТКАЗ, а не пустой корень. Обход, которому нечего
// обходить, даёт зелёное по непрочитанному, и отличить его от настоящего
// зелёного нечем — ровно тот дефект, который этот гейт чинит.
func ComposeCanonJudgeRoot(dst string, treeManifests []string, canonSrc, moduleManifestSrc string) (CanonJudgeCensus, error) {
	var c CanonJudgeCensus

	if len(treeManifests) == 0 {
		return c, fmt.Errorf(
			"манифестов домена не передано ни одного: собирать корень не из чего, а " +
				"сверка на пустом корне дала бы зелёное по непрочитанному")
	}
	if canonSrc == "" {
		return c, fmt.Errorf("путь канона пуст — второй операнд сверки не назван")
	}

	canon, err := os.ReadFile(canonSrc) // #nosec G304 -- путь резолвит contractsource
	if err != nil {
		return c, fmt.Errorf("канон не прочитан (%s): %w", canonSrc, err)
	}
	if len(canon) == 0 {
		return c, fmt.Errorf("канон пуст (%s) — сверять не с чем", canonSrc)
	}
	canonDst := filepath.Join(dst, "proto", filepath.FromSlash(ModelCanonRelToProto))
	if err := writeUnder(canonDst, canon); err != nil {
		return c, err
	}
	c.CanonBytes = len(canon)
	c.CanonSrc = canonSrc

	// Каталог назначения выводится из имени каталога ИСХОДНИКА: два манифеста,
	// лежащие в одноимённых каталогах, затёрли бы друг друга молча, и один
	// модуль ушёл бы из-под сверки, не дав ни одной находки.
	seen := make(map[string]string, len(treeManifests))
	for _, src := range treeManifests {
		dir := filepath.Base(filepath.Dir(src))
		if prev, dup := seen[dir]; dup {
			return c, fmt.Errorf(
				"два манифеста претендуют на один каталог собранного корня (%s): %s и %s — "+
					"один из них затёр бы другой, и его модуль ушёл бы из-под сверки молча",
				dir, prev, src)
		}
		seen[dir] = src

		b, err := os.ReadFile(src) // #nosec G304 -- путь из индекса git этого дерева
		if err != nil {
			return c, fmt.Errorf("манифест не прочитан (%s): %w", src, err)
		}
		if err := writeUnder(filepath.Join(dst, "services", dir, modulemanifest.FileName), b); err != nil {
			return c, err
		}
		c.ManifestsFromTree++
	}

	if moduleManifestSrc != "" {
		b, err := os.ReadFile(moduleManifestSrc) // #nosec G304 -- путь в кэше модулей
		if err != nil {
			return c, fmt.Errorf("манифест службы не прочитан (%s): %w", moduleManifestSrc, err)
		}
		p := filepath.Join(dst, filepath.FromSlash(canonJudgeModuleManifestDir), modulemanifest.FileName)
		if err := writeUnder(p, b); err != nil {
			return c, err
		}
		c.ManifestFromModule = true
	}

	return c, nil
}

// writeUnder — записать файл, заведя его каталоги.
//
// Права 0o600 на файл: собранный корень читает только этот прогон, а исходник в
// кэше модулей лежит доступным лишь на чтение — копировать его права значило бы
// получить корень, который не пересобрать поверх.
func writeUnder(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return fmt.Errorf("каталог собранного корня не заведён (%s): %w", filepath.Dir(path), err)
	}
	// #nosec G703 -- path собран ЭТИМ ЖЕ пакетом из временного каталога прогона
	// и координат, объявленных постоянными: ни один его сегмент не приходит из
	// запроса, окружения или содержимого судимых файлов. Каталог порождается на
	// время прогона и снимается вместе с ним.
	if err := os.WriteFile(path, b, 0o600); err != nil {
		return fmt.Errorf("файл собранного корня не записан (%s): %w", path, err)
	}
	return nil
}

// canonJudgeCensusRe — перепись исполнителя. Читаются ДВЕ величины: сколько
// блоков он сверил из скольких и сколько байт сравнил.
var (
	canonJudgeBlocksRe = regexp.MustCompile(`блоков сверено (\d+) из (\d+)`)
	canonJudgeBytesRe  = regexp.MustCompile(`байт сверено (\d+)`)
)

// ParseCanonJudgeCensus — достаёт объём ОСМОТРЕННОГО ИСПОЛНИТЕЛЕМ из его вывода.
//
// ПОЧЕМУ ЭТО ЧИТАЕТСЯ, А НЕ ПРИНИМАЕТСЯ НА ВЕРУ. Код возврата 0 означает «не
// нашёл», а не «прочитал». Исполнитель отдаёт VOID на пустом обходе сам, но
// полагаться на одну только его арифметику значило бы иметь ОДНО утверждение
// там, где нужно два: сколько он прочитал — вопрос к нему, и задать его обязан
// тот, кто его позвал.
//
// НЕРАЗОБРАННАЯ ПЕРЕПИСЬ — ОТКАЗ, а не нули. Формат вывода принадлежит чужому
// репозиторию и может смениться; молчаливые нули тогда прошли бы за «сверять
// было нечего», то есть расхождение формата выдало бы себя за свойство дерева.
func ParseCanonJudgeCensus(out string) (blocksCompared, blocksOwned, bytesCompared int, err error) {
	mb := canonJudgeBlocksRe.FindStringSubmatch(out)
	my := canonJudgeBytesRe.FindStringSubmatch(out)
	if mb == nil || my == nil {
		return 0, 0, 0, fmt.Errorf(
			"перепись исполнителя не разобрана: в его выводе нет величин «блоков сверено N из M» "+
				"и «байт сверено B». Объём осмотренного назвать нечем, поэтому вердикт о сверке "+
				"не выносится — вероятно, сменился формат вывода в модуле службы.\nвывод:\n%s",
			strings.TrimSpace(out))
	}
	blocksCompared, _ = strconv.Atoi(mb[1])
	blocksOwned, _ = strconv.Atoi(mb[2])
	bytesCompared, _ = strconv.Atoi(my[1])
	return blocksCompared, blocksOwned, bytesCompared, nil
}
