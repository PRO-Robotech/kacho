// authzcheckoutage_test.go — гейт: страж прав не вправе схлопывать «спросить не
// удалось» в «не положено».
//
// Предмет, механика разбора и границы — в шапке `authzcheckoutage.go`; здесь они
// не пересказываются, чтобы два места об одном предмете не разошлись.
//
// Способность упасть доказана инъекцией в обе стороны —
// `authzcheckoutage_injection_test.go`.
package repohygiene

import (
	"testing"
)

// TestAuthzCheckOutageIsNotADenial — ни один страж прав в непробном дереве не
// теряет ошибку проверки.
//
// Выведено из #665: `requireQuotaReader` читал ответ как `err == nil && allowed`
// и на любом ином исходе отвечал отказом в правах. Цена не в тянущем величины, а
// на пути мутации — тот же страж стоит на резолве пределов, который зовётся при
// создании ресурса, поэтому мигание хранилища прав давало арендатору
// ТЕРМИНАЛЬНЫЙ отказ вместо повторяемого.
//
// Класс мерился по дереву, а не по диффу, в котором дефект заметили: помимо
// названного в задаче нашлось ещё три места той же формы в трёх разных пакетах.
// «Починили там, где нашли» закрыло бы находку и оставило класс.
func TestAuthzCheckOutageIsNotADenial(t *testing.T) {
	root := repoRoot(t)

	c, err := ScanAuthzCheckOutage(root)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// ПЕРЕПИСЬ — печатается ВСЕГДА. «Ноль находок» обязано быть отличимо от
	// «ноль прочитанного»: без этой строки поломка разбора выглядела бы чистотой.
	t.Logf("осмотрено: файлов %d, вызовов проверки прав распознано %d, находок %d",
		c.FilesRead, len(c.Sites), len(c.Findings))

	// ПРЕДПОСЫЛКА гейта. Он обоснован тем, что в дереве ЕСТЬ стражи прав; если
	// разбор перестал их видеть (переехала подпись, сменилось имя метода), запрет
	// становится беспредметным и молчит по причине, не имеющей отношения к
	// свойству.
	if c.FilesRead == 0 {
		t.Fatal("прочитано ноль файлов — обход беспредметен, вердикт недействителен")
	}
	if len(c.Sites) == 0 {
		t.Fatal("распознано ноль вызовов проверки прав при непустом дереве — " +
			"это поломка разбора, а не чистота: подпись `Check(ctx, subject, relation, object)` " +
			"либо переехала, либо перестала разбираться")
	}

	if len(c.Findings) == 0 {
		return
	}
	for _, f := range c.Findings {
		t.Errorf("%s:%d — %s", f.File, f.Line, f.Why)
	}
	t.Fatalf("стражей, схлопывающих недоступность хранилища прав в отказ: %d.\n"+
		"Отказ говорит «вам нельзя» и повторять его бессмысленно; недоступность не говорит о правах ничего.\n"+
		"Канон ответа — `authzguard.AuthzBackendUnavailable()`; проброс ошибки наверх тоже законен.\n"+
		"Fail-closed при этом не меняется — меняется только код, а код и есть весь сигнал.",
		len(c.Findings))
}
