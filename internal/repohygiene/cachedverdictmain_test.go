// cachedverdictmain_test.go — пакет проверок ДЕРЕВА отказывается работать на прогоне,
// результат которого `go test` положит в кеш.
//
// # Почему страж стоит здесь, а не в каждой проверке
//
// Проверок дерева в этом пакете сотни, и часть из них берёт состав НЕ через
// [treecorpus], а вызовом git напрямую. Страж внутри конструкторов treecorpus
// такую проверку не накрывает: отбор `-run` по одному имени — самый частый
// способ отладки гейта, и именно он давал бы `ok (cached)` над красным деревом.
// TestMain накрывает пакет by construction, включая проверки, которых ещё нет.
//
// Замер 2026-08-25 (единица счёта — тестовая ФУНКЦИЯ, разбор, а не поиск по
// образцу): по дереву проверок дерева 609 в 48 пакетах, из них до конструкторов
// treecorpus доходят 363, а 246 читают состав в обход них. В этом пакете таких
// проверок 401, до treecorpus доходят 280 — то есть 121 проверка осталась бы под
// кешем, будь страж только в конструкторах.
//
// # Цена названа, а не спрятана
//
// Под стражем оказываются и пробы этого пакета, дерева НЕ судящие, — их 588 из
// 989. Их вердикт кешировался бы законно, и плата за стража — их повторное
// исполнение. Она принята сознательно по двум причинам: разделить пробы по этому
// признаку внутри одного пакета нечем (TestMain у тестового бинаря один, а
// рукописный перечень разойдётся с деревом молча), и в санкционированном пути
// платы нет вовсе — цели Makefile и так несут `-count=1`, то есть там не
// кешировалось ничего и до стража.
//
// Кеш при этом НЕ выключен глобально: пакет без проверок дерева кешируется
// по-прежнему — измерено, pkg/ids отвечает `(cached)` и после правки чужого
// каталога.
//
// Разбор класса, замеры и дискриминатор — [treecorpus] (cachedverdict.go).

package repohygiene

import (
	"fmt"
	"os"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

func TestMain(m *testing.M) {
	if msg := treecorpus.CachedVerdictRefusal(); msg != "" {
		fmt.Fprintln(os.Stderr, "internal/repohygiene: "+msg)
		os.Exit(1)
	}
	os.Exit(m.Run())
}
