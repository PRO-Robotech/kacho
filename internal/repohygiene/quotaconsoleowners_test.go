// Витрина квот спрашивает РОВНО тех владельцев, у кого есть что показать
// ПРОЕКТУ.
//
// # Предмет (задача `PRO-Robotech/kacho#1749`)
//
// Комментарий у `QUOTA_OWNERS` объявлял: «Домен, СПИСЫВАЮЩИЙ квоту и не
// названный здесь, — находка… Совпадение множеств держит гейт дерева». Гейта
// НЕ БЫЛО: сосед `TestEveryQuotaChargingOwnerAnswersTheTenantRead` сверяет
// миграции с контрактами и витрины не читает вовсе. То есть правило обещало
// механизм, которого нет, — тот самый класс, который корпус ловит в коде.
//
// # Почему сверяются ВИДЫ-НОСИТЕЛИ ПРОЕКТА, а не «домены, которые списывают»
//
// Правило в прежней редакции было ЛОЖНЫМ КАК СФОРМУЛИРОВАНО, и это измерено:
// `iam` списывает — и в перечне его нет ПРАВИЛЬНО. Из тридцати трёх видов
// каталога у iam девять, и НИ ОДИН не носится проектом: шесть носит аккаунт,
// один — сама личность, два — родительский принципал. Витрина же
// project-scoped: она берёт `projectId` из адреса и подаёт его каждому
// владельцу. Спросить у неё про вид, у которого проекта нет, невозможно
// by construction — не по недосмотру, а потому что вопрос не выражается.
//
// Поэтому мерка — НОСИТЕЛЬ вида, а не факт списания. С ней перечень витрины и
// дерево совпадают в обе стороны, а правило становится истинным.
//
// # Что этот гейт НЕ закрывает, и это названо, а не умолчано
//
// Девять видов iam арендатору в консоли не показывает ни один экран. Один из
// них (`iam.account`, носитель — личность) читаемую поверхность ИМЕЕТ —
// `IdentityQuotaService.List`, `GET /iam/v1/quotas`, — и её не зовёт ни одна
// строка консоли (замер: `grep -rn "iam/v1/quotas" ui-future/` → пусто).
// Остальные восемь носятся аккаунтом либо родительским принципалом, и
// поверхности чтения у них нет вовсе — это предмет КОНТРАКТА, а не витрины.
// Ни то ни другое здесь не судится: гейт про соответствие перечня витрины
// project-видам, и расширять его на чужой предмет значило бы завести проверку,
// которая краснеет на том, чего её адресат починить не может.
//
// # Чем держится способность упасть
//
// Инъекцией в обе стороны, тремя прогонами (`quotaconsoleowners_injection_test.go`):
// контроль · снятая запись витрины · запись без единого project-вида.
func TestQuotaConsoleAsksEveryProjectCarryingOwner(t *testing.T) {
	t.Parallel()

	root := repoRootFor(t)

	limitPath := filepath.Join(root, "services", "iam", "internal", "domain", "limit.go")
	limitSrc, err := os.ReadFile(limitPath) // #nosec G304 -- путь собран из корня репозитория
	require.NoError(t, err, "чтение каталога величин %s", limitPath)

	pagePath := filepath.Join(root, "ui-future", "shared", "src", "pages", "QuotasPage.tsx")
	pageSrc, err := os.ReadFile(pagePath) // #nosec G304 -- путь собран из корня репозитория
	require.NoError(t, err, "чтение витрины квот %s", pagePath)

	findings, cen := repohygiene.AuditQuotaConsoleOwners(string(limitSrc), string(pageSrc))

	// Предпосылки: ноль здесь означает «ноль прочитанного», а не «ноль находок».
	require.NotZero(t, cen.Kinds,
		"в каталоге величин не прочитано НИ ОДНОГО вида — распознаватель ослеп, и "+
			"«расхождения нет» стало бы верно при любом дереве")
	require.NotZero(t, cen.ProjectKinds,
		"видов с носителем ПРОЕКТ прочитано ноль при %d прочитанных: имя носителя "+
			"сменилось, и гейт сверял бы пустое множество с перечнем витрины", cen.Kinds)
	require.NotZero(t, cen.PageOwners,
		"в витрине не прочитано НИ ОДНОЙ записи перечня — сменилась форма объявления "+
			"`QUOTA_OWNERS`, и молчание такого гейта неотличимо от согласия")

	t.Log(cen.String())

	require.Emptyf(t, findings,
		"перечень витрины квот разошёлся с каталогом величин:\n  %s\n\n"+
			"Мерка — НОСИТЕЛЬ вида, а не факт списания: витрина project-scoped, и вид, "+
			"у которого проекта нет, спросить у неё нельзя by construction.\n%s",
		joinFindings(findings), cen.String())
}

func joinFindings(f []string) string {
	out := ""
	for i, s := range f {
		if i > 0 {
			out += "\n  "
		}
		out += s
	}
	return out
}
