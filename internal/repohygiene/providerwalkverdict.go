package repohygiene

// providerwalkverdict.go — три исхода обхода поверхности внешнего поставщика.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Гейт поверхности (providersurface.go) отвечает «находок ноль» тремя разными
// способами, и снаружи они выглядят одинаково:
//
//  1. поверхность НЕПУСТА и в точности равна ведомости — зелёный по делу;
//  2. поверхность ПУСТА и ведомость пуста — цель переезда, отдельный исход;
//  3. гейт НЕ СМОГ ПОСМОТРЕТЬ — словарь путей пуст, обход не дошёл до дерева,
//     разбор потерял исполняемую часть. Молчание здесь не значит ничего.
//
// Пока поверхность жива, третий случай прикрыт вторым продуктом: опустевший
// словарь оставляет ведомость без предмета, и гейт краснеет записями,
// пережившими предмет. Ровно в тот день, когда поверхность снимут и ведомость
// опустеет, это прикрытие исчезнет — и «поверхности нет» станет неотличимо от
// «гейт ослеп» ровно тогда, когда его вердикт важнее всего.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЗНАМЕНАТЕЛЬ СНИМАЕТСЯ ВТОРЫМ ВЫРАЖЕНИЕМ
//
// Порог, выраженный от того же обхода, который он проверяет, подтверждает сам
// себя: `census.Files > 0` истинно ровно тогда, когда обход прочитал хоть
// что-нибудь, и ничего не говорит о том, СКОЛЬКО он был обязан прочитать.
//
// Поэтому у каждой величины знаменателя два производителя, и они разной
// природы:
//
//	состав дерева   первое: индекс git  (`ls-files`) → разбор `go/parser`
//	                второе: КОММИТ git  (`ls-tree HEAD`), разбора не касается
//	литералы        первое: обход синтаксического дерева `ast.Inspect`
//	                второе: ЛЕКСИЧЕСКИЙ проход `go/scanner` по тем же исходникам
//	словарь         первое: длина перечня ProviderSurfaces
//	                второе: сколько его путей распознаватель ДОКАЗАННО находит
//	                        на синтетическом входе (положительный контроль)
//
// Слепые зоны у пар разные, и каждая закрывает чужую. Пара «индекс против
// коммита» ловит усечённый обход (обход прочитал меньше, чем лежит в коммите) и
// работу, оставленную в индексе, но не ловит одинаково сломанный фильтр у обеих
// сторон. Пара «дерево разбора против лексики» ловит разбор, потерявший
// исполняемую часть, но читает тот же набор исходников и усечения набора не
// видит. Пара про словарь не зависит от дерева вовсе: она судит СПОСОБНОСТЬ
// распознавателя находить, а не состояние продукта.
//
// Расхождение внутри любой пары — находка, а не повод выбрать большее число.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА НАЗВАНА ВСЛУХ
//
// Состав дерева берётся у git, а СОДЕРЖИМОЕ файлов — с диска. Правка, лежащая в
// рабочем каталоге и не закоммиченная, меняет содержимое, но не число файлов, и
// такой обход здесь считается состоявшимся. Пара чисел ловит появление и
// исчезновение файла, а не редактирование существующего.

import (
	"fmt"
	"go/scanner"
	"go/token"
	"sort"
	"strconv"
)

// Исходы обхода. Названы константами, чтобы проба утверждала ИСХОД, а не
// подстроку напечатанного текста.
const (
	// ProviderOutcomeBounded — поверхность есть, и она судится ведомостью.
	ProviderOutcomeBounded = "поверхность есть и ограничена ведомостью"
	// ProviderOutcomeNoSurface — поверхности нет и ведомость пуста. Зелёный,
	// но ОТДЕЛЬНЫЙ: он законен только при доказанном знаменателе обхода.
	ProviderOutcomeNoSurface = "поверхности нет"
	// ProviderOutcomeBlind — обход не состоялся. Молчание гейта здесь ничего не
	// утверждает, и вердикта у него нет.
	ProviderOutcomeBlind = "обход не состоялся"
)

// ProviderWalkDenominator — знаменатель обхода, снятый ВТОРЫМ выражением.
//
// Каждое поле приходит из источника, независимого от того обхода, который оно
// проверяет (разбор пар — в шапке файла).
type ProviderWalkDenominator struct {
	// CommitGoFiles — непроверочных файлов Go в КОММИТЕ, без учёта правила
	// игнорирования. Снимается `git ls-tree -r HEAD`, то есть не индексом, из
	// которого гейт берёт свой состав дерева.
	CommitGoFiles int
	// SkippedGoFiles — сколько из них отброшено правилом игнорирования ДО
	// разбора. Считается отдельно, чтобы отброшенное было видно числом, а не
	// растворялось в разнице.
	SkippedGoFiles int
	// LexicalLiterals — строковых литералов по ЛЕКСИЧЕСКОМУ проходу тех же
	// исходников, без синтаксического дерева.
	LexicalLiterals int
	// DictionaryPaths — объявлено путей в словаре поставщика.
	DictionaryPaths int
	// RecogniserReach — сколько путей словаря распознаватель ДОКАЗАННО находит
	// на синтетическом входе. Положительный контроль: без него «находок ноль»
	// не отличимо от «распознаватель ничего не умеет найти».
	RecogniserReach int
}

// ProviderVerdict — исход обхода и, если он не состоялся, причины поимённо.
type ProviderVerdict struct {
	// Outcome — один из трёх исходов выше.
	Outcome string
	// Blind — причины, по которым обход признан несостоявшимся. Собираются ВСЕ:
	// гейт, называющий одну причину, прячет остальные, и чинить его приходится
	// по одной за прогон.
	Blind []string
}

// JudgeProviderWalk — исход обхода по переписи и знаменателю.
//
// Исходов три, и они РАЗНЫЕ: «поверхность есть», «поверхности нет» и «обход не
// состоялся». Первые два — зелёные, но названы по отдельности; третий — красный,
// и у него нет представления на зелёном пути.
//
// Причины слепоты собираются ВСЕ, а не первая: гейт, называющий одну, прячет
// остальные, и чинить его пришлось бы по одной за прогон.
func JudgeProviderWalk(census ProviderCensus, denom ProviderWalkDenominator) ProviderVerdict {
	var blind []string

	// (1) Инструмент. Словарь путей — единственное, чем распознаватель отличает
	// разговор с поставщиком от любой другой строки. Пустой словарь не находит
	// ничего ни на каком дереве, и его молчание не утверждение, а неспособность.
	//
	// Порог здесь не от дерева, и это НАМЕРЕННО: дерево не знает, какой у
	// поставщика API. Словарь — прибор, и прибор не опустевает по мере переезда;
	// опустевают ведомость и сами места разговора.
	if denom.DictionaryPaths == 0 {
		blind = append(blind, "словарь путей поставщика пуст: распознавателю нечем "+
			"отличить разговор с поставщиком от любой другой строки, и «находок ноль» "+
			"здесь значит «искать было нечем»")
	}
	// (2) Способность инструмента находить. Длина перечня ещё не доказывает, что
	// распознаватель его читает: положительный контроль подаёт ему синтетический
	// вход по каждому пути словаря и требует находки.
	if denom.RecogniserReach != denom.DictionaryPaths {
		blind = append(blind, fmt.Sprintf(
			"распознаватель находит %d из %d путей словаря на синтетическом входе: "+
				"молчание на дереве неотличимо от неумения найти",
			denom.RecogniserReach, denom.DictionaryPaths))
	}

	// (3) Состав дерева. Знаменатель снят у КОММИТА, обход шёл по индексу —
	// два разных выражения одного числа, и сходятся они тождеством учёта:
	// прочитано + снято послаблением + отброшено игнорированием = в коммите.
	if denom.CommitGoFiles == 0 {
		blind = append(blind, "в коммите ноль непроверочных файлов Go: "+
			"обход не дошёл до дерева, и спрашивать было не у чего")
	} else if read := census.Files + census.Exempt + denom.SkippedGoFiles; read != denom.CommitGoFiles {
		blind = append(blind, fmt.Sprintf(
			"обход учёл %d файлов Go (прочитано %d, снято послаблением %d, отброшено "+
				"игнорированием %d) при %d в коммите: %s",
			read, census.Files, census.Exempt, denom.SkippedGoFiles, denom.CommitGoFiles,
			walkAccountingHint(read, denom.CommitGoFiles)))
	}
	// (4) Правило игнорирования не имеет права съесть продукт. Перечень
	// игнорирования называет ВСПОМОГАТЕЛЬНЫЕ деревья — документацию, вендоренное
	// чужое, сборочные каталоги, — а продукт лежит вне них. Поэтому отброшенного
	// обязано быть меньше прочитанного; равенство уже означает, что перечень
	// перестал быть вспомогательным.
	if denom.SkippedGoFiles >= census.Files {
		blind = append(blind, fmt.Sprintf(
			"правило игнорирования отбросило %d файлов Go при %d прочитанных: перечень "+
				"игнорирования называет вспомогательные деревья, а продукт лежит вне их — "+
				"отброшенного не может быть не меньше прочитанного",
			denom.SkippedGoFiles, census.Files))
	}

	// (5) Разбор дошёл до исполняемой части. Знаменатель снят ЛЕКСИЧЕСКИМ
	// проходом по тем же исходникам: он не строит синтаксического дерева и потому
	// не разделяет его отказов.
	if census.Literals == 0 {
		blind = append(blind, "осмотрено ноль строковых литералов: разбор не дошёл "+
			"до исполняемой части, а путь поставщика пишется только литералом")
	} else if denom.LexicalLiterals != census.Literals {
		blind = append(blind, fmt.Sprintf(
			"обход синтаксического дерева насчитал %d строковых литералов, лексический "+
				"проход по тем же исходникам — %d: разбор теряет исполняемую часть",
			census.Literals, denom.LexicalLiterals))
	}

	if len(blind) > 0 {
		return ProviderVerdict{Outcome: ProviderOutcomeBlind, Blind: blind}
	}
	// Знаменатель доказан — только теперь пустой результат становится вердиктом.
	if census.Reaches == 0 && census.LedgerEntries == 0 {
		return ProviderVerdict{Outcome: ProviderOutcomeNoSurface}
	}
	return ProviderVerdict{Outcome: ProviderOutcomeBounded}
}

// walkAccountingHint — куда смотреть при расхождении состава дерева. Направление
// расхождения называет разные механизмы, и лечатся они по-разному.
func walkAccountingHint(read, inCommit int) string {
	if read < inCommit {
		return "обход недобрал файлы коммита — он не дошёл до дерева либо оборвался"
	}
	return "обход прочитал больше, чем лежит в коммите — работа осталась в индексе, " +
		"а гейт судит коммит"
}

// MeasureLiteralsLexically — ВТОРОЕ выражение числа строковых литералов: проход
// лексического разборщика по тем же исходникам, без синтаксического дерева.
//
// Ошибка лексического разбора возвращается, а не пропускается молча: файл,
// который не прочитался, превратил бы «литералов столько-то» в «литералов
// столько-то, сколько удалось».
func MeasureLiteralsLexically(
	sources map[string]string, exempt func(path string) bool,
) (files, literals int, err error) {
	names := make([]string, 0, len(sources))
	for name := range sources {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		if exempt != nil && exempt(name) {
			continue
		}
		src := sources[name]
		fset := token.NewFileSet()
		handle := fset.AddFile(name, fset.Base(), len(src))

		var (
			s     scanner.Scanner
			first error
		)
		s.Init(handle, []byte(src), func(pos token.Position, msg string) {
			if first == nil {
				first = fmt.Errorf("лексический разбор %s: %s", pos, msg)
			}
		}, 0)
		for {
			_, tok, _ := s.Scan()
			if tok == token.EOF {
				break
			}
			if tok == token.STRING {
				literals++
			}
		}
		if first != nil {
			return 0, 0, first
		}
		files++
	}
	return files, literals, nil
}

// MeasureRecogniserReach — положительный контроль распознавателя: сколько путей
// переданного словаря он находит на СИНТЕТИЧЕСКОМ входе.
//
// Вход строится здесь, а не берётся из дерева: предмет — способность
// распознавателя находить, а не состояние продукта. Дерево, в котором
// поверхности больше нет, обязано оставлять этот контроль зелёным, иначе гейт
// краснел бы на достижении собственной цели.
//
// Контроль НЕ вакуумен только вместе с требованием непустого словаря: пустой
// перечень даёт ноль найденного при нуле ожидаемого, и это молчание судится
// отдельным правилом вердикта, а не здесь.
func MeasureRecogniserReach(dict []ProviderSurface) (found int, missed []string, err error) {
	for _, s := range dict {
		src := "package providerprobe\n\n" +
			"// Синтетический вход положительного контроля распознавателя.\n" +
			"const providerProbeURL = " +
			strconv.Quote("https://provider.invalid"+s.Path+"?probe=1") + "\n"

		findings, _, ferr := FindProviderSurface(
			map[string]string{"synthetic/providerprobe.go": src}, nil, nil,
		)
		if ferr != nil {
			return 0, nil, fmt.Errorf("синтетический вход для %q: %w", s.Path, ferr)
		}
		hit := false
		for _, f := range findings {
			if f.Surface == s.Path {
				hit = true
				break
			}
		}
		if hit {
			found++
			continue
		}
		missed = append(missed, s.Path)
	}
	return found, missed, nil
}
