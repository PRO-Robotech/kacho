// TestQuotaSurfaceCensusClassifiesEveryCandidate — задача продукта #2135.
//
// Гейт держит ОДНО свойство: у каждого кандидата признака есть названная
// поверхность. Кандидат, которого не относит ни одно правило, — слепая зона
// САМОЙ переписи, и именно она возвращает продукту одно нечитаемое число.
//
// Чего гейт НЕ утверждает — сказано прямо, чтобы его не приняли за более
// сильный:
//
//   - он не требует нуля ни на одной поверхности. Ноль на «A» — это ЦЕЛЬ стадии
//     S4, а проверка, краснеющая на достижении цели, толкает держать предмет
//     ради зелёного;
//   - он не судит, ВЕРНО ли отнесение по существу: это суждение человека, и оно
//     записано в «Why» каждого правила;
//   - он не заменяет предикаты снятия задачи #2117 — они о поверхности «A», и
//     их три.
//
// Что он даёт стадии S4: пару чисел на каждой поверхности СЕГОДНЯ, то есть тот
// самый парный замер «предикат давал не ноль», без которого `DoD S4` п. 1 не
// допускает нулевой вердикт.
func TestQuotaSurfaceCensusClassifiesEveryCandidate(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)

	res, err := runQuotaSurfaceCensus(root)
	require.NoError(t, err)

	require.NotZero(t, res.FilesWalked,
		"обход беспредметен: ни одного отслеживаемого файла подходящего расширения — "+
			"«ноль находок» здесь неотличимо от «ноль прочитанного»")
	require.NotEmpty(t, res.Candidates,
		"обход беспредметен: признак переписи не нашёл ни одного кандидата на %d файлах. "+
			"Либо форма записи предмета сменилась целиком, либо признак сломан — "+
			"в обоих случаях вердикт о поверхностях брать неоткуда", res.FilesWalked)

	t.Log(formatQuotaCensus(res))

	require.True(t, res.OwnSourceSeen,
		"исходник самой переписи (%s) в дереве не найден — исключение осталось без "+
			"предмета. Либо файл переехал (тогда правьте константу тем же изменением), "+
			"либо перепись судит собственное описание наравне с предметом: она несёт "+
			"признаки всех поверхностей сразу и потому отнеслась бы к каждой",
		quotaCensusOwnSource)

	require.Empty(t, res.RulesWithoutHit,
		"правило переписи не совпало НИ С ОДНИМ кандидатом: %s.\n"+
			"Предмет правила исчез — снимите правило ТЕМ ЖЕ изменением, что его предмет. "+
			"Правило, которому нечего относить, есть послабление без ответственного: "+
			"следующий читатель унаследует его как описание действительности",
		strings.Join(res.RulesWithoutHit, "; "))

	require.Empty(t, res.Unclassified,
		"кандидат признака не отнесён ни к одной поверхности:\n  %s\n\n"+
			"Это слепая зона переписи, а не файла. Пока она есть, число кандидатов "+
			"читается как «столько-то мест под снос», и берущий работу снесёт лишнее "+
			"либо не снесёт нужное — ровно предмет задачи #2135.\n"+
			"Чинится ПОЛОЖИТЕЛЬНЫМ правилом в quotaCensusRules с названной причиной, "+
			"а не корзиной «прочее»: корзина возвращает то же одно число под другим именем",
		strings.Join(res.Unclassified, "\n  "))
}

// formatQuotaCensus — перепись. Печатает ПАРУ чисел на каждой поверхности
// (осмотрено и найдено) и вердикт по каждой: чем «найдено» является.
//
// Осмотренное у всех поверхностей одно и то же — это не небрежность, а форма,
// которую требует `DoD S4` п. 1: без знаменателя ноль в числителе неотличим от
// ноля на мёртвой координате.
func formatQuotaCensus(res *quotaCensusResult) string {
	var b strings.Builder
	fmt.Fprintf(&b, "перепись поверхностей слова «квота»\n")
	fmt.Fprintf(&b, "  файлов дерева осмотрено:            %d\n", res.FilesWalked)
	fmt.Fprintf(&b, "  кандидатов признака ПЕРЕПИСИ:       %d\n", len(res.Candidates))
	fmt.Fprintf(&b, "  из них видит признак задачи #2135:  %d (разница %d — слепая зона признака задачи)\n",
		res.TaskCandidates, len(res.Candidates)-res.TaskCandidates)
	fmt.Fprintf(&b, "\n  поверхность | осмотрено | найдено | найдено как ГЛАВНАЯ | вердикт\n")

	for _, code := range quotaCensusOrder {
		fmt.Fprintf(&b, "  %-11s | %9d | %7d | %19d | %s\n",
			code, len(res.Candidates), res.PerSurface[code], res.PerPrimary[code],
			quotaSurfaceVerdict[code])
	}

	fmt.Fprintf(&b, "\n  членство МНОЖЕСТВЕННОЕ: файл, называющий и авторитет, и учёт, стоит в обоих.\n")
	fmt.Fprintf(&b, "  «главная» — разбиение по объявленному порядку, и только оно складывается в кандидатов.\n")

	codes := make([]string, 0, len(res.PerPrimary))
	for k := range res.PerPrimary {
		codes = append(codes, k)
	}
	sort.Strings(codes)
	sum := 0
	for _, k := range codes {
		sum += res.PerPrimary[k]
	}
	fmt.Fprintf(&b, "  сумма главных: %d; кандидатов: %d; не отнесено: %d\n",
		sum, len(res.Candidates), len(res.Unclassified))
	return b.String()
}
