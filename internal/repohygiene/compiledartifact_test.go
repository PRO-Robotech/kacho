// compiledartifact_test.go — в дереве нет СКОМПИЛИРОВАННЫХ артефактов.
//
// # Предмет
//
// Артефакт сборки называется по каталогу пакета `main`, поэтому попадает в
// корень репозитория с именем обычного файла без расширения — `go build ./путь/`
// без `-o` кладёт его именно туда, а `git add -A` подметает следом. Дальше он
// живёт как исходник: тридцать семь мегабайт в ПУБЛИЧНОМ репозитории, невидимые
// глазу правки внутри и расхождение с тем исходником, из которого собран.
//
// # Почему по магии, а не по имени
//
// Защита от этого класса уже существовала — перечнем имён в объявлении
// игнорируемого. Перечень покрывал имена одного вида и не покрыл имя края, и
// класс воспроизвёлся. Рукописный перечень имён расходится с деревом при первом
// новом сервисе, и расходится молча; первые байты файла не расходятся ни с чем.
//
// # Что гейт НЕ ловит
//
// Он судит СОДЕРЖИМОЕ отслеживаемых файлов, а не намерение. Артефакт, лежащий в
// рабочем каталоге и не добавленный в индекс, ему невидим — и правильно: он
// ничей не предмет, пока не отслеживается. Предмет здесь один: артефакт,
// ставший частью истории.
package repohygiene

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// compiledArtifactCensusFloor — порог переписи: ниже него «находок нет» означает
// «ничего не прочитано».
const compiledArtifactCensusFloor = 1000

func TestNoCompiledArtifactIsTracked(t *testing.T) {
	root := repoRoot(t)
	tt := newTrackedTree(t, root)

	var (
		inspected  int
		unreadable int
		findings   []string
		byKind     = map[compiledArtifactKind]int{}
	)
	for rel := range tt.files {
		f, err := os.Open(filepath.Join(root, filepath.FromSlash(rel))) // #nosec G304 -- путь из индекса git этого дерева, не из ввода
		if err != nil {
			// Файл в индексе, но не на диске: разреженная выкладка либо
			// удаление, ещё не закоммиченное. Не находка, но и не молчание —
			// считается отдельно.
			unreadable++
			continue
		}
		head := make([]byte, compiledArtifactMagicLen)
		n, _ := f.Read(head)
		_ = f.Close()
		inspected++
		if kind := classifyCompiledArtifact(head[:n]); kind != kindNone {
			byKind[kind]++
			findings = append(findings, rel+" — "+string(kind))
		}
	}
	sort.Strings(findings)

	t.Logf("перепись: отслеживаемых файлов %d, прочитано %d, недоступно на диске %d, "+
		"находок %d", len(tt.files), inspected, unreadable, len(findings))

	if inspected < compiledArtifactCensusFloor {
		t.Fatalf("перепись обвалилась: прочитано %d файлов при пороге %d — «находок нет» "+
			"на таком объёме означало бы «ноль прочитанного», а не чистое дерево",
			inspected, compiledArtifactCensusFloor)
	}

	if len(findings) > 0 {
		t.Fatalf("скомпилированные артефакты в дереве — %d:\n  %s\n\n"+
			"Артефакт сборки не коммитится: он производное от исходника, весит мегабайты в "+
			"ПУБЛИЧНОМ репозитории и расходится с тем исходником, из которого собран, никак "+
			"этого не показывая.\n"+
			"Как он сюда попадает: `go build ./<путь>/` БЕЗ `-o` кладёт бинарь в текущий "+
			"каталог под именем каталога пакета, а `git add -A` подметает его следом.\n"+
			"Исходы: снять из индекса и собирать через `-o` во временный каталог; "+
			"объявление игнорируемого — подпорка, а не защита: оно перечисляет ИМЕНА и "+
			"расходится с деревом при первом новом имени.",
			len(findings), strings.Join(findings, "\n  "))
	}
}
