// Совет в комментарии контракта обязан называть ОБЪЯВЛЕННЫЙ глагол.
//
// ПРЕДМЕТ и границы — в шапке `contractadvice.go`; здесь они не пересказываются,
// иначе заведутся два места об одном предмете.
//
// ЧЕГО ЭТОТ ГЕЙТ НЕ СУДИТ, названо, чтобы его не расширили молча:
//   - упоминание глагола ВНЕ совета (надгробие снятого, разбор чужого отказа,
//     описание того, кто заполняет поле) — предмет здесь именно рекомендация;
//   - существование маршрута на крае: глагол объявлен — значит совет исполним
//     на своём слушателе. Публикацию наружу судит ban #6 и свои гейты;
//   - правдивость совета по существу («точно ли ЭТОТ глагол решает задачу»).
//     Это суждение, а не предикат.
//
// ВЕДОМОСТИ ПОСЛАБЛЕНИЙ У ГЕЙТА НЕТ, и это решение, а не упущение — но НЕ по
// той причине, по которой её здесь не было раньше. Прежняя редакция этой шапки
// обосновывала отсутствие ведомости словами «предмета сегодня нет — дерево гейт
// проходит». Замер опроверг обе половины: на стволе гейт находит ДВА живых
// совета, называющих необъявленный глагол, и дерево его НЕ проходит. Утверждение
// было заявлением шире сделанного ровно в том файле, который этот класс и ловит.
//
// Ведомости нет потому, что оба предмета — живые дефекты контракта с
// владельцами, а не слепые зоны гейта:
//
//   - `user_service.proto` («Revoke the invitation instead») — задача #1442,
//     починена в накопительной линии, на стволе жива. Предикат снятия: вливание
//     линии в ствол;
//   - `project_service.proto` («use ProjectService.Move») — найдено ЭТИМ гейтом
//     и на момент записи не заведено задачей; соседний контракт того же ресурса
//     (`project.proto`) прямо говорит «НЕТ ProjectService.Move RPC», то есть
//     дерево противоречит само себе, и верна та половина, что отрицает глагол.
//
// Прощать их записью значило бы гасить единственный сигнал о них: ведомость
// сделала бы гейт зелёным над двумя дефектами, которые он для того и заведён
// находить. Понадобится послабление под предмет иного рода — заводится вместе
// со своим номером задачи и своей проверкой самоистечения (`testing.md` §«Гейт
// на класс», п.5).
func TestContractAdviceNamesADeclaredVerb(t *testing.T) {
	root := repoRoot(t)

	sources, err := loadContractAdviceSources(root)
	if err != nil {
		t.Fatalf("обход контрактов: %v", err)
	}
	c := auditContractAdvice(sources)

	t.Logf("контрактов прочитано: %d (свои, по объявленному пакету); чужих, не "+
		"судимых как не наше обещание: %d %v",
		c.Files, len(c.Foreign), c.Foreign)
	t.Logf("служб объявлено: %d; глаголов объявлено (уникальных имён): %d",
		c.Services, c.Verbs)
	// ОБЕ величины по оси текста, а не одна: «предложений осмотрено» без «из них
	// советов» скрывает ровно тот случай, ради которого ось заведена, —
	// распознаватель ослеп, а находок ноль.
	t.Logf("блоков комментариев осмотрено: %d; предложений: %d; из них советов: %d",
		c.Blocks, c.Sentences, c.AdviceSentences)
	// ОБЕ величины по оси имени: «советов» без «глаголов проверено» не отличает
	// совет, назвавший глагол, от совета, назвавшего поле или код отказа.
	t.Logf("глаголов проверено: %d; по формам совета: %s; по формам имени: %s",
		c.Checked, adviceFormat(c.ByForm), adviceFormat(c.ByShape))
	// Допущение «советуемый глагол обязан быть в ТОЙ ЖЕ службе» здесь не
	// делается, и это печатается замером, а не объявляется словами: совет вправе
	// указать на соседа, назвав его службу, и такие советы в дереве есть.
	t.Logf("из них советов на глагол СОСЕДА (служба названа явно и глагол "+
		"объявляет): %d", c.CrossService)

	// Форма, не сработавшая ни разу, названа вслух: расширение распознавателя,
	// не меняющее осмотренного, — холостое, и его снимают, а не оставляют «на
	// всякий случай» (`testing.md` §«Гейт на класс», п.7). Это НЕ отказ: форму
	// держит своя инъекция, и дерево вправе сегодня её не использовать.
	var idle []string
	for _, f := range adviceForms {
		if c.ByForm[f.Name] == 0 {
			idle = append(idle, f.Name)
		}
	}
	if c.ByForm["F2-en-instead"] == 0 {
		idle = append(idle, "F2-en-instead")
	}
	sort.Strings(idle)
	if len(idle) > 0 {
		t.Logf("формы совета, не сработавшие в дереве ни разу: %v — каждая держится "+
			"своей инъекцией; если форма простаивает и дальше, её снимают", idle)
	}

	// ПРЕДПОСЫЛКИ. «Ноль находок» обязано быть отличимо от «ноль прочитанного»:
	// каждая ступень обхода утверждается отдельно, потому что обрыв на любой из
	// них даёт зелёное, ничего не проверив.
	if c.Files == 0 {
		t.Fatal("прочитано ноль своих контрактов — обход пуст, вердикт беспредметен")
	}
	if c.Services == 0 || c.Verbs == 0 {
		t.Fatalf("в контрактах не найдено ни одной службы (%d) либо ни одного "+
			"глагола (%d) — сверять совет не с чем, и молчание здесь означало бы "+
			"«проверено», а не «чисто»", c.Services, c.Verbs)
	}
	if c.Blocks == 0 || c.Sentences == 0 {
		t.Fatalf("комментариев контрактов прочитано ноль (блоков %d, предложений "+
			"%d) — предмет гейта не читался вовсе", c.Blocks, c.Sentences)
	}
	// Предпосылка распознавателя: дерево советы ПИШЕТ. Ноль советов на семи
	// тысячах предложений означает ослепший распознаватель гораздо вероятнее,
	// чем корпус, из которого исчезли все рекомендации. Читать это надо так:
	// либо формы совета перестали совпадать с тем, как их пишут, либо предмет и
	// вправду исчез — и тогда гейт снимается ВМЕСТЕ с ним, а не остаётся молчать
	// (`testing.md` §«Гейт на класс», п.9).
	if c.AdviceSentences == 0 {
		t.Fatal("не распознано ни одного совета при непустом корпусе комментариев — " +
			"распознаватель ослеп либо предмет исчез; молчание в обоих случаях " +
			"неотличимо от исправной работы")
	}
	if c.Checked == 0 {
		t.Fatalf("советы распознаны (%d), а имён глаголов в них не извлечено ни "+
			"одного — оборвана вторая половина цепочки, и вердикт беспредметен",
			c.AdviceSentences)
	}

	if len(c.Findings) == 0 {
		return
	}
	var b strings.Builder
	b.WriteString("совет в комментарии контракта называет глагол, которого нет там, " +
		"куда пойдёт вызывающий:\n")
	for _, f := range c.Findings {
		b.WriteString("  " + f.Describe() + "\n")
	}
	b.WriteString("\nИСХОДА ТРИ, четвёртого нет: назвать глагол, который в этой службе " +
		"ОБЪЯВЛЕН; написать имя через службу-владельца (`GroupService.ListMembers`) — " +
		"совет вправе указывать на соседа, когда владелец назван; либо сказать ИСХОД " +
		"вместо имени глагола — имя в прозе устаревает молча, а исход переживает " +
		"переименование.")
	t.Fatal(b.String())
}

// adviceFormat — перепись по осям в устойчивом порядке.
func adviceFormat(m map[string]int) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, k+"="+strconv.Itoa(m[k]))
	}
	if len(parts) == 0 {
		return "(пусто)"
	}
	return strings.Join(parts, " ")
}
