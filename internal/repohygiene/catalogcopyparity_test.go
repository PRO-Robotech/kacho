// catalogcopyparity_test.go — гейты шва «две вшитые копии каталога прав обязаны
// сверяться, и сверка обязана исполняться».
//
// Утверждений ЧЕТЫРЕ, и они о РАЗНОМ. Три живут здесь, четвёртое — в соседнем
// файле, потому что читает другое дерево и другим механизмом:
//
//  1. КЛАСС по дереву — ни одна сверка НИ В РЕЦЕПТЕ make, НИ В СКРИПТЕ ШЕЛЛА не
//     исполняется условно по наличию файла. Структурное свойство дерева,
//     читается разбором обеих популяций одними распознавателями.
//  2. ПОВЕДЕНИЕ цели — сверка копий каталога прав на целом дереве проходит.
//     Читается ЗАПУСКОМ, а не прочтением: объявление и исход — разные предметы,
//     и корпус требует судить исход.
//  3. СВЯЗЬ ВНУТРИ Makefile — цель `permission-catalog-check` обязана звать
//     сверку: зависимостью в заголовке правила либо вызовом в рецепте. Читается
//     разбором gateway/Makefile, где заголовок и тело рецепта судятся порознь.
//  4. ПРОВЯЗКА С КОНВЕЙЕРОМ — эту цепочку обязан звать хотя бы один шаг
//     объявленного процесса. Живёт в catalogcheckwiring_test.go (#2084): предмет
//     у неё другой — не Makefile, а .github/workflows, — и механизм тоже другой,
//     общий с гейтами судей services/* (gatetargetwiring.go).
//
// Ни одно не заменяет трёх остальных. Первое зелено при мёртвой цели; второе —
// при цели, которую никто не зовёт; третье — при сверке, которая ничего не
// сверяет; четвёртое — при сверке, вызов которой сняли из конвейера, не тронув
// ни одной строки Makefile.
//
// # Популяции ДВЕ, и перепись печатает их ПОРОЗНЬ (#2086)
//
// Прежняя редакция первого утверждения отбирала из состава дерева только
// `Makefile` и `*.mk`. Скрипты шелла — их в дереве почти два десятка на каждый
// Makefile — не осматривались ни одной строкой, и «обёрнутых сверок ноль»
// означало «в скриптах прочитано ноль».
//
// Одним отбором файлов это не чинится, и причина СТРУКТУРНАЯ. Единица разбора у
// распознавателя — логическая строка: в рецепте make она есть один вызов шелла,
// поэтому обёртка `if [ -f X ]; then diff …; fi` помещается в неё целиком. В
// скрипте `if`, `diff` и `fi` — РАЗНЫЕ строки, и построчный распознаватель не
// видит ни одной из трёх. Гейт, читающий сто семьдесят восемь файлов и не
// видящий того, что объявляет, — ровно «форма без содержания», против которой он
// и написан. Поэтому расширен РАЗБОР (стек ветвлений, состояние цитирования и
// тела heredoc переносятся между строками), а распознаватели остались одни на обе
// популяции.
//
// Перепись печатает популяции ПОРОЗНЬ: одно число скрыло бы ровно тот случай,
// ради которого гейт заводится, — рецепты читаются, скрипты нет, а сумма растёт.
//
// # Здесь стояло ТРИ утверждения, и третье было ШИРЕ своей пробы (#2084)
//
// Прежняя редакция называла третье «цель, которую ЗОВЁТ КОНВЕЙЕР, обязана звать
// сверку». Оборот «которую зовёт конвейер» был ПРЕДПОСЫЛКОЙ, не утверждаемой
// ничем: проба читала только gateway/Makefile и о .github/workflows не
// высказывалась ни строкой. Снятие шага из ci.yaml оставляло её зелёной, а
// сверку — исполнимой и неисполняемой. Четвёртое утверждение заведено ровно на
// этот шов: предпосылка стала предметом, и шапка теперь совпадает с тем, что
// пробы делают.
//
// # Почему сверка вынесена ОТДЕЛЬНОЙ целью
//
// Она не требует ни buf, ни proto-дерева — это сравнение двух закоммиченных
// файлов. Пока она стояла внутри `permission-catalog-check`, её поведение было
// недоступно `go test`: первым же оператором рецепта идёт генерация каталога.
// Отдельная цель делает свойство проверяемым запуском везде, а не только в той
// единственной джобе конвейера, где стоит buf.
package repohygiene

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/treecorpus"
)

// makefilesOfTree — отслеживаемые Makefile и *.mk дерева.
//
// Состав берётся из ИНДЕКСА git, а не с диска: обход диска втянул бы рабочие
// копии агентов и распаковки чартов, и вердикт стал бы свойством рабочего
// каталога, а не коммита.
func makefilesOfTree(t *testing.T, root string) []string {
	t.Helper()
	var out []string
	for _, abs := range trackedTreeFiles(t, root) {
		base := filepath.Base(abs)
		if base == "Makefile" || strings.HasSuffix(base, ".mk") {
			out = append(out, abs)
		}
	}
	return out
}

// shellScriptsOfTree — отслеживаемые скрипты шелла дерева.
//
// Отбор — по свойству файла (расширение ЛИБО шебанг), а не по одному
// расширению: часть скриптов дерева названа без `.sh`, и отбор по расширению
// оставил бы их вне наблюдения молча.
//
// Ведомости исключений здесь нет и быть не должно — в том числе для фикстур под
// `testdata`. Фикстура, несущая обёрнутую сверку, есть такая же находка: гейт
// судит СОСТАВ ДЕРЕВА, а не намерение автора файла.
func shellScriptsOfTree(t *testing.T, root string) []string {
	t.Helper()
	var out []string
	for _, abs := range trackedTreeFiles(t, root) {
		ok, err := isShellScript(abs)
		if err != nil {
			t.Fatalf("вид файла %s не установлен: %v — вердикт беспредметен", abs, err)
		}
		if ok {
			out = append(out, abs)
		}
	}
	return out
}

// trackedTreeFiles — состав дерева по индексу git.
func trackedTreeFiles(t *testing.T, root string) []string {
	t.Helper()
	all, err := treecorpus.Under(root)
	if err != nil {
		t.Fatalf("состав дерева не прочитан: %v — вердикт беспредметен", err)
	}
	return all
}

// TestNoRecipeOrScriptRunsAComparisonOnlyIfAFileExists — КЛАСС: сверка,
// обёрнутая условием существования файла, не сверяет ничего с того дня, как
// файл уедет.
//
// Популяции ДВЕ — рецепты make и скрипты шелла, — и перепись печатает их
// ПОРОЗНЬ. Одно суммарное число скрыло бы ровно тот случай, ради которого гейт
// заводится: одна популяция читается, вторая нет, а сумма при этом растёт.
//
// Предпосылки обхода проверяются у КАЖДОЙ популяции своей парой (непустой состав
// и непустой разбор) и распознаватель — своим положительным контролем на каждой:
// «обёрнутых ноль» обязано быть отличимо от «прочитано ноль» отдельно для
// рецептов и отдельно для скриптов, иначе живая половина покрывает мёртвую.
//
// Что делать, если гейт сработал: снять обёртку и завести на её месте ЯВНЫЙ
// ОТКАЗ, называющий недостающий путь и причину, — по образцу
// `services/iam/Makefile`, цель `sync-permission-catalog`. Обёртку обратно не
// возвращать и ведомость прощённых не заводить: пока условие ложно, цель зелена
// и неотличима от исправной, поэтому у такого послабления нет предиката, по
// которому его снимут.
//
// Форма, у которой ветка «файла нет» НАЗВАНА (`else`/`elif`), находкой не
// является и послаблением не является тоже: предмет гейта — ТИХИЙ пропуск, а
// названный путь тихим не бывает. Эта форма живёт в дереве
// (`gateway/scripts/check-domain-generation.sh`, сверка двух прогонов под
// `if [[ -s A && -s B ]]; then … else finding … fi`), и вменять ей обёртку
// значило бы краснеть на коде, который никто не ломал.
func TestNoRecipeOrScriptRunsAComparisonOnlyIfAFileExists(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)

	// ── ПОПУЛЯЦИЯ 1: РЕЦЕПТЫ make ───────────────────────────────────────────
	makefiles := makefilesOfTree(t, root)
	var (
		found        []guardedComparison
		mkPhysical   int
		mkRecipeRaw  int
		mkLogical    int
		mkComparison int
	)
	for _, abs := range makefiles {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			t.Fatalf("относительный путь для %s: %v", abs, err)
		}
		recipes, perr := parseMakefileRecipes(abs)
		if perr != nil {
			t.Fatalf("рецепты не разобраны: %v — вердикт беспредметен", perr)
		}
		mkPhysical += recipes.PhysicalLines
		mkRecipeRaw += recipes.RecipeLinesRaw
		mkLogical += len(recipes.Lines)
		g, n := findGuardedComparisons(rel, recipes)
		found = append(found, g...)
		mkComparison += n
	}

	// ── ПОПУЛЯЦИЯ 2: СКРИПТЫ ШЕЛЛА ──────────────────────────────────────────
	scripts := shellScriptsOfTree(t, root)
	var (
		shPhysical   int
		shLogical    int
		shHeredoc    int
		shUnclosed   int
		shComparison int
	)
	for _, abs := range scripts {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			t.Fatalf("относительный путь для %s: %v", abs, err)
		}
		src, perr := parseShellSource(abs)
		if perr != nil {
			t.Fatalf("скрипт не разобран: %v — вердикт беспредметен", perr)
		}
		shPhysical += src.PhysicalLines
		shLogical += len(src.Lines)
		shHeredoc += src.HeredocLines
		if src.UnclosedQuote {
			shUnclosed++
		}
		g, n := findGuardedComparisonsInShell(rel, src)
		found = append(found, g...)
		shComparison += n
	}

	// ── ПРЕДПОСЫЛКИ ОБХОДА — ПО КАЖДОЙ ПОПУЛЯЦИИ ОТДЕЛЬНО ───────────────────
	//
	// Пустой обход обязан ронять прогон: иначе «находок ноль» означало бы «ноль
	// прочитанного», и эти два состояния печатались бы одинаково. Отдельно по
	// каждой популяции — потому что живой Makefile прикрыл бы мёртвый обход
	// скриптов, и наоборот.
	if len(makefiles) == 0 {
		t.Fatal("в индексе нет ни одного Makefile — гейт смотрит не туда, его вердикт беспредметен")
	}
	if mkLogical == 0 {
		t.Fatalf("прочитано %d Makefile и ни одной строки рецепта — разбор сломан", len(makefiles))
	}
	if len(scripts) == 0 {
		t.Fatal("в индексе нет ни одного скрипта шелла — отбор смотрит не туда, вердикт беспредметен")
	}
	if shLogical == 0 {
		t.Fatalf("прочитано %d скриптов и ни одной логической строки — разбор шелла сломан", len(scripts))
	}
	// Положительный контроль РАСПОЗНАВАТЕЛЯ, тоже по каждой популяции: сверки
	// есть и там, и там, и гейт обязан их видеть. Ноль сверок означает, что
	// сломалось распознавание команды, а не что дерево чисто, — и тогда
	// молчание гейта не значит ничего.
	if mkComparison == 0 {
		t.Fatalf("ни одной сверки (diff/cmp) не распознано в %d строках рецептов — "+
			"распознаватель команды сломан; «обёрнутых сверок ноль» тогда означает "+
			"«прочитано ноль сверок»", mkLogical)
	}
	if shComparison == 0 {
		t.Fatalf("ни одной сверки (diff/cmp) не распознано в %d логических строках "+
			"скриптов — разбор шелла ослеп; «обёрнутых сверок ноль» тогда означает "+
			"«прочитано ноль сверок»", shLogical)
	}

	// Перепись — ПОРОЗНЬ по популяциям. Незакрытая на конце файла кавычка
	// печатается отдельной величиной, а не прячется: с места сбоя разбор гасит
	// всё подряд, то есть уводит в молчание, и знать объём этого молчания
	// обязан читатель, а не только автор.
	t.Logf("перепись · РЕЦЕПТЫ: Makefile %d · строк файлов %d · строк рецепта %d "+
		"(логических %d) · сверок осмотрено %d",
		len(makefiles), mkPhysical, mkRecipeRaw, mkLogical, mkComparison)
	t.Logf("перепись · СКРИПТЫ: файлов %d · строк файлов %d · логических строк %d · "+
		"погашено телом heredoc %d · файлов с незакрытой кавычкой %d · сверок осмотрено %d",
		len(scripts), shPhysical, shLogical, shHeredoc, shUnclosed, shComparison)
	t.Logf("перепись · ИТОГО: обёрнутых условием %d", len(found))

	if len(found) > 0 {
		var lines []string
		for _, g := range found {
			where := g.File + ":" + itoa(g.Line)
			if g.Target != "" {
				where += " (цель " + g.Target + ")"
			}
			lines = append(lines, where+": "+g.Text)
		}
		t.Fatalf("сверок, исполняемых условно по наличию файла: %d. Такая сверка не "+
			"сверяет НИЧЕГО с того дня, как файл перестанет существовать, — и цель "+
			"остаётся зелёной, неотличимой от исправной. Замени условие явным отказом, "+
			"называющим путь и причину:\n  %s", len(found), strings.Join(lines, "\n  "))
	}
}

// ЗДЕСЬ СТОЯЛИ ТРИ УТВЕРЖДЕНИЯ О ЦЕЛИ `permission-catalog-copies-in-sync` —
// СНЯТЫ ВМЕСТЕ СО СВОИМ ПРЕДМЕТОМ.
//
// Цель сверяла ДВЕ вшитые копии каталога прав: у края и у службы доступа. Служба
// вынесена отдельным продуктом, её копия уехала вместе с каталогом, второго
// операнда в дереве нет, и цель снята (разбор — в шапке `gateway/Makefile`).
// Утверждения о ней сняты тем же изменением, а не оставлены звать несуществующую
// цель: `make` на неизвестной цели выходит кодом 2, и проба, читающая только
// «ненулевой», объявила бы находкой отсутствие предмета.
//
// Снято здесь ТРИ: поведение цели на целом дереве, её вызов зависимостью из
// `permission-catalog-check` и (в catalogcheckwiring_test.go) её вызов
// конвейером.
//
// КЛАСС, ради которого файл заведён, ОСТАЁТСЯ и держится выше:
// TestNoRecipeOrScriptRunsAComparisonOnlyIfAFileExists читает ДЕРЕВО — всякий
// Makefile и всякий скрипт — и требует, чтобы ни одна сверка не исполнялась
// условно по наличию файла. Он не знал этой цели по имени и от её снятия не
// ослеп.
