// Компонент, ОБЪЯВЛЯЮЩИЙ посадочные ручки, обязан довести их до стража, который
// на небезопасном значении ОТКАЗЫВАЕТ.
//
// ПРЕДМЕТ — ban #16 дословно: «Каждый сервис ОБЯЗАН нести production boot-guard
// (`Config.Validate()` fail-closed → refuse-to-start при insecure config)».
//
// ЧЕМ ЭТОТ ГЕЙТ ОТЛИЧАЕТСЯ ОТ СВОЕЙ ПЕРВОЙ РЕДАКЦИИ, И ПОЧЕМУ ЕЁ ПРИШЛОСЬ
// РАЗВЕРНУТЬ. Первая требовала ЛОКАЛЬНОГО стража у каждого сервиса — то есть в
// линии, чья цель централизация, принуждала каждый следующий сервис писать
// своего стража ВДОБАВОК к центральному контракту. Отзывать такое решение
// пришлось бы правкой семи пакетов (ban #18, «перспективность»: ошибка решения
// обязана быть обратимой). Ось развёрнута: судится ДОСТИЖЕНИЕ центрального
// дескриптора — `servicecontract.New(servicecontract.Spec{…})` в композиционном
// корне, чей отказ доезжает до вызывающего и роняет старт ДО подъёма
// слушателей. Локальная `Config.Validate()` остаётся законной как ДОПОЛНЕНИЕ и
// этим гейтом не судится (см. «чего гейт не судит» ниже).
//
// ПОСЫЛКА, ИЗ КОТОРОЙ ВЫРОСЛА ПЕРВАЯ РЕДАКЦИЯ, БЫЛА ЛОЖНОЙ — и это записано
// здесь, чтобы её не восстановили из истории. Её godoc утверждал, что geo
// «объявлял четыре посадочные ручки и не проверял НИ ОДНУ». Замер говорит
// обратное: все четыре подавались в `servicecontract.New`, ошибка дескриптора
// возвращалась наверх и роняла старт. Предикат, повторяемый одной строкой:
//
//	git show 170b08737^:services/geo/cmd/kacho-geo/serve.go | grep -nE 'Mode:|Forwarders|OptIn|DBSSLMode'
//
// Из ложной посылки выросли три следствия, снятые вместе с ней: ВТОРОЙ страж у
// geo, дублировавший центральный по обеим осям своими копиями (`sslmode` —
// свой перечень безопасных значений; круг отправителей — тот же
// `grpcsrv.ForwarderGate` с теми же именами ручек); требование такого стража от
// каждого следующего сервиса; и признание свидетеля ПО ФАЙЛУ вместо тела.
// Третье было проверено опытом: страж, сведённый к раннему `return nil`,
// проходил и этот гейт, и весь набор `internal/repohygiene` (код возврата 0).
//
// ПОЧЕМУ ЦЕНТРАЛЬНЫЙ ДЕСКРИПТОР И ЕСТЬ СТРАЖ. Он отказывает, НАЗЫВАЯ каждую
// незаполненную ось разом, и делает это ОДНИМ перечнем безопасных значений на
// всё дерево. Пока перечень копируется по сервисам, «эту ось здесь забыли»
// неотличимо от «эту ось здесь решили не судить», и расходятся копии молча.
//
// ПОЧЕМУ ГЕЙТ, А НЕ ОБЗОР. Отсутствие стража ничем не проявляется: компонент
// собирается, поднимается, отвечает и печатает красивый самоотчёт. Заметить
// можно только сравнением с соседями — то есть ровно тем действием, которое
// никто не совершает, добавляя восьмой компонент.
//
// ВТОРАЯ ОСЬ ТОГО ЖЕ ГЕЙТА: ЗНАЧЕНИЕ РУЧКИ ОБЯЗАНО ДО СТРАЖА ДОЙТИ. Принять
// дескриптор мало. Компонент может объявить ручку, прочитать её из окружения — и
// подставить в `Spec` ПРАВДОПОДОБНУЮ КОНСТАНТУ; тогда страж доволен всегда,
// ручка не действует никогда, а вызов стоит на месте. Класс найден внешней
// проверкой на живом дереве: подстановка `DBSSLMode: "require"` вместо
// `cfg.DBSSLMode` собирается и первую ось проходит насквозь.
//
// Подделка тиха BY CONSTRUCTION, и это главное в ней: негодная константа
// уронила бы старт громко (дескриптор её отвергает), поэтому подставляют
// ГОДНУЮ. Одной строки в композиционном корне достаточно, и в обзоре она
// выглядит настройкой.
//
// Судится ЗАКРЫТЫЙ перечень посадочных полей (`postureSpecFields`) — тех, чьё
// значение приходит из ручки. `ForwarderKnobs.SANs` и `.TrustAny` в него не
// входят намеренно: это ИМЕНА ручек, они обязаны быть литералами, иначе текст
// отказа не назовёт оператору, что править.
//
// ТРЕТЬЯ ОСЬ: ОТКАЗ ДЕСКРИПТОРА ОБЯЗАН ДОЙТИ ДО ОСТАНОВКИ ПРОЦЕССА. Двух
// предыдущих не хватает, и это измерено, а не предположено. Они спрашивают, где
// СТОИТ вызов дескриптора и что в него ПРИЕХАЛО; ни одна не спрашивает, что
// делают с его ОТКАЗОМ. Между ними живёт форма, гасящая посадку одним символом
// у ВЫЗЫВАЮЩЕГО поставщика:
//
//	desc, _ := describe(cfg, …)   // вместо `desc, err := …; if err != nil {…}`
//
// Замер: подделка собирается, `go vet` молчит, `errcheck` присваивание в `_` по
// умолчанию не судит (`check-blank` в настройках линта не объявлен), а весь
// набор `internal/repohygiene` проходил насквозь (код возврата 0) при
// НЕИЗМЕННОЙ переписи гейта — «доводят до центрального дескриптора: 6» до и
// после. Форма поражала всю популяцию: все шесть провязанных компонентов
// устроены одинаково.
//
// ЕЩЁ ТИШЕ — ГАШЕНИЕ ПРИ СОХРАНЁННОЙ ПРОВЕРКЕ. Там, где `err` объявлен выше по
// телу, после гашения остаётся `if err != nil { return err }`, судящий
// УСТАРЕВШУЮ переменную: код собирается и ВЫГЛЯДИТ проверяющим отказ стража.
//
// НАПРАВЛЕНИЕ ОСТОРОЖНОСТИ ЗДЕСЬ ОБРАТНО ОСИ ПРОВЯЗКИ, и это названо, а не
// подразумевается. Там незнакомая форма уходит в молчание — ложная находка
// отключила бы гейт. Здесь незнакомая форма обработки отказа даёт НАХОДКУ:
// молчание означало бы «посадка проверена», а это неправда, и заметить её
// нечем. Популяция мала (поставщиков единицы), поэтому цена ложной находки —
// одна строка в распознавателе, а цена слепоты — незамеченный обход стража.
//
// ЧЕГО ГЕЙТ НЕ СУДИТ — НАЗВАНО ЦЕЛИКОМ, а не наполовину:
//
//   - НЕ судит локальную `Config.Validate()`: ни её наличия, ни её осей, ни
//     свидетеля отказа для неё. Она — дополнение, и требовать её значило бы
//     вернуть развёрнутую ось;
//   - НЕ судит ПОЛНОТУ набора осей, поданных в `Spec`: компонент, объявивший
//     ось `NotApplicable` с неверной причиной, пройдёт. Полноту держит сам
//     дескриптор — он отказывает на незаполненной оси, — а не эта проверка;
//   - НЕ судит, что значение доехало ВЕРНЫМ: конфигурация может отдать не ту
//     величину, и разбор этого не увидит. Судится СВЯЗЬ — поле выведено из
//     конфигурации, а не назначено на месте;
//   - НЕ судит поле, чьё значение приходит параметром, если ни одного вызова
//     этой функции в компоненте не нашлось. Такое поле идёт в перепись
//     ОТДЕЛЬНОЙ величиной («не судится»), а не в находку и не в провязанные:
//     молчание здесь означало бы «проверено», а это неправда;
//   - НЕ судит край и iam по существу, пока они стоят в ведомости послаблений:
//     их посадку сегодня не судит ничто, кроме их собственных стражей. Это
//     сказано в теле задач #1406 и #1407, а не спрятано. По третьей оси они не
//     судятся ТЕМ ЖЕ САМЫМ: поставщика дескриптора у них нет вовсе;
//   - НЕ судит, что остановка происходит РАНЬШЕ подъёма слушателей. Судится
//     наличие пути «отказ → остановка», а не его место в порядке старта:
//     проверка, стоящая после `Serve`, этой осью будет засчитана;
//   - НЕ считает выходом `return` внутри функционального литерала: он выходит из
//     замыкания, а не из процесса, и засчитывать его значило бы зеленеть на
//     отложенном обработчике;
//   - НЕ судит ОБЛАСТЬ ВИДИМОСТИ проверки: `if err != nil` засчитывается, если
//     стоит по тексту ПОСЛЕ вызова, — хотя бы и в соседнем блоке. Разбор без
//     типов областей не строит, и осторожность здесь в сторону молчания:
//     ложная находка на исправном дереве отключила бы гейт;
//   - НЕ судит вызовы ЭКСПОРТИРОВАННОГО поставщика из чужого модуля: разбор без
//     типов их не видит. Такой поставщик без вызовов внутри компонента идёт в
//     перепись отдельной величиной («не судится»), а не в находку.
//     Неэкспортированный без вызовов — находка: из своего пакета звать его
//     больше неоткуда, значит страж собран и не исполняется;
//   - НЕ запускает ничего. Он читает разобранное дерево, поэтому доказать
//     «дескриптор действительно отказывает» он может только ЧЕРЕЗ СВИДЕТЕЛЯ —
//     пробу пакета контракта. Это второе обязательство ниже.
//
// ГРАНИЦА ОХВАТА НАЗВАНА ЧИСЛОМ, А НЕ СЛОВОМ. Перепись печатает величины
// порознь — осмотрено компонентов · объявляют ручки · доводят до дескриптора ·
// стоят в ведомости; посадочных полей осмотрено · провязано · не судится;
// поставщиков · их вызовов осмотрено · отказ доходит до остановки · не судится.
// ПАРАМИ, а не по одной: одно число скрывает ровно тот случай, ради которого
// каждая ось заведена, — «ноль находок» становится неотличимо от «ноль
// прочитанного». Числа сюда НЕ переписываются: их печатает прогон.
func TestServiceDeclaringPostureKnobsHasABootGuard(t *testing.T) {
	root := repoRoot(t)

	reach, err := scanPostureReach(root)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	v := adjudicatePostureReachFull(reach, postureReachRelaxations)
	for _, note := range v.relaxNotes {
		t.Logf("послабление: %s", note)
	}

	t.Logf("осмотрено компонентов: %d (файлов %d); объявляют посадочные ручки: %d; "+
		"доводят до центрального дескриптора: %d; стоят в ведомости послаблений: %d",
		len(reach.components), reach.filesRead, v.withKnobs, v.reached, v.relaxed)
	// ОБЕ величины по оси провязки, а не одна: «полей осмотрено» без «из них
	// провязано» скрывает ровно тот случай, ради которого ось заведена, —
	// поле на месте, значение подставлено.
	t.Logf("посадочных полей дескриптора осмотрено: %d; получают значение из "+
		"конфигурации: %d; не судится (значение приходит параметром, вызывающих "+
		"в компоненте не нашлось): %d",
		reach.fieldsSeen, reach.fieldsWired, reach.fieldsUnjudged)
	// ОБЕ величины по оси достижения выхода, а не одна: «вызовов осмотрено» без
	// «у скольких отказ доходит до остановки» скрывает ровно тот случай, ради
	// которого ось заведена, — вызов на месте, отказ погашен одним символом.
	t.Logf("поставщиков дескриптора: %d; их вызовов осмотрено: %d; отказ доходит "+
		"до остановки процесса: %d; не судится (экспортированный поставщик без "+
		"вызовов в компоненте): %d",
		reach.providersSeen, reach.callersSeen, reach.callersReach,
		reach.providersUncalled)

	// Предпосылка оси достижения выхода: дескриптор где-то принят, значит
	// поставщик обязан быть найден. Ноль поставщиков при живых принятиях означает
	// ослепший распознаватель, а не исправное дерево, — и молчание тогда
	// утверждало бы «посадка проверена».
	if v.reached > 0 && reach.providersSeen == 0 {
		t.Fatal("предпосылка оси достижения выхода не выполняется: дескриптор " +
			"принимается, а ни одного поставщика не распознано — судьба его отказа " +
			"не установлена ни у одного компонента")
	}
	if reach.providersSeen > 0 && reach.callersSeen == 0 && reach.providersUncalled == 0 {
		t.Fatal("предпосылка оси достижения выхода не выполняется: поставщики " +
			"найдены, а ни одного их вызова не осмотрено — «ноль находок» здесь " +
			"неотличимо от «ноль прочитанного»")
	}

	if v.reached > 0 && reach.fieldsSeen == 0 {
		t.Fatal("предпосылка оси провязки не выполняется: дескриптор принимается, а " +
			"ни одного посадочного поля в его `Spec` не распознано — либо перечень " +
			"полей разошёлся с контрактом, либо распознаватель ослеп; «ноль находок» " +
			"в таком дереве не утверждает ничего")
	}

	if reach.filesRead == 0 {
		t.Fatal("предпосылка гейта не выполняется: обход не прочитал НИ ОДНОГО файла — " +
			"«ноль находок» в таком дереве не утверждает ничего")
	}
	if v.withKnobs == 0 {
		t.Fatal("предпосылка гейта не выполняется: ни один компонент не объявляет " +
			"посадочных ручек — либо имена ручек сменились, либо распознаватель ослеп; " +
			"форма, о которой он не знает, не даёт ни красного, ни зелёного, она молчит")
	}

	if len(v.findings) > 0 {
		t.Fatalf("ban #16 требует, чтобы посадочные ручки доезжали до стража, который "+
			"ОТКАЗЫВАЕТ, и чтобы его отказ ОСТАНАВЛИВАЛ старт:\n  %s\n\n"+
			"Самоотчёт о посадке стражем НЕ является: он сообщает, а не отказывает. "+
			"Процесс с `sslmode=disable` в боевом режиме стартует и честно об этом "+
			"рапортует. Ровно так же не является стражем и тот, чей отказ погашен у "+
			"вызывающего: он собран, исполняется и не может ничего остановить.",
			strings.Join(v.findings, "\n  "))
	}
}

// Центральный дескриптор обязан нести СВИДЕТЕЛЯ ОТКАЗА, и утверждение об ошибке
// обязано стоять НА РЕЗУЛЬТАТЕ ТОГО ЖЕ вызова.
//
// ПОЧЕМУ ЭТО ВТОРАЯ ПОЛОВИНА ПЕРВОГО ГЕЙТА, А НЕ ОТДЕЛЬНЫЙ ПРЕДМЕТ. Гейт выше
// утверждает «ручки доехали до дескриптора». Само по себе это ничего не стоит,
// если дескриптор не отказывает: `New`, сведённый к `return Descriptor{}, nil`,
// прошёл бы его насквозь у всех шести компонентов разом. Раз ось — достижение
// ОДНОГО места, то и свидетель нужен в ОДНОМ месте, а не в семи.
//
// ЧЕМ ЭТО ДОКАЗЫВАЕТ БЕЗОПАСНОСТЬ СНЯТИЯ ЛОКАЛЬНОГО СТРАЖА geo. Тот судил две
// оси — `sslmode` в боевом режиме и круг отправителей, — обе своими копиями
// того, что дескриптор судит сам (`strongSSLModes` и тот же
// `grpcsrv.ForwarderGate` с теми же именами ручек). Гейт требует, чтобы
// свидетель ТРОГАЛ обе оси поимённо: пока это так, снятие копии ничего не
// потеряло, и это держится проверкой, а не памятью о замере.
//
// ЧЕГО ЭТОТ ГЕЙТ НЕ СУДИТ. Он не судит, что свидетель проверяет ВЕРНОЕ
// поведение, — только что утверждение об ошибке связано с результатом вызова.
// Истинность утверждения держит прогон самого пакета, а не чтение.
func TestCentralDescriptorCarriesARefusalWitness(t *testing.T) {
	root := repoRoot(t)
	dir := filepath.Join(root, "pkg", "servicecontract")

	w, err := scanContractRefusalWitness(dir)
	if err != nil {
		t.Fatalf("разбор проб центрального контракта: %v", err)
	}

	t.Logf("осмотрено функций проб: %d; ПРЯМЫХ свидетелей отказа: %d (%s); "+
		"свидетелей по делегации: %d",
		w.funcsRead, len(w.direct), strings.Join(w.direct, ", "), len(w.delegating))

	if w.funcsRead == 0 {
		t.Fatal("предпосылка гейта не выполняется: в пакете центрального контракта не " +
			"прочитано ни одной функции проб — «ноль свидетелей» здесь не утверждает ничего")
	}

	if len(w.direct) == 0 {
		t.Fatal("центральный дескриптор НЕ НЕСЁТ свидетеля отказа: ни в одном теле " +
			"утверждение об ошибке не стоит на результате вызова `servicecontract.New`. " +
			"Без него `New`, сведённый к `return Descriptor{}, nil`, прошёл бы гейт " +
			"достижения насквозь у всех компонентов разом — то есть форма без содержания.")
	}

	// Оси, ради которых снята локальная копия стража geo. Перечень закрыт
	// намеренно: он называет не «все оси Spec», а РОВНО ТЕ, чьё дублирование
	// было снято, — то есть то, что снятие обязано было сохранить.
	var missing []string
	for _, axis := range []string{"DBSSLMode", "Forwarders"} {
		if !w.axes[axis] {
			missing = append(missing, axis)
		}
	}
	if len(missing) > 0 {
		t.Fatalf("свидетель отказа не трогает ось %s — а именно её судила снятая "+
			"локальная копия стража geo. Пока оси нет у свидетеля, снятие копии "+
			"ничем не подпёрто.", strings.Join(missing, ", "))
	}
}
