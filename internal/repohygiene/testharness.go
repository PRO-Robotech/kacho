package repohygiene

import "strings"

// testharness.go — пакеты-харнессы проб: код, который Go считает непроверочным
// (файлы без `_test`), а продукт — нет.
//
// # Зачем такой пакет вообще
//
// Пробы, которые обязаны собираться ОТДЕЛЬНОЙ единицей сборки, но строить ТОТ ЖЕ
// харнесс (приёмка KA1, стадия S2: пробы, чьё «Дано» передаёт сборке параметр,
// которого на базе стадии нет), не могут взять харнесс из `_test.go` соседнего
// каталога: Go такого импорта не допускает. Харнесс становится обычным пакетом —
// и попадает под гейты продуктового дерева (места сборки gRPC-сервера,
// производители отказов края), хотя слушателем продукта не является: его серверы —
// дублёры соседей и пробная поверхность.
//
// # Почему это не исключение по имени
//
// Харнесс признаётся харнессом по СВОЙСТВУ, проверяемому машинно
// (TestHarnessPackagesAreImportedOnlyByTests): его не импортирует ни один
// непроверочный файл дерева. Пакет, который начал импортировать продукт, роняет
// эту проверку — и вместе с ней перестаёт быть вне суда продуктовых гейтов.
// Запись без пакета — тоже находка (исключение пережило свой предмет).

// TestHarnessPackages — каталоги пакетов-харнессов от корня репозитория.
var TestHarnessPackages = []string{
	"gateway/internal/e2e/ka1stand",
}

// IsTestHarnessPath — лежит ли файл (путь от корня) в пакете-харнессе.
func IsTestHarnessPath(rel string) bool {
	for _, p := range TestHarnessPackages {
		if strings.HasPrefix(rel, p+"/") {
			return true
		}
	}
	return false
}
