// outboxorderinggate_test.go — гейт на КЛАСС: у каждой дренируемой очереди
// решение о порядке ПРИНЯТО и ЗАПИСАНО там, где его можно проверить.
//
// # Предмет
//
// Общий дренаж выбирает строки `ORDER BY (attempt_count, id)`. Строка, разок
// не доехавшая по временной причине, получает attempt_count>0 и уезжает в конец
// этого порядка — то есть за свежую строку с attempt_count=0, попадая в ДРУГУЮ
// выборку. Если поток очереди несёт две противоположные половины про одну
// единицу состояния (поставить и снять), их перестановка означает, что снятие
// применяется раньше постановки, а постановка — последней. Итог: снятое
// состояние ВОССТАНАВЛИВАЕТСЯ и больше никем не убирается, потому что событий
// про него в очереди уже нет. Конкурентность применения тут ни при чём: она
// добавляет перестановку и внутри одной выборки, но причина — сам порядок
// выборки, и перестановка происходит при последовательном применении тоже.
//
// Лечится это на уровне ВЫБОРКИ, а не применения: строка не берётся, пока в её
// партиции есть доставляемый предшественник с меньшим идентификатором
// (`drainer.Config.PartitionColumn`). Пересортировка уже выбранной пачки
// бессильна — предшественник лежит в другой пачке. Поведение и границы —
// в godoc того поля; здесь оно не пересказывается.
//
// # Почему гейт, а не «мы это уже починили»
//
// На момент заведения гейта решение принято ВЕРНО во всех восьми проводках
// дерева. Держалось оно при этом НИЧЕМ: измерено инъекцией — снятие ключа
// партиции с проводки vpc оставляет зелёными все пять соседних гейтов очередей,
// собственную пробу vpc про индекс и пакетные тесты его composition root, и
// бинарь собирается. Свойство, которое ничем не удержано, — это не свойство
// дерева, а состояние сегодняшнего дня: девятая очередь, заведённая завтра,
// проезжает молча.
//
// Сервисная проба про свою очередь этого не ловит by construction: пробы
// проверяют НАЛИЧИЕ нужных индексов в схеме, а ключ живёт в Go-проводке, и одно
// от другого не зависит. Место, где видно «сколько очередей дренится и по
// скольким решение о порядке записано», в дереве отсутствовало.
//
// # Что читается
//
// Разбор AST композитных литералов `drainer.Config` в composition root'ах
// (общий инвентарь `outboxWiringInventory`, см. outboxobservedgate_test.go):
// поле `Table` даёт очередь, поле `PartitionColumn` — её ключ порядка. Имя
// таблицы и ключ резолвятся через константы того же сервиса.
//
// # Объявленная слепая зона
//
// Инвентарь обходит `services/*`. Дренаж, поднятый вне этого поддерева, гейту
// невиден — сегодня таких нет (перепись всего индекса git даёт восемь проводок,
// все под `services/`), но невидимость молчаливая, поэтому названа здесь.
// Вторая зона — ключ, заданный выражением, которое разбором не восстановить;
// она НЕ молчаливая: такие координаты гейт печатает отдельной ошибкой.
package repohygiene

import (
	"sort"
	"strings"
	"testing"
)

// commutativeDrainExempt — очереди, поток которых КОММУТАТИВЕН, поэтому ключ
// порядка им не нужен, с указанием ПОЧЕМУ.
//
// Запись обязана объяснять коммутативность по СУЩЕСТВУ применения: какое
// действие производит применение строки и почему ни одно событие потока не
// отменяет предыдущее. «Так исторически» и «ключа не было» обоснованием не
// являются — предмет утверждения в том, что финальное состояние приёмника
// сходится при ЛЮБОМ порядке применения строк одного ключа.
//
// ПРЕДПОСЫЛКА — какие события очередь несёт — здесь НЕ пересказывается: она
// объявлена один раз в declaredQueueEventDictionary и сверяется с БД гейтом
// (outboxeventdictionary_test.go). Пересказ её прозой уже обошёлся дорого: одно
// и то же утверждение о числе видов события лежало в СЕМИ местах дерева и стало
// ложным разом во всех, когда миграция расширила словарь. Перепись радиуса при
// этом дважды объявлялась законченной на пяти — предикат искал фразу, а два
// последних места говорили то же перифразом и цитатой значений (разбор — в
// declaredQueueEventDictionary).
//
// Запись живёт, пока очередь дренится: гейт ниже падает на записи, которой
// больше нечего исключать. А то, что проводка на эту роспись действительно
// ССЫЛАЕТСЯ, а не пересказывает её у настроек, держит
// TestCommutativeDrainWiringDelegatesTheDecision.
