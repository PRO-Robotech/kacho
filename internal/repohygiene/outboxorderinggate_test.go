// outboxorderinggate_test.go — гейт на КЛАСС: у каждой дренируемой очереди
// решение о порядке ПРИНЯТО и ЗАПИСАНО там, где его можно проверить.
//
// # Предмет
//
// Общий дренаж выбирает строки `ORDER BY (attempt_count, id)`. Строка, разок
// не доехавшая по временной причине, получает attempt_count>0 и уезжает в конец
// этого порядка — то есть за свежую строку с attempt_count=0, попадая в ДРУГУЮ
// выборку. Если поток очереди несёт две противоположные половины про одну
// единицу состояния (поставить и снять), их перестановка означает, что снятие
// применяется раньше постановки, а постановка — последней. Итог: снятое
// состояние ВОССТАНАВЛИВАЕТСЯ и больше никем не убирается, потому что событий
// про него в очереди уже нет. Конкурентность применения тут ни при чём: она
// добавляет перестановку и внутри одной выборки, но причина — сам порядок
// выборки, и перестановка происходит при последовательном применении тоже.
//
// Лечится это на уровне ВЫБОРКИ, а не применения: строка не берётся, пока в её
// партиции есть доставляемый предшественник с меньшим идентификатором
// (`drainer.Config.PartitionColumn`). Пересортировка уже выбранной пачки
// бессильна — предшественник лежит в другой пачке. Поведение и границы —
// в godoc того поля; здесь оно не пересказывается.
//
// # Почему гейт, а не «мы это уже починили»
//
// На момент заведения гейта решение принято ВЕРНО во всех восьми проводках
// дерева. Держалось оно при этом НИЧЕМ: измерено инъекцией — снятие ключа
// партиции с проводки vpc оставляет зелёными все пять соседних гейтов очередей,
// собственную пробу vpc про индекс и пакетные тесты его composition root, и
// бинарь собирается. Свойство, которое ничем не удержано, — это не свойство
// дерева, а состояние сегодняшнего дня: девятая очередь, заведённая завтра,
// проезжает молча.
//
// Сервисная проба про свою очередь этого не ловит by construction: пробы
// проверяют НАЛИЧИЕ нужных индексов в схеме, а ключ живёт в Go-проводке, и одно
// от другого не зависит. Место, где видно «сколько очередей дренится и по
// скольким решение о порядке записано», в дереве отсутствовало.
//
// # Что читается
//
// Разбор AST композитных литералов `drainer.Config` в composition root'ах
// (общий инвентарь `outboxWiringInventory`, см. outboxobservedgate_test.go):
// поле `Table` даёт очередь, поле `PartitionColumn` — её ключ порядка. Имя
// таблицы и ключ резолвятся через константы того же сервиса.
//
// # Объявленная слепая зона
//
// Инвентарь обходит `services/*`. Дренаж, поднятый вне этого поддерева, гейту
// невиден — сегодня таких нет (перепись всего индекса git даёт восемь проводок,
// все под `services/`), но невидимость молчаливая, поэтому названа здесь.
// Вторая зона — ключ, заданный выражением, которое разбором не восстановить;
// она НЕ молчаливая: такие координаты гейт печатает отдельной ошибкой.
package repohygiene

import (
	"sort"
	"strings"
	"testing"
)

// commutativeDrainExempt — очереди, поток которых КОММУТАТИВЕН, поэтому ключ
// порядка им не нужен, с указанием ПОЧЕМУ.
//
// Запись обязана объяснять коммутативность по СУЩЕСТВУ применения: какое
// действие производит применение строки и почему ни одно событие потока не
// отменяет предыдущее. «Так исторически» и «ключа не было» обоснованием не
// являются — предмет утверждения в том, что финальное состояние приёмника
// сходится при ЛЮБОМ порядке применения строк одного ключа.
//
// Запись живёт, пока очередь дренится: гейт ниже падает на записи, которой
// больше нечего исключать.
var commutativeDrainExempt = map[string]string{
	"kacho_iam.provider_compensation_outbox": "" +
		"событие ровно одного вида — «снять клиента у провайдера». Второй половины " +
		"нет by construction: ни одно событие потока не ставит клиента обратно, поэтому " +
		"отменять предыдущему нечего. Два снятия одного клиента идемпотентны (провайдер " +
		"отвечает «нет такого», клиент трактует это как исполнено), финальное состояние " +
		"— отсутствие клиента — сходится при любом порядке.",
	"kacho_iam.subject_change_outbox": "" +
		"очередь инвалидаций кэша решений о доступе. Применение строки — сброс записей " +
		"субъекта у шлюза (InternalAuthzCacheService.InvalidateSubject); поля события " +
		"про ресурс шлюзом ИГНОРИРУЮТСЯ, сброс всегда по субъекту целиком. Событие " +
		"ничего не устанавливает, поэтому отменить предыдущее ему нечем: два сброса " +
		"одного субъекта коммутируют и идемпотентны (пустой кэш → «нет записей» → " +
		"строка помечается доставленной). Финальное состояние — отсутствие кэшированных " +
		"записей субъекта — сходится при любом порядке.",
}

// TestEveryDrainedOutboxDeclaresItsOrdering — по каждой дренируемой очереди
// решение о порядке принято: либо задан ключ партиции, либо есть запись о
// коммутативности с обоснованием.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. поток очереди несёт две противоположные половины про одну единицу
//     состояния -> задать `PartitionColumn` (САМЫЙ УЗКИЙ ключ, на котором
//     события не коммутируют) и завести под него частичный индекс
//     `(<ключ>, id) WHERE sent_at IS NULL`;
//  2. поток коммутативен -> завести запись в commutativeDrainExempt, назвав
//     ПО СУЩЕСТВУ, почему ни одно событие не отменяет предыдущее;
//  3. неизвестно -> это исход (1): порядок дешевле, чем воскресшее состояние,
//     и его цена — сериализация внутри одного ключа, а не всей очереди.
//
// Проверено инъекцией в обе стороны: снятие ключа партиции с любой из шести
// упорядоченных проводок красит гейт и печатает имя очереди с координатой
// проводки; две очереди с записью о коммутативности он пропускает молча, как и
// проводку, где ключ задан константой соседнего файла того же сервиса.
func TestEveryDrainedOutboxDeclaresItsOrdering(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	// «Ноль находок» обязано быть отличимо от «ноль прочитанного».
	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root — предпосылка обхода "+
			"сломана, молчание ничего не доказывает (корень %s)", root)
	}
	if len(inv.drained) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ дренируемой очереди в %d прочитанных файлах — "+
			"распознавание сломано (ищется композитный литерал drainer.Config с полем Table)",
			inv.filesRead)
	}

	// Слепая зона, названная вслух: ключ, заданный выражением, которое разбором
	// не восстановить, для гейта неотличим от отсутствующего.
	for _, u := range inv.partitionUnresolved {
		t.Errorf("%s: ключ партиции задан выражением, которое не резолвится разбором "+
			"исходника — гейт не может сверить его ни с чем и молчал бы «чисто». Назови "+
			"ключ строковым литералом или строковой константой того же сервиса.", u)
	}

	drained := sortedKeys(inv.drained)
	ordered, commutative := 0, 0
	for _, table := range drained {
		if inv.partition[table] != "" {
			ordered++
			continue
		}
		commutative++
	}
	t.Logf("прочитано файлов composition root: %d; дренируемых очередей: %d "+
		"(с ключом порядка: %d, объявлено коммутативными: %d)",
		inv.filesRead, len(drained), ordered, commutative)

	for _, table := range drained {
		if inv.partition[table] != "" {
			continue
		}
		why, exempt := commutativeDrainExempt[table]
		if !exempt {
			t.Errorf("очередь %s дренится (%s) БЕЗ ключа порядка и без записи о "+
				"коммутативности: выборка идёт `ORDER BY (attempt_count, id)`, поэтому "+
				"строка, разок не доехавшая по временной причине, уезжает за свежую и "+
				"применяется ПОСЛЕ неё. Если поток несёт постановку и снятие одной "+
				"единицы состояния, снятое восстановится и убрать его будет уже нечем. "+
				"Задай drainer.Config.PartitionColumn (самый узкий ключ, на котором "+
				"события не коммутируют) + частичный индекс (<ключ>, id) WHERE sent_at "+
				"IS NULL, либо заведи запись в commutativeDrainExempt с обоснованием.",
				table, strings.Join(inv.drained[table], ", "))
			continue
		}
		if strings.TrimSpace(why) == "" {
			t.Errorf("запись о коммутативности %s без обоснования: обязана называть, "+
				"какое действие производит применение строки и почему ни одно событие "+
				"потока не отменяет предыдущее", table)
		}
	}
}

// TestCommutativeDrainExemptionsHaveSubject — запись живёт, пока у неё есть
// предмет: очередь, переставшая дрениться или получившая ключ порядка,
// унаследует следующую слепую зону.
func TestCommutativeDrainExemptionsHaveSubject(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root (корень %s)", root)
	}

	for table := range commutativeDrainExempt {
		if _, ok := inv.drained[table]; !ok {
			t.Errorf("запись о коммутативности %s больше не имеет предмета: такой "+
				"дренируемой очереди в дереве нет. Удали запись.", table)
			continue
		}
		if key := inv.partition[table]; key != "" {
			t.Errorf("запись о коммутативности %s больше не имеет предмета: её проводка "+
				"задаёт ключ порядка %q, то есть поток объявлен НЕкоммутативным. Два "+
				"места об одном предмете, из которых верно одно. Удали запись.", table, key)
		}
	}
}

// TestPartitionedOutboxKeyMatchesIndexTier — ключ, по которому очередь
// ВЫБИРАЕТСЯ, и ключ, под который ей строят индекс, — один и тот же.
//
// Это два места об одном предмете: ключ живёт в Go-проводке
// (`drainer.Config.PartitionColumn`), а роспись очередей с ключом партиции —
// в гейте набора индексов (partitionDrainedOutboxes, outboxpendingindexset_test.go),
// откуда берётся ожидаемое имя индекса. Разъехавшись, они дают худший из
// возможных исходов: проверка набора индексов остаётся зелёной, потому что
// сверяет схему с УСТАРЕВШИМ ожиданием, а выборка тем временем просит
// коррелированное анти-соединение по колонке, под которую индекса нет — то есть
// читает всю очередь, которую разгребает.
//
// Сверка идёт по имени таблицы без схемы: одноимённые очереди разных сервисов
// (`fga_register_outbox` живёт в vpc, nlb и storage) обязаны нести ОДИН ключ, и
// расхождение между ними — тоже находка этого гейта.
func TestPartitionedOutboxKeyMatchesIndexTier(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root (корень %s)", root)
	}

	// Проводка → роспись: ключ проводки обязан совпасть с объявленным.
	wired := map[string]string{} // таблица без схемы → ключ из проводки
	for _, table := range sortedKeys(inv.drained) {
		key := inv.partition[table]
		if key == "" {
			continue
		}
		short := unqualify(table)
		if prev, seen := wired[short]; seen && prev != key {
			t.Errorf("очередь %s несёт РАЗНЫЕ ключи порядка в разных сервисах: %q и %q. "+
				"Одноимённые очереди обязаны выбираться одинаково — иначе роспись гейта "+
				"индексов верна ровно для одной из них.", short, prev, key)
		}
		wired[short] = key

		declared, listed := partitionDrainedOutboxes[short]
		if !listed {
			t.Errorf("очередь %s выбирается по ключу %q (%s), но в росписи гейта набора "+
				"индексов её нет: набор её частичных индексов не проверяет никто, а "+
				"выборка просит коррелированное анти-соединение по этой колонке. Добавь "+
				"запись в partitionDrainedOutboxes.", short, key, strings.Join(inv.drained[table], ", "))
			continue
		}
		if declared != key {
			t.Errorf("очередь %s: проводка выбирает по ключу %q (%s), а роспись гейта "+
				"индексов объявляет %q — два места об одном предмете, из которых верно "+
				"одно. Проверка набора индексов при этом ЗЕЛЁНАЯ: она сверяет схему с "+
				"устаревшим ожиданием.", short, key, strings.Join(inv.drained[table], ", "), declared)
		}
	}

	// Роспись → проводка: запись, которой больше нечего проверять.
	missing := make([]string, 0, len(partitionDrainedOutboxes))
	for short := range partitionDrainedOutboxes {
		if _, ok := wired[short]; !ok {
			missing = append(missing, short)
		}
	}
	sort.Strings(missing)
	for _, short := range missing {
		t.Errorf("роспись гейта индексов объявляет очередь %s выбираемой по ключу "+
			"партиции, но ни одна проводка дренажа в дереве этого ключа не задаёт: "+
			"запись пережила свой предмет либо ключ сняли с проводки, оставив индексы.",
			short)
	}

	t.Logf("очередей с ключом порядка в проводках: %d; записей в росписи гейта индексов: %d",
		len(wired), len(partitionDrainedOutboxes))
}
