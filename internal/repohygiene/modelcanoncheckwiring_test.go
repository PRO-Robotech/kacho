// modelcanoncheckwiring_test.go — гейт «побайтовая сверка модели с манифестами
// обязана иметь вызывающего» (задача #1893).
//
// # Что охраняется
//
// Блоки модели доступов сверяет с манифестами модулей ОДИН исполнитель —
// services/iam/tools/modelcanoncheck, поднимаемый целью `model-canon-check`
// (services/iam/Makefile). Сверка ПОБАЙТОВАЯ, и её предмет — право: лишняя
// строка в модели есть лишнее право, недостающая — отказ там, где доступ выдан.
//
// # Почему пробы пакета этого не закрывают
//
// Исполнителя зовёт сегодня ровно один вызывающий — проба
// `TestModelCanonCheckOnTheRealTreeComparesEveryOwnedBlock` в services/iam/tools,
// попадающая в конвейер частью `go test ./... -race -short`. Пока это работает,
// но НИЧТО не удерживает: пропуск под `-short`, отбор пакетов, переименование
// пробы — любое из трёх снимает единственного вызывающего МОЛЧА, и сверка
// перестанет исполняться, оставаясь на вид рабочей. Это тот же класс, что
// предъявлен #1851 её соседу: цель полна, защитима и не исполняется.
//
// # Чем этот гейт НЕ является
//
// Он не сверяет модель с манифестами и не дублирует исполнителя — второй судья
// здесь был бы вторым разборщиком, а сверка объявлена побайтовой именно чтобы не
// измерять согласие двух разборщиков вместо согласия текстов. Его предмет —
// ПРОВЯЗКА: существует ли у цели вызывающий среди того, что исполняется само.
//
// # Почему перечень ВЫВОДИТСЯ, а не выписан
//
// Рукописный перечень расходится с деревом — свойство механизма, а не
// аккуратности автора. Множество «кто объявляет цель» берётся из
// services/*/Makefile, множество «кто её зовёт» — из разобранного YAML конвейера
// и из локального прогонщика, которым отправка ветки проверяется хуком. Сверка
// идёт в ОБЕ стороны: вызов цели, которой в Makefile нет, — такая же находка,
// потому что шаг молча позеленел бы на несуществующей цели.
//
// Механизм общий с гейтом соседа и живёт в gatetargetwiring.go: имя цели —
// параметр обхода, а не его свойство. Вторая копия обхода расходилась бы с
// первой молча и расходилась бы там, где обе зелены.
package repohygiene

import (
	"testing"
)

// modelCanonCheckTarget — цель, поднимающая исполнителя побайтовой сверки.
const modelCanonCheckTarget = "model-canon-check"

// TestModelCanonCheckTargetHasACaller — у судьи побайтовой сверки обязан быть
// вызывающий среди того, что исполняется само.
//
// Что делать, если гейт сработал: провязать цель `model-canon-check` шагом
// конвейера и группой локального прогонщика, читая её код возврата ЧЕТЫРЬМЯ
// исходами (0 сверено · 1 находка · 2 сверять нечего · 3 не исполнялась). VOID
// не схлопывать ни в успех, ни в отказ: в успех — пустое дерево отчитывалось бы
// зелёным так же уверенно, как сверенное; в отказ — прогон, красный по
// построению, перестают читать на третий день. Заводить второго судью взамен
// провязки нельзя: сверка побайтовая именно затем, чтобы не измерять согласие
// двух разборщиков.
func TestModelCanonCheckTargetHasACaller(t *testing.T) {
	root := repoRoot(t)
	w, err := readJudgeTargetWiring(root, modelCanonCheckTarget)
	if err != nil {
		t.Fatalf("провязка не прочитана: %v — вердикт беспредметен", err)
	}

	// Предпосылки обхода: пустой обход обязан ронять прогон, иначе «находок
	// ноль» означало бы «прочитано ноль».
	if w.MakefilesRead == 0 {
		t.Fatal("не прочитано ни одного services/*/Makefile — гейт смотрит не туда, его вердикт беспредметен")
	}
	if w.WorkflowsRead == 0 {
		t.Fatal("не прочитано ни одного файла .github/workflows — гейт смотрит не туда")
	}
	if w.WorkflowStepsRead == 0 {
		t.Fatal("ни в одном файле конвейера не найдено шага с телом `run:` — разбор сломан, " +
			"и «вызова нет» означало бы «не прочитано ничего»")
	}
	if w.LocalRunnersRead == 0 {
		t.Fatalf("не прочитан %s — гейт смотрит не туда", localRunnerRel)
	}
	// Положительный контроль: цель обязана быть НАЙДЕНА объявленной. Ноль
	// объявляющих означает, что распознавание сломалось либо цель сняли, и тогда
	// «провязка в порядке» — не свойство дерева, а слепота гейта.
	if len(w.Declaring) == 0 {
		t.Fatalf("ни один из %d прочитанных Makefile не объявляет цель %s — распознавание сломано "+
			"либо цель сняли; в обоих случаях молчание про провязку ничего не значит",
			w.MakefilesRead, modelCanonCheckTarget)
	}

	for _, f := range findJudgeTargetWiringFaults(w) {
		t.Errorf("%s", f)
	}

	t.Log(judgeTargetWiringCensus(w))
}
