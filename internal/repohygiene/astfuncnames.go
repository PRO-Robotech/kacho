// astfuncnames.go — два общих помощника разбора: плоское имя типа и
// «Тип.Метод» объявления функции.
//
// # Откуда они здесь
//
// Оба приехали из носителя гейта однократности допуска утверждения клиента
// (`assertionadmissioncalls.go`). Предметом того гейта был файл хранилища
// службы доступа, и вместе со службой он ушёл в отдельный продукт — гейт снят.
// Помощники пережили его СВОИМ предметом: их зовут четыре чужих гейта
// Сейчас вызывающий ОДИН: `renderTypeExpr` зовёт `keysourceheadermembers.go`.
// Прежде их было четыре — три остальных звали `functionQualifiedName`, и все три
// судили предметы внутри службы доступа; они сняты вместе с ней, и функция ушла
// следом (см. врезку ниже). Число вызывающих названо здесь потому, что первым
// его читает тот, кто решает, можно ли снять файл целиком.
//
// Файл назван по тому, что он делает, а не по гейту, которого больше нет:
// имя, пережившее свой предмет, читается следующим как живое утверждение.
package repohygiene

import "go/ast"

// renderTypeExpr — плоское представление типа: достаточно, чтобы разглядеть в
// нём имя пакета, и не требует вывода типов.
func renderTypeExpr(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return renderTypeExpr(t.X)
	case *ast.SelectorExpr:
		return renderTypeExpr(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		return renderTypeExpr(t.Elt)
	case *ast.IndexExpr:
		return renderTypeExpr(t.X)
	default:
		return ""
	}
}

// Здесь стояла functionQualifiedName — сборка полного имени функции с приёмником.
// Она снята вместе со своими вызывающими: гейты, звавшие её, судили предметы
// внутри службы доступа и сняты вместе с ними. Функция без вызывающих в
// прод-дереве — мёртвый код (LEAN), и оставленная «на случай» она пережила бы
// своё основание молча.
