package repohygiene

// retiredenginemodelversion_test.go — таблица версии модели, загруженной во
// ВНЕШНИЙ движок прав, не живёт в схеме iam (задача #1717).
//
// # Предмет
//
// Внешний движок отношений снят линией R7-3: вердикт вычисляет реляционная форма
// в собственной базе службы. Таблица `kacho_iam.fga_model_version` хранила
// идентификатор модели, ЗАГРУЖЕННОЙ в этот движок, и версию её языка. Загружать
// стало некуда, писателя у строки не осталось ни одного, а форма таблицы
// (идентификатор модели, отпечаток текста, отметка применения, кем применено)
// читается как действующее версионирование модели прав.
//
// Этим она опаснее обыкновенной мёртвой таблицы: читатель схемы заключает, что
// версионирование держит она, и дальше у него два пути, и оба неверны — искать
// её писателя либо завести второго.
//
// # Почему проверка именная, а НЕ по имени движка
//
// Имя движка в схеме остаётся законно и во множестве мест: `kacho_iam.fga_outbox`
// (журнал намерений, чьё переименование отвергнуто решением — задача #1667),
// `compute_fga_register_outbox` и ещё десятки объектов шести служб. Проверка по
// имени движка краснела бы на исправном дереве и была бы снята первым же обходом.
//
// Поэтому судится ОДИН предмет, у которого механизма больше нет, и судится он по
// тому же разбору, что и гейт роста: живой считается таблица, созданная секцией
// `-- +goose Up` и не снятая последующей миграцией. Разбор сворачивается В
// ПОРЯДКЕ ПРИМЕНЕНИЯ, поэтому «создана в 0001 и снята позже» отличимо от
// «создана и жива».
//
// # Что эта проверка НЕ даёт — названо, а не спрятано
//
// Она не запрещает завести хранилище версии модели ПОД ДРУГИМ ИМЕНЕМ. Такого
// предиката не существует: «таблица, хранящая версию модели» по синтаксису
// неотличима от любого другого журнала выкаток. Что она даёт — невозможность
// вернуть СНЯТЫЙ объект молча.

import "testing"

// retiredEngineModelVersionTable — единственный предмет проверки.
//
// Владелец назван вместе с именем: одно имя носят таблицы разных служб, и счёт
// по голому имени объявил бы их одной (см. [TableRef]).
var retiredEngineModelVersionTable = TableRef{Owner: "services/iam", Name: "fga_model_version"}

// TestRetiredEngineModelVersionTableIsGone — сама проверка.
func TestRetiredEngineModelVersionTableIsGone(t *testing.T) {
	root := repoRoot(t)
	state, census := readTableGrowthTree(t, root)

	// Перепись печатает ОБЕ величины — сколько осмотрено и что найдено, — потому
	// что одно число не отличает «ноль находок» от «ноль прочитанного».
	t.Logf("перепись обхода: миграций прочитано %d (с секциями goose %d), "+
		"операторов создания таблиц %d, снятия таблиц %d; живых таблиц %d",
		census.MigrationFiles, census.SectionedMigrations,
		census.Creates, census.Drops, len(state.Tables))

	// ПРЕДПОСЫЛКИ РАЗБОРА. Каждая — факт о дереве; факт меняется, и тогда
	// молчание проверки перестаёт что-либо означать.
	if census.MigrationFiles == 0 {
		t.Fatal("прочитано ноль миграций — проверка не читала дерева, и её молчание ничего не значит")
	}
	if census.SectionedMigrations == 0 {
		t.Fatal("ни одна миграция не несёт секций `-- +goose Up`/`-- +goose Down` — предпосылка " +
			"разбора («применяется секция Up, Down есть откат») перестала быть верной")
	}
	if census.Drops == 0 {
		t.Fatal("операторов снятия таблиц не найдено ни одного — а именно ими разбор и отличает " +
			"снятую таблицу от живой. Ноль здесь означает, что ветвь снятия не читается, " +
			"и всякая когда-либо созданная таблица была бы объявлена живой")
	}
	if len(state.Tables) == 0 {
		t.Fatal("живых таблиц не найдено ни одной — предикат разбора разъехался с миграциями, " +
			"и молчание проверки означает слепоту, а не отсутствие предмета")
	}

	for _, tab := range state.Tables {
		if tab.TableRef != retiredEngineModelVersionTable {
			continue
		}
		t.Errorf("%s:%d %s — живая таблица версии модели, загружаемой во ВНЕШНИЙ движок прав, "+
			"который снят линией R7-3. Загружать некуда: писателя у строки нет ни одного, "+
			"а форма таблицы читается как действующее версионирование модели. Снимите её "+
			"новой миграцией (применённые не правятся, ban #5) вместе с записью в "+
			"`dropguard.json` и записью реестра роста",
			tab.File, tab.Line, tab.TableRef)
	}
}
