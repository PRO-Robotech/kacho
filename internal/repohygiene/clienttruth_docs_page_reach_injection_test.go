// Инъекция для гейта достижимости страницы — В ОБЕ СТОРОНЫ.
//
// Дефект возвращается НАСТОЯЩИЙ: страница пределов, заведённая коммитом «отказ
// по исчерпанию квоты описан, поверхность чтения названа», БЕЗ записи в меню —
// ровно та правка, которая не нужна ни сборке, ни пробам и потому пропускается
// молча.
//
// Каждая проба меняет ОДНО против контроля (п.2в §«Гейт на класс»).

// docsReachFixture — синтетический сайт: меню, страницы, и знобы для каждой из
// проверяемых полос.
type docsReachFixture struct {
	menuHasQuotas bool // меню называет страницу пределов
	menuDangling  bool // меню называет страницу, которой нет
	autogenerated bool // меню собирается генератором
	noSidebar     bool // объявления меню нет вовсе
}

func docsReachControlFixture() docsReachFixture { return docsReachFixture{menuHasQuotas: true} }

func writeDocsReachTree(t *testing.T, f docsReachFixture) string {
	t.Helper()
	root := t.TempDir()
	mk := func(rel, body string) {
		t.Helper()
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatalf("mkdir %s: %v", rel, err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatalf("write %s: %v", rel, err)
		}
	}

	mk("services/vpc/docs/content/intro.mdx", "# Введение\n")
	mk("services/vpc/docs/content/api/overview.mdx", "# Обзор API\n")
	mk("services/vpc/docs/content/api/quotas.mdx", "# Квоты\n")

	if f.noSidebar {
		return root
	}

	var items []string
	items = append(items, "'api/overview'")
	if f.menuHasQuotas {
		items = append(items, "'api/quotas'")
	}
	if f.menuDangling {
		items = append(items, "'api/limits'")
	}

	body := "const sidebars = {\n  vpcSidebar: [\n    'intro',\n"
	if f.autogenerated {
		body += "    { type: 'autogenerated', dirName: 'api' },\n"
	} else {
		// Подпись раздела — тоже строка в кавычках, и она НЕ идентификатор
		// страницы. Она стоит в фикстуре именно ради этого различения.
		body += "    {\n      type: 'category',\n      label: 'API',\n" +
			"      items: [" + strings.Join(items, ", ") + "],\n    },\n"
	}
	body += "  ],\n}\n\nexport default sidebars\n"
	mk("services/vpc/docs/sidebars.ts", body)
	return root
}

func docsReachInjectionCensus(t *testing.T, f docsReachFixture) docsReachCensus {
	t.Helper()
	c, err := collectDocsPageReach(mustSyntheticTree(t, writeDocsReachTree(t, f)))
	if err != nil {
		t.Fatalf("обход: %v", err)
	}
	// Инъекция беспредметна, если фикстура не прочитана.
	if len(c.Sites) != 1 || c.Pages != 3 {
		t.Fatalf("фикстура не прочитана: сайтов %d, страниц %d", len(c.Sites), c.Pages)
	}
	return c
}

func TestDocsPageReachGateInjection(t *testing.T) {
	t.Run("КОНТРОЛЬ: все страницы подключены — гейт молчит", func(t *testing.T) {
		c := docsReachInjectionCensus(t, docsReachControlFixture())
		if c.Judged != 1 {
			t.Fatalf("достижимость не судится: судится у %d сайтов", c.Judged)
		}
		// Подпись раздела 'API' и вид узла 'category' идентификаторами НЕ
		// являются: пунктов ровно три.
		if c.MenuRefs != 3 {
			t.Fatalf("пунктов-ссылок %d вместо 3 — разбор объявления меню читает "+
				"подписи и виды узлов как идентификаторы: %v", c.MenuRefs, c.Sites[0].MenuRefs)
		}
		if f := docsPageReachFindings(c); len(f) != 0 {
			t.Errorf("гейт краснеет на исправном дереве: %v", f)
		}
	})

	t.Run("ДЕФЕКТ: страница пределов заведена, а в меню не внесена", func(t *testing.T) {
		fx := docsReachControlFixture()
		fx.menuHasQuotas = false
		c := docsReachInjectionCensus(t, fx)
		f := docsPageReachFindings(c)
		if len(f) != 1 {
			t.Fatalf("ожидалась одна находка, получено %d: %v", len(f), f)
		}
		t.Logf("находка: %s", f[0])
		if !strings.Contains(f[0], "api/quotas") || !strings.Contains(f[0], "sidebars.ts") {
			t.Errorf("находка не называет ни страницы, ни меню: %s", f[0])
		}
	})

	t.Run("ДЕФЕКТ в обратную сторону: пункт меню без страницы", func(t *testing.T) {
		fx := docsReachControlFixture()
		fx.menuDangling = true
		c := docsReachInjectionCensus(t, fx)
		f := docsPageReachFindings(c)
		if len(f) != 1 {
			t.Fatalf("ожидалась одна находка, получено %d: %v", len(f), f)
		}
		t.Logf("находка: %s", f[0])
		if !strings.Contains(f[0], "api/limits") {
			t.Errorf("находка не называет пункт: %s", f[0])
		}
	})

	t.Run("ДЕФЕКТ: страницы есть, объявления меню нет вовсе", func(t *testing.T) {
		fx := docsReachControlFixture()
		fx.noSidebar = true
		c := docsReachInjectionCensus(t, fx)
		f := docsPageReachFindings(c)
		if len(f) != 1 {
			t.Fatalf("ожидалась одна находка, получено %d: %v", len(f), f)
		}
		t.Logf("находка: %s", f[0])
		if !strings.Contains(f[0], "sidebars.ts") {
			t.Errorf("находка не называет отсутствующее меню: %s", f[0])
		}
	})

	t.Run("ГРАНИЦА: автособираемое меню не судится и НАЗВАНО в переписи",
		func(t *testing.T) {
			// Состав такого меню знает генератор, а не дерево. Гейт обязан не
			// выдумывать находок и одновременно не выдавать своё молчание за
			// проверенное: сайт уходит из числа судимых и попадает в отдельный
			// счётчик переписи.
			fx := docsReachControlFixture()
			fx.autogenerated = true
			c := docsReachInjectionCensus(t, fx)
			if c.Judged != 0 || c.AutogenSkip != 1 {
				t.Fatalf("автособираемое меню не названо в переписи: судится %d, "+
					"автособираемых %d", c.Judged, c.AutogenSkip)
			}
			if f := docsPageReachFindings(c); len(f) != 0 {
				t.Errorf("гейт выдумал находки на меню, которого не судит: %v", f)
			}
		})

	t.Run("ПУСТОЙ ОБХОД отличим от «нарушений нет»", func(t *testing.T) {
		c, err := collectDocsPageReach(mustSyntheticTree(t, t.TempDir()))
		if err != nil {
			t.Fatalf("обход: %v", err)
		}
		if len(c.Sites) != 0 || c.Pages != 0 || c.MenuRefs != 0 {
			t.Fatalf("пустое дерево дало непустую перепись: %+v", c)
		}
	})
}
