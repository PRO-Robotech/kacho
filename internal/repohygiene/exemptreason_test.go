// exemptreason_test.go — ПОЛОСА «ПРОВЕРКИ НЕТ» ОБЯЗАНА НАЗЫВАТЬ ПРИЧИНУ, И
// ПРИЧИНА МАШИННО РАЗЛИЧИМА.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Запись каталога прав со значением `<exempt>` означает «модель не спрашивают».
// Одна и та же строка при этом стоит за несопоставимыми вещами: внутренний
// слушатель, куда попадают по сертификату; список, авторизуемый сужением на
// данных страницы; вход, у которого объекта нет by construction; глагол, чью
// область называет само тело запроса. Отличить их можно было ТОЛЬКО прочитав
// реализацию каждого RPC — то есть поверхность не говорила правды о себе, и
// «здесь проверки нет» читалось одинаково у внутреннего вызова и у публичного
// списка.
//
// Причина, названная машинно, делает возможным разное требование по разному
// основанию: у внутреннего — что он и вправду внутренний; у остальных — что в
// дереве есть КООРДИНАТА, где решение действительно принимается.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ В СЛОВАРЕ НЕТ ПРИЧИНЫ «ГЛОБАЛЬНЫЙ СПРАВОЧНИК»
//
// Публичное чтение справочников перестало быть освобождением: у отношения,
// которым оно гейтится, появился производитель — системная выдача с
// подстановочным субъектом, видимая перечислением выдач и отзываемая штатно.
// Освобождение там означало бы доступ, который виден только в контракте и не
// закрывается ничем, кроме выкатки. Поэтому такой причины НЕ существует, и
// запись, которая её назовёт, — находка.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТОТ ГЕЙТ НЕ УТВЕРЖДАЕТ
//
// Он не судит, ВЕРНА ли названная причина по существу: «этот список правда сужает
// на данных» — суждение о поведении, а не предикат о дереве. Он требует, чтобы
// причина была НАЗВАНА, была из закрытого словаря, и чтобы у неё в дереве была
// живая координата. Это ровно та часть, которая машинно проверяема, и граница
// названа здесь, чтобы гейт не читался шире, чем он есть.

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// catalogCopies — обе встроенные копии каталога. Требование предъявляется к
// ОБЕИМ: копия, о которой гейт не знает, разошлась бы молча.
func catalogCopies() []string {
	return []string{
		filepath.Join("gateway", "internal", "middleware", "embed", "permission_catalog.json"),
		filepath.Join("services", "iam", "internal", "apps", "kaname", "seed", "embedded", "permission_catalog.json"),
	}
}

func readExemptCatalogRows(t *testing.T, root, rel string) []ExemptCatalogRow {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, rel)) // #nosec G304 -- путь из своего дерева
	if err != nil {
		t.Fatalf("чтение каталога прав %s: %v — «ноль находок» здесь означало бы «ноль прочитанного»", rel, err)
	}
	var rows []ExemptCatalogRow
	if err := json.Unmarshal(b, &rows); err != nil {
		t.Fatalf("разбор каталога прав %s: %v", rel, err)
	}
	for i := range rows {
		rows[i].Source = rel
	}
	return rows
}

// TestR893_ExemptLaneNamesItsReason — у каждой записи `<exempt>` есть причина из
// закрытого словаря; у не-освобождённой записи причины нет; по каждой причине
// выполнено её собственное требование.
func TestR893_ExemptLaneNamesItsReason(t *testing.T) {
	root := repoRoot(t)

	var rows []ExemptCatalogRow
	for _, rel := range catalogCopies() {
		got := readExemptCatalogRows(t, root, rel)
		if len(got) == 0 {
			t.Fatalf("каталог %s пуст — гейт беспредметен", rel)
		}
		rows = append(rows, got...)
	}

	j := JudgeExemptLane(rows, EnforcementSite, func(site string) bool {
		_, err := os.Stat(filepath.Join(root, site))
		return err == nil
	})
	t.Logf("копий каталога %d; %s", len(catalogCopies()), j.Census())

	if j.Exempt == 0 {
		t.Fatalf("записей `<exempt>` ноль — гейт беспредметен, и его молчание ничего не значит")
	}
	if len(j.Findings) > 0 {
		t.Fatalf("полоса «проверки нет» не называет причину: %d\n  %s\n%s\n\n"+
			"Причина обязана быть машинно различимой: у внутреннего — внутренняя служба, "+
			"у остальных — названная координата, где решение принимается. Причины "+
			"«глобальный справочник» в словаре НЕТ: публичное чтение выражается системной "+
			"выдачей, которую видно перечислением и можно отозвать.",
			len(j.Findings), strings.Join(j.Findings, "\n  "), j.Census())
	}
}
