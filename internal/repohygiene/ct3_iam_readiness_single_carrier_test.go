// commonReadinessCarrierPkg — путь общего носителя готовности. Единственное
// имя, выписанное в этом гейте руками, и выписано оно ради ПОЛОЖИТЕЛЬНОГО
// КОНТРОЛЯ: распознаватель обязан узнать носитель там, где тот заведомо есть.
// Всё остальное выводится обходом дерева.
const commonReadinessCarrierPkg = "pkg/observability/health"

// Готовность в дереве сервисов отдаётся ОДНИМ носителем.
//
// # ПРЕДМЕТ
//
// Соседний гейт `TestEveryServiceBuildsReadinessRatherThanServingLiveness`
// требует, чтобы готовность у сервиса БЫЛА, и судит по структуре литерала, а не
// по имени пакета. Это его сознательное свойство, и из него следует граница:
// сервис, собравший ту же машинерию СВОИМ типом, проходит его законно.
//
// Здесь утверждается то, о чём тот гейт не высказывается: у одного механизма ОДИН
// носитель. Правка общего до собственного не доедет — бюджет одного чекера,
// перевод готовности в отказ на гашении, зеркало результата в счётчики появятся у
// одних и не появятся у других. Разойтись формам нечем: они не собираются вместе
// и друг друга не читают, поэтому расхождение приходит МОЛЧА и обнаруживается
// тем, кто в три часа ночи читает разные ответы одной поверхности.
//
// # ЧЕМ ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (задача продукта #1729)
//
// На день заведения формы было ДВЕ: общая (шесть сервисов) и собственная у iam.
// Единственный довод в пользу второй — «iam лист графа, набор зависимостей у него
// другой» — опровергается предикатом: у общего носителя НОЛЬ зависимостей вне
// stdlib
//
//	comm -23 <(go list -deps ./pkg/observability/health | sort) <(go list std | sort)
//
// то есть его импорт не добавляет листу ни ребра, ни чужой библиотеки, и
// различие держаться было не на чем.
//
// # ПОЧЕМУ ГЕЙТ, А НЕ ЗАМЕР ОДИН РАЗ
//
// Предикат снятия задачи звучал «число реализаций в дереве равно единице». Замер
// это утверждение подтверждает на своей ревизии и не удерживает вперёд: пятая
// форма заведётся так же тихо, как четвёртая, — не нарушив ни одной проверки,
// потому что каждая форма по отдельности корректна.
func TestReadinessIsServedByASingleCarrier(t *testing.T) {
	root := repoRoot(t)

	rels := ct3TrackedRelGoFiles(t, root, "services")
	if len(rels) == 0 {
		t.Fatal("предпосылка гейта не выполняется: не-тестовых файлов Go под services/ в индексе " +
			"НОЛЬ — обход смотрит не туда; чинить надо гейт, а не молча выходить успехом")
	}
	carrier := ct3TrackedRelGoFiles(t, root, filepath.FromSlash(commonReadinessCarrierPkg))
	if len(carrier) == 0 {
		t.Fatalf("общий носитель %s не читается обходом: положительного контроля нет, и "+
			"«собственных носителей ноль» ниже означало бы «распознаватель ничего не искал»",
			commonReadinessCarrierPkg)
	}

	findings, cen, err := auditReadinessCarrierIsSingle(root, rels, carrier)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// Предпосылка: «ноль находок» обязано быть отличимо от «ноль прочитанного».
	if cen.FilesRead == 0 {
		t.Fatal("разобрано ноль файлов Go — гейт не утверждает ничего")
	}
	if cen.Services == 0 {
		t.Fatal("обход не нашёл ни одного сервиса — гейт не утверждает ничего")
	}
	// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. Отрицание «собственных носителей ноль» теряет вход
	// молча: снимут общий носитель или переименуют его поля — распознаватель
	// перестанет узнавать что-либо вовсе и напечатает ТОТ ЖЕ ноль
	// (`testing.md` §«Гейт на класс», п.9).
	if cen.CarriersAll-cen.CarriersOwn == 0 {
		t.Fatalf("распознаватель не нашёл носителя готовности в %s — он не способен узнать "+
			"даже эталонную форму, поэтому его ноль под services/ не значит ничего. Чинить надо "+
			"распознаватель либо признать, что общий носитель сменил форму", commonReadinessCarrierPkg)
	}

	for _, f := range findings {
		t.Errorf("%s (%s): %s", f.Service, f.File, f.Why)
	}

	t.Logf("перепись: носителей готовности всего %d · из них общих %d · собственных у сервисов %d · "+
		"сервисов осмотрено %d · файлов Go разобрано %d · носители: %s",
		cen.CarriersAll, cen.CarriersAll-cen.CarriersOwn, cen.CarriersOwn,
		cen.Services, cen.FilesRead, strings.Join(cen.CarrierNames, ", "))

	if t.Failed() {
		t.Logf("исходов два, и оба закрывают предмет: сервис берёт %s, либо различие называется "+
			"РЕШЕНИЕМ в docs/engineering/architecture своего сервиса и гейт учится требовать "+
			"свойства от каждой формы. «Оставить как есть» исходом не является: расхождение "+
			"останется, и решать его будет тот, кто наткнётся", commonReadinessCarrierPkg)
	}
}

// ct3TrackedRelGoFiles — не-тестовые файлы Go под каталогом, ОТНОСИТЕЛЬНЫМИ
// путями от корня репозитория.
//
// Состав берётся у индекса git (`trackedGoFiles`), а не обходом диска: под
// корнем лежат рабочие копии соседних сессий и сборочные выходы, и обход по
// диску сделал бы вердикт свойством чужого рабочего каталога, а не коммита.
func ct3TrackedRelGoFiles(t *testing.T, root, sub string) []string {
	t.Helper()
	var out []string
	for _, abs := range trackedGoFiles(t, filepath.Join(root, sub)) {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			t.Fatalf("относительный путь %s: %v", abs, err)
		}
		out = append(out, filepath.ToSlash(rel))
	}
	sort.Strings(out)
	return out
}
