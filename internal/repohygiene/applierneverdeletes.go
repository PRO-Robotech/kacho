// applierneverdeletes.go — разбор пакета применителя ролей на предмет удаления
// строки роли (приёмка
// `services/iam/docs/engineering/acceptance/roles-come-as-data-not-migrations.md`
// §3.1, держатель Г3; сценарий MOD-RD-15).
//
// # Предмет
//
// Роль с выдачами удалить нельзя — `access_bindings_role_fk … ON DELETE
// RESTRICT` отвергнет операцию, и применитель встанет на первой же роли,
// которой кто-то пользуется. А если бы не отверг, каскад унёс бы селекторы,
// проекцию глаголов и проекцию сегментов МОЛЧА: каскад ничего не печатает.
// Отзыв роли — отдельный предмет (#1913), и «снять и положить» вместо
// приведения его не заменяет. Форма отзыва ВЫБРАНА и записана решением:
// строка ПОМЕЧАЕТСЯ снятой, а не удаляется —
// `services/iam/docs/engineering/architecture/role-withdrawal-is-a-mark.md`.
// Запрет ниже она не задевает by construction: пометка — это `UPDATE`.
//
// Прежде здесь стоял #1823. Он закрыт живостью КАТАЛОГА и роли не касался,
// то есть отсылал читателя к закрытой задаче за предметом, которого в ней
// нет, — утверждение, пережившее свой предмет.
//
// # Что здесь считается находкой — ДВЕ оси, и первая сильнее
//
//  1. **порт применителя объявляет ОДНОЗНАЧНО удаляющий глагол.** Это ось by
//     construction: пока порт его не несёт, применитель не может удалить
//     НИЧЕГО, каким бы ни был его код. Ось судит имена методов интерфейса, а не
//     их тела, — и потому в её перечне стоят только те глаголы, у которых в
//     этом дереве ОДИН смысл. Почему `Retire` из перечня выведен и чем держится
//     то, что он держал, сказано у самого перечня ниже;
//  2. **в пакете стоит оператор `DELETE` над таблицей ролей.** Ось судит
//     СТРОКОВЫЙ ЛИТЕРАЛ узла разбора, а не текст файла: слово `DELETE` стоит и
//     в комментариях, объясняющих сам запрет, — гейт, судящий подстроку,
//     краснел бы на собственном объяснении.
//
// # Чего разбор НЕ видит — названо, а не спрятано
//
// Запрос, собранный из кусков в рантайме (`"DELE" + "TE FROM roles"`), и запрос,
// приехавший параметром. Первое — форма, которой в дереве нет; второе ловит
// первая ось: чтобы позвать чужое удаление, порт обязан его объявить.
package repohygiene

import (
	"go/ast"
	"go/parser"
	"go/token"
	"regexp"
	"strconv"
	"strings"
)

// ApplierDeleteSite — координата находки.
type ApplierDeleteSite struct {
	File string
	Line int
	// Kind — ось: `port-verb` либо `sql-literal`.
	Kind string
	// What — что именно найдено: имя метода либо начало литерала.
	What string
}

// ApplierDeleteCensus — объём осмотренного одним файлом.
type ApplierDeleteCensus struct {
	// InterfaceMethods — методов интерфейсов прочитано.
	InterfaceMethods int
	// StringLiterals — строковых литералов прочитано.
	StringLiterals int
	// Comments — комментариев прочитано. Печатается отдельно: их гейт судить НЕ
	// обязан, и ненулевой счётчик при нулевых находках говорит, что различение
	// «код против текста» вообще имело предмет.
	Comments int
}

// applierDeleteVerbRe — имена методов, ОДНОЗНАЧНО означающие удаление.
//
// # Почему `Retire` здесь НЕТ — токен двузначен, и обе стороны измерены
//
// В этом дереве `retire` называет ОБА исхода, и различает их не слово, а то,
// что делает код:
//
//	пометка, строка ОСТАЁТСЯ  — 3 таблицы каталога (`catalog_module`,
//	                            `catalog_resource`, `catalog_verb`) несут
//	                            `retired_at` под `CHECK (live = (retired_at IS
//	                            NULL))`; миграция `20260901113757`;
//	удаление строки          — 10 миграций с именем `_retire*`
//	                            (`git ls-files services/iam/internal/migrations/
//	                            | grep -c '_retire'`), в каждой стоит `DELETE`
//	                            либо `DROP`.
//
// Ось, судящая СЛОВО, ошибалась на нём в обе стороны сразу:
//
//  1. **ложное срабатывание.** Форму отзыва роли модуля выбрало решение
//     `services/iam/docs/engineering/architecture/role-withdrawal-is-a-mark.md`:
//     строка ПОМЕЧАЕТСЯ снятой. Порт с глаголом `RetireSystemRole` — это
//     `UPDATE`, удаления в нём нет ни в одной ветке, а гейт краснел. Гейт,
//     краснеющий на верном коде, отключают первым;
//  2. **ложное молчание, и оно НЕ чинилось расширением перечня.** Глагол
//     `WithdrawSystemRole`, чья реализация удаляет строку, под перечень не
//     подпадал вовсе — а `withdraw` рабочее слово этого дерева (**25**
//     нетестовых файлов iam). Гнаться за словами бесполезно by construction:
//     их множество открыто.
//
// # Чем держится вторая половина — соседом, и это ПОКАЗАНО, а не предположено
//
// `systemrolerowisneverdeleted.go` обходит **всё** прод-дерево Go сервиса iam и
// судит ОПЕРАТОР: удаление над `roles`, не сужённое на пользовательскую роль, —
// находка, как бы ни назывался метод, который его исполняет. Реализация живёт в
// адаптере, то есть ВНЕ пакета применителя, куда эта ось не смотрит by
// construction. Проба
// `TestTheDeletingImplementationIsHeldWhateverTheVerbIsCalled` подаёт соседу
// удаляющую реализацию именно `RetireSystemRole` и требует находки; законный
// близнец — та же реализация пометкой — обязан молчать.
//
// # Что осталось СЛЕПЫМ у этой оси, и это названо, а не спрятано
//
// Ось судит глагол, а не ЕГО ПРЕДМЕТ. Удаление ПРОЕКЦИИ правила законно — с него
// начинается приведение (`ReplaceRuleRefs`), — поэтому порт с методом вида
// `RemoveRuleRef` стал бы находкой, ничего не нарушив. Сегодня такого метода в
// порте нет (перепись гейта печатает число прочитанных методов), и предмет
// заведён задачей продукта #1926, а не оставлен словами.
//
// # Приёмка этим НЕ задета — перемерено, а не предположено
//
// Приёмка `roles-come-as-data-not-migrations.md` определяет Г3 так: «`DELETE`
// над таблицей ролей в пакете применителя — находка; **судить по узлу разбора,
// а не по слову**» (§6), и в её таблице инъекций (§7) у Г3 названы только
// оператор и проза. Перечня глаголов порта она не называет: `purge`, `remove` и
// `drop` в её тексте — **0** строк каждое; `retire` — **8**, и ни одна не про
// порт, метод или интерфейс (`grep -niE 'retire' … | grep -iE
// 'порт|глагол|метод|интерфейс'` → пусто). Значит сужение перечня — решение
// автора гейта, а не правка чужого APPROVED-сценария; MOD-RD-15 остаётся верным
// дословно, потому что говорит об операторе, а не об имени метода.
var applierDeleteVerbRe = regexp.MustCompile(`^(Delete|Remove|Drop|Purge)`)

// applierDeleteSQLRe — оператор удаления над таблицей ролей в строковом
// литерале.
//
// # Образец привязан к НАЧАЛУ СТРОКИ, и это несущее
//
// Запрос, отдаваемый оператору, НАЧИНАЕТСЯ глаголом (возможно, после отступа,
// перевода строки или общего табличного выражения) — таков он и в дереве, где
// запросы пишутся сырыми строками с переносами. Проза о самом запрете
// («применитель не производит DELETE FROM roles») несёт то же слово ПОСРЕДИ
// предложения. Образец без привязки не различает их и краснеет на тексте
// отказа, объясняющем запрет, — то есть на собственном объяснении гейта. Это
// поймал законный близнец инъекции, а не подозрение.
//
// Слепая зона названа: сообщение об отказе, НАЧИНАЮЩЕЕСЯ с самого оператора,
// стало бы находкой. Форма редкая, чинится перефразированием, и цена ошибки
// здесь — лишний разбор, а не пропущенное удаление.
var applierDeleteSQLRe = regexp.MustCompile(`(?im)^\s*(with\b[^\n]*\n\s*)?delete\s+from\s+(kacho_iam\.)?roles\b`)

// ScanApplierDeletes разбирает один файл пакета применителя.
func ScanApplierDeletes(path string, src []byte) (sites []ApplierDeleteSite, census ApplierDeleteCensus, err error) {
	fset := token.NewFileSet()
	f, perr := parser.ParseFile(fset, path, src, parser.ParseComments)
	if perr != nil {
		return nil, ApplierDeleteCensus{}, perr
	}
	for _, g := range f.Comments {
		census.Comments += len(g.List)
	}
	ast.Inspect(f, func(n ast.Node) bool {
		switch v := n.(type) {
		case *ast.InterfaceType:
			if v.Methods == nil {
				return true
			}
			for _, m := range v.Methods.List {
				for _, name := range m.Names {
					census.InterfaceMethods++
					if applierDeleteVerbRe.MatchString(name.Name) {
						sites = append(sites, ApplierDeleteSite{
							File: path, Line: fset.Position(name.Pos()).Line,
							Kind: "port-verb", What: name.Name,
						})
					}
				}
			}
		case *ast.BasicLit:
			if v.Kind != token.STRING {
				return true
			}
			census.StringLiterals++
			if applierDeleteSQLRe.MatchString(litText(v.Value)) {
				sites = append(sites, ApplierDeleteSite{
					File: path, Line: fset.Position(v.Pos()).Line,
					Kind: "sql-literal", What: firstLineOf(v.Value),
				})
			}
		}
		return true
	})
	return sites, census, nil
}

// litText — содержимое литерала БЕЗ кавычек. Обязательно: образец привязан к
// началу строки, а `v.Value` несёт открывающую кавычку — без снятия привязка
// не срабатывала бы никогда, и вторая ось гейта молчала бы всегда. Поймано
// инъекцией, а не чтением.
func litText(v string) string {
	if u, err := strconv.Unquote(v); err == nil {
		return u
	}
	return strings.Trim(v, "`\"")
}

// firstLineOf — начало литерала для текста находки: целый запрос в сообщении
// нечитаем, а координата и первая строка называют место однозначно.
func firstLineOf(s string) string {
	s = strings.TrimSpace(strings.Trim(s, "`\""))
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 80 {
		s = s[:80] + "…"
	}
	return strings.TrimSpace(s)
}
