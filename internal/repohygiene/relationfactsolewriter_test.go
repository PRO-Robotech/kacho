// relationfactsolewriter_test.go — У ПРЯМОГО ФАКТА ОДИН ПРОИЗВОДИТЕЛЬ, И ЭТО ЖУРНАЛ.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Таблица `kaname.relation_fact` — то, из чего реляционная форма собирает
// безусловное основание вердикта. Наполняет её ТРИГГЕР на журнале намерений
// (`kaname.fga_outbox`, миграция 0098), и это выбор схемы, а не привычка:
// производителей кортежа много и они разной природы (use-case, реконсайлер, посев
// старта, сырой SQL миграции), поэтому писатель, добавленный в код, не покрывает
// SQL вовсе, а перечень «кто ещё обязан писать факт» расходится с деревом при
// первой же новой миграции — молча.
//
// Пока производитель ОДИН, появление пятого происходит by construction: он кладёт
// строку журнала, и проекция подхватывает её, не зная о нём. Стоит завести второго
// писателя из кода — и инвариант ломается ровно в ту сторону, которую не видно:
// факт есть, журнала за ним нет, а значит нет и того, что журнал даёт (порядок
// применения, снятие, разбор оснований).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕЙ ЭТО ПРЕЕМНИК
//
// До стадии S6 эпика #747 соседний гейт стерёг обратную сторону: «в движок пишут
// только через строку журнала». Движка нет, и та формулировка предмета лишилась —
// но инвариант остался, только теперь его вторая сторона это ФАКТ, а не чужое
// хранилище. Гейт снят вместе со своим предметом, этот заведён вместо него.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦА НАЗВАНА
//
// Гейт читает ЗАПРОСЫ в непроверочном коде Go. Он НЕ видит: SQL миграций (там
// запись законна — миграция и есть схема), проб (им положено готовить состояние) и
// динамически собранного имени таблицы. Последнее — настоящая слепая зона, и она
// названа, а не умолчана: собранное из кусков имя предикатом по подстроке не
// ловится ничем.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/gitenv"
)

// factTable — таблица прямого факта.
const factTable = "kaname.relation_fact"

// factMutations — глаголы записи. Чтение (`SELECT`) законно и в перечень не входит:
// форма его и делает.
var factMutations = []string{"INSERT INTO " + factTable, "UPDATE " + factTable, "DELETE FROM " + factTable}

// TestR7_3_27_OnlyTheJournalProducesTheDirectFact — в непроверочном коде Go нет ни
// одной записи в таблицу прямого факта.
func TestR7_3_27_OnlyTheJournalProducesTheDirectFact(t *testing.T) {
	root := repoRoot(t)
	out, err := gitenv.Command(root, "ls-files", "-z", "--", "*.go").Output()
	if err != nil {
		t.Fatalf("git ls-files: %v — состав дерева не установлен, и «ноль находок» "+
			"здесь означало бы «ноль прочитанного»", err)
	}

	var (
		filesRead   int
		mentions    int
		findings    []string
		sawTheTable bool
	)
	for _, rel := range strings.Split(strings.TrimRight(string(out), "\x00"), "\x00") {
		if rel == "" || skipPath(rel) || strings.HasSuffix(rel, "_test.go") {
			continue
		}
		b, readErr := os.ReadFile(filepath.Join(root, rel)) // #nosec G304 -- путь из индекса своего дерева
		if readErr != nil {
			t.Fatalf("чтение %s: %v", rel, readErr)
		}
		filesRead++
		body := string(b)
		if !strings.Contains(body, factTable) {
			continue
		}
		sawTheTable = true
		mentions++
		upper := strings.ToUpper(body)
		for _, verb := range factMutations {
			if strings.Contains(upper, strings.ToUpper(verb)) {
				findings = append(findings, rel+": "+verb)
			}
		}
	}

	t.Logf("осмотрено непроверочных файлов Go: %d; называют таблицу прямого факта: %d",
		filesRead, mentions)

	if filesRead == 0 {
		t.Fatal("осмотрено ноль файлов — гейт не читал дерева, и его молчание ничего не значит")
	}
	// Предпосылка: таблица вообще существует в коде как читаемая. Ноль упоминаний
	// означает либо переименование (тогда правь `factTable` вместе с ним), либо что
	// форма перестала её читать — и то и другое обязано быть замечено здесь, а не
	// принято за «нарушений нет».
	if !sawTheTable {
		t.Fatalf("имя %q не встречается в непроверочном коде НИ РАЗУ — предмета у гейта "+
			"нет: либо таблица переименована, либо её перестали читать", factTable)
	}

	for _, f := range findings {
		t.Errorf("%s — запись в таблицу прямого факта из кода.\n"+
			"У неё ОДИН производитель: триггер на журнале намерений (миграция 0098). "+
			"Второй писатель кладёт факт, за которым нет строки журнала, — то есть без "+
			"порядка применения, без снятия и без разбора оснований. Ломается это в ту "+
			"сторону, которую не видно: факт ЕСТЬ, и вердикт по нему выносится", f)
	}
}
