// TestMigrationRemovingGrantsLeavesATrace — IAM-RM-1-11.
func TestMigrationRemovingGrantsLeavesATrace(t *testing.T) {
	root := repoRoot(t)

	paths, err := treecorpus.UnderWithSuffix(
		filepath.Join(root, filepath.FromSlash(grantRemovalMigrationsDir)), ".sql")
	if err != nil {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: корпус миграций %s не перечислен: %v — "+
			"«ноль находок» ниже означало бы «ноль прочитанного»",
			grantRemovalMigrationsDir, err)
	}

	corpus, err := readMigrationCorpus(paths, os.ReadFile)
	if err != nil {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: файл корпуса не читается: %v", err)
	}

	silent, c := auditGrantRemovalTrace(corpus)
	mentions := grantTableMentions(corpus)

	// Перепись печатается ДО вердикта: она обязана быть видна и на зелёном
	// прогоне, иначе «ноль находок» неотличимо от «ноль прочитанного».
	t.Logf("перепись: файлов корпуса прочитано %d; операторов, называющих таблицу выдач %d; "+
		"с удалением выдач где угодно %d; из них в накатной половине %d; "+
		"из них без следа %d (храповик %d)",
		c.FilesRead, mentions, c.WithDelete, c.InUpHalf, len(silent), grantRemovalRatchet)
	if len(silent) > 0 {
		t.Logf("прощённые сегодня: %s", strings.Join(silent, ", "))
	}

	// ПРЕДПОСЫЛКИ. Каждая — факт, который может измениться и сделать вердикт
	// беспредметным, поэтому гейт проверяет их сам, а не подразумевает.
	if c.FilesRead == 0 {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: в %s не прочитано ни одного файла", grantRemovalMigrationsDir)
	}
	// Здесь стояла предпосылка «удалений выдач обязано быть не ноль», и она СНЯТА
	// ВМЕСТЕ СО СВОИМ ПРЕДМЕТОМ (свод миграций iam, 2026-09-04). Она опиралась на
	// удаления в ОТКАТНОЙ половине исторических миграций; свод написан `pg_dump`,
	// то есть конечным состоянием, и ни удалений, ни откатной половины прежних
	// файлов в нём нет — операторов над таблицей выдач осталось восемь, все
	// вставки. Требовать от дерева событий истории, которых его форма не
	// производит, значит краснеть на исправном корпусе.
	//
	// На её место встала предпосылка, которую дерево ПРОИЗВОДИТ: таблица выдач в
	// корпусе названа. Она слабее — доказывает, что корпус читается и таблица в
	// нём есть, но не что распознаватель узнаёт свой глагол, — и слабость эта
	// названа, а не скрыта. Способность узнавать глагол доказывает ИНЪЕКЦИЯ
	// (TestGrantRemovalTraceGateInjection): она подаёт вход сама, поэтому форма
	// корпуса её не касается.
	if mentions == 0 {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: во всём корпусе %s таблица kacho_iam.access_bindings не "+
			"названа НИ ОДНИМ оператором. Выдача существует только в схеме iam, поэтому ноль "+
			"означает либо нечитаемый корпус, либо разбор, разъехавшийся со схемой, — и "+
			"молчание вердикта было бы сказано о нём, а не о дереве", grantRemovalMigrationsDir)
	}

	if len(silent) != grantRemovalRatchet {
		t.Error(grantRemovalFinding(len(silent), silent))
	}
}

// TestNoMigrationMovesGrantsBetweenRoles — IAM-RM-1-13, характеризующий замок.
//
// Дерево уже даёт это поведение; проба обязана его ПЕРЕЖИТЬ, а не покраснеть.
// Требовать от неё красноты запрещено: она утверждает, что отвергнутый исход
// («перенести выдачи на роли-преемники») не исполнялся ни разу, а не что кто-то
// его исполнил.
func TestNoMigrationMovesGrantsBetweenRoles(t *testing.T) {
	root := repoRoot(t)

	paths, err := treecorpus.UnderWithSuffix(
		filepath.Join(root, filepath.FromSlash(grantRemovalMigrationsDir)), ".sql")
	if err != nil {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: корпус миграций не перечислен: %v", err)
	}
	corpus, err := readMigrationCorpus(paths, os.ReadFile)
	if err != nil {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: файл корпуса не читается: %v", err)
	}

	moves, statements := auditGrantRoleReassignment(corpus)
	mentions := grantTableMentions(corpus)
	t.Logf("перепись: файлов корпуса %d; операторов, называющих таблицу выдач %d; "+
		"операторов «UPDATE access_bindings … SET» в накатной половине %d; "+
		"из них переставляющих role_id %d",
		len(corpus), mentions, statements, len(moves))

	// Здесь стояла предпосылка «операторов правки выдачи обязано быть не ноль», и
	// она СНЯТА ВМЕСТЕ СО СВОИМ ПРЕДМЕТОМ (свод миграций iam, 2026-09-04).
	//
	// Случай тот же, что у соседней пробы, но опаснее, и это надо сказать прямо:
	// здесь утверждение ОТРИЦАТЕЛЬНОЕ («переносов не бывает»). Отрицание,
	// лишившееся входа, не краснеет — оно ЗАМОЛКАЕТ: обход цел, перепись цела,
	// вердикт зелен, а проверять больше нечего. До свода правка выдачи стояла в
	// каждой миграции мягкого отзыва (4 файла корпуса); свод написан `pg_dump`,
	// то есть конечным состоянием, и правок не содержит вовсе — операторов над
	// таблицей выдач осталось восемь, все вставки.
	//
	// Предмет запрета при этом ЖИВ и вперёд действует: следующая миграция вправе
	// «просто перевесить» выдачи, и это тихое расширение прав. Поэтому проба не
	// снимается, а её предпосылка переводится на признак, который дерево
	// производит; способность распознавателя различать перенос от мягкого отзыва
	// доказывает инъекция в обе стороны
	// (TestGrantRoleReassignmentDiscriminatorCutsBothWays).
	if mentions == 0 {
		t.Fatalf("ПРЕДПОСЫЛКА ЛОЖНА: во всём корпусе %s таблица kacho_iam.access_bindings не "+
			"названа НИ ОДНИМ оператором — отрицание «переносов не бывает» выполняется "+
			"тождественно, и его молчание сказано о разборе, а не о дереве",
			grantRemovalMigrationsDir)
	}
	if len(moves) > 0 {
		t.Errorf("миграция переставляет выдачу с одной роли на другую: %s. "+
			"Это ТИХОЕ расширение прав: выдача на снятую роль дала бы доступ к ресурсу, "+
			"которого выдававший НЕ НАЗЫВАЛ, а согласия у него никто не спрашивал. "+
			"Исход отвергнут приёмкой §2.5; законный путь — снять выдачу и оставить след",
			strings.Join(moves, ", "))
	}
}
