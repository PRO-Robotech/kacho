// materializationstepobservable_test.go — ОСТАТОК снятого гейта: одна общая
// вспомогательная функция координаты.
//
// # Что здесь было и почему снято
//
// Файл нёс пятое условие соприкосновения с владельцем прав: «ноль срабатываний
// доказанного входа за прогон» обязано быть находкой, а не тишиной. Две пробы —
// TestMaterializationStepCounterIsWiredAtBoot (провязка счётчика шагов
// материализации в композиционном корне) и
// TestEveryDeclaredMaterializationStepHasAnEmitter (у каждого объявленного шага
// есть эмитент) — читали перечень шагов из коллектора службы доступа
// (`…/internal/observability/metrics/register_postcommit_recorder.go`) и её
// композиционный корень.
//
// Служба вынесена отдельным продуктом: коллектора в дереве нет, конструктора
// провязки нет ни в одном из 724 прод-файлов. Обе пробы отказывали на своей
// предпосылке — то есть вердикта не выносили вовсе, — и обе сняты ВМЕСТЕ с
// предметом (записи надгробия — в retired_gate_carriers.json). Свойство целиком
// уехало в репозиторий службы: провязка её счётчика есть предмет её дерева, и
// судить его отсюда нечем.
//
// # Почему файл остался, а не ушёл целиком
//
// fmtLine ниже зовут ЧЕТЫРЕ соседние пробы — accumulatorreader_test.go,
// diagnosticcollector_test.go, edgemetricsroute_test.go,
// listnarrowcollector_test.go, — и их предметы живут своей жизнью. Унеся её
// вместе со своим гейтом, снятие сломало бы чужую сборку. Цена выбора НАЗВАНА:
// имя файла шире того, что в нём осталось. Уйдут четыре соседа — уйдёт и эта
// функция вместе с файлом.

// fmtLine — координата «строка:колонка» без имени файла: имя печатается
// вызывающим отдельно, и дублировать его в каждой находке нечитаемо.
func fmtLine(fset *token.FileSet, pos token.Pos) string {
	p := fset.Position(pos)
	return strings.TrimPrefix(p.String(), p.Filename+":")
}
