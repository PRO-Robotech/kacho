// grantremovaltrace.go — миграция, СНИМАЮЩАЯ выдачи, обязана оставить след той
// формы, которую платформа для этого завела.
//
// # Предмет
//
// Строка `kacho_iam.access_bindings` — это доступ, выданный арендатору. Миграция,
// удаляющая её, доступ ОТБИРАЕТ; и если рядом нет записи в журнал жизненного
// цикла выдачи, у которого есть читатель, то «отобрано» становится неотличимо от
// «никогда не выдавалось». Арендатор видит отсутствие права и не может узнать ни
// что оно было, ни когда исчезло, ни почему.
//
// Класс измерен, а не предположен: на ревизии заведения этой проверки удаление
// выдач стояло в накатной половине ШЕСТИ миграций, и запись в журнал не
// сопровождала НИ ОДНУ из них. В `kacho_iam.audit_outbox` не пишет ни одна
// миграция корпуса, поэтому вторая половина предиката сегодня не отсекает
// ничего — и это сказано вслух, а не скрыто: она начнёт различать в тот день,
// когда норма впервые исполнится. До того дня её способность различать
// доказывает только инъекция.
//
// Приёмка: services/iam/docs/engineering/acceptance/roles-pointing-at-moved-resources.md
// (APPROVED круга 2), сценарии IAM-RM-1-11 и IAM-RM-1-12. Задача продукта #1825.
//
// # Почему ХРАПОВИК, а не ведомость имён
//
// Шесть исторических миграций править нельзя (запрет #5) — значит их придётся
// либо простить, либо держать ствол красным за прошлое. Ведомость имён растёт
// молча, и её никто не сверяет; число сверяется одним обходом и меняется только
// сознательно. Перечень имён при этом ПЕЧАТАЕТСЯ каждым прогоном — прощение
// остаётся видимым, а не превращается в файл, который перестают читать.
//
// Храповик ДВУСТОРОННИЙ: находка приходит и на седьмой миграции, и на пятой.
// Односторонний потолок не истекает никогда и потому механизмом не является.
//
// # Он ИСТЁК — 2026-09-04, и истёк не починкой, а сводом
//
// Свод миграций iam (171 файл → один, написанный `pg_dump`) снял вопрос о шести
// исторических миграциях иначе, чем ожидалось: их не починили, их БОЛЬШЕ НЕТ.
// Дамп пишет КОНЕЧНОЕ СОСТОЯНИЕ, а состояние удалений не содержит — в корпусе
// осталось восемь операторов над таблицей выдач, все вставки, и прощать стало
// нечего. Храповик опущен до нуля тем же изменением, которым это обнаружено:
// запись, которой нечего исключать, — находка, и она пришла с той стороны, ради
// которой храповик и сделан двусторонним.
//
// Что из этого следует для ЧТЕНИЯ гейта, и это надо сказать прямо: при нуле
// удалений в корпусе вердикт выполняется ТОЖДЕСТВЕННО. Прежние предпосылки обоих
// гейтов файла опирались на события ИСТОРИИ («удалений обязано быть не ноль»,
// «операторов правки обязано быть не ноль») и вместе с историей умерли; на их
// месте стоит признак, который дерево ПРОИЗВОДИТ (grantTableMentions), а
// способность распознавателей узнавать свои операторы доказывает инъекция.
// Слабость замены названа там же, где она стоит, а не подразумевается.
//
// # Почему снятие выдач У СУБЪЕКТА входит в класс
//
// Один из шести файлов снимает выдачи по субъекту (служебная учётка сетевого
// оператора), не трогая ни одной роли. Норма — про ОТОБРАННЫЙ ДОСТУП, а не про
// снятую роль: строки выдач исчезают одинаково, а служебная учётка — такой же
// первоклассный принципал, как человек. Сужение «снятие вместе с ролью»
// потребовало бы суждения, которого у гейта дерева нет, и выдало бы вперёд
// послабление, которое не истечёт никогда.
//
// # Граница, названная честно
//
// Гейт судит НАКАТНУЮ половину: `DELETE` в откатной половине снимает СВОЮ ЖЕ
// вставку, откатываясь, и доступа не отбирает. Он не судит, ВЕРЕН ли текст
// оставленного следа и доедет ли он до читателя, — только что запись есть. И он
// ничего не говорит о выдачах, снятых прод-кодом: у того путь свой и свой
// журнал.
package repohygiene

import (
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// grantRemovalRatchet — сколько миграций корпуса СЕГОДНЯ снимают выдачи без
// следа. Число, а не перечень: см. шапку. Отклонение в любую сторону — находка.
//
// Замер на ревизии заведения (`c2d573654c`, 154 файла корпуса): 14 файлов несут
// удаление выдач где угодно, 6 — в накатной половине, из них 6 без записи в
// журнал. Перечень имён печатается прогоном.
//
// # Опущен до НУЛЯ 2026-09-04 — прощение истекло вместе со своим предметом
//
// Шесть прощённых были ИСТОРИЧЕСКИМИ миграциями, и прощались они ровно потому,
// что применённую миграцию не правят (запрет #5). Свод (171 файл → один,
// написанный `pg_dump`) снял с них этот статус не починкой, а тем, что файлов
// больше нет: дамп пишет КОНЕЧНОЕ СОСТОЯНИЕ, а состояние удалений не содержит —
// в нём остались только те строки выдач, которые пережили всю цепочку.
// Прощать стало нечего, и запись, которой нечего исключать, — находка (та самая
// вторая сторона храповика, ради которой он двусторонний).
//
// Ноль здесь — не ослабление, а самое сильное состояние гейта: ВСЯКАЯ следующая
// миграция, снимающая выдачи без следа, становится находкой немедленно, без
// прощения вперёд.
//
// Обратная сторона названа честно: при нуле удалений в корпусе вердикт
// `len(silent) == 0` выполняется ТОЖДЕСТВЕННО. Поэтому предпосылка гейта
// перенесена на признак, который дерево производит (grantTableMentions), а
// способность распознавателя узнавать свой глагол доказывает инъекция.
const grantRemovalRatchet = 0

// grantRemovalMigrationsDir — корпус. Каталог один: `access_bindings` живёт
// только в схеме iam, и выдача существует только там.
const grantRemovalMigrationsDir = "services/iam/internal/migrations"

// Распознаватели намеренно ТЕРПИМЫ к написанию: SQL нечувствителен к регистру
// ключевых слов и допускает произвольные пробелы между лексемами, а предикат,
// узнающий одну запись из многих законных, МОЛЧИТ на остальных — и молчание
// читается как факт о дереве. Терпимая форма строго шире точной; обе прогнаны на
// корпусе и дали одно число.
var (
	reGrantDelete = regexp.MustCompile(`(?i)delete\s+from\s+kacho_iam\s*\.\s*access_bindings`)
	reGrantTrace  = regexp.MustCompile(`(?i)insert\s+into\s+kacho_iam\s*\.\s*audit_outbox`)
	// reGrantTableNamed — таблица выдач, названная ЛЮБЫМ глаголом.
	//
	// Ею проверяется предпосылка обоих гейтов после свода миграций (2026-09-04):
	// корпус iam — один файл, написанный `pg_dump`, то есть КОНЕЧНОЕ СОСТОЯНИЕ, и
	// ни удалений, ни правок выдач он не содержит вовсе. Прежние предпосылки
	// («удалений обязано быть не ноль», «операторов правки обязано быть не ноль»)
	// требовали от дерева событий ИСТОРИИ, которых его форма больше не производит.
	//
	// Эта — производится: восемь операторов называют таблицу. Она слабее прежних и
	// названа слабой честно: она доказывает, что корпус читается и таблица выдач в
	// нём есть, но НЕ доказывает, что распознаватель узнаёт свой глагол. Второе —
	// предмет инъекции, и она подаёт вход сама.
	reGrantTableNamed = regexp.MustCompile(`(?i)\bkacho_iam\s*\.\s*access_bindings\b`)
)

// grantRemovalCensus — объём осмотренного. Три величины, а не одна: «ноль
// находок» обязано быть отличимо от «ноль прочитанного», а «ноль в накатной
// половине» — от «распознаватель перестал узнавать удаление вовсе».
type grantRemovalCensus struct {
	FilesRead  int
	WithDelete int // удаление выдач где угодно в файле
	InUpHalf   int // из них — в накатной половине
}

// grantMigrationSource — один файл корпуса: имя для находки и текст для разбора.
type grantMigrationSource struct {
	Name string
	Body string
}

// auditGrantRemovalTrace — ядро гейта, отделённое от корня дерева НАМЕРЕННО:
// инъекция обязана прогнать его на синтетическом корпусе, а не на этом.
//
// Возвращает имена миграций, снимающих выдачи без следа, и перепись.
func auditGrantRemovalTrace(corpus []grantMigrationSource) (silent []string, c grantRemovalCensus) {
	for _, m := range corpus {
		c.FilesRead++
		// Литералы забеливаются ВМЕСТЕ с комментариями: прозаическое сообщение
		// об отказе, называющее оператор, для поиска по образцу неотличимо от
		// самого оператора. Предикат, считающий собственное объяснение
		// проверяемого, даёт число, которого в дереве нет.
		whole := sqlBlankStrings(sqlBlankComments(m.Body))
		if !reGrantDelete.MatchString(whole) {
			continue
		}
		c.WithDelete++
		up := sqlBlankStrings(migrationUpSection(m.Body))
		if !reGrantDelete.MatchString(up) {
			continue
		}
		c.InUpHalf++
		if reGrantTrace.MatchString(up) {
			continue
		}
		silent = append(silent, m.Name)
	}
	sort.Strings(silent)
	return silent, c
}

// grantTableMentions — сколько операторов корпуса называют таблицу выдач ЛЮБЫМ
// глаголом.
//
// Общая предпосылка обоих гейтов этого файла: ноль означает, что корпус не
// прочитан либо таблица выдач из него исчезла, — и тогда молчание обоих сказано
// о разборе, а не о дереве.
func grantTableMentions(corpus []grantMigrationSource) int {
	n := 0
	for _, m := range corpus {
		// Литералы и комментарии забеливаются по той же причине, что и в разборе:
		// имя таблицы, названное в прозе отказа, оператором не является.
		body := sqlBlankStrings(sqlBlankComments(m.Body))
		n += len(reGrantTableNamed.FindAllStringIndex(body, -1))
	}
	return n
}

// readMigrationCorpus — корпус миграций сервиса, состав берётся у индекса git,
// а не с диска: игнорируемый мусор в число корпуса не попадает.
func readMigrationCorpus(paths []string, read func(string) ([]byte, error)) ([]grantMigrationSource, error) {
	out := make([]grantMigrationSource, 0, len(paths))
	for _, p := range paths {
		body, err := read(p)
		if err != nil {
			return nil, err
		}
		out = append(out, grantMigrationSource{Name: filepath.Base(p), Body: string(body)})
	}
	return out, nil
}

// grantRemovalFinding — текст находки. Отдельной функцией, чтобы обе стороны
// храповика (перебор и недобор) говорили ОДНИМ голосом и назывались вместе с
// перечнем — читателю нужен не только счёт, но и кто именно в него вошёл.
func grantRemovalFinding(got int, names []string) string {
	var b strings.Builder
	switch {
	case got > grantRemovalRatchet:
		b.WriteString("миграций, снимающих выдачи БЕЗ следа, стало больше: ")
	default:
		b.WriteString("миграций, снимающих выдачи без следа, стало меньше: ")
	}
	b.WriteString("было ")
	b.WriteString(strconv.Itoa(grantRemovalRatchet))
	b.WriteString(", стало ")
	b.WriteString(strconv.Itoa(got))
	b.WriteString(". Перечень: ")
	b.WriteString(strings.Join(names, ", "))
	if got > grantRemovalRatchet {
		b.WriteString(". Миграция, удаляющая строки kacho_iam.access_bindings в накатной " +
			"половине, ОТБИРАЕТ у арендатора доступ; без записи в kacho_iam.audit_outbox " +
			"«отобрано» неотличимо от «никогда не выдавалось». Оставь след в той же " +
			"половине — либо, если удаление снимает собственную вставку той же миграции, " +
			"перенеси его в откатную половину")
	} else {
		b.WriteString(". Уменьшение — это ХОРОШО, и потому оно тоже находка: храповик " +
			"обязан двигаться СОЗНАТЕЛЬНО. Опусти grantRemovalRatchet до нового числа " +
			"тем же изменением, которым закрыл прощённое, — иначе прощение переживёт " +
			"свой предмет")
	}
	return b.String()
}

// ── ПЕРЕНОС ВЫДАЧИ МЕЖДУ РОЛЯМИ ──────────────────────────────────────────────
//
// Приёмка отвергла исход «перенести выдачи на роли-преемники» как ТИХОЕ
// расширение прав: выдача на снятую роль дала бы доступ к ресурсу, которого
// выдававший не называл, а согласия у него никто не спрашивал. Решение обязано
// быть ИСПОЛНЕНО, а не только объявлено, — иначе оно живёт ровно до первой
// миграции, которая «просто перевесит» выдачи.

// reGrantUpdateHead — начало оператора, переставляющего поля выдачи.
//
// Разбор идёт по ПРИСВАИВАНИЯМ, а не по всему оператору: `role_id` стоит в
// условии отбора у КАЖДОГО оператора мягкого отзыва, и предикат по всему тексту
// объявил бы переносом дедупликацию выдач (проверено — он так и сделал: 1
// попадание там, где переносов ноль).
var (
	reGrantUpdateHead = regexp.MustCompile(`(?i)update\s+(?:kacho_iam\s*\.\s*)?access_bindings\b\s+set\b`)
	reGrantAssignRole = regexp.MustCompile(`(?i)\brole_id\s*=`)
	reGrantWhereOrEnd = regexp.MustCompile(`(?i)\bwhere\b|;`)
)

// auditGrantRoleReassignment — миграции, переставляющие выдачу с одной роли на
// другую, и число осмотренных операторов.
//
// Второе число обязательно: ноль переносов при нуле прочитанных операторов
// означает «распознаватель ослеп», а не «переносов нет».
func auditGrantRoleReassignment(corpus []grantMigrationSource) (moves []string, statements int) {
	for _, m := range corpus {
		up := sqlBlankStrings(migrationUpSection(m.Body))
		for _, loc := range reGrantUpdateHead.FindAllStringIndex(up, -1) {
			statements++
			rest := up[loc[1]:]
			stop := len(rest)
			if g := reGrantWhereOrEnd.FindStringIndex(rest); g != nil {
				stop = g[0]
			}
			if reGrantAssignRole.MatchString(rest[:stop]) {
				moves = append(moves, m.Name)
				break
			}
		}
	}
	sort.Strings(moves)
	return moves, statements
}
