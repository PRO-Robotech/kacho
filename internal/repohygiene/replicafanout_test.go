// replicafanout_test.go — фоновая работа обязана нести ИСХОД по многорепличности.
//
// # Предмет
//
// Фоновая петля — дренаж очереди, сверка, уборка, синхронизация — поднимается в
// КАЖДОЙ реплике: у процесса нет способа узнать, что он не один. Если работа не
// разведена, при N репликах она исполняется N раз. Иногда это безвредно
// (условная однооператорная правка, чтение собственного состояния), иногда даёт
// двойную работу, N-кратную подачу соседу или гонку.
//
// Разница между «безвредно» и «опасно» — СУЖДЕНИЕ, и машина его не выносит.
// Поэтому гейт требует не механизма, а ЗАПИСАННОГО исхода: у каждой фоновой петли
// в шапке её функции стоит
//
//	РЕПЛИКИ: <вид> — <причина>
//
// где вид берётся из закрытого словаря (клейм · одиночка · разбиение ·
// на-реплику · запрос), а причина обязана быть причиной, а не отпиской.
//
// # Почему запись, а не автоматический вывод
//
// Автоматически различить идемпотентный проход от опасного дубля нельзя: оба —
// «читает строки и что-то делает». Попытка вывести это из формы SQL дала бы
// предикат, который либо пропускает опасное, либо ловит безвредное; и то и другое
// хуже отсутствия гейта, потому что выглядит как проверка. Запись переносит
// суждение туда, где оно и принимается — к автору петли, — и оставляет его в
// дереве навсегда: следующая реплика поднимется без него.
//
// # Объём осмотренного
//
// Гейт печатает перепись на каждом прогоне: каталогов, файлов, петель, разбивку
// по видам исхода. «Ноль находок» обязано быть отличимо от «ноль прочитанного», а
// пустой корпус — отказ, а не молчаливый успех.
//
// # Способность упасть
//
// Доказана инъекцией в обе стороны — `replicafanout_injection_test.go`.
package repohygiene

import (
	"fmt"
	"sort"
	"strings"
	"testing"
)

func TestBackgroundLoopDeclaresItsReplicaFanout(t *testing.T) {
	root := repoRoot(t)

	c, err := scanBackgroundLoops(root)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// Перепись печатается ВСЕГДА, включая зелёный прогон.
	byKind := c.ByKind()
	kinds := make([]string, 0, len(byKind))
	for k := range byKind {
		kinds = append(kinds, k)
	}
	sort.Strings(kinds)
	parts := make([]string, 0, len(kinds))
	for _, k := range kinds {
		parts = append(parts, fmt.Sprintf("%s %d", k, byKind[k]))
	}
	t.Logf("перепись: каталогов %d (%s) · файлов %d · фоновых петель %d · с записью: %s",
		len(c.Dirs), strings.Join(c.Dirs, ", "), c.FilesRead, len(c.Loops),
		strings.Join(parts, " · "))

	// Проверка собственной предпосылки: обход, ничего не прочитавший, молчал бы
	// «ноль находок» — и это было бы неотличимо от исправного дерева.
	if c.FilesRead == 0 {
		t.Fatalf("прочитано 0 файлов в %v — гейту нечего рассматривать", c.Dirs)
	}
	if len(c.Loops) == 0 {
		t.Fatalf("фоновых петель найдено 0 при %d прочитанных файлах: "+
			"признак петли перестал что-либо находить, и молчание гейта означает "+
			"«ноль прочитанного», а не «ноль находок»", c.FilesRead)
	}

	findings := c.Findings()
	if len(findings) == 0 {
		return
	}
	var b strings.Builder
	fmt.Fprintf(&b, "фоновых петель без годной записи об исходе: %d из %d\n",
		len(findings), len(c.Loops))
	for _, l := range findings {
		why := "записи нет вовсе"
		if l.Bad != "" {
			why = l.Bad
		}
		fmt.Fprintf(&b, "  %s:%d %s (движима: %s) — %s\n", l.File, l.Line, l.Func, l.Driver, why)
	}
	b.WriteString("\nФоновая петля исполняется в КАЖДОЙ реплике. Поставь в шапку её функции\n")
	fmt.Fprintf(&b, "  // %s <вид> — <почему это верно>\n", fanoutMarker)
	fmt.Fprintf(&b, "виды: %s\n", kindList())
	b.WriteString("Если дубль безвреден — назови, ЧЕМ он безвреден: идемпотентность есть\n" +
		"свойство оператора, а не намерение автора.\n")
	t.Fatal(b.String())
}
