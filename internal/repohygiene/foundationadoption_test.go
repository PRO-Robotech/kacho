// foundationadoption_test.go — гейт: усыновление возможностей общего фундамента
// наблюдается переписью, а не памятью.
//
// # Предмет
//
// Замер #702 по шести механизмам сразу: усыновление возможности фундамента есть
// функция от того, следит ли за ним гейт. Где следит — усыновлена пятью
// слушателями из семи, и оба пропуска названы задачами. Где не следит — одним из
// восьми, одним из восьми, ни одним из восьми, и об этом не знал никто до
// переписи.
//
// Механизм при этом ни при чём: допуск на арендатора написан лучше среднего по
// дереву и применён ОДИН раз. В этом и опасность — наличие возможности в
// фундаменте делает остальные поверхности похожими на закрытые: появляется
// перечень ключей чарта, отказ старта, проба, и всё это относится к одной
// восьмой поверхности, а выглядит решённым вопросом.
//
// # Почему гейт, а не разовая перепись
//
// Разовая перепись отвечает про сегодняшнее дерево. Следующая возможность
// фундамента заведётся так же тихо, и найдёт её снова только сплошной обход.
// Свойство «каждый слушатель либо несёт, либо объяснил» — свойство ДЕРЕВА, и
// требовать его надо от кода, которого ещё нет.
//
// # Что гейт держит
//
//	ЕДИНИЦА     клетка считается по МЕСТУ СБОРКИ СЕРВЕРА для возможностей,
//	            которые провязывают в сервер, и по КАТАЛОГУ для тех, что
//	            заводятся раз на процесс. Единица объявлена у каждой возможности
//	            явно. Почему не одна на всю перепись — foundationsites.go, и это
//	            поправка к первой редакции, которая считала всё каталогом.
//	ПРИЗНАК     достижимость возможности — своей проводкой либо через
//	            посредника, транзитивно. Читается разбором синтаксиса, не текстом.
//	ТРЕБОВАНИЕ  у каждой клетки ровно один из трёх законных исходов: несёт ·
//	            записанное отсутствие предмета · записанный пропуск с номером
//	            задачи. Четвёртый — «не несёт и не объяснил» — роняет прогон.
//	ВЕДОМОСТИ   обе самоистекают. Пропуск, чью возможность усыновили ВСЕ единицы,
//	            которые запись называет, — находка. Запись «предмета нет»,
//	            опровергнутая усыновлением хотя бы одной, — находка. Запись о
//	            слушателе или возможности, которых в дереве нет, — находка.
//	ПРЕДПОСЫЛКИ посредник, объявленный носителем, обязан возможность СТАВИТЬ;
//	            обёртка обязана и правда оборачивать сборку сервера, и её обязан
//	            кто-то звать; каталог с уликой сборки обязан дать хотя бы одно
//	            место. Все три роняют прогон РАНЬШЕ вердикта по клеткам.
//	ПЕРЕПИСЬ    возможностей · каталогов · мест сборки · клеток · прод-файлов
//	            разобрано · несут · нет предмета · записанных пропусков ·
//	            находок. «Ноль находок» обязано быть отличимо от «ноль
//	            прочитанного».
//
// # Чего гейт НЕ держит, и это названо, а не умолчано
//
//  1. Что возможность провязана ПРАВИЛЬНО. Достижимость отвечает «доезжает»,
//     а не «поставлена в верную позицию цепочки с верными величинами». Это
//     держат пробы самих механизмов на проводе: `pkg/grpcsrv/panicrecovery_chain_test.go`,
//     `pkg/grpcsrv/limits_behaviour_test.go`, `pkg/grpcsrv/admission_wire_test.go`,
//     `pkg/servicehost/wiring_test.go`.
//  2. Что заявление посредника верно НА КАЖДОМ его пути. Сверка ловит
//     «возможности в пакете посредника нет вовсе», а не «есть, но эта ветка её
//     не ставит». Второе — свойство поведения, см. п. 1.
//  3. Два сервера, собранные ЧЕРЕЗ ОДНУ величину, срез провязки не различает —
//     и различать нечего: у них общий источник. Разъединить их гейт не
//     потребует; потребует поведенческая проба листенера.
//  4. СОСТАВ набора обязательных возможностей. Он — решение владельца, и гейт
//     его не выводит: он даёт набору ИСПОЛНИТЕЛЯ. Возможность, которой в
//     фундаменте ещё нет (метрика задержки RPC — #695), в набор не входит и
//     войдёт вместе со своей реализацией; объявить её сейчас значило бы
//     завести десять одинаковых изъятий вокруг пустоты.
//
// # Способность упасть
//
// Доказана инъекцией в обе стороны — `foundationadoption_injection_test.go`.
