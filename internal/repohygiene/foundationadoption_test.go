// foundationSurvey — общий заход переписи: перечень, места сборки, разборы
// посредников и обёрток.
//
// Вынесен, чтобы гейт и инъекция настоящим входом брали ОДИН И ТОТ ЖЕ заход:
// две копии разошлись бы молча, и разошлись бы ровно там, где инъекция
// доказывает способность упасть.
type foundationSurvey struct {
	Dirs         []string
	Scans        map[string]*FoundationScan
	Sites        []FoundationSite
	Candidates   []string
	Markers      []string
	ProviderScan map[string]*FoundationScan
	WrapperScan  map[string]*FoundationScan
}

func foundationSurveyTree(t *testing.T, root string, r FoundationRoster) foundationSurvey {
	t.Helper()
	sv := foundationSurvey{
		Markers:      serverSiteMarkers(foundationBaseMarkers, r.Wrappers),
		ProviderScan: map[string]*FoundationScan{},
		WrapperScan:  map[string]*FoundationScan{},
	}
	var err error
	sv.Dirs, sv.Scans, sv.Candidates, err = DiscoverListeners(root, sv.Markers)
	if err != nil {
		t.Fatalf("перепись слушателей не состоялась: %v", err)
	}
	if len(sv.Dirs) == 0 {
		t.Fatalf("слушателей не найдено ни одного при %d рассмотренных каталогах: перепись "+
			"беспредметна, и её молчание означало бы «ноль прочитанного», а не «ноль находок»",
			len(sv.Candidates))
	}
	if sv.Sites, err = DiscoverServerSites(root, sv.Dirs, sv.Markers, r.Wrappers); err != nil {
		t.Fatalf("перепись мест сборки сервера не состоялась: %v", err)
	}
	for _, p := range r.Providers {
		s, serr := ScanGoTree(filepath.Join(root, filepath.FromSlash(p.Name)))
		if serr != nil {
			t.Fatalf("посредник %s не разбирается: %v", p.Name, serr)
		}
		sv.ProviderScan[p.Name] = s
	}
	for _, w := range r.Wrappers {
		s, serr := ScanGoTree(filepath.Join(root, filepath.FromSlash(w.Dir)))
		if serr != nil {
			t.Fatalf("обёртка %s не разбирается: %v", w.Dir, serr)
		}
		sv.WrapperScan[w.Dir] = s
	}
	return sv
}

// TestFoundationCapabilitiesAreAdoptedOrAccountedFor — сама перепись.
func TestFoundationCapabilitiesAreAdoptedOrAccountedFor(t *testing.T) {
	root := repoRoot(t)
	r := foundationRoster()

	// Предпосылка нулевого уровня: набор не вправе требовать усыновления того,
	// чего в фундаменте нет, не вправе нести возможность, провязку которой нечем
	// увидеть, и не вправе умолчать о единице счёта.
	if bad := r.VerifyCapabilities(root); len(bad) > 0 {
		for _, b := range bad {
			t.Errorf("набор возможностей: %s", b)
		}
		t.FailNow()
	}

	sv := foundationSurveyTree(t, root, r)

	// Предпосылки проверяются ДО вердикта по клеткам: на устаревшем заявлении
	// посредника все его вызывающие считались бы усыновившими, а на объявлении
	// обёртки без предмета из переписи исчез бы целый слушатель — в обоих
	// случаях перепись отчиталась бы зелёным ровно там, где возможность пропала.
	if bad := r.VerifyProviderClaims(sv.ProviderScan); len(bad) > 0 {
		for _, b := range bad {
			t.Errorf("заявление посредника: %s", b)
		}
		t.FailNow()
	}
	if bad := r.VerifyWrappers(sv.Markers, sv.Scans, sv.WrapperScan); len(bad) > 0 {
		for _, b := range bad {
			t.Errorf("объявление обёртки: %s", b)
		}
		t.FailNow()
	}

	cen := r.Adjudicate(sv.Dirs, sv.Scans, sv.Sites, sv.ProviderScan)
	t.Logf("рассмотрено каталогов-кандидатов %d, слушателями признаны %d: %v",
		len(sv.Candidates), len(sv.Dirs), sv.Dirs)
	t.Logf("мест сборки сервера %d: %v", len(cen.Sites), cen.Sites)
	t.Logf("%s", cen)

	for _, s := range cen.Stale {
		t.Errorf("ведомость пережила свой предмет: %s\n\n"+
			"Запись, которой больше нечего исключать, — находка: иначе ведомость становится "+
			"описанием несуществующего долга и ставит в очередь работу, которой не требуется.", s)
	}
	for _, f := range cen.Findings {
		t.Errorf("%s.\n\n"+
			"Исходов у клетки три: усыновить · записать отсутствие предмета с причиной · "+
			"записать пропуск с номером задачи. Четвёртого — «не несёт и не объяснил» — нет: "+
			"именно он делает усыновление функцией от чьей-то памяти.", f.Detail)
	}
}
