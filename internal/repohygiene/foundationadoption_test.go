// foundationServerMarkers — улика того, что каталог поднимает слушатель.
//
// Перечислены ВСЕ три формы сборки, живущие в дереве: голый конструктор
// библиотеки, конструктор фундамента и общий носитель. Одной формы мало: слушатель
// края собирается голым конструктором, и предикат по одному лишь носителю
// объявил бы край не слушателем — то есть вывел бы из переписи ровно ту
// поверхность, которая смотрит наружу.
var foundationServerMarkers = []string{
	"grpc.NewServer",
	"grpcsrv.NewServer",
	"servicehost.Serve",
}

