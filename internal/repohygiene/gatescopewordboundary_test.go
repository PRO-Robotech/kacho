// gatescopewordboundary_test.go — ГРАНИЦА СЛОВА СЧИТАЕТСЯ ПО РУНЕ, А НЕ ПО БАЙТУ.
//
// # Дефект, ради которого заведена эта проба
//
// Предикат границы проверял БАЙТ и считал словесным всякий байт со старшим
// битом. В тексте на русском такими байтами записаны не только буквы, но и
// кавычки-ёлочки, тире, неразрывные пробелы. А граница требуется с ОБЕИХ
// сторон — значит слово, стоящее вплотную за ёлочкой, не опознавалось, хотя
// разделитель после него стоял.
//
// Цена: девять файлов дерева перестали опознаваться, и среди неопознанных
// оказались строки шапки самого механизма — те, которыми он иллюстрирует
// обещание полноты. Коммит, задачей которого было сделать обещание равным
// измеренному, сам ввёл дефект в предикат.
//
// # Почему чинится КОРЕНЬ, а не называется шестая форма
//
// Назвать «слово за ёлочкой» шестой невидимой формой было бы законно по букве
// — и неверно по существу: это зафиксировало бы дефект как норму и оставило
// девять файлов неопознанными. Граница по руне снимает регрессию, возвращает
// девять файлов и делает правдой комментарий у предиката. Механизм чинится в
// механизме, а не объявляется в его границах.
package repohygiene

import (
	"strings"
	"testing"
)

// Слово, стоящее ВПЛОТНУЮ за небуквенной руной, опознаётся. Перечень форм
// закрыт и назван: это те разделители, которыми в этом дереве пишут по-русски.
func TestScopeWordBoundary_AWordAgainstANonASCIISeparatorIsFound(t *testing.T) {
	const word = "каждое"
	cases := []struct {
		name string
		text string
		want bool
	}{
		{"за открывающей ёлочкой", "обещает «каждое» вхождение", true},
		{"за тире", "обещает —каждое— вхождение", true},
		{"за неразрывным пробелом", "обещает каждое вхождение", true},
		{"в обычных пробелах", "обещает каждое вхождение", true},
		{"в начале строки", "каждое вхождение", true},
		{"в конце строки", "обещает каждое", true},
		{"за кавычкой-лапкой", "обещает „каждое“ вхождение", true},
		// Отрицательная половина: слово ВНУТРИ другого слова границей не
		// отделено и находкой быть не должно.
		{"часть длинного слова", "обещаеткаждоевхождение", false},
		{"с русской буквой слева", "ыкаждое вхождение", false},
		{"с русской буквой справа", "каждоеы вхождение", false},
	}
	found := 0
	for _, tc := range cases {
		got := containsWord(strings.ToLower(tc.text), word)
		if got != tc.want {
			t.Errorf("%s: предикат ответил %v, ожидалось %v (текст %q)",
				tc.name, got, tc.want, tc.text)
			continue
		}
		if tc.want {
			found++
		}
	}
	t.Logf("перепись: форм окружения проверено %d · положительных %d · отрицательных %d",
		len(cases), found, len(cases)-found)
}

// Вторая половина того же, и она о ДЕРЕВЕ, а не о синтетике: строки шапки
// самого механизма. Они и есть тот текст, ради которого предикат написан, и
// именно на них он молчал — все пять до починки.
//
// Строки взяты ДОСЛОВНО, а не прочитаны из файла: предмет здесь ФОРМА ЗАПИСИ,
// а не текущее содержимое соседа. Изменится она там — пробу обязано
// пересмотреть то же изменение.
func TestScopeWordBoundary_TheMechanismsOwnHeaderLinesAreRecognised(t *testing.T) {
	// Строки, несущие слово ВИДИМОЙ формы вплотную за ёлочкой. До починки не
	// опознавалась ни одна.
	carrying := []string{
		"// ИСПОЛНЯЕМОГО. Гейт обещает шапкой «всякое», «каждое», «ни одного вне», а",
		"\t\t// сюда. Дефект — когда шапка обещает полноту («всякое», «каждое», «ни",
		"// Ищется в КОММЕНТАРИЯХ, а не в строках: текст отказа, называющий «каждый»,",
	}
	recognised := 0
	for _, line := range carrying {
		if wordOfPerchenIn(line) == "" {
			t.Errorf("строка шапки механизма не опознана ни одним словом перечня: %q — "+
				"предикат молчит на том самом тексте, которым механизм иллюстрирует обещание "+
				"полноты", line)
			continue
		}
		recognised++
	}

	// ОТРИЦАТЕЛЬНАЯ ПОЛОВИНА, и она не послабление: эти две строки шапки
	// опознаваться НЕ ДОЛЖНЫ, и причина у каждой своя — она названа, а не
	// списана на границу слова.
	notCarrying := []struct {
		line string
		why  string
	}{
		{
			line: "// разделителем после него. НЕ ВИДНЫ пять: «ни один» · «все» · «исчерпывающий» ·",
			why: "несёт только слова ОБЪЯВЛЕННО НЕВИДИМЫХ форм («ни один», «все», " +
				"«исчерпывающий») — молчание здесь и есть объявленное поведение",
		},
		{
			line: "\t\t// одного вне»), а корень выписан: тогда «вне области 0» читается как",
			why: "оборот «ни одного» разорван переносом строки, а предикат судит ОДНУ строку " +
				"комментария: это форма «обещание, разорванное переносом», и она в перечне " +
				"невидимых не значилась — назвать её обязано то же изменение, что её заметило",
		},
	}
	for _, tc := range notCarrying {
		if w := wordOfPerchenIn(tc.line); w != "" {
			t.Errorf("строка опознана словом %q, а опознаваться не должна: %s (%q)",
				w, tc.why, tc.line)
		}
	}

	t.Logf("перепись: строк шапки проверено %d · несущих слово видимой формы %d, опознано %d · "+
		"не несущих %d (причины названы: объявленно невидимые формы · оборот, разорванный "+
		"переносом строки)",
		len(carrying)+len(notCarrying), len(carrying), recognised, len(notCarrying))
}

// wordOfPerchenIn — слово перечня, опознанное в строке; "" если ни одного.
func wordOfPerchenIn(line string) string {
	low := strings.ToLower(line)
	for _, w := range completenessWords {
		if containsWord(low, w) {
			return w
		}
	}
	return ""
}
