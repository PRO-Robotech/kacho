package repohygiene

// kanamemigratorshowcase.go — накатчик, названный на витрине Kaname, обязан быть
// накатчиком Kaname.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ — ВИТРИНА, а не дерево
//
// Критерий П3 эпика #2076 сформулирован со стороны клиента: «увидит ли это
// оператор чужого облака, НЕ ОТКРЫВАЯ наш исходный код». По полосе накатчика
// ответ был «да» сразу в пяти местах: спецификация пода (`kubectl describe`),
// клиентский документ установки, раздел «с чего начать» на сайте документации,
// перечень сторонних лицензий и текст отказа службы. То есть имя чужой
// платформы доезжало до арендатора ИНСТРУКЦИЕЙ, которую он обязан выполнить.
//
// Отсюда область, и она названа ТОЧНО, чтобы не читалась ни шире, ни у́же
// сделанного: судится ПОСТАВКА Kaname — дерево модуля, уезжающее арендатору
// целиком, плюс подчарт зонта, зовущий тот же путь. Внутри поставки витрина —
// подмножество (документы, чарты, тексты, которые печатает служба), а остальное
// (сборка, инженерные записки) имя ПРОИЗВОДИТ либо о нём УТВЕРЖДАЕТ. Разойтись
// им нельзя: производитель и употребитель, назвавшие разное, дают под, чей
// init-контейнер зовёт несуществующий путь, а записка, назвавшая снятое имя, —
// утверждение, пережившее свой предмет.
//
// Гейт по ВСЕМУ ДЕРЕВУ репозитория был бы неверен в обе стороны: он покраснел бы
// на шести службах платформы, законно делящих `kacho-migrator`, и на законном
// внутреннем упоминании внутри самой поставки (собственная инъекция, вердикт
// приёмки — оба изъяты ниже с причиной).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАКОННОЕ ИМЯ ВЫВОДИТСЯ, А НЕ ВЫПИСАНО
//
// Имя берётся у владельца имён — productnaming.MigratorBinary. Литерал здесь
// был бы вторым местом об одном предмете: он пережил бы следующее
// переименование молча, и гейт продолжал бы требовать имя, которого нет.
//
// Имя накатчика — ОДНО НА ПРОДУКТ, а не на службу: `kacho-migrator` у шести
// служб платформы, `kaname-migrator` у Kaname. Знание об одном накатчике обязано
// применяться к соседнему, поэтому различаются продукты, а не службы.
//
// ─────────────────────────────────────────────────────────────────────────────
// РАСПОЗНАВАТЕЛЬ СУДИТ ТОКЕН, А НЕ ПОДСТРОКУ
//
// Судится токен, оканчивающийся на `migrator`, и судится он ТОЛЬКО когда среди
// его сегментов, разделённых дефисом, стоит имя продукта дерева (перечень —
// productnaming.ProductNames). Иначе гейт краснел бы на `build-migrator` — цели
// сборки, которая имени платформы не несёт и предметом П3 не является.
//
// Сегментом, а не приставкой: `kacho-nlb-migrator` несёт имя платформы ВТОРЫМ
// словом от конца, и распознаватель, читающий только приставку, такую запись не
// отверг бы, а НЕ УВИДЕЛ — то есть дал бы молчание вместо находки.
//
// Форма ТОКЕНА, а не подстроки, закрывает три написания разом: голое имя
// (`kacho-migrator up`), путь установки (`/usr/local/bin/kacho-migrator`) и путь
// сборки (`bin/kacho-migrator`) — во всех трёх токен один и тот же.
//
// ОБЕ латинские формы имени платформы. Обычная и диакритическая; предикат,
// знающий одну, недобирает МОЛЧА (`printf 'Kachō\n' | grep -ci kacho` → 0).
// Сегодня диакритической формы рядом с накатчиком в дереве НОЛЬ — и это сказано
// числом, а не умолчанием: держатель остатка имени намерил шестнадцать файлов,
// невидимых ASCII-предикату ЦЕЛИКОМ, значит форма живая и слепота дорога́.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧЕГО ГЕЙТ НЕ СУДИТ — НАЗВАНО ЧИСЛОМ И ПРИЧИНОЙ, А НЕ ОГОВОРКОЙ
//
//  1. ПРОБЫ (`*_test.go`). Проба называет имя как ПРЕДМЕТ своей проверки, а
//     инъекция обязана вносить дефект настоящим именем — гейт, судящий
//     собственную инъекцию, не смог бы доказать, что способен упасть. Витриной
//     проба не является by construction: арендатору она не едет.
//  2. ОДОБРЕННАЯ ПРИЁМКА. Вердикт есть утверждение о РЕВИЗИИ, которую прочитал
//     проверяющий; механическая правка его не переносит. Та же граница, что у
//     держателя остатка имени, и по той же причине.
//  3. НАЛОЖЕНИЯ ЗНАЧЕНИЙ ЗОНТА (`deploy/helm/umbrella/values*.yaml`). Там
//     подчарты соседствуют в ОДНОМ файле, и форму вызова привязывает к подчарту
//     уже объявленный разбор (`internal/migratorapply`, TestEveryApplyPoint…).
//     Второй разбор той же привязки был бы вторым местом об одном предмете.
//  4. ИСПОЛНЯЕМАЯ ЧАСТЬ СОСЕДНИХ ПРОДУКТОВ. Что имя одно на продукт у ВСЕХ
//     семи точек наката, судит соседний гейт (migratoroperatorcli.go). Здесь —
//     только витрина Kaname.
//
// ─────────────────────────────────────────────────────────────────────────────
// «НОЛЬ НАХОДОК» ОТЛИЧИМО ОТ «НОЛЬ ПРОЧИТАННОГО»
//
// Перепись печатается ВСЕГДА, включая зелёный прогон, и несёт ДВЕ величины на
// каждую ось: сколько прочитано и сколько признано предметом. Пустой обход —
// ОТКАЗ: каталог витрины без единого отслеживаемого файла означает, что
// поверхность переехала, а гейт этого не заметил.

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/PRO-Robotech/kacho/internal/productnaming"
)

// kanameServiceDir — каталог исходников службы, чью витрину судит гейт.
const kanameServiceDir = "iam"

// KanameMigratorShowcaseRoots — поверхность, которой продукт говорит с
// оператором: дерево поставки службы и её подчарт в зонте.
//
// Подчарт зонта входит НЕ для полноты: путь двоичного файла производит один
// Dockerfile, а зовут его ДВА чарта. Односторонняя правка даёт под, чей
// init-контейнер зовёт несуществующий путь, — отказ приходит только в кластере
// и только на подъёме.
//
// Перечень объявлен ОДИН раз: и обход, и перепись, и инъекция читают отсюда.
var KanameMigratorShowcaseRoots = []string{
	"services/iam",
	"deploy/helm/umbrella/charts/kaname",
}

// kanameShowcaseExemptions — изъятия из витрины: приставка пути и причина.
//
// Перечнем с причиной, а не признаком формы: признак («файл объявляет
// константу») освободил бы и тех, кого гейт заводился ловить.
var kanameShowcaseExemptions = []struct{ Prefix, Reason string }{
	{"services/iam/docs/engineering/acceptance/",
		"одобренная приёмка: вердикт назван вместе со своей ревизией"},
}

// kanameShowcaseExempt — изъят ли путь из витрины, и по какой причине.
//
// Пробы изымаются по СУФФИКСУ имени, а не перечнем: перечень проб стареет с
// каждой новой, и стареет молча.
func kanameShowcaseExempt(rel string) (string, bool) {
	if strings.HasSuffix(rel, "_test.go") {
		return "проба: имя названо как предмет проверки, а инъекция вносит дефект настоящим именем", true
	}
	for _, ex := range kanameShowcaseExemptions {
		if strings.HasPrefix(rel, ex.Prefix) {
			return ex.Reason, true
		}
	}
	return "", false
}

// migratorBinaryTokenRe — токен, оканчивающийся на `migrator`.
//
// Класс символов включает дефис (сегменты имени), точку и подчёркивание (их
// допускает имя продукта) и диакритическую `ō`. Косой черты в классе НЕТ
// намеренно: она и есть граница между путём и именем, поэтому
// `/usr/local/bin/kacho-migrator` даёт токен `kacho-migrator`.
//
// `\b` на конце обязателен: без него `migratorcli` — имя ПАКЕТА разбора —
// читалось бы как имя двоичного файла.
var migratorBinaryTokenRe = regexp.MustCompile(`[A-Za-z0-9_.\x{014C}\x{014D}-]*migrator\b`)

// migratorTokenNamesAProduct — несёт ли токен имя продукта отдельным сегментом.
//
// Диакритическая форма приводится к обычной перед сверкой: перечень имён
// продуктов записан обычной, и сверка без приведения объявила бы диакритическую
// запись посторонним словом — то есть промолчала бы там, где обязана назвать.
func migratorTokenNamesAProduct(token string, products map[string]bool) bool {
	for _, seg := range strings.Split(token, "-") {
		// Регистр снимается ПЕРВЫМ: заглавная диакритическая форма (U+014C)
		// после приведения становится строчной, и замена ниже видит одну запись,
		// а не две.
		seg = strings.ReplaceAll(strings.ToLower(seg), "\u014d", "o")
		if seg != "migrator" && products[seg] {
			return true
		}
	}
	return false
}

// KanameMigratorShowcaseFinding — одно место витрины, называющее чужой накатчик.
type KanameMigratorShowcaseFinding struct {
	Rel  string
	Line int
	Name string
}

func (f KanameMigratorShowcaseFinding) String() string {
	return fmt.Sprintf("%s:%d — витрина называет накатчик %q, а накатчик этого продукта %q",
		f.Rel, f.Line, f.Name, productnaming.MigratorBinary(kanameServiceDir))
}

// KanameMigratorShowcaseCensus — объём осмотренного. Печатается ВСЕГДА.
type KanameMigratorShowcaseCensus struct {
	// FilesTracked — отслеживаемых файлов под корнями витрины.
	FilesTracked int
	// FilesExempt — из них изъятых, с разложением по причинам.
	FilesExempt   int
	ExemptReasons map[string]int
	// FilesRead — прочитано, то есть реально осмотрено.
	FilesRead int
	// TokensSeen — токенов формы `<X>-migrator` встречено.
	TokensSeen int
	// TokensJudged — из них признано ИМЕНЕМ накатчика (приставка есть имя
	// продукта дерева). Разность с TokensSeen — посторонние слова той же формы.
	TokensJudged int
	// TokensOwn — из признанных названо накатчиком ЭТОГО продукта.
	TokensOwn int
}

// kanameProductNameSet — имена продуктов дерева, приведённые к нижнему регистру.
func kanameProductNameSet() map[string]bool {
	out := map[string]bool{}
	for _, name := range productnaming.ProductNames() {
		out[strings.ToLower(name)] = true
	}
	return out
}

// KanameMigratorShowcaseScan судит витрину: files — путь → содержимое.
//
// Принимает готовый корпус, а не читает дерево само: инъекция подаёт
// синтетический корпус тем же входом, что и прогон по дереву, — иначе
// доказательство способности упасть проверяло бы другой код.
func KanameMigratorShowcaseScan(files map[string]string) ([]KanameMigratorShowcaseFinding, KanameMigratorShowcaseCensus) {
	census := KanameMigratorShowcaseCensus{
		FilesTracked:  len(files),
		ExemptReasons: map[string]int{},
	}
	products := kanameProductNameSet()
	own := productnaming.MigratorBinary(kanameServiceDir)

	var findings []KanameMigratorShowcaseFinding
	rels := make([]string, 0, len(files))
	for rel := range files {
		rels = append(rels, rel)
	}
	sort.Strings(rels)

	for _, rel := range rels {
		if reason, exempt := kanameShowcaseExempt(rel); exempt {
			census.FilesExempt++
			census.ExemptReasons[reason]++
			continue
		}
		census.FilesRead++
		for i, line := range strings.Split(files[rel], "\n") {
			for _, token := range migratorBinaryTokenRe.FindAllString(line, -1) {
				census.TokensSeen++
				if !migratorTokenNamesAProduct(token, products) {
					continue
				}
				census.TokensJudged++
				if token == own {
					census.TokensOwn++
					continue
				}
				findings = append(findings, KanameMigratorShowcaseFinding{
					Rel: rel, Line: i + 1, Name: token,
				})
			}
		}
	}
	return findings, census
}
