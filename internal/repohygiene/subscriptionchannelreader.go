// subscriptionchannelreader.go — разбор ЧТЕНИЙ КАНАЛА Postgres (задача #1416,
// DoD эпика #1016 п.4).
//
// # Предмет: оператор, а не слово
//
// Инвариант эпика — «ни один провязанный владелец не заводит СВОЕГО чтения
// канала; сервер потока живёт в pkg/subscription в единственном экземпляре».
// Предикат, которым его объявили, искал ПОДСТРОКУ `LISTEN` и потому отвечал
// «нет» независимо от состояния дерева: на базе волны он давал 17 файлов в
// services при одном настоящем операторе. Под него попадали
//
//   - `Listener` — РЕСУРС домена nlb и его permission-строки;
//   - `INTERNAL_LISTENER`, `LISTEN-feed`, `PER-LISTENER` — имена ручек и прозвища
//     слушателей в комментариях;
//   - проза, объясняющая само решение: «`LISTEN` требует своей сессии»;
//   - сгенерённые стабы, где слово стоит в именах служб.
//
// Оценивающий DoD прочитал бы по нему провал там, где инвариант держится, — то
// есть предикат ошибался в сторону ЛОЖНОГО ОТКАЗА.
//
// # Чем судит этот разбор
//
// СТРОКОВЫМ ЛИТЕРАЛОМ, который уезжает драйверу. `LISTEN` — глагол SQL, и
// исполнить его можно ровно одним способом: передать текстом в `Exec`. Литерал
// есть узел синтаксического дерева, поэтому комментарий, имя типа и имя
// константы исключены BY CONSTRUCTION, а не перечнем исключений, который
// пришлось бы вести.
//
// Граница слова несущая: `LISTENER` не совпадает с `LISTEN\b`, потому что после
// `LISTEN` стоит буква. Ровно это и отличает предмет от его имени.
//
// # Литерала НЕДОСТАТОЧНО — судится ГРАММАТИКА оператора
//
// Первая редакция этого разбора принимала всякий литерал, начинающийся с глагола,
// и немедленно поймала два места, где глагол стоит ПРОЗОЙ ВНУТРИ СТРОКИ:
//
//	fmt.Errorf("LISTEN: %w", err)      ← обёртка ошибки, а не оператор
//	log.Fatalf("listen %s: %v", …)     ← СЕТЕВОЙ слушатель, к каналу не относится
//
// То есть переход от подстроки к литералу снял комментарии и имена, но оставил
// формат-строки — предикат по-прежнему судил бы слово, только в другом месте.
//
// Поэтому за глаголом обязано следовать то, что следует за ним в SQL: конец
// строки (имя канала приклеивается конкатенацией), либо пробел, за которым либо
// ничего, либо НАЧАЛО ИМЕНИ (буква, подчёркивание или кавычка составного имени).
// `:` и `%` именами не начинаются — и обе прозаические формы отсеиваются не
// перечнем, а грамматикой.
//
// # Почему литерал, а НЕ «литерал внутри вызова Exec»
//
// Сужение до аргумента вызова точнее по форме и хуже по существу: оператор,
// вынесенный в константу (`const listenSQL = "LISTEN " + ch`), перестал бы
// находиться. Разбор по литералу ошибается в сторону НАХОДКИ, а не молчания, —
// и это верное направление ошибки для гейта.
//
// # Чего разбор НЕ видит — названо, а не спрятано
//
//  1. **оператор, собранный из кусков** (`"LIS"+"TEN "+ch`) — литерал целиком не
//     начинается с глагола. Форма умозрительная: в дереве её ноль, а писать её
//     незачем.
//  2. **оператор, пришедший извне** — имя, прочитанное из настройки или из базы.
//     Тогда чтения канала в исходнике нет вовсе, и судить нечего.
//  3. **`UNLISTEN`** — не чтение канала, а отписка от него; под `^LISTEN\b` не
//     подпадает и находкой не является.
package repohygiene

import (
	"go/ast"
	"go/parser"
	"go/token"
	"strconv"
	"strings"
)

// ChannelReadSite — координата чтения канала.
type ChannelReadSite struct {
	File string
	Line int
	// Operator — сам литерал, приведённый к одной строке: находка обязана
	// показывать то, что нашла, а не только место.
	Operator string
}

// ChannelReadCensus — объём осмотренного одним файлом.
//
// Литералы считаются отдельно от файлов: «ноль находок» на файлах, в которых не
// оказалось ни одной строки, сказано ни о чём.
type ChannelReadCensus struct {
	// Literals — строковых литералов осмотрено.
	Literals int
}

// ScanChannelReads находит чтения канала в одном файле.
func ScanChannelReads(rel string, src []byte) ([]ChannelReadSite, ChannelReadCensus, error) {
	var census ChannelReadCensus

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, rel, src, parser.SkipObjectResolution)
	if err != nil {
		return nil, census, err
	}

	var sites []ChannelReadSite
	ast.Inspect(file, func(n ast.Node) bool {
		lit, ok := n.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		census.Literals++

		value, err := strconv.Unquote(lit.Value)
		if err != nil {
			// Литерал, который не разбирается, судить нечем. Он остаётся
			// посчитанным переписью — иначе объём осмотренного завысился бы.
			return true
		}
		if !isChannelReadOperator(value) {
			return true
		}
		sites = append(sites, ChannelReadSite{
			File:     rel,
			Line:     fset.Position(lit.Pos()).Line,
			Operator: strings.Join(strings.Fields(value), " "),
		})
		return true
	})
	return sites, census, nil
}

// isChannelReadOperator отвечает, есть ли перед нами оператор чтения канала.
//
// Регистр не важен: SQL его не различает, и `listen ch` исполнится наравне с
// `LISTEN ch`. Именно поэтому одной границы слова мало — прозаическое
// `"listen %s: %v"` её проходит, — и за глаголом проверяется НАЧАЛО ИМЕНИ.
func isChannelReadOperator(value string) bool {
	const verb = "LISTEN"

	trimmed := strings.TrimLeft(value, " \t\r\n")
	if len(trimmed) < len(verb) || !strings.EqualFold(trimmed[:len(verb)], verb) {
		return false
	}

	rest := trimmed[len(verb):]
	if rest == "" {
		// Голый глагол: имя канала приклеивается конкатенацией. Принимается —
		// ошибка здесь идёт в сторону находки, а не молчания.
		return true
	}
	if !isSpace(rest[0]) {
		// `LISTENER`, `LISTEN:` — за глаголом стоит то, чего в операторе быть
		// не может.
		return false
	}

	tail := strings.TrimLeft(rest, " \t\r\n")
	if tail == "" {
		// `"LISTEN "` — каноничная форма этого дерева.
		return true
	}
	return isNameStart(tail[0])
}

// isSpace — пробельный знак, отделяющий глагол от имени канала.
func isSpace(b byte) bool {
	return b == ' ' || b == '\t' || b == '\r' || b == '\n'
}

// isNameStart — знак, с которого может начаться имя канала: буква,
// подчёркивание либо кавычка составного имени. Подстановка формат-строки (`%`)
// и двоеточие обёртки ошибки сюда не попадают.
func isNameStart(b byte) bool {
	switch {
	case b >= 'a' && b <= 'z', b >= 'A' && b <= 'Z', b == '_', b == '"':
		return true
	default:
		return false
	}
}
