// Имя в коде — ТОЛЬКО латиницей. Комментарии и тексты — на любом языке.
//
// # Зачем гейт, если это вопрос вкуса
//
// Не вкуса. Кириллица даёт ОМОГЛИФЫ — знаки, неотличимые от латинских на глаз:
// «В» и «B», «С» и «C», «Р» и «P», «А» и «A», «о» и «o». Имя, содержащее такой
// знак, выглядит обычным и не находится ни поиском, ни отбором по имени.
//
// Цена измерена, а не предположена. Пять проб разбора доступа назывались с
// кириллической «В», и отбор по видимому имени отвечал «no tests to run»: пробы
// существовали, были зелёными и НЕ ЗАПУСКАЛИСЬ тем, кто их звал. «Прогнал»
// молча означало «не прогнал», и отличить это можно было только счётом.
//
// # Что здесь, а что в фундаменте
//
// Сам разбор узлов-имён живёт в [github.com/PRO-Robotech/corelib/treehygiene]:
// он общий для платформы и службы доступа и до переезда лежал КОПИЕЙ в обоих
// деревьях — 17 совпавших строк кода из 34. Держателя у одинаковости не было ни
// одного (ban #20), и разойтись копии обязаны были молча.
//
// Здесь остаётся СВОЯ часть — область обхода ЭТОГО дерева: его корень, состав по
// индексу git и вычет чужого каталога зависимостей консоли. Область есть
// утверждение о своём дереве, и судить по ней чужое значило бы краснеть на чужом.
//
// Доказательство, что разбор различает ИМЯ и текст — что кириллица в
// комментарии, строке и ключе законна, а тот же знак, перенесённый в имя, есть
// находка, — стоит там же, где разбор, и здесь не повторяется: это ровно то
// второе место об одном предмете, ради снятия которого разбор и получил дом.
func TestIdentifiersAreASCII(t *testing.T) {
	t.Parallel()
	// ПРЕДПОСЫЛКА ОБХОДА: три исхода вместо одного зелёного.
	requireTreeWalkOverCorpus(t, repoRoot(t), treeWalkKeepGo, "файлов Go")
	root := repoRoot(t)

	out, err := gitenv.Command(root, "ls-files", "-z", "*.go").Output()
	if err != nil {
		t.Fatalf("git ls-files: %v — без переписи «ноль находок» неотличимо от "+
			"«ноль прочитанного»", err)
	}

	var filesRead, identsSeen int
	var findings []string

	for _, rel := range strings.Split(strings.TrimRight(string(out), "\x00"), "\x00") {
		if rel == "" || strings.Contains(rel, "/node_modules/") {
			continue
		}
		src, err := os.ReadFile(filepath.Join(root, rel)) // #nosec G304 — путь из индекса git
		if err != nil {
			continue
		}
		seen, found, err := treehygiene.ScanNonASCIIIdents(rel, src)
		if err != nil {
			// Неразбираемый файл — не находка: он и собраться не может, об этом
			// скажет сборка. Но и молчать о нём нельзя, иначе перепись завысит
			// объём осмотренного.
			t.Logf("не разобран (пропущен): %s: %v", rel, err)
			continue
		}
		filesRead++
		identsSeen += seen
		for _, f := range found {
			findings = append(findings, f.String())
		}
	}

	t.Logf("перепись: файлов Go прочитано %d, имён осмотрено %d, находок %d",
		filesRead, identsSeen, len(findings))

	if filesRead == 0 {
		t.Fatal("прочитано НОЛЬ файлов Go — перепись беспредметна, и «ноль находок» " +
			"означало бы «ноль прочитанного»")
	}
	// Провязка с разбором проверяется ЧИСЛОМ, а не тем, что он позван: разбор,
	// позванный не так, вернул бы ноль имён на каждом файле и оставил гейт
	// зелёным — «имена латинские» стало бы неотличимо от «разбор ничего не
	// увидел». Файлы прочитаны, значит имена в них есть by construction.
	if identsSeen == 0 {
		t.Fatalf("прочитано %d файлов Go и осмотрено НОЛЬ имён — разбор не увидел ни одного "+
			"узла-идентификатора: вердикт «находок нет» здесь ничего не утверждает", filesRead)
	}

	if len(findings) > 0 {
		t.Errorf("имя в коде обязано быть латинским — найдено %d:\n  %s\n\n"+
			"Кириллица даёт омоглифы: имя выглядит латинским и не находится ни поиском, "+
			"ни отбором по имени. Пробу с такой буквой нельзя выбрать через `-run`, и "+
			"«прогнал» молча означает «не прогнал».\n"+
			"Комментарии и тексты сообщений правило НЕ ограничивает.",
			len(findings), strings.Join(findings, "\n  "))
	}
}
