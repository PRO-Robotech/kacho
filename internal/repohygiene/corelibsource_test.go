// corelibsource_test.go — общий помощник для гейтов, чей предмет ПЕРЕЕХАЛ из
// каталога дерева в модуль общего фундамента (`github.com/PRO-Robotech/corelib`).
//
// # Предмет
//
// Свойство, которое такой гейт стерёг, не исчезло — оно объявляется всё так же
// в единственном месте, но это место теперь не отслеживаемый файл дерева, а
// пакет модуля, закреплённого `go.mod`. Гейт, продолжающий искать владельца
// только в дереве, «беспредметен»: он молчит и тогда, когда объявление
// переехало, и тогда, когда пропало вовсе, — различить эти два случая по его
// молчанию нельзя.
//
// Помощник читает объявление ТУДА, куда оно переехало: резолвит версию
// `corelib`, закреплённую судимым деревом, и отдаёт не-тестовые файлы Go
// названного пакета из кэша модулей.
//
// # Почему ОТКАЗ, а не пустой список
//
// Модуль, не извлечённый в кэш (`go mod download` не выполнялся), и пакет,
// переименованный внутри модуля, — это РАЗНЫЕ события, но оба дают одно и то же
// пустое множество, если тут промолчать. Тогда «объявления не стало» и «кэш не
// наполнен» становятся неотличимы, а гейт, беспредметный по второй причине,
// выглядел бы нашедшим первую. Поэтому оба пути завершаются `t.Fatalf`, а не
// пустым срезом: гейт, не сумевший прочитать владельца, обязан упасть сам, а не
// молча решить, что предмета не стало.
//
// # Синтетический путь — не подмена дерева, а его отличимая координата
//
// Файлам, прочитанным из кэша, помощник даёт путь вида `corelib/<pkg>/<файл>`.
// Он не совпадает ни с одним путём индекса git (там нет каталога `corelib/`) и
// поэтому однозначно опознаётся классификацией «владелец / вне владельца» по
// префиксу, принятой во всех гейтах этого пакета: обновить нужно только
// константу-владельца, а не код классификации.
package repohygiene

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// corelibModulePath — путь модуля общего фундамента. Один на все гейты этого
// класса: второе написание разошлось бы с этим молча при переносе.
const corelibModulePath = "github.com/PRO-Robotech/corelib"

// corelibModuleDir — каталог модуля `corelib` в кэше модулей Go, разрешённый по
// версии, которую закрепляет go.mod судимого дерева. Версия возвращается
// отдельно — она нужна текстам отказа, чтобы читатель понимал, какую ревизию
// проверка читала.
func corelibModuleDir(t *testing.T, root string) (dir, version string) {
	t.Helper()
	body, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatalf("чтение go.mod: %v", err)
	}
	for _, dep := range ParseGoModRequires(string(body)) {
		if dep.Path != corelibModulePath {
			continue
		}
		return ModuleCacheDir(moduleCacheDir(t), dep), dep.Version
	}
	t.Fatalf("go.mod не закрепляет %s — общий фундамент не резолвится, гейту нечем "+
		"проверить перенесённое объявление", corelibModulePath)
	return "", ""
}

// corelibPackageGoFiles — не-тестовые файлы Go ОДНОГО пакета общего фундамента
// (например "tokenpolicy" либо "db/pgfault"), по имени каталога ОТНОСИТЕЛЬНО
// корня модуля. Обход НЕ рекурсивный: вложенные пакеты (скажем,
// "modulemanifest/producer") — другой пакет с другим предметом, и подмешивать
// его сюда значило бы судить не то, что названо.
//
// Ключ отдаваемой карты — синтетический путь `corelib/<pkg>/<файл>`, а не
// абсолютный путь кэша: версия модуля в имени файла не участвует, поэтому её
// бамп не меняет текст находок, а сравнение путей в вызывающих гейтах остаётся
// простым префиксом.
func corelibPackageGoFiles(t *testing.T, root, pkg string) map[string][]byte {
	t.Helper()
	dir, version := corelibModuleDir(t, root)
	pkgDir := filepath.Join(dir, filepath.FromSlash(pkg))
	entries, err := os.ReadDir(pkgDir)
	if err != nil {
		t.Fatalf("каталог %s общего фундамента (%s@%s) не читается: %v — модуль не "+
			"извлечён в кэш модулей (`go mod download`), либо пакет переехал внутри "+
			"модуля. Гейт беспредметен: отличить «кэш не наполнен» от «объявления не "+
			"стало» по пустому списку нельзя, поэтому он падает сам.",
			pkg, corelibModulePath, version, err)
	}
	var names []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	out := make(map[string][]byte, len(names))
	for _, name := range names {
		src, rerr := os.ReadFile(filepath.Join(pkgDir, name))
		if rerr != nil {
			t.Fatalf("файл %s/%s общего фундамента (%s@%s) не читается: %v",
				pkg, name, corelibModulePath, version, rerr)
		}
		out["corelib/"+pkg+"/"+name] = src
	}
	if len(out) == 0 {
		t.Fatalf("в %s общего фундамента (%s@%s) не нашлось ни одного не-тестового файла "+
			"Go — каталог пуст либо весь пакет составляют тесты. Гейт беспредметен ровно "+
			"тем же способом, что и на несуществующем каталоге.",
			pkg, corelibModulePath, version)
	}
	return out
}
