package repohygiene

// membershiporacle_test.go — гейт IAM-ID-2-15: вопроса «в каких аккаунтах
// состоит этот человек» на публичной поверхности iam нет — ни параметром, ни
// термом фильтра, ни арифметикой.
//
// Предмет, устройство трёх полос и границы гейта изложены ОДИН раз — в шапке
// `membershiporacle.go`; здесь они не пересказываются, иначе завелись бы два
// места об одном предмете.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. чтение действительно отвечает на запретный вопрос → его форма меняется:
//     аккаунт становится обязательным ЛИБО ответ сужается пообъектно правами
//     вызывающего;
//  2. чтение гасит условие «г» доказанным сужением → запись в
//     `oracleQuenchedByNarrowing` вместе с КООРДИНАТОЙ доказательства, которую
//     гейт проверяет;
//  3. чтение признано дефектом продукта → задача заводится, и послабление
//     объявляется в `oracleDeclaredAllowances` СО ССЫЛКОЙ на неё.
//
// Молчаливое исключение из полосы запрещено: оно было бы маской, а не близнецом.

import (
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

func TestMembershipOracle_TheQuestionIsNotAskableOnThePublicSurface(t *testing.T) {
	root := repoRoot(t)
	tree, err := treecorpus.NewTree(root)
	if err != nil {
		t.Fatalf("состав дерева не собран: %v", err)
	}

	c, err := SurveyMembershipOracle(tree)
	if err != nil {
		t.Fatalf("обход дерева: %v", err)
	}

	// ── ПЕРЕПИСЬ. «Ноль находок» обязано быть отличимо от «ноль прочитанного»
	// И от «ноль распознанного»: сломанный обход и сгнивший разбор дают
	// одинаково зелёный вердикт.
	t.Logf("перепись: файлов контрактов %d · сообщений %d · RPC распознано %d · "+
		"из них публичных чтений %d · рассмотрено полосой A %d, полосой B %d, полосой C %d",
		c.ProtoFiles, c.Messages, c.RPCs, c.PublicReads, c.LaneASeen, c.LaneBSeen, c.LaneCSeen)
	// Предпосылка полосы C печатается ОБЪЁМОМ, а не только исходом: деривация
	// переезжает между файлами при каждом своде миграций, и «признака нет»
	// обязано быть отличимо от «читать было нечего».
	t.Logf("предпосылка полосы C: корпус %s — файлов прочитано %d, деривация найдена %v",
		oracleMembershipIDCorpus, c.IDCorpusFiles, c.IDComputable)

	// Две величины, которые суть РЕШЕНИЯ, а не измерения. Без них «ноль находок»
	// неотличимо от «не дошёл».
	t.Logf("глубина обхода вложенных сообщений (условие «б») %d · усечено на ней сообщений %d%s",
		c.Depth, len(c.TruncatedAt), oracleTruncSuffix(c.TruncatedAt))
	t.Logf("словарь условия «б» ЦЕЛИКОМ: %v (плюс типы %v) — имя, которого в нём нет, "+
		"делает поле невидимым для полосы", c.Dictionary, oracleAccountTypes)
	t.Logf("формы, которыми запрос называет человека (условие «а»): поле %v либо тот же "+
		"сегмент пути — читаются ОБЕ", oracleSubjectFields)

	// Связывание белых списков печатается: читатель обязан видеть, ЧТО именно
	// сопоставлено, а не верить, что сопоставлено верно.
	for _, w := range c.Whitelists {
		bound := w.Bound
		if bound == "" {
			bound = "СВЯЗАТЬ НЕЧЕМ"
		}
		t.Logf("  белый список %s:%d термы %v → %s", w.File, w.Line, w.Terms, bound)
	}

	// ── ПРЕДПОСЫЛКИ ГЕЙТА. Пустой обход — ОТКАЗ, а не успех.
	if c.ProtoFiles == 0 || c.Messages == 0 {
		t.Fatal("контрактов iam не прочитано ни одного: разбор перестал распознавать " +
			"объявления либо каталог переехал. «Совпало» здесь означает «не с чем сравнивать»")
	}
	if c.PublicReads == 0 {
		t.Fatal("публичных чтений не распознано ни одного — предикат устарел: чтения " +
			"человека, аккаунта и выдач существуют, и ноль здесь означает сломанный обход")
	}
	if c.LaneBSeen == 0 {
		t.Fatal("белых списков фильтра не найдено ни одного — полоса B рассматривает пустоту")
	}

	// Предпосылка полосы C названа рядом с ней и ПРОВЕРЯЕТСЯ: перестанет
	// идентификатор быть вычислимым — запрет обязан быть ПЕРЕСМОТРЕН, а не
	// унаследован молча.
	if c.IDCorpusFiles == 0 {
		t.Errorf("корпус миграций %s не прочитан НИ ОДНИМ файлом — предпосылка полосы C "+
			"не проверена, а не опровергнута. «Признака нет» и «читать было нечего» "+
			"обязаны различаться", oracleMembershipIDCorpus)
	} else if !c.IDComputable {
		t.Errorf("предпосылка полосы C больше не верна: идентификатор членства "+
			"перестал выводиться из пары «человек:аккаунт» (ни один из %d файлов корпуса "+
			"%s не несёт %q). Полоса C держалась ИМЕННО этим — пересмотрите её вместе с "+
			"предпосылкой, а не оставляйте по наследству",
			c.IDCorpusFiles, oracleMembershipIDCorpus, oracleMembershipIDMark)
	}

	// ── ГАСЯЩИЕ ЗАПИСИ. Каждая обязана нести доказательство, живое в дереве.
	for _, p := range SurveyOracleQuenchProofs(tree) {
		if !p.Found {
			t.Errorf("гасящая запись %s потеряла доказательство: признак сужения в %s "+
				"больше не находится. Гейт лишился единственного основания не краснеть "+
				"на этом чтении — близнец обязан быть ЗАМЕНЁН, а не унаследован",
				p.FQN, p.File)
			continue
		}
		t.Logf("  гасит условие «г»: %s — доказательство живо (%s)", p.FQN, p.File)
	}

	// ── ПОСЛАБЛЕНИЯ. Печатаются ВСЛУХ и самоистекают в обе стороны.
	declared := OracleAllowanceNames()
	t.Logf("объявленных послаблений %d: %v; сработало на этом дереве %d: %v",
		len(declared), declared, len(c.Allowed), c.Allowed)
	for _, a := range oracleDeclaredAllowances {
		hit := false
		for _, got := range c.Allowed {
			if strings.HasSuffix(got, a.FQN) {
				hit = true
			}
		}
		if !hit {
			t.Errorf("послаблению %s (#%d) больше нечего прощать: на этом дереве оно "+
				"находкой не является. Снимите запись — послабление без предмета "+
				"переживает то, ради чего заведено, и следующий читатель примет его "+
				"за действующее основание", a.FQN, a.Issue)
		}
	}

	// ── НАХОДКИ.
	for _, f := range c.Findings {
		t.Errorf("полоса %s · %s (%s): %s", f.Lane, f.FQN, f.File, f.Why)
	}
}

func oracleTruncSuffix(trunc []string) string {
	if len(trunc) == 0 {
		return ""
	}
	return " — часть ответов осмотрена НЕ ДО КОНЦА: " + strings.Join(trunc, ", ")
}
