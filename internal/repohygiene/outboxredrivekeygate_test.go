package repohygiene

// Возврат отравленных строк и дренаж обязаны упорядочивать ОДНУ очередь ОДНИМ
// ключом.
//
// # Почему это одно правило, а не два совпадения
//
// Правило целиком звучит так: «строка не применяется мимо другой строки той же
// партиции». У него две половины, и они живут в разных механизмах:
//
//	дренаж   — не берёт строку, пока в её партиции есть ДОСТАВЛЯЕМЫЙ
//	           предшественник с меньшим идентификатором;
//	возврат  — не поднимает отравленную строку, если в её партиции уже есть
//	           ДОСТАВЛЕННЫЙ преемник.
//
// Заявка дренажа о доставленных строках не говорит ничего — доставленная строка
// покидает набор доставляемых, — поэтому вторую половину несёт возврат. На
// РАЗНЫХ ключах каждая половина стережёт партицию, которой не стережёт другая, и
// видимое следствие конкретно: выдача, поднятая мимо своего уже доставленного
// отзыва, применяется поверх него, и снятое право возвращается. У кортежа прав
// надгробия нет — сравнивать повторной записи не с чем.
//
// # Почему гейт по дереву, а не проба у сервиса
//
// Пара проверяется парной пробой у iam, и это верно ДЛЯ IAM. Свойство же тут —
// свойство ДЕРЕВА: оно обязано выполняться у очереди, которую заведут завтра, в
// сервисе, которого сегодня нет. Перечень пообъектных проб такого не держит —
// он молчит ровно там, где пробу забыли написать.
//
// Ключи резолвятся разбором исходника (тем же инвентарём, что читают гейты
// наблюдаемости и порядка), поэтому имя, вычисляемое в рантайме, для гейта
// неотличимо от отсутствующего — и это называется вслух ниже, а не проглатывается.

import (
	"sort"
	"strings"
	"testing"
)

// TestRedriveAndDrainKeyTheSameOutboxTheSameWay — две половины одного правила
// обязаны стоять на одном ключе.
func TestRedriveAndDrainKeyTheSameOutboxTheSameWay(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	// Предпосылка обхода. «Ноль находок» обязано быть отличимо от «ноль
	// прочитанного», а для ЭТОГО гейта — ещё и от «ни одного возврата в дереве»:
	// распознавание literal-а reconciler.Config могло сломаться, и тогда молчание
	// не значит ничего.
	if inv.filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одного файла composition root — предпосылка "+
			"обхода сломана (корень %s)", root)
	}
	if len(inv.redrive) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ очереди с возвратом отравленных строк в %d "+
			"прочитанных файлах — распознавание сломано (ищется композитный литерал "+
			"reconciler.Config с полем Table)", inv.filesRead)
	}

	tables := make([]string, 0, len(inv.redrive))
	for table := range inv.redrive {
		tables = append(tables, table)
	}
	sort.Strings(tables)

	var paired, orphan int
	for _, table := range tables {
		redriveKey, hasRedriveKey := inv.redrivePartition[table]
		if !hasRedriveKey {
			// Ключ обязателен полем настройки: reconciler.NewRedriveOnly не
			// строится без него. Дойти сюда можно только через выражение, которое
			// разбор исходника не восстанавливает, — и тогда гейт эту проводку не
			// видит, а молчал бы о ней «чисто».
			t.Errorf("%s: возврат поднят в %s, но его ключ партиции не резолвится "+
				"разбором исходника — гейт не может сверить его с ключом дренажа и "+
				"молчал бы об этой очереди. Назови ключ строковой константой (той же, "+
				"что стоит в конфигурации дренажа), а не выражением времени выполнения.",
				table, strings.Join(inv.redrive[table], ", "))
			continue
		}

		drainKey, drained := inv.partition[table]
		if _, isDrained := inv.drained[table]; !isDrained {
			// Возврат без дренажа — это подъём строк, которые никто не применяет.
			orphan++
			t.Errorf("%s: возврат отравленных строк поднят (%s), а дренажа у этой "+
				"очереди нет ни одного — поднятые строки применять некому.",
				table, strings.Join(inv.redrive[table], ", "))
			continue
		}
		if !drained {
			t.Errorf("%s: возврат объявляет ключ порядка %q, а дренаж той же очереди "+
				"ключа не задаёт вовсе, то есть заявляет коммутативность потока. Одно "+
				"из двух утверждений неверно: либо порядок значим — и тогда его обязан "+
				"держать дренаж, либо не значим — и тогда возврату нечего стеречь.",
				table, redriveKey)
			continue
		}
		if redriveKey != drainKey {
			t.Errorf("%s: ключ порядка разошёлся — дренаж %q, возврат %q. Заявка "+
				"стережёт ДОСТАВЛЯЕМОГО предшественника, возврат — ДОСТАВЛЕННОГО "+
				"преемника; на разных ключах каждая половина стережёт партицию, которой "+
				"не стережёт другая, и строка, поднятая мимо своего доставленного "+
				"преемника, отменяет его. Проводка: дренаж %s, возврат %s.",
				table, drainKey, redriveKey,
				strings.Join(inv.drained[table], ", "), strings.Join(inv.redrive[table], ", "))
			continue
		}
		paired++
	}

	// Перепись — отдельное утверждение: без неё «пройдено» неотличимо от
	// «рассмотрено ноль пар».
	lines := make([]string, 0, len(tables))
	for _, table := range tables {
		lines = append(lines, table+" → "+inv.redrivePartition[table])
	}
	t.Logf("прочитано файлов composition root: %d; очередей с дренажом: %d; из них с "+
		"возвратом отравленных строк: %d; ключи сошлись у %d\n  %s",
		inv.filesRead, len(inv.drained), len(inv.redrive), paired,
		strings.Join(lines, "\n  "))
}

// outboxRedriveDebt — очереди, которые дренятся и травят строки, но возврата
// отравленных пока не имеют. Это ДОЛГ С ПРЕДМЕТОМ, а не обоснование: у обеих
// записей потеря названа и заведена задачей.
//
// Запись живёт, пока у неё есть предмет, и истекает С ДВУХ сторон: очередь
// исчезла из дерева — запись удалить; у очереди появился возврат — запись
// удалить. Обе проверки ниже. Перечень, которому нечего исключать, — не
// поломка: гейт на пустом перечне ПРОХОДИТ, объявляя перепись, потому что
// пустой перечень и есть цель, ради которой он заведён.
var outboxRedriveDebt = map[string]string{
	"kacho_iam.subject_change_outbox": "" +
		"kacho#455. Доставляет краю инвалидацию кэша решений о доступе: " +
		"недоставленная строка означает, что край продолжает отвечать по устаревшему " +
		"вердикту — ровно тот эффект, ради предотвращения которого очередь заведена. " +
		"Событие возврата (что именно способно превратить постоянный отказ в " +
		"проходящую доставку) у этой очереди ещё не названо, а привязывать возврат к " +
		"таймеру запрещено той же причиной, что и у очереди tuple'ов.",
	"kacho_iam.provider_compensation_outbox": "" +
		"kacho#455. Несёт снятия у внешнего провайдера: недоставленная строка " +
		"означает, что снятое у нас осталось выданным у него. Возможно, возврат тут " +
		"вообще не нужен — отказ «объекта нет» правильнее классифицировать " +
		"идемпотентным успехом, и тогда травиться будет нечему; решение принимается " +
		"в задаче, а не здесь.",
}

// TestEveryPoisoningOutboxHasARedrive — травление корректно ТОЛЬКО там, где
// отравленную строку кто-то возвращает в работу.
//
// Отравленная строка выбывает из блокирующего набора заявки — её партиция
// разблокируется, ради этого травление и делается, — но сама после этого не
// берётся никогда. Комментарий классификатора в общей библиотеке говорит это
// прямо; до 2026-08-16 условие не выполнялось у очереди tuple'ов kacho-iam, и
// невыполнение было НЕВИДИМО: обе стороны выглядели исправно.
//
// Гейт рассматривает КАЖДУЮ дренируемую очередь, а не только упорядоченную.
// Первая редакция отбирала по объявленному ключу порядка — и это был неверный
// признак: коммутативность говорит о ПОРЯДКЕ, а не о ПОТЕРЕ. Две коммутативные
// очереди теряют строки ровно так же, и обе стоят в перечне долга выше.
func TestEveryPoisoningOutboxHasARedrive(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if len(inv.drained) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ дренируемой очереди в %d прочитанных файлах — "+
			"предмета нет, распознавание сломано", inv.filesRead)
	}

	tables := make([]string, 0, len(inv.drained))
	for table := range inv.drained {
		tables = append(tables, table)
	}
	sort.Strings(tables)

	var covered, owed int
	for _, table := range tables {
		if _, ok := inv.redrive[table]; ok {
			covered++
			continue
		}
		if why, declared := outboxRedriveDebt[table]; declared {
			if strings.TrimSpace(why) == "" {
				t.Errorf("запись долга %s без обоснования: обязана называть, ЧТО теряется "+
					"и где заведена задача", table)
			}
			owed++
			continue
		}
		t.Errorf("%s: очередь дренится (%s), но возврата отравленных строк у неё нет. "+
			"Отравленная строка выбывает из блокирующего набора заявки и после этого не "+
			"берётся НИКОГДА — временная причина отказа становится бессрочной потерей "+
			"намерения. Подними reconciler.NewRedriveOnly на той же таблице и с тем же "+
			"ключом, либо заведи запись в outboxRedriveDebt с названной потерей и задачей.",
			table, strings.Join(inv.drained[table], ", "))
	}

	t.Logf("дренируемых очередей: %d; с возвратом отравленных строк: %d; в объявленном "+
		"долге: %d", len(tables), covered, owed)
}

// TestRedriveDebtEntriesHaveSubject — запись долга истекает С ДВУХ сторон.
//
// Одна сторона обычная: очередь исчезла из дерева — исключать нечего. Вторая —
// та, ради которой перечень и заведён: у очереди ПОЯВИЛСЯ возврат, и запись
// пережила свой предмет. Именно так исключение начинает лгать, оставаясь
// зелёным: следующий читатель видит очередь в списке долга и не проверяет, что
// долг уже закрыт.
func TestRedriveDebtEntriesHaveSubject(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	for table := range outboxRedriveDebt {
		if _, ok := inv.drained[table]; !ok {
			t.Errorf("запись долга %s больше не имеет предмета: такой дренируемой очереди "+
				"в дереве нет. Удали запись.", table)
			continue
		}
		if _, ok := inv.redrive[table]; ok {
			t.Errorf("запись долга %s пережила свой предмет: у очереди ЕСТЬ возврат "+
				"отравленных строк (%s). Удали запись — иначе перечень долга объявляет "+
				"закрытое открытым.", table, strings.Join(inv.redrive[table], ", "))
		}
	}

	t.Logf("записей долга: %d (пустой перечень — цель, а не поломка)", len(outboxRedriveDebt))
}
