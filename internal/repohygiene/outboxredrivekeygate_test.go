// применения, но возврата отравленных строк пока не имеют. Запись — долг с
// предметом, а не обоснование: она обязана называть, ЧТО теряется и где заведена
// задача.
//
// ПЕРЕЧЕНЬ ПУСТ, и это его цель, а не временное состояние. Две записи, стоявшие
// здесь до 2026-08-16 (kacho#455), сняты не постройкой возврата, а тем, что у их
// очередей исчез предмет: обе объявили PermanentPolicy: drainer.RetryPermanent и
// перестали травить отказ применения. Полный разбор — у гейта ниже.
//
// Запись живёт, пока у неё есть предмет, и истекает С ДВУХ сторон: очередь
// исчезла из дерева — запись удалить; у очереди появился возврат — запись
// удалить. Обе проверки в TestRedriveDebtEntriesHaveSubject. Гейт на пустом
// перечне ПРОХОДИТ, объявляя перепись: пустой перечень и есть то, ради чего он
// заведён.
var outboxRedriveDebt = map[string]string{}

// TestEveryPoisoningOutboxHasARedrive — травление корректно ТОЛЬКО там, где
// отравленную строку кто-то возвращает в работу.
//
// Отравленная строка выбывает из блокирующего набора заявки — её партиция
// разблокируется, ради этого травление и делается, — но сама после этого не
// берётся никогда. Комментарий классификатора в общей библиотеке говорит это
// прямо; до 2026-08-16 условие не выполнялось у очереди tuple'ов kacho-iam, и
// невыполнение было НЕВИДИМО: обе стороны выглядели исправно.
//
// Гейт рассматривает каждую очередь, которая МОЖЕТ отравить строку по отказу
// ПРИМЕНЕНИЯ, — и отбирает их по объявленной политике, а не по ключу порядка.
//
// # Две редакции признака, обе неверные, и почему
//
// Первая редакция отбирала по объявленному ключу порядка. Неверно: коммутативность
// говорит о ПОРЯДКЕ, а не о ПОТЕРЕ — коммутативная очередь теряет строки ровно
// так же.
//
// Вторая рассматривала КАЖДУЮ дренируемую очередь и держала две коммутативные в
// перечне долга. Тоже неверно, но тоньше: у такой очереди возврат нельзя ни
// построить, ни осмыслить. Построить — потому что возврат отравленных строк
// собирается вокруг ключа партиции, которого у неё нет; осмыслить — потому что
// сам смысл травления в разблокировке партиции, и там, где партиции нет,
// травление не покупает НИЧЕГО, платя полной ценой. Запись долга требовала
// работы, которая не могла быть сделана правильно, — то есть была не долгом, а
// вечным исключением.
//
// Верный признак — что очередь ДЕЛАЕТ с постоянным отказом (kacho#455):
//
//	травит  → обязана иметь возврат, иначе намерение теряется навсегда;
//	повторяет → возврат не нужен и не имеет предмета: терять нечего.
//
// Признак читается из дерева (`drainer.Config.PermanentPolicy`), а не
// объявляется здесь, поэтому очередь, сменившая политику, немедленно меняет и
// требование к себе.
func TestEveryPoisoningOutboxHasARedrive(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if len(inv.drained) == 0 {
		t.Fatalf("гейт не нашёл НИ ОДНОЙ дренируемой очереди в %d прочитанных файлах — "+
			"предмета нет, распознавание сломано", inv.filesRead)
	}

	tables := make([]string, 0, len(inv.drained))
	for table := range inv.drained {
		tables = append(tables, table)
	}
	sort.Strings(tables)

	var covered, owed, retrying int
	for _, table := range tables {
		if _, ok := inv.redrive[table]; ok {
			covered++
			continue
		}
		if _, ok := inv.retryPermanent[table]; ok {
			// Очередь не травит постоянный отказ применения — возврату нечего
			// возвращать. Что при этом остаётся единственным путём отравления
			// (отказ РАЗБОРА) и что он закрыт ограничениями схемы, проверяет
			// TestRetryPermanentQueuesCannotBePoisonedByDecode ниже.
			retrying++
			continue
		}
		if why, declared := outboxRedriveDebt[table]; declared {
			if strings.TrimSpace(why) == "" {
				t.Errorf("запись долга %s без обоснования: обязана называть, ЧТО теряется "+
					"и где заведена задача", table)
			}
			owed++
			continue
		}
		t.Errorf("%s: очередь дренится (%s) и травит постоянный отказ применения, но "+
			"возврата отравленных строк у неё нет. Отравленная строка выбывает из "+
			"блокирующего набора заявки и после этого не берётся НИКОГДА — временная "+
			"причина отказа становится бессрочной потерей намерения. Есть три исхода: "+
			"подними reconciler.NewRedriveOnly на той же таблице и с тем же ключом; "+
			"либо, если поток коммутативен, объяви PermanentPolicy: drainer.RetryPermanent "+
			"— травление у такой очереди не покупает ничего; либо заведи запись в "+
			"outboxRedriveDebt с названной потерей и задачей.",
			table, strings.Join(inv.drained[table], ", "))
	}

	t.Logf("дренируемых очередей: %d; с возвратом отравленных строк: %d; не травящих "+
		"постоянный отказ применения: %d; в объявленном долге: %d",
		len(tables), covered, retrying, owed)
}

// TestRetryPermanentQueuesCannotBePoisonedByDecode — у очереди, отказавшейся
// травить постоянный отказ применения, ЕДИНСТВЕННЫЙ оставшийся путь отравления
// закрыт ОГРАНИЧЕНИЕМ СХЕМЫ.
//
// # Почему это обязательно, а не «и так понятно»
//
// Политика повтора снимает травление по отказу ПРИМЕНЕНИЯ и НЕ снимает его по
// отказу РАЗБОРА — и не должна: тело строки не станет разбираемым ни от какого
// события. Значит утверждение «травиться нечему» держится ровно на одном факте:
// неразбираемую строку НЕЛЬЗЯ ЗАПИСАТЬ. Факт этот принадлежит схеме владельца
// очереди, а не коду дренажа, поэтому проверять его надо здесь.
//
// Без этой пробы предыдущий гейт стал бы способом ЗАМОЛЧАТЬ потерю: объявил
// политику повтора — и очередь вышла из-под требования, сохранив живой путь
// отравления.
//
// # Что именно утверждается
//
// Миграции сервиса, которому принадлежит очередь, обязаны нести для её таблицы
// ограничение непустоты тела (`payload … NOT NULL`) и ограничение его формы
// (`CHECK` над `payload`). Оба — предпосылки того, что декодер не встретит
// строки, на которой откажет.
//
// Проверка НАМЕРЕННО грубая: она утверждает наличие ограничений, а не их
// достаточность. Достаточность — свойство пары «декодер ↔ схема», и её
// доказывает интеграционная проба владельца, вставляющая каждую негодную форму и
// требующая отказа базы (services/iam/internal/migrations). Здесь стоит то, что
// проверяемо по дереву и что первым сломается при заведении следующей такой
// очереди.
func TestRetryPermanentQueuesCannotBePoisonedByDecode(t *testing.T) {
	root := repoRoot(t)
	inv := outboxWiringInventory(t, root)

	if len(inv.retryPermanent) == 0 {
		// Пустой перечень — не поломка: очередей с такой политикой может не быть
		// вовсе. Но и молчать об этом нельзя, иначе «ноль находок» неотличимо от
		// «признак перестал распознаваться».
		t.Logf("очередей с политикой повтора: 0 (признак читается из drainer.Config.PermanentPolicy)")
		return
	}

	tables := make([]string, 0, len(inv.retryPermanent))
	for table := range inv.retryPermanent {
		tables = append(tables, table)
	}
	sort.Strings(tables)

	body, filesRead := migrationCorpus(t, root)
	if filesRead == 0 {
		t.Fatalf("гейт не прочитал ни одной миграции — предпосылка обхода сломана, "+
			"молчание ничего не доказывает (корень %s)", root)
	}

	for _, table := range tables {
		_, bare := splitQualifiedTable(table)
		stmts := statementsAbout(body, bare)
		if len(stmts) == 0 {
			t.Errorf("%s: в миграциях дерева нет ни одного оператора об этой таблице — "+
				"утверждение «неразбираемую строку нельзя записать» проверить НЕЧЕМ. "+
				"Либо имя разошлось, либо очередь заводится не миграцией.", table)
			continue
		}
		scoped := strings.Join(stmts, "\n")
		if !regexpPayloadNotNull.MatchString(scoped) {
			t.Errorf("%s: очередь объявила PermanentPolicy: RetryPermanent (%s), но её тело "+
				"не объявлено обязательным (`payload … NOT NULL`) ни в одном из %d "+
				"операторов об этой таблице. Пустое тело — условие отказа разбора, а отказ "+
				"разбора травит при ЛЮБОЙ политике: значит путь отравления у очереди "+
				"остался, а возврата у неё по-прежнему нет.",
				table, strings.Join(inv.retryPermanent[table], ", "), len(stmts))
		}
		if !regexpPayloadCheck.MatchString(scoped) {
			t.Errorf("%s: очередь объявила PermanentPolicy: RetryPermanent (%s), но форма её "+
				"тела не закреплена ограничением (`CHECK` над `payload`) ни в одном из %d "+
				"операторов об этой таблице. Тело негодной формы — условие отказа разбора, "+
				"а он травит при любой политике.",
				table, strings.Join(inv.retryPermanent[table], ", "), len(stmts))
		}
	}

	t.Logf("очередей с политикой повтора: %d (%s); прочитано файлов миграций: %d",
		len(tables), strings.Join(tables, ", "), filesRead)
}

// migrationCorpus склеивает ВСЕ миграции дерева в одно тело.
//
// Склейка по дереву, а не по файлу и не по сервису, намеренно — по двум разным
// причинам, и обе стоили бы гейту предмета:
//
//   - НЕ по файлу: ограничение приезжает миграцией, отличной от заводящей таблицу
//     (у subject_change_outbox таблица из 0001, ограничения из 0097). Проверка
//     «в том же файле» проверяла бы историю правок, а не состояние схемы.
//   - НЕ по сервису ЦЕЛИКОМ: у одного сервиса очередей несколько, и тело сервиса
//     содержит ограничения ВСЕХ из них. Гейт, ищущий `payload NOT NULL` в теле
//     сервиса, зеленел бы на неограниченной очереди за счёт ограниченной соседки —
//     ровно та ошибка, которую он призван ловить. Поэтому отбор идёт по
//     операторам ОБ ЭТОЙ таблице (statementsAbout).
func migrationCorpus(t *testing.T, root string) (string, int) {
	t.Helper()
	files, err := treecorpus.UnderWithSuffix(filepath.Join(root, "services"), ".sql")
	if err != nil {
		t.Fatalf("состав миграций взять неоткуда: %v", err)
	}
	var b strings.Builder
	read := 0
	for _, path := range files {
		if !strings.Contains(path, "/internal/migrations/") {
			continue
		}
		raw, rerr := os.ReadFile(path) // #nosec G304 -- путь из индекса дерева
		if rerr != nil {
			continue
		}
		read++
		b.Write(raw)
		b.WriteString("\n")
	}
	return b.String(), read
}

// statementsAbout отдаёт операторы, ОТНОСЯЩИЕСЯ к названной таблице: тело
// `CREATE TABLE … <bare> ( … );` и каждый `ALTER TABLE … <bare> …;`.
//
// Именно они несут ограничения столбца: остальные упоминания имени (индексы,
// COMMENT, триггеры, INSERT, DROP) о форме строки не говорят и только размывали
// бы предмет.
func statementsAbout(corpus, bare string) []string {
	var out []string
	for _, re := range []*regexp.Regexp{
		regexp.MustCompile(`(?is)CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?\s+[\w.]*\b` +
			regexp.QuoteMeta(bare) + `\b\s*\(.*?\n\s*\)\s*;`),
		regexp.MustCompile(`(?is)ALTER\s+TABLE(?:\s+ONLY)?\s+[\w.]*\b` +
			regexp.QuoteMeta(bare) + `\b[^;]*;`),
	} {
		out = append(out, re.FindAllString(corpus, -1)...)
	}
	return out
}

// splitQualifiedTable разбирает `kacho_iam.subject_change_outbox` на сервис и
// голое имя. Имя схемы у всех владельцев — `kacho_<сервис>`, кроме живущих в
// `public`; сервис сегодня не читается, но возвращается, чтобы отказ мог назвать
// владельца очереди.
func splitQualifiedTable(qualified string) (service, bare string) {
	i := strings.Index(qualified, ".")
	if i < 0 {
		return "", qualified
	}
	schema, bare := qualified[:i], qualified[i+1:]
	return strings.TrimPrefix(schema, "kacho_"), bare
}

