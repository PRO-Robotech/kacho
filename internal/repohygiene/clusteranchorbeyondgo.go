// BeyondGoCensus — объём осмотренного по осям. «Ноль находок» обязано быть
// отличимо от «ноль прочитанного», а «ноль по виду» — от «вид не читали».
type BeyondGoCensus struct {
	// FilesRead — прочитано отслеживаемых файлов вне Go.
	FilesRead int
	// FilesBinary — пропущено двоичных: текста нет, искать нечего.
	FilesBinary int
	// FilesEmpty — пропущено пустых.
	FilesEmpty int
	// FilesWithAnchor — файлов, несущих хотя бы одно вхождение.
	FilesWithAnchor int
	// Occurrences — осмотрено вхождений формы якоря.
	Occurrences int
	// FilesByKind / OccurrencesByKind — те же две величины по видам файлов.
	FilesByKind       map[string]int
	OccurrencesByKind map[string]int
	// Assembled — кандидатов «якорь собран из частей»: образцу не видны.
	Assembled int
	// Elided — прозаических сокращений: намеренно не судятся.
	Elided int
	// LedgerEntries — записей ведомости.
	LedgerEntries int
	// Forgiven — вхождений, прощённых ведомостью.
	Forgiven int
}

// FindClusterAnchorBeyondGo разбирает отслеживаемые файлы ВНЕ Go (путь →
// содержимое) и возвращает вхождения, разошедшиеся с объявленным написанием.
//
// declared приходит ИЗВНЕ — из объявлений Go, добытых FindClusterAnchorLiterals.
// Гейт, знающий написание наизусть, умер бы молча в день перехода.
func FindClusterAnchorBeyondGo(
	files map[string][]byte,
	declared string,
	ledger []ClusterAnchorBeyondGoException,
) ([]BeyondGoFinding, []BeyondGoLedgerFinding, BeyondGoCensus, error) {
	census := BeyondGoCensus{
		FilesByKind:       map[string]int{},
		OccurrencesByKind: map[string]int{},
		LedgerEntries:     len(ledger),
	}

	// ─── предпосылки: гейт ОТКАЗЫВАЕТ на беспредметности, а не молчит ───
	if declared == "" {
		return nil, nil, census, fmt.Errorf(
			"написание якоря не объявлено — гейт не знает, что стережёт, " +
				"и «расхождений ноль» здесь тривиально верно")
	}
	if m := ClusterAnchorShape.FindString(declared); m != declared {
		return nil, nil, census, fmt.Errorf(
			"объявленное написание %q не подходит под образец %s (образец видит в нём %q) — "+
				"распознаватель перестал бы видеть предмет ЦЕЛИКОМ, оставаясь на вид рабочим; "+
				"правьте образец тем же изменением, каким переехало написание",
			declared, ClusterAnchorShape, m)
	}
	if len(files) == 0 {
		return nil, nil, census, fmt.Errorf(
			"на вход подано ноль файлов — обход дерева не состоялся, " +
				"и молчание гейта ничего не значит")
	}

	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	forgiveable := map[string]*ClusterAnchorBeyondGoException{}
	for i := range ledger {
		forgiveable[ledger[i].Path] = &ledger[i]
	}
	diverged := map[string]int{} // путь → сколько расхождений в нём
	anchorsIn := map[string]int{}

	var findings []BeyondGoFinding
	for _, path := range paths {
		body := files[path]
		switch {
		case len(body) == 0:
			census.FilesEmpty++
			continue
		case bytes.IndexByte(body, 0) >= 0:
			// Двоичный: текста нет. Названо вслух и сосчитано, а не пропущено молча.
			census.FilesBinary++
			continue
		}
		census.FilesRead++

		text := string(body)
		census.Assembled += len(clusterAnchorAssembled.FindAllString(text, -1))
		census.Elided += len(clusterAnchorElided.FindAllString(text, -1))

		locs := ClusterAnchorShape.FindAllStringIndex(text, -1)
		if len(locs) == 0 {
			continue
		}
		kind := anchorFileKind(path)
		census.FilesWithAnchor++
		census.FilesByKind[kind]++
		for _, loc := range locs {
			census.Occurrences++
			census.OccurrencesByKind[kind]++
			token := text[loc[0]:loc[1]]
			anchorsIn[path]++
			if token == declared {
				continue
			}
			diverged[path]++
			findings = append(findings, BeyondGoFinding{
				BeyondGoOccurrence: BeyondGoOccurrence{
					Path: path,
					Line: 1 + strings.Count(text[:loc[0]], "\n"),
					Text: token,
					Kind: kind,
				},
				Declared: declared,
			})
		}
	}

	if census.Occurrences == 0 {
		return nil, nil, census, fmt.Errorf(
			"обход прочитал %d файлов и не нашёл НИ ОДНОГО вхождения формы %s — "+
				"предмет не найден, поэтому молчание гейта ничего не утверждает; "+
				"либо образец разошёлся с деревом, либо на вход подано не то дерево",
			census.FilesRead, ClusterAnchorShape)
	}

	// ─── ведомость: прощаем и тут же требуем, чтобы записи было что прощать ───
	//
	// Прощает ТОЛЬКО запись, чьё число сошлось с фактом. Разошедшаяся не прощает
	// ничего: иначе устаревшая запись продолжала бы прятать координаты — то
	// есть ровно те строки, ради которых гейт заведён, — и читатель видел бы
	// одно число вместо перечня мест.
	var ledgerFindings []BeyondGoLedgerFinding
	kept := findings[:0]
	for _, f := range findings {
		if e, ok := forgiveable[f.Path]; ok && diverged[f.Path] == e.Count {
			census.Forgiven++
			continue
		}
		kept = append(kept, f)
	}
	findings = kept

	for _, e := range ledger {
		got := diverged[e.Path]
		switch {
		case anchorsIn[e.Path] == 0:
			ledgerFindings = append(ledgerFindings, BeyondGoLedgerFinding{
				Path: e.Path, Reason: e.Reason, Want: e.Count, Got: 0,
				Why: "файла нет в обходе либо якоря в нём нет — записи нечего прощать, " +
					"и она пережила свой предмет",
			})
		case got == 0:
			ledgerFindings = append(ledgerFindings, BeyondGoLedgerFinding{
				Path: e.Path, Reason: e.Reason, Want: e.Count, Got: 0,
				Why: "расхождений в файле ноль — написание в нём уже сошлось с объявленным, " +
					"и запись прощает то, чего нет",
			})
		case got != e.Count:
			ledgerFindings = append(ledgerFindings, BeyondGoLedgerFinding{
				Path: e.Path, Reason: e.Reason, Want: e.Count, Got: got,
				Why: "ведомость разошлась с фактом — число обязано быть точным, " +
					"а не потолком: потолок не краснеет никогда и потому не истекает",
			})
		}
	}

	sort.Slice(findings, func(i, j int) bool {
		if findings[i].Path != findings[j].Path {
			return findings[i].Path < findings[j].Path
		}
		return findings[i].Line < findings[j].Line
	})
	sort.Slice(ledgerFindings, func(i, j int) bool { return ledgerFindings[i].Path < ledgerFindings[j].Path })
	return findings, ledgerFindings, census, nil
}

// anchorFileKind — вид файла для оси переписи. Расширение, а не каталог: чинятся
// вхождения по виду носителя (контракт — генерацией, манифест — рукой,
// коллекция — своим производителем), а не по месту в дереве.
func anchorFileKind(path string) string {
	ext := strings.ToLower(filepath.Ext(path))
	if ext == "" {
		return "(без расширения)"
	}
	return strings.TrimPrefix(ext, ".")
}
