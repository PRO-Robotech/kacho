package repohygiene

// clusteranchorbeyondgo.go — написание якоря кластера ВНЕ Go: контракты, модель
// прав, манифесты модулей, миграции, фикстуры, сквозные пробы, консоль, модули
// инфраструктуры, посевы стенда, страницы документации.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Соседний разбор (clusteranchorliteral.go) стережёт то же написание и читает
// ТОЛЬКО Go — это названо его собственной границей, а не упущено. Следствие
// границы измерено: написание якоря живёт ещё в 57 отслеживаемых файлах вне Go.
// Единица счёта названа, иначе два замера одного предмета разойдутся молча:
// ВХОЖДЕНИЙ прежнего написания — 243, вхождений формы якоря (прежнее написание
// плюс одно называние целевого) — 244; замер `release/kaname` 50a654eb9f.
// Не читает их НИЧТО.
//
// Отсюда класс, который не поймает ни один сегодняшний гейт: написание
// переезжает в Go — оба объявления правятся, разбор Go зелен by construction, —
// а контракт, модель прав и манифест продолжают называть ПРЕЖНИЙ объект. Служба
// спрашивает про один объект, модель отвечает про другой, и расходятся они
// молча: proto собирается, YAML разбирается, консоль рисуется.
//
// Цена названа приёмкой F5 и повторена здесь, потому что она и есть довод:
// ошибка вокруг якоря отбирает доступ У ТОГО ЕДИНСТВЕННОГО, кто мог бы её
// починить.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗНАЧЕНИЕ ЧИТАЕТСЯ ИЗ ОБЪЯВЛЕНИЯ, А НЕ ВПИСАНО В ГЕЙТ
//
// Тот же довод, что у разбора Go, и он здесь сильнее: гейт заведён РАДИ
// перехода написания. Гейт, знающий строку наизусть, умер бы в день перехода и
// умер бы молча — «прежнего написания ноль» тривиально верно на дереве, где
// написание уже другое.
//
// Поэтому значение приходит извне: его добывает FindClusterAnchorLiterals из
// объявлений Go, и гейт спрашивает «равен ли объявленному КАЖДЫЙ найденный
// якорь». Владелец истины один, второго места об одном предмете не заводится.
//
// ─────────────────────────────────────────────────────────────────────────────
// РАСПОЗНАВАТЕЛЬ УЗНАЁТ ФОРМУ, И ЕГО ПРЕДПОСЫЛКА ПРОВЕРЯЕТСЯ
//
// Вне Go якорь стоит голой строкой: у YAML, proto и .fga формы «взять
// константу» нет by construction, и требовать её значило бы требовать
// невозможного. Значит найти надо не «литерал, равный объявлению» (таких мимо
// объявления и не бывает), а токен ТОЙ ЖЕ ФОРМЫ, отличающийся от объявленного.
//
// Форму задаёт ClusterAnchorShape. Она знает ОБЕ латинские формы имени
// платформы — обычную и с диакритическим знаком (`\p{L}` принимает `ō`), —
// потому что поиск по одной недобирает МОЛЧА: замер дерева даёт 477 файлов с
// диакритической формой имени, и распознаватель, её не знающий, дал бы по ним
// «ноль находок», означающее «ноль прочитанного».
//
// Предпосылка распознавателя: ОБЪЯВЛЕННОЕ значение само обязано подходить под
// образец. Не подходит — гейт ОТКАЗЫВАЕТ и называет обе строки. Молчание здесь
// было бы худшим исходом: образец, не узнающий нового написания, перестал бы
// видеть предмет целиком, оставаясь на вид рабочим.
//
// ─────────────────────────────────────────────────────────────────────────────
// ГРАНИЦЫ НАЗВАНЫ ВСЛУХ, И У КАЖДОЙ ЕСТЬ ЧИСЛО В ПЕРЕПИСИ
//
//  1. Файлы Go — предмет соседнего разбора, здесь не читаются. Число: перепись
//     печатает, сколько файлов вне Go прочитано, а не «сколько всего».
//  2. ДВОИЧНЫЕ файлы не читаются: текста в них нет, искать нечего. Их число
//     печатается отдельно, чтобы «ноль находок» по ним было отличимо от «ноль
//     прочитанного». Сегодня их ноль, и это тоже сказано числом.
//  3. Якорь, СОБРАННЫЙ ИЗ ЧАСТЕЙ (подстановка шаблона, форматная строка,
//     склейка), образцу не виден by construction — распознаватель судит текст.
//     Кандидаты такой формы считаются отдельно и печатаются: рост этого числа
//     означает, что появилась форма, которой гейт не судит.
//  4. Прозаическое СОКРАЩЕНИЕ («cluster …root» в таблице документа) намеренно
//     не судится: оно переживает переход написания и остаётся верным. Число
//     печатается, чтобы граница была наблюдаемой, а не подразумеваемой.
//  5. ЗАКОДИРОВАННЫЕ формы (base64, процентное кодирование, `\uXXXX` в JSON)
//     разбором не читаются: распознаватель судит текст как он записан.
//     Граница названа с числом, а не подразумевается — на ревизии
//     50a654eb9f таких форм в дереве ПО НУЛЮ у каждой из трёх (предикаты:
//     `git grep -Il Y2x1c3Rlcl9rYWNob19yb290`, `git grep -Il 'cluster%5Fkacho'`,
//     `git grep -Il 'cluster\u005f'`). Появится хоть одна — её обязан
//     научиться читать разбор, а не эта строка объяснить, почему он не стал.
//
// ─────────────────────────────────────────────────────────────────────────────
// ВЕДОМОСТЬ РЕШЁННОГО ОСТАТЬСЯ
//
// Часть вхождений обязана пережить переход с ПРЕЖНИМ написанием — решение
// эпика #2076 §«ЧТО НЕ ТРОГАЕТСЯ НИКОГДА»: номера прежнего трекера, имена
// прежних репозиториев, разборы прошлых решений, записи замеров в приёмках.
// Их правка сделала бы ложными утверждения, которые были верны. Сюда же —
// ПРИМЕНЁННАЯ миграция: править её нельзя (ban #5), поэтому прежнее написание
// в ней остаётся фактом истории, а не долгом.
//
// Запись называет файл, причину и ЧИСЛО прощаемых вхождений. Прежняя редакция
// говорила «сегодня запись ОДНА, остальные заводятся самим ПЕРЕХОДОМ» — переход
// состоялся (задача #2113), и записей стало СЕМЬ: документ возврата доступа
// (цитата решения, называющая оба написания разом), применённая базовая
// миграция, четыре приёмки службы с записями замеров и сама миграция перехода,
// которой назвать оба написания велит её предмет.
//
// Числа здесь не выписываются: они живут в записях ниже, а перепись печатает
// их сумму. Число в прозе шапки не имеет владельца и стареет молча — а эта
// строка уже однажды пережила свой предмет.
//
// Ведомость истекает сама: запись, которой нечего прощать (файла нет, якоря в
// нём нет, расхождений в нём ноль), — НАХОДКА. И число в записи — точное, а не
// потолок: потолок не краснеет никогда, поэтому не истекает и прощает вперёд
// ту находку, ради которой гейт заведён.

import (
	"bytes"
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// ClusterAnchorShape — образец формы якоря кластера.
//
// Принимает `cluster_root`, `cluster_kacho_root`, `cluster_kaname_root`,
// `cluster_kachō_root` — то есть и сегодняшнее написание, и оба обсуждаемых
// целевых, и диакритическую форму имени платформы. Не принимает `cluster:root`,
// `kacho_root` и токен, склеенный с соседним словом.
var ClusterAnchorShape = regexp.MustCompile(`\bcluster(?:_[\p{L}\p{N}]+)*_root\b`)

// clusterAnchorAssembled — кандидат «якорь собран из частей»: подстановка
// шаблона, форматная строка, склейка. Образцу такая форма не видна, поэтому её
// число печатается переписью, а не умалчивается.
var clusterAnchorAssembled = regexp.MustCompile(
	"cluster_[^\\s\"'`]{0,24}?(\\{\\{|\\$\\{|%[sdv]|\\$\\(|\"\\s*\\+|'\\s*\\+)")

// clusterAnchorElided — прозаическое сокращение якоря («cluster …root»).
// Переживает переход написания и потому не судится; число печатается.
var clusterAnchorElided = regexp.MustCompile(`cluster[^\n]{0,8}(\.\.\.|…|\p{Zs}*[…])[^\n]{0,8}root`)

// BeyondGoOccurrence — вхождение якоря вне Go.
type BeyondGoOccurrence struct {
	Path string
	Line int
	// Text — найденный токен целиком.
	Text string
	// Kind — вид файла (расширение либо «(без расширения)»): по нему идёт
	// перепись, и по нему же читатель находки понимает, чем её чинить —
	// контракт правится генерацией, манифест рукой, коллекция — своим
	// производителем.
	Kind string
}

// BeyondGoFinding — вхождение, разошедшееся с объявленным написанием.
type BeyondGoFinding struct {
	BeyondGoOccurrence
	// Declared — то, что объявлено в Go на момент прогона.
	Declared string
}

// BeyondGoLedgerFinding — запись ведомости, которой нечего прощать либо
// разошедшаяся с фактом.
type BeyondGoLedgerFinding struct {
	Path   string
	Reason string
	// Want — сколько записано в ведомости, Got — сколько в дереве.
	Want, Got int
	Why       string
}

// ClusterAnchorBeyondGoException — запись ведомости решённого остаться.
