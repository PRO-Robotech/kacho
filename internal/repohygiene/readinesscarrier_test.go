package repohygiene

// readinesscarrier_test.go — сервис, поднимающий `/readyz`, строит его
// ОБЪЯВЛЕННЫМ носителем, а не своим.
//
// # Предмет
//
// Шапка `pkg/observability/health` объявляет пакет ЕДИНСТВЕННЫМ в дереве
// носителем разведённых живости и готовности. Пока это только фраза, второй
// носитель заводится молча: копии не собираются вместе и друг друга не читают,
// поэтому разойтись им нечем — расхождение приходит не отказом, а тишиной.
//
// И придёт оно в свойствах, которые общий носитель УЖЕ решил: срок на чекер
// (зависший `Ping` иначе держит обработчик до probe-timeout kubelet'а),
// различение «носитель не провязан» и «носитель ответил»
// (`health.ErrDependencyNotWired`), перевод готовности в 503 на гашении
// (`SetShuttingDown`), зеркало результата в счётчик. Своя форма ничего этого не
// несёт — и не потому, что решили иначе, а потому что вопрос не задавали.
//
// Замер, из которого гейт выведен (задача продукта #1752): поднимали `/readyz`
// СЕМЬ сервисов, объявленным носителем строили ШЕСТЬ. Седьмой нёс свой тип той
// же формы (`{Name string; Check func(ctx) error}`) в handler-слое.
//
// # Почему предикат — «чем построено монтирование», а не перечень сервисов
//
// Перечень — это место, которое забывают дополнить. Условие ВЫВОДИТСЯ из дерева:
// файл, монтирующий `/readyz`, обязан отдать туда обработчик, произведённый
// носителем (`<агрегатор>.ReadyHandler()`), и обязан носитель ИМПОРТИРОВАТЬ.
// Восьмой сервис, заведший свою готовность, краснеет в тот же день.
//
// # Разбор синтаксического дерева, а не текста
//
// Путь `/readyz` в этом дереве встречается в шапках, комментариях и в перечне
// публичных путей края. Текстовый поиск принял бы объяснение за исполнение —
// тот самый класс, ради которого гейт разбирает синтаксическое дерево.
//
// # Чего гейт НЕ утверждает (граница названа, чтобы её не приняли шире)
//
//   - ЧТО именно проверяет каждая зависимость — вопрос композиционного корня, и
//     носитель его намеренно не решает;
//   - что готовность переводится в 503 на гашении — это провязка корня, у неё
//     свой предмет;
//   - ничего о крае (`gateway/`): его готовность отвечает на другой вопрос —
//     агрегирует `grpc.health.v1.Health` бэкендов, а не свои зависимости.
//     Популяция обхода — `services/`, и это сказано в `scanReadinessCarriers`.

import (
	"sort"
	"strings"
	"testing"
)

// TestEveryServiceServingReadyzBuildsItWithTheDeclaredCarrier — единственность
// носителя готовности есть свойство ДЕРЕВА, и держать его может только обход
// дерева.
func TestEveryServiceServingReadyzBuildsItWithTheDeclaredCarrier(t *testing.T) {
	root := repoRoot(t)
	reach, err := scanReadinessCarriers(root)
	if err != nil {
		t.Fatalf("%v", err)
	}

	// Перепись печатается ВСЕГДА и ПОРОЗНЬ: одно число скрывает ровно тот
	// случай, ради которого ось заведена.
	t.Logf("осмотрено: файлов Go прочитано=%d, сервисов в дереве=%d, поднимают /readyz=%d (%s), "+
		"строят объявленным носителем=%d, объявляют свой тип именованной проверки=%d",
		reach.filesRead, reach.servicesSeen, len(reach.services),
		strings.Join(reach.services, ", "), reach.byCarrierCount(), reach.localCheckerTypes())

	// Предпосылка гейта: обход что-то прочитал и что-то нашёл. Ноль означает,
	// что каталог сервисов переехал либо монтирование записывается формой, о
	// которой распознаватель не знает, — и тогда гейт судит пустоту.
	if reach.filesRead == 0 {
		t.Fatalf("предпосылка гейта нарушена: под services/ не прочитано ни одного прод-файла Go — " +
			"каталог переехал либо состав дерева не читается; пока это не выяснено, гейт не судит ничего")
	}
	if len(reach.services) == 0 {
		t.Fatalf("предпосылка гейта нарушена: ни один сервис не монтирует /readyz (файлов прочитано %d) — "+
			"поверхность переехала либо монтирование записывается формой, о которой распознаватель не знает; "+
			"«ноль находок» здесь означало бы «ноль прочитанного»", reach.filesRead)
	}

	svcs := append([]string(nil), reach.services...)
	sort.Strings(svcs)
	for _, svc := range svcs {
		m := reach.mounts[svc]
		if !m.byCarrier {
			t.Errorf("services/%s монтирует /readyz (%s) НЕ объявленным носителем: обработчик не "+
				"произведён `<агрегатор>.%s()` из %s. Второй носитель той же формы расходится с общим "+
				"молча — копии не собираются вместе и друг друга не читают, — и расходится он в том, "+
				"что общий уже решил: срок на чекер, различение «носитель не провязан» и «носитель "+
				"ответил», перевод готовности в 503 на гашении, зеркало результата в счётчик",
				svc, m.coord, readyHandlerSel, healthCarrierPkg)
		}
		if m.localCheckerType != "" {
			t.Errorf("services/%s объявляет СВОЙ тип именованной проверки (%s) в том же пакете, что "+
				"монтирование /readyz (%s) — это форма `health.Checker`, заведённая по месту. "+
				"Об одном предмете высказываются два места, и одно из них объявляет себя единственным",
				svc, m.localCheckerType, m.coord)
		}
	}
}
