// TestEdgeAddressLaneActuallyInspectsTheRealTree — ПРЕМИСА половины АДРЕСА на
// настоящем дереве.
//
// Вердикт о дереве по всем трём полосам выносит `TestNoModuleIsTypedByItsConsumer`;
// здесь утверждается другое и не менее нужное: что новая половина **осматривала**
// свой предмет, а не молчала на пустом обходе.
//
// Различие несущее. Половина АДРЕСА судит литералы и строки, НАЗВАВШИЕ край; если
// таких в дереве ноль ПО ОБЕИМ ПОЛОВИНАМ, её молчание означает «нечего было
// читать», а не «дозвонов нет» — сменился токен хоста, переехал каталог, сузился
// обход.
//
// По ОДНОЙ половине ноль законен, и это выведено замером, а не допущено на
// всякий случай: литералы с именем края в прод-коде `services/` держались одним
// производителем — стражем личности вызывающего службы доступа, — а служба
// вынесена отдельным продуктом. Шести оставшимся модулям круг законных
// отправителей приезжает НАСТРОЙКОЙ, поэтому имени края в их исходниках нет и
// быть не должно. Разбор — у самого утверждения ниже.
//
// Порог нижний, а не точный: число законных упоминаний края растёт и падает с
// каждой правкой прозы, и точное число здесь запретило бы её править.
func TestEdgeAddressLaneActuallyInspectsTheRealTree(t *testing.T) {
	t.Parallel()
	var log strings.Builder
	_, census, err := AuditModuleKnowsNoEdge(moduleKnowsNoEdgeOptions(t), &log)
	if err != nil {
		t.Fatalf("анализатор не отработал: %v", err)
	}
	t.Log(strings.TrimSpace(log.String()))

	// ЗДЕСЬ СТОЯЛО отдельное требование к половине Go: «прод-код модулей называет
	// край хотя бы раз». Оно держалось ОДНИМ производителем, и производитель
	// назван замером, а не памятью: на ревизии до выноса службы доступа литералы
	// с именем края в прод-коде `services/` стояли ровно в пяти файлах, и все
	// пять — в её страже личности вызывающего (круг законных отправителей).
	// Предикат: `git grep -c '"[^"]*api-gateway' -- 'services/**/*.go'` — до
	// выноса пять файлов службы плюс один КОММЕНТАРИЙ реестра (литералом не
	// является), после выноса остался только комментарий.
	//
	// Требование СНЯТО ВМЕСТЕ С ПРЕДМЕТОМ, а не ослаблено: шести оставшимся
	// модулям круг отправителей приезжает НАСТРОЙКОЙ, а не литералом в коде, и
	// потребовать от них имени края значило бы требовать ровно того, что корпус
	// запрещает — жёсткого адреса соседа в исходнике.
	//
	// Проверяемость премисы при этом сохранена ДВУМЯ утверждениями ниже: чарты
	// край называют (11 строк), а полная слепота обеих половин остаётся отказом.
	// Ноль по ОДНОЙ половине теперь факт о дереве; ноль по ОБЕИМ — по-прежнему
	// признак того, что распознаватель перестал видеть предмет.
	if census.EdgeNamedGo+census.EdgeNamedChart == 0 {
		t.Fatalf("край не назван НИ РАЗУ ни в прод-коде, ни в чартах (литералов Go %d, "+
			"строк чарта %d) — половина АДРЕСА не осматривала свой предмет, и её молчание "+
			"означает «нечего было читать», а не «дозвонов нет»: сменился токен хоста, "+
			"переехал каталог, сузился обход",
			census.EdgeNamedGo, census.EdgeNamedChart)
	}
	if census.EdgeNamedChart == 0 {
		t.Fatalf("чарты модулей не называют край НИ РАЗУ (строк чарта %d) — то же для посадки: "+
			"селектор пода края и круг отправителей в чартах живут и обязаны жить",
			census.EdgeNamedChart)
	}
	t.Logf("премиса половины АДРЕСА: край назван в прод-коде %d раз(а), в чартах %d — "+
		"осмотрено и признано законным. Ноль по прод-коду — факт о дереве, а не "+
		"слепота: круг законных отправителей приезжает модулям настройкой",
		census.EdgeNamedGo, census.EdgeNamedChart)
}
