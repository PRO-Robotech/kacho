// acceptanceeditafterverdict_test.go — правка ОДОБРЕННОЙ приёмки после вердикта
// объявляется в самом документе.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Вердикт есть утверждение о РЕВИЗИИ, которую прочитал проверяющий, а не о файле
// по имени: правка его не переносит и не отзывает задним числом. Половина этого
// решения держалась гейтом (массовое переименование не правит дом приёмок);
// вторая — что запись о правке вообще внесена — не держалась НИЧЕМ. Сегодня все
// записи внесены разом; следующая массовая правка их не заведёт, и шапка снова
// будет объявлять вердикт, молча о том, что содержимое двигалось (kacho#2225).
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПАРА ВЕЛИЧИН, А НЕ ОДНА
//
// Признак — сравнение двух отметок: когда последний раз правилась СТРОКА
// СОСТОЯНИЯ и когда сам документ. Обе берутся в ЭПОХЕ: в этом доме даты стоят в
// двух поясах, и строковое сравнение даёт неверный порядок.
package repohygiene

import (
	"testing"
)

// acceptanceHomeDir — дом одобренных приёмок службы.
//
// Каталог, а не образец имени: перечень выводится обходом дома, поэтому приёмка,
// заведённая завтра, попадает под наблюдение сама.
const acceptanceHomeDir = "services/iam/docs/engineering/acceptance"

// TestAcceptanceEditedAfterItsVerdictSaysSo — несущее утверждение.
func TestAcceptanceEditedAfterItsVerdictSaysSo(t *testing.T) {
	root := repoRoot(t)
	findings, census, err := AuditAcceptanceEditsAfterVerdict(root, acceptanceHomeDir)
	if err != nil {
		t.Fatalf("проверка НЕ ИСПОЛНЯЛАСЬ: %v", err)
	}
	if census.DocsRead == 0 {
		t.Fatalf("дом приёмок пуст: прочитано 0 документов — вердикт беспредметен (%s)", census)
	}
	// Ветвь сравнения обязана ИСПОЛНЯТЬСЯ: при нуле правленных после вердикта
	// «находок ноль» означало бы, что сравнение не делалось ни разу, и молчание
	// гейта ничего бы не значило.
	if census.EditedAfter == 0 {
		t.Fatalf("ни один документ не правлен после объявления состояния при %d "+
			"прочитанных: ветвь сравнения не исполнялась, и молчание гейта ничего "+
			"не означает (%s)", census.DocsRead, census)
	}
	for _, d := range census.NoStateLine {
		t.Logf("без строки состояния (предмет ДРУГОГО держателя, не находка): %s", d)
	}
	for _, d := range census.NoHistory {
		t.Logf("без построчной истории (вердикт не выносится): %s", d)
	}
	for _, f := range findings {
		t.Error(f)
	}
	t.Logf("перепись: %s", census)
}
