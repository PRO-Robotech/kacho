package repohygiene

import (
	"fmt"
	"sort"
	"strings"
)

// proxyforbiddentypes.go — вердикт о запретительном наборе типов объекта
// проксируемой записи (pkg/authz/proxytuple, forbiddenObjectTypes).
//
// # Предмет — ДВЕ стороны одного набора, и каждая молчит по-своему
//
// Набор объявляет: «эти типы объекта никогда не принадлежат модулю, поэтому через
// прокси они недостижимы при ЛЮБОЙ настройке — в том числе когда домен вызывающего
// неизвестен и привязка к домену отключена». Утверждение проверяемо только вместе
// с моделью прав, и разойтись с ней оно может в обе стороны:
//
//   - ЗАПИСЬ БЕЗ РЕФЕРЕНТА. Имя, которого модель не объявляет, не исключает
//     ничего: вход, который оно отвергало бы, непредставим. Перечень при этом
//     выглядит полнее, чем есть, и следующий читатель заключает, что тип прикрыт.
//     Наблюдаемо это НИКАК: набор читается на каждой записи, отказов не даёт и
//     выглядит работающим (задача #1883 — запись `role` при типе модели
//     `iam_role`);
//   - ТИП БЕЗ ЗАПИСИ. Тип модели, не принадлежащий ни одному модулю-эмитенту и в
//     наборе отсутствующий, остаётся достижимым ровно в том режиме, ради которого
//     набор и написан, — когда домен вызывающего пуст и привязка к домену не
//     действует. Это молчаливое выпадение: ни красного, ни зелёного.
//
// Обе стороны судятся ОДНОВРЕМЕННО. Одна сторона доказывает лишь половину: набор
// из одних верных имён бывает неполон, а полный — содержать мёртвую запись.
//
// # Кто считается модулем
//
// Домены-эмитенты берутся из proxyConsumerDomains — той же переписи, которую в обе
// стороны держит TestProxyIntentCensusMatchesExpectedConsumers. Своего списка здесь
// не заводится намеренно: второй перечень тех же доменов разошёлся бы с первым
// молча, а при появлении нового модуля перепись эмитентов краснеет ПЕРВОЙ, и её
// правка автоматически учитывает приставку новых типов.
//
// `iam` в эмитентах отсутствует НЕ по недосмотру: iam пишет свои связи напрямую,
// без прокси, — поэтому типы его домена и суть тот класс, который набор обязан
// закрывать.

// forbiddenTypesCensus — объём осмотренного. Печатается ВСЕГДА: молчание проверки,
// не прочитавшей ни одного типа модели, неотличимо от молчания проверившей все.
type forbiddenTypesCensus struct {
	// Entries — записей запретительного набора осмотрено.
	Entries int
	// EntriesResolved — из них резолвится типом модели.
	EntriesResolved int
	// ModelTypes — типов объявлено моделью прав.
	ModelTypes int
	// NonModuleTypes — из них не принадлежит ни одному домену-эмитенту.
	NonModuleTypes int
	// NonModuleCovered — из них названо запретительным набором.
	NonModuleCovered int
}

func (c forbiddenTypesCensus) Summary() string {
	return fmt.Sprintf(
		"записей набора %d · резолвится %d · типов модели %d · вне модулей %d · из них в наборе %d",
		c.Entries, c.EntriesResolved, c.ModelTypes, c.NonModuleTypes, c.NonModuleCovered)
}

// judgeForbiddenProxyTypes выносит вердикт по набору, модели и перечню доменов.
//
// Вход подаётся значениями, а не читается из дерева, чтобы инъекция подавала
// синтетический набор тем же путём, каким гейт подаёт настоящий: проверка,
// умеющая читать только дерево, свою способность падать не доказывает.
//
// Находки собираются ВСЕ: названная первая заставила бы чинить их по одной, по
// прогону на каждую, и скрыла бы, сколько их всего.
func judgeForbiddenProxyTypes(entries, modelTypes, moduleDomains []string) ([]string, forbiddenTypesCensus) {
	census := forbiddenTypesCensus{Entries: len(entries), ModelTypes: len(modelTypes)}

	declared := make(map[string]struct{}, len(modelTypes))
	for _, t := range modelTypes {
		declared[t] = struct{}{}
	}
	inSet := make(map[string]struct{}, len(entries))
	for _, e := range entries {
		inSet[e] = struct{}{}
	}

	var faults []string

	// Сторона А — запись без референта.
	for _, e := range sorted(entries) {
		if _, ok := declared[e]; ok {
			census.EntriesResolved++
			continue
		}
		faults = append(faults, fmt.Sprintf(
			"запись %q запретительного набора не резолвится ни одним типом модели прав: "+
				"вход, который она отвергала бы, непредставим, поэтому запись не исключает "+
				"НИЧЕГО. Чинится именем типа, как его объявляет модель "+
				"(proto/kaname/cloud/iam/v1/fga_model.fga), либо снятием записи вместе с "+
				"предметом", e))
	}

	// Сторона Б — тип без записи.
	for _, t := range sorted(modelTypes) {
		if ownedByModule(t, moduleDomains) {
			continue
		}
		census.NonModuleTypes++
		if _, ok := inSet[t]; ok {
			census.NonModuleCovered++
			continue
		}
		faults = append(faults, fmt.Sprintf(
			"тип модели %q не принадлежит ни одному домену-эмитенту (%s) и не назван "+
				"запретительным набором: через прокси он остаётся достижимым ровно в том "+
				"режиме, ради которого набор написан, — когда домен вызывающего пуст и "+
				"привязка к домену не действует. Чинится записью в forbiddenObjectTypes "+
				"либо, если тип всё же принадлежит модулю, его доменом в переписи эмитентов",
			t, strings.Join(sorted(moduleDomains), ", ")))
	}

	return faults, census
}

// ownedByModule — принадлежит ли тип домену модуля-эмитента. Сравнение по
// приставке `<домен>_` здесь уместно и не является тем соглашением об именовании,
// которое стережёт #1885: гейт судит ПРИНАДЛЕЖНОСТЬ К КЛАССУ «ресурс какого-то
// модуля», а не «чей именно», и ошибка в эту сторону даёт находку, а не молчание.
func ownedByModule(fgaType string, moduleDomains []string) bool {
	for _, d := range moduleDomains {
		if strings.HasPrefix(fgaType, d+"_") {
			return true
		}
	}
	return false
}

func sorted(in []string) []string {
	out := append([]string(nil), in...)
	sort.Strings(out)
	return out
}
