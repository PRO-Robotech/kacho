// decisionsuccessor.go — разбор ЗАДАЧИ-ПРЕЕМНИКА, объявленной решением
// архитектуры, и её присутствия на всех поверхностях этого решения.
//
// # Предмет
//
// Решение, принятое, но не реализованное, живёт на нескольких поверхностях
// сразу: документ архитектуры объявляет выбор, контракт описывает действующее
// поведение, страница арендатора называет цену. Каждая из трёх отсылает
// читателя к задаче, которая механизм несёт.
//
// Пока номер выписан в каждой из трёх ОТДЕЛЬНО, они расходятся молча — и
// расходятся в сторону, которая УСПОКАИВАЕТ: задача, при которой решение
// принималось, закрывается, а поверхности продолжают её называть. Клиент,
// прошедший по такой ссылке, видит закрытую задачу и заключает, что работа
// сделана. Наблюдалось на решении об удалении проекта: три поверхности называли
// закрытую задачу, а открытой задачи-преемника не было названо ни одной
// (kacho#1231).
//
// # Единица суждения — ОБЪЯВЛЕНИЕ, а не упоминание
//
// Номер объявляется ОДИН раз, строкой [SuccessorMarker] в документе решения;
// прочие поверхности обязаны его СОДЕРЖАТЬ. Обратное — «все упоминания
// совпадают» — запретило бы историческую ссылку на задачу, при которой решение
// принималось, а она законна и полезна: без неё не восстановить, кто и когда
// выбирал.
//
// # Вторая единица суждения — ОБЪЯВЛЕННЫЙ ОТКАЗ, и она появилась вместе с механизмом
//
// Пока механизм не был посажен, поверхности сходились на одном: кто держит
// остаток. После посадки (PRO-Robotech/kaname#166) у решения появилось
// НАБЛЮДАЕМОЕ — тон отказа и его машинный признак, — и оно записано в двух
// деревьях сразу: документ решения объявляет выбор, контракт службы описывает
// действующее поведение. Контракт приезжает сюда опубликованным модулем, то есть
// гейт видит его правку ТОЛЬКО на подъёме пина; до подъёма документ, уже
// приведённый к посаженному, утверждал бы то, чего стоящий в дереве контракт
// не обещает. Поэтому документ объявляет строкой [RefusalMarker] литералы,
// которые каждая поверхность обязана нести ДОСЛОВНО, — и пин, отставший от
// объявления, есть находка, а не «ещё не доехало».
//
// Литералы берутся из объявления, а не из прозы: разбор перечисляет тон
// примерами, и требовать каждого примера от контракта значило бы требовать
// дословного присутствия иллюстрации.
//
// # ЧЕГО РАЗБОР НЕ ВИДИТ — названо, а не спрятано
//
//   - открыта ли названная задача: это вопрос к трекеру, а гейт читает дерево и
//     обязан работать без сети. Он держит СОГЛАСИЕ поверхностей, а не состояние
//     задачи; закрытая задача, названная всеми тремя согласованно, для него
//     законна;
//   - соседнюю поверхность, о которой документ решения не сказал: перечень
//     координат берётся ИЗ ДОКУМЕНТА, поэтому поверхность, им не названная,
//     не судится. Это осознанно: у перечня один автор, и он же отвечает за
//     полноту.
package repohygiene

import (
	"regexp"
	"strconv"
	"strings"
)

// SuccessorMarker — строка, которой документ решения объявляет свою
// задачу-преемника.
//
// Одна форма, а не перечень синонимов: вторая форма означала бы два места об
// одном предмете внутри самого разбора.
const SuccessorMarker = "**Задача-преемник:**"

// SurfacesMarker — строка, которой документ решения объявляет СВОИ поверхности.
//
// Объявляются явно, а не собираются со всего документа: документ называет в
// прозе и правила корпуса, и координаты-свидетельства (файл, по которому сделан
// замер). Сбор «всех путей в обратных кавычках» приписал бы обязанность и им —
// то есть дал бы находку там, где обязанности нет, а гейт, у которого часть
// находок ложные, перестают читать.
const SurfacesMarker = "**Поверхности решения:**"

// RefusalMarker — строка, которой документ решения объявляет ЛИТЕРАЛЫ ОТКАЗА:
// то, что каждая поверхность несёт дословно (начало текста отказа и его
// машинный признак). Объявляются в обратных кавычках, через любой разделитель.
const RefusalMarker = "**Отказ на поверхностях:**"

// DecisionSurface — поверхность решения: координата в дереве и то, что на ней
// прочитано.
type DecisionSurface struct {
	// Path — координата, как её назвал документ решения.
	Path string
	// Cites — называет ли поверхность объявленный номер.
	Cites bool
	// Found — какие номера задач на ней вообще встречены (для текста находки).
	Found []int
}

// DecisionCensus — объём осмотренного.
type DecisionCensus struct {
	// Successor — объявленный номер задачи-преемника; 0, если объявления нет.
	Successor int
	// Coordinates — координат прочитано из документа решения.
	Coordinates int
	// Surfaces — поверхностей открыто и разобрано.
	Surfaces int
	// Citations — ссылок на задачи встречено суммарно.
	Citations int
}

var (
	// issueRefRe — ссылка на задачу в любой из трёх форм, которыми её пишут в
	// этом дереве: `#1231`, `kacho#1231`, `…/issues/1231`.
	issueRefRe = regexp.MustCompile(`(?:issues/|#)(\d{1,6})\b`)
	// htmlEntityRe — числовая литера разметки (`&#91;`). Гасится ПЕРЕД поиском
	// ссылок: иначе `&#91;` читается как задача №91, и страница арендатора
	// объявляется называющей четыре несуществующие задачи. Найдено этим же
	// гейтом на его первом прогоне.
	htmlEntityRe = regexp.MustCompile(`&#\d+;`)
	// coordinateRe — координата в обратных кавычках.
	coordinateRe = regexp.MustCompile("`([A-Za-z0-9_./-]+\\.(?:proto|mdx|md|go|yaml|sql))`")
	// literalRe — литерал в обратных кавычках, как есть: содержимое между
	// кавычками, без ограничения формы. Литерал отказа несёт пробелы, угловые
	// скобки и незакрытую скобку перечня — координатным выражением его не прочесть.
	literalRe = regexp.MustCompile("`([^`]+)`")
)

// DeclaredSuccessor читает номер задачи-преемника из документа решения.
//
// Ноль означает «объявления нет» — и это отказ у вызывающего, а не пустой
// успех: без объявления сверять поверхности не с чем, и молчание гейта было бы
// сказано ни о чём.
func DeclaredSuccessor(doc []byte) int {
	for _, ln := range strings.Split(string(doc), "\n") {
		if !strings.Contains(ln, SuccessorMarker) {
			continue
		}
		m := issueRefRe.FindStringSubmatch(ln)
		if m == nil {
			continue
		}
		n, err := strconv.Atoi(m[1])
		if err != nil {
			continue
		}
		return n
	}
	return 0
}

// DeclaredCoordinates читает координаты поверхностей, названные документом
// решения строкой [SurfacesMarker].
//
// Перечень ВЫВОДИТСЯ из документа, а не выписывается здесь: выписанный разошёлся
// бы с ним ровно тогда, когда автор добавит поверхность и забудет про гейт.
func DeclaredCoordinates(doc []byte) []string {
	seen := map[string]struct{}{}
	var out []string
	// Читается ВЕСЬ абзац объявления, а не одна строка. Корпус переносит строки
	// по ширине, поэтому объявление из двух координат обычно занимает две строки —
	// и построчный разбор увидел бы первую, промолчав про вторую. Молчание тут
	// хуже находки: поверхность, ускользнувшая от суждения, выглядит проверенной.
	// Наблюдалось на первом же прогоне этого гейта: объявлено 2, прочитано 1.
	inParagraph := false
	for _, ln := range strings.Split(string(doc), "\n") {
		if strings.Contains(ln, SurfacesMarker) {
			inParagraph = true
		} else if inParagraph && strings.TrimSpace(ln) == "" {
			inParagraph = false
		}
		if !inParagraph {
			continue
		}
		for _, m := range coordinateRe.FindAllStringSubmatch(ln, -1) {
			p := m[1]
			if _, ok := seen[p]; ok {
				continue
			}
			seen[p] = struct{}{}
			out = append(out, p)
		}
	}
	return out
}

// CitesSuccessor отвечает, называет ли поверхность объявленный номер, и
// перечисляет встреченные номера.
func CitesSuccessor(src []byte, successor int) (bool, []int) {
	var found []int
	cites := false
	// Литеры разметки гасятся ДО поиска: `&#91;` — это символ, а не задача.
	text := htmlEntityRe.ReplaceAllString(string(src), " ")
	for _, m := range issueRefRe.FindAllStringSubmatch(text, -1) {
		n, err := strconv.Atoi(m[1])
		if err != nil {
			continue
		}
		found = append(found, n)
		if n == successor {
			cites = true
		}
	}
	return cites, found
}

// SuccessorFinding — текст находки: поверхность, которая преемника не называет.
func SuccessorFinding(s DecisionSurface, successor int) string {
	var b strings.Builder
	b.WriteString(s.Path)
	b.WriteString(" не называет задачу-преемника #")
	b.WriteString(strconv.Itoa(successor))
	if len(s.Found) == 0 {
		b.WriteString(" и не называет НИ ОДНОЙ задачи")
		return b.String()
	}
	nums := make([]string, 0, len(s.Found))
	for _, n := range s.Found {
		nums = append(nums, "#"+strconv.Itoa(n))
	}
	b.WriteString("; названы: ")
	b.WriteString(strings.Join(nums, ", "))
	return b.String()
}

// DeclaredRefusalLiterals читает литералы отказа, объявленные документом
// решения строкой [RefusalMarker]. Пусто означает «объявления нет» — и это отказ
// у вызывающего, а не пропуск оси: после посадки механизма документ обязан
// сказать, чем отказ узнаётся.
//
// Читается ТОЛЬКО строка объявления, а не абзац: литерал не координата, и
// перенос строки внутри объявления сделал бы вторую строку неотличимой от
// прозы, которая тоже пишет тон в обратных кавычках.
func DeclaredRefusalLiterals(doc []byte) []string {
	var out []string
	for _, ln := range strings.Split(string(doc), "\n") {
		if !strings.Contains(ln, RefusalMarker) {
			continue
		}
		tail := ln[strings.Index(ln, RefusalMarker)+len(RefusalMarker):]
		for _, m := range literalRe.FindAllStringSubmatch(tail, -1) {
			if lit := m[1]; lit != "" {
				out = append(out, lit)
			}
		}
		return out
	}
	return nil
}

// MissingRefusalLiterals перечисляет объявленные литералы, которых поверхность
// НЕ несёт дословно. Пустой ответ — поверхность несёт каждый.
//
// Сверка дословная и без разбора синтаксиса поверхности намеренно: поверхность
// бывает контрактом (комментарий у глагола) и страницей (проза с врезкой), и
// обе цитируют отказ как текст. Литера разметки здесь не гасится — литерал
// отказа её не содержит, а гашение сдвинуло бы пробелы внутри чужого текста.
func MissingRefusalLiterals(src []byte, declared []string) []string {
	var missing []string
	text := string(src)
	for _, lit := range declared {
		if !strings.Contains(text, lit) {
			missing = append(missing, lit)
		}
	}
	return missing
}

// RefusalFinding — текст находки: поверхность, которая объявленный отказ не
// несёт. Называет каждый недостающий литерал, потому что пропажа признака при
// живом тексте и пропажа текста при живом признаке — разные дефекты, и читатель
// обязан видеть, какой из них перед ним.
func RefusalFinding(path string, missing []string) string {
	var b strings.Builder
	b.WriteString(path)
	b.WriteString(" не несёт объявленный отказ дословно; отсутствует: ")
	quoted := make([]string, 0, len(missing))
	for _, m := range missing {
		quoted = append(quoted, strconv.Quote(m))
	}
	b.WriteString(strings.Join(quoted, ", "))
	return b.String()
}
