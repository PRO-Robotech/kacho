// gatecarrierremoval.go — разбор класса «носитель гейта исчез МОЛЧА».
//
// Живёт в НЕ-тестовом файле намеренно: инъекция обязана звать ТУ ЖЕ функцию,
// что и гейт, иначе она доказывает свойство своей копии.
//
// # Предмет: единственная правка, которую прогон не может заметить
//
// Гейт, потерявший способность падать, на чистом дереве выглядит ТОЧНО ТАК ЖЕ,
// как исправный. Отсюда асимметрия, которой нет больше ни у одной правки:
// удаление сторожа делает прогон ЗЕЛЕНЕЕ и при этом не может быть замечено
// прогоном by construction — проверка исчезает вместе со своей способностью
// краснеть.
//
// Замер, из которого гейт выведен (`d46aaa7280`, задача продукта #2167): одно
// изменение на 911 файлов удалило ДЕВЯТЬ носителей — три семейства по три файла
// (разбор, гейт, инъекция). Сообщение коммита об этом не говорит ни строкой.
// `go test ./internal/repohygiene/...` дал код 0: держателей в дереве не стало,
// а предмет остался живым. Утрачено было 34 гейтовых утверждения (перепись имён
// `func Test` в корпусе: 2463 → 2429).
//
// # Чем это отличается от соседнего класса, уже записанного корпусом
//
// `testing.md` §«Гейт на класс», п. 9 говорит о проверке, которая ЗАМОЛКАЕТ,
// когда снят её ПРЕДМЕТ: ветвь цела, вход перестал быть представимым. Здесь
// обратное — снят не предмет, а САМА проверка, и ловить её некому: у гейта нет
// ведомости, которая бы истекла вместе с ним.
//
// # Почему признак ОБЯЗАН быть разностным, а не свойством дерева
//
// Ни одно состояние дерева не отличает «гейта здесь никогда не было» от «гейт
// отсюда убрали»: удаление СОГЛАСОВАННОЕ (разбор, гейт и инъекция уходят
// вместе) не оставляет ни висячей ссылки, ни осиротевшей пары. Замер это
// подтверждает: три снятых семейства цитировались ТОЛЬКО собственными
// файлами-соседями, то есть цитаты ушли вместе с предметом.
//
// Значит источник знания о прошлом ровно один — git. Отсюда форма: перепись
// носителей СЕЙЧАС против переписи на базе линии.
//
// # Почему единица счёта — ФАЙЛ-носитель, а не имя утверждения
//
// Решено замером, а не вкусом. Обе единицы прогнаны по 120 переходам первого
// родителя, ПО ДВУМ РАЗНЫМ ЦЕПЯМ — они дают разные числа, и цепь обязана быть
// названа вместе с числом:
//
//	цепь                  единица ИМЯ        единица ФАЙЛ
//	релизной линии        7 срабат. / 49     3 срабат. / 15
//	ствола (origin/main)  7 срабат. / 25     3 срабат. / 10
//
// Имя утверждения даёт в основном ШУМ ПЕРЕИМЕНОВАНИЙ: из семи срабатываний по
// именам шесть были переименованием либо обобщением того же гейта
// (`TestNoMakefileRunsAComparison…` → `TestNoRecipeOrScriptRunsAComparison…`,
// семейство `TestDocsBodyInjection_*` → `TestBodyGate_*`). Признак, краснеющий
// на верной работе, отключат первым — поэтому единица иная.
//
// # Чего распознавание переименований в этом замере НЕ сделало
//
// Сокращение 7 → 3 целиком есть переход от единицы ИМЯ к единице ФАЙЛ, и
// заслуги флага `-M` в нём НЕТ: переименований `.go` в корпусе за окно замера
// ровно НОЛЬ (`--diff-filter=R` → 0), поэтому `-M` и `--no-renames` дают там
// побайтово одно и то же — 3 срабатывания, 15 файлов.
//
// Флаг всё равно стоит, и это защита, а не украшение: распознавание
// переименований выключается настройкой `diff.renames=false`, и тогда всякое
// переименование носителя приходило бы видом `D`. Здесь оно объявлено явно,
// чтобы вердикт не зависел от настройки клона. Проба на переименование ниже
// поэтому и заведена: без неё свойство держалось бы пустым окном замера.
//
// # База — ТОЧКА ОТВЕТВЛЕНИЯ ЛИНИИ, а не ствол (иначе гейт слеп к своему же инциденту)
//
// Первая редакция брала базой ствол (`origin/main`) и была ЗЕЛЕНА на том самом
// коммите, ради которого заведена. Причина структурная, а не описка: все девять
// снятых носителей были заведены и убиты ВНУТРИ одной релизной линии, в
// `origin/main` их нет ни одного. Файл, рождённый после точки ответвления и
// убитый до HEAD, видом `D` не приходит НИКОГДА — его нет ни на одном конце
// сравнения. Замер на коммите инцидента:
//
//	база = origin/main   → снятых носителей 0   (гейт молчит)
//	база = точка ответвления линии → 9          (гейт краснеет)
//
// Отсюда правило, и оно одно на все случаи: база есть ТОЧКА, ОТ КОТОРОЙ ОТОШЛО
// ТЕКУЩЕЕ ИЗМЕНЕНИЕ.
//
//   - изменение ещё не принадлежит ни одной линии (живая полоса) → ближайшая
//     по `merge-base` точка ответвления среди линий и ствола. Ближайшая, а не
//     ствол: ствол лежит дальше, и всё, что линия завела и сняла у себя, в
//     сравнении с ним отсутствует на обоих концах;
//   - изменение УЖЕ принадлежит какой-либо линии или стволу → `HEAD^`. Судится
//     последнее изменение, а не вся линия: остальное уже судилось, когда было
//     вершиной.
//
// Ссылки-кандидаты берутся у git (`for-each-ref`), а не выписываются: список
// имён линий разошёлся бы с деревом молча. Origin впереди локальных — конвейер
// видит именно его, и локальная ветка соседа не вправе двигать базу.
//
// Ручка [gateCarrierBaseEnv] перебивает вывод: на запросе слияния точную базу
// знает конвейер, и угадывать её здесь незачем.
//
// # Что отличает «снято вместе с предметом» от «снято молча»
//
// Надгробие [gateCarrierLedgerName]. Запись в нём есть ОБЪЯВЛЕНИЕ снятия:
// названы носитель, причина и преемник предмета. Нет записи — снятие молчаливое,
// и это находка С ИМЕНЕМ носителя.
//
// Надгробие не вырождается в перечень имён гейтов, потому что называет только
// СНЯТОЕ и самоистекает в обе стороны: запись, чей носитель в дереве ЕСТЬ,
// прикрывала бы живую координату и потому сама находка. Именно этим оно
// отличается от запрещённого потолка «не меньше N гейтов»: потолок не краснеет
// на осмысленном снятии и не истекает никогда.
//
// # Границы названы, а не умолчаны
//
// Корпус — [gateCorpusDir], и только он. Каталог `tools` несёт ещё 18 гейтовых
// файлов и сюда НЕ включён осознанно: замер по тем же 120 переходам дал там
// одно событие на 29 файлов (вынос службы доступа в отдельный репозиторий), и
// надгробие из 29 строк на один законный переезд сделало бы механизм тем самым
// признаком, который отключают первым. Расширение корпуса — свой предмет со
// своим замером, а не строка здесь.
//
// Предмет — СНЯТИЕ НОСИТЕЛЯ, и два соседних класса он не ловит. Оба названы
// здесь, а не только в отчёте о работе: отчёт через полгода никто не откроет.
//
//   - ВЫХОЛАЩИВАНИЕ БЕЗ УДАЛЕНИЯ. Тело утверждения вырезано, гейт сведён к
//     раннему `return`, инъекция обессмыслена — файл при этом на месте, и здесь
//     находки не будет. Это соседний класс (`testing.md` §«Гейт на класс», п. 9
//     и п. 8): его держат инъекция и требование доказывать способность падать
//     повторно после переустройства, а не перепись носителей.
//   - СНЯТИЕ ОТДЕЛЬНОГО `func Test` ИЗ СОХРАНЁННОГО ФАЙЛА. Утверждение исчезло,
//     носитель остался — молчание. Это прямая и ИЗМЕРЕННАЯ цена выбора файла
//     единицей: обратный выбор ловил бы этот случай, но давал шесть ложных из
//     семи (таблица выше), а признак, краснеющий на верной работе, отключают
//     первым. Класс остаётся открытым, и здесь он назван, а не умолчан.
//
// gateCorpusDir — корпус носителей гейта относительно корня дерева.
//
// Самоистечение: перепись ниже отказывает на нулевом обходе, поэтому переезд
// или исчезновение каталога даёт ОТКАЗ, а не тихое «ноль находок».
const gateCorpusDir = "internal/repohygiene"

// gateCarrierLedgerName — имя надгробия. Лежит внутри самого корпуса: снятие
// носителя и объявление снятия правятся одним изменением.
const gateCarrierLedgerName = "retired_gate_carriers.json"

// GateCarrierRetirement — одна запись надгробия: носитель, которого в дереве
// больше нет.
type GateCarrierRetirement struct {
	// Carrier — путь снятого носителя от корня дерева, ровно в том виде, в
	// каком его называет git.
	Carrier string `json:"carrier"`
	// Reason — почему носитель снят. Пустая причина превращает надгробие в
	// список имён: она ничего не объявляет и ничем не проверяется.
	Reason string `json:"reason"`
	// Successor — кто держит предмет теперь либо чем доказано, что предмета
	// больше нет. Отвечает на единственный вопрос, ради которого запись и
	// заводится: что стало со свойством, которое этот носитель стерёг.
	Successor string `json:"successor"`
}

// gateCarrierLedger — надгробие снятых носителей.
//
// Две формы записи, и обе объявляют одно — осознанное снятие. Различаются
// ЗЕРНОМ, а не смыслом: [GateCarrierRetirement] называет ТОЧНЫЙ путь (единица
// корпуса, где носителей десятки), [GateCarrierScopeRetirement] — ПРИСТАВКУ
// (единица дерева, где одно решение уносит десятки носителей разом, и запись на
// каждого была бы перечнем имён, а не объявлением).
//
// Надгробие ОДНО на обе формы намеренно: два надгробия об одном предмете
// разошлись бы молча. Читатель тоже один — [readGateCarrierLedger].
//
// Разбор здесь судит ТОЛЬКО точные записи: его предмет — корпус, и приставок
// корпус не знает. Записи-приставки судит перепись снятых путей по дереву
// (removedpathcensus.go), и разведены предметы затем, чтобы одно снятие не
// давало двух находок.
type gateCarrierLedger struct {
	Retired []GateCarrierRetirement `json:"retired"`
	// RetiredScopes — записи-приставки. Разбором корпуса НЕ читаются: у корпуса
	// нет предмета, который они объявляют.
	RetiredScopes []GateCarrierScopeRetirement `json:"retired_scopes,omitempty"`
}

// readGateCarrierLedger читает надгробие из корпуса.
//
// Отсутствие файла — НЕ ошибка и не находка: дерево, из которого носителей не
// снимали, надгробия не несёт, и это норма (и цель). Возвращается (nil, nil).
// Пустое надгробие обязано быть зелёным по той же причине: проба не имеет права
// падать на достижении своей цели.
func readGateCarrierLedger(root string) (*gateCarrierLedger, error) {
	p := filepath.Join(root, filepath.FromSlash(gateCorpusDir), gateCarrierLedgerName)
	// #nosec G304 — путь собран из корня, названного вызывающим, и двух КОНСТАНТ.
	b, err := os.ReadFile(p)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var l gateCarrierLedger
	if err := json.Unmarshal(b, &l); err != nil {
		return nil, fmt.Errorf("%s: %w", gateCarrierLedgerName, err)
	}
	return &l, nil
}

// gateCarrierCensus — носители, которые в корпусе ЕСТЬ, путями от корня дерева.
//
// Состав берётся у git-индекса ([treecorpus]), а не обходом диска: вердикт
// обязан быть свойством коммита, а не рабочего каталога. Пустой обход —
// ОТКАЗ: «ноль находок» на «ноль прочитанного» неотличимо от чистого дерева.
func gateCarrierCensus(root string) (map[string]bool, error) {
	files, err := treecorpus.UnderWithSuffix(filepath.Join(root, filepath.FromSlash(gateCorpusDir)), ".go")
	if err != nil {
		return nil, err
	}
	present := map[string]bool{}
	for _, abs := range files {
		rel, err := filepath.Rel(root, abs)
		if err != nil {
			return nil, err
		}
		present[filepath.ToSlash(rel)] = true
	}
	if len(present) == 0 {
		return nil, fmt.Errorf(
			"корпус %s не дал ни одного носителя — смотреть было не на что; "+
				"это отказ, а не пустой успех: проверь, не переехал ли каталог",
			gateCorpusDir)
	}
	return present, nil
}

// deletedGateCarriers — носители, СНЯТЫЕ между базой и HEAD.
//
// `-M` включает распознавание переименований: переименованный файл приходит
// видом R и в снятые не попадает. Порог сходства считает git, а не этот код, —
// иначе здесь появился бы придуманный порог, который никто не мерил.
//
// Форма `base...HEAD` — та же, что у соседних гейтов дерева: сравнение идёт от
// ТОЧКИ ОТВЕТВЛЕНИЯ, поэтому вердикт относится к текущему изменению целиком, а
// не к последнему коммиту.
func deletedGateCarriers(root, base string) ([]string, error) {
	out, err := gitenv.Command(root, "diff", "-M", "--diff-filter=D", "--name-only",
		base+"...HEAD", "--", gateCorpusDir).Output()
	if err != nil {
		return nil, fmt.Errorf("git diff от %s: %w — сравнить не с чем, "+
			"и это отказ, а не пустой успех", base, err)
	}
	var gone []string
	for _, rel := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if rel == "" || !strings.HasSuffix(rel, ".go") {
			continue
		}
		gone = append(gone, rel)
	}
	sort.Strings(gone)
	return gone, nil
}

// judgeGateCarrierRemoval — ЧИСТОЕ суждение: что из снятого объявлено, а что нет.
//
// Разведено с добычей входа намеренно: инъекция гоняет эту функцию на настоящем
// синтетическом репозитории, а не на её копии.
// everRemovedFn — предикат «этот путь когда-либо снимали». Передаётся, а не
// зовётся напрямую, чтобы суждение осталось проверяемым без git.
type everRemovedFn func(carrier string) (bool, error)

func judgeGateCarrierRemoval(
	deleted []string, present map[string]bool, l *gateCarrierLedger, everRemoved everRemovedFn,
) []string {
	declared := map[string]GateCarrierRetirement{}
	var findings []string

	if l != nil {
		seen := map[string]bool{}
		rows := append([]GateCarrierRetirement(nil), l.Retired...)
		sort.Slice(rows, func(i, j int) bool { return rows[i].Carrier < rows[j].Carrier })
		for _, r := range rows {
			switch {
			case r.Carrier == "":
				findings = append(findings, fmt.Sprintf(
					"%s: запись без носителя — объявлять нечего", gateCarrierLedgerName))
				continue
			case seen[r.Carrier]:
				findings = append(findings, fmt.Sprintf(
					"%s: %q назван дважды", gateCarrierLedgerName, r.Carrier))
				continue
			}
			seen[r.Carrier] = true

			// Самоистечение: запись, чей носитель в дереве ЕСТЬ, прикрывает
			// живую координату — то есть стала бы маской.
			if present[r.Carrier] {
				findings = append(findings, fmt.Sprintf(
					"%s: числит снятым носитель %q, а он в дереве ЕСТЬ — "+
						"эта запись прикрыла бы живую координату; снимите запись",
					gateCarrierLedgerName, r.Carrier))
				continue
			}
			// Второе направление истечения: строке есть что покрывать.
			// Без него запись, чьё снятие уехало за базу, перестала бы
			// проверяться вовсе и жила бы вечно неопровержимой.
			if everRemoved != nil {
				was, err := everRemoved(r.Carrier)
				if err != nil {
					findings = append(findings, fmt.Sprintf(
						"%s: историю %q прочитать не удалось (%v) — это отказ, а не пустой успех",
						gateCarrierLedgerName, r.Carrier, err))
					continue
				}
				if !was {
					findings = append(findings, fmt.Sprintf(
						"%s: %q не снимали НИКОГДА — в истории, достижимой от HEAD, нет коммита, "+
							"убравшего этот путь. Строке нечего покрывать: она объявляет снятие, "+
							"которого не было; снимите запись либо исправьте путь",
						gateCarrierLedgerName, r.Carrier))
					continue
				}
			}
			if strings.TrimSpace(r.Reason) == "" {
				findings = append(findings, fmt.Sprintf(
					"%s: %q снят без причины — запись ничего не объявляет",
					gateCarrierLedgerName, r.Carrier))
				continue
			}
			if strings.TrimSpace(r.Successor) == "" {
				findings = append(findings, fmt.Sprintf(
					"%s: %q снят, но не сказано, что стало с его предметом — "+
						"назовите держателя либо чем доказано, что предмета нет",
					gateCarrierLedgerName, r.Carrier))
				continue
			}
			declared[r.Carrier] = r
		}
	}

	for _, c := range deleted {
		if _, ok := declared[c]; ok {
			continue
		}
		findings = append(findings, fmt.Sprintf(
			"носитель гейта %s снят МОЛЧА: в %s о нём записи нет. "+
				"Снятие носителя — единственная правка, которую прогон заметить не может: "+
				"проверка исчезает вместе со своей способностью краснеть. "+
				"Исходов два — вернуть носитель либо объявить снятие записью "+
				"(носитель, причина, что стало с предметом)",
			c, gateCarrierLedgerName))
	}

	sort.Strings(findings)
	return findings
}

// gateCarrierBaseEnv — ручка, которой вызывающий называет базу точно.
//
// Нужна конвейеру: на запросе слияния база известна ему достоверно
// (`pull_request.base.sha`), и вывод её из ссылок там лишний.
const gateCarrierBaseEnv = "KACHO_GATE_CARRIER_BASE"

// gateLineRefGlobs — ФОРМЫ имён линий, а не их перечень. Перечень имён линий
// стареет молча; форма переживает заведение и снятие каждой из них.
//
// Порядок значим: origin — то, что видит конвейер; локальные — то, что есть у
// человека в клоне без удалённого. Локальные берутся ТОЛЬКО когда ни одна
// origin-ссылка не резолвится, иначе ветка соседа, отошедшая от моей линии
// позже точки ответвления, придвинула бы базу к HEAD и сузила предмет.
var gateLineRefGlobs = [][]string{
	{"refs/remotes/origin/main", "refs/remotes/origin/release/*"},
	{"refs/heads/main", "refs/heads/release/*"},
}

// gateCarrierBase — точка, от которой отошло текущее изменение.
//
// Возвращает ревизию и СЛОВЕСНОЕ описание того, как она получена: перепись
// обязана называть не только число, но и то, с чем сравнивали, — иначе «снято
// 0» неотличимо от «сравнивали не с тем».
func gateCarrierBase(root string) (rev, how string, err error) {
	if v := strings.TrimSpace(os.Getenv(gateCarrierBaseEnv)); v != "" {
		return v, fmt.Sprintf("%s=%s (объявлена ручкой)", gateCarrierBaseEnv, v), nil
	}

	var refs []string
	for _, globs := range gateLineRefGlobs {
		args := append([]string{"for-each-ref", "--format=%(refname)"}, globs...)
		out, e := gitenv.Command(root, args...).Output()
		if e != nil {
			return "", "", fmt.Errorf("перечислить ссылки линий: %w", e)
		}
		for _, r := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if r != "" {
				refs = append(refs, r)
			}
		}
		if len(refs) > 0 {
			break
		}
	}

	// Принадлежит ли HEAD уже какой-нибудь линии. Если да — сравнивать с точкой
	// её ответвления бессмысленно: она совпадёт с HEAD либо уедет за него, и
	// предметом станет чужая, уже судившаяся работа.
	for _, ref := range refs {
		if gitenv.Command(root, "merge-base", "--is-ancestor", "HEAD", ref).Run() == nil {
			parent, e := gitenv.Command(root, "rev-parse", "--verify", "--quiet", "HEAD^").Output()
			if e != nil || strings.TrimSpace(string(parent)) == "" {
				return "", "", fmt.Errorf(
					"HEAD принадлежит линии %s, но у него нет родителя — сравнить не с чем; "+
						"это отказ, а не пустой успех", ref)
			}
			return strings.TrimSpace(string(parent)),
				fmt.Sprintf("HEAD^ (изменение уже принадлежит линии %s)", ref), nil
		}
	}

	// Живая полоса: ближайшая точка ответвления.
	best, bestRef, bestDist := "", "", -1
	for _, ref := range refs {
		mb, e := gitenv.Command(root, "merge-base", "HEAD", ref).Output()
		if e != nil {
			continue // ссылка без общей истории с HEAD точкой ответвления не является
		}
		base := strings.TrimSpace(string(mb))
		if base == "" {
			continue
		}
		cnt, e := gitenv.Command(root, "rev-list", "--count", base+"..HEAD").Output()
		if e != nil {
			continue
		}
		d, e := strconv.Atoi(strings.TrimSpace(string(cnt)))
		if e != nil {
			continue
		}
		if bestDist < 0 || d < bestDist {
			best, bestRef, bestDist = base, ref, d
		}
	}
	if best == "" {
		return "", "", fmt.Errorf(
			"ни одна ссылка линии или ствола не дала точки ответвления (осмотрено ссылок %d) — "+
				"сравнить не с чем; чинится глубиной клона, а не терпимостью гейта", len(refs))
	}
	return best, fmt.Sprintf("точка ответвления от %s (%s, впереди коммитов %d)",
		bestRef, best[:min(len(best), 10)], bestDist), nil
}

// carrierWasEverRemoved — есть ли в истории, достижимой от HEAD, коммит,
// СНЯВШИЙ этот путь.
//
// Это второе направление истечения записи надгробия. Первое («носитель жив»)
// ловит воскрешение; но после того как снятие уедет за базу, запись перестаёт
// проверяться дельтой вовсе — и без этой проверки ЛЮБАЯ строка выродилась бы в
// форму «покрывать нечего» и жила бы вечно неопровержимой. История же помнит
// снятие всегда, поэтому запись остаётся falsifiable до конца своих дней.
//
// `--no-renames` намеренно: спрашивается «исчез ли этот путь», а не «куда
// уехало содержимое».
func carrierWasEverRemoved(root, carrier string) (bool, error) {
	out, err := gitenv.Command(root, "log", "--no-renames", "--diff-filter=D",
		"--format=%H", "-n", "1", "HEAD", "--", carrier).Output()
	if err != nil {
		return false, fmt.Errorf("история пути %s: %w", carrier, err)
	}
	return strings.TrimSpace(string(out)) != "", nil
}
