// «Сервис принял единую форму имени» — ОДНО производное на два гейта.
//
// # Что здесь было неверно и почему это класс, а не опечатка
//
// Два гейта выводили одно и то же — какие схемы пришли к канону формы имени
// (#715) — и оба выводили это ИЗ ИМЕНИ ФАЙЛА `*_resource_name_single_form.sql`.
// Имя файла было ПРОКСИ: настоящий признак — ограничение формы имени в схеме, а
// файл лишь то место, откуда оно однажды туда попало.
//
// Прокси пережил свой предмет ровно так, как проксям и положено. Цепь iam сведена
// в одну первичную миграцию: ограничение на месте, файла нет. Гейт суффикса стал
// считать пять схем вместо шести и падать на переписи, а гейт имён фикстур —
// вовсе не смотреть в коллекции iam, отчего его освобождение `/iam/v1/roles`
// потеряло предмет и было объявлено находкой. Одна причина, две разные красноты,
// и ни одна не про то, что сломано.
//
// # Отбор и утверждение — РАЗНЫЕ признаки, и это несущее
//
// Отбирает форма имени, записанная строковым литералом SQL; утверждается имя
// ограничения. Соблазн отбирать по тому же суффиксу велик и неверен: предикат
// совпал бы с предметом, и гейт подтверждал бы сам себя — зеленел бы на любой
// схеме, а на схеме без суффикса просто не считал бы её принявшей канон.
//
// Литерал в кавычках, а не просто вхождение формы: в шапке миграции vpc форма
// стоит прозой (в обратных кавычках, RFC-ссылкой), и предикат по вхождению
// принял бы объяснение за объявление — тот самый класс, который корпус ловит
// (`testing.md` §«Гейт на класс», п. 4).
//
// # Обе законные формы записи, а не та, что попалась
//
// Миграцию пишет человек: форма кладётся в переменную, имена ограничений
// строятся `format`-ом с суффиксом. Сведённую схему печатает `pg_dump`: те же
// ограничения стоят материализованными, с формой прямо в `CHECK`. Записи разные,
// предмет один; распознаватель, знающий одну из них, на другой МОЛЧИТ — не
// краснеет и не зеленеет (`testing.md` §«Гейт на класс», п. 7).

// nameFormCanonLiteral — форма имени, записанная строковым литералом SQL.
//
// Значение выписано, а не взято из `pkg/validate/nameform`: гейты сверяют
// константу пакета с деревом, и взяв её оттуда же, сверяли бы значение с самим
// собой.
var nameFormCanonLiteral = regexp.MustCompile(`'\^\[a-z0-9\]\(\[-a-z0-9\]\{0,61\}\[a-z0-9\]\)\?\$'`)

// nameFormMaterialisedConstraint — материализованное ограничение, несущее форму:
// `CONSTRAINT <имя> CHECK ((name ~ '<форма>'...))`. Есть только у сведённой схемы —
// у неписаной цепи имена строятся в рантайме и в тексте их нет.
var nameFormMaterialisedConstraint = regexp.MustCompile(
	`CONSTRAINT\s+([a-z0-9_]+)\s+CHECK\s*\(\(\s*name\s*~\s*'\^\[a-z0-9\]`)

// nameFormAdoption — что известно про схему, принявшую канон.
type nameFormAdoption struct {
	// Service — каталог сервиса под `services/`.
	Service string
	// File — путь к файлу миграции, ОБЪЯВЛЯЮЩЕМУ форму, относительно корня.
	// Он же координата в тексте находки: без неё читателю нечего открывать.
	File string
}

// nameFormCanonAdoptions — схемы, ПРИНЯВШИЕ единую форму имени, выведенные из
// СОДЕРЖИМОГО миграций.
//
// # Граница, названная честно: «приняла» — не то же, что «несёт сейчас»
//
// Предикат судит ОБЪЯВЛЕНИЕ формы и ничего не знает о её последующем снятии.
// Разница не умозрительная: geo объявил форму в `715001` и снял её целиком в
// `716001` вместе со столбцом имени, поэтому сегодня он в перечне «принявших»
// стоит, а формы не несёт. Прежний отбор по имени файла считал его точно так же,
// так что здесь ничего не изменилось, — но и не исправилось.
//
// Различать «поставлена» и «стоит сейчас» умеет соседний механизм,
// `nameformdbprobe.go`: он судит миграции В ПОРЯДКЕ ПРИМЕНЕНИЯ и вычитает
// снятие (`nameFormWithdrawnRe`). Его перепись на том же дереве даёт ПЯТЬ
// сервисов против шести здесь, и расхождение это — не спор, а разные вопросы:
// там «чей сервер отвергает негодное имя», здесь «чьё объявление формы строит
// имена ограничений условленным суффиксом». Второе остаётся верным и после
// снятия: миграция, которая форму ставила, суффикс использовала.
//
// Сказано вслух, чтобы следующий читатель не принял одно за другое и не свёл два
// вопроса к одному числу.
//
// Единица счёта — СЕРВИС, а не файл. Прежде считались файлы, и совпадение
// «по одному на сервис» было случайным: заведи кто-нибудь вторую миграцию,
// трогающую форму, и перепись выросла бы, ничего не сообщив о числе схем.
//
// Возвращает отсортированный срез, чтобы перечень в переписи и в находках был
// устойчив между прогонами.
func nameFormCanonAdoptions(root string) ([]nameFormAdoption, error) {
	files, err := treecorpus.UnderWithSuffix(root, ".sql")
	if err != nil {
		return nil, fmt.Errorf("состав дерева у индекса репозитория: %w", err)
	}

	bodies := map[string][]byte{}
	for _, abs := range files {
		rel, rerr := filepath.Rel(root, abs)
		if rerr != nil {
			continue
		}
		body, rerr := os.ReadFile(abs) // #nosec G304 -- путь из индекса репозитория
		if rerr != nil {
			return nil, fmt.Errorf("read %s: %w", rel, rerr)
		}
		bodies[filepath.ToSlash(rel)] = body
	}
	return nameFormCanonAdoptionsFrom(bodies), nil
}

// nameFormCanonAdoptionsFrom — ОТБОР, отделённый от обхода дерева.
//
// Отделён ради инъекции: дерево нарочно не испортишь, а предикат, который нельзя
// заставить ответить иначе, от неспособного ответить иначе не отличить. На вход
// подаётся состав «путь → содержимое», и обе законные формы записи проверяются
// подачей, а не рассуждением.
func nameFormCanonAdoptionsFrom(bodies map[string][]byte) []nameFormAdoption {
	byService := map[string]nameFormAdoption{}
	for rel, body := range bodies {
		parts := strings.Split(rel, "/")
		if len(parts) < 5 || parts[0] != "services" || parts[2] != "internal" || parts[3] != "migrations" {
			continue
		}
		if !strings.HasSuffix(rel, ".sql") || !nameFormCanonLiteral.Match(body) {
			continue
		}
		svc := parts[1]
		// Побеждает позднейший файл по имени: у goose имя и есть порядок, а
		// объявление формы, приехавшее позже, и есть действующее.
		if prev, ok := byService[svc]; !ok || rel > prev.File {
			byService[svc] = nameFormAdoption{Service: svc, File: rel}
		}
	}

	out := make([]nameFormAdoption, 0, len(byService))
	for _, a := range byService {
		out = append(out, a)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Service < out[j].Service })
	return out
}

// adjudicateNameFormConstraintNaming — СУЖДЕНИЕ о том, строит ли объявление формы
// имена ограничений условленным суффиксом. Отделено от добычи ради инъекции:
// уронить настоящее дерево нарочно нельзя, а проверку, которую нельзя уронить, от
// неспособной упасть не отличить.
//
// Возвращает находки; пусто — согласие.
func adjudicateNameFormConstraintNaming(a nameFormAdoption, body, suffix string) []string {
	var out []string
	if !strings.Contains(body, suffix) {
		out = append(out, fmt.Sprintf("%s (%s): объявление формы имени не строит имя ограничения суффиксом %q — "+
			"отображение ошибки перестанет узнавать полосу формы имени, и «сервис пропустил негодное имя» "+
			"снова прочитается как «виноват ваш ввод»", a.Service, a.File, suffix))
	}

	// У сведённой схемы ограничения стоят материализованными, и тогда суффикс
	// проверяется у КАЖДОГО, а не вообще где-то в файле. У неписаной цепи таких
	// вхождений ноль — имена там строятся в рантайме, — и эта половина
	// вырождается в тождество; так и должно быть, поэтому её отсутствие находкой
	// НЕ объявляется.
	for _, m := range nameFormMaterialisedConstraint.FindAllStringSubmatch(body, -1) {
		if !strings.HasSuffix(m[1], suffix) {
			out = append(out, fmt.Sprintf("%s (%s): ограничение %q несёт форму имени, но названо не суффиксом %q — "+
				"отображение ошибки не узнает именно это ограничение, а остальные узнает, и полоса отказа станет "+
				"зависеть от того, на какую таблицу попал арендатор", a.Service, a.File, m[1], suffix))
		}
	}
	return out
}
