// publishedkeyprivatehalf_test.go — публикуемая форма подписного ключа не имеет
// поля для приватной половины (приёмка F1, сценарий F1-05).
//
// # Предмет
//
// Приватный материал не покидает процесс — ни журналом, ни текстом ошибки, ни
// метрикой, ни ответом. Из всех этих носителей ОТВЕТ отличается тем, что его
// содержимое задаётся ТИПОМ, а тип проверяет компилятор. Значит требование
// выражается формой, а не вниманием: у публикуемого типа поля приватной
// половины нет, и положить её туда НЕ ВЫРАЖАЕТСЯ.
//
// Форма «поле есть, но на этом пути мы его не заполняем» отвергнута осознанно.
// Она возлагает свойство на каждого будущего вызывающего сразу: заполнить поле
// законно, компилятор не возразит, а проба заметит это лишь там, где кто-то
// догадался сравнить ответ побайтово.
//
// # Почему у гейта ОБЯЗАН быть положительный близнец
//
// Предмет этого гейта — ОТСУТСТВИЕ. Проверка отсутствия молчит одинаково в двух
// совершенно разных случаях: предмет исчез (хорошо) и сломалась сама проверка
// (плохо). Различить их нечем, пока рядом нет места, которое гейт ОБЯЗАН
// находить.
//
// Близнец здесь не приписан списком, а получается из самого разбора: пара
// «хранимая форма → публикуемая» опознаётся по тому, что ПРИЁМНИК проекции несёт
// приватное поле. Пропадёт разбор — пропадут и пары, и гейт скажет об этом
// прямо, вместо того чтобы молча зазеленеть.
//
// # Что здесь считается деревом
//
// Индекс git — то же множество, что увидит свежий клон и CI. Обход диска читал
// бы рабочие копии соседних сеансов, и вердикт перестал бы быть свойством
// коммита.
package repohygiene

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// keyProjectionCensusFloor — сколько не-тестовых файлов Go гейт обязан
// разобрать, чтобы его молчание вообще что-то значило.
//
// Порог намеренно занижен на порядок относительно дерева: он ловит обвал
// переписи (пустой индекс, чужой каталог, обрезанный вывод), а не рост или
// усадку дерева.
const keyProjectionCensusFloor = 500

// TestPublishedKeyFormCarriesNoPrivateHalf — сам гейт.
func TestPublishedKeyFormCarriesNoPrivateHalf(t *testing.T) {
	root := repoRoot(t)
	tt := newTrackedTree(t, root)

	var rels []string
	for rel := range tt.files {
		if !strings.HasSuffix(rel, ".go") || strings.HasSuffix(rel, "_test.go") {
			continue
		}
		if skipPath(rel) {
			continue
		}
		rels = append(rels, rel)
	}
	sort.Strings(rels)

	var parsed, types, fields int
	var projections []KeyProjection
	for _, rel := range rels {
		src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			// Файл индекса, которого нет на диске, в перепись не идёт: он не
			// находка и не тишина, он просто не прочитан.
			continue
		}
		found, census, err := ScanKeyProjections(rel, src)
		if err != nil {
			// Неразбираемый файл — отказ, а не пропуск: молча не прочитанный
			// файл и есть слепая зона, ради которой пишут перепись.
			t.Fatalf("разбор %s: %v", rel, err)
		}
		parsed++
		types += census.TypesInspected
		fields += census.FieldsInspected
		projections = append(projections, found...)
	}

	t.Logf("перепись: не-тестовых файлов Go разобрано %d, типов осмотрено %d, "+
		"полей осмотрено %d, пар «хранимая → публикуемая» найдено %d",
		parsed, types, fields, len(projections))

	if parsed < keyProjectionCensusFloor {
		t.Fatalf("перепись обвалилась: разобрано %d файлов при пороге %d — "+
			"«ноль находок» на таком объёме означало бы «ноль прочитанного»",
			parsed, keyProjectionCensusFloor)
	}

	// ПОЛОЖИТЕЛЬНЫЙ БЛИЗНЕЦ. Гейт обязан найти хотя бы одну пару: место, где
	// хранимая форма приватную половину НЕСЁТ. Ноль пар означает не «приватного
	// материала в дереве нет», а «разбор перестал видеть предмет» — и тогда
	// утверждение об отсутствии сделано ни о чём.
	if len(projections) == 0 {
		t.Fatalf("не найдено НИ ОДНОЙ пары «хранимая форма ключа → публикуемая» "+
			"(разобрано %d файлов, %d типов, %d полей).\n"+
			"Это отказ, а не чистота: предмет гейта — ОТСУТСТВИЕ приватного поля у "+
			"публикуемой формы, и такая проверка молчит одинаково когда предмет исчез и "+
			"когда сломалась она сама. Пара — единственное, что эти два случая различает.\n"+
			"Исходов два: либо проекция ключа переехала и разбор надо привести за ней, "+
			"либо хранимая форма перестала нести приватную половину — и тогда гейту "+
			"больше нечего охранять, а его место в дереве надо пересмотреть, а не "+
			"оставить зелёным.", parsed, types, fields)
	}

	var findings []string
	for _, p := range projections {
		if p.SameType {
			findings = append(findings, fmt.Sprintf(
				"%s:%d  %s проецирует %s в САМ СЕБЯ — публикуемая форма не отделена от хранимой",
				p.File, p.Line, p.Method, p.StoredType))
		}
		for _, f := range p.PrivateInPublished {
			findings = append(findings, fmt.Sprintf(
				"%s:%d  публикуемая форма %s несёт поле %s %s (проекция %s из %s)",
				p.File, f.Line, p.PublishedType, f.Name, f.Type, p.Method, p.StoredType))
		}
	}
	sort.Strings(findings)

	if len(findings) > 0 {
		t.Fatalf("публикуемая форма подписного ключа несёт приватный материал — %d место(а):\n  %s\n\n"+
			"Требование выражается ФОРМОЙ: у публикуемого типа поля приватной половины нет, "+
			"поэтому положить её туда не выражается. Вариант «поле есть, но мы его не "+
			"заполняем» держится вниманием каждого будущего вызывающего сразу — компилятор "+
			"такое заполнение примет, и заметит его только тот, кто догадается сравнить "+
			"ответ побайтово.\n"+
			"Снятие: два отдельных типа и ОДНОСТОРОННЯЯ проекция из хранимого в публикуемый; "+
			"обратного конструктора не заводить.",
			len(findings), strings.Join(findings, "\n  "))
	}

	for _, p := range projections {
		t.Logf("пара найдена: %s:%d  %s → %s (метод %s), приватных полей у хранимой формы %d",
			p.File, p.Line, p.StoredType, p.PublishedType, p.Method, len(p.StoredPrivate))
	}
}
