package repohygiene

// treewalkverdict.go — ОДИН судья исхода обхода на все гейты дерева.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПРЕДМЕТ
//
// Гейт, обходящий дерево, отвечает «находок ноль» тремя разными способами, и
// снаружи они выглядят одинаково: предмет есть и он чист · предмета нет вовсе ·
// ГЕЙТ НЕ СМОТРЕЛ. Измерено прогоном собранного бинаря проб из дерева в ДВА
// файла (файл модуля и один файл Go): из 544 проб о дереве 28 остались
// ЗЕЛЁНЫМИ, печатая «осмотрено 1, находок 0» — то есть отчитались успехом о
// дереве, которое продуктом не является.
//
// Судья здесь один и тот же для всех: класс чинится классом, а не по одному
// гейту за полосу. Форма повторяет `providerwalkverdict.go`, откуда она и
// выведена, — там же разобрано, почему знаменатель снимается ВТОРЫМ выражением.
//
// ─────────────────────────────────────────────────────────────────────────────
// ТРИ ИСТОЧНИКА ЗНАМЕНАТЕЛЯ, И НИ ОДИН НЕ ВЫРАЖЕН ОТ ПРОВЕРЯЕМОГО ОБХОДА
//
//	состав дерева   первое: обход гейта, по ИНДЕКСУ git либо по диску
//	                второе: КОММИТ (`ls-tree HEAD`), тем же отбором
//	судимое         первое: сколько путей гейт довёл до суда
//	                второе: — (отношение к обойдённому, не самостоятельное число)
//	ЧТО ЭТО ЗА      второе и единственное: ВНУТРЕННИЕ РЁБРА СБОРОЧНОГО ГРАФА,
//	ДЕРЕВО          прочитанные из файла модуля в КОММИТЕ
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРЕДПОСЫЛКА — СБОРОЧНЫЙ ГРАФ, А НЕ ПЕРЕЧЕНЬ КАТАЛОГОВ
//
// Ни одно число о САМОМ КЛАССЕ не делает гейт красным на дереве из двух файлов:
// обход честно прочитал всё, что там было, и первое выражение сходится со
// вторым — их просто нечего было считать. Красным гейт обязан стать по другой
// причине: судимое дерево ПРОДУКТОМ НЕ ЯВЛЯЕТСЯ.
//
// Перечень каталогов («есть `services/`, есть `gateway/`») был бы ведомостью:
// он слепнет ровно тогда, когда раскладка переезжает, и молчит о дереве, где
// каталоги есть, а продукта нет. Сборочный граф — свойство, а не список:
// платформа собирается против внутренних модулей семейства, и дерево, где этих
// рёбер ноль, платформой не является, как бы ни назывались его каталоги.
// Предикат уже имеет дом — им же проверяется предпосылка потолка привязок.
//
// ГРАНИЦА НАЗВАНА ВСЛУХ: подделать предпосылку можно, выписав рёбра в файл
// модуля пустого дерева. Судья ловит не злой умысел, а ОБЫЧНЫЙ способ, каким
// гейт слепнет, — прогон не там, оборванный обход, дерево, из которого предмет
// вынули целиком.

import (
	"fmt"
	"strings"
)

// Исходы обхода. Названы константами, чтобы инъекция утверждала ИСХОД, а не
// подстроку напечатанного текста.
const (
	// TreeWalkSubjectPresent — предмет класса в дереве есть, и гейт его судил.
	TreeWalkSubjectPresent = "предмет есть"
	// TreeWalkSubjectAbsent — предмета класса в дереве НЕТ. Зелёный, но
	// ОТДЕЛЬНЫЙ: законен только при доказанном знаменателе обхода.
	TreeWalkSubjectAbsent = "предмета нет"
	// TreeWalkFailed — обход не состоялся. Вердикта о предмете у гейта НЕТ.
	TreeWalkFailed = "обход не состоялся"
)

// TreeWalkCensus — перепись обхода, снятая ПЕРВЫМ выражением, то есть самим
// гейтом.
type TreeWalkCensus struct {
	// Gate — имя гейта, чтобы находка называла, чей обход не состоялся.
	Gate string
	// Walked — путей принёс обход.
	Walked int
	// Judged — из них дошли до суда. Ноль означает, что обход был, а суда не
	// было: путь отфильтрован целиком, и «находок ноль» ничего не утверждает.
	Judged int
	// Subjects — предметов класса найдено. Ноль — законный исход, но ОТДЕЛЬНЫЙ.
	Subjects int
	// Unit — единица счёта предмета. Число без единицы не читается.
	Unit string
}

// TreeWalkDenominator — знаменатель, снятый ВТОРЫМ выражением.
type TreeWalkDenominator struct {
	// CommitPaths — путей того же вида в КОММИТЕ, отобранных тем же предикатом.
	CommitPaths int
	// Exact — отбор коммита совпадает с отбором обхода точно. Ложь означает, что
	// предикат коммита ШИРЕ, и тогда требуется не равенство, а вложение.
	Exact bool
	// Expression — чем снято второе выражение. Печатается: знаменатель без
	// названия своего источника нечем перепроверить.
	Expression string
	// BuildGraphEdges — внутренних рёбер сборочного графа в файле модуля
	// КОММИТА. Ноль означает, что судимое дерево не есть дерево продукта.
	BuildGraphEdges int
}

// TreeWalkVerdict — исход обхода и, если он не состоялся, причины поимённо.
type TreeWalkVerdict struct {
	Outcome string
	// Blind — причины. Собираются ВСЕ: гейт, называющий одну, прячет остальные.
	Blind []string
}

// JudgeTreeWalk — исход обхода по переписи и знаменателю.
//
// Исходов три, и они РАЗНЫЕ. Первые два зелёные и названы по отдельности;
// третий красный, и у него нет представления на зелёном пути.
func JudgeTreeWalk(c TreeWalkCensus, d TreeWalkDenominator) TreeWalkVerdict {
	var blind []string

	// (1) ЧТО ЭТО ЗА ДЕРЕВО. Единственная причина, по которой гейт обязан
	// краснеть на дереве, где считать было нечего: считал он не продукт.
	if d.BuildGraphEdges == 0 {
		blind = append(blind, "внутренних рёбер сборочного графа в файле модуля коммита ноль: "+
			"судимое дерево не есть дерево продукта, и «находок ноль» здесь значит "+
			"«гейт прогнан не там»")
	}

	// (2) Состав дерева. Второе выражение — коммит; обход идёт по индексу либо
	// по диску, и сойтись они могут только если обход дошёл до дерева.
	switch {
	case d.CommitPaths == 0:
		blind = append(blind, fmt.Sprintf(
			"в коммите ноль путей того вида, который гейт судит (%s): спрашивать было не у чего",
			d.Expression))
	case d.Exact && c.Walked != d.CommitPaths:
		blind = append(blind, fmt.Sprintf(
			"обход принёс %d путей при %d в коммите (%s): %s",
			c.Walked, d.CommitPaths, d.Expression, treeWalkHint(c.Walked, d.CommitPaths)))
	case !d.Exact && (c.Walked == 0 || c.Walked > d.CommitPaths):
		blind = append(blind, fmt.Sprintf(
			"обход принёс %d путей при %d в коммите (%s): отбор обхода обязан быть ВЛОЖЕН "+
				"в отбор коммита и непуст",
			c.Walked, d.CommitPaths, d.Expression))
	}

	// (3) Суд состоялся. Обход, из которого до суда не дошло ничего, молчит не
	// потому, что нечего сказать.
	if c.Judged == 0 {
		blind = append(blind, "до суда не дошло ни одного пути: обход был, а суда не было")
	}

	if len(blind) > 0 {
		return TreeWalkVerdict{Outcome: TreeWalkFailed, Blind: blind}
	}
	if c.Subjects == 0 {
		return TreeWalkVerdict{Outcome: TreeWalkSubjectAbsent}
	}
	return TreeWalkVerdict{Outcome: TreeWalkSubjectPresent}
}

// treeWalkHint — направление расхождения называет разные механизмы, и лечатся
// они по-разному.
func treeWalkHint(walked, inCommit int) string {
	if walked < inCommit {
		return "обход недобрал пути коммита — он не дошёл до дерева либо оборвался"
	}
	return "обход прочитал больше, чем лежит в коммите — работа осталась в индексе, " +
		"а гейт судит коммит"
}

// String — перепись и знаменатель одной строкой, для журнала гейта.
func (v TreeWalkVerdict) String() string {
	if len(v.Blind) == 0 {
		return v.Outcome
	}
	return v.Outcome + ": " + strings.Join(v.Blind, "; ")
}
