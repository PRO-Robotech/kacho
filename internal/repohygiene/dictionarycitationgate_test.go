// dictionarycitationgate_test.go — гейт на КЛАСС: комментарий, называющий
// ограничение БД по имени и перечисляющий его значения, перечисляет их ЦЕЛИКОМ.
//
// # Предмет
//
// Ограничение вида `CHECK (<колонка> = ANY (ARRAY[…]))` закрывает набор значений,
// и это единственное место, где набор задан. Комментарий, который называет такое
// ограничение по имени и тут же перечисляет значения, делает утверждение о НЁМ —
// то есть становится вторым местом об одном предмете. Расхождение прозы с
// ограничением не даёт ни ошибки сборки, ни конфликта при слиянии: миграция
// расширяет словарь, комментарий остаётся прежним и с этого дня лжёт, стоя ровно
// там, где вызывающий решает, какое значение ему позволено записать.
//
// Живой экземпляр найден переписью по референту (2026-08-06): годок порта
// эмиссии перечислял ТРИ значения из семи и приписывал это ограничение самому
// ограничению («op MUST be one of: … (DB CHECK …)»), при том что 137 строками
// ниже, в том же файле, у поля структуры тот же набор выписан ПОЛНОСТЬЮ и верно.
// Два места об одном предмете, из которых верно одно, — и неверное стоит в
// интерфейсе, который читают чаще.
//
// # Триггер выбран так, чтобы у него был законный близнец
//
// Красит только цитата, где сошлось ОБА признака: имя ограничения И не меньше
// ДВУХ его значений. Порог в два — не осторожность, а измерение: в дереве
// сегодня десять мест называют ограничение со словарём рядом с хотя бы одним его
// значением, и одно из них — законная фраза «пустое значение приводится к
// ENABLED, чтобы ограничение держалось» (одно значение, никакого перечисления).
// Перечисление начинается с двух.
//
// Обратная половина у гейта тоже есть, и она уже в дереве: СЕМЬ мест называют
// ограничение и перечисляют его словарь ЦЕЛИКОМ. Гейт молчит на них — то есть
// он запрещает не цитирование, а НЕПОЛНОЕ цитирование.
//
// # Что читается
//
// Только КОММЕНТАРИИ Go-файлов, разобранные `go/parser` — не текст. Различать
// код, строковый литерал и комментарий обязан всякий гейт над текстом, а здесь
// это ещё и по существу: имена ограничений и их значения ЖИВУТ в коде (константы
// домена, SQL-строки репозитория, фикстуры проб), и предметом гейта они не
// являются.
//
// # Объявленные слепые зоны
//
//   - Корпус — отслеживаемые `.go`. Цитата в `.proto`, `.md`, `.mdx` этому гейту
//     невидима, и такие цитаты в дереве ЕСТЬ (напр. контрактный комментарий поля
//     `op` в proto перечисляет три значения из семи). Причина не в лени: у
//     разбора Go различение «код / литерал / комментарий» точное и бесплатное, а
//     для прочих типов пришлось бы писать свой сканер — и он стал бы третьим
//     местом, где живёт определение комментария. Число названо, чтобы зона не
//     выглядела проверенной.
//   - Словари берутся из ТЕКСТА миграций (проигрывание Up-секций). Ограничение,
//     поставленное руками мимо миграции, невидимо — как и всему семейству гейтов
//     этого пакета.
//   - Значение, упомянутое в комментарии как ЧАСТЬ другого слова, засчитывается
//     как цитата (поиск подстрокой). Ложное срабатывание такого рода даёт
//     находку, а не молчание, и снимается уточнением комментария.
package repohygiene

import (
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/PRO-Robotech/kacho/pkg/treecorpus"
)

// TestCommentCitingDictionaryConstraintQuotesItWhole — комментарий, назвавший
// ограничение со словарём и перечисливший не меньше двух его значений, обязан
// перечислить их все.
//
// Что делать, если гейт сработал, — три исхода, четвёртого нет:
//
//  1. перечень устарел -> дописать недостающие значения (они напечатаны);
//  2. перечень тут не нужен -> убрать перечисление и сослаться на ограничение
//     по имени, оставив словарь в одном месте — в миграции;
//  3. речь о ПОДМНОЖЕСТВЕ по существу («этот путь эмитит только эти два») ->
//     сказать это прямо и не называть ограничение: имя ограничения превращает
//     фразу в утверждение о полном наборе.
func TestCommentCitingDictionaryConstraintQuotesItWhole(t *testing.T) {
	root := repoRoot(t)
	dicts := enumDictionaryInventory(t, root, trackedMigrationSQL)

	if dicts.filesRead == 0 || len(dicts.byName) == 0 {
		t.Fatalf("гейт не получил ни одного именованного словаря (прочитано миграций: %d, "+
			"именованных ограничений со словарём: %d) — предпосылка сломана, молчание "+
			"ничего не доказывает (корень %s)", dicts.filesRead, len(dicts.byName), root)
	}

	files, err := treecorpus.UnderWithSuffix(root, ".go")
	if err != nil {
		t.Fatalf("состав дерева взять неоткуда: %v", err)
	}
	if len(files) == 0 {
		t.Fatalf("корпус пуст — гейту нечего читать (корень %s)", root)
	}

	names := make([]string, 0, len(dicts.byName))
	for name := range dicts.byName {
		names = append(names, name)
	}
	sort.Strings(names)

	scanned, withName, groups, citations, whole := 0, 0, 0, 0, 0
	fset := token.NewFileSet()
	for _, path := range files {
		body, readErr := os.ReadFile(path)
		if readErr != nil {
			t.Fatalf("чтение %s: %v", path, readErr)
		}
		scanned++
		text := string(body)
		// Дешёвый отсев ДО разбора: имя ограничения — редкая подстрока, и парсить
		// весь корпус ради десяти файлов незачем. Отсев идёт по СЫРОМУ тексту,
		// поэтому файл с именем в коде тоже разбирается — и отбрасывается уже
		// точным различением кода и комментария.
		hit := false
		for _, name := range names {
			if strings.Contains(text, name) {
				hit = true
				break
			}
		}
		if !hit {
			continue
		}
		withName++

		f, parseErr := parser.ParseFile(fset, path, body, parser.ParseComments)
		if parseErr != nil {
			t.Errorf("%s: не разбирается (%v) — гейт не может отличить комментарий от кода "+
				"и молчал бы о файле «чисто»", relTo(root, path), parseErr)
			continue
		}
		for _, cg := range f.Comments {
			groups++
			comment := cg.Text()
			for _, name := range names {
				if !strings.Contains(comment, name) {
					continue
				}
				variants := dicts.byName[name]
				best, bestHit := -1, 0
				for i, v := range variants {
					n := 0
					for _, val := range v.values {
						if strings.Contains(comment, val) {
							n++
						}
					}
					if n > bestHit {
						best, bestHit = i, n
					}
				}
				if bestHit < 2 {
					continue // не перечисление: имя названо, набор не пересказан
				}
				citations++
				v := variants[best]
				if bestHit == len(v.values) {
					whole++
					continue
				}
				missing := make([]string, 0, len(v.values))
				for _, val := range v.values {
					if !strings.Contains(comment, val) {
						missing = append(missing, val)
					}
				}
				t.Errorf("%s:%d — комментарий называет ограничение %s и перечисляет %d из %d "+
					"его значений: НЕ ХВАТАЕТ %v.\n"+
					"  ограничение стоит на %s.%s, словарь целиком: %v (миграция %s)\n"+
					"Имя ограничения превращает перечисление в утверждение о ПОЛНОМ наборе, "+
					"а неполный набор читается вызывающим как запрет на остальные значения. "+
					"Допиши недостающие, либо убери перечисление и сошлись на ограничение по "+
					"имени, либо — если речь о подмножестве по существу — не называй "+
					"ограничение вовсе.",
					relTo(root, path), fset.Position(cg.Pos()).Line, name,
					bestHit, len(v.values), missing, v.table, v.column, v.values, v.source)
			}
		}
	}

	t.Logf("именованных ограничений со словарём: %d; прочитано .go: %d (содержат имя "+
		"ограничения: %d); комментарных групп разобрано: %d; цитат словаря (имя + ≥2 "+
		"значения): %d, из них ЦЕЛИКОМ: %d",
		len(dicts.byName), scanned, withName, groups, citations, whole)

	// Предпосылка гейта: цитаты в дереве ЕСТЬ, и полные среди них тоже. Ноль цитат
	// означал бы, что предикат перестал их видеть, а гейт при этом остался бы
	// зелёным — то есть молчал бы ровно так же, как на чистом дереве.
	if citations == 0 {
		t.Errorf("в %d комментарных группах не нашлось НИ ОДНОЙ цитаты словаря — предикат "+
			"перестал видеть предмет (переименовали ограничения? сменился разбор?), и "+
			"молчание этого гейта больше ничего не доказывает", groups)
	}
	if whole == 0 {
		t.Errorf("среди %d цитат нет ни одной ПОЛНОЙ — законной половины у гейта не "+
			"осталось, и он неотличим от запрета цитировать словарь вообще", citations)
	}
}

// relTo (путь относительно корня дерева — координата находки обязана быть
// свойством репозитория, а не рабочего каталога того, кто её увидел) объявлена в
// panicrecoverywiring_test.go того же пакета: второй экземпляр той же функции
// разошёлся бы с первым молча.
