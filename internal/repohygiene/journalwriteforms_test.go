//
// # Предмет (#1573)
//
// Разбор, судящий точки записи журнала подписки, знал ОДНУ форму — узел вызова
// порта. У двух владельцев из пяти этой формы нет вовсе, а перепись об этом
// молчала: она называла число найденных вызовов и не называла числа точек,
// которых не видела. Молчание распознавателя неотличимо от «их нет» — это
// `testing.md` §«Гейт на класс», п. 7.
//
// Класс сработал на самом ЗАМЕРЕ: предикат по литеральному имени таблицы дал у
// одного владельца ноль писателей при живом писателе, потому что имя таблицы там
// приходит аргументом.
//
// # Что этот гейт утверждает
//
//  1. владельцы журнала ВЫВОДЯТСЯ обходом, а не выписаны;
//  2. у КАЖДОЙ формы есть живой распознаватель — он нашёл хотя бы один экземпляр
//     формы в дереве ВООБЩЕ, включая вставки в не-журнальные таблицы. Только
//     тогда ноль журнальных точек этой формы означает «искали и не нашли»;
//  3. у КАЖДОГО владельца журнала есть хотя бы одна точка записи. Журнал,
//     объявленный и никем не производимый, — не «пока пусто», а объявление без
//     предмета: подписчик открывает поток, который не наполнится никогда;
//  4. вставка, чьё имя таблицы подставляется форматированием ЦЕЛИКОМ, обязана
//     быть РАЗРЕШИМА — до константы либо до параметра объемлющей функции. Не
//     разрешилась — предмет её не установлен, и она МОЖЕТ писать журнал: тогда
//     она идёт мимо всех соседних гейтов, и ни один из них об этом не скажет.
//
// # Чего гейт НЕ утверждает
//
// # Шов с ПЕРЕПИСЬЮ ОДНОГО ВЛАДЕЛЬЦА — назван, чтобы два места не разошлись
//
// У nlb есть СВОЯ перепись форм (`TestEveryJournalWriteFormIsAccountedFor` в
// `services/nlb/internal/subscriptionjournal`), и она осталась на месте. Предметы
// у них РАЗНЫЕ, и это не педантизм:
//
//	у владельца  что этот владелец ДЕЛАЕТ своими точками — род оператора обязан
//	             быть снятием, потому что у снятия состояния не бывает; судить
//	             это можно, только зная словарь ЭТОГО журнала;
//	здесь        СКОЛЬКО точек какой формы у КАЖДОГО владельца — вопрос, который
//	             у одного владельца не задать вовсе.
//
// Числа обеих переписей сошлись на nlb в день заведения (18 точек формы вызова,
// 2 оператора, из них 1 перенос) — но сходятся они НЕ по построению: каждая
// выводит их своим обходом. Расхождение читается как находка у той стороны, чей
// распознаватель уже, а не как поломка.
//
// Одна ось у переписей всё же различается ПО СУЩЕСТВУ. Владелец объявляет
// оператор с целиком форматируемым именем НЕРАЗРЕШИМЫМ и печатает его отдельной
// величиной, не роняя; здесь такое имя РАЗРЕШАЕТСЯ — до константы пакета либо до
// параметра объемлющей функции, — и неразрешённое становится находкой. Разница
// не вкусовая: именно резолв показал, что оператор с форматируемым именем у
// машин целит не в журнал, а в очередь прав, — то есть опроверг посылку, на
// которой задача была заведена.
//
// Он не судит НАГРУЗКУ точки — собрана ли она общим строителем и полно ли
// состояние. Это предмет соседних проб у владельца, и они есть у того, у кого
// форма вызова живая. Здесь названо ровно то, чего до сих пор не было названо
// нигде: СКОЛЬКО точек какой формы у кого.
package repohygiene

import (
	"fmt"
	"sort"
	"testing"
)

func TestEveryJournalWriteFormIsCensusedPerOwner(t *testing.T) {
	root := repoRoot(t)
	tree := newTrackedTree(t, root)

	census, err := CensusJournalWriteForms(root, tree.files)
	if err != nil {
		t.Fatalf("перепись форм записи журнала не собрана: %v", err)
	}
	reportJournalWriteFormCensus(t, census)

	for _, why := range JournalCensusPremiseFailures(census) {
		t.Error(why)
	}
	if t.Failed() {
		// Беспредметная перепись — не «ноль нарушений». Дальше судить нечего.
		t.FailNow()
	}
	for _, finding := range JournalCensusFindings(census) {
		t.Error(finding)
	}
}

// reportJournalWriteFormCensus печатает перепись ПО ФОРМАМ РАЗДЕЛЬНО.
//
// Одно суммарное число скрывает ровно тот случай, ради которого перепись
// заведена: прибавка к осмотренному неотличима от роста дерева, а ноль по форме
// — от «не искали».
func reportJournalWriteFormCensus(t *testing.T, c JournalWriteFormCensus) {
	t.Helper()
	t.Logf("перепись форм записи журнала подписки: владельцев %d, файлов Go осмотрено %d, "+
		"миграций осмотрено %d", len(c.Owners), c.GoFiles, c.SQLFiles)
	t.Log("  распознаватели форм (экземпляров формы в дереве ВООБЩЕ, включая не-журнальные):")
	for _, form := range JournalWriteForms {
		t.Logf("    %-46s %d", form, c.Recognizer[form])
	}
	for _, owner := range c.Owners {
		t.Logf("  %s — журнал %q (объявлен %s):", owner.Service, owner.Table, owner.Decl)
		for _, form := range JournalWriteForms {
			pts := c.PointsOf(owner.Service, form)
			transports := 0
			for _, p := range pts {
				if p.Transport() {
					transports++
				}
			}
			note := ""
			if form == JournalFormTrigger {
				note = " — ОБЪЯВЛЕНИЙ по всем ревизиям, а не живой набор: живое тело " +
					"функции знает только база (прежние переопределения лежат в " +
					"применённых миграциях, править которые нельзя)"
			}
			t.Logf("    %-46s точек %d (из них переносов %d)%s", form, len(pts), transports, note)
			for _, p := range pts {
				t.Logf("        %s%s", p.Pos, describeJournalPoint(p))
			}
		}
	}
	t.Logf("  операторов с ЦЕЛИКОМ форматируемым именем таблицы %d: разрешено до имени %d, "+
		"переносов %d (из них вне общей библиотеки %d — их вызывающие этой переписью НЕ "+
		"разбираются, это край), предмет не установлен %d",
		len(c.Formatted), countFormatted(c, func(f JournalFormattedInsert) bool { return f.Resolved != "" }),
		countFormatted(c, func(f JournalFormattedInsert) bool { return f.Transport }),
		len(c.TransportsOutsideSharedLibrary()), len(c.Unresolved()))
	for _, f := range c.Formatted {
		switch {
		case f.Resolved != "":
			t.Logf("        %s — таблица %q", f.Pos, f.Resolved)
		case f.Transport:
			t.Logf("        %s — перенос: имя таблицы пришло параметром объемлющей функции", f.Pos)
		default:
			t.Logf("        %s — ПРЕДМЕТ НЕ УСТАНОВЛЕН", f.Pos)
		}
	}
}

func describeJournalPoint(p JournalWritePoint) string {
	if p.Transport() {
		return " — перенос (ни одного слова не назвал сам)"
	}
	words := append([]string(nil), p.Literals...)
	sort.Strings(words)
	if len(words) > 6 {
		words = words[:6]
	}
	return fmt.Sprintf(" — называет %v", words)
}

func countFormatted(c JournalWriteFormCensus, pred func(JournalFormattedInsert) bool) int {
	n := 0
	for _, f := range c.Formatted {
		if pred(f) {
			n++
		}
	}
	return n
}
