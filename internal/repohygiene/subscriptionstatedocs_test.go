// subscriptionstatedocs_test.go — гейт «клиентская страница подписки говорит про
// КАЖДОГО владельца то же, что делает его журнал».
//
// # Предмет — два места об одном предмете, из которых верно одно
//
// Несёт событие состояние предмета или нет — это ФАКТ О ВЛАДЕЛЬЦЕ, и клиент
// строит на нём свой код: получив состояние, он отбирает по меткам у себя;
// не получив — читает ресурс на каждое событие. Факт записан ДВАЖДЫ: в
// объявлении журнала владельца (`state`) и в таблице владельцев клиентской
// страницы. Второе место расходится с первым молча — ничем, кроме этого гейта,
// согласие не держится.
//
// # Что наблюдалось (и почему гейт заведён, а не «внимание»)
//
// Оба места приехали ОДНИМ коммитом — слиянием линии эпика единого потока
// изменений, — и уже в нём разошлись: журнал vpc собирал состояние у всех своих
// видов, а таблица про vpc говорила «состояния нет — приходит только оболочка
// события». Это столкновение параллельных полос: каждая половина верна у себя,
// неверна их РАЗНИЦА, и в диффе она не видна ни одной из сторон.
//
// # Почему предикат ПОЛОЖИТЕЛЬНЫЙ
//
// Проверяется, что клетка НАЗЫВАЕТ ТИП состояния, а не что в ней нет слов
// «состояния нет». Отрицание здесь неисправимо: ровно эта фраза стоит и у
// производящего владельца — у него нет состояния у СНЯТИЯ, и он обязан это
// сказать. Гейт по отрицанию краснел бы на верном тексте и был бы снят первым.
//
// # Как он истекает и как заводится
//
// От ФАКТА В ДЕРЕВЕ. Перестанет домен служить журнал — его строка и его
// объявление уйдут вместе, и требование снимется само. Появится шестой владелец —
// гейт потребует от страницы того же, не будучи тронут: биекция «журнал ↔ строка»
// проверяется в обе стороны, поэтому ни новый владелец, ни переименование
// прежнего не проходят молча.

// subscriptionClientPageRel — клиентская страница подписки.
//
// Она ОДНА на платформу — таково решение о единой форме, — поэтому здесь стоит
// путь, а не обход: страница, которой нет, обязана ронять гейт, а не оставлять
// его без предмета незаметно.
const subscriptionClientPageRel = "gateway/docs/content/api/subscription.mdx"

// TestSubscriptionOwnerPageSaysWhatItsJournalDoes — таблица владельцев обещает
// ровно то, что журнал владельца делает.
func TestSubscriptionOwnerPageSaysWhatItsJournalDoes(t *testing.T) {
	root := repoRoot(t)
	list := subscriptionDocsLister(treecorpus.UnderWithSuffix)

	reports, filesRead, err := subscriptionJournalStates(root, list)
	if err != nil {
		t.Fatalf("состав исходников сервисов у корпуса дерева: %v", err)
	}

	pagePath := filepath.Join(root, subscriptionClientPageRel)
	raw, readErr := os.ReadFile(pagePath) // #nosec G304 -- обход собственного дерева
	if readErr != nil {
		t.Fatalf("клиентская страница подписки %s не читается (%v) — сверять таблицу не с чем",
			subscriptionClientPageRel, readErr)
	}
	rows := subscriptionOwnerRows(string(raw))

	produces := 0
	for _, rep := range reports {
		if rep.produces {
			produces++
		}
	}
	claims := 0
	for _, row := range rows {
		if row.claimsState {
			claims++
		}
	}
	walked := 0
	for _, rep := range reports {
		walked += rep.funcsWalked
	}
	// Перепись печатает ОБЕ величины по каждой стороне: одно число скрыло бы
	// ровно тот случай, ради которого гейт заведён, — согласие количеств при
	// расхождении по владельцам.
	t.Logf("перепись: объявлений журналов осмотрено %d · функций обойдено %d · "+
		"из них собирают состояние %d · строк таблицы владельцев прочитано %d · "+
		"из них называют тип состояния %d",
		filesRead, walked, produces, len(rows), claims)
	for _, rep := range reports {
		t.Logf("  · журнал services/%s: функция состояния %q · обойдено функций %d · "+
			"файлов пакета %d · собирает %v",
			rep.service, rep.stateFunc, rep.funcsWalked, rep.pkgFiles, rep.produces)
	}
	for _, row := range rows {
		t.Logf("  · строка %q: называет тип состояния %v · обещает %q",
			row.owner, row.claimsState, row.claim)
	}

	if filesRead == 0 {
		t.Fatal("не осмотрено ни одного объявления журнала — прочитано ноль, и зелёное " +
			"здесь неотличимо от пустого обхода")
	}
	if len(rows) == 0 {
		t.Fatal("в клиентской странице не прочитано ни одной строки таблицы владельцев — " +
			"предмета у гейта нет. Если раздел переименован, гейт обязан покраснеть, " +
			"а не молча одобрить любую страницу")
	}

	for _, finding := range subscriptionStateFindings(reports, rows) {
		t.Error(finding)
	}
}
