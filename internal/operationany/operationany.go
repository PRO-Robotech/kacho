// Package operationany — ЕДИНЫЙ ИСТОЧНИК того, какие типы край обязан разрешать,
// отдавая клиенту `Operation`.
//
// # Предмет
//
// `Operation.response` и `Operation.metadata` — это `google.protobuf.Any`, то
// есть пара «адрес типа + байты». Упаковка у ВЛАДЕЛЬЦА реестра не спрашивает:
// она сериализует сообщение, тип которого у неё под рукой. Спрашивает
// РАСПАКОВКА, и происходит она в ДРУГОМ процессе — на крае, когда protojson
// отображает ответ в JSON. Резолвер protojson по умолчанию — реестр типов
// процесса (`protoregistry.GlobalTypes`), а туда тип попадает единственным
// способом: пакет с ним ВЛИНКОВАН в бинарь. Тип, которого в реестре края нет,
// роняет маршаллинг; grpc-gateway пишет `Marshal error` и уходит в `HTTPError`,
// поэтому вызывающий получает 500 на совершенно штатном пути — например на
// удалении, чей ответ пуст by design.
//
// # Почему это отдельный пакет, а не объявление внутри края
//
// У объявления ДВА читателя, и они лежат по разные стороны границы `internal`:
//
//   - край (`gateway/internal/restmux`) — ради самой линковки и своих проб;
//   - гейт дерева (`internal/repohygiene`) — ради сверки объявления с тем, что
//     владельцы в дерево кладут.
//
// Пакет края импортировать из `internal/repohygiene` нельзя: `gateway/internal`
// закрыт для всего, что не под `gateway/`. Оставить объявление там значило бы
// сверять его ЧТЕНИЕМ ЧУЖОГО ИСХОДНИКА КАК ТЕКСТА — приём, запрещённый в этом
// дереве: он не отличает код от комментария и зеленеет тем увереннее, чем лучше
// место задокументировано. Здесь объявление одно, и обе стороны читают ЕГО
// ЗНАЧЕНИЯ, а не его текст.
//
// # Две половины названы порознь намеренно
//
//   - [Anchors] — МЕХАНИЗМ: чем разрешение обеспечено (импорт, чей `init()`
//     кладёт тип в реестр процесса);
//   - [RequiredResponseTypeURLs] — НАМЕРЕНИЕ: что край обязан отдать.
//
// Слить их в одно значение нельзя: тогда перечень выводился бы из якорей, и
// проверка «намерение обеспечено» стала бы тождественно истинной. Порознь она
// ловит обе ошибки — якорь без намерения (мёртвый импорт, который снимут как
// непонятный) и намерение без якоря (обещание, которое держится чужой
// случайной линковкой).
package operationany

import (
	"reflect"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/emptypb"
)

// typeURLPrefix — префикс адреса типа в `Any`. Тот же, что пишет `anypb.New`.
const typeURLPrefix = "type.googleapis.com/"

// Anchors — МЕХАНИЗМ разрешения. Значения существуют ради побочного эффекта
// СВОИХ ПАКЕТОВ: импорт `emptypb` регистрирует `google.protobuf.Empty` в
// реестре типов процесса. Это НЕ мёртвый код — снятие ссылки уносит
// регистрацию, и край начинает отвечать 500 на каждом завершённом удалении.
//
// Ровно так это однажды и отказало: тип держался ПОБОЧНЫМ импортом файла
// соседнего пакета, к отображению ответов отношения не имевшего. Пока файл
// существовал, всё работало; когда его сняли вместе с его собственным
// предметом, разрешение ответов уехало вместе с ним. Сборка не сломалась, ни
// одна проба не покраснела: связь была ненаблюдаемой, потому что нигде не
// объявлена. Здесь она объявлена.
func Anchors() []proto.Message {
	return []proto.Message{
		(*emptypb.Empty)(nil), // ответ всякого Delete: `Operation.response`
	}
}

// RequiredResponseTypeURLs — НАМЕРЕНИЕ: адреса, которые край обязан разрешать.
// Записаны строками, а не выведены из якорей, — иначе проверка сверяла бы
// якоря сами с собой.
//
// Перечень СВЯЗЫВАЕТ ДЕРЕВО: гейт `internal/repohygiene` требует, чтобы всякий
// ЧУЖОЙ (не из наших стабов) тип, упаковываемый владельцами в `Any`, стоял
// здесь. Тип, которого край разрешать не обязан, — это РЕШЕНИЕ, и место ему
// здесь же, рядом с объяснением; послаблений в самом гейте не заводится.
func RequiredResponseTypeURLs() []string {
	return []string{
		typeURLPrefix + "google.protobuf.Empty",
	}
}

// AnchoredTypeURLs — адреса, которые якоря фактически вносят в реестр.
func AnchoredTypeURLs() []string {
	anchors := Anchors()
	urls := make([]string, 0, len(anchors))
	for _, m := range anchors {
		urls = append(urls, typeURLPrefix+string(m.ProtoReflect().Descriptor().FullName()))
	}
	return urls
}

// GoCoordinate — якорь, названный так, как его пишут в МЕСТЕ УПАКОВКИ: путём
// Go-пакета и именем Go-типа.
//
// Зачем отдельно от адреса. Место упаковки в дереве написано Go-именами
// (`&emptypb.Empty{}`), а край объявляет proto-адреса
// (`…/google.protobuf.Empty`). Отображение одного в другое синтаксически не
// выводится — Go-имя типа и его proto-имя связаны только генератором. Поэтому
// словарь строится ЗДЕСЬ, из тех же значений, что дают адрес: одно значение —
// обе координаты, разойтись им негде.
type GoCoordinate struct {
	// Package — путь Go-пакета, например
	// "google.golang.org/protobuf/types/known/emptypb".
	Package string
	// Name — имя Go-типа без указателя, например "Empty".
	Name string
	// TypeURL — адрес того же типа в `Any`.
	TypeURL string
}

// AnchoredGoCoordinates — словарь «Go-координата якоря → адрес типа».
//
// Выводится рефлексией из тех же значений, что и [AnchoredTypeURLs], поэтому
// вторая копии перечня не заводит.
func AnchoredGoCoordinates() []GoCoordinate {
	anchors := Anchors()
	out := make([]GoCoordinate, 0, len(anchors))
	for _, m := range anchors {
		rt := reflect.TypeOf(m)
		for rt.Kind() == reflect.Pointer {
			rt = rt.Elem()
		}
		out = append(out, GoCoordinate{
			Package: rt.PkgPath(),
			Name:    rt.Name(),
			TypeURL: typeURLPrefix + string(m.ProtoReflect().Descriptor().FullName()),
		})
	}
	return out
}
