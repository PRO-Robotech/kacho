// Package identityvendor — ИМЯ снятого поставщика личности: единственное
// объявление в дереве (эпик #2564, задача #2929).
//
// # Зачем пакет, а не переменная у гейта
//
// Имя читают ДВА пакета проб: потолок привязок (`internal/repohygiene`,
// `retiredidentityvendorceiling.go`) и рендерная проба развёртывания
// (`deploy/own_render_carries_no_vendor_object_test.go`). Второй не
// импортирует первый: тот тянет разбор контракта и регистрацию дескрипторов,
// которых пробе рендера не нужно ни одного. Словарь, выписанный у второго
// читателя копией, разошёлся бы с первым молча — ровно на правке, где
// расхождение и опасно. Образец — `internal/retiredknobs`: ведомость для гейтов
// живёт непроверочным объявлением и отдаётся КОПИЕЙ.
//
// # Что здесь объявлено
//
//   - отметки — подстроки без учёта регистра: имя службы сессий и
//     самообслуживания, имя издателя токенов и пространство их образов. Любая
//     форма записи (переменная окружения, имя службы, алиас подчарта, столбец,
//     сегмент пути) накрывается подстрокой, поэтому перечня форм здесь нет;
//   - бренд — слово, которое отметкой НЕ является. Под тем же именем издатель
//     публикует библиотеки, и одна из них (`github.com/ory/fosite`) законно
//     остаётся у собственной чеканки токенов: потолок привязок судит исходник и
//     бренд намеренно не читает. Бренд судится только там, где библиотек нет by
//     construction, — в узлах-идентификаторах рендера, и только с границей
//     буквы с обеих сторон (иначе словом поставщика стали бы `memory`,
//     `factory`).
package identityvendor

// marks — отметки имени поставщика, в нижнем регистре.
var marks = []string{"hydra", "kratos", "oryd/"}

// brand — слово бренда, в нижнем регистре; судится только с границей буквы.
const brand = "ory"

// Marks возвращает КОПИЮ отметок: правка результата не меняет словарь
// соседнего читателя.
func Marks() []string {
	return append([]string(nil), marks...)
}

// Brand возвращает слово бренда.
func Brand() string { return brand }
