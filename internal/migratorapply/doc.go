// Package migratorapply — доказательство наката: КАЖДАЯ точка наката дерева
// собирается и запускается против живой базы.
//
// # Зачем пакет, а не проба рядом с каждым мигратором
//
// Правило `internal` языка запрещает пакету из корня импортировать
// `services/<svc>/internal/migrations`: такой импорт разрешён только пакетам,
// укоренённым в `services/<svc>`. Общий пакет не может дотянуться до цепочек семи
// сервисов через импорт — это построение, а не неудобство, и обходится оно ровно
// одним способом: собрать бинарь точки наката и запустить его.
//
// Способ оказался не обходным путём, а лучшим предметом. Проба, зовущая функцию,
// доказывала бы ту половину тракта, до которой дотянулась; запуск бинаря доказывает
// весь: разбор аргументов, резолв DSN, встроенную FS, диалект, барьер готовности
// базы, счёт перед сносом и сам накат goose. Ровно это и означает «сервис
// разворачивается».
//
// # Перечень точек наката ВЫВОДИТСЯ из дерева
//
// `go list ./services/*/cmd/migrator` — не выписанный список. Новый сервис попадает
// под доказательство сам; слепой зоны «пробу забыли дописать» не заводится, а
// перепись печатает оба числа (сколько найдено · сколько доказано), чтобы «ноль
// находок» было отличимо от «ноль прочитанного».
//
// # Производитель
//
// Пакет гоняет цель `make test-pg-outside-selection` (задание `pg-outside-selection`
// в ci.yaml): отбор интеграционной джобы сужен каталогами внутри сервиса, и ни одна
// точка наката в него не входит. Провязку держат гейты — pgoutsideselection_test.go
// (перечень цели ↔ освобождение) и migratorapplyproducer_test.go (у доказательства
// есть производитель). Без производителя проба была бы зелена всегда, потому что не
// исполнялась бы никогда.
